#!/usr/bin/env python3
"""[ЧЁТНОСТЬ ДЕЙСТВИЙ] — закон о классах, проверенный разложением.

Суд не пишет закона заново: он берёт его у дома (`parityforms`), где рамки и числа объявлены одной
таблицей. Подмена разложения, суммы и самого ЗАКОНА ловится машинально: чётность
считается по записи «2 × m» и «2 × m + 1», а не принимается на слово.
ЧЁТНОСТЬ ЗДЕСЬ ПРОВЕРЯЕТСЯ РАЗЛОЖЕНИЕМ, А НЕ СЛОВОМ: «4 = 2 × 2» и «5 = 2 × 2 + 1» суть само
определение чётного и нечётного, данное счётом. Суд сверяет и САМ ЗАКОН: чётность итога обязана
быть чётностью суммы остатков, и страница, где два нечётных дают нечётное, есть ложь.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ПОЛНОТА СЛУЧАЕВ ЕСТЬ УСЛОВИЕ ЗАКОНА: три рода сложения — чёт с чётом, нечёт с нечётом, чёт с
нечётом — суть полный перебор, и самопроверка дома сторожит эту полноту. ЗАКОН О КЛАССАХ,
ПОКАЗАННЫЙ НЕ ВСЕМИ СЛУЧАЯМИ, ЕСТЬ ПРАВИЛО С НЕНАЗВАННОЙ ДЫРОЙ.

ЭТОТ ДОМ ЧИТАЕТСЯ И СУДОМ АРИФМЕТИКИ: его страницы написаны так, что слова стоя́т до двоеточия, а
равенства после, — и потому каждая проверена ДВАЖДЫ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/parity_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import parityforms  # noqa: E402 — дом, объявивший чётность действий

ИМЯ_СУДА = "parity"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"parity"})


def _судить(строка):
    return parityforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ЧЁТНОСТЬ ДЕЙСТВИЙ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(parityforms.РОДЫ)}, страниц {len(parityforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
