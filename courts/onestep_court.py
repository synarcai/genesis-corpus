#!/usr/bin/env python3
"""[ОДНОШАГОВОЕ УРАВНЕНИЕ] — обратное действие, пересчитанное судом.

Суд не пишет закона заново: он берёт его у дома (`onestepforms`), где рамки, числа и
числительные объявлены одной таблицей. Подмена ЛЮБОГО из четырёх чисел ловится
машинально — сумма, разность, произведение и частное пересчитываются порознь, и
всякое обязано сойтись с КОРНЕМ, названным в конце строки.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЧЕТЫРЕ ЧИСЛА И ОДИН КОРЕНЬ. Строка «x + 4 = 18. x = 18 − 4. x = 14.» говорит одно и то
же трижды, и суд требует согласия всех трёх: подмена в любом месте расходится с корнем.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним
словом, суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/onestep_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import onestepforms  # noqa: E402 — дом, объявивший одношаговое уравнение

ИМЯ_СУДА = "onestep"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"onestep"})


def _судить(строка):
    return onestepforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ОДНОШАГОВОЕ УРАВНЕНИЕ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(onestepforms.РОДЫ)}, страниц {len(onestepforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
