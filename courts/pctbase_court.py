#!/usr/bin/env python3
"""[ОСНОВАНИЕ ПРОЦЕНТА] — доля от своего целого, пересчитанная судом.

Суд не пишет закона заново: он берёт его у дома (`pctbaseforms`), где пары «процент —
основание» объявлены тремя таблицами: перевёрнутые (больший процент даёт меньшее число),
при общем основании и иное основание для показа того же процента. Всякая запись страницы
считается разбором свода (`arithread`), и путь счёта идёт УМНОЖЕНИЕМ ВПЕРЁД: «20 × 50 ÷ 100»
остаётся в целых числах, а «20 ÷ 100 × 50» выходит из них на первом же шаге.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: обе стороны ловушки обязаны быть
показаны; у перевёрнутой пары больший процент обязан давать МЕНЬШЕЕ число (иначе ловушки нет
вовсе); при общем основании порядок обязан сохраняться; и всякая доля обязана быть ЦЕЛОЙ —
свод, сказавший «262,5 человека», научил бы дроби людей.

    python3 courts/pctbase_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import pctbaseforms  # noqa: E402 — дом, объявивший множитель размерности

ИМЯ_СУДА = "pctbase"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"pctbase"})


def _судить(строка):
    return pctbaseforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ОСНОВАНИЕ ПРОЦЕНТА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(pctbaseforms.РОДЫ)}, страниц {len(pctbaseforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
