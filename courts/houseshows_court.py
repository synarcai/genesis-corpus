#!/usr/bin/env python3
"""[ПОКАЗ ДОМА] — мир, писанный домом без своего суда, судится ПРИНАДЛЕЖНОСТЬЮ К ЕГО ПОКАЗАМ.

    МИР БЕЗ СВОЕГО СУДА СУДИТСЯ СОСЕДЯМИ, И ЭТО ТОТ ЖЕ ДОЛГ М-131, ПОДНЯТЫЙ С СТРОКИ НА МИР.

ПОВОД, НАЙДЕННЫЙ ПРИБОРОМ (08.09). `word_mutants` подсаживает в живую строку испорченное
слово и спрашивает палату; из десяти худших миров ЧЕТЫРЕ оказались без единого своего суда —
verbbridge, measureof, totalsubj, relcompare (47 непойманных из 183); обход нашёл ещё двух
братьев того же вида — ninelang и subjcount. Их страницы читают
только соседи: `arith` пересчитывает леджер, `engram` и `langcount` подписывают слова, —
и порча РАМКИ проходит мимо всех троих:

    «Felix adds 40 dollars. how many dollars does Felix add? …» → «Feli adds 40 dollars. …»
    Леджер цел, счёт цел, слово «Feli» ни одному словарю не принадлежит — и палата молчала.

ЧЕМ СУДИТ ЭТОТ СУД. Дома эти пишут ПОЛНЫЙ и ДЕТЕРМИНИРОВАННЫЙ набор страниц функцией
`показы(проход)`; сличено по своду — все 5574 строки четырёх миров суть страницы своих домов,
ВНЕ ДОМА НЕТ НИ ОДНОЙ. Оттого принадлежность к набору есть полный и точный признак истины,
а закон замкнутого мира делает всякую иную строку такого файла ложью.

    НАБОР ПОКАЗОВ ЕСТЬ САМЫЙ УЗКИЙ ИЗ ВЕРНЫХ ОБРАЗЦОВ: он не выводит правил и не гадает —
    он знает страницы поимённо. Дом, у которого такой набор есть, не нуждается в рамке,
    чтобы быть замкнутым.

ГРАНИЦА ОБЪЯВЛЕНА: этот суд НЕ ЗАМЕНЯЕТ дому своего суда с рамкой и вердиктом. Рамочный суд
читает строку, которой дом ещё не писал, и говорит о ней правду; этот — лишь отличает
писанное от неписанного. Он есть ПОЛ, а не потолок, и день, когда дом получит рамку, есть
день, когда его имя уйдёт отсюда.

ЦЕНА НАЗВАНА ЧИСЛОМ: наборы собираются один раз при сборке палаты, 8 проходов на дом.

    python3 courts/houseshows_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира

ИМЯ_СУДА = "houseshows"

# ДОМА, ПИШУЩИЕ МИР БЕЗ СВОЕГО СУДА. Названы поимённо, а не найдены обходом: обход взял бы
# и те дома, чей суд есть, и замкнул бы их вторым законом поверх первого.
# СОСТАВ НАЙДЕН ДЕЛОМ, А ЗАПИСАН СПИСКОМ: обход домов искал тех, у кого есть `показы(проход)`
# и НЕТ `судить`, а мир их — точное подмножество набора. Таких шесть, и все шесть здесь.
# Список, а не обход, по доводу соседа (`panel_court`): обход взял бы и дом, чей суд напишут
# завтра, и замкнул бы его вторым законом поверх первого — молча.
ДОМА = ("verbbridge", "measureof", "totalsubj", "relcompare", "ninelang", "subjcount")
ПРОХОДОВ = 8            # столько же, сколько берут их ворота записи


def _показы():
    вон = {}
    for имя in ДОМА:
        try:
            дом = __import__(имя)
        except Exception:                       # noqa: BLE001
            continue
        собрать = getattr(дом, "показы", None)
        if not callable(собрать):
            continue
        for проход in range(ПРОХОДОВ):
            try:
                ряд = собрать(проход)
            except Exception:                   # noqa: BLE001
                break
            for с in (ряд.keys() if isinstance(ряд, dict) else ряд):
                вон.setdefault(str(с).strip(), имя)
    return вон


ПОКАЗЫ = _показы()
# ИМЯ МИРА БЕРЁТСЯ ИЗ МАНИФЕСТА, А НЕ ИЗ ИМЕНИ ФАЙЛА: там оно без приставки «genesis_»
ЗАМКНУТЫЕ_МИРЫ = frozenset(ДОМА)


def _судить(строка):
    """(судимо, истинно): страница есть показ своего дома, иначе молчание."""
    с = строка.strip()
    if с in ПОКАЗЫ:
        return True, True
    return False, False


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    свои = чужие = 0
    примеры = []
    for имя in ДОМА:
        путь = КОРЕНЬ / "datasets" / f"genesis_{имя}.txt"
        if not путь.is_file():
            print(f"ПОКАЗ ДОМА ОТКАЗ: мира нет — {путь.name}")
            return 2
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            с = строка.strip()
            if not с:
                continue
            if с in ПОКАЗЫ:
                свои += 1
            else:
                чужие += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.name}: {с[:90]}")
    for п in примеры:
        print(f"  ВНЕ ДОМА {п}")
    поза = "PASS" if чужие == 0 else "FAIL"
    print(f"ПОКАЗ ДОМА {поза}: домов {len(ДОМА)}, показов собрано {len(ПОКАЗЫ)}; "
          f"строк своих {свои}, ВНЕ ДОМА {чужие} (рубеж 0)")
    return 0 if чужие == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
