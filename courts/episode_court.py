def имена_на_месте(строка, слой=None):
    """False — на месте деятеля стоит слово, которого дом имён не знает.

    Закон действует в мирах, ОБЪЯВИВШИХ деятелей лицами пакета (манифест
    `actors: person_names:en`): предложение начинается именем, зачином
    пакета или числительным; после «does» и «than» стоит имя или слово
    сравнения. Так порченое имя («elen», «pi») ловится и тогда, когда оно
    сломало рамку и строку читал один лишь суд числа.
    """
    if слой is None or not (слой.лица("en") or слой.лица("ru")) or not ИМЕНА_EN:
        return True
    низ = строка.strip().lower()
    if re.search(r"[а-яё]", низ):
        if слой.лица("ru") and ИМЕНА_RU:
            return all(м.group(1) in ИМЕНА_RU for м in _ЗАЧИН_RU.finditer(низ))
        return True
    for м in _ЗАЧИН.finditer(низ):
        w = м.group(1)
        if w not in ИМЕНА_EN and w not in ЗАЧИНЫ_EN and w not in ЧИСЛИТЕЛЬНЫЕ_EN:
            return False
    for м in _ПОСЛЕ.finditer(низ):
        w = м.group(1)
        if w not in ИМЕНА_EN and w not in КРАТНОСТИ_EN and w not in ЧИСЛИТЕЛЬНЫЕ_EN:
            return False
    return True


def судить(строка, слой=None):
    с = строка.strip()
    # ГЛАГОЛ БЕРЁТ СВОЙ РОД ВЕЩЕЙ (tools/verbthings.py, 03.09): «ate 12 books»,
    # «wrote 8 pencils» — ложь о языке, какова бы ни была арифметика.
    for г, в in ГЛАГОЛ_ВЕЩЬ.findall(с):
        if not verbthings.берёт(г, в):
            return True, False
    if not имена_на_месте(с, слой):
        return True, False
    ру = русские_рамки(строка)
    if ру is not None:
        return True, ру
    русское = русская_ставка(строка)
    if русское is not None:
        return True, русское
    упаковано = упаковка_возможна(строка)
    if упаковано is not None:
        return True, упаковано
    боевое = боевые_рамки(строка)
    if боевое is not None:
        return True, боевое
    m = ДЕЛЁЖ.match(с)
    if m:
        сколько, _, делящих, _, остаток = m.groups()
        if int(делящих) < 1:
            return True, False
        return True, int(сколько) % int(делящих) == int(остаток)
    m = ЗА_ДНИ.match(с)
    if m:
        _, _, ставка, вещь1, дней, итог, вещь2, дней2 = m.groups()
        вещи = {singular(вещь1), singular(вещь2)}
        числом = (вещь1 == (singular(вещь1) if int(ставка) == 1
                            else plural_of(singular(вещь1)))
                  and вещь2 == (singular(вещь2) if int(итог) == 1
                                else plural_of(singular(вещь2))))
        return True, (len(вещи) == 1 and дней == дней2
                      and int(ставка) * int(дней) == int(итог) and числом)
    лицо = лицо_сходится(строка)
    if лицо is not None:
        return True, лицо
    m = ОТДАЛ.match(с)
    if m:
        имя, было, вещь1, отдал, вещь2, стало, вещь3 = m.groups()
        вещи = {singular(в) for в in (вещь1, вещь2, вещь3)}
        числа = int(было), int(отдал), int(стало)
        # ФОРМА ВЕЩИ СОГЛАСУЕТСЯ СО СВОИМ ЧИСЛОМ В КАЖДОЙ ТРЕТИ ПОКАЗА,
        # и это отдельное утверждение рядом со счётным: «gave away 1
        # apples» ложно о языке при верной арифметике.
        формы = all(
            в == (singular(в) if n == 1 else plural_of(singular(в)))
            for n, в in zip(числа, (вещь1, вещь2, вещь3)))
        return True, (len(вещи) == 1 and числа[0] - числа[1] == числа[2]
                      and формы)
    m = РОД_ВЕЩИ.match(с)
    if m:
        слово, связка, род = m.groups()
        разбор = _род(слово)
        if разбор is None:
            return False, True
        _, живое, много = разбор
        числом = связка == ("are" if много else "is")
        ждём = "person" if живое else "thing"
        return True, числом and род == ждём
    m = МЕСТО_ВЕЩИ.match(с)
    if m:
        слово, связка, место = m.groups()
        разбор = _род(слово)
        if разбор is None:
            return False, True
        _, живое, много = разбор
        числом = связка == ("are" if много else "is")
        return True, числом and место == ("here" if живое
                                          else "on the table")
    m = ПРИБАВЛЕНИЕ.match(с)
    if m:
        a, b, итог = int(m.group(2)), int(m.group(4)), int(m.group(8))
        вещи = {singular(m.group(i)) for i in (3, 5, 6, 9)}
        return True, len(вещи) == 1 and a + b == итог and _звено_итога(m, a, b, "+", итог)
    m = УБАВЛЕНИЕ.match(с)
    if m:
        a, b, итог = int(m.group(2)), int(m.group(4)), int(m.group(8))
        вещи = {singular(m.group(i)) for i in (3, 5, 7, 9)}
        return True, len(вещи) == 1 and a - b == итог and _звено_итога(m, a, b, "−", итог)
    m = АГРЕГАТ3.match(с)
    if m:
        вещи = {singular(m.group(i)) for i in (3, 6, 9, 10, 12)}
        x, y, z, итог = (int(m.group(i)) for i in (2, 5, 8, 11))
        return True, len(вещи) == 1 and x + y + z == итог
    m = АГРЕГАТ2.match(с)
    if m:
        вещи = {singular(m.group(i)) for i in (3, 6, 7, 9)}
        x, y, итог = (int(m.group(i)) for i in (2, 5, 8))
        return True, len(вещи) == 1 and x + y == итог
    m = ПЕРФЕКТ_ПАРА.match(с)
    if m:
        # «A has V-ed N X. A V-ed N X.» — перфект рядом со своим
        # прошедшим: числа обязаны совпасть, иначе пара учит разному.
        вещи = {singular(m.group(4)), singular(m.group(6))}
        return True, len(вещи) == 1 and int(m.group(3)) == int(m.group(5))
    m = ЖИЗНЬ.match(с)
    if m:
        слово = next(г for г in m.groups() if г)
        return True, слово in ПРЕДМЕТЫ
    m = ЖИЗНЬ_РОДА.match(с)
    if m:
        слово = next(г for г in m.groups() if г)
        известно = ВМЕСТИЛИЩА | ПЕРИОДЫ | {singular(w) for w in ВМЕСТИЛИЩА}
        if слово in известно:
            return True, True
        # СУД НЕ СУДИТ ТОГО, ЧЕМ НЕ ВЛАДЕЕТ. Поверхность «what is a X?»
        # общая для многих слоёв: доли спрашивают ею о трети, остаток —
        # об остатке. Объявив ложью всё, чего не знает сам, этот суд
        # обвинил бы чужие честные показы — и обвинил, пока не был
        # поправлен. Незнакомое слово уходит в СЧЁТ, а не в приговор.
        НЕЗНАКОМЫЕ.append(слово)
        return False, True
    m = ДЕРЖАНИЕ.match(с)
    if m:
        return True, _держание(m)
    m = РУ_ДЕРЖАНИЕ.match(с)
    if m:
        return True, _ру_держание(m)
    m = НАКОПЛЕНИЕ.match(с)
    if m:
        n, k, m2, n2, m3, t, t2, k2, d = (int(m.group(i)) for i in (2, 4, 5, 6, 7, 8, 9, 10, 11))
        return True, ((n2, m3) == (n, m2) and t == n + m2 and t2 == t and k2 == k
                      and k <= n and d == t - k >= 0)
    m = СТАВКА.match(с)
    if m:
        ставка, k, итог = int(m.group(3)), int(m.group(5)), int(m.group(7))
        return True, ставка * k == итог
    m = УПАКОВКА.match(с)
    if m:
        ставка, k, итог = int(m.group(2)), int(m.group(4)), int(m.group(5))
        return True, ставка * k == итог
    for рег, места in ((ВОПРОС_RU, (2, 3)), (ВОПРОС_RU_ПЛАТА, (2, 3)),
                       (ВОПРОС_EN, (2, 3)), (ВОПРОС_EN_ПЛАТА, (1, 2))):
        m = рег.match(с)
        if not m:
            continue
        имя = m.group(места[0])
        итог = int(m.group(места[1]))
        видано = ИТОГИ_СЛОЯ.get(имя)
        if видано is None:
            return False, True
        return True, итог in видано
    m = СЮЖЕТ_RU.match(с)
    if m:
        было, стало_чем, итог = int(m.group(2)), m.group(7), int(m.group(8))
        сколько = int(m.group(5))
        ждём = было + сколько if стало_чем == "стало" else было - сколько
        return True, ждём == итог
    m = СЮЖЕТ_EN_УБЫЛЬ.match(с)
    if m:
        было, ушло, итог = (int(m.group(i)) for i in (2, 4, 5))
        return True, было - ушло == итог
    m = СЮЖЕТ_EN_ПРИБЫЛЬ.match(с)
    if m:
        было, пришло, итог = (int(m.group(i)) for i in (2, 4, 6))
        return True, было + пришло == итог
    m = СТАВКА_EN.match(с)
    if m:
        штук, цена, итог = (int(m.group(i)) for i in (2, 4, 5))
        return True, штук * цена == итог
    m = СТАВКА_СЮЖЕТ_RU.match(с)
    if m:
        штук, цена, итог = (int(m.group(i)) for i in (2, 4, 6))
        return True, штук * цена == итог
    if с in НАЧАЛА:
        return True, True
    m = ДВА_ШАГА.match(с)
    if m:
        a, b, зн = int(m.group(2)), int(m.group(4)), знаменатель(m.group(5))
        осталось = int(m.group(6))
        if зн is None:
            return False, True
        всего = a + b
        return True, всего % зн == 0 and всего - всего // зн == осталось
    m = ОДИН_ШАГ.match(с)
    if m:
        всего, зн = int(m.group(2)), знаменатель(m.group(4))
        осталось = int(m.group(5))
        if зн is None:
            return False, True
        return True, всего % зн == 0 and всего - всего // зн == осталось
    m = УШЕДШЕЕ.match(с)
    if m:
        всего, зн = int(m.group(2)), знаменатель(m.group(4))
        ушло = int(m.group(5))
        if зн is None:
            return False, True
        return True, всего % зн == 0 and всего // зн == ушло
    m = УБЫЛЬ_RU.match(с)
    if m:
        всего, зн = int(m.group(1)), знаменатель(m.group(3))
        осталось = int(m.group(5))
        if зн is None:
            return False, True
        return True, всего % зн == 0 and всего - всего // зн == осталось
    m = ОСТАТОК_ВОПРОС.match(с)
    if m:
        a, b, q, r = (int(г) for г in m.groups() if г is not None)
        return True, b > 0 and a == b * q + r and 0 <= r < b
    m = ОСТАТОК_EN.match(с) or ОСТАТОК_RU.match(с)
    if m:
        a, b, q, r = (int(x) for x in m.groups())
        return True, b != 0 and divmod(a, b) == (q, r)
    m = СТАВКА_ШТУК.match(с)
    if m:
        штук, цена, итог = (int(m.group(i)) for i in (1, 3, 5))
        return True, штук * цена == итог
    m = СТАВКА_RU.match(с)
    if m:
        штук, цена, итог = (int(m.group(i)) for i in (1, 2, 4))
        return True, штук * цена == итог
    m = РАВНЫ.match(с)
    if m:
        k, один, итог, много = (m.group(1), m.group(2),
                                m.group(3), m.group(4))
        ставка = ОТНОШЕНИЯ.get((один.rstrip("s"), много))
        if ставка is None:
            return False, True
        return True, int(k) * ставка == int(итог)
    m = УПАКОВКА_ВОПРОС.match(с)
    if m:
        k, итог = int(m.group(2)), int(m.group(4))
        return True, k > 0 and итог % k == 0
    m = КОНВЕРСИЯ.match(с) or ДЕРЖИТ.match(с)
    if m:
        # ОБЪЯВЛЕНИЕ СВЕРЯЕТСЯ С ОБЪЯВЛЕНИЕМ. Прежде суд говорил
        # «судить нечего»: показ САМ объявляет отношение. Но отношение
        # объявлено и в генераторе, и расхождение между ними есть
        # дрейф — тот самый, ради которого суды и написаны.
        один, ставка, много = m.group(1), int(m.group(2)), m.group(3)
        объявлено = ОТНОШЕНИЯ.get((один.rstrip("s"), много))
        if объявлено is not None:
            return True, объявлено == ставка
        свои = СТАВКИ_СЛОЯ.get((один, много))
        if свои is not None:
            return True, ставка in свои
        return False, True
    m = КОНВЕРСИЯ_RU.match(с)
    if m:
        # русская запись отношения: «в часе 60 минут». Сверяется числом
        # с тем же объявлением — имена падежные, потому судится ставка
        # по её ЗНАЧЕНИЮ среди объявленных. НО ТОЛЬКО МЕЖДУ ЕДИНИЦАМИ:
        # «в упаковке 2 яблока» той же формы и другого рода, и суд,
        # читавший форму без рода, звал ложью честную ставку вместилища.
        часть = units.единица(m.group(3).rstrip("ыиова"))
        if часть is None and units.единица(m.group(3)) is None:
            return False, True
        ставка = int(m.group(2))
        return True, ставка in set(ОТНОШЕНИЯ.values())
    m = КОНВЕРСИЯ_К.match(с)
    if m:
        k, итог = int(m.group(1)), int(m.group(3))
        return True, итог % k == 0 if k else False
    # СРАВНЕНИЕ: части в любом порядке, итог в конце
    итог_m = ИТОГ.search(с)
    if итог_m and not _звено_верно(с, итог_m, int(итог_m.group(2))):
        return True, False
    if итог_m:
        база = {им: int(n) for им, n, _ in БАЗА.findall(с)}
        база.update({им: int(n) for им, n, _ in БАЗА_ПЕРФЕКТ.findall(с)})
        кто, сколько = итог_m.group(1), int(итог_m.group(2))
        # ВЛОЖЕННОЕ ЧИТАЕТСЯ ПЕРВЫМ: «3 more than twice the number of X»
        # содержит и «more than», и множитель, и суд, взявший внешнее
        # отношение отдельно, посчитал бы 2·база вместо 2·база + 3.
        m = ВЛОЖЕННО.search(с)
        if m:
            a, d, b = m.group(1), int(m.group(2)), m.group(4)
            if a == кто and b in база:
                return True, база[b] * 2 + d == сколько
        m = ДВАЖДЫ.search(с)
        if m:
            a, b = m.group(1), m.group(3)
            if a == кто and b in база:
                return True, база[b] * 2 == сколько
        for рег, действие in (
                (БОЛЬШЕ, lambda o, d: o + d),
                (БОЛЬШЕ_ПЕРФЕКТ, lambda o, d: o + d),
                (МЕНЬШЕ, lambda o, d: o - d),
                (РАЗ_КОНЕЦ, lambda o, d: o * d),
                (РАЗ_СЕРЕДИНА, lambda o, d: o * d)):
            m = рег.search(с)
            if not m:
                continue
            a, d = m.group(1), int(m.group(2))
            b = m.group(4) if рег in (РАЗ_КОНЕЦ, РАЗ_СЕРЕДИНА) else m.group(3)
            if a != кто or b not in база:
                continue
            return True, действие(база[b], d) == сколько
    return False, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ЭПИЗОД ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ЭПИЗОД ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        впитать_ставки(путь)
        впитать_итоги(путь)
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:110]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ЭПИЗОД {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)"
          + (f", вне владения {len(set(НЕЗНАКОМЫЕ))} слов: "
             f"{sorted(set(НЕЗНАКОМЫЕ))[:5]}" if НЕЗНАКОМЫЕ else ""))
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
