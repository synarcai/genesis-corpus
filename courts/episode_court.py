# РУССКИЕ РАМКИ ИСТОРИИ. Слой ru-глаголов прошёл ворота записи, ибо
# КАЖДАЯ его строка была судима — судом СОГЛАСОВАНИЯ. Но согласование
# читает формы, а не счёт: «вера написала 3 книги… всего 9 книг» верно
# по формам и ложно по числу, и ворота его пропустили.
#
# ОТСЮДА ЗАКОН, КОТОРОГО У НАС НЕ БЫЛО: СУДИМОСТЬ СТРОКИ НЕ ЕСТЬ
# СУДИМОСТЬ ВСЕХ ЕЁ УТВЕРЖДЕНИЙ. Строка, говорящая две вещи, может быть
# прочитана судом, знающим одну. Здесь эта дыра закрыта для русских
# рамок; общий прибор — отдельная работа, названная коллегии.
РУ_ВОПРОС = re.compile(
    r"^(\w+) (\w+) (\d+) (\S+)\. сколько (\S+) \2 \1\? "
    r"\1 \2 (\d+) (\S+)\.$")
РУ_ВСЕГО = re.compile(
    r"^(\w+) (\w+) (\d+) (\S+)\. \1 \2 ещё (\d+) (\S+)\. "
    r"сколько (\S+) \2 \1 всего\? \1 \2 (\d+) (\S+)\.$")


def русские_рамки(строка):
    """(истинно) для русских рамок истории; None — не наше."""
    с = строка.strip()
    m = РУ_ВОПРОС.match(с)
    if m:
        было, стало = int(m.group(3)), int(m.group(6))
        return было == стало
    m = РУ_ВСЕГО.match(с)
    if m:
        было, ещё, всего = (int(m.group(i)) for i in (3, 5, 8))
        return было + ещё == всего
    return None


# РУССКАЯ СТАВКА ВМЕСТИЛИЩА. Имена вещей и вместилищ по-русски нельзя
# вывести из английских — их объявляет слой, и суд ЧИТАЕТ ЭТО
# ОБЪЯВЛЕНИЕ, а не гадает по окончанию. Отсутствие объявления есть
# отказ, а не чистота (М-88).
def _русские_имена():
    import ast
    ф = КОРЕНЬ / "tools/gen_genesis_rates.py"
    вон = {}
    try:
        дерево = ast.parse(ф.read_text(encoding="utf-8"))
    except OSError:
        return вон
    for узел in дерево.body:
        if (isinstance(узел, ast.Assign)
                and isinstance(узел.targets[0], ast.Name)
                and узел.targets[0].id in ("ВЕЩЬ_RU", "ВМЕСТИЛИЩЕ_RU")):
            try:
                вон[узел.targets[0].id] = ast.literal_eval(узел.value)
            except (ValueError, SyntaxError):
                continue
    return вон


РУССКИЕ = _русские_имена()
# форма → основа: «яблока»/«яблок» → ключ вещи; «упаковке»/«упаковки» → ключ
ВЕЩЬ_ПО_ФОРМЕ = {ф: ключ
                 for ключ, формы in (РУССКИЕ.get("ВЕЩЬ_RU") or {}).items()
                 for ф in формы}
ВМЕСТ_ПО_ФОРМЕ = {ф: ключ
                  for ключ, формы in
                  (РУССКИЕ.get("ВМЕСТИЛИЩЕ_RU") or {}).items()
                  for ф in формы}

СТАВКА_ВМЕСТ_RU = re.compile(r"^в (\S+) (\d+) (\S+)\.$")
КРАТНО_ВМЕСТ_RU = re.compile(r"^(\d+) (\S+) вмещают (\d+) (\S+)\.$")
СТАВКИ_RU = {}


def впитать_русские_ставки(путь):
    """Ставка объявлена слоем строкой «в упаковке 2 яблока»."""
    СТАВКИ_RU.clear()
    with путь.open(encoding="utf-8", errors="replace") as поток:
        for строка in поток:
            m = СТАВКА_ВМЕСТ_RU.match(строка.strip())
            if not m:
                continue
            вмест = ВМЕСТ_ПО_ФОРМЕ.get(m.group(1))
            вещь = ВЕЩЬ_ПО_ФОРМЕ.get(m.group(3))
            if вмест and вещь:
                СТАВКИ_RU.setdefault((вмест, вещь), set()).add(int(m.group(2)))


def русская_ставка(строка):
    """(судимо, истинно) для русской ставки вместилища; None — не наше."""
    с = строка.strip()
    m = СТАВКА_ВМЕСТ_RU.match(с)
    if m:
        вмест = ВМЕСТ_ПО_ФОРМЕ.get(m.group(1))
        вещь = ВЕЩЬ_ПО_ФОРМЕ.get(m.group(3))
        if not (вмест and вещь):
            return None
        # СТАВКА ПРИНАДЛЕЖИТ ПАРЕ, И ДВЕ РАЗНЫЕ У ОДНОЙ ПАРЫ СУТЬ
        # ПРОТИВОРЕЧИЕ, которого не увидит счёт: обе строки верны
        # поодиночке.
        return len(СТАВКИ_RU.get((вмест, вещь), {0})) == 1
    m = КРАТНО_ВМЕСТ_RU.match(с)
    if m:
        k, всего = int(m.group(1)), int(m.group(3))
        вмест = ВМЕСТ_ПО_ФОРМЕ.get(m.group(2))
        вещь = ВЕЩЬ_ПО_ФОРМЕ.get(m.group(4))
        объявлено = СТАВКИ_RU.get((вмест, вещь)) if вмест and вещь else None
        if not объявлено or len(объявлено) != 1:
            return None
        return всего == k * next(iter(объявлено))
    return None


# УПАКОВАТЬ МОЖНО ВЕЩЬ, НО НЕ МЕРУ — И ЭТО ОБЪЯВЛЕНО РЯДОМ СО СПИСКОМ
# (М-103). «apples come 2 to a pack» истинно, «acres come 2 to a pack»
# безупречно грамматически и ложно о мире: у акра нет штук, которые
# кладут в коробку. Двадцать таких строк стояли вне суда последними —
# не оттого, что их нечем проверить, а оттого, что суд ждал ВТОРОЙ
# поверхности отношения и молчал, когда её не было. Проверяемое здесь
# не число, а РОД: вторая поверхность уточняет ставку, объявление —
# саму возможность её иметь.
КОРОБКИ = {"pack", "box", "crate", "batch", "packs", "boxes",
           "crates", "batches"}


def упаковка_возможна(строка):
    """Можно ли упаковать названное; None — не наше."""
    m = ПРИХОДЯТ.match(строка.strip())
    if not m:
        return None
    вещь, _, вместилище = m.groups()
    if вместилище not in КОРОБКИ:
        return None
    один = singular(вещь)
    if вещь not in ПРЕДМЕТЫ and один not in ПРЕДМЕТЫ:
        return None
    можно = {вещь, один} & {*PACKAGEABLE,
                            *(singular(w) for w in PACKAGEABLE)}
    return bool(можно)


