# РОД ВЕЩИ ОБЪЯВЛЕН РЯДОМ СО СПИСКОМ, И ПОТОМУ ПРОВЕРЯЕМ (М-103).
# «the teacher is a thing» и «the books are here» безупречны
# грамматически и ложны о мире — тот же род ошибки, что «ida bought 3
# friends». Восемьсот строк этого рода стояли вне суда не оттого, что
# их нечем проверить, а оттого, что никто не спросил: суд ВЛАДЕЕТ
# одушевлённостью, объявленной в `gsm_items.py`.
#
# ЧИСЛО ТОЖЕ УТВЕРЖДЕНИЕ: «is» стоит при единственном, «are» при
# множественном, и подмена одного другим есть ложь о языке, отличимая
# от лжи о мире.
# ЛИЦО ГЛАГОЛА ЕСТЬ УТВЕРЖДЕНИЕ О ЯЗЫКЕ, И ОНО ОБЪЯВЛЕНО. «vera walks
# 9 kilometers every day. they walk 9 kilometers every day» ставит
# рядом третье лицо единственного и множественное — и подмена одного
# другим есть ложь, отличимая от лжи о счёте. Формы объявлены в пакете
# СПИСКОМ, как объявлены формы существительных: правило «прибавь s»
# лгало бы на «catches», а угадывать язык суд не вправе.
ЛИЦОМ = re.compile(
    rf"^({С}) ({С}) (\d+) ([\w ]+?) every day\. "
    rf"they ({С}) (\d+) ([\w ]+?) every day\.$")
# ПЕРФЕКТ И ПРОШЕДШЕЕ — ДВЕ КЛЕТКИ ОДНОЙ ПАРАДИГМЫ: «has seen» рядом с
# «saw» истинно ровно тогда, когда обе формы объявлены формами одного
# глагола.
ПЕРФЕКТОМ = re.compile(
    rf"^({С}) has ({С}) (\d+) ([\w ]+?)\. \1 ({С}) (\d+) ([\w ]+?)\.$")

_ГЛАГОЛЫ = None


def глаголы():
    """(основа→третье лицо, прошедшее→причастие) — из пакета."""
    global _ГЛАГОЛЫ
    if _ГЛАГОЛЫ is None:
        пакет = КОРЕНЬ / "tools/langpacks/en.json"
        try:
            п = json.loads(пакет.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            п = {}
        _ГЛАГОЛЫ = (п.get("verb_forms") or {},
                    п.get("verb_perfect") or {})
    return _ГЛАГОЛЫ


def лицо_сходится(строка):
    """Сходятся ли формы глагола и остальное; None — не наше."""
    с = строка.strip()
    m = ЛИЦОМ.match(с)
    if m:
        _, третье, n1, вещь1, основа, n2, вещь2 = m.groups()
        формы, _ = глаголы()
        if основа not in формы:
            return None
        return (формы[основа] == третье and n1 == n2
                and вещь1.strip() == вещь2.strip())
    m = ПЕРФЕКТОМ.match(с)
    if m:
        _, причастие, n1, вещь1, прошедшее, n2, вещь2 = m.groups()
        _, перфект = глаголы()
        if прошедшее not in перфект:
            return None
        return (перфект[прошедшее] == причастие and n1 == n2
                and вещь1.strip() == вещь2.strip())
    return None


# СТАВКА В ДЕНЬ, ПОМНОЖЕННАЯ НА ДНИ, ЕСТЬ ИТОГ — и форма вещи идёт за
