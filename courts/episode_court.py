def _звено_итога(m, a, b, знак, итог):
    """The optional link after the total names the same operation."""
    if m.group(10) is None:
        return True
    return (int(m.group(10)), m.group(11), int(m.group(12)), int(m.group(13))) == (a, знак, b, итог)
