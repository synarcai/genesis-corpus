def боевые_рамки(строка):
    """(судимо, истинно) для рамок боевых слоёв; None — не наше."""
    с = строка.strip()
    for образец, знак in ((УБЫЛО_СБЕРЁГ, -1), (УБЫЛО_ОСТАЛОСЬ, -1),
                          (ПРИБЫЛО_ТЕПЕРЬ, 1)):
        m = образец.match(с)
        if not m:
            continue
        г = m.groups()
        было, ушло, итог = int(г[1]), int(г[3]), int(г[6])
        вещи = {singular(г[i]) for i in (2, 4, 5, 7)}
