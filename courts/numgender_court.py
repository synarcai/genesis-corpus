#!/usr/bin/env python3
"""[РОД ЧИСЛИТЕЛЬНОГО] — «один» и «два» гнутся по роду того, что считают, а имя — по ним.

    РОД ЧИСЛИТЕЛЬНОГО ЕСТЬ РОД ИМЕНИ; ЯЧЕЙКА ИМЕНИ ЕСТЬ ЧИСЛО ЧИСЛИТЕЛЬНОГО.

ПОВОД, НАЙДЕННЫЙ 22.09 ГЛАЗОМ И ПОДТВЕРЖДЁННЫЙ ПРИБОРОМ. Счётный дом вьетнамского писал
русскую глоссу «hai tờ báo — два газеты»; прибор, спросивший всю свод дверями `rugram`, нашёл
143 такие строки в одиннадцати мирах: «два книги», «один минута», «один яблоко», и даже
обратное — «одна шар», где род взят не у того имени. Хуже всех — дом украинского счёта,
чьё дело и есть счётная форма: «двадцять один книга», «двадцять два книги».

Вчерашний отчёт назвал это ПРОБЕЛОМ: «род числительного не объявлен ни одним пакетом». Это
был не пробел, а ЛОЖЬ, ещё не предъявленная суду: ни один из трёхсот судов не спрашивал рода
числа, и суд согласования прямо объявлял его чужим («согласование по роду и падежу — иной
род дефекта, иной прибор»). Вот этот прибор.

ЧТО СУДИТСЯ. «один / одна / одно / два / две» и украинские «один / одна / одне / два / дві»
перед ИМЕНЕМ, чья форма и род известны дверям:

  · русское — `rugram`: форма узнаётся по объявленным тройкам, род — `rugram.род`;
  · украинское — пакетом `uk`: формы — его `noun_count`, род — `langpack.род_имени`.

Составное судится последним словом: в «двадцать один книга» лжёт «один».

ЧЕГО СУД НЕ СУДИТ, И ЭТО ГРАНИЦА, А НЕ ПОЛНОТА:

  · цифру: «1 книги» судит суд согласования, ибо порча там родилась цифрой; здесь судится
    число СЛОВОМ — и в нём заодно ячейка имени: «два час», «два стол» лгут тем же местом,
    что «два книги», и суд, видящий одно и слепой к другому, судил бы половину фразы;
  · имя, чью форму двери не знают, и имя, чей род дверь отказалась назвать (мягкий знак,
    не объявленный): незнание не есть находка;
  · падеж: «двух книг», «одной книги» — числительное в косвенном падеже есть иная рамка;
  · ЦИТАТУ НЕВЕРНОГО: строку с меткой отказа («¬ два кіт.») и форму под звёздочкой («*два
    кіт»). Свод их не утверждает, а ОТВЕРГАЕТ — и суд, назвавший отвергнутое ложью, лгал бы
    сам: первая редакция этого суда обвинила семнадцать таких строк в трёх мирах.

    python3 courts/numgender_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-world-file
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import langpack  # noqa: E402 — двери пакета: формы числительного и род имени
import manifest_kinds  # noqa: E402 — метка отказа кузни пакетов, объявленная там, а не здесь
import rugram  # noqa: E402 — дверь русских форм и русского рода

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

_ПАКЕТЫ = {яз: json.loads((КОРЕНЬ / "tools" / "langpacks" / f"{яз}.json").read_text(encoding="utf-8"))
           for яз in ("ru", "uk")}


def _числа(пакет):
    """Слово числительного → (цифра, род) по объявлению пакета."""
    return {ф.lower(): (цифра, род) for цифра, формы in пакет["numeral_gender"].items()
            for род, ф in формы.items()}


_ЧИСЛА = {яз: _числа(п) for яз, п in _ПАКЕТЫ.items()}


def _формы_uk():
    """Украинская форма → (лемма, ячейка): «книги» → («книга», 1)."""
    вон = {}
    for лемма, формы in _ПАКЕТЫ["uk"]["morph_classes"]["noun_count"]["lexemes"].items():
        for ячейка, ф in enumerate(формы):
            вон.setdefault(ф.lower(), (лемма, ячейка))
    return вон


_ФОРМЫ_UK = _формы_uk()


def _имя_ru(форма, ячейка):
    """(род, форма нужной ячейки) — или None, если дверь имени не знает."""
    ключ = rugram.ПО_ФОРМЕ.get(форма)
    if ключ is None or форма not in rugram.СЧЁТНЫЕ[ключ][:3]:
        return None
    try:
        return rugram.род(ключ), rugram.СЧЁТНЫЕ[ключ][ячейка]
    except KeyError:
        return None


def _имя_uk(форма, ячейка):
    найдено = _ФОРМЫ_UK.get(форма)
    if найдено is None:
        return None
    лемма, _ = найдено
    формы = _ПАКЕТЫ["uk"]["morph_classes"]["noun_count"]["lexemes"][лемма]
    if ячейка >= len(формы):
        return None
    try:
        return langpack.род_имени(_ПАКЕТЫ["uk"], лемма), формы[ячейка]
    except KeyError:
        return None


_ДВЕРИ = {"ru": _имя_ru, "uk": _имя_uk}

# ЧИСЛО ЭТОМУ СУДУ СВОБОДНО ЦЕЛИКОМ, и это объявлено ПРИБОРУ МУТАНТОВ, а не умолчано.
# Предмет суда есть ЧИСЛИТЕЛЬНОЕ СЛОВОМ и форма имени при нём; цифра в строке ему не
# подсудна вовсе. Подсадка «8 шаров стоят 64 карты» → «9 шаров» рода не касается, и
# вердикт «истина» о ней честен — её ловит арифметика, чей это предмет.
#
# ВТОРОЙ ПРОВЕРЯЮЩИЙ НАЗВАН, ИБО ИСКЛЮЧЕНИЕ БЕЗ НЕГО ЕСТЬ ПОБЛАЖКА: порчу СЛОВА над этим
# судом ставит `scripts/word_mutants.py` (обрезание и подмена слова), а свои подсадки —
# число не того рода и форма не той ячейки — суд ставит себе сам (`_подсадки`, 27 из 27).
СВОБОДНОЕ_ЧИСЛО = (re.compile(r"\d+"),)
_ПАРА = {яз: re.compile(r"(?<![\w'-])(" + "|".join(sorted(ч, key=len, reverse=True))
                        + r")\s+([^\W\d_]+)", re.IGNORECASE)
         for яз, ч in _ЧИСЛА.items()}


def _под_звездой(строка, начало):
    """Стоит ли место в цитате, помеченной звёздочкой как неверная.

    ЗВЕЗДА МЕТИТ ЦИТАТУ, А НЕ СЛОВО: в «*двадцать два час» она стоит перед «двадцать», и суд,
    смотревший лишь знак перед «два», назвал ложью шесть отвергнутых цитат двух миров.
    """
    if начало > 0 and строка[начало - 1] == "*":
        return True
    открыта = строка.rfind("«", 0, начало)
    return (открыта >= 0 and строка.find("»", открыта, начало) < 0
            and строка[открыта + 1:открыта + 2] == "*")


def разбор(строка):
    """[(как написано, как надо)] — всякое судимое МЕСТО строки, по разу.

    ОДНО МЕСТО, ДВА ЯЗЫКА. «два книги» есть форма и русская, и украинская, и обе двери его
    судят; место считается ОДИН раз и ложно лишь тогда, когда лжёт на ВСЕХ языках, его
    судивших: «дві книги» верно по-украински, и русская дверь его вовсе не видит, — но
    место, верное хоть на одном языке, есть строка этого языка, а не ложь чужого.
    """
    места = collections.defaultdict(list)
    if строка.lstrip().startswith(manifest_kinds.ОТКАЗ_МЕТКА):
        return []
    for яз, пара in _ПАРА.items():
        for м in пара.finditer(строка):
            if _под_звездой(строка, м.start()):
                continue
            числ, форма = м.group(1).lower(), м.group(2).lower()
            цифра, _ = _ЧИСЛА[яз][числ]
            ячейка = 0 if цифра == "1" else 1
            имя = _ДВЕРИ[яз](форма, ячейка)
            if имя is None:
                continue
            род, форма_надо = имя
            надо = _ПАКЕТЫ[яз]["numeral_gender"][цифра][род]
            места[м.span()].append((f"{числ} {форма}", f"{надо} {форма_надо}"))
    вон = []
    for _, суды in sorted(места.items()):
        верный = next(((б, н) for б, н in суды if б == н), None)
        вон.append(верный or суды[0])
    return вон


def судить(строка):
    """(судимо, истинно): числительное при имени согласовано по роду — или лжёт."""
    сочетания = разбор(строка)
    if not сочетания:
        return False, False
    return True, all(было == надо for было, надо in сочетания)


def _подсадки():
    """Верные сочетания всех родов, испорченные родом: каждую суд обязан назвать ложью."""
    вон = []
    for яз, (форма_ед, форма_мн, род) in (("ru", ("книга", "книги", "ж")),
                                          ("ru", ("яблоко", "яблока", "с")),
                                          ("ru", ("шар", "шара", "м")),
                                          ("uk", ("книга", "книги", "ж")),
                                          ("uk", ("яблуко", "яблука", "с"))):
        формы = _ПАКЕТЫ[яз]["numeral_gender"]
        for цифра, форма in (("1", форма_ед), ("2", форма_мн)):
            верное = f"{формы[цифра][род]} {форма}"
            for чужой, слово in формы[цифра].items():
                if слово != формы[цифра][род]:
                    вон.append((f"на полке {верное}.", f"на полке {слово} {форма}."))
        # ЯЧЕЙКА: число верного рода при форме чужой ячейки — «две книга», «одна книги»
        вон.append((f"на полке {формы['2'][род]} {форма_мн}.", f"на полке {формы['2'][род]} {форма_ед}."))
        вон.append((f"на полке {формы['1'][род]} {форма_ед}.", f"на полке {формы['1'][род]} {форма_мн}."))
    return вон


# ОТВЕРГНУТОЕ НЕ СУДИТСЯ: строка отказа и форма под звёздочкой суть цитаты неверного.
_ОТВЕРГНУТОЕ = (f"{manifest_kinds.ОТКАЗ_МЕТКА} два книга.", "по-русски говорят не «*два книги», а «две книги».",
                "свод отвергает «*двадцать два час.» и ставит «двадцать два часа.».")


def main():
    """Миры манифеста — или явные пути лентой; пропавший файл и пустой обход — ОТКАЗ.

    ПОМЕТА ПУСТОГО ОБХОДА ЕСТЬ ОБЕЩАНИЕ УМЕТЬ ОТКАЗАТЬ: суд, зовомый с путём, которого нет,
    обязан сказать «нечего судить», а не «ложных ноль». Ноль лжей на пустоте есть зелёный
    цвет без суда.
    """
    итог = collections.Counter()
    примеры = collections.Counter()
    from genesis import worlds  # noqa: E402
    явные = [pathlib.Path(а) for а in sys.argv[1:]]
    for путь in явные:
        if not путь.is_file():
            print(f"РОД ЧИСЛИТЕЛЬНОГО ОТКАЗ: файла нет — {путь}")
            return 2
    файлов = 0
    for путь in (явные or worlds(kind="shows")):
        файлов += 1
        for с in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            for было, надо in разбор(с):
                итог["судимых"] += 1
                if было != надо:
                    итог["ложных"] += 1
                    примеры[(путь.stem.replace("genesis_", ""), было, надо)] += 1
    поймано = 0
    подсадки = _подсадки()
    for верное, битое in подсадки:
        assert судить(верное) == (True, True), верное
        if судить(битое) == (True, False):
            поймано += 1
    if not итог["судимых"]:
        print(f"РОД ЧИСЛИТЕЛЬНОГО ОТКАЗ: судить нечего — {файлов} файлов, ни одного числа при имени")
        return 2
    for отвергнутое in _ОТВЕРГНУТОЕ:
        судимо, истинно = судить(отвергнутое)
        assert not судимо or истинно, ("суд назвал ложью цитату неверного", отвергнутое)
    for (мир, было, надо), n in примеры.most_common(8):
        print(f"  ЛОЖЬ ×{n} [{мир}]: «{было}» — надо «{надо}»")
    поза = ("PASS" if итог["ложных"] <= ЛОЖНЫХ_РУБЕЖ and поймано == len(подсадки)
            else "FAIL")
    print(f"РОД ЧИСЛИТЕЛЬНОГО {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых "
          f"(рубеж {ЛОЖНЫХ_РУБЕЖ}; {файлов} файлов), подсадок поймано {поймано} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
