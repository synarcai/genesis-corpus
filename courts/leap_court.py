#!/usr/bin/env python3
"""[ВИСОКОСНЫЙ ГОД] — правило с двумя вложенными исключениями, пересчитанное судом.

Суд не пишет закона заново: он берёт его у дома (`leapforms`), где годы объявлены ЧЕТЫРЬМЯ
таблицами — по одной на каждый слой правила и одна на простой отказ, — а число високосных в
веке не объявлено, а ПЕРЕСЧИТАНО перебором ста лет. Всякая запись страницы считается разбором
свода (`arithread`), знающим скобку ПОЯСНЕНИЯ: «1900 делится на четыре (1900 ÷ 4 = 475)» несёт
скобку речи, а не записи.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: все ТРИ слоя правила обязаны быть
показаны — без любого из них правило становится ложью, а не упрощением; счёт по векам обязан
дать ОБА числа, 24 и 25, иначе исключение не видно; и всякая таблица обязана быть тем, чем
названа.

    python3 courts/leap_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import leapforms  # noqa: E402 — дом, объявивший множитель размерности

ИМЯ_СУДА = "leap"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"leap"})


def _судить(строка):
    return leapforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ВИСОКОСНЫЙ ГОД {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(leapforms.РОДЫ)}, страниц {len(leapforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
