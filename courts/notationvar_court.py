#!/usr/bin/env python3
"""[НАЧЕРТАНИЕ] — одна запись, сказанная двумя начертаниями.

ОДИН ЗНАК, ДВА НАЧЕРТАНИЯ — ОБА ЖИВУТ, ИЛИ ОРГАНИЗМ ЗНАЕТ ОДНО. Замер
по своду в 194 392 строки: «x^2» — 1702 раза, «x²» — НОЛЬ; «≤» — 351,
«<=» — НОЛЬ; «sqrt» — 2091, «√» — шесть. Корпус знает каждый знак лишь
в ОДНОМ начертании, и в разных знаках — в разных.

СУД ИСПОЛНЯЕТ, А НЕ СВЕРЯЕТ СО СПИСКОМ. Он приводит обе записи к
КАНОНУ (`tools/notation_variants.канон`) и требует их совпадения; для
неравенств он ВЫЧИСЛЯЕТ вердикт сам, а не читает написанный. Оттого
показ, где начертания разошлись, есть ЛОЖЬ, а не неизвестность.

ГРАНИЦА ОТКАЗА ОБЪЯВЛЕНА: суд берётся лишь за строки объявленных здесь
форм. Всякая иная запись со знаком «≤» или «x²» ему не подсудна —
молчание честнее вердикта о том, чего не разбирал.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import notation_variants as НВ  # noqa: E402
from genesis import worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ПАРА = re.compile(r"^«(.+?)» и «(.+?)» суть одна запись\.?$")
ПАРА_EN = re.compile(r"^«(.+?)» and «(.+?)» are one record\.?$")
ВОПРОС = re.compile(r"^как ещё пишется «(.+?)»\? — «(.+?)»\.?$")
ВОПРОС_EN = re.compile(r"^how else is «(.+?)» written\? — «(.+?)»\.?$")
ОТКАЗА = re.compile(r"^у записи «(.+?)» второго начертания нет: "
                    r"ни один её знак не имеет двойника\.?$")
НЕРАВЕНСТВО = re.compile(
    r"^«(\d+) (<=|>=|!=|≤|≥|≠) (\d+)» (верно|неверно), "
    r"и «(\d+) (<=|>=|!=|≤|≥|≠) (\d+)» говорит то же\.?$")

ДЕЙСТВИЕ = {"<=": lambda a, b: a <= b, "≤": lambda a, b: a <= b,
            ">=": lambda a, b: a >= b, "≥": lambda a, b: a >= b,
            "!=": lambda a, b: a != b, "≠": lambda a, b: a != b}


def судить(строка):
    с = строка.strip()
    m = ПАРА.match(с) or ПАРА_EN.match(с)
    if m:
        а, б = m.groups()
        # ДВЕ ЗАПИСИ ОДНОЙ ВЕЩИ ОБЯЗАНЫ РАЗЛИЧАТЬСЯ. Показ ««x^2» и
        # «x^2» суть одна запись» истинен по букве и пуст по делу: он
        # не учит второму начертанию. Тождество здесь есть ложь.
        return True, а != б and НВ.канон(а) == НВ.канон(б)
    m = ВОПРОС.match(с) or ВОПРОС_EN.match(с)
    if m:
        дано, ответ = m.groups()
        двойник = НВ.двойник(дано)
        if двойник is None:
            двойник = НВ.канон(дано)
        return True, ответ == двойник and ответ != дано
    m = ОТКАЗА.match(с)
    if m:
        запись = m.group(1)
        # ОТКАЗ ПРОВЕРЯЕТСЯ ТАК ЖЕ СТРОГО, КАК УТВЕРЖДЕНИЕ: сказать «у
        # неё нет двойника» о записи, двойник у которой есть, — ложь
        # того же рода, что неверный ответ.
        return True, НВ.двойник(запись) is None
    m = НЕРАВЕНСТВО.match(с)
    if m:
        а1, з1, б1, вердикт, а2, з2, б2 = m.groups()
        если = ДЕЙСТВИЕ.get(з1)
        если2 = ДЕЙСТВИЕ.get(з2)
        if если is None or если2 is None:
            return False, True
        истина = если(int(а1), int(б1))
        сходится = (истина == если2(int(а2), int(б2))
                    and (а1, б1) == (а2, б2)
                    and НВ.канон(з1) == НВ.канон(з2)
                    and з1 != з2)
        return True, сходится and истина == (вердикт == "верно")
    return False, True


def main():
    ложных = судимых = 0
    файлов = 0
    for путь in worlds():
        if not путь.exists():
            continue
        файлов += 1
        for с in путь.read_text(encoding="utf-8").splitlines():
            судимо, истинно = судить(с)
            if not судимо:
                continue
            судимых += 1
            if not истинно:
                ложных += 1
                if ложных <= 6:
                    print(f"  ЛОЖЬ {путь.name}: {с[:90]}")
    if not файлов:
        print("НАЧЕРТАНИЕ ОТКАЗ: обход пуст, судить нечего")
        return 2
    поза = "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL"
    print(f"НАЧЕРТАНИЕ {поза}: {ложных} ложных из {судимых} судимых "
          f"({файлов} файлов, рубеж {ЛОЖНЫХ_РУБЕЖ})")
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
