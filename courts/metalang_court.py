def вычислить(формула, n):
    """Значение записи вида «n * n + n + 41» при данном n, или None.

    ФОРМУЛА ЧИТАЕТСЯ ЗАКОНОМ, А НЕ УЗНАЁТСЯ ОБРАЗЦОМ: сумма
    произведений, где множитель есть либо целое, либо буква. Всё
    прочее отвергается — суд, догадывающийся о записи, судит свою
    догадку.
    """
    итог = 0
    for слагаемое in формула.split(" + "):
        множители = слагаемое.split(" * ")
        часть = 1
        for м in множители:
            if м == "n":
                часть *= n
            elif м.isdigit():
                часть *= int(м)
            else:
                return None
        итог += часть
    return итог


_ОБЛАСТЬ = re.compile(
    r"^(?:при всяком целом n(?: больше (\d+))?"
    r"|for every whole n(?: greater than (\d+))?)$")


def начало_области(слова):
    """С какого n говорит гипотеза, или None — область не названа.

    ОБЛАСТЬ ЕСТЬ ЧАСТЬ УТВЕРЖДЕНИЯ. «n * n + 1 просто при всяком целом
    n» ложно сразу при нуле, и гипотеза, умалчивающая о своей границе,
    выдаёт за долгую правду то, что неверно с первого шага. Граница
    читается словом («больше 0»), а не берётся из списка: закон языка
    здесь тот же, что и всюду, и новое число в нём не нуждается в новой
    строке кода.
    """
    м = _ОБЛАСТЬ.match(слова)
    if м is None:
        return None
    порог = м.group(1) if м.group(1) is not None else м.group(2)
    return 0 if порог is None else int(порог) + 1


def область_максимальна(формула, начало):
    """Область названа ЦЕЛИКОМ — её нельзя продлить влево.

    ОДИН ЗАКОН НА ОБЛАСТЬ И НА ОТРЕЗОК ПОДТВЕРЖДЕНИЙ, и оба места
    куплены одной подсадкой. Гипотеза «n * n + 1 просто при всяком
    целом n больше 1» есть истина, и суд, знающий лишь истину,
    пропустит её; но она молча выбрасывает единицу, при которой
    гипотеза тоже верна, — то есть занижает, сколько раз утверждение
    держалось. Граница области законна там, где слева от неё формула
    УЖЕ не проста (или где целых чисел больше нет).
    """
    return начало == 0 or not просто(вычислить(формула, начало - 1))


def просто(n):
    if n < 2:
        return False
    d = 2
    while d * d <= n:
        if n % d == 0:
            return False
        d += 1
    return True


def притворщица_верна(формула, начало, предел, убийца, значение, мал,
                      частное):
    """Гипотеза, верная до границы и убитая за нею, — ОТРЕЗОК ПРОЙДЕН.

    Проверяется ВСЁ, что показ утверждает, и порознь: что граница есть
    та, что названа (всё до неё просто), что убийца вправду убивает
    (значение составное), и что разложение сходится с наименьшим
    делителем. Показ, где верно два из трёх, учит доверять границам, за
    которые никто не ходил.

    ОТРЕЗОК ПОДТВЕРЖДЕНИЙ ОБЯЗАН БЫТЬ МАКСИМАЛЕН ВЛЕВО, И ЭТОТ ЗАКОН
    КУПЛЕН ПОДСАДКОЙ. Прибор мутантов сдвинул начало с нуля на единицу,
    и суд первой редакции назвал испорченное истиной: отрезок 1..39
    вправду весь прост. Но показ говорит не о КАКОМ-ТО отрезке, а о
    том, СКОЛЬКО РАЗ гипотеза подтвердилась, — и урезанный слева
    отрезок скрывает ровно это число. Оттого требуется, чтобы слева от
    начала отрезок было НЕЛЬЗЯ продлить: либо там нет целых, либо там
    формула уже не проста. Закон выводится счётом и не нуждается ни в
    каком объявленном списке областей.
    """
    if вычислить(формула, убийца) != значение:
        return False
    if мал * частное != значение or мал < 2 or мал > частное:
        return False
    if значение % мал or просто(значение):
        return False
    if предел != убийца - 1 or начало > предел or начало < 0:
        return False
    if начало and просто(вычислить(формула, начало - 1)):
        return False
    return all(просто(вычислить(формула, n))
               for n in range(начало, убийца))


