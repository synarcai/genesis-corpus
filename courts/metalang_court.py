_ПРЕДСТ = re.compile(r"^(\d+) = (\d+) \* (\d+)(?: \+ (\d+))?$")


def представление(запись, ожидаемое=None):
    """(n, d) из «6 = 2 * 3» или «7 = 2 * 3 + 1», или None — не сходится.

    ЗАКОН НУЛЕВОГО СЛАГАЕМОГО ПРОВЕРЯЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ:
    «6 = 2 * 3 + 0» отвергается вовсе. Слагаемое, равное нулю, не
    пишется — и запись, его написавшая, есть нарушение закона, а не
    другой способ сказать то же.
    """
    м = _ПРЕДСТ.match(запись)
    if м is None:
        return None
    n, d, k = (int(з) for з in м.groups()[:3])
    r = int(м.group(4)) if м.group(4) is not None else 0
    if м.group(4) is not None and r == 0:
        return None
    if d < 2 or not 0 <= r < d or n != d * k + r:
        return None
    if ожидаемое is not None and n != ожидаемое:
        return None
    return n, d


_ЦЕПЬ = re.compile(
    r"^(\d+) ([+*]) (\d+) = (\d+) \* \( (.+?) \)(?: \+ (\d+))? = "
    r"(\d+) \* (\d+)(?: \+ (\d+))? = (\d+)$")


def цепь_верна(запись, знак=None, a=None, b=None):
    """Цепь доказательства — ПЕРЕСЧИТАНА ПО ЗВЕНЬЯМ И ПО СТРОЕНИЮ.

    ОЖИДАЕМОЕ СТРОИТСЯ ЗДЕСЬ, А НЕ СВЕРЯЕТСЯ СО СТРОКОЙ. Суд берёт из
    записи только a, b и делитель, САМ выводит k и r делением, САМ
    выводит, какие слагаемые обязаны стоять внутри скобки, — и требует
    совпадения списком. Проверка «итог сходится» без этого пропустила
    бы «4 + 6 = 2 * ( 1 + 4 ) = 2 * 5 = 10»: счёт верен, а разложение
    выдумано, и организм выучил бы ход, которого не бывает.

    Оба хвоста (после скобки и после второго произведения) обязаны
    нести ОДИН И ТОТ ЖЕ остаток, и нулевой не пишется ни в одном.
    """
    м = _ЦЕПЬ.match(запись)
    if м is None:
        return False
    сa, сзнак, сb, d1, внутри, хв1, d2, K, хв2, итог = м.groups()
    сa, сb, d1, d2, K, итог = (int(з) for з in (сa, сb, d1, d2, K, итог))
    if знак is not None and сзнак != знак:
        return False
    if a is not None and (сa, сb) != (a, b):
        return False
    if d1 != d2 or d1 < 2:
        return False
    if (хв1 is None) != (хв2 is None):
        return False
    if хв1 is not None and (хв1 != хв2 or int(хв1) == 0):
        return False
    остаток = int(хв1) if хв1 is not None else 0
    d = d1
    k1, r1 = divmod(сa, d)
    k2, r2 = divmod(сb, d)
    сырой = (r1 + r2) if сзнак == "+" else (r1 * r2)
    перенос, свой_остаток = divmod(сырой, d)
    if остаток != свой_остаток:
        return False
    if сзнак == "+":
        ожидаемые = [str(k1), str(k2)]
        K_свой = k1 + k2 + перенос
    else:
        ожидаемые = [f"{d} * {k1} * {k2}"]
        ожидаемые += [str(ч) for ч in (k1 * r2, k2 * r1) if ч]
        K_свой = d * k1 * k2 + k1 * r2 + k2 * r1 + перенос
    if перенос:
        ожидаемые.append(str(перенос))
    return (внутри.split(" + ") == ожидаемые and K == K_свой
            and d * K + остаток == итог
            and счесть(сзнак, сa, сb) == итог)


