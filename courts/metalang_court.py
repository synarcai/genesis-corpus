def _н_случай_закона(м):
    """Закон верен, условие на числах выполнено, счёт сошёлся, род итога тот.

    Ядро всех падежных поверхностей теоремы: «по теореме», «теоремой
    доказано», «обоих условий требует». Проверяется то же, что и у
    самой теоремы, — иначе падежная поверхность была бы дешевле
    прямой, и организм выучил бы, что косвенная речь не обязывает.
    """
    д = м.groupdict()
    разбор = разобрать_закон(д["закон"])
    if разбор is None or not закон_верен(разбор):
        return False
    знак, (d, r1), (_d2, r2), (_dи, rи) = разбор
    a, b, итог = int(д["a"]), int(д["b"]), int(д["итог"])
    if д.get("сa") is not None and (int(д["сa"]), int(д["сb"])) != (a, b):
        return False
    if д.get("знак") is not None and д["знак"] != знак:
        return False
    if д.get("сит") is not None and int(д["сит"]) != итог:
        return False
    if д.get("имяи") is not None and род(д["имяи"]) != (d, rи):
        return False
    if д.get("имя1") is not None and (
            род(д["имя1"]), род(д["имя2"])) != ((d, r1), (d, r2)):
        return False
    return (a % d == r1 and b % d == r2 and счесть(знак, a, b) == итог
            and итог % d == rи)


def _н_цепь_с_итогом(м):
    """Цепь, чей итог назван отдельно, и род итога — если назван."""
    д = м.groupdict()
    if not цепь_верна(д["цепь"]):
        return False
    м2 = _ЦЕПЬ.match(д["цепь"])
    a, знак, b, итог = (int(м2.group(1)), м2.group(2), int(м2.group(3)),
                        int(м2.group(10)))
    if д.get("итог") is not None and int(д["итог"]) != итог:
        return False
    if д.get("a") is not None and (int(д["a"]), int(д["b"])) != (a, b):
        return False
    if д.get("зп") is not None:
        п = представление(д["зп"])
        if п is None or п[0] not in (a, b):
            return False
    if д.get("имяи") is not None:
        р = род(д["имяи"])
        # РОД ИТОГА НАЗЫВАЕТСЯ ДЕЛИТЕЛЕМ ЦЕПИ, А НЕ ЛЮБЫМ СВОИМ. Число
        # 350 даёт остаток 2 и при делении на 3, и при делении на 4, и
        # суд, проверявший лишь остаток, называл истиной заключение о
        # чужом делителе при верной цепи. Заключение доказательства
        # есть заключение ЭТОГО доказательства.
        if р is None or р[0] != int(м2.group(4)) or итог % р[0] != р[1]:
            return False
    if д.get("сa") is not None:
        if (int(д["сa"]), int(д["сb"])) != (a, b) or д["знак"] != знак:
            return False
        if int(д["сит"]) != итог:
            return False
    return True


def _н_контрпример(м):
    """Свидетель убивает: условие выполнено, счёт сошёлся, заключение нет."""
    д = м.groupdict()
    разбор = разобрать_закон(д["закон"])
    if разбор is None or закон_верен(разбор):
        return False
    знак, (d, r1), (d2, r2), (dл, rл) = разбор
    if d != d2 or д["знак"] != знак:
        return False
    a, b, итог = int(д["a"]), int(д["b"]), int(д["итог"])
    if a % d != r1 or b % d != r2 or счесть(знак, a, b) != итог:
        return False
    if итог % dл == rл:
        return False
    п = представление(д["зп"], итог)
    return п is not None and п[1] == dл


def _н_два_контрпримера(м):
    """Два РАЗНЫХ свидетеля, и каждый убивает сам по себе."""
    д = м.groupdict()
    первый = _н_контрпример(м)
    if not первый:
        return False
    разбор = разобрать_закон(д["закон"])
    знак, (d, r1), (_d2, r2), (dл, rл) = разбор
