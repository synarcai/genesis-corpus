# ИМЯ РОДА ЧИТАЕТСЯ В ПАРУ (ДЕЛИТЕЛЬ, ОСТАТОК) — ЭТО И ЕСТЬ ВСТРЕЧНЫЙ
# ХОД. Генератор строил имя по паре; суд добывает пару из имени и
# дальше не имеет дела со словами вовсе. Синонимы законны: «чётно» и
# «делится на 2 без остатка» суть один род, и суд, требующий одного из
# них, судил бы ВЫБОР СЛОВА вместо истины.
ИМЕНА_РОДОВ = (
    (re.compile(r"^чётно$"), lambda м: (2, 0)),
    (re.compile(r"^нечётно$"), lambda м: (2, 1)),
    (re.compile(r"^is even$"), lambda м: (2, 0)),
    (re.compile(r"^is odd$"), lambda м: (2, 1)),
    (re.compile(r"^делится на (\d+) без остатка$"),
     lambda м: (int(м.group(1)), 0)),
    (re.compile(r"^is divisible by (\d+)$"),
     lambda м: (int(м.group(1)), 0)),
    (re.compile(r"^даёт остаток (\d+) при делении на (\d+)$"),
     lambda м: (int(м.group(2)), int(м.group(1)))),
    (re.compile(r"^leaves remainder (\d+) when divided by (\d+)$"),
     lambda м: (int(м.group(2)), int(м.group(1)))),
)


def род(имя):
    """(делитель, остаток) по имени рода, или None — имя не рода.

    Пара с остатком, не меньшим делителя, отвергается: «даёт остаток 5
    при делении на 3» есть запись, которой в мире нет, и принять её
    значило бы завести род, которого не бывает.
    """
    for образец, взять in ИМЕНА_РОДОВ:
        м = образец.match(имя)
        if м:
            d, r = взять(м)
            return (d, r) if d > 1 and 0 <= r < d else None
    return None


# ------------------------------------------- РАЗБОР ЗАКОНА НАЗАД

НЕ_ДЕЛИТСЯ = (re.compile(r"^не делится на (\d+)$"),
              re.compile(r"^is not divisible by (\d+)$"))


def остатки(имя):
    """(делитель, множество остатков) по сказуемому, или None.

    ОТРИЦАНИЕ ЕСТЬ ДОПОЛНЕНИЕ: «не делится на d» называет все остатки,
    кроме нуля, и утверждение с ним верно лишь при каждом из них. Род с
    одним остатком есть частный случай — множество из одного числа.
    """
    for образец in НЕ_ДЕЛИТСЯ:
        м = образец.match(имя)
        if м:
            d = int(м.group(1))
            return (d, frozenset(range(1, d))) if d > 1 else None
    р = род(имя)
    return None if р is None else (р[0], frozenset((р[1],)))


ЗАКОН_RU = re.compile(r"^если a (.+?) и b (.+?), то a ([+*]) b (.+)$")
ЗАКОН_EN = re.compile(r"^if a (.+?) and b (.+?), then a ([+*]) b (.+)$")


def разобрать_закон(текст):
    """(знак, род1, род2, родИтога) из всеобщего утверждения, или None."""
    м = ЗАКОН_RU.match(текст) or ЗАКОН_EN.match(текст)
    if м is None:
        return None
    п1, п2, знак, пи = м.groups()
    роды = [род(п1), род(п2), род(пи)]
    if any(р is None for р in роды):
        return None
    return (знак, *роды)


def разобрать_закон_множеств(текст):
    """(знак, (d, R1), (d, R2), (d, Rи)) — закон со сказуемыми-множествами."""
    м = ЗАКОН_RU.match(текст) or ЗАКОН_EN.match(текст)
    if м is None:
        return None
    п1, п2, знак, пи = м.groups()
    роды = [остатки(п1), остатки(п2), остатки(пи)]
    if any(р is None for р in роды):
        return None
    return (знак, *роды)


def закон_верен_всюду(разбор):
    """Истина ПРИ КАЖДОЙ паре остатков из названных множеств."""
    знак, (d1, R1), (d2, R2), (dи, Rи) = разбор
    return d1 == d2 == dи and all(
        итог_рода(знак, d1, r1, r2) in Rи for r1 in R1 for r2 in R2)


def итог_рода(знак, d, r1, r2):
    """Закон остатка — СЧЁТ СУДА, а не сверка с чужим ответом."""
    return ((r1 + r2) % d) if знак == "+" else ((r1 * r2) % d)


def счесть(знак, a, b):
    return a + b if знак == "+" else a * b


def закон_верен(разбор):
    """Всеобщее утверждение ИСТИННО — по закону остатков, а не по случаю.

    Три рода обязаны стоять при ОДНОМ делителе: утверждение, где
    условие о двойке, а заключение о четвёрке, есть ровно та ловушка,
    ради которой заведён контрпример, и теоремой её звать нельзя.
    """
    знак, (d1, r1), (d2, r2), (dи, rи) = разбор
    return d1 == d2 == dи and rи == итог_рода(знак, d1, r1, r2)


