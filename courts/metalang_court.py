"""СУД МЕТАЯЗЫКА ДОКАЗАТЕЛЬСТВА: слово судится СОДЕРЖАНИЕМ ПРИ НЁМ.

Слой метаязыка говорит словами «теорема», «условие», «заключение»,
«лемма», «следствие», «гипотеза», «контрпример» — и ровно в этом его
опасность. Слово метаязыка нельзя пересчитать: «теорема» не сходится и
не расходится ни с чем. Оттого суд не судит слов ВОВСЕ, а судит то, что
при них стоит, и требует, чтобы стояло ИМЕННО ТО, что слово обещает:

    при УСЛОВИИ    — числа, которые ВПРЯМЬ обладают названным родом;
    при ЗАКЛЮЧЕНИИ — посчитанный итог, ВПРЯМЬ обладающий названным;
    при ДОКАЗАТЕЛЬСТВЕ — цепь равенств, где сходится КАЖДОЕ звено;
    при КОНТРПРИМЕРЕ — свидетель, который ВПРЯМЬ опровергает;
    при ГИПОТЕЗЕ  — случай, который ВПРЯМЬ её подтверждает, и граница
                    подтверждений, которая ВПРЯМЬ там, где названа.

Строка, где слово стоит при чужом или несходящемся содержании, есть
ЯРЛЫК, и ярлык здесь объявляется ложью наравне с ошибкой в счёте.

ЧТО ЗНАЧИТ «СВОИМ КОДОМ» ЗДЕСЬ, И ЭТО ГЛАВНОЕ О ВСТРЕЧНОСТИ. Генератор
идёт ОТ РОДОВ К ЧИСЛАМ: берёт пару (делитель, остаток), строит имя,
строит числа, строит цепь. Суд идёт ОБРАТНО — ОТ ИМЕНИ К РОДУ и ОТ
ЧИСЕЛ К СТРУКТУРЕ: он читает «даёт остаток 1 при делении на 3» и
добывает пару (3, 1); он берёт из строки числа a и b и САМ выводит,
какие слагаемые ОБЯЗАНЫ стоять внутри скобки, а потом требует
совпадения списком. Ошибка в законе остатка, в переносе или в нулевом
слагаемом ломает встречу, а не проходит сквозь обе стороны одинаково.

ЗАКОН ПРОВЕРЯЕТСЯ ЗАКОНОМ, А НЕ СЛУЧАЕМ. Теорема слоя есть всеобщее
утверждение, и суд проверяет ЕГО САМО — своей формулой остатков
(r = (r1 + r2) mod d для суммы, r = (r1 * r2) mod d для произведения),
— а уже потом проверяет случай при нём. Показ, где случай сходится, а
утверждение ложно, есть самая убедительная ложь корпуса: у него верны
все числа. Оттого проверяются оба, и порознь.

ОСОБО О КОНТРПРИМЕРЕ. «Утверждение ложно, ибо при a = 2 и b = 4
выходит 6» проверяется ТРЕМЯ вещами разом: условие на свидетеле
ВЫПОЛНЕНО (иначе свидетель не о том утверждении), счёт сходится, и
заключение на итоге НАРУШЕНО (иначе свидетель ничего не убил). Показ,
у которого верны две из трёх, учит опровергать мимо цели.

ОСОБО О ГИПОТЕЗЕ, УБИТОЙ ДАЛЬНИМ СВИДЕТЕЛЕМ. «Верна при n от 0 до 39,
но при n = 40 выходит 1681 = 41 * 41» есть утверждение о ВСЁМ отрезке,
и проверить его можно только пройдя отрезок. Суд его проходит: все
сорок значений обязаны быть простыми, сороковое — составным, и его
разложение обязано сойтись. Граница, которую никто не проверял, есть
худший род корпусного мусора: она выглядит знанием и есть догадка.

ОСОБО ОБ ОТКРЫТОЙ ГИПОТЕЗЕ. «Доказательства у неё нет» пересчитать
нельзя: это утверждение о состоянии математики, а не о числах. Оттого
формулировка таких гипотез объявлена ЗДЕСЬ ВТОРОЙ РУКОЙ, и суд
сверяет с объявлением; правка формулировки в одном доме и не в другом
делает строку НЕСУДИМОЙ, а ворота записи несудимую строку не
пропускают — и слой не будет записан вовсе. Числа при гипотезе
пересчитываются как всякие другие.

СУД НЕ СМЕЕТ ЧИТАТЬ ЧУЖОЙ РОД. Образцы привязаны к зачину строки;
неузнанная строка есть (False, False) — молчание, а не вердикт.
Прибор, судящий по совпадению формы, обвиняет честное: этот шрам
корпус уже покупал шестью русскими ставками, объявленными ложью чужим
судом.
"""

