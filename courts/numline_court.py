#!/usr/bin/env python3
"""[ЧИСЛОВАЯ ПРЯМАЯ] — порядок и расстояние, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`numlineforms`), где пары объявлены тремя
таблицами — обе отрицательные, обе положительные и через ноль. Всякая запись страницы
считается разбором свода (`arithread`), знающим ОДНОМЕСТНЫЙ МИНУС: «3 − (−5) = 8» есть
честная запись прямой, и разбор, не берущий её, объявил бы её ложью, а не непонятной.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: обе стороны ловушки обязаны быть
показаны, у отрицательной пары цифры обязаны ЛГАТЬ (иначе ловушка не видна), а минус обязан
писаться знаком свода «−», а не дефисом.

    python3 courts/numline_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import numlineforms  # noqa: E402 — дом, объявивший порядок на прямой

ИМЯ_СУДА = "numline"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"numline"})


def _судить(строка):
    return numlineforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ЧИСЛОВАЯ ПРЯМАЯ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(numlineforms.РОДЫ)}, страниц {len(numlineforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
