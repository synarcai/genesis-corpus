#!/usr/bin/env python3
"""[СУД ДОВОДА О ГОВОРЯЩЕМ] — ряд довода найден по объявлению; МИР ЗАМКНУТ.

Страница мира (`tools/adhominem.py`) есть утверждение, довод к нему и ИМЯ, какое странице
дано доводу: о деле, о говорящем, о говорящем но к делу.

    ДОВОД О ГОВОРЯЩЕМ МОЖЕТ БЫТЬ ИСТИННЫМ И ВСЁ РАВНО НЕ ОТНОСИТЬСЯ К ДЕЛУ. «Он ошибся
    вчера» бывает чистой правдой и ничего не говорит о том, верно ли сказанное сегодня. Ложь
    тут ни при чём: негодность довода лежит не в его истинности, а в том, О ЧЁМ ОН.

Граница прибора объявлена прямо:

    СУД НЕ ПОНИМАЕТ «ОТНОСИТСЯ ЛИ» И НЕ БЕРЁТСЯ. Он смотрит, ИЗ КАКОГО ОБЪЯВЛЕННОГО РЯДА
    взят довод — из свойств предмета или из свойств говорящего, — и этого довольно.

Две строгости сверх ответа: РЯД ДОВОДА обязан сойтись с именем, какое ему дала страница, и
МЕСТО довода — с утверждением. Довод о бочке, приставленный к мосту, истинен сам по себе и
ложен здесь; эта подмена в живом рассуждении встречается чаще первой и заметна хуже.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import adhominem as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"adhominem"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_adhominem.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_adhominem.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_adhominem.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ДОВОД О ГОВОРЯЩЕМ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
