#!/usr/bin/env python3
"""[РАЗРЯД] — вес места цифры, пересчитанный судом.

Суд не пишет закона заново: он берёт его у дома (`placevalforms`), где имена мест и веса объявлены
одной таблицей. Подмена цифры, места и САМОГО ВЕСА ловится машинально: разложение, разность и
частное пересчитываются, а ловушка обязана стоять НА ОДНИХ ЦИФРАХ — иначе она не о местах.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

НОЛЬ СУДИТСЯ КАК ДЕРЖАТЕЛЬ МЕСТА: страница рода обязана нести трёхзначное число с нулём
ПОСЕРЕДИНЕ и двузначное, вышедшее из него выбрасыванием нуля. Ноль в конце — другой закон,
и о нём этот дом молчит.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/placeval_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import placevalforms  # noqa: E402 — дом, объявивший места и веса

ИМЯ_СУДА = "placeval"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"placeval"})


def _судить(строка):
    return placevalforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"РАЗРЯД {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(placevalforms.РОДЫ)}, страниц {len(placevalforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
