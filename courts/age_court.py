def _кратное_вперёд(г, лица, форма, к):
    """Кратность НАСТУПАЕТ: сдвиг обоим, и лишь тогда отношение."""
    а, б = лица
    if not двое_разных(а, б):
        return False
    ва, вб, с, па, пб, па2, пб2 = чис(
        г, "va", "vb", "s", "pa", "pb", "pa2", "pb2")
    return (с >= 1 and ва >= 1 and вб >= 1
            and па == ва + с and пб == вб + с
            and па2 == па and пб2 == пб and па == к * пб
            and г["ys"] == форма(с))


def _кратное_вперёд_en(г):
    if г["a"] != г["a2"] or г["b"] != г["b2"] or г["a"] == г["b"]:
        return False
    return _кратное_вперёд(г, (г["a"], г["b"]), years,
                           ПО_КРАТНОМУ_EN[г["k"]])


