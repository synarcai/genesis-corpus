def _кратное_en(г):
    """Кратность СЛОВОМ и та же кратность ЧИСЛОМ — обе из ряда."""
    if г["a"] != г["a2"] or г["b"] != г["b2"] or г["a"] == г["b"]:
        return False
    ва, вб, ва2, кн, вб2 = чис(г, "va", "vb", "va2", "kn", "vb2")
    к = ПО_КРАТНОМУ_EN[г["k"]]
    return (ва == к * вб and ва2 == ва and вб2 == вб and кн == к
            and вб >= 1)


def _кратное_ru(г):
    а = одно_лицо(г, ("da", ПО_ДАТЕЛЬНОМУ), ("ia", ПО_ИМЕНИТЕЛЬНОМУ))
    б = одно_лицо(г, ("db", ПО_ДАТЕЛЬНОМУ), ("gb", ПО_РОДИТЕЛЬНОМУ))
