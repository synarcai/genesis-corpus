#!/usr/bin/env python3
"""[ВОЗРАСТ] — сдвиг прибавляется ОБОИМ, и суд прибавляет его сам.

Мир возраста говорит о величине, которая движется вместе со временем.
Суд берёт из строки возраста и сдвиг — и всё остальное считает заново:
складывает, вычитает, умножает, берёт разницу ДО сдвига и ПОСЛЕ него и
сверяет их между собою.

ГЛАВНЫЙ ЗАКОН СУДИТСЯ ПЕРЕСЧЁТОМ, А НЕ СЛОВОМ. Строка «разница не
меняется» есть УТВЕРЖДЕНИЕ, и суд, поверивший ему на слово, пропустил
бы ровно ту порчу, ради которой мир и написан: сдвиг, прибавленный
ОДНОМУ. Здесь разница считается дважды — из нынешних возрастов и из
будущих, — и обе обязаны сойтись с названной. Показ, где том состарился
на три года, а аня осталась при своих, умирает на этой сверке, хотя все
его числа по отдельности верны.

ИМЯ СКЛОНЯЕТСЯ, И ПАДЕЖИ ОБЪЯВЛЕНЫ ЗДЕСЬ ВТОРОЙ РУКОЙ. Тот же список,
что в генераторе, записан отдельно; правка в одном доме и не в другом
делает строку НЕСУДИМОЙ, а ворота записи несудимую строку не
пропускают. Больше того: образец берёт ТОЛЬКО объявленные формы, и
потому «аня старше ани» не проходит не по счёту, а по лицу — суд
сверяет, что именительный и дательный указывают на ОДНОГО человека, а
старший и младший суть РАЗНЫЕ люди.

СЧЁТНАЯ ФОРМА ПЕРЕСЧИТЫВАЕТСЯ ДОМОМ ЯЗЫКА. «1 год», «3 года», «5 лет»
и «1 year», «3 years» проверяются у `tools/rugram.py` и
`tools/plural.py` — там, где эти законы объявлены. Суд не держит своей
таблицы форм: вторая таблица разошлась бы с первой в первый же день.

ГРУППЫ НАЗВАНЫ, А НЕ СОСЧИТАНЫ. Образцы здесь несут до тринадцати
величин, и позиционная скобка в таком образце есть готовый шрам: сдвиг
на единицу в счёте групп не заметен ни глазу, ни синтаксису, а вердикт
выносится по соседнему числу. Имя группы делает такую ошибку
невозможной, а не обнаружимой.

ЧЕГО СУД НЕ ЧИТАЕТ: чужого рода. Все образцы привязаны к зачину и к
ОБЪЯВЛЕННЫМ именам; неузнанная строка есть (False, False).
"""

