def лет(сколько):
    return rugram.форма("год", сколько)


def years(сколько):
    return by_count(сколько, "years")


def чис(г, *имена):
    """Целые из НАЗВАННЫХ групп."""
    return [int(г[и]) for и in имена]


def одно_лицо(г, *пары):
    """Указывают ли названные формы на ОДНОГО человека.

    `пары` — (имя группы, таблица форм). Форма, которой нет в таблице,
    невозможна: образец её бы не принял; но проверка стоит здесь, ибо
    суд обязан падать на своём противоречии, а не на чужом.
    """
    кто = set()
    for имя, таблица in пары:
        если = таблица.get(г[имя])
        if если is None:
            return None
        кто.add(если)
    return next(iter(кто)) if len(кто) == 1 else None


def двое_разных(а, б):
    return а is not None and б is not None and а != б


