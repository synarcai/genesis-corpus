def выбор(слова):
    """Образец, берущий ТОЛЬКО объявленное, и ничего кроме.

    Длинное впереди короткого: иначе «три» откусит начало у «тридцати»,
    а «о брате» распадётся на предлог и слово.
    """
    return "(?:" + "|".join(sorted((re.escape(с) for с in слова),
                                   key=len, reverse=True)) + ")"


