def _закон(г, лица, форма):
    """ЗАКОН: разница ДО сдвига и ПОСЛЕ него — одна и та же.

    Три сверки, и ни одна не лишняя: сдвиг прибавлен старшему, сдвиг
    прибавлен младшему, и разница, названная в конце, равна обеим
    разницам. Порча, двинувшая одного, ломает вторую и третью разом —
    а порча, подменившая одну лишь названную разницу, ломает третью.
    """
    а, б = лица
    if not двое_разных(а, б):
        return False
    ва, вб, с, па, пб, р = чис(г, "va", "vb", "s", "pa", "pb", "r")
    return (с >= 1 and па == ва + с and пб == вб + с
            and р == ва - вб and р == па - пб and р > 0
            and г["ys"] == форма(с) and г["yr"] == форма(р))


