#!/usr/bin/env python3
"""[ДВА «БЫТЬ»] — согласие страницы с законом выбора между «ser» и «estar».

Суд не знает испанского. Он берёт цитаты, стоящие в «ёлочках», и спрашивает у дома три вещи,
объявленные там таблицей: сходится ли глагол с МЕТКОЙ СМЫСЛА при цитате (СВОЙСТВО — «es»,
СОСТОЯНИЕ — «está»), не поставлены ли предлог и глагол НАКРЕСТ («es en», «está de»), и не
пошло ли занятие через «estar». Четвёртый закон — о ЗВЁЗДОЧКЕ: цитата, помеченная ею, обязана
нарушать один из трёх, а непомеченная — не нарушать ни одного.

    СТРАНИЦА, ПОКАЗЫВАЮЩАЯ ЗАПРЕЩЁННОЕ, ОБЯЗАНА ПОМЕЧАТЬ ЕГО ЗНАКОМ, КОТОРЫЙ ЧИТАЕТ СУД:
    иначе учить ошибке и совершать её — одно и то же на вид.

ЧТО ЭТОТ СУД СТЕРЕЖЁТ, И ЭТО НЕ ЧИТАТЕЛЬ. Порча чужой рукой ловится закрытым набором дома
(строка, разошедшаяся с показом одним словом, есть порча этой страницы). Содержательные
законы выше сторожат ПИСЦА: они ловят ложь, порождённую самим домом, — и потому пробуются
ложной страницей, вписанной в набор на время опыта, а не мутантом.

    python3 courts/serestar_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import serestarforms  # noqa: E402 — дом, показывающий закон двух «быть»

ИМЯ_СУДА = "serestar"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"serestar"})


def _судить(строка):
    return serestarforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ДВА «БЫТЬ» {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(serestarforms.РОДЫ)}, "
          f"страниц {len(serestarforms.ПОКАЗЫ)}, "
          f"перемен смысла {len(serestarforms.ПЕРЕМЕНЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
