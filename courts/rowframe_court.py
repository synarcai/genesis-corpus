#!/usr/bin/env python3
"""[РАМКА РЯДА] — ряд из трёх и более шагов, повторяющий свою рамку, не терпит в ней БЛИЗНЕЦА.

    СЛОВО, СКАЗАННОЕ ТРИЖДЫ, САМО СЕБЕ СВИДЕТЕЛЬ. Там, где строка повторяет одну рамку над
    разными числами, порча одного её слова видна БЕЗ СЛОВАРЯ И БЕЗ ЯЗЫКА: два целых шага
    показывают, как слово пишется, а третий пишет иначе.

ПОВОД. [ПОДСАДКА СЛОВОМ] держит долг: строк, где палата зовёт порченое слово ИСТИНОЙ, было 85 из
4793 проб в 25 мирах, и худшим стоял мир индукции — 12 дыр из 22. Его страницы суть ряды:
«0² + 0 + 41 = 41 is een priemgetal. 1² + 1 + 41 = 43 is een priemgetal. …», «3 — простое.
5 — простое. 7 — простое. значит ли, что…». Обрезание «een» → «ee» не трогает ни одного числа,
и всякий суд, читающий числа, о нём МОЛЧИТ.

    СУДЫ ПОКАЗОВ ЧИТАЮТ ЧИСЛА, А СЛОВА У НИХ ДЕКОРАЦИЯ — и лечится это не словарём на каждый
    язык, а ЗАКОНОМ ЗАМКНУТОГО МИРА: истина берётся из самой строки.

ЗАКОН. Строка режется на шаги по точке и вопросу; шаги переводятся в СКЕЛЕТЫ — наборы слов от
двух букв, без чисел. Если шагов три и более и один скелет стои́т в двух и более шагах БЕЗ
НИЧЬЕЙ — он объявляется РАМКОЙ. Шаг, чей скелет той же длины и расходится с рамкой РОВНО В ОДНОМ
месте, где слово КОРОЧЕ рамочного на последний знак («ee» при «een»), — ЛОЖЕН.

ГРАНИЦА ОБЪЯВЛЕНА ЗАМЕРОМ, А НЕ ОБЕЩАНИЕМ. Четыре меры искали ту же порчу; три названы здесь
ПОИМЁННО, ибо каждая выглядела законом и НИ ОДНА им не была:

  · БЛИЗНЕЦ ПО ВСЕЙ СТРОКЕ (слово, стоящее раз, при слове на букву длиннее, стоящем дважды):
    9979 обвинений, и все честные — «apple»/«apples», «cent»/«cents», «собрал»/«собрала»,
    «ein»/«eine», «nell»/«nella».
  · ОБРЕЗОК ПО СЛОВАРЮ МИРА (слово, стоящее в мире однажды, при своём удлинении, стоящем пять
    раз и более): 94 обвинения — «kid»/«kids», «blume»/«blumen», «godzin»/«godziny».
  · ОБРЕЗОК СЛУЖЕБНОГО СЛОВА (слово, которого пакет языка не объявил, при объявленном служебном
    на букву длиннее): 9907 обвинений — «habe»/«haben», «viel»/«viele», «uno»/«unos»,
    «no»/«non». Мера пакетной НЕПОЛНОТЫ, а не порчи.

        ПОРЧА СЛОВА НЕОТЛИЧИМА ОТ СЛОВОИЗМЕНЕНИЯ БЕЗ ОБЪЯВЛЕННОГО СЛОВАРЯ ЯЗЫКА. Всякая мера,
        берущая истину из ДОГАДКИ о языке, меряет эту догадку. Устояла одна — та, что берёт
        истину ИЗ САМОЙ СТРОКИ: ряд, повторивший рамку трижды, сам себе словарь.

  · РАМКА РЯДА даёт НОЛЬ обвинений на 405 654 строках показов; судимых рядов 19 674.

ЧЕГО ЗАКОН НЕ ВИДИТ, СКАЗАНО ЗДЕСЬ ЧИСЛОМ. Строк о трёх и более шагах 147 582, из них со
словами во всяком шаге 123 114, а РАМКУ держат 19 674: прочие разошлись словами, и это законно
— числительное словом само есть слово, и «twee appels» против «drie appels» рамкой не стоит.
Не видит закон и порчи, задевшей ДВА слова разом; и порчи, попавшей в рамку ДВАЖДЫ, — тогда
лжёт большинство, и суд назовёт ложным целый шаг.

ЧЕМ ЭТОТ ЗАКОН МОЖЕТ УКУСИТЬ ЗАВТРА, СКАЗАНО СЕГОДНЯ. Суд стои́т в палате, а палата есть
ВОРОТА ЗАПИСИ: ложный вердикт здесь не портит корпус, он ОТКАЗЫВАЕТ честной строке. Опасен
ровно один вид ряда — тот, где рамка гнётся ЧИСЛОМ, а не порчей:

    «I have 1 apple. I have 3 apples. I have 5 apples.»

Большинство держит «apples», одинокий шаг пишет «apple», и это ОБРЕЗАНИЕ на последний знак —
суд назвал бы честную строку ложной. Ныне таких строк в корпусе НЕТ (замер: 0 обвинений на
405 654 строках), и потому обхода здесь не написано: код против случая, которого не было,
проверить нечем, а непроверенный обход есть та же догадка. День, когда дом напишет такой ряд,
узнается СРАЗУ — ворота откажут кузнице, — и лечение известно заранее: показать полосу счёта
отдельным показом, как это сделано в польском пакете, либо объявить обход ЗАМЕРЕННЫМ числом.

    python3 courts/rowframe_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402 — общий слой замкнутого мира
import foreign  # noqa: E402 — закон чужого текста: полка и проза судятся своим договором

ИМЯ_СУДА = "rowframe"
СЛОВО = re.compile(r"[^\W\d_]{2,}", re.UNICODE)
# РЕЗ ИДЁТ ПО ТОЧКЕ И ВОПРОСУ, НО НЕ ПО ВОСКЛИЦАНИЮ: «!» есть ещё и ЗНАК ФАКТОРИАЛА, и
# ряд «1! + 1 = 2 est premier. 2! + 1 = 3 est premier.» он рвёт на куски без слов —
# рамка пропадает, и суд немеет там, где ловил. Замерено: с «!» ряд факториалов уходит
# из-под суда целиком.
ШАГ = re.compile(r"[.?。？]\s+")
ШАГОВ_НАИМЕНЬШЕ = 3

# ЧИСЛО ЗДЕСЬ СВОБОДНО ЦЕЛИКОМ, И ЭТО НЕ УСТУПКА, А ПРЕДМЕТ СУДА. Скелет шага строится из слов
# и ТОЛЬКО из слов: «3 — простое» и «5 — простое» суть один скелет, и в этом вся сила закона —
# он читает рамку поверх разных чисел. Подсадка в число («41» → «42») рамки не трогает, и
# молчание о ней честно: её ловит арифметика, чей это предмет. Объявлено ПРИБОРУ МУТАНТОВ,
# а не спрятано: суд, не сказавший, чего он не читает, зелен обманом.
СВОБОДНОЕ_ЧИСЛО = (re.compile(r"\d+"),)


# ДЕШЁВЫЙ ОТКАЗ ПЕРЕД ДОРОГИМ РАЗБОРОМ: суд стои́т в палате, а палату зовут на КАЖДОЙ строке
# свода — четыреста тысяч раз за обход. Ряда из трёх шагов не бывает при менее чем двух
# концах предложения, и счёт знаков дешевле разреза образцом. Смысл не меняется ни на строку.
КОНЦЫ = ".?。？"


def _рамка(строка):
    """(рамка, скелеты) для ряда, повторяющего одну рамку, — иначе None."""
    if sum(строка.count(з) for з in КОНЦЫ) < ШАГОВ_НАИМЕНЬШЕ - 1:
        return None
    шаги = [ш for ш in ШАГ.split(строка.strip()) if ш.strip()]
    if len(шаги) < ШАГОВ_НАИМЕНЬШЕ:
        return None
    скелеты = [tuple(с.lower() for с in СЛОВО.findall(ш)) for ш in шаги]
    if any(not с for с in скелеты):
        return None
    счёт = collections.Counter(скелеты)
    рамка, сколько = счёт.most_common(1)[0]
    if сколько < 2 or sum(1 for _, н in счёт.items() if н == сколько) > 1:
        return None  # ничья: рамки нет, и большинства нет
    return рамка, скелеты


def близнец(слово, рамочное):
    """Порча одного знака: ОБРЕЗАНИЕ последнего, и только оно.

    ПОДМЕНА ОДНОЙ БУКВЫ ЗАКОНОМ НЕ ЧИТАЕТСЯ, И ЭТО КУПЛЕНО ЗАМЕРОМ. Пока шаги резались одной
    точкой, судимых рядов было 713 и обвинений ноль — при обоих родах близнеца. Как только рез
    расширили вопросом и восклицанием (713 → 19 656 рядов), подмена дала 132 обвинения, и все
    честные: «in der Kiste sind 5 Nachrichten. in der Liste sind 8 Nachrichten» — Kiste и Liste
    суть ДВА РАЗНЫХ ПРЕДМЕТА, отличных одной буквой, и ряд об обоих законен.

        ДВА СЛОВА, РАЗНЯЩИЕСЯ ОДНОЙ БУКВОЙ, БЫВАЮТ ДВУМЯ СЛОВАМИ. ОДНО СЛОВО, УКОРОЧЕННОЕ НА
        БУКВУ, НЕ БЫВАЕТ ДРУГИМ СЛОВОМ ТОГО ЖЕ РЯДА — ибо ряд повторяет РАМКУ, а не предмет.

    Порча подменой не уходит без суда: подмена НЕОТЛИЧИМОЙ буквой другого письма («простoе» с
    латинской «o») делает слово смешанным, и его ловит суд письма, чей это предмет.
    """
    return len(рамочное) == len(слово) + 1 and рамочное.startswith(слово)


def расхождения(строка):
    """Слова шагов, что стоя́т близнецами рамочных, — список (шаг, слово, рамочное)."""
    вон = _рамка(строка)
    if вон is None:
        return None
    рамка, скелеты = вон
    вин = []
    for н, скелет in enumerate(скелеты):
        if скелет == рамка or len(скелет) != len(рамка):
            continue
        места = [м for м in range(len(скелет)) if скелет[м] != рамка[м]]
        if len(места) != 1:
            continue
        м = места[0]
        if близнец(скелет[м], рамка[м]):
            вин.append((н, скелет[м], рамка[м]))
    return вин


class Слой(closedworld.Слой):
    """Признак ЧУЖОГО ТЕКСТА — тот же общий закон, что у судов памяти, счёта и артикля.

    ПРИБОР ПРОЗЫ НАЗВАЛ ЗДЕСЬ ДЕВЯТЬ ВОЗРАЖЕНИЙ В ТОТ ЖЕ ДЕНЬ, КОГДА СУД ПОСТАВЛЕН (09.09).
    Ряд из трёх шагов бывает и в прозе — но проза цитирует, обрывает и переносит, и рамка её
    рядов не есть рамка показа. МЕРА ПОКАЗОВ ЧУЖОМУ ТЕКСТУ НЕ СУДЬЯ, и молчание тут есть
    подсудность, а не слепота.
    """

    ИМЯ_СУДА = "rowframe"

    def __init__(self):
        super().__init__()
        self.полка = False

    def впитать(self, путь):
        super().впитать(путь)
        self.полка = foreign.чужой(путь, self.ИМЯ_СУДА)


def судить(строка, слой=None):
    """(судимо, истинно): рамка ряда держится во всех его шагах."""
    if слой is not None and getattr(слой, "полка", False):
        return False, True          # чужой текст: мера показов ему не судья
    вин = расхождения(строка)
    if вин is None:
        return False, True
    return True, not вин


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    по_мирам = collections.Counter()
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                по_мирам[путь.stem] += 1
                if len(примеры) < 5:
                    вин = расхождения(строка)
                    что = ", ".join(f"«{с}» при «{р}»" for _, с, р in вин)
                    примеры.append(f"{путь.stem}: {что} — {строка.strip()[:80]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"РАМКА РЯДА {поза}: {ложных} ложных из {судимо} судимых рядов (рубеж 0)"
          + (f"; миры: {dict(по_мирам.most_common(5))}" if по_мирам else ""))
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
