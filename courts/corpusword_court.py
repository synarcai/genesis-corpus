#!/usr/bin/env python3
"""[СЛОВО ИЗ СВОДА] — слово мира показов, которого свод не знает нигде, есть порча.

ПОВОД НАЗВАН ЧИСЛОМ, И НЕ МНОЮ. Прибор «подсадка словом» два дня подряд даёт одно и то же:

    ПОДСАДКА СЛОВОМ FAIL: проб 6 802 — ПОЙМАН 6 553 (96%), НЕ ПОЙМАН 78 (1%)

Примеры непойманных называют дыру прямо:

    «2097152 equally likely outcomes carry 21 bits.» → «…equall likely…»  ['engram','langcount']
    «1 year = 12 months.»                           → «1 yea = 12 months.» ['engram','langcount']

    СУД, ЧИТАЮЩИЙ ЧИСЛО, МОЛЧИТ О СЛОВЕ, И ЕГО МОЛЧАНИЕ ПАЛАТА ЧИТАЕТ КАК СОГЛАСИЕ. Дыра
    здесь не в суде, а в СОСТАВЕ: на английские слова миров показов не поставлено НИКОГО.

ЧЕМ СУДИТ ЭТОТ СУД, И ПОЧЕМУ ЭТОГО ДОВОЛЬНО. Словаря английского в корпусе нет и не будет:
пакет объявляет служебные слова, имена и числительные, а не язык целиком. Зато есть СВОД — и
он сам себе словарь:

    СЛОВО, КОТОРОГО СВОД НЕ ПИШЕТ НИГДЕ, НЕ ЕСТЬ СЛОВО ЭТОГО СВОДА. Подсадка, обрезавшая
    «equally» до «equall», создаёт слово, которого в своде нет ни разу, — и тем выдаёт себя.

ДВА ИСТОЧНИКА ЗАКОННОСТИ, И ОБА НУЖНЫ:

  · СЛОВАРЬ СВОДА — все латинские слова `datasets/GENESIS-FULL.txt` (13 398 слов, читается
    за 0,66 с и живёт в памяти процесса одним множеством);
  · СЛОВАРЬ СУДИМОГО ФАЙЛА — слой, который палата строит по файлу целиком. Он нужен для
    ВОРОТ: новый мир судится ПРЕЖДЕ, чем войдёт в свод, и его слова законны потому, что он
    их пишет — все разом, а не по одному.

    СУД, ЗНАЮЩИЙ ЛИШЬ СТАРЫЙ СВОД, ОТВЕРГ БЫ ВСЯКИЙ НОВЫЙ ДОМ ЦЕЛИКОМ. Слой файла есть
    условие роста, а не послабление: подсадка портит ОДНУ строку уже записанного мира, и
    порченое слово не попадает ни в свод, ни в файл.

ГРАНИЦЫ, И ОНИ НАЗВАНЫ ЧИСЛОМ:

  · судятся ТОЛЬКО миры показов (300 из 513 объявленных) — проза полки живёт по своему
    договору, и слова её никто не обязан знать;
  · слово берётся от ДВУХ букв, и порог снижался дважды по замеру: при четырёх подсадка
    «1 year» → «1 yea» проходила незамеченной, при трёх — «the» → «th». Опасение, что
    короткие слова разных языков («ein», «los», «que», «in», «of») дадут ложные обвинения,
    замер не подтвердил: все они СТОЯ́Т В СВОДЕ и потому законны;
  · читается и КИРИЛЛИЦА, и ударение в ней: «стои́т» есть слово свода, а «стои» — нет, и
    без знака ударения в признаке первое резалось бы надвое, а второе считалось законным;
  · слова с цифрами, знаками и заглавными не читаются: имена собственные и записи формул
    не есть словарь;
  · одиночки свода (233 латинских слова живут в нём ровно раз) ЗАКОННЫ: они есть в словаре,
    и суд их пропускает. LAW = 2 стережёт `word_once`, а не этот суд.

ЦЕНА НАЗВАНА, ИБО ОНА НЕ НУЛЕВАЯ И ПАДАЕТ НА ВСЯКОГО, КТО СТРОИТ ПАЛАТУ:

    палата целиком (257 судов)   2,76 с
    словарь свода (21 278 слов)  0,82 с — один раз на процесс, лениво
    слой одного мира             0,006 с (237 слов у `compsci`)

    СУД, ЧИТАЮЩИЙ ВЕСЬ СВОД ПРИ ПОСТРОЕНИИ ПАЛАТЫ, УДОРОЖАЕТ ВСЯКИЙ ПРИБОР, КОТОРЫЙ ПАЛАТУ
    СТРОИТ, — и цена эта множится на число рабочих. Она названа здесь, чтобы тот, кто
    увидит подорожавший прогон, не искал причины в чужом приборе.

Словарь строится ЛЕНИВО — при первом вопросе к суду, — и потому приборы, до этого суда не
дошедшие, за него не платят.

    python3 courts/corpusword_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402

ИМЯ_СУДА = "corpusword"
СВОД = КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"

# ЛАТИНСКОЕ СЛОВО С ДИАКРИТИКОЙ: турецкое «kitaplar», вьетнамское «cuốn», польское «książka».
СЛОВО = re.compile(
    r"[a-zà-öø-ÿāăąćčđēėęěğīįıłńņňōőœřśşšţūůűųźżžơưа-яё́'-]{2,}")

_СЛОВАРЬ = None
_ПОКАЗЫ = None


def словарь_свода():
    """Все латинские слова свода — читается один раз на процесс."""
    global _СЛОВАРЬ
    if _СЛОВАРЬ is None:
        if СВОД.is_file():
            _СЛОВАРЬ = set(СЛОВО.findall(
                СВОД.read_text(encoding="utf-8", errors="replace").lower()))
        else:
            _СЛОВАРЬ = set()
    return _СЛОВАРЬ


def миры_показов():
    """Имена миров показов — суд молчит обо всех прочих."""
    global _ПОКАЗЫ
    if _ПОКАЗЫ is None:
        try:
            м = json.loads(МАНИФЕСТ.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            _ПОКАЗЫ = frozenset()
        else:
            _ПОКАЗЫ = frozenset(w.get("name") for w in м.get("worlds", ())
                                if w.get("text") == "shows")
    return _ПОКАЗЫ


class Слой(closedworld.Слой):
    """Имя мира от общего слоя плюс СЛОВАРЬ САМОГО ФАЙЛА.

    СЛОВАРЬ ФАЙЛА ЕСТЬ УСЛОВИЕ РОСТА: ворота судят новый мир прежде, чем он войдёт в свод,
    и слова его законны потому, что он пишет их ВСЕ РАЗОМ. Подсадка же портит одну строку
    уже записанного мира — и порченое слово не попадает ни в свод, ни в файл.
    """

    def __init__(self):
        super().__init__()
        self.слова = frozenset()

    def впитать(self, путь):
        super().впитать(путь)
        try:
            т = pathlib.Path(путь).read_text(encoding="utf-8", errors="replace")
        except OSError:
            return
        self.слова = frozenset(СЛОВО.findall(т.lower()))


def судить(строка, слой=None):
    """(судимо, истинно): латинские слова строки обязаны быть в своде или в своём файле."""
    if слой is None or getattr(слой, "мир", None) not in миры_показов():
        return False, False
    с = строка.strip()
    if not с:
        return False, False
    свод, файл = словарь_свода(), getattr(слой, "слова", frozenset())
    for w in СЛОВО.findall(с.lower()):
        if w not in свод and w not in файл:
            return True, False
    # СУД ВЫНОСИТ ТОЛЬКО ЛОЖЬ, А ИСТИНЫ НЕ ВЫНОСИТ, И ЭТО КУПЛЕНО ЗАМЕРОМ (13.09).
    #
    # Первая редакция звала истиной всякую строку, чьи слова нашлись в своде. Подсадка
    # тотчас показала цену: ОНЕМЕЛ упал со 171 до 72, а НЕ ПОЙМАН вырос с 78 до 88 —
    # строки, прежде НЕМЫЕ (их ловили ворота, ибо немую строку мир не пишет), стали
    # получать от этого суда ИСТИНУ. Пример: «the regulator…» → «th regulator…», где «th»
    # стои́т в своде и потому законно.
    #
    #     СУД, СУДЯЩИЙ СТРОКУ, НО НЕ ЧИТАЮЩИЙ ПРЕДМЕТА ПОРЧИ, ХУЖЕ МОЛЧАНИЯ: немоту ловят
    #     ВОРОТА, а ложное согласие не ловит никто.
    #
    # Ныне суд есть ЛОВЕЦ ПОРЧИ, а не подтверждатель истины: нашёл слово вне свода — ложь;
    # не нашёл — молчит, и строка остаётся на попечении тех, кто читает её по существу.
    return False, False


def main():
    import genesis
    # СВОЙ СЛОЙ СТРОИТСЯ ЗДЕСЬ, А НЕ ПАЛАТОЙ, И ЭТО НЕ СРЕЗКА УГЛА (13.09, куплено ценой):
    # `палата.слои(путь)` строит слои ВСЕХ судов для каждого мира — сотни впитываний ради
    # одного нужного. Прогон по трёмстам мирам не кончился за две минуты.
    #
    #     ПРИБОР, БЕРУЩИЙ У ПАЛАТЫ ВЕСЬ КОНТЕКСТ РАДИ ОДНОГО ЕГО ПОЛЯ, ПЛАТИТ ЗА ВСЮ ПАЛАТУ.
    #
    # Палате этот слой по-прежнему нужен — она строит его сама, когда судит строку; здесь же
    # прибор проверяет СВОЙ ЗАКОН и вправе взять лишь своё.
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        слой = Слой()
        слой.впитать(путь)
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка, слой)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"СЛОВО ИЗ СВОДА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"словарь свода {len(словарь_свода())} слов, миров показов {len(миры_показов())}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
