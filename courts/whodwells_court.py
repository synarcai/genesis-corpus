#!/usr/bin/env python3
"""[СУД РАССАДКИ ПО ОГРАНИЧЕНИЯМ] — все шесть рассадок перебраны заново; МИР ЗАМКНУТ.

Страница мира (`tools/whodwells.py`) есть три дома в ряд, несколько ограничений и одна
рассадка. Суд читает ограничения ИЗ ЗАПИСИ (чужое ограничение делает запись не нашей) и
перебирает все шесть рассадок сам.

    ОДИН ХОД И ПЕРЕСЕЧЕНИЕ ЗАПРЕТОВ — РАЗНЫЕ ДЕЛА. Модус поненс берёт одну посылку и делает
    один шаг; здесь ни одно ограничение не даёт ответа в одиночку, и ответ рождается ТЕМ,
    ЧТО ОСТАЛОСЬ, когда все запреты наложены друг на друга.

Двух вещей суд требует сверх согласия:

    ЗАДАЧА, У КОТОРОЙ ДВА РЕШЕНИЯ, НЕ ЕСТЬ ЗАДАЧА — рассадка обязана быть ЕДИНСТВЕННОЙ.
    ИЗБЫТОЧНОЕ УСЛОВИЕ НЕ УЧИТ НИЧЕМУ — набор обязан быть наименьшим: выбрось любое условие,
    и единственность обязана пропасть.

Запись с одним условием суд СУДИТ, а не пропускает молча: дом таких не строит, но молчание
вывело бы целый разряд заведомо ложных записей из-под суда.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import whodwells as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"whodwells"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_whodwells.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_whodwells.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_whodwells.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"РАССАДКА {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
