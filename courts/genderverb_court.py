#!/usr/bin/env python3
"""[РОДОВАЯ ФОРМА] — «а» есть женский род, и это проверяется СКЛЕЙКОЙ и ОБЪЯВЛЕННЫМ РОДОМ ЛИЦА.

    ОКОНЧАНИЕ ГЛАГОЛА ЕСТЬ МЕСТО НОСИТЕЛЯ ТАМ, ГДЕ ПОДЛЕЖАЩЕЕ ОПУСКАЕТСЯ. Страница «Аня
    женского рода, и потому Аня сделала» связывает род ИМЕНИ с окончанием ФОРМЫ, и суд
    сверяет эту связь с объявлением лиц, а не с чутьём.

Три проверки, и все счётны:

    женская форма обязана быть мужской ПЛЮС окончание («сделал» + «а» = «сделала»);
    названный род обязан отвечать окончанию («какого рода сделала? женского»);
    род ИМЕНИ обязан отвечать форме при нём («Аня … сделала», «Ваня … сделал»).

Подмена любой из трёх делает страницу ложной: «Ваня женского рода» — ложь по объявлению лиц,
«какого рода сделал? женского» — ложь по окончанию.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import svampforms as S  # noqa: E402

ИМЯ_СУДА = "genderverb"

ОКОНЧАНИЕ = {"ru": "а", "pl": "a"}
СЛОВА = {
    # ОБОРОТ О ФОРМЕ И ОБОРОТ О ЛИЦЕ — РАЗНЫЕ, И ЭТО НЕ ПРИДИРКА: по-польски форма есть
    # «rodzaj żeński» (именительный, о слове), а лицо — «jest rodzaju żeńskiego» (родительный,
    # о человеке). Первая редакция суда взяла один оборот на оба места и не прочла пяти
    # польских показов из пяти.
    "ru": dict(жен="женского рода", муж="мужского рода", ж="женского", м="мужского",
               какого="какого рода", потому="и потому",
               лицо_ж="женского рода", лицо_м="мужского рода"),
    "pl": dict(жен="rodzaj żeński", муж="rodzaj męski", ж="żeńskiego", м="męskiego",
               какого="jakiego rodzaju jest", потому="dlatego",
               лицо_ж="jest rodzaju żeńskiego", лицо_м="jest rodzaju męskiego"),
}
РОД_ЛИЦА = {я: {и.lower(): род for и, род, *_ in S.A.ЛИЦА[я]} for я in СЛОВА}


def _пара(язык):
    с, о = СЛОВА[язык], ОКОНЧАНИЕ[язык]
    return с, о


def судить(строка, *_):
    с = строка.strip().rstrip(".")
    for язык in СЛОВА:
        сл, ок = _пара(язык)
        # «ж — женского рода, м — мужского рода»
        м = re.match(rf"^(\S+) — {re.escape(сл['жен'])}, (\S+) — {re.escape(сл['муж'])}$", с)
        if м:
            ж, муж = м.groups()
            return True, ж == муж + ок
        # «какого рода X? женского» / «... мужского»
        м = re.match(rf"^{re.escape(сл['какого'])} (\S+)\? ({re.escape(сл['ж'])}"
                     rf"|{re.escape(сл['м'])})$", с)
        if м:
            форма, назван = м.groups()
            return True, (назван == сл["ж"]) == форма.endswith(ок)
        # «Имя женского рода, и потому Имя форма» — род объявленного лица против окончания
        for назв, знак in ((сл["лицо_ж"], "f"), (сл["лицо_м"], "m")):
            м = re.match(rf"^(\S+) {re.escape(назв)}, {re.escape(сл['потому'])} "
                         rf"(\S+) (\S+)$", с)
            if м:
                имя, имя2, форма = м.groups()
                род = РОД_ЛИЦА[язык].get(имя.lower())
                if род is None:
                    continue
                return True, (имя == имя2 and род == знак
                              and форма.endswith(ок) == (знак == "f"))
        # «какого рода Имя? женского, и потому Имя форма»
        м = re.match(rf"^{re.escape(сл['какого'])} (\S+)\? "
                     rf"({re.escape(сл['ж'])}|{re.escape(сл['м'])}), "
                     rf"{re.escape(сл['потому'])} (\S+) (\S+)$", с)
        if м:
            имя, назван, имя2, форма = м.groups()
            род = РОД_ЛИЦА[язык].get(имя.rstrip("?").lower())
            if род is None:
                continue
            жен = назван == сл["ж"]
            return True, (имя.rstrip("?") == имя2 and жен == (род == "f")
                          and форма.endswith(ок) == жен)
    return False, True


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.name}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"РОДОВАЯ ФОРМА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0)")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
