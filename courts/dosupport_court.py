#!/usr/bin/env python3
"""[АНГЛИЙСКОЕ «do»] — согласие страницы с пятью законами вспомогательного глагола.

Суд не знает английского. Он берёт цитаты в «ёлочках» и спрашивает у дома пять вещей,
объявленных там таблицей: ходит ли «does» с третьим лицом единственного, а «do» с прочими;
стои́т ли главный глагол после вспомогательного в БАЗОВОЙ форме; не взяли ли вспомогательного
связка «be» и модальные, которые идут в вопрос сами; не взял ли его вопрос о ПОДЛЕЖАЩЕМ. Пятый
закон — о ЗВЁЗДОЧКЕ: помеченная цитата обязана нарушать один из четырёх, непомеченная — не
нарушать ни одного.

    СТРАНИЦА, ПОКАЗЫВАЮЩАЯ ЗАПРЕЩЁННОЕ, ОБЯЗАНА ПОМЕЧАТЬ ЕГО ЗНАКОМ, КОТОРЫЙ ЧИТАЕТ СУД:
    иначе учить ошибке и совершать её — одно и то же на вид.

ЧТО ЭТОТ СУД СТЕРЕЖЁТ, И ЭТО НЕ ЧИТАТЕЛЬ. Порча чужой рукой ловится закрытым набором дома.
Содержательные законы выше сторожат ПИСЦА: они ловят ложь, порождённую самим домом, — и
потому пробуются ложной страницей, вписанной в набор на время опыта, а не мутантом.

    python3 courts/dosupport_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import dosupportforms  # noqa: E402 — дом, показывающий закон вспомогательного «do»

ИМЯ_СУДА = "dosupport"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"dosupport"})


def _судить(строка):
    return dosupportforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"АНГЛИЙСКОЕ «do» {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(dosupportforms.РОДЫ)}, "
          f"страниц {len(dosupportforms.ПОКАЗЫ)}, "
          f"лиц {len(dosupportforms.ЛИЦА)}, глаголов {len(dosupportforms.ГЛАГОЛЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
