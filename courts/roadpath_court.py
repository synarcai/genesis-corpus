#!/usr/bin/env python3
"""[СУД ПУТИ ПО ДОРОГАМ] — сеть построена заново, путь найден судом; МИР ЗАМКНУТ.

Страница мира (`tools/roadpath.py`) есть список дорог и один вопрос о пути. Суд строит сеть
по ЗАПИСИ, ходит по ней сам — считает кратчайшие пути и круг достижимых мест, — и собирает
страницу заново ЦЕЛИКОМ, сверяя её с записью буква в букву.

    СВЯЗЬ ПЕРЕДАЁТСЯ, А БЛИЗОСТЬ НЕТ. «А соединено с Б» и «Б с В» даёт «из А можно попасть в
    В» — но не даёт «А соединено с В».

Две строгости сверх ответа:

    ОТКАЗ БЕЗ КРУГА ЕСТЬ СЛОВО, А НЕ ДОВОД. Страница рода «никак» обязана назвать ВЕСЬ круг
    мест, куда из начала дойти можно; суд считает его сам.
    ВОПРОС, У КОГО ДВА ОТВЕТА, НЕ ЕСТЬ ВОПРОС. Род «через» строится лишь там, где кратчайший
    путь ЕДИНСТВЕН: две равные дороги делают всякий ответ и верным, и ложным.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import roadpath as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"roadpath"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_roadpath.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_roadpath.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_roadpath.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ПУТЬ ПО ДОРОГАМ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
