#!/usr/bin/env python3
"""[СУД ДВУХ СПИСКОВ] — оба списка прочитаны, дело сделано заново; МИР ЗАМКНУТ.

Страница мира (`tools/bothlists.py`) есть два списка имён и вопрос о них. Суд читает оба
списка ИЗ ЗАПИСИ и делает дело сам — пересечение, объединение или разность.

    «И» НАД ИСТИННОСТЬЮ И «И» НАД ПРИНАДЛЕЖНОСТЬЮ — ОДИН ЗАКОН И ДВА ДЕЛА. Мир булевых
    выражений учит первому; здесь то же «и» ходит по спискам, и ответ — не «да» и не «нет»,
    а ИМЕНА.

Две строгости сверх ответа:

    ПОРЯДОК ОТВЕТА ОБЪЯВЛЕН, А НЕ СЛУЧАЕН: сперва по первому списку, потом новые из
    второго. Без объявленного порядка у вопроса было бы столько ответов, сколько
    перестановок, и всякий был бы верен.
    ПУСТОЙ ОТВЕТ ЕСТЬ ОТВЕТ, И ОН НАЗВАН СЛОВОМ. «Никого» суд проверяет так же строго, как
    список имён: сказать «никого» там, где кто-то есть, — ложь, и наоборот.

Имя вне объявленных делает запись не нашей, и суд о ней молчит.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import bothlists as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"bothlists"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_bothlists.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_bothlists.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_bothlists.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ДВА СПИСКА {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
