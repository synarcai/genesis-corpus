#!/usr/bin/env python3
"""[ДЕСЯТИЧНАЯ ДОЛЯ] — десятичная запись и доля как ОДНО число, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`decforms`), где рамки и числа объявлены одной
таблицей. Подмена разряда, сотых долей, разложения знаменателя и самой ЛОВУШКИ ловится
машинально: величина десятичной записи считается по разряду, а не принимается на слово.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЗАПЯТАЯ И ТОЧКА СУТЬ ГРАНИЦЫ ЧИСЛА, КАК ДРОБНАЯ ЧЕРТА: образец, читающий «0,12 меньше 0,2» как
«12 меньше 0», берёт хвост одного числа и голову другого и зовёт истину ложью.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/dec_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import decforms  # noqa: E402 — дом, объявивший десятичную запись доли

ИМЯ_СУДА = "dec"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"dec"})


def _судить(строка):
    return decforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ДЕСЯТИЧНАЯ ДОЛЯ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(decforms.РОДЫ)}, страниц {len(decforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
