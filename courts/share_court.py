#!/usr/bin/env python3
"""СУД МИРА ДОЛЕЙ: доля, сказанная словом, ПЕРЕСЧИТЫВАЕТСЯ дробью.

Слой долей говорит шестью родами — имя и запись, доля от величины,
вопрос, сравнение, смешанное число, целое из долей, — и почти каждый
его показ несёт ОСНОВАНИЕ рядом с ответом: «12 divided by 3 is 4, and 4
times 2 is 8», «1/3 + 2/3 = 1». Суд не верит ни имени, ни ответу, ни
основанию: он ПЕРЕВОДИТ ИМЯ ОБРАТНО В ДРОБЬ и считает всё заново
точными дробями.

ЧТО ЗНАЧИТ «ЗАНОВО» ЗДЕСЬ. Генератор идёт от пары (числитель,
знаменатель) к имени и к величине; суд идёт от ИМЕНИ к паре и дальше к
счёту. Встреча идёт навстречу, а не следом: ошибка в русской форме
числителя, в законе несократимости или в счёте ломает встречу, а не
проходит сквозь обе стороны одинаково.

ИМЕНА ДОЛЕЙ ОБЪЯВЛЕНЫ ЗДЕСЬ ВТОРОЙ РУКОЙ. «две трети» есть 2/3 не
потому, что так написал генератор, а потому, что так объявлено в этом
файле отдельно от него. Правка имени в одном доме и не в другом делает
строку НЕСУДИМОЙ, а ворота записи несудимую строку не пропускают — и
слой не будет записан вовсе. Это дороже одного списка и дешевле одной
молчаливой лжи.

ЗАКОН УМНОЖЕНИЯ НА ЕДИНИЦУ ПРОВЕРЯЕТСЯ КАК ЗАКОН, А НЕ КАК ОФОРМЛЕНИЕ.
У доли с числителем один второго действия нет, и хвост «and 7 times 1
is 7» ОБЯЗАН отсутствовать; у доли с числителем больше единицы он
обязан быть и обязан сойтись. Показ, договоривший несуществующий шаг,
объявляется ложью, а не остаётся несудимым: запись действия есть
утверждение о том, что действие было.

ДОЛЯ И ЕЁ ДОПОЛНЕНИЕ ОБЯЗАНЫ БЫТЬ НЕСОКРАТИМЫ. «два шестых и четыре
шестых составляют целое» верно по счёту и неверно по речи — так не
говорят. Суд проверяет обе доли на несократимость, ибо корпус, учащий
верному счёту в несуществующем обороте, портит речь ровно там, где
чинит счёт.

ФОРМА РУССКОГО ИМЕНИ ПРЕДМЕТА — НЕ ЭТОГО СУДА РОД. «12 яблок» против
«12 яблоков» судит дом русского счёта (`rugram`), и делить один факт
надвое значило бы завести двух судей одному показу. Здесь берётся из
того дома лишь ТОЖДЕСТВО предмета: три формы одного счёта обязаны
принадлежать ОДНОМУ имени, иначе строка говорит о разных вещах и
сравнение её бессмысленно.

ВОПРОС ЕСТЬ ПРИСТАВКА К ОТВЕТУ — ОДИН ЗАКОН НА ОБЕ ВОПРОСНЫЕ
ПОВЕРХНОСТИ. Суд отрезает приставку, требует, чтобы ОСТАТОК был судимой
истиной ЭТОГО ЖЕ суда и чтобы ответ ЗАЧИНАЛСЯ подлежащим вопроса
дословно. «Чему равны две трети от 12? половина от 14 — это 7» не
пройдёт: обе половины честны, пара — нет.

ЗАЧИН ДОСЛОВЕН, А НЕ ПРОСТО УПОМЯНУТ, И ЭТО КУПЛЕНО МУТАНТОМ. Первая
редакция требовала лишь, чтобы всё названное вопросом стояло
ГДЕ-НИБУДЬ в ответе, — и пропускала «чему равны две трети от 12? две
трети от 18 — это 12»: имя стоит, и двенадцать стоит, но стоит ИТОГОМ,
а не величиной, от которой берут долю. Число обязано стоять в ответе В
ТОЙ ЖЕ РОЛИ, и дословный зачин есть самая дешёвая проверка роли.

СУД НЕ СМЕЕТ ЧИТАТЬ ЧУЖОЙ РОД. Образцы узкие и привязаны к зачину;
неузнанная строка есть (False, False) — молчание, а не вердикт. Мир
записи (`notation`) говорит «three and a half plus three and a half is
seven» СВОИМ образцом, привязанным к концу строки, и здешние показы
кончаются основанием дробями — читать их этот суд не вправе, а тот не
может.
"""

