# здесь отдельно: три русские формы на знаменатель (при одном, при
# двух-четырёх, при пяти и более) и два английских имени.
ЗНАМЕНАТЕЛИ = (
    (2, "half", "halves", ("половина", "половины", "половин")),
    (3, "third", "thirds", ("треть", "трети", "третей")),
    (4, "quarter", "quarters", ("четверть", "четверти", "четвертей")),
    (5, "fifth", "fifths", ("пятая", "пятых", "пятых")),
    (6, "sixth", "sixths", ("шестая", "шестых", "шестых")),
    (8, "eighth", "eighths", ("восьмая", "восьмых", "восьмых")),
    (10, "tenth", "tenths", ("десятая", "десятых", "десятых")),
)
СЧЁТОМ_Ж = {1: "одна", 2: "две", 3: "три", 4: "четыре", 5: "пять",
            6: "шесть", 7: "семь", 8: "восемь", 9: "девять"}
СЧЁТОМ_М = {1: "один", 2: "два", 3: "три", 4: "четыре", 5: "пять",
            6: "шесть", 7: "семь"}
СЧЁТОМ_EN = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five",
             6: "six", 7: "seven", 8: "eight", 9: "nine"}
# КРАТНОСТЬ ЕСТЬ ОТДЕЛЬНОЕ СЛОВО ЯЗЫКА, А НЕ ВЫВОД ИЗ ИМЕНИ ДОЛИ.
КРАТНО_EN = {"half": 2, "a third": 3, "a quarter": 4, "a fifth": 5}
КРАТНО_RU = {"вдвое": 2, "втрое": 3, "вчетверо": 4, "впятеро": 5}


def _имена_долей():
    """{английское имя: (ч, з)}, {русское имя: (ч, з)} — все несократимые.

    Строится тем же законом, что у слоя, но НЕЗАВИСИМО от него: суд,
    берущий имена из генератора, проверял бы генератор им же самим.
    """
    англ, рус = {}, {}
    for з, ед, мн, формы in ЗНАМЕНАТЕЛИ:
        for ч in range(1, з):
            if gcd(ч, з) != 1:
                continue
            if з == 2 and ч == 1:
                англ["half"] = рус["половина"] = (ч, з)
                continue
            англ["one " + ед if ч == 1 else
                 f"{СЧЁТОМ_EN[ч]} {мн}"] = (ч, з)
            форма = (формы[0] if ч == 1 else
                     формы[1] if ч <= 4 else формы[2])
            рус[f"{СЧЁТОМ_Ж[ч]} {форма}"] = (ч, з)
    return англ, рус


ДОЛЯ_АНГЛ, ДОЛЯ_РУС = _имена_долей()
# СМЕШАННОЕ ЧИСЛО: «полтора» — отдельное слово, а не «один с половиной».
СМЕШАННОЕ_АНГЛ = {f"{с} and a half": ц for ц, с in СЧЁТОМ_EN.items()
                  if ц in СЧЁТОМ_М}
СМЕШАННОЕ_РУС = {("полтора" if ц == 1 else f"{с} с половиной"): ц
                 for ц, с in СЧЁТОМ_М.items()}


def _выбор(имена):
    """Образец-перечень имён; ДЛИННОЕ ИМЯ ПРОБУЕТСЯ ПЕРВЫМ.

    «одна треть» и «треть» — разные имена, и перечень, поставивший
    короткое вперёд, откусил бы у длинного хвост. Тот же закон, что у
    многословных чисел в арифметическом суде: объявленное многословное
    есть ОДИН знак.
    """
    return "(" + "|".join(re.escape(и) for и in
                          sorted(имена, key=len, reverse=True)) + ")"


ДА = _выбор(ДОЛЯ_АНГЛ)
ДР = _выбор(ДОЛЯ_РУС)
СА = _выбор(СМЕШАННОЕ_АНГЛ)
СР = _выбор(СМЕШАННОЕ_РУС)
Н = r"(\d+)"
ЛИЦО_EN = r"([A-Z][a-z]+)"
ЛИЦО_RU = r"([А-ЯЁ][а-яё]+)"
ВЕЩЬ_EN = r"([a-z]+)"
ВЕЩЬ_RU = r"([а-яё]+)"


