def _доля(имя, англ):
    """(ч, з) по объявленному имени, или None."""
    return (ДОЛЯ_АНГЛ if англ else ДОЛЯ_РУС).get(имя)


def _запись(м, англ):
    """«two thirds is 2/3» — имя и запись суть ОДНО число."""
    имя, ч, з = м.groups()
    пара = _доля(имя, англ)
    return пара is not None and пара == (int(ч), int(з))


def _запись_англ(м):
    return _запись(м, True)


def _запись_рус(м):
    return _запись(м, False)


def _ответ(имя, сколько, итог, англ):
    """Доля от величины ЦЕЛАЯ и равна названному итогу."""
    пара = _доля(имя, англ)
    if пара is None:
        return False
    ч, з = пара
    доля = Fraction(ч, з) * сколько
    return доля.denominator == 1 and доля == итог


def _коротко(м, англ):
    имя, сколько, итог = м.groups()
    return _ответ(имя, int(сколько), int(итог), англ)


def _коротко_англ(м):
    return _коротко(м, True)


def _коротко_рус(м):
    return _коротко(м, False)


def _с_основанием(м, англ):
    """Ответ И ОБА ДЕЙСТВИЯ основания, и закон умножения на единицу.

    Хвост «and 4 times 2 is 8» есть УТВЕРЖДЕНИЕ О ВТОРОМ ДЕЙСТВИИ. При
    числителе один второго действия нет, и хвост обязан отсутствовать;
    при числителе больше единицы он обязан стоять и сойтись. Прибор,
    считавший хвост оформлением, пропустил бы «half of 14 is 7: 14
    divided by 2 is 7, and 7 times 1 is 7» — счёт верен, а сказанное о
    ходе счёта ложно.
    """
    (имя, сколько, итог, сколько2, з2, частное,
     частное2, ч2, итог2) = м.groups()
    пара = _доля(имя, англ)
    if пара is None:
        return False
    ч, з = пара
    сколько, итог = int(сколько), int(итог)
    if not _ответ(имя, сколько, итог, англ):
        return False
    if (int(сколько2), int(з2)) != (сколько, з):
        return False
    if сколько % з or int(частное) != сколько // з:
        return False
    if ч == 1:
        return частное2 is None and int(частное) == итог
    return (частное2 is not None and int(частное2) == сколько // з
            and int(ч2) == ч and int(итог2) == итог
            and (сколько // з) * ч == итог)


def _с_основанием_англ(м):
    return _с_основанием(м, True)


def _с_основанием_рус(м):
    return _с_основанием(м, False)


def _одна_вещь(*формы):
    """Все названные формы принадлежат ОДНОМУ объявленному имени.

    Согласование числа судит дом русского счёта; здесь берётся из него
    только ТОЖДЕСТВО: «у Тома 12 яблок, а у Ани 4 книги» есть строка о
    двух разных вещах, и сравнение в ней бессмысленно, какими бы
    верными ни были обе формы порознь.
    """
    ключи = {rugram.ПО_ФОРМЕ.get(ф) for ф in формы}
    return len(ключи) == 1 and None not in ключи


def _сравнение(м, англ):
    """«half as many apples as Tom» — доля как ОТНОШЕНИЕ ДВУХ ЧИСЕЛ."""
    (а, больше, вещь1, б, меньше, вещь2, б2, слово, вещь3,
     а2) = м.groups()
    з = (КРАТНО_EN if англ else КРАТНО_RU).get(слово)
    if з is None or а != а2 or б != б2 or а == б:
        return False
    больше, меньше = int(больше), int(меньше)
    if англ:
        одна_вещь = вещь1 == вещь2 == вещь3
    else:
        одна_вещь = _одна_вещь(вещь1, вещь2, вещь3)
    return одна_вещь and меньше * з == больше and меньше > 0


def _сравнение_англ(м):
    return _сравнение(м, True)


def _сравнение_рус(м):
    return _сравнение(м, False)


def _доля_от_чужого(м, англ):
    """«Ann has one third of what Tom has: 12 divided by 3 is 4.»

    Доля здесь обязана быть ЕДИНИЧНОЙ: «две трети от того, что у Тома»
    делением не считается, и основание, состоящее из одного деления,
    было бы неполным. Граница названа, а не подразумевается.
    """
    б, имя, а, больше, з2, меньше = м.groups()
    пара = _доля(имя, англ)
    if пара is None or а == б:
        return False
    ч, з = пара
    больше, меньше = int(больше), int(меньше)
    return (ч == 1 and int(з2) == з and больше % з == 0
            and больше // з == меньше and меньше > 0)


def _доля_от_чужого_англ(м):
    return _доля_от_чужого(м, True)


def _доля_от_чужого_рус(м):
    return _доля_от_чужого(м, False)


def _смешанное(имя, англ):
    """Целая часть смешанного имени, или None."""
    return (СМЕШАННОЕ_АНГЛ if англ else СМЕШАННОЕ_РУС).get(имя)


def _смешанная_запись(м, англ):
    """«two and a half is 5/2» — знаменатель два, числитель 2ц + 1."""
    имя, числитель = м.groups()
    целое = _смешанное(имя, англ)
    return целое is not None and int(числитель) == 2 * целое + 1


def _смешанная_запись_англ(м):
    return _смешанная_запись(м, True)


def _смешанная_запись_рус(м):
    return _смешанная_запись(м, False)


def _смешанная_сумма(м, англ):
    """СУММА ДВУХ «ц с половиной» ЕСТЬ 2ц + 1, А НЕ 2ц.

    Шрам куплен миром записи и здесь не покупается заново: половинки
    складываются в целое, и итог на единицу больше удвоенной целой
    части. Основание стоит дробями рядом, и суд складывает их сам.
    """
    имя1, имя2, итог, ч1, ч2, сумма = м.groups()
    целое = _смешанное(имя1, англ)
    if целое is None or имя1 != имя2:
        return False
    смесь = Fraction(2 * целое + 1, 2)
    return (int(ч1) == int(ч2) == 2 * целое + 1
            and int(итог) == int(сумма) == смесь * 2
            and Fraction(int(ч1), 2) + Fraction(int(ч2), 2) == int(сумма))


def _смешанная_сумма_англ(м):
    return _смешанная_сумма(м, True)


def _смешанная_сумма_рус(м):
    return _смешанная_сумма(м, False)


def _часы_англ(м):
    """«one and a half hours is 90 minutes» — час есть шестьдесят минут."""
    имя, минуты = м.groups()
    целое = _смешанное(имя, True)
    return целое is not None and int(минуты) == (2 * целое + 1) * 30


def _часы_рус(м):
    """То же по-русски; ФОРМА ИМЕНИ — род суда согласования, не этого.

    Здесь проверяется, что названы именно ЧАС и МИНУТА (тождество имён
    по объявленному дому) и что минут ровно столько, сколько выходит из
    половин часа. Верна ли форма «часа» или «часов» при этом счёте —
    вопрос дома русского счёта, и он его читает.
    """
    имя, час, минуты, минута = м.groups()
    целое = _смешанное(имя, False)
    if целое is None:
        return False
    return (rugram.ПО_ФОРМЕ.get(час) == "час"
            and rugram.ПО_ФОРМЕ.get(минута) == "минута"
            and int(минуты) == (2 * целое + 1) * 30)


def _целое(м, англ):
    """Две доли ОДНОГО знаменателя, обе несократимые, в сумме единица."""
    имя1, имя2, ч1, з1, ч2, з2 = м.groups()
    первая, вторая = _доля(имя1, англ), _доля(имя2, англ)
    if первая is None or вторая is None:
        return False
    if первая != (int(ч1), int(з1)) or вторая != (int(ч2), int(з2)):
        return False
    return (з1 == з2 and первая[1] == вторая[1]
            and Fraction(*первая) + Fraction(*вторая) == 1)


def _целое_англ(м):
    return _целое(м, True)


def _целое_рус(м):
    return _целое(м, False)


def _приставка(зачин, ответ):
    """ВОПРОС ЕСТЬ ПРИСТАВКА: ОТВЕТ ПОВТОРЯЕТ ЕГО ПОДЛЕЖАЩЕЕ ДОСЛОВНО.

    Вопросный показ верен ровно тогда, когда ответ ЗАЧИНАЕТСЯ тем же
    самым «две трети от 12 — это» и сам по себе есть судимая истина
    этого суда.

    ПЕРВАЯ РЕДАКЦИЯ ТРЕБОВАЛА МЕНЬШЕГО — «всё названное вопросом стоит
    где-нибудь в ответе», — и этого НЕ ХВАТИЛО. «Чему равны две трети
    от 12? две трети от 18 — это 12.» проходило: имя стояло в ответе, и
    двенадцать стояло в ответе — но стояло ИТОГОМ, а не величиной, от
    которой берут долю. Число, названное вопросом, обязано стоять в
    ответе В ТОЙ ЖЕ РОЛИ, и дословный зачин есть самая дешёвая проверка
    роли из возможных.
    """
    судимо, истинно = судить(ответ)
    return судимо and истинно and ответ.startswith(зачин)


def _вопрос_англ(м):
    имя, сколько, ответ = м.groups()
    return _приставка(f"{имя} of {сколько} is", ответ)


def _вопрос_рус(м):
    """Та же приставка, и вдобавок СВЯЗКА, согласованная с числителем.

    «Чему РАВНА половина» против «чему РАВНЫ две трети»: связка есть
    часть утверждения о числителе, а не оборот вежливости, и суд,
    её не читавший, пропустил бы «чему равна две трети».
    """
    связка, имя, сколько, ответ = м.groups()
    пара = _доля(имя, False)
    if пара is None:
        return False
    ждём = "равна" if пара[0] == 1 else "равны"
    return связка == ждём and _приставка(f"{имя} от {сколько} — это",
                                         ответ)


# ------------------------------------------------------------- ОБРАЗЦЫ

ОБРАЗЦЫ = (
    (rf"^{ДА} is {Н}/{Н}\.$", _запись_англ),
    (rf"^{ДР} — это {Н}/{Н}\.$", _запись_рус),
    (rf"^{ДА} of {Н} is {Н}: {Н} divided by {Н} is {Н}"
     rf"(?:, and {Н} times {Н} is {Н})?\.$", _с_основанием_англ),
    (rf"^{ДР} от {Н} — это {Н}: {Н} разделить на {Н} — это {Н}"
     rf"(?:, а {Н} умножить на {Н} — это {Н})?\.$", _с_основанием_рус),
    (rf"^{ДА} of {Н} is {Н}\.$", _коротко_англ),
    (rf"^{ДР} от {Н} — это {Н}\.$", _коротко_рус),
    (rf"^{ЛИЦО_EN} has {Н} {ВЕЩЬ_EN} and {ЛИЦО_EN} has {Н} {ВЕЩЬ_EN}; "
     rf"{ЛИЦО_EN} has (half|a third|a quarter|a fifth) as many "
     rf"{ВЕЩЬ_EN} as {ЛИЦО_EN}\.$", _сравнение_англ),
    (rf"^у {ЛИЦО_RU} {Н} {ВЕЩЬ_RU}, а у {ЛИЦО_RU} {Н} {ВЕЩЬ_RU}; у "
     rf"{ЛИЦО_RU} (вдвое|втрое|вчетверо|впятеро) меньше {ВЕЩЬ_RU}, чем "
     rf"у {ЛИЦО_RU}\.$", _сравнение_рус),
    (rf"^{ЛИЦО_EN} has {ДА} of what {ЛИЦО_EN} has: {Н} divided by {Н} "
     rf"is {Н}\.$", _доля_от_чужого_англ),
    (rf"^у {ЛИЦО_RU} {ДР} от того, что у {ЛИЦО_RU}: {Н} разделить на "
     rf"{Н} — это {Н}\.$", _доля_от_чужого_рус),
    (rf"^{СА} is {Н}/2\.$", _смешанная_запись_англ),
    (rf"^{СР} — это {Н}/2\.$", _смешанная_запись_рус),
    (rf"^{СА} plus {СА} is {Н}: {Н}/2 \+ {Н}/2 = {Н}\.$",
     _смешанная_сумма_англ),
    (rf"^{СР} плюс {СР} — это {Н}: {Н}/2 \+ {Н}/2 = {Н}\.$",
     _смешанная_сумма_рус),
    (rf"^{СА} hours is {Н} minutes\.$", _часы_англ),
    (rf"^{СР} {ВЕЩЬ_RU} — это {Н} {ВЕЩЬ_RU}\.$", _часы_рус),
    (rf"^{ДА} and {ДА} make one whole: {Н}/{Н} \+ {Н}/{Н} = 1\.$",
     _целое_англ),
    (rf"^{ДР} и {ДР} составляют целое: {Н}/{Н} \+ {Н}/{Н} = 1\.$",
     _целое_рус),
    # ВОПРОСНЫЕ ПОВЕРХНОСТИ СТОЯТ ПОСЛЕДНИМИ: их ответ судится тем же
    # судом, и утверждающие образцы обязаны быть уже разобраны.
    (rf"^what is {ДА} of {Н}\? (.+)$", _вопрос_англ),
    (r"^чему (равна|равны) " + ДР + rf" от {Н}\? (.+)$", _вопрос_рус),
)
ПРАВИЛА = tuple((re.compile(о), п) for о, п in ОБРАЗЦЫ)


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    for образец, проверить in ПРАВИЛА:
        м = образец.match(с)
        if м:
            return True, bool(проверить(м))
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ДОЛЯ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ДОЛЯ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ДОЛЯ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
