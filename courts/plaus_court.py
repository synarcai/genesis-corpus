#!/usr/bin/env python3
"""[ПРАВДОПОДОБИЕ] — ответ, невозможный по существу вещи, пересчитанный судом.

Суд не пишет закона заново: он берёт его у дома (`plausforms`), где рамки, границы вещей и числа
объявлены одной таблицей. Подмена счёта, границы и самой НЕВОЗМОЖНОСТИ ловится машинально:
произведение и частное пересчитываются, а сравнение с границей сверяется числами страницы.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЗАКОН ДОМА ПРОВЕРЯЕТСЯ ДЕЛОМ: на странице «счёт сошёлся» произведение обязано быть ВЕРНЫМ, а его
итог — тем самым числом, что сравнивается с границей. Страница, где счёт неверен, говорит не о
правдоподобии, а об ошибке счёта, и это другой разговор.

    ПРОВЕРКА СЧЁТА НЕ ЕСТЬ ПРОВЕРКА ОТВЕТА: ЧИСЛО МОЖЕТ БЫТЬ ВЕРНЫМ И НЕВОЗМОЖНЫМ РАЗОМ.

ГРАНИЦЫ ВЕЩЕЙ — ЗНАНИЕ О МИРЕ, ОБЪЯВЛЕННОЕ ДОМОМ ПОИМЁННО, и суд не выводит их заново: он сверяет
то, что написано на странице, с тем, что объявлено в таблице дома.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/plaus_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import plausforms  # noqa: E402 — дом, объявивший правдоподобие

ИМЯ_СУДА = "plaus"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"plaus"})


def _судить(строка):
    return plausforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ПРАВДОПОДОБИЕ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(plausforms.РОДЫ)}, страниц {len(plausforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
