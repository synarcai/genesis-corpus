#!/usr/bin/env python3
"""[АНГЛИЙСКОЕ ЧИСЛО] — счёт правит формой существительного.

«3 meters», но «1 meter»; «0 eggs» — множественное, ибо английский
считает нуль во множественном. Прибор порчи показал дыру: «3 meter
equal 300 centimeters» проходило истиной судов единиц и эпизодов —
они читают число и величину, а форму слова не читал никто, как
русскую счётную форму до дома rugram. Правило — согласование по
счёту из пакета английского (`count_agreement`: единица — одна
форма, всё прочее — другая), слова — из объявленных форм пакета
(`noun_forms`), а не из вкуса суда.

ЧЕГО СУД НЕ ЧИТАЕТ: слово, не объявленное пакетом (молчание); число с
дробью или запятой («1.5 meters» — дробь берёт множественное, и это
иной закон); первое слово составного имени («3 apple pies» — счёт
правит последним словом, и суд его пропускает).
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import langsign  # noqa: E402
import closedworld  # noqa: E402
ПАКЕТ = json.loads((КОРЕНЬ / "tools" / "langpacks" / "en.json")
                   .read_text(encoding="utf-8"))
ЕДИНСТВЕННОЕ = dict(ПАКЕТ["noun_forms"])            # one → many
МНОЖЕСТВЕННОЕ = {м: е for е, м in ЕДИНСТВЕННОЕ.items()}
ОДНО = set()
for правило in ПАКЕТ["count_agreement"]:
    if правило.get("form") == "one":
        ОДНО.update(правило.get("in", ()))

# ЧИСЛО — ЦЕЛОЕ, СЛОВОМ ПОСЛЕ НЕГО — ЛАТИНИЦА; дробь и запятая — не наш
# счёт. Границы слова обязательны: «3 meters» — да, «x3 meters» — нет.
# СЛОВО СЧЁТА — ЦЕЛОЕ СЛОВО: «7 listów» (польское) не есть «7 list» — буква
# любого письма после латинских букв закрывает слово (рынок дыр на десяти
# языках, 04.09: суд ронял польские и турецкие строки как английский счёт).
# СЛОВО СЧЁТА АНГЛИЙСКОЕ — СТРОЧНОЕ: немецкий пишет имена с заглавной
# («1650 Cent», «3 Äpfel»), и суд английского счёта им не судья (деньги на
# языках 04.09: «Cent» читался как английское «cent» без «s»). На своде
# d4400a0 ни одна строка от этого вердикта не меняет.
ПАРА = re.compile(r"(?<![\w.,])(\d+)(?![\d.,])\s+([a-z]+)(?![^\W\d_])(?:\s+([a-z]+)(?![^\W\d_]))?")


def форма(n, слово):
    """Какой формы требует счёт n от слова; None — слово не объявлено."""
    низ = слово.lower()
    if низ in ЕДИНСТВЕННОЕ:
        одно, много = низ, ЕДИНСТВЕННОЕ[низ]
    elif низ in МНОЖЕСТВЕННОЕ:
        одно, много = МНОЖЕСТВЕННОЕ[низ], низ
    else:
        return None
    return одно if n in ОДНО else много


# ДЕСЯТИЧНАЯ ЗАПЯТАЯ — НЕ АНГЛИЙСКОЕ ПИСЬМО: строка с «3,10» написана другим
# языком (нидерландские «310 cent», «3,10 euro» совпадают с английскими
# словами буква в букву, а счёта не меняют), и суд английского счёта в ней
# не судья (деньги на языках 04.09).
ДЕСЯТИЧНАЯ_ЗАПЯТАЯ = re.compile(r"\d,\d\d(?!\d)")




# ПОДСУДНОСТЬ ОБЪЯВЛЯЕТСЯ РОДОМ ТЕКСТА МИРА, А НЕ ПУТЁМ ФАЙЛА (05.09, суд письма).
# Полка и проза суть ЧУЖОЙ ТЕКСТ: он писан не нами, цитирует чужие записи и теряет знаки при
# сборке, и мера показов ему не судья — он судится своей (договор полки). Суд, читающий его
# своим правилом, даёт «возражение вне подсудности»: не находку, а шум, за которым не видно
# настоящих двенадцати.
РОД_ТЕКСТА = "shows"


def _прозаические():
    """Имена миров, чей объявленный род текста НЕ «показы»."""
    try:
        import genesis
        показы = {pathlib.Path(п).stem for п in genesis.worlds(existing=False, kind=РОД_ТЕКСТА)}
        все = {pathlib.Path(п).stem for п in genesis.worlds(existing=False)}
    except Exception:
        return frozenset()
    return frozenset(все - показы)


_ПРОЗА = _прозаические()


def _договор(путь):
    """Имена судов, названных договором полки для ЭТОЙ книги («судится» манифеста)."""
    global _ДОГОВОРЫ
    if _ДОГОВОРЫ is None:
        _ДОГОВОРЫ = {}
        try:
            import genesis
            for м in genesis.manifest()["worlds"]:
                с = м.get("судится")
                if с:
                    _ДОГОВОРЫ[pathlib.Path(м.get("file", "")).stem] = frozenset(с)
        except Exception:
            pass
    return _ДОГОВОРЫ.get(pathlib.Path(путь).stem, frozenset())


_ДОГОВОРЫ = None


class Слой(closedworld.Слой):
    """Признак ЧУЖОГО ТЕКСТА, ИМЕННОГО ДОГОВОРА книги и ИМЕНИ МИРА.

    Полка и проза суть чужой текст, и мера показов им не судья — КРОМЕ книг, чей договор
    назвал этот суд поимённо (поле «судится» манифеста). Договор старше общего правила:
    он объявлен рукой и прочитан прибором полки, который требует от названного судьи ЧТЕНИЯ.
    """

    ИМЯ_СУДА = "engram"

    def __init__(self):
        # ОДИН СЛОЙ, ДВА ПОЛЯ: `мир` от замкнутого мира, `полка` от договора книги.
        # Палата кладёт в `слои[имя]` РОВНО ОДИН предмет, и два слоя в одном имени
        # столкнулись бы молча — потому наследование, а не второй класс.
        super().__init__()
        self.полка = False

    def впитать(self, путь):
        super().впитать(путь)   # имя мира из манифеста — для закона замкнутости
        основа = pathlib.Path(путь).stem
        чужой = ("shelf" in pathlib.Path(путь).parts) or (основа in _ПРОЗА)
        self.полка = чужой and self.ИМЯ_СУДА not in _договор(путь)


def _судить(строка, слой=None):
    if слой is not None and слой.полка:
        return False, True          # чужой текст: мера показов ему не судья

    """(судимо, истинно): судимо, если есть счёт объявленного слова."""
    if ДЕСЯТИЧНАЯ_ЗАПЯТАЯ.search(строка):
        return False, False
    # СТРОКА ДРУГОГО ЯЗЫКА — НЕ ПОДСУДНА: знак языка по служебным словам
    # пакетов (tools/langsign.py); «ein Rechteck 2 mal 3 hat die Fläche» —
    # немецкий, и «3 hat» не английский счёт (геометрия на языках 04.09).
    # …и СТРОКА БЕЗ ЗНАКА АНГЛИЙСКОГО — ТОЖЕ: молчание или ничья («is» —
    # английское и нидерландское; «2 kilometer is 2000 meter» — голландская
    # мера без «s») не есть знак; на своде 638f120 нет строки, где этот суд
    # был бы единственным судьёй без знака «en» (замер 04.09, 1 894 строки).
    if langsign.чужой(строка, "en"):
        return False, False
    судимо = True_ = False
    for м in ПАРА.finditer(строка):
        n, слово, следом = int(м.group(1)), м.group(2), м.group(3)
        if следом and (следом.lower() in ЕДИНСТВЕННОЕ
                       or следом.lower() in МНОЖЕСТВЕННОЕ
                       or (len(следом) > 3 and следом.endswith("s"))):
            continue                    # составное имя: счёт правит последним
        ждём = форма(n, слово)
        if ждём is None:
            continue
        судимо = True
        if слово.lower() != ждём:
            return True, False
    return (True, True) if судимо else (False, False)


# МИРЫ ЗАМКНУТЫ, И ЭТО ПРОВЕРЕНО ДЕЛОМ (06.09, перепись закрываемости): палата,
# суженная до одного этого суда, судила КАЖДУЮ строку миров «aggregate» (430),
# «genesis_compare» (1440), «gsmlex» (400), «gsmwide» (900), «heads» (560) —
# судимы ВСЕ до одной, ложных 0, немых 0.
#
# ЧИСЛА ВЗЯТЫ ИЗ ЛОГА ЗАМЕРА, А НЕ ИЗ ГОЛОВЫ, и это шрам того же часа: первая
# редакция этого объявления несла 1804 / 2340 / 1076 / 1512 / 1284 — числа,
# вписанные рукой по памяти, вчетверо больше истинных. Объявление, несущее
# выдуманный замер, ХУЖЕ объявления без замера: второе честно молчит, первое лжёт
# с видом доказательства, и проверить его некому, ибо оно уже похоже на правду. Значит молчание суда о строке этих миров есть не воздержание,
# а форма, которой мир не писал. Обёртка не может сработать ни на одной сегодняшней
# строке — доказательство, а не выборка.
#
# ОБЁРТКА ВЗЯТА СО СЛОЕМ: у этого суда слой уже несёт ДОГОВОР ПОЛКИ, и обычное
# `замкнуть` съело бы его, зовя `судить_(строка)` без слоя.
ЗАМКНУТЫЕ_МИРЫ = frozenset({"aggregate", "genesis_compare", "gsmlex", "gsmwide", "heads"})
судить = closedworld.замкнуть_слоем(_судить, ЗАМКНУТЫЕ_МИРЫ)


if __name__ == "__main__":
    for с in sys.stdin:
        print(судить(с.rstrip("\n")), с.rstrip("\n"))
