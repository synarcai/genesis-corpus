#!/usr/bin/env python3
"""[ЛОВУШКИ ОТНОШЕНИЯ] — четыре ловушки сложения, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`ratetrapforms`), где дороги, работы и
проценты объявлены тремя таблицами. Всякая сумма, разность и деление пересчитываются
порознь — а СВОЙСТВО ЛОВУШКИ стережёт самопроверка дома, ибо суду оно не видно:

    ЛОВУШКА, В КОТОРОЙ ПРАВИЛЬНЫЙ ОТВЕТ СОВПАЛ С НЕПРАВИЛЬНЫМ, ЕСТЬ ПОКАЗ БЕЗ ПРЕДМЕТА.

Дом отбирает дороги, где средняя скорость НЕ РАВНА полусумме скоростей, и проценты, где
прирост строго больше суммы, а убыль строго меньше. Числа, не прошедшие отбор, не
записываются вовсе — оттого таблицы длиннее, чем вышедших страниц.

    python3 courts/dist_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import ratetrapforms  # noqa: E402 — дом, объявивший законы расстояния

ИМЯ_СУДА = "ratetrap"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"ratetrap"})


def _судить(строка):
    return ratetrapforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ЛОВУШКИ ОТНОШЕНИЯ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(ratetrapforms.РОДЫ)}, страниц {len(ratetrapforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
