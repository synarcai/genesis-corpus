#!/usr/bin/env python3
"""[ИМЕНОВАННОЕ ЧИСЛО] — перенос и заём через объявленное основание, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`carryforms`), где меры, основания и числа
объявлены одной таблицей. Подмена суммы, разности и САМОГО ОСНОВАНИЯ ловится машинально: всякое
равенство страницы пересчитывается, а род основания обязан нести ДВА разных основания.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

СВЁРТКА СМОТРИТ ВЛЕВО, И ЭТО КУПЛЕНО ДЕЛОМ: первая редакция читала в «2 + 1 + 1 = 4» подстроку
«1 + 1 = 4» и назвала ложью 1692 честные страницы — у действия, стоя́щего слева, отнимался его
первый операнд.

    СВЁРТКА, НЕ СМОТРЯЩАЯ ВЛЕВО, ЧИТАЕТ ХВОСТ ВЫРАЖЕНИЯ КАК ЦЕЛОЕ ВЫРАЖЕНИЕ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/carry_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import carryforms  # noqa: E402 — дом, объявивший меры и основания
import closedworld  # noqa: E402

ИМЯ_СУДА = "carry"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"carry"})


def _судить(строка):
    return carryforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ИМЕНОВАННОЕ ЧИСЛО {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(carryforms.РОДЫ)}, страниц {len(carryforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
