#!/usr/bin/env python3
"""[УСЛОВИЯ ЗАДАЧИ] — хватает ли данных, и не лишние ли они, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`needforms`), где рамки, вещи и числа объявлены
одной таблицей. Подмена суммы, отказа и самого ЛИШНЕГО ловится машинально: сумма пересчитывается,
отказ обязан быть без второго числа, а названное лишним число обязано НЕ входить в сумму.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ОТКАЗ ПРОВЕРЯЕТСЯ КАК ОТКАЗ: страница, где сказано «ответа нет», обязана нести РОВНО ОДНО число и
ни одной суммы. Отказ, на котором стои́т ответ, отрицает сам себя.

    ОТКАЗ БЕЗ ОСНОВАНИЯ ЕСТЬ МОЛЧАНИЕ; ОТКАЗ С ОСНОВАНИЕМ ЕСТЬ ОТВЕТ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/need_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import needforms  # noqa: E402 — дом, объявивший условия задачи

ИМЯ_СУДА = "need"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"need"})


def _судить(строка):
    return needforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"УСЛОВИЯ ЗАДАЧИ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(needforms.РОДЫ)}, страниц {len(needforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
