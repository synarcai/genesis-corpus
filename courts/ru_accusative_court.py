#!/usr/bin/env python3
"""[ВИНИТЕЛЬНЫЙ ПРИ ЧИСЛЕ] — дополнение переходного глагола стоит в винительном, и при числе тоже (24.09).

    ДОПОЛНЕНИЕ ПРИ ЧИСЛЕ БЕРЁТ ПАДЕЖ У ГЛАГОЛА, А ФОРМУ СЧЁТА — У ЧИСЛА.

ПОВОД — перепись свода 24.09 (строка 37 реестра пробелов): «Вера получила 1 книга», «Маша отдала
1 марка», «Ваня купил 21 книга», «Мария отдала 21 монета Пете», «ребёнок ждал 1 неделя», «поездка длится
1 минута», «Иван освободил корзина». Дома ставили дополнение счётной формой ИМЕНИТЕЛЬНОГО, и она верна
ровно там, где винительный с ним совпадает, — у неодушевлённых мужского и среднего рода и при числах не на
один. Суд русской задачи прямо пропускал «получила 1 X»: писан он был под «яблоко», где падежи совпадают.

ЗАКОН (дверь — `rugram.винительный_при_числе`): после глагола, управляющего винительным, «число имя» стоит
в винительном при этом числе — «получила 1 книгу», «купил 21 карандаш», «увидел 1 кота», «купил 5 книг»;
сосуд без числа — в винительном единственного: «освободил корзину».

СУДИМО: глаголы, какими дома говорят акт над вещью и длительность (`ГЛАГОЛЫ`, все формы рода и числа
прошедшего — у двери прошедшего), и настоящие «длится», «кладут», «делит», перед «число имя» (между ними — до двух
слов: «дал Марии», «купил у него»), где имя — счётное имя двери; продолжение того же дополнения («купила
2 карты, а потом ещё 1 карту»); «освободил(а) имя» без числа; и разность при сравнительном — «на» с
винительным: «на 1 коробку больше».

ГРАНИЦА, А НЕ ПОЛНОТА:
  · ответ-эллипсис («сколько книг купил Ваня? 21 книга.») не судится: у ответа нет глагола в строке;
  · глагол вне объявленного круга не судится — угадывать переходность по окончанию нельзя: «если» и
    «Оли» кончаются на «-ли», и первая перепись звала их глаголами;
  · одушевлённое при двух—четырёх («3 кота» вместо «трёх котов») — граница двери, а не этого суда.

ЛОВЕЦ ПОРЧИ: суд зовёт ложью именительный на месте винительного и МОЛЧИТ обо всём остальном; истины не
выдаёт — верный падеж не делает строку верной, её счёт судят суды миров.

    python3 courts/ru_accusative_court.py [файл …]
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import rugram  # noqa: E402 — дверь винительного при числе и прошедшего по роду

ЛОВЕЦ_ПОРЧИ = True
# РУБЕЖ-ДОЛГА: ИМЕНИТЕЛЬНЫХ_РУБЕЖ = 0
ИМЕНИТЕЛЬНЫХ_РУБЕЖ = 0

# глаголы акта над вещью и длительности, какими говорят дома свода (мужская форма прошедшего)
ГЛАГОЛЫ = ("взял", "дал", "отдал", "получил", "купил", "продал", "нашёл", "потерял", "съел", "принёс",
           "собрал", "скопил", "заработал", "сосчитал", "насчитал", "израсходовал", "использовал",
           "потратил", "разделил", "отложил", "имел", "держал", "ждал", "занял", "освободил", "написал",
           "отправил")
НАСТОЯЩИЕ = ("длится", "кладут", "делит")
_ФОРМЫ = {rugram.прошедшее_рода(г, р) for г in ГЛАГОЛЫ for р in ("м", "ж", "с", "мн")} | set(НАСТОЯЩИЕ)
_АЛЬТ = "|".join(sorted(_ФОРМЫ, key=len, reverse=True))
# между глаголом и числом — до двух слов: кому («дал Марии»), у кого («купил у него»), «ещё»
_ПРИ_ЧИСЛЕ = re.compile(rf"(?:^|[^а-яё])(?:{_АЛЬТ})\s+(?:[а-яё]+\s+){{0,2}}(\d+)\s+([а-яё]+)(?![а-яё])")
# продолжение того же дополнения в том же предложении: «купила 2 карты, а потом ещё 1 карту»
_ЕЩЁ = re.compile(rf"(?:^|[^а-яё])(?:{_АЛЬТ})\s[^.?!;]*?(?:,\s*а\s+потом|,?\s+и)\s+ещё\s+(\d+)\s+([а-яё]+)(?![а-яё])")
_СОСУД = re.compile(r"(?:^|[^а-яё])освободила?\s+([а-яё]+)(?=:)")
# разность при сравнительном — «на» с винительным: «на 1 коробку больше», «на 21 марку меньше»
СРАВНИТЕЛЬНЫЕ = ("больше", "меньше", "дороже", "дешевле", "старше", "младше", "выше", "ниже", "длиннее",
                 "короче", "тяжелее", "легче")
_РАЗНОСТЬ = re.compile(rf"(?:^|[^а-яё])на\s+(\d+)\s+([а-яё]+)\s+(?:{'|'.join(СРАВНИТЕЛЬНЫЕ)})(?![а-яё])")


def _ключ_именительного(слово, n):
    """Ключ счётного имени, если слово — его СЧЁТНАЯ форма при n (именительный счёта); иначе None."""
    ключ = rugram.ПО_ФОРМЕ.get(слово)
    if ключ is None or rugram.форма(ключ, n) != слово:
        return None
    return ключ


def разбор(строка):
    """[(было, надо)] — места строки, где именительный стоит на месте винительного."""
    с = строка.lower()
    вон = []
    for м in [*_ПРИ_ЧИСЛЕ.finditer(с), *_ЕЩЁ.finditer(с), *_РАЗНОСТЬ.finditer(с)]:
        n, слово = int(м.group(1)), м.group(2)
        ключ = _ключ_именительного(слово, n)
        if ключ is None:
            continue
        надо = rugram.винительный_при_числе(ключ, n)
        if надо != слово:
            вон.append((f"{n} {слово}", f"{n} {надо}"))
    for м in _СОСУД.finditer(с):
        слово = м.group(1)
        ключ = _ключ_именительного(слово, 1)
        if ключ is None:
            continue
        надо = rugram.винительный_при_числе(ключ, 1)
        if надо != слово:
            вон.append((слово, надо))
    return вон


def судить(строка, слой=None):
    """(судимо, истинно): именительный на месте винительного — ложь; иначе суд МОЛЧИТ."""
    return (True, False) if разбор(строка) else (False, False)


def _подсадки():
    """[(верное, битое)] — ДВЕРЬЮ: винительный при числе и именительный на его месте."""
    пары = []
    for ключ in ("книга", "монета", "неделя", "карандаш", "кот", "яблоко"):
        for n in (1, 21, 3, 5):
            верное, битое = rugram.винительный_при_числе(ключ, n), rugram.форма(ключ, n)
            if верное == битое:
                continue
            пары.append((f"Вера получила {n} {верное}.", f"Вера получила {n} {битое}."))
    пары.append(("Иван освободил корзину: был 1 цветок.", "Иван освободил корзина: был 1 цветок."))
    пары.append(("ребёнок ждал 1 неделю.", "ребёнок ждал 1 неделя."))
    пары.append(("Петя дал Марии 21 монету.", "Петя дал Марии 21 монета."))
    пары.append(("Аня купила 2 карты, а потом ещё 1 карту.", "Аня купила 2 карты, а потом ещё 1 карта."))
    пары.append(("у Ивана на 1 коробку больше, чем у Ани.", "у Ивана на 1 коробка больше, чем у Ани."))
    return пары


# ВЕРНОЕ, КОТОРОЕ СУД ОБЯЗАН ПРОПУСТИТЬ: подлежащее, неодушевлённое мужского рода, ответ-эллипсис, «если»
_ВЕРНОЕ = ("у Веры была 21 монета.", "Ваня купил 21 карандаш.", "сколько книг купил Ваня? 21 книга.",
           "если 21 страница — это три четверти книги, сколько страниц в книге?",
           "вместе у Димы, Лены и Оли 51 марка.", "Маша купила 5 книг.", "на пруду была 41 утка.")


def main():
    """Миры манифеста — или явные пути лентой; пропавший файл и пустой обход — ОТКАЗ."""
    from genesis import worlds  # noqa: E402
    явные = [pathlib.Path(а) for а in sys.argv[1:]]
    for путь in явные:
        if not путь.is_file():
            print(f"ВИНИТЕЛЬНЫЙ ПРИ ЧИСЛЕ ОТКАЗ: файла нет — {путь}")
            return 2
    подсадки = _подсадки()
    поймано = sum(1 for _, битое in подсадки if судить(битое) == (True, False))
    for верное, _ in подсадки:
        assert судить(верное) == (False, False), ("подсадка: верное названо ложью", верное)
    for верное in _ВЕРНОЕ:
        assert судить(верное) == (False, False), ("суд назвал ложью верное", верное)
    итог = collections.Counter()
    примеры = collections.Counter()
    по_миру = collections.Counter()
    файлов = 0
    for путь in (явные or worlds(kind="shows")):
        файлов += 1
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            места = разбор(строка)
            if not места:
                continue
            итог["ложных"] += 1
            по_миру[путь.stem.replace("genesis_", "")] += 1
            примеры[(путь.stem.replace("genesis_", ""),) + места[0]] += 1
    if not файлов:
        print("ВИНИТЕЛЬНЫЙ ПРИ ЧИСЛЕ ОТКАЗ: обход пуст, судить нечего")
        return 2
    for (мир, было, надо), n in примеры.most_common(8):
        print(f"  ЛОЖЬ ×{n} [{мир}]: «{было}» — надо «{надо}»")
    if по_миру:
        print("  по мирам: " + ", ".join(f"{м} {n}" for м, n in по_миру.most_common()))
    поза = "PASS" if итог["ложных"] <= ИМЕНИТЕЛЬНЫХ_РУБЕЖ and поймано == len(подсадки) else "FAIL"
    print(f"ВИНИТЕЛЬНЫЙ ПРИ ЧИСЛЕ {поза}: {итог['ложных']} ложных строк (рубеж {ИМЕНИТЕЛЬНЫХ_РУБЕЖ}; "
          f"{файлов} файлов); подсадок поймано {поймано} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
