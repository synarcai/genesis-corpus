sys.path.insert(0, str(КОРЕНЬ / "tools"))

import actors  # noqa: E402 — дверь лиц и рынок падежа лица
from actors import Слой  # noqa: E402 — деятели мира из манифеста

# ЛОВЕЦ ПОРЧИ БЕЗ ИСТИНЫ, И ОБЪЯВЛЕНО ЭТО ДВАЖДЫ — здесь и в списке `court_mutants`: суд
# говорит ЛОЖЬ о строке, где лицо стоит в падеже, какого свод после слова не ставил, и
# МОЛЧИТ обо всех прочих.
ЛОВЕЦ_ПОРЧИ = True


def судить(строка, слой=None):
    """(судимо, истинно): падеж лица после слова — из купленных падежей."""
    if слой is None:
        return False, False
    языки = слой.языки()
    if not языки:
        return False, False
    return (True, False) if actors.порча_падежа(строка, языки) else (False, False)


def main():
    судимо = ложных = 0
    примеры = []
    for имя, путь, языки in actors.миры_деятелей():
        if not путь.exists():
            continue
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            беды = actors.порча_падежа(строка, языки)
            if not беды:
                continue
            судимо += 1
            ложных += 1
            if len(примеры) < 5:
                перед, форма, язык = беды[0]
                примеры.append(f"{имя}/{язык}: «{перед} {форма}» ← {строка.strip()[:80]}")
    for п in примеры:
        print(f"  {п}")
    куплено = actors.куплен_падеж()
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ПАДЕЖ ЛИЦА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"слов перед лицом {len(куплено)} на {len({я for я, _ in куплено})} языках")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
