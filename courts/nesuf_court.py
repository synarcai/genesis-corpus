#!/usr/bin/env python3
"""[НЕОБХОДИМОЕ И ДОСТАТОЧНОЕ] — оба ответа об условии, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`nesufforms`), где делители и свидетели
объявлены одной таблицей. Подмена делителя, свидетеля и САМОГО ОТРИЦАНИЯ ловится машинально:
произведения и частные с остатком пересчитываются, а свидетель отказа обязан нести остаток,
ОТЛИЧНЫЙ ОТ НУЛЯ, — иначе он доказывает обратное тому, ради чего написан.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ОСТАТОК СУДИТСЯ ПРЕЖДЕ ПРОИЗВЕДЕНИЯ, и это куплено разбором: «6 = 4 × 1 + 2» несёт обе формы
разом, и свёртка произведения прочла бы в ней «6 = 4 × 1» — ложь о строке, которой в ней нет.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/nesuf_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import nesufforms  # noqa: E402 — дом, объявивший делители и свидетелей

ИМЯ_СУДА = "nesuf"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"nesuf"})


def _судить(строка):
    return nesufforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"НЕОБХОДИМОЕ И ДОСТАТОЧНОЕ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(nesufforms.РОДЫ)}, страниц {len(nesufforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
