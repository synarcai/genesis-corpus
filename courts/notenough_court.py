#!/usr/bin/env python3
"""[СУД НЕХВАТКИ ДАННЫХ] — суд сам решает, хватает ли данных; МИР ЗАМКНУТ.

Страница мира (`tools/notenough.py`) есть задача и либо ответ, либо ОТКАЗ отвечать. Суд
читает задачу заново и решает САМ, определяют ли данные ответ, — а потом сверяет своё решение
со сказанным.

    КОРПУС НАУЧИЛ ОТБРАСЫВАТЬ ЛИШНЕЕ И НИ РАЗУ НЕ НАУЧИЛ ОСТАНАВЛИВАТЬСЯ. «Лишнее число в
    задаче» — 63 строки свода; «данных не хватает» — ноль. Читатель, у какого всякая задача
    решаема, отвечает и там, где ответа НЕТ, и уверенности его не на чем сломаться.

Суд не верит ни ответу, ни отказу:

    ОТКАЗ ТАМ, ГДЕ ДАННЫХ ДОВОЛЬНО, ЕСТЬ ЛОЖЬ РОВНО ТАК ЖЕ, КАК ОТВЕТ ТАМ, ГДЕ ИХ НЕТ.
    ОТКАЗ БЕЗ ИМЕНИ НЕДОСТАЮЩЕГО ЕСТЬ УКЛОНЕНИЕ: страница обязана назвать, ЧЕГО именно не
    сказано, и суд сверяет это имя с тем, что и правда пропущено.

И третья строгость — об однозначности вопроса: когда вещей в задаче две, и «отдано», и сам
вопрос обязаны называть, о ЧЁМ речь. «Отдано 5» при яблоках и грушах не значит ничего.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import notenough as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"notenough"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_notenough.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_notenough.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_notenough.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"НЕХВАТКА ДАННЫХ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
