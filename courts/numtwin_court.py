#!/usr/bin/env python3
"""[ДВОЙНИК ЧИСЛА] — цифра и слово на одной странице как РАВНЫЕ; МИР ЗАМКНУТ.

    ЦИФРА И СЛОВО СУТЬ ДВА ПИСЬМА ОДНОГО ЧИСЛА, И РАВЕНСТВО ИХ НАДО ПОКАЗАТЬ, А НЕ ВЫВЕСТИ.

Замер 21.09: миров, где цифра и слово стоя́т рядом двойниками («20 = twenty», «сорок — это
40»), у свода НЕ БЫЛО НИ ОДНОГО. Дом чтения чисел учит иному: он читает список вещей и
спрашивает об их числе, а слово-числительное живёт у него в вопросе, не против своей цифры.

Повод пришёл от соседа: организм, встречая цепь двадцаток, ценит звено НОМЕРОМ В ЦЕПИ —
«venti» становится единицей, «quaranta» двойкой, «cento» пятёркой, — ибо масштабировать цепь
ему нечем. Масштаб даёт ЗАСВИДЕТЕЛЬСТВОВАННЫЙ член: слово, у которого в показах есть
двойник-цифра.

    ЗНАНИЕ, КОТОРОЕ ЧИТАТЕЛЬ ВЫВОДИТ ИЗ ПОРЯДКА, А НЕ ИЗ ПОКАЗА, ДЕРЖИТСЯ РОВНО ДО ПЕРВОЙ
    ПЕРЕСТАНОВКИ. Цепь, где «сорок» стои́т вторым, учит, что сорок есть два, — и учит этому
    тем вернее, чем стройнее цепь.

ЗАКОН СУДА В ОДНОЙ ФРАЗЕ: на странице ровно одна цифра и ровно одно объявленное
числительное, и числительное это есть имя ЭТОЙ цифры. Проверяется объявлением пакета, а не
памятью суда, — потому «40 — это пятьдесят» ложно без всякого набора.

ФОРМА, ОБЪЯВЛЕННАЯ ДЛЯ СОСТАВА, НЕ ЕСТЬ ИМЯ ЧИСЛА: пакет даёт `100 = "hundred"` — верно для
«two hundred», — а само число зовётся «one hundred». Дом объявил это отдельно и только там,
где расходится; прочие восемь языков зовут сотню одним словом.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import numtwin as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"numtwin"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_numtwin.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_numtwin.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_numtwin.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ДВОЙНИК ЧИСЛА {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
