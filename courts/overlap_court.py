#!/usr/bin/env python3
"""[ДВА КРУЖКА] — счёт пересекающихся групп, пересчитанный судом разбором записи.

Суд не пишет закона заново: он берёт его у дома (`overlapforms`), где три таблицы классов
объявлены порознь — перекрытые, скрытые и беспересечные. Всякая запись страницы считается
РАЗБОРОМ, а не парой чисел: «20 − (12 + 9 − 5) = 4» есть одно утверждение, и судья, читающий
пары, нашёл бы в нём «9 − 5 = 4» — истину, стоящую не на своём месте, и обманулся бы вдвойне.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: обе стороны ловушки обязаны быть
показаны, и таблицы обязаны быть тем, чем названы, — класс, попавший из скрытых в
перекрытые, показал бы ловушку не ту.

    python3 courts/overlap_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import overlapforms  # noqa: E402 — дом, объявивший счёт пересекающихся групп

ИМЯ_СУДА = "overlap"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"overlap"})


def _судить(строка):
    return overlapforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ДВА КРУЖКА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(overlapforms.РОДЫ)}, страниц {len(overlapforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
