#!/usr/bin/env python3
"""[ИЗМЕНЕНИЕ НА ПРОЦЕНТ] — рост, убыль и смена основания, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`pctchangeforms`), где рамки и числа объявлены одной
ЛОВУШКА ПРОВЕРЯЕТСЯ КАК ЛОВУШКА: на странице «туда-обратно» итог обязан быть МЕНЬШЕ прежней цены.
Страница, где он вышел равным или большим, говорит о возврате — то есть ровно обратное тому, ради
чего написана, — и суд зовёт её ложью.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ПРОЦЕНТЫ ВЗЯТЫ ТЕ, ЧТО ДАЮТ ЦЕЛЫЕ ДОЛИ ДВАЖДЫ ПОДРЯД (10, 20, 50 при цене, кратной сотне): иначе
вторая доля вышла бы дробной, и дом заговорил бы о десятичной записи — предмете соседа, а не
своём. ГРАНИЦА ДОМА ЕСТЬ ГРАНИЦА ЕГО ПРЕДМЕТА, А НЕ УДОБСТВО СЧЁТА.

ЭТОТ ДОМ ЧИТАЕТСЯ И СУДОМ АРИФМЕТИКИ: его страницы написаны так, что слова стоя́т до двоеточия, а
равенства после, — и потому каждая проверена ДВАЖДЫ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/pctchange_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import pctchangeforms  # noqa: E402 — дом, объявивший изменение на процент

ИМЯ_СУДА = "pctchange"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"pctchange"})


def _судить(строка):
    return pctchangeforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ИЗМЕНЕНИЕ НА ПРОЦЕНТ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(pctchangeforms.РОДЫ)}, страниц {len(pctchangeforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
