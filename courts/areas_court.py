#!/usr/bin/env python3
"""[ОБЛАСТИ] — страницы мира обыденных областей, судимые замкнутым миром и пересчётом (24.09).

Мир `areas` (строка 34 реестра пробелов) объявляет все свои страницы (`gen_genesis_areas.ПОКАЗЫ`), и суд берёт
закон у дома, а не пишет его рамки второй раз.

    СТРОКА МИРА, КАКОЙ ДОМ НЕ ПИШЕТ, ЕСТЬ ЛОЖЬ ЭТОГО МИРА: замкнутый мир говорит о своём, и порча одного
    слова страницы есть порча страницы.

ПЕРЕСЧЁТ, А НЕ ВЕРА ПЕРЕЧНЮ: всякая счётная страница несёт звено «a + b = s», «n × k = p» или «n − m = r».
Звено пересчитывается, и его числа обязаны быть числами фактов той же страницы, в их порядке: ответ,
сведённый не из сказанного, есть ложь, даже когда арифметика верна. У «сделано и осталось» сделанное меньше
данного.

ГРАНИЦА: строка чужого мира, какой перечень не порождает и какая не расходится с ним одним словом, суду не
подсудна; формы при числе судят суды согласования, а не этот.

    python3 courts/areas_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402,F401 — палата подаёт имя мира лишь тому, кто ввёз Слой
import gen_genesis_areas as Д  # noqa: E402 — дом, объявивший страницы областей

ИМЯ_СУДА = "areas"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"areas"})

_ПО_ДЛИНЕ = {}
for _п in Д.ПОКАЗЫ:
    _ПО_ДЛИНЕ.setdefault(len(_п.split(" ")), []).append(_п.split(" "))

_ЗВЕНО = re.compile(r"(\d+) ([+−×]) (\d+) = (\d+)\.$")
_ЧИСЛО = re.compile(r"(?<![\d.])\d+(?![\d.])")


def _порча_одним_словом(с):
    """Строка С ЧИСЛАМИ, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    if not re.search(r"\d", с):
        return False
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        if sum(x != y for x, y in zip(свои, слова)) == 1:
            return True
    return False


def _звено_верно(с):
    """Счётная страница: звено пересчитано, его числа — числа фактов страницы в их порядке."""
    м = _ЗВЕНО.search(с)
    if м is None:
        return True                       # страница понятия: чисел нет, ей верит замкнутый мир
    a, зн, b, итог = int(м.group(1)), м.group(2), int(м.group(3)), int(м.group(4))
    верно = {"+": a + b, "−": a - b, "×": a * b}[зн] == итог
    факты = [int(x) for x in _ЧИСЛО.findall(с[:с.index("?")])]
    if зн == "−" and not 0 < b < a:
        return False
    return верно and факты == [a, b]


def _судить(строка):
    с = строка.strip()
    if not с:
        return False, False
    if с not in Д.ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    return True, _звено_верно(с)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def _самопроверка():
    """Всякая страница дома истинна; порча итога, знака и числа факта — ложь."""
    беды = [с for с in Д.ПОКАЗЫ if _судить(с) != (True, True)]
    счётные = sorted(с for с in Д.ПОКАЗЫ if _ЗВЕНО.search(с))
    порч = 0
    for с in счётные[::7]:
        м = _ЗВЕНО.search(с)
        итог = int(м.group(4))
        порчи = [с[:м.start(4)] + f"{итог + 1}.",
                 с[:м.start(2)] + ("+" if м.group(2) != "+" else "×") + с[м.end(2):]]
        for порча in порчи:
            порч += 1
            if порча in Д.ПОКАЗЫ:
                continue
            if _звено_верно(порча) is not False and _судить(порча)[1] is not False:
                беды.append(f"порча прошла: {порча[:90]}")
        # число факта сменено, звено прежнее: ответ сведён не из сказанного
        факт = _ЧИСЛО.search(с)
        порча = с[:факт.start()] + str(int(факт.group()) + 1) + с[факт.end():]
        порч += 1
        if _звено_верно(порча):
            беды.append(f"число факта сменено, а звено принято: {порча[:90]}")
    return беды, порч


def main():
    import genesis
    беды, порч = _самопроверка()
    for б in беды[:3]:
        print(f"  САМОПРОВЕРКА: {б}")
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 and not беды else "FAIL"
    print(f"ОБЛАСТИ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); страниц дома {len(Д.ПОКАЗЫ)}, "
          f"порч самопроверки {порч}, бед {len(беды)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
