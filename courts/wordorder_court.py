#!/usr/bin/env python3
"""[МЕСТО СКАЗУЕМОГО] — «сказуемое есть слово 3 из 3» проверяется СЧЁТОМ СЛОВ.

    ПОРЯДОК, НАЗВАННЫЙ СЛОВОМ «SOV», НЕЧЕМ ПРОВЕРИТЬ. Место, названное числом, проверяется
    разрезом строки по пробелу: слово под этим номером обязано быть тем самым, и слов обязано
    быть столько, сколько сказано.

Суд не знает и не спрашивает, каков порядок языка: он читает ОДНО утверждение о ОДНОМ
предложении. Подмена номера или числа слов делает страницу ложной.

    СУД, ПРОВЕРЯЮЩИЙ СЧЁТ, СИЛЬНЕЕ СУДА, ПРОВЕРЯЮЩЕГО ЯРЛЫК: ярлык верен или неверен по
    словарю типологии, счёт — по самой строке.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ИМЯ_СУДА = "wordorder"

RU = re.compile(r"^в предложении «(.+?)» сказуемое «(.+?)» — слово (\d+) из (\d+)$")
EN = re.compile(r'^in the sentence "(.+?)" the verb "(.+?)" is word (\d+) of (\d+)$')
RU_В = re.compile(r"^какое слово в «(.+?)» сказуемое\? «(.+?)» — слово (\d+) из (\d+)$")
EN_В = re.compile(r'^which word in "(.+?)" is the verb\? "(.+?)" is word (\d+) of (\d+)$')


def _верно(с, гл, место, всего):
    слова = с.split()
    место, всего = int(место), int(всего)
    return (len(слова) == всего and 1 <= место <= всего
            and слова[место - 1] == гл)


def судить(строка, *_):
    с = строка.strip().rstrip(".")
    for обр in (RU, EN, RU_В, EN_В):
        m = обр.match(с)
        if m:
            return True, _верно(*m.groups())
    return False, True


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.name}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"МЕСТО СКАЗУЕМОГО {поза}: {ложных} ложных мест из {судимо} судимых (рубеж 0)")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
