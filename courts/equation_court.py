# --------------------------------------------- РАЗБОР ЗАПИСИ НАЗАД

_ЧЛЕН_ПРИ_X = re.compile(r"^ ([-+]) (?:(\d+) )?x")
_ЧЛЕН_ГОЛЫЙ = re.compile(r"^ ([-+]) (\d+)$")


def коэффициенты(запись):
    """(b, c) из ЗАПИСИ «x^2 - 5 x + 6 = 0», или None — вне закона.

    ЗАПИСЬ РАЗБИРАЕТСЯ ЗАКОНОМ, А НЕ УЗНАЁТСЯ ОБРАЗЦОМ. Три закона
    записи, объявленные слоем, проверяются здесь все три и каждый
    отдельно:

      · НУЛЕВОЕ СЛАГАЕМОЕ НЕ ПИШЕТСЯ. «x^2 + 0 x + 6 = 0» и
        «x^2 - 5 x + 0 = 0» отвергаются: величина нуль в записи есть
        нарушение закона, а не другой способ сказать то же;
      · ЕДИНИЦА ПРИ БУКВЕ НЕ ПИШЕТСЯ: «- x» разбирается в b = -1,
        а «- 1 x» отвергается;
      · ПОСЛЕ РАЗБОРА НЕ ОСТАЁТСЯ ХВОСТА. Разбор, довольный началом
        строки, — тот самый вердикт по остатку, которым уже болел
        арифметический суд корпуса: прочитано не всё, а сказано «верно».
    """
    if not запись.endswith(" = 0"):
        return None
    тело = запись[:-len(" = 0")]
    if not тело.startswith("x^2"):
        return None
    хвост = тело[len("x^2"):]
    b = c = 0
    м = _ЧЛЕН_ПРИ_X.match(хвост)
    if м:
        величина = int(м.group(2)) if м.group(2) is not None else 1
        if величина == 0 or м.group(2) == "1":
            return None
        b = величина if м.group(1) == "+" else -величина
        хвост = хвост[м.end():]
    м = _ЧЛЕН_ГОЛЫЙ.match(хвост)
    if м:
        величина = int(м.group(2))
        if величина == 0:
            return None
        c = величина if м.group(1) == "+" else -величина
        хвост = хвост[м.end():]
    return (b, c) if not хвост else None


def корень_множителя(запись):
    """Корень по множителю: «( x - 2 )» → 2, «( x + 4 )» → -4, «( x )» → 0.

    Тот же закон нулевого слагаемого: «( x - 0 )» отвергается, ибо
    нуль в записи не пишется вовсе, и множитель корня нуль есть «( x )».
    """
    м = re.fullmatch(r"\( x(?: ([-+]) (\d+))? \)", запись)
    if м is None:
        return None
    if м.group(1) is None:
        return 0
    величина = int(м.group(2))
    if величина == 0:
        return None
    return -величина if м.group(1) == "+" else величина


def слагаемые(запись):
    """[целые со знаком] из записи «4 - 10 + 6», или None."""
    м = re.fullmatch(r"(\d+)((?: [-+] \d+)*)", запись)
    if м is None:
        return None
    вон = [int(м.group(1))]
    for знак, величина in re.findall(r" ([-+]) (\d+)", м.group(2)):
        вон.append(int(величина) if знак == "+" else -int(величина))
    return вон


def высота(b, c, v):
    """Величина многочлена x^2 + b x + c при x = v — счёт суда."""
    return v * v + b * v + c


def целые(запись):
    """[целые] из перечня «7, 7, 9, 13», или None."""
    if not re.fullmatch(r"(?:-?\d+, )*-?\d+", запись):
        return None
    return [int(ч) for ч in запись.split(", ")]


def подстановка_верна(ур, v, слова, итог):
    """Слагаемые, счёт и итог подстановки — все три разом.

    ОЖИДАЕМОЕ СТРОИТСЯ ЗДЕСЬ, А НЕ СВЕРЯЕТСЯ СО СТРОКОЙ. Суд сам
    выводит, какие слагаемые ОБЯЗАНЫ стоять в записи при этом
    уравнении и этом значении (голова — всегда, нулевое после головы —
    никогда), и требует совпадения списком. Проверка «сумма сходится»
    без этого пропустила бы «10 - 10 + 0 = 0» на месте «4 - 10 + 6 = 0»:
    счёт верен, подстановка выдумана.
    """
    кф = коэффициенты(ур)
    if кф is None:
        return False
    b, c = кф
    записанные = слагаемые(слова)
    if записанные is None:
        return False
    ожидаемые = [v * v] + [т for т in (b * v, c) if т != 0]
    return (записанные == ожидаемые and sum(записанные) == итог
            and высота(b, c, v) == итог)


