def _вердикт(м):
    """«is 2 a root of …? yes: 4 - 10 + 6 = 0.» — вердикт ПО ИТОГУ."""
    v, ур, слово, слова, итог = м.groups()
    v, итог = int(v), int(итог)
    да = слово in ("yes", "да")
    return (подстановка_верна(ур, v, слова, итог)
            and да == (итог == 0))


def _подстановка(м):
    """Подстановка без вердикта: «put 2 in place of x and it gives …»."""
    ур, v, слова, итог = м.groups()
    return подстановка_верна(ур, int(v), слова, int(итог))


def _подстановка_нуль(м):
    """Обобщение рода корня: названное значение ОБЯЗАНО быть корнем."""
    ур, v, слова, итог = м.groups()
    return подстановка_верна(ур, int(v), слова, int(итог)) and int(итог) == 0


def _контр_значение(м):
    """Свидетель убивает «всякое значение годится» лишь если НЕ нуль."""
    ур, v, слова, итог, повтор = м.groups()
    итог = int(итог)
    return (подстановка_верна(ур, int(v), слова, итог) and итог != 0
            and int(повтор) == итог)


def _два_корня(м):
    """«У уравнения один корень» убито ДВУМЯ РАЗНЫМИ настоящими корнями.

    Свидетель, который не опровергает, есть самая убедительная ложь
    корпуса: форма у него правильная. Потому проверяется работа —
    что корней вправду два, что они РАЗНЫЕ и что каждый вправду
    обращает уравнение в нуль.
    """
    ур, r1, r2 = м.groups()
    кф = коэффициенты(ур)
    if кф is None:
        return False
    b, c = кф
    r1, r2 = int(r1), int(r2)
    return (r1 != r2 and высота(b, c, r1) == 0 and высота(b, c, r2) == 0)


def _ряд_значений(м):
    """Ряд высот при названных значениях — пересчитывается весь."""
    ур, где, что = м.groups()
    кф = коэффициенты(ур)
    if кф is None:
        return False
    b, c = кф
    точки, итоги = целые(где), целые(что)
    if точки is None or итоги is None or len(точки) != len(итоги):
        return False
    return all(высота(b, c, v) == и for v, и in zip(точки, итоги))


def _разложение(м):
    """Разложение, сумма и произведение — три утверждения, три проверки.

    Корни берутся ИЗ МНОЖИТЕЛЕЙ, а не из хвоста строки, и лишь потом
    сверяются с коэффициентами и с обоими счётами. Порядок важен: суд,
    берущий корни из объявления «the roots are 2 and 3», проверял бы
    разложение самим разложением.
    """
    ур, м1, м2, s1, s2, сумма, p1, p2, произв, к1, к2 = м.groups()
    кф = коэффициенты(ур)
    if кф is None:
        return False
    b, c = кф
    r1, r2 = корень_множителя(м1), корень_множителя(м2)
    if r1 is None or r2 is None:
        return False
    return (r1 + r2 == -b and r1 * r2 == c
            and (int(s1), int(s2), int(сумма)) == (r1, r2, r1 + r2)
            and (int(p1), int(p2), int(произв)) == (r1, r2, r1 * r2)
            and (int(к1), int(к2)) == (r1, r2))


def _контр_виета(м):
    """Ловушка знака: сумма корней есть -b, и потому b ей не равно.

    Контрпример работает лишь там, где b НЕ НУЛЬ: при b = 0 сумма
    корней и средний коэффициент совпадают, и опровергаемое
    утверждение оказывается в этом случае истинным. Суд требует
    именно этого — иначе показ «опровергал» бы истину.
    """
    ур, r1, r2, s1, s2, сумма, средний = м.groups()
    кф = коэффициенты(ур)
    if кф is None:
        return False
    b, c = кф
    r1, r2 = int(r1), int(r2)
    return (высота(b, c, r1) == 0 and высота(b, c, r2) == 0 and r1 != r2
            and (int(s1), int(s2), int(сумма)) == (r1, r2, r1 + r2)
            and int(средний) == b and r1 + r2 != b)


def _общ_виета(м):
    """Закон Виеты на своём случае: сумма есть -b, произведение есть c."""
    ур, r1, r2, s1, s2, сумма, p1, p2, произв = м.groups()
    кф = коэффициенты(ур)
    if кф is None:
        return False
    b, c = кф
    r1, r2 = int(r1), int(r2)
    return (r1 + r2 == -b and r1 * r2 == c
            and (int(s1), int(s2), int(сумма)) == (r1, r2, r1 + r2)
            and (int(p1), int(p2), int(произв)) == (r1, r2, r1 * r2))


def _пусто(b, c, начало, конец):
    """Нет ли целого корня на отрезке — ОТРЕЗОК ПРОХОДИТСЯ ЦЕЛИКОМ."""
    return начало <= конец and all(высота(b, c, v) != 0
                                   for v in range(начало, конец + 1))


def _отказ(м):
    """Отказ проверяется проходом по отрезку, а не доверием к слову."""
    ур, начало, конец = м.groups()
    кф = коэффициенты(ур)
    if кф is None:
        return False
    b, c = кф
    return _пусто(b, c, int(начало), int(конец))


def _контр_отказ(м):
    """Отказ плюс НАИМЕНЬШАЯ высота: и пусто, и названная точка честна.

    Ничьи здесь законны («x^2 - x + 7» равен семи и при нуле, и при
    единице), и суд не требует, чтобы названная точка была первой из
    наименьших: он требует, чтобы названная высота БЫЛА наименьшей и
    чтобы она вправду достигалась в названной точке. Прибор, требующий
    большего, чем утверждает показ, зовёт чинить исправное.
    """
    ур, начало, конец, где, низ = м.groups()
    кф = коэффициенты(ур)
    if кф is None:
        return False
    b, c = кф
    начало, конец, где, низ = (int(начало), int(конец), int(где),
                               int(низ))
    if not _пусто(b, c, начало, конец) or not начало <= где <= конец:
        return False
    return (высота(b, c, где) == низ
            and низ == min(высота(b, c, v)
                           for v in range(начало, конец + 1)))


def _ряд_отрезка(м):
    """Весь ряд высот отрезка, и нуля в нём нет — пересчитывается весь."""
    ур, ряд, начало, конец = м.groups()
    кф = коэффициенты(ур)
    if кф is None:
        return False
    b, c = кф
    начало, конец = int(начало), int(конец)
    итоги = целые(ряд)
    if итоги is None or не_отрезок(начало, конец, итоги):
        return False
    ожидаемые = [высота(b, c, v) for v in range(начало, конец + 1)]
    return итоги == ожидаемые and 0 not in ожидаемые


def не_отрезок(начало, конец, итоги):
    """Длина ряда обязана быть длиной отрезка — иначе ряд не о нём."""
    return начало > конец or len(итоги) != конец - начало + 1


def _квадрат_и_корень(м):
    """«квадрат 15 есть 225, значит корень из 225 есть 15» — оба хода."""
    n, кв, кв2, n2 = (int(з) for з in м.groups())
    return кв == n * n and кв2 == кв and n2 == n


def _контр_квкорень(м):
    """Число МЕЖДУ соседними квадратами целого корня иметь не может."""
    m, n, n2, кв, n1, n1b, кв1 = (int(з) for з in м.groups())
    return (n == n2 and n1 == n1b == n + 1 and кв == n * n
            and кв1 == n1 * n1 and кв < m < кв1)


def _обратность(м):
    """Квадрат и корень отменяют друг друга — на одном числе, дважды."""
    n, n2, кв, кв2, n3 = (int(з) for з in м.groups())
    return n2 == n and кв == n * n and кв2 == кв and n3 == n


def _мост(м):
    """Корень из кв есть ПОЛОЖИТЕЛЬНЫЙ целый корень x^2 - кв = 0.

    Уравнение «x^2 - 36 = 0» имеет ДВА целых корня, 6 и -6, и потому
    показ обязан говорить «положительный»: мост, сказанный неточно,
    учит неточности крепче, чем отсутствие моста учит незнанию.
    """
    кв, кв2, n, n2, кв3 = (int(з) for з in м.groups())
    return (кв2 == кв and n2 == n and n > 0 and n * n == кв
            and кв3 == кв)


def _названо(что, ответ):
    """Величина или запись, названная вопросом, СТОИТ В ОТВЕТЕ.

    Число ищется как целая величина, а не как подстрока: «10» внутри
    «100» не есть названная десятка, и суд, ищущий подстроку, принял бы
    ответ о чужом числе.
    """
    if re.fullmatch(r"-?\d+", что):
        return re.search(rf"(?<![\d-]){re.escape(что)}(?!\d)",
                         ответ) is not None
    return что in ответ


def _вопрос(м):
    """ВОПРОС ЕСТЬ ПРИСТАВКА, А ОТВЕТ СУДИТСЯ САМ ПО СЕБЕ.

    Один закон на все вопросные поверхности слоя. Вопросный показ верен
    ровно тогда, когда ОСТАТОК после приставки есть судимая истина
    ЭТОГО суда И всё, названное вопросом (уравнение, отрезок, число),
    стоит в ответе. Иначе «каковы корни x^2 - 5 x + 6 = 0? квадрат 15
    есть 225» прошло бы как честная пара двух честных половин.

    Отдельного пересчёта вопросу не нужно: ответ уже пересчитан своим
    родом, а вопрос не утверждает ничего сверх ответа.
    """
    *названное, ответ = м.groups()
    судимо, истинно = судить(ответ)
    return (судимо and истинно
            and all(_названо(з, ответ) for з in названное))


