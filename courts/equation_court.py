Ц = r"(-?\d+)"
Н = r"(\d+)"
# Уравнение ловится ШИРОКО, а разбирается СТРОГО: «x^2 + 0 x + 6 = 0»
# обязано попасть в суд и быть названо ложью, а не остаться немым.
УР = r"(x\^2[-+\dx ]*= 0)"
ОСН = r"(\d+(?: [-+] \d+)*) = (-?\d+)"
МН = r"(\( x(?: [-+] \d+)? \))"
РЯД = r"((?:-?\d+, )*-?\d+)"

