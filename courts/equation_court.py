"""СУД МИРА УРАВНЕНИЙ: вердикт не читается, а ПЕРЕСЧИТЫВАЕТСЯ.

Слой уравнений говорит пятью родами — корень, переменная, разложение,
отказ, квадратный корень, — и почти каждый его показ несёт ОСНОВАНИЕ
рядом с ответом: «yes: 4 - 10 + 6 = 0», «( x - 2 ) ( x - 3 ): 2 + 3 = 5
and 2 * 3 = 6». Суд не верит ни ответу, ни основанию, ни даже записи
уравнения: он РАЗБИРАЕТ ЗАПИСЬ ОБРАТНО В КОЭФФИЦИЕНТЫ и считает всё
заново своим кодом.

ЧТО ЗНАЧИТ «СВОИМ КОДОМ» ЗДЕСЬ. Генератор идёт от корней к
коэффициентам (Виета вперёд); суд идёт от ЗАПИСИ к коэффициентам и
дальше к значению многочлена (разбор и подстановка назад). Это не то же
самое вычисление, сказанное дважды, а встречное: ошибка в законе знака,
в законе нулевого слагаемого или в подстановке ломает встречу, а не
проходит сквозь обе стороны одинаково.

ТРИ ВЕЩИ СВЕРЯЮТСЯ РАЗОМ В КАЖДОЙ ПОДСТАНОВКЕ:
  · СЛАГАЕМЫЕ ЗАПИСИ суть ровно те, что даёт уравнение при этом
    значении (голова — квадрат, дальше b·v и c, и НУЛЕВОЕ НЕ ПИСАНО);
  · СЧЁТ этих слагаемых сходится с записанным итогом;
  · ВЕРДИКТ («yes»/«нет») соответствует итогу: корень тогда и только
    тогда, когда итог нуль.

Показ, у которого верны два из трёх, есть самая убедительная ложь: у
него правильная форма. Оттого проверяются все три, а не форма.

ОСОБО ОБ ОТКАЗЕ. «У x^2 - x + 7 = 0 нет целого корня от 0 до 10» —
утверждение о ВСЁМ отрезке, и проверить его можно только пройдя
отрезок. Суд его проходит. Отказ, который никто не проверял, есть
худший род корпусного мусора: он выглядит как знание границы, а на деле
есть догадка, и организм выучивает отказывать там, где ответ был.

ОСОБО О ЗАПИСИ УРАВНЕНИЯ. Запись судится ЗАКОНОМ, а не образцом:
«x^2 + 0 x + 6 = 0» разбору не поддаётся вовсе (нулевое слагаемое не
пишется), и показ с такой записью объявляется ЛОЖЬЮ, а не остаётся
несудимым. Форма записи есть часть утверждения, а не оформление.

ВОПРОС ЕСТЬ ПРИСТАВКА К ОТВЕТУ — ОДИН ЗАКОН НА ВСЕ ВОПРОСНЫЕ
ПОВЕРХНОСТИ. Вопросный показ («what are the roots of …? …») не судится
своим отдельным пересчётом: суд отрезает приставку, требует, чтобы
ОСТАТОК был судимой истиной ЭТОГО ЖЕ суда, и чтобы всё, названное в
вопросе (уравнение, отрезок, число), СТОЯЛО В ОТВЕТЕ. Ответ на чужой
вопрос («каковы корни x^2 - 5 x + 6 = 0? квадрат 15 есть 225…») этого
не проходит. Закон один, вопросных поверхностей шесть, и седьмая
обойдётся объявлением, а не кодом.

ОБРАЗЦЫ РУССКИХ ПОВЕРХНОСТЕЙ НЕСУТ ЧУЖОЙ ШРАМ. «в {уравнение} при
x = 1 выходит …» стоит здесь не ради красоты речи: первая редакция
слоя писала «в {уравнение} значение 1 даёт …», и суд русского
согласования назвал сорок таких строк ложью — он прочёл «0 значение»,
где ноль пришёл из хвоста уравнения, а имя принадлежало следующей
мысли. Образец, переписанный обратно на имя, вернёт и тот вердикт.

СУД НЕ СМЕЕТ ЧИТАТЬ ЧУЖОЙ РОД. Образцы узкие и привязаны к зачину
строки; неузнанная строка есть (False, False) — молчание, а не
вердикт. Прибор, судящий по совпадению формы, обвиняет честное: этот
шрам корпус уже покупал шестью русскими ставками, объявленными ложью
чужим судом.

ОБ ОПРЕДЕЛЕНИЯХ. Их суд — сверка с независимо записанным ЗДЕСЬ
списком: тот же факт, сказанный второй рукой. Правка определения в
одном доме и не в другом делает строку НЕСУДИМОЙ, а ворота записи
несудимую строку не пропускают — и слой не будет записан вовсе.
"""

