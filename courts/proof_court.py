#!/usr/bin/env python3
"""[ФОРМЫ ДОКАЗАТЕЛЬСТВА] — судится не имя формы, а её ЭКЗЕМПЛЯР.

Математика делают не теоремы, а ФОРМЫ, в которых показывают истинность.
Форма без экземпляра есть слово, и потому здесь всякий показ несёт
проверяемый случай, а суд его пересчитывает:

  · ИНДУКЦИЯ — основание и шаг. Шаг не утверждается, а ПОКАЗАН на паре
    чисел, и суд проверяет обе стороны равенства «S(n) + (n+1) =
    S(n+1)»: показ, где шаг записан неверно, учит неверному ходу при
    верной теореме.
  · РАЗБОР СЛУЧАЕВ — исчерпывающее деление со свидетелем в каждом
    случае; чётность числа пересчитывается.
  · КОНТРПРИМЕР — всеобщее утверждение, убитое одним свидетелем. Суд
    проверяет самого свидетеля: «2 is prime and 2 is even» ложно, если
    двойка не проста или не чётна.
  · ПРЯМОЕ — условное с экземпляром, где ПОСЫЛКА ВЫПОЛНЕНА. Условное,
    показанное там, где посылка ложна, не учит ничему, и суд требует
    истинности обеих половин.

ЧЕГО ЗДЕСЬ НЕТ: доказательства от противного. Его экземпляры
(иррациональность корня) счётом не проверяются, а форма, чей экземпляр
непроверяем, есть ровно то, что корпус нести отказывается. Она ждёт
суда, умеющего читать вывод.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import asking  # noqa: E402
import universals  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import arith_court  # noqa: E402
import declared  # noqa: E402

_СЛОВАРЬ = None

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file


def просто(n):
    return n > 1 and all(n % d for d in range(2, int(n ** 0.5) + 1))


def квадрат(n):
    к = int(n ** 0.5)
    return к * к == n


# свидетели контрпримеров: каждое утверждение проверяется само
СВИДЕТЕЛИ = {
    "2 is prime and 2 is even": lambda: просто(2) and 2 % 2 == 0,
    "0 is whole and 0 is not positive": lambda: 0 <= 0,
    "9 is a square and 9 is odd": lambda: квадрат(9) and 9 % 2 == 1,
    "6 is a multiple of 3 and 6 is even": lambda: 6 % 3 == 0 and 6 % 2 == 0,
}
ЛОЖНЫЕ = {
    "all primes are odd": lambda: False,
    "all whole numbers are positive": lambda: False,
    "every square is even": lambda: False,
    "all multiples of 3 are odd": lambda: False,
}

ШАГ_EN = re.compile(
    r"^if it holds for n = (\d+) then it holds for n = (\d+): "
    r"(\d+) \+ (\d+) = (\d+)$")
ШАГ_RU = re.compile(
    r"^если верно для n = (\d+), то верно и для n = (\d+): "
    r"(\d+) \+ (\d+) = (\d+)$")
СЛУЧАЙ_EN = re.compile(
    r"^every whole number is even or odd; (\d+) is (even|odd)$")
СЛУЧАЙ_RU = re.compile(
    r"^всякое целое чётно или нечётно; (\d+) (чётно|нечётно)$")
# ПОЛОЖИТЕЛЬНОСТЬ — ВЕРДИКТ С ОСНОВАНИЕМ: «да» при n > 0 со свидетелем «n > 0»,
# «нет» при n < 0 («n < 0») и при нуле («0 is not above 0»); суд читает знак сам.
ПОЛОЖИТЕЛЬНОСТЬ = re.compile(
    r"^(yes|no|да|нет): (−?\d+) (?:(>) 0|(<) 0|(is not above 0|не больше 0))$")
# ВЫБОР ОТКРЫВАЕТ ОТВЕТ (М-147): слово выбора, затем свидетель делением на два.
ВЫБОР_ЧЁТНОСТИ = re.compile(
    r"^(even|odd|чётно|нечётно): (\d+) = 2 × (\d+)( \+ 1)?$")
КОНТР = re.compile(r"^(.+?) is false: (.+?)$")
# ВОПРОС КОНТРПРИМЕРА ВЫВЕДЕН ИЗ ЕГО ОБРАЗЦА (tools/universals.py, М-149).
ВОПРОС_КОНТР = re.compile(universals.вопрос_образца(КОНТР.pattern, ("en", "ru")))
ПРЯМОЕ_EN = re.compile(
    r"^(?:yes: )?if n is even then n squared is even: (\d+) is even and (\d+) "
    r"is even$")
ПРЯМОЕ_RU = re.compile(
    r"^(?:да: )?если n чётно, то n в квадрате чётно: (\d+) чётно и (\d+) чётно$")
ПРЯМОЕ_НЕТ = re.compile(
    r"^(?:no: (\d+) is even and (\d+) is odd|нет: (\d+) чётно, а (\d+) нечётно)$")


# ШАГ ИНДУКЦИИ НЕСЁТ СВОЮ ЦЕПЬ, И ЦЕПЬ ОБЯЗАНА КОНЧАТЬСЯ ТАМ, КУДА
# ШАГНУЛИ. «шаг от 3 к 4: … цепь: 1 2 3 4» — истина; та же цепь при
# шаге к пяти была бы обрывом, о котором не скажет ни одна арифметика:
# каждое число в строке верно поодиночке.
ШАГ_ЦЕПИ = re.compile(
    r"^шаг от (\d+) к (\d+): если верно для (\d+) и из (\d+) следует "
    r"(\d+), то верно для (\d+)\. цепь: ([\d ]+)\.$")


def шаг_цепи_сходится(строка):
    """Сходится ли шаг со своей цепью; None — не наше."""
    m = ШАГ_ЦЕПИ.match(строка.strip())
    if not m:
        return None
    откуда, куда, а, б, в, г = (int(x) for x in m.groups()[:6])
    цепь = [int(x) for x in m.group(7).split()]
    подряд = all(п - о == 1 for о, п in zip(цепь, цепь[1:]))
    return (куда - откуда == 1 and а == откуда == б and в == куда == г
            and подряд and цепь and цепь[-1] == куда and цепь[0] == 1)


# ИНДУКЦИЯ ДЕРЖИТСЯ ШАГОМ В ЕДИНИЦУ, А НЕ СЛОВОМ «итог». «база: верно
# для 1. шаг: из n следует n+1. итог: верно для каждого n в цепи» —
# истина; тот же показ с шагом в двойку заключал бы о КАЖДОМ n из того,
# что доказано лишь о нечётных. Проверяемое здесь есть ПОКРЫТИЕ ЦЕПИ.
# ОТКАЗ ИСЧЕРПАНИЕМ ЕСТЬ ТОТ ЖЕ КОНТРПРИМЕР, ВЫВЕРНУТЫЙ НАИЗНАНКУ.
# Контрпример убивает всеобщее ОДНИМ свидетелем; отказ исчерпанием
# утверждает, что свидетеля НЕТ, — и такое утверждение проверяется
# только проходом всего отрезка. Слой показывал лишь первое, и корпус
# учился опровергать, не умея сказать «искомого нет, и вот почему».
#
# ОСНОВАНИЕ ПРОВЕРЯЕТСЯ ОТДЕЛЬНО ОТ ОТКАЗА: чётное число больше двух не
# просто не потому, что оно чётно, а потому, что двойка есть его
# делитель, отличный от единицы и от него самого. Суд требует и
# отсутствия свидетеля, и верности названной причины.
ИСЧЕРПАНИЕ = re.compile(
    r"^(?:there is no even prime between 3 and (\d+): every even number "
    r"there has the divisor 2 besides 1 and itself"
    r"|чётного простого между 3 и (\d+) нет: у всякого чётного там есть "
    r"делитель 2, кроме 1 и самого себя)\.$")


def исчерпание_держит(строка):
    """Проходит ли отрезок целиком; None значит «не наше».

    ПРОХОД, А НЕ ПРАВИЛО: суд не знает теоремы о единственном чётном
    простом, он идёт по отрезку и смотрит своими глазами. Отрезок,
    начатый ниже трёх, впустил бы двойку и сделал бы отказ ложным.
    """
    m = ИСЧЕРПАНИЕ.match(строка.strip())
    if not m:
        return None
    предел = int(next(г for г in m.groups() if г is not None))
    if предел < 3:
        return False
    for n in range(3, предел + 1):
        if n % 2:
            continue
        # причина названа верно, если двойка и правда СОБСТВЕННЫЙ
        # делитель этого числа, и оттого число не просто
        if просто(n) or not (n % 2 == 0 and 2 != n):
            return False
    return True


ИНДУКЦИЯ = re.compile(
    r"^(?:база: верно для (\d+)\. шаг: из n следует n\+(\d+)\. "
    r"итог: верно для каждого n в цепи"
    r"|base: true for (\d+)\. step: from n follows n\+(\d+)\. "
    r"hence: true for every n in the chain)\.$")


def индукция_покрывает(строка):
    """Покрывает ли индукция всю цепь; None — не наше."""
    m = ИНДУКЦИЯ.match(строка.strip())
    if not m:
        return None
    группы = [г for г in m.groups() if г is not None]
    основание, шаг = int(группы[0]), int(группы[1])
    return шаг == 1 and основание >= 1


def _счёт(кусок):
    """Пересчитать пример при максиме, если он счётный."""
    global _СЛОВАРЬ
    if _СЛОВАРЬ is None:
        _СЛОВАРЬ = arith_court.словари()
    return arith_court.судить(кусок, _СЛОВАРЬ)


def судить(строка):
    # ВОПРОС СУДИТСЯ СВОИМ ОТВЕТОМ, А РОД ОПРЕДЕЛЯЕТСЯ ОТВЕТОМ.
    # Связь половин держит общий дом `tools/asking.py`: величины
    # вопроса суть начальный отрезок величин ответа, и порча любой из
    # них рвёт пару. Без этого суд читал бы вторую половину строки и
    # звал истиной вопрос, спрашивающий о другом.
    если = asking.судить_парой(строка, судить)
    if если is not None:
        return если
    # ОБЪЯВЛЕННОЕ ЗНАНИЕ ЕСТЬ РОД ЭТОГО СУДА. Максимы слоя нельзя
    # пересчитать, но они объявлены рядом со списком, который
    # уточняют, — и сверяются с объявлением, как имена знаков.
    судимо, истинно = declared.судить_объявленное(строка, _счёт)
    if судимо:
        return судимо, истинно
    покрыто = индукция_покрывает(строка)
    if покрыто is not None:
        return True, покрыто
    шагнуто = шаг_цепи_сходится(строка)
    if шагнуто is not None:
        return True, шагнуто
    исчерпано = исчерпание_держит(строка)
    if исчерпано is not None:
        return True, исчерпано

    с = строка.strip().rstrip(".")
    m = ШАГ_EN.match(с) or ШАГ_RU.match(с)
    if m:
        n, следом, слева, добавка, справа = (int(x) for x in m.groups())
        # ШАГ ПРОВЕРЯЕТСЯ ОБЕИМИ СТОРОНАМИ, а не только итогом
        return True, (следом == n + 1
                      and слева == n * (n + 1) // 2
                      and добавка == следом
                      and справа == следом * (следом + 1) // 2
                      and слева + добавка == справа)
    m = ПОЛОЖИТЕЛЬНОСТЬ.match(с)
    if m:
        слово, n = m.group(1), int(m.group(2).replace("−", "-"))
        да = слово in ("yes", "да")
        if m.group(3):
            return True, да and n > 0
        if m.group(4):
            return True, (not да) and n < 0
        return True, (not да) and n == 0
    m = ВЫБОР_ЧЁТНОСТИ.match(с)
    if m:
        слово, x, q, хвост = m.group(1), int(m.group(2)), int(m.group(3)), m.group(4)
        чётн = слово in ("even", "чётно")
        return True, (x == 2 * q + (0 if чётн else 1)) and (хвост is None) == чётн
    m = СЛУЧАЙ_EN.match(с)
    if m:
        x, род = int(m.group(1)), m.group(2)
        return True, (x % 2 == 0) == (род == "even")
    m = СЛУЧАЙ_RU.match(с)
    if m:
        x, род = int(m.group(1)), m.group(2)
        return True, (x % 2 == 0) == (род == "чётно")
    m = ПРЯМОЕ_НЕТ.match(с)
    if m:
        n, нечёт = (int(x) for x in m.groups() if x is not None)
        return True, n % 2 == 0 and нечёт % 2 == 1
    m = ПРЯМОЕ_EN.match(с) or ПРЯМОЕ_RU.match(с)
    if m:
        n, квадратик = (int(x) for x in m.groups())
        # ПОСЫЛКА ОБЯЗАНА БЫТЬ ВЫПОЛНЕНА, иначе показ ничему не учит
        return True, (n % 2 == 0 and квадратик == n * n
                      and квадратик % 2 == 0)
    m = КОНТР.match(с) or ВОПРОС_КОНТР.match(с)
    if m:
        утверждение, свидетель = m.group(1).strip(), m.group(2).strip()
        если = СВИДЕТЕЛИ.get(свидетель)
        если_ложно = ЛОЖНЫЕ.get(утверждение)
        if если is None or если_ложно is None:
            return False, True
        # свидетель обязан быть ИСТИНЕН, а утверждение — ЛОЖНО
        return True, если() and not если_ложно()
    return False, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ДОКАЗАТЕЛЬСТВО ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ДОКАЗАТЕЛЬСТВО ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:90]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ДОКАЗАТЕЛЬСТВО {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
