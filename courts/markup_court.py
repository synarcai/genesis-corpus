#!/usr/bin/env python3
"""[РАЗМЕТКА] — суд ИСПОЛНЯЕТ разметку, а не читает утверждение о ней.

Слой разметки — крупнейший в корпусе (5724 строки) и почти несудимый:
двенадцать процентов. Между тем всё в нём проверяемо, ибо разметка есть
запись со строгим смыслом, а не украшение текста.

  · ЗАГОЛОВОК: «заголовок уровня 3: поле» истинно, если в слое есть
    строка «### поле» — и уровень сверяется ЧИСЛОМ РЕШЁТОК, а не
    словом рядом с ними;
  · НАЖИМ, КУРСИВ, КОД: «**сила** читается как жирное сила» несёт
    маркер, имя стиля и содержимое — все три обязаны сойтись. Показ
    самодостаточен, и суд разбирает его целиком;
  · СПИСОК: «список из двух пунктов: время и сила» — числительное
    словом против длины перечня;
  · ССЫЛКА: «ссылка с текстом X ведёт на URL» сверяется с записью
    «[X](URL)», живущей в том же слое;
  · МАТЕМАТИКА в «$…$» отдана суду арифметики — она числовая, и
    делить её надвое значило бы завести второго судью одному факту.

ЗАГОЛОВОК СУДИТСЯ ПО СЛОЮ, А НЕ ПО СОСЕДУ. Утверждение и сама строка
заголовка разведены перестановкой проходов, и требовать их соседства
значило бы судить порядок вместо факта. Суд собирает все заголовки слоя
и спрашивает: на каком уровне это слово вообще стоит.
"""
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import Unreadable, worlds  # noqa: E402
import lexicon  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ЧИСЛОМ = {"одного": 1, "двух": 2, "трёх": 3, "четырёх": 4,
          "пяти": 5, "шести": 6, "семи": 7, "восьми": 8,
          "один": 1, "два": 2, "три": 3, "четыре": 4, "пять": 5,
          "шесть": 6, "семь": 7, "восемь": 8,
          "one": 1, "two": 2, "three": 3, "four": 4, "five": 5}
# (маркер, имя стиля) — объявление, а не догадка
СТИЛИ = [(r"\*\*", "жирное"), (r"\*\*", "bold"),
         (r"\*", "курсив"), (r"\*", "italic"),
         (r"`", "код"), (r"`", "code")]

# ЗАГОЛОВОК ПИШЕТСЯ И С ТОЧКОЙ: «## свет.» — та же запись, что «## свет»,
# и суд, требовавший её отсутствия, не находил в слое НИ ОДНОГО заголовка,
# а потому молчал обо всех утверждениях о них.
def _словарь_слоя():
    """Слова, которыми слои вправе размечать, — из дома пар.

    САМА РАЗМЕТКА ТОЖЕ СУДИМА. Тысяча семьсот строк «# поле.» и
    «- вода» суть материал, а не утверждения о нём, и потому казались
    непроверяемыми. Но слово в заголовке взято из объявленного набора,
    и слово вне его есть дрейф.

    ЧИТАЛСЯ ЭТОТ НАБОР РАЗБОРОМ ЛИТЕРАЛОВ В ИСХОДНИКАХ ДВУХ
    ГЕНЕРАТОРОВ — и один из них НЕ СУЩЕСТВОВАЛ: словарь крупнейшего
    слоя был пуст, а с ним молчала и половина суда. Читать надо ДОМ, а
    не текст того, кто его читает.
    """
    вон = set()
    for рус, англ in lexicon.ПАРЫ:
        вон.add(рус.lower())
        вон |= {а.lower() for а in англ}
    return вон


СЛОВАРЬ_СЛОЯ = _словарь_слоя()
ЗАГОЛОВОК = re.compile(r"^(#{1,6}) (\S+?)\.?$")
ПУНКТ = re.compile(r"^(?:[-*]|\d+\.) (\S+?)\.?$")
# УРОВЕНЬ ПИШЕТСЯ И СЛОВОМ: «заголовок уровня два» — та же запись, что
# «уровня 2», и суд, знающий только цифру, молчал о двухстах строках.
ЗАГ_УТВ = re.compile(r"^заголовок уровня (\S+): (\S+?)\.$")
# УРОВЕНЬ ПИШЕТСЯ СЛОВОМ И ПО-АНГЛИЙСКИ. Русская сторона это уже
# знала, английская — нет: тридцать объявлений «heading level one»
# стояли вне суда, ибо образец требовал цифры. Одно правило на два
# языка есть то же правило, а не два похожих.
ЗАГ_УТВ_EN = re.compile(r"^heading level (\S+): (\S+?)\.$")
ССЫЛКА = re.compile(r"^\[([^\]]+)\]\((\S+)\)$")
ССЫЛ_УТВ = re.compile(r"^ссылка с текстом (\S+) ведёт на (\S+?)\.$")
СПИСОК = re.compile(r"^список из (\S+) пунктов: (.+?)\.$")
СПИСОК_БЕЗ_ЧИСЛА = re.compile(r"^(?:список|list): (.+?)\.$")
РАЗДЕЛ = re.compile(
    r"^(?:раздел|section) (\S+) (?:содержит|contains) (\S+?)\.$")
СТИЛЬ_УТВ = re.compile(
    r"^(\*\*|\*|`)(.+?)\1 (?:читается как|is read as) (\S+) (.+?)\.$")
СПИСОК_EN = re.compile(
    r"^numbered list of (\S+) items: (.+?)\.$")
ТАБЛИЦА_УТВ = re.compile(
    r"^таблица: столбцы (\S+) и (\S+); строка значений (\d+) и (\d+)\.$")
ТАБЛИЦА_УТВ_EN = re.compile(
    r"^table: columns (\S+) and (\S+); value row (\d+) and (\d+)\.$")
БЛОК_УТВ = re.compile(
    r"^(?:код-блок из одной строки|a code block of one line): (.+)$")
СТРОКА_ТАБЛИЦЫ = re.compile(r"^\|(?: [^|]+ \|)+$")
ОГРАДА = re.compile(r"^```$")


def разделить(перечень):
    """Пункты перечня — обоими союзами, ОДНИМ правилом.

    Союз разбирался в четырёх местах и в двух из них только по-русски:
    английский перечень приходил одним куском, и двести тридцать
    честных объявлений оказались «ложью» — не в корпусе, а в суде.
    """
    return [x.strip().rstrip(".")
            for x in re.split(r" и | and ", перечень) if x.strip()]


class Слой:
    """Что слой сам о себе содержит: заголовки и ссылки."""

    def __init__(self):
        self.уровни = collections.defaultdict(set)
        self.ссылки = {}
        # ВЛОЖЕННОСТЬ ОБЪЯВЛЕНА ПАРОЙ СТРОК «# X.» и «## Y.», идущих
        # подряд: это единственное место, где соседство есть ЧАСТЬ
        # записи, а не случайность перестановки.
        self.вложенность = collections.defaultdict(set)
        # ОБЪЯВЛЕНИЯ СЛОЯ — ВТОРАЯ ЕГО ПОЛОВИНА. Прежде слой впитывал
        # только разметку и судил ею объявления; обратная сторона
        # («разметка без объявления есть дрейф») не проверялась вовсе,
        # и тысяча строк сырой разметки стояла вне суда.
        self.объявленные_уровни = collections.defaultdict(set)
        self.объявленные_пункты = set()
        self.объявленные_блоки = set()
        self.объявленные_столбцы = set()
        self.объявленные_значения = set()
        self.столбцы_разметки = set()
        self.значения_разметки = set()
        self.строки_блоков = set()
        self.объявленные_разделы = set()

    def впитать(self, путь):
        прежний = None
        внутри_ограды = False
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                с = строка.strip()
                m = ЗАГОЛОВОК.match(с)
                if m and прежний and len(m.group(1)) > len(прежний[0]):
                    self.вложенность[прежний[1]].add(m.group(2))
                прежний = (m.group(1), m.group(2)) if m else None
                m = ЗАГОЛОВОК.match(с)
                if m:
                    self.уровни[m.group(2)].add(len(m.group(1)))
                m = ССЫЛКА.match(с)
                if m:
                    self.ссылки.setdefault(m.group(1), set()).add(m.group(2))
                if СТРОКА_ТАБЛИЦЫ.match(с):
                    ячейки = tuple(x.strip()
                                   for x in с.strip("|").split("|"))
                    if len(ячейки) == 2:
                        (self.значения_разметки
                         if all(x.isdigit() for x in ячейки)
                         else self.столбцы_разметки).add(ячейки)
                elif внутри_ограды and с and not ОГРАДА.match(с):
                    self.строки_блоков.add(с)
                if ОГРАДА.match(с):
                    внутри_ограды = not внутри_ограды
                self._объявление(с)

    def _объявление(self, с):
        """Впитать то, что слой САМ О СЕБЕ объявляет."""
        m = ЗАГ_УТВ.match(с) or ЗАГ_УТВ_EN.match(с)
        if m:
            сырой = m.group(1)
            ур = int(сырой) if сырой.isdigit() else ЧИСЛОМ.get(сырой)
            if ур is not None:
                self.объявленные_уровни[m.group(2)].add(ур)
            return
        m = СПИСОК.match(с) or СПИСОК_EN.match(с)
        if m:
            self.объявленные_пункты |= set(разделить(m.group(2)))
            return
        m = СПИСОК_БЕЗ_ЧИСЛА.match(с)
        if m:
            self.объявленные_пункты |= set(разделить(m.group(1)))
            return
        m = РАЗДЕЛ.match(с)
        if m:
            self.объявленные_разделы |= set(m.groups())
            return
        m = БЛОК_УТВ.match(с)
        if m:
            self.объявленные_блоки.add(m.group(1).strip())
            return
        m = ТАБЛИЦА_УТВ.match(с) or ТАБЛИЦА_УТВ_EN.match(с)
        if m:
            а, б, n, k = m.groups()
            self.объявленные_столбцы.add((а, б))
            self.объявленные_значения.add((n, k))


def судить(строка, слой):
    с = строка.strip()
    m = ЗАГ_УТВ.match(с) or ЗАГ_УТВ_EN.match(с)
    if m:
        сырой = m.group(1)
        уровень = int(сырой) if сырой.isdigit() else ЧИСЛОМ.get(сырой)
        слово = m.group(2)
        if уровень is None:
            return False, True
        если = слой.уровни.get(слово)
        if если is None:
            return False, True
        return True, уровень in если
    # РАЗМЕТКА СУДИТСЯ ОБЪЯВЛЕНИЕМ, КАК ОБЪЯВЛЕНИЕ СУДИТСЯ РАЗМЕТКОЙ.
    # Заголовок, чей уровень слой объявляет иным, есть ЛОЖЬ, а не
    # неизвестность: обе стороны записи присутствуют в слое, и
    # расхождение между ними — противоречие, которого не увидит счёт,
    # ибо каждая строка верна поодиночке.
    m = ЗАГОЛОВОК.match(с)
    if m:
        уровень, слово = len(m.group(1)), m.group(2)
        объявлено = слой.объявленные_уровни.get(слово)
        if объявлено:
            # У СЛОВА БЫВАЕТ ДВА ЗАКОННЫХ УРОВНЯ, И ВТОРОЙ ОБЪЯВЛЕН
            # ИНАЧЕ. Заголовок внутри вложенности («# X.» над «## Y.»)
            # объявлен не уровнем, а отношением «раздел X содержит Y»:
            # слово там не стоит на своём уровне, оно ИГРАЕТ РОЛЬ. Суд,
            # знавший одно объявление из двух, назвал ложью сто
            # тридцать честных строк — вина не корпуса, а суда.
            if слово in слой.объявленные_разделы:
                return True, True
            return True, уровень in объявлено
        if СЛОВАРЬ_СЛОЯ:
            return (True, True) if слово.lower() in СЛОВАРЬ_СЛОЯ \
                else (False, True)
        return False, True
    m = ПУНКТ.match(с)
    if m:
        слово = m.group(len(m.groups()))
        if слой.объявленные_пункты:
            return True, слово in слой.объявленные_пункты
        if СЛОВАРЬ_СЛОЯ:
            return (True, True) if слово.lower() in СЛОВАРЬ_СЛОЯ \
                else (False, True)
        return False, True
    # СТРОКА ВНУТРИ ОГРАДЫ СУДИТСЯ СВОИМ ОБЪЯВЛЕНИЕМ, как и всякая
    # разметка. Слой, называющий содержимое блока, обязан его и
    # написать — и наоборот: код, которого никто не объявлял, есть
    # дрейф той же природы, что заголовок без уровня.
    if слой.строки_блоков and с in слой.строки_блоков:
        return True, с in слой.объявленные_блоки
    if ОГРАДА.match(с):
        # ОГРАДА КОДА СУДИМА СВОЕЙ ПАРНОСТЬЮ И ОБЪЯВЛЕНИЕМ: слой,
        # называющий код-блок, обязан его и открыть.
        return bool(слой.объявленные_блоки), True
    m = ТАБЛИЦА_УТВ.match(с) or ТАБЛИЦА_УТВ_EN.match(с)
    if m:
        а, б, n, k = m.groups()
        return True, ((а, б) in слой.столбцы_разметки
                      and (n, k) in слой.значения_разметки)
    m = БЛОК_УТВ.match(с)
    if m:
        return True, m.group(1).strip() in слой.строки_блоков
    if СТРОКА_ТАБЛИЦЫ.match(с):
        ячейки = tuple(x.strip() for x in с.strip("|").split("|"))
        if len(ячейки) != 2:
            return False, True
        if all(x.isdigit() for x in ячейки):
            return bool(слой.объявленные_значения), \
                ячейки in слой.объявленные_значения
        if слой.объявленные_столбцы:
            return True, ячейки in слой.объявленные_столбцы
        return False, True
    m = РАЗДЕЛ.match(с)
    if m:
        внешний, внутренний = m.group(1), m.group(2)
        пара = слой.вложенность.get(внешний)
        if пара is None:
            return False, True
        return True, внутренний in пара
    m = СПИСОК_БЕЗ_ЧИСЛА.match(с)
    if m:
        пункты = разделить(m.group(1))
        # список без объявленной длины судится непустотой и различием
        # пунктов: перечень, повторяющий пункт, есть не список, а сбой
        return True, len(пункты) > 1 and len(set(пункты)) == len(пункты)
    m = СТИЛЬ_УТВ.match(с)
    if m:
        маркер, тело, имя, назван = m.groups()
        ждём = {и for мар, и in СТИЛИ if re.fullmatch(мар, маркер)}
        return True, имя in ждём and тело.strip() == назван.strip()
    m = СПИСОК.match(с)
    if m:
        сколько = ЧИСЛОМ.get(m.group(1))
        пункты = разделить(m.group(2))
        if сколько is None:
            return False, True
        return True, сколько == len(пункты)
    m = ССЫЛ_УТВ.match(с)
    if m:
        текст, адрес = m.groups()
        если = слой.ссылки.get(текст)
        if если is None:
            return False, True
        return True, адрес in если
    return False, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"РАЗМЕТКА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("РАЗМЕТКА ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        слой = Слой()
        слой.впитать(путь)
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка, слой)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"РАЗМЕТКА {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
