#!/usr/bin/env python3
"""СУД ТРЁХЧЛЕННОЙ ЦЕПОЧКИ: закон эпизода пересчитывается заново.

Показ утверждает три факта об одном носителе и одном предмете и связывает
их законом: третье число есть первое, изменённое вторым. Суд не верит ни
одному из трёх: он берёт числа, берёт ОБЪЯВЛЕННУЮ полярность тройки
глаголов и считает сам.

ПОЛЯРНОСТЬ ЖИВЁТ В ГЛАГОЛАХ, А НЕ В ЧИСЛАХ. «picked … gave away …
keeps» отнимает, «had … found … holds» прибавляет; сказать это по
числам нельзя — 12, 5 и 7 согласны с вычитанием, а 12, 5 и 17 со
сложением, и оба ряда законны при СВОИХ глаголах. Потому тройка глаголов
объявлена вместе со знаком, и суд сверяет ЗНАК, а не подгоняет его.

НОСИТЕЛЬ ОБЯЗАН БЫТЬ ТЕМ ЖЕ ВО ВСЕХ ТРЁХ ФАКТАХ. Показ, где взял один, а
держит другой, есть не эпизод, а два эпизода рядом; рынок такого не
покупает, и суд такого не пропускает.

СОГЛАСОВАНИЕ ЧИСЛА СУДИТСЯ НАРАВНЕ СО СЧЁТОМ: «1 apple» против «5
apples», русское «1 яблоко / 3 яблока / 8 яблок». Слой, считающий верно
и говорящий неверно, учит неверному языку с полной судимостью.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import gen_genesis_story_chain as дом  # noqa: E402
import rugram  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

_ЗНАК_EN = {(в1, в2, в3): знак
            for в1, в2, в3, _о, знак in дом.ТРОЙКИ_EN}
_ЗНАК_RU = {(в1, в2, в3): знак for в1, в2, в3, знак in дом.ТРОЙКИ_RU}
_ЕД = {ед: (ед, мн) for ед, мн in дом.ВЕЩИ_EN}
_МН = {мн: (ед, мн) for ед, мн in дом.ВЕЩИ_EN}

# ГЛАГОЛ БЫВАЕТ ИЗ ДВУХ СЛОВ НА ЛЮБОМ ИЗ ТРЁХ МЕСТ. Первая редакция
# позволяла «away» только первому и «left» только третьему — а «gave
# away» стоит ВТОРЫМ, и семьдесят пять честных показов остались
# несудимыми. Составной глагол есть глагол, где бы он ни стоял.
_ГЛ = r"([a-z]+(?: away| left)?)"
ЦЕПЬ = re.compile(
    rf"^(\w+) {_ГЛ} (\d+) ([a-z]+) and {_ГЛ} (\d+) "
    rf"([a-z]+); \1 {_ГЛ} (\d+) ([a-z]+)\.$")
# ГЛАГОЛ СУДИТСЯ ОБЪЯВЛЕННОЙ ПАРОЙ, А НЕ ОСНОВОЙ С СУФФИКСОМ (08.09).
#
# Прежний образец читал «(\S+?)(а?)» — основу и необязательную «а», — и тем УЧИЛ ТО ЖЕ
# НЕВЕРНОЕ ПРАВИЛО, что и дом: женское прошедшее есть мужское плюс буква. На «нашёл» правило
# ломается («нашла», а не «нашёла»), и суд, построенный на нём, звал бы верную страницу чужой.
#
#     СУД, ВЫВОДЯЩИЙ ФОРМУ ТЕМ ЖЕ ПРАВИЛОМ, ЧТО И ДОМ, НЕ ПРОВЕРЯЕТ ДОМ — ОН ЕМУ ВТОРИТ.
#
# Ныне обе формы каждого глагола берутся у дома языка (`rugram.прошедшее`) и кладутся в
# указатель вместе с ПОЛОМ, которого они требуют. Оттого суд стал строже прежнего: он читает
# род лица и ловит «Ваня взяла» — шестьдесят две страницы, которые прежний пропускал, ибо
# сверял лишь имя с его родительным.
_ФОРМЫ_RU = {}
for _в1, _в2, _в3, _знак in дом.ТРОЙКИ_RU:
    for _пол in ("m", "f"):
        _ФОРМЫ_RU[(rugram.прошедшее(_в1, _пол), rugram.прошедшее(_в2, _пол), _в3)] = (_знак, _пол)
_ПОЛ_ЛИЦА = {им: пол for им, _род, пол in дом.ЛЮДИ_RU}
_РОД_ЛИЦА = {им: род for им, род, _пол in дом.ЛЮДИ_RU}

ЦЕПЬ_RU = re.compile(
    r"^(\S+) (\S+) (\d+) (\S+) и (\S+) (\d+) (\S+); у (\S+) "
    r"(\S+) (\d+) (\S+)\.$")
ВОПРОС = re.compile(
    r"^(?:how many [a-z]+ does \w+ [a-z ]+\? |сколько \S+ у \S+\? )"
    r"(.+)$")


def _форма_en(n, слово):
    пара = _ЕД.get(слово) or _МН.get(слово)
    if пара is None:
        return None
    return слово == (пара[0] if n == 1 else пара[1])


def _вещь_en(слово):
    пара = _ЕД.get(слово) or _МН.get(слово)
    return пара[0] if пара else None


def _судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    м = ВОПРОС.match(с)
    if м:
        return судить(м.group(1))
    м = ЦЕПЬ.match(с)
    if м:
        (кто, в1, а, вещь1, в2, б, вещь2, в3, итог, вещь3) = м.groups()
        а, б, итог = int(а), int(б), int(итог)
        знак = _ЗНАК_EN.get((в1, в2, в3))
        if знак is None:
            return False, False
        вещи = {_вещь_en(вещь1), _вещь_en(вещь2), _вещь_en(вещь3)}
        if None in вещи or len(вещи) != 1:
            return True, False
        ждём = а - б if знак == "-" else а + б
        return True, (итог == ждём
                      and _форма_en(а, вещь1)
                      and _форма_en(б, вещь2)
                      and _форма_en(итог, вещь3))
    м = ЦЕПЬ_RU.match(с)
    if м:
        (им, в1, а, ф1, в2, б, ф2, род, в3, итог, ф3) = м.groups()
        а, б, итог = int(а), int(б), int(итог)
        запись = _ФОРМЫ_RU.get((в1, в2, в3))
        if запись is None:
            return False, False
        знак, пол = запись
        ключ = rugram.ПО_ФОРМЕ.get(ф1)
        if ключ is None or rugram.ПО_ФОРМЕ.get(ф2) != ключ \
                or rugram.ПО_ФОРМЕ.get(ф3) != ключ:
            return True, False
        ждём = а - б if знак == "-" else а + б
        return True, (итог == ждём
                      and rugram.согласовано(а, ф1)
                      and rugram.согласовано(б, ф2)
                      and rugram.согласовано(итог, ф3)
                      and _РОД_ЛИЦА.get(им) == род
                      # РОД ГЛАГОЛА ЕСТЬ РОД ЛИЦА, А НЕ ОКОНЧАНИЕ ЕГО ИМЕНИ
                      and _ПОЛ_ЛИЦА.get(им) == пол)
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ЦЕПОЧКА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ЦЕПОЧКА ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:88]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ЦЕПОЧКА {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


# МИР ЗАМКНУТ, И ЭТО ПРОВЕРЕНО ДЕЛОМ, А НЕ ОБЪЯВЛЕНО МНЕНИЕМ (06.09, перепись
# закрываемости): палата, суженная до одного этого суда, судила КАЖДУЮ строку
# мира («story_chain» — 890 строк) — судимы ВСЕ до одной. Значит показы суда суть весь мир, и
# молчание его о строке этого мира есть не воздержание, а форма, которой мир
# не писал. Обёртка не может сработать ни на одной сегодняшней строке — это
# доказательство, а не выборка; ловится лишь то, чего в файле НЕТ.
ЗАМКНУТЫЕ_МИРЫ = frozenset({"story_chain"})
судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


if __name__ == "__main__":
    sys.exit(main())
