#!/usr/bin/env python3
"""[ДВА ОТВЕТА ОДНОГО ДЕЛЕНИЯ] — какое из двух округлений верно, пересчитано судом.

Суд не пишет закона заново: он берёт его у дома (`ceilfloorforms`), где рамки, вещи и числа
объявлены одной таблицей. Подмена частного, остатка и САМОГО ОКРУГЛЕНИЯ ловится машинально:
произведение и сумма пересчитываются, остаток обязан быть меньше делителя, а два ответа —
расходиться ровно на единицу.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЧАСТНОЕ С ОСТАТКОМ ПРОВЕРЯЕТСЯ БЕЗ ЗНАКА РАВЕНСТВА: «53 ÷ 20 даёт 2 и остаток 13» истинно, если
20 × 2 + 13 = 53 и 13 < 20. Написанное равенством «53 ÷ 20 = 2» было бы ложью, и её назвал бы
ложью суд арифметики — потому дом так и не пишет.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/ceilfloor_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import ceilfloorforms  # noqa: E402 — дом, объявивший два ответа
import closedworld  # noqa: E402

ИМЯ_СУДА = "ceilfloor"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"ceilfloor"})


def _судить(строка):
    return ceilfloorforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ДВА ОТВЕТА ОДНОГО ДЕЛЕНИЯ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(ceilfloorforms.РОДЫ)}, страниц {len(ceilfloorforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
