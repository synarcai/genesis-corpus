#!/usr/bin/env python3
"""[УСЛОВНАЯ ВЕРОЯТНОСТЬ] — доля при условии, пересчитанная судом.

Суд не пишет закона заново: он берёт его у дома (`condforms`), где ящики объявлены двумя
таблицами — зависимые и независимые, — а события кости объявлены МНОЖЕСТВАМИ ИСХОДОВ, а не
описаны словами. Всякая запись страницы считается разбором свода (`arithread`), и равенство
накрест «4 × 25 = 10 × 10» читается как одно утверждение о двух произведениях.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: обе стороны ловушки обязаны быть
показаны; ящик, у которого доли сошлись, не смеет лежать в зависимых; и знаменатели пары
кости обязаны различаться — иначе несимметричность не видна вовсе.

    python3 courts/cond_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import condforms  # noqa: E402 — дом, объявивший условную вероятность

ИМЯ_СУДА = "cond"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"cond"})


def _судить(строка):
    return condforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"УСЛОВНАЯ ВЕРОЯТНОСТЬ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(condforms.РОДЫ)}, страниц {len(condforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
