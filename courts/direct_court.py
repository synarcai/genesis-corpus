#!/usr/bin/env python3
"""[ПРЯМАЯ РЕЧЬ] — знак при речи, выведенный судом по правилу, а не припомненный.

Суд не пишет закона заново: он берёт его у дома (`directforms`), где речи объявлены вместе со
своим ЗНАКОМ КОНЦА, а слова автора — ДВУМЯ порядками (за речью «сказал он», впереди неё «он
сказал»), ибо порядок слов есть часть правила.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: запятая обязана стоять ЛИШЬ там, где снята
точка, и не смеет появиться после вопросительного или восклицательного знака; кавычки обязаны
быть ёлочками; знаки конца обязаны быть все три, и у всякого — объявленное ИМЯ, ибо дом,
говорящий о знаке, называет его именем, а не ставит его: суд письма прочёл бы поставленный
знак как настоящий вопрос строки.

ИМЯ ЭТОГО СУДА — `direct`, А НЕ `speech`: имя `speech` уже несёт суд связи речи, и два суда
под одним именем неотличимы в наборе и в леджере (`scripts/court_voice.py`).

    python3 courts/direct_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import directforms  # noqa: E402 — дом, объявивший множитель размерности

ИМЯ_СУДА = "direct"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"direct"})


def _судить(строка):
    return directforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ПРЯМАЯ РЕЧЬ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(directforms.РОДЫ)}, страниц {len(directforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
