#!/usr/bin/env python3
"""[СЛОВО ПЕРЕД ЛИЦОМ] — за словом, после которого свод ставил лишь объявленное, не стоит незнакомое.

    ЗАКОН ЛОВИТ НЕЗНАКОМОЕ, А НЕ НЕВИДАННОЕ.

«how many eggs does Ben hold now?» → «…does Be hold now?» палата звала ИСТИНОЙ: закон зачина
судит лишь зачин, закон падежа — лишь формы лица, а внутри предложения обрезок имени был ничей.
Здесь читается тройка «класс слова перед → слово → класс слова за ним»: за «вещь does» свод
ставил лицо, местоимение, число и отрицание — всё объявленное пакетом, — и необъявленное «be»
на этом месте есть ложь. Право берётся у двери (`tools/actors.py`, четвёртый слой): там покупка,
улов, цена, граница и замер, почему тройка, а не пара.

    СУД ЕСТЬ ЛОВЕЦ ПОРЧИ, А НЕ ПОДТВЕРЖДАТЕЛЬ ИСТИНЫ, как и соседи `actoropener_court` и
    `personcase_court`: нашёл незнакомое за строгим словом — ложь; не нашёл — молчит.

ЧТО ЭТОТ СУД ЛОВИТ, ЧИСЛОМ (23.09, ночь): порча всякого имени внутри предложения во всех 42 мирах
деятелей — палата пропускала 1 731 и не судила 340; этот суд ловит 688 и судит 105; цена на
невиданной половине 0 обвинений на 40 247 строках. Покупка читается с полки, собранной
`scripts/beforeperson_market.py`, и не пересчитывается.
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import actors  # noqa: E402 — дверь лиц и рынок слова перед лицом
from actors import Слой  # noqa: E402 — деятели мира из манифеста

# ЛОВЕЦ ПОРЧИ БЕЗ ИСТИНЫ, И ОБЪЯВЛЕНО ЭТО ДВАЖДЫ — здесь и в списке `court_mutants`: суд
# говорит ЛОЖЬ о строке, где за строгим словом стоит незнакомое, и МОЛЧИТ обо всех прочих.
ЛОВЕЦ_ПОРЧИ = True


def судить(строка, слой=None):
    """(судимо, истинно): за строгим словом перед лицом — лишь объявленное."""
    if слой is None:
        return False, False
    языки = слой.языки()
    if not языки:
        return False, False
    return (True, False) if actors.порча_соседа(строка, языки) else (False, False)


def main():
    судимо = ложных = 0
    примеры = []
    for имя, путь, языки in actors.миры_деятелей():
        if not путь.exists():
            continue
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            беды = actors.порча_соседа(строка, языки)
            if not беды:
                continue
            судимо += 1
            ложных += 1
            if len(примеры) < 5:
                перед, слово, за, язык = беды[0]
                примеры.append(f"{имя}/{язык}: «{перед} {слово} {за}» ← {строка.strip()[:80]}")
    for п in примеры:
        print(f"  {п}")
    куплено = actors.куплен_сосед()
    строгих = sum(1 for к in куплено.values() if actors.НЕТ_КЛАССА not in к)
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"СЛОВО ПЕРЕД ЛИЦОМ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"ключей {len(куплено)}, строгих {строгих}, на {len({к[0] for к in куплено})} языках")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
