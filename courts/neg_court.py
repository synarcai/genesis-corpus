#!/usr/bin/env python3
"""[ОТРИЦАТЕЛЬНОЕ ЧИСЛО] — порядок за нулём, пересчитанный судом.

Суд не пишет закона заново: он берёт его у дома (`negforms`), где рамки и числа объявлены одной
таблицей. Подмена порядка и РАССТОЯНИЯ ДО НУЛЯ ловится машинально: «меньше», «больше» и «дальше»
сверяются числами СО ЗНАКОМ, а не принимаются на слово.

    ЗНАК МИНУС ЕСТЬ ЧАСТЬ ЧИСЛА. Образец, читающий «5 меньше 2» сквозь «-5 меньше -2», теряет
    весь предмет дома разом — и зовёт истину ложью.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/neg_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import negforms  # noqa: E402 — дом, объявивший отрицательное число

ИМЯ_СУДА = "neg"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"neg"})


def _судить(строка):
    return negforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ОТРИЦАТЕЛЬНОЕ ЧИСЛО {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(negforms.РОДЫ)}, страниц {len(negforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
