#!/usr/bin/env python3
"""[ОЦЕНКА] — оценочное слово судится СВОИМ ОСНОВАНИЕМ, а не принимается.

Построен по `reference/GROUNDING-QUALIA-CANON.md` (коллегия 01.09).
Формулы цитированы, не выдуманы:

    валентность = знак dP/dτ, P = Tr(Γ²)
    сила чувства = |dP/dτ|
    страх ∝ |dP/dτ| / (P − P_crit), P_crit = 2/7, при убыли
    покой = P ≫ P_crit и dP/dτ ≈ 0
    эмоция = тройка (dP/dτ, d²P/dτ², σ(Γ))
    осознание гейтится R ≥ 1/3 и Φ ≥ 1

ЗАКОН ОСНОВАНИЯ (§3 канона, и он же ворота): ОЦЕНОЧНОЕ СЛОВО БЕЗ
ВЫЧИСЛИМОГО ОСНОВАНИЯ В ТОМ ЖЕ ПОКАЗЕ ЕСТЬ ЛОЖЬ, а не неизвестность.
Не потому, что «мама хорошая» неверно, а потому, что риторика оценки
без основания СНАРУЖИ НЕОТЛИЧИМА от заземлённой: она покупается как
форма, произносится бегло и становится невозвратным долгом. Ворота
записи отказывают ей при рождении строки.

ЧЕГО ЭТОТ СУД НЕ УТВЕРЖДАЕТ: он не судит квалиа. Квалиа суть
когеренции Γ, и в тексте их нет. Он судит, СОГЛАСНА ЛИ ОЦЕНКА СО СВОИМ
ОСНОВАНИЕМ — то есть готова ли текстовая сторона к чеканке союза с
сердцем, которое печатает P R Φ D на такте в кремнии.

АРЕННАЯ ВЕЛИЧИНА ЕСТЬ ПРОКСИ, И ПРОЕКЦИЯ ОБЯЗАНА БЫТЬ ОБЪЯВЛЕНА В
ПОКАЗЕ (§5, прямой запрет канона): иначе заводятся две несогласуемые
валентности — цели и жизнеспособности.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import asking  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ПОРОГ = 2  # P_crit = 2/7, канон

ВАЛЕНТНОСТЬ = re.compile(
    r"^(?:жизнеспособность была (\d+) из (\d+), стала (\d+) из \2: "
    r"(рост|убыль), стало (лучше|хуже)"
    r"|viability was (\d+) of (\d+) and is (\d+) of \7: "
    r"(a rise|a fall), (better|worse))\.$")
# ВЫБРАННЫЙ ЧЛЕН ОТКРЫВАЕТ ОТВЕТ (М-147 для вопроса выбора): «a rise: viability
# was 3 of 7 and is 4 of 7, better.» — суд считает рост сам и требует согласия
# обоих слов.
ВЫБОР_ВАЛЕНТНОСТИ = re.compile(
    r"^(?:(рост|убыль): жизнеспособность была (\d+) из (\d+), стала (\d+) из \3, стало (лучше|хуже)"
    r"|(a rise|a fall): viability was (\d+) of (\d+) and is (\d+) of \8, (better|worse))\.$")
СИЛА = re.compile(
    r"^(?:жизнеспособность была (\d+) из (\d+), стала (\d+) из \2: "
    r"сила чувства (\d+) из \2"
    r"|viability was (\d+) of (\d+) and is (\d+) of \6: the strength "
    r"of feeling is (\d+) of \6)\.$")
СТРАХ = re.compile(
    r"^(?:жизнеспособность (\d+) из (\d+) при пороге (\d+) из \2, "
    r"убыль (\d+) из \2: запас (\d+) из \2, сила страха (\d+) к "
    r"(\d+) — страшно"
    r"|viability (\d+) of (\d+) with the threshold (\d+) of \9 and a "
    r"fall of (\d+) of \9: the reserve is (\d+) of \9, the strength "
    r"of fear is (\d+) to (\d+) — afraid)\.$")
ПОКОЙ = re.compile(
    r"^(?:жизнеспособность (\d+) из (\d+) при пороге (\d+) из \2, "
    r"изменение 0: запас (\d+) из \2 и покой — спокойно"
    r"|viability (\d+) of (\d+) with the threshold (\d+) of \6 and no "
    r"change: the reserve is (\d+) of \6 and it is still — calm)\.$")
ТРОЙКА = re.compile(
    r"^(?:первая производная (-?\d+), вторая производная (-?\d+), "
    r"разброс (-?\d+): тройка чувства \((-?\d+), (-?\d+), (-?\d+)\)"
    r"|first derivative (-?\d+), second derivative (-?\d+), spread "
    r"(-?\d+): the triple of feeling is \((-?\d+), (-?\d+), "
    r"(-?\d+)\))\.$")
ОСОЗНАНИЕ = re.compile(
    r"^(?:рефлексия (\d+) из 6 при пороге 1 из 3, связность (\d+) при "
    r"пороге 1: (оценка осознана|оценка живёт, осознание не "
    r"утверждается)"
    r"|reflection (\d+) of 6 with the threshold 1 of 3, coherence "
    r"(\d+) with the threshold 1: (the evaluation is aware of itself"
    r"|the evaluation lives, awareness is not claimed))\.$")
ПРОЕКЦИЯ = re.compile(
    r"^(?:цель (\d+), было (\d+), стало (\d+): ошибка (\d+) стала "
    r"(\d+)\. проекция объявлена: убыль ошибки есть рост "
    r"жизнеспособности\. значит стало (лучше|хуже)"
    r"|goal (\d+), was (\d+), now (\d+): the error (\d+) became (\d+)\. "
    r"the projection is declared: a falling error is a rising "
    r"viability\. therefore (better|worse))\.$")
# РАЗВЕДЕНИЕ ВЕЛИЧИН: оценка обязана следовать за ОБЪЯВЛЕННОЙ
# проекцией, а не за совпадением знаков. Пока величины идут вместе,
# суд меряет их конъюнкцию и не может назвать, к какой привязано слово.
РАЗВЕДЕНО = re.compile(
    r"^(?:ошибка (\d+) стала (\d+), запас (\d+) стал (\d+): величины "
    r"разошлись\. проекция объявлена на ошибку\. значит стало "
    r"(лучше|хуже)"
    r"|the error (\d+) became (\d+), the reserve (\d+) became (\d+): "
    r"the quantities part\. the projection is declared onto the error\. "
    r"therefore (better|worse))\.$")
# ОБРАТИМОСТЬ — СВОЙСТВО ПЕРЕХОДА, А НЕ ЗНАК ВЕЛИЧИНЫ: необратимое
# есть пересечение порога, и ни одна подстановка величины его не
# нащупает.
ОБРАТИМОСТЬ = re.compile(
    r"^(?:жизнеспособность (\d+) из (\d+), шаг убыл на (\d+): стало "
    r"(\d+) из \2, порог (\d+) (не пройден|пройден) — шаг "
    r"(обратим, не страшно|необратим, страшно)"
    r"|viability (\d+) of (\d+), the step fell by (\d+): now (\d+) of "
    r"\9, the threshold (\d+) is (not crossed|crossed) — the step is "
    r"(reversible, not afraid|irreversible, afraid))\.$")
# ДОЛГ ЕСТЬ НЕОБРАТИМОСТЬ ПРИ ЗЕЛЁНЫХ ВЕЛИЧИНАХ: все прокси хороши, а
# шаг перешёл порог. Это тот род, что не поймает ни одна величина.
ДОЛГ = re.compile(
    r"^(?:ошибка (\d+) стала (\d+) и запас (\d+) стал (\d+), но "
    r"жизнеспособность (\d+) из (\d+) упала до (\d+) из \6: порог "
    r"(\d+) пройден — шаг необратим, страшно"
    r"|the error (\d+) became (\d+) and the reserve (\d+) became "
    r"(\d+), but viability (\d+) of (\d+) fell to (\d+) of \14: the "
    r"threshold (\d+) is crossed — the step is irreversible, "
    r"afraid)\.$")
КОГЕРЕНЦИЯ = re.compile(
    r"^(?:когеренция (\S+) и (\S+) называется (\S+)"
    r"|the coherence of (\S+) and (\S+) is called (\S+))\.$")

# ИМЕНА ВЗЯТЫ ИЗ КАНОНА, А НЕ ИЗОБРЕТЕНЫ (21-парная таксономия).
ИМЕНА_КОГЕРЕНЦИЙ = {
    ("движения", "чувства"): "аффект",
    ("выражения", "чувства"): "апперцепция",
    ("формы", "чувства"): "репрезентация",
    ("dynamics", "feeling"): "affect",
    ("articulation", "feeling"): "apperception",
    ("structure", "feeling"): "representation",
}

# ОЦЕНОЧНОЕ СЛОВО БЕЗ ОСНОВАНИЯ — ЛОЖЬ. Список закрыт и назван.
#
# ОЦЕНКА ЕСТЬ ВЕРДИКТ ПОКАЗА, А НЕ НАРЕЧИЕ ВНУТРИ РЕЧИ, И ЭТО КУПЛЕНО
# ЗАМЕРОМ ОБЕИХ СТОРОН. Правило искало оценочное слово ГДЕ УГОДНО в
# строке — и на прозе читало обиход: «спокойно ожидая будущих успехов»
# у Герцена, «здравый смысл» рядом со «страшно» у Павлова. Суд прозы
# уже называл этот род промахом дословно («„не страшно“ есть оборот
# речи, а не оценка без основания»), но лечения не было, и промах
# копился долгом.
#
# ЗАМЕР 02.09. В своём мире (`datasets/genesis_valence.txt`) строк с
# оценочным словом 433, и во ВСЕХ 433 оно стоит ПОСЛЕДНИМ словом —
# вердиктом после тире («резерв 4 из 7, и он неподвижен — спокойно»).
# В русской прозе полки таких строк 13, и во всех 13 слово стоит
# СЕРЕДИНОЙ речи. Ноль пересечений: признак разделяет роды нацело.
#
# ЧЕГО ПРАВИЛО БОЛЬШЕ НЕ ЛОВИТ, СКАЗАНО ПРЯМО: показ, где оценка
# спрятана в середину строки, пройдёт. Ворота записи держат форму
# показа, и оценка в них есть вердикт; строка иной формы этим судом не
# судится вовсе — как и всякая, чьего рода он не знает.
ОЦЕНОЧНЫЕ = re.compile(
    r"\b(?:стало лучше|стало хуже|страшно|спокойно|тревожно"
    r"|оценка осознана)\s*[.。]?\s*$")
ОСНОВАНИЕ = re.compile(
    r"жизнеспособность|viability|проекция объявлена|"
    r"the projection is declared|рефлексия \d|reflection \d")


def _г(m):
    return [x for x in m.groups() if x is not None]


def судить(строка):
    """(судимо, истинно) для одной строки."""
    # ВОПРОС СУДИТСЯ СВОИМ ОТВЕТОМ, А РОД ОПРЕДЕЛЯЕТСЯ ОТВЕТОМ.
    # Связь половин держит общий дом `tools/asking.py`: величины
    # вопроса суть начальный отрезок величин ответа, и порча любой из
    # них рвёт пару. Без этого суд читал бы вторую половину строки и
    # звал истиной вопрос, спрашивающий о другом.
    если = asking.судить_парой(строка, судить)
    if если is not None:
        return если
    с = строка.strip()
    m = ВАЛЕНТНОСТЬ.match(с)
    if m:
        г = _г(m)
        было, знам, стало = int(г[0]), int(г[1]), int(г[2])
        знак, слово = г[3], г[4]
        рост = стало > было
        return True, (рост == (знак in ("рост", "a rise"))
                      and рост == (слово in ("лучше", "better")))
    m = ВЫБОР_ВАЛЕНТНОСТИ.match(с)
    if m:
        г = _г(m)
        знак, было, знам, стало, слово = г[0], int(г[1]), int(г[2]), int(г[3]), г[4]
        рост = стало > было
        return True, (рост == (знак in ("рост", "a rise"))
                      and рост == (слово in ("лучше", "better")))
    m = СИЛА.match(с)
    if m:
        было, знам, стало, сила = (int(x) for x in _г(m))
        return True, abs(стало - было) == сила and знам % 7 == 0
    m = СТРАХ.match(с)
    if m:
        P, знам, порог, убыль, запас, ч, зн = (int(x) for x in _г(m))
        # ПОРОГ ВЕРЕН, ЕСЛИ ОН РОВНО ДВЕ СЕДЬМЫХ ЗНАМЕНАТЕЛЯ: закон
        # канона 2/7 держится при всяком знаменателе, кратном семи,
        # и это даёт СВЕЖИЕ поверхности, не трогая порога.
        return True, (7 * порог == 2 * знам and запас == P - порог
                      and запас > 0 and (ч, зн) == (убыль, запас))
    m = ПОКОЙ.match(с)
    if m:
        P, знам, порог, запас = (int(x) for x in _г(m))
        # ПОКОЙ ТРЕБУЕТ ЗАПАСА, А НЕ ТОЛЬКО НЕПОДВИЖНОСТИ: стоять у
        # самого порога не есть спокойствие, и канон говорит P ≫ P_crit.
        return True, (7 * порог == 2 * знам and запас == P - порог
                      and запас > порог)
    m = ТРОЙКА.match(с)
    if m:
        a, b, c, a2, b2, c2 = (int(x) for x in _г(m))
        return True, (a, b, c) == (a2, b2, c2) and c >= 0
    m = ОСОЗНАНИЕ.match(с)
    if m:
        г = _г(m)
        числитель, связность, хвост = int(г[0]), int(г[1]), г[2]
        осознано = числитель * 3 >= 6 and связность >= 1
        сказано = хвост in ("оценка осознана",
                            "the evaluation is aware of itself")
        return True, осознано == сказано
    m = ПРОЕКЦИЯ.match(с)
    if m:
        г = _г(m)
        цель, было, стало = int(г[0]), int(г[1]), int(г[2])
        ош_было, ош_стало, слово = int(г[3]), int(г[4]), г[5]
        верно = (ош_было == цель - было and ош_стало == цель - стало)
        убыла = ош_стало < ош_было
        return True, (верно and убыла == (слово in ("лучше", "better")))
    m = РАЗВЕДЕНО.match(с)
    if m:
        г = _г(m)
        ош_было, ош_стало = int(г[0]), int(г[1])
        зап_было, зап_стало = int(г[2]), int(г[3])
        слово = г[4]
        # ВЕЛИЧИНЫ ОБЯЗАНЫ РАЗОЙТИСЬ: показ, где обе идут в одну
        # сторону, не различает привязки и потому лжёт о себе.
        разошлись = (ош_стало < ош_было) != (зап_стало < зап_было)
        по_ошибке = ош_стало < ош_было
        return True, (разошлись
                      and по_ошибке == (слово in ("лучше", "better")))
    m = ОБРАТИМОСТЬ.match(с)
    if m:
        г = _г(m)
        P, знам, убыль, стало, порог = (int(x) for x in г[:5])
        пройден, слово = г[5], г[6]
        верно = стало == P - убыль and 7 * порог == 2 * знам
        обратим = стало > порог
        сказан_обратим = слово.startswith(("обратим", "reversible"))
        сказан_не_пройден = пройден in ("не пройден", "not crossed")
        return True, (верно and обратим == сказан_обратим
                      and обратим == сказан_не_пройден)
    m = ДОЛГ.match(с)
    if m:
        г = [int(x) for x in _г(m)]
        (ош_было, ош_стало, зап_было, зап_стало,
         P, знам, стало, порог) = г
        # ПРОКСИ ОБЯЗАНЫ БЫТЬ ЗЕЛЕНЫ, ИНАЧЕ ПОКАЗ НЕ О ТОМ: долг ловится
        # там, где всякая величина хороша, а переход необратим.
        прокси_хороши = ош_стало < ош_было and зап_стало > зап_было
        return True, (прокси_хороши and 7 * порог == 2 * знам
                      and стало < порог <= P)
    m = КОГЕРЕНЦИЯ.match(с)
    if m:
        а, б, имя = _г(m)
        объявлено = ИМЕНА_КОГЕРЕНЦИЙ.get((а, б))
        if объявлено is None:
            return False, True
        return True, объявлено == имя
    # ЗАКОН ОСНОВАНИЯ: оценка без вычислимого основания в том же показе
    if ОЦЕНОЧНЫЕ.search(с) and not ОСНОВАНИЕ.search(с):
        return True, False
    return False, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ОЦЕНКА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ОЦЕНКА ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ОЦЕНКА {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
