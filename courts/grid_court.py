#!/usr/bin/env python3
"""[СУД ЧТЕНИЯ ТАБЛИЦЫ] — таблица построена заново по записи; МИР ЗАМКНУТ.

Страница мира (`tools/gridread.py`) есть таблица и один вопрос к ней. Суд не берёт у дома ни
имён, ни чисел: он читает ЗАПИСЬ — имена строк, имена столбцов, полосы чисел, — сверяет, что
полос столько же, сколько строк, а чисел в полосе столько, сколько столбцов, и лишь потом
отвечает сам.

    СТРОКА И СТОЛБЕЦ СУТЬ ДВЕ КООРДИНАТЫ, А НЕ ДВА ПОИСКА ПОДРЯД: «Тверь» без столбца и
    «груши» без строки не значат ничего.

И отдельный закон об обратном чтении:

    ВОПРОС, У КОГО ДВА ОТВЕТА, НЕ ЕСТЬ ВОПРОС. Спроси, какая строка даёт в столбце число,
    стоящее там дважды, — и всякий ответ будет и верен, и ложен. Суд такую страницу не
    пропускает, даже когда названная строка это число и правда несёт.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import gridread as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"grid"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    о = "март дал 120 колёс, апрель дал 95 колёс, май дал 140 колёс. "

    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО (14.09). Подсадка бывает
    # СУДИМА И ИСТИННА — тогда лгал сам список: строка похожа на ложь, а есть правда.
    # Бывает и НЕСУДИМА — тогда она выпала из рамки дома, и прибор, считающий её просто
    # «непойманной», молчит о том, что перестал её читать вовсе. Суд скобок так и потерял
    # четыре подсадки из семи, когда рамка вопроса переменилась.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_grid.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_grid.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_grid.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ЧТЕНИЕ ТАБЛИЦЫ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
