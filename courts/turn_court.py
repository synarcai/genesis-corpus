#!/usr/bin/env python3
"""[СТОРОНЫ И ПОВОРОТЫ] — цепь сторон, пересчитанная судом по названным в ней поворотам.

Суд не пишет закона заново: он берёт его у дома (`turnforms`), где стороны объявлены
рядом по часовой стрелке, а поворот есть прибавление или вычитание единицы в этом ряду.
Всякое звено цепи «север → восток → юг» пересчитывается порознь, и поворот для него
берётся ИЗ ТОЙ ЖЕ СТРОКИ, а не из рамки.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ПОВОРОТ БЕРЁТСЯ ЛИШЬ СТРОЧНЫМ НАПИСАНИЕМ: «НАЛЕВО ЕСТЬ НЕ СТОРОНА СВЕТА, А ПОВОРОТ» есть
речь О слове, не поворачивающая никого. Прописная буква здесь несёт смысл.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: обе стороны ловушки обязаны быть
показаны, и несовпадение обязано перевешивать — одна сторона света из четырёх даёт
совпадение, три не дают.

    python3 courts/turn_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import turnforms  # noqa: E402 — дом, объявивший стороны и повороты

ИМЯ_СУДА = "turn"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"turn"})


def _судить(строка):
    return turnforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"СТОРОНЫ И ПОВОРОТЫ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(turnforms.РОДЫ)}, страниц {len(turnforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
