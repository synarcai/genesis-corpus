#!/usr/bin/env python3
"""[РУССКИЙ ПЕРЕВОД ЕДИНИЦ] — отношение спрашивается у графа заново.

Мир говорит «в двух часах 120 минут: в часе 60 минут, 60 × 2 = 120».
Суд не верит ни ответу, ни основанию. Он читает из строки ТОЛЬКО
косвенное числительное и две единицы, а всё прочее берёт сам:
отношение — у объявленного графа `units.РЁБРА`, счётные формы — у дома
единиц, предложные — у дома русской грамматики. Строка, у которой
сошлись все её числа и все её формы, истинна; строка, где не сошлось
хоть одно, ложна.

ЧЕТЫРЕ СВЕРКИ РАЗОМ, И НИ ОДНА НЕ ЛИШНЯЯ:
  · ЧИСЛИТЕЛЬНОЕ СЛОВОМ равно числу, стоящему в выкладке («двух» = 2);
  · ОТНОШЕНИЕ равно объявленному в графе (60, а не 50);
  · ИТОГ равен произведению отношения на счёт;
  · ФОРМА каждой единицы отвечает своему числу — «120 минут», но
    «2 минуты», и «в 21 дне», но «в 400 копейках».
Порча любой из четырёх ломает вердикт, и ни одна не прикрывает другую:
основание, сошедшееся с ответом, но разошедшееся с графом, есть самая
дорогая ложь корпуса — она учит верному способу на неверной мере.

ОТКАЗ СУДИТСЯ РАБОТОЙ, А НЕ ФОРМОЙ. «нет такого перевода: дом единиц
не объявляет ребра между метром и минутой» — суд спрашивает у графа, и
если ребро ТАМ ЕСТЬ, отказ ложен. Отказ, который отказывает напрасно, учит
молчать там, где ответ был; и он же — самая правдоподобная ложь, ибо
форма у него правильная.

ЧЕГО СУД НЕ ЧИТАЕТ: чужого рода. Образцы привязаны к зачину «сколько»
и к объявленным единицам; неузнанная строка есть (False, False).
"""

import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import rugram  # noqa: E402
import units  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# КОСВЕННОЕ ЧИСЛИТЕЛЬНОЕ ЧИТАЕТСЯ ОБРАТНО ПО ТОЙ ЖЕ ТАБЛИЦЕ ПАКЕТА,
# по какой мир его пишет: «двух» → 2. Второго списка здесь нет.
_ПАКЕТ = json.loads(
    (КОРЕНЬ / "tools/langpacks/ru.json").read_text(encoding="utf-8"))
ПО_КОСВЕННОМУ = {з: int(к)
                 for к, з in _ПАКЕТ["numeral_oblique"].items()}


def ключ(имя):
    return units.ФОРМЫ_ВСЕХ[имя][1][0]


def родительный_мн(имя):
    return units.ФОРМЫ_ВСЕХ[имя][1][2]


def предложный_ед(имя):
    формы = rugram.ПАРАДИГМЫ.get(ключ(имя))
    return формы[rugram.ПАДЕЖИ.index("предложный")] if формы else None


def предложный_мн(имя):
    return rugram.предложный_мн(ключ(имя))


def творительный(имя):
    формы = rugram.ПАРАДИГМЫ.get(ключ(имя))
    return формы[rugram.ПАДЕЖИ.index("творительный")] if формы else None


def предложный_по_счёту(имя, n):
    """Единственное при «…один», множественное иначе — законом ПАКЕТА."""
    ячейки = ("_ОДИН", "_ДВА", "_ПЯТЬ")
    один = units.ру_форма(ячейки, n) == ячейки[0]
    return предложный_ед(имя) if один else предложный_мн(имя)


# ОБРАТНЫЕ КАРТЫ СТРОЯТСЯ ИЗ ОБЪЯВЛЕННОГО, А НЕ ПЕРЕЧИСЛЯЮТСЯ. Всякая
# форма, какую мир может написать, узнаётся здесь обратно; форма,
# которой дома не объявили, не узнаётся вовсе — и строка с нею
# остаётся несудимой, а не ложной.
def _обратные_карты():
    """(предложные, родительные, творительные): форма → единица.

    ФОРМА, ПРИНАДЛЕЖАЩАЯ ДВУМ ЕДИНИЦАМ, НЕ ЧИТАЕТСЯ ОБРАТНО НИ К ОДНОЙ:
    выбрать за корпус значило бы догадаться. Такая форма выбывает из
    карты, и строка с нею честно немеет.

    СБОРКА ИДЁТ В ФУНКЦИИ, А НЕ НА ВЕРХНЕМ УРОВНЕ: первая редакция
    строила карты, а затем ПРИСВАИВАЛА ИМ ЖЕ отфильтрованные — три
    имени, определённых дважды, и суд затенения назвал их в первом же
    прогоне. Имя, присвоенное дважды, есть тихая потеря, даже когда
    вторая запись верна.
    """
    предл, родит, творит = {}, {}, {}
    for имя in units.ФОРМЫ_ВСЕХ:
        for карта, форма in ((предл, предложный_мн(имя)),
                             (предл, предложный_ед(имя)),
                             (родит, родительный_мн(имя)),
                             (творит, творительный(имя))):
            if форма is None:
                continue
            занято = форма in карта and карта[форма] != имя
            карта[форма] = None if занято else имя
    return tuple({ф: и for ф, и in к.items() if и}
                 for к in (предл, родит, творит))


ПО_ПРЕДЛОЖНОМУ, ПО_РОДИТЕЛЬНОМУ, ПО_ТВОРИТЕЛЬНОМУ = _обратные_карты()

С = r"[а-яё]+"
Ч = r"\d+"


def _вперёд(г):
    """Прямая рамка: числительное, отношение, итог и все формы."""
    if г["косв"] != г["косв2"] or г["пм"] != г["пм2"]:
        return False
    большая = ПО_ПРЕДЛОЖНОМУ.get(г["пм"])
    малая = ПО_РОДИТЕЛЬНОМУ.get(г["род_м"])
    if большая is None or малая is None:
        return False
    n_слово = ПО_КОСВЕННОМУ.get(г["косв"])
    отношение = units.отношение(большая, малая)
    if n_слово is None or отношение is None:
        return False
    n, r, итог = int(г["n"]), int(г["r"]), int(г["итог"])
    return (n == n_слово and r == int(отношение) and итог == r * n
            and int(г["итог2"]) == итог and int(г["r2"]) == r
            and г["пм"] == предложный_мн(большая)
            and г["пе"] == предложный_ед(большая)
            and г["форма_итог"] == units.рус(малая, итог)
            and г["форма_r"] == units.рус(малая, r))


def _назад(г):
    """Обратная рамка: то же отношение делением, и форма по счёту."""
    if г["где"] != г["где2"]:
        return False
    большая = ПО_РОДИТЕЛЬНОМУ.get(г["род_б"])
    малая = ПО_ПРЕДЛОЖНОМУ.get(г["где"])
    if большая is None or малая is None:
        return False
    отношение = units.отношение(большая, малая)
    if отношение is None:
        return False
    n, r, итог = int(г["n"]), int(г["r"]), int(г["итог"])
    return (r == int(отношение) and итог == r * n
            and int(г["итог2"]) == итог and int(г["итог3"]) == итог
            and int(г["r2"]) == r and int(г["n2"]) == n
            and г["где"] == предложный_по_счёту(малая, итог)
            and г["пе"] == предложный_ед(большая)
            and г["форма_б"] == units.рус(большая, n)
            and г["форма_r"] == units.рус(малая, r))


def _отказ(г):
    """РАБОТА ОТКАЗА: ребра и вправду нет, и названы те же единицы."""
    большая = ПО_ПРЕДЛОЖНОМУ.get(г["пм"])
    малая = ПО_РОДИТЕЛЬНОМУ.get(г["род_м"])
    если_б = ПО_ТВОРИТЕЛЬНОМУ.get(г["тв_б"])
    если_м = ПО_ТВОРИТЕЛЬНОМУ.get(г["тв_м"])
    if None in (большая, малая, если_б, если_м):
        return False
    return (units.отношение(большая, малая) is None
            and если_б == большая and если_м == малая
            and ПО_КОСВЕННОМУ.get(г["косв"]) is not None
            and г["пм"] == предложный_мн(большая))


ОБРАЗЦЫ = (
    (rf"^сколько (?P<род_м>{С}) в (?P<косв>{С}) (?P<пм>{С})\? в "
     rf"(?P<косв2>{С}) (?P<пм2>{С}) (?P<итог>{Ч}) "
     rf"(?P<форма_итог>{С}): в (?P<пе>{С}) (?P<r>{Ч}) "
     rf"(?P<форма_r>{С}), (?P<r2>{Ч}) × (?P<n>{Ч}) = "
     rf"(?P<итог2>{Ч})\.$", _вперёд),
    (rf"^сколько (?P<род_б>{С}) в (?P<итог>{Ч}) (?P<где>{С})\? в "
     rf"(?P<итог2>{Ч}) (?P<где2>{С}) (?P<n>{Ч}) (?P<форма_б>{С}): в "
     rf"(?P<пе>{С}) (?P<r>{Ч}) (?P<форма_r>{С}), (?P<итог3>{Ч}) ÷ "
     rf"(?P<r2>{Ч}) = (?P<n2>{Ч})\.$", _назад),
    (rf"^сколько (?P<род_м>{С}) в (?P<косв>{С}) (?P<пм>{С})\? нет "
     rf"такого перевода: дом единиц не объявляет ребра между "
     rf"(?P<тв_б>{С}) и (?P<тв_м>{С})\.$", _отказ),
)
ПРАВИЛА = tuple((re.compile(о), п) for о, п in ОБРАЗЦЫ)


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    for образец, проверить in ПРАВИЛА:
        м = образец.match(с)
        if м:
            return True, bool(проверить(м.groupdict()))
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"РУССКИЙ ПЕРЕВОД ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("РУССКИЙ ПЕРЕВОД ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"РУССКИЙ ПЕРЕВОД {поза}: {ложных} ложных из {судимых} "
          f"судимых ({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
