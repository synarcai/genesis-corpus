#!/usr/bin/env python3
"""[РУССКИЕ ГЛАГОЛЫ] — сказуемое и имя читаются, а не украшают счёт.

ПОДСАДКА СЛОВОМ НАШЛА, ЧТО ЭТОТ МИР НЕ ЧИТАЕТ НИКТО: 22 из 24 порченых
строк палата звала истиной. «юри ест 8 яблок» — имя искажено, счёт цел;
«где лежа яблоки? яблоки лежат на столе» — глагол искажён. Суд
согласования читал счётную форму «8 яблок» и был прав о ней; суд
эпизода брал любое слово из букв за имя и был слеп по устройству.
СУДЫ ПОКАЗОВ ЧИТАЛИ ЧИСЛА, А СЛОВА У НИХ БЫЛИ ДЕКОРАЦИЕЙ.

СУД ЧИТАЕТ ТО, ЧТО ГЕНЕРАТОР ОБЪЯВИЛ — И ТОЛЬКО ЭТО. Таблицы лиц,
глаголов, падежных форм и мест берутся ИЗ ГЕНЕРАТОРА мира, а не
переписываются здесь вторично: два списка одного разошлись бы в тот же
день (М-110). Имя обязано быть объявленным лицом, глагол — объявленной
формой ТОГО ЖЕ времени, родовое окончание прошедшего — окончанием ЭТОГО
лица, вещь — формой rugram при ЭТОМ числе, а числа эпизода — сходиться.

ГРАНИЦА ОТКАЗА: строка, не подходящая ни под одну форму этого мира, суду
не подсудна — он молчит. Строка формы мира с необъявленным словом ЛЖЁТ.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import rugram  # noqa: E402
from actors import Слой  # noqa: E402
import gen_genesis_ruverbs as Г  # noqa: E402
from genesis import worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ИМЕНА = {л[0]: л for л in Г.ЛИЦА}
РОД_ИМЕНИ = {л[1]: л for л in Г.ЛИЦА}
НАСТ = {н: вещь for н, _, вещь in Г.ГЛАГОЛЫ}
ПРОШ = {п: вещь for _, п, вещь in Г.ГЛАГОЛЫ}
С = r"([А-ЯЁа-яё]+)"   # обе кассы: имя лица с заглавной (пакет, 05.09) — судимых было 758, стало 193
ЧИСЛО = r"(\d+)"
НАСТОЯЩЕЕ = re.compile(rf"^{С} {С} {ЧИСЛО} {С}\.$")
ВОПРОС = re.compile(rf"^{С} {С} {ЧИСЛО} {С}\. сколько {С} {С} {С}\? "
                    rf"{С} {С} {ЧИСЛО} {С}\.$")
АНАФОРА = re.compile(rf"^у {С} было {ЧИСЛО} {С}\. {С} {С} {ЧИСЛО} {С}\. "
                     rf"у {С} осталось {ЧИСЛО} {С}\.$")
МНОЖЕСТВО = re.compile(rf"^{С} {С} ((?:[а-яё]+ ){{1,2}}[а-яё]+)\.$")
ГДЕ = re.compile(rf"^где {С} {С}\? {С} {С} ((?:[а-яё]+ ){{1,2}}[а-яё]+)\.$")
МЕСТА = {(в, мн): места for в, _, мн, места in Г.МНОЖЕСТВА}
ЕД = {в: ед for в, ед, _, _ in Г.МНОЖЕСТВА}


def _ключ_множества(вещи):
    """Ключ вещи по её именительному множественного — как пишет генератор."""
    for к, _, _, _ in Г.МНОЖЕСТВА:
        if rugram.именительный_мн(к) == вещи:
            return к
    return None


def _глагол(слово, имя):
    """Ключ вещи, если слово — объявленная форма при ЭТОМ лице, иначе None."""
    if слово in НАСТ:
        return НАСТ[слово]
    род = ИМЕНА[имя][4]
    if род and слово.endswith(род) and слово[:-len(род)] in ПРОШ:
        return ПРОШ[слово[:-len(род)]]
    if not род and слово in ПРОШ:
        return ПРОШ[слово]
    return None


def _факт(имя, глагол, n, вещь):
    if имя not in ИМЕНА:
        return False
    ключ = _глагол(глагол, имя)
    if ключ is None:
        return False
    return вещь == rugram.форма(ключ, int(n))


def судить(строка, слой=None):
    с = строка.strip()
    m = НАСТОЯЩЕЕ.match(с)
    if m:
        имя, гл, n, вещь = m.groups()
        if имя not in ИМЕНА:
            # ЧУЖОЕ ЛИЦО: в мире, объявившем деятелей лицами пакета, — ложь
            # записи; иначе — чужая рамка, и суд молчит (М-131, дом имён).
            return (True, False) if слой is not None and слой.лица("ru") else (False, True)
        return True, _факт(имя, гл, n, вещь)
    m = ВОПРОС.match(с)
    if m:
        имя, гл, n, вещь, чего, гл2, имя2, имя3, гл3, n2, вещь2 = m.groups()
        if имя not in ИМЕНА:
            return (True, False) if слой is not None and слой.лица("ru") else (False, True)
        ключ = _глагол(гл, имя)
        return True, (ключ is not None and _факт(имя, гл, n, вещь)
                      and чего == Г.РОДИТЕЛЬНЫЙ.get(ключ)
                      and гл2 == гл == гл3 and имя2 == имя == имя3
                      and n2 == n and вещь2 == вещь)
    m = АНАФОРА.match(с)
    if m:
        (род_имени, было, вещь1, он, отдал, ушло, вещь2,
         него, стало, вещь3) = m.groups()
        лицо = РОД_ИМЕНИ.get(род_имени)
        if лицо is None:
            # НЕОБЪЯВЛЕННОЕ ЛИЦО ЕСТЬ ЧУЖАЯ РАМКА, А НЕ ЛОЖЬ. Мир историй
            # говорит той же анафорой о Диме и Лене; суд, назвавший их
            # ложью, забрал 688 честных строк — тот же шрам, что у суда
            # поверхностей (440) и ограды (2607). Свои лица — судим,
            # чужие — молчим; порча своего имени («у мари») даёт
            # несудимую строку, и ворота её не пропустят.
            return False, True
        _, _, он_она, него_неё, род = лицо
        ключ = next((к for к, ф in Г.ВИНИТЕЛЬНЫЙ.items()
                     if rugram.форма(к, int(было)) == вещь1), None)
        # РАМКА СВОЯ, ЛИШЬ КОГДА ВСЕ ТРИ ОПОРЫ ОБЪЯВЛЕНЫ: лицо, вещь и
        # МЕСТОИМЕНИЕ. Мир историй говорит о той же Вере, но именем
        # вместо местоимения и о марках, которых здесь нет, — 132
        # честные строки были названы ложью. Чужая опора — чужая рамка;
        # суд молчит, а ложью зовёт только расхождение ЧИСЛА, родового
        # окончания и формы вещи при своей рамке.
        if ключ is None or он != он_она or него != него_неё:
            return False, True
        return True, (отдал == "отдал" + род
                      and int(было) - int(ушло) == int(стало)
                      and вещь2 == Г._вещь(ключ, int(ушло))
                      and вещь3 == rugram.форма(ключ, int(стало)))
    m = ГДЕ.match(с)
    if m:
        вещи, гл, вещи2, гл2, где = m.groups()
        ключ = _ключ_множества(вещи)
        if ключ is None:
            return False, True
        мн = next(мн for к, _, мн, _ in Г.МНОЖЕСТВА if к == ключ)
        return True, (гл == гл2 == мн and вещи2 == вещи
                      and где in МЕСТА[(ключ, мн)])
    m = МНОЖЕСТВО.match(с)
    if m:
        вещи, гл, где = m.groups()
        ключ = _ключ_множества(вещи)
        if ключ is None:
            return False, True
        мн = next(мн for к, _, мн, _ in Г.МНОЖЕСТВА if к == ключ)
        return True, гл == мн and где in МЕСТА[(ключ, мн)]
    return False, True


def main():
    ложных = судимых = файлов = 0
    for путь in worlds():
        if not путь.exists():
            continue
        файлов += 1
        for с in путь.read_text(encoding="utf-8").splitlines():
            судимо, истинно = судить(с)
            if not судимо:
                continue
            судимых += 1
            if not истинно:
                ложных += 1
                if ложных <= 6:
                    print(f"  ЛОЖЬ {путь.name}: {с[:90]}")
    if not файлов:
        print("РУССКИЕ ГЛАГОЛЫ ОТКАЗ: обход пуст")
        return 2
    поза = "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL"
    print(f"РУССКИЕ ГЛАГОЛЫ {поза}: {ложных} ложных из {судимых} судимых "
          f"({файлов} файлов, рубеж {ЛОЖНЫХ_РУБЕЖ})")
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
