#!/usr/bin/env python3
"""[ДВА СМЫСЛА ДЕЛЕНИЯ] — одно равенство и два вопроса, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`divsenseforms`), где рамки и числа объявлены
одной таблицей. Подмена частного, произведения и самого РАЗЛИЧЕНИЯ ловится машинально: оба
смысла пересчитываются числами страницы, а не принимаются на слово.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЛОВУШКА ПРОВЕРЯЕТСЯ КАК ЛОВУШКА: на странице «два смысла» делитель и частное обязаны РАЗОЙТИСЬ —
иначе оба смысла совпали бы, и показывать было бы нечего.

ЧИСЛО ОТВЕТА НЕ ЕСТЬ ОТВЕТ: ответ есть число С ВЕЩЬЮ, и деление различается именно вещью.
Счётные формы вещей взяты у языка, и потому этот дом читают ещё и счётные суды двух языков.

ЭТОТ ДОМ ЧИТАЕТСЯ И СУДОМ АРИФМЕТИКИ: его страницы написаны так, что слова стоя́т до двоеточия, а
равенства после, — и потому каждая проверена ДВАЖДЫ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/divsense_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import divsenseforms  # noqa: E402 — дом, объявивший два смысла деления

ИМЯ_СУДА = "divsense"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"divsense"})


def _судить(строка):
    return divsenseforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ДВА СМЫСЛА ДЕЛЕНИЯ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(divsenseforms.РОДЫ)}, страниц {len(divsenseforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
