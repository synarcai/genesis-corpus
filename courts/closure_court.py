#!/usr/bin/env python3
"""[ЗАМКНУТОСТЬ] — останется ли итог там же, где слагаемые, пересчитано судом.

Суд не пишет закона заново: он берёт его у дома (`closureforms`), где множества, действия
и разложения объявлены одной таблицей. Подмена ЛЮБОГО числа ловится машинально — сумма,
произведение, частное и РАЗБОР по делителю пересчитываются порознь.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЦЕПЬ ЧИТАЕТСЯ ЦЕЛИКОМ, А НЕ ПО ЗВЕНЬЯМ: «6 + 4 = 2 × 5 = 10» связывает три числа разом,
и одиночный признак суммы прочёл бы здесь «6 + 4 = 2» и назвал бы честную страницу ложью.

    ПРИЗНАК, ЧИТАЮЩИЙ ЗВЕНО ЦЕПИ КАК ЦЕЛОЕ РАВЕНСТВО, НАХОДИТ ЛОЖЬ В СВОЁМ ЖЕ ЧТЕНИИ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним
словом, суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/closure_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import closureforms  # noqa: E402 — дом, объявивший замкнутость

ИМЯ_СУДА = "closure"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"closure"})


def _судить(строка):
    return closureforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ЗАМКНУТОСТЬ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(closureforms.РОДЫ)}, страниц {len(closureforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
