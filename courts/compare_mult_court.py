ПРАВИЛА = tuple((re.compile(о), п) for о, п in ОБРАЗЦЫ)


def судить(строка):
    """(судимо, истинно) для строки — или для ПОКАЗА из нескольких.

    ПОКАЗ МОЖЕТ ГОВОРИТЬ НЕСКОЛЬКИМИ СТРОКАМИ, и в этом мире он так и
    говорит: считаемая рамка и меряемая стоят в ОДНОМ показе, чтобы
    перестановка прохода не развела их по разным концам слоя. Палата
    читает корпус построчно и о многострочном показе не знает — а
    всякий, кто спросит суд о показе ЦЕЛИКОМ, получал молчание, и
    молчание это выглядело как чистота: суд, не читающий своего слоя,
    объявит ноль лжи на пустом множестве судимых.

    ВЕРДИКТ О ПОКАЗЕ СВОДИТСЯ ИЗ ВЕРДИКТОВ О СТРОКАХ, и ложь весит
    больше немоты: показ с ложной строкой ЛОЖЕН (её надо назвать), а
    показ с немой строкой НЕСУДИМ (дыра есть дыра, и ворота записи не
    пропустят её ни при каком числе честных соседок).
    """
    if "\n" in строка:
        вердикты = [судить(ч) for ч in строка.split("\n") if ч.strip()]
        if not вердикты:
            return False, False
        if any(су and not ис for су, ис in вердикты):
            return True, False
        return all(су for су, _ in вердикты), True
    с = строка.strip()
    if not с:
        return False, False
    for образец, проверить in ПРАВИЛА:
        м = образец.match(с)
        if м is None:
            continue
        вердикт = проверить(м)
        if вердикт is None:
            return False, False
        return True, bool(вердикт)
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"КРАТНОЕ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("КРАТНОЕ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(
                            f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"КРАТНОЕ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
