#!/usr/bin/env python3
"""[СУД ЦЕПИ СВИДЕТЕЛЬСТВ] — цепь пройдена заново; МИР ЗАМКНУТ.

Страница мира (`tools/liarchain.py`) есть цепь: первый объявлен правдивым или лживым,
каждый следующий говорит О ПРЕДЫДУЩЕМ, и вопрос — правдив ли названный.

    СВИДЕТЕЛЬ ПРАВДИВ РОВНО ТОГДА, КОГДА ЕГО СВИДЕТЕЛЬСТВО СОВПАЛО С ДЕЛОМ. Это не
    правило записи, а правило ДОВЕРИЯ, и оно не выводится из умения снимать отрицания:
    «не не истина» и «Вера говорит, что Аня лжёт» считаются одинаково и учат разному.

Суд проходит цепь сам и не верит ни ответу страницы, ни её проходу: сверяются ОБА. Три
строгости, и каждая куплена делом:

    ЦЕПЬ ОБЯЗАНА БЫТЬ ЦЕПЬЮ — всякий свидетель говорит о ПРЕДЫДУЩЕМ; страница, где
        свидетель говорит через голову, есть ложь о строении, а не о правде;
    ЛИЦО ОБЯЗАНО СТОЯТЬ В ОБЪЯВЛЕННОМ РЯДУ ПАКЕТА — о слове вне ряда суд МОЛЧИТ, ибо
        такая строка ему не принадлежит (закон 16.09: лицо есть объявление пакета, а не
        форма буквы);
    ПРОХОД ОБЯЗАН СОЙТИСЬ ДО СЛОВА — ответ без прохода учит называть исход, а не идти по
        цепи, и проверить его нечем, кроме как поверив ему.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import liarchain as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"liarchain"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_liarchain.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_liarchain.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_liarchain.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ЦЕПЬ СВИДЕТЕЛЬСТВ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
