#!/usr/bin/env python3
"""[СУД СОВПАДЕНИЯ И ПРИЧИНЫ] — числа и разности проверены; О ПРИЧИНЕ СУД НЕ СУДИТ.

Страница мира (`tools/cooccur.py`) есть два числа до и после, их разности и ОТКАЗ назвать
причину. Суд берёт из записи четыре числа, считает разности сам, смотрит направление
движения — и требует, чтобы сказанное на странице сошлось с этим.

    ЧИСЛА ГОВОРЯТ, ЧТО БЫЛО, И МОЛЧАТ О ТОМ, ПОЧЕМУ. «Оба выросли» есть ФАКТ, и он
    проверяется вычитанием. «Одно подняло другое» есть ПРИЧИНА, и из тех же чисел она не
    выводится ничем.

И вот граница самого прибора, объявленная вслух:

    СУД СЧИТАЕТ ФАКТЫ И НЕ СУДИТ ПРИЧИН. Отказ он сверяет с ОБЪЯВЛЕННЫМ словом и не решает,
    верен ли он: причину не проверить вычитанием — на то она и причина, — и прибор,
    взявшийся её проверять, лгал бы о собственной силе.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import cooccur as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"cooccur"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_cooccur.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_cooccur.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_cooccur.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"СОВПАДЕНИЕ И ПРИЧИНА {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
