#!/usr/bin/env python3
"""СУД ПРОЦЕНТОВ: доля ПЕРЕСЧИТЫВАЕТСЯ, а не сверяется со строкой.

Мир процентов говорит пятью родами — доля, вопрос, конверсия, обратная
задача, рост и убыль, — и все пять суть одно умножение с делением,
надетое на разные вопросы. Суд не верит ни одному написанному числу:
он берёт процент и целое из показа и СЧИТАЕТ долю заново своим счётом,
после чего сверяет с нею объявленный ответ. Сличение строки со строкой
поймало бы опечатку и не поймало бы неверного закона; пересчёт ловит
второе, а первое ловит заодно.

ЦЕЛОСТЬ ДОЛИ ЕСТЬ ЧАСТЬ УТВЕРЖДЕНИЯ, А НЕ УСЛОВИЕ ПОКАЗА. «3% от 50 —
это 2» правдоподобно на глаз и ложно по существу: сто пятьдесят сотых
не есть целое, и такому равенству неоткуда взяться. Суд зовёт это
ЛОЖЬЮ, а не молчит: округление, сказанное равенством, есть самая
убедительная ложь, какую способен нести корпус процентов.

СОГЛАСОВАНИЕ ЧИСЛА С ФОРМОЙ ТОЖЕ СУДИМО. «двадцать процентов», но «два
процента» и «один процент»: форма выбрана СЧЁТОМ, и подмена формы есть
подмена утверждения о языке, а не описка. Закон согласования берётся из
пакета русского (`langpacks/ru.json`), формы объявлены здесь ВТОРОЙ
РУКОЙ — тот же факт, сказанный отдельно от генератора; расхождение
домов делает строку ложной, а ворота записи ложную строку не
пропускают.

ЧУЖОЙ РОД НЕ ЧИТАЕТСЯ. Образцы узки и привязаны к зачину предложения, а
вопросная поверхность ловится ЦЕЛИКОМ — вместе со своим ответом. Слой
записи отвечает на тот же вопрос иначе («what is 20% of 40? it is 8»),
и это его род, не наш: суд поверхностей однажды объявил ложью четыреста
сорок честных строк чужих миров ровно потому, что ловил всякое «what
is …?». Строка, которую этот суд не узнал, есть (False, False) — и
молчание тут дешевле любого правдоподобного приговора.

ИМЯ ДОЛИ ОБЯЗАНО НАЗЫВАТЬ ИМЕННО ЭТУ ДОЛЮ. «половина — это 25%»
построено из объявленных слов и ложно отношением между ними; членство
имени в списке долей не есть соответствие величине, и проверяется
именно величина.
"""

import pathlib
import re
import sys
from fractions import Fraction

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import numerals  # noqa: E402
import units  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402
from plural import by_count  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# ФОРМЫ СЧЁТА, ЗАПИСАННЫЕ ВТОРОЙ РУКОЙ. Закон, по которому счёт выбирает
# форму, живёт в пакете языка и берётся оттуда; здесь названы лишь сами
# формы — и названы отдельно от генератора, чтобы правка в одном доме и
# не в другом стала видна приговором, а не осталась незамеченной.
ФОРМЫ_ПРОЦЕНТА = ("процент", "процента", "процентов")
ФОРМЫ_СОТОЙ = ("сотая", "сотых", "сотых")

# ИМЯ ДОЛИ И ЕЁ ВЕЛИЧИНА — ВТОРОЙ РУКОЙ И ШИРЕ, ЧЕМ ПОКАЗЫВАЕТ СЛОЙ:
# треть здесь объявлена, хотя целым процентом не выражается. Суд обязан
# звать ложью «треть — это 33%», а не молчать о ней: молчание о знакомом
# имени с неверной величиной есть дыра ровно того рода, ради которого
# суд написан.
ДОЛИ_EN = {
    "one half": Fraction(1, 2),
    "one third": Fraction(1, 3),
    "one quarter": Fraction(1, 4),
    "three quarters": Fraction(3, 4),
    "one fifth": Fraction(1, 5),
    "two fifths": Fraction(2, 5),
    "one tenth": Fraction(1, 10),
    "one twentieth": Fraction(1, 20),
    "one hundredth": Fraction(1, 100),
}
ДОЛИ_RU = {
    "половина": Fraction(1, 2),
    "треть": Fraction(1, 3),
    "четверть": Fraction(1, 4),
    "три четверти": Fraction(3, 4),
    "пятая часть": Fraction(1, 5),
    "две пятых": Fraction(2, 5),
    "десятая часть": Fraction(1, 10),
    "двадцатая часть": Fraction(1, 20),
    "сотая часть": Fraction(1, 100),
}
ТАБЛИЦЫ = {"en": numerals.таблица("en"), "ru": numerals.таблица("ru")}


# ---------------------------------------------------------------- счёт

def доля(процент, целое):
    """Часть целого, пересчитанная СУДОМ, или None — доля не целая."""
    произведение = процент * целое
    return произведение // 100 if произведение % 100 == 0 else None


def ч(м, *номера):
    """Целые из НАЗВАННЫХ скобок — не из всей строки.

    Число, стоящее в записи БУКВОЙ ЗАКОНА («сотая часть», «100» в самом
    слове «процент»), не есть величина показа, и суд обязан брать ровно
    то, что назвал образцом.
    """
    return [int(м.group(i)) for i in номера]


# ------------------------------------------------------------ ПРОВЕРКИ
# Проверка отвечает True, False — или None, если форма её образца
# совпала, а РОД оказался чужим (незнакомое имя доли, число, которого
# язык не называет). None есть отказ судить, и он честнее приговора.

def _глиф(м):
    п, ц, д = ч(м, 1, 2, 3)
    return доля(п, ц) == д


def _словом_en(м):
    ц, д = ч(м, 2, 3)
    п = numerals.прочесть(м.group(1), ТАБЛИЦЫ["en"])
    if п is None:
        return None
    return доля(п, ц) == д


def _словом_ru(м):
    ц, д = ч(м, 3, 4)
    п = numerals.прочесть(м.group(1), ТАБЛИЦЫ["ru"])
    if п is None:
        return None
    # ФОРМА ИМЕНИ ЕСТЬ УТВЕРЖДЕНИЕ О ЯЗЫКЕ, и она судится наравне со
    # счётом: «два процентов» ложно, даже когда доля сошлась.
    if м.group(2) != units.ру_форма(ФОРМЫ_ПРОЦЕНТА, п):
        return False
    return доля(п, ц) == д


def _вопрос(м):
    п1, ц1, п2, ц2, д = ч(м, 1, 2, 3, 4, 5)
    # ОТВЕТ ОБЯЗАН ОТВЕЧАТЬ НА СВОЙ ВОПРОС: пара, разошедшаяся числами,
    # верна по счёту и лжёт как пара — и поймать это может только сверка
    # спрошенного с отвечающим.
    return п1 == п2 and ц1 == ц2 and доля(п2, ц2) == д


def _сотые_en(м):
    п, н = ч(м, 1, 2)
    return п == н and м.group(3) == by_count(н, "hundredths")


def _сотые_ru(м):
    п, н = ч(м, 1, 2)
    return п == н and м.group(3) == units.ру_форма(ФОРМЫ_СОТОЙ, н)


def _имя_доли(м, имена):
    знач = имена.get(м.group(1).lower())
    if знач is None:
        return None          # ЧУЖОЕ ИМЯ — ЧУЖОЙ РОД, И НЕ НАШ ПРИГОВОР
    return знач * 100 == int(м.group(2))


def _имя_доли_en(м):
    return _имя_доли(м, ДОЛИ_EN)


def _имя_доли_ru(м):
    return _имя_доли(м, ДОЛИ_RU)


def _обратное(м):
    д, п, ц = ч(м, 1, 2, 3)
    return доля(п, ц) == д


def _рост(м):
    ц, п, итог = ч(м, 1, 2, 3)
    д = доля(п, ц)
    return д is not None and ц + д == итог


def _убыль(м):
    ц, п, итог = ч(м, 1, 2, 3)
    д = доля(п, ц)
    return д is not None and ц - д == итог


Ч = r"(\d+)"
# ОБРАЗЕЦ ПРИВЯЗАН К ЗАЧИНУ ПРЕДЛОЖЕНИЯ И ЛОВИТ ЕГО ЦЕЛИКОМ. Общий
# зачин («X is N%.») стоит ПОСЛЕДНИМ: поставленный первым, он перехватил
# бы частные роды, как определение перехватывало часть в суде связок.
ОБРАЗЦЫ = (
    (rf"^{Ч}% of {Ч} is {Ч}\.$", _глиф),
    (rf"^{Ч}% от {Ч} — это {Ч}\.$", _глиф),
    (rf"^(.+?) percent of {Ч} is {Ч}\.$", _словом_en),
    (rf"^(.+?) (процент|процента|процентов) от {Ч} — это {Ч}\.$",
     _словом_ru),
    (rf"^what is {Ч}% of {Ч}\? {Ч}% of {Ч} is {Ч}\.$", _вопрос),
    (rf"^сколько будет {Ч}% от {Ч}\? {Ч}% от {Ч} — это {Ч}\.$",
     _вопрос),
    (rf"^{Ч}% is {Ч} (hundredth|hundredths)\.$", _сотые_en),
    (rf"^{Ч}% — это {Ч} (сотая|сотых)\.$", _сотые_ru),
    (rf"^{Ч} is {Ч}% of {Ч}\.$", _обратное),
    (rf"^{Ч} — это {Ч}% от {Ч}\.$", _обратное),
    (rf"^{Ч} grown by {Ч}% is {Ч}\.$", _рост),
    (rf"^{Ч}, выросшее на {Ч}%, — это {Ч}\.$", _рост),
    (rf"^{Ч} cut by {Ч}% is {Ч}\.$", _убыль),
    (rf"^{Ч}, уменьшенное на {Ч}%, — это {Ч}\.$", _убыль),
    (rf"^(.+?) is {Ч}%\.$", _имя_доли_en),
    (rf"^(.+?) — это {Ч}%\.$", _имя_доли_ru),
)
ПРАВИЛА = tuple((re.compile(о), п) for о, п in ОБРАЗЦЫ)


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    for образец, проверить in ПРАВИЛА:
        м = образец.match(с)
        if м is None:
            continue
        вердикт = проверить(м)
        if вердикт is None:
            return False, False
        return True, bool(вердикт)
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ПРОЦЕНТЫ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ПРОЦЕНТЫ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(
                            f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ПРОЦЕНТЫ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
