#!/usr/bin/env python3
"""[ЗАКОН СЧЁТНОЙ ФОРМЫ] — согласие страницы с таблицами домов языка, пересчитанное судом.

Суд не пишет закона заново: формы объявлены домами языка (`rugram.СЧЁТНЫЕ`, `plgram.СЧЁТНЫЕ`),
а правило выбора — пакетами (`count_agreement`). Судится СОГЛАСИЕ: всякая пара «число и имя»
на странице обязана быть верной формой хоть в одном объявленном языке.

    СУД, СВЕРЯЮЩИЙ ФОРМУ С ТАБЛИЦЕЙ, НЕ ЗНАЕТ ЯЗЫКА И НЕ ДОЛЖЕН ЗНАТЬ: он знает ТО, ЧТО ДОМ
    ОБЪЯВИЛ, и ровно этим и силён.

ПОЧЕМУ «ХОТЬ В ОДНОМ», А НЕ «В СВОЁМ». Сердце дома — страница, где ОДНО число показано двумя
языками разом: «21 книга по-русски, но 21 książek по-польски». Суд, требующий одного языка на
страницу, назвал бы её ложью — и тем запретил бы дому сказать то, ради чего он построен.

    python3 courts/countlaw_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import countlawforms  # noqa: E402 — дом, объявивший закон счётной формы

ИМЯ_СУДА = "countlaw"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"countlaw"})


def _судить(строка):
    return countlawforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ЗАКОН СЧЁТНОЙ ФОРМЫ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(countlawforms.РОДЫ)}, страниц {len(countlawforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
