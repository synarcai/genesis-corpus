#!/usr/bin/env python3
"""[СОГЛАСОВАНИЕ ПО ЧИСЛУ] — счёт «один» рядом с множественной формой.

ПОВОД, ПРОЖИТЫЙ 01.09: слой сравнения показывал «ben has 1 eggs more
than elena», и таких показов по дому набралось 1700 ПРИ НУЛЕ ВЕРНЫХ.
Единственного числа после «1» в GENESIS не существовало вовсе. По
закону повтора организм ВЛАДЕЕТ тем, что видел дважды, — значит он
покупал неверное согласование как норму и не видел верного никогда.

ПРИБОР СЛЕП К АНГЛИЙСКОМУ, И В ЭТОМ ЕГО СИЛА. Он не знает ни правил
языка, ни списка существительных: судит КОРПУС САМИМ КОРПУСОМ.
  · МНОЖЕСТВЕННАЯ ФОРМА — та, что корпус сам ставит после числа
    БОЛЬШЕ ЕДИНИЦЫ (не реже закона повтора);
  · ПРЕДМЕТ — слово, встающее в конце счётной фразы («… ЧИСЛО слово.»),
    тоже не реже закона. Этот второй ценз необходим: без него
    «1 more», «1 fewer», «1 is», «1 remainder» читались бы находками,
    а они не существительные. Ложных срабатываний было 504 из 2204.
  · НАХОДКА — «1 слово», где слово прошло оба ценза.

Оттого прибор ГОДИТСЯ ДЛЯ ЛЮБОГО ЯЗЫКА, где множественность метится
формой: он спросит у текста, а не у грамматики.

ЧЕГО ПРИБОР НЕ ВИДИТ, НАЗВАНО ЧЕСТНО:
  · языки, где счёт «один» законно берёт множественное (арабский
    двойственный род, и подобные) — там рубеж просто не опустится
    до нуля, и это будет честным ЗНАНИЕМ, а не поломкой;
  · согласование по роду и падежу — иной род дефекта, иной прибор;
  · числительное СЛОВОМ («one egg») — здесь судится цифра, потому
    что порча родилась в порождённых показах, а они пишут цифрой.

ОБХОД: миры МАНИФЕСТА, ибо GENESIS есть манифест. Поза `--all` берёт
все датасеты лентой — там живут сборки, где слои повторены, и
складывать их с мирами значило бы считать одну порчу дважды.
Явные пути в доводах судятся лентой: рубеж принадлежит корпусу, а не
случайной горсти файлов.
"""

# ПУСТОЙ-ОБХОД: no-such-corpus-file
import json
import pathlib
import re
import sys

# ЗАКОН ПОВТОРА ЖИВЁТ В КРЕМНИИ: один случай есть случайность (D7),
# два владеют фактом. Прибор не смеет носить свою копию числа.
# ГРАНИЦА: назван ОДИН крейт — synarc-kan, потому что закон повтора
# объявлен там и только там (`LAW_OF_REPETITION` в его lib.rs), и
# прибор обязан читать его из кремния, а не носить копию. Если закон
# однажды переедет, отказ кодом 2 назовёт это вслух в тот же прогон —
# граница сторожит сама себя.
КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import Unreadable, worlds  # noqa: E402

# ПУТЬ ОТ КОРНЯ, А НЕ ОТ ТЕКУЩЕГО КАТАЛОГА: прибор с относительным
# путём отвечает из репозитория и ОТКАЗЫВАЕТ отовсюду ещё — а суд
# арифметики рядом работал откуда угодно. Два судьи одного корпуса
# разной прочности есть несогласованность, даже когда оба честны.
# КРЕМНИЙ ЖИВЁТ В АРХИТЕКТУРЕ, А НЕ В КОРПУСЕ, и разрешается тем же
# объявленным внешним корнем, что и прозаические миры: закон повтора
# принадлежит организму, корпус лишь ему подчиняется.
def _кремний():
    свой = КОРЕНЬ / "rust/crates/synarc-kan/src/lib.rs"
    if свой.is_file():
        return свой
    from genesis import external_root
    return external_root() / "rust/crates/synarc-kan/src/lib.rs"


КРЕМНИЙ = _кремний()

# РУБЕЖ-ДОЛГА: РАССОГЛАСОВАНО_РУБЕЖ = 0
# Рубеж поставлен ПО ИЗМЕРЕННОМУ, а не по глазу: миры
# манифеста вылечены до нуля в тот же такт, что и прибор.
РАССОГЛАСОВАНО_РУБЕЖ = 0

СЧЁТ = re.compile(r"\b(\d+) ([a-z]+)\b")
ПРЕДМЕТНО = re.compile(r"\b(\d+) ([a-z]+)[.,]")
ЕДИНИЦА = re.compile(r"\b1 ([a-z]+)\b")


def закон_повтора():
    """Отказ, а не догадка: без кремния прибор не судит."""
    try:
        текст = КРЕМНИЙ.read_text(encoding="utf-8")
    except OSError as беда:
        print(f"СОГЛАСОВАНИЕ ОТКАЗ: кремний не читается ({беда})")
        sys.exit(2)
    м = re.search(r"LAW_OF_REPETITION\s*:\s*\w+\s*=\s*(\d+)", текст)
    if not м:
        print("СОГЛАСОВАНИЕ ОТКАЗ: LAW_OF_REPETITION не найден в кремнии")
        sys.exit(2)
    return int(м.group(1))


def чаще(счётчик, закон):
    return {с for с, к in счётчик.items() if к >= закон}


def _служебные():
    """Function words and question words declared by the packs — never count nouns.

    THE COURT READS «4 weg» AS FOUR OF A THING. Dutch «gaf er 4 weg» carries a
    separable particle after the number, Dutch «5 op» a preposition; the text-derived
    dictionary took them for nouns and called «1 weg» a disagreement 96 times (05.09,
    the links world). A pack declares its function words; the court reads them.
    """
    import json
    вон = set()
    for ф in sorted((КОРЕНЬ / "tools" / "langpacks").glob("*.json")):
        try:
            п = json.loads(ф.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for ключ in ("function_words", "sentence_openers"):
            вон |= {str(с).lower() for с in (п.get(ключ) or ())}
        вон |= {str(с).lower() for с in ((п.get("ask_words") or {}).get("words") or ())}
    return frozenset(вон)


СЛУЖЕБНЫЕ = _служебные()


def _по_языкам():
    """language → its declared function words: the witness of a line's language."""
    import json
    вон = {}
    for ф in sorted((КОРЕНЬ / "tools" / "langpacks").glob("*.json")):
        try:
            п = json.loads(ф.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        слова = {str(с).lower() for с in (п.get("function_words") or ())}
        if слова and п.get("script", "latin") in ("latin", None):
            вон[ф.stem] = frozenset(слова)
    return вон


ПО_ЯЗЫКАМ = _по_языкам()
_СЛОВО = re.compile(r"[a-z]+")


def язык_строки(строка):
    """The pack whose declared function words the line carries most; None on a tie."""
    слова = _СЛОВО.findall(строка)
    if not слова:
        return None
    счёт = {я: sum(1 for с in слова if с in набор) for я, набор in ПО_ЯЗЫКАМ.items()}
    лучший = max(счёт.values()) if счёт else 0
    if лучший == 0:
        return None
    победители = [я for я, к in счёт.items() if к == лучший]
    return победители[0] if len(победители) == 1 else None


def судить(путь, закон):
    """(рассогласовано, верно, порча) — числом и поимённо.

    AGREEMENT IS JUDGED WITHIN ONE LANGUAGE. A world of nine languages carries
    Italian «9 carte» (a plural) and French «1 carte» (a singular) in one file, and
    the single text-wide dictionary read the French as a disagreement of the Italian
    (05.09, the links world: 186 accusations, all of this kind or of particles).
    Every line is assigned to the pack whose declared function words it carries most;
    the dictionaries and the verdicts are kept per language, and a line of no
    decidable language contributes nothing.
    """
    полный = путь.read_text(encoding="utf-8", errors="replace").lower()
    итого_порча, итого_верно = {}, 0
    по_языку = {}
    for строка in полный.splitlines():
        я = язык_строки(строка)
        if я is None:
            continue
        по_языку.setdefault(я, []).append(строка)
    for я, строки in по_языку.items():
        рассогласовано, верно, порча = _судить_текст("\n".join(строки), закон)
        итого_верно += верно
        for слово, к in порча.items():
            итого_порча[слово] = итого_порча.get(слово, 0) + к
    return sum(итого_порча.values()), итого_верно, итого_порча


def _судить_текст(текст, закон):
    множественные = {}
    for число, слово in СЧЁТ.findall(текст):
        if int(число) > 1 and слово not in СЛУЖЕБНЫЕ:
            множественные[слово] = множественные.get(слово, 0) + 1
    # ОБА ЦЕНЗА СВИДЕТЕЛЬСТВУЮТ ОБ ОДНОМ — О СЧЁТЕ БОЛЬШЕ ЕДИНИЦЫ.
    #
    # ЯЗЫК С ГЛАГОЛОМ В КОНЦЕ ПРОБИЛ ЭТОТ ЦЕНЗ 90 РАЗ. Немецкое «eine
    # Zahl ist durch eine andere teilbar, wenn der Rest 0 ist.» и
    # голландское «wanneer de rest 0 is.» ставят ГЛАГОЛ последним, и
    # образец «ЧИСЛО слово.» видел в них имя предмета: «ist» и «is»
    # вошли в словарь множественных форм, а честное «jede ganze Zahl
    # größer als 1 ist ein Produkt von Primzahlen» стало «1 ist» —
    # рассогласованием. Сорок пять обвинений на язык, все ложные.
    #
    # Порок был в НЕСОГЛАСИИ ДВУХ ЦЕНЗОВ: первый спрашивал число
    # БОЛЬШЕ ЕДИНИЦЫ (ибо только оно свидетельствует о множественности),
    # второй брал ЛЮБОЕ — и «0 ist.» проходило свидетелем предметности.
    # Ноль не считает: он есть ЗНАЧЕНИЕ остатка, а не счёт глаголов.
    # Ныне свидетель предметности тот же, что свидетель формы.
    #
    # ЦЕНА ЗАМЕРЕНА, А НЕ ОБЕЩАНА: словарь по всему своду 405 → 403
    # слов, и выбывшие двое суть ровно «is» и «ist». Порча 90 → 0.
    # Соседний ценз (требовать РАЗНЫХ чисел) убрал бы вместе с ними
    # «metres», «seconds», «people», «edges», «numbers» — восемь слов
    # вместо двух, и потому отвергнут замером.
    предметы = {}
    for число, слово in ПРЕДМЕТНО.findall(текст):
        if int(число) > 1 and слово not in СЛУЖЕБНЫЕ:
            предметы[слово] = предметы.get(слово, 0) + 1
    # СЛОВО ИЗ ОДНОЙ БУКВЫ НЕ БЫВАЕТ СЧЁТНЫМ ИМЕНЕМ. В алгебраическом
    # слое «1 x + 7 x = 8 x» дало пятнадцать ложных обвинений: «x» —
    # переменная, и никакое согласование по числу к ней не относится.
    # Ценз слеп к языку: в любом алфавитном письме однобуквенное слово
    # есть местоимение, частица или переменная, но не имя предмета.
    словарь = {с for с in чаще(множественные, закон) & чаще(предметы, закон)
               if len(с) > 1}
    порча, верно = {}, 0
    for слово in ЕДИНИЦА.findall(текст):
        if слово in словарь:
            порча[слово] = порча.get(слово, 0) + 1
        elif слово + "s" in словарь or слово + "es" in словарь:
            верно += 1
    return sum(порча.values()), верно, порча


def обход(все, явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    if все:
        return sorted((КОРЕНЬ / "datasets").glob("*.txt"))
    try:
        # СУД ЭТОТ ОТКАЛИБРОВАН НА ПОКАЗЫ и прозу судить не вправе:
        # на научном тексте он обвинял честное («T-113» — дефис в
        # имени, «48 = 7² − 1» — степень, «5 - 3 = 3 - 5» — ложь,
        # ПРИВЕДЁННАЯ ради опровержения). Род текста объявляет мир.
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"СОГЛАСОВАНИЕ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    все = "--all" in sys.argv
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    закон = закон_повтора()
    пути = [п for п in обход(все, явные) if п.exists()]
    # ПУСТОЙ-ОБХОД: обход без единого файла есть ОТКАЗ, а не чистота —
    # прибор, которому нечего читать, обязан молчать громко.
    if not пути:
        print("СОГЛАСОВАНИЕ ОТКАЗ: обход пуст, судить нечего")
        return 2
    всего_порчи = всего_верно = 0
    строки = []
    for путь in пути:
        порчи, верно, поимённо = судить(путь, закон)
        всего_порчи += порчи
        всего_верно += верно
        if порчи or верно:
            топ = sorted(поимённо.items(), key=lambda п: -п[1])[:4]
            строки.append(
                f"  {путь.name:<30} рассогласовано {порчи:>4} "
                f"верно {верно:>4}   {топ if топ else ''}"
            )
    for с in строки:
        print(с)
    поза = "ЛЕНТА" if (все or явные) else (
        "PASS" if всего_порчи <= РАССОГЛАСОВАНО_РУБЕЖ else "FAIL"
    )
    рубеж = "" if (все or явные) else (
        f" при рубеже {РАССОГЛАСОВАНО_РУБЕЖ}"
    )
    print(
        f"СОГЛАСОВАНИЕ {поза}: {всего_порчи} рассогласований"
        f"{рубеж} ({всего_верно} верных, {len(пути)} файлов, закон {закон})"
    )
    if все or явные:
        return 0
    return 0 if всего_порчи <= РАССОГЛАСОВАНО_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
