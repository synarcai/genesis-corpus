#!/usr/bin/env python3
"""[СУММА УГЛОВ] — постоянство суммы, пересчитанное судом.

Суд не пишет закона заново: он берёт его у дома (`angleforms`), где тройки углов, четвёрки и
пары острых объявлены таблицами, а общий закон «(n − 2) × 180» пересчитывается для каждого
числа сторон. Всякая запись страницы считается разбором свода (`arithread`).

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: всякая тройка обязана давать 180 и всякая
четвёрка 360; углы обязаны быть целыми и лежать внутри границ; двух прямых в одной тройке быть
не смеет; треугольники обязаны РАЗЛИЧАТЬСЯ формой — иначе постоянство суммы не видно вовсе; и
общий закон обязан покрывать оба показанных случая.

    python3 courts/angle_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import angleforms  # noqa: E402 — дом, объявивший множитель размерности

ИМЯ_СУДА = "angle"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"angle"})


def _судить(строка):
    return angleforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"СУММА УГЛОВ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(angleforms.РОДЫ)}, страниц {len(angleforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
