#!/usr/bin/env python3
"""[ВЕКТОР И МАТРИЦА] — суд ПРИМЕНЯЕТ преобразование заново.

    (1, 2) + (3, 4) = (4, 6).
    the dot product of (1, 2) and (3, 4) is 11.
    [1 2; 3 4] × (1, 1) = (3, 7).
    the matrix [1 2; 3 4] has determinant -2.

ВЕКТОР ЕСТЬ ОДИН ПРЕДМЕТ, А НЕ ДВА ЧИСЛА, и потому обе его доли
проверяются вместе: показ, верный по первой и ложный по второй, есть
ровно тот дефект, какой не поймает счёт по одному числу.

ДЛИНА ПРОВЕРЯЕТСЯ КВАДРАТАМИ: целое, чей квадрат равен сумме
квадратов долей, есть точный ответ; корень здесь не берётся, ибо
приближение, названное равенством, было бы ложью.

ОПРЕДЕЛИТЕЛЬ ЕСТЬ ЧИСЛО, А ПРИМЕНЕНИЕ — ДЕЙСТВИЕ: матрица, названная
верно по определителю и неверно по применению, противоречит себе, и
обе поверхности считаются здесь своим счётом.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import asking  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

Ч = r"-?\d+"
СЛОЖЕНИЕ = re.compile(
    rf"^\(({Ч}), ({Ч})\) ([+−]) \(({Ч}), ({Ч})\) = \(({Ч}), ({Ч})\)\.$")
МАСШТАБ = re.compile(
    rf"^({Ч}) (?:× |умножить на )\(({Ч}), ({Ч})\)"
    rf"(?: = | даёт )\(({Ч}), ({Ч})\)\.$")
ЗВЕНО = r"(\d+) × (\d+) = (\d+)"
ДЛИНА = re.compile(
    rf"^(?:the vector \(({Ч}), ({Ч})\) has length"
    rf"|вектор \(({Ч}), ({Ч})\) имеет длину) ({Ч}): {ЗВЕНО}, {ЗВЕНО}, (\d+) \+ (\d+) = (\d+), {ЗВЕНО}\.$")
СКАЛЯРНОЕ = re.compile(
    rf"^(?:the dot product of \(({Ч}), ({Ч})\) and \(({Ч}), ({Ч})\) is"
    rf"|скалярное произведение \(({Ч}), ({Ч})\) и \(({Ч}), ({Ч})\) равно) "
    rf"({Ч}): ({Ч}) × ({Ч}) = ({Ч}), ({Ч}) × ({Ч}) = ({Ч}), ({Ч}) \+ ({Ч}) = ({Ч})\.$")
ОПРЕДЕЛИТЕЛЬ = re.compile(
    rf"^(?:the matrix \[({Ч}) ({Ч}); ({Ч}) ({Ч})\] has determinant"
    rf"|матрица \[({Ч}) ({Ч}); ({Ч}) ({Ч})\] имеет определитель) ({Ч}): ({Ч}) × ({Ч}) = ({Ч}), ({Ч}) × ({Ч}) = ({Ч}), ({Ч}) − ({Ч}) = ({Ч})\.$")
# ОТКАЗ ЕСТЬ ТАКОЕ ЖЕ УТВЕРЖДЕНИЕ: «целого нет» истинно ровно тогда,
# когда сумма квадратов посчитана верно И корень из неё не целый.
ЦЕЛОСТЬ_ДЛИНЫ = re.compile(
    rf"^(?:yes: ({Ч})\^2 \+ ({Ч})\^2 = ({Ч}) = ({Ч})\^2, the length is ({Ч})"
    rf"|no: ({Ч})\^2 \+ ({Ч})\^2 = ({Ч}), and ({Ч}) is not a perfect square"
    rf"|да: ({Ч})\^2 \+ ({Ч})\^2 = ({Ч}) = ({Ч})\^2, длина равна ({Ч})"
    rf"|нет: ({Ч})\^2 \+ ({Ч})\^2 = ({Ч}), а ({Ч}) не полный квадрат)\.$")


def полный_квадрат(n):
    """Целое ли число корень — суд считает сам, а не верит показу."""
    к = int(n ** 0.5)
    while к * к < n:
        к += 1
    return к * к == n


ПРИМЕНЕНИЕ = re.compile(
    rf"^\[({Ч}) ({Ч}); ({Ч}) ({Ч})\] (?:× |умножить на )"
    rf"\(({Ч}), ({Ч})\)(?: = | даёт )\(({Ч}), ({Ч})\)\.$")


def числа(m, сколько):
    все = [г for г in m.groups() if г is not None and г.lstrip("-").isdigit()]
    return [int(x) for x in все[:сколько]]


import laws  # noqa: E402
ЗАКОНЫ = laws.свод("linalg")
ЗАКОНЫ_ЯЗЫКА = laws.по_языкам("linalg")
import discourse  # noqa: E402


def судить(строка):
    """(судимо, истинно) для одной строки."""
    if строка.strip() in ЗАКОНЫ:
        return True, True
    # ВОПРОС СУДИТСЯ СВОИМ ОТВЕТОМ, А РОД ОПРЕДЕЛЯЕТСЯ ОТВЕТОМ.
    # Связь половин держит общий дом `tools/asking.py`: величины
    # вопроса суть начальный отрезок величин ответа, и порча любой из
    # них рвёт пару. Без этого суд читал бы вторую половину строки и
    # звал истиной вопрос, спрашивающий о другом.
    р = discourse.судить_рассуждение_мира(строка, судить, ЗАКОНЫ_ЯЗЫКА)
    if р is not None:
        return р
    если = asking.судить_парой(строка, судить)
    if если is not None:
        return если
    с = строка.strip()
    m = СЛОЖЕНИЕ.match(с)
    if m:
        a, b = int(m.group(1)), int(m.group(2))
        знак = m.group(3)
        c, d = int(m.group(4)), int(m.group(5))
        x, y = int(m.group(6)), int(m.group(7))
        ждём = (a + c, b + d) if знак == "+" else (a - c, b - d)
        return True, (x, y) == ждём
    m = МАСШТАБ.match(с)
    if m:
        k, a, b, x, y = числа(m, 5)
        return True, (x, y) == (k * a, k * b)
    # ЗВЕНЬЯ ЦЕПИ СВЕРЯЮТСЯ КАЖДОЕ (compose, e9): множители — числа вопроса,
    # итог звена — счёт, последнее звено — ответ.
    m = ДЛИНА.match(с)
    if m:
        a, b, c, x1, x2, xx, y1, y2, yy, s1, s2, s, c1, c2, cc = числа(m, 15)
        return True, ((x1, x2, y1, y2) == (a, a, b, b) and xx == a * a and yy == b * b
                      and (s1, s2) == (xx, yy) and s == xx + yy
                      and (c1, c2) == (c, c) and cc == c * c and s == cc)
    m = СКАЛЯРНОЕ.match(с)
    if m:
        a, b, c, d, итог, a1, c1, p1, b1, d1, p2, q1, q2, s = числа(m, 14)
        return True, ((a1, c1, b1, d1) == (a, c, b, d) and p1 == a * c and p2 == b * d
                      and (q1, q2) == (p1, p2) and s == p1 + p2 and итог == s)
    m = ОПРЕДЕЛИТЕЛЬ.match(с)
    if m:
        a, b, c, d, det, a1, d1, p1, b1, c1, p2, q1, q2, r = числа(m, 14)
        return True, ((a1, d1, b1, c1) == (a, d, b, c) and p1 == a * d and p2 == b * c
                      and (q1, q2) == (p1, p2) and r == p1 - p2 and det == r)
    m = ЦЕЛОСТЬ_ДЛИНЫ.match(с)
    if m:
        г = числа(m, 5)
        if len(г) == 5:
            a, b, сумма, c, c2 = г
            return True, (a * a + b * b == сумма and c * c == сумма and c2 == c)
        a, b, сумма, сумма2 = г
        return True, (a * a + b * b == сумма and сумма2 == сумма
                      and not полный_квадрат(сумма))
    m = ПРИМЕНЕНИЕ.match(с)
    if m:
        a, b, c, d, x, y, u, v = числа(m, 8)
        return True, (u, v) == (a * x + b * y, c * x + d * y)
    return False, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ВЕКТОР ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ВЕКТОР ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ВЕКТОР {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
