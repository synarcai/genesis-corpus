#!/usr/bin/env python3
"""[АРИФМЕТИКА ЯЗЫКОВОГО ПЛАСТА] — равенство, сказанное словами языка, ПЕРЕСЧИТЫВАЕТСЯ.

Долг судимости (03.09, мера scripts/coverage.py): 2 007 строк свода были
зачтены СЛОВАРЁМ пакета — то есть проверкой «всякое слово объявлено», а не
истиной. Разведка назвала их поимённо: 1 240 из них суть арифметика,
сказанная словами языка, у которого нет своего счётного суда — «sita
jumlisha tano ni sawa na kumi na moja.» (суахили), «kuusi plus viisi on
yksitoista.» (финский). Слова объявлены, и потому строка проходила; ЧИСЛА
при этом не считал никто, и ложное равенство прошло бы так же.

Суд читает равенство ТЕМ ЖЕ домом, каким пишутся цепочки (tools/chainforms.py):
шаблон рода `arithmetic` объявлен в самом пакете, действие узнаётся по МЕСТУ
дыр, числительные читаются в числа по таблице пакета — и результат
пересчитывается. Ни одного слова не выдумано, ни одного языка не зашито:
суд знает ровно столько языков, сколько объявили свои шаблоны.

Строка, которая не есть равенство объявленного шаблона, этому суду не
принадлежит — он молчит, и её судят прежние суды.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import chainforms as F  # noqa: E402


def судить(строка):
    """(судимо, истинно): одиночное равенство языка, пересчитанное по его же
    шаблону. Цепочки из двух и более равенств судит дом цепочек."""
    с = строка.strip()
    куски = F._куски(с)
    if len(куски) != 1:
        return False, False
    for язык in F.ЯЗЫКИ:
        ш = F.разобрать_шаг(язык, куски[0])
        if ш is None:
            continue
        оп, a, b, r = ш
        return True, F._счёт(оп, a, b) == r
    return False, False


def main():
    import collections
    from genesis import worlds
    итог = collections.Counter(); примеры = []
    for путь in worlds(kind="shows"):
        for с in путь.read_text(encoding="utf-8").splitlines():
            if not с.strip() or с.startswith("\x0c"):
                continue
            судимо, истинно = судить(с)
            if not судимо:
                continue
            итог["судимых"] += 1
            if not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.name}: {с}")
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:120]}")
    поза = "PASS" if итог["ложных"] == 0 else "FAIL"
    print(f"АРИФМЕТИКА ПЛАСТОВ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
