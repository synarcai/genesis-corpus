"""[КОШЕЛЁК] — деньги как величина, которую тратят и которая остаётся; МИР ЗАМКНУТ.

Свод считал ЦЕНУ и не считал КОШЕЛЬКА: он умел спросить «сколько стоят пять яблок» и
«хватит ли десяти рублей» — и не умел спросить «сколько денег осталось ПОСЛЕ ПОКУПКИ».
Замер 21.09 по 471 605 строкам: покупка с остатком денег — НОЛЬ строк; вопрос о
потраченных деньгах — десять; об оставшихся — пятьдесят четыре.

    ВЕЛИЧИНА, КОТОРУЮ ЧИТАТЕЛЬ ВИДЕЛ ТОЛЬКО ОТВЕТОМ, НЕ ОПОЗНАЁТСЯ ИМ В ВОПРОСЕ. Деньги
    стояли в своде ценой — тем, что дано; здесь они стоя́т и тем, что спрошено.

СУД ТРЕБУЕТ ТРЁХ ВЕЩЕЙ, И ВСЯКАЯ ПРОВЕРЯЕМА БЕЗ НАБОРА:

    ИТОГ ЛЕДЖЕРА ПЕРЕСЧИТЫВАЕТСЯ, а знак его отвечает роду страницы;
    ЧИСЛО ОТВЕТА СТОИ́Т ПРИ ВАЛЮТЕ и равно итогу — ответ «15» без валюты учит числу, а не
        деньгам;
    ВАЛЮТА ПРИ ВСЯКОМ ЧИСЛЕ — В СЧЁТНОЙ ФОРМЕ ЭТОГО ЧИСЛА: «20 рублей», но «1 рубль» и
        «23 złote». Счётная форма объявлена пакетом, и проверить её можно, не веря странице.

ВИНИТЕЛЬНЫЙ ПАДЕЖ ВЕЩИ ОБЪЯВЛЕН ДОМОМ, А НЕ ВЫВЕДЕН: «купил ОДНУ КНИГУ», «kupił jedną
książkę», «kaufte einen Apfel». Грамматическая ложь не ловится ни одним счётным судом —
числа в ней сойдутся, — и потому падеж объявляется, а не угадывается.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import wallet as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"wallet"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_wallet.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_wallet.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_wallet.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"КОШЕЛЁК {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
