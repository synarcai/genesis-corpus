#!/usr/bin/env python3
"""[АРИФМЕТИЧЕСКАЯ ИСТИНА КОРПУСА] — показ, утверждающий равенство,
обязан утверждать ИСТИННОЕ.

ПОВОД, ПРОЖИТЫЙ 01.09: языковой пакет отгрузил СОРОК показов деления,
и все сорок были ложны — шаблон писал «(n+m)/m = n», потому что
движку нечем было выразить произведение, а судья пар считал ВХОЖДЕНИЯ
слова, а не истину его показов. Восьмое поле langpack закрыло этот род
для языковых пластов. Но слои генераторов — головы, истории, ставки,
доли, сравнение, агрегат — не судил на истину НИКТО: у них нет
langpack, и их равенства жили непроверенными.

ПРИБОР СЛЕП К ЯЗЫКАМ И В ЭТОМ ЕДИН С НИМИ. Он не знает ни «равно», ни
«gleich», ни «equals»: значения слов и знаки операций он читает ИЗ
ПАКЕТОВ ЯЗЫКОВ (`tools/langpacks/*.json`) — тех же, по которым эти
пласты и порождаются. Сотый язык и здесь стоит один пакет. Глифы
(`+ - × ÷ =`) не требуют объявления вовсе: они всеобщи.

ЦЕПЬ ЧИТАЕТСЯ ПО СТАРШИНСТВУ, А НЕ СЛЕВА НАПРАВО. Первая редакция
судила слева направо и объявила ЛОЖНЫМИ сто девяносто пять честных
показов, среди них «2 + 3 × 4 = 14» — истину, которую знает всякий
школьник. Прибор ошибся раньше корпуса, и это его собственный шрам:
мера, не знающая правила предмета, зовёт чинить исправное. Умножение
и деление берутся прежде сложения и вычитания, равные по старшинству —
слева направо, потому «4 ÷ 4 × 3 = 3» по-прежнему читается верно.

ЧЕГО ПРИБОР НЕ ВИДИТ, НАЗВАНО ЧЕСТНО И СЧИТАЕТСЯ ЧИСЛОМ:
  · равенство, сказанное СВЯЗКОЙ, а не знаком («half of six is
    three») — слово «is» стоит в тысяче обычных фраз, и объявить его
    равенством значило бы залить прибор шумом. Такие показы судит
    порождающий их генератор;
  · составное числительное из двух слов там, где пакет не объявил
    сложения («twenty one») — читается как два значения подряд и в
    счёт не идёт;
  · неразобранные строки С признаком равенства печатаются числом
    (`неразобрано`), потому что молчащая слепота читается как чистота.
"""
import json
import pathlib
import re
import sys
from fractions import Fraction

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ПАКЕТЫ = КОРЕНЬ / "tools/langpacks"
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import Unreadable, worlds  # noqa: E402
from segment import tokens  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ДЕЙСТВИЕ = {
    "+": lambda a, b: a + b,
    "-": lambda a, b: a - b,
    "*": lambda a, b: a * b,
    # СЧЁТ ТОЧНЫМИ ДРОБЯМИ. Целочисленное деление объявило ложными
    # двадцать честных показов «4/10 + 6/10 = 1»: над дробями это
    # истина, и мера, не знающая дробей, зовёт чинить исправное.
    # Строгость не потеряна: «5 ÷ 2 = 2» по-прежнему ложь, ибо
    # Fraction(5, 2) не равно двум.
    "/": lambda a, b: None if b == 0 else Fraction(a) / b,
    # показатель обязан быть целым и небольшим: «2^1000» есть истина,
    # которую незачем считать в суде корпуса
    "^": lambda a, b: (None if b < 0 or b > 32 or b.denominator != 1
                       else a ** int(b)),
}
# ЗНАК МИНУСА В КОРПУСЕ — U+2212, А НЕ ДЕФИС. Первая редакция знала
# только ASCII и молча ТЕРЯЛА его: «8 − 2 × 3 = 2» разбиралось без
# операции, две цифры слипались в одну, и честный показ объявлялся
# ложным. Потерянный знак опаснее незнакомого — незнакомый виден.
# СТЕПЕНЬ — ОПЕРАЦИЯ, А НЕ УКРАШЕНИЕ. «$ 5^3 = 125 $» есть истинное
# числовое утверждение, и его не читал ни один суд: слой разметки нёс
# двести таких строк непроверенными.
ГЛИФЫ = {"+": "+", "-": "-", "\u2212": "-", "*": "*", "×": "*",
         "\u22c5": "*", "/": "/", "÷": "/", "^": "^"}
# `\d` в Python берёт и надстрочные цифры — здесь нужны ТОЛЬКО
# ASCII: «10²» есть степень, а не число «102».
ЛЕКСЕМА = re.compile(
    r"[0-9]+|[^\W\d_]+|[+\-*/×÷=^\u2212\u22c5]"
)


def письмена_без_пробела():
    """[(образец письма, словарь пакета)] — языки, пишущие без пробелов.

    ПОСЛЕДНИЙ НЕПОЧИНЕННЫЙ СЛУЧАЙ ОБЩЕЙ СЛЕПОТЫ. Разбор здесь полагал
    пробел, и «九加一等于十» приходило одним токеном: суд читал
    китайскую арифметику как одно слово и молчал о ней — тысяча триста
    строк пласта стояли при пяти процентах судимости.
    """
    вон = []
    if not ПАКЕТЫ.is_dir():
        return вон
    for ф in sorted(ПАКЕТЫ.glob("*.json")):
        try:
            п = json.loads(ф.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if п.get("segmentation") != "longest-match":
            continue
        словарь = {str(v) for v in (п.get("numerals") or {}).values()}
        for род in (п.get("show_kinds") or {}).values():
            словарь |= {str(w) for w in (род.get("ops") or {})}
            словарь |= {str(w) for w in род.get("lexicon", [])}
        for кл in (п.get("morph_classes") or {}).values():
            for формы in кл.get("lexemes", {}).values():
                словарь |= {str(ф_) for ф_ in формы}
        диапазон = п.get("script_range")
        if диапазон and словарь:
            вон.append((re.compile(f"[{диапазон}]"), словарь))
    return вон


БЕЗ_ПРОБЕЛА = None


def словари():
    """(значения слов, операторы, знаки равенства, сложение составных).

    Отказ, а не догадка: если два пакета дают одному слову разные
    значения, судить нельзя — прибор скажет об этом и замолчит.
    """
    значения, операции, равенства = {}, dict(ГЛИФЫ), {"="}
    складывать = False
    if not ПАКЕТЫ.is_dir():
        return значения, операции, равенства, складывать
    for ф in sorted(ПАКЕТЫ.glob("*.json")):
        try:
            п = json.loads(ф.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for ключ, слово in (п.get("numerals") or {}).items():
            if not str(ключ).lstrip("-").isdigit():
                continue
            с = str(слово).lower()
            if значения.get(с, int(ключ)) != int(ключ):
                print(f"АРИФМЕТИКА ОТКАЗ: слово «{с}» значит и "
                      f"{значения[с]}, и {ключ} — судить нельзя")
                sys.exit(2)
            значения[с] = int(ключ)
        for род in (п.get("show_kinds") or {}).values():
            for слово, знак in (род.get("ops") or {}).items():
                if знак == "=":
                    равенства.add(слово.lower())
                else:
                    операции[слово.lower()] = знак
            if род.get("numeral_compose") == "additive":
                складывать = True
    return значения, операции, равенства, складывать


def разбор(строка, значения, операции, равенства, складывать):
    """[(род, величина)] строки: v — значение, o — операция, e — равно."""
    global БЕЗ_ПРОБЕЛА
    if БЕЗ_ПРОБЕЛА is None:
        БЕЗ_ПРОБЕЛА = письмена_без_пробела()
    куски = None
    for образец, словарь in БЕЗ_ПРОБЕЛА:
        if образец.search(строка):
            куски = tokens(строка, словарь, spaced=False)
            break
    ряд = []
    for знак in (куски if куски is not None else ЛЕКСЕМА.findall(строка)):
        н = знак.lower()
        if знак.isdigit() and знак.isascii():
            ряд.append(("v", Fraction(int(знак)), True))
        elif н in значения:
            ряд.append(("v", Fraction(значения[н]), False))
        elif н in операции:
            ряд.append(("o", операции[н], False))
        elif н in равенства:
            ряд.append(("e", 0, False))
    if not складывать:
        return [(р, в) for р, в, _ in ряд]
    # СКЛАДЫВАЮТСЯ ТОЛЬКО СЛОВА («twenty one» = 20 + 1). Две ЦИФРЫ
    # рядом не составное числительное, а две величины, и слипшись они
    # лгут: «8 − 2» с потерянным знаком стало «10» и объявило истинный
    # показ ложным.
    слитый = []
    for род, вел, цифрой in ряд:
        if (род == "v" and not цифрой and слитый
                and слитый[-1][0] == "v"
                and not слитый[-1][2]):
            слитый[-1] = ("v", слитый[-1][1] + вел, False)
        else:
            слитый.append((род, вел, цифрой))
    return [(р, в) for р, в, _ in слитый]


def свернуть(ряд):
    """Значение цепи «v (o v)*» по старшинству, или None."""
    if not re.fullmatch(r"v(?:ov)*", "".join(р for р, _ in ряд)):
        return None
    величины = [в for р, в in ряд if р == "v"]
    знаки = [в for р, в in ряд if р == "o"]
    # СТЕПЕНЬ СВОРАЧИВАЕТСЯ ПЕРВОЙ: она старше умножения, и «2 × 3^2»
    # есть восемнадцать, а не тридцать шесть.
    i = 0
    while i < len(знаки):
        if знаки[i] == "^":
            итог = ДЕЙСТВИЕ["^"](величины[i], величины[i + 1])
            if итог is None:
                return None
            величины[i:i + 2] = [итог]
            знаки.pop(i)
        else:
            i += 1
    i = 0
    while i < len(знаки):
        if знаки[i] in ("*", "/"):
            итог = ДЕЙСТВИЕ[знаки[i]](величины[i], величины[i + 1])
            if итог is None:
                return None
            величины[i:i + 2] = [итог]
            знаки.pop(i)
        else:
            i += 1
    итог = величины[0]
    for j, знак in enumerate(знаки):
        итог = ДЕЙСТВИЕ[знак](итог, величины[j + 1])
        if итог is None:
            return None
    return итог


ВЫЗОВ = re.compile(r"[^\W\d_]\w*\s*\(")


def свернуть_скобки(строка, словарь):
    """Значение выражения со скобками, или None.

    Скобки — не украшение: «( ( 341 − 12 ) ÷ 7 ) × 3 + 12» есть
    законная запись, и суд, их не знающий, либо молчит, либо лжёт.
    Свёртка идёт изнутри наружу, самой глубокой парой.
    """
    текст = строка
    for _ in range(20):
        м = re.search(r"\(([^()]*)\)", текст)
        if not м:
            break
        значение = свернуть(разбор(м.group(1), *словарь))
        if значение is None:
            return None
        текст = текст[:м.start()] + f" {значение} " + текст[м.end():]
    return текст if "(" not in текст else None


def судить(строка, словарь):
    """(судимо, истинно) — РАВЕНСТВО ДВУХ ВЫРАЖЕНИЙ.

    Первая редакция требовала справа одну величину и оттого не судила
    законы вида «2 + 3 = 3 + 2» — триста показов переместительности,
    которые есть настоящие утверждения и могут быть ложными. Обе
    стороны сворачиваются одним правилом; тождества с буквами
    («z + x = x + z») по-прежнему несудимы и попадают в счёт
    неразобранного, ибо величин в них нет вовсе.
    """
    # ЧИСЛО В ВЫЗОВЕ ФУНКЦИИ ЕСТЬ АРГУМЕНТ, А НЕ СЛАГАЕМОЕ.
    # «factorial(5) = 5 × factorial(4)» — истинное рекурсивное
    # определение, а суд читал его как «5 = 5 × 4» и звал ложью.
    # Термы, которых суд вычислить не может, лишают его подсудности:
    # честный отказ, а не догадка.
    if ВЫЗОВ.search(строка):
        return False, False
    if "(" in строка or ")" in строка:
        строка = свернуть_скобки(строка, словарь)
        if строка is None:
            return False, False
    ряд = разбор(строка, *словарь)
    if not any(р == "e" for р, _ in ряд):
        return False, True
    делит = [i for i, (р, _) in enumerate(ряд) if р == "e"]
    if len(делит) != 1:
        return False, False
    лево, право = ряд[:делит[0]], ряд[делит[0] + 1:]
    # РАВЕНСТВО БЕЗ ЕДИНОЙ ОПЕРАЦИИ НЕ УТВЕРЖДАЕТ АРИФМЕТИКИ. «5 минут
    # равно 300 секунд» и «one week equals 7 days» суть ПЕРЕВОДЫ ЕДИНИЦ
    # (род конверсий), и числа в них равны лишь вместе с единицами,
    # которых прибор не читает. Обобщив суд на две стороны, я тут же
    # объявил ложными 375 честных переводов — граница поставлена там,
    # где кончается арифметика, а не там, где кончается разбор.
    if not any(р == "o" for р, _ in лево + право):
        return False, False
    слева = свернуть(лево)
    справа = свернуть(право)
    if слева is None or справа is None:
        # неточное деление, названное точным, есть ЛОЖЬ; отсутствие
        # величин — несудимость. Различаются по форме, а не по итогу.
        стороны = ("".join(р for р, _ in ряд[:делит[0]]),
                   "".join(р for р, _ in ряд[делит[0] + 1:]))
        if all(re.fullmatch(r"v(?:ov)*", с) for с in стороны):
            return True, False
        return False, False
    return True, слева == справа


# Пробел после знака уже отделяет дробь «1.5» — лишний запрет на цифру
# перед точкой не пускал границу туда, где она есть («исходов 6. доля
# шестёрки»). И двойной обратный слэш от heredoc требовал ЛИТЕРАЛЬНОГО
# слэша: правка, не проверенная опытом, не правка.
ПРЕДЛОЖЕНИЕ = re.compile(r"[.。?!]+(?:\s+|$)")


def предложения(строка):
    """Строка режется на предложения ПЕРЕД судом.

    Одна строка часто несёт несколько утверждений, и число из
    предыдущего втекало в равенство следующего: «кость: исходов 6.
    доля шестёрки = 1/6» читалось как «6 = 1/6» и объявлялось ложью.
    Точка между цифрами (1.5) границей не считается.
    """
    return [ч for ч in ПРЕДЛОЖЕНИЕ.split(строка) if ч and ч.strip()]


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        # СУД ЭТОТ ОТКАЛИБРОВАН НА ПОКАЗЫ и прозу судить не вправе:
        # на научном тексте он обвинял честное («T-113» — дефис в
        # имени, «48 = 7² − 1» — степень, «5 - 3 = 3 - 5» — ложь,
        # ПРИВЕДЁННАЯ ради опровержения). Род текста объявляет мир.
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"АРИФМЕТИКА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    словарь = словари()
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("АРИФМЕТИКА ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = неразобрано = 0
    примеры = []
    for путь in пути:
        свои_ложные = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for сырая in поток:
              for строка in предложения(сырая):
                судимо, истинно = судить(строка, словарь)
                if судимо:
                    судимых += 1
                    if not истинно:
                        ложных += 1
                        свои_ложные += 1
                        if len(примеры) < 4:
                            примеры.append(
                                f"{путь.name}: {строка.strip()[:70]}")
                elif not истинно:
                    неразобрано += 1
        if свои_ложные:
            print(f"  {путь.name:<30} ложных {свои_ложные}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"АРИФМЕТИКА {поза}: {ложных} ложных равенств из {судимых} "
          f"судимых ({len(пути)} файлов, неразобрано {неразобрано})")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
