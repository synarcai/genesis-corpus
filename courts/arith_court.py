def словари():
    """(значения слов, операторы, знаки равенства, сложение составных).

    Отказ, а не догадка: если два пакета дают одному слову разные
    значения, судить нельзя — прибор скажет об этом и замолчит.
    """
    значения, операции, равенства, связки = {}, dict(ГЛИФЫ), {"="}, set()
    if not ПАКЕТЫ.is_dir():
        return значения, операции, равенства, связки
    for ф in sorted(ПАКЕТЫ.glob("*.json")):
        try:
            п = json.loads(ф.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        # ЧИСЛИТЕЛЬНОЕ СКЛОНЯЕТСЯ, И КОСВЕННАЯ ФОРМА — ТО ЖЕ ЧИСЛО.
        # «половина шести — три» есть счётное утверждение, и суд,
        # знавший лишь именительный, читал «шести» как незнакомое
        # слово. Формы объявлены в пакете, а не выведены отсечением.
        таблицы = [(п.get("numerals") or {}),
                   (п.get("numeral_oblique") or {})]
        for ключ, слово in [(к, з) for т in таблицы for к, з in т.items()]:
            # ЧИСЛИТЕЛЬНОЕ БЫВАЕТ ДРОБНЫМ. «half» есть такое же
            # объявленное число, как «ten», и без него смешанное число
            # («three and a half») не читается вовсе.
            try:
                в = Fraction(str(ключ))
            except (ValueError, ZeroDivisionError):
                continue
            с = str(слово).lower()
            if значения.get(с, в) != в:
                print(f"АРИФМЕТИКА ОТКАЗ: слово «{с}» значит и "
                      f"{значения[с]}, и {в} — судить нельзя")
                sys.exit(2)
            значения[с] = в
        for род in (п.get("show_kinds") or {}).values():
            for слово, знак in (род.get("ops") or {}).items():
                if знак == "=":
                    равенства.add(слово.lower())
                else:
                    операции[слово.lower()] = знак
        # СВЯЗКА ЧИСЛИТЕЛЬНЫХ — СВОЙСТВО ПАКЕТА, А НЕ ПРИБОРА. Прежде
        # здесь стоял ОДИН булев на все двенадцать языков: пакет,
        # объявивший сложение, включал его ВСЕМ — тот же род, что
        # затенённое имя, взявшее чужих хозяев. Теперь пакет объявляет
        # СВОИ связки («noventa Y nueve», «noventa E nove»), а сам
        # закон сложения всеобщ и флага не требует.
        связки |= {с.lower() for с in (п.get("numeral_connectors") or [])}
    return значения, операции, равенства, связки


_МНОГОСЛОВНЫЕ = None


def объявленные_многословные(значения, операции, равенства):
    """(образец, роль по тексту) — всё объявленное, что длиннее слова.

    ОБЪЯВЛЕННОЕ МНОГОСЛОВНОЕ ЕСТЬ ОДИН ТОКЕН — КАКИЕ БЫ ЗНАКИ ИЛИ
    ПРОБЕЛЫ В НЁМ НИ СТОЯЛИ. Закон родился на французском «dix-huit»,
    читанном как «10 − 8», и на китайском письме без пробелов; он же
    правит украинское «дев'ять» с апострофом и турецкое «on bir».
    Здесь он доведён до своего рода: не «составное ЧИСЛИТЕЛЬНОЕ», а
    ВСЯКОЕ объявленное многословное — ибо операция тоже бывает
    фразой. «умножить на», «divided by», «ist gleich», «es igual a» —
    настоящая речь языков, и суд, читавший лишь первое слово фразы,
    ВЫБРАСЫВАЛ второе и выносил вердикт по остатку: тринадцать тысяч
    строк судились догадкой, которая случайно совпадала с истиной.

    Границы слова стерегутся с обеих сторон: фраза «es igual a» не
    смеет откусить «а» от соседнего слова. Письму без пробелов этот
    путь не нужен — у него свой, и он выбирается прежде.
    """
    global _МНОГОСЛОВНЫЕ
    if _МНОГОСЛОВНЫЕ is None:
        роль = {}
        for таблица, род in ((значения, "v"), (операции, "o"),
                             (равенства, "e")):
            for с in таблица:
                if not с.isalnum():
                    роль[с] = род
        БУКВА = r"[^\W\d_]"
        куски = []
        for с in sorted(роль, key=len, reverse=True):
            тело = re.escape(с)
            слева = f"(?<!{БУКВА})" if с[:1].isalpha() else ""
            справа = f"(?!{БУКВА})" if с[-1:].isalpha() else ""
            куски.append(слева + тело + справа)
        _МНОГОСЛОВНЫЕ = ((re.compile("|".join(куски)), роль) if куски
                         else (None, роль))
    return _МНОГОСЛОВНЫЕ


def разбор(строка, значения, операции, равенства, связки):
    """[(род, величина)] строки: v — значение, o — операция, e — равно."""
    global БЕЗ_ПРОБЕЛА
    # НАДСТРОЧНАЯ СТЕПЕНЬ РАСКРЫВАЕТСЯ ДО РАЗБОРА, ИНАЧЕ ОНА ПРОПАДАЕТ.
    #
    # «x² − 36 = 0» читалось как «x − 36 = 0»: надстрочная двойка не
    # была ни числом, ни знаком, и разбор ГЛОТАЛ её молча, после чего
    # выносил вердикт по остатку — ЛОЖЬ о строке, прочитанной
    # наполовину. Дыру нашли ворота записи нового мира начертаний:
    # 190 честных показов не вошли в корпус.
    #
    # Это тот же закон, что уже казнил здесь потерю токенов: ЗНАК,
    # КОТОРОГО РАЗБОР НЕ ЗНАЕТ, ОН ГЛОТАЕТ МОЛЧА — И ЭТО ХУЖЕ ОТКАЗА.
    # Раскрытие ставит степень в начертание, которое разбор знает, и
    # живёт оно в ОДНОМ доме начертаний на весь корпус.
    строка = notation_variants.раскрыть_степени(строка)
    if БЕЗ_ПРОБЕЛА is None:
        БЕЗ_ПРОБЕЛА = письмена_без_пробела()
    куски = None
    for образец, словарь in БЕЗ_ПРОБЕЛА:
        if образец.search(строка):
            куски = tokens(строка, словарь, spaced=False)
            break
    # СОСТАВНОЕ ЧИСЛИТЕЛЬНОЕ ВЫНИМАЕТСЯ ДО ГЛИФОВ: иначе его знаки
    # достанутся операциям. Оно кладётся в ряд целиком, а остаток
    # строки разбирается обычным порядком.
    образец, роль = объявленные_многословные(значения, операции,
                                             равенства)
    if куски is None and образец is not None and образец.search(строка):
        ряд, хвост = [], 0
        for m in образец.finditer(строка):
            for знак in ЛЕКСЕМА.findall(строка[хвост:m.start()]):
                ряд += _один(знак, значения, операции, равенства, связки)
            с = m.group()
            р = роль[с]
            ряд.append((р, Fraction(значения[с]) if р == "v" else
                        (операции[с] if р == "o" else 0), False))
            хвост = m.end()
        for знак in ЛЕКСЕМА.findall(строка[хвост:]):
            ряд += _один(знак, значения, операции, равенства, связки)
        return _слить(ряд, связки)
    ряд = []
    for знак in (куски if куски is not None else ЛЕКСЕМА.findall(строка)):
        ряд += _один(знак, значения, операции, равенства, связки)
    return _слить(ряд, связки)


def _один(знак, значения, операции, равенства, связки):
    """Ряд из одного знака: значение, операция или равенство."""
    н = знак.lower()
    if знак.isdigit() and знак.isascii():
        return [("v", Fraction(int(знак)), True)]
    if н in значения:
        return [("v", Fraction(значения[н]), False)]
    if н in операции:
        return [("o", операции[н], False)]
    if н in равенства:
        return [("e", 0, False)]
    if н in связки:
        return [("c", 0, False)]
    # НЕПРОЧИТАННОЕ НЕ ВЫБРАСЫВАЕТСЯ, А ВСТАЁТ В РЯД. Это была самая
    # дешёвая строка разборщика — `return []` — и самая дорогая:
    # вердикт выносился ПО ОСТАТКУ, а суд не знал, что читал не всё.
    # Признак рода (verum): прочитано N знаков, использовано M < N,
    # вердикт вынесен — и нигде N с M не сверены. Теперь непрочитанное
    # видно, и `свернуть` отвергнет ряд само: форма «v (o v)*» уже
    # требовала полноты, её обходил именно этот сброс.
    return [("?", 0, False)]


