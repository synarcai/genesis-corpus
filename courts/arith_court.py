def _слить(ряд, связки):
    """Составные числительные словом складываются; цифры — никогда."""
    """Составные числительные словом складываются; цифры — никогда."""
    # СКЛАДЫВАЮТСЯ ТОЛЬКО СЛОВА («twenty one» = 20 + 1). Две ЦИФРЫ
    # рядом не составное числительное, а две величины, и слипшись они
    # лгут: «8 − 2» с потерянным знаком стало «10» и объявило истинный
    # показ ложным.
    слитый, отложенные = [], []
    for род, вел, цифрой in ряд:
        связка = род == "c"
        if связка:
            отложенные.append((род, вел, цифрой))
            continue
        если_слить = (
            род == "v" and not цифрой and слитый
            and слитый[-1][0] == "v" and not слитый[-1][2]
            and all(о[0] == "c" for о in отложенные))
        вместе = составить(слитый[-1][1], вел) if если_слить else None
        if вместе is not None:
            слитый[-1] = ("v", вместе, False)
        else:
            слитый.extend(отложенные)
            слитый.append((род, вел, цифрой))
        отложенные = []
    слитый.extend(отложенные)
    return [(р, в) for р, в, _ in слитый]


def обрамление_прочь(ряд):
    """Зачин и хвост из непрочитанного — рамка, а не вторжение.

    ГРАНИЦА, ДАННАЯ ХОЛОНОМ: суд равенства имеет право на вердикт лишь
    тогда, когда КАЖДАЯ СТОРОНА прочитана целиком; но обрамление,
    стоящее ВНЕ сторон, выбрасывается свободно. Сторона начинается
    первой величиной строки и кончается последней — «but 7 = 2 × 3 + 1»
    и «without: 2 + 3 × 2 = 8» суть честные показы с зачином, а
    «6 x + 2 y = 8 x» несёт непрочитанное МЕЖДУ величинами и потому
    нем. Выброс на краю есть работа суда; выброс внутри — догадка.
    """
    # НЕПРОЧИТАННОЕ РЯДОМ С ОПЕРАЦИЕЙ — ОПЕРАНД, А НЕ РАМКА (подсадка 04.09:
    # «нол минус ноль равно ноль» — «нол» выбрасывалось зачином, и
    # «− 0 = 0» звалось истиной): слово перед знаком действия или после
    # него стоит на месте величины и остаётся внутри — суд немеет честно.
    i, j = 0, len(ряд)
    while i < j and ряд[i][0] == "?" and not (i + 1 < j and ряд[i + 1][0] == "o"):
        i += 1
    while j > i and ряд[j - 1][0] == "?" and not (j - 2 >= i and ряд[j - 2][0] == "o"):
        j -= 1
    return ряд[i:j]


def свернуть(ряд):
    """Значение цепи «v (o v)*» по старшинству, или None.

    МИНУС ПЕРЕД ЧИСЛОМ ЕСТЬ ВЫЧИТАНИЕ ИЗ НИЧЕГО. «8 − 10 = −2» —
    истинное равенство, и суд, знавший минус только между величинами,
    отказывал всякому отрицательному итогу: не ложь, а слепота, и она
    молчала о целом роде.
    """
    if ряд and ряд[0][0] == "o" and ряд[0][1] == "-":
        ряд = [("v", Fraction(0))] + list(ряд)
    if not re.fullmatch(r"v(?:ov)*", "".join(р for р, _ in ряд)):
        return None
    величины = [в for р, в in ряд if р == "v"]
    знаки = [в for р, в in ряд if р == "o"]
    # СТЕПЕНЬ СВОРАЧИВАЕТСЯ ПЕРВОЙ: она старше умножения, и «2 × 3^2»
    # есть восемнадцать, а не тридцать шесть.
    i = 0
    while i < len(знаки):
        if знаки[i] in ("^", "\u221a"):
            итог = ДЕЙСТВИЕ[знаки[i]](величины[i], величины[i + 1])
            if итог is None:
                return None
            величины[i:i + 2] = [итог]
            знаки.pop(i)
        else:
            i += 1
    i = 0
    while i < len(знаки):
        if знаки[i] in ("*", "/"):
            итог = ДЕЙСТВИЕ[знаки[i]](величины[i], величины[i + 1])
            if итог is None:
                return None
            величины[i:i + 2] = [итог]
            знаки.pop(i)
        else:
            i += 1
    итог = величины[0]
    for j, знак in enumerate(знаки):
        итог = ДЕЙСТВИЕ[знак](итог, величины[j + 1])
        if итог is None:
            return None
    return итог


ЛАТЕХ_ЗНАКИ = {r"\cdot": "×", r"\times": "×", r"\div": "÷",
                r"\left": " ", r"\right": " "}


_СЛОВАМИ = None


def словами():
    """[(образец, запись)] — словесная запись числа, из пакетов."""
    global _СЛОВАМИ
    if _СЛОВАМИ is None:
        вон = []
        if ПАКЕТЫ.is_dir():
            for ф in sorted(ПАКЕТЫ.glob("*.json")):
                try:
                    п = json.loads(ф.read_text(encoding="utf-8"))
                except (OSError, ValueError):
                    continue
                for образец, запись in (п.get("verbal_math") or []):
                    куски, имена, хвост = [], [], 0
                    for m in re.finditer(r"<(\w+?)(\.\.\.)?>", образец):
                        куски.append(re.escape(образец[хвост:m.start()]))
                        имена.append(m.group(1))
                        # СЛОТ БЫВАЕТ ВЕЛИЧИНОЙ И БЫВАЕТ ВЫРАЖЕНИЕМ.
                        # «сумма первых n чисел есть n × ( n + 1 ) / 2»
                        # держит справа не число, а целую запись, и
                        # слот, знающий только цифры, отказал бы всему
                        # роду законов. Многоточие в имени объявляет
                        # слот ХВОСТОВЫМ — тем же способом, каким его
                        # объявляют в языках.
                        куски.append(r"(.+)" if m.group(2)
                                     else r"([-\u2212]?\w+)")
                        хвост = m.end()
                    куски.append(re.escape(образец[хвост:]))
                    вон.append((re.compile("^" + "".join(куски) + "$"),
                                имена, запись))
        _СЛОВАМИ = вон
    return _СЛОВАМИ


_ИМЕНАМИ = None


def именами():
    """{имя знака: знак} — обратное чтение, из тех же пакетов."""
    global _ИМЕНАМИ
    if _ИМЕНАМИ is None:
        вон = {}
        if ПАКЕТЫ.is_dir():
            for ф in sorted(ПАКЕТЫ.glob("*.json")):
                try:
                    п = json.loads(ф.read_text(encoding="utf-8"))
                except (OSError, ValueError):
                    continue
                for знак, имена in (п.get("sign_names") or {}).items():
                    если = [имена] if isinstance(имена, str) else имена
                    for имя in если or []:
                        имя = str(имя).lower()
                        # ИМЯ, ДАННОЕ ДВУМ ЗНАКАМ, НЕ ЧИТАЕТСЯ ОБРАТНО:
                        # «дельта» есть имя и большой, и малой буквы, и
                        # выбрать за корпус значило бы догадаться.
                        вон[имя] = None if имя in вон and вон[имя] != знак \
                            else знак
        _ИМЕНАМИ = {и: з for и, з in вон.items() if з}
    return _ИМЕНАМИ


def понизить_именами(строка):
    """Утверждение, сказанное ИМЕНАМИ знаков, — теми же знаками.

    «икс плюс игрек равно игрек плюс икс» есть ровно «x + y = y + x»:
    имена знаков объявлены в пакетах, и обратное чтение по ним ничего
    не добавляет к объявленному. Довольно, что ВСЯКОЕ слово строки —
    объявленное имя либо число: условие острое, и обычный текст под
    него не подпадает, а потому не может быть испорчен.
    """
    слова = re.findall(r"[^\W\d_]+|\d+|[^\s\w]", строка.strip().rstrip(".。"))
    if len(слова) < 3:
        return строка
    таблица = именами()
    вон = []
    for слово in слова:
        н = слово.lower()
        if слово.isdigit():
            вон.append(слово)
        elif н in таблица:
            вон.append(таблица[н])
        else:
            return строка
    return " ".join(вон)


def понизить_словами(строка):
    r"""Словесная запись, переписанная в ту же запись, что и LaTeX.

    ЗАПИСЬ ПОНИЖАЕТСЯ В ЗАПИСЬ, А НЕ В ЧАСТНЫЙ СЛУЧАЙ. «сумма i от 1
    до 4 равно 10» есть ровно «$ \sum_{i=1}^{4} i = 10 $», а «корень
    из 16 равен 4» — «$ \sqrt{16} = 4 $». Довольно объявить, ЧЕМ одна
    запись является в другой, и оба понижения складываются: слова →
    LaTeX → глифы. Новый язык стоит одного пакета и ни строки движка.
    """
    с = строка.strip().rstrip(".。")
    for образец, имена, запись in словами():
        m = образец.match(с)
        if not m:
            continue
        # A WORD IN A NUMBER SLOT MUST BE A NUMBER (mutation 04.09: «нол минус
        # ноль равно ноль» lowered to «нол - ноль = ноль», the framing law
        # dropped the unreadable word and the rest was true): a one-word slot
        # value is digits or a numeral of some pack, else the record is not
        # lowered — and the line stays outside this court's jurisdiction.
        for значение in m.groups():
            if значение and " " not in значение and not re.fullmatch(r"[-\u2212]?\d+", значение) and not _числительное(значение):
                return строка
        вон = запись
        for имя, значение in zip(имена, m.groups()):
            вон = вон.replace(f"<{имя}>", значение)
        return вон
    return строка


_ТАБЛИЦЫ_ЧИСЛИТЕЛЬНЫХ = None


def _числительное(слово):
    """Is the word a numeral of some pack — in any DECLARED form, the oblique
    ones included («половина шести»: the pack's numeral_oblique, read by
    словари() as the court reads every numeral)?"""
    global _ТАБЛИЦЫ_ЧИСЛИТЕЛЬНЫХ
    if _ТАБЛИЦЫ_ЧИСЛИТЕЛЬНЫХ is None:
        _ТАБЛИЦЫ_ЧИСЛИТЕЛЬНЫХ = словари()[0]
    return слово.lower() in _ТАБЛИЦЫ_ЧИСЛИТЕЛЬНЫХ


def понизить_латех(строка):
    r"""LaTeX, переписанный в ту запись, которую суд уже читает.

    ЗАПИСЬ — НЕ ЗНАНИЕ. «$ \sqrt{16} = 4 $» есть ровно то же
    утверждение, что «2 √ 16 = 4», и суду, умеющему корень, недоставало
    единственно ЧТЕНИЯ. Потому здесь не новый суд, а понижение записи:
    дробь становится делением, корень — корнем, сумма по указателю —
    явной цепью слагаемых. Незнакомая команда остаётся как есть и
    честно лишает суд подсудности, а не толкуется наугад.
    """
    if "$" not in строка and "\\" not in строка:
        return строка
    т = строка.replace("$", " ")
    for знак, глиф in ЛАТЕХ_ЗНАКИ.items():
        т = т.replace(знак, f" {глиф} ")
    # СУММА ПО УКАЗАТЕЛЮ РАЗВОРАЧИВАЕТСЯ В ЦЕПЬ, а не считается тайно:
    # суд обязан видеть слагаемые, чтобы его ошибка была видна тоже.
    def сумма(м):
        имя, низ = м.group(1), int(м.group(2))
        верх, тело = int(м.group(3)), м.group(4).strip()
        if верх - низ > 64 or верх < низ:
            return м.group(0)
        куски = []
        for к in range(низ, верх + 1):
            кусок = re.sub(rf"\b{re.escape(имя)}\b", str(к), тело)
            if re.search(r"[^\W\d_]", кусок):
                return м.group(0)
            куски.append(f"( {кусок} )")
        return " ( " + " + ".join(куски) + " ) "
    т = re.sub(r"\\sum_\{(\w+)=(\d+)\}\^\{(\d+)\}([^=$]*)", сумма, т)
    for _ in range(8):
        новое = re.sub(r"\\frac\{([^{}]*)\}\{([^{}]*)\}",
                       r" ( \1 ) ÷ ( \2 ) ", т)
        новое = re.sub(r"\\sqrt\[(\d+)\]\{([^{}]*)\}",
                       r" ( \1 √ ( \2 ) ) ", новое)
        новое = re.sub(r"\\sqrt\{([^{}]*)\}", r" ( 2 √ ( \1 ) ) ", новое)
        новое = re.sub(r"\^\{(\d+)\}", r" ^ \1 ", новое)
        новое = re.sub(r"_\{[^{}]*\}", " ", новое)
        if новое == т:
            break
        т = новое
    return т


ВЫЗОВ = re.compile(r"[^\W\d_]\w*\s*\(")
# ни одной буквы: только цифры, знаки и пробелы
ЧИСТО_ЧИСЛОМ = re.compile(r"[\d\s+\-*/×÷=^√().,\u2212\u22c5]+")


def свернуть_скобки(строка, словарь):
    """Значение выражения со скобками, или None.

    Скобки — не украшение: «( ( 341 − 12 ) ÷ 7 ) × 3 + 12» есть
    законная запись, и суд, их не знающий, либо молчит, либо лжёт.
    Свёртка идёт изнутри наружу, самой глубокой парой.
    """
    текст = строка
    for _ in range(20):
        м = re.search(r"\(([^()]*)\)", текст)
        if not м:
            break
        значение = свернуть(разбор(м.group(1), *словарь))
        if значение is None:
            return None
        текст = текст[:м.start()] + f" {значение} " + текст[м.end():]
    return текст if "(" not in текст else None


# ЦЕПЬ ЧИСЛИТЕЛЬНЫХ ЕСТЬ УТВЕРЖДЕНИЕ О ПОРЯДКЕ, А НЕ УКРАШЕНИЕ.
# «one two three … twenty» и «1 2 3 … 20» говорят одно: числа идут
# подряд. Пропуск или перестановка — ложь, видимая глазом и невидимая
# всякому прибору, у которого нет своего суда для этого рода.
ЦЕПЬЮ = 5


_РАЗДЕЛИТЕЛИ = None


def разделители_перечня():
    """Знаки, которыми языки разделяют перечень, — по объявлению.

    Цепь есть перечень, а перечень у каждого письма свой: пробел у
    буквенных, «、» у китайского. Знак объявлен пакетом, и потому суд
    не должен ни угадывать его, ни держать список.
    """
    global _РАЗДЕЛИТЕЛИ
    if _РАЗДЕЛИТЕЛИ is None:
        вон = set()
        if ПАКЕТЫ.is_dir():
            for ф in sorted(ПАКЕТЫ.glob("*.json")):
                try:
                    п = json.loads(ф.read_text(encoding="utf-8"))
                except (OSError, ValueError):
                    continue
                з = п.get("list_separator")
                if з and not з.isspace():
                    вон.add(з)
        _РАЗДЕЛИТЕЛИ = frozenset(вон)
    return _РАЗДЕЛИТЕЛИ


def цепь_числительных(строка, словарь):
    """Идут ли числа подряд; None — строка не цепь."""
    с = строка.strip().rstrip(".。")
    for знак in разделители_перечня():
        с = с.replace(знак, " ")
    # ЦЕПЬ НЕ ДОЛЖНА СОДЕРЖАТЬ НИЧЕГО, КРОМЕ ЧИСЕЛ: «1 + 2 + 3 + 4 + 5»
    # есть недописанное действие, а не перечень, и суд, считавший
    # только числа, прочёл бы его цепью и объявил истиной.
    if re.search(r"[^\w\s]", с):
        return None
    # ЦЕПЬ НА ПИСЬМЕ БЕЗ ПРОБЕЛОВ ЕСТЬ ОДИН ТОКЕН ДЛЯ ТОГО, КТО НЕ
    # СПРОСИЛ. «一二三四五六七八九十» приходило сюда одним словом, и
    # суд молчал о целом роде — та же слепота, что была у разбора,
    # одним этажом выше. Резка берётся у ОБЪЯВЛЕНИЯ пакета.
    слова = None
    for образец, словарь_письма in письмена_без_пробела():
        if образец.search(с):
            слова = tokens(с, словарь_письма, spaced=False)
            break
    if слова is None:
        # ОБЪЯВЛЕННОЕ МНОГОСЛОВНОЕ ЕСТЬ ОДИН ТОКЕН — И В ЦЕПИ ТОЖЕ.
        # Турецкое одиннадцать есть «on bir», десять один; цепь
        # «… dokuz on on bir on iki …» наивным резом даёт
        # «…9, 10, 10, 1, 10, 2…» и объявляется ложью, будучи верной.
        # Тот же закон, что правит французское «dix-huit» и китайское
        # «等于», действует здесь; он жил в разборе и не жил в цепи —
        # один закон, два дома, и второй о нём не знал.
        образец, роль = объявленные_многословные(*словарь[:3])
        слова, хвост = [], 0
        if образец is not None:
            for м in образец.finditer(с):
                if роль[м.group()] != "v":
                    continue
                слова += re.findall(r"[^\W\d_]+|\d+", с[хвост:м.start()])
                слова.append(м.group())
                хвост = м.end()
        слова += re.findall(r"[^\W\d_]+|\d+", с[хвост:])
    if len(слова) < ЦЕПЬЮ:
        return None
    значения = []
    for слово in слова:
        в = (int(слово) if слово.isdigit() and слово.isascii()
             else словарь[0].get(слово.lower()))
        if в is None:
            return None
        значения.append(в)
    return all(б - а == 1 for а, б in zip(значения, значения[1:]))


# ВОПРОС О ЗНАЧЕНИИ ВЫРАЖЕНИЯ СВЯЗАН С ОТВЕТОМ ДОМОМ ПАРЫ (tools/asking.py,
# 04.09): «what is 220 + 11? 220 + 10 = 230.» — равенство верно, пара лжёт.
# Палата судит арифметику ПО ПРЕДЛОЖЕНИЯМ, и связь целой строки спрашивается
# здесь, до дробления.
def связь_пары(строка):
    """False — вопрос/задание формы значения не о том же, что ответ; None — не пара
    формы значения (связь спрашивать не с чего)."""
    пара = asking.пара(строка)
    if not пара or not asking.форма_значения(пара[0]):
        return None
    return asking.о_том_же(пара[0], пара[1])


def судить(строка, словарь):
    """(судимо, истинно) — РАВЕНСТВО ДВУХ ВЫРАЖЕНИЙ.

    Первая редакция требовала справа одну величину и оттого не судила
    законы вида «2 + 3 = 3 + 2» — триста показов переместительности,
    которые есть настоящие утверждения и могут быть ложными. Обе
    стороны сворачиваются одним правилом; тождества с буквами
    («z + x = x + z») по-прежнему несудимы и попадают в счёт
    неразобранного, ибо величин в них нет вовсе.
    """
    # ЧИСЛО В ВЫЗОВЕ ФУНКЦИИ ЕСТЬ АРГУМЕНТ, А НЕ СЛАГАЕМОЕ.
    # «factorial(5) = 5 × factorial(4)» — истинное рекурсивное
    # определение, а суд читал его как «5 = 5 × 4» и звал ложью.
    # Термы, которых суд вычислить не может, лишают его подсудности:
    # честный отказ, а не догадка.
    if связь_пары(строка) is False:
        return True, False
    цепь = цепь_числительных(строка, словарь)
    if цепь is not None:
        return True, цепь
    строка = понизить_латех(понизить_словами(
        понизить_именами(строка)))
    if ВЫЗОВ.search(строка):
        return False, False
    # ОПЕРАЦИЯ СЧИТЫВАЕТСЯ ДО СВЁРТКИ СКОБОК, А НЕ ПОСЛЕ. Свёртка
    # СЪЕДАЕТ операцию вместе со скобкой, и граница «равенство без
    # операции несудимо» глохла на всяком показе, где всё действие
    # стояло в скобках: «( 2 + 3 ) = 6» — ложь, которую суд не видел.
    операций = sum(р == "o" for р, _ in разбор(строка, *словарь))
    if "(" in строка or ")" in строка:
        строка = свернуть_скобки(строка, словарь)
        if строка is None:
            return False, False
    ряд = обрамление_прочь(разбор(строка, *словарь))
    if not any(р == "e" for р, _ in ряд):
        return False, True
    делит = [i for i, (р, _) in enumerate(ряд) if р == "e"]
    if len(делит) > 1 and ЧИСТО_ЧИСЛОМ.fullmatch(строка.strip()):
        # ЦЕПЬ РАВЕНСТВ ЕСТЬ НЕСКОЛЬКО РАВЕНСТВ, И КАЖДОЕ ОТДЕЛЬНО.
        # ЦЕПЬ ЧИТАЕТСЯ ТОЛЬКО В ЧИСТОЙ ЗАПИСИ: «if x > 4 then y = 1
        # else y = 0» несёт два знака равенства, между которыми стоят
        # СЛОВА, — и суд, слова пропускающий, прочёл бы ветвление
        # цепью и объявил ложью сорок восемь честных строк.
        # «2^2 − 3^2 = ( 2 − 3 ) × ( 2 + 3 ) = −5» утверждает две
        # вещи, и суд, требовавший ровно одного знака равенства,
        # отказывался от обеих — а именно в цепи и живёт выкладка.
        части, прежний = [], 0
        for i in делит:
            части.append(ряд[прежний:i])
            прежний = i + 1
        части.append(ряд[прежний:])
        значения = [свернуть(ч) for ч in части]
        if any(з is None for з in значения):
            return False, False
        return True, len(set(значения)) == 1
    if len(делит) != 1:
        return False, False
    лево, право = ряд[:делит[0]], ряд[делит[0] + 1:]
    # РАВЕНСТВО БЕЗ ЕДИНОЙ ОПЕРАЦИИ НЕ УТВЕРЖДАЕТ АРИФМЕТИКИ. «5 минут
    # равно 300 секунд» и «one week equals 7 days» суть ПЕРЕВОДЫ ЕДИНИЦ
    # (род конверсий), и числа в них равны лишь вместе с единицами,
    # которых прибор не читает. Обобщив суд на две стороны, я тут же
    # объявил ложными 375 честных переводов — граница поставлена там,
    # где кончается арифметика, а не там, где кончается разбор.
    if not операций and not ЧИСТО_ЧИСЛОМ.fullmatch(строка.strip()):
        # РАВЕНСТВО БЕЗ ОПЕРАЦИИ НЕ УТВЕРЖДАЕТ АРИФМЕТИКИ — если в нём
        # есть СЛОВА: «5 минут равно 300 секунд» равно лишь вместе с
        # единицами. Но «1 = 1» слов не имеет вовсе, и отказывать ему
        # значит путать границу рода с границей разбора: основание
        # индукции стояло вне суда именно так.
        return False, False
    слева = свернуть(лево)
    справа = свернуть(право)
    if слева is None or справа is None:
        # неточное деление, названное точным, есть ЛОЖЬ; отсутствие
        # величин — несудимость. Различаются по форме, а не по итогу.
        стороны = ("".join(р for р, _ in ряд[:делит[0]]),
                   "".join(р for р, _ in ряд[делит[0] + 1:]))
        # ПОСЛАБЛЕНИЕ ДАНО МИНУСУ, А НЕ ВСЯКОЙ ОПЕРАЦИИ. Разрешив
        # любой знак впереди, суд принял за сторону обрубок «/ 2»,
        # оставшийся от неразобранного слова, — и объявил ложью
        # полторы сотни честных показов. Вычитание из ничего есть
        # смысл, деление ничего на два — обломок разбора.
        def сторона_годна(форма, часть):
            минусом = bool(часть) and часть[0] == ("o", "-")
            образец = r"o?v(?:ov)*" if минусом else r"v(?:ov)*"
            return bool(re.fullmatch(образец, форма))

        if all(сторона_годна(ф, ч)
               for ф, ч in zip(стороны, (лево, право))):
            return True, False
        return False, False
    return True, слева == справа


# Пробел после знака уже отделяет дробь «1.5» — лишний запрет на цифру
# перед точкой не пускал границу туда, где она есть («исходов 6. доля
# шестёрки»). И двойной обратный слэш от heredoc требовал ЛИТЕРАЛЬНОГО
# слэша: правка, не проверенная опытом, не правка.
ПРЕДЛОЖЕНИЕ = re.compile(r"[.。?!]+(?:\s+|$)")


def предложения(строка):
    """Строка режется на предложения ПЕРЕД судом.

    Одна строка часто несёт несколько утверждений, и число из
    предыдущего втекало в равенство следующего: «кость: исходов 6.
    доля шестёрки = 1/6» читалось как «6 = 1/6» и объявлялось ложью.
    Точка между цифрами (1.5) границей не считается.
    """
    return [ч for ч in ПРЕДЛОЖЕНИЕ.split(строка) if ч and ч.strip()]


_ПОЛЯРНОСТИ = None


def полярности():
    """({слова «да»}, {слова «нет»}) — объявлены пакетами языков (polarity).

    Отказ, а не догадка: слово, которое один пакет зовёт «да», а другой
    «нет», судить нельзя — прибор скажет об этом и замолчит.
    """
    global _ПОЛЯРНОСТИ
    if _ПОЛЯРНОСТИ is not None:
        return _ПОЛЯРНОСТИ
    да, нет = set(), set()
    if ПАКЕТЫ.is_dir():
        for ф in sorted(ПАКЕТЫ.glob("*.json")):
            try:
                п = json.loads(ф.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            пол = п.get("polarity") or {}
            да |= {str(с).lower() for с in пол.get("yes", [])}
            нет |= {str(с).lower() for с in пол.get("no", [])}
    if да & нет:
        print(f"АРИФМЕТИКА ОТКАЗ: слово «{sorted(да & нет)[0]}» есть и «да», и «нет» — судить нельзя")
        sys.exit(2)
    _ПОЛЯРНОСТИ = (frozenset(да), frozenset(нет))
    return _ПОЛЯРНОСТИ


ПЕРВОЕ_СЛОВО = re.compile(r"^[^\w¿¡]*([^\W\d_]+)", re.UNICODE)


def судить_строку(строка, словарь):
    """[(судимо, истинно)] по предложениям строки — с ОКНОМ ВОПРОСА.

    ЦИТАТА В ВОПРОСЕ СУДИТСЯ ОТВЕТОМ (05.09). «правда ли, что дважды два —
    пять? нет, дважды два — четыре: 2 × 2 = 4.» истинна как целое: ложное
    равенство в ней ПРОЦИТИРОВАНО вопросом, а не утверждено. Суд, читавший
    предложение как предложение, находил в вопросе «2 × 2 = 5» и звал строку
    ложью — и корпус не смел отказывать лжи с основанием, ибо не мог её
    процитировать. Окно: равенство в предложении, кончающемся «?», истинно
    ровно тогда, когда согласно со словом, открывающим ответ, — после «нет»
    оно обязано быть ложным, после «да» истинным; слово полярности объявляет
    пакет языка. Вопрос без слова полярности за ним судится, как прежде.
    Связь пары — по целой строке (04.09): вопрос формы значения обязан быть
    о том же, что ответ.
    """
    if связь_пары(строка) is False:
        return [(True, False)]
    части = предложения(строка)
    вон = [судить(ч, словарь) for ч in части]
    # ОТВЕТ ЧЕРЕЗ ДВОЕТОЧИЕ — РАВЕНСТВО С ЗАЯВЛЕННЫМ ИТОГОМ (05.09, суд родов: 1 424
    # строки английских миров историй — «Felix holds 4 cookies: 3 + 1 = 4.» — не
    # читал ни один суд, умеющий считать: предложение с двоеточием не есть
    # равенство целиком, и суд молчал). Хвост после двоеточия судится как
    # равенство, и последнее число перед двоеточием обязано быть его итогом.
    for i, ч in enumerate(части):
        if вон[i][0] or ": " not in ч:
            continue
        голова, хвост = ч.rsplit(": ", 1)
        судимо, истинно = судить(хвост, словарь)
        if not судимо:
            continue
        # СУДИТСЯ РАВЕНСТВО, А НЕ ГОЛОВА: число перед двоеточием бывает ответом («7:»),
        # ярлыком («шаг 1:»), приговором («22 non è primo:») или объяснением («было 10,
        # а отдано 3:») — согласие ответа с итогом судят суды историй; первая проба
        # сверяла голову с итогом и назвала ложью 1 500 честных строк семи миров (05.09).
        вон[i] = (True, истинно)
    # ЗНАК КОНЦА ПРЕДЛОЖЕНИЯ РЕЗКА СЪЕДАЕТ — вопрос узнаётся по знаку, снятому
    # тем же образцом (первая редакция окна глядела на хвост части и не видела
    # ни одного вопроса: «?» уже был отрезан).
    знаки = [м.group(0).strip() for м in ПРЕДЛОЖЕНИЕ.finditer(строка)]
    да, нет = полярности()
    for i, ч in enumerate(части):
        if i >= len(знаки) or "?" not in знаки[i] or not вон[i][0] or i + 1 >= len(части):
            continue
        м = ПЕРВОЕ_СЛОВО.match(части[i + 1])
        слово = м.group(1).lower() if м else ""
        if слово in нет:
            вон[i] = (True, not вон[i][1])
        # слово «да» и отсутствие слова оставляют суд предложения как есть
    return вон


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        # СУД ЭТОТ ОТКАЛИБРОВАН НА ПОКАЗЫ и прозу судить не вправе:
        # на научном тексте он обвинял честное («T-113» — дефис в
        # имени, «48 = 7² − 1» — степень, «5 - 3 = 3 - 5» — ложь,
        # ПРИВЕДЁННАЯ ради опровержения). Род текста объявляет мир.
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"АРИФМЕТИКА ОТКАЗ: {беда}")
        sys.exit(2)


ПОДСАДКИ_ОКНА = (
    # (строка, ожидаемый вердикт вопроса): цитата ложного равенства с «no» — истина;
    # верное равенство, отвергнутое «no», — ложь; без слова полярности — суд как прежде
    ("è vero che due per due fa cinque? no, due per due fa quattro: 2 × 2 = 4.", (True, True)),
    ("è vero che due per due fa quattro? no, due per due fa cinque: 2 × 2 = 5.", (True, False)),
    ("è vero che due per due fa quattro? sì, due per due fa quattro: 2 × 2 = 4.", (True, True)),
    ("è vero che due per due fa cinque? due per due fa quattro.", (True, False)),
)


def _зубы_окна(словарь):
    """Окно вопроса обязано ловить своё «нет» прежде, чем судить корпус."""
    for строка, ждём in ПОДСАДКИ_ОКНА:
        если = судить_строку(строка, словарь)[0]
        if если != ждём:
            print(f"АРИФМЕТИКА ОТКАЗ: окно вопроса дало {если}, ждали {ждём}: {строка[:60]}")
            return False
    return True


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    словарь = словари()
    if not _зубы_окна(словарь):
        return 2
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("АРИФМЕТИКА ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = неразобрано = 0
    примеры = []
    for путь in пути:
        свои_ложные = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for сырая in поток:
              for строка, (судимо, истинно) in zip(предложения(сырая), судить_строку(сырая, словарь)):
                if судимо:
                    судимых += 1
                    if not истинно:
                        ложных += 1
                        свои_ложные += 1
                        if len(примеры) < 4:
                            примеры.append(
                                f"{путь.name}: {строка.strip()[:70]}")
                elif not истинно:
                    неразобрано += 1
        if свои_ложные:
            print(f"  {путь.name:<30} ложных {свои_ложные}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"АРИФМЕТИКА {поза}: {ложных} ложных равенств из {судимых} "
          f"судимых ({len(пути)} файлов, неразобрано {неразобрано})")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
