# тому, кто числа ЧИТАЕТ (этот суд), и тому, кто их ГОВОРИТ (своды,
# произносящие «сорок два минус пять»); закон, живущий у одного из
# двоих, назавтра расходится сам с собой. См. tools/numerals.py.
