_МЕРА = re.compile(r" · (definitions|references|symbols|occurrences) (\d+)")


def _другой(язык, sort):
    return next(с_ for с_ in H.СОРТ[язык] if с_ != sort)


def _порчи_сорта(с, язык, род, форма, мир_, строки_):
    """Слово сорта — сборкой дома с другим сортом (причастие согласовано, как пишет дом): ответ об определении, у формы
    «сорт» — и вопрос, и вопрос об одном сорте при ответе о другом; первый символ перечня; сорт в приказе
    переименования."""
    if not мир_:
        return []
    дыры, мир_ = H.ПЕРЕПИСЬ.get(с, {}), мир_[:-1]
    if род == H.ОПРЕДЕЛЕНИЕ:
        (строка_,) = строки_
        sort, f, n = строка_["sort"], строка_["path"], строка_["line"]
        другой = _другой(язык, sort)
        вон = [H.сборка_определения(язык, форма, дыры["x"], мир_, другой, f, n)]
        if форма in H.ФОРМЫ_СОРТОМ:
            метка = A._реплика(язык, "мир", "")
            вон.append(с.split(метка, 1)[0] + метка + вон[0].split(метка, 1)[1])
            вон.append(вон[0].split(метка, 1)[0] + метка + с.split(метка, 1)[1])
        return вон
    if род == H.СИМВОЛЫ:
        тройки = [(с_["sort"], с_["name"], с_["line"]) for с_ in строки_]
        порча = [(_другой(язык, тройки[0][0]),) + тройки[0][1:]] + тройки[1:]
        return [с.replace(H.символы(язык, тройки), H.символы(язык, порча), 1)]
    if форма in H.ФОРМЫ_СОРТОМ and род in (H.УПОМИНАНИЯ, H.НЕ_УПОМИНАЕТСЯ):
        # вопрос о символе другим родом, ответ тот же: сорт вопроса — не сорт определения
        x = дыры["x"]
        sort = _сорт_имени(x)
        было = H._вопрос_текст(язык, "q_упом_с", x=x, С=H.сорт(язык, sort, x), С2=H.сорт(язык, sort, x, 1))
        стало = H._вопрос_текст(язык, "q_упом_с", x=x, С=H.сорт(язык, _другой(язык, sort), x),
                                С2=H.сорт(язык, _другой(язык, sort), x, 1))
        return [с.replace(было, стало, 1)]
    if форма == "сорт" and род in (H.ПЕРЕИМЕНОВАНИЕ, H.ПЕРЕИМЕНОВАНИЕ_ОТКАЗ):
        x, y = дыры["x"], дыры["y"]
        sort = _сорт_имени(x)
        return [с.replace(H._приказ_переименования(язык, форма, x, y, sort),
                          H._приказ_переименования(язык, форма, x, y, _другой(язык, sort)), 1)]
    return []


def _порчи(с, язык, род, форма):
    """Подсадки от страницы дома: последнее число итога на единицу больше; первое число леджера другое; мера хода
    мира другая; последний путь итога — другим файлом мира кода; слово сорта — сборкой дома с другим сортом; перечень
    итога (места, символы, файлы правки) — дверью дома над строками хода в обратном порядке."""
    вон = []
    орг = с.rfind(A._реплика(язык, "орг", ""))
    числа = [м for м in re.finditer(r"(?<![\w/.])\d+(?![\w/.])", с) if м.start() > орг]
    if числа:
        п = числа[-1]
        вон.append(с[:п.start()] + str(int(п.group()) + 1) + с[п.end():])
    леджеры = list(re.finditer(r"(\d+)( [+−] \d+)* = (\d+)", с))
    if леджеры:
        л = леджеры[-1]
        вон.append(с[:л.start(1)] + str(int(л.group(1)) + 2) + с[л.end(1):])
    мера = _МЕРА.search(с)
    if мера:
        вон.append(с[:мера.start(2)] + str(int(мера.group(2)) + 3) + с[мера.end(2):])
    пути = [м for м in re.finditer(_ПУТЬ, с) if м.start() > орг]
    if пути:
        п = пути[-1]
        чужой = next((x for x in К.ФАЙЛЫ_КОДА if x != п.group() and x not in с), None)
        if чужой:
            вон.append(с[:п.start()] + чужой + с[п.end():])
    мир_ = next((т for роль, т in R.реплики(с, язык) if роль == "мир"), None)
    строки_ = К.клетки(мир_[:-1])[1] if мир_ else []
    вон += _порчи_сорта(с, язык, род, форма, мир_, строки_)
    if len(строки_) >= 2:
        перечень = {H.УПОМИНАНИЯ: lambda ряд: H.места(язык, [(с_["line"], с_["path"]) for с_ in ряд]),
                    H.СИМВОЛЫ: lambda ряд: H.символы(язык, [(с_["sort"], с_["name"], с_["line"]) for с_ in ряд]),
                    H.ПЕРЕИМЕНОВАНИЕ: lambda ряд: H.файлы(язык, [с_["path"] for с_ in ряд]),
                    H.ПЛАН: lambda ряд: H.файлы(язык, [с_["path"] for с_ in ряд])}.get(род)
        if перечень is not None:
            было, стало = перечень(строки_), перечень(строки_[::-1])
            вон.append(с[:орг] + с[орг:].replace(было, стало, 1))
    return [в for в in dict.fromkeys(вон) if в != с]


def _самопроверка():
    беды = [с for с in H.ПОКАЗЫ if _судить(с) != (True, True)]
    порч = пойманных = 0
    for с, (язык, род, форма, _р) in sorted(H.ПОКАЗЫ.items()):
        for порча in _порчи(с, язык, род, форма):
            порч += 1
            вердикт = _судить(порча)
            if вердикт == (True, False):
                пойманных += 1
            elif вердикт == (True, True):
                беды.append(f"порча прошла: {порча[:220]}")
            else:
                беды.append(f"порча — молчание: {порча[:220]}")
        р = A.РЕЧЬ[язык]
        да = A._реплика(язык, "польз", р["да"] + ".") + " "
        нет = A._реплика(язык, "польз", р["нет"] + ".") + " "
        порчи = ([с.replace(да, "", 1), с.replace(да, нет, 1)] if да in с
                 else [с.replace(нет, да, 1)] if нет in с else [])
        for порча in порчи:
            порч += 1
            if _судить(порча) == (True, False):
                пойманных += 1
            else:
                беды.append(f"порча устройства не ложь: {порча[:220]}")
    # ПОРЧА ХОДА — от дома: под вопросом об одном имени — ход мира о другом имени того же рода (сервер ответил не на тот
    # акт) — ложь, хотя итог верен своему ходу
    ходы = {}
    for с, (язык, род, форма, _р) in H.ПОКАЗЫ.items():
        ходы.setdefault((язык, род, форма), []).append(с)
    for (язык, род, форма), страницы in ходы.items():
        if len(страницы) < 2:
            continue
        a, b = страницы[0], страницы[1]
        мир_a = next(т for роль, т in R.реплики(a, язык) if роль == "мир")
        мир_b = next(т for роль, т in R.реплики(b, язык) if роль == "мир")
        if мир_a == мир_b:
            continue
        порч += 1
        порча = a.replace(мир_a, мир_b, 1)
        if _судить(порча) == (True, False):
            пойманных += 1
        else:
            беды.append(f"ход чужого акта не ложь: {порча[:220]}")
    # ПОРЧА СОСТОЯНИЯ — от дома: под планом прогон печатает отчёт объявленного проекта ДО правки (тот же прогон, те же
    # запуски «до») — отчёт не того мира, ложь
    for с, (язык, род, форма, _р) in H.ПОКАЗЫ.items():
        if род != H.ПЛАН:
            continue
        ход2 = [т for роль, т in R.реплики(с, язык) if роль == "мир"][1][:-1]
        имя = R.ИМЕНА_ПРОГОНОВ[H.ПЕРЕПИСЬ[с]["Я"]]
        прежний = W.текст(W.прогон(имя, Р.снятое(имя), R.клетки(ход2)[0]["runs"] - 1))
        if прежний == ход2:
            continue
        порч += 1
        порча = с.replace(ход2, прежний, 1)
        if _судить(порча) == (True, False):
            пойманных += 1
        else:
            беды.append(f"отчёт проекта до правки под планом не ложь: {порча[:220]}")
    return беды, порч, пойманных, len(H.ПОКАЗЫ)


