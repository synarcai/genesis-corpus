def _объекты():
    """Имена и файлы мира кода: файлы объявленного проекта, объекты и доводы снятых актов."""
    с, вон = К.семя(), set(К.ПРОЕКТ)
    for ключ in list(с.get("reads", {})) + list(с.get("renames", {})):
        акт = json.loads(ключ)
        вон.add(акт["object"])
        if акт.get("arg") is not None:
            вон.add(bytes(акт["arg"]).decode("utf-8"))
    return frozenset(вон)


