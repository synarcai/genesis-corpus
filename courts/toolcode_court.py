def М(имя):
    return f"\x01{имя}\x01"


def _образец(текст):
    куски, счёт = [], {}
    for кусок in re.split(r"(\x01[^\x01]+\x01)", текст):
        if кусок.startswith("\x01"):
            имя = кусок[1:-1]
            счёт[имя] = счёт.get(имя, 0) + 1
            куски.append(f"(?P<h{len(куски)}_{счёт[имя]}_{_ЛАТ.get(имя, имя)}>{_КЛАСС[имя]})")
        else:
            куски.append(re.escape(кусок))
    return re.compile("^" + "".join(куски) + "$")


def _рамки():
    """{язык: [(образец, род, форма, сорт)]} — рамки берутся у сборки дома с метками вместо частей; сорт — слово
    сорта, какое рамка говорит (у рамок без слова сорта — None)."""
    вон = {}
    x, y, f, n, N, L, МИР, Мм, F = (М(и) for и in ("x", "y", "f", "n", "N", "L", "МИР", "М", "F"))
    for язык in H.ЯЗЫКИ:
        рамки = []
        р_ = A.РЕЧЬ[язык]
        да = A._реплика(язык, "польз", р_["да"] + ".") + " "
        нет = A._реплика(язык, "польз", р_["нет"] + ".") + " "

        def положить(текст, род, форма, sort=None):
            рамки.append((_образец(текст), род, форма, sort))
            if да in текст:
                рамки.append((_образец(текст.replace(да, "", 1)), СКРЕЩЕНО, форма, sort))
                рамки.append((_образец(текст.replace(да, нет, 1)), СКРЕЩЕНО, форма, sort))
            elif нет in текст:
                рамки.append((_образец(текст.replace(нет, да, 1)), СКРЕЩЕНО, форма, sort))

        сорта = tuple(H.СОРТ[язык])
        мир_метка = A._реплика(язык, "мир", "")
        # ВОПРОСЫ: определение — всякая форма при всяком слове сорта ответа; у формы «сорт» слово сорта говорит и вопрос,
        # и рамка держит пару (сорт вопроса, сорт ответа) — вопрос об одном сорте с ответом о другом ложен, а не нем;
        # имени нет — формы без слова сорта
        for форма in H.ФОРМЫ_ОПРЕДЕЛЕНИЯ:
            for sort in сорта:
                ответ_ = H.сборка_определения(язык, форма, x, МИР, sort, f, n)
                if форма not in H.ФОРМЫ_СОРТОМ:
                    положить(ответ_, H.ОПРЕДЕЛЕНИЕ, форма, sort)
                    continue
                for sort_q in сорта:
                    вопрос_ = H.сборка_определения(язык, форма, x, МИР, sort_q, f, n)
                    положить(вопрос_.split(мир_метка, 1)[0] + мир_метка + ответ_.split(мир_метка, 1)[1],
                             H.ОПРЕДЕЛЕНИЕ, форма, (sort_q, sort))
            if форма not in H.ФОРМЫ_СОРТОМ:
                положить(H.сборка_определения(язык, форма, x, МИР), H.ИМЕНИ_НЕТ, форма)
        for форма in H.ФОРМЫ_УПОМИНАНИЙ:
            # у формы «где·сорт» вопрос называет символ родом: рамка на всякий сорт, суд сверяет его с определением
            for sort in (сорта if форма in H.ФОРМЫ_СОРТОМ else (None,)):
                положить(H.сборка_упоминаний(язык, форма, x, МИР, N, L, Мм, sort=sort), H.УПОМИНАНИЯ, форма, sort)
                положить(H.сборка_упоминаний(язык, форма, x, МИР, sort=sort), H.НЕ_УПОМИНАЕТСЯ, форма, sort)
            if форма not in H.ФОРМЫ_СОРТОМ:
                положить(H.сборка_упоминаний(язык, форма, x, МИР, нет=True), H.ИМЕНИ_НЕТ, форма + "·упом")
        for форма in H.ФОРМЫ_СИМВОЛОВ:
            положить(H.сборка_символов(язык, форма, f, МИР, Мм), H.СИМВОЛЫ, форма)
            положить(H.сборка_символов(язык, форма, f, МИР), H.СИМВОЛОВ_НЕТ, форма)
            положить(H.сборка_символов(язык, форма, f, МИР, нет=True), H.ФАЙЛА_НЕТ, форма)
        # АКТ: всякий регистр дома, всякая форма приказа (форма «сорт» — при всяком слове сорта); отказ пользователем —
        # со счётом упоминаний и без него («нигде»); невозможные — отказ мира по имени
        for р in H.РЕГИСТРЫ:
            for форма in H.ФОРМЫ_ПЕРЕИМЕНОВАНИЯ:
                for sort in (сорта if форма == "сорт" else (None,)):
                    положить(H.сборка_переименования(язык, H.ПЕРЕИМЕНОВАНИЕ, форма, р, x, y, МИР, sort, N, L, F),
                             H.ПЕРЕИМЕНОВАНИЕ, форма, sort)
                    положить(H.сборка_переименования(язык, H.ПЕРЕИМЕНОВАНИЕ_ОТКАЗ, форма, р, x, y, МИР, sort, N, L),
                             H.ПЕРЕИМЕНОВАНИЕ_ОТКАЗ, форма, sort)
                    положить(H.сборка_переименования(язык, H.ПЕРЕИМЕНОВАНИЕ_ОТКАЗ, форма, р, x, y, МИР, sort),
                             H.ПЕРЕИМЕНОВАНИЕ_ОТКАЗ, форма, sort)
                    for род in (H.ПЕРЕИМЕНОВАНИЕ_ЗАНЯТО, H.ПЕРЕИМЕНОВАНИЕ_НЕТ):
                        положить(H.сборка_переименования(язык, род, форма, р, x, y, МИР, sort), род, форма, sort)
        # ПЛАН ДВУХ МИРОВ: правка и прогон; отказ пользователем — со счётом упоминаний и без него
        Я, МИР1, МИР2, N1, L1, F1 = (М(и) for и in ("Я", "МИР1", "МИР2", "N1", "L1", "F1"))
        положить(H.сборка_плана(язык, H.ПЛАН, x, y, Я, МИР1, N1, L1, F1, МИР2, М("ЧИСЛА"), М("ИСХОД"), N, L),
                 H.ПЛАН, "план")
        положить(H.сборка_плана(язык, H.ПЛАН_ОТКАЗ, x, y, Я, МИР1, N1, L1), H.ПЛАН_ОТКАЗ, "план")
        положить(H.сборка_плана(язык, H.ПЛАН_ОТКАЗ, x, y, Я, МИР1), H.ПЛАН_ОТКАЗ, "план")
        вон[язык] = рамки
    return вон


