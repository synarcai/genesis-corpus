def _ход(род, форма, зн):
    """Ход мира, какой обязан показать мир: акт по дырам страницы — ответ сервера из семени."""
    if род == H.ОПРЕДЕЛЕНИЕ or род == H.ИМЕНИ_НЕТ and not форма.endswith("·упом"):
        return К.ход("define", зн["x"])
    if род in (H.УПОМИНАНИЯ, H.НЕ_УПОМИНАЕТСЯ, H.ИМЕНИ_НЕТ, H.ПЕРЕИМЕНОВАНИЕ_ОТКАЗ):
        return К.ход("refs", зн["x"])
    if род in (H.СИМВОЛЫ, H.СИМВОЛОВ_НЕТ, H.ФАЙЛА_НЕТ):
        return К.ход("symbols", зн["f"])
    return К.ход("rename", зн["x"], зн["y"])


def _счёт_верен(язык, зн, k):
    """Счёт итога — клетка хода: фраза раз и леджер «k = k»; нулю — ни фразы, ни леджера («нигде»)."""
    if k == 0:
        return "N" not in зн and "L" not in зн
    return зн.get("N") == T.раз(язык, k) and зн.get("L") == R._л(k, 0)


def _сорт_имени(x):
    """Сорт имени — клетка sort его определения в семени (слово сорта приказа «rename the function …»)."""
    (sort,) = dict.fromkeys(К.поле(К.ход("define", x), "sort"))
    return sort


def _итог_верен(язык, род, форма, sort, зн):
    """Итог — клетки хода мира страницы (он уже равен ходу семени)."""
    меры, строки_, отказ_ = К.клетки(зн["МИР"])
    почему = отказ_.split(" ", 1)[0] if отказ_ is not None else None
    if род in (H.ИМЕНИ_НЕТ, H.ФАЙЛА_НЕТ, H.ПЕРЕИМЕНОВАНИЕ_НЕТ):
        return почему == "not-there"
    if род == H.ПЕРЕИМЕНОВАНИЕ_ЗАНЯТО:
        return почему == "already-there"
    if отказ_ is not None:
        return False
    if род == H.ОПРЕДЕЛЕНИЕ:
        # одно определение: сорт, путь и номер строки — его клетки; у формы «сорт» вопрос говорит тот же сорт
        if isinstance(sort, tuple):
            if sort[0] != sort[1]:
                return False
            sort = sort[1]
        return (меры.get(К.СЧЁТ["define"]) == 1 and len(строки_) == 1 and строки_[0].get("sort") == sort
                and строки_[0].get("path") == зн["f"] and строки_[0].get("line") == зн["n"])
    if род in (H.УПОМИНАНИЯ, H.НЕ_УПОМИНАЕТСЯ):
        if форма in H.ФОРМЫ_СОРТОМ and sort != _сорт_имени(зн["x"]):
            return False
        k = меры.get(К.СЧЁТ["refs"])
        if k is None or len(строки_) != k or (род == H.УПОМИНАНИЯ) != (k > 0) or not _счёт_верен(язык, зн, k):
            return False
        return k == 0 or зн["М"] == H.места(язык, [(с["line"], с["path"]) for с in строки_])
    if род in (H.СИМВОЛЫ, H.СИМВОЛОВ_НЕТ):
        k = меры.get(К.СЧЁТ["symbols"])
        if k is None or len(строки_) != k or (род == H.СИМВОЛЫ) != (k > 0):
            return False
        return k == 0 or зн["М"] == H.символы(язык, [(с["sort"], с["name"], с["line"]) for с in строки_])
    if форма == "сорт" and sort != _сорт_имени(зн["x"]):
        return False
    if род == H.ПЕРЕИМЕНОВАНИЕ_ОТКАЗ:
        # чтение «до»: упоминания имени, без правки
        k = меры.get(К.СЧЁТ["refs"])
        return k is not None and len(строки_) == k and _счёт_верен(язык, зн, k)
    if род == H.ПЕРЕИМЕНОВАНИЕ:
        k = меры.get(К.СЧЁТ["rename"])
        пути = [с["path"] for с in строки_]
        return bool(k) and bool(пути) and _счёт_верен(язык, зн, k) and зн["F"] == H.файлы(язык, пути)
    return False


def _план_верен(язык, род, зн):
    """План двух миров: первый ход — ход семени мира кода (правка, у отказа — чтение «до»), его итог — его клетки;
    второй — прогон мира процесса на проекте после этой правки (`codeworld.снятое_после`) с запусками «до» + 1, итог —
    числа отчёта бегуна, исход по коду выхода и леджер запусков."""
    x, y = зн["x"], зн["y"]
    первый = {"МИР": зн["МИР1"], **{к: зн[к + "1"] for к in ("N", "L", "F") if к + "1" in зн}, "x": x, "y": y}
    if род == H.ПЛАН_ОТКАЗ:
        return (W.текст(К.ход("refs", x)) == зн["МИР1"]
                and _итог_верен(язык, H.ПЕРЕИМЕНОВАНИЕ_ОТКАЗ, "канон", None, первый))
    if W.текст(К.ход("rename", x, y)) != зн["МИР1"] or not _итог_верен(язык, H.ПЕРЕИМЕНОВАНИЕ, "канон", None, первый):
        return False
    имя = R.ИМЕНА_ПРОГОНОВ[зн["Я"]]
    снятое = К.снятое_после(x, y, имя)
    было = R.клетки(зн["МИР2"])[0]["runs"] - 1
    if W.текст(W.прогон(имя, снятое, было)) != зн["МИР2"]:
        return False
    if зн["N"] != A.запусков(язык, было + 1) or зн["L"] != R._л(было, 1):
        return False
    числа, исход_ = R.исход(язык, зн["Я"], снятое)
    return (зн["ЧИСЛА"] == числа and зн["ИСХОД"] == исход_
            and runnerread.стоят("\n".join(снятое["report"]), R.строки_итога(снятое)))


def _вердикт(язык, род, форма, sort, зн):
    if род in (H.ПЛАН, H.ПЛАН_ОТКАЗ):
        return _план_верен(язык, род, зн)
    ход_ = _ход(род, форма, зн)
    if W.текст(ход_) != зн["МИР"]:
        return False
    return _итог_верен(язык, род, форма, sort, зн)


def _судить(строка):
    с = строка.strip()
    if not с:
        return False, False
    язык = next((я for начало, я in _НАЧАЛО.items() if с.startswith(начало)), None)
    if язык is None:
        return False, False
    совпал = False
    for образ, род, форма, sort in РАМКИ[язык]:
        м = образ.match(с)
        if not м:
            continue
        if род == СКРЕЩЕНО:
            совпал = True
            continue
        зн, согласна = _значения(м)
        if not _свой(зн):
            continue
        совпал = True
        try:
            if согласна and _вердикт(язык, род, форма, sort, зн):
                return True, True
        except (KeyError, ValueError, IndexError, TypeError):
            continue
    return (True, False) if совпал else (False, False)


