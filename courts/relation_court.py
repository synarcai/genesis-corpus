def _порядок(г):
    """(множество, имя) — и порядок обязан БЫТЬ порядком на нём."""
    множество, имя = _разбор(г[1], г[0])
    if имя is None:
        return None, None
    # ПОРЯДКОМ ЗОВЁТСЯ НЕ ВСЯКОЕ ОТНОШЕНИЕ: рефлексивность и
    # транзитивность проверяются прежде всякого утверждения о «ниже»,
    # «наибольшем» и «цепи», и сверх того сводятся два встречных хода —
    # правило против достижимости по покрытиям.
    if о.свидетель_рефлексивности(имя, множество) is not None:
        return None, None
    if о.свидетель_транзитивности(имя, множество) is not None:
        return None, None
    if о.порядок_обходом(имя, множество) != set(о.пары(имя, множество)):
        return None, None
    return множество, имя


