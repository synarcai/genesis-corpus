def _расстояние(г):
    a, b, d = г[0], г[1], int(г[2])
    return (_узел_графа(a) and _узел_графа(b)
            and о.расстояние(a, b) == d)


def _симметрия(г):
    a, b, ещё_b, ещё_a = г
    if not (_узел_графа(a) and _узел_графа(b)):
        return False
    return (a == ещё_a and b == ещё_b
            and о.расстояние(a, b) == о.расстояние(b, a))


def _треугольник(г):
    a, b, c = г[0], г[1], г[2]
    d, d1, d2 = int(г[3]), int(г[4]), int(г[5])
    if not all(_узел_графа(и) for и in (a, b, c)):
        return False
    return (о.расстояние(a, b) == d and о.расстояние(a, c) == d1
            and о.расстояние(c, b) == d2 and d <= d1 + d2)


def _пространство(_г_):
    """ЗАКОНЫ РАССТОЯНИЯ ПРОВЕРЯЮТСЯ НА ВСЁМ, А НЕ НА ПРИМЕРЕ."""
    for a in о.УЗЛЫ:
        for b in о.УЗЛЫ:
            d = о.расстояние(a, b)
            if d is None or о.расстояние(b, a) != d or (d == 0) != (a == b):
                return False
            for c in о.УЗЛЫ:
                if d > о.расстояние(a, c) + о.расстояние(c, b):
                    return False
    return True


