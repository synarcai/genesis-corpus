# ВОПРОС ЕСТЬ ПРИСТАВКА К ОТВЕТУ — тот же закон, каким живут вопросные
# поверхности уравнений и дерева документов.
ВОПРОС = re.compile(r"^([^?]+)\? (.+)$")
ЧИСЛА_В = re.compile(r"\d+")
КАВЫЧКИ = re.compile(r"«([^»]+)»")
СЛОВА_В = re.compile(r"[a-zA-Zа-яёА-ЯЁ]+")


def названо(текст):
    """Что вопрос НАЗВАЛ: числа, имена в кавычках, узлы двух структур.

    Прочее — служебные слова языка, и требовать их в ответе значило бы
    требовать пересказа вопроса, а не ответа на него.
    """
    имена = set(КАВЫЧКИ.findall(текст))
    узлы = {с for с in СЛОВА_В.findall(текст)
            if с in о.УЗЕЛ or с in о.СМЕЖНЫЕ}
    return set(ЧИСЛА_В.findall(текст)), имена | узлы


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    м = ВОПРОС.match(с)
    if м:
        # ВОПРОС ВЕРЕН, ЕСЛИ ВЕРЕН ЕГО ОТВЕТ И СПРОШЕНО ТО ЖЕ САМОЕ.
        # Ответ на чужой вопрос — «на каком уровне стоит узел stone?
        # уровень узла water равен 3» — проходит первую половину и
        # валится на второй, и это ровно тот род лжи, которого корпус
        # без вопросной поверхности не умеет распознавать.
        вопрос, ответ = м.group(1), м.group(2)
        судимо, истинно = судить(ответ)
        числа_в, имена_в = названо(вопрос)
        числа_из, имена_из = названо(ответ)
        то_же = числа_в <= числа_из and имена_в <= имена_из
        return судимо, bool(судимо and истинно and то_же)
    for образец, ход in ПРАВИЛА:
        м = образец.match(с)
        if м:
            return True, bool(ход(_г(м)))
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"СТРОЕНИЕ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("СТРОЕНИЕ ОТКАЗ: обход пуст, судить нечего")
        return 2
    беды = о.оракул()
    if беды:
        print(f"СТРОЕНИЕ FAIL: структуры разошлись на встречных ходах в "
              f"{len(беды)} местах: {беды[:2]}")
        return 1
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:90]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"СТРОЕНИЕ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов, структуры обходимы)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
