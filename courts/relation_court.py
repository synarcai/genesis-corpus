def _г(м):
    """Захваты совпадения без пустых: русская и английская ветви равны."""
    return [x for x in м.groups() if x is not None]


def _множество(текст):
    """Числа названного множества, или None, если это не множество.

    МНОЖЕСТВО ЕСТЬ РАЗЛИЧНЫЕ ЭЛЕМЕНТЫ. «{1, 2, 3, 3}» не есть запись
    множества из четырёх элементов, и показ, её несущий, лжёт о своей
    же записи прежде, чем скажет о свойстве.
    """
    ряд = [int(ч) for ч in текст.split(", ")]
    if len(set(ряд)) != len(ряд) or ряд != sorted(ряд):
        return None
    return tuple(ряд)


def _узел(имя):
    return имя if имя in о.УЗЕЛ else None


def _отношение(имя):
    """Имя отношения по-английски или по-русски — или None."""
    if имя in о.ПРАВИЛО:
        return имя
    return о.ПО_РУССКИ.get(имя)


def _соответствие(имя):
    if имя in о.ОБЛАСТЬ:
        return имя
    return о.СООТВЕТСТВИЕ_ПО_РУССКИ.get(имя)


def _ру(ключ, счёт):
    return units.ру_форма(rugram.СЧЁТНЫЕ[ключ], счёт)


def _счёт(текст, число, ключ_ру, множ_ан):
    """Верна ли форма имени при счёте — на любом из двух языков."""
    return текст in (by_count(число, множ_ан), _ру(ключ_ру, число))


def _счёт_свой(текст, число, ключ):
    """То же для имён, объявленных в доме отношения (класс, пара, …)."""
    return текст == о.ру(ключ, число)


def _ключ(текст, отображение):
    """Ключ отображения, чья запись совпала с текстом, — или None."""
    for к in отображение:
        if str(к) == текст:
            return к
    return None


