def _однозначно(г):
    имя = _соответствие(г[0])
    if имя is None or not _область_верна(имя, г[1]):
        return False
    сколько_э, слово_э, сколько_з, слово_з = int(г[2]), г[3], int(г[4]), г[5]
    туда = о.отображение(имя)
    return (о.однозначно(имя) and len(туда) == сколько_э
            and len(о.обратное(имя)) == сколько_з
            and _счёт(слово_э, сколько_э, "элемент", "elements")
            and (слово_з == by_count(сколько_з, "values")
                 or _счёт_свой(слово_з, сколько_з, "значение")))


def _не_однозначно(г):
    имя = _соответствие(г[0])
    if имя is None or not _область_верна(имя, г[1]):
        return False
    туда = о.отображение(имя)
    a, b = _ключ(г[2], туда), _ключ(г[3], туда)
    if a is None or b is None or a == b:
        return False
    # СВИДЕТЕЛЬ ЕСТЬ ДВА РАЗНЫХ ПРООБРАЗА ОДНОГО ЗНАЧЕНИЯ, и суд
    # проверяет именно это, а не одно лишь слово «не однозначно».
    return (str(туда[a]) == г[4] and str(туда[b]) == г[4]
            and not о.однозначно(имя))


def _туда_обратно(г):
    имя = _соответствие(г[0])
    if имя is None:
        return False
    туда = о.отображение(имя)
    э = _ключ(г[1], туда)
    if э is None or г[2] != г[3] or г[1] != г[4]:
        return False
    прообразы = о.обратное(имя).get(туда[э], [])
    # ХОД ОБРАТНО ЗАЯВЛЕН СТРОКОЙ, И СУД ЕГО ДЕЛАЕТ: значение
    # возвращается в тот же элемент лишь тогда, когда прообраз один.
    return (str(туда[э]) == г[2] and len(прообразы) == 1
            and прообразы[0] == э)


def _туда(г):
    имя = _соответствие(г[0])
    if имя is None:
        return False
    туда = о.отображение(имя)
    э = _ключ(г[1], туда)
    return э is not None and str(туда[э]) == г[2]


