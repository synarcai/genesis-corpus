def _длина_от_корня(г):
    узел, к = г
    return bool(_узел(узел) and len(о.путь_от_корня(узел)) - 1 == int(к))


def _путь_от_корня(г):
    узел, дорога = г
    return bool(_узел(узел)
                and tuple(дорога.split(" / ")) == о.путь_от_корня(узел))


def _иерархия(г):
    узлов, рёбер = int(г[0]), int(г[1])
    # ИЕРАРХИЯ ЕСТЬ ПРОВЕРЯЕМОЕ УТВЕРЖДЕНИЕ, А НЕ ИМЯ: ровно один узел
    # без родителя, у прочих родитель ровно один и объявлен.
    без_родителя = [и for и in о.ИМЕНА if о.УЗЕЛ[и][0] is None]
    свои = [и for и in о.ИМЕНА
            if о.УЗЕЛ[и][0] is None or о.УЗЕЛ[и][0] in о.УЗЕЛ]
    return (len(без_родителя) == 1 and len(свои) == len(о.ИМЕНА)
            and узлов == len(о.ИМЕНА) and рёбер == len(о.ИМЕНА) - 1)


def _структура_уровней(г):
    сколько, верх = int(г[0]), int(г[1])
    return сколько == о.уровней() and верх == о.уровней() - 1


