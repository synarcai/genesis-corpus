def _числа(предел):
    return tuple(range(1, предел + 1))


def _эквивалентность(г):
    предел, модуль = int(г[0]), int(г[1])
    if предел < 1 or модуль < 1:
        return False
    return о.эквивалентность(модуль, _числа(предел)) == (True, True, True)


def _сколько_классов(г):
    предел, модуль, сколько, слово = int(г[0]), int(г[1]), int(г[2]), г[3]
    if предел < 1 or модуль < 1:
        return False
    числа = _числа(предел)
    # ДВА ВСТРЕЧНЫХ ХОДА СВОДЯТСЯ ЗДЕСЬ ЖЕ: ящики остатка против
    # связных кусков отношения. Совпадение и есть проверка того, что
    # классов именно столько.
    ящики = о.классы(модуль, числа)
    куски = о.классы_обходом(модуль, числа)
    return (len(ящики) == сколько and len(куски) == сколько
            and (слово == by_count(сколько, "classes")
                 or _счёт_свой(слово, сколько, "класс")))


def _разбиение(г):
    модуль, предел, всего = int(г[0]), int(г[1]), int(г[2])
    if предел < 1 or модуль < 1 or всего != предел:
        return False
    числа = _числа(предел)
    куски = о.классы_обходом(модуль, числа)
    собрано = [н for к in куски for н in к]
    return sorted(собрано) == list(числа) and len(set(собрано)) == предел


def _класс_содержит(г):
    остаток, модуль, предел = int(г[0]), int(г[1]), int(г[2])
    сколько, слово, ряд = int(г[3]), г[4], г[5]
    if предел < 1 or модуль < 1:
        return False
    свои = о.классы(модуль, _числа(предел)).get(остаток)
    если = tuple(int(x) for x in ряд.split(", "))
    return bool(свои is not None and свои == если and len(свои) == сколько
                and _счёт(слово, сколько, "число", "numbers"))


def _в_классе(г):
    число, остаток, модуль = int(г[0]), int(г[1]), int(г[2])
    return модуль > 0 and о.остаток(число, модуль) == остаток


def _один_класс(г):
    a, b, модуль = int(г[0]), int(г[1]), int(г[2])
    return (модуль > 0 and a != b
            and о.остаток(a, модуль) == о.остаток(b, модуль))


def _разные_классы(г):
    a, b, модуль, оa, оb = (int(x) for x in г[:5])
    return (модуль > 0 and о.остаток(a, модуль) == оa
            and о.остаток(b, модуль) == оb and оa != оb)


