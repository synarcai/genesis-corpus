def _разбор(текст_множества, имя_отношения):
    """(множество, имя) — или (None, None), если что-то не объявлено."""
    множество = _множество(текст_множества)
    имя = _отношение(имя_отношения)
    return (множество, имя) if множество and имя else (None, None)


def _рефлексивно(г):
    множество, имя = _разбор(г[0], г[1])
    if имя is None:
        return False
    return о.свидетель_рефлексивности(имя, множество) is None


def _не_рефлексивно(г):
    множество, имя = _разбор(г[0], г[1])
    if имя is None:
        return False
    a = int(г[2])
    return a in множество and not о.стоит(имя, a, a)


def _симметрично(г):
    множество, имя = _разбор(г[0], г[1])
    if имя is None:
        return False
    return о.свидетель_симметричности(имя, множество) is None


def _не_симметрично(г):
    множество, имя = _разбор(г[0], г[1])
    if имя is None:
        return False
    a, b, ещё_b, ещё_a = (int(x) for x in г[2:6])
    if (a, b) != (ещё_a, ещё_b):
        return False
    return (a in множество and b in множество
            and о.стоит(имя, a, b) and not о.стоит(имя, b, a))


def _транзитивно(г):
    множество, имя = _разбор(г[0], г[1])
    if имя is None:
        return False
    return о.свидетель_транзитивности(имя, множество) is None


def _не_транзитивно(г):
    множество, имя = _разбор(г[0], г[1])
    if имя is None:
        return False
    a, b, ещё_b, c, ещё_a, ещё_c = (int(x) for x in г[2:8])
    if (a, b, c) != (ещё_a, ещё_b, ещё_c):
        return False
    # СВИДЕТЕЛЬ ПРОВЕРЯЕТСЯ КАК СВИДЕТЕЛЬ: две ступени стоят, третья
    # нет. Строка, назвавшая тройку, где всё стоит, лжёт о свидетеле,
    # даже если отношение и правда не транзитивно.
    return (all(э in множество for э in (a, b, c))
            and о.стоит(имя, a, b) and о.стоит(имя, b, c)
            and not о.стоит(имя, a, c))


def _сколько_пар(г):
    множество, имя = _разбор(г[0], г[1])
    if имя is None:
        return False
    сколько, слово, всего = int(г[2]), г[3], int(г[4])
    return (len(о.пары(имя, множество)) == сколько
            and всего == len(множество) ** 2
            and (слово == by_count(сколько, "pairs")
                 or _счёт_свой(слово, сколько, "пара")))


def _пара_стоит(г):
    множество, имя = _разбор(г[0], г[3])
    if имя is None:
        return False
    a, b = int(г[1]), int(г[2])
    return a in множество and b in множество and о.стоит(имя, a, b)


def _пара_не_стоит(г):
    множество, имя = _разбор(г[0], г[3])
    if имя is None:
        return False
    a, b = int(г[1]), int(г[2])
    return a in множество and b in множество and not о.стоит(имя, a, b)


