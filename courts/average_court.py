#!/usr/bin/env python3
"""[СВОДКА] — среднее не читается, а ПЕРЕСЧИТЫВАЕТСЯ из ряда.

Мир сводки говорит одно и то же о ряде восемью родами: среднее с
основанием, тот же факт вопросом, сумма отдельно, счёт отдельно,
наибольшее, наименьшее, закон о границах и контрпример. Суд не верит ни
одному из них. Он берёт ИЗ СТРОКИ ТОЛЬКО РЯД — а всё прочее считает
сам: складывает, считает длину, делит, берёт крайние. Строка, у которой
сошлись все её числа, истинна; строка, у которой хоть одно не сошлось,
ложна — и неважно, какое именно.

ПОЧЕМУ ЭТОГО НЕ ДЕЛАЕТ СУД СТАТИСТИКИ. Там среднее объявлено там же,
где показ: «the mean of 2 4 6 is 4» — одно число и одна проверка. Здесь
среднее сказано ВМЕСТЕ С ОСНОВАНИЕМ, и проверок три сразу: что сумма
названа верно, что счёт назван верно и что среднее есть их частное.
Основание, сошедшееся с ответом, но не с рядом, — самая дорогая ложь
корпуса: она учит верному способу на неверных величинах.

ОСОБО О КОНТРПРИМЕРЕ. Свидетель, который НЕ опровергает, звучит
убедительнее всего, ибо форма у него правильная. Здесь проверяется не
форма, а РАБОТА: что среднее ряда и вправду посчитано верно и что его и
вправду НЕТ среди чисел ряда. «Среднее 2, 4 есть 3, и 3 среди них нет»
убивает «среднее всегда есть одно из чисел» лишь тогда, когда три
действительно среднее и действительно не два и не четыре.

ОСОБО О СЧЁТЕ, НАЗВАННОМ СЛОВОМ. Русский показ говорит «три числа» —
числительным, а не цифрой. Суд не сверяет слово со словом: он ЧИТАЕТ
имя обратно законом разрядов дома числительных (`tools/numerals.py`) и
получает величину, которую сверяет с длиной ряда. Назвать и прочесть
проверяют друг друга по построению — потому обратное чтение здесь есть
пересчёт, а не сверка.

ОБРАЗЦЫ УЗКИ И ПРИВЯЗАНЫ К ЗАЧИНУ. Суд не смеет читать чужой род: ряд
этого мира пишется ЗАПЯТОЙ («3, 5, 7»), а соседние миры пишут его
пробелом («2 4 6») — и ни один их показ сюда не попадёт. Неузнанная
строка есть (False, False): молчание о чужом честнее вердикта о нём.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import numerals  # noqa: E402
import rugram  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# Дом языка читается ЗДЕСЬ ЖЕ, а не берётся у генератора: суд, взявший
# таблицу из проверяемого дома, проверял бы дом самим собой.
ТАБЛИЦА_РУ = numerals.таблица("ru")

# РЯД ЕСТЬ ДВА ЧИСЛА И БОЛЕЕ, ЧЕРЕЗ ЗАПЯТУЮ. Одно число рядом не
# бывает: у ряда из одного среднее равно ему самому, закон о границах
# вырождается в равенство, а контрпример невозможен вовсе.
РЯД = r"(\d+(?:, \d+)+)"
Ч = r"(\d+)"


def числа(запись):
    return [int(x) for x in запись.split(", ")]


def ч(м, *номера):
    """Целые из НАЗВАННЫХ скобок — не из всей строки.

    Число, стоящее в записи БУКВОЙ ЗАКОНА, не есть величина показа, и
    суд обязан брать ровно то, что назвал образцом.
    """
    return [int(м.group(i)) for i in номера]


def целое_среднее(ряд):
    """Среднее ряда, или None — у ряда его нет.

    ЧАСТНОЕ, КОТОРОГО НЕТ, НЕ ЕСТЬ НУЛЬ И НЕ ЕСТЬ ОКРУГЛЕНИЕ. Ряд без
    целого среднего не имеет права на показ вовсе, и всякая строка,
    назвавшая среднее такого ряда, ложна — какое бы число она ни
    назвала.
    """
    return sum(ряд) // len(ряд) if sum(ряд) % len(ряд) == 0 else None


# ------------------------------------------------------------ ПРОВЕРКИ

def _среднее(м):
    """Среднее с основанием-цепью: слагаемые суть ряд, сумма — счёт, количество
    — длина ряда, деление — звено с итогом-средним."""
    ряд = числа(м.group(1))
    return _цепь_среднего(ряд, м, 2)


def _цепь_среднего(ряд, м, с):
    # СЛАГАЕМЫЕ ЦЕПИ РАЗДЕЛЕНЫ ПЛЮСОМ, РЯД — ЗАПЯТОЙ: два разных разбора.
    слагаемые = [int(x) for x in м.group(с + 1).split(" + ")]
    ср, сумма, счёт, д1, д2, д3 = ч(м, с, с + 2, с + 3, с + 4, с + 5, с + 6)
    return (слагаемые == ряд and сумма == sum(ряд) and счёт == len(ряд)
            and (д1, д2) == (сумма, счёт) and д3 == ср == целое_среднее(ряд))


def _вопрос(м):
    """Вопрос и ответ говорят об ОДНОМ ряде, и ответ верен.

    РЯД СПРОШЕННЫЙ И РЯД ОТВЕЧЕННЫЙ СВЕРЯЮТСЯ. Ответ, верный сам по
    себе, но данный о другом ряде, есть подмена предмета — и она
    читается как правильный ответ всяким, кто сверяет только числа
    ответа.
    """
    if числа(м.group(1)) != числа(м.group(2)):
        return False
    return _цепь_среднего(числа(м.group(2)), м, 3)


def _сумма(м):
    return sum(числа(м.group(1))) == int(м.group(2))


def _счёт_цифрой(м):
    """Счёт цифрой, и счётное имя при нём — во множественном числе."""
    счёт = int(м.group(1))
    return счёт == len(числа(м.group(2))) and счёт != 1


def _счёт_словом(м):
    """Числительное ЧИТАЕТСЯ ОБРАТНО, и счётная форма при нём — своя."""
    величина = numerals.прочесть(м.group(2), ТАБЛИЦА_РУ)
    if величина is None:
        return False
    return (величина == len(числа(м.group(1)))
            and м.group(3) == rugram.форма("число", int(величина)))


def _наибольшее(м):
    return max(числа(м.group(1))) == int(м.group(2))


def _наименьшее(м):
    return min(числа(м.group(1))) == int(м.group(2))


def _закон(м):
    """Закон о границах: среднее верно, границы верны, и оно между ними.

    ПОСЛЕДНЕЕ УСЛОВИЕ ПРОВЕРЯЕТСЯ, ХОТЯ И ДОКАЗУЕМО. Показ УТВЕРЖДАЕТ
    его, а суд обязан читать утверждение, а не доверять теореме: правка
    шаблона, поставившая границы наоборот, есть ровно та ложь, которую
    доверие к теореме и пропустит.
    """
    ряд = числа(м.group(1))
    ср, мин, ср2, макс = ч(м, 2, 3, 4, 5)
    return (ср == целое_среднее(ряд) and мин == min(ряд)
            and макс == max(ряд) and ср2 == ср and мин <= ср <= макс)


def _контрпример(м):
    """Свидетель обязан РАБОТАТЬ: среднее верно и его НЕТ среди чисел."""
    ряд = числа(м.group(1))
    ср, ср2 = ч(м, 2, 3)
    return (ср == целое_среднее(ряд) and ср2 == ср and ср not in ряд)


СЛАГАЕМЫЕ = r"(\d+(?: \+ \d+)*)"

ОБРАЗЦЫ = (
    (rf"^the average of {РЯД} is {Ч}: {СЛАГАЕМЫЕ} = {Ч}, there are "
     rf"{Ч} of them, {Ч} ÷ {Ч} = {Ч}\.$", _среднее),
    (rf"^среднее чисел {РЯД} — это {Ч}: {СЛАГАЕМЫЕ} = {Ч}, их количество "
     rf"{Ч}, {Ч} ÷ {Ч} = {Ч}\.$", _среднее),
    (rf"^what is the average of {РЯД}\? the average of {РЯД} is {Ч}: "
     rf"{СЛАГАЕМЫЕ} = {Ч}, there are {Ч} of them, {Ч} ÷ {Ч} = {Ч}\.$", _вопрос),
    (rf"^чему равно среднее чисел {РЯД}\? среднее чисел {РЯД} — это "
     rf"{Ч}: {СЛАГАЕМЫЕ} = {Ч}, их количество {Ч}, {Ч} ÷ {Ч} = {Ч}\.$", _вопрос),
    (rf"^the sum of {РЯД} is {Ч}\.$", _сумма),
    (rf"^сумма чисел {РЯД} — это {Ч}\.$", _сумма),
    (rf"^there are {Ч} numbers in {РЯД}\.$", _счёт_цифрой),
    (rf"^в ряду {РЯД} ([^\W\d_]+) ([^\W\d_]+)\.$", _счёт_словом),
    (rf"^the largest of {РЯД} is {Ч}\.$", _наибольшее),
    (rf"^наибольшее из {РЯД} — это {Ч}\.$", _наибольшее),
    (rf"^the smallest of {РЯД} is {Ч}\.$", _наименьшее),
    (rf"^наименьшее из {РЯД} — это {Ч}\.$", _наименьшее),
    (rf"^the average of {РЯД} is {Ч}, and {Ч} ≤ {Ч} ≤ {Ч}\.$", _закон),
    (rf"^среднее чисел {РЯД} — это {Ч}, и {Ч} ≤ {Ч} ≤ {Ч}\.$", _закон),
    (rf"^the average is always one of the numbers is false: the "
     rf"average of {РЯД} is {Ч}, and {Ч} is not among them\.$",
     _контрпример),
    (rf"^среднее всегда есть одно из чисел — ложь: среднее чисел {РЯД} "
     rf"— это {Ч}, а {Ч} среди них нет\.$", _контрпример),
)
ПРАВИЛА = tuple((re.compile(о), п) for о, п in ОБРАЗЦЫ)


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    for образец, проверить in ПРАВИЛА:
        м = образец.match(с)
        if м:
            return True, bool(проверить(м))
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"СВОДКА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("СВОДКА ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"СВОДКА {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
