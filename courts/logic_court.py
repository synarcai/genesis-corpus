#!/usr/bin/env python3
"""[ЛОГИКА И МНОЖЕСТВА] — утверждение об истине проверяется вычислением.

Суд арифметики судит равенства чисел. Но GENESIS обязан нести
ОСНОВАНИЯ — логику, множества, вывод, — и там утверждений не меньше, а
проверяемость такая же полная: «{b c} ∪ {b e} = {b c e}» либо верно,
либо нет, и узнать это можно счётом, а не мнением.

ПЯТЬ РОДОВ, И КАЖДЫЙ ПРОВЕРЯЕТСЯ СВОИМ ВЫЧИСЛЕНИЕМ:
  · СОЕДИНЕНИЕ И ПЕРЕСЕЧЕНИЕ множеств;
  · ВКЛЮЧЕНИЕ — знаком (⊂) и словами («каждый элемент A принадлежит
    B»), ибо поверхность иная, а факт тот же;
  · ПРИНАДЛЕЖНОСТЬ (∈) с ответом T или F;
  · БУЛЕВА связка — и, или, не — на обоих языках;
  · MODUS PONENS: «из A и A → B следует B». Здесь проверяется не
    истинность посылок, а СТРОЕНИЕ вывода: заключение обязано быть
    консеквентом той импликации, чей антецедент назван посылкой.
    Показ, где заключение взято с потолка, есть ложь о выводе — и
    именно она страшна, ибо выглядит как рассуждение.

ИМЕНА ЗНАКОВ — ФАКТ ЯЗЫКА, и потому читаются из пакетов
(`sign_names`), а не пишутся здесь: «∨ читается как или» есть
утверждение о русском, «∨ is read as or» — об английском, и суд не
вправе знать ни того, ни другого сам.

ЧЕГО СУД НЕ ВИДИТ, НАЗВАНО: он не проверяет ИСТИННОСТЬ посылок вывода
(это дело мира, а не логики) и не разбирает кванторы — они иной род и
ждут своего суда.
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ПАКЕТЫ = КОРЕНЬ / "tools/langpacks"
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ИСТИНА = {"истина": True, "ложь": False, "true": True, "false": False,
          "t": True, "f": False}
МНОЖ = re.compile(r"\{([^}]*)\}\s*([∪∩])\s*\{([^}]*)\}\s*=\s*\{([^}]*)\}")
ПОДМН = re.compile(r"\{([^}]*)\}\s*⊂\s*\{([^}]*)\}\s*=\s*([TF])")
СЛОВАМИ = re.compile(
    r"(?:каждый элемент|every element of)\s*\{([^}]*)\}\s*"
    r"(?:принадлежит|belongs to)\s*\{([^}]*)\}")
ПРИНАД = re.compile(r"(\w+)\s*∈\s*\{([^}]*)\}\s*=\s*([TF])")
БУЛЬ = re.compile(
    r"\b(истина|ложь|true|false)\s+(и|или|and|or)\s+"
    r"(истина|ложь|true|false)\s+(?:равно|is)\s+"
    r"(истина|ложь|true|false)")
ОТРИЦ = re.compile(
    r"\b(?:не|not)\s+(истина|ложь|true|false)\s+"
    r"(?:равно|is)\s+(истина|ложь|true|false)")
ВЫВОД = re.compile(
    r"(?:из|from)\s+(\w+)\s+(?:и|and)\s+(\w+)\s*→\s*(\w+)\s+"
    r"(?:следует|follows)\s+(\w+)")


def имена_знаков():
    """{язык: {знак: имя}} — из пакетов, ибо это факт языка."""
    вон = {}
    if not ПАКЕТЫ.is_dir():
        return вон
    for ф in sorted(ПАКЕТЫ.glob("*.json")):
        try:
            п = json.loads(ф.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if п.get("sign_names") and п.get("lang"):
            вон[п["lang"]] = п["sign_names"]
    return вон


ЗНАКОМ = re.compile(
    r"(?:знак|the sign)\s+(\S+)\s+(?:читается как|is read as)\s+(\S+?)[.。]?$")


def судить(строка, знаки):
    """(судимо, истинно) для одной строки."""
    с = строка.strip().rstrip(".")
    m = МНОЖ.search(с)
    if m:
        a, оп, b, c = m.groups()
        A, B, C = set(a.split()), set(b.split()), set(c.split())
        return True, (A | B if оп == "∪" else A & B) == C
    m = ПОДМН.search(с)
    if m:
        a, b, r = m.groups()
        return True, (set(a.split()) <= set(b.split())) == (r == "T")
    m = СЛОВАМИ.search(с)
    if m:
        a, b = m.groups()
        return True, set(a.split()) <= set(b.split())
    m = ПРИНАД.search(с)
    if m:
        e, b, r = m.groups()
        return True, (e in set(b.split())) == (r == "T")
    m = БУЛЬ.search(с)
    if m:
        a, оп, b, c = (g.lower() for g in m.groups())
        A, B, C = ИСТИНА[a], ИСТИНА[b], ИСТИНА[c]
        ждём = (A and B) if оп in ("и", "and") else (A or B)
        return True, ждём == C
    m = ОТРИЦ.search(с)
    if m:
        a, b = (g.lower() for g in m.groups())
        return True, (not ИСТИНА[a]) == ИСТИНА[b]
    m = ВЫВОД.search(с)
    if m:
        посылка, антецедент, консеквент, вывод = m.groups()
        # СТРОЕНИЕ, А НЕ ИСТИННОСТЬ: посылка обязана быть антецедентом,
        # а заключение — консеквентом. Иначе это не вывод, а вид вывода.
        return True, (посылка == антецедент and вывод == консеквент)
    m = ЗНАКОМ.search(с)
    if m and знаки:
        знак, имя = m.group(1), m.group(2).lower()
        # У ЗНАКА БЫВАЕТ НЕСКОЛЬКО ИМЁН, И ОБА ИСТИННЫ: у стрелки есть
        # имя формы («arrow») и имя роли («implies»). Первая редакция
        # держала одно, и добавление второго объявило ложью двадцать два
        # честных показа — затёртое имя, а не ошибка корпуса.
        объявлено = set()
        for т in знаки.values():
            имена = т.get(знак)
            if isinstance(имена, str):
                объявлено.add(имена.lower())
            elif имена:
                объявлено |= {str(x).lower() for x in имена}
        if имя in объявлено:
            return True, True
        # НЕВЕРНОЕ ИМЯ И НЕОБЪЯВЛЕННОЕ — РАЗНЫЕ ВЕЩИ, и суд, не
        # различавший их, объявил ложью «знак ≈ читается как примерно»
        # — верное русское имя, которого не было в пакете. Ложь есть
        # имя, объявленное ЗА ДРУГИМ знаком; имя, не объявленное нигде,
        # есть НЕИЗВЕСТНОЕ: оно считается отдельно и печатается числом,
        # чтобы пробел в описании был виден, а не выдан за находку.
        чужое = any(
            имя in {str(x).lower() for x in
                    ([имена] if isinstance(имена, str) else имена or [])}
            for т in знаки.values()
            for з, имена in т.items() if з != знак)
        if чужое:
            return True, False
        return False, True
    return False, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ЛОГИКА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    знаки = имена_знаков()
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ЛОГИКА ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка, знаки)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:70]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ЛОГИКА {поза}: {ложных} ложных утверждений из {судимых} "
          f"судимых ({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
