#!/usr/bin/env python3
"""[ПРОПОРЦИЯ] — равенство отношений, пересчитанное судом крест-накрест.

Суд не пишет закона заново: он берёт его у дома (`propforms`), где рамки и числа объявлены одной
таблицей. Подмена члена, произведения и самой ЛОВУШКИ ловится машинально: пропорция
пересчитывается крест-накрест, а не принимается записью.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЛОВУШКА ОБЯЗАНА ЛОВИТЬ, И ЭТО ТОЖЕ ПРОВЕРЯЕТСЯ: на странице о разности обе разности обязаны
РАЗОЙТИСЬ — страница, где они совпали, показывает ровно обратное тому, ради чего написана.

ЭТОТ ДОМ ЧИТАЕТСЯ И СУДОМ АРИФМЕТИКИ: его страницы написаны так, что слова стоя́т до двоеточия, а
равенства после, — и потому каждая проверена ДВАЖДЫ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/prop_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import propforms  # noqa: E402 — дом, объявивший пропорцию

ИМЯ_СУДА = "prop"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"prop"})


def _судить(строка):
    return propforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ПРОПОРЦИЯ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(propforms.РОДЫ)}, страниц {len(propforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
