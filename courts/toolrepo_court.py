def _судить(строка):
    с = строка.strip()
    if not с:
        return False, False
    язык = next((я for начало, я in _НАЧАЛО.items() if с.startswith(начало)), None)
    if язык is None:
        return False, False
    совпал = False
    for образ, род, форма in РАМКИ[язык]:
        м = образ.match(с)
        if not м:
            continue
        if род == СКРЕЩЕНО:
            совпал = True
            continue
        зн, согласна = _значения(м)
        if not _свой(зн):
            continue
        совпал = True
        try:
            if согласна and _вердикт(язык, род, форма, зн):
                return True, True
        except (KeyError, ValueError, IndexError, TypeError):
            continue
    return (True, False) if совпал else (False, False)


