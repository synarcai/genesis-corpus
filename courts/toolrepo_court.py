def _свой(зн):
    """Строка этого мира: её пути и имена — имена мира, папки — папки мира, язык проекта — объявленный."""
    def есть(ключ, свои):
        return any(x in свои for x in зн[ключ].split("\n"))
    for ключ in ("f", "g", "n", "q", "s", "p1", "p2", "p3"):
        if ключ in зн and not есть(ключ, _СВОИ_ИМЕНА):
            return False
    if "d" in зн and not есть("d", _ПАПКИ):
        return False
