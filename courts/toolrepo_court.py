def _порчи(с):
    """Подсадки от страницы дома: последнее число на единицу больше; первое число последнего леджера другое;
    последний путь подменён другим путём мира; мера в ходе мира подменена."""
    вон = []
    числа = list(re.finditer(r"\d+", с))
    if числа:
        п = числа[-1]
        вон.append(с[:п.start()] + str(int(п.group()) + 1) + с[п.end():])
    леджеры = list(re.finditer(r"(\d+)( [+−] \d+)* = (\d+)", с))
    if леджеры:
        л = леджеры[-1]
        вон.append(с[:л.start(1)] + str(int(л.group(1)) + 2) + с[л.end(1):])
    пути = list(re.finditer(_ПУТЬ, с))
    if len(пути) >= 2:
        п = пути[-1]
        чужой = next((x for x in R.ТЕКСТЫ if x != п.group() and x not in с), None)
        if чужой:
            вон.append(с[:п.start()] + чужой + с[п.end():])
    мера = re.search(r" · (files|lines|occurrences|bytes|runs) (\d+)", с)
    if мера:
        вон.append(с[:мера.start(2)] + str(int(мера.group(2)) + 3) + с[мера.end(2):])
    return [в for в in вон if в != с]


def _самопроверка():
    """Всякая страница дома истинна; всякая порча — ложь, пойманная рамкой, а не молчание."""
    беды = [с for с in R.ПОКАЗЫ if _судить(с) != (True, True)]
    порч = пойманных = 0
    for i, с in enumerate(sorted(R.ПОКАЗЫ)):
        if i % 5:
            continue
        for порча in _порчи(с):
            порч += 1
            вердикт = _судить(порча)
            if вердикт == (True, False):
                пойманных += 1
            elif вердикт == (True, True):
                беды.append(f"порча прошла: {порча[:200]}")
            else:
                беды.append(f"порча — молчание: {порча[:200]}")
        язык = R.ПОКАЗЫ[с][0]
        р = A.РЕЧЬ[язык]
        да = A._реплика(язык, "польз", р["да"] + ".") + " "
        нет = A._реплика(язык, "польз", р["нет"] + ".") + " "
        порчи = ([с.replace(да, "", 1), с.replace(да, нет, 1)] if да in с
                 else [с.replace(нет, да, 1)] if нет in с else [])
        for порча in порчи:
            порч += 1
            if _судить(порча) == (True, False):
                пойманных += 1
            else:
                беды.append(f"порча устройства не ложь: {порча[:200]}")
    # ПОРЧА МЕСТОИМЕНИЯ — от дома: предложение называет второй акт путём ПРИКАЗА («append … to the file
    # home/chores.md» после переименования в tasks.md), а не путём, где объект стоит после первого акта
    for с, (язык, род, форма, _р) in R.ПОКАЗЫ.items():
        план = форма.split("·")[0]
        if not (род in (R.МЕСТО_ИМЯ, R.МЕСТО_ПЕРЕНОС, R.МЕСТО_ОТКАЗ, R.МЕСТО_СТРОК) and форма in ("имя", "перенос")
                or род == R.ПЛАН_СКАЖИ and план in ("имя", "перенос")):
            continue
        дыры = R.ПЕРЕПИСЬ[с]
        порч += 1
        порча = с.replace(_путь_приказа(план, дыры), дыры["f"], 1)
        if _судить(порча) == (True, False):
            пойманных += 1
        else:
            беды.append(f"порча местоимения не ложь: {порча[:200]}")
    # ПОРЧА МЕНЯЮЩЕГО СЛОВА — от дома: исполненная страница той же основы с приказом на потом, «не …», «притворись»
    # («delete … later», «don't delete …» — и файл удалён) — акт вопреки слову, ложь в любом мире
    исполненные = {(я, R.форма_приказа(род, ф), ф, tuple(sorted(R.ПЕРЕПИСЬ[с].items()))): с
                   for с, (я, род, ф, р) in R.ПОКАЗЫ.items() if р == "плоский" and род not in R.ОТКАЗЫ}
    for с, (язык, род, форма, р) in R.ПОКАЗЫ.items():
        if р not in T.МЕНЯЮЩИЕ[язык]:
            continue
        с_ = исполненные.get((язык, R.форма_приказа(род, форма), форма, tuple(sorted(R.ПЕРЕПИСЬ[с].items()))))
        if с_ is None:
            continue
        приказ_, потом_ = R.реплики(с_, язык)[0][1], R.реплики(с, язык)[0][1]
        порч += 1
        if _судить(с_.replace(приказ_, потом_, 1)) == (True, False):
            пойманных += 1
        else:
            беды.append(f"акт вопреки слову времени не ложь: {с_.replace(приказ_, потом_, 1)[:200]}")
    # ПОРЧА ВОПРОСА О ПРОШЛОМ — от дома: исполненное удаление того же файла в ответ на «did you delete …?» — ложь
    удаления = {R.ПЕРЕПИСЬ[с]["f"]: с for с, (я, род, ф, р) in R.ПОКАЗЫ.items()
                if род == R.УДАЛИТЬ and ф == "канон" and р == "плоский"}
    for с, (язык, род, форма, _р) in R.ПОКАЗЫ.items():
        с_ = удаления.get(R.ПЕРЕПИСЬ[с]["f"]) if род == R.ПРОШЛОЕ else None
        if с_ is None or R.ПОКАЗЫ[с_][0] != язык:
            continue
        порч += 1
        порча = с_.replace(R.реплики(с_, язык)[0][1], R.реплики(с, язык)[0][1], 1)
        if _судить(порча) == (True, False):
            пойманных += 1
        else:
            беды.append(f"удаление в ответ на вопрос о прошлом не ложь: {порча[:200]}")
    # ПОРЧА СОСТОЯНИЯ — от дома: прогон после правки кода печатает отчёт проекта ДО правки (время бегуна и строки —
    # объявленного проекта) — отчёт не того мира, ложь
    for с, (язык, род, форма, _р) in R.ПОКАЗЫ.items():
        if форма != "код":
            continue
        ходы = [т for роль, т in R.реплики(с, язык) if роль == "мир"]
        меры, _строки, _отказ = R.клетки(ходы[1][:-1])
        имя = R.ИМЕНА_ПРОГОНОВ[R.ПЕРЕПИСЬ[с]["Я"]]
        прежний = W.текст(W.прогон(имя, R.снятое(имя), меры["runs"] - 1))
        if прежний == ходы[1][:-1]:
            continue
        порч += 1
        порча = с.replace(ходы[1][:-1], прежний, 1)
        if _судить(порча) == (True, False):
            пойманных += 1
        else:
            беды.append(f"отчёт прежнего состояния не ложь: {порча[:200]}")
    return беды, порч, пойманных, len(R.ПОКАЗЫ)


