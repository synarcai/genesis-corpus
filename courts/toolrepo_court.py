def _ход(язык, род, форма, зн):
    """Ходы мира, какие обязан показать мир: акт по дырам страницы на её репозитории."""
    мир_ = R.папка(язык)
    f, d = зн.get("f"), зн.get("d")
    путь = f if f is not None else (f"{d}/{зн['n']}" if "n" in зн else None)
    if род in (R.СОЗДАТЬ, R.СОЗДАТЬ_ПАПКА, R.СОЗДАТЬ_ЕСТЬ):
        return [мир_.create(путь)[1]]
    if род in (R.УДАЛИТЬ, R.УДАЛИТЬ_ПАПКА, R.УДАЛИТЬ_НЕТ):
        return [мир_.delete(путь)[1]]
    if род in (R.СОЗДАТЬ_ОТКАЗ, R.УДАЛИТЬ_ОТКАЗ):
        return [мир_.count(d if форма.startswith("папка") else R.папка_пути(путь))[1]]
    if род in (R.ПЕРЕНОС, R.ПЕРЕНОС_НЕТ):
        return [мир_.move(f, d)[1]]
    if род == R.ПЕРЕНОС_ОТКАЗ:
        return [мир_.count(d)[1]]
    if род in (R.ИМЯ, R.ИМЯ_ЗАНЯТО, R.ИМЯ_НЕТ):
        return [мир_.move(f, (R.папка_пути(f) + "/" if R.папка_пути(f) else "") + зн["g"])[1]]
    if род == R.ИМЯ_ОТКАЗ:
        return [мир_.count(R.папка_пути(f))[1]]
    if род in (R.ЗАМЕНА, R.ЗАМЕНА_СЛОВА, R.ЗАМЕНА_НЕТ):
        return [мир_.replace(f, зн["A"], зн["B"])[1]]
    if род == R.ЗАМЕНА_ОТКАЗ:
        return [мир_.find(f, зн["A"])[1]]
    if род == R.ДОПИСАТЬ:
        return [мир_.line(f, зн["S"])[1]]
    if род == R.ДОПИСАТЬ_ОТКАЗ:
        return [мир_.lines(f)[1]]
    if род in (R.ПЛАН_ЗАМЕНА, R.ПЛАН_ДОПИСАТЬ, R.ПЛАН_ПЕРЕНОС, R.ПЛАН_ОТКАЗ):
        if форма == "замена":
            return [(мир_.find(f, зн["A"]) if род == R.ПЛАН_ОТКАЗ else мир_.replace(f, зн["A"], зн["B"]))[1]]
        if форма == "дописать":
            return [(мир_.lines(f) if род == R.ПЛАН_ОТКАЗ else мир_.line(f, зн["S"]))[1]]
        if род == R.ПЛАН_ОТКАЗ:
            return [мир_.count(d)[1]]
        мир2, ход1 = мир_.move(f, d)
        return [ход1, мир2.delete(зн["q"])[1]]
    if род in R.МЕСТО:
        return _ход_места(мир_, род, форма.partition("|")[0].split("·")[0], зн, "строк" if форма.endswith("·строк") else None)
    if род == R.ПРОШЛОЕ:
        ход_ = мир_.read(f)[1]
        return [ход_] if (форма == "есть") == isinstance(ход_, W.Наблюдение) else []
    if род in (R.В_КАКОМ, R.В_КАКИХ, R.НИГДЕ):
        return [мир_.find(".", зн["W"])[1]]
    if род == R.НА_СТРОКЕ:
        return [мир_.find(f, зн["W"])[1]]
    if род in (R.ВЫБОР, R.СТРОКА_Н, R.СТРОК):
        return [мир_.lines(f)[1]]
    if род in (R.КЛЮЧ, R.О_КЛЮЧЕ):
        return [мир_.find(зн["s"], зн["k"])[1]]
    if род == R.РАЗ:
        return [мир_.find(d if форма == "папка" else ".", зн["W"])[1]]
    if род == R.ФАЙЛОВ:
        return [мир_.count(d)[1]]
    return []


def _ход_места(мир_, род, план, зн, второй=None):
    """Ходы плана с местоимением: первый акт по дырам приказа; второй — на месте, какое строка path первого хода
    назвала после акта («it»), если место одно; у отказа пользователем — чтение «до» папки, какую двинул бы акт."""
    f, d = зн.get("f"), зн.get("d")
    if род == R.МЕСТО_СТРОК:
        if план == "имя":
            мир2, ход1 = мир_.move(f, (R.папка_пути(f) + "/" if R.папка_пути(f) else "") + зн["g"])
        elif план == "перенос":
            мир2, ход1 = мир_.move(f, d)
        else:
            мир2, ход1 = мир_.line(f, зн["S"])
        места = list(dict.fromkeys(R.поле(ход1, "path"))) if isinstance(ход1, W.Наблюдение) else []
        return [ход1] if len(места) != 1 else [ход1, мир2.lines(места[0])[1]]
    if род == R.МЕСТО_ОТКАЗ:
        return [мир_.count(d if план == "перенос" else R.папка_пути(f))[1]]
    if план == "создать":
        мир2, ход1 = мир_.create(f)
    elif план == "имя":
        мир2, ход1 = мир_.move(f, (R.папка_пути(f) + "/" if R.папка_пути(f) else "") + зн["g"])
    elif план == "перенос":
        мир2, ход1 = мир_.move(f, d)
    else:
        мир2, ход1 = мир_.find(".", зн["W"])
    места = list(dict.fromkeys(R.поле(ход1, "path"))) if isinstance(ход1, W.Наблюдение) else []
    if len(места) != 1 or род in (R.МЕСТО_НЕВОЗМОЖНО, R.МЕСТО_МНОГО):
        return [ход1]
    if второй == "строк":
        return [ход1, мир2.lines(места[0])[1]]
    ход2 = мир2.delete(места[0])[1] if план == "перенос" else мир2.line(места[0], зн["S"])[1]
    return [ход1, ход2]


def _путь_приказа(план, зн):
    """Путь, какой определяет сам приказ: создание — созданный файл; переименование — новое имя в той же папке;
    перенос — папка/имя."""
    if план == "имя":
        return (R.папка_пути(зн["f"]) + "/" if R.папка_пути(зн["f"]) else "") + зн["g"]
    if план == "перенос":
        return f"{зн['d']}/{R.имя_пути(зн['f'])}"
    return зн.get("f")


def _место_верно(язык, род, форма, зн, ходы):
    """План с местоимением: ходы мира — свои, байт в байт; путь, какой организм назвал вторым актом, — строка path
    первого хода; итоги — леджеры мер обоих актов; невозможное — отказ мира тем именем, какое назвал мир."""
    план, _, почему = форма.partition("|")
    план = план.split("·")[0]
    ход1 = ходы[0]
    if W.текст(ход1) != зн["МИР1"]:
        return False
    if род == R.МЕСТО_СТРОК:
        # первый итог — отчёт акта по его мере; путь второго шага — строка path первого хода и путь, какой
        # определяет приказ; второй итог — «сколько строк» по мере lines хода мира на этом месте
        if not isinstance(ход1, W.Наблюдение) or len(ходы) != 2 or W.текст(ходы[1]) != зн["МИР2"]:
            return False
        место_ = R.поле(ход1, "path")[0]
        путь_ = _путь_приказа(план, зн) if план != "дописать" else зн["f"]
        первый_род = {"имя": R.ИМЯ, "перенос": R.ПЕРЕНОС, "дописать": R.ДОПИСАТЬ}[план]
        return (зн.get("p", зн["f"]) == место_ == путь_
                and _итог_верен(язык, первый_род, {**зн, "N": зн["N1"], "L": зн["L1"]}, ход1)
                and _итог_верен(язык, R.СТРОК, {**зн, "N": зн["N2"], "L": зн["L2"]}, ходы[1]))
    первый = {**зн, "N": зн.get("N1"), "L": зн.get("L1")}
    if род == R.МЕСТО_ОТКАЗ:
        # предложение назвало путь, какой определяет приказ; мир прочёл «до» — леджер без движения
        return (зн.get("p", зн.get("f")) == _путь_приказа(план, зн)
                and _итог_верен(язык, R.ПЕРЕНОС_ОТКАЗ if план == "перенос" else R.СОЗДАТЬ_ОТКАЗ, первый, ход1))
    if род == R.МЕСТО_НЕВОЗМОЖНО:
        return isinstance(ход1, W.Отказ) and ход1.почему == почему and зн["p"] == ход1.названо()
    if not isinstance(ход1, W.Наблюдение):
        return False
    места = list(dict.fromkeys(R.поле(ход1, "path")))
    if род == R.МЕСТО_МНОГО:
        return len(места) >= 2 and места == [зн[к] for к in ("p1", "p2", "p3") if к in зн]
    if len(места) != 1 or len(ходы) != 2 or W.текст(ходы[1]) != зн["МИР2"]:
        return False
    if план == "найти":
        if места != [зн["f"]] or R.поле(ход1, "line") != [зн[к] for к in ("a", "b") if к in зн]:
            return False
    elif not _итог_верен(язык, {"создать": R.СОЗДАТЬ, "имя": R.ИМЯ, "перенос": R.ПЕРЕНОС}[план], первый, ход1):
        return False
    if зн.get("p", зн["f"]) != места[0] or (план != "найти" and места[0] != _путь_приказа(план, зн)):
        return False
    второй = R.СТРОК if форма.endswith("·строк") else R.УДАЛИТЬ if план == "перенос" else R.ДОПИСАТЬ
    return _итог_верен(язык, второй, {**зн, "N": зн["N2"], "L": зн["L2"]}, ходы[1])


_CARGO = re.compile(r"^test result: (?:ok|FAILED)\. (\d+) passed; (\d+) failed;", re.M)
_UNITTEST = re.compile(r"^Ran (\d+) tests? in .*\n\n(OK|FAILED \(failures=(\d+)\))$", re.M)


def _стоят(отчёт, строки_итога):
    """Числа итога стоят в отчёте бегуна — своим чтением отчёта: строки «test result» cargo по порядку или «Ran N
    tests» и «OK» / «FAILED (failures=K)» unittest."""
    cargo = [(int(п), int(у)) for п, у in _CARGO.findall(отчёт)]
    if cargo:
        return cargo == строки_итога
    м = _UNITTEST.search(отчёт)
    упало = int(м.group(3) or 0) if м else None
    return м is not None and строки_итога == [(int(м.group(1)) - упало, упало)]


def _прогон_верен(язык, зн, мир_, сдвиг, ключи=("N", "L"), папка=None):
    """Ход прогона — отчёт бегуна, снятый с проекта в том состоянии, в каком его держит мир (`папка` — мир после
    прежних актов страницы; без неё — объявленный проект), с запусками «до» + 1; итог — числа отчёта, исход по коду,
    леджер запусков."""
    имя = R.ИМЕНА_ПРОГОНОВ.get(зн["Я"])
    if имя is None:
        return False
    меры, _строки, _отказ = R.клетки(мир_)
    было = меры.get("runs", 0) - сдвиг
    снятое = R.снятое(имя, папка.файлы if папка is not None else None)
    ход_ = W.прогон(имя, снятое, было) if сдвиг else W.счёт_прогонов(имя, было)
    if W.текст(ход_) != мир_:
        return False
    N, L = (зн[к] for к in ключи)
    if N != A.запусков(язык, было + сдвиг) or L != _лед(было, сдвиг):
        return False
    if сдвиг == 0:
        return True
    числа, исход = R.исход(язык, зн["Я"], снятое)
    return (зн["ЧИСЛА"] == числа and зн["ИСХОД"] == исход
            and _стоят("\n".join(снятое["report"]), R.строки_итога(снятое)))


def _итог_верен(язык, род, зн, ход_):
    """Итог — клетки хода мира: леджер меры акта, найденное вопроса, чтение «до» у отказа."""
    меры, строки_, отказ_ = R.клетки(W.текст(ход_))
    N, L = зн.get("N"), зн.get("L")

    def лед(имя, сдвиг, счётная):
        после = меры.get(имя)
        return после is not None and L == _лед(после - сдвиг, сдвиг) and N == счётная(после)

    if род == R.ПРОШЛОЕ:
        return True
    if род in НЕВОЗМОЖНЫЕ_:
        return отказ_ is not None
    if отказ_ is not None:
        return False
    if род in (R.СОЗДАТЬ, R.СОЗДАТЬ_ПАПКА, R.ПЕРЕНОС):
        return лед("files", 1, lambda x: A.файлов(язык, x))
    if род in (R.УДАЛИТЬ, R.УДАЛИТЬ_ПАПКА):
        return лед("files", -1, lambda x: A.файлов(язык, x))
    if род == R.ИМЯ or род in ОТКАЗЫ_СЧЁТА:
        return лед("files", 0, lambda x: A.файлов(язык, x))
    if род in (R.ЗАМЕНА, R.ЗАМЕНА_СЛОВА):
        # новое стояло ноль раз: «0 + k = k» — сколько заменено, столько нового
        до = sum(с.count(зн["B"]) for с in R.папка(язык).файлы[зн["f"]])
        return до == 0 and лед("occurrences", меры.get("occurrences", 0), lambda x: T.раз(язык, x))
    if род in (R.ЗАМЕНА_ОТКАЗ, R.РАЗ):
        return лед("occurrences", 0, lambda x: T.раз(язык, x))
    if род == R.ДОПИСАТЬ:
        return лед("lines", 1, lambda x: T.строк_вин(язык, x))
    if род in (R.ДОПИСАТЬ_ОТКАЗ, R.СТРОК):
        return лед("lines", 0, lambda x: T.строк_вин(язык, x))
    if род == R.ФАЙЛОВ:
        return лед("files", 0, lambda x: A.файлов(язык, x))
    if род in (R.В_КАКОМ, R.НА_СТРОКЕ):
        пути = list(dict.fromkeys(с["path"] for с in строки_))
        return пути == [зн["f"]] and [с["line"] for с in строки_] == [зн[к] for к in ("a", "b") if к in зн]
    if род == R.В_КАКИХ:
        return list(dict.fromkeys(с["path"] for с in строки_)) == [зн[к] for к in ("p1", "p2", "p3") if к in зн]
    if род == R.НИГДЕ:
        return not строки_ and меры.get("occurrences") == 0
    if род == R.ВЫБОР:
        выбор = R.РЕЧЬ[язык]["выбор"]
        if зн["c"] not in выбор or len(строки_) < 2:
            return False
        i = выбор.index(зн["c"])
        return зн["T"] == строки_[-1 if i == 2 else i]["text"]
    if род == R.СТРОКА_Н:
        строка = next((с for с in строки_ if с["line"] == зн["a"]), None)
        return строка is not None and зн["T"] == строка["text"]
    if род in (R.КЛЮЧ, R.О_КЛЮЧЕ):
        if len(строки_) != 1:
            return False
        k, _, v = строки_[0]["text"].partition(" = ")
        if род == R.КЛЮЧ:
            return k == зн["k"] and v == зн["v"]
        return k == зн["k"] and строки_[0]["text"] == зн["T"]
    return False


def _три_верно(язык, форма, зн):
    """Три акта: первый — по дырам приказа; второй дописывает строку на место из строки path первого хода, и это место
    — путь, какой определяет приказ; третий — чтение строк там же или прогон; всякий ход байт в байт, итоги — клетки."""
    мир_, f = R.папка(язык), зн["f"]
    if форма == "создать":
        (мир2, ход1), первый = мир_.create(f), R.СОЗДАТЬ
    elif форма == "имя":
        (мир2, ход1), первый = мир_.move(f, _путь_приказа("имя", зн)), R.ИМЯ
    elif форма == "перенос":
        (мир2, ход1), первый = мир_.move(f, зн["d"]), R.ПЕРЕНОС
    else:
        (мир2, ход1), первый = мир_.replace(f, зн["A"], зн["B"]), R.ЗАМЕНА
    if not isinstance(ход1, W.Наблюдение) or W.текст(ход1) != зн["МИР1"]:
        return False
    место_ = R.поле(ход1, "path")[0]
    if зн.get("p", f) != место_ or место_ != (_путь_приказа(форма, зн) if форма in ("имя", "перенос") else f):
        return False
    if not _итог_верен(язык, первый, {**зн, "N": зн["N1"], "L": зн["L1"]}, ход1):
        return False
    мир3, ход2 = мир2.line(место_, зн["S"])
    if W.текст(ход2) != зн["МИР2"] or not _итог_верен(язык, R.ДОПИСАТЬ, {**зн, "N": зн["N2"], "L": зн["L2"]}, ход2):
        return False
    if форма == "замена":
        return _прогон_верен(язык, зн, зн["МИР3"], 1, ключи=("N3", "L3"), папка=мир3)
    ход3 = мир3.lines(место_)[1]
    return W.текст(ход3) == зн["МИР3"] and _итог_верен(язык, R.СТРОК, {**зн, "N": зн["N3"], "L": зн["L3"]}, ход3)


def _скажи_верно(язык, форма, зн):
    """План «акт, затем зачин и вопрос»: первый акт — по дырам приказа, ход байт в байт, итог — клетки; путь, какой
    назвал организм, — строка path первого хода и путь, какой определяет приказ; второй ход — чтение строк на этом
    месте (ответ — текст первой строки хода) или находка слова во всём репозитории после акта (ответ — путь и строки
    находки), байт в байт."""
    план, вопрос_, _вид = форма.split("·")
    мир_, f = R.папка(язык), зн["f"]
    if план == "имя":
        (мир2, ход1), первый = мир_.move(f, _путь_приказа("имя", зн)), R.ИМЯ
    elif план == "перенос":
        (мир2, ход1), первый = мир_.move(f, зн["d"]), R.ПЕРЕНОС
    else:
        (мир2, ход1), первый = мир_.line(f, зн["S"]), R.ДОПИСАТЬ
    if not isinstance(ход1, W.Наблюдение) or W.текст(ход1) != зн["МИР1"]:
        return False
    место_ = R.поле(ход1, "path")[0]
    if зн.get("p", f) != место_ or место_ != (_путь_приказа(план, зн) if план != "дописать" else f):
        return False
    if not _итог_верен(язык, первый, {**зн, "N": зн["N1"], "L": зн["L1"]}, ход1):
        return False
    if вопрос_ == "первая":
        ход2 = мир2.lines(место_)[1]
        return W.текст(ход2) == зн["МИР2"] and _итог_верен(
            язык, R.ВЫБОР, {**зн, "f": место_, "c": R.РЕЧЬ[язык]["выбор"][0]}, ход2)
    ход2 = мир2.find(".", зн["W"])[1]
    return W.текст(ход2) == зн["МИР2"] and _итог_верен(язык, R.В_КАКОМ, {**зн, "f": место_}, ход2)


def _условие_верно(язык, род, форма, зн):
    """Условный приказ: проверка — ход мира байт в байт (чтение файла, находка текста); ветка страницы — та, какую
    показал мир; акт ветки — второй ход мира, итог — его клетки; ветка без акта — один ход."""
    мир_, f = R.папка(язык), зн["f"]
    if род == R.УСЛОВИЕ_ЗАМЕНА:
        ход1 = мир_.find(f, зн["A"])[1]
        да = isinstance(ход1, W.Наблюдение) and R.мера(ход1, "occurrences") > 0
    else:
        ход1 = мир_.read(f)[1]
        да = isinstance(ход1, W.Наблюдение)
    if W.текст(ход1) != зн["МИР1"] or форма.endswith("|да") != да:
        return False
    if not да and род != R.УСЛОВИЕ_ДОПИСАТЬ:
        return True
    if род == R.УСЛОВИЕ_ЗАМЕНА:
        ход2, род2 = мир_.replace(f, зн["A"], зн["B"])[1], R.ЗАМЕНА
    elif род == R.УСЛОВИЕ_УДАЛИТЬ:
        ход2, род2 = мир_.delete(f)[1], R.УДАЛИТЬ
    elif да:
        ход2, род2 = мир_.line(f, зн["S"])[1], R.ДОПИСАТЬ
    else:
        ход2, род2 = мир_.create(f)[1], R.СОЗДАТЬ
    return W.текст(ход2) == зн["МИР2"] and _итог_верен(язык, род2, зн, ход2)


def _кроме_верно(язык, форма, зн):
    """«Все файлы папки, кроме n»: чтение папки — ход мира байт в байт, итог называет её записи по порядку мира,
    названный файл — среди них; акты идут на всякий файл, кроме названного, по порядку, и итог каждого — клетки."""
    акт = форма.split("·")[0]
    мир_, d, n = R.папка(язык), зн["d"], зн["n"]
    ход1 = мир_.list(d)[1]
    if not isinstance(ход1, W.Наблюдение) or W.текст(ход1) != зн["МИР1"]:
        return False
    записи = R.поле(ход1, "path")
    if записи != [зн[к] for к in ("p1", "p2", "p3") if к in зн] or n not in записи:
        return False
    цели = [f"{d}/{з}" for з in записи if not з.endswith("/") and з != n]
    if [зн[к] for к in ("q1", "q2") if к in зн] != цели:
        return False
    for путь, (м, N, L) in zip(цели, (("МИР2", "N2", "L2"), ("МИР3", "N3", "L3"))):
        мир_, ход_ = мир_.delete(путь) if акт == "удалить" else мир_.move(путь, зн["e"])
        род_ = R.УДАЛИТЬ_ПАПКА if акт == "удалить" else R.ПЕРЕНОС
        if W.текст(ход_) != зн[м] or not _итог_верен(язык, род_, {**зн, "N": зн[N], "L": зн[L]}, ход_):
            return False
    return True


def _двух_верно(язык, форма, зн):
    """Два объекта: акт на первый, затем на второй — на мире после первого; всякий ход байт в байт, итоги — клетки."""
    акт = форма.split("·")[0]
    мир_ = R.папка(язык)
    for x, (м, N, L) in ((зн["f"], ("МИР1", "N1", "L1")), (зн["q"], ("МИР2", "N2", "L2"))):
        if акт == "создать":
            (мир_, ход_), род_ = мир_.create(x), R.СОЗДАТЬ
        elif акт == "удалить":
            (мир_, ход_), род_ = мир_.delete(x), R.УДАЛИТЬ
        elif акт == "перенести":
            (мир_, ход_), род_ = мир_.move(x, зн["d"]), R.ПЕРЕНОС
        else:
            (мир_, ход_), род_ = мир_.line(x, зн["S"]), R.ДОПИСАТЬ
        if W.текст(ход_) != зн[м] or not _итог_верен(язык, род_, {**зн, "f": x, "N": зн[N], "L": зн[L]}, ход_):
            return False
    return зн["f"] != зн["q"]


_ПЕРВЫЙ = {R.ПЛАН_ЗАМЕНА: R.ЗАМЕНА, R.ПЛАН_ДОПИСАТЬ: R.ДОПИСАТЬ, R.ПЛАН_ПЕРЕНОС: R.ПЕРЕНОС}
_ПЕРВЫЙ_ОТКАЗ = {"замена": R.ЗАМЕНА_ОТКАЗ, "дописать": R.ДОПИСАТЬ_ОТКАЗ, "перенос": R.ПЕРЕНОС_ОТКАЗ}


def _вердикт(язык, род, форма, зн):
    if род in (R.ТЕСТЫ, R.ТЕСТЫ_ОТКАЗ, R.ТЕСТЫ_СКОЛЬКО, R.ПЛАН_ТЕСТЫ_СКОЛЬКО):
        return _прогон_верен(язык, зн, зн["МИР"], 0 if род == R.ТЕСТЫ_ОТКАЗ else 1)
    if род == R.ТРИ_АКТА:
        return _три_верно(язык, форма, зн)
    if род == R.ПЛАН_СКАЖИ:
        return _скажи_верно(язык, форма, зн)
    if род in R.УСЛОВНЫЕ:
        return _условие_верно(язык, род, форма, зн)
    if род == R.ВСЕ_КРОМЕ:
        return _кроме_верно(язык, форма, зн)
    if род == R.ДВА_ОБЪЕКТА:
        return _двух_верно(язык, форма, зн)
    ходы = _ход(язык, род, форма, зн)
    if not ходы:
        return False
    if род in R.МЕСТО:
        return _место_верно(язык, род, форма, зн, ходы)
    if род in (R.ПЛАН_ЗАМЕНА, R.ПЛАН_ДОПИСАТЬ, R.ПЛАН_ПЕРЕНОС, R.ПЛАН_ОТКАЗ):
        первый = _ПЕРВЫЙ_ОТКАЗ[форма] if род == R.ПЛАН_ОТКАЗ else _ПЕРВЫЙ[род]
        if W.текст(ходы[0]) != зн["МИР1"] or not _итог_верен(язык, первый, {**зн, "N": зн["N1"], "L": зн["L1"]},
                                                             ходы[0]):
            return False
        if род == R.ПЛАН_ОТКАЗ:
            return True
        if форма == "перенос":
            return (зн["q"] != зн["f"] and W.текст(ходы[1]) == зн["МИР2"]
                    and _итог_верен(язык, R.УДАЛИТЬ, {**зн, "N": зн["N2"], "L": зн["L2"]}, ходы[1]))
        мир_ = R.папка(язык)
        мир2 = (мир_.replace(зн["f"], зн["A"], зн["B"]) if форма == "замена" else мир_.line(зн["f"], зн["S"]))[0]
        return _прогон_верен(язык, зн, зн["МИР2"], 1, папка=мир2)
