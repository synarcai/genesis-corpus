def _свой(зн):
    """Строка этого мира: её пути и имена — имена мира, папки — папки мира, язык проекта — объявленный."""
    def есть(ключ, свои):
        return any(x in свои for x in зн[ключ].split("\n"))
    for ключ in ("f", "g", "n", "q", "s", "p1", "p2", "p3", "q1", "q2"):
        if ключ in зн and not есть(ключ, _СВОИ_ИМЕНА):
            return False
    for ключ in ("d", "e"):
        if ключ in зн and not есть(ключ, _ПАПКИ):
            return False
    return "Я" not in зн or есть("Я", R.ИМЕНА_ПРОГОНОВ)


