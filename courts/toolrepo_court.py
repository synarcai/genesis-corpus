def _значения(м):
    """({дыра: значение}, согласна ли страница с собой): повторная дыра обязана нести одно значение; «X» и «X·» —
    слова одного текста."""
    вон, согласна = {}, True
    for ключ, знач in м.groupdict().items():
        имя = ключ.split("_", 2)[2]
        имя = _ИЗ_ЛАТ.get(имя, имя)
        if имя in вон and вон[имя] != знач:
            согласна = False
            вон[имя] = вон[имя] + "\n" + знач
            continue
        вон[имя] = знач
    for имя in ("A", "B", "W"):
        if имя + "·" in вон:
            вон[имя] = вон[имя] + " " + вон.pop(имя + "·")
    return вон, согласна


