# a prime number» / «is NOT a prime number». Суд берёт полярность из
# этого слова и требует, чтобы она сошлась с пересчётом основания, — так
# же, как вопросная форма берёт её из «yes/no». Функции проверки общие
# там, где группы совпадают (простота, делимость): один закон, две
# поверхности. Где сказуемое несёт группу, которой нет в вопросе, —
# своя проверка, но тот же пересчёт.


def _инъекция_повеств(м):
    k, a, b, c = ч(м, 1, 3, 4, 5)
    да = м.group(2) in ("is injective", "инъективна")
    разные = м.group(6) in ("all different", "все разные")
    return (a == k and b == 2 * k and c == 3 * k
            and разные == (len({a, b, c}) == 3)
            and да == (k != 0) and разные == да)


def _условное_запятой(м):
    """«если n чётно, n + m чётно: e чётно и e + m = s.» — полярность слова
    судится чётностью m, свидетель — чётностью e и счётом суммы."""
    m, слово, e, e2, m2, s_ = м.groups()
    m, e, e2, m2, s_ = int(m), int(e), int(e2), int(m2), int(s_)
    return (e == e2 and m == m2 and e % 2 == 0 and e + m == s_
            and (слово == "чётно") == (m % 2 == 0))


def _условное_повеств(м):
    m_, e, e2, m2, s = ч(м, 1, 3, 4, 5, 6)
    да = м.group(2) in ("is even", "чётно")
    чётно = м.group(7) in ("even", "чётно")
    return (e % 2 == 0 and e2 == e and m2 == m_ and e + m_ == s
            and чётно == (s % 2 == 0) and да == (m_ % 2 == 0))


def _сумма_повеств(м):
    k, итог, итог2 = ч(м, 1, 2, 4)
    ряд = [int(x) for x in re.findall(r"\d+", м.group(3))]
    return (ряд == [2 * j + 1 for j in range(k)]
            and sum(ряд) == итог == итог2 == k * k)


def _квадрат_повеств(м):
    n, sq, n2, n3, sq2 = ч(м, 1, 2, 3, 4, 5)
    return n2 == n3 == n and sq == sq2 == n * n


