def делители(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def простое(n):
    return n > 1 and делители(n) == [1, n]


def ч(м, *номера):
    """Целые из НАЗВАННЫХ скобок — не из всей строки.

    Первая редакция брала все числа подряд из совпадения, и «the
    divisors of 47 are 1 and 47» отдавала четыре числа вместо трёх:
    единица закона попадала в счёт наравне с величинами показа. Число,
    стоящее в записи БУКВОЙ ЗАКОНА («= 4 × q + r», «1 и n»), не есть
    величина ряда, и суд обязан брать ровно то, что назвал образцом.
    """
    return [int(м.group(i)) for i in номера]


