def буквенный(номер):
    """Есть ли в номере составляющая не из одних цифр («85.T», «6.x»)."""
    return any(not к.isdigit() for к in номер.split("."))


def не_буквенное(дерево):
    """Нумерует ли дерево себя ОДНИМИ цифрами — тогда буква ему чужая."""
    return not any(буквенный(н) for н in дерево)


def вне_ряда(номер, дерево):
    """Больше ли старший ярус номера всего, что дерево объявило.

    Дерево, чей наибольший старший ярус есть сто сорок два, не имеет
    теоремы с номером тысяча восемьсот девяносто восемь; такое число
    пришло из года, из страницы или из чужой нумерации. Порог не
    назначен — он ВЫЧИСЛЕН из самих объявлений.
    """
    вершина = номер.split(".")[0]
    if not вершина.isdigit():
        return False
    свои = [int(н.split(".")[0]) for н in дерево
            if н.split(".")[0].isdigit()]
    return bool(свои) and int(вершина) > max(свои)


def свой_предшественник(слово):
    """Не назвал ли предшествующий знак ЧУЖОЕ дерево.

    ЗАКОН ВТОРОЙ, КУПЛЕННЫЙ ЗАМЕРОМ. Перед знаком рода стоит либо
    ничто (начало строки), либо знак препинания, либо объявленное
    служебное слово — тогда ссылка о своём дереве. Голое имя («spec»,
    «CVE», «CFR», римская «V») называет чужое, и ребро это не наше.
    """
    if not слово:
        return True
    с = слово.strip().lower()
    if с in СВОИ_ПРЕДШЕСТВЕННИКИ:
        return True
    # знак препинания на конце — «(», «,», «—», «:» и прочее
    return not с[-1:].isalnum()


def начало_строки(строка, м):
    """Стоит ли знак рода в САМОМ начале строки — тогда это объявление.

    Объявление не есть ссылка: «Глава 19. Дзета» вводит главу, а не
    ссылается на неё. Признак — перед знаком рода нет ничего, кроме
    пробелов и решёток заголовка.
    """
    до = строка[:м.start()]
    return not до.strip() and not (м.group(1) or "").strip()


class Слой:
    """Дерево, объявленное САМИМ КОРПУСОМ, — собранное одним проходом.

    Корпуса тяжелы (двести двадцать две тысячи строк на семь файлов), и
    искать объявление на каждую ссылку значило бы читать файл столько
    раз, сколько в нём ссылок. Объявления собираются ОДИН РАЗ, ссылки
    разрешаются множеством.
    """

    def __init__(self):
        # ДВА ДЕРЕВА, А НЕ ОДНО: своё имя корпус пишет на своём языке,
        # а чужую книгу цитирует на её. Ключ — латиница ли слово рода.
        self.утверждения = {False: set(), True: set()}
        self.разделы = {False: set(), True: set()}
        # §-ОБЪЯВЛЕНИЯ ДЕРЖАТСЯ ОТДЕЛЬНО: только они однозначны, и
        # только по ним судится разрыв ряда. Голое «2.10 …» в начале
        # строки бывает десятичным числом («2.10 значения не выведены»),
        # и ряд по таким числам был бы рядом выдуманным.
        self.параграфы = set()

    def впитать(self, путь):
        with pathlib.Path(путь).open(encoding="utf-8",
                                     errors="replace") as поток:
            for строка in поток:
                m = ОБЪЯВЛ_УТВЕРЖДЕНИЯ.match(строка)
                if m:
                    self.утверждения[
                        _латиница(m.group(1).lower())].add(m.group(2))
                m = ОБЪЯВЛ_ПАРАГРАФ.match(строка)
                if m:
                    self.параграфы.add(m.group(1))
                    # ЗАГОЛОВОК ЗНАКОМ «§» ЯЗЫКА НЕ НЕСЁТ и потому
                    # питает оба дерева разделов разом.
                    self.разделы[False].add(m.group(1))
                    self.разделы[True].add(m.group(1))
                    continue
                m = ОБЪЯВЛ_СЛОВОМ.match(строка)
                if m:
                    self.разделы[
                        _латиница(m.group(1).lower())].add(m.group(2))
                    continue
                m = ОБЪЯВЛ_НОМЕРОМ.match(строка)
                if m:
                    self.разделы[False].add(m.group(1))
                    self.разделы[True].add(m.group(1))


def ряд_открыт(номер, объявленные):
    """Объявлено ли НАЧАЛО ряда, к которому принадлежит номер.

    ЗАКОН: РАЗРЫВ СУДИТСЯ ЛИШЬ В РЯДУ, КОТОРЫЙ КОРПУС САМ ОТКРЫЛ.
    `diakrisis_ru` пишет «§00.03» и «§06.02», но ни «§00.01», ни
    «§06.01» не объявляет: ряд начат не здесь, номера пришли из
    другого документа, и звать их разрывом значило бы вменить корпусу
    чужую нумерацию. Начало ряда пробуется в обеих записях — с нулём
    впереди и без него.
    """
    куски = номер.split(".")
    if len(куски) < 2:
        return False
    ширина = len(куски[-1])
    голова = куски[:-1]
    return bool({".".join(голова + ["1"]),
                 ".".join(голова + ["1".zfill(ширина)])} & объявленные)


def предшествующий_номер(номер):
    """Номера, любой из которых годится предшественником в ряду.

    НУЛЬ ВПЕРЕДИ БЫВАЕТ И БЫВАЕТ НЕ. Корпус пишет «§18.9» и «§18.10» —
    предшественник десятого есть девятый БЕЗ нуля; но пишет и «§06.02»,
    где предшественник есть «06.01» С нулём. Прибор, знавший одну
    запись, обвинял бы другую: обе пробуются, и хватает любой.
    """
    куски = номер.split(".")
    последний = куски[-1]
    if not последний.isdigit() or int(последний) <= 1:
        return None
    п = int(последний) - 1
    голова = куски[:-1]
    return {".".join(голова + [str(п)]),
            ".".join(голова + [str(п).zfill(len(последний))])}


def _ссылки(строка, образец, дерево):
    """[(номер, судимо)] — ссылки строки, отсеянные законами границы.

    `дерево` есть ПАРА множеств: русское и латинское.
    """
    вон = []
    for м in образец.finditer(строка):
        # ПРЕДШЕСТВЕННИК БЕРЁТСЯ ИЗ САМОГО СОВПАДЕНИЯ, А НЕ ИЩЕТСЯ
        # ЗАНОВО. Первая редакция искала слово ПЕРЕД началом
        # совпадения — а совпадение уже включало предшественника, и
        # прибор смотрел на слово ДВУМЯ назад: «в препринте §2.2»
        # проверялось по «в» вместо «препринте», и чужая ссылка
        # объявлялась своей. Двести сорок пять ложных первого прогона
        # выросли в основном отсюда.
        if начало_строки(строка, м):
            continue
        if not свой_предшественник(м.group(1)):
            continue
        # ЯЗЫК ЗНАКА РОДА ВЫБИРАЕТ ДЕРЕВО, и дерево пустое молчит.
        своё = дерево[_латиница(м.group(2).lower())]
        if not своё:
            continue
        # ФОРМА НОМЕРА ОБЯЗАНА БЫТЬ ФОРМОЙ ЭТОГО ДЕРЕВА. `uhm_en`
        # нумерует теоремы одними цифрами («Theorem 10.1») и пишет
        # «Theorems 6.x» — семейство, а не номер; `diakrisis_ru`
        # нумерует буквой («85.T»), и там такая форма законна. Суд,
        # не знавший формы дерева, звал бы семейство битой ссылкой.
        if не_буквенное(своё) and буквенный(м.group(3)):
            continue
        # НОМЕР ВЫШЕ ВСЕГО ОБЪЯВЛЕННОГО НЕ ИЗ ЭТОГО ДЕРЕВА. «Теорема
        # 1898 года о нормированных алгебрах» есть теорема ГОДА, а не
        # номер: старший ярус её больше всякого объявленного здесь
        # (у самого длинного корпуса он не превосходит полутора сотен).
        # Правило выведено из объявлений, а не назначено числом.
        if вне_ряда(м.group(3), своё):
            continue
        вон.append((м.group(3), м.group(3) in своё))
    return вон


def судить(строка, слой=None):
    """(судимо, истинно) для одной строки прозы в её корпусе.

    БЕЗ СЛОЯ ВЕРДИКТА НЕТ. Ссылка есть ребро, а ребро не судится вне
    графа: строка, вынутая из корпуса, о разрешимости своей ссылки не
    свидетельствует. Это не слабость прибора, а свойство предмета.
    """
    if слой is None:
        return False, False
    с = строка.rstrip("\n")
    if not с.strip():
        return False, False

    # РОД ТРЕТИЙ: РАЗРЫВ РЯДА. Судится на самой строке объявления —
    # она вводит §N и тем самым утверждает, что ряд до N существует.
    m = ОБЪЯВЛ_ПАРАГРАФ.match(с)
    if m and ряд_открыт(m.group(1), слой.параграфы):
        нужны = предшествующий_номер(m.group(1))
        if нужны is not None:
            return True, bool(нужны & слой.параграфы)

    # РОД ПЕРВЫЙ: ССЫЛКА НА УТВЕРЖДЕНИЕ.
    if any(слой.утверждения.values()):
        найдено = _ссылки(с, ССЫЛКА_УТВЕРЖДЕНИЕ, слой.утверждения)
        if найдено:
            return True, all(и for _н, и in найдено)

    # РОД ВТОРОЙ: ССЫЛКА НА РАЗДЕЛ — словом рода либо знаком §.
    if any(слой.разделы.values()):
        найдено = _ссылки(с, ССЫЛКА_РАЗДЕЛ, слой.разделы)
        # §-ССЫЛКА СУДИТСЯ ЛИШЬ ТАМ, ГДЕ КОРПУС САМ ПИШЕТ §-ЗАГОЛОВКИ.
        # В корпусе без §-объявлений знак этот называет чужую
        # спецификацию, и замер это показал: `verum_en` несёт два своих
        # §-заголовка и триста семьдесят шесть ссылок в чужой документ.
        if найдено:
            return True, all(и for _н, и in найдено)

    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        # СУД ЧИТАЕТ ПРОЗУ, А НЕ ПОКАЗЫ, и объявляет это обходом —
        # палата берёт объявление отсюда.
        return worlds(kind="prose")
    except Unreadable as беда:
        print(f"ДЕРЕВО ПРОЗЫ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ДЕРЕВО ПРОЗЫ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        слой = Слой()
        слой.впитать(путь)
        свои_ложных = свои_судимых = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка, слой)
                if not судимо:
                    continue
                свои_судимых += 1
                if not истинно:
                    свои_ложных += 1
                    if len(примеры) < 30:
                        примеры.append(
                            f"{путь.name}: {строка.strip()[:88]}")
        судимых += свои_судимых
        ложных += свои_ложных
        print(f"  {путь.name:<20} объявл: утв "
              f"{len(слой.утверждения[False]):4}ру/"
              f"{len(слой.утверждения[True]):<4}en разд "
              f"{len(слой.разделы[False]):5}ру/"
              f"{len(слой.разделы[True]):<5}en § {len(слой.параграфы):5}"
              f" | судимых {свои_судимых:6} ложных {свои_ложных:4}")
    for п in примеры:
        print(f"    БИТАЯ {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ДЕРЕВО ПРОЗЫ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
