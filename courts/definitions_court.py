#!/usr/bin/env python3
"""[ОПРЕДЕЛЕНИЯ] — цитата находится в названном словаре полки снова.

Мир определений (tools/gen_genesis_definitions.py) показывает
«понятие — это <цитата>: <источник>» и «что такое понятие? понятие —
это <цитата>: <источник>» (и то же по-английски: «X is …: Webster's
Unabridged Dictionary, 1913.»). Суд не знает, ЧТО такое энтропия, и не
судит толкования по существу — он судит ОСНОВАНИЕ, названное после
двоеточия, тремя проверками без вывода:

  · ИСТОЧНИК ЕСТЬ НА ПОЛКЕ — файл словаря объявлен манифестом (поле
    `file` мира полки) и лежит на месте; год в ярлыке равен году
    издания, объявленному манифестом (`издано`);
  · ЦИТАТА СТОИТ В ТЕЛЕ СТАТЬИ ПОДСТРОКОЙ — после нормализации пробелов
    (первая буква вольна в регистре: словарь начинает толкование с
    заглавной, показ ставит его после связки строчной);
  · СЛОВО-ПОНЯТИЕ СТОИТ В ЗАГОЛОВКЕ ЭТОЙ СТАТЬИ — целым словом. У ЭСБЕ
    статья названа в ярлыке («ЭСБЕ, статья «Сила, в механике»»), и
    цитата ищется именно в ней; у Webster и Даля статью называет само
    понятие, и цитата ищется во всех статьях с его заголовком.

Порча любого слова цитаты рвёт подстроку — ложь; порча понятия рвёт
заголовок — ложь; порча года рвёт манифест — ложь. Дом разреза статей и
нормализации один у генератора и суда (tools/definitions.py); правил
ОТБОРА цитаты суд не знает — он делит определение, но не вывод.

ЧЕГО СУД НЕ ЧИТАЕТ: строку без ярлыка словаря полки после двоеточия —
(False, False). Словарь режется лениво, при первой судимой строке:
палата зовёт суд на всякую строку свода, и разрез 26 МБ Webster не
должен платиться за строки чужих миров.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import definitions as D  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ПОНЯТИЕ_EN = r"[a-z][a-z' -]*[a-z]"
ПОНЯТИЕ_RU = r"[а-яё][а-яё -]*[а-яё]"
ОБРАЗЦЫ = (
    ("en", re.compile(rf"^(?:what is (?P<в>{ПОНЯТИЕ_EN})\? )?(?P<п>{ПОНЯТИЕ_EN}) is "
                      rf"(?P<ц>.+): (?P<я>Webster's Unabridged Dictionary, \d{{4}})\.$")),
    ("ru", re.compile(rf"^(?:что такое (?P<в>{ПОНЯТИЕ_RU})\? )?(?P<п>{ПОНЯТИЕ_RU}) — это "
                      rf"(?P<ц>.+): (?P<я>ЭСБЕ, статья «[^«»]+»|Толковый словарь Даля, \d{{4}})\.$")),
)
БЫСТРО = re.compile(r": (?:Webster's Unabridged Dictionary, \d{4}|ЭСБЕ, статья «[^«»]+»"
                    r"|Толковый словарь Даля, \d{4})\.$")


def _источник(ярлык):
    """(источник, год или заголовок статьи) по ярлыку, или (None, None)."""
    for имя, образец in D.ЯРЛЫКИ.items():
        м = образец.match(ярлык)
        if м:
            return D.ИСТОЧНИКИ[имя], м.group(1)
    return None, None


def _истинно(понятие, цитата, ярлык):
    источник, довод = _источник(ярлык)
    if источник is None or not D.объявленные_файлы(источник):
        return False
    словарь = D.словарь(источник.имя)
    if источник.имя == "esbe":
        статьи = словарь.по_заголовку(довод)
    else:
        if str(D.год(источник)) != довод:
            return False
        статьи = словарь.по_слову(понятие)
    return any(D.понятие_в_заголовке(понятие, с.заголовок)
               and D.цитата_в_теле(цитата, с.тело) for _, с in статьи)


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not БЫСТРО.search(с):
        return False, False
    for _, образец in ОБРАЗЦЫ:
        м = образец.match(с)
        if not м:
            continue
        понятие, цитата, ярлык = м.group("п"), м.group("ц"), м.group("я")
        if м.group("в") is not None and м.group("в") != понятие:
            return True, False
        return True, bool(_истинно(понятие, цитата, ярлык))
    return False, False


def main():
    import collections
    итог = collections.Counter()
    пути = [pathlib.Path(п) for п in sys.argv[1:]] or [
        КОРЕНЬ / "datasets" / "genesis_definitions.txt"]
    for путь in пути:
        if not путь.is_file():
            print(f"ОПРЕДЕЛЕНИЯ ОТКАЗ: файла «{путь}» нет, судить нечего")
            return 2
        for с in путь.read_text(encoding="utf-8").splitlines():
            if not с.strip():
                continue
            судимо, истинно = судить(с)
            итог["несудимо" if not судимо else ("истина" if истинно else "ЛОЖЬ")] += 1
            if судимо and not истинно:
                print("  ЛОЖЬ:", с[:120])
    ложь = итог["ЛОЖЬ"]
    print(f"ОПРЕДЕЛЕНИЯ {'PASS' if ложь <= ЛОЖНЫХ_РУБЕЖ else 'FAIL'}: {ложь} ложных, "
          f"{итог['истина']} истинных, {итог['несудимо']} несудимых")
    return 0 if ложь <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
