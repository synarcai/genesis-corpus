#!/usr/bin/env python3
"""[РУССКОЕ СОГЛАСОВАНИЕ] — форма слова обязана идти за числом.

    3 паскаля   истинно        3 паскалей   ложно
    2 квадратных метра  истинно   2 квадратных метров  ложно

СУД СОГЛАСОВАНИЯ ЗНАЛ ТОЛЬКО АНГЛИЙСКИЙ: его образец `\\b1 ([a-z]+)\\b`
берёт лишь латиницу, и всякая русская ошибка проходила сквозь него
молча. За одну смену я написал четыре таких ошибки в трёх слоях, и три
из них поймал глаз, а не прибор — то есть не поймал бы, будь смена
длиннее.

СУД ВЛАДЕЕТ ТЕМ, ЧТО ОБЪЯВЛЕНО, И МОЛЧИТ О ПРОЧЕМ. Слово, не названное
в `tools/rugram.py`, не судится вовсе: суд не знает русского языка, он
знает объявленные тройки форм. Это честная граница, а не слабость —
она и делает вердикт вердиктом.

ЧИСЛИТЕЛЬНОЕ СЛОВОМ ТОЖЕ СЧИТАЕТСЯ: «два часа» есть тот же счёт, что
«2 часа», и форма при нём та же.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import Unreadable, worlds  # noqa: E402
from rugram import ПО_ФОРМЕ, согласовано  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# число, затем одно или два слова: «3 паскаля», «2 квадратных метра»
# ПРЕДЫДУЩЕЕ СЛОВО БЕРЁТСЯ ПО МЕСТУ, А НЕ ИЗ ЗАХВАТА. Прежний образец
# ловил «перед» частью совпадения — и на строке «1 неделя против 3
# месяцев» первое совпадение съедало «против» хвостом («неделя
# против»), а второе оставалось БЕЗ управляющего слова вовсе. Родительный
# по предлогу читался как сбой счёта, и вина была не в списке
# управляющих, а в том, что совпадение поглощало соседа.
СЧЁТОМ = re.compile(r"\b(\d+) ([а-яё]+(?: [а-яё]+)?)")

# СЧЁТ НЕ ВСЯКОЕ ЧИСЛО ПРИ СЛОВЕ. Русский родительный приходит и по
# УПРАВЛЕНИЮ: «не более 4 шагов», «около 5 метров», «номер 7 недели» —
# формы верны и правилу счёта не подчиняются вовсе. Первая редакция
# этого не знала и объявила ложью шестьдесят честных строк слоя
# алгоритмов и двадцать календаря: суд, обвиняющий слишком охотно,
# опаснее молчащего, ибо его вердикт выглядит работой.
#
# Слова, требующие родительного, ОБЪЯВЛЕНЫ: вывести их из формы нельзя.
# СЛОВО, ТРЕБУЮЩЕЕ РОДИТЕЛЬНОГО, СНИМАЕТ СЧЁТНОЕ СОГЛАСОВАНИЕ. «в
# течение 24 часов» и «против 3 месяцев» верны по-русски, и суд,
# знавший лишь счёт, звал их ложью: обвинение по форме без разбора
# СВЯЗИ. Список рос дважды — сперва предлогами, потом
# существительными, — и оба раза от одного и того же: проза говорит
# управлением там, где показ говорит счётом.
УПРАВЛЯЮТ = {"более", "менее", "больше", "меньше", "около", "свыше",
             "номер", "до", "от", "из", "порядка", "минимум", "максимум",
             "первых", "первые", "последних", "всего",
             # предлоги и обороты, требующие родительного
             "течение", "продолжение", "протяжении", "против", "для",
             "без", "кроме", "вместо", "сверх", "среди", "у",
             # имена, требующие родительного при счёте
             "совокупность", "сумма", "набор", "список", "число",
             "количество", "множество", "группа", "пара", "тройка",
             "всех", "этих", "тех", "своих",
             # имена, требующие родительного при счёте
             "стирание", "глава", "главы", "чаще", "реже", "возрасте",
             "пределах", "протяжении", "с"}

# ДВУСЛОВНЫЕ ОБОРОТЫ УПРАВЛЕНИЯ — объявлены парой, ибо ни одно их
# слово в одиночку родительного не требует.
УПРАВЛЯЮТ_ПАРОЙ = {"в течение", "в возрасте", "в пределах",
                   "на протяжении", "по крайней", "не менее",
                   "не более", "чаще одного", "в размере"}

# ФОРМА, ПРИЗНАННАЯ НАРЯДУ С ОБЪЯВЛЕННОЙ. «8 бит» и «8 битов» оба
# живут в русском, и технический обиход держит краткую. Такие слова
# названы здесь, а не молча прощены образцом.
КРАТКИЕ = {"бит", "байт"}


def судить(строка):
    """(судимо, истинно) для одной строки."""
    судимо = True
    хоть_раз = False
    for м in СЧЁТОМ.finditer(строка):
        перед, число, слова = строка[:м.start()], м.group(1), м.group(2)
        # ЧИСЛО, ПРОДОЛЖАЮЩЕЕ ЧИСЛО, НЕ ЕСТЬ ОТДЕЛЬНОЕ ЧИСЛО. «0.577
        # шага», «2,75 раза», «2-3 дней», «1–2 дней» суть ОДНА величина
        # — дробь или предел, — и берут родительный единственного, а не
        # счёт. Суд, читавший «577» отдельным числом, объявил ложью
        # двадцать пять честных строк: он считал не то, что видел.
        # Признак взят по знаку, а не по словарю: перед числом стои́т
        # разделитель, а до него цифра.
        хвост = перед.rstrip()
        if хвост[-1:].isdigit():
            continue
        if хвост[-1:] in ".,–-—/:" and хвост[-2:-1].isdigit():
            continue
        # ЧИСЛО В СОСТАВЕ ИМЕНИ ЕСТЬ ЧАСТЬ ИМЕНИ. «G-21 карты», «§ 4
        # пункта» — двадцать первое есть НОМЕР, и слово рядом к нему
        # не относится счётом.
        if хвост[-1:] in "-‑–" and хвост[-2:-1].isalpha():
            continue
        # ЧИСЛО ВНУТРИ ЗАПИСИ ЕСТЬ ЧЛЕН ВЫРАЖЕНИЯ, А НЕ СЧЁТ. «N =
        # q²+q+1 узлов» говорит о величине, а не о единице узлов.
        #
        # ПУСТАЯ СТРОКА ЕСТЬ ПОДСТРОКА ЛЮБОЙ, И СТРАЖ, СПРАШИВАЮЩИЙ
        # «in», ОТКРЫВАЕТСЯ НА ПУСТОТЕ. Страж стоял как
        # «хвост[-1:] in "+=²³)⁄^*"», и когда число начинало строку,
        # хвост был пуст: «"" in "+=²³)⁄^*"» есть ИСТИНА, и суд
        # пропускал показ ВОВСЕ. «5 яблоко лежит на столе» не судилось
        # ни разу; та же ложь в середине строки — «в корзине 5 яблоко»
        # — ловилась исправно. Радиус дыры: 467 строк в семи мирах.
        # Ложных среди них не оказалось, но страж был открыт
        # безусловно, и первая же такая ошибка прошла бы молча.
        #
        # Два соседних стража от того же спасены ВТОРЫМ условием
        # («и до него цифра», «и до него буква»), которое на пустоте
        # ложно. У этого второго условия не было — потому пустота
        # проверяется прямо. Дыру открыло вчерашнее лечение, и нашла
        # её подсадка, а не чтение: ПРОВЕРКА ГРАНИЦЫ НЕ ВЫВОДИТСЯ
        # ГЛАЗАМИ ИЗ КОДА, КОТОРЫЙ КАЖЕТСЯ ОЧЕВИДНЫМ.
        if хвост and хвост[-1] in "+=²³)⁄^*":
            continue
        # УПРАВЛЯЕТ БЛИЖАЙШЕЕ СЛОВО, А НЕ ВЕСЬ ЗАХВАТ. Образец берёт
        # перед числом кусок текста, и «1 неделя против» приходило
        # целиком: сравнение с управляющим списком не совпадало ни с
        # чем, и родительный по предлогу читался как сбой счёта.
        куски = перед.strip(",.:;()—-").lower().split()
        предыдущее = куски[-1] if куски else ""
        # УПРАВЛЕНИЕ БЫВАЕТ ДВУСЛОВНЫМ, И ТОГДА НАЗАД СМОТРИТСЯ НЕ
        # ПРЕДЛОГ, А ЕГО ХВОСТ: у «в течение» — «течение», у «в
        # возрасте» — «возрасте». Один оборот «в течение» снимал шесть
        # ложных обвинений из двенадцати. Смотрим два токена, а не один.
        пара = " ".join(куски[-2:]) if len(куски) >= 2 else ""
        if предыдущее in УПРАВЛЯЮТ or пара in УПРАВЛЯЮТ_ПАРОЙ:
            continue
        # ЧИСЛО ПОСЛЕ СЧЁТНОГО СЛОВА МЕТИТ ЕГО, А НЕ СЧИТАЕТ СЛЕДУЮЩЕЕ.
        # «после шага 2 значение равно 3» — двойка есть НОМЕР ШАГА, и
        # «значение» к ней не относится вовсе. Суд, читавший всякую
        # пару «число + слово» как счёт, объявил ложью девяносто честных
        # строк кибернетики: обвинение по форме без разбора связи.
        if предыдущее in ПО_ФОРМЕ:
            continue
        n = int(число)
        # ЧЕТЫРЁХЗНАЧНОЕ ЧИСЛО ПЕРЕД «ГОД» ЕСТЬ ПОРЯДКОВОЕ, А НЕ СЧЁТ.
        # «2035 год» читается «две тысячи тридцать пятый год» и счётного
        # согласования не требует вовсе; суд, знавший лишь счёт, объявил
        # ложью сорок честных строк прозы — дат, а не количеств. Признак
        # взят по существу, а не по списку: год есть НОМЕР В РЯДУ, и
        # четыре знака при слове «год» иным быть почти не могут.
        if 1000 <= n <= 2999 and слова.split()[0].startswith("год"):
            continue
        if слова.split()[0] in КРАТКИЕ:
            continue
        # ДЛИННОЕ ИМЯ ПРОБУЕТСЯ ПЕРВЫМ: «квадратных метра» есть одно
        # объявленное имя, а не «метра» с лишним словом впереди.
        for кандидат in (слова, слова.split()[0]):
            если = согласовано(n, кандидат)
            if если is None:
                continue
            хоть_раз = True
            if not если:
                return True, False
            break
    return (True, True) if хоть_раз else (False, True)


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"РУССКОЕ СОГЛАСОВАНИЕ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    if not ПО_ФОРМЕ:
        print("РУССКОЕ СОГЛАСОВАНИЕ ОТКАЗ: формы не объявлены")
        return 2
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("РУССКОЕ СОГЛАСОВАНИЕ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"РУССКОЕ СОГЛАСОВАНИЕ {поза}: {ложных} ложных из {судимых} "
          f"судимых ({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
