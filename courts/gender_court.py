#!/usr/bin/env python3
"""[РОД В ЧУЖОМ ЯЗЫКЕ] — согласие таблицы с собою, пересчитанное судом.

Суд не пишет закона заново: он берёт его у дома (`genderforms`), где род всякого слова
объявлен рукой того, кто язык знает. И судит он СОГЛАСИЕ, а не истину рода:

    РОД СЛОВА НЕ ВЫВОДИТСЯ НИ ИЗ ЧЕГО; МЕРА ЕГО ЕСТЬ ОБЪЯВЛЕНИЕ, А ПРОВЕРКА — СОГЛАСИЕ.

Всякая пара «артикль ↔ имя рода» на странице сверяется с таблицей дома: подменённый
артикль ловится, подменённое имя рода ловится, а вопрос, точно ли Tisch мужского рода,
суду не подсуден — на него отвечает словарь, а не счёт.

ЕДИНСТВЕННОЕ ИСКЛЮЧЕНИЕ ОБЪЯВЛЕНО ДОМОМ И ПРОПУЩЕНО СУДОМ: «el agua» несёт мужской
артикль при женском роде, и потому проверка артикля при имени рода делается лишь тогда,
когда артикль есть артикль ЕДИНСТВЕННОГО числа этого самого слова.

    python3 courts/dist_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import genderforms  # noqa: E402 — дом, объявивший законы расстояния

ИМЯ_СУДА = "gender"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"gender"})


def _судить(строка):
    return genderforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"РОД В ЧУЖОМ ЯЗЫКЕ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(genderforms.РОДЫ)}, страниц {len(genderforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
