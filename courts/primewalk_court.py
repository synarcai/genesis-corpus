#!/usr/bin/env python3
"""[ОБХОД ПРОСТОТЫ] — обход, пересчитанный судом пробой за пробой.

Суд не пишет закона заново: он берёт его у дома (`primewalkforms`), где простые и составные
объявлены двумя таблицами, а наименьший делитель находится счётом. ВСЯКАЯ ПРОБА СВЕРЕНА
ДЕЛЕНИЕМ: «7 — нет» на странице числа 91 есть ложь, ибо 91 делится на 7 нацело.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ПРЕДМЕТ ОБХОДА ВЗЯТ ПО ЗАКОНУ ДОМА — это число, названное непосредственно перед первой
пробой, а не первое число строки: на странице «труд не равен» в голове стои́т СОСТАВНОЕ,
а обходят на ней ПРОСТОЕ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним
словом, суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/dist_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import primewalkforms  # noqa: E402 — дом, объявивший законы расстояния

ИМЯ_СУДА = "primewalk"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"primewalk"})


def _судить(строка):
    return primewalkforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ОБХОД ПРОСТОТЫ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(primewalkforms.РОДЫ)}, страниц {len(primewalkforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
