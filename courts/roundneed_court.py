#!/usr/bin/env python3
"""[СУД ОКРУГЛЕНИЯ ПО ДЕЛУ] — деление сделано заново, прочтение взято из рамки; МИР ЗАМКНУТ.

Страница мира (`tools/roundneed.py`) есть одно деление и одно из двух его прочтений. Суд НЕ
ЗНАЕТ РОДА страницы: он смотрит, КАКАЯ РАМКА совпала, и тем узнаёт, что́ на странице
обещано, — а потом делит сам.

    ОДНО ДЕЛЕНИЕ, ДВА ОТВЕТА, И РЕШАЕТ НЕ ЧИСЛО, А ДЕЛО. «Пассажиров 95, в автобус входит
    40: автобусов нужно 3»; «ткани 95, на платье идёт 40: платьев выйдет 2». То же 95 ÷ 40 =
    2 и остаток 15 — и ответы разные.

Сверх ответа суд держит границу:

    ОСТАТОК НУЛЬ СТИРАЕТ РАЗНИЦУ. Страница рода «вверх» или «вниз» на числах без остатка не
    учит ничему — оба ответа совпали, — и суд её не пропускает, иначе два рода стали бы
    одним молча. Род «обе_рядом» такие числа берёт НАРОЧНО и говорит вслух, что стороны
    сошлись: граница показана, а не умолчана.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import roundneed as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"roundneed"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    о = "март дал 120 колёс, апрель дал 95 колёс, май дал 140 колёс. "

    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО (14.09). Подсадка бывает
    # СУДИМА И ИСТИННА — тогда лгал сам список: строка похожа на ложь, а есть правда.
    # Бывает и НЕСУДИМА — тогда она выпала из рамки дома, и прибор, считающий её просто
    # «непойманной», молчит о том, что перестал её читать вовсе. Суд скобок так и потерял
    # четыре подсадки из семи, когда рамка вопроса переменилась.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_roundneed.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_roundneed.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_roundneed.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ОКРУГЛЕНИЕ ПО ДЕЛУ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
