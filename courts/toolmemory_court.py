def М(имя):
    return f"\x01{имя}\x01"


def _образец(текст):
    куски, счёт = [], {}
    for кусок in re.split(r"(\x01[^\x01]+\x01)", текст):
        if кусок.startswith("\x01"):
            имя = кусок[1:-1]
            счёт[имя] = счёт.get(имя, 0) + 1
            куски.append(f"(?P<h{len(куски)}_{счёт[имя]}_{_ЛАТ.get(имя, имя)}>{_КЛАСС[имя]})")
        else:
            куски.append(re.escape(кусок))
    return re.compile("^" + "".join(куски) + "$")


class _Метки:
    """Метки имён на время сборки рамок: у голосов, где имя склоняется, падеж метки — своя метка («Xп», «Yв»)."""

    def __init__(self, язык):
        self.язык = язык

    def __enter__(self):
        формы = П.ФОРМЫ_ИМЁН.setdefault(self.язык, {})
        for метка in ("X", "Y"):
            if self.язык in ("ru", "pl"):
                формы[М(метка)] = {падеж: М(метка + к) for падеж, к in _ПАДЕЖИ.items()}
        return self

    def __exit__(self, *_):
        for метка in ("X", "Y"):
            П.ФОРМЫ_ИМЁН.get(self.язык, {}).pop(М(метка), None)


