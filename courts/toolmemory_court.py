def _значения(м):
    """({дыра: значение}, согласна ли страница с собой): повторная дыра обязана нести одно значение."""
    вон, согласна = {}, True
    for ключ, знач in м.groupdict().items():
        имя = ключ.split("_", 2)[2]
        имя = _ИЗ_ЛАТ.get(имя, имя)
        if имя in вон and вон[имя] != знач:
            согласна = False
        вон.setdefault(имя, знач)
    return вон, согласна


