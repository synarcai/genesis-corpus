def _порчи(с, язык, род, дыры):
    """Подсадки от дома: ход другого человека под тем же вопросом; наблюдение итога — наблюдением другого человека; род —
    родом другого; связь наоборот; строка плана — не клетка чтения; последнее число итога плюс единица."""
    вон = []
    г = П.ГРАФ[язык]
    люди_ = П.люди(язык)
    орг = с.rfind(A._реплика(язык, "орг", ""))
    for i, (имя_, t, наблюдения) in enumerate(люди_):
        чужой_имя, чужой_t, чужие = люди_[(i + 1) % len(люди_)]
        for н in наблюдения:
            for ч in чужие:
                if н in с[орг:] and ч not in с:
                    вон.append(с[:орг] + с[орг:].replace(н, ч, 1))
                    break
        if f" {t}." in с[орг:] and t != чужой_t:
            вон.append(с[:орг] + с[орг:].replace(f" {t}.", f" {чужой_t}.", 1))
    связь = г["связь"]
    for a, b in П.СВЯЗИ:
        x, y = П.имя(язык, a), П.имя(язык, b)
        прямо = H.связь_(язык, x, связь, y)
        if прямо in с[орг:]:
            вон.append(с[:орг] + с[орг:].replace(прямо, H.связь_(язык, y, связь, x), 1))
    числа = [м for м in re.finditer(r"(?<![\w/.])\d+(?![\w/.])", с) if м.start() > орг]
    if числа:
        п = числа[-1]
        вон.append(с[:п.start()] + str(int(п.group()) + 1) + с[п.end():])
    if род == H.ПЛАН:
        ходы = [т[:-1] for роль, т in R.реплики(с, язык) if роль == "мир"]
        if len(ходы) >= 3:
            # вторая строка файла — перелицованная первая: строка не клетка чтения
            вторая = ходы[2].split('"')[1]
            первая = ходы[1].split('"')[1]
            вон.append(с.replace(f'"{вторая}"', f'"{первая}"', 1))
    # ход другого человека под тем же вопросом (сервер ответил не на тот акт)
    x = дыры.get("X")
    if x and род in (H.ЗНАЕШЬ, H.СВЯЗАН):
        другой = next(и for и, _t, _н in люди_ if и != x)
        kind = "open_nodes" if род == H.ЗНАЕШЬ else "search_nodes"
        свой_ход, чужой_ход = W.текст(П.ход(язык, kind, x)), W.текст(П.ход(язык, kind, другой))
        if свой_ход != чужой_ход:
            вон.append(с.replace(свой_ход, чужой_ход, 1))
    return [в for в in dict.fromkeys(вон) if в != с]


def _самопроверка():
    беды = [с for с in H.ПОКАЗЫ if _судить(с) != (True, True)]
    порч = пойманных = 0
    for с, (язык, род, _форма, _р) in sorted(H.ПОКАЗЫ.items()):
        for порча in _порчи(с, язык, род, H.ПЕРЕПИСЬ[с]):
            порч += 1
            вердикт = _судить(порча)
            if вердикт == (True, False):
                пойманных += 1
            elif вердикт == (True, True):
                беды.append(f"порча прошла: {порча[:220]}")
            else:
                беды.append(f"порча — молчание: {порча[:220]}")
        р = A.РЕЧЬ[язык]
        да = A._реплика(язык, "польз", р["да"] + ".") + " "
        нет = A._реплика(язык, "польз", р["нет"] + ".") + " "
        порчи = ([с.replace(да, "", 1), с.replace(да, нет, 1)] if да in с
                 else [с.replace(нет, да, 1)] if нет in с else [])
        for порча in порчи:
            порч += 1
            if _судить(порча) == (True, False):
                пойманных += 1
            else:
                беды.append(f"порча устройства не ложь: {порча[:220]}")
    return беды, порч, пойманных, len(H.ПОКАЗЫ)


