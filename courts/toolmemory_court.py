def _рамки_голоса(язык, x, y):
    """[(текст рамки, род, вид, число строк плана)] — сборки дома на именах x, y (метках или заглушках)."""
    ОТВЕТ, ЧТЕНИЕ, F = М("ОТВЕТ"), М("ЧТЕНИЕ"), М("F")
    T_, O, R_ = М("T"), М("O"), М("R")
    вон = [(H.сборка_знаешь(язык, x, М("МИР0"), ОТВЕТ), H.ЗНАЕШЬ, "знаешь", 0),
           (H.сборка_связан(язык, x, М("МИР0"), ОТВЕТ), H.СВЯЗАН, "связан", 0),
           (H.сборка_всё(язык, М("МИР0"), ОТВЕТ), H.ВСЁ, "всё", 0)]
    клаузы = {"нового": H.клауза(язык, "нового", X=x, T=T_, O=O), "факта": H.клауза(язык, "факта", X=x, O=O),
              "связи": H.клауза(язык, "связи", A=x, B=y, R=R_)}
    for вид, клауза_ in клаузы.items():
        вон += [(H.сборка_запомни(язык, H.ЗАПОМНИ_НОВОГО, клауза_, М("МИР0")), H.ЗАПОМНИ_НОВОГО, вид, 0),
                (H.сборка_запомни(язык, H.ЗАПОМНИ_ОТКАЗ, клауза_, М("МИР0"), ЧТЕНИЕ), H.ЗАПОМНИ_ОТКАЗ, вид, 0),
                (H.сборка_факт_незнакомому(язык, x, клауза_, М("МИР0")), H.ФАКТ_НЕЗНАКОМОМУ, вид, 0)]
    for вид, клауза_ in (("человека", None), ("факта", клаузы["факта"]), ("связи", клаузы["связи"])):
        вон += [(H.сборка_забудь(язык, H.ЗАБУДЬ, x, клауза_, М("МИР0")), H.ЗАБУДЬ, вид, 0),
                (H.сборка_забудь(язык, H.ЗАБУДЬ_ОТКАЗ, x, клауза_, М("МИР0"), ЧТЕНИЕ), H.ЗАБУДЬ_ОТКАЗ, вид, 0)]
    вон.append((H.сборка_забыть_нечего(язык, x, М("МИР0")), H.ЗАБЫТЬ_НЕЧЕГО, "человека", 0))
    # ПЛАН: чтение и его пересказ, затем k строк мира папки (k = 1…3); писать нечего; отказ «нет»
    for k in range(1, 4):
        строки_ = [(М(f"МИР{i}"), H.отчёт_строки(язык, М(f"S{i}"), F, М(f"N{i}"), М(f"L{i}"))) for i in range(1, k + 1)]
        вон.append((H.сборка_плана(язык, H.ПЛАН, x, F, М("МИР0"), ОТВЕТ + ".", строки_), H.ПЛАН, "план", k))
    вон.append((H.сборка_плана(язык, H.ПЛАН_НЕЧЕГО, x, F, М("МИР0"), ОТВЕТ + "."), H.ПЛАН_НЕЧЕГО, "план", 0))
    вон.append((H.сборка_плана(язык, H.ПЛАН_ОТКАЗ, x, F, М("МИР0"), None, чтение=ЧТЕНИЕ), H.ПЛАН_ОТКАЗ, "план", 0))
    return вон


def _рамки():
    """{язык: [(образец, род, вид, число строк плана)]} — рамки у сборок дома с метками вместо частей."""
    вон = {}
    for язык in H.ЯЗЫКИ:
        рамки = []
        р_ = A.РЕЧЬ[язык]
        да = A._реплика(язык, "польз", р_["да"] + ".") + " "
        нет = A._реплика(язык, "польз", р_["нет"] + ".") + " "

        def положить(текст, род, вид, k=0):
            рамки.append((_образец(текст), род, вид, k))
            if да in текст:
                рамки.append((_образец(текст.replace(да, "", 1)), СКРЕЩЕНО, вид, k))
                рамки.append((_образец(текст.replace(да, нет, 1)), СКРЕЩЕНО, вид, k))
            elif нет in текст:
                рамки.append((_образец(текст.replace(нет, да, 1)), СКРЕЩЕНО, вид, k))

        if язык == "fr":
            тексты = {}
            for x in _ЗАГЛУШКИ["X"]:
                for y in _ЗАГЛУШКИ["Y"]:
                    for текст, род, вид, k in _рамки_голоса(язык, x, y):
                        for заглушка in _ЗАГЛУШКИ["X"]:
                            текст = текст.replace(заглушка, М("X"))
                        for заглушка in _ЗАГЛУШКИ["Y"]:
                            текст = текст.replace(заглушка, М("Y"))
                        тексты.setdefault(текст, (род, вид, k))
            for текст, (род, вид, k) in тексты.items():
                положить(текст, род, вид, k)
        else:
            with _Метки(язык):
                for текст, род, вид, k in _рамки_голоса(язык, М("X"), М("Y")):
                    положить(текст, род, вид, k)
        вон[язык] = рамки
    return вон


