def _люди_голоса(язык):
    """Имена, какие мир памяти голоса знает или страница называет: люди графа, новые, незнакомый."""
    г = П.ГРАФ[язык]
    return frozenset([и for и, _р, _н in г["люди"]] + [и for и, _р, _н in г["новые"]] + [г["незнакомый"]])


def _имя(язык, зн, метка):
    """Имя дыры: прямо («X») или по падежу (у ru, pl — обратно двери форм); все формы обязаны сойтись на одном имени."""
    найдено = set()
    if метка in зн:
        найдено.add(зн[метка])
    for падеж, к in _ПАДЕЖИ.items():
        if метка + к in зн:
            найдено |= {и for и in _люди_голоса(язык) if П.форма(язык, и, падеж) == зн[метка + к]}
            if not найдено:
                return None
    return найдено.pop() if len(найдено) == 1 else None


def _свой(язык, зн):
    return all(_имя(язык, зн, м) in _люди_голоса(язык) for м in ("X", "Y")
               if м in зн or any(м + к in зн for к in _ПАДЕЖИ.values()))


def _ряды(ход_):
    """Своё чтение рядов хода: (род, наблюдения, связи) человека и связей — по полям ряда."""
    t, наблюдения, связи = None, [], []
    for ряд in ход_.строки:
        р = dict(ряд)
        if "name" in р:
            t = р.get("entityType")
            наблюдения += [р["observations"]] if "observations" in р else []
        elif "from" in р:
            связи.append((р["from"], р["relationType"], р["to"]))
    return t, наблюдения, связи


def _ответ_верен(язык, род, вид, x, ход_, ответ):
    """Ответ вопроса — то, что голос дома сказал бы о рядах хода, прочтённых судом."""
    t, наблюдения, связи = _ряды(ход_)
    не_помню = H._ф(язык, H._р(язык, "a_не_помню", **H.имена(язык, x))) + "."
    if род == H.ЗНАЕШЬ:
        return ответ == (H.знание(язык, x, t, наблюдения, связи)[:-1] if t is not None else не_помню[:-1])
    if род == H.СВЯЗАН:
        if t is None and not связи:
            return ответ == не_помню[:-1]
        if not связи:
            return ответ == H._ф(язык, H._р(язык, "a_никто", **H.имена(язык, x)))
        return ответ == ". ".join(H.связь_(язык, a, r, b) for a, r, b in связи)
    if род == H.ВСЁ:
        люди_ = list(dict.fromkeys(dict(р)["name"] for р in ход_.строки if "name" in dict(р)))
        return ответ == ". ".join([H.перечень_людей(язык, люди_)] + [H.связь_(язык, a, r, b) for a, r, b in связи])
    return False


def _акт_просьбы(язык, род, вид, зн, x):
    """(род мира, объект, доводы) правки, какую называет просьба по дырам."""
    if род in (H.ЗАБУДЬ, H.ЗАБУДЬ_ОТКАЗ):
        if вид == "человека":
            return "delete_entities", x, ()
        if вид == "факта":
            return "delete_observations", x, (зн["O"],)
        return "delete_relations", x, (_имя(язык, зн, "Y"), зн["R"])
    if вид == "нового":
        return "create_entities", x, (зн["T"], зн["O"])
    if вид == "факта":
        return "add_observations", x, (зн["O"],)
    return "create_relations", x, (_имя(язык, зн, "Y"), зн["R"])


def _правка_верна(род, вид, ход_, акт):
    """Мир записал ровно то, что сказала просьба: у записи — ряд с именем, родом, наблюдением, связью дословно; у
    удаления — успех; у провала — error 1."""
    меры = dict(ход_.меры)
    if род == H.ФАКТ_НЕЗНАКОМОМУ:
        return меры.get("error") == 1
    if меры.get("error") != 0 or len(ход_.строки) != 1:
        return False
    р = dict(ход_.строки[0])
    kind, x, доводы = акт
    if kind == "create_entities":
        return (р.get("name"), р.get("entityType"), р.get("observations")) == (x, *доводы)
    if kind == "add_observations":
        return (р.get("entityName"), р.get("addedObservations")) == (x, доводы[0])
    if kind == "create_relations":
        return (р.get("from"), р.get("to"), р.get("relationType")) == (x, *доводы)
    return р.get("success") == "true"


def _план_верен(язык, род, k, зн, x):
    мир_папки = R.папка(язык)
    if род == H.ПЛАН_ОТКАЗ:
        ход_ = мир_папки.lines(зн["F"])[1]
        n = ход_.мера("lines")
        return (W.текст(ход_) == зн["МИР0"]
                and зн["ЧТЕНИЕ"] == T.наблюдение(язык, R._строк_в(язык, зн["F"], T.строк_вин(язык, n)), R._л(n, 0)))
    ход1 = П.ход(язык, "open_nodes", x)
    if W.текст(ход1) != зн["МИР0"]:
        return False
    t, наблюдения, _связи = _ряды(ход1)
    if род == H.ПЛАН_НЕЧЕГО:
        нечего = H._ф(язык, H._р(язык, "нечего_писать", К=H.к_файлу(язык, зн["F"])))
        первое = (H.род_(язык, x, t) if t is not None else H._ф(язык, H._р(язык, "a_не_помню", **H.имена(язык, x))))
        return not наблюдения and зн["ОТВЕТ"] == первое + ". " + нечего
    # строки плана — клетки observations чтения дословно и по порядку; всякий line — ход мира папки после прежних строк
    if [зн.get(f"S{i}") for i in range(1, k + 1)] != наблюдения or зн["ОТВЕТ"] != H.наблюдения_(язык, x, наблюдения):
        return False
    for i, s in enumerate(наблюдения, 1):
        мир_папки, ход_ = мир_папки.line(зн["F"], s)
        n = ход_.мера("lines")
        if (W.текст(ход_) != зн[f"МИР{i}"] or зн[f"N{i}"] != T.строк_вин(язык, n) or зн[f"L{i}"] != R._л(n - 1, 1)):
            return False
    return True


def _вердикт(язык, род, вид, k, зн):
    x = _имя(язык, зн, "X") if род != H.ВСЁ else None
    if род in (H.ПЛАН, H.ПЛАН_НЕЧЕГО, H.ПЛАН_ОТКАЗ):
        return _план_верен(язык, род, k, зн, x)
    if род in (H.ЗНАЕШЬ, H.СВЯЗАН, H.ВСЁ):
        kind = {H.ЗНАЕШЬ: "open_nodes", H.СВЯЗАН: "search_nodes", H.ВСЁ: "read_graph"}[род]
        ход_ = П.ход(язык, kind, x or "")
        return W.текст(ход_) == зн["МИР0"] and _ответ_верен(язык, род, вид, x, ход_, зн["ОТВЕТ"])
    if род == H.ЗАБЫТЬ_НЕЧЕГО:
        ход_ = П.ход(язык, "open_nodes", x)
        return W.текст(ход_) == зн["МИР0"] and not ход_.строки
    if род in (H.ЗАПОМНИ_ОТКАЗ, H.ЗАБУДЬ_ОТКАЗ):
        # чтение «до»: что память держит о человеке сейчас, без правки
        ход_ = П.ход(язык, "open_nodes", x)
        t, наблюдения, связи = _ряды(ход_)
        return W.текст(ход_) == зн["МИР0"] and зн["ЧТЕНИЕ"] == H.знание(язык, x, t, наблюдения, связи)
    акт = _акт_просьбы(язык, род, вид, зн, x)
    ход_ = П.ход(язык, *акт)
    return W.текст(ход_) == зн["МИР0"] and _правка_верна(род, вид, ход_, акт)


def _судить(строка):
    с = строка.strip()
    if not с:
        return False, False
    язык = next((я for начало, я in _НАЧАЛО.items() if с.startswith(начало)), None)
    if язык is None:
        return False, False
    совпал = False
    for образ, род, вид, k in РАМКИ[язык]:
        м = образ.match(с)
        if not м:
            continue
        if род == СКРЕЩЕНО:
            совпал = True
            continue
        зн, согласна = _значения(м)
        if not _свой(язык, зн):
            continue
        совпал = True
        try:
            if согласна and _вердикт(язык, род, вид, k, зн):
                return True, True
        except (KeyError, ValueError, IndexError, TypeError):
            continue
    return (True, False) if совпал else (False, False)


