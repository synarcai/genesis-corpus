#!/usr/bin/env python3
"""[ЕДИНИЦЫ] — одна единица, названная в другой, ПЕРЕСЧИТЫВАЕТСЯ.

    1 metre = 1000 millimetres.
    5 километров равно 5000 метров.
    one week equals 7 days.

ЭТО НЕ АРИФМЕТИКА, И АРИФМЕТИЧЕСКИЙ СУД ПРАВИЛЬНО СТОИТ В СТОРОНЕ:
числа по обе стороны равны лишь ВМЕСТЕ С ЕДИНИЦАМИ, и суд, читающий
одни числа, объявил бы ложью триста семьдесят пять честных переводов
(шрам уже оплачен). Здесь у рода свой суд: отношение берётся из
ОБЪЯВЛЕННОГО графа `tools/units.py` и перемножается по пути.

ЧИСЛА СЛОВОМ читаются из пакетов языков — того же дома, откуда их
берёт арифметический суд. Второй список числительных разошёлся бы с
первым в день, когда тронут любой.

ПАРА ЕДИНИЦ БЕЗ ОБЪЯВЛЕННОГО ПУТИ НЕ ЕСТЬ ЛОЖЬ. «5 apples = 5 apples»
и «3 newtons = 3 newtons» суду неподсудны: он владеет отношениями, а
не всяким равенством с существительными. Такие пары считаются отдельно
и печатаются числом — пробел в объявлении должен быть виден, а не выдан
за находку.
"""
import pathlib
import re
import sys
from fractions import Fraction

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import asking  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402
from gsm_items import ITEMS  # noqa: E402
from plural import singular  # noqa: E402
from units import единица, отношение  # noqa: E402
import units  # noqa: E402
import arith_court  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# СВЯЗКА НАЗВАНА, А НЕ УГАДАНА: «=», «равно», «equals», «equal».
ПЕРЕВОД = re.compile(
    r"^([\w]+)\s+([^\W\d_]+)\s+(?:=|равно|равен|равна|equals|equal)\s+"
    r"([\w]+)\s+([^\W\d_]+)(?:: (\d+) × (\d+) = (\d+))?\s*[.。]?$"
)

# ЕДИНИЦА, НАЗВАННАЯ МЕРОЙ, ЕСТЬ УТВЕРЖДЕНИЕ О РОДЕ, И ОНО ПРОВЕРЯЕМО
# ТЕМ ЖЕ ДОМОМ: «год — это мера» истинно, ибо год объявлен единицей;
# «яблоко — это мера» было бы ложью того же рода, что «the teacher is a
# thing». ВОПРОС О ЕДИНИЦЕ судится так же: спросить можно о том, что
# объявлено, — вопрос о невыдуманном есть его собственное ручательство.
РОД_ЕДИНИЦЫ = re.compile(
    r"^(?:the ([^\W\d_]+) is an? (unit|measure)"
    r"|([^\W\d_]+) — это (мера|единица))\.$")
# ОТКАЗ ЕСТЬ ТАКОЕ ЖЕ УТВЕРЖДЕНИЕ: «ответа нет» истинно ровно тогда,
# когда отношения между единицами и вправду НЕТ в объявленном графе.
# Суд проходит граф сам, а не верит слову «нет».
ОТКАЗ_РОДА = re.compile(
    r"^(?:no answer: \d+ [^\W\d_]+, and a ([^\W\d_]+) and a "
    r"([^\W\d_]+) measure different kinds"
    r"|ответа нет: \d+ [^\W\d_]+, а ([^\W\d_]+) и ([^\W\d_]+) — "
    r"меры разных родов)\.$")
ВОПРОС = re.compile(
    r"^(?:what is an? ([^\W\d_]+)\?|что такое ([^\W\d_]+)\?)$")

# ВЕЩЬ, НАЗВАННАЯ МЕРОЙ, ЕСТЬ ЛОЖЬ, А НЕ НЕИЗВЕСТНОСТЬ. Без этого суд
# лишь принимал истинное и молчал о ложном — а молчание о ложном есть
# та же слепота, только вежливая. Список вещей объявлен переписью, и
# слово, стоящее в нём и не стоящее среди единиц, мерой не является.
ВЕЩИ = set(ITEMS) | {singular(w) for w in ITEMS}

# ПОСТОЯННАЯ, ОТКРЫВАЮЩАЯ СТРАНИЦУ (23.09): «в часе 60 минут. 2 часа равно 120 минут: 2 × 60 = 120.»
# Фраза постоянной — у одной двери (`unitforms.сказать_отношение`); суд сверяет её с тем, что
# сказала бы дверь по графу единиц, и требует, чтобы это была постоянная ПЕРЕВОДА СТРАНИЦЫ.
#
#     ФРАЗА ПОСТОЯННОЙ С ЧУЖИМ ЧИСЛОМ ЕСТЬ ЛОЖЬ, А НЕ ЧУЖАЯ СТРОКА: «an hour has 50 minutes»
#     утверждает отношение единиц, и суд единиц за него отвечает.
#
# Форма фразы узнаётся ТОЛЬКО при двух единицах графа: «в классе 25 учеников» — не постоянная
# и суду единиц неподсудна.
import unitforms  # noqa: E402
# СКАЗАННОЕ БЕРЁТСЯ ПО ВСЕМ ПАРАМ, КАКИЕ ДВЕРЬ УМЕЕТ СКАЗАТЬ, А НЕ ПО РЁБРАМ ГРАФА (23.09): ребро
# соединяет единицу с основой («metre → centimetre»), а дверь говорит и выведенное отношение — «в
# сантиметре 10 миллиметров», «в дециметре 10 сантиметров». Суд, знавший одни рёбра, звал такую
# честную фразу ЛОЖЬЮ (104 страницы дома квадратных единиц у ворот).
_ЕДИНИЦЫ_ГРАФА = sorted({_е for _ребро in units.РЁБРА for _е in _ребро})
_ПАРЫ_СКАЗА = []
for _а in _ЕДИНИЦЫ_ГРАФА:
    for _б in _ЕДИНИЦЫ_ГРАФА:
        _к = units.отношение(_а, _б) if _а != _б else None
        if _к is not None and _к.denominator == 1 and _к > 1:
            _ПАРЫ_СКАЗА.append((_а, _б))
_СКАЗАННЫЕ = {}
for _язык, _письма in (("ru", ("amer",)), ("en", ("amer", "brit"))):
    for _письмо in _письма:
        for (_а, _б) in _ПАРЫ_СКАЗА:
            try:
                _СКАЗАННЫЕ[unitforms.сказать_отношение(_язык, _а, _б, письмо=_письмо)] = (_а, _б)
            except (KeyError, AssertionError, TypeError):
                pass
_БОЛЬШАЯ_РУ = {в: и for и, в in units.ПРЕДЛОЖНЫЙ_ЕД.items()}
_ФОРМА_СКАЗА = re.compile(r"^(?:an? ([^\W\d_]+) has (\d+) ([^\W\d_]+)|в ([^\W\d_]+) (\d+) ([^\W\d_]+))\. ")
_ЗВЕНО = re.compile(r"([^\W\d_]+)\s+(?:=|равно|равен|равна|equals|equal)\s+\w+\s+([^\W\d_]+): \d+ × (\d+) = \d+")


def _постоянная(с):
    """None — строка не открыта фразой постоянной; иначе (пара или None, остаток строки)."""
    м = _ФОРМА_СКАЗА.match(с)
    if not м:
        return None
    б_слово, м_слово = (м.group(1), м.group(3)) if м.group(1) else (м.group(4), м.group(6))
    большая = единица(б_слово) if м.group(1) else _БОЛЬШАЯ_РУ.get(б_слово)
    # БОЛЬШАЯ ЕДИНИЦА ФРАЗЫ ДВЕРИ СТОИ́Т В ПРЕДЛОЖНОМ (24.09, прибор [ПОДСАДКА СЛОВОМ]): «в килограмм
    # 1000 граммов», «в дюжин 12 штук» — форма той же единицы в чужом падеже — не узнавались фразой
    # вовсе, и страница судилась одним переводом, то есть как истина. Единица графа на этом месте в
    # любой форме, кроме предложной, есть порча фразы двери, а не чужая строка.
    if большая is None and not м.group(1) and единица(б_слово) is not None \
            and единица(м_слово) is not None:
        return None, с[м.end():]
    if большая is None or единица(м_слово) is None:
        return None
    return _СКАЗАННЫЕ.get(м.group(0)[:-2]), с[м.end():]


_ЧИСЛА = None


def числа():
    """слово → величина, из пакетов языков (один дом с арифметикой)."""
    global _ЧИСЛА
    if _ЧИСЛА is None:
        _ЧИСЛА = arith_court.словари()[0]
    return _ЧИСЛА


def величина(слово):
    """Число цифрами или словом, или None."""
    if слово.isdigit() and слово.isascii():
        return Fraction(int(слово))
    в = числа().get(слово.lower())
    return Fraction(в) if в is not None else None


def _форма_единицы(слово, имя, n):
    """Is `слово` the form the house of units writes beside n for `имя`?"""
    # THE ABBREVIATION IS A FORM OF THE UNIT (tools/units.py: «2 м = 200 см»)
    if units.СОКРАЩЕНИЯ.get(слово) == имя:
        return True
    if re.search(r"[а-яё]", слово):
        try:
            return слово == units.рус(имя, n)
        except (KeyError, IndexError):
            return True
    формы = set()
    for письмо in ("brit", "amer"):
        try:
            формы.add(units.англ(имя, n != 1, письмо=письмо))
        except (KeyError, IndexError):
            pass
    return not формы or слово in формы


def судить(строка):
    """(судимо, истинно) для одной строки."""
    сказ = _постоянная(строка.strip())
    if сказ is not None:
        пара, остаток = сказ
        if пара is None:
            return True, False
        судимо, верно = судить(остаток)
        if not судимо:
            return False, True
        # постоянная обязана быть постоянной ПЕРЕВОДА СТРАНИЦЫ: единицы и число звена — её
        звенья = _ЗВЕНО.findall(остаток)
        своя = bool(звенья) and all((единица(а), единица(б)) == пара and
                                    Fraction(int(к)) == отношение(*пара) for а, б, к in звенья)
        return True, верно and своя
    return _судить_без_постоянной(строка)


def _судить_без_постоянной(строка):
    """(судимо, истинно) для строки, не открытой фразой постоянной."""
    # ВОПРОС СУДИТСЯ СВОИМ ОТВЕТОМ, А РОД ОПРЕДЕЛЯЕТСЯ ОТВЕТОМ.
    # Связь половин держит общий дом `tools/asking.py`: величины
    # вопроса суть начальный отрезок величин ответа, и порча любой из
    # них рвёт пару. Без этого суд читал бы вторую половину строки и
    # звал истиной вопрос, спрашивающий о другом.
    если = asking.судить_парой(строка, судить)
    if если is not None:
        return если
    с = строка.strip()
    m = ОТКАЗ_РОДА.match(с)
    if m:
        слева, справа = [г for г in m.groups() if г]
        a, b = единица(слева), единица(справа)
        if a is None or b is None:
            return False, True
        return True, отношение(a, b) is None
    m = РОД_ЕДИНИЦЫ.match(с)
    if m:
        слово = next(г for г in m.groups() if г)
        if единица(слово):
            return True, True
        if слово in ВЕЩИ or singular(слово) in ВЕЩИ:
            return True, False
        return False, True
    m = ВОПРОС.match(с)
    if m:
        # ВОПРОС НЕ УТВЕРЖДАЕТ РОДА. «what is a pack?» спрашивает о
        # вместилище, а не объявляет его мерой, и суд, читавший вопрос
        # как утверждение, назвал ложью пятнадцать честных строк.
        # Опровержимое в вопросе одно: СУЩЕСТВУЕТ ЛИ СПРОШЕННОЕ —
        # спрашивать о том, чего корпус не объявлял, значит выдумывать.
        слово = next(г for г in m.groups() if г)
        известно = bool(единица(слово)) or слово in ВЕЩИ \
            or singular(слово) in ВЕЩИ
        return (True, True) if известно else (False, True)
    m = ПЕРЕВОД.match(строка.strip())
    if not m:
        return False, True
    чс, чо, чт, чч, з1, з2, з3 = m.groups()
    сколько_слева, сколько_справа = величина(чс), величина(чт)
    если_слева, если_справа = единица(чо), единица(чч)
    if None in (сколько_слева, сколько_справа, если_слева, если_справа):
        # СО ЗВЕНОМ «k × f = k·f» строка говорит о единицах, и неизвестное
        # слово единицы — ложь, не молчание (подсадка «5 мину равно 300
        # секунд: 5 × 60 = 300.» проходила судом арифметики, 04.09).
        if з1 is not None and None not in (сколько_слева, сколько_справа):
            return True, False
        # BOTH UNITS KNOWN, A COUNT UNREADABLE («оди метр равно 100 сантиметров»,
        # mutation 04.09): the sentence claims a conversion with a number that
        # is no number — a lie, not silence.
        if None not in (если_слева, если_справа) and отношение(если_слева, если_справа) is not None:
            return True, False
        return False, True
    ставка = отношение(если_слева, если_справа)
    if ставка is None:
        return False, True
    # THE COUNT FORM OF THE UNIT IS PART OF THE CLAIM (mutation 04.09: «12
    # kilogram equal 12000 grams» passed — the unit was resolved by any of
    # its forms): beside n the English unit stands in its plural unless n = 1,
    # in either spelling; the Russian one in the form of the house of units.
    if not (_форма_единицы(чо, если_слева, сколько_слева) and _форма_единицы(чч, если_справа, сколько_справа)):
        return True, False
    верно = сколько_слева * ставка == сколько_справа
    if з1 is not None:
        # ЗВЕНО «k × f = k·f» сверяется: множители — величина и отношение единиц.
        верно = верно and (int(з1), int(з2), int(з3)) == (сколько_слева, ставка, сколько_справа)
    return True, верно


def незнакомые(пути):
    """Пары единиц, у которых нет объявленного пути, — счёт и образцы."""
    пары = {}
    for путь in пути:
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                m = ПЕРЕВОД.match(строка.strip())
                if not m:
                    continue
                # ОБРАЗЕЦ НЕСЁТ И ЗВЕНО (03.09): единицы — вторая и четвёртая группы.
                чо, чч = m.group(2), m.group(4)
                а, б = единица(чо), единица(чч)
                if а and б and отношение(а, б) is None:
                    пары[(а, б)] = строка.strip()[:60]
    return пары


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ЕДИНИЦЫ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ЕДИНИЦЫ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(
                            f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    без_пути = незнакомые(пути)
    хвост = ""
    if без_пути:
        имена = sorted(f"{а}/{б}" for а, б in без_пути)[:3]
        хвост = f", ПАР БЕЗ ПУТИ {len(без_пути)}: {имена}"
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ЕДИНИЦЫ {поза}: {ложных} ложных переводов из {судимых} "
          f"судимых ({len(пути)} файлов){хвост}")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
