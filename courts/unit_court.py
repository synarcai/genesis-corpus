#!/usr/bin/env python3
"""[ЕДИНИЦЫ] — одна единица, названная в другой, ПЕРЕСЧИТЫВАЕТСЯ.

    1 metre = 1000 millimetres.
    5 километров равно 5000 метров.
    one week equals 7 days.

ЭТО НЕ АРИФМЕТИКА, И АРИФМЕТИЧЕСКИЙ СУД ПРАВИЛЬНО СТОИТ В СТОРОНЕ:
числа по обе стороны равны лишь ВМЕСТЕ С ЕДИНИЦАМИ, и суд, читающий
одни числа, объявил бы ложью триста семьдесят пять честных переводов
(шрам уже оплачен). Здесь у рода свой суд: отношение берётся из
ОБЪЯВЛЕННОГО графа `tools/units.py` и перемножается по пути.

ЧИСЛА СЛОВОМ читаются из пакетов языков — того же дома, откуда их
берёт арифметический суд. Второй список числительных разошёлся бы с
первым в день, когда тронут любой.

ПАРА ЕДИНИЦ БЕЗ ОБЪЯВЛЕННОГО ПУТИ НЕ ЕСТЬ ЛОЖЬ. «5 apples = 5 apples»
и «3 newtons = 3 newtons» суду неподсудны: он владеет отношениями, а
не всяким равенством с существительными. Такие пары считаются отдельно
и печатаются числом — пробел в объявлении должен быть виден, а не выдан
за находку.
"""
import pathlib
import re
import sys
from fractions import Fraction

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import asking  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402
from gsm_items import ITEMS  # noqa: E402
from plural import singular  # noqa: E402
from units import единица, отношение  # noqa: E402
import arith_court  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# СВЯЗКА НАЗВАНА, А НЕ УГАДАНА: «=», «равно», «equals», «equal».
ПЕРЕВОД = re.compile(
    r"^([\w]+)\s+([^\W\d_]+)\s+(?:=|равно|равен|равна|equals|equal)\s+"
    r"([\w]+)\s+([^\W\d_]+)\s*[.。]?$"
)

# ЕДИНИЦА, НАЗВАННАЯ МЕРОЙ, ЕСТЬ УТВЕРЖДЕНИЕ О РОДЕ, И ОНО ПРОВЕРЯЕМО
# ТЕМ ЖЕ ДОМОМ: «год — это мера» истинно, ибо год объявлен единицей;
# «яблоко — это мера» было бы ложью того же рода, что «the teacher is a
# thing». ВОПРОС О ЕДИНИЦЕ судится так же: спросить можно о том, что
# объявлено, — вопрос о невыдуманном есть его собственное ручательство.
РОД_ЕДИНИЦЫ = re.compile(
    r"^(?:the ([^\W\d_]+) is an? (unit|measure)"
    r"|([^\W\d_]+) — это (мера|единица))\.$")
# ОТКАЗ ЕСТЬ ТАКОЕ ЖЕ УТВЕРЖДЕНИЕ: «ответа нет» истинно ровно тогда,
# когда отношения между единицами и вправду НЕТ в объявленном графе.
# Суд проходит граф сам, а не верит слову «нет».
ОТКАЗ_РОДА = re.compile(
    r"^(?:no answer: \d+ [^\W\d_]+, and a ([^\W\d_]+) and a "
    r"([^\W\d_]+) measure different kinds"
    r"|ответа нет: \d+ [^\W\d_]+, а ([^\W\d_]+) и ([^\W\d_]+) — "
    r"меры разных родов)\.$")
ВОПРОС = re.compile(
    r"^(?:what is an? ([^\W\d_]+)\?|что такое ([^\W\d_]+)\?)$")

# ВЕЩЬ, НАЗВАННАЯ МЕРОЙ, ЕСТЬ ЛОЖЬ, А НЕ НЕИЗВЕСТНОСТЬ. Без этого суд
# лишь принимал истинное и молчал о ложном — а молчание о ложном есть
# та же слепота, только вежливая. Список вещей объявлен переписью, и
# слово, стоящее в нём и не стоящее среди единиц, мерой не является.
ВЕЩИ = set(ITEMS) | {singular(w) for w in ITEMS}

_ЧИСЛА = None


def числа():
    """слово → величина, из пакетов языков (один дом с арифметикой)."""
    global _ЧИСЛА
    if _ЧИСЛА is None:
        _ЧИСЛА = arith_court.словари()[0]
    return _ЧИСЛА


def величина(слово):
    """Число цифрами или словом, или None."""
    if слово.isdigit() and слово.isascii():
        return Fraction(int(слово))
    в = числа().get(слово.lower())
    return Fraction(в) if в is not None else None


def судить(строка):
    """(судимо, истинно) для одной строки."""
    # ВОПРОС СУДИТСЯ СВОИМ ОТВЕТОМ, А РОД ОПРЕДЕЛЯЕТСЯ ОТВЕТОМ.
    # Связь половин держит общий дом `tools/asking.py`: величины
    # вопроса суть начальный отрезок величин ответа, и порча любой из
    # них рвёт пару. Без этого суд читал бы вторую половину строки и
    # звал истиной вопрос, спрашивающий о другом.
    если = asking.судить_парой(строка, судить)
    if если is not None:
        return если
    с = строка.strip()
    m = ОТКАЗ_РОДА.match(с)
    if m:
        слева, справа = [г for г in m.groups() if г]
        a, b = единица(слева), единица(справа)
        if a is None or b is None:
            return False, True
        return True, отношение(a, b) is None
    m = РОД_ЕДИНИЦЫ.match(с)
    if m:
        слово = next(г for г in m.groups() if г)
        if единица(слово):
            return True, True
        if слово in ВЕЩИ or singular(слово) in ВЕЩИ:
            return True, False
        return False, True
    m = ВОПРОС.match(с)
    if m:
        # ВОПРОС НЕ УТВЕРЖДАЕТ РОДА. «what is a pack?» спрашивает о
        # вместилище, а не объявляет его мерой, и суд, читавший вопрос
        # как утверждение, назвал ложью пятнадцать честных строк.
        # Опровержимое в вопросе одно: СУЩЕСТВУЕТ ЛИ СПРОШЕННОЕ —
        # спрашивать о том, чего корпус не объявлял, значит выдумывать.
        слово = next(г for г in m.groups() if г)
        известно = bool(единица(слово)) or слово in ВЕЩИ \
            or singular(слово) in ВЕЩИ
        return (True, True) if известно else (False, True)
    m = ПЕРЕВОД.match(строка.strip())
    if not m:
        return False, True
    чс, чо, чт, чч = m.groups()
    сколько_слева, сколько_справа = величина(чс), величина(чт)
    если_слева, если_справа = единица(чо), единица(чч)
    if None in (сколько_слева, сколько_справа, если_слева, если_справа):
        return False, True
    ставка = отношение(если_слева, если_справа)
    if ставка is None:
        return False, True
    return True, сколько_слева * ставка == сколько_справа


def незнакомые(пути):
    """Пары единиц, у которых нет объявленного пути, — счёт и образцы."""
    пары = {}
    for путь in пути:
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                m = ПЕРЕВОД.match(строка.strip())
                if not m:
                    continue
                _, чо, _, чч = m.groups()
                а, б = единица(чо), единица(чч)
                if а and б and отношение(а, б) is None:
                    пары[(а, б)] = строка.strip()[:60]
    return пары


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ЕДИНИЦЫ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ЕДИНИЦЫ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(
                            f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    без_пути = незнакомые(пути)
    хвост = ""
    if без_пути:
        имена = sorted(f"{а}/{б}" for а, б in без_пути)[:3]
        хвост = f", ПАР БЕЗ ПУТИ {len(без_пути)}: {имена}"
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ЕДИНИЦЫ {поза}: {ложных} ложных переводов из {судимых} "
          f"судимых ({len(пути)} файлов){хвост}")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
