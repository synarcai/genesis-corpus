#!/usr/bin/env python3
"""[АРТИКЛЬ] — английское «a/an» судится ЗВУКОМ слова, перед которым стоит.

    АРТИКЛЬ, ВЫНЕСЕННЫЙ В РАМКУ, ПЕРЕСТАЁТ СЛЫШАТЬ СЛОВО, ПЕРЕД КОТОРЫМ СТОИТ.

ПОВОД. Сто шесть строк семи миров писали «a apple», «a egg», «a hour», «a insect», «a eye»,
«a axe», «a onion», «a orange»: дома ставили артикль ЛИТЕРАЛОМ перед дырой имени. Страницы
вылечены, и тогда открылась вторая половина: СЕМЬ ДОМОВ НЕ ВИДЯТ ПОДМЕНЫ — их образцы держат
артикль дырой (иначе не покрыли бы обеих форм), а вердикт о нём не спрашивает.

    ЗАКОН, ВЕРНЫЙ ДЛЯ ВСЕГО КОРПУСА, ДЕШЕВЛЕ ОДНИМ СУДОМ, ЧЕМ СЕМЬЮ ПРОВЕРКАМИ В СЕМИ ДОМАХ:
    дом, написанный завтра, получит его даром, а семь проверок пришлось бы писать восьмой раз.

ЧТО СУДИТСЯ И ЧТО НЕТ — ГРАНИЦА ОБЪЯВЛЕНА ТРИЖДЫ, И КАЖДЫЙ РАЗ КУПЛЕНА ОШИБКОЙ МЕРЫ:

  · СТРОКА СУДИТСЯ, ЛИШЬ ЕСЛИ ОНА АНГЛИЙСКАЯ ПО ЗНАКУ ЯЗЫКА. Испанское «es igual a ocho» и
    французское «il y a des fichiers» несут «a», и мера, не спросившая о языке, дала 2884
    обвинения при 106 честных.
  · СУДИТСЯ ЛИШЬ ИМЯ, ОБЪЯВЛЕННОЕ ПАКЕТОМ. «the sum of a and 17» несёт ПЕРЕМЕННУЮ «a», а не
    артикль; «an mdx» верно, ибо буква зовётся по имени.
  · ЗВУК ОБЪЯВЛЕН ПОИМЁННО, А НЕ ВЫВЕДЕН: «a unit» и «an hour» — обе стороны в списках дома
    английского языка (`plural.СОГЛАСНЫЙ_ЗВУК`, `plural.ГЛАСНЫЙ_ЗВУК`), и «u» из гласных букв
    выведено вовсе, ибо звучит надвое («a user», но «an ultimate»).

    МЕРА, СУДЯЩАЯ СЛОВО, КОТОРОГО ЯЗЫК ЕЙ НЕ ОБЪЯВЛЯЛ, МЕРЯЕТ СВОЮ ДОГАДКУ.

    python3 courts/article_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import langsign  # noqa: E402 — знак языка: чья это строка
import plural  # noqa: E402 — дом английского языка, объявивший звук

ИМЯ_СУДА = "article"
ПАРА = re.compile(r"\b(an?) ([a-z]+)\b")
# ЧИСЛО ЭТОМУ СУДУ СВОБОДНО ЦЕЛИКОМ, и это объявлено ПРИБОРУ МУТАНТОВ, а не умолчано.
# Предмет суда есть ЗВУК СЛЕДУЮЩЕГО СЛОВА; цифр в паре «артикль — имя» не бывает по
# самому образцу. Подсадка «50 cents» → «51 cents» артикля не касается, и вердикт
# «истина» о ней честен: её ловит арифметика, чей это предмет. Суд, промолчавший о
# том, чего он не читает, выглядит слепым — а он лишь НЕ О ТОМ.
СВОБОДНОЕ_ЧИСЛО = (re.compile(r"\d+"),)


def _объявленные():
    """Имена, объявленные английским пакетом; форма и множественное — обе судимы."""
    путь = КОРЕНЬ / "tools" / "langpacks" / "en.json"
    try:
        пакет = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return frozenset()
    вон = set()
    for имя, кл in (пакет.get("morph_classes") or {}).items():
        if not имя.startswith("noun"):
            continue
        for формы in (кл.get("lexemes") or {}).values():
            вон.update(str(ф).lower() for ф in формы if str(ф).isalpha())
    return frozenset(вон)


ОБЪЯВЛЕННЫЕ = _объявленные()


def _английская(строка):
    вон = langsign.счёт(строка)
    if not вон:
        return False
    лучший = max(вон, key=lambda я: вон[я])
    return лучший == "en" and вон[лучший] > 0


def судить(строка, *_):
    """(судимо, истинно): артикль перед ОБЪЯВЛЕННЫМ именем английской строки."""
    с = строка.strip()
    низ = с.lower()
    пары = [(а, w) for а, w in ПАРА.findall(низ) if w in ОБЪЯВЛЕННЫЕ]
    if not пары or not _английская(с):
        return False, True
    return True, all(а == plural.article(w) for а, w in пары)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.name}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"АРТИКЛЬ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"имён объявлено {len(ОБЪЯВЛЕННЫЕ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
