#!/usr/bin/env python3
"""[СЛИЯНИЕ ПРЕДЛОГА С АРТИКЛЕМ] — согласие страницы с объявленными таблицами четырёх языков.

Суд не знает ни одного из четырёх языков. Он берёт цитаты в «ёлочках» и спрашивает у дома
три вещи, объявленные там таблицами: не написана ли ВРОЗЬ пара, которая сливается
обязательно; не выдумана ли слитая форма, которой нет ни в одном языке; и стои́т ли ЗВЁЗДОЧКА
ровно при нарушении — ни раньше, ни позже.

    ОДНА И ТА ЖЕ ПАРА СЛОВ ЗАКОННА В ОДНОМ ЯЗЫКЕ И НЕВОЗМОЖНА В ДРУГОМ; СУД, ЧИТАЮЩИЙ
    ТАБЛИЦУ БЕЗ ЯЗЫКА, СУДИТ НЕ ЯЗЫК, А СОВПАДЕНИЕ БУКВ.

Оттого дом показывает соседей теми парами, что в итальянскую таблицу не попадают, — и это
граница СУДА, названная вслух, а не умолчание.

    python3 courts/fuseprep_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import fuseprepforms  # noqa: E402 — дом, показывающий закон слияния

ИМЯ_СУДА = "fuseprep"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"fuseprep"})


def _судить(строка):
    return fuseprepforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"СЛИЯНИЕ ПРЕДЛОГА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(fuseprepforms.РОДЫ)}, "
          f"страниц {len(fuseprepforms.ПОКАЗЫ)}, "
          f"слияний объявлено {len(fuseprepforms._СЛИЯНИЯ)}, "
          f"немецких {len(fuseprepforms._НЕМЕЦКИЕ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
