#!/usr/bin/env python3
"""[ПРОЦЕНТНАЯ РАЗНИЦА] — несимметричность сравнения процентом, пересчитанная судом.

Суд не пишет закона заново: он берёт его у дома (`pctdiffforms`), где рамки и числа объявлены одной
таблицей. Подмена процента, излишка и самой ЛОВУШКИ ловится машинально: оба процента
считаются заново, и каждый — от своего основания.
ЛОВУШКА ПРОВЕРЯЕТСЯ КАК ЛОВУШКА: на странице «не на столько-то, а на столько-то» отвергнутый
процент обязан РАЗОЙТИСЬ с верным, и верный обязан быть тем самым частным, что стои́т в конце
строки. Страница, где они совпали, отрицает ровно то, что утверждает.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ПАРЫ ВЗЯТЫ ТЕ, ГДЕ ОБА ПРОЦЕНТА ЦЕЛЫЕ И НЕ ВЫШЕ СТА: дробный процент увёл бы дом к десятичной
записи, а рост свыше сотни — к кратности, о которой говорит сосед («во сколько раз», 268 строк).
ГРАНИЦА ДОМА ЕСТЬ ГРАНИЦА ЕГО ПРЕДМЕТА, А НЕ УДОБСТВО СЧЁТА.

ЭТОТ ДОМ ЧИТАЕТСЯ И СУДОМ АРИФМЕТИКИ: его страницы написаны так, что слова стоя́т до двоеточия, а
равенства после, — и потому каждая проверена ДВАЖДЫ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/pctdiff_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import pctdiffforms  # noqa: E402 — дом, объявивший процентную разницу

ИМЯ_СУДА = "pctdiff"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"pctdiff"})


def _судить(строка):
    return pctdiffforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ПРОЦЕНТНАЯ РАЗНИЦА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(pctdiffforms.РОДЫ)}, страниц {len(pctdiffforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
