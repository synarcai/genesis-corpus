#!/usr/bin/env python3
"""[СУД МНОГОШАГОВОГО СЧЁТА] — выражение посчитано заново И КАЖДЫЙ ШАГ ПРОВЕРЕН; МИР ЗАМКНУТ.

Страница мира (`tools/nestcalc.py`) есть выражение со скобками, названные ШАГИ и ответ. Суд
не знает очертания, каким дом его строил: он разбирает ЗАПИСЬ спуском по старшинству
(«×» прежде «+» и «−», скобка прежде всего) и считает сам.

    ИТОГ НЕ ЕСТЬ ПУТЬ, И СУД ПРОВЕРЯЕТ ОБА. Строка «((3 + 5) × 2) − 7 = 9» истинна и не
    учит ничему: из неё не видно, что считалось первым. Потому суд требует от каждого шага
    четырёх вещей — счёт верен, оба слагаемых взяты ЛИБО из чисел выражения, ЛИБО из итогов
    прежних шагов, число шагов равно числу знаков, а последний итог равен ответу. Шаг,
    взявший число ниоткуда, есть ложь, даже когда ответ сошёлся.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import nestcalc as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"nestcalc"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds

    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО (14.09). Подсадка бывает
    # СУДИМА И ИСТИННА — тогда лгал сам список: строка похожа на ложь, а есть правда.
    # Бывает и НЕСУДИМА — тогда она выпала из рамки дома, и прибор, считающий её просто
    # «непойманной», молчит о том, что перестал её читать вовсе. Суд скобок так и потерял
    # четыре подсадки из семи, когда рамка вопроса переменилась.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_nestcalc.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_nestcalc.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_nestcalc.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"МНОГОШАГОВЫЙ СЧЁТ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
