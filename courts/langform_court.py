# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ДЫРА = re.compile(r"\{([^}]*)\}")

# ЧИСЛОВЫЕ ДЫРЫ ДВИЖКА, ЗЕРКАЛО ЕГО `ctx`. Показ, где число стоит само
# по себе, говорит о счёте, а не о форме; здесь оно нужно двояко — как
# алиби чужому шаблону и как ДОВОД правила согласования по счёту.
ЧИСЛА = ("n", "m", "sum", "prod")

# УМОЛЧАНИЕ МАРКЕРА ЗЕРКАЛИТ ДВИЖОК, А НЕ ВЫДУМАНО ЗДЕСЬ: пласт пишет
# `gen_refusal_kind`, и он берёт `kind.get("marker", "¬ ")`.
МАРКЕР_ПО_УМОЛЧАНИЮ = "¬ "


def _альт(строки):
    """Чередование объявленного, длинное первым.

    ДЛИННОЕ ПЕРЕЧИСЛЯЕТСЯ ПЕРВЫМ: чередование берёт первое совпавшее, и
    короткая форма, стоящая началом длинной, отрезала бы у показа хвост.
    """
    строки = sorted({с for с in строки if с}, key=len, reverse=True)
    if not строки:
        return None
    return "(?:" + "|".join(re.escape(с) for с in строки) + ")"


def таблицы(пакет):
    """{(класс, клетка): {форма: {лексемы}}} — объявленные таблицы.

    КЛЕТКА АДРЕСУЕТСЯ ИМЕНЕМ, А НЕ ПОРЯДКОМ: шаблон пишет
    «verb_pres:s2», и то, какой это по счёту столбец, есть дело таблицы,
    а не показа. Обратная связь «форма → лексемы» нужна закону одной
    лексемы: без неё нельзя отличить показ от склейки двух слов.
    """
    вон = {}
    for имя, класс in (пакет.get("morph_classes") or {}).items():
        имена = класс.get("forms") or []
        for лексема, формы in (класс.get("lexemes") or {}).items():
            for i, форма in enumerate(формы):
                клетка = имена[i] if i < len(имена) else str(i)
                (вон.setdefault((имя, клетка), {})
                    .setdefault(str(форма), set()).add(лексема))
    return вон


def числительные(пакет):
    """({слово: число}, чередование числительных) — счётный словарь."""
    слова = {}
    for ключ, слово in (пакет.get("numerals") or {}).items():
        if str(ключ).lstrip("-").isdigit():
            слова[str(слово)] = int(ключ)
    return слова, _альт(слова)


def цепь_образец(пакет, числа_альт):
    """Образец счётной цепи — перечень числительных объявленным швом.

    Шов берётся ровно там же, где его берёт движок (`chain_of`): свой
    `list_separator`, а без него — пусто у письма без пробелов и пробел
    у прочих. Цепь, где хоть одно числительное не объявлено, движком не
    пишется вовсе, и потому чередование строится лишь из объявленных.
    """
    if числа_альт is None:
        return None
    шов = пакет.get("list_separator")
    if шов is None:
        шов = ("" if пакет.get("segmentation") == "longest-match" else " ")
    return f"{числа_альт}(?:{re.escape(шов)}{числа_альт})*"


class Образец:
    """Один объявленный шаблон, собранный в образцы и в способ проверки."""

    def __init__(self, род, форменный, точный, грубый, скелет,
                 клетки, счётные, числа, дословный=False):
        self.род = род
        self.форменный = форменный
        self.дословный = дословный
        self.точный = точный
        self.грубый = грубый
        self.скелет = скелет
        self.клетки = клетки
        self.счётные = счётные
        self.числа = числа


def образцы(пакет, табл):
    """[Образец] по всякому шаблону, чьи дыры движку известны."""
    буквы = set(пакет.get("graphemes", ""))
    числа_альт = числительные(пакет)[1]
    цепь = цепь_образец(пакет, числа_альт)
    классы = пакет.get("morph_classes") or {}
    вон = []
    for род, показ in (пакет.get("show_kinds") or {}).items():
        if показ.get("refusal"):
            continue
        for шаблон in показ.get("templates", []):
            куски = ДЫРА.split(шаблон)
            литеры, дыры = куски[::2], куски[1::2]
            if not дыры:
                # ПОСТОЯННЫЙ ШАБЛОН ЕСТЬ АЛИБИ, А НЕ ПОКАЗ ФОРМЫ.
                # Пять немецких определений («das system ist ein ding.»)
                # объявлены без единой дыры, и грубый образец соседа
                # «{lex:noun_masc_case:nom} ist ein ding.» назвал их
                # ложью — пятьдесят честных строк. Такой показ ничего не
                # утверждает о клетке, и потому суд его не берёт; но
                # пакет его объявил, и оправдание он даёт.
                вон.append(Образец(род, False,
                                   re.compile("^" + re.escape(шаблон) + "$"),
                                   None, шаблон, {}, {}, {}, True))
                continue
            точный = [re.escape(литеры[0])]
            клетки, счётные, числа, видены = {}, {}, {}, {}
            брошен = False
            for i, (дыра, литера) in enumerate(zip(дыры, литеры[1:])):
                имя_группы = f"г{i}"
                кусок = None
                if дыра in видены:
                    # ТА ЖЕ ДЫРА ЕСТЬ ТО ЖЕ СЛОВО: движок подставляет
                    # одну лексему на весь показ, и обратная ссылка
                    # требует буквального совпадения.
                    кусок = f"(?P={видены[дыра]})"
                elif дыра.startswith("lex:") and дыра.count(":") == 2:
                    класс, клетка = дыра.split(":")[1:3]
                    if (класс, клетка) in табл:
                        кусок = _альт(табл[(класс, клетка)])
                        клетки[имя_группы] = (класс, клетка)
                    elif (клетка in ("by_n", "by_sum")
                          and класс in классы):
                        # СЧЁТНАЯ КЛЕТКА НЕ ОБЪЯВЛЕНА В ТАБЛИЦЕ: столбец
                        # выбирает правило от числа показа. Образец
                        # берёт ВСЕ формы класса, а столбец сверяется
                        # правилом ниже — иначе образец не собрать.
                        все = {ф for формы in
                               (классы[класс].get("lexemes") or {}).values()
                               for ф in формы}
                        кусок = _альт(все)
                        счётные[имя_группы] = (класс, клетка[3:])
                elif дыра in ЧИСЛА:
                    кусок = r"\d+"
                    числа[имя_группы] = дыра
                elif дыра.startswith("num:") and дыра[4:] in ЧИСЛА:
                    # ДВИЖОК ПАДАЕТ НА ЦИФРУ, КОГДА СЛОВА НЕТ:
                    # `numerals.get(str(n), str(n))`. Образец обязан
                    # знать оба исхода, иначе честная строка не сойдётся.
                    кусок = (rf"(?:{числа_альт}|\d+)" if числа_альт
                             else r"\d+")
                    числа[имя_группы] = дыра[4:]
                elif дыра == "chain":
                    кусок = цепь
                if кусок is None:
                    брошен = True
                    break
                if дыра not in видены:
                    видены[дыра] = имя_группы
                    точный.append(f"(?P<{имя_группы}>{кусок})")
                else:
                    точный.append(кусок)
                точный.append(re.escape(литера))
            if брошен:
                continue
            форменный = bool(клетки or счётные)
            скелет = "".join(литеры)
            грубый = None
            if форменный and any(з in буквы for з in скелет.lower()):
                грубый = re.compile(
                    "^" + "(.+?)".join(re.escape(л) for л in литеры) + "$")
            вон.append(Образец(
                род, форменный, re.compile("^" + "".join(точный) + "$"),
                грубый, скелет, клетки, счётные, числа))
    return вон


def отказы(пакет):
    """(маркер, {объявленные под маркером}, {объявленные добрые})."""
    маркер, плохие, добрые = None, set(), set()
    for показ in (пакет.get("show_kinds") or {}).values():
        if not показ.get("refusal"):
            continue
        м = показ.get("marker", МАРКЕР_ПО_УМОЛЧАНИЮ)
        if маркер is None:
            маркер = м
        for пара in показ.get("pairs", []):
            плохие.add(м + str(пара.get("bad", "")))
            добрые.add(str(пара.get("good", "")))
    плохие.discard(маркер or "")
    добрые.discard("")
    return маркер, плохие, добрые


def воспроизводится(совпало, обр, слой):
    """Сходится ли совпавший показ с таблицами и правилами пакета."""
    по_классам = {}

    def сузить(класс, кто):
        прежде = по_классам.get(класс)
        по_классам[класс] = кто if прежде is None else прежде & кто
        return bool(по_классам[класс])

    for имя, адрес in обр.клетки.items():
        if not сузить(адрес[0], слой.таблицы[адрес][совпало.group(имя)]):
            return False
    if обр.счётные:
        знач = {}
        for имя, что in обр.числа.items():
            текст = совпало.group(имя)
            знач[что] = (int(текст) if текст.isdigit()
                         else слой.слова.get(текст))
        for имя, (класс, откуда) in обр.счётные.items():
            k = знач.get(откуда)
            if k is None:
                return False
            cls = слой.классы[класс]
            i = count_form_index(слой.пакет, cls, k)
            форма = совпало.group(имя)
            кто = {л for л, формы in (cls.get("lexemes") or {}).items()
                   if i < len(формы) and формы[i] == форма}
            if not сузить(класс, кто):
                return False
    return True


class Слой:
    """Объявленные таблицы ТОГО пакета, чей это пласт, — и ничего сверх.

    СУДИТЬ ЧУЖОЙ СЛОЙ ТАБЛИЦАМИ ОДНОГО ЯЗЫКА ЗНАЧИЛО БЫ ОБЪЯВЛЯТЬ ЛОЖЬЮ
    ВСЁ ИНОЯЗЫЧНОЕ В НЁМ. Пласт узнаётся по имени мира
    («genesis_lang_uk» → «uk») — тем же признаком, каким его узнаёт суд
    пласта. Файл без этого признака оставляет слой пустым, и суд молчит
    о нём целиком: молчание вне подсудности честнее вердикта.
    """

    def __init__(self):
        self.язык = None
        self.пакет = {}
        self.классы = {}
        self.таблицы = {}
        self.слова = {}
        self.образцы = ()
        self.маркер = None
        self.плохие = set()
        self.добрые = set()

    def впитать(self, путь):
        основа = pathlib.Path(путь).stem
        if "_lang_" not in основа:
            return
        язык = основа.rsplit("_", 1)[-1]
        try:
            пакет = json.loads(
                (ПАКЕТЫ / f"{язык}.json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return
        self.язык = язык
        self.пакет = пакет
        self.классы = пакет.get("morph_classes") or {}
        self.таблицы = таблицы(пакет)
        self.слова = числительные(пакет)[0]
        self.образцы = tuple(образцы(пакет, self.таблицы))
        self.маркер, self.плохие, self.добрые = отказы(пакет)


def вердикт(строка, слой):
    """(судимо, истинно, род) — с именем рода показа для разбора."""
    if слой is None or слой.язык is None:
        return False, True, None
    с = строка.strip()
    if not с:
        return False, True, None
    if с in слой.добрые:
        return True, True, "дословно:refusal"
    if слой.маркер and с.startswith(слой.маркер):
        return True, с in слой.плохие, "refusal"
    алиби = None
    опознан = None
    for обр in слой.образцы:
        совпало = обр.точный.match(с)
        if совпало and воспроизводится(совпало, обр, слой):
            if обр.форменный:
                return True, True, обр.род
            if обр.дословный:
                # ДОСЛОВНЫЙ ПОКАЗ ЕСТЬ ВОСПРОИЗВЕДЕНИЕ, НО НЕ ПОКАЗ
                # ФОРМЫ, и потому назван отдельным именем. Клетки в нём
                # нет, опознавателя соседа нет — суд не скажет о такой
                # строке «ложь» НИКОГДА; порча всплывёт не ложью, а
                # слепотой, ибо испорченная строка перестанет совпадать
                # с объявлением. Число таких строк названо в вердикте:
                # мера обязана называть, чем она держится.
                return True, True, f"дословно:{обр.род}"
            алиби = алиби or обр.род
    if алиби is not None:
        return False, True, f"чужой:{алиби}"
    for обр in слой.образцы:
        if обр.грубый is not None and обр.грубый.match(с):
            if опознан is None or len(обр.скелет) > len(опознан[1]):
                опознан = (обр.род, обр.скелет)
    if опознан is not None:
        return True, False, опознан[0]
    return False, True, None


def судить(строка, слой=None):
    """(судимо, истинно) — воспроизводится ли строка из пакета."""
    судимо, истинно, _ = вердикт(строка, слой)
    return судимо, истинно


# ── ПОДСАДКА ФОРМОЙ ИЗ СОСЕДНЕЙ КЛЕТКИ ─────────────────────────────
#
# СУД, КОТОРЫЙ НИКОГДА НЕ ПАДАЛ, ПОДОЗРИТЕЛЕН В НЕПОДКЛЮЧЁННОСТИ, и
# зелень его говорит две неотличимые снаружи вещи: либо пласт чист,
# либо провод оторван. Различает только подсадка.
#
# ЧИСЛОВАЯ ПОДСАДКА ЗДЕСЬ НЕПРИМЕНИМА, И ЭТО НЕ ОТГОВОРКА, А РОД. Общий
# прибор (`scripts/court_mutants.py`) портит ЧИСЛО на соседнее; показ
# формы числа не несёт вовсе («tú hablas.»), и о таком суде прибор
# честно говорит «НЕТ ЧИСЛА». Порча этого рода есть ФОРМА ИЗ СОСЕДНЕЙ
# КЛЕТКИ ТОЙ ЖЕ ЛЕКСЕМЫ — лицо, число, род, падеж, — и она берётся из
# таблицы, а не выдумывается.
#
# ПАРА ОБЯЗАТЕЛЬНА. Мутант без честного близнеца не доказывает ничего:
# он мог не дойти до места. Близнец берётся ИЗ ПЛАСТА и потому заведомо
# зовётся истиной — по этому признаку он и найден.


def соседи_клетки(слой, класс, клетка, форма):
    """[(форма ТОЙ ЖЕ лексемы из иной клетки, имя клетки)] — все соседи."""
    имена = (слой.классы[класс].get("forms") or [])
    вон = []
    for лексема in sorted(слой.таблицы[(класс, клетка)][форма]):
        формы = слой.классы[класс]["lexemes"][лексема]
        for i, ф in enumerate(формы):
            имя = имена[i] if i < len(имена) else str(i)
            if имя != клетка and ф != форма:
                вон.append((ф, имя))
    return вон


def соседи_счёта(слой, класс, форма):
    """То же для клетки, выбираемой правилом счёта: иные столбцы."""
    класс_ = слой.классы[класс]
    имена = класс_.get("forms") or []
    вон = []
    for лексема, формы in sorted((класс_.get("lexemes") or {}).items()):
        if форма not in формы:
            continue
        свой = формы.index(форма)
        for i, ф in enumerate(формы):
            if i != свой and ф != форма:
                вон.append((ф, имена[i] if i < len(имена) else str(i)))
    return вон


def объявлен(строка, слой):
    """Объявляет ли ПАКЕТ эту строку показом — хоть каким шаблоном.

    РАМКА, ОБЩАЯ ДВУМ КЛЕТКАМ, НЕ ЕСТЬ МЕСТО ПОДСАДКИ. Китайский пакет
    объявляет и «{lex:person_plural:one}来了。», и
    «{lex:person_plural:many}来了。»: замена «朋友» на «朋友们» даёт не
    порчу, а ЧЕСТНЫЙ показ соседнего шаблона (обоих в пласте по 47), и
    вердикт «истина» о нём верен. Тот же закон, каким живёт свободное
    число в приборе мутантов: подсадка в место, где язык не хранит
    различия, не доказывает ни о суде, ни о корпусе ничего.

    Спрашивается ОБЪЯВЛЕНИЕ ПАКЕТА, а не вердикт суда: иначе проба
    искала бы порчу, которую суд уже назвал ложью, и доказывала бы
    сама себя.
    """
    if строка in слой.добрые or строка in слой.плохие:
        return True
    for обр in слой.образцы:
        совпало = обр.точный.match(строка)
        # СОВПАДЕНИЕ ОБРАЗЦА ЕЩЁ НЕ ЕСТЬ ОБЪЯВЛЕНИЕ. Счётная клетка
        # берёт в образец ВСЕ формы класса, а столбец выбирает правило:
        # «было 6 чашка.» образцу подходит и правилу — нет. Без этой
        # проверки проба звала бы порчу согласования честным показом.
        if совпало and воспроизводится(совпало, обр, слой):
            return True
    return False


def подсадки(строка, слой):
    """[(порча, повод)] — замены одной формы соседней по таблице."""
    с = строка.strip()
    вон = []
    if слой.маркер and с.startswith(слой.маркер):
        # ОТКАЗ ПОРТИТСЯ ЗАМЕНОЙ ОДНОГО СЛОВА НА ЗАКОННОЕ: пара
        # объявляет и негодный показ, и его законного близнеца, и там,
        # где они разнятся РОВНО ОДНИМ словом, замена есть подсадка в
        # одно место — «¬ два час.» → «¬ два часа.», то есть законная
        # речь, выставленная под маркером отказа.
        if с not in слой.плохие:
            return вон
        тело = с[len(слой.маркер):]
        for добро in sorted(слой.добрые):
            а, б = тело.split(), добро.split()
            if len(а) != len(б):
                continue
            розно = [i for i in range(len(а)) if а[i] != б[i]]
            if len(розно) == 1:
                i = розно[0]
                было = а[i]
                а[i] = б[i]
                вон.append((слой.маркер + " ".join(а),
                            f"отказ: «{было}» → «{б[i]}» "
                            f"(законная форма под маркером отказа)"))
        return вон
    for обр in слой.образцы:
        совпало = обр.точный.match(с)
        if not (совпало and обр.форменный
                and воспроизводится(совпало, обр, слой)):
            continue
        for имя, (класс, клетка) in обр.клетки.items():
            a, b = совпало.span(имя)
            форма = совпало.group(имя)
            for иная, имя_клетки in соседи_клетки(слой, класс, клетка,
                                                  форма):
                вон.append((с[:a] + иная + с[b:],
                            f"{класс}: «{форма}» ({клетка}) → «{иная}» "
                            f"({имя_клетки})"))
        for имя, (класс, откуда) in обр.счётные.items():
            a, b = совпало.span(имя)
            форма = совпало.group(имя)
            for иная, имя_клетки in соседи_счёта(слой, класс, форма):
                вон.append((с[:a] + иная + с[b:],
                            f"{класс}: «{форма}» (по счёту {откуда}) → "
                            f"«{иная}» ({имя_клетки})"))
    return вон


ПОЙМАН, НЕ_ПОЙМАН, ОНЕМЕЛ = "ПОЙМАН", "НЕ ПОЙМАН", "ОНЕМЕЛ"
ОБЩАЯ = "РАМКА ОБЩАЯ"
# ПОЙМАН вытесняет всё, НЕ ПОЙМАН — всё кроме поимки: суд, назвавший
# испорченное истинным, сказал о себе больше, чем суд, промолчавший.
ВЕС = {ОБЩАЯ: 1, ОНЕМЕЛ: 2, НЕ_ПОЙМАН: 3, ПОЙМАН: 4}


def доказать(пути):
    """Подсадка парой на каждый род показа, что суд берётся судить."""
    доказан, роды = {}, set()
    for путь in пути:
        слой = Слой()
        слой.впитать(путь)
        if слой.язык is None:
            continue
        роды |= {обр.род for обр in слой.образцы if обр.форменный}
        if слой.плохие:
            роды.add("refusal")
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                if not строка.strip():
                    continue
                судимо, истинно, род = вердикт(строка, слой)
                if not (судимо and истинно):
                    continue
                if доказан.get(род, ("", ))[0] == ПОЙМАН:
                    continue
                for порча, повод in подсадки(строка, слой):
                    if объявлен(порча, слой):
                        исход, повод = ОБЩАЯ, повод + " — оба показа объявлены"
                    else:
                        судимо_п, истинно_п, _ = вердикт(порча, слой)
                        исход = (ПОЙМАН if судимо_п and not истинно_п
                                 else НЕ_ПОЙМАН if судимо_п else ОНЕМЕЛ)
                    прежде = доказан.get(род)
                    if прежде is None or ВЕС[исход] > ВЕС[прежде[0]]:
                        доказан[род] = (исход, слой.язык, строка.strip(),
                                        порча.strip(), повод)
                    if исход == ПОЙМАН:
                        break
    плохо = 0
    for род in sorted(роды):
        если = доказан.get(род)
        if если is None:
            плохо += 1
            print(f"  РОД {род:<16} НЕТ ИСТИННОЙ СТРОКИ — суд не прочёл "
                  f"ни одного показа этого рода")
            continue
        исход, язык, честно, порча, повод = если
        плохо += исход == НЕ_ПОЙМАН
        print(f"  РОД {род:<16} {исход:<12} {язык}  {повод}")
        print(f"      честно «{честно[:76]}»")
        print(f"      порча  «{порча[:76]}»")
    поймано = sum(1 for з in доказан.values() if з[0] == ПОЙМАН)
    общих = sum(1 for з in доказан.values() if з[0] == ОБЩАЯ)
    поза = "PASS" if not плохо else "FAIL"
    print(f"ПОДСАДКА ФОРМОЙ {поза}: {поймано} родов поймали порчу, "
          f"{плохо} не поймали или пусты, {общих} с общей рамкой "
          f"(родов {len(роды)})")
    return 0 if поза == "PASS" else 1


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ФОРМА ПЛАСТА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ФОРМА ПЛАСТА ОТКАЗ: обход пуст, судить нечего")
        return 2
    if "--мутанты" in sys.argv:
        return доказать(пути)
    по_родам = {}
    ложных = судимых = всего = пластов = слепых_рамок = дословных = 0
    примеры = []
    for путь in пути:
        слой = Слой()
        слой.впитать(путь)
        if слой.язык is None:
            continue
        пластов += 1
        # РАМКА БЕЗ ОПОЗНАВАТЕЛЯ СЧИТАЕТСЯ ВСЛУХ. Шаблон, чья
        # неизменная часть не несёт ни одной буквы письма (тайские
        # «{lex:noun_count:one}{lex:adj_forms:plain}» — две дыры
        # подряд), судится только истиной: ложь в нём суд назвать не
        # может, ибо опознать род ему нечем. Слепота, названная
        # числом, есть граница; неназванная — обещание.
        слепых_рамок += sum(1 for обр in слой.образцы
                            if обр.форменный and обр.грубый is None)
        свои_ложных = свои_судимых = свои_всего = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                if not строка.strip():
                    continue
                свои_всего += 1
                судимо, истинно, род = вердикт(строка, слой)
                счёт = по_родам.setdefault(род or "НЕ ОПОЗНАН", [0, 0])
                счёт[0 if истинно else 1] += 1
                if not судимо:
                    continue
                свои_судимых += 1
                дословных += род.startswith("дословно:")
                if not истинно:
                    свои_ложных += 1
                    if len(примеры) < 6:
                        примеры.append(
                            f"{путь.name}: {строка.strip()[:78]}")
        всего += свои_всего
        судимых += свои_судимых
        ложных += свои_ложных
        if свои_ложных or "--пласты" in sys.argv:
            print(f"  {путь.name:<26} судимых {свои_судимых:>6} из "
                  f"{свои_всего:>6}, ложных {свои_ложных}")
    if "--роды" in sys.argv:
        for род, (истин, ложь) in sorted(
                по_родам.items(), key=lambda п: -sum(п[1])):
            print(f"  РОД {род:<20} истина {истин:>6}  ложь {ложь:>5}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ФОРМА ПЛАСТА {поза}: {ложных} ложных из {судимых} судимых "
          f"({всего} строк пласта, {пластов} пластов, "
          f"дословных {дословных}, рамок без опознавателя "
          f"{слепых_рамок}, рубеж {ЛОЖНЫХ_РУБЕЖ})")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
