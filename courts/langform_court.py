"""[ФОРМА ПЛАСТА] — стоит ли ЭТА форма в ЭТОЙ клетке объявленной таблицы.

ПЛАСТ ЯЗЫКА ЕСТЬ СЛЕДСТВИЕ ПАКЕТА, И ПОТОМУ СУДИМ ВОСПРОИЗВЕДЕНИЕМ.
Строка «tú hablas.» не выдумана: движок взял объявленный шаблон
«tú {lex:verb_pres:s2}.» и подставил в дыру клетку `s2` объявленной
таблицы `verb_pres`. Значит вопрос суда не «объявлено ли слово», а
«СТОИТ ЛИ ЭТА ФОРМА В ЭТОЙ КЛЕТКЕ» — и на него отвечает воспроизведение.

ПОВОД, ПРОЖИТЫЙ 02.09, И ЕГО ЧИСЛО. Мера судимости объявила долгом
67 162 строки языкового пласта — тридцать семь процентов всего свода
показов: их не читал НИ ОДИН суд истины. Зачёт им ставился СЛОВАРЁМ
ПАКЕТА, то есть проверкой «всякое ли слово строки объявлено». Проверка
настоящая, она умеет падать; но она слабая, ибо «tú hablo.» её проходит
— оба слова объявлены. Здесь она не проходит.

ПЕРВЫЙ УЛОВ, И ОН ОПРАВДАЛ ЗАКОН В ТОТ ЖЕ ЧАС. Русский пакет объявлял
повествование «вчера юра {lex:verb_past:m} {num:m} {lex:noun_masc:by_n}.»:
ЧИСЛО берётся у `m`, а СОГЛАСОВАНИЕ выбирается по `n`. Оттого в корпусе
стояло 135 строк вида «вчера юра нашёл один домов» и «вчера юра отдал
два орех» — неправильная русская речь, прожившая все прежние суды: и
словарь пакета цел (все слова объявлены), и правило языка цело (формы
стоят в своих клетках таблицы), и счёт молчит (числа тут нет).
Соседний показ того же рода — «вчера маша {lex:verb_past:f} {num:n}
{lex:noun_fem_a:by_n}.» — берёт оба у `n` и потому верен: намерение
доказано близнецом, а не догадкой. Пакет исправлен, пласт пересобран;
135 ложных строк ушли из корпуса.

ТРИ ИСХОДА, И РАЗЛИЧАТЬ ИХ ОБЯЗАТЕЛЬНО:

    ИСТИНА   — строка целиком выводится из объявленных таблиц;
    ЛОЖЬ     — род показа опознан по неизменной части шаблона, но форма
               стоит не в той клетке: «tú hablo.» есть клетка `s1` на
               месте `s2`, и это ЛОЖЬ, а не неизвестность;
    МОЛЧАНИЕ — род показа не опознан, и суд не берётся.

ЧУЖОЙ ШАБЛОН СОБИРАЕТСЯ НАРАВНЕ СО СВОИМ, И В ЭТОМ ВЕСЬ СМЫСЛ. Первая
редакция строила образцы лишь для шаблонов формы и объявила ЛОЖЬЮ 842
ЧЕСТНЫЕ строки: немецкое «ich zähle 6 wege.» рождено счётным шаблоном
«ich zähle {n} {lex:noun_count:by_n}.», а грубый образец спряжения
«ich {lex:verb_pres:s1}.» совпал с ним и захватил «zähle 6 wege». ЗАКОН:
СТРОКА, КОТОРУЮ ВОСПРОИЗВОДИТ ХОТЬ ОДИН ОБЪЯВЛЕННЫЙ ШАБЛОН, НЕ ЕСТЬ
ЛОЖЬ ЭТОГО СУДА. Потому образцы строятся для ВСЕХ шаблонов пакета:
счётные и цепные — не для вердикта, а для алиби, и их совпадение есть
молчание (истину такой строки считает счётный суд).

ДЫРА, КОТОРУЮ ДВИЖОК НЕ ЗНАЕТ, НЕ РОДИЛА НИ ОДНОЙ СТРОКИ. Финский
«{many} ovat suomen sanoja.» несёт дыру, которой нет в наборе движка:
подстановка её не заменяет, а показ со скобкой отбрасывается
(`if "{" not in s`). Такой шаблон не судит и не оправдывает — его нет.

РОД ОПОЗНАЁТСЯ НЕИЗМЕНЯЕМОЙ ЧАСТЬЮ ШАБЛОНА, А НЕ ДЫРОЙ. Шаблон
«{chain}.» есть дыра под точкой: его грубый образец совпал бы со ВСЯКОЙ
строкой, и суд объявил бы ложью весь счётный пласт. Потому род опознаётся
лишь тем шаблоном, чья неизменная часть несёт хоть одну букву
ОБЪЯВЛЕННОГО письма (`graphemes` пакета). Три тайских шаблона
согласования такой части не имеют вовсе — они суть две дыры подряд, — и
суд судит их только истиной; ложью не судит и говорит об этом числом.
Когда грубых образцов совпало несколько, род называет тот, чья
неизменная часть ДЛИННЕЕ: он опознаёт точнее.

ТОЧНОЕ СОВПАДЕНИЕ СПРАШИВАЕТСЯ РАНЬШЕ ГРУБОГО, И ЭТО ЗАКОН, А НЕ
ПОРЯДОК. Испанские «aquí está {lex:noun_count:one}.» и «aquí están
{lex:noun_count:many}.» делят начало: грубый образец первого совпадает с
ЧЕСТНОЙ строкой второго и захватывает «n las casas». Строка истинна ровно
тогда, когда её воспроизводит ХОТЬ ОДИН объявленный шаблон; ложна —
когда её опознал шаблон и не воспроизвёл НИ ОДИН.

ФОРМЫ ОДНОГО КЛАССА В ОДНОМ ПОКАЗЕ ВЗЯТЫ У ОДНОЙ ЛЕКСЕМЫ. Движок
выбирает лексему НА КЛАСС, а не на дыру: показ хинди
«{lex:noun_count:one} क्या है? {lex:noun_count:one} एक वस्तु है।» несёт одно
и то же слово дважды. Склейка форм двух разных лексем есть ложь того же
рода, что и чужая клетка, и судится тем же вердиктом.

СОГЛАСОВАНИЕ ПО СЧЁТУ ВОСПРОИЗВОДИТСЯ ПРАВИЛОМ ПАКЕТА, А НЕ УГАДЫВАЕТСЯ.
Клетки `by_n` и `by_sum` не объявлены в таблице: движок выбирает столбец
правилом `count_agreement` от самого числа показа («ich zähle 2 häuser»
против «ich zähle 1 haus»). Суд зовёт ТО ЖЕ правило (`count_form_index`
движка), а не пишет второе такое же: два дома одного закона разошлись бы
в день его правки.

ОТКАЗ ЕСТЬ ВТОРОЙ РОД ВОСПРОИЗВЕДЕНИЯ. Пара отказа объявлена в пакете
ДОСЛОВНО — «bad» под маркером и «good» без него, — и потому пласт обязан
нести ровно объявленное, буква в букву. Маркер и есть признак рода:
строка под маркером, которой в объявленных парах нет, есть ЛОЖЬ.

ДОСЛОВНОЕ ВОСПРОИЗВЕДЕНИЕ ЕСТЬ ВОСПРОИЗВЕДЕНИЕ, И ОНО НАЗВАНО ЧИСЛОМ.
Часть показов объявлена пакетом БЕЗ ЕДИНОЙ ДЫРЫ — пять немецких
определений, венгерское «Ez a házam.», законные близнецы пар отказа. В
такой строке клетки нет, а стало быть нет и опознавателя соседа: суд не
скажет о ней «ложь» НИКОГДА. Порча всплывает не ложью, а СЛЕПОТОЙ —
испорченная строка перестаёт совпадать с объявлением, и мера охвата
видит её как непрочтённую. Проверка настоящая, но иного устройства, и
потому вердикт называет её долю отдельным числом («дословных N»): суд,
не называющий, чем он держится, ставит зачёт вместо проверки.

ГРАНИЦА ОБЪЯВЛЕНА ЗДЕСЬ, А НЕ СПРЯТАНА. Суд заявляет: «строка пласта
воспроизводится из объявленных таблиц пакета» — и ни словом больше. Верна
ли сама таблица (стоит ли «hablas» во втором лице испанского), знает не
он: это предмет суда правила языка, где форма утверждена дважды
независимыми путями, и предмет носителя. Ложный пакет, породивший
согласный с собою пласт, этот суд пройдёт.
"""
