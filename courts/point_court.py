#!/usr/bin/env python3
"""[ТОЧКА НА ПЛОСКОСТИ] — пара чисел и порядок в ней, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`pointforms`), где рамки и числа объявлены одной
таблицей. Подмена разности, пары и самого ПОРЯДКА ловится машинально: страница о порядке обязана
нести ДВЕ переставленные и РАЗНЫЕ пары, а страница о ходе — менять РОВНО ОДНО число из двух.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ПАРА НЕ ЕСТЬ МНОЖЕСТВО: в ней значит не только ЧТО, но и ГДЕ, и потому суд сверяет не числа
поодиночке, а их МЕСТА в скобках.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/point_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import pointforms  # noqa: E402 — дом, объявивший точку на плоскости

ИМЯ_СУДА = "point"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"point"})


def _судить(строка):
    return pointforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ТОЧКА НА ПЛОСКОСТИ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(pointforms.РОДЫ)}, страниц {len(pointforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
