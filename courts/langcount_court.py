#!/usr/bin/env python3
"""[СЧЁТ НА ДЕВЯТИ ЯЗЫКАХ] — стои́т ли при числе та форма, какой требует пакет.

ПОВОД. Суд памяти (`engram_court`) судит счёт объявленного слова — и только ПО-АНГЛИЙСКИ;
русский счёт судит `rugram`. Прочие семь языков не судил никто: страница «Anne a acheté 18
livres et Anne a acheté 20 fleurs. combien de livres Anne a-t-il achetés ? 18 livres.»
арифметики не несёт, и палата о ней МОЛЧАЛА — не по недосмотру, а потому что суда не было.

    ЯЗЫК, У КОТОРОГО НЕТ СУДА СЧЁТА, ПРИНИМАЕТ ЛЮБУЮ ФОРМУ ПРИ ЧИСЛЕ. «5 les livres», «5
    książki», «5 bücher» прошли бы все три — и первые две суть ложь о языке при верной
    арифметике.

ЧЕМ ЭТОТ СУД СТАЛ ВОЗМОЖЕН. До 07.09 счётный класс семи языков объявлял формы С АРТИКЛЕМ
(«le livre / les livres»), то есть НАЗЫВАЛ вещь, а не считал её; немецкий объявлял
строчную, польский — две ячейки при правиле, требующем трёх. Судить было не по чему.
Класс починен (141 лексема), и ныне пакет отвечает на вопрос «какая форма при этом числе»
на всех девяти языках — а суд лишь спрашивает.

КАК СУДИТ. В строке ищется «ЧИСЛО СЛОВО»; слово ищется среди объявленных лексем девяти
пакетов. Если хоть один пакет, объявивший это слово, признаёт форму верной при этом числе —
строка ИСТИННА. Если ни один не признаёт — ЛОЖНА.

    СЛОВО, ЖИВУЩЕЕ В ДВУХ ЯЗЫКАХ, СУДИТСЯ СНИСХОДИТЕЛЬНО, И ЭТО НЕ СЛАБОСТЬ, А ГРАНИЦА.
    «casa» стои́т в испанском, итальянском и португальском, «table» — в английском и
    французском; суд, не знающий языка строки наверное, не смеет звать ложью форму, верную
    хоть в одном из них. Он ловит то, что не верно НИГДЕ, — и этого довольно, чтобы «5 les
    livres» и «5 książki» не прошли.

ГРАНИЦА ОБЪЯВЛЕНА И ВТОРОЙ РАЗ: судится лишь то, что пакет ОБЪЯВИЛ. Слово вне лексем
девяти пакетов суду не подсудно, и молчание о нём есть честная граница, а не зачёт.

ГРАНИЦА ТРЕТЬЯ, И ОНА ЖЕ ЦЕНА ВТОРОЙ: строка, чей язык не назван НИ ОДНИМ служебным словом
пакета, не судится вовсе. «2 kwiaty leżą na stole.» — польская речь, но знака польского в
ней `langsign` не видит, и суд о ней молчит.

    СУД, НЕ ЗНАЮЩИЙ ЯЗЫКА СТРОКИ, МОЛЧИТ О НЕЙ — И ЭТО ЛУЧШЕЕ, ЧТО ОН МОЖЕТ. Прежде он не
    молчал: судил французское «1 carte» по итальянской лексеме и назвал ложью 1 899 строк.
    Цена молчания — короткие строки без служебных слов; цена крика была бы — ложь о своде.

ПРОБА НА НЕ-НОЛЬ (07.09): шесть честных строк испорчены соседней ячейкой той же лексемы —
«5 książek → 5 książki», «3 książki → 3 książek», «5 книг → 5 книги», «5 livres → 5 livre»,
«5 books → 5 book». Пять из шести названы ложью, шестая («2 kwiaty») не судится по границе
третьей. Ноль на своде есть показание, а не слепота.
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import langpack  # noqa: E402
import langsign  # noqa: E402

ЯЗЫКИ = ("ru", "en", "de", "fr", "es", "it", "pt", "nl", "pl")
_ПАКЕТЫ = {}
for _я in ЯЗЫКИ:
    _п = КОРЕНЬ / "tools" / "langpacks" / f"{_я}.json"
    if _п.is_file():
        _ПАКЕТЫ[_я] = json.loads(_п.read_text(encoding="utf-8"))

# УКАЗАТЕЛЬ: форма (строчная) → [(язык, класс, лексема)] — по каким лексемам она стои́т.
_ПО_ФОРМЕ = {}
for _я, _пак in _ПАКЕТЫ.items():
    for _имя, _кл in (_пак.get("morph_classes") or {}).items():
        if not (set(_кл.get("forms") or []) & {"one", "many"}):
            continue
        # КЛАСС, ЧЬИ СЛОВА НЕ СТОЯТ ПОСЛЕ СВОЕГО ЧИСЛА, ЭТОМУ СУДУ НЕ ПОДСУДЕН (08.09).
        #
        # Суд читает пару «ЧИСЛО СЛОВО» и ждёт там СЧИТАЕМОЕ ИМЯ. Наличие ячеек «one»/«many»
        # было верным признаком имени ровно до того часа, когда польский пакет объявил СВЯЗКУ,
        # гнущуюся тем же правилом: «są 3 koty» — связка стои́т ПЕРЕД числом, а после числа она
        # оказывается лишь случайно, и там её согласование правит уже не это число.
        #
        #     ПРИЗНАК, ВЕРНЫЙ ПОКА КЛАСС ОДИН, ЕСТЬ ПРИЗНАК КЛАССА, А НЕ ЗАКОНА. Пятьдесят три
        #     честные строки двух миров были названы ложью: «o ile 4 jest cieplej niż −14?»
        #     (подлежащее есть само число, и «jest» верно) и «po kroku 2 jest 16 książek»
        #     (двойка есть номер шага, а связка правится шестнадцатью).
        #
        # Пакет объявляет границу полем `follows_its_number`; умолчание — «да», и ни один
        # прежний класс не сдвинут.
        if _кл.get("follows_its_number", True) is False:
            continue
        for _лекс, _формы in (_кл.get("lexemes") or {}).items():
            for _ф in _формы:
                _ПО_ФОРМЕ.setdefault(_ф.lower(), []).append((_я, _имя, _лекс.lower()))
    for _лекс, _мн in (_пак.get("noun_forms") or {}).items():
        _ПО_ФОРМЕ.setdefault(_лекс.lower(), []).append((_я, "noun_forms", _лекс.lower()))
        _ПО_ФОРМЕ.setdefault(str(_мн).lower(), []).append((_я, "noun_forms", _лекс.lower()))

# ПАРА БЕРЁТ И СЛЕДУЮЩЕЕ СЛОВО: счёт правит ПОСЛЕДНИМ именем составного (07.09, первый
# обход свода). «36 bottle caps» — считаются КРЫШКИ, а «bottle» есть определение; суд,
# читавший слово сразу за числом, назвал ложью 270 честных строк одного мира. Правило то
# же, что у суда памяти: составное имя судится по последнему слову.
ПАРА = re.compile(r"(?<![\w.,])(\d+)(?![\d.,])\s+([^\W\d_]+)(?:\s+([^\W\d_]+))?")

# ПАДЕЖ, НАВЯЗАННЫЙ СОСЕДОМ, ОТМЕНЯЕТ СЧЁТНУЮ ФОРМУ (08.09, обход свода выборкой в 38 377
# строк — каждая десятая: девять «лжей», и все девять оказались ЧЕСТНЫМИ строками).
#
#     ЦИФРА СКРЫВАЕТ ПАДЕЖ. «сумма первых 4 чисел» — числительное тут в РОДИТЕЛЬНОМ («первых
#     четырёх»), и имя при нём стои́т в родительном множественном, а не в счётной форме. Суд,
#     читающий одну лишь цифру, видит «4» и требует «4 числа» — и зовёт ложью правильную речь.
#
# Признак берётся у СОСЕДА, ибо в самой цифре его нет: слово перед числом, ставящее оборот в
# родительный, объявлено ПОИМЁННО. Не угадано по окончанию — «-ых/-их» носят прилагательные и
# иных падежей («в этих 4 домах» — предложный, и там счётная форма как раз нужна).
УПРАВЛЯЮТ_РОДИТЕЛЬНЫМ = frozenset({"первых", "последних", "остальных", "обоих"})

# ДАТА НЕ ЕСТЬ СЧЁТ (08.09). «2 сентября 2026 года» — день месяца, то есть ПОРЯДКОВОЕ
# числительное («второго сентября»), и месяц при нём в родительном единственном, а «года» —
# хвост той же даты. Суд читал пару «2 сентября» как счёт и требовал «2 сентябрь»; тем же
# чтением он спотыкался о «2026 года». Дата опознаётся целиком, а не по одному слову.
МЕСЯЦЫ_РОДИТЕЛЬНЫЙ = ("января", "февраля", "марта", "апреля", "мая", "июня",
                      "июля", "августа", "сентября", "октября", "ноября", "декабря")
ДАТА = re.compile(r"\b\d{1,2} (?:" + "|".join(МЕСЯЦЫ_РОДИТЕЛЬНЫЙ) + r")(?: \d{4} года)?")
ПЕРЕД = re.compile(r"([^\W\d_]+)\W*$")


def _годна(язык, класс_имя, лексема, форма, n):
    """Годна ли ЭТА форма при этом числе по объявлению ЭТОГО пакета."""
    пак = _ПАКЕТЫ[язык]
    if класс_имя == "noun_forms":
        nf = пак.get("noun_forms") or {}
        ждём = лексема if n == 1 else str(nf.get(лексема, "")).lower()
        return форма == ждём.lower()
    кл = (пак.get("morph_classes") or {}).get(класс_имя) or {}
    формы = кл.get("forms") or []
    ряд = {k.lower(): v for k, v in (кл.get("lexemes") or {}).items()}.get(лексема)
    if not ряд:
        return False
    i = langpack.count_form_index(пак, кл, n)
    годные = {ряд[i].lower()}
    счётная = f"count_{формы[i]}"
    if счётная in формы:
        годные.add(ряд[формы.index(счётная)].lower())
    return форма in годные


def _языки_строки(строка):
    """Языки, которым строка НЕ ЧУЖДА по знаку служебных слов (`langsign`).

    СУДИТЬ СЛОВО ПО ЧУЖОМУ ЯЗЫКУ — ХУЖЕ, ЧЕМ МОЛЧАТЬ (07.09, первый обход свода). Суд
    назвал ложью «1 carte» французской строки — по ИТАЛЬЯНСКОЙ лексеме «carta», где
    «carte» есть множественное; «310 Cent» и «3 Meter» немецких строк — по АНГЛИЙСКИМ
    «cent»/«meter», хотя немецкая мера при числе не меняется. Тысяча восемьсот
    девяносто девять «лжей» первого обхода были почти все этого рода.

        ФОРМА ВЕРНА ИЛИ ЛОЖНА ТОЛЬКО ВНУТРИ ЯЗЫКА. Суд, не знающий языка строки, судит
        не форму, а совпадение букв.
    """
    вон = []
    for я in _ПАКЕТЫ:
        try:
            if not langsign.чужой(строка, я):
                вон.append(я)
        except Exception:
            continue
    return вон


def _судить(строка, слой=None):
    """(судимо, истинно): судимо, если при числе стои́т ОБЪЯВЛЕННОЕ слово ЭТОГО языка."""
    if слой is not None and getattr(слой, "полка", False):
        return False, True          # чужой текст: мера показов ему не судья
    свои = set(_языки_строки(строка))
    if not свои:
        return False, False         # язык строки не назван ни одним знаком — суд молчит
    судимо = False
    даты = [(д.start(), д.end()) for д in ДАТА.finditer(строка)]
    for м in ПАРА.finditer(строка):
        n, форма = int(м.group(1)), м.group(2).lower()
        if any(а <= м.start() < б for а, б in даты):
            continue                # день месяца и год: порядковое, а не счёт
        слева = ПЕРЕД.search(строка[:м.start()])
        if слева and слева.group(1).lower() in УПРАВЛЯЮТ_РОДИТЕЛЬНЫМ:
            continue                # оборот в родительном: счётная форма тут не правит
        следом = (м.group(3) or "").lower()
        # СОСТАВНОЕ ИМЯ: счёт правит последним словом — «36 bottle caps» о крышках.
        # Признак тот же, что у суда памяти: следующее слово объявлено ЛИБО похоже на
        # множественное («caps» при необъявленном «cap»). Второе взято у `engram_court`
        # дословно, а не выдумано: «len > 3 и кончается на s».
        if следом and (следом in _ПО_ФОРМЕ or (len(следом) > 3 and следом.endswith("s"))):
            continue
        # НЕМЕЦКОЕ ИМЯ ПИШЕТСЯ С ПРОПИСНОЙ, И ЭТО ПРИЗНАК, А НЕ УКРАШЕНИЕ (07.09, второй
        # обход). «er gab 15 weg» — «weg» здесь ОТДЕЛЯЕМАЯ ПРИСТАВКА глагола «weggeben»,
        # а не имя «Weg»; суд, читавший строчное слово как имя, назвал ложью 32 честных
        # строки мира `svamp`. Строчное слово после числа немецким именем быть не может.
        сырое = м.group(2)
        свои_здесь = свои if сырое[:1].isupper() else [я for я in свои if я != "de"]
        места = [(я, к, л) for я, к, л in (_ПО_ФОРМЕ.get(форма) or ()) if я in свои_здесь]
        if not места:
            continue
        судимо = True
        if any(_годна(я, класс, лекс, форма, n) for я, класс, лекс in set(места)):
            continue
        return True, False
    return (True, True) if судимо else (False, False)


# МИРЫ ЗАМКНУТЫ: суд сузился до объявленных лексем, и молчание его о прочих есть граница.
судить = closedworld.замкнуть_слоем(_судить, frozenset())


if __name__ == "__main__":
    for с in sys.stdin:
        print(судить(с.rstrip("\n")), с.rstrip("\n"))
