#!/usr/bin/env python3
"""[СУД ОДНОГО СЛУЧАЯ] — импликация проверена обходом ряда, случай — порознь; МИР ЗАМКНУТ.

Страница мира (`tools/onecase.py`) есть общее утверждение и один случай к нему. Суд не верит
ни слову «неверно», ни слову «если»: держится ли импликация, он решает САМ, проходя весь
объявленный ряд, а названное число обязано БЫТЬ тем самым случаем, а не каким угодно.

    ОДИН СЛУЧАЙ НЕ ДОКАЗЫВАЕТ ОБЩЕГО И ОПРОВЕРГАЕТ ЕГО ЦЕЛИКОМ. Это не симметрия: чтобы
    утвердить «всякое», нужен весь ряд; чтобы свалить — довольно одного.

    И ЕСТЬ ТРЕТЬЕ, ЧТО СНИМАЕТ МНИМОЕ ПРОТИВОРЕЧИЕ: на ОБЪЯВЛЕННОМ КОНЕЧНОМ РЯДУ обход
    всего ряда ЕСТЬ доказательство. Асимметрия живёт не в логике примера, а в
    БЕСКОНЕЧНОСТИ области; назови область конечной и пройди её — и «всякое» доказано.

Потому суд строг к счёту: «проверены все» без числа пройденных есть слово, а не обход, и он
сверяет названное число с тем, сколько чисел ряда и правда попадают под посылку.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import onecase as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"onecase"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_onecase.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_onecase.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_onecase.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ОДИН СЛУЧАЙ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
