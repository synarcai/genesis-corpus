#!/usr/bin/env python3
"""[ДЕЛЕНИЕ С ОСТАТКОМ] — закон об остатке, который не проверяется суммой.

Суд не пишет закона заново: он берёт его у дома (`remdivforms`), где рамки и числа объявлены одной
таблицей. Здесь суд делает то, чего НЕ МОЖЕТ сделать суд арифметики: сверяет ОСТАТОК С
ДЕЛИТЕЛЕМ. Сумма «10 + 7 = 17» верна и у недоведённого деления, и арифметика подтвердит её —
ПРОВЕРКА, КОТОРУЮ ПРОХОДИТ И НЕВЕРНЫЙ ОТВЕТ, НЕ ЕСТЬ ПРОВЕРКА ОТВЕТА.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЛОВУШКА ОБЯЗАНА ЛОВИТЬ, И ЭТО ТОЖЕ ПРОВЕРЯЕТСЯ: у отвергнутого ответа сумма обязана СХОДИТЬСЯ, а
остаток — нарушать закон. Страница, где отвергнут ответ с неверной суммой, отвергает не то, что
читатель мог бы подумать.

ЭТОТ ДОМ ЧИТАЕТСЯ И СУДОМ АРИФМЕТИКИ: его страницы написаны так, что слова стоя́т до двоеточия, а
равенства после, — и потому каждая проверена ДВАЖДЫ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/rem_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import remdivforms  # noqa: E402 — дом, объявивший деление с остатком

ИМЯ_СУДА = "rem"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"rem"})


def _судить(строка):
    return remdivforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ДЕЛЕНИЕ С ОСТАТКОМ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(remdivforms.РОДЫ)}, страниц {len(remdivforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
