#!/usr/bin/env python3
"""[ЗАЧИН ДЕЯТЕЛЯ] — слово на месте деятеля обязано быть тем, чем свод это место открывает.

    ЗАКОН, ЗАПЕРТЫЙ В ДОМЕ, ОХРАНЯЕТ ЛИШЬ ЭТОТ ДОМ.

Закон лица (М-131) в своде БЫЛ и молчал: он жил внутри `episode_court`, а тот зовёт чужую
рамку несудимой и до закона не доходит. Мир `everyday` деятелей ОБЪЯВИЛ — и порча имени
«Tom has 6 books…» → «To has 6 books…» проходила палату ИСТИНОЙ, ибо читали её суд памяти и
суд счёта, у которых слово есть украшение.

Здесь тот же закон стои́т ОТДЕЛЬНО и судит ВСЯКУЮ строку ВСЯКОГО мира, объявившего деятелей,
какой бы рамкой она ни была писана. Право берётся у двери (`tools/actors.py`) — там и покупка
показами, и её цена числом.

    СУД ЕСТЬ ЛОВЕЦ ПОРЧИ, А НЕ ПОДТВЕРЖДАТЕЛЬ ИСТИНЫ (закон соседа `corpusword_court`):
    нашёл зачин, какого свод перед этим словом не ставил, — ложь; не нашёл — молчит, и
    строка остаётся на попечении тех, кто читает её по существу.

ЦЕНА ЗАМЕРЕНА, А НЕ ПРЕДПОЛОЖЕНА: 6,4 мкс на строку мира деятелей (4698 строк `everyday` за
0,03 с), то есть около семи секунд на весь свод против 50 993 секунд набора. Мир, деятелей
не объявивший, стои́т и того меньше: суд выходит на первом же вопросе к слою. Покупка не
пересчитывается вовсе — она читается с полки, собранной `scripts/actorplace_market.py`.

ЧТО ЭТОТ СУД ПОЙМАЛ, ЧИСЛОМ (подсадка словом, 22.09): непойманных 23 → 18 самим законом и
23 → 13 вместе с тринадцатью мирами, какие он заставил объявить деятелей; пойманных
7858 → 7869; миров с дырой 13 → 10.
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import actors  # noqa: E402 — дверь лиц и рынок места лица
from actors import Слой  # noqa: E402 — деятели мира из манифеста

# ЛОВЕЦ ПОРЧИ БЕЗ ИСТИНЫ, И ОБЪЯВЛЕНО ЭТО ДВАЖДЫ — здесь и в списке `court_mutants`.
# Суд говорит ЛОЖЬ о строке, чей зачин свод перед этим словом не ставил, и МОЛЧИТ обо всех
# прочих: истинной строки не выдаёт ни одной. Читатель объявления — `scripts/court_mutants.py`,
# который иначе счёл бы молчание изъяном; проверяет же суд `scripts/word_mutants.py` — подсадкой
# СЛОВА, и она его проверила: непойманных 23 → 13.
ЛОВЕЦ_ПОРЧИ = True


def судить(строка, слой=None):
    """(судимо, истинно): зачин перед словом при лице — из купленных классов."""
    if слой is None:
        return False, False
    языки = слой.языки()
    if not языки:
        return False, False
    return (True, False) if actors.порча(строка, языки) else (False, False)


def main():
    судимо = ложных = 0
    примеры = []
    for имя, путь, языки in actors.миры_деятелей():
        if not путь.exists():
            continue
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            беды = actors.порча(строка, языки)
            if not беды:
                continue
            судимо += 1
            ложных += 1
            if len(примеры) < 5:
                зачин, слово, язык = беды[0]
                примеры.append(f"{имя}/{язык}: «{зачин} {слово}» ← {строка.strip()[:80]}")
    for п in примеры:
        print(f"  {п}")
    куплено = actors.куплено()
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ЗАЧИН ДЕЯТЕЛЯ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"слов при лице {len(куплено)} на {len({я for я, _ in куплено})} языках, "
          f"миров деятелей {len(list(actors.миры_деятелей()))}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
