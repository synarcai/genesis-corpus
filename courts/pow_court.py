#!/usr/bin/env python3
"""[СТЕПЕНЬ ЗА НУЛЁМ] — нулевой и отрицательный показатель, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`powforms`), где рамки и числа объявлены одной
таблицей. Подмена степени, доли и самого ОЖИДАНИЯ («а не −8») ловится машинально: каждая степень
строки возводится заново, а не принимается на слово.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЭТОТ СУД НУЖЕН ТАМ, ГДЕ СУД АРИФМЕТИКИ МОЛЧИТ, И ГРАНИЦА ИЗМЕРЕНА: арифметика читает свидетеля
(«2^3 = 8»), но отрицательную степень не считает вовсе — «2^-3 = 1/9» проходит у неё истиной.
Страница дома потому проверяется ДВАЖДЫ разными приборами, и вторая проверка — здесь.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/pow_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import powforms  # noqa: E402 — дом, объявивший степень за нулём

ИМЯ_СУДА = "pow"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"pow"})


def _судить(строка):
    return powforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"СТЕПЕНЬ ЗА НУЛЁМ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(powforms.РОДЫ)}, страниц {len(powforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
