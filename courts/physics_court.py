#!/usr/bin/env python3
"""[ФИЗИЧЕСКАЯ ИСТИНА] — судится и счёт, и ИМЯ ЗАКОНА, и единица.

Показ физики несёт три утверждения сразу, и все три проверяемы:
  · ОТНОШЕНИЕ величин («20 ньютонов × 3 метра = 60 джоулей»);
  · ИМЯ закона, под которым отношение записано («работа = сила × путь»);
  · ЕДИНИЦА, в которой величина измеряется.

СУД ЧИСЛА НЕДОСТАТОЧЕН, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Строка «мощность = сила ×
путь; 20 × 3 = 60» арифметически безупречна и физически ложна: имя
закона не отвечает записанному отношению. Соседняя сессия нашла тот же
род в математическом корпусе — ссылка вела на СОСЕДНЕЕ утверждение,
адрес разрешался, номер существовал, расходились только смыслы. Прибор,
проверяющий лишь то, что число сходится, такую ложь пропускает
принципиально, и потому здесь имя закона объявлено вместе с его
отношением и сверяется с ним.

ЕДИНИЦЫ ОБЪЯВЛЕНЫ ТАБЛИЦЕЙ: «скорость измеряется в метрах в секунду»
верно, «в ньютонах» — нет, и никакой счёт этого не покажет.

ЧЕГО ПРИБОР НЕ СУДИТ, НАЗВАНО: размерность произведения он не выводит
(этому нужна алгебра размерностей — отдельный род), и приближённых
законов с вещественными постоянными в слое нет вовсе, потому судить их
нечем и не о чем.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import asking  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# ИМЯ ЗАКОНА ОБЪЯВЛЕНО ВМЕСТЕ С ЕГО ОТНОШЕНИЕМ: суд сверяет их, а не
# одно только число.
ЗАКОНЫ = {
    "speed": ("distance / time", lambda a, b: a / b),
    "скорость": ("расстояние / время", lambda a, b: a / b),
    "force": ("mass × acceleration", lambda a, b: a * b),
    "сила": ("масса × ускорение", lambda a, b: a * b),
    "work": ("force × distance", lambda a, b: a * b),
    "работа": ("сила × путь", lambda a, b: a * b),
    "power": ("work / time", lambda a, b: a / b),
    "мощность": ("работа / время", lambda a, b: a / b),
    "density": ("mass / volume", lambda a, b: a / b),
    "плотность": ("масса / объём", lambda a, b: a / b),
    "voltage": ("current × resistance", lambda a, b: a * b),
    "напряжение": ("ток × сопротивление", lambda a, b: a * b),
}
ЕДИНИЦЫ = {
    "speed": "metres per second", "force": "newtons", "work": "joules",
    "power": "watts", "mass": "kilograms", "length": "metres",
    "time": "seconds", "current": "amperes", "voltage": "volts",
    "resistance": "ohms",
    "скорость": "метрах в секунду", "сила": "ньютонах",
    "работа": "джоулях", "мощность": "ваттах", "масса": "килограммах",
    "длина": "метрах", "время": "секундах", "ток": "амперах",
    "напряжение": "вольтах", "сопротивление": "омах",
}

ЗАКОН_СТРОКА = re.compile(
    r"^([\w]+) = ([^;]+); (\d+)[^\d]*?([×/])[^\d]*?(\d+)[^=]*= (\d+)")
СКОРОСТЬ_EN = re.compile(
    r"^a body covering (\d+) metres in (\d+) seconds has speed "
    r"(\d+) metres per second$")
СКОРОСТЬ_RU = re.compile(
    r"^тело, прошедшее (\d+) метр\S* за (\d+) секунд\S*, имеет скорость "
    r"(\d+) метр\S* в секунду$")
# ЗАПИСЬ ЗАКОНА ЕСТЬ ЧАСТЬ ПОКАЗА, А НЕ ЕГО ОБРАМЛЕНИЕ.
#
# Образец стоял как «… = .*?; N × N × N / 2 = N», и «.*?» ПРОГЛАТЫВАЛО
# сам закон: суд исполнял пример и не читал того, что рядом с ним
# записано. Подсадка нашла это так: «kinetic energy = mass × speed
# squared / 3; 16 × 3 × 3 / 2 = 72 joules» — закон делит на три, пример
# на два, и суд назвал строку ИСТИНОЙ, ибо пример сам по себе сходится.
#
# Это тот же закон, что уже казнил разбор арифметики: РАЗБОР,
# СОГЛАШАЮЩИЙСЯ НА ВСЁ, НЕ ЧИТАЕТ — ОН ГАДАЕТ. Здесь он принимает
# частный вид: ЗАКОН И ЕГО ПРИМЕР ЕСТЬ ОДНО УТВЕРЖДЕНИЕ, и делитель
# примера обязан быть ТЕМ ЖЕ, что назван законом. Делитель читается
# из записи, а не полагается двойкой.
КИНЕТИКА = re.compile(
    r"^(?:kinetic energy|кинетическая энергия) = "
    r"(?:mass × speed squared|масса × квадрат скорости) / (\d+); "
    r"(\d+) × (\d+) × (\d+) / (\d+) = (\d+)")
ИЗМЕРЯЕТСЯ = re.compile(
    r"^([\w]+) (?:is measured in|измеряется в) (.+?)$")
# ОТКАЗ ЕСТЬ ТАКОЕ ЖЕ УТВЕРЖДЕНИЕ, И ПРОВЕРЯЕТСЯ ТАК ЖЕ: «целого
# ответа нет» истинно ровно тогда, когда путь и вправду не делится на
# время нацело. Суд считает остаток, а не верит слову «нет».
ЦЕЛОСТЬ_СКОРОСТИ = re.compile(
    r"^(?:yes: (\d+) ÷ (\d+) = (\d+) metres per second"
    r"|no: (\d+) metres in (\d+) seconds do not give a whole speed, "
    r"(\d+) is not divisible by (\d+)"
    r"|да: (\d+) ÷ (\d+) = (\d+) метр\S* в секунду"
    r"|нет: (\d+) метр\S* за (\d+) секунд\S* не да[её]?т?ю?т? целой скорости, "
    r"(\d+) не делится на (\d+) нацело)$")


def судить(строка):
    с = строка.strip().rstrip(".")
    # ВОПРОС СУДИТСЯ СВОИМ ОТВЕТОМ: род определяется ответом, а связь
    # половин — общим домом `tools/asking.py`.
    если = asking.судить_парой(с, судить)
    if если is not None:
        return если
    m = ЦЕЛОСТЬ_СКОРОСТИ.match(с)
    if m:
        г = [int(x) for x in m.groups() if x is not None]
        if len(г) == 3:
            путь, срок, v = г
            return True, срок != 0 and путь == v * срок
        путь, срок, путь2, срок2 = г
        return True, (путь == путь2 and срок == срок2 and срок != 0
                      and путь % срок != 0)
    m = СКОРОСТЬ_EN.match(с) or СКОРОСТЬ_RU.match(с)
    if m:
        s, t, v = (int(x) for x in m.groups())
        return True, t != 0 and s == v * t
    m = КИНЕТИКА.match(с)
    if m:
        закон, a, b, c, делитель, d = (int(x) for x in m.groups())
        return True, (делитель == закон and закон != 0
                      and b == c and a * b * c == закон * d)
    m = ЗАКОН_СТРОКА.match(с)
    if m:
        имя, отношение, x, знак, y, итог = m.groups()
        если = ЗАКОНЫ.get(имя.lower())
        if если is None:
            # ИСКАЖЁННОЕ ИМЯ ПРИ ОБЪЯВЛЕННОМ ОТНОШЕНИИ ЕСТЬ ЛОЖЬ, А НЕ
            # НЕИЗВЕСТНОСТЬ. Подсадка словом: «давлениЕ = сила ÷ площадь;
            # 42 ньютона ÷ 6 квадратных метров = 7 паскалей» → «давлени =
            # …». Суд, не найдя имени в таблице, МОЛЧАЛ, а суд
            # согласования, читающий счётные формы, звал строку истиной
            # — палата выносила «истина» строке с искажённым именем
            # закона. Здесь суд знает отношение «сила ÷ площадь» как
            # отношение ДАВЛЕНИЯ; строка, несущая объявленное отношение
            # под необъявленным именем, лжёт об имени — и лжёт судимо.
            # Строка с незнакомым отношением по-прежнему не наша.
            объявленные = {о.strip() for о, _ in ЗАКОНЫ.values()}
            if отношение.strip() in объявленные:
                return True, False
            return False, True
        объявлено, действие = если
        # ИМЯ И ОТНОШЕНИЕ СВЕРЯЮТСЯ ДРУГ С ДРУГОМ — числа мало
        if отношение.strip() != объявлено:
            return True, False
        ждали = "×" if действие(6, 2) == 12 else "/"
        if знак != ждали:
            return True, False
        значение = действие(int(x), int(y))
        return True, значение == int(итог)
    m = ИЗМЕРЯЕТСЯ.match(с)
    if m:
        величина, единица = m.group(1).lower(), m.group(2).strip()
        объявлено = ЕДИНИЦЫ.get(величина)
        if объявлено is None:
            return False, True
        return True, единица == объявлено
    return False, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ФИЗИКА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ФИЗИКА ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:70]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ФИЗИКА {поза}: {ложных} ложных утверждений из {судимых} "
          f"судимых ({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
