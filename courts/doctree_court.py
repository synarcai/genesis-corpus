#!/usr/bin/env python3
"""СУД СТРУКТУРЫ: притязание о ссылке проверяется ЕЁ РАЗРЕШЕНИЕМ.

Показ говорит «в core/form.md ссылка […](../world/water.md) ведёт на
world/water.md». Суд не сверяет строку со строкой: он БЕРЁТ текст ссылки
и РАЗРЕШАЕТ его от названного места по дереву — то есть проделывает ход,
ОБРАТНЫЙ тому, каким свод эту ссылку построил. Согласие встречных ходов
и есть проверка; сверка написанного с написанным была бы пересказом.

ЧЕТЫРЕ ПРИТЯЗАНИЯ, И КАЖДОЕ СВОИМ ХОДОМ:
    ВЕДЁТ НА       — разрешение возвращает названный документ;
    ВЕДЁТ В РАЗДЕЛ — разрешение возвращает документ И якорь, а якорь
                     совпадает с приведением названного заголовка;
    НЕ ВЕДЁТ НИКУДА — разрешение возвращает НИЧЕГО, и основание отказа
                     («нет документа» / «нет раздела») отличимо: суд
                     проверяет, что отказ назван ВЕРНОЙ причиной;
    ПОРЯДОК        — «следующий» вычисляется по местам в боковике.

Отказ проверяется НАРАВНЕ с утверждением. Показ, объявляющий ссылку
битой, когда она цела, есть та же ложь, что показ, объявляющий целой
битую, — и суд, проверявший бы только первое, учил бы корпус ломать
ссылки безнаказанно.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import doctree as дт  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

П = r"([\w./-]+\.md)"
С = r"\[[^\]]*\]\(([^)\s]+)\)"

ВЕДЁТ = re.compile(
    rf"^(?:in {П} the link {С} leads to {П}"
    rf"|в {П} ссылка {С} ведёт на {П})\.$")
В_РАЗДЕЛ = re.compile(
    rf"^(?:in {П} the link {С} leads to the section «([^»]+)» of {П}"
    rf"|в {П} ссылка {С} ведёт в раздел «([^»]+)» документа {П})\.$")
ЯКОРЬ_ИЗ = re.compile(
    r"^(?:the heading «([^»]+)» becomes the anchor #([\w-]+)"
    r"|заголовок «([^»]+)» становится якорем #([\w-]+))\.$")
ОГЛАВЛЕНИЕ = re.compile(
    rf"^(?:in {П} the table of contents entry - \[([^\]]+)\]"
    r"\(#([\w-]+)\) leads to the section «([^»]+)» of the same document"
    rf"|в {П} строка оглавления - \[([^\]]+)\]\(#([\w-]+)\) ведёт в "
    r"раздел «([^»]+)» того же документа)\.$")
НЕТ_ДОКУМЕНТА = re.compile(
    rf"^(?:in {П} the link {С} leads nowhere: there is no such document"
    rf"|в {П} ссылка {С} не ведёт никуда: такого документа нет)\.$")
НЕТ_РАЗДЕЛА = re.compile(
    rf"^(?:in {П} the link {С} leads nowhere: {П} has no such section"
    rf"|в {П} ссылка {С} не ведёт никуда: в {П} нет такого раздела)\.$")
ОБЪЯВЛЯЕТ = re.compile(
    rf"^(?:the document {П} declares id ([\w-]+), title ([^,]+) and "
    r"sidebar_position (\d+)"
    rf"|документ {П} объявляет id ([\w-]+), заголовок ([^,]+) и "
    r"sidebar_position (\d+))\.$")
СЛЕДУЮЩИЙ = re.compile(
    rf"^(?:in the folder ([\w/]+) the document after {П} is {П}"
    rf"|в папке ([\w/]+) документ после {П} — это {П})\.$")
ПОСЛЕДНИЙ = re.compile(
    rf"^(?:{П} is the last document of the folder ([\w/]+)"
    rf"|{П} — последний документ папки ([\w/]+))\.$")
ВОПРОС = re.compile(
    r"^(?:what does the link .+? lead to\? "
    r"|на что ведёт ссылка .+?\? )(.+)$")


def _г(м):
    return [x for x in м.groups() if x is not None]


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    м = ВОПРОС.match(с)
    if м:
        # ВОПРОС ВЕРЕН, ЕСЛИ ВЕРЕН ЕГО ОТВЕТ И СПРОШЕНО ТО ЖЕ САМОЕ.
        ответ = м.group(1)
        судимо, истинно = судить(ответ)
        спрошено = re.search(r"\[[^\]]*\]\(([^)\s]+)\).+?([\w./-]+\.md)",
                             с)
        свой = re.search(r"\[[^\]]*\]\(([^)\s]+)\)", ответ)
        если = (спрошено and свой
                and спрошено.group(1) == свой.group(1))
        return судимо, bool(судимо and истинно and если)
    м = ВЕДЁТ.match(с)
    if м:
        откуда, ссылка, куда = _г(м)
        вышло = дт.разрешить(откуда, ссылка)
        return True, вышло is not None and вышло[0] == куда
    м = В_РАЗДЕЛ.match(с)
    if м:
        откуда, ссылка, раздел, куда = _г(м)
        вышло = дт.разрешить(откуда, ссылка)
        return True, (вышло is not None and вышло[0] == куда
                      and вышло[1] == дт.якорь(раздел))
    м = ЯКОРЬ_ИЗ.match(с)
    if м:
        заголовок, я = _г(м)
        return True, дт.якорь(заголовок) == я
    м = ОГЛАВЛЕНИЕ.match(с)
    if м:
        путь, текст, я, раздел = _г(м)
        вышло = дт.разрешить(путь, f"#{я}")
        return True, (вышло is not None and вышло[0] == путь
                      and вышло[1] == дт.якорь(раздел)
                      and текст == раздел)
    м = НЕТ_ДОКУМЕНТА.match(с)
    if м:
        откуда, ссылка = _г(м)
        путь = ссылка.split("#")[0]
        цель = дт.разрешить(откуда, путь)
        return True, цель is None
    м = НЕТ_РАЗДЕЛА.match(с)
    if м:
        откуда, ссылка, куда = _г(м)
        # ОСНОВАНИЕ ОТКАЗА ПРОВЕРЯЕТСЯ ОТДЕЛЬНО ОТ ОТКАЗА: документ
        # обязан СУЩЕСТВОВАТЬ, иначе причина названа неверно.
        путь = ссылка.split("#")[0]
        есть = дт.разрешить(откуда, путь)
        нет = дт.разрешить(откуда, ссылка)
        return True, (есть is not None and есть[0] == куда
                      and нет is None)
    м = ОБЪЯВЛЯЕТ.match(с)
    if м:
        путь, ид, заг, место = _г(м)
        если = дт.УЗЕЛ.get(путь)
        return True, (если is not None and дт.имя_файла(путь) == ид
                      and если[0] == заг.strip()
                      and str(если[1]) == место)
    м = СЛЕДУЮЩИЙ.match(с)
    if м:
        папка, путь, след = _г(м)
        свой = дт.папка(путь) or "root"
        return True, свой == папка and дт.следующий(путь) == след
    м = ПОСЛЕДНИЙ.match(с)
    if м:
        путь, папка = _г(м)
        свой = дт.папка(путь) or "root"
        return True, свой == папка and дт.следующий(путь) is None
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"СТРУКТУРА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("СТРУКТУРА ОТКАЗ: обход пуст, судить нечего")
        return 2
    беды = дт.оракул()
    if беды:
        print(f"СТРУКТУРА FAIL: дерево разошлось на встречных ходах в "
              f"{len(беды)} парах: {беды[:2]}")
        return 1
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"СТРУКТУРА {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов, дерево обратимо)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
