#!/usr/bin/env python3
"""[РУССКАЯ СЛОВЕСНАЯ ЗАДАЧА] — итог складывается заново, носитель сверяется.

Мир говорит цепью: «у пети было 8 яблок. петя отдал 3 яблока. у пети
осталось 5 яблок». Суд не сверяет итог с записанным — он складывает и
вычитает сам, и вдобавок держит то, ради чего эпизод и существует:
НОСИТЕЛЬ ОДИН НА ВСЮ ЦЕПЬ. Именительный первого действия и родительный
обоих «у …» обязаны указывать на ОДНОГО человека; цепь, где начали за
петю, а кончили за машу, есть арифметически верная и по существу
ложная задача — ровно та подмена, которую счётный суд не увидит.

ОБОРОТ ИТОГА СЛЕДУЕТ ЗА ЗНАКОМ ДЕЙСТВИЯ, И ЭТО СУДИТСЯ. «отдал» ведёт к
«осталось», «купил» — к «стало»; «отдал … стало» есть ложь о русском
языке при верной арифметике. Действия объявлены со своим знаком, а не
угаданы по виду.

СЧЁТНАЯ ФОРМА СУДИТСЯ НАРАВНЕ С ЧИСЛОМ: «5 яблок», но «2 яблока», и
форма берётся у дома русской грамматики, а не сверяется со списком.

ОТКАЗ СУДИТСЯ РАБОТОЙ. «сколько яблок было у маши? не сказано: в задаче
назван петя, а не маша» — суд требует, чтобы спрошенный и вправду НЕ
БЫЛ носителем задачи, и чтобы названный в основании был им. Отказ,
отказавший о том самом человеке, о котором речь и шла, есть самая
правдоподобная ложь: форма у него правильная.

ЧЕГО СУД НЕ ЧИТАЕТ: чужого рода. Образцы привязаны к зачину «у …
было» и к объявленным именам; неузнанная строка есть (False, False).
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import rugram  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# ТОТ ЖЕ СПИСОК ИМЁН, ЧТО В ГЕНЕРАТОРЕ, СКАЗАННЫЙ ВТОРОЙ РУКОЙ:
# (именительный, родительный, окончание прошедшего). Правка имени в
# одном доме и не в другом делает строку НЕСУДИМОЙ, а ворота записи
# несудимую строку не пропускают.
ЛИЦА = (("петя", "пети", ""), ("маша", "маши", "а"),
        ("коля", "коли", ""), ("аня", "ани", "а"),
        ("ваня", "вани", ""), ("оля", "оли", "а"))
ПО_ИМЕНИТЕЛЬНОМУ = {им: им for им, _р, _г in ЛИЦА}
ПО_РОДИТЕЛЬНОМУ = {р: им for им, р, _г in ЛИЦА}
РОД_ПРОШЕДШЕГО = {им: г for им, _р, г in ЛИЦА}

# ДЕЙСТВИЕ ОБЪЯВЛЕНО СО СВОИМ ЗНАКОМ И СВОИМ ОБОРОТОМ ИТОГА, а не
# выведено из вида слова: «отдал» и «продал» убавляют и ведут к
# «осталось», «купил» и «взял» прибавляют и ведут к «стало».
ДЕЙСТВИЯ = {"отда": ("осталось", -1), "прода": ("осталось", -1),
            "купи": ("стало", +1), "взя": ("стало", +1)}

# ВЕЩИ, О КОТОРЫХ ЭТОТ МИР ГОВОРИТ. Список тот же, что в генераторе,
# сказанный второй рукой; всякая счётная форма каждой вещи узнаётся
# обратно домом форм.
ВЕЩИ = ("яблоко", "книга", "монета", "ручка", "карта", "чашка",
        "игрушка")


def выбор(слова):
    """Образец, берущий ТОЛЬКО объявленное; длинное впереди короткого."""
    return "(?:" + "|".join(sorted((re.escape(с) for с in слова),
                                   key=len, reverse=True)) + ")"


# УЗНАВАНИЕ СТОИТ В ОБРАЗЦЕ, А НЕ В ПРОВЕРКЕ, И ЭТО ШРАМ, КУПЛЕННЫЙ
# ЗАМЕРОМ. Первая редакция брала любое слово `[а-яё]+` и отсеивала
# чужое проверкой — то есть выносила о чужом ВЕРДИКТ «ложь». Прогон по
# корпусу дал 606 ложных из 755 на честных строках трёх чужих миров
# («у маши было 2 яблока. маша получила 1 яблоко…»): суд, не владеющий
# родом, обязан МОЛЧАТЬ о нём, а не обвинять. Теперь имя, действие,
# оборот и вещь берутся альтернативами из объявленного, и чужая строка
# не совпадает вовсе.
ИМЯ_ИМ = выбор(ПО_ИМЕНИТЕЛЬНОМУ)
ИМЯ_РОД = выбор(ПО_РОДИТЕЛЬНОМУ)
ОСНОВА = выбор(ДЕЙСТВИЯ)
ОБОРОТ = выбор({о for о, _з in ДЕЙСТВИЯ.values()})
ВЕЩЬ = выбор({ф for в in ВЕЩИ for ф in rugram.СЧЁТНЫЕ[в]})
# СЧЁТ ЭТОГО МИРА НАЧИНАЕТСЯ С ДВУХ (при единице русское имя стои́т в
# винительном, какого дом не объявляет), и граница мира есть граница
# ПОДСУДНОСТИ: строка с единицей — не наш род, а не наша ложь.
Ч = r"(?:[2-9]|[1-9][0-9]+)"
С = r"[а-яё]+"


def _лицо(г, *ключи):
    """Одно ли лицо названо всеми формами; None — нет или незнакомо."""
    кто = set()
    for имя_группы, таблица in ключи:
        если = таблица.get(г[имя_группы])
        if если is None:
            return None
        кто.add(если)
    return next(iter(кто)) if len(кто) == 1 else None


def _цепь_верна(г, лицо):
    """Общее ядро цепи: действие, знак, оборот, формы и итог."""
    основа = г["основа"]
    если = ДЕЙСТВИЯ.get(основа)
    if если is None:
        return False
    оборот, знак = если
    if г["оборот"] != оборот:
        return False
    if г["род_прош"] != РОД_ПРОШЕДШЕГО[лицо]:
        return False
    вещь = г["вещь_ключ"]
    было, изм, стало = int(г["было"]), int(г["изм"]), int(г["стало"])
    # ЦЕНЗ «НЕ МЕНЬШЕ ДВУХ» СТОИТ В ОБРАЗЦЕ, А НЕ ЗДЕСЬ: он есть
    # граница МИРА, а не закон русского языка, и судить по нему
    # значило бы звать ложью чужую честную строку с единицей.
    return (стало == было + знак * изм
            and г["форма_было"] == rugram.форма(вещь, было)
            and г["форма_изм"] == rugram.форма(вещь, изм)
            and г["форма_стало"] == rugram.форма(вещь, стало))


def _ключ_вещи(г):
    """Ключ дома форм по счётной форме; None — вещь не объявлена."""
    return rugram.ПО_ФОРМЕ.get(г["форма_было"])


def _цепь(г):
    лицо = _лицо(г, ("род1", ПО_РОДИТЕЛЬНОМУ),
                 ("им", ПО_ИМЕНИТЕЛЬНОМУ), ("род2", ПО_РОДИТЕЛЬНОМУ))
    вещь = _ключ_вещи(г)
    if лицо is None or вещь is None:
        return False
    return _цепь_верна(dict(г, вещь_ключ=вещь), лицо)


def _вопрос(г):
    """Та же цепь, но итог приходит ОТВЕТОМ, и носитель в нём назван."""
    лицо = _лицо(г, ("род1", ПО_РОДИТЕЛЬНОМУ),
                 ("им", ПО_ИМЕНИТЕЛЬНОМУ), ("род2", ПО_РОДИТЕЛЬНОМУ),
                 ("род3", ПО_РОДИТЕЛЬНОМУ))
    вещь = _ключ_вещи(г)
    if лицо is None or вещь is None:
        return False
    if г["оборот"] != г["оборот2"]:
        return False
    # «сколько ЧЕГО» требует родительного множественного — третьей
    # счётной формы дома, а не формы при каком-то выдуманном числе.
    if г["род_вещи"] != rugram.СЧЁТНЫЕ[вещь][2]:
        return False
    return _цепь_верна(dict(г, вещь_ключ=вещь), лицо)


def _отказ(г):
    """РАБОТА ОТКАЗА: спрошенный и вправду НЕ носитель задачи."""
    хозяин = _лицо(г, ("род1", ПО_РОДИТЕЛЬНОМУ),
                   ("им", ПО_ИМЕНИТЕЛЬНОМУ))
    чужой_род = ПО_РОДИТЕЛЬНОМУ.get(г["род_чужой"])
    чужой_им = ПО_ИМЕНИТЕЛЬНОМУ.get(г["им_чужой"])
    вещь = _ключ_вещи(г)
    if None in (хозяин, чужой_род, чужой_им, вещь):
        return False
    было = int(г["было"])
    return (чужой_род == чужой_им and чужой_род != хозяин
            and г["род_прош"] == РОД_ПРОШЕДШЕГО[хозяин]
            and г["род_вещи"] == rugram.СЧЁТНЫЕ[вещь][2]
            and г["форма_было"] == rugram.форма(вещь, было))


ОБРАЗЦЫ = (
    (rf"^у (?P<род1>{ИМЯ_РОД}) было (?P<было>{Ч}) (?P<форма_было>{ВЕЩЬ})\. "
     rf"(?P<им>{ИМЯ_ИМ}) (?P<основа>{ОСНОВА})л(?P<род_прош>а?) "
     rf"(?P<изм>{Ч}) (?P<форма_изм>{ВЕЩЬ})\. у (?P<род2>{ИМЯ_РОД}) "
     rf"(?P<оборот>{ОБОРОТ}) (?P<стало>{Ч}) (?P<форма_стало>{ВЕЩЬ})\.$",
     _цепь),
    (rf"^у (?P<род1>{ИМЯ_РОД}) было (?P<было>{Ч}) (?P<форма_было>{ВЕЩЬ})\. "
     rf"(?P<им>{ИМЯ_ИМ}) (?P<основа>{ОСНОВА})л(?P<род_прош>а?) "
     rf"(?P<изм>{Ч}) (?P<форма_изм>{ВЕЩЬ})\. сколько "
     rf"(?P<род_вещи>{С}) (?P<оборот>{ОБОРОТ}) у (?P<род2>{ИМЯ_РОД})\? "
     rf"у (?P<род3>{ИМЯ_РОД}) (?P<оборот2>{ОБОРОТ}) (?P<стало>{Ч}) "
     rf"(?P<форма_стало>{ВЕЩЬ})\.$", _вопрос),
    (rf"^у (?P<род1>{ИМЯ_РОД}) было (?P<было>{Ч}) (?P<форма_было>{ВЕЩЬ})\. "
     rf"сколько (?P<род_вещи>{С}) было у (?P<род_чужой>{ИМЯ_РОД})\? не "
     rf"сказано: в задаче назван(?P<род_прош>а?) (?P<им>{ИМЯ_ИМ}), а не "
     rf"(?P<им_чужой>{ИМЯ_ИМ})\.$", _отказ),
)
ПРАВИЛА = tuple((re.compile(о), п) for о, п in ОБРАЗЦЫ)


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    for образец, проверить in ПРАВИЛА:
        м = образец.match(с)
        if м:
            return True, bool(проверить(м.groupdict()))
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"РУССКАЯ ЗАДАЧА ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("РУССКАЯ ЗАДАЧА ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"РУССКАЯ ЗАДАЧА {поза}: {ложных} ложных из {судимых} "
          f"судимых ({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
