#!/usr/bin/env python3
"""[СУД ЛОЖНОЙ ДИЛЕММЫ] — выходы пересчитаны по объявлению; МИР ЗАМКНУТ.

Страница мира (`tools/dilemma.py`) есть выбор «или то, или это» и приговор ему: дилемма
честная либо ложная, и если ложная — чем именно.

    «ИЛИ ТО, ИЛИ ЭТО» ЕСТЬ УТВЕРЖДЕНИЕ О МИРЕ, А НЕ О ЛОГИКЕ. Связка «или» верна всегда;
    неверным бывает СПИСОК, к какому она приставлена. И проверяется это не рассуждением, а
    ПЕРЕСЧЁТОМ: сколько выходов объявлено и сколько названо.

Граница прибора объявлена прямо:

    СУД НЕ РЕШАЕТ, ПОЛОН ЛИ СПИСОК ВООБЩЕ, — этого не решить счётом. Он сверяет названное с
    ОБЪЯВЛЕННЫМ набором, и полнота здесь есть объявление, а не истина о мире.

Три строгости: названные два обязаны быть ПЕРВЫМИ ДВУМЯ набора (иначе «пропущенный» назывался
бы из уже названных); число выходов обязано сойтись; пропущенный обязан стоять в наборе и не
быть названным. И род «середина» — о шкале, где пропущен не выход, а ЦЕЛЫЙ РЯД.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import dilemma as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"dilemma"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_dilemma.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_dilemma.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_dilemma.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ЛОЖНАЯ ДИЛЕММА {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
