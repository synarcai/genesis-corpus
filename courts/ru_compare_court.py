#!/usr/bin/env python3
"""[РУССКОЕ СРАВНЕНИЕ] — кратное делится заново, разностное вычитается.

Мир говорит на одной паре чисел две вещи: «12 больше 4 в 3 раза» и «12
больше 4 на 8». Суд не сверяет ответы с записанными — он делит и
вычитает сам, и порознь: кратный показ обязан сойтись УМНОЖЕНИЕМ,
разностный — ВЫЧИТАНИЕМ, а показ, где обе рамки стоят рядом, обязан
сойтись обеими сразу. Подмена одной меры другою — «12 больше 4 на 3
рубля» — ломается ровно там, где её и путают.

СЧЁТНАЯ ФОРМА СУДИТСЯ НАРАВНЕ С ЧИСЛОМ. «в 3 раза», но «в 5 раз»; «на
8 рублей», но «на 21 рубль». Форма берётся у дома русской грамматики
(`rugram.форма`), а не сверяется со списком: верное число при неверной
форме есть та же ложь, только тише.

ОТКАЗ СУДИТСЯ РАБОТОЙ. «во сколько раз 10 больше 4? нет целого
ответа: 10 = 2 × 4 + 2, остаток 2» — суд делит с остатком заново и
требует, чтобы остаток и вправду был не нулевым. Отказ, отказавший
напрасно, учит молчать там, где ответ был, и форма у него правильная.

ЧЕГО СУД НЕ ЧИТАЕТ: чужого рода. Образцы привязаны к зачинам «во
сколько раз», «на сколько» и к объявленным именам вещей; неузнанная
строка есть (False, False).
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import rugram  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# ЕДИНИЦА ЦЕНЫ ОБЪЯВЛЕНА, А НЕ УГАДАНА ПО ФОРМЕ: «рублей» есть счётная
# форма, и узнаётся она обратно домом форм, как всякая другая.
ДЕНЬГИ = "рубль"

С = r"[а-яё]+"
Ч = r"\d+"


def _кратно(б, м, к, форма):
    """Кратность верна, и слово при ней — своё."""
    return (м >= 1 and к >= 2 and б == к * м
            and форма == rugram.форма("раз", к))


def _кратное(г):
    б, м, к = int(г["б"]), int(г["м"]), int(г["к"])
    return (_кратно(б, м, к, г["форма"])
            and int(г["б2"]) == б and int(г["к2"]) == к
            and int(г["м2"]) == м)


def _разностное(г):
    б, м, р = int(г["б"]), int(г["м"]), int(г["р"])
    return (б > м and р == б - м and int(г["б2"]) == б
            and int(г["м2"]) == м and int(г["р2"]) == р)


def _рядом(г):
    """ОБЕ МЕРЫ РАЗОМ: показ утверждает две вещи и отвечает за обе."""
    б, м, к, р = (int(г["б"]), int(г["м"]), int(г["к"]), int(г["р"]))
    return _кратно(б, м, к, г["форма"]) and р == б - м


def _цена(г):
    """Та же двойня при вещах: имя дорогой повторено, дешёвая иная."""
    if г["в1"] != г["в3"] or г["в1"] == г["в2"]:
        return False
    if г["в1"] not in rugram.СЧЁТНЫЕ or г["в2"] not in rugram.СЧЁТНЫЕ:
        return False
    б, м, к, р = (int(г["б"]), int(г["м"]), int(г["к"]), int(г["р"]))
    return (_кратно(б, м, к, г["фк"]) and р == б - м
            and г["фб"] == rugram.форма(ДЕНЬГИ, б)
            and г["фм"] == rugram.форма(ДЕНЬГИ, м)
            and г["фр"] == rugram.форма(ДЕНЬГИ, р))


def _отказ(г):
    """РАБОТА ОТКАЗА: деление и вправду не целое, и остаток тот самый."""
    б, м = int(г["б"]), int(г["м"])
    ч, о, р = int(г["ч"]), int(г["о"]), int(г["р"])
    return (м >= 1 and б > м and б % м != 0
            and б == ч * м + о and о == б % м and о > 0
            and int(г["б2"]) == б and int(г["м2"]) == м
            and int(г["о2"]) == о and int(г["б3"]) == б
            and int(г["м3"]) == м and р == б - м)


ОБРАЗЦЫ = (
    (rf"^во сколько раз (?P<б>{Ч}) больше (?P<м>{Ч})\? в (?P<к>{Ч}) "
     rf"(?P<форма>{С}): (?P<б2>{Ч}) = (?P<к2>{Ч}) × (?P<м2>{Ч})\.$",
     _кратное),
    (rf"^на сколько (?P<б>{Ч}) больше (?P<м>{Ч})\? на (?P<р>{Ч}): "
     rf"(?P<б2>{Ч}) − (?P<м2>{Ч}) = (?P<р2>{Ч})\.$", _разностное),
    (rf"^(?P<б>{Ч}) больше (?P<м>{Ч}) в (?P<к>{Ч}) (?P<форма>{С}) и на "
     rf"(?P<р>{Ч}): во сколько раз — это деление, на сколько — это "
     rf"вычитание\.$", _рядом),
    (rf"^(?P<в1>{С}) стоит (?P<б>{Ч}) (?P<фб>{С}), (?P<в2>{С}) стоит "
     rf"(?P<м>{Ч}) (?P<фм>{С}): (?P<в3>{С}) дороже в (?P<к>{Ч}) "
     rf"(?P<фк>{С}) и на (?P<р>{Ч}) (?P<фр>{С})\.$", _цена),
    (rf"^во сколько раз (?P<б>{Ч}) больше (?P<м>{Ч})\? нет целого "
     rf"ответа: (?P<б2>{Ч}) = (?P<ч>{Ч}) × (?P<м2>{Ч}) \+ (?P<о>{Ч}), "
     rf"остаток (?P<о2>{Ч})\. на сколько (?P<б3>{Ч}) больше "
     rf"(?P<м3>{Ч})\? на (?P<р>{Ч})\.$", _отказ),
)
ПРАВИЛА = tuple((re.compile(о), п) for о, п in ОБРАЗЦЫ)


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    for образец, проверить in ПРАВИЛА:
        м = образец.match(с)
        if м:
            return True, bool(проверить(м.groupdict()))
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"РУССКОЕ СРАВНЕНИЕ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("РУССКОЕ СРАВНЕНИЕ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"РУССКОЕ СРАВНЕНИЕ {поза}: {ложных} ложных из {судимых} "
          f"судимых ({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
