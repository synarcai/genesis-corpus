#!/usr/bin/env python3
"""[ЗАКОН ЭЛИЗИИ] — согласие страницы с законом дома языка, пересчитанное судом.

ИМЯ ВЗЯТО НЕ ТО, ЧТО ПРОСИЛОСЬ, И ЭТО НАРОЧНО. Голос «ЭЛИЗИЯ» уже носит прибор
`scripts/elision.py` — он ищет в своде НЕСОКРАЩЁННОЕ служебное слово, то есть ЛОВИТ
нарушение. Этот суд делает иное: он сверяет страницу, которая закон ПОКАЗЫВАЕТ. Два
голоса под одним именем читались бы как один, и вторая работа пропала бы молча
(`scripts/court_voice.py` стережёт ровно это).

Суд не знает французского и не должен знать. Он берёт всякий французский кусок страницы,
РАЗВОРАЧИВАЕТ его тем же законом (`frgram.развернуть`) и сличает с тем, что даёт `frgram.элизия`
над развёрнутым. Сокращено там, где закон сокращает; цело там, где нет.

    СУД, СВЕРЯЮЩИЙ ФОРМУ С ЗАКОНОМ ДОМА ЯЗЫКА, СИЛЁН РОВНО ТЕМ, ЧТО САМ ЯЗЫКА НЕ ЗНАЕТ.

ПОЧЕМУ СУДЯТСЯ ЛИШЬ КУСКИ В КАВЫЧКАХ. Страница говорит ПО-РУССКИ и ПО-АНГЛИЙСКИ о французском;
кавычки суть граница, какою дом отделяет показываемое от говоримого. Слагаемые же («je +
ouvre») стоя́т без кавычек нарочно: дом не пишет несокращённой формы как строки — он пишет её
как СЛАГАЕМОЕ, и потому суду нечего в ней ловить.

    python3 courts/elision_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import elisionforms  # noqa: E402 — дом, показывающий закон элизии

ИМЯ_СУДА = "elision"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"elision"})


def _судить(строка):
    return elisionforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ЗАКОН ЭЛИЗИИ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(elisionforms.РОДЫ)}, страниц {len(elisionforms.ПОКАЗЫ)}, "
          f"слов с немым h {len(elisionforms.frgram.НЕМОЕ_H)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
