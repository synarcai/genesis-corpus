#!/usr/bin/env python3
"""[ОБЩАЯ МЕРА] — наибольший общий делитель и наименьшее общее кратное, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`measureforms`), где три таблицы пар
объявлены порознь — общие, делящие и взаимно простые. Всякая цепь равенств страницы
пересчитывается звено за звеном, и деление с остатком проверяется целиком, включая то,
что остаток МЕНЬШЕ делителя и не равен нулю.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: обе стороны обеих ловушек обязаны
быть показаны, и таблицы обязаны быть тем, чем названы, — пара, попавшая из взаимно
простых в общие, показала бы ловушку не ту.

    python3 courts/measure_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import measureforms  # noqa: E402 — дом, объявивший законы общей меры

ИМЯ_СУДА = "measure"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"measure"})


def _судить(строка):
    return measureforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ОБЩАЯ МЕРА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(measureforms.РОДЫ)}, страниц {len(measureforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
