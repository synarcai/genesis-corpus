#!/usr/bin/env python3
"""[СОСТАВ СЛОВА] — «talo + ssa = talossa» проверяется СКЛЕЙКОЙ, а не узнаванием.

    ЗНАК «+» ЕСТЬ СЛОЖЕНИЕ ТАМ, ГДЕ ПОКАЗЫ ДАЮТ СУММУ, И СОСТАВ ТАМ, ГДЕ РЕЗУЛЬТАТ РАВЕН
    СКЛЕЙКЕ ЧАСТЕЙ. Тело оператора не объявляется словом, а покупается показами.

Суд читает страницы дома состава слова и проверяет их счётом письма: склейка частей обязана
дать слово в точности. «talo + ssa = talosta» — ложь, и суд зовёт её ложью, не спрашивая ни
у какого словаря.

ГРАНИЦА ОБЪЯВЛЕНА, ЧТОБЫ СУД НЕ ВЗЯЛ ЧУЖОГО. Части здесь суть БУКВЫ, а не цифры: «5 + 3 = 8»
есть арифметика и судится своим судом. Образец требует небуквенно-нецифровых частей и потому
не притязает на счёт.

    СУД, ЧИТАЮЩИЙ «A + B = C» БЕЗ РАЗБОРА, ЧТО ТАКОЕ A, ОТНЯЛ БЫ У АРИФМЕТИКИ ЕЁ СТРАНИЦЫ
    И СУДИЛ БЫ ИХ ЗАКОНОМ СКЛЕЙКИ: «5 + 3 = 53».
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ИМЯ_СУДА = "wordparts"

# ЧАСТЬ ЕСТЬ БУКВЫ, НЕ ЦИФРЫ — но НАЧИНАТЬСЯ она может не с буквы, и это куплено отказом
# (07.09, ворота записи: 952 несудимых страницы при нуле ложных).
#
#     ПЕРСИДСКОЕ «‌ها» НАЧИНАЕТСЯ С НЕВИДИМОГО ЗНАКА — U+200C, разрывателя связи, — а
#     индонезийское удвоение «-buku» с дефиса. Образец, требовавший буквы первым знаком,
#     не читал их вовсе и оставил девятьсот пятьдесят две честные страницы без судьи.
#
#     ГРАНИЦА ЧАСТИ ЕСТЬ ГРАНИЦА ПИСЬМА, А НЕ ГРАНИЦА ЛАТИНИЦЫ. Всё, что письмо клеит внутри
#     слова, — буква, дефис, разрыватель связи, — здесь часть; пробел и цифра — нет.
# ЗНАК СЛОВА ОБЪЯВЛЕН ОТРИЦАНИЕМ, А НЕ ПЕРЕЧНЕМ (07.09, куплено дважды отказом ворот).
#
# Первый образец требовал первым знаком БУКВУ — и не прочёл персидского «‌ها», начинающегося
# с невидимого разрывателя связи U+200C, и индонезийского «-buku» с дефиса: 952 честные
# страницы остались без судьи. Второй допустил шов в начале — и не прочёл тамильского
# «படி», ибо `\w` не берёт СОЕДИНИТЕЛЬНЫХ ЗНАКОВ (Mn, Mc), из которых тамильское письмо
# состои́т наравне с буквами: ещё 399 страниц.
#
#     ГРАНИЦА СЛОВА ЕСТЬ ГРАНИЦА ПИСЬМА, А НЕ ГРАНИЦА ЛАТИНИЦЫ. Перечислять, ЧТО есть буква,
#     значит перечислять письменности мира и ошибиться на следующей; сказать, что слово есть
#     всё, кроме пробела, цифры и знаков этой самой страницы, — значит объявить границу один
#     раз и для всех.
ЗНАК = r"[^\s\d+=?.,;:!—«»()]"
СЛОВО = rf"({ЗНАК}+)"
ЧАСТЬ = СЛОВО
СКЛЕЙКА = re.compile(rf"^{СЛОВО} \+ {ЧАСТЬ} = {СЛОВО}$")
ВОПРОС_EN = re.compile(rf"^what is {СЛОВО} \+ {ЧАСТЬ}\? {СЛОВО} \+ {ЧАСТЬ} = {СЛОВО}$")
ВОПРОС_RU = re.compile(rf"^сколько будет {СЛОВО} \+ {ЧАСТЬ}\? {СЛОВО} \+ {ЧАСТЬ} = {СЛОВО}$")
МОСТ_EN = re.compile(rf"^{СЛОВО} is {СЛОВО} with the ending -{ЧАСТЬ}$")
МОСТ_RU = re.compile(rf"^{СЛОВО} — это {СЛОВО} с окончанием -{ЧАСТЬ}$")
СОСТАВ_EN = re.compile(rf"^what is {СЛОВО} made of\? {СЛОВО} is {СЛОВО} "
                       rf"with the ending -{ЧАСТЬ}$")
СОСТАВ_RU = re.compile(rf"^из чего состои́т {СЛОВО}\? {СЛОВО} — это {СЛОВО} "
                       rf"с окончанием -{ЧАСТЬ}$")


def судить(строка, *_):
    с = строка.strip().rstrip(".")
    m = СКЛЕЙКА.match(с)
    if m:
        a, b, c = m.groups()
        return True, a + b == c
    for обр in (ВОПРОС_EN, ВОПРОС_RU):
        m = обр.match(с)
        if m:
            a, b, a2, b2, c = m.groups()
            return True, (a, b) == (a2, b2) and a + b == c
    for обр in (МОСТ_EN, МОСТ_RU):
        m = обр.match(с)
        if m:
            c, a, b = m.groups()
            return True, a + b == c
    for обр in (СОСТАВ_EN, СОСТАВ_RU):
        m = обр.match(с)
        if m:
            c0, c, a, b = m.groups()
            return True, c0 == c and a + b == c
    return False, True


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.name}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"СОСТАВ СЛОВА {поза}: {ложных} ложных склеек из {судимо} судимых (рубеж 0)")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
