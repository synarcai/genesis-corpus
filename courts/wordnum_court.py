#!/usr/bin/env python3
"""[ЧИСЛО СЛОВОМ] — история, писанная словами, и выкладка, писанная цифрами; МИР ЗАМКНУТ.

Страница этого дома учит РАВЕНСТВУ ДВУХ ПИСЕМ: «у Оли было пятнадцать монет… 15 − 3 = 12».
Читатель, знающий число только цифрой, её не пройдёт — и до сего дня свод не давал ему ни
одной такой страницы: строк с количеством, писанным словом, было НОЛЬ на 471 605.

СУД ТРЕБУЕТ ТРЁХ ВЕЩЕЙ, И ВСЯКАЯ ПРОВЕРЯЕМА БЕЗ НАБОРА:

    ИСТОРИЯ БЕЗ ЕДИНОЙ ЦИФРЫ — иначе это страница дома действий, и судить её здесь значило
        бы брать чужое;
    ЧИСЛА, НАЗВАННЫЕ СЛОВАМИ, СУТЬ В ТОЧНОСТИ ЧИСЛА ВЫКЛАДКИ и в том же порядке — слово,
        говорящее одно, и цифра, говорящая другое, суть ложь этого дома;
    ВЫКЛАДКА СХОДИТСЯ — равенство пересчитывается, а не принимается на слово.

ЯЗЫК СТРАНИЦЫ НЕ УГАДЫВАЕТСЯ ПЕРВЫМ СОВПАВШИМ СЛОВОМ: числительные языков пересекаются
(«six» — и английское, и французское), и суд спрашивает ВСЕ девять, признавая страницу
ложью лишь тогда, когда своей её не признал никто.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import wordnum as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"wordnum"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_wordnum.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_wordnum.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_wordnum.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ЧИСЛО СЛОВОМ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
