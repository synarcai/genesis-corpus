#!/usr/bin/env python3
"""[ЗНАКОВОЕ СЛОЖЕНИЕ] — сумма и разность со знаком, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`signaddforms`), где рамки и числа объявлены
одной таблицей. Подмена итога, знака и самой СКОБКИ ловится машинально: всякая сумма и всякая разность
строки пересчитываются СО ЗНАКОМ, а не принимаются на слово.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

СКОБКА ЕСТЬ ЧАСТЬ ЧИСЛА. «5 − (−3) = 8» и «5 − 3 = 8» разнятся ровно скобкой, и первое истинно,
второе ложно; образец, скобку теряющий, зовёт ложь истиной.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/signadd_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import signaddforms  # noqa: E402 — дом, объявивший знаковое сложение

ИМЯ_СУДА = "signadd"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"signadd"})


def _судить(строка):
    return signaddforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ЗНАКОВОЕ СЛОЖЕНИЕ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(signaddforms.РОДЫ)}, страниц {len(signaddforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
