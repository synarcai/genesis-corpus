#!/usr/bin/env python3
"""[СУД СРЕДНЕГО И РАЗБРОСА] — оба числа пересчитаны, основание показа проверено; МИР ЗАМКНУТ.

Страница мира (`tools/spread.py`) ставит рядом два числа о ряде — среднее и разброс — и
показывает, что первое теряет второе. Суд пересчитывает оба и проверяет САМО ОСНОВАНИЕ
показа: «среднее одно» при разных средних есть ложь, даже когда оба числа посчитаны верно.

    СРЕДНЕЕ ЕСТЬ ОДНО ЧИСЛО О МНОГИХ, И ОНО ТЕРЯЕТ ИХ РАЗЛИЧИЯ. Два ряда с ОДНИМ средним
    могут расходиться как угодно широко; и самое неприятное — среднее бывает числом, какого
    нет НИ У КОГО: «среднее 4» при ряде 1, 1, 10 верно и не описывает никого.

    ОБА ЧИСЛА НАЗВАНЫ, И ОБА ПРОВЕРЯЕМЫ. Дом не говорит «среднее обманывает» — это было бы
    мнение, и суду его не проверить. Он ставит рядом два пересчитываемых числа, и различие
    видно само.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import spread as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"spread"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_spread.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_spread.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_spread.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"СРЕДНЕЕ И РАЗБРОС {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
