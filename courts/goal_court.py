#!/usr/bin/env python3
"""[СУД ЦЕЛИ] — цель, сказанная речью, запечатана наблюдением; МИР ЗАМКНУТ.

Страница мира цели (`tools/goalturn.py`) есть целый ход: приказ пользователя с числом цели,
ответ органа и наблюдение леджера — «было столько, стало столько». Суд ПЕРЕСЧИТЫВАЕТ
сравнение сам: «доведи угол до 30» при угле 0 требует хода, при угле 30 — не требует;
«доведи мощность хотя бы до 40» при мощности 55 держится и без хода; «держи температуру не
выше 30» на датчике, объявленном НЕСТАВИМЫМ, кончается отказом по имени.

ЧЕТЫРЕ ШВА, И КАЖДЫЙ ЗАПЕЧАТАН ЧИСЛОМ:

    ход             — стало есть цель, и до хода цель НЕ держалась;
    отказ словом    — мир не двинут («было 0, стало 0»), и предлагать было что;
    держится        — мир не двинут, и цель держалась ДО просьбы;
    только чтение   — мир не двинут, и леджер объявлен нествимым.

    ОТКАЗ, СДВИНУВШИЙ МИР, ЕСТЬ ЛОЖЬ, ВИДНАЯ В ЧИСЛАХ, А НЕ В ТОНЕ. Оттого наблюдение стои́т
    на КАЖДОЙ странице — и на той, где ничего не произошло, тоже.

СУД ПЕРЕСЧИТЫВАЕТ, А НЕ СВЕРЯЕТ СО СТРОИТЕЛЕМ: он читает ОБЪЯВЛЕНИЕ дома (`РЕЧЬ`,
`ЛЕДЖЕРЫ`), разбирает страницу образцами из него и считает сравнение заново. Мера, зовущая
строителя, зеленеет от совпадения с самой собою.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import goalturn as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"goal"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    # ПРЕДСТАВЛЕННОЕ «НЕТ»: отказ сдвинул мир; ход не довёл до цели; «держится» там, где не
    # держится; ставимый леджер назван читаемым; приказ об одном, отчёт о другом; наблюдение
    # само с собою не сошлось; ход при уже достигнутой цели; то же по-немецки; вопрос
    # отвечен чужим леджером.

    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО (14.09). Подсадка бывает
    # СУДИМА И ИСТИННА — тогда лгал сам список: строка похожа на ложь, а есть правда.
    # Бывает и НЕСУДИМА — тогда она выпала из рамки дома, и прибор, считающий её просто
    # «непойманной», молчит о том, что перестал её читать вовсе. Суд скобок так и потерял
    # четыре подсадки из семи, когда рамка вопроса переменилась.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_goal.txt"]
    if not пути:
        свой = pathlib.Path(__file__).resolve().parents[1] / "datasets" / "genesis_goal.txt"
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_goal.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ЦЕЛЬ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
