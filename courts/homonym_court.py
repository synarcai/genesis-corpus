#!/usr/bin/env python3
"""[СУД ОДНОГО СЛОВА В ДВУХ СМЫСЛАХ] — принадлежность рядам пересчитана; МИР ЗАМКНУТ.

Страница мира (`tools/homonym.py`) есть слово и утверждение о том, в скольких объявленных
рядах оно стои́т, либо ряд соседей и вопрос, какой это ряд.

    ОДНО СЛОВО В ДВУХ СМЫСЛАХ РАЗЛИЧАЕТСЯ НЕ СЛОВОМ, А ОКРУЖЕНИЕМ.

И граница самого прибора, объявленная вслух:

    СУД НЕ ПОНИМАЕТ СМЫСЛА И НЕ БЕРЁТСЯ. Он считает ПРИНАДЛЕЖНОСТЬ ОБЪЯВЛЕННЫМ РЯДАМ:
    «коса» объявлена и в орудиях, и в причёсках, «топор» — только в орудиях. Всё проверяемо
    счётом, и ни одна страница не просит от прибора понимания.

Две строгости сверх ответа: ДВА РЯДА ОБЯЗАНЫ БЫТЬ ИМЕННО ТЕМИ И ИМЕННО ВСЕМИ — назвать два
из четырёх значит умолчать о двух; и СОСЕДИ ОБЯЗАНЫ БЫТЬ ИЗ НАЗВАННОГО РЯДА И САМИ
ОДНОЗНАЧНЫ, иначе решать нечем и у вопроса два ответа.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import homonym as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"homonym"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_homonym.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_homonym.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_homonym.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ОДНО СЛОВО В ДВУХ СМЫСЛАХ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
