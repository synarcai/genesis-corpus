#!/usr/bin/env python3
"""[СУД ВЕРИФИКАЦИИ] — вердикт согласен с проверкой, или страница лжёт; МИР ЗАМКНУТ.

Показ мира верификации (tools/verifyforms.py) есть одна из шести рамок: проверка сошлась
(«вердикт: верно»), проверка не сошлась и назвала верное число («ложно, верно 120»),
проверка была о ДРУГОМ действии («не проверено» — прибор отказывается подтверждать даже
истинное утверждение, потому что мерил не то), чётность подтверждена тождеством, чётность
опровергнута остатком, и вопрос о том, КАКОЕ из двух утверждений даёт названное число.

Суд читает каждую строку рамками дома и пересчитывает КАЖДОЕ равенство страницы: сумма,
разность, тождество чётности с остатком и без. Согласие вердикта с проверкой есть предмет
суда: «верно» при несошедшейся проверке, «ложно» при верной цитате, исправление неверным
числом, «не проверено» при совпадающей проверке и указание на неверное утверждение — всё
это ложь страницы, а не молчание. Строка, не читаемая ни одной рамкой, есть ложь замкнутого
мира.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import verifyforms as F  # noqa: E402
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира

ЗАМКНУТЫЕ_МИРЫ = frozenset({"verifyforms"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    # ПРЕДСТАВЛЕННОЕ «НЕТ» (М-106): вердикт «верно» при неверной проверке; вердикт «ложно» при
    # верной цитате; исправление неверным числом; «не проверено» при совпадающей проверке;
    # чётность, проверенная неверным тождеством; названо утверждение, которого вопрос не просил;
    # нечётное, объявленное чётным без остатка.
    подсадки = (
        "утверждение: 67 + 53 = 120. проверка: 67 + 53 = 121. вердикт: верно.",
        "правда ли, что 67 + 53 = 120? нет: 67 + 53 = 120. вердикт: ложно, верно 120.",
        "правда ли, что 67 + 53 = 121? нет: 67 + 53 = 120. вердикт: ложно, верно 122.",
        "claim: 67 + 53 = 120. the check is about something else: 67 − 53 = 15. verdict: unverified: the check is about another act.",
        "утверждение: 52 чётно. проверка: 52 = 27 × 2, остатка нет. вердикт: верно.",
        "какое из двух даёт 120: 67 + 53 или 67 − 53? второе: 67 − 53 = 14.",
        "is it true that 53 is even? no: 53 = 27 × 2 + 1, the remainder is 1. verdict: false.",
    )
    пойманы = sum(1 for п in подсадки if _судить(п) == (True, False))
    if пойманы != len(подсадки):
        for п in подсадки:
            print(f"  ПОДСАДКА {_судить(п)}: {п[:110]}")
        print(f"ВЕРИФИКАЦИЯ FAIL: подсадок поймано {пойманы} из {len(подсадки)}")
        return 1
    итог = collections.Counter(); примеры = []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_verifyforms.txt"]
    if not пути:  # мира ещё нет в манифесте — суд читает свой файл по имени и говорит об этом
        свой = pathlib.Path(__file__).resolve().parents[1] / "datasets" / "genesis_verifyforms.txt"
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_verifyforms.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:120]}")
    поза = "PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0 else "FAIL"
    print(f"ВЕРИФИКАЦИЯ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
