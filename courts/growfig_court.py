#!/usr/bin/env python3
"""[РОСТ ФИГУРЫ] — линейный, квадратичный и кубический рост, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`growfigforms`), где пары прямоугольников
объявлены двумя таблицами — с одним периметром и с одной площадью, — а наибольшая площадь при
данном полупериметре не объявлена, а ПЕРЕСЧИТАНА перебором всех целых сторон. Всякая запись
страницы считается разбором свода (`arithread`).

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: у равнопериметрной пары площади обязаны
РАЗЛИЧАТЬСЯ, а у равноплощадной — периметры (иначе ловушки нет вовсе); перебор обязан быть
полон; и наибольшую площадь обязан давать КВАДРАТ — это проверяется, а не заявляется.

    python3 courts/growfig_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import growfigforms  # noqa: E402 — дом, объявивший множитель размерности

ИМЯ_СУДА = "growfig"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"growfig"})


def _судить(строка):
    return growfigforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"КВАДРАТНЫЕ ЕДИНИЦЫ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(growfigforms.РОДЫ)}, страниц {len(growfigforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
