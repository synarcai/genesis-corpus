#!/usr/bin/env python3
"""[РАССТОЯНИЕ] — три закона расстояния, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`distforms`), где пифагоровы тройки
объявлены одной таблицей. Подмена ЛЮБОГО числа ловится машинально — квадраты катетов и
гипотенузы, сумма путей, разность соседних точек и сравнение «больше» пересчитываются порознь.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

КВАДРАТ ЧИТАЕТСЯ КАК КВАДРАТ, А НЕ КАК ЧИСЛО РЯДОМ СО ЗНАКОМ: «3² + 4² = 5²» проверяется
возведением, и подмена «5²» на «6²» не пройдёт, хотя строка осталась бы похожей.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним
словом, суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/dist_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import distforms  # noqa: E402 — дом, объявивший законы расстояния

ИМЯ_СУДА = "dist"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"dist"})


def _судить(строка):
    return distforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"РАССТОЯНИЕ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(distforms.РОДЫ)}, страниц {len(distforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
