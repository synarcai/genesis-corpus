#!/usr/bin/env python3
"""[СУД НЕСВОДИМЫХ МЕР] — меры сведены заново по объявленным ступеням; МИР ЗАМКНУТ.

Страница мира (`tools/unitmix.py`) есть две величины и либо их сумма, либо отказ её считать.
Суд берёт ступени мер из объявления, считает множитель ДЕЛЕНИЕМ и требует, чтобы названное
на странице сошлось. Мера вне объявленных делает запись не нашей.

    ЧИСЛО БЕЗ МЕРЫ НЕ ЕСТЬ ВЕЛИЧИНА. «30» само по себе не значит ничего: 30 см и 30 м —
    разные вещи, и вторая больше первой в сто раз.

    СЛОЖИТЬ МОЖНО ЛИШЬ ОДНОРОДНОЕ, И ЭТО НЕ ПРАВИЛО ЗАПИСИ, А СВОЙСТВО МИРА. Между длиной и
    массой нет множителя, каким одно превратилось бы в другое, — и потому отказ здесь не
    запрет, а следствие.

Суд строг и к самому отказу: «сложить нечем» о двух мерах ОДНОГО рода есть ложь, и «мерит
массу» о метре — тоже. Отказ обязан назвать, ЧТО ЧЕМ меряет каждая мера, и назвать верно.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import unitmix as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"unitmix"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_unitmix.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_unitmix.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_unitmix.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"НЕСВОДИМЫЕ МЕРЫ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
