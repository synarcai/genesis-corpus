#!/usr/bin/env python3
"""[ПРАВИЛО ЯЗЫКА] — форма, утверждённая ДВАЖДЫ, судит сама себя.

Замысел verum-6c, и он снимает вопрос, который я не мог решить: движок
пакетов судит СТРОЕНИЕ и не знает, верна ли форма «hablas». Девять его
полей могут быть зелены при пакете, полном ложных форм — как теорема
`c == Red || c != Red` проходит на сломанной кодировке.

ЧЕТВЁРТЫЙ ХОД: ФОРМА ПРОВЕРЯЕМА БЕЗ НОСИТЕЛЯ РОВНО ТОГДА, КОГДА ПАКЕТ
УТВЕРЖДАЕТ ЕЁ ДВАЖДЫ, НЕЗАВИСИМЫМИ ПУТЯМИ:

    клеткой таблицы:     hablar / s2 → «hablas»
    выводом из правила:  основа habl- + окончание s2 «-as»

Правило и таблица — независимые высказывания об одном факте. Подмена
«hablas» на «hablo» рушится о правило: не потому, что суд знает
испанский, а потому что ложь пришлось бы солгать СОГЛАСОВАННО ДВАЖДЫ, а
ошибочный пакет почти никогда этого не делает.

ВЫИГРЫШ: носитель нужен ПРАВИЛАМ (десятки на язык), а не каждой форме
(тысячи). Доверяемое основание падает на два порядка.

ГРАНИЦА ОБЪЯВЛЕНА ЗДЕСЬ, А НЕ СПРЯТАНА: суд обнаруживает
НЕСОГЛАСОВАННОСТЬ, не ложность. Пакет, одинаково неверный на обоих
путях, пройдёт. Заявление звучит так: «формы пакета согласны с его
собственными объявленными правилами» — и ни словом больше.

ИСКЛЮЧЕНИЕ ОБЪЯВЛЯЕТСЯ, А НЕ МОЛЧИТ. Неправильный глагол не ломает
правило — он назван в списке исключений, и это ЗНАНИЕ О ЯЗЫКЕ, а не
поблажка суду: язык без исключений есть выдумка.
"""
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ПАКЕТЫ = КОРЕНЬ / "tools/langpacks"

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 0
РАЗЛАДОВ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: --packs no-such-dir


def обход():
    каталог = ПАКЕТЫ
    if "--packs" in sys.argv:
        каталог = pathlib.Path(sys.argv[sys.argv.index("--packs") + 1])
    return sorted(каталог.glob("*.json")) if каталог.is_dir() else []


def вывести(лексема, правило, клеток):
    """[формы по правилу] или None, если лексема — объявленное исключение."""
    если = правило.get("of", {}).get(лексема)
    if если is None or если == "*":
        return None
    класс = правило["classes"].get(если)
    if класс is None:
        return None
    хвост = класс.get("strip", "")
    if хвост and not лексема.endswith(хвост):
        return None
    основа = лексема[:len(лексема) - len(хвост)] if хвост else лексема
    окончания = класс["endings"]
    if len(окончания) != клеток:
        return None
    return [основа + о for о in окончания]


def судить_пакет(путь):
    """[(язык, класс, лексема, клетка, сказано, выведено)] — разлады."""
    try:
        п = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return [], 0
    я = п.get("lang", "?")
    разлады, сверено = [], 0
    for имя, класс in (п.get("morph_classes") or {}).items():
        правило = класс.get("rule")
        if not правило:
            continue
        клеток = класс.get("paradigm_cells", 0)
        имена = класс.get("forms", [])
        for лексема, формы in (класс.get("lexemes") or {}).items():
            ждём = вывести(лексема, правило, клеток)
            if ждём is None:
                continue
            for i, (сказано, выведено) in enumerate(zip(формы, ждём)):
                сверено += 1
                if сказано != выведено:
                    клетка = имена[i] if i < len(имена) else str(i)
                    разлады.append((я, имя, лексема, клетка,
                                    сказано, выведено))
    return разлады, сверено


def main():
    пакеты = обход()
    if not пакеты:
        print("ПРАВИЛО ЯЗЫКА ОТКАЗ: пакетов нет, судить нечего")
        return 2
    все, сверено, с_правилом = [], 0, 0
    for путь in пакеты:
        разлады, n = судить_пакет(путь)
        все += разлады
        сверено += n
        if n:
            с_правилом += 1
    for я, класс, лексема, клетка, сказано, выведено in все[:6]:
        print(f"  {я} {класс} {лексема}/{клетка}: сказано «{сказано}», "
              f"правило даёт «{выведено}»")
    поза = "PASS" if len(все) <= РАЗЛАДОВ_РУБЕЖ else "FAIL"
    print(f"ПРАВИЛО ЯЗЫКА {поза}: {len(все)} разладов формы с правилом "
          f"из {сверено} сверенных ({с_правилом} пакетов с правилом "
          f"из {len(пакеты)})")
    return 0 if len(все) <= РАЗЛАДОВ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
