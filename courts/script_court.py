#!/usr/bin/env python3
"""[ПИСЬМО] — слово, собранное из двух письменностей, ложно по записи.

ДВОЙНИК-БУКВА ЛОВИТСЯ НЕ СМЫСЛОМ, А ПИСЬМОМ. Подсадка словом заменяет
одну букву НЕОТЛИЧИМОЙ буквой другого письма: «давление» → «давлениe»
с латинской «e», «в рубле» → «в pубле» с латинской «p», «even» → «еven»
с кириллической «е». Глазу не видно; суду показа не видно тоже — он
знает своё слово, а чужого не знает и МОЛЧИТ, после чего палата берёт
истину у соседа (М-131).

ЭТА ПРОВЕРКА ЖИВЁТ В ОДНОМ МЕСТЕ И ПРИМЕНИМА КО ВСЕМ РОДАМ РАЗОМ, ибо
не спрашивает, что слово значит, — только каким письмом оно написано.
Слово, внутри которого встретились кириллица и латиница, не есть слово
ни одного языка корпуса. Русский пишет латиницей целые слова («LaTeX»,
«graph TD», «xor»), и они законны: смесь судится ВНУТРИ слова, а не
между словами.

ГРАНИЦА ОТКАЗА: суд не читает смысла и не зовёт ложью ничего, кроме
смешанного слова. Строка без такого слова ему не подсудна — он молчит,
и вердикт остаётся за судами родов.
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402
import asking  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПИСЬМО СУДИТСЯ В ПОКАЗАХ, А НЕ В ПРОЗЕ. Первый прогон по всем 145
# файлам дал 8615 «смешанных» слов — все в прозе: «∞-стек» после потери
# знака бесконечности становится «-стек», а «категорная» рядом с
# латинским термином читается как смесь. Проза цитирует чужие записи и
# теряет знаки при сборке; показ пишется нами и обязан быть чист.
# Обход — по мирам показов; род текста объявлен.
РОД_ТЕКСТА = "shows"

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# Слово из букв (дефис внутри допустим); цифры и знаки словом не считаются.
СЛОВО = re.compile(r"[^\W\d_]+(?:-[^\W\d_]+)*")
ДЫРА = re.compile(r"(?<=[,+\-−×÷=] )\?(?=\s|$)")
КИРИЛЛИЦА = re.compile(r"[а-яёА-ЯЁ]")
ЛАТИНИЦА = re.compile(r"[a-zA-Z]")


def смешанное(слово):
    """Есть ли в слове обе письменности разом."""
    return bool(КИРИЛЛИЦА.search(слово)) and bool(ЛАТИНИЦА.search(слово))


class Слой:
    """Признак ПЛАСТА ЯЗЫКА: там вопрос судится пакетом, не зачином.

    Пласты французского, итальянского, турецкого ставят вопрос своими
    словами («où est le stylo ?», «che cosa è un oggetto ?»), и зачины
    здешнего дома их не знают — первый прогон назвал ложью 1653 честных
    строки пластов. Пласт узнаётся по имени файла, как в палате.
    """

    def __init__(self):
        self.пласт = False
        self.полка = False       # книга полки: чужой текст письмом не судится
        self.объявление = None  # ask_words пакета: {"words", "position"}

    def впитать(self, путь):
        """Протокол палаты: слой создаётся пустым и впитывает файл.

        ПЛАСТ СУДИТСЯ ОБЪЯВЛЕНИЕМ СВОЕГО ПАКЕТА, А НЕ ЗАЧИНАМИ ДОМА.
        Пакет объявляет вопросные слова и их ПОЗИЦИЮ — впереди
        (русский, английский) или в конце (турецкий «nedir», суахили
        «nini», японский «ですか»). Пласт без объявления — молчание.
        """
        основа = pathlib.Path(путь).stem
        # ПОЛКА — ЧУЖОЙ ТЕКСТ, И ПИСЬМО ПОКАЗОВ ЕЙ НЕ СУДЬЯ. Зачины дома
        # замерены по своду показов; проза XIX века спрашивает «whence
        # does space get its quantitative character?», и суд письма
        # назвал Пуанкаре ложью — а палата на лжи одного суда дальше не
        # спрашивает, и суд деревьев прозы «не читал ни одной строки».
        # Полка судится своей мерой (договор полки), письмо показов на
        # ней молчит.
        self.полка = "shelf" in pathlib.Path(путь).parts
        self.пласт = "_lang_" in основа
        if self.пласт:
            язык = основа.rsplit("_", 1)[-1]
            пакет = КОРЕНЬ / "tools" / "langpacks" / f"{язык}.json"
            if пакет.exists():
                try:
                    self.объявление = json.loads(
                        пакет.read_text(encoding="utf-8")).get("ask_words")
                except ValueError:
                    self.объявление = None


# …a TASK carries an operation («compute 7 + 8.»); a word before a bare number
# («детей 54.», «pupils 30.» — a fact of the relation pages, 03.09) is no task
ЗАДАНИЕ_ВИД = re.compile(r"^([^\W\d_]+) ((?=[^.]*[+\-*/×÷^√\u2212\u22c5])[\d\s+\-*/×÷^√().,\u2212\u22c5]+[\d)])\. \S")


def судить(строка, слой=None):
    if слой is not None and слой.полка:
        return False, True
    for m in СЛОВО.finditer(строка):
        if смешанное(m.group()):
            return True, False
    # ВОПРОС БЕЗ ВОПРОСНОГО СЛОВА ЛОЖЕН ПО ЗАПИСИ. Порчу вопросного слова
    # («чем равно», «каков делители», «wha is») звали истиной геометрия,
    # числа и машина — их вопросные образцы читают предмет и ответ, а
    # само слово вопроса не читал никто. Признак формальный и общий, как
    # смесь письма: множество вопросных слов объявлено в доме пары и
    # замерено по своду (96,6 % честных вопросов; остаток — «¬» и «или»,
    # объявленные там же). Письмо без пробелов дому не подсудно.
    # ЗАДАНИЕ БЕЗ ОБЪЯВЛЕННОГО ЗАЧИНА ЛОЖНО ПО ЗАПИСИ (подсадка словом 04.09:
    # «вычисл 7 + 8. 7 + 8 = 15.», «comput 240 ÷ 8. …» звал истиной суд
    # арифметики — голову задания не читал никто): голова вида «слово +
    # чисто числовое выражение + точка» обязана открываться словом задания
    # пакета (asking.ЗАДАНИЕ).
    м = ЗАДАНИЕ_ВИД.match(строка)
    if м and asking.ЗАДАНИЕ is not None and not asking.ЗАДАНИЕ.match(строка):
        return True, False
    # «?» КАК ДЫРА, А НЕ КОНЕЦ ВОПРОСА (шестая полоса, 05.09): «продолжи ряд: 2, 4, 6, ?»
    # и «3 + ? = 5» несут знак вопроса на месте ЧИСЛА — после запятой или знака
    # действия. Такой знак есть дыра (слот), и вопросного зачина от строки не
    # требует; французское « ?» стоит после слова, не после запятой, и дырой не
    # читается.
    без_дыр = ДЫРА.sub("□", строка)
    if "?" in без_дыр or "？" in без_дыр or "؟" in без_дыр:
        вопрос = re.split(r"[?？؟]", без_дыр)[0]
        if слой is not None and слой.пласт:
            объ = слой.объявление
            if not объ:
                return False, True  # пакет не объявил — молчим
            слова = [w.strip(asking._КРАЙ).lower() for w in вопрос.split()]
            слова = [w for w in слова if w]
            if not слова:
                return False, True
            words = {w.lower() for w in объ.get("words", ())}
            # ЗНАК ОТКАЗА «¬» СТОИТ ВПЕРЕДИ В ЛЮБОМ ЯЗЫКЕ: вопрос-отказ
            # пласта («¬ yedi ne renktedir ?») объявлен им самим.
            if слова[0] == "¬" and "¬" in words:
                return True, True
            позиция = объ.get("position")
            if позиция == "end":
                # письмо без пробелов: вопросное слово — хвост строки
                хвост = слова[-1]
                ок = хвост in words or any(хвост.endswith(w) for w in words)
            elif позиция == "any":
                # хинди ставит «क्या» перед связкой, амхарский — «ምን» в
                # середине: слово ищется где-либо, в письме без пробелов —
                # подстрокой
                ок = any(w in words or any(x in w for x in words) for w in слова)
            else:
                голова = слова[0]
                ок = (голова in words or any(голова.startswith(w) for w in words)
                      or (len(слова) > 1 and слова[1] in words))
            return True, ок
        if asking.зачин_объявлен(вопрос) is False:
            return True, False
    return False, True


def main():
    ложных = судимых = файлов = прочитано = 0
    показы = {genesis._resolve(м["file"]) for м in genesis.manifest()["worlds"]
              if м.get("text") == "shows"}
    for путь in genesis.worlds():
        if not путь.exists() or путь.resolve() not in {п.resolve() for п in показы}:
            continue
        файлов += 1
        слой = Слой()
        слой.впитать(путь)
        for с in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            прочитано += bool(с.strip())
            судимо, истинно = судить(с, слой)
            if not судимо:
                continue
            судимых += 1
            if not истинно:
                ложных += 1
                if ложных <= 6:
                    print(f"  СМЕШАНО {путь.name}: {с.strip()[:90]}")
    if not файлов:
        print("ПИСЬМО ОТКАЗ: обход пуст")
        return 2
    поза = "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL"
    print(f"ПИСЬМО {поза}: {ложных} смешанных слов в {прочитано} строках "
          f"показов ({файлов} файлов, рубеж {ЛОЖНЫХ_РУБЕЖ})")
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
