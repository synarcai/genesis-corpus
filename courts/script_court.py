#!/usr/bin/env python3
"""[ПИСЬМО] — слово, собранное из двух письменностей, ложно по записи.

ДВОЙНИК-БУКВА ЛОВИТСЯ НЕ СМЫСЛОМ, А ПИСЬМОМ. Подсадка словом заменяет
одну букву НЕОТЛИЧИМОЙ буквой другого письма: «давление» → «давлениe»
с латинской «e», «в рубле» → «в pубле» с латинской «p», «even» → «еven»
с кириллической «е». Глазу не видно; суду показа не видно тоже — он
знает своё слово, а чужого не знает и МОЛЧИТ, после чего палата берёт
истину у соседа (М-131).

ЭТА ПРОВЕРКА ЖИВЁТ В ОДНОМ МЕСТЕ И ПРИМЕНИМА КО ВСЕМ РОДАМ РАЗОМ, ибо
не спрашивает, что слово значит, — только каким письмом оно написано.
Слово, внутри которого встретились кириллица и латиница, не есть слово
ни одного языка корпуса. Русский пишет латиницей целые слова («LaTeX»,
«graph TD», «xor»), и они законны: смесь судится ВНУТРИ слова, а не
между словами.

ГРАНИЦА ОТКАЗА: суд не читает смысла и не зовёт ложью ничего, кроме
смешанного слова. Строка без такого слова ему не подсудна — он молчит,
и вердикт остаётся за судами родов.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПИСЬМО СУДИТСЯ В ПОКАЗАХ, А НЕ В ПРОЗЕ. Первый прогон по всем 145
# файлам дал 8615 «смешанных» слов — все в прозе: «∞-стек» после потери
# знака бесконечности становится «-стек», а «категорная» рядом с
# латинским термином читается как смесь. Проза цитирует чужие записи и
# теряет знаки при сборке; показ пишется нами и обязан быть чист.
# Обход — по мирам показов; род текста объявлен.
РОД_ТЕКСТА = "shows"

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# Слово из букв (дефис внутри допустим); цифры и знаки словом не считаются.
СЛОВО = re.compile(r"[^\W\d_]+(?:-[^\W\d_]+)*")
КИРИЛЛИЦА = re.compile(r"[а-яёА-ЯЁ]")
ЛАТИНИЦА = re.compile(r"[a-zA-Z]")


def смешанное(слово):
    """Есть ли в слове обе письменности разом."""
    return bool(КИРИЛЛИЦА.search(слово)) and bool(ЛАТИНИЦА.search(слово))


def судить(строка):
    for m in СЛОВО.finditer(строка):
        if смешанное(m.group()):
            return True, False
    return False, True


def main():
    ложных = судимых = файлов = прочитано = 0
    показы = {genesis._resolve(м["file"]) for м in genesis.manifest()["worlds"]
              if м.get("text") == "shows"}
    for путь in genesis.worlds():
        if not путь.exists() or путь.resolve() not in {п.resolve() for п in показы}:
            continue
        файлов += 1
        for с in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            прочитано += bool(с.strip())
            судимо, истинно = судить(с)
            if not судимо:
                continue
            судимых += 1
            if not истинно:
                ложных += 1
                if ложных <= 6:
                    print(f"  СМЕШАНО {путь.name}: {с.strip()[:90]}")
    if not файлов:
        print("ПИСЬМО ОТКАЗ: обход пуст")
        return 2
    поза = "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL"
    print(f"ПИСЬМО {поза}: {ложных} смешанных слов в {прочитано} строках "
          f"показов ({файлов} файлов, рубеж {ЛОЖНЫХ_РУБЕЖ})")
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
