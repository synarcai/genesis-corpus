#!/usr/bin/env python3
"""[СУД ДВУХ ПРОЦЕНТОВ ПОДРЯД] — цепь посчитана заново, каждое число проверено; МИР ЗАМКНУТ.

Страница мира (`tools/pctchain.py`) есть число, два изменения в процентах и итог. Суд считает
цепь сам, ШАГ ЗА ШАГОМ, и проверяет КАЖДОЕ число записи: середину, итог и — где он назван —
наивный ответ.

    ПРОЦЕНТЫ НЕ СКЛАДЫВАЮТСЯ, ИБО ВТОРОЙ БЕРЁТСЯ НЕ ОТ ТОГО ЖЕ ЧИСЛА. «Минус десять и ещё
    минус десять» есть не минус двадцать: вторую десятую снимают уже с 180, а не с 200.

И закон о том, зачем на странице стои́т ЧУЖОЕ число:

    ОШИБКА НАЗВАНА НА СТРАНИЦЕ, А НЕ ОБОЙДЕНА. Страница говорит не только «стало 162», но и
    «а не 160». Суд требует, чтобы наивный ответ был посчитан ВЕРНО КАК НАИВНЫЙ и чтобы он
    ОТЛИЧАЛСЯ от истинного: там, где он совпал, ошибки нет и показывать нечего.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import pctchain as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"pctchain"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_pctchain.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_pctchain.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_pctchain.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ДВА ПРОЦЕНТА {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
