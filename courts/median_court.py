#!/usr/bin/env python3
"""[МЕДИАНА И СРЕДНЕЕ] — две меры одного ряда, пересчитанные судом.

Суд не пишет закона заново: он берёт его у дома (`medianforms`), где ряды объявлены таблицей
вместе с ДВУМЯ выбросами на каждый — ближним и дальним, — и всякая запись страницы считается
разбором свода (`arithread`).

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО, И СТЕРЕЖЁТ ДОРОГО: выброс обязан ДВИГАТЬ
среднее и НЕ ДВИГАТЬ медианы (иначе ловушки нет вовсе); ряд обязан быть нечётной длины, по
возрастанию и без повторов — иначе место середины спорно; все три средних обязаны быть
ЦЕЛЫМИ, ибо свод, сказавший «среднее 22,8», научил бы округлению как истине; и в ровном ряду
среднее обязано СОВПАСТЬ с медианой, иначе вторая сторона ловушки ложна.

    python3 courts/median_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import medianforms  # noqa: E402 — дом, объявивший множитель размерности

ИМЯ_СУДА = "median"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"median"})


def _судить(строка):
    return medianforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"МЕДИАНА И СРЕДНЕЕ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(medianforms.РОДЫ)}, страниц {len(medianforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
