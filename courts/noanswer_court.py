#!/usr/bin/env python3
"""[СУД ДВУХ ОТКАЗОВ] — довод проверен счётом, а не сверен с запретом; МИР ЗАМКНУТ.

Страница мира (`tools/noanswer.py`) есть действие, у какого ответа НЕТ, — и причина, почему
его нет. Суд считает сам: разность в роде «больше, чем есть», и неравенство нулю делимого в
роде «на ноль».

    НЕВОЗМОЖНОЕ ПО ЧИСЛУ И НЕВОЗМОЖНОЕ ПО МИРУ — РАЗНЫЕ ОТКАЗЫ. «5 ÷ 0» не имеет ответа
    никакого; «отдать 8 яблок из 5» невозможно НЕ ПО ЧИСЛУ — число тут есть, и оно −3, — а
    по миру: яблок минус три не бывает.

    ОТКАЗ С ПРИЧИНОЙ, А НЕ ЗАПРЕТ. «На ноль не делят» есть правило, какое читатель запомнит
    и не поймёт; «нет числа, какое, умноженное на 0, дало бы 12» есть довод.

И граница дома, какую суд держит: «0 ÷ 0» есть ТРЕТИЙ случай — там ответом было бы ВСЯКОЕ
число, а это иное дело, чем «ответа нет». Дом его не берёт, и подсадка на нём объявлена.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import noanswer as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"noanswer"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_noanswer.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_noanswer.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_noanswer.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ДВА ОТКАЗА {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
