def ход_деления(делимое, делитель):
    """[(снос, набранное, цифра, произведение, остаток)] — ВТОРОЙ РУКОЙ.

    Тот же алгоритм углом, написанный здесь отдельно от свода: цифры
    делимого берутся слева направо, ведущие только набираются, а как
    только частное началось — шаг есть всегда, и при нулевой цифре
    частного тоже. Свод идёт от чисел к записи, суд — от записи к
    числам и обратно к ходу; согласие двух встречных ходов и есть
    проверка.
    """
    if делитель <= 0:
        return [], 0, 0
    текущее = 0
    частное = ""
    шаги = []
    for ц in str(делимое):
        текущее = текущее * 10 + int(ц)
        if not частное and текущее < делитель:
            continue
        цифра = текущее // делитель
        произведение = делитель * цифра
        остаток = текущее - произведение
        шаги.append(("" if not частное else ц, текущее, цифра,
                     произведение, остаток))
        частное += str(цифра)
        текущее = остаток
    return шаги, (int(частное) if частное else 0), текущее


def частичные(множимое, множитель):
    """[(разряд, частичное)] — раскладка множителя ВТОРОЙ РУКОЙ."""
    вон = []
    for i, ц in enumerate(reversed(str(множитель))):
        цифра = int(ц)
        if цифра == 0:
            continue
        разряд = цифра * 10 ** i
        вон.append((разряд, множимое * разряд))
    return вон


