#!/usr/bin/env python3
"""СУД ДЕЛЕНИЯ УГЛОМ: суд ПРОХОДИТ ХОД ЗАНОВО, а не сверяет итог.

Слой говорит не итогом, а ХОДОМ: каждый шаг деления стоит отдельной
строкой, и каждый есть самостоятельное равенство. Суд, проверявший бы
только итог, пропустил бы неверный шаг при верном ответе — а именно
неверный шаг при верном ответе есть та ложь, которую корпус выучил бы
как приём.

ЧЕМ ИМЕННО СУД ПЕРЕСЧИТЫВАЕТ, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Он не разбирает
написанное на части и не сверяет части между собой — он БЕРЁТ ДЕЛИМОЕ
И ДЕЛИТЕЛЬ И ДЕЛИТ САМ, своим кодом, тем же алгоритмом углом, и
получает СПИСОК ШАГОВ. Затем требует, чтобы четвёрка, написанная в
строке (набранное, цифра частного, произведение, остаток), СТОЯЛА В
ЭТОМ СПИСКЕ — вместе со снесённой цифрой. Подмена одной цифры
частичного остатка выбрасывает четвёрку из списка, и вердикт падает
сам, без отдельного правила о том, что именно подменено.

ОБРАТНЫЙ ХОД СУДИТСЯ КАК ТОЖДЕСТВО, А НЕ КАК ПОВТОР. «23 × 17 + 0 =
391» верно не потому, что так написано выше, а потому, что частное,
остаток и делитель обязаны складываться в делимое, а остаток обязан
быть МЕНЬШЕ делителя. Второе условие и делает тождество проверкой:
без него «0 × 17 + 391 = 391» прошло бы как честное деление.

ОТКАЗ ПРОВЕРЯЕТСЯ ЗАЖИМОМ, А НЕ СЛОВОМ. «391 ÷ 19 целого не даёт»
истинно, если названные два кратных ВПРАВДУ зажимают делимое: нижнее
не больше его, верхнее строго больше, и между ними ровно один шаг
делителя. Отказ, чьи кратные не зажимают, есть отказ без основания —
и он ложь, даже когда делимое и вправду не делится.

УМНОЖЕНИЕ СТОЛБИКОМ СУДИТСЯ ЧАСТИЧНЫМИ, А НЕ ПРОИЗВЕДЕНИЕМ. Суд
раскладывает множитель по разрядам сам и требует, чтобы написанный ряд
частичных совпал с его собственным — по разрядам, по значениям и по
порядку, — и чтобы их сумма дала итог. Нулевая цифра множителя
частичного не даёт и в ряду стоять не смеет.

СУД НЕ СМЕЕТ ЧИТАТЬ ЧУЖОЙ РОД: образцы привязаны к зачину строки,
неузнанная строка есть (False, False) — молчание, а не вердикт.
"""

