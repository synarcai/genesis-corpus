def _шаг(м, со_сносом):
    """Четвёрка шага обязана СТОЯТЬ В ХОДЕ, посчитанном судом."""
    если = м.groups()
    if со_сносом:
        (a, b, снос, текущее, b2, цифра, произв, тек2, произв2,
         остаток) = если
    else:
        a, b, текущее, b2, цифра, произв, тек2, произв2, остаток = если
        снос = ""
    a, b, b2 = int(a), int(b), int(b2)
    текущее, цифра, произв = int(текущее), int(цифра), int(произв)
    тек2, произв2, остаток = int(тек2), int(произв2), int(остаток)
    if b2 != b or тек2 != текущее or произв2 != произв:
        return False
    шаги, _ч, _о = ход_деления(a, b)
    return (снос, текущее, цифра, произв, остаток) in шаги


def _шаг_первый(м):
    return _шаг(м, False)


def _шаг_сносом(м):
    return _шаг(м, True)


def _ноль_в_частном(м):
    """Ноль в частном берётся ровно там, где делитель БОЛЬШЕ набранного."""
    a, b, текущее, b2, тек2 = (int(з) for з in м.groups())
    if b2 != b or тек2 != текущее:
        return False
    шаги, _ч, _о = ход_деления(a, b)
    return (b > текущее
            and any(т == текущее and ц == 0 for _с, т, ц, _п, _о in шаги))


def _итог(м):
    """Голая запись итога УТВЕРЖДАЕТ ТОЧНОСТЬ: остатка в ней нет."""
    a, _знак, b, частное = м.group(1), м.group(2), м.group(3), м.group(4)
    a, b, частное = int(a), int(b), int(частное)
    return b != 0 and a % b == 0 and a // b == частное


def _итог_с_остатком(м):
    a, b, частное, остаток = (int(з) for з in м.groups())
    return (b != 0 and a // b == частное and a % b == остаток
            and остаток < b)


def _вопрос_деления(м):
    a, b, a2, b2, частное = (int(з) for з in м.groups())
    return (a2 == a and b2 == b and b != 0 and a % b == 0
            and a // b == частное)


def _тождество(м):
    """ОСТАТОК МЕНЬШЕ ДЕЛИТЕЛЯ — без этого тождество не есть деление.

    «0 × 17 + 391 = 391» складывается верно и делением не является:
    остаток, не меньший делителя, значит, что делить не кончили.

    ОБРАЗЕЦ ПРИВЯЗАН К ЗАЧИНУ «в делении», И ЭТО КУПЛЕНО ЗАМЕРОМ.
    Голая четвёрка «a × b + c = d» есть обычная арифметика: первый
    прогон забрал пять честных строк «2 × 3 + 4 = 10» из школьного
    мира и объявил их ложью, ибо мерил их делением, которым они не
    были.
    """
    (a, b, частное0, остаток0, частное, делитель, остаток,
     делимое) = (int(з) for з in м.groups())
    if a != делимое or b != делитель or частное0 != частное \
            or остаток0 != остаток:
        return False
    return (делитель != 0 and остаток < делитель
            and частное * делитель + остаток == делимое
            and делимое // делитель == частное)


def _обратный(м):
    a, b, частное, b2, a2 = (int(з) for з in м.groups())
    return (b2 == b and a2 == a and b != 0 and a % b == 0
            and a // b == частное and частное * b == a)


def _вопрос_проверки(м):
    a, b, частное, частное2, b2, a2 = (int(з) for з in м.groups())
    return (частное2 == частное and b2 == b and a2 == a and b != 0
            and a % b == 0 and a // b == частное and частное * b == a)


def _отказ(м):
    """Зажим двумя кратными: нижнее не больше, верхнее строго больше."""
    (a, b, b2, частное, снизу, a2, снизу2, остаток, b3, следом,
     сверху, a3) = (int(з) for з in м.groups())
    if not (b2 == b3 == b and a2 == a3 == a and снизу2 == снизу):
        return False
    return (b != 0 and a % b != 0 and a // b == частное
            and b * частное == снизу and снизу <= a
            and a - снизу == остаток and остаток > 0
            and следом == частное + 1 and b * следом == сверху
            and сверху > a)


def _вопрос_делимости(м):
    """Обе полярности одной формой вопроса: «да» — остаток 0, «нет» —
    остаток положительный; суд считает остаток, а не верит слову."""
    ответ = м.group(3)
    a, b, b2, частное, снизу, остаток = (int(з) for з in м.groups()[:2] + м.groups()[3:])
    return (b2 == b and b != 0 and a // b == частное
            and b * частное == снизу and a - снизу == остаток
            and (остаток == 0) == (ответ == "да"))


_ЧАСТЬ = re.compile(r"^(\d+) × (\d+) = (\d+)$")


def _столбик(м):
    """Ряд частичных обязан СОВПАСТЬ с раскладкой, посчитанной судом."""
    a, b, итог, ряд, сумма, итог2 = м.groups()
    a, b, итог, итог2 = int(a), int(b), int(итог), int(итог2)
    if итог != a * b or итог2 != итог:
        return False
    сказано = []
    for кусок in ряд.split(", "):
        ч = _ЧАСТЬ.match(кусок)
        if ч is None or int(ч.group(1)) != a:
            return False
        сказано.append((int(ч.group(2)), int(ч.group(3))))
    if сказано != частичные(a, b):
        return False
    слагаемые = [x.strip() for x in сумма.split(" + ")]
    if not all(x.isdigit() for x in слагаемые):
        return False
    числа = [int(x) for x in слагаемые]
    return числа == [п for _р, п in сказано] and sum(числа) == итог


# ГОЛОЕ ПРОИЗВЕДЕНИЕ «19 × 19 = 361.» ЭТОТ СУД НЕ ЧИТАЕТ, И ЭТО
# ГРАНИЦА, А НЕ ПРОБЕЛ. Такая запись живёт в двух с половиной тысячах
# строк ЧУЖИХ миров, и владеет ею суд арифметики: он её и пересчитывает.
# Здешний род есть СТОЛБИК — произведение, разложенное частичными, — и
# образец берёт только его.


def _вопрос_умножения(м):
    a, b, a2, b2, итог = (int(з) for з in м.groups())
    return a2 == a and b2 == b and a * b == итог


# ------------------------------------------------------------- ОБРАЗЦЫ

Ч = r"(\d+)"
ОБРАЗЦЫ = (
    (rf"^в делении {Ч} ÷ {Ч} берём {Ч}: {Ч} × {Ч} = {Ч}, {Ч} − {Ч} = "
     rf"{Ч}\.$", _шаг_первый),
    (rf"^в делении {Ч} ÷ {Ч} сносим (\d) и берём {Ч}: {Ч} × {Ч} = {Ч}, "
     rf"{Ч} − {Ч} = {Ч}\.$", _шаг_сносом),
    (rf"^в делении {Ч} ÷ {Ч} на {Ч} частное берёт 0: {Ч} больше "
     rf"{Ч}\.$", _ноль_в_частном),
    (rf"^{Ч} (÷|/) {Ч} = {Ч}\.$", _итог),
    (rf"^{Ч} ÷ {Ч} = {Ч}, остаток {Ч}\.$", _итог_с_остатком),
    (rf"^сколько будет {Ч} ÷ {Ч}\? {Ч} ÷ {Ч} = {Ч}\.$",
     _вопрос_деления),
    (rf"^в делении {Ч} ÷ {Ч} частное {Ч} и остаток {Ч} дают делимое: "
     rf"{Ч} × {Ч} \+ {Ч} = {Ч}\.$", _тождество),
    (rf"^обратный ход деления {Ч} ÷ {Ч}: {Ч} × {Ч} = {Ч}\.$",
     _обратный),
    (rf"^чем проверить {Ч} ÷ {Ч} = {Ч}\? {Ч} × {Ч} = {Ч}\.$",
     _вопрос_проверки),
    (rf"^{Ч} ÷ {Ч} целого не даёт: {Ч} × {Ч} = {Ч}, а {Ч} − {Ч} = {Ч}; "
     rf"{Ч} × {Ч} = {Ч} больше {Ч}\.$", _отказ),
    (rf"^делится ли {Ч} на {Ч} нацело\? (да|нет): {Ч} × {Ч} = {Ч}, остаток "
     rf"{Ч}\.$", _вопрос_делимости),
    (rf"^{Ч} × {Ч} = {Ч}: (.+); (.+) = {Ч}\.$", _столбик),
    (rf"^сколько будет {Ч} × {Ч}\? {Ч} × {Ч} = {Ч}\.$",
     _вопрос_умножения),
)
ПРАВИЛА = tuple((re.compile(о), п) for о, п in ОБРАЗЦЫ)


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    for образец, проверить in ПРАВИЛА:
        м = образец.match(с)
        if м:
            return True, bool(проверить(м))
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"УГОЛ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("УГОЛ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"УГОЛ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
