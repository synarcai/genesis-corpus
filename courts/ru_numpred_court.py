#!/usr/bin/env python3
"""[СКАЗУЕМОЕ ПРИ ЧИСЛЕ] — русское сказуемое при числовом подлежащем согласуется с ячейкой счёта (24.09).

    СКАЗУЕМОЕ ПРИ ЧИСЛЕ БЕРЁТ РОД У ИМЕНИ, А НЕ У ШАБЛОНА: шаблон один, чисел много.

ПОВОД — чтение свода глазами: «у Петра было 21 монета», «у Ани осталось 1 монета», «было 1 цветок»,
«41 кот сидели на столе», «31 шар были синие» — 221 строка в двенадцати мирах, и ни один из трёхсот
судов их не видел: счёт верен, форма каждого слова объявлена, род числительного судим (`numgender`),
а согласования СКАЗУЕМОГО с числом не судил никто.

ЗАКОН (дверь — `rugram.прошедшее_при_числе`): при числе на один (кроме одиннадцати) имя стоит в
единственном, и сказуемое согласуется с ним в роде и числе — «была 21 монета», «осталась 1 монета»,
«был 1 цветок», «было 1 яблоко», «41 кот сидел», «31 шар был синий»; при прочих числах глагол стоит в
среднем роде или во множественном — «было 5 монет», «5 котов сидели», — и то и другое законно.

ЧТО СУДИТСЯ:
  · глагол бытия, становления, остатка, движения и положения (`ГЛАГОЛЫ`) ПЕРЕД «число имя» — там, где
    число и есть подлежащее: в начале предложения, после «у кого» и места («в библиотеке», «на пруду»),
    после слов времени и связи;
  · тот же глагол ПОСЛЕ «число имя», начинающих предложение;
  · после «число из них» и «число имя [глагол]» при числе на один — множественное сказуемое
    (глагол «были», прилагательное на -ые/-ие перед концом предложения) есть ложь: единица стоит в
    единственном, какого бы рода она ни была.

ГРАНИЦА, А НЕ ПОЛНОТА:
  · подлежащее перед глаголом («температура была −1 градус», «ошибка 9 стала 1») делает число не
    подлежащим — такой строки суд не судит;
  · глагол переходный или неопределённо-личный после числа («21 яблоко разложили», «8 ручек убрали»)
    не судится: число там есть дополнение, и различить их без знания глагола нельзя; потому суд
    судит лишь объявленные непереходные глаголы;
  · род прилагательного при единице не судится — у суда нет его форм; судится лишь множественное,
    и без имени и глагола — лишь на -ые: «21 сообщение» есть имя среднего рода, и письмо не отличает
    его от прилагательного на -ие.

ЛОВЕЦ ПОРЧИ: суд зовёт ложью рассогласование и молчит об остальном; истины не выдаёт ни одной.
Подсадки строятся ДВЕРЬЮ, а не литералом: для всякого глагола, рода и ячейки счёта верная форма
берётся у двери, битая — у соседней ячейки.

    python3 courts/ru_numpred_court.py [файл …]
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import json  # noqa: E402
import langpack  # noqa: E402 — правило ячейки счёта пакета
import rugram  # noqa: E402 — дверь русских форм, рода и сказуемого при числе

ЛОВЕЦ_ПОРЧИ = True
# РУБЕЖ-ДОЛГА: РАССОГЛАСОВАНИЙ_РУБЕЖ = 0
РАССОГЛАСОВАНИЙ_РУБЕЖ = 0

# непереходные: их подлежащее — всегда число, стоит ли оно до глагола или после
ГЛАГОЛЫ = ("был", "стал", "остался", "ушёл", "пришёл", "сидел", "стоял", "лежал")
_РОДЫ = ("м", "ж", "с", "мн")
ФОРМА_ГЛАГОЛА = {rugram.прошедшее_рода(г, р): (г, р) for г in ГЛАГОЛЫ for р in _РОДЫ}
_ФОРМЫ = "|".join(sorted(ФОРМА_ГЛАГОЛА, key=len, reverse=True))
_ЧИСЛО = r"(−?-?\d+)"
_ДО = re.compile(rf"(?:^|[^а-яё])({_ФОРМЫ})\s+{_ЧИСЛО}\s+([а-яё]+)")
_ПОСЛЕ = re.compile(rf"(?:^|[^\d.,−-]){_ЧИСЛО}\s+([а-яё]+)\s+({_ФОРМЫ})(?![а-яё])")
# число, начинающее сказуемое: за ним «из них», имя или ничего (имя опущено: «…, 31 были старые»)
_ЧИСЛО_СКАЗУЕМОГО = re.compile(rf"(?:^|[^\d.,−-]){_ЧИСЛО}(?=\s)")
_СЛОВО = re.compile(r"\s+([а-яё]+)")
_КОНЕЦ = re.compile(r"\s*[,.;:!?]|\s+(?:и|а)\s")
# что стоит перед сказуемым или числом, когда подлежащее — само число: ничего, «у кого», место, время, связь
_БЕЗ_ПОДЛЕЖАЩЕГО = re.compile(
    r"(?:^|[.?!:;,—(]\s*|\s(?:и|а|но|что|утром|днём|вечером|ночью|сначала|изначально|теперь|потом|тогда|там|"
    r"здесь|всего|сейчас))\s*$"
    r"|(?:^|\s)(?:у|в|во|на|вне)\s+[а-яё]+(?:\s+(?:и|с)\s+[а-яё]+)?\s*$")


def _допустимые(глагол, n, род):
    """Формы глагола, законные при числе n и имени рода «род»: при единице — одна, в роде имени;
    иначе — средний и множественное."""
    if rugram.единица_при_числе(n):
        return {rugram.прошедшее_рода(глагол, род)}
    return {rugram.прошедшее_рода(глагол, "с"), rugram.прошедшее_рода(глагол, "мн")}


# ИМЁН У РУССКОГО ДВЕ ДВЕРИ, И СУД СПРАШИВАЕТ ОБЕ (24.09): дом форм (`rugram`) и классы русского
# пакета, чей пласт писал «осталось 1 файл», «было 1 ложка», «осталось 1 дверь» — двадцать строк с
# именами, которых дом форм не объявляет. Род класса объявлен пакетом (`gender`), ячейка — его правилом.
_ПАКЕТ_RU = json.loads((КОРЕНЬ / "tools" / "langpacks" / "ru.json").read_text(encoding="utf-8"))
_ПАКЕТНЫЕ = {}
for _кл in (_ПАКЕТ_RU.get("morph_classes") or {}).values():
    if _кл.get("plural_by_count") and _кл.get("gender") in ("m", "f", "n"):
        for _формы in (_кл.get("lexemes") or {}).values():
            for _ф in _формы:
                _ПАКЕТНЫЕ.setdefault(_ф, (_кл, _формы))
_РОД_ПАКЕТА = {"m": "м", "f": "ж", "n": "с"}


def _род(слово, n):
    """Род счётного имени, если слово — его форма при n (именительный счёта); иначе None."""
    ключ = rugram.ПО_ФОРМЕ.get(слово)
    if ключ is not None and rugram.форма(ключ, n) == слово:
        return rugram.род(ключ.split()[-1])
    кл_формы = _ПАКЕТНЫЕ.get(слово)
    if кл_формы is not None:
        кл, формы = кл_формы
        if формы[langpack.count_form_index(_ПАКЕТ_RU, кл, n)] == слово:
            return _РОД_ПАКЕТА[кл["gender"]]
    return None


def разбор(строка):
    """[(было, надо)] — судимые места строки; было != надо есть ложь."""
    с = строка.lower()
    вон = []
    for м in _ДО.finditer(с):
        форма, n = м.group(1), int(м.group(2).replace("−", "-"))
        род = _род(м.group(3), n)
        if род is None or not _БЕЗ_ПОДЛЕЖАЩЕГО.search(с[:м.start(1)]):
            continue
        глагол = ФОРМА_ГЛАГОЛА[форма][0]
        можно = _допустимые(глагол, n, род)
        вон.append((f"{форма} {м.group(2)} {м.group(3)}",
                    f"{форма if форма in можно else min(можно)} {м.group(2)} {м.group(3)}"))
    for м in _ПОСЛЕ.finditer(с):
        n, форма = int(м.group(1).replace("−", "-")), м.group(3)
        род = _род(м.group(2), n)
        if род is None or not _БЕЗ_ПОДЛЕЖАЩЕГО.search(с[:м.start(1)]):
            continue
        глагол = ФОРМА_ГЛАГОЛА[форма][0]
        можно = _допустимые(глагол, n, род)
        вон.append((f"{м.group(1)} {м.group(2)} {форма}",
                    f"{м.group(1)} {м.group(2)} {форма if форма in можно else min(можно)}"))
    for м in _ЧИСЛО_СКАЗУЕМОГО.finditer(с):
        n = int(м.group(1).replace("−", "-"))
        if not rugram.единица_при_числе(n) or not _БЕЗ_ПОДЛЕЖАЩЕГО.search(с[:м.start(1)]):
            continue
        было = _множественное_при_единице(с, м.end(), n)
        if было:
            вон.append((f"{м.group(1)} {было}", f"{м.group(1)} … (единственное)"))
    return вон


def _множественное_при_единице(с, i, n):
    """Сказуемое во множественном за числом на один: «из них» или имя (или ничего), затем глагол и
    признак; ложь — глагол во множественном или признак на -ые/-ие перед концом предложения."""
    слова, j = [], i
    for _ in range(4):
        м = _СЛОВО.match(с, j)
        if not м:
            break
        слова.append((м.group(1), м.end()))
        j = м.end()
    k = 0
    if len(слова) >= 2 and слова[0][0] == "из" and слова[1][0] == "них":
        k = 2
    elif слова and _род(слова[0][0], n) is not None:
        k = 1
    глагол = слова[k][0] if k < len(слова) and слова[k][0] in ФОРМА_ГЛАГОЛА else None
    k += глагол is not None
    признак = None
    # БЕЗ ИМЕНИ И БЕЗ ГЛАГОЛА НА -ИЕ ПРИЗНАК НЕ УЗНАЁТСЯ: «21 сообщение» — имя среднего рода, и письмо
    # не отличает его от «21 синие»; там судится лишь -ые («…, 21 старые, …»)
    окончания = ("ые", "ие") if (k > 0 or глагол is not None) else ("ые",)
    if k < len(слова) and слова[k][0].endswith(окончания) and _КОНЕЦ.match(с, слова[k][1]):
        признак = слова[k][0]
    множественное = (глагол is not None and ФОРМА_ГЛАГОЛА[глагол][1] == "мн") or признак is not None
    if not множественное:
        return None
    return " ".join(w for w, _ in слова[:k + (признак is not None)])


def судить(строка, слой=None):
    """(судимо, истинно): рассогласование сказуемого с числом — ложь; иначе суд МОЛЧИТ.

    ЛОВЕЦ ПОРЧИ ИСТИНЫ НЕ ВЫДАЁТ: согласованный глагол не делает строку верной — её счёт судят
    суды мира, и «истина» отсюда поручилась бы за то, чего этот суд не читал (`corpusword`, 20.09)."""
    return (True, False) if any(было != надо for было, надо in разбор(строка)) else (False, False)


def _подсадки():
    """[(верное, битое)] — ДВЕРЬЮ: всякий глагол при единице своего рода и при прочем числе."""
    имена = {"м": "шар", "ж": "монета", "с": "яблоко"}
    пары = []
    for глагол in ГЛАГОЛЫ:
        for род, ключ in имена.items():
            for n in (1, 21, 5, 3, 11):
                верная = rugram.прошедшее_при_числе(глагол, n, ключ)
                чужой = "ж" if род != "ж" else "м"
                битая = (rugram.прошедшее_рода(глагол, чужой) if rugram.единица_при_числе(n)
                         else rugram.прошедшее_рода(глагол, род if род != "с" else "м"))
                if битая in _допустимые(глагол, n, род):
                    continue
                имя = rugram.форма(ключ, n)
                пары.append((f"у Ани {верная} {n} {имя}.", f"у Ани {битая} {n} {имя}."))
                после = rugram.прошедшее_при_числе(глагол, n, ключ, после=True)
                битое_после = rugram.прошедшее_рода(глагол, "мн") if rugram.единица_при_числе(n) else None
                if битое_после is not None:
                    пары.append((f"{n} {имя} {после} там.", f"{n} {имя} {битое_после} там."))
    for n in (1, 21, 31):
        пары.append((f"в коробке 100 шаров. {n} из них красный, а остальные синие.",
                     f"в коробке 100 шаров. {n} из них красные, а остальные синие."))
    return пары


# ВЕРНОЕ, КОТОРОЕ СУД ОБЯЗАН ПРОПУСТИТЬ: подлежащее перед глаголом, переходный глагол, число не на один
_ВЕРНОЕ = ("если температура была −1 градус, то холодно.", "ошибка 9 стала 1 и запас вырос.",
           "21 яблоко разложили по корзинам.", "8 ручек убрали.", "4 из них старые, а остальные новые.",
           "у Оли были 5 карт.", "осталось 11 монет.", "5 котов сидели на столе.", "было 3 кота.")


def main():
    """Миры манифеста — или явные пути лентой; пропавший файл и пустой обход — ОТКАЗ."""
    from genesis import worlds  # noqa: E402
    явные = [pathlib.Path(а) for а in sys.argv[1:]]
    for путь in явные:
        if not путь.is_file():
            print(f"СКАЗУЕМОЕ ПРИ ЧИСЛЕ ОТКАЗ: файла нет — {путь}")
            return 2
    подсадки = _подсадки()
    поймано = 0
    for верное, битое in подсадки:
        судимо, истинно = судить(верное)
        assert not судимо or истинно, ("подсадка: верное названо ложью", верное)
        if судить(битое) == (True, False):
            поймано += 1
    for верное in _ВЕРНОЕ:
        судимо, истинно = судить(верное)
        assert not судимо or истинно, ("суд назвал ложью верное", верное)
    итог = collections.Counter()
    примеры = collections.Counter()
    по_миру = collections.Counter()
    файлов = 0
    for путь in (явные or worlds(kind="shows")):
        файлов += 1
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            места = разбор(строка)
            if not места:
                continue
            итог["судимых"] += 1
            ложные = [(было, надо) for было, надо in места if было != надо]
            if ложные:
                итог["ложных"] += 1
                по_миру[путь.stem.replace("genesis_", "")] += 1
                примеры[(путь.stem.replace("genesis_", ""),) + ложные[0]] += 1
    if not итог["судимых"]:
        print(f"СКАЗУЕМОЕ ПРИ ЧИСЛЕ ОТКАЗ: судить нечего — {файлов} файлов, ни одного сказуемого при числе")
        return 2
    for (мир, было, надо), n in примеры.most_common(8):
        print(f"  ЛОЖЬ ×{n} [{мир}]: «{было}» — надо «{надо}»")
    if по_миру:
        print("  по мирам: " + ", ".join(f"{м} {n}" for м, n in по_миру.most_common()))
    поза = "PASS" if итог["ложных"] <= РАССОГЛАСОВАНИЙ_РУБЕЖ and поймано == len(подсадки) else "FAIL"
    print(f"СКАЗУЕМОЕ ПРИ ЧИСЛЕ {поза}: {итог['ложных']} ложных строк из {итог['судимых']} судимых "
          f"(рубеж {РАССОГЛАСОВАНИЙ_РУБЕЖ}); подсадок поймано {поймано} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
