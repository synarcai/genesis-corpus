#!/usr/bin/env python3
"""[ЧИСЛО-ИМЯ] — что делает число: зовёт или мерит, пересчитано судом.

Суд не пишет закона заново: он берёт его у дома (`numlabelforms`), где имена, вещи и числа
объявлены одной таблицей. Подмена числа и САМОГО ДЕЛА ЧИСЛА ловится машинально: суммы,
произведения и сравнения пересчитываются, а место числа проверяется по строке — у меры число
стои́т ПЕРЕД словом, у имени ПОСЛЕ.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

РАВЕНСТВА НА СТРАНИЦАХ ИМЕНИ ИСТИННЫ, И ЭТО НЕ ПРОТИВОРЕЧИЕ: «2 + 5 = 7» верно как счёт и
не называет никакой страницы. Суд арифметики прочтёт его и согласится — и будет прав.

    ВЕРНЫЙ СЧЁТ НАД ИМЕНАМИ ДАЁТ ВЕРНОЕ ЧИСЛО И НИКАКОЙ ВЕЩИ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/numlabel_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import numlabelforms  # noqa: E402 — дом, объявивший имена и меры

ИМЯ_СУДА = "numlabel"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"numlabel"})


def _судить(строка):
    return numlabelforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ЧИСЛО-ИМЯ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(numlabelforms.РОДЫ)}, страниц {len(numlabelforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
