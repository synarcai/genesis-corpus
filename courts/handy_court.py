#!/usr/bin/env python3
"""[УДОБНЫЙ СЧЁТ] — перегруппировка к круглому числу, пересчитанная судом.

Суд не пишет закона заново: он берёт его у дома (`handyforms`), где рамки и числа объявлены одной
таблицей. Подмена итога, поправки и самой КРУГЛОСТИ ловится машинально: круглое число сверяется
разрядом, а дополнение — вычитанием, и ни то, ни другое не принимается на слово.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

СКОБКА ЕСТЬ ГРАНИЦА ЧЛЕНА: образец, читающий «(37 + 3) + 45 = 85» как «37 + 3 = 85», берёт голову
скобки за целое. Потому скобки считаются первыми, а простой счёт идёт по строке БЕЗ них.

ЭТОТ ДОМ ЧИТАЕТСЯ И СУДОМ АРИФМЕТИКИ: его страницы написаны так, что слова стоя́т до двоеточия, а
равенства после, — и потому каждая проверена ДВАЖДЫ.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/handy_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import handyforms  # noqa: E402 — дом, объявивший удобный счёт

ИМЯ_СУДА = "handy"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"handy"})


def _судить(строка):
    return handyforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"УДОБНЫЙ СЧЁТ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(handyforms.РОДЫ)}, страниц {len(handyforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
