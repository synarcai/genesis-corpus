#!/usr/bin/env python3
"""[СУД СКОБОК] — стопка пересчитана заново; МИР ЗАМКНУТ.

Страница мира скобок (`tools/dyckforms.py`) есть ряд и утверждение о нём: чем он
закрывается, уравновешен ли он и на сколько вложен. Суд кладёт СВОЮ стопку и считает всё
заново — хвост, число пар и глубину, — и ни одному числу страницы не верит на слово.

    СКОБКА В ФОРМУЛЕ ЕСТЬ ЗНАК ПРИ ЧИСЛАХ; СКОБКА В РЯДУ ЕСТЬ ПАМЯТЬ О ТОМ, ЧТО ОТКРЫТО.
    Оттого суд ряда есть суд ПАМЯТИ, и проверяется он не образцом, а стопкой.

Ряд, в котором закрыта не та скобка, объявляется ложью целиком: закрывать нечего — значит
утверждение о нём неверно, каким бы ни был хвост.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import dyckforms as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"dyck"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = ("ряд ( [ — чем закрыть? ] .",
                "ряд ( [ — чем закрыть? ) ].",
                "ряд ( ) уравновешен: пар 2.",
                "ряд ( [ не уравновешен: открытых без пары 1.",
                "ряд ( [ ] ) вложен на 1.",
                "the row ( [ — how is it closed? ] } ).",
                "the row ( ) nests 2 deep.")
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО (14.09). Подсадка бывает
    # СУДИМА И ИСТИННА — тогда лгал сам список: строка похожа на ложь, а есть правда.
    # Бывает и НЕСУДИМА — тогда она выпала из рамки дома, и прибор, считающий её просто
    # «непойманной», молчит о том, что перестал её читать вовсе. Суд скобок так и потерял
    # четыре подсадки из семи, когда рамка вопроса переменилась.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_dyck.txt"]
    if not пути:
        свой = pathlib.Path(__file__).resolve().parents[1] / "datasets" / "genesis_dyck.txt"
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_dyck.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"СКОБКИ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
