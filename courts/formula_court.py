# УЗЕЛ ЗОВЁТСЯ И ПО-РУССКИ: «вход --> обработка» есть та же
# диаграмма, что «start --> work», и латинская азбука в образце
# была не правилом записи, а следом первого слоя.
РЕБРО = re.compile(
    r"([^\W\d_]\w*)\s*-->\s*(?:\|[^|]*\|\s*)?([^\W\d_]\w*)")
ГРАФ = re.compile(r"^graph\s+(?:TD|LR|TB|RL|BT)\s*;")


# ЦЕПЬ РЁБЕР БЕЗ ЗАГОЛОВКА ЕСТЬ ТА ЖЕ ДИАГРАММА. «start --> work; work
# --> end;» — законная запись потока, и суд, требовавший слова «graph
# TD», молчал о ней. Проверяемое в ней есть СТРОЕНИЕ: поток идёт от
# одного начала к одному концу, ни один узел не ветвится и не
# повторяется. Цепь, где две стрелки входят в один узел, потоком не
# является — и это ловится, а не принимается на веру.
ГОЛЫЕ_РЁБРА = re.compile(r"^(?:[A-Za-zА-Яа-яЁё]\w*\s*-->\s*"
                         r"[A-Za-zА-Яа-яЁё]\w*\s*;\s*)+$")


def цепь_рёбер(строка):
    """Является ли голый список рёбер потоком; None — не наше."""
    с = строка.strip()
    if not ГОЛЫЕ_РЁБРА.match(с):
        return None
    рёбра = РЕБРО.findall(с)
    if len(рёбра) < 1:
        return None
    исходит, входит = collections.Counter(), collections.Counter()
    for а, б in рёбра:
        исходит[а] += 1
        входит[б] += 1
    узлы = set(исходит) | set(входит)
    начала = [у for у in узлы if not входит[у]]
    концы = [у for у in узлы if not исходит[у]]
    ветвится = any(исходит[у] > 1 or входит[у] > 1 for у in узлы)
    связно = len(рёбра) == len(узлы) - 1
    return (len(начала) == 1 and len(концы) == 1
            and not ветвится and связно)


# ВЕТВЛЕНИЕ И ЕГО ДИАГРАММА — ОДИН ФАКТ В ДВУХ ЗАПИСЯХ, и суд их
# СЛИЧАЕТ: условие в ромбе обязано быть тем же условием, ветвь «да» —
# вести к тому, что стоит после «then», ветвь «нет» — к тому, что
# после «else». Показ самодостаточен: обе записи в одной строке, и
# расхождение между ними есть противоречие, невидимое счёту.
ВЕТВЛЕНИЕ = re.compile(
    r"^(?:if|если)\s+(.+?)\s+(?:then|то)\s+(\S+?)\s+(?:else|иначе)\s+"
    r"(\S+?)\.\s*(?:code|код):\s*graph\s+\w+;\s*"
    r"(\w+)\{(.+?)\};\s*"
    r"\4-->\|(?:yes|да)\|(\w+);\s*\4-->\|(?:no|нет)\|(\w+);$")


# ДОРОГА ОБЪЯВЛЕНА СЛОЕМ, А НЕ СОСЕДОМ. «путь от A к C идёт через B»
# и «graph TD; A-->B; B-->C;» суть один факт в двух записях, но
# перестановка проходов их разводит — и требовать соседства значило бы
# судить порядок вместо факта. Суд собирает ВСЕ рёбра слоя и ПРОХОДИТ
# по ним: восемьдесят утверждений о пути стояли вне суда при готовом
# обходчике в трёх строках выше.
ДОРОГА = re.compile(
    r"^(?:the road from|путь от)\s+(\w+)\s+(?:to|к)\s+(\w+)\s+"
    r"(?:goes through|идёт через)\s+(\w+)[.。]?$")


class Слой:
    """Рёбра, объявленные всеми диаграммами файла."""

    def __init__(self):
        self.рёбра = set()

    def впитать(self, путь_):
        with путь_.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                if ГРАФ.match(строка.strip()):
                    self.рёбра |= set(РЕБРО.findall(строка))


def дорога_ведёт(строка, слой):
    """Проходит ли объявленная дорога через названный узел."""
    m = ДОРОГА.match(строка.strip())
    if not m or слой is None or not слой.рёбра:
        return None
    откуда, куда, через = m.groups()
    прямо = путь(слой.рёбра, откуда, куда)
    if прямо is None:
        return False
    к_среднему = путь(слой.рёбра, откуда, через)
    от_среднего = путь(слой.рёбра, через, куда)
    if к_среднему is None or от_среднего is None:
        return False
    return к_среднему + от_среднего == прямо


# ПРОСЬБА НАРИСОВАТЬ ЦЕПЬ И НАРИСОВАННОЕ — ОДИН ФАКТ В ДВУХ ЗАПИСЯХ.
# «нарисуй цепь A C: graph TD; A-->C;» проверяемо целиком: названные
# узлы обязаны быть ровно узлами схемы и ровно в том же порядке.
РИСУНОК = re.compile(
    r"^(?:draw the chain|нарисуй цепь)\s+([\w ]+?):\s*(graph\s+\w+;.*)$")


def рисунок_сходится(строка):
    """Сходится ли просьба со схемой; None — не наше."""
    m = РИСУНОК.match(строка.strip())
    if not m:
        return None
    названы = m.group(1).split()
    граф = разбор_графа(m.group(2))
    if граф is None:
        return False
    _, рёбра = граф
    нарисованы = [рёбра[0][0]] + [б for _, б in рёбра]
    return названы == нарисованы


def ветвление_сходится(строка):
    """Сходятся ли ветвление и его диаграмма; None — не наше."""
    m = ВЕТВЛЕНИЕ.match(строка.strip())
    if not m:
        return None
    условие, да, нет, _, в_ромбе, к_да, к_нет = m.groups()
    return (" ".join(условие.split()) == " ".join(в_ромбе.split())
            and да == к_да and нет == к_нет)


# ЦЕПЬ СУДИТСЯ ЗАВИСИМОСТЯМИ, А НЕ ПОРЯДКОМ ТЕКСТА.
#
# Первая редакция звала разрывом честную транзитивность и была
# исправлена «наибольшим связным префиксом с начала». Это была починка
# СИМПТОМА, и она куплена молчанием: префикс берётся ПО ПОРЯДКУ ТЕКСТА,
# а значит суд судит порядок. Опыт: «B ведёт к C. A ведёт к B. A ведёт
# к C.» — та же цепь, переставленная в тексте, все зависимости целы, —
# объявлялась ЛОЖЬЮ. Дефект назван verum-6c и подтверждён прогоном.
#
# ВЕРНЫЙ ЗАКОН: звено либо ОСНОВНОЕ, либо ВЫВЕДЕННОЕ. Выведенное — то,
# до чего есть путь БЕЗ НЕГО САМОГО; основное — то, без чего пути нет.
# Основные обязаны складываться в ОДНУ простую цепь, покрывающую все
# названные узлы; выведенные обязаны быть по ней достижимы. Порядок
# текста в этот счёт не входит вовсе, и потому перестановка вердикта не
# меняет — а обрубок падает, и падает С АДРЕСОМ.
def цепь_держится(звенья, назвать=None):
    """Держится ли цепь по зависимостям; `назвать` получает адрес разрыва."""
    if not звенья:
        return False
    звенья = list(dict.fromkeys(звенья))
    основные, выведенные = [], []
    for i, (u, v) in enumerate(звенья):
        без_него = звенья[:i] + звенья[i + 1:]
        (выведенные if путь(без_него, u, v) is not None
         else основные).append((u, v))
    if not основные:
        return False
    исходит = collections.Counter(u for u, _ in основные)
    входит = collections.Counter(v for _, v in основные)
    узлы = set(исходит) | set(входит)
    if any(исходит[у] > 1 or входит[у] > 1 for у in узлы):
        if назвать is not None:
            назвать("основные звенья ветвятся — это не цепь")
        return False
    начала = [у for у in узлы if not входит[у]]
    if len(начала) != 1 or len(основные) != len(узлы) - 1:
        if назвать is not None:
            назвать(f"основные звенья не сходятся в одну цепь: "
                    f"начал {len(начала)}, звеньев {len(основные)}, "
                    f"узлов {len(узлы)}")
        return False
    for u, v in выведенные:
        if путь(основные, u, v) is None:
            if назвать is not None:
                назвать(f"звено {u}→{v} не выводится из цепи")
            return False
    # ВСЕ УЗЛЫ ЦЕПИ ОБЯЗАНЫ БЫТЬ НАЗВАНЫ ЕЮ ЖЕ: узел, помянутый лишь в
    # выведенном звене, есть утверждение о том, чего цепь не содержит.
    помянуты = {у for звено in звенья for у in звено}
    if помянуты - узлы:
        if назвать is not None:
            назвать(f"узлы вне цепи: {sorted(помянуты - узлы)}")
        return False
    return True


def разбор_графа(строка):
    """(узлы, рёбра) диаграммы mermaid, или None."""
    if not ГРАФ.match(строка.strip()):
        return None
    рёбра = РЕБРО.findall(строка)
    if not рёбра:
        return None
    узлы = {у for пара in рёбра for у in пара}
    return узлы, рёбра


def путь(рёбра, откуда, куда):
    """Длина кратчайшего пути ОБХОДОМ, или None."""
    смежность = collections.defaultdict(list)
    for a, b in рёбра:
        смежность[a].append(b)
    очередь, видано = collections.deque([(откуда, 0)]), {откуда}
    while очередь:
        узел, шагов = очередь.popleft()
        if узел == куда:
            return шагов
        for сосед in смежность[узел]:
            if сосед not in видано:
                видано.add(сосед)
                очередь.append((сосед, шагов + 1))
    return None


