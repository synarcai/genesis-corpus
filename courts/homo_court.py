#!/usr/bin/env python3
"""[ОМОГРАФ] — совпадение письма у двух языков, пересчитанное судом по самим пакетам.

Суд не пишет закона заново: он берёт его у дома (`homoforms`), а дом НЕ ХРАНИТ списка
омографов — он читает `tools/langpacks/*.json` и выводит их заново при всяком запросе.

    СПИСОК, ПЕРЕПИСАННЫЙ В ДОМ ИЗ ПАКЕТА, РАЗОЙДЁТСЯ С ПАКЕТОМ В ДЕНЬ ПЕРВОЙ ЖЕ ПРАВКИ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: перепись обязана быть ЖИВОЙ (омографов не
ноль, форм не горсть) и ПОВТОРИМОЙ — два чтения пакетов обязаны дать одно и то же, иначе мир
не будет воспроизводим; всякий показанный омограф обязан нести не менее двух РАЗНЫХ языков;
всякий язык обязан иметь объявленное имя И творительный падеж, отличный от именительного —
падеж объявляют, а не выводят.

    python3 courts/homo_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import homoforms  # noqa: E402 — дом, объявивший множитель размерности

ИМЯ_СУДА = "homo"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"homo"})


def _судить(строка):
    return homoforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ОМОГРАФ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(homoforms.РОДЫ)}, страниц {len(homoforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
