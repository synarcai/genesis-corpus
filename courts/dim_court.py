#!/usr/bin/env python3
"""[РАЗМЕРНОСТЬ] — что складывается, что умножается, пересчитано судом.

Суд не пишет закона заново: он берёт его у дома (`dimforms`), где единицы, произведения и
частные объявлены тремя таблицами. Всякая сумма, произведение, частное и сравнение
пересчитываются порознь.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ЧЕГО СУД НЕ ПРОВЕРЯЕТ, И ЭТО ГРАНИЦА, А НЕ УПУЩЕНИЕ: он не знает, что метр меряет длину,
а килограмм массу. Однородность мер ОБЪЯВЛЕНА домом и стережётся его самопроверкой —
две единицы, мерящие одно, обратили бы законное сложение в показанный отказ.

    python3 courts/dist_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import dimforms  # noqa: E402 — дом, объявивший законы расстояния

ИМЯ_СУДА = "dim"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"dim"})


def _судить(строка):
    return dimforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"РАЗМЕРНОСТЬ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(dimforms.РОДЫ)}, страниц {len(dimforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
