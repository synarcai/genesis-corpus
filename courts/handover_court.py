#!/usr/bin/env python3
"""[СУД СЛЕЖЕНИЯ ЗА ВЕЩАМИ] — обмены разыграны заново по записи; МИР ЗАМКНУТ.

Страница мира (`tools/handoverforms.py`) есть зачин (у кого что в начале), ряд обменов и
вопрос о чьих-то руках. Суд НЕ БЕРЁТ у дома ни начала, ни ряда: он читает ЗАПИСЬ — кто с
чего начал, кто с кем менялся — и ведёт свои руки шаг за шагом.

    ОБМЕН НИЧЕГО НЕ СОЗДАЁТ И НЕ ТЕРЯЕТ. Сколько вещей было, столько и осталось; меняется
    только рука. Из умения вычитать («отдала 1 монету, осталось 4») это не следует ничем, и
    потому мир отдельный.

Порча имени, вещи или порядка обменов меняет вердикт: имя вне зачина — запись не судима,
вещь вне объявленных — то же, переставленные обмены — иной ответ.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import handoverforms as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"handover"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    зачин = "Анна держит мяч, Борис держит книгу, Вера держит ключ. "

    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО (14.09). Подсадка бывает
    # СУДИМА И ИСТИННА — тогда лгал сам список: строка похожа на ложь, а есть правда.
    # Бывает и НЕСУДИМА — тогда она выпала из рамки дома, и прибор, считающий её просто
    # «непойманной», молчит о том, что перестал её читать вовсе. Суд скобок так и потерял
    # четыре подсадки из семи, когда рамка вопроса переменилась.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_handover.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_handover.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_handover.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"СЛЕЖЕНИЕ ЗА ВЕЩАМИ {поза}: {итог['ложных']} ложных из {итог['судимых']} "
          f"судимых, несудимых {итог['несудимых']}; подсадок поймано {пойманы} "
          f"из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
