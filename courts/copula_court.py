#!/usr/bin/env python3
"""[СВЯЗКИ] — утверждение о мире сверяется с ОБЪЯВЛЕНИЕМ, а не с числом.

«вода — это жидкость» нельзя пересчитать: это факт о мире, а не о
счёте. Но он не взят с потолка — он ОБЪЯВЛЕН в генераторе слоя, и
потому проверяем: всякая связка корпуса обязана отвечать объявленной
паре своего рода.

Так ловится дрейф, которого не увидит ни один счётный прибор: правка
шаблона, перепутавшая роды («вода вызывает жидкость»), перестановка
сторон («жидкость — это вода»), слово, попавшее в показ из соседнего
рода. Слой стоял НЕСУДИМЫМ вовсе — ноль процентов, — и это опаснее
слоя с найденной ложью: там знают, что искать.

ЧЕТЫРЕ РОДА РАЗЛИЧАЮТСЯ НЕ ФОРМОЙ, А ОТНОШЕНИЕМ: определение (что есть
что), причина (что вызывает что), состав (что содержит что) и часть
(что чему принадлежит). Одна и та же пара в другом роде — ложь:
«клетка содержит ядро» истинно, «клетка — это ядро» нет.

ПОРЯДОК СТОРОН ЗНАЧИМ. Отношения несимметричны, и суд требует именно
объявленного порядка: вода есть жидкость, но жидкость не есть вода.

ЧЕГО СУД НЕ НАЗЫВАЕТ ЛОЖЬЮ, НО СЧИТАЕТ. Перевёрнутая русская пара
меняет падеж («ядро — часть клетки» против «клетка — часть ядра»), и
формы перестают совпадать с объявленными. Суд не зовёт такое ложью — он
не знает падежей, — но и не молчит: пара уходит в счёт НЕЗНАКОМЫХ,
который на здоровом корпусе равен нулю. Всякий дрейф поднимает этот
счёт, и потому молчание здесь не читается как чистота.
"""
import ast
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ГЕНЕРАТОР = КОРЕНЬ / "tools/gen_genesis_l4.py"


def объявленное():
    """{род: {(что, чему)}} — из генератора слоя, а не из головы.

    ОТСУТСТВИЕ ОБЪЯВЛЕНИЯ ЕСТЬ ОТКАЗ, А НЕ ЧИСТОТА (М-88): суд без
    источника не вправе сказать «ноль лжи».
    """
    try:
        дерево = ast.parse(ГЕНЕРАТОР.read_text(encoding="utf-8"))
    except OSError as беда:
        print(f"СВЯЗКИ ОТКАЗ: генератор не читается ({беда})")
        sys.exit(2)
    for узел in ast.walk(дерево):
        if (isinstance(узел, ast.Assign)
                and getattr(узел.targets[0], "id", None) == "FACTS"):
            сырое = ast.literal_eval(узел.value)
            вон = {}
            for род, пары in сырое.items():
                вон[род] = set()
                for (ru, en) in пары:
                    вон[род].add(tuple(x.lower() for x in ru))
                    вон[род].add(tuple(x.lower() for x in en))
            return вон
    print("СВЯЗКИ ОТКАЗ: FACTS не найдено в генераторе")
    sys.exit(2)


ФАКТЫ = объявленное()
НЕЗНАКОМЫЕ = []
# (род, образец) — сторона «что» первой, сторона «чему» второй
# ЧАСТНОЕ ПЕРЕД ОБЩИМ. Образец «X is Y» перехватывал вопросную форму
# «what is oxygen? oxygen is a gas» целиком, давая парой всё до «is», —
# и суд молчал там, где обязан был судить. Порядок здесь не украшение.
ОБРАЗЦЫ = [
    # вопросные формы — самые частные
    ("def", re.compile(r"^что такое (.+?)\? \1 — это (.+?)\.$")),
    ("def", re.compile(r"^what is (.+?)\? \1 is (.+?)\.$")),
    # отношения со своим глаголом или предлогом
    ("part", re.compile(r"^(.+?) — часть (.+?)\.$")),
    ("part", re.compile(r"^(.+?) is part of (.+?)\.$")),
    ("cause", re.compile(r"^(.+?) вызывает (.+?)\.$")),
    ("cause", re.compile(r"^(.+?) causes (.+?)\.$")),
    ("contain", re.compile(r"^(.+?) содержит (.+?)\.$")),
    ("contain", re.compile(r"^(.+?) contains (.+?)\.$")),
    # определение — самое общее, и потому ПОСЛЕДНЕЕ: «a wheel is part of
    # the car» перехватывалось им как определение колеса через «part of
    # the car», и счётчик незнакомых пар назвал это в первом же прогоне.
    ("def", re.compile(r"^(.+?) — это (.+?)\.$")),
    ("def", re.compile(r"^(.+?) is (.+?)\.$")),
]


def судить(строка):
    с = строка.strip()
    for род, образец in ОБРАЗЦЫ:
        m = образец.match(с)
        if not m:
            continue
        пара = (m.group(1).lower().strip(), m.group(2).lower().strip())
        объявлено = ФАКТЫ.get(род, set())
        if пара in объявлено:
            return True, True
        # ПАРА, ЖИВУЩАЯ В ДРУГОМ РОДЕ, ЕСТЬ ЛОЖЬ, А НЕ НЕЗНАКОМСТВО:
        # «клетка — это ядро» построено из объявленной пары, но не того
        # отношения, и именно такую подмену счёт не заметит.
        for иной, пары in ФАКТЫ.items():
            if иной != род and (пара in пары or пара[::-1] in пары):
                return True, False
        if пара[::-1] in объявлено:
            return True, False   # стороны переставлены
        # ПАРА НЕЗНАКОМА — не судим, но и не молчим: связка объявленной
        # ФОРМЫ с необъявленной парой есть либо новый факт (тогда его
        # место в объявлении), либо дрейф. Молчание тут читалось бы как
        # чистота, и потому оно СЧИТАЕТСЯ отдельно.
        НЕЗНАКОМЫЕ.append(f"{род}: {пара[0]} / {пара[1]}")
        return False, True
    return False, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"СВЯЗКИ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("СВЯЗКИ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:70]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"СВЯЗКИ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)"
          + (f", НЕЗНАКОМЫХ ПАР {len(set(НЕЗНАКОМЫЕ))}: "
             f"{sorted(set(НЕЗНАКОМЫЕ))[:3]}" if НЕЗНАКОМЫЕ else ""))
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
