#!/usr/bin/env python3
"""[ПОЛЬСКАЯ СВЯЗКА] — согласие страницы с домом языка, пересчитанное судом.

Суд не знает польского. Он берёт всякую пару «число + имя» и всякую тройку «число + имя +
связка» и спрашивает у дома языка (`plgram.форма`, `plgram.связка`), что полагается этой
счётной ячейке. Ни форма, ни связка здесь не выведены.

    СУД, СВЕРЯЮЩИЙ ФОРМУ С ЗАКОНОМ ДОМА ЯЗЫКА, СИЛЁН РОВНО ТЕМ, ЧТО САМ ЯЗЫКА НЕ ЗНАЕТ.

СВЯЗКА СВЕРЯЕТСЯ С ОБЕИМИ ВРЕМЕНАМИ РАЗОМ: страница говорит и о настоящем, и о прошедшем, и
суду довольно, чтобы стоящее слово было ОДНИМ ИЗ ДВУХ законных при этой ячейке. Требовать
большего значило бы заставить суд разбирать время предложения — работу, которой он не умеет и
которая ему не поручена.

    python3 courts/plcopula_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import plcopulaforms  # noqa: E402 — дом, показывающий закон польской связки

ИМЯ_СУДА = "plcopula"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"plcopula"})


def _судить(строка):
    return plcopulaforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ПОЛЬСКАЯ СВЯЗКА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(plcopulaforms.РОДЫ)}, "
          f"страниц {len(plcopulaforms.ПОКАЗЫ)}, пар имён {len(plcopulaforms.ПАРЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
