#!/usr/bin/env python3
"""[СУД ДОЛИ И ЕЁ ОСНОВАНИЯ] — доли пересчитаны по таблице, основание сверено; МИР ЗАМКНУТ.

Страница мира (`tools/condprob.py`) несёт ВСЕ ЧЕТЫРЕ числа таблицы и одну долю с названным
основанием. Суд считает доли сам и требует, чтобы основание было названо ВЕРНО.

    ДОЛЯ БЕЗ ОСНОВАНИЯ НЕ ЕСТЬ ЧИСЛО. «9 из 20» и «9 из 12» суть разные доли одного и того
    же счёта.

    ДВЕ УСЛОВНЫЕ ДОЛИ НЕ РАВНЫ ДРУГ ДРУГУ: «девять из двенадцати девочек в очках» и «девять
    из пятнадцати очкариков — девочки» стоят на одном числе сверху и на разных снизу.

Числа хвоста читаются ОТДЕЛЬНЫМИ дырами, а не ссылками на зачин, — и это не мелочь записи:
со ссылками рамка сама не пускала бы страницу с чужим основанием, и сильнейшая ложь стала бы
НЕСУДИМОЙ вместо ложной. Суд обязан мочь назвать её ложью, а не промолчать.

Сверх того суд требует, чтобы ТАБЛИЦА СХОДИЛАСЬ: части не превышают целого, целое равно
сумме. Иначе доля считалась бы от выдуманного основания.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import condprob as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"condprob"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_condprob.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_condprob.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_condprob.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ДОЛЯ И ЕЁ ОСНОВАНИЕ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
