#!/usr/bin/env python3
"""[ПЛАН] — вердикт посадки СЛЕДУЕТ из сличения леджера с условием, а не из словаря.

    ОТЧЁТ ЕСТЬ ЗАПИСЬ НАБЛЮДЕНИЯ. Страница дома плана несёт условие («если exit = 0, посади»),
    отчёт («files 1, runs 1, exit 0, millis 700») и вердикт; суд читает отчёт, сличает
    названный леджер с числом условия и требует, чтобы вердикт был следствием, а не мнением.

Подмена вердикта делает страницу ложной: «exit 3 … посажено» суд зовёт ложью, не спрашивая
ни у какого языка. Так же ложна подмена ответа о леджере — «exit 3 … какой exit? 0».

    СЛОВА ДЕВЯТИ ЯЗЫКОВ СУД БЕРЁТ ТАМ ЖЕ, ГДЕ ИХ БЕРЁТ ДОМ (`planlang.СЛОВА`), и потому
    разойтись с домом не может: список объявления один на обоих.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import planlang as P  # noqa: E402
import actturn as A  # noqa: E402

ИМЯ_СУДА = "plan"

ОТЧЁТ = re.compile(r"files (\d+), runs (\d+), exit (\d+), millis (\d+)")
УСЛОВИЕ_ЧИСЛО = re.compile(r"exit\D{0,12}?(\d+)")


def _языки(с):
    """Все языки, чьё слово отчёта стои́т в строке.

    ОДНО СЛОВО МОЖЕТ ПРИНАДЛЕЖАТЬ ДВУМ ЯЗЫКАМ: «rapport» есть и французское, и нидерландское,
    и суд, бравший ПЕРВЫЙ подошедший, читал нидерландскую страницу французскими словами и
    звал её ложью. Берутся ВСЕ, и страница истинна, если она истинна ХОТЬ НА ОДНОМ из них.
    """
    return [(я, сл) for я, сл in P.СЛОВА.items()
            if re.search(r"(?:^|[.!?] )" + re.escape(сл["отчёт"]) + ":", с)]


# ЗАКОН ПОКРЫТИЯ: СУД, ЧИТАЮЩИЙ СТРОКУ ЦЕЛИКОМ, ОБЯЗАН ЧИТАТЬ И КАЖДОЕ ЕЁ ПРЕДЛОЖЕНИЕ.
#
# Палата зачитывает строку лишь тогда, когда покрыты все её части: страница «si exit es 0,
# aterriza. informe: … ¿aterrizó? no.» была прочитана судом целиком и ОТВЕРГНУТА палатой,
# ибо предложение приказа «si exit es 0, aterriza» в одиночку не читал никто. Ворота записи
# назвали это несудимостью 200 страниц — и правильно назвали.
#
#     СУД, БЕРУЩИЙ ДЛИННУЮ СТРОКУ И МОЛЧАЩИЙ О ЕЁ ПОЛОВИНЕ, ЗАЧИТЫВАЕТ НЕПРОЧИТАННОЕ.
#
# Потому здесь объявлены и одиночные предложения плана: приказ акта, шаг следования и условие.
# Проверяются они СЛОВАРЁМ ОБЪЯВЛЕНИЯ — акт и файл обязаны быть объявленными, леджер условия
# обязан быть из наблюдения, — а не истиной, которой в приказе ещё нет.
def _приказ(с):
    """«создай файл a.txt» — акт и файл объявлены."""
    for _язык, слова in P.СЛОВА.items():
        for акт, формы in A.ГЛАГОЛЫ.get(_язык, {}).items():
            начало = f"{формы[0]} {слова['файл']} "
            if с.startswith(начало):
                return True, с[len(начало):].strip() in A.ФАЙЛЫ
    return False, True


def _след(с):
    """«затем запусти сборку» — слово следования и акт запуска объявлены."""
    for _язык, слова in P.СЛОВА.items():
        if с == f"{слова['затем']} {слова['запусти']}":
            return True, True
    return False, True


def _условие(с):
    """«если exit = 0, посади» — леджер из наблюдения, число целое."""
    for _язык, слова in P.СЛОВА.items():
        for значение in range(0, 10):
            if с == слова["условие"].format(v=значение, посади=слова["посади"]):
                return True, True
    return False, True



ОТВЕТ_СО_СЛИЧЕНИЕМ = re.compile(r"^(.+?): exit (\d+) ([=\u2260]) (\d+)$")


def _ответ(с):
    """«нет: exit 2 ≠ 0» — ответ, несущий СВОЁ основание, и потому проверяемый в одиночку."""
    м = ОТВЕТ_СО_СЛИЧЕНИЕМ.match(с)
    if not м:
        return False, True
    слово, выход, знак, условное = м.group(1).strip(), int(м.group(2)), м.group(3), int(м.group(4))
    сличение = (выход == условное) if знак == "=" else (выход != условное)
    for _язык, слова in P.СЛОВА.items():
        if слово == слова["да"]:
            return True, сличение and выход == условное
        if слово == слова["нет"]:
            return True, сличение and выход != условное
    return False, True



def судить(строка, *_):
    с = строка.strip().rstrip(".")
    м = ОТЧЁТ.search(с)
    if not м:
        for проверка in (_приказ, _след, _условие, _ответ):
            если, верно = проверка(с)
            if если:
                return True, верно
        return False, True
    кандидаты = _языки(с)
    if not кандидаты:
        return False, True
    итог = None
    for _язык, слова in кандидаты:
        если, верно = _судить_языком(с, м, слова)
        if если and верно:
            return True, True
        if если:
            итог = (True, False)
    return итог or (False, True)


def _судить_языком(с, м, слова):
    _файлов, запусков, выход, _милли = (int(x) for x in м.groups())
    голова = с[:м.start()]
    # ВЕРДИКТ СЛЕДУЕТ ИЗ СЛИЧЕНИЯ, А НЕ ИЗ СЛОВАРЯ
    if с.endswith(слова["посажено"]) or с.endswith(слова["не_посажено"]):
        у = УСЛОВИЕ_ЧИСЛО.search(голова)
        if у is None:
            return True, False
        сказано = с.endswith(слова["посажено"]) and not с.endswith(слова["не_посажено"])
        return True, сказано == (выход == int(у.group(1)))
    # ВОПРОС БЕЗ СВОЕГО ОТВЕТА — НЕ МОЙ ВЕРДИКТ, А ЧУЖОЙ ВОПРОС (08.09).
    #
    # Палата режет строку по вопросительному знаку и спрашивает суд о ПОЛОВИНАХ: «отчёт: … —
    # посажено ли?» отдельно и «нет.» отдельно. Суд, называвший первую половину ЛОЖЬЮ за то,
    # что ответа в ней нет, лгал сам: ответ есть, он за знаком вопроса, и связывает их дом
    # пары, а не этот суд.
    #
    #     СУД, СУДЯЩИЙ ПОЛОВИНУ ПАРЫ КАК ЦЕЛОЕ, ЗОВЁТ ЛОЖЬЮ СВОЮ СОБСТВЕННУЮ СЛЕПОТУ.
    for зачин, значение in ((слова["какой_exit"], выход),
                            (слова["сколько_запусков"], запусков)):
        если = с.find(зачин)
        если = если if если >= 0 else None
        if если is not None:
            хвост = с[если + len(зачин):].strip()
            if not хвост:
                return False, True
            return True, хвост.isdigit() and int(хвост) == значение
    если = с.find(слова["посажено_ли"])
    if если >= 0:
        ответ = с[если + len(слова["посажено_ли"]):].strip()
        if not ответ:
            return False, True          # вопрос без ответа — половина пары, не мой вердикт
        # ОТВЕТ НЕСЁТ СВОЁ ОСНОВАНИЕ ЗА ДВОЕТОЧИЕМ («нет: exit 2 ≠ 0»), и основание это
        # проверяется отдельным правилом; здесь берётся слово вердикта.
        основание = ОТВЕТ_СО_СЛИЧЕНИЕМ.match(ответ)
        if основание is not None:
            если_ответ, верно_ответ = _ответ(ответ)
            if если_ответ and not верно_ответ:
                return True, False
            ответ = основание.group(1).strip()
        у = УСЛОВИЕ_ЧИСЛО.search(голова)
        if у is None or ответ not in (слова["да"], слова["нет"]):
            return True, False
        return True, (ответ == слова["да"]) == (выход == int(у.group(1)))
    return True, False


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.name}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ПЛАН {поза}: {ложных} ложных вердиктов из {судимо} судимых (рубеж 0)")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
