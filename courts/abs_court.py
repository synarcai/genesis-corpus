#!/usr/bin/env python3
"""[МОДУЛЬ ЧИСЛА] — расстояние до нуля, пересчитанное судом.

Суд не пишет закона заново: он берёт его у дома (`absforms`), где рамки и числа объявлены одной
таблицей. Подмена модуля, суммы модулей и самой ЛОВУШКИ ловится машинально: модуль считается
здесь, и ни один прибор свода его прежде не считал — слово «модуль» в своде занято ОСТАТКОМ ПО
МОДУЛЮ, иным понятием.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ПРЯМАЯ ЧЕРТА ЕСТЬ ГРАНИЦА ЧИСЛА: образец, читающий «|−2| + |1| = 3» как «|1| = 3», берёт второе
слагаемое вместе с итогом всей суммы и зовёт истину ложью.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/abs_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import absforms  # noqa: E402 — дом, объявивший модуль числа

ИМЯ_СУДА = "abs"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"abs"})


def _судить(строка):
    return absforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"МОДУЛЬ ЧИСЛА {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(absforms.РОДЫ)}, страниц {len(absforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
