#!/usr/bin/env python3
"""[ГЕОМЕТРИЯ] — суд ВЫВОДИТ меру фигуры заново.

    a rectangle 3 by 4 has area 12 and perimeter 14.
    a right triangle with legs 3 and 4 has hypotenuse 5.
    a box 2 by 3 by 4 has volume 24 and surface 52.

МЕРА ФИГУРЫ НЕ ИЗМЕРЯЕТСЯ, А ВЫВОДИТСЯ, и потому проверяема нацело:
площадь есть произведение, периметр — сумма, объём — три множителя.
Показ, назвавший площадь верно, а периметр неверно, есть ложь, которую
не поймает суд, проверяющий одно из двух: здесь считаются ОБА.

ГИПОТЕНУЗА ПРОВЕРЯЕТСЯ КВАДРАТАМИ, А НЕ КОРНЕМ: целое, чей квадрат
равен сумме квадратов, есть точный ответ; всё прочее — приближение, и
корпус его не пишет.

ВОПРОС СУДИТСЯ ТЕМ ЖЕ ХОДОМ, ЧТО И УТВЕРЖДЕНИЕ. Строка «чему равна
площадь прямоугольника 4 на 5? прямоугольник 4 на 5 имеет площадь 20 и
периметр 18» есть ОДНА пара, и суд берётся за неё лишь тогда, когда
судим её ОТВЕТ: вопросная форма принадлежит всем родам сразу. Связь
половин проверяет общий дом `tools/asking.py` — величины вопроса суть
начальный отрезок величин ответа, — и порча любой из них рвёт пару.

ОТКАЗ ЕСТЬ ТАКОЕ ЖЕ УТВЕРЖДЕНИЕ, И ПРОВЕРЯЕТСЯ ТАК ЖЕ. «Целого ответа
нет для катетов 2 и 3: 2² + 3² = 13, а 13 не полный квадрат» истинно
ровно тогда, когда сумма посчитана верно И корень из неё не целый; суд
считает оба, а не верит слову «нет».
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import asking  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# ПРОМЕЖУТОЧНЫЕ ВЕЛИЧИНЫ В ОТВЕТЕ (коллегия 03.09, П-1): показ несёт и счёт, и
# итог, и суд сверяет каждое звено: множители — стороны, произведение — счёт.
# ОДНА ВЕЛИЧИНА ИЛИ ОБЕ: утверждение о фигуре несёт площадь, периметр или
# обе (ответ на вопрос называет только спрошенную величину); суд считает
# каждую названную и требует хотя бы одну.
_ПЛ_EN = r" area (\d+) × (\d+) = (\d+)"
_ПЕР_EN = r" perimeter (\d+) \+ (\d+) = (\d+), 2 × (\d+) = (\d+)"
_ПЛ_RU = r" площадь (\d+) × (\d+) = (\d+)"
_ПЕР_RU = r" периметр (\d+) \+ (\d+) = (\d+), 2 × (\d+) = (\d+)"
ПРЯМОУГОЛЬНИК = re.compile(
    rf"^(?:a rectangle (\d+) by (\d+) has(?:{_ПЛ_EN}(?: and{_ПЕР_EN})?|{_ПЕР_EN})"
    rf"|прямоугольник (\d+) на (\d+) имеет(?:{_ПЛ_RU}(?: и{_ПЕР_RU})?|{_ПЕР_RU}))\.$")
_КПЛ_EN = r" area (\d+) × (\d+) = (\d+)"
_КПЕР_EN = r" perimeter 4 × (\d+) = (\d+)"
_КПЛ_RU = r" площадь (\d+) × (\d+) = (\d+)"
_КПЕР_RU = r" периметр 4 × (\d+) = (\d+)"
КВАДРАТ = re.compile(
    rf"^(?:a square with side (\d+) has(?:{_КПЛ_EN}(?: and{_КПЕР_EN})?|{_КПЕР_EN})"
    rf"|квадрат со стороной (\d+) имеет(?:{_КПЛ_RU}(?: и{_КПЕР_RU})?|{_КПЕР_RU}))\.$")
ТРЕУГОЛЬНИК = re.compile(
    r"^(?:a triangle with base (\d+) and height (\d+) has area (\d+) × (\d+) ÷ 2 = (\d+)"
    r"|треугольник с основанием (\d+) и высотой (\d+) "
    r"имеет площадь (\d+) × (\d+) ÷ 2 = (\d+))\.$")
ГИПОТЕНУЗА = re.compile(
    r"^(?:a right triangle with legs (\d+) and (\d+) has hypotenuse (\d+)"
    r"|прямоугольный треугольник с катетами (\d+) и (\d+) "
    r"имеет гипотенузу (\d+)): (\d+) × (\d+) = (\d+), (\d+) × (\d+) = (\d+), (\d+) \+ (\d+) = (\d+), (\d+) × (\d+) = (\d+)\.$")
КВАДРАТЫ = re.compile(r"^(\d+)\^2 \+ (\d+)\^2 = (\d+)\^2\.$")
# ОДНА ВЕЛИЧИНА ИЛИ ОБЕ (как у прямоугольника): объём, поверхность или обе.
_ОБ = r" (\d+) × (\d+) = (\d+), (\d+) × (\d+) = (\d+)"
_ПОВ = r" (\d+) × (\d+) = (\d+), (\d+) × (\d+) = (\d+), (\d+) × (\d+) = (\d+), (\d+) \+ (\d+) \+ (\d+) = (\d+), 2 × (\d+) = (\d+)"
КОРОБКА = re.compile(
    rf"^(?:a box (\d+) by (\d+) by (\d+) has(?: volume{_ОБ}(?: and surface{_ПОВ})?| surface{_ПОВ})"
    rf"|коробка (\d+) на (\d+) на (\d+) имеет(?: объём{_ОБ}(?: и поверхность{_ПОВ})?| поверхность{_ПОВ}))\.$")
КУБ = re.compile(
    r"^(?:a cube with edge (\d+) has volume|куб с ребром (\d+) имеет объём) (\d+) × (\d+) = (\d+), (\d+) × (\d+) = (\d+)\.$")
# ЦЕЛОСТЬ — ВЕРДИКТ С ОСНОВАНИЕМ: «да» несёт корень, «нет» — сумму
# квадратов, не являющуюся квадратом; суд считает обе.
ЦЕЛОСТЬ_ГИПОТЕНУЗЫ = re.compile(
    r"^(?:yes: (\d+)\^2 \+ (\d+)\^2 = (\d+) = (\d+)\^2, the hypotenuse is (\d+)"
    r"|no: (\d+)\^2 \+ (\d+)\^2 = (\d+), and (\d+) is not a perfect square"
    r"|да: (\d+)\^2 \+ (\d+)\^2 = (\d+) = (\d+)\^2, гипотенуза равна (\d+)"
    r"|нет: (\d+)\^2 \+ (\d+)\^2 = (\d+), а (\d+) не полный квадрат)\.$")


def полный_квадрат(n):
    """Целое ли число корень — суд считает сам, а не верит показу."""
    к = int(n ** 0.5)
    while к * к < n:
        к += 1
    return к * к == n


def числа(m, сколько):
    """Группы образца, названного двумя языками, — одним рядом."""
    все = [г for г in m.groups() if г is not None]
    return [int(x) for x in все[:сколько]]


import laws  # noqa: E402
ЗАКОНЫ = laws.свод("geometry")
ЗАКОНЫ_ЯЗЫКА = laws.по_языкам("geometry")
import discourse  # noqa: E402


def g_части(числа_, длины):
    """Split the numbers of a one-or-both statement into its named parts:
    the area part comes first when present, the perimeter part after it;
    the lengths name the two parts (area, perimeter)."""
    пл, пер = длины
    if len(числа_) == пл + пер:
        return [tuple(числа_[:пл]), tuple(числа_[пл:])]
    if len(числа_) == пл:
        return [tuple(числа_)]
    if len(числа_) == пер:
        return [tuple(числа_)]
    return []


def судить(строка):
    """(судимо, истинно) для одной строки."""
    if строка.strip() in ЗАКОНЫ:
        return True, True
    с = строка.strip()
    # ВОПРОС ПЕРЕД УТВЕРЖДЕНИЕМ: пара судится ответом, и ответ идёт в
    # тот же ход ниже. Рекурсия конечна — в ответе вопросного знака нет.
    р = discourse.судить_рассуждение_мира(строка, судить, ЗАКОНЫ_ЯЗЫКА)
    if р is not None:
        return р
    если = asking.судить_парой(с, судить)
    if если is not None:
        return если
    m = ПРЯМОУГОЛЬНИК.match(с)
    if m:
        г = [int(x) for x in m.groups() if x is not None]
        a, b, части = г[0], г[1], g_части(г[2:], (3, 5))
        верно = bool(части)
        for часть in части:
            if len(часть) == 3:
                a2, b2, площадь = часть
                верно = верно and (a2, b2) == (a, b) and площадь == a * b
            else:
                a3, b3, сумма, с2, периметр = часть
                верно = верно and (a3, b3) == (a, b) and сумма == a + b and с2 == сумма and периметр == 2 * сумма
        return True, верно
    m = КВАДРАТ.match(с)
    if m:
        г = [int(x) for x in m.groups() if x is not None]
        a, части = г[0], g_части(г[1:], (3, 2))
        верно = bool(части)
        for часть in части:
            if len(часть) == 3:
                a2, a3, площадь = часть
                верно = верно and a2 == a3 == a and площадь == a * a
            else:
                a4, периметр = часть
                верно = верно and a4 == a and периметр == 4 * a
        return True, верно
    m = ТРЕУГОЛЬНИК.match(с)
    if m:
        b, h, b2, h2, площадь = числа(m, 5)
        return True, (b2, h2) == (b, h) and b * h == 2 * площадь
    m = ГИПОТЕНУЗА.match(с)
    if m:
        a, b, c, a1, a2, aa, b1, b2, bb, s1, s2, сумма, c1, c2, кв = числа(m, 15)
        return True, ((a1, a2, b1, b2, c1, c2) == (a, a, b, b, c, c) and aa == a * a and bb == b * b
                      and (s1, s2) == (aa, bb) and сумма == aa + bb and кв == c * c and сумма == кв)
    m = КВАДРАТЫ.match(с)
    if m:
        a, b, c = числа(m, 3)
        return True, a * a + b * b == c * c
    m = КОРОБКА.match(с)
    if m:
        г = [int(x) for x in m.groups() if x is not None]
        a, b, c, части = г[0], г[1], г[2], g_части(г[3:], (6, 15))
        верно = bool(части)
        for часть in части:
            if len(часть) == 6:
                a1, b1, ab, ab2, c1, объём = часть
                верно = верно and (a1, b1, c1) == (a, b, c) and ab == a * b and ab2 == ab and объём == ab * c
            else:
                x1, x2, ab3, y1, y2, bc, z1, z2, ac, s1, s2, s3, сумма, d2, поверхность = часть
                верно = верно and ((x1, x2, y1, y2, z1, z2) == (a, b, b, c, a, c) and ab3 == a * b and bc == b * c and ac == a * c
                                   and (s1, s2, s3) == (ab3, bc, ac) and сумма == ab3 + bc + ac and d2 == сумма and поверхность == 2 * сумма)
        return True, верно
    m = КУБ.match(с)
    if m:
        a, a1, a2, aa, aa2, a3, объём = числа(m, 7)
        return True, (a1 == a2 == a3 == a and aa == a * a and aa2 == aa and объём == aa * a)
    m = ЦЕЛОСТЬ_ГИПОТЕНУЗЫ.match(с)
    if m:
        г = числа(m, 5)
        if len(г) == 5:
            a, b, сумма, c, c2 = г
            return True, (a * a + b * b == сумма and c * c == сумма and c2 == c)
        a, b, сумма, сумма2 = г
        return True, (a * a + b * b == сумма and сумма2 == сумма
                      and not полный_квадрат(сумма))
    return False, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ГЕОМЕТРИЯ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ГЕОМЕТРИЯ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ГЕОМЕТРИЯ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
