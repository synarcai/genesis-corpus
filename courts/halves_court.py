#!/usr/bin/env python3
"""[СОГЛАСИЕ ПОЛОВИН] — вопрос и ответ есть одна строка, и судить их
порознь значит не судить.

МУТАНТНАЯ ПРОБА ПО МИРАМ вскрыла род лжи, которого не видел ни один
суд, и вот он целиком:

    how is |16| said in words? |15| in words is the absolute value of 15.
    как читается {"level": 34}? {"level": 33} в словах …

Каждая половина БЕЗУПРЕЧНА сама по себе: «|15| in words is the absolute
value of 15» верно, «{"level": 33} в словах» верно. Ложь живёт В
РАЗРЫВЕ между половинами — спрошено об одном, отвечено о другом, — и
оттого её не видит никто: всякий суд читает, ЧТО утверждается, и ни
один не читает, О ЧЁМ спрашивалось.

ЭТОТ СУД НЕ ЗНАЕТ НИ АРИФМЕТИКИ, НИ ЯЗЫКОВ. Он знает одно: ОДНА И ТА
ЖЕ ВЕЩЬ, НАЗВАННАЯ ДВАЖДЫ В ОДНОЙ СТРОКЕ, ОБЯЗАНА БЫТЬ ОДНОЙ. Он не
сверяет числа половин — «сколько будет 20% от 80? это 16» не обязано
повторять восьмидесяти, — он сверяет ЦИТИРУЕМУЮ ЗАПИСЬ: то, что взято
в свои скобки и потому названо, а не сказано.

РАЗДЕЛИТЕЛЬ И РОД ЗАПИСИ ВЫВЕДЕНЫ ЗАМЕРОМ КОРПУСА, А НЕ ВЗЯТЫ ИЗ
ГОЛОВЫ. Замер (184 393 строки показов) дал разделители «?» (20 676
строк), «;» (12 686) и четыре именных — «solution:», «answer:»,
«решение:», «ответ:» (по 24). Он же назвал роды записи, цитируемые
ОБЕИМИ половинами, и сказал, у каких половины расходятся на ЧЕСТНОМ
корпусе:

    |N|   186 строк, разошлось 0
    {…}   610 строк, разошлось 0
    $…$   432 строки, разошлось 0
    […]   470 строк, разошлось 0
    «…»   810 строк, РАЗОШЛОСЬ 120 — и род отвергнут

ПОЧЕМУ «…» ОТВЕРГНУТ, И ЭТО ГЛАВНАЯ ОСТОРОЖНОСТЬ СУДА. Кавычка русского
письма называет РАЗНЫЕ вещи в двух половинах законно: «what does a
block opening with «:::warning» mean? three colons and «warning» open
an admonition» — вопрос цитирует зачин, ответ цитирует имя, и обе
цитаты верны. Взяв этот род, суд объявил бы ложью сто двадцать честных
строк мира разметки. Род, у которого замер нашёл расхождения на
здоровом корпусе, В СУД НЕ БЕРЁТСЯ: где сомневаешься — молчи, ибо
молчание честнее ложного вердикта, и два суда здесь уже были казнены
за обратное.

ЧЕГО ЭТОТ СУД НЕ ЛОВИТ, И ЭТО НАЗВАНО, А НЕ СПРЯТАНО. Разрыв бывает и
там, где ни одна половина ничего не цитирует:

    task: x plus 8 equals 10. solution: x = 10 − 7 = 3.
    kinetic energy = mass × speed squared / 3; 16 × 3 × 3 / 2 = 72 joules.

Здесь расходятся не записи, а СЧЁТ задачи со счётом решения и запись
закона со своим примером. Их обязан прочесть суд, умеющий считать, —
свой у каждого рода; этот молчит о них честно.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# РАЗДЕЛИТЕЛЬ ПОЛОВИН, ВЫВЕДЕННЫЙ ЗАМЕРОМ. Строка режется по ПЕРВОМУ
# его появлению: вопрос кончается там, где стоит вопросительный знак, а
# закон — там, где стоит точка с запятой перед примером.
РАЗДЕЛИТЕЛЬ = re.compile(
    r"\?|;|\bsolution:|\banswer:|\bрешение:|\bответ:")

# РОД ЗАПИСИ — то, что взято в СВОИ скобки и потому НАЗВАНО, а не
# сказано. Четыре рода, и каждый прошёл замер на здоровом корпусе с
# нулём расхождений. Длина ограничена нарочно: запись есть короткая
# цитата, а не пол-строки — иначе род расползётся на текст.
РОДЫ = (
    ("|N|", re.compile(r"\|[^|\n]{1,40}\|")),
    ("{…}", re.compile(r"\{[^{}\n]{1,80}\}")),
    ("$…$", re.compile(r"\$[^$\n]{1,80}\$")),
    ("[…]", re.compile(r"\[[^\[\]\n]{1,60}\]")),
)


def половины(строка):
    """(левая, правая) по первому разделителю, или None — его нет."""
    м = РАЗДЕЛИТЕЛЬ.search(строка)
    if м is None:
        return None
    лево, право = строка[:м.start()], строка[м.end():]
    if not лево.strip() or not право.strip():
        return None
    return лево, право


def судить(строка, слой=None):
    """(судимо, истинно) для одной строки.

    СУДИМО РОВНО ТО, ЧТО ЦИТИРУЮТ ОБЕ ПОЛОВИНЫ. Запись, названная лишь
    одной из них, ни о чём не говорит: ответ вправе не повторять
    вопроса. Оттого суд молчит обо всём, кроме прямого совпадения рода.
    """
    с = строка.strip()
    if not с:
        return False, False
    пара = половины(с)
    if пара is None:
        return False, False
    лево, право = пара
    судимо = False
    for _имя, образец in РОДЫ:
        слева = образец.findall(лево)
        справа = образец.findall(право)
        if not слева or not справа:
            continue
        судимо = True
        # СВЕРЯЕТСЯ ПЕРВАЯ ЗАПИСЬ КАЖДОЙ ПОЛОВИНЫ — именно так мерился
        # корпус, и именно на этом правиле замер дал ноль расхождений.
        if слева[0] != справа[0]:
            return True, False
    return (True, True) if судимо else (False, False)


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ПОЛОВИНЫ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ПОЛОВИНЫ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 6:
                        примеры.append(
                            f"{путь.name}: {строка.strip()[:96]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ПОЛОВИНЫ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
