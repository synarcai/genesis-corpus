    print(f"АКТЫ ИНСТРУМЕНТОВ {поза}: {ложных} ложных из {судимо} судимых (рубеж {ЛОЖНЫХ_РУБЕЖ}); страниц дома "
          f"{страниц}, порч самопроверки {порч}, из них поймано рамкой {пойманных}, бед {len(беды)}")
    return 0 if поза == "PASS" else 1


