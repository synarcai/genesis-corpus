def _строки(язык, f):
    запись = T.СОДЕРЖИМОЕ[язык].get(f)
    return None if запись is None else запись[0]


def _сколько(язык, f, w):
    return sum(стр.split().count(w) for стр in _строки(язык, f))


def _где(язык, f, w):
    return [i + 1 for i, стр in enumerate(_строки(язык, f)) if w in стр.split()]


def _есть(f):
    return f in T.ТЕКСТЫ or f in T.ТЕСТЫ


def _лед(было, сдвиг):
    return A.леджер(было, сдвиг)[0]


def _после(L):
    """«a + k = b» → (a, b)."""
    м = re.fullmatch(r"(\d+)(?: [+−] \d+)? = (\d+)", L)
    return int(м.group(1)), int(м.group(2))


def _вердикт(язык, род, зн):
    f = зн.get("f")
    if род in (T.ПОИСК, T.ПОИСК_ОТКАЗ, T.ПОИСК_ВОПРОС):
        if _строки(язык, f) is None:
            return False
        k = _сколько(язык, f, зн["w"])
        if род == T.ПОИСК_ОТКАЗ and k == 0:
            return False
        return зн["N"] == T.раз(язык, k) and зн["L"] == _лед(k, 0)
    if род == T.СТРОКИ:
        if _строки(язык, f) is None:
            return False
        поз = _где(язык, f, зн["w"])
        сказано = [int(зн[к]) for к in ("a", "b") if к in зн]
        if len(поз) == 2 and len(сказано) == 2:
            ок = сказано == поз
        elif len(поз) == 1 and len(сказано) == 1:
            ок = сказано == поз
        else:
            ок = not поз and not сказано
        return ок and зн["N"] == T.строк(язык, len(поз)) and зн["L"] == _лед(len(поз), 0)
    if род in (T.ЗАМЕНА, T.ЗАМЕНА_ОТКАЗ, T.ЗАМЕНА_НЕЧЕГО):
        if _строки(язык, f) is None or зн["w"] == зн["v"]:
            return False
        k, a = _сколько(язык, f, зн["w"]), _сколько(язык, f, зн["v"])
        if род == T.ЗАМЕНА_НЕЧЕГО:
            return k == 0 and зн["N0"] == T.раз(язык, 0) and зн["L0"] == _лед(0, 0)
        if k == 0:
            return False
        if род == T.ЗАМЕНА_ОТКАЗ:
            return зн["N0"] == T.раз(язык, k) and зн["L0"] == _лед(k, 0)
        return (зн["N0"] == T.раз(язык, 0) and зн["L0"] == _лед(k, -k)
                and зн["N1"] == T.раз(язык, a + k) and зн["L1"] == _лед(a, k))
    if род in (T.ДОПИСАТЬ, T.ДОПИСАТЬ_ОТКАЗ):
        if _строки(язык, f) is None:
            return False
        n = len(_строки(язык, f))
        сдвиг = 1 if род == T.ДОПИСАТЬ else 0
        return зн["N"] == T.строк(язык, n + сдвиг) and зн["L"] == _лед(n, сдвиг)
    if род in (T.ДОПИСАТЬ_НЕТ, T.ИМЯ, T.ИМЯ_ЗАНЯТО, T.ИМЯ_НЕТ):
        папка_ок = зн["N"] == A.файлов(язык, T.ПАПКА) and зн["L"] == _лед(T.ПАПКА, 0)
        if род == T.ДОПИСАТЬ_НЕТ:
            return папка_ок and not _есть(f)
        g = зн["g"]
        if род == T.ИМЯ:
            return папка_ок and _есть(f) and not _есть(g)
        if род == T.ИМЯ_ЗАНЯТО:
            return папка_ок and _есть(f) and _есть(g) and f != g
        return папка_ок and not _есть(f) and f != g
    if род == T.ПЕРЕНОС:
        c, d = _после(зн["L1"])
        return (_есть(f) and зн["N0"] == A.файлов(язык, T.ПАПКА - 1) and зн["L0"] == _лед(T.ПАПКА, -1)
                and зн["L1"] == _лед(c, 1) and зн["N1"] == A.файлов(язык, d))
    if род in (T.ПРОГОН, T.ПРОГОН_ОТКАЗ, T.ПЛАН_ВЫПУСКА):
        t = зн["t"]
        if t not in T.ТЕСТЫ:
            return False
        было, стало = _после(зн["L"])
        сдвиг = 0 if род == T.ПРОГОН_ОТКАЗ else 1
        if зн["L"] != _лед(было, сдвиг) or зн["N"] != A.запусков(язык, стало):
            return False
        if род == T.ПРОГОН_ОТКАЗ:
            return True
        всего, падает = T.ТЕСТЫ[t]
        фраза = T.РЕЧЬ[язык]["итог" if род == T.ПРОГОН else "выпуск"][0 if падает == 0 else 1]
        исход = зн["ИСХОД"] if род == T.ПРОГОН else зн["ВЫПУСК"]
        return (зн["П"] == T.прошло(язык, всего - падает, всего) and зн["L0"] == _лед(всего, -падает)
                and исход == T._фр(язык, фраза))
    if род in (T.ПЛАН_ЗАМЕНЫ, T.ПЛАН_ЗАМЕНЫ_ОТКАЗ):
        if _строки(язык, f) is None or зн["w"] == зн["v"]:
            return False
        k, a = _сколько(язык, f, зн["w"]), _сколько(язык, f, зн["v"])
        if k == 0 or зн["Nk"] != T.раз(язык, k):
            return False
        if род == T.ПЛАН_ЗАМЕНЫ_ОТКАЗ:
            return зн["L"] == _лед(k, 0)
        return (зн["N0"] == T.раз(язык, 0) and зн["N1"] == T.раз(язык, a + k) and зн["L1"] == _лед(a, k))
    return False


def _судить(строка):
    с = строка.strip()
    if not с:
        return False, False
    язык = next((я for начало, я in _НАЧАЛО.items() if с.startswith(начало)), None)
    if язык is None:
        return False, False
    совпал = False
    for образ, род, _регистр in РАМКИ[язык]:
        м = образ.match(с)
        if not м:
            continue
        совпал = True
        if род == СКРЕЩЕНО:
            continue
        зн = _значения(м)
        if зн is not None and _вердикт(язык, род, зн):
            return True, True
    return (True, False) if совпал else (False, False)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def _порчи(с):
    """Подсадки от страницы дома: последнее число наблюдения на единицу больше; первое число леджера другое;
    файл в отчёте подменён; слово подменено в наблюдении."""
    вон = []
    числа = list(re.finditer(r"\d+", с))
    if числа:
        п = числа[-1]
        вон.append(с[:п.start()] + str(int(п.group()) + 1) + с[п.end():])
    леджеры = list(re.finditer(r"(\d+)( [+−] \d+)? = (\d+)", с))
    if леджеры:
        л = леджеры[-1]
        вон.append(с[:л.start(1)] + str(int(л.group(1)) + 2) + с[л.end(1):])
    файлы = list(re.finditer(_ФАЙЛ, с))
    if len(файлы) >= 2:
        ф = файлы[-1]
        чужой = next(x for x in T.ТЕКСТЫ + tuple(T.ТЕСТЫ) if x != ф.group())
        вон.append(с[:ф.start()] + чужой + с[ф.end():])
    return [в for в in вон if в != с]


def _самопроверка():
    """Всякая страница дома истинна; всякая порча — ложь, пойманная рамкой, а не молчание."""
    беды = [с for с in T.ПОКАЗЫ if _судить(с) != (True, True)]
    порч = пойманных = 0
    for i, с in enumerate(sorted(T.ПОКАЗЫ)):
        if i % 7:
            continue
        for порча in _порчи(с):
            порч += 1
            вердикт = _судить(порча)
            if вердикт == (True, False):
                пойманных += 1
            elif вердикт == (True, True):
                беды.append(f"порча прошла: {порча[:120]}")
    for i, с in enumerate(sorted(T.ПОКАЗЫ)):
        if i % 7:
            continue
        язык = T.ПОКАЗЫ[с][0]
        р = A.РЕЧЬ[язык]
        да = A._реплика(язык, "польз", р["да"] + ".") + " "
        нет = A._реплика(язык, "польз", р["нет"] + ".") + " "
        порчи = ([с.replace(да, "", 1), с.replace(да, нет, 1)] if да in с
                 else [с.replace(нет, да, 1)] if нет in с else [])
        for порча in порчи:
            порч += 1
            if _судить(порча) == (True, False):
                пойманных += 1
            else:
                беды.append(f"порча устройства не ложь: {порча[:120]}")
    return беды, порч, пойманных, len(T.ПОКАЗЫ)


