def _значения(м):
    """{дыра: значение} — повторная дыра обязана нести одно значение, иначе страница лжёт о себе."""
    вон = {}
    for ключ, знач in м.groupdict().items():
        имя = ключ.split("_", 2)[2]
        имя = _ИЗ_ЛАТ.get(имя, имя)
        if имя in вон and вон[имя] != знач:
            return None
        вон[имя] = знач
    return вон


