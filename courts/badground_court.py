#!/usr/bin/env python3
"""[СУД НЕГОДНОГО ОСНОВАНИЯ] — сила основания выведена обходом ряда; МИР ЗАМКНУТ.

Страница мира (`tools/badground.py`) есть утверждение, основание к нему и ИМЯ, какое странице
дано доводу: круг, не довод или довод. Суд не читает этого имени: он берёт из записи два
свойства, проходит весь объявленный ряд в обе стороны и выводит силу основания САМ.

    ОСНОВАНИЕ БЫВАЕТ ИСТИННЫМ И НЕГОДНЫМ РАЗОМ. «12 делится на 2, потому что оно чётное» —
    оба утверждения истинны, и второе не доказывает первого: это одно и то же, сказанное
    дважды. Ложь тут ни при чём, и потому ни один суд над ИСТИННОСТЬЮ такого не поймает.

Отсюда и место этого суда среди прочих: он судит не истинность, а СИЛУ СВЯЗИ, и обе беды —
круг и слабое основание — состоят из истинных частей.

Свидетель обязан БЫТЬ свидетелем: число, названное в доказательство слабости, обязано делать
основание и не делать утверждения; названное в доказательство строгости — наоборот. И число
самого показа обязано отвечать обоим, иначе спор идёт ни о чём.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import badground as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"badground"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_badground.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_badground.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_badground.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"НЕГОДНОЕ ОСНОВАНИЕ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
