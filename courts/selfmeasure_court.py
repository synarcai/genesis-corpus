def счётная(ключ, n):
    """Форма имени при счёте — законом ПАКЕТА, а не рукой."""
    return units.ру_форма(СЧЁТНЫЕ[ключ], n)


def _замер(г, снимок=None):
    """(ключ имени, взято, всего) объявленного замера; None — не наш.

    ПАРА ЧИСЕЛ ОБЯЗАНА СТОЯТЬ В СНИМКЕ. Показ, у которого выкладка
    сходится, а числа не из снимка, есть складная неправда о себе —
    ровно то, ради чего этот суд и написан.
    """
    прибор = г["прибор"]
    если = (снимок or СНИМОК_ВТОРОЙ).get(прибор)
    if если is None:
        return None
    что, взято, всего = если
    if int(г["взято"]) != взято or int(г["всего"]) != всего:
        return None
    return что, взято, всего


def _состояние(г):
    """Доля, названная границей: умножение и сравнение заново."""
    если = _замер(г)
    if если is None:
        return False
    что, взято, всего = если
    знаменатель = ДОЛИ.get(г["доля"])
    if знаменатель is None or int(г["зн"]) != знаменатель:
        return False
    произведение = знаменатель * взято
    куда = "больше" if произведение > всего else "меньше"
    return (int(г["взято2"]) == взято and int(г["всего2"]) == всего
            and int(г["произв"]) == произведение and г["куда"] == куда
            and г["форма"] == счётная(что, взято))


def _граница(г):
    """Дополнение сходится с целым, и обе формы — свои."""
    если = _замер(г)
    if если is None:
        return False
    что, взято, всего = если
    нет = всего - взято
    return (int(г["нет"]) == нет and int(г["нет2"]) == нет
            and int(г["взято2"]) == взято and int(г["всего2"]) == всего
            and г["форма"] == счётная(что, взято)
            and г["форма2"] == счётная(что, нет))


def _нужда(г):
    """Нужда есть РАЗНОСТЬ, и она вычитается заново."""
    если = _замер(г)
    if если is None:
        return False
    что, взято, всего = если
    не_хватает = всего - взято
    return (int(г["нет"]) == не_хватает and int(г["нет2"]) == не_хватает
            and int(г["всего2"]) == всего and int(г["взято2"]) == взято
            and г["форма_в"] == счётная(что, всего)
            and г["форма_н"] == счётная(что, не_хватает))


def _рост(г, целое_выросло):
    """Рост есть разность ДВУХ замеров, и обе части пересчитываются.

    САМАЯ СОБЛАЗНИТЕЛЬНАЯ ЛОЖЬ ЭТОГО МИРА — назвать прибавку взятого и
    умолчать о прибавке целого. Потому обе стои́т в показе и обе
    сверяются; и потому же нулевая прибавка целого обязана быть названа
    нулём, а не пропущена.
    """
    прибор = г["прибор"]
    было = СНИМОК_ПЕРВЫЙ.get(прибор)
    стало = СНИМОК_ВТОРОЙ.get(прибор)
    if было is None or стало is None:
        return False
    что, б_взято, б_всего = было
    _ч, с_взято, с_всего = стало
    прибавка = с_взято - б_взято
    прибавка_всего = с_всего - б_всего
    if (int(г["было"]) != б_взято or int(г["стало"]) != с_взято
            or int(г["было2"]) != б_взято or int(г["стало2"]) != с_взято
            or int(г["приб"]) != прибавка
            or int(г["приб2"]) != прибавка
            or г["ф1"] != счётная(что, б_взято)):
        return False
    if целое_выросло != (прибавка_всего > 0):
        return False
    if (int(г["с_всего"]) != с_всего or int(г["б_всего"]) != б_всего):
        return False
    return int(г["приб_всего"]) == прибавка_всего


def _рост_с_ростом(г):
    return _рост(г, True)


def _рост_без_роста(г):
    return _рост(г, False)


def _вопрос_сколько(г):
    если = _замер(г)
    if если is None:
        return False
    что, взято, _всего = если
    return (г["род_мн"] == СЧЁТНЫЕ[что][2]
            and г["форма"] == счётная(что, взято))


def _вопрос_чего_нет(г):
    если = _замер(г)
    if если is None:
        return False
    что, взято, всего = если
    нет = всего - взято
    return (г["о_чём"] == О_ЧЁМ[г["прибор"]] and int(г["нет"]) == нет
            and г["форма"] == счётная(что, нет))


def _отказ(г):
    """РАБОТА ОТКАЗА: назван день снимка, и позже замеров нет."""
    прибор = г["прибор"]
    if прибор not in СНИМОК_ВТОРОЙ or г["прибор2"] != прибор:
        return False
    что, _взято, _всего = СНИМОК_ВТОРОЙ[прибор]
    return (г["род_мн"] == СЧЁТНЫЕ[что][2] and г["день"] == ДЕНЬ)


