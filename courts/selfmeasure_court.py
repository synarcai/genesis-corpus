def _рост(г, целое_выросло):
    """Рост есть разность ДВУХ замеров, и обе части пересчитываются.

    САМАЯ СОБЛАЗНИТЕЛЬНАЯ ЛОЖЬ ЭТОГО МИРА — назвать прибавку взятого и
    умолчать о прибавке целого. Потому обе стои́т в показе и обе
    сверяются; и потому же нулевая прибавка целого обязана быть названа
    нулём, а не пропущена.
    """
    прибор = г["прибор"]
    # ПАРА ЗАМЕРОВ БЕРЁТСЯ ИЗ САМОГО ПОКАЗА, А НЕ ПРЕДПОЛАГАЕТСЯ. Прежде суд знал одну пару
    # (первый и второй) и потому не умел бы отличить верной второй пары от выдуманной.
    п1 = ЗАМЕРЫ.get(г["имя1"])
    п2 = ЗАМЕРЫ.get(г["имя2"])
    if п1 is None or п2 is None:
        return False
    д1, снимок1, подписи1 = п1
    д2, снимок2, подписи2 = п2
    if г["день1"] != д1:
        return False
    if г["день2"] != ("того же дня" if д2 == д1 else д2):
        return False
    # ВЫЧИТАТЬ ВОЛЬНО ЛИШЬ ТАМ, ГДЕ ПРИБОР ТОТ ЖЕ.
    if подписи1.get(прибор) != подписи2.get(прибор):
        return False
    было = снимок1.get(прибор)
    стало = снимок2.get(прибор)
    if было is None or стало is None:
        return False
    что, б_взято, б_всего = было
    _ч, с_взято, с_всего = стало
    прибавка = с_взято - б_взято
    прибавка_всего = с_всего - б_всего
    if (int(г["было"]) != б_взято or int(г["стало"]) != с_взято
            or int(г["было2"]) != б_взято or int(г["стало2"]) != с_взято
            or int(г["приб"]) != прибавка
            or int(г["приб2"]) != прибавка
            or г["ф1"] != счётная(что, б_взято)):
        return False
    if целое_выросло != (0 if прибавка_всего == 0 else
                         (1 if прибавка_всего > 0 else -1)):
        return False
    if (int(г["с_всего"]) != с_всего or int(г["б_всего"]) != б_всего):
        return False
    return int(г["приб_всего"]) == abs(прибавка_всего)


