def _несравнимость(г):
    """ОТКАЗ ВЫЧЕСТЬ: обе подписи обязаны стоять в показе и обе — разойтись."""
    прибор = г["прибор"]
    п1, п2 = ЗАМЕРЫ.get(г["имя1"]), ЗАМЕРЫ.get(г["имя2"])
    if п1 is None or п2 is None:
        return False
    _д1, снимок1, подписи1 = п1
    _д2, _с2, подписи2 = п2
    если = снимок1.get(прибор)
    # ИМЯ ЗАМЕРА В ОСНОВАНИИ ОБЯЗАНО ПОВТОРИТЬ ИМЯ В ВОПРОСЕ: отказ, где спрошено об одной
