#!/usr/bin/env python3
"""[РАССКАЗ О СЕБЕ] — отношение замера пересчитывается, замер сверяется.

Мир «о себе» — единственный в корпусе, где ложь не видна глазом: «я
вырос», «мне не хватает знаний» звучат осмысленно ПРИ ЛЮБЫХ ЧИСЛАХ.
Оттого суд здесь устроен строже прочих и держит ДВЕ независимые опоры,
из которых ни одна не прикрывает другую.

ПЕРВАЯ ОПОРА — ОТНОШЕНИЕ, И ОНО ВЕРНО НАВСЕГДА. Суд не верит ни одному
итогу показа: он умножает, складывает и вычитает заново. «901 из 8221
больше десятой доли» проверяется умножением 10 × 901 = 9010 и
сравнением с 8221; «вне меня осталось 7320» — сложением; «не хватало
7320» — вычитанием; «прибавилось 128» — разностью ДВУХ замеров. Всякое
такое отношение истинно или ложно независимо от того, устарел ли замер:
время не портит арифметики.

ВТОРАЯ ОПОРА — САМ ЗАМЕР, ОБЪЯВЛЕННЫЙ ЗДЕСЬ ВТОРОЙ РУКОЙ. Пара
(взято, всего) обязана стоять в снимке, записанном в этом файле
ОТДЕЛЬНО от генератора. Порча, согласованно поправившая и число, и его
выкладку, пройдёт первую опору и разобьётся о вторую; правка снимка в
одном доме и не в другом делает строку НЕСУДИМОЙ, а ворота записи
несудимую строку не пропускают.

ЧЕГО СУД НЕ ДЕЛАЕТ И НЕ ПРИТВОРЯЕТСЯ, ЧТО ДЕЛАЕТ. Он не зовёт приборы и
не утверждает, что 901 есть сегодняшнее число: он утверждает, что так
записано в снимке за названный день. Проверить сам замер может лишь тот,
кто заново позовёт прибор, — и потому имя прибора стои́т в КАЖДОМ показе,
а день назван словами. Это граница, объявленная вслух, а не слепота.

ОТКАЗ СУДИТСЯ РАБОТОЙ. «сколько предметов насчитает прибор завтра? нет
такого замера: есть замеры по 2 сентября 2026 года и ни одного позже» —
суд сверяет названный день с днём снимка. Отказывает не незнание, а
ОТСУТСТВИЕ ЗАМЕРА: это проверяемый факт о таблице снимков, а не
расположение духа. Отказ, сославшийся на чужой день,
ложен: он выдал бы за границу знания то, чего не проверял.

ЧЕГО СУД НЕ ЧИТАЕТ: чужого рода. Образцы привязаны к зачинам этого мира
и к объявленным приборам; неузнанная строка есть (False, False).
"""

