#!/usr/bin/env python3
"""[ГЛИФЫ 5×7] — суд рендерит названное и сравнивает с показанным.

Мир глифов (tools/gen_genesis_glyphs.py) показывает «сетка → символ»,
«символ → сетка», слово рядом глифов и отрицание. Суд НЕ УЗНАЁТ сетку —
узнавание есть работа организма (OCR рынком, мандат 02.09). Суд берёт
названный символ, рендерит его по единой таблице шрифта (tools/glyphs.py)
и сравнивает клетка в клетку; отрицание истинно, когда рендер не совпал.
Имя символа несёт письмо и регистр, и потому однозначно; сетка без письма
многозначна (латинская A и русская А), и суд её никогда не толкует.

ЧЕГО СУД НЕ ЧИТАЕТ: чужого рода. Строка без сетки в нотации «#/.» —
(False, False).
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import families  # noqa: E402
import glyphs as G  # noqa: E402
import spacegrid as S  # noqa: E402

С = G.СЕТКА.pattern
СС = G.СЛОВО_СЕТКА.pattern
ИМЯ = "(" + G.ОБРАЗЕЦ_ИМЕНИ + ")"
СЛОВО = r"[^\s\"«»]+"


def _символ(имя):
    return G.символ_по_имени(имя)


def _рендер_слова(слово):
    if any(с not in G.ТАБЛИЦА for с in слово):
        return None
    return G.слово_сеткой(слово)


ОСНОВАНИЕ = re.compile(r"no cell differs|(\d+) cells? differs?|ни одна клетка не отличается|отлича(?:ется|ются) (\d+) клет(?:ка|ки|ок)")


def _сетка_символ(м):
    группы = м.groups()
    сетка, не, имя = группы[0], группы[1], группы[2]
    основание = группы[3] if len(группы) > 3 else None
    с = _символ(имя)
    if с is None:
        return False
    k = S.разница(сетка.split("/"), G.ТАБЛИЦА[с])
    if k is None:
        return False
    if основание is not None:
        мм = ОСНОВАНИЕ.fullmatch(основание)
        if not мм:
            return False
        названо = int(мм.group(1) or мм.group(2) or 0)
        if названо != k:
            return False
    return (k == 0) == (не is None)


def _символ_сетка(м):
    имя, сетка = м.groups()
    с = _символ(имя)
    return с is not None and G.сетка(с) == сетка


def _слово_сетка(м):
    слово, сетка = м.groups()
    return _рендер_слова(слово) == сетка


def _сетка_слово(м):
    сетка, слово = м.groups()
    return _рендер_слова(слово) == сетка


class _Г:
    """Группы выровненной формы — для судей, читающих м.groups()."""
    def __init__(self, г):
        self._г = г

    def groups(self):
        return self._г


# ВОПРОС ПОВТОРЯЕТ ПРЕДМЕТ, ОТВЕТ — САМО УТВЕРЖДЕНИЕ (М-146): половины
# сверяются, утверждение судится своим судьёй.
def _сетка_символ_вопрос(м):
    сетка, сетка2, имя = м.groups()
    return сетка == сетка2 and _сетка_символ(_Г((сетка2, None, имя)))


def _символ_сетка_вопрос(м):
    имя, имя2, сетка = м.groups()
    return имя == имя2 and _символ_сетка(_Г((имя2, сетка)))


def _слово_сетка_вопрос(м):
    слово, слово2, сетка = м.groups()
    return слово == слово2 and _слово_сетка(_Г((слово2, сетка)))


def _сетка_слово_вопрос(м):
    сетка, сетка2, слово = м.groups()
    return сетка == сетка2 and _сетка_слово(_Г((сетка2, слово)))


ОБРАЗЦЫ = (
    (rf"^glyph ({С}) is (not )?{ИМЯ}: ([^.]+)\.$", _сетка_символ),
    (rf"^глиф ({С}) — (не )?(?:это )?{ИМЯ}: ([^.]+)\.$", _сетка_символ),
    (rf"^glyph ({С}) is (not )?{ИМЯ}\.$", _сетка_символ),
    (rf"^глиф ({С}) — (не )?(?:это )?{ИМЯ}\.$", _сетка_символ),
    (rf"^{ИМЯ} as a 5×7 glyph is ({С})\.$", _символ_сетка),
    (rf"^{ИМЯ} глифом 5×7 — ({С})\.$", _символ_сетка),
    (rf"^what does glyph ({С}) show\? glyph ({С}) is {ИМЯ}\.$", _сетка_символ_вопрос),
    (rf"^что показывает глиф ({С})\? глиф ({С}) — это {ИМЯ}\.$", _сетка_символ_вопрос),
    (rf"^what is {ИМЯ} as a 5×7 glyph\? {ИМЯ} as a 5×7 glyph is ({С})\.$", _символ_сетка_вопрос),
    (rf"^какова {ИМЯ} глифом 5×7\? {ИМЯ} глифом 5×7 — ({С})\.$", _символ_сетка_вопрос),
    (rf"^the (?:word|number|expression) \"({СЛОВО})\" in 5×7 glyphs is ({СС})\.$",
     _слово_сетка),
    (rf"^(?:слово|число|выражение) «({СЛОВО})» глифами 5×7 — ({СС})\.$",
     _слово_сетка),
    (rf"^glyph rows ({СС}) read as the (?:word|number|expression) \"({СЛОВО})\"\.$",
     _сетка_слово),
    (rf"^ряд глифов ({СС}) читается как (?:слово|число|выражение) «({СЛОВО})»\.$",
     _сетка_слово),
    (rf"^what is the (?:word|number|expression) \"({СЛОВО})\" in 5×7 glyphs\? the (?:word|number|expression) \"({СЛОВО})\" in 5×7 glyphs is ({СС})\.$",
     _слово_сетка_вопрос),
    (rf"^каково (?:слово|число|выражение) «({СЛОВО})» глифами 5×7\? (?:слово|число|выражение) «({СЛОВО})» глифами 5×7 — ({СС})\.$",
     _слово_сетка_вопрос),
    (rf"^what do glyph rows ({СС}) read as\? glyph rows ({СС}) read as the (?:word|number|expression) \"({СЛОВО})\"\.$",
     _сетка_слово_вопрос),
    (rf"^как читается ряд глифов ({СС})\? ряд глифов ({СС}) читается как (?:слово|число|выражение) «({СЛОВО})»\.$",
     _сетка_слово_вопрос),
)
# СЕМЕЙСТВО ЕСТЬ РОД (М-146).
СЕМЕЙСТВА_СУДА = (
    ("сетка→знак", [ОБРАЗЦЫ[i] for i in (0, 1, 2, 3, 6, 7)]),
    ("знак→сетка", [ОБРАЗЦЫ[i] for i in (4, 5, 8, 9)]),
    ("слово→ряды", [ОБРАЗЦЫ[i] for i in (10, 11, 14, 15)]),
    ("ряды→слово", [ОБРАЗЦЫ[i] for i in (12, 13, 16, 17)]),
)
assert sum(len(ф) for _, ф in СЕМЕЙСТВА_СУДА) == len(ОБРАЗЦЫ) == 18, len(ОБРАЗЦЫ)
# Пустая группа-заглушка в вопросах играет роль «не» = None.
ПРАВИЛА = families.правила(
    СЕМЕЙСТВА_СУДА,
    обёртка=lambda мм: type("М", (), {"groups": lambda self, г=tuple(None if г == "" else г for г in мм.groups()): г})())


import laws  # noqa: E402
ЗАКОНЫ = laws.свод("glyphs")


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if с in ЗАКОНЫ:
        return True, True
    if "/" not in с or ("#" not in с and "_" not in с):
        return False, False
    for образец, проверить in ПРАВИЛА:
        м = образец.match(с)
        if м:
            return True, bool(проверить(м))
    return False, False


def main():
    import collections
    итог = collections.Counter()
    for путь in [pathlib.Path(п) for п in sys.argv[1:]] or [КОРЕНЬ / "datasets" / "genesis_glyphs.txt"]:
        for с in путь.read_text(encoding="utf-8").splitlines():
            if not с.strip():
                continue
            судимо, истинно = судить(с)
            итог["несудимо" if not судимо else ("истина" if истинно else "ЛОЖЬ")] += 1
            if судимо and not истинно:
                print("  ЛОЖЬ:", с[:120])
    ложь = итог["ЛОЖЬ"]
    print(f"ГЛИФЫ {'PASS' if not ложь else 'FAIL'}: {ложь} ложных, "
          f"{итог['истина']} истинных, {итог['несудимо']} несудимых")
    return 0 if not ложь else 1


if __name__ == "__main__":
    sys.exit(main())
