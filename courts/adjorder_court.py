#!/usr/bin/env python3
"""[СУД ПОРЯДКА ПРИЛАГАТЕЛЬНЫХ] — порядок пересчитан по ряду ПАКЕТА; МИР ЗАМКНУТ.

Страница мира (`tools/adjorder.py`) кладёт рядом две записи одной вещи и называет верную с
ОСНОВАНИЕМ: «размер прежде цвета».

    ПОРЯДОК ПРИЛАГАТЕЛЬНЫХ ЕСТЬ ЗАКОН ЯЗЫКА, А НЕ ВКУС ГОВОРЯЩЕГО. «a red big table» не
    стилистически хуже — оно НЕВЕРНО, и проверяется это рядом разрядов, объявленным пакетом
    (`en.json → adjective_order`), а не слухом судящего.

Суд читает ТОТ ЖЕ ряд, что и дом, и пересчитывает порядок сам. Четыре строгости:

    ОБЕ ЗАПИСИ — ОДНА ВЕЩЬ И ОДНИ СЛОВА, иначе это не выбор порядка, а две разные вещи;
    ВЕРНАЯ ОБЯЗАНА СТОЯТЬ ПО РЯДУ, А НЕВЕРНАЯ — НЕ СТОЯТЬ: страница, где обе верны либо обе
        неверны, лжёт самим своим устройством;
    НАЗВАННАЯ ПАРА ОБЯЗАНА БЫТЬ ПАРОЙ ЭТОЙ ЗАПИСИ и стоять в ней подряд;
    СЛОВО ВНЕ ОБЪЯВЛЕННОГО РЯДА ДЕЛАЕТ СТРОКУ ЧУЖОЙ — и суд о ней МОЛЧИТ, а не зовёт ложью
        (закон 16.09: судить по виду слова значит судить чужое как своё).
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import adjorder as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"adjorder"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    for с, (судимо, _и) in zip(подсадки, вердикты):
        if not судимо:
            print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_adjorder.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_adjorder.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_adjorder.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ПОРЯДОК ПРИЛАГАТЕЛЬНЫХ {поза}: {итог['ложных']} ложных из {итог['судимых']} "
          f"судимых, несудимых {итог['несудимых']}; подсадок поймано {пойманы} из "
          f"{len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
