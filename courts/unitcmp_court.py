#!/usr/bin/env python3
"""[СРАВНЕНИЕ ВЕЛИЧИН] — какая величина больше, пересчитано судом через объявленное основание.

Суд не пишет закона заново: он берёт его у дома (`unitcmpforms`), где меры, основания и семьи
объявлены одной таблицей. Подмена числа, меры и САМОГО СРАВНЕНИЯ ловится машинально: произведение
и сумма пересчитываются, а «больше» и «меньше» судятся КАК УТВЕРЖДЕНИЯ, а не как оборот речи.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

ОТКАЗ ПРОВЕРЯЕТСЯ КАК ОТКАЗ: страница, где сказано «ответа нет», обязана не нести ни равенства,
ни сравнения. Отказ, на котором стои́т счёт, отрицает сам себя.

ГРАНИЦА: строка, которой рамка дома не порождает и которая не расходится с нею одним словом,
суду не подсудна — ложь о СВОЁМ мире говорит замыкание, а не начало строки.

    python3 courts/unitcmp_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
import unitcmpforms  # noqa: E402 — дом, объявивший меры и семьи

ИМЯ_СУДА = "unitcmp"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"unitcmp"})


def _судить(строка):
    return unitcmpforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"СРАВНЕНИЕ ВЕЛИЧИН {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(unitcmpforms.РОДЫ)}, страниц {len(unitcmpforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
