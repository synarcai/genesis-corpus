#!/usr/bin/env python3
"""[СУД РАВНОЙ ДОЛИ] — частное и остаток пересчитаны; МИР ЗАМКНУТ.

Страница мира равной доли (`tools/equalshare.py`) есть голое повелительное над двумя
числами и распределительный ответ: «раздели 14 на 3 поровну. что получится? по 4, и 2
останется.» Суд разбирает приказ по объявленной рамке, ПЕРЕСЧИТЫВАЕТ частное и остаток и
сверяет ответ дословно с объявленной речью языка.

ТРИ ШВА, И КАЖДЫЙ ЗАПЕЧАТАН ЧИСЛОМ:

    ровно       — «по q», и q × b = a без остатка;
    с_остатком  — «по q, и r останется», и a = b × q + r при r > 0. ОСТАТОК НАЗВАН, А НЕ
                  ОТБРОШЕН: мир, молчащий об остатке, учит, что его не бывает;
    на_ноль     — отказ с основанием, дословно тот, какой объявил язык.

И ЧЕТВЁРТЫЙ ШОВ, ГРАММАТИЧЕСКИЙ: где имя части согласуется с числом (польский: 2…4 —
именительный, прочие и ноль — родительный), суд проверяет и его. Ложь грамматики видна
так же ясно, как ложь арифметики.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import equalshare as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"equalshare"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    # ПРЕДСТАВЛЕННОЕ «НЕТ»: доля неверна; остаток отброшен; остаток неверен; ноль отвечен
    # числом; чужая форма части при числе; ответ без доли вовсе.
    подсадки = (
        "раздели 14 на 2 поровну. что получится? по 6.",
        "раздели 14 на 3 поровну. что получится? по 4.",
        "раздели 14 на 3 поровну: по 4, и 3 останется.",
        "раздели 14 на 0 поровну: по 0.",
        "podziel 15 na 5 równe części: po 3.",
        "divide 14 into 2 equal parts: 6 each.",
    )
    пойманы = sum(1 for с in подсадки if (lambda т: т[0] and not т[1])(_судить(с)))
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_equalshare.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_equalshare.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_equalshare.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"РАВНАЯ ДОЛЯ {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
