#!/usr/bin/env python3
"""[СУД ДВУХ ПРИЗНАКОВ] — записи сравнены заново, имя решившего проверено; МИР ЗАМКНУТ.

Страница мира (`tools/twokeys.py`) есть две записи «имя, число», объявленный порядок ключей и
ответ с ПРИЧИНОЙ — что именно решило. Суд сравнивает записи сам, а порядок ключей берёт из
ОБЪЯВЛЕНИЯ, а не со страницы.

    ВТОРОЙ КЛЮЧ МОЛЧИТ, ПОКА ГОВОРИТ ПЕРВЫЙ. Он не запасной, а ПОДЧИНЁННЫЙ: вступает ровно
    там, где первый сказал «равно», и нигде более.

Сверх ответа суд проверяет ИМЯ РЕШИВШЕГО:

    СКАЗАТЬ «РЕШИЛА АЗБУКА» ТАМ, ГДЕ ЧИСЛА РАЗЛИЧНЫ, — ЛОЖЬ, ДАЖЕ КОГДА РАННЯЯ ЗАПИСЬ
    НАЗВАНА ВЕРНО. Ответ без причины не есть ответ, и причина судится наравне с ответом.

Азбука берётся у дома азбучного порядка, а не объявляется вторым списком: второй ключ
проверяется той же азбукой, какой строится.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "tools"))
import closedworld  # noqa: E402
import twokeys as F  # noqa: E402

ЗАМКНУТЫЕ_МИРЫ = frozenset({"twokeys"})


def _судить(строка):
    return F.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    подсадки = F.ПОДСАДКИ
    # «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО: подсадка бывает судима и
    # истинна — тогда лгал список; бывает и несудима — тогда её не читает никто.
    вердикты = [_судить(с) for с in подсадки]
    пойманы = sum(1 for судимо, истинно in вердикты if судимо and not истинно)
    немых = [с for с, (судимо, _и) in zip(подсадки, вердикты) if not судимо]
    for с in немых:
        print(f"  ПОДСАДКА ВНЕ РАМКИ (не судима, а не «не поймана»): {с[:110]}")
    итог, примеры = collections.Counter(), []
    пути = [п for п in worlds(kind="shows") if п.name == "genesis_twokeys.txt"]
    if not пути:
        свой = (pathlib.Path(__file__).resolve().parents[1] / "datasets"
                / "genesis_twokeys.txt")
        пути = [свой] if свой.exists() else []
        print("  мир не в манифесте — суд читает datasets/genesis_twokeys.txt по имени")
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8").splitlines():
            if not стр.strip() or стр.startswith("\x0c"):
                continue
            судимо, истинно = _судить(стр)
            итог["судимых" if судимо else "несудимых"] += 1
            if судимо and not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(стр)
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:150]}")
    поза = ("PASS" if итог["ложных"] == 0 and итог["несудимых"] == 0
            and пойманы == len(подсадки) else "FAIL")
    print(f"ДВА ПРИЗНАКА {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых, "
          f"несудимых {итог['несудимых']}; подсадок поймано {пойманы} из {len(подсадки)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
