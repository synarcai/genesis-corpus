#!/usr/bin/env python3
"""[ПОРОЖДЕНИЕ ПЛАСТА С ЧИСЛОМ] — строка судима тем, ПОРОЖДАЕТСЯ ЛИ ОНА из пакета.

Остаток долга судимости (03.09): 767 строк свода зачитывались СЛОВАРЁМ
пакета — «всякое ли слово объявлено», — а не истиной. Разведка назвала их:
счёт с классификатором (ja 187, am 145, ko 135, th 125, ta 125) и счётные
цепи (uk 30, fr 20). Суд формы пласта (`courts/langform_court.py`) до них не
дотянулся, ибо читает лексические дыры «{lex:класс:клетка}», а эти строки
стоят в шаблонах С ЧИСЛОМ: «{num:prod}冊の本があります。», «እዚህ {num:prod}
መጽሐፍ አለ።».

Форма суда — слово holon (03.09): судим не словарь, а СПОСОБНОСТЬ ПОРОДИТЬ
строку из объявленной формы и объявленных слов. Пакет объявляет шаблоны
рода в `show_kinds`; суд обращает шаблон в образец, где «{num:…}» есть
объявленное числительное этого языка, а «{lex:класс:клетка}» — объявленная
форма ИМЕННО ЭТОЙ клетки. Строка, ставшая подстановкой такого шаблона, —
порождается пакетом и потому судима содержанием: чужое слово, форма из
соседней клетки или неизвестное числительное образца не пройдут.

СЧЁТНАЯ ЦЕПЬ судится своим законом: «один два три чотири…» есть ряд
объявленных числительных, идущих ПОДРЯД; разрыв ряда — ложь.
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import closedworld  # noqa: E402 — закон замкнутого мира
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира

ПАКЕТЫ = КОРЕНЬ / "tools" / "langpacks"
# ЭЛИЗИЯ В ОБРАЗЦЕ ЕСТЬ ВЫБОР ИЗ ДВУХ, А НЕ БУКВА (08.09). Движок сокращает служебное слово
# перед гласной ПОСЛЕ подстановки («je ouvre» → «j'ouvre»), а шаблон держит его целым — и
# образец, собранный из шаблона буквально, не совпал бы с готовой страницей.
#
#     ОБРАЗЕЦ, СОБРАННЫЙ ИЗ ШАБЛОНА, ОБЯЗАН ЗНАТЬ ВСЁ, ЧТО ДВИЖОК ДЕЛАЕТ ПОСЛЕ ПОДСТАНОВКИ.
#
# Какая из двух форм верна, решает не этот суд: элизия есть закон ПИСЬМА, и мерит её свой
# прибор. Здесь довольно принять обе.
def _с_элизией(сырой, пакет):
    """Экранированный кусок образца, где объявленное служебное слово принимает ОБЕ формы.

    РАБОТА ИДЁТ НАД СЫРЫМ ТЕКСТОМ, А НЕ НАД ЭКРАНИРОВАННЫМ: первая редакция искала «de » в
    уже экранированной строке и не нашла ни разу — `re.escape` пробела не трогает с версии
    3.7, и якорь по «\ » не совпал. Замер сказал это одним словом: «j'ouvre» осталось чужим.
    """
    пары = ((пакет.get("elision") or {}).get("pairs") or {})
    for целое, сокращённое in пары.items():
        хвост = целое + " "
        if сырой.endswith(хвост) and (len(сырой) == len(хвост)
                                      or not сырой[-len(хвост) - 1].isalpha()):
            голова = re.escape(сырой[:-len(хвост)])
            return голова + "(?:" + re.escape(хвост) + "|" + re.escape(сокращённое) + ")"
    return re.escape(сырой)


_ЛЕКС = re.compile(r"\{lex:([^:}]+):([^}]+)\}")
_ЧИСЛ = re.compile(r"\{num:([^}]+)\}")
_ЦЕПЬ = re.compile(r"\{chain\}")


def _пакеты():
    вон = {}
    for путь in sorted(ПАКЕТЫ.glob("*.json")):
        try:
            вон[путь.stem] = json.loads(путь.read_text(encoding="utf-8"))
        except ValueError:
            continue
    return вон


ПАКЕТЫ_ВСЕ = _пакеты()


def _числительные(пакет):
    вон = {}
    for ключ, слово in (пакет.get("numerals") or {}).items():
        к = str(ключ)
        if к.lstrip("-").isdigit():
            вон[int(к)] = str(слово)
    return вон


def _формы_клетки(пакет, класс, клетка):
    """The declared forms of ONE cell of a class — «one», «many», «by_n» …"""
    кл = (пакет.get("morph_classes") or {}).get(класс) or {}
    формы = кл.get("forms") or []
    лексемы = кл.get("lexemes") or {}
    вон = set()
    if клетка in формы:
        i = формы.index(клетка)
        for ряд in лексемы.values():
            if isinstance(ряд, list) and len(ряд) > i:
                вон.add(str(ряд[i]))
    else:
        # «by_n», «by_sum» — the cell is chosen by a count; every form may stand
        for ряд in лексемы.values():
            if isinstance(ряд, list):
                вон.update(str(ф) for ф in ряд)
    return вон


def _образцы():
    """[(язык, pattern)] — every declared template that carries a NUMBER."""
    вон = []
    for язык, пакет in ПАКЕТЫ_ВСЕ.items():
        числа = _числительные(пакет)
        if not числа:
            continue
        альт_чисел = "(?:" + "|".join(re.escape(с) for с in sorted(set(числа.values()), key=lambda с: (-len(с), с))) + ")"
        for род in (пакет.get("show_kinds") or {}).values():
            for ш in род.get("templates") or ():
                if not _ЧИСЛ.search(ш) or _ЦЕПЬ.search(ш):
                    continue
                куски, конец, годно = [], 0, True
                for м in re.finditer(r"\{[^}]+\}", ш):
                    куски.append(_с_элизией(ш[конец:м.start()], пакет))
                    дыра = м.group()
                    лекс = _ЛЕКС.fullmatch(дыра)
                    if лекс:
                        формы = _формы_клетки(пакет, лекс.group(1), лекс.group(2))
                        if not формы:
                            годно = False
                            break
                        куски.append("(?:" + "|".join(re.escape(ф) for ф in sorted(формы, key=lambda с: (-len(с), с))) + ")")
                    elif _ЧИСЛ.fullmatch(дыра):
                        куски.append(альт_чисел)
                    else:
                        годно = False
                        break
                    конец = м.end()
                if not годно:
                    continue
                куски.append(re.escape(ш[конец:]))
                вон.append((язык, re.compile("^" + "".join(куски) + "$")))
    return вон


ОБРАЗЦЫ = _образцы()
_ПО_СЛОВУ = {язык: {с: з for з, с in _числительные(п).items()} for язык, п in ПАКЕТЫ_ВСЕ.items()}


_ПОРЯДОК = {язык: sorted(по_слову, key=lambda с: (-len(с), с)) for язык, по_слову in
            ((язык, {с: з for з, с in _числительные(п).items()}) for язык, п in ПАКЕТЫ_ВСЕ.items())}


# РАЗДЕЛИТЕЛЬ ЦЕПИ ЕСТЬ НЕ ТОЛЬКО ПРОБЕЛ (08.09). Китайская цепь разделена «、», и разрез по
# пробелу не находил в ней ни одного числительного: сорок пять честных строк были названы
# ложью в час, когда пласт замкнули порождаемостью.
#
#     ПИСЬМО БЕЗ ПРОБЕЛОВ РАЗДЕЛЯЕТ ЧИСЛА СВОИМ ЗНАКОМ, И ЗНАК ЭТОТ ОБЪЯВЛЯЮТ, А НЕ ГАДАЮТ.
РАЗДЕЛИТЕЛИ_ЦЕПИ = " 、,，"


def _раскусить(текст, язык):
    """Числа цепи, откушенные ЖАДНО: составное числительное есть ОДНО число
    («on bir» = 11, «двадцать один» = 21), и ряд по словам его бы разорвал."""
    по_слову = _ПО_СЛОВУ[язык]
    вон, i = [], 0
    while i < len(текст):
        if текст[i] in РАЗДЕЛИТЕЛИ_ЦЕПИ:
            i += 1
            continue
        for слово in _ПОРЯДОК[язык]:
            конец = i + len(слово)
            if текст.startswith(слово, i) and (конец == len(текст)
                                               or текст[конец] in РАЗДЕЛИТЕЛИ_ЦЕПИ):
                вон.append(по_слову[слово])
                i = конец
                break
        else:
            return None
    return вон


def _цепь_счёта(строка):
    """(судимо, истинно) о счётной цепи: ряд объявленных числительных подряд."""
    текст = строка.strip().rstrip(".。")
    # ДЛИНА ЦЕПИ МЕРИТСЯ ЧИСЛАМИ, А НЕ СЛОВАМИ: письмо без пробелов даёт одно «слово» на всю
    # цепь, и порог по словам отсекал бы её целиком.
    if len(текст) < 3:
        return False, False
    for язык in _ПО_СЛОВУ:
        значения = _раскусить(текст, язык)
        if значения is None or len(значения) < 3:
            continue
        подряд = all(b - a == 1 for a, b in zip(значения, значения[1:]))
        return True, подряд
    return False, False


# ПОРОЖДАЕМОСТЬ ЕСТЬ ЗАМЫКАНИЕ ПЛАСТА (08.09).
#
# Суд читал лишь шаблоны С ЧИСЛОМ — прочие оставлял соседу формы пласта. Оттого порча, не
# тронувшая числа, проходила мимо всех: «wegen des buches» → «wege des buches» («wege» ЕСТЬ
# объявленное немецкое слово, и словарь молчит законно), «四乘一等于四。» → «四乘一等于。»
# (порча УДАЛИЛА иероглиф, и остаток весь объявлен).
#
#     СЛОВО, ОБЪЯВЛЕННОЕ ЯЗЫКУ, НЕ ДЕЛАЕТ СТРОКУ ЕГО СТРОКОЙ: пласт порождён ШАБЛОНОМ, и
#     строка, которой шаблон породить не может, есть строка НЕ ЭТОГО ПЛАСТА.
#
# ЦЕНА ЗАМЕРЕНА ПРЕЖДЕ ЗАМЫКАНИЯ И РАВНА НУЛЮ: обход всех 29 пластов (94 128 строк) нашёл
# ВНЕ ОБРАЗЦОВ ровно ноль — но лишь после того, как сборщик научился четырём вещам, и каждая
# куплена своим замером:
#
#     · числительное бывает ЦИФРОЙ, когда пакет слова не объявил («45 قسمة خمسة»): 2915 → 1500;
#     · строка ЯДРА не есть строка пакета — пласт собирается пакетом ПОВЕРХ ядра;
#     · ОТКАЗ объявлен ПАРОЙ, а не шаблоном («yo canto.» стоит в `refusals.pairs`): 1500 → 65;
#     · ЦЕПЬ режется ДЛИННЕЙШИМ совпадением, а не пробелом («on bir» есть ОДНО числительное,
#       «五、六、七» разделено «、»): 65 → 0.
#
#     МИР НЕ ЗАМЫКАЮТ, ПОКУДА ЗАМЫКАНИЕ НЕ ПРОВЕРЕНО ПО КАЖДОЙ ЕГО СТРОКЕ.
def _образцы_всех():
    """[(язык, pattern)] по КАЖДОМУ объявленному шаблону, а не только числовому."""
    вон = []
    for язык, пакет in ПАКЕТЫ_ВСЕ.items():
        числа = _числительные(пакет)
        альт = ("(?:" + "|".join(re.escape(с) for с in sorted(set(числа.values()),
                                                              key=lambda с: (-len(с), с)))
                + r"|\d+)") if числа else r"\d+"
        for род in (пакет.get("show_kinds") or {}).values():
            for ш in род.get("templates") or ():
                if _ЦЕПЬ.search(ш):
                    continue
                куски, конец, годно = [], 0, True
                for м in re.finditer(r"\{[^}]+\}", ш):
                    куски.append(_с_элизией(ш[конец:м.start()], пакет))
                    дыра = м.group()
                    лекс = _ЛЕКС.fullmatch(дыра)
                    if лекс:
                        формы = _формы_клетки(пакет, лекс.group(1), лекс.group(2))
                        if not формы:
                            годно = False
                            break
                        куски.append("(?:" + "|".join(re.escape(ф) for ф in sorted(
                            формы, key=lambda с: (-len(с), с))) + ")")
                    elif _ЧИСЛ.fullmatch(дыра):
                        куски.append(альт)
                    elif дыра in ("{n}", "{m}", "{sum}", "{prod}"):
                        куски.append(r"\d+")
                    elif дыра.startswith("{art:"):
                        куски.append(r"(?:an?)")
                    else:
                        годно = False
                        break
                    конец = м.end()
                if not годно:
                    continue
                куски.append(re.escape(ш[конец:]))
                вон.append((язык, re.compile("^" + "".join(куски) + "$")))
    return вон


def _объявленные_строки():
    """Строки, объявленные пакетом НЕ шаблоном: обе половины пары отказа, со знаком и без."""
    вон = set()
    for пакет in ПАКЕТЫ_ВСЕ.values():
        for род in (пакет.get("show_kinds") or {}).values():
            знак = str(род.get("marker", ""))
            for пара in род.get("pairs") or ():
                for ключ in ("bad", "good"):
                    если = пара.get(ключ)
                    if если:
                        вон.add(str(если).strip())
                        вон.add((знак + str(если)).strip())
    return frozenset(вон)


def _ядро():
    """Строки ядра: пласт собирается пакетом ПОВЕРХ него, и они не его вина."""
    путь = КОРЕНЬ / "datasets" / "genesis_v0.txt"
    if not путь.is_file():
        return frozenset()
    return frozenset(с.strip() for с in путь.read_text(encoding="utf-8", errors="replace").splitlines() if с.strip())


ОБРАЗЦЫ_ВСЕХ = _образцы_всех()
ОБЪЯВЛЕННЫЕ = _объявленные_строки()
ЯДРО = _ядро()
ЗАМКНУТЫЕ_МИРЫ = frozenset(f"lang_{язык}" for язык in ПАКЕТЫ_ВСЕ)


def _судить(строка):
    с = строка.strip()
    if not с:
        return False, False
    for язык, образец in ОБРАЗЦЫ:
        if образец.match(с):
            return True, True
    if с in ОБЪЯВЛЕННЫЕ or с in ЯДРО:
        return True, True
    for язык, образец in ОБРАЗЦЫ_ВСЕХ:
        if образец.match(с):
            return True, True
    return _цепь_счёта(с)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import collections
    from genesis import worlds
    итог = collections.Counter(); примеры = []
    for путь in worlds(kind="shows"):
        for с in путь.read_text(encoding="utf-8").splitlines():
            if not с.strip() or с.startswith("\x0c"):
                continue
            судимо, истинно = судить(с)
            if not судимо:
                continue
            итог["судимых"] += 1
            if not истинно:
                итог["ложных"] += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.name}: {с}")
    for п in примеры:
        print(f"  ЛОЖЬ: {п[:120]}")
    поза = "PASS" if итог["ложных"] == 0 else "FAIL"
    print(f"ПОРОЖДЕНИЕ ПЛАСТА {поза}: {итог['ложных']} ложных из {итог['судимых']} судимых")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
