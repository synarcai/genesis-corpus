#!/usr/bin/env python3
"""СУД КОНВЕРСИИ ФОРМУЛ: обе стороны разбираются, и сверяются ДЕРЕВЬЯ.

Показ утверждает, что одна запись есть другая запись того же. Суд не
сверяет строку со строкой и не спрашивает генератора: он РАЗБИРАЕТ обе
стороны СВОИМИ ходами и требует, чтобы вышло ОДНО И ТО ЖЕ ДЕРЕВО.

Это сильнее всякой сверки поверхностей. Две записи могут отличаться
пробелом и значить одно; могут совпадать почти во всём и значить разное
(«( a + b ) / 2» и «a + b / 2»). Дерево не знает ни пробелов, ни
порядка слов — оно знает только СТРОЕНИЕ, а строение и есть то, что
конверсия обязана сохранить.

ДВА РАЗБОРЩИКА, НЕ ОДИН. Левую сторону читает разборщик своей
поверхности, правую — разборщик своей; они написаны отдельно и ничего
друг о друге не знают. Их согласие есть проверка, а не пересказ.

ПЛЮС ОРАКУЛ ДОМА: прежде всякого вердикта суд требует, чтобы дом
формул был обратим на своих деревьях. Дом, потерявший обратимость,
делает бессмысленным весь слой, и молчать об этом нельзя.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import formula_lang as фл  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# (образец, чем читать левую сторону, чем читать правую)
ЛАТ = r"\$ (.+?) \$"
ПРАВИЛА = (
    (re.compile(rf"^{ЛАТ} in words is (.+)\.$"), "лат", "en"),
    (re.compile(r"^(.+) in symbols is \$ (.+?) \$\.$"), "en", "лат"),
    (re.compile(rf"^{ЛАТ} в словах есть (.+)\.$"), "лат", "ru"),
    (re.compile(r"^(.+) в записи есть \$ (.+?) \$\.$"), "ru", "лат"),
    (re.compile(rf"^{ЛАТ} in glyphs is (.+)\.$"), "лат", "глиф"),
    (re.compile(r"^(.+) в словах есть (.+)\.$"), "глиф", "ru"),
    # ИНФИКСНАЯ РЕЧЬ — ПЯТАЯ ПОВЕРХНОСТЬ, И СУДИТСЯ ТАК ЖЕ: обе
    # стороны разбираются своими ходами, сверяются ДЕРЕВЬЯ.
    (re.compile(r"^(.+) read aloud is (.+)\.$"), "глиф", "вслух:en"),
    (re.compile(r"^(.+) вслух читается как (.+)\.$"), "глиф",
     "вслух:ru"),
    (re.compile(r"^(.+) in glyphs is (.+)\.$"), "вслух:en", "глиф"),
    (re.compile(r"^(.+) в записи есть (.+)\.$"), "вслух:ru", "глиф"),
)
ВОПРОС = re.compile(
    r"^(?:how is .+? said in words\? |как читается .+?\? "
    r"|how is .+? read aloud\? |как читается вслух .+?\? )(.+)$")


def _читать(текст, чем):
    """Дерево из поверхности названного рода, или None.

    Все четыре хода живут в ДОМЕ ФОРМУЛ и проверяются его оракулом;
    суд их только ЗОВЁТ. Понижение латеха, стоявшее здесь первой
    редакцией, было пятой правдой о записи — и разошлось с домом на
    вложенной сумме в тот же час.
    """
    if чем == "глиф":
        return фл.разобрать_глиф(текст)
    if чем in ("en", "ru"):
        return фл.разобрать_слова(текст, чем)
    if чем.startswith("вслух:"):
        return фл.разобрать_инфикс(текст, чем.split(":")[1])
    if чем == "лат":
        return фл.разобрать_латех(текст)
    return None


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    м = ВОПРОС.match(с)
    if м:
        судимо, истинно = судить(м.group(1))
        return судимо, истинно
    for образец, слева, справа in ПРАВИЛА:
        м = образец.match(с)
        if not м:
            continue
        левый, правый = _читать(м.group(1), слева), _читать(
            м.group(2), справа)
        if левый is None or правый is None:
            return False, False
        return True, левый == правый
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"КОНВЕРСИЯ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("КОНВЕРСИЯ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:90]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"КОНВЕРСИЯ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
