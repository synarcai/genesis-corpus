#!/usr/bin/env python3
"""СУД РАЗМЕТКИ ПОЛНОЙ: принадлежность выведенному и НЕЗАВИСИМАЯ сверка.

Суд делает две разные вещи, и смешивать их нельзя.

ПЕРВОЕ — ПРИНАДЛЕЖНОСТЬ. Слой выводит из дома разметки ВСЕ поверхности,
какие объявленные конструкции могут дать: саму запись, два смысла, два
вопроса. Строка корпуса, равная одной из выведенных, судима и истинна;
строка, похожая на них, но не выведенная, НЕСУДИМА — а ворота записи
несудимую строку не пропускают, и потому испорченная строка не может
попасть в слой вовсе.

ВТОРОЕ, И ОНО ГЛАВНОЕ — НЕЗАВИСИМАЯ СВЕРКА ПРИТЯЗАНИЯ. Принадлежность
ловит порчу корпуса, но НЕ ловит ошибку самого дома: если бы дом
объявил, что «###» есть заголовок уровня ДВА, все строки согласовались
бы между собой и лгали хором. Потому суд ВЫЧИСЛЯЕТ притязание сам —
считает решётки, читает двоеточия выравнивания, смотрит на крестик
задачи — и сверяет со ЧИСЛОМ, СТОЯЩИМ В ПРЕДЛОЖЕНИИ. Это вторая рука:
она не знает, как дом получил своё число, и потому её согласие есть
проверка, а не пересказ.

Третья рука — обратимость записи и чтения внутри самого дома
(`markdown.оракул`), и она проверяет ГРАММАТИКУ формата. Три руки
стерегут три разные беды: порчу корпуса, ложь дома о смысле и ошибку
дома в грамматике.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import markdown as md  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

ПРОХОДОВ = 8


def _числом(с):
    return int(с) if с.isdigit() else None


# ВТОРАЯ РУКА: (образец над предложением, что сосчитать самому).
# Каждый проверяет ОДНО притязание и вычисляет его из ЗАПИСИ своими
# средствами, не спрашивая дом.
def _уровень_решёток(запись, м):
    return len(запись.split(" ", 1)[0]) == _числом(м.group("n"))


def _уровень_подчёркивания(запись, м):
    черта = запись.split("\n")[1]
    return (1 if черта[0] == "=" else 2) == _числом(м.group("n"))


def _номер_пункта(запись, м):
    return запись.split(".", 1)[0] == м.group("n")


def _глубина_вложения(запись, м):
    return len(запись) - len(запись.lstrip(" ")) == _числом(м.group("n"))


def _задача_сделана(запись, м):
    сделано = запись[3] == "x"
    return сделано == (м.group("v") in ("done", "сделан"))


def _выравнивание(запись, м):
    лево = запись.split("|")[1].strip()
    слева, справа = лево.startswith(":"), лево.endswith(":")
    было = ("centred" if слева and справа
            else "right" if справа else "left")
    ру = ("по центру" if слева and справа
          else "вправо" if справа else "влево")
    return м.group("v") in (было, ру)


def _язык_ограды(запись, м):
    объявлен = запись.split("\n")[0][3:].strip()
    сказан = м.group("v").strip()
    if сказан in ("with no language named", "без названного языка"):
        return объявлен == ""
    return объявлен != "" and объявлен in сказан


def _ход_графа(запись, м):
    ход = "TD" if "graph TD" in запись else "LR"
    вниз = м.group("v") in ("top down", "сверху вниз")
    return вниз == (ход == "TD")


def _место_в_боковике(запись, м):
    for строка in запись.split("\n"):
        if строка.startswith("sidebar_position: "):
            return строка.split(": ", 1)[1] == м.group("n")
    return False


def _разрыв_из_одних_знаков(запись, м):
    знаки = м.group("v")
    return len(set(знаки)) == 1 and len(знаки) >= 3 and знаки == запись


# ОБРАЗЕЦ СВЕРКИ ОБЯЗАН РАЗЛИЧАТЬ РОД, А НЕ УЗНАВАТЬ СЛОВА. Первая
# редакция ловила «heading of level (\d+)» — и проверка заголовка ATX
# срабатывала на заголовке setext, считая решётки там, где их нет: сто
# двадцать восемь честных строк объявились ложью. Это тот же шрам, что
# «суд владеет строкой, чей ответ его рода»: похожая форма ещё не род.
# Каждый образец здесь привязан к ЗАЧИНУ своего предложения.
СВЕРКИ = (
    (re.compile(r"^«#{1,6} [^»]*» is a heading of level (?P<n>\d+) "
                r"whose text"), _уровень_решёток),
    (re.compile(r"^«#{1,6} [^»]*» — заголовок уровня (?P<n>\d+),"),
     _уровень_решёток),
    (re.compile(r"^text underlined by .+? is a heading of level "
                r"(?P<n>\d+):"), _уровень_подчёркивания),
    (re.compile(r"^текст, подчёркнутый .+?, есть заголовок уровня "
                r"(?P<n>\d+):"), _уровень_подчёркивания),
    (re.compile(r"^a number then a dot begins an ordered list item: "
                r"item (?P<n>\d+) is"), _номер_пункта),
    (re.compile(r"^число и точка начинают пункт нумерованного списка: "
                r"пункт (?P<n>\d+) —"), _номер_пункта),
    (re.compile(r"^(?P<n>\d+) leading spaces nest"), _глубина_вложения),
    (re.compile(r"^(?P<n>\d+) пробела в начале вкладывают"),
     _глубина_вложения),
    (re.compile(r"^«- \[[ x]\]» begins a task item: the item «.+» is "
                r"(?P<v>not done|done)\."), _задача_сделана),
    # ПОРЯДОК В ЧЕРЕДОВАНИИ ЕСТЬ ЗАКОН, А НЕ ВКУС: «сделан|не сделан»
    # находит «сделан» ВНУТРИ «не сделан», и суд читал отрицание как
    # утверждение. Длинная ветвь стоит первой.
    (re.compile(r"^«- \[[ x]\]» начинает пункт задачи: пункт «.+» "
                r"(?P<v>не сделан|сделан)\."), _задача_сделана),
    (re.compile(r"^the second row of a table sets alignment: «[:\-]+» "
                r"is (?P<v>centred|right|left)\."), _выравнивание),
    (re.compile(r"^вторая строка таблицы задаёт выравнивание: "
                r"«[:\-]+» есть (?P<v>по центру|вправо|влево)\."),
     _выравнивание),
    (re.compile(r"^three backticks fence a code block"
                r"(?P<v> of language [a-z]+| with no language named);"),
     _язык_ограды),
    (re.compile(r"^три обратные кавычки огораживают блок кода"
                r"(?P<v> на языке [a-z]+| без названного языка);"),
     _язык_ограды),
    (re.compile(r"^a mermaid fence draws a graph: it goes "
                r"(?P<v>top down|left to right)"), _ход_графа),
    (re.compile(r"^ограда mermaid рисует граф: он идёт "
                r"(?P<v>сверху вниз|слева направо)"), _ход_графа),
    (re.compile(r"^front matter fenced by three dashes .+ place in the "
                r"sidebar is (?P<n>\d+)\."), _место_в_боковике),
    (re.compile(r"^front matter, огороженный тремя дефисами, .+ место "
                r"в боковике — (?P<n>\d+)\."), _место_в_боковике),
    (re.compile(r"^«(?P<v>[*\-_]{3,})» alone on a line"),
     _разрыв_из_одних_знаков),
    (re.compile(r"^«(?P<v>[*\-_]{3,})» в отдельной строке"),
     _разрыв_из_одних_знаков),
)


def _поверхности():
    """{строка: запись} — всё, что объявленные конструкции могут сказать.

    Выводится из дома, а не читается из корпуса: суд знает, ЧТО должно
    быть сказано, прежде чем увидит, что сказано. Рядом с каждой
    поверхностью стоит ЕЁ ЗАПИСЬ — предмет, о котором поверхность
    говорит и по которому суд считает притязание сам.
    """
    import gen_genesis_markdown as ген
    вон = {}
    for шаг in range(ПРОХОДОВ):
        for семья in ("commonmark", "gfm", "mdx"):
            for запись, строки in ген.поверхности(семья, шаг):
                for строка in строки:
                    for часть in строка.split("\n"):
                        вон.setdefault(часть, запись)
    return вон


_ПОВЕРХНОСТИ = None


def поверхности():
    global _ПОВЕРХНОСТИ
    if _ПОВЕРХНОСТИ is None:
        sys.path.insert(0, str(КОРЕНЬ / "tools"))
        _ПОВЕРХНОСТИ = _поверхности()
    return _ПОВЕРХНОСТИ





def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.rstrip("\n")
    if not с.strip():
        return False, False
    запись = поверхности().get(с)
    if запись is None:
        return False, False
    # СВЕРЯЕТСЯ ТЕЛО ОТВЕТА, А НЕ СТРОКА ЦЕЛИКОМ. Образцы привязаны к
    # зачину предложения (иначе проверка ATX срабатывает на setext), и
    # вопросная поверхность, несущая то же предложение ПОСЛЕ вопроса,
    # уходила из-под проверки: подсадка «дом лжёт об уровне» ловилась
    # лишь на половине строк. Вопрос отделяется, притязание сверяется.
    тело = с
    for зачин in ("what does ", "что значит "):
        if с.startswith(зачин) and "? " in с:
            тело = с.split("? ", 1)[1]
            break
    for образец, сверить in СВЕРКИ:
        м = образец.search(тело)
        if м:
            try:
                if not сверить(запись, м):
                    return True, False
            except (IndexError, ValueError):
                return True, False
    return True, True


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"РАЗМЕТКА-ПОЛНАЯ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("РАЗМЕТКА-ПОЛНАЯ ОТКАЗ: обход пуст, судить нечего")
        return 2
    беды = md.оракул()
    if беды:
        print(f"РАЗМЕТКА-ПОЛНАЯ FAIL: дом необратим на "
              f"{len(беды)} случаях: {беды[:3]}")
        return 1
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"РАЗМЕТКА-ПОЛНАЯ {поза}: {ложных} ложных из {судимых} "
          f"судимых ({len(пути)} файлов, обратимость дома цела)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
