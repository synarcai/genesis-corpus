#!/usr/bin/env python3
"""[ВЗВЕШЕННОЕ СРЕДНЕЕ] — вес группы, пересчитанный судом разбором записи.

Суд не пишет закона заново: он берёт его у дома (`wmeanforms`), где две таблицы групп
объявлены порознь — неравные и равные. Всякая запись страницы считается РАЗБОРОМ со
скобками и четырьмя знаками, и ДЕЛЕНИЕ БЕРЁТСЯ ТОЛЬКО НАЦЕЛО: корпус, сказавший «среднее
3,25», научил бы округлению как истине, и запись с остатком не есть запись этого дома.

    СУД, ПИШУЩИЙ ЗАКОН ВТОРОЙ РАЗ, РАСХОДИТСЯ С ДОМОМ НА ПЕРВОЙ ЖЕ ПРАВКЕ.

САМОПРОВЕРКА ДОМА СТЕРЕЖЁТ ТО, ЧЕГО СУДУ НЕ ВИДНО: обе стороны ловушки обязаны быть
показаны, и таблицы обязаны быть тем, чем названы, — пара, у которой счёты сошлись при
неравных группах, показала бы ловушку не ту.

    python3 courts/wmean_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import closedworld  # noqa: E402
from closedworld import Слой  # noqa: E402 — палата подаёт имя мира лишь тому, кто ввёз Слой
import wmeanforms  # noqa: E402 — дом, объявивший вес и среднее

ИМЯ_СУДА = "wmean"
ЗАМКНУТЫЕ_МИРЫ = frozenset({"wmean"})


def _судить(строка):
    return wmeanforms.судить(строка)


судить = closedworld.замкнуть(_судить, ЗАМКНУТЫЕ_МИРЫ)


def main():
    import genesis
    судимо = ложных = 0
    примеры = []
    for путь in genesis.worlds(kind="shows"):
        for строка in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            если, верно = судить(строка)[:2]
            if not если:
                continue
            судимо += 1
            if not верно:
                ложных += 1
                if len(примеры) < 5:
                    примеры.append(f"{путь.stem}: {строка.strip()[:90]}")
    for п in примеры:
        print(f"  {п}")
    поза = "PASS" if ложных == 0 else "FAIL"
    print(f"ВЗВЕШЕННОЕ СРЕДНЕЕ {поза}: {ложных} ложных из {судимо} судимых (рубеж 0); "
          f"родов объявлено {len(wmeanforms.РОДЫ)}, страниц {len(wmeanforms.ПОКАЗЫ)}")
    return 0 if ложных == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
