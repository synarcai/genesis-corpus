#!/usr/bin/env python3
"""СУД ПОВЕРХНОСТЕЙ ДЕЙСТВИЯ: имя, управление, род связки и счёт разом.

Слой именования говорит одно и то же четырьмя поверхностями, и каждая
может солгать по-своему. Суд проверяет ЧЕТЫРЕ вещи, и ни одна не
выводится из прочих:

  СЧЁТ        — «сложение 9 и 3 даёт 12» пересчитывается заново;
  УПРАВЛЕНИЕ  — «вычитание 3 ИЗ 9», но «сложение 9 И 3»: предлог назван
                действием, и подмена предлога есть подмена УТВЕРЖДЕНИЯ
                («вычитание 9 из 3» говорит обратное), а не описка;
  РОД СВЯЗКИ  — «сумма … равнА», но «произведение … равнО»: связка
                согласуется с родом имени результата;
  СОГЛАСИЕ ВОПРОСА С ОТВЕТОМ — вопрос обязан спрашивать ТУ ЖЕ фразу,
                какою отвечает. Первая редакция свода спрашивала «что
                даёт вычитание 4 и 2?», отвечая «вычитание 2 из 4 даёт
                2», — две записи одного управления разошлись в первой
                же строке, и поймать это может только сверка пары.

ЧИСЛА СЛОВАМИ читаются домом числительных (tools/numerals.py) по
объявленной таблице пакета, а не разбираются здесь заново: «сорок два
минус пять будет тридцать семь» проверяется тем же законом разрядов,
каким слой это имя построил.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import numerals  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
ЛОЖНЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-corpus-file

# ДЕЙСТВИЕ, ЗАПИСАННОЕ ВТОРОЙ РУКОЙ: имя → (знак, предлог, порядок).
# «порядок» говорит, что стоит первым в фразе: 'ab' — уменьшаемое, 'ba'
# — вычитаемое (русское и английское вычитание называют вычитаемое
# ПЕРВЫМ: «вычитание 3 из 9», «the subtraction of 3 from 9»).
НОМИНАЛИЗАЦИИ = {
    "сложение": ("+", "и", "ab"), "вычитание": ("-", "из", "ba"),
    "умножение": ("*", "на", "ab"), "деление": ("/", "на", "ab"),
    "addition": ("+", "and", "ab"), "subtraction": ("-", "from", "ba"),
    "multiplication": ("*", "by", "ab"), "division": ("/", "by", "ab"),
}
# имя результата → (знак, связка)
РЕЗУЛЬТАТЫ = {
    "сумма": ("+", "равна"), "разность": ("-", "равна"),
    "произведение": ("*", "равно"), "частное": ("/", "равно"),
    "sum": ("+", "is"), "difference": ("-", "is"),
    "product": ("*", "is"), "quotient": ("/", "is"),
}


def счёт(знак, a, b):
    """Величина действия, или None — действие на этой паре не целое."""
    if знак == "+":
        return a + b
    if знак == "-":
        return a - b
    if знак == "*":
        return a * b
    if знак == "/":
        return a // b if b and a % b == 0 else None
    return None


НОМ = re.compile(
    r"^(?:(\w+) (\d+) (\w+) (\d+) даёт (\d+)"
    r"|the (\w+) of (\d+) (\w+) (\d+) gives (\d+))\.$")
РЕЗ = re.compile(
    r"^(?:(\w+) (\d+) и (\d+) (равна|равно) (\d+)"
    r"|the (\w+) of (\d+) and (\d+) (is) (\d+))\.$")
ВОПР_НОМ = re.compile(
    r"^(?:что даёт (.+?)\? (.+)|what does (.+?) give\? (.+))$")
ВОПР_РЕЗ = re.compile(
    r"^(?:чему (?:равна|равно) (.+?)\? (.+)|what is (.+?)\? (.+))$")
БУДЕТ = re.compile(
    r"^([^\d?]+?) (плюс|минус) ([^\d?]+?) будет ([^\d?]+?)\.$")
ВОПР_БУДЕТ = re.compile(r"^сколько будет (.+?)\? (.+)$")


def _номинализация(м):
    г = [x for x in м.groups() if x is not None]
    имя, a, предлог, b, c = г[0], int(г[1]), г[2], int(г[3]), int(г[4])
    объявлено = НОМИНАЛИЗАЦИИ.get(имя)
    if объявлено is None:
        return None
    знак, свой_предлог, порядок = объявлено
    if предлог != свой_предлог:
        return False
    лево, право = (a, b) if порядок == "ab" else (b, a)
    итог = счёт(знак, лево, право)
    return итог is not None and итог == c


def _результат(м):
    г = [x for x in м.groups() if x is not None]
    имя, a, b, связка, c = г[0], int(г[1]), int(г[2]), г[3], int(г[4])
    объявлено = РЕЗУЛЬТАТЫ.get(имя)
    if объявлено is None:
        return None
    знак, своя_связка = объявлено
    if связка != своя_связка:
        return False
    итог = счёт(знак, a, b)
    return итог is not None and итог == c


def _пара(фраза, ответ, образец, проверить):
    """Вердикт о паре вопрос-ответ, или None — пара не этого рода.

    СУД ВЛАДЕЕТ СТРОКОЙ, ЧЕЙ ОТВЕТ ЕГО РОДА, а не всякой, чей вопрос
    похож на его вопрос. Первая редакция ловила образцом «what is …? …»
    ВЕСЬ корпус — и объявила ложью четыреста сорок честных строк чужих
    миров, у которых просто та же вопросная форма. Вопрос принадлежит
    всем; род определяется ОТВЕТОМ.
    """
    м = образец.match(ответ)
    if not м:
        return None
    вердикт = проверить(м)
    if вердикт is None:
        return None
    return bool(вердикт) and ответ.startswith(фраза + " ")


def судить(строка):
    """(судимо, истинно) для одной строки."""
    с = строка.strip()
    if not с:
        return False, False
    м = НОМ.match(с)
    if м:
        в = _номинализация(м)
        if в is not None:
            return True, в
    м = РЕЗ.match(с)
    if м:
        в = _результат(м)
        if в is not None:
            return True, в
    м = ВОПР_НОМ.match(с)
    if м:
        г = [x for x in м.groups() if x is not None]
        в = _пара(г[0], г[1], НОМ, _номинализация)
        if в is not None:
            return True, в
    м = ВОПР_РЕЗ.match(с)
    if м:
        г = [x for x in м.groups() if x is not None]
        в = _пара(г[0], г[1], РЕЗ, _результат)
        if в is not None:
            return True, в
    м = БУДЕТ.match(с)
    if м:
        табл = numerals.таблица("ru")
        а, знак, б, ц = (numerals.прочесть(м.group(1), табл), м.group(2),
                         numerals.прочесть(м.group(3), табл),
                         numerals.прочесть(м.group(4), табл))
        if а is None or б is None or ц is None:
            return False, False
        итог = счёт("+" if знак == "плюс" else "-", а, б)
        return True, итог == ц
    м = ВОПР_БУДЕТ.match(с)
    if м:
        спрошено, ответ = м.group(1), м.group(2)
        судимо, истинно = судить(ответ)
        if судимо:
            return True, истинно and ответ.startswith(спрошено + " будет ")
    return False, False


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    try:
        return worlds(kind="shows")
    except Unreadable as беда:
        print(f"ПОВЕРХНОСТИ ОТКАЗ: {беда}")
        sys.exit(2)


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ПОВЕРХНОСТИ ОТКАЗ: обход пуст, судить нечего")
        return 2
    ложных = судимых = 0
    примеры = []
    for путь in пути:
        свои = 0
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                судимо, истинно = судить(строка)
                if not судимо:
                    continue
                судимых += 1
                if not истинно:
                    ложных += 1
                    свои += 1
                    if len(примеры) < 4:
                        примеры.append(f"{путь.name}: {строка.strip()[:80]}")
        if свои:
            print(f"  {путь.name:<30} ложных {свои}")
    for п in примеры:
        print(f"    {п}")
    поза = "ЛЕНТА" if явные else (
        "PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ПОВЕРХНОСТИ {поза}: {ложных} ложных из {судимых} судимых "
          f"({len(пути)} файлов)")
    if явные:
        return 0
    return 0 if ложных <= ЛОЖНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
