#!/usr/bin/env python3
"""[ЛОВУШКА СОГЛАСОВАНИЯ] — миры, чья порча формы имени не ловится ничем или ловится лишь соседом.

СУД, НЕ ЧИТАЮЩИЙ ФОРМЫ, КОТОРУЮ ЕГО ДОМ ПИШЕТ, ЗЕЛЕН И БЕСПОЛЕЗЕН НА ТОЙ САМОЙ ПОРЧЕ, РАДИ
КОТОРОЙ ПОСТАВЛЕН. Прибор `sign_traps` спрашивает это о знаке действия; этот — о ФОРМЕ ИМЕНИ
ПРИ ЧИСЛЕ, законе, каким за неделю были вылечены дом календаря, дом формул, дом доли, дом
случая и дом школьных форм — все пятеро поимённо, рукой, и ни один прибором.

    ПОРЧА, КОТОРУЮ СУД НЕ ВИДИТ, ЕСТЬ ПОРЧА, КОТОРОЙ ЕГО РУБЕЖ НЕ КАСАЕТСЯ.

ПРИЗНАК ЧИСТ И НЕ СПРАШИВАЕТ ОБ ИСТИНЕ. Берётся ЖИВАЯ строка мира, в ней ОДНО множественное имя
при числе больше единицы заменяется своим единственным («7 books» → «7 book»); ЧИСЛА НЕ
ТРОГАЮТСЯ ВОВСЕ, и потому строка ложна ТОЛЬКО согласованием, а не счётом. Палата судит порчу
так, как судили бы ворота записи, — со слоями своего мира.

ТРИ ИСХОДА, И ТОЛЬКО ПЕРВЫЙ ЕСТЬ ДОЛГ РУБЕЖА:

  · НЕ ПОЙМАНА — палата зовёт порчу истиной или молчит о ней. Мир беззащитен: подмена формы
    пройдёт в него при первой же правке дома.
  · ПОД ОБЩИМ ЗАКОНОМ — ложь названа судом ЯЗЫКА (`engram`, `langcount`, `rugram`), а не судом
    мира. Считается отдельно и НЕ ДЕРЖИТ РУБЕЖА, и вот почему.
  · ПОЙМАНА СВОИМ — ложь названа судом самого мира.

ЭТО НЕ ДОЛГ М-131, И РАЗЛИЧИЕ ЗДЕСЬ ВАЖНО (08.09, при рождении прибора). Прибор `sign_traps`
считает долгом всякую поимку соседом — и прав: ЗНАК ДЕЙСТВИЯ есть закон ДОМА, его пишет леджер
дома, и дом обязан его читать. ФОРМА ЖЕ ИМЕНИ ПРИ ЧИСЛЕ есть закон ЯЗЫКА, а не дома: он объявлен
пакетом, и живут им `engram` (английский), `rugram` (русский), `langcount` (девять языков).

    ЗАКОН ЯЗЫКА, ПЕРЕПИСАННЫЙ В СУДЕ МИРА, ЕСТЬ ВТОРОЙ СПИСОК — тот самый, о каком корпус
    предупреждает всю неделю: два списка об одном расходятся не «если», а «когда».

Оттого 75 миров, где подмену ловит лишь суд языка, суть НЕ ДОЛГ, А РАЗДЕЛЕНИЕ ТРУДА. Долгом
остаётся лишь то, чего не ловит НИКТО: там либо суд языка молчит (строка сочтена чужой), либо
слово не объявлено пакетом вовсе, — и рубеж стои́т на этом числе.

ЧЕГО ПРИБОР НЕ ДЕЛАЕТ: он не чинит и не судит домов, а только называет. И он не берёт слова,
объявленного пакетом лишь в одной форме, — там подмены не построить.

    python3 scripts/agree_traps.py [--подробно] [--мир ИМЯ] [--проб N]
"""
# ПУСТОЙ-ОБХОД: --мир no-such-world
import argparse
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import panel  # noqa: E402
from plural import singular  # noqa: E402

# РУБЕЖ-ДОЛГА: НЕПОЙМАННЫХ_РУБЕЖ = 0
#
# Рубеж есть ПОЛ и поставлен на достигнутом в час рождения прибора. Мир, куда подмена формы
# войдёт незамеченной, роняет прибор в тот же день, когда его напишут.
НЕПОЙМАННЫХ_РУБЕЖ = 0

# СУДЫ ЯЗЫКА — те, чей закон не о мире, а о речи. Они ловят порчу всюду, и поимка ими есть
# ПОЛНАЯ защита: закон формы имени принадлежит языку, а не дому.
ОБЩИЕ = frozenset({"engram", "langcount", "rugram", "arith"})
ПРОБ = 6


def имена_множественного():
    пакет = json.loads((КОРЕНЬ / "tools" / "langpacks" / "en.json").read_text(encoding="utf-8"))
    формы = пакет.get("noun_forms") or {}
    return {str(м).lower(): str(е).lower() for е, м in формы.items() if str(м) != str(е)}


def миры(дов):
    манифест = json.loads((КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json")
                          .read_text(encoding="utf-8"))
    вон = []
    for мир in манифест["worlds"]:
        путь = КОРЕНЬ / мир["file"]
        if not путь.is_file():
            continue
        # ПРОЗА НЕ ПОКАЗ, И ПАЛАТА ОБ ЭТОМ СКАЗАЛА ПРЕЖДЕ ПРИБОРА (08.09). Полка — книги Дарвина,
        # Фарадея, Гюйгенса — объявлена манифестом как `prose`, и суды показов ей не судьи:
        # «чужой текст: мера показов ему не судья». Порча формы там не ловится и не должна:
        # прибор, считавший бы это долгом, требовал бы судить чужую книгу законом своего дома.
        if мир.get("text") != "shows":
            continue
        if дов.мир and путь.stem not in (дов.мир, f"genesis_{дов.мир}"):
            continue
        вон.append(путь)
    return вон


def порчи(строки, пары, сколько):
    """[(живая, битая, слово)] — по одной подмене на строку, ровной выборкой по миру."""
    вон = []
    шаг = max(1, len(строки) // (сколько * 40))
    образец = re.compile(r"\b([2-9]|[1-9]\d+) (" + "|".join(sorted(пары, key=len, reverse=True))
                         + r")\b")
    for i in range(0, len(строки), шаг):
        с = строки[i]
        м = образец.search(с)
        if not м:
            continue
        ед = пары[м.group(2)]
        битая = с[:м.start(2)] + ед + с[м.end(2):]
        if битая != с:
            вон.append((с, битая, м.group(2)))
        if len(вон) >= сколько:
            break
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--мир", default=None)
    ап.add_argument("--проб", type=int, default=ПРОБ)
    дов = ап.parse_args()
    список = миры(дов)
    if not список:
        print(f"ЛОВУШКА СОГЛАСОВАНИЯ ОТКАЗ: миров не найдено"
              f"{f' ({дов.мир})' if дов.мир else ''}")
        return 2
    пары = имена_множественного()
    П = panel.палата()
    непойманные, соседом, всего_проб, поймано = [], [], 0, 0
    for путь in список:
        строки = [с for с in путь.read_text(encoding="utf-8", errors="replace").splitlines()
                  if с.strip()]
        проба = порчи(строки, пары, дов.проб)
        if not проба:
            continue
        слои, пласт = П.слои(путь), П.пласт_файла(путь)
        не_видит, лишь_сосед, свои = [], [], 0
        for живая, битая, слово in проба:
            всего_проб += 1
            судимо, истинно, кем = П.судить(битая, слои, пласт)
            if not судимо or истинно:
                не_видит.append((битая, слово))
                continue
            поймано += 1
            if set(кем) - ОБЩИЕ:
                свои += 1
            else:
                лишь_сосед.append((битая, кем))
        if не_видит:
            непойманные.append((путь.stem, len(не_видит), len(проба), не_видит[0]))
        elif лишь_сосед and not свои:
            соседом.append((путь.stem, len(лишь_сосед), len(проба), лишь_сосед[0]))
        if дов.подробно:
            print(f"{путь.stem:<32}{len(проба):>4} проб, не видит {len(не_видит)}, "
                  f"лишь сосед {len(лишь_сосед)}, свой {свои}")
    for имя, n, проб, (строка, слово) in непойманные:
        print(f"  НЕ ВИДИТ [{имя}] {n} из {проб} («{слово}»): «{строка[:96]}»")
    if дов.подробно:
        for имя, n, проб, (строка, кем) in соседом:
            print(f"  ПОД ЗАКОНОМ ЯЗЫКА [{имя}] {n} из {проб}, судьи {кем}: «{строка[:70]}»")
    поза = "PASS" if len(непойманные) <= НЕПОЙМАННЫХ_РУБЕЖ else "FAIL"
    print(f"ЛОВУШКА СОГЛАСОВАНИЯ {поза}: миров {len(список)}, проб {всего_проб}, поймано "
          f"{поймано}; МИРОВ, ГДЕ ПОРЧА НЕ ПОЙМАНА, {len(непойманные)} "
          f"(рубеж {НЕПОЙМАННЫХ_РУБЕЖ}); миров под ОБЩИМ ЗАКОНОМ ЯЗЫКА {len(соседом)} "
          f"— разделение труда, а не долг")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
