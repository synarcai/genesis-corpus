#!/usr/bin/env python3
"""[ЗАТЕНЕНИЕ] — имя, определённое в приборе дважды, есть тихая потеря.

ШРАМ, КУПЛЕННЫЙ ДОРОГО И ДВАЖДЫ ЗА ОДНУ ПРАВКУ. Добавляя суду программ
закон о цикле «пока», я назвал образец `ЦИКЛ` — именем, под которым в
том же файле уже жил ДРУГОЙ закон, — и затёр его. Починив, назвал
следующий образец `ШАГ` и затёр второй. Оба раза двадцать честных
показов проваливались сквозь исчезнувшую ветвь в чужую.

НИ СИНТАКСИС, НИ ЗАПУСК ОБ ЭТОМ НЕ СКАЗАЛИ. Python не считает
переопределение ошибкой, линтер молчит о верхнем уровне, и вердикт
остаётся «PASS», пока не спросишь у корпуса. Сказал только замер — а
замер есть последняя линия, не первая.

ЭТО ПРОВЕРЯЕТСЯ МЕХАНИЧЕСКИ И ПОТОМУ ОБЯЗАНО ПРОВЕРЯТЬСЯ. Имя верхнего
уровня, присвоенное дважды в одном файле, — находка. Условная ветвь
(`if …: X = A else: X = B`) исключением не является: она стоит внутри
блока, а не на верхнем уровне, и здесь не считается.
"""
import ast
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent

# РУБЕЖ-ДОЛГА: ЗАТЕНЕНИЙ_РУБЕЖ = 0
ЗАТЕНЕНИЙ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: --корень no-such-directory


def имена(дерево):
    """[(имя, строка)] присваиваний ВЕРХНЕГО уровня, по порядку."""
    вон = []
    for узел in дерево.body:
        цели = []
        if isinstance(узел, ast.Assign):
            цели = узел.targets
        elif isinstance(узел, ast.AnnAssign):
            цели = [узел.target]
        elif isinstance(узел, ast.AugAssign):
            # ПРИРАЩЕНИЕ НЕ ЕСТЬ ЗАТЕНЕНИЕ: «ФОРМЫ += [...]» ТРЕБУЕТ
            # прежнего имени, а не отменяет его, и без него упало бы
            # само. Первая редакция считала его находкой и назвала
            # затенением два честных расширения списка — граница
            # прибора, найденная первым же его прогоном.
            continue
        elif isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef,
                               ast.ClassDef)):
            вон.append((узел.name, узел.lineno))
            continue
        for цель in цели:
            if isinstance(цель, ast.Name):
                вон.append((цель.id, узел.lineno))
    return вон


def судить_файл(путь):
    """[(имя, первая строка, вторая строка)] — затенённые имена."""
    try:
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return []
    видано, вон = {}, []
    for имя, строка in имена(дерево):
        if имя in видано:
            вон.append((имя, видано[имя], строка))
        else:
            видано[имя] = строка
    return вон


def обход(корень):
    места = ("courts", "tools", "scripts")
    for место in места:
        каталог = корень / место
        if каталог.is_dir():
            yield from sorted(каталог.glob("*.py"))


def main():
    корень = КОРЕНЬ
    if "--корень" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--корень") + 1])
    файлы = list(обход(корень))
    if not файлы:
        print("ЗАТЕНЕНИЕ ОТКАЗ: обход пуст, судить нечего")
        return 2
    затенений = 0
    for путь in файлы:
        for имя, первая, вторая in судить_файл(путь):
            затенений += 1
            if затенений <= 6:
                print(f"  {путь.name}:{вторая} имя «{имя}» уже занято "
                      f"строкой {первая}")
    поза = "PASS" if затенений <= ЗАТЕНЕНИЙ_РУБЕЖ else "FAIL"
    print(f"ЗАТЕНЕНИЕ {поза}: {затенений} имён определены дважды "
          f"({len(файлы)} файлов, рубеж {ЗАТЕНЕНИЙ_РУБЕЖ})")
    return 0 if затенений <= ЗАТЕНЕНИЙ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
