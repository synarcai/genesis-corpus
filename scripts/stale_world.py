#!/usr/bin/env python3
"""[МИР БЕЗ ПРЕДЪЯВЛЕНИЯ] — миры, чьи СТОЯЩИЕ строки нынешняя палата назвала бы ложью.

ВОРОТА ЗАПИСИ СУДЯТ ПРИ КОВКЕ, А НЕ ПОСЛЕ. `layer.emit` не пропускает ни ложной, ни несудимой
строки — но спрашивает об этом ОДИН РАЗ, в час, когда мир куётся. Суд, написанный назавтра,
о старом мире не спрашивает никто.

    МИР, НЕ ПЕРЕКОВАННЫЙ ПОСЛЕ ПОЯВЛЕНИЯ СУДА, НЕ ПРОВЕРЕН ИМ. Ковка есть не только письмо, но
    и ПРЕДЪЯВЛЕНИЕ мира новым судьям.

ПОВОД НАЙДЕН ДЕЛОМ, А НЕ ДОГАДКОЙ (08.09). Дом формул перековывался ради иного долга, и ворота
его не пустили: двенадцать строк, стоявших в своде, нынешняя палата звала ложью. Обвинение
оказалось напрасным (суд счёта не знал ни родительного падежа, ни даты) — но УЗНАЛ Я ОБ ЭТОМ
ЛИШЬ ПОТОМУ, ЧТО СЛУЧАЙНО ТРОНУЛ ДОМ. Прибор ставится, чтобы не зависеть от случая.

ЧТО ЗАМЕРЯЕТСЯ. Из каждого мира берётся РОВНАЯ выборка строк (каждая k-я, а не жребий: замер
обязан повторяться), слои строятся по ВСЕМУ файлу — как их строит палата у ворот, — и каждая
строка выборки судится всей палатой. Мир, где нашлась хоть одна ложная строка, назван.

    ЛОЖЬ ЕСТЬ ДОЛГ, НЕМОТА — НЕТ. Ворота не пускают и несудимого, но немота на выборке бывает
    честной границей суда, а не порчей мира; она считается и показывается, но рубежа не держит.

    И ЭТО НЕ ДОГАДКА: шесть немых, какие прибор показывает изо дня в день, названы поимённо
    (08.09). Все шесть — ПОСЛЕДНЯЯ строка цепи стенограмм: «конец: сетка …» / «end: grid …».
    Суд её образец имеет и в целом файле её ЧИТАЕТ; но вердикт его стои́т на состоянии,
    накопленном предыдущими шагами, а выборка эти шаги пропускает — и свежий слой их не
    возвращает, ибо состояние копится ПРИ СУДЕЙСТВЕ, а не при чтении файла.

        ТА ЖЕ ЦЕПЬ, ЧТО ДАЁТ ЛОЖНЫЕ ПОДОЗРЕНИЯ, ДАЁТ И ЧЕСТНУЮ НЕМОТУ. Вторая проверка снимает
        первое и не снимает второго — оттого ложь держит рубеж, а немота лишь показывается.

АРХИВ НЕ ЕСТЬ СВОД, и это вторая граница прибора (08.09). В папке миров лежат слепки прошлых
выпусков — `genesis_v4`, `v5`, `v6`, — которых нет ни в манифесте, ни в своде. Нынешняя палата
зовёт в них ложью 6 149 строк: «the letter x is read as x» и подобное, писанное домами, каких
уже нет. Это не долг свода, а РАЗНИЦА ЭПОХ.

    МИР, НЕ ВОШЕДШИЙ В СВОД, НЕ ПРЕДЪЯВЛЯЕТСЯ ПАЛАТЕ. Судить слепок прошлого нынешним законом
    значит вменять вчерашнему дню сегодняшний указ.

Прибор берёт лишь миры, ОБЪЯВЛЕННЫЕ МАНИФЕСТОМ, — тот же список, каким живёт свод.

ЦЕПЬ ПОКАЗОВ НЕ ТЕРПИТ ВЫБОРКИ, И ЭТО СТОИЛО ПРИБОРУ ПЕРВОГО ЖЕ ПРОГОНА (08.09). Мир стенограмм
был назван разошедшимся: 37 строк из 200. Судимый ЦЕЛИКОМ, тот же мир даёт ноль. Разница не в
строках, а в СЛОЕ: слой мира живёт при судействе и помнит сетку предыдущего шага, и «шаг 4»,
прочитанный сразу после «шага 1», сверяется с чужой сеткой.

    СТРОКА, ВЫРВАННАЯ ИЗ ЦЕПИ, СУДИТСЯ НЕ ТА. Выборка дешева именно тем, что рвёт порядок, — и
    ровно тем же она лжёт о мирах, чьи показы стоят цепью.

Оттого прибор судит ДВАЖДЫ: дешёвая выборка при общем слое лишь ПОДОЗРЕВАЕТ, а всякая
подозреваемая строка пересуживается со СВЕЖИМ слоем, построенным по всему файлу заново, — так,
как её судили бы ворота записи. Ложью зовётся лишь то, что пережило вторую проверку.

    ПОДОЗРЕНИЕ ДЁШЕВО, ПРОВЕРКА ДОРОГА́, И ПОТОМУ ПРОВЕРЯЕТСЯ ЛИШЬ ПОДОЗРЕВАЕМОЕ.

ЦЕНА И ЕЁ ГРАНИЦА НАЗВАНЫ ПРЯМО: выборка есть выборка. Ноль этого прибора значит «в выборке
лжи нет», а не «мир чист»; полную проверку даёт лишь перековка всех миров, и она дорога́ —
оттого прибор ходит по всем мирам дёшево и часто, а ковка остаётся редкой и полной.

    python3 scripts/stale_world.py [--проб N] [--мир ИМЯ] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --мир no-such-world
import argparse
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import panel  # noqa: E402

# РУБЕЖ-ДОЛГА: ЛЖИВЫХ_МИРОВ_РУБЕЖ = 0
#
# Поставлен прибор был на 0 — и это не пустой рубеж, а показание: тот единственный мир, что
# подал повод (формулы), был вылечен в тот же час правкой СУДА, а не мира, ибо обвинение его
# было напрасным. Рубеж есть ПОЛ: мир, разошедшийся с палатой, роняет прибор в тот день, когда
# суд станет строже мира.
ЛЖИВЫХ_МИРОВ_РУБЕЖ = 0
ПРОБ = 40


def _объявленные():
    """Имена файлов миров, объявленных манифестом, — тот же список, каким живёт свод."""
    п = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    если = json.loads(п.read_text(encoding="utf-8")) if п.is_file() else []
    ряд = если.get("worlds", если) if isinstance(если, dict) else если
    вон = set()
    for мир in ряд if isinstance(ряд, list) else ():
        файл = (мир or {}).get("file") if isinstance(мир, dict) else None
        if файл:
            вон.add(pathlib.Path(файл).name)
    return вон


def выборка(строки, сколько):
    """Каждая k-я строка — ровно по всему миру, и тот же набор при том же мире."""
    живые = [с for с in строки if с.strip()]
    if len(живые) <= сколько:
        return живые
    шаг = len(живые) // сколько
    return [живые[i * шаг] for i in range(сколько)]


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--проб", type=int, default=ПРОБ)
    ап.add_argument("--мир", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    объявлено = _объявленные()
    миры = [п for п in sorted((КОРЕНЬ / "datasets").glob("genesis_*.txt"))
            if п.name in объявлено]
    if дов.мир:
        миры = [п for п in миры if п.stem == f"genesis_{дов.мир}" or п.stem == дов.мир]
    if not миры:
        print(f"МИР БЕЗ ПРЕДЪЯВЛЕНИЯ ОТКАЗ: миров не найдено{f' ({дов.мир})' if дов.мир else ''}")
        return 2
    П = panel.палата()
    лживые, всего_проб, всего_немых, всего_лжи = [], 0, 0, 0
    for путь in миры:
        строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
        проба = выборка(строки, дов.проб)
        if not проба:
            continue
        слои, пласт = П.слои(путь), П.пласт_файла(путь)
        ложь, немых = [], 0
        for с in проба:
            судимо, истинно, кем = П.судить(с, слои, пласт)
            if not судимо:
                немых += 1
            elif not истинно:
                # ВТОРАЯ ПРОВЕРКА СО СВЕЖИМ СЛОЕМ: подозрение выборки против цепи показов
                судимо2, истинно2, кем2 = П.судить(с, П.слои(путь), П.пласт_файла(путь))
                if судимо2 and not истинно2:
                    ложь.append((с, кем2 or кем))
        всего_проб += len(проба); всего_немых += немых; всего_лжи += len(ложь)
        if ложь:
            лживые.append((путь.stem, len(ложь), len(проба), ложь[0]))
        if дов.подробно:
            print(f"{путь.stem:<34}{len(проба):>5} проб, ложных {len(ложь)}, немых {немых}")
    for имя, сколько, проб, (строка, кем) in лживые:
        print(f"  РАЗОШЁЛСЯ [{имя}] {сколько} из {проб}, судьи {кем}: «{строка[:100]}»")
    поза = "PASS" if len(лживые) <= ЛЖИВЫХ_МИРОВ_РУБЕЖ else "FAIL"
    print(f"МИР БЕЗ ПРЕДЪЯВЛЕНИЯ {поза}: миров {len(миры)}, проб {всего_проб}; "
          f"РАЗОШЕДШИХСЯ С ПАЛАТОЙ {len(лживые)} (рубеж {ЛЖИВЫХ_МИРОВ_РУБЕЖ}); "
          f"ложных строк {всего_лжи}, немых {всего_немых}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
