# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import collections
import itertools
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"

# РУБЕЖ-ДОЛГА: МОЛЧАЩИХ_РУБЕЖ = 0
МОЛЧАЩИХ_РУБЕЖ = 0

# БЛИЗОСТЬ, С КОТОРОЙ НАЧИНАЕТСЯ ВОПРОС. Взята из замера: ниже неё пары идут сплошь и близость
# перестаёт что-либо значить; выше — их двадцать три на двести пятьдесят четыре мира.
# ПРИБОР ГОНИТСЯ ЗА СОБСТВЕННЫМ ХВОСТОМ, И ЭТО НАЗВАНО (12.09).
#
#     ОБЪЯВЛЕНИЕ, НАЗЫВАЮЩЕЕ СОСЕДА, СБЛИЖАЕТСЯ С НИМ.
#
# Прибор нашёл две молчащие пары: `bignum ~ ruler_dense` и `fractions ~ ruler_dense`.
# Родство было настоящее — три мира показывают ОДНО ДЕЙСТВИЕ ОТ ЧИСЛА разным шагом:
# единицей, сотней, долей. Я назвал его в объявлениях — и прибор тут же нашёл ТРЕТЬЮ
# пару, `fractions ~ bignum`, ибо два объявления, заговорив об одном, стали похожи.
#
# ЭТО НЕ ПОРОК ПРИБОРА, А СВОЙСТВО МЕРЫ: близость считается по редким словам, а имя
# соседа есть редкое слово. Погоня кончается САМА, когда семья замкнута: три мира,
# три пары, и всякая названа. Прибор не заставляет называть — он заставляет НЕ МОЛЧАТЬ
# о том, что уже измеримо близко, и семья из трёх замыкается на трёх шагах, а не растёт.
БЛИЗКО = 0.25
# МАЛЫЙ ЖАНР НЕ СУДИТСЯ: доля от знаменателя меньше восьми скачет от одного слова.
МАЛЫЙ_ЖАНР = 8
# ОБЩИХ СЛОВ ДОЛЖНО БЫТЬ НЕ МЕНЬШЕ ЧЕТЫРЁХ, И ЭТО КУПЛЕНО ЗАМЕРОМ 12.09.
#
# Одной доли мало: пара с двумя общими словами при малых словарях даёт те же 0,25, что и пара
# с пятью. Хуже того, мера ОКАЗАЛАСЬ НЕУСТОЙЧИВОЙ: стои́т написать трём бедным мирам честные
# объявления — и редкость слов по всему своду сдвигается, а с нею и соседи ЧУЖИХ пар. Замер:
# при отсечке по одному общему слову молчащих было 6, после трёх новых объявлений стало 9;
# при отсечке в четыре — 2 и 2.
#
#     МЕРА, СЧИТАЮЩАЯ РЕДКОСТЬ СЛОВА ПО ВСЕМУ СВОДУ, МЕНЯЕТСЯ ОТ ВСЯКОГО НОВОГО ОБЪЯВЛЕНИЯ:
#     БОГАТЕЯ РЕЧЬЮ, СВОД ПЕРЕСТАВЛЯЕТ СВОИХ ЖЕ СОСЕДЕЙ.
#
# Снятый двойник `carry ~ mixedunits` делил ПЯТЬ редких слов и потому не теряется: отсечка
# срезает пол шума и оставляет сигнал.
МИН_ОБЩИХ = 4
СЛОВО = re.compile(r"[a-zа-яё]{4,}", re.I)


def жанры(манифест):
    тело = json.loads(манифест.read_text(encoding="utf-8"))
    return {з["name"]: (з.get("genre") or "")
            for з in тело["worlds"] if з.get("text") == "shows"}


def редкие_слова(жанр_по_имени):
    """Слова, встречающиеся не более чем в сороковой доле объявлений."""
    часто = collections.Counter()
    for текст in жанр_по_имени.values():
        часто.update({с.lower() for с in СЛОВО.findall(текст)})
    порог = max(3, len(жанр_по_имени) // 40)
    return {с for с, n in часто.items() if n <= порог}, порог


def близкие(жанр_по_имени):
    """[(доля, a, b, общие слова)] для пар выше рубежа близости."""
    редкие, _ = редкие_слова(жанр_по_имени)
    свои = {и: {с.lower() for с in СЛОВО.findall(т)} & редкие
            for и, т in жанр_по_имени.items()}
    вон = []
    for a, b in itertools.combinations(sorted(жанр_по_имени), 2):
        ta, tb = свои[a], свои[b]
        if len(ta) < МАЛЫЙ_ЖАНР or len(tb) < МАЛЫЙ_ЖАНР:
            continue
        общ = ta & tb
        доля = len(общ) / min(len(ta), len(tb))
        if доля >= БЛИЗКО and len(общ) >= МИН_ОБЩИХ:
            вон.append((доля, a, b, sorted(общ)))
    вон.sort(reverse=True)
    return вон


# ССЫЛКА НА СОСЕДА, А НЕ СЛУЧАЙНОЕ СЛОВО. Первая редакция искала имя мира как отдельное слово —
# и объявила знающими пару `carry ~ mixedunits`, ибо жанр соседа начинается словами «the carry
# that is a thousand»: имя моего мира было обиходным английским словом, и проверка сработала
# в мою же пользу.
#
#     ИМЯ, СОВПАВШЕЕ С ОБИХОДНЫМ СЛОВОМ, ПРЕВРАЩАЕТ ПОИСК ИМЕНИ В ПОИСК СЛОВА.
#
# Свод ссылается на соседа ОДНИМ СПОСОБОМ — обратными кавычками (`mixedunits`) или путём
# (`tools/mixedunits.py`, `genesis_mixedunits`). Ссылкой считается только это.
def назван(имя, текст):
    """Сосед назван, если на него СОСЛАЛИСЬ: в обратных кавычках или путём."""
    формы = (rf"`[^`]*(?<![A-Za-z0-9_]){re.escape(имя)}(?![A-Za-z0-9_])[^`]*`",
             rf"(?:tools|courts|datasets)/[A-Za-z0-9_]*{re.escape(имя)}",
             rf"genesis_{re.escape(имя)}(?![A-Za-z0-9_])",
             rf"(?<![A-Za-z0-9_]){re.escape(имя)}(?:forms)?\.py")
    return any(re.search(ф, текст) for ф in формы)


def main():
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
        if not манифест.is_file():
            print(f"БЛИЗКИЙ СОСЕД ОТКАЗ: манифеста нет — {манифест}")
            return 2
    жанр = жанры(манифест)
    if not жанр:
        print("БЛИЗКИЙ СОСЕД ОТКАЗ: миров показов в манифесте нет, сравнивать нечего")
        return 2
    пары = близкие(жанр)
    молчат = []
    for доля, a, b, общие in пары:
        знают = назван(a, жанр[b]) or назван(b, жанр[a])
        if "--рядом" in sys.argv:
            метка = "знают" if знают else "МОЛЧАТ"
            print(f"  {доля:.3f}  {метка}  {a} ~ {b}: {' '.join(общие[:8])}")
        if not знают:
            молчат.append((доля, a, b))
    if "--рядом" in sys.argv:
        print(f"близких пар {len(пары)} (рубеж близости {БЛИЗКО}), молчат {len(молчат)}")
        return 0
    for доля, a, b in молчат[:8]:
        print(f"  {доля:.3f}  {a} ~ {b}: близки, и ни один не назвал другого")
    поза = "PASS" if len(молчат) <= МОЛЧАЩИХ_РУБЕЖ else "FAIL"
    print(f"БЛИЗКИЙ СОСЕД {поза}: {len(молчат)} пар молчат о близости "
          f"(рубеж {МОЛЧАЩИХ_РУБЕЖ}) из {len(пары)} близких; миров показов {len(жанр)}")
    return 0 if len(молчат) <= МОЛЧАЩИХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
