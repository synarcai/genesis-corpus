#!/usr/bin/env python3
"""[ГОЛОС СУДА] — два суда, кричащие одним именем, неразличимы в наборе и в леджере.

ПОВОД НАЙДЕН ДЕЛОМ, А НЕ ДОГАДКОЙ (12.09). Четыре новых суда были сделаны КОПИЕЙ с соседа, и
два из них унесли с собою чужое имя: `growfig` и `leap` печатали «КВАДРАТНЫЕ ЕДИНИЦЫ». Обе
правки прошли все прочие приборы свода: договор дома цел, палата полна, ворота открыты, миры
судимы — ибо имя в строке вердикта не читает НИКТО.

    КОПИЯ ПЕРЕНОСИТ НЕ ТОЛЬКО УСТРОЙСТВО, НО И ИМЯ; А ВЕРДИКТ ПОД ЧУЖИМ ИМЕНЕМ ПОТЕРЯН
    ДВАЖДЫ: СВОЙ НЕ НАЙДЁТСЯ, ЧУЖОЙ УДВОИТСЯ.

И тот же прибор, поставленный на дерево, нашёл ЧЕТЫРЕ пары, жившие так давно:

    «ПЛАН»    — `plan_court` (вердикт посадки) и `planforms_court` (задача по шагам)
    «СВОДКА»  — `average_court` (среднее из ряда) и `summaryforms_court` (заметка об эпизоде)
    «ШКАЛА»   — `scale_court` (порядок вещей) и `tempscale_court` (два градусника)
    «ЭПИЗОД»  — `episode_court` (алгебра эпизода) и `episodeforms_court` (лента по шагам)

Восемь судов, четыре имени, и всякая строка набора об одном из них читалась как строка о
другом. Разведены: «ПЛАН ШАГОВ», «СВОДКА ЭПИЗОДА», «ТЕМПЕРАТУРНАЯ ШКАЛА», «ЭПИЗОДНАЯ АЛГЕБРА».

ЧТО ЗАМЕРЯЕТСЯ. Голос суда есть текст ПЕРЕД «{поза}» в строке вердикта — то самое имя, под
которым суд входит в набор, в леджер и в отчёт. Прибор читает его РАЗБОРОМ дерева, а не
прогоном: суд, чтобы назвать себя, не обязан быть запущен.

ГРАНИЦА НАЗВАНА. Суд, не имеющий строки вердикта с «{поза}», НЕ СЧИТАЕТСЯ БЕЗЫМЯННЫМ: иные
пишут вердикт иначе (словом «PASS» прямо в рамке, ветвями if/else), и требовать одной формы
значило бы чинить обычай, а не беду. Такие названы отдельным числом, и это долг ПРИБОРА —
он видит не всех, — а не долг судов.

    python3 scripts/court_voice.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --дворы no-such-court-yard
import argparse
import ast
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: ОБЩИХ_ИМЁН_РУБЕЖ = 0
#
# Ноль есть ПОЛ: всякий новый суд, унёсший чужое имя копией, роняет прибор в час своего
# рождения — то есть ровно тогда, когда беду ещё дёшево исправить.
ОБЩИХ_ИМЁН_РУБЕЖ = 0

# ГОЛОС БЕРЁТСЯ ИЗ f-СТРОКИ ВЕРДИКТА: «f"ИМЯ {поза}: …"». Имя есть всё, что стои́т в строке
# ДО дыры позы, без хвостовых пробелов.
ГОЛОС = re.compile(r'"\s*([^"\'{}]*?)\s*\{поза\}')


def голоса(двор):
    """{имя файла: [голоса]} — по разбору текста, а не по прогону суда."""
    вон = {}
    for путь in sorted(двор.glob("*.py")):
        текст = путь.read_text(encoding="utf-8", errors="replace")
        try:
            ast.parse(текст)
        except SyntaxError:
            continue                    # неразбираемый файл есть находка ИНОГО прибора
        свои = [г for г in ГОЛОС.findall(текст) if г]
        вон[путь.stem] = свои
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ГОЛОС ЧИТАЕТСЯ и что общее имя видно.

        ЭТОТ ПРИБОР СТОИТ НА НУЛЕ И ЗЕЛЕНЕЕТ ОТ НУЛЯ НАХОДОК. Пусть признак голоса
        перестанет совпадать — и голосов не станет ни у кого, а общих имён, стало быть,
        тоже ноль: молчание, неотличимое от порядка.

    Четыре записи, и про каждую известно заранее, что прибор обязан из неё взять.
    """
    import tempfile
    беды = []
    случаи = (
        ('print(f"ИМЯ МОЁ {поза}: 0 ложных")\n', ["ИМЯ МОЁ"], "простой вердикт"),
        ('print(f"ДВА СЛОВА {поза}: {n} из {m}")\n', ["ДВА СЛОВА"], "вердикт с числами"),
        ('print(f"итого {n} строк")\n', [], "строка без позы"),
        ('x = 1\n', [], "файл без вердикта"),
    )
    with tempfile.TemporaryDirectory() as д:
        двор = pathlib.Path(д)
        for i, (текст, ждём, что) in enumerate(случаи):
            (двор / f"проба{i}.py").write_text(текст, encoding="utf-8")
        найдено = голоса(двор)
        for i, (_т, ждём, что) in enumerate(случаи):
            дало = найдено.get(f"проба{i}")
            if дало != ждём:
                беды.append(f"{что}: {дало} вместо {ждём}")
    # И ГЛАВНОЕ: ДВА ОДИНАКОВЫХ ГОЛОСА ОБЯЗАНЫ БЫТЬ НАЙДЕНЫ.
    with tempfile.TemporaryDirectory() as д:
        двор = pathlib.Path(д)
        (двор / "первый.py").write_text('print(f"ОДНО ИМЯ {поза}: a")\n', encoding="utf-8")
        (двор / "второй.py").write_text('print(f"ОДНО ИМЯ {поза}: b")\n', encoding="utf-8")
        (двор / "третий.py").write_text('print(f"ИНОЕ ИМЯ {поза}: c")\n', encoding="utf-8")
        общие = _общие(голоса(двор))
    if list(общие) != ["ОДНО ИМЯ"]:
        беды.append(f"общее имя не найдено: {dict(общие)}")
    return беды


def _общие(найдено):
    """{голос: [суды]} — только те голоса, что кричат из двух дворов и более."""
    по_голосу = collections.defaultdict(list)
    for имя, свои in найдено.items():
        for г in set(свои):
            по_голосу[г].append(имя)
    return {г: sorted(к) for г, к in sorted(по_голосу.items()) if len(к) > 1}


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ГОЛОС СУДА ОТКАЗ: чтение голоса не доказано ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--дворы", nargs="+", default=["courts"])
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    найдено = {}
    for двор in дов.дворы:
        п = КОРЕНЬ / двор
        if not п.is_dir():
            print(f"ГОЛОС СУДА ОТКАЗ: двора «{двор}» нет")
            return 2
        for имя, свои in голоса(п).items():
            найдено[f"{двор}/{имя}"] = свои
    if not найдено:
        print("ГОЛОС СУДА ОТКАЗ: судов не найдено, спрашивать не о ком")
        return 2
    общие = _общие(найдено)
    безголосых = [и for и, свои in найдено.items() if not свои]
    многоголосых = [(и, свои) for и, свои in найдено.items() if len(set(свои)) > 1]
    for г, кто in list(общие.items())[:8]:
        print(f"  ОДНО ИМЯ НА ДВОИХ «{г}»: {', '.join(кто)}")
    if дов.подробно:
        for и, свои in многоголосых[:12]:
            print(f"  МНОГОГОЛОСЫЙ {и}: {', '.join(sorted(set(свои)))}")
        for и in безголосых[:12]:
            print(f"  БЕЗ ГОЛОСА {и}")
    поза = "PASS" if len(общие) <= ОБЩИХ_ИМЁН_РУБЕЖ else "FAIL"
    print(f"ГОЛОС СУДА {поза}: судов с общим именем {len(общие)} пар (рубеж "
          f"{ОБЩИХ_ИМЁН_РУБЕЖ}); прочитано {len(найдено)} файлов, голосов "
          f"{sum(len(set(с)) for с in найдено.values())}, многоголосых {len(многоголосых)}, "
          f"без голоса {len(безголосых)} — их вердикт писан иначе, и это долг прибора")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
