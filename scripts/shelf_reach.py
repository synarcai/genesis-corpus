#!/usr/bin/env python3
"""[ОХВАТ ПОЛКИ] — какую долю ПРЕДЛОЖЕНИЙ книг корпус умеет прочесть судами.

Вопрос владельца стоит о знании: «сколько процентов знаний извлекается».
Показы корпуса читаются судами на сто процентов — это измерено. Но полка
(199 миров прозы, больше миллиона строк: учебники, книги, статьи) держит
знание, которого показы не касались, и мера её иная: не «верна ли строка»,
а КАКУЮ ЕЁ ФОРМУ КОРПУС ВООБЩЕ УМЕЕТ ПРОЧЕСТЬ.

Прибор берёт из полки выборку ПРЕДЛОЖЕНИЙ (детерминированную по семени),
подаёт каждое палате и считает три числа: прочитанные (какой-то суд взялся
судить), непрочитанные и ложные. Затем режет непрочитанные в скелеты
переписи форм и печатает самые частые — это карта: не «чего нет», а «какой
формы прозы у корпуса ещё нет дома».

Прибор НИЧЕГО НЕ ТРЕБУЕТ ОТ ПОЛКИ. Проза не обязана быть судимой: книга
пишется не для суда. Число здесь — не долг полки, а список ближайших домов.

    python3 scripts/shelf_reach.py [--выборка 4000] [--семя 1]
"""
import argparse
import collections
import pathlib
import random
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "courts"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import panel  # noqa: E402
import form_census as C  # noqa: E402
import genesis  # noqa: E402

# предложение кончается точкой, вопросом или восклицанием и пробелом
_КОНЕЦ = re.compile(r"(?<=[.!?])\s+")
_ДЛИНА = (30, 300)


def предложения(текст):
    for кусок in _КОНЕЦ.split(текст):
        с = кусок.strip()
        if _ДЛИНА[0] <= len(с) <= _ДЛИНА[1] and not с.startswith("\x0c"):
            yield с


def выборка(n, семя):
    """n предложений полки, взятых поровну из книг (детерминированно)."""
    книги = [м for м in genesis.manifest()["worlds"]
             if м.get("text") == "prose" and pathlib.Path(КОРЕНЬ / м["file"]).is_file()]
    р = random.Random(семя)
    на_книгу = max(1, n // max(1, len(книги)))
    вон = []
    for м in книги:
        путь = КОРЕНЬ / м["file"]
        try:
            текст = путь.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        свои = list(предложения(текст))
        if not свои:
            continue
        вон += [(м["name"], с) for с in р.sample(свои, min(на_книгу, len(свои)))]
    р.shuffle(вон)
    return вон[:n]


_РАВЕНСТВО = re.compile(r"\d\s*[=+×÷−-]\s*\d")
_СВЯЗКА = re.compile(r"\b(?:is|are|was|were|ist|sind|est|sont|есть|суть)\b|\s—\s")
_ПЕРЕЧЕНЬ = re.compile(r",[^,]+,[^,]+,")
_ВОПРОС = re.compile(r"[?？؟]")


def природа(с, скелет_):
    """ЧЕМ предложение МОГЛО БЫ быть судимо — карта ближайших домов, а не приговор.

    Проза не обязана быть судимой; но её предложения делятся по природе, и
    доля каждой природы говорит, какой дом дал бы больше всего чтения:
    равенство судится счётом уже сегодня; предложение С ЧИСЛОМ, но без
    равенства, ждёт дома, который свяжет число с вещью; связка без числа —
    дома определений; перечисление — дома списков; вопрос — дома пары.
    """
    есть_число = "#" in скелет_
    if _РАВЕНСТВО.search(с):
        return "равенство (судится счётом уже сегодня)"
    if _ВОПРОС.search(с):
        return "вопрос без ответа рядом (дом пары)"
    if есть_число and _ПЕРЕЧЕНЬ.search(с):
        return "перечисление с числом (дом списков)"
    if есть_число:
        return "число без равенства (дом «число при вещи»)"
    if _ПЕРЕЧЕНЬ.search(с):
        return "перечисление без числа (дом списков)"
    if _СВЯЗКА.search(с):
        return "связка без числа (дом определений)"
    return "повествование без числа и связки"


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--выборка", type=int, default=4000)
    ап.add_argument("--семя", type=int, default=1)
    а = ап.parse_args()
    суд = panel.палата()
    проба = выборка(а.выборка, а.семя)
    прочитано = ложно = 0
    кем = collections.Counter()
    немые = collections.Counter()
    примеры = {}
    природы = collections.Counter()
    природа_пример = {}
    for мир, с in проба:
        try:
            судимо, истинно, судьи = суд.судить(с, {}, None)
        except Exception:
            судимо, истинно, судьи = False, True, []
        if судимо:
            прочитано += 1
            for и in (судьи or ()):
                кем[и] += 1
            if not истинно:
                ложно += 1
        else:
            ск = C.род(C.скелет(с))
            ключ = " ".join(ск.split()[:6])
            немые[ключ] += 1
            примеры.setdefault(ключ, с)
            имя = природа(с, ск)
            природы[имя] += 1
            природа_пример.setdefault(имя, с)
    всего = len(проба)
    print(f"ОХВАТ ПОЛКИ: {прочитано} из {всего} предложений прочитаны судами ({100 * прочитано // max(1, всего)} %), "
          f"из них ложными названы {ложно}; книг в выборке {len({м for м, _ in проба})}")
    if кем:
        print("  чем читаются: " + ", ".join(f"{и} {n}" for и, n in кем.most_common(8)))
    print("  самые частые НЕПРОЧИТАННЫЕ начала (скелет первых шести слов):")
    for ключ, n in немые.most_common(8):
        print(f"    {n:4}  {ключ[:70]}")
    print("  НЕПРОЧИТАННОЕ ПО ПРИРОДЕ (чем предложение могло бы быть судимо):")
    всего_н = sum(природы.values()) or 1
    for имя, n in природы.most_common():
        print(f"    {n:5} ({100 * n // всего_н:2} %)  {имя}")
        if имя in природа_пример:
            print(f"            «{природа_пример[имя][:96]}»")
    return 0


if __name__ == "__main__":
    sys.exit(main())
