#!/usr/bin/env python3
"""[ПЕРЕПИСЬ ПОВТОРОВ] — сколько строк корпуса суть КОПИИ уже стоящей строки.

Найдено 05.09 через мир определений: он нёс 2930 строк при 1327 уникальных
(55 % повторов; «момент — это миг» тринадцать раз). Перепись по всем мирам дала
число, о котором не знал ни один прибор: 53 % строк корпуса — точные копии.

ПОЧЕМУ НИ ОДИН ПРИБОР ЭТОГО НЕ ВИДЕЛ. Палата судит СТРОКУ — и тринадцатая копия
так же истинна, как первая. Перепись форм считает МАССУ РАМКИ — и копия
прибавляет массу так же, как новая огласовка. Масса на форму, широта вопроса,
щербатость — все считают строки. Копия неотличима от показа для всякого прибора,
который не спрашивает «видел ли я эту строку».

ЧТО ЭТО ЗНАЧИТ И ЧЕГО НЕ ЗНАЧИТ. Повтор до LAW (слово покупается при двух
встречах) есть закон, а не порок. Повтор сверх LAW есть либо СТРОЙ сборки
(проходы пишут перестановку одного множества — «перестановка, а не выборка»),
либо огласовка одного показа, выдаваемая за массу (закон d5 о подделке
разнообразия). Прибор не решает, что из двух: он называет число и делит копии
на «до LAW» и «сверх LAW». Решение о потолке — за владельцем: половина свода
есть не долг, а вопрос строения.

ЧИСЛО РАЗОБРАНО НА ПРИЧИНЫ 12.09, И ИХ ОКАЗАЛОСЬ ТРИ, А НЕ ОДНА.

    ДОЛГ, НАЗВАННЫЙ ОДНИМ ЧИСЛОМ, НЕЧЕМ ПЛАТИТЬ: чтобы решать о потолке, надо
    знать, ЧТО ИМЕННО под ним лежит.

    ВОРОТА        Мир, кованный через `layer.emit_grouped`, потолка НЕ нарушает —
                  и это проверено делом: `compare_mult` перекован, файл не
                  изменился, и пять копий строки остались. Потолок считает
                  ПОКАЗЫ, а показ бывает МНОГОСТРОЧНЫМ: у этого мира 363 разных
                  показа, всякий предложен 21 раз и обрезан до двух. Строка же
                  повторяется оттого, что РАЗНЫЕ ПОКАЗЫ ДЕЛЯТ СТРОКУ.

                      ЗАКОН ВОРОТ ЕСТЬ ЗАКОН О ПОКАЗЕ, А НЕ О СТРОКЕ, И СЧИТАТЬ
                      ЕГО СТРОКАМИ ЗНАЧИТ МЕРИТЬ ЧУЖОЙ МЕРОЙ.

    ПАКЕТ ЯЗЫКА   Языковые миры кует не `layer`, а `langpack`, и там LAW есть ПОЛ,
                  а не потолок: «всякое слово, начертание и неправильность живёт
                  НЕ МЕНЕЕ LAW раз». Пол этот добирается повторением ЦЕЛЫХ СТРОК
                  — до шестидесяти двух копий одной. На них приходится 98 %
                  всего лишнего среди миров показов (74 376 строк из 75 847).

                      ДВА ЗАКОНА ОБ ОДНОМ ЧИСЛЕ, СМОТРЯЩИЕ В РАЗНЫЕ СТОРОНЫ,
                      НАДО НАЗЫВАТЬ РАЗНЫМИ ИМЕНАМИ.

    ОГРАДА        Строка разметки — «```», «---», «<details>» — не есть показ, и
                  повторение её не есть копия. `md_latex` несёт ограду блока кода
                  четыреста двадцать раз, и это его строение, а не долг.

Прибор делит лишнее на эти три и называет всякое порознь — решение о потолке
по-прежнему за владельцем, но теперь оно делится на три решения, из которых
два очевидны.

    python3 scripts/repeat_census.py [--свод] [--подробно]
"""
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from langpack import LAW  # noqa: E402


# ОГРАДА — СТРОКА РАЗМЕТКИ, А НЕ ПОКАЗ. Признак узкий нарочно: не «мало букв», а
# ИМЕННО ТЕ начертания, какими форматы отделяют блок от блока. Строка, несущая хоть
# одно слово, оградой не считается, сколько бы знаков препинания в ней ни стояло.
ОГРАДА = re.compile(r"^\s*(?:```[a-z]*|~~~|---+|===+|\*\*\*+|</?[a-z]+>|\|[\s|:-]*\|)\s*$")

# КУЗНИ ВОРОТ — те, что зовут `layer.emit` или `layer.emit_grouped`. Их миры судятся
# законом О ПОКАЗЕ, а не о строке, и лишнее в них есть общая строка разных показов.
#
# ЦЕЛЬ ОБЪЯВЛЯЕТСЯ ДВОЯКО, И ОБА ВИДА НАДО ЗНАТЬ: переменной наверху файла
# (`ЦЕЛЬ = "datasets/..."`) или прямо в зове (`emit_grouped("datasets/...", …)`).
# Первая редакция признака знала только первый вид и объявила `md_latex` и
# `markdown` НЕ воротными — а они воротные, и их четыреста восемнадцать копий суть
# ограда блока кода.
#
#     ПРИЗНАК, ЗНАЮЩИЙ ОДНУ ФОРМУ ОБЪЯВЛЕНИЯ, ЛЖЁТ О ТЕХ, КТО ОБЪЯВИЛ ИНАЧЕ.
_ЦЕЛЬ_ПЕРЕМЕННОЙ = re.compile(r'^ЦЕЛЬ\s*=\s*[\'"]([^\'"]+)[\'"]', re.M)
_ЦЕЛЬ_В_ЗОВЕ = re.compile(r'emit(?:_grouped)?\(\s*[\'"]([^\'"]+)[\'"]')


def _кузни(корень):
    """({мир: True} воротных, {мир: True} мимо ворот) — по всем кузням парка.

    МИМО ВОРОТ — кузня, объявившая цель, но пишущая файл СВОЕЙ РУКОЙ
    (`f.write(text)`), а не через `layer`. Закон копий её не касается, и это
    видно только так: по ОТСУТСТВИЮ зова, а не по присутствию имени.
    """
    ворота, мимо = {}, {}
    for ф in sorted((корень / "tools").glob("gen_genesis_*.py")):
        т = ф.read_text(encoding="utf-8", errors="replace")
        зовёт = "emit_grouped(" in т or "emit(" in т
        цели = set(_ЦЕЛЬ_ПЕРЕМЕННОЙ.findall(т)) | set(_ЦЕЛЬ_В_ЗОВЕ.findall(т))
        for цель in цели:
            (ворота if зовёт else мимо)[pathlib.Path(цель).name] = True
    return ворота, мимо


def перепись(путь, воротные=(), мимо=()):
    """(строк, уник, копий, сверх, макс, по_причинам) — лишнее, делённое на три.

    ПРИЧИНА НАЗЫВАЕТСЯ ПО МИРУ И ПО СТРОКЕ РАЗОМ: мир кован воротами или пакетом
    языка, а строка есть показ или ограда. Ограда считается оградой в ЛЮБОМ мире.
    """
    счёт = collections.Counter()
    for с in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        if с.strip() and not с.startswith("\x0c"):
            счёт[с] += 1
    n = sum(счёт.values())
    у = len(счёт)
    сверх = sum(k - LAW for k in счёт.values() if k > LAW)
    макс = max(счёт.values()) if счёт else 0
    причины = collections.Counter()
    воротный = путь.name in воротные
    for с, k in счёт.items():
        if k <= LAW:
            continue
        лишних = k - LAW
        if ОГРАДА.match(с):
            причины["ограда"] += лишних
        elif воротный:
            причины["ворота"] += лишних
        elif путь.name in мимо:
            причины["мимо ворот"] += лишних
        elif путь.name.startswith("genesis_lang_"):
            причины["пакет языка"] += лишних
        else:
            причины["неназванное"] += лишних
    return n, у, n - у, сверх, макс, причины


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--свод", action="store_true", help="только миры сборки full")
    ап.add_argument("--подробно", action="store_true")
    а = ап.parse_args()
    if а.свод:
        import genesis
        пути = [genesis._resolve(м["file"]) for м in genesis.manifest()["worlds"]
                if м.get("text") == "shows"]
        пути = [п for п in пути if п.is_file()]
    else:
        пути = sorted((КОРЕНЬ / "datasets").glob("genesis_*.txt"))
    ряды = []
    В = collections.Counter()
    П = collections.Counter()
    воротные, мимо = _кузни(КОРЕНЬ)
    for п in пути:
        n, у, повт, сверх, макс, причины = перепись(п, воротные, мимо)
        if not n:
            continue
        ряды.append((100 * повт // n, n, у, сверх, макс, п.name))
        В["строк"] += n; В["уник"] += у; В["повт"] += повт; В["сверх"] += сверх
        П.update(причины)
    ряды.sort(reverse=True)
    print(f"{'повт':>5} {'строк':>7} {'уник':>7} {'сверх LAW':>10} {'макс':>5}  мир")
    for д, n, у, сверх, макс, имя in ряды[:(40 if а.подробно else 12)]:
        print(f"{д:>4} % {n:>7} {у:>7} {сверх:>10} {макс:>5}  {имя}")
    доля = 100 * В["повт"] // В["строк"] if В["строк"] else 0
    доля_сверх = 100 * В["сверх"] // В["строк"] if В["строк"] else 0
    # ЛИШНЕЕ, ДЕЛЁННОЕ НА ПРИЧИНЫ: решение о потолке делится на три решения,
    # из которых два очевидны — ограда есть строение, ворота есть закон о показе.
    части = ", ".join(f"{и} {П[и]}" for и in ("пакет языка", "мимо ворот", "ворота", "ограда", "неназванное") if П[и])
    print(f"ПЕРЕПИСЬ ПОВТОРОВ: миров {len(ряды)}, строк {В['строк']}, уникальных {В['уник']}, "
          f"копий {В['повт']} ({доля} %), из них сверх LAW={LAW}: {В['сверх']} ({доля_сверх} %) "
          f"— {части}; миров с копиями > 10 %: {sum(1 for д, *_ in ряды if д > 10)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
