#!/usr/bin/env python3
"""[ОХВАТ ПОНЯТИЯ] — что проза НАЗЫВАЕТ, но показы не ПОКАЗЫВАЮТ.

МЕРА, ЧЕЙ ЗНАМЕНАТЕЛЬ ОБЪЯВЛЕН ТОЙ ЖЕ РУКОЙ, НЕ УМЕЕТ СКАЗАТЬ О
ПРОПУСКЕ. Полнота свода говорит «0 непокрытых из 62» — и это значит
ровно «62 из 62», ибо свод предметов написан здесь же. Свод не назовёт
предмета, которого в своде нет: он не лжёт, он слеп по устройству.

ЗНАМЕНАТЕЛЬ БЕРЁТСЯ ИЗВНЕ. Прозаические корпуса — MSFS, УГМ, Diakrisis,
математические основания, Verum — писаны НЕ ЗДЕСЬ и не для этой меры.
Их ОГЛАВЛЕНИЯ суть объявление предметов, сделанное чужой рукой: автор
корпуса назвал главу «Категорная семантика» потому, что считал предмет
нужным, а не потому, что его спросила мера.

ЗАГОЛОВОК ОПОЗНАЁТСЯ СТРОЕНИЕМ, А НЕ СЛОВАРЁМ: строка, окружённая
пустотой с обеих сторон, начатая заглавной и не несущая точки. Признак
структурный, и потому не зависит от языка — он одинаково берёт
«Reestr dopuscheniy» и «Assumption Register». Тринадцать тысяч
заголовков в семи корпусах.

ПОИСК ИДЁТ ПОДСТРОКОЙ, И ЭТО ОБЪЯВЛЯЕТСЯ ПРЯМО. Морфологии у меры нет:
«панпсихизм» в оглавлении и «панпсихизма» в показе — одно понятие, и
сверять их точным равенством значило бы объявить пробелом падеж. Поиск
префиксом ЗАВЫШАЕТ покрытие: понятие, случайно оказавшееся началом
другого слова, зачтётся показанным.

И ИМЕННО ПОЭТОМУ МЕРА ГОДИТСЯ. МЕРА, ЗАВЫШАЮЩАЯ ПОКРЫТИЕ, НАЗЫВАЕТ
ТОЛЬКО ВЕРНЫЕ ПРОБЕЛЫ: понятие, не найденное даже подстрокой, не
показано ТОЧНО. Числу покрытия здесь верить нельзя, числу пробелов —
можно, и мера объявляет, какое из двух своих чисел чего стоит.

РУБРИКА ОТЛИЧАЕТСЯ ОТ ПРЕДМЕТА ПОВТОРОМ, А НЕ СЛОВАРЁМ. Первый замер
назвал пробелами «chapter», «references», «обзор», «related» — это не
предметы, а служебные рубрики документа. Отсеять их списком значило бы
завести список, стареющий рукой; отсеять частотой в общем языке —
завести второй корпус ради одного признака.

Признак нашёлся там же, где и заголовок, — В СТРОЕНИИ. Служебная
рубрика есть ОДИН И ТОТ ЖЕ заголовок, повторённый в каждой главе:
«обзор» встречается 63 раза, но РАЗНЫХ заголовков с ним всего 10.
Предмет живёт в РАЗНЫХ заголовках: «теорема» — 202 вхождения и 193
разных заголовка, «consciousness» — 60 и 58.

ГРАНИЦА НЕ ВЫБРАНА, А ВЫВЕДЕНА: понятие есть предмет, если разных
заголовков БОЛЬШЕ ПОЛОВИНЫ вхождений, то есть если слово чаще приходит
из НОВОГО заголовка, чем из повтора старого. Половина — единственная
граница, не требующая выбора: она отделяет «чаще ново» от «чаще
повтор», и всякая другая была бы вкусом.

ЗАКОН: РУБРИКА ПОВТОРЯЕТСЯ ДОСЛОВНО, ПРЕДМЕТ ПОВТОРЯЕТСЯ ПО-РАЗНОМУ.
"""
import bisect
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest

# РУБЕЖ-ДОЛГА: НЕПОКАЗАННЫХ_РУБЕЖ = 6556
#
# ЧИСЛО ПЕРВОГО ЗАМЕРА, и оно тяжёлое: из 7668 предметов, названных
# оглавлениями семи прозаических корпусов, показы показывают 682 —
# восемь процентов. «Теорема» названа 202 раза по-русски и 205 раз
# по-английски и не показана НИ ОДНИМ показом; то же с «определением»,
# «доказательством» по-английски, «сознанием», «иерархией».
#
# ЧИСЛО ОБЪЯВЛЕНО ПОСЛЕ ЗАМЕРА, А НЕ ДО: долг, названный до замера,
# есть догадка. Расти ему нельзя, убывать можно, и всякий новый мир
# показов опускает его ровно на те предметы, которые внёс в дело.
#
# ПЕРВАЯ УПЛАТА В ТОТ ЖЕ ДЕНЬ. Два мира метаязыка — metalang (теорема с
# условием и заключением, определение с границей, лемма, следствие,
# гипотеза, контрпример) и relation (вложенность, транзитивность,
# классы эквивалентности, порядок, путь) — внесли в дело 91 предмет:
# 6986 → 6895, показано 682 → 773. Слово «теорема» имело в своде НОЛЬ
# вхождений на 184 393 строки; ныне их 218, «доказательство» — 195,
# «theorem» — 218, «transitive» — 110. Долг опущен до достигнутого В
# ТОТ ЖЕ ЧАС, как и велит закон о долге.
#
# ДОЛЯ МИРА СТРОЕНИЯ В ЭТОЙ УПЛАТЕ ЗАМЕРЕНА ОТДЕЛЬНО — ИЗОЛЯЦИЕЙ, а не
# разностью общих чисел: тем же прибором по манифесту БЕЗ этого мира
# (6944 против 6899 в тот час). `datasets/genesis_relation.txt` закрыл
# 45 предметов, и все они об ОТНОШЕНИЯХ МЕЖДУ ВЕЩАМИ, а не о самих
# вещах: «связь» (169 упоминаний), «структура» (115),
# «connection» (69), «hierarchy» (47), «иерархия» (45), «levels» (38),
# «relation» (28), «closure» (28), «соответствие» (24), «уровень» (23),
# «эквивалентность» (19), «пространство» (19), «correspondence» (15),
# «equivalence» (14), «замыкание» (10). Изоляция нужна оттого, что в
# один час корпус растили несколько рук, и разность двух общих чисел
# приписала бы одному то, что сделали все.
#
# ДОЛЯ МИРА МЕТАЯЗЫКА ЗАМЕРЕНА ТОЙ ЖЕ ИЗОЛЯЦИЕЙ: 103 предмета (7248
# непоказанных без него против 7145 с ним), и 79 из них суть слова
# метаязыка — «theorem», «proof», «lemma», «corollary», «hypothesis»,
# «counterexample», «axiom», «теорема», «определение», «доказательство»
# со своими падежами. Слово «теорема» имело в своде НОЛЬ вхождений на
# 186 421 строку; ныне их 365, «доказательство» — 249, «theorem» — 385.
#
# ЗНАМЕНАТЕЛЬ ЭТОЙ МЕРЫ РАСТЁТ ЧУЖОЙ РУКОЙ, И РУБЕЖ ЭТОГО НЕ ЗНАЕТ.
# Замер 6838 взят при 7668 предметах из СЕМИ корпусов прозы. В тот же
# день манифест объявил ещё двенадцать прозаических сводов, предметов
# стало 8009, и непоказанных — 7143 БЕЗ единой правки показов. Рубеж не
# поднят нарочно: поднятый рубеж скрыл бы долг, а долг тут настоящий —
# новые корпуса вправду называют то, чего показы не показывают.
# Сравнимое между замерами число есть ВКЛАД МИРА при ОДНОМ знаменателе,
# и объявить новый рубеж вправе тот, кто ввёл новый знаменатель.
НЕПОКАЗАННЫХ_РУБЕЖ = 6556

# Понятие короче этого не берётся: трёхбуквенные обрывки суть предлоги
# и союзы всех семи языков разом, и подстрочный поиск зачтёт их все.
# Порог выведен, а не выбран: при длине 4 в знаменатель входят «этот»,
# «that», «есть»; при 5 — уходят, а первое настоящее понятие («число»,
# «axiom») остаётся. Меньшая из длин, при которой знаменатель чист.
ДЛИНА = 5

# Заголовок: начат заглавной, не несёт конечного знака, короток.
ЗАГОЛОВОК = re.compile(r"^[А-ЯЁA-Z][^.!?:;]{3,70}$")
СЛОВО = re.compile(r"[^\W\d_]{%d,}" % ДЛИНА, re.UNICODE)


def манифест(путь):
    if not путь.exists():
        return None
    return json.loads(путь.read_text(encoding="utf-8"))


def _файл(мир, корень, внешний):
    п = корень / мир["file"]
    if п.exists():
        return п
    if внешний:
        п = (корень / внешний / мир["file"]).resolve()
        if п.exists():
            return п
    return None


def заголовки(путь):
    """Строки, ОКРУЖЁННЫЕ ПУСТОТОЙ, — оглавление корпуса."""
    строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
    for i, с in enumerate(строки):
        т = с.strip()
        if not т or not ЗАГОЛОВОК.match(т):
            continue
        до = строки[i - 1].strip() if i else ""
        после = строки[i + 1].strip() if i + 1 < len(строки) else ""
        if до or после:
            continue
        yield т


def слова_показов(миры, корень, внешний):
    """Все слова всех миров ПОКАЗОВ, отсортированные для поиска."""
    вон = set()
    for мир in миры:
        if мир.get("text") != "shows":
            continue
        п = _файл(мир, корень, внешний)
        if п is None:
            continue
        for с in п.read_text(encoding="utf-8", errors="replace").splitlines():
            вон.update(м.group().lower() for м in СЛОВО.finditer(с))
    return sorted(вон)


def показано(понятие, ряд):
    """Есть ли в показах слово, НАЧИНАЮЩЕЕСЯ этим понятием."""
    где = bisect.bisect_left(ряд, понятие)
    return где < len(ряд) and ряд[где].startswith(понятие)


def main():
    путь = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    if "--manifest" in sys.argv:
        путь = pathlib.Path(sys.argv[sys.argv.index("--manifest") + 1])
    м = манифест(путь)
    if not м:
        print(f"ОХВАТ ПОНЯТИЯ ОТКАЗ: манифеста «{путь}» нет")
        return 2
    внешний = м.get("external_root")
    миры = м["worlds"]

    названо = collections.Counter()
    заголовков_с = collections.defaultdict(set)
    # ДВА ЗНАМЕНАТЕЛЯ, И ОБА ПЕЧАТАЮТСЯ: НАШИ СВОДЫ И ПОЛКА. Полка
    # (Евклид, Буль, Пуанкаре, Милль) внесла в оглавления 690 новых
    # предметов строгих наук, и долг «не показано» вырос 6895 → 7435
    # — не оттого, что корпус обеднел, а оттого, что знаменатель стал
    # честнее. Считать это ростом долга значило бы наказывать за
    # чтение (ср. меру библиотеки); считать одним числом — прятать, что
    # классики называют то, чего наши своды не называли. Признак тот
    # же, что у библиотеки: у мира полки объявлен «источник».
    с_полки = set()
    корпусов = 0
    for мир in миры:
        if мир.get("text") != "prose":
            continue
        п = _файл(мир, КОРЕНЬ, внешний)
        if п is None:
            continue
        корпусов += 1
        полка = bool(мир.get("источник"))
        for заг in заголовки(п):
            for м_ in СЛОВО.finditer(заг):
                слово = м_.group().lower()
                названо[слово] += 1
                заголовков_с[слово].add(заг)
                if полка:
                    с_полки.add(слово)
    if not названо:
        print("ОХВАТ ПОНЯТИЯ ОТКАЗ: прозаических корпусов не найдено")
        return 2
    рубрик = {п for п, n in названо.items()
              if len(заголовков_с[п]) * 2 <= n}
    предметы = {п: n for п, n in названо.items() if п not in рубрик}

    ряд = слова_показов(миры, КОРЕНЬ, внешний)
    if not ряд:
        print("ОХВАТ ПОНЯТИЯ ОТКАЗ: миров показов не найдено")
        return 2

    пробелы = [(п, n) for п, n in предметы.items() if not показано(п, ряд)]
    пробелы.sort(key=lambda х: (-х[1], х[0]))
    показанных = len(предметы) - len(пробелы)
    доля = 100 * показанных // len(предметы)
    # предметы, названные ТОЛЬКО полкой (наши своды их не называют)
    только_полка = {п for п in предметы if п in с_полки
                    and заголовков_с[п] <= {з for з in заголовков_с[п]}}
    свои_пробелы = [(п, n) for п, n in пробелы if п not in с_полки]
    полки_пробелы = [(п, n) for п, n in пробелы if п in с_полки]

    for понятие, n in пробелы[:25]:
        print(f"  НЕ ПОКАЗАНО «{понятие}» — названо в оглавлениях {n} раз")
    if len(пробелы) > 25:
        print(f"  … и ещё {len(пробелы) - 25} понятий")
    # рубеж судит долг НАШИХ сводов; полка печатается рядом отдельным числом
    поза = ("ОТЧЁТ" if НЕПОКАЗАННЫХ_РУБЕЖ is None else
            "PASS" if len(свои_пробелы) <= НЕПОКАЗАННЫХ_РУБЕЖ else "FAIL")
    print(f"ОХВАТ ПОНЯТИЯ {поза}: {показанных} из {len(предметы)} предметов "
          f"показаны ({доля}%); не показано из НАШИХ сводов "
          f"{len(свои_пробелы)} (рубеж {НЕПОКАЗАННЫХ_РУБЕЖ}), из полки "
          f"{len(полки_пробелы)} — {корпусов} корпусов прозы, отсеяно "
          f"рубрик {len(рубрик)}, слов в показах {len(ряд)}")
    if НЕПОКАЗАННЫХ_РУБЕЖ is None:
        return 0
    return 0 if len(свои_пробелы) <= НЕПОКАЗАННЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
