#!/usr/bin/env python3
"""[КЛЮЧ БЕЗ ОПОРЫ] — вопрос удержанного ключа, чей РОД свод почти не пишет.

    КЛЮЧ, СПРАШИВАЮЩИЙ О РОДЕ, КОТОРОГО В СВОДЕ НЕТ, МЕРИТ НЕ ЧИТАТЕЛЯ, А СВОД.

Удержанный ключ строится ИЗ свода и проверяется на то, что ни один его вопрос не прожит
(`scripts/holdout_key.py`, «прожитых 0»). Это верное требование, и оно не полное: вопрос может
быть не прожит И ПРИ ТОМ принадлежать роду, которого в своде четыре страницы или ноль. Тогда
отказ читателя есть свидетельство о своде, а не о читателе, и всякая мера, построенная на
таком вопросе, меряет собственную дыру.

ЧИСЛО, КУПИВШЕЕ ПРИБОР (07.09, вечер). holon прислал таблицу «на каких родах ядро отвечает»:
181 ответ, 0 лжей, 979 ОТКАЗОВ из 1160. Сличение её со сводом по массе рода дало:

    средняя масса рода в своде: у отвечающих 343, у молчащих 110
    медиана:                    у отвечающих  60, у молчащих  45

Связь есть, но слабая — и на дне списка молчащих нашлось то, ради чего прибор написан:
условные вопросы («if more», «wenn mehr», «si elle», «als hij») при массе рода ОТ НУЛЯ ДО
ЧЕТЫРЁХ. Ключ спрашивает о том, чего свод не показывал.

    ОТКАЗ ЧИТАТЕЛЯ НА РОДЕ, КОТОРОГО В СВОДЕ НЕТ, ЕСТЬ ЕДИНСТВЕННО ЧЕСТНЫЙ ЕГО ОТВЕТ.

РОД БЕРЁТСЯ ПО ЗАЧИНУ ВОПРОСНОГО ПРЕДЛОЖЕНИЯ — два первых слова последнего предложения,
кончающегося вопросительным знаком. Это грубо и сказано, что грубо: род тем самым шире
настоящего (все «сколько шаров» суть один род, каков бы ни был дом). Мера от этого ЗАНИЖАЕТ
долг — широкий род набирает массу легче узкого, — и потому её число есть ПОЛ, а не потолок.

    python3 scripts/key_support.py [--ключ ФАЙЛ] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --ключ no-such-key
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import frgram  # noqa: E402 — разворот стяжения объявлен домом языка

# РУБЕЖ-ДОЛГА: БЕЗ_ОПОРЫ_РУБЕЖ = 0
#
# РУБЕЖ ОБЪЯВЛЕН ПО ДОСТИГНУТОМУ: 24 при постановке, 14 после того, как местоимение носителя
# сведено в «@» наравне с именем. Условные роды («if he» 3, «если он» 4, «wenn sie» 4) ушли из
# списка не работой, а ПОЧИНКОЙ МЕРЫ: сличено по своду — условная форма живёт восемью
# страницами с местоимением и 238 с именем в каждом языке.
#
# Осталось 14 родов, держащих 23 вопроса (0.6 % от 3620), и цена их снижения — по восемь
# страниц каждому:
#
#     шкала    — «градуса по» 2, «stopnie fahrenheita» 2
#     место    — «где книги» 3, «где яблока» 3
#     счёт     — «quantos são» 1, «quantos tem» 2, «cuántos tiene» 4, «cuántos son» 5
#
# Опора считается по LAW³ = 8: столько же страниц требует от рода всякий дом этого свода.
# 6 → 4 (12.09): ДВА РОДА УПЛАЧЕНЫ ПОКАЗАМИ. Русское «N градуса по» и польское «N stopnie
# Fahrenheita» держали вопросы ключа при массе два: оба возникают, когда фаренгейт кончается
# на 2, 3 или 4, — а прежних десяти цельсиев такими были лишь два. Дом температурной шкалы
# получил шесть новых цельсиев (−30, −20, 0, 50, 90, 95), масса обоих родов 2 → 8.
#
#     РОД, ВОЗНИКАЮЩИЙ ЛИШЬ ПРИ НЕКОТОРЫХ ЧИСЛАХ ТАБЛИЦЫ, ЖИВЁТ РОВНО СТОЛЬКО РАЗ,
#     СКОЛЬКО ТАКИХ ЧИСЕЛ В НЕЙ, — И ЧИСЛА ЭТИ ОТБИРАЮТСЯ, А НЕ ВЫПАДАЮТ.
#
# 4 → 0 (12.09, вечер): ОСТАТОК УПЛАЧЕН ПОКАЗОМ, И ОБЕ ЕГО ПОЛОВИНЫ ОКАЗАЛИСЬ ОДНОЙ БОЛЕЗНЬЮ.
# «где книги» 5 → 10 и «где яблока» 4 → 10: дом держания раздавал вещи числам ДИАГОНАЛЬЮ, а
# форма счёта есть свойство ЧИСЛА, и диагонали она не подвластна; ряд пошёл парой «вещь и её
# написание». «quantos tem» 2 → 8 и «cuántos tiene» 4 → 8: вопросное слово согласуется с родом
# вещи, а вещь доставалась числу ОДНИМ указателем — и слово жило столько раз, сколько вещей
# его рода в таблице (португальских мужских две из восьми). Число теперь показывается и вещью
# другого рода — та же двусторонность, что в `declarations/BOTH-SIDES.md`.
#
#     ОПОРА ПРИЧИТАЕТСЯ КАЖДОЙ ФОРМЕ, А НЕ ИХ СУММЕ (`declarations/EACH-FORM.md`).
#
# КЛЮЧ НАСЛЕДУЕТ ЛОЖЬ СВОДА, И ЭТА МЕРА ЕЁ ВИДИТ. По дороге к нулю прибор показал два рода
# массою НОЛЬ — «quanti voci» (8 вопросов ключа) и «quantos mensagens» (1): ключ нарезан из
# свода ДО того, как в семи домах нашлось несогласование рода, и держал вопросы в форме,
# которой свод больше не пишет, ибо она ЛОЖНА. Пересборка ключа из исправленного свода увела
# оба рода; мера же осталась и есть единственный страж этого — прожитость ключа тут молчит.
#
#     ВОПРОС, ЗАДАННЫЙ В ФОРМЕ, КОТОРОЙ СВОД БОЛЬШЕ НЕ ПИШЕТ, МЕРИТ НЕ ЧИТАТЕЛЯ, А ВОЗРАСТ
#     КЛЮЧА.
БЕЗ_ОПОРЫ_РУБЕЖ = 0
LAW3 = 8

ВОПРОС = re.compile(r"([^.?!]*\?)")
# СЛОВО СО СТЯЖЕНИЕМ ЕСТЬ ОДНО СЛОВО (12.09). Французская элизия, введённая утром, сделала
# из «si il en donne» — «s'il en donne», и признак, не знающий апострофа, прочёл ЗАЧИН как
# «s @»: осколок слова да местоимение, принятое за имя. Род распался, и новый обломок
# оказался ниже закона копии в кубе — прибор объявил долг, которого нет.
#
#     РОД, РАЗРЕЗАННЫЙ ПО ЖИВОМУ СЛОВУ, ЕСТЬ НЕ РОД, А СЛЕД ПРИЗНАКА. Долг, им объявленный,
#     есть долг прибора перед языком, а не свода перед читателем.
#
# Признак берётся тот же, что у самоспроса (`sweep_self.СЛОВО`): стяжение читается целиком.
СЛОВО = re.compile(r"[^\W\d_]+(?:['’][^\W\d_]+)?")


def _имена():
    """Объявленные имена лиц и МЕСТОИМЕНИЯ НОСИТЕЛЯ — оба суть заполнители одной дыры.

    МЕСТОИМЕНИЕ, КАК И ИМЯ, НЕ ЕСТЬ ЧАСТЬ РОДА. Первая редакция сводила в «@» только имена, и
    условный род распался натрое: «if he» 3 страницы, «if she» 5, «if @» 238 — и первые два
    были названы стоящими ниже пола кворума. Сличено по своду: условная форма живёт восемью
    страницами с местоимением и двумястами тридцатью восемью с именем в КАЖДОМ языке, то есть
    показана богато.

        РОД, РАЗРЕЗАННЫЙ ПО ЗАПОЛНИТЕЛЮ ДЫРЫ, СЧИТАЕТСЯ ВТРОЕ И КАЖДЫЙ РАЗ ЗОВЁТСЯ БЕДНЫМ.
        Это тот же изъян, что и счёт СЕТЕЙ наравне со страницами в мере ширины: мера считает
        не то, что показано, а то, чем оно записано.
    """
    try:
        sys.path.insert(0, str(КОРЕНЬ / "tools"))

        import svampforms as S                      # noqa: PLC0415
    except Exception:                               # noqa: BLE001
        return frozenset()
    вон = set()
    for язык, ряд in S.A.ЛИЦА.items():
        for лицо in ряд:
            for ф in лицо:
                if isinstance(ф, str) and len(ф) > 1 and not ф.islower():
                    вон.add(ф.lower())
                elif isinstance(ф, str) and len(ф) > 2 and ф not in ("m", "f"):
                    вон.add(ф.lower())
    for _язык, роды in S.МЕСТОИМЕНИЯ.items():
        for г in роды.values():
            вон.update(str(ф).lower() for ф in г.values() if str(ф).strip())
    return frozenset(вон)


ИМЕНА = _имена()


def зачин(вопрос):
    """Два первых слова последнего вопросного предложения — грубый род.

    ИМЯ ЛИЦА НЕ ЕСТЬ ЧАСТЬ РОДА, И ЭТО КУПЛЕНО ОШИБКОЙ. Первая проба резала род по двум
    словам как есть, и «combien paul» с «combien hugo» стали ДВУМЯ родами по одной странице
    каждый — то есть прибор насчитал долг там, где стои́т один род о шестидесяти трёх
    вопросах. Объявленные имена заменяются на «@», и роды сходятся.
    """
    куски = ВОПРОС.findall(вопрос)
    если = куски[-1] if куски else вопрос
    # СТЯЖЕНИЕ РАЗВОДИТСЯ ДО СЧЁТА СЛОВ: «s'il» ЕСТЬ «si il», и род у них один. Закон
    # разворота живёт в доме языка (`frgram.развернуть`), а не переписан здесь.
    если = frgram.развернуть(если)
    слова = ["@" if w.lower() in ИМЕНА else w.lower() for w in СЛОВО.findall(если)]
    return " ".join(слова[:2]) if len(слова) >= 2 else (слова[0] if слова else "")


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что РОД РЕЖЕТСЯ И МАССА СЧИТАЕТСЯ.

        ЭТОТ ПРИБОР СЧИТАЕТ ЛИШЬ ТЕ РОДЫ, КОТОРЫЕ САМ И НАРЕЗАЛ. Пусть зачин перестанет
        резаться — и всякий вопрос уйдёт в один пустой род, который мера отбрасывает; прибор
        скажет «родов ниже закона 0», сверив НОЛЬ РОДОВ. Пусть счёт массы разойдётся с
        резкой — и род, живущий в своде сотней страниц, объявится бедным.

        ДОЛГ ЭТОТ ЗАВЕДЁН УПЛАТОЙ ДРУГОГО (12.09, вечер): рубеж прибора ушёл к нулю, и закон
        пробы (`declarations/PROBE.md`) тем же движением лёг на него. Нуль зрячего обязан
        отличаться от нуля слепого.

    Четыре случая резки и один счёт массы на выдуманном своде — всё заведомо известно.
    """
    беды = []
    случаи = (
        ("сколько книг у Ани?", "сколько книг"),
        ("у Ани 3 книги. сколько книг у неё?", "сколько книг"),
        ("s'il en donne 13, combien reste-t-il ?", "si il"),
        ("¿cuántas manzanas hay?", "cuántas manzanas"),
    )
    for вопрос, ждём in случаи:
        дало = зачин(вопрос)
        if дало != ждём:
            беды.append(f"зачин «{вопрос}» дал «{дало}», а не «{ждём}»")
    # СЧЁТ МАССЫ НА ВЫДУМАННОМ СВОДЕ: род «сколько книг» живёт двумя страницами, род
    # «сколько яблок» — ни одной; оба ниже закона, и оба обязаны быть названы.
    свод = ("у Ани 3 книги. сколько книг у неё? 3 книги.",
            "у Веры 5 книг. сколько книг у неё? 5 книг.",
            "у Ани 3 яблока. это факт.")
    масса = collections.Counter()
    for с in свод:
        if "?" in с:
            з = зачин(с)
            if з:
                масса[з] += 1
    if масса.get("сколько книг") != 2:
        беды.append(f"масса «сколько книг» сочтена {масса.get('сколько книг')}, а не 2")
    if масса.get("сколько яблок"):
        беды.append("масса найдена там, где вопроса нет вовсе")
    if not ИМЕНА:
        беды.append("имена лиц не прочтены — род распадётся по именам, и долг будет ложным")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"КЛЮЧ БЕЗ ОПОРЫ ОТКАЗ: резка рода не доказана ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--ключ", default=None)
    ап.add_argument("--свод", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    ключ = pathlib.Path(дов.ключ) if дов.ключ else КОРЕНЬ / "datasets" / "HOLDOUT-KEY-NEXT.tsv"
    свод = pathlib.Path(дов.свод) if дов.свод else КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
    if not ключ.is_file() or not свод.is_file():
        нет = ключ if not ключ.is_file() else свод
        print(f"КЛЮЧ БЕЗ ОПОРЫ ОТКАЗ: нет «{нет}»")
        return 2
    вопросы = []
    for стр in ключ.read_text(encoding="utf-8", errors="replace").split("\n"):
        ч = стр.split("\t")
        if len(ч) >= 2 and ч[1].strip():
            вопросы.append(ч[1].strip())
    if not вопросы:
        print(f"КЛЮЧ БЕЗ ОПОРЫ ОТКАЗ: в «{ключ.name}» вопросов нет")
        return 2
    роды = collections.Counter(зачин(в) for в in вопросы)
    роды.pop("", None)
    # ОДИН ПРОХОД ПО СВОДУ, А НЕ ОДИН НА РОД. Первая проба искала каждый род отдельным
    # поиском по тремстам восьмидесяти тысячам строк: двести родов дали бы семьдесят шесть
    # миллионов поисков и четверть часа хода. Свод режется в роды ОДНАЖДЫ — тем же правилом,
    # каким режется ключ, — и вопрос к нему становится вопросом о числе.
    масса = collections.Counter()
    for с in свод.read_text(encoding="utf-8", errors="replace").lower().split("\n"):
        if "?" not in с:
            continue
        з = зачин(с)
        if з:
            масса[з] += 1
    без_опоры = sorted(((масса[р], n, р) for р, n in роды.items() if масса[р] < LAW3),
                       key=lambda x: (x[0], -x[1]))
    вопросов_без_опоры = sum(n for _м, n, _р in без_опоры)
    print(f"{'масса':>6}{'вопросов ключа':>16}  род")
    for м, n, р in (без_опоры if дов.подробно else без_опоры[:12]):
        print(f"{м:>6}{n:>16}  {р}")
    поза = "PASS" if len(без_опоры) <= БЕЗ_ОПОРЫ_РУБЕЖ else "FAIL"
    print(f"КЛЮЧ БЕЗ ОПОРЫ {поза}: вопросов {len(вопросы)}, родов {len(роды)}; "
          f"РОДОВ НИЖЕ LAW³={LAW3} страниц — {len(без_опоры)} (рубеж {БЕЗ_ОПОРЫ_РУБЕЖ}), "
          f"и они держат {вопросов_без_опоры} вопросов ключа "
          f"({100 * вопросов_без_опоры / len(вопросы):.1f} %)")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
