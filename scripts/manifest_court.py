#!/usr/bin/env python3
"""СУД МАНИФЕСТА: объявление о мире обязано сойтись с миром.

Манифест есть договор корпуса о себе: какие миры в нём, где они лежат,
какого рода их текст, в какие сборки входят и какого они размера. Всё
это ЧИТАЮТ другие — приборы мер, кузница пробелов, соседние сессии,
варящие канон, — и потому всякая строка манифеста есть обещание,
данное третьему.

ОБЕЩАНИЕ, КОТОРОГО НИКТО НЕ СВЕРЯЕТ, НЕОТЛИЧИМО ОТ ФАКТА, ПОКА НЕ
СПРОСЯТ. Поле `size` стояло у сборок нулём и старым числом; сосед,
варивший канон по манифесту, взял объявленный размер и потерял хвост
корпуса. Вина не его: он поверил договору. Здесь договор проверяется.

ЧТО СВЕРЯЕТСЯ:
    ФАЙЛ СУЩЕСТВУЕТ — мир, чьего файла нет, есть обещание, а не мир;
    РАЗМЕР И СТРОКИ — где объявлены, там обязаны сойтись с файлом;
    РОД ТЕКСТА — объявлен из известных («shows», «prose», «mix»);
    СБОРКИ — имя сборки, объявленное миром, обязано принадлежать
        существующей сборке, иначе мир входит в никуда;
    ИМЯ ЕДИНСТВЕННО — два мира с одним именем суть тихая потеря;
    АКТ, ОРАКУЛ, ГРАНИЦА — объявлены и объявлены ИЗ НАБОРА
        (`tools/manifest_kinds.py`): поля нет — ложь, значение вне
        набора — ложь, «не названо» вперемешку со знанием — ложь.

СВЕРКА СО СПИСКОМ ЕСТЬ ПОЛОВИНА СУДА. Значение из набора доказывает
лишь то, что писавший знал набор; проверяемым объявление делает связь
С ДЕЛОМ — с телом мира, которое лгать не умеет. Потому здесь три
закона дела, и каждый ОБЯЗЫВАЕТ объявившего:

    ОТКАЗ ОБЪЯВЛЕН — ОТКАЗ ПОКАЗАН. Мир, чей акт несёт `refuse`,
        обязан иметь строки отказа, и суд обязан их найти;
    ТОЧНОЕ ИЛИ ЦЕЛОЕ — БЕЗ ДРОБНОЙ ЗАПИСИ. Мир, объявивший границу
        «только целые» или «только точные», не смеет нести число,
        записанное дробью: неточный итог пишется в корпусе ровно ею;
    ЯРУС ОБЪЯВЛЯЕТ ПАКЕТ, А НЕ ПРОЗА. Мир, объявивший границу
        «строение зелено, язык не проверен», обязан иметь пакет,
        объявляющий ярус первый.

ОБЯЗЫВАЕТ ОБЪЯВЛЕНИЕ, А НЕ МОЛЧАНИЕ: мир, не объявивший отказа, здесь
не обвиняется, даже если строки отказа в нём есть. Признак отказа
неточен по природе (метка `¬` живёт в мире логики связкой), и
обвинение по неточному признаку дороже пропуска.
"""

import collections
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402
import manifest_kinds  # noqa: E402

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 0
РАЗЛАДОВ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest

РОДЫ_ТЕКСТА = {"shows", "prose", "mix"}

# ГРАНИЦЫ, ЧЬЁ ДЕЛО ВИДНО ЗАПИСЬЮ ЧИСЛА. Обе говорят об итоге, который
# мир согласился произносить, и обе нарушаются одним и тем же: дробью.
ТОЧНЫЕ_ГРАНИЦЫ = {"whole_only", "exact_only"}


def объявленное(мир, имя, разлады):
    """АКТ, ОРАКУЛ, ГРАНИЦА — есть, из набора, и незнание стоит одно."""
    for поле, набор in manifest_kinds.ПОЛЯ:
        значения = мир.get(поле)
        if not isinstance(значения, list) or not значения:
            разлады.append(f"{имя}: поле «{поле}» не объявлено")
            continue
        for значение in значения:
            if значение not in набор:
                разлады.append(
                    f"{имя}: {поле} «{значение}» вне объявленного набора")
        if manifest_kinds.НЕ_НАЗВАНО in значения and len(значения) > 1:
            разлады.append(
                f"{имя}: {поле} держит «{manifest_kinds.НЕ_НАЗВАНО}» "
                f"вместе со знанием — незнание стоит одно")


def дело(мир, имя, тело, разлады):
    """Три закона дела. Возвращает, сколько обязательств проверено."""
    акт = set(мир.get("act") or ())
    границы = set(мир.get("boundary") or ())
    проверено = 0
    # ТЕЛО ЧИТАЕТСЯ ЛИШЬ ТОМУ, КТО ОБЪЯВИЛ. Развернуть все своды корпуса
    # ради двух законов значило бы платить двадцатью мегабайтами за
    # шестьдесят обязательств.
    текст = (тело.decode("utf-8", "replace")
             if "refuse" in акт or границы & ТОЧНЫЕ_ГРАНИЦЫ else "")
    if "refuse" in акт:
        проверено += 1
        if not manifest_kinds.отказов(текст):
            разлады.append(
                f"{имя}: акт объявляет отказ, а строк отказа в файле нет")
    if границы & ТОЧНЫЕ_ГРАНИЦЫ:
        проверено += 1
        дробью = manifest_kinds.дробных(текст)
        if дробью:
            разлады.append(
                f"{имя}: граница «{sorted(границы & ТОЧНЫЕ_ГРАНИЦЫ)[0]}», "
                f"а строк с дробной записью числа {дробью}")
    if "tier1_unverified" in границы:
        проверено += 1
        ярус = manifest_kinds.ярус_пакета(имя)
        if ярус != 1:
            разлады.append(
                f"{имя}: граница объявляет ярус первый, а пакет языка "
                f"объявляет «{ярус}»")
    return проверено


def main():
    if "--manifest" in sys.argv:
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        м = genesis.manifest()
    except genesis.Unreadable as беда:
        print(f"МАНИФЕСТ ОТКАЗ: {беда}")
        return 2
    миры = м.get("worlds") or []
    if not миры:
        print("МАНИФЕСТ ОТКАЗ: миров не объявлено, сверять нечего")
        return 2
    разлады = []
    имена = collections.Counter(мир.get("name") for мир in миры)
    for имя, сколько in имена.items():
        if сколько > 1:
            разлады.append(f"имя «{имя}» объявлено {сколько} раза")
    сборки = {имя for мир in миры if мир.get("text") == "mix"
              for имя in (мир.get("name"),)}
    дел = 0
    for мир in миры:
        имя = мир.get("name", "?")
        род = мир.get("text")
        if род not in РОДЫ_ТЕКСТА:
            разлады.append(f"{имя}: род текста «{род}» не объявлен")
        объявленное(мир, имя, разлады)
        путь = genesis._resolve(мир.get("file", ""))
        if not путь.is_file():
            разлады.append(f"{имя}: файла нет — {мир.get('file')}")
            continue
        тело = путь.read_bytes()
        if "size" in мир and мир["size"] and род == "mix":
            if мир["size"] != len(тело):
                разлады.append(
                    f"{имя}: size {мир['size']} против "
                    f"{len(тело)} в файле")
        if "lines" in мир:
            строк = sum(1 for с in тело.decode("utf-8", "replace")
                        .splitlines() if с.strip())
            if мир["lines"] != строк:
                разлады.append(
                    f"{имя}: lines {мир['lines']} против {строк}")
        for сборка in (мир.get("assemblies") or ()):
            if сборка not in сборки:
                разлады.append(
                    f"{имя}: сборка «{сборка}» не объявлена миром")
        дел += дело(мир, имя, тело, разлады)
    for р in разлады[:6]:
        print(f"  {р}")
    поза = "PASS" if len(разлады) <= РАЗЛАДОВ_РУБЕЖ else "FAIL"
    print(f"МАНИФЕСТ {поза}: {len(разлады)} разладов объявления с "
          f"делом ({len(миры)} миров, сборок {len(сборки)}, "
          f"обязательств дела {дел})")
    return 0 if len(разлады) <= РАЗЛАДОВ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
