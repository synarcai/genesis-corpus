#!/usr/bin/env python3
"""СУД МАНИФЕСТА: объявление о мире обязано сойтись с миром.

Манифест есть договор корпуса о себе: какие миры в нём, где они лежат,
какого рода их текст, в какие сборки входят и какого они размера. Всё
это ЧИТАЮТ другие — приборы мер, кузница пробелов, соседние сессии,
варящие канон, — и потому всякая строка манифеста есть обещание,
данное третьему.

ОБЕЩАНИЕ, КОТОРОГО НИКТО НЕ СВЕРЯЕТ, НЕОТЛИЧИМО ОТ ФАКТА, ПОКА НЕ
СПРОСЯТ. Поле `size` стояло у сборок нулём и старым числом; сосед,
варивший канон по манифесту, взял объявленный размер и потерял хвост
корпуса. Вина не его: он поверил договору. Здесь договор проверяется.

ЧТО СВЕРЯЕТСЯ:
    ФАЙЛ СУЩЕСТВУЕТ — мир, чьего файла нет, есть обещание, а не мир;
    РАЗМЕР И СТРОКИ — где объявлены, там обязаны сойтись с файлом;
    РОД ТЕКСТА — объявлен из известных («shows», «prose», «mix»);
    СБОРКИ — имя сборки, объявленное миром, обязано принадлежать
        существующей сборке, иначе мир входит в никуда;
    ИМЯ ЕДИНСТВЕННО — два мира с одним именем суть тихая потеря.
"""

import collections
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 0
РАЗЛАДОВ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest

РОДЫ_ТЕКСТА = {"shows", "prose", "mix"}


def main():
    if "--manifest" in sys.argv:
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        м = genesis.manifest()
    except genesis.Unreadable as беда:
        print(f"МАНИФЕСТ ОТКАЗ: {беда}")
        return 2
    миры = м.get("worlds") or []
    if not миры:
        print("МАНИФЕСТ ОТКАЗ: миров не объявлено, сверять нечего")
        return 2
    разлады = []
    имена = collections.Counter(мир.get("name") for мир in миры)
    for имя, сколько in имена.items():
        if сколько > 1:
            разлады.append(f"имя «{имя}» объявлено {сколько} раза")
    сборки = {имя for мир in миры if мир.get("text") == "mix"
              for имя in (мир.get("name"),)}
    for мир in миры:
        имя = мир.get("name", "?")
        род = мир.get("text")
        if род not in РОДЫ_ТЕКСТА:
            разлады.append(f"{имя}: род текста «{род}» не объявлен")
        путь = genesis._resolve(мир.get("file", ""))
        if not путь.is_file():
            разлады.append(f"{имя}: файла нет — {мир.get('file')}")
            continue
        тело = путь.read_bytes()
        if "size" in мир and мир["size"] and род == "mix":
            if мир["size"] != len(тело):
                разлады.append(
                    f"{имя}: size {мир['size']} против "
                    f"{len(тело)} в файле")
        if "lines" in мир:
            строк = sum(1 for с in тело.decode("utf-8", "replace")
                        .splitlines() if с.strip())
            if мир["lines"] != строк:
                разлады.append(
                    f"{имя}: lines {мир['lines']} против {строк}")
        for сборка in (мир.get("assemblies") or ()):
            if сборка not in сборки:
                разлады.append(
                    f"{имя}: сборка «{сборка}» не объявлена миром")
    for р in разлады[:6]:
        print(f"  {р}")
    поза = "PASS" if len(разлады) <= РАЗЛАДОВ_РУБЕЖ else "FAIL"
    print(f"МАНИФЕСТ {поза}: {len(разлады)} разладов объявления с "
          f"делом ({len(миры)} миров, сборок {len(сборки)})")
    return 0 if len(разлады) <= РАЗЛАДОВ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
