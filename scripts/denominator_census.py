#!/usr/bin/env python3
"""[ЧИСЛО БЕЗ ЗНАМЕНАТЕЛЯ] — последняя строка каждого прибора: сказано ли, ИЗ СКОЛЬКИХ.

Закон holon (04.09): «причин 0» есть правда о списке и ложь о мире, пока не
сказано, из скольких. Пай аудита «меры и пороги», вторая ступень. Прибор читает
ЛЕДЖЕР приборов (reports/ledger.tsv — последняя строка каждого суда с датой и
кодом, пишется courts.sh) и спрашивает у каждой строки одно: назван ли объём,
по которому число получено.

ЗНАМЕНАТЕЛЬ УЗНАЁТСЯ ФОРМОЙ, И ФОРМ ОБЪЯВЛЕНО НЕСКОЛЬКО — не одна «из N».
Первая проба знала лишь «из» и назвала голыми тринадцать строк, из которых
десять несли объём иначе: «0 ложных, 2982 истинных, 0 несудимых» (объём есть
сумма частей), «0 разладов (316 миров, сборок 2)» (объём в скобках), «пали 3:
… в леджере 79». Шестая поправка прибора на себе за сутки: перепись, не
знающая форм предмета, зовёт формой своё незнание.

    python3 scripts/denominator_census.py
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ЛЕДЖЕР = КОРЕНЬ / "reports" / "ledger.tsv"

# формы знаменателя: «из N», «of N», рубеж, доля, «N истинных» рядом с «0 ложных»,
# объём в скобках после числа, «в леджере N», «при N», «всего N», «на N …»
ЗНАМЕНАТЕЛЬ = (
    re.compile(r"\bиз\s+\d"), re.compile(r"\bof\s+\d"), re.compile(r"рубеж"),
    re.compile(r"\d+\s*%"), re.compile(r"\d+\s+истинных"), re.compile(r"\(\s*\d+\s+\w+"),
    re.compile(r"в леджере\s+\d"), re.compile(r"\bпри\s+\d"), re.compile(r"\bвсего\s+\d"),
    re.compile(r"\bна\s+\d+\s+\w"), re.compile(r"\bсреди\s+\d"), re.compile(r"\d+\s+(?:строк|миров|слов|пар|проб|домов|родов|форм|книг|источников)\b"),
    # объём дробью «24/24», леджером «79 в леджере», именем перед числом «строк реестра 46»
    re.compile(r"\d+\s*/\s*\d+"), re.compile(r"\d+\s+в леджере"),
    re.compile(r"(?:строк|миров|имён|слов|проб)\s+\w*\s*\d+"),
    # объём, названный делом: «проверено: N», «сличено N», «перебрано N»
    re.compile(r"(?:проверено|сличено|перебрано|осмотрено|прочитано):?\s*\d"),
    # объём в скобках словом вперёд: «(объявлено 18, храповиков 6, ВКУС 1)»
    re.compile(r"\(\s*[^\W\d_]+\s+\d+"),
)
ЧИСЛО_ВЕРДИКТА = re.compile(r"\b(?:0|ни одного|ноль)\b")


def последние():
    вон = {}
    if not ЛЕДЖЕР.is_file():
        return вон
    for с in ЛЕДЖЕР.read_text(encoding="utf-8", errors="replace").splitlines():
        ч = с.split("\t")
        if len(ч) >= 4:
            вон[ч[1]] = ч[3]
    return вон


def main():
    строки = последние()
    if not строки:
        print("ЧИСЛО БЕЗ ЗНАМЕНАТЕЛЯ: леджера нет — нечего переписывать")
        return 0
    голые = []
    for имя, с in sorted(строки.items()):
        if any(з.search(с) for з in ЗНАМЕНАТЕЛЬ):
            continue
        голые.append((имя, с))
    for имя, с in голые:
        нуль = " — И ЭТО НОЛЬ" if ЧИСЛО_ВЕРДИКТА.search(с) else ""
        print(f"  БЕЗ ЗНАМЕНАТЕЛЯ {имя}{нуль}: {с[:110]}")
    нулей = sum(1 for _, с in голые if ЧИСЛО_ВЕРДИКТА.search(с))
    итог = "PASS" if нулей == 0 else "FAIL"
    print(f"ЧИСЛО БЕЗ ЗНАМЕНАТЕЛЯ {итог}: приборов в леджере {len(строки)}, строк без объёма "
          f"{len(голые)}, из них НУЛЕЙ без объёма {нулей} (рубеж 0)")
    return 1 if нулей else 0


if __name__ == "__main__":
    sys.exit(main())
