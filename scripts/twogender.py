#!/usr/bin/env python3
"""[ДВУРОДОЕ ИМЯ] — имя, стоящее и после мужского вопросного слова, и после женского.

    У ИМЕНИ ОДИН РОД. Слово, встреченное и после «quanti», и после «quante», выдаёт ЛОЖЬ одной
    из двух страниц — и какой именно, знает дом этого имени, а не мера.

Эта мера не спрашивает, сколько раз показана форма (о том — `scripts/agree_skew.py`), и не
ждёт, чтобы ложь была РЕДКОЙ. Она спрашивает одно: не сказал ли свод об одном имени двумя
родами. Одного совпадения довольно: порог тут не нужен, ибо два рода у имени невозможны.

ЧИСЛО, КУПИВШЕЕ ПРИБОР (12.09). Прибор перекоса согласования, поставленный ради РОВНОСТИ
показа, на первом прогоне по своду назвал не неровность, а ложь: «quanti mele» 3 страницы при
411 у «quante mele», «quantos mensagens» 208, «quanti voci» 213, «cuántos horas» 15. Семь домов
писали вопросное слово ВПИСАННЫМ В РАМКУ, и ни один суд свода этого не видел — потому что суд
сличает страницу с рамкой, а рамка лгала сама.

    ЛОЖЬ, ЖИВУЩАЯ В РАМКЕ, НЕ ЛОВИТСЯ СЛИЧЕНИЕМ СО СВОЕЙ ЖЕ РАМКОЙ.

ПОЧЕМУ ДВЕ МЕРЫ, А НЕ ОДНА. Перекос видит лишь ту ложь, у которой есть ВЕРНАЯ СЕСТРА в своде,
и молчит о лжи, сказанной всегда одинаково («quanti barche» жило бы вечно, не будь у дома мер
второго читателя). Эта мера видит ту же беду с другого конца — и тоже не всю: имя, о котором
свод говорит одним родом, ей не подсудно, каков бы род ни был. Обе меры суть половины, и обе
названы половинами.

ЧТО СЧИТАЕТСЯ ИМЕНЕМ — ПО ДЕЛУ, А НЕ ПО СЛОВАРЮ. Имя есть слово, хоть раз стоявшее СРАЗУ ЗА
ЧИСЛОМ («2 días», «15 mensagens»): счёт — это то, что корпус делает на каждой странице, и
потому признак этот дёшев и не выдуман. Служебные слова вычитаются по объявлению
языкового пакета (`function_words`): «¿cuántas le quedan?» и «quante ne ha» суть вопросы с
ОПУЩЕННЫМ именем, и род в них берётся у опущенного — оба верны, и оба не подсудны.

ПАРЫ ВОПРОСНОГО СЛОВА БЕРУТСЯ У ДОМА ЯЗЫКА (`tools/romgram.py`), а не переписаны здесь.

ТРЕТЬЯ ПОВЕРКА — АРТИКЛЬ ПРИ ИМЕНИ, И ЭТО ТОТ ЖЕ ЗАКОН. Служебное слово, стоящее в рамке целым,
не слышит того, что за ним подставят, — будь то «cuántos» или «el»: «un mela», «la libro»,
«os mensagens» суть та же ложь под другим словом. Таблица артиклей объявлена домом языка
(`romgram.АРТИКЛИ`), род имени — домом имени, и сверка идёт лишь там, где род ОБЪЯВЛЕН.
Итальянское «un'» есть ЖЕНСКОЕ, а «un» — мужское, и различает их АПОСТРОФ: прибор читает сырую
строку, а не разбитые слова, иначе он звал бы ложью верное «un'ora». На день написания поверка
эта не находит ничего — и сказано, что не находит: она стои́т не ради сегодняшнего числа, а
ради дома, который завтра впишет «el» в рамку целым.

ВТОРАЯ ПОВЕРКА — ПО ОБЪЯВЛЕННОМУ РОДУ, И ЕЙ СЕСТРА НЕ НУЖНА. Дома объявляют род своих имён
таблицами вида `РОД*` («toolforms.РОД», «cmpforms.РОД_ВЕЩЕЙ», «timeunits.РОД_МАЛОЙ»,
«measurelangs.РОД_НОСИТЕЛЯ», …), и прибор собирает их ВСЕ по одному признаку: имя дома
начинается на «РОД», ключ — язык, значение — слово и «m» либо «f». Имя, чей род объявлен, а
спрошено о нём словом другого рода, есть ложь — и видна она даже там, где свод говорит о ней
ВСЕГДА ОДИНАКОВО, то есть там, где первая поверка молчит.

    ДВА ДОМА, ОБЪЯВИВШИЕ ОДНОМУ СЛОВУ РАЗНЫЙ РОД, ЕСТЬ ТРЕТЬЯ БЕДА, И ОНА НАЗЫВАЕТСЯ ЗДЕСЬ ЖЕ:
    мера, молча выбравшая одно из двух объявлений, судила бы по жребию.

    python3 scripts/twogender.py [--свод FILE] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --свод no-such-file
import argparse
import collections
import importlib
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import romgram  # noqa: E402 — пары вопросного слова объявлены домом языка

# РУБЕЖ-ДОЛГА: ДВУРОДЫХ_РУБЕЖ = 0
ДВУРОДЫХ_РУБЕЖ = 0
_ТОКЕН = re.compile(r"\d+|[^\W\d_]+", re.UNICODE)


def _объявленные_роды():
    """(род по (язык, слово), беды несогласия) — все таблицы «РОД*» домов, собранные по признаку.

    ПРИЗНАК ОБЪЯВЛЕН ФОРМОЙ, А НЕ СПИСКОМ: перечисли прибор дома поимённо — и дом, написанный
    завтра, останется непроверенным, а молчание это неотличимо от здоровья.
    """
    роды, откуда, беды = {}, {}, []
    двор = КОРЕНЬ / "tools"
    for путь in sorted(двор.glob("*.py")):
        if путь.name.startswith("gen_genesis_"):
            continue
        try:
            дом = importlib.import_module(путь.stem)
        except Exception:                                  # noqa: BLE001 — чужой дом не наша беда
            continue
        for имя in dir(дом):
            if not имя.startswith("РОД"):
                continue
            таблица = getattr(дом, имя)
            if not isinstance(таблица, dict):
                continue
            for язык, ряд in таблица.items():
                if not isinstance(язык, str) or not isinstance(ряд, dict) or not ряд:
                    continue
                if not all(isinstance(к, str) and з in ("m", "f") for к, з in ряд.items()):
                    continue
                for слово, род in ряд.items():
                    ключ = (язык, слово.lower())
                    если = роды.get(ключ)
                    if если is not None and если != род:
                        беды.append((ключ, если, откуда[ключ], род, f"{путь.stem}.{имя}"))
                    роды[ключ] = род
                    откуда[ключ] = f"{путь.stem}.{имя}"
    return роды, откуда, беды


def спрошено_чужим(после, роды):
    """Имена, чей род ОБЪЯВЛЕН, а спрошено о них словом другого рода."""
    вон = []
    for язык in sorted(после):
        for слово, счёт in после[язык].items():
            род = роды.get((язык, слово))
            if род is None:
                continue
            чужой = "f" if род == "m" else "m"
            if счёт.get(чужой):
                вон.append((язык, слово, род, счёт[чужой]))
    вон.sort(key=lambda з: -з[3])
    return вон


def артикль_чужим(артикли, роды):
    """Имена с объявленным родом, при которых стои́т служебное слово ДРУГОГО рода."""
    вон = []
    for язык in sorted(артикли):
        for (слово, имя), счёт in артикли[язык].items():
            род = роды.get((язык, имя))
            if род is None:
                continue
            чужой = "f" if род == "m" else "m"
            if счёт.get(чужой):
                вон.append((язык, слово, имя, род, счёт[чужой]))
    вон.sort(key=lambda з: -з[4])
    return вон


def _служебные(язык):
    """Слова языка, которые НЕ ИМЕНА, по объявлению его пакета; пакета нет — вычета нет.

    СВЯЗКА ЕСТЬ КЛЕТКА ПАРАДИГМЫ, А НЕ ИМЯ (16.09). Признак имени здесь — «слово, хоть раз
    стоявшее СРАЗУ ЗА ЧИСЛОМ», и он дёшев и не выдуман; но дом страниц действия пишет «3
    deles eram azuis», и за числом там стои́т СВЯЗКА. Отсюда «quantos eram» против «quantas
    eram» — два рода у одного «имени», хотя обе страницы честны: род взят у ОПУЩЕННОГО
    имени, названного первым предложением («no pátio havia 40 ovos… quantos eram fortes?»).

        ПРИЗНАК ИМЕНИ ПО СОСЕДСТВУ С ЧИСЛОМ ЛОВИТ ВСЁ, ЧТО В ЭТОЙ РАМКЕ СТОИТ ЗА ЧИСЛОМ.
        Чинится он не сужением признака, а ВЫЧЕТОМ ПО ОБЪЯВЛЕНИЮ: пакет знает, где у него
        глагол, и прибор спрашивает пакет, а не догадывается сам.

    Вычитаются служебные слова и формы связки — ровно те два объявления, какие пакет несёт
    о словах, не являющихся именами.
    """
    путь = КОРЕНЬ / "tools" / "langpacks" / f"{язык}.json"
    try:
        пакет = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return frozenset()
    вон = {с.lower() for с in (пакет.get("function_words") or ())}
    for имя, класс in (пакет.get("morph_classes") or {}).items():
        if имя != "copula":
            continue
        for формы in (класс.get("lexemes") or {}).values():
            вон |= {ф.lower() for ф in формы}
    return frozenset(вон)


# АПОСТРОФ ЧИТАЕТСЯ ИЗ СЫРОЙ СТРОКИ, А НЕ ИЗ РАЗБИТЫХ СЛОВ: «un\'ora» женское, «un tavolo»
# мужское, и разбиение по буквам эту разницу стирает — прибор звал бы ложью верную страницу.
# СЛЕДУЮЩЕЕ СЛОВО БЕРЁТСЯ ЗАГЛЯДЫВАНИЕМ, А НЕ СЪЕДАЕТСЯ (12.09, поймано чтением). Образец,
# съедающий пару целиком, идёт дальше ЗА нею — и всякая вторая пара строки теряется: «a b c d»
# дало бы (a, b) и (c, d), а (b, c) не дало бы никогда.
#
#     МЕРА, ЧИТАЮЩАЯ ПАРАМИ ВПРИТЫК, ВИДИТ ПОЛОВИНУ ПАР И МОЛЧИТ О ПОЛОВИНЕ.
# МЕЖДУ СЛОВАМИ ОБЯЗАН СТОЯТЬ ПРОБЕЛ ИЛИ АПОСТРОФ, А НЕ НИЧТО: заглядывание без этого требования
# находит пару ВНУТРИ слова («tavol» + «o») и зовёт началом имени его хвост.
_СЛОВО_ПОДРЯД = re.compile(r"([^\W\d_]+)(?:([\'’])\s*|\s+)(?=([^\W\d_]+))", re.UNICODE)


def _пары_слов(строка):
    """(слово, следующее слово, стоит ли апостроф между ними) — по сырой строке."""
    return [(м.group(1).lower(), м.group(3).lower(), bool(м.group(2)))
            for м in _СЛОВО_ПОДРЯД.finditer(строка)]


def перепись(строки):
    """(после вопросного слова по языкам, имена) — один проход по строкам свода."""
    вопросные = {}
    for язык, (м, ж) in romgram.ПАРЫ.items():
        вопросные[м.lower()] = (язык, "m")
        вопросные[ж.lower()] = (язык, "f")
    после = collections.defaultdict(lambda: collections.defaultdict(collections.Counter))
    артикли = collections.defaultdict(lambda: collections.defaultdict(collections.Counter))
    имена = collections.Counter()
    for стр in строки:
        токены = [т.lower() for т in _ТОКЕН.findall(стр)]
        for i, т in enumerate(токены[:-1]):
            if т.isdigit():
                имена[токены[i + 1]] += 1
        for слово, следом, апостроф in _пары_слов(стр):
            for язык in romgram.АРТИКЛИ:
                род = romgram.артикль(язык, слово, апостроф)
                if род is not None:
                    артикли[язык][(слово, следом)][род] += 1
        if "?" not in стр:
            continue
        for i, т in enumerate(токены[:-1]):
            чьё = вопросные.get(т)
            if чьё:
                после[чьё[0]][токены[i + 1]][чьё[1]] += 1
    return после, имена, артикли


def двуродые(после, имена, служебные):
    """Имена, названные обоими родами: (язык, слово, счёт мужского, счёт женского)."""
    вон = []
    for язык in sorted(после):
        for слово, счёт in после[язык].items():
            if len(счёт) < 2 or not имена.get(слово) or слово in служебные.get(язык, ()):
                continue
            вон.append((язык, слово, счёт["m"], счёт["f"]))
    вон.sort(key=lambda з: min(з[2], з[3]))
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ДВА РОДА ВИДНЫ, А ОДИН — НЕТ.

        ПРИБОР, СЧИТАЮЩИЙ ЛИШЬ ТЕХ, КОГО УЗНАЛ, МОЛЧИТ О НЕУЗНАННЫХ, и молчание его
        неотличимо от здоровья: пусть пары вопросных слов перестанут читаться — и всякая
        строка уйдёт мимо, а прибор скажет «двуродых 0», сверив НОЛЬ СТРОК.

    Четыре заведомо известных случая: ложь, честное имя, опущенное имя и слово, за числом
    никогда не стоявшее.
    """
    беды = []
    строки = (
        "ci sono 3 mele. quanti mele ci sono? 3 mele.",     # ложь: два рода у «mele»
        "ci sono 3 mele. quante mele ci sono? 3 mele.",
        "ci sono 4 libri. quanti libri ci sono? 4 libri.",  # честное имя: один род
        "ne ha 5. quanti ne ha? 5.",                        # опущенное имя: служебное слово
        "ne ha 5. quante ne ha? 5.",
        "quanti xyzzy? quante xyzzy?",                      # за числом не стояло — не имя
    )
    после, имена, артикли = перепись(строки)
    найдено = {(я, с) for я, с, _, _ in двуродые(после, имена, {"it": _служебные("it")})}
    if ("it", "mele") not in найдено:
        беды.append("ложь «quanti mele / quante mele» не названа")
    if ("it", "libri") in найдено:
        беды.append("честное имя одного рода названо двуродым")
    if ("it", "ne") in найдено:
        беды.append("опущенное имя (служебное слово) принято за имя")
    if ("it", "xyzzy") in найдено:
        беды.append("слово, за числом не стоявшее, принято за имя")
    if not romgram.ПАРЫ:
        беды.append("пары вопросного слова не прочтены — сверять будет нечего")
    # ВТОРАЯ ПОВЕРКА ПРОБУЕТСЯ ТАМ ЖЕ: ложь без сестры обязана быть видна.
    без_сестры, _, _ = перепись(("ci sono 3 penne. quanti penne ci sono? 3 penne.",))
    чужим = {(я, с) for я, с, _, _ in спрошено_чужим(без_сестры, {("it", "penne"): "f"})}
    if ("it", "penne") not in чужим:
        беды.append("ложь без сестры («quanti penne» при объявленном женском) не названа")
    свои, _, _ = перепись(("ci sono 4 libri. quanti libri ci sono? 4 libri.",))
    if спрошено_чужим(свои, {("it", "libri"): "m"}):
        беды.append("верное согласование названо ложью")
    роды, _, разлад = _объявленные_роды()
    if not роды:
        беды.append("объявлений рода не прочтено ни одного — вторая поверка слепа")
    # ТРЕТЬЯ ПОВЕРКА: артикль при имени, и апостроф, который её решает.
    _, _, арт = перепись(("c'è una mela sul tavolo.",          # верно: «mela» женское
                          "c'è un mela sul tavolo.",           # ложь: мужское при женском
                          "c'è un'ora di tempo.",              # верно: «un'» есть женское
                          "ci sono 2 libri.",))
    имена_рода = {("it", "mela"): "f", ("it", "ora"): "f"}
    чужой_артикль = {(я, а, и) for я, а, и, _, _ in артикль_чужим(арт, имена_рода)}
    if ("it", "un", "mela") not in чужой_артикль:
        беды.append("«un mela» при объявленном женском не названо")
    if ("it", "una", "mela") in чужой_артикль:
        беды.append("верный артикль назван ложью")
    if ("it", "un", "ora") in чужой_артикль:
        беды.append("«un'ora» названо ложью — апостроф не прочтён")
    if not romgram.АРТИКЛИ:
        беды.append("артиклей не прочтено ни одного — третья поверка слепа")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ДВУРОДОЕ ИМЯ ОТКАЗ: признак двух родов не доказан ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--свод", default=None)
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--рубеж", type=int, default=ДВУРОДЫХ_РУБЕЖ)
    дов = ап.parse_args()
    свод = pathlib.Path(дов.свод) if дов.свод else КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
    if not свод.is_file():
        print(f"ДВУРОДОЕ ИМЯ ОТКАЗ: нет свода «{свод}»")
        return 2
    строки = свод.read_text(encoding="utf-8", errors="replace").splitlines()
    после, имена, артикли = перепись(строки)
    служебные = {язык: _служебные(язык) for язык in romgram.ПАРЫ}
    роды, откуда, разлад = _объявленные_роды()
    двурод = двуродые(после, имена, служебные)
    чужим = спрошено_чужим(после, роды)
    при_имени = артикль_чужим(артикли, роды)
    for язык, слово, м, ж in (двурод if дов.подробно else двурод[:6]):
        мс, жс = romgram.ПАРЫ[язык]
        print(f"  ДВА РОДА   {язык}  «{мс} {слово}» {м:5}   против   «{жс} {слово}» {ж:5}")
    for язык, слово, род, сколько in (чужим if дов.подробно else чужим[:6]):
        чужое = romgram.вопросное(язык, "f" if род == "m" else "m")
        print(f"  ЧУЖИМ      {язык}  «{чужое} {слово}» {сколько:5} — род объявлен «{род}» "
              f"({откуда[(язык, слово)]})")
    for язык, слово, имя, род, сколько in (при_имени if дов.подробно else при_имени[:6]):
        print(f"  АРТИКЛЬ    {язык}  «{слово} {имя}» {сколько:5} — род имени объявлен «{род}» "
              f"({откуда[(язык, имя)]})")
    for ключ, первый, где1, второй, где2 in разлад:
        print(f"  РАЗЛАД     {ключ[0]}  «{ключ[1]}»: {где1} зовёт «{первый}», {где2} — «{второй}»")
    всего = len(двурод) + len(чужим) + len(при_имени) + len(разлад)
    итог = "PASS" if всего <= дов.рубеж else "FAIL"
    спрошено = sum(sum(с.values()) for я in после for с in после[я].values())
    print(f"ДВУРОДОЕ ИМЯ {итог}: бед {всего} (рубеж {дов.рубеж}) — двуродых {len(двурод)}, "
          f"спрошенных чужим родом {len(чужим)}, артикль чужого рода {len(при_имени)}, "
          f"разладов объявления {len(разлад)}; языков с гнутьём {len(romgram.ПАРЫ)}, "
          f"вопросов с гнутым словом {спрошено}, объявлений рода {len(роды)}, "
          f"имён свода {len(имена)}")
    return 0 if итог == "PASS" else 1


