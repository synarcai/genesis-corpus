#!/usr/bin/env python3
"""[ЗНАК ПРОТИВ СЛОВА] — где один язык мира говорит действие знаком, а другой словом.

Изъян, найденный holon 03.09 на мире линала: русские строки говорили действие
СЛОВОМ («[9 3; 3 4] умножить на (2, 4) даёт (30, 22)»), английские — только
ЗНАКОМ («[9 3; 3 4] × (2, 4) = (30, 22)»), и рынок, купивший цепочку по одной
поверхности, не узнавал её в другой: английского близнеца русской цепочки в
своде как бы не было, хотя строки стояли рядом.

Прибор ищет такие расхождения ВЕЗДЕ. Для каждого мира он считает, каким
способом говорит действие каждая половина — кириллическая и латинская, — и
называет мир, где половины разошлись: одна знает только знак, другая только
слово. Действия и их слова объявлены ниже; ничего не угадывается.

ЭТО КАРТА, А НЕ ПРИГОВОР. Мир вправе говорить одним знаком на обоих языках
(таблица умножения) или одним словом (речь о вычислении). Расхождение же —
место, где одна и та же цепочка живёт двумя поверхностями, и рынок обязан
покупать её дважды вместо одного раза.

    python3 scripts/sign_word.py [--сколько 20]
"""
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402

# действие: знак и объявленные слова каждой половины
ДЕЙСТВИЯ = {
    "умножение": ("×", ("times", "multiplied by"), ("умножить на", "умноженное на")),
    "деление": ("÷", ("divided by",), ("делить на", "делённое на", "разделить на")),
    "сложение": ("+", ("plus",), ("плюс",)),
    "вычитание": ("−", ("minus",), ("минус",)),
}
КИРИЛЛИЦА = re.compile(r"[А-Яа-яЁё]")
ЛАТИНИЦА = re.compile(r"[A-Za-z]")


def половина(строка):
    """«кир», «лат» — или None: строка без букв не принадлежит ни одной.

    Первая редакция звала латинской ВСЯКУЮ строку без кириллицы, и чисто
    числовые строки пакетов («1 + 4 = 5.») выходили латинской половиной,
    говорящей знаком: расхождение объявлялось там, где половины нет вовсе.
    """
    if КИРИЛЛИЦА.search(строка):
        return "кир"
    return "лат" if ЛАТИНИЦА.search(строка) else None


def счёт(путь):
    """{(половина, действие): {'знак': n, 'слово': n}}"""
    вон = collections.defaultdict(lambda: collections.Counter())
    for с in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        с = с.strip()
        if not с or с.startswith("\x0c"):
            continue
        п = половина(с)
        if п is None:
            continue
        for имя, (знак, слова_лат, слова_кир) in ДЕЙСТВИЯ.items():
            слова = слова_кир if п == "кир" else слова_лат
            if знак in с:
                вон[(п, имя)]["знак"] += 1
            if any(сл in с for сл in слова):
                вон[(п, имя)]["слово"] += 1
    return вон


def расхождения(вон):
    """[(действие, у кого знак, у кого слово)] — половины разошлись поверхностью."""
    итог = []
    for имя in ДЕЙСТВИЯ:
        кир, лат = вон.get(("кир", имя), collections.Counter()), вон.get(("лат", имя), collections.Counter())
        if not (кир or лат):
            continue
        # половина ЗНАЕТ поверхность, если сказала ею хоть раз
        for одна, другая, имена in ((кир, лат, ("кир", "лат")), (лат, кир, ("лат", "кир"))):
            if одна["слово"] and not одна["знак"] and другая["знак"] and not другая["слово"]:
                итог.append((имя, имена[1], имена[0], другая["знак"], одна["слово"]))
    return итог


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--сколько", type=int, default=20)
    а = ап.parse_args()
    найдено = []
    миров = 0
    for путь in genesis.worlds(kind="shows"):
        миров += 1
        for имя, знаком, словом_, n_знак, n_слово in расхождения(счёт(путь)):
            найдено.append((n_знак + n_слово, путь.stem, имя, знаком, словом_, n_знак, n_слово))
    найдено.sort(reverse=True)
    print(f"ЗНАК ПРОТИВ СЛОВА: миров {миров}, расхождений {len(найдено)}")
    for _, мир, имя, знаком, словом_, n_знак, n_слово in найдено[:а.сколько]:
        print(f"  {мир}: {имя} — {знаком} говорит ЗНАКОМ ({n_знак} строк), "
              f"{словом_} СЛОВОМ ({n_слово} строк)")
    if not найдено:
        print("  расхождений нет: обе половины говорят действие одинаково везде")
    return 0


if __name__ == "__main__":
    sys.exit(main())
