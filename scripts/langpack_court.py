#!/usr/bin/env python3
"""[ЯЗЫКИ] — сколько объявленных языков ПРОХОДИТ девять полей движка.

Владелец назвал цель: ВСЕ ЯЗЫКИ, и назвал причину — «чтобы мы выявили
все дефекты в нашей архитектуре и реализации». Это верно устроено:
всякий язык, не влезающий в движок, есть НАХОДКА, а не неудача. Пакет,
потребовавший правки движка, опровергает заявление архитектуры («язык
стоит одного пакета и ноль правок»), и опровергает его ФАКТОМ.

ПРИБОР МЕРИТ ЛЕСТНИЦУ, А НЕ ИТОГ. Языков будет больше, чем зелёных, и
это нормально: рубеж стоит на числе зелёных, и он ПОДНИМАЕТСЯ. Красный
язык не выкидывается — он стоит в счёте с именем своего красного поля,
чтобы долг был виден числом, а не памятью.

ЯРУС ПАКЕТА ОБЪЯВЛЕН В НЁМ САМОМ. `tier: 1` значит «строение зелено,
формы не проверены носителем» — движок судит СТРОЕНИЕ и не знает, верно
ли «hablas». Смешивать эти две уверенности значило бы лгать о второй.
"""
import json
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ПАКЕТЫ = КОРЕНЬ / "tools/langpacks"
ДВИЖОК = КОРЕНЬ / "tools/langpack.py"
ЯДРО = КОРЕНЬ / "datasets/genesis_v0.txt"

# РУБЕЖ-ДОЛГА: ЗЕЛЁНЫХ_РУБЕЖ = 6
ЗЕЛЁНЫХ_РУБЕЖ = 6

# ПУСТОЙ-ОБХОД: --packs no-such-dir

ПОЛЕ = re.compile(r"^LANGPACK-(\w+)\t(.*)$", re.M)


def обход():
    каталог = ПАКЕТЫ
    if "--packs" in sys.argv:
        каталог = pathlib.Path(sys.argv[sys.argv.index("--packs") + 1])
    return sorted(каталог.glob("*.json")) if каталог.is_dir() else []


def судить_пакет(путь):
    """(зелен ли, имя красного поля или None)."""
    зов = [sys.executable, str(ДВИЖОК), str(путь)]
    if ЯДРО.is_file():
        зов += ["--core", str(ЯДРО)]
    r = subprocess.run(зов, capture_output=True, text=True, cwd=КОРЕНЬ)
    красное = None
    for имя, хвост in ПОЛЕ.findall(r.stdout):
        if имя == "OUT":
            continue
        m = re.match(r"^(\d+) of (\d+)", хвост)
        плохо = (m and m.group(1) != m.group(2)) or "REFUSED" in хвост
        if плохо and красное is None:
            красное = имя
    return r.returncode == 0, красное


def main():
    пакеты = обход()
    if not пакеты:
        print("ЯЗЫКИ ОТКАЗ: пакетов нет, судить нечего")
        return 2
    зелёных, красные = 0, []
    for путь in пакеты:
        try:
            я = json.loads(путь.read_text(encoding="utf-8")).get("lang", "?")
        except (OSError, ValueError):
            красные.append((путь.stem, "НЕЧИТАЕМ"))
            continue
        зелен, поле = судить_пакет(путь)
        if зелен:
            зелёных += 1
        else:
            красные.append((я, поле or "?"))
    for я, поле in красные[:8]:
        print(f"  {я:<6} красное поле: {поле}")
    поза = "PASS" if зелёных >= ЗЕЛЁНЫХ_РУБЕЖ else "FAIL"
    # ДОЛГ, НАЗВАННЫЙ ЧИСЛОМ: ВОПРОСНЫЕ СЛОВА ОБЯЗАН ОБЪЯВЛЯТЬ ПАКЕТ.
    # Суд письма ловит вопрос без вопросного слова по множеству зачинов,
    # ЗАМЕРЕННОМУ по своду и живущему в доме пары временно (М-137).
    # Языки с постпозицией вопросного слова (турецкий, суахили, японский)
    # этому дому не подсудны вовсе — пока их пакет не объявит своё. Поле
    # «ask_words» — объявление; здесь считается, у скольких его нет.
    без_вопросных = [п for п in пакеты if not json.loads(
        п.read_text(encoding="utf-8")).get("ask_words")]
    # ЗАЧИНЫ ПАКЕТА ≡ ЗАЧИНЫ ПЛАСТА — объявление сверяется с делом. Пакет
    # объявил вопросные слова и позицию; его пласт порождён из того же
    # пакета — значит каждый вопрос пласта обязан нести объявленное слово
    # на объявленном месте. Иначе либо объявление лжёт, либо пласт
    # спрашивает словом, которого пакет не признал. Замер тот же, каким
    # объявления выводились (К-1 C6, М-137): вопросы пласта, первое или
    # последнее слово, «¬» впереди в любом языке.
    разладов_зачинов = 0
    for п in пакеты:
        пакет = json.loads(п.read_text(encoding="utf-8"))
        объ = пакет.get("ask_words")
        пласт = КОРЕНЬ / "datasets" / f"genesis_lang_{пакет.get('lang')}.txt"
        if not объ or not пласт.exists():
            continue
        words = {w.lower() for w in объ.get("words", ())}
        позиция = объ.get("position")
        чужих = 0
        всего_в = 0
        for с in пласт.read_text(encoding="utf-8").splitlines():
            т = с.strip()
            if not re.search(r"[?？؟]", т):
                continue
            вопрос = re.split(r"[?？؟]", т)[0].strip()
            слова = [w.strip("«»\"'()[],.;:!").lower() for w in вопрос.split()]
            слова = [w for w in слова if w]
            if not слова:
                continue
            всего_в += 1
            if слова[0] == "¬" and "¬" in words:
                continue
            if позиция == "end":
                ок = слова[-1] in words or any(слова[-1].endswith(w) for w in words)
            elif позиция == "any":
                ок = any(w in words or any(x in w for x in words) for w in слова)
            else:
                ок = (слова[0] in words or any(слова[0].startswith(w) for w in words)
                      or (len(слова) > 1 and слова[1] in words))
            if not ок:
                чужих += 1
        if чужих:
            разладов_зачинов += 1
            print(f"  ЗАЧИН ВНЕ ОБЪЯВЛЕНИЯ {пакет.get('lang')}: {чужих} вопросов "
                  f"пласта из {всего_в} несут слово, которого пакет не объявил")
    print(f"  ЗАЧИНЫ ПАКЕТА ≡ ЗАЧИНЫ ПЛАСТА: разладов {разладов_зачинов} "
          f"(объявлений {len(пакеты) - len(без_вопросных)})")
    print(f"  ВОПРОСНЫХ СЛОВ НЕ ОБЪЯВЛЯЮТ {len(без_вопросных)} из "
          f"{len(пакеты)} пакетов — долг дому пары (М-137)")
    print(f"ЯЗЫКИ {поза}: {зелёных} зелёных из {len(пакеты)}, "
          f"красных {len(красные)} (рубеж {ЗЕЛЁНЫХ_РУБЕЖ})")
    return 0 if зелёных >= ЗЕЛЁНЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
