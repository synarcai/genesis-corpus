#!/usr/bin/env python3
"""[ПУСТОЕ ВХОЖДЕНИЕ] — `срез in "литерал"`: проверка, которую пустота проходит насквозь.

    «'' in "+−×÷-"» ЕСТЬ ИСТИНА. Пустая строка есть подстрока всякой, и потому проверка
    «последний знак хвоста есть знак действия» ГОВОРИТ ДА о хвосте, которого нет.

ПОВОД, И ОН СТОИЛ ЗЕЛЁНОГО СУДА. 09.09 суд порождения пласта учили читать леджер своими
глазами; чтобы не принять кусок большего выражения за выражение, он спрашивал
`до[-1:] in "+−×÷-"`. Для леджера, стоящего в НАЧАЛЕ строки, `до` пусто — и всякий такой
леджер объявлялся куском, то есть НЕ ЧИТАЛСЯ. Суд снова звал «9 + 9 = 17» истиной и звал бы
МОЛЧА: мера была зелена, вердикт был «истина», и ничто не указывало на дыру.

    ПРОВЕРКА НА ВХОЖДЕНИЕ, ПРОПУСКАЮЩАЯ ПУСТОТУ, ЕСТЬ ПРОВЕРКА, КОТОРОЙ НЕТ. Она не падает,
    не шумит и не лжёт в лицо — она ТИХО ОТВЕЧАЕТ ДА, и ошибка уходит в вердикт соседа.

ЛЕЧЕНИЕ ОДНО И ОНО ЖЕ ЕСТЬ ОБЪЯВЛЕНИЕ: `frozenset("+−×÷-")`. Набор знаков есть набор ЗНАКОВ,
а не строка, и пустой строки в нём нет. Замена буквальна, цены не имеет и читается лучше.

ЧТО СЧИТАЕТСЯ НАХОДКОЙ. Сравнение `in`/`not in`, у которого СЛЕВА стои́т СРЕЗ (`x[-1:]`,
`x[:1]`, `x[i:j]`), а СПРАВА — строковый литерал. Индекс (`x[-1]`) сюда не входит: он на
пустоте ПАДАЕТ, то есть кричит, а прибор поставлен против МОЛЧАЛИВЫХ.

ГРАНИЦА: находка не всегда есть ошибка — соседний конъюнкт может гасить пустоту
(`хвост[-1:] in ".," and хвост[-2:-1].isdigit()` цел, ибо `''.isdigit()` ложно). Прибор
считает не ошибки, а ФОРМЫ, чья истинность держится на соседе: рубеж НОЛЬ поставлен потому,
что цена лечения — одно слово, а цена пропуска — зелёный суд.

    python3 scripts/empty_in_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-park-dir
import ast
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: НАХОДОК_РУБЕЖ = 0
#
# ПОСТАВЛЕН НА ТРЁХ И ЗАКРЫТ В ТОТ ЖЕ ЧАС: две в суде русской грамматики (обе спасены
# соседним конъюнктом) и одна в доме английского числа (`голова[:1] in "aeio"` при имени
# из одних знаков препинания давало «an»). Рубеж есть ПОЛ, а не потолок.
НАХОДОК_РУБЕЖ = 0


def _срез(узел):
    return isinstance(узел, ast.Subscript) and isinstance(узел.slice, ast.Slice)


def находки(дерево):
    """Сравнения `срез in "литерал"` — (строка, текст)."""
    вон = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Compare) or len(узел.ops) != 1:
            continue
        if not isinstance(узел.ops[0], (ast.In, ast.NotIn)):
            continue
        прав = узел.comparators[0]
        if not (isinstance(прав, ast.Constant) and isinstance(прав.value, str)):
            continue
        if _срез(узел.left):
            вон.append((узел.lineno, ast.unparse(узел)[:90]))
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что признак ВИДИТ срез и не берёт лишнего.

        ПРИБОР СТОИТ НА НУЛЕ И ЗЕЛЕНЕЕТ ОТ НУЛЯ. Пусть разбор перестанет узнавать срез —
        и он будет зелен над деревом, полным той самой беды, ради которой заведён.

    Пять записей, и про каждую известно заранее, находка она или нет. Среди них два
    близких промаха: срез с ИМЕНЕМ справа (литерала нет — сравнить не с чем) и целое имя
    слева (пустоты там не бывает).
    """
    беды = []
    случаи = (
        ('if хвост[-1:] in "+−×÷":\n    pass\n', 1, "срез против литерала — находка"),
        ('if хвост[-1:] not in "+−×÷":\n    pass\n', 1, "отрицание того же — находка"),
        ('if знак in "+−×÷":\n    pass\n', 0, "целое имя слева — пустоты не бывает"),
        ('if хвост[-1:] in ЗНАКИ:\n    pass\n', 0, "справа имя, а не литерал"),
        ('if хвост[0] in "+−×÷":\n    pass\n', 0, "один знак, а не срез"),
    )
    for текст, ждём, что in случаи:
        дало = len(находки(ast.parse(текст)))
        if дало != ждём:
            беды.append(f"{что}: находок {дало}, а надо {ждём}")
    # И ГЛАВНОЕ: НАХОДКА ОБЯЗАНА НАЗВАТЬ МЕСТО, А НЕ ТОЛЬКО СЛУЧИТЬСЯ.
    вон = находки(ast.parse('x = 1\nif хвост[-1:] in "+−":\n    pass\n'))
    if not вон or вон[0][0] != 2 or "хвост" not in вон[0][1]:
        беды.append(f"находка без места или без записи: {вон}")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ПУСТОЕ ВХОЖДЕНИЕ ОТКАЗ: прибор не доказал, что видит срез ({len(беды)} бед)")
        return 2
    файлов, всего, битые = 0, 0, []
    for путь in sorted(КОРЕНЬ.rglob("*.py")):
        if ".git" in путь.parts:
            continue
        файлов += 1
        try:
            дерево = ast.parse(путь.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        вон = находки(дерево)
        всего += len(вон)
        for н, т in вон:
            битые.append(f"{путь.relative_to(КОРЕНЬ)}:{н}: {т}")
    if not файлов:
        print("ПУСТОЕ ВХОЖДЕНИЕ ОТКАЗ: ни одного файла .py")
        return 2
    for б in битые[:20]:
        print(f"  {б}")
    поза = "PASS" if всего <= НАХОДОК_РУБЕЖ else "FAIL"
    print(f"ПУСТОЕ ВХОЖДЕНИЕ {поза}: срезов, сличаемых со строковым литералом, {всего} "
          f"(рубеж {НАХОДОК_РУБЕЖ}); файлов {файлов}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
