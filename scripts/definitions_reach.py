#!/usr/bin/env python3
"""[СЛЕД РАЗБОРА ОПРЕДЕЛЕНИЙ] — где разбор статьи остановился на каждом понятии без определения.

Мир определений сам печатает «НЕ НАЙДЕНО НА ПОЛКЕ (222)», и число это лгало о полке:
у 127 из 222 заголовок на полке ЕСТЬ. Долг был не полки, а разбора — но разбор молчал о
том, где остановился, и перечитать полку было бы единственным способом узнать.

Прибор повторяет путь разбора шаг за шагом и называет ПЕРВЫЕ ЗАКРЫТЫЕ ВОРОТА для каждого
немого понятия (слово holon о следе уходов: долг закрывается списком мест, а не
перечитыванием). Ворота Вебстера: статья по слову → существительное («n.» в голове) →
разобранные смыслы → первая фраза → укорочение → чистота. Ворота ЭСБЕ/Даля: статья →
кандидаты первой фразы → чистота; Даль — выделение цитаты.

    python3 scripts/definitions_reach.py [--подробно]
"""
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import gen_genesis_definitions as G  # noqa: E402
import definitions as D  # noqa: E402


def ворота_en(п):
    сл = D.словарь("webster")
    все = list(сл.по_слову(п))
    if not все:
        return "нет статьи по слову"
    сущ = [с for _, с in все if re.search(r"(?:^|[ ,])n\.", с.тело.split("\n", 1)[0])]
    if not сущ:
        return "статья есть, но не существительное"
    раз = [(с, G._смыслы(с.тело.split("\n"))) for с in сущ]
    if not any(см for _, см in раз):
        return "существительное без разобранных смыслов"
    _, см = max(раз, key=lambda x: len(x[1]))
    ф0 = G._первая_фраза_en(см[0][1])
    if not ф0:
        return "первая фраза пуста"
    ф = G._укоротить(ф0)
    if not ф:
        return "фраза длиннее МАКС_СЛОВ и не режется"
    if not G._чисто_en(ф):
        return "первая фраза нечиста"
    return "прошла бы — причина не названа"


def ворота_ru(п):
    сэ = list(D.словарь("esbe").по_слову(п))
    сд = list(D.словарь("dal").по_слову(п))
    if not сэ and not сд:
        return "нет статьи ни в ЭСБЕ, ни у Даля"
    к = []
    for _, с in сэ:
        к += G._кандидаты_эсбе(п, с)
    if сэ and not к:
        return "ЭСБЕ: статья есть, кандидатов первой фразы нет"
    if к and not any(G._чисто_ru(x if isinstance(x, str) else x[0]) for x in к):
        return "ЭСБЕ: кандидаты нечисты"
    # ВОРОТА РАНГА: цитата берётся лишь из точной статьи (ранг ≤ 1); чистая
    # фраза в уточнённой статье («Дивергенция (в биологии)») не берётся — и
    # разбор молчал об этом, пока прибор не назвал ворота по имени
    if сэ:
        точные = [с for _, с in сэ if G._ранг_эсбе(п, с.заголовок) <= 1]
        чистые_точные = [x for с in точные for x in G._кандидаты_эсбе(п, с)
                         if G._чисто_ru(x if isinstance(x, str) else x[0])]
        if к and not чистые_точные:
            return "ЭСБЕ: чистая цитата лишь в уточнённой статье (ранг > 1)"
    if сд and not G.цитата_даля(п):
        return "Даль: статья есть, цитата не выделилась"
    return "прошла бы — причина не названа"


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    а = ап.parse_args()
    все = G.понятия()
    немые = [(я, п) for я, п in все if not G.факты(я, п)]
    причины = collections.Counter()
    прим = collections.defaultdict(list)
    for я, п in немые:
        r = (ворота_en if я == "en" else ворота_ru)(п)
        причины[(я, r)] += 1
        if len(прим[(я, r)]) < (12 if а.подробно else 4):
            прим[(я, r)].append(п)
    print(f"{'яз':<3}{'понятий':>8}  ворота")
    for (я, r), n in sorted(причины.items(), key=lambda x: -x[1]):
        print(f"{я:<3}{n:>8}  {r:<48} {' '.join(прим[(я, r)])}")
    без_статьи = sum(n for (я, r), n in причины.items() if r.startswith("нет статьи"))
    не_названо = sum(n for (я, r), n in причины.items() if r.startswith("прошла бы"))
    print(f"СЛЕД РАЗБОРА ОПРЕДЕЛЕНИЙ: понятий {len(все)}, без определения {len(немые)}, "
          f"из них полка не знает {без_статьи}, разбор остановился на названных воротах "
          f"{len(немые) - без_статьи - не_названо}, причина не названа {не_названо} (рубеж 0)")
    return 1 if не_названо else 0


if __name__ == "__main__":
    sys.exit(main())
