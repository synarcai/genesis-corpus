#!/usr/bin/env python3
"""[РЫНОК ПАДЕЖА ЛИЦА] — в каком падеже свод ставит лицо после слова.

    ЛИЦО ПОСЛЕ СЛОВА СТОИТ В ТОМ ПАДЕЖЕ, В КАКОМ СВОД ЕГО ПОСЛЕ ЭТОГО СЛОВА СТАВИЛ; А КАКОЙ
    ЭТО ПАДЕЖ, ГОВОРИТ ПАКЕТ, ОБЪЯВИВШИЙ ФОРМЫ ИМЕНИ ПОИМЁННО.

Покупка живёт в двери лиц (`tools/actors.py`, третий слой — там повод, улов и граница), а
здесь она ЗАПИСЫВАЕТСЯ на полку — `datasets/GENESIS-FULL.personcase.tsv` — и сверяется с
делом, как полка зачина деятеля у соседа `scripts/actorplace_market.py`.

ЧТО НА ПОЛКЕ. Строка сайдкара — язык, слово перед лицом, показы, купленные падежи через
запятую. Падеж объявлен ПАКЕТОМ (`person_forms`: `gen`, `dat`; `nom` — само имя).

ЧТО СУДИТ ГОЛЫЙ ЗОВ. Пересобирает рынок по своду и сличает с полкой: расхождение есть
устаревшая покупка. Рубеж НОЛЬ.

    python3 scripts/personcase_market.py [--собрать] [--цена] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import argparse
import collections
import pathlib
import sys
import zlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import actors  # noqa: E402 — дверь лиц: рынок падежа лица живёт там

# РУБЕЖ-ДОЛГА: РАСХОЖДЕНИЙ_РУБЕЖ = 0
#
# Полка и свод либо сходятся, либо покупка лжёт — рубеж рождён нулём, как у соседа.
РАСХОЖДЕНИЙ_РУБЕЖ = 0


def строки_полки(куплено, рынок):
    вон = ["# РЫНОК ПАДЕЖА ЛИЦА — в каком падеже свод ставит лицо после этого слова.",
           "# Собран `python3 scripts/personcase_market.py --собрать` по мирам, объявившим",
           "# деятелей (манифест `actors`). Столбцы: язык, слово перед лицом, показы, падежи.",
           "# Падеж объявлен ПАКЕТОМ языка (`person_forms`); `nom` — само имя."]
    for (язык, слово), падежи in sorted(куплено.items()):
        показы = sum(рынок[(язык, слово)].values())
        вон.append(f"{язык}\t{слово}\t{показы}\t{','.join(sorted(падежи))}")
    return вон


def цена_на_другой_половине():
    """Рынок куплен на половине строк, суд идёт по другой — той, какой он не видел."""
    половина = lambda с: zlib.crc32(с.encode("utf-8")) % 2 == 0   # noqa: E731
    куп = actors.куплены_падежи(actors.собрать_рынок_падежа(доля=половина))
    обвинений, примеры, судимых = collections.Counter(), [], 0
    for имя, путь, языки in actors.миры_деятелей():
        if not путь.exists() or not any(actors.падежи_лиц(я) for я in языки):
            continue
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            строка = строка.strip()
            if not строка or половина(строка):
                continue
            судимых += 1
            for перед, форма, язык in actors.порча_падежа(строка, языки, куп=куп):
                обвинений[имя] += 1
                if len(примеры) < 6:
                    примеры.append((имя, язык, перед, форма, строка[:70]))
    return len(куп), судимых, обвинений, примеры


# ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ. Пары «целое → порча» взяты из строк свода, какие палата до
# закона звала истиной порченными: первая — непойманная подсадки словом (мир `speech`),
# вторая и третья — из замера всякой формы лица (мир `everyday`). Порча здесь НЕ ИЩЕТСЯ
# прибором, а названа — проба доказывает не поиск, а ЧТЕНИЕ.
ПРОБЫ = (
    (("ru",), "у Ивана было 5 яблок. он отдал 3 яблока. у него осталось 2 яблока.",
              "у Иван было 5 яблок. он отдал 3 яблока. у него осталось 2 яблока."),
    (("ru",), "у Иры 3 книги, а у Тома 5 книг; у Иры на 2 книги меньше, чем у Тома.",
              "у Иры 3 книги, а у Том 5 книг; у Иры на 2 книги меньше, чем у Тома."),
    (("ru",), "у Ивана 14 монет, а у Ани 7 монет; у Ивана вдвое больше, чем у Ани.",
              "у Иван 14 монет, а у Ани 7 монет; у Ивана вдвое больше, чем у Ани."),
)


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: лицо в чужом падеже ловится, в своём — молчит."""
    куп = actors.куплен_падеж()
    if not куп:
        return None
    поймано = sum(1 for языки, _, порча in ПРОБЫ
                  if actors.порча_падежа(порча, list(языки), куп=куп))
    ложных = sum(1 for языки, цело, _ in ПРОБЫ
                 if actors.порча_падежа(цело, list(языки), куп=куп))
    return поймано, len(ПРОБЫ), ложных


def main():
    ап = argparse.ArgumentParser(add_help=True)
    ап.add_argument("--собрать", action="store_true")
    ап.add_argument("--цена", action="store_true")
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--манифест", default=None)
    дано = ап.parse_args()
    if дано.манифест:
        actors.МАНИФЕСТ = pathlib.Path(дано.манифест)
    миры = [м for м in actors.миры_деятелей()
            if м[1].exists() and any(actors.падежи_лиц(я) for я in м[2])]
    if not миры:
        print("РЫНОК ПАДЕЖА ЛИЦА ОТКАЗ: обход пуст — ни одного мира деятелей с падежами лица")
        return 2

    if дано.цена:
        n, судимых, обвинений, примеры = цена_на_другой_половине()
        print(f"ЦЕНА НА ДРУГОЙ ПОЛОВИНЕ: куплено {n}, судимых строк {судимых}, "
              f"ОБВИНЕНИЙ {sum(обвинений.values())} в {len(обвинений)} мирах")
        for имя, язык, перед, форма, тело in примеры:
            print(f"    [{имя}/{язык}] «{перед} {форма}» ← {тело}")
        return 0

    рынок = actors.собрать_рынок_падежа()
    куплено = actors.куплены_падежи(рынок)
    языков = len({я for я, _ in куплено})
    if дано.собрать:
        actors.САЙДКАР_ПАДЕЖА.write_text("\n".join(строки_полки(куплено, рынок)) + "\n",
                                         encoding="utf-8")
        print(f"РЫНОК ПАДЕЖА ЛИЦА СОБРАН: слов перед лицом {len(куплено)} на {языков} языках, "
              f"миров деятелей с падежами {len(миры)} → {actors.САЙДКАР_ПАДЕЖА.name}")
        return 0

    было = actors.куплен_падеж()
    расхождения = sorted(set(было) ^ set(куплено)) + sorted(
        к for к in set(было) & set(куплено) if было[к] != куплено[к])
    if дано.подробно:
        for язык, слово in расхождения[:40]:
            print(f"    {язык} · {слово}: полка {sorted(было.get((язык, слово), ()))} "
                  f"≠ свод {sorted(куплено.get((язык, слово), ()))}")
    проба = _проба()
    слово_пробы = ("пробы нет: полка пуста" if проба is None else
                   f"проба {проба[0]}/{проба[1]} поймано, ложных {проба[2]}")
    поза = "FAIL" if len(расхождения) > РАСХОЖДЕНИЙ_РУБЕЖ else "PASS"
    print(f"РЫНОК ПАДЕЖА ЛИЦА {поза}: расхождений полки со сводом {len(расхождения)} "
          f"(рубеж {РАСХОЖДЕНИЙ_РУБЕЖ}); слов перед лицом {len(куплено)} на {языков} языках, "
          f"миров деятелей с падежами {len(миры)}, {слово_пробы}")
    return 1 if len(расхождения) > РАСХОЖДЕНИЙ_РУБЕЖ else 0


if __name__ == "__main__":
    sys.exit(main())
