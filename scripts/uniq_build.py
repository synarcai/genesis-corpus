#!/usr/bin/env python3
"""[СВОД БЕЗ ПОВТОРОВ] — тот же свод, из которого вычеркнуты ТОЧНЫЕ копии.

Проба, названная d5 сильнее её же выгоды (04.09): если меры на этом своде
совпадут с мерами на полном, доказано, что половина свода НЕ ПОКУПАЕТСЯ, и
это утверждение о природе покупки, а не о времени сборки. Если разойдутся —
повтор покупается, и тогда он закон, а не долг. Экономия веса (53 %) —
побочная выгода, а не цель.

ТРИ УСЛОВИЯ ЧИСТОТЫ ПРОБЫ, названные d5 и соблюдённые здесь:
  · дедупликация ВНУТРИ МИРА, не по своду: строка, встреченная в двух разных
    мирах, есть совпадение миров, а не повтор пасса, и резать её значило бы
    менять состав мира;
  · ПОРЯДОК СТРОК СОХРАНЁН: страница есть единица организма, и перестановка
    меняет соседства — вычёркивается только вторая и следующие копии, первая
    стоит на своём месте;
  · ОТЧЁТ ПО МИРАМ рядом со сводом: расхождение мер, если оно будет, должно
    быть отнесено к конкретному миру, а не к своду вообще.

Швы миров те же, что у полного свода: сборка есть функция уже судимых миров.

    python3 scripts/uniq_build.py [--цель datasets/GENESIS-UNIQ.txt]
                                  [--отчёт reports/UNIQ-CUTS.tsv]
"""
import argparse
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
from gen_genesis_full import куски_сборки, записать_размер  # noqa: E402
from layer import SEAM  # noqa: E402


def собрать(сборка="full"):
    куски, перепись = [], []
    for имя, тело in куски_сборки(сборка):
        видано, свои = set(), []
        было = 0
        for с in тело.splitlines():
            if not с.strip():
                continue
            было += 1
            if с in видано:
                continue          # вторая копия — вычеркнута, первая на месте
            видано.add(с)
            свои.append(с)
        if свои:
            куски.append("\n".join(свои))
            перепись.append((имя, было, len(свои)))
    return SEAM.join(куски) + "\n", перепись


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--цель", default="datasets/GENESIS-UNIQ.txt")
    ап.add_argument("--отчёт", type=pathlib.Path, default=КОРЕНЬ / "reports" / "UNIQ-CUTS-2026-09-04.tsv")
    а = ап.parse_args()
    тело, перепись = собрать()
    путь = КОРЕНЬ / а.цель
    путь.write_text(тело, encoding="utf-8")
    строк = sum(n for _, _, n in перепись)
    было = sum(b for _, b, _ in перепись)
    записать_размер(а.цель, len(тело.encode("utf-8")), строк)
    ряды = ["мир\tбыло\tстало\tсрезано\tдоля среза"]
    for имя, b, n in sorted(перепись, key=lambda р: -(р[1] - р[2])):
        ряды.append(f"{имя}\t{b}\t{n}\t{b - n}\t{(b - n) / b:.2f}")
    а.отчёт.write_text("\n".join(ряды) + "\n", encoding="utf-8")
    print(f"СВОД БЕЗ ПОВТОРОВ: written {а.цель}: {len(тело.encode('utf-8'))} bytes, {строк} строк "
          f"(было {было}, срезано {было - строк} — {100 * (было - строк) // max(1, было)} %), "
          f"миров {len(перепись)}; отчёт по мирам: {а.отчёт.relative_to(КОРЕНЬ)}")
    верх = sorted(перепись, key=lambda р: -(р[1] - р[2]))[:6]
    print("  больше всего срезано: " + ", ".join(f"{и} {b - n}" for и, b, n in верх))
    return 0


if __name__ == "__main__":
    sys.exit(main())
