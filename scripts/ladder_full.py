#!/usr/bin/env python3
"""[ЛЕСТНИЦА ПОЛНА] — школьная сборка отстала от свода на шестьдесят восемь миров.

    СБОРКА, В КОТОРУЮ НОВЫЙ ДОМ НЕ ВПИСАН, МОЛЧИТ О НЁМ НЕ ПО РЕШЕНИЮ, А ПО ЗАБЫВЧИВОСТИ,
    И МОЛЧАНИЕ ЭТО НЕОТЛИЧИМО ОТ ВЫБОРА.

ПОВОД, ЗАМЕРЕННЫЙ 12.09. Манифест объявляет школьную сборку следствием манифеста, а не
решением сборщика: «every world that declares "school" in its `assemblies`, in manifest
order — the ladder a learner walks before the whole corpus». Но объявляют её сами миры, и
шестьдесят восемь миров показов не объявили ничего. Среди них — ЯДРО КОРПУСА
`school_biling_v2c`, самый большой мир показов свода: из 6622 его строк в школьном своде
нашлось 546, и те лишь по совпадению с другими мирами.

    ЛЕСТНИЦА, НЕ СОДЕРЖАЩАЯ ЯДРА, ЕСТЬ ЛЕСТНИЦА БЕЗ ПЕРВОЙ СТУПЕНИ.

ЗАКОН БЫЛ УЖЕ ВЫВЕДЕН — И НЕ ПЕРЕНЕСЁН. `scripts/strat_slice.py` (07.09) сказал о срезе
ровно то, что нужно было сказать и о лестнице:

    СРЕЗ, В КОТОРОМ НЕТ КОНСТРУКЦИИ, НЕ ГОВОРИТ О НЕЙ НИЧЕГО — ни хорошего, ни плохого.
    Отбор миров ЦЕЛИКОМ выбрасывает конструкции пачками.

Довод тот же, сборка другая — и не перешёл сам:

    ЗАКОН, ВЫВЕДЕННЫЙ ДЛЯ ОДНОГО СРЕЗА, НЕ ПЕРЕХОДИТ НА ДРУГОЙ САМ.

ЧТО ПРИБОР ТРЕБУЕТ. Не того, чтобы всякий мир был школьным, — а того, чтобы мир вне
лестницы был вне неё ПО ОБЪЯВЛЕННОЙ ПРИЧИНЕ. Причина объявляется рукой того, кто знает
предмет, ибо школьность мира не выводится из его строк никаким счётом:

    ИЗ «ЗДЕСЬ СЧИТАЮТ» НЕ СЛЕДУЕТ «ЭТО ДЛЯ ШКОЛЫ», КАК ИЗ «ЗДЕСЬ ЕСТЬ БУКВЫ» НЕ СЛЕДУЕТ
    «ЭТО ДЛЯ ЧТЕНИЯ».

ЧЕГО ПРИБОР НЕ ДЕЛАЕТ. Он не судит о ПОРЯДКЕ ступеней и не спрашивает, вовремя ли мир
стои́т в лестнице. Лестница по манифесту идёт в порядке манифеста, и порядок этот —
предмет другого разговора.

    python3 scripts/ladder_full.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import collections
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
ЛЕСТНИЦА = "school"

# РУБЕЖ-ДОЛГА: УМОЛЧАВШИХ_РУБЕЖ = 0
#
# Рубеж есть ПОЛ, а не поблажка: замер 12.09 нашёл шестьдесят восемь умолчавших миров,
# и все шестьдесят восемь разобраны в тот же час — сорок шесть вписаны в лестницу,
# двадцать два получили причину. Прибор поставлен, чтобы шестьдесят девятый нашёлся
# в час своего рождения, а не через семь суток.
УМОЛЧАВШИХ_РУБЕЖ = 0

# ПРИЧИНЫ, ПО КОТОРЫМ МИР СТОИ́Т ВНЕ ЛЕСТНИЦЫ, ОБЪЯВЛЕНЫ ПОИМЁННО.
#
# Разряды причин суть не ярлыки, а ответы на один вопрос: чего в этом мире нет из того,
# ради чего лестницу проходят? Мир об устройстве агента учит не счёту, а себе; мир о
# разметке учит не языку счёта, а записи; мир о программе учит не арифметике, а машине.
ВНЕ_ЛЕСТНИЦЫ = {
    # ОБ ОРГАНИЗМЕ САМОМ: читатель на лестнице ещё не предмет своего же чтения.
    "selfmeasure": "об организме самом — датированный самоотчёт, а не урок счёта",
    "selfmodelforms": "об организме самом — предсказать себя и свериться с делом",
    "valence": "об организме самом — знак и сила чувства, а не величина мира",
    # РАЗМЕТКА ДОКУМЕНТА: запись о записи, и счёта в ней нет.
    "markdown": "разметка документа — тридцать две конструкции записи, а не счёта",
    "doctree": "разметка документа — ссылка как ребро дерева, разрешаемая обходом",
    "md_latex": "разметка документа — одна вещь в двух поверхностях записи",
    "md_structures": "разметка документа — строение разметки, сказанное словом",
    # ПРОГРАММИРОВАНИЕ И ЕГО ТЕОРИЯ: машина прежде числа сбивает порядок лестницы.
    "prog": "программирование — программа как утверждение о входе и выходе",
    "programs": "программирование — программа как утверждение о своём итоге",
    "algorithms": "программирование — действие над списком, а не над числом",
    "eng_proof": "программирование — инженерная запись кодом и речью",
    "compsci": "теория вычисления — цена знака в битах и энтропия",
    "cybernetics": "теория управления — закон необходимого разнообразия",
    # ФИЗИКА СВЕРХ СЧЁТА: величина здесь несёт закон, которого лестница не даёт.
    "physlaws": "физика сверх счёта — закон сохранения и размерность",
    # УСТРОЙСТВО АГЕНТА (05.09—06.09): рынок, кованный под органы, а не под ученика.
    "toolforms": "устройство агента — состояние до, вызов, состояние после",
    "planforms": "устройство агента — задача, шаги, проверяемый конец",
    "verifyforms": "устройство агента — утверждение, проверка, вердикт",
    "episodeforms": "устройство агента — лента действий над одним состоянием",
    "mandateforms": "устройство агента — стоящее правило против приказа",
    "personforms": "устройство агента — тот же факт другим голосом",
    "summaryforms": "устройство агента — что сжатая запись хранит и что потеряла",
    "actturn": "устройство агента — собственный ход организма в диалоге",
}


def миры(манифест):
    тело = json.loads(манифест.read_text(encoding="utf-8"))
    return [м for м in тело.get("worlds", ()) if м.get("text") == "shows"]


def main():
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
    if not манифест.is_file():
        print(f"ЛЕСТНИЦА ПОЛНА ОТКАЗ: манифеста нет — {манифест}")
        return 2
    свод = миры(манифест)
    if not свод:
        print("ЛЕСТНИЦА ПОЛНА ОТКАЗ: миров показов нет, спрашивать не о ком")
        return 2
    подробно = "--подробно" in sys.argv
    в_лестнице, умолчали, названы = [], [], []
    for м in свод:
        имя = м["name"]
        if ЛЕСТНИЦА in (м.get("assemblies") or ()):
            в_лестнице.append(имя)
            if имя in ВНЕ_ЛЕСТНИЦЫ:
                умолчали.append((имя, "объявлен и в лестнице, и в причинах — противоречие"))
        elif имя in ВНЕ_ЛЕСТНИЦЫ:
            названы.append(имя)
        else:
            умолчали.append((имя, "вне лестницы и без причины"))
    # ПРИЧИНА БЕЗ МИРА ЕСТЬ ОБЕЩАНИЕ, А НЕ ДОГОВОР: имя, ушедшее из манифеста, обязано
    # уйти и отсюда, иначе таблица растёт призраками.
    живые = {м["name"] for м in свод}
    призраки = sorted(и for и in ВНЕ_ЛЕСТНИЦЫ if и not in живые)
    for и in призраки:
        умолчали.append((и, "причина объявлена, а мира такого нет"))
    if подробно:
        разряды = collections.Counter(п.split(" — ")[0] for п in ВНЕ_ЛЕСТНИЦЫ.values())
        for р, n in разряды.most_common():
            print(f"  вне лестницы по причине «{р}»: {n}")
    for имя, беда in умолчали[:8]:
        print(f"  {имя}: {беда}")
    поза = "PASS" if len(умолчали) <= УМОЛЧАВШИХ_РУБЕЖ else "FAIL"
    print(f"ЛЕСТНИЦА ПОЛНА {поза}: умолчавших миров {len(умолчали)} "
          f"(рубеж {УМОЛЧАВШИХ_РУБЕЖ}); в лестнице {len(в_лестнице)}, "
          f"вне по объявленной причине {len(названы)}, миров показов {len(свод)}")
    return 0 if len(умолчали) <= УМОЛЧАВШИХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
