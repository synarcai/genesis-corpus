def роды_суда(модуль, суд):
    """[(имя рода, образец)] — якорные образцы верхнего уровня.

    ОДИН ОБРАЗЕЦ ЕСТЬ ОДИН РОД, СКОЛЬКО БЫ ИМЁН ЕМУ НИ ДАЛИ. Суд
    строения держит свои образцы и по именам, и разом в кортеже
    `ПРАВИЛА`; считать их дважды значило бы удвоить знаменатель тому,
    кто свод образцов у себя завёл, и не тронуть того, кто не завёл.
    Отбор идёт по ТОЖДЕСТВУ ОБРАЗЦА, а имя берётся прямое, если оно
    есть, и составное («ФОРМЫ[3]») — если образец живёт только в своде.
    """
    прямо = {id(ч): и for и, ч in vars(модуль).items()
             if isinstance(ч, re.Pattern)}
    найдено = []

    def обойти(имя, что, глубина=0):
        """Образцы, где бы они ни лежали: список, словарь, список кортежей.

        ДОМ КЛАДЁТ ОБРАЗЦЫ ПО-СВОЕМУ, И ЭТО ЕГО ПРАВО. Прибор, знавший лишь
        два уровня, не видел образцов дома страниц действия («язык → список
        троек») и звал его мир читаемым тремя чужими родами при четырёх
        тысячах строк — то есть мерил не то, что судится.
        """
        if isinstance(что, re.Pattern):
            найдено.append((прямо.get(id(что), имя), что))
            return
        if глубина >= 4:
            return
        if isinstance(что, dict):
            for к, в in что.items():
                обойти(f"{имя}[{к}]", в, глубина + 1)
        elif isinstance(что, (tuple, list)):
            for место, э in enumerate(что):
                обойти(f"{имя}[{место}]", э, глубина + 1)

    for имя, что in vars(модуль).items():
        обойти(имя, что)
    # БУКВА ПЕРЕМЕННОЙ НЕ ДЕЛАЕТ НОВОГО РОДА (03.09): универсалия, сказанная
    # через «k», «n» и «m», есть ОДНА форма показа, и суд читает её тремя
    # образцами лишь потому, что буква подставляется в шаблон целиком.
    # Считать их тремя родами значило бы утроить знаменатель тому, кто
    # исполнил закон «дыра есть то, что варьируется».
    видано, видано_текстом, вон = set(), set(), []
    for имя, о in найдено:
        if id(о) in видано:
            continue
        ключ = БУКВА_ПЕРЕМЕННОЙ.sub("𝑣", о.pattern)
        if ключ in видано_текстом:
            continue
        # ЯКОРЬ С ОБЕИХ СТОРОН И ЕСТЬ ПРИЗНАК РОДА: образец, ловящий
        # кусок строки, описывает материал, а не форму показа.
        if not (о.pattern.startswith("^") and о.pattern.endswith("$")):
            continue
        видано.add(id(о))
        видано_текстом.add(ключ)
        вон.append((f"{суд}.{имя}", о))
    return вон


def все_роды():
    """(роды, судов всего, судов с родами) — обходом каталогов.

    СОСТАВ БЕРЁТСЯ ОБХОДОМ, А НЕ СПИСКОМ: список судов уже дважды
    расходился с каталогом в этом доме, и оба раза его чинили обходом.
    Суд, не загрузившийся или отказавший о себе, просто не даёт родов,
    и его отсутствие видно числом.
    """
    вон, всего, своих = [], 0, 0
    # РОД ОБЪЯВЛЕН ТАМ, ГДЕ ОН СУДИТСЯ, — И ТОЛЬКО ТАМ. Каталог
    # `scripts` держит и судей («claims_court», «prose_court»), и МЕРЫ
    # («lexicon_reach», «coverage»), а у меры образец описывает форму,
    # которую она СЧИТАЕТ, а не род, который она судит. Первый прогон
    # выдал пласту суахили единственный род `lexicon_reach.СТРОКА_СЛОВ`
    # — то есть приписал миру род от прибора, ничего о его истине не
    # решающего. Отбор идёт по здешнему имени судьи, `*_court`, тому
    # же, каким палата собирает свой состав.
    # РОД ОБЪЯВЛЕН ТАМ, ГДЕ ОН СУДИТСЯ, — А У ДОМА ЭТО САМ ДОМ (03.09). Суды
    # новых миров (два рода, счётные единицы, истории с мерой, страницы
    # действия) не держат образцов у себя: они зовут дом, а дом объявляет
    # свои образцы полем «ОБРАЗЦЫ». Прибор, читавший только каталог судов,
    # видел их миры чужими родами — и звал немым то, чего не видел. Из домов
    # берётся ТОЛЬКО это поле: прочие выражения дома суть его материал.
    for каталог, образец in (("courts", "*.py"), ("scripts", "*_court.py"),
                             ("tools", "*.py")):
        for путь in sorted((КОРЕНЬ / каталог).glob(образец)):
            if путь.name == pathlib.Path(__file__).name:
                continue
            try:
                модуль = importlib.import_module(путь.stem)
            except (Exception, SystemExit):
                continue
            if каталог == "tools":
                если = getattr(модуль, "ОБРАЗЦЫ", None)
                if если is None:
                    continue
                свои = роды_суда(type("Дом", (), {"ОБРАЗЦЫ": если}), путь.stem)
            else:
                свои = роды_суда(модуль, путь.stem)
            if каталог == "courts":
                всего += 1
                своих += bool(свои)
            вон += свои
    return вон, всего, своих


def вопросный():
    """Признак вопроса — ТОТ ЖЕ, что у соседнего прибора, а не второй.

    Знак берётся из `ask_reach`, и вопросные слова тоже: два прибора
    одной поверхности, разошедшиеся в том, что считают вопросом, дали
    бы два несравнимых числа об одном предмете. Пустой список слов
    оставляет признак знаковым — так же, как у соседа.
    """
    слова = ask_reach.вопросные_слова()
    словом = (re.compile(r"\b(?:%s)\b" % "|".join(
        re.escape(с) for с in sorted(слова, key=len, reverse=True)))
        if слова else None)

    def разобрать(строка):
        """(вопрос ли, ответная часть) — хвост после последнего знака."""
        места = [i for i, з in enumerate(строка) if з in ask_reach.ЗНАКИ]
        if места:
            return True, строка[места[-1] + 1:].strip()
        if словом is not None and словом.search(строка.lower()):
            return True, ""
        return False, строка

    return разобрать, len(слова)


def по_манифесту(мир, строк, вопросов):
    """([акт], решение) — роды мира, чей суд родов не объявил.

    РЕШАЕТСЯ ТОЛЬКО ТО, ЧТО РЕШАЕТСЯ ТОЧНО. Мир, у которого вопросна
    КАЖДАЯ строка, спрашивает обо всём, что показывает, каким бы ни
    было деление на акты; мир, у которого не вопросна НИ ОДНА, не
    спрашивает ни о чём. Между этими двумя случаями приписать вопрос
    отдельному акту нечем — и прибор говорит «не разрешено», а не
    выбирает чашу.
    """
    акты = list(мир.get("act") or ())
    if not строк or not акты:
        return акты, НЕ_РАЗРЕШЕНО
    if вопросов == 0:
        return акты, НЕТ
    if вопросов == строк:
        return акты, ЕСТЬ
    return акты, НЕ_РАЗРЕШЕНО


def обойти(миры, образцы, разобрать):
    """[(имя, строк, без рода, роды, роды с вопросом, вопросов)]."""
    кэш = {}

    def прочесть(текст):
        если = кэш.get(текст)
        if если is None:
            если = tuple(и for и, о in образцы if о.match(текст))
            кэш[текст] = если
        return если

    вон = []
    for мир in миры:
        путь = genesis._resolve(мир["file"])
        if not путь.is_file():
            continue
        свои, с_вопросом = set(), set()
        строк = без_рода = вопросов = 0
        поток = путь.read_text(encoding="utf-8", errors="replace")
        for строка in поток.splitlines():
            текст = строка.strip()
            if not текст:
                continue
            строк += 1
            это_вопрос, ответ = разобрать(текст)
            # ОТВЕТНАЯ ЧАСТЬ ПЕРВИЧНА, ЦЕЛАЯ СТРОКА — ЗАПАСНОЙ ХОД.
            # Суды объявляют род ДВУМЯ разными способами, и оба живут в
            # доме. Одни держат вопросную обёртку отдельным образцом, а
            # содержание — своим («уровень узла stone равен 3»); другие
            # объявляют вопрос и ответ ОДНИМ образцом («ist 56 eine
            # Primzahl? nein: 56 = 2 × 28»). Мера, примерявшая образцы
            # только к хвосту, первым отвечала верно, а вторым ставила
            # ноль: три вопросные лестницы — миры, у которых вопросна
            # КАЖДАЯ строка, — вышли с нулём родов, имеющих вопрос.
            # Оттого зачёт идёт по ответной части, а где её не читает
            # НИКТО — по целой строке. Вопросная обёртка при этом сама
            # родом не становится: её строку уже забрал род ответа.
            # РОД, ЧИТАЮЩИЙ ВСЮ ВОПРОСНУЮ СТРОКУ, ТОЖЕ ЕЁ РОД (03.09): суд,
            # объявивший вопрос и ответ одним образцом («is it true that all
            # odd numbers are prime? no: 9 is odd and 9 = 3 × 3»), терял
            # вопрос, когда хвост ответа читал чужой род (связка copula:
            # «no: 9 is odd and …»), — зачёт идёт и по хвосту, и по целой
            # строке; строка без рода — та, которую не читает никто.
            если = прочесть(ответ) if ответ else ()
            целиком = прочесть(текст)
            если = если + tuple(и for и in целиком if и not in если)
            без_рода += not если
            свои.update(если)
            if это_вопрос:
                вопросов += 1
                с_вопросом.update(если)
        вон.append((мир, строк, без_рода, свои, с_вопросом, вопросов))
    return вон


def акты_текст(акты):
    return ", ".join(акты) if акты else "не объявлены"


def main():
    if "--manifest" in sys.argv:
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        м = genesis.manifest()
    except genesis.Unreadable as беда:
        print(f"ШИРОТА ВОПРОСА ОТКАЗ: {беда}")
        return 2
    миры = [в for в in (м.get("worlds") or []) if в.get("text") == "shows"]
    if not миры:
        print("ШИРОТА ВОПРОСА ОТКАЗ: миров показов не объявлено")
        return 2
    образцы, судов, судов_с_родами = все_роды()
    if not образцы:
        print("ШИРОТА ВОПРОСА ОТКАЗ: суды не объявили ни одного рода")
        return 2
    разобрать, слов = вопросный()

    итоги = обойти(миры, образцы, разобрать)
    if not итоги:
        print("ШИРОТА ВОПРОСА ОТКАЗ: обход пуст, мерить нечего")
        return 2

    строка_всего = без_рода_всего = 0
    родов = с_вопросом = 0
    решением = collections.Counter()
    актов = collections.Counter()
    таблица, заказ = [], []
    для_манифеста = []
    # РОД, ЧЕЙ ФАКТ СПРАШИВАЕТ СОСЕДНИЙ РОД ТОГО ЖЕ СУДА, НЕ НЕМ (03.09).
    # Дом единиц говорит парадигму («поездка длится 3 дня.») и тут же
    # спрашивает её («поездка длится 3 дня. сколько длится поездка? 3 дня.»),
    # и вопросный образец СТРОИТСЯ ИЗ утвердительного — он начинается им.
    # Мера, считавшая парадигму немой при спрошенном факте, звала бы немым и
    # того, кто закон исполнил.
    текст_рода = {и: о.pattern for и, о in образцы}

    def спрошен_соседом(род, вопросные):
        тело = текст_рода.get(род, "")[1:-1]
        if len(тело) < 12:
            return False
        return any(текст_рода.get(в, "")[1:].startswith(тело) for в in вопросные if в != род)

    for мир, строк, без_рода, свои, с_воп, вопросов in итоги:
        соседом = {р for р in свои - с_воп if спрошен_соседом(р, с_воп)}
        if соседом:
            с_воп = set(с_воп) | соседом
        строка_всего += строк
        без_рода_всего += без_рода
        if свои:
            родов += len(свои)
            с_вопросом += len(с_воп)
            доля = 100 * len(с_воп) // len(свои)
            таблица.append((доля, мир["name"], len(свои), len(с_воп),
                            строк, без_рода))
            немые = sorted(свои - с_воп)
            if немые:
                заказ.append((доля, мир["name"], немые))
            continue
        акты, решение = по_манифесту(мир, строк, вопросов)
        решением[решение] += 1
        актов[решение] += len(акты)
        для_манифеста.append((решение, мир["name"], строк, вопросов, акты))

    таблица.sort()
    for доля, имя, всего, воп, строк, без in таблица:
        print(f"  {имя:<24}{всего:>5} родов {воп:>4} с вопросом "
              f"{доля:>4}%   строк {строк:>6}, без рода {без:>6}")
    всё = "--всё" in sys.argv
    заказ.sort()
    for доля, имя, немые in заказ:
        сколько = len(немые) if всё else ИМЁН
        хвост = "" if всё or len(немые) <= ИМЁН else \
            f" … и ещё {len(немые) - ИМЁН}"
        print(f"  НЕТ ВОПРОСА {имя}: {', '.join(немые[:сколько])}{хвост}")
    for решение, имя, строк, вопросов, акты in sorted(для_манифеста):
        print(f"  РОДЫ ОТ МАНИФЕСТА {имя}: акты {акты_текст(акты)} — "
              f"вопрос {решение} (строк {строк}, вопросных {вопросов})")

    доля = 100 * с_вопросом // родов if родов else 0
    без_вопроса = родов - с_вопросом + актов[НЕТ]
    поза = ("ОТЧЁТ" if БЕЗ_ВОПРОСА_РУБЕЖ is None else
            "PASS" if без_вопроса <= БЕЗ_ВОПРОСА_РУБЕЖ else "FAIL")
    # ЧИСЛО РУБЕЖА И ЧИСЛО ОТЧЁТА СУТЬ ОДНО ЧИСЛО. Мера, стерегущая
    # одну величину и печатающая другую, читается неверно всяким, кто
    # не открыл её кода.
    print(f"ШИРОТА ВОПРОСА {поза}: {с_вопросом} из {родов} родов суда "
          f"имеют вопросную поверхность ({доля}%); БЕЗ ВОПРОСА "
          f"{без_вопроса} (рубеж {БЕЗ_ВОПРОСА_РУБЕЖ}) — от судов "
          f"{родов - с_вопросом}, от манифеста {актов[НЕТ]}; роды "
          f"объявлены судами ({судов_с_родами} из {судов}, образцов "
          f"{len(образцы)}, вопросных слов от пакетов {слов}); от "
          f"манифеста {sum(актов.values())} актов в "
          f"{sum(решением.values())} мирах — с вопросом {актов[ЕСТЬ]}, "
          f"без {актов[НЕТ]}, не разрешено {актов[НЕ_РАЗРЕШЕНО]}; строк "
          f"без рода {без_рода_всего} из {строка_всего}")
    if БЕЗ_ВОПРОСА_РУБЕЖ is None:
        return 0
    return 0 if без_вопроса <= БЕЗ_ВОПРОСА_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
