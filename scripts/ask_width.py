#!/usr/bin/env python3
"""[ШИРОТА ВОПРОСА] — на скольких РОДАХ мира стоит вопрос, а не на одном.

СОСЕДНИЙ ПРИБОР МЕРИТ НАЛИЧИЕ И САМ ОБЪЯВЛЯЕТ СВОЮ ГРАНИЦУ: «мир,
спрашивающий об одном роде из десяти, покажет здесь ненулевую долю».
Эта дыра и есть предмет здешнего замера. Мир показывает вложенность,
транзитивность, классы, порядок и путь; если вопрос стоит только на
уровне узла, организм выучит отвечать об уровне и молчать о четырёх
остальных — а первая мера назовёт такой мир говорящим.

РОД БЕРЁТСЯ ОТТУДА, ГДЕ ОН СУДИТСЯ, А НЕ ОТТУДА, ГДЕ О НЁМ ГОВОРЯТ.
Суд разбирает строки ОБРАЗЦАМИ, и всякий образец есть объявление рода,
сделанное рукой, которая за этот род отвечает: `УРОВЕНЬ`,
`НЕ_ТРАНЗИТИВНО`, `НЕТ_НАИБОЛЬШЕГО`, `ОБХОД_НЕ_ДОШЁЛ`. Ни манифест, ни
проза, ни кластеризация строк такого имени не дают: первый грубее
(один `act` покрывает десяток родов), последняя есть гадание, выдающее
себя за замер.

ОБРАЗЕЦ ЕСТЬ РОД, ЕСЛИ ОН ПРИВЯЗАН К ЦЕЛОЙ СТРОКЕ. Признак взят
структурный, а не списочный: `^…$` значит «эта форма есть форма
ПОКАЗА», а незакреплённый кусок («\\d+», «[а-яё]+») есть материал
образца, а не род. Замерено 02.09: якорных образцов 1135 у 49 судов
из 58; девять не дают ни одного — они разбирают строку не образцом
(арифметика режет её на предложения, согласование ищет счёт внутри,
пласт языка судится словарём пакета), — и это названо числом в итоге.

ВОПРОС СТОИТ НА РОДЕ, ЕСЛИ ТОТ ЖЕ ОБРАЗЕЦ ЧИТАЕТ ХВОСТ ВОПРОСНОЙ
СТРОКИ. Вопросный показ здешнего дома есть ПРИСТАВКА К ОТВЕТУ («на
каком уровне стоит узел stone? уровень узла stone равен 3.»), и потому
род вопроса есть род его ответа. Оттого образцы примеряются не к
строке, а к её ОТВЕТНОЙ ЧАСТИ — всему, что стоит после последнего
вопросного знака, — и вопросная обёртка сама родом не становится: её
образец не читает ни одной ответной части и потому не читает ничего.

ГДЕ СУД РОДОВ НЕ ОБЪЯВИЛ, БЕРЁТСЯ МАНИФЕСТ — И РЕШЕНИЕ ТРОИТСЯ.
Двадцать шесть миров не получают от судов ни одного рода: двадцать
пять языковых пластов (их судит СЛОВАРЬ пакета, а не форма строки) и
плотная линейка. Их роды берутся из поля `act`, объявленного у всех
миров, но поле это ГРУБЕЕ образца — один акт покрывает десяток родов, —
и приписать вопрос отдельному акту нечем. Потому решается лишь то, что
решается ТОЧНО:

    ВСЕ строки мира вопросные → вопрос стоит на КАЖДОМ акте;
    НИ ОДНА строка не вопросная → вопроса нет НИ НА ОДНОМ;
    иначе → НЕ РАЗРЕШЕНО, и это долг прибора, названный числом.

Неразрешённое не зачитывается ни в «с вопросом», ни в «без вопроса»:
мера, прячущая своё незнание в любую из двух чаш, лжёт о себе.

ЧЕГО ЭТОТ ПРИБОР НЕ МЕРИТ, И ЭТО ОБЪЯВЛЕНО ПРЯМО:
    ХОРОШ ЛИ ВОПРОС — только есть ли он на роде. Вопрос, спрашивающий
        не о том, что в ответе, здесь неотличим от честного; это ловит
        суд мира, у которого вопрос есть приставка к ответу;
    ВЕРЕН ЛИ ОТВЕТ — истину считают суды, здесь считают ШИРОТУ;
    СКОЛЬКО вопросов на роде — один вопрос и тысяча стоят одинаково:
        мера отвечает «есть ли», а не «много ли»;
    ИМЯ РОДА НЕ ЛУЧШЕ ТОГО, КАК НАЗВАЛ ЕГО СУД. Суд, давший образцу
        имя, отдаёт читаемый заказ («relation_court.НЕ_ТРАНЗИТИВНО»);
        суд, спрятавший образцы в один кортеж, отдаёт номер
        («metalang_court.ПРАВИЛА[104]»). Прибор имён не сочиняет: он
        берёт прямое имя, где оно есть, и место в своде — где нет;
    РОДЫ, КОТОРЫХ НЕ ОБЪЯВИЛ НИКТО — строка, не прочтённая ни одним
        якорным образцом, не принадлежит ни одному роду и в знаменатель
        не входит. Таких строк 111 059 из 200 880, и число это стоит
        рядом с итогом и в каждой строке отчёта, ибо МЕРА ОБЯЗАНА
        НАЗЫВАТЬ СВОЙ ЗНАМЕНАТЕЛЬ. Оттого и доля родов не есть доля
        строк: пласт русского языка даёт сто процентов на двух родах,
        прочтя пять строк из трёх тысяч четырёхсот, и колонка «без
        рода» говорит это прямо.
"""
