#!/usr/bin/env python3
"""[ТЕЧЬ ПОЛОСЫ] — стои́т ли такт меры в самом своде, на котором учат читателя.

МЕРА, ЧЬИ ТАКТЫ ЖИВУТ В УЧЕБНИКЕ, МЕРИТ ПАМЯТЬ, А НЕ ПОНИМАНИЕ. Полоса SVAMP есть
внешняя мера читателя: 726 тактов, писанных не нами. Если такт полосы стои́т в своде,
читатель отвечает на него узнаванием, и число полосы говорит о заучивании.

    ЧИТАТЕЛЬ, ВИДЕВШИЙ ВОПРОС МЕРЫ В УЧЕБНИКЕ, ОТВЕЧАЕТ НА НЕГО ПАМЯТЬЮ. Такая мера
    зелена вдвойне: она и завышена, и нечувствительна — рост её не говорит о росте
    понимания, а падение не говорит о его убыли.

ПОВОД (07.09): школьный срез, на котором снимались все полосы, не содержит 43 % свода —
93 мира, 157 702 строки, — и среди пропавших `svamp`, тот самый мир, чьи такты полоса и
меряет. Восьмая же точка куётся на ПОЛНОМ своде, где `svamp` есть. Вопрос встал прямо:
не окажется ли мера на точке замером памяти?

ДВЕ ПРОБЫ, И ОБЕ ОБЪЯВЛЕНЫ:
    ДОСЛОВНАЯ — самое длинное предложение такта ищется в своде как есть. Совпадение
        значит, что читатель видел эти самые слова.
    СКЕЛЕТОМ — числа такта заменяются на «#», и скелет ищется среди скелетов миров
        задач. Совпадение значит, что читатель видел ФОРМУ вопроса с иными числами;
        это не течь, но это стои́т знать: форма, виденная тысячу раз, отвечается
        рамкой, а не счётом.

ЗАМЕР 07.09 (полоса t7_svamp_s1.jsonl 726 тактов против GENESIS-FULL 32 549 388 байт):
дословных совпадений ОДНО, совпадений скелета НОЛЬ. Единственное — «the recipe calls
for 12 cups of flour and 5 cups of sugar» — есть совпадение ФАКТА, а не вопроса: мир
`svamp` пишет эту фразу восемью разными парами чисел (35/3, 18/11, 20/8…), одна выпала
12/5, и вопрос при ней иной («how many more cups of flour than sugar?» против «how many
cups of flour did she put in?»), и ответ иной (7 против 10).

    СОВПАДЕНИЕ ФАКТА НЕ ЕСТЬ ТЕЧЬ: течёт ВОПРОС С ОТВЕТОМ, а не обстановка задачи.
    Факт «в рецепте 12 чашек муки» — общее место, и запретить его значило бы запретить
    корпусу говорить о том же мире, о чём говорит мера.

    python3 scripts/bench_leak.py [--полоса ПУТЬ] [--свод ПУТЬ] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --полоса no-such-bench
import argparse
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ПОЛОСА = pathlib.Path("/Users/taaliman/projects/oldman/synarcai/omega/bench/suites/t7_svamp_s1.jsonl")

# РУБЕЖ-ДОЛГА: ТЕЧЕЙ_РУБЕЖ = 0
#
# НОЛЬ ЕСТЬ ПОЛ, А НЕ ПОТОЛОК: дом, написавший страницу словами такта меры, роняет
# прибор в тот же час. Совпадение ФАКТА (обстановки задачи) течью не считается и в это
# число не входит — считается совпадение ВОПРОСА С ОТВЕТОМ.
ТЕЧЕЙ_РУБЕЖ = 0

_ЦИФРЫ = re.compile(r"\d+")
_КОНЕЦ = re.compile(r"[.?!]")
МИРЫ_ЗАДАЧ = ("genesis_svamp.txt", "genesis_gsmwide.txt", "genesis_gsmlex.txt",
              "genesis_gsmforms.txt", "genesis_verbal.txt", "genesis_items.txt")


def ожидания(д):
    """Поверхности ожидаемого ответа такта — то, что обязано совпасть при течи.

    ОТКАЗ ОЖИДАНИЙ НЕ ИМЕЕТ: такт, ждущий отказа, не может протечь от строки, дающей
    ответ, — и пустой список означает «этот такт не течёт по построению».
    """
    о = д.get("expect") or {}
    вид = о.get("kind")
    if вид == "refuse":
        return []
    вон = []
    for ключ in ("v", "n"):
        if о.get(ключ) is not None:
            вон.append(str(о[ключ]).lower())
    for п in (о.get("surfaces") or ()):
        вон.append(str(п).lower())
    return [x for x in вон if x]


def такты(путь):
    """[(имя, вопрос)] полосы; строка-заголовок с «#» пропускается."""
    вон = []
    for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        try:
            д = json.loads(строка)
        except ValueError:
            continue
        ask = str(д.get("ask") or д.get("input") or д.get("text") or "").strip()
        if ask:
            вон.append((str(д.get("id") or "?"), ask, д))
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--полоса", default=None)
    ап.add_argument("--свод", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    п_полосы = pathlib.Path(дов.полоса) if дов.полоса else ПОЛОСА
    п_свода = pathlib.Path(дов.свод) if дов.свод else КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
    if not п_полосы.exists():
        print(f"ТЕЧЬ ПОЛОСЫ ОТКАЗ: полосы «{п_полосы}» нет")
        return 2
    if not п_свода.exists():
        print(f"ТЕЧЬ ПОЛОСЫ ОТКАЗ: свода «{п_свода}» нет")
        return 2
    свод = п_свода.read_text(encoding="utf-8", errors="replace").lower()
    скелеты = set()
    for имя in МИРЫ_ЗАДАЧ:
        ф = КОРЕНЬ / "datasets" / имя
        if not ф.exists():
            continue
        for с in ф.read_text(encoding="utf-8", errors="replace").splitlines():
            с = с.strip().lower()
            if с:
                скелеты.add(_ЦИФРЫ.sub("#", с))
    течи, формы, формулировки, всего = [], [], [], 0
    for имя, ask, д_такта in такты(п_полосы):
        всего += 1
        низ = ask.lower()
        # ТЕЧЬ СЧИТАЕТСЯ ПО ВОПРОСУ, А НЕ ПО ФАКТУ: берётся ПОСЛЕДНЕЕ предложение
        # такта — то, где стои́т сам вопрос, — а не самое длинное (им обычно бывает
        # обстановка задачи, общая для меры и корпуса по существу дела).
        части = [ч.strip() for ч in _КОНЕЦ.split(низ) if ч.strip()]
        вопрос = части[-1] if части else низ
        # ТЕЧЁТ ВОПРОС ВМЕСТЕ СО СВОИМИ ЧИСЛАМИ, А НЕ ГОЛАЯ ФОРМУЛИРОВКА (07.09, первый
        # же прогон). «how far did the frog jump» стои́т и в полосе, и в мире меры
        # действия — но в полосе при нём 19 дюймов и ответ 15, а в своде 12 дюймов и
        # ответ 12. Читатель, видевший «how far did the frog jump? 12 inches», НЕ
        # ЗНАЕТ ответа на такт про 19 дюймов; он знает лишь, о чём спрашивают.
        #
        #     ВОПРОС БЕЗ СВОИХ ЧИСЕЛ ЕСТЬ РОД ВОПРОСА, А НЕ ВОПРОС. Родам корпус учит
        #     нарочно — в том и смысл моста вопросной формы; течёт же ПАРА «вопрос с
        #     числами → ответ», ибо только она отвечается памятью.
        #
        # Потому течь считается по вопросу С ЧИСЛАМИ, взятыми из всего такта: если та
        # же формулировка стои́т в своде при тех же числах — читатель видел ответ.
        числа_такта = set(_ЦИФРЫ.findall(низ))
        # ТЕЧЁТ ПАРА «ВОПРОС → ОТВЕТ», И ОТВЕТ ОБЯЗАН СОВПАСТЬ ТОЖЕ (07.09, второй
        # шрам прибора). Первая редакция звала течью совпадение вопроса с числами — и
        # объявила текущими 102 такта ОТКАЗА стенда школьных форм: «Vera has 4 books.
        # what's the total number of books?» ждёт ОТКАЗА (факта недостаёт), а строка
        # свода «Vera has 11 books and Peter has 4 books… 11 + 4 = 15» даёт ОТВЕТ.
        #
        #     ТАКТ ОТКАЗА НЕ ТЕЧЁТ ОТ ПОЛНОЙ СТРОКИ СВОДА: он ждёт отказа, а свод даёт
        #     ответ. Память тут не помогает, а МЕШАЕТ — читатель, помнящий полную
        #     задачу, скорее ответит числом там, где обязан отказаться.
        #
        # Ныне течь требует троякого совпадения: вопрос, его числа И ожидаемый ответ.
        ожидаемое = ожидания(д_такта)
        течёт = False
        if len(вопрос) >= 25 and вопрос in свод and ожидаемое:
            for строка_свода in свод.split("\n"):
                if вопрос not in строка_свода:
                    continue
                if not (числа_такта and числа_такта <= set(_ЦИФРЫ.findall(строка_свода))):
                    continue
                хвост = строка_свода.split(вопрос, 1)[-1]
                if any(о in хвост for о in ожидаемое):
                    течёт = True
                    break
        if течёт:
            течи.append((имя, вопрос))
        elif len(вопрос) >= 25 and вопрос in свод:
            формулировки.append((имя, вопрос))
        if _ЦИФРЫ.sub("#", низ) in скелеты:
            формы.append((имя, низ))
    for имя, в in течи[:10]:
        print(f"  ТЕЧЬ [{имя}] «{в[:100]}»")
    if дов.подробно:
        for имя, в in формы[:10]:
            print(f"  ФОРМА [{имя}] «{в[:100]}»")
    for имя, в in формулировки[:6]:
        print(f"  РОД ВОПРОСА (не течь) [{имя}] «{в[:90]}»")
    поза = "PASS" if len(течи) <= ТЕЧЕЙ_РУБЕЖ else "FAIL"
    print(f"ТЕЧЬ ПОЛОСЫ {поза}: тактов {всего}, вопрос такта стои́т в своде "
          f"{len(течи)} (рубеж {ТЕЧЕЙ_РУБЕЖ}); та же формулировка с ИНЫМИ числами "
          f"{len(формулировки)}, совпадений СКЕЛЕТА {len(формы)} — "
          f"считано, но не судимо; полоса {п_полосы.name} "
          f"({п_полосы.stat().st_size} байт), свод {п_свода.name} "
          f"({п_свода.stat().st_size} байт)")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
