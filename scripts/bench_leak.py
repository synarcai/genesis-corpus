def ожидания(д):
    """Поверхности ожидаемого ответа такта — то, что обязано совпасть при течи.

    ОТКАЗ ОЖИДАНИЙ НЕ ИМЕЕТ: такт, ждущий отказа, не может протечь от строки, дающей
    ответ, — и пустой список означает «этот такт не течёт по построению».
    """
    о = д.get("expect") or {}
    вид = о.get("kind")
    if вид == "refuse":
        return []
    вон = []
    for ключ in ("v", "n"):
        if о.get(ключ) is not None:
            вон.append(str(о[ключ]).lower())
    for п in (о.get("surfaces") or ()):
        вон.append(str(п).lower())
    return [x for x in вон if x]


def такты(путь):
    """[(имя, вопрос)] полосы; строка-заголовок с «#» пропускается."""
    вон = []
    for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        try:
            д = json.loads(строка)
        except ValueError:
            continue
        ask = str(д.get("ask") or д.get("input") or д.get("text") or "").strip()
        if ask:
            вон.append((str(д.get("id") or "?"), ask, д))
    return вон


