#!/usr/bin/env python3
"""[ОЧЕРТАНИЯ РОДА] — род, богатый страницами и бедный очертаниями.

    РОД, БОГАТЫЙ СТРАНИЦАМИ И БЕДНЫЙ ОЧЕРТАНИЯМИ, ПОВТОРЯЕТ ОДНУ МЫСЛЬ ЧИСЛАМИ. Двести
    страниц одного очертания учат тому же, чему двадцать, — и заглушают соседний род, у
    какого очертаний двадцать на двадцать страниц. Перекос родов это видит лишь тогда, когда
    он двадцатикратен; здесь он виден вчетверо раньше.

ОЧЕРТАНИЕ ЕСТЬ СТРАНИЦА БЕЗ ЧИСЕЛ. Прибор заменяет всякое число знаком «#» и считает, сколько
РАЗЛИЧНЫХ скелетов осталось в роде. Мера рода — страниц на очертание; мера дома — во сколько
раз эта мера у самого «плотного» рода больше, чем у самого «редкого».

Так 14.09 три дома подряд дали перекос 7, 12 и 15 по одной и той же причине: РОД ПЕРЕБИРАЛ
ТО, ОТ ЧЕГО НЕ ЗАВИСИТ. «Хватает» не поминает второй вещи — и все страницы с разными вторыми
вещами сходились в одну, пока «лишнее» множилось ими. Прибор ниже узнаёт такое по числам, а
не по чтению кода.

    ДВА ОБЪЯВЛЕНИЯ РАЗВЕДЕНЫ ВСЛУХ, А НЕ СВЕДЕНЫ МОЛЧА (14.09). Корпус уже держал
    `РОДЫ_ПО_ПРЕДМЕТУ` — объявление 13.09 для прибора ПЕРЕКОСА: род, чьё ЧИСЛО СТРАНИЦ есть
    факт о предмете («деление нуля на ноль есть ОДИН СЛУЧАЙ, а не семья случаев»). Здешнее
    `ОЧЕРТАНИЕ_ПО_ПРИРОДЕ` — о другом: род, чьё ЧИСЛО ОЧЕРТАНИЙ есть факт о предмете («x +
    2 = 3» на пятидесяти пяти числах). Первое про ПЕРЕКОС, второе про ПОВТОР, и дом бывает
    в одном без другого: у «ноль на ноль» две страницы и два очертания — он неровен и не
    повторяется; у «голого» пятьдесят пять страниц на одно очертание — он ровен и
    повторяется.

    СВЕСТИ ИХ В ОДНО ЗНАЧИЛО БЫ ДАТЬ ОДНИМ ОБЪЯВЛЕНИЕМ УКРЫТЬСЯ ОТ ДВУХ ПРИБОРОВ.

    РОД-УПРАЖНЕНИЕ ОБЪЯВЛЯЕТСЯ, А НЕ УГАДЫВАЕТСЯ. Есть роды, чья ПРИРОДА — одно очертание
    на многих числах: «x + 2 = 3. x = 3 − 2. x = 1» пятьдесят пять раз учит одному делу на
    разных числах, и это не повтор, а УПРАЖНЕНИЕ. Дом вправе объявить такой род в
    `ОЧЕРТАНИЕ_ПО_ПРИРОДЕ`, и прибор его не считает. Но объявить — значит НАЗВАТЬ ВСЛУХ и
    взять на себя: род с одним очертанием, НЕ ОБЪЯВЛЕННЫЙ упражнением, есть долг.

ЗАЙМ НАЗВАН ВСЛУХ: прибор читает лишь дома, объявившие `ПОКАЗЫ` вида {строка: (язык, род)}
или {строка: род}. Прочие считаны числом и НЕ ПРОЧИТАНЫ.

usage: scripts/genus_shapes.py [--всё] [--дом ИМЯ …]
"""
import collections
import importlib
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: НЕРОВНЫХ = 20
#
# РУБЕЖ НОВОГО ПРИБОРА СТАВИТСЯ ПО МЕРЕ, А НЕ ПО ЖЕЛАНИЮ. Первая мера 14.09 дала 36 домов
# неровнее восьмикратного из 257 прочитанных. Поставить здесь ноль значило бы объявить
# красным полкорпуса и приучить смотреть мимо красного; поставить мерой — значит НАЗВАТЬ
# ДОЛГ ЧИСЛОМ и ратчетом сводить его вниз. Долг этот не выдуман прибором: он копился, пока
# его нечем было увидеть.
#
#     СПИСОК ПЕРЕСТРАИВАЕТСЯ ПОСЛЕ КАЖДОГО ВЫЧЁРКИВАНИЯ (14.09, третья ошибка того же
#     рода). Прибор показывает роды по убыванию плотности; объявил верхние — и шестой стал
#     первым. Чтение всего свода не спасает, если читать его СВЕРХУ И ОСТАНАВЛИВАТЬСЯ: в
#     доме рядов остался «вопрос о прогрессии», в доме числового ряда — «на_сколько», оба
#     близнецы уже объявленных.
#
#         МЕРИТЬ НАДО ЗАНОВО ПОСЛЕ КАЖДОЙ ПРАВКИ, А НЕ ИДТИ ДАЛЬШЕ ПО СТАРОМУ СПИСКУ.
#
#     ПРИБОР НАЗЫВАЕТ КРАЙНИХ, А НЕ ВСЕХ (14.09, первый платёж по этому долгу). Вердикт
#     печатает плотнейший род и реже́йший — этого довольно, чтобы понять беду, и мало, чтобы
#     её вылечить: за крайним стои́т следующий, иногда ТОЖДЕСТВЕННЫЙ ему. В доме денег рядом
#     с объявленным родом стоял его близнец — те же девять валют на сорока парах чисел, — и
#     первая правка его пропустила. ЧИНИТЬ НАДО ПО ВСЕМУ СВОДУ РОДОВ ДОМА, А НЕ ПО ДВУМ
#     СТРОКАМ ВЕРДИКТА.
#
#     ПЯТЬ СОСТОЯНИЙ РОДА, РАЗЛИЧЁННЫХ ПЕРВЫМ ПЛАТЕЖОМ (14.09, девять домов прочитаны,
#     долг 36 → 29). Объявления требуют два: УПРАЖНЕНИЕ (одна мысль, числа — материал) и
#     ФАКТ О ПРЕДМЕТЕ (случай один, семьи случаев не бывает — `РОДЫ_ПО_ПРЕДМЕТУ`). Трём же
#     объявление НЕ НУЖНО, и надевать его на них нельзя:
#
#         · СВОЯ МЫСЛЬ НА КАЖДОЙ СТРАНИЦЕ — «законы» геометрии, 12 на 12, и чисел в них нет;
#         · ВМЕСТЕ С ЧИСЛАМИ РАЗНЯТСЯ ИМЕНА И ПРЕДМЕТЫ — «анафора», 240 на 145;
#         · ПЕРЕБИРАЕТСЯ ЕДИНИЦА ВМЕСТЕ С ЧИСЛОМ — «давление», «волна»: «ньютон ÷
#           квадратный метр», «колебаний в минуту»;
#         · ПЕРЕБИРАЕТСЯ САМО СЛОВО — «доля» («six sevenths», «half»), 540 на 216: слово
#           меняет ЗАПИСЬ, а не только значение при ней.
#
#     ОБЩЕЕ У ВСЕХ ЧЕТЫРЁХ, КАКИМ ОБЪЯВЛЕНИЕ НЕ НУЖНО: ИХ МАТЕРИАЛ МНОГОМЕРЕН. Меняется не
#     одно число, а число ВМЕСТЕ С ЧЕМ-ТО ЕЩЁ — словом, именем, единицей, мыслью, — и тогда
#     очертаний становится столько же, сколько страниц, не оттого что дом старался, а оттого
#     что таков ПРЕДМЕТ.
#
#         РОД РОВЕН САМ СОБОЮ, КОГДА ЕГО МАТЕРИАЛ МНОГОМЕРЕН.
#
#     И ЗАЩИТА ОТ ЗЛОУПОТРЕБЛЕНИЯ САМИМ ОБЪЯВЛЕНИЕМ (14.09, семнадцать домов прочитаны).
#     Есть дома ЦЕЛИКОМ СЧЁТНЫЕ — деление долей, сравнение доли с единицей, — где ровного
#     собою рода нет вовсе и объявлены ВСЕ роды. «Объявлено всё» есть ровно тот вид, какой
#     принимает уклонение, и отличить одно от другого можно лишь одним:
#
#         ОБЪЯВЛЕНИЕ, ПОКРЫВАЮЩЕЕ ВЕСЬ ДОМ, ОБЯЗАНО НАЗВАТЬ СЕБЯ РЕДКИМ И СКАЗАТЬ, ПОЧЕМУ
#         СЛУЧАЙ ТАКОВ. Иначе через год его не отличить от уклонения — ни читателю, ни
#         самому автору.
#
#     Оговорка эта не украшение: она СЛЕД ТОГО, ЧТО АВТОР ЗАМЕТИЛ ОПАСНОСТЬ и не прошёл
#     мимо. Тот, кто объявляет ради тишины прибора, такой оговорки не напишет. ОБЪЯВЛЕНИЕ НУЖНО ЛИШЬ ТАМ, ГДЕ
#         МЕРНОСТЬ ОДНА: ЧИСЛА ПРИ НЕИЗМЕННОЙ ЗАПИСИ.
#
#     Прибор этих шести состояний НЕ РАЗЛИЧАЕТ и не должен: он называет ЧИСЛО. Различает
#     человек, читая дом, — а прибор удерживает от того, чтобы не читать.
#
#     И ГРАНИЦА, ПО КАКОЙ ОТЛИЧАЕТСЯ УПРАЖНЕНИЕ ОТ ПОВТОРА, ОДНА ДЛЯ ВСЕХ ДОМОВ: упражнение
#     там, где ЧИСЛА СУТЬ МАТЕРИАЛ, А МЫСЛЬ ОДНА; повтор — там, где всякая страница несёт
#     СВОЮ мысль, а числа при ней случайны. «x + 2 = 3» на пятидесяти пяти числах — одна
#     мысль и пятьдесят пять упражнений; «S → a S b» на двадцати четырёх правилах — двадцать
#     четыре мысли, и числа тут ни при чём.
НЕРОВНЫХ = 20
ПРЕДЕЛ = 8.0        # во сколько раз «плотный» род смеет быть плотнее «редкого»
МАЛО = 30           # дома меньше этого числа страниц не мерятся: числа там не значат ничего
ЧИСЛО = re.compile(r"\d+")


def очертание(строка):
    return ЧИСЛО.sub("#", строка)


def дома():
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        if not путь.stem.startswith("gen_") and not путь.stem.startswith("_"):
            yield путь.stem


def мера(показы):
    """{род: (страниц, очертаний)} — или None, если объявление не той формы."""
    вон = collections.defaultdict(lambda: [0, set()])
    for строка, знак in показы.items():
        if isinstance(знак, tuple):
            род = знак[1] if len(знак) > 1 else знак[0]
        elif isinstance(знак, str):
            род = знак
        else:
            return None
        вон[род][0] += 1
        вон[род][1].add(очертание(строка))
    return {р: (n, len(о)) for р, (n, о) in вон.items()}


def main():
    только = set(sys.argv[sys.argv.index("--дом") + 1:]) if "--дом" in sys.argv else None
    всё = "--всё" in sys.argv
    прочитано = пропущено = мелких = сломан = неровных = объявлено = 0
    беда = []
    for имя in дома():
        if только and имя not in только:
            continue
        try:
            дом = importlib.import_module(имя)
        except Exception:
            сломан += 1
            continue
        показы = getattr(дом, "ПОКАЗЫ", None)
        if not isinstance(показы, dict) or not показы:
            пропущено += 1
            continue
        свод = мера(показы)
        if свод is None or len(свод) < 2:
            пропущено += 1
            continue
        # РОД-УПРАЖНЕНИЕ ОБЪЯВЛЯЕТСЯ, А НЕ УГАДЫВАЕТСЯ: дом называет его поимённо, и прибор
        # его не считает. Необъявленный род с одним очертанием остаётся долгом.
        упражнения = set(getattr(дом, "ОЧЕРТАНИЕ_ПО_ПРИРОДЕ", ()) or ())
        if упражнения:
            свод = {р: з for р, з in свод.items() if р not in упражнения}
            объявлено += len(упражнения)
            if len(свод) < 2:
                пропущено += 1
                continue
        if sum(n for n, _о in свод.values()) < МАЛО:
            мелких += 1
            continue
        прочитано += 1
        плотность = {р: n / о for р, (n, о) in свод.items() if о}
        if not плотность:
            continue
        густо, редко = max(плотность.values()), min(плотность.values())
        во_сколько = густо / редко if редко else float("inf")
        if во_сколько > ПРЕДЕЛ:
            неровных += 1
            гуще = max(плотность, key=плотность.get)
            реже = min(плотность, key=плотность.get)
            беда.append((имя, во_сколько, гуще, свод[гуще], реже, свод[реже]))
        elif всё:
            print(f"  {имя}: {во_сколько:.1f}×")
    for имя, во, гуще, (n1, о1), реже, (n2, о2) in sorted(беда, key=lambda б: -б[1])[:10]:
        print(f"  НЕРОВНО {во:.1f}× в доме {имя}: «{гуще}» {n1} страниц на {о1} очертаний, "
              f"а «{реже}» {n2} на {о2}")
    поза = "PASS" if неровных <= НЕРОВНЫХ else "FAIL"
    print(f"ОЧЕРТАНИЯ РОДА {поза}: {неровных} домов неровнее {ПРЕДЕЛ:.0f}× "
          f"(рубеж {НЕРОВНЫХ}); прочитано {прочитано}, мелких {мелких} (меньше {МАЛО} "
          f"страниц), без объявления {пропущено} — ЗАЙМ, не молчание; родов объявлено "
          f"упражнением {объявлено}; не ввезлось {сломан}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
