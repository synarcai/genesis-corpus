#!/usr/bin/env python3
"""[ПЕРЕСТАНОВКА СВЕЖА] — тот же свод в другом порядке, а не свод десятидневной давности.

    ПЕРЕСТАНОВКА, ОТСТАВШАЯ ОТ СВОДА, СРАВНИВАЕТ НЕ ДВА ПОРЯДКА ОДНОГО СВОДА, А ДВА
    РАЗНЫХ СВОДА — И ВСЯКИЙ ВЫВОД ИЗ ТАКОГО СРАВНЕНИЯ ЛОЖЕН ДВАЖДЫ.

ПОВОД, ЗАМЕРЕННЫЙ 12.09. Перестановка школьной сборки (`GENESIS-SCHOOL-PERMUTED.txt`) есть
ТОТ ЖЕ свод в порядке, заданном семенем: множество строк её обязано совпасть со школьным до
единой. Ею проверяется независимость выученного от ПРЕДСТАВЛЕНИЯ — схема, сваренная из двух
порядков, обязана совпасть отпечатком, иначе организм учил порядок файла, а не язык.

Замер нашёл её недвижимой с второго сентября: 9 002 437 байт против 32 015 381 у школьного
свода — десять суток и ВТРОЕ меньше. Сборщик о том знал и молчал: он отказывается писать
перестановку при несовпадении отпечатков, но никто его не звал.

    ОТКАЗ, КОТОРОГО НИКТО НЕ СЛЫШАЛ, НЕ ЕСТЬ СТОРОЖ: он срабатывает лишь тогда, когда
    о нём вспомнят, — а вспоминают о нём ровно тогда, когда он уже не нужен.

ЧТО СУДИТ ПРИБОР. Отпечаток МНОЖЕСТВА строк (отсортированных, без пустых) перестановки
против школьного свода. Порядок в отпечаток не входит — он-то и есть предмет перестановки.

    ДВЕ СБОРКИ ОДНОГО СВОДА РАЗЛИЧАЮТСЯ ПОРЯДКОМ И НИЧЕМ ИНЫМ; РАЗЛИЧИЕ В МНОЖЕСТВЕ
    СТРОК ЕСТЬ НЕ ПЕРЕСТАНОВКА, А ДРУГОЙ СВОД.

ЧЕГО ОН НЕ ДЕЛАЕТ. Он не пересобирает: сборка есть дело `gen_genesis_full.py --permute`,
и прибор, молча её пишущий, двигал бы дерево под набором.

ПРИБОР ДОКАЗЫВАЕТ СЕБЯ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ. Замер 12.09: из 119 приборов с
рубежом НОЛЬ пробу несут 24, а 95 зеленеют от нуля находок, ничем того не доказав. Суды миров
пробуются общим прибором (`court_mutants` подсаживает во все 225), приборы свода — ничем.

    ПРИБОР, ЗЕЛЕНЕЮЩИЙ ОТ НУЛЯ НАХОДОК, ОБЯЗАН ДОКАЗАТЬ, ЧТО УМЕЕТ НАХОДИТЬ.
    ПРОБА, СДЕЛАННАЯ РУКОЮ И НЕ ЗАПИСАННАЯ, ДОКАЗЫВАЕТ ПРИБОР ОДНАЖДЫ И НЕ ДОКАЗЫВАЕТ ВПРЕДЬ.

Проба здесь — две пары строк на временных файлах: одинаковое множество в разном порядке
обязано дать ОДИН отпечаток, разное множество — РАЗНЫЕ. Первое доказывает, что прибор не
путает порядок с содержанием; второе — что он вообще что-то различает. Проба, павшая, даёт
ОТКАЗ, а не FAIL: прибор, не доказавший себя, не вправе судить свод.

    python3 scripts/permuted_fresh.py [--проба]
"""
# ПУСТОЙ-ОБХОД: --школа /no/such/school.txt
import hashlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ШКОЛА = КОРЕНЬ / "datasets" / "GENESIS-SCHOOL.txt"
ПЕРЕСТАНОВКА = КОРЕНЬ / "datasets" / "GENESIS-SCHOOL-PERMUTED.txt"

# РУБЕЖ-ДОЛГА: РАСХОЖДЕНИЙ_РУБЕЖ = 0
#
# Рубеж есть ПОЛ: перестановка либо тот же свод, либо не перестановка. Середины нет.
РАСХОЖДЕНИЙ_РУБЕЖ = 0


def отпечаток(путь):
    """sha256 ОТСОРТИРОВАННЫХ непустых строк — порядок в отпечаток не входит."""
    строки = sorted(с for с in путь.read_text(encoding="utf-8", errors="replace").splitlines()
                    if с.strip())
    return hashlib.sha256("\n".join(строки).encode("utf-8")).hexdigest()


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что прибор УМЕЕТ находить.

        ПРИБОР, ЗЕЛЕНЕЮЩИЙ ОТ НУЛЯ НАХОДОК, ОБЯЗАН ДОКАЗАТЬ, ЧТО УМЕЕТ НАХОДИТЬ:
        молчание признака неотличимо от честного нуля, покуда не спросишь его самого.

    И ПРОБА ЗАПИСЫВАЕТСЯ, А НЕ ДЕЛАЕТСЯ РУКОЮ (12.09):

        ПРОБА, СДЕЛАННАЯ РУКОЮ И НЕ ЗАПИСАННАЯ, ДОКАЗЫВАЕТ ПРИБОР ОДНАЖДЫ И НЕ
        ДОКАЗЫВАЕТ ВПРЕДЬ.

    Две пары строк: одинаковое множество в разном порядке обязано дать ОДИН отпечаток,
    разное множество — РАЗНЫЕ. Первое доказывает, что прибор не путает порядок с
    содержанием; второе — что он вообще что-то различает.
    """
    import tempfile
    беды = []
    с_а = "первая\nвторая\nтретья\n"
    с_б = "третья\nпервая\nвторая\n"          # тот же набор, иной порядок
    с_в = "первая\nвторая\nчетвёртая\n"       # иной набор
    with tempfile.TemporaryDirectory() as д:
        д = pathlib.Path(д)
        а, б, в = д / "а.txt", д / "б.txt", д / "в.txt"
        а.write_text(с_а, encoding="utf-8")
        б.write_text(с_б, encoding="utf-8")
        в.write_text(с_в, encoding="utf-8")
        if отпечаток(а) != отпечаток(б):
            беды.append("порядок вошёл в отпечаток — прибор судит не то")
        if отпечаток(а) == отпечаток(в):
            беды.append("разные множества дали один отпечаток — прибор слеп")
    return беды


def main():
    if "--проба" in sys.argv:
        беды = _проба()
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ПЕРЕСТАНОВКА СВЕЖА ПРОБА: бед {len(беды)} (рубеж 0)")
        return 0 if not беды else 1
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ЛИШЬ ПО ПРОСЬБЕ: прибор, доказывающий себя
    # только когда его просят, доказан ровно столько раз, сколько его просили.
    беды = _проба()
    if беды:
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ПЕРЕСТАНОВКА СВЕЖА ОТКАЗ: прибор не доказал, что умеет находить "
              f"({len(беды)} бед) — вердикту о своде верить нельзя")
        return 2
    школа, перестановка = ШКОЛА, ПЕРЕСТАНОВКА
    if "--школа" in sys.argv:
        школа = pathlib.Path(sys.argv[sys.argv.index("--школа") + 1])
    if not школа.is_file():
        print(f"ПЕРЕСТАНОВКА СВЕЖА ОТКАЗ: школьной сборки нет — {школа}")
        return 2
    if not перестановка.is_file():
        print(f"ПЕРЕСТАНОВКА СВЕЖА ОТКАЗ: перестановки нет — {перестановка.name}; "
              f"собрать: python3 tools/gen_genesis_full.py --permute 1")
        return 2
    ш, п = отпечаток(школа), отпечаток(перестановка)
    ш_б, п_б = школа.stat().st_size, перестановка.stat().st_size
    if ш != п:
        print(f"  школа {ш[:16]} ({ш_б} б), перестановка {п[:16]} ({п_б} б) — "
              f"расхождение {abs(ш_б - п_б)} байт")
        print("  собрать заново: python3 tools/gen_genesis_full.py --permute 1")
    поза = "PASS" if ш == п else "FAIL"
    print(f"ПЕРЕСТАНОВКА СВЕЖА {поза}: {0 if ш == п else 1} расхождений множества строк "
          f"(рубеж {РАСХОЖДЕНИЙ_РУБЕЖ}); отпечаток {ш[:16]}, байт {п_б}")
    return 0 if ш == п else 1


if __name__ == "__main__":
    sys.exit(main())
