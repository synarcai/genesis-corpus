#!/usr/bin/env python3
"""[ЛОВУШКА НАЧАЛА] — суды, зовущие строку ложной по ЕЁ НАЧАЛУ.

04.09 дом фактов мира написал честную строку «snow is cold. why? because snow
is frozen water.», и дом ТЕМ назвал её ложью: у него объявлена тема «snow» и
рамка «{т} is {о}.», а суд читал НАЧАЛО строки. Ворота мир не записали — их
работа, — но важно другое: до этой строки захвата НЕ БЫЛО НИ ОДНОГО, и прибор
ЧУЖОЙ РАМКИ, сличающий дома по существующим показам, честно печатал ноль.

    СУД ПО НАЧАЛУ СТРОКИ ЕСТЬ ЛОВУШКА, ВЗВЕДЁННАЯ НА БУДУЩЕЕ. Он молчит ровно
    до дня, когда сосед напишет свою первую строку, начинающуюся объявленным
    словом, — и тогда ломает не себя, а СОСЕДА, чья строка честна.

Ловушку нельзя увидеть сличением показов: показов, которые её тронут, ещё нет.
Её видно СТРОЕНИЕМ суда, и прибор берёт признак, который отличает строение, не
трогая истины: строку УДВАИВАЮТ. «X. X.» есть не показ и не ложь — это строка,
о которой суду сказать нечего; суд, читающий полный образец, молчит о ней, а суд,
читающий начало, зовёт её ложной, ибо начало на месте.

Признак чист: он не спрашивает, права ли ловушка, — он спрашивает, ЕСТЬ ЛИ ОНА.

    python3 scripts/prefix_traps.py [--подробно]
"""
import argparse
import importlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
ОБРАЗЦОВ = 40      # проб на дом — ловушка видна на первой же


def дома():
    """Всякий дом с показами и своим судом — найден делом, а не списком."""
    вон = []
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        try:
            дом = importlib.import_module(путь.stem)
        except Exception:
            continue
        показы = getattr(дом, "ПОКАЗЫ", None)
        судить = getattr(дом, "судить", None)
        if isinstance(показы, dict) and показы and callable(судить):
            вон.append((путь.stem, дом))
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    а = ап.parse_args()
    print(f"{'дом':<20}{'проб':>6}{'ЛОВУШЕК':>9}")
    всего = поймано = 0
    виновные = []
    for имя, дом in дома():
        показы = list(дом.ПОКАЗЫ)
        шаг = max(1, len(показы) // ОБРАЗЦОВ)
        проб = ловушек = 0
        первая = None
        for с in показы[::шаг][:ОБРАЗЦОВ]:
            двойная = f"{с} {с}"
            try:
                судимо, истинно = дом.судить(двойная)[:2]
            except Exception:
                continue
            проб += 1
            if судимо and not истинно:
                ловушек += 1
                if первая is None:
                    первая = двойная
        всего += проб
        поймано += ловушек
        знак = f"{ловушек:>9}" if ловушек else f"{'—':>9}"
        print(f"{имя:<20}{проб:>6}{знак}")
        if ловушек:
            виновные.append((имя, ловушек, первая))
    print(f"{'ИТОГО':<20}{всего:>6}{поймано:>9}")
    for имя, ловушек, первая in виновные:
        print(f"  ЛОВУШКА [{имя}] {ловушек} проб из {ОБРАЗЦОВ}: «{первая[:100]}»")
    итог = "PASS" if not виновные else "FAIL"
    print(f"ЛОВУШКА НАЧАЛА {итог}: домов с судом по началу строки {len(виновные)} "
          f"(рубеж 0), проб {всего}, пойманных удвоений {поймано}")
    return 1 if виновные else 0


if __name__ == "__main__":
    sys.exit(main())
