#!/usr/bin/env python3
"""[СТОРОЖ НАБОРА] — цепь от набора до прибора не смеет отрастить лишнего звена.

ПОВОД, ПРОЖИТЫЙ 12.09. Питоны, переживавшие снятие набора, жили сиротами при init и ели
машину рядом со следующим прогоном: один такой прожил ДВАДЦАТЬ ВОСЕМЬ МИНУТ. Беда была
записана в самой точке ещё 09.09 — и закрыта лишь сегодня, чистой мерой по списку потомков.

ДВЕ ПРИЧИНЫ, И ОБЕ ВОЗВРАЩАЮТСЯ ОДНОЙ СТРОКОЙ ПРАВКИ:

    ЛИШНЯЯ ОБОЛОЧКА  «out=$(python3 …)» заводит оболочку между сторожем и питоном; она
                     несёт ТУ ЖЕ командную строку набора, и `pkill -f` бьёт по ней тоже —
                     она умирает без обработчика, и питон остаётся при init.
    ПЕРЕДНИЙ ПЛАН    bash, ожидающий переднего дела, откладывает обработчик до его конца.

        ЛОВУШКА, ЖДУЩАЯ КОНЦА ТОГО, ОТ ЧЕГО СТЕРЕЖЁТ, НЕ СТЕРЕЖЁТ.
        ЛИШНЯЯ ОБОЛОЧКА МЕЖДУ СТОРОЖЕМ И ДЕЛОМ ЕСТЬ ЛИШНЕЕ МЕСТО, ГДЕ ЦЕПЬ РВЁТСЯ.

ЧТО ЗАМЕРЯЕТСЯ, И ПОЧЕМУ СТАТИЧЕСКИ. Живая мера требует ПУСТИТЬ набор и снять его — то есть
часы машины и невозможность идти внутри самого набора. Прибор же читает точку ТЕКСТОМ и
спрашивает четыре условия, каждое из которых куплено опытом:

    1. вызов прибора НЕ обёрнут подстановкой команды;
    2. питон запускается фоном и ждётся по имени;
    3. ловушка на TERM/INT берёт его поимённо;
    4. одиночный прибор идёт фоновой задачей, а не передним планом.

    СТАТИЧЕСКИЙ СТОРОЖ НЕ ДОКАЖЕТ, ЧТО СИРОТ НЕТ; ОН ДОКАЖЕТ, ЧТО НЕ ВЕРНУЛИСЬ ИХ ПРИЧИНЫ —
    А ЭТО РОВНО ТО, ЧТО МОЖНО ПРОВЕРИТЬ БЕЗ ЧАСА МАШИНЫ.

ГРАНИЦА НАЗВАНА: прибор судит ОДНУ точку — `scripts/courts.sh`. Иных запускателей в своде
нет, и появление второго есть находка соседнего прибора, а не этого.

    python3 scripts/suite_guard.py [--точка ФАЙЛ]
"""
# ПУСТОЙ-ОБХОД: --точка no-such-suite
import argparse
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ТОЧКА = КОРЕНЬ / "scripts" / "courts.sh"

# РУБЕЖ-ДОЛГА: БЕЗ_СТОРОЖА_РУБЕЖ = 0
#
# Ноль есть ПОЛ: всякая правка, вернувшая хоть одну из двух причин, роняет прибор в тот же
# час — то есть прежде, чем осиротевший питон успеет съесть чужой прогон.
БЕЗ_СТОРОЖА_РУБЕЖ = 0

# ЧЕТЫРЕ УСЛОВИЯ, И ВСЯКОЕ — СВОИМ ПРИЗНАКОМ.
# ПРИЗНАК БЕРЁТ ВЫЗОВ ПРИБОРА, А НЕ ВСЯКИЙ ВЫЗОВ ПИТОНА. Точка зовёт питона и в преамбуле
# («suite_resume --метка»), и там подстановка честна: дело коротко, сирот не бывает.
#
#     ПРИЗНАК, ВЗЯВШИЙ РОД ВМЕСТО ВИДА, ОБВИНЯЕТ ЧЕСТНОЕ И ПРЯЧЕТ ВИНОВНОЕ ЗА ШУМОМ.
ПОДСТАНОВКА = re.compile(r"\$\(\s*python3\s+\"\$tool\"")
ФОНОМ = re.compile(r"^\s*python3\s+\"\$tool\"\s+\"\$@\"[^\n]*&\s*$", re.M)
ЖДЁТ_ПОИМЁННО = re.compile(r"wait\s+\"\$\w+\"")
ЛОВУШКА_ПИТОНА = re.compile(r"trap\s+'kill\s+-TERM\s+'\"\$\w+\"'[^']*'\s+TERM\s+INT")
ОДИНОЧНЫЙ_ФОНОМ = re.compile(r"run_one\s+\"\$i\"\s+\"\$entry\"\s*&")


def _без_примечаний(текст):
    """Текст точки без строк-примечаний: закон читается в ДЕЛЕ, а не в рассказе о нём.

    ПРИМЕЧАНИЕ, ОПИСЫВАЮЩЕЕ БЕДУ, СОДЕРЖИТ ЕЁ ОБРАЗЕЦ — и прибор, читающий примечания,
    находит беду в рассказе о том, как её убрали.
    """
    return "\n".join(л for л in текст.split("\n") if not л.lstrip().startswith("#"))


def условия(сырой):
    """[(имя, выполнено, чем куплено)] — пять условий цепи, по порядку опыта."""
    текст = _без_примечаний(сырой)
    return [
        ("нет подстановки команды вокруг прибора", not ПОДСТАНОВКА.search(текст),
         "оболочка подстановки несёт ту же строку и гибнет без обработчика"),
        ("прибор запускается фоном", bool(ФОНОМ.search(текст)),
         "ждущий переднего дела bash откладывает обработчик"),
        ("прибор ждётся по имени", bool(ЖДЁТ_ПОИМЁННО.search(текст)),
         "«wait» без имени не даёт кого снимать"),
        ("ловушка берёт прибор поимённо", bool(ЛОВУШКА_ПИТОНА.search(текст)),
         "надежда на группу процессов не сбылась опытом"),
        ("одиночный прибор идёт фоновой задачей", bool(ОДИНОЧНЫЙ_ФОНОМ.search(текст)),
         "передний план откладывает обработчик набора"),
    ]


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что признаки ВИДЯТ и своё, и чужое.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ НУЛЯ НЕВЫПОЛНЕННЫХ УСЛОВИЙ. Пусть признак перестанет
        совпадать с ЧЕСТНОЙ точкой — и условие объявится невыполненным (прибор закричит,
        и это видно). Но пусть признак начнёт совпадать с ЧЕМ УГОДНО — и прибор будет
        зелен над точкой, где беда вернулась.

    Потому проба держит ДВЕ точки: цепь по-новому и цепь по-старому, — и требует, чтобы
    первая прошла целиком, а вторая пала по ОБЕИМ причинам.
    """
    беды = []
    новая = (
        '  t0=$(date +%s)\n'
        '  python3 "$tool" "$@" > "$TMPDIR_SUITE/$idx.out" 2>&1 &\n'
        '  pypid=$!\n'
        '  trap \'kill -TERM \'"$pypid"\' 2>/dev/null; exit 143\' TERM INT\n'
        '  wait "$pypid"; rc=$?\n'
        '    run_one "$i" "$entry" &\n'
        '    wait\n')
    старая = (
        '  t0=$(date +%s)\n'
        '  out=$(python3 "$tool" "$@" 2>&1); rc=$?\n'
        '    run_one "$i" "$entry"\n')
    не_прошли = [и for и, есть, _ч in условия(новая) if not есть]
    if не_прошли:
        беды.append(f"честная цепь не прошла: {не_прошли}")
    прошли_старую = [и for и, есть, _ч in условия(старая) if есть]
    if прошли_старую:
        беды.append(f"ПРЕЖНЯЯ ЦЕПЬ ПРОШЛА по условиям {прошли_старую} — признак слишком широк")
    # И ГЛАВНОЕ: ОБЕ ПРИЧИНЫ БЕДЫ ОБЯЗАНЫ БЫТЬ НАЗВАНЫ ПОРОЗНЬ.
    старые_беды = [и for и, есть, _ч in условия(старая) if not есть]
    if len(старые_беды) < 4:
        беды.append(f"прежняя цепь пала лишь по {len(старые_беды)} условиям из пяти")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"СТОРОЖ НАБОРА ОТКАЗ: признаки цепи не доказаны ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--точка", default=None)
    дов = ап.parse_args()
    точка = pathlib.Path(дов.точка) if дов.точка else ТОЧКА
    if not точка.is_file():
        print(f"СТОРОЖ НАБОРА ОТКАЗ: точки «{точка}» нет")
        return 2
    текст = точка.read_text(encoding="utf-8", errors="replace")
    ряд = условия(текст)
    павшие = [(и, ч) for и, есть, ч in ряд if not есть]
    for и, ч in павшие:
        print(f"  НЕ ВЫПОЛНЕНО: {и} — {ч}")
    поза = "PASS" if len(павшие) <= БЕЗ_СТОРОЖА_РУБЕЖ else "FAIL"
    print(f"СТОРОЖ НАБОРА {поза}: условий цепи не выполнено {len(павшие)} "
          f"(рубеж {БЕЗ_СТОРОЖА_РУБЕЖ}) из {len(ряд)}; точка {точка.name}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
