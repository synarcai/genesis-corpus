#!/usr/bin/env python3
"""[МИНИМАЛЬНЫЙ СВОД] — корпус, урезанный до девяти показов на РОД.

Вопрос владельца (03.09): насколько минимальным должен быть корпус, чтобы
обучение дало исследователя. Перепись форм (scripts/form_census.py) даёт
ЧИСЛО — Σ min(масса, 9) по родам, 42 % строк свода, — но число проверяется
только прогоном: организм, обученный на минимальном своде, обязан ответить
столько же, сколько обученный на полном, или разница назовёт цену массы.

Этот прибор строит ФАЙЛ. Он читает миры показов в порядке манифеста, режет
каждую строку в её РОД (числа и числительные → «#», объявленные имена →
«@», заполнители домов фраз, слова дробей и кратностей → «※» — та же
вторая ступень, что в переписи), и берёт из каждого рода первые LAW² = 9
строк В ПОРЯДКЕ МИРА. Порядок мира — не случайность: показы внутри мира уже
перемешаны законом слоя (tools/layer.py), и первые девять есть честная
выборка рода, а не его начало по алфавиту.

Что сохраняется: швы между мирами (тот же SEAM, что у полного свода), имя и
порядок миров, кратность родов ≤ 9. Что теряется: разнообразие ЧИСЕЛ сверх
девяти показов — то самое, что перепись называет весом, а исполнитель может
назвать знанием. Разницу и меряет прогон.

    python3 scripts/minimal_build.py [--масса 9] [--цель datasets/GENESIS-MIN.txt]
"""
import argparse
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import form_census as C  # noqa: E402
from gen_genesis_full import куски_сборки, записать_размер  # noqa: E402
from layer import SEAM  # noqa: E402


def собрать(масса=C.LAW2, сборка="full", в_пределах_мира=False):
    """(тело, перепись по мирам, сколько родов) — минимальный свод.

    СЧЁТ ВЕДЁТСЯ ПО ВСЕМУ СВОДУ ИЛИ В ПРЕДЕЛАХ МИРА, и это две разные вещи.
    По своду: рамка, встреченная в первом мире, тратит массу и на второй —
    свод выходит меньше, но мир, чьи рамки совпали с соседскими, теряет свои
    показы. В пределах мира: каждый мир держит ≥ массы показов на КАЖДУЮ свою
    рамку — это и есть закон среза, названный holon 03.09 для судов на срезах
    («срез = ≥ LAW² показов на каждую рамку каждого мира»), и цена его выше
    ровно настолько, насколько миры делят рамки.
    """
    видано = collections.Counter()
    куски, перепись = [], []
    родов = set()
    for имя, тело in куски_сборки(сборка):
        if в_пределах_мира:
            видано = collections.Counter()
        строки = []
        for с in тело.splitlines():
            if not с.strip():
                continue
            р = C.род(C.скелет(с))
            родов.add(р)
            if видано[р] >= масса:
                continue
            видано[р] += 1
            строки.append(с)
        if строки:
            куски.append("\n".join(строки))
            перепись.append((имя, len(строки)))
    return SEAM.join(куски) + "\n", перепись, len(родов)


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--масса", type=int, default=C.LAW2)
    ап.add_argument("--цель", default="datasets/GENESIS-MIN.txt")
    ап.add_argument("--в-пределах-мира", action="store_true", dest="в_пределах_мира")
    а = ап.parse_args()
    тело, перепись, родов = собрать(а.масса, в_пределах_мира=а.в_пределах_мира)
    путь = КОРЕНЬ / а.цель
    путь.write_text(тело, encoding="utf-8")
    строк = sum(n for _, n in перепись)
    # ОБЪЯВЛЕНИЕ СВЕРЯЕТСЯ ПРИ КАЖДОЙ СБОРКЕ (тот же закон, что у полного
    # свода): срез вписывает СВОЙ размер в свой узел манифеста сам, иначе
    # его число стоит обещанием и отстаёт на волну — так и вышло 03.09,
    # когда суд манифеста уронил шесть разладов на трёх срезах
    записать_размер(а.цель, len(тело.encode("utf-8")), строк)
    полных = sum(1 for _ in open(КОРЕНЬ / "datasets" / "GENESIS-FULL.txt", encoding="utf-8"))
    print(f"МИНИМАЛЬНЫЙ СВОД: written {а.цель}: {len(тело.encode('utf-8'))} bytes, {строк} строк, "
          f"{len(перепись)} миров, родов {родов}, масса ≤ {а.масса}"
          f"{' в пределах мира' if а.в_пределах_мира else ' по своду'}; полный свод {полных} строк "
          f"({100 * строк // max(1, полных)} %)")
    верх = sorted(перепись, key=lambda п: -п[1])[:8]
    print("  крупнейшие миры минимального свода: " + ", ".join(f"{и} {n}" for и, n in верх))
    return 0


if __name__ == "__main__":
    sys.exit(main())
