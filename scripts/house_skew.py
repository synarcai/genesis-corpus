# РУБЕЖ-ДОЛГА: ОСВОБОЖДЁННЫХ_РУБЕЖ = 17
#
# РОДОВ, ОБЪЯВЛЕННЫХ ДОМОМ КАК «ПО ПРЕДМЕТУ», И ОТТОГО НЕ ВХОДЯЩИХ В СЧЁТ РОВНОСТИ.
#
# Заголовок этого прибора говорит: «он НЕ требует ровности — есть роды, которым довольно
# одного показа». Но покуда мера не знала, КАКИЕ это роды, она считала их наравне со всеми,
# и дом, честно показавший единственный существующий отказ, выходил перекошенным.
#
# Отныне дом объявляет их сам, СЛОВАРЁМ С ПРИЧИНОЙ: `РОДЫ_ПО_ПРЕДМЕТУ = {род: почему}`.
#
#     РОД, ЧЬЁ ЧИСЛО СТРАНИЦ ЕСТЬ ФАКТ О ПРЕДМЕТЕ, А НЕ ВЫБОР ДОМА, НЕ ПОДЛЕЖИТ МЕРЕ
#     РОВНОСТИ — НО ОБЯЗАН БЫТЬ ОБЪЯВЛЕН ТАКОВЫМ, ИНАЧЕ ПОД ЭТИМ ИМЕНЕМ СПРЯЧЕТСЯ ВСЯКИЙ
#     НЕДОПИСАННЫЙ.
#
# Оттого у освобождения СВОЙ рубеж: освобождать можно, но не молча и не всех. Число
# освобождённых печатается всегда, и растёт оно только с письменным отчётом.
# 12 → 14 С ПИСЬМЕННЫМ ОТЧЁТОМ, КАК ТРЕБУЕТ СТРОКА ВЫШЕ (13.09). Три рода дома
# `numnounforms` говорят о свойстве, которое несут ОДИН или ДВА языка из двадцати шести
# объявленных: возвратная лестница — только арабский, обратное согласование — только иврит,
# особая форма при двойке — арабский и иврит. Страниц у такого рода выходит ровно по одной на
# язык объяснения, и взяться им больше неоткуда.
#
# ОБЪЯВЛЕНИЕ ЭТО НЕ ПРОЗА: дом сверяет числа сам (`_проверить_предметные`), и если пакеты
# заговорят иначе — второй язык с возвратной лестницей найдётся, — самопроверка падёт, а
# объявление придётся переписать, а не унаследовать.
#
#     ОБЪЯВЛЕНИЕ, КОТОРОЕ НЕ ПАДАЕТ, ЕСТЬ УКРАШЕНИЕ. Род по предмету освобождён от меры
#     ровности, и потому именно он обязан доказывать своё число.
# 14 → 16 ВТОРЫМ ОТЧЁТОМ ТОГО ЖЕ ДНЯ. Ещё два рода объявлены по предмету, и оба — счёт, а
# не вкус: у `zerodivforms` род «ноль на ноль» есть ОДИН случай (нуль один, перебирать
# нечего), у `refusalwhyforms` род «один закон, много языков» есть ТРИ причины, объявленные
# всеми двадцатью девятью пакетами. Обе цифры сверяются самими домами и падают, если предмет
# заговорит иначе. Перекос при этом 10 → 8: два дома ушли из крайних не подгонкой, а счётом.
# 16 → 17 ТРЕТЬИМ ОТЧЁТОМ ТОГО ЖЕ ДНЯ, И ОН ПОСЛЕДНИЙ. Род «когеренции» дома `valforms`
# несёт шесть страниц — три имени канона (аффект, апперцепция, репрезентация) на двух языках
# объяснения. Четвёртого имени в каноне нет, и выдумать его значило бы солгать о предмете.
#
# ВЫХОД ИЗ ОСВОБОЖДЕНИЯ НАЗВАН В САМОМ ДОМЕ: девяти показов род достигнет ТРЕТЬИМ ЯЗЫКОМ, а
# не четвёртой когеренцией, — и в день, когда мир валентности заговорит на третьем языке,
# освобождение подлежит СНЯТИЮ.
#
#     ОСВОБОЖДЕНИЕ, ПРИ КОТОРОМ НЕ НАЗВАН ВЫХОД, ЕСТЬ ВЕЧНОЕ ОСВОБОЖДЕНИЕ.
ОСВОБОЖДЁННЫХ_РУБЕЖ = 17

# РУБЕЖ-ДОЛГА: КРАЙНИХ_РУБЕЖ = 4
#
# ЧЕТЫРЕ ДОМА ХУЖЕ ДВАДЦАТИКРАТНОГО ПЕРЕКОСА НА ДЕНЬ ПОСТРОЙКИ, И ЧИСЛО ЭТО — ПОТОЛОК.
# Выправить их — работа не одного часа: у `dialogueforms` семнадцать родов, и самый частый
# идёт 662 страницами против девяти у самого редкого. Рубеж ходит только вниз.
# РУБЕЖ ОСТАЁТСЯ ЧЕТЫРЬМЯ, ХОТЯ ЗАМЕР ПОКАЗЫВАЕТ ДЕСЯТЬ, И ЭТО НЕ ОПИСКА (13.09).
#
# За день дом за домом получили роды тридцать четыре бездомных мира, и мера, читавшая прежде
# 133 дома, стала читать 176. Из десяти нынешних крайних ПЯТЬ суть дома, поставленные сегодня
# над кузницами от 1 сентября: `seriesforms` (52.5×), `speechforms` (51.4×), `valforms`
# (34.0×), `linalgforms` (28.5×), `mathfoundforms` (21.6×). Перекос их двенадцати дней от
# роду; новое в нём — только то, что его СТАЛО ВИДНО.
#
#     МЕРА, ПОЛУЧИВШАЯ ЗРЕНИЕ, ПОКАЗЫВАЕТ ХУДШЕЕ ЧИСЛО ПРИ ТОМ ЖЕ ДЕРЕВЕ — И ПОДНЯТЬ ЕЙ
#     РУБЕЖ ЗНАЧИЛО БЫ ЗАПЛАТИТЬ ЗА ЗРЕНИЕ СЛЕПОТОЙ.
#
# Оттого рубеж не тронут: он ходит только вниз, и семеро стоя́т КРАСНЫМИ как долг, названный
# поимённо.
#
# ЧТО ЗА РАБОТА ИХ ЖДЁТ — СКАЗАНО ЧИСЛАМИ, А НЕ ДОГАДКОЙ (13.09, разбор всех оставшихся).
# Это НЕ дома с тощим родом: у семерых самый редкий род несёт 9…48 страниц, то есть добирает
# закона массы и учится. Это дома с РОДОМ-ВЕЛИКАНОМ: 662 страницы у `dialogueforms`, 720 у
# `speechforms`, 1368 у `linalgforms`, 1680 у `seriesforms`.
#
#     ПЕРЕКОС, У КОТОРОГО РЕДКИЙ РОД ЗДОРОВ, ЛЕЧИТСЯ НЕ ПРИБАВКОЙ К РЕДКОМУ, А РАЗДЕЛЕНИЕМ
#     ВЕЛИКАНА: род на тысячу семьсот страниц почти всегда есть НЕСКОЛЬКО родов под одним
#     именем, и мера ровности говорит здесь о ЛЕНИ ИМЕНОВАНИЯ, а не о нехватке страниц.
#
# Оттого работа их — в кузнице и в имени рода, а прибавлять страницы тощим не нужно.
КРАЙНИХ_РУБЕЖ = 4
КРАЙНИЙ = 20.0


def _перекос(счёт):
    """Отношение САМОГО ЧАСТОГО рода к САМОМУ РЕДКОМУ — и никак иначе.

    РАБОТА ЭТА ВЫНЕСЕНА ОТДЕЛЬНО РАДИ ПРОБЫ, И ЭТО КУПЛЕНО ПРОБОЙ ПРОБЫ (12.09). Прежде счёт
    стоял внутри обхода, а проба считала на своих числах — и порча, заменившая МИНИМУМ
    СРЕДНИМ, прошла зелёной: число дома менялось вдвое (ровных 61 → 108), а проба молчала.

        ПРОБА, СЧИТАЮЩАЯ СВОЮ АРИФМЕТИКУ ВМЕСТО РАБОТЫ ПРИБОРА, ПРОВЕРЯЕТ СЕБЯ, А НЕ ЕГО.
    """
    return max(счёт.values()) / min(счёт.values())


def перекосы(двор, освобождённые=None):
    """[(перекос, имя, родов, наим, наиб)] по всем домам двора, у кого родов больше одного.

    `освобождённые` — список, куда прибор дописывает пары «дом · род», вынутые из счёта по
    объявлению дома. Список этот НЕ молчалив: он печатается вердиктом.
    """
    вон = []
    if освобождённые is None:
        освобождённые = []
    for п in sorted(pathlib.Path(двор).glob("*forms.py")):
        try:
            м = importlib.import_module(п.stem)
        except Exception:                                   # noqa: BLE001
            continue
        показы = getattr(м, "ПОКАЗЫ", None)
        if not isinstance(показы, dict) or not показы:
            continue
        значения = list(показы.values())
        # ОБЪЯВЛЕНИЕ РОДА ЧИТАЕТСЯ В ОБЕИХ ЕГО ФОРМАХ (13.09). Старшие дома кладут в
        # `ПОКАЗЫ` кортеж — «(язык, род)», — и род стои́т в нём последним. Дома, писанные
        # переездом перебора, кладут ОДНО ИМЯ РОДА строкой: языка у них в показе нет.
        #
        # Первая редакция брала только кортеж — и двадцать девять новых домов прошли мимо
        # меры МОЛЧА. Указатель родов их читал, а эта мера не видела вовсе.
        #
        #     ДОМ, ЧЬЁ ОБЪЯВЛЕНИЕ МЕРА НЕ УМЕЕТ ПРОЧЕСТЬ, НЕ ПАДАЕТ ЕЁ РУБЕЖОМ — ОН ПРОСТО
        #     НЕ СУЩЕСТВУЕТ ДЛЯ НЕЁ. И это хуже падения: падение видно.
        #
        #     ДВЕ МЕРЫ, ЧИТАЮЩИЕ ОДНО ОБЪЯВЛЕНИЕ ПО-РАЗНЫМ ПРАВИЛАМ, ДАЮТ ДВА ОТВЕТА, И ОБА
        #     БУДУТ НАЗВАНЫ ПРАВДОЙ.
        def _род(v):
            if isinstance(v, str):
                return v
            if isinstance(v, tuple) and len(v) >= 2:
                return v[-1]
            return None
        роды = [_род(v) for v in значения]
        if any(р is None for р in роды):
            continue
        счёт = collections.Counter(роды)
        # РОДЫ ПО ПРЕДМЕТУ ВЫНИМАЮТСЯ ИЗ СЧЁТА, НО НЕ ИЗ ВИДУ: они считаны и названы.
        по_предмету = getattr(м, "РОДЫ_ПО_ПРЕДМЕТУ", None) or {}
        освобождённые.extend(f"{п.stem} · {р}" for р in sorted(по_предмету) if р in счёт)
        for р in по_предмету:
            счёт.pop(р, None)
        if len(счёт) < 2:
            continue
        наим, наиб = min(счёт.values()), max(счёт.values())
        вон.append((_перекос(счёт), п.stem, len(счёт), наим, наиб))
    вон.sort(reverse=True)
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ПЕРЕКОС СЧИТАЕТСЯ ОТНОШЕНИЕМ КРАЙНИХ.

        ПРИБОР СУДИТ ОДНИМ ЧИСЛОМ, И ЧИСЛО ЭТО ЛЕГКО СПУТАТЬ С ТРЕМЯ СОСЕДНИМИ: разностью
        крайних, отношением к среднему, долей наибольшего. Пусть он возьмёт разность — и дом
        из двух родов по тысяче страниц, разошедшихся на единицу, объявится перекошенным.

        НУЛЬ ЗРЯЧЕГО ОБЯЗАН ОТЛИЧАТЬСЯ ОТ НУЛЯ СЛЕПОГО.
    """
    беды = []
    # ПРОБА ЗОВЁТ РАБОТУ ПРИБОРА, А НЕ СЧИТАЕТ РЯДОМ СВОЁ.
    выдумка = collections.Counter({"а": 100, "б": 5, "в": 50})
    дало = _перекос(выдумка)
    if дало != 20.0:
        беды.append(f"перекос сочтён {дало}, а не 20.0 — крайние взяты неверно "
                    "(минимум подменён средним или разностью?)")
    if _перекос(collections.Counter({"а": 7, "б": 7})) != 1.0:
        беды.append("ровный дом сочтён перекошенным")
    if _перекос(collections.Counter({"а": 1001, "б": 1000})) > 1.01:
        беды.append("перекос считается РАЗНОСТЬЮ, а не отношением — большой дом ложно красен")
    # ПОРОГ КРАЙНЕГО ОБЯЗАН БЫТЬ РАЗУМЕН: порог в сто тысяч раз объявит «крайних 0» на любом
    # дворе и будет зелен всегда — тот же слепой нуль, что и при снятом признаке.
    if not 5.0 <= КРАЙНИЙ <= 50.0:
        беды.append(f"порог крайнего {КРАЙНИЙ} вне разумного: при нём число ничего не значит")
    return беды


def main():
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ПЕРЕКОС ДОМА ОТКАЗ: счёт перекоса не доказан ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--двор", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    двор = pathlib.Path(дов.двор) if дов.двор else КОРЕНЬ / "tools"
    if not двор.is_dir():
        print(f"ПЕРЕКОС ДОМА ОТКАЗ: двора нет — {двор}")
        return 2
    освобождённые = []
    ряд = перекосы(двор, освобождённые)
    if not ряд:
        print(f"ПЕРЕКОС ДОМА ОТКАЗ: домов с родами в «{двор}» нет")
        return 2
    крайние = [с for с in ряд if с[0] > КРАЙНИЙ]
    for к, имя, родов, наим, наиб in (ряд if дов.подробно else крайние):
        print(f"  ПЕРЕКОС {имя}: {к:.1f}× — родов {родов}, реже всех {наим}, чаще всех {наиб}")
    ровных = sum(1 for с in ряд if с[0] <= 2)
    средний = sum(с[0] for с in ряд) / len(ряд)
    if дов.подробно and освобождённые:
        for о in освобождённые:
            print(f"  ПО ПРЕДМЕТУ (вне счёта) {о}")
    итог = ("PASS" if len(крайние) <= КРАЙНИХ_РУБЕЖ
            and len(освобождённые) <= ОСВОБОЖДЁННЫХ_РУБЕЖ else "FAIL")
    print(f"ПЕРЕКОС ДОМА {итог}: хуже {КРАЙНИЙ:.0f}× домов {len(крайние)} "
          f"(рубеж {КРАЙНИХ_РУБЕЖ}) из {len(ряд)} с родами; ровнее двукратного {ровных}, "
          f"средний перекос {средний:.2f}×; родов по предмету вне счёта "
          f"{len(освобождённые)} (рубеж {ОСВОБОЖДЁННЫХ_РУБЕЖ})")
    return 0 if итог == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
