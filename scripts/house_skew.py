"""[ПЕРЕКОС ДОМА] — во сколько раз дом показывает один свой род чаще другого.

    ДОМ, ПОКАЗЫВАЮЩИЙ ОДИН РОД В ДВАДЦАТЬ РАЗ ЧАЩЕ ДРУГОГО, УЧИТ ОДНОМУ В ДВАДЦАТЬ РАЗ
    ЛУЧШЕ — и объявляет при этом оба.

ПОВОД, ЗАМЕРЕННЫЙ 12.09 НА СОБСТВЕННЫХ ДОМАХ ЭТОЙ ЖЕ СМЕНЫ. Дом двух «быть» показывает род
«два слова на одно» 26 страницами, а «сосед делит так же» — четырьмя: перекос 6,5×. Дом
слияния — 42 против 8: 5,2×. Дом нидерландского артикля — 22 против 22: ровно.

Ни один из трёх не лгал: все роды объявлены и все написаны. Но читатель, прошедший дом
насквозь, встретит первый род шесть раз на один встреченный последний, — и вынесет из дома
не пять законов, а один закон и четыре упоминания.

    РОД, ОБЪЯВЛЕННЫЙ И ПОКАЗАННЫЙ ВЧЕТВЕРО РЕЖЕ СОСЕДА, ЧЕСТЕН ПО ОБЪЯВЛЕНИЮ И СЛАБ ПО ДЕЛУ.
    Ровность есть мера того, СКОЛЬКО ИЗ ОБЪЯВЛЕННОГО дом успевает сказать.

ЭТО ТОТ ЖЕ ЗАКОН, ЧТО НАЙДЕН ДНЁМ У ВСЕГО СВОДА, И НАЙДЕН ОН БЫЛ ТАК ЖЕ — ЗАМЕРОМ ПОРОЗНЬ:
«im» стои́т 4 775 раз, «ins» — 28, и свод учил не закону, а его половине. Здесь тот же
перекос меряется этажом ниже — внутри дома.

    СВОД, ПОКАЗЫВАЮЩИЙ ОДНУ СТОРОНУ ЗАКОНА В СТО РАЗ ЧАЩЕ ДРУГОЙ, УЧИТ НЕ ЗАКОНУ, А ЕГО
    ПОЛОВИНЕ. Дом — не исключение, и мера у них общая.

ЧЕГО ПРИБОР НЕ ТРЕБУЕТ, И ЭТО ВАЖНЕЕ ТОГО, ЧТО ОН ТРЕБУЕТ. Он НЕ ТРЕБУЕТ РОВНОСТИ: есть
роды, которым довольно одного показа, — довод наружу («сосед делит так же»), граница закона,
единственное исключение. Требовать от них числа, равного основному роду, значило бы
раздувать дом ради меры.

    МЕРА, ТРЕБУЮЩАЯ РОВНОСТИ ОТ ВСЕГО, ЗАСТАВЛЯЕТ ПИСАТЬ ЛИШНЕЕ; МЕРА, НАЗЫВАЮЩАЯ КРАЙНЕЕ,
    ЗАСТАВЛЯЕТ ДУМАТЬ.

Оттого рубеж стои́т лишь на КРАЙНИХ: дома с перекосом хуже двадцатикратного названы поимённо
и сочтены. Замер на день постройки: домов с родами 123, средний перекос 5,54×, медиана
2,02×, ровнее двукратного 61 дом, хуже пятикратного 35, хуже двадцатикратного — ЧЕТЫРЕ:
`dialogueforms` (73,6×), `zerodivforms` (63,0×), `svampforms` (55,5×), `topicforms` (26,5×).

    python3 scripts/house_skew.py [--подробно] [--двор ПУТЬ]
"""
