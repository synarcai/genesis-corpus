#!/usr/bin/env python3
"""[МАССА НА ФОРМУ] — сколько строк мира приходится на ОДИН его скелет.

Закон d5 (04.09): «двадцать четыре показа в ОДНОМ окружении дают ноль
операторов, те же двадцать четыре в ДВУХ — покупку; масса одинаковых строк не
покупает НИЧЕГО сверх первого показа своего рода. Форма родится на ГРАНИЦЕ,
где кончается повтор.» Отсюда мера, которой у корпуса не было: не сколько
строк несёт мир, а сколько строк приходится у него на ОДНУ форму.

    genesis_infer.txt        1080 строк,  72 скелета,  масса на форму 15,0
    genesis_worldfacts.txt    320 строк, 305 скелетов, масса на форму  1,0

Первый мир пишет пятнадцать строк там, где покупается одна форма; второй —
одну. Излишек не ложен и не вреден (тот же d5: слияние и повтор рынку НЕ
мешают, они его лишь не кормят), но он ВЫТЕСНЯЕТ: рядом стоят школьные формы
массой в сорок пять строк, и тысяча строк одного рода перевешивает их в общей
анти-унификации. Так и вышло 04.09: полоса атаки просела 178 → 175 в тот час,
когда в свод вошёл мир с массой пятнадцать.

ЧТО ПРИБОР НЕ ГОВОРИТ: он не зовёт большую массу ложью. Мир счёта обязан
нести много чисел при одной рамке — в числах и состоит его предмет. Прибор
называет ЦЕНУ и оставляет решение дому: там, где масса велика, а форм мало,
лишние строки суть плата за хранение, и срезать их можно без потери формы.

    python3 scripts/mass_per_form.py [--сверху 15] [--рубеж 8]
"""
import argparse
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import form_census as C  # noqa: E402
import genesis  # noqa: E402


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--сверху", type=int, default=15)
    ап.add_argument("--рубеж", type=float, default=8.0)
    а = ап.parse_args()
    ряды = []
    for путь in genesis.worlds(kind="shows"):
        строки = [с.strip() for с in путь.read_text(encoding="utf-8", errors="replace").splitlines()
                  if с.strip() and not с.startswith("\x0c")]
        if not строки:
            continue
        скелеты = {C.род(C.скелет(с)) for с in строки}
        ряды.append((len(строки) / len(скелеты), len(строки), len(скелеты), путь.name))
    ряды.sort(reverse=True)
    print(f"{'масса/форма':>11} {'строк':>7} {'форм':>6}  мир")
    for масса, строк, форм, имя in ряды[:а.сверху]:
        print(f"{масса:11.1f} {строк:7} {форм:6}  {имя}")
    всего_строк = sum(р[1] for р in ряды)
    всего_форм = sum(р[2] for р in ряды)
    тяжёлых = [р for р in ряды if р[0] >= а.рубеж]
    излишек = sum(int(р[1] - р[2] * а.рубеж) for р in тяжёлых)
    print(f"МАССА НА ФОРМУ: всего строк {всего_строк}, форм {всего_форм}, "
          f"в среднем {всего_строк / max(1, всего_форм):.1f}; миров тяжелее {а.рубеж}: "
          f"{len(тяжёлых)} из {len(ряды)}, в них строк сверх рубежа {излишек}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
