#!/usr/bin/env python3
"""[СОГЛАСИЕ ДОМОВ] — два дома, сказавшие о ПРЕДМЕТЕ разное, найдены до ворот.

Дважды за один день дом наступал на объявление соседа, и оба раза ловили его
ВОРОТА — то есть после того, как мир уже был написан и отвергнут целиком:

  · «вода — жидкость» дома фактов мира против «вода — это то, что пьют, когда
    хотят пить» дома бытовых тем: рамки совпали слово в слово, замкнутый суд
    тем прочёл строку своей и назвал ложью;
  · «iron is a metal» и «the sun is a star» — двойники мира genesis_l4, и
    поймал их вовсе прибор ШИРОТЫ ВОПРОСА, с неожиданной стороны.

Ворота — суд последней инстанции, и находить такое ими дорого: мир пишется
целиком и отвергается целиком. Прибор ищет то же в ОБЪЯВЛЕНИЯХ, до всякой
записи, и говорит не «ложь», а «два дома сказали о предмете разное — решите,
кто из них прав или чей это предмет».

ДОМА ПЕРЕЧИСЛЕНЫ ПОИМЁННО, И ЭТО НЕ ЛЕНЬ. Таблицы у них разной формы (у одного
{тема: ((термин, определение), …)}, у другого {язык: ((член, класс), …)}), и
общего вида им никто не объявлял. Перечень честнее вида, которого нет: он
называет, ЧТО именно сличено, и растёт вместе с домами.

    python3 scripts/agree_probe.py
"""
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))


def _сказанное():
    """{(язык, предмет): {дом: сказуемое}} — всё, что дома говорят О ПРЕДМЕТЕ."""
    вон = collections.defaultdict(dict)
    try:
        import topicforms
        for язык, темы in topicforms.ОПРЕДЕЛЕНИЯ.items():
            for пары in темы.values():
                for т, о in пары:
                    вон[(язык, т)]["темы"] = о
    except Exception as е:                      # дом недоступен — видно в отчёте
        print(f"  ДОМ НЕ ПРОЧТЁН topicforms: {е}", file=sys.stderr)
    try:
        import worldfacts
        for язык, ряд in worldfacts.КЛАССЫ.items():
            for ч, к in ряд:
                вон[(язык, ч)]["факты мира"] = к
    except Exception as е:
        print(f"  ДОМ НЕ ПРОЧТЁН worldfacts: {е}", file=sys.stderr)
    try:
        import defforms
        # дом определений держит тройки (термин, РОД, отличие); сличается РОД —
        # то самое, что дом фактов мира зовёт классом, а дом тем растворяет в
        # определении («ручка — инструмент, который пишет»)
        for язык, я in defforms.ЯЗЫКИ.items():
            for тройка in я.get("определения", ()):
                if len(тройка) >= 2:
                    вон[(язык, тройка[0])]["определения"] = тройка[1]
    except Exception as е:
        print(f"  ДОМ НЕ ПРОЧТЁН defforms: {е}", file=sys.stderr)
    return вон


def _лестница():
    """{(язык, класс): надкласс} — объявленная ступень дома фактов мира."""
    try:
        import worldfacts
        return {(язык, к): н for язык, ряд in worldfacts.ИЕРАРХИЯ.items() for к, _, н in ряд}
    except Exception as е:
        print(f"  ЛЕСТНИЦА НЕ ПРОЧТЕНА: {е}", file=sys.stderr)
        return {}


def _одна_лестница(язык, a, b, ступени):
    """Стоят ли два рода на одной лестнице — один над другим, через любое число
    ступеней. РАЗНЫЙ УРОВЕНЬ ЕСТЬ СОГЛАСИЕ, А НЕ СПОР: «дуб — дерево» и «дуб —
    растение» оба истинны, и корпус, объявивший ступень между ними, вправе
    говорить обоими. Спор есть лишь то, что лестницей НЕ СВЯЗАНО."""
    for низ, верх in ((a, b), (b, a)):
        текущий, шагов = низ, 0
        while текущий is not None and шагов < 8:
            if текущий == верх:
                return True
            текущий = ступени.get((язык, текущий))
            шагов += 1
    return False


def main():
    # ПРЕДСТАВЛЕННОЕ «НЕТ» (М-106): подсаженный спор обязан находиться, а
    # согласие двух домов об одном и том же — не обязано.
    проба = {("ru", "вода"): {"темы": "то, что пьют", "факты мира": "жидкость"},
             ("ru", "лёд"): {"темы": "твёрдая вода", "факты мира": "твёрдая вода"}}
    споры = [к for к, д in проба.items() if len(set(д.values())) > 1]
    if споры != [("ru", "вода")]:
        print(f"СОГЛАСИЕ ДОМОВ FAIL: подсадка не сходится ({споры}) — прибор не годен")
        return 1
    сказанное = _сказанное()
    ступени = _лестница()
    спорных = ступенями = 0
    for (язык, предмет), дома in sorted(сказанное.items()):
        if len(дома) < 2:
            continue
        значения = set(дома.values())
        if len(значения) < 2:
            continue                            # сказали одно и то же — согласие
        печать = "; ".join(f"{д}: «{з}»" for д, з in sorted(дома.items()))
        пары = sorted(значения)
        if len(пары) == 2 and _одна_лестница(язык, пары[0], пары[1], ступени):
            ступенями += 1
            continue
        спорных += 1
        print(f"  СПОР [{язык}] «{предмет}» — {печать[:150]}")
    предметов = len(сказанное)
    общих = sum(1 for д in сказанное.values() if len(д) > 1)
    поза = "PASS" if спорных == 0 else "FAIL"
    print(f"СОГЛАСИЕ ДОМОВ {поза}: {спорных} споров из {общих} предметов, о которых "
          f"говорит больше одного дома (всего предметов {предметов}, домов сличено 3); "
          f"подсадка сходится; разный уровень ОДНОЙ лестницы (согласие) {ступенями}")
    if общих == 0:
        print("  ВНИМАНИЕ: общих предметов НОЛЬ — сличать нечего, и этот ноль есть "
              "немота прибора, а не согласие домов (М-264)")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
