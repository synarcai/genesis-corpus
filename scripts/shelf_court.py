#!/usr/bin/env python3
"""СУД ПОЛКИ: «очень качественные тексты» — это число, а не похвала.

Владелец поставил внешним книгам одно условие: «чтобы там не было
нейрослопа и тексты были очень качественными». Условие, которое нельзя
исполнить прибором, есть пожелание; договор `declarations/SHELF.md`
обратил его в признаки, а этот суд их проверяет.

ЧТО СВЕРЯЕТСЯ:

    ОБЪЯВЛЕНИЕ — у мира полки есть все поля договора, и `тема`,
        `плотность`, `источник`, `язык` взяты из закрытых наборов
        (`tools/shelf_kinds.py`). «Взято из интернета» не есть
        происхождение: поле `происхождение` обязано быть названо;
    ЧИСТОТА ПРОИСХОЖДЕНИЯ — `издано` против рубежа машины (2022):
        общественное достояние обязано быть издано до 1929, свободная
        лицензия — до рубежа, а всё, что издано ПОСЛЕ рубежа, обязано
        назвать источник `named-author` и человека-автора;
    ПЛОТНОСТЬ — доля предложений, несущих определение, вывод или
        ссылку на утверждение. Мир, объявивший себя трактатом или
        статьёй, обязан её иметь; «пересказ» на полке не лежит вовсе;
    СЛОВАРНАЯ НОВИЗНА — сколько слов книга приносит СВЕРХ прожитых
        показами и сверх прочих сводов прозы. Ноль значит, что книга
        уже лежит на полке под другим именем;
    ОТЛОЖЕННОЕ — файл `held_out` есть, непуст и НЕ ПЕРЕСЕКАЕТСЯ с
        телом мира: отложенное, лежащее и там и там, не отложено.

И ГЛАВНОЕ — СУДИМОСТЬ, ГДЕ ОБЪЯВЛЕНИЕ СВЕРЯЕТСЯ С ДЕЛОМ. Поле
`судится` называет суды, читающие этот текст, и палата — сама тот, кто
читает, — сверяет объявление с чтением. Стороны две, и вес их разный:
названный суд, не читающий НИ ОДНОЙ строки, есть ЛОЖЬ (объявивший
сказал то, чего нет); читающий суд, не названный в объявлении, есть
ДОЛГ (объявление неполно, но не лживо — состав палаты растёт чужими
руками, и вчерашняя правда становится неполной без ведома
объявившего).

ДОЛГ, А НЕ ЛОЖЬ: КНИГА, КОТОРУЮ НЕ ЧИТАЕТ НИКТО. Договор зовёт такой
мир грудой байтов, и он прав; но суды корпуса писаны для показов, и
русский трактат сегодня не читает никто, кроме суда русской грамматики
на редких строках. Запретить это значило бы запретить полку. Потому
число таких миров объявлено ДОЛГОМ: расти ему нельзя, убывать можно, и
всякий новый суд прозы опускает его собой.

ЧЕГО ЭТОТ СУД НЕ ДЕЛАЕТ, И ЭТО СКАЗАНО ЧИСЛОМ. Он не доказывает, что
мир не читает НИКТО: такое утверждение всеобще и стоит полного обхода
семнадцати мегабайт полки палатой в полсотни судов — часы на каждом
прогоне, при том что миры прибывают чужими руками ежечасно. Он
проверяет ОБЪЯВЛЕННОЕ: названный суд обязан прочесть строку (обход
останавливается, едва все названные найдены), а мир, объявивший
`судится: []`, зачитывается в долг ПО СВОЕМУ ЖЕ ОБЪЯВЛЕНИЮ — он сам
сказал, что его не читают. Уклониться пустым списком нельзя: пустой
список и есть признание.
"""

import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
for _где in (КОРЕНЬ / "tools", КОРЕНЬ / "courts", КОРЕНЬ / "scripts"):
    if str(_где) not in sys.path:
        sys.path.insert(0, str(_где))
import genesis  # noqa: E402
import shelf_kinds  # noqa: E402
from panel import палата  # noqa: E402

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 0
РАЗЛАДОВ_РУБЕЖ = 0

# РУБЕЖ-ДОЛГА: НЕДОГОВОРЁННЫХ_РУБЕЖ = 3
#
# ЗАМЕР 02.09 по тридцати мирам полки: три суда читают мир, не будучи
# названными в его объявлении, — половины у Милля, половины и формула у
# Пуанкаре. Это неполнота объявления, а не обман, и потому долг: состав
# палаты растёт чужими руками, и вчерашняя правда становится неполной
# без ведома объявившего. Число это НИЖНЯЯ ОЦЕНКА: обход мира
# останавливается, едва найдены все названные суды, и сторонний
# читатель за этой точкой не ищется.
НЕДОГОВОРЁННЫХ_РУБЕЖ = 3

# РУБЕЖ-ДОЛГА: НЕЧИТАЕМЫХ_РУБЕЖ = 15
#
# СЧИТАЮТСЯ ОБЪЯВИВШИЕ `судится: []` — те, кто сам сказал, что его не
# читает никто.
#
# ЗАМЕР 02.09: из тридцати миров полки пятнадцать не назвали ни одного
# суда — половина. Русский трактат читает почти только суд русской
# грамматики, и то на четырёх строках из тысячи; суд структуры прозы
# судит ссылку на СВОЁ дерево («см. §5», «по Теореме 8.3»), а книга
# 1897 года ссылается на чужие труды и на главы словами, а не номерами.
# Это находка о наших судах, а не о книгах, и потому долг, а не
# обвинение; но расти ему нельзя: договор полки прямо говорит, что
# полка без судимости лишь растит знаменатель.
НЕЧИТАЕМЫХ_РУБЕЖ = 15

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest

ДОМ_ПОЛКИ = "shelf/"

# ЛЕНТА: СУД ОДНОЙ КНИГИ. Полный обход читает четырнадцать книг палатой
# в полсотни судов и стоит минут; правящему одну книгу это дорого, а
# отвечает суд на тот же вопрос. С лентой долги не считаются — они о
# полке целиком, — и вердикт говорит об этом вслух.
ЛЕНТА = "--мир"


def набором(мир, имя, разлады):
    """Поля договора есть, и значения их — из объявленных наборов."""
    for поле in shelf_kinds.ПОЛЯ_ПОЛКИ:
        if поле not in мир:
            разлады.append(f"{имя}: поля «{поле}» нет — договор полки "
                           f"требует его у всякого мира полки")
    for поле, набор in shelf_kinds.НАБОРЫ:
        значение = мир.get(поле)
        if значение is not None and значение not in набор:
            разлады.append(
                f"{имя}: {поле} «{значение}» вне объявленного набора")
    if not isinstance(мир.get("издано"), int):
        разлады.append(f"{имя}: издано «{мир.get('издано')}» не год")
    if not isinstance(мир.get("судится"), list):
        разлады.append(f"{имя}: судится объявлено не списком")
    if not str(мир.get("происхождение") or "").strip():
        разлады.append(
            f"{имя}: происхождение не названо — «взято из интернета» "
            f"не есть происхождение")


def чистотой(мир, имя, разлады):
    """Дата отсекает машину, а источник обязан ей соответствовать."""
    год, источник = мир.get("издано"), мир.get("источник")
    if not isinstance(год, int):
        return
    if год >= shelf_kinds.РУБЕЖ_МАШИНЫ:
        # ПОСЛЕ РУБЕЖА МАШИНЫ ЧЕЛОВЕК НАЗЫВАЕТСЯ ПОИМЁННО. Дата больше
        # не свидетельствует, и единственное, что остаётся, — названное
        # авторство; безымянный текст этих лет неотличим от машинного.
        if источник != "named-author":
            разлады.append(
                f"{имя}: издано {год} — после рубежа машины "
                f"{shelf_kinds.РУБЕЖ_МАШИНЫ}, а источник «{источник}»: "
                f"после рубежа берётся лишь названное человеком")
        if not str(мир.get("автор") or "").strip():
            разлады.append(
                f"{имя}: издано {год} — после рубежа машины, а автор не "
                f"назван: безымянное этих лет от машинного неотличимо")
    if (источник == "public-domain"
            and год > shelf_kinds.РУБЕЖ_ОБЩЕСТВЕННОГО):
        разлады.append(
            f"{имя}: источник «public-domain», а издано {год} — позже "
            f"рубежа общественного {shelf_kinds.РУБЕЖ_ОБЩЕСТВЕННОГО}")
    if источник == "free-license" and год >= shelf_kinds.РУБЕЖ_МАШИНЫ:
        разлады.append(
            f"{имя}: источник «free-license», а издано {год} — не "
            f"раньше рубежа машины {shelf_kinds.РУБЕЖ_МАШИНЫ}")


def отложенным(мир, имя, тело, разлады):
    """Отложенное отложено, если его в теле НЕТ."""
    объявлено = мир.get("held_out")
    if not объявлено:
        return
    путь = genesis._resolve(объявлено)
    if not путь.is_file():
        разлады.append(f"{имя}: отложенного файла нет — {объявлено}")
        return
    отложенное = путь.read_text(encoding="utf-8", errors="replace").strip()
    if not отложенное:
        разлады.append(f"{имя}: отложенное пусто")
        return
    # СВЕРЯЕТСЯ КУСОК ЦЕЛИКОМ, А НЕ ОТДЕЛЬНЫЕ СТРОКИ. Первая редакция
    # искала совпадение построчно и обвинила пять честных миров: у книги
    # с разделами заголовок «Логика» законно стоит и в теле, и в
    # отложенном хвосте. Отложено то, чего в теле НЕТ КАК КУСКА.
    if отложенное in тело:
        разлады.append(
            f"{имя}: отложенное стоит и в теле — отложенное, лежащее и "
            f"там и там, не отложено")


def кем_читается(суд, путь, ждём):
    """Имена судов, прочитавших хоть строку мира.

    ОБХОД ОСТАНАВЛИВАЕТСЯ, КОГДА ОТВЕТ УЖЕ ПОЛУЧЕН: если все
    объявленные суды прочли по строке и ни один сторонний не
    объявился, дальше читать нечего. Полный обход остаётся там, где он
    нужен, — когда объявленного суда всё ещё не видно.
    """
    слои = суд.слои(путь)
    пласт = суд.пласт_файла(путь)
    видены = set()
    with путь.open(encoding="utf-8", errors="replace") as поток:
        for строка in поток:
            if not строка.strip():
                continue
            _судимо, _истинно, кем = суд.судить(строка, слои, пласт)
            видены.update(кем)
            if ждём and ждём <= видены:
                break
    return видены


def main():
    if "--manifest" in sys.argv:
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        миры = genesis.manifest()["worlds"]
    except (genesis.Unreadable, KeyError) as беда:
        print(f"ПОЛКА ОТКАЗ: {беда}")
        return 2
    полка = [м for м in миры if "источник" in м]
    лента = [а for i, а in enumerate(sys.argv)
             if i and sys.argv[i - 1] == ЛЕНТА]
    if лента:
        полка = [м for м in полка if м.get("name") in лента]
    подкидыши = [м for м in миры
                 if ДОМ_ПОЛКИ in str(м.get("file", ""))
                 and "источник" not in м]
    if not полка:
        print("ПОЛКА ОТКАЗ: миров полки не объявлено, судить нечего")
        return 2
    разлады = []
    for мир in подкидыши:
        разлады.append(
            f"{мир.get('name', '?')}: лежит в {ДОМ_ПОЛКИ}, а источника "
            f"не объявляет — мир полки без договора")
    # СЛОВАРЬ ЧУЖОГО СОБИРАЕТСЯ ОДИН РАЗ: показы прожиты, прочие своды
    # прозы прочитаны, и новизна книги есть то, чего нет ни там ни там.
    прожито = set()
    по_мирам = {}
    for мир in миры:
        # СБОРКА СВОЕЙ СТРОКИ НЕ НЕСЁТ, и слова её суть слова показов,
        # уже посчитанные: читать её значило бы читать корпус дважды.
        if мир.get("text") == "mix":
            continue
        путь = genesis._resolve(мир.get("file", ""))
        if not путь.is_file():
            continue
        свои = shelf_kinds.слова(
            путь.read_text(encoding="utf-8", errors="replace"))
        if мир.get("text") == "shows":
            прожито |= свои
        else:
            по_мирам[мир.get("name")] = свои
    суд = палата()
    нечитаемых, недоговорено, строки_отчёта = [], [], []
    for мир in полка:
        имя = мир.get("name", "?")
        набором(мир, имя, разлады)
        чистотой(мир, имя, разлады)
        путь = genesis._resolve(мир.get("file", ""))
        if not путь.is_file():
            разлады.append(f"{имя}: файла нет — {мир.get('file')}")
            continue
        if ДОМ_ПОЛКИ not in str(мир.get("file", "")):
            разлады.append(
                f"{имя}: объявляет источник, а лежит вне {ДОМ_ПОЛКИ}")
        тело = путь.read_text(encoding="utf-8", errors="replace")
        отложенным(мир, имя, тело, разлады)
        доля, предложений, _счёт = shelf_kinds.плотность(тело)
        объявлена = мир.get("плотность")
        if объявлена == "пересказ":
            разлады.append(
                f"{имя}: объявлен пересказом — договор полки таких не "
                f"кладёт вовсе")
        elif (объявлена in shelf_kinds.ПЛОТНОСТИ
                and доля < shelf_kinds.ПОРОГ_ПЛОТНОСТИ):
            разлады.append(
                f"{имя}: объявлен «{объявлена}», а плотность "
                f"{100 * доля:.1f}% ниже порога "
                f"{100 * shelf_kinds.ПОРОГ_ПЛОТНОСТИ:.0f}%")
        чужие = set()
        for другое, слова_мира in по_мирам.items():
            if другое != имя:
                чужие |= слова_мира
        новых = len(по_мирам.get(имя, set()) - прожито - чужие)
        if not новых:
            разлады.append(
                f"{имя}: не приносит ни одного нового слова — книга, "
                f"уже лежащая на полке под другим именем")
        объявленные = set(мир.get("судится") or ())
        призраки = объявленные - set(суд.суды)
        for призрак in sorted(призраки):
            разлады.append(
                f"{имя}: судится «{призрак}» — такого суда в палате нет")
        # ОБХОД — ТОЛЬКО РАДИ ОБЪЯВЛЕННОГО. Мир, никого не назвавший,
        # не читается вовсе: его признание уже сказано списком.
        читают = (кем_читается(суд, путь, объявленные - призраки)
                  if объявленные - призраки else set())
        for молчун in sorted(объявленные - призраки - читают):
            разлады.append(
                f"{имя}: объявлен судимым судом «{молчун}», а тот не "
                f"читает ни одной его строки")
        # НЕДОГОВОРЁННОЕ — ДОЛГ, А НЕ ЛОЖЬ, И ПРИЧИНА НАЗВАНА. Суд,
        # читающий мир и не названный в объявлении, есть неполнота
        # объявления, а не обман: состав палаты растёт чужими руками, и
        # вчерашняя правда становится неполной без ведома объявившего.
        # Названный же и молчащий — ложь: так объявивший СКАЗАЛ то,
        # чего нет.
        недоговорено.extend(
            f"{имя}: {суд_}" for суд_ in sorted(читают - объявленные))
        if not объявленные:
            нечитаемых.append(имя)
        строки_отчёта.append(
            f"  {имя:<22}{предложений:>6} предл, плотность "
            f"{100 * доля:5.1f}%, новых слов {новых:>5}, "
            f"судится {sorted(читают) or '—'}")
    for с in строки_отчёта:
        print(с)
    for р in разлады[:8]:
        print(f"  РАЗЛАД {р}")
    for н in недоговорено[:6]:
        print(f"  НЕДОГОВОРЕНО {н} читает мир, а `судится` о нём молчит")
    плохо = len(разлады) > РАЗЛАДОВ_РУБЕЖ or (
        not лента and (len(нечитаемых) > НЕЧИТАЕМЫХ_РУБЕЖ
                       or len(недоговорено) > НЕДОГОВОРЁННЫХ_РУБЕЖ))
    поза = "FAIL" if плохо else "PASS"
    хвост = (f", не читает никто {len(нечитаемых)} миров (рубеж "
             f"{НЕЧИТАЕМЫХ_РУБЕЖ}), недоговорено {len(недоговорено)} "
             f"(рубеж {НЕДОГОВОРЁННЫХ_РУБЕЖ})" if not лента
             else " — ЛЕНТА, долги полки не считаны")
    print(f"ПОЛКА {поза}: {len(разлады)} разладов объявления с делом "
          f"(рубеж {РАЗЛАДОВ_РУБЕЖ}){хвост} — {len(полка)} миров "
          f"полки, судов живых {суд.живых}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
