#!/usr/bin/env python3
"""[ЗАКОН ПЕРВЫМ] — докстринг, сдвинутый ввозом, есть не докстринг, а строка ни о чём.

    ЗАКОН, НАПИСАННЫЙ ДЛЯ ЧЕЛОВЕКА И НЕВИДИМЫЙ МАШИНЕ, ЕСТЬ ПОЛОВИНА ЗАКОНА. Строковый
    литерал становится докстрингом ЛИШЬ первым в теле модуля; стоит поставить над ним ввоз —
    и две тысячи знаков объявленного закона превращаются в выражение, которое Python
    вычисляет и выбрасывает. Файл читается по-прежнему, `__doc__` есть None.

ПОВОД. Дом речевого обихода объявляет девять языков и пять форм показа; его закон занимает
2079 знаков. Первая строка файла — `import closedworld`, вторая — шебанг, третья — тройная
кавычка. `dialogueforms.__doc__` есть None, и всякий прибор, спрашивающий у модуля его закон,
получает от этого дома МОЛЧАНИЕ.

    ТА ЖЕ ПРИРОДА, ЧТО У ПУСТОГО ВХОЖДЕНИЯ И У КИРИЛЛИЦЫ В ПОДСТАНОВКЕ: файл говорит одно,
    машина читает другое, и НИЧТО НЕ ПАДАЕТ. Против таких дыр и ставятся приборы — крикливая
    ошибка находит себя сама.

ЧТО СЧИТАЕТСЯ НАХОДКОЙ, И ГРАНИЦА ВЗЯТА УЗКО. Строковый литерал, стоящий в теле модуля
ОТДЕЛЬНЫМ ВЫРАЖЕНИЕМ и НЕ ПЕРВЫМ. Отсутствие докстринга вовсе находкой НЕ считается: два дома
парка (`gen_genesis_l4`, `planlang`) объявили свой закон РЕШЁТКОЙ, и это выбор письма, а не
порча — их закон читается ровно так, как написан. Порча же есть РАСХОЖДЕНИЕ НАМЕРЕНИЯ С ДЕЛОМ:
рука писала докстринг, вышло выражение.

ЗАМЕР ДО ПРИБОРА: 611 файлов парка, находок ТРИ — `crossforms` (1564 знака), `dialogueforms`
(2079), `topicforms` (1409). Все три вылечены переносом ввоза под закон; рубеж есть НОЛЬ и есть
ПОЛ, ибо цена лечения — перенос строки.

    python3 scripts/lawfirst_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-park-dir
import ast
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: СДВИНУТЫХ_РУБЕЖ = 0
#
# Поставлен на трёх и закрыт в тот же час. Число есть ПОЛ: дом, чей ввоз завтра встанет над
# законом, роняет прибор в тот же час, когда его напишут, — а не через месяц, когда кто-то
# спросит у дома его `__doc__` и получит None.
СДВИНУТЫХ_РУБЕЖ = 0


def сдвинутые(дерево):
    """Строковые литералы тела модуля, стоящие НЕ первыми."""
    вон = []
    for место, узел in enumerate(дерево.body):
        if место == 0:
            continue
        if (isinstance(узел, ast.Expr) and isinstance(узел.value, ast.Constant)
                and isinstance(узел.value.value, str)):
            вон.append((узел.lineno, len(узел.value.value)))
    return вон


def main():
    файлов, битые = 0, []
    for путь in sorted(КОРЕНЬ.rglob("*.py")):
        if ".git" in путь.parts:
            continue
        файлов += 1
        try:
            дерево = ast.parse(путь.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        for строка, длина in сдвинутые(дерево):
            битые.append(f"{путь.relative_to(КОРЕНЬ)}:{строка}: "
                         f"литерал в {длина} знаков стои́т не первым — "
                         f"перенесите ввоз ПОД него")
    if not файлов:
        print("ЗАКОН ПЕРВЫМ ОТКАЗ: ни одного файла .py")
        return 2
    for б in битые[:20]:
        print(f"  {б}")
    поза = "PASS" if len(битые) <= СДВИНУТЫХ_РУБЕЖ else "FAIL"
    print(f"ЗАКОН ПЕРВЫМ {поза}: докстрингов, сдвинутых с первого места, {len(битые)} "
          f"(рубеж {СДВИНУТЫХ_РУБЕЖ}); файлов {файлов}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
