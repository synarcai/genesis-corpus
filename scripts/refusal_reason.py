#!/usr/bin/env python3
"""[ЗАПРЕТ БЕЗ ПРИЧИНЫ] — пласт отвергает форму, а объясняет ли её кто-нибудь.

    ПОКАЗ ОТКАЗА УЧИТ, ЧТО ТАК НЕЛЬЗЯ, И НЕ УЧИТ, ПОЧЕМУ. Ученик запоминает список запретов
    вместо одного правила — и первый же случай вне списка берёт наугад.

ПОВОД. Третий род молчания (`declarations/UNNAMED-LAW.md`) найден 12.09 на суахили: пласт
отвергал «kitabu mmoja» пятнадцатью строками и не говорил, почему. Замер по всем двадцати
девяти пластам показал, что отказы есть У КАЖДОГО — по пять-шесть различных на язык, — и что
это устройство кузни пакетов, а не особенность языка.

    ЗАКОН, НАЙДЕННЫЙ В ОДНОМ ЯЗЫКЕ, НЕ ЕСТЬ ЗАКОН ЭТОГО ЯЗЫКА: он есть ВОПРОС, который
    следует задать остальным двадцати восьми.

Прибор задаёт этот вопрос машинно: у скольких языков, чей пласт ЧТО-ТО ОТВЕРГАЕТ, есть дом
неназванного закона, объясняющий их речь. Связь «пласт → дом» не угадывается по словам
докстринга, а ОБЪЯВЛЯЕТСЯ домом: `ЯЗЫК_ЗАКОНА = "tr"`.

    СВЯЗЬ, УГАДЫВАЕМАЯ ПО СЛОВАМ, РАЗОЙДЁТСЯ С ДЕЛОМ В ТОТ ДЕНЬ, КОГДА СЛОВО ПЕРЕПИШУТ.
    Объявленная связь переживает всякую правку прозы.

ЧИСЛО ЭТО — ОТЧЁТ, А НЕ РУБЕЖ, И СКАЗАНО ПОЧЕМУ: дом строится не ради покрытия, а ради
закона, который стои́т назвать. Требовать дома для каждого из двадцати девяти значило бы
заказать двадцать девять домов прежде, чем найден хоть один их закон.

    МЕРА, ТРЕБУЮЩАЯ ПОЛНОТЫ ОТ ТОГО, ЧТО РАСТЁТ ПО ОДНОМУ, ТОРОПИТ ПИСЦА И ПОРТИТ РАБОТУ.

    python3 scripts/refusal_reason.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --двор no-such-dir
import argparse
import importlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ОТКАЗ = "¬"


def отказы_пластов(двор):
    """{язык: число различных строк отказа} по языковым пластам свода."""
    вон = {}
    for п in sorted(pathlib.Path(двор).glob("genesis_lang_*.txt")):
        язык = п.stem.replace("genesis_lang_", "")
        строки = {с.strip() for с in п.read_text(encoding="utf-8", errors="replace").splitlines()
                  if с.strip().startswith(ОТКАЗ)}
        if строки:
            вон[язык] = len(строки)
    return вон


def дома_по_языкам(двор):
    """{язык: [имена домов]} — по объявленному в доме `ЯЗЫК_ЗАКОНА`."""
    вон = {}
    for п in sorted(pathlib.Path(двор).glob("*forms.py")):
        try:
            м = importlib.import_module(п.stem)
        except Exception:                                   # noqa: BLE001
            continue
        язык = getattr(м, "ЯЗЫК_ЗАКОНА", None)
        if isinstance(язык, str) and язык:
            вон.setdefault(язык, []).append(п.stem)
        elif isinstance(язык, (tuple, list)):
            for я in язык:
                вон.setdefault(я, []).append(п.stem)
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ОТКАЗ УЗНАЁТСЯ ПО НАЧАЛУ СТРОКИ.

        ЗНАК «¬» ЖИВЁТ В СВОДЕ ДВУМЯ ЖИЗНЯМИ (`declarations/STARRED.md`): в начале строки он
        МЕТКА ОТКАЗА, внутри формулы — логическое «не». Замер на день объявления: 964 в
        начале, 584 внутри. Прибор, считающий все вхождения, насчитал бы отказов там, где их
        нет, и объявил бы долг по чужому знаку.

        НУЛЬ ЗРЯЧЕГО ОБЯЗАН ОТЛИЧАТЬСЯ ОТ НУЛЯ СЛЕПОГО.
    """
    import tempfile
    беды = []
    строки = ("¬ два кіт.",
              "знак ¬ читается как не.",
              "matches(x) ⇒ ¬ y.",
              "¬ два кіт.",
              "обычная строка без знака.")
    with tempfile.TemporaryDirectory() as д:
        (pathlib.Path(д) / "genesis_lang_xx.txt").write_text(
            "\n".join(строки) + "\n", encoding="utf-8")
        дало = отказы_пластов(д)
    if дало.get("xx") != 1:
        беды.append(f"различных отказов сочтено {дало.get('xx')}, а не 1 — "
                    "знак внутри строки принят за метку отказа или повтор не свёрнут")
    with tempfile.TemporaryDirectory() as д:
        (pathlib.Path(д) / "genesis_lang_yy.txt").write_text(
            "нет здесь отказов вовсе.\n", encoding="utf-8")
        пусто = отказы_пластов(д)
    if пусто:
        беды.append(f"пласт без отказов сочтён отвергающим: {пусто}")
    return беды


def main():
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ЗАПРЕТ БЕЗ ПРИЧИНЫ ОТКАЗ: чтение метки не доказано ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--двор", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    двор = pathlib.Path(дов.двор) if дов.двор else КОРЕНЬ / "datasets"
    if not двор.is_dir():
        print(f"ЗАПРЕТ БЕЗ ПРИЧИНЫ ОТКАЗ: двора нет — {двор}")
        return 2
    отказы = отказы_пластов(двор)
    if not отказы:
        print(f"ЗАПРЕТ БЕЗ ПРИЧИНЫ ОТКАЗ: пластов с отказами в «{двор}» нет")
        return 2
    дома = дома_по_языкам(КОРЕНЬ / "tools")
    с_домом = {я: д for я, д in дома.items() if я in отказы}
    без_дома = sorted(я for я in отказы if я not in дома)
    if дов.подробно:
        for я in sorted(отказы):
            кто = ", ".join(дома.get(я, ())) or "—"
            print(f"  {я}: отказов {отказы[я]}, объясняет {кто}")
    print(f"ЗАПРЕТ БЕЗ ПРИЧИНЫ ОТЧЁТ: пластов с отказами {len(отказы)}, "
          # НОЛЬ БЕЗ ОБЪЁМА ЕСТЬ МОЛЧАНИЕ, А НЕ ПОКАЗАНИЕ (закон holon, 16.09): «БЕЗ
          # ДОМА 0» не говорит, из скольких, и потому неотличимо от «не считали».
          f"объяснено домами {len(с_домом)}, БЕЗ ДОМА {len(без_дома)} из {len(отказы)}"
          + (f": {', '.join(без_дома[:10])}" if без_дома else "")
          + f"; домов, объявивших свой язык, {sum(len(д) for д in дома.values())}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
