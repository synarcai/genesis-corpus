#!/usr/bin/env python3
"""[ДВЕ РАМКИ НА ОДНОЙ ЗАПИСИ] — род, какой суд решает порядком перебора, а не делом.

Дом пишет страницы по рамкам и судит их теми же рамками. Пока рамки РАЗВЕДЕНЫ, всякая запись
ложится ровно в одну, и суд узнаёт по ней, ЧТО на странице обещано. Но стоит двум рамкам
сойтись на одной записи —

    ДВЕ РАМКИ, СОВПАДАЮЩИЕ НА ОДНОЙ ЗАПИСИ, ДЕЛАЮТ РОД НЕРАЗЛИЧИМЫМ. Суд решает тогда
    ПОРЯДКОМ ПЕРЕБОРА рамок, то есть случайностью записи в дереве, а не делом страницы.
    Перестановка двух строк в объявлении дома молча меняет вердикт — и ни один нынешний
    прибор этого не видит: суд зелен, покрытие полно, ложных нет.

Так 14.09 дом двух процентов писал «стало 198, а не 200» для рода «не возвращается», и эта
запись ложилась ТАКЖЕ в рамку рода «не складываются», где «200» читалось наивным ответом.
Поймала самопроверка дома; прибор ниже ловит то же по всем домам разом.

ЗАЙМ НАЗВАН ВСЛУХ. Прибор читает лишь тех, кто объявил рамки поимённо — модулем с
`_ОБРАЗЦЫ` или `ОБРАЗЦЫ` вида {язык: [(имя, образец)]} либо {язык: {имя: образец}}. Дома,
чьи рамки собраны иначе, названы числом и НЕ ПРОЧИТАНЫ: это займ, а не молчание.

usage: scripts/frames_apart.py [--дом ИМЯ …]
"""
import importlib
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: ДВОЙНЫХ = 0
ДВОЙНЫХ = 0
ИМЕНА_РАМОК = ("_ОБРАЗЦЫ", "ОБРАЗЦЫ")


def _пары(объявление):
    """{язык: [(имя, образец)]} из любой из двух объявленных форм — или None."""
    if not isinstance(объявление, dict):
        return None
    вон = {}
    for язык, свои in объявление.items():
        if isinstance(свои, dict):
            пары = list(свои.items())
        elif isinstance(свои, (list, tuple)):
            пары = [п for п in свои if isinstance(п, (list, tuple)) and len(п) == 2]
        else:
            return None
        if not пары or not all(hasattr(о, "fullmatch") for _и, о in пары):
            return None
        вон[язык] = пары
    return вон or None


def дома():
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        if путь.stem.startswith("gen_") or путь.stem.startswith("_"):
            continue
        yield путь.stem


def main():
    только = set(sys.argv[sys.argv.index("--дом") + 1:]) if "--дом" in sys.argv else None
    прочитано = пропущено = страниц = двойных = сломан = 0
    беда = []
    for имя in дома():
        if только and имя not in только:
            continue
        try:
            дом = importlib.import_module(имя)
        except Exception:
            сломан += 1
            continue
        показы = getattr(дом, "ПОКАЗЫ", None)
        рамки = next((_пары(getattr(дом, и)) for и in ИМЕНА_РАМОК
                      if isinstance(getattr(дом, и, None), dict)), None)
        if not isinstance(показы, dict) or рамки is None:
            пропущено += 1
            continue
        прочитано += 1
        for показ, знак in показы.items():
            язык = знак[0] if isinstance(знак, tuple) else None
            свои = рамки.get(язык) or [п for с in рамки.values() for п in с]
            совпали = [и for и, о in свои if о.fullmatch(показ.strip())]
            страниц += 1
            if len(совпали) > 1:
                двойных += 1
                if len(беда) < 8:
                    беда.append((имя, совпали, показ))
    for имя, совпали, показ in беда:
        print(f"  ДВЕ РАМКИ ({', '.join(совпали)}) в доме {имя}: {показ[:100]}")
    поза = "PASS" if двойных <= ДВОЙНЫХ else "FAIL"
    print(f"ДВЕ РАМКИ НА ОДНОЙ ЗАПИСИ {поза}: {двойных} страниц из {страниц} ложатся в две "
          f"рамки (рубеж {ДВОЙНЫХ}); домов прочитано {прочитано}, "
          f"без объявленных рамок {пропущено} — ЗАЙМ, не молчание; не ввезлось {сломан}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
