#!/usr/bin/env python3
"""[ПОЧВА ОТКАЗА] — есть ли в пласте показы, на которых можно построить дом для этого отказа.

    ОТКАЗ, ЧЬЮ ЗАМЕНУ ПЛАСТ ПОКАЗЫВАЕТ ПЯТЬЮ СТРОКАМИ И БОЛЬШЕ НИЧЕМ, НЕ ЖДЁТ ДОМА — ОН ЖДЁТ
    ПОКАЗОВ. Дом, построенный на пяти строках, объявит таблицей то, чего свод не показывает.

ПОВОД, ПРОЖИТЫЙ 13.09 ЧЕТЫРЕЖДЫ. Четыре раза за смену дом останавливался на одном и том же:

    тайский разряд          «เล่ม» и «ตัว» стоя́т в своде ТОЛЬКО под чертой
    ивритский род числа     «שלושה ספרים» — пять строк, и это ЕДИНСТВЕННАЯ пара во всём пласте
    испанское «cantas»      ноль утвердительных строк
    турецкое «okuyorsun»    ноль утвердительных строк

И на пятый раз — целым рядом: «множественное после числа» отвергают ПЯТНАДЦАТЬ языков, а пар
«число + имя» пласты почти не показывают.

    РЯД, СТРОЙНЫЙ В ОТКАЗАХ, МОЖЕТ БЫТЬ ПУСТ В ПОКАЗАХ.

Прежде это находилось РУКОЙ и всякий раз заново — уже начав дом. Прибор спрашивает то же
машинно и ДО того, как на дом потрачен час.

ЧТО СЧИТАЕТСЯ. Берутся СОДЕРЖАТЕЛЬНЫЕ слова отвергнутого И его замены — все, кроме
числительных пакета и слов короче трёх знаков, — и в пласте считаются строки, несущие хоть
одно из них. Число это есть ПОЧВА отказа: сколько материала лежит рядом.

    ПОЧВА МЕРИТСЯ ОБОИМИ — И ОТВЕРГНУТЫМ, И ЗАМЕНОЙ (13.09, куплено ложным нулём). Первая
    редакция мерила одной заменой и назвала пустыми украинское «я читаєш» и польское «ja
    czytasz»: замена у них берёт ДРУГОЙ ГЛАГОЛ («я танцюю», «ja tańczę»), и родни у неё пять
    строк. А форма «читаєш» стои́т в пласте двадцать четыре раза — при своём лице.

    ЗАМЕНА, ВЗЯВШАЯ ДРУГОЙ ГЛАГОЛ, НЕ ГОВОРИТ О ПОЧВЕ ОТВЕРГНУТОГО: пласт богат формами
    «читати», а мера считала строки о «танцювати».

    И МЕРИТСЯ ОДНИМ СЛОВОМ, А НЕ ДВУМЯ: отказ бывает в два слова («два кіт»), и требовать
    двух общих значило бы требовать от пласта повторить весь отказ.

ТРИ ПОЛОСЫ, И ГРАНИЦЫ ИХ ОБЪЯВЛЕНЫ ЧИСЛОМ, А НЕ ЧУТЬЁМ:

    БОГАТАЯ ПОЧВА   сто и более родственных строк — дом строится, и материал будет
    СКУДНАЯ         от шести до девяноста девяти — дом возможен, но проверить глазом
    ПУСТАЯ          пять и менее — в пласте стои́т ОДНА ЗАМЕНА и ничего кроме

Числа эти взяты по делу: замер 13.09 нашёл 923 у немецкого винительного (дом построен), 543 у
шведского рода (построен), 313/259/206/182 у романского (построен) — и ровно 5 у пятнадцати
отказов ряда «множественное после числа» (не построен, и сказано почему).

ЯЗЫК ОБЪЯСНЕНИЯ ЖИВЁТ НЕ ТОЛЬКО В СВОЁМ ПЛАСТЕ, И ПОЧВА ЕГО СЧИТАЕТСЯ ШИРЕ (13.09, найдено
на живом деле). Русский отказ «*пять книга» получил почву 83 по пласту — а счётный ряд
русского живёт в МИРАХ ПОКАЗОВ: «одна книга» 131 строка, «три книги» 23, «пять книг» 22, и
пласт русского не держит из них ни одной. То же у английского: «one book» 101, «two books» 20.

    ПОЧВА, СОЧТЁННАЯ ОДНИМ ПЛАСТОМ, ЗАНИЖЕНА ДЛЯ ЯЗЫКА, НА КОТОРОМ СВОД ОБЪЯСНЯЕТ: у прочих
    двадцати семи пласт — единственное место, где язык вообще звучит, а русский и английский
    звучат во всех трёхстах девяти мирах.

Оттого для языков объяснения почва берётся БОЛЬШЕЙ из двух: по своему пласту и по мирам
показов. Список их объявлен здесь поимённо (`ЯЗЫКИ_ОБЪЯСНЕНИЯ`), а не угадывается.

ПИСЬМО БЕЗ ПРОБЕЛОВ ЭТОЙ МЕРОЙ НЕ МЕРИТСЯ, И ЭТО СЧИТАЕТСЯ ОТДЕЛЬНО. Китайское, японское,
тайское (объявленное `segmentation: longest-match`) и корейское письмо дают у всякого отказа
пустую почву — не оттого, что пласт пуст, а оттого, что мера делит по пробелу.

    ПУСТАЯ ПОЧВА У БЕСПРОБЕЛЬНОГО ПИСЬМА ЕСТЬ СЛЕПОТА МЕРЫ, А НЕ ПУСТОТА ПЛАСТА. Смешать их
    одним числом значило бы объявить долгом свою же неспособность прочесть.

ЧИСЛО ЭТО — ОТЧЁТ, А НЕ РУБЕЖ. Пустая почва не есть долг дома: она есть долг ПОКАЗОВ, и
платится он кузней пакетов, а не домом.

    ЗАМЕР, НАЗВАВШИЙ РЯД И ПОКАЗАВШИЙ ЕГО ПУСТОТУ, СДЕЛАЛ ПОЛОВИНУ ДЕЛА: вторая половина —
    показы, и они не пишутся тем, кто языка не знает.

    python3 scripts/refusal_ground.py [--подробно] [--полоса богатая|скудная|пустая]
"""
# ПУСТОЙ-ОБХОД: --двор no-such-dir
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

БОГАТАЯ, СКУДНАЯ = 100, 6

# ЯЗЫКИ, НА КОТОРЫХ СВОД ОБЪЯСНЯЕТ: их речь живёт во всех мирах показов, а не в одном пласте.
ЯЗЫКИ_ОБЪЯСНЕНИЯ = frozenset({"ru", "en"})

# СЛОВО ОТРЕЗАЕТСЯ ПРОБЕЛОМ, А НЕ ПРИЗНАКОМ «БУКВА» (13.09, второй раз за смену).
#
# Питоновский `\w` не считает буквой ЗНАКИ ОГЛАСОВКИ (Mn/Mc), и деванагари распадается:
# «पढ़ता» → «पढ», «त». Первая редакция этого прибора дала хинди почву НОЛЬ там, где её 1417.
#
#     ПРИЗНАК «БУКВА», ВЗЯТЫЙ У ДВИЖКА, РЕЖЕТ ПО ЛАТИНСКОЙ МЕРКЕ: то, что в одном письме
#     украшение буквы, в другом — её половина. Та же беда чинилась утром в
#     `scripts/refusal_only_word.py`, и лечение то же: слово берётся так, как его отделяет
#     САМО ПИСЬМО.
ЗНАКИ = ".,;:!?()[]«»„“”'\"—–-…۔؟،；：！？。、（）「」『』।॥"


def слова_строки(с):
    """Слова строки: отрезано ПРОБЕЛОМ, знаки препинания сняты с концов, числа отброшены."""
    вон = []
    for кусок in с.split():
        w = кусок.strip(ЗНАКИ).lower()
        if w and not w.isdigit():
            вон.append(w)
    return вон


def содержательные(строки, числительные):
    """Слова длиннее двух знаков, не числительные — то, чем и меряется почва."""
    вон = set()
    for с in строки:
        for w in слова_строки(с):
            if len(w) > 2 and w not in числительные:
                вон.add(w)
    return вон


def почва(отвергнутое, замена, прямые, числительные):
    """Сколько строк пласта несут хоть одно содержательное слово отказа или его замены."""
    свои = содержательные((отвергнутое, замена), числительные)
    if not свои:
        return 0
    return sum(1 for с in прямые if свои & set(слова_строки(с)))


def без_пробелов(двор):
    """Коды языков, чьё письмо не делится пробелом, — по объявлению самих пакетов."""
    вон = set()
    for п in sorted((двор / "langpacks").glob("*.json")):
        тело = json.loads(п.read_text(encoding="utf-8"))
        if тело.get("segmentation") == "longest-match" or тело.get("script") == "hangul":
            вон.add(п.stem)
    return вон


def полоса(n):
    """«богатая» / «скудная» / «пустая» — по объявленным числом границам."""
    return "богатая" if n >= БОГАТАЯ else ("скудная" if n >= СКУДНАЯ else "пустая")


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что почва СЧИТАЕТСЯ и полосы РАЗЛИЧАЮТСЯ.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ ОТЧЁТА, А НЕ ОТ НУЛЯ. Пусть счёт почвы сломается — и всякий
        отказ ляжет в «пустую», а прибор скажет «пустых 150» и будет выглядеть работающим.

    Три замены на выдуманном пласте: одна с богатой роднёй, одна со скудной, одна без родни.
    """
    прямые = ["два кота сидят"] * 120 + ["пять сорок бегут"] * 8 + ["дом стои́т"] * 3
    числ = {"два", "пять", "три"}
    беды = []
    for отверг, замена, ждём, имя in (
            ("два кот", "два кота", "богатая", "богатая почва"),
            ("пять сорока", "пять сорок", "скудная", "скудная почва"),
            ("три ежа", "три ежи", "пустая", "пустая почва")):
        вышло = полоса(почва(отверг, замена, прямые, числ))
        if вышло != ждём:
            беды.append(f"{имя}: сочтена «{вышло}», а надо «{ждём}»")
    # ЗАМЕНА ДРУГИМ ГЛАГОЛОМ НЕ ДОЛЖНА ДАВАТЬ ПУСТОТУ, ЕСЛИ ОТВЕРГНУТОЕ БОГАТО.
    богатый = ["ти читаєш книгу"] * 24 + ["я танцюю"] * 5
    if полоса(почва("я читаєш", "я танцюю", богатый, {"один"})) != "скудная":
        беды.append("замена другим глаголом дала не ту полосу при богатом отвергнутом")
    if полоса(БОГАТАЯ) != "богатая" or полоса(БОГАТАЯ - 1) != "скудная":
        беды.append("граница богатой полосы читается неверно")
    if полоса(СКУДНАЯ) != "скудная" or полоса(СКУДНАЯ - 1) != "пустая":
        беды.append("граница скудной полосы читается неверно")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ПОЧВА ОТКАЗА ОТКАЗ: счёт почвы не доказан ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--двор", default=None)
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--полоса", default=None)
    дов = ап.parse_args()
    двор = pathlib.Path(дов.двор) if дов.двор else КОРЕНЬ / "tools"
    if not (двор / "langpacks").is_dir():
        print(f"ПОЧВА ОТКАЗА ОТКАЗ: пакетов нет — {двор / 'langpacks'}")
        return 2
    # ОТКАЗЫ, УЖЕ ОБЪЯСНЁННЫЕ ДОМОМ СВОЕГО ЯЗЫКА, НЕ СЧИТАЮТСЯ: почва их уже пригодилась.
    sys.path.insert(0, str(КОРЕНЬ / "scripts"))
    try:
        import refusal_house                             # noqa: PLC0415
        дома = refusal_house.дома_по_языкам(двор)
    except Exception:                                    # noqa: BLE001
        дома = {}
    беспробельные = без_пробелов(двор)
    # СТРОКИ МИРОВ ПОКАЗОВ ЧИТАЮТСЯ ОДИН РАЗ НА ВЕСЬ ПРОГОН, а не по разу на отказ.
    показы = []
    try:
        import genesis                                   # noqa: PLC0415
        for путь in genesis.worlds(kind="shows"):
            if путь.stem.startswith("genesis_lang_"):
                continue
            показы += [с.strip() for с in
                       путь.read_text(encoding="utf-8", errors="replace").split("\n") if с.strip()]
    except Exception:                                    # noqa: BLE001
        показы = []
    ряд, счёт, слепых, всего_пар = [], collections.Counter(), 0, 0
    for п in sorted((двор / "langpacks").glob("*.json")):
        тело = json.loads(п.read_text(encoding="utf-8"))
        слой = КОРЕНЬ / "datasets" / f"genesis_lang_{п.stem}.txt"
        if not слой.is_file():
            continue
        прямые = [с.strip() for с in слой.read_text(encoding="utf-8", errors="replace").split("\n")
                  if с.strip() and not с.strip().startswith("¬")]
        числительные = {str(в).lower() for в in (тело.get("numerals") or {}).values()}
        for пр in ((тело.get("show_kinds") or {}).get("refusals") or {}).get("pairs", ()):
            bad = (пр.get("bad") or "").rstrip(".。？?! ")
            замена = (пр.get("good") or "").rstrip(".。？?! ")
            if not bad or not замена:
                continue
            всего_пар += 1
            if any(ц in bad for _и, з in дома.get(п.stem, ()) for ц in з):
                continue                                 # уже объяснён домом своего языка
            n = почва(bad, замена, прямые, числительные)
            if п.stem in ЯЗЫКИ_ОБЪЯСНЕНИЯ and показы:
                n = max(n, почва(bad, замена, показы, числительные))
            if п.stem in беспробельные:
                слепых += 1
                continue
            ряд.append((n, п.stem, пр.get("reason", "?"), bad, замена))
            счёт[полоса(n)] += 1
    if not ряд:
        print("ПОЧВА ОТКАЗА ОТЧЁТ: необъяснённых отказов нет вовсе")
        return 0
    ряд.sort(reverse=True)
    для_показа = [x for x in ряд if дов.полоса is None or полоса(x[0]) == дов.полоса]
    for n, яз, причина, bad, замена in для_показа[: None if дов.подробно else 12]:
        print(f"  {n:5}  [{яз}] {полоса(n):<8} {причина:<13} «{bad[:34]}» → «{замена[:26]}»")
    # ОБЪЁМ НАЗВАН (16.09): «необъяснённых 78» молчало о том, из скольких пар отказа,
    # а сказать это есть половина показания — без неё не видно, много ли 78.
    print(f"ПОЧВА ОТКАЗА ОТЧЁТ: необъяснённых отказов {len(ряд) + слепых} из {всего_пар}; БОГАТАЯ ПОЧВА "
          f"{счёт['богатая']} (дом строится), СКУДНАЯ {счёт['скудная']} (проверить глазом), "
          f"ПУСТАЯ {счёт['пустая']} (ждут не дома, а ПОКАЗОВ); беспробельным письмом эта мера "
          f"не мерится — отброшено {слепых}; границы {БОГАТАЯ} и {СКУДНАЯ}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
