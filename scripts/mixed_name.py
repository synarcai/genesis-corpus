#!/usr/bin/env python3
"""[ИМЯ СМЕШАННОГО ПИСЬМА] — имя, читаемое глазом одинаково, а машиной по-разному.

    ИМЯ, ЧИТАЕМОЕ ГЛАЗОМ ОДИНАКОВО И МАШИНОЙ ПО-РАЗНОМУ, ЕСТЬ ЛОВУШКА, А НЕ ИМЯ.

ПОВОД, НАЙДЕННЫЙ 21.09 НА ЖИВОМ ДЕЛЕ. В доме акта диалога стояла функция `roды_плохи`, где
«ro» писано латиницей, а «ды_плохи» кириллицей. На глаз она неотличима от `роды_плохи` —
и всякий, кто позвал бы её по виду, получил бы `NameError` на ровном месте: имя есть, имя
видно, имя не зовётся.

Свод пишет имена по-русски, и это его решение; но кириллица делит с латиницей два десятка
начертаний — «а», «о», «е», «р», «с», «у», «х», «А», «В», «Е», «К», «М», «Н», «О», «Р», «С»,
«Т», «У», «Х», — и рука, набирающая имя, сбивается с раскладки незаметно для себя.

    ОШИБКА, КОТОРУЮ НЕ ВИДНО ГЛАЗОМ, НЕ ИСПРАВЛЯЕТСЯ ЧТЕНИЕМ. Её ловит лишь прибор,
    смотрящий не на вид знака, а на его КОД.

ЧТО СУДИТСЯ. Всякое имя, объявленное кодом свода, — имена функций и классов, имена
переменных при присваивании, имена доводов. Имя делится по подчёркиваниям и цифрам, и
виновно оно, если хоть одно его СЛОВО несёт буквы обоих алфавитов разом.

    ЛОВУШКА НЕ В ИМЕНИ ИЗ ДВУХ АЛФАВИТОВ, А В СЛОВЕ ИЗ ДВУХ АЛФАВИТОВ.
#
# РУБЕЖ ДОВЕДЁН ДО НУЛЯ 22.09: все 61 имя переписаны в 23 файлах. Пятерым
# вернулось задуманное написание — то были описки раскладки («taбл» → «табл»,
# «formы_guess» → «формы_guess», «pак_слова» → «пак_слова» при доводе «пак»,
# «порог_иso» → «порог_iso» при сравнении со штампом времени); прочим поставлено
# ПОДЧЁРКИВАНИЕ на границе алфавитов («едb» → «ед_b», «Xр» → «X_р», «oч» → «o_ч»),
# как велит закон этого же прибора: латинский кусок законен, когда ОТДЕЛЁН.
# Ни одна страница свода не сдвинулась: воспроизводимость 0 из 348. Свод полон честных
    имён вроде `ГОД_DE`, `A_нет`, `вещь_i`: латинский кусок в них есть метка языка или
    буква переменной, он ОТДЕЛЁН подчёркиванием, и глаз читает их как два слова.

Слова в строках и комментариях не судятся: там смешение бывает нарочным (цитата, пример
чужой речи), а зваться такое слово не зовётся.

ЧЕГО ПРИБОР НЕ ДЕЛАЕТ. Он не судит о том, хорошо ли имя по-русски, и не требует латиницы:
имя из одного алфавита — любого — есть имя честное.

    python3 scripts/mixed_name.py
"""
# ПУСТОЙ-ОБХОД: --корень /no/such/root
import ast
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ДВОРЫ = ("tools", "scripts", "courts", "forge")
# РУБЕЖ-ДОЛГА: РУБЕЖ = 0
#
# 61 имя свода несёт слово из двух алфавитов с омоглифом внутри: «рy», «nа», «Xр», «_ксk»,
# «formы_guess», «доводen». Всякое из них — ловушка на глаз, и всякое чинится по-своему:
# «formы_guess» просится в латиницу целиком, «_ксk» — в кириллицу, а «Xр» несёт латинское
# «X» нарочно, как метку неизвестного.
#
#     ПЕРЕЕЗД ИМЕНИ ЕСТЬ ПРАВКА ВСЕХ, КТО ЕГО НАЗЫВАЕТ, и потому шестьдесят одна починка
#     есть шестьдесят одна отдельная работа, а не один обход заменой.
#
# Долг назван числом и стережётся ратчетом; прибор заведён не ради этого числа, а ради
# того, чтобы новых не прибавлялось незаметно.
РУБЕЖ = 0

ЛАТИНИЦА = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ")
КИРИЛЛИЦА = set("абвгдеёжзийклмнопрстуфхцчшщъыьэюяАБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ")

# ОМОГЛИФЫ — БУКВЫ, У КОТОРЫХ ЕСТЬ ДВОЙНИК ТОГО ЖЕ НАЧЕРТАНИЯ В ДРУГОМ АЛФАВИТЕ. Только они
# и делают смешение ОПАСНЫМ: слово «dл» смешано, но прочитывается однозначно — ни «d», ни
# «л» двойника не имеют, и набрать его иначе рука не может. Слово же «roды» набирается
# двояко и выглядит при этом одинаково.
#
#     СМЕШЕНИЕ БЕЗ ОМОГЛИФА ВИДНО ГЛАЗУ И ПОТОМУ НЕ ЛОВУШКА; СМЕШЕНИЕ С ОМОГЛИФОМ НЕВИДИМО
#     И ПОТОМУ ЛОВУШКА ВСЕГДА.
ОМОГЛИФЫ = set("aceopxyABCEHKMOPTXасеорхуАВСЕНКМОРТХ")


def _смешано(имя):
    """Смешаны ли алфавиты ВНУТРИ ОДНОГО СЛОВА имени, а не между его кусками.

    ПЕРВАЯ РЕДАКЦИЯ МЕРЫ ЗВАЛА ВИНОВНЫМИ 1 111 ИМЁН, И ПОЧТИ ВСЕ БЫЛИ ЧЕСТНЫ. Свод полон
    имён вроде `ГОД_DE`, `A_нет`, `вещь_i`, `_re_скелет`: латинский кусок в них есть метка
    языка, буква переменной или имя ввезённого дома, и всякий такой кусок ОТДЕЛЁН
    подчёркиванием. Глаз читает их как два слова и зовёт ровно так, как видит.

        ЛОВУШКА НЕ В ИМЕНИ ИЗ ДВУХ АЛФАВИТОВ, А В СЛОВЕ ИЗ ДВУХ АЛФАВИТОВ.
#
# РУБЕЖ ДОВЕДЁН ДО НУЛЯ 22.09: все 61 имя переписаны в 23 файлах. Пятерым
# вернулось задуманное написание — то были описки раскладки («taбл» → «табл»,
# «formы_guess» → «формы_guess», «pак_слова» → «пак_слова» при доводе «пак»,
# «порог_иso» → «порог_iso» при сравнении со штампом времени); прочим поставлено
# ПОДЧЁРКИВАНИЕ на границе алфавитов («едb» → «ед_b», «Xр» → «X_р», «oч» → «o_ч»),
# как велит закон этого же прибора: латинский кусок законен, когда ОТДЕЛЁН.
# Ни одна страница свода не сдвинулась: воспроизводимость 0 из 348. «ГОД_DE»
        читается как «год по-немецки» и зовётся как пишется; «roды» читается как «роды» и
        зовётся иначе — вот это и есть ловушка.

    Оттого имя делится по подчёркиваниям и цифрам, и виновно оно, если хоть одно его слово
    несёт буквы обоих алфавитов разом.
    """
    слово = []
    for знак in имя + "_":
        if знак in ЛАТИНИЦА or знак in КИРИЛЛИЦА:
            слово.append(знак)
            continue
        знаки = set(слово)
        if знаки & ЛАТИНИЦА and знаки & КИРИЛЛИЦА and знаки & ОМОГЛИФЫ:
            return True
        слово = []
    return False


def _имена(дерево):
    """Имена, ОБЪЯВЛЕННЫЕ кодом: определения, присваивания, доводы.

    Читается дерево, а не текст: имя в строке или в комментарии не зовётся никем, и
    смешение там бывает нарочным.
    """
    вон = []
    for узел in ast.walk(дерево):
        if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            # КЛАСС НЕ НЕСЁТ ДОВОДОВ, И СПРАШИВАТЬ ИХ У НЕГО ЗНАЧИТ ПАСТЬ НА ПЕРВОМ ЖЕ
            # КЛАССЕ: доводы берутся отдельным узлом `ast.arg` ниже, одним правилом на всех.
            вон.append((узел.name, узел.lineno))
        elif isinstance(узел, ast.Name) and isinstance(узел.ctx, ast.Store):
            вон.append((узел.id, узел.lineno))
        elif isinstance(узел, ast.arg):
            вон.append((узел.arg, узел.lineno))
    return вон


def _проба():
    """Прибор доказывает чтение прежде, чем судить."""
    беды = []
    if not _смешано("roды_плохи"):
        беды.append("смешанное имя не опознано")
    if not _смешано("доводnl"):
        беды.append("слитное смешение с омоглифом не опознано: доводnl")
    if _смешано("роды_плохи") or _смешано("kinds_bad"):
        беды.append("честное имя одного алфавита названо смешанным")
    for честное in ("ГОД_DE", "A_нет", "вещь_i", "_re_скелет", "ГОД_NL", "dл"):
        if _смешано(честное):
            беды.append(f"имя с ОТДЕЛЁННЫМ латинским куском названо смешанным: {честное}")
    дерево = ast.parse("def roд(х):\n    сумma = х\n    return сумma\n")
    имена = {и for и, _ in _имена(дерево)}
    if not {и for и in имена if _смешано(и)} >= {"roд", "сумma"}:
        беды.append(f"чтение дерева не нашло смешанных имён: {sorted(имена)}")
    return беды


def main():
    корень = КОРЕНЬ
    if "--корень" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--корень") + 1])
    if not корень.is_dir() or not any((корень / д).is_dir() for д in ДВОРЫ):
        print(f"ИМЯ СМЕШАННОГО ПИСЬМА ОТКАЗ: дворов кода нет в {корень}")
        return 2
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ИМЯ СМЕШАННОГО ПИСЬМА ОТКАЗ: чтение не доказано ({len(беды)} бед)")
        return 2

    виновные, файлов, имён = [], 0, 0
    for двор in ДВОРЫ:
        п = корень / двор
        if not п.is_dir():
            continue
        for файл in sorted(п.rglob("*.py")):
            try:
                дерево = ast.parse(файл.read_text(encoding="utf-8", errors="replace"))
            except SyntaxError:
                continue
            файлов += 1
            видано = set()
            for имя, строка in _имена(дерево):
                имён += 1
                if _смешано(имя) and имя not in видано:
                    видано.add(имя)
                    виновные.append((файл.relative_to(корень), строка, имя))

    for путь, строка, имя in виновные[:20]:
        латинские = "".join(sorted({з for з in имя if з in ЛАТИНИЦА}))
        print(f"    {путь}:{строка}: «{имя}» — латиницей писано «{латинские}»")
    if len(виновные) > 20:
        print(f"    … и ещё {len(виновные) - 20}")
    вердикт = "PASS" if len(виновные) <= РУБЕЖ else "FAIL"
    print(f"ИМЯ СМЕШАННОГО ПИСЬМА {вердикт}: имён двух алфавитов {len(виновные)} "
          f"(рубеж {РУБЕЖ}); прочитано файлов {файлов}, имён {имён}, дворов {len(ДВОРЫ)}")
    return 0 if вердикт == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
