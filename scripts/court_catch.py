#!/usr/bin/env python3
"""[УЛОВ СУДА] — сколько строк свода этот суд ловит ЕДИНСТВЕННЫЙ.

    СУД, ДОРОГОЙ И БЕЗ ЕДИНОЛИЧНОГО УЛОВА, СНИМАЕТСЯ БЕЗ ПОТЕРИ; СУД, ДЕШЁВЫЙ И ЕДИНСТВЕННЫЙ,
    НЕ СНИМАЕТСЯ НИКОГДА, КАКОВА БЫ НИ БЫЛА ЕГО ЦЕНА.

ПОВОД, ПРИШЕДШИЙ ОТ СОСЕДА (12.09, ночь, holon-f9). Цена набора измерена: 311 приборов, из них
три держат больше половины времени, и полный обход перестал помещаться в полтора часа. Первая
мысль всякого — снять дорогое. Но цена есть лишь ПОЛОВИНА вопроса, и вторая половина такая:

    ЧТО ПРОПАДЁТ, ЕСЛИ СНЯТЬ. Суд, читающий сто тысяч строк, из которых КАЖДУЮ читает и
    кто-нибудь ещё, не держит ничего: снимите его — и ни одна ложь не пройдёт незамеченной.
    Суд, читающий триста строк, которых не читает больше НИКТО, держит эти триста целиком.

Прибор берёт у палаты то, что она и так знает и выбрасывает: множество судов, прочитавших
строку (`палата.судить` возвращает третьим значением КЕМ). Строка, у которой читатель один,
есть единоличный улов этого суда.

ТРИ ЧИСЛА НА СУД, И НИ ОДНО ИЗ НИХ НЕ ЕСТЬ ВЕРДИКТ: судит (сколько строк взял), единственный
(сколько взял один), цена (секунды из `reports/SUITE-COST.tsv`). Прибор НИЧЕГО НЕ РЕШАЕТ и
ничего не снимает — он называет, а снятие есть дело руки.

    ПРИБОР, СНИМАЮЩИЙ СУД САМ, ЕСТЬ ПРИБОР, КОТОРОМУ ПОВЕРИЛИ БОЛЬШЕ, ЧЕМ ОН ЗНАЕТ.

ГРАНИЦА НАЗВАНА, И ОНА ВАЖНА. Ноль единоличного улова НЕ ЕСТЬ довод снять: суд может ловить
ровно то, что ловит сосед, и быть при этом ВТОРЫМ ЧТЕНИЕМ — а второе чтение стои́т ровно
столько, сколько стои́т несогласие двух. Прибор различает это одним вопросом: судит ли суд
ХОТЬ ЧТО-НИБУДЬ. Суд, не взявший ни строки, слеп; суд, взявший строки без единоличного улова,
есть второе чтение, и снимать его можно лишь зная, расходится ли он с первым.

ЦЕНА ЭТОГО ПРИБОРА НАЗЫВАЕТСЯ С ТРЕМЯ ОГОВОРКАМИ, И ЭТО ЖЕ ВЕРНО ДЛЯ ВСЯКОГО ПРИБОРА СВОДА.
Он читает КАЖДУЮ строку КАЖДЫМ судом, то есть принадлежит к тому самому классу, который
измеряет, — и первый его прогон стоил тридцать минут при ОДНОМ работнике. Работников он берёт
у палаты (`panel._джобы()`), а та читает `GENESIS_SUITE_JOBS`; в наборе стои́т тройка, в
одиночном прогоне единица, и это ВТРОЕ иная цена.

    ЦЕНА, СНЯТАЯ ПОД ПОТОЛКОМ, ЕСТЬ ГРАНИЦА ТЕРПЕНИЯ.
    ЦЕНА, СНЯТАЯ РЯДОМ С ДРУГОЙ МЕРОЙ, ЕСТЬ СОСЕДСТВО.
    ЦЕНА, СНЯТАЯ ПРИ ИНОМ ЧИСЛЕ РАБОТНИКОВ, ЕСТЬ ЦЕНА ДРУГОГО ПРОГОНА.

Оттого «цена прибора» есть не одно число, а число ПРИ НАЗВАННЫХ УСЛОВИЯХ, и сравнивать по ней
приборы можно лишь внутри ОДНОГО прогона. Запись `reports/SUITE-COST.tsv` ни одного из трёх
условий не называет — это её граница, названная здесь, а не её ложь.

    python3 scripts/court_catch.py [--подробно] [--имён 20]
"""
# ПУСТОЙ-ОБХОД: --свод no-such-file
import argparse
import collections
import concurrent.futures
import os
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

from genesis import Unreadable, worlds  # noqa: E402
import panel  # noqa: E402
from panel import палата  # noqa: E402

ЦЕНА = КОРЕНЬ / "reports" / "SUITE-COST.tsv"
_ПАЛАТА_РАБОЧЕГО = None


def _палата_рабочего():
    """Палата — по одной на процесс: строить её на каждую строку значило бы платить втрое."""
    global _ПАЛАТА_РАБОЧЕГО
    if _ПАЛАТА_РАБОЧЕГО is None:
        _ПАЛАТА_РАБОЧЕГО = палата()
    return _ПАЛАТА_РАБОЧЕГО


def _ломоть(задача):
    """Один ломоть мира: (судит, единственный) по судам."""
    путь, начало, конец = задача
    суд = _палата_рабочего()
    слои = суд.слои(pathlib.Path(путь))
    судит, один = collections.Counter(), collections.Counter()
    строк = 0
    with pathlib.Path(путь).open(encoding="utf-8", errors="replace") as поток:
        строки = [с for с in поток if с.strip()]
    for строка in строки[начало:конец]:
        _, _, кем = суд.судить(строка, слои)
        if not кем:
            continue
        строк += 1
        for имя in кем:
            судит[имя] += 1
        if len(кем) == 1:
            один[next(iter(кем))] += 1
    return строк, судит, один


def цены():
    """Последняя названная цена каждого прибора; неизмеренный получает None."""
    вон = {}
    if not ЦЕНА.is_file():
        return вон
    for с in ЦЕНА.read_text(encoding="utf-8", errors="replace").split("\n"):
        ч = с.split("\t")
        if len(ч) == 3 and ч[2].lstrip("-").isdigit():
            сек = int(ч[2])
            if сек >= 0:
                вон[ч[1].removesuffix(".py")] = сек
    return вон


СЛЕД = КОРЕНЬ / "reports" / "COURT-CATCH.tsv"


def _записать(судит, один, строк, сделано, всего):
    """Частный итог в сайдкар — чтобы убитый прогон оставил измеренную половину."""
    ряды = ["# суд\tсудит\tодин\tломтей {}/{}\tстрок {}".format(сделано, всего, строк)]
    for имя in sorted(судит, key=lambda и: (один[и], -судит[и], и)):
        ряды.append(f"{имя}\t{судит[имя]}\t{один[имя]}")
    СЛЕД.write_text("\n".join(ряды) + "\n", encoding="utf-8")


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что УЛОВ ОТЛИЧАЕТСЯ ОТ СУДИМОСТИ.

        ПРИБОР, СЧИТАЮЩИЙ УЛОВ, И ПРИБОР, СЧИТАЮЩИЙ СУДИМОСТЬ, ДАЮТ ОДИНАКОВЫЙ НОЛЬ У СУДА,
        КОТОРЫЙ НЕ ВЗЯЛ НИ СТРОКИ, — и различить их можно лишь там, где строку взяли ДВОЕ.

    Три заведомо известных случая на выдуманных множествах читателей.
    """
    беды = []
    случаи = (({"а"}, {"а": 1}, {"а": 1}, "один читатель — улов его"),
              ({"а", "б"}, {"а": 1, "б": 1}, {}, "двое читателей — улова нет ни у кого"),
              (set(), {}, {}, "читателей нет — ни судимости, ни улова"))
    for кем, ждём_судит, ждём_один, беда in случаи:
        судит, один = collections.Counter(), collections.Counter()
        if кем:
            for имя in кем:
                судит[имя] += 1
            if len(кем) == 1:
                один[next(iter(кем))] += 1
        if dict(судит) != ждём_судит or dict(один) != ждём_один:
            беды.append(f"{беда}: судит {dict(судит)}, улов {dict(один)}")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"УЛОВ СУДА ОТКАЗ: счёт улова не доказан ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--имён", type=int, default=20)
    дов = ап.parse_args()
    try:
        пути = [п for п in worlds(kind="shows") if п.is_file()]
    except Unreadable as беда:
        print(f"УЛОВ СУДА ОТКАЗ: {беда}")
        return 2
    if not пути:
        print("УЛОВ СУДА ОТКАЗ: миров показов нет, мерить нечего")
        return 2
    jobs = panel._джобы()
    куски = panel.ломти(пути, panel.ЦЕЛЬ_ЛОМТЯ if jobs > 1 else 0)
    задачи = [(str(п), a, b) for п, a, b, _ц in куски]
    # ПРИБОР ПИШЕТ ПО ХОДУ, А НЕ ТОЛЬКО В КОНЦЕ (12.09, ночь, куплено собственной гибелью).
    # Первый его прогон упёрся в часовой потолок и оставил НОЛЬ БАЙТ: шестьдесят минут работы
    # пропали целиком, потому что вердикт печатался последней строкой.
    #
    #     ПРИБОР, ПЕЧАТАЮЩИЙ ВЕРДИКТ ТОЛЬКО В КОНЦЕ, ПРИ ГИБЕЛИ НЕ ОСТАВЛЯЕТ НИЧЕГО, — и
    #     видно это лишь тогда, когда он гибнет, то есть когда ответ нужнее всего.
    #
    # Ныне частный итог ложится в сайдкар после каждого десятого ломтя: убитый прогон оставляет
    # измеренную половину, и она годна, ибо ломти считаются НЕЗАВИСИМО.
    строк = 0
    судит, один = collections.Counter(), collections.Counter()
    сделано = 0

    def _сложить(итог):
        nonlocal строк, сделано
        своё_строк, своё_судит, свой_один = итог
        строк += своё_строк
        судит.update(своё_судит)
        один.update(свой_один)
        сделано += 1
        if сделано % 10 == 0 or сделано == len(задачи):
            _записать(судит, один, строк, сделано, len(задачи))

    if jobs <= 1:
        for з in задачи:
            _сложить(_ломоть(з))
    else:
        with concurrent.futures.ProcessPoolExecutor(
                max_workers=jobs, initializer=panel._сторожить_родителя,
                initargs=(os.getpid(),)) as пул:
            for итог in пул.map(_ломоть, задачи):
                _сложить(итог)
    цена = цены()
    ряды = sorted(судит, key=lambda имя: (один[имя], -цена.get(имя, 0), имя))
    print(f"{'суд':26}{'судит':>9}{'один':>9}{'цена, с':>9}")
    for имя in (ряды if дов.подробно else ряды[:дов.имён]):
        с = цена.get(имя)
        print(f"{имя[:26]:26}{судит[имя]:9}{один[имя]:9}{'—' if с is None else с:>9}")
    без_улова = [и for и in судит if not один[и]]
    слепые = [и for и in цена if и not in судит]
    дорогие = sorted((и for и in без_улова if цена.get(и, 0) >= 30),
                     key=lambda и: -цена.get(и, 0))
    print(f"УЛОВ СУДА: судов, взявших хоть строку — {len(судит)}; БЕЗ ЕДИНОЛИЧНОГО УЛОВА "
          f"{len(без_улова)}, из них дороже 30 с — {len(дорогие)}"
          + (f" ({', '.join(дорогие[:5])})" if дорогие else "")
          + f"; строк судимых {строк}, приборов с ценой без улова строк {len(слепые)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
