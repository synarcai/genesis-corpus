#!/usr/bin/env python3
"""[ЗАПАС РУБЕЖА] — ОТЧЁТ: насколько дело ниже объявленного предела.

    РУБЕЖ, НЕ ОПУЩЕННЫЙ ЗА УЛУЧШЕНИЕМ, ЕСТЬ ЗАПАС НА УХУДШЕНИЕ: он пропустит возврат
    к прежнему, не дойдя до себя, и промолчит о нём.

ПОВОД, ЗАМЕРЕННЫЙ 12.09. Свод несёт сто сорок три рубежа. Тридцать два из них стоят на
НОЛЕ и не могут отстать: дело обязано быть нулём, и всякое ухудшение видно сразу. Прочие
же держат число — и число это стареет молча, как стареет замер в объявлении.

Первый же замер нашёл два отставших: охват понятия стоял на 6556 при деле 4957 (рубеж
остался от ПРЕЖНЕЙ меры, считавшей одним числом наши своды и чужую полку), ячейка без
показа — на 32 при деле 12, хотя прибор её сам объявлял «опущен до достигнутого, чтобы не
стать запасом».

    РУБЕЖ, ОСТАВШИЙСЯ ОТ ПРЕЖНЕЙ МЕРЫ, СУДИТ НЕ ТО, ЧТО МЕРЯЕТ ПРИБОР.

ПОЧЕМУ ОТЧЁТ, А НЕ СУДЬЯ. Допустимый запас не выводится ниоткуда: рубеж иного прибора
СПРАВЕДЛИВО стоит выше дела — он держит колеблющуюся меру, чей знаменатель растёт чужой
рукой, и подтянуть его впритык значило бы красить свод от чужого прироста.

    МЕРА, КОЛЕБЛЮЩАЯСЯ НЕ ОТ НАШЕЙ РУКИ, ТРЕБУЕТ ЗАПАСА; МЕРА, ИДУЩАЯ ЛИШЬ ЗА НАШЕЙ
    РАБОТОЙ, НЕ ТРЕБУЕТ ЕГО ВОВСЕ. РАЗЛИЧИТЬ ИХ СЧЁТОМ НЕЛЬЗЯ — ЭТО ЗНАЕТ ТОТ, КТО
    МЕРУ ЗАВЁЛ.

Оттого прибор ПЕЧАТАЕТ и не судит: он кладёт запасы перед тем, кто их объявлял, и молчит
о том, велики они или малы.

ГРАНИЦА ВИДИМОСТИ СКАЗАНА ПРЯМО. Прибор читает ЛЕДЖЕР, а не код: он видит лишь те рубежи,
что напечатаны в вердикте парой «дело (рубеж N)» — сорок один из ста сорока трёх. Прочие
рубежи стерегут своё, но о запасе своём молчат, и молчание это есть граница отчёта.

    ЧИСЛО, НАПЕЧАТАННОЕ РЯДОМ С РУБЕЖОМ, НЕ ОБЯЗАНО БЫТЬ ТЕМ, ЧТО РУБЕЖ СТЕРЕЖЁТ:
    у пакетов языка «красных 0 (рубеж 6)» значило ПОЛ ДЛЯ ЗЕЛЁНЫХ, и первый замер
    счёл это запасом в сто процентов. Вердикт тот переписан, но урок остался.

СТОРОНА РУБЕЖА ОБЪЯВЛЯЕТСЯ СЛОВОМ «СНИЗУ», И ЭТО СОГЛАШЕНИЕ, ВВЕДЁННОЕ ЭТИМ ЖЕ ЗАМЕРОМ.
Прибор удержанного ключа печатал «вопросов 3622 (рубеж 1500)» — и первый прогон объявил
его превышенным, тогда как рубеж там ПОЛ: вопросов должно быть НЕ МЕНЬШЕ полутора тысяч.

    ВЕРДИКТ, НЕ СКАЗАВШИЙ, В КАКУЮ СТОРОНУ СТЕРЕЖЁТ РУБЕЖ, ЧИТАЕТСЯ В ОДНУ — И ЧАЩЕ
    НЕВЕРНО.

Два вердикта переписаны в тот же час; прочие рубежи свода — потолки, и молчание их о
стороне есть умолчание по общему правилу, а не недосмотр.

    python3 scripts/margin_census.py [--все]
"""
# ПУСТОЙ-ОБХОД: --леджер /no/such/ledger.tsv
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ЛЕДЖЕР = КОРЕНЬ / "reports" / "ledger.tsv"

# ПАРА «ДЕЛО (РУБЕЖ N)» — первая в вердикте: она и есть главное число прибора.
# ЧИСЛО БЕРЁТСЯ ЦЕЛИКОМ, НО НЕ ДАЛЬШЕ СВОЕГО НАЧАЛА. Первая редакция позволяла
# пробелу входить в число («1 599» пишется с пробелом) — и склеила «сверх LAW=2 0
# (рубеж 0)» в число 20, объявив честный прибор превышенным.
#
#     ПРИЗНАК, ПОЗВОЛЯЮЩИЙ ПРОБЕЛ ВНУТРИ ЧИСЛА, СКЛЕИТ ДВА ЧИСЛА, СТОЯЩИЕ РЯДОМ.
#
# Ныне разряды берутся лишь ТРОЙКАМИ («1 599», «429 923»), как их и пишет свод.
_ЧИСЛО = r"\d{1,3}(?:[  ]\d{3})+|\d+"
ПАРА = re.compile(rf"({_ЧИСЛО})\s*\(рубеж\s*(?:снизу\s*)?({_ЧИСЛО})\)")
# РУБЕЖ СНИЗУ судится наоборот, и запас его считается иначе; прибор их различает.
СНИЗУ = re.compile(r"\(рубеж\s+снизу")


def _чис(s):
    return int(re.sub(r"[\s ]", "", s))


def запасы(леджер):
    """[(прибор, дело, рубеж, снизу)] — по ПОСЛЕДНЕМУ вердикту каждого прибора."""
    последний = {}
    for стр in леджер.read_text(encoding="utf-8").splitlines():
        ч = стр.split("\t")
        if len(ч) >= 4:
            последний[ч[1]] = ч[3]
    вон = []
    for имя, вердикт in последний.items():
        м = ПАРА.search(вердикт)
        if not м:
            continue
        вон.append((имя, _чис(м.group(1)), _чис(м.group(2)),
                    bool(СНИЗУ.search(вердикт[max(0, м.start() - 4):м.end()]))))
    return вон


def main():
    леджер = ЛЕДЖЕР
    if "--леджер" in sys.argv:
        леджер = pathlib.Path(sys.argv[sys.argv.index("--леджер") + 1])
    if not леджер.is_file():
        print(f"ЗАПАС РУБЕЖА ОТКАЗ: леджера нет — {леджер}")
        return 2
    все = запасы(леджер)
    if not все:
        print("ЗАПАС РУБЕЖА ОТКАЗ: в леджере нет вердиктов с рубежом, считать нечего")
        return 2
    показать_все = "--все" in sys.argv
    нолевые = [т for т in все if not т[3] and т[2] == 0]
    впритык = [т for т in все if not т[3] and т[2] > 0 and т[1] == т[2]]
    снизу = [т for т in все if т[3]]
    сзапасом = sorted((т for т in все if not т[3] and т[2] > 0 and т[1] < т[2]),
                      key=lambda т: -(т[2] - т[1]) / т[2])
    превышены = [т for т in все if not т[3] and т[1] > т[2]]
    for имя, дело, рубеж, _ in (сзапасом if показать_все else сзапасом[:8]):
        доля = 100 * (рубеж - дело) / рубеж
        print(f"  ЗАПАС {доля:>3.0f} %  {имя:<26} дело {дело}, рубеж {рубеж} "
              f"(отстал на {рубеж - дело})")
    for имя, дело, рубеж, _ in превышены:
        print(f"  ПРЕВЫШЕН  {имя:<26} дело {дело} БОЛЬШЕ рубежа {рубеж} — прибор красен")
    if показать_все:
        for имя, дело, рубеж, _ in впритык:
            print(f"  впритык    {имя:<26} дело {дело} = рубеж {рубеж}")
    print(f"ЗАПАС РУБЕЖА ОТЧЁТ: рубежей с числом {len(все)} из ста сорока трёх "
          f"объявленных; на НОЛЕ {len(нолевые)}, впритык {len(впритык)}, с запасом "
          f"{len(сзапасом)}, превышенных {len(превышены)}, рубежей СНИЗУ {len(снизу)}; "
          f"наибольший запас "
          f"{100 * (сзапасом[0][2] - сзапасом[0][1]) / сзапасом[0][2]:.0f} % "
          f"({сзапасом[0][0]})" if сзапасом else
          f"ЗАПАС РУБЕЖА ОТЧЁТ: рубежей с числом {len(все)}; все стоят у дела")
    return 0


if __name__ == "__main__":
    sys.exit(main())
