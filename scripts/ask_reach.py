#!/usr/bin/env python3
"""[ВОПРОСНАЯ ПОВЕРХНОСТЬ] — отвечает ли мир или только сообщает.

ЗНАНИЕ БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ НЕ ОТВЕЧАЕТ — ОНО ТОЛЬКО СООБЩАЕТ.
Мир, показывающий «сумма 7 и 6 равна 13» и ни разу не спрашивающий
«чему равна сумма 7 и 6?», учит УЗНАВАТЬ утверждение, а не ОТВЕЧАТЬ на
вопрос. Разница видна на полосе: организм, живший в мире сообщений,
молчит там, где спрошено то же самое иначе.

ДВЕ ПОЛОВИНЫ ОДНОГО ЗАМЕРА, И ВТОРАЯ ГЛАВНАЯ.
  · ЕСТЬ ЛИ ВОПРОС — доля строк мира, несущих вопросительный знак или
    вопросное слово. Мир с нулём таких строк только сообщает.
  · СУДИМ ЛИ ОТВЕТ — вопросная строка, которую палата не берётся
    судить, есть вопрос БЕЗ ПРОВЕРЯЕМОГО ответа. Такой вопрос хуже
    отсутствия вопроса: он выглядит поверхностью, ею не будучи.

ВОПРОС ОПОЗНАЁТСЯ ЗНАКОМ ИЛИ ОБЪЯВЛЕННЫМ СЛОВОМ, А НЕ ДОГАДКОЙ. Знак
берётся тот, что письменность языка для вопроса и держит: «?» в
большинстве, «¿» открывающий в испанском, «؟» в арабском и персидском.
Вопросные слова берутся из ОБЪЯВЛЕНИЙ ЯЗЫКОВЫХ ПАКЕТОВ, а не из
списка: пакет, объявивший пару отказа или вопросную частицу, знает о
своём языке больше, чем здешний список знал бы обо всех.

ЧЕГО ЭТОТ ПРИБОР НЕ ГОВОРИТ. Он мерит НАЛИЧИЕ поверхности, а не её
широту: мир, спрашивающий об одном роде из десяти, покажет здесь
ненулевую долю. Широта есть отдельный замер, и смешивать их значило бы
получить число, которое нельзя истолковать.
"""
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import panel  # noqa: E402

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest

# ДИАГНОСТИКА, НЕ ЗАКОН: НЕМЫХ_РУБЕЖ = None
#
# ЭТОТ ПРИБОР — ДИАГНОСТИКА КОРПУСА, А НЕ ЗАКОН О НЁМ. Владелец
# спросил: «почему немоту миров нужно лечить добавлением вопросов в
# корпус? почему архитектура не обобщает это?» — и штурм ответил
# вердиктом: обращение есть обобщающий дефект ОРГАНА, а не корпуса.
# Реляционные роды отвечают на вопросы, которых им не показывали
# (четыре из пяти); рамочные молчали не оттого, что не видели вопроса,
# а оттого, что не видели ПОВЕСТВОВАНИЯ, из которого покупается
# предикат.
#
# ЗАКОН, ПРИНЯТЫЙ ШТУРМОМ (формулировка holon, слово владельца
# «архитектура обобщает, а не корпус латает»):
#
#   НЕМОТА — СВОЙСТВО ОРГАНИЗМА, НЕ КОРПУСА. Род считается немым, если
#   организм не отвечает на НЕПОКАЗАННЫЙ вопрос к нему при показанном
#   ПОВЕСТВОВАНИИ; мера — held-out суд (третья группа, narrative_shown),
#   а не число знаков «?» в мире. Корпус обязан роду ПОВЕСТВОВАНИЕМ
#   (из него покупается предикат и исполнитель); ФОРМА вопроса живёт на
#   немногих родах (из неё покупается обращение и вердикт-слова) и не
#   тиражируется по мирам.
#
# Потому здесь рубежа нет: число миров без вопроса печатается как
# ОТЧЁТ и вердикта не выносит. Путь числа за день, чтобы движение было
# видно: 34 из 95 утром, 25 к полудню, 2 из 103 к вечеру — и последние
# два (algebra, algebra_units) оставлены нарочно: их вопрос — о СИМВОЛЕ,
# иной род, и дом числовой пары его не принимает; ломать границу под
# число нельзя. Снятие вопросных поверхностей с миров, кроме немногих
# родов-учителей формы (не меньше трёх, чтобы обращение покупалось
# двумя и более родами), решится ЧИСЛОМ третьей группы HOLDOUT.
НЕМЫХ_РУБЕЖ = None

# ЗНАК БЕРЁТСЯ ТОТ, ЧТО ПИСЬМЕННОСТЬ ЯЗЫКА ДЛЯ ВОПРОСА И ДЕРЖИТ, и
# список рос вместе с корпусом: полноширинный «？» есть вопросный знак
# китайского и японского письма, и без него два пласта, получившие
# вопрос, остались бы немыми для этой меры. Греческая точка с
# запятой сюда НЕ ВХОДИТ: ею же в корпусе разделяют связывания
# («let a = 7; let b = 3»), и общий знак сделал бы вопросом всякую
# такую строку — греческий пакет объявляет своё вопросное СЛОВО.
ЗНАКИ = "?¿؟？"
# Сколько вопросных строк мира проверять на судимость. Судить все
# значило бы пройти палатой по всему своду вторично; ПОДТВЕРЖДЕНИЕ
# ЕСТЬ ВЫБОРКА, А НАЛИЧИЕ — ПЕРЕСЧЁТ, и смешивать их не надо.
ПРОБА = 40


def манифест(путь):
    if not путь.exists():
        return None
    return json.loads(путь.read_text(encoding="utf-8"))


def _файл(мир, корень, внешний):
    п = корень / мир["file"]
    if п.exists():
        return п
    if внешний:
        п = (корень / внешний / мир["file"]).resolve()
        if п.exists():
            return п
    return None


def вопросные_слова():
    """Вопросные слова, ОБЪЯВЛЕННЫЕ языковыми пакетами."""
    вон = set()
    где = КОРЕНЬ / "tools" / "langpacks"
    for путь in sorted(где.glob("*.json")):
        try:
            пакет = json.loads(путь.read_text(encoding="utf-8"))
        except (ValueError, OSError):
            continue
        for ключ in ("ask", "question", "вопрос", "ask_words"):
            если = пакет.get(ключ)
            if isinstance(если, str):
                вон.add(если.lower())
            elif isinstance(если, (list, tuple)):
                вон.update(str(x).lower() for x in если)
            elif isinstance(если, dict):
                вон.update(str(x).lower() for x in если.values())
    return вон


def main():
    путь = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    if "--manifest" in sys.argv:
        путь = pathlib.Path(sys.argv[sys.argv.index("--manifest") + 1])
    м = манифест(путь)
    if not м:
        print(f"ВОПРОСНАЯ ПОВЕРХНОСТЬ ОТКАЗ: манифеста «{путь}» нет")
        return 2
    внешний = м.get("external_root")
    слова = вопросные_слова()
    словом = (re.compile(r"\b(?:%s)\b" % "|".join(
        re.escape(с) for с in sorted(слова, key=len, reverse=True)))
        if слова else None)

    палата = panel.Палата()
    строки_итог = collections.Counter()
    отчёт = []
    for мир in м["worlds"]:
        if мир.get("text") != "shows":
            continue
        п = _файл(мир, КОРЕНЬ, внешний)
        if п is None:
            continue
        всего = вопросов = судимых = проб = 0
        слои = палата.слои(п)
        пласт = палата.пласт_файла(п) if hasattr(
            палата, "пласт_файла") else None
        for с in п.read_text(encoding="utf-8", errors="replace").splitlines():
            т = с.strip()
            if not т:
                continue
            всего += 1
            есть = any(з in т for з in ЗНАКИ) or (
                словом is not None and словом.search(т.lower()))
            if not есть:
                continue
            вопросов += 1
            if проб < ПРОБА:
                проб += 1
                судимо, _, _ = палата.судить(т, слои, пласт)
                судимых += судимо
        отчёт.append((мир["name"], всего, вопросов, судимых, проб))
        строки_итог["всего"] += всего
        строки_итог["вопросов"] += вопросов

    немые = [и for и in отчёт if и[2] == 0]
    несудимые = [и for и in отчёт if и[2] and и[4] and и[3] * 2 < и[4]]
    for имя, всего, q, суд, проб in sorted(немые):
        print(f"  ТОЛЬКО СООБЩАЕТ {имя}: {всего} строк, вопросов 0")
    for имя, всего, q, суд, проб in sorted(
            несудимые, key=lambda и: и[3] / (и[4] or 1)):
        print(f"  ВОПРОС БЕЗ ОТВЕТА {имя}: вопросов {q}, "
              f"судима палатой {суд} проба из {проб}")
    доля = (100 * строки_итог["вопросов"] // строки_итог["всего"]
            if строки_итог["всего"] else 0)
    поза = ("ОТЧЁТ" if НЕМЫХ_РУБЕЖ is None else
            "PASS" if len(немые) <= НЕМЫХ_РУБЕЖ else "FAIL")
    print(f"ВОПРОСНАЯ ПОВЕРХНОСТЬ {поза}: {len(отчёт) - len(немые)} из "
          f"{len(отчёт)} миров спрашивают, только сообщают {len(немые)}; "
          f"вопросных строк {строки_итог['вопросов']} из "
          f"{строки_итог['всего']} ({доля}%); миров с непроверяемым "
          f"вопросом {len(несудимые)}")
    if НЕМЫХ_РУБЕЖ is None:
        return 0
    return 0 if len(немые) <= НЕМЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
