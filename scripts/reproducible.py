#!/usr/bin/env python3
"""[ВОСПРОИЗВОДИМОСТЬ] — отгруженный корпус обязан совпадать с порождённым.

Корпус в репозитории есть ИЗДЕЛИЕ генераторов, лежащих рядом. Если они
разошлись — правкой генератора без пересборки или правкой файла руками,
— то отгружено одно, а порождается другое, и всякий, кто соберёт корпус
заново, получит не то, что судили суды. Это тот же род беды, что
выведенные данные без выводящего: подпись «измерено» на рукописном
списке.

Прибор перезапускает КАЖДЫЙ генератор во временный каталог и сличает
sha256 с отгруженным. Ноль расхождений — рубеж.

ЧЕГО ПРИБОР НЕ ВИДИТ, НАЗВАНО: миры, у которых генератора нет вовсе
(школьные корпуса, прозаические учебники), он не проверяет и считает
отдельно — их воспроизводимость есть дело того конвейера, что их строит.
"""
import hashlib
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402

# РУБЕЖ-ДОЛГА: РАСХОЖДЕНИЙ_РУБЕЖ = 0
РАСХОЖДЕНИЙ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: no-such-generator-dir

# ЦЕЛЬ ЧИТАЕТСЯ ДВУМЯ СПОСОБАМИ, ИБО ГЕНЕРАТОРЫ ГОВОРЯТ ДВУМЯ: одни
# зовут `emit`, другие объявляют `ЦЕЛЬ` и пишут сами (полный микс не
# перемешивается и не проходит ворота заново — его строки уже прошли их
# в своих мирах). Дефис в имени тоже законен: «GENESIS-FULL.txt».
ПУТЬ = re.compile(
    r'(?:emit(?:_grouped)?\(\s*|ЦЕЛЬ = )"(datasets/[-\w.]+\.txt)"')


def хэш(п):
    return hashlib.sha256(п.read_bytes()).hexdigest()


def main():
    генераторы = sorted((КОРЕНЬ / "tools").glob("gen_genesis_*.py"))
    if not генераторы:
        print("ВОСПРОИЗВОДИМОСТЬ ОТКАЗ: генераторов нет, сличать нечего")
        return 2
    # ГЕНЕРАТОР БЕЗ ОБЪЯВЛЕННОГО МИРА ПИШЕТ В ПУСТОТУ. Его строки не
    # видит ни прибор охвата, ни один суд: файл есть, мира нет, и
    # тысяча сто строк стояли невидимыми, пока ворота записи не
    # спросили о них при рождении. Молчание об этом было тем же родом
    # долга, что слепая строка внутри мира.
    # РУБЕЖ-ДОЛГА: БЕЗ_МИРА_РУБЕЖ = 0
    БЕЗ_МИРА_РУБЕЖ = 0
    # РУБЕЖ-ДОЛГА: БЕЗ_ПУТИ_РУБЕЖ = 0
    # ГЕНЕРАТОР БЕЗ ОБЪЯВЛЕННОЙ ЦЕЛИ НЕ ОСВОБОЖДАЕТСЯ ОТ МЕРЫ, А РОНЯЕТ
    # ЕЁ. Прежде такой генератор просто прибавлялся к числу в скобках —
    # щедрое послабление, прятавшее ровно то, что мера ищет: слой,
    # который никто никогда не пересобирал. Один такой (genesis_l4) жил
    # невидимым всё время существования прибора и вскрылся лишь оттого,
    # что рядом встал второй.
    БЕЗ_ПУТИ_РУБЕЖ = 0
    try:
        объявлены = {м["file"] for м in genesis.manifest()["worlds"]}
    except Exception:
        объявлены = None
    без_мира = []
    расхождений = сличено = без_пути = 0
    layer_gate = __import__('layer').ВОРОТА_ВЫКЛ
    имена = []
    with tempfile.TemporaryDirectory() as врем:
        двор = pathlib.Path(врем)
        # ДВОР ЕСТЬ ЗЕРКАЛО ДОМА, А НЕ ПЛОСКАЯ ГОРСТЬ ФАЙЛОВ. Прежде
        # общие модули клались рядом с генератором в корень двора, и
        # всякий, кто выводит корень из СВОЕГО места («корень есть
        # родитель tools»), промахивался на уровень: манифест искался
        # вне двора, а палата судов не находилась вовсе — ворота
        # записи молча не работали ни разу за жизнь прибора. Дерево,
        # повторяющее дом, чинит это без единого условия.
        (двор / "datasets").mkdir()
        (двор / "tools").mkdir()
        (двор / "courts").mkdir()
        # ДОМА ВЫВОДЯТСЯ, А НЕ ПЕРЕЧИСЛЯЮТСЯ. Здесь стоял рукописный
        # список из шести имён — и первый же новый общий дом
        # (`units.py`) обрушил сборку трёх генераторов: список
        # охраняет список, а не закон (М-76). Общий дом есть всякий
        # модуль `tools/`, который не генератор; лишняя копия не стоит
        # ничего, пропущенная стоит ложного «FAIL».
        for ф in sorted((КОРЕНЬ / "tools").glob("*.py")):
            if not ф.name.startswith("gen_genesis_"):
                shutil.copy(ф, двор / "tools" / ф.name)
        for ф in sorted((КОРЕНЬ / "courts").glob("*.py")):
            shutil.copy(ф, двор / "courts" / ф.name)
        # СЕМЕНА СИРОТ (tools/seeds/, М-126) — тоже сырьё генераторов: без
        # них шесть генераторов во дворе падали, и мера звала это
        # расхождением, хотя пересборка в доме была побайтовой.
        # ОБЪЯВЛЕНИЯ И ПОЛКА — ТОЖЕ СЫРЬЁ: мир определений читает список
        # понятий (declarations/CONCEPTS.txt) и словари полки (shelf/);
        # полка велика и потому не копируется, а зеркалится ссылкой.
        shutil.copytree(КОРЕНЬ / "declarations", двор / "declarations")
        if (КОРЕНЬ / "shelf").is_dir():
            (двор / "shelf").symlink_to(КОРЕНЬ / "shelf", target_is_directory=True)
        for имя in ("langpacks", "langseeds", "seeds"):
            if (КОРЕНЬ / "tools" / имя).is_dir():
                shutil.copytree(КОРЕНЬ / "tools" / имя,
                                двор / "tools" / имя)
        # ДВОРУ ДАЁТСЯ ВЕСЬ КОРПУС, А ЦЕЛЬ ИЗ НЕГО УБИРАЕТСЯ. Генератор
        # полного микса читает СОСЕДНИЕ миры — он есть функция корпуса,
        # а не источник нового, — и в пустом дворе не собирался вовсе.
        # Дать двору корпус значит проверить и то, чего мера прежде не
        # видела: генератор, тайно читающий чужой мир, теперь тоже под
        # мерой. Удаление ЦЕЛИ перед запуском сохраняет главное: слой,
        # которого генератор не написал, не может совпасть сам с собой.
        for ф in sorted((КОРЕНЬ / "datasets").glob("*")):
            if ф.is_file():
                shutil.copy(ф, двор / "datasets" / ф.name)
        for ген in генераторы:
            текст = ген.read_text(encoding="utf-8")
            # СВОД БЫВАЕТ О ДВУХ ЦЕЛЯХ, И СВЕРЯТЬ НАДО ОБЕ. Полный микс
            # пишет и школьную сборку, свод уравнений — и мир со
            # знаком; прибор, бравший ПЕРВОЕ совпадение, оставлял
            # вторую цель без меры — та же дыра, что «генератор без
            # объявленной цели», только на шаг глубже.
            цели = [м.group(1) for м in ПУТЬ.finditer(текст)]
            if not цели:
                без_пути += 1
                continue
            for имя_цели in цели:
                if объявлены is not None and имя_цели not in объявлены:
                    без_мира.append(f"{ген.name}:{имя_цели}")
            shutil.copy(ген, двор / "tools" / ген.name)
            for имя_цели in цели:
                свой = двор / имя_цели
                if свой.is_file():
                    свой.unlink()
            # ВОРОТА ВО ДВОРЕ ВЫКЛЮЧЕНЫ НАРОЧНО И СКАЗАНО ПОЧЕМУ: их
            # мера — запись дома, и она берётся при каждой сборке слоя;
            # здесь мерится ДРУГОЕ — побайтовое совпадение пересборки.
            # Прежде они были выключены МОЛЧА, промахом дерева.
            среда = dict(os.environ, **{layer_gate: "1"})
            r = subprocess.run([sys.executable,
                                str(pathlib.Path("tools") / ген.name)],
                               cwd=двор, capture_output=True, text=True,
                               env=среда)
            for имя_цели in цели:
                свежий, цель = двор / имя_цели, КОРЕНЬ / имя_цели
                if r.returncode or not свежий.is_file():
                    расхождений += 1
                    имена.append(f"{ген.name}: {имя_цели} не собран "
                                 f"(rc={r.returncode})")
                    continue
                if not цель.is_file():
                    continue
                сличено += 1
                if хэш(свежий) != хэш(цель):
                    расхождений += 1
                    имена.append(f"{ген.name}: {имя_цели} разошёлся")
    for и in имена[:6]:
        print(f"  {и}")
    плохо = (расхождений > РАСХОЖДЕНИЙ_РУБЕЖ
             or len(без_мира) > БЕЗ_МИРА_РУБЕЖ
             or без_пути > БЕЗ_ПУТИ_РУБЕЖ)
    итог = "FAIL" if плохо else "PASS"
    хвост = ""
    if без_мира:
        хвост = (f", БЕЗ ОБЪЯВЛЕННОГО МИРА {len(без_мира)} "
                 f"(рубеж {БЕЗ_МИРА_РУБЕЖ}): {sorted(без_мира)[:3]}")
    print(f"ВОСПРОИЗВОДИМОСТЬ {итог}: {расхождений} расхождений из "
          f"{сличено} сличённых (без объявленной цели {без_пути}, "
          f"рубеж {БЕЗ_ПУТИ_РУБЕЖ})"
          f"{хвост}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
