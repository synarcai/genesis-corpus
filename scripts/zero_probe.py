def мера(текст):
    return [(имя, len(re.findall(узор, текст, re.I))) for имя, узор in СЕМЕЙСТВА]


def main():
    if not СВОД.is_file():
        print(f"ПРОБА НА НОЛЬ ОТКАЗ: свода нет — {СВОД}")
        return 2
    текст = СВОД.read_text(encoding="utf-8", errors="replace")
    вышло = мера(текст)
    нули = [имя for имя, n in вышло if n == 0]
    куплено = len(вышло) - len(нули)
    всё = "--всё" in sys.argv
    for имя, n in sorted(вышло, key=lambda п: п[1]):
        if n == 0:
            print(f"  НОЛЬ — {имя}")
        elif всё:
            print(f"  {n:8d}  {имя}")
    поза = "PASS" if куплено >= КУПЛЕНО else "FAIL"
    print(f"ПРОБА НА НОЛЬ {поза}: куплено {куплено} семейств из {len(вышло)} "
          f"(рубеж {КУПЛЕНО}, растёт и не опускается); нулей {len(нули)}")
    if поза == "FAIL":
        print("  ВЕРНУЛОСЬ В НОЛЬ ТО, ЧТО БЫЛО КУПЛЕНО: мир снят с ковки или сломан переездом "
              "дома — покрытие этого не видит, ибо считает строки, а пропало УМЕНИЕ.")
    return 0 if поза == "PASS" else 1


