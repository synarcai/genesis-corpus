#!/usr/bin/env python3
"""[УКАЗАТЕЛЬ МИРОВ] — рассказ о мирах есть СЛЕДСТВИЕ манифеста, а не рука составителя.

Свод вырос до 257 миров показов, и читателю негде увидеть их разом: манифест есть JSON на
полтора мегабайта, а `README` называет четыре числа. Указатель (`reports/ATLAS-WORLDS.md`)
собирается ИЗ МАНИФЕСТА и потому не может разойтись с ним молча.

    УКАЗАТЕЛЬ, ПИСАННЫЙ РУКОЙ, РАСХОДИТСЯ С МАНИФЕСТОМ В ДЕНЬ, КОГДА ЗАВОДЯТ МИР И ЗАБЫВАЮТ
    ДОПИСАТЬ СТРОКУ. Этот есть следствие и стареть не умеет — а если устарел, суд об этом скажет.

ЧТО СУДИТСЯ. Прибор пересобирает указатель в памяти и сличает с лежащим на диске: расхождение
есть УСТАРЕВШИЙ УКАЗАТЕЛЬ, и оно называется числом строк. Это тот же закон, каким живёт рука
записи манифеста: следствие обязано совпадать с тем, из чего выведено.

СУТЬ МИРА БЕРЁТСЯ ИЗ ЕГО ЖЕ ОБЪЯВЛЕНИЯ — заглавие и первая фраза за ним. Рука составителя не
пишет ни слова: где жанр беден, беден и указатель, и это ВИДНО, а не скрыто.

ГРУППЫ — ПО ОБЪЯВЛЕННОМУ АКТУ, а не по выдуманным семьям: акт есть словарь самого свода
(`manifest_kinds.АКТЫ`), и группировка по нему выведена, а не назначена.

ВТОРОЙ ДОЛГ, КОТОРЫЙ ДЕРЖИТ ЭТОТ ПРИБОР: миры, объявленные короче двухсот знаков. Первый замер
12.09 дал ШЕСТЬДЕСЯТ ТРИ из 257 — почти четверть: «arithmetic school (3 surfaces)» — тридцать
знаков на 11 380 строк. В ту же ночь уплачено ВОСЕМНАДЦАТЬ, и рубеж опущен до 45.

    ОБЪЯВЛЕНИЕ В ТРИДЦАТЬ ЗНАКОВ НЕ ЛЖЁТ И НЕ ГОВОРИТ: читатель узнаёт имя мира и ничего
    сверх него. Это долг манифеста, а не указателя, и он назван числом — убывать ему
    ковкой объявлений, а не правкой рубежа.

    python3 scripts/world_atlas.py            # сличить с лежащим на диске
    python3 scripts/world_atlas.py --собрать  # пересобрать указатель
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
УКАЗАТЕЛЬ = КОРЕНЬ / "reports" / "ATLAS-WORLDS.md"

# РУБЕЖ-ДОЛГА: РАСХОЖДЕНИЙ_РУБЕЖ = 0
РАСХОЖДЕНИЙ_РУБЕЖ = 0
# РУБЕЖ-ДОЛГА: БЕДНЫХ_РУБЕЖ = 16
БЕДНЫХ_РУБЕЖ = 16

БЕДНОЕ = 200
ТИРЕ = re.compile(r"\s[—–]\s")
ТОЧКА = re.compile(r"(?<=[a-zа-яё\)»0-9])\.(?:\s+(?=[A-ZА-ЯЁ«])|$)")


def суть(жанр):
    """Заглавие и первая фраза за ним — ровно то, чем мир себя называет.

    ПЕРВАЯ РЕДАКЦИЯ РЕЗАЛА ПО ПЕРВОМУ ЖЕ ТИРЕ и давала одно заглавие: «THE EPISODE»,
    «CONVERSATION LINKS». Заглавие есть ИМЯ, а не суть; суть стои́т сразу за ним.
    """
    ж = " ".join((жанр or "").split())
    if not ж:
        return "— объявление пусто"
    м = ТИРЕ.search(ж)
    if м:
        заглавие, хвост = ж[:м.start()].strip(), ж[м.end():].strip()
        т = ТОЧКА.search(хвост)
        вон = f"**{заглавие}** — {(хвост[:т.start() + 1] if т else хвост).strip()}"
    else:
        т = ТОЧКА.search(ж)
        вон = (ж[:т.start() + 1] if т else ж).strip()
    return вон if len(вон) <= 260 else вон[:257] + "…"


def собрать(манифест):
    """Текст указателя и число бедных объявлений — оба суть следствие манифеста."""
    import manifest_kinds as mk
    м = json.loads(манифест.read_text(encoding="utf-8"))
    миры = [з for з in м["worlds"] if з.get("text") == "shows"]
    по_акту, всего = {}, 0
    for з in миры:
        п = КОРЕНЬ / з["file"]
        строк = (len([x for x in п.read_text(encoding="utf-8", errors="replace").split("\n")
                      if x.strip()]) if п.is_file() else 0)
        всего += строк
        акт = (з.get("act") or ["unnamed"])[0]
        по_акту.setdefault(акт, []).append(
            (строк, з["name"], суть(з.get("genre")),
             list(з.get("oracle") or []) + list(з.get("boundary") or [])))
    out = [f"# УКАЗАТЕЛЬ МИРОВ ПОКАЗА — {len(миры)} миров, {всего} строк", "",
           "Собран из `datasets/GENESIS-MANIFEST.json` прибором `scripts/world_atlas.py`,",
           "а не написан рукой: суть каждого мира — первая фраза его собственного объявления,",
           "группы — по объявленному АКТУ. Суд сличает лежащее на диске с пересобранным.", "",
           "    УКАЗАТЕЛЬ, ПИСАННЫЙ РУКОЙ, РАСХОДИТСЯ С МАНИФЕСТОМ В ДЕНЬ, КОГДА ЗАВОДЯТ МИР",
           "    И ЗАБЫВАЮТ ДОПИСАТЬ СТРОКУ.", "",
           "Где объявление бедно, беден и указатель — и это ВИДНО, а не скрыто.", ""]
    for акт in sorted(по_акту, key=lambda а: (-len(по_акту[а]), а)):
        свои = sorted(по_акту[акт], reverse=True)
        out += [f"## АКТ «{акт}» — {mk.АКТЫ.get(акт, 'словарём не объявлен')}", "",
                f"Миров {len(свои)}, строк {sum(с for с, *_ in свои)}.", ""]
        for строк, имя, сут, метки in свои:
            out.append(f"- **`{имя}`** ({строк} строк; {', '.join(метки) or '—'})  ")
            out.append(f"  {сут}")
        out.append("")
    бедные = sorted((len(з.get("genre") or ""), з["name"]) for з in миры)
    бедные = [(n, и) for n, и in бедные if n < БЕДНОЕ]
    out += [f"## БЕДНЫЕ ОБЪЯВЛЕНИЯ — короче {БЕДНОЕ} знаков", "",
            "    ОБЪЯВЛЕНИЕ В ТРИДЦАТЬ ЗНАКОВ НЕ ЛЖЁТ И НЕ ГОВОРИТ: читатель узнаёт имя мира",
            "    и ничего сверх него.", "",
            f"Миров: **{len(бедные)}** из {len(миры)}.", ""]
    out += [f"- `{и}` — {n} знаков" for n, и in бедные]
    return "\n".join(out) + "\n", len(бедные)


def main():
    манифест = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
        if not манифест.is_file():
            print(f"УКАЗАТЕЛЬ МИРОВ ОТКАЗ: манифеста нет — {манифест}")
            return 2
    текст, бедных = собрать(манифест)
    if "--собрать" in sys.argv:
        УКАЗАТЕЛЬ.parent.mkdir(parents=True, exist_ok=True)
        УКАЗАТЕЛЬ.write_text(текст, encoding="utf-8")
        print(f"УКАЗАТЕЛЬ МИРОВ СОБРАН: {УКАЗАТЕЛЬ.name}, строк {текст.count(chr(10))}, "
              f"бедных объявлений {бедных}")
        return 0
    было = УКАЗАТЕЛЬ.read_text(encoding="utf-8") if УКАЗАТЕЛЬ.is_file() else ""
    расхождений = 0 if было == текст else abs(текст.count("\n") - было.count("\n")) or 1
    if расхождений:
        print(f"  указатель на диске разошёлся с манифестом: строк было "
              f"{было.count(chr(10))}, стало бы {текст.count(chr(10))}")
    поза = ("PASS" if расхождений <= РАСХОЖДЕНИЙ_РУБЕЖ and бедных <= БЕДНЫХ_РУБЕЖ else "FAIL")
    print(f"УКАЗАТЕЛЬ МИРОВ {поза}: {расхождений} расхождений с манифестом "
          f"(рубеж {РАСХОЖДЕНИЙ_РУБЕЖ}), бедных объявлений {бедных} "
          f"(рубеж {БЕДНЫХ_РУБЕЖ})")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
