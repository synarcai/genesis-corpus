#!/usr/bin/env python3
"""[БИБЛИОТЕКА КОРПУСА] — что наши тексты велят прочесть, и чего у нас нет.

КОРПУС САМ НАЗЫВАЕТ, ЧТО НАДО ПРОЧЕСТЬ, ЧТОБЫ ЕГО ПОНЯТЬ. Прозаические
корпуса ссылаются на чужие труды — «Lurie 2021», «Higher Topos Theory»,
«Process and Reality» — и всякая такая ссылка есть ОБЪЯВЛЕНИЕ, сделанное
автором корпуса: без этой книги мой текст понят не будет.

ЭТО ТРЕТИЙ ЗНАМЕНАТЕЛЬ ИЗВНЕ ЗА СУТКИ, и он лучший из трёх. Оглавления
корпусов дали список ПРЕДМЕТОВ; полоса дала список СЛОВ; библиография
даёт список КНИГ — причём отобранный не нами и не для этой меры.

ДВА РОДА ССЫЛКИ, И ОБА ЖИВУТ В НАШЕЙ ПРОЗЕ ЧИСЛОМ:
  · АВТОР И ГОД — «Росицкий 1994», «Albert & Jiang 2014»: 2424 строки;
  · ИМЯ ТРУДА — «Higher Topos Theory, Theorem 6.2.2.7», «The Octonions,
    §3»: 92 строки, и это самые точные ссылки, ибо несут заглавие.

ЧЕГО ЭТА МЕРА НЕ ГОВОРИТ, И ЭТО НАДО СКАЗАТЬ ПЕРВЫМ. Она не знает, что
книга ДОСТУПНА: авторские права, издания, переводы — вне её ведения.
Она называет ДОЛГ ЧТЕНИЯ, а не план закупки. Книга, названная корпусом
и защищённая правом, остаётся в списке — и остаётся честной строкой
долга, которую закрывает не полка, а переоткрытие.
"""
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "scripts"))

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest

# РУБЕЖ-ДОЛГА: НЕ_НА_ПОЛКЕ_РУБЕЖ = 1643
#
# ЧИСЛО ВТОРОГО ЗАМЕРА, ПОСЛЕ ОЧИСТКИ ЗНАМЕНАТЕЛЯ: наши семь сводов
# называют 1684 источника, и 1647 из них на полке нет. Первый замер
# давал 1992 и 1947 — но он читал и КНИГИ ПОЛКИ, а те ссылаются на
# свою эпоху: долг РОС ОТ ЧТЕНИЯ и уменьшиться не мог никогда. Верх списка по частоте упоминаний: Яновский (2003) — 34 раза,
# Petz (1996) — 28, Uhlmann (1976) — 26, Schreiber (2013) — 25, Лоувер
# (1969) — 20, Тарский (1933) — 15, Жирар (1987) — 14, Гёдель (1931) —
# 12, Коэн (1963) — 12.
#
# ДОЛГ ЧТЕНИЯ НЕ ЕСТЬ ПЛАН ЗАКУПКИ. Часть названного защищена правом и
# на полку не ляжет никогда; такая строка долга закрывается не покупкой,
# а ПЕРЕОТКРЫТИЕМ — выведением механизма не слабее из наших оснований.
# Потому убыль этого числа не есть единственная его добродетель:
# честнее знать, чего мы не читали, чем не знать.
НЕ_НА_ПОЛКЕ_РУБЕЖ = 1643

# Год издания: от начала книгопечатания науки до сего дня. Границы
# объявлены, чтобы «Уровень 6» и «поколение 2» не читались как год.
ГОД = r"(1[5-9]\d\d|20[0-2]\d)"
АВТОР_ГОД = re.compile(
    r"\b([A-ZА-ЯЁ][a-zа-яё]{3,}(?:\s+(?:and|&|и)\s+[A-ZА-ЯЁ][a-zа-яё]{3,})?)"
    r"[\s,]+\(?" + ГОД + r"\)?")
# Имя труда опознаётся тем, что за ним следует УКАЗАНИЕ МЕСТА в нём:
# теорема, глава, страница, параграф. Ссылка на место есть вернейший
# признак книги: на «уровень» и «поколение» так не ссылаются.
ИМЯ_ТРУДА = re.compile(
    r"\b([A-Z][A-Za-z]+(?:\s+(?:of|and|the|in|[A-Z][A-Za-z]+)){1,5})"
    r"\s*,\s*(?:Theorem|Chapter|Ch\.|p\.|pp\.|§|Prop|Proposition|Lemma)")


def манифест(путь):
    if not путь.exists():
        return None
    return json.loads(путь.read_text(encoding="utf-8"))


def _файл(мир, корень, внешний):
    п = корень / мир["file"]
    if п.exists():
        return п
    if внешний:
        п = (корень / внешний / мир["file"]).resolve()
        if п.exists():
            return п
    return None


def main():
    путь = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    if "--manifest" in sys.argv:
        путь = pathlib.Path(sys.argv[sys.argv.index("--manifest") + 1])
    м = манифест(путь)
    if not м:
        print(f"БИБЛИОТЕКА ОТКАЗ: манифеста «{путь}» нет")
        return 2
    внешний = м.get("external_root")

    авторы = collections.Counter()
    труды = collections.Counter()
    корпусов = 0
    # ПОЛКА ЕСТЬ ТО, ЧТО У НАС УЖЕ ЛЕЖИТ: её имена собираются из
    # манифеста, а не из каталога, ибо мир, не объявленный манифестом,
    # для корпуса не существует.
    на_полке = " ".join(
        (w.get("name", "") + " " + w.get("genre", "") + " "
         + str(w.get("происхождение", ""))).lower()
        for w in м["worlds"] if w.get("text") == "prose")

    for мир in м["worlds"]:
        if мир.get("text") != "prose":
            continue
        # МЕРА ЧИТАЕТ БИБЛИОГРАФИЮ НАШИХ СВОДОВ, А НЕ ЧУЖИХ КНИГ.
        #
        # Прибор брал ссылки ВСЕХ прозаических миров, включая полку, —
        # и оттого РОС ОТ ЧТЕНИЯ: книга XIX века сплошь ссылается на
        # свою эпоху, закрывает одну строку долга и приносит десятки
        # новых. Долг, который нельзя уменьшить чтением, не есть долг
        # чтения.
        #
        # Предельный случай, найденный подсадкой соседней руки: Де
        # Морган, «Budget of Paradoxes», — по содержанию драгоценная
        # книга (разборы ложных доказательств, квадратура круга), по
        # устройству библиографический каталог: «Paris, 1618»,
        # «London, 1611», «Leipsic, 1892». Прибор читал ГОРОД ИЗДАНИЯ
        # КАК ФАМИЛИЮ и внёс с одной книги 734 источника — больше, чем
        # весь свод математических оснований.
        #
        # Признак объявлен и уже живёт в манифесте: у мира ПОЛКИ есть
        # поле «источник» (public-domain, CC BY), у нашего свода его
        # нет. Долг чтения есть долг НАШИХ текстов: что назвали МЫ,
        # чтобы нас поняли, — а не что называет купленная книга.
        if мир.get("источник"):
            continue
        п = _файл(мир, КОРЕНЬ, внешний)
        if п is None:
            continue
        корпусов += 1
        for с in п.read_text(encoding="utf-8", errors="replace").splitlines():
            for m in АВТОР_ГОД.finditer(с):
                авторы[(m.group(1), m.group(2))] += 1
            for m in ИМЯ_ТРУДА.finditer(с):
                труды[m.group(1)] += 1

    if not авторы and not труды:
        print("БИБЛИОТЕКА ОТКАЗ: ссылок в прозе не найдено")
        return 2

    нет_труда = [(т, n) for т, n in труды.items()
                 if т.lower().split()[0] not in на_полке]
    нет_автора = [(а, г, n) for (а, г), n in авторы.items()
                  if а.lower() not in на_полке]
    нет_труда.sort(key=lambda х: -х[1])
    нет_автора.sort(key=lambda х: -х[2])

    print("  НАЗВАННЫЕ ТРУДЫ, КОТОРЫХ НА ПОЛКЕ НЕТ:")
    for т, n in нет_труда[:20]:
        print(f"    «{т}» — названо {n} раз")
    print("  НАЗВАННЫЕ АВТОРЫ, КОТОРЫХ НА ПОЛКЕ НЕТ:")
    for а, г, n in нет_автора[:25]:
        print(f"    {а} ({г}) — названо {n} раз")
    всего = len(труды) + len(авторы)
    нет = len(нет_труда) + len(нет_автора)
    поза = ("ОТЧЁТ" if НЕ_НА_ПОЛКЕ_РУБЕЖ is None else
            "PASS" if нет <= НЕ_НА_ПОЛКЕ_РУБЕЖ else "FAIL")
    print(f"БИБЛИОТЕКА {поза}: названо {всего} источников "
          f"({len(труды)} трудов по заглавию, {len(авторы)} по автору с "
          f"годом), НЕТ НА ПОЛКЕ {нет}; корпусов прозы {корпусов}")
    if НЕ_НА_ПОЛКЕ_РУБЕЖ is None:
        return 0
    return 0 if нет <= НЕ_НА_ПОЛКЕ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
