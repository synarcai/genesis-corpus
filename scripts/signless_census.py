#!/usr/bin/env python3
"""[ПЕРЕПИСЬ БЕЗЗНАКОВЫХ] — строки пластов, не несущие знака НИ ОДНОГО языка.

ПЕЧАТАЕТ ЧИСЛО, НЕ ПАДАЕТ. Это перепись, а не суд: она называет размер беды и цену лечения,
а решение о лечении принимается отдельно, ибо лечение задевает опознание языка во всём своде.

    СТРОКА БЕЗ ЕДИНОГО ОБЪЯВЛЕННОГО СЛОВА БЕЗЗАЩИТНА: ЕЁ СУДИТ ВСЯКИЙ, КТО УЗНАЛ В НЕЙ
    СВОЁ СЛОВО.

Знак языка (`tools/langsign.счёт`) считается по СЛУЖЕБНЫМ словам, объявленным пакетами. Выбор
разумный: служебные слова различают языки лучше прочих. Но у него есть цена, и перепись её
называет: строка, в которой служебных слов нет вовсе, получает ноль ото всех — и `чужой()`
для всякого языка ложен, то есть ВСЯКИЙ суд считает её своей.

Так 07.09 английский счёт назвал ложью польскую «liczę 2 ruble.»: польских служебных слов в
ней нет, «ruble» стояло объявленным английскому, и суд взял строку по праву.

ЦЕНА ЛЕЧЕНИЯ ИЗМЕРЕНА, А НЕ ОБЕЩАНА. Из 6539 слов, объявленных двадцатью девятью пакетами,
5955 объявлены РОВНО ОДНИМ языком. Закон «слово, объявленное ровно одним языком, есть знак
этого языка» дал бы знак 84 % беззнаковых строк.

    ЧЕГО ЛЕЧЕНИЕ СТО́ИТ, И ПОЧЕМУ ОНО НЕ СДЕЛАНО ОДНИМ ДВИЖЕНИЕМ. `чужой()` молчит, когда
    чужой знак НЕ МЕНЬШЕ своего. Двуязычная страница (ядро пар, переводы) получит знак ОБОИХ
    языков поровну — и оба суда откажутся, а строка станет НЕМОЙ у всех. Немота дороже
    ложной тревоги: ложь видна, немота нет.

Потому перепись стои́т, а закон ждёт меры немоты до и после. Число здесь — заказ, а не приговор.

    python3 scripts/signless_census.py [--строк 200]
"""
# ПУСТОЙ-ОБХОД: --строк 0
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import langsign  # noqa: E402

СЛОВО = re.compile(r"[^\W\d_]+")
НЕ_СЛОВАРНЫЕ = frozenset(("comment", "lexeme_source", "ask_words_comment"))


def указатель():
    """Слово → языки, его объявившие."""
    идх = collections.defaultdict(set)
    for п in sorted((КОРЕНЬ / "tools" / "langpacks").glob("*.json")):
        пак = json.loads(п.read_text(encoding="utf-8"))
        я = пак.get("lang", п.stem)
        слова = set()

        def взять(x):
            if isinstance(x, str):
                слова.update(w.lower() for w in СЛОВО.findall(x))
            elif isinstance(x, dict):
                for k, v in x.items():
                    взять(k); взять(v)
            elif isinstance(x, (list, tuple)):
                for v in x:
                    взять(v)

        for поле, знач in пак.items():
            if поле in НЕ_СЛОВАРНЫЕ:
                continue
            взять(знач)
        for w in слова:
            идх[w].add(я)
    return идх


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--строк", type=int, default=200, help="строк на пласт")
    дов = ап.parse_args()
    пласты = sorted((КОРЕНЬ / "datasets").glob("genesis_lang_*.txt"))
    if not пласты or дов.строк <= 0:
        print("ПЕРЕПИСЬ БЕЗЗНАКОВЫХ ОТКАЗ: считать нечего "
              f"(пластов {len(пласты)}, строк на пласт {дов.строк})")
        return 0
    идх = указатель()
    единоличных = {w: next(iter(я)) for w, я in идх.items() if len(я) == 1}
    без_знака = спасено = всего = 0
    по_языкам = collections.Counter()
    for f in пласты:
        я = f.stem.replace("genesis_lang_", "")
        строки = [с for с in f.read_text(encoding="utf-8").split("\n") if с.strip()][:дов.строк]
        for с in строки:
            всего += 1
            if any(v > 0 for v in langsign.счёт(с).values()):
                continue
            без_знака += 1
            по_языкам[я] += 1
            if any(w in единоличных for w in СЛОВО.findall(с.lower())):
                спасено += 1
    доля = 100 * без_знака / max(1, всего)
    лечит = 100 * спасено / max(1, без_знака)
    print(f"{'пласт':<8}{'беззнаковых':>13}")
    for я, n in по_языкам.most_common(10):
        print(f"{я:<8}{n:>13}")
    print(f"ПЕРЕПИСЬ БЕЗЗНАКОВЫХ: строк осмотрено {всего} из {len(пласты)} пластов; "
          f"БЕЗ ЗНАКА НИ ОДНОГО ЯЗЫКА {без_знака} ({доля:.0f} %); знак дало бы единоличное "
          f"слово {спасено} ({лечит:.0f} %); слов в указателе {len(идх)}, "
          f"единоличных {len(единоличных)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
