#!/usr/bin/env python3
"""[СТРАЖ ЧАСТНОГО ИТОГА] — дорогой прибор обязан сказать первое слово рано.

Прибор, идущий час и печатающий один вердикт в конце, отдаёт своду ВСЁ ИЛИ
НИЧЕГО: дошёл — час работы; снят на пятьдесят девятой минуте — ноль байт.
Свод, чей набор обрывается (машина занята, потолок времени, рука), теряет
на этом не проценты, а целые приборы: ночью 12.09 один такой прибор отработал
шестьдесят минут и оставил пустой файл.

    ПРИБОР, ГОВОРЯЩИЙ ТОЛЬКО В КОНЦЕ, ЕСТЬ ПРИБОР, КОТОРОГО ПРИ ОБРЫВЕ НЕ БЫЛО.
    Цена его при этом уплачена полностью — обрыв берёт машинное время и не
    отдаёт ничего.

ДВЕ ПРИЧИНЫ МОЛЧАНИЯ, И ОБЕ ЛЕЧАТСЯ РАЗНО:

  · ПРИВЫЧКА ПЕЧАТАТЬ В КОНЦЕ — видна в исходнике, лечится рукой писавшего;
  · БУФЕР — невидим. CPython, пишущий в файл, копит вывод блоками по 8 КБ.
    Замер 12.09: скрипт, печатавший строку каждые 50 мс и снятый через две
    секунды, оставил РОВНО НОЛЬ БАЙТ; он же под `python3 -u` — 34 строки.
    Оттого набор ныне зовёт приборы с `-u`, и это условие меры: без него
    честный прибор неотличим от молчащего.

МЕРА БЕРЁТСЯ С НАСТОЯЩЕГО ПРОГОНА, А НЕ С ЛИШНЕГО. Набор сам засекает, через
сколько секунд у прибора появилась первая строка, и пишет в `reports/SUITE-TRACE.tsv`
пять полей: метка, имя, секунд всего, секунд до первой строки, строк вывода.

    МЕРА, ТРЕБУЮЩАЯ ВТОРОГО ПРОГОНА, МЕРИТ ВТОРОЙ ПРОГОН. Она к тому же
    удваивает цену того самого, на что жалуется.

ЗАКОН ЗДЕСЬ ТАКОВ: прибор дороже ПОРОГА обязан сказать первое слово прежде,
чем истечёт ЧЕТВЕРТЬ его времени (но ему всегда дано не меньше тридцати
секунд на разгон — чтение свода не есть молчание).

ПОКА ЭТО ОТЧЁТ, А НЕ РУБЕЖ, И СКАЗАНО ПОЧЕМУ: числа ещё нет — след заведён в
тот же день, что и прибор. Рубеж заводится по ПЕРВОМУ полному прогону и с той
поры ходит только вниз, как всякий долг корпуса. Отчёт, объявленный рубежом
прежде замера, есть рубеж, взятый с потолка.

    python3 scripts/partial_guard.py
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
СЛЕД = КОРЕНЬ / "reports" / "SUITE-TRACE.tsv"

# ДОРОГИМ СЧИТАЕТСЯ ПРИБОР ОТ ДВУХ МИНУТ: дешевле — не жаль перегнать заново,
# и требовать от него частного итога значит требовать шума.
ПОРОГ_ДОРОГОГО = 120
# РАЗГОН: тридцать секунд молчания прощаются всякому — прибор, читающий свод
# в 40 МБ, эти секунды тратит на чтение, и это не молчание, а работа.
РАЗГОН = 30
ДОЛЯ = 4  # первое слово — до истечения 1/ДОЛЯ времени прибора


def срок(всего):
    """Докуда прибору позволено молчать."""
    return max(РАЗГОН, всего // ДОЛЯ)


def след(строки):
    """{имя: (всего, до_первой, строк)} — ПОСЛЕДНЯЯ запись каждого прибора."""
    вон = {}
    for с in строки:
        ч = с.split("\t")
        if len(ч) < 5 or ч[0].startswith("#"):
            continue
        try:
            вон[ч[1]] = (int(ч[2]), int(ч[3]), int(ч[4]))
        except ValueError:
            continue
    return вон


def молчащие(записи):
    """(молчащие, дорогие) — дорогие приборы, чьё первое слово пришло поздно."""
    дорогие = {и: з for и, з in записи.items() if з[0] >= ПОРОГ_ДОРОГОГО}
    вон = []
    for и, (всего, первая, строк) in sorted(дорогие.items()):
        if первая < 0:
            вон.append((и, всего, первая, строк, "сторож не досчитал — прибор снят"))
        elif первая > срок(всего):
            вон.append((и, всего, первая, строк,
                        f"молчал {первая} с при позволенных {срок(всего)}"))
    return вон, дорогие


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что СРОК СЧИТАЕТСЯ И ПОЗДНИЙ ВИДЕН.

        ПРИБОР ЭТОТ СУДИТ ПО ДВУМ ЧИСЛАМ, И ОБА ЛЕГКО СПУТАТЬ МЕСТАМИ. Пусть
        срок посчитается от доли без разгона — и всякий двухминутный прибор,
        читающий свод сорок секунд, объявится молчащим. Пусть дорогим станет
        кто угодно — и отчёт наполнится приборами, которых не жаль.

        НУЛЬ ЗРЯЧЕГО ОБЯЗАН ОТЛИЧАТЬСЯ ОТ НУЛЯ СЛЕПОГО.

    Шесть записей следа настоящей формы, и про каждую известно заранее.
    """
    беды = []
    if срок(120) != 30:
        беды.append(f"срок двухминутного {срок(120)}, а не 30 — разгон потерян")
    if срок(4000) != 1000:
        беды.append(f"срок часового {срок(4000)}, а не 1000 — доля потеряна")
    выдумка = [
        "# метка\tимя\tвсего\tдо первой\tстрок",
        "2026-09-12T12:00:00Z\tдешёвый_молчун.py\t20\t20\t1",
        "2026-09-12T12:00:01Z\tдорогой_говорун.py\t400\t12\t900",
        "2026-09-12T12:00:02Z\tдорогой_молчун.py\t400\t399\t1",
        "2026-09-12T12:00:03Z\tдорогой_разгон.py\t130\t29\t40",
        "2026-09-12T12:00:04Z\tснятый.py\t600\t-1\t0",
        "рваная строка",
    ]
    записи = след(выдумка)
    if len(записи) != 5:
        беды.append(f"прочтено записей {len(записи)}, а не 5 — рваная строка сбила разбор")
    имена, дорогие = молчащие(записи)
    имена = {и for и, *_ in имена}
    if "дешёвый_молчун.py" in имена:
        беды.append("дешёвый назван молчащим — порог дороговизны не работает")
    if "дешёвый_молчун.py" in дорогие:
        беды.append("двадцатисекундный сочтён дорогим")
    if "дорогой_говорун.py" in имена:
        беды.append("говорун назван молчащим — ранняя строка не зачтена")
    if "дорогой_молчун.py" not in имена:
        беды.append("МОЛЧУН НЕ НАЙДЕН — прибор слеп к тому, ради чего поставлен")
    if "дорогой_разгон.py" in имена:
        беды.append("разгон в 29 с сочтён молчанием — прибор требует невозможного")
    if "снятый.py" not in имена:
        беды.append("снятый без замера сочтён говоруном — неизвестное принято за доброе")
    return беды


def main():
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ЧАСТНЫЙ ИТОГ ОТКАЗ: счёт срока не доказан ({len(беды)} бед)")
        return 2
    if not СЛЕД.is_file():
        print(f"ЧАСТНЫЙ ИТОГ ОТКАЗ: следа нет — {СЛЕД.relative_to(КОРЕНЬ)}; "
              "его пишет scripts/courts.sh по ходу набора")
        return 2
    записи = след(СЛЕД.read_text(encoding="utf-8", errors="replace").splitlines())
    имена, дорогие = молчащие(записи)
    for и, всего, первая, строк, почему in имена:
        print(f"  БЕЗ ЧАСТНОГО ИТОГА {и}: шёл {всего} с, {почему}, строк вывода {строк}")
    цена = sum(в for и, в, *_ in имена)
    print(f"ЧАСТНЫЙ ИТОГ ОТЧЁТ: без частного итога {len(имена)} из {len(дорогие)} дорогих "
          f"(дороже {ПОРОГ_ДОРОГОГО} с) при {len(записи)} приборах следа; "
          f"их общая цена {цена} с — столько теряет всякий обрыв на этом месте")
    return 0


if __name__ == "__main__":
    sys.exit(main())
