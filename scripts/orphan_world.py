#!/usr/bin/env python3
"""[МИР БЕЗ КУЗНИ] — мир, которого не кует никто, нельзя собрать заново.

СВОД СТОИ́Т НА ОДНОМ ОБЕЩАНИИ: всякий мир есть СЛЕДСТВИЕ манифеста, и его можно снести и собрать
заново из ничего. Воспроизводимость это обещание проверяет — но только в одну сторону: она берёт
КУЗНИЦЫ и сверяет, что каждая даёт свой файл. Мир, которого не кует НИ ОДНА кузня, в её обход
не попадает вовсе.

    ПРОВЕРКА, ИДУЩАЯ ОТ КУЗНИЦ К МИРАМ, НЕ ВИДИТ МИРА, У КОТОРОГО КУЗНИЦЫ НЕТ.

ЗАМЕР 11.09: из 254 миров показов у ОДНОГО нет кузни — `algebra_units`
(`datasets/genesis_l2_algebra_units.txt`, 261 строка). Файл есть, суды его читают, манифест о нём
знает; снести и собрать заново его нельзя ничем.

    МИР, КОТОРОГО НЕЛЬЗЯ СОБРАТЬ, ЕСТЬ НЕ СЛЕДСТВИЕ МАНИФЕСТА, А НАХОДКА В КАТАЛОГЕ.

ЦЕЛЬ КУЗНИ БЕРЁТСЯ РАЗБОРОМ, А НЕ ПОИСКОМ ПОДСТРОКИ: кузня языков пишет цель СОСТАВНОЙ строкой
(`f"datasets/genesis_lang_" f"{pack['lang']}.txt"`), и поиск литерала объявил бы сиротами все
двадцать девять языковых миров. Разбор деревом видит такую строку как образец и обращает
подставляемое в «что угодно, кроме косой черты».

    ПРИЗНАК, ИЩУЩИЙ ЦЕЛЬ ПОДСТРОКОЙ, ОБЪЯВЛЯЕТ СИРОТОЙ ВСЯКОГО, ЧЬЁ ИМЯ СОБРАНО НА ЛЕТУ.

ПОЧЕМУ ДОЛГ РАВЕН ЕДИНИЦЕ, А НЕ НУЛЮ. Сироту можно было бы закрыть в час: написать кузню, которая
держит все 261 строку списком и выкладывает их подряд. Воспроизводимость тогда сойдётся, число
станет нулём, и обещание свода будет нарушено ровно так же, как теперь, — только молча.

    КУЗНЯ, ПЕРЕЧИСЛЯЮЩАЯ СВОИ СТРОКИ, ЕСТЬ НЕ КУЗНЯ, А СПИСОК: она собирает мир заново,
    ничего о нём не зная, и обращает проверку в обряд.

Долг оставлен числом и названием. Уплатить его значит РАЗОБРАТЬ мир на роды и выковать их
правилами — то есть сделать с ним то, что сделано с остальными двумястами пятьюдесятью тремя.

ГРАНИЦА НАЗВАНА: прибор спрашивает, ЕСТЬ ЛИ кузня, а не собирается ли мир ею верно — на второй
вопрос отвечает воспроизводимость, и стои́т это часа. Два прибора идут в одну сторону с разных
концов.

    python3 scripts/orphan_world.py
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import ast
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
ГДЕ = ("tools", "scripts")

# РУБЕЖ-ДОЛГА: СИРОТ_РУБЕЖ = 0
СИРОТ_РУБЕЖ = 0

ЦЕЛЬ = re.compile(r"^datasets/[^/]+\.txt$")


def _образцы_файла(путь):
    """Все строковые образцы «datasets/….txt», какие даёт файл, — литералы и f-строки."""
    try:
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return set()
    вон = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            if ЦЕЛЬ.match(узел.value):
                вон.add(re.escape(узел.value))
        elif isinstance(узел, ast.JoinedStr):
            куски = []
            for часть in узел.values:
                if isinstance(часть, ast.Constant) and isinstance(часть.value, str):
                    куски.append(re.escape(часть.value))
                else:
                    # ПОДСТАВЛЯЕМОЕ ЕСТЬ ЧТО УГОДНО, КРОМЕ КОСОЙ ЧЕРТЫ: цель лежит в одной папке.
                    куски.append(r"[^/]+")
            образец = "".join(куски)
            if образец.startswith(re.escape("datasets/")) and образец.endswith(re.escape(".txt")):
                вон.add(образец)
    return вон


def кузни(корень):
    """Образцы целей всех кузниц дерева."""
    вон = set()
    for где in ГДЕ:
        двор = корень / где
        if двор.is_dir():
            for путь in sorted(двор.glob("*.py")):
                вон |= _образцы_файла(путь)
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что цель кузницы УЗНАЁТСЯ и что чужая
    строка целью НЕ становится.

        СИРОТ НЕ НАЙДЕТСЯ НИ ОДНОЙ, ЕСЛИ ОБРАЗЕЦ ЦЕЛИ РАЗРАСТЁТСЯ ДО «ЧЕГО УГОДНО»:
        всякий мир окажется кем-то кованным, и прибор зазеленеет навсегда. Обратная
        порча — образец, не узнающий ничего, — кричит сама (все миры сироты), и потому
        опаснее именно первая.

    Проба ставит кузницу из четырёх строк: литерал цели, f-строка с дырой, чужой путь и
    строка вовсе не о файлах.
    """
    import tempfile
    кузня = (
        'ЦЕЛЬ = "datasets/genesis_проба.txt"\n'
        'def имя(род):\n'
        '    return f"datasets/genesis_{род}.txt"\n'
        'ЧУЖОЕ = "reports/DAY.md"\n'
        'СЛОВО = "просто строка"\n'
    )
    беды = []
    with tempfile.TemporaryDirectory() as д:
        ф = pathlib.Path(д) / "gen_genesis_проба.py"
        ф.write_text(кузня, encoding="utf-8")
        свои = _образцы_файла(ф)
    прямой = re.escape("datasets/genesis_проба.txt")
    сдырой = re.escape("datasets/genesis_") + "[^/]+" + re.escape(".txt")
    if прямой not in свои:
        беды.append("литерал цели не узнан — кузница осталась бы безголосой")
    if сдырой not in свои:
        беды.append(f"f-строка не узнана: {sorted(свои)}")
    if len(свои) != 2:
        беды.append(f"взято лишнее: {sorted(свои)} — образец цели разросся")
    # И ГЛАВНОЕ: ОБРАЗЕЦ ОБЯЗАН РАЗЛИЧАТЬ, А НЕ ПРОСТО НАХОДИТЬ.
    if any(re.fullmatch(о, "reports/DAY.md") for о in свои):
        беды.append("ЧУЖОЙ ПУТЬ ПОДОШЁЛ ПОД ОБРАЗЕЦ ЦЕЛИ — сирот не найдётся никогда")
    if any(re.fullmatch(о, "datasets/genesis_чужой/внутри.txt") for о in свои):
        беды.append("дыра проглотила косую черту — цель ищется не в своей папке")
    if not any(re.fullmatch(о, "datasets/genesis_иной.txt") for о in свои):
        беды.append("f-строка не покрыла своей же цели")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"МИР-СИРОТА ОТКАЗ: образец цели не доказан ({len(беды)} бед)")
        return 2
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
        if not манифест.is_file():
            print(f"МИР БЕЗ КУЗНИ ОТКАЗ: манифеста нет — {манифест}")
            return 2
    миры = [з for з in json.loads(манифест.read_text(encoding="utf-8"))["worlds"]
            if з.get("text") == "shows"]
    if not миры:
        print("МИР БЕЗ КУЗНИ ОТКАЗ: миров показов в манифесте нет, спрашивать не о ком")
        return 2
    образцы = [re.compile(о + "$") for о in кузни(КОРЕНЬ)]
    сироты = [з["name"] for з in миры
              if not any(о.match(з["file"]) for о in образцы)]
    for и in сироты[:8]:
        print(f"  {и}: ни одна кузня не объявляет его целью")
    поза = "PASS" if len(сироты) <= СИРОТ_РУБЕЖ else "FAIL"
    print(f"МИР БЕЗ КУЗНИ {поза}: {len(сироты)} миров нельзя собрать заново "
          f"(рубеж {СИРОТ_РУБЕЖ}) из {len(миры)}; образцов целей {len(образцы)}")
    return 0 if len(сироты) <= СИРОТ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
