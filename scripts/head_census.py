#!/usr/bin/env python3
"""[ПЕРЕПИСЬ ВОПРОСНЫХ ГОЛОВ] — сколько голов свод несёт и сколько из них ОДИНОЧКИ.

Закон d5 (04.09): форма покупается, когда встречена не меньше чем в ДВУХ
окружениях; двадцать четыре показа в одном окружении дают ноль операторов.
Приложенный к вопросным головам, он даёт меру, которой у корпуса не было:

    голова, встреченная ОДИН раз, не покупается НИКОГДА, сколько бы строк
    ни стояло за нею в других родах. Она есть не форма, а обмолвка.

Прибор режет всякую вопросную строку до ГОЛОВЫ (первые N слов до знака
вопроса), считает их массу и печатает: сколько голов всего, сколько одиночек,
и какие миры их несут. Одиночка не есть ложь и не есть долг — она есть ЦЕНА,
названная числом: место, где корпус сказал нечто единожды и потому не сказал.

ГОЛОВА РЕЖЕТСЯ ПО СЛОВАМ, А НЕ ПО СКЕЛЕТУ, и это нарочно: скелет заменяет
числа и имена дырами, а голова вопроса тем и важна, что состоит из СЛУЖЕБНЫХ
слов, которых скелет не трогает. Две меры смотрят на разное.

    python3 scripts/head_census.py [--слов 2] [--свод datasets/GENESIS-FULL.txt]
"""
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402
import asking  # noqa: E402


# ЧИСЛО В ГОЛОВЕ ЕСТЬ ДЫРА, А НЕ СЛОВО. Первая проба резала голову по словам
# как есть, и всякая пара чисел давала СВОЮ голову: дом подобия дал 64
# «одиночки», дом мнения 58 — то есть прибор считал одиночками не обмолвки, а
# исправно работающие роды. Числа заменяются дырой прежде счёта.
_ЧИСЛО = re.compile(r"\d+")
_КРАЙ = " .,:;!?«»\"'()¿¡"

# ВОПРОСНЫЕ СЛОВА БЕРУТСЯ У ДОМА ПАРЫ, А НЕ ИЗ ПОЛНОГО СПИСКА ЗАЧИНОВ. Полный
# `asking.ЗАЧИНЫ` (436 записей) вобрал зачины ПАКЕТОВ и потому несёт имена
# («ben»), предлоги («во», «на»), союзы («и», «e») и даже дыру числа «#» — он
# годен там, где спрашивают «открывается ли строка чем-то объявленным», и не
# годен там, где спрашивают «где НАЧИНАЕТСЯ ВОПРОС». Резав по нему, прибор
# считал головами «# coins» и «ben had» и насчитал 258 одиночек вместо 88.
# Третий раз за час одна и та же болезнь (М-275): разрез не по границе предмета.
# ДЫРА ЧИСЛА ОБЪЯВЛЕНА ЗАЧИНОМ, но головой быть не может: «# balón», «# coins»,
# «# градусах» суть не вопросные головы, а числа, попавшие в начало. Дом пары
# объявляет «#» зачином по своему делу (строка МОЖЕТ открываться числом), у
# переписи голов дело иное — и потому она берёт объявление соседа С ИМЕНОВАННЫМ
# ВЫЧЕТОМ, а не целиком. Вычет один и назван.
_ВОПРОСНЫЕ = frozenset(asking._ЗАЧИНЫ_ДОМА) - {"#"}


def головы(строки, слов):
    вон = collections.Counter()
    for с in строки:
        т = с.strip()
        if "?" not in т:
            continue
        вопрос = _ЧИСЛО.sub("#", т.split("?")[0].split(". ")[-1])
        части = вопрос.split()
        # ГОЛОВА НАЧИНАЕТСЯ С ВОПРОСНОГО СЛОВА, А НЕ С НАЧАЛА ПРЕДЛОЖЕНИЯ.
        # Дом факта и мнения ставит вопрос в КОНЕЦ («лёд плавает в воде — это
        # факт или мнение?»), и прибор, резавший с начала, звал одиночками 58
        # его показов — то есть считал головой подлежащее. Голова вопроса
        # объявлена домом пары (asking.ЗАЧИНЫ), и с неё же она и начинается.
        с_какого = next((i for i, сл in enumerate(части)
                         if сл.strip(_КРАЙ).lower() in _ВОПРОСНЫЕ), None)
        if с_какого is None:
            вон["(без объявленного зачина)"] += 1
            continue
        части = части[с_какого:]
        if len(части) >= слов:
            вон[" ".join(части[:слов]).lower()] += 1
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--слов", type=int, default=2)
    ап.add_argument("--свод", default="datasets/GENESIS-FULL.txt")
    ап.add_argument("--имён", type=int, default=6)
    а = ап.parse_args()
    путь = КОРЕНЬ / а.свод
    строки = [с for с in путь.read_text(encoding="utf-8", errors="replace").splitlines()
              if с.strip() and not с.startswith("\x0c")]
    счёт = головы(строки, а.слов)
    одиночки = [г for г, n in счёт.items() if n == 1]
    # МИРЫ ОДИНОЧЕК: где именно сказано единожды
    по_мирам = collections.Counter()
    один = set(одиночки)
    for путь_мира in genesis.worlds(kind="shows"):
        свои = головы(путь_мира.read_text(encoding="utf-8", errors="replace").splitlines(), а.слов)
        для_мира = sum(1 for г in свои if г in один)
        if для_мира:
            по_мирам[путь_мира.name] = для_мира
    всего = sum(счёт.values())
    print(f"{'голова':34} {'строк':>7}")
    for г, n in счёт.most_common(а.имён):
        print(f"{г[:34]:34} {n:7}")
    print(f"  МИРЫ, ГДЕ БОЛЬШЕ ВСЕГО ОДИНОЧЕК:")
    for имя, n in по_мирам.most_common(а.имён):
        print(f"    {n:5}  {имя}")
    доля = 100 * len(одиночки) // max(1, len(счёт))
    print(f"ПЕРЕПИСЬ ГОЛОВ: голов {len(счёт)} на {всего} вопросных строк "
          f"(по {а.слов} слова); ОДИНОЧЕК {len(одиночки)} ({доля} %), они несут "
          f"{len(одиночки)} строк — столько же, сколько голов")
    if not счёт:
        print("  ВНИМАНИЕ: голов НОЛЬ — прибор ничего не прочёл (М-264)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
