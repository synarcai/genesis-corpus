#!/usr/bin/env python3
"""[СТРАТИФИЦИРОВАННЫЙ СРЕЗ] — мера за минуты, у которой есть КАЖДАЯ конструкция свода.

ПОВОД (ARCH-REVIEW-0907, П-3 и Р-4). Школьный срез есть первые 143 мира из 420 по полю
`assemblies`, и в нём НЕТ `svamp` — того самого мира, чьи такты меряет полоса. Читатель на
срезе читает SVAMP 116/0, на полном своде — 56/0: срез не предсказывает полного свода, и
цикл «корпус → ковка → полоса» в восемьдесят минут остаётся единственной мерой.

    СРЕЗ, В КОТОРОМ НЕТ КОНСТРУКЦИИ, НЕ ГОВОРИТ О НЕЙ НИЧЕГО — ни хорошего, ни плохого.
    Отбор миров ЦЕЛИКОМ выбрасывает конструкции пачками; отбор СТРАНИЦ оставляет все
    конструкции и режет лишь их обилие.

Потому срез строится иначе: **берётся КАЖДЫЙ мир показов, усечённый до потолка страниц**,
а не часть миров целиком.

    СРЕЗ ЕСТЬ КАЖДЫЙ МИР, УСЕЧЁННЫЙ, А НЕ ЧАСТЬ МИРОВ ЦЕЛИКОМ.

ЧТО ЭТОТ СРЕЗ ОБЕЩАЕТ И ЧЕГО НЕ ОБЕЩАЕТ — сказано прямо, ибо ворота Р-4 (±5 тактов из 726)
до посадки Р-3 недостижимы В ПРИНЦИПЕ, и это следует из самой П-3:

    ПОКУПКИ НЫНЕ СУТЬ АБСОЛЮТНЫЕ КВОРУМЫ (LAW², LAW³, «одна страница делает хвост»). При
    абсолютном кворуме больший свод покупает СТРОГО БОЛЬШЕ меньшего: у полного свода на
    каждый род больше страниц, значит больше и случайных совпадений, дающих кворум. Мусор
    есть функция МАСШТАБА, а не состава.

    СТРАТИФИКАЦИЯ ВЫРАВНИВАЕТ ТО, ЧТО СРЕЗ УМЕЕТ ПОКАЗАТЬ, И НЕ ВОСПРОИЗВОДИТ ТОГО, ЧТО
    БОЛЬШОЙ СВОД УМЕЕТ ИСПОРТИТЬ. Всё, что полный свод покупает ПО ДЕЛУ, купит и срез;
    мусорных же покупок полного свода срез не сделает никогда.

Оттого срез объявляется МЕРОЙ ВЕРХНЕЙ ГРАНИЦЫ: читатель на срезе читает НЕ ХУЖЕ, чем на
полном своде, и разность двух чисел есть мера МУСОРА, а не ошибка среза. Мерой предсказания
он станет после посадки Р-3 (свидетель-контраст вместо абсолютного кворума), и тогда же
встанут ворота ±5.

    python3 scripts/strat_slice.py [--потолок 700] [--проба]
"""
# ПУСТОЙ-ОБХОД: --потолок 0
import argparse
import hashlib
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ЦЕЛЬ = "datasets/GENESIS-STRAT.txt"
ШОВ = "\n\n"

# РУБЕЖ-ДОЛГА: МИРОВ_БЕЗ_СТРАНИЦ = 0
#
# Всякий мир показов обязан войти в срез хоть одной страницей: мир, выпавший целиком, есть
# конструкция, о которой срез молчит. Ноль есть ПОЛ, а не потолок.
МИРОВ_БЕЗ_СТРАНИЦ = 0

# ПОТОЛОК СТРАНИЦ НА МИР — не порог качества, а БЮДЖЕТ РАЗМЕРА, и он ВЫБРАН ЗАМЕРОМ, а не
# назначен. Проба по всем 207 мирам показов:
#
#     потолок  700  → 11 012 546 байт, урезано 133 мира
#     потолок 1200  → 16 368 181 байт, урезано 103
#     потолок 1500  → **18 915 765 байт**, урезано 87
#     потолок 1800  → 21 119 530 байт, урезано 84
#
# Взят 1500: срез весит столько же, сколько школьный (19 476 861), — и несёт при этом ВСЕ
# 207 миров показов против его 143. То есть та же цена во времени за меру, у которой есть
# каждая конструкция свода.
ПОТОЛОК = 1500


def миры():
    """[(имя, путь)] — все миры показов манифеста, в порядке манифеста."""
    м = json.loads((КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json").read_text(encoding="utf-8"))
    корень = м.get("external_root") or ""
    вон = []
    for мир in м["worlds"]:
        if мир.get("text") != "shows":
            continue
        путь = КОРЕНЬ / мир["file"]
        if not путь.exists() and корень:
            путь = (КОРЕНЬ / корень / мир["file"]).resolve()
        if путь.is_file():
            вон.append((мир["name"], путь))
    return вон


def кусок(путь, потолок):
    """Первые `потолок` непустых строк мира — В ПОРЯДКЕ ФАЙЛА, без выбора.

    ВЫБОР СТРАНИЦ ЕСТЬ ВТОРОЙ ИСТОЧНИК СЛУЧАЙНОСТИ, И ОН ЗДЕСЬ НЕ НУЖЕН. Порядок строк
    внутри мира уже перемешан его собственной сборкой (`layer.emit` тасует показы пятью
    проходами с объявленными множителями), и первые N строк суть выборка не хуже всякой
    иной — зато ВОСПРОИЗВОДИМАЯ без семени.
    """
    строки = [с for с in путь.read_text(encoding="utf-8", errors="replace").splitlines() if с.strip()]
    return строки[:потолок], len(строки)


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--потолок", type=int, default=ПОТОЛОК)
    ап.add_argument("--проба", action="store_true", help="не писать файл, только сказать число")
    дов = ап.parse_args()
    if дов.потолок <= 0:
        print("СТРАТИФИЦИРОВАННЫЙ СРЕЗ ОТКАЗ: потолок страниц не положителен")
        return 2
    список = миры()
    if not список:
        print("СТРАТИФИЦИРОВАННЫЙ СРЕЗ ОТКАЗ: миров показов нет")
        return 2
    куски, перепись, пустых, всего_строк = [], [], 0, 0
    for имя, путь in список:
        строки, было = кусок(путь, дов.потолок)
        if not строки:
            пустых += 1
            continue
        куски.append("\n".join(строки))
        перепись.append((имя, len(строки), было))
        всего_строк += len(строки)
    тело = ШОВ.join(куски) + "\n"
    байт = len(тело.encode("utf-8"))
    подпись = hashlib.sha256(тело.encode("utf-8")).hexdigest()[:16]
    урезано = sum(1 for _и, взято, было in перепись if взято < было)
    if not дов.проба:
        (КОРЕНЬ / ЦЕЛЬ).write_text(тело, encoding="utf-8")
    поза = "PASS" if пустых <= МИРОВ_БЕЗ_СТРАНИЦ else "FAIL"
    print(f"СТРАТИФИЦИРОВАННЫЙ СРЕЗ {поза}: миров {len(перепись)} из {len(список)} "
          f"(без страниц {пустых}, рубеж {МИРОВ_БЕЗ_СТРАНИЦ}), строк {всего_строк}, "
          f"байт {байт}, подпись {подпись}; потолок {дов.потолок} строк с мира, "
          f"урезано миров {урезано}; {'проба, файл не писан' if дов.проба else ЦЕЛЬ}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
