#!/usr/bin/env python3
"""[ЛИЦО СВОДА] — числа, объявленные читателю, против измеренного дерева.

README есть ЛИЦО свода: первое и часто единственное, что о нём прочтут. 11.09 первая строка его
таблицы говорила «169 worlds of shows + 213 of prose», а манифест держал 253 и 207. Ошибка
в полтора раза стояла месяцами, и ни один прибор о ней не спрашивал: суды меряют СТРОКИ СВОДА,
а не рассказ о своде.

    ТАБЛИЦА ЧИСЕЛ БЕЗ СТОРОЖА СТАРЕЕТ МОЛЧА. Свод, растущий каждый день, лжёт о себе ровно на
    столько, на сколько вырос со дня последней правки рассказа.

    РАССКАЗ О СВОДЕ ЕСТЬ УТВЕРЖДЕНИЕ О СВОДЕ, И ПОТОМУ ПОДСУДЕН, как всякое утверждение.

ЧЕТЫРЕ СТРОКИ И ЧЕТЫРЕ ИСТОЧНИКА, И КАЖДЫЙ НАЗВАН:

    миры          манифест: сколько объявлено `shows`, `prose`, прочего
    языки         `tools/langpacks/*.json` — по пакету на язык
    суды, приборы палата (`tools/panel.py`) и набор (`scripts/courts.sh`) — устами `panel_court`
    охват         ЛЕДЖЕР: последний ЗАВЕРШЁННЫЙ прогон `court_reach.py`

ПОСЛЕДНЯЯ СТРОКА БЕРЁТСЯ ИЗ ЛЕДЖЕРА, А НЕ ПЕРЕМЕРЯЕТСЯ, И ЭТО НАЗВАНО: полный охват палаты стои́т
часа, и прибор, который ради одной строки README гонял бы его заново, не позвали бы ни разу.
Леджер же есть след ЗАВЕРШЁННОГО прогона, и ссылаться на него честно — если названа его дата.

    ЧИСЛО ИЗ ПРОШЛОГО ЗАМЕРА ЧЕСТНО РОВНО ТОГДА, КОГДА НАЗВАН ДЕНЬ ЗАМЕРА.

ГРАНИЦА НАЗВАНА: прибор судит ЧИСЛА, а не слова вокруг них. Рассказ, верный числами и лживый
словами, он пропустит — за слова отвечает тот, кто их писал.

    python3 scripts/readme_court.py
"""
# ПУСТОЙ-ОБХОД: --лицо no-such-readme
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ЛИЦО = КОРЕНЬ / "README.md"
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
ПАКЕТЫ = КОРЕНЬ / "tools" / "langpacks"
ЛЕДЖЕР = КОРЕНЬ / "reports" / "ledger.tsv"

# РУБЕЖ-ДОЛГА: РАСХОЖДЕНИЙ_РУБЕЖ = 0
РАСХОЖДЕНИЙ_РУБЕЖ = 0

СТРОКА_МИРОВ = re.compile(
    r"\*\*(\d+) worlds of shows \+ (\d+) of prose \+ (\d+) mixed\*\*")
СТРОКА_ЯЗЫКОВ = re.compile(r"\*\*(\d+) languages\*\*")
СТРОКА_СУДОВ = re.compile(r"\*\*(\d+) courts \+ (\d+) instruments\*\*")
СТРОКА_ОХВАТА = re.compile(
    r"of ([\d   ]+) lines across (\d+) worlds.*?ledger (\S+?)\)")
ОХВАТ_ЛЕДЖЕРА = re.compile(r"миров (\d+), строк (\d+)")


def число(текст):
    """«404 772» → 404772: разряды в лице свода отбиваются пробелом."""
    return int(re.sub(r"[^\d]", "", текст))


def из_манифеста():
    миры = json.loads(МАНИФЕСТ.read_text(encoding="utf-8"))["worlds"]
    показов = sum(1 for з in миры if з.get("text") == "shows")
    прозы = sum(1 for з in миры if з.get("text") == "prose")
    return показов, прозы, len(миры) - показов - прозы


def из_палаты():
    """(судов живых, приборов объявленных) — ГЛАЗАМИ САМОГО СУДА СОСТАВА.

    ЗАКОН НЕ ПИШЕТСЯ ВТОРОЙ РАЗ. Первая редакция считала приборы своей свёрткой по набору и дала
    261 против 166 у `panel_court`: тот считает ОБЪЯВИВШИХ СЕБЯ приборами (по метке пустого
    обхода), а не строки списка. Два счёта одного и того же расходятся на первой же правке.
    """
    sys.path.insert(0, str(КОРЕНЬ / "tools"))
    sys.path.insert(0, str(КОРЕНЬ / "scripts"))
    import panel
    import panel_court
    return panel.Палата().живых, len(panel_court.приборы())


def из_леджера():
    """(миров, строк, метка) последнего ЗАВЕРШЁННОГО прогона охвата."""
    if not ЛЕДЖЕР.is_file():
        return None
    for строка in reversed(ЛЕДЖЕР.read_text(encoding="utf-8", errors="replace").splitlines()):
        поля = строка.split("\t")
        if len(поля) >= 4 and поля[1] == "court_reach.py" and поля[2] == "0":
            найдено = ОХВАТ_ЛЕДЖЕРА.search(поля[3])
            if найдено:
                return int(найдено.group(1)), int(найдено.group(2)), поля[0]
    return None


def main():
    лицо = ЛИЦО
    if "--лицо" in sys.argv:
        лицо = pathlib.Path(sys.argv[sys.argv.index("--лицо") + 1])
        if not лицо.is_file():
            print(f"ЛИЦО СВОДА ОТКАЗ: рассказа нет — {лицо}")
            return 2
    текст = лицо.read_text(encoding="utf-8")
    расхождения, сверено = [], 0

    найдено = СТРОКА_МИРОВ.search(текст)
    if not найдено:
        расхождения.append("строки о мирах в лице свода нет вовсе")
    else:
        сверено += 1
        сказано = tuple(int(x) for x in найдено.groups())
        измерено = из_манифеста()
        if сказано != измерено:
            расхождения.append(f"миры: сказано {сказано}, а в манифесте {измерено}")

    найдено = СТРОКА_ЯЗЫКОВ.search(текст)
    if not найдено:
        расхождения.append("строки о языках нет вовсе")
    else:
        сверено += 1
        пакетов = len(list(ПАКЕТЫ.glob("*.json")))
        if int(найдено.group(1)) != пакетов:
            расхождения.append(
                f"языки: сказано {найдено.group(1)}, а пакетов {пакетов}")

    найдено = СТРОКА_СУДОВ.search(текст)
    if not найдено:
        расхождения.append("строки о судах нет вовсе")
    else:
        сверено += 1
        судов, приборов = из_палаты()
        if судов is not None and int(найдено.group(1)) != судов:
            расхождения.append(f"суды: сказано {найдено.group(1)}, а в палате {судов}")
        if int(найдено.group(2)) != приборов:
            расхождения.append(
                f"приборы: сказано {найдено.group(2)}, а в наборе {приборов}")

    найдено = СТРОКА_ОХВАТА.search(текст)
    след = из_леджера()
    if not найдено:
        расхождения.append("строки об охвате нет вовсе")
    elif след is None:
        расхождения.append("охват назван, а завершённого прогона в леджере нет")
    else:
        сверено += 1
        строк, миров, метка = число(найдено.group(1)), int(найдено.group(2)), найдено.group(3)
        if (миров, строк, метка) != (след[0], след[1], след[2]):
            расхождения.append(
                f"охват: сказано ({миров} миров, {строк} строк, {метка}), "
                f"а в леджере ({след[0]}, {след[1]}, {след[2]})")

    for р in расхождения:
        print(f"  {р}")
    поза = "PASS" if len(расхождения) <= РАСХОЖДЕНИЙ_РУБЕЖ else "FAIL"
    print(f"ЛИЦО СВОДА {поза}: {len(расхождения)} расхождений рассказа с деревом "
          f"(рубеж {РАСХОЖДЕНИЙ_РУБЕЖ}); сверено строк {сверено} из 4")
    return 0 if len(расхождения) <= РАСХОЖДЕНИЙ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
