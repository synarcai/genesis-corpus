#!/usr/bin/env python3
"""[ПОДСАДКИ ВНЕ РАМКИ] — заведомая ложь, какую не читает НИКТО.

Подсадка есть строка, объявленная ЗАВЕДОМО ЛОЖНОЙ: прибор ставит её перед судом и требует,
чтобы суд назвал её ложью. Пока подсадка судима, она мерит суд. Но стоит рамке дома
перемениться — и подсадка перестаёт попадать в рамку вовсе:

    «НЕ ПОЙМАНА» ИМЕЕТ ДВЕ ПРИЧИНЫ, И ОНИ ТРЕБУЮТ РАЗНОГО. Подсадка бывает СУДИМА И
    ИСТИННА — тогда лгал список: строка похожа на ложь, а есть правда, и чинить надо
    список. Бывает и НЕСУДИМА — тогда её не читает никто, и чинить надо рамку либо саму
    подсадку. Прибор, считающий обе «непойманными», молчит о второй.

Так 14.09 суд скобок потерял четыре подсадки из семи: рамка вопроса в доме переменилась
(«ряд ( [ — чем закрыть?» стало «чем закрыть ряд „( [“?»), список в приборе остался
прежним, и прибор доложил «поймано 4 из 7», не сказав, что три строки он больше НЕ ЧИТАЕТ.

ПРИБОР НЕ ВВОЗИТ СУДОВ И НЕ ВЕРИТ ИМ НА СЛОВО: он читает объявления `подсадки`/`ПОДСАДКИ`
во всех приборах и домах ДЕРЕВОМ РАЗБОРА, а судимость спрашивает у ПАЛАТЫ — то есть у всех
живых судов разом. Строка, какую не берётся судить никто, есть долг.
"""
import ast
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: ВНЕ_РАМКИ = 0
ВНЕ_РАМКИ = 0
ИМЕНА = ("подсадки", "ПОДСАДКИ")


def запись_ли(с):
    """ПОДСАДКА ЕСТЬ ЗАПИСЬ, А НЕ ИМЯ. Дом мутантов зовёт `ПОДСАДКИ` пары «имя — порча»
    («MORPH», «KINDS», «ARITH»), и это не строки мира, а клички полей: судить их некому и
    не за что. Строка без пробела записью не бывает ни в одном мире показов."""
    return " " in с.strip()


def _строки(узел):
    """Строковые литералы объявления — и только литералы: склейку с именем не читаем."""
    if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
        return [узел.value], 0
    if isinstance(узел, (ast.Tuple, ast.List, ast.Set)):
        вон, тёмных = [], 0
        for э in узел.elts:
            с, т = _строки(э)
            вон += с
            тёмных += т
        return вон, тёмных
    if isinstance(узел, ast.BinOp) and isinstance(узел.op, ast.Add):
        л, тл = _строки(узел.left)
        п, тп = _строки(узел.right)
        if len(л) == 1 and len(п) == 1 and not тл and not тп:
            return [л[0] + п[0]], 0
        return [], 1
    return [], 1


def объявления(путь):
    """[(строка, тёмных)] — подсадки файла, где «тёмное» есть невычислимый кусок."""
    try:
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return [], 0
    вон, тёмных = [], 0
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Assign):
            continue
        if not any(isinstance(ц, ast.Name) and ц.id in ИМЕНА for ц in узел.targets):
            continue
        с, т = _строки(узел.value)
        вон += с
        тёмных += т
    return вон, тёмных


def main():
    from panel import палата
    суд = палата()
    дворы = [КОРЕНЬ / "courts", КОРЕНЬ / "tools", КОРЕНЬ / "scripts"]
    всего = вне = ложных_нет = тёмных = файлов = 0
    беда = []
    for двор in дворы:
        for путь in sorted(двор.glob("*.py")):
            строки, темно = объявления(путь)
            тёмных += темно
            if not строки:
                continue
            файлов += 1
            for с in строки:
                if not запись_ли(с):
                    continue
                всего += 1
                судимо, истинно, _кем = суд.судить(с)
                if not судимо:
                    вне += 1
                    беда.append((путь.relative_to(КОРЕНЬ), "ВНЕ РАМКИ", с))
                elif истинно:
                    ложных_нет += 1
                    беда.append((путь.relative_to(КОРЕНЬ), "НЕ ЛОЖЬ", с))
    for путь, что, с in беда[:12]:
        print(f"  {что}: {путь} — {с[:100]}")
    поза = "PASS" if вне <= ВНЕ_РАМКИ else "FAIL"
    print(f"ПОДСАДКИ ВНЕ РАМКИ {поза}: {вне} из {всего} не судит никто (рубеж {ВНЕ_РАМКИ}); "
          f"судимых, но истинных {ложных_нет}; объявлений в {файлов} файлах, "
          f"невычислимых кусков {тёмных}; судов живых {суд.живых}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
