#!/usr/bin/env python3
"""[СПРОШЕНО, НО НЕ СОСЧИТАНО] — имя, о числе которого свод спрашивает и никогда не отвечает им.

    ИМЯ, СПРОШЕННОЕ КЛАССОМ И ОТВЕЧЕННОЕ ГОЛЫМ ЧИСЛОМ, НИ РАЗУ НЕ СТОИ́Т ПРИ ЧИСЛЕ — и
    читатель, выучивший вопрос, не выучил ответа.

ПОВОД, ПРИШЕДШИЙ СНАРУЖИ (13.09). holon-f9 померил рынок классовых слов и назвал восемь слов
«упражнений» (девять языков), у которых НОЛЬ показов в роли класса над товарами. Проверка по
своду показала, что страницы эти ЕСТЬ и делают ровно то, что от них хотели:

    Ava did 20 push-ups and 8 crunches. how many push-ups did Ava do? 20.
    how many exercises in all? 28: 20 + 8 = 28.

Класс стои́т над двумя различными товарами, счёт верен, девять языков. И при этом «28 exercises»
в своде НЕТ НИ РАЗУ — как и «N exercises» вообще. Вопрос задан, ответ дан ЦИФРОЙ, а слово при
цифре не встало никогда.

    ЧУЖОЙ ПРИБОР, НЕ НАШЕДШИЙ ТОГО, ЧТО У НАС ЕСТЬ, УКАЗЫВАЕТ НЕ НА СВОЮ СЛЕПОТУ, А НА ФОРМУ
    НАШЕГО ПОКАЗА. Он искал «число + класс»; свод пишет «класс? число».

ЧТО СЧИТАЕТСЯ. Имя, стоящее в вопросе о количестве («how many X», «сколько X», и так по девяти
языкам), — и та же строка свода, где это имя стои́т ПРИ ЧИСЛЕ: цифрой («28 exercises») или
СЛОВОМ («three sides»). Числительные словом берутся из языковых пакетов, а не пишутся рукой.

    МЕРА, ЗНАЮЩАЯ ЛИШЬ ЦИФРУ, НАЗЫВАЕТ ДОЛГОМ «a triangle has three sides». Первая проба так
    и сделала — и назвала четыре честных имени из пятнадцати.

ЧЕГО ПРИБОР НЕ СЧИТАЕТ ДОЛГОМ. Имя, спрошенное СТРАНИЦЕЙ ОТКАЗА: «how many centigrams are in
2 cents? no answer: a cent and a centigram measure different kinds» — вопрос здесь задан
затем, чтобы быть отвергнутым, и ответа числом у него нет и не должно быть.

    ВОПРОС, ЗАДАННЫЙ РАДИ ОТКАЗА, НЕ ЖДЁТ ЧИСЛА В ОТВЕТ, И ТРЕБОВАТЬ ОТ НЕГО ЧИСЛА ЗНАЧИЛО БЫ
    ТРЕБОВАТЬ ОТМЕНЫ ОТКАЗА.

    python3 scripts/asked_uncounted.py [--подробно] [--свод ПУТЬ]
"""
# ПУСТОЙ-ОБХОД: --свод /dev/null
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: НЕСОСЧИТАННЫХ_РУБЕЖ = 0
#
# РУБЕЖ ПОСТАВЛЕН НУЛЁМ И ДОСТИГНУТ В ТОТ ЖЕ ЧАС. Первый замер 13.09 дал одиннадцать имён
# (после отсева числительных словом и страниц отказа): exercises и восемь его переводов,
# adults, spiders, cows, chickens, beetles, bicycles, places. Все закрыты показом «N имя»
# в том же доме, что задаёт вопрос.
#
#     ДОЛГ, НАЙДЕННЫЙ ЧУЖИМ ПРИБОРОМ И ЗАКРЫТЫЙ СВОИМ, СТОИ́Т ДВУХ: он куплен дважды —
#     чужим замером и своим показом.
НЕСОСЧИТАННЫХ_РУБЕЖ = 0

# ЗАЧИНЫ ВОПРОСА О КЛАССЕ — С ЗАМЫКАЮЩИМ СЛОВОМ «ВСЕГО», И ЭТО КУПЛЕНО ЛОЖНЫМ ДОЛГОМ (13.09).
#
# Первая редакция брала слово сразу после «сколько» / «how many» — и насчитала 180 долгов из
# 1015 «имён». Среди них: «получится» (321 раз), «krijg» (321), «zähle» (192), «płaci» (120),
# «pozostaje» (118). Это ГЛАГОЛЫ: «сколько получится?», «hoeveel krijg ik?».
#
#     СЛОВО ПОСЛЕ ВОПРОСИТЕЛЬНОГО «СКОЛЬКО» НЕ ЕСТЬ ИМЯ, И ПРИЗНАК, СЧИТАЮЩИЙ ЕГО ИМЕНЕМ,
#     ЗОВЁТ ДОЛГОМ ТО, ЧТО ИМЕНЕМ НЕ БЫВАЕТ ВОВСЕ.
#
# Замыкающее «всего» / «in all» / «en tout» / «razem» отсекает их разом: глагол в этой рамке
# не стои́т. Заодно оно сужает предмет прибора до того, о чём он и заведён — ВОПРОСА О КЛАССЕ
# НАД РАЗЛИЧНЫМИ ТОВАРАМИ, — и граница эта названа, а не подразумевается.
#
# ГРАНИЦА НАЗВАНА ПРЯМО: имя, спрошенное вопросом БЕЗ «всего» («how many cows are there?»),
# этим прибором не судится. Таких вопросов в своде много, и среди них есть свой долг; он
# ждёт прибора, умеющего отличить имя от глагола без опоры на замыкающее слово.
ЗАЧИНЫ = (
    (r"how many ([a-zà-ÿ][a-zà-ÿ\-]+) in all", "en"),
    (r"сколько ([а-яё][а-яё\-]+) всего", "ru"),
    (r"сколько всего ([а-яё][а-яё\-]+)", "ru"),
    (r"wie viele ([a-zà-ÿäöüß][a-zà-ÿäöüß\-]+) insgesamt", "de"),
    (r"combien d[e\u2019']([a-zà-ÿ][a-zà-ÿ\-]+) en tout", "fr"),
    (r"cuánt[oa]s ([a-zà-ÿ][a-zà-ÿ\-]+) en total", "es"),
    (r"quant[ei] ([a-zà-ÿ][a-zà-ÿ\-]+) in tutto", "it"),
    (r"quant[oa]s ([a-zà-ÿ][a-zà-ÿ\-]+) (?:ao |no )total", "pt"),
    (r"hoeveel ([a-zà-ÿ][a-zà-ÿ\-]+) in totaal", "nl"),
    (r"ile ([a-ząćęłńóśźż][a-ząćęłńóśźż\-]+) (?:razem|w sumie)", "pl"),
)

# ВОПРОС О КЛАССЕ БЕЗ ИМЕНИ КЛАССА (13.09, найдено этим же прибором). Польский свод
# спрашивает «mam 7 jabłek, ty masz 4 jabłka. ile mamy razem? 11 jabłek» — и «mamy» тут не
# имя, а ГЛАГОЛ («сколько мы имеем всего?»). Класса в вопросе нет вовсе: имя названо в
# ОТВЕТЕ, а не в вопросе.
#
#     ЯЗЫК ВПРАВЕ СПРАШИВАТЬ О КЛАССЕ, НЕ НАЗЫВАЯ КЛАССА, и мера, требующая имени в вопросе,
#     обязана назвать этот случай, а не молча счесть глагол именем.
#
# Слово объявлено ЗДЕСЬ И ПОИМЁННО, а не отсеяно правилом: правило «глагол не имя» требовало
# бы разбора речи, какого у прибора нет, и отсекло бы заодно честные имена. Прибор считает
# такие случаи отдельным числом и говорит о них вслух.
НЕ_ИМЕНА = frozenset({"mamy"})

# СЛОВА ОТКАЗА: страница, несущая их, спрашивает ради отказа, а не ради числа.
ОТКАЗ = ("no answer", "нет ответа", "keine antwort", "pas de réponse", "sin respuesta",
         "nessuna risposta", "sem resposta", "geen antwoord", "brak odpowiedzi", "¬")


def числительные():
    """{язык: множество числительных СЛОВОМ} — из пакетов, а не из рук."""
    вон = {}
    for п in sorted((КОРЕНЬ / "tools" / "langpacks").glob("*.json")):
        тело = json.loads(п.read_text(encoding="utf-8"))
        слова = {str(с).lower() for с in (тело.get("numerals") or {}).values() if str(с).strip()}
        if слова:
            вон[п.stem] = слова
    return вон


def замер(строки, числом):
    """(спрошено, при_числе, отказные) по строкам свода.

    Отделено от чтения файла, чтобы проба гоняла ТО САМОЕ место, которым прибор судит.
    """
    спрошено = collections.Counter()
    языки = {}
    отказные = collections.Counter()
    при_числе = set()
    # ОБА ПОРЯДКА, И ЭТО КУПЛЕНО ЛОЖНЫМ ДОЛГОМ (13.09). Первая редакция искала «число имя» и
    # назвала несосчитанными «пчёл» и «людей» — а дом отношений пишет их ДРУГИМ ПОРЯДКОМ:
    # «всего пчёл 132», «всего людей 141». Класс сосчитан, и сосчитан прямо в ответе.
    #
    #     МЕРА, ЗНАЮЩАЯ ОДИН ПОРЯДОК СЛОВ, НАЗЫВАЕТ ДОЛГОМ ЯЗЫК, КОТОРЫЙ СТАВИТ ИХ ИНАЧЕ.
    цифрой = re.compile(r"\d+\s+([^\W\d_][\w\-]+)", re.UNICODE)
    обратно = re.compile(r"([^\W\d_][\w\-]+)\s+\d+", re.UNICODE)
    for сырая in строки:
        с = сырая.lower()
        if not с.strip():
            continue
        отказ = any(з in с for з in ОТКАЗ)
        for образец, язык in ЗАЧИНЫ:
            for m in re.finditer(образец, с):
                имя = m.group(1)
                (отказные if отказ else спрошено)[имя] += 1
                языки.setdefault(имя, язык)
        for m in цифрой.finditer(с):
            при_числе.add(m.group(1))
        for m in обратно.finditer(с):
            при_числе.add(m.group(1))
        # ЧИСЛИТЕЛЬНОЕ СЛОВОМ — ВТОРОЙ СПОСОБ СОСЧИТАТЬ, И ОН РАВНОПРАВЕН ЦИФРЕ.
        слова = re.findall(r"[^\W\d_][\w\-]*", с, re.UNICODE)
        for i, сл in enumerate(слова[:-1]):
            if сл in числом:
                при_числе.add(слова[i + 1])
    return спрошено, при_числе, отказные, языки


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что прибор УМЕЕТ находить и умеет НЕ находить.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ НУЛЯ НАХОДОК. Пусть зачин перестанет совпадать — и спрошенных
        не станет вовсе, а прибор объявит «несосчитанных 0», сверив НОЛЬ ИМЁН.

    Четыре случая на выдуманном своде: имя спрошенное и сосчитанное ЦИФРОЙ (долгом не зовётся),
    спрошенное и сосчитанное СЛОВОМ (тоже не зовётся — иначе «three sides» пойдёт в долг),
    спрошенное и не сосчитанное вовсе (обязано найтись), спрошенное СТРАНИЦЕЙ ОТКАЗА (обязано
    быть отсеяно).
    """
    свод = (
        "there are 5 cats here. how many cats in all? 5 cats.",
        "молодых пчёл 54. сколько всего пчёл? всего пчёл 270.",
        "a triangle has three sides. how many sides in all? three sides.",
        "Ava did 20 push-ups and 8 crunches. how many exercises in all? 28: 20 + 8 = 28.",
        "how many centigrams in all? no answer: a cent and a centigram measure different kinds.",
    )
    спрошено, при_числе, отказные, _яз = замер(свод, {"three", "two", "five"})
    беды = []
    долг = {и for и in спрошено if и not in при_числе}
    if "cats" in долг:
        беды.append("имя, сосчитанное ЦИФРОЙ, названо несосчитанным")
    if "sides" in долг:
        беды.append("имя, сосчитанное СЛОВОМ, названо несосчитанным")
    if "пчёл" in долг:
        беды.append("имя, сосчитанное ОБРАТНЫМ ПОРЯДКОМ («всего пчёл 270»), названо несосчитанным")
    if "exercises" not in долг:
        беды.append("имя, спрошенное и не сосчитанное, НЕ НАЙДЕНО — прибор слеп")
    if "centigrams" in спрошено:
        беды.append("вопрос страницы отказа сочтён обычным вопросом")
    if "centigrams" not in отказные:
        беды.append("вопрос страницы отказа не отнесён к отказным")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"СПРОШЕНО, НО НЕ СОСЧИТАНО ОТКАЗ: чтение вопроса не доказано ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--свод", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    путь = pathlib.Path(дов.свод) if дов.свод else КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
    if not путь.is_file():
        print(f"СПРОШЕНО, НО НЕ СОСЧИТАНО ОТКАЗ: свода нет — {путь}")
        return 2
    числом = set()
    for слова in числительные().values():
        числом |= слова
    if not числом:
        print("СПРОШЕНО, НО НЕ СОСЧИТАНО ОТКАЗ: пакеты не объявляют числительных")
        return 2
    строки = путь.read_text(encoding="utf-8", errors="replace").split("\n")
    спрошено, при_числе, отказные, языки = замер(строки, числом)
    if not спрошено:
        print("СПРОШЕНО, НО НЕ СОСЧИТАНО ОТКАЗ: вопросов о количестве в своде нет")
        return 2
    без_имени = {и: n for и, n in спрошено.items() if и in НЕ_ИМЕНА}
    долг = sorted(((n, и) for и, n in спрошено.items()
                   if и not in при_числе and и not in НЕ_ИМЕНА), reverse=True)
    for n, и in долг[: None if дов.подробно else 12]:
        print(f"  {n:5}  {и:<18} [{языки.get(и, '?')}] спрошено и НИ РАЗУ не сосчитано")
    поза = "PASS" if len(долг) <= НЕСОСЧИТАННЫХ_РУБЕЖ else "FAIL"
    print(f"СПРОШЕНО, НО НЕ СОСЧИТАНО {поза}: НЕСОСЧИТАННЫХ ИМЁН {len(долг)} "
          f"(рубеж {НЕСОСЧИТАННЫХ_РУБЕЖ}); имён спрошено {len(спрошено)}, из них при числе "
          f"стоя́т {len(спрошено) - len(долг) - len(без_имени)}; отсеяно страницами отказа "
          f"{len(отказные)}; ВОПРОСОВ О КЛАССЕ БЕЗ ИМЕНИ КЛАССА "
          f"{sum(без_имени.values())} ({', '.join(sorted(без_имени)) or '—'})")
    return 0 if len(долг) <= НЕСОСЧИТАННЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
