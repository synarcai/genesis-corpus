#!/usr/bin/env python3
"""[СОСТАВ] — объявленный состав против живущего, на двух этажах.

ПОВОД, ПРОЖИТЫЙ 02.09. Палата держала состав СПИСКОМ, пополняемым
рукой. Два готовых суда — вопросные лестницы pt/nl и pl/tr — лежали в
каталоге, читались, судили строку правильно; палата о них не знала.
Ворота записи спрашивают палату, палата молчала, и оба мира отказались
собираться с вердиктом «несудимых 1370». Причина — четыре недостающих
слова в кортеже — не была видна НИ В ОДНОМ отчёте: ни судимость, ни
мутанты, ни манифест о составе палаты не спрашивали.

ТОТ ЖЕ ПОРОК УЖЕ БЫЛ КАЗНЁН ОДНАЖДЫ. Прибор судимости держал свой
список судов, разошедшийся с явью в день, когда рядом появился суд;
тысяча двести пятьдесят строк звались судимыми вслепую. Список
переехал в палату — и порок переехал вместе с ним, ибо казнили не
список, а его место.

СПИСОК, КОТОРЫЙ НАДО ПОПОЛНЯТЬ РУКОЙ, РАЗОЙДЁТСЯ С ЖИВУЩИМИ; вопрос
лишь в том, назовёт ли кто-нибудь день расхождения. Потому истиной о
составе стал ОБХОД КАТАЛОГА, а список остался ОБЪЯВЛЕНИЕМ — он нужен
читателю и прибору зависимостей, что выводит соседей по строкам-
литералам, — и этот суд сверяет одно с другим.

ДВА РОДА РАСХОЖДЕНИЯ, И ОБА ЛОЖЬ:
  · НЕЗАЯВЛЕННЫЙ — суд живёт и судит, а объявление о нём молчит;
  · ПРИЗРАК — объявление называет суд, которого в каталоге нет.

ОБЪЯВЛЕНИЕ, КОТОРОЕ НИЧЕГО НЕ РЕШАЕТ, ЛЖЁТ БЕЗНАКАЗАННО. Список,
переставший быть истиной, обязан быть СВЕРЯЕМ — иначе он превращается
в комментарий, стареющий молча.

И ТОТ ЖЕ РОД ЖИВЁТ ЭТАЖОМ ВЫШЕ. Набор `courts.sh` перечисляет приборы
тем же рукописным списком, и в час, когда палата разошлась с каталогом
на два суда, набор разошёлся на три: два новых суда и прибор мутантов
судов не звались НИ РАЗУ. Род один — ОБЪЯВЛЕННЫЙ СОСТАВ ПРОТИВ
ЖИВУЩЕГО, — и потому судится одним судом на обоих этажах, а не двумя
похожими.

ПРИБОР ОПОЗНАЁТСЯ ОБЪЯВЛЕНИЕМ, А НЕ КАТАЛОГОМ. Всякий здешний прибор
называет, как позвать его С ПУСТЫМ ОБХОДОМ («# ПУСТОЙ-ОБХОД: …») — то
есть чем доказать, что он умеет ОТКАЗАТЬ, а не только соглашаться. Это
объявление и есть признак: файл, его несущий, обязан быть в наборе.
Признак не выдуман для сверки — он жил в приборах прежде неё.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import panel  # noqa: E402

# РУБЕЖ-ДОЛГА: РАСХОЖДЕНИЙ_РУБЕЖ = 0
РАСХОЖДЕНИЙ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: --набор no-such-roster
НАБОР = КОРЕНЬ / "scripts" / "courts.sh"
ПРИЗНАК = "ПУСТОЙ-ОБХОД"
ГДЕ = ("scripts", "courts", "tools")
В_НАБОРЕ = re.compile(r'"([a-z_]+/[a-z0-9_]+\.py)')


def приборы():
    """Файлы, ОБЪЯВИВШИЕ себя приборами, — по всему дереву."""
    вон = set()
    for где in ГДЕ:
        for путь in sorted((КОРЕНЬ / где).glob("*.py")):
            if ПРИЗНАК in путь.read_text(encoding="utf-8"):
                вон.add(f"{где}/{путь.name}")
    return вон


def в_наборе(путь):
    """Приборы, названные набором."""
    if not путь.exists():
        return None
    return set(В_НАБОРЕ.findall(путь.read_text(encoding="utf-8")))


def main():
    набор = НАБОР
    if "--набор" in sys.argv:
        набор = pathlib.Path(sys.argv[sys.argv.index("--набор") + 1])
    названы = в_наборе(набор)
    if названы is None:
        print(f"СОСТАВ ОТКАЗ: набора «{набор}» нет, сверять не с чем")
        return 2
    палата = panel.Палата()
    if not палата.живых:
        print("СОСТАВ ПАЛАТЫ ОТКАЗ: судов нет, сверять нечего")
        return 2
    for м in палата.незаявленные:
        print(f"  НЕЗАЯВЛЕН {м}: суд живёт и судит, объявление молчит")
    for м in палата.призраки:
        print(f"  ПРИЗРАК {м}: объявление называет, в каталоге нет")
    живые_приборы = приборы()
    вне_набора = tuple(sorted(живые_приборы - названы))
    набор_призраки = tuple(sorted(
        и for и in названы - живые_приборы
        if not (КОРЕНЬ / и).exists()))
    for и in вне_набора:
        print(f"  ВНЕ НАБОРА {и}: прибор объявлен, набор не зовёт")
    for и in набор_призраки:
        print(f"  ПРИЗРАК НАБОРА {и}: набор зовёт, файла нет")
    расхождений = (len(палата.незаявленные) + len(палата.призраки)
                   + len(вне_набора) + len(набор_призраки))
    поза = "PASS" if расхождений <= РАСХОЖДЕНИЙ_РУБЕЖ else "FAIL"
    print(f"СОСТАВ {поза}: {расхождений} расхождений "
          f"(рубеж {РАСХОЖДЕНИЙ_РУБЕЖ}) — палата: судов живых "
          f"{палата.живых}, незаявленных {len(палата.незаявленные)}, "
          f"призраков {len(палата.призраки)}; набор: приборов "
          f"{len(живые_приборы)}, вне набора {len(вне_набора)}, "
          f"призраков {len(набор_призраки)}")
    return 0 if расхождений <= РАСХОЖДЕНИЙ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
