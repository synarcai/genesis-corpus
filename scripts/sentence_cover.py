#!/usr/bin/env python3
"""[ПОКРЫТИЕ ПРЕДЛОЖЕНИЯМИ] — истинная строка, часть которой не читает НИКТО.

ЧТО СУД НЕ ЧИТАЕТ, ТО ОН ПОДПИСЫВАЕТ (М-530 на области внимания). Сосед `verdict_cover`
мерит это ПОРЧЕЙ КАЖДОГО СЛОВА и потому дорог; здесь то же меряется даром, ибо суды и
так режут строку предложениями, а вопрос «судимо ли предложение САМО ПО СЕБЕ» есть один
зов палаты.

ЗАКОН ПОКРЫТИЯ ВЕРДИКТА, предложенный holon: «истина» даётся строке лишь тогда, когда
всё в ней покрыто хоть одним судом. Прибор меряет ЕГО ЦЕНУ — сколько честных строк
свода замолчит, если закон ввести, — и цена эта названа ДО правки, а не после.

    ПОКРЫТИЕ ЕСТЬ ТРИ ВЕЩИ, А НЕ ОДНА. Предложение покрыто, если
        (а) СУДИМО САМО;
        (б) есть ВОПРОСНАЯ ПОЛОВИНА объявленной пары, чей ответ судим («род
            определяется ответом» — закон `asking`, и вопрос сам по себе несудим
            по построению, а не по недосмотру);
        (в) есть ОБЪЯВЛЕНИЕ ПРЕДМЕТА — форма без утверждения («x = 4», «массив
            [6 5 3]», «цикл: пока x < 3 повторяй шаг»): подлежащее страницы,
            поставленное отдельным предложением, судить нечем ПО СУЩЕСТВУ.
    ТРЕТЬЯ ВЕЩЬ ЗАЧИТЫВАЕТСЯ ТОЛЬКО ПО ОБЪЯВЛЕНИЮ, и условие на неё жёсткое (holon,
    06.09): предмет объявляется МИРОМ ПОИМЁННО — полем `ПРЕДМЕТЫ` манифеста, списком
    ФОРМ с дырами, — и совпадение проверяется ФОРМОЙ, а не подстрокой (тот же закон
    границы). Иначе (в) стало бы тем карманом, куда уедет всё непрочитанное, то есть
    ровно тем, от чего закон ставится.

    ОБЪЯВЛЕНИЕ ПРОВЕРЯЕТСЯ ВСТРЕЧНО, И ЭТО ВТОРАЯ ПОЛОВИНА УСЛОВИЯ: форма, объявленная
    миром и НЕ СОВПАВШАЯ НИ С ОДНИМ его предложением, есть разлад объявления с делом —
    карман с другой стороны. Такие формы прибор печатает поимённо и роняет ими себя.

    ЧТО ПРЕДМЕТОМ НЕ ОБЪЯВЛЯЕТСЯ: предложение, несущее УТВЕРЖДЕНИЕ. «сумма столбца1 =
    5 + 7 = 12» и «add(4 6) → 4 + 6 → 10» несут счёт и проверяемы (их читает суд
    арифметики с 06.09); «нет: 34 = 6 × 5 + 4, остаток 4» и «no: 10 is not a power of
    two» суть ОТВЕТЫ, и объявить их предметами значило бы спрятать утверждение под
    именем формы. Первый разбор назвал предметами все десять непокрытых строк; полная
    выписка показала восемь — двое оказались ответами, и это поправлено до посадки.

ПЕРВЫЙ ЗАМЕР (06.09, 380 строк ≥2 предложений, названных истиной): покрыты
предложениями 340 (89 %), покрыты вопросной половиной пары 30 (7 %), НЕ ПОКРЫТО НИЧЕМ
10 (2 %) в пяти мирах. Грубая первая редакция давала 10 % немых; разбор вопросной
половины снял восемь из них — и это ровно закон «вопрос судится ответом», уже стоящий
в `asking`.

ЧЕГО ЭТОТ ПРИБОР НЕ МЕРИТ, И ЭТО ОБЪЯВЛЕНО ПРЯМО:
    СТРОКИ ИЗ ОДНОГО ПРЕДЛОЖЕНИЯ — в них покрывать нечего, и они не считаются;
    СЛОВА — их мерит `verdict_cover` порчей; здесь зерно крупнее предложения;
    ЛОЖНЫЕ СТРОКИ — берутся лишь названные ИСТИНОЙ: подпись есть только у них.

    python3 scripts/sentence_cover.py [--подробно] [--manifest ПУТЬ]
"""
