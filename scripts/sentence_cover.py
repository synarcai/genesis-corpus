#!/usr/bin/env python3
"""[ПОКРЫТИЕ ПРЕДЛОЖЕНИЯМИ] — истинная строка, часть которой не читает НИКТО.

ЧТО СУД НЕ ЧИТАЕТ, ТО ОН ПОДПИСЫВАЕТ (М-530 на области внимания). Сосед `verdict_cover`
мерит это ПОРЧЕЙ КАЖДОГО СЛОВА и потому дорог; здесь то же меряется даром, ибо суды и
так режут строку предложениями, а вопрос «судимо ли предложение САМО ПО СЕБЕ» есть один
зов палаты.

ЗАКОН ПОКРЫТИЯ ВЕРДИКТА, предложенный holon: «истина» даётся строке лишь тогда, когда
всё в ней покрыто хоть одним судом. Прибор меряет ЕГО ЦЕНУ — сколько честных строк
свода замолчит, если закон ввести, — и цена эта названа ДО правки, а не после.

    ПОКРЫТИЕ ЕСТЬ ТРИ ВЕЩИ, А НЕ ОДНА. Предложение покрыто, если
        (а) СУДИМО САМО;
        (б) есть ВОПРОСНАЯ ПОЛОВИНА объявленной пары, чей ответ судим («род
            определяется ответом» — закон `asking`, и вопрос сам по себе несудим
            по построению, а не по недосмотру);
        (в) есть ОБЪЯВЛЕНИЕ ПРЕДМЕТА — форма без утверждения («x = 4», «массив
            [6 5 3]», «цикл: пока x < 3 повторяй шаг»): подлежащее страницы,
            поставленное отдельным предложением, судить нечем ПО СУЩЕСТВУ.
    ТРЕТЬЯ ВЕЩЬ ЗДЕСЬ НЕ ЗАЧИТЫВАЕТСЯ, и условие на неё поставлено жёстко (holon,
    06.09): предмет объявляется МИРОМ ПОИМЁННО — образцом формы предмета в манифесте
    мира, — и прибор считает (в) только по объявлению. Иначе (в) станет тем самым
    карманом, куда уедет всё непрочитанное, то есть ровно тем, от чего закон ставится.
    Покуда объявления нет, все десять строк первого замера считаются НЕПОКРЫТЫМИ, и
    прибор держит их долгом; объявите — и покрытие станет ста процентами ДЕЛОМ, а не
    отговоркой.

ПЕРВЫЙ ЗАМЕР (06.09, 380 строк ≥2 предложений, названных истиной): покрыты
предложениями 340 (89 %), покрыты вопросной половиной пары 30 (7 %), НЕ ПОКРЫТО НИЧЕМ
10 (2 %) в пяти мирах. Грубая первая редакция давала 10 % немых; разбор вопросной
половины снял восемь из них — и это ровно закон «вопрос судится ответом», уже стоящий
в `asking`.

ЧЕГО ЭТОТ ПРИБОР НЕ МЕРИТ, И ЭТО ОБЪЯВЛЕНО ПРЯМО:
    СТРОКИ ИЗ ОДНОГО ПРЕДЛОЖЕНИЯ — в них покрывать нечего, и они не считаются;
    СЛОВА — их мерит `verdict_cover` порчей; здесь зерно крупнее предложения;
    ЛОЖНЫЕ СТРОКИ — берутся лишь названные ИСТИНОЙ: подпись есть только у них.

    python3 scripts/sentence_cover.py [--подробно] [--manifest ПУТЬ]
"""
# ПУСТОЙ-ОБХОД: --manifest no-such-manifest
import argparse
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "courts"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import arith_court  # noqa: E402
import asking  # noqa: E402
import panel  # noqa: E402
import word_mutants as W  # noqa: E402

# РУБЕЖ-ДОЛГА: НЕПОКРЫТЫХ_РУБЕЖ = 10
#
# ЧИСЛО ПЕРВОГО ЗАМЕРА, объявленное ПОСЛЕ него. Стережётся АБСОЛЮТНОЕ ЧИСЛО, а не доля
# (довод соседей `ask_width` и `verdict_cover`): доля падает от прихода нового покрытого
# мира, ничего не вылечив, и разбавление выдало бы себя за лечение.
#
# БЮДЖЕТ ВЫБОРКИ ФИКСИРОВАН НА МИР (3 строки), потому число растёт от ЧИСЛА МИРОВ, а не
# от размера мира. Новый мир, чьё предложение не читает никто, роняет прибор в тот же
# час — и так задумано.
НЕПОКРЫТЫХ_РУБЕЖ = 10

СТРОК_НА_МИР = 3


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--manifest", default=None)
    дов = ап.parse_args()
    путь = pathlib.Path(дов.manifest) if дов.manifest else \
        КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    м = W.манифест(путь)
    if not м:
        print(f"ПОКРЫТИЕ ПРЕДЛОЖЕНИЯМИ ОТКАЗ: манифеста «{путь}» нет")
        return 2
    внешний = м.get("external_root")
    палата = panel.Палата()
    строк = целых = парой = дыра = 0
    по_мирам = collections.Counter()
    примеры = collections.defaultdict(list)
    for мир in м["worlds"]:
        if мир.get("text") != "shows":
            continue
        п = W._файл(мир, внешний)
        if п is None:
            continue
        слои = палата.слои(п)
        пласт = палата.пласт_файла(п)
        все = [с.strip() for с in
               п.read_text(encoding="utf-8", errors="replace").splitlines() if с.strip()]
        if не_пусто(все):
            for честно in W.равномерно(все, СТРОК_НА_МИР, W.зерно_мира(мир["name"])):
                судимо, истинно, _ = палата.судить(честно, слои, пласт)
                if not (судимо and истинно):
                    continue
                части = [ч.strip() for ч in arith_court.предложения(честно) if ч.strip()]
                if len(части) < 2:
                    continue
                строк += 1
                немые = [ч for ч in части
                         if not палата.судить(ч, слои, пласт)[0]]
                if not немые:
                    целых += 1
                    continue
                пара = asking.пара(честно)
                вопрос = пара[0] if пара else ""
                if вопрос and all(ч in вопрос for ч in немые):
                    парой += 1
                    continue
                дыра += 1
                по_мирам[мир["name"]] += 1
                if len(примеры[мир["name"]]) < 2:
                    примеры[мир["name"]].append((немые[0][:60], честно[:70]))
    if not строк:
        print("ПОКРЫТИЕ ПРЕДЛОЖЕНИЯМИ ОТКАЗ: ни одной строки о двух предложениях")
        return 2
    for имя, n in по_мирам.most_common(20 if дов.подробно else 8):
        н, ц = примеры[имя][0]
        print(f"  НЕ ПОКРЫТО [{имя}] {n}: немое «{н}»" + (f"  в «{ц}»" if дов.подробно else ""))
    поза = "PASS" if дыра <= НЕПОКРЫТЫХ_РУБЕЖ else "FAIL"
    print(f"ПОКРЫТИЕ ПРЕДЛОЖЕНИЯМИ {поза}: строк о двух и более предложениях {строк} — "
          f"покрыты предложениями {целых} ({100 * целых // строк}%), покрыты вопросной "
          f"половиной пары {парой} ({100 * парой // строк}%), НЕ ПОКРЫТО НИЧЕМ {дыра} "
          f"({100 * дыра // строк}%, рубеж {НЕПОКРЫТЫХ_РУБЕЖ}) в {len(по_мирам)} мирах")
    return 0 if поза == "PASS" else 1


def не_пусто(строки):
    return bool(строки)


if __name__ == "__main__":
    sys.exit(main())
