# РУБЕЖ-ДОЛГА: НЕПОКРЫТЫХ_РУБЕЖ = 0
#
# ЧИСЛО ПЕРВОГО ЗАМЕРА, объявленное ПОСЛЕ него. Стережётся АБСОЛЮТНОЕ ЧИСЛО, а не доля
# (довод соседей `ask_width` и `verdict_cover`): доля падает от прихода нового покрытого
# мира, ничего не вылечив, и разбавление выдало бы себя за лечение.
#
# БЮДЖЕТ ВЫБОРКИ ФИКСИРОВАН НА МИР (3 строки), потому число растёт от ЧИСЛА МИРОВ, а не
# от размера мира. Новый мир, чьё предложение не читает никто, роняет прибор в тот же
# час — и так задумано.
# 10 → 2 В ТОТ ЖЕ ВЕЧЕР: восемь строк из десяти оказались ОБЪЯВЛЕНИЯМИ ПРЕДМЕТА, и три
# мира (prog, eng_proof, algebra_units) объявили свои формы полем `ПРЕДМЕТЫ` — 65 форм,
# собранных прибором ПО ВСЕМУ МИРУ, каждая куплена не менее чем двумя страницами.
#
# ОСТАВШИЕСЯ ДВА — НЕ ПРЕДМЕТЫ, А ОТВЕТЫ, и это записано, чтобы завтра их не объявили:
#     «кратно ли 34 числу 6? нет: 34 = 6 × 5 + 4, остаток 4.»
#     «does a sign of an alphabet of 10 signs cost a whole number of bits?
#      no: 10 is not a power of two.»
# Вопросная половина обеих покрыта; непокрыт ОТВЕТ — то самое место, где живёт
# утверждение. «34 = 6 × 5 + 4, остаток 4» есть счёт с остатком, «10 is not a power of
# two» — утверждение о числе; оба проверяемы, и лечит их СУД, а не объявление.
#
# 2 → 0 В ТОТ ЖЕ ВЕЧЕР, И ОБА ВЫЛЕЧЕНЫ СУДОМ, А НЕ ОБЪЯВЛЕНИЕМ, как и было обещано:
#   · «10 is not a power of two» судил суд науки о счёте ВСЕГДА — дырой был этот
#     прибор, резавший предложение без конечного знака, которого требует образец суда;
#   · «34 = 6 × 5 + 4, остаток 4» взял новый закон суда арифметики: слово остатка
#     объявлено пакетами языков (omega, 562a97b), 1290 строк семи миров, судимых стало
#     133 534 → 134 824 при нуле ложных.
#
#     ПОКРЫТИЕ ЕСТЬ СТО ПРОЦЕНТОВ ДЕЛОМ, А НЕ ОТГОВОРКОЙ: 341 предложениями, 31
#     вопросной половиной пары, 8 объявленным предметом, 0 ничем.
#
# РУБЕЖ НОЛЬ ЕСТЬ ПОЛ, А НЕ ПОТОЛОК: мир, чьё предложение не читает никто и чью форму
# он не объявил предметом, роняет прибор в тот же час, когда его напишут.
НЕПОКРЫТЫХ_РУБЕЖ = 0

СТРОК_НА_МИР = 3


def предложения_со_знаком(строка):
    r"""Предложения строки, КАЖДОЕ СО СВОИМ КОНЕЧНЫМ ЗНАКОМ (06.09, шрам прибора).

    `arith_court.предложения` режет строку по знаку конца и знак СЪЕДАЕТ, а суды
    держат его в образце (`…\.$`, `…\?$`): вырезанное предложение образцу не
    отвечает, и суд, честно судящий его В СОСТАВЕ СТРОКИ, о нём МОЛЧИТ. Так «no: 10
    is not a power of two» звалось непокрытым, хотя суд науки о счёте судит его —
    и судит верно, ловя подмену («no: 8 is not a power of two» есть ложь).

        ПРЕДЛОЖЕНИЕ, ВЫРЕЗАННОЕ ИЗ СТРОКИ БЕЗ СВОЕГО ЗНАКА, ЕСТЬ ДРУГОЕ ПРЕДЛОЖЕНИЕ.
        Мера покрытия, отнявшая у предложения то, чего требует суд, меряет СЕБЯ,
        а не корпус.

    Знак берётся тем же образцом, каким идёт резка, и приставляется назад; где знака
    нет (последняя часть без точки), предложение остаётся как есть.
    """
    части = [ч.strip() for ч in arith_court.предложения(строка) if ч.strip()]
    знаки = [м.group(0).strip() for м in arith_court.ПРЕДЛОЖЕНИЕ.finditer(строка)]
    вон = []
    for i, ч in enumerate(части):
        вон.append(ч + знаки[i] if i < len(знаки) else ч)
    return вон


def сверить_объявление(м, внешний, палата):
    """Формы, объявленные миром и не совпавшие НИ С ОДНИМ его предложением.

    СВЕРКА ИДЁТ ПО ВСЕМУ МИРУ, А НЕ ПО ВЫБОРКЕ, и это не мелочь: объявление собрано по
    всем страницам, и проверять его выборкой в три строки значило бы звать разладом
    всякую форму, которой в выборке не случилось. Первая редакция так и делала — и
    назвала «объявленными без дела» пятьдесят форм из шестидесяти пяти, все честные.

        МЕРА ДОЛГА ВПРАВЕ БРАТЬ ВЫБОРКУ; СВЕРКА ОБЪЯВЛЕНИЯ С ДЕЛОМ — НЕ ВПРАВЕ.
        Первая говорит «сколько», вторая — «есть ли», и «есть ли» не выбирается.
    """
    вон = []
    for мир in м["worlds"]:
        предметы = мир.get("ПРЕДМЕТЫ") or ()
        if not предметы:
            continue
        п = W._файл(мир, внешний)
        if п is None:
            continue
        слои = палата.слои(п)
        пласт = палата.пласт_файла(п)
        встречены = set()
        for честно in п.read_text(encoding="utf-8", errors="replace").splitlines():
            честно = честно.strip()
            if not честно:
                continue
            судимо, истинно, _ = палата.судить(честно, слои, пласт)
            if not (судимо and истинно):
                continue
            части = предложения_со_знаком(честно)
            if len(части) < 2:
                continue
            пара = asking.пара(честно)
            вопрос = пара[0] if пара else ""
            for ч in части:
                if (палата.судить(ч, слои, пласт)[0]
                        or (вопрос and subjectforms._КОНЕЦ.sub("", ч) in вопрос)):
                    continue
                встречены.add(subjectforms.форма(ч))
        вон.extend((мир["name"], ф) for ф in sorted(set(предметы) - встречены))
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--manifest", default=None)
    дов = ап.parse_args()
    путь = pathlib.Path(дов.manifest) if дов.manifest else \
        КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    м = W.манифест(путь)
    if not м:
        print(f"ПОКРЫТИЕ ПРЕДЛОЖЕНИЯМИ ОТКАЗ: манифеста «{путь}» нет")
        return 2
    внешний = м.get("external_root")
    палата = panel.Палата()
    строк = целых = парой = предметами = дыра = 0
    по_мирам = collections.Counter()
    примеры = collections.defaultdict(list)
    объявлено = sum(len(w.get("ПРЕДМЕТЫ") or ()) for w in м["worlds"])
    for мир in м["worlds"]:
        if мир.get("text") != "shows":
            continue
        п = W._файл(мир, внешний)
        if п is None:
            continue
        предметы = frozenset(мир.get("ПРЕДМЕТЫ") or ())
        слои = палата.слои(п)
        пласт = палата.пласт_файла(п)
        все = [с.strip() for с in
               п.read_text(encoding="utf-8", errors="replace").splitlines() if с.strip()]
        if не_пусто(все):
            for честно in W.равномерно(все, СТРОК_НА_МИР, W.зерно_мира(мир["name"])):
                судимо, истинно, _ = палата.судить(честно, слои, пласт)
                if not (судимо and истинно):
                    continue
                части = предложения_со_знаком(честно)
                if len(части) < 2:
                    continue
                строк += 1
                немые = [ч for ч in части
                         if not палата.судить(ч, слои, пласт)[0]]
                if not немые:
                    целых += 1
                    continue
                пара = asking.пара(честно)
                вопрос = пара[0] if пара else ""
                # ЗНАК СНИМАЕТСЯ И ЗДЕСЬ: половина пары объявлена БЕЗ конечного знака
                # («calcule 23 × 6» при предложении «calcule 23 × 6.»), и сравнение со
                # знаком назвало бы задание непокрытым — то же лицо, что и у формы.
                если = [ч for ч in немые
                        if not (вопрос and subjectforms._КОНЕЦ.sub("", ч) in вопрос)]
                if not если:
                    парой += 1
                    continue
                предметом = [ч for ч in если if subjectforms.форма(ч) in предметы]
                если = [ч for ч in если if ч not in предметом]
                if not если:
                    предметами += 1
                    continue
                немые = если
                дыра += 1
                по_мирам[мир["name"]] += 1
                if len(примеры[мир["name"]]) < 2:
                    примеры[мир["name"]].append((немые[0][:60], честно[:70]))
    if not строк:
        print("ПОКРЫТИЕ ПРЕДЛОЖЕНИЯМИ ОТКАЗ: ни одной строки о двух предложениях")
        return 2
    for имя, n in по_мирам.most_common(20 if дов.подробно else 8):
        н, ц = примеры[имя][0]
        print(f"  НЕ ПОКРЫТО [{имя}] {n}: немое «{н}»" + (f"  в «{ц}»" if дов.подробно else ""))
    пустые = сверить_объявление(м, внешний, палата)
    for имя, ф in пустые[:12]:
        print(f"  ОБЪЯВЛЕНО БЕЗ ДЕЛА [{имя}]: форма «{ф}» не совпала ни с одним предложением")
    поза = "PASS" if дыра <= НЕПОКРЫТЫХ_РУБЕЖ and not пустые else "FAIL"
    print(f"ПОКРЫТИЕ ПРЕДЛОЖЕНИЯМИ {поза}: строк о двух и более предложениях {строк} — "
          f"покрыты предложениями {целых} ({100 * целых // строк}%), покрыты вопросной "
          f"половиной пары {парой} ({100 * парой // строк}%), покрыты ОБЪЯВЛЕННЫМ "
          f"ПРЕДМЕТОМ {предметами} ({100 * предметами // строк}%), НЕ ПОКРЫТО НИЧЕМ "
          f"{дыра} ({100 * дыра // строк}%, рубеж {НЕПОКРЫТЫХ_РУБЕЖ}) в {len(по_мирам)} "
          f"мирах; форм предмета объявлено {объявлено}, из них без дела {len(пустые)}")
    return 0 if поза == "PASS" else 1


def не_пусто(строки):
    return bool(строки)


if __name__ == "__main__":
    sys.exit(main())
