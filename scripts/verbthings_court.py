#!/usr/bin/env python3
"""[ГЛАГОЛ–ВЕЩЬ] — известный глагол с вещью чужого рода ложен о языке.

ЗАКОН: глагол берёт свой род вещей (tools/verbthings.py): еду едят, письменное
пишут, расстояние и время проходят, вес поднимают. Показ «sara wrote 8
pencils», «ann bought 21 books and ate 12 books», «walks 2 pounds every day»
верен арифметикой и ложен речью — а корпус, который учит речи, не вправе
учить обратному. Прибор считает по всем мирам показов тройки «глагол число
вещь», у которых дом сочетаемости отвечает «нет».

ПОВОД (03.09): 138 таких строк в пяти мирах историй нашлись только глазами,
после того как рынок историй e9 купил «walks pounds» как ставку.

ЧЕГО ПРИБОР НЕ ВИДИТ, НАЗВАНО ЧЕСТНО:
  · глагол вне дома и вещь вне всех родов не судятся — дом читает не
    смысл, а ОБЪЯВЛЕННУЮ сочетаемость, и молчит о необъявленном;
  · вещь, отделённая от глагола не числом («ate 5 of them»), здесь не
    читается: её судит суд мира, знающий свою рамку.

РУБЕЖ — 0: бессмыслица не порог, а дефект.

Использование:
  python3 scripts/verbthings_court.py
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402
import verbthings  # noqa: E402

# РУБЕЖ-ДОЛГА: ЧУЖИХ_РУБЕЖ = 0
ЧУЖИХ_РУБЕЖ = 0
# МНОЖИТЕЛЬ — НЕ ВЕЩЬ (25.09): «spent 5 times as much» — пара «spent — times» не пара глагола и вещи; взгляд
# вперёд — у двери (`verbthings.НЕ_ВЕЩЬ_КРАТНОСТЬ`), один на оба суда пары
ТРОЙКА = re.compile(rf"\b([a-z]+) (\d+) {verbthings.НЕ_ВЕЩЬ_КРАТНОСТЬ}([a-z]+)\b")


def обход():
    return [genesis._resolve(м["file"]) for м in genesis.manifest()["worlds"] if м.get("text") == "shows"]


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что признак ВИДИТ тройку и что дом
    сочетаемости ОТЛИЧАЕТ свою вещь от чужой.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ НУЛЯ НАХОДОК, И НОЛЬ ЕГО ДВУЗНАЧЕН ВДВОЙНЕ: пусть
        признак перестанет собирать тройки — находок не будет; пусть дом сочетаемости
        начнёт отвечать «да» всему — находок не будет тоже. Обе порчи дают ту же зелень,
        что и чистый свод.

    Потому проба идёт двумя ножами сразу: сперва тройка, потом ответ дома.
    """
    беды = []
    строка = "sara wrote 8 pencils and ate 12 apples today"
    тройки = ТРОЙКА.findall(строка)
    if тройки != [("wrote", "8", "pencils"), ("ate", "12", "apples")]:
        беды.append(f"признак тройки: {тройки} — ПРИБОРУ НЕЧЕГО СПРАШИВАТЬ")
    if ТРОЙКА.findall("у Вани 8 карандашей"):
        беды.append("признак взял русскую строку — тройка объявлена латиницей")
    # ДОМ СОЧЕТАЕМОСТИ ОБЯЗАН ОТВЕЧАТЬ «НЕТ» ХОТЬ ЧЕМУ-НИБУДЬ.
    случаи = (("ate", "apples", True), ("ate", "books", False),
              ("wrote", "letters", True), ("wrote", "pencils", False),
              ("walks", "miles", True), ("walks", "pounds", False))
    for глагол, вещь, ждём in случаи:
        было = verbthings.берёт(глагол, вещь)
        if было != ждём:
            беды.append(f"«{глагол} … {вещь}»: {было}, а надо {ждём}")
    if all(verbthings.берёт(г, в) for г, в, _ in случаи):
        беды.append("ДОМ СОЧЕТАЕМОСТИ СОГЛАШАЕТСЯ СО ВСЕМ — прибор не найдёт ничего никогда")
    return беды + _проба_актов()


def _проба_актов():
    """ДВЕРЬ АКТОВ (24.09, `verbthings.АКТЫ`) СУДИТСЯ СТРОЕНИЕМ И ЧУЖОЙ РУКОЙ.

    Строение: акт движет вещь между двумя РАЗНЫМИ держателями из объявленных четырёх; частица
    отдачи («away») стоит лишь при акте, уносящем вещь от носителя; знак зависит от держателя —
    «took» прибавляет взявшему и убавляет месту; держание («had») актом не является.

    Чужая рука: русская половина троек дома местоимений пишет «у кого остался» при убыли и «у кого
    стал» при прибыли СВОИМ текстом — знак английского акта дом берёт у двери, а русский оборот
    нет (форму при числе оборот берёт у двери сказуемого, лемму же — свою). Разойдись дверь с
    оборотом, одна из рук лжёт.

        ДВЕРЬ, КАКУЮ ЧИТАЮТ И ДОМ, И СУД, СУДОМ ДОМА НЕ ПРОВЕРЯЕТСЯ: ложь двери он повторит.
        Проверяет её свидетель, писанный мимо неё.
    """
    import gen_genesis_pronouns as местоимения  # noqa: PLC0415 — свидетели знака, писанные по-русски
    import story_chainforms as цепочки  # noqa: PLC0415
    V = verbthings
    беды = []
    держатели = {V.НОСИТЕЛЬ, V.МЕСТО, V.ДРУГОЙ, V.НИЧТО}
    for акт, (откуда, куда, частица) in V.АКТЫ.items():
        if откуда == куда or not {откуда, куда} <= держатели:
            беды.append(f"акт «{акт}»: {откуда} → {куда} — не движение между двумя держателями")
        if частица and откуда != V.НОСИТЕЛЬ:
            беды.append(f"акт «{акт} … {частица}»: частица отдачи при акте, не уносящем от носителя")
    if (V.знак_акта("took", V.НОСИТЕЛЬ), V.знак_акта("took", V.МЕСТО)) != (1, -1):
        беды.append("«took» обязан прибавлять взявшему и убавлять месту")
    if V.знак_акта("had", V.НОСИТЕЛЬ) is not None:
        беды.append("«had» — держание, а дверь зовёт его актом")
    свидетелей = {1: 0, -1: 0}
    пары = list(zip(местоимения.ТРОЙКИ_EN, местоимения.ТРОЙКИ_RU)) + list(zip(цепочки.ТРОЙКИ_EN, цепочки.ТРОЙКИ_RU))
    for en, ru in пары:
        оборот = ru[2]
        акт = en[1].split()[0]                   # «gave away» — акт «gave» с его частицей
        # последним СЛОВОМ, а не подстрокой: «стал» сидит внутри «о-стал-ся»; свидетель назван
        # леммой — словом тройки или дырой шаблона («у {кого} {остался}»), форму при числе даёт дверь
        ждём = {"стал": 1, "остался": -1}.get(оборот.split()[-1].strip("{}"))
        if ждём is None:
            continue
        свидетелей[ждём] += 1
        if V.знак_акта(акт, V.НОСИТЕЛЬ) != ждём:
            беды.append(f"акт «{акт}»: дверь даёт {V.знак_акта(акт, V.НОСИТЕЛЬ)}, русский оборот «{оборот}» — {ждём}")
    # СВИДЕТЕЛЬ БЕЗ СИЛЫ НЕ СВИДЕТЕЛЬ: переворот знака ловится лишь там, где оборот есть обоих знаков
    if not all(свидетелей.values()):
        беды.append(f"русский свидетель знака одного знака: {свидетелей} — переворот другого не виден")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ГЛАГОЛ–ВЕЩЬ ОТКАЗ: прибор не доказал, что различает ({len(беды)} бед)")
        return 2
    пути = [п for п in обход() if п.is_file()]
    if not пути:
        print("ГЛАГОЛ–ВЕЩЬ ОТКАЗ: обход пуст, судить нечего")
        return 2
    чужих = collections.Counter()
    примеры = {}
    строк = 0
    for путь in пути:
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            if not строка.strip():
                continue
            строк += 1
            for глагол, _, вещь in ТРОЙКА.findall(строка):
                if not verbthings.берёт(глагол, вещь):
                    ключ = (путь.stem, глагол, вещь)
                    чужих[ключ] += 1
                    примеры.setdefault(ключ, строка.strip()[:100])
    всего = sum(чужих.values())
    вердикт = "PASS" if всего <= ЧУЖИХ_РУБЕЖ else "FAIL"
    print(f"ГЛАГОЛ–ВЕЩЬ {вердикт}: {всего} чужих пар глагол–вещь в {строк} строках показов ({len(пути)} файлов, рубеж {ЧУЖИХ_РУБЕЖ})")
    for ключ, сколько in чужих.most_common(8):
        мир, глагол, вещь = ключ
        print(f"  {сколько:4d} {мир}: «{глагол} … {вещь}» — {примеры[ключ]}")
    return 0 if вердикт == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
