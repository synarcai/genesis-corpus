#!/usr/bin/env python3
"""[ИМЯ ПЕРЕШЛО ЯЗЫК] — имя, выделенное в одном языке мира и молчащее в другом.

    ВЫДЕЛЕНИЕ ЕСТЬ ЧАСТЬ ИМЕНИ: слово, названное в одном языке и сказанное мимоходом
    в другом, читается как имя только там, где выделено.

ПОВОД, ПРОЖИТЫЙ ДВАЖДЫ ЗА ОДИН ДЕНЬ. Свод называет русский род 624 строками — «Анна
женского рода» — и молчит о роде во всех девяти чужих языках при трёх тысячах артиклей.
Дом ярлыка числа пишет по-английски «a number after the word CALLS and does not MEASURE»,
выделяя оба дела, и по-русски «номер зовёт, а не мерит» — без выделения.

    ЗНАНИЕ, НАЗВАННОЕ НА ОДНОМ ЯЗЫКЕ И МОЛЧАЩЕЕ НА ДРУГОМ, УЧИТ, ЧТО ЭТО СВОЙСТВО
    ОДНОГО ЯЗЫКА, А НЕ СВОЙСТВО ЯЗЫКОВ.

ЧЕМ МЕРИТЬ. Свод держит соглашение: ИМЯ ПОНЯТИЯ ПИШЕТСЯ ЗАГЛАВНЫМИ на самой странице —
«это свойство зовётся СИММЕТРИЕЙ», «ПЕРЕМЕСТИТЕЛЬНЫМ», «modus ponens», «РОД есть свойство
СЛОВА». Соглашение это и есть мера: в двуязычном мире, где одна половина выделяет имена,
а другая не выделяет ни одного, вторая половина учит делу без слова.

ЧЕГО ПРИБОР НЕ ТРЕБУЕТ. Он не требует РАВНОГО ЧИСЛА имён: языки не переводятся строка в
строку, и мир вправе называть понятие там, где оно впервые встретилось. Он говорит лишь о
ПОЛНОМ МОЛЧАНИИ одной стороны при говорящей другой — и только в мирах, где обеих сторон
довольно, чтобы молчание было выбором, а не малостью.

    МОЛЧАНИЕ ОДНОЙ СТОРОНЫ ПРИ ГОВОРЯЩЕЙ ДРУГОЙ ЕСТЬ ДОЛГ; НЕРАВЕНСТВО ЧИСЕЛ — НЕТ.

ИСКЛЮЧЕНИЯ ОБЪЯВЛЕНЫ ПОИМЁННО, ибо заглавные буквы несут в своде и другое дело: имя
источника («ЭСБЕ»), обозначение единицы, римскую цифру. Такое слово есть ИМЯ СОБСТВЕННОЕ,
а не имя понятия, и требовать его перевода было бы требовать перевода подписи.

    python3 scripts/name_crossed.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"

import langsign  # noqa: E402 — язык строки берётся у знака корпуса, а не у счёта букв

# РУБЕЖ-ДОЛГА: НЕМЫХ_РУБЕЖ = 0
#
# Рубеж есть ПОЛ, а не поблажка: замер 12.09 нашёл один мир, выделявший имена лишь по
# -английски, и он выправлен в тот же час.
НЕМЫХ_РУБЕЖ = 0

# СКОЛЬКО СТРОК ДОЛЖНО БЫТЬ У СТОРОНЫ, ЧТОБЫ ЕЁ МОЛЧАНИЕ БЫЛО ВЫБОРОМ, А НЕ МАЛОСТЬЮ.
ДОВОЛЬНО_СТРОК = 20

# ИМЯ ПОНЯТИЯ: четыре и более заглавных подряд. Три буквы дали бы римские цифры и
# сокращения; четыре — предел, за которым случайных попаданий в своде не нашлось.
ИМЯ = re.compile(r"\b[А-ЯЁA-ZÄÖÜÉÈÀÇÑŁŚŻŹĆŃ]{4,}\b")

# ИМЕНА СОБСТВЕННЫЕ И ОБОЗНАЧЕНИЯ, объявленные поимённо: заглавные здесь не имя понятия.
НЕ_ИМЯ = frozenset({"ЭСБЕ", "SVAMP", "GENESIS", "ASCII", "CommonMark", "LATEX", "HTML",
                    "JSON", "TSV", "SHA", "UTF", "MDX", "GFM"})


def _имена(строка):
    return [и for и in ИМЯ.findall(строка) if и not in НЕ_ИМЯ]


def миры(манифест):
    тело = json.loads(манифест.read_text(encoding="utf-8"))
    вон = []
    for з in тело.get("worlds", ()):
        if з.get("text") != "shows":
            continue
        п = pathlib.Path(з.get("file", ""))
        if not п.is_absolute():
            п = КОРЕНЬ / п
        if п.is_file():
            вон.append((з["name"], п.read_text(encoding="utf-8", errors="replace")))
    return вон


def main():
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
    if not манифест.is_file():
        print(f"ИМЯ ПЕРЕШЛО ЯЗЫК ОТКАЗ: манифеста нет — {манифест}")
        return 2
    свод = миры(манифест)
    if not свод:
        print("ИМЯ ПЕРЕШЛО ЯЗЫК ОТКАЗ: миров показов нет, спрашивать не о ком")
        return 2
    подробно = "--подробно" in sys.argv
    немые, двуязычных, всего_имён = [], 0, 0
    for имя_мира, тело in свод:
        строк, имён = collections.Counter(), collections.Counter()
        for с in тело.split("\n"):
            if not с.strip():
                continue
            # ЯЗЫК СТРОКИ БЕРЁТСЯ У ЗНАКА КОРПУСА: счёт букв ошибается там, где строка
            # несёт числа и знаки, а знак читает письмо.
            сторона = "чужой" if langsign.чужой(с, "en") else "en"
            строк[сторона] += 1
            n = len(_имена(с))
            имён[сторона] += n
            всего_имён += n
        если_обе = [с for с in строк if строк[с] >= ДОВОЛЬНО_СТРОК]
        if len(если_обе) < 2:
            continue
        двуязычных += 1
        молчат = [с for с in если_обе if имён[с] == 0]
        говорят = [с for с in если_обе if имён[с] > 0]
        if молчат and говорят:
            немые.append((имя_мира, dict(строк), dict(имён)))
        if подробно and говорят:
            print(f"  {имя_мира:<24} строк {dict(строк)}  имён {dict(имён)}")
    for имя_мира, стр, им in немые[:8]:
        молчащая = [с for с in стр if им.get(с, 0) == 0 and стр[с] >= ДОВОЛЬНО_СТРОК]
        print(f"  ИМЯ НЕ ПЕРЕШЛО «{имя_мира}»: сторона {', '.join(молчащая)} молчит "
              f"({стр}), а другая называет ({им})")
    поза = "PASS" if len(немые) <= НЕМЫХ_РУБЕЖ else "FAIL"
    print(f"ИМЯ ПЕРЕШЛО ЯЗЫК {поза}: миров, где имя стои́т в одной стороне и МОЛЧИТ в "
          f"другой, {len(немые)} (рубеж {НЕМЫХ_РУБЕЖ}); двуязычных миров {двуязычных} "
          f"из {len(свод)}, имён понятий {всего_имён}, объявлено не-имён {len(НЕ_ИМЯ)}")
    return 0 if len(немые) <= НЕМЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
