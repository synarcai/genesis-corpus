#!/usr/bin/env python3
"""[БОГАТСТВО] — умеет ли корпус СОЕДИНЯТЬ, а не только говорить.

Судимость мерит, читают ли строку. Полнота мерит, есть ли предмет.
Богатство мерит ФОРМЫ СОЕДИНЕНИЯ и их СТЫКИ — а речь есть соединение,
и рассуждение есть речь.

ДВЕ ОСИ, И ВТОРАЯ ГЛАВНАЯ. Формы растут линейно, речь — стыками:
двадцать форм дают двадцать умений и четыреста возможных пар. Оттого
прибор считает не только формы, но и пары F над G, и ориентация в них
значима.

СТЫК СЧИТАЕТСЯ КОНТРОЛЕМ, А НЕ МАССОЙ. Композиция купленных форм есть
ВЫВОД, а не заучивание: покупки глубины два не существует, и требовать
для неё учебной массы значило бы вернуть зубрёжку туда, где построен
вывод. Проб довольно одной-двух на стык — они нужны ПРИБОРУ, чтобы
отличить живой стык от мёртвого, а не рынку.

ЧЕГО ЭТОТ ПРИБОР НЕ ГОВОРИТ, И ЭТО ГЛАВНАЯ ЕГО ОГОВОРКА: он мерит ОДИН
столбец из трёх — ПОКАЗАНО. Два других — КУПЛЕНО и ИСПОЛНЕНО — живут на
стороне организма. Показанное есть ВЕРХНЯЯ ГРАНИЦА купленного и не
более: замер организма говорит, что вне купленных родов он нем
полностью, шестьдесят из шестидесяти пяти. Мера на входе не вправе
выдавать себя за меру на выходе, и потому прибор печатает своё имя
столбца в каждой строке вывода.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import Unreadable, worlds  # noqa: E402
from rhetoric import СТЫКИ, ФОРМЫ  # noqa: E402

# РУБЕЖ-ДОЛГА: НЕПОКАЗАННЫХ_РУБЕЖ = 0
НЕПОКАЗАННЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest


def обход():
    if "--manifest" in sys.argv:
        import genesis
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        return [п for п in worlds(kind="shows") if п.is_file()]
    except Unreadable as беда:
        print(f"БОГАТСТВО ОТКАЗ: {беда}")
        sys.exit(2)


def массы(пути, чего):
    образцы = [(э, re.compile(э.проба, re.I)) for э in чего]
    счёт = {э.имя if hasattr(э, "масса") and hasattr(э, "зачем")
            and not hasattr(э, "верх") else (э.верх, э.низ): 0
            for э in чего}
    for путь in пути:
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                if not строка.strip():
                    continue
                for э, образец in образцы:
                    if образец.search(строка):
                        ключ = ((э.верх, э.низ) if hasattr(э, "верх")
                                else э.имя)
                        счёт[ключ] += 1
    return счёт


def выбранные(чего, довод):
    """Формы (или стыки), названные доводом, либо весь свод.

    МЕРИТЬ ОДНУ ФОРМУ — НЕ ПОБЛАЖКА, А НУЖДА: без этого у прибора нет
    стенда, ибо честный близнец обязан нести ВЕСЬ свод, а в стенде из
    трёх строк это невозможно. Тем же пользуются в работе, закрывая
    один пробел.
    """
    имена = [sys.argv[i + 1] for i, а in enumerate(sys.argv)
             if а == довод and i + 1 < len(sys.argv)]
    if not имена:
        return чего
    выбор = [э for э in чего
             if (э.имя if hasattr(э, "имя") else f"{э.верх}∘{э.низ}")
             in имена]
    if not выбор:
        print(f"БОГАТСТВО ОТКАЗ: {имена} не объявлено в своде")
        sys.exit(2)
    return выбор


def main():
    пути = обход()
    if not пути:
        print("БОГАТСТВО ОТКАЗ: обход пуст, мерить нечего")
        return 2
    свои_формы = выбранные(ФОРМЫ, "--форма")
    свои_стыки = ([] if "--форма" in sys.argv
                  else выбранные(СТЫКИ, "--стык"))
    форм = массы(пути, свои_формы) if свои_формы else {}
    стыков = массы(пути, свои_стыки) if свои_стыки else {}
    нет_форм = [(ф, форм[ф.имя]) for ф in свои_формы
                if форм[ф.имя] < ф.масса]
    нет_стыков = [(с, стыков[(с.верх, с.низ)]) for с in свои_стыки
                  if стыков[(с.верх, с.низ)] < с.масса]
    if нет_форм:
        print("  ФОРМЫ НЕ ПОКАЗАНЫ: "
              + ", ".join(f"{ф.имя} ({б}/{ф.масса})"
                          for ф, б in нет_форм[:8]))
    if нет_стыков:
        print("  СТЫКИ НЕ ПОКАЗАНЫ: "
              + ", ".join(f"{с.верх}∘{с.низ} ({б}/{с.масса})"
                          for с, б in нет_стыков[:6]))
    всего = len(нет_форм) + len(нет_стыков)
    поза = "PASS" if всего <= НЕПОКАЗАННЫХ_РУБЕЖ else "FAIL"
    print(f"БОГАТСТВО[показано] {поза}: не показаны {len(нет_форм)} форм "
          f"из {len(свои_формы)} и {len(нет_стыков)} стыков "
          f"из {len(свои_стыки)} "
          f"(рубеж {НЕПОКАЗАННЫХ_РУБЕЖ}, {len(пути)} файлов); "
          f"КУПЛЕНО и ИСПОЛНЕНО мерятся на стороне организма")
    return 0 if всего <= НЕПОКАЗАННЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
