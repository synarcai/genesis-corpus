#!/usr/bin/env python3
"""МЕРА ОХВАТА СЛОВА: хватает ли корпусу СЛОВ, а не только правды.

Все меры корпуса спрашивали одно и то же: ВЕРНА ЛИ СТРОКА. Судимость
требует, чтобы всякую строку кто-то читал; суды требуют, чтобы всякая
прочтённая была истинной; воспроизводимость требует, чтобы всё это
пересобиралось побайтово. Сто двадцать тысяч строк, ноль лжи — и на
школьном вопросе «Janey counted the apples in the parking lot» корпус
нем, потому что слова «parking» он не видел НИ РАЗУ.

ЭТО НЕ ДЕФЕКТ ПОКАЗА, А ОТСУТСТВИЕ МЕРЫ. Мера, которой нет, не падает
никогда — и потому её отсутствие неотличимо от здоровья. Здесь она
есть: корпус ОБЪЯВЛЯЕТ словарь, который берётся прожить
(`declarations/TARGET-LEXICON.md`), и мера считает, сколько из
объявленного действительно живёт.

ПРОЖИТО — ЗНАЧИТ ВСТРЕЧЕНО НЕ МЕНЕЕ ДВУХ РАЗ. Сказанное однажды не
выучивается: то же правило, каким живёт поле LANGPACK-ONCE у языковых
пакетов, и оно здесь не переизобретается, а повторяется сознательно.

МЕРА НАЗЫВАЕТ НЕДОСТАЮЩЕЕ ПОИМЁННО. Число «охвачено 300 из 360» само
по себе не строит ни одного мира; список отсутствующих строит.
"""

import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402

# РУБЕЖ-ОХВАТА: доля объявленного словаря, прожитая корпусом, %
ОХВАТА_РУБЕЖ = 100

# ВТОРОЙ ЗНАМЕНАТЕЛЬ — ОТ ДЕЛА, А НЕ ОТ ОБЪЯВЛЕНИЯ.
#
# 366 из 366 говорят лишь то, что мы прожили ВСЁ, ЧТО ОБЯЗАЛИСЬ
# прожить, — и ни слова о том, чего обязаться забыли. Соседняя рука
# (e9) построила прибор `omega/tools/band_walls.py`: он гоняет полосу
# по вопросам GSM8K и называет слова, на которых она ВСТАЛА СТЕНОЙ.
# Первый замер: 64 вопроса из 65 несут стены, 438 разных слов-дыр, из
# них 81 — имена. Валюта дела оказалась ШИРЕ объявленного договора.
#
# Замер лежит отдельным файлом (`declarations/BAND-WALLS.md`) и рукой
# НЕ ПРАВИТСЯ; договор (`TARGET-LEXICON.md`) правится ТОЛЬКО рукой.
# Слить их автопополнением значило бы сделать договор всегда покрытым:
# он перестал бы уметь сказать «этого я не крою». Мера печатает ОБА
# числа, и расхождение между ними видно, а не заглажено.
#
# ИМЯ НЕ ЕСТЬ ПРОБЕЛ СЛОВАРЯ: агент локален эпизоду, и «jamal's» знать
# незачем. Прибор помечает такие стены kind=name, и мера их не считает.
СТЕНЫ = КОРЕНЬ / "declarations" / "BAND-WALLS.md"

# ПУСТОЙ-ОБХОД: --словарь no-such-lexicon.md

СЛОВАРЬ = КОРЕНЬ / "declarations" / "TARGET-LEXICON.md"
ПРОЖИТО = 2
СЛОВО = re.compile(r"[a-z']+")
СТРОКА_СЛОВ = re.compile(r"^[a-z, ]+$")


def объявленные(путь):
    """Слова договора — по строкам вида «слово, слово, слово»."""
    try:
        текст = путь.read_text(encoding="utf-8")
    except OSError as беда:
        print(f"ОХВАТ ОТКАЗ: словарь не читается ({беда})")
        sys.exit(2)
    вон = []
    for строка in текст.splitlines():
        с = строка.strip()
        if not с or с.startswith("#") or not СТРОКА_СЛОВ.match(с):
            continue
        вон += [w.strip() for w in с.split(",") if w.strip()]
    return вон


def прожитые(фразы=()):
    """({слово: сколько раз}, {фраза: сколько раз}) по мирам показов.

    ДОГОВОР БЫВАЕТ О ФРАЗЕ, А НЕ ТОЛЬКО О СЛОВЕ. «in all», «each
    other», «left over» суть единицы речи, и мера, считавшая одни
    словоформы, объявляла их непрожитыми, пока корпус говорил их
    сотнями раз. Ошибка была в МЕРЕ, а не в корпусе — и это тот самый
    род, ради которого мера и заводилась: прибор, отвечающий на
    вопрос, который умеет задать, молчит о том, который надо.
    """
    счёт = collections.Counter()
    счёт_фраз = collections.Counter()
    try:
        миры = genesis.manifest()["worlds"]
    except genesis.Unreadable as беда:
        print(f"ОХВАТ ОТКАЗ: {беда}")
        sys.exit(2)
    for мир in миры:
        if мир.get("text") != "shows":
            continue
        путь = genesis._resolve(мир["file"])
        if not путь.is_file():
            continue
        текст = путь.read_text(encoding="utf-8",
                               errors="replace").lower()
        счёт.update(СЛОВО.findall(текст))
        for фраза in фразы:
            счёт_фраз[фраза] += текст.count(фраза)
    return счёт, счёт_фраз


def стены(путь):
    """Слова-дыры замера полосы; None — замера нет."""
    if not путь.exists():
        return None
    вон = []
    for с in путь.read_text(encoding="utf-8").splitlines():
        части = с.split("\t")
        if len(части) >= 3 and части[0] == "WALL" and части[1] == "gap":
            вон.append(части[2])
    return вон


def main():
    путь = СЛОВАРЬ
    if "--словарь" in sys.argv:
        путь = pathlib.Path(sys.argv[sys.argv.index("--словарь") + 1])
    цель = объявленные(путь)
    if not цель:
        print("ОХВАТ ОТКАЗ: словарь пуст, мерить нечего")
        return 2
    фразы = tuple(с for с in цель if " " in с)
    счёт, счёт_фраз = прожитые(фразы)

    def сколько(с):
        return счёт_фраз[с] if " " in с else счёт.get(с, 0)

    живут = [с for с in цель if сколько(с) >= ПРОЖИТО]
    раз = [с for с in цель if сколько(с) == 1]
    нет = [с for с in цель if сколько(с) == 0]
    доля = 100 * len(живут) // len(цель)
    if нет:
        print(f"  НЕ ПРОЖИТО ВОВСЕ {len(нет)}: "
              f"{', '.join(sorted(нет)[:24])}"
              f"{' …' if len(нет) > 24 else ''}")
    if раз:
        print(f"  СКАЗАНО ОДНАЖДЫ {len(раз)}: "
              f"{', '.join(sorted(раз)[:16])}"
              f"{' …' if len(раз) > 16 else ''}")
    стена = стены(СТЕНЫ)
    if стена is not None:
        крыто = [с for с in стена if сколько(с) >= ПРОЖИТО]
        д2 = 100 * len(крыто) // len(стена) if стена else 0
        print(f"  ВАЛЮТА ПОЛОСЫ: {len(крыто)} из {len(стена)} слов-дыр "
              f"замера прожиты корпусом ({д2}%) — знаменатель от ДЕЛА, "
              f"а не от объявления")
    поза = "PASS" if доля >= ОХВАТА_РУБЕЖ else "FAIL"
    print(f"ОХВАТ {поза}: {len(живут)} из {len(цель)} объявленных слов "
          f"прожиты >={ПРОЖИТО} раз ({доля}% при рубеже "
          f"{ОХВАТА_РУБЕЖ}%)")
    return 0 if доля >= ОХВАТА_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
