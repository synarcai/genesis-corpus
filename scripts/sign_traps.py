#!/usr/bin/env python3
"""[ЛОВУШКА ЗНАКА] — дома, чей суд НЕМЕЕТ на подмене собственного знака действия (М-489).

ЗАКОН СТОИТ ДЫРОЙ, А НЕ БУКВОЙ. Образец суда, держащий знак действия литералом, не может
отличить «9 + 5 = 14» от «9 − 5 = 14»: подменённая строка просто НЕ СОВПАДАЕТ с образцом, и суд
о ней МОЛЧИТ. Он не называет её ложью — он говорит «не моя», а это разные вещи. Суд, слепой ровно
на той порче, ради которой поставлен, есть худший из ложных приборов: он зелен и бесполезен.

    ПОРЧА, КОТОРУЮ СУД НЕ ВИДИТ, ЕСТЬ ПОРЧА, КОТОРОЙ ЕГО РУБЕЖ НЕ КАСАЕТСЯ. «0 ложных» такого
    суда есть число о том, что он УМЕЕТ прочесть, а не о том, что в мире верно.

ПОЧЕМУ ЭТО НЕ ДЫРА КОРПУСА, И ЭТО ЗАМЕРЕНО, А НЕ ОБЕЩАНО. Те же подмены, прогнанные через ВСЮ
ПАЛАТУ путём ворот записи (файл с именем мира, `panel.палата().судить_файл`), названы ложью все:
144 из 144, не увидел никто — их ловит суд арифметики, ибо «60 × 2 = 30» ложно само по себе,
что бы ни думал о нём дом дроби единицы. Корпус защищён СОСЕДОМ.

    НО ИМЕННО ЭТО И ЕСТЬ ДОЛГ (М-131): палата берёт истину у соседа. Дом дроби не знает, что его
    собственный леджер испорчен, — он знает лишь, что строка «не его»; и в день, когда сосед
    сузится или мир выйдет из-под него, порча станет невидимой. Прибор считает не безопасность
    корпуса, а САМОСТОЯТЕЛЬНОСТЬ каждого суда.

ПРИЗНАК ЧИСТ И НЕ СПРАШИВАЕТ ОБ ИСТИНЕ. Берётся ЖИВАЯ страница дома, в первом шаге её леджера
знак меняется на обратный (+↔−, ×↔÷), а ЧИСЛО ОТВЕТА НЕ ТРОГАЕТСЯ — значит строка заведомо ложна
арифметически. Дом, читающий закон дырой, зовёт её ЛОЖЬЮ; дом, держащий знак буквой, МОЛЧИТ.
Прибор спрашивает не «прав ли суд», а «видит ли он».

    python3 scripts/sign_traps.py [--подробно] [--дом ИМЯ]
"""
# ПУСТОЙ-ОБХОД: --дом no-such-house
import argparse
import importlib
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: НЕМЫХ_РУБЕЖ = 0
#
# Долг ведётся ЧИСЛОМ ДОМОВ, а не числом проб: проб тем больше, чем больше дом, и рубеж по ним
# рос бы от роста корпуса, а не от порчи.
#
# ПОСТАВЛЕН ПРИБОР БЫЛ НА 28 — уровень того часа, — И ЗАКРЫТ В ТОТ ЖЕ ДЕНЬ. Двадцать девять
# домов молчали на подмене собственного знака; шесть вылечены поимённо (дыра в рамке и проверка
# в вердикте), двадцать три — общим законом замкнутого мира `closedworld.ложь_по_знаку`, не
# тронувшим ни одной их рамки. Один из двадцати девяти оказался хуже немого: дом мер на языках
# ОБЪЯВИЛ знак дырой и ни разу его не прочёл, отчего «43 − 21 = 64» звалось ИСТИНОЙ — 126 строк
# из 462. Дыра без проверки не слепа, она БЛАГОСЛОВЛЯЕТ.
#
# Ныне рубеж есть НОЛЬ и есть ПОЛ, а не потолок: дом, написанный со знаком-буквой и без закона,
# роняет прибор в тот же час, когда его напишут.
НЕМЫХ_РУБЕЖ = 0

# БЮДЖЕТ ВЫБОРКИ, НЕ ПОРОГ: слепота видна на первой же пробе — образцов взято ради времени
ОБРАЗЦОВ = 40
ОБРАТНЫЙ = {"+": "−", "−": "+", "×": "÷", "÷": "×"}
ЛЕДЖЕР = re.compile(r"(\d+) ([+−×÷]) (\d+) = (\d+)")
# ДОМА, ЧЕЙ ЛЕДЖЕР НЕ ЕСТЬ АРИФМЕТИКА: там подмена знака не делает строку ложной по счёту
# (сравнение записей, а не действие), и молчание суда законно. Названы поимённо, а не угаданы.
НЕ_СЧЁТНЫЕ = frozenset()


def дома():
    """Всякий дом с показами и своим судом — найден делом, а не списком."""
    вон = []
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        if путь.stem.startswith("gen_"):
            continue
        try:
            дом = importlib.import_module(путь.stem)
        except Exception:
            continue
        показы = getattr(дом, "ПОКАЗЫ", None)
        судить = getattr(дом, "судить", None)
        if isinstance(показы, dict) and показы and callable(судить):
            вон.append((путь.stem, дом))
    return вон


def проба(дом, показ):
    """Живая страница с подменённым знаком первого шага — или None, если леджера нет."""
    найдено = ЛЕДЖЕР.search(показ)
    if not найдено:
        return None
    a, знак, b, r = найдено.groups()
    битая = показ.replace(f"{a} {знак} {b} = {r}", f"{a} {ОБРАТНЫЙ[знак]} {b} = {r}", 1)
    return битая if битая != показ else None


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--дом", default=None, help="проверить один дом")
    дов = ап.parse_args()
    список = [(и, д) for и, д in дома() if дов.дом is None or и == дов.дом]
    if not список:
        print(f"ЛОВУШКА ЗНАКА ОТКАЗ: домов не найдено{f' ({дов.дом})' if дов.дом else ''}")
        return 2
    слепые, всего_проб, всего_немых, всего_поймано = [], 0, 0, 0
    print(f"{'дом':<20}{'проб':>6}{'поймано':>9}{'НЕМЫХ':>7}")
    for имя, дом in список:
        проб = немых = поймано = 0
        первая = None
        for показ in list(дом.ПОКАЗЫ)[:ОБРАЗЦОВ * 8]:
            if проб >= ОБРАЗЦОВ:
                break
            битая = проба(дом, показ)
            if битая is None:
                continue
            try:
                судимо, истинно = дом.судить(битая)[:2]
            except Exception:
                continue
            проб += 1
            if not судимо:
                немых += 1
                if первая is None:
                    первая = битая
            elif not истинно:
                поймано += 1
        if not проб:
            continue
        всего_проб += проб; всего_немых += немых; всего_поймано += поймано
        знак = f"{немых:>7}" if немых else f"{'—':>7}"
        print(f"{имя:<20}{проб:>6}{поймано:>9}{знак}")
        if немых and имя not in НЕ_СЧЁТНЫЕ:
            слепые.append((имя, немых, проб, первая))
    print(f"{'ИТОГО':<20}{всего_проб:>6}{всего_поймано:>9}{всего_немых:>7}")
    for имя, немых, проб, первая in слепые:
        print(f"  СЛЕПОЙ [{имя}] {немых} из {проб}: «{первая[:110]}»")
    поза = "PASS" if len(слепые) <= НЕМЫХ_РУБЕЖ else "FAIL"
    print(f"ЛОВУШКА ЗНАКА {поза}: домов, немеющих на подмене СВОЕГО знака, {len(слепые)} "
          f"(рубеж {НЕМЫХ_РУБЕЖ}); проб {всего_проб}, поймано {всего_поймано}, "
          f"немых проб {всего_немых}; палата ловит их все (замер 144 из 144)")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
