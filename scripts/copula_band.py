#!/usr/bin/env python3
"""[СВЯЗКА ПО ПОЛОСЕ] — глагол при счёте: стои́т ли он по закону языка и видит ли суд подмену.

Дом польской грамматики знал ТРИ формы существительного при числе и брал их законом
(`plgram.форма`). Связку при том же числе пять его читателей писали БУКВОЙ:

    «na półce jest 3 jabłka»      вместо «są»       (дом держания, 18 страниц)
    «było 4 minuty»               вместо «były»     (польский слой, 42)
    «w koszyku jest 4 jabłka»     вместо «są»       (дом квантора, 6)
    «po kroku 2 jest 22 książki»  вместо «są»       (дом плана, 6)
    «rano było 1 stopień»         вместо «był»      (знаковый мир, 11)

Сто пять страниц свода были ложны по-польски, и палата звала их истиной.

    ДОМ, ЗНАЮЩИЙ ЗАКОН ДЛЯ СУЩЕСТВИТЕЛЬНОГО И НЕ ДАЮЩИЙ ЕГО ГЛАГОЛУ, ЗНАЕТ ЗАКОН НАПОЛОВИНУ —
    И ПОЛОВИНА ЭТА ВЫХОДИТ ЛОЖЬЮ РОВНО ТАМ, ГДЕ ЯЗЫК РАСХОДИТСЯ С ЧИСЛОМ.

ДВА ЭТАЖА, И ВТОРОЙ ХУЖЕ ПЕРВОГО. Порча на странице (первый этаж) видна и считается; но связка,
стоящая в образце суда ЛИТЕРАЛОМ, делает подменённую строку не ложной, а ЧУЖОЙ — суд о ней
молчит (тот же род, что у знака действия, М-489). Дом, чей вердикт зелен оттого, что он не умеет
прочесть порчу, есть худший из ложных приборов.

    ПОРЧА, КОТОРУЮ СУД НЕ ВИДИТ, ЕСТЬ ПОРЧА, КОТОРОЙ ЕГО РУБЕЖ НЕ КАСАЕТСЯ.

ПРИЗНАК ЧИСТ И БЕРЁТСЯ У ДОМА ЯЗЫКА, А НЕ ЗДЕСЬ. Прибор не знает польского: он спрашивает у
`plgram` (объявленные леммы, их род и таблицу связки), какая форма стои́т при этом числе, — и
сравнивает. Язык, чей дом такой таблицы не объявил, прибору не подсуден, и молчание о нём есть
честная граница. День, когда таблицу объявит второй язык, есть день, когда прибор станет мерить
и его — без правки здесь.

    python3 scripts/copula_band.py [--подробно] [--дом ИМЯ]
"""
# ПУСТОЙ-ОБХОД: --дом no-such-house
import argparse
import collections
import importlib
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import plgram  # noqa: E402 — дом языка, объявивший связку

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
#
# НОЛЬ ОТ РОЖДЕНИЯ. Сто пять страниц найдены и вылечены в тот же час — пять домов получили
# связку дырой, гнущейся полосой счёта, и ни один не потерял страницы. Долг, закрытый прежде
# объявления рубежа, объявляется нулём, а не своим прежним числом: рубеж есть пол, а не запас.
ЛОЖНЫХ_РУБЕЖ = 0

# РУБЕЖ-ДОЛГА: НЕМЫХ_РУБЕЖ = 0
#
# ВТОРОЙ ЭТАЖ, И ОН СТЕРЕЖЁТСЯ ЧИСЛОМ ДОМОВ, а не проб: проб тем больше, чем больше дом.
# Дому довольно ОДНОГО из двух путей — дыры с проверкой в вердикте (дома держания, плана,
# знакового мира) или закона замкнутого мира `closedworld.ложь_по_связке` (дом квантора);
# прибор не спрашивает, каким путём, он спрашивает, ВИДИТ ЛИ.
НЕМЫХ_РУБЕЖ = 0

# РУБЕЖ-ДОЛГА: БЫТИЯ_РУБЕЖ = 0
#
# ТРЕТИЙ ЭТАЖ, И ОН ЗАКРЫТ В ЧАС ОТКРЫТИЯ. Двенадцать страниц знакового мира в трёх языках
# получили связку утра дырой, гнущейся модулем числа; больше во всём своде не нашлось ни одной.
# Долг, стоивший одной рамки на язык, объявляется нулём.
БЫТИЯ_РУБЕЖ = 0

ОБРАЗЦОВ = 40          # бюджет выборки на дом, не порог: слепота видна на первой же пробе

# ЗАКОН ЧИТАЕТСЯ У ДОМА ЯЗЫКА, А НЕ ПОВТОРЯЕТСЯ ЗДЕСЬ. Первая редакция держала свою таблицу
# форм и своё чтение строки; они совпадали с домом в час написания и разошлись бы в первый же
# день, когда дом объявит новую лемму. Прибор спрашивает `plgram.обвинения` — то же чтение,
# каким дом свамп судит свои страницы, — и потому не может мерить не то, что охраняет.
# СВЯЗКА БЫТИЯ: ТА, ЧЬЁ ПОДЛЕЖАЩЕЕ ЕСТЬ САМО ЧИСЛО (08.09, второй заход).
#
# Польская связка гнётся ПОЛОСОЙ из трёх; у шести прочих языков корпуса она гнётся ЕДИНИЦЕЙ —
# и гнётся, стало быть, тоже. Замер по своду нашёл двенадцать страниц знакового мира в трёх
# языках разом: «am Morgen waren es 1 Grad», «la mattina c'erano 1 grado», «de manhã estavam
# 1 grau». Рамка писала множественное буквой, и правота её держалась тем, что утро редко
# бывает ровно в один градус.
#
# ТАБЛИЦА ОБЪЯВЛЕНА ЗДЕСЬ, А НЕ УГАДАНА ПО СТРОКЕ, и это цена первой редакции меры: она искала
# «ist ЧИСЛО ИМЯ» и назвала ложью 369 честных немецких строк — «Felix ist 4 Jahre alt», где
# связка согласуется с ФЕЛИКСОМ, а не с четырьмя.
#
#     СВЯЗКА СОГЛАСУЕТСЯ СО СВОИМ ПОДЛЕЖАЩИМ, А НЕ С БЛИЖАЙШИМ ЧИСЛОМ. Мера, читающая
#     соседство вместо подлежащего, находит ложь там, где стои́т язык.
#
# Оттого судятся лишь обороты бытия, где подлежащим стои́т само число: «there are N», «es sind
# N», «c'erano N», «er liggen N». Язык, чей оборот бытия связки не гнёт («il y a», «hay»,
# «há», «было»), в таблицу не внесён — ему нечего нарушать.
#
# ГНЁТСЯ ПО МОДУЛЮ: «minus ein Grad» единственно, «meno 3 gradi» множественно, — как и
# счётная форма имени рядом.
БЫТИЕ = {
    "en": (("there is", "there are"), ("there was", "there were")),
    "de": (("es ist", "es sind"), ("war es", "waren es"), ("es war", "es waren")),
    "nl": (("er ligt", "er liggen"), ("er is", "er zijn"), ("er zit", "er zitten"),
           ("er was", "er waren")),
    "it": (("c'è", "ci sono"), ("c'era", "c'erano")),
    "pt": (("estava", "estavam"), ("está", "estão")),
    "es": (("estaba", "estaban"),),
}
_ЧИСЛО_ПОСЛЕ = {}
for _я, _пары in БЫТИЕ.items():
    for _ед, _мн in _пары:
        for _ф, _единственно in ((_ед, True), (_мн, False)):
            # ГРАНИЦА СЛЕВА ОБЯЗАТЕЛЬНА: без неё «er is» находилось внутри «warmer is»,
            # «chapter is», «number is» — сто семь честных строк шести миров звались ложью.
            _ЧИСЛО_ПОСЛЕ[(_я, _ф)] = (
                re.compile(r"(?<![\w'])" + re.escape(_ф) + r" (−?\d+)(?= )"), _единственно)


def _цел(с):
    return int(с.replace("−", "-"))


def обвинения_бытия(строка):
    """[(язык, связка, число)] — обороты бытия строки, стоящие не по числу своего подлежащего."""
    вон = []
    for (язык, форма), (образ, единственно) in _ЧИСЛО_ПОСЛЕ.items():
        for м in образ.finditer(строка):
            n = abs(_цел(м.group(1)))
            if (n == 1) != единственно:
                вон.append((язык, форма, n))
    return вон


обвинения = plgram.обвинения
_ГРУППЫ = plgram.ГРУППЫ_СВЯЗКИ
_ВСЕ_СВЯЗКИ = sorted({ф for г in _ГРУППЫ for ф in г}, key=lambda с: (-len(с), с))
_ПАРА = plgram._ТРОЙКА
_ВРЕМЯ = plgram._ВРЕМЯ_ФОРМЫ
_ПО_ФОРМЕ = plgram._ФОРМА_ПОЛОСЫ


def дома():
    """Всякий дом с показами и своим судом — найден делом, а не списком."""
    вон = []
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        if путь.stem.startswith("gen_"):
            continue
        try:
            дом = importlib.import_module(путь.stem)
        except Exception:                 # noqa: BLE001
            continue
        показы = getattr(дом, "ПОКАЗЫ", None)
        судить = getattr(дом, "судить", None)
        if isinstance(показы, dict) and показы and callable(судить):
            вон.append((путь.stem, дом))
    return вон


def подмена(строка):
    """Строка с ОДНОЙ связкой, подменённой на иную ЕЁ ЖЕ времени, — или None.

    ПОДМЕНЯЕТСЯ ЛИШЬ СВЯЗКА, СТОЯЩАЯ ПЕРЕД ЧИСЛОМ И ОБЪЯВЛЕННОЙ ВЕЩЬЮ, — то есть ровно там,
    где закон этого прибора её и судит. Первая редакция портила ВСЯКОЕ «jest» строки и
    насчитала тридцать два слепых дома: «jaka liczba są po 1?», «co są cięższe: kamień czy
    pióro?» — порча настоящая, но НЕ ЭТОГО ЗАКОНА: связка там не согласуется ни с каким
    числом, и молчание дома о ней есть долг соседа (`word_mutants`), а не этого прибора.

        МЕРА, ПОРТЯЩАЯ ШИРЕ СВОЕГО ЗАКОНА, СЧИТАЕТ ЧУЖОЙ ДОЛГ СВОИМ И НАЗЫВАЕТ ЕГО СВОИМ
        ЧИСЛОМ. Тридцать два слепых дома были верным замером неверного вопроса.
    """
    for м in _ПАРА.finditer(строка):
        связка, число, слово = м.group(1), м.group(2), м.group(3)
        if слово not in _ПО_ФОРМЕ:
            continue
        n = int(число)
        и = plgram.индекс(n)
        if not any(полоса == и for полоса, _род in _ПО_ФОРМЕ[слово]):
            continue
        время = _ВРЕМЯ[связка]
        for иная in sorted({ф for г in _ГРУППЫ if связка in г for ф in г}):
            if иная == связка or _ВРЕМЯ.get(иная) != время:
                continue
            битая = строка[:м.start(1)] + иная + строка[м.end(1):]
            if not обвинения(битая):
                continue      # подмена, случайно давшая верную связку, не есть порча
            return битая
    return None


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--дом", default=None, help="проверить один дом")
    дов = ап.parse_args()

    # ЭТАЖ ПЕРВЫЙ: что написано на страницах свода
    ложных, по_мирам, примеры = 0, collections.Counter(), {}
    миры = sorted((КОРЕНЬ / "datasets").glob("genesis_*.txt"))
    for мир in миры:
        for строка in мир.read_text(encoding="utf-8", errors="replace").splitlines():
            for связка, n, слово, ждём in обвинения(строка):
                ложных += 1
                по_мирам[мир.name] += 1
                примеры.setdefault(мир.name, (строка[:90], f"«{связка} {n} {слово}» ждём «{ждём}»"))
    бытия, по_бытию, прим_бытия = 0, collections.Counter(), {}
    for мир in миры:
        for строка in мир.read_text(encoding="utf-8", errors="replace").splitlines():
            for язык, форма, n in обвинения_бытия(строка):
                бытия += 1
                по_бытию[(мир.name, язык, форма)] += 1
                прим_бытия.setdefault((мир.name, язык, форма), строка[:90])
    print(f"СТРАНИЦЫ: миров {len(миры)}, связок не по полосе {ложных}, "
          f"оборотов бытия не по числу {бытия}")
    for (мир, язык, форма), n in по_бытию.most_common():
        print(f"  БЫТИЕ {мир} [{язык}] «{форма}» ×{n}\n       «{прим_бытия[(мир, язык, форма)]}»")
    for мир, n in по_мирам.most_common():
        строка, чего = примеры[мир]
        print(f"  ЛОЖЬ {мир} ×{n}: {чего}\n       «{строка}»")

    # ЭТАЖ ВТОРОЙ: видит ли суд дома подмену своей связки
    список = [(и, д) for и, д in дома() if дов.дом is None or и == дов.дом]
    if not список:
        print(f"СВЯЗКА ПО ПОЛОСЕ ОТКАЗ: домов не найдено{f' ({дов.дом})' if дов.дом else ''}")
        return 2
    слепые, всего_проб, всего_немых, всего_поймано = [], 0, 0, 0
    print(f"{'дом':<20}{'проб':>6}{'поймано':>9}{'НЕМЫХ':>7}")
    for имя, дом in список:
        проб = немых = поймано = 0
        первая = None
        for показ in дом.ПОКАЗЫ:
            if проб >= ОБРАЗЦОВ:
                break
            битая = подмена(показ)
            if битая is None or битая == показ:
                continue
            try:
                судимо, истинно = дом.судить(битая)[:2]
            except Exception:             # noqa: BLE001
                continue
            проб += 1
            if not судимо:
                немых += 1
                первая = первая or битая
            elif not истинно:
                поймано += 1
        if not проб:
            continue
        всего_проб += проб; всего_немых += немых; всего_поймано += поймано
        print(f"{имя:<20}{проб:>6}{поймано:>9}{немых if немых else '—':>7}")
        if немых:
            слепые.append((имя, немых, проб, первая))
    print(f"{'ИТОГО':<20}{всего_проб:>6}{всего_поймано:>9}{всего_немых:>7}")
    for имя, немых, проб, первая in слепые:
        print(f"  СЛЕПОЙ [{имя}] {немых} из {проб}: «{первая[:100]}»")
    if дов.подробно:
        print(f"  связок объявлено: {_ВСЕ_СВЯЗКИ}; лемм с родом: {len(plgram.РОД)}")

    поза = ("PASS" if ложных <= ЛОЖНЫХ_РУБЕЖ and len(слепые) <= НЕМЫХ_РУБЕЖ
            and бытия <= БЫТИЯ_РУБЕЖ else "FAIL")
    print(f"СВЯЗКА ПО ПОЛОСЕ {поза}: страниц со связкой не по полосе {ложных} "
          f"(рубеж {ЛОЖНЫХ_РУБЕЖ}); оборотов бытия не по числу {бытия} (рубеж {БЫТИЯ_РУБЕЖ}); "
          f"домов, немеющих на подмене связки, {len(слепые)} "
          f"(рубеж {НЕМЫХ_РУБЕЖ}); проб {всего_проб}, поймано {всего_поймано}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
