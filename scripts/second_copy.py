# ПУСТОЙ-ОБХОД: --корень /no/such/root
import ast
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import rugram  # noqa: E402 — первая копия, с которой сверяются все прочие

# РУБЕЖ-ДОЛГА: КОПИЙ_РУБЕЖ = 0
#
# Рубеж есть ПОЛ, а не поблажка: замер 12.09 нашёл три совпавших копии, из них одна была
# привязана утверждением, а две сняты в тот же час. Прибор поставлен, чтобы четвёртая
# нашлась прежде, чем разойдётся.
КОПИЙ_РУБЕЖ = 0

ДВОРЫ = ("tools", "courts", "scripts")
# ФАЙЛ ПЕРВОЙ КОПИИ СЕБЯ НЕ СУДИТ: он и есть объявление.
СВОИ = frozenset({"rugram.py"})


def копии(корень):
    """[(файл, слово, тройка, привязана)] — клетки, дословно повторяющие пакет."""
    вон = []
    for двор in ДВОРЫ:
        for п in sorted((корень / двор).glob("*.py")):
            if п.name in СВОИ:
                continue
            try:
                тело = п.read_text(encoding="utf-8")
                дерево = ast.parse(тело)
            except (OSError, SyntaxError):
                continue
            # ПРИВЯЗКА ИЩЕТСЯ В ТОМ ЖЕ ФАЙЛЕ: утверждение, называющее пакет.
            привязан = any(
                isinstance(у, ast.Assert) and "rugram" in ast.dump(у.test)
                for у in ast.walk(дерево))
            for узел in ast.walk(дерево):
                if not isinstance(узел, ast.Dict):
                    continue
                for кл, зн in zip(узел.keys, узел.values):
                    if not (isinstance(кл, ast.Constant) and isinstance(кл.value, str)):
                        continue
                    if not isinstance(зн, (ast.Tuple, ast.List)) or len(зн.elts) != 3:
                        continue
                    if not all(isinstance(э, ast.Constant) and isinstance(э.value, str)
                               for э in зн.elts):
                        continue
                    свои = tuple(э.value for э in зн.elts)
                    пакет = rugram.СЧЁТНЫЕ.get(кл.value)
                    # СУДИМА ЛИШЬ ДОСЛОВНАЯ КОПИЯ: расхождение может быть иной таблицей.
                    if пакет is not None and свои == пакет:
                        вон.append((п.name, кл.value, свои, привязан))
    return вон


def main():
    корень = КОРЕНЬ
    if "--корень" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--корень") + 1])
    if not корень.is_dir():
        print(f"ВТОРАЯ КОПИЯ ОТКАЗ: корня нет — {корень}")
        return 2
    if not any((корень / д).is_dir() for д in ДВОРЫ):
        print(f"ВТОРАЯ КОПИЯ ОТКАЗ: дворов нет в {корень}")
        return 2
    подробно = "--подробно" in sys.argv
    все = копии(корень)
    голые = [(ф, с, т) for ф, с, т, п in все if not п]
    привязанные = [(ф, с) for ф, с, т, п in все if п]
    if подробно:
        for ф, с in привязанные:
            print(f"  привязана утверждением: {ф} «{с}» — законный приём, долгом не числится")
    for ф, с, т in голые[:8]:
        print(f"  ВТОРАЯ КОПИЯ «{ф}»: слово «{с}» объявлено {т} — та же таблица, что в "
              f"пакете, и ничто не держит их вместе")
    поза = "PASS" if len(голые) <= КОПИЙ_РУБЕЖ else "FAIL"
    print(f"ВТОРАЯ КОПИЯ {поза}: копий без привязки {len(голые)} (рубеж {КОПИЙ_РУБЕЖ}); "
          f"привязанных утверждением {len(привязанные)}, слов в пакете "
          f"{len(rugram.СЧЁТНЫЕ)}, дворов {len(ДВОРЫ)}")
    return 0 if len(голые) <= КОПИЙ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
