# ЧИСЛО ОБЪЯВЛЕНО ПОСЛЕ ЗАМЕРА И ПОСЛЕ ПОЧИНКИ ЗЕРНА, а не до. Прежде здесь стоял
# `None`, и стоял ПРАВИЛЬНО: зерно выборки бралось от `hash()` строки, гуляло на
# двадцать процентов между процессами, и рубежом такое число быть не могло (см.
# докстринг `равномерно`). Причина, однако, названа не была, и `None` жил немым
# симптомом. Ныне причина названа, зерно взято `zlib.crc32`, и РАВЕНСТВО ДОКАЗАНО
# ДВУМЯ ПОЛНЫМИ ПРОГОНАМИ ПОДРЯД: проб 4570, ПОЙМАН 3959, ОНЕМЕЛ 379, НЕ ПОЙМАН 232,
# миров с дырой 64 — знак в знак, при неизменной подписи манифеста.
#
# СТЕРЕЖЁТСЯ «НЕ ПОЙМАН», А НЕ «МИРОВ С ДЫРОЙ»: число миров равняет indu (12 дыр из
# 23) с geometry (6 из 24), а меряется здесь ЛОЖЬ, КОТОРАЯ ПРОШЛА БЫ ВОРОТА, и её
# счёт есть счёт строк. Довод соседа (`sign_traps`: «долг ведётся числом домов, ибо
# проб тем больше, чем больше дом») здесь не работает: БЮДЖЕТ ПРОБ ФИКСИРОВАН НА МИР
# (ПРОБ_НА_МИР = 12), и число не растёт от роста мира — только от прихода нового.
#
# НОВЫЙ МИР С ДЫРОЙ РОНЯЕТ ПРИБОР, И ТАК ЗАДУМАНО: дом, чей суд подписывает слова, не
# читая их, есть новый долг в тот же час, когда его напишут.
#
# КУДА ЭТОМУ ЧИСЛУ ПАДАТЬ, БЫЛО НАЗВАНО ДЕЛОМ, И В ТОТ ЖЕ ЧАС ОНО УПАЛО. Перепись
# 06.09 нашла, что из 38 миров с дырой замкнутыми объявлены ТРИ; сорок четыре суда
# получили объявление, проверенное по КАЖДОЙ строке своего мира, и замер дал:
#
#     232 → 151 (миров с дырой 64 → 43; ПОЙМАН 86 % → 93 %; ОНЕМЕЛ 379 → 143)
#
# ДОЛГ, РАЗ ОБЪЯВЛЕННЫЙ, ОПУСКАЕТСЯ ДО ДОСТИГНУТОГО В ТОТ ЖЕ ЧАС — иначе он
# перестаёт быть долгом и становится запасом (закон соседа `prose_court`).
#
# ЧТО ОСТАЛОСЬ — ИНАЯ БОЛЕЗНЬ, И ОНА НАЗВАНА. Замыкание лечит МОЛЧАНИЕ; оставшиеся
# 151 суть положительная ИСТИНА о непрочитанном: суд читает своё и подписывает
# прочее («wha is (1, 2) − (3, 1)?» — суд вектора судит и зовёт истиной). Их меряет
# `verdict_cover`, и лечит не объявление, а ФОРМА ЧТЕНИЯ.
# 151 → 147: три отложенных случая закрыты вторым ходом обёртки (`замкнуть_слоем`) —
# engram пятью мирами, episode миром «items», speech своим. Остались arith и logic:
# палата зовёт их ОСОБО, и обёртка до них не доходит.
#
# 147 → 130 БЕЗ ЕДИНОЙ ПРАВКИ СУДА: закрыты два лица дыры в ОБЩЕМ ДОМЕ `tools/asking.py`
# — зачин вопроса искался ПОДСТРОКОЙ (двухбуквенные «ли», «де», «que», «τι» находились
# внутри «буДЕт», «веЛИчина») и запятая внутри вектора «(1, 2)» делала клаузу
# «предметом», отворяя правило «зачин стои́т где угодно». Семнадцать подмен слова,
# проходивших воротами, теперь ловятся законом пары, а не судом.
#
#     ДЫРА В ОБЩЕМ ДОМЕ СТОИТ ШЕСТИДЕСЯТИ ДЫР В ДОМАХ ЧАСТНЫХ: её видно лишь
#     прибором, что мерит палату целиком, и лечится она в одном месте.
# 130 → 138 → 124. Число ВЫРОСЛО и было записано выросшим, прежде чем упало: закон
# остатка (06.09) научил суд арифметики читать ОТВЕТ строки — и восемь строк, прежде
# становившихся при порче НЕСУДИМЫМИ, стали ИСТИННЫМИ. «кратн ли 7 числу 3? нет: 7 =
# 3 × 2 + 1, остаток 1.» проходила ворота, ибо ответ читался, а вопрос — нет.
#
#     ВСЯКИЙ ЗАКОН, ЧИТАЮЩИЙ ЧАСТЬ СТРОКИ, ЕСТЬ ВЫИГРЫШ ДЛЯ МЕРЫ И ПРОИГРЫШ ДЛЯ ВОРОТ,
#     ПОКУДА ПОКРЫТИЕ ТОЛЬКО МЕРЯЕТ, А НЕ ЗАПРЕЩАЕТ.
#
# Запрет посажен в палате (`panel.судить`: вердикт ИСТИНА невозможен, покуда хоть одно
# предложение строки не покрыто), и число упало до 124 — ниже прежнего рубежа.
#
# ЧЕГО ЗАПРЕТ НЕ ЛЕЧИТ, И ЭТО НАЗВАНО: порчу СЛОВА ВОПРОСА. Порченый вопрос остаётся
# вопросной половиной объявленной пары и покрыт правилом (б); пара проверяет ВЕЛИЧИНЫ
# вопроса и их порядок, а СЛОВА вопроса не читает никто. Снятие поблажки стои́т 172
# честных строк из 12 155 в одиннадцати мирах — то есть слова вопроса не читаются В
# КОРПУСЕ ВООБЩЕ, и лечит это суд формы вопроса, а не запрет.
# 124 → 107: ПЯТОЕ ЛИЦО ПОКРЫТИЯ — ЗАМКНУТЫЙ СЛОВАРЬ ВОПРОСА. Поблажка вопросу (правило
# «б» закона покрытия) сужена словарём мира: вопрос покрыт лишь тогда, когда все его
# слова суть слова ЭТОГО мира. Цена — НОЛЬ (проб 4568 до и после), ОНЕМЕЛ 146 → 163:
# ровно те строки, за которые палата больше не ручается.
#
# ПРЕДЕЛ ЗАКОНА НАЗВАН ЧИСЛОМ: четыре порчи из семидесяти проходят мимо, ибо дают
# слово, которое В СЛОВАРЕ МИРА ЕСТЬ («ist» → «is» в многоязычном `indu`, где «is»
# стои́т в голландских строках). Замкнутый мир замкнут по СЛОВАРЮ, а не по языку.
НЕ_ПОЙМАНО_РУБЕЖ = 107

ПРОБ_НА_МИР = 12
СЛОВО = re.compile(r"(?<![\w-])[^\W\d_]{3,}(?![\w-])")
# латиница ↔ кириллица: буквы, неотличимые глазом
ДВОЙНИКИ = {"a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х",
            "y": "у", "а": "a", "с": "c", "е": "e", "о": "o", "р": "p",
            "х": "x", "у": "y"}
def зерно_мира(имя):
    """Зерно мира — от ИМЕНИ, одинаково во всяком процессе (см. `равномерно`)."""
    return zlib.crc32(имя.encode("utf-8"))


ПОЙМАН, ОНЕМЕЛ, НЕ_ПОЙМАН = "ПОЙМАН", "ОНЕМЕЛ", "НЕ ПОЙМАН"


def манифест(путь):
    return json.loads(путь.read_text(encoding="utf-8")) if путь.exists() else None


def _файл(мир, внешний):
    п = КОРЕНЬ / мир["file"]
    if п.exists():
        return п
    if внешний:
        п = (КОРЕНЬ / внешний / мир["file"]).resolve()
        if п.exists():
            return п
    return None


def обрезание(строка):
    m = СЛОВО.search(строка)
    if not m:
        return None
    с = m.group()
    return строка[:m.start()] + с[:-1] + строка[m.end():], m.start()


def двойник(строка):
    m = СЛОВО.search(строка)
    if not m:
        return None
    с = m.group()
    for i, б in enumerate(с):
        if б in ДВОЙНИКИ:
            return (строка[:m.start()] + с[:i] + ДВОЙНИКИ[б] + с[i + 1:]
                    + строка[m.end():], m.start() + i)
    return None


def равномерно(строки, n, зерно):
    """n строк, взятых РАВНОМЕРНО по файлу, а не с его начала.

    Первые строки мира однородны — узкая выборка первых четырёхсот
    дала «68 %» там, где равномерная дала 91 %. Выборка объявлена
    зерном, и прогон воспроизводим.

    ЗЕРНО ОБЯЗАНО БЫТЬ ЗЕРНОМ, А НЕ ЧАСАМИ ЗАПУСКА (шрам 06.09). Здесь
    стояло `hash(мир["name"]) & 0xffff`, а `hash()` от строки в Python
    СОЛИТСЯ НА КАЖДЫЙ ПРОЦЕСС: `hash("indu")` дал 63262, 42853 и 48854
    в трёх запусках подряд, и прибор всякий раз мерил ДРУГУЮ выборку.
    Два прогона одного часа по одному своду дали НЕ ПОЙМАН 230 и 193 —
    разброс в двадцать процентов, названный одним числом.

        ПРИБОР, ОБЪЯВИВШИЙ ВОСПРОИЗВОДИМОСТЬ И ВЗЯВШИЙ ЗЕРНО ОТ СОЛИ
        ПРОЦЕССА, ЛЖЁТ О СЕБЕ ГРОМЧЕ, ЧЕМ О КОРПУСЕ: его число нельзя
        ни сравнить со вчерашним, ни поставить рубежом.

    Оттого рубеж здесь и стоял `None`: рука, ставившая прибор, честно
    не смела назвать гуляющее число долгом — но причины не назвала, и
    причина осталась жить. Зерно взято `zlib.crc32`: та же величина в
    любом процессе и любой версии, и ОДНО МЕСТО НА КОРПУС — проверено
    обходом всех `scripts/ courts/ tools/`, других `hash()` в мере нет.
    """
    if len(строки) <= n:
        return строки
    шаг = len(строки) / n
    р = random.Random(зерно)
    return [строки[min(len(строки) - 1, int(i * шаг + р.random() * шаг))]
            for i in range(n)]


def main():
    путь = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    if "--manifest" in sys.argv:
        путь = pathlib.Path(sys.argv[sys.argv.index("--manifest") + 1])
    м = манифест(путь)
    if not м:
        print(f"ПОДСАДКА СЛОВОМ ОТКАЗ: манифеста «{путь}» нет")
        return 2
    внешний = м.get("external_root")
    палата = panel.Палата()
    итог = collections.Counter()
    по_мирам = []
    примеры = []
    без_слов = 0
    for мир in м["worlds"]:
        if мир.get("text") != "shows":
            continue
        п = _файл(мир, внешний)
        if п is None:
            continue
        слои = палата.слои(п)
        пласт = палата.пласт_файла(п)
        строки = [с.strip() for с in
                  п.read_text(encoding="utf-8", errors="replace").splitlines()
                  if с.strip()]
        годные = [с for с in строки if СЛОВО.search(с)]
        без_слов += len(строки) - len(годные)
        счёт = collections.Counter()
        for честно in равномерно(годные, ПРОБ_НА_МИР, зерно_мира(мир["name"])):
            судимо, истинно, _ = палата.судить(честно, слои, пласт)
            if not (судимо and истинно):
                continue  # близнец обязан быть истинным ИЗ КОРПУСА
            for род, порча_ф in (("обрезание", обрезание), ("двойник", двойник)):
                если = порча_ф(честно)
                if если is None:
                    continue
                порча, _ = если
                с, и, кем = палата.судить(порча, слои, пласт)
                исход = ПОЙМАН if (с and not и) else (ОНЕМЕЛ if not с else НЕ_ПОЙМАН)
                счёт[(род, исход)] += 1
                итог[(род, исход)] += 1
                if исход == НЕ_ПОЙМАН and len(примеры) < 8:
                    примеры.append((мир["name"], честно[:60], порча[:60], кем))
        не = sum(v for (р, и), v in счёт.items() if и == НЕ_ПОЙМАН)
        if не:
            по_мирам.append((мир["name"], не, sum(счёт.values())))
    if not итог:
        print("ПОДСАДКА СЛОВОМ ОТКАЗ: ни одной пробы — миров показов нет")
        return 2
    for имя, честно, порча, кем in примеры:
        print(f"  НЕ ПОЙМАН [{имя}] «{честно}» → «{порча}» {кем}")
    по_мирам.sort(key=lambda х: -х[1])
    print("  ХУДШИЕ МИРЫ: " + ", ".join(f"{и} {н}/{в}" for и, н, в in по_мирам[:10]))
    всего = sum(итог.values())
    не_пойм = sum(v for (р, и), v in итог.items() if и == НЕ_ПОЙМАН)
    пойм = sum(v for (р, и), v in итог.items() if и == ПОЙМАН)
    онем = sum(v for (р, и), v in итог.items() if и == ОНЕМЕЛ)
    поза = ("ОТЧЁТ" if НЕ_ПОЙМАНО_РУБЕЖ is None else
            "PASS" if не_пойм <= НЕ_ПОЙМАНО_РУБЕЖ else "FAIL")
    print(f"ПОДСАДКА СЛОВОМ {поза}: проб {всего} — ПОЙМАН {пойм} "
          f"({100 * пойм // всего}%), ОНЕМЕЛ {онем} ({100 * онем // всего}%), "
          f"НЕ ПОЙМАН {не_пойм} ({100 * не_пойм // всего}%); строк без слова "
          f"{без_слов}; миров с дырой {len(по_мирам)}")
    if НЕ_ПОЙМАНО_РУБЕЖ is None:
        return 0
    return 0 if не_пойм <= НЕ_ПОЙМАНО_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
