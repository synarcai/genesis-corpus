#!/usr/bin/env python3
"""[ПОДСАДКА СЛОВОМ] — читают ли суды слова, или слова у них декорация.

ПОДСАДКА ЧИСЛОМ НЕ ВИДИТ ЛЖИ В СЛОВЕ. Прибор мутантов судов
(`court_mutants.py`) портит ЧИСЛО и честно объявляет границу: шестьдесят
процентов строк свода чисел не несут. Здесь портится СЛОВО — и оказалось,
что это иной род лжи, невидимый первой пробе.

ЧТО НАШЛА ПЕРВАЯ ПРОБА (соседняя рука, 02.09; прибор жил в скретчпаде и
умер с сессией — потому он здесь заново, в камне):

    ПЛАСТЫ ЯЗЫКА:  ловят 91–98 % подсадок в слово
    МИРЫ ПОКАЗОВ:  ловят 5 %; 70 % онемели; 24 % зовут порчу ИСТИНОЙ

    «давление = сила ÷ площадь; 42 ньютона ÷ 6 квадратных метров = 7 паскалей»
    → «давлениE = …»: имя закона искажено, счёт цел, палата говорит истина.

СУДЫ ПОКАЗОВ ЧИТАЮТ ЧИСЛА, А СЛОВА У НИХ ДЕКОРАЦИЯ — и это надо мерить
постоянно, а не помнить как находку.

ДВА РОДА ПОРЧИ, ОБА ОБЪЯВЛЕНЫ:
  · ОБРЕЗАНИЕ — у первого слова от трёх букв снят последний знак
    («сумма» → «сумм»);
  · ДВОЙНИК — одна буква заменена НЕОТЛИЧИМОЙ буквой другого письма
    («сумма» → «cумма» с латинской «c»). Неприменим к письму без
    латинско-кириллических близнецов, и это честно считается.

ТРИ ИСХОДА, И ВТОРОЙ ЗДЕСЬ ЗНАЧИТ ИНОЕ, ЧЕМ ПРИ ПОРЧЕ ЧИСЛА:
    ПОЙМАН    — суд сказал «ложь»;
    ОНЕМЕЛ    — строка стала несудимой: для ВОРОТ ЗАПИСИ это защита
                (несудимое не входит), для уже написанного — слепота;
    НЕ ПОЙМАН — палата зовёт порченую строку ИСТИНОЙ. Это и есть дыра:
                такая ложь прошла бы ворота.

ГРАНИЦЫ ПРОБЫ, ЧИСЛОМ: строки без слова в три буквы (глифовые показы
«2 + 2 = 4») не проверяются ничем; проба меняет ОДНО слово и о порче
двух не говорит.
"""
import collections
import json
import pathlib
import random
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import panel  # noqa: E402

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest

# РУБЕЖ-ДОЛГА: объявится числом первого замера в камне.
НЕ_ПОЙМАНО_РУБЕЖ = None

ПРОБ_НА_МИР = 12
СЛОВО = re.compile(r"(?<![\w-])[^\W\d_]{3,}(?![\w-])")
# латиница ↔ кириллица: буквы, неотличимые глазом
ДВОЙНИКИ = {"a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х",
            "y": "у", "а": "a", "с": "c", "е": "e", "о": "o", "р": "p",
            "х": "x", "у": "y"}
ПОЙМАН, ОНЕМЕЛ, НЕ_ПОЙМАН = "ПОЙМАН", "ОНЕМЕЛ", "НЕ ПОЙМАН"


def манифест(путь):
    return json.loads(путь.read_text(encoding="utf-8")) if путь.exists() else None


def _файл(мир, внешний):
    п = КОРЕНЬ / мир["file"]
    if п.exists():
        return п
    if внешний:
        п = (КОРЕНЬ / внешний / мир["file"]).resolve()
        if п.exists():
            return п
    return None


def обрезание(строка):
    m = СЛОВО.search(строка)
    if not m:
        return None
    с = m.group()
    return строка[:m.start()] + с[:-1] + строка[m.end():], m.start()


def двойник(строка):
    m = СЛОВО.search(строка)
    if not m:
        return None
    с = m.group()
    for i, б in enumerate(с):
        if б in ДВОЙНИКИ:
            return (строка[:m.start()] + с[:i] + ДВОЙНИКИ[б] + с[i + 1:]
                    + строка[m.end():], m.start() + i)
    return None


def равномерно(строки, n, зерно):
    """n строк, взятых РАВНОМЕРНО по файлу, а не с его начала.

    Первые строки мира однородны — узкая выборка первых четырёхсот
    дала «68 %» там, где равномерная дала 91 %. Выборка объявлена
    зерном, и прогон воспроизводим.
    """
    if len(строки) <= n:
        return строки
    шаг = len(строки) / n
    р = random.Random(зерно)
    return [строки[min(len(строки) - 1, int(i * шаг + р.random() * шаг))]
            for i in range(n)]


def main():
    путь = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    if "--manifest" in sys.argv:
        путь = pathlib.Path(sys.argv[sys.argv.index("--manifest") + 1])
    м = манифест(путь)
    if not м:
        print(f"ПОДСАДКА СЛОВОМ ОТКАЗ: манифеста «{путь}» нет")
        return 2
    внешний = м.get("external_root")
    палата = panel.Палата()
    итог = collections.Counter()
    по_мирам = []
    примеры = []
    без_слов = 0
    for мир in м["worlds"]:
        if мир.get("text") != "shows":
            continue
        п = _файл(мир, внешний)
        if п is None:
            continue
        слои = палата.слои(п)
        пласт = палата.пласт_файла(п)
        строки = [с.strip() for с in
                  п.read_text(encoding="utf-8", errors="replace").splitlines()
                  if с.strip()]
        годные = [с for с in строки if СЛОВО.search(с)]
        без_слов += len(строки) - len(годные)
        счёт = collections.Counter()
        for честно in равномерно(годные, ПРОБ_НА_МИР, hash(мир["name"]) & 0xffff):
            судимо, истинно, _ = палата.судить(честно, слои, пласт)
            if not (судимо and истинно):
                continue  # близнец обязан быть истинным ИЗ КОРПУСА
            for род, порча_ф in (("обрезание", обрезание), ("двойник", двойник)):
                если = порча_ф(честно)
                if если is None:
                    continue
                порча, _ = если
                с, и, кем = палата.судить(порча, слои, пласт)
                исход = ПОЙМАН if (с and not и) else (ОНЕМЕЛ if not с else НЕ_ПОЙМАН)
                счёт[(род, исход)] += 1
                итог[(род, исход)] += 1
                if исход == НЕ_ПОЙМАН and len(примеры) < 8:
                    примеры.append((мир["name"], честно[:60], порча[:60], кем))
        не = sum(v for (р, и), v in счёт.items() if и == НЕ_ПОЙМАН)
        if не:
            по_мирам.append((мир["name"], не, sum(счёт.values())))
    if not итог:
        print("ПОДСАДКА СЛОВОМ ОТКАЗ: ни одной пробы — миров показов нет")
        return 2
    for имя, честно, порча, кем in примеры:
        print(f"  НЕ ПОЙМАН [{имя}] «{честно}» → «{порча}» {кем}")
    по_мирам.sort(key=lambda х: -х[1])
    print("  ХУДШИЕ МИРЫ: " + ", ".join(f"{и} {н}/{в}" for и, н, в in по_мирам[:10]))
    всего = sum(итог.values())
    не_пойм = sum(v for (р, и), v in итог.items() if и == НЕ_ПОЙМАН)
    пойм = sum(v for (р, и), v in итог.items() if и == ПОЙМАН)
    онем = sum(v for (р, и), v in итог.items() if и == ОНЕМЕЛ)
    поза = ("ОТЧЁТ" if НЕ_ПОЙМАНО_РУБЕЖ is None else
            "PASS" if не_пойм <= НЕ_ПОЙМАНО_РУБЕЖ else "FAIL")
    print(f"ПОДСАДКА СЛОВОМ {поза}: проб {всего} — ПОЙМАН {пойм} "
          f"({100 * пойм // всего}%), ОНЕМЕЛ {онем} ({100 * онем // всего}%), "
          f"НЕ ПОЙМАН {не_пойм} ({100 * не_пойм // всего}%); строк без слова "
          f"{без_слов}; миров с дырой {len(по_мирам)}")
    if НЕ_ПОЙМАНО_РУБЕЖ is None:
        return 0
    return 0 if не_пойм <= НЕ_ПОЙМАНО_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
