#!/usr/bin/env python3
"""[УКАЗАТЕЛЬ ЗАПИСЕЙ] — четвёртый указатель свода: летопись, собранная в оглавление.

    ЛЕТОПИСЬ БЕЗ ОГЛАВЛЕНИЯ ЕСТЬ ГРУДА ЛИСТОВ: ЧИТАТЕЛЬ НАЙДЁТ В НЕЙ ЛИШЬ ТО, ЧТО УЖЕ ЗНАЕТ.

ПОВОД, ЗАМЕРЕННЫЙ 12.09. Свод несёт сорок пять записей — дневные отчёты, переписи форм,
объявления, три указателя, — и на тридцать одну из них НЕ ССЫЛАЕТСЯ НИКТО: ни код, ни
README, ни соседние отчёты.

    ЗАПИСЬ, НА КОТОРУЮ НИКТО НЕ ССЫЛАЕТСЯ, ПОТЕРЯНА ВЕРНЕЕ, ЧЕМ УНИЧТОЖЕННАЯ: ОНА ЕСТЬ
    И НЕ ЧИТАЕТСЯ.

И это не порок самих записей: дневной лист не обязан ссылаться на вчерашний, а лист форм —
на позавчерашний. Летопись пишется вперёд, а читается назад, и связь её есть ОГЛАВЛЕНИЕ, а
не перекрёстные ссылки.

ЧТО СОБИРАЕТ УКАЗАТЕЛЬ. Заголовок первой строки, дату из имени файла, число разделов и
размер — всё ВЫЧИТАННОЕ из самих записей, ничего объявленного рукой.

    УКАЗАТЕЛЬ, ПИСАННЫЙ РУКОЮ, РАСХОДИТСЯ С ДЕЛОМ НА ПЕРВОЙ ЖЕ НОВОЙ ЗАПИСИ; УКАЗАТЕЛЬ,
    СОБРАННЫЙ ИЗ ДЕЛА, РАСХОДИТЬСЯ НЕ УМЕЕТ.

ЧЕГО ОН НЕ ДЕЛАЕТ. Он не судит: запись без ссылок — не долг, а свойство летописи. Он не
пересказывает содержания: пересказ стареет вместе с записью, а заголовок и число разделов
берутся заново при каждой сборке.

    python3 scripts/reports_index.py [--собрать]
"""
# ПУСТОЙ-ОБХОД: --корень /no/such/root
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ЦЕЛЬ = КОРЕНЬ / "reports" / "INDEX.md"
ДВОРЫ = ("reports", "declarations")
ДАТА = re.compile(r"(\d{4})-(\d{2})-(\d{2})|(\d{2})(\d{2})(?:\.md)?$")


def запись(п):
    """(заголовок, дата, разделов, байт) — вычитанное из файла, а не объявленное."""
    тело = п.read_text(encoding="utf-8", errors="replace")
    строки = тело.split("\n")
    заголовок = next((с.lstrip("# ").strip() for с in строки if с.startswith("# ")), п.stem)
    разделов = sum(1 for с in строки if с.startswith("## "))
    m = ДАТА.search(п.stem)
    дата = f"{m.group(1)}-{m.group(2)}-{m.group(3)}" if m and m.group(1) else ""
    return заголовок, дата, разделов, len(тело.encode("utf-8"))


def собрать(корень):
    строки = ["# УКАЗАТЕЛЬ ЗАПИСЕЙ СВОДА", "",
              "*Собран `scripts/reports_index.py` из самих записей. Заголовок, дата, число",
              "разделов и размер ВЫЧИТАНЫ, а не объявлены рукой; всякая сборка читает дерево",
              "заново.*", "",
              "    ЛЕТОПИСЬ БЕЗ ОГЛАВЛЕНИЯ ЕСТЬ ГРУДА ЛИСТОВ: ЧИТАТЕЛЬ НАЙДЁТ В НЕЙ ЛИШЬ",
              "    ТО, ЧТО УЖЕ ЗНАЕТ.", ""]
    всего = 0
    for двор in ДВОРЫ:
        п = корень / двор
        if not п.is_dir():
            continue
        файлы = sorted(п.glob("*.md"))
        if not файлы:
            continue
        строки += [f"## {двор} — {len(файлы)} записей", "",
                   "| запись | дата | разделов | байт | о чём |", "|---|---|---|---|---|"]
        for ф in файлы:
            if ф.resolve() == ЦЕЛЬ.resolve():
                continue
            заг, дата, разд, байт = запись(ф)
            всего += 1
            строки.append(f"| [`{ф.name}`]({ф.name if двор == 'reports' else '../' + двор + '/' + ф.name}) "
                          f"| {дата or '—'} | {разд or '—'} | {байт} | {заг[:96]} |")
        строки.append("")
    строки += ["", f"*Записей всего: {всего}.*"]
    return "\n".join(строки) + "\n"


def main():
    корень = КОРЕНЬ
    if "--корень" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--корень") + 1])
    if not корень.is_dir() or not any((корень / д).is_dir() for д in ДВОРЫ):
        print(f"УКАЗАТЕЛЬ ЗАПИСЕЙ ОТКАЗ: дворов записей нет в {корень}")
        return 2
    тело = собрать(корень)
    цель = корень / "reports" / "INDEX.md"
    было = цель.read_text(encoding="utf-8") if цель.is_file() else ""
    if "--собрать" in sys.argv:
        цель.write_text(тело, encoding="utf-8")
        print(f"УКАЗАТЕЛЬ ЗАПИСЕЙ СОБРАН: {цель.name}, строк {тело.count(chr(10))}")
        return 0
    строк_было = было.count("\n")
    строк_стало = тело.count("\n")
    if было != тело:
        print(f"  указатель на диске разошёлся с деревом: строк было {строк_было}, "
              f"стало бы {строк_стало}")
    поза = "PASS" if было == тело else "FAIL"
    print(f"УКАЗАТЕЛЬ ЗАПИСЕЙ {поза}: {0 if было == тело else 1} расхождений с деревом "
          f"(рубеж 0); записей {тело.count('| [`')}, дворов {len(ДВОРЫ)}")
    return 0 if было == тело else 1


if __name__ == "__main__":
    sys.exit(main())
