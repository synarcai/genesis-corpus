#!/usr/bin/env python3
"""СУД ПРОЗЫ: её не судят на полноту, но лгать она не смеет.

Двести двадцать две тысячи строк корпуса объявлены прозой — и ни одна
мера их не касалась. Судимость их пропускает намеренно и правильно:
прозаический свод есть связная речь, а не перечень проверяемых
утверждений, и требовать, чтобы КАЖДУЮ его строку читал какой-то суд,
значило бы требовать невозможного.

НО «НЕ СУДИТСЯ НА ПОЛНОТУ» НЕ ЕСТЬ «НЕ СУДИТСЯ ВОВСЕ». Проза говорит
теми же словами и теми же числами, что и показы; строка «2 + 2 = 5»
в ней так же ложна, как в любом мире. И потому здесь мерится не то,
СКОЛЬКО её прочитано, а то, НЕТ ЛИ ЛЖИ В ПРОЧИТАННОМ.

ТРИ ВОПРОСА, И КАЖДЫЙ СВОЙ:

    ЕСТЬ ЛИ ФАЙЛ — мир, чьего файла нет, есть обещание, а не мир.
    ТОТ ЛИ ЯЗЫК — имя мира несёт язык («diakrisis_ru»), и написанное
        обязано быть на нём. Первый же прогон этой меры нашёл ДВА мира,
        чьё имя говорит одно, а путь другое: `diakrisis_ru` указывал на
        `diakrisis_en.txt`, `mf_ru` — на `mf_en.txt`, и оба файла
        содержат РУССКИЙ. Имя мира было право, лгало имя файла — и
        никто не знал этого полтора месяца, потому что прозы не
        касалась ни одна мера. Род тот же, что нашли соседи в чужих
        каталогах: РОД ОБЪЯВЛЕН ОДНИМ, А СКАЗАН ДРУГИМ.
    НЕТ ЛИ ЛЖИ — палата судов проходит по строкам, и всякая, которую
        ХОТЬ ОДИН суд зовёт ложью, называется здесь поимённо. Молчание
        судов о прозе ожидаемо и не считается бедой; их ВОЗРАЖЕНИЕ —
        считается.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
for _где in (КОРЕНЬ / "tools", КОРЕНЬ / "courts", КОРЕНЬ / "scripts"):
    if str(_где) not in sys.path:
        sys.path.insert(0, str(_где))
import genesis  # noqa: E402
from panel import палата  # noqa: E402

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 0
РАЗЛАДОВ_РУБЕЖ = 0
# РУБЕЖ-ДОЛГА: ВОЗРАЖЕНИЙ_РУБЕЖ = 55
#
# ВОЗРАЖЕНИЕ СУДА ПРОЗЕ НЕ ЕСТЬ ВЕРДИКТ, И ЭТО НАДО СКАЗАТЬ ПРЯМО.
# Суды писались для ПОКАЗОВ, а показ УТВЕРЖДАЕТ. Проза цитирует,
# отрицает и предполагает: строка «"commutativity" proofs of 5 - 3 =
# 3 - 5 were rejected» говорит о ложном равенстве, а не утверждает
# его; «не страшно» есть оборот речи, а не оценка без основания;
# «в течение 24 часов» есть родительный ПО УПРАВЛЕНИЮ, а не сбой
# счёта. Объявить эти строки ложью значило бы судить жанр, а не текст.
#
# Потому число возражений объявлено ДОЛГОМ, а не ложью: расти ему
# нельзя, убывать можно, и всякий новый разбор, отделивший истинную
# беду от промаха суда, опускает рубеж. Первый прогон дал 107; сорок
# из них были ГОДАМИ, прочитанными как счёт («2035 год»), и это
# вылечено в самом суде согласования — год есть номер в ряду; после
# лечения осталось 55, и рубеж опущен до достигнутого. ДОЛГ, РАЗ
# ОБЪЯВЛЕННЫЙ, ОПУСКАЕТСЯ ДО ДОСТИГНУТОГО В ТОТ ЖЕ ЧАС — иначе он
# перестаёт быть долгом и становится запасом.
ВОЗРАЖЕНИЙ_РУБЕЖ = 55

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest

КИРИЛЛИЦА = re.compile(r"[а-яёА-ЯЁ]")
ЛАТИНИЦА = re.compile(r"[a-zA-Z]")
# язык, объявленный ХВОСТОМ ИМЕНИ мира; иные хвосты не о языке
ЯЗЫКИ = {"ru", "en"}


def язык_текста(текст):
    """Какое письмо преобладает — по счёту букв, а не по догадке."""
    кир, лат = len(КИРИЛЛИЦА.findall(текст)), len(ЛАТИНИЦА.findall(текст))
    if кир == лат == 0:
        return None
    return "ru" if кир > лат else "en"


def main():
    if "--manifest" in sys.argv:
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        миры = genesis.manifest()["worlds"]
    except genesis.Unreadable as беда:
        print(f"ПРОЗА ОТКАЗ: {беда}")
        return 2
    проза = [м for м in миры if м.get("text") == "prose"]
    if not проза:
        print("ПРОЗА ОТКАЗ: прозаических миров не объявлено")
        return 2
    суд = палата()
    разлады, строк, ложных, примеры = [], 0, 0, []
    чужие_имена = []
    for мир in проза:
        имя = мир.get("name", "?")
        путь = genesis._resolve(мир.get("file", ""))
        if not путь.is_file():
            разлады.append(f"{имя}: файла нет — {мир.get('file')}")
            continue
        текст = путь.read_text(encoding="utf-8", errors="replace")
        свои = sum(1 for с in текст.splitlines() if с.strip())
        строк += свои
        if not свои:
            разлады.append(f"{имя}: файл пуст")
            continue
        объявлен = имя.rsplit("_", 1)[-1]
        на_деле = язык_текста(текст)
        if объявлен in ЯЗЫКИ and на_деле and объявлен != на_деле:
            разлады.append(
                f"{имя}: имя обещает «{объявлен}», написано «{на_деле}»")
        по_файлу = путь.stem.split(".")[0].rsplit("_", 1)[-1]
        if по_файлу in ЯЗЫКИ and на_деле and по_файлу != на_деле:
            # ИМЯ ЧУЖОГО ФАЙЛА НЕ В МОЕЙ ВЛАСТИ, И ПОТОМУ ЭТО НЕ
            # РАЗЛАД, А ИЗВЕСТИЕ. Файлы прозы собираются другим сводом
            # в другом дереве; переименовать их отсюда значило бы
            # тронуть чужое. Сказать вслух — можно и должно.
            чужие_имена.append(
                f"{имя}: файл «{путь.name}» обещает «{по_файлу}», "
                f"написано «{на_деле}»")
        for строка, судимо, истинно, кем in суд.судить_файл(путь):
            if судимо and not истинно:
                ложных += 1
                if len(примеры) < 6:
                    примеры.append(f"{имя} [{','.join(кем)}]: "
                                   f"{строка.strip()[:78]}")
    for р in разлады[:8]:
        print(f"  РАЗЛАД {р}")
    for р in чужие_имена:
        print(f"  ЧУЖОЕ ИМЯ {р}")
    for п in примеры:
        print(f"  ЛОЖЬ {п}")
    плохо = (len(разлады) > РАЗЛАДОВ_РУБЕЖ
             or ложных > ВОЗРАЖЕНИЙ_РУБЕЖ)
    поза = "FAIL" if плохо else "PASS"
    print(f"ПРОЗА {поза}: {len(разлады)} разладов объявления "
          f"(рубеж {РАЗЛАДОВ_РУБЕЖ}) и {ложных} возражений судов "
          f"(рубеж {ВОЗРАЖЕНИЙ_РУБЕЖ}, долг, не ложь) — {len(проза)} "
          f"миров, {строк} строк, судов живых {суд.живых}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
