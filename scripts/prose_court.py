# неизвестных по двум крайним точкам дают ЦЕНУ ЗА СТРОКУ и ЦЕНУ ЗА БАЙТ порознь.
#
#     МИР ДОРОГ НЕ БАЙТАМИ, А СТРОКАМИ: палата из 212 судов зовётся НА КАЖДУЮ
#     СТРОКУ, и мир из четырёхсот тысяч коротких строк дороже мира вчетверо
#     большего, но в шесть тысяч длинных.
#
# Это и было причиной хвоста. Я думал, что суд прозы ждёт `esbe_nature_ru` — 38.8 МБ,
# самый большой файл свода. Замер сказал иное: esbe несёт 5892 строки и стои́т 2.8 мин,
# а `gutenberg_webster_1913` при 26 МБ несёт 400 919 строк и стои́т ДВАДЦАТЬ ДВЕ МИНУТЫ —
# один мир, одна задача, восемь рабочих из девяти простаивают. Вся проза — 77 минут
# работы; идеал на восьмерых — 9.6 мин, а дно срока при раздаче ПО МИРАМ — 21.8.
ЦЕНА_СТРОКИ = 0.00268   # с на строку — палата зовётся на каждую
ЦЕНА_БАЙТА = 9.86e-6    # с на байт — суды читают саму строку
ЦЕЛЬ_ЛОМТЯ = 120        # с — во столько метит один ломоть


def цена_мира(строк, байт):
    """Оценка секунд на мир — по замеренным ценам строки и байта."""
    return строк * ЦЕНА_СТРОКИ + байт * ЦЕНА_БАЙТА


def _ломти(мир, цель):
    """[(мир, начало, конец, оценка)] — мир, разрезанный по оценённой цене.

    Мир дешевле цели не режется вовсе: у всякого ломтя своя цена — палата строится
    заново, слои впитывают ЦЕЛЫЙ файл. У webster это 6 секунд на ломоть против
    двадцати двух минут работы, и одиннадцать ломтей окупаются вдесятеро; у мира
    в полминуты не окупились бы никогда.

        РЕЗАТЬ СТОИТ ЛИШЬ ТО, ЧТО ДОРОЖЕ САМОГО РАЗРЕЗА.

    Цена меряется по ЖИВЫМ строкам и их байтам — ровно по тем, что пойдут в суд.
    Файла нет или он пуст — один ломоть, и тот скажет о беде.
    """
    путь = genesis._resolve(мир.get("file", ""))
    if not путь.is_file():
        return [(мир, 0, None, 0.0)]
    строк = байт = 0
    try:
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for с in поток:
                if с.strip():
                    строк += 1
                    байт += len(с)
    except OSError:
        return [(мир, 0, None, 0.0)]
    цена = цена_мира(строк, байт)
    if not строк or not цель or цена <= цель:
        return [(мир, 0, None, цена)]
    частей = max(2, min(строк, int(цена // цель) + 1))
    шаг, остаток = divmod(строк, частей)
    вон, начало = [], 0
    for и in range(частей):
        конец = начало + шаг + (1 if и < остаток else 0)
        вон.append((мир, начало, конец, цена * (конец - начало) / строк))
        начало = конец
    return вон


def _судить_ломоть(задача):
    """One SLICE of one world in one process: (имя, начало, свои, прочтено, ложных, ...).

    ЛОМОТЬ, А НЕ МИР. Раздача по мирам не может быть быстрее самого длинного мира;
    раздача по ломтям может. Слои и пласт строятся по ЦЕЛОМУ файлу в каждом ломте
    (иначе эпизодные ставки и итоги увидели бы обрубок), судятся строки [начало, конец),
    и вердикт тот же до буквы — тот же закон резки, что у `panel._судить_кусок`.

    ПРОВЕРКИ О МИРЕ — ОДИН РАЗ. Язык, имя файла, «файла нет», «файл пуст» и счёт своих
    строк спрашиваются только у ПЕРВОГО ломтя: иначе мир, разрезанный на одиннадцать
    частей, одиннадцать раз объявил бы о себе одно и то же.

    ДОЛГ, НЕ НАЗЫВАЮЩИЙ СВОЕГО МЕСТА, НЕЛЕЧИМ. The instrument counted the objections and
    printed six of them: to learn WHICH court objects to WHICH world one had to run the
    whole palata by hand. The eighth field is that map — objections by (court, world), and
    the verdict prints the heaviest pairs, because a court that reads one foreign world
    wrongly is one boundary to name, and the number alone never says which.
    """
    мир, начало, конец = задача
    голова = начало == 0
    суд = _палата_рабочего()
    имя = мир.get("name", "?")
    путь = genesis._resolve(мир.get("file", ""))
    разлады, чужие_имена, примеры = [], [], []
    возражатели = collections.Counter()
    if not путь.is_file():
        беда = [f"{имя}: файла нет — {мир.get('file')}"] if голова else []
        return имя, начало, 0, 0, 0, примеры, беда, чужие_имена, возражатели
    строки = panel._живые_строки(путь)
    свои = len(строки) if голова else 0
    if not строки:
        беда = [f"{имя}: файл пуст"] if голова else []
        return имя, начало, 0, 0, 0, примеры, беда, чужие_имена, возражатели
    if голова:
        текст = путь.read_text(encoding="utf-8", errors="replace")
        объявлен = имя.rsplit("_", 1)[-1]
        на_деле = язык_текста(текст)
        if объявлен in ЯЗЫКИ and на_деле and объявлен != на_деле:
            разлады.append(f"{имя}: имя обещает «{объявлен}», написано «{на_деле}»")
        по_файлу = путь.stem.split(".")[0].rsplit("_", 1)[-1]
        if по_файлу in ЯЗЫКИ and на_деле and по_файлу != на_деле:
            чужие_имена.append(f"{имя}: файл «{путь.name}» обещает «{по_файлу}», написано «{на_деле}»")
    чужие_суды = set(суд.вне_подсудности("prose")) | {
        имя_с for имя_с, с in суд.суды.items()
        if getattr(с, "РОД_ТЕКСТА", None) == "prose"
        and any(hasattr(с, поле) for поле in ("ЛОЖНЫХ_РУБЕЖ", "РАЗЛАДОВ_РУБЕЖ"))}
    прочтено = ложных = 0
    слои = суд.слои(путь)
    пласт = суд.пласт_файла(путь)
    ломоть = ((с, *суд.судить(с, слои, пласт)) for с in строки[начало:конец])
    for строка, судимо, истинно, кем in ломоть:
        прочтено += bool(судимо)
        if судимо and not истинно:
            ложных += 1
            for к in кем:
                возражатели[(к, имя)] += 1
            подсудные = [к for к in кем if к not in чужие_суды]
            клеймо = "" if подсудные else " (вне подсудности)"
            if len(примеры) < 6:
                примеры.append(f"{имя} [{','.join(кем)}]{клеймо}: {строка.strip()[:70]}")
    return имя, начало, свои, прочтено, ложных, примеры, разлады, чужие_имена, возражатели

КИРИЛЛИЦА = re.compile(r"[а-яёА-ЯЁ]")
ЛАТИНИЦА = re.compile(r"[a-zA-Z]")
# язык, объявленный ХВОСТОМ ИМЕНИ мира; иные хвосты не о языке
ЯЗЫКИ = {"ru", "en"}


def язык_текста(текст):
    """Какое письмо преобладает — по счёту букв, а не по догадке."""
    кир, лат = len(КИРИЛЛИЦА.findall(текст)), len(ЛАТИНИЦА.findall(текст))
    if кир == лат == 0:
        return None
    return "ru" if кир > лат else "en"


def main():
    if "--manifest" in sys.argv:
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        миры = genesis.manifest()["worlds"]
    except genesis.Unreadable as беда:
        print(f"ПРОЗА ОТКАЗ: {беда}")
        return 2
    проза = [м for м in миры if м.get("text") == "prose"]
    if not проза:
        print("ПРОЗА ОТКАЗ: прозаических миров не объявлено")
        return 2
    jobs = int(sys.argv[sys.argv.index("--jobs") + 1]) if "--jobs" in sys.argv else max(1, (os.cpu_count() or 2) // 2)
    разлады, строк, ложных, примеры = [], 0, 0, []
    чужие_имена = []
    # ЗНАМЕНАТЕЛЬ ЕСТЬ ЧАСТЬ МЕРЫ. «Ноль возражений» без числа
    # ПРОЧТЁННЫХ строк говорит о мере, а не о предмете: мир uhm_en несёт
    # сорок семь тысяч строк, из которых судами прочитано ВОСЕМЬ, и его
    # ноль означает не чистоту, а непрочтённость. Мера, не называющая,
    # сколько она видела, обещает, а не свидетельствует.
    прочтено = 0
    по_мирам = []
    # ЛОМТИ, ДЛИННЫЕ ВПЕРЁД. Пул раздаёт задачи в порядке перечисления, и мир,
    # попавший в хвост, оставляет рабочих без дела. Потому список ломтей строится
    # плоским и сортируется ПО УБЫВАНИЮ ОЦЕНКИ — самый длинный уходит первым.
    #
    #     САМАЯ ДЛИННАЯ ЗАДАЧА ЕСТЬ ДНО СРОКА: раздача не может кончиться раньше,
    #     чем кончится её самая большая часть, сколько бы рабочих ни ждало.
    задачи, порядок = [], {}
    for место, м in enumerate(проза):
        порядок[м.get("name", "?")] = место
        задачи.extend(_ломти(м, ЦЕЛЬ_ЛОМТЯ if jobs > 1 else 0))
    задачи.sort(key=lambda з: -з[3])
    if jobs <= 1:
        итоги = [_судить_ломоть(з[:3]) for з in задачи]
    else:
        with concurrent.futures.ProcessPoolExecutor(max_workers=jobs) as пул:
            итоги = list(пул.map(_судить_ломоть, [з[:3] for з in задачи]))
    # СБОРКА В ПОРЯДКЕ МАНИФЕСТА И СТРОК: ломти вернулись в порядке раздачи,
    # а вердикт обязан читаться так же, как читался бы в один поток.
    итоги.sort(key=lambda и: (порядок.get(и[0], 10**9), и[1]))
    возражатели = collections.Counter()
    for имя, _нач, свои, свои_прочтено, свои_ложных, свои_примеры, свои_разлады, свои_чужие, свои_кем in итоги:
        возражатели.update(свои_кем)
        разлады += свои_разлады
        чужие_имена += свои_чужие
        прочтено += свои_прочтено
        ложных += свои_ложных
        for п in свои_примеры:
            if len(примеры) < 6:
                примеры.append(п)
        if свои:                      # счёт своих строк несёт ТОЛЬКО первый ломоть
            строк += свои
            по_мирам.append([имя, свои, свои_прочтено])
        elif по_мирам and по_мирам[-1][0] == имя:
            по_мирам[-1][2] += свои_прочтено
    суд = _палата_рабочего()
    for имя_м, всего_м, прочт_м in по_мирам:
        доля = 100 * прочт_м // всего_м if всего_м else 0
        print(f"  {имя_м:<16}{всего_м:>8} строк, прочтено "
              f"{прочт_м:>6} ({доля:>3}%)")
    if возражатели:
        по_судам = collections.Counter()
        for (суд_имя, мир_имя), к in возражатели.items():
            по_судам[суд_имя] += к
        print("  ВОЗРАЖЕНИЯ ПО СУДАМ: "
              + ", ".join(f"{с} {к}" for с, к in по_судам.most_common(8)))
        for (суд_имя, мир_имя), к in возражатели.most_common(10):
            print(f"    ДОЛГ {суд_имя:<16} {мир_имя:<16} {к:>6}")
    for р in разлады[:8]:
        print(f"  РАЗЛАД {р}")
    for р in чужие_имена:
        print(f"  ЧУЖОЕ ИМЯ {р}")
    for п in примеры:
        print(f"  ЛОЖЬ {п}")
    плохо = (len(разлады) > РАЗЛАДОВ_РУБЕЖ
             or ложных > ВОЗРАЖЕНИЙ_РУБЕЖ)
    поза = "FAIL" if плохо else "PASS"
    print(f"ПРОЗА {поза}: {len(разлады)} разладов объявления "
          f"(рубеж {РАЗЛАДОВ_РУБЕЖ}) и {ложных} возражений судов "
          f"(рубеж {ВОЗРАЖЕНИЙ_РУБЕЖ}, чтение вне подсудности) — "
          f"{len(проза)} миров, {строк} строк, прочтено {прочтено} "
          f"({100 * прочтено // строк if строк else 0}%), судов живых "
          f"{суд.живых}")
    return 1 if плохо else 0


