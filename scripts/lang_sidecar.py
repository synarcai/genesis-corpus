#!/usr/bin/env python3
"""[САЙДКАР ЯЗЫКОВ] — язык строки свода, ОБЪЯВЛЕННЫЙ, а не угаданный.

ПОВОД (14.09, просьба holon-f9). Рынок теряет роли и голоса на ОМОГРАФАХ: «er» живёт в
немецком и в нидерландском, «a» — во французском и португальском, «en» — во французском,
нидерландском и испанском, «and» бывает оператором и стыком. Читатель, у которого слово
одно, видит два разных слова как одно и покупает ложь; знай он ЯЗЫК строки — половина
омографов расходится до всякого разбора.

    ОМОГРАФ ЕСТЬ ДВА СЛОВА, У КОТОРЫХ ОДНА ЗАПИСЬ. Различить их можно лишь тем, что
    ЗАПИСИ НЕ ПРИНАДЛЕЖИТ, — языком строки, в которой она стои́т.

ЯЗЫК БЕРЁТСЯ ИЗ ОБЪЯВЛЕНИЯ, А НЕ ИЗ ДОГАДКИ ПО БУКВАМ. Угадывать язык по виду слова —
значит строить меру на том самом смешении, ради которого она делается. Три источника, и
все три суть ОБЪЯВЛЕНИЯ корпуса:

    дом    — 175 домов метят страницу парой «(язык, род)» в своём словаре `ПОКАЗЫ`.
             Это самый точный источник: он ПОСТРОЧНЫЙ и живёт в доме, строящем страницу.
    мир    — 207 миров объявляют `язык` в манифесте. Это объявление на мир целиком, и оно
             годится лишь там, где мир одноязычен по построению (проза).
    пакет  — 29 пластов языка лежат в `datasets/genesis_lang_XX.txt`, и путь этот СТРОИТ
             сам `langpack.py` из поля `lang` СВОЕГО пакета. Имя файла здесь не догадка, а
             запись объявления; и всё же мера не верит ему на слово — она открывает
             `tools/langpacks/XX.json` и берёт язык ОТТУДА, а при несовпадении молчит.
    ничей  — всё прочее НЕ НАЗЫВАЕТСЯ. Многоязычный мир, чей дом языка не метит, лучше
             оставить немым, чем назвать одним языком из девяти.

        ЛУЧШЕ НАЗВАТЬ МЕНЬШЕ И ВЕРНО, ЧЕМ БОЛЬШЕ И НАУГАД: мера, угадавшая язык, портит
        ровно тот замер, ради которого её звали.

СТОЛБЦЫ: номер строки файла (с единицы, пустые считаются), язык. Номера — ТЕ ЖЕ, что в
`GENESIS-FULL.genera.tsv`: два сайдкара кладутся рядом и читаются одним ключом.

    python3 scripts/lang_sidecar.py --собрать
"""
# ПУСТОЙ-ОБХОД: --собрать --свод /dev/null
import argparse
import collections
import hashlib
import importlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))

СВОД = КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
ВЫХОД = КОРЕНЬ / "datasets" / "GENESIS-FULL.langs.tsv"

# РУБЕЖ-ДОЛГА: ПОКРЫТО_РУБЕЖ = 73
#
# ДОЛЯ НАЗВАННОГО ЯЗЫКА — МЕРА ПОКРЫТИЯ, И ОНА ХОДИТ ТОЛЬКО ВВЕРХ. На день постройки язык
# назван у 63 % непустых строк свода (280 196 из 444 820), и языков названо 29.
#
# ПЕРВАЯ РЕДАКЦИЯ ДАЛА 39,2 % И БЫЛА КРАСНА ПРИ РУБЕЖЕ 40 — и это оказалось не поводом
# опустить рубеж, а поводом ДОЧИТАТЬ ИСТОЧНИКИ. Двадцать девять пластов языка —
# `genesis_lang_de`, `genesis_lang_es`, … — лежали неназванными, хотя путь каждого СТРОИТ
# сам `langpack.py` из поля `lang` своего пакета. Прибавив третий источник (и сверив его с
# пакетом, а не с именем файла), мера пришла к 63 %.
#
#     МЕРА, УПАВШАЯ НИЖЕ СВОЕГО РУБЕЖА, СПРАШИВАЕТ СНАЧАЛА СЕБЯ: ВСЁ ЛИ ОНА ПРОЧЛА. Опустить
#     рубеж под замер легко и всегда возможно; оттого это последнее, что делают, а не первое.
# ПОДНЯТ 63 → 64 (15.09), И ПОДНЯЛА ЕГО НЕ КОВКА, А ОБЪЯВЛЕНИЕ. Прибор щербатости назвал
# дома, чьи показы не несут языка; десять из них ОБЪЯВИЛИ свой язык строкою `ЯЗЫК` (шесть
# английских, четыре русских), а дом девяти языков донёс язык до словаря показов — и сайдкар
# назвал ещё 1796 строк, ничего нового не выковав.
#
#     ЯЗЫК, ИЗВЕСТНЫЙ ДОМУ И НЕ ЗАПИСАННЫЙ В ПОКАЗ, ЕСТЬ СТРОКА БЕЗ ЯЗЫКА ДЛЯ ВСЕГО КОРПУСА.
#     Покрытие этой меры и читаемость меры щербатости суть ОДНО ЧИСЛО, взятое с двух сторон.
# 63 → 66 ЗА ОДИН ВЕЧЕР, И НИ ОДНОЙ НОВОЙ СТРАНИЦЫ НЕ ВЫКОВАНО. Прибор щербатости назвал
# дома, чьи показы не несут языка; двадцать один дом ответил на это объявлением:
#
#   · десять сказали `ЯЗЫК` строкою (шесть английских, четыре русских);
#   · одиннадцать донесли язык до словаря показов — ninelang, календарь, сравнение, цепи на
#     двадцати девяти языках, геометрия, физика, деньги, простые числа, остатки, ряды,
#     статистика.
#
#     ТРИНАДЦАТЬ ТЫСЯЧ СТРОК СВОДА ПЕРЕСТАЛИ БЫТЬ БЕЗЪЯЗЫКИМИ ОТ ОДНОГО ТОГО, ЧТО ДОМА
#     СКАЗАЛИ ВСЛУХ ТО, ЧТО ЗНАЛИ. Ковка тут ни при чём: страницы стояли те же.
# 66 → 68 (тот же вечер): дом начертания проставил язык при каждой странице и ДОПИСАЛ
# английские близнецы двух родов, которых у него не было; один этот дом дал 10 692 названные
# строки. Мир его 5386 → 10 696 показов.
# 68 → 69: дом теории чисел и дом рядов проставили язык при каждой странице (+6584 строки).
# СТУПЕНЬ ЗАКОНОВ, общая десяткам домов, отдаёт теперь язык сама (`laws.ступень_с_языком`) —
# двадцать домов, гадающих об одном, дали бы двадцать разных ответов.
# 69 → 70: дом линейной алгебры проставил язык — и вместе с ним ОБЪЯВЛЕННУЮ ВНЕЯЗЫЧНОСТЬ.
# Запись «(1, 2) + (3, 1) = (4, 3).» не принадлежит языку, и знак «—» на месте языка есть
# такое же объявление, как имя языка: 494 страницы дома названы внеязычными ВСЛУХ.
#
#     МЕРА, НАЗЫВАЮЩАЯ ЯЗЫК У 70 % СВОДА, ОБЯЗАНА ЗНАТЬ И О СТРОКАХ, У КОТОРЫХ ЯЗЫКА НЕТ.
#     Иначе прочие 30 % суть смесь ненаписанного с неписьменным, и разделить их нечем.
# 70 → 71: дом быта (132 рамки помечены по своим же литералам), дом сравнения свойств и дом
# единиц времени. За сутки 63 % → 71 %, и почти всё это — не ковка, а ОБЪЯВЛЕНИЕ уже
# написанного.
# 71 → 72: дом частей слова (4627 показов на двадцати одном языке МАТЕРИАЛА и двух языках
# РЕЧИ) и дом формул. ЯЗЫК СТРАНИЦЫ ЕСТЬ ЯЗЫК ЕЁ ОБЁРТКИ, А НЕ ЕЁ МАТЕРИАЛА: пометь дом частей
# слова языком материала — и мера потребовала бы амхарского вопроса о венгерском слове.
# 72 → 73: дом поверхностей, где связка «будет» объявлена ЧЕРТОЙ РУССКОГО, а не пропуском
# ковки: «два плюс три БУДЕТ пять» — вторая связка языка, какой у английского нет.
ПОКРЫТО_РУБЕЖ = 73


def _язык_пласта():
    """{имя мира: язык} — для пластов `lang_XX`, СВЕРЕННЫХ с объявлением своего пакета.

    ПУТЬ ПЛАСТА СТРОИТ `langpack.py` ИЗ ПОЛЯ `lang` ПАКЕТА, и потому имя файла есть запись
    объявления, а не догадка о нём. Но мера не берёт имени на веру: она открывает пакет и
    спрашивает его самого. Пласт без пакета или с пакетом, объявившим ИНОЙ язык, остаётся
    неназванным — расхождение это работа, а не повод угадать.
    """
    import json                                           # noqa: PLC0415
    import genesis                                        # noqa: PLC0415
    вон = {}
    for м in genesis.manifest()["worlds"]:
        имя = pathlib.Path(м["file"]).stem
        if not имя.startswith("genesis_lang_"):
            continue
        код = имя[len("genesis_lang_"):]
        пакет = КОРЕНЬ / "tools" / "langpacks" / f"{код}.json"
        if not пакет.is_file():
            continue
        try:
            объявлен = json.loads(пакет.read_text(encoding="utf-8")).get("lang")
        except Exception:                                 # noqa: BLE001
            continue
        if объявлен == код:
            вон[м["name"]] = код
    return вон


def _язык_мира():
    """{имя мира: язык} — по ОБЪЯВЛЕНИЮ манифеста, и только для одноязычных по построению."""
    import genesis                                        # noqa: PLC0415
    вон = {}
    for м in genesis.manifest()["worlds"]:
        я = м.get("язык") or м.get("lang")
        if я:
            вон[м["name"]] = я
    return вон


def _язык_строки(двор):
    """{(мир, тело строки): язык} — по словарям `ПОКАЗЫ`, метящим страницу парой.

    ПРАВИЛО ДОПУСКА ФАЙЛА БЕРЁТСЯ У УКАЗАТЕЛЯ РОДОВ, а не пишется здесь второй раз.
    """
    import genus_atlas                                    # noqa: PLC0415
    кормит = genus_atlas.кормит(двор)
    вон = {}
    for п in sorted(pathlib.Path(двор).glob("*.py")):
        if not genus_atlas.дом_ли(п):
            continue
        try:
            м = importlib.import_module(п.stem)
        except Exception:                                 # noqa: BLE001
            continue
        показы = getattr(м, "ПОКАЗЫ", None)
        if not isinstance(показы, dict) or not показы:
            continue
        # ЯЗЫК СТОИТ ПЕРВЫМ ЧЛЕНОМ ПАРЫ ЛИШЬ ТАМ, ГДЕ РОД СТОИТ ВТОРЫМ. Дом, объявивший
        # `РОД_В_ПОКАЗЕ` иначе, кладёт в кортеж другое, и языка в нём нет.
        if getattr(м, "РОД_В_ПОКАЗЕ", 1) != 1:
            continue
        миры = [w for w in кормит.get(п.stem, ())]
        if not миры:
            continue
        for стр, знач in показы.items():
            if not (isinstance(знач, tuple) and len(знач) == 2):
                continue
            язык = знач[0]
            if not isinstance(язык, str) or not 2 <= len(язык) <= 3:
                continue
            ключ = стр.rstrip()
            for мир in миры:
                вон.setdefault((мир, ключ), язык)
    return вон


def собрать(свод=СВОД, двор=None):
    двор = двор or str(КОРЕНЬ / "tools")
    import genera_sidecar                                 # noqa: PLC0415
    по_миру = _язык_мира()
    по_миру.update(_язык_пласта())      # пакет сильнее манифеста: он и строит путь
    пласты = set(_язык_пласта())
    по_строке = _язык_строки(двор)
    строки = свод.read_text(encoding="utf-8", errors="replace").split("\n")
    вон, откуда = [], collections.Counter()
    непустых = 0
    for мир, нач, кон in genera_sidecar.границы(свод):
        мирный = по_миру.get(мир)
        for i in range(нач, кон + 1):
            тело = строки[i - 1].rstrip()
            if not тело:
                continue
            язык = по_строке.get((мир, тело))
            если_откуда = "дом"
            if язык is None:
                язык = мирный
                если_откуда = "пакет" if мир in пласты else "мир"
            if язык is None:
                continue
            откуда[если_откуда] += 1
            вон.append(f"{i}\t{язык}")
    for с in строки:
        if с.strip():
            непустых += 1
    доля = round(100.0 * len(вон) / max(1, непустых), 1)
    языки = collections.Counter(с.split("\t")[1] for с in вон)
    шапка = [
        f"# свод\t{свод.name}",
        f"# sha256\t{hashlib.sha256(свод.read_bytes()).hexdigest()}",
        f"# строк непустых\t{непустых}",
        f"# язык назван\t{len(вон)}",
        f"# доля от непустых\t{доля}",
        f"# имён от домов (построчно)\t{откуда['дом']}",
        f"# имён от манифеста (на мир)\t{откуда['мир']}",
        f"# имён от пакета языка (пласты)\t{откуда['пакет']}",
        f"# языков различных\t{len(языки)}",
        "# крупнейшие\t" + ", ".join(f"{я} {n}" for я, n in языки.most_common(12)),
        "# столбцы\tномер строки файла (с единицы, пустые считаются)\tязык",
        "# номера — ТЕ ЖЕ, что в GENESIS-FULL.genera.tsv",
    ]
    return шапка, вон, доля, языки


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--собрать", action="store_true")
    ап.add_argument("--свод", default=None)
    дов = ап.parse_args()
    свод = pathlib.Path(дов.свод) if дов.свод else СВОД
    if not свод.is_file():
        print(f"САЙДКАР ЯЗЫКОВ ОТКАЗ: свода {свод} нет")
        return 2
    шапка, вон, доля, языки = собрать(свод)
    if дов.собрать:
        ВЫХОД.write_text("\n".join(шапка + вон) + "\n", encoding="utf-8")
        print(f"САЙДКАР ЯЗЫКОВ СОБРАН: {ВЫХОД.name}, язык назван у {len(вон)} строк "
              f"({доля} %), языков {len(языки)}")
        return 0
    итог = "PASS" if доля >= ПОКРЫТО_РУБЕЖ else "FAIL"
    print(f"САЙДКАР ЯЗЫКОВ {итог}: назван язык у {len(вон)} строк ({доля} %, "
          f"рубеж {ПОКРЫТО_РУБЕЖ} %), языков {len(языки)}")
    return 0 if итог == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
