#!/usr/bin/env python3
"""[МИР × ПОЛОСА] — что спрошено без показа и что показано без спроса.

ДВЕ БЕДЫ, И ОБЕ НЕВИДИМЫ ПОРОЗНЬ.
  · РОД ПОЛОСЫ БЕЗ МИРА: организм спрашивается о том, чего не видел ни
    разу. Провал такого рода не есть находка о нём — он есть находка о
    нас, и читать его как «организм не умеет» значит лгать себе.
  · МИР БЕЗ ПОЛОСЫ: корпус учит тому, чего никто не проверяет. Такой
    мир может гнить годами: судимость его зелена, ибо суды читают
    строки, а спрашивает ли о нём хоть кто-нибудь — не спрашивал никто.

ЗНАМЕНАТЕЛЬ БЕРЁТСЯ ИЗВНЕ, И ЭТО УСЛОВИЕ ЧЕСТНОСТИ (М-111). Реестр
полос (`forge/band_registry.tsv`) пишет НЕ ЭТА рука: он снимается
прибором `omega/tools/band_registry.py` с ЖИВЫХ сьютов и стендов —
g1 из тегов t7-jsonl, t8 из своего сьюта, atlas из своих check-строк,
narrative из case-листа, valence из своего. Здешняя мера сверяет два
НЕЗАВИСИМЫХ источника, а не список с самим собой.

ОПОЗНАНИЕ, КОТОРОЕ НЕЛЬЗЯ ИСПОЛНИТЬ, ЕСТЬ ОПИСАНИЕ, А НЕ ПРИЗНАК.
Третье поле реестра бывает двух родов: ЗАПИСЬ («19 × 19 =»), которую
можно искать в мирах, и ОПИСАНИЕ («cross: EN-вопрос о RU-факте → 12»),
которое читает человек. Мера ищет ПОДСТРОКОЙ и потому не различает
«род не показан» и «опознание не есть образец»: оба дают ненайденное.
Различить может только тот, кто реестр писал, — и потому ненайденные
перечисляются ПОИМЁННО, а не сводятся в одно число.
"""
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ВНЕШНИЙ = КОРЕНЬ.parent / "omega"

# ПУСТОЙ-ОБХОД: --реестр no-such-registry

# РУБЕЖ-ДОЛГА: объявится числом первого замера; долг, названный до
# замера, есть догадка.
БЕЗ_МИРА_РУБЕЖ = None

РЕЕСТР = ВНЕШНИЙ / "forge" / "band_registry.tsv"
# Опознание короче этого ищется как слово целиком: «g1» встретится
# подстрокой в тысяче мест и покроет всё, ничего не сказав.
КОРОТКОЕ = 6


def реестр(путь):
    """Строки band<TAB>род<TAB>опознание; None — реестра нет."""
    if not путь.exists():
        return None
    вон = []
    for с in путь.read_text(encoding="utf-8").splitlines():
        части = с.rstrip("\n").split("\t")
        if len(части) >= 3 and части[0].strip():
            вон.append((части[0].strip(), части[1].strip(),
                        части[2].strip()))
    return вон


def миры(манифест, корень):
    вон = []
    внешний = манифест.get("external_root")
    for мир in манифест["worlds"]:
        if мир.get("text") != "shows":
            continue
        п = корень / мир["file"]
        if not п.exists() and внешний:
            п = (корень / внешний / мир["file"]).resolve()
        if п.exists():
            вон.append((мир["name"], п))
    return вон


def main():
    путь = РЕЕСТР
    if "--реестр" in sys.argv:
        путь = pathlib.Path(sys.argv[sys.argv.index("--реестр") + 1])
    роды = реестр(путь)
    if not роды:
        print(f"МИР × ПОЛОСА ОТКАЗ: реестра «{путь}» нет или он пуст")
        return 2
    м = json.loads((КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json")
                   .read_text(encoding="utf-8"))
    все = миры(м, КОРЕНЬ)
    if not все:
        print("МИР × ПОЛОСА ОТКАЗ: миров показов не найдено")
        return 2

    тексты = {имя: п.read_text(encoding="utf-8", errors="replace").lower()
              for имя, п in все}
    крыт = collections.defaultdict(set)     # мир → полосы
    # КЛЮЧ ВКЛЮЧАЕТ ОПОЗНАНИЕ, ИБО ОДИН РОД ОПОЗНАЁТСЯ РАЗНЫМ.
    # Ключ «(полоса, род)» схлопнул 60 строк реестра в 31: у полосы
    # t8 девятнадцать родов, но у atlas один род «derive» несёт четыре
    # РАЗНЫХ опознания, и словарь оставлял последнее. Потеря была
    # молчаливой — счёт «родов 31» выглядел как правда.
    живёт = {}                              # (полоса, род, опознание) → миры
    for полоса, род, опознание in роды:
        о = опознание.lower().strip()
        если = re.compile(r"\b%s\b" % re.escape(о)) if len(о) < КОРОТКОЕ \
            else None
        нашлось = set()
        for имя, текст in тексты.items():
            есть = (если.search(текст) if если else о in текст)
            if есть:
                нашлось.add(имя)
                крыт[имя].add(полоса)
        живёт[(полоса, род, опознание)] = нашлось

    без_мира = sorted(к for к, v in живёт.items() if not v)
    крытые = [(к, v) for к, v in живёт.items() if v]
    без_полосы = sorted(имя for имя, _ in все if имя not in крыт)
    for полоса, род, опознание in без_мира:
        print(f"  РОД БЕЗ МИРА {полоса}/{род}: опознание «{опознание}» "
              f"не найдено ни в одном мире")
    # МЕРА, ЧЕЙ ПРИЗНАК НЕ ИСПОЛНЯЕТСЯ, НЕ ВПРАВЕ СУДИТЬ О ПОКРЫТИИ.
    #
    # Первый замер: исполнимы 2 опознания из 60. Прочие суть ОПИСАНИЯ
    # («derive: 19 × 19 → 361 (MulColumn)», «cross: EN-вопрос о
    # RU-факте → 12») — их читает человек, а не прибор. При таком
    # реестре «91 мир из 96 без полосы» есть не находка о корпусе, а
    # СЛЕД НЕИСПОЛНИМОСТИ ПРИЗНАКА: мера не нашла бы покрытия, даже
    # будь оно полным.
    #
    # Печатать такое число как находку значило бы обвинить корпус в
    # своей немоте. Половина отчёта объявляется НЕОПРЕДЕЛИМОЙ, пока
    # исполнимых опознаний меньше половины, — и это объявление есть
    # заказ тому, кто реестр пишет: дать ОБРАЗЕЦ отдельным полем.
    доля_исполнимых = len(крытые) * 2 >= len(живёт)
    if доля_исполнимых:
        for имя in без_полосы:
            print(f"  МИР БЕЗ ПОЛОСЫ {имя}: показывается, но не "
                  f"спрашивается")
    else:
        print(f"  ПОКРЫТИЕ МИРОВ НЕОПРЕДЕЛИМО: исполнимых опознаний "
              f"{len(крытые)} из {len(живёт)}; прочие суть ОПИСАНИЯ, а "
              f"не образцы, и по ним покрытия не установить")
    поза = ("ОТЧЁТ" if БЕЗ_МИРА_РУБЕЖ is None else
            "PASS" if len(без_мира) <= БЕЗ_МИРА_РУБЕЖ else "FAIL")
    for (полоса, род, опознание), где in sorted(крытые)[:8]:
        print(f"  ЖИВЁТ {полоса}/{род}: «{опознание}» — в мирах "
              f"{', '.join(sorted(где)[:4])}"
              f"{' …' if len(где) > 4 else ''}")
    хвост = (f"миров показов {len(все)}, из них без полосы "
             f"{len(без_полосы)}" if доля_исполнимых else
             f"миров показов {len(все)}, покрытие НЕОПРЕДЕЛИМО")
    print(f"МИР × ПОЛОСА {поза}: строк реестра {len(живёт)}, исполнимых "
          f"опознаний {len(крытые)}, родов без мира {len(без_мира)}; "
          f"{хвост}; полос в реестре {len({п for п, _, _ in роды})}")
    if БЕЗ_МИРА_РУБЕЖ is None:
        return 0
    return 0 if len(без_мира) <= БЕЗ_МИРА_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
