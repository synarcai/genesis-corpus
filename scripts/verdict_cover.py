#!/usr/bin/env python3
"""[ПОКРЫТИЕ ВЕРДИКТА] — сколько слов истинной строки суд ПОДПИСАЛ, не прочитав.

ЧТО СУД НЕ ЧИТАЕТ, ТО ОН ПОДПИСЫВАЕТ. Вердикт даётся строке ЦЕЛИКОМ, а читает суд
её ЧАСТЬ: арифметика находит «12 − 5 = 7» целым и зовёт истиной всю строку, вместе
с изувеченным вопросом «wa ist 12 − 5?» перед ним. Молчание о части строки есть не
воздержание, а благословение, — и это лицо М-530 («дыра без проверки благословляет»),
перенесённое с рамки дома на ОБЛАСТЬ ВНИМАНИЯ суда.

    СЛОВО, ПОРЧА КОТОРОГО НЕ МЕНЯЕТ ВЕРДИКТА, ЕСТЬ СЛОВО, КОТОРОГО СУД НЕ ЧИТАЕТ.

ПОКРЫТИЕ МЕРИТСЯ ДЕЛОМ, А НЕ ОБЪЯВЛЕНИЕМ, и это выбор со своим доводом. Суд мог бы
объявлять отрезок, который читает, как М-105 печатает цену; но объявление разошлось
бы с делом в первый же день правки образца, и мы мерили бы объявление. Здесь берётся
строка, которую палата назвала ИСТИННОЙ, и каждое её слово от трёх букв по очереди
обрезается на букву — строка судится снова. Три исхода:

    ЧИТАНО — вердикт стал ЛОЖЬЮ: суд прочёл это слово;
    НЕМО   — строка стала несудимой: воротам записи это защита (несудимое не входит),
             покрытием это не является — суд не прочёл слова, он потерял строку;
    СЛЕПО  — вердикт остался ИСТИНОЙ: слова не читал НИКТО из подписавших.

ВИНОВНЫМИ ЗОВУТСЯ СУДЫ, НАЗВАВШИЕ ЧЕСТНУЮ СТРОКУ ИСТИННОЙ: подписали её они, и слепое
слово лежит внутри их подписи. Суд, не судивший строки, не отвечает за неё ничем.

ЧТО НАШЁЛ ПЕРВЫЙ ЗАМЕР (06.09, 406 строк, 2943 слова): ЧИТАНО 69 %, НЕМО 13 %,
СЛЕПО 17 %. И доля слепых оказалась свойством НЕ СУДА, А ФОРМЫ ЕГО ЧТЕНИЯ:

    script 86 %, compare_mult 80 %, indu 53 %, episode 51 %, geometry 51 %,
    langgen 45 %, engram 41 %, rugram 38 %, arith 19 %
    langmath, money_story, relations_story, chains_langs, action_pages,
    two_kinds, behavior, worldfacts, hypo, measure_story — НОЛЬ

    СУД, ЧИТАЮЩИЙ СТРОКУ ОБРАЗЦОМ НА ЦЕЛУЮ СТРОКУ (`^…$`), СЛЕП НА НОЛЬ ПРОЦЕНТОВ.
    СУД, ВЫНИМАЮЩИЙ ИЗ СТРОКИ ЧИСЛА, СЛЕП НА БОЛЬШИНСТВО ЕЁ СЛОВ.

Все десять нулей — дома, читающие строку целиком; все высокие доли — суды, берущие
из строки числа и считающие их. Оттого лечение не «починить суд», а «сменить форму
чтения»: либо образец на целую строку, либо отказ от вердикта о непрочитанном.

ЧЕГО ЭТОТ ПРИБОР НЕ МЕРИТ, И ЭТО ОБЪЯВЛЕНО ПРЯМО:
    ПОРЧУ ДВУХ СЛОВ — меняется одно слово, и о совместной слепоте здесь молчат;
    СЛОВА КОРОЧЕ ТРЁХ БУКВ — «в», «и», «is» не проверяются: обрезание их убивает;
    ЛОЖНЫЕ СТРОКИ — берутся лишь названные ИСТИННЫМИ: подпись есть только у них;
    ХОРОШ ЛИ СУД — слепота на слово не есть ошибка суда, покуда слово читает сосед;
        она есть ДОЛГ ПАЛАТЫ, и потому счёт ведётся по палате, а не по одному суду.

    python3 scripts/verdict_cover.py [--подробно] [--manifest ПУТЬ]
"""
# ПУСТОЙ-ОБХОД: --manifest no-such-manifest
import argparse
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import panel  # noqa: E402
import word_mutants as W  # noqa: E402

# РУБЕЖ-ДОЛГА: СЛЕПЫХ_РУБЕЖ = 343
#
# ЧИСЛО ПЕРВОГО ЗАМЕРА, объявленное ПОСЛЕ него, а не до: долг, названный до замера,
# есть догадка.
#
# СТЕРЕЖЁТСЯ АБСОЛЮТНОЕ ЧИСЛО, А НЕ ДОЛЯ, и довод взят у соседа (`ask_width`): доля
# ПАДАЕТ от прихода нового хорошего мира, ничего не вылечив, — то есть разбавление
# выдаёт себя за лечение. Абсолютное число растёт от нового слепого мира (новый долг,
# и прибор роняется в тот же час) и стоит на месте от нового зрячего.
#
# БЮДЖЕТ ВЫБОРКИ ФИКСИРОВАН НА МИР (2 строки × 12 слов), потому число растёт от ЧИСЛА
# МИРОВ, а не от размера мира: большой мир не тяжелее малого, и рубеж не растёт от
# роста свода вширь.
#
# 501 → 350 В ТОТ ЖЕ ЧАС, ЧТО И ОБЪЯВЛЕН (06.09). Сорок четыре суда объявили свои миры
# ЗАМКНУТЫМИ — по проверке КАЖДОЙ строки каждого мира, — и молчание суда о слове
# обратилось в ложь: ЧИТАНО 69 % → 84 %, НЕМО 13 % → 3 %, СЛЕПО 17 % → 11 %, судов со
# слепыми словами 51 → 41. Замыкание не читает слов; оно ЗАПРЕЩАЕТ МОЛЧАТЬ о строке
# своего мира, и слово, потерянное судом, перестаёт быть подписанным.
#
# ОСТАВШИЕСЯ 350 — ИНАЯ БОЛЕЗНЬ, И ЗАМЫКАНИЕМ ОНА НЕ ЛЕЧИТСЯ: суд не молчит, он
# ГОВОРИТ «истина» о строке, части которой не прочёл. Лечит только форма чтения.
# 350 → 343 тем же вторым ходом обёртки.
СЛЕПЫХ_РУБЕЖ = 343

СТРОК_НА_МИР = 2
СЛОВ_НА_СТРОКУ = 12
ЧИТАНО, НЕМО, СЛЕПО = "ЧИТАНО", "НЕМО", "СЛЕПО"


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--manifest", default=None)
    дов = ап.parse_args()
    путь = pathlib.Path(дов.manifest) if дов.manifest else \
        КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    м = W.манифест(путь)
    if not м:
        print(f"ПОКРЫТИЕ ОТКАЗ: манифеста «{путь}» нет")
        return 2
    внешний = м.get("external_root")
    палата = panel.Палата()
    итог = collections.Counter()
    слепых_суда, всего_суда = collections.Counter(), collections.Counter()
    примеры = collections.defaultdict(list)
    строк = 0
    for мир in м["worlds"]:
        if мир.get("text") != "shows":
            continue
        п = W._файл(мир, внешний)
        if п is None:
            continue
        слои = палата.слои(п)
        пласт = палата.пласт_файла(п)
        все = [с.strip() for с in
               п.read_text(encoding="utf-8", errors="replace").splitlines() if с.strip()]
        годные = [с for с in все if W.СЛОВО.search(с)]
        if not годные:
            continue
        for честно in W.равномерно(годные, СТРОК_НА_МИР, W.зерно_мира(мир["name"])):
            судимо, истинно, кем = палата.судить(честно, слои, пласт)
            if not (судимо and истинно):
                continue
            строк += 1
            места = [(m.start(), m.end()) for m in W.СЛОВО.finditer(честно)][:СЛОВ_НА_СТРОКУ]
            for a, b in места:
                порча = честно[:a] + честно[a:b][:-1] + честно[b:]
                с, и, _ = палата.судить(порча, слои, пласт)
                исход = ЧИТАНО if (с and not и) else (НЕМО if not с else СЛЕПО)
                итог[исход] += 1
                for к in кем:
                    всего_суда[к] += 1
                    if исход == СЛЕПО:
                        слепых_суда[к] += 1
                        if len(примеры[к]) < 3:
                            примеры[к].append((мир["name"], честно[a:b]))
    всего = sum(итог.values())
    if not всего:
        print("ПОКРЫТИЕ ОТКАЗ: ни одного слова не проверено — миров показов нет")
        return 2
    print(f"{'суд':<24}{'слепых':>8}{'подписал':>10}{'доля':>7}")
    for к, n in всего_суда.most_common():
        с = слепых_суда.get(к, 0)
        if not дов.подробно and not с:
            continue
        хвост = ""
        if с and примеры[к]:
            хвост = "  " + ", ".join(f"«{сл}»[{м_}]" for м_, сл in примеры[к][:2])
        print(f"{к:<24}{с:>8}{n:>10}{100 * с // n:>6}%{хвост}")
    слепо = итог[СЛЕПО]
    поза = "PASS" if слепо <= СЛЕПЫХ_РУБЕЖ else "FAIL"
    print(f"ПОКРЫТИЕ ВЕРДИКТА {поза}: строк {строк}, слов {всего} — ЧИТАНО "
          f"{итог[ЧИТАНО]} ({100 * итог[ЧИТАНО] // всего}%), НЕМО {итог[НЕМО]} "
          f"({100 * итог[НЕМО] // всего}%), СЛЕПО {слепо} ({100 * слепо // всего}%, "
          f"рубеж {СЛЕПЫХ_РУБЕЖ}); судов со слепыми словами "
          f"{sum(1 for к in всего_суда if слепых_суда.get(к))} из {len(всего_суда)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
