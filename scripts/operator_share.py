#!/usr/bin/env python3
"""[ДОЛЯ ОПЕРАТОРА] — какую часть своей жизни в своде слово действия стои́т ОПЕРАТОРОМ.

    ЧЕМ БОЛЬШЕ СЛОВО ЖИВЁТ ВНЕ РОЛИ ОПЕРАТОРА, ТЕМ МЕНЬШЕ ОНО КУПЛЕНО КАК ОПЕРАТОР.

ЗАКАЗ ПРИШЁЛ СНАРУЖИ И БЫЛ ЗАКРЫТ ЧИСЛОМ (07.09, вечер). holon прогнал удержанный ключ на
свидетеле и назвал испанскую ложь: «¿cuánto es 23 más 19?» → ядро ответило 4, то есть
23 − 19. Слово «más» прочитано как СРАВНЕНИЕ («более»), а не как оператор сложения.

Перепись отвечает, отчего именно это слово:

    más (es)                 оператором   124 из 3245 —  3.8 %   ← ядро ошиблось здесь
    mais (pt), più (it)                   124 из ~2750 —  4.5 %
    plus (de/en/fr/nl/pl)                 767 из 8882  —  8.6 %
    плюс (ru)                             233 из 2601  —  9.0 %
    ...
    dividido entre (es), diviso per (it)          140 из 140  — 100 %

    СЛОВО, ЖИВУЩЕЕ В СВОДЕ ТРИ ТЫСЯЧИ РАЗ И СТОЯЩЕЕ ОПЕРАТОРОМ СТО, ЧИТАЕТСЯ НЕ КАК
    ОПЕРАТОР. Многословный оборот («multiplicado por», «geteilt durch») безопасен не оттого,
    что он яснее, а оттого, что ему НЕГДЕ жить иначе: доля его — девяносто процентов и выше.

ПОРЯДОК ЕСТЬ ПРЕДСКАЗАНИЕ, А НЕ ОПИСАНИЕ. Таблица упорядочивает слова по риску ДО того, как
читатель ошибётся, и «más» стои́т в ней первым. Если следующая ошибка чтения придётся на
«mais», «più», «plus» или «плюс» прежде, чем на девяностопроцентные обороты, — мера верна;
если на них, — мера неверна и подлежит замене. Прибор объявляет это своим условием
опровержения.

ЧТО СЧИТАЕТСЯ. Слова берутся из таблицы самого дома (`opforms.ИНФИКС`), а не угадываются:
первая проба гадала («times», «por», «entre») и дала четыре ложных нуля там, где дом пишет
«multiplied by», «multiplicado por», «dividido entre».

    python3 scripts/operator_share.py [--свод ФАЙЛ] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --свод no-such-file
import argparse
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: РИСКОВЫХ_РУБЕЖ = 0
#
# РУБЕЖ ОБЪЯВЛЕН ПО ДОСТИГНУТОМУ: три слова ниже пяти процентов в час постановки — «más»,
# «mais», «più». Это ПОТОЛОК: цена снижения — страницы леджера со словом между числами
# (`opforms`, образцы `повеление_инфикс` и `повеление_равенством`), и цена эта известна:
# двадцать страниц на слово на язык дают нынешние доли.
#
# 3 → 0 (12.09, ЦЕНА УПЛАЧЕНА). Дом оператора получил одиннадцать новых пар сложения к
# десяти прежним, и все три рисковых слова перешли пятипроцентный порог: «más» 3,8 → 5,1 %,
# «mais» и «più» 4,5 → 5,8 %. Мир 3824 → 4599 страниц.
#
#     ДОЛЯ, ПОДНЯТАЯ НОВЫМИ ПОКАЗАМИ, ЕСТЬ УПЛАТА; ДОЛЯ, ПОДНЯТАЯ СДВИГОМ РУБЕЖА,
#     ЕСТЬ ОТКАЗ ОТ УПЛАТЫ.
#
# Рубеж опущен до нуля в тот же час: прибор, знавший цену и её получивший, не вправе
# держать запас на возврат.
РИСКОВЫХ_РУБЕЖ = 0
ПОРОГ_РИСКА = 5.0          # процентов — ниже него слово зовётся рисковым


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ОБА СЧЁТА различают слово-оператор от
    слова вообще.

        ЭТОТ ПРИБОР СЧИТАЕТ ДОЛЮ: сколько раз слово стои́т МЕЖДУ ЧИСЛАМИ из всех его
        вхождений. Обе стороны дроби он считает сам, и обе можно обмануть. Пусть верхний
        счёт станет равен нижнему — и всякое слово окажется чистым оператором; пусть оба
        обнулятся — и доля станет нулём из нуля, то есть молчанием, выданным за находку.

    Четыре строки, и про каждую известно, что она даёт каждому из двух счётов.
    """
    беды = []
    слово = "plus"
    текст = ("2 plus 3 is 5. "            # оператор
             "plus one more thing. "      # слово, но не оператор
             "the surplus is large. "     # слово ВНУТРИ другого — не в счёт
             "7 plus 8 is 15.")           # оператор
    всего = len(re.findall(r"(?<![^\W\d_])" + re.escape(слово) + r"(?![^\W\d_])", текст))
    опер = len(re.findall(r"\d+ " + re.escape(слово) + r" \d+", текст))
    if всего != 3:
        беды.append(f"всех вхождений {всего} вместо 3 — граница слова сбита")
    if опер != 2:
        беды.append(f"оператором {опер} вместо 2 — признак между числами мёртв")
    if опер == всего:
        беды.append("ВЕРХНИЙ СЧЁТ РАВЕН НИЖНЕМУ — всякое слово объявится оператором")
    # И ДОМ ОПЕРАТОРОВ ОБЯЗАН ЧТО-ТО ОБЪЯВЛЯТЬ, ИНАЧЕ РЯД ПУСТ И ДОЛИ НЕТ.
    try:
        import opforms
    except Exception:                       # noqa: BLE001
        return беды + ["дом операторов не ввозится — проба неполна"]
    слов = sum(len(г) for г in opforms.ИНФИКС.values())
    if слов < 8:
        беды.append(f"дом операторов объявил {слов} слов — мерить почти нечего")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ДОЛЯ ОПЕРАТОРА ОТКАЗ: счёт доли не доказан ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--свод", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    п = pathlib.Path(дов.свод) if дов.свод else КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
    if not п.is_file():
        print(f"ДОЛЯ ОПЕРАТОРА ОТКАЗ: свода «{п}» нет")
        return 2
    try:
        import opforms
    except Exception as e:                      # noqa: BLE001
        print(f"ДОЛЯ ОПЕРАТОРА ОТКАЗ: дом операторов не ввозится ({type(e).__name__})")
        return 2
    низ = п.read_text(encoding="utf-8", errors="replace").lower()
    ряд = []
    for я, г in opforms.ИНФИКС.items():
        for глиф, слово in г.items():
            с = слово.lower()
            всего = len(re.findall(r"(?<![^\W\d_])" + re.escape(с) + r"(?![^\W\d_])", низ))
            опер = len(re.findall(r"\d+ " + re.escape(с) + r" \d+", низ))
            ряд.append((100 * опер / max(1, всего), с, я, глиф, опер, всего))
    ряд.sort()
    рисковые = [r for r in ряд if r[0] < ПОРОГ_РИСКА]
    показать = ряд if дов.подробно else ряд[:8]
    print(f"{'слово':<22}{'язык':<5}{'оператором':>11}{'в своде':>10}{'доля':>8}")
    for доля, слово, я, _глиф, опер, всего in показать:
        print(f"{слово:<22}{я:<5}{опер:>11}{всего:>10}{доля:>7.1f}%")
    поза = "PASS" if len(рисковые) <= РИСКОВЫХ_РУБЕЖ else "FAIL"
    имена = ", ".join(f"{с} ({я}) {д:.1f} %" for д, с, я, _г, _о, _в in рисковые)
    print(f"ДОЛЯ ОПЕРАТОРА {поза}: слов действия {len(ряд)}; НИЖЕ {ПОРОГ_РИСКА:.0f} % — "
          f"{len(рисковые)} (рубеж {РИСКОВЫХ_РУБЕЖ}): {имена or '—'}; "
          f"самое низкое {ряд[0][1]} ({ряд[0][2]}) {ряд[0][0]:.1f} %, "
          f"самое высокое {ряд[-1][1]} ({ряд[-1][2]}) {ряд[-1][0]:.1f} %")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
