#!/usr/bin/env python3
"""СОСТОЯНИЕ КРИСТАЛЛА — все меры замкнутости корпуса на одном листе.

Слово владельца (03.09): GENESIS есть знаниевый движок, который
агрегирует и структурирует знание и создаёт КРИСТАЛЛ — то, чем питается
организм. Кристалл замкнут, когда каждая его мера замкнута; приборов
много, и каждый печатает свой вердикт своей строкой — здесь они
собираются в один лист с датой каждого числа, чтобы состояние кристалла
читалось разом, а не по десяти логам.

ИСТОЧНИК ЧИСЕЛ — ЛЕДЖЕР ПРИБОРОВ (reports/ledger.tsv): courts.sh
дописывает в него последнюю строку каждого суда с датой и кодом
возврата; сюда ничего не вписывается рукой, и число без даты здесь не
печатается. Ось, чей прибор не бегал, показана как «не мерено».

  python3 scripts/crystal.py            # лист на экран
  python3 scripts/crystal.py --снимок   # + reports/CRYSTAL-<дата>.md (история не редактируется)
"""
import collections
import datetime
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ЛЕДЖЕР = КОРЕНЬ / "reports" / "ledger.tsv"

# ОСИ ЗАМКНУТОСТИ — каждая названа тем, что она закрывает, и прибором,
# который её меряет. Порядок — от свода к организму.
ОСИ = (
    ("судимость", "coverage.py",
     "каждая строка свода судима хоть одним судом; слепых нет"),
    ("воспроизводимость", "reproducible.py",
     "каждый мир пересобирается генератором побайтово"),
    ("состав палаты", "panel_court.py",
     "все суды объявлены и все объявленные живы"),
    ("манифест", "manifest_court.py",
     "объявление каждого мира сходится с его делом"),
    ("пакеты языков", "langpack_court.py",
     "каждый язык объявлен пакетом, и пакет сходится с пластом"),
    ("порча словом", "word_mutants.py",
     "порченое слово в показе ловится судом, а не проходит истиной"),
    ("порча числом", "court_mutants.py",
     "порченое число в показе ловится судом"),
    ("полка", "shelf_court.py",
     "каждая книга полки объявлена договором и читается названным судом"),
    ("полоса", "band_reach.py",
     "каждый род полосы организма имеет мир в своде"),
    ("библиотека", "biblio_reach.py",
     "источник, названный корпусом и свободный по праву, лежит на полке"),
    ("охват понятия", "concept_reach.py",
     "понятие из оглавлений прозы показано в показах"),
    ("немота", "ask_reach.py",
     "род без вопросной поверхности — диагностика (орган, не корпус)"),
    ("ширина вопроса", "ask_width.py",
     "доля родов с вопросной поверхностью — диагностика"),
)
ЧИСЛО = re.compile(r"\d[\d ]*")


def леджер():
    """{прибор: (дата, rc, строка)} — последний вердикт каждого прибора."""
    вон = {}
    if not ЛЕДЖЕР.is_file():
        return вон
    for строка in ЛЕДЖЕР.read_text(encoding="utf-8").splitlines():
        части = строка.split("\t", 3)
        if len(части) != 4:
            continue
        дата, прибор, rc, вердикт = части
        вон[прибор] = (дата, rc, вердикт)
    return вон


def поза(вердикт, rc):
    if "PASS" in вердикт:
        return "замкнута"
    if "FAIL" in вердикт or rc not in ("0", ""):
        return "ОТКРЫТА"
    if "ОТЧЁТ" in вердикт:
        return "диагностика"
    return "неясно"


def лист(записи):
    """Строки листа и итог (замкнутых, открытых, не мерено)."""
    строки, итог = [], collections.Counter()
    for ось, прибор, смысл in ОСИ:
        если = записи.get(прибор)
        if если is None:
            строки.append(f"  {ось:<18} не мерено            — {смысл}")
            итог["не мерено"] += 1
            continue
        дата, rc, вердикт = если
        п = поза(вердикт, rc)
        итог[п] += 1
        строки.append(f"  {ось:<18} {п:<12} {дата[:16]}  {вердикт[:150]}")
    прочие = sorted(п for п in записи if п not in {о[1] for о in ОСИ})
    пало = [п for п in прочие if записи[п][1] != "0"]
    строки.append(f"  суды миров: {len(прочие)} в леджере, пали {len(пало)}"
                  + (": " + ", ".join(пало[:8]) if пало else ""))
    return строки, итог


def main():
    записи = леджер()
    строки, итог = лист(записи)
    сегодня = datetime.date.today().isoformat()
    шапка = (f"КРИСТАЛЛ {сегодня}: осей замкнуто {итог['замкнута']}, открыто "
             f"{итог['ОТКРЫТА']}, диагностик {итог['диагностика']}, "
             f"не мерено {итог['не мерено']} из {len(ОСИ)}")
    print(шапка)
    for с in строки:
        print(с)
    if "--снимок" in sys.argv:
        # ИСТОРИЯ НЕ РЕДАКТИРУЕТСЯ: снимок кладётся новым файлом с датой;
        # снимок того же дня перезаписывается — день один, число одно.
        путь = КОРЕНЬ / "reports" / f"CRYSTAL-{сегодня}.md"
        тело = ["# " + шапка, "", "Ось · состояние · дата числа · вердикт прибора", ""]
        тело += ["    " + с for с in строки]
        тело += ["", "Источник чисел — reports/ledger.tsv (пишет scripts/courts.sh); "
                 "смысл осей — declarations/KNOWLEDGE-ENGINE.md."]
        путь.write_text("\n".join(тело) + "\n", encoding="utf-8")
        print(f"снимок: {путь.relative_to(КОРЕНЬ)}")
    return 0 if not итог["ОТКРЫТА"] else 1


if __name__ == "__main__":
    sys.exit(main())
