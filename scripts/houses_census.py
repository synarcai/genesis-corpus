#!/usr/bin/env python3
"""ПЕРЕПИСЬ ДОМОВ: чему учит каждый дом, названное его собственными именами.

    ОТСУТСТВИЕ СЛОВА НЕ ЕСТЬ ОТСУТСТВИЕ РОДА, И ЭТО КУПЛЕНО ОПЛОШНОСТЬЮ (10.09).

Рука искала в своде обратную импликацию: «верно ли обратное» — ноль, «converse» — ноль,
«тогда и только тогда» — ноль, «необходимо и достаточно» — ноль. Вывод напрашивался: рода нет,
надо строить дом. Рода не было только у СЛОВ. Дом строгого вывода (`inferforms`) показывает его
с рождения и называет своим именем — ОБРАЩЕНИЕ: «6 делится на 2. значит ли, что 6 делится на 4?
нет: 6 не делится на 4», и рядом ОТРИЦАНИЕ посылки. Дом был бы построен второй раз.

    СЛОВО ИЩЕТСЯ ГРЕПОМ. РОД — ТОЛЬКО ЧТЕНИЕМ ДОМОВ. Восемьдесят два дома рукой не
    перечитываются перед каждым замыслом, и потому их перечисляет прибор.

ЧТО ПЕЧАТАЕТСЯ: имя дома, первая строка его докстринга и ИМЕНА РОДОВ, которые он объявил своими
верхними таблицами (`РОДЫ`, `ФОРМЫ`, `РАМКИ`, `ОБОРОТЫ`, `ОБРАЗЦЫ`). Имена берутся у дома, а не
выводятся из показов: дом, чей род назван только в показе, назван для машины, а не для читателя.

ДВА ЗАКОНА, И У КАЖДОГО СВОЙ РУБЕЖ, ИБО ОНИ РАЗНОЙ ЦЕНЫ:

  НЕМОЙ ДОМ (рубеж 0). Всякий дом обязан назвать свой ПРЕДМЕТ первой строкой докстринга. Это
  та строка, которую читает ищущий дыру, и её отсутствие — не мелочь оформления, а дом, о
  котором нельзя узнать, не читая его целиком. Измерено 10.09: немых нет.

  ДОМ БЕЗ ИМЁН РОДОВ (рубеж 17). Имена родов суть второй ярус: они говорят не «о чём дом», а
  «что именно он показывает». Прибор поймал бы оплошность выше именно ими — у `inferforms` он
  печатает «закон, поненс, толленс, ОБРАЩЕНИЕ, отрицание».

ДОЛГ БЫЛ 17 ИЗ 64 И УПЛАЧЕН ЦЕЛИКОМ В ТОТ ЖЕ ДЕНЬ (10.09). Дома объявляли свой МАТЕРИАЛ, а не
свои РОДЫ: `geoforms` знал `ФАКТЫ` и `ЛЕДЖЕРЫ`, `primeforms` — `ДЫРЫ`, `countforms` — `СЧЁТЫ`.
Прибор НЕ БЫЛ РАСШИРЕН, чтобы их принять: взять `ФАКТЫ` за имена родов значило бы научить
перепись считать материал предметом, и лист стал бы зелен, ничего не назвав.

    РУБЕЖ ИДЁТ ВНИЗ ПО МЕРЕ ТОГО, КАК ДОМА НАЗЫВАЮТ СЕБЯ, — А НЕ ПРИБОР ВШИРЬ.

ЧЕТЫРЕ СПОСОБА ПЛАТЕЖА, И КАЖДЫЙ ДЕРЖИТСЯ ПРОВЕРКОЙ, А НЕ СЛОВОМ:

  ТАБЛИЦА ЧИСТА — роды выводятся ИЗ неё целиком (`remforms`, `seqforms`, `statforms`,
  `physforms`). Новый ключ без имени валит дом ПРЯМО НА ВВОЗЕ:

      _ИМЯ_РОДА = {"утв": "утверждение с леджером деления", "воп": "вопрос, отвечаемый им же"}
      РОДЫ = tuple(_ИМЯ_РОДА[к] for к in next(iter(ЯЗЫКИ.values())))

  ТАБЛИЦА СМЕШАНА — несущие ключи названы явно, `assert` держит их ПРИ таблице (`primeforms`,
  `shareforms`, `geoforms`, `roleforms`, `calforms`, `priceforms`, `countforms`, `cmpforms`).
  У `primeforms` «прост», «сост», «воп» суть роды, а «да» и «нет» — ответные слова.

  РОД ЗАДАН МЕСТОМ В ПАРЕ, а не ключом (`unitforms`, `translateforms`, `moneyforms`): имена
  написаны явно, а `assert` держит ДЛИНУ пары равной числу имён.

  РОД ЗАДАН ГЛУБИНОЙ ЛЕДЖЕРА (`chainforms`): два строителя суть два рода, и `assert` держит
  имена при строителях.

ЗАКОН, А НЕ ДОМ — И ЭТО ИЗМЕРЯЕТСЯ. `subjectforms` кончается на «forms» и лежит среди домов, но
страниц не даёт ни одной: он объявляет форму предмета, и ввозят его палата и прибор покрытия, а
не кузня. Прежде такие перечислялись рукой, и список был МЁРТВЫМ — в нём стоя́ли имена, под
перепись не попадающие вовсе. Ныне признак меряется: дом, которого не ввозит ни одна кузня, есть
закон для других.

ЧТО ПРОВЕРЕНО ПОСЛЕ ВСЕХ ПРАВОК: все затронутые миры перекованы ПОБАЙТОВО ТЕМИ ЖЕ. Объявление
рода не трогает ни одной страницы.

    python3 scripts/houses_census.py            # лист
    python3 scripts/houses_census.py --снимок   # reports/HOUSES-<дата>.md
"""
# ПУСТОЙ-ОБХОД: no-such-house-dir
import datetime
import ast
import importlib
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: НЕМЫХ_РУБЕЖ = 0
НЕМЫХ_РУБЕЖ = 0
# РУБЕЖ-ДОЛГА: БЕЗЫМЯННЫХ_РУБЕЖ = 0
БЕЗЫМЯННЫХ_РУБЕЖ = 0

# ИМЕНА, КОТОРЫМИ ДОМА НАЗЫВАЮТ СВОИ РОДЫ. Порядок значим: берётся первая найденная таблица,
# ибо `РОДЫ` точнее `ФОРМ`, а `ФОРМЫ` точнее `ОБРАЗЦОВ`.
ТАБЛИЦЫ = ("РОДЫ", "ФОРМЫ", "ОБОРОТЫ", "РАМКИ", "ОБРАЗЦЫ")

# ИМЕНА ДОМОВ — ОДИН РАЗ И ПО ФАЙЛАМ. Дом, которого нет файлом, не может быть ничьим ввозом;
# без этой сверки прибор приписывал миры несуществующему «forms».
_ИМЕНА_ДОМОВ = frozenset(п.stem for п in (КОРЕНЬ / "tools").glob("*forms.py")
                         if not п.name.startswith("gen_genesis_"))


def _ввезённые(путь, текст):
    """Имена модулей, которые файл ВВОЗИТ, — по разбору, а не по началу строки.

    ЧТЕНИЕ ВВОЗА ПО ПРЕФИКСУ СТРОКИ ПРИНЯЛО ПРОЗУ ЗА ЗАКОН (10.09). Докстринг кузни
    `gen_genesis_compare_langs.py` начинается со слова «from»: «from the packs, things with
    their count forms, the multiplier by the …» — и сканер вычитал оттуда ввоз модуля «forms»,
    которого нет на свете. Мир был приписан несуществующему дому, и ничто не упало.

        РАЗБОР НЕ СПУТАЕТ ПРОЗУ С ВВОЗОМ. Начало строки — спутает.

    Файл, который не разбирается, отдаёт пустое: это находка соседних приборов, а не этого.
    """
    try:
        дерево = ast.parse(текст, filename=str(путь))
    except SyntaxError:
        return set()
    вон = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            вон.update(и.name.split(".")[0] for и in узел.names)
        elif isinstance(узел, ast.ImportFrom):
            if узел.module:
                вон.add(узел.module.split(".")[0])
            вон.update(и.name for и in узел.names)
    return вон


def _кузни():
    """дом → миры, которые он кормит: {имя дома: [цели кузен, ввозящих его]}.

    ЛИСТ БЕЗ МИРА ЗАСТАВЛЯЕТ ИСКАТЬ ДВАЖДЫ. Ищущий дыру читает имена родов и хочет тут же
    увидеть страницу; без имени мира он идёт гадать по каталогу, какая кузня какой дом
    ввозит. Связь берётся у самих кузен — из их `ЦЕЛЬ` и их ввоза, — а не пишется рядом.
    """
    вон = {}
    для_цели = re.compile(r'^ЦЕЛЬ\s*=\s*"([^"]+)"', re.M)
    for кузня in sorted((КОРЕНЬ / "tools").glob("gen_genesis_*.py")):
        текст = кузня.read_text(encoding="utf-8", errors="replace")
        цели = для_цели.findall(текст)
        if not цели:
            continue
        миры = {pathlib.Path(ц).stem.replace("genesis_", "") for ц in цели}
        for имя in _ввезённые(кузня, текст):
            if имя in _ИМЕНА_ДОМОВ:
                вон.setdefault(имя, set()).update(миры)
    return {к: sorted(v) for к, v in вон.items()}


def _миры_показов():
    """Имена миров показов по манифесту — знаменатель реестра родов.

    ЗНАМЕНАТЕЛЬ БЕРЁТСЯ У МАНИФЕСТА, А НЕ У КАТАЛОГА: в `datasets/` лежат ещё и своды, и
    сборки, и они суть КОПИИ миров. Считать по каталогу — удваивать всякую долю.
    """
    try:
        м = json.loads((КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    return [w.get("name") for w in м.get("worlds", ()) if w.get("text") == "shows"]


def _законы():
    """Модули, которые НЕ ЕСТЬ дома: их не ввозит ни одна кузня.

    ДОМ УЗНАЁТСЯ КУЗНЕЙ, А НЕ ИМЕНЕМ ФАЙЛА. `subjectforms` кончается на «forms» и лежит среди
    домов, но страниц не даёт ни одной: он объявляет ФОРМУ ПРЕДМЕТА («массив [6 4 7]»,
    «x = 4») — предложение без утверждения, — и ввозят его палата и прибор покрытия, а не
    кузня. Требовать от него имён родов значило бы требовать предмета у того, чей предмет
    есть закон для других.

    ПРИЗНАК ПОВЕРЕН ВТОРОЙ, НЕЗАВИСИМОЙ МЕРОЙ, И ОНИ СОШЛИСЬ. `_кузни()` считает, какие миры
    кормит дом, — и единственный дом без мира есть тот же `subjectforms`. Две меры смотрят с
    разных сторон (кто ввозит дом / что дом кормит) и называют одно имя из шестидесяти
    четырёх; будь признак случаен, они разошлись бы.

    Признак ИЗМЕРЯЕТСЯ, а не перечисляется рукой: прежде здесь стоя́л список
    («rugram», «foreign», «closedworld», «layer», «panel»), и он был МЁРТВЫМ — перепись берёт
    только `*forms.py`, и ни одно из тех имён под неё не попадало никогда. Список, который не
    может сработать, есть худший вид закона: он выглядит действующим.
    """
    ввезённые = set()
    for кузня in (КОРЕНЬ / "tools").glob("gen_genesis_*.py"):
        ввезённые |= _ввезённые(кузня, кузня.read_text(encoding="utf-8", errors="replace"))
    return {и for и in _ИМЕНА_ДОМОВ if и not in ввезённые}


def _имена_родов(дом):
    """Имена родов дома: ключи первой из объявленных таблиц, годной к перечислению."""
    for имя in ТАБЛИЦЫ:
        т = getattr(дом, имя, None)
        if т is None:
            continue
        if isinstance(т, dict):
            ключи = list(т)
            # ТАБЛИЦА ПО ЯЗЫКАМ: роды лежат ярусом ниже — «ru» не есть род.
            if ключи and all(isinstance(к, str) and len(к) == 2 for к in ключи):
                вложено = т[ключи[0]]
                if isinstance(вложено, dict):
                    return имя, sorted(вложено)
                continue
            return имя, sorted(str(к) for к in ключи if isinstance(к, str))
        if isinstance(т, (tuple, list)) and т and all(isinstance(э, str) for э in т):
            return имя, list(т)
    return None, []


def main():
    снимок = "--снимок" in sys.argv
    # КУЗНЯ НЕ ЕСТЬ ДОМ, хотя имя её и кончается на «forms»: `gen_genesis_clockforms.py`
    # выковывает мир из дома, а не объявляет род. Перепись домов, считающая кузни, врёт вдвое.
    дома = sorted(p for p in (КОРЕНЬ / "tools").glob("*forms.py")
                  if not p.name.startswith("gen_genesis_"))
    законы = _законы()
    кузни = _кузни()
    if not дома:
        print("ПЕРЕПИСЬ ДОМОВ ОТКАЗ: домов не найдено")
        return 2
    строки = [f"# ПЕРЕПИСЬ ДОМОВ {datetime.date.today().isoformat()}", "",
              "Имя дома · чему учит (первая строка докстринга) · имена родов, объявленные домом.",
              ""]
    безымянных = []
    немых = []          # дом, не назвавший предмета первой строкой
    невозимых = []      # дом, который не ввозится вовсе — находка, а не повод молчать
    всего_родов = 0
    for путь in дома:
        имя = путь.stem
        try:
            дом = importlib.import_module(имя)
        except Exception as бе:                          # noqa: BLE001
            невозимых.append(f"{имя}: {type(бе).__name__}")
            continue
        первая = (дом.__doc__ or "").strip().split("\n")[0]
        # ПРЕДМЕТ НАЗВАН, ЕСЛИ ЕСТЬ ИМЯ И ЕСТЬ ПОЯСНЕНИЕ ЗА ТИРЕ. «ДОМ ЧИСЕЛ.» есть имя файла
        # другими буквами; предмет начинается там, где сказано, ЧТО ИМЕННО дом показывает.
        if len(первая) < 24 or ("—" not in первая and " - " not in первая):
            немых.append(имя)
        табл, роды = _имена_родов(дом)
        всего_родов += len(роды)
        if not роды and имя not in законы:
            безымянных.append(имя)
        строки.append(f"## {имя}")
        строки.append(f"  {первая}")
        помета = "ЗАКОН, А НЕ ДОМ: ни одна кузня его не ввозит" if имя in законы else \
                 (табл or "НЕ ОБЪЯВЛЕНЫ")
        строки.append(f"  роды ({помета}): {', '.join(роды) if роды else '—'}")
        миры = кузни.get(имя)
        if миры:
            строки.append(f"  кормит миры: {', '.join(миры)}")
        страниц = getattr(дом, "ПОКАЗЫ", None)
        if страниц is not None:
            строки.append(f"  страниц: {len(страниц)}")
        строки.append("")
    for н in невозимых:
        строки.append(f"## НЕ ВВОЗИТСЯ: {н}")
    if снимок:
        путь = КОРЕНЬ / "reports" / f"HOUSES-{datetime.date.today().isoformat()}.md"
        путь.write_text("\n".join(строки) + "\n", encoding="utf-8")
        print(f"снимок: {путь.relative_to(КОРЕНЬ)}")
    else:
        for с in строки:
            print(с)
    # РЕЕСТР РОДОВ И ФОРМ (долг Д-1 кристалла): какая доля миров показов кормится домом,
    # объявившим свои роды. Число печатается ПРИБОРОМ, а не считается на стороне и не
    # переписывается рукой в документ.
    показов = _миры_показов()
    кормимых = sorted({м for миры in кузни.values() for м in миры} & set(показов))
    доля = f"{len(кормимых)} из {len(показов)}" + (
        f" ({100 * len(кормимых) // len(показов)} %)" if показов else "")
    print(f"  РЕЕСТР РОДОВ: миров показов, кормимых домом с объявленными родами — {доля}; "
          f"прочие кузня пишет напрямую, и род их нигде не назван")
    цело = (len(немых) + len(невозимых) <= НЕМЫХ_РУБЕЖ
            and len(безымянных) <= БЕЗЫМЯННЫХ_РУБЕЖ)
    if немых:
        print(f"  НЕ НАЗВАЛИ ПРЕДМЕТА: {', '.join(немых)}")
    if безымянных:
        print(f"  БЕЗ ИМЁН РОДОВ: {', '.join(безымянных)}")
    print(f"ПЕРЕПИСЬ ДОМОВ {'PASS' if цело else 'FAIL'}: "
          f"{len(немых) + len(невозимых)} немых (рубеж {НЕМЫХ_РУБЕЖ}), "
          f"{len(безымянных)} без имён родов (рубеж {БЕЗЫМЯННЫХ_РУБЕЖ}); "
          f"домов {len(дома)} (из них законов, а не домов: {len(законы)}), "
          f"имён родов {всего_родов}, не ввозится {len(невозимых)}")
    return 0 if цело else 1


if __name__ == "__main__":
    sys.exit(main())
