"""[ВОЛОСОК ЕДИНСТВЕННОГО] — у скольких пакетов единственное число держится на жребии.

    ПАКЕТ, ПОКАЗЫВАЮЩИЙ ЕДИНСТВЕННОЕ ЧИСЛО ЛИШЬ СЛУЧАЙНЫМ ВЫПАДЕНИЕМ ЕДИНИЦЫ, ДЕРЖИТ ЕГО НА
    ВОЛОСКЕ: каждая новая лексема делает волосок тоньше. Немецкий пал на этом сегодня —
    закон «ни одного слова по разу» упал не на слове, а на ЧИСЛЕ МЕСТ для него.

Прибор спрашивает у каждого пакета: есть ли у его счётного класса показ, называющий ЯЧЕЙКУ
единственного ПРЯМО (`{lex:КЛАСС:one}` или `{lex:КЛАСС:count_one}`), — или единственное
выходит лишь через `by_n`, когда счётному инстансу выпадет единица.

ЭТО РУБЕЖ, И ОН НОЛЬ. Прежде я счёл это предупреждением, а не долгом; но немецкий показал
цену: закон «ни одного слова по разу» пал молча, слой НЕ ЗАПИСАЛСЯ вовсе, и нашлось это лишь
потому, что я полез смотреть, отчего суд пакетов держит двух красных. Пакет на волоске падает
не сегодня, а в тот день, когда кто-то объявит ему слово, — и падает не там, где правил.

ПРОБА НА НЕ-НОЛЬ (07.09): немецкий пакет ДО починки — «классы на жребии: noun_count».
Ныне все двадцать девять называют единственное прямо.

    python3 scripts/pack_singular_risk.py
"""
import json, pathlib, re, sys
К = pathlib.Path("/Users/taaliman/projects/oldman/synarcai/genesis-corpus")
ПРЯМО = re.compile(r"\{lex:([^:}]+):(count_)?one\}")
ЖРЕБИЕМ = re.compile(r"\{lex:([^:}]+):by_")
# РУБЕЖ-ДОЛГА: ВОЛОСКОВ_РУБЕЖ = 0
ВОЛОСКОВ_РУБЕЖ = 0

на_волоске, прямые, без_счёта = [], [], []
for п in sorted((К / "tools" / "langpacks").glob("*.json")):
    пак = json.loads(п.read_text(encoding="utf-8"))
    счётные = {и for и, к in (пак.get("morph_classes") or {}).items()
               if set(к.get("forms") or []) & {"one", "many"}}
    if не := (not счётные):
        continue
    шаблоны = [t for р in (пак.get("show_kinds") or {}).values() for t in (р.get("templates") or [])]
    прямо = {м.group(1) for t in шаблоны for м in ПРЯМО.finditer(t)} & счётные
    жребием = {м.group(1) for t in шаблоны for м in ЖРЕБИЕМ.finditer(t)} & счётные
    лексем = sum(len((пак["morph_classes"][к].get("lexemes") or {})) for к in счётные)
    if жребием - прямо:
        на_волоске.append((п.stem, sorted(жребием - прямо), лексем))
    elif прямо:
        прямые.append(п.stem)
    else:
        без_счёта.append(п.stem)
print(f"{'пакет':<6}{'классы на жребии':<28}{'лексем':>8}")
for имя, классы, n in sorted(на_волоске, key=lambda x: -x[2]):
    print(f"{имя:<6}{', '.join(классы):<28}{n:>8}")
поза = "PASS" if len(на_волоске) <= ВОЛОСКОВ_РУБЕЖ else "FAIL"
print(f"ВОЛОСОК ЕДИНСТВЕННОГО {поза}: пакетов на жребии {len(на_волоске)} "
      f"(рубеж {ВОЛОСКОВ_РУБЕЖ}); прямо называют {len(прямые)}, счёта в показах нет у "
      f"{len(без_счёта)}; пакетов всего {len(на_волоске) + len(прямые) + len(без_счёта)}")
sys.exit(0 if поза == "PASS" else 1)
