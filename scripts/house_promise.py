#!/usr/bin/env python3
"""[ОБЕЩАНИЕ ДОМА] — род, ОБЪЯВЛЕННЫЙ домом и показанный меньше закона массы.

    РОД, ОБЪЯВЛЕННЫЙ ДОМОМ И ПОКАЗАННЫЙ МЕНЬШЕ ДЕВЯТИ РАЗ, ЕСТЬ ОБЕЩАНИЕ, ДАННОЕ И НЕ
    ИСПОЛНЕННОЕ. Не «редкость свода» и не «случайность»: дом сам назвал этот род своим и сам
    не дал ему массы.

ЧЕМ ЭТО НЕ ЕСТЬ МАССА РОДА (`scripts/mass_census.py`). Тот прибор считает роды, ВЫВЕДЕННЫЕ из
текста свода схлопыванием чисел и имён, — их шестьдесят пять тысяч, и восемьдесят процентов
непокупаемы. Число верное и почти неподъёмное: у выведенного рода нет хозяина, которого можно
спросить.

Здесь — роды ОБЪЯВЛЕННЫЕ. Их около тысячи, у каждого есть дом, и каждый недобор адресуем:
известно, кто обещал и чего недодал.

    ДВЕ МЕРЫ ОДНОГО ЗАКОНА РАЗЛИЧАЮТСЯ НЕ СТРОГОСТЬЮ, А АДРЕСОМ. Число без адреса зовёт к
    унынию; число с адресом зовёт к работе.

ОСВОБОЖДЕНИЕ ЧИТАЕТСЯ ТО ЖЕ, ЧТО У МЕРЫ РОВНОСТИ: род, объявленный домом в
`РОДЫ_ПО_ПРЕДМЕТУ`, в счёт не идёт — его число есть факт о предмете, а не выбор дома. Число
освобождённых печатается, чтобы освобождение не было молчаливым.

ЗАМЕР ПРИ ПОСТРОЙКЕ (13.09, после тридцати новых домов): объявленных родов 1 117 у 191 дома;
ниже девяти показов и НЕ объявленных по предмету — 89. Худшее: `speechforms · уступка` четыре
страницы против семисот двадцати у соседа по дому.

    python3 scripts/house_promise.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --двор no-such-dir
import argparse
import collections
import importlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# ПРАВИЛО ДОПУСКА ФАЙЛА БЕРЁТСЯ У УКАЗАТЕЛЯ, А НЕ ПИШЕТСЯ ЗДЕСЬ ВТОРОЙ РАЗ.
import genus_atlas as _допуск  # noqa: E402

# ЗАКОН МАССЫ ВЗЯТ У СОСЕДА, А НЕ ОБЪЯВЛЕН ЗАНОВО: девять — то же число, каким мерит
# `mass_census`, и ДВА ЧИСЛА, НАЗЫВАЮЩИЕ ОДИН ЗАКОН, СУТЬ ОДНО ЧИСЛО ИЛИ ОДНА ЛОЖЬ.
LAW2 = 9

# РУБЕЖ-ДОЛГА: НЕДОДАННЫХ_РУБЕЖ = 45
#
# РОДОВ, ОБЪЯВЛЕННЫХ ДОМОМ И НЕ ДОБРАВШИХ ДЕВЯТИ ПОКАЗОВ. Замерено 13.09: 89 из 1 074.
# Рубеж — потолок, и только опускается: платится он ПИСЬМОМ СТРАНИЦ, а не правкой меры.
#
# 89 → 88 В ТОТ ЖЕ ДЕНЬ, И ПЛАЧЕНО ИМЕННО ПИСЬМОМ. Род `speechforms · уступка` показывал
# ЧЕТЫРЕ страницы против семисот двадцати у соседа по дому; прибавлено три правила, каждое с
# ВЫЧИСЛЯЕМЫМ основанием и единственным исключением, — стало шестнадцать. Перекос дома при
# этом упал 180,0× → 51,4×.
#
#     РУБЕЖ, ОПУЩЕННЫЙ ПИСЬМОМ СТРАНИЦ, ОПУЩЕН ЧЕСТНО; РУБЕЖ, ОПУЩЕННЫЙ ПРАВКОЙ МЕРЫ,
#     ОПУЩЕН ТОЛЬКО НА БУМАГЕ.
#
# 88 → 62 ЗА ОДИН ВЕЧЕР, И ВСЁ ПИСЬМОМ: `directforms` 30 → 90 страниц (прибавка в ОДНУ
# таблицу подняла четыре рода), `angleforms` 74 → 122 (прибавка ЧИСЛАМИ, без единого нового
# слова), `pctbaseforms` 80 → 104 (две перевёрнутые пары и два объявленных основания),
# `condforms` 74 → 102 (два зависимых ящика и два независимых, проверенных крест-накрест),
# `tzoneforms` 82 → 120 (пары из тех же восьми городов), `speechforms` уступка 4 → 16.
# Двадцать семь родов перешагнули закон массы.
# 62 → 45 ЗА РАЗДЕЛЕНИЕМ ВЕЛИКАНОВ (13.09). Три дома разделили род-великан по ДЕЛУ строителя
# (`seriesforms`, `linalgforms`, `speechforms`), и роды, прежде тонувшие в общем имени, стали
# считаться порознь: объявленных родов 1 093 вместо 1 026, а недодавших девяти — 45 вместо 50.
#
#     РАЗДЕЛЕНИЕ ВЕЛИКАНА НЕ ПРИБАВЛЯЕТ СТРАНИЦ, НО ПРИБАВЛЯЕТ ЧЕСТНОСТИ СЧЁТУ: род, чьи
#     страницы считались вместе с чужими, не был ни выучен, ни назван.
НЕДОДАННЫХ_РУБЕЖ = 45


def _род(значение):
    """Имя рода из значения `ПОКАЗЫ`: строкой у новых домов, последним в кортеже у старших."""
    if isinstance(значение, str):
        return значение
    if isinstance(значение, tuple) and len(значение) >= 2:
        return значение[-1]
    return None


def недоданные(двор):
    """[(страниц, дом, род, наибольший сосед)] и (родов всего, освобождённых)."""
    вон, всего, освобождённых = [], 0, 0
    for п in sorted(pathlib.Path(двор).glob("*.py")):
        # ДОМ НАЙДЕН ПО ДЕЛУ, А НЕ ПО ОКОНЧАНИЮ ИМЕНИ ФАЙЛА (14.09). Обход брал
        # `glob("*forms.py")` — и не видел ни `measureof`, ни `relcompare`, ни
        # `totalsubj`, ни семи домов, поставленных сегодня в самих кузницах. Правило
        # допуска у корпуса ОДНО, и живёт оно в указателе родов (`genus_atlas.дом_ли`).
        #
        #     ДОМ, ЧЬЁ ОБЪЯВЛЕНИЕ МЕРА НЕ УМЕЕТ ПРОЧЕСТЬ, НЕ ПАДАЕТ ЕЁ РУБЕЖОМ — ОН
        #     ПРОСТО НЕ СУЩЕСТВУЕТ ДЛЯ НЕЁ. Этот закон записан в этом же файле, и
        #     исполнялся он лишь наполовину: мера научилась читать оба вида
        #     объявления и продолжала смотреть лишь на половину домов.
        if not _допуск.дом_ли(п):
            continue
        try:
            м = importlib.import_module(п.stem)
        except Exception:                                  # noqa: BLE001 — чужая беда не наша
            continue
        показы = getattr(м, "ПОКАЗЫ", None)
        if not isinstance(показы, dict) or not показы:
            continue
        роды = [_род(з) for з in показы.values()]
        if any(р is None for р in роды):
            continue
        счёт = collections.Counter(роды)
        if len(счёт) < 2:
            continue
        по_предмету = set(getattr(м, "РОДЫ_ПО_ПРЕДМЕТУ", None) or {})
        наибольший = max(счёт.values())
        for род, n in счёт.items():
            всего += 1
            if род in по_предмету:
                освобождённых += 1
                continue
            if n < LAW2:
                вон.append((n, п.stem, род, наибольший))
    вон.sort()
    return вон, всего, освобождённых


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: мера обязана считать ОБЪЯВЛЕННЫЕ роды и чтить освобождение.

    Прибор, зеленеющий от нуля находок, обязан доказать, что умеет находить.
    """
    import tempfile                                       # noqa: PLC0415
    беды = []
    with tempfile.TemporaryDirectory() as д:
        д = pathlib.Path(д)
        # ГУСТОЙ РОД ОБЯЗАН БЫТЬ ГУСТЫМ ПО ЗАКОНУ, А НЕ НА ВИД: первая редакция пробы дала
        # ему две страницы и объявила ошибкой то, что мера верно сочла недобором.
        #
        #     ПРОБА, ПОСТРОЕННАЯ НЕ ПО ЗАКОНУ, КОТОРЫЙ ПРОБУЕТ, СУДИТ МЕРУ ПО СВОЕЙ ОШИБКЕ.
        густо = ", ".join(f'"г{i}": "густой"' for i in range(LAW2 + 1))
        (д / "пробаforms.py").write_text(
            "ПОКАЗЫ = {" + густо + ', "в": "тощий"}\n'
            'РОДЫ_ПО_ПРЕДМЕТУ = {}\n', encoding="utf-8")
        (д / "вольныйforms.py").write_text(
            "ПОКАЗЫ = {" + густо + ', "в": "тощий"}\n'
            'РОДЫ_ПО_ПРЕДМЕТУ = {"тощий": "их столько и есть"}\n', encoding="utf-8")
        sys.path.insert(0, str(д))
        try:
            ряд, всего, свободных = недоданные(д)
        finally:
            sys.path.remove(str(д))
        имена = {(дом, род) for _n, дом, род, _б in ряд}
        if ("пробаforms", "тощий") not in имена:
            беды.append("НЕДОБОР НЕ ПОЙМАН: род о трёх показах сочтён исполненным")
        if ("вольныйforms", "тощий") in имена:
            беды.append("ОСВОБОЖДЕНИЕ НЕ ЧТИМО: род по предмету сочтён недоданным")
        if свободных != 1:
            беды.append(f"освобождённых сочтено {свободных}, а объявлен один")
        if ("пробаforms", "густой") in имена:
            беды.append("ГУСТОЙ РОД СОЧТЁН НЕДОДАННЫМ — мера считает не то")
    return беды


def main():
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ОБЕЩАНИЕ ДОМА ОТКАЗ: счёт недобора не доказан ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser(description="род объявленный и показанный меньше закона массы")
    ап.add_argument("--двор", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    двор = pathlib.Path(дов.двор) if дов.двор else КОРЕНЬ / "tools"
    if not двор.is_dir():
        print(f"ОБЕЩАНИЕ ДОМА ОТКАЗ: двора нет — {двор}")
        return 2
    ряд, всего, свободных = недоданные(двор)
    if not всего:
        print(f"ОБЕЩАНИЕ ДОМА ОТКАЗ: домов с объявленными родами в «{двор}» нет")
        return 2
    показать = ряд if дов.подробно else ряд[:12]
    for n, дом, род, наиб in показать:
        print(f"  НЕДОДАНО {дом} · {род}: {n} страниц при {наиб} у соседа по дому")
    if not дов.подробно and len(ряд) > len(показать):
        print(f"  … и ещё {len(ряд) - len(показать)}; поимённо — с доводом --подробно")
    поза = "PASS" if len(ряд) <= НЕДОДАННЫХ_РУБЕЖ else "FAIL"
    домов = len({д for _n, д, _р, _б in ряд})
    print(f"ОБЕЩАНИЕ ДОМА {поза}: родов объявлено и НЕ ДОБРАЛО девяти показов {len(ряд)} "
          f"(рубеж {НЕДОДАННЫХ_РУБЕЖ}) из {всего} объявленных, в {домов} домах; "
          f"по предмету вне счёта {свободных}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
