#!/usr/bin/env python3
"""[САМОПРОВЕРКА ДОМА] — дом, чью самопроверку никто не зовёт, красен молча.

    ПРИБОР, КОТОРОГО НАБОР НЕ ГОНЯЕТ, ПАДАЕТ МОЛЧА — И ЭТОТ ЗАКОН ДЕЙСТВУЕТ ЭТАЖОМ НИЖЕ ТОЖЕ.
    Набор зовёт суды и приборы; САМОПРОВЕРКИ ДОМОВ он не звал никогда, и звали их рукой.

ПОВОД, И ОН НАЙДЕН СЛУЧАЙНО. 09.09, правя дом поведения, я запустил его самопроверку — и она
упала на строке, которой я не касался: «parce que une personne est fatiguée». Дом строит свои
ПОКАЗЫ через французскую элизию (`_fr.элизия`), а самопроверка звала рамку НАПРЯМУЮ и потому
проверяла страницу, которой в мире нет.

    ПРОВЕРКА, ИДУЩАЯ ИНЫМ ПУТЁМ, ЧЕМ ДЕЛО, ПРОВЕРЯЕТ НЕ ДЕЛО.

Замер по всему парку нашёл второй такой дом (`linkforms`) с той же бедой. Оба вылечены; прибор
поставлен, чтобы третий нашёлся в час своего рождения, а не через месяц.

ЧТО СЧИТАЕТСЯ ДОМОМ С САМОПРОВЕРКОЙ: файл `tools/*.py` (кроме кузниц `gen_*`), несущий
`if __name__ == "__main__"`. Таких 103 из 167.

ОРУДИЯ, ТРЕБУЮЩИЕ ДОВОДОВ, ОБЪЯВЛЕНЫ ПОИМЁННО, А НЕ УГАДАНЫ ПО КОДУ ВОЗВРАТА. Девять файлов
парка суть не дома, а орудия руки: движок пакетов ждёт имени пакета, добытчики полки — каталога
кэша. Зов их без доводов даёт «error: the following arguments are required» и код 2 — не
падение дома, а отказ орудия. Список объявлен здесь; орудие, забытое в нём, уронит прибор, и
это лучше, чем правило «код 2 прощается», под которое спрячется настоящее падение.

    python3 scripts/house_selfcheck.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --парк no-such-dir
import pathlib
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: КРАСНЫХ_РУБЕЖ = 0
#
# Поставлен на двух и закрыт в тот же час: `behaviorforms` и `linkforms`, обе беды одной
# природы — проверка шла мимо элизии. Рубеж есть ПОЛ: дом, чья самопроверка упадёт завтра,
# роняет прибор в тот же день.
КРАСНЫХ_РУБЕЖ = 0

# ОРУДИЯ РУКИ, А НЕ ДОМА: зовутся с доводами и без них отказываются по праву.
ОРУДИЯ = frozenset({
    "langpack",      # движок пакетов: ждёт имени пакета
    "mass_slices",   # режет полосу: ждёт --в
    "shelf_fetch", "shelf_forge", "shelf_libru", "shelf_open",
    "shelf_scan", "shelf_tex", "shelf_wiki",   # добытчики полки: ждут --кэш
    "verdicts",      # отказывается по закону разделения труда, и это его вердикт
    # ТРИ ОРУДИЯ РУКИ 11–12.09, И ДВА ИЗ НИХ ОПАСНЫ НЕ ОТКАЗОМ, А СОГЛАСИЕМ.
    #
    # `world_probe` ждёт имени мира и без него отказывает кодом 2 — беда обычная.
    # Но `law_atlas` и `court_atlas` без доводов работают ОХОТНО: они ПЕРЕСОБИРАЮТ
    # свои отчёты. Самопроверка звала бы их при всяком наборе, и указатели свода
    # переписывались бы ПОСРЕДИ СУДА — а рядом стои́т `world_atlas`, который судит
    # РАСХОЖДЕНИЕ отчёта с манифестом.
    #
    #     ОРУДИЕ, ПЕРЕПИСЫВАЮЩЕЕ ДЕРЕВО, ОПАСНЕЕ ТОГО, ЧТО ОТКАЗЫВАЕТ: отказ виден
    #     сразу, а правка посреди суда делает вердикт соседа случайным.
    "world_probe",   # замер мира: ждёт имени мира
    "law_atlas",     # указатель законов: без доводов ПЕРЕСОБИРАЕТ отчёт
    "court_atlas",   # указатель приборов: без доводов ПЕРЕСОБИРАЕТ отчёт
})
СЕКУНД = 240


def дома(парк):
    """Дома парка, несущие самопроверку, — найдены делом, а не списком."""
    вон = []
    for путь in sorted(парк.glob("*.py")):
        if путь.stem.startswith("gen_"):
            continue
        try:
            текст = путь.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if '__name__ == "__main__"' in текст:
            вон.append(путь)
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ДОМ С САМОПРОВЕРКОЙ НАХОДИТСЯ и что
    КРАСНЫЙ ВОЗВРАТ ЗАМЕЧАЕТСЯ.

        ЭТОТ ПРИБОР ГОНЯЕТ САМОПРОВЕРКИ ВСЕХ ДОМОВ, И ДВЕ ЕГО ПОРЧИ ТИХИ. Пусть признак
        дома перестанет узнавать самопроверку — и домов станет ноль, а «красных 0» будет
        правдой о пустом списке. Пусть возврат перестанет читаться — и красный дом
        пройдёт зелёным.

        СЕГОДНЯ ЭТОТ ПРИБОР НАШЁЛ КРАСНЫЙ ДОМ, КОТОРЫЙ СЛОМАЛА УТРЕННЯЯ ПРАВКА, — и это
        ровно то, ради чего он стои́т. Оттого его проба спрашивает оба признака.

    Три дома во временном парке: зелёный, красный и без самопроверки вовсе.
    """
    import subprocess
    import tempfile
    беды = []
    with tempfile.TemporaryDirectory() as д:
        парк = pathlib.Path(д)
        (парк / "зелёный.py").write_text(
            'import sys\n\n\ndef _самопроверка():\n    return 0\n\n\n'
            'if __name__ == "__main__":\n    sys.exit(_самопроверка())\n', encoding="utf-8")
        (парк / "красный.py").write_text(
            'import sys\n\n\ndef _самопроверка():\n    return 1\n\n\n'
            'if __name__ == "__main__":\n    sys.exit(_самопроверка())\n', encoding="utf-8")
        (парк / "немой.py").write_text("ФОРМЫ = {}\n", encoding="utf-8")
        (парк / "gen_кузня.py").write_text(
            'if __name__ == "__main__":\n    pass\n', encoding="utf-8")
        найдены = sorted(п.stem for п in дома(парк))
        # КУЗНЯ НЕ ЕСТЬ ДОМ, И НЕМОЙ ФАЙЛ НЕ ЕСТЬ ДОМ: в парке пробы их по одному,
        # и найтись обязаны ровно двое.
        if найдены != ["зелёный", "красный"]:
            беды.append(f"дома парка: {найдены} вместо ['зелёный', 'красный']")
        коды = {}
        for имя in ("зелёный", "красный"):
            коды[имя] = subprocess.run([sys.executable, str(парк / f"{имя}.py")],
                                       capture_output=True).returncode
    if коды.get("зелёный") != 0:
        беды.append(f"зелёный дом дал {коды.get('зелёный')} вместо 0")
    if коды.get("красный") == 0:
        беды.append("КРАСНЫЙ ДОМ ДАЛ НОЛЬ — возврат самопроверки не читается")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"САМОПРОВЕРКА ДОМА ОТКАЗ: признаки не доказаны ({len(беды)} бед)")
        return 2
    парк = КОРЕНЬ / "tools"
    if "--парк" in sys.argv:
        парк = pathlib.Path(sys.argv[sys.argv.index("--парк") + 1])
    if not парк.is_dir():
        print(f"САМОПРОВЕРКА ДОМА ОТКАЗ: нет каталога парка {парк}")
        return 2
    пути = дома(парк)
    if not пути:
        print(f"САМОПРОВЕРКА ДОМА ОТКАЗ: ни одного дома с самопроверкой в {парк}")
        return 2
    красные, орудий = [], 0
    for путь in пути:
        if путь.stem in ОРУДИЯ:
            орудий += 1
            continue
        try:
            r = subprocess.run([sys.executable, str(путь)], cwd=КОРЕНЬ,
                               capture_output=True, text=True, timeout=СЕКУНД)
        except subprocess.TimeoutExpired:
            красные.append((путь.stem, "не кончил за %d с" % СЕКУНД))
            continue
        if r.returncode != 0:
            хвост = (r.stderr or r.stdout).strip().split("\n")[-1][:110]
            красные.append((путь.stem, f"rc={r.returncode}: {хвост}"))
    for имя, беда in красные:
        print(f"  КРАСЕН {имя} — {беда}")
    поза = "PASS" if len(красные) <= КРАСНЫХ_РУБЕЖ else "FAIL"
    print(f"САМОПРОВЕРКА ДОМА {поза}: домов с самопроверкой {len(пути) - орудий}, "
          f"КРАСНЫХ {len(красные)} (рубеж {КРАСНЫХ_РУБЕЖ}); орудий руки {орудий} — "
          f"объявлены поимённо и не зовутся")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
