"""[САМОПРОВЕРКА ДОМА] — дом, чью самопроверку никто не зовёт, красен молча.

    ПРИБОР, КОТОРОГО НАБОР НЕ ГОНЯЕТ, ПАДАЕТ МОЛЧА — И ЭТОТ ЗАКОН ДЕЙСТВУЕТ ЭТАЖОМ НИЖЕ ТОЖЕ.
    Набор зовёт суды и приборы; САМОПРОВЕРКИ ДОМОВ он не звал никогда, и звали их рукой.

ПОВОД, И ОН НАЙДЕН СЛУЧАЙНО. 09.09, правя дом поведения, я запустил его самопроверку — и она
упала на строке, которой я не касался: «parce que une personne est fatiguée». Дом строит свои
ПОКАЗЫ через французскую элизию (`_fr.элизия`), а самопроверка звала рамку НАПРЯМУЮ и потому
проверяла страницу, которой в мире нет.

    ПРОВЕРКА, ИДУЩАЯ ИНЫМ ПУТЁМ, ЧЕМ ДЕЛО, ПРОВЕРЯЕТ НЕ ДЕЛО.

Замер по всему парку нашёл второй такой дом (`linkforms`) с той же бедой. Оба вылечены; прибор
поставлен, чтобы третий нашёлся в час своего рождения, а не через месяц.

ЧТО СЧИТАЕТСЯ ДОМОМ С САМОПРОВЕРКОЙ: файл `tools/*.py` (кроме кузниц `gen_*`), несущий
`if __name__ == "__main__"`. Таких 103 из 167.

ОРУДИЯ, ТРЕБУЮЩИЕ ДОВОДОВ, ОБЪЯВЛЕНЫ ПОИМЁННО, А НЕ УГАДАНЫ ПО КОДУ ВОЗВРАТА. Девять файлов
парка суть не дома, а орудия руки: движок пакетов ждёт имени пакета, добытчики полки — каталога
кэша. Зов их без доводов даёт «error: the following arguments are required» и код 2 — не
падение дома, а отказ орудия. Список объявлен здесь; орудие, забытое в нём, уронит прибор, и
это лучше, чем правило «код 2 прощается», под которое спрячется настоящее падение.

    python3 scripts/house_selfcheck.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --парк no-such-dir
import pathlib
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: КРАСНЫХ_РУБЕЖ = 0
#
# Поставлен на двух и закрыт в тот же час: `behaviorforms` и `linkforms`, обе беды одной
# природы — проверка шла мимо элизии. Рубеж есть ПОЛ: дом, чья самопроверка упадёт завтра,
# роняет прибор в тот же день.
КРАСНЫХ_РУБЕЖ = 0

# ОРУДИЯ РУКИ, А НЕ ДОМА: зовутся с доводами и без них отказываются по праву.
ОРУДИЯ = frozenset({
    "langpack",      # движок пакетов: ждёт имени пакета
    "mass_slices",   # режет полосу: ждёт --в
    "shelf_fetch", "shelf_forge", "shelf_libru", "shelf_open",
    "shelf_scan", "shelf_tex", "shelf_wiki",   # добытчики полки: ждут --кэш
    "verdicts",      # отказывается по закону разделения труда, и это его вердикт
})
СЕКУНД = 240


def дома(парк):
    """Дома парка, несущие самопроверку, — найдены делом, а не списком."""
    вон = []
    for путь in sorted(парк.glob("*.py")):
        if путь.stem.startswith("gen_"):
            continue
        try:
            текст = путь.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if '__name__ == "__main__"' in текст:
            вон.append(путь)
    return вон


def main():
    парк = КОРЕНЬ / "tools"
    if "--парк" in sys.argv:
        парк = pathlib.Path(sys.argv[sys.argv.index("--парк") + 1])
    if not парк.is_dir():
        print(f"САМОПРОВЕРКА ДОМА ОТКАЗ: нет каталога парка {парк}")
        return 2
    пути = дома(парк)
    if not пути:
        print(f"САМОПРОВЕРКА ДОМА ОТКАЗ: ни одного дома с самопроверкой в {парк}")
        return 2
    красные, орудий = [], 0
    for путь in пути:
        if путь.stem in ОРУДИЯ:
            орудий += 1
            continue
        try:
            r = subprocess.run([sys.executable, str(путь)], cwd=КОРЕНЬ,
                               capture_output=True, text=True, timeout=СЕКУНД)
        except subprocess.TimeoutExpired:
            красные.append((путь.stem, "не кончил за %d с" % СЕКУНД))
            continue
        if r.returncode != 0:
            хвост = (r.stderr or r.stdout).strip().split("\n")[-1][:110]
            красные.append((путь.stem, f"rc={r.returncode}: {хвост}"))
    for имя, беда in красные:
        print(f"  КРАСЕН {имя} — {беда}")
    поза = "PASS" if len(красные) <= КРАСНЫХ_РУБЕЖ else "FAIL"
    print(f"САМОПРОВЕРКА ДОМА {поза}: домов с самопроверкой {len(пути) - орудий}, "
          f"КРАСНЫХ {len(красные)} (рубеж {КРАСНЫХ_РУБЕЖ}); орудий руки {орудий} — "
          f"объявлены поимённо и не зовутся")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
