#!/usr/bin/env python3
"""[АРТИКЛЬ ПО ЗВУКУ] — английское «a/an» и артикль романских при вещи иного рода.

    АРТИКЛЬ, ВЫНЕСЕННЫЙ В РАМКУ, ПЕРЕСТАЁТ СЛЫШАТЬ СЛОВО, ПЕРЕД КОТОРЫМ СТОИТ.

ТРЕТИЙ ЛИК ОДНОЙ БОЛЕЗНИ (08.09). Дня этого корпус трижды нашёл одно и то же: связка,
написанная буквой, не гнулась числом; причастие, вынесенное в рамку, не гнулось родом; ныне —
артикль, вынесенный туда же, не гнётся ни родом вещи, ни её начальным ЗВУКОМ.

    «a apple», «a egg», «a hour», «a insect», «a eye», «a axe», «a onion», «a orange»
        — 106 строк в семи мирах: money 40, lang_en 29, everyday 16, svamp 8, nature 7,
          money_story 4, conversions 2;
    «ein Pfote», «ein Hand», «ein Farbe», «une œil», «una colore», «una pianeta»
        — двадцать строк дома природы, где артикль части стоял литералом.

ЗВУК НЕ ВЫВОДИТСЯ ИЗ ПИСЬМА, И ОБЕ СТОРОНЫ ОБЪЯВЛЕНЫ ПОИМЁННО (`plural.СОГЛАСНЫЙ_ЗВУК`,
`plural.ГЛАСНЫЙ_ЗВУК`): английское «u» чаще звучит согласной («a unit», «a user», «a one-shot»),
а «h» бывает немой («an hour», «an honest answer»). Прибор берёт закон у дома языка и не
знает английского сам.

ГРАНИЦА: судятся лишь строки, признанные АНГЛИЙСКИМИ по знаку языка (`langsign`), — иначе
испанское «es igual a ocho» и французское «a acheté» пошли бы в счёт. Первая редакция меры
насчитала 2884 обвинения, из которых честных было 106.

    МЕРА, НЕ СПРАШИВАЮЩАЯ О ЯЗЫКЕ СТРОКИ, СУДИТ ЧУЖУЮ РЕЧЬ СВОИМ ЗАКОНОМ.

    python3 scripts/article_sound.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --папка no-such-dir
import argparse
import collections
import importlib
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import langsign  # noqa: E402 — знак языка: чья это строка
import plural  # noqa: E402 — дом английского языка, объявивший звук

# РУБЕЖ-ДОЛГА: НЕ_ПО_ЗВУКУ_РУБЕЖ = 0
#
# НОЛЬ ОТ РОЖДЕНИЯ: сто шесть строк найдены и вылечены в тот же час — семь домов, один пакет
# и движок пакетов получили артикль дырой, гнущейся звуком. Долг, закрытый прежде объявления
# рубежа, объявляется нулём, а не своим прежним числом.
НЕ_ПО_ЗВУКУ_РУБЕЖ = 0

# РУБЕЖ-ДОЛГА: ПРОПУЩЕНО_РУБЕЖ = 0
#
# ПАЛАТА, НАЗЫВАЮЩАЯ ПОРЧУ АРТИКЛЯ ИСТИНОЙ, ЕСТЬ ДОЛГ. Спрашивается ПАЛАТА, а не дом: закон
# артикля объявлен корпусу и живёт одним судом (`courts/article_court.py`), и слепота дома
# есть не долг, а устройство.
ПРОПУЩЕНО_РУБЕЖ = 0

ОБРАЗЦОВ = 40
ПАРА = re.compile(r"\b(an?) ([a-z]+)\b")


def _объявленные():
    """Имена, объявленные английским пакетом, — и только они судятся.

    ПЕРВАЯ РЕДАКЦИЯ СУДИЛА ВСЯКОЕ СЛОВО ЗА АРТИКЛЕМ И ДАЛА 954 ОБВИНЕНИЯ, ЧЕСТНЫХ ИЗ КОТОРЫХ
    НЕ БЫЛО НИ ОДНОГО:

        «the sum of a and 17» — «a» есть ПЕРЕМЕННАЯ, а не артикль, и «and» не имя;
        «an ultimate», «an unordered» — верно: «u» тут звучит гласной, и правило по букве,
            выведшее «u» из гласных ради «a unit», лжёт о ней в другую сторону;
        «an mdx» — верно: буква «m» зовётся /em/, и сокращение читается по именам букв.

        МЕРА, СУДЯЩАЯ СЛОВО, КОТОРОГО ЯЗЫК ЕЙ НЕ ОБЪЯВЛЯЛ, МЕРЯЕТ СВОЮ ДОГАДКУ.

    Оттого судится лишь то, что пакет ОБЪЯВИЛ именем: там звук известен, ибо слово известно.
    Молчание о прочем есть честная граница, а не зачёт.
    """
    вон = set()
    путь = КОРЕНЬ / "tools" / "langpacks" / "en.json"
    try:
        пакет = __import__("json").loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return frozenset()
    for имя, кл in (пакет.get("morph_classes") or {}).items():
        if not имя.startswith("noun"):
            continue
        for формы in (кл.get("lexemes") or {}).values():
            вон.update(str(ф).lower() for ф in формы if str(ф).isalpha())
    return frozenset(вон)


ОБЪЯВЛЕННЫЕ = _объявленные()


def английская(строка):
    """Строка ли это английской речи — по знаку языка, а не по буквам."""
    вон = langsign.счёт(строка)
    if not вон:
        return False
    лучший = max(вон, key=lambda я: вон[я])
    return лучший == "en" and вон[лучший] > 0


def обвинения(строка):
    """[(артикль, слово, ждём)] — артикли строки, стоящие не по звуку своего слова."""
    вон = []
    for артикль, слово in ПАРА.findall(строка.lower()):
        if слово not in ОБЪЯВЛЕННЫЕ:
            continue                            # слово пакету не объявлено — не судим
        ждём = plural.article(слово)
        if артикль != ждём:
            вон.append((артикль, слово, ждём))
    return вон


def палата():
    """Палата целиком: закон артикля живёт ОДНИМ судом, и спрашивать надо её, а не дом.

    ПЕРВАЯ РЕДАКЦИЯ ВТОРОГО ЭТАЖА СПРАШИВАЛА КАЖДЫЙ ДОМ и насчитала семь слепых — верный
    замер неверного вопроса. Дом артикля не судит и судить не обязан: закон объявлен
    корпусу, а не дому, и живёт в `courts/article_court.py`.

        ЕСЛИ ЗАКОН ОТДАН ОДНОМУ СУДУ, СЛЕПОТА ДОМА ЕСТЬ НЕ ДОЛГ, А УСТРОЙСТВО.
    """
    sys.path.insert(0, str(КОРЕНЬ / "courts"))
    import panel                                # noqa: PLC0415 — палата собирается долго
    return panel.палата()


def подмена(строка):
    """Строка с ОДНИМ артиклем, подменённым на другую его форму, — или None.

    ПОРТИТСЯ ЛИШЬ АНГЛИЙСКАЯ СТРОКА И ЛИШЬ ПРИ ОБЪЯВЛЕННОМ ИМЕНИ: первая редакция портила
    французское «il y a des fichiers» в «il y an des fichiers» и звала сорок два дома
    слепыми — верный замер неверного вопроса.
    """
    if not английская(строка):
        return None
    for м in ПАРА.finditer(строка.lower()):
        if м.group(2) not in ОБЪЯВЛЕННЫЕ:
            continue
        иной = "an" if м.group(1) == "a" else "a"
        битая = строка[:м.start(1)] + иной + строка[м.end(1):]
        if обвинения(битая) and not обвинения(строка):
            return битая
    return None


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--папка", default="datasets")
    дов = ап.parse_args()
    корень = КОРЕНЬ / дов.папка
    миры = sorted(корень.glob("genesis_*.txt")) if корень.is_dir() else []
    if not миры:
        print(f"АРТИКЛЬ ПО ЗВУКУ ОТКАЗ: миров в «{дов.папка}» нет")
        return 2

    плохо, по_мирам, прим, всего = 0, collections.Counter(), {}, 0
    for мир in миры:
        for строка in мир.read_text(encoding="utf-8", errors="replace").splitlines():
            if "a " not in строка and "an " not in строка:
                continue
            if not английская(строка):
                continue
            всего += len(ПАРА.findall(строка.lower()))
            for артикль, слово, ждём in обвинения(строка):
                плохо += 1
                по_мирам[мир.name] += 1
                прим.setdefault((мир.name, артикль, слово), (строка[:88], ждём))
    print(f"СТРАНИЦЫ: миров {len(миры)}, английских артиклей {всего}, НЕ ПО ЗВУКУ {плохо}")
    for (мир, артикль, слово), n in sorted(прим.items()):
        строка, ждём = прим[(мир, артикль, слово)]
        print(f"  НЕ ПО ЗВУКУ {мир} «{артикль} {слово}» → «{ждём} {слово}»\n       «{строка}»")

    П = палата()
    проб = поймано = пропущено = 0
    первая = None
    for мир in миры:
        if проб >= ОБРАЗЦОВ:
            break
        for строка in мир.read_text(encoding="utf-8", errors="replace").splitlines():
            if проб >= ОБРАЗЦОВ:
                break
            битая = подмена(строка)
            if битая is None:
                continue
            проб += 1
            судимо, истинно = П.судить(битая)[:2]
            if судимо and not истинно:
                поймано += 1
            else:
                пропущено += 1
                первая = первая or битая
    print(f"ПАЛАТА: проб {проб}, поймано {поймано}, ПРОПУЩЕНО {пропущено}")
    if первая is not None:
        print(f"  ПРОПУЩЕНА: «{первая[:96]}»")

    поза = ("PASS" if плохо <= НЕ_ПО_ЗВУКУ_РУБЕЖ and пропущено <= ПРОПУЩЕНО_РУБЕЖ
            else "FAIL")
    print(f"АРТИКЛЬ ПО ЗВУКУ {поза}: строк не по звуку {плохо} (рубеж {НЕ_ПО_ЗВУКУ_РУБЕЖ}); "
          f"палата пропустила {пропущено} из {проб} (рубеж {ПРОПУЩЕНО_РУБЕЖ}), "
          f"поймала {поймано}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
