"""[ОТКАЗ БЕЗ ДОМА СВОЕГО ЯЗЫКА] — сколько отказов названо домом ТОГО ЖЕ языка, а не вообще.

    ОТКАЗ, ОБЪЯСНЁННЫЙ ОБЩИМ ДОМОМ, НЕ ОБЪЯСНЁН ДОМОМ СВОЕГО ЯЗЫКА: первый называет ПРИЧИНУ
    («agreement»), второй — ЗАКОН («после числа больше единицы стои́т партитив»). Это разная
    глубина, и мера, их смешавшая, показала бы полноту там, где её нет.

ПОВОД, ПРОЖИТЫЙ 13.09. В тот же день поставлены две меры об отказах, и вторая едва не погасила
первую. `refusal_reason` считает ПЛАСТЫ, у которых есть дом (28 из 29). Дом причины отказа
(`refusalwhyforms`) цитирует ВСЕ 150 отказов — и всякая мера вида «процитирован ли отказ хоть
кем-нибудь» после него показала бы 150 из 150.

    ДОМ, ОБЪЯСНЯЮЩИЙ ВСЁ ОДНИМ СПОСОБОМ, ГАСИТ МЕРУ, КОТОРАЯ ИСКАЛА ОБЪЯСНЕНИЯ КАЖДОМУ
    СВОИМ. Он прав, и мера была права; спорят они не о деле, а о ГЛУБИНЕ.

Оттого здесь считается ИНОЕ: процитирован ли отказ домом, ОБЪЯВИВШИМ ЭТОТ ЯЗЫК своим
(`ЯЗЫК_ЗАКОНА`). Дом причины отказа языка не объявляет — и потому этой мерой не считается
вовсе, что верно: он и не берётся объяснять турецкую гармонию.

ЗАМЕР 13.09 ПО 150 ОТКАЗАМ ДВАДЦАТИ ДЕВЯТИ ПАКЕТОВ:

    объяснено домом СВОЕГО языка         25
    БЕЗ ДОМА СВОЕГО ЯЗЫКА               125   (agreement 64, unanswerable 32, type_mismatch 29)
    языков, где дом есть, а отказы не покрыты   28 из 28

    ДОМ ЯЗЫКА ОБЪЯСНЯЕТ ОДИН ЕГО ЗАКОН, А НЕ ЯЗЫК. У турецкого есть дом гармонии, и три
    отказа турецкого пласта им не названы; у финского — дом партитива, и три отказа мимо.
    ЗАКРЫТЫЙ ПЛАСТ НЕ ЕСТЬ ЗАКРЫТЫЕ ОТКАЗЫ.

ЦИТАТА ИЩЕТСЯ СО ЗВЁЗДОЧКОЙ, А НЕ ПОДСТРОКОЙ, И ЭТО КУПЛЕНО ПРОБОЙ. Первая редакция искала
отвергнутую строку как подстроку показов — и назвала покрытым финский отказ «kaksi talo»,
ибо дом партитива пишет ЗАМЕНУ «kaksi taloa», а замена содержит отвергнутое началом.

    ВХОЖДЕНИЕ ПОДСТРОКОЙ СЧИТАЕТ ПОКРЫТЫМ ОТКАЗ, ЧЬЯ ЗАМЕНА ЕГО СОДЕРЖИТ: «kaksi talo» есть
    начало «kaksi taloa», и мера принимает урок о ВЕРНОЙ форме за урок о неверной.

Дом, объясняющий отказ, ставит при нём ЗВЁЗДОЧКУ (`declarations/STARRED.md`), и мера ищет
именно её. Но ищет НЕ ЦЕЛИКОМ: пакет отвергает предложение («Minä näen kaksi talo»), а дом
объясняет в нём СУТЬ («*kaksi talo»), и требовать от дома повторить всё предложение значило бы
требовать пересказа вместо закона.

    ДОМ ОБЪЯСНИЛ ОТКАЗ, ЕСЛИ ЕГО ЗВЁЗДНАЯ ЦИТАТА ЕСТЬ ЧАСТЬ ОТВЕРГНУТОЙ СТРОКИ. Звезда
    отсекает ложное покрытие («kaksi taloa» звезды не носит), часть — лишнюю строгость.

Дом, показавший отвергнутое без звезды, этой мерой не считается — и верно, ибо показ без
пометы учит ошибке.

НЕ ВСЯКИЙ ОТКАЗ ЖДЁТ ДОМА ЯЗЫКА, И ЧИСЛО РАЗДЕЛЕНО НА ДВА (13.09, вечер). Из 125 непокрытых
шестьдесят один — причины «unanswerable» и «type_mismatch», и закон у них НЕ ЯЗЫКОВОЙ: «у
числа нет цвета» и «складывают числа, а не вещи разных родов» верны на всех двадцати девяти
языках разом, и дом того или иного языка тут ничего не прибавит.

    ОТКАЗ, ЧЕЙ ЗАКОН НЕ ЕСТЬ ЗАКОН ЯЗЫКА, НЕ ЖДЁТ ДОМА ЯЗЫКА. Требовать для него такого дома
    значило бы держать в долге то, что уплачено иначе — общим домом причины отказа.

    ЧИСЛО, СМЕШИВАЮЩЕЕ «ЕЩЁ НЕ СДЕЛАНО» С «ДЕЛАТЬ НЕ НАДО», СТОИ́Т НА МЕСТЕ ВЕЧНО И ПЕРЕСТАЁТ
    ЧТО-ЛИБО ЗНАЧИТЬ.

Оттого прибор называет ТРИ числа: покрытых домом языка, ЖДУЩИХ такого дома (только
«agreement») и НЕ ЖДУЩИХ его вовсе.

ЧИСЛО ЭТО — ОТЧЁТ, А НЕ РУБЕЖ, И СКАЗАНО ПОЧЕМУ: уплата тут есть ДОМ, а дом строится не ради
покрытия, а ради закона, который стои́т назвать. Тридцать два отказа «unanswerable» и двадцать
девять «type_mismatch» суть ОДИН закон каждый, сказанный на двадцати девяти языках, и требовать
для них двадцати девяти домов значило бы просить двадцать девять раз об одном.

    МЕРА, ТРЕБУЮЩАЯ ПОЛНОТЫ ОТ ТОГО, ЧТО РАСТЁТ ПО ОДНОМУ, ТОРОПИТ ПИСЦА И ПОРТИТ РАБОТУ.

    python3 scripts/refusal_house.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --двор no-such-dir
#
# ПРИЧИНЫ, ЧЕЙ ЗАКОН НЕ ЕСТЬ ЗАКОН ЯЗЫКА. Объявлены поимённо: список этот растёт лишь рукой,
# и всякое имя в нём — решение, а не умолчание.
import argparse
import collections
import importlib
import json
import pathlib
import re as _re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))


НЕ_ЯЗЫКОВЫЕ = frozenset({"unanswerable", "type_mismatch"})


def дома_по_языкам(двор):
    """{код языка: [(имя дома, слитый текст его показов)]} — по объявленному `ЯЗЫК_ЗАКОНА`."""
    вон = collections.defaultdict(list)
    for п in sorted(pathlib.Path(двор).glob("*forms.py")):
        try:
            м = importlib.import_module(п.stem)
        except Exception:                               # noqa: BLE001
            continue
        коды = getattr(м, "ЯЗЫК_ЗАКОНА", None)
        if not коды:
            continue
        if isinstance(коды, str):
            коды = (коды,)
        # БЕРУТСЯ ЛИШЬ ЗВЁЗДНЫЕ ЦИТАТЫ ДОМА, а не весь его текст: закон о невозможном
        # сказан звездой, и она же отличает урок об ошибке от урока о верной форме.
        звёздные = frozenset(
            ц[1:] for п_ in getattr(м, "ПОКАЗЫ", {})
            for ц in _re.findall(r"«([^»]+)»", п_) if ц.startswith("*"))
        for к in коды:
            вон[к].append((п.stem, звёздные))
    return вон


# ЗНАКИ КОНЦА ФРАЗЫ — ВСЕХ ПИСЬМЁН, А НЕ ТОЛЬКО ЛАТИНСКОГО (13.09). Список держал точку,
# идеографическую точку, полноширинный и обычный вопросительные знаки и восклицательный, — и
# не держал арабского «؟» (ar, fa), греческого «;» и деванагарской данды «।» (hi): шестнадцать
# отвергнутых строк оставались с хвостом. Мера ищет звёздную цитату дома ВНУТРИ отвергнутой
# строки, и потому необрезанный хвост опасен не здесь, а у ДОМА: цитата, сохранившая точку,
# длиннее строки, внутри которой её ищут, — и дом, честно объяснивший отказ, считается
# молчащим. Так пять японских и китайских отказов уже считались необъяснёнными.
#
#     ДВЕ МЕРЫ, ОБРЕЗАЮЩИЕ ОДНУ СТРОКУ РАЗНЫМИ НАБОРАМИ ЗНАКОВ, НЕ НАЙДУТ ДРУГ ДРУГА. Знак
#     конца фразы есть свойство ПИСЬМА, и список его полон лишь тогда, когда в нём есть
#     письмена всех пластов свода.
КОНЕЦ_ФРАЗЫ = ".。？?!।؟; "


def отказы(пакеты):
    """[(код, отвергнутое, причина)] — из объявлений пакетов."""
    вон = []
    for п in sorted(pathlib.Path(пакеты).glob("*.json")):
        тело = json.loads(п.read_text(encoding="utf-8"))
        роды = (тело.get("show_kinds") or {}).get("refusals") or {}
        for пр in роды.get("pairs", ()):
            bad = (пр.get("bad") or "").rstrip(КОНЕЦ_ФРАЗЫ)
            if bad:
                вон.append((п.stem, bad, пр.get("reason", "без причины")))
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что прибор УМЕЕТ находить цитату.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ НУЛЯ НЕПОКРЫТЫХ. Пусть чтение показов сломается — и всякий
        отказ объявится непокрытым, что видно; но пусть сломается чтение ОТКАЗОВ — и прибор
        скажет «без дома 0», сверив НОЛЬ ОТКАЗОВ.

    Проба на выдуманных данных: три отказа, два дома, и заведомо известно, какой покрыт.
    """
    дома = {"tr": [("trharmforms", frozenset({"beş kediler"}))],
            "fi": [("fipartforms", frozenset())]}
    пары = [("tr", "ben beş kediler görüyorum", "agreement"),
            ("fi", "Minä näen kaksi talo", "agreement"),
            ("ru", "два кот", "agreement")]
    покрыт = [к for к, bad, _r in пары
              if any(ц in bad for _и, зв in дома.get(к, ()) for ц in зв)]
    беды = []
    if покрыт != ["tr"]:
        беды.append(f"покрытым назван {покрыт}, а заведомо известен только «tr»")
    if not дома or not пары:
        беды.append("проба пуста — сверять нечего")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ОТКАЗ БЕЗ ДОМА ЯЗЫКА ОТКАЗ: чтение цитаты не доказано ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--двор", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    двор = pathlib.Path(дов.двор) if дов.двор else КОРЕНЬ / "tools"
    if not двор.is_dir():
        print(f"ОТКАЗ БЕЗ ДОМА ЯЗЫКА ОТКАЗ: двора нет — {двор}")
        return 2
    пакеты = двор / "langpacks"
    if not пакеты.is_dir():
        print(f"ОТКАЗ БЕЗ ДОМА ЯЗЫКА ОТКАЗ: пакетов нет — {пакеты}")
        return 2
    дома = дома_по_языкам(двор)
    ряд = отказы(пакеты)
    if not ряд:
        print("ОТКАЗ БЕЗ ДОМА ЯЗЫКА ОТКАЗ: отказов в объявлениях пакетов нет")
        return 2
    покрыто, без = 0, collections.Counter()
    непокрытые = collections.defaultdict(list)
    for код, bad, причина in ряд:
        свои = дома.get(код, ())
        if any(ц in bad for _и, зв in свои for ц in зв):
            покрыто += 1
        else:
            без[причина] += 1
            if причина not in НЕ_ЯЗЫКОВЫЕ:
                непокрытые[код].append((причина, bad))
    с_домом = {к for к in непокрытые if дома.get(к)}
    роспись = ", ".join(f"{п} {n}" for п, n in sorted(без.items(), key=lambda x: -x[1])
                        if п not in НЕ_ЯЗЫКОВЫЕ)
    if дов.подробно:
        for код in sorted(непокрытые):
            имена = ", ".join(и for и, _з in дома.get(код, ())) or "дома нет"
            for причина, bad in непокрытые[код]:
                print(f"  [{код}] {причина:<14} «{bad[:44]}»   ({имена})")
    else:
        for код in sorted(с_домом)[:10]:
            имена = ", ".join(и for и, _з in дома[код])
            print(f"  {код}: не названо {len(непокрытые[код])} отказов, а дом есть — {имена}")
    ждут = sum(n for п, n in без.items() if п not in НЕ_ЯЗЫКОВЫЕ)
    не_ждут = sum(без.values()) - ждут
    print(f"ОТКАЗ БЕЗ ДОМА ЯЗЫКА ОТЧЁТ: отказов {len(ряд)}; объяснено домом СВОЕГО языка "
          f"{покрыто}; ЖДУТ ДОМА ЯЗЫКА {ждут} ({роспись}); НЕ ЖДУТ ЕГО ВОВСЕ {не_ждут} "
          f"({', '.join(sorted(НЕ_ЯЗЫКОВЫЕ))} — закон их не языковой); языков, где дом есть, "
          f"а отказы ждут, {len(с_домом)} из {len(дома)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
