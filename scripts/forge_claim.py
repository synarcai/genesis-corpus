#!/usr/bin/env python3
"""[ЦЕЛЬ ЗАНЯТА] — две кузни на один мир, два дома на одно имя, два суда на одно дело.

ПОВОД — МОЯ ЖЕ ОШИБКА 12.09, И ОНА СТОИЛА ТРЁХ ЗАТЁРТЫХ ФАЙЛОВ. Новый дом был назван
`speechforms`, кузня его написала `datasets/genesis_speech.txt` — и затёрла УЖЕ СУЩЕСТВОВАВШИЙ
мир в 322 килобайта; тем же движением легли суд связи речи и его кузня. Всё трое вернулись из
свода, но вернулись УДАЧЕЙ, а не порядком.

    ИМЯ, НЕ СПРОШЕННОЕ У СВОДА, БЫВАЕТ ЗАНЯТО; И КУЗНЯ НЕ СПРАШИВАЕТ — ОНА ПИШЕТ.

    ПРОВЕРКА ЗАНЯТОСТИ, СДЕЛАННАЯ ПОСЛЕ КОВКИ, ПРОВЕРЯЕТ УЖЕ ЗАТЁРТОЕ.

ЧТО ЗАМЕРЯЕТСЯ. Прибор читает дерево ТЕКСТОМ и ищет спор о трёх родах имён:

    ЦЕЛЬ КУЗНИ   два `gen_genesis_*.py`, пишущих один и тот же `datasets/*.txt`;
    ИМЯ СУДА     два `courts/*.py` с одним `ИМЯ_СУДА`;
    ЗАМКНУТЫЙ МИР два суда, объявивших один и тот же мир своим (`ЗАМКНУТЫЕ_МИРЫ`).

Всякий спор есть молчаливая потеря: кто пишет вторым, стирает первого, и ни один прибор свода
об этом не скажет — ибо каждый из двоих сам по себе честен.

    БЕДА ДВУХ ИМЁН НЕ ВИДНА НИ ОДНОМУ ИЗ НИХ: ОНА ЖИВЁТ В ПРОМЕЖУТКЕ.

ГРАНИЦА НАЗВАНА: прибор судит объявленные ЦЕЛИ и ИМЕНА, а не содержимое. Кузня, пишущая цель
вычисленным именем, которого не прочесть разбором, ему не видна — и это долг прибора, а не
свода; он назван отдельным числом.

    python3 scripts/forge_claim.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --дерево no-such-tree
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: СПОРОВ_РУБЕЖ = 0
#
# Ноль есть ПОЛ: всякая новая кузня, взявшая занятую цель, роняет прибор в час своего
# рождения — то есть ДО того, как её запустят и она сотрёт чужой труд.
СПОРОВ_РУБЕЖ = 0

ЦЕЛЬ = re.compile(r"(?:emit(?:_grouped)?\(\s*|ЦЕЛЬ\s*=\s*)\"(datasets/[-\w.]+\.txt)\"")
ИМЯ_СУДА = re.compile(r"^ИМЯ_СУДА\s*=\s*\"([^\"]+)\"", re.M)
ЗАМКНУТЫЕ = re.compile(r"^ЗАМКНУТЫЕ_МИРЫ\s*=\s*frozenset\(\{([^}]*)\}\)", re.M)
_В_КАВЫЧКАХ = re.compile(r"\"([^\"]+)\"")


def _спор(по_ключу):
    return {к: sorted(кто) for к, кто in sorted(по_ключу.items()) if len(set(кто)) > 1}


def цели_кузниц(двор):
    вон = collections.defaultdict(list)
    for г in sorted(двор.glob("gen_genesis_*.py")):
        т = г.read_text(encoding="utf-8", errors="replace")
        for ц in set(ЦЕЛЬ.findall(т)):
            вон[ц].append(г.stem)
    return вон


def имена_судов(двор):
    имена, миры, немые = collections.defaultdict(list), collections.defaultdict(list), []
    for с in sorted(двор.glob("*.py")):
        т = с.read_text(encoding="utf-8", errors="replace")
        м = ИМЯ_СУДА.search(т)
        if м:
            имена[м.group(1)].append(с.stem)
        else:
            немые.append(с.stem)
        з = ЗАМКНУТЫЕ.search(т)
        if з:
            for мир in _В_КАВЫЧКАХ.findall(з.group(1)):
                миры[мир].append(с.stem)
    return имена, миры, немые


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что спор ВИДЕН, а согласие не обвиняется.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ НУЛЯ СПОРОВ, И НУЛЬ ЕГО ДВУЗНАЧЕН: либо спора нет, либо
        признак перестал читать цели и имена — и тогда споров не будет НИКОГДА, сколько бы
        их ни завелось.

    Три дерева во временной папке: две кузни на одну цель, две — на разные, и суд без имени.
    """
    import tempfile
    беды = []
    with tempfile.TemporaryDirectory() as д:
        двор = pathlib.Path(д)
        (двор / "gen_genesis_a.py").write_text(
            'ЦЕЛЬ = "datasets/genesis_общий.txt"\n', encoding="utf-8")
        (двор / "gen_genesis_b.py").write_text(
            'emit_grouped("datasets/genesis_общий.txt", f)\n', encoding="utf-8")
        (двор / "gen_genesis_c.py").write_text(
            'ЦЕЛЬ = "datasets/genesis_свой.txt"\n', encoding="utf-8")
        спор = _спор(цели_кузниц(двор))
        if list(спор) != ["datasets/genesis_общий.txt"]:
            беды.append(f"спор целей: {спор} — признак цели слеп или слишком широк")
        elif спор["datasets/genesis_общий.txt"] != ["gen_genesis_a", "gen_genesis_b"]:
            беды.append(f"спорящие названы неверно: {спор}")
    with tempfile.TemporaryDirectory() as д:
        двор = pathlib.Path(д)
        (двор / "первый_court.py").write_text(
            'ИМЯ_СУДА = "общее"\nЗАМКНУТЫЕ_МИРЫ = frozenset({"мир"})\n', encoding="utf-8")
        (двор / "второй_court.py").write_text(
            'ИМЯ_СУДА = "общее"\nЗАМКНУТЫЕ_МИРЫ = frozenset({"мир", "иной"})\n',
            encoding="utf-8")
        (двор / "третий_court.py").write_text(
            'ИМЯ_СУДА = "своё"\nЗАМКНУТЫЕ_МИРЫ = frozenset({"третий"})\n', encoding="utf-8")
        (двор / "немой_court.py").write_text("x = 1\n", encoding="utf-8")
        имена, миры, немые = имена_судов(двор)
        if list(_спор(имена)) != ["общее"]:
            беды.append(f"спор имён судов: {_спор(имена)}")
        if list(_спор(миры)) != ["мир"]:
            беды.append(f"спор замкнутых миров: {_спор(миры)}")
        if немые != ["немой_court"]:
            беды.append(f"суд без имени не назван: {немые}")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ЦЕЛЬ ЗАНЯТА ОТКАЗ: признаки спора не доказаны ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--дерево", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    корень = pathlib.Path(дов.дерево) if дов.дерево else КОРЕНЬ
    кузни, суды = корень / "tools", корень / "courts"
    if not кузни.is_dir() or not суды.is_dir():
        print(f"ЦЕЛЬ ЗАНЯТА ОТКАЗ: дерева нет — {корень}")
        return 2
    цели = цели_кузниц(кузни)
    имена, миры, немые = имена_судов(суды)
    споры = [("ЦЕЛЬ КУЗНИ", _спор(цели)), ("ИМЯ СУДА", _спор(имена)),
             ("ЗАМКНУТЫЙ МИР", _спор(миры))]
    всего = sum(len(с) for _и, с in споры)
    for имя, с in споры:
        for к, кто in list(с.items())[:6]:
            print(f"  СПОР [{имя}] «{к}»: {', '.join(кто)}")
    if дов.подробно:
        for и in немые[:10]:
            print(f"  БЕЗ ИМЕНИ {и}")
    поза = "PASS" if всего <= СПОРОВ_РУБЕЖ else "FAIL"
    print(f"ЦЕЛЬ ЗАНЯТА {поза}: споров {всего} (рубеж {СПОРОВ_РУБЕЖ}); целей кузниц "
          f"{len(цели)}, имён судов {len(имена)}, замкнутых миров {len(миры)}, "
          f"судов без имени {len(немые)} — их прибор не видит, и это его долг")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
