#!/usr/bin/env python3
"""[РАМКА ДВУХ ДОМОВ] — шаблон, на который претендует больше одного дома.

Повод (04.09, шрам того же часа). Дом речевого обихода объявил рамку «что
такое {с}? {с} — это {в}.» СВОЕЙ и назвал ложью 128 честных определений мира
бытовых тем в тот же час, как они появились. Рамка «что такое X?» есть рамка
ВСЕГО КОРПУСА, а не одного дома: ею спрашивают о приветствии, о дожде, о
числе, о роде. Дом, объявивший общую рамку своей, судит чужое.

Прибор читает ОБЪЯВЛЕНИЯ домов (`tools/*.py`), а не показы: всякую строку
модульного уровня, несущую дыру `{имя}`, он режет в СКЕЛЕТ — дыры в «□»,
числа в «#» — и считает, сколько домов заявили один и тот же скелет. Два
дома на одной рамке суть либо разделение труда (и тогда чей-то суд обязан
смотреть на СЛОВО, а не на рамку), либо столкновение, и оно видно ДО
порождения, а не после ворот.

ПАЛИТРА КАК ДОПОЛНЕНИЕ (заказ holon, П-6): рядом печатается, сколько рамок
дом объявил и сколько из них ЕДИНОЛИЧНЫ — «палитра» дома есть то, чего он не
заявляет, и она выводится из объявленного, а не пишется отдельно; вторым
источником истины стать не может по построению.

    python3 scripts/frames.py [--out reports/FRAMES.tsv]
"""
import argparse
import ast
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
_ДЫРА = re.compile(r"\{[^{}]*\}")
_ЧИСЛО = re.compile(r"\d+")
_ПРОБЕЛ = re.compile(r"\s+")
# строка становится рамкой, лишь если несёт дыру и хоть сколько-то слов
_МИН_ДЛИНА = 12


def скелет(строка):
    с = _ДЫРА.sub("□", строка)
    с = _ЧИСЛО.sub("#", с)
    return _ПРОБЕЛ.sub(" ", с).strip()


def рамки_дома(путь):
    """Скелеты всех строковых литералов дома, несущих дыру."""
    try:
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
    except SyntaxError:
        return set()
    вон = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            з = узел.value
            if "{" in з and "}" in з and len(з) >= _МИН_ДЛИНА and "\n" not in з:
                вон.add(скелет(з))
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--out", type=pathlib.Path)
    а = ап.parse_args()
    дома = {}
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        if путь.name.startswith("gen_genesis_"):
            continue          # генератор не объявляет рамок, он их читает
        р = рамки_дома(путь)
        if р:
            дома[путь.stem] = р
    чей = collections.defaultdict(set)
    for дом, р in дома.items():
        for с in р:
            чей[с].add(дом)
    общие = {с: d for с, d in чей.items() if len(d) > 1}
    ряды = ["рамка\tдомов\tдома"]
    for с, d in sorted(общие.items(), key=lambda п: (-len(п[1]), п[0])):
        ряды.append(f"{с}\t{len(d)}\t{','.join(sorted(d))}")
    текст = "\n".join(ряды) + "\n"
    if а.out:
        а.out.write_text(текст, encoding="utf-8")
    else:
        sys.stdout.write(текст)
    единолично = {дом: sum(1 for с in р if len(чей[с]) == 1) for дом, р in дома.items()}
    print(f"РАМКА ДВУХ ДОМОВ: домов с объявленными рамками {len(дома)}, различных рамок {len(чей)}, "
          f"заявленных более чем одним домом {len(общие)}", file=sys.stderr)
    спор = sorted(((len(р) - единолично[дом], дом, len(р)) for дом, р in дома.items()), reverse=True)[:6]
    print("  дома с наибольшим числом ОБЩИХ рамок: "
          + ", ".join(f"{дом} {общ} из {всего}" for общ, дом, всего in спор if общ), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
