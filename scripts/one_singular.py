#!/usr/bin/env python3
"""[ЕДИНСТВЕННОЕ ПРИ ЕДИНИЦЕ] — имя, показанное своду только во множественном при числе.

    ФОРМА, НЕ ПОКАЗАННАЯ ПРИ ЕДИНИЦЕ, НЕ КУПЛЕНА. Свод пишет «5 newtons» шестьсот одиннадцать
    раз и «1 newton» — ни разу; читателю неоткуда взять, что при единице имя стои́т иначе, и на
    вопрос о единице он напишет «1 newtons».

ЭТО НЕ ДОГАДКА О ЧИТАТЕЛЕ, А СЧЁТ ПО ПИСЬМУ. Прибор не спрашивает, что́ читатель выучил; он
спрашивает, ЕСТЬ ЛИ В СВОДЕ СТРОКА, ИЗ КОТОРОЙ ЭТО МОЖНО ВЗЯТЬ. Нет строки — нет покупки,
сколько бы ни было строк о множественном.

ВТОРАЯ, ХУДШАЯ БЕДА — И ОНА ПОКА НЕ СЛУЧИЛАСЬ. Дома мер пишут единицу ЛИТЕРАЛОМ:

    f"...{m * a} newtons."                       (tools/gen_genesis_physics.py:160)

Здесь нет правила единственного числа вовсе. Дом спасён не законом, а ЖРЕБИЕМ: множители
таковы, что произведение ни разу не вышло единицей. В день, когда выйдет, свод напишет «1
newtons» и будет учить лжи. Прибор считает такие строки отдельно, и рубеж им — НОЛЬ.

    ДОМ, ЧЬЯ ПРАВОТА ДЕРЖИТСЯ НА ТОМ, ЧТО ЖРЕБИЙ НЕ ДАЛ ЕДИНИЦЫ, НЕ ПРАВ — ОН НЕ ПРОВЕРЕН.

ЧЕГО ПРИБОР НЕ СЧИТАЕТ. Имени, чьё множественное ни разу не стои́т при числе, свод ничего не
обещал: считать его долгом значило бы мерить собственную слепоту (тот же изъян, за который
07.09 переписана мера `cell_shown`). Берутся лишь пары, где множественное ПРИ ЧИСЛЕ показано.
Единица засчитывается и цифрой, и словом: «1 newton» и «one newton» покупают одно и то же.

    python3 scripts/one_singular.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --свод no-such-file
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: БЕЗ_ЕДИНИЦЫ_РУБЕЖ = 9
#
# РУБЕЖ ОБЪЯВЛЕН ПО ДОСТИГНУТОМУ и в тот же вечер СНИЖЕН ДЕЛОМ: 24 при постановке (84 %),
# 16, 15, 13, 9 — после того, как единицу показали дома физики, людей, кибернетики,
# статистики, законов физики и алгоритмов; 94 % куплено — физика (newton, joule, watt, ampere, ohm,
# volt) и дом людей (customer, passenger); ныне 132 из 148, 89 %.
#
# Цена дальнейшего снижения известна поимённо и не угадана: pupil (242 «pupils»), item,
# disturbance (330), gram (322), centimetre (292), pascal (289), number, way, order,
# outcome, kopeck, edge, value, element, transition, sweet, millimetre. Каждое имя есть
# ОДИН дом, которому недостаёт страницы с единицей, — не догадка о читателе, а адрес.
#
# ЧЕТЫРЕ ИМЕНИ КУПЛЕНЫ СЛОВОМ, А НЕ ЦИФРОЙ. Первая проба считала лишь «1 X» и дала 28; счёт,
# берущий и «one X», даёт 24. Разница есть мера того, как ЛЕГКО ЗАВЫСИТЬ ДОЛГ, спросив свод
# одним письмом числа из двух: «one gram» покупает единственное не хуже, чем «1 gram».
БЕЗ_ЕДИНИЦЫ_РУБЕЖ = 0

# РУБЕЖ-ДОЛГА: ЛОЖНЫХ_РУБЕЖ = 0
#
# «1 newtons» есть прямая ложь письма, а не недостача показа. Ноль есть ПОЛ: одна такая строка
# роняет прибор в тот же час, когда жребий её выпишет.
ЛОЖНЫХ_РУБЕЖ = 0

СЛОВОМ_ОДИН = ("one",)


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--свод", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    п_свода = pathlib.Path(дов.свод) if дов.свод else КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
    п_пакета = КОРЕНЬ / "tools" / "langpacks" / "en.json"
    if not п_свода.is_file() or not п_пакета.is_file():
        print(f"ЕДИНСТВЕННОЕ ПРИ ЕДИНИЦЕ ОТКАЗ: нет «{п_свода if not п_свода.is_file() else п_пакета}»")
        return 2
    пары = {л.lower(): мн.lower()
            for л, мн in (json.loads(п_пакета.read_text(encoding="utf-8")).get("noun_forms")
                          or {}).items()}
    if not пары:
        print("ЕДИНСТВЕННОЕ ПРИ ЕДИНИЦЕ ОТКАЗ: пакет не объявляет noun_forms")
        return 2
    т = п_свода.read_text(encoding="utf-8", errors="replace").lower()
    один = r"(?:1|" + "|".join(СЛОВОМ_ОДИН) + r")"
    при_единице = collections.Counter(re.findall(r"\b" + один + r" ([a-z]+)\b", т))
    при_многих = collections.Counter(w for _n, w in re.findall(r"\b([2-9]|\d\d+) ([a-z]+)\b", т))
    долг, ложь, показано = [], [], 0
    for ед, мн in sorted(пары.items()):
        # ЛОЖЬ ПИСЬМА СЧИТАЕТСЯ ПРЕЖДЕ ВСЯКОГО ОТБОРА (07.09, поймано подсадкой).
        #
        # Проверка стояла ПОСЛЕ отсева «свод ничего не обещал», и подсаженная строка
        # «the force was 1 newtons.» осталась незамеченной: в урезанном своде «newtons»
        # не встретилось при числе больше единицы, пара отсеялась — и ложь ушла вместе с
        # ней. Отсев верен для НЕДОСТАЧИ ПОКАЗА и неверен для ЛЖИ.
        #
        #     ОТСЕВ «НАМ ЭТОГО НЕ ОБЕЩАЛИ» ГОДИТСЯ ДЛЯ ДОЛГА И НЕ ГОДИТСЯ ДЛЯ ЛЖИ: ложь
        #     не перестаёт быть ложью оттого, что рядом нет правды.
        if при_единице[мн]:
            ложь.append((мн, при_единице[мн]))
        if not при_многих[мн]:
            continue            # МНОЖЕСТВЕННОЕ ПРИ ЧИСЛЕ НЕ ПОКАЗАНО — СВОД НИЧЕГО НЕ ОБЕЩАЛ
        if при_единице[ед]:
            показано += 1
        else:
            долг.append((ед, мн, при_многих[мн]))
    обещано = показано + len(долг)
    доля = 100 * показано / max(1, обещано)
    print(f"{'имя':<16}{'«1 ед.»':>9}{'«N мн.»':>9}")
    for ед, мн, n in sorted(долг, key=lambda x: -x[2])[: None if дов.подробно else 12]:
        print(f"{ед:<16}{'—':>9}{n:>9}   («{мн}»)")
    for мн, n in ложь:
        print(f"  ЛОЖЬ ПИСЬМА: «1 {мн}» {n} раз — единица при множественном")
    поза = ("PASS" if len(долг) <= БЕЗ_ЕДИНИЦЫ_РУБЕЖ and len(ложь) <= ЛОЖНЫХ_РУБЕЖ else "FAIL")
    print(f"ЕДИНСТВЕННОЕ ПРИ ЕДИНИЦЕ {поза}: обещано {обещано} имён, единица показана "
          f"{показано} ({доля:.0f} %), БЕЗ ЕДИНИЦЫ {len(долг)} (рубеж {БЕЗ_ЕДИНИЦЫ_РУБЕЖ}); "
          f"лжи письма {len(ложь)} (рубеж {ЛОЖНЫХ_РУБЕЖ}); пар в пакете {len(пары)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
