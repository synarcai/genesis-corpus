#!/usr/bin/env python3
"""[СУДИМОСТЬ КОРПУСА] — доля строк, которую хоть один суд ЧИТАЕТ.

Всякий суд отвечает на вопрос «нет ли лжи среди того, что я понимаю».
Ни один не отвечает на вопрос «а много ли я понимаю» — и корпус может
стоять зелёным, будучи проверенным наполовину. Это тот же род беды, что
молчащий прибор: ноль находок при нулевом обходе.

ПРИБОР МЕРИТ ОХВАТ, А НЕ ИСТИНУ. Строка считается судимой, если ХОТЬ
ОДИН суд взялся её судить — безразлично, признал он её истинной или
ложной. Ложь считают суды; здесь считают ВИДИМОСТЬ.

СТРОКА ЯЗЫКОВОГО ПЛАСТА СУДИМА ВСЕГДА: суд пластов проверяет каждое её
слово на объявленность, и это проверка не слабее счётной.

РУБЕЖ МОЖЕТ ТОЛЬКО РАСТИ. Владелец потребовал ста процентов, и путь
туда лежит через объявления: форма, которую не судит никто, обязана
либо получить судью, либо исчезнуть из слоя.
"""
import collections
import concurrent.futures
import importlib
import os
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "courts"))
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402
import panel  # noqa: E402
from panel import палата  # noqa: E402

# СУД, КОТОРОГО НЕТ, НЕ ДОЛЖЕН УБИВАТЬ МЕРУ. Прибор мерит охват, и его
# собственный отказ при отсутствии одного суда есть та же слепота, что
# он ищет: мера, умирающая от неполноты окружения, не измерит и
# неполноту корпуса. Отсутствующий суд просто ничего не видит, и это
# СКАЗАНО числом загруженных.


# ВТОРОГО СПИСКА СУДОВ БОЛЬШЕ НЕТ. Здесь жил свой перечень судов и
# свой порядок их зова — ровно тот двойник, ради упразднения которого
# строилась палата; и он разошёлся с нею в первый же день, когда новый
# суд был введён в палату и не введён сюда: тысяча двести пятьдесят
# судимых строк объявились слепыми, и мера солгала не о корпусе, а о
# себе. Вопрос «кто судит эту строку» теперь ОДИН и живёт в палате;
# прибор судимости только СЧИТАЕТ её ответы.

# РУБЕЖ-ОХВАТА: доля судимых строк корпуса, %
СУДИМОСТЬ_РУБЕЖ = 100

# РУБЕЖ-ДОЛГА: СЛОВАРЁМ_РУБЕЖ = 0
#
# СТО ПРОЦЕНТОВ СУДИМОСТИ СОДЕРЖАЛИ ТРЕТЬ, КОТОРУЮ НЕ ЧИТАЛ НИКТО.
# Строка языкового пласта, не взятая ни одним судом истины, зачитывалась
# палатой по ПРИЗНАКУ ИМЕНИ ФАЙЛА — «это пласт языка, стало быть истина».
# Таких строк 67 162: тридцать семь процентов всего свода показов.
# Зачёт, неспособный упасть, не есть проверка; он есть обещание.
#
# Вылечено двумя ходами. Зачёт теперь ДЕЛАЕТ РАБОТУ — спрашивает
# словарь пакета, и строка со словом, которого пакет не объявлял, есть
# ЛОЖЬ. И вердикт помечен своим именем, а доля таких строк названа
# ЗДЕСЬ, отдельным числом, ибо МЕРА ОБЯЗАНА НАЗЫВАТЬ СВОЙ ЗНАМЕНАТЕЛЬ.
#
# Проверка словарём слабее проверки содержанием: ложное утверждение,
# собранное из объявленных слов, её пройдёт. Потому число было
# объявлено ДОЛГОМ, и путь его вниз назван заранее: пласт языка есть
# СЛЕДСТВИЕ ПАКЕТА, и судить его должно ВОСПРОИЗВЕДЕНИЕМ — не
# «объявлено ли слово», а «стоит ли ЭТА форма в ЭТОЙ клетке
# объявленной таблицы».
#
# ДОЛГ УПЛАЧЕН ПОЧТИ ЦЕЛИКОМ В ТОТ ЖЕ ДЕНЬ. Суд формы пласта
# (`courts/langform_court.py`) читает 65 918 строк языковых пластов
# СОДЕРЖАНИЕМ, и зачёт словарём стал не нужен там, где есть настоящее
# чтение: 67 162 → 2007. Остаток есть строки, до которых суд формы не
# дотянулся; они по-прежнему зачитываются словарём, и это честно
# названо числом.
#
# ДОСТИГНУТОЕ БЕРЁТСЯ ИЗ СВЕЖЕГО ЗАМЕРА, А НЕ ИЗ ВЧЕРАШНЕГО. Я едва не
# поставил здесь ноль — по прогону, где зачёт показал 0, — и это был бы
# рубеж, которого корпус не достигал: тот прогон шёл ДО того, как
# соседняя рука закрыла восемь тысяч слепых строк, и число сдвинулось.
# Долг, опущенный ниже достигнутого, есть не строгость, а ложь в свою
# пользу наоборот: он валит зелёный корпус и учит не верить мере.
# ДОЛГ УПЛАЧЕН ЦЕЛИКОМ (03.09, коллегия ста процентов). Путь вниз был назван
# заранее — «судить пласт ВОСПРОИЗВЕДЕНИЕМ, а не объявленностью слова», — и
# пройден двумя судами: арифметика пласта (`courts/langmath_court.py`)
# пересчитывает равенство, сказанное словами языка, а порождение пласта
# (`courts/langgen_court.py`) читает строку шаблоном самого пакета и счётную
# цепь рядом объявленных числительных подряд. 67 162 → 2 007 → 767 → 0: ни
# одна строка свода больше не зачитывается словарём, и рубеж ноль означает,
# что зачёт словарём отныне есть отказ.
СЛОВАРЁМ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest


_ПАЛАТА_РАБОЧЕГО = None


def _палата_рабочего():
    """Одна палата на процесс — суды дороги при загрузке."""
    global _ПАЛАТА_РАБОЧЕГО
    if _ПАЛАТА_РАБОЧЕГО is None:
        _ПАЛАТА_РАБОЧЕГО = палата()
    return _ПАЛАТА_РАБОЧЕГО


def _судить_ломоть(задача):
    """Один ЛОМОТЬ мира: (имя, начало, свои, взяты, словарём, слепые).

    ЛОМОТЬ, А НЕ МИР. Прибор ходил свод мир за миром, и внутри мира палата делилась
    лишь при двух тысячах строк и лишь если машина не занята — то есть почти никогда.
    Сорок шесть минут на набор, и это САМЫЙ дорогой прибор свода.

        САМАЯ ДЛИННАЯ ЗАДАЧА ЕСТЬ ДНО СРОКА.

    Слои и пласт строятся по ЦЕЛОМУ файлу в каждом ломте, судятся строки
    [начало, конец) — тот же закон резки, что у `panel._судить_кусок`.
    """
    имя, путь, начало, конец, со_слепыми = задача
    путь = pathlib.Path(путь)
    суд = _палата_рабочего()
    слои = суд.слои(путь)
    пласт = суд.пласт_файла(путь)
    строки = panel._живые_строки(путь)
    свои = взяты = словарём = 0
    слепые = []
    for строка in строки[начало:конец]:
        судимо, _истинно, кем = суд.судить(строка, слои, пласт)
        свои += 1
        взяты += судимо
        if кем == ["langlayer:словарь"]:
            словарём += 1
        if not судимо and со_слепыми:
            слепые.append(строка)
    return имя, начало, свои, взяты, словарём, слепые


def main():
    # ЯВНО НАЗВАННЫЙ МАНИФЕСТ: без него прибор не мог отказать НИ НА ЧЁМ
    # — обход выводился из репозитория и всегда был полон. Маркер
    # пустого обхода при этом стоял, и парк честно назвал его ложью:
    # объявление, которого нельзя прожить, есть обещание, а не договор.
    if "--manifest" in sys.argv:
        свой = sys.argv[sys.argv.index("--manifest") + 1]
        genesis.MANIFEST = pathlib.Path(свой)
    try:
        миры = genesis.manifest()["worlds"]
    except genesis.Unreadable as беда:
        print(f"СУДИМОСТЬ ОТКАЗ: {беда}")
        return 2
    всего = взято = словарём = 0
    по_мирам = []
    суд = палата()
    # СЛЕПОЕ ПОКАЗЫВАЕТСЯ, А НЕ СЧИТАЕТСЯ. Число слепых строк
    # говорит, СКОЛЬКО осталось, но не говорит ЧТО — а закон
    # покупается только с формой в руках.
    слепые = {} if "--слепые" in sys.argv else None
    # МЕРА БЕРЁТ ТОЛЬКО ПОКАЗЫ, И ПО ИМЕНИ РОДА, А НЕ ПО СПИСКУ ИСКЛЮЧЕНИЙ.
    # Прежде отсеивалась названная поимённо проза, и всякий НОВЫЙ род текста
    # входил бы в меру молча — полный микс удвоил бы весь корпус и раздул
    # охват вместе с ложью.
    #
    # ЗАЧЁТ ПО СЛОВАРЮ НЕ ЕСТЬ ЧТЕНИЕ СОДЕРЖАНИЯ, И МЕРА ОБЯЗАНА НАЗВАТЬ ЭТО
    # ЧИСЛОМ. Строка языкового пласта, которую не прочёл ни один суд истины,
    # зачитывается словарём пакета: всякое ли слово объявлено. Проверка
    # настоящая, но СЛАБЕЕ — ложное утверждение, собранное из объявленных
    # слов, её пройдёт. Замер вскрыл, что таких строк 67 795, то есть
    # тридцать семь процентов всего свода показов, и все они молча входили
    # в «сто процентов». Доля названа отдельно, чтобы сто процентов означали
    # то, что говорят.
    взятые = [(м["name"], genesis._resolve(м["file"])) for м in миры
              if м.get("text") == "shows"]
    взятые = [(и, п_) for и, п_ in взятые if п_.is_file()]
    порядок = {и: i for i, (и, _п) in enumerate(взятые)}
    имена = {str(п_): и for и, п_ in взятые}
    jobs = panel._джобы()
    ломти = panel.ломти([п_ for _и, п_ in взятые],
                        panel.ЦЕЛЬ_ЛОМТЯ if jobs > 1 else 0)
    задачи = [(имена[str(п_)], str(п_), a, b, слепые is not None)
              for п_, a, b, _ц in ломти]
    if jobs <= 1:
        итоги = [_судить_ломоть(з) for з in задачи]
    else:
        # СТОРОЖ РОДИТЕЛЯ: рабочий, переживший убитый набор, есть память,
        # которую никто не освободит (79 таких сирот на 5.9 ГБ, замер 12.09).
        with concurrent.futures.ProcessPoolExecutor(
                max_workers=jobs, initializer=panel._сторожить_родителя,
                initargs=(os.getpid(),)) as пул:
            итоги = list(пул.map(_судить_ломоть, задачи))
    # СБОРКА В ПОРЯДКЕ МАНИФЕСТА И СТРОК: вердикт обязан читаться так же,
    # как читался бы в один поток.
    итоги.sort(key=lambda и: (порядок.get(и[0], 10**9), и[1]))
    свои_мира = collections.OrderedDict()
    for имя_м, _нач, свои, взяты, свои_словарём, свои_слепые in итоги:
        словарём += свои_словарём
        всего += свои
        взято += взяты
        если = свои_мира.setdefault(имя_м, [0, 0])
        если[0] += свои
        если[1] += взяты
        if слепые is not None and свои_слепые:
            слепые.setdefault(имя_м, []).extend(свои_слепые)
    for имя_м, (свои, взяты) in свои_мира.items():
        по_мирам.append((взяты / свои if свои else 1.0, имя_м, свои, взяты))
    if not всего:
        print("СУДИМОСТЬ ОТКАЗ: обход пуст, мерить нечего")
        return 2
    доля = 100 * взято // всего
    по_мирам.sort()
    сколько_миров = len(по_мирам) if "--всё" in sys.argv else 5
    for д, имя, свои, взяты in по_мирам[:сколько_миров]:
        if д < 1.0:
            print(f"  {имя:<22}{свои:>7}{взяты:>8}{int(д * 100):>6}%")
    if слепые is not None:
        сколько = 3 if "--много" not in sys.argv else 10 ** 9
        for _, имя, _, _ in по_мирам:
            for строка in слепые.get(имя, ())[:сколько]:
                print(f"  СЛЕП {имя:<20} {строка[:110]}")
    итог = ("PASS" if доля >= СУДИМОСТЬ_РУБЕЖ
            and словарём <= СЛОВАРЁМ_РУБЕЖ else "FAIL")
    # СЛЕПЫЕ НАЗВАНЫ ЧИСЛОМ, А НЕ ВЫЧИТАНИЕМ В ГОЛОВЕ ЧИТАЮЩЕГО:
    # находка прибора есть строка, которую не читает никто, и она
    # должна стоять в выводе как находка, а не как остаток.
    print(f"СУДИМОСТЬ {итог}: {взято} из {всего} строк судимы "
          f"({доля}% при рубеже {СУДИМОСТЬ_РУБЕЖ}%, "
          f"судов живых {суд.живых}), слепых {всего - взято}, "
          f"зачтено словарём пакета {словарём} "
          f"({100 * словарём // всего if всего else 0}% свода, "
          f"долг {СЛОВАРЁМ_РУБЕЖ})")
    return 0 if доля >= СУДИМОСТЬ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
