#!/usr/bin/env python3
"""[ПРОДОЛЖЕНИЕ НАБОРА] — какие приборы уже зелены НА ЭТОМ САМОМ ДЕРЕВЕ.

Набор из 232 приборов идёт часами, и за две смены он не дошёл до конца ни разу: машина занята
чужой работой, прогон обрывается на шестьдесят пятом приборе, и вся работа теряется. Между тем
она НЕ ПОТЕРЯНА: набор пишет вердикт каждого прибора в `reports/ledger.tsv` по ходу дела.

    ПАМЯТЬ У НАБОРА БЫЛА, НЕ БЫЛО ЧТЕНИЯ: оборванный прогон оставлял полный след и начинал
    следующий с нуля.

Прибор отвечает на один вопрос: ЧТО МОЖНО НЕ ГОНЯТЬ СНОВА. Ответ строг и назван:

    ПРИБОР ПРОПУСКАЕТСЯ, ЕСЛИ В ЛЕДЖЕРЕ СТОИ́Т ЕГО НУЛЬ, ПОСТАВЛЕННЫЙ ПОЗЖЕ САМОЙ СВЕЖЕЙ
    ПРАВКИ ДЕРЕВА. Всё, что старше правки, гонится заново — довод о прежнем дереве не есть
    довод об этом.

МЕТКА СТАВИТСЯ ПО СУДИМОМУ ДЕРЕВУ, А НЕ ПО ВСЕМУ, КРОМЕ СЛЕДОВ НАБОРА, и это второе основание,
взамен первого. Первое отмеряло «всё, кроме трёх файлов, которые пишет сам набор», и было ЛОЖНЫМ
по делу: набор пишет не три файла, а сколько угодно — `sweep_self.py` кладёт свой вердикт
в `reports/sweep/latest.tsv` посреди прогона, и одна эта запись сдвигала метку на середину,
обесценивая все зелёные, поставленные до неё.

    СПИСОК ИСКЛЮЧЕНИЙ ВЕРЕН РОВНО ДО ТОГО ДНЯ, КОГДА ИСКЛЮЧЕНИЕ ЗАВЕДУТ И НЕ ВПИШУТ.

Ныне названо ПОЛОЖИТЕЛЬНО: корпус есть `datasets`, `tools`, `courts`, `scripts`, `declarations`
и файлы в корне. `reports` — не корпус, а ЗАПИСЬ О НЁМ, и правка записи не меняет судимого.

ГРАНИЦА НАЗВАНА ЧЕСТНО: прибор не знает, ЧТО читает каждый суд, и потому судит по дереву целиком.
Правка одного дома гонит заново весь набор. Это грубо и безопасно; тонкая мера потребовала бы
объявления зависимостей, которого в своде нет.

    ГРУБАЯ МЕРА, ОШИБАЮЩАЯСЯ В СТОРОНУ ЛИШНЕЙ РАБОТЫ, ЧЕСТНЕЕ ТОНКОЙ, ОШИБАЮЩЕЙСЯ В СТОРОНУ
    ПРОПУЩЕННОЙ ПРОВЕРКИ.

СТЕНД ОТДЕЛЯЕТ ВОПРОС ПРИБОРА ОТ ОКРУЖЕНИЯ, и потому леджер можно назвать доводом: честный
близнец, требующий живого дерева и живого леджера, проверял бы полноту свода, а не прибор. Тем же
пользуется суд родов, беря `--род`.

    python3 scripts/suite_resume.py          # имена приборов, которых можно не гонять
    python3 scripts/suite_resume.py --метка  # сама метка дерева и её причина
    python3 scripts/suite_resume.py --леджер путь --корень дерево   # стенд
"""
# ПУСТОЙ-ОБХОД: --корень no-such-dir
import datetime
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ЛЕДЖЕР = КОРЕНЬ / "reports" / "ledger.tsv"
# СУДИМОЕ ДЕРЕВО — то, о чём говорят приборы. Отчёты сюда не входят: они запись о своде.
СУДИМОЕ = ("datasets", "tools", "courts", "scripts", "declarations")
МИМО = {".git", "__pycache__", ".venv", "node_modules", ".mypy_cache", ".pytest_cache"}


def _файлы(корень):
    """Файлы СУДИМОГО дерева: названные дворы и всё, что лежит в корне."""
    for двор in СУДИМОЕ:
        путь = корень / двор
        if путь.is_dir():
            yield from (п for п in путь.rglob("*") if not set(п.parts) & МИМО)
    yield from (п for п in корень.iterdir() if п.is_file())


def метка(корень):
    """(время последней правки судимого дерева, чем она поставлена)."""
    свежесть, кем = 0.0, "—"
    for п in _файлы(корень):
        if not п.is_file():
            continue
        м = п.stat().st_mtime
        if м > свежесть:
            свежесть, кем = м, str(п.relative_to(корень))
    return свежесть, кем


def зелёные_позже(порог, леджер=None):
    """Имена приборов, чей ПОСЛЕДНИЙ вердикт в леджере — нуль, поставленный позже порога."""
    последний = {}
    леджер = леджер or ЛЕДЖЕР
    if not леджер.is_file():
        return set()
    for строка in леджер.read_text(encoding="utf-8", errors="replace").splitlines():
        поля = строка.split("\t")
        if len(поля) < 3:
            continue
        стамп, имя, rc = поля[0], поля[1], поля[2]
        # ПОСЛЕДНИЙ ВЕРДИКТ, А НЕ ЛУЧШИЙ: прибор, упавший после того, как был зелён,
        # пропускать нельзя.
        предыдущий = последний.get(имя)
        if предыдущий is None or стамп >= предыдущий[0]:
            последний[имя] = (стамп, rc)
    порог_иso = datetime.datetime.fromtimestamp(
        порог, datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return {имя for имя, (стамп, rc) in последний.items()
            if rc == "0" and стамп > порог_иso}


def main():
    корень = КОРЕНЬ
    if "--корень" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--корень") + 1])
        if not корень.is_dir():
            print(f"ПРОДОЛЖЕНИЕ НАБОРА ОТКАЗ: дерева нет — {корень}", file=sys.stderr)
            return 2
    леджер = None
    if "--леджер" in sys.argv:
        леджер = pathlib.Path(sys.argv[sys.argv.index("--леджер") + 1])
        if not леджер.is_file():
            print(f"ПРОДОЛЖЕНИЕ НАБОРА ОТКАЗ: леджера нет — {леджер}", file=sys.stderr)
            return 2
    свежесть, кем = метка(корень)
    if "--метка" in sys.argv:
        когда = datetime.datetime.fromtimestamp(
            свежесть, datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        print(f"метка дерева {когда} — поставлена файлом {кем}")
        return 0
    for имя in sorted(зелёные_позже(свежесть, леджер)):
        print(имя)
    return 0


if __name__ == "__main__":
    sys.exit(main())
