#!/usr/bin/env python3
"""[ДОЛГ АРИФМЕТИКИ] — чем именно давится суд счёта на 137 655 непрочитанных предложениях.

Суд арифметики печатает число непрочитанного («неразобрано 137655»), и это честно: МОЛЧАЩАЯ
СЛЕПОТА ЧИТАЕТСЯ КАК ЧИСТОТА. Но число не говорит, ЧТО именно не прочитано, и потому долг,
названный числом, платить нечем.

    ДОЛГ, НАЗВАННЫЙ ЧИСЛОМ, НЕ ГОВОРИТ, ЧЕМ ЕГО ПЛАТИТЬ. Триста строк одной причины и тридцать
    тысяч другой стои́т числом одно и то же и работой — совсем разное.

Прибор берёт РАЗБОР САМОГО СУДА (`arith_court`), прогоняет им те же предложения и раскладывает
непрочитанное по НАЗВАННЫМ причинам. Он ничего не судит и ничего не чинит: он только называет.

ПРИЧИНЫ ОБЪЯВЛЕНЫ ЗАРАНЕЕ И ПРОВЕРЯЮТСЯ ПО ПОРЯДКУ — первая подошедшая и есть имя. Порядок
значим и потому назван: от самой узкой причины к самой широкой, чтобы «прочее» осталось
последним и малым.

ГРАНИЦА НАЗВАНА: прибор говорит о ФОРМЕ непрочитанного, а не о том, стало бы прочтённое истинным.
Он показывает, СКОЛЬКО СТОИТ каждая правка, и молчит о том, ЧТО она найдёт.

ЧТО ЭТОТ ПРИБОР ЗАЩИЩАЕТ. Первая редакция не ставила его в набор, рассудив, что у меры нет рубежа
и в наборе вердиктов она была бы вечно зелена. Суд состава отверг этот довод своим законом: ПРИБОР
ОПОЗНАЁТСЯ ОБЪЯВЛЕНИЕМ О ПУСТОМ ОБХОДЕ, И ВСЯКИЙ ТАКОЙ ОБЯЗАН БЫТЬ В НАБОРЕ, ибо прибор, которого
никто не зовёт, падает молча. Довод свода сильнее: рубеж у меры НАЙТИ МОЖНО.

Рубеж этот — доля «ПРОЧЕЕ»: сколько непрочитанного не подошло НИ ПОД ОДНУ названную причину.

    МЕРА, ЧЬИ ПРИЧИНЫ ПЕРЕСТАЛИ ПОКРЫВАТЬ БЕДУ, МОЛЧИТ О СВОЕЙ СЛЕПОТЕ ТАК ЖЕ, КАК МОЛЧАЛ БЫ
    СУД. Растущее «прочее» есть весть о том, что свод завёл беду, которой разбор не знает.

ЗАМЕР 11.09 ПО 256 МИРАМ (160 498 судимых, 137 875 непрочитанных):

     86522  62.4%  знака равенства нет вовсе        ← НЕ ДОЛГ ВОВСЕ: судить нечего
     18406  13.3%  буква вместо числа               ← дело суда формул, не счёта
     15067  10.9%  запятая: равенство рядом с неравенством
     10285   7.4%  прочее                           ← РУБЕЖ
      6593   4.8%  отрицание при равенстве
       785   0.6%  одни знаки, слов нет
       769   0.6%  дробь косой чертой
       195   0.1%  запятая десятичная: резать нельзя

ЧИСЛО «137 875» ЗАВЫШАЛО ДОЛГ ВТРОЕ: почти две трети непрочитанного не несут знака равенства
вовсе, и судить там нечего. Вот зачем долг называют причинами, а не числом.

ДОГАДКА, ОПРОВЕРГНУТАЯ ЗАМЕРОМ, НАЗВАНА ЗДЕСЬ ЖЕ. Я полагал, что запятую нельзя резать из-за
десятичного разделителя («8,35 Euro + 15,15 Euro»), — и разделил причину надвое, чтобы проверить.
Таких строк оказалось 195 из 15 262, чуть больше процента: РЕЗАТЬ МЕШАЕТ НЕ ЧИСЛО.

    ПРИЧИНА, НАЗВАННАЯ ПО ДОГАДКЕ, СТОИ́Т РОВНО СТОЛЬКО, СКОЛЬКО ЗАМЕР ЕЙ ОТМЕРИТ.

    python3 scripts/arith_debt.py                 # весь свод
    python3 scripts/arith_debt.py datasets/x.txt  # один мир
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "courts"))

# РУБЕЖ-ДОЛГА: ПРОЧЕГО_РУБЕЖ = 10285
ПРОЧЕГО_РУБЕЖ = 10285

import arith_court as A  # noqa: E402

РАВЕНСТВО = re.compile(r"(?<![<>≠≤≥])=(?!=)")
# СЛОВА ОТРИЦАНИЯ БЕРУТСЯ У ЯЗЫКОВ, А НЕ ПИШУТСЯ РУКОЙ. Первая редакция знала два языка из
# двадцати девяти, и замер показал ей же цену: в долю «запятая» попало немецкое «nein: 9 ist keine
# Primzahl, denn 9 = 3 × 3» — отрицание, опознанное бы мгновенно, будь оно русским.
#
#     ПРИЗНАК, ЗНАЮЩИЙ ДВА ЯЗЫКА СВОДА ИЗ ДВАДЦАТИ ДЕВЯТИ, НАЗЫВАЕТ ПРИЧИНЫ ПО-РУССКИ И
#     МОЛЧИТ О ПРОЧИХ.
#
# ГРАНИЦА НАЗВАНА ЧИСЛОМ: полярность объявили ДЕВЯТЬ пакетов из двадцати девяти, и объявили они
# слово, ОТКРЫВАЮЩЕЕ ОТВЕТ («нет», «nein», «não»), а не всякое отрицание. Потому доля отрицаний
# по-прежнему ЗАНИЖЕНА, а доля запятой ЗАВЫШЕНА — сказано здесь, а не оставлено читателю.
def _слова_отрицания():
    """Слова отрицания: рукой названные для двух языков и ОБЪЯВЛЕННЫЕ пакетами для прочих."""
    вон = {"не", "нет", "неверно", "ложь", "ложно", "not", "no", "wrong", "false", "incorrect"}
    for пакет in sorted((КОРЕНЬ / "tools" / "langpacks").glob("*.json")):
        try:
            тело = json.loads(пакет.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        слова = (тело.get("polarity") or {}).get("no") or ()
        вон |= {с.lower() for с in (слова if isinstance(слова, list) else [слова]) if с}
    return вон


ОТРИЦАНИЕ = re.compile(
    r"\b(?:" + "|".join(sorted(re.escape(с) for с in _слова_отрицания()))
    + r"|неправ\w*)\b", re.I)
ДРОБЬ_КОСОЙ = re.compile(r"\d+\s*/\s*\d+")
# ЗАПЯТАЯ МЕЖДУ ЦИФРАМИ ЕСТЬ ДЕСЯТИЧНЫЙ РАЗДЕЛИТЕЛЬ, А НЕ ГРАНИЦА ПРЕДЛОЖЕНИЯ, и это закон
# свода, объявленный миром записи: «0,5 и 0.5 — одно число». Резать по такой запятой значило бы
# рвать число пополам, и потому причина названа отдельно: долг этой доли НЕ ПЛАТИТСЯ РЕЗКОЙ.
ЗАПЯТАЯ_ЧИСЛА = re.compile(r"\d,\d")
БУКВА = re.compile(r"[A-Za-zА-Яа-яЁё]")
ПЕРЕМЕННАЯ = re.compile(r"(?<![A-Za-zА-Яа-яЁё])[a-zxyzn](?![A-Za-zА-Яа-яЁё])")


def причина(ч):
    """Имя причины, по которой предложение осталось непрочитанным.

    ПОРЯДОК — ОТ УЗКОГО К ШИРОКОМУ: первая подошедшая причина и есть имя.
    """
    куски = [к.strip() for к in ч.split(",") if к.strip()]
    с_равенством = [к for к in куски if РАВЕНСТВО.search(к)]
    if ОТРИЦАНИЕ.search(ч) and с_равенством:
        return "отрицание при равенстве"
    if len(куски) > 1 and с_равенством and len(с_равенством) < len(куски):
        if ЗАПЯТАЯ_ЧИСЛА.search(ч):
            return "запятая десятичная: резать нельзя"
        return "запятая: равенство рядом с неравенством"
    if ДРОБЬ_КОСОЙ.search(ч):
        return "дробь косой чертой"
    if ПЕРЕМЕННАЯ.search(ч) and с_равенством:
        return "буква вместо числа"
    if not РАВЕНСТВО.search(ч):
        return "знака равенства нет вовсе"
    if not БУКВА.search(ч):
        return "одни знаки, слов нет"
    return "прочее"


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    import genesis
    return [п for п in genesis.worlds(kind="shows") if п.is_file()]


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ДОЛГ АРИФМЕТИКИ ОТКАЗ: обход пуст, считать нечего")
        return 2
    словарь = A.словари()
    счёт = collections.Counter()
    образцы = {}
    судимых = неразобрано = 0
    for путь in пути:
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for сырая in поток:
                части = A.предложения(сырая)
                for ч, (судимо, истинно) in zip(части, A.судить_строку(сырая, словарь)):
                    if судимо:
                        судимых += 1
                        continue
                    if истинно:
                        continue
                    неразобрано += 1
                    имя = причина(ч)
                    счёт[имя] += 1
                    образцы.setdefault(имя, f"{путь.stem}: {ч.strip()[:88]}")
    print(f"НЕПРОЧИТАННОЕ ПО ПРИЧИНАМ (судимых {судимых}, непрочитанных {неразобрано}, "
          f"файлов {len(пути)}):")
    for имя, n in счёт.most_common():
        доля = 100 * n / неразобрано if неразобрано else 0
        print(f"  {n:8}  {доля:5.1f}%  {имя}")
        print(f"            {образцы[имя]}")
    прочего = счёт.get("прочее", 0)
    if явные:
        print(f"ДОЛГ АРИФМЕТИКИ ЛЕНТА: прочего {прочего} (обход назван доводом, рубеж не судит)")
        return 0
    поза = "PASS" if прочего <= ПРОЧЕГО_РУБЕЖ else "FAIL"
    print(f"ДОЛГ АРИФМЕТИКИ {поза}: непрочитанного без названной причины {прочего} "
          f"(рубеж {ПРОЧЕГО_РУБЕЖ}) из {неразобрано}; причин названо {len(счёт)}")
    return 0 if прочего <= ПРОЧЕГО_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
