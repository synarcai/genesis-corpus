#!/usr/bin/env python3
"""[ДОЛГ АРИФМЕТИКИ] — чем именно давится суд счёта на 137 655 непрочитанных предложениях.

Суд арифметики печатает число непрочитанного («неразобрано 137655»), и это честно: МОЛЧАЩАЯ
СЛЕПОТА ЧИТАЕТСЯ КАК ЧИСТОТА. Но число не говорит, ЧТО именно не прочитано, и потому долг,
названный числом, платить нечем.

    ДОЛГ, НАЗВАННЫЙ ЧИСЛОМ, НЕ ГОВОРИТ, ЧЕМ ЕГО ПЛАТИТЬ. Триста строк одной причины и тридцать
    тысяч другой стои́т числом одно и то же и работой — совсем разное.

Прибор берёт РАЗБОР САМОГО СУДА (`arith_court`), прогоняет им те же предложения и раскладывает
непрочитанное по НАЗВАННЫМ причинам. Он ничего не судит и ничего не чинит: он только называет.

ПРИЧИНЫ ОБЪЯВЛЕНЫ ЗАРАНЕЕ И ПРОВЕРЯЮТСЯ ПО ПОРЯДКУ — первая подошедшая и есть имя. Порядок
значим и потому назван: от самой узкой причины к самой широкой, чтобы «прочее» осталось
последним и малым.

ГРАНИЦА НАЗВАНА: прибор говорит о ФОРМЕ непрочитанного, а не о том, стало бы прочтённое истинным.
Он показывает, СКОЛЬКО СТОИТ каждая правка, и молчит о том, ЧТО она найдёт.

В НАБОР СУДОВ ОН НЕ ПОСТАВЛЕН, И ЭТО ВЫБОР, А НЕ ЗАБЫВЧИВОСТЬ: у него нет рубежа, который он
защищает, и потому в наборе PASS/FAIL он был бы вечно зелён.

    МЕРА БЕЗ ВЕРДИКТА, ПОСТАВЛЕННАЯ В НАБОР ВЕРДИКТОВ, УЧИТ ТОМУ, ЧТО ЗЕЛЁНОЕ И ЕСТЬ
    ПРОВЕРЕННОЕ. Его место — рука работающего, перед правкой и после неё.

    python3 scripts/arith_debt.py                 # весь свод
    python3 scripts/arith_debt.py datasets/x.txt  # один мир
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "courts"))

import arith_court as A  # noqa: E402

РАВЕНСТВО = re.compile(r"(?<![<>≠≤≥])=(?!=)")
ОТРИЦАНИЕ = re.compile(
    r"\b(?:не|нет|неверно|ложь|ложно|неправ\w*|not|no|wrong|false|incorrect)\b", re.I)
ДРОБЬ_КОСОЙ = re.compile(r"\d+\s*/\s*\d+")
# ЗАПЯТАЯ МЕЖДУ ЦИФРАМИ ЕСТЬ ДЕСЯТИЧНЫЙ РАЗДЕЛИТЕЛЬ, А НЕ ГРАНИЦА ПРЕДЛОЖЕНИЯ, и это закон
# свода, объявленный миром записи: «0,5 и 0.5 — одно число». Резать по такой запятой значило бы
# рвать число пополам, и потому причина названа отдельно: долг этой доли НЕ ПЛАТИТСЯ РЕЗКОЙ.
ЗАПЯТАЯ_ЧИСЛА = re.compile(r"\d,\d")
БУКВА = re.compile(r"[A-Za-zА-Яа-яЁё]")
ПЕРЕМЕННАЯ = re.compile(r"(?<![A-Za-zА-Яа-яЁё])[a-zxyzn](?![A-Za-zА-Яа-яЁё])")


def причина(ч):
    """Имя причины, по которой предложение осталось непрочитанным.

    ПОРЯДОК — ОТ УЗКОГО К ШИРОКОМУ: первая подошедшая причина и есть имя.
    """
    куски = [к.strip() for к in ч.split(",") if к.strip()]
    с_равенством = [к for к in куски if РАВЕНСТВО.search(к)]
    if ОТРИЦАНИЕ.search(ч) and с_равенством:
        return "отрицание при равенстве"
    if len(куски) > 1 and с_равенством and len(с_равенством) < len(куски):
        if ЗАПЯТАЯ_ЧИСЛА.search(ч):
            return "запятая десятичная: резать нельзя"
        return "запятая: равенство рядом с неравенством"
    if ДРОБЬ_КОСОЙ.search(ч):
        return "дробь косой чертой"
    if ПЕРЕМЕННАЯ.search(ч) and с_равенством:
        return "буква вместо числа"
    if not РАВЕНСТВО.search(ч):
        return "знака равенства нет вовсе"
    if not БУКВА.search(ч):
        return "одни знаки, слов нет"
    return "прочее"


def обход(явные):
    if явные:
        return [pathlib.Path(п) for п in явные]
    import genesis
    return [п for п in genesis.worlds(kind="shows") if п.is_file()]


def main():
    явные = [а for а in sys.argv[1:] if not а.startswith("-")]
    пути = [п for п in обход(явные) if п.is_file()]
    if not пути:
        print("ДОЛГ АРИФМЕТИКИ ОТКАЗ: обход пуст, считать нечего")
        return 2
    словарь = A.словари()
    счёт = collections.Counter()
    образцы = {}
    судимых = неразобрано = 0
    for путь in пути:
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for сырая in поток:
                части = A.предложения(сырая)
                for ч, (судимо, истинно) in zip(части, A.судить_строку(сырая, словарь)):
                    if судимо:
                        судимых += 1
                        continue
                    if истинно:
                        continue
                    неразобрано += 1
                    имя = причина(ч)
                    счёт[имя] += 1
                    образцы.setdefault(имя, f"{путь.stem}: {ч.strip()[:88]}")
    print(f"НЕПРОЧИТАННОЕ ПО ПРИЧИНАМ (судимых {судимых}, непрочитанных {неразобрано}, "
          f"файлов {len(пути)}):")
    for имя, n in счёт.most_common():
        доля = 100 * n / неразобрано if неразобрано else 0
        print(f"  {n:8}  {доля:5.1f}%  {имя}")
        print(f"            {образцы[имя]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
