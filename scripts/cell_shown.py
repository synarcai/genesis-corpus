"""[ЯЧЕЙКА БЕЗ ПОКАЗА] — объявленная форма счёта, ни разу не показанная при числе.

    ОБЪЯВЛЕНИЕ, ДО КОТОРОГО НЕ ДОХОДИТ ПОКАЗ, ЕСТЬ ОБЕЩАНИЕ, А НЕ ФАКТ. Утром этот закон
    поймал два русских класса, чьи лексемы не давали строк; ныне он спрашивает глубже: даёт
    ли слой КАЖДУЮ объявленную ячейку счёта КАЖДОЙ лексемы.

Повод — вопрос holon-f9: «единица с одной формой купится как несклоняемое имя». Проверка
показала, что «минута» стои́т в русском слое только при числах 6…11 и ни разу при 2…4, то
есть форма «минуты» объявлена и не показана.

ПРИЧИНА ОБЩАЯ И НАЗВАНА: движок берёт и ЧИСЛО, и ЛЕКСЕМУ из ОДНОГО семени —
`n = seed % 9 + 1`, `pick = pool[(seed + ti) % len(pool)]`. Оттого пара «лексема ↔ число»
жёстко связана, и часть лексем не встречает часть чисел никогда.

    ДВА СЧЁТЧИКА ОТ ОДНОГО ЧИСЛА СВЯЗАНЫ, А НЕ НЕЗАВИСИМЫ — тот же закон, что уронил дом
    счёта подлежащего утром, только здесь он в движке пакетов, а не в доме.

РУБЕЖ ОБЪЯВЛЕН ПО ДОСТИГНУТОМУ, А НЕ ПО ЖЕЛАЕМОМУ: 74 ячейки без показа при 325 обещанных
(77 % показано). Число это есть ДОЛГ ДВИЖКА, а не пакетов: связку «лексема ↔ число» чинить
надо там, где она заведена, и правка эта тронет все двадцать девять слоёв разом. Рубеж
держит достигнутое, чтобы долг не рос, покуда правка не сделана и не замерена.

    python3 scripts/cell_shown.py
"""
import collections, json, pathlib, re, sys
К = pathlib.Path("/Users/taaliman/projects/oldman/synarcai/genesis-corpus")
sys.path.insert(0, str(К / "tools"))
import langpack

# РУБЕЖ-ДОЛГА: БЕЗ_ПОКАЗА_РУБЕЖ = 32
#
# 74 → 32 (07.09, развязка «лексема ↔ число» в движке пакетов). Прежде движок брал ЧИСЛО и
# ЛЕКСЕМУ из одного семени, и пара их была связана намертво: русская «минута» стояла при
# 6…11 и ни разу при 2…4. Ныне лексема шагает по кольцу единицей инстанса, число остаётся
# при своём семени — и «было 3 минуты», «было 1 минута» встали в слое рядом с «5 минут».
#
# Рубеж опущен до достигнутого в тот же час, чтобы не стать запасом.

БЕЗ_ПОКАЗА_РУБЕЖ = 32

ЧИСЛА = (1, 2, 3, 4, 5, 11, 21, 22)
всего_ячеек = показано = 0
по_языкам = collections.Counter(); дыры = []
for п in sorted((К / "tools" / "langpacks").glob("*.json")):
    пак = json.loads(п.read_text(encoding="utf-8"))
    я = пак.get("lang", п.stem)
    слой = К / "datasets" / f"genesis_lang_{я}.txt"
    if not слой.is_file():
        continue
    т = слой.read_text(encoding="utf-8")
    # СЧИТАЕТСЯ ЛИШЬ ТО, ЧТО ПАКЕТ ОБЕЩАЛ ПОКАЗАТЬ ПРИ ЧИСЛЕ (07.09, вторая редакция).
    #
    # Первая мерила ВСЕ классы с ячейками one/many и дала «16 % показано» — число о
    # собственной слепоте: в него вошли амхарские прилагательные (при числе не стоя́т вовсе)
    # и языки, чей слой счётного шаблона не имеет. Это тот же изъян, за который я утром
    # ловил меру слепоты суда счёта:
    #
    #     МЕРА, НЕ ОТЛИЧАЮЩАЯ «НЕ ПОКАЗАНО» ОТ «НЕ ОБЕЩАНО», ЗАВЫШАЕТ ДОЛГ И ТЕМ
    #     ОБЕСЦЕНИВАЕТ СЕБЯ.
    #
    # Ныне берутся лишь классы, к которым пакет обращается через `by_n`/`by_sum`: он тем
    # самым ОБЕЩАЛ показать их формы при числе.
    шаблоны = " ".join(t for р in (пак.get("show_kinds") or {}).values()
                       for t in (р.get("templates") or []))
    for имя, кл in (пак.get("morph_classes") or {}).items():
        формы = кл.get("forms") or []
        if not (set(формы) & {"one", "many"}):
            continue
        if f"lex:{имя}:by_" not in шаблоны:
            continue
        for лекс, ряд in (кл.get("lexemes") or {}).items():
            нужные = set()
            for n in ЧИСЛА:
                i = langpack.count_form_index(пак, кл, n)
                сч = f"count_{формы[i]}"
                нужные.add(ряд[формы.index(сч)] if сч in формы else ряд[i])
            for ф in нужные:
                всего_ячеек += 1
                if re.search(r"\d+\s+" + re.escape(ф) + r"\b", т):
                    показано += 1
                else:
                    по_языкам[я] += 1
                    дыры.append((я, имя, лекс, ф))
print(f"{'язык':<6}{'ячеек без показа':>18}")
for я, n in по_языкам.most_common():
    print(f"{я:<6}{n:>18}")
доля = 100 * показано / max(1, всего_ячеек)
print(f"\nЯЧЕЕК СЧЁТА ВСЕГО {всего_ячеек}; ПОКАЗАНО ПРИ ЧИСЛЕ {показано} ({доля:.0f} %); "
      f"БЕЗ ПОКАЗА {всего_ячеек - показано}")
for я, кл, л, ф in дыры[:8]:
    print(f"    ДЫРА {я}/{кл}: {л} → «{ф}» ни разу при числе")
поза = "PASS" if (всего_ячеек - показано) <= БЕЗ_ПОКАЗА_РУБЕЖ else "FAIL"
print(f"ЯЧЕЙКА БЕЗ ПОКАЗА {поза}: обещано {всего_ячеек}, показано {показано} ({доля:.0f} %), "
      f"без показа {всего_ячеек - показано} (рубеж {БЕЗ_ПОКАЗА_РУБЕЖ})")
sys.exit(0 if поза == "PASS" else 1)
