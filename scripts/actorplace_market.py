#!/usr/bin/env python3
"""[РЫНОК ЗАЧИНА ДЕЯТЕЛЯ] — чем свод открывает предложение перед словом, стоящим при деятеле.

    СЛОВО, ПЕРЕД КОТОРЫМ СВОД СТАВИТ ТОЛЬКО ЛИЦО, ТРЕБУЕТ ЛИЦА И ВПРЕДЬ; А ЧЕМ ИМЕННО
    ОНО МОЖЕТ БЫТЬ ОТКРЫТО, ГОВОРЯТ ПОКАЗЫ, А НЕ СПИСОК СЛОВ.

Покупка живёт в двери лиц (`tools/actors.py`, где сказан и повод, и цена), а здесь она
ЗАПИСЫВАЕТСЯ на полку — `datasets/GENESIS-FULL.actorplace.tsv` — и сверяется с делом.

    ПОКУПКА, ПЕРЕСЧИТЫВАЕМАЯ МОЛЧА ПРИ ВСЯКОМ ЗОВЕ, НЕ ЕСТЬ ЗНАНИЕ ОРГАНИЗМА: её никто
    не видит, никто не сличит со вчера, и стои́т она двенадцать с половиной секунд НА
    КАЖДЫЙ процесс палаты. Покупка, записанная строкой, есть предмет — её судят.

ЧТО НА ПОЛКЕ. Строка сайдкара — язык, слово, показы, купленные классы зачина через запятую.
Классы объявлены ПАКЕТОМ: `лицо` (`person_names`, `person_forms`), `вопрос` (`ask_words`),
`задание` (`task_words`), `зачин` (`sentence_openers`); `·неизвестно` — зачин, какого пакет
не объявляет никаким (вещь, чужое имя, число словом).

ЧТО СУДИТ ГОЛЫЙ ЗОВ. Пересобирает рынок по своду и сличает с полкой: расхождение есть
устаревшая покупка. Рубеж НОЛЬ — свод и покупка либо сходятся, либо покупка лжёт.

    python3 scripts/actorplace_market.py [--собрать] [--цена] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import argparse
import collections
import pathlib
import sys
import zlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import actors  # noqa: E402 — дверь лиц: рынок места лица живёт там

# РУБЕЖ-ДОЛГА: РАСХОЖДЕНИЙ_РУБЕЖ = 0
#
# ПОЛКА И СВОД ЛИБО СХОДЯТСЯ, ЛИБО ПОКУПКА ЛЖЁТ — третьего у сайдкара нет, и потому рубеж
# рождён нулём, а не опущен до него. Проба доказывает, что прибор умеет находить: четыре
# порчи имени на трёх языках, взятые из строк, какие подсадка словом держала непойманными.
РАСХОЖДЕНИЙ_РУБЕЖ = 0


def строки_полки(куплено, рынок):
    вон = ["# РЫНОК ЗАЧИНА ДЕЯТЕЛЯ — чем свод открывает предложение перед этим словом.",
           "# Собран `python3 scripts/actorplace_market.py --собрать` по мирам, объявившим",
           "# деятелей (манифест `actors`). Столбцы: язык, слово, показы, классы зачина.",
           "# Класс объявлен ПАКЕТОМ языка; `·неизвестно` — зачин, не объявленный никаким."]
    for (язык, слово), классы in sorted(куплено.items()):
        показы = sum(рынок[(язык, слово)].values())
        вон.append(f"{язык}\t{слово}\t{показы}\t{','.join(sorted(классы))}")
    return вон


def цена_на_другой_половине():
    """Рынок куплен на половине строк, суд идёт по другой — той, какой он не видел."""
    половина = lambda с: zlib.crc32(с.encode("utf-8")) % 2 == 0   # noqa: E731
    куп = actors.куплены(actors.собрать_рынок(доля=половина))
    обвинений, примеры, судимых = collections.Counter(), [], 0
    for имя, путь, языки in actors.миры_деятелей():
        if not путь.exists():
            continue
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            строка = строка.strip()
            if not строка or половина(строка):
                continue
            судимых += 1
            for зачин, слово, язык in actors.порча(строка, языки, куп=куп):
                обвинений[имя] += 1
                if len(примеры) < 6:
                    примеры.append((имя, язык, зачин, слово, строка[:70]))
    return len(куп), судимых, обвинений, примеры


# ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ, ТРЕМЯ ЯЗЫКАМИ. Пара «целое имя → обрезок» берётся из тех самых
# строк свода, какие подсадка словом (`scripts/word_mutants.py`) держала непойманными; обрезок
# здесь НЕ ИЩЕТСЯ прибором, а назван — проба доказывает не поиск, а ЧТЕНИЕ.
ПРОБЫ = (
    (("en",), "tom has 6 books, and ira has 3 books; tom has twice as many books.",
              "to has 6 books, and ira has 3 books; tom has twice as many books."),
    (("en",), "ann had 6 cookies. ann got 3 cookies. how many cookies does ann have now?",
              "an had 6 cookies. ann got 3 cookies. how many cookies does ann have now?"),
    (("de",), "jonas hatte 9 bücher. jonas bekam 6 bücher mehr.",
              "jona hatte 9 bücher. jonas bekam 6 bücher mehr."),
    (("es",), "luis tenía 9 libros. luis recibió 6 libros más.",
              "lui tenía 9 libros. luis recibió 6 libros más."),
)


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: порченое имя ловится, целое — молчит."""
    куп = actors.куплено()
    if not куп:
        return None
    поймано = sum(1 for языки, _, порча in ПРОБЫ if actors.порча(порча, list(языки), куп=куп))
    ложных = sum(1 for языки, цело, _ in ПРОБЫ if actors.порча(цело, list(языки), куп=куп))
    return поймано, len(ПРОБЫ), ложных


def main():
    ап = argparse.ArgumentParser(add_help=True)
    ап.add_argument("--собрать", action="store_true")
    ап.add_argument("--цена", action="store_true")
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--манифест", default=None)
    дано = ап.parse_args()
    if дано.манифест:
        actors.МАНИФЕСТ = pathlib.Path(дано.манифест)
    миры = [м for м in actors.миры_деятелей() if м[1].exists()]
    if not миры:
        print("РЫНОК ЗАЧИНА ДЕЯТЕЛЯ ОТКАЗ: обход пуст — ни одного мира деятелей, мерить нечего")
        return 2

    if дано.цена:
        # ПОЛНЫЙ РЫНОК ЗДЕСЬ НЕ НУЖЕН И НЕ СТРОИТСЯ: замер цены покупает ПОЛОВИНУ и судит
        # другую, а лишний обход свода стои́т двенадцать с половиной секунд впустую.
        n, судимых, обвинений, примеры = цена_на_другой_половине()
        print(f"ЦЕНА НА ДРУГОЙ ПОЛОВИНЕ: куплено {n}, судимых строк {судимых}, "
              f"ОБВИНЕНИЙ {sum(обвинений.values())} в {len(обвинений)} мирах")
        for имя, язык, зачин, слово, тело in примеры:
            print(f"    [{имя}/{язык}] «{зачин} {слово}» ← {тело}")
        return 0

    рынок = actors.собрать_рынок()
    куплено = actors.куплены(рынок)
    языков = len({я for я, _ in куплено})
    if дано.собрать:
        actors.САЙДКАР.write_text("\n".join(строки_полки(куплено, рынок)) + "\n", encoding="utf-8")
        print(f"РЫНОК ЗАЧИНА ДЕЯТЕЛЯ СОБРАН: слов при лице {len(куплено)} на {языков} языках, "
              f"миров деятелей {len(миры)} → {actors.САЙДКАР.name}")
        return 0

    было = actors.куплено()
    ныне = {к: v for к, v in куплено.items()}
    расхождения = sorted(set(было) ^ set(ныне)) + sorted(
        к for к in set(было) & set(ныне) if было[к] != ныне[к])
    if дано.подробно:
        for язык, слово in расхождения[:40]:
            print(f"    {язык} · {слово}: полка {sorted(было.get((язык, слово), ()))} "
                  f"≠ свод {sorted(ныне.get((язык, слово), ()))}")
    проба = _проба()
    слово_пробы = ("пробы нет: полка пуста" if проба is None else
                   f"проба {проба[0]}/{проба[1]} поймано, ложных {проба[2]}")
    поза = "FAIL" if len(расхождения) > РАСХОЖДЕНИЙ_РУБЕЖ else "PASS"
    print(f"РЫНОК ЗАЧИНА ДЕЯТЕЛЯ {поза}: расхождений полки со сводом {len(расхождения)} "
          f"(рубеж {РАСХОЖДЕНИЙ_РУБЕЖ}); слов при лице {len(ныне)} на {языков} языках, "
          f"миров деятелей {len(миры)}, {слово_пробы}")
    return 1 if len(расхождения) > РАСХОЖДЕНИЙ_РУБЕЖ else 0


if __name__ == "__main__":
    sys.exit(main())
