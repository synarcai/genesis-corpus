set -u
cd "$(dirname "$0")/.."
LOCK=/Users/taaliman/projects/oldman/synarcai/omega/scripts/heavy_lock.sh
NAME="corpus-suite-$(date '+%H%M%S')"
OUT="${1:-}"
run() { if [ -n "$OUT" ]; then bash scripts/courts.sh > "$OUT" 2>&1; else bash scripts/courts.sh; fi; }
if [ -x "$LOCK" ]; then
  "$LOCK" "$NAME" -- bash -c "$(printf 'cd %q; ' "$PWD")$(declare -f run); OUT=$(printf '%q' "$OUT"); run"
  RC=$?
else
  run; RC=$?
fi
if [ "$RC" = 75 ]; then
  echo "НАБОР НЕ ЗАПУСКАЛСЯ: тяжёлый лок занят чужой работой дольше срока (код 75)."
