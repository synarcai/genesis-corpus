#!/usr/bin/env python3
"""[РУКА ЗАПИСИ] — машинный файл обязан быть переписан ТОЙ ЖЕ РУКОЙ, какой прочтён.

11.09 я вписал в манифест два мира — сорок девять строк — и переписал файл отступом в один
пробел вместо двух. `git diff --stat` показал:

    datasets/GENESIS-MANIFEST.json | 21599 +++++++++++++++++++--------------------
    1 file changed, 10824 insertions(+), 10775 deletions(-)

Дело осталось делом: манифест разбирался, суд манифеста дал PASS, все 464 мира на месте.
И всё-таки это беда, ибо ДЕЛО, УТОНУВШЕЕ В ПЕРЕПИСИ, НЕ ПРОЧТЁТ НИКТО: сорок девять строк
правки, неразличимые среди десяти тысяч переписанных, не может проверить ни человек, ни суд.

    ПРАВКА, НЕ ОТЛИЧИМАЯ ОТ ПЕРЕПИСИ, ЕСТЬ ПРАВКА БЕЗ СВИДЕТЕЛЯ.

ЗАМЕР 11.09 ПО ВСЕМ 32 JSON СВОДА: тридцать написаны отступом в два пробела с переводом строки
в конце, `declarations/GENERA.json` — отступом в один, `reports/FREE-TACTS-0907.json` — отступом
в один и без перевода строки. НИ ОДИН не написан рукой, которой не даёт ни один дампер: все
тридцать два переписываются сами в себя — значит, рука у каждого ЕСТЬ, и её можно назвать.

    РУКА ОБЪЯВЛЯЕТСЯ, А НЕ ВЫВОДИТСЯ ИЗ БОЛЬШИНСТВА: два файла из тридцати двух написаны иначе,
    и это не беда, а их письмо. Беда была бы, если бы письмо СМЕНИЛОСЬ молча.

Потому прибор не гонит все файлы к одному отступу. Он берёт объявленную руку каждого файла
(`declarations/JSON-HAND.json`) и сверяет, что файл в ней и написан. Мой промах он назвал бы
первой же строкой: «манифест объявил руку (2, перевод), а написан (1, перевод)».

ГРАНИЦА НАЗВАНА: прибор судит ПИСЬМО, а не СОДЕРЖАНИЕ. Файл, переписанный в своей руке с
испорченным телом, он пропустит — тело судят манифестный суд и суд охвата. И он не судит JSON,
которого нет в объявлении: новый файл он НАЗЫВАЕТ, требуя объявить руку, но это не ложь,
а долг — потому такие считаются отдельно и обвинением не становятся.

    python3 scripts/json_hand.py            # сверить
    python3 scripts/json_hand.py --объявить # записать руку всех найденных (первый раз и для новых)
"""
# ПУСТОЙ-ОБХОД: --корень no-such-dir
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ОБЪЯВЛЕНИЕ = КОРЕНЬ / "declarations" / "JSON-HAND.json"
МИМО = (".git", "node_modules", ".venv", "__pycache__")

# РУБЕЖ-ДОЛГА: СМЕНИВШИХ_РУКУ_РУБЕЖ = 0
СМЕНИВШИХ_РУКУ_РУБЕЖ = 0

# РУКИ, КОТОРЫЕ УМЕЕТ ПИСАТЬ `json.dumps`. Иных в своде нет — это замерено,
# а не предположено; файл, не попавший ни в одну, объявляется рукой «чужая».
РУКИ = tuple((отступ, хвост)
             for отступ in (2, 1, 4, None)
             for хвост in ("\n", ""))


def рука_файла(сырое, тело):
    """(отступ, есть ли перевод строки в конце) или None, если такой руки нет."""
    for отступ, хвост in РУКИ:
        if json.dumps(тело, ensure_ascii=False, indent=отступ) + хвост == сырое:
            return [отступ, хвост == "\n"]
    return None


def обход():
    корень = КОРЕНЬ
    if "--корень" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--корень") + 1])
        if not корень.is_dir():
            print(f"РУКА ЗАПИСИ ОТКАЗ: дерева нет — {корень}")
            sys.exit(2)
    return sorted(п for п in корень.rglob("*.json")
                  if not set(п.parts) & set(МИМО))


def main():
    пути = обход()
    объявить = "--объявить" in sys.argv
    объявлено = {}
    if ОБЪЯВЛЕНИЕ.is_file():
        объявлено = json.loads(ОБЪЯВЛЕНИЕ.read_text(encoding="utf-8")).get("руки", {})

    сменили, безымянных, сверено, новое = [], [], 0, {}
    for п in пути:
        имя = str(п.relative_to(КОРЕНЬ)) if КОРЕНЬ in п.parents or п.parent == КОРЕНЬ else str(п)
        сырое = п.read_text(encoding="utf-8")
        try:
            тело = json.loads(сырое)
        except json.JSONDecodeError as беда:
            сменили.append(f"{имя}: не разбирается — {беда}")
            continue
        рука = рука_файла(сырое, тело)
        новое[имя] = рука if рука else "чужая"
        было = объявлено.get(имя)
        if было is None:
            безымянных.append(имя)
            continue
        сверено += 1
        если_рука = рука if рука else "чужая"
        if если_рука != было:
            сменили.append(f"{имя}: объявлена рука {было}, а написан {если_рука}")

    if объявить:
        ОБЪЯВЛЕНИЕ.parent.mkdir(parents=True, exist_ok=True)
        тело = {"comment": "рука записи каждого машинного JSON: [отступ, перевод строки в конце]; "
                           "сменилась молча — значит, правка утонула в переписи",
                "руки": dict(sorted(новое.items()))}
        # ОБЪЯВЛЕНИЕ ПИШЕТСЯ СВОЕЙ ЖЕ РУКОЙ (2, перевод) — иначе первый же прогон
        # обвинил бы его самого.
        ОБЪЯВЛЕНИЕ.write_text(json.dumps(тело, ensure_ascii=False, indent=2) + "\n",
                              encoding="utf-8")
        print(f"РУКА ЗАПИСИ ОБЪЯВЛЕНА: {len(новое)} файлов → {ОБЪЯВЛЕНИЕ.name}")
        return 0

    for с in сменили[:8]:
        print(f"  {с}")
    for б in безымянных[:5]:
        print(f"  ДОЛГ: {б} — руки не объявлено")
    поза = "PASS" if len(сменили) <= СМЕНИВШИХ_РУКУ_РУБЕЖ else "FAIL"
    print(f"РУКА ЗАПИСИ {поза}: {len(сменили)} сменивших руку (рубеж {СМЕНИВШИХ_РУКУ_РУБЕЖ}); "
          f"сверено {сверено} файлов, не объявлено {len(безымянных)}")
    return 0 if len(сменили) <= СМЕНИВШИХ_РУКУ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
