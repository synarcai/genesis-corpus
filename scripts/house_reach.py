#!/usr/bin/env python3
"""[ЧУЖАЯ РАМКА] — дом, берущийся судить показы ЧУЖОГО дома.

Правило holon (04.09): «всякий новый мир есть кандидат в чужую рамку; проверить
дёшево — прогнать суд одного рода на своде другого». Повод у правила есть и у
меня: дом речевого обихода объявил рамку «что такое X?» своей и назвал ложью
128 честных определений мира бытовых тем в тот же час, как они появились
(М-177).

ЗАМКНУТЫЙ МИР ОТ ЭТОГО НЕ СПАСАЕТ, и в этом соль. Суд замкнутого мира отступает
от чужой строки ПО ИМЕНИ МИРА — но у ворот имени ещё нет: мир пишется впервые, и
палата судит его строки всеми судами разом. Столкновение случается именно там,
до того как замок начнёт действовать.

Прибор берёт ПОКАЗЫ каждого дома и подаёт их `судить` каждого ДРУГОГО дома. Три
исхода:
  · МОЛЧАНИЕ — дом чужого не судит: так и должно быть;
  · ИСТИНА — дом чужую строку признал: рамки пересекаются, но вреда нет;
  · ЛОЖЬ — дом назвал чужой честный показ ложью: это и есть чужая рамка, и
    она остановит ворота, когда новый мир будет писаться.

    python3 scripts/house_reach.py
"""
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ДОМА = ("dialogueforms", "linkforms", "behaviorforms", "topicforms", "natureforms",
        "oppositeforms", "roleforms", "scaleforms", "jointforms", "actionpages")


def _показы(модуль):
    п = getattr(модуль, "ПОКАЗЫ", None)
    return list(п) if isinstance(п, dict) else []


def main():
    дома = {}
    for имя in ДОМА:
        try:
            дома[имя] = __import__(имя)
        except Exception as e:                       # дом, который не читается, назван
            print(f"  дом не прочитан: {имя}: {e}", file=sys.stderr)
    показы = {и: _показы(м) for и, м in дома.items()}
    ложь = collections.Counter()
    истина = collections.Counter()
    пример = {}
    for судья, м in дома.items():
        судить = getattr(м, "судить", None)
        if судить is None:
            continue
        for хозяин, ряд in показы.items():
            if хозяин == судья or not ряд:
                continue
            for с in ряд:
                try:
                    судимо, истинно = судить(с)
                except Exception:
                    continue
                if not судимо:
                    continue
                if истинно:
                    истина[(судья, хозяин)] += 1
                else:
                    ложь[(судья, хозяин)] += 1
                    пример.setdefault((судья, хозяин), с)
    print(f"ЧУЖАЯ РАМКА: домов {len(дома)}, показов всего {sum(len(р) for р in показы.values())}; "
          f"пар «судья × хозяин» с ЛОЖЬЮ {len(ложь)}, с истиной {len(истина)}")
    for (судья, хозяин), n in ложь.most_common():
        print(f"  ЛОЖЬ  {судья} судит {хозяин}: {n}")
        print(f"        «{пример[(судья, хозяин)][:96]}»")
    for (судья, хозяин), n in истина.most_common(6):
        print(f"  истина {судья} признаёт {хозяин}: {n}")
    return 1 if ложь else 0


if __name__ == "__main__":
    sys.exit(main())
