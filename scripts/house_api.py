"""[ДОГОВОР ДОМА] — имя, которое кузня или суд берёт у дома, обязано в доме быть.

11.09 я записал СВОЙ дом поверх ЧУЖОГО: `tools/remforms.py` жил с 03.09 (дом фраз деления с
остатком на восьми языках), и простое `cp` затёрло его новым домом того же имени. Мир старого
дома остался в своде, его суд продолжал читать строки — а кузня легла:

    AttributeError: module 'remforms' has no attribute 'утверждение'

    ПЕРЕЗАПИСЬ ЧУЖОГО ДОМА НЕ ВИДНА НИ ОДНОМУ СУДУ: манифест проверяет миры, состав — суды,
    самопроверка — что дом не краснеет. Никто не спрашивает, ТОТ ЛИ ЭТО ДОМ.

Нашла беду ВОСПРОИЗВОДИМОСТЬ — единственный прибор, который пересобирает миры, — и стоит она
часа. Этот прибор спрашивает то же самое за секунды: он не собирает миры, а сверяет ДОГОВОР —
всякое имя, которое кузня или суд берёт у дома через ввоз, обязано в этом доме быть.

    ДОГОВОР ПРОВЕРЯЕТСЯ ИМЕНАМИ, А НЕ СБОРКОЙ: сборка говорит то же, но часом позже.

ЧТО ПРОВЕРЯЕТСЯ: у всякого файла в `tools/gen_genesis_*.py` и `courts/*.py` берутся ввозы вида
«import X as F» и «import X», где X лежит в `tools/`, и все обращения «F.имя» (или «X.имя»).
Каждое такое имя ищется в модуле — без запуска кузни, одним ввозом.

ГРАНИЦА НАЗВАНА: прибор не ходит внутрь функций чужих модулей и не знает имён, собираемых на лету
(`getattr`). Он ловит РАЗОШЕДШИЙСЯ ДОГОВОР, а не всякую ошибку ввоза.

ПРОЗВИЩЕ СВЯЗЫВАЕТСЯ В СВОЕЙ ОБЛАСТИ ВИДИМОСТИ (24.09). Суд эпизодов ввозит в трёх функциях три
разных дома под одним прозвищем «Д» (`gen_genesis_items`, `gen_genesis_aggregate`, `gen_genesis_verbs`),
и прибор, связывавший прозвище один раз на файл, сверил «Д.АКТ_НОСИТЕЛЯ» с домом глаголов и назвал
два разлада, которых нет. Ввоз внутри функции связывает имя в ней (и во вложенных), ввоз модуля — везде,
где его не перекрыли.

    ПРОЗВИЩЕ ЕСТЬ ИМЯ ОБЛАСТИ, А НЕ ФАЙЛА: сверять его с чужим домом значит лгать о договоре.

    python3 scripts/house_api.py
"""
# ПУСТОЙ-ОБХОД: --дерево no-such-dir
import ast
import importlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "courts"))

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 0
РАЗЛАДОВ_РУБЕЖ = 0


def ввозы_дома(дерево):
    """{имя в коде: имя модуля} для ввозов, чей модуль лежит в tools/."""
    вон = {}
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            for имя in узел.names:
                if (КОРЕНЬ / "tools" / f"{имя.name}.py").is_file():
                    вон[имя.asname or имя.name] = имя.name
    return вон


_ОБЛАСТИ = (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda, ast.ClassDef)


def _в_области(узел):
    """Узлы ОДНОЙ области видимости — без тел вложенных функций и классов."""
    стек = list(ast.iter_child_nodes(узел))
    while стек:
        п = стек.pop()
        yield п
        if not isinstance(п, _ОБЛАСТИ):
            стек.extend(ast.iter_child_nodes(п))


def взятые_по_областям(дерево):
    """{(модуль, имя)} — прозвище сверяется с домом, какой ввезла под ним ЕГО область."""
    вон = set()

    def обойти(узел, внешние):
        свои = dict(внешние)
        for п in _в_области(узел):
            if isinstance(п, ast.Import):
                for имя in п.names:
                    if (КОРЕНЬ / "tools" / f"{имя.name}.py").is_file():
                        свои[имя.asname or имя.name] = имя.name
        for п in _в_области(узел):
            if (isinstance(п, ast.Attribute) and isinstance(п.value, ast.Name)
                    and п.value.id in свои):
                вон.add((свои[п.value.id], п.attr))
            if isinstance(п, _ОБЛАСТИ):
                обойти(п, свои)

    обойти(дерево, {})
    return вон


def взятые_имена(дерево, местные):
    """{(модуль, имя)} — всё, что берётся у ввезённого дома точкой."""
    вон = set()
    for узел in ast.walk(дерево):
        if (isinstance(узел, ast.Attribute) and isinstance(узел.value, ast.Name)
                and узел.value.id in местные):
            вон.add((местные[узел.value.id], узел.attr))
    return вон


def обход():
    if "--дерево" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--дерево") + 1])
        if not корень.is_dir():
            print(f"ДОГОВОР ДОМА ОТКАЗ: дерева нет — {корень}")
            sys.exit(2)
        return sorted(корень.rglob("*.py"))
    вон = sorted((КОРЕНЬ / "tools").glob("gen_genesis_*.py"))
    вон += sorted((КОРЕНЬ / "courts").glob("*.py"))
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ввоз УЗНАЁТСЯ под прозвищем и что
    взятое имя видно.

        ДОГОВОР СВЕРЯЕТСЯ ЛИШЬ С ТЕМ ДОМОМ, КОГО ПРИБОР НАШЁЛ. Пусть ввоз под прозвищем
        («import fenceforms as F») перестанет узнаваться — и договор не будет сверен ни у
        одной кузницы свода, ибо ВСЕ они зовут свой дом прозвищем. Прибор скажет
        «разладов 0» и будет зелен над деревом, где договор нарушен везде.

    Дом пробы взят НАСТОЯЩИЙ (`rugram` — он есть в дереве), ибо признак спрашивает файл.
    """
    беды = []
    дерево = ast.parse(
        "import rugram\n"
        "import rugram as R\n"
        "import json\n"
        "x = rugram.форма('кот', 2)\n"
        "y = R.СЧЁТНЫЕ\n"
        "z = json.dumps({})\n")
    местные = ввозы_дома(дерево)
    if местные != {"rugram": "rugram", "R": "rugram"}:
        беды.append(f"ввозы дома: {местные} — ПРОЗВИЩЕ НЕ УЗНАНО")
    if "json" in местные:
        беды.append("чужой ввоз принят за дом — сверять будут не то")
    взятые = взятые_имена(дерево, местные)
    if взятые != {("rugram", "форма"), ("rugram", "СЧЁТНЫЕ")}:
        беды.append(f"взятые имена: {sorted(взятые)} — имя под прозвищем не видно")
    if any(м == "json" for м, _и in взятые):
        беды.append("имя чужого ввоза взято в сверку")
    if взятые_по_областям(дерево) != взятые:
        беды.append("области видимости разошлись с ввозом модуля на файле без функций")
    # ОДНО ПРОЗВИЩЕ В ДВУХ ФУНКЦИЯХ — ДВА ДОМА: имя сверяется с домом своей функции
    дерево2 = ast.parse(
        "import rugram as Д\n"
        "def a():\n    import units as Д\n    return Д.ФОРМЫ_ВСЕХ\n"
        "def b():\n    return Д.СЧЁТНЫЕ\n")
    взятые2 = взятые_по_областям(дерево2)
    if взятые2 != {("units", "ФОРМЫ_ВСЕХ"), ("rugram", "СЧЁТНЫЕ")}:
        беды.append(f"области видимости: {sorted(взятые2)} — прозвище связано не своей областью")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ДОГОВОР ДОМА ОТКАЗ: прибор не доказал, что видит ввоз ({len(беды)} бед)")
        return 2
    пути = обход()
    разлады, сверено, домов = [], 0, set()
    for п in пути:
        try:
            дерево = ast.parse(п.read_text(encoding="utf-8"))
        except SyntaxError as беда:
            разлады.append(f"{п.name}: не разбирается — {беда}")
            continue
        for модуль, имя in sorted(взятые_по_областям(дерево)):
            домов.add(модуль)
            try:
                м = importlib.import_module(модуль)
            except Exception as беда:                      # noqa: BLE001
                разлады.append(f"{п.name}: дом «{модуль}» не ввозится — {type(беда).__name__}")
                continue
            сверено += 1
            if not hasattr(м, имя):
                разлады.append(f"{п.name}: берёт у дома «{модуль}» имя «{имя}», которого нет")
    for р in разлады[:8]:
        print(f"  {р}")
    поза = "PASS" if len(разлады) <= РАЗЛАДОВ_РУБЕЖ else "FAIL"
    print(f"ДОГОВОР ДОМА {поза}: {len(разлады)} разладов (рубеж {РАЗЛАДОВ_РУБЕЖ}); "
          f"сверено имён {сверено} у {len(домов)} домов, файлов {len(пути)}")
    return 0 if len(разлады) <= РАЗЛАДОВ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
