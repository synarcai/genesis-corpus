"""[ДОГОВОР ДОМА] — имя, которое кузня или суд берёт у дома, обязано в доме быть.

11.09 я записал СВОЙ дом поверх ЧУЖОГО: `tools/remforms.py` жил с 03.09 (дом фраз деления с
остатком на восьми языках), и простое `cp` затёрло его новым домом того же имени. Мир старого
дома остался в своде, его суд продолжал читать строки — а кузня легла:

    AttributeError: module 'remforms' has no attribute 'утверждение'

    ПЕРЕЗАПИСЬ ЧУЖОГО ДОМА НЕ ВИДНА НИ ОДНОМУ СУДУ: манифест проверяет миры, состав — суды,
    самопроверка — что дом не краснеет. Никто не спрашивает, ТОТ ЛИ ЭТО ДОМ.

Нашла беду ВОСПРОИЗВОДИМОСТЬ — единственный прибор, который пересобирает миры, — и стоит она
часа. Этот прибор спрашивает то же самое за секунды: он не собирает миры, а сверяет ДОГОВОР —
всякое имя, которое кузня или суд берёт у дома через ввоз, обязано в этом доме быть.

    ДОГОВОР ПРОВЕРЯЕТСЯ ИМЕНАМИ, А НЕ СБОРКОЙ: сборка говорит то же, но часом позже.

ЧТО ПРОВЕРЯЕТСЯ: у всякого файла в `tools/gen_genesis_*.py` и `courts/*.py` берутся ввозы вида
«import X as F» и «import X», где X лежит в `tools/`, и все обращения «F.имя» (или «X.имя»).
Каждое такое имя ищется в модуле — без запуска кузни, одним ввозом.

ГРАНИЦА НАЗВАНА: прибор не ходит внутрь функций чужих модулей и не знает имён, собираемых на лету
(`getattr`). Он ловит РАЗОШЕДШИЙСЯ ДОГОВОР, а не всякую ошибку ввоза.

    python3 scripts/house_api.py
"""
# ПУСТОЙ-ОБХОД: --дерево no-such-dir
import ast
import importlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "courts"))

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 0
РАЗЛАДОВ_РУБЕЖ = 0


def ввозы_дома(дерево):
    """{имя в коде: имя модуля} для ввозов, чей модуль лежит в tools/."""
    вон = {}
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            for имя in узел.names:
                if (КОРЕНЬ / "tools" / f"{имя.name}.py").is_file():
                    вон[имя.asname or имя.name] = имя.name
    return вон


def взятые_имена(дерево, местные):
    """{(модуль, имя)} — всё, что берётся у ввезённого дома точкой."""
    вон = set()
    for узел in ast.walk(дерево):
        if (isinstance(узел, ast.Attribute) and isinstance(узел.value, ast.Name)
                and узел.value.id in местные):
            вон.add((местные[узел.value.id], узел.attr))
    return вон


def обход():
    if "--дерево" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--дерево") + 1])
        if not корень.is_dir():
            print(f"ДОГОВОР ДОМА ОТКАЗ: дерева нет — {корень}")
            sys.exit(2)
        return sorted(корень.rglob("*.py"))
    вон = sorted((КОРЕНЬ / "tools").glob("gen_genesis_*.py"))
    вон += sorted((КОРЕНЬ / "courts").glob("*.py"))
    return вон


def main():
    пути = обход()
    разлады, сверено, домов = [], 0, set()
    for п in пути:
        try:
            дерево = ast.parse(п.read_text(encoding="utf-8"))
        except SyntaxError as беда:
            разлады.append(f"{п.name}: не разбирается — {беда}")
            continue
        местные = ввозы_дома(дерево)
        for модуль, имя in sorted(взятые_имена(дерево, местные)):
            домов.add(модуль)
            try:
                м = importlib.import_module(модуль)
            except Exception as беда:                      # noqa: BLE001
                разлады.append(f"{п.name}: дом «{модуль}» не ввозится — {type(беда).__name__}")
                continue
            сверено += 1
            if not hasattr(м, имя):
                разлады.append(f"{п.name}: берёт у дома «{модуль}» имя «{имя}», которого нет")
    for р in разлады[:8]:
        print(f"  {р}")
    поза = "PASS" if len(разлады) <= РАЗЛАДОВ_РУБЕЖ else "FAIL"
    print(f"ДОГОВОР ДОМА {поза}: {len(разлады)} разладов (рубеж {РАЗЛАДОВ_РУБЕЖ}); "
          f"сверено имён {сверено} у {len(домов)} домов, файлов {len(пути)}")
    return 0 if len(разлады) <= РАЗЛАДОВ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
