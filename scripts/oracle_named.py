#!/usr/bin/env python3
"""[ОРАКУЛ НАЗВАН] — мир показов обязан сказать, ЧЕМ проверяется его строка.

Манифест держит у каждого мира поле `oracle` — чем истинность строки проверяется. Словарь его
объявлен в `tools/manifest_kinds.py`, и два значения в нём даны ПРОЗЕ: «none» («оракула нет: проза
не есть перечень проверяемого») и «unnamed» («проза не называет, чем строка проверяется»).

    ПОКАЗ — НЕ ПРОЗА: он несёт утверждение, и утверждение обязано быть проверяемо. Мир показов,
    объявивший, что проверять его нечем, объявляет себя непроверяемым — и лжёт, если его
    кто-то читает.

ЗАМЕР 11.09: из 257 миров показов ПЯТНАДЦАТЬ объявили `unnamed`. Все пятнадцать — старейшие миры
свода, с жанрами по двадцать-сто восемьдесят знаков против нынешних двух-трёх тысяч.

И ВСЕ ПЯТНАДЦАТЬ ЧИТАЮТСЯ. Палата, спрошенная о пробе в пятьдесят строк из каждого, назвала
читающих поимённо: `genesis_l4` — суд связок (50 из 50), `lang_ru` — суд порождения пласта и суд
формы, `proof` — суд форм доказательства, `items` — эпизодная алгебра, и так все.

    ОБЪЯВЛЕНИЕ «ПРОВЕРИТЬ НЕЧЕМ» ПРИ ЖИВОМ СУДЕ ЕСТЬ НЕ ГРАНИЦА, А УСТАРЕВШАЯ ЗАПИСЬ.

Долг был уплачен в тот же день: оракул каждого из пятнадцати назван ПО ДЕЛУ ЧИТАЮЩЕГО СУДА, а дело
сверено с кодом, а не с докстрингом. `copula_court` судит пару по объявленной таблице `ФАКТЫ` —
значит `declared`; `episode_court` пересчитывает итог из частей — значит `recompute`.

    ОПИСАНИЕ ДЕЛА СВЕРЕНО С КОДОМ СУДА, А НЕ НАПИСАНО ПО ПАМЯТИ.

ГРАНИЦА НАЗВАНА: прибор судит ОБЪЯВЛЕНИЕ, а не дело. Мир, объявивший `recompute` и никем не
пересчитываемый, он пропустит — за это отвечает досягаемость суда (`court_reach`). Здесь ловится
лишь молчание: мир, который не назвал ничего.

ГРАНИЦА ВТОРАЯ, НЕ ЗАКРЫТАЯ, И ОНА ШИРЕ, ЧЕМ КАЗАЛОСЬ: поле `boundary` стои́т `unnamed` не у
пятнадцати миров, а у СОРОКА ЧЕТЫРЁХ. Я ждал пятнадцати — тех же, что без оракула, — и прибор
поправил меня числом с первого прогона.

    ПРИБОР, ПОСТАВЛЕННЫЙ РАДИ ОДНОГО ДОЛГА, МЕРИТ И СОСЕДНИЙ, ЕСЛИ СПРОСИТЬ ЕГО ЗАОДНО.

ГРАНИЦУ МОЖНО ПЛАТИТЬ ЗАМЕРОМ, А НЕ ДОГАДКОЙ, и тридцать четыре мира из сорока четырёх уплачены
в тот же час. У манифеста есть свои признаки — дробной записи и отрицательного значения, — и суд
манифеста их ПРОВЕРЯЕТ: объявивший `whole_only` и написавший дробь падает.

    ГРАНИЦА, ОБЪЯВЛЕННАЯ ПО ЗАМЕРУ И ПРОВЕРЯЕМАЯ СУДОМ, ЕСТЬ ЗНАНИЕ; ОБЪЯВЛЕННАЯ ПО ДОГАДКЕ —
    ЛИШЬ ВЕЖЛИВОСТЬ К ПОЛЮ МАНИФЕСТА.

Оставшиеся ДЕСЯТЬ — миры, которые НЕ СЧИТАЮТ: менее половины их строк несут число вовсе (словарь,
дерево разбора, разметка, части слова).

    ГРАНИЦА СЧЁТА, ОБЪЯВЛЕННАЯ МИРУ, КОТОРЫЙ НЕ СЧИТАЕТ, ЕСТЬ ПУСТАЯ ПРАВДА: она истинна
    и не говорит ничего.

Долг их назван числом и может только убывать — но платится он не замером счёта, а знанием о том,
чего эти миры не показывают, и знание это добывается ковкой, а не признаком.

    python3 scripts/oracle_named.py
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"

# РУБЕЖ-ДОЛГА: БЕЗМОЛВНЫХ_РУБЕЖ = 0
БЕЗМОЛВНЫХ_РУБЕЖ = 0
# РУБЕЖ-ДОЛГА: БЕЗ_ГРАНИЦЫ_РУБЕЖ = 10
БЕЗ_ГРАНИЦЫ_РУБЕЖ = 10

# ЗНАЧЕНИЯ, ДАННЫЕ ПРОЗЕ: показу они не дозволены.
ПРОЗАИЧЕСКИЕ = {"unnamed", "none"}


def main():
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
        if not манифест.is_file():
            print(f"ОРАКУЛ НАЗВАН ОТКАЗ: манифеста нет — {манифест}")
            return 2
    миры = [з for з in json.loads(манифест.read_text(encoding="utf-8"))["worlds"]
            if з.get("text") == "shows"]
    if not миры:
        print("ОРАКУЛ НАЗВАН ОТКАЗ: миров показов в манифесте нет, спрашивать не о ком")
        return 2
    безмолвные = [з["name"] for з in миры
                  if set(з.get("oracle") or ()) <= ПРОЗАИЧЕСКИЕ]
    без_границы = [з["name"] for з in миры
                   if set(з.get("boundary") or ()) <= ПРОЗАИЧЕСКИЕ]
    for и in безмолвные[:10]:
        print(f"  {и}: мир показов не назвал, чем проверяется его строка")
    поза = ("PASS" if len(безмолвные) <= БЕЗМОЛВНЫХ_РУБЕЖ
            and len(без_границы) <= БЕЗ_ГРАНИЦЫ_РУБЕЖ else "FAIL")
    print(f"ОРАКУЛ НАЗВАН {поза}: {len(безмолвные)} миров без оракула "
          f"(рубеж {БЕЗМОЛВНЫХ_РУБЕЖ}), {len(без_границы)} без границы "
          f"(рубеж {БЕЗ_ГРАНИЦЫ_РУБЕЖ}); миров показов {len(миры)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
