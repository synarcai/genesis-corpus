#!/usr/bin/env python3
"""[ДВЕРИ ЕДИНИЦЫ] — сколько домов пишут форму единицы своей рукой, минуя дверь.

    ДОМ, БЕРУЩИЙ У ДВЕРИ ПРАВИЛО И ПИШУЩИЙ РУКОЙ ФОРМУ, ЕСТЬ ВТОРАЯ ДВЕРЬ,
    КОТОРАЯ СЕБЯ ТАКОВОЙ НЕ СЧИТАЕТ.

ПОВОД, НАЙДЕННЫЙ 21.09 ЗАМЕРОМ, А НЕ ПОЛОМКОЙ. Отчёт дня назвал долгом две двери на
единицы длины — `actionmeasure` для ru/en и `unitforms` для прочих. Замер нашёл иное:
`rugram`, дом русских счётных форм, объявлял СВОЮ тройку двадцати двум единицам, какие
дверь `units.py` уже знала, — и при этом звал ту же дверь за ПРАВИЛОМ (`ру_форма`). Все
двадцать две тройки совпадали с дверью до буквы, и потому долг был невидим ни одному
из трёхсот судов.

    ВТОРАЯ ДВЕРЬ, СОГЛАСНАЯ С ПЕРВОЙ, НЕ ЕСТЬ ОТСУТСТВИЕ ДОЛГА: ЭТО ДОЛГ,
    СРОК КОТОРОГО ЕЩЁ НЕ НАСТУПИЛ. Наступает он в день, когда пополняют одну.

Приставочная тройка («миллиметр») у двери ВЫВОДИТСЯ законом приставки, а рукой была
написана — и разошлась бы молча, ибо рука закона не знает.

ЧТО ПРИБОР СУДИТ. Разбирает исходники (`ast`, не чтением строк) и считает три числа:

  · ДОМОВ РУКОЙ — сколько домов пишут строкой ФОРМУ единицы, какую знает дверь;
  · ПАР ВДВОЁМ — сколько пар «единица × язык» объявлены двумя и более домами;
  · ПАР ВРОЗЬ — сколько из них УЖЕ пишут разное.

ЧЕГО ПРИБОР НЕ СУДИТ, И ЭТО ГРАНИЦА, А НЕ ПОЛНОТА:

  · ИМЯ единицы («metre», «hour») — это КЛЮЧ, которым дом зовёт дверь, и он законен;
    судится только ФОРМА («метра», «metres», «Stunden»);

  · ПАДЕЖНУЮ ПАРАДИГМУ. `rugram.ПАРАДИГМЫ` держит «час / часа / часу / час / часом /
    часе» — это падежи, а не счёт, и дверь падежей не знает вовсе. Прибор, смешавший
    их со счётной тройкой, назвал бы долгом ПАДЕЖ;

  · ПЕРВУЮ ДВЕРЬ — `units.py` — и себя самого. Всё прочее считается, включая дома
    грамматик (`unitforms` для восьми языков, `plgram` для польского): с места двери
    они суть ВТОРОЕ объявление того же понятия, и в этом весь остаток долга. Рубеж не
    обязан дойти до нуля — он обязан не расти; а упадёт он в день, когда дверь выучит
    язык, как сегодня выучила фунт.

    python3 scripts/unit_doors.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --корень /no/such/root
import ast
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import units  # noqa: E402 — дверь единиц: имена, формы и закон приставки
import unitforms  # noqa: E402 — дверь тех же единиц на восьми прочих языках

# РУБЕЖ-ДОЛГА: ДОМОВ_РУКОЙ_РУБЕЖ = 80, ПАР_ВДВОЁМ_РУБЕЖ = 18, ПАР_ВРОЗЬ_РУБЕЖ = 6, ФОРМ_РУКОЙ_РУБЕЖ = 757
#
# Числа суть ЗАМЕР 21.09 ПОСЛЕ уплаты русско-английского долга (`rugram` −22 тройки,
# `actionmeasure` −8 пар и троек), а не цель. Рубеж падает и не растёт: дом, заведший
# следующую рукопись, роняет прибор — и это ВСЯ его власть.
#
# РУБЕЖ ЗАТЯНУТ 22.09, И УБЫЛЬ РАЗДЕЛЕНА ЧЕСТНО: пар вдвоём 61 → 34 — это УПЛАТА (дом смешанной
# меры отдал двери 61 форму на девяти языках); форм рукой 877 → 818 и домов 86 → 81 — это на 59
# форм и 5 домов ПОЧИНКА САМОЙ МЕРЫ (имя-ключ, совпавшее с формой, считалось рукописью), а на
# остальное — та же уплата.
#
#     УБЫЛЬ ДОЛГА И УТОЧНЕНИЕ МЕРЫ СУТЬ РАЗНОЕ, И ЧИСЛО, ИХ СМЕШАВШЕЕ, ХВАЛИТ СЕБЯ ЧУЖИМ.
#
# ЗАТЯНУТ ВТОРИЧНО в тот же день: дома часов, дат и долей единицы отданы двери
# `unitforms.формы_единицы` — пар вдвоём 34 → 18, форм рукой 818 → 757. Остаток назван: у домов
# полосы SVAMP и календаря формы вшиты В САМИ РАМКИ, и отдать их двери — работа не выборки, а
# перестройки рамки; она ждёт своего дня.
#
# ЗАМЕР ПРИБОРА НЕ РАВЕН ЗАМЕРУ ПРОБЫ, И ЧИСЛО БЕРЁТСЯ У ПРИБОРА. Проба, писанная на
# коленке при поиске причины, знала двадцать пять языков рукой и не знала поверхностей
# `unitforms` — она насчитала 75/36/12 там, где прибор, читающий имена пакетов
# (их 29) и обе двери, видит 86/61/6.
ДОМОВ_РУКОЙ_РУБЕЖ = 80
ПАР_ВДВОЁМ_РУБЕЖ = 18
ПАР_ВРОЗЬ_РУБЕЖ = 6
# ЧЕТВЁРТОЕ ЧИСЛО — ФОРМ РУКОЙ, а не только домов: дом смешанной меры отдал двери 61 форму из
# 61, и число ДОМОВ от этого не двинулось бы вовсе. МЕРА, НЕ ВИДЯЩАЯ УПЛАТЫ, ДОЛГА НЕ МЕРИТ.
ФОРМ_РУКОЙ_РУБЕЖ = 757

# Языки, какие читают пакеты дерева. Список НЕ пишется рукой: он есть имена пакетов.
ЯЗЫКИ = {п.stem for п in (КОРЕНЬ / "tools" / "langpacks").glob("*.json")}

# Род в таблице форм стои́т рядом с формами и формой не является.
РОДЫ = {"m", "f", "n"}


def _поверхности():
    """форма → имя единицы. ТОЛЬКО формы: имя-ключ законно и не судится."""
    имена = set(units.ФОРМЫ_ВСЕХ)
    поверх = {}
    for форма, имя in units.ПОВЕРХНОСТЬ.items():
        низ = форма.lower()
        if низ in имена or форма in units.СОКРАЩЕНИЯ or len(низ) <= 2:
            continue
        поверх[низ] = имя
    for язык, единицы in unitforms.ЕДИНИЦЫ.items():
        for имя, формы in единицы.items():
            for форма in формы:
                # ИМЯ-КЛЮЧ НЕ СТАНОВИТСЯ ФОРМОЙ ОТТОГО, ЧТО СОВПАЛО С НЕЮ (22.09): нидерландское
                # «kilogram» писано так же, как каноническое имя единицы, и прибор считал ключ
                # дома его рукописью — три ложных у дома смешанной меры, отдавшего двери всё.
                if форма in РОДЫ or len(форма) <= 2 or форма.lower() in имена:
                    continue
                поверх.setdefault(форма.lower(), имя)
    return поверх


def _исходники():
    for каталог in ("tools", "scripts"):
        for путь in sorted((КОРЕНЬ / каталог).glob("*.py")):
            yield путь


def _падежные(дерево):
    """Строки таблиц падежей: их формы — не счёт, и прибор их не видит."""
    места = set()
    for узел in ast.walk(дерево):
        if not (isinstance(узел, ast.Assign) and isinstance(узел.value, ast.Dict)):
            continue
        имя = next((ц.id for ц in узел.targets if isinstance(ц, ast.Name)), "")
        if "ПАДЕЖ" not in имя and "ПАРАДИГМ" not in имя:
            continue
        for з in узел.value.values:
            for вложенный in ast.walk(з):
                строка = getattr(вложенный, "lineno", None)
                if строка is not None:
                    места.add(строка)
    return места


def _рукой(путь, поверх):
    """Формы единиц, писанные строкой в этом доме, — без падежных таблиц."""
    try:
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
    except SyntaxError:
        return {}, дерево_пусто()
    падежи = _падежные(дерево)
    найдено = collections.defaultdict(set)
    for узел in ast.walk(дерево):
        if (isinstance(узел, ast.Constant) and isinstance(узел.value, str)
                and узел.lineno not in падежи):
            низ = узел.value.strip().lower()
            if низ in поверх:
                найдено[поверх[низ]].add(низ)
    return найдено, дерево


def дерево_пусто():
    return ast.parse("")


def _языковые(путь, дерево, поверх):
    """(единица, язык) → набор форм, объявленных в этом доме."""
    объявлено = {}
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Dict):
            continue
        ключи = [к.value if isinstance(к, ast.Constant) else None for к in узел.keys]
        if sum(1 for к in ключи if isinstance(к, str) and к.lower() in ЯЗЫКИ) < 3:
            continue
        for ключ, значение in zip(ключи, узел.values):
            if not (isinstance(ключ, str) and ключ.lower() in ЯЗЫКИ):
                continue
            for _, набор in _ветви(значение):
                формы = _строки(набор)
                if not формы:
                    continue
                кандидаты = {поверх.get(ф.lower()) for ф in формы} - {None}
                if len(кандидаты) != 1:
                    continue
                единица = кандидаты.pop()
                объявлено[(единица, ключ.lower())] = tuple(
                    ф for ф in формы if ф not in РОДЫ)
    return объявлено


def _ветви(значение):
    """Кортеж форм — или словарь/вызов, чьи ветви суть кортежи форм."""
    if isinstance(значение, (ast.Tuple, ast.List)):
        yield None, значение
    elif isinstance(значение, ast.Dict):
        for к, з in zip(значение.keys, значение.values):
            yield (к.value if isinstance(к, ast.Constant) else None), з
    elif isinstance(значение, ast.Call):
        for слово in значение.keywords:
            yield слово.arg, слово.value


def _строки(узел):
    if not isinstance(узел, (ast.Tuple, ast.List)):
        return ()
    формы = [э.value.strip() for э in узел.elts
             if isinstance(э, ast.Constant) and isinstance(э.value, str)]
    return tuple(формы) if len(формы) == len(узел.elts) else ()


def мера():
    поверх = _поверхности()
    рукой, пары = {}, collections.defaultdict(list)
    for путь in _исходники():
        if путь.name in ("units.py", "unit_doors.py"):
            continue            # сама дверь и сам прибор
        формы, дерево = _рукой(путь, поверх)
        if формы:
            рукой[путь.name] = формы
        for (единица, язык), набор in _языковые(путь, дерево, поверх).items():
            пары[(единица, язык)].append((путь.name, набор))
    вдвоём = {к: v for к, v in пары.items() if len({д for д, _ in v}) > 1}
    врозь = {к: v for к, v in вдвоём.items() if len({н for _, н in v}) > 1}
    return рукой, вдвоём, врозь


def main():
    подробно = "--подробно" in sys.argv
    рукой, вдвоём, врозь = мера()
    беды = []
    формами = sum(sum(len(в) for в in формы.values()) for формы in рукой.values())
    if формами > ФОРМ_РУКОЙ_РУБЕЖ:
        беды.append(f"форм рукой {формами} > рубежа {ФОРМ_РУКОЙ_РУБЕЖ}")
    if len(рукой) > ДОМОВ_РУКОЙ_РУБЕЖ:
        беды.append(f"домов рукой {len(рукой)} > рубежа {ДОМОВ_РУКОЙ_РУБЕЖ}")
    if len(вдвоём) > ПАР_ВДВОЁМ_РУБЕЖ:
        беды.append(f"пар вдвоём {len(вдвоём)} > рубежа {ПАР_ВДВОЁМ_РУБЕЖ}")
    if len(врозь) > ПАР_ВРОЗЬ_РУБЕЖ:
        беды.append(f"пар врозь {len(врозь)} > рубежа {ПАР_ВРОЗЬ_РУБЕЖ}")
    if подробно:
        for (единица, язык), дома in sorted(врозь.items()):
            print(f"  {единица} × {язык}:")
            for дом, набор in sorted(дома):
                print(f"      {дом:28} {набор}")
    слово = "FAIL" if беды else "PASS"
    print(f"ДВЕРИ ЕДИНИЦЫ {слово}: форм рукой {формами} (рубеж {ФОРМ_РУКОЙ_РУБЕЖ}), "
          f"домов рукой {len(рукой)} (рубеж {ДОМОВ_РУКОЙ_РУБЕЖ}), "
          f"пар вдвоём {len(вдвоём)} (рубеж {ПАР_ВДВОЁМ_РУБЕЖ}), "
          f"пар врозь {len(врозь)} (рубеж {ПАР_ВРОЗЬ_РУБЕЖ}); "
          f"единиц у двери {len(units.ФОРМЫ_ВСЕХ)}, языков {len(ЯЗЫКИ)}")
    for беда in беды:
        print(f"  ДОЛГ ВЫРОС: {беда}")
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())
