#!/usr/bin/env python3
"""[ПЕРЕПИСЬ ПОРОГОВ] — всякое число, стоящее в роли рубежа, и есть ли у него основание.

Пай аудита краты (04.09, слово владельца, раздел d5: «меры и пороги»). Закон
выразительной архитектуры запрещает невыведенные константы; но запрет, не
измеренный, есть пожелание. Прибор переписывает ЧИСЛА В РОЛИ ПОРОГА и делит их
на три класса — не по вкусу, а по тому, что стоит рядом в коде:

  ВЫВЕДЕН   — число вычислено из данных или другого объявления (не литерал);
  ОБЪЯВЛЕН  — литерал, при котором в те же шесть строк названо ОСНОВАНИЕ
              (закон, номер М-, слово «потому/ибо/из», «объявлен», «=» в
              комментарии, счёт от предмета);
  ВКУС      — литерал без основания рядом. Не обязательно порок: бюджет выборки
              или ширина колонки — тоже число. Но число, названное «рубежом» и
              не имеющее основания, есть то самое «≥ 5», которое d5 заменил на
              «> 0» без перемены результата: шум, читавшийся как смысл.

Две поверхности: ИМЕНОВАННЫЕ константы («РУБЕЖ = 12») и ВСТРОЕННЫЕ сравнения
(«>= 5», «[:12]», «< 3»). Единицу и ноль прибор не считает: они суть не пороги, а
существование и отсутствие.

    python3 scripts/threshold_census.py [--подробно] [--папки scripts courts tools]
"""
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ИМЕНОВАННАЯ = re.compile(r"^\s*([А-ЯЁA-Z_][А-ЯЁA-Z_0-9]{2,})\s*=\s*(\d+)\s*(#.*)?$")
# СРЕЗЫ «[:70]» И «range(8)» НЕ СЧИТАЮТСЯ: первая перепись их считала и
# назвала порогом ширину печати — число, считавшее не то, что называло.
# Порог есть СРАВНЕНИЕ величины с числом; всё прочее — строй.
# ШИРИНА КОЛОНКИ «{п:>6}» — НЕ СРАВНЕНИЕ: четвёртая поправка прибора на себе.
# Первая перепись встроенных считала спецификации формата порогами — 45 из
# «вкуса» были шириной печати. Знак после двоеточия не есть знак «больше».
ВСТРОЕННАЯ = re.compile(r"(?<![:{])(?:>=|<=|==|!=|>|<)\s*(\d+)\b")
# ОСНОВАНИЕ УЗНАЁТСЯ СЛОВОМ, А НЕ ЗНАКОМ: первая проба принимала «=» в
# комментарии за основание и объявила все 26 именованных констант объявленными
# — прибор, считавший не то, что называл, на своей же первой странице.
# восьмая поправка на себе: слово основания пишется и ЗАГЛАВНЫМИ («БЮДЖЕТ ВЫБОРКИ, НЕ ПОРОГ»)
ОСНОВАНИЕ = re.compile(r"#.*(?:потому|ибо|закон|М-\d|LAW|выведен|объявлен|бюджет|выборк|колонк|ширин|ровно|столько|замер|долг|ступен|форма|взят|путь|достигнут)", re.I)
# ХРАПОВИК — рубеж, объявленный протоколом «РУБЕЖ-ДОЛГА»: число снято замером и
# не смеет расти. Это не вкус и не вывод, а третий род: ПАМЯТЬ О ДОСТИГНУТОМ.
ХРАПОВИК = re.compile(r"РУБЕЖ-ДОЛГА")
# ОКНО В ДЕСЯТЬ СТРОК: при шести прибор назвал вкусом три константы с основанием
# в восьмой строке выше — мерил ширину своего окна, а не крату
ОКНО = 10
_ЛИТЕРАЛ = re.compile(r'"[^"]*"|\'[^\']*\'|«[^»]*»')
_ТРОЙНАЯ = ('"""', "\'\'\'")
# ПЕЧАТЬ — «сколько примеров показать»: не порог, а бюджет вывода. Пятая
# поправка прибора на себе: «if len(примеры) < 5» стояло первым родом «вкуса».
_ПЕЧАТЬ = re.compile(r"len\((?:примеры|образцы|показ|беды|находки|строки_печати)\w*\)\s*[<>]")


def перепись(папки, подробно):
    итог = collections.Counter()
    вкус = []
    for папка in папки:
        for п in sorted((КОРЕНЬ / папка).glob("*.py")):
            строки = п.read_text(encoding="utf-8", errors="replace").splitlines()
            в_докстринге = False
            for i, с in enumerate(строки, 1):
                # ДОКСТРИНГИ И СТРОКОВЫЕ ЛИТЕРАЛЫ — не код: перепись считала
                # собственную документацию («>= 5» в примере) порогом
                if any(т3 in с for т3 in _ТРОЙНАЯ):
                    if sum(с.count(т3) for т3 in _ТРОЙНАЯ) % 2 == 1:
                        в_докстринге = not в_докстринге
                    continue
                if в_докстринге or с.lstrip().startswith("#"):
                    continue
                код = _ЛИТЕРАЛ.sub('""', с.split("#", 1)[0])
                рядом = " ".join(строки[max(0, i - 1 - ОКНО):i])
                м = ИМЕНОВАННАЯ.match(с)
                if м:
                    n = int(м.group(2))
                    if n in (0, 1):
                        continue
                    if ХРАПОВИК.search(рядом):
                        класс = "ХРАПОВИК"
                    else:
                        класс = "ОБЪЯВЛЕН" if (м.group(3) or ОСНОВАНИЕ.search(рядом)) else "ВКУС"
                    итог[("именованная", класс)] += 1
                    if класс == "ВКУС":
                        вкус.append((str(п.relative_to(КОРЕНЬ)), i, f"{м.group(1)} = {n}"))
                    continue
                if _ПЕЧАТЬ.search(код):
                    итог[("встроенная", "ПЕЧАТЬ")] += 1
                    continue
                for м in ВСТРОЕННАЯ.finditer(код):
                    n = int(м.group(1))
                    # двойка — строй пары, а не порог; порогом зовётся число от трёх
                    if n < 3:
                        continue
                    класс = "ОБЪЯВЛЕН" if ОСНОВАНИЕ.search(рядом) else "ВКУС"
                    итог[("встроенная", класс)] += 1
                    if класс == "ВКУС" and подробно:
                        вкус.append((str(п.relative_to(КОРЕНЬ)), i, код.strip()[:70]))
    return итог, вкус


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--папки", nargs="+", default=["scripts", "courts"])
    а = ап.parse_args()
    итог, вкус = перепись(а.папки, а.подробно)
    print(f"{'поверхность':<14}{'ОБЪЯВЛЕН':>10}{'ХРАПОВИК':>10}{'ПЕЧАТЬ':>8}{'ВКУС':>8}{'доля вкуса':>12}")
    for пов in ("именованная", "встроенная"):
        о, х, пч, в = (итог[(пов, "ОБЪЯВЛЕН")], итог[(пов, "ХРАПОВИК")],
                       итог[(пов, "ПЕЧАТЬ")], итог[(пов, "ВКУС")])
        доля = 100 * в // (о + х + пч + в) if (о + х + пч + в) else 0
        print(f"{пов:<14}{о:>10}{х:>10}{пч:>8}{в:>8}{доля:>11} %")
    for путь, i, что in вкус[:40]:
        print(f"  ВКУС {путь}:{i}  {что}")
    о = итог[("именованная", "ОБЪЯВЛЕН")]
    в = итог[("именованная", "ВКУС")]
    х = итог[("именованная", "ХРАПОВИК")]
    print(f"ПЕРЕПИСЬ ПОРОГОВ: именованных {о + х + в} (объявлено {о}, храповиков {х}, ВКУС {в}); "
          f"встроенных сравнений от трёх {итог[('встроенная', 'ОБЪЯВЛЕН')] + итог[('встроенная', 'ВКУС')]} "
          f"(печать {итог[('встроенная', 'ПЕЧАТЬ')]}, без основания рядом {итог[('встроенная', 'ВКУС')]} — ВЕРХНЯЯ ОЦЕНКА: строй и порог здесь не разделены); "
          f"папки {' '.join(а.папки)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
