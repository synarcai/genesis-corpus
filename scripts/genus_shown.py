#!/usr/bin/env python3
"""[РОД ДОШЁЛ] — всякий род, объявленный домом, обязан стоять в мире хоть одной страницей.

Дом объявляет роды и проверяет сам себя: его самопроверка краснеет, если род пуст В ДОМЕ. Между
домом и миром лежат ворота записи и ПОТОЛОК ПОВТОРОВ, снимающий копии сверх закона (LAW = 2 на
мир). Ни один прибор не спрашивает, что дошло ДО МИРА.

    САМОПРОВЕРКА ДОМА ГОВОРИТ О ДОМЕ, А НЕ О МИРЕ. Между ними стои́т ковка, и она умеет ронять.

Прибор берёт кузню (`tools/gen_genesis_*.py`), читает из неё ДВА имени — ввезённый дом и цель, —
и спрашивает мир: стои́т ли в нём хоть одна страница каждого объявленного рода?

    РОД, ОБЪЯВЛЕННЫЙ И НЕ ДОШЕДШИЙ, ЕСТЬ ОБЕЩАНИЕ ЧИТАТЕЛЮ, КОТОРОГО НИКТО НЕ СДЕРЖАЛ.

ЦЕЛЬ И ДОМ БЕРУТСЯ РАЗБОРОМ ДЕРЕВА, А НЕ ПОИСКОМ ПОДСТРОКИ — тем же ходом, каким `house_api`
берёт договор дома, а `orphan_world` — цель кузни.

ГРАНИЦА НАЗВАНА: судятся лишь дома, объявившие `РОДЫ` и `ПОКАЗЫ` парой (имя рода стои́т вторым
в значении показа). Дом иного устройства прибор не толкует и молча пропускает — считать чужое
устройство своим значило бы обвинять по форме.

    python3 scripts/genus_shown.py
"""
# ПУСТОЙ-ОБХОД: --кузни no-such-dir
import ast
import importlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: НЕДОШЕДШИХ_РУБЕЖ = 0
НЕДОШЕДШИХ_РУБЕЖ = 0


def _дом_и_цель(путь):
    """(имя дома, цель) из кузни — разбором дерева."""
    try:
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return None, None
    дом = цель = None
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            for имя in узел.names:
                # СВОЙ ДОМ КУЗНЯ ЗОВЁТ `F`, И ТОЛЬКО ЭТО ЕСТЬ ПРИЗНАК. Две редакции ошиблись
                # до этой: первая брала лишь имена на `forms` и не видела 116 кузниц из 220
                # (дом бывает и `actionmeasure`); вторая взяла ЛЮБОЙ `*forms` — и приписала
                # `gen_genesis_genderverb.py` дом `svampforms`, ввезённый им ПОД ИМЕНЕМ `S`
                # как ЗАИМСТВОВАННЫЙ. Тридцать девять «недошедших» родов оказались моим
                # разбором, а не бедой свода.
                #
                #     ПРИЗНАК ПО ОКОНЧАНИЮ ИМЕНИ ВИДИТ ОБЫЧАЙ, А НЕ УСТРОЙСТВО; ПРОЗВИЩЕ,
                #     ОБЪЯВЛЕННОЕ ОДИНАКОВО ВО ВСЕХ КУЗНЯХ, ВИДИТ УСТРОЙСТВО.
                if имя.asname == "F" and (КОРЕНЬ / "tools" / f"{имя.name}.py").is_file():
                    дом = имя.name
        elif isinstance(узел, ast.Assign):
            for цел in узел.targets:
                if (isinstance(цел, ast.Name) and цел.id == "ЦЕЛЬ"
                        and isinstance(узел.value, ast.Constant)
                        and isinstance(узел.value.value, str)):
                    цель = узел.value.value
    return дом, цель


def main():
    двор = КОРЕНЬ / "tools"
    if "--кузни" in sys.argv:
        двор = pathlib.Path(sys.argv[sys.argv.index("--кузни") + 1])
        if not двор.is_dir():
            print(f"РОД ДОШЁЛ ОТКАЗ: двора кузниц нет — {двор}")
            return 2
    кузни = sorted(двор.glob("gen_genesis_*.py"))
    if not кузни:
        print(f"РОД ДОШЁЛ ОТКАЗ: кузниц в «{двор}» нет, спрашивать не о чем")
        return 2
    недошедших, сверено, домов, пропущено = [], 0, 0, 0
    for кузня in кузни:
        имя_дома, цель = _дом_и_цель(кузня)
        if not имя_дома or not цель:
            пропущено += 1
            continue
        мир = КОРЕНЬ / цель
        if not мир.is_file():
            пропущено += 1
            continue
        try:
            дом = importlib.import_module(имя_дома)
        except Exception:                                  # noqa: BLE001
            пропущено += 1
            continue
        # ИМЯ РОДОВ ОБЪЯВЛЯЕТСЯ ДОМОМ, И ИМЁН ЭТИХ НЕСКОЛЬКО: «РОДЫ» у молодых домов,
        # «ФОРМЫ» у тех, что старше. Прибор берёт первое, какое найдёт.
        роды = None
        for как in ("РОДЫ", "ФОРМЫ", "ВИДЫ"):
            роды = getattr(дом, как, None)
            if роды:
                break
        показы = getattr(дом, "ПОКАЗЫ", None)
        if not роды or not isinstance(показы, dict):
            пропущено += 1
            continue
        по_роду = {}
        for страница, метка in показы.items():
            род = (метка[1] if isinstance(метка, (tuple, list)) and len(метка) > 1
                   else метка)
            по_роду.setdefault(род, []).append(страница)
        строки = set(мир.read_text(encoding="utf-8", errors="replace").split("\n"))
        домов += 1
        for род in роды:
            свои = по_роду.get(род)
            if not свои:
                continue
            сверено += 1
            if not any(с in строки for с in свои):
                недошедших.append(f"{имя_дома}: род «{род}» объявлен и НЕ дошёл до {цель}")
    for н in недошедших[:8]:
        print(f"  {н}")
    поза = "PASS" if len(недошедших) <= НЕДОШЕДШИХ_РУБЕЖ else "FAIL"
    print(f"РОД ДОШЁЛ {поза}: {len(недошедших)} родов объявлено и не дошло "
          f"(рубеж {НЕДОШЕДШИХ_РУБЕЖ}); сверено родов {сверено} у {домов} домов, "
          f"кузниц не истолковано {пропущено}")
    return 0 if len(недошедших) <= НЕДОШЕДШИХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
