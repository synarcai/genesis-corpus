#!/usr/bin/env python3
"""[РОД ДОШЁЛ] — всякий род, объявленный домом, обязан стоять в мире хоть одной страницей.

Дом объявляет роды и проверяет сам себя: его самопроверка краснеет, если род пуст В ДОМЕ. Между
домом и миром лежат ворота записи и ПОТОЛОК ПОВТОРОВ, снимающий копии сверх закона (LAW = 2 на
мир). Ни один прибор не спрашивает, что дошло ДО МИРА.

    САМОПРОВЕРКА ДОМА ГОВОРИТ О ДОМЕ, А НЕ О МИРЕ. Между ними стои́т ковка, и она умеет ронять.

Прибор берёт кузню (`tools/gen_genesis_*.py`), читает из неё ДВА имени — ввезённый дом и цель, —
и спрашивает мир: стои́т ли в нём хоть одна страница каждого объявленного рода?

    РОД, ОБЪЯВЛЕННЫЙ И НЕ ДОШЕДШИЙ, ЕСТЬ ОБЕЩАНИЕ ЧИТАТЕЛЮ, КОТОРОГО НИКТО НЕ СДЕРЖАЛ.

ЦЕЛЬ И ДОМ БЕРУТСЯ РАЗБОРОМ ДЕРЕВА, А НЕ ПОИСКОМ ПОДСТРОКИ — тем же ходом, каким `house_api`
берёт договор дома, а `orphan_world` — цель кузни.

ГРАНИЦА НАЗВАНА: судятся лишь дома, объявившие `РОДЫ` и `ПОКАЗЫ` парой (имя рода стои́т вторым
в значении показа). Дом иного устройства прибор не толкует и молча пропускает — считать чужое
устройство своим значило бы обвинять по форме.

    python3 scripts/genus_shown.py
"""
# ПУСТОЙ-ОБХОД: --кузни no-such-dir
import ast
import re
import importlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: НЕДОШЕДШИХ_РУБЕЖ = 0
НЕДОШЕДШИХ_РУБЕЖ = 0


def _дом_и_цель(путь):
    """(имя дома, цель) из кузни — разбором дерева."""
    try:
        дерево = ast.parse(путь.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return None, None
    дом = цель = None
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            for имя in узел.names:
                # СВОЙ ДОМ КУЗНЯ ЗОВЁТ `F`, И ТОЛЬКО ЭТО ЕСТЬ ПРИЗНАК. Две редакции ошиблись
                # до этой: первая брала лишь имена на `forms` и не видела 116 кузниц из 220
                # (дом бывает и `actionmeasure`); вторая взяла ЛЮБОЙ `*forms` — и приписала
                # `gen_genesis_genderverb.py` дом `svampforms`, ввезённый им ПОД ИМЕНЕМ `S`
                # как ЗАИМСТВОВАННЫЙ. Тридцать девять «недошедших» родов оказались моим
                # разбором, а не бедой свода.
                #
                #     ПРИЗНАК ПО ОКОНЧАНИЮ ИМЕНИ ВИДИТ ОБЫЧАЙ, А НЕ УСТРОЙСТВО; ПРОЗВИЩЕ,
                #     ОБЪЯВЛЕННОЕ ОДИНАКОВО ВО ВСЕХ КУЗНЯХ, ВИДИТ УСТРОЙСТВО.
                if имя.asname == "F" and (КОРЕНЬ / "tools" / f"{имя.name}.py").is_file():
                    дом = имя.name
        elif isinstance(узел, ast.Assign):
            for цел in узел.targets:
                if (isinstance(цел, ast.Name) and цел.id == "ЦЕЛЬ"
                        and isinstance(узел.value, ast.Constant)
                        and isinstance(узел.value.value, str)):
                    цель = узел.value.value
    return дом, цель


ПОКАЗЫ_В_ДОМЕ = re.compile(r"^ПОКАЗЫ\s*[:=]", re.M)


def _есть_дом(кузня):
    """Есть ли у кузни ДОМ вовсе: ввезённый модуль двора `tools` с набором `ПОКАЗЫ`.

    Признак берётся ДЕЛОМ, а не именем: не «кончается ли имя на forms» и не «зовётся ли
    прозвищем F», а «несёт ли ввезённый модуль набор показов». Прозвище `F` остаётся
    обычаем и проверяется отдельно — но отсутствие его у кузни, ввозящей дом, есть ДОЛГ
    КУЗНИ, а у кузни без дома — свойство, и числа их разные.
    """
    текст = кузня.read_text(encoding="utf-8", errors="replace")
    # КУЗНЯ, ОБЪЯВИВШАЯ СВОИ ПОКАЗЫ, САМА СЕБЕ ДОМ — и чужой модуль она ввозит ЗА МАТЕРИАЛОМ,
    # а не за показами. `gen_genesis_genderverb` ввозит `svampforms as S` ради лиц и рамок,
    # а страницы пишет своими `ПОКАЗЫ = _показы()`; приписать ей дом `svampforms` значило бы
    # спросить с неё чужие роды — ровно та ошибка, о какой предупреждает шрам этого прибора.
    #
    #     ДОМ КУЗНИ ЕСТЬ ТОТ, ЧЬИ ПОКАЗЫ ОНА ПИШЕТ, А НЕ ТОТ, КОГО ОНА ЗОВЁТ. Ввоз говорит о
    #     знакомстве, и только письмо — о принадлежности.
    if ПОКАЗЫ_В_ДОМЕ.search(текст):
        return False
    try:
        дерево = ast.parse(текст)
    except (SyntaxError, UnicodeDecodeError):
        return False
    имена = []
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            имена += [и.name for и in узел.names]
        elif isinstance(узел, ast.ImportFrom) and узел.module:
            имена.append(узел.module)
    for имя in имена:
        путь = КОРЕНЬ / "tools" / f"{имя}.py"
        if путь.is_file() and ПОКАЗЫ_В_ДОМЕ.search(путь.read_text(encoding="utf-8",
                                                                  errors="replace")):
            return True
    return False


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ДОМ КУЗНИЦЫ НАХОДИТСЯ ПО ПРОЗВИЩУ.

        ЭТОТ ПРИБОР СЧИТАЕТ ЛИШЬ ТЕХ, КОГО НАШЁЛ, И МОЛЧИТ О ТЕХ, КОГО НЕ НАШЁЛ. Пусть
        признак дома («import <дом> as F») перестанет узнаваться — и всякая кузница уйдёт
        в «не истолковано», а прибор скажет «0 родов не дошло», сверив НОЛЬ ДОМОВ.

        ЭТО НЕ ВЫДУМКА: 12.09 пять новых домов дня были названы в кузницах прозвищами
        `M`, `T`, `O`, `W`, `C` — и сорок три их рода не проверялись ВОВСЕ, а прибор был
        зелен. Нашлось это чтением прибора, а не его вердиктом.

        ПРИБОР, НАХОДЯЩИЙ ПРЕДМЕТ ПО ОБЪЯВЛЕННОМУ ПРИЗНАКУ, МОЛЧИТ О ТОМ, КТО ПРИЗНАКА НЕ
        НОСИТ, — И МОЛЧАНИЕ ЭТО НЕОТЛИЧИМО ОТ ЗДОРОВЬЯ.

    Четыре кузницы, и про каждую известно заранее, найдётся ли у неё дом и цель.
    """
    import tempfile
    беды = []
    случаи = (
        ('import rugram as F\nЦЕЛЬ = "datasets/genesis_проба.txt"\n',
         ("rugram", "datasets/genesis_проба.txt"), "прозвище F и цель"),
        ('import rugram as R\nЦЕЛЬ = "datasets/genesis_проба.txt"\n',
         (None, "datasets/genesis_проба.txt"), "чужое прозвище — дом не назван"),
        ('import rugram as F\n', ("rugram", None), "дом есть, цели нет"),
        ('x = 1\n', (None, None), "ни дома, ни цели"),
    )
    with tempfile.TemporaryDirectory() as д:
        for текст, ждём, что in случаи:
            п = pathlib.Path(д) / "gen_genesis_проба.py"
            п.write_text(текст, encoding="utf-8")
            дало = _дом_и_цель(п)
            if дало != ждём:
                беды.append(f"{что}: {дало} вместо {ждём}")
        # ДОМ, КОТОРОГО НЕТ НА СВЕТЕ, НЕ НАЗЫВАЕТСЯ ДОМОМ, ХОТЬ БЫ И ПОД ПРОЗВИЩЕМ F.
        п = pathlib.Path(д) / "gen_genesis_нет.py"
        п.write_text('import нет_такого_дома as F\nЦЕЛЬ = "datasets/x.txt"\n',
                     encoding="utf-8")
        if _дом_и_цель(п)[0] is not None:
            беды.append("несуществующий дом назван домом — сверять будут с пустотой")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"РОД ДОШЁЛ ОТКАЗ: признак дома не доказан ({len(беды)} бед)")
        return 2
    двор = КОРЕНЬ / "tools"
    if "--кузни" in sys.argv:
        двор = pathlib.Path(sys.argv[sys.argv.index("--кузни") + 1])
        if not двор.is_dir():
            print(f"РОД ДОШЁЛ ОТКАЗ: двора кузниц нет — {двор}")
            return 2
    кузни = sorted(двор.glob("gen_genesis_*.py"))
    if not кузни:
        print(f"РОД ДОШЁЛ ОТКАЗ: кузниц в «{двор}» нет, спрашивать не о чем")
        return 2
    недошедших, сверено, домов, пропущено, сами = [], 0, 0, 0, 0
    for кузня in кузни:
        имя_дома, цель = _дом_и_цель(кузня)
        if not имя_дома or not цель:
            # КУЗНЯ БЕЗ ДОМА НЕ ЕСТЬ КУЗНЯ С ДОМОМ НЕОПОЗНАННЫМ (21.09), И СМЕШИВАТЬ ИХ В
            # ОДНОМ ЧИСЛЕ ЗНАЧИТ ГОВОРИТЬ О СЕБЕ ТО, ЧТО ДУМАЕШЬ О ДРУГИХ. Пятьдесят семь
            # кузниц свода не звали дом прозвищем `F`, и все они числились одним числом «не
            # истолковано» — будто прибор чего-то не разобрал. На деле у большинства ДОМА
            # НЕТ ВОВСЕ: кузня пишет показы сама, своими рамками, и объявлять ей нечего.
            #
            #     ЧИСЛО, СМЕШИВАЮЩЕЕ «У НЕГО НЕТ» С «Я НЕ НАШЁЛ», ОБВИНЯЕТ ДЕРЕВО В СВОЕЙ
            #     СЛЕПОТЕ. Первое есть свойство предмета, второе — долг меры, и лечатся они
            #     разным: свойство объявляется, долг платится.
            #
            # Дом узнаётся по делу, а не по имени: ввезённый модуль двора `tools`, несущий
            # набор `ПОКАЗЫ`, и есть дом. Не нашлось такого — кузня сама себе дом.
            if _есть_дом(кузня):
                пропущено += 1
            else:
                сами += 1
            continue
        мир = КОРЕНЬ / цель
        if not мир.is_file():
            пропущено += 1
            continue
        try:
            дом = importlib.import_module(имя_дома)
        except Exception:                                  # noqa: BLE001
            пропущено += 1
            continue
        # ИМЯ РОДОВ ОБЪЯВЛЯЕТСЯ ДОМОМ, И ИМЁН ЭТИХ НЕСКОЛЬКО: «РОДЫ» у молодых домов,
        # «ФОРМЫ» у тех, что старше. Прибор берёт первое, какое найдёт.
        роды = None
        for как in ("РОДЫ", "ФОРМЫ", "ВИДЫ"):
            роды = getattr(дом, как, None)
            if роды:
                break
        показы = getattr(дом, "ПОКАЗЫ", None)
        if not роды or not isinstance(показы, dict):
            пропущено += 1
            continue
        по_роду = {}
        for страница, метка in показы.items():
            род = (метка[1] if isinstance(метка, (tuple, list)) and len(метка) > 1
                   else метка)
            по_роду.setdefault(род, []).append(страница)
        строки = set(мир.read_text(encoding="utf-8", errors="replace").split("\n"))
        домов += 1
        for род in роды:
            свои = по_роду.get(род)
            if not свои:
                continue
            сверено += 1
            if not any(с in строки for с in свои):
                недошедших.append(f"{имя_дома}: род «{род}» объявлен и НЕ дошёл до {цель}")
    for н in недошедших[:8]:
        print(f"  {н}")
    поза = "PASS" if len(недошедших) <= НЕДОШЕДШИХ_РУБЕЖ else "FAIL"
    print(f"РОД ДОШЁЛ {поза}: {len(недошедших)} родов объявлено и не дошло "
          f"(рубеж {НЕДОШЕДШИХ_РУБЕЖ}); сверено родов {сверено} у {домов} домов, "
          f"кузниц не истолковано {пропущено}"
          + (" — ДОЛГ прибора" if пропущено else "")
          + f", кузниц без дома {сами} — они пишут показы сами, и это свойство")
    return 0 if len(недошедших) <= НЕДОШЕДШИХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
