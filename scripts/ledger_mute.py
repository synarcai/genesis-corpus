#!/usr/bin/env python3
"""[НЕМОЙ ПРИБОР] — кто стои́т в наборе, а вердикта в леджере не оставил НИ РАЗУ.

Набор пишет в `reports/ledger.tsv` строку о каждом приборе: метка, имя, код,
вердикт. До 12.09 строка писалась и о том, кто НЕ СУДИЛ: если `run_one` был
снят сигналом, файла с кодом он не оставлял, и родитель ставил `|| echo 2` —
код 2 при ПУСТОМ вердикте. Запись выходила неотличимой от суда, сказавшего
ОТКАЗ.

    ЗАПИСЬ ОБ ОБРЫВЕ, ЧИТАЕМАЯ КАК ВЕРДИКТ, ДЕРЖИТ ПРИБОР В ВЕЧНОМ ФРОНТЕ.
    `--продолжить` пропускает того, чей последний вердикт ЗЕЛЁН; у оборванного
    зелёного нет никогда, и всякий следующий прогон доходит ровно до него — а
    значит, всякий следующий обрыв ложится на него же. Слепота сама себя кормит.

Замер 12.09, которым беда и найдена: строк леджера 7 997, из них с пустым
вердиктом 1 982 (24%), из них 1 966 — за один день; последней строкой обрыв
стоял у 221 прибора из 316 при ДЕВЯТИ действительно павших; точка объявила
«пало 311 из 311» о наборе, который не судил ни разу. Двадцать два суда —
`dist`, `primewalk`, `orderlaw`, `gender`, `measureprec`, `chancetrap`,
`ratetrap`, `negquant`, `measuregrow`, `dim`, `fence`, `measure`, `turn`,
`overlap`, `wmean`, `cond`, `numline`, `squnit`, `pctbase`, `leap`, `tzone`,
`median` — лежали непрерывным куском списка и молчали шесть дней. Прогнаны
рукою по одному: все двадцать два ЦЕЛЫ, а цена всех двадцати двух вместе
есть ТРИДЦАТЬ ВОСЕМЬ СЕКУНД.

    МОЛЧАНИЕ О ПРИБОРЕ НЕ ЕСТЬ МЕРА ЕГО ЦЕНЫ. Здесь оно было мерой
    бухгалтерии: одного `|| echo 2` хватило, чтобы тридцать восемь секунд
    работы выглядели непосильными шесть дней подряд.

ДВА СОСТОЯНИЯ РАЗЛИЧАЮТСЯ, И ЛИШЬ ОДНО ЕСТЬ ДОЛГ:

  · НЕМОЙ — набор до него ДОХОДИЛ (обрывы в леджере есть), а вердикта нет ни
    одного. Это и есть беда: прибор в вечном фронте. Рубеж 0.
  · НЕ ГОНЯВШИЙСЯ — в леджере нет ни единой его строки. Так выглядит всякий
    прибор, поставленный после последнего прогона набора, и это не долг, а
    возраст. Считается и называется, рубежа не имеет.

    python3 scripts/ledger_mute.py
"""
# ПУСТОЙ-ОБХОД: --леджер no-such-ledger
import argparse
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ЛЕДЖЕР = КОРЕНЬ / "reports" / "ledger.tsv"
НАБОР = КОРЕНЬ / "scripts" / "courts.sh"

# ТОТ ЖЕ ПРИЗНАК, ЧТО У `panel_court`: набор зовёт прибор путём в кавычках.
В_НАБОРЕ = re.compile(r'"([a-z_]+/[a-z0-9_]+\.py)')

# РУБЕЖ-ДОЛГА: НЕМЫХ_РУБЕЖ = 0
НЕМЫХ_РУБЕЖ = 0


def разбор(строки):
    """Вердикты и обрывы по именам приборов.

    Вердиктом считается строка с НЕПУСТЫМ четвёртым полем; обрывом — с пустым.
    """
    вердиктов, обрывов = {}, {}
    for с in строки:
        ч = с.split("\t")
        if len(ч) < 4:
            continue
        куда = вердиктов if ч[3].strip() else обрывов
        куда[ч[1]] = куда.get(ч[1], 0) + 1
    return вердиктов, обрывов


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ОБРЫВ ОТЛИЧИМ ОТ ВЕРДИКТА.

    Строки здесь — настоящей формы леджера, поле в поле: так их пишет
    `flush_range`, и ровно так они лежат в `reports/ledger.tsv` тысячами.
    Пусть разбор перестанет глядеть на пустоту четвёртого поля — и немой
    сольётся с павшим, а прибор объявит «немых 0», не умея их видеть.

        НУЛЬ ЗРЯЧЕГО ОБЯЗАН ОТЛИЧАТЬСЯ ОТ НУЛЯ СЛЕПОГО.
    """
    беды = []
    выдумка = [
        "2026-09-12T12:00:00Z\tалеф_court.py\t0\tАЛЕФ PASS: 0 ложных из 10",
        "2026-09-12T12:00:01Z\tалеф_court.py\t2\t",
        "2026-09-12T12:00:02Z\tбет_court.py\t2\t",
        "2026-09-12T12:00:03Z\tбет_court.py\t2\t",
        "2026-09-12T12:00:04Z\tгимел_court.py\t1\tГИМЕЛ FAIL: 3 ложных из 10",
        "не строка леджера вовсе",
    ]
    вердиктов, обрывов = разбор(выдумка)
    if вердиктов.get("алеф_court.py") != 1:
        беды.append(f"вердиктов алефа сочтено {вердиктов.get('алеф_court.py')}, а не 1")
    if обрывов.get("алеф_court.py") != 1:
        беды.append(f"обрывов алефа сочтено {обрывов.get('алеф_court.py')}, а не 1")
    if "бет_court.py" in вердиктов:
        беды.append("бет сочтён судившим, хотя обе его строки пусты — обрыв слился с судом")
    if обрывов.get("бет_court.py") != 2:
        беды.append(f"обрывов бета сочтено {обрывов.get('бет_court.py')}, а не 2")
    if "гимел_court.py" not in вердиктов:
        беды.append("павший с вердиктом сочтён немым — краснота принята за молчание")
    немые = set(обрывов) - set(вердиктов)
    if немые != {"бет_court.py"}:
        беды.append(f"немыми названы {sorted(немые)}, а не один бет")
    if not В_НАБОРЕ.findall('"courts/бет_court.py" "scripts/alef.py"'):
        беды.append("признак набора не узнаёт пути в кавычках — список выйдет пустым")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ (declarations/PROBE.md).
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"НЕМОЙ ПРИБОР ОТКАЗ: обрыв от вердикта не отличён ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--леджер", default=None)
    ап.add_argument("--набор", default=None)
    дов = ап.parse_args()
    леджер = pathlib.Path(дов.леджер) if дов.леджер else ЛЕДЖЕР
    набор = pathlib.Path(дов.набор) if дов.набор else НАБОР
    if not набор.is_file() or not леджер.is_file():
        нет = набор if not набор.is_file() else леджер
        print(f"НЕМОЙ ПРИБОР ОТКАЗ: нет «{нет}»")
        return 2
    в_наборе = {pathlib.Path(п).name
                for п in В_НАБОРЕ.findall(набор.read_text(encoding="utf-8"))}
    вердиктов, обрывов = разбор(
        леджер.read_text(encoding="utf-8", errors="replace").splitlines())
    немые = sorted(и for и in в_наборе if и in обрывов and и not in вердиктов)
    незнаемые = sorted(и for и in в_наборе if и not in обрывов and и not in вердиктов)
    for и in немые:
        print(f"  НЕМОЙ {и}: обрывов {обрывов[и]}, вердиктов 0 — набор доходил, суда не было")
    for и in незнаемые:
        print(f"  НЕ ГОНЯЛСЯ {и}: в леджере нет ни строки — поставлен после прогона")
    итог = "PASS" if len(немые) <= НЕМЫХ_РУБЕЖ else "FAIL"
    print(f"НЕМОЙ ПРИБОР {итог}: немых {len(немые)} (рубеж {НЕМЫХ_РУБЕЖ}) из "
          f"{len(в_наборе)} приборов набора; с вердиктом "
          f"{sum(1 for и in в_наборе if и in вердиктов)}, не гонялось ни разу "
          f"{len(незнаемые)}; строк леджера с обрывом {sum(обрывов.values())}")
    return 1 if len(немые) > НЕМЫХ_РУБЕЖ else 0


if __name__ == "__main__":
    sys.exit(main())
