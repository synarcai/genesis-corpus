#!/usr/bin/env python3
"""[САЙДКАР РОДОВ] — номер строки свода → «дом · род» той рамки, что её родила.

    РОД, ОБЪЯВЛЕННЫЙ ДОМОМ, ЕСТЬ СУЩНОСТЬ. Но в теле свода он НЕВИДИМ: строка лежит там
    голой, и всякий, кто читает свод, а не дерево, о роде её не узнаёт ничего.

ПОВОД ПРИШЁЛ СНАРУЖИ (13.09, вторая просьба того же соседа). holon-f9 читает свод при варке и
покупает знание РОДАМИ — но род объявлен в дереве, а варится СВОД. Между объявлением и телом
не было моста: указатель родов (`reports/ATLAS-GENERA.json`) знает, какие роды есть у какого
дома, и не знает, какая СТРОКА свода к какому роду принадлежит.

    УКАЗАТЕЛЬ, ЗНАЮЩИЙ ИМЕНА И НЕ ЗНАЮЩИЙ АДРЕСОВ, ПОЛЕЗЕН ТОМУ, КТО ЧИТАЕТ ДЕРЕВО, И
    БЕСПОЛЕЗЕН ТОМУ, КТО ЧИТАЕТ СВОД.

ЧТО ЗДЕСЬ ЕСТЬ. Строка сайдкара — номер строки свода (с единицы) и «дом · род», ДОСЛОВНО теми
же именами, что в `reports/ATLAS-GENERA.json` и в четвёртом столбце `HOLDOUT-KEY-NEXT.tsv`.
Соединение идёт по ТОЧНОМУ ТЕЛУ СТРОКИ: дом узнаёт свою страницу по принадлежности к своему
набору, и сайдкар не гадает по признаку.

ДВА ИСТОЧНИКА РОДА, И ОБА ОБЪЯВЛЕНЫ. Первый — ДОМ: строка стои́т в его словаре показов, и род
её есть закон, который она утверждает. Второй — ПЛАСТ ЯЗЫКА: его кует не дом, а движок пакетов,
но пакет объявляет РОД ПОКАЗА (`show_kinds`: counting, conjugation, definition, case_frames,
arithmetic…), и суд формы умеет узнать, каким шаблоном писана строка.

    ДОМ СИЛЬНЕЕ ПЛАСТА, И РАЗНИЦА ЭТА СКАЗАНА ЧИСЛОМ. Объявление дома говорит о ЗАКОНЕ
    страницы («утверждает итог сложения»), объявление пакета — о ШАБЛОНЕ, которым она писана
    («писана счётным шаблоном немецкого»). Где есть оба, стои́т дом; имена не спутать, ибо дом
    зовётся именем модуля, а пласт — именем мира, и ни один дом не зовётся `lang_*`.

ЧТО ЗДЕСЬ ПОКРЫТО, И ЭТО СКАЗАНО ЧИСЛОМ, А НЕ УМОЛЧАНИЕМ: 64,3 % свода — 178 699 имён от домов
и 17 795 от пластов (те покрывают сто шесть тысяч строк, ибо строка пласта повторяется). Прежде
источник был один, и покрытие было 36 %. Остальное кует кузница напрямую, минуя и дом, и
пакет, и объявления, из которого взять род, у тех строк нет. Число их и имена стоя́т В САМОЙ
ШАПКЕ слепка — `# миров без рода`, `# строк в них`, `# крупнейшие`, — и считаются при всякой
сборке, а не пишутся здесь прозой.

    ГРАНИЦА, НАЗВАННАЯ ЧИСЛОМ И ИМЕНАМИ, ЕСТЬ РАБОТА, КОТОРУЮ МОЖНО ВЗЯТЬ; граница, названная
    словом «остальное», есть работа, о которой забудут. Но ЧИСЛО, СКАЗАННОЕ В ПРОЗЕ, ВЕРНО В
    ДЕНЬ НАПИСАНИЯ; ЧИСЛО, СЧИТАННОЕ ПРИБОРОМ, ВЕРНО ВСЕГДА ИЛИ ПАДАЕТ.

Двадцать кузниц объявляют `ГРУППЫ`, но группа там есть РАЗДАЧА ПО ПРОХОДАМ, а не род страницы,
и звать её родом значило бы назвать родом порядок печати. Дом `holes` объявляет `РОЛИ` — пять
ролей вопроса, и это НАСТОЯЩИЙ род его страниц, — но словаря страниц он не держит, и связать
строку с ролью можно было бы лишь ПРИЗНАКОМ (по вопросному слову), а признак корпус для рода
не берёт: ДОМ, УЗНАЮЩИЙ СТРАНИЦУ ПО ПРИЗНАКУ, А НЕ ПО НАБОРУ, ЗОВЁТ СВОЕЙ ЧУЖУЮ РЕЧЬ. Работа
эта — дать таким домам словарь страниц, и она названа, а не сделана.

    ДОЛЯ, СКАЗАННАЯ ЧИСЛОМ, ЕСТЬ ГРАНИЦА ЗНАНИЯ; ДОЛЯ, НЕ СКАЗАННАЯ ВОВСЕ, ЕСТЬ ОБЕЩАНИЕ
    ПОЛНОТЫ, КОТОРОГО НИКТО НЕ ДАВАЛ.

ПОЧЕМУ САЙДКАР НЕСЁТ ПОДПИСЬ СВОДА. Номер строки верен ровно для того свода, по которому он
снят: пересоберут свод — и всякий номер уедет, а файл будет выглядеть исправным.

    СЛЕПОК, СНЯТЫЙ ПО НОМЕРУ СТРОКИ, ЕСТЬ СЛЕПОК ОДНОГО ФАЙЛА, А НЕ ОДНОГО КОРПУСА. Он
    обязан нести подпись того файла и падать, когда она разошлась, — иначе он лжёт молча,
    и ложь его тем убедительнее, что все номера на месте.

Оттого прибор без доводов СВЕРЯЕТ сайдкар со сводом и падает при расхождении подписи;
`--собрать` пересобирает его заново.

    python3 scripts/genera_sidecar.py [--собрать] [--свод datasets/GENESIS-FULL.txt]
"""
