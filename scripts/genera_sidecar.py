def карта(двор):
    """{тело строки: «дом · род»} — по объявлениям домов, тем же правилом, что у указателя."""
    вон, двойных = {}, []
    for п in sorted(pathlib.Path(двор).glob("*.py")):
        if п.stem.startswith("gen_"):
            continue                       # КУЗНИЦА НЕ ЕСТЬ ДОМ
        try:
            м = importlib.import_module(п.stem)
        except Exception:                  # noqa: BLE001
            continue
        роды = getattr(м, "РОДЫ", None) or getattr(м, "ФОРМЫ", None)
        показы = getattr(м, "ПОКАЗЫ", None)
        if not роды or not isinstance(показы, dict):
            continue
        место = getattr(м, "РОД_В_ПОКАЗЕ", 1)
        for стр, знач in показы.items():
            род = знач[место] if isinstance(знач, tuple) and len(знач) > место else знач
            if not isinstance(род, str):
                continue
            ключ, имя = стр.strip(), f"{п.stem} · {род}"
            if ключ in вон and вон[ключ] != имя:
                двойных.append((ключ[:60], вон[ключ], имя))
            вон[ключ] = имя
    return вон, двойных


def роды_пластов(корень):
    """{тело строки: «lang_<код> · <род показа>»} — по объявлению `show_kinds` пакетов.

    ВТОРОЙ ИСТОЧНИК РОДА, И ОН ТОЖЕ ОБЪЯВЛЕН, А НЕ УГАДАН. Языковые пласты кует не дом, а
    движок пакетов, и рода у их строк не было НИГДЕ — 106 737 строк, четверть свода, лежали
    без имени. Но пакет объявляет РОД ПОКАЗА (`show_kinds`: counting, conjugation, definition,
    case_frames, arithmetic…), и суд формы (`courts/langform_court.py`) уже умеет узнавать,
    каким шаблоном писана строка. Сайдкар зовёт ЕГО, а не пишет второго узнавателя.

        ДВА УЗНАВАТЕЛЯ ОДНОГО ПРЕДМЕТА РАСХОДЯТСЯ НА ПЕРВОЙ ЖЕ ПРАВКЕ ПАКЕТА. Мера, которой
        нужен чужой разбор, ЗОВЁТ ЕГО — и стареет вместе с ним, а не отдельно.

    ИМЯ ЗДЕСЬ — ИМЯ МИРА, А НЕ ДОМА («lang_de · counting»), и спутать их нельзя: дом зовётся
    именем модуля, мир — именем мира, и ни один дом не зовётся `lang_*`. Читатель, которому
    нужен только дом, отличит их одним взглядом.
    """
    import langform_court as L                             # noqa: PLC0415
    вон, павшие = {}, []
    двор_пакетов = корень / "tools" / "langpacks"
    for путь in sorted(двор_пакетов.glob("*.json")):
        код = путь.stem
        слой = корень / "datasets" / f"genesis_lang_{код}.txt"
        if not слой.is_file():
            continue
        try:
            пакет = json.loads(путь.read_text(encoding="utf-8"))
            образцы = L.образцы(пакет, L.таблицы(пакет))
        except Exception as почему:                        # noqa: BLE001
            # ПРОПУСК, О КОТОРОМ НЕ СКАЗАНО, ЕСТЬ ЛОЖЬ О ПОЛНОТЕ. Первая редакция глотала
            # ошибку ввоза и отдавала пустой ряд: покрытие пласта было ноль, и число это
            # выглядело честным ответом о пласте, а было ответом о сломанном ввозе.
            павшие.append(f"{код}: {type(почему).__name__} {почему}")
            continue
        мир = f"lang_{код}"
        for л in слой.read_text(encoding="utf-8", errors="replace").split("\n"):
            с = л.strip()
            if not с or с in вон:
                continue
            for о in образцы:
                проба = getattr(о, "точный", None)
                if проба is not None and hasattr(проба, "search") and проба.search(с):
                    вон[с] = f"{мир} · {о.род}"
                    break
    if павшие:
        print(f"  ПАКЕТ НЕ РАЗОБРАН ({len(павшие)}): {', '.join(павшие[:5])}")
    return вон


def без_рода(свод, отмечено):
    """[(мир, строк)] — миры, у которых родом не отмечена НИ ОДНА строка, от больших к малым.

    ГРАНИЦА, НАЗВАННАЯ ЧИСЛОМ И ИМЕНАМИ, ЕСТЬ РАБОТА, КОТОРУЮ МОЖНО ВЗЯТЬ; граница, названная
    словом «остальное», есть работа, о которой забудут. Но число, вписанное в прозу, СТАРЕЕТ
    МОЛЧА, — оттого оно считается здесь при всякой сборке и ложится в шапку самого слепка.

        ЧИСЛО, СКАЗАННОЕ В ПРОЗЕ, ВЕРНО В ДЕНЬ НАПИСАНИЯ; ЧИСЛО, СЧИТАННОЕ ПРИБОРОМ, ВЕРНО
        ВСЕГДА ИЛИ ПАДАЕТ.
    """
    import genesis                                        # noqa: PLC0415
    строки = свод.read_text(encoding="utf-8", errors="replace").split("\n")
    вон, позиция = [], 0
    for м in genesis.manifest()["worlds"]:
        if м.get("text") != "shows":
            continue
        путь = КОРЕНЬ / м["file"]
        if not путь.is_file():
            continue
        свои = [л for л in путь.read_text(encoding="utf-8", errors="replace").split("\n")
                if л.strip()]
        if not свои:
            continue
        try:
            нач = строки.index(свои[0], позиция)
        except ValueError:
            continue
        есть = any((i + 1) in отмечено for i in range(нач, нач + len(свои)))
        позиция = нач + len(свои)
        if not есть:
            вон.append((м["name"], len(свои)))
    вон.sort(key=lambda т: -т[1])
    return вон


def работа_без_рода(немые, двор):
    """(миров с домом, строк в них, миров без дома, строк в них) — ДВА РОДА ОСТАВШЕЙСЯ РАБОТЫ.

        РАБОТА, ДО КОТОРОЙ ОДИН ПЕРЕЕЗД ПЕРЕБОРА, И РАБОТА, ДЛЯ КОТОРОЙ НАДО ПОСТРОИТЬ ДОМ, —
        РАЗНЫЕ РАБОТЫ, И СЛОЖЕННЫЕ В ОДНО ЧИСЛО ОНИ ОБЕ ВЫГЛЯДЯТ НЕПОДЪЁМНЫМИ.

    Мир, кормимый домом, который объявил роды и не держит словаря страниц, ждёт одного: чтобы
    перебор переехал из кузницы в дом (так сегодня сделан `holes` — мир вышел байт в байт
    прежним, а свод получил 6 640 адресов). Мир, у которого дома нет вовсе, ждёт дома.
    """
    import genus_atlas                                   # noqa: PLC0415
    кормление = genus_atlas.кормит(двор)
    объявили = set()
    for имя, миры in кормление.items():
        try:
            м = importlib.import_module(имя)
        except Exception:                                # noqa: BLE001
            continue
        # ПРАВИЛО ДОПУСКА БЕРЁТСЯ У УКАЗАТЕЛЯ, А НЕ ПИШЕТСЯ ЗДЕСЬ ВТОРОЙ РАЗ (13.09). Первая
        # редакция спрашивала просто «есть ли `РОДЫ` или `ФОРМЫ`» — и засчитала домами
        # `parity` и `coprime`, у которых `ФОРМЫ` есть словарь рамок с языками в ключах.
        # Семья `inquiry` вышла «ждущей переезда», а она ждёт ДОМА: кузница её в пятьсот
        # сорок три строки не опирается ни на один дом с родами.
        #
        #     ДВЕ МЕРЫ, СУДЯЩИЕ ОБ ОДНОМ ПО РАЗНЫМ ПРАВИЛАМ, ДАЮТ ДВА ЧИСЛА, И ОБА БУДУТ
        #     НАЗВАНЫ ПРАВДОЙ. Правило допуска у корпуса одно, и живёт оно в указателе.
        разбор = genus_atlas.разобрать(имя, м)
        if разбор and разбор[0]:
            объявили.update(миры)
    с_домом = [(и, n) for и, n in немые if и in объявили]
    без_дома = [(и, n) for и, n in немые if и not in объявили]
    return с_домом, без_дома


def собрать(свод, двор):
    """(тело сайдкара, строк, покрыто, двойных)."""
    имена, двойных = карта(двор)
    домом = len(имена)
    # ДОМ СИЛЬНЕЕ ПЛАСТА: объявление дома точнее, ибо говорит о ЗАКОНЕ страницы, а объявление
    # пакета — о ШАБЛОНЕ, которым она писана. Где есть оба, берётся дом.
    for тело, имя in роды_пластов(КОРЕНЬ).items():
        имена.setdefault(тело, имя)
    пластом = len(имена) - домом
    строки = свод.read_text(encoding="utf-8", errors="replace").split("\n")
    подпись = hashlib.sha256(свод.read_bytes()).hexdigest()
    вон, всего, покрыто = [], 0, 0
    for i, л in enumerate(строки, 1):
        с = л.strip()
        if not с:
            continue
        всего += 1
        имя = имена.get(с)
        if имя:
            покрыто += 1
            вон.append(f"{i}\t{имя}")
    доля = 100 * покрыто / max(1, всего)
    немые = без_рода(свод, {int(с.split("\t")[0]) for с in вон})
    с_домом, без_дома = работа_без_рода(немые, двор)
    # ДВА ЧИСЛА СТРОК, И ОБА НАЗВАНЫ. Номер в первом столбце считает строки файла КАК ОН
    # ЕСТЬ — с единицы, включая пустые (их 9 890, они делят миры). Доля же считается от
    # НЕПУСТЫХ, ибо пустая строка не есть страница и рода иметь не может.
    #
    #     ДВА РАЗНЫХ СЧЁТА СТРОК, НАЗВАННЫЕ ОДНИМ СЛОВОМ «СТРОК», СУТЬ ОДНА ЛОЖЬ: читатель
    #     возьмёт то из них, что ближе, и уедет на десять тысяч.
    голова = [f"# свод\t{свод.name}", f"# sha256\t{подпись}",
              f"# строк в файле\t{len(строки)}", f"# строк непустых\t{всего}",
              f"# покрыто\t{покрыто}", f"# доля от непустых\t{доля:.1f}",
              f"# имён от домов\t{домом}", f"# имён от пластов\t{пластом}",
              f"# миров без рода\t{len(немые)}",
              f"# строк в них\t{sum(n for _и, n in немые)}",
              f"# из них с домом, объявившим роды\t{len(с_домом)} миров, "
              f"{sum(n for _и, n in с_домом)} строк — ждут переезда перебора в дом",
              f"# из них без дома вовсе\t{len(без_дома)} миров, "
              f"{sum(n for _и, n in без_дома)} строк — ждут дома",
              "# крупнейшие с домом\t" + ", ".join(f"{и} {n}" for и, n in с_домом[:6]),
              "# крупнейшие без дома\t" + ", ".join(f"{и} {n}" for и, n in без_дома[:6]),
              "# столбцы\tномер строки файла (с единицы, пустые считаются)\tдом · род",
              "# имена дословно те же, что в reports/ATLAS-GENERA.json"]
    return "\n".join(голова + вон) + "\n", всего, покрыто, двойных, домом, пластом


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что соединение ИДЁТ и что оно ТОЧНОЕ.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ ПУСТОТЫ: пусть соединение сломается — и сайдкар выйдет
        пустым, а «строк 440 000, покрыто 0» будет чистой правдой о ничём.
    """
    беды = []
    имена = {"вот кот.": "домкот · кот", "вот два кота.": "домкот · коты"}
    строки = ["вот кот.", "чужая строка.", "вот два кота."]
    нашлось = [(i, имена[с]) for i, с in enumerate(строки, 1) if с in имена]
    if нашлось != [(1, "домкот · кот"), (3, "домкот · коты")]:
        беды.append(f"соединение по телу строки дало {нашлось}")
    if "вот кот" in имена:
        беды.append("соединение идёт по ЧАСТИ строки, а должно по целой")
    return беды


def main():
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"САЙДКАР РОДОВ ОТКАЗ: соединение не доказано ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--свод", default=None)
    ап.add_argument("--двор", default=None)
    ап.add_argument("--собрать", action="store_true")
    дов = ап.parse_args()
    свод = pathlib.Path(дов.свод) if дов.свод else СВОД
    двор = pathlib.Path(дов.двор) if дов.двор else КОРЕНЬ / "tools"
    if not свод.is_file():
        print(f"САЙДКАР РОДОВ ОТКАЗ: свода нет — {свод}")
        return 2
    тело, всего, покрыто, двойных, домом, пластом = собрать(свод, двор)
    доля = 100 * покрыто / max(1, всего)
    for к, а, б in двойных[:3]:
        print(f"  ОДНА СТРОКА У ДВУХ ДОМОВ: «{к}» — {а} и {б}")
    if дов.собрать:
        куда = цель(свод)
        куда.write_text(тело, encoding="utf-8")
        print(f"САЙДКАР РОДОВ СОБРАН: {куда}, строк свода {всего}, покрыто {покрыто} "
              f"({доля:.1f} %; имён от домов {домом}, от пластов {пластом}), "
              f"двойных {len(двойных)}")
        return 0
    куда = цель(свод)
    было = куда.read_text(encoding="utf-8") if куда.is_file() else ""
    сошлось = было == тело
    хватает = доля >= ПОКРЫТО_РУБЕЖ
    if not сошлось:
        причина = ("сайдкара нет вовсе" if not было
                   else "подпись свода разошлась" if "# sha256" in было
                   and было.split("\n")[1] != тело.split("\n")[1]
                   else "состав разошёлся с деревом")
        print(f"  сайдкар разошёлся со сводом: {причина}")
    if not хватает:
        print(f"  покрыто {доля:.1f} % — ниже рубежа {ПОКРЫТО_РУБЕЖ} %")
    поза = "PASS" if сошлось and хватает and not двойных else "FAIL"
    print(f"САЙДКАР РОДОВ {поза}: строк свода {всего}, покрыто {покрыто} ({доля:.1f} %, "
          f"рубеж {ПОКРЫТО_РУБЕЖ} %; имён от домов {домом}, от пластов {пластом}), "
          f"двойных {len(двойных)} (рубеж 0)")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
