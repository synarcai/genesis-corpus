#!/usr/bin/env python3
"""[ПОВТОР] — сколько строк свода есть ТОЧНАЯ копия другой строки того же мира.

Вопрос владельца стоит давно: насколько минимальным может быть корпус. Ответ
на него искали срезом по родам (`scripts/minimal_build.py`) — и не искали там,
где он лежал открыто: СРЕДИ ОДИНАКОВЫХ СТРОК.

Слой пишет мир пассами, и пасс обязан ВАРЬИРОВАТЬ свои случаи. Мир, чей
объявленный набор конечен (пакет языка, таблица форм), варьировать нечего:
пять пассов пишут одно и то же пять раз, и мир из четырёхсот различных строк
весит шесть тысяч. Мир, чья формула пасса сталкивается сама с собой, платит
тем же. Ни один прибор корпуса этого не мерил, и потому цена не была названа.

Прибор считает по каждому миру показов: строк, различных строк, повторов и
их долю; и по своду — то же самое. Строка, встреченная дважды В РАЗНЫХ
мирах, считается отдельно: это не повтор пасса, а пересечение миров, и оно
законно (два мира вправе показать один факт), но знать его число полезно.

ЧЕГО ПРИБОР НЕ УТВЕРЖДАЕТ, И ПОПРАВКА К ПЕРВОМУ ЗАМЕРУ (04.09, тот же день).
Первая редакция сказала: «столько-то процентов веса не несёт ни одной новой
строки». Это верно БУКВАЛЬНО и неверно ПО СМЫСЛУ, и поправка стоит числа:
новой СТРОКИ повтор не несёт, а МАССУ РОДА несёт — и масса есть то, чем
закон покупается (М-148, LAW² = 9 показов на род). Померено:

    мир            родов   мало С повторами   мало БЕЗ повторов
    lang_de          282          82                 270
    lang_sw          168          12                 163
    school_biling    181          33                 120
    compare_mult     357         152                 313

То есть дедупликация роняет ниже LAW² почти все роды этих миров. Свод без
повторов (`scripts/uniq_build.py`) — не бесплатная экономия, а ПРОБА: если
меры организма на нём совпадут с мерами на полном своде, значит масса
одинаковыми строками не покупается, и тогда лекарство иное и дороже —
РАСТИТЬ набор, а не резать повторы. Прибор считает и то и другое; решает
варка, а не он.

    python3 scripts/repeats.py [--out reports/REPEATS.tsv]
"""
import argparse
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import worlds  # noqa: E402


def мир_имя(путь):
    return путь.stem[len("genesis_"):] if путь.stem.startswith("genesis_") else путь.stem


def масса_родов(строки):
    """(родов, родов с массой < LAW²) — по строкам как они есть."""
    import form_census as C
    масса = collections.Counter(C.род(C.скелет(с)) for с in строки)
    return len(масса), sum(1 for n in масса.values() if n < C.LAW2)


def перепись():
    ряды, где = [], collections.defaultdict(set)
    for путь in worlds(kind="shows"):
        имя = мир_имя(путь)
        строки = [с.strip() for с in путь.read_text(encoding="utf-8", errors="replace").splitlines()
                  if с.strip() and not с.startswith("\x0c")]
        if not строки:
            continue
        for с in строки:
            где[с].add(имя)
        разные = list(dict.fromkeys(строки))
        родов, мало_с = масса_родов(строки)
        _, мало_без = масса_родов(разные)
        ряды.append((имя, len(строки), len(разные), родов, мало_с, мало_без))
    межмировых = sum(1 for м in где.values() if len(м) > 1)
    return ряды, межмировых


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--out", type=pathlib.Path)
    а = ап.parse_args()
    ряды, межмировых = перепись()
    всего = sum(n for _, n, *_ in ряды)
    разных = sum(d for _, _, d, *_ in ряды)
    строки = ["мир\tстрок\tразличных\tповторов\tдоля повторов\tродов\tмало с повторами\tмало без повторов"]
    for имя, n, d, родов, мс, мб in sorted(ряды, key=lambda р: -(р[1] - р[2])):
        строки.append(f"{имя}\t{n}\t{d}\t{n - d}\t{(n - d) / n:.2f}\t{родов}\t{мс}\t{мб}")
    текст = "\n".join(строки) + "\n"
    if а.out:
        а.out.write_text(текст, encoding="utf-8")
    else:
        sys.stdout.write(текст)
    чистых = sum(1 for _, n, d, *_ in ряды if n == d)
    print(f"ПОВТОР: показов {всего}, различных {разных}, повторов {всего - разных} "
          f"({100 * (всего - разных) // max(1, всего)} % веса свода); миров без единого повтора "
          f"{чистых} из {len(ряды)}; строк, живущих более чем в одном мире, {межмировых}", file=sys.stderr)
    мало_с = sum(мс for *_, мс, _ in ряды)
    мало_без = sum(мб for *_, мб in ряды)
    print(f"  МАССА: родов с массой < LAW² — с повторами {мало_с}, БЕЗ повторов {мало_без}; "
          f"то есть дедупликация роняет ниже закона ещё {мало_без - мало_с} родов "
          f"(повтор не несёт новой строки, но несёт массу рода)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
