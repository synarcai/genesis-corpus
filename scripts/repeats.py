#!/usr/bin/env python3
"""[ПОВТОР] — сколько строк свода есть ТОЧНАЯ копия другой строки того же мира.

Вопрос владельца стоит давно: насколько минимальным может быть корпус. Ответ
на него искали срезом по родам (`scripts/minimal_build.py`) — и не искали там,
где он лежал открыто: СРЕДИ ОДИНАКОВЫХ СТРОК.

Слой пишет мир пассами, и пасс обязан ВАРЬИРОВАТЬ свои случаи. Мир, чей
объявленный набор конечен (пакет языка, таблица форм), варьировать нечего:
пять пассов пишут одно и то же пять раз, и мир из четырёхсот различных строк
весит шесть тысяч. Мир, чья формула пасса сталкивается сама с собой, платит
тем же. Ни один прибор корпуса этого не мерил, и потому цена не была названа.

Прибор считает по каждому миру показов: строк, различных строк, повторов и
их долю; и по своду — то же самое. Строка, встреченная дважды В РАЗНЫХ
мирах, считается отдельно: это не повтор пасса, а пересечение миров, и оно
законно (два мира вправе показать один факт), но знать его число полезно.

ЧЕГО ПРИБОР НЕ УТВЕРЖДАЕТ. Он НЕ говорит, что повтор есть изъян: масса рода
куплена законом М-148, и повтор её держит. Он говорит цену: столько-то
процентов веса свода не несёт ни одной новой строки, и всякая варка платит
за них временем. Лекарство там, где набор КОНЕЧЕН: резать его по пассам, а
не повторять (так написаны миры разговора — у них повторов ноль).

    python3 scripts/repeats.py [--out reports/REPEATS.tsv]
"""
import argparse
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import worlds  # noqa: E402


def мир_имя(путь):
    return путь.stem[len("genesis_"):] if путь.stem.startswith("genesis_") else путь.stem


def перепись():
    ряды, где = [], collections.defaultdict(set)
    for путь in worlds(kind="shows"):
        имя = мир_имя(путь)
        строки = [с.strip() for с in путь.read_text(encoding="utf-8", errors="replace").splitlines()
                  if с.strip() and not с.startswith("\x0c")]
        if not строки:
            continue
        for с in строки:
            где[с].add(имя)
        ряды.append((имя, len(строки), len(set(строки))))
    межмировых = sum(1 for м in где.values() if len(м) > 1)
    return ряды, межмировых


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--out", type=pathlib.Path)
    а = ап.parse_args()
    ряды, межмировых = перепись()
    всего = sum(n for _, n, _ in ряды)
    разных = sum(d for _, _, d in ряды)
    строки = ["мир\tстрок\tразличных\tповторов\tдоля повторов"]
    for имя, n, d in sorted(ряды, key=lambda р: -(р[1] - р[2])):
        строки.append(f"{имя}\t{n}\t{d}\t{n - d}\t{(n - d) / n:.2f}")
    текст = "\n".join(строки) + "\n"
    if а.out:
        а.out.write_text(текст, encoding="utf-8")
    else:
        sys.stdout.write(текст)
    чистых = sum(1 for _, n, d in ряды if n == d)
    print(f"ПОВТОР: показов {всего}, различных {разных}, повторов {всего - разных} "
          f"({100 * (всего - разных) // max(1, всего)} % веса свода); миров без единого повтора "
          f"{чистых} из {len(ряды)}; строк, живущих более чем в одном мире, {межмировых}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
