_КАНА_И_ХАНЬ = ("\u3040", "\u9fff")
_ТАЙСКОЕ = ("\u0e00", "\u0e7f")


def без_пробельного_письма(слово):
    """Несёт ли слово знак письма, где пробел слов не разделяет."""
    return any(_КАНА_И_ХАНЬ[0] <= з <= _КАНА_И_ХАНЬ[1]
               or _ТАЙСКОЕ[0] <= з <= _ТАЙСКОЕ[1] for з in слово)



# СЛОВО, НАЗВАННОЕ ЧТОБЫ БЫТЬ ОТВЕРГНУТЫМ, ЗАКОНУ ПОВТОРЕНИЯ НЕ ПОДЛЕЖИТ (09.09).
#
# Тринадцать одиночек мира `genderverb` суть ЗАВЕДОМО НЕВЕРНЫЕ формы, показанные ради
# опровержения: «верно ли, что вёз + а = вёза? нет: везла.» Слово «вёза» русским языком не
# существует, и требовать от него ВТОРОГО показа значит требовать, чтобы небылицу повторили.
#
#     ЗАКОН ПОВТОРЕНИЯ ЕСТЬ ЗАКОН О ТОМ, ЧЕМУ УЧАТ. Отвергнутое не есть то, чему учат: его
#     называют ОДИН РАЗ И ТУТ ЖЕ ОТРИЦАЮТ, и второй показ учил бы ему, а не против него.
#
# ПРИЗНАК ЧИТАЕТСЯ ИЗ ОБЪЯВЛЕНИЯ, А НЕ УГАДЫВАЕТСЯ: слово отрицания берётся у пакетов
# (`polarity.no` — «нет», «no», «nein», «non», …), и отвергнутым считается слово, стоящее в
# строке ДО этого слова, когда оно открывает ответ («… ? нет: …»). Строка без отрицания под
# признак не идёт вовсе, и мера остаётся мерой корпуса, а не догадкой о жанре.
def _слова_отрицания():
    """Слова «нет» девяти языков — из объявлений пакетов, а не из головы."""
    вон = set()
    try:
        for путь in sorted((КОРЕНЬ / "tools" / "langpacks").glob("*.json")):
            пакет = json.loads(путь.read_text(encoding="utf-8"))
            for с in ((пакет.get("polarity") or {}).get("no") or ()):
                вон.add(str(с).lower())
    except (OSError, ValueError):
        pass
    return frozenset(вон)


СЛОВА_ОТРИЦАНИЯ = _слова_отрицания()


def отвергнутое(строка):
    """Слова строки, названные ДО отрицания, открывающего ответ, — они отвергнуты ею же."""
    низ = строка.lower()
    for нет in СЛОВА_ОТРИЦАНИЯ:
        место = низ.find(f"? {нет}:")
        if место >= 0:
            return {w.lower() for w in СЛОВО.findall(низ[:место])}
    return set()


