#!/usr/bin/env python3
"""[СЛОВО ОДНАЖДЫ] — LAW = 2 на словах СВОДА, а не одного пакета.

    СЛОВО, ПОКАЗАННОЕ ОДИН РАЗ, ЕСТЬ СЛОВО НЕПОКАЗАННОЕ: читателю не с чем его сличить.
    LAW = 2 есть закон повторения, и корпус носит его в своём основании.

ЗАКОН БЫЛ, А МЕРЫ У НЕГО НЕ БЫЛО. Движок пакетов стережёт его строго — `LANGPACK-ONCE`
роняет пласт, если хоть одно объявленное слово живёт в нём меньше двух раз, — но стережёт
ВНУТРИ ПАКЕТА. Прочие двести десять миров корпуса пишут слова, которых не объявлял никакой
пакет: имена вещей домов, глаголы историй, слова ответов, — и о них не спрашивал никто.

    ЗАКОН, СТЕРЕЖОМЫЙ В ОДНОМ ДОМЕ И НЕ СТЕРЕЖОМЫЙ В КОРПУСЕ, ЕСТЬ ЗАКОН ЭТОГО ДОМА,
    А НЕ КОРПУСА.

ПЕРВЫЙ ЗАМЕР (08.09): 616 слов из 21 356 живут во всём своде РОВНО РАЗ. Долг собран не
ровно: девять миров держат две трети его — dialogue 113, roles 97, behavior 73,
chains_langs 65, indu 51, nature 49, reply 36, countfacts 31, opinion 28.

    «woraus ist ein Pullover gemacht? aus Wolle.» — «Wolle» и «Pullover» стоя́т в своде по
    одному разу каждое. Дом показывает вещь и её вещество ОДНОЙ парой, и обе половины пары
    остаются словами, которых не с чем сличить.

ГРАНИЦА ОБЪЯВЛЕНА ДВАЖДЫ И ОБЕ РАЗА ЧИТАЕТСЯ ИЗ МАНИФЕСТА, А НЕ УГАДЫВАЕТСЯ:

    · мир, чьё письмо БЕЗ ПРОБЕЛОВ (`segmentation: longest-match` — китайский, японский,
      тайский), не меряется вовсе: «слово», найденное разрывом по пробелу, там не слово,
      и счёт по нему был бы счётом о разметке, а не о языке;
    · меряются лишь миры показов (`text: shows`): проза и таблицы живут иным законом.

СЧЁТ ИДЁТ ПО ВСЕМУ СВОДУ, А НЕ ПО МИРУ. Слово, стоящее однажды в одном мире и однажды в
другом, ЗАКОН ИСПОЛНЯЕТ: читатель сличает их между собою. Оттого долг мира есть число слов,
чей ЕДИНСТВЕННЫЙ показ пришёлся на него, — и мир, повторивший чужое слово, гасит чужой долг.

    python3 scripts/word_once.py [--подробно] [--мир ИМЯ]
"""
# ПУСТОЙ-ОБХОД: --мир no-such-world
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"

# РУБЕЖ-ДОЛГА: ОДНАЖДЫ_РУБЕЖ = 346
#
# ЧИСЛО ПЕРВОГО ЗАМЕРА, И ОНО ЕСТЬ ДОЛГ, А НЕ ПОЗВОЛЕНИЕ. Названо ПОСЛЕ замера, а не до:
# долг, названный до, есть догадка. Расти ему нельзя, убывать можно, и всякое слово, ПОВТОРЁННОЕ
# вторым показом, опускает его на единицу.
#
# ПОЧЕМУ НЕ НОЛЬ СРАЗУ. Закрыть его — значит дописать корпусу шестьсот десять показов, и каждый
# должен быть ИСТИНЕН, а не просто повторён: «Wolle» требует второй вещи из шерсти, а не второй
# строки о свитере. Это работа домов, а не правка числа.
#
# ЧТО ЭТОТ ДОЛГ СТОИТ СОСЕДУ. Прибор подсадки словом (`word_mutants`) ловит порчу словарём;
# слово, живущее однажды, есть ровно то слово, ради которого словарный закон стоил бы честных
# строк («цена прыгает с нуля до 52», замер 06.09). Шестьсот слов суть цена, которую заплатил
# бы корпус за словарный суд, — и она падает вместе с этим долгом.
#
# 610 → 616 В ТОТ ЖЕ ЧАС, И ЭТО ЗАКОН, А НЕ НЕУДАЧА. Прибор родился, назвал долг мира ролей
# (97 слов), и первая же попытка платить его показала, чем этот долг ОТЛИЧАЕТСЯ ОТ ПРОЧИХ:
#
#     ДОЛГ ЗАКОНА ПОВТОРЕНИЯ НЕ ЗАКРЫВАЕТСЯ ДОПИСЫВАНИЕМ. Всякий НОВЫЙ показ приносит НОВЫЕ
#     слова, и каждое из них приходит ОДНАЖДЫ. Шестое вещество («книга из бумаги») дало
#     второй показ пяти причастиям — и привело шесть новых имён вещества, по одному на язык.
#
# ОТКУДА ЖЕ ОН ПАДАЕТ. Не от новых показов, а от показов, ПОВТОРЯЮЩИХ СТАРЫЕ СЛОВА В НОВОЙ
# РОЛИ: страница, где факт СКАЗАН и тут же СПРОШЕН, показывает каждое своё слово дважды и в
# двух местах речи, не вводя ни одного нового. Заказ следующей руке назван этим и есть:
# дом диалога (113), дом поведения (73), дом цепей (65) пишут только вопрос — и каждое их
# содержательное слово живёт один раз.
#
# 616 → 513 В ТОТ ЖЕ ЧАС, И ЗАМЫСЕЛ ПОДТВЕРЖДЁН ДЕЛОМ. Дом ролей получил утвердительную
# половину — «пишут ручкой. чем пишут? ручкой.», — и ушёл из списка ЦЕЛИКОМ: девяносто восемь
# слов стали показаны дважды, ни одного нового слова не введено, число показов не выросло
# (144 и 144), вырос лишь их вес.
#
#     ОДИН ПОКАЗ, ГОВОРЯЩИЙ ФАКТ И СПРАШИВАЮЩИЙ ЕГО, СТОИТ ДВУХ ПОКАЗОВ И НЕ ПЛАТИТ ЗА ВТОРОЙ
#     НИ ОДНИМ НОВЫМ СЛОВОМ.
#
# И ЭТО ЖЕ ЕСТЬ ЗАКАЗ: тот же ход открыт дому диалога, дому поведения, дому цепей и дому
# природы. Ход стоит одной утвердительной рамки на язык и на тип, и порядок слов в ней есть
# ЗАКОН ЯЗЫКА, а не рамка дома: французская инверсия разворачивается обратно, португальская
# и польская клитики становятся при глаголе, немецкий и нидерландский держат V2 сами собою.
# 448 → 417 (09.09, вечер): ТРИДЦАТЬ ОДНА ОДИНОЧКА ЗАКРЫТА ВТОРОЙ ПОВЕРХНОСТЬЮ, А НЕ ВТОРОЙ
# ВЕЩЬЮ. Дом счётных фактов показывал каждую вещь ОДНОЙ страницей, и зелёный, синий, чёрный,
# красный жили в своде ровно раз на язык. Белый и жёлтый долга не давали — их по две вещи, — и
# это же указало лекарство: противопоставление двух вещей разных цветов в одной строке
# («снег белый, а уголь чёрный»), 72 страницы на девяти языках.
# 417 → 389: ТОТ ЖЕ РЕЦЕПТ, ДРУГОЙ ДОМ. Дом мнения показывал факт и мнение ВРОЗЬ, каждой
# страницей своей, и двадцать восемь его оценочных слов (belle, bello, buena, gemütlich,
# gezellig, interesting) жили в своде ровно раз. Пара ставит их рядом при одном вопросе —
# «что тут факт, а что мнение?» — и различие видно НЕ ИЗ ОТВЕТА, А ИЗ САМОГО ПОЛОЖЕНИЯ.
# Дом ушёл из списка одиночек целиком.
# 389 → 346: ТРЕТИЙ ДОМ ТЕМ ЖЕ РЕЦЕПТОМ, И ОБЕ ЕГО СЕМЬИ ОДИНОЧЕК РАЗНЫЕ. Дом природы держал
# сорок девять слов: МНОЖЕСТВЕННОЕ ЦЕЛОГО стояло только в парном показе («две паучихи»),
# ЕДИНСТВЕННОЕ ЧАСТИ — только в показе части («нога — часть паука»). Обратный ход гасит первую
# («у двух пауков 16 ног. сколько ног у паука? 8 ног: 16 ÷ 2 = 8») и учит ОБРАТИМОСТИ: умножение
# дом показывал, деления не показывал ни разу, хотя это то же отношение с другой стороны.
# Вопрос к части гасит вторую и даёт вопросную поверхность роду, у которого её не было.
#
#     ВТОРАЯ ПОВЕРХНОСТЬ ЕСТЬ НЕ ПОВТОР, А ДРУГАЯ СТОРОНА ТОГО ЖЕ ОТНОШЕНИЯ.
ОДНАЖДЫ_РУБЕЖ = 346

СЛОВО = re.compile(r"[^\W\d_]+", re.UNICODE)
БЕЗ_ПРОБЕЛОВ = "longest-match"

# ПИСЬМО БЕЗ ПРОБЕЛОВ ИСКЛЮЧАЕТСЯ ПО СЛОВУ, А НЕ ПО МИРУ (09.09).
#
# Граница объявлена была верно и читалась из манифеста: мир с `segmentation: longest-match`
# не меряется вовсе. Но МНОГОЯЗЫЧНЫЙ мир сегментации НЕ ОБЪЯВЛЯЕТ НИКАКОЙ — ни `chains_langs`,
# ни `dialogue`, ни `nature`, — и его китайские строки проходили меру целыми: «十六乘二等于三十二»
# есть ОДНО «слово» по разрыву пробелом, то есть целое уравнение, и оно, разумеется, живёт в
# своде однажды. Шестьдесят пять одиночек из пятисот тринадцати были такими, и все в одном мире.
#
#     ГРАНИЦА, ЧИТАЕМАЯ ПО ОБЪЯВЛЕНИЮ МИРА, НЕ ДЕРЖИТ МИРА, КОТОРЫЙ НИЧЕГО НЕ ОБЪЯВЛЯЕТ.
#     Признак взят у САМОГО СЛОВА: знак письма виден в нём, а не в манифесте.
#
# Ряды названы кодами, а не «иероглифами»: кана и китайское письмо U+3040–U+9FFF, тайское
# U+0E00–U+0E7F. Замер: 513 → 448, и убыль есть НЕ ПОГАШЕННЫЙ ДОЛГ, а слова, которых не было.
_КАНА_И_ХАНЬ = ("\u3040", "\u9fff")
_ТАЙСКОЕ = ("\u0e00", "\u0e7f")


def без_пробельного_письма(слово):
    """Несёт ли слово знак письма, где пробел слов не разделяет."""
    return any(_КАНА_И_ХАНЬ[0] <= з <= _КАНА_И_ХАНЬ[1]
               or _ТАЙСКОЕ[0] <= з <= _ТАЙСКОЕ[1] for з in слово)


def миры():
    try:
        м = json.loads(МАНИФЕСТ.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    ряд = м["worlds"] if isinstance(м, dict) and "worlds" in м else м
    return [w for w in ряд
            if w.get("text") == "shows" and w.get("segmentation") != БЕЗ_ПРОБЕЛОВ]


def перепись(ряд):
    """(счёт слова, мир первого показа, строка первого показа)."""
    счёт = collections.Counter()
    откуда, строка = {}, {}
    for w in ряд:
        путь = КОРЕНЬ / w["file"]
        if not путь.is_file():
            continue
        for с in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            for слово in СЛОВО.findall(с):
                if без_пробельного_письма(слово):
                    continue        # разрыв по пробелу там не даёт слова
                счёт[слово] += 1
                if слово not in откуда:
                    откуда[слово], строка[слово] = w["name"], с.strip()
    return счёт, откуда, строка


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--мир", default=None, help="показать слова одного мира")
    дов = ап.parse_args()
    ряд = миры()
    if not ряд:
        print("СЛОВО ОДНАЖДЫ ОТКАЗ: миров показов в манифесте нет")
        return 2
    if дов.мир is not None and not any(w["name"] == дов.мир for w in ряд):
        print(f"СЛОВО ОДНАЖДЫ ОТКАЗ: мира «{дов.мир}» среди меряемых нет")
        return 2

    счёт, откуда, строка = перепись(ряд)
    однажды = sorted(с for с, n in счёт.items() if n == 1)
    по_мирам = collections.Counter(откуда[с] for с in однажды)
    print(f"миров меряно {len(ряд)}, различных слов {len(счёт)}, "
          f"ЖИВУЩИХ ОДНАЖДЫ {len(однажды)} ({100 * len(однажды) / max(len(счёт), 1):.1f} %)")
    for мир, n in по_мирам.most_common(12 if not дов.подробно else len(по_мирам)):
        print(f"  {мир:<24} {n:>4}")
    if дов.мир is not None:
        свои = [с for с in однажды if откуда[с] == дов.мир]
        print(f"  — слова мира «{дов.мир}» ({len(свои)}) —")
        for с in свои:
            print(f"    «{с}»  ←  {строка[с][:96]}")
    elif дов.подробно:
        for с in однажды[:60]:
            print(f"    «{с}»  [{откуда[с]}]  ←  {строка[с][:80]}")

    поза = "PASS" if len(однажды) <= ОДНАЖДЫ_РУБЕЖ else "FAIL"
    print(f"СЛОВО ОДНАЖДЫ {поза}: слов, показанных РОВНО РАЗ, {len(однажды)} "
          f"(рубеж {ОДНАЖДЫ_РУБЕЖ}); миров с такими словами {len(по_мирам)} из {len(ряд)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
