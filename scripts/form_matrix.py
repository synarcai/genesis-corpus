def _перекос_дома(имя, по_форме, языки, на_форму, объявлено, вон):
    """Неровность языков дома ПО СТРАНИЦАМ, а не по присутствию рода.

    ЯЗЫК, ОБЪЯВЛЕННО ПРОПУЩЕННЫЙ В РОДЕ, НЕ ДОЛЖЕН ЕГО СТРАНИЦ (15.09). Первая редакция меры
    назвала неровными четыре дома вежливого регистра: английский там вдвое беднее, ибо «you»
    служит обоим регистрам и второй формы у него НЕТ. Дом сказал об этом словарём
    `ОБЪЯВЛЕННЫЕ_ПРОПУСКИ` — и мера обязана его прочесть.

        МЕРА, НЕ ЧИТАЮЩАЯ ОБЪЯВЛЕНИЯ СОСЕДНЕЙ МЕРЫ, НАЗЫВАЕТ ДОЛГОМ ТО, ЧТО КОРПУС УЖЕ
        ОБЪЯСНИЛ. Одно объявление — два читателя: щербатость не зовёт такую клетку пустой,
        перекос не зовёт такой язык бедным.
    """
    # СЧЁТ ИДЁТ ПО РОДАМ, ГДЕ НИ ОДИН ЯЗЫК НЕ ОБЪЯВЛЕН ПРОПУЩЕННЫМ. Исключить один язык из
    # рода мало: дом вежливого регистра пишет четыре рода, из них два английскому недоступны, —
    # и английский беден ВДВОЕ по числу родов, а не по обилию внутри них. Сравнивать надо
    # РОВНЫЕ роды, те, где все языки дома обещаны.
    ровно = collections.Counter()
    for форма, свои in по_форме.items():
        if объявлено.get(форма):
            continue                       # род с объявленным пропуском в счёт не идёт
        for яз in свои:
            if яз != ВНЕЯЗЫЧНО:
                ровно[яз] += на_форму[(форма, яз)]
    for яз in языки:
        ровно.setdefault(яз, 0)
    if len(ровно) > 1 and min(ровно.values()) > 0:
        наиб, наим = max(ровно.values()), min(ровно.values())
        если = наиб / наим
        if если >= ЯЗЫКОВЫЙ_ПЕРЕКОС:
            вон.append((если, имя, dict(sorted(ровно.items()))))


def объявленный_язык(м):
    """Сколько языков дом объявил ВЕРХНИМ УРОВНЕМ — или None, если не объявлял.

    ДОМ, НЕ КЛАДУЩИЙ ЯЗЫКА В ПОКАЗ, БЫВАЕТ ДВУХ РАЗНЫХ ПОРОД (15.09). Один многоязычен, и
    щербатость его НЕИЗМЕРИМА — язык известен строителю и потерян на пороге словаря. Другой
    пишет на одном языке (дом `subjcount` — весь английский, `ruverbsforms` — весь русский), и
    щербатости в нём не может быть вовсе: сравнивать не с чем.

        МЕРА, СЧИТАЮЩАЯ ОДНОЯЗЫЧНЫЙ ДОМ СВОИМ ДОЛГОМ, ТРЕБУЕТ ОТ НЕГО ВТОРОГО ЯЗЫКА — а он
        его не обещал. Долг тут не у дома, а у меры: она не спросила.

    Спрашивается объявление, а не догадка по виду строк: `ЯЗЫК` строкой либо `ЯЗЫКИ` /
    `ЯЗЫКИ_МИРА` рядом. Дом, не сказавший ничего, остаётся в долге — и это верно, ибо
    молчание о языке неотличимо от многоязычия, потерянного на пороге.
    """
    один = getattr(м, "ЯЗЫК", None)
    if isinstance(один, str) and один:
        return 1
    for имя in ("ЯЗЫКИ_МИРА", "ЯЗЫКИ"):
        ряд = getattr(м, имя, None)
        if isinstance(ряд, (tuple, list, set, frozenset, dict)) and ряд:
            return len(ряд)
    return None


def решётка(показы):
    """({форма: языки}, языки, внеязычные) — или None, если нет пар (язык, форма)."""
    по_форме = collections.defaultdict(set)
    языки = set()
    со_словом = set()
    страниц = collections.Counter()
    на_форму = collections.Counter()
    для_пар = 0
    for _ключ, значение in показы.items():
        # ПОКАЗ БЫВАЕТ ТРОЙКОЙ, И ЭТО ОБЪЯВЛЕНИЕ, А НЕ ПОРЧА (15.09). Дом рамок сравнения
        # кладёт «(язык, группа, форма)»: группа есть ДОВОД страницы, как местоимение у
        # соседа `pronobject`. Прибор перекоса это читает с первого дня («род стои́т в
        # кортеже последним»), а здешняя мера требовала ровно двух полей — и отвергала
        # шесть с половиной тысяч страниц, где язык был НАЗВАН.
        #
        #     МЕРА, ТРЕБУЮЩАЯ ОТ ОБЪЯВЛЕНИЯ ОДНОЙ ДЛИНЫ, ЧИТАЕТ НЕ ОБЪЯВЛЕНИЕ, А СВОЮ
        #     ПРИВЫЧКУ К НЕМУ. Язык стои́т первым, род — всё, что после него; при двух полях
        #     это прежняя пара, при трёх — «группа·форма», и два рода одного имени в разных
        #     группах остаются разными.
        if not (isinstance(значение, tuple) and len(значение) >= 2):
            continue
        яз, хвост = значение[0], значение[1:]
        if not isinstance(яз, str) or not all(isinstance(ч, str) for ч in хвост):
            continue
        форма = "·".join(хвост)
        по_форме[форма].add(яз)
        if яз != ВНЕЯЗЫЧНО:
            языки.add(яз)
            страниц[яз] += 1
        на_форму[(форма, яз)] += 1
        для_пар += 1
        if СЛОВО.search(_ключ):
            со_словом.add(форма)
    if для_пар == 0:
        return "без пары"    # ПОКАЗЫ несут одно имя рода строкой, без языка
    if len(языки) < 2:
        return "одноязычный"  # щербатости в нём быть не может: не с чем сравнить
    return по_форме, языки, set(по_форме) - со_словом, страниц, на_форму


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--сверху", type=int, default=12)
    ап.add_argument("--дом", default=None, help="один дом поимённо")
    ап.add_argument("--при-объявлении", action="store_true",
                    dest="при_объявлении", help="только щербатость при объявлении")
    ап.add_argument("--мимо", action="store_true", help="дома, прошедшие мимо меры, поимённо")
    ап.add_argument("--перекос", action="store_true",
                    help="дома, чьи языки неровны страницами")
    а = ап.parse_args()

    щербатых = целых = прочтено = без_слов = 0
    # НЕПРОЧТЁННОЕ НАЗЫВАЕТСЯ, А НЕ МОЛЧИТ (15.09). Прибор дошёл до нуля щербатых — и ноль этот
    # взят на 203 домах из примерно трёхсот сорока пяти. Прочие 140 прибор пропускал МОЛЧА, и
    # молчание его было неотличимо от их исправности.
    #
    #     ПРИБОР, ДОШЕДШИЙ ДО НУЛЯ, ОБЯЗАН СКАЗАТЬ, НА ЧЁМ ЭТОТ НОЛЬ ВЗЯТ. Иначе ноль растёт
    #     не работой, а сужением знаменателя — тем же пороком, что и рукописный список, только
    #     скрытым глубже: список хоть был виден в коде.
    #
    # Три рода непрочтённого, и все три РАЗНЫЕ: дом без ПОКАЗОВ (мера его не берёт вовсе), дом
    # с показом без языка (одно имя рода строкой — такому щербатость неизмерима), и дом
    # одноязычный (сравнивать не с чем, и это не порок). Читатель: ключ --мимо.
    мимо = collections.Counter()
    мимо_имена = collections.defaultdict(list)
    одноязычных = 0
    перекос = []
    ряды = []
    при_объявлении = []
    имена = [а.дом] if а.дом else list(дома())
    for имя in имена:
        try:
            м = importlib.import_module(имя)
        except Exception as е:
            if а.дом:
                print(f"  ДОМ НЕ ПРОЧТЁН {имя}: {е}", file=sys.stderr)
            continue
        показы = getattr(м, "ПОКАЗЫ", None)
        if not isinstance(показы, dict) or not показы:
            мимо["без ПОКАЗОВ"] += 1
            мимо_имена["без ПОКАЗОВ"].append(имя)
            continue
        снято = решётка(показы)
        if isinstance(снято, str):
            сколько = объявленный_язык(м)
            если_один = снято == "без пары" and сколько == 1
            ключ = "объявленно одноязычный" if (снято == "одноязычный" or если_один) else снято
            if ключ == "объявленно одноязычный":
                одноязычных += 1
                continue                     # щербатости быть не может: сравнивать не с чем
            мимо[ключ] += 1
            мимо_имена[ключ].append(имя + (f" ({сколько} яз.)" if сколько else ""))
            continue
        по_форме, языки, внеязычные, страниц, на_форму = снято
        прочтено += 1
        без_слов += len(внеязычные)
        # ПЕРЕКОС ЯЗЫКОВ ДОМА — ВТОРАЯ МЕРА ТОЙ ЖЕ РЕШЁТКИ (15.09, вечер). Щербатость мерит
        # ПРИСУТСТВИЕ рода на языке и молчит об обилии: дом быта держит все пятнадцать родов
        # на обоих языках и всё же пишет 2702 английские страницы против 1258 русских.
        #
        #     РОД, НАПИСАННЫЙ НА ОБОИХ ЯЗЫКАХ ВТРОЕ НЕРОВНО, НЕ ЩЕРБАТ И НЕ РОВЕН. Клетка
        #     решётки не пуста — она ХУДА, и мера присутствия о ней сказать не может.
        # ЯЗЫК, ОБЪЯВЛЕННО ПРОПУЩЕННЫЙ В РОДЕ, НЕ ДОЛЖЕН ЕГО СТРАНИЦ (15.09). Первая редакция
        # этой меры назвала неровными четыре дома вежливого регистра: английский там вдвое
        # беднее, ибо «you» служит обоим регистрам и второй формы у него НЕТ. Дом сказал об
        # этом словарём `ОБЪЯВЛЕННЫЕ_ПРОПУСКИ` — и мера обязана его прочесть.
        #
        #     МЕРА, НЕ ЧИТАЮЩАЯ ОБЪЯВЛЕНИЯ СОСЕДНЕЙ МЕРЫ, НАЗЫВАЕТ ДОЛГОМ ТО, ЧТО КОРПУС УЖЕ
        #     ОБЪЯСНИЛ. Одно объявление — два читателя: щербатость не зовёт такую клетку
        #     пустой, перекос не зовёт такой язык бедным.
        объявлено = getattr(м, "ОБЪЯВЛЕННЫЕ_ПРОПУСКИ", {}) or {}
        _перекос_дома(имя, по_форме, языки, на_форму, объявлено, перекос)
        for форма, свои in sorted(по_форме.items()):
            if форма in внеязычные:
                continue     # страница без слов: второй язык был бы дубликатом
            назван = set(объявлено.get(форма, ()))
            нет = sorted(языки - свои - назван - {ВНЕЯЗЫЧНО})
            if нет:
                щербатых += 1
                ряды.append((len(нет), имя, форма, нет))
                if назван:
                    # ДОМ УЖЕ ПИСАЛ ЭТОМУ РОДУ ПРИЧИНУ — И ВСЁ-ТАКИ НЕ ДОНАЗВАЛ
                    при_объявлении.append((len(нет), имя, форма, sorted(назван), нет))
            else:
                целых += 1

    if а.при_объявлении:
        при_объявлении.sort(reverse=True)
        print(f"{'дом':16} {'форма':22} {'названо':16} молчит ещё")
        for _, имя, форма, назв, нет in при_объявлении[:а.сверху]:
            print(f"{имя[:16]:16} {форма[:22]:22} {','.join(назв)[:16]:16} {', '.join(нет)}")
    else:
        ряды.sort(reverse=True)
        print(f"{'дом':16} {'форма':22} нет на языках")
        for _, имя, форма, нет in ряды[:а.сверху]:
            print(f"{имя[:16]:16} {форма[:22]:22} {', '.join(нет)}")

    if а.перекос:
        перекос.sort(reverse=True)
        print(f"{'дом':22} {'раз':>6}  страниц по языкам")
        for если, имя, стр in перекос[:а.сверху]:
            print(f"{имя[:22]:22} {если:6.1f}  " + " ".join(f"{я}:{n}" for я, n in стр.items()))

    if а.мимо:
        for почему in sorted(мимо, key=lambda п: -мимо[п]):
            print(f"  {почему} ({мимо[почему]}): {', '.join(sorted(мимо_имена[почему]))}")

    всего = щербатых + целых
    беда = not а.дом and (прочтено < ПРОЧТЕНО_РУБЕЖ or щербатых > ЩЕРБАТЫХ_РУБЕЖ
                          or sum(мимо.values()) > МИМО_РУБЕЖ
                          or len(перекос) > ПЕРЕКОС_РУБЕЖ)
    print(f"ЩЕРБАТОСТЬ ДОМОВ {'FAIL' if беда else 'PASS'}: {щербатых} щербатых форм из {всего} "
          f"({100 * щербатых // max(1, всего)} %, рубеж {ЩЕРБАТЫХ_РУБЕЖ}), домов прочтено {прочтено} "
          f"(рубеж {ПРОЧТЕНО_РУБЕЖ}), из них при объявлении {len(при_объявлении)}; "
          f"внеязычных форм {без_слов} — вне счёта; "
          f"объявленно одноязычных {одноязычных} — вне долга; "
          f"домов с языковым перекосом хуже {ЯЗЫКОВЫЙ_ПЕРЕКОС:g}× — {len(перекос)} "
          f"(рубеж {ПЕРЕКОС_РУБЕЖ}); "
          f"МИМО МЕРЫ {sum(мимо.values())} домов (рубеж {МИМО_РУБЕЖ}: "
          + ", ".join(f"{п} {n}" for п, n in sorted(мимо.items())) + ")")
    if всего == 0:
        print("  ВНИМАНИЕ: форм НОЛЬ — прибор ничего не прочёл (М-264)")
    return 1 if беда else 0


if __name__ == "__main__":
    sys.exit(main())
