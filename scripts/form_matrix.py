#!/usr/bin/env python3
"""[ЩЕРБАТОСТЬ ДОМОВ] — форма, написанная не на всех языках своего дома.

Слово holon (04.09), снявшего произведение «голова × запись × действие»:
немота сидит не на голове и не на записи, а на КЛЕТКЕ, и часто на ОДНОМ
действии из четырёх. Дыры ВНУТРИ дома дешевле и важнее новых домов — но
увидеть их можно, лишь померив дом по его собственному произведению.

Прибор берёт у каждого дома форм его ПОКАЗЫ (там при каждой строке стоят язык
и форма) и строит решётку «форма × язык». Щербатая клетка — форма, живущая на
одних языках дома и молчащая на других.

ЩЕРБАТОСТЬ НЕ ЕСТЬ ЛОЖЬ И ЧАСТО НЕ ЕСТЬ ДОЛГ, и потому дом называет свои
НАМЕРЕННЫЕ дыры сам — словарём `ОБЪЯВЛЕННЫЕ_ПРОПУСКИ` вида {форма: языки}.
Дом поведения не пишет «кратко» по-немецки и по-голландски (их порядок ставит
местоимение перед именем); дома с вежливым регистром не пишут его
по-английски («you» служит обоим, и вторая форма совпала бы с первой). Прибор
читает объявление и такую дыру щербатостью не зовёт — судить английский
русской меркой значило бы мерить не корпус, а свою мерку.

Дыра НЕОБЪЯВЛЕННАЯ остаётся названной: прибор не судит, а НАЗЫВАЕТ, и решение
оставляет дому — как прибор массы на форму называет цену, а не приговор.

    ЗНАМЕНАТЕЛЬ СНЯТ С РУК (15.09). До сего дня прибор держал рукописный список
    из двадцати трёх домов при трёх с половиной сотнях в корпусе — и мерил не
    корпус, а свою память о нём. Теперь он обходит tools/ целиком и читает
    всякий дом, чей ПОКАЗЫ несёт пару (язык, род); рубеж стои́т на ЧИСЛЕ
    ПРОЧТЁННЫХ ДОМОВ и ходит только вверх, как у прибора рамок.

    ЩЕРБАТОСТЬ ПРИ ОБЪЯВЛЕНИИ (15.09) — вторая находка того же дня и примета
    острее первой. Род `единица` дома svampforms объявлен пропущенным по-русски
    — одним языком из девяти, — а живёт лишь по-английски: семь дыр молчат при
    написанном объявлении. ЧАСТИЧНОЕ ОБЪЯВЛЕНИЕ ХУЖЕ ОТСУТСТВИЯ ОБЪЯВЛЕНИЯ:
    отсутствие честно молчит, частичное же наводит на мысль, что об остальных
    языках позаботились. Дом уже думал о таком роде и уже писал ему причину —
    значит чинится он дешевле прочих, и прибор называет его отдельной строкой.

    python3 scripts/form_matrix.py [--сверху 12] [--дом svampforms] [--при-объявлении]
"""
import argparse
import collections
import importlib
import pathlib
import re
import sys

# СТРАНИЦА БЕЗ СЛОВА НЕ ПРИНАДЛЕЖИТ ЯЗЫКУ (15.09). Дом одношаговых уравнений метит «x + 2 =
# 3. x = 3 − 2. x = 1.» русским языком — по месту в таблице, а не по делу: здесь нет ни
# одного слова, и по-английски эта же страница вышла бы знак в знак той же. Прибор назвал
# такую форму щербатой трижды, требуя от дома дубликата.
#
#     ТРЕБОВАТЬ ВТОРОГО ЯЗЫКА ОТ СТРАНИЦЫ БЕЗ СЛОВ ЗНАЧИТ ТРЕБОВАТЬ ДУБЛИКАТА. Прибор видит
#     это сам и не просит дом объявлять очевидное: форма, НИ ОДНА страница которой не несёт
#     слова в две буквы и более, зовётся ВНЕЯЗЫЧНОЙ и считается особо. Одной буквы мало —
#     «x» и «n» суть имена неизвестного, а не слова языка.
СЛОВО = re.compile(r"[A-Za-zА-Яа-яЁёĄ-ž\u0100-\u024f]{2,}")

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
# ПРАВИЛО ДОПУСКА У КОРПУСА ОДНО, И ЖИВЁТ ОНО В УКАЗАТЕЛЕ РОДОВ. Первая редакция полного
# обхода считала домом всякий файл в tools/, не начинающийся с «gen_», — и вписала в
# непрочтённое `layer`, `panel`, `phrases`, `rugram` и семь десятков прочих ОРУДИЙ, которые
# домами не были никогда. Мера, назвавшая орудие непрочтённым домом, лжёт о своём долге вверх.
import genus_atlas as _допуск  # noqa: E402

# РУБЕЖ-ПОКРОВ: число домов, чьи ПОКАЗЫ прибор сумел прочесть. Ходит только
# вверх — падение значит, что дом перестал объявлять пару (язык, род) либо
# перестал ввозиться, и это разлад, а не новость.
# РУБЕЖ-ДОЛГА: ПРОЧТЕНО_РУБЕЖ = 203
ПРОЧТЕНО_РУБЕЖ = 203

# РУБЕЖ-ДОЛГА: ЩЕРБАТЫХ_РУБЕЖ = 0
# Долговой ратчет: только вниз. Пятнадцать при первом полном чтении двора — и тринадцать из
# них выкованы в тот же день: группа «место», «список», «доля» и «кратное» дома действий
# заговорили на четырёх романских (+1374 страницы в мире, суд PASS 0 из 6295). Дорога к ним
# шла через ЧУЖОЙ ДОМ: род `доля` звал `fracforms.доля_слово`, а дом долей знал три языка, и
# ковка его на четыре романских (+1746 страниц) была условием, а не поводом.
#
# Двое оставшихся — у дома svamp: `единица` и `итог_всего` жили по-английски, и объявление
# первого называло пропущенным один русский (то самое ЧАСТИЧНОЕ ОБЪЯВЛЕНИЕ, что хуже
# отсутствия). Выкованы на всех девяти в тот же день, и ковка сразу вскрыла ошибку в теле
# дома: `Тk` считался ДО подмены числа парой цены, и славянская рамка сказала бы «стоят 4
# монет». Английская того не замечала, ибо берёт `Тмн`, одну на все числа.
#
#     НОЛЬ ЗДЕСЬ ЕСТЬ МЕРА ДВОРА, А НЕ КОНЕЦ РАБОТЫ. Прибор читает 203 дома из ~345: те, чей
#     `ПОКАЗЫ` несёт пару (язык, род) и кто держит два языка и более. Дом, писанный одним
#     языком, для этой меры не существует — и это отдельный долг, стоящий отдельной меры.
ЩЕРБАТЫХ_РУБЕЖ = 0

# РУБЕЖ-ДОЛГА: МИМО_РУБЕЖ = 111
# Долговой ратчет: только вниз. Сто одиннадцать домов, объявивших род своим текстом и всё же
# непрочитанных этой мерой. Сто четыре из них кладут в `ПОКАЗЫ` ОДНО ИМЯ РОДА строкой: языка
# в показе нет, и щербатость их НЕИЗМЕРИМА — не «нулевая», а именно неизмеримая. Шесть не
# объявляют `ПОКАЗЫ` вовсе. Один одноязычен, и это не порок: сравнивать не с чем.
#
#     НЕИЗМЕРИМОЕ И ИЗМЕРЕННОЕ В НОЛЬ СУТЬ РАЗНЫЕ СОСТОЯНИЯ, И МЕРА, НЕ РАЗЛИЧАЮЩАЯ ИХ,
#     РАСТЁТ СУЖЕНИЕМ ЗНАМЕНАТЕЛЯ. Ноль щербатых взят на 203 домах; эти сто одиннадцать —
#     цена того нуля, и она названа рядом с ним, а не спрятана.
МИМО_РУБЕЖ = 111

ВНЕ = {"__init__"}


def дома():
    """ВЕСЬ tools/, а не список в голове прибора. Кузницы (gen_*) не дома."""
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        имя = путь.stem
        if имя.startswith("_") or имя in ВНЕ:
            continue
        # ДОМ ТОТ, КТО ОБЪЯВИЛ РОД СВОИМ ТЕКСТОМ. Орудия корпуса (`layer`, `panel`,
        # `phrases`, три дома грамматики) родов не объявляют и домами не были никогда —
        # их непрочтение не есть долг меры.
        if not _допуск.дом_ли(путь) or not _допуск.объявляет_род(путь):
            continue
        yield имя


def решётка(показы):
    """({форма: языки}, языки, внеязычные) — или None, если нет пар (язык, форма)."""
    по_форме = collections.defaultdict(set)
    языки = set()
    со_словом = set()
    для_пар = 0
    for _ключ, значение in показы.items():
        if not (isinstance(значение, tuple) and len(значение) == 2):
            continue
        яз, форма = значение
        if not isinstance(яз, str) or not isinstance(форма, str):
            continue
        по_форме[форма].add(яз)
        языки.add(яз)
        для_пар += 1
        if СЛОВО.search(_ключ):
            со_словом.add(форма)
    if для_пар == 0:
        return "без пары"    # ПОКАЗЫ несут одно имя рода строкой, без языка
    if len(языки) < 2:
        return "одноязычный"  # щербатости в нём быть не может: не с чем сравнить
    return по_форме, языки, set(по_форме) - со_словом


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--сверху", type=int, default=12)
    ап.add_argument("--дом", default=None, help="один дом поимённо")
    ап.add_argument("--при-объявлении", action="store_true",
                    dest="при_объявлении", help="только щербатость при объявлении")
    ап.add_argument("--мимо", action="store_true", help="дома, прошедшие мимо меры, поимённо")
    а = ап.parse_args()

    щербатых = целых = прочтено = без_слов = 0
    # НЕПРОЧТЁННОЕ НАЗЫВАЕТСЯ, А НЕ МОЛЧИТ (15.09). Прибор дошёл до нуля щербатых — и ноль этот
    # взят на 203 домах из примерно трёхсот сорока пяти. Прочие 140 прибор пропускал МОЛЧА, и
    # молчание его было неотличимо от их исправности.
    #
    #     ПРИБОР, ДОШЕДШИЙ ДО НУЛЯ, ОБЯЗАН СКАЗАТЬ, НА ЧЁМ ЭТОТ НОЛЬ ВЗЯТ. Иначе ноль растёт
    #     не работой, а сужением знаменателя — тем же пороком, что и рукописный список, только
    #     скрытым глубже: список хоть был виден в коде.
    #
    # Три рода непрочтённого, и все три РАЗНЫЕ: дом без ПОКАЗОВ (мера его не берёт вовсе), дом
    # с показом без языка (одно имя рода строкой — такому щербатость неизмерима), и дом
    # одноязычный (сравнивать не с чем, и это не порок). Читатель: ключ --мимо.
    мимо = collections.Counter()
    мимо_имена = collections.defaultdict(list)
    ряды = []
    при_объявлении = []
    имена = [а.дом] if а.дом else list(дома())
    for имя in имена:
        try:
            м = importlib.import_module(имя)
        except Exception as е:
            if а.дом:
                print(f"  ДОМ НЕ ПРОЧТЁН {имя}: {е}", file=sys.stderr)
            continue
        показы = getattr(м, "ПОКАЗЫ", None)
        if not isinstance(показы, dict) or not показы:
            мимо["без ПОКАЗОВ"] += 1
            мимо_имена["без ПОКАЗОВ"].append(имя)
            continue
        снято = решётка(показы)
        if isinstance(снято, str):
            мимо[снято] += 1
            мимо_имена[снято].append(имя)
            continue
        по_форме, языки, внеязычные = снято
        прочтено += 1
        без_слов += len(внеязычные)
        объявлено = getattr(м, "ОБЪЯВЛЕННЫЕ_ПРОПУСКИ", {}) or {}
        for форма, свои in sorted(по_форме.items()):
            if форма in внеязычные:
                continue     # страница без слов: второй язык был бы дубликатом
            назван = set(объявлено.get(форма, ()))
            нет = sorted(языки - свои - назван)
            if нет:
                щербатых += 1
                ряды.append((len(нет), имя, форма, нет))
                if назван:
                    # ДОМ УЖЕ ПИСАЛ ЭТОМУ РОДУ ПРИЧИНУ — И ВСЁ-ТАКИ НЕ ДОНАЗВАЛ
                    при_объявлении.append((len(нет), имя, форма, sorted(назван), нет))
            else:
                целых += 1

    if а.при_объявлении:
        при_объявлении.sort(reverse=True)
        print(f"{'дом':16} {'форма':22} {'названо':16} молчит ещё")
        for _, имя, форма, назв, нет in при_объявлении[:а.сверху]:
            print(f"{имя[:16]:16} {форма[:22]:22} {','.join(назв)[:16]:16} {', '.join(нет)}")
    else:
        ряды.sort(reverse=True)
        print(f"{'дом':16} {'форма':22} нет на языках")
        for _, имя, форма, нет in ряды[:а.сверху]:
            print(f"{имя[:16]:16} {форма[:22]:22} {', '.join(нет)}")

    if а.мимо:
        for почему in sorted(мимо, key=lambda п: -мимо[п]):
            print(f"  {почему} ({мимо[почему]}): {', '.join(sorted(мимо_имена[почему]))}")

    всего = щербатых + целых
    беда = not а.дом and (прочтено < ПРОЧТЕНО_РУБЕЖ or щербатых > ЩЕРБАТЫХ_РУБЕЖ
                          or sum(мимо.values()) > МИМО_РУБЕЖ)
    print(f"ЩЕРБАТОСТЬ ДОМОВ {'FAIL' if беда else 'PASS'}: {щербатых} щербатых форм из {всего} "
          f"({100 * щербатых // max(1, всего)} %, рубеж {ЩЕРБАТЫХ_РУБЕЖ}), домов прочтено {прочтено} "
          f"(рубеж {ПРОЧТЕНО_РУБЕЖ}), из них при объявлении {len(при_объявлении)}; "
          f"внеязычных форм {без_слов} — вне счёта; "
          f"МИМО МЕРЫ {sum(мимо.values())} домов (рубеж {МИМО_РУБЕЖ}: "
          + ", ".join(f"{п} {n}" for п, n in sorted(мимо.items())) + ")")
    if всего == 0:
        print("  ВНИМАНИЕ: форм НОЛЬ — прибор ничего не прочёл (М-264)")
    return 1 if беда else 0


if __name__ == "__main__":
    sys.exit(main())
