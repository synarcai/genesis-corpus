#!/usr/bin/env python3
"""[ЗОВ ПО СТАРОМУ АДРЕСУ] — прибор, зовущий у соседа имя, какого у соседа нет.

ПОВОД, ПРОЖИТЫЙ 16.09. Разбор понятий жил в кузнице `gen_genesis_definitions`, потом переехал
в дом `defnforms`, и кузница стала звать его соседом. Прибор следа разбора
(`scripts/definitions_reach.py`) остался при старом адресе — и ПАЛ С ОШИБКОЙ ИМЕНИ на первом
же вызове: `module 'gen_genesis_definitions' has no attribute 'понятия'`. Он лежал павшим
двое суток, и палата знала о нём ровно то, что знает о всяком павшем: «ПАЛО 22 из 365».

    ПАВШИЙ ПРИБОР НЕ МЕРИТ. Число в его строке не «ноль находок», а «ничего не сказано», и
    это ровно тот случай, когда молчание неотличимо от чистоты.

ПОЧЕМУ ЭТО ЛОВИТСЯ СТАТИЧЕСКИ, А НЕ ПРОГОНОМ. Прогнать всё — часы машины: иные приборы идут
по получасу на своде в полмиллиона строк. А беда видна БЕЗ ПРОГОНА: `import defnforms as F`
объявляет адрес, `F.понятия` — зов по нему, и есть ли у дома такое имя, говорит его же текст.
Прибор читает ДЕРЕВО, а не запускает его, и потому идёт секунды.

    ИМЯ, ОБЪЯВЛЕННОЕ ОДНИМ МОДУЛЕМ И НАЗВАННОЕ ДРУГИМ, ЕСТЬ ДОГОВОР ДВОИХ. Переезд имени
    рвёт договор молча — молчит и тот, кто уехал, и тот, кто зовёт, покуда зов не случится.

ЧТО ПРИБОР ЧИТАЕТ ИМЕНЕМ МОДУЛЯ. Объявлением считается всё, что модуль кладёт на верхний
уровень: `def`, `class`, присвоение, ввоз — включая те, что стоят внутри `if`, `try`, `for` и
`with` верхнего уровня. Имени, положенного ВНУТРИ функции, снаружи нет, и прибор его не
считает: `globals()` есть ровно та дверь, о которой сказано ниже.

ЧЕГО ПРИБОР НЕ СУДИТ, И ЭТО СКАЗАНО ЧИСЛОМ:

    ОТКРЫТЫЙ МОДУЛЬ — тот, кто пишет свои имена сам (`from X import *`, `globals()[...] = `,
                      `setattr(sys.modules…)`). Что у него есть, текстом не сказано, и
                      требовать от зовущего знания о нём нельзя;
    ЗАТЕНЁННЫЙ АЛИАС — имя ввоза, каким где-то в том же файле зовётся ещё и переменная или
                      довод функции (`def f(F): F.понятия()`). Тогда `F.имя` может быть и
                      не о модуле, и прибор молчит обо всём этом алиасе.

    python3 scripts/stale_call.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --двор /no/such/dir
import argparse
import ast
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ДВОРЫ = ("tools", "scripts", "courts")

# РУБЕЖ-ДОЛГА: ЗОВОВ_РУБЕЖ = 0
#
# ЗОВОВ ПО СТАРОМУ АДРЕСУ. Замерено 16.09 при рождении прибора; рубеж есть ПОТОЛОК и только
# опускается. Платится он либо правкой зовущего (звать по новому адресу), либо возвратом
# имени на прежнее место — но НЕ ОБЪЯВЛЕНИЕМ ИСКЛЮЧЕНИЯ: список исключений у такого прибора
# растёт ровно так же молча, как рвутся договоры, которые он стережёт.
ЗОВОВ_РУБЕЖ = 0


def _модули_корпуса():
    """{имя модуля: путь} — всё, что можно ввезти именем из объявленных дворов."""
    вон = {}
    for двор in ДВОРЫ:
        for путь in sorted((КОРЕНЬ / двор).glob("*.py")):
            вон.setdefault(путь.stem, путь)
    return вон


def открыт(дерево, текст):
    """Модуль, пишущий свои имена сам, — о нём текстом ничего не сказано."""
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.ImportFrom) and any(и.name == "*" for и in узел.names):
            return True
    return "globals()" in текст or "setattr(sys.modules" in текст


def объявленное(дерево):
    """Имена верхнего уровня: def, class, присвоение, ввоз — и те, что внутри if/try/for."""
    вон = set()

    def обойти(тело):
        for узел in тело:
            if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                вон.add(узел.name)
            elif isinstance(узел, ast.Assign):
                for цель in узел.targets:
                    for имя in ast.walk(цель):
                        if isinstance(имя, ast.Name):
                            вон.add(имя.id)
            elif isinstance(узел, (ast.AnnAssign, ast.AugAssign)):
                if isinstance(узел.target, ast.Name):
                    вон.add(узел.target.id)
            elif isinstance(узел, (ast.Import, ast.ImportFrom)):
                for и in узел.names:
                    вон.add(и.asname or и.name.split(".")[0])
            elif isinstance(узел, (ast.If, ast.Try, ast.For, ast.While, ast.With)):
                обойти(узел.body)
                обойти(getattr(узел, "orelse", []))
                обойти(getattr(узел, "finalbody", []))
                for о in getattr(узел, "handlers", []):
                    обойти(о.body)

    обойти(дерево.body)
    return вон


def _затенённые(дерево):
    """Имена, какими в этом же файле зовётся ещё и переменная или довод функции."""
    вон = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef)):
            д = узел.args
            for а in (*д.posonlyargs, *д.args, *д.kwonlyargs, д.vararg, д.kwarg):
                if а is not None:
                    вон.add(а.arg)
            for вложенный in ast.walk(узел):
                if isinstance(вложенный, ast.Assign):
                    for цель in вложенный.targets:
                        for имя in ast.walk(цель):
                            if isinstance(имя, ast.Name):
                                вон.add(имя.id)
    return вон


def адреса(дерево, свои):
    """{алиас: имя модуля} — ввозы верхнего уровня, указывающие на модуль корпуса."""
    вон = {}
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            for и in узел.names:
                корень = и.name.split(".")[0]
                if корень in свои:
                    вон[и.asname or корень] = корень
    return вон


def зовы(путь, свои, объявления):
    """[(алиас, модуль, имя, строка)] — зовы по адресу, где имени нет."""
    текст = путь.read_text(encoding="utf-8")
    try:
        дерево = ast.parse(текст)
    except SyntaxError:
        return [], 0
    адрес = адреса(дерево, свои)
    if not адрес:
        return [], 0
    тень = _затенённые(дерево) & set(адрес)
    вон = []
    for узел in ast.walk(дерево):
        if not (isinstance(узел, ast.Attribute) and isinstance(узел.value, ast.Name)):
            continue
        алиас = узел.value.id
        if алиас not in адрес or алиас in тень:
            continue
        модуль = адрес[алиас]
        известные = объявления.get(модуль)
        if известные is None or узел.attr in известные or узел.attr.startswith("__"):
            continue
        вон.append((алиас, модуль, узел.attr, узел.lineno))
    return вон, len(тень)


def _коротко(путь):
    """Путь от корня, а вне корня — как есть: двор задаётся доводом и бывает чужим."""
    try:
        return путь.relative_to(КОРЕНЬ)
    except ValueError:
        return путь


def _проба():
    """Прибор с рубежом НОЛЬ обязан доказать, что умеет находить (`scripts/probe_present.py`)."""
    сосед = ast.parse("ПОКАЗЫ = {}\n\n\ndef судить(с):\n    return False, True\n")
    объявления = {"сосед_проба": объявленное(сосед)}
    беды = []
    if "судить" not in объявления["сосед_проба"] or "ПОКАЗЫ" not in объявления["сосед_проба"]:
        беды.append("объявленное не видит def и присвоения верхнего уровня")
    зовущий = ast.parse("import сосед_проба as С\n\n\ndef f():\n    return С.понятия()\n")
    адрес = адреса(зовущий, {"сосед_проба"})
    if адрес != {"С": "сосед_проба"}:
        беды.append(f"адрес ввоза не прочитан: {адрес}")
    найдено = [у.attr for у in ast.walk(зовущий)
               if isinstance(у, ast.Attribute) and isinstance(у.value, ast.Name)
               and у.value.id in адрес and у.attr not in объявления[адрес[у.value.id]]]
    if найдено != ["понятия"]:
        беды.append(f"зов по старому адресу не пойман: {найдено}")
    # ЗАТЕНЁННЫЙ АЛИАС: `def f(С)` — и `С.понятия` уже не о модуле.
    затенённый = ast.parse("import сосед_проба as С\n\n\ndef f(С):\n    return С.понятия()\n")
    if "С" not in _затенённые(затенённый):
        беды.append("затенение доводом функции не замечено")
    if "С" in _затенённые(зовущий):
        беды.append("затенение выдумано там, где его нет")
    # ОТКРЫТЫЙ МОДУЛЬ: о его именах текстом ничего не сказано.
    if not открыт(ast.parse("from math import *\n"), "from math import *\n"):
        беды.append("открытость через `import *` не замечена")
    if открыт(сосед, "ПОКАЗЫ = {}"):
        беды.append("открытость выдумана у закрытого модуля")
    return беды


def main():
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ЗОВ ПО СТАРОМУ АДРЕСУ ОТКАЗ: мера не доказана ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--двор", action="append", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    дворы = дов.двор or list(ДВОРЫ)
    пути = [п for д in дворы for п in sorted((КОРЕНЬ / д).glob("*.py"))]
    if not пути:
        print(f"ЗОВ ПО СТАРОМУ АДРЕСУ ОТКАЗ: обход пуст — {', '.join(дворы)}")
        return 2
    свои = _модули_корпуса()
    объявления, открытых = {}, []
    for имя, путь in свои.items():
        текст = путь.read_text(encoding="utf-8")
        try:
            дерево = ast.parse(текст)
        except SyntaxError:
            continue
        if открыт(дерево, текст):
            открытых.append(имя)
            continue
        объявления[имя] = объявленное(дерево)
    найдено, теней = [], 0
    for путь in пути:
        ряд, т = зовы(путь, свои, объявления)
        теней += т
        for алиас, модуль, имя, строка in ряд:
            найдено.append((_коротко(путь), строка, алиас, модуль, имя))
    for путь, строка, алиас, модуль, имя in найдено[:None if дов.подробно else 20]:
        print(f"  ЗОВ  {путь}:{строка}: {алиас}.{имя} — у модуля «{модуль}» такого имени нет")
    поза = "PASS" if len(найдено) <= ЗОВОВ_РУБЕЖ else "FAIL"
    print(f"ЗОВ ПО СТАРОМУ АДРЕСУ {поза}: зовов {len(найдено)} (рубеж {ЗОВОВ_РУБЕЖ}) "
          f"при {len(пути)} читанных файлах и {len(объявления)} судимых модулях; "
          f"открытых модулей {len(открытых)} — их имена текстом не сказаны; "
          f"затенённых алиасов {теней}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
