#!/usr/bin/env python3
"""[ПРОБА ЕСТЬ] — прибор с рубежом НОЛЬ обязан доказывать, что умеет находить.

    ПРИБОР, ЗЕЛЕНЕЮЩИЙ ОТ НУЛЯ НАХОДОК, ОБЯЗАН ДОКАЗАТЬ, ЧТО УМЕЕТ НАХОДИТЬ:
    молчание признака неотличимо от честного нуля, покуда не спросишь его самого.

ПОВОД, ПРОЖИТЫЙ 12.09. Признак кода выхода в долге арифметики родился НЕМЫМ: граница слова
«\\b» обратилась в байт забоя, признак искал забой перед словом «exit» и не нашёл ни одной
строки во всём своде. Он молчал, и молчание его было неотличимо от честного нуля.

    ПРИЗНАК, ИЩУЩИЙ НЕВОЗМОЖНОЕ, ВЕДЁТ СЕБЯ КАК ПРИЗНАК, ИЩУЩИЙ РЕДКОЕ.

Замер того же часа: из 119 приборов с рубежом НОЛЬ пробу несли 24. Суды миров пробуются
общим прибором — `court_mutants` подсаживает порчу во все 225 и требует, чтобы её поймали, —
а приборы свода не пробовались ничем.

    СУДЫ МИРОВ ПРОБУЮТСЯ ОБЩИМ ПРИБОРОМ, А ПРИБОРЫ СВОДА — НИЧЕМ.

ЧТО СУДИТ ЭТОТ ПРИБОР. Он не исполняет чужих проб — приборы разнородны, и общая подсадка им
не годится: один читает манифест, другой леджер, третий дерево. Он требует, чтобы проба
БЫЛА, и считает тех, у кого её нет.

    ТРЕБОВАТЬ ПРОБЫ ДЕШЕВЛЕ, ЧЕМ ИСПОЛНЯТЬ ЕЁ ЗА ДРУГОГО, И ЧЕСТНЕЕ: прибор знает свой
    предмет, а общий подсадчик — лишь общую форму.

ЧТО СЧИТАЕТСЯ ПРОБОЙ: имя `_проба` либо довод `--проба`, либо подсадка (`ПОДСАДКА`,
`подсадк`, `мутант`) — три способа, которыми свод уже доказывает приборы.

РУБЕЖ ЕСТЬ ДОСТИГНУТОЕ И ПАДАЕТ ЗА ДЕЛОМ. Он объявлен по числу беспробных в час постановки
и опускается всякий раз, как прибор получает пробу: рубеж, не идущий за делом, стережёт
память о долге.

    python3 scripts/probe_present.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --корень /no/such/root
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ДВОРЫ = ("scripts", "courts")

# РУБЕЖ-ДОЛГА: БЕЗ_ПРОБЫ_РУБЕЖ = 13
#
# 47 беспробных приборов двора `scripts` в час постановки (12.09), при 23 с пробой.
# Рубеж падает за делом: всякий прибор, получивший пробу, опускает его на единицу.
БЕЗ_ПРОБЫ_РУБЕЖ = 13

НУЛЕВОЙ = re.compile(r"_РУБЕЖ\s*=\s*0\b")
ПРОБА = re.compile(r"def _проба\b|--проба|ПОДСАДКА|подсадк|мутант")
# ПРИБОР УЗНАЁТСЯ МЕТКОЙ ПУСТОГО ОБХОДА — тем же признаком, каким его узнаёт палата.
МЕТКА = "# ПУСТОЙ-ОБХОД:"


def приборы(корень):
    """[(путь, нулевой, с пробой)] — по всем дворам."""
    вон = []
    for двор in ДВОРЫ:
        п = корень / двор
        if not п.is_dir():
            continue
        for ф in sorted(п.glob("*.py")):
            тело = ф.read_text(encoding="utf-8", errors="replace")
            if МЕТКА not in тело:
                continue
            вон.append((f"{двор}/{ф.name}", bool(НУЛЕВОЙ.search(тело)),
                        bool(ПРОБА.search(тело))))
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: прибор, требующий проб, обязан иметь свою.

    Три файла на временном корне: прибор с рубежом ноль и пробой, прибор с рубежом ноль
    без пробы (обязан найтись долгом) и файл БЕЗ метки пустого обхода (обязан быть
    пропущен — он не прибор).
    """
    import tempfile
    беды = []
    with tempfile.TemporaryDirectory() as д:
        д = pathlib.Path(д)
        (д / "scripts").mkdir()
        (д / "scripts" / "с_пробой.py").write_text(
            f'"""док"""\n{МЕТКА} --нет\nЛОЖНЫХ_РУБЕЖ = 0\ndef _проба():\n    return []\n',
            encoding="utf-8")
        (д / "scripts" / "без_пробы.py").write_text(
            f'"""док"""\n{МЕТКА} --нет\nЛОЖНЫХ_РУБЕЖ = 0\n', encoding="utf-8")
        (д / "scripts" / "не_прибор.py").write_text('"""док"""\nЛОЖНЫХ_РУБЕЖ = 0\n',
                                                    encoding="utf-8")
        найдено = приборы(д)
        имена = {пп.split("/")[-1] for пп, _н, _п in найдено}
        if "не_прибор.py" in имена:
            беды.append("файл без метки пустого обхода сочтён прибором")
        беспробных = [пп for пп, н, п in найдено if н and not п]
        if [п.split("/")[-1] for п in беспробных] != ["без_пробы.py"]:
            беды.append(f"беспробным сочтён не тот: {беспробных}")
    return беды


def main():
    беды = _проба()
    if беды:
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ПРОБА ЕСТЬ ОТКАЗ: прибор не доказал, что умеет находить ({len(беды)} бед)")
        return 2
    корень = КОРЕНЬ
    if "--корень" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--корень") + 1])
    все = приборы(корень)
    if not все:
        print(f"ПРОБА ЕСТЬ ОТКАЗ: приборов не найдено в {корень}")
        return 2
    нулевые = [(пп, п) for пп, н, п in все if н]
    # СУД ПРОБУЕТСЯ ОБЩИМ ПРИБОРОМ, И ЭТО ЕСТЬ ЕГО ПРОБА. `court_mutants` подсаживает
    # порчу во все суды палаты и требует, чтобы её поймали; суд, своей пробы не имеющий,
    # доказан ЧУЖОЙ — и это доказательство, а не его отсутствие.
    #
    #     СУД, ПРОБУЕМЫЙ ОБЩИМ ПРИБОРОМ, ДОКАЗАН ИМ; ПРИБОР, НЕ ПРОБУЕМЫЙ НИЧЕМ,
    #     НЕ ДОКАЗАН НИЧЕМ.
    #
    # Оттого долгом числятся лишь приборы двора `scripts`, а суды печатаются рядом
    # отдельным числом — не долгом, а границей этого прибора.
    без_пробы = sorted(пп for пп, п in нулевые if not п and пп.startswith("scripts/"))
    суды_без_своей = [пп for пп, п in нулевые if not п and пп.startswith("courts/")]
    if "--подробно" in sys.argv:
        for пп in без_пробы:
            print(f"  без пробы: {пп}")
    else:
        for пп in без_пробы[:6]:
            print(f"  без пробы: {пп}")
        if len(без_пробы) > 6:
            print(f"  … и ещё {len(без_пробы) - 6}")
    поза = "PASS" if len(без_пробы) <= БЕЗ_ПРОБЫ_РУБЕЖ else "FAIL"
    print(f"ПРОБА ЕСТЬ {поза}: приборов `scripts` с рубежом НОЛЬ без записанной пробы "
          f"{len(без_пробы)} (рубеж {БЕЗ_ПРОБЫ_РУБЕЖ}); с пробой "
          f"{len(нулевые) - len(без_пробы) - len(суды_без_своей)}, нулевых {len(нулевые)}, "
          f"приборов всего {len(все)}; судов без СВОЕЙ пробы {len(суды_без_своей)} — "
          f"их пробует общий подсадчик `court_mutants`, и это не долг")
    return 0 if len(без_пробы) <= БЕЗ_ПРОБЫ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
