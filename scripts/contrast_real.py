#!/usr/bin/env python3
"""[ПРОТИВОПОСТАВЛЕНИЕ БЕЗ РАЗЛИЧИЯ] — страница, противопоставляющая две вещи, которые совпали.

    СТРАНИЦА, ГОВОРЯЩАЯ «А ПРОТИВ Б» ПРИ РАВНЫХ А И Б, ЛЖЁТ ДВАЖДЫ: она обещает различие,
    которого нет, и прячет то, что различия и не бывает.

ПОВОД, ПРОЖИТЫЙ 13.09. Дом места лица получил девятый язык — иврит, — и рамка потребовала
пары, у которой ОПРАВА РАЗНАЯ. Требование это указало на ложь, СТОЯВШУЮ В МИРЕ С ПЕРВОГО ДНЯ:

    «du läser» — ты читаешь, «han läser» — он читает. Корень «läser» ОДИН И ТОТ ЖЕ, меняется
    ОПРАВА: у первого — одно слово «läser», без головы и без хвоста; у второго — одно слово
    «läser», без головы и без хвоста.

Шесть страниц по-русски и шесть по-английски. Оправа не менялась ни в одной.

    ЯЗЫК, ВВЕДЁННЫЙ ДЕВЯТЫМ, ПРОВЕРЯЕТ ВОСЕМЬ ПРЕЖНИХ: он требует от рамки того, чего
    прежние восемь не требовали, — и находит в ней то, что стояло там с первого дня.

ЧТО СЧИТАЕТСЯ. Строка, несущая ОБЪЯВЛЕННЫЙ ПРИЁМ противопоставления, у которого обе стороны
совпали посимвольно. Приёмы объявлены здесь поимённо и взяты из свода, а не выдуманы:

    «А» против «Б»              35 строк      «А» against «Б»              35
    у первого — А; у второго — Б  29          for the first — А; ... Б     29
    «А», а не «Б»                21          «А», not «Б»                 21
    одно и то же слово «А» стои́т и при «Б», и при «В»   6 (равными обязаны быть Б и В)

    ПРИЁМ, НЕ ОБЪЯВЛЕННЫЙ ЗДЕСЬ, НЕ СУДИТСЯ ВОВСЕ, И ЭТО СКАЗАНО, А НЕ УМОЛЧАНО: прибор
    читает восемь приёмов, а не всякое противопоставление русской речи.

    python3 scripts/contrast_real.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --двор no-such-dir
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: СОВПАВШИХ_РУБЕЖ = 0
#
# РУБЕЖ НОЛЬ И ДОСТИГНУТ В ТОТ ЖЕ ЧАС: двенадцать найденных страниц сняты правкой дома —
# род, говорящий о перемене, стал брать пару, в которой перемена есть, а языку без неё этот
# род не пишется вовсе. Ноль тут есть ПОЛ: страница, обещавшая различие и его не давшая,
# роняет прибор в тот же день, когда её напишут.
СОВПАВШИХ_РУБЕЖ = 0

# ПРИЁМЫ ПРОТИВОПОСТАВЛЕНИЯ: (имя, образец, какие группы обязаны различаться).
ПРИЁМЫ = (
    ("против", re.compile(r"«([^»]+)» против «([^»]+)»"), (0, 1)),
    ("against", re.compile(r"«([^»]+)» against «([^»]+)»"), (0, 1)),
    ("первое и второе", re.compile(r"у первого — (.+?); у второго — (.+?)\."), (0, 1)),
    ("first and second", re.compile(r"for the first — (.+?); for the second — (.+?)\."), (0, 1)),
    ("а не", re.compile(r"«([^»]+)», а не «([^»]+)»"), (0, 1)),
    ("not", re.compile(r"«([^»]+)», not «([^»]+)»"), (0, 1)),
    ("и при, и при", re.compile(r"«([^»]+)» стои́т и при «([^»]+)», и при «([^»]+)»"), (1, 2)),
    ("both at and at", re.compile(r"«([^»]+)» stands both at «([^»]+)» and at «([^»]+)»"), (1, 2)),
)


def совпавшие(строки):
    """[(имя приёма, строка)] — противопоставления, у которых стороны совпали.

    Отделено от чтения свода, чтобы проба гоняла ТО САМОЕ место, которым прибор судит.
    """
    вон = []
    for с in строки:
        т = с.strip()
        if not т or "«" not in т and "—" not in т:
            continue
        for имя, образец, (a, b) in ПРИЁМЫ:
            for m in образец.finditer(т):
                г = m.groups()
                if г[a].strip() == г[b].strip():
                    вон.append((имя, т))
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что прибор ВИДИТ совпадение и НЕ ВИДИТ разницы.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ НУЛЯ НАХОДОК. Пусть образец перестанет совпадать — и
        противопоставлений не станет вовсе, а прибор скажет «совпавших 0», сверив НОЛЬ СТРОК.

    Четыре строки: два приёма с равными сторонами (обязаны найтись), два с разными (обязаны
    быть пропущены).
    """
    свод = (
        "у первого — одно слово «talar»; у второго — одно слово «talar».",
        "у первого — голова «ვ»; у второго — хвост «ენ».",
        "«látok» против «látok» — вот и вся разница.",
        "«látok» против «látom» — вот и вся разница.",
    )
    нашли = совпавшие(свод)
    беды = []
    if len(нашли) != 2:
        беды.append(f"совпавших найдено {len(нашли)}, а заведомо известно 2")
    имена = {и for и, _ in нашли}
    if "первое и второе" not in имена:
        беды.append("приём «первое и второе» с равными сторонами не найден")
    if "против" not in имена:
        беды.append("приём «против» с равными сторонами не найден")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ПРОТИВОПОСТАВЛЕНИЕ БЕЗ РАЗЛИЧИЯ ОТКАЗ: чтение приёма не доказано ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--двор", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    двор = pathlib.Path(дов.двор) if дов.двор else None
    if двор is not None and not двор.is_dir():
        print(f"ПРОТИВОПОСТАВЛЕНИЕ БЕЗ РАЗЛИЧИЯ ОТКАЗ: двора нет — {двор}")
        return 2
    import genesis
    счёт, примеры, строк = collections.Counter(), {}, 0
    for путь in genesis.worlds(kind="shows"):
        if двор is not None and путь.parent != двор:
            continue
        строки = путь.read_text(encoding="utf-8", errors="replace").split("\n")
        строк += len(строки)
        for имя, т in совпавшие(строки):
            счёт[(путь.stem, имя)] += 1
            примеры.setdefault((путь.stem, имя), т[:130])
    if not строк:
        print("ПРОТИВОПОСТАВЛЕНИЕ БЕЗ РАЗЛИЧИЯ ОТКАЗ: миров показов нет, читать нечего")
        return 2
    всего = sum(счёт.values())
    for (мир, имя), n in счёт.most_common(None if дов.подробно else 10):
        print(f"  {мир} [{имя}] ×{n}: {примеры[(мир, имя)]}")
    поза = "PASS" if всего <= СОВПАВШИХ_РУБЕЖ else "FAIL"
    print(f"ПРОТИВОПОСТАВЛЕНИЕ БЕЗ РАЗЛИЧИЯ {поза}: страниц, обещавших различие и не давших "
          f"его, {всего} (рубеж {СОВПАВШИХ_РУБЕЖ}); приёмов объявлено {len(ПРИЁМЫ)}; "
          f"строк прочитано {строк}")
    return 0 if всего <= СОВПАВШИХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
