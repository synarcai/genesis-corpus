#!/usr/bin/env python3
"""[ЧИСТОТА РЕГИСТРА] — не говорит ли НЕФОРМАЛЬНАЯ рамка вежливыми словами.

Долг вежливости уплачен 04.09, и в тот же час открылся долг обратный. Дом
обихода объявляет списки зачинов «неформальными», но русское извинение стоит в
них ТОЛЬКО вежливым: «извините», «простите», «прошу прощения», а «извини» и
«прости» нет во всём своде ни разу. То же у француза («excusez-moi» без
«excuse-moi»), у испанца («disculpe» без «disculpa»), у португальца.

СЛЕДСТВИЕ ХУЖЕ ПРОПУСКА, И ОНО СКРЫТО. Вежливый показ пишется, лишь если он
ОТЛИЧАЕТСЯ от неформального (двойник в корпусе хуже пустой клетки). Строка,
которая уже вежлива, замены не имеет, отличия не даёт — и потому решётка
регистра стоит ПОЛНОЙ там, где полон один регистр из двух. Прибор пары регистра
этого не видит: он сличает то, что написано, а здесь беда в том, чего не
написано. Нужен второй прибор, и он смотрит с другой стороны.

ПРИЗНАК ВЕЖЛИВОСТИ НЕ УГАДЫВАЕТСЯ, А ОБЪЯВЛЯЕТСЯ — И ПРОВЕРЯЕТСЯ ДЕЛОМ ДОМА.
Метки объявлены здесь по одной строке на язык, но ни одна не принята на веру:
всякая ПРАВАЯ сторона объявленной домом замены обязана нести метку, и ни одна
ЛЕВАЯ не смеет её нести. Метка, не прошедшая этой поверки, есть ошибка прибора,
и он падает на себе прежде, чем судить дома, — тот же закон, каким оракул
проверяет себя собой.

    python3 scripts/register_purity.py [--подробно]
"""
import argparse
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import register_pairs as П  # noqa: E402

# МЕТКИ ВЕЖЛИВОГО РЕГИСТРА — поверхностный знак второго обращения, и он есть НЕ
# ВЕЗДЕ. Прибор объявляет три состояния языка, а не два, ибо языки различают
# регистр тремя разными способами, и делать вид, что способ один, значило бы
# мерить свою мерку вместо корпуса:
#
#   ПОЛНАЯ метка (ru de fr nl pl) — вежливость видна СЛОВОМ: местоимением
#       («вы», «Sie», «vous», «u»), существительным обращения («pan») или
#       повелительным множественного («ответьте», «répondez»). Обе поверки
#       обязательны: правая сторона замены обязана нести метку, левая — не смеет.
#
#   НЕПОЛНАЯ метка (es it pt) — вежливость несёт ФОРМА ГЛАГОЛА третьего лица
#       («responda», «come sta?», «se chama»), неотличимая по поверхности от
#       третьего лица о ком-то третьем. Местоимение («usted», «Lei», «o senhor»)
#       стоит не во всякой строке. Прибор видит эти языки лишь местоимением и
#       ОБЪЯВЛЯЕТ свою слепоту: правая сторона без метки бедой не считается,
#       левая с меткой — считается по-прежнему.
#
#   РАЗЛИЧИЯ НЕТ (en) — «you» служит обоим регистрам (М-279).
#
# Слепота, названная прибором, есть его знание; слепота, не названная, есть
# ложный PASS. Потому третье состояние объявлено, а не выведено из пустоты.
МЕТКИ = {
    # второе лицо множественного метит и повелительное («скажите»), и
    # настоящее («поживаете», «умеете») — поверка собой поймала «как
    # поживаете?» правой стороной без метки, когда веер малого разговора
    # принёс первую вежливую форму настоящего времени
    "ru": (r"(?:йте|ите|ьте|ете|ёте)(?:сь)?\b", r"\bвы\b", r"\bвас\b", r"\bвам\b", r"\bваш"),
    "en": (),
    "de": (r"\bSie\b", r"\bIhnen\b", r"\bIhr(?:e|en|em)?\b"),
    "fr": (r"\bvous\b", r"\bvotre\b", r"\w{2,}ez(?:-|\b)"),
    "es": (r"\busted\b",),
    "it": (r"\bLei\b",),
    "pt": (r"\bo senhor\b",),
    "nl": (r"\bu\b", r"\buw\b", r"\balstublieft\b"),
    # «proszę» одно значит «пожалуйста» и «не за что» — метит не оно, а
    # ПОСТРОЕНИЕ «proszę + неопределённая форма», которым поляк велит вежливо.
    # Неопределённая форма кончается на «-ć» ИЛИ на «-c» («pomóc», «móc»), и
    # поверка собой поймала бы половину правил, будь объявлена одна буква.
    "pl": (r"\bpan(?:a|u|i|em)?\b", r"\bprosz[eę]\b[^.?!]*[cć]\b"),
}
# языки, чью вежливость прибор видит лишь местоимением (см. выше)
НЕПОЛНАЯ_МЕТКА = frozenset({"es", "it", "pt"})


def _метка(язык, строка):
    for узор in МЕТКИ.get(язык, ()):
        if re.search(узор, строка):
            return узор
    return None


def _поверка_меток():
    """Прибор падает на СЕБЕ прежде, чем судить дома.

    Условие двустороннее: правая сторона объявленной замены обязана нести
    метку, левая — не смеет. Односторонняя поверка пропустила бы метку,
    стоящую в обоих регистрах, а такая метка не метит ничего.
    """
    беды = []
    for имя, дом in П.дома_с_регистром():
        for поле in ("ВЕЖЛИВО", "ЗАМЕНЫ_ОБРАЩЕНИЯ"):
            таблица = getattr(дом, поле, None)
            if not isinstance(таблица, dict):
                continue
            for язык, пары in таблица.items():
                пары = пары.items() if isinstance(пары, dict) else пары
                for из, в in пары:
                    if not _метка(язык, в) and язык not in НЕПОЛНАЯ_МЕТКА:
                        беды.append((имя, язык, "правая без метки", в))
                    if _метка(язык, из):
                        беды.append((имя, язык, "левая с меткой", из))
    return беды


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    а = ап.parse_args()

    беды = _поверка_меток()
    if беды:
        for имя, язык, что, строка in беды[:10]:
            print(f"  МЕТКА НЕВЕРНА [{имя} {язык}] {что}: «{строка}»")
        print(f"ЧИСТОТА РЕГИСТРА FAIL: прибор не прошёл поверку собой — {len(беды)} меток")
        return 1

    print(f"{'дом':<18}{'неформ.':>9}{'ВЕЖЛИВЫХ':>10}{'из них с парой':>16}")
    всего = {"неформ": 0, "грязных": 0, "спасённых": 0}
    находки = []
    for имя, дом in П.дома_с_регистром():
        свои = {}
        for с, (я, ф) in дом.ПОКАЗЫ.items():
            свои.setdefault((я, str(ф)), []).append(с)
        н = г = с_парой = 0
        for (язык, форма), строки in sorted(свои.items()):
            if форма.endswith("_вы"):
                continue
            есть_вежливая = (язык, форма + "_вы") in свои
            for строка in строки:
                н += 1
                узор = _метка(язык, строка)
                if not узор:
                    continue
                г += 1
                if есть_вежливая:
                    с_парой += 1
                находки.append((имя, язык, форма, строка, узор, есть_вежливая))
        print(f"{имя:<18}{н:>9}{г:>10}{с_парой:>16}")
        всего["неформ"] += н
        всего["грязных"] += г
        всего["спасённых"] += с_парой
    print(f"{'ИТОГО':<18}{всего['неформ']:>9}{всего['грязных']:>10}{всего['спасённых']:>16}")

    видел = set()
    for имя, язык, форма, строка, узор, пара in находки:
        ключ = (имя, язык, форма)
        if ключ in видел and not а.подробно:
            continue
        видел.add(ключ)
        знак = "есть вежливая пара" if пара else "ВЕЖЛИВОЙ ПАРЫ НЕТ"
        print(f"  [{язык} {имя}.{форма}] «{строка[:70]}» ← {узор} ({знак})")
    доля = 100 * всего["грязных"] // всего["неформ"] if всего["неформ"] else 0
    полно = sorted(я for я, м in МЕТКИ.items() if м and я not in НЕПОЛНАЯ_МЕТКА)
    print(f"  ВИДИТ ПОЛНО: {' '.join(полно)}; лишь местоимением: "
          f"{' '.join(sorted(НЕПОЛНАЯ_МЕТКА))}; различия не имеет: "
          f"{' '.join(sorted(я for я, м in МЕТКИ.items() if not м))}")
    print(f"ЧИСТОТА РЕГИСТРА: неформальных показов {всего['неформ']}, "
          f"говорящих вежливо {всего['грязных']} ({доля} %), "
          f"из них имеющих и вежливую пару {всего['спасённых']}; "
          f"мест {len(видел)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
