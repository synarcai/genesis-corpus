#!/usr/bin/env python3
"""[МИР НЕИЗМЕНЕН] — подпись мира до правки против подписи после.

Есть род правки, вся суть которой в том, что мир НЕ ШЕВЕЛЬНЁТСЯ. Перебор страниц переезжает
из кузницы в дом; помощник переселяется в другой файл; тридцать вызовов сводятся к одной
двери. Такая правка честна ровно настолько, насколько байты на диске остались прежними, —
и нечестна вся целиком, если сдвинулся хоть один.

    ПРАВКА, ОБЪЯВЛЕННАЯ НЕВИДИМОЙ, ПРОВЕРЯЕТСЯ НЕ ЧТЕНИЕМ ДИФФА, А ПОДПИСЬЮ МИРА.

ПОВОД (13.09). Восемь домов узнали свои страницы: `holes`, `action_pages`, `joints`,
`relations_story`, `genus_diff`, `shares_percent`, `search_langs`, `measure_story`. Каждый
переезд проверялся `cmp` рукой, и трижды `cmp` поймал поломку — забытый помощник, невезённый
ввоз, число, переписанное по памяти. Но ЛИСТ ПОСАДКИ нёс это утверждение заголовком, а
проверял его человек накануне.

    УТВЕРЖДЕНИЕ, КОТОРОЕ ПРОВЕРЯЕТ ПАМЯТЬ, А НЕ ПРИБОР, ПЕРЕЖИВЁТ ДЕНЬ, КОГДА ОНО
    ПЕРЕСТАНЕТ БЫТЬ ВЕРНЫМ.

ПРИБОР НЕ ЗНАЕТ, КАКИЕ МИРЫ ОБЯЗАНЫ БЫТЬ ПРЕЖНИМИ, и не должен: список даёт тот, кто делает
переезд, и даёт ПОИМЁННО. Мера, сама решающая, что считать неизменным, объявила бы прежними
и те миры, о которых никто не обещал.

ТРИ ИСХОДА, И ВСЕ ТРИ ГРОМКИЕ:

    сошлись — PASS с числом миров;
    разошлись — FAIL с именем мира и обеими подписями, а не одним словом «разошлось»;
    мира нет — ОТКАЗ, а не тихий пропуск. Мир, которого нет до переезда, не может быть
    «прежним»; молчаливый пропуск обратил бы отсутствие в успех.

    ПРОПУСК, О КОТОРОМ НЕ СКАЗАНО, ЕСТЬ ЛОЖЬ О ПОЛНОТЕ.

ПОДПИСЬ ЛОЖИТСЯ ВНЕ ДЕРЕВА. Прибор, кладущий свой след в корпус, двигает дерево под набором,
и ближайший указатель упадёт от его следа, а не от правки. Путь подписи объявляется рукой.

    python3 scripts/worlds_unchanged.py --снять holes joints --подпись /tmp/восемь.sha
    python3 scripts/worlds_unchanged.py --сверить --подпись /tmp/восемь.sha
"""
# ПУСТОЙ-ОБХОД: --снять --подпись /dev/null
import argparse
import hashlib
import pathlib
import sys

МИРЫ = pathlib.Path("datasets")
ИМЯ_МИРА = "genesis_{}.txt"
РАЗОШЛОСЬ_РУБЕЖ = 0
ПОДПИСЬ_ДО = 16          # сколько знаков подписи показывать читателю


def подпись(имя, корень=None):
    """(подпись, метка времени) мира; None, если мира нет."""
    п = (корень or МИРЫ) / ИМЯ_МИРА.format(имя)
    if not п.is_file():
        return None
    h = hashlib.sha256()
    with п.open("rb") as ф:
        for кусок in iter(lambda: ф.read(1 << 20), b""):
            h.update(кусок)
    return h.hexdigest(), п.stat().st_mtime_ns


def _самопроверка():
    """Подпись обязана меняться от одного байта и молчать об отсутствии.

    Мера, чья подпись не дрогнет от правки, пропустит ровно ту правку, ради которой
    заведена, — и объявит переезд невидимым, когда он всё сдвинул.
    """
    a = hashlib.sha256("мир".encode("utf-8")).hexdigest()
    b = hashlib.sha256("миР".encode("utf-8")).hexdigest()
    assert a != b, "ПОДПИСЬ НЕ ДРОГНУЛА ОТ ПРАВКИ — мерить ею нечего"
    assert len(a) == 64, "подпись не sha256"


_самопроверка()


def снять(имена, куда, корень=None):
    строки, нет = [], []
    for имя in имена:
        п = подпись(имя, корень)
        if п is None:
            нет.append(имя)
        else:
            строки.append(f"{имя}\t{п[0]}\t{п[1]}")
    if нет:
        # ОТКАЗ, А НЕ ПРОПУСК: см. заголовок.
        print(f"ОТКАЗ СНЯТЬ: {len(нет)} миров нет до правки — "
              f"{', '.join(sorted(нет))}", file=sys.stderr)
        return 2
    куда.parent.mkdir(parents=True, exist_ok=True)
    куда.write_text("\n".join(строки) + "\n", encoding="utf-8")
    print(f"ПОДПИСЬ СНЯТА: {len(строки)} миров до правки → {куда}")
    return 0


def сверить(откуда, корень=None):
    if not откуда.is_file() or not откуда.read_text(encoding="utf-8").strip():
        print(f"ОТКАЗ СВЕРИТЬ: подпись не снята ({откуда})", file=sys.stderr)
        return 2
    сошлись, разошлись, пропали, немые = 0, [], [], []
    for строка in откуда.read_text(encoding="utf-8").splitlines():
        if not строка.strip():
            continue
        части = строка.split("\t")
        имя, было = части[0], части[1]
        когда = int(части[2]) if len(части) > 2 else None
        стало = подпись(имя, корень)
        if стало is None:
            пропали.append(имя)
            continue
        цифры, теперь = стало
        # МИР, КОТОРОГО НЕ ПЕРЕКОВАЛИ, СОШЁЛСЯ БЫ САМ С СОБОЙ. Кузница, павшая на воротах,
        # не пишет файла вовсе — и подпись, глядящая ОДНИ БАЙТЫ, зеленеет от бездействия.
        # Пойман этот случай 13.09 на четырёх мирах разом: две кузницы пали, четыре мира
        # объявились «байт в байт прежними», и это была правда о байтах и ложь о работе.
        #
        #     ПОДПИСЬ, СВЕРЕННАЯ БЕЗ ДОКАЗАТЕЛЬСТВА, ЧТО КУЗНИЦА РАБОТАЛА, ЗЕЛЕНЕЕТ ОТ
        #     БЕЗДЕЙСТВИЯ. Доказательство здесь — метка времени: перековка трогает файл,
        #     даже когда байты в нём те же.
        if когда is not None and теперь == когда:
            немые.append(имя)
        elif цифры == было:
            сошлись += 1
        else:
            разошлись.append((имя, было, цифры))
    for имя, было, стало in разошлись:
        print(f"  РАЗОШЁЛСЯ {имя}: было {было[:ПОДПИСЬ_ДО]}…, стало {стало[:ПОДПИСЬ_ДО]}…")
    for имя in пропали:
        print(f"  ПРОПАЛ {имя}: подпись снята, а мира на диске нет")
    for имя in немые:
        print(f"  НЕ ПЕРЕКОВАН {имя}: файл не тронут с той поры, как снята подпись, — "
              f"кузница не работала, и «байт в байт» тут о бездействии")
    беда = len(разошлись) + len(пропали) + len(немые)
    поза = "PASS" if беда <= РАЗОШЛОСЬ_РУБЕЖ else "FAIL"
    print(f"МИР НЕИЗМЕНЕН {поза}: {сошлись} миров перекованы и байт в байт прежние, "
          f"разошлось {len(разошлись)}, пропало {len(пропали)}, "
          f"не перековано {len(немые)} (рубеж {РАЗОШЛОСЬ_РУБЕЖ})")
    return 0 if поза == "PASS" else 1


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: пять случаев порознь, ибо это пять разных вин.

    Прибор, зеленеющий от нуля находок, обязан доказать, что умеет находить. Пятый случай
    добавлен 13.09, когда прибор сказал PASS о четырёх мирах, две кузницы которых ПАЛИ:
    байты не двигались оттого, что их никто не писал.
    """
    import contextlib, io, tempfile                       # noqa: PLC0415,E401
    # ГОЛОС ПРОБЫ ГЛУШИТСЯ, А НЕ ЕЁ ВЕРДИКТ: она нарочно роняет прибор четырежды.
    #
    #     ПРОБА, КРИЧАЩАЯ ЧУЖИМ ГОЛОСОМ, УЧИТ ЧИТАТЕЛЯ НЕ ВЕРИТЬ ЛОГУ.
    беды = []
    тихо = contextlib.redirect_stdout(io.StringIO())
    тихо_же = contextlib.redirect_stderr(io.StringIO())
    with tempfile.TemporaryDirectory() as д, тихо, тихо_же:
        д = pathlib.Path(д)

        def перековать(имя, тело):
            """Кузница, отдавшая тот же текст: файл ТРОНУТ, байты те же."""
            (д / ИМЯ_МИРА.format(имя)).write_text(тело, encoding="utf-8")

        перековать("а", "мир а\n")
        перековать("б", "мир б\n")
        знак = д / "подпись.sha"
        if снять(["а", "б"], знак, д) != 0:
            беды.append("подпись не снялась с двух целых миров")
        перековать("а", "мир а\n")
        перековать("б", "мир б\n")
        if сверить(знак, д) != 0:
            беды.append("перекованные и не сдвинувшиеся миры объявлены разошедшимися")

        перековать("а", "мир а\n")
        перековать("б", "мир б ИНОЙ\n")
        if сверить(знак, д) == 0:
            беды.append("ПОДСАДКА НЕ ПОЙМАНА: мир шевельнулся, а прибор смолчал")

        (д / ИМЯ_МИРА.format("а")).unlink()
        if сверить(знак, д) == 0:
            беды.append("ПРОПАЖА НЕ ПОЙМАНА: мира нет, а прибор смолчал")

        if снять(["а", "б"], д / "второй.sha", д) != 2:
            беды.append("ОТКАЗА НЕТ: мира нет до снятия, а прибор снял подпись")

        # БЕЗДЕЙСТВИЕ: мир цел, подпись снята, кузница НЕ РАБОТАЛА.
        перековать("в", "мир в\n")
        знак3 = д / "третий.sha"
        снять(["в"], знак3, д)
        if сверить(знак3, д) == 0:
            беды.append("БЕЗДЕЙСТВИЕ НЕ ПОЙМАНО: мир не перекован, а прибор сказал PASS")
    return беды


def main():
    р = argparse.ArgumentParser(description="подпись мира до правки против подписи после")
    р.add_argument("--снять", nargs="*", metavar="МИР",
                   help="имена миров без «genesis_» и «.txt»")
    р.add_argument("--сверить", action="store_true")
    р.add_argument("--подпись", type=pathlib.Path)
    р.add_argument("--проба", action="store_true")
    дов = р.parse_args()
    if дов.проба:
        беды = _проба()
        for б in беды:
            print(f"  {б}")
        print(f"МИР НЕИЗМЕНЕН {'PASS' if not беды else 'FAIL'}: проба на заведомо известном, "
              f"бед {len(беды)} (рубеж 0)")
        return 0 if not беды else 1
    if дов.подпись is None:
        print("нужно --подпись ФАЙЛ", file=sys.stderr)
        return 2
    if дов.сверить:
        return сверить(дов.подпись)
    if дов.снять is None:
        print("нужно --снять МИР… или --сверить", file=sys.stderr)
        return 2
    if not дов.снять:
        # ПУСТОЙ ОБХОД НЕ ЕСТЬ УСПЕХ, НО И НЕ ЕСТЬ ПАДЕНИЕ: сказать и уйти нулём.
        print("ПОДПИСЬ СНЯТА: 0 миров (список пуст)")
        return 0
    return снять(дов.снять, дов.подпись)


if __name__ == "__main__":
    sys.exit(main())
