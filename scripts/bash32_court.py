#!/usr/bin/env python3
"""[СУД BASH 3.2] — кириллица в скрипте обязана стоять там, где
bash 3.2 не примет её за ИМЯ.

ЗАКОН: `/bin/bash` на macOS — версия 3.2 (2007), и вне UTF-8-локали
она считает ВСЯКИЙ байт ≥ 0x80 законной буквой идентификатора. Из
этого следуют ровно два дефекта, и оба падают НЕ ТАМ, где написаны:

  1. ПРИСВОЕНИЕ КИРИЛЛИЧЕСКОМУ ИМЕНИ.  `ДОМ=/tmp/x` разбирается не
     как присвоение, а как ЗОВ КОМАНДЫ `ДОМ=/tmp/x`, и скрипт
     падает строкой «command not found» — с указанием на строку,
     где имя лишь ЧИТАЕТСЯ, а не на ту, где оно заведено.

  2. КИРИЛЛИЦА ВПЛОТНУЮ ЗА `$имя`.  В `«$name»` закрывающая ёлочка
     ПРИКЛЕИВАЕТСЯ К ИМЕНИ: bash ищет переменную `name»`, и под
     `set -u` скрипт умирает «unbound variable» на строке, где имя
     написано ПРАВИЛЬНО. Лечится скобками: `«${name}»`.

ПОВОД. Род всплывал ТРИЖДЫ в трёх приборах (`guards.sh`,
`full_v8_court.sh`, `heavy_lock.sh`), и каждый раз его находили
руками — по загадочному «command not found» на исправной строке.
Четвёртый раз родился в тот же час: тяжёлый лок, переписанный на
латинские имена, пал на `«$name»` — ТО ЖЕ ПРАВИЛО, ДРУГОЕ ЛИЦО.
Шрам, найденный руками трижды, есть не невезение, а отсутствие
прибора.

ПОЧЕМУ СТРАЖ, А НЕ ЛЕНТА: оба дефекта — не вкус и не порог. Скрипт
с ними НЕ РАБОТАЕТ; счёт может быть только нулём.

  3. КИРИЛЛИЦА В ФИГУРНОЙ ПОДСТАНОВКЕ.  `${ВОЗРАСТ}` есть не имя,
     а «bad substitution»: bash умирает НА ЭТОЙ СТРОКЕ И ТОЛЬКО
     НА НЕЙ.

     ЭТОТ РОД СУД ОБЪЯВЛЯЛ НЕСУДИМЫМ — И ОБЪЯВЛЯЛ ЛОЖНО. Стояло
     здесь: «под `set -u` они падают немедленно и громко». Это была
     ДОГАДКА, а не замер, и она стоила своего дня: правка точки
     (`point.sh`, 09.09) несла `${ВОЗРАСТ}` в предпоследней строке
     тринадцатиминутного прогона, `set -u` там нет вовсе, `bash -n`
     подстановок не разбирает — и упала бы она НА ТРИНАДЦАТОЙ
     МИНУТЕ, после всей работы. Нашли её глазами, при чтении диффа.

         «ПАДАЕТ ГРОМКО» ЕСТЬ УТВЕРЖДЕНИЕ О МИРЕ, И ОНО ПРОВЕРЯЕТСЯ.
         СУД, ОБЪЯВИВШИЙ ЧТО-ТО НЕСУДИМЫМ ПО ДОГАДКЕ, ЕСТЬ ДЫРА С
         ОБЪЯСНЕНИЕМ.

     Имя берётся ДО первого оператора подстановки: `${VERDICT:-НЕТ}`
     законно — кириллица там есть ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ, а не имя.

ЧЕГО ПРИБОР НЕ ВИДИТ, НАЗВАНО ЧЕСТНО:
  · кириллица в комментариях, строках и heredoc-телах законна и
    здесь не разбирается — вычесть их нельзя, не разобрав bash
    целиком, поэтому суд смотрит лишь ТРИ РОДА ФОРМ, чей вид
    однозначен вне зависимости от того, где они стоят (замер на
    шести скриптах парка: ложных обвинений ноль);
  · `имя()` как функция и `for имя in` он не судит: обе формы
    падают на РАЗБОРЕ, то есть на первой же строке `bash -n`, и
    прибор для них есть — сам bash.

Использование:
  python3 scripts/bash32_court.py [каталог парка]
"""
# ПУСТОЙ-ОБХОД: no-such-park-dir
import re
import sys
from pathlib import Path

# Присвоение имени, в котором есть неASCII-байт, в начале команды.
ПРИСВОЕНИЕ = re.compile(
    r"(?:^|[;&|]\s*|\bthen\s+|\belse\s+|\bdo\s+)"
    r"([A-Za-z_0-9]*[^\x00-\x7f][^\s=]*)=",
    re.M,
)
# `$имя`, за которым ВПЛОТНУЮ идёт неASCII: байт уходит в имя.
ПРИЛИПАНИЕ = re.compile(r"\$([A-Za-z_][A-Za-z_0-9]*)(?=[^\x00-\x7f])")
# `${...}`: нутро подстановки целиком; имя из него вырезается отдельно.
ФИГУРНАЯ = re.compile(r"\$\{!?#?([^{}]*)\}")
# Знаки, за которыми в `${...}` кончается ИМЯ и начинается действие над ним.
ОПЕРАТОРЫ = frozenset(":-+?=#%/^,@*[!")


def имя_подстановки(нутро: str) -> str:
    """Имя из нутра `${...}` — всё до первого оператора подстановки."""
    for н, з in enumerate(нутро):
        if з in ОПЕРАТОРЫ:
            return нутро[:н]
    return нутро


def находки(текст: str) -> list[str]:
    """Оба рода, каждый со своим лечением."""
    вон = []
    for m in ПРИСВОЕНИЕ.finditer(текст):
        строка = текст.count("\n", 0, m.start()) + 1
        вон.append(f"стр.{строка}: присвоение имени «{m.group(1)}» — "
                   f"перепишите латиницей")
    for m in ПРИЛИПАНИЕ.finditer(текст):
        строка = текст.count("\n", 0, m.start()) + 1
        вон.append(f"стр.{строка}: $" + m.group(1) + " вплотную к кириллице — "
                   "напишите ${" + m.group(1) + "}")
    for m in ФИГУРНАЯ.finditer(текст):
        имя = имя_подстановки(m.group(1))
        if not имя or all(з < "\x80" for з in имя):
            continue
        строка = текст.count("\n", 0, m.start()) + 1
        вон.append(f"стр.{строка}: подстановка «${{{имя}}}» — bash 3.2 скажет "
                   f"«bad substitution»; перепишите имя латиницей")
    return вон


def main() -> int:
    argv = sys.argv[1:]
    парк = Path(argv[0]) if argv else Path(__file__).resolve().parent
    if not парк.is_dir():
        print(f"bash32_court: нет каталога парка {парк} — ОТКАЗ", file=sys.stderr)
        return 2
    файлы = sorted(парк.glob("*.sh"))
    if not файлы:
        print(f"bash32_court: ни одного .sh в {парк} — ОТКАЗ", file=sys.stderr)
        return 2

    всего, битые = 0, []
    for f in файлы:
        вон = находки(f.read_text(encoding="utf-8", errors="replace"))
        всего += len(вон)
        if вон:
            битые.append((f.name, вон))

    print("СУД BASH 3.2")
    print(f"  скриптов:   {len(файлы)}")
    print(f"  нарушений:  {всего}")
    for имя, вон in битые:
        for в in вон:
            print(f"  {имя:<22} {в}")
    if всего:
        print("\nBASH32-COURT FAIL: скрипт НЕ РАБОТАЕТ на /bin/bash macOS")
        return 1
    # ОБЪЁМ В ВЕРДИКТЕ: «ни одного» есть правда о списке и ложь о мире, пока не
    # сказано, из скольких (закон holon; прибор ЧИСЛО БЕЗ ЗНАМЕНАТЕЛЯ нашёл эту
    # строку единственной голой среди 99 приборов леджера)
    print(f"\nBASH32-COURT PASS: ни одного имени, съедаемого bash 3.2; скриптов проверено: {len(файлы)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
