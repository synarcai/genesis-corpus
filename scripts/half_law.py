#!/usr/bin/env python3
"""[ПОЛОВИНЧАТЫЙ ЗАКОН] — место, где дом пишет множественное ЛИТЕРАЛОМ рядом с числом.

    ДОМ, ЗНАЮЩИЙ ЗАКОН СОГЛАСОВАНИЯ НА ОДНОМ ЯЗЫКЕ И ПИШУЩИЙ ЛИТЕРАЛОМ НА ДРУГОМ, НЕ ЗАБЫЛ
    ЗАКОН — ОН ОБЪЯВИЛ ОДИН ЯЗЫК ВТОРОСОРТНЫМ.

ЗА НОЧЬ 07–08.09 ЭТО НАЙДЕНО В ЧЕТЫРЁХ ДОМАХ ПОДРЯД — физика, кибернетика, статистика, законы
физики. Во всех четырёх русская сторона звала закон формы (`rugram.форма`), английская держала
литерал множественного, и правота английской держалась НЕ ЗАКОНОМ, А ЖРЕБИЕМ: числа домов
подобраны так, что единица не выпадала.

    ПРАВОТА, ДЕРЖАЩАЯСЯ НА ТОМ, ЧТО ЖРЕБИЙ НЕ ДАЛ ЕДИНИЦЫ, НЕ ЕСТЬ ПРАВОТА — ОНА НЕ ПРОВЕРЕНА.

Четыре дома подряд суть уже не оплошность писца, а ПРИВЫЧКА СВОДА, и прибор считает её место
за местом, чтобы следующая единица не искала их поодиночке.

ЧТО СЧИТАЕТСЯ. Место — это объявленное МНОЖЕСТВЕННОЕ имя (`en.json → noun_forms`), стоящее в
f-строке дома сразу за дырой. Дома делятся надвое:

    БЕЗЗАКОННЫЕ — те, где `by_count` не зовётся НИ РАЗУ. Имя это об АНГЛИЙСКОМ законе:
                  дом может звать `rugram.форма` для русской стороны и всё же не знать
                  `by_count` для английской — таков, например, дом ставок, и это ровно тот
                  случай, ради которого прибор поставлен;
    ПОЛОВИНЧАТЫЕ — те, где закон зовётся, но местами всё же стои́т литерал.

    МЕРА СЧИТАЕТ ВОЗМОЖНОСТЬ ЛЖИ, А НЕ ЛОЖЬ. Ни одно из этих мест не лжёт СЕГОДНЯ — в своде
    нет ни «1 things», ни «1 pupils». Она считает то, что солжёт в день, когда число станет
    единицей, — и потому её число есть мера ХРУПКОСТИ, а не порчи.

    И НЕ ВСЯКОЕ ЕЁ МЕСТО ПОДЛЕЖИТ ПРАВКЕ (08.09, куплено ошибкой): «{квантор} students» есть
    имя после КВАНТОРА, и оно стои́т во множественном, каково бы ни было число. Правка законом
    дала «some student have a key» при одном ученике; сличение с прежним миром это поймало, а
    ворота бы пропустили.

        НЕ ВСЯКОЕ ИМЯ РЯДОМ С ЧИСЛОМ ЕСТЬ ИМЯ СЧЁТНОЕ. Мера называет МЕСТА, где закон МОЖЕТ
        понадобиться, и не берётся решать за глаз, где он нужен.

    python3 scripts/half_law.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --дома no-such-dir
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: БЕЗЗАКОННЫХ_РУБЕЖ = 15
#
# РУБЕЖ ОБЪЯВЛЕН ПО ДОСТИГНУТОМУ: восемнадцать домов в час постановки, семнадцать через
# четверть часа (дом быта получил закон в двадцати двух местах), шестнадцать — когда из
# счёта вышли СТРОКИ ОТЧЁТА, которых читатель не видит, пятнадцать — когда закон получил дом
# ставок (мир и там не изменился ни на байт).
#
# ЧАСТЬ ОСТАВШИХСЯ МЕСТ БЕЗОПАСНА ПО ПОСТРОЕНИЮ, И ЭТО СКАЗАНО, ЧТОБЫ СЛЕДУЮЩАЯ РУКА НЕ ЧИНИЛА
# ЦЕЛОГО. Дом календаря держит «{ДЛИНЫ[i]} days» — длину месяца, которая не бывает единицей, — а
# там, где у него единица ВОЗМОЖНА («1 days after»), закон уже стои́т, и в самом доме записано,
# что суд согласования поймал эту ошибку в тот же прогон. Дома повестей (`relstory`,
# `moneystory`) держат литерал в ОБРАЗЦАХ, а не в счёте, и правка их есть правка образцов —
# работа иного рода., и мир не изменился ни на
# байт (сличено), ибо единица туда не выпадала. Это ПОТОЛОК: цена снятия — один вызов закона на место, и четыре дома за ночь
# показали, что цена эта в самом деле мала (правка каждого не изменила ни байта свода, покуда
# в ряд не внесли единицу).
БЕЗЗАКОННЫХ_РУБЕЖ = 5

# ОМОГРАФ ВНУТРИ ОДНОГО ЯЗЫКА (08.09): слово, которое пакет объявляет МНОЖЕСТВЕННЫМ ИМЕНЕМ, а
# дом пишет ГЛАГОЛОМ. «{a} leaves remainder 0 when divided by {b}» — «оставляет остаток», и при
# единице там ВЕРНО стои́т «1 leaves», ибо у глагола «-s» при единице, а у имени — при многих
# (тот же закон, каким `scripts/unknown_name.py` отделяет give/gives от boy/boys). Прибор брал
# это место за литерал имени и обвинял дом напрасно.
#
#     СТАТИЧЕСКИ ОТЛИЧИТЬ НЕЛЬЗЯ, И СВОД НЕ ПОМОГАЕТ: обе жизни слова живут в своде — «26 leaves
#     remainder 4» (глагол) и «i count 6 leaves» (имя); а «1 leaves» не встречается ни разу, ибо
#     дом опроса никогда не делит единицу. Оттого место названо ПОИМЁННО, домом и словом.
#
# И ЗДЕСЬ ЖЕ НАЗВАН ДОЛГ, КОТОРЫЙ НЕ ЗАКРЫТ: пакет объявляет «leaf → leaves», и суд английского
# числа (`courts/engram_court.py`) читает «26 leaves» как имя — верно лишь по жребию, ибо при
# многих обе формы совпадают. Пусть дом опроса однажды разделит единицу — и суд назовёт ЛОЖЬЮ
# истинную строку «1 leaves remainder 0». То же, что польское «ruble» под английским судом,
# только омограф здесь СВОЙ, а не чужого языка.
ГЛАГОЛЫ_ОМОГРАФЫ = frozenset({
    # «оставляет остаток» — дом опроса и дом метаязыка пишут один оборот
    ("gen_genesis_inquiry", "leaves"),
    ("gen_genesis_metalang", "leaves"),
    # «раскладывается на множители»: «x^2 − 4x = 0 factors as ( x )( x − 4 )». Здесь дыра перед
    # словом держит не число, а УРАВНЕНИЕ, — и это, пожалуй, вернейший признак глагола в
    # образце. Признак не взят законом лишь потому, что содержимое дыры статически не разобрать:
    # прибор видит имя переменной, а не её род.
    ("gen_genesis_equation", "factors"),
})

# СЛОВО УМНОЖЕНИЯ НЕ ЕСТЬ СЧЁТНОЕ ИМЯ (08.09). Объявив «time → times» в пакете ради суда числа,
# я тем самым научил ЭТОТ прибор видеть «times» в домах — и он обвинил три дома разом. Но там
# «times» есть ЗНАК УМНОЖЕНИЯ, читанный словом: «{A} times {B} is {C}», «{a} is three times more
# than {b}». Закон счёта туда не идёт вовсе: по-английски при единице говорят не «1 time as many»,
# а «as many», при двух — «twice», и дом умножения это уже знает («twice» if k == 2).
#
#     ЗА СЛОВОМ УМНОЖЕНИЯ ИДЁТ ВТОРОЙ МНОЖИТЕЛЬ ИЛИ СРАВНЕНИЕ, ЗА СЧЁТНЫМ ИМЕНЕМ — ГРАНИЦА.
#     Оттого признак берётся не списком домов, а СЛЕДУЮЩИМ СЛОВОМ образца.
#
# Прибор остаётся зряч на счётное «times»: «применённое 3 раза» / «applied 3 times» в доме
# compsci пишет форму условием прямо в шве строк, и бареное «{n} times.» с границей за ним
# прибор поймает по-прежнему.
УМНОЖЕНИЕ = {"times"}
СЛЕД_УМНОЖЕНИЯ = ("{", "more", "as", "greater", "larger", "bigger", "smaller", "less", "fewer")

# Дыра, за которой сразу стои́т слово: «{n} things», «{сколько} pupils»
ЛИТЕРАЛ = re.compile(r"\{[^{}]{1,40}\}\s+([a-z][a-z ]{1,24}?)(?=[\s.,;:!?\"'}])")


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--дома", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    папка = pathlib.Path(дов.дома) if дов.дома else КОРЕНЬ / "tools"
    пакет = КОРЕНЬ / "tools" / "langpacks" / "en.json"
    if not папка.is_dir() or not пакет.is_file():
        print(f"ПОЛОВИНЧАТЫЙ ЗАКОН ОТКАЗ: нет домов в «{папка}»")
        return 2
    мн = {м.lower() for м in (json.loads(пакет.read_text(encoding="utf-8"))
                              .get("noun_forms") or {}).values()}
    места = collections.Counter()
    знает = {}
    примеры = collections.defaultdict(list)
    for путь in sorted(папка.glob("*.py")):
        текст = путь.read_text(encoding="utf-8", errors="replace")
        знает[путь.stem] = "by_count" in текст
        for м in ЛИТЕРАЛ.finditer(текст):
            слово = м.group(1).strip()
            # СТРОКА ОТЧЁТА НЕ ЕСТЬ СТРАНИЦА СВОДА (08.09). «written … {n} lines» печатается
            # ковкой в лог и читателю не показывается никогда; править её законом значило бы
            # чинить то, чего никто не читает.
            начало = текст.rfind("\n", 0, м.start()) + 1
            строка_кода = текст[начало:текст.find("\n", м.start())]
            # …И ПРОДОЛЖЕНИЕ СТРОКИ ОТЧЁТА ЕСТЬ ТА ЖЕ СТРОКА ОТЧЁТА (08.09). Правило смотрело
            # лишь на ФИЗИЧЕСКУЮ строку кода — и второй строкой того же `print(...)` дом полного
            # свода был назван беззаконным дважды: «{…} lines, {…} worlds» печатается ковкой в
            # лог и читателю не показывается никогда. Ныне проверяется ЛОГИЧЕСКАЯ строка: открыт
            # ли зов печати скобкой к тому месту, где стои́т литерал.
            хвост = текст[max(0, начало - 400):м.start()]
            зов = хвост.rfind("print(")
            в_отчёте = (зов != -1
                        and хвост[зов:].count("(") > хвост[зов:].count(")"))
            # …И СЛОВО ПРОВЕРКИ — ТОЖЕ НЕ СТРАНИЦА (08.09). «assert поз − 1 == всего, f"index
            # {…} ≠ file {…} lines"» есть ГОЛОС ПРИБОРА САМОМУ СЕБЕ: он звучит лишь тогда, когда
            # дом сломан, и в свод не идёт никогда. Три рода строк кода несут литерал, не будучи
            # страницей, — печать, продолжение печати и слово проверки; все три названы.
            голос_прибора = строка_кода.lstrip().startswith(("assert ", "raise ", "#"))
            if в_отчёте or "print(" in строка_кода or голос_прибора:
                continue
            if слово in УМНОЖЕНИЕ:
                хвост = текст[м.end():м.end() + 24].lstrip()
                if хвост.startswith(СЛЕД_УМНОЖЕНИЯ):
                    continue    # знак умножения, читанный словом, а не счётное имя
            if (путь.stem, слово) in ГЛАГОЛЫ_ОМОГРАФЫ:
                continue        # объявленное имя, писанное глаголом
            if слово in мн:
                места[путь.stem] += 1
                if len(примеры[путь.stem]) < 3:
                    примеры[путь.stem].append(слово)
    беззаконные = [(д, n) for д, n in места.most_common() if not знает.get(д)]
    половинчатые = [(д, n) for д, n in места.most_common() if знает.get(д)]
    сколько_б = sum(n for _д, n in беззаконные)
    сколько_п = sum(n for _д, n in половинчатые)
    print(f"{'дом':<30}{'мест':>6}  слова")
    for д, n in (беззаконные if дов.подробно else беззаконные[:8]):
        print(f"{д:<30}{n:>6}  {', '.join(примеры[д])}   ← английского закона не знает")
    for д, n in (половинчатые if дов.подробно else половинчатые[:6]):
        print(f"{д:<30}{n:>6}  {', '.join(примеры[д])}")
    поза = "PASS" if len(беззаконные) <= БЕЗЗАКОННЫХ_РУБЕЖ else "FAIL"
    print(f"ПОЛОВИНЧАТЫЙ ЗАКОН {поза}: домов с литеральным множественным {len(места)}; "
          f"БЕЗЗАКОННЫХ {len(беззаконные)} (рубеж {БЕЗЗАКОННЫХ_РУБЕЖ}, мест {сколько_б}); "
          f"половинчатых {len(половинчатые)} (мест {сколько_п})")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
