#!/usr/bin/env python3
"""[СЛОВО ТОЛЬКО В ОТКАЗЕ] — слово, которое свод показывает лишь внутри отвергнутой строки.

    СЛОВО, ПОКАЗАННОЕ ТОЛЬКО ВНУТРИ ОТКАЗА, ВЫУЧИВАЕТСЯ КАК ЧАСТЬ ОШИБКИ. Читатель встречает
    его один раз — и ровно там, где сказано «так не говорят».

ПОВОД, ПРОЖИТЫЙ 13.09. Тайский пласт отвергает «*ผมเห็นแก้วสองเล่ม» — счётное слово книг при
стакане — и «*ผมเห็นหนังสือสองตัว» — счётное животных при книге. Я взялся строить пятый дом
разряда и остановился: во всём своде тайское «เล่ม» и «ตัว» стоя́т ТОЛЬКО в этих отказах.
Дом, объявивший их таблицей, объявил бы то, чего свод не показывает.

    ДОМ БЕРЁТ ЛИШЬ ТЕ ФОРМЫ, ЧТО СТОЯ́Т В ПЛАСТЕ, — И ОТТОГО ОТКАЗ, ВВОДЯЩИЙ СЛОВО ВПЕРВЫЕ И
    ЕДИНСТВЕННЫЙ РАЗ, ЗАКРЫВАЕТ ДОРОГУ ДОМУ, КОТОРЫЙ ЕГО ОБЪЯСНИЛ БЫ.

ЧТО СЧИТАЕТСЯ. Слово, стоящее хоть в одной строке с меткой «¬» и НИ В ОДНОЙ прямой строке
свода показов. Считается по всему своду, а не по своему пласту: слово, живущее в чужом мире,
показано читателю, и долга тут нет.

ДВА РОДА НАХОДОК, И ОНИ НЕ РАВНЫ:

    НЕБЫЛИЦА       — форма, которой в языке НЕТ вовсе: «childs», «házek», «talarar»,
                     «一本笔». Ей и место лишь в отказе, и требовать второго её показа
                     значило бы требовать, чтобы небылицу повторили. Такие объявлены
                     ЗДЕСЬ ПОИМЁННО, с языком и причиной.
    ЗАКОННОЕ СЛОВО — слово, в языке существующее и верное: арабское «كتاب» (книга),
                     греческое «χρώμα» (цвет), суахили «rangi» (цвет). Отказ берёт его
                     ПРАВИЛЬНО и отвергает не его, а сочетание, — а свод не показывает
                     его больше нигде. Это долг.

    ОТКАЗ ОТВЕРГАЕТ СОЧЕТАНИЕ, А ЧИТАТЕЛЬ ЗАПОМИНАЕТ СЛОВА. Отвергнув «*дом плюс кот равно»,
    свод не отверг ни дома, ни кота — но показал их единственный раз под чертой.

ГРАНИЦА ПРИБОРА НАЗВАНА. Мера идёт ПО СЛОВАМ, а слово отрезается пробелом. Письмо без
пробелов — китайское, японское, тайское (`segmentation: longest-match`) — этой мерой не
меряется: там «слово» вышло бы обрывком строки. Их долг виден глазом и ждёт своего прибора.

    МЕРА ПО СЛОВАМ ТРЕБУЕТ ПРОБЕЛОВ. Прибор, поделивший письмо, которое не делится, считает
    свои обрывки, а не чужие слова.

ОТКУДА ЭТИ СЛОВА БЕРУТСЯ — СКАЗАНО ВТОРЫМ ЧИСЛОМ. Всякий отказ пакета объявлен ПАРОЙ: «bad»
и «good», отвергнутое и замена. Прибор считает, сколько замен берёт ХОТЬ ОДНО СЛОВО
отвергнутой строки. Замер 13.09 по 150 парам: 121 берёт, 29 НЕ БЕРЁТ НИ ОДНОГО, и пятнадцать
из этих двадцати девяти объявлены причиной «unanswerable» — «какого цвета семь?» заменяется
вопросом о другом предмете и другими словами.

    ОТКАЗ, ЧЬЯ ЗАМЕНА БЕРЁТ ТЕ ЖЕ СЛОВА, УЧИТ ГРАНИЦЕ: «у семи цвета нет, у неба есть».
    ОТКАЗ, ЧЬЯ ЗАМЕНА БЕРЁТ ДРУГИЕ СЛОВА, УЧИТ ТОЛЬКО ЗАПРЕТУ — и слово, ради которого он
    поставлен, остаётся стоять под чертой в единственном своём показе.

Часть двадцати девяти — не долг: у пар с причиной «agreement» замена есть ИНАЯ ФОРМА того же
слова («اثنان كتاب» → «كتابان», «שתיים שעות» → «שעתיים»), и общих слов у них нет по существу
языка, а не по недосмотру. Прибор потому разделяет их по ОБЪЯВЛЕННОЙ ПРИЧИНЕ и не сводит в
одно число.

ЧИСЛО ЭТО — ОТЧЁТ, А НЕ РУБЕЖ, И СКАЗАНО ПОЧЕМУ: уплата тут есть ПОКАЗ, а показ строится
домом. Требовать нуля сегодня значило бы заказать двадцать девять правок пакетов прежде, чем
найден хоть один дом, которому эти слова нужны.

    python3 scripts/refusal_only_word.py [--подробно] [--двор ПУТЬ]
"""
# ПУСТОЙ-ОБХОД: --двор no-such-dir
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ОТКАЗ = "¬"

# СЛОВО ОТРЕЗАЕТСЯ ПРОБЕЛОМ, А НЕ ПРИЗНАКОМ «БУКВА» (13.09, куплено ложной находкой).
#
# Первая редакция брала `[^\W\d_]+` — и тамильское «நிறம்» распалось на «றம»: питоновский
# `\w` не считает буквой ЗНАКИ ОГЛАСОВКИ (категории Mn/Mc), а тамильское, деванагари и
# эфиопское письмо ставят их внутри слова. Прибор объявил долгом три обрывка.
#
#     ПРИЗНАК «БУКВА», ВЗЯТЫЙ У ДВИЖКА, РЕЖЕТ ПО ЛАТИНСКОЙ МЕРКЕ: то, что в одном письме
#     украшение буквы, в другом — её половина.
#
# Слово берётся так, как его отделяет САМО ПИСЬМО: пробелом, — а знаки препинания снимаются
# с концов. Письму без пробелов эта мера не адресуется вовсе, и это сказано в законе выше.
ЗНАКИ = ".,;:!?()[]«»„“”'\"—–-…۔؟،；：！？。、（）「」『』।॥"


def слова(строка):
    """Слова строки: отрезано ПРОБЕЛОМ, знаки препинания сняты с концов, числа отброшены."""
    вон = []
    for кусок in строка.split():
        с = кусок.strip(ЗНАКИ).lower()
        if с and not с.isdigit():
            вон.append(с)
    return вон

# НЕБЫЛИЦЫ — формы, которых в языке НЕТ. Объявлены поимённо, с языком и с тем, что отвергает
# их отказ. Список этот РАСТЁТ ТОЛЬКО РУКОЙ: слово попадает сюда, лишь когда прочитано и
# признано несуществующим, — и потому прибор не умеет тихо простить новое.
НЕБЫЛИЦЫ = {
    "childs": ("en", "множественное «child» есть «children», а не «childs»"),
    "házek": ("hu", "гармония гласных требует «házak»"),
    "talarar": ("sv", "окончание удвоено: «talar»"),
    "stora": ("sv", "при «en hus» стои́т «stor», а не определённая форма"),
    "eviniz": ("tr", "притяжательное «ваш дом» вместо счётного «ev»"),
    "okuyorsun": ("tr", "второе лицо при «ben»: нужно «okuyorum»"),
    "kirjastoon": ("fi", "направление вместо места: при «on» стои́т «kirjastossa»"),
    # КОРЕЙСКИЕ — ЧАСТИЦА НЕ ПО КОНЦУ СЛОВА, И ЭТО РОВНО ТОТ ЗАКОН, ЧТО ОБЪЯСНЯЕТ ДОМ
    # `koparticleforms`: после согласного стои́т одна форма пары, после гласного другая.
    "책가": ("ko", "«책» кончается согласным: именующая частица «이», а не «가»"),
    "책를": ("ko", "«책» кончается согласным: винящая частица «을», а не «를»"),
    "나무이": ("ko", "«나무» кончается гласным: именующая частица «가», а не «이»"),
}


def слова_свода(двор):
    """(в отказах, в прямых строках, где впервые) по всем мирам показов."""
    import genesis                                      # noqa: PLC0415
    отк, прям, где = collections.Counter(), set(), {}
    for путь in genesis.worlds(kind="shows"):
        if двор is not None and путь.parent != двор:
            continue
        for с in путь.read_text(encoding="utf-8", errors="replace").split("\n"):
            т = с.strip()
            if not т:
                continue
            слова_ = слова(т.lstrip(ОТКАЗ + " "))
            if т.startswith(ОТКАЗ):
                отк.update(слова_)
                for w in слова_:
                    где.setdefault(w, (путь.stem, т[:78]))
            else:
                прям.update(слова_)
    return отк, прям, где


def замены_пакетов():
    """(всего пар, берущих слово отвергнутого, {причина: сколько не берёт}) по всем пакетам."""
    всего, берут, не_берут = 0, 0, collections.Counter()
    for п in sorted((КОРЕНЬ / "tools" / "langpacks").glob("*.json")):
        тело = json.loads(п.read_text(encoding="utf-8"))
        пары = ((тело.get("show_kinds") or {}).get("refusals") or {}).get("pairs", [])
        for пр in пары:
            всего += 1
            общие = set(слова(пр.get("bad", ""))) & set(слова(пр.get("good", "")))
            if общие:
                берут += 1
            else:
                не_берут[пр.get("reason", "без причины")] += 1
    return всего, берут, не_берут


def без_пробелов():
    """Коды языков, чьё письмо не делится пробелом, — по объявлению самих пакетов."""
    вон = set()
    for п in sorted((КОРЕНЬ / "tools" / "langpacks").glob("*.json")):
        тело = json.loads(п.read_text(encoding="utf-8"))
        if тело.get("segmentation") == "longest-match":
            вон.add(п.stem)
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что прибор УМЕЕТ находить и умеет НЕ находить.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ НУЛЯ НАХОДОК. Пусть метка отказа перестанет узнаваться — и
        отвергнутых строк не станет вовсе, а прибор скажет «слов только в отказе 0», сверив
        НОЛЬ СТРОК.

    Четыре строки выдуманного свода: слово, стоящее и в отказе, и прямо (долгом не зовётся);
    слово, стоящее только в отказе (обязано найтись); объявленная небылица (обязана быть
    отнесена к небылицам, а не к долгу); и слово прямой строки, не бывавшее в отказе вовсе.
    """
    отк, прям = collections.Counter(), set()
    for т in ("¬ three childs.", "three children.", "¬ a rangi seven.", "the cat sleeps.",
              "seven is a number."):
        слова_ = слова(т.lstrip(ОТКАЗ + " "))
        (отк.update(слова_) if т.startswith(ОТКАЗ) else прям.update(слова_))
    только = {w for w in отк if w not in прям}
    беды = []
    if "three" in только:
        беды.append("слово, стоящее и в отказе, и прямо, названо стоящим только в отказе")
    if "rangi" not in только:
        беды.append("слово, стоящее ТОЛЬКО в отказе, НЕ НАЙДЕНО — прибор слеп")
    if "childs" not in только:
        беды.append("объявленная небылица не найдена вовсе — метка отказа не читается")
    if "childs" not in НЕБЫЛИЦЫ:
        беды.append("небылица «childs» не объявлена — разбор надвое не работает")
    if "number" in только:
        беды.append("слово прямой строки сочтено словом отказа")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"СЛОВО ТОЛЬКО В ОТКАЗЕ ОТКАЗ: чтение отказа не доказано ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--двор", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    двор = pathlib.Path(дов.двор) if дов.двор else None
    if двор is not None and not двор.is_dir():
        print(f"СЛОВО ТОЛЬКО В ОТКАЗЕ ОТКАЗ: двора нет — {двор}")
        return 2
    отк, прям, где = слова_свода(двор)
    if not отк:
        print("СЛОВО ТОЛЬКО В ОТКАЗЕ ОТКАЗ: строк с меткой отказа в своде нет")
        return 2
    беспробельные = {f"genesis_lang_{к}" for к in без_пробелов()}
    только, небылиц, обрывков = [], 0, 0
    for w in sorted(w for w in отк if w not in прям):
        мир, строка = где[w]
        if мир in беспробельные:
            обрывков += 1
            continue
        if w in НЕБЫЛИЦЫ:
            небылиц += 1
            continue
        только.append((отк[w], w, мир, строка))
    для_показа = sorted(только, reverse=True)[: None if дов.подробно else 14]
    for n, w, мир, строка in для_показа:
        print(f"  {w:<16} [{мир.replace('genesis_lang_', '')}] ×{n}  {строка}")
    пар, берут, не_берут = замены_пакетов()
    роспись = ", ".join(f"{п} {n}" for п, n in sorted(не_берут.items(), key=lambda x: -x[1]))
    print(f"  ЗАМЕНА ОТКАЗА: пар {пар}, берут слово отвергнутого {берут}, "
          f"НЕ БЕРУТ НИ ОДНОГО {sum(не_берут.values())} ({роспись or '—'})")
    print(f"СЛОВО ТОЛЬКО В ОТКАЗЕ ОТЧЁТ: законных слов, показанных ЛИШЬ под чертой, "
          f"{len(только)}; объявленных небылиц {небылиц} из {len(НЕБЫЛИЦЫ)}; "
          f"обрывков беспробельного письма отброшено {обрывков}; "
          f"слов в отказах {len(отк)}, в прямых строках {len(прям)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
