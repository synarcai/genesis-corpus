#!/usr/bin/env python3
"""[ПЕРЕКОС СОГЛАСОВАНИЯ] — две формы одного слова, показанные врозь.

    СОГЛАСУЕМОЕ СЛОВО ЕСТЬ НЕ ОДНО СЛОВО, А СТОЛЬКО, СКОЛЬКО У НЕГО ФОРМ, — И ЗАКОН ОПОРЫ
    ПРИЧИТАЕТСЯ КАЖДОЙ ИЗ НИХ, А НЕ ИХ СУММЕ.

Рамка, чьё слово гнётся по роду вещи («cuántos» — «cuántas») или по форме счёта («книга» —
«книги» — «книг»), пишет НЕ ОДИН вопрос, а по одному на каждую форму. Читатель покупает форму,
а не рамку: тот, кому нужно сказать «24 книги», должен был видеть эту форму восемь раз, и
богатство её сестры ему не в помощь.

ЧИСЛО, КУПИВШЕЕ ПРИБОР (12.09). Два долга ключа были уплачены в один день, и оба оказались
одной болезнью, найденной РУКОЙ:

  · дом держания давал вещи число ДИАГОНАЛЬЮ (`Т = (5n + 1) % 8`), и русская форма при
    двух-четырёх доставалась каждой вещи дважды из десяти — «где книги» 5 страниц, «где
    яблока» 4 при законе опоры LAW³ = 8, а их сёстры «где книг» и «где яблок» по пятнадцати;
  · дом SVAMP давал вещь числу ОДНИМ указателем (`Т = q % вещей` при восьми числах и восьми
    вещах), и вопросное слово жило столько раз, сколько вещей его рода в таблице: «quantos
    tem» 2 страницы против «quantas tem» 6, ибо португальских мужских вещей две из восьми.

    ПЕРЕКОС НЕ ЕСТЬ ЛОЖЬ: обе страницы верны, и всякий суд над ними зелен. Он есть НЕРОВНОСТЬ
    ПОКАЗА, и видна она лишь тому, кто считает формы ПОРОЗНЬ.

ОТКУДА БЕРУТСЯ ФОРМЫ. Прибор не угадывает их по буквам — он читает ОБЪЯВЛЕНИЯ домов:

  · `svampforms.РОДОВЫЕ` — пары «мужское / женское» одного слова в испанском, итальянском,
    португальском («cuántos»/«cuántas», «quanti»/«quante», «alguns»/«algumas»);
  · `actionpages._вещь` — все написания ОДНОЙ вещи на числах ряда: это формы счёта, и в
    русском с польским их три, в прочих языках две;
  · `numberline.год` — то же для слова «год», которое гнётся тем же законом.

Слова, попавшие в две группы сразу, сливаются в одну: «карты» есть и множественное «карты»,
и форма при двух-четырёх — один и тот же ряд написаний.

РОД БЕРЁТСЯ ТОТ ЖЕ, ЧТО У «КЛЮЧА БЕЗ ОПОРЫ» (`key_support.зачин`): два первых слова последнего
вопросного предложения, числа выпадают, имена сводятся в «@». Один закон — один дом; прибор
зовёт соседа, а не переписывает его правило.

ЧТО СЧИТАЕТСЯ ПЕРЕКОСОМ. Группа сестёр — это один зачин, где одно слово меняется по своему
ряду форм, а другое стои́т. Группа перекошена, если ХОТЬ ОДНА сестра живёт (масса больше нуля)
и НЕ ДОБИРАЕТ до закона опоры, покуда другая его перешагнула. Форма, не выходящая вовсе (масса
ноль), НЕ в счёт: дом вправе не писать того, чего в его ряду нет.

    python3 scripts/agree_skew.py [--свод FILE] [--подробно] [--рубеж N]
"""
# ПУСТОЙ-ОБХОД: --свод no-such-file
import argparse
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))

import actionpages as A      # noqa: E402 — написания вещи на числах ряда
import numberline as N       # noqa: E402 — написания слова «год»
import romgram              # noqa: E402 — пары вопросного слова: их судит сосед
import svampforms as S       # noqa: E402 — объявленные пары рода
import key_support           # noqa: E402 — закон зачина объявлен там

LAW3 = 8
# РУБЕЖ-ДОЛГА: ПЕРЕКОС_РУБЕЖ = 0
ПЕРЕКОС_РУБЕЖ = 0
ВЕРХ = 40                    # ряд чисел, на котором спрашиваются написания


def _ряды_форм():
    """Ряды написаний ОДНОГО слова, взятые из объявлений домов, со слиянием пересечений."""
    ряды = []
    for язык, родовые in S.РОДОВЫЕ.items():
        for пара in родовые.values():
            if isinstance(пара, tuple) and len(пара) > 1:
                ряды.append({с.lower() for с in пара if с})
    for язык in A.ЯЗЫКИ:
        for т in range(len(A.ЯЗЫКИ[язык]["вещи"])):
            ряды.append({A._вещь(язык, т, c).lower() for c in range(0, ВЕРХ + 1)})
        ряды.append({N.год(язык, c).lower() for c in range(0, ВЕРХ + 1)})
    # СЛИЯНИЕ ПЕРЕСЕЧЕНИЙ: слово, стоящее в двух рядах, делает их одним рядом.
    слитые = []
    for ряд in ряды:
        ряд = {с for с in ряд if с}
        if len(ряд) < 2:
            continue
        свои = [г for г in слитые if г & ряд]
        for г in свои:
            слитые.remove(г)
            ряд |= г
        слитые.append(ряд)
    вон = {}
    for i, ряд in enumerate(слитые):
        for с in ряд:
            вон[с] = i
    return слитые, вон


# ВОПРОСНОЕ СЛОВО СУДИТСЯ НЕ ЗДЕСЬ (12.09, в тот же час). Первый прогон этой меры по своду
# назвал одиннадцать перекосов, и девять из них были не неровностью показа, а ЛОЖЬЮ: «quanti
# mele» при 411 страницах «quante mele». Ложь эта уплачена домами и с тех пор судится мерой
# без порога — `scripts/twogender.py`: у имени один род, и одного совпадения довольно.
#
# Оставшиеся два — «cuántos tengo» 6 против «cuántas tengo» 18 — ВЕРНЫ ОБА: имя в них
# опущено, и род берётся у опущенного. Считать их перекосом значило бы требовать ровности
# там, где её нет в языке.
#
#     ДВЕ МЕРЫ НЕ ДЕЛЯТ ОДНОЙ БЕДЫ: эта считает формы ИМЕНИ, а вопросное слово при имени
#     судит та, которой порог не нужен.
_ВОПРОСНЫЕ = frozenset(с.lower() for пара in romgram.ПАРЫ.values() for с in пара)


def группы(счёт, ряды, где):
    """Зачин → его сёстры: то же место, та же группа написаний, иное написание."""
    вон = collections.defaultdict(dict)
    for зачин, масса in счёт.items():
        слова = зачин.split()
        if len(слова) != 2:
            continue
        for место in (0, 1):
            i = где.get(слова[место])
            if i is None or слова[место] in _ВОПРОСНЫЕ:
                continue
            вон[(место, слова[1 - место], i)][слова[место]] = масса
    return вон


def перекошенные(гр, рубеж=LAW3):
    вон = []
    for ключ, сёстры in гр.items():
        живые = {с: м for с, м in сёстры.items() if м > 0}
        if len(живые) < 2:
            continue
        if max(живые.values()) >= рубеж and min(живые.values()) < рубеж:
            вон.append((ключ, живые))
    вон.sort(key=lambda п: (min(п[1].values()), -max(п[1].values())))
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ПЕРЕКОС ВИДЕН, а ровный ряд — нет.

        ПРИБОР, СЧИТАЮЩИЙ ЛИШЬ ТЕХ, КОГО УЗНАЛ, МОЛЧИТ О НЕУЗНАННЫХ — и молчание его
        неотличимо от здоровья. Пусть ряд написаний перестанет узнаваться: всякий зачин
        уйдёт в «не группу», и прибор скажет «перекосов 0», сверив НОЛЬ ГРУПП.

    Три заведомо известных случая на выдуманном ряде: перекос, ровность и мёртвая форма.
    """
    беды = []
    ряды = [{"аа", "бб", "вв"}]
    где = {с: 0 for с in ряды[0]}
    случаи = (
        ({"где аа": 15, "где бб": 3}, 1, "перекос 15 против 3 не назван"),
        ({"где аа": 15, "где бб": 9}, 0, "ровный ряд назван перекошенным"),
        ({"где аа": 15, "где бб": 0}, 0, "мёртвая форма принята за перекос"),
        ({"где аа": 3, "где бб": 2}, 0, "оба ниже закона — это бедность рода, не перекос"),
    )
    for счёт, ждём, беда in случаи:
        дало = len(перекошенные(группы(счёт, ряды, где)))
        if дало != ждём:
            беды.append(f"{беда} (назвал {дало}, ждали {ждём})")
    if не_пусто := [с for с in ("cuántos", "cuántas") if с not in _ГДЕ]:
        беды.append(f"объявленная пара рода не прочтена: {' '.join(не_пусто)}")
    return беды


_РЯДЫ, _ГДЕ = _ряды_форм()


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ПЕРЕКОС СОГЛАСОВАНИЯ ОТКАЗ: ряд написаний не доказан ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--свод", default=None)
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--рубеж", type=int, default=ПЕРЕКОС_РУБЕЖ)
    ап.add_argument("--имён", type=int, default=12)
    дов = ап.parse_args()
    свод = pathlib.Path(дов.свод) if дов.свод else КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
    if not свод.is_file():
        print(f"ПЕРЕКОС СОГЛАСОВАНИЯ ОТКАЗ: нет свода «{свод}»")
        return 2
    счёт = collections.Counter()
    строк = 0
    for стр in свод.read_text(encoding="utf-8", errors="replace").splitlines():
        т = стр.strip()
        if "?" not in т:
            continue
        строк += 1
        з = key_support.зачин(т)
        if з:
            счёт[з] += 1
    гр = группы(счёт, _РЯДЫ, _ГДЕ)
    кос = перекошенные(гр)
    for (место, стоит, _), живые in кос[:дов.имён if дов.подробно else 6]:
        бедная = min(живые, key=живые.get)
        богатая = max(живые, key=живые.get)
        зачин_б = f"{бедная} {стоит}" if место == 0 else f"{стоит} {бедная}"
        зачин_г = f"{богатая} {стоит}" if место == 0 else f"{стоит} {богатая}"
        print(f"  {живые[бедная]:5} «{зачин_б}»   против {живые[богатая]:5} «{зачин_г}»")
    итог = "PASS" if len(кос) <= дов.рубеж else "FAIL"
    print(f"ПЕРЕКОС СОГЛАСОВАНИЯ {итог}: групп сестёр {len(гр)}, ПЕРЕКОШЕННЫХ {len(кос)} "
          f"(рубеж {дов.рубеж}); зачинов {len(счёт)} на {строк} вопросных строк, "
          f"рядов написаний {len(_РЯДЫ)}")
    return 0 if итог == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
