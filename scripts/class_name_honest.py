#!/usr/bin/env python3
"""[ИМЯ КЛАССА] — одна лексема, объявленная в одном пакете и именем, и глаголом.

Пакет языка держит `morph_classes` — классы словоизменения, и имя класса есть УТВЕРЖДЕНИЕ О
ЧАСТИ РЕЧИ: `adj_forms` обещает прилагательное, `noun_count` — имя, `verb_pres` — глагол.
Утверждение это читает всякий, кто берёт из пакета образец, и никто его не проверял.

    ИМЯ КЛАССА ЕСТЬ УТВЕРЖДЕНИЕ, А НЕ ЯРЛЫК: ПО НЕМУ БЕРУТ ОБРАЗЕЦ ДЛЯ ПОКАЗА.

ПРИБОР НЕ СУДИТ О ЧАСТИ РЕЧИ И НЕ УМЕЕТ. «Есть ли `auto` прилагательное по-фински» — вопрос
языка, и мера, взявшаяся отвечать на него сама, выдумала бы знание. Прибор спрашивает у
ПАКЕТА О ПАКЕТЕ: не стои́т ли ОДНА И ТА ЖЕ лексема в двух классах, чьи имена обещают РАЗНЫЕ
части речи. Тогда лжёт один из двух, и оба — объявления самого пакета.

    ОДНА ЛЕКСЕМА, ОБЪЯВЛЕННАЯ В ОДНОМ ПАКЕТЕ И ИМЕНЕМ, И ГЛАГОЛОМ, ЕСТЬ ЛОЖЬ ОДНОГО ИЗ ДВУХ
    КЛАССОВ, И КАКОГО ИМЕННО — РЕШИТ РУКА, А НЕ МЕРА.

ЗАМЕР 13.09 (повод). Класс `adj_forms` объявлен в девяти пакетах. В пяти под ним лежит
обещанное: `am` (ረጅም → ረጃጅም), `hi` (अच्छा · अच्छे · अच्छी), `ta`, `th`, `ja` — пересечение с
прочими классами ПУСТО. В четырёх лежит иное, и говорит об этом сам пакет:

    fi — восемь лексем стоят и в `noun_count`; ячейки зовутся `nominative, genitive,
         partitive, inessive…`, то есть падежами имени;
    ko — десять лексем стоят и в `noun_count`: «고양이 · 고양이가 · 고양이를 · 고양이예요»;
    sw — шесть лексем стоят и в `noun_count`: «kitabu kimoja · vitabu viwili · kitabu kikubwa»,
         согласование по классу, где гнётся и числительное, и прилагательное при имени;
    hu — восемь лексем стоят и в `verb_pres`: «olvasom · olvasod · olvassa…», определённое
         спряжение глагола.

ДАННЫЕ ХОРОШИ, ПЛОХО ИМЯ НАД НИМИ. Двенадцать финских падежей и шесть венгерских лиц —
объявления верные; ложно лишь то, что зовутся они прилагательными.

ЧТО ЭТОТ ДОЛГ НЕ ЕСТЬ. Имя класса НИ РАЗУ не выходит на страницу: `adj_forms` не встречается
ни в одном из миров свода, а английское «adjective» стои́т 71 раз и все 71 — в мире испанского
артикля, где прилагательное и вправду прилагательное.

    ИМЯ, ЛГУЩЕЕ ВНУТРИ ПРИБОРА, И ИМЯ, ЛГУЩЕЕ НА СТРАНИЦЕ, — РАЗНЫЕ ДОЛГИ, И ПЛАТЯТСЯ ОНИ
    ПОРОЗНЬ. Первое чинится переименованием класса и сверкой миров подписью; второе чинилось
    бы отзывом мира. Здесь долг первого рода.

ЧЕГО ПРИБОР НЕ ВИДИТ, И ЭТО СКАЗАНО ЧИСЛОМ: класс, чьё имя не начинается ни с одной
объявленной приставки, НЕ СУДИТСЯ вовсе — он не обещает части речи, и требовать от него
нечего. Число таких классов печатается всякий раз.

    python3 scripts/class_name_honest.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --пакеты /no/such/dir
import argparse
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# ПРИСТАВКА ИМЕНИ КЛАССА → ЧАСТЬ РЕЧИ, КОТОРУЮ ОНА ОБЕЩАЕТ. Таблица ЗАКРЫТА и объявлена
# здесь; всё, что в неё не попало, прибор честно не судит и говорит, сколько таких.
ЧАСТИ_РЕЧИ = {
    "adj_": "прилагательное",
    "noun_": "имя",
    "verb_": "глагол",
    "pron_": "местоимение",
    "num_": "числительное",
}

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 32
#
# ЛЕКСЕМ, СТОЯЩИХ В ДВУХ КЛАССАХ РАЗНЫХ ЧАСТЕЙ РЕЧИ. Замерено 13.09: 32 — fi 8, ko 10, sw 6,
# hu 8. Рубеж есть ПОТОЛОК и только опускается: платится он переименованием класса в пакете,
# и всякое такое переименование ОБЯЗАНО пройти подписью миров (`scripts/worlds_unchanged.py`),
# ибо порядок обхода классов у иных кузниц идёт по имени.
РАЗЛАДОВ_РУБЕЖ = 32


def часть_речи(имя):
    """Часть речи, обещанная именем класса, или None, если имя ничего не обещает."""
    for приставка, часть in ЧАСТИ_РЕЧИ.items():
        if имя.startswith(приставка):
            return часть
    return None


def _самопроверка():
    """Мера обязана делить обещающие имена от необещающих и не путать частей.

    Таблица приставок закрыта; проверка стои́т здесь, чтобы правка её не прошла молча.
    """
    assert часть_речи("adj_forms") == "прилагательное"
    assert часть_речи("noun_count") == "имя"
    assert часть_речи("verb_pres") == "глагол"
    assert часть_речи("show_kinds") is None, "имя без приставки не обещает части речи"
    # ЧЕРТА В ПРИСТАВКЕ НЕ УКРАШЕНИЕ. Первая редакция этой проверки утверждала, что мера
    # поймает `adjacent`, — и упала на себе самой: приставка `adj_` требует черты, а стало
    # быть, есть ЧАСТЬ ИМЕНИ, а не пробег букв. Проверка исправлена по мере, а не мера по
    # проверке.
    #
    #     ПРИСТАВКА С ЧЕРТОЙ ЕСТЬ ЧАСТЬ ИМЕНИ; БЕЗ ЧЕРТЫ ОНА ЛИШЬ НАЧАЛО БУКВ И ЛОВИТ СЛОВА,
    #     О КОТОРЫХ НИКТО НЕ ГОВОРИЛ.
    assert часть_речи("adjacent") is None
    assert часть_речи("adj_degree") == "прилагательное"


_самопроверка()


def разлады(корень_пакетов):
    """[(пакет, лексема, класс1, часть1, класс2, часть2)] и число несудимых классов."""
    найдено, несудимых, классов = [], 0, 0
    for путь in sorted(корень_пакетов.glob("*.json")):
        тело = json.loads(путь.read_text(encoding="utf-8"))
        классы = тело.get("morph_classes") or {}
        обещают = {}
        for имя, кл in классы.items():
            классов += 1
            часть = часть_речи(имя)
            if часть is None:
                несудимых += 1
                continue
            обещают[имя] = (часть, set((кл or {}).get("lexemes") or {}))
        имена = sorted(обещают)
        for i, первое in enumerate(имена):
            ч1, л1 = обещают[первое]
            for второе in имена[i + 1:]:
                ч2, л2 = обещают[второе]
                if ч1 == ч2:
                    continue
                for лексема in sorted(л1 & л2):
                    найдено.append((путь.stem, лексема, первое, ч1, второе, ч2))
    return найдено, несудимых, классов


def main():
    р = argparse.ArgumentParser(description="имя класса против объявлений того же пакета")
    р.add_argument("--подробно", action="store_true")
    р.add_argument("--пакеты", type=pathlib.Path, default=КОРЕНЬ / "tools" / "langpacks")
    дов = р.parse_args()
    if not дов.пакеты.is_dir():
        print(f"ИМЯ КЛАССА PASS: пакетов нет ({дов.пакеты}) — судить нечего")
        return 0
    найдено, несудимых, классов = разлады(дов.пакеты)
    по_пакетам = {}
    for пакет, лексема, к1, _ч1, к2, _ч2 in найдено:
        по_пакетам.setdefault(пакет, {}).setdefault((к1, к2), []).append(лексема)
    for пакет in sorted(по_пакетам):
        for (к1, к2), лексемы in sorted(по_пакетам[пакет].items()):
            образец = ", ".join(лексемы[:4]) + ("…" if len(лексемы) > 4 else "")
            print(f"  [{пакет}] {len(лексемы)} лексем стоят и в `{к1}`, и в `{к2}`: {образец}")
            if дов.подробно:
                for л in лексемы:
                    print(f"      {л}")
    поза = "PASS" if len(найдено) <= РАЗЛАДОВ_РУБЕЖ else "FAIL"
    print(f"ИМЯ КЛАССА {поза}: {len(найдено)} лексем в двух частях речи "
          f"(рубеж {РАЗЛАДОВ_РУБЕЖ}); пакетов с разладом {len(по_пакетам)}, "
          f"классов всего {классов}, из них не обещают части речи {несудимых}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
