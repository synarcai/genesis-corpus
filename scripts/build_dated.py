#!/usr/bin/env python3
"""[СБОРКА НАЗЫВАЕТ ДЕНЬ] — файл, собранный из прошлого свода, обязан сказать, из какого.

    ОБЪЯВЛЕНИЕ, СХОДЯЩЕЕСЯ С ФАЙЛОМ, НЕ ГОВОРИТ, ЧТО ФАЙЛ СХОДИТСЯ СО СВОДОМ.

ПОВОД, ЗАМЕРЕННЫЙ 12.09. Свод несёт шесть сборок. Две живут вместе с ним — полная и
школьная, — а четыре собраны 04.09 и с тех пор не трогались: минимальная (10,7 МБ),
уникальная, две средних. Суд манифеста сверяет их размер с объявлением — и сходится, ибо
объявление описывает ЛЕЖАЩИЙ файл честно.

    СУД, СВЕРЯЮЩИЙ ОБЪЯВЛЕНИЕ С ФАЙЛОМ, МОЛЧИТ О ТОМ, ИЗ ЧЕГО ФАЙЛ СОБРАН: он видит две
    величины и не видит третьей — СВОДА, КОТОРЫЙ ОБЕ ОПИСЫВАЮТ.

За восемь суток свод вырос с тринадцати миллионов байт до тридцати девяти, а сборки стоят.
Читатель, взявший минимальную сборку ныне, получит корпус трети нынешних миров — и ничто в
дереве ему о том не скажет.

ЧТО СУДИТ ПРИБОР. Всякая сборка (`text: mix` в манифесте), чей файл СТАРШЕ полной сборки,
обязана назвать в своём жанре ДЕНЬ своей сборки — словом «СОБРАНА ДД.ММ». Названный день не
делает сборку свежей; он делает её ЧЕСТНОЙ.

    СТАРАЯ СБОРКА, НАЗВАВШАЯ СВОЙ ДЕНЬ, ЕСТЬ ИСТОРИЧЕСКИЙ СНИМОК; ТА ЖЕ СБОРКА БЕЗ ДНЯ
    ЕСТЬ ЛОЖЬ О НЫНЕШНЕМ СВОДЕ.

ЧЕГО ОН НЕ ТРЕБУЕТ. Он не требует пересборки: минимальная сборка стои́т переписи форм по
всему своду, и решать, платить ли эту цену, — не дело прибора. Он требует одного: чтобы
возраст был НАЗВАН.

    python3 scripts/build_dated.py [--манифест ФАЙЛ]
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
ПОЛНАЯ = "datasets/GENESIS-FULL.txt"

# РУБЕЖ-ДОЛГА: БЕЗЫМЯННЫХ_РУБЕЖ = 0
#
# Рубеж есть ПОЛ: сборка либо ровесница свода, либо назвала свой день. Середины нет.
БЕЗЫМЯННЫХ_РУБЕЖ = 0

ДЕНЬ = re.compile(r"СОБРАНА\s+(\d{2}\.\d{2})")
# ЗАПАС В ЧАС: сборки одного прогона пишутся не в одну секунду, и разница в минуты
# не есть отставание. Сутки — уже отставание, и час их надёжно отделяет.
ЗАПАС = 3600


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что прибор УМЕЕТ находить.

        ПРИБОР, ЗЕЛЕНЕЮЩИЙ ОТ НУЛЯ НАХОДОК, ОБЯЗАН ДОКАЗАТЬ, ЧТО УМЕЕТ НАХОДИТЬ.

    Признак дня проверяется на четырёх жанрах: с днём в объявленном виде (обязан
    найтись), без дня вовсе, с днём иного вида («собрано 4 сентября» — прибор требует
    ОДНОГО вида записи и о прочих молчит), и с днём в середине строки.
    """
    случаи = (
        ("сборка СОБРАНА 04.09 из свода того дня", "04.09", "день в объявленном виде"),
        ("сборка без всякого дня", None, "дня нет вовсе"),
        ("собрано 4 сентября из свода", None, "день иного вида — не признаётся"),
        ("прочее, и СОБРАНА 11.09, и ещё прочее", "11.09", "день в середине"),
    )
    беды = []
    for жанр, ждём, имя in случаи:
        m = ДЕНЬ.search(жанр)
        было = m.group(1) if m else None
        if было != ждём:
            беды.append(f"{имя}: прочтено {было}, а надо {ждём}")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    беды = _проба()
    if беды:
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"СБОРКА НАЗЫВАЕТ ДЕНЬ ОТКАЗ: прибор не доказал, что умеет находить "
              f"({len(беды)} бед)")
        return 2
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
    if not манифест.is_file():
        print(f"СБОРКА НАЗЫВАЕТ ДЕНЬ ОТКАЗ: манифеста нет — {манифест}")
        return 2
    тело = json.loads(манифест.read_text(encoding="utf-8"))
    корень = манифест.parent.parent
    полная = корень / ПОЛНАЯ
    if not полная.is_file():
        print(f"СБОРКА НАЗЫВАЕТ ДЕНЬ ОТКАЗ: полной сборки нет — {ПОЛНАЯ}")
        return 2
    свежесть = полная.stat().st_mtime
    сборки = [м for м in тело.get("worlds", ()) if м.get("text") == "mix"]
    if not сборки:
        print("СБОРКА НАЗЫВАЕТ ДЕНЬ ОТКАЗ: сборок не объявлено, судить нечего")
        return 2
    ровесниц, названных, безымянных = 0, [], []
    for м in сборки:
        п = pathlib.Path(м.get("file", ""))
        if not п.is_absolute():
            п = корень / п
        if not п.is_file():
            continue
        отстала = свежесть - п.stat().st_mtime > ЗАПАС
        if not отстала:
            ровесниц += 1
            continue
        m = ДЕНЬ.search(м.get("genre", ""))
        (названных if m else безымянных).append(
            (м["name"], m.group(1) if m else "", (свежесть - п.stat().st_mtime) / 86400))
    for имя, _д, суток in безымянных:
        print(f"  СБОРКА БЕЗ ДНЯ «{имя}»: отстала на {суток:.1f} сут и о том молчит")
    for имя, день, суток in названных:
        print(f"  назвала день: {имя} — СОБРАНА {день}, отстала на {суток:.1f} сут")
    поза = "PASS" if len(безымянных) <= БЕЗЫМЯННЫХ_РУБЕЖ else "FAIL"
    print(f"СБОРКА НАЗЫВАЕТ ДЕНЬ {поза}: сборок без названного дня {len(безымянных)} "
          f"(рубеж {БЕЗЫМЯННЫХ_РУБЕЖ}); ровесниц свода {ровесниц}, отставших с названным "
          f"днём {len(названных)}, сборок всего {len(сборки)}")
    return 0 if len(безымянных) <= БЕЗЫМЯННЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
