#!/usr/bin/env python3
"""[ПРАЗДНОЕ СЛОВО] — объявленное языку и не встречающееся в своде ни разу.

    СЛОВО, ОБЪЯВЛЕННОЕ ЯЗЫКУ, КОТОРЫЙ ИМ НЕ ПОЛЬЗУЕТСЯ, ВООРУЖАЕТ ЕГО СУД ПРОТИВ ДРУГИХ.

Закон куплен делом (07.09). Я объявил «ruble» английскому пакету ради полноты понятия —
английские миры рублей не считают, — и тем вооружил суд памяти: польская строка «liczę 2
ruble.» опознаётся как НЕ ЧУЖДАЯ английскому (польских служебных слов в ней нет),
английский счёт требует при двойке «rubles», и честная строка названа ложью.

    ОБЪЯВЛЕНИЕ ЕСТЬ НЕ ТОЛЬКО РАЗРЕШЕНИЕ, НО И ОРУЖИЕ: всякое слово, внесённое в пакет,
    даёт суду ЭТОГО языка право судить ВСЯКУЮ строку, где оно встретится, — в том числе
    строку чужого языка, где оно стои́т по совпадению письма.

ЧТО ПРИБОР СЧИТАЕТ, И ЧЕГО НЕ СЧИТАЕТ. Праздно слово, не встречающееся во ВСЁМ своде — ни в
своём слое, ни в мирах показов. Слово, живущее в мирах, но не в своём слое, ПРАЗДНЫМ НЕ
ЗОВЁТСЯ: пакет объявляет словарь языка, а не оглавление своего пласта, и английских
существительных, живущих в мирах задач, сто двадцать одно.

    МЕРА, НЕ ОТЛИЧАЮЩАЯ «НЕ В СВОЁМ СЛОЕ» ОТ «НИГДЕ», НАЗВАЛА БЫ ДОЛГОМ СТО ДВАДЦАТЬ ОДНО
    ЧЕСТНОЕ СЛОВО. Первая проба так и сделала; вторая спрашивает свод целиком.

    python3 scripts/idle_word.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --свод no-such-file
import argparse
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: ПРАЗДНЫХ_РУБЕЖ = 4
#
# ПОСТАВЛЕН БЫЛ НА НОЛЬ ПО ЖЕЛАЕМОМУ И ТУТ ЖЕ ИСПРАВЛЕН ПО ДОСТИГНУТОМУ. В час постановки
# праздных было 17: восемь корейских голых ячеек и девять английских имён. Восемь корейских
# закрыты одним шаблоном (см. `scripts/form_unshown.py`), четыре английских — показом
# единицы в доме физики и в доме людей (ampere, customer, passenger, centimetre). Осталось
# ЧЕТЫРЕ (было пять; «transition» показан домом кибернетики), и рубеж есть ровно они:
#
#     litres      — множественное не пишется нигде; «litre» живёт в глифах
#     millimetre  — стои́т лишь МЕНЬШЕЙ стороной отношения, оттого один не показан
#     outcome     — 40 «outcomes» в статистике и в счётных науках, единицы нет
#     pupil       — 242 «pupils» в задачах о школе, единицы нет
#     transition  — 12 «transitions» в кибернетике, единицы нет
#
# ОДИН ИЗ ПЯТИ ОПАСЕН НЕ МОЛЧАНИЕМ, А ОРУЖИЕМ. Французское письмо тоже знает «litres»; пока
# слово объявлено английским и не показано английским, оно даёт английскому суду право на
# французскую строку — ровно та беда, которой куплен этот прибор («ruble»). Прочие четыре
# суть недостача показа, а не ловушка.
ПРАЗДНЫХ_РУБЕЖ = 1


def слова_пакета(пак):
    """Всякая объявленная форма имени — из классов и из плоского указателя."""
    вон = set()
    for _имя, кл in (пак.get("morph_classes") or {}).items():
        for _л, формы in (кл.get("lexemes") or {}).items():
            вон |= {str(ф) for ф in формы if str(ф).strip()}
    for л, мн in (пак.get("noun_forms") or {}).items():
        вон.add(str(л)); вон.add(str(мн))
    return {ф for ф in вон if ф.strip()}


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--свод", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    п_свода = pathlib.Path(дов.свод) if дов.свод else КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
    if not п_свода.is_file():
        print(f"ПРАЗДНОЕ СЛОВО ОТКАЗ: свода «{п_свода}» нет")
        return 2
    свод = п_свода.read_text(encoding="utf-8", errors="replace").lower()
    # ОДИН ПРОХОД ПО СВОДУ, А НЕ ОДИН НА СЛОВО. Первая проба искала каждую форму отдельным
    # поиском по тридцати трём мегабайтам — три тысячи форм дали бы сто гигабайт чтения и час
    # хода. Свод разбирается на слова ОДНАЖДЫ, и вопрос к нему становится вопросом о членстве.
    словарь_свода = set(re.findall(r"[^\W\d_]+", свод))
    пакеты = sorted((КОРЕНЬ / "tools" / "langpacks").glob("*.json"))
    if not пакеты:
        print("ПРАЗДНОЕ СЛОВО ОТКАЗ: пакетов нет")
        return 2
    праздные, всего = [], 0
    print(f"{'пакет':<6}{'форм':>7}{'праздных':>10}")
    for п in пакеты:
        пак = json.loads(п.read_text(encoding="utf-8"))
        я = пак.get("lang", п.stem)
        формы = слова_пакета(пак)
        всего += len(формы)
        свои = []
        for ф in sorted(формы):
            низ = ф.lower()
            # ГРАНИЦА СЛОВА — ТАМ, ГДЕ ЕЁ ЗНАЕТ ПИСЬМО: языки без пробелов ищутся подстрокой
            # (их формы в своде стоят внутри слитной строки), прочие — членством в словаре.
            # Форма из нескольких слов («New York») спрашивается по каждому слову.
            if пак.get("segmentation") == "longest-match":
                нашлось = низ in свод
            else:
                части = re.findall(r"[^\W\d_]+", низ)
                нашлось = bool(части) and all(ч in словарь_свода for ч in части)
            if not нашлось:
                свои.append(ф)
        if свои:
            праздные.append((я, свои))
        print(f"{я:<6}{len(формы):>7}{len(свои):>10}")
    for я, свои in праздные:
        видно = ", ".join(свои[:8]) + ("…" if len(свои) > 8 else "")
        print(f"  ПРАЗДНЫЕ [{я}] {len(свои)}: {видно}")
    сколько = sum(len(с) for _я, с in праздные)
    поза = "PASS" if сколько <= ПРАЗДНЫХ_РУБЕЖ else "FAIL"
    print(f"ПРАЗДНОЕ СЛОВО {поза}: форм объявлено {всего}, праздных {сколько} "
          f"(рубеж {ПРАЗДНЫХ_РУБЕЖ}); пакетов {len(пакеты)}, свод {п_свода.name} "
          f"({len(свод)} знаков)")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
