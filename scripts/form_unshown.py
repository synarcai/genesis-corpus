#!/usr/bin/env python3
"""[ФОРМА БЕЗ ПОКАЗА] — ячейка класса, которую пакет объявил, а его собственный слой не пишет.

    КЛАСС ОБЕЩАЕТ КАЖДОЙ СВОЕЙ ЯЧЕЙКОЙ. Ячейка, ни разу не вставшая в слое, есть обещание,
    которого письмо языка не исполняет: читателю нечего с неё взять, а суду формы — не на чём
    её проверить.

ЧЕМ ЭТОТ ПРИБОР ОТЛИЧАЕТСЯ ОТ ДВУХ СОСЕДЕЙ, И ПОЧЕМУ ИХ ТРИ, А НЕ ОДИН.

    `cell_shown`   — ячейка счёта, не показанная ПРИ ЧИСЛЕ. Спрашивает лишь классы, к которым
                     пакет обращается через `by_n`: он ими ОБЕЩАЛ согласование с числом.
    `form_unshown` — ячейка ЛЮБОГО класса, не показанная В СВОЁМ СЛОЕ НИГДЕ, ни при числе, ни
                     без. Спрашивает лишь классы, к которым обращается хоть один шаблон.
    `idle_word`    — объявленное слово, не встречающееся ВО ВСЁМ СВОДЕ. Спрашивает и плоский
                     указатель `noun_forms` тоже.

ГРАНИЦА МЕЖДУ ВТОРЫМ И ТРЕТЬИМ КУПЛЕНА ОШИБКОЙ (07.09). Плоский указатель `noun_forms` есть
СЛОВАРЬ ЯЗЫКА, а не оглавление его пласта: сто двадцать одно английское имя не стои́т в
английском слое и живёт в мирах задач — и это не долг. Класс же есть МАШИНА ПИСЬМА самого
пласта: его ячейка, не вставшая в пласте, не встанет нигде. Потому второй прибор берёт классы
и не берёт указатель, а третий берёт оба и спрашивает свод целиком.

    МЕРА, НЕ ОТЛИЧАЮЩАЯ СЛОВАРЬ ОТ МАШИНЫ ПИСЬМА, НАЗВАЛА БЫ ДОЛГОМ СТО ДВАДЦАТЬ ОДНО
    ЧЕСТНОЕ СЛОВО.

ЧТО НАЙДЕНО В ДЕНЬ ПОСТАНОВКИ: из 3572 объявленных форм показано 3564 (100 %), и все восемь
дыр — корейские. Корейский класс `adj_forms` держит четыре ячейки — bare, subject, object,
copula, — и ГОЛУЮ не называет ни один шаблон: письмо пласта пишет 책이, 책을, 책이에요 и никогда
책. Голая форма стои́т в слое пять раз, и все пять — внутри отказа «¬ 책 더하기 고양이 답은?», то
есть в жёстко вписанной паре, а не в работе класса. Девять остальных лексем не показаны вовсе.

    ЯЧЕЙКА, ЖИВУЩАЯ ТОЛЬКО В ЖЁСТКО ВПИСАННОЙ СТРОКЕ, НЕ ПОКАЗАНА КЛАССОМ — ОНА ПОКАЗАНА
    ПИСЦОМ. Прибор этого различить не может и не притворяется, что может: он считает письмо, а
    не намерение. Различил — глаз, прочитавший пять строк.

    python3 scripts/form_unshown.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --пакеты no-such-dir
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: БЕЗ_ПОКАЗА_РУБЕЖ = 0
#
# ПОСТАВЛЕН БЫЛ НА 8 — восемь корейских голых ячеек часа постановки — И ЗАКРЫТ В ТОТ ЖЕ ЧАС.
# Цена оказалась ровно та, что была названа: ОДИН шаблон в ko.json, назвавший голую ячейку
# («{lex:adj_forms:bare} 있어요.» — форма речи, уже жившая в пласте у счётного класса, оттого
# нового рода не завелось), и перековка одного пласта. Ныне 3572 из 3572.
#
# Ноль есть ПОЛ, а не потолок: пакет, объявивший ячейку, которой его письмо не пишет, роняет
# прибор в тот же час.
БЕЗ_ПОКАЗА_РУБЕЖ = 0


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--пакеты", default=None, help="иная папка пакетов")
    дов = ап.parse_args()
    папка = (pathlib.Path(дов.пакеты) if дов.пакеты
             else КОРЕНЬ / "tools" / "langpacks")
    пакеты = sorted(папка.glob("*.json")) if папка.is_dir() else []
    if not пакеты:
        print(f"ФОРМА БЕЗ ПОКАЗА ОТКАЗ: пакетов нет в «{папка}»")
        return 2
    по_языкам = collections.Counter()
    дыры, всего, показано, вне_шаблонов, без_слоя = [], 0, 0, [], 0
    for п in пакеты:
        пак = json.loads(п.read_text(encoding="utf-8"))
        я = пак.get("lang", п.stem)
        слой = КОРЕНЬ / "datasets" / f"genesis_lang_{я}.txt"
        if not слой.is_file():
            без_слоя += 1
            continue
        т = слой.read_text(encoding="utf-8").lower()
        слитно = пак.get("segmentation") == "longest-match"
        # ОДИН РАЗБОР ПЛАСТА НА СЛОВА, А НЕ ОДИН ПОИСК НА ФОРМУ.
        токены = set(re.findall(r"[^\W\d_]+", т))
        шаблоны = " ".join(t for р in (пак.get("show_kinds") or {}).values()
                           for t in (р.get("templates") or []))
        for имя, кл in (пак.get("morph_classes") or {}).items():
            # КЛАСС, К КОТОРОМУ НЕ ОБРАЩАЕТСЯ НИ ОДИН ШАБЛОН, НИЧЕГО НЕ ОБЕЩАЛ ПЛАСТУ.
            # Это иной долг (класс без дела), и его считает иной прибор.
            if f"lex:{имя}:" not in шаблоны:
                вне_шаблонов.append((я, имя))
                continue
            for лекс, ряд in (кл.get("lexemes") or {}).items():
                for ф in sorted({str(x) for x in ряд if str(x).strip()}):
                    всего += 1
                    низ = ф.lower()
                    части = re.findall(r"[^\W\d_]+", низ)
                    есть = (низ in т) if слитно else (bool(части)
                                                      and all(ч in токены for ч in части))
                    if есть:
                        показано += 1
                    else:
                        по_языкам[я] += 1
                        дыры.append((я, имя, лекс, ф))
    доля = 100 * показано / max(1, всего)
    print(f"{'язык':<6}{'форм без показа':>17}")
    for я, n in по_языкам.most_common():
        print(f"{я:<6}{n:>17}")
    сколько = всего - показано
    for я, кл, л, ф in (дыры if дов.подробно else дыры[:10]):
        print(f"    ДЫРА {я}/{кл}: {л} → «{ф}» ни разу в своём пласте")
    if вне_шаблонов:
        имена = ", ".join(f"{я}/{к}" for я, к in вне_шаблонов[:6])
        print(f"  ВНЕ ШАБЛОНОВ (не считано) {len(вне_шаблонов)}: {имена}")
    поза = "PASS" if сколько <= БЕЗ_ПОКАЗА_РУБЕЖ else "FAIL"
    print(f"ФОРМА БЕЗ ПОКАЗА {поза}: объявлено {всего}, показано {показано} ({доля:.0f} %), "
          f"без показа {сколько} (рубеж {БЕЗ_ПОКАЗА_РУБЕЖ}); пакетов {len(пакеты)}"
          + (f", без пласта {без_слоя}" if без_слоя else ""))
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
