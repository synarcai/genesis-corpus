#!/usr/bin/env python3
"""[КРИВАЯ ПО МИРАМ] — какой мир даёт охват, и во что обходится срез.

holon (03.09): суды на срезах идут минуты вместо форжа, но срез до сих пор
выбирался массой на глаз. Закон среза он назвал так: «срез = ≥ LAW² показов
на КАЖДУЮ рамку КАЖДОГО мира». Прибор считает цену этого закона и говорит,
какие миры её составляют.

Три числа на мир:
  РАМКИ        — сколько различных рамок (родов переписи) мир держит;
  СОБСТВЕННЫЕ  — сколько из них не встречаются больше НИГДЕ: это тот охват,
                 который исчезнет вместе с миром;
  СРЕЗ         — сколько строк мир даёт в срез по закону (≤ LAW² показов на
                 рамку, счёт ведётся В ПРЕДЕЛАХ МИРА, ибо закон именно так и
                 назван: каждая рамка каждого мира).

Отсюда две кривые. Первая — по массе: сколько строк стоит срез при массе 1,
3, 5, 9, 13, 20. Вторая — по мирам: если брать миры в порядке убывания
собственных рамок, сколько миров нужно, чтобы покрыть половину, четыре пятых
и девятнадцать двадцатых всех рамок свода.

ЭТО КАРТА ЦЕНЫ, А НЕ ПРИГОВОР МИРАМ. Мир с малым числом собственных рамок не
хуже: он может держать массу, которой покупается форма соседа. Прибор говорит
лишь, что исчезнет, если его вынуть, — и во что обходится то, что он даёт.

    python3 scripts/world_curve.py [--массы 1,3,5,9,13,20] [--сколько 25]
"""
import argparse
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import form_census as C  # noqa: E402
from minimal_build import куски_сборки  # noqa: E402


def перепись(сборка="full"):
    """[(мир, [роды строк])] — рода каждой строки каждого мира, один проход."""
    вон = []
    for имя, тело in куски_сборки(сборка):
        роды = [C.род(C.скелет(с)) for с in тело.splitlines() if с.strip()]
        вон.append((имя, роды))
    return вон


def срез_мира(роды, масса):
    """Сколько строк мир даёт в срез, где счёт идёт в пределах МИРА."""
    видано = collections.Counter()
    строк = 0
    for р in роды:
        if видано[р] < масса:
            видано[р] += 1
            строк += 1
    return строк


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--массы", default="1,3,5,9,13,20")
    ап.add_argument("--сколько", type=int, default=25)
    а = ап.parse_args()
    массы = [int(м) for м in а.массы.split(",") if м.strip()]
    миры = перепись()
    где = collections.defaultdict(set)
    for имя, роды in миры:
        for р in роды:
            где[р].add(имя)
    всего_рамок = len(где)
    всего_строк = sum(len(роды) for _, роды in миры)

    строки_таблицы = []
    for имя, роды in миры:
        свои = {р for р in роды if len(где[р]) == 1}
        строки_таблицы.append((имя, len(роды), len(set(роды)), len(свои),
                               срез_мира(роды, C.LAW2)))
    строки_таблицы.sort(key=lambda з: -з[3])

    print(f"КРИВАЯ ПО МИРАМ: миров {len(миры)}, строк {всего_строк}, "
          f"рамок {всего_рамок}, LAW² = {C.LAW2}")
    print("  ЦЕНА ЗАКОНА СРЕЗА (≤ масса показов на рамку В ПРЕДЕЛАХ МИРА):")
    for м in массы:
        строк = sum(срез_мира(роды, м) for _, роды in миры)
        print(f"    масса {м:3}: {строк:7} строк ({100 * строк // max(1, всего_строк):3} % свода)")
    print(f"  МИРЫ ПО СОБСТВЕННЫМ РАМКАМ (первые {а.сколько}):")
    print(f"    {'мир':28} {'строк':>7} {'рамок':>7} {'своих':>7} {'срез':>7}")
    for имя, строк, рамок, свои, срез in строки_таблицы[:а.сколько]:
        print(f"    {имя[:28]:28} {строк:7} {рамок:7} {свои:7} {срез:7}")

    накоплено, взято = set(), 0
    рубежи = {50: None, 80: None, 95: None, 100: None}
    for имя, роды in sorted(миры, key=lambda з: -len({р for р in з[1] if len(где[р]) == 1})):
        накоплено |= set(роды)
        взято += 1
        доля = 100 * len(накоплено) // всего_рамок
        for рубеж in sorted(рубежи):
            if рубежи[рубеж] is None and доля >= рубеж:
                рубежи[рубеж] = (взято, len(накоплено))
    print("  СКОЛЬКО МИРОВ ДЕРЖАТ ОХВАТ РАМОК (в порядке убывания собственных):")
    for рубеж in sorted(рубежи):
        если = рубежи[рубеж]
        if если:
            print(f"    {рубеж:3} % рамок — {если[0]:3} миров ({если[1]} рамок)")
    одиночки = sum(1 for р, м in где.items() if len(м) == 1)
    print(f"  рамок, живущих в одном мире: {одиночки} из {всего_рамок} "
          f"({100 * одиночки // всего_рамок} %)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
