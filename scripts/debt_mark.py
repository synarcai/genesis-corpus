#!/usr/bin/env python3
"""[МЕТКА ДОЛГА] — рубеж, объявленный меткой, против рубежа, действующего в законе.

Всякий здешний прибор, стерегущий долг, объявляет его машиночитаемой меткой

    # РУБЕЖ-ДОЛГА: ИМЯ_РУБЕЖ = N

и тут же — иногда через полсотни строк объяснения — кладёт сам закон `ИМЯ_РУБЕЖ = N`.
Метка есть ЗАГОЛОВОК объявления: по ней читатель и всякая будущая рука узнают долг корпуса
одним обходом, не читая ста строк рассуждения. Закон есть то, ЧЕМ ПРИБОР ПАДАЕТ.

    ДВА ЧИСЛА, НАЗЫВАЮЩИЕ ОДИН ДОЛГ, СУТЬ ОДНО ЧИСЛО ИЛИ ОДНА ЛОЖЬ.

ПОВОД, НАЙДЕННЫЙ ЗАМЕРОМ (08.09). Меток 113, разошедшихся — восемь, и все восемь разошлись
ВНИЗ: метка называет старый, БОЛЬШИЙ долг, чем действующий закон. Долг платили — метку не
переписывали. Худший случай нашёлся у соседа `word_mutants`: метка говорит 232, а сам её
комментарий двадцатью строками ниже РАССКАЗЫВАЕТ, как долг упал до 107, и закон стоит на 107.
Объявление противоречит себе на протяжении одного абзаца, и никто не падал.

    МЕТКА, ОТСТАВШАЯ ВНИЗ, НЕ ПРОПУСКАЕТ ЛЖИ — ОНА ЛЖЁТ О ЦЕНЕ РАБОТЫ. Читатель, считающий
    долг корпуса по меткам, насчитал бы 1097 там, где закон держит 573: почти вдвое.

ОБРАТНОЕ РАСХОЖДЕНИЕ ХУЖЕ И ПОКА НЕ СЛУЧАЛОСЬ. Метка, говорящая 0 при законе 20, ПРЯЧЕТ долг:
обход меток показывает закрытую позицию, а прибор молча пропускает двадцать порч. Оттого класс
СКРЫТЫЙ стережётся отдельным нулём, а не общим числом, — он есть иной род вины, а не худшая
степень того же.

    ПРИЗНАК ЧИСТ И НЕ СПРАШИВАЕТ О ПРАВИЛЬНОСТИ ЧИСЛА. Прибор не судит, хорош ли рубеж 107;
    он спрашивает лишь, ОДНО ЛИ ЧИСЛО названо дважды. Оттого он не стареет вместе с корпусом:
    всякая честная храповая правка проходит его, всякая забытая — роняет.

ЗАКОН БЕРЁТСЯ БЛИЖАЙШИЙ СНИЗУ, А НЕ ПЕРВЫЙ В ФАЙЛЕ, и берётся на ЛЮБОМ отступе: у соседа
`reproducible` два рубежа объявлены внутри тела, и первая редакция этой меры звала их
«без закона», ища присвоение только от начала строки. Мера, читающая объявление уже́, чем
язык его пишет, находит порок в своей слепоте и зовёт его пороком корпуса.

    python3 scripts/debt_mark.py [--подробно] [--папки scripts tools courts]
"""
# ПУСТОЙ-ОБХОД: --папки no-such-dir
import argparse
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 0
#
# НОЛЬ ОТ РОЖДЕНИЯ И БЕЗ ЛЬГОТЫ: восемь расхождений, найденных первым замером, исправлены
# в тот же час — правка стоит одной строки на прибор и не трогает ни закона, ни страницы.
# Долг, чья цена есть переписать восемь чисел, не объявляется числом первого замера: он
# закрывается. Рубеж, поставленный на 8, был бы запасом, а не долгом.
РАЗЛАДОВ_РУБЕЖ = 0

# РУБЕЖ-ДОЛГА: СКРЫТЫХ_РУБЕЖ = 0
#
# ИНОЙ РОД ВИНЫ, А НЕ ХУДШАЯ СТЕПЕНЬ. Метка, называющая долг МЕНЬШЕ действующего закона,
# прячет разницу от всякого обхода меток. Такого не случалось ни разу — и оттого рубеж
# есть ноль от рождения и навсегда, а не «достигнутое».
СКРЫТЫХ_РУБЕЖ = 0

МЕТКА = re.compile(r"^\s*#\s*РУБЕЖ-ДОЛГА:\s*([А-ЯЁ_A-Z][\w]*)\s*=\s*(-?\d+)\s*$")
ПАПКИ = ("scripts", "tools", "courts")


def закон(текст, имя, с_какой):
    """Ближайшее снизу присвоение `имя = <целое>` на любом отступе — или None."""
    правило = re.compile(rf"^[ \t]*{re.escape(имя)}\s*=\s*(-?\d+)\s*(?:#.*)?$")
    for номер, строка in enumerate(текст[с_какой:], start=с_какой):
        м = правило.match(строка)
        if м:
            return int(м.group(1)), номер + 1
    return None, None


def обход(папки):
    вон = []
    for папка in папки:
        корень = КОРЕНЬ / папка
        if not корень.is_dir():
            continue
        for путь in sorted(корень.rglob("*.py")):
            строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
            for номер, строка in enumerate(строки):
                м = МЕТКА.match(строка)
                if not м:
                    continue
                имя, объявлено = м.group(1), int(м.group(2))
                действует, где = закон(строки, имя, номер + 1)
                вон.append((путь.relative_to(КОРЕНЬ), номер + 1, имя, объявлено, действует, где))
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что МЕТКА УЗНАЁТСЯ и что закон под ней
    находится — БЛИЖАЙШИЙ СНИЗУ, а не какой попало.

        ЭТОТ ПРИБОР СТЕРЕЖЁТ ВСЕ РУБЕЖИ СВОДА, И ЗЕЛЕНЬ ЕГО ЕСТЬ РАВЕНСТВО ДВУХ ЧИСЕЛ,
        КОТОРЫЕ ОН ЖЕ И НАХОДИТ. Пусть признак метки перестанет узнавать её — и меток
        станет НОЛЬ, а прибор откажет (это видно). Но пусть перестанет находиться ЗАКОН
        — и всякая метка уйдёт в «без закона», а согласных станет ноль при нуле разладов:
        число, неотличимое от здоровья, покуда не спросишь, ЧТО ИМЕННО сверено.

    Семь строк, и про каждую известно заранее, что прибор обязан из них взять.
    """
    беды = []
    текст = ["# РУБЕЖ-ДОЛГА: ПЕРВЫЙ = 7",
             "ПЕРВЫЙ = 7",
             "",
             "# РУБЕЖ-ДОЛГА: ВТОРОЙ = 3",
             "# между меткой и законом стои́т речь, и это не помеха",
             "    ВТОРОЙ = 5   # закон с отступом и хвостом",
             "ПЕРВЫЙ = 999"]
    for строка, ждём in ((текст[0], ("ПЕРВЫЙ", 7)), (текст[3], ("ВТОРОЙ", 3)),
                         (текст[4], None), ("ПЕРВЫЙ = 7", None)):
        м = МЕТКА.match(строка)
        дало = (м.group(1), int(м.group(2))) if м else None
        if дало != ждём:
            беды.append(f"метка «{строка[:40]}»: {дало}, а надо {ждём}")
    # ЗАКОН БЕРЁТСЯ БЛИЖАЙШИЙ СНИЗУ — И ИМЕННО СНИЗУ.
    if закон(текст, "ПЕРВЫЙ", 1) != (7, 2):
        беды.append(f"закон ПЕРВЫЙ: {закон(текст, 'ПЕРВЫЙ', 1)} вместо (7, 2)")
    if закон(текст, "ВТОРОЙ", 4) != (5, 6):
        беды.append(f"закон ВТОРОЙ с отступом: {закон(текст, 'ВТОРОЙ', 4)} вместо (5, 6)")
    if закон(текст, "ТРЕТИЙ", 0) != (None, None):
        беды.append("имя без закона нашлось")
    # И ГЛАВНОЕ: РАЗЛАД ОБЯЗАН БЫТЬ ВИДЕН. Метка ВТОРОЙ говорит 3, закон говорит 5.
    объявлено, (действует, _где) = 3, закон(текст, "ВТОРОЙ", 4)
    if объявлено == действует:
        беды.append("РАЗЛАД НЕ ВИДЕН: метка и закон сошлись там, где расходятся")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"МЕТКА ДОЛГА ОТКАЗ: прибор не доказал, что сверяет ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--папки", nargs="+", default=list(ПАПКИ))
    дов = ап.parse_args()
    метки = обход(дов.папки)
    if not метки:
        print(f"МЕТКА ДОЛГА ОТКАЗ: меток не найдено в {' '.join(дов.папки)}")
        return 2

    согласны, отстали, скрыли, без_закона = [], [], [], []
    for запись in метки:
        _путь, _строка, _имя, объявлено, действует, _где = запись
        if действует is None:
            без_закона.append(запись)
        elif действует == объявлено:
            согласны.append(запись)
        elif объявлено > действует:
            отстали.append(запись)
        else:
            скрыли.append(запись)

    print(f"меток {len(метки)} в {len(set(з[0] for з in метки))} приборах")
    print(f"  согласны       {len(согласны):>4}")
    print(f"  ОТСТАЛИ ВНИЗ   {len(отстали):>4}   (метка называет долг БОЛЬШЕ закона)")
    print(f"  СКРЫЛИ         {len(скрыли):>4}   (метка называет долг МЕНЬШЕ закона)")
    print(f"  БЕЗ ЗАКОНА     {len(без_закона):>4}   (метка есть, присвоения ниже нет)")
    for имя_класса, ряд in (("ОТСТАЛА", отстали), ("СКРЫЛА", скрыли), ("БЕЗ ЗАКОНА", без_закона)):
        for путь, строка, имя, объявлено, действует, где in ряд:
            хвост = f"закон {действует} (строка {где})" if действует is not None else "закона нет"
            print(f"  {имя_класса} {путь}:{строка} {имя}: метка {объявлено}, {хвост}")
    if дов.подробно:
        print("  — согласные —")
        for путь, строка, имя, объявлено, _д, где in согласны:
            print(f"    {путь}:{строка} {имя} = {объявлено} (закон строка {где})")

    сумма_меток = sum(з[3] for з in метки if з[4] is not None)
    сумма_законов = sum(з[4] for з in метки if з[4] is not None)
    разладов = len(отстали) + len(без_закона)
    поза = "PASS" if разладов <= РАЗЛАДОВ_РУБЕЖ and len(скрыли) <= СКРЫТЫХ_РУБЕЖ else "FAIL"
    print(f"МЕТКА ДОЛГА {поза}: разладов {разладов} (рубеж {РАЗЛАДОВ_РУБЕЖ}), "
          f"скрытых {len(скрыли)} (рубеж {СКРЫТЫХ_РУБЕЖ}); "
          f"долг по меткам {сумма_меток}, по законам {сумма_законов}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
