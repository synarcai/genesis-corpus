#!/usr/bin/env python3
"""[СЛОВО ШАБЛОНА БЕЗ ОБЪЯВЛЕНИЯ] — литерал, которым пакет пишет, но которого не объявляет.

    СТРОКА БЕЗ ЕДИНОГО ОБЪЯВЛЕННОГО СЛОВА БЕЗЗАЩИТНА: ЕЁ СУДИТ ВСЯКИЙ, КТО УЗНАЛ В НЕЙ
    СВОЁ СЛОВО.

ПОЧЕМУ ЭТО ДОЛГ, А НЕ МЕЛОЧЬ. Знак языка (`tools/langsign.py`) считается по словам, которые
пакеты ОБЪЯВИЛИ. Польский шаблон пишет «liczę {n} {lex:noun_count:by_n}.», и слово «liczę» не
объявлено ни одним пакетом; строка «liczę 2 ruble.» получает знак ноль ото ВСЕХ языков, и суд
чужого языка, узнавший в ней «ruble», судит её своим счётом и зовёт ложью честную польскую
речь. Так и случилось 07.09, и цена была снятое объявление — то есть ослепший суд.

    ПАКЕТ, ПИШУЩИЙ СЛОВОМ, КОТОРОГО НЕ ОБЪЯВЛЯЕТ, ОТДАЁТ СВОИ СТРОКИ ЧУЖИМ СУДАМ.

ЧТО СЧИТАЕТСЯ ОБЪЯВЛЕНИЕМ. Всякое поле пакета, кроме самих шаблонов: служебные слова, лексемы
классов, плоский указатель имён, числительные, лексикон вида показа, слова отказа, вопросные
слова, пробные слова. Мера щедра нарочно: она ищет не «объявлено ли как надо», а «объявлено ли
ВООБЩЕ ХОТЬ ГДЕ-НИБУДЬ В СВОЁМ ПАКЕТЕ».

ЧЕГО МЕРА НЕ СЧИТАЕТ, И ЭТО СКАЗАНО, А НЕ СКРЫТО. Пакеты письма без пробелов (`segmentation:
longest-match` — китайский, японский, тайский) не считаются вовсе: разбор на слова по краю
слова там даёт не слова, а куски («是东西», «があります»), и мера мерила бы собственную
слепоту. Их долг, если он есть, требует иной меры — по словарю самого письма.

    python3 scripts/template_word.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --пакеты no-such-dir
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: НЕОБЪЯВЛЕННЫХ_РУБЕЖ = 30
#
# РУБЕЖ ОБЪЯВЛЕН ПО ДОСТИГНУТОМУ: тридцать слов в тринадцати пакетах в час постановки.
# Это ПОТОЛОК, и цена его снижения есть одна строка объявления на слово — но строка эта
# ДОЛЖНА БЫТЬ ВЕРНОЙ: объявить «liczę» польским значит дать польскому суду право на всякую
# строку с этим словом, и потому объявление кладётся в тот класс, которому слово вправду
# принадлежит, а не в первый попавшийся.
НЕОБЪЯВЛЕННЫХ_РУБЕЖ = 30

# АПОСТРОФ ВНУТРИ СЛОВА НЕ РАЗРЕЗАЕТ ЕГО. Разбор по краю слова делил итальянское «cos'è»
# на «cos» и «è» и требовал объявить «cos» — обрубок, которого в языке нет. Стяжение есть
# ОДНО слово письма, и объявляться должно целиком.
СЛОВО = re.compile(r"[^\W\d_]+(?:['’][^\W\d_]+)*")
ДЫРА = re.compile(r"\{[^}]*\}")


def объявленное(пак):
    """Всё, что пакет объявил ЛЮБЫМ полем, кроме самих шаблонов."""
    вон = set()

    def взять(x):
        if isinstance(x, str):
            вон.update(w.lower() for w in СЛОВО.findall(x))
        elif isinstance(x, dict):
            for k, v in x.items():
                взять(k); взять(v)
        elif isinstance(x, (list, tuple)):
            for v in x:
                взять(v)

    for поле, знач in пак.items():
        if поле == "show_kinds":
            continue
        взять(знач)
    for _и, вид in (пак.get("show_kinds") or {}).items():
        for поле in ("lexicon", "ops", "words", "concepts", "reasons"):
            взять(вид.get(поле))
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--пакеты", default=None, help="иная папка пакетов")
    дов = ап.parse_args()
    папка = (pathlib.Path(дов.пакеты) if дов.пакеты
             else КОРЕНЬ / "tools" / "langpacks")
    пакеты = sorted(папка.glob("*.json")) if папка.is_dir() else []
    if not пакеты:
        print(f"СЛОВО ШАБЛОНА ОТКАЗ: пакетов нет в «{папка}»")
        return 2
    итог, слитных, всего_слов = [], [], 0
    for п in пакеты:
        пак = json.loads(п.read_text(encoding="utf-8"))
        я = пак.get("lang", п.stem)
        if пак.get("segmentation") == "longest-match":
            слитных.append(я)
            continue
        объ = объявленное(пак)
        свои = collections.Counter()
        for _имя, вид in (пак.get("show_kinds") or {}).items():
            for ш in (вид.get("templates") or []):
                for w in СЛОВО.findall(ДЫРА.sub(" ", ш)):
                    всего_слов += 1
                    if w.lower() not in объ:
                        свои[w.lower()] += 1
        if свои:
            итог.append((я, свои))
    сколько = sum(len(с) for _я, с in итог)
    print(f"{'язык':<6}{'необъявленных':>15}")
    for я, с in sorted(итог, key=lambda x: -len(x[1])):
        видно = ", ".join(w for w, _ in с.most_common(None if дов.подробно else 8))
        print(f"{я:<6}{len(с):>15}   {видно}")
    if слитных:
        print(f"  ПИСЬМО БЕЗ ПРОБЕЛОВ (не считано): {', '.join(слитных)}")
    поза = "PASS" if сколько <= НЕОБЪЯВЛЕННЫХ_РУБЕЖ else "FAIL"
    print(f"СЛОВО ШАБЛОНА БЕЗ ОБЪЯВЛЕНИЯ {поза}: разных слов {сколько} "
          f"(рубеж {НЕОБЪЯВЛЕННЫХ_РУБЕЖ}) в {len(итог)} пакетах из "
          f"{len(пакеты) - len(слитных)} считанных; слов в шаблонах {всего_слов}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
