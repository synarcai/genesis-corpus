#!/usr/bin/env python3
"""МУТАНТЫ СУДОВ: способен ли суд назвать ложью то, что ложно.

ЗЕЛЕНЬ СУДА ГОВОРИТ ДВЕ РАЗНЫЕ ВЕЩИ, И СНАРУЖИ ОНИ НЕОТЛИЧИМЫ: либо в
корпусе нет лжи ЕГО РОДА, либо суд своего рода не видит вовсе. Сорок
с лишним суда объявляют `ЛОЖНЫХ_РУБЕЖ = 0`, и все сегодня зелены;
счётчик отказов, никогда не двигавшийся, есть либо здоровье, либо
оторванный провод. Различить может только подсадка.

ЧТО ДЕЛАЕТ ПРИБОР. Для каждого суда, читающего СТРОКУ, он берёт из
корпуса строку, которую ЭТОТ суд зовёт истиной, портит её РОВНО В
ОДНОМ МЕСТЕ — одно число на соседнее — и спрашивает снова.

ПАРА ОБЯЗАТЕЛЬНА. Мутант без честного близнеца не доказывает ничего:
он мог не дойти до места. Близнец здесь есть та же строка без порчи, и
он берётся не из головы, а ИЗ КОРПУСА — то есть заведомо читается
судом и заведомо зовётся истиной, ибо по этому признаку и найден.

ЧЕТЫРЕ ИСХОДА, И РАЗЛИЧАТЬ ИХ ОБЯЗАТЕЛЬНО:

    ПОЙМАН      — суд сказал о порче «ложь». Провод подключён.
    НЕ ПОЙМАН   — суд сказал о порче «истина». Место, которое он
                  обещал мерить, он не мерит: находка о суде.
    ОНЕМЕЛ      — суд сказал «несудимо». Это НЕ ПОРОК сам по себе:
                  суд, чья мера есть принадлежность объявленному,
                  честно немеет на неизвестном, а ворота записи
                  несудимую строку и так не пропустят. Но исход иной,
                  и смешивать его с поимкой нельзя.
    НЕТ ЧИСЛА   — суд читает истинные строки, но ни одна из них не
                  несёт числа. Числовая подсадка к такому роду
                  НЕПРИМЕНИМА, и суд остаётся НЕДОКАЗАННЫМ — это
                  долг прибора, а не суда, и он назван числом.

ПЯТЫЙ ИСХОД БЫЛ БЫ ХУДШИМ ИЗ ВСЕХ: суд, у которого во всём корпусе нет
НИ ОДНОЙ строки, зовомой истиной, зелен вечно и не меряет ничего.
Сегодня таких нет, и прибор проверяет это ПОЛНЫМ обходом, а не
выборкой: суд, не нашедший строки по первым строкам мира, ищет по
всему корпусу, прежде чем быть названным пустым.

ДОВОДЫ СУДЬИ ВЫВОДЯТСЯ ИЗ ЕГО ПОДПИСИ, А НЕ ПЕРЕЧИСЛЯЮТСЯ СПИСКОМ.
Четырём судам нужен второй довод — словарь чисел, имена знаков, слой
файла, — и прибор узнаёт об этом, прочитав имена параметров `судить` и
взяв одноимённое из палаты. Список «этим четырём — так, прочим —
иначе» разошёлся бы с палатой в первый же день, когда появится пятый.

ДВЕ НАХОДКИ ПЕРВОГО ЖЕ ПРОГОНА, И ОБЕ ЗАПИСАНЫ ЗДЕСЬ, А НЕ ПОЧИНЕНЫ:

    markup — номер пункта упорядоченного списка не судится никем
        (см. рубеж ниже): «1. water.», «2. water.», «3. water.» —
        все три истинны на одном слое;
    inquiry_pt_nl — суд, не прочётший НИ ОДНОЙ строки корпуса. Его
        генератор написан, мир не построен и в манифест не объявлен, и
        потому суд зелен, не прочитав ничего. Это ровно тот исход,
        ради которого прибор и заведён: зелень без чтения.

ПРИБОР НИЧЕГО НЕ ПИШЕТ И НИЧЕГО НЕ ЧИНИТ. Суды общие; найденное здесь
называется, а не правится.
"""

import collections
import importlib
import inspect
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
for _где in ("courts", "tools", "scripts"):
    sys.path.insert(0, str(КОРЕНЬ / _где))
import genesis  # noqa: E402
import panel  # noqa: E402

# РУБЕЖ-ДОЛГА: НЕ_ПОЙМАНО_РУБЕЖ = 1
#
# ОДИН СУД ПОДСАДКУ НЕ ЛОВИТ, И ЭТО ЗАМЕР, А НЕ ДОПУЩЕНИЕ.
#
# markup — НОМЕР ПУНКТА СПИСКА НЕ СУДИТСЯ НИКЕМ. Ветвь `ПУНКТ` суда
# разметки берёт из совпадения ПОСЛЕДНЮЮ группу — слово пункта — и
# сверяет её принадлежность объявленным пунктам слоя; порядковый номер
# образец захватывает, но с объявлением не сличает никогда. Замерено:
# «1. water.», «2. water.», «3. water.» — все три (True, True) на одном
# и том же слое. Мир вправе перенумеровать свой упорядоченный список
# как угодно, и ни один суд корпуса этого не заметит.
НЕ_ПОЙМАНО_РУБЕЖ = 1

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest

# Сколько первых строк мира читать в первом обходе. Миры однородны и
# перетасованы, и потому род суда, живущий в мире, встречается в его
# начале. Суд, не нашедший строки за этот предел, ищет по ВСЕМУ
# корпусу: утверждение «истинных строк нет вовсе» слишком тяжело,
# чтобы делать его по выборке.
ПЕРВЫЙ_ПРЕДЕЛ = 400

# Сколько разных истинных строк пробовать одному суду, прежде чем
# назвать исход. Одна строка может не иметь числа, годного для порчи
# (число бывает номером, а не величиной), и тогда нужна следующая.
КАНДИДАТОВ = 12

ПОЙМАН, НЕ_ПОЙМАН, ОНЕМЕЛ = "ПОЙМАН", "НЕ ПОЙМАН", "ОНЕМЕЛ"
НЕТ_ЧИСЛА, ПУСТ = "НЕТ ЧИСЛА", "НЕТ ИСТИННОЙ СТРОКИ"
СВОБОДНО = "ЧИСЛО СВОБОДНО"
ЧИСЛО = re.compile(r"\d+")


def свободные_места(суд, строка):
    """Промежутки строки, где число НЕ НЕСЁТ ИСТИНЫ ПО ПРАВИЛУ ЯЗЫКА.

    ПОДСАДКА В СВОБОДНОЕ МЕСТО НИЧЕГО НЕ ДОКАЗЫВАЕТ. Первый прогон
    объявил суд разметки слепым: «1. water» → «2. water», и суд назвал
    испорченное истиной. Но порчи не было. По CommonMark номера пунктов
    после первого отбрасываются рендерером — «1. 1. 1.» и «1. 2. 3.»
    дают одну страницу, и число там не утверждает о порядке ничего.
    Суд мерил ИМЯ пункта, то есть ровно то, что несёт истину; слеп был
    ПРИБОР, не знавший, что бывают свободные места.

    Место объявляется САМИМ СУДОМ (`СВОБОДНОЕ_ЧИСЛО`), ибо знание о
    том, где язык не хранит смысла, есть знание о языке, и живёт оно
    там же, где прочие правила этого языка. Прибор его ЧИТАЕТ, а не
    угадывает, и умолчание суда значит «свободных мест нет».
    """
    места = []
    for правило in getattr(суд, "СВОБОДНОЕ_ЧИСЛО", ()):
        for м in правило.finditer(строка):
            # группа 1 есть само число; без групп свободен весь захват
            места.append(м.span(1) if м.groups() else м.span())
    return места


def суды():
    """{имя: (модуль, имена доводов сверх строки)} — все судьи СТРОКИ.

    ОТБОР ИДЁТ ПО ПОДПИСИ, А НЕ ПО СПИСКУ. Суд, судящий ФАЙЛ или
    ПАКЕТ (`судить(путь, закон)`, `судить_пакет`, `судить_файл`), сюда
    не попадает сам собою: у него иной предмет, и числовая подсадка в
    строку ему не адресуется. Отказ суда при загрузке («источника нет,
    судить не вправе») тоже не валит прибор — такой суд просто
    отсутствует, как в палате.
    """
    вон = {}
    for каталог in ("courts", "scripts"):
        for файл in sorted((КОРЕНЬ / каталог).glob("*.py")):
            if файл.name == pathlib.Path(__file__).name:
                continue
            try:
                модуль = importlib.import_module(файл.stem)
            except (Exception, SystemExit):
                continue
            судья = getattr(модуль, "судить", None)
            if судья is None:
                continue
            try:
                имена = list(inspect.signature(судья).parameters)
            except (TypeError, ValueError):
                continue
            if имена and имена[0] == "строка":
                вон[файл.stem] = (модуль, имена[1:])
    return вон


def короткое(имя):
    return имя[:-len("_court")] if имя.endswith("_court") else имя


def спросить(суд, доводы_имена, строка, снаряга):
    """(судимо, истинно) от одного суда о одной строке.

    ОТКАЗ СУДА О СТРОКЕ ЕСТЬ МОЛЧАНИЕ О НЕЙ, а не обвал прибора: тот
    же закон, каким живёт палата.
    """
    доводы = {и: снаряга[и] for и in доводы_имена if и in снаряга}
    try:
        # СУД, РЕЖУЩИЙ СТРОКУ НА ПРЕДЛОЖЕНИЯ, СПРАШИВАЕТСЯ ЕГО ЖЕ
        # РЕЗКОЙ: одна строка часто несёт несколько утверждений, и
        # число из первого втекало бы в равенство второго.
        if hasattr(суд, "предложения"):
            части = [суд.судить(ч, **доводы)
                     for ч in суд.предложения(строка)]
            return next((р for р in части if р[0]), (False, True))
        return суд.судить(строка, **доводы)
    except (Exception, SystemExit):
        return False, False


def порчи(строка, свободные=()):
    """Все подсадки строки: каждое её число — на соседнее, по одному.

    ПОРЧА ЕСТЬ ОДНА ПРАВКА, И ТОЛЬКО ОДНА. Строка с тремя числами даёт
    три разных мутанта, а не одного с тремя правками: подсадка,
    задевшая три места, не сказала бы, какое из них суд читает.

    Числа, стоящие в объявленных судом СВОБОДНЫХ местах, пропускаются:
    подсадка туда не есть порча, и вердикт «истина» о ней честен.
    """
    for м in ЧИСЛО.finditer(строка):
        if any(a <= м.start() and м.end() <= b for a, b in свободные):
            continue
        было = int(м.group())
        yield (строка[:м.start()] + str(было + 1) + строка[м.end():],
               м.start())


def вырезка(строка, место, ширина=44):
    """Окно строки ВОКРУГ правки: пара видна лишь там, где разошлась.

    Обрезка с начала прятала правку, стоявшую в хвосте, и две строки
    отчёта выглядели одинаковыми — отчёт, в котором подсадки не видно,
    доказывает читателю ровно ничего.
    """
    начало = max(0, место - ширина // 3)
    кусок = строка[начало:начало + ширина]
    return ("…" if начало else "") + кусок + (
        "…" if начало + ширина < len(строка) else "")


def испытать(суд, доводы_имена, строка, снаряга):
    """Исход подсадки на одной честной строке, или None — числа нет."""
    лучшее = None
    свободные = свободные_места(суд, строка)
    порченые = list(порчи(строка, свободные))
    # Строка, ВСЕ числа которой свободны, не есть материал для пробы, и
    # молчание о ней честнее любого исхода: назвать её «не пойманной»
    # значило бы вменить суду отказ мерить то, что смысла не несёт.
    if not порченые and свободные:
        return СВОБОДНО, строка, свободные[0][0]
    for порча, место in порченые:
        судимо, истинно = спросить(суд, доводы_имена, порча, снаряга)
        if судимо and not истинно:
            return ПОЙМАН, порча, место
        исход = НЕ_ПОЙМАН if судимо else ОНЕМЕЛ
        # НЕ ПОЙМАН ХУЖЕ, ЧЕМ ОНЕМЕЛ, и потому вытесняет его в отчёте:
        # суд, назвавший испорченное истинным, сказал о себе больше,
        # чем суд, честно промолчавший.
        if лучшее is None or (лучшее[0] == ОНЕМЕЛ and исход == НЕ_ПОЙМАН):
            лучшее = (исход, порча, место)
    return лучшее


def обход():
    """Миры показов, или честный отказ."""
    if "--manifest" in sys.argv:
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        return [п for п in genesis.worlds(kind="shows") if п.is_file()]
    except genesis.Unreadable as беда:
        print(f"МУТАНТЫ СУДОВ ОТКАЗ: {беда}")
        sys.exit(2)


def пройти(все_суды, палата, пути, предел, ждут, итоги):
    """Один обход корпуса: искать честную строку и тут же портить её.

    ПОДСАДКА СТАВИТСЯ НА МЕСТЕ, А НЕ ПОСЛЕ ОБХОДА. Слои файла живут в
    состоянии судов (`палата.слои` их впитывает), и строка, унесённая
    из своего мира, судилась бы уже чужим слоем — то есть близнец
    перестал бы быть близнецом.
    """
    for путь in пути:
        if not ждут:
            return
        слои = палата.слои(путь)
        строки = []
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for номер, строка in enumerate(поток):
                if предел is not None and номер >= предел:
                    break
                if строка.strip():
                    строки.append(строка.rstrip("\n"))
        for имя in list(ждут):
            суд, доводы_имена = все_суды[имя]
            снаряга = {"словарь": палата.словарь, "знаки": палата.знаки,
                       "слой": слои.get(короткое(имя))}
            учёт = итоги.setdefault(имя, {"исход": ПУСТ, "честно": None,
                                          "порча": None, "мир": None,
                                          "место": 0, "истинных": 0,
                                          "с_числом": 0, "судимых": 0})
            for честно in строки:
                вердикт = спросить(суд, доводы_имена, честно, снаряга)
                # ЧИТАЕТ ЛИ СУД ХОТЬ ЧТО-НИБУДЬ — вопрос отдельный от
                # того, зовёт ли он это истиной, и различать их надо.
                # Суд, не прочётший НИ ОДНОЙ строки корпуса, молчит не
                # потому, что корпус чист, а потому, что его мира здесь
                # нет вовсе: так выглядит суд, чей генератор написан, а
                # мир ещё не построен и в манифест не объявлен.
                учёт["судимых"] += вердикт[0]
                if вердикт != (True, True):
                    continue
                учёт["истинных"] += 1
                if учёт["исход"] == ПУСТ:
                    учёт["исход"] = НЕТ_ЧИСЛА
                    учёт["мир"] = путь.name
                если = испытать(суд, доводы_имена, честно, снаряга)
                if если is None:
                    continue
                исход, порча, место = если
                # СТРОКА, ГДЕ ПОДСАДКА НЕПРИМЕНИМА, НЕ ТРАТИТ КВОТУ.
                # Предел кандидатов считает строки, ГОДНЫЕ для пробы;
                # строка, все числа которой свободны, не материал, и
                # засчитывать её значило бы прекращать поиск, ничего
                # не испытав. Суд разметки так и оставался «свободным»,
                # исчерпав предел на тринадцати пунктах списка, тогда
                # как заголовки его слоя несут числа не свободные.
                if исход != СВОБОДНО:
                    учёт["с_числом"] += 1
                прежде = учёт["исход"]
                # ПОЙМАН вытесняет всё, НЕ ПОЙМАН — всё кроме поимки.
                вес = {НЕТ_ЧИСЛА: 0, СВОБОДНО: 1, ОНЕМЕЛ: 2,
                       НЕ_ПОЙМАН: 3, ПОЙМАН: 4}
                if вес[исход] > вес.get(прежде, 0):
                    учёт.update(исход=исход, честно=честно, порча=порча,
                                место=место, мир=путь.name)
                if учёт["исход"] == ПОЙМАН:
                    break
                if учёт["с_числом"] >= КАНДИДАТОВ:
                    break
            if учёт["исход"] == ПОЙМАН:
                ждут.discard(имя)


def main():
    пути = обход()
    if not пути:
        print("МУТАНТЫ СУДОВ ОТКАЗ: обход пуст, испытывать не на чем")
        return 2
    все_суды = суды()
    if not все_суды:
        print("МУТАНТЫ СУДОВ ОТКАЗ: судов со строковой подписью нет")
        return 2
    палата = panel.Палата()

    итоги = {}
    ждут = set(все_суды)
    пройти(все_суды, палата, пути, ПЕРВЫЙ_ПРЕДЕЛ, ждут, итоги)
    # ВТОРОЙ ОБХОД — ПОЛНЫЙ, И ТОЛЬКО ДЛЯ НЕДОКАЗАННЫХ. Утверждение
    # «у суда нет истинной строки» есть тягчайшее из здешних, и делать
    # его по первым четырёмстам строкам мира нельзя.
    ещё = {и for и in ждут if итоги.get(и, {}).get("исход") in
           (ПУСТ, НЕТ_ЧИСЛА, СВОБОДНО, ОНЕМЕЛ, НЕ_ПОЙМАН)} | (
        set(все_суды) - set(итоги))
    if ещё:
        # СЧЁТ НАЧИНАЕТСЯ ЗАНОВО: строки первого обхода лежат и во
        # втором, и сложенные счётчики назвали бы каждую дважды.
        for и in ещё:
            итоги[и].update(истинных=0, с_числом=0, судимых=0)
        пройти(все_суды, палата, пути, None, ещё, итоги)

    счёт = collections.Counter()
    for имя in sorted(все_суды):
        учёт = итоги.get(имя, {"исход": ПУСТ})
        исход = учёт["исход"]
        счёт[исход] += 1
        if исход in (ПОЙМАН, НЕ_ПОЙМАН, ОНЕМЕЛ):
            место = учёт["место"]
            пара = (f"«{вырезка(учёт['честно'], место)}» → "
                    f"«{вырезка(учёт['порча'], место)}»")
        if исход == ПОЙМАН:
            хвост = пара
        elif исход == НЕ_ПОЙМАН:
            хвост = (f"{пара} — суд зовёт испорченную истиной "
                     f"(строк перебрано {учёт['с_числом']})")
        elif исход == ОНЕМЕЛ:
            хвост = (f"{пара} — порча вывела строку из объявленного "
                     f"(строк перебрано {учёт['с_числом']})")
        elif исход == СВОБОДНО:
            хвост = (f"«{вырезка(учёт['честно'], учёт['место'])}» — "
                     f"все числа строки стоят в местах, которые ЯЗЫК "
                     f"объявил не несущими смысла (строк перебрано "
                     f"{учёт['с_числом']}); подсадка неприменима")
        elif исход == НЕТ_ЧИСЛА:
            хвост = (f"истинных строк {учёт['истинных']}, и ни одна не "
                     f"несёт числа — подсадка неприменима")
        elif учёт.get("судимых"):
            хвост = (f"суд прочёл {учёт['судимых']} строк корпуса и "
                     f"НИ ОДНУ не назвал истиной")
        else:
            хвост = ("суд не прочёл НИ ОДНОЙ строки корпуса — его мира "
                     "нет в манифесте или он ещё не построен")
        print(f"СУД {короткое(имя):<18} {исход:<10} {хвост}")

    пусто = счёт[ПУСТ]
    поза = ("PASS" if счёт[НЕ_ПОЙМАН] <= НЕ_ПОЙМАНО_РУБЕЖ and not пусто
            else "FAIL")
    print(f"МУТАНТЫ СУДОВ {поза}: {счёт[ПОЙМАН]} поймали, "
          f"{счёт[ОНЕМЕЛ]} онемели, {счёт[НЕ_ПОЙМАН]} не поймали "
          f"(рубеж {НЕ_ПОЙМАНО_РУБЕЖ}), {счёт[СВОБОДНО]} со свободным "
          f"числом, {счёт[НЕТ_ЧИСЛА]} без числовой "
          f"истинной строки, {пусто} без истинной строки вовсе "
          f"(судов {len(все_суды)})")
    return 0 if поза == "PASS" else 1


