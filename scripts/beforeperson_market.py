#!/usr/bin/env python3
"""[РЫНОК СЛОВА ПЕРЕД ЛИЦОМ] — какие классы свод ставит за словом, после которого стоит лицо.

    СЛОВО, ЗА КОТОРЫМ СВОД СТАВИЛ ЛИШЬ ОБЪЯВЛЕННОЕ, НЕ ТЕРПИТ ЗА СОБОЙ НЕОБЪЯВЛЕННОГО.

Покупка живёт в двери лиц (`tools/actors.py`, четвёртый слой — там повод, улов, цена и граница),
а здесь она ЗАПИСЫВАЕТСЯ на полку — `datasets/GENESIS-FULL.beforeperson.tsv` — и сверяется с
делом, как полки соседей `scripts/actorplace_market.py` и `scripts/personcase_market.py`.

ЧТО НА ПОЛКЕ. Строка сайдкара — язык, классы слова ПЕРЕД словом (через «+»), слово, показы,
классы слова ЗА ним через запятую: ключ есть тройка «класс → слово → класс». Классы
объявлены ПАКЕТОМ (`лицо`, `зачин`, `вопрос`, `задание`, `число`, `отрицание`); `·неизвестно` —
слово, не объявленное никаким. Слово без `·неизвестно` СТРОГО, и лишь оно судит.

ЧТО СУДИТ ГОЛЫЙ ЗОВ. Пересобирает рынок по своду и сличает с полкой: расхождение есть
устаревшая покупка. Рубеж НОЛЬ.

    python3 scripts/beforeperson_market.py [--собрать] [--цена] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import argparse
import collections
import pathlib
import sys
import zlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import actors  # noqa: E402 — дверь лиц: рынок слова перед лицом живёт там

# РУБЕЖ-ДОЛГА: РАСХОЖДЕНИЙ_РУБЕЖ = 0
#
# Полка и свод либо сходятся, либо покупка лжёт — рубеж рождён нулём, как у соседа.
РАСХОЖДЕНИЙ_РУБЕЖ = 0


def строки_полки(куплено, рынок):
    вон = ["# РЫНОК СЛОВА ПЕРЕД ЛИЦОМ — какие классы свод ставит за этим словом.",
           "# Собран `python3 scripts/beforeperson_market.py --собрать` по мирам, объявившим",
           "# деятелей (манифест `actors`). Столбцы: язык, классы слова перед, слово, показы,",
           "# классы слова за ним.",
           "# Класс объявлен ПАКЕТОМ языка; `·неизвестно` — слово, не объявленное никаким."]
    for ключ, классы in sorted(куплено.items()):
        показы = sum(рынок[ключ].values())
        вон.append("\t".join(ключ) + f"\t{показы}\t{','.join(sorted(классы))}")
    return вон


def цена_на_другой_половине():
    """Рынок куплен на половине строк, суд идёт по другой — той, какой он не видел."""
    половина = lambda с: zlib.crc32(с.encode("utf-8")) % 2 == 0   # noqa: E731
    куп = actors.куплены_соседом(actors.собрать_рынок_соседа(доля=половина))
    обвинений, примеры, судимых = collections.Counter(), [], 0
    for имя, путь, языки in actors.миры_деятелей():
        if not путь.exists():
            continue
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            строка = строка.strip()
            if not строка or половина(строка):
                continue
            судимых += 1
            for перед, слово, за, язык in actors.порча_соседа(строка, языки, куп=куп):
                обвинений[имя] += 1
                if len(примеры) < 6:
                    примеры.append((имя, язык, f"{перед} {слово} {за}", строка[:70]))
    return len(куп), судимых, обвинений, примеры


# ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ. Пары «целое → порча» взяты из строк свода, какие палата до
# закона звала истиной порченными (замер всякого имени внутри предложения): обрезок имени за
# «does» — в мирах `genesis_story`, `heads`, `realverbs`. Порча здесь НЕ ИЩЕТСЯ прибором, а
# названа — проба доказывает не поиск, а ЧТЕНИЕ.
ПРОБЫ = (
    (("en",), "how many balls does Ann have left? 8 balls left.",
              "how many balls does An have left? 8 balls left."),
    (("en",), "Ann had 4 nuts. Ann got 1 nut. how many nuts does Ann have now? Ann has 5 nuts.",
              "Ann had 4 nuts. Ann got 1 nut. how many nuts does An have now? Ann has 5 nuts."),
    (("en",), "Tom packed 9 pages. Tom used 1 page away. how many pages does Tom keep? "
              "Tom keeps 8 pages: 9 − 1 = 8.",
              "Tom packed 9 pages. Tom used 1 page away. how many pages does To keep? "
              "Tom keeps 8 pages: 9 − 1 = 8."),
)


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: обрезок за строгим словом ловится, целое имя — молчит."""
    куп = actors.куплен_сосед()
    if not куп:
        return None
    поймано = sum(1 for языки, _, порча in ПРОБЫ
                  if actors.порча_соседа(порча, list(языки), куп=куп))
    ложных = sum(1 for языки, цело, _ in ПРОБЫ
                 if actors.порча_соседа(цело, list(языки), куп=куп))
    return поймано, len(ПРОБЫ), ложных


def main():
    ап = argparse.ArgumentParser(add_help=True)
    ап.add_argument("--собрать", action="store_true")
    ап.add_argument("--цена", action="store_true")
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--манифест", default=None)
    дано = ап.parse_args()
    if дано.манифест:
        actors.МАНИФЕСТ = pathlib.Path(дано.манифест)
    миры = [м for м in actors.миры_деятелей() if м[1].exists()]
    if not миры:
        print("РЫНОК СЛОВА ПЕРЕД ЛИЦОМ ОТКАЗ: обход пуст — ни одного мира деятелей, мерить нечего")
        return 2

    if дано.цена:
        n, судимых, обвинений, примеры = цена_на_другой_половине()
        print(f"ЦЕНА НА ДРУГОЙ ПОЛОВИНЕ: куплено {n}, судимых строк {судимых}, "
              f"ОБВИНЕНИЙ {sum(обвинений.values())} в {len(обвинений)} мирах")
        for имя, язык, тройка, тело in примеры:
            print(f"    [{имя}/{язык}] «{тройка}» ← {тело}")
        return 0

    рынок = actors.собрать_рынок_соседа()
    куплено = actors.куплены_соседом(рынок)
    языков = len({к[0] for к in куплено})
    строгих = sum(1 for к in куплено.values() if actors.НЕТ_КЛАССА not in к)
    if дано.собрать:
        actors.САЙДКАР_СОСЕДА.write_text("\n".join(строки_полки(куплено, рынок)) + "\n",
                                         encoding="utf-8")
        print(f"РЫНОК СЛОВА ПЕРЕД ЛИЦОМ СОБРАН: ключей {len(куплено)} на {языков} языках, "
              f"строгих {строгих}, миров деятелей {len(миры)} → {actors.САЙДКАР_СОСЕДА.name}")
        return 0

    было = actors.куплен_сосед()
    расхождения = sorted(set(было) ^ set(куплено)) + sorted(
        к for к in set(было) & set(куплено) if было[к] != куплено[к])
    if дано.подробно:
        for ключ in расхождения[:40]:
            print(f"    {' · '.join(ключ)}: полка {sorted(было.get(ключ, ()))} "
                  f"≠ свод {sorted(куплено.get(ключ, ()))}")
    проба = _проба()
    слово_пробы = ("пробы нет: полка пуста" if проба is None else
                   f"проба {проба[0]}/{проба[1]} поймано, ложных {проба[2]}")
    поза = "FAIL" if len(расхождения) > РАСХОЖДЕНИЙ_РУБЕЖ else "PASS"
    print(f"РЫНОК СЛОВА ПЕРЕД ЛИЦОМ {поза}: расхождений полки со сводом {len(расхождения)} "
          f"(рубеж {РАСХОЖДЕНИЙ_РУБЕЖ}); ключей {len(куплено)} на {языков} языках, строгих "
          f"{строгих}, миров деятелей {len(миры)}, {слово_пробы}")
    return 1 if len(расхождения) > РАСХОЖДЕНИЙ_РУБЕЖ else 0


if __name__ == "__main__":
    sys.exit(main())
