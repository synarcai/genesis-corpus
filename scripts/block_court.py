#!/usr/bin/env python3
"""[БЛОК ОТДАН НАРУЖУ] — страж двора `blocks/`: блока, который уходит от свода к чужим руками.

    БЛОК, ОТДАННЫЙ НАРУЖУ, ЕСТЬ ЕДИНСТВЕННАЯ ЧАСТЬ СВОДА, КОТОРУЮ НЕЛЬЗЯ ИСПРАВИТЬ
    ЗАДНИМ ЧИСЛОМ. Мир пересобирается кузницей, отчёт переписывается, рубеж затягивается
    — а блок уже у читателя, и ошибка в нём живёт столько же, сколько сам блок.

Потому у блока страж строже, чем у мира: у мира ответ сверяется законом, у блока —
ПЕРЕСЧИТЫВАЕТСЯ ЗАНОВО, из одной лишь истории вопроса, без единого взгляда на колонку
ответа. Прибор не спрашивает «согласен ли ответ с законом» — он спрашивает «какой ответ
даёт закон», и сличает.

ЧТО ПРОВЕРЯЕТСЯ У ВСЯКОГО БЛОКА.

  1. СОСТАВ СОШЁЛСЯ С ОБЪЯВЛЕНИЕМ. Рядом с `ИМЯ.tsv` лежит `ИМЯ.md`, и в нём таблица
     родов с числами. Число строк рода, посчитанное по блоку, равно объявленному.

  2. ОТВЕТ ПЕРЕСЧИТАН. Всякий род блока имеет здесь СВОЙ счётчик, читающий историю:
     цепь свидетелей разрешается своим законом, порядок прилагательных — разрядами,
     объявленными в `tools/langpacks/en.json`. Счётчика нет — род не принимается вовсе:

         РОД, КОТОРЫЙ НЕКОМУ ПЕРЕСЧИТАТЬ, НЕ ОТДАЁТСЯ НАРУЖУ. Отдать его значило бы
         сказать «мы уверены», не имея, чем эту уверенность показать.

  3. НИ ОДНА СТРАНИЦА НЕ ПРОЖИТА. Ни вопрос, ни история не встречаются в своде дословно.
     Блок, чьи страницы живут в своде, мерит ПАМЯТЬ читателя о своде, а не его умение, —
     и мерит тем вернее, чем полнее читатель свод прочёл.

  4. ОТВЕТ НЕ ЧИТАЕТСЯ ИЗ ВОПРОСА. Ответы рода не распределены так, что угадывающий
     большинством берёт больше положенного: у двоичного рода перевес не более чем на
     строку, у родов с открытым ответом всякий ответ встречается однажды.

ЧЕГО ПРИБОР НЕ ДЕЛАЕТ. Он не судит о трудности блока — трудность есть свойство читателя,
а не блока. Он не сверяет блок со сводом на сходство рамок: блок ДОЛЖЕН быть собран теми
же рамками, иначе он мерит чужой дом; он лишь не должен повторять дословных страниц.

    python3 scripts/block_court.py
"""
# ПУСТОЙ-ОБХОД: --двор /no/such/blocks
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
ДВОР = КОРЕНЬ / "blocks"
СВОД = КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
ПАКЕТЫ = КОРЕНЬ / "tools" / "langpacks"

БЕД_РУБЕЖ = 0
ПРОЖИТЫХ_РУБЕЖ = 0

# Строка объявления: «| цепь-en | 20 |»
СТРОКА_РОДА = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*(\d+)\s*\|")


# ---------------------------------------------------------------- счётчики родов

ПРАВДИВ = {
    "en": (re.compile(r"\btells the truth\b"), re.compile(r"\blies\b")),
    "ru": (re.compile(r"говорит правду"), re.compile(r"(?:лжёт|врёт)")),
}
# ЗАЧИН ЦЕПИ БЫВАЕТ И ЛЖИВЫМ, И ЭТО НЕ ИСКЛЮЧЕНИЕ, А ЦЕЛЫЙ РОД (`отрицание`). Первое
# чтение прибора знало один зачин — правдивый — и на лживом молчало: «пересчёт не дал
# ответа». Молчание счётчика опаснее ошибки: ошибку видно сличением, а молчание можно
# принять за отсутствие беды.
ПЕРВЫЙ = {
    "en": re.compile(r"^(\w+) (tells the truth|lies)\."),
    "ru": re.compile(r"^(\S+) (говорит правду|лжёт)\."),
}
ПРАВДИВ_ЗАЧИН = frozenset(("tells the truth", "говорит правду"))
ЗВЕНО = {
    "en": re.compile(r"(\w+) says that (\w+) (tells the truth|lies)\."),
    "ru": re.compile(r"(\S+) говорит, что (\S+) (говорит правду|лжёт)\."),
}
СПРОШЕН = {
    "en": re.compile(r"does (\w+) tell the truth\?"),
    "ru": re.compile(r"говорит ли (\S+) правду\?"),
}
ДА_НЕТ = {"en": ("yes", "no"), "ru": ("да", "нет")}


def _цепь(язык, вопрос, история):
    """Кто правдив — из одной истории. Первый объявлен, прочие выводятся звеньями.

    ЗАКОН ЦЕПИ: сказавший правду о правдивом правдив; сказавший ложь о правдивом лжёт;
    сказавший ложь о лжеце правдив. Одна строка на всю цепь.
    """
    m = ПЕРВЫЙ[язык].match(история)
    if not m:
        return None
    правда = {m.group(1): m.group(2) in ПРАВДИВ_ЗАЧИН}
    for кто, о_ком, что in ЗВЕНО[язык].findall(история):
        if о_ком not in правда:
            return None
        сказал_правду = что in ("tells the truth", "говорит правду")
        правда[кто] = сказал_правду == правда[о_ком]
    m = СПРОШЕН[язык].search(вопрос)
    if not m or m.group(1) not in правда:
        return None
    да, нет = ДА_НЕТ[язык]
    return да if правда[m.group(1)] else нет


def _разряды():
    """Разряды прилагательных — из объявления пакета, а не из памяти прибора.

    Пакет объявляет ДВЕ вещи порознь: `ranks` — порядок разрядов, `words` — слова
    каждого разряда. Прибор берёт обе и не выводит порядок из порядка ключей: ключи
    словаря есть след записи, а не объявление.
    """
    пак = json.loads((ПАКЕТЫ / "en.json").read_text(encoding="utf-8"))
    объявление = пак.get("adjective_order") or {}
    разряды, слова = объявление.get("ranks"), объявление.get("words")
    if not разряды or not слова:
        return None
    вон = {}
    for i, разряд in enumerate(разряды):
        for слово in слова.get(разряд, ()):
            вон[слово] = i
    return вон or None


ПОРЯДОК_ВОПРОС = re.compile(r"«([^»]+)»\s*or\s*«([^»]+)»")


def _порядок(_язык, вопрос, история, разряды=None):
    """Какая из двух записей права — по разрядам, а не по тому, что стои́т первым.

    Прибор не знает «правильной» записи: он берёт ОБЕ, раскладывает по разрядам и
    выбирает ту, чьи разряды не убывают. Если таких две или ни одной — ответа нет.
    """
    if разряды is None:
        разряды = _разряды()
    m = ПОРЯДОК_ВОПРОС.search(история)
    if not m:
        return None
    годные = []
    for запись in (m.group(1), m.group(2)):
        слова = запись.split()
        if len(слова) < 3:
            return None
        # артикль впереди, вещь в хвосте; между ними — прилагательные
        прил = слова[1:-1]
        места = [разряды.get(w) for w in прил]
        if any(м is None for м in места):
            return None
        if all(a < b for a, b in zip(места, места[1:])):
            годные.append(запись)
    return годные[0] if len(годные) == 1 else None


СЧЁТЧИКИ = {
    "цепь-en": lambda в, и, п: _цепь("en", в, и),
    "цепь-ru": lambda в, и, п: _цепь("ru", в, и),
    "порядок-en": lambda в, и, п: _порядок("en", в, и, п),
}
ДВОИЧНЫЕ = {"цепь-en", "цепь-ru"}


# ---------------------------------------------------------------- род строки

def _род(вопрос, история):
    """Род строки — по её собственному виду, а не по месту в файле."""
    if ПОРЯДОК_ВОПРОС.search(история):
        return "порядок-en"
    if СПРОШЕН["ru"].search(вопрос):
        return "цепь-ru"
    if СПРОШЕН["en"].search(вопрос):
        return "цепь-en"
    return None


def _объявлено(лист):
    """Состав, объявленный рядом лежащим листом: {род: сколько}."""
    if not лист.is_file():
        return {}
    вон = {}
    for с in лист.read_text(encoding="utf-8").split("\n"):
        m = СТРОКА_РОДА.match(с.strip())
        if m:
            вон[m.group(1)] = int(m.group(2))
    return вон


def _область(строки):
    """Беды области: чем блок обязан отличаться от мира, чтобы не прожиться ЗАВТРА.

    ПРОВЕРКА «НЕТ В СВОДЕ СЕГОДНЯ» СТАРЕЕТ ВМЕСТЕ СО СВОДОМ (21.09). Первая сборка блока
    брала лиц и вещи у самих домов, и в час замера ни одна её страница в своде не жила —
    а назавтра дома вошли в свод, и сорок страниц блока стали прожиты дословно. Мера,
    верная лишь в час замера, есть не мера, а снимок.

        БЛОК ОТЛИЧАЕТСЯ ОТ МИРА НЕ РАСПИСАНИЕМ, А ОБЛАСТЬЮ: он берёт то, чего мир не
        берёт вовсе, — и тогда рост свода ему не страшен.

    Три отличия, и все три читаются из самих домов, а не объявляются здесь списком:
    лица вне `person_names`, цепь длиннее всякой домовой, вещи вне `adjorder.ВЕЩИ`.
    """
    try:
        import adjorder
        import liarchain
    except Exception as беда:                       # noqa: BLE001
        return [f"домов блока нет в дереве, пересчитывать нечем — {беда}"]

    беды = []
    домовы_длины = set()
    for д in liarchain.ДЛИНЫ.values():
        домовы_длины |= {д} if isinstance(д, int) else set(д)
    предел = max(домовы_длины) if домовы_длины else 0

    for блок, i, род, вопрос, история in строки:
        if род.startswith("цепь-"):
            язык = род.split("-")[1]
            лица = set()
            m = ПЕРВЫЙ[язык].match(история)
            if m:
                лица.add(m.group(1))
            for кто, о_ком, _ in ЗВЕНО[язык].findall(история):
                лица.update((кто, о_ком))
            свои = лица & set(liarchain.ЛИЦА.get(язык, ()))
            if свои:
                беды.append(f"{блок}:{i}: лицо блока живёт в пакете — {sorted(свои)}")
            if лица and len(лица) <= предел:
                беды.append(f"{блок}:{i}: цепь из {len(лица)} звеньев, а дом даёт до {предел}")
        elif род == "порядок-en":
            m = ПОРЯДОК_ВОПРОС.search(история)
            if m:
                вещь = m.group(1).split()[-1]
                if вещь in adjorder.ВЕЩИ:
                    беды.append(f"{блок}:{i}: вещь «{вещь}» живёт в доме порядка")
    return беды


def _проба():
    """Прибор доказывает чтение, прежде чем судить: подложная строка должна быть поймана."""
    беды = []
    ответ = _цепь("en", "does Kate tell the truth?",
                  "James tells the truth. Janet says that James lies. "
                  "Kate says that Janet lies.")
    if ответ != "yes":
        беды.append(f"цепь-en: ждали yes, вышло {ответ!r}")
    ответ = _цепь("ru", "говорит ли Катя правду?",
                  "Саша говорит правду. Марк говорит, что Саша лжёт. "
                  "Катя говорит, что Марк говорит правду.")
    if ответ != "нет":
        беды.append(f"цепь-ru: ждали нет, вышло {ответ!r}")
    разряды = _разряды()
    if not разряды:
        беды.append("разрядов прилагательных нет в en.json")
    else:
        ответ = _порядок("en", "which order is right?",
                         "«a big old table» or «an old big table»", разряды)
        if ответ != "a big old table":
            беды.append(f"порядок-en: ждали «a big old table», вышло {ответ!r}")
    return беды


def main():
    двор = ДВОР
    if "--двор" in sys.argv:
        двор = pathlib.Path(sys.argv[sys.argv.index("--двор") + 1])
    if not двор.is_dir():
        print(f"БЛОК ОТДАН НАРУЖУ ОТКАЗ: двора нет — {двор}")
        return 2
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"БЛОК ОТДАН НАРУЖУ ОТКАЗ: пересчёт не доказан ({len(беды)} бед)")
        return 2

    блоки = sorted(двор.glob("*.tsv"))
    if not блоки:
        print("БЛОК ОТДАН НАРУЖУ ОТКАЗ: во дворе нет ни одного блока")
        return 2

    свод = СВОД.read_text(encoding="utf-8", errors="replace") if СВОД.is_file() else ""
    разряды = _разряды()
    беды, строк_всего, прожитых = [], 0, 0
    опознанные = []

    for блок in блоки:
        строки = [с for с in блок.read_text(encoding="utf-8").split("\n") if с.strip()]
        объявлено = _объявлено(блок.with_suffix(".md"))
        if not объявлено:
            беды.append(f"{блок.name}: объявления состава нет — блок отдан без описи")
            continue
        сосчитано, ответы = {}, {}
        for i, с in enumerate(строки, 1):
            доли = с.split("\t")
            if len(доли) != 3:
                беды.append(f"{блок.name}:{i}: долей {len(доли)}, а не три")
                continue
            ответ, вопрос, история = (д.strip() for д in доли)
            строк_всего += 1
            род = _род(вопрос, история)
            if род is None:
                беды.append(f"{блок.name}:{i}: род не опознан — «{вопрос[:40]}»")
                continue
            сосчитано[род] = сосчитано.get(род, 0) + 1
            опознанные.append((блок.name, i, род, вопрос, история))
            счётчик = СЧЁТЧИКИ.get(род)
            if счётчик is None:
                беды.append(f"{блок.name}:{i}: род «{род}» некому пересчитать")
                continue
            свой = счётчик(вопрос, история, разряды)
            if свой is None:
                беды.append(f"{блок.name}:{i}: пересчёт не дал ответа — «{история[:50]}»")
            elif свой != ответ:
                беды.append(f"{блок.name}:{i}: сказано «{ответ}», пересчёт даёт «{свой}»")
            ответы.setdefault(род, []).append(ответ)
            if вопрос in свод or история in свод:
                прожитых += 1
                беды.append(f"{блок.name}:{i}: страница ПРОЖИТА — живёт в своде дословно")

        for род, сколько in sorted(объявлено.items()):
            было = сосчитано.get(род, 0)
            if было != сколько:
                беды.append(f"{блок.name}: род «{род}» объявлен {сколько}, а в блоке {было}")
        for род in sorted(set(сосчитано) - set(объявлено)):
            беды.append(f"{блок.name}: род «{род}» в блоке есть, а в объявлении нет")

        # ОТВЕТ НЕ ЧИТАЕТСЯ ИЗ ВОПРОСА: у двоичного рода перевес не больше строки.
        for род, ряд in sorted(ответы.items()):
            счёт = {}
            for о in ряд:
                счёт[о] = счёт.get(о, 0) + 1
            if род in ДВОИЧНЫЕ:
                if len(счёт) != 2 or abs(счёт[ряд[0]] - (len(ряд) - счёт[ряд[0]])) > 1:
                    беды.append(f"{блок.name}: род «{род}» перекошен ответом: {счёт}")
            elif (частых := [о for о, к in счёт.items() if к > 1]):
                беды.append(f"{блок.name}: род «{род}» повторяет ответ {len(частых)} раз")

    беды_области = _область(опознанные)
    беды += беды_области

    for б in беды[:20]:
        print(f"    {б}")
    if len(беды) > 20:
        print(f"    … и ещё {len(беды) - 20}")
    вердикт = "PASS" if len(беды) <= БЕД_РУБЕЖ and прожитых <= ПРОЖИТЫХ_РУБЕЖ else "FAIL"
    print(f"БЛОК ОТДАН НАРУЖУ {вердикт}: бед {len(беды)} (рубеж {БЕД_РУБЕЖ}), "
          f"ПРОЖИТЫХ страниц {прожитых} (рубеж {ПРОЖИТЫХ_РУБЕЖ}); "
          f"блоков {len(блоки)}, строк {строк_всего}, "
          f"родов с пересчётом {len(СЧЁТЧИКИ)}, вне ОБЛАСТИ домов {len(беды_области)}, "
          f"свод {len(свод)} знаков")
    return 0 if вердикт == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
