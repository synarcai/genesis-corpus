#!/usr/bin/env python3
"""[КРУГ] — ответ на «почему», не приносящий НИ ОДНОГО нового слова, есть круг.

М-263 родился на живом изъяне: дом поведения писал «почему, когда человек
устал, он ошибается чаще? потому что человек устал». Обе части истинны, ответ
пуст — условие вопроса повторено вместо причины. Ни суд истины, ни суд письма
его не ловят: в обоих измерениях он безупречен. Ловится он только ЧТЕНИЕМ
ЦЕЛОГО, от вопроса к ответу, — и вот прибор, который это чтение делает.

ПРИЗНАК ЗНАЧИМ НЕ ВСЮДУ, И ЭТО ПОЛОВИНА ЗАКОНА, ДОПЛАЧЕННАЯ holon (04.09).
Наивное «слова ответа суть подмножество слов вопроса» сработало у него
тринадцать раз на атаке организма, и все тринадцать оказались законными:

    what is the maximum of 4 19 7?  →  the maximum of 4 19 7 is 19

ВЫБОР ОБЯЗАН СОСТОЯТЬ ИЗ СЛОВ ВОПРОСА — в этом и состоит выбирать. Признак
ловил не круг, а само существо селекции. Отсюда ограничение: круг судится не
по словам, а по тому, ЧЕГО ТРЕБУЕТ ВОПРОС. «Который из» требует выбора из
данного; «почему» требует НОВОГО основания — и только там ответ обязан нести
слово, которого в вопросе не было.

Новым считается всякое слово длиной от трёх букв, не стоявшее в вопросе, —
служебные слова вопроса тем самым исключены сами собой, ибо они в вопросе и
стоят. Одно исключение объявлено и неизбежно: СВЯЗКА ПРИЧИНЫ («потому что»,
«weil», «parce que», «bo») в вопросе не стоит НИКОГДА и потому всегда была бы
новым словом — первая проба прибора не поймала обеих своих подсадок именно
из-за неё. Связка есть рамка ответа, а не его содержание, и снимается перед
сличением. Список её девятиязычен и короток; ничего, кроме связки, в нём нет.

ВТОРАЯ МЕРА ТОГО ЖЕ ЧТЕНИЯ — ОТКАЗ БЕЗ ОСНОВАНИЯ. Круг и отговорка суть два
конца одной болезни: первый отвечает вопросом, вторая не отвечает ничем.
«Я не знаю» есть отговорка; «я не знаю: погода меняется каждый день, а я её не
вижу» есть знание о ГРАНИЦЕ знания, и разница между ними вся в том, стоит ли
за отказом причина. Прибор считает отказы и отказы БЕЗ причины отдельно —
по той же причине, по какой считает причинные ответы: ноль без знаменателя
ничего не говорит (М-264).

    python3 scripts/circle_probe.py [--свод datasets/GENESIS-FULL.txt]
"""
import argparse
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# ПРИЧИННЫЕ ЗАЧИНЫ ДЕВЯТИ ЯЗЫКОВ АТАКИ — вопрос, требующий НОВОГО знания.
ПРИЧИННЫЕ = ("почему", "отчего", "зачем", "why", "warum", "wozu", "pourquoi",
             "por qué", "perché", "porque", "porquê", "waarom", "dlaczego")
# СВЯЗКИ ПРИЧИНЫ — рамка ответа, а не его содержание (см. голову файла)
СВЯЗКИ = ("потому что", "оттого что", "because", "weil", "denn", "parce que",
          "parce qu", "porque", "perché", "omdat", "ponieważ", "bo ", "dlatego że")
# ОТКАЗЫ ДЕВЯТИ ЯЗЫКОВ АТАКИ — «не знаю» во всех лицах, какими его пишет корпус
ОТКАЗЫ = ("я не знаю", "не знаю", "i do not know", "i don't know", "ich weiß es nicht",
          "je ne sais pas", "no lo sé", "non lo so", "não sei", "ik weet het niet", "nie wiem")
_СЛОВО = re.compile(r"[^\W\d_]{3,}", re.UNICODE)
_ЗНАК = re.compile(r"[?？؟]")


def причинный(вопрос):
    н = вопрос.lower()
    return any(з in н for з in ПРИЧИННЫЕ)


def круг(вопрос, ответ):
    """Ответ не принёс ни одного слова, которого не было в вопросе."""
    о_текст = ответ.lower()
    for с in СВЯЗКИ:
        о_текст = о_текст.replace(с, " ")
    в = set(_СЛОВО.findall(вопрос.lower()))
    о = set(_СЛОВО.findall(о_текст))
    return bool(о) and not (о - в)


def разобрать(строка):
    """(вопрос, ответ) по ПОСЛЕДНЕМУ вопросительному знаку.

    ВОПРОС ЕСТЬ ПОСЛЕДНЕЕ ПРЕДЛОЖЕНИЕ ПЕРЕД ЗНАКОМ, А НЕ ВЕСЬ ЗАЧИН, и это
    вторая половина уточнения, за которую прибор заплатил 938 ложными
    тревогами. Показ дома связок несёт ПОСЫЛКИ перед вопросом:

        Marta tenía 17 cartas. Marta dio 2 cartas. Marta tiene 15 cartas.
        ¿por qué Marta tiene 15 cartas? porque Marta tenía 17 y dio 2: 17 − 2 = 15.

    Ответ здесь повторяет ПОСЫЛКИ — и обязан их повторять, ибо в них и состоит
    объяснение. Круг есть повтор ВОПРОСА, а не повтор данных: контекст суть
    материал ответа, вопрос суть его предмет. Прибор, считавший зачин частью
    вопроса, звал кругом всякий верный вывод из посылок.
    """
    места = [м.end() for м in _ЗНАК.finditer(строка)]
    if not места:
        return None
    к = места[-1]
    зачин = строка[:к]
    начало = max(зачин.rfind(". "), зачин.rfind("! "), зачин.rfind("? ", 0, к - 1))
    вопрос = зачин[начало + 2:] if начало >= 0 else зачин
    return вопрос, строка[к:].strip()


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--свод", default="datasets/GENESIS-FULL.txt")
    ап.add_argument("--имён", type=int, default=8)
    а = ап.parse_args()
    путь = КОРЕНЬ / а.свод
    if not путь.is_file():
        print(f"нет свода: {путь}", file=sys.stderr)
        return 1
    # ПРЕДСТАВЛЕННОЕ «НЕТ» (М-106): прибор обязан поймать подсаженный круг и
    # НЕ поймать законный выбор — оба случая проверяются до всякого чтения.
    подсадка = ("почему, когда человек устал, он ошибается чаще? потому что человек устал.",
                "warum macht ein Mensch mehr Fehler, wenn er müde ist? weil ein Mensch müde ist.")
    невинные = ("what is the maximum of 4 19 7? the maximum of 4 19 7 is 19.",
                "почему человек ошибается чаще, когда устал? потому что усталость ослабляет внимание.")
    поймано = sum(1 for с in подсадка
                  for р in (разобрать(с),) if р and причинный(р[0]) and круг(*р))
    # ПОДСАДКА ВТОРОЙ МЕРЫ: голый отказ обязан ловиться, отказ с основанием — нет
    голая = "какая сегодня погода? я не знаю."
    с_основанием = "какая сегодня погода? я не знаю: погода меняется каждый день."
    def _гол(с):
        низ = разобрать(с)[1].lower()
        о = next((о for о in ОТКАЗЫ if о in низ), None)
        return bool(о) and not _СЛОВО.findall(низ.replace(о, " "))
    if not _гол(голая) or _гол(с_основанием):
        print("КРУГ FAIL: подсадка отказа не сходится — прибор не годен")
        return 1
    ложных_тревог = sum(1 for с in невинные
                        for р in (разобрать(с),) if р and причинный(р[0]) and круг(*р))
    if поймано != len(подсадка) or ложных_тревог:
        print(f"КРУГ FAIL: подсадок поймано {поймано} из {len(подсадка)}, "
              f"ложных тревог {ложных_тревог} — прибор не годен")
        return 1
    причинных = кругов = вопросов = отказов = голых_отказов = 0
    голые = []
    круги = []
    for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        с = строка.strip()
        if not с or с.startswith("\x0c"):
            continue
        р = разобрать(с)
        if not р:
            continue
        вопросов += 1
        вопрос, ответ = р
        if not ответ:
            continue
        низ = ответ.lower()
        отказ = next((о for о in ОТКАЗЫ if о in низ), None)
        if отказ:
            отказов += 1
            # ОТКАЗ БЕЗ ОСНОВАНИЯ: снять сам отказ и посмотреть, осталось ли
            # хоть одно содержательное слово. «Я не знаю.» — отговорка;
            # «я не знаю: погода меняется» — знание о границе знания.
            остаток = низ.replace(отказ, " ")
            if not _СЛОВО.findall(остаток):
                голых_отказов += 1
                if len(голые) < а.имён:
                    голые.append(с)
        if not причинный(вопрос):
            continue
        причинных += 1
        if круг(вопрос, ответ):
            кругов += 1
            if len(круги) < а.имён:
                круги.append(с)
    for с in круги:
        print(f"  КРУГ: {с[:130]}")
    for с in голые:
        print(f"  ОТКАЗ БЕЗ ОСНОВАНИЯ: {с[:130]}")
    поза = "PASS" if кругов == 0 and голых_отказов == 0 else "FAIL"
    print(f"КРУГ {поза}: {кругов} кругов из {причинных} причинных ответов "
          f"({вопросов} вопросных строк всего); отказов {отказов}, из них БЕЗ ОСНОВАНИЯ "
          f"{голых_отказов}; подсадок поймано {поймано} из {len(подсадка)}, ложных тревог 0")
    # М-264: ноль без знаменателя есть немота, а не чистота
    if причинных == 0:
        print("  ВНИМАНИЕ: причинных ответов НОЛЬ — этот ноль есть немота, а не чистота (М-264)")
    if отказов == 0:
        print("  ВНИМАНИЕ: отказов НОЛЬ — корпус не показывает границы своего знания (М-264)")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
