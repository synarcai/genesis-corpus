#!/usr/bin/env python3
"""[САМОСЧЁТ ОБЪЯВЛЕНИЯ] — «пять родов, 52 страницы» в рассказе о мире против дома и мира.

    ЗАМЕР, ВПИСАННЫЙ В ОБЪЯВЛЕНИЕ, СТАРЕЕТ МОЛЧА. `genre_measured` сторожит одно такое число —
    счёт строк мира; а дом объявляет и ВТОРОЕ, и оно стареет ровно так же: сколько у него
    РОДОВ показа.

ПОВОД, ПРОЖИТЫЙ 13.09. Дом китайского счётного получил седьмой род — «общее есть свой разряд»,
— и объявление его осталось говорить «Пять родов». Я правил жанр той же рукой, что и дом, и
всё же разошёлся: приписал абзац о новом роде и не тронул числа тремя строками выше.

    ЧИСЛО, СТОЯЩЕЕ В ДРУГОМ МЕСТЕ ТОГО ЖЕ ОБЪЯВЛЕНИЯ, ЧЕМ ПРАВКА, НЕ ПОПАДАЕТСЯ НА ГЛАЗА
    ПРАВЯЩЕМУ. Оттого его сторожит прибор, а не внимание.

Замер по 47 домам, чьё объявление называет число родов: РАЗОШЛОСЬ ВОСЕМЬ — chancetrap, dist,
fuseprep, gender, measuregrow, nlarticle, serestar, zhclass. Три из них разошлись давно и
молча; пять — оттого, что дом рос, а объявление не росло.

ВТОРОЕ ЧИСЛО ТОГО ЖЕ САМОСЧЁТА — СТРАНИЦЫ. Двадцать объявлений пишут «N родов, M страниц»,
и у ШЕСТИ число страниц устарело: angle 70 против 74, direct 28 против 30, fence 60 против 66,
measuregrow 52 против 84, numline 74 против 82, tzone 72 против 82. Все шесть — В МЕНЬШУЮ
сторону: дом рос, объявление стояло.

    ЧИСЛО СТРАНИЦ, НАЗВАННОЕ РЯДОМ С ЧИСЛОМ РОДОВ, ЕСТЬ ЧАСТЬ ОДНОГО САМОСЧЁТА, и стареет
    оно тем же способом. Признак берётся УЗКИЙ — «N родов, M страниц», — ибо слово
    «страницы» живёт в объявлениях и СОДЕРЖАНИЕМ («в первой главе 48 страниц»), и мера,
    читающая всякое его вхождение, назвала бы долгом семнадцать объявлений вместо шести.

СВЯЗЬ «МИР → ДОМ» НЕ УГАДЫВАЕТСЯ, А БЕРЁТСЯ ПО ИМЕНИ: мир `zhclass` объясняется домом
`zhclassforms`, и `РОДЫ` его — объявленная машинно таблица, а не проза. Дом, не назвавший
`РОДЫ`, и объявление, не назвавшее числа, не судятся вовсе.

    ПРИБОР, СУДЯЩИЙ ЛИШЬ ОБЪЯВЛЕННОЕ ДВАЖДЫ, НЕ ТРЕБУЕТ ОБЪЯВЛЯТЬ ДВАЖДЫ: он ловит РАЗЛАД
    тех, кто уже сказал одно и то же в двух местах.

    python3 scripts/genre_kinds.py [--подробно] [--манифест ПУТЬ]
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import argparse
import importlib
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

# РУБЕЖ-ДОЛГА: РАЗОШЕДШИХСЯ_РУБЕЖ = 0
#
# РУБЕЖ НОЛЬ И ДОСТИГНУТ В ТОТ ЖЕ ЧАС: восемь найденных объявлений выправлены — правка тут
# ЧИСТО СЛОВЕСНАЯ и ничего не стоит, кроме внимания. Ноль есть ПОЛ: девятое расхождение
# роняет прибор в тот же день, когда дом вырастет, а объявление нет.
РАЗОШЕДШИХСЯ_РУБЕЖ = 0

# ЧИСЛИТЕЛЬНЫЕ СЛОВОМ, какими объявления и пишут. Цифрой число родов не пишет ни одно, и
# потому цифра здесь не читается: признак берёт то, что есть, а не то, что могло бы быть.
СЛОВОМ = {"один": 1, "одно": 1, "два": 2, "две": 2, "три": 3, "четыре": 4, "пять": 5,
          "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10,
          "одиннадцать": 11, "двенадцать": 12}
ОБРАЗЕЦ = re.compile(r"\b(" + "|".join(СЛОВОМ) + r")\s+род(?:а|ов)?\b", re.IGNORECASE)

# ПРИБАВКА НЕ ЕСТЬ ИТОГ, И ЭТО КУПЛЕНО ЛОЖНОЙ НАХОДКОЙ (13.09). Объявление мира законов
# действия говорит «И ЕЩЁ ДВА РОДА, ТАКЖЕ БЕЗЫМЯННЫХ ДО 12.09» — это ПРИБАВКА к прежним, а
# не счёт всех семи. Прибор объявил разлад там, где сказана правда.
#
#     ЧИСЛО, ЧИТАЕМОЕ БЕЗ СЛОВА ПЕРЕД НИМ, ЧИТАЕТСЯ КАК ИТОГ — а перед ним могло стоять
#     «ещё», и тогда оно прибавка.
ПРИБАВКА = re.compile(r"(?i)ещё\s*$")


def сказано(жанр):
    """Число родов, названное объявлением ИТОГОМ, либо None."""
    т = жанр or ""
    for m in ОБРАЗЕЦ.finditer(т):
        if ПРИБАВКА.search(т[max(0, m.start() - 6):m.start()]):
            continue                   # «и ещё два рода» — прибавка, а не итог
        return СЛОВОМ[m.group(1).lower()]
    return None


СТРАНИЦЫ = re.compile(r"род(?:а|ов)?,\s*(\d[\d\s\u00a0]*)\s*страниц\w*")


def страниц_сказано(жанр):
    """Число страниц, названное САМОСЧЁТОМ «N родов, M страниц», либо None."""
    m = СТРАНИЦЫ.search(жанр or "")
    return int(re.sub(r"[\s\u00a0]", "", m.group(1))) if m else None


def дом_мира(имя):
    """Таблица РОДЫ дома этого мира, либо None. Связь берётся ПО ИМЕНИ, а не угадывается."""
    try:
        дом = importlib.import_module(f"{имя}forms")
    except Exception:                                   # noqa: BLE001
        return None
    роды = getattr(дом, "РОДЫ", None)
    return tuple(роды) if роды else None


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что прибор УМЕЕТ читать число родов.

        ЭТОТ ПРИБОР ЗЕЛЕНЕЕТ ОТ НУЛЯ РАСХОЖДЕНИЙ. Пусть признак перестанет находить число —
        и сверять станет нечего, а прибор скажет «разошлось 0», сверив НОЛЬ ОБЪЯВЛЕНИЙ.

    Четыре объявления с заведомым ответом: число родов в начале фразы, в середине, с иной
    падежной формой — и объявление БЕЗ числа родов, которое обязано остаться немым.
    """
    случаи = (("Пять родов и четыре ложных вывода: …", 5, "в начале фразы"),
              ("… НЕ УЧИТ, ПОЧЕМУ. Шесть родов, 52 страницы, два языка.", 6, "в середине"),
              ("Дом строится на два рода: показ и отказ.", 2, "иная падежная форма"),
              ("Мир о числах, и родов у него нет вовсе.", None, "без числа"),
              ("Три рода названы, и ещё два рода безымянны.", 3, "прибавка не есть итог"),
              ("И ещё два рода, также безымянных.", None, "одна прибавка без итога"))
    беды = []
    for жанр, ждём, имя in (("Пять родов, 52 страницы, два языка.", 52, "страницы самосчёта"),
                            ("в первой главе 48 страниц", None, "страницы содержанием")):
        было = страниц_сказано(жанр)
        if было != ждём:
            беды.append(f"{имя}: прочтено {было}, а надо {ждём}")
    for жанр, ждём, имя in случаи:
        было = сказано(жанр)
        if было != ждём:
            беды.append(f"{имя}: прочтено {было}, а надо {ждём}")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"САМОСЧЁТ ОБЪЯВЛЕНИЯ ОТКАЗ: чтение числа не доказано ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--манифест", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    путь = (pathlib.Path(дов.манифест) if дов.манифест
            else КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json")
    if not путь.is_file():
        print(f"САМОСЧЁТ ОБЪЯВЛЕНИЯ ОТКАЗ: манифеста нет — {путь}")
        return 2
    тело = json.loads(путь.read_text(encoding="utf-8"))
    миры = [м for м in тело.get("worlds", ()) if м.get("text") == "shows"]
    if not миры:
        print("САМОСЧЁТ ОБЪЯВЛЕНИЯ ОТКАЗ: миров показов нет, спрашивать не о ком")
        return 2
    сошлось, разошлось, немых = 0, [], 0
    стр_сошлось, стр_разошлось = 0, []
    for м in миры:
        # ВТОРОЕ ЧИСЛО САМОСЧЁТА: страницы против непустых строк мира.
        стр = страниц_сказано(м.get("genre", ""))
        if стр is not None:
            п = pathlib.Path(м.get("file", ""))
            if not п.is_absolute():
                п = КОРЕНЬ / п
            if п.is_file():
                дело = sum(1 for с in п.read_text(encoding="utf-8", errors="replace").split("\n")
                           if с.strip())
                if стр == дело:
                    стр_сошлось += 1
                else:
                    стр_разошлось.append((м["name"], стр, дело))
        n = сказано(м.get("genre", ""))
        if n is None:
            немых += 1
            continue
        роды = дом_мира(м.get("name", ""))
        if роды is None:
            немых += 1
            continue
        if n == len(роды):
            сошлось += 1
            if дов.подробно:
                print(f"  {м['name']:<20} {n} родов — сошлось")
        else:
            разошлось.append((м["name"], n, len(роды)))
    for имя, n, д in разошлось[: None if дов.подробно else 10]:
        print(f"  РОДОВ РАЗОШЛОСЬ «{имя}»: объявление говорит {n}, в доме родов {д}")
    for имя, n, д in стр_разошлось[: None if дов.подробно else 10]:
        print(f"  СТРАНИЦ РАЗОШЛОСЬ «{имя}»: объявление говорит {n}, в мире {д} ({д - n:+d})")
    всего = len(разошлось) + len(стр_разошлось)
    поза = "PASS" if всего <= РАЗОШЕДШИХСЯ_РУБЕЖ else "FAIL"
    print(f"САМОСЧЁТ ОБЪЯВЛЕНИЯ {поза}: разошлось {всего} (рубеж {РАЗОШЕДШИХСЯ_РУБЕЖ}) — "
          f"родов {len(разошлось)}, страниц {len(стр_разошлось)}; сошлось родов {сошлось}, "
          f"страниц {стр_сошлось}; немых объявлений {немых} из {len(миры)}")
    return 0 if всего <= РАЗОШЕДШИХСЯ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
