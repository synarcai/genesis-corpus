#!/usr/bin/env python3
"""[ЗНАК НЕ ТОТ] — строки пласта, чей знак языка называет ЧУЖОЙ язык.

Перепись беззнаковых считает строки, о которых знак МОЛЧИТ. Этот прибор считает те, о которых он
ГОВОРИТ НЕВЕРНО, — и это беда иного рода и худшая.

    МОЛЧАНИЕ ЗНАКА ОСТАВЛЯЕТ СТРОКУ ВСЯКОМУ СУДУ; ЛОЖЬ ЗНАКА ОТДАЁТ ЕЁ ОДНОМУ — И ИМЕННО ТОМУ,
    КТО НЕ ДОЛЖЕН СУДИТЬ. Итальянская «la cartella contiene 4 file» под английским знаком была
    названа ложью; английская «3 newtons × 1 metre» под турецким не была защищена ничем.

ЧТО ЗАМЕРЯЕТСЯ. У каждого языкового пласта язык ОБЪЯВЛЕН именем файла (`genesis_lang_fi` —
финский). Строка пласта, о которой `langsign.язык` говорит ДРУГОЙ язык, есть ошибка знака —
и она считается поимённо, парой «объявлено → сказано».

    ГОМОГРАФ СЛУЖЕБНОГО СЛОВА ЕСТЬ ГЛАВНАЯ ПРИЧИНА, И ЭТО ЗАМЕР, А НЕ ДОГАДКА: из 173 ошибок
    первого прогона 118 дало одно слово — «on». Оно английский предлог, финская связка («kauppa
    on tässä»), польское местоимение («on mieszka») и турецкое «десять» («on iki eksi dört»).
    Прочие: индонезийское «dia» против португальского «dia», французское «il» против
    итальянского, венгерское «hat» («шесть») против немецкого «hat» («имеет»).

ЧЕГО ПРИБОР НЕ СЧИТАЕТ ОШИБКОЙ: молчания. Строка без знака есть предмет ПЕРЕПИСИ БЕЗЗНАКОВЫХ, и
считать её дважды значило бы сложить два разных долга в одно число.

    python3 scripts/wrong_sign.py [--строк N] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --строк 0
import argparse
import collections
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import langsign  # noqa: E402

# РУБЕЖ-ДОЛГА: ЧУЖИХ_РУБЕЖ = 3
#
# Поставлен был на 173 — уровень того часа — И ЗАКРЫТ ПОЧТИ ЦЕЛИКОМ В ТОТ ЖЕ ЧАС. Причина
# оказалась одна и общая для всех шести пар: ЗНАК В ОДНО СЛОВО СЛИШКОМ ТОНОК, ЧТОБЫ РЕШАТЬ СПОР
# В ОДИНОЧКУ. Языку довольно было набрать ЕДИНИЦУ гомографом, чтобы забрать строку у того, чьи
# слова стоят в ней объявленными единолично. Ныне при таком знаке к нему прибавляются
# единоличные слова (`langsign.счёт`), и ошибок осталось 3 из 5 800: «uno por uno es uno» —
# испанская строка из слов, объявленных и итальянским, — да «il court» о трёх буквах.
#
# Рубеж есть ПОТОЛОК: всякая правка знака двигает его вниз, всякая новая ошибка роняет прибор.
ЧУЖИХ_РУБЕЖ = 3


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--строк", type=int, default=200, help="строк на пласт")
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    пласты = sorted((КОРЕНЬ / "datasets").glob("genesis_lang_*.txt"))
    if not пласты or дов.строк <= 0:
        print(f"ЗНАК НЕ ТОТ ОТКАЗ: считать нечего (пластов {len(пласты)}, "
              f"строк на пласт {дов.строк})")
        return 2
    итог = collections.Counter()
    пары = collections.Counter()
    примеры = {}
    for путь in пласты:
        свой = путь.stem[len("genesis_lang_"):]
        строки = [с for с in путь.read_text(encoding="utf-8", errors="replace").splitlines()
                  if с.strip()][:дов.строк]
        for с in строки:
            сказано = langsign.язык(с)
            итог["всего"] += 1
            if сказано == свой:
                итог["свой"] += 1
            elif сказано is None:
                итог["молчит"] += 1
            else:
                итог["чужой"] += 1
                пары[(свой, сказано)] += 1
                примеры.setdefault((свой, сказано), с)
    сколько = len(пары) if дов.подробно else 8
    for (свой, сказано), n in пары.most_common(сколько):
        print(f"  {свой} → {сказано}: {n:>4}   «{примеры[(свой, сказано)][:78]}»")
    поза = "PASS" if итог["чужой"] <= ЧУЖИХ_РУБЕЖ else "FAIL"
    доля = 100 * итог["чужой"] / max(1, итог["всего"])
    print(f"ЗНАК НЕ ТОТ {поза}: строк осмотрено {итог['всего']} из {len(пласты)} пластов; "
          f"ЗНАК НАЗВАЛ ЧУЖОЙ ЯЗЫК {итог['чужой']} ({доля:.1f} %, рубеж {ЧУЖИХ_РУБЕЖ}); "
          f"свой {итог['свой']}, молчит {итог['молчит']} (их считает перепись беззнаковых)")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
