#!/usr/bin/env python3
"""[ОТВЕРГНУТО ПО ИМЕНИ] — каждый дом обязан показать не только согласие, но и ОТКАЗ.

ПОВОД (ARCH-REVIEW-0907, Р-3, условие holon-f9 к моим домам). Дома вносятся в свод с двумя
числами: «не читает никто 0» и «ложных 0». Оба суть СОГЛАСИЕ.

    ПАЛАТА, ПОКАЗАВШАЯ ТОЛЬКО СОГЛАСИЕ, НЕ ОТЛИЧИМА ОТ ПАЛАТЫ МОЛЧАЩЕЙ. «Ложных 0» есть
    либо чистота мира, либо слепота судов на нём, и по самому нулю их не различить — ровно
    как «течей 0» у прибора полосы, который пришлось проверять шестьюдесятью тактами,
    слепленными из свода.

Потому третье число: ОТВЕРГНУТО ПО ИМЕНИ. Живая страница дома портится ОБЪЯВЛЕННОЙ порчей —
число ответа заменяется соседним, — и палата обязана назвать её ложью И НАЗВАТЬ СУД, который
это сделал. Дом, чью порчу не увидел никто, идёт в свод с объявленной дырой, а не с
молчаливой.

ПОРЧА ОБЪЯВЛЕНА И МИНИМАЛЬНА: берётся ПОСЛЕДНЕЕ число строки (итог ответа) и увеличивается
на единицу. Строка остаётся той же по форме, по словам и по согласованию — ложной делается
ровно ВЕЛИЧИНА, то есть то, ради чего дом и стои́т.

    python3 scripts/house_rejects.py [--дом ИМЯ] [--проб 12]
"""
# ПУСТОЙ-ОБХОД: --дом no-such-house
import argparse
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "courts"))

# РУБЕЖ-ДОЛГА: СЛЕПЫХ_ДОМОВ_РУБЕЖ = 0
#
# Дом, чью объявленную порчу не увидел ни один суд палаты, есть дом, о котором палата
# ничего не говорит. Ноль есть ПОЛ: всякий новый мир, чья порча невидима, роняет прибор в
# час своего внесения.
#
# ЧИСЛО ПРОБ — БЮДЖЕТ, А НЕ ПОРОГ: слепота видна на первой же пробе, пробы взяты ради
# устойчивости к случайной строке без числа.
СЛЕПЫХ_ДОМОВ_РУБЕЖ = 0
ПРОБ = 12

_ЧИСЛО = re.compile(r"(\d+)(?!.*\d)")   # последнее число строки

# ПОСЛЕДНЕЕ ЧИСЛО СТРОКИ НЕ ВСЕГДА ЕСТЬ ИТОГ (07.09, первый прогон прибора). Два дома из
# двухсот семи объявились слепыми — `md_latex` и `mandateforms`, — и оба слепыми не были:
#
#     «правило: не создавай файлы. удали 3 файла. можно ли выполнить приказ? да: правило
#      запрещает создание, а это удаление.»
#
# Тройка здесь есть ЧИСЛО ФАЙЛОВ В ПРИКАЗЕ, а ответ — «да»; замени её на четвёрку, и
# страница останется ИСТИННОЙ. Порча была не порчей, и молчание палаты — законным.
#
#     ПОРЧА, НЕ ДЕЛАЮЩАЯ СТРОКУ ЛОЖНОЙ, НЕ МЕРИТ НИЧЕГО. Прибор, зовущий дом слепым за
#     то, что тот не возразил на честную строку, есть ложный прибор — и он опаснее
#     молчащего, ибо кричит.
#
# Потому портится не всякое последнее число, а лишь то, что стои́т ИТОГОМ: результат
# ЛЕДЖЕРА (два числа и действие перед знаком равенства) или число ОТВЕТА (после
# вопросительного знака). Это признак, а не список имён: дом, у которого нет ни леджера, ни
# числового ответа, честно выпадает из пробы, и прибор говорит о нём «проб 0», а не «слеп».
#
# ЗНАК РАВЕНСТВА САМ ПО СЕБЕ ИТОГА НЕ ОБЪЯВЛЯЕТ (07.09, вторая проба прибора). Мир
# начертаний показывает КОД: «код-блок из одной строки: let schema = 8;» — и восьмёрка там
# есть ПРИСВОЕНИЕ, а не результат: замени её на девятку, и страница останется истинной, ибо
# ничего перед ней не вычислялось.
#
#     ИТОГ ЕСТЬ ТО, ЧТО ИЗ ЧЕГО-ТО СЛЕДУЕТ. Число после «=» без действия перед ним не
#     следует ни из чего, и портить его — значит менять показ, а не лгать в нём.
_ИТОГ = re.compile(r"(?:\d+\s*[-+−*×/÷]\s*\d+\s*=\s*|\?[^?]*?)(\d+)(?!.*\d)")


def порча(строка):
    """Строка с испорченным ИТОГОМ — или None, если итога в ней нет."""
    м = _ИТОГ.search(строка)
    if not м:
        return None
    было = int(м.group(1))
    стало = str(было + 1)
    return строка[:м.start(1)] + стало + строка[м.end(1):]


def миры(только=None):
    м = json.loads((КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json").read_text(encoding="utf-8"))
    корень = м.get("external_root") or ""
    вон = []
    for мир in м["worlds"]:
        if мир.get("text") != "shows":
            continue
        if только is not None and мир["name"] != только:
            continue
        путь = КОРЕНЬ / мир["file"]
        if not путь.exists() and корень:
            путь = (КОРЕНЬ / корень / мир["file"]).resolve()
        if путь.is_file():
            вон.append((мир["name"], путь))
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--дом", default=None)
    ап.add_argument("--проб", type=int, default=ПРОБ)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    список = миры(дов.дом)
    if not список:
        print(f"ОТВЕРГНУТО ПО ИМЕНИ ОТКАЗ: миров не найдено"
              f"{f' ({дов.дом})' if дов.дом else ''}")
        return 2
    import panel
    п = panel.Палата()
    слепые, всего_проб, всего_отвергнуто = [], 0, 0
    print(f"{'дом':<24}{'проб':>6}{'отвергнуто':>12}{'кем':>26}")
    for имя, путь in список:
        слои = п.слои(путь)
        пласт = п.пласт_файла(путь)
        строки = [с.strip() for с in путь.read_text(encoding="utf-8", errors="replace").splitlines() if с.strip()]
        проб = отвергнуто = 0
        судьи = {}
        первая = None
        for с in строки:
            if проб >= дов.проб:
                break
            битая = порча(с)
            if битая is None or битая == с:
                continue
            проб += 1
            судимо, истинно, кем = п.судить(битая, слои, пласт)
            if судимо and not истинно:
                отвергнуто += 1
                for к in кем:
                    судьи[к] = судьи.get(к, 0) + 1
            elif первая is None:
                первая = битая
        if not проб:
            continue
        всего_проб += проб
        всего_отвергнуто += отвергнуто
        кем_строка = ", ".join(f"{к}:{n}" for к, n in sorted(судьи.items(), key=lambda x: -x[1])[:2])
        print(f"{имя:<24}{проб:>6}{отвергнуто:>12}{кем_строка:>26}")
        if отвергнуто == 0:
            слепые.append((имя, проб, первая))
    print(f"{'ИТОГО':<24}{всего_проб:>6}{всего_отвергнуто:>12}")
    for имя, проб, первая in слепые:
        print(f"  СЛЕПОЙ ДОМ [{имя}] 0 из {проб}: «{(первая or '')[:110]}»")
    поза = "PASS" if len(слепые) <= СЛЕПЫХ_ДОМОВ_РУБЕЖ else "FAIL"
    print(f"ОТВЕРГНУТО ПО ИМЕНИ {поза}: домов, чью объявленную порчу не увидел никто, "
          f"{len(слепые)} (рубеж {СЛЕПЫХ_ДОМОВ_РУБЕЖ}); домов {len(список)}, проб "
          f"{всего_проб}, отвергнуто {всего_отвергнуто}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
