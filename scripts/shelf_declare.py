#!/usr/bin/env python3
"""[ПОЛКА БЕЗ ОБЪЯВЛЕНИЯ] — книга, лежащая на диске и не стоящая в манифесте.

Мир есть функция манифеста: файл, которого манифест не называет, не читается
ни судом, ни сборкой, ни прибором — он невидим целиком. Такая книга не просто
бесполезна, она ОБМАНЧИВА: на диске она есть, в корпусе её нет, и разница
видна только тому, кто сличит две стороны.

Так и вышло 03.09: подагент выковал три тома «Fizyka dla szkół wyższych» (4 МБ
чистого текста, CC BY 4.0 по четырём свидетельствам издателя), положил файлы на
полку — и остановился, не дописав манифест. Файлы пролежали сутки НЕ ЗАМЕЧЕННЫМИ
НИКЕМ, пока владелец не спросил, почему они болтаются в изменениях.

Прибор сличает ДОГОВОР ПОЛКИ (`tools/shelf_open.py`, где у каждой книги
объявлены заглавие, автор, издатель, лицензия, происхождение) с манифестом, и
называет по имени всякую книгу, чей файл есть, а записи нет. С ключом
`--вписать` он эту запись СТРОИТ ИЗ ДОГОВОРА — ни одно поле не пишется рукой,
и потому вписанное не может разойтись с объявленным.

    python3 scripts/shelf_declare.py [--вписать]
"""
import argparse
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"


def запись(книга, путь):
    """Запись манифеста, ПОСТРОЕННАЯ ИЗ ДОГОВОРА — ни одного поля рукой."""
    держ = путь.with_suffix("").with_suffix("")  # …/имя.txt → …/имя
    held = держ.parent / f"{держ.name}.holdout.txt"
    вон = {
        "name": книга.имя,
        "file": str(путь.relative_to(КОРЕНЬ)),
        "genre": f"{книга.заглавие} — {книга.автор}; {книга.издатель} {книга.издано} под {книга.лицензия}",
        "act": ["expound"], "oracle": ["none"], "boundary": ["unnamed"],
        "size": путь.stat().st_size, "tiers": [], "text": "prose",
        "тема": книга.тема, "язык": книга.язык, "плотность": книга.плотность,
        "издано": книга.издано, "источник": книга.источник,
        "происхождение": (f"{книга.дорога}-archive:{книга.uuid}@{книга.версия}, "
                          f"{книга.происхождение} ({книга.лицензия})"),
        "судится": [], "автор": книга.автор,
    }
    if held.is_file():
        вон["held_out"] = str(held.relative_to(КОРЕНЬ))
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--вписать", action="store_true")
    а = ап.parse_args()
    import shelf_open
    манифест = json.loads(МАНИФЕСТ.read_text(encoding="utf-8"))
    объявлено = {м.get("name") for м in манифест["worlds"]}
    пропавшие, безфайла = [], []
    for книга in shelf_open.ПОЛКА:
        путь = None
        for кандидат in (КОРЕНЬ / "shelf" / (книга.язык or "en") / f"{книга.имя}.txt",):
            if кандидат.is_file():
                путь = кандидат
        if книга.имя in объявлено:
            continue
        (пропавшие if путь else безфайла).append((книга, путь))
    for книга, путь in пропавшие:
        print(f"  НЕ ОБЪЯВЛЕНА: {книга.имя} ({путь.stat().st_size} байт, {книга.лицензия})")
    for книга, _ in безфайла:
        print(f"  НЕТ ФАЙЛА (и не объявлена, это не долг): {книга.имя}")
    if а.вписать and пропавшие:
        for книга, путь in пропавшие:
            манифест["worlds"].append(запись(книга, путь))
        МАНИФЕСТ.write_text(json.dumps(манифест, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"  ВПИСАНО в манифест: {len(пропавшие)}")
    # ВПИСАВ, ПРИБОР БОЛЬШЕ НЕ ДОЛЖНИК: без ключа он суд и падает на находке,
    # с ключом — рука, и падать после починки значило бы врать о состоянии.
    исправлено = а.вписать and пропавшие
    поза = "PASS" if not пропавшие or исправлено else "FAIL"
    хвост = " (вписаны этим же прогоном)" if исправлено else ""
    print(f"ПОЛКА БЕЗ ОБЪЯВЛЕНИЯ {поза}: {len(пропавшие)} книг лежали на диске без записи{хвост} "
          f"(в договоре {len(shelf_open.ПОЛКА)}, в манифесте {len(объявлено)} миров)")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
