#!/usr/bin/env python3
"""[ОДИНОКИЙ ОТВЕТ] — вопрос, чьё число не подпёрто в своде ничем.

Повод (04.09). Перепись леджеров, обретя третий вердикт (М-171), назвала
2 794 строки «без опоры В СТРОКЕ»: вопрос без единого числа, а ответ —
число («how many balls does mary have left? 6 balls left.»). Прибор, читающий
строки, не вправе судить страницу — и потому честно молчал. Но молчание
было о СТРОКЕ, а не о СВОДЕ: опора такой строки, если она есть, живёт на
другой строке того же свода, и это уже проверяемо.

    mary had 9 balls. mary gave away 3 balls. mary has 6 balls left.   ← опора
    how many balls does mary have left? 6 balls left.                  ← вопрос

Проверка ставится так. Содержательные слова вопросной строки (имена, вещи,
глаголы — всё, кроме объявленных служебных) и ЗНАЧЕНИЕ её ответа образуют
якорь. Строка ПОДПЁРТА, если в том же своде есть ИНАЯ строка, несущая это
значение числом и не менее двух её содержательных слов: такая строка могла
родить ответ. Строка, для которой такой нет, есть ОДИНОКИЙ ОТВЕТ — число,
которое нечем вывести, и потому доступное лишь заучиванию.

ЧЕГО ПРИБОР НЕ ВИДИТ, НАЗВАНО ЧЕСТНО (М-171):
  · он не проверяет, что опора АРИФМЕТИЧЕСКИ рождает ответ, — только что
    она могла бы: совпадение значения и двух слов есть свидетельство
    возможности, а не вывода;
  · «подпёрто» потому и не зовётся «выведено»: прибор считает ОДИНОКИЕ, и
    это число — верхняя граница памяти без вывода, а не точная её мера.

Повод сильнее прочих: срез (`scripts/minimal_build.py`) берёт первые LAW²
строк КАЖДОГО РОДА, а пять поверхностей одного факта суть пять РАЗНЫХ родов
— и срез берёт из них поверхности РАЗНЫХ фактов. Свод полон, срез рвёт.

    python3 scripts/orphans.py [datasets/GENESIS-MIN.txt ...]
"""
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

_ВОПРОС = re.compile(r"\?\s*(.+)$", re.S)
_ЧИСЛО = re.compile(r"\d+")
_СЛОВО = re.compile(r"[^\W\d_]{3,}", re.UNICODE)
# служебные слова вопросной рамки — они стоят в КАЖДОЙ строке рода и потому
# не различают факт; якорь строится на остальных
СЛУЖЕБНЫЕ = {
    "how", "many", "much", "does", "did", "do", "has", "have", "had", "the",
    "and", "now", "left", "are", "was", "were", "there", "what", "who", "when",
    "сколько", "стало", "осталось", "было", "есть", "теперь", "всего", "что",
    "кто", "когда", "ответ", "равно",
}


def якорь(строка):
    """(значение ответа, содержательные слова) или None, если строка не та."""
    м = _ВОПРОС.search(строка)
    if not м:
        return None
    вопрос, ответ = строка[:м.start()], м.group(1)
    if _ЧИСЛО.search(вопрос):
        return None            # вопрос несёт своё число — опора при нём
    числа = _ЧИСЛО.findall(ответ)
    if len(числа) != 1:
        return None            # либо не число, либо уже кузница
    слова = {с.lower() for с in _СЛОВО.findall(строка)} - СЛУЖЕБНЫЕ
    return (числа[0], слова) if len(слова) >= 2 else None


def подпорки(строки):
    """слово → номера строк, где оно стоит вместе с каким-нибудь числом."""
    вон = collections.defaultdict(set)
    числа_строки = []
    for i, с in enumerate(строки):
        числа = set(_ЧИСЛО.findall(с))
        числа_строки.append(числа)
        if not числа:
            continue
        for сл in {w.lower() for w in _СЛОВО.findall(с)} - СЛУЖЕБНЫЕ:
            вон[сл].add(i)
    return вон, числа_строки


def одинокие(строки):
    где, числа_строки = подпорки(строки)
    вон = []
    for i, с in enumerate(строки):
        я = якорь(с)
        if not я:
            continue
        значение, слова = я
        сколько = collections.Counter()
        for сл in слова:
            for j in где.get(сл, ()):
                if j != i and значение in числа_строки[j]:
                    сколько[j] += 1
        if not any(n >= 2 for n in сколько.values()):
            вон.append((i, с))
    return вон


def main():
    цели = sys.argv[1:] or ["datasets/GENESIS-FULL.txt", "datasets/GENESIS-MIN.txt"]
    беда = 0
    for имя in цели:
        путь = КОРЕНЬ / имя
        if not путь.is_file():
            print(f"  нет файла: {имя}", file=sys.stderr)
            continue
        строки = [с for с in путь.read_text(encoding="utf-8").splitlines()
                  if с.strip() and not с.startswith("\x0c")]
        сироты = одинокие(строки)
        всего = sum(1 for с in строки if якорь(с))
        доля = 100 * len(сироты) // max(1, всего)
        print(f"ОДИНОКИЙ ОТВЕТ {путь.name}: {len(сироты)} из {всего} вопросов без числа "
              f"не подпёрты ничем ({доля} %); строк {len(строки)}")
        for _, с in сироты[:5]:
            print(f"    {с[:100]}")
        беда = max(беда, len(сироты))
    return 0


if __name__ == "__main__":
    sys.exit(main())
