#!/usr/bin/env python3
"""[НЕВЕДОМОЕ ИМЯ] — счётные имена, которые свод показывает, а английский пакет не объявляет.

Суд английского числа (`courts/engram_court.py`) правит формой имени по счёту: «1 meter», но
«3 meters». Слова, которого нет в `noun_forms`, он НЕ ЧИТАЕТ — и молчит. Молчание честно, но
оно есть ДЫРА В СТРАЖЕ: у «7 boys» нет судьи вовсе, и подмена формы там пройдёт незамеченной.
Прибор `idle_word` считает объявленное и не показанное; этот считает ОБРАТНОЕ — показанное и
не объявленное.

    ИМЯ ДОКАЗЫВАЕТСЯ ДВУМЯ ФОРМАМИ. Свод сам показывает, что слово счётно: «1 boy» при единице
    и «7 boys» при многих. Догадка о части речи не нужна — довольно двух клеток.

ГЛАГОЛ ОТЛИЧАЕТСЯ ОТ ИМЕНИ ОБРАТНЫМ ЗНАКОМ ЧИСЛА, и это не вкус, а закон английского: у ИМЕНИ
«-s» стои́т ПРИ МНОГИХ («3 boys»), у ГЛАГОЛА — ПРИ ЕДИНИЦЕ («1 gives», «3 give»). Оттого пара
(give, gives) выглядит как имя, покуда смотришь лишь на две клетки, и опровергается третьей:
«1 gives» встречается 12 раз. Пять слов свода — give, equal, do, lie, stand — отсеяны этим
законом, и ни одно не названо рукой.

ЧЕТЫРЕ КЛЕТКИ, А НЕ ДВЕ. Слово считается неведомым именем, только если ОБЕ опровергающие клетки
пусты: нет ни «1 <мн>», ни «N <ед>». Та же пустота есть и ДОКАЗАТЕЛЬСТВО БЕЗОПАСНОСТИ: объявить
такое слово нельзя во вред, ибо в своде нет ни одной строки, которую новый закон назвал бы ложью.
Долг тут ровно тот, что можно закрыть сегодня и без порчи.

ЧУЖОЙ ОМОГРАФ ЗАПРЕЩАЕТ ОБЪЯВЛЕНИЕ, ПОКА ЗНАК ЯЗЫКА МОЛЧИТ (08.09). Польское «ruble» пишется как
английское единственное; строка «liczę 2 ruble.» коротка и не несёт ни одного служебного слова,
какое знает `langsign`, — знак языка о ней молчит, и английский суд взялся бы её судить. Объяви
«ruble» — и ИСТИННАЯ польская строка была бы названа ложью. Такие слова прибор кладёт в
ОСПОРЕННЫЕ, а не в долг: клетка «N <ед>» полна, и полна она чужим языком.

    python3 scripts/unknown_name.py [--подробно] [--свод ПУТЬ]
"""
# ПУСТОЙ-ОБХОД: --свод /dev/null
import argparse
import collections
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import langsign  # noqa: E402

# РУБЕЖ-ДОЛГА: НЕВЕДОМЫХ_РУБЕЖ = 0
#
# Поставлен прибор был на 10 — boy, brother, buyer, doctor, driver, farmer, father, mother,
# sister, time — и закрыт в тот же час: все десять объявлены пакетом, ибо четыре клетки
# доказали, что ни одна строка свода от того не станет ложной. Рубеж есть ПОЛ: имя, вошедшее
# в свод без объявления, роняет прибор в тот же день, когда его напишут.
НЕВЕДОМЫХ_РУБЕЖ = 0

# СЛОВО-ОПЕРАТОР НЕ ОБЪЯВЛЯЕТСЯ ИМЕНЕМ, ХОТЯ И ДОКАЗАНО ДВУМЯ ФОРМАМИ (08.09, тем же днём).
# «time / times» прошло все четыре клетки и было объявлено — а назавтра обвинило три дома в
# половинчатом законе и уронило меру «единственное при единице» на 114 строках «one times five
# equals five». Ибо в этом своде у слова ДВЕ ЖИЗНИ, и счётная — меньшая: 12 страниц «applied
# 3 times» против тысячи с лишним страниц таблицы умножения.
#
#     ОБЪЯВЛЕНИЕ ЕСТЬ НЕ ТОЛЬКО ПРАВО СУДИТЬ, НО И ОБЯЗАННОСТЬ РАЗЛИЧАТЬ. Объявив слово, я учу
#     ВСЯКОГО читателя пакета — и суды, и приборы — его видеть; и всякий из них обязан отличить
#     имя от оператора. Когда счётная жизнь слова редка, а дом и без того пишет её законом
#     («'time' if n == 1 else 'times'» в доме грамматик), объявление стои́т дороже, чем даёт.
#
# Цена названа прямо: двенадцать строк «applied N time(s)» остаются без суда числа. Дом пишет их
# условием при самом числе, и потому они верны письмом, а не надзором.
ОПЕРАТОРЫ = frozenset({"times"})

# ОБЪЯВЛЕНИЕ ГАСИТ ТОТ САМЫЙ ЗНАК, КОТОРЫЙ ЕГО РАЗРЕШАЛ (08.09, вечер). Утром «ruble» лежало в
# оспоренных: клетка «N ruble» была полна ПОЛЬСКИМИ строками, какие знак языка не опознавал, и
# объявить слово английским значило бы солгать о них. Днём знак получил ЗАКОН ПОСЛЕДНЕЙ НАДЕЖДЫ
# (`langsign.ЕДИНОЛИЧНЫЕ`), «liczę 2 ruble.» стало польским — и клетка очистилась: слово вышло
# честным неведомым именем, и прибор потребовал его объявить.
#
# ОБЪЯВИЛ — И ЗНАК ПОГАС. «ruble» перестало быть словом РОВНО ОДНОГО пакета в тот же миг, как
# английский пакет его назвал; польская строка снова осталась без знака, и суд английского числа
# тут же назвал её ложью. Круг замкнулся на себе.
#
#     СЛОВО, ЧЕЙ ЗНАК ДЕРЖИТСЯ ЕДИНОЛИЧНОСТЬЮ, НЕЛЬЗЯ ОБЪЯВИТЬ ВТОРЫМ ЯЗЫКОМ, НЕ ПОГАСИВ ЗНАКА.
#     Долг тут закрывается не объявлением имени, а объявлением СЛУЖЕБНОГО СЛОВА той строки, —
#     как «voici» и «ik» были объявлены нынче утром. Пока такого слова нет, имя лежит здесь.
СЛОВА_ЧУЖОГО_ЗНАКА = frozenset({"ruble"})


ПАКЕТ = json.loads((КОРЕНЬ / "tools" / "langpacks" / "en.json").read_text(encoding="utf-8"))
ЧИСЛО_СЛОВО = re.compile(r"\b(\d+) ([a-z]+)\b")


def объявленные():
    формы = ПАКЕТ.get("noun_forms", {})
    return set(формы) | {str(v) for v in формы.values()}


def клетки(путь):
    """Счёт слова при единице и при многих — по строкам, которые английский суд БЕРЁТ."""
    при1, приN, строк = collections.Counter(), collections.Counter(), 0
    for строка in путь.read_text(encoding="utf-8").splitlines():
        if not строка.strip() or langsign.чужой(строка, "en"):
            continue
        строк += 1
        for число, слово in ЧИСЛО_СЛОВО.findall(строка):
            (при1 if число == "1" else приN)[слово] += 1
    return при1, приN, строк


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--свод", default=None)
    дов = ап.parse_args()
    путь = pathlib.Path(дов.свод) if дов.свод else КОРЕНЬ / "datasets" / "GENESIS-FULL.txt"
    if not путь.exists():
        print(f"НЕВЕДОМОЕ ИМЯ ОТКАЗ: свода нет ({путь})")
        return 2
    знаемо = объявленные()
    при1, приN, строк = клетки(путь)
    if not строк:
        print(f"НЕВЕДОМОЕ ИМЯ ОТКАЗ: английских строк не найдено ({путь})")
        return 2
    имена, глаголы, оспорено = [], [], []
    for ед in sorted(при1):
        if ед in знаемо:
            continue
        мн = next((ф for ф in (ед + "s", ед + "es") if приN.get(ф) and ф not in знаемо), None)
        if not мн:
            continue
        при_1_мн, при_N_ед = при1.get(мн, 0), приN.get(ед, 0)
        запись = (ед, мн, при1[ед], приN[мн], при_1_мн, при_N_ед)
        if ед in СЛОВА_ЧУЖОГО_ЗНАКА or мн in СЛОВА_ЧУЖОГО_ЗНАКА:
            оспорено.append(запись)     # объявление погасило бы знак чужой строки
        elif мн in ОПЕРАТОРЫ:
            оспорено.append(запись)     # слово-оператор: объявление стои́т дороже, чем даёт
        elif при_1_мн:
            глаголы.append(запись)          # «-s» при единице: это глагол, не имя
        elif при_N_ед:
            оспорено.append(запись)         # клетка полна — чужой омограф или не имя
        else:
            имена.append(запись)
    имена.sort(key=lambda з: -(з[2] + з[3]))
    if имена or дов.подробно:
        print(f"{'слово':<14}{'1 ед':>7}{'N мн':>7}")
        for ед, мн, a, b, _, _ in имена:
            print(f"{ед:<14}{a:>7}{b:>7}   («1 {ед}» / «N {мн}») — суд числа НЕ ЧИТАЕТ")
    if дов.подробно:
        for имя, ряд in (("ГЛАГОЛ", глаголы), ("ОСПОРЕНО", оспорено)):
            for ед, мн, a, b, c, d in ряд:
                print(f"  {имя} {ед}/{мн}: «1 {ед}» {a}, «N {мн}» {b}; "
                      f"опровержения: «1 {мн}» {c}, «N {ед}» {d}")
    поза = "PASS" if len(имена) <= НЕВЕДОМЫХ_РУБЕЖ else "FAIL"
    print(f"НЕВЕДОМОЕ ИМЯ {поза}: английских строк {строк}, слов при числе {len(при1) + len(приN)}; "
          f"НЕВЕДОМЫХ ИМЁН {len(имена)} (рубеж {НЕВЕДОМЫХ_РУБЕЖ}); отсеяно обратным знаком "
          f"{len(глаголы)}, оспорено чужой клеткой {len(оспорено)}; объявлено пакетом "
          f"{len(ПАКЕТ.get('noun_forms', {}))} имён")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
