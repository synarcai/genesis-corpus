#!/usr/bin/env python3
"""[РАЗНОГЛАСИЕ СУДОВ] — ловит ли суд порчу, которую сосед пропускает.

ЧЕТВЁРТОЕ ЧИСЛО О СУДЕ, И ОНО ОТВЕЧАЕТ НА ВОПРОС, ОСТАВЛЕННЫЙ ОТКРЫТЫМ В
`declarations/COURT-WORTH.md`. Улов (`court_catch`) назвал 81 суд из 241, не
держащих НИ ОДНОЙ строки единолично. Объявление честно сказало, что это не
довод снять:

    СУД, ВЗЯВШИЙ СТРОКИ БЕЗ ЕДИНОЛИЧНОГО УЛОВА, ЕСТЬ ВТОРОЕ ЧТЕНИЕ, И СНИМАТЬ
    ЕГО МОЖНО ЛИШЬ ЗНАЯ, РАСХОДИТСЯ ЛИ ОН С ПЕРВЫМ.

Здесь это и меряется. На ЧЕСТНОМ своде разногласия нет по построению — ворота
не пускают строку, которую хоть кто-то зовёт ложью, — и мера по чистым строкам
дала бы ноль, ничего не сказав. Потому спрашивается ПОРЧА:

    берём строку, которую судят ДВОЕ И БОЛЕЕ, портим её ровно в одном месте и
    смотрим, КТО ИЗ НИХ СКАЗАЛ «ЛОЖЬ». Суд, поймавший порчу один, есть
    настоящее второе чтение: снимите его — и эта ложь пройдёт ворота.
    Суд, ловящий ровно то же, что сосед, не держит ничего.

ПРИЁМЫ ПОРЧИ НЕ ПИШУТСЯ ЗДЕСЬ ЗАНОВО, А БЕРУТСЯ У `word_mutants` — обрезание
слова и буква-двойник, — вместе с равномерной выборкой и зерном от `crc32`.

    ВТОРОЙ СПИСОК ТЕХ ЖЕ ПРИЁМОВ РАЗОШЁЛСЯ БЫ С ПЕРВЫМ В ТОТ ЖЕ ДЕНЬ. Общий
    список — не бережливость, а условие сравнимости двух мер.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ `word_mutants`, И ЗАЧЕМ НУЖНЫ ОБА. Тот спрашивает ПАЛАТУ
(«поймал ли кто-нибудь») и мерит ДЫРУ СВОДА. Этот спрашивает КАЖДЫЙ СУД ВРОЗЬ и
мерит ЦЕНУ СУДА. Первый отвечает «что пройдёт ворота», второй — «что пройдёт,
если снять вот этого». Числа их не выводятся одно из другого.

ПАЛАТА НЕ ГОДИТСЯ ДЛЯ ЭТОГО ВОПРОСА БЕЗ ПРАВКИ, И ПРАВКА НАЗВАНА: `судить`
возвращается на ПЕРВОМ сказавшем «ложь» (`return True, False, [имя]`) — так
надо воротам, которым довольно одного лжеца. Обход, считающий разногласие по
такому ответу, всякий раз видел бы ровно одного поймавшего и объявил бы всякий
суд единственным.

    МЕРА, ПОСТРОЕННАЯ НА ОТВЕТЕ, КОТОРЫЙ ОБРЫВАЕТСЯ НА ПЕРВОМ НАЙДЕННОМ, МЕРИТ
    ПОРЯДОК СЛОВАРЯ, А НЕ ДЕЛО. Оттого в палате заведён `судить_врозь`, а
    ветвление вызова вынесено в одно место (`_спросить`), чтобы два хода не
    разошлись.

ЧИСЛО ЭТО — ОТЧЁТ, А НЕ РУБЕЖ, и сказано почему: «ноль единоличных порч» не
есть долг. Он может значить и дубль, и то, что выборка не добралась до рода
этого суда. Рубеж здесь поставила бы рука, спутавшая незнание с виной.

    python3 scripts/court_split.py [--проб N] [--манифест ПУТЬ] [--подробно]
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import argparse
import collections
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import panel  # noqa: E402
import word_mutants as WM  # noqa: E402

МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
СЛЕД = КОРЕНЬ / "reports" / "COURT-SPLIT.tsv"
ПРОБ_НА_МИР = 12


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ВРОЗЬ — ЭТО ВРОЗЬ.

        ВЕСЬ ПРИБОР ДЕРЖИТСЯ НА ОДНОМ: что палата, спрошенная врозь, называет
        ВСЕХ поймавших, а не первого. Пусть `судить_врозь` вернётся к раннему
        выходу — и всякая порча окажется пойманной ровно одним судом, а прибор
        объявит второе чтение незаменимым всюду.

        НУЛЬ ЗРЯЧЕГО ОБЯЗАН ОТЛИЧАТЬСЯ ОТ НУЛЯ СЛЕПОГО.

    Проба не выдумывает строк: она берёт две настоящие — одну заведомо ложную
    для арифметики, одну честную — и спрашивает палату обоими ходами.
    """
    беды = []
    if not hasattr(panel.Палата, "судить_врозь"):
        return ["палата не знает `судить_врозь` — прибор мерить нечем"]
    п = panel.Палата()
    честно = "2 + 2 = 4"
    лживо = "2 + 2 = 5"
    врозь_ч = п.судить_врозь(честно)
    врозь_л = п.судить_врозь(лживо)
    if not врозь_ч:
        беды.append("честную строку «2 + 2 = 4» не судит НИКТО — палата пуста")
    if any(not и for и in врозь_ч.values()):
        беды.append(f"честная строка названа ложью: {sorted(и for и, в in врозь_ч.items() if not в)}")
    поймали = [и for и, в in врозь_л.items() if not в]
    if not поймали:
        беды.append("«2 + 2 = 5» не поймана никем — прибор слеп к самой явной лжи")
    # СОГЛАСИЕ ДВУХ ХОДОВ: что нашла палата коротким ходом, обязано найтись и врозь.
    судимо, истинно, кем = п.судить(лживо)
    if судимо and not истинно and кем and кем[0] not in поймали:
        беды.append(f"короткий ход назвал {кем[0]}, а врозь его среди поймавших нет")
    if len(врозь_ч) < len(кем or []):
        беды.append("врозь судящих МЕНЬШЕ, чем у короткого хода")
    return беды


def _порчи(строка):
    """[(род, порченая строка)] — приёмы берутся у `word_mutants`."""
    вон = []
    for род, приём in (("обрезание", WM.обрезание), ("двойник", WM.двойник)):
        если = приём(строка)
        if если is not None:
            вон.append((род, если[0]))
    return вон


def обойти(миры, внешний, проб_на_мир, подробно=False):
    """(судит, поймал, один, порч, разобрано, примеры) по всем мирам показов."""
    п = panel.Палата()
    поймал = collections.Counter()   # суд → сколько порч назвал ложью
    один = collections.Counter()     # суд → сколько порч поймал ОДИН
    судит = collections.Counter()    # суд → сколько честных строк читает
    порч = пойманных = разобрано = 0
    примеры = []
    for мир in миры:
        if мир.get("text") != "shows":
            continue
        путь = WM._файл(мир, внешний)
        if путь is None:
            continue
        слои = п.слои(путь)
        пласт = п.пласт_файла(путь)
        строки = [с.strip() for с in
                  путь.read_text(encoding="utf-8", errors="replace").splitlines()
                  if с.strip()]
        годные = [с for с in строки if WM.СЛОВО.search(с)]
        for честно in WM.равномерно(годные, проб_на_мир, WM.зерно_мира(мир["name"])):
            врозь = п.судить_врозь(честно, слои)
            if len(врозь) < 2 or any(not в for в in врозь.values()):
                # МЕРА ИДЁТ ТОЛЬКО ПО СТРОКАМ, КОТОРЫЕ ЧИТАЮТ ДВОЕ И БОЛЕЕ:
                # у строки с одним читателем разногласию не с кем случиться,
                # и считать её здесь значило бы разбавлять знаменатель.
                continue
            разобрано += 1
            for имя in врозь:
                судит[имя] += 1
            for род, порча in _порчи(честно):
                порч += 1
                после = п.судить_врозь(порча, слои)
                поймавшие = [и for и, в in после.items() if not в]
                if поймавшие:
                    пойманных += 1
                for и in поймавшие:
                    поймал[и] += 1
                if len(поймавшие) == 1:
                    один[поймавшие[0]] += 1
                    if len(примеры) < 8 or подробно:
                        примеры.append((мир["name"], поймавшие[0], род, честно[:58]))
    return судит, поймал, один, порч, пойманных, разобрано, примеры


def _записать(судит, поймал, один, порч, пойманных, разобрано):
    СЛЕД.parent.mkdir(parents=True, exist_ok=True)
    строки = [f"# суд\tчитает\tпоймал порч\tпоймал ОДИН\t"
              f"порч {порч}\tпойманных {пойманных}\tстрок {разобрано}"]
    for имя in sorted(set(судит) | set(поймал)):
        строки.append(f"{имя}\t{судит[имя]}\t{поймал[имя]}\t{один[имя]}")
    СЛЕД.write_text("\n".join(строки) + "\n", encoding="utf-8")


def main():
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"РАЗНОГЛАСИЕ СУДОВ ОТКАЗ: раздельный опрос не доказан ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--проб", type=int, default=ПРОБ_НА_МИР)
    ап.add_argument("--манифест", default=None)
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    манифест = pathlib.Path(дов.манифест) if дов.манифест else МАНИФЕСТ
    if not манифест.is_file():
        print(f"РАЗНОГЛАСИЕ СУДОВ ОТКАЗ: нет манифеста {манифест}")
        return 2
    м = json.loads(манифест.read_text(encoding="utf-8"))
    судит, поймал, один, порч, пойманных, разобрано, примеры = обойти(
        м["worlds"], м.get("external_root"), дов.проб, дов.подробно)
    if not порч:
        print("РАЗНОГЛАСИЕ СУДОВ ОТКАЗ: ни одной порчи — миров показов нет")
        return 2
    for имя, кто, род, строка in примеры:
        print(f"  ЕДИНСТВЕННЫЙ [{имя}] {кто} ({род}): «{строка}»")
    единоличные = sorted(((в, и) for и, в in один.items() if в), reverse=True)
    print("  ДЕРЖАТ ПОРЧУ ОДНИ: " + (", ".join(f"{и} {в}" for в, и in единоличные[:12])
                                     or "никто"))
    немые = sorted(и for и in судит if not поймал[и])
    print(f"  ЧИТАЮТ, НО НЕ ЛОВЯТ НИЧЕГО ({len(немые)}): " + ", ".join(немые[:12]))
    _записать(судит, поймал, один, порч, пойманных, разобрано)
    print(f"РАЗНОГЛАСИЕ СУДОВ ОТЧЁТ: порч {порч} по {разобрано} строкам, читаемым двумя "
          f"и более; поймано {пойманных} ({100 * пойманных // порч}%); судов, поймавших "
          f"хоть одну, {sum(1 for и in поймал if поймал[и])} из {len(судит)} читающих; "
          f"держат порчу ЕДИНСТВЕННЫМИ {len(единоличные)}; сайдкар "
          f"{СЛЕД.relative_to(КОРЕНЬ)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
