#!/usr/bin/env python3
"""[ЗНАК ЦЕЛ] — испорченный знак не ловит ни один суд свода.

ПОВОД, И ОН МОЙ СОБСТВЕННЫЙ. 12.09, дописывая дом одношагового уравнения, я оставил в его
законе строку «ДОМ СТРОИТСЯ НА ТОМ, ЧТО МИР НЕСЁТ ОДИН, А НЕ НА ВС?ём» — с ЗНАКОМ ЗАМЕНЫ
посреди слова. Дом прошёл самопроверку, палата прошла состав, суд оборванной фразы прошёл,
закон первым прошёл. Двести тринадцать судов и сто семьдесят восемь приборов не сказали
ничего: они читают СМЫСЛ строки, а не ЦЕЛОСТЬ её знаков.

    СУД, ЧИТАЮЩИЙ СТРОКУ, НЕ ВИДИТ ПОРЧИ ЗНАКА: для него испорченная буква есть
    просто другая буква, и утверждение остаётся тем же утверждением.

ЧТО ЗДЕСЬ МЕРИТСЯ — ТРИ БЕДЫ, И ВСЕ ТРИ МАШИННЫ:

    ЗНАК ЗАМЕНЫ         U+FFFD — след чтения чужой кодировкой. Всякое его вхождение есть
                        утраченная буква, и восстановить её нельзя: знак замены не помнит,
                        чем он был.
    МОЙЖИБАКЕ           кириллица или типографский знак, прочтённые как latin-1 и записанные
                        обратно. Буквы целы поодиночке, а слово мертво — и потому глазом это
                        ловится, а грепом по букве нет. ОБРАЗЦА ЗДЕСЬ НЕ СТОИ́Т НАРОЧНО: прибор
                        нашёл САМОГО СЕБЯ на первом же зове, ибо в этой самой строке стояло
                        живое слово-мойжибаке. Тот закон, о котором писано ниже, поймал своего
                        писца через минуту после того, как был записан.
    НЕ ЧИТАЕТСЯ         файл, который не открывается как utf-8 вовсе.

ПРИЗНАК ПИСАН КОДОМ, А НЕ ЗНАКОМ, И ЭТО КУПЛЕНО ПАДЕНИЕМ ТОГО ЖЕ ДНЯ. Указатель приборов,
встав в `tools/`, счёл прибором самого себя — он нёс имя признака строкой и искал подстрокой.

    ПРИЗНАК, ИСКОМЫЙ ПОДСТРОКОЙ, НАХОДИТСЯ В ТОМ, КТО О НЁМ ГОВОРИТ.

Потому знак замены здесь записан как `chr(0xFFFD)`, а мойжибаке — диапазонами по кодам:
прибор не смеет нести в себе то, что ищет.

ГРАНИЦА НАЗВАНА: прибор не ищет ОПЕЧАТОК и не судит языка. Он ловит лишь ту порчу, что
оставляет МАШИННЫЙ СЛЕД — знак замены, латиницу вместо кириллицы, нечитаемый файл. Слово,
написанное с ошибкой, но целыми буквами, для него цело, и это сказано вслух.

    python3 scripts/sign_intact.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --двор no-such-dir
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: ПОРЧИ_РУБЕЖ = 0
#
# Рубеж есть ПОЛ, а не поблажка: замер 12.09 по 1162 файлам дерева нашёл НОЛЬ — одна
# найденная порча была вылечена в тот же час, а прибор поставлен, чтобы следующая нашлась
# в час своего рождения, а не через месяц.
ПОРЧИ_РУБЕЖ = 0

ДВОРЫ = ("tools", "courts", "scripts", "datasets", "reports", "declarations")
РАСШИРЕНИЯ = (".py", ".txt", ".json", ".md", ".tsv", ".sh")

# ЗНАК ЗАМЕНЫ — КОДОМ, А НЕ ЗНАКОМ: прибор не смеет нести в себе то, что ищет.
ЗАМЕНА = chr(0xFFFD)

# МОЙЖИБАКЕ — ДИАПАЗОНАМИ ПО КОДАМ, ПО ТОЙ ЖЕ ПРИЧИНЕ, И ПРИЧИНА ЭТА СРАБОТАЛА ТРИЖДЫ.
# Первый байт двухбайтовой кириллицы в utf-8 есть 0xD0 или 0xD1, типографского знака —
# 0xE2; прочтённые как latin-1, они дают по букве, а следом идёт знак из 0x80–0xBF.
# НАЗВАТЬ ЭТИ БУКВЫ ЗДЕСЬ НЕЛЬЗЯ: вторая редакция этого самого комментария их назвала —
# и прибор упал на нём же, ибо буква с закрывающей кавычкой «…» и есть искомая пара.
МОЙЖИБАКЕ = re.compile(
    "[" + chr(0xD0) + chr(0xD1) + "][" + chr(0x80) + "-" + chr(0xBF) + "]"
    "|" + chr(0xC3) + "[" + chr(0x80) + "-" + chr(0xBF) + "]"
    "|" + chr(0xE2) + "[" + chr(0x80) + "-" + chr(0x9F) + "]")


def файлы(корень, дворы=ДВОРЫ):
    """Файлы дерева, чья запись объявлена текстовой."""
    вон = []
    for двор in дворы:
        д = корень / двор
        if not д.is_dir():
            continue
        for ф in sorted(д.rglob("*")):
            if ф.is_file() and ф.suffix in РАСШИРЕНИЯ:
                вон.append(ф)
    return вон


def порча(ф):
    """[(род, сколько, образец)] — беды этого файла, или пусто."""
    try:
        т = ф.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return [("не читается как utf-8", 1, "")]
    except OSError as беда:
        return [("не открывается", 1, str(беда)[:60])]
    вон = []
    if ЗАМЕНА in т:
        i = т.index(ЗАМЕНА)
        вон.append(("знак замены", т.count(ЗАМЕНА), т[max(0, i - 30):i + 15]))
    найдено = МОЙЖИБАКЕ.findall(т)
    if найдено:
        вон.append(("мойжибаке", len(найдено), "".join(найдено[:4])))
    return вон


def main():
    дворы = ДВОРЫ
    if "--двор" in sys.argv:
        дворы = (sys.argv[sys.argv.index("--двор") + 1],)
    пути = файлы(КОРЕНЬ, дворы)
    if not пути:
        print(f"ЗНАК ЦЕЛ ОТКАЗ: в дворах {list(дворы)} нет ни одного текстового файла")
        return 2
    беды, по_роду = [], collections.Counter()
    for ф in пути:
        for род, сколько, образец in порча(ф):
            по_роду[род] += сколько
            беды.append((ф.relative_to(КОРЕНЬ), род, сколько, образец))
    сколько = "--подробно" in sys.argv and len(беды) or min(len(беды), 8)
    for путь, род, n, образец in беды[:сколько]:
        print(f"  ПОРЧА {путь}: {род} x{n} — {образец!r}")
    всего = sum(по_роду.values())
    поза = "PASS" if всего <= ПОРЧИ_РУБЕЖ else "FAIL"
    роды = ", ".join(f"{и} {к}" for и, к in по_роду.most_common()) or "ни одной"
    print(f"ЗНАК ЦЕЛ {поза}: порч {всего} (рубеж {ПОРЧИ_РУБЕЖ}) — {роды}; "
          f"файлов проверено {len(пути)}, дворов {len(дворы)}")
    return 0 if всего <= ПОРЧИ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
