# ПУСТОЙ-ОБХОД: --дерево no-such-dir
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent

# РУБЕЖ-ДОЛГА: ОБРЫВОВ_РУБЕЖ = 0
ОБРЫВОВ_РУБЕЖ = 0

ЗАЧИН = re.compile(r"^(?:[А-ЯЁ][А-ЯЁ]+[,:]?\s+){2,}[А-ЯЁ][А-ЯЁ]+")
ОБРЫВ = re.compile(r"[а-яёa-z]$")

# ПРИЁМ ВЫДЕЛЕНИЯ, А НЕ ОБРЫВ: фраза сознательно переходит в прописные, и читается она целиком.
# ОБЪЯВЛЕНЫ ТОЛЬКО ТЕ, ЧТО СРАБАТЫВАЮТ. Первая редакция назвала пять — по широкому признаку; с
# сужением до нулевого отступа два из них («tools/panel.py», «scripts/word_mutants.py») перестали
# попадаться вовсе, и остались бы ПРИЗРАКАМИ объявления. Прибор считает объявленные приёмы и
# печатает, сколько из них СРАБОТАЛО: объявление, которое не срабатывает, есть ложь о деле.
ОБЪЯВЛЕННЫЕ_ПРИЁМЫ = {
    ("tools/gen_genesis_metalang.py", "ЯЗЫК, НА КОТОРОМ НАПИСАНЫ ВСЕ ОСТАЛЬНЫЕ."),
    ("tools/relation.py", "ОТНОШЕНИЯ МЕЖДУ ВЕЩАМИ"),
    ("scripts/template_word.py", "ВООБЩЕ ХОТЬ ГДЕ-НИБУДЬ В СВОЁМ ПАКЕТЕ»."),
}


def объявлен(путь, строка):
    """Названо ли это место приёмом — по имени файла и зачину строки."""
    имя = str(путь)
    return any(имя.endswith(файл) and строка.strip().startswith(зачин)
               for файл, зачин in ОБЪЯВЛЕННЫЕ_ПРИЁМЫ)


def обход():
    if "--дерево" in sys.argv:
        корень = pathlib.Path(sys.argv[sys.argv.index("--дерево") + 1])
        if not корень.is_dir():
            print(f"ОБОРВАННАЯ ФРАЗА ОТКАЗ: дерева нет — {корень}")
            sys.exit(2)
        return sorted(корень.rglob("*.py"))
    вон = []
    for каталог in ("tools", "courts", "scripts"):
        вон += sorted((КОРЕНЬ / каталог).rglob("*.py"))
    return вон


def main():
    пути = обход()
    обрывов = приёмов = 0
    примеры = []
    for п in пути:
        строки = п.read_text(encoding="utf-8", errors="replace").split("\n")
        for i, с in enumerate(строки[1:], 1):
            if not ЗАЧИН.match(с):
                continue
            пред = строки[i - 1].rstrip()
            if not пред or not ОБРЫВ.search(пред):
                continue
            если = п.relative_to(КОРЕНЬ) if п.is_relative_to(КОРЕНЬ) else п
            if объявлен(если, с):
                приёмов += 1
                continue
            обрывов += 1
            if len(примеры) < 6:
                примеры.append(f"{если}:{i + 1} — «…{пред.strip()[-40:]}» ‖ «{с.strip()[:44]}…»")
    for э in примеры:
        print(f"  {э}")
    # ПРИЗРАК ОБЪЯВЛЕНИЯ ЕСТЬ ТАКАЯ ЖЕ БЕДА, КАК ОБРЫВ: объявленный приём, который ни разу не
    # встретился, говорит о дереве то, чего в нём нет.
    if приёмов != len(ОБЪЯВЛЕННЫЕ_ПРИЁМЫ):
        обрывов += 1
        print(f"  ПРИЗРАК ОБЪЯВЛЕНИЯ: сработало {приёмов} приёмов из "
              f"{len(ОБЪЯВЛЕННЫЕ_ПРИЁМЫ)} объявленных")
    поза = "PASS" if обрывов <= ОБРЫВОВ_РУБЕЖ else "FAIL"
    print(f"ОБОРВАННАЯ ФРАЗА {поза}: {обрывов} обрывов (рубеж {ОБРЫВОВ_РУБЕЖ}); "
          f"файлов {len(пути)}, приёмов объявлено {приёмов} из {len(ОБЪЯВЛЕННЫЕ_ПРИЁМЫ)}")
    return 0 if обрывов <= ОБРЫВОВ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
