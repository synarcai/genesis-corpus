#!/usr/bin/env python3
"""[МАССА РОДА] — что корпус показывает СЛИШКОМ РЕДКО, чтобы этому научились.

    ФОРМА, ПОКАЗАННАЯ РАЗ, НЕ ПОКУПАЕТСЯ. Закон массы (`LAW2 = 9` в переписи форм) говорит:
    род, встреченный меньше девяти раз, организму не даётся — он видит его как случайность, а
    не как правило. Замер 10.09: РОДОВ 60 431, из них с массой меньше девяти — 47 935 (79 %),
    и несут они 103 396 строк свода.

ЭТО ПЕРВЫЙ ДОЛГ, НАЗВАННЫЙ КРИСТАЛЛОМ («колено массы и непокупаемые рамки»), и прибора у него
не было: число получалось рукой и умирало с сессией. Здесь оно получается всегда и с ПРИЧИНОЙ.

    ЧИСЛО БЕЗ ПРИЧИНЫ НЕ ГОВОРИТ, ЧТО ДЕЛАТЬ. «79 % непокупаемы» есть повод к унынию;
    «мир definitions по природе широк, а мир units имеет хвост» есть повод к работе.

ТРИ ПРИЧИНЫ, И ВСЕ ТРИ ВЫЧИСЛЯЮТСЯ, А НЕ ПРИПИСЫВАЮТСЯ:

    МИР МАЛ         строк в мире меньше девяти — массы взяться неоткуда, и это не порок
                    мира, а его размер. Лечится только ростом мира.
    МИР ШИРОК       строк на род меньше девяти В СРЕДНЕМ: мир по устройству даёт много форм
                    по разу (словарь, определения, диалог). Лечится ПОВТОРЕНИЕМ формы на
                    иных числах и вещах — то есть правкой кузни, а не дописыванием строк.
    ХВОСТ           строк на род девять и больше в среднем, но у части родов масса мала: мир
                    умеет давать массу и даёт её неровно. Лечится выравниванием — тем же
                    числом проходов у всякой формы.

ПУТЬ, ЗАКРЫТЫЙ ЗАМЕРОМ ДО ПРАВКИ (10.09). Разбор родов мира `countfacts` показал, что закон
рода схлопывает числительные НЕПОСЛЕДОВАТЕЛЬНО: «сколько ног у собаки? у собаки четыре ноги» даёт
род «сколько ※ у собаки? у собаки # ※», а «у птицы две ноги» — «у ※ две ※», ибо «две» не
схлопнулось. Причина найдена в пакете языка: `numerals` русского объявляет числительные ТОЛЬКО
мужского рода («один», «два»), а «одна» и «две» в нём нет вовсе — и это настоящая дыра пакета.

Казалось, что её уплата схлопнет тысячи родов. ЗАМЕР ДО ПРАВКИ СКАЗАЛ ИНОЕ: с «одна», «две»,
«одну», «двух», «обе» родов становится 60 430 вместо 60 431 — СХЛОПЫВАЕТСЯ ОДИН. Женские
числительные словом в своде почти не встречаются.

    ЗАМЕР ПРЕЖДЕ ПРАВКИ ДЕШЕВЛЕ ПРАВКИ ПРЕЖДЕ ЗАМЕРА. Дыра пакета названа и остаётся; но
    оплачивать её ради одного рода из шестидесяти тысяч — работа не по цене.

ЧЕГО ПРИБОР НЕ УТВЕРЖДАЕТ: он не зовёт непокупаемый род ЛИШНИМ. Мир определений по природе
своей есть словарь, и требовать девяти показов от всякого определения значило бы требовать
девяти синонимов у каждого слова. Прибор называет ЧИСЛО и ПРИЧИНУ; что с ними делать, решает
тот, кто правит кузню.

РУБЕЖ СТЕРЕЖЁТ НЕ ЧИСЛО, А ДОЛЮ: корпус растёт, и абсолютное число непокупаемых родов растёт
вместе с ним. Доля же говорит, растёт ли корпус ТУДА.

    python3 scripts/mass_census.py            # лист
    python3 scripts/mass_census.py --снимок   # reports/MASS-<дата>.md
"""
# ПУСТОЙ-ОБХОД: no-such-corpus-file
import collections
import datetime
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import form_census  # noqa: E402 — закон рамки и рода живёт там, и берётся оттуда

# РУБЕЖ-ДОЛГА: ДОЛЯ_РУБЕЖ = 80
#
# ДОЛЯ НЕПОКУПАЕМЫХ РОДОВ В ПРОЦЕНТАХ, ВЫШЕ КОТОРОЙ ПРИБОР ПАДАЕТ. Замерено 10.09: 79 %,
# 11.09: 78 %. Рубеж — не цель, а ПОЛ: он опускается всякий раз, как опустился замер, и
# поднимается только с письменным отчётом.
#
# ПЕРВОЕ ПАДЕНИЕ ДОЛИ КУПЛЕНО НЕ РОСТОМ КОРПУСА, А ТОЧНОСТЬЮ МЕРЫ: дома счётных отношений
# стали отдавать переписи свои вещи, цвета и места, и «a bag holds # black ※» перестало быть
# особой рамкой против «a bag holds # ※ ※». Доля 79 → 78 при том же своде.
# РУБЕЖ ПОДНЯТ 79 → 80 С ПИСЬМЕННЫМ ОТЧЁТОМ, КАК ОН САМ И ТРЕБУЕТ (13.09).
#
# ПРИБОР ПРИШЁЛ С ЧУЖОЙ ВЕТВИ ВМЕСТЕ СО СВОИМ РУБЕЖОМ, И РУБЕЖ ЭТОТ НИКОГДА НЕ ОПИСЫВАЛ ЭТО
# ДЕРЕВО. Число 79 замерено 10.09 на своде другой линии работы; сюда прибор посажен 13.09
# первым листом, и с первого же прогона он КРАСЕН — не потому, что дерево ухудшилось, а
# потому, что рубеж говорил о чужом своде.
#
#     РУБЕЖ, ЗАМЕРЕННЫЙ НА ОДНОМ СВОДЕ И ПОСАЖЕННЫЙ В ДРУГОЙ, НЕ ЕСТЬ РУБЕЖ: он не стережёт
#     ухудшения, ибо не отличит его от разницы сводов, — он лишь горит красным всегда.
#
# ЗАМЕР ДО И ПОСЛЕ, ОДНИМ И ТЕМ ЖЕ ПРИБОРОМ, НА ДВУХ СВОДАХ ЭТОЙ ЛИНИИ:
#
#     свод 06.09 (2188137, до всей дневной работы)   61 639 из 71 734 — 85 %
#     свод 13.09 (68987e8, после шести посадок)      54 190 из 67 295 — 80 %
#
# То есть за день доля УПАЛА на пять пунктов, а абсолютное число непокупаемых родов — на
# 7 449, и это при 82 тысячах прибавленных строк. Рубеж 80 записывает ДОСТИГНУТОЕ на этом
# дереве и с этого часа стережёт настоящее ухудшение.
#
#     РУБЕЖ ОБЪЯВЛЕН ПО ДОСТИГНУТОМУ, А НЕ ПО ЖЕЛАЕМОМУ, И НЕ ПО ЧУЖОМУ ДОСТИГНУТОМУ ТОЖЕ.
#
# ЧТО ПРОВЕРЕНО И ОТВЕРГНУТО ПО ДОРОГЕ. Казалось, что доля высока из-за непоследовательности
# закона рода: римская запись не схлопывается, хотя «число, сказанное словом, есть число» —
# и мир `roman` даёт 387 родов на 387 строк. Замер до правки: схлоп римской записи даёт 126
# родов вместо 387, то есть 261 род из 67 295 — доля 80,52 % → 80,45 %.
#
# ЗАМЕР ПРЕЖДЕ ПРАВКИ ДЕШЕВЛЕ ПРАВКИ ПРЕЖДЕ ЗАМЕРА — и второй замер правку ОТМЕНИЛ. Прежде
# чем менять закон рода, я посчитал, сколько раз римский образец встречается ВНЕ мира римской
# записи: 1 281 раз в семи мирах, и это не числа, а «CLI» (642), «CI» (639), «ML», «DI»,
# «DC», «CV», «CD» — сокращения ремесла в мирах v4…v6. Схлоп их в «#» испортил бы роды семи
# миров ради 261 рода одного.
#
#     ЗНАК, ЧИТАЕМЫЙ КАК ЧИСЛО ЛИШЬ ПРИ ОБЪЯВЛЕНИИ, НЕ СХЛОПЫВАЕТСЯ ЗАКОНОМ, ЧИТАЮЩИМ ОДИН
#     СКЕЛЕТ. Римская запись есть число ПО ОБЪЯВЛЕНИЮ СТРАНИЦЫ («римская запись LXI»), а не
#     по виду букв; закон же рода видит скелет, а не объявление.
#
# Оттого мир `roman` остаётся широким по природе, как словарь, и это НЕ ПОРОК: прибор и не
# зовёт непокупаемый род лишним.
ДОЛЯ_РУБЕЖ = 80

МИР_МАЛ, МИР_ШИРОК, ХВОСТ = "МИР МАЛ", "МИР ШИРОК", "ХВОСТ"


def причина(строк, родов):
    """Отчего роды мира непокупаемы — по числу, а не по мнению."""
    if строк < form_census.LAW2:
        return МИР_МАЛ
    return МИР_ШИРОК if строк / max(1, родов) < form_census.LAW2 else ХВОСТ


def main():
    снимок = "--снимок" in sys.argv
    пути = [п for п in form_census.worlds(kind="shows") if п.is_file()]
    if not пути:
        print("МАССА РОДА ОТКАЗ: обход пуст, мерить нечего")
        return 2
    миры = form_census.перепись(пути)
    LAW2 = form_census.LAW2

    масса = collections.Counter()
    свои = collections.defaultdict(collections.Counter)
    for имя, скелеты in миры:
        for с in скелеты:
            р = form_census.род(с)
            масса[р] += 1
            свои[имя][р] += 1

    мало = {р for р, n in масса.items() if n < LAW2}
    доля = 100 * len(мало) // max(1, len(масса))
    строки = [f"# МАССА РОДА {datetime.date.today().isoformat()}", "",
              f"Закон массы: род, встреченный меньше {LAW2} раз, организмом не покупается.",
              f"Родов всего {len(масса)}, непокупаемых {len(мало)} ({доля} %); "
              f"строк под ними {sum(масса[р] for р in мало)}.", ""]

    ряд = []
    for имя, счёт in свои.items():
        строк = sum(счёт.values())
        родов = len(счёт)
        свои_мало = sum(1 for р in счёт if р in мало)
        ряд.append((свои_мало, имя, строк, родов, причина(строк, родов)))
    ряд.sort(reverse=True)

    по_причине = collections.Counter(п for _, _, _, _, п in ряд)
    строки.append("## Миры по числу непокупаемых родов")
    строки.append("")
    for свои_мало, имя, строк, родов, поч in ряд[:40]:
        строки.append(f"  {имя:<24} {свои_мало:>6} из {родов:>6} родов, строк {строк:>7} "
                      f"({строк / max(1, родов):>5.1f} на род)  {поч}")
    строки.append("")
    строки.append("## Миры по причине")
    строки.append("")
    for поч in (МИР_МАЛ, МИР_ШИРОК, ХВОСТ):
        свои_миры = [имя for _, имя, _, _, п in ряд if п == поч]
        строки.append(f"  {поч:<12} {по_причине[поч]:>4} миров: "
                      f"{', '.join(свои_миры[:12])}{' …' if len(свои_миры) > 12 else ''}")

    if снимок:
        путь = КОРЕНЬ / "reports" / f"MASS-{datetime.date.today().isoformat()}.md"
        путь.write_text("\n".join(строки) + "\n", encoding="utf-8")
        print(f"снимок: {путь.relative_to(КОРЕНЬ)}")
    else:
        for с in строки:
            print(с)

    поза = "PASS" if доля <= ДОЛЯ_РУБЕЖ else "FAIL"
    print(f"МАССА РОДА {поза}: непокупаемых родов {len(мало)} из {len(масса)} "
          f"({доля} %, рубеж {ДОЛЯ_РУБЕЖ} %); строк под ними "
          f"{sum(масса[р] for р in мало)} из {sum(масса.values())}; "
          f"миров широких {по_причине[МИР_ШИРОК]}, с хвостом {по_причине[ХВОСТ]}, "
          f"малых {по_причине[МИР_МАЛ]}")
    return 0 if доля <= ДОЛЯ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
