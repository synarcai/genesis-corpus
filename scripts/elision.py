#!/usr/bin/env python3
"""[ЭЛИЗИЯ] — французское служебное слово перед гласной: сократилось ли оно.

    СЛУЖЕБНОЕ СЛОВО, СТОЯЩЕЕ В РАМКЕ ЦЕЛЫМ, НЕ СЛЫШИТ ТОГО, ЧТО ЗА НИМ ПОДСТАВЯТ.

ЧЕТВЁРТЫЙ ЛИК ТОЙ ЖЕ БОЛЕЗНИ, ЧТО СВЯЗКА, ПРИЧАСТИЕ И АРТИКЛЬ (08.09). Рамка держит «je»,
«de», «que» целыми — иначе она не покрыла бы согласных, — и сокращение приходится делать
ПОСЛЕ подстановки. Дома этого не делали, и 496 строк одиннадцати миров стояли без элизии:

    «combien de abdos a fait Hugo ?»        → d'abdos
    «est-ce que une souris peut être… ?»     → qu'une souris
    «je ouvre. qui ouvre ? je ouvre.»        → j'ouvre

ЭТО НЕ ОТТЕНОК РЕЧИ, А ЕЁ ЗАКОН: «je ouvre» по-французски есть ошибка, а не вариант.

ПРИЗНАК БЕРЁТСЯ У ДОМА ЯЗЫКА (`frgram.ПАРЫ`, `ГЛАСНЫЕ`, `НЕМОЕ_H`), а не пишется здесь.
«h» бывает придыхательным («le héros»), и слова с НЕМЫМ «h» названы поимённо.

ГРАНИЦА ОБЪЯВЛЕНА И КУПЛЕНА ДВУМЯ ОШИБКАМИ МЕРЫ:

  · СУДИТСЯ ЛИШЬ ФРАНЦУЗСКАЯ СТРОКА. Нидерландское «de» и португальское «que» не элидируют,
    и мера, не спросившая о языке, дала 8605 обвинений при 496 честных.
  · ИНВЕРСИЯ ЭЛИЗИИ НЕ ТРЕБУЕТ: «avais-je au début ?» верно, и дефис перед «je» её отменяет.
    Мера, забывшая дефис, дала 1214.

        МЕРА, НЕ СПРАШИВАЮЩАЯ О ЯЗЫКЕ СТРОКИ, СУДИТ ЧУЖУЮ РЕЧЬ СВОИМ ЗАКОНОМ.

ЯЗЫК УЗНАЁТСЯ ПО СВОИМ СЛУЖЕБНЫМ СЛОВАМ, А НЕ ПО ЗНАКУ: признак требует ДВУХ французских
служебных слов в строке. Он строг и оттого ЗАНИЖАЕТ долг — число его есть ПОЛ, а не потолок.

    python3 scripts/elision.py [--подробно] [--папка datasets]
"""
# ПУСТОЙ-ОБХОД: --папка no-such-dir
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import frgram  # noqa: E402 — дом французской грамматики, объявивший элизию

# РУБЕЖ-ДОЛГА: БЕЗ_ЭЛИЗИИ_РУБЕЖ = 37
#
# ЧИСЛО ОБЪЯВЛЕНО ПОСЛЕ ЗАМЕРА И ПОСЛЕ ПОЧИНКИ ШЕСТИ ДОМОВ: 496 → 65. Движок пакетов получил
# элизию правилом-данными, дом французской грамматики — законом, пять домов — вызовом закона
# над готовой строкой и обеими формами в образце.
#
# ЧИСЛО ЭТОГО ПРИБОРА БОЛЬШЕ ЧИСЛА ПРОБЫ, И ЭТО НЕ РОСТ ДОЛГА, А ПОЛНОТА ПРИЗНАКА. Проба,
# нашедшая 496, знала четыре пары из одиннадцати и не знала ни «œ», ни немого «h», ни имён:
#
#     «de œufs» → d'œufs      «de histoires» → d'histoires      «que anne» → qu'anne
#     «de yeux» → d'yeux      «de heures» → d'heures            «que œuf» → qu'œuf
#
# Прибор берёт признак у ДОМА ЯЗЫКА целиком и потому видит их все.
#
# 176 → 39 В ТОТ ЖЕ ЧАС, И ХОД НАЙДЕН ОДИН НА ВСЕ ДОМА, СОБИРАЮЩИЕ СТРАНИЦУ ВО МНОГИХ МЕСТАХ:
#
#     ЗАКОН, КАСАЮЩИЙСЯ ВСЯКОЙ СТРАНИЦЫ, ЗОВЁТСЯ ТАМ, ГДЕ ВСЯКАЯ СТРАНИЦА ПРОХОДИТ, — а
#     проходит она через НАБОР ПОКАЗОВ, и суд дома судит принадлежностью к нему. Оттого
#     страница и суд остаются в согласии сами собою, и звать закон при каждом `format` не надо.
#
# Так взяты дома связок, поведения и тем; дома с образцами (держание, сцена, единицы времени)
# получили обе половины — закон над готовой страницей и обе формы в образце.
#
# ОСТАТОК НАЗВАН ПОИМЁННО И ЖДЁТ РУКИ: 39 строк в шести мирах (scale, holes, svamp, lang_fr,
# nature, worldfacts). Долг записан здесь, а не спрятан.
# 39 → 37 (09.09): ДОМ ПРИРОДЫ ПОЛУЧИЛ ЗАКОН ЭЛИЗИИ ПОВЕРХ ГОТОВОЙ СТРАНИЦЫ, А НЕ ПРАВКУ РАМКИ.
# Рамка пишет «combien de {ва}», и при имени на гласную выходило «combien de ailes» — три
# такие строки жили в мире. Рамку правкой не вылечить: имя приходит ДЫРОЙ, и гласная в нём то
# есть, то нет. Закон объявлен домом французской грамматики (`frgram.элизия`) и стои́т ПОВЕРХ
# собранной строки — там, где гласная уже видна.
БЕЗ_ЭЛИЗИИ_РУБЕЖ = 37

# ФРАНЦУЗСКОЕ СЛУЖЕБНОЕ СЛОВО — признак языка строки; двух довольно, одного нет.
_ФРАНЦУЗСКИЕ = ("combien", "est-ce", "il y a", "elle", "dans", "pourquoi", "parce", "sur",
                "avec", "une", "des", "les", "fait", "sont", "qui", "quoi", "cette")
ФР = re.compile(r"\b(?:" + "|".join(re.escape(с) for с in _ФРАНЦУЗСКИЕ) + r")\b")


def обвинения(строка):
    """[(целое, сокращённое, слово)] — служебные слова строки, не сократившиеся перед гласной."""
    вон = []
    for целое, сокращённое in frgram.ПАРЫ.items():
        образец = re.compile(r"(?<![-\w'’])" + re.escape(целое) + r" (?=([a-zà-ÿœæ]+))")
        for м in образец.finditer(строка.lower()):
            if frgram._сократить(целое, м.group(1)):
                вон.append((целое, сокращённое, м.group(1)))
    return вон


def французская(строка):
    return len(ФР.findall(строка.lower())) >= 2


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--папка", default="datasets")
    дов = ап.parse_args()
    корень = КОРЕНЬ / дов.папка
    миры = sorted(корень.glob("genesis_*.txt")) if корень.is_dir() else []
    if not миры:
        print(f"ЭЛИЗИЯ ОТКАЗ: миров в «{дов.папка}» нет")
        return 2

    плохо, по_мирам, прим, всего = 0, collections.Counter(), {}, 0
    for мир in миры:
        for строка in мир.read_text(encoding="utf-8", errors="replace").splitlines():
            if not французская(строка):
                continue
            всего += 1
            for целое, сокращённое, слово in обвинения(строка):
                плохо += 1
                по_мирам[мир.name[8:-4]] += 1
                прим.setdefault((мир.name[8:-4], целое), (строка[:88], сокращённое, слово))
    print(f"СТРАНИЦЫ: миров {len(миры)}, французских строк {всего}, БЕЗ ЭЛИЗИИ {плохо}")
    for мир, n in по_мирам.most_common(12 if not дов.подробно else len(по_мирам)):
        print(f"  {мир:<18} {n:>4}")
    if дов.подробно:
        for (мир, целое), (строка, кратко, слово) in sorted(прим.items()):
            print(f"  {мир} «{целое} {слово}» → «{кратко}{слово}»\n       {строка}")

    поза = "PASS" if плохо <= БЕЗ_ЭЛИЗИИ_РУБЕЖ else "FAIL"
    print(f"ЭЛИЗИЯ {поза}: строк без элизии {плохо} (рубеж {БЕЗ_ЭЛИЗИИ_РУБЕЖ}); "
          f"миров с долгом {len(по_мирам)}; пар объявлено {len(frgram.ПАРЫ)}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
