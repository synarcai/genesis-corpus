# показала, что законом стерегут тридцатью шестью домами больше. Стражей 100 → 135, молчащих
# 48 → 15.
#
#     ЧЕТВЁРТАЯ РЕДАКЦИЯ ЧИСЛА, И ВСЕ ЧЕТЫРЕ НАЗВАНЫ: 135 (первая порча из первых десяти
#     слов), 110 (до десяти попыток), 99 (порча равномерно по странице), 63 (порча числом).
#     ЧИСЛО, УБАВЛЯВШЕЕСЯ ЧЕТЫРЕЖДЫ ОТ УТОЧНЕНИЯ МЕРЫ, ГОВОРИТ О МЕРЕ БОЛЬШЕ, ЧЕМ О ДОМАХ.
#
#     СУД, ЧЕЙ ЗАКРЫТЫЙ НАБОР ЛОВИТ ВСЯКУЮ ПОРЧУ РАНЬШЕ СОДЕРЖАТЕЛЬНОЙ ПРОВЕРКИ, ИМЕЕТ ЭТУ
#     ПРОВЕРКУ ЛИШЬ НА ВИД — покуда её не спросят о странице, КОТОРАЯ В НАБОРЕ ЕСТЬ.
