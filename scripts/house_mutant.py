# Здесь она и спрашивается: порча ВПИСЫВАЕТСЯ в набор на время опыта. Дом, назвавший её
# истиной, стережёт себя НАБОРОМ, а не ЗАКОНОМ, — и если закон его ошибочен, никто не
# узнает. Это долг, а не поломка: закон работает, но не проверяется.
#
# ВТОРОЕ ПРИСВОЕНИЕ РУБЕЖА СНЯТО 16.09, И ОНО СТОИ́ЛО ДОРОЖЕ, ЧЕМ КАЗАЛОСЬ. Рубеж этот был
# уплачен 13.09 с 63 до 55 — тринадцать домов получили закон скелета, — и уплата записана
