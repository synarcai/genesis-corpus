ПОПЫТОК = 10


def _порченые(показ, показы=(), попыток=ПОПЫТОК, дом=None):
    """До `попыток` порч страницы, каждая — подмена РОВНО ОДНОГО слова другим из той же страницы.

    ПОРЧА СОХРАНЯЕТ ЧИСЛО СЛОВ: признак порчи у домов считает расхождение ПОСЛОВНО, и подмена,
    меняющая длину, уходит мимо него — проба, на ней стоящая, доказывает лишь то, что признак
    её не берёт.

    ПОРЧА, ПОПАВШАЯ В НАБОР ПОКАЗОВ, НЕ ЕСТЬ ПОРЧА (12.09, ночь, поймано на живом деле). Дом
    SVAMP был объявлен слепым за то, что назвал истиной строку «Ann had 12 coins. Ann gave
    some of them away…» — а она СТОИ́Т в его показах: дом пишет и «she gave», и «Ann gave».
    Подмена слова другим словом ТОЙ ЖЕ страницы иногда даёт ДРУГУЮ ЧЕСТНУЮ страницу.

        ПОРЧА, ДАЮЩАЯ ЧЕСТНУЮ СТРАНИЦУ, НЕ ЕСТЬ ПОРЧА, И СУД, НАЗВАВШИЙ ЕЁ ИСТИНОЙ, ПРАВ.

    Оттого порча сверяется с набором показов и отбрасывается, если в него попала.
    """
    слова = показ.split(" ")
    вон = []
    # МЕСТА ПОРЧИ БЕРУТСЯ РАВНОМЕРНО ПО СТРАНИЦЕ, А НЕ ПОДРЯД С НАЧАЛА (12.09, день).
    #
    # Прежде порча ставилась в первые десять слов, и для длинной страницы предмет её закона
    # — глагол, метка смысла, звёздочка — лежал ДАЛЬШЕ и не задевался ни разу. Дом двух
    # «быть», у которого содержательный закон заведомо зряч (проверено ложными страницами в
    # его собственной пробе), объявлялся стерегущим лишь набором.
    #
    #     ПОРЧА, СТАВИМАЯ ВСЕГДА В НАЧАЛО, МЕРИТ НАЧАЛО СТРАНИЦЫ, А НЕ СТРАНИЦУ.
    # СВОБОДНОЕ МЕСТО СВОБОДНО ОТ ВСЯКОЙ ПОРЧИ, А НЕ ОТ ЧИСЛОВОЙ ТОЛЬКО (16.09). Подмена
    # СЛОВА «40» на слово «3» есть та же подсадка в свободное место, что и подмена числа:
    # прибор делит страницу по пробелам, и число для него — слово. Первая редакция закона
    # берегла лишь `_порча_числа`, и дом смешанных мер остался слепым при живом объявлении.
    свободные = _свободные(дом, показ) if дом is not None else []
    начала, поз = [], 0
    for сл in слова:
        начала.append(поз)
        поз += len(сл) + 1
    свободно = {i for i, н in enumerate(начала)
                if any(a <= н < b for a, b in свободные)}
    шаг = max(1, len(слова) // попыток)
    for i in range(0, len(слова), шаг):
        if i in свободно:
            continue
        сл = слова[i]
        for j, чужое in enumerate(слова):
            if i == j or j in свободно or чужое == сл or not чужое.strip():
                continue
            новая = " ".join(слова[:i] + [чужое] + слова[i + 1:])
            if новая not in показы:
                вон.append(новая)
            break
        if len(вон) >= попыток:
            break
    вон.extend(_порча_цитаты(показ, показы, попыток))
    вон.extend(_порча_числа(показ, показы, попыток, дом))
    return вон


# МЕРА, ПОРТЯЩАЯ ЛИШЬ СЛОВА, НЕ СПРАШИВАЕТ ЗАКОНА У ДОМА, ЧЕЙ ЗАКОН О ЧИСЛАХ (13.09).
#
# Два прежних рода порчи меняли СЛОВО и ЗНАК ВНУТРИ ЁЛОЧЕК. Дому, чей содержательный закон
# пересчитывает («сумма долей», «цена со скидкой», «во сколько раз растёт площадь»), ни то
# ни другое предмета закона не задевало: он честно молчал, и мера писала молчание в вину.
#
# Опыт 13.09 по 150 домам с судом и показами: третий род порчи — подмена ОДНОГО ЧИСЛА
# страницы ДРУГИМ ЧИСЛОМ ТОЙ ЖЕ страницы — показал, что законом стерегут ТРИДЦАТЬ ШЕСТЬЮ
# домами больше, чем считалось: доли, скидки, рычаг, чётность, степени, точность меры,
# масштаб карты, числовой ряд, деление на ноль.
#
#     ДОМ, ЧЕЙ ЗАКОН О ЧИСЛАХ, ОТВЕЧАЕТ ЛИШЬ НА ВОПРОС О ЧИСЛАХ. Мера, не задавшая его,
#     измерила СВОЙ СЛОВАРЬ ПОРЧИ, а не зоркость домов.
#
# Порча берёт число ИЗ ТОЙ ЖЕ СТРАНИЦЫ, а не любое: чужое число сделало бы строку
# невозможной по виду, и её отверг бы признак, а не закон.
# ЧЕТВЁРТЫЙ РОД ПРОБОВАН И ОТВЕРГНУТ, И ЭТО ЗАПИСАНО, ЧТОБЫ НЕ ПРОБОВАЛИ ВНОВЬ (13.09).
# Перестановка двух соседних слов ВНУТРИ ёлочек — казалось бы, прямой вопрос к законам о
# ПОРЯДКЕ, — не добавила НИ ОДНОГО дома: 87 законом и с нею, и без неё.
#
#     РОД ПОРЧИ, НЕ ДОБАВИВШИЙ НИ ОДНОГО ДОМА, ЕСТЬ УКРАШЕНИЕ МЕРЫ: он удлиняет прогон и не
#     меняет вердикта. Отрицательный опыт назван здесь, ибо иначе его повторят.
ЧИСЛО_В_СТРОКЕ = re.compile(r"\d+")


def _свободные(дом, показ):
    """Промежутки, где число НЕ НЕСЁТ ИСТИНЫ ПО ЗАКОНУ ДОМА — объявлены самим домом.

    ПОДСАДКА В СВОБОДНОЕ МЕСТО НИЧЕГО НЕ ДОКАЗЫВАЕТ (16.09, тот же закон, что у соседа
    `court_mutants`, и та же причина). Дом смешанных мер говорит «3 мм и 40 г. сколько
    всего? ничего: мм мерит длину, г мерит массу, и сложить их нечем» — и числа тут не
    несут НИЧЕГО: несложимость длины с массой верна при всяких числах. Прибор, подменивший
    40 на 3, получил ДРУГУЮ ЧЕСТНУЮ страницу и записал дому слепоту.

        МЕСТО, ГДЕ ЗАКОН ДОМА ЧИСЛА НЕ ЧИТАЕТ, ЕСТЬ СВОБОДНОЕ МЕСТО, И ПОРЧА В НЁМ МЕРИТ
        ПРИБОР, А НЕ ДОМ.

    Объявляет его САМ ДОМ (`СВОБОДНОЕ_ЧИСЛО`), ибо знание о том, где закон не смотрит на
    число, есть знание закона и живёт при нём. Умолчание значит «свободных мест нет».
    """
    места = []
    for правило in getattr(дом, "СВОБОДНОЕ_ЧИСЛО", ()):
        for м in правило.finditer(показ):
            места.append(м.span(1) if м.groups() else м.span())
    return места


def _порча_числа(показ, показы=(), попыток=ПОПЫТОК, дом=None):
    """Порчи, меняющие ОДНО число страницы на другое число ТОЙ ЖЕ страницы."""
    свободные = _свободные(дом, показ) if дом is not None else []
    места = [(m.start(), m.group()) for m in ЧИСЛО_В_СТРОКЕ.finditer(показ)
             if not any(н <= m.start() < к for н, к in свободные)]
    алфавит = sorted({ч for _i, ч in места})
    if len(алфавит) < 2:
        return []
    вон = []
    for i, ч in места:
        чужое = next((x for x in алфавит if x != ч), None)
        if чужое is None:
            continue
        новая = показ[:i] + чужое + показ[i + len(ч):]
        if новая != показ and новая not in показы:
            вон.append(новая)
        if len(вон) >= попыток:
            break
    return вон


# ПОРЧА ПО СЛОВАМ НЕ ТРОГАЕТ ПРЕДМЕТА ЗАКОНА ТАМ, ГДЕ ПИСЬМО НЕ СТАВИТ ПРОБЕЛОВ (13.09).
#
# Дома китайского, японского и корейского счётного стоя́ли в «стерегущих набором», и не потому,
# что их закон слеп: подмена РУССКОГО слова другим русским словом оставляла цитату «一本书»
# нетронутой, а закон дома читает ровно цитату. Мера спрашивала закон о том, чего он не судит,
# и записывала молчание в вину.
#
#     МЕРА, ПОРТЯЩАЯ ЛИШЬ ТО, ЧТО РАЗДЕЛЕНО ПРОБЕЛОМ, НЕ ТРОГАЕТ ПРЕДМЕТА ЗАКОНА В ДОМАХ,
#     ЧЬЁ ПИСЬМО ПРОБЕЛОВ НЕ СТАВИТ, — и обвиняет их в слепоте своего же признака.
#
# Второй род порчи потому таков: ОДИН ЗНАК ВНУТРИ ЁЛОЧЕК заменяется другим знаком из ёлочек
# ЭТОЙ ЖЕ страницы. Число слов сохраняется (признак домов считает пословно), предмет закона
# задевается, и порча остаётся речью того же языка — а не мусором, отвергаемым по виду.
ЁЛОЧКИ = re.compile(r"«([^»]+)»")


def _порча_цитаты(показ, показы=(), попыток=ПОПЫТОК):
    """Порчи, меняющие ОДИН ЗНАК ВНУТРИ ёлочек на другой знак из ёлочек той же страницы."""
    места = [(m.start(1), m.group(1)) for m in ЁЛОЧКИ.finditer(показ)]
    алфавит = sorted({з for _, тело in места for з in тело.lstrip("*") if not з.isspace()})
    if len(алфавит) < 2:
        return []
    вон = []
    for начало, тело in места:
        голое = тело.lstrip("*")
        for сдвиг, знак in enumerate(голое):
            чужой = next((з for з in алфавит if з != знак), None)
            if чужой is None:
                continue
            i = начало + (len(тело) - len(голое)) + сдвиг
            новая = показ[:i] + чужой + показ[i + 1:]
            if новая != показ and новая not in показы:
                вон.append(новая)
            break
        if len(вон) >= попыток:
            break
    return вон


def дома(двор):
    """Дома с судом и набором показов — только они и подсудны этому прибору."""
    вон = []
    for путь in sorted(двор.glob("*.py")):
        if путь.name.startswith("gen_genesis_"):
            continue
        try:
            дом = importlib.import_module(путь.stem)
        except Exception:                                  # noqa: BLE001 — чужая беда не наша
            continue
        показы = getattr(дом, "ПОКАЗЫ", None)
        судить = getattr(дом, "судить", None)
        if callable(судить) and isinstance(показы, dict) and показы:
            вон.append((путь.stem, дом, показы, судить))
    return вон


def исходы(набор, подробно=False):
    """(стражи, молчащие, слепые) — ТРИ исхода порчи, а не два.

    ТРИ ИСХОДА, И СМЕШИВАТЬ ИХ НЕЛЬЗЯ (12.09, ночь, куплено собственным неверным приговором):

      · ЛОЖЬ   — суд назвал порчу ложью: он СТЕРЕЖЁТ свою страницу сам;
      · НЕ МОЁ — суд промолчал: порча становится НЕМОЙ строкой, и ловят её ВОРОТА, ибо они
                 отказываются писать мир, где строка не судима никем;
      · ИСТИНА — суд назвал порчу ИСТИНОЙ: вот это и есть слепота, и она одна есть долг.

        СУД, ОТВЕЧАЮЩИЙ НА ПОРЧУ «НЕ МОЁ», НЕ ЛЖЁТ — НО И НЕ ЗАЩИЩАЕТ: разница видна лишь для
        порчи, внесённой ПОСЛЕ ковки, которую ворота уже не перечитают.

    Первая редакция звала слепыми всех, кто не сказал «ложь», — и насчитала сорок девять там,
    где слепых НОЛЬ.
    """
    стражи, молчащие, слепые, без_закона = [], [], [], []
    for имя, дом_, показы, судить in набор:
        исход, законом = None, False
        for показ in list(показы)[:3]:
            for порча in _порченые(показ, показы, дом=дом_):
                try:
                    если, верно = судить(порча)[:2]
                except Exception:                          # noqa: BLE001
                    continue
                if если and not верно:
                    исход = "ложь"
                elif если and верно:
                    исход = "истина"
                # ВТОРОЙ ВОПРОС О ТОЙ ЖЕ ПОРЧЕ: а если она В НАБОРЕ? Закрытый набор тогда
                # молчит, и отвечает один лишь содержательный закон дома.
                #
                # ТРЕБУЕТСЯ ХОТЬ ОДНА ПОЙМАННАЯ, А НЕ ПЕРВАЯ ЖЕ, И ЭТО ТА ЖЕ МЕРА МИЛОСЕРДИЯ,
                # ЧТО У ПЕРВОГО ЧИСЛА: подмена слова может не задеть предмета закона вовсе
                # («ПРИЛАГАТЕЛЬНОЕ» вместо «ПРИЛАГАТЕЛЬНОЕ» в пояснении), и судить по ней
                # значило бы звать слепым зрячего. Первая редакция брала первую порчу и
                # нашла одного стерегущего законом там, где их больше.
                if not законом and isinstance(показы, dict) and порча not in показы:
                    показы[порча] = показы[показ]
                    try:
                        е2, в2 = судить(порча)[:2]
                        законом = bool(е2 and not в2)
                    except Exception:                      # noqa: BLE001
                        pass
                    finally:
                        показы.pop(порча, None)
                if исход == "ложь" and законом:
                    break
            if исход == "ложь" and законом:
                break
        (стражи if исход == "ложь" else слепые if исход == "истина" else молчащие).append(имя)
        if not законом:
            без_закона.append(имя)
        if подробно and исход == "истина":
            print(f"  СЛЕП {имя}: порчу своей страницы назвал ИСТИНОЙ")
        if подробно and not законом:
            print(f"  БЕЗ ЗАКОНА {имя}: порчу, ВПИСАННУЮ В НАБОР, назвал истиной")
    return стражи, молчащие, слепые, без_закона


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ПОРЧА СТРОИТСЯ и что слепота ВИДНА.

        ПРИБОР, НЕ УМЕЮЩИЙ ПОСТРОИТЬ ПОРЧУ, НАЗОВЁТ СЛЕПЫМИ ВСЕХ И БУДЕТ КРАСЕН ЗРЯ; прибор,
        строящий порчу, неотличимую от честной страницы, назовёт зрячими всех и будет зелен зря.
    """
    беды = []
    показ = "у Ани 3 книги и 5 ручек."
    порчи = _порченые(показ, {показ})
    if not порчи:
        беды.append("порча не построена вовсе")
    for п in порчи:
        if len(п.split(" ")) != len(показ.split(" ")):
            беды.append(f"порча сменила число слов: {п}")
        if п == показ:
            беды.append("порча совпала с честной страницей")
    зрячий = {показ: ("ru", "проба")}
    видит = lambda с: (True, True) if с == показ else (True, False)
    слепой = lambda с: (True, True)
    if исходы([("зрячий", None, зрячий, видит)])[0] != ["зрячий"]:
        беды.append("страж не назван стражем")
    если_слеп = исходы([("слепой", None, зрячий, слепой)])
    if если_слеп[2] != ["слепой"]:
        беды.append("слепой не назван слепым")
    немой = lambda с: (False, False)
    if исходы([("немой", None, зрячий, немой)])[1] != ["немой"]:
        беды.append("молчащий не назван молчащим")
    # ЧЕТВЁРТОЕ ЧИСЛО ПРОБУЕТСЯ ДВУМЯ СУДАМИ, НЕОТЛИЧИМЫМИ ПО ПЕРВОМУ: оба зовут порчу
    # ложью, но один — оттого, что её нет в наборе, другой — оттого, что видит саму порчу.
    # СЛОВАРЬ ЗДЕСЬ ТОТ ЖЕ, ЧТО ОТДАН ПРИБОРУ, А НЕ ЕГО КОПИЯ, И ЭТО СУЩЕСТВЕННО:
    # прибор вписывает порчу в ОТДАННЫЙ ему набор, и суд, глядящий в копию, порчи там не
    # найдёт — проба тогда назвала бы стерегущего набором стерегущим законом. Поймано
    # самой этой пробой в час её написания.
    набором = lambda с: (True, True) if с in зрячий else (True, False)
    если_набором = исходы([("набором", None, зрячий, набором)])
    if если_набором[0] != ["набором"]:
        беды.append("стерегущий набором не назван стражем по первому числу")
    if если_набором[3] != ["набором"]:
        беды.append("СТЕРЕГУЩИЙ НАБОРОМ НЕ НАЗВАН: четвёртое число слепо к тому, "
                    "ради чего заведено")
    если_законом = исходы([("законом", None, зрячий, видит)])
    if если_законом[3]:
        беды.append("стерегущий законом сочтён стерегущим набором")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"СУД ДОМА ЛОВИТ ПОРЧУ ОТКАЗ: построение порчи не доказано ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--двор", default=None)
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--рубеж", type=int, default=СЛЕПЫХ_РУБЕЖ)
    дов = ап.parse_args()
    двор = pathlib.Path(дов.двор) if дов.двор else КОРЕНЬ / "tools"
    if not двор.is_dir():
        print(f"СУД ДОМА ЛОВИТ ПОРЧУ ОТКАЗ: двора нет — {двор}")
        return 2
    набор = дома(двор)
    if not набор:
        print(f"СУД ДОМА ЛОВИТ ПОРЧУ ОТКАЗ: домов с судом и показами в «{двор}» нет")
        return 2
    стражи, молчащие, слепцы, без_закона = исходы(набор, дов.подробно)
    плохо = len(слепцы) > дов.рубеж or len(без_закона) > БЕЗ_ЗАКОНА_РУБЕЖ
    итог = "FAIL" if плохо else "PASS"
    print(f"СУД ДОМА ЛОВИТ ПОРЧУ {итог}: СЛЕПЫХ домов {len(слепцы)} (рубеж {дов.рубеж}) "
          f"из {len(набор)} с судом и показами; стражей {len(стражи)}, молчащих "
          f"{len(молчащие)} (их порчу ловят ВОРОТА, а не суд); СТЕРЕГУТ НАБОРОМ, А НЕ "
          f"ЗАКОНОМ {len(без_закона)} (рубеж {БЕЗ_ЗАКОНА_РУБЕЖ}) — их содержательная "
          f"проверка не спрашивается ни разу"
          + (f"; слепые: {', '.join(слепцы[:6])}" if слепцы else ""))
    return 0 if итог == "PASS" else 1


