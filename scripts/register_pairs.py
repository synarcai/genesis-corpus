#!/usr/bin/env python3
"""[ПАРА РЕГИСТРА] — различаются ли неформальный и вежливый показы ТОЛЬКО обращением.

Условие названо holon 04.09, и оно есть условие ПОКУПКИ, а не вкуса: его рынок
покупает закон анти-унификацией над парой — общее уходит в рамку, различие
становится дырой. Если вежливая строка отличается от неформальной ещё чем-нибудь
(иным числом, иным именем, иным предметом), рынок вынесет в дыру и это, и закон
будет куплен ШИРЕ, чем дом хотел: он выйдет верным на показанном и солжёт на
следующем. Цена ошибки — не строка, а закон.

ПРИБОР НЕ ВЕРИТ ОБЪЯВЛЕНИЮ ДОМА, И В ЭТОМ ВЕСЬ ЕГО СМЫСЛ. Дома объявляют регистр
по-разному: один словарём замен, три — вежливой рамкой, писанной отдельно. Дом,
писавший вторую рамку рукой, и есть тот, где различие могло уехать дальше
обращения, — а его собственное объявление об этом не скажет. Потому пара ищется
СЛИЧЕНИЕМ: ближайший неформальный показ той же формы и того же языка. Так прибор
делает ровно то, что сделает рынок, и меряет то, что рынок увидит.

ВЕРДИКТ ПО КАЖДОЙ ПАРЕ — ЧИСЛО ДЫР И ИХ СОДЕРЖИМОЕ:
  · одна дыра — чистый корм: закон регистра купится ровно как регистр;
  · две и более — не порок сам по себе: польский меняет лицо подлежащего И
    глагол, немецкий — местоимение И глагол; узел один, блоков текста два;
  · дыра С ЧИСЛОМ ИЛИ ИМЕНЕМ — ПОРОК ВСЕГДА: обращение не меняет ни числа, ни
    лица, о котором речь, и пара, где оно изменилось, учит рынок неправде.

    python3 scripts/register_pairs.py [--дом dialogueforms] [--подробно]
"""
import argparse
import difflib
import importlib
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

_ЦИФРА = re.compile(r"\d")


def дома_с_регистром():
    """Дома, чьи показы несут форму на «_вы» — найдены делом, а не списком."""
    вон = []
    # ПО ВСЕМ ДОМАМ, А НЕ ПО ИМЕНИ: «worldfacts» не зовётся *forms*, и прибор,
    # искавший по имени, прошёл бы мимо дома, где регистр как раз и начинался.
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        имя = путь.stem
        try:
            дом = importlib.import_module(имя)
        except Exception:
            continue
        показы = getattr(дом, "ПОКАЗЫ", None)
        if not isinstance(показы, dict):
            continue
        if any(str(ф).endswith("_вы") for _, ф in показы.values()):
            вон.append((имя, дом))
    return вон


def дыры(a, b):
    """Блоки, которыми две строки различаются: [(из, в), …] по словам."""
    сa, сb = a.split(), b.split()
    вон = []
    for тег, i1, i2, j1, j2 in difflib.SequenceMatcher(None, сa, сb).get_opcodes():
        if тег != "equal":
            вон.append((" ".join(сa[i1:i2]), " ".join(сb[j1:j2])))
    return вон


def имена_дома(дом):
    """Имена лиц, объявленные домом, — их подмена в дыре есть порок."""
    вон = set()
    for имя in ("ИМЕНА", "ИМЕНА_Ж", "ЛИЦА"):
        значение = getattr(дом, имя, None)
        if isinstance(значение, dict):
            for с in значение.values():
                вон.update(с if isinstance(с, (list, tuple)) else [])
        elif isinstance(значение, (list, tuple)):
            вон.update(значение)
    языки = getattr(дом, "ЯЗЫКИ", None)
    if isinstance(языки, dict):
        for я in языки.values():
            if isinstance(я, dict) and isinstance(я.get("имена"), (list, tuple)):
                вон.update(я["имена"])
    return {str(и).lower() for и in вон}


def разобрать(имя, дом, подробно):
    показы = дом.ПОКАЗЫ
    свои = {}
    for с, (язык, форма) in показы.items():
        свои.setdefault((язык, str(форма)), []).append(с)
    имена = имена_дома(дом)
    итог = {"пар": 0, "дыр1": 0, "дырN": 0, "порок": [], "без пары": 0}
    for (язык, форма), строки in sorted(свои.items()):
        if not форма.endswith("_вы"):
            continue
        неформальные = свои.get((язык, форма[:-3]), [])
        if not неформальные:
            итог["без пары"] += len(строки)
            continue
        for вежливая in строки:
            близкие = difflib.get_close_matches(вежливая, неформальные, n=1, cutoff=0.0)
            if not близкие:
                итог["без пары"] += 1
                continue
            д = дыры(близкие[0], вежливая)
            итог["пар"] += 1
            итог["дыр1" if len(д) == 1 else "дырN"] += 1
            for из, в in д:
                слова = set((из + " " + в).lower().split())
                if _ЦИФРА.search(из + в) or (слова & имена):
                    итог["порок"].append((язык, форма, близкие[0], вежливая, из, в))
            if подробно and len(д) > 1:
                print(f"    {язык} {форма}: {д}")
    return итог


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--дом")
    ап.add_argument("--подробно", action="store_true")
    а = ап.parse_args()
    дома = [(и, д) for и, д in дома_с_регистром() if not а.дом or и == а.дом]
    если_нет = 0
    print(f"{'дом':<18}{'пар':>6}{'одна дыра':>11}{'дыр больше':>12}{'ПОРОК':>7}{'без пары':>10}")
    всего = {"пар": 0, "дыр1": 0, "дырN": 0, "порок": 0, "без пары": 0}
    пороки = []
    for имя, дом in дома:
        и = разобрать(имя, дом, а.подробно)
        print(f"{имя:<18}{и['пар']:>6}{и['дыр1']:>11}{и['дырN']:>12}"
              f"{len(и['порок']):>7}{и['без пары']:>10}")
        for к in ("пар", "дыр1", "дырN", "без пары"):
            всего[к] += и[к]
        всего["порок"] += len(и["порок"])
        пороки.extend(и["порок"])
    print(f"{'ИТОГО':<18}{всего['пар']:>6}{всего['дыр1']:>11}{всего['дырN']:>12}"
          f"{всего['порок']:>7}{всего['без пары']:>10}")
    for язык, форма, неф, веж, из, в in пороки[:12]:
        print(f"  ПОРОК [{язык} {форма}] дыра «{из}» → «{в}»")
        print(f"    неформально: {неф}")
        print(f"    вежливо:     {веж}")
    доля = 100 * всего["дыр1"] // всего["пар"] if всего["пар"] else 0
    итог = "PASS" if всего["порок"] == 0 else "FAIL"
    print(f"ПАРА РЕГИСТРА {итог}: пар {всего['пар']}, одной дырой {всего['дыр1']} ({доля} %), "
          f"дыр больше {всего['дырN']}, ПОРОКОВ {всего['порок']} (рубеж 0), без пары {всего['без пары']}")
    return 1 if всего["порок"] else если_нет


if __name__ == "__main__":
    sys.exit(main())
