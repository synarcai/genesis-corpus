#!/usr/bin/env python3
"""[ПАСПОРТ КОРНЕЙ] — корень обязан знать своих читателей, а читатель — назвать свой корень.

ПОВОД — ТРИ ШРАМА ОДНОГО ДНЯ (07.09), и все три одного рода:

    ПАКЕТ ЯЗЫКА ПЕРЕПИСАЛ ЧУЖОЙ МИР. Три слова, объявленные в `langpacks/en.json` ради суда
        памяти, сдвинули общий список — и дом глифов, выбирающий рисуемые слова ПО НОМЕРУ
        в этом списке, переписался весь: «child» стал «chair», «nut» — «number». МОЛЧА;
        поймал прибор воспроизводимости, сличением постфактум.
    МИР БУКВ СТОЛКНУЛСЯ С УДЕРЖАННЫМ КЛЮЧОМ. Слово «книга», вписанное в список букв,
        стои́т в тайном списке ключа следующей точки. ГРОМКО — утверждением, в тот же миг.
    ДОМ ПЕРЕВОДА СПАРИВАЛ ПО НОМЕРУ МЕСТА чужой список — 75 ложных строк в своде.

    ПРАВКА ЛЮБОГО ДОМА, НА КОТОРЫЙ СМОТРИТ ДРУГОЙ, ЕСТЬ ПРАВКА ОБОИХ. Между «поймал прибор
    постфактум» и «поймало утверждение в доме» — вся разница; второе надо ставить всюду,
    где первое сработало хоть раз.

ЧТО МЕРИТ ПРИБОР. Дом, объявивший себя КОРНЕМ, несёт список `ЧИТАЮТ` — имена домов, что
читают его таблицы. Прибор сверяет объявление с делом двусторонне:

    ЧИТАЕТ, НО НЕ НАЗВАН — корень не знает своего читателя, и правка корня застанет его
        врасплох. Это долг КОРНЯ: дописать имя.
    НАЗВАН, НО НЕ ЧИТАЕТ — паспорт несёт призрака, и всякий, кто по нему судит о цене
        правки, судит по выдумке. Это долг того же корня: имя вычеркнуть.

Список читателей есть ОБЪЯВЛЕНИЕ, и потому он проверяется, а не выводится: прибор не
дописывает его сам — он роняет ход и называет имена.

    python3 scripts/root_passport.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: корней нет — прибор говорит ОТКАЗ, а не PASS
import argparse
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

# РУБЕЖ-ДОЛГА: РАЗЛАДОВ_РУБЕЖ = 0
#
# Ноль есть ПОЛ, а не потолок: корень, чей паспорт разошёлся с делом, роняет прибор в тот
# же час, когда его правят. Цена этого нуля — одна строка в объявлении корня.
РАЗЛАДОВ_РУБЕЖ = 0

_ЧИТАЮТ = re.compile(r"^ЧИТАЮТ\s*=\s*\(([^)]*)\)", re.M)
_ИМЯ = re.compile(r'"([^"]+)"')


def корни():
    """[(имя корня, [объявленные читатели])] — дома, объявившие себя корнями."""
    вон = []
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        т = путь.read_text(encoding="utf-8", errors="replace")
        м = _ЧИТАЮТ.search(т)
        if м:
            вон.append((путь.stem, sorted(_ИМЯ.findall(м.group(1)))))
    return вон


def читатели(имя_корня):
    """Дома и приборы, которые ДЕЙСТВИТЕЛЬНО ввозят этот корень."""
    образец = re.compile(rf"^\s*(?:import\s+{re.escape(имя_корня)}\b"
                         rf"|from\s+{re.escape(имя_корня)}\s+import\b)", re.M)
    вон = []
    for место in ("tools", "courts", "scripts"):
        for путь in sorted((КОРЕНЬ / место).glob("*.py")):
            if путь.stem == имя_корня:
                continue
            if образец.search(путь.read_text(encoding="utf-8", errors="replace")):
                вон.append(путь.stem)
    return sorted(вон)


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    дов = ап.parse_args()
    список = корни()
    if not список:
        print("ПАСПОРТ КОРНЕЙ ОТКАЗ: ни один дом не объявил себя корнем (нет `ЧИТАЮТ`)")
        return 2
    разлады = []
    print(f"{'корень':<20}{'объявлено':>11}{'читают':>9}{'разлад':>8}")
    for имя, объявлено in список:
        на_деле = читатели(имя)
        лишние = [ч for ч in объявлено if ч not in на_деле]
        забытые = [ч for ч in на_деле if ч not in объявлено]
        разлад = len(лишние) + len(забытые)
        разлады += [(имя, "НАЗВАН, НО НЕ ЧИТАЕТ", ч) for ч in лишние]
        разлады += [(имя, "ЧИТАЕТ, НО НЕ НАЗВАН", ч) for ч in забытые]
        print(f"{имя:<20}{len(объявлено):>11}{len(на_деле):>9}{разлад:>8}")
        if дов.подробно:
            print(f"    объявлено: {', '.join(объявлено) or '—'}")
            print(f"    на деле:   {', '.join(на_деле) or '—'}")
    for имя, род, ч in разлады:
        print(f"  РАЗЛАД [{имя}] {род}: {ч}")
    поза = "PASS" if len(разлады) <= РАЗЛАДОВ_РУБЕЖ else "FAIL"
    print(f"ПАСПОРТ КОРНЕЙ {поза}: корней {len(список)}, разладов объявления с делом "
          f"{len(разлады)} (рубеж {РАЗЛАДОВ_РУБЕЖ})")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
