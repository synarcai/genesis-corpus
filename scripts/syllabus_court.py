#!/usr/bin/env python3
"""[ПОЛНОТА] — чего в корпусе НЕТ ВОВСЕ.

Судимость говорит, что каждую строку кто-то читает; она молчит о том,
чего не написано. Сто процентов судимости при одной арифметике — сто
процентов. Полнота есть вторая мера, и меряется она снаружи: сводом
`tools/syllabus.py`, где названо, чем обязан владеть исследователь.

ПРЕДМЕТ ИЩЕТСЯ СВОЕЙ ПРОБОЙ ПО ВСЕМУ КОРПУСУ, а не по указанному миру:
слой можно переписать, разделить и переименовать, не трогая свода.

МАССА, А НЕ ПРИСУТСТВИЕ. Предмет, показанный трижды, не выучен: у
показа есть закон повтора, и одна строка не покупает формы. Порог
назван у каждого предмета свой.

ЧТО ЭТОТ ПРИБОР НЕ ГОВОРИТ, И ЭТО НАДО ЗНАТЬ: он мерит МАССУ ПОДПИСИ, а
не глубину понимания. Проба, нашедшая двадцать строк, ручается, что
предмет в корпусе ЕСТЬ, — не за то, что он раскрыт хорошо. Судимость
ручается за истинность каждой строки, полнота — за наличие предмета;
глубина не меряется ни тем, ни другим и покупается судами рода.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genesis import Unreadable, worlds  # noqa: E402
from syllabus import РАЗДЕЛЫ, СВОД  # noqa: E402

# РУБЕЖ-ДОЛГА: НЕПОКРЫТЫХ_РУБЕЖ = 0
НЕПОКРЫТЫХ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest


def обход():
    if "--manifest" in sys.argv:
        import genesis
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        return [п for п in worlds(kind="shows") if п.is_file()]
    except Unreadable as беда:
        print(f"ПОЛНОТА ОТКАЗ: {беда}")
        sys.exit(2)


def массы(пути):
    """{(раздел, имя): сколько строк корпуса несут подпись предмета}."""
    образцы = [(п, re.compile(п.проба, re.I)) for п in СВОД]
    счёт = {(п.раздел, п.имя): 0 for п in СВОД}
    for путь in пути:
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                if not строка.strip():
                    continue
                for предмет, образец in образцы:
                    if образец.search(строка):
                        счёт[(предмет.раздел, предмет.имя)] += 1
    return счёт


def main():
    пути = обход()
    if not пути:
        print("ПОЛНОТА ОТКАЗ: обход пуст, мерить нечего")
        return 2
    счёт = массы(пути)
    непокрытых = []
    for предмет in СВОД:
        было = счёт[(предмет.раздел, предмет.имя)]
        if было < предмет.масса:
            непокрытых.append((предмет, было))
    for раздел in РАЗДЕЛЫ:
        свои = [(п, б) for п, б in непокрытых if п.раздел == раздел]
        всего = sum(1 for п in СВОД if п.раздел == раздел)
        if свои:
            print(f"  {раздел:<14} нет {len(свои)} из {всего}: "
                  + ", ".join(f"{п.имя} ({б}/{п.масса})" for п, б in свои[:6]))
    поза = "PASS" if len(непокрытых) <= НЕПОКРЫТЫХ_РУБЕЖ else "FAIL"
    print(f"ПОЛНОТА {поза}: {len(непокрытых)} предметов свода не покрыты "
          f"из {len(СВОД)} (рубеж {НЕПОКРЫТЫХ_РУБЕЖ}, {len(пути)} файлов)")
    return 0 if len(непокрытых) <= НЕПОКРЫТЫХ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
