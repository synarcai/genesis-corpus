#!/usr/bin/env python3
"""[ОХВАТ БЕСЕДЫ] — есть ли в своде ПОКАЗ под каждый вопрос разговорной полосы.

Полоса `omega/bench/attack/beseda.txt` (holon, 04.09) меряет ОРГАНИЗМ: сколько
вопросов обычного человека он не оставит без ответа. Этот прибор меряет
КОРПУС и потому дешевле варки на три порядка: он спрашивает, есть ли в своде
строка, на которой форму ответа вообще можно купить. Показа нет — купить
неоткуда, и никакая варка этого не изменит.

ТРИ ВЕРДИКТА, И ИХ РАЗЛИЧЕНИЕ ЕСТЬ ГЛАВНОЕ, ЧТО ДАЁТ ПРИБОР:
  · СТРОКА — свод несёт этот вопрос буква в букву;
  · ФОРМА — свод несёт его РОД: тот же скелет (имена → «@», числа → «#»,
    заполнители домов → «※»), иные слова в дырах. «у ани 5 яблок. а у тома?»
    и «у Анны 7 шаров. а у Вани?» суть одна форма и разные строки.
  · ЧУЖОЕ ИМЯ — форма есть, но полоса назвала лицо, какого в своде нет
    вовсе («а у тома?» при «а у Вани?»). Прибор, знавший имена лишь по
    объявлению пакетов, звал такую строку НЕМОЙ и врал: форма стоит в своде
    целиком, разнится одно слово в дыре. Слово, не встреченное НИ РАЗУ во
    всех 323 тысячах строк свода, не может быть частью корпусной формы —
    значит оно дыра, а не слово, и прибор метит его «@» второй попыткой.
    Вердикт назван отдельно, ибо приём опасен: чем больше слов он сочтёт
    дырами, тем легче найдёт совпадение, и потому он берётся ТОЛЬКО после
    неудачи честного сличения и ТОЛЬКО для слов, свод которых не знает.
Различение не косметическое: «формы нет» лечится КОРПУСОМ, «форма есть,
спрошена иначе» — второй поверхностью ИЛИ рынком, читающим вопрос по роли, а
не по строке; это разные работы и разные руки.

    python3 scripts/beseda_reach.py [--полоса …] [--свод datasets/GENESIS-FULL.txt]
"""
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import form_census as C  # noqa: E402

ПОЛОСА = КОРЕНЬ.parent / "omega" / "bench" / "attack" / "beseda.txt"
_СЛОВО = re.compile(r"[^\W\d_]+", re.UNICODE)


def вопросы(путь):
    род = None
    for с in путь.read_text(encoding="utf-8").splitlines():
        с = с.strip()
        if с.startswith("# GENUS:"):
            род = с.split(":", 1)[1].strip()
            continue
        if not с or с.startswith("#"):
            continue
        в = с.split("|||")[0].strip()
        if в:
            yield род, в


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--полоса", type=pathlib.Path, default=ПОЛОСА)
    ап.add_argument("--свод", default="datasets/GENESIS-FULL.txt")
    а = ап.parse_args()
    if not а.полоса.is_file():
        print(f"нет полосы: {а.полоса}", file=sys.stderr)
        return 1
    строки = [с.strip() for с in (КОРЕНЬ / а.свод).read_text(encoding="utf-8").splitlines()
              if с.strip() and not с.startswith("\x0c")]
    скелеты = collections.defaultdict(list)
    словарь = set()
    for с in строки:
        скелеты[C.род(C.скелет(с))].append(с)
        словарь.update(_СЛОВО.findall(с.lower()))
    итог = collections.Counter()
    нет = collections.defaultdict(list)
    иначе = collections.defaultdict(list)
    чужие = collections.defaultdict(list)
    for род, в in вопросы(а.полоса):
        if any(л.startswith(в) or f" {в}" in л for л in строки):
            итог[(род, "строка")] += 1
            continue
        # ФОРМА ИЩЕТСЯ ВХОЖДЕНИЕМ СКЕЛЕТА, А НЕ РАВЕНСТВОМ: полоса даёт ОДИН
        # вопрос, а показ свода есть страница — утверждение, вопрос и ответ.
        # Прибор, сличавший скелеты целиком, нашёл ноль форм из пятнадцати и
        # тем сам себя опроверг: формы в своде есть, вопрос в них лишь часть.
        ск = C.род(C.скелет(в)).strip(" .")
        нашлось = None
        if len(ск) >= 10:
            for л_ск, ряд in скелеты.items():
                if ск in л_ск:
                    нашлось = ряд[0]
                    break
        if нашлось:
            итог[(род, "форма")] += 1
            иначе[род].append((в, нашлось))
            continue
        # ВТОРАЯ ПОПЫТКА — С ЧУЖИМ ИМЕНЕМ (см. вердикты в голове файла).
        ск2 = _СЛОВО.sub(lambda м: м.group() if м.group().lower() in словарь else "@", ск)
        нашлось2 = None
        if ск2 != ск and len(ск2) >= 10:
            for л_ск, ряд in скелеты.items():
                if ск2 in л_ск:
                    нашлось2 = ряд[0]
                    break
        if нашлось2:
            итог[(род, "чужое имя")] += 1
            чужие[род].append((в, нашлось2))
        else:
            итог[(род, "нет")] += 1
            нет[род].append(в)
    роды = sorted({р for р, _ in итог})
    print(f"{'род полосы':26} {'строкой':>8} {'формой':>7} {'чужим именем':>13} {'нет':>5}")
    с_всего = ф_всего = ч_всего = н_всего = 0
    for р in роды:
        с_, ф_, ч_, н_ = итог[(р, "строка")], итог[(р, "форма")], итог[(р, "чужое имя")], итог[(р, "нет")]
        с_всего += с_; ф_всего += ф_; ч_всего += ч_; н_всего += н_
        print(f"{р:26} {с_:8} {ф_:7} {ч_:13} {н_:5}")
    всего = с_всего + ф_всего + ч_всего + н_всего
    print(f"{'ИТОГО':26} {с_всего:8} {ф_всего:7} {ч_всего:13} {н_всего:5}   "
          f"— строкой {100 * с_всего // всего} %, с формой {100 * (с_всего + ф_всего) // всего} %, "
          f"с чужим именем {100 * (с_всего + ф_всего + ч_всего) // всего} %")
    for р, ряд in иначе.items():
        for в, л in ряд[:2]:
            print(f"  ФОРМА ЕСТЬ, СПРОШЕНА ИНАЧЕ [{р}]: «{в}» ← «{л[:70]}»")
    for р, ряд in чужие.items():
        for в, л in ряд[:2]:
            print(f"  ФОРМА ЕСТЬ, ЛИЦО ЧУЖОЕ [{р}]: «{в}» ← «{л[:70]}»")
    for р, ряд in нет.items():
        print(f"  ФОРМЫ НЕТ [{р}] {len(ряд)}: {ряд[:3]}")
    return 0



if __name__ == "__main__":
    sys.exit(main())
