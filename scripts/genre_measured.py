#!/usr/bin/env python3
"""[ЗАМЕР В ОБЪЯВЛЕНИИ] — число, вписанное в рассказ о мире, против тела этого мира.

    ЗАМЕР, ВПИСАННЫЙ В ОБЪЯВЛЕНИЕ, СТАРЕЕТ МОЛЧА: ЧИСЛО, БЫВШЕЕ ВЕРНЫМ, ОСТАЁТСЯ
    СТОЯТЬ И ЛЖЁТ, И НИКТО ЕГО НЕ СПРАШИВАЕТ.

ПОВОД. Закон был выведен 11.09 для ЛИЦА СВОДА — README, — и звучал так:

    РАССКАЗ О СВОДЕ ЕСТЬ УТВЕРЖДЕНИЕ О СВОДЕ, И ПОТОМУ ПОДСУДЕН, как всякое утверждение.

Прибор поставлен был на четыре строки README и с тех пор поймал их трижды. А сорок четыре
мира несут в своих объявлениях СВОИ замеры — «Measured 12.09: 520 lines», «замер 12.09:
182 строки», — и о них не спрашивал никто.

    ЗАКОН, ВЫВЕДЕННЫЙ ДЛЯ ЛИЦА СВОДА, НЕ ПЕРЕШЁЛ НА ЛИЦА МИРОВ САМ.

СОГЛАШЕНИЕ, КОТОРОЕ ЭТОТ ПРИБОР ДЕЛАЕТ ЗАКОНОМ: ПЕРВОЕ «N строк» ПОСЛЕ СЛОВА «ЗАМЕР»
ЕСТЬ ОБЩИЙ СЧЁТ СТРОК ЭТОГО МИРА. Замер 12.09 нашёл соглашение соблюдённым в сорока двух
объявлениях из сорока четырёх; два выправлены в тот же час — одно писало первым частный
счёт («4766 lines in Russian» при 11 380 всего), другое замеряло СВОД, не сказав того.

ЗАМЕР СВОДА НЕ ЕСТЬ ЗАМЕР МИРА, и прибор их различает по словам объявления: «across the
show worlds», «по мирам показов», «свода». Мир вправе рассказывать о своде — он лишь
обязан сказать, что говорит о своде.

    ЧИСЛО БЕЗ СКАЗАННОГО ПРЕДМЕТА ЧИТАЕТСЯ КАК ЧИСЛО О БЛИЖАЙШЕМ ПРЕДМЕТЕ, И ЭТО НЕ
    ВИНА ЧИТАТЕЛЯ.

ТРЕТИЙ ПРЕДМЕТ ЗАМЕРА — ЧУЖОЙ ПЛАСТ (13.09). Двадцать один дом неназванного закона стои́т
против отказа языкового пласта и объявляет в первой строке замер ЭТОГО ПЛАСТА: «ПОВОД,
ЗАМЕРЕННЫЙ 13.09 ПО ПЛАСТУ КОРЕЙСКОГО (2 215 строк)». Число верно и говорит о другом мире;
прибор же читал его как счёт СВОЕГО мира и назвал устаревшими девять замеров подряд.

    ЧИСЛО, ГОВОРЯЩЕЕ О ЧУЖОМ МИРЕ, НЕ ЕСТЬ УСТАРЕВШЕЕ ЧИСЛО О СВОЁМ. Девять расхождений
    подряд суть не девять долгов дома, а ОДИН ДОЛГ СОГЛАШЕНИЯ: у замера завёлся третий
    предмет, а слов для него не было.

И ЗАМЕР ЭТОТ НЕ ПРОЩАЕТСЯ, А ПРОВЕРЯЕТСЯ. Пласт назван домом машинно — `ЯЗЫК_ЗАКОНА = "ko"`,
то самое объявление, которым дом отвечает `scripts/refusal_reason.py`, — и прибор сверяет
число с `datasets/genesis_lang_ko.txt`. Замер о чужом мире подсуден ровно так же, как о своём.

    ПРОЩЁННОЕ ЧИСЛО СТАРЕЕТ ТАК ЖЕ, КАК НЕПРОЧИТАННОЕ. Единственная разница между ними —
    что о прощёнии кто-то однажды знал.

ЧЕГО ПРИБОР НЕ ДЕЛАЕТ. Он не сверяет ЧАСТНЫХ чисел объявления — «251 русская строка»,
«342 вопроса», «2940 артиклей». Их сверка требовала бы, чтобы прибор знал, что такое
русская строка и что такое вопрос, — а он знает лишь одно: сколько строк в файле.

    python3 scripts/genre_measured.py [--подробно]
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"

# РУБЕЖ-ДОЛГА: РАЗОШЕДШИХСЯ_РУБЕЖ = 0
#
# Рубеж есть ПОЛ, а не поблажка: замер 12.09 нашёл сорок четыре объявленных замера, и все
# сорок четыре сошлись с делом после двух правок соглашения. Прибор поставлен, чтобы
# сорок пятый расходился не дольше часа.
РАЗОШЕДШИХСЯ_РУБЕЖ = 0

# ПРИЗНАК ЧИТАЕТСЯ БЕЗ РАЗБОРА РЕГИСТРА (12.09, ночь). Писанный строчными, он не видел
# тех объявлений, что НАЧИНАЮТ словом «Замер» предложение, — а таких двадцать три из
# ста пятидесяти. Прибор говорил «сошлось 44» и молчал о двадцати трёх, которых не
# читал вовсе.
#
#     ПРИБОР, НЕ ВИДЯЩИЙ ЗАГЛАВНОЙ БУКВЫ ПРИЗНАКА, МОЛЧИТ О ТЕХ, КТО НАЧАЛ ИМ
#     ПРЕДЛОЖЕНИЕ, — И МОЛЧАНИЕ ЭТО НЕОТЛИЧИМО ОТ СОГЛАСИЯ.
#
# Слепота прятала РОВНО ОДИН расходящийся замер, и он выправлен тем же движением.
ЗАЧИН = re.compile(r"замер\w*|Measured|measured|census", re.IGNORECASE)
ЧИСЛО = re.compile(r"(\d[\d\s ]*?)\s*(?:строк\w*|lines)\b")
# СЛОВА, ОБЪЯВЛЯЮЩИЕ ПРЕДМЕТОМ ЗАМЕРА СВОД, А НЕ МИР.
О_СВОДЕ = ("across", "show worlds", "свод", "мирам", "worlds", "по всему")
# СЛОВА, ОБЪЯВЛЯЮЩИЕ ПРЕДМЕТОМ ЗАМЕРА ЧУЖОЙ ЯЗЫКОВОЙ ПЛАСТ. Замер этот не прощается, а
# сверяется с тем пластом, который дом назвал в `ЯЗЫК_ЗАКОНА`.
О_ПЛАСТЕ = ("по пласту", "пласту ", "layer of", "по пластам")
ОКНО = 200


def пласт_дома(имя_мира):
    """Пути языковых пластов, объявленных домом мира через `ЯЗЫК_ЗАКОНА`, либо ()."""
    sys.path.insert(0, str(КОРЕНЬ / "tools"))
    try:
        дом = __import__(f"{имя_мира}forms")                    # noqa: PLC0415
    except Exception:                                           # noqa: BLE001
        return ()
    коды = getattr(дом, "ЯЗЫК_ЗАКОНА", None)
    if isinstance(коды, str):
        коды = (коды,)
    return tuple(КОРЕНЬ / "datasets" / f"genesis_lang_{к}.txt" for к in (коды or ()))


def сказанное(жанр):
    """(число, кусок) — объявленный общий счёт строк мира, либо None."""
    m = ЗАЧИН.search(жанр)
    if not m:
        return None
    хвост = жанр[m.end():m.end() + ОКНО]
    ч = ЧИСЛО.search(хвост)
    if not ч:
        return None
    перед = хвост[:ч.start()].lower()
    if any(з in перед for з in О_СВОДЕ):
        return None
    предмет = "пласт" if any(з in перед for з in О_ПЛАСТЕ) else "мир"
    return int(re.sub(r"[\s ]", "", ч.group(1))), хвост[:ч.end()].strip(), предмет


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что прибор УМЕЕТ находить.

        ПРИБОР, ЗЕЛЕНЕЮЩИЙ ОТ НУЛЯ НАХОДОК, ОБЯЗАН ДОКАЗАТЬ, ЧТО УМЕЕТ НАХОДИТЬ.

    Четыре объявления, каждое со своим заведомым ответом: замер мира (обязан
    прочесться), замер СВОДА (обязан быть пропущен — «across the show worlds»),
    объявление без замера (обязано остаться немым) и замер с разрядами через пробел
    («1 234 строки» — обязан прочесться целиком, а не куском).
    """
    случаи = (
        ("Measured 12.09: 520 lines, 251 Russian", 520, "замер мира"),
        ("measured across the show worlds on 380 610 lines", None, "замер свода"),
        ("a world of shows about nothing at all", None, "объявление без замера"),
        ("замер 12.09: 1 234 строки, 500 вопросов", 1234, "разряды через пробел"),
    )
    беды = []
    for жанр, ждём, имя in случаи:
        вышло = сказанное(жанр)
        было = вышло[0] if вышло else None
        if было != ждём:
            беды.append(f"{имя}: прочтено {было}, а надо {ждём}")
    # ПРЕДМЕТ ЗАМЕРА ЧИТАЕТСЯ ТОЖЕ, И ЭТО ПРОБУЕТСЯ ОТДЕЛЬНО: замер своего мира и замер
    # чужого пласта различаются словом, и прибор обязан их развести.
    for жанр, ждём, имя in (
            ("Замер 13.09 ПО ПЛАСТУ КОРЕЙСКОГО (2 215 строк)", "пласт", "замер чужого пласта"),
            ("Measured 12.09: 520 lines, 251 Russian", "мир", "замер своего мира")):
        вышло = сказанное(жанр)
        было = вышло[2] if вышло else None
        if было != ждём:
            беды.append(f"{имя}: предмет прочтён «{было}», а надо «{ждём}»")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    беды = _проба()
    if беды:
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"ЗАМЕР В ОБЪЯВЛЕНИИ ОТКАЗ: прибор не доказал, что умеет находить "
              f"({len(беды)} бед) — вердикту о своде верить нельзя")
        return 2
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
    if not манифест.is_file():
        print(f"ЗАМЕР В ОБЪЯВЛЕНИИ ОТКАЗ: манифеста нет — {манифест}")
        return 2
    тело = json.loads(манифест.read_text(encoding="utf-8"))
    миры = [м for м in тело.get("worlds", ()) if м.get("text") == "shows"]
    if not миры:
        print("ЗАМЕР В ОБЪЯВЛЕНИИ ОТКАЗ: миров показов нет, спрашивать не о ком")
        return 2
    подробно = "--подробно" in sys.argv
    сошлось, разошлось, без_замера = 0, [], 0
    for м in миры:
        п = pathlib.Path(м.get("file", ""))
        if not п.is_absolute():
            п = КОРЕНЬ / п
        if not п.is_file():
            continue
        сказ = сказанное(м.get("genre", ""))
        if сказ is None:
            без_замера += 1
            continue
        n, кусок, предмет = сказ
        пути = list(пласт_дома(м["name"])) or [п] if предмет == "пласт" else [п]
        дело = sum(1 for путь in пути if путь.is_file()
                   for с in путь.read_text(encoding="utf-8", errors="replace").split("\n")
                   if с.strip())
        if n == дело:
            сошлось += 1
            if подробно:
                print(f"  {м['name']:<24} {n} строк — сошлось")
        else:
            разошлось.append((м["name"], n, дело, кусок))
    for имя, n, дело, кусок in разошлось[:8]:
        знак = "+" if дело > n else "−"
        print(f"  ЗАМЕР УСТАРЕЛ «{имя}»: объявлено {n}, в деле {дело} "
              f"({знак}{abs(дело - n)}) — «{кусок[-56:]}»")
    поза = "PASS" if len(разошлось) <= РАЗОШЕДШИХСЯ_РУБЕЖ else "FAIL"
    print(f"ЗАМЕР В ОБЪЯВЛЕНИИ {поза}: устаревших замеров {len(разошлось)} "
          f"(рубеж {РАЗОШЕДШИХСЯ_РУБЕЖ}); сошлось {сошлось}, миров без объявленного "
          f"замера {без_замера} из {len(миры)}")
    return 0 if len(разошлось) <= РАЗОШЕДШИХСЯ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
