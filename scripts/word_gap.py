#!/usr/bin/env python3
"""[ПРОПУЩЕННОЕ СЛОВО] — где одна форма корпуса роняет слово, которое держит другая.

Расхождение, найденное holon 03.09 трассой полосы: русская универсалия
говорила «сумма первых k нечётных равна k × k», а русская рамка значения —
«чему равна сумма первых # нечётных ЧИСЕЛ?». Английская пара совпадала слово
в слово, поэтому английская строка разбиралась как уравнение, а русская нет.
Изъян был не в языке и не в суде: две строки одного корпуса говорили одно
разными словами, и одна из них роняла родовое слово.

Прибор ищет такие пропуски ВЕЗДЕ, и ищет их формой, а не списком: если в
корпусе стоит тройка слов «W G X» и одновременно стоит пара «W X» — та же
левая и та же правая рука, но без середины, — и слово G есть ЧАСТЫЙ спутник
W, то пара «W X» подозревается в пропуске G. Число рядом с находкой есть
цена подозрения: сколько раз сказано с серединой и сколько без неё.

ЭТО КАРТА, А НЕ ПРИГОВОР. Пропуск бывает законным: язык знает эллипсис, и
«сумма первых десяти» без «чисел» — не ложь. Прибор называет места, где
корпус говорит ДВУМЯ формами об одном, и решает человек — но молчать о них
он не вправе: форма, встреченная однажды, есть форма, которую полоса не
купит, а суд соседа не разберёт.

    python3 scripts/word_gap.py [--рубеж 5] [--сколько 20] [--мир имя]
"""
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import form_census as C  # noqa: E402
import genesis  # noqa: E402

# слово есть буквенная связка, число — «#», имя — «@»; знаки препинания
# СОХРАНЯЮТСЯ отдельными словами, ибо «нечётных равна» и «нечётных, равна»
# суть разные формы
СЛОВО = re.compile(r"[^\W\d_]+|#|@|[^\s\w]", re.UNICODE)
# ОДНОБУКВЕННАЯ ПЕРЕМЕННАЯ ЕСТЬ ЧИСЛО. Универсалия говорит «при k = 3», а
# рамка значения — «при 3»: не приравняв «k» числу, прибор не увидел бы, что
# две строки говорят одно, и пропуск слова между ними остался бы незаметен.
ПЕРЕМЕННАЯ = frozenset("knmxy")
# КОНТЕКСТ В ДВА СЛОВА С КАЖДОЙ СТОРОНЫ. Первая редакция брала одно слово
# слева и одно справа, и двадцать пять первых находок оказались случайными
# встречами разных миров («the house cost ?» из мира кратного против «where
# is the house ?» из бытового): совпадение двух слов в корпусе из трёхсот
# тысяч строк ничего не значит. Четыре слова общего окружения — уже форма.
ОКНО = 2


def слова(строка):
    ряд = СЛОВО.findall(C.скелет(строка))
    return ["#" if (len(с) == 1 and с in ПЕРЕМЕННАЯ) else с for с in ряд]


def счёт(пути):
    """Счёт окон с серединой (2+1+2) и без неё (2+2) — В ПРЕДЕЛАХ ОДНОГО МИРА.

    МИР ЕСТЬ ГРАНИЦА СРАВНЕНИЯ, и это не удобство, а закон. Два разных мира
    вправе говорить по-разному: «the house cost 20000 dollars» в мире
    кратного и «where is the house?» в бытовом не спорят друг с другом, они
    о разном. Спорят две формы ОДНОГО мира — так и был устроен изъян,
    найденный holon: универсалия и рамка значения стояли рядом, в мире
    дознания, и роняли слово по-разному.
    """
    с_серединой = collections.Counter()
    без_середины = collections.Counter()
    пример_с = {}
    пример_без = {}
    for путь in пути:
        мир = путь.stem
        for стр in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            с = стр.strip()
            if not с or с.startswith("\x0c"):
                continue
            ряд = слова(с)
            for i in range(len(ряд) - 2 * ОКНО):
                ключ = (мир, tuple(ряд[i:i + 2 * ОКНО + 1]))
                с_серединой[ключ] += 1
                пример_с.setdefault(ключ, с)
            for i in range(len(ряд) - 2 * ОКНО + 1):
                ключ = (мир, tuple(ряд[i:i + 2 * ОКНО]))
                без_середины[ключ] += 1
                пример_без.setdefault(ключ, с)
    return с_серединой, без_середины, пример_с, пример_без


def находки(с_серединой, без_середины, рубеж):
    """Подозрение: то же окружение ТОГО ЖЕ МИРА стоит и без середины, и реже."""
    вон = []
    for (мир, окно), n in с_серединой.items():
        G = окно[ОКНО]
        if n < рубеж or not G.isalpha():
            continue
        куцее = окно[:ОКНО] + окно[ОКНО + 1:]
        если_бы = без_середины.get((мир, куцее), 0)
        if если_бы == 0 or если_бы >= n:
            continue
        вон.append((n / если_бы, n, если_бы, мир, окно, куцее))
    вон.sort(key=lambda з: (-з[0], -з[1]))
    return вон


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--рубеж", type=int, default=5)
    ап.add_argument("--сколько", type=int, default=20)
    ап.add_argument("--мир", default=None)
    а = ап.parse_args()
    пути = [п for п in genesis.worlds(kind="shows")
            if а.мир is None or а.мир in п.stem]
    с_серединой, без_середины, пр_с, пр_б = счёт(пути)
    найдено = находки(с_серединой, без_середины, а.рубеж)
    print(f"ПРОПУЩЕННОЕ СЛОВО: миров {len(пути)}, окон {len(с_серединой)}, "
          f"подозрений {len(найдено)} (рубеж окна {а.рубеж}, "
          f"контекст {ОКНО}+{ОКНО})")
    for кратность, n, если_бы, мир, окно, куцее in найдено[:а.сколько]:
        слева = " ".join(окно[:ОКНО])
        справа = " ".join(окно[ОКНО + 1:])
        print(f"  {мир}: «{слева} [{окно[ОКНО]}] {справа}» — с серединой {n}, "
              f"без неё {если_бы} (в {кратность:.0f} раз реже)")
        print(f"      с:   {пр_с[(мир, окно)][:96]}")
        print(f"      без: {пр_б[(мир, куцее)][:96]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
