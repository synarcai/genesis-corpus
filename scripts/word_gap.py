#!/usr/bin/env python3
"""[ПРОПУЩЕННОЕ СЛОВО] — где одна форма корпуса роняет слово, которое держит другая.

Расхождение, найденное holon 03.09 трассой полосы: русская универсалия
говорила «сумма первых k нечётных равна k × k», а русская рамка значения —
«чему равна сумма первых # нечётных ЧИСЕЛ?». Английская пара совпадала слово
в слово, поэтому английская строка разбиралась как уравнение, а русская нет.
Изъян был не в языке и не в суде: две строки одного корпуса говорили одно
разными словами, и одна из них роняла родовое слово.

Прибор ищет такие пропуски ВЕЗДЕ, и ищет их формой, а не списком: если в
корпусе стоит тройка слов «W G X» и одновременно стоит пара «W X» — та же
левая и та же правая рука, но без середины, — и слово G есть ЧАСТЫЙ спутник
W, то пара «W X» подозревается в пропуске G. Число рядом с находкой есть
цена подозрения: сколько раз сказано с серединой и сколько без неё.

ЭТО КАРТА, А НЕ ПРИГОВОР. Пропуск бывает законным: язык знает эллипсис, и
«сумма первых десяти» без «чисел» — не ложь. Прибор называет места, где
корпус говорит ДВУМЯ формами об одном, и решает человек — но молчать о них
он не вправе: форма, встреченная однажды, есть форма, которую полоса не
купит, а суд соседа не разберёт.

    python3 scripts/word_gap.py [--рубеж 5] [--сколько 20] [--мир имя]
"""
import argparse
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "scripts"))
import form_census as C  # noqa: E402
import genesis  # noqa: E402

# слово есть буквенная связка, число — «#», имя — «@»; знаки препинания
# СОХРАНЯЮТСЯ отдельными словами, ибо «нечётных равна» и «нечётных, равна»
# суть разные формы
СЛОВО = re.compile(r"[^\W\d_]+|#|@|[^\s\w]", re.UNICODE)
# доля, при которой спутник считается ЧАСТЫМ: слово, идущее за W чаще
# половины всех случаев, есть его обычная середина, и пропуск такого слова
# заметнее пропуска редкого
ДОЛЯ_СПУТНИКА = 0.34


def слова(строка):
    return СЛОВО.findall(C.скелет(строка))


def счёт(пути):
    тройки = collections.Counter()
    пары = collections.Counter()
    за = collections.Counter()
    пример_тройки = {}
    пример_пары = {}
    for путь in пути:
        for стр in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            с = стр.strip()
            if not с or с.startswith("\x0c"):
                continue
            ряд = слова(с)
            for i in range(len(ряд) - 1):
                пары[(ряд[i], ряд[i + 1])] += 1
                за[ряд[i]] += 1
                пример_пары.setdefault((ряд[i], ряд[i + 1]), (путь.stem, с))
            for i in range(len(ряд) - 2):
                тройки[(ряд[i], ряд[i + 1], ряд[i + 2])] += 1
                пример_тройки.setdefault((ряд[i], ряд[i + 1], ряд[i + 2]), (путь.stem, с))
    return тройки, пары, за, пример_тройки, пример_пары


def находки(тройки, пары, за, рубеж):
    вон = []
    for (W, G, X), n in тройки.items():
        if n < рубеж or not G.isalpha():
            continue
        если_бы = пары.get((W, X), 0)
        if не_подозрение(если_бы, n):
            continue
        доля = пары[(W, G)] / max(1, за[W])
        if доля < ДОЛЯ_СПУТНИКА:
            continue
        вон.append((n / max(1, если_бы), n, если_бы, доля, (W, G, X)))
    вон.sort(key=lambda з: (-з[0], -з[1]))
    return вон


def не_подозрение(если_бы, n):
    """Пара без середины должна СУЩЕСТВОВАТЬ и быть РЕЖЕ тройки."""
    return если_бы == 0 or если_бы >= n


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--рубеж", type=int, default=5)
    ап.add_argument("--сколько", type=int, default=20)
    ап.add_argument("--мир", default=None)
    а = ап.parse_args()
    пути = [п for п in genesis.worlds(kind="shows")
            if а.мир is None or а.мир in п.stem]
    тройки, пары, за, пр_т, пр_п = счёт(пути)
    найдено = находки(тройки, пары, за, а.рубеж)
    print(f"ПРОПУЩЕННОЕ СЛОВО: миров {len(пути)}, троек {len(тройки)}, "
          f"подозрений {len(найдено)} (рубеж тройки {а.рубеж})")
    for кратность, n, если_бы, доля, (W, G, X) in найдено[:а.сколько]:
        мир_т, стр_т = пр_т[(W, G, X)]
        мир_п, стр_п = пр_п[(W, X)]
        print(f"  «{W} [{G}] {X}»: с серединой {n}, без неё {если_бы} "
              f"(в {кратность:.0f} раз реже; «{G}» идёт за «{W}» в "
              f"{100 * доля:.0f} % случаев)")
        print(f"      с: {мир_т}: {стр_т[:96]}")
        print(f"      без: {мир_п}: {стр_п[:96]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
