#!/usr/bin/env python3
"""[РОД ПРОШЕДШЕГО] — русский глагол прошедшего времени: та ли форма и при том ли лице.

Русское прошедшее гнётся РОДОМ носителя, и корпус гнул его ДВУМЯ правилами, оба неверными:

    ПЕРВОЕ: «женское есть мужское плюс а». Верно для тринадцати основ корпуса из четырнадцати
    и ложно о четырнадцатой: «нашёл» + «а» = «нашёла» — слова, которого в русском НЕТ.
    Восемьдесят четыре страницы свода несли его, и восемнадцать из них стояли в доме, чей
    ПРЕДМЕТ есть ровно это правило.

        ДОМ, УЧАЩИЙ ПРАВИЛУ, УЧИЛ ЕГО НА ТОМ САМОМ ГЛАГОЛЕ, НА КОТОРОМ ПРАВИЛО ЛОМАЕТСЯ.

    ВТОРОЕ: «род лица есть окончание его имени». Верно для четырёх имён дома из шести и ложно
    о «Ване» и «Мише» — мужских именах, склоняющихся как женские. Шестьдесят две страницы
    цепи истории писали «Ваня взяла», «Миша купила»; ещё двадцать в доме девяти языков писали
    «купил» БУКВОЙ и оттого звали Веру и Аню мужчинами.

        ПРАВИЛО, ВЕРНОЕ ДЛЯ ЧЕТЫРЁХ ИЗ ШЕСТИ, ЕСТЬ НЕ ЗАКОН, А УДАЧА.

ДВА ЭТАЖА, И ОБА СЧЁТНЫ. Первый — что написано на странице: форма при объявленном лице.
Второй — видит ли суд подмену рода; связка, стоящая в образце основой с суффиксом, не отличит
«нашла» от «нашёла», ибо выводит обе одним и тем же неверным правилом.

    СУД, ВЫВОДЯЩИЙ ФОРМУ ТЕМ ЖЕ ПРАВИЛОМ, ЧТО И ДОМ, НЕ ПРОВЕРЯЕТ ДОМ — ОН ЕМУ ВТОРИТ.

ЗАКОН ЧИТАЕТСЯ У ДОМА ЯЗЫКА (`rugram.прошедшее`, `rugram.ПРОШЕДШЕЕ_ЖЕНСКОЕ`), а имена и их
род — у домов, что их объявили. Прибор не знает русского: он спрашивает.

    python3 scripts/past_gender.py [--подробно] [--дом ИМЯ]
"""
# ПУСТОЙ-ОБХОД: --дом no-such-house
import argparse
import collections
import importlib
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import rugram  # noqa: E402 — дом языка, объявивший закон прошедшего

# РУБЕЖ-ДОЛГА: НЕ_ПО_РОДУ_РУБЕЖ = 0
#
# НОЛЬ ОТ РОЖДЕНИЯ: восемьдесят две страницы найдены и вылечены в тот же час — четыре дома
# получили закон вместо правила, а суд цепи истории стал СТРОЖЕ прежнего (он читает род лица,
# чего не читал никогда). Долг, закрытый прежде объявления рубежа, объявляется нулём.
НЕ_ПО_РОДУ_РУБЕЖ = 0

# РУБЕЖ-ДОЛГА: НЕСЛОВ_РУБЕЖ = 0
#
# СЛОВО, КОТОРОГО НЕТ В ЯЗЫКЕ, ЕСТЬ ХУДШИЙ РОД ЛЖИ: его не с чем сличить, и всякий суд о нём
# молчит законно. «нашёла» и «принёса» жили в трёх мирах и в своде — 84 и 62 страницы.
НЕСЛОВ_РУБЕЖ = 0

# РУБЕЖ-ДОЛГА: СЛЕПЫХ_РУБЕЖ = 0
#
# ЧИСЛО ПЕРВОГО ЗАМЕРА, И ОНО ЕСТЬ ДОЛГ, А НЕ ПОЗВОЛЕНИЕ. Шесть домов пишут русское прошедшее
# при объявленном лице; ОДИН ловит подмену рода (`pronobject`), пять — нет. Трое НЕМЕЮТ
# (behaviorforms, kinbearer, linkforms: образец держит окончание дырой и не сверяет его с
# лицом), двое НАЗЫВАЮТ ПОРЧУ ИСТИНОЙ (svampforms, cmpframes) — и это хуже немоты:
#
#     СУД, МОЛЧАЩИЙ О ПОРЧЕ, БЕРЁТ ИСТИНУ У СОСЕДА. СУД, ЗОВУЩИЙ ПОРЧУ ИСТИНОЙ, ОТНИМАЕТ ЕЁ
#     У ВСЕХ: палата видит зелёный вердикт и дальше не смотрит.
#
# Долг ведётся ЧИСЛОМ ДОМОВ, а не проб (довод соседа `sign_traps`: проб тем больше, чем больше
# дом). Убывать ему можно, расти нельзя: новый дом, пишущий прошедшее и не читающий рода,
# роняет прибор в тот же час, когда его напишут.
#
# 5 → 0 В ТОТ ЖЕ ЧАС, И ТРЕМЯ РАЗНЫМИ ПУТЯМИ, ибо слепота была трёх разных родов:
#
#   · двое ЗВАЛИ ПОРЧУ ИСТИНОЙ (svampforms, cmpframes) — вердикт получил проверку рода
#     чтением строки у дома языка (`rugram.не_по_роду`) поверх своего образца;
#   · трое НЕМЕЛИ (behaviorforms, kinbearer, linkforms) — их образцы порчи не узнаю́т вовсе,
#     и о ней говорит ПЯТЫЙ БРАТ законов замкнутого мира (`closedworld.ложь_по_роду`):
#     форма, отличающаяся от показа одной буквой рода, есть этот же показ испорченный.
#
# Проб 202, поймано 202. Рубеж есть ПОЛ, а не потолок.
СЛЕПЫХ_РУБЕЖ = 0

ОБРАЗЦОВ = 40          # бюджет выборки на дом, не порог


def _лица():
    """Имя → род, собранное у ВСЕХ домов, что объявили лиц с родом, — а не списком здесь."""
    вон = {}
    споры = set()
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        if путь.stem.startswith("gen_") and путь.stem != "gen_genesis_story_chain":
            continue
        try:
            дом = importlib.import_module(путь.stem)
        except Exception:                       # noqa: BLE001
            continue
        for имя_поля in ("ЛИЦА", "ЛЮДИ_RU"):
            таблица = getattr(дом, имя_поля, None)
            ряды = None
            if isinstance(таблица, dict):
                ряды = таблица.get("ru")
            elif isinstance(таблица, (list, tuple)):
                ряды = таблица
            if not ряды:
                continue
            for строка in ряды:
                if not isinstance(строка, (list, tuple)) or len(строка) < 2:
                    continue
                имя = str(строка[0])
                пол = next((str(з) for з in строка[1:] if з in ("m", "f")), None)
                if пол is None or not re.fullmatch(r"[А-ЯЁ][а-яё]+", имя):
                    continue
                if вон.get(имя, пол) != пол:
                    споры.add(имя)
                вон[имя] = пол
    for имя in споры:                            # ИМЯ, О ЧЬЁМ РОДЕ ДОМА СПОРЯТ, НЕ СУДИТСЯ
        вон.pop(имя, None)
    return вон, споры


ЛИЦА, СПОРНЫЕ = _лица()
_ПРОШЕДШЕЕ = r"[а-яё]+(?:л|ла|ло)"
ПАРА = re.compile(r"\b(" + "|".join(sorted(ЛИЦА, key=len, reverse=True)) +
                  r")\s+(?:не\s+)?(" + _ПРОШЕДШЕЕ + r")\b") if ЛИЦА else None
# СЛОВО, КОТОРОГО НЕТ: женское, собранное прибавлением буквы к мужскому с беглой гласной
НЕСЛОВА = frozenset(м + rugram.СУФФИКС_ПРОШЕДШЕГО["f"] for м in rugram.ПРОШЕДШЕЕ_ЖЕНСКОЕ)


def обвинения(строка):
    """[(имя, форма, ждём)] — прошедшее при объявленном лице, стоящее не по его роду."""
    if ПАРА is None:
        return []
    вон = []
    for имя, форма in ПАРА.findall(строка):
        женская = форма.endswith("а")
        if (ЛИЦА[имя] == "f") != женская:
            вон.append((имя, форма, "женское" if ЛИЦА[имя] == "f" else "мужское"))
    return вон


_ВЕРНАЯ = {м + rugram.СУФФИКС_ПРОШЕДШЕГО["f"]: ж for м, ж in rugram.ПРОШЕДШЕЕ_ЖЕНСКОЕ.items()}


def неслова(строка):
    """Несуществующие формы, СТОЯЩИЕ в строке, — а не названные ею.

    СЛОВО, НАЗВАННОЕ РАДИ ОТКАЗА, НЕ ЕСТЬ СЛОВО НАПИСАННОЕ. Дом рода глагола показывает
    исключение отказом с основанием — «верно ли, что нашёл + а = нашёла? нет: нашла», — и
    первая редакция меры насчитала тринадцать таких страниц ложью. Признак: если рядом в той
    же строке стои́т ВЕРНАЯ форма того же глагола, строка о слове ГОВОРИТ, а не пишет его.

        МЕРА, СЧИТАЮЩАЯ УПОМИНАНИЕ УПОТРЕБЛЕНИЕМ, НАКАЗЫВАЕТ ЗА ТО, ЧЕМУ УЧИТ.
    """
    слова = set(re.findall(r"[а-яё]+", строка))
    return [с for с in слова if с in НЕСЛОВА and _ВЕРНАЯ[с] not in слова]


def дома():
    вон = []
    for путь in sorted((КОРЕНЬ / "tools").glob("*.py")):
        if путь.stem.startswith("gen_"):
            continue
        try:
            дом = importlib.import_module(путь.stem)
        except Exception:                       # noqa: BLE001
            continue
        показы, судить = getattr(дом, "ПОКАЗЫ", None), getattr(дом, "судить", None)
        if isinstance(показы, dict) and показы and callable(судить):
            вон.append((путь.stem, дом))
    return вон


def подмена(строка):
    """Строка с ОДНИМ прошедшим, подменённым на форму другого рода, — или None."""
    if ПАРА is None:
        return None
    for м in ПАРА.finditer(строка):
        имя, форма = м.group(1), м.group(2)
        if ЛИЦА[имя] == "f":
            иная = next((м_ for м_, ж in rugram.ПРОШЕДШЕЕ_ЖЕНСКОЕ.items() if ж == форма), None)
            иная = иная or (форма[:-1] if форма.endswith("а") else None)
        else:
            try:
                иная = rugram.прошедшее(форма, "f")
            except KeyError:
                иная = None
        if иная and иная != форма:
            битая = строка[:м.start(2)] + иная + строка[м.end(2):]
            if обвинения(битая):
                return битая
    return None


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--подробно", action="store_true")
    ап.add_argument("--дом", default=None, help="проверить один дом")
    дов = ап.parse_args()
    if not ЛИЦА:
        print("РОД ПРОШЕДШЕГО ОТКАЗ: ни один дом не объявил русских лиц с родом")
        return 2

    # ЭТАЖ ПЕРВЫЙ: страницы свода
    миры = sorted((КОРЕНЬ / "datasets").glob("genesis_*.txt"))
    не_по_роду, нет_слова = collections.Counter(), collections.Counter()
    прим1, прим2, пар = {}, {}, 0
    for мир in миры:
        for строка in мир.read_text(encoding="utf-8", errors="replace").splitlines():
            пар += len(ПАРА.findall(строка))
            for имя, форма, ждём in обвинения(строка):
                не_по_роду[(мир.name, имя, форма)] += 1
                прим1.setdefault((мир.name, имя, форма), (строка[:88], ждём))
            for с in неслова(строка):
                нет_слова[(мир.name, с)] += 1
                прим2.setdefault((мир.name, с), строка[:88])
    print(f"СТРАНИЦЫ: миров {len(миры)}, пар «лицо + прошедшее» {пар}; "
          f"не по роду {sum(не_по_роду.values())}, несуществующих форм {sum(нет_слова.values())}")
    for (мир, имя, форма), n in не_по_роду.most_common():
        строка, ждём = прим1[(мир, имя, форма)]
        print(f"  НЕ ПО РОДУ {мир} «{имя} {форма}» ×{n} (ждём {ждём})\n       «{строка}»")
    for (мир, с), n in нет_слова.most_common():
        print(f"  НЕТ ТАКОГО СЛОВА {мир} «{с}» ×{n}\n       «{прим2[(мир, с)]}»")

    # ЭТАЖ ВТОРОЙ: видит ли суд дома подмену рода
    список = [(и, д) for и, д in дома() if дов.дом is None or и == дов.дом]
    if not список:
        print(f"РОД ПРОШЕДШЕГО ОТКАЗ: домов не найдено{f' ({дов.дом})' if дов.дом else ''}")
        return 2
    слепые, всего_проб, всего_поймано, всего_немых, всего_пропущено = [], 0, 0, 0, 0
    print(f"{'дом':<20}{'проб':>6}{'поймано':>9}{'НЕМЫХ':>7}{'ПРОПУЩЕНО':>11}")
    for имя, дом in список:
        проб = немых = поймано = пропущено = 0
        первая = None
        for показ in дом.ПОКАЗЫ:
            if проб >= ОБРАЗЦОВ:
                break
            битая = подмена(показ)
            if битая is None:
                continue
            try:
                судимо, истинно = дом.судить(битая)[:2]
            except Exception:                   # noqa: BLE001
                continue
            проб += 1
            if not судимо:
                немых += 1
                первая = первая or битая
            elif not истинно:
                поймано += 1
            else:
                пропущено += 1                  # ХУЖЕ НЕМОТЫ: суд НАЗВАЛ порчу истиной
                первая = первая or битая
        if not проб:
            continue
        всего_проб += проб; всего_поймано += поймано
        всего_немых += немых; всего_пропущено += пропущено
        print(f"{имя:<20}{проб:>6}{поймано:>9}{немых if немых else '—':>7}"
              f"{пропущено if пропущено else '—':>11}")
        if немых or пропущено:
            слепые.append((имя, немых, пропущено, проб, первая))
    print(f"{'ИТОГО':<20}{всего_проб:>6}{всего_поймано:>9}{всего_немых:>7}"
          f"{всего_пропущено:>11}")
    for имя, немых, пропущено, проб, первая in слепые:
        как = f"немых {немых}, пропущено {пропущено}"
        print(f"  СЛЕПОЙ [{имя}] {как} из {проб}: «{первая[:96]}»")
    if дов.подробно:
        print(f"  лиц объявлено: {len(ЛИЦА)}; спорных (не судятся): {sorted(СПОРНЫЕ) or '—'}")
        print(f"  исключений закона: {len(rugram.ПРОШЕДШЕЕ_ЖЕНСКОЕ)}")

    плохо = sum(не_по_роду.values())
    поза = "PASS" if (плохо <= НЕ_ПО_РОДУ_РУБЕЖ and sum(нет_слова.values()) <= НЕСЛОВ_РУБЕЖ
                      and len(слепые) <= СЛЕПЫХ_РУБЕЖ) else "FAIL"
    print(f"РОД ПРОШЕДШЕГО {поза}: не по роду {плохо} (рубеж {НЕ_ПО_РОДУ_РУБЕЖ}); "
          f"несуществующих форм {sum(нет_слова.values())} (рубеж {НЕСЛОВ_РУБЕЖ}); "
          f"домов, слепых на подмене рода, {len(слепые)} (рубеж {СЛЕПЫХ_РУБЕЖ}); "
          f"проб {всего_проб}, поймано {всего_поймано}, немых {всего_немых}, "
          f"пропущено {всего_пропущено}")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
