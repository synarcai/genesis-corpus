_ПОРЯДОК_РУ = "|".join(sorted(ЧИСЛИТЕЛЬНЫЕ_РУ, key=len, reverse=True))
ЛОВУШКА_РУ = re.compile(rf"({_ПОРЯДОК_РУ})\s+ЛОВУШКА\s+РЯДА")
# ОДИН МИР МОЖЕТ НЕСТИ ДВЕ ЛОВУШКИ РАЗОМ: «the seventh and eighth traps of the series».
# Первая редакция признака искала «Nth trap of the series» и потеряла обе — ряд показался
# дырявым там, где он цел.
#
#     ПРИЗНАК, ЖДУЩИЙ ОДНОГО, НЕ ВИДИТ ДВУХ, СКАЗАННЫХ ОДНОЙ ФРАЗОЙ.
ЛОВУШКА = re.compile(
    rf"(?<!-)\b({_ПОРЯДОК})\b(?:\s+and\s+({_ПОРЯДОК})\b)?\s+traps?\s+of\s+the\s+series",
    re.I)


def ряд(манифест):
    """{номер: [миры]} — ловушки, названные объявлениями миров показов."""
    тело = json.loads(манифест.read_text(encoding="utf-8"))
    вон = {}
    for з in тело["worlds"]:
        if з.get("text") != "shows":
            continue
        for m in ЛОВУШКА.finditer(з.get("genre") or ""):
            for группа in (m.group(1), m.group(2)):
                if группа:
                    вон.setdefault(ЧИСЛИТЕЛЬНЫЕ[группа.lower()], []).append(з["name"])
    return вон


def дома(корень):
    """{номер: [дома]} — ловушки, названные ЗАГОЛОВКАМИ домов.

        ДОМ, НЕ ЗНАЮЩИЙ СВОЕГО МЕСТА В РЯДУ, УЗНАЁТ О НЁМ ИЗ ЧУЖОГО ОБЪЯВЛЕНИЯ;
        А ЧИТАЮЩИЙ ДОМ МАНИФЕСТА НЕ ЧИТАЕТ.

    Оттого номер стои́т ДВАЖДЫ — в заголовке дома и в объявлении мира, — и два
    объявления одного факта обязаны сойтись.
    """
    import ast
    вон = {}
    двор = корень / "tools"
    if not двор.is_dir():
        return вон
    for п in sorted(двор.glob("*.py")):
        try:
            док = ast.get_docstring(ast.parse(п.read_text(encoding="utf-8"))) or ""
        except (OSError, SyntaxError, ValueError):
            continue
        for m in ЛОВУШКА_РУ.finditer(док):
            вон.setdefault(ЧИСЛИТЕЛЬНЫЕ_РУ[m.group(1)], []).append(п.stem)
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ОБА признака живы.

        ПРИБОР, ЗЕЛЕНЕЮЩИЙ ОТ НУЛЯ НАХОДОК, ОБЯЗАН ДОКАЗАТЬ, ЧТО УМЕЕТ НАХОДИТЬ.

    Ряд ведут ДВА признака — английский в объявлении мира и русский в заголовке дома, —
    и оба обязаны поймать свои строки. Проверяются и составные числительные: «thirty-third»
    обязано прочесться тридцать третьим, а не третьим, — на этом прибор уже спотыкался,
    объявив четыре повтора там, где ряд был цел.
    """
    случаи_ан = (("this is the tenth trap of the series", 10, None),
                 ("the seventh and eighth traps of the series", 7, 8),
                 ("это the thirty-third trap of the series — сложение отношений", 33, None),
                 ("about the series of traps and nothing more", None, None))
    случаи_ру = (("ТРИДЦАТЬ ПЯТАЯ ЛОВУШКА РЯДА — мера, растущая степенью", 35),
                 ("ДЕСЯТАЯ ЛОВУШКА РЯДА — третий род", 10),
                 ("дом без всякого номера в ряду", None))
    беды = []
    for текст, п1, п2 in случаи_ан:
        m = ЛОВУШКА.search(текст)
        было = (ЧИСЛИТЕЛЬНЫЕ.get((m.group(1) or "").lower()) if m else None,
                ЧИСЛИТЕЛЬНЫЕ.get((m.group(2) or "").lower()) if m and m.group(2) else None)
        if было != (п1, п2):
            беды.append(f"английский признак: прочтено {было}, а надо {(п1, п2)} — «{текст[:44]}»")
    for текст, ждём in случаи_ру:
        m = ЛОВУШКА_РУ.search(текст)
        было = ЧИСЛИТЕЛЬНЫЕ_РУ.get(m.group(1)) if m else None
        if было != ждём:
            беды.append(f"русский признак: прочтено {было}, а надо {ждём} — «{текст[:44]}»")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    беды = _проба()
    if беды:
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"РЯД ЛОВУШЕК ОТКАЗ: прибор не доказал, что умеет находить ({len(беды)} бед)")
        return 2
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
        if not манифест.is_file():
            print(f"РЯД ЛОВУШЕК ОТКАЗ: манифеста нет — {манифест}")
            return 2
    найдено = ряд(манифест)
    if not найдено:
        print("РЯД ЛОВУШЕК ОТКАЗ: ни одной ловушки не названо, судить нечего")
        return 2
    высшая = max(найдено)
    пропуски = [n for n in range(1, высшая + 1) if n not in найдено]
    повторы = {n: м for n, м in найдено.items() if len(м) > 1}
    for n in range(1, высшая + 1):
        кто = найдено.get(n)
        метка = ", ".join(кто) if кто else "— НЕ НАЗВАНА"
        print(f"  {n:3}  {метка}")
    for n, м in повторы.items():
        print(f"  ПОВТОР {n}: {м}")
    # ДВА ОБЪЯВЛЕНИЯ ОДНОГО ФАКТА ОБЯЗАНЫ СОЙТИСЬ, ИНАЧЕ ОДНО ИЗ НИХ ЛЖЁТ. Номер ловушки
    # стои́т в заголовке ДОМА (по-русски) и в объявлении МИРА (по-английски); дом, забывший
    # свой номер, не есть беда ряда — но дом, назвавший ЧУЖОЙ номер, есть.
    в_домах = дома(КОРЕНЬ)
    чужие = sorted(n for n in в_домах if n not in найдено)
    безымянные = sorted(n for n in найдено if n not in в_домах)
    for n in чужие:
        print(f"  ДОМ НАЗВАЛ НОМЕР, КОТОРОГО НЕТ В ОБЪЯВЛЕНИЯХ: {n} — {в_домах[n]}")
    поза = ("PASS" if len(повторы) <= ПОВТОРОВ_РУБЕЖ and len(пропуски) <= ПРОПУСКОВ_РУБЕЖ
            and not чужие
            else "FAIL")
    print(f"РЯД ЛОВУШЕК {поза}: названо {len(найдено)} из {высшая}, "
          f"пропусков {len(пропуски)} {пропуски} (рубеж {ПРОПУСКОВ_РУБЕЖ}), "
          f"повторов {len(повторы)} (рубеж {ПОВТОРОВ_РУБЕЖ})"
          f"; в заголовках домов названо {len(в_домах)}, из них с чужим номером {len(чужие)} (рубеж 0), миров без дома с номером {len(безымянные)} — не долг, а граница")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
