import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"

# РУБЕЖ-ДОЛГА: ПОВТОРОВ_РУБЕЖ = 0
ПОВТОРОВ_РУБЕЖ = 0
# РУБЕЖ-ДОЛГА: ПРОПУСКОВ_РУБЕЖ = 0
ПРОПУСКОВ_РУБЕЖ = 0

# ЧИСЛИТЕЛЬНОЕ ЕСТЬ ЗАКОН, А НЕ СПИСОК: СПИСОК КОНЧАЕТСЯ, ЗАКОН — НЕТ.
#
# ДВАЖДЫ ЗА ДЕНЬ ОДНА И ТА ЖЕ ГРАНИЦА. Утром словарь кончался на тридцати, и «thirty-third»
# читалось как «third»: прибор объявил ПОВТОРЫ там, где ряд был цел. Словарь продлили до
# сорока — и вечером, на сорок первой ловушке, он ослеп ВТОРОЙ РАЗ, но уже ИНАЧЕ и хуже:
# «forty-first» не прочлось никак, и прибор сказал «названо 40 из 40», не заметив двух
# новых домов.
#
#     ГРАНИЦА, ОТОДВИНУТАЯ НА ШАГ, ЕСТЬ ТА ЖЕ ГРАНИЦА. Прибор, читающий число по списку
#     имён, слепнет ровно там, где список кончается, — и молчит об этом, ибо
#     непрочитанное для него не существует.
#
# Потому ныне числительные СТРОЯТСЯ: единицы и десятки объявлены, составное складывается
# из них по правилу обоих языков. Ряд может идти до девяноста девяти, и словарь за ним
# поспеет сам.
_ЕДИНИЦЫ = ("first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth",
            "ninth", "tenth", "eleventh", "twelfth", "thirteenth", "fourteenth", "fifteenth",
            "sixteenth", "seventeenth", "eighteenth", "nineteenth")
_ДЕСЯТКИ = {20: ("twentieth", "twenty"), 30: ("thirtieth", "thirty"),
            40: ("fortieth", "forty"), 50: ("fiftieth", "fifty"),
            60: ("sixtieth", "sixty"), 70: ("seventieth", "seventy"),
            80: ("eightieth", "eighty"), 90: ("ninetieth", "ninety")}
ЧИСЛИТЕЛЬНЫЕ = {имя: n for n, имя in enumerate(_ЕДИНИЦЫ, 1)}
for _д, (_круглое, _начало) in _ДЕСЯТКИ.items():
    ЧИСЛИТЕЛЬНЫЕ[_круглое] = _д
    for _e, _имя in enumerate(_ЕДИНИЦЫ[:9], 1):
        ЧИСЛИТЕЛЬНЫЕ[f"{_начало}-{_имя}"] = _д + _e

_ПОРЯДОК = "|".join(sorted(ЧИСЛИТЕЛЬНЫЕ, key=len, reverse=True))

# РУССКИЕ ЧИСЛИТЕЛЬНЫЕ — ДЛЯ ЗАГОЛОВКОВ ДОМОВ. Объявление мира пишется по-английски
# («the tenth trap of the series»), заголовок дома — по-русски («ДЕСЯТАЯ ЛОВУШКА РЯДА»),
# и оба говорят об одном.
_ЕДИНИЦЫ_РУ = ("ПЕРВАЯ", "ВТОРАЯ", "ТРЕТЬЯ", "ЧЕТВЁРТАЯ", "ПЯТАЯ", "ШЕСТАЯ", "СЕДЬМАЯ",
               "ВОСЬМАЯ", "ДЕВЯТАЯ", "ДЕСЯТАЯ", "ОДИННАДЦАТАЯ", "ДВЕНАДЦАТАЯ",
               "ТРИНАДЦАТАЯ", "ЧЕТЫРНАДЦАТАЯ", "ПЯТНАДЦАТАЯ", "ШЕСТНАДЦАТАЯ",
               "СЕМНАДЦАТАЯ", "ВОСЕМНАДЦАТАЯ", "ДЕВЯТНАДЦАТАЯ")
_ДЕСЯТКИ_РУ = {20: ("ДВАДЦАТАЯ", "ДВАДЦАТЬ"), 30: ("ТРИДЦАТАЯ", "ТРИДЦАТЬ"),
               40: ("СОРОКОВАЯ", "СОРОК"), 50: ("ПЯТИДЕСЯТАЯ", "ПЯТЬДЕСЯТ"),
               60: ("ШЕСТИДЕСЯТАЯ", "ШЕСТЬДЕСЯТ"), 70: ("СЕМИДЕСЯТАЯ", "СЕМЬДЕСЯТ"),
               80: ("ВОСЬМИДЕСЯТАЯ", "ВОСЕМЬДЕСЯТ"), 90: ("ДЕВЯНОСТАЯ", "ДЕВЯНОСТО")}
ЧИСЛИТЕЛЬНЫЕ_РУ = {имя: n for n, имя in enumerate(_ЕДИНИЦЫ_РУ, 1)}
for _д, (_круглое, _начало) in _ДЕСЯТКИ_РУ.items():
    ЧИСЛИТЕЛЬНЫЕ_РУ[_круглое] = _д
    for _e, _имя in enumerate(_ЕДИНИЦЫ_РУ[:9], 1):
        ЧИСЛИТЕЛЬНЫЕ_РУ[f"{_начало} {_имя}"] = _д + _e

_ПОРЯДОК_РУ = "|".join(sorted(ЧИСЛИТЕЛЬНЫЕ_РУ, key=len, reverse=True))
ЛОВУШКА_РУ = re.compile(rf"({_ПОРЯДОК_РУ})\s+ЛОВУШКА\s+РЯДА")
# ОДИН МИР МОЖЕТ НЕСТИ ДВЕ ЛОВУШКИ РАЗОМ: «the seventh and eighth traps of the series».
# Первая редакция признака искала «Nth trap of the series» и потеряла обе — ряд показался
# дырявым там, где он цел.
#
#     ПРИЗНАК, ЖДУЩИЙ ОДНОГО, НЕ ВИДИТ ДВУХ, СКАЗАННЫХ ОДНОЙ ФРАЗОЙ.
ЛОВУШКА = re.compile(
    rf"(?<!-)\b({_ПОРЯДОК})\b(?:\s+and\s+({_ПОРЯДОК})\b)?\s+traps?\s+of\s+the\s+series",
    re.I)


# СТРАХОВКА ОТ ГРАНИЦЫ СЛОВАРЯ: объявление ловушки БЕЗ ЧТЕНИЯ ЧИСЛА. Числительное ныне
# строится законом и до девяноста девяти не кончится, — но прибор, чьё молчание однажды
# уже означало слепоту, обязан уметь сказать «здесь объявлена ловушка, а номер я не
# прочёл», а не пропускать её.
#
#     ПРИБОР, НЕ УМЕЮЩИЙ НАЗВАТЬ НЕПРОЧИТАННОЕ, ОБЪЯВЛЯЕТ ЕГО НЕСУЩЕСТВУЮЩИМ.
# СЛОВО ПЕРЕД «ЛОВУШКОЙ РЯДА» БЕРЁТСЯ ВСЯКОЕ, А СУДИТСЯ ЛИШЬ ПОРЯДКОВОЕ ПО ВИДУ. Первая
# редакция страховки считала всякое упоминание «trap of the series» объявлением номера — и
# обвинила мир `numlabel` за честную речь: «Every EARLIER trap of the series».
#
#     НЕ ВСЯКОЕ УПОМИНАНИЕ ЕСТЬ ОБЪЯВЛЕНИЕ. Страховка, не различающая речи от объявления,
#     кричит там, где надо молчать, — и её снимут прежде, чем она пригодится.
ПЕРЕД_ЛОВУШКОЙ = re.compile(r"\b([a-z]+(?:-[a-z]+)?)\s+traps?\s+of\s+the\s+series", re.I)
ПЕРЕД_ЛОВУШКОЙ_РУ = re.compile(r"([А-ЯЁ]+(?:\s+[А-ЯЁ]+)?)\s+ЛОВУШКА\s+РЯДА")
_ВИД_ОРДИНАЛА = re.compile(r"(?:th|first|second|third)$", re.I)
_ВИД_ОРДИНАЛА_РУ = re.compile(r"(?:АЯ|ЯЯ)$")
# РУБЕЖ-ДОЛГА: НЕПРОЧИТАННЫХ_РУБЕЖ = 0
НЕПРОЧИТАННЫХ_РУБЕЖ = 0


def непрочитанные(манифест, корень):
    """[(где, что)] — объявления ловушки, чьё числительное ПО ВИДУ порядковое, а признак
    его не взял: словарь кончился раньше ряда.

        ПРИБОР, НЕ УМЕЮЩИЙ НАЗВАТЬ НЕПРОЧИТАННОЕ, ОБЪЯВЛЯЕТ ЕГО НЕСУЩЕСТВУЮЩИМ.
    """
    import ast
    вон = []
    тело = json.loads(манифест.read_text(encoding="utf-8"))
    for з in тело["worlds"]:
        if з.get("text") != "shows":
            continue
        for m in ПЕРЕД_ЛОВУШКОЙ.finditer(з.get("genre") or ""):
            слово = m.group(1).lower()
            if _ВИД_ОРДИНАЛА.search(слово) and слово not in ЧИСЛИТЕЛЬНЫЕ:
                вон.append((з["name"], f"объявление мира: «{m.group(1)}» — словарь не знает"))
    двор = корень / "tools"
    for п in sorted(двор.glob("*.py")) if двор.is_dir() else ():
        try:
            док = ast.get_docstring(ast.parse(п.read_text(encoding="utf-8"))) or ""
        except (OSError, SyntaxError, ValueError):
            continue
        for m in ПЕРЕД_ЛОВУШКОЙ_РУ.finditer(док):
            слово = m.group(1)
            if _ВИД_ОРДИНАЛА_РУ.search(слово) and слово not in ЧИСЛИТЕЛЬНЫЕ_РУ:
                хвост = слово.split()[-1]
                if хвост in ЧИСЛИТЕЛЬНЫЕ_РУ and слово != хвост:
                    continue        # «ДЕСЯТАЯ» внутри «ВОСЕМЬДЕСЯТ ДЕСЯТАЯ» не бывает
                вон.append((п.stem, f"заголовок дома: «{слово}» — словарь не знает"))
    return вон


def ряд(манифест):
    """{номер: [миры]} — ловушки, названные объявлениями миров показов."""
    тело = json.loads(манифест.read_text(encoding="utf-8"))
    вон = {}
    for з in тело["worlds"]:
        if з.get("text") != "shows":
            continue
        for m in ЛОВУШКА.finditer(з.get("genre") or ""):
            for группа in (m.group(1), m.group(2)):
                if группа:
                    вон.setdefault(ЧИСЛИТЕЛЬНЫЕ[группа.lower()], []).append(з["name"])
    return вон


def дома(корень):
    """{номер: [дома]} — ловушки, названные ЗАГОЛОВКАМИ домов.

        ДОМ, НЕ ЗНАЮЩИЙ СВОЕГО МЕСТА В РЯДУ, УЗНАЁТ О НЁМ ИЗ ЧУЖОГО ОБЪЯВЛЕНИЯ;
        А ЧИТАЮЩИЙ ДОМ МАНИФЕСТА НЕ ЧИТАЕТ.

    Оттого номер стои́т ДВАЖДЫ — в заголовке дома и в объявлении мира, — и два
    объявления одного факта обязаны сойтись.
    """
    import ast
    вон = {}
    двор = корень / "tools"
    if not двор.is_dir():
        return вон
    for п in sorted(двор.glob("*.py")):
        try:
            док = ast.get_docstring(ast.parse(п.read_text(encoding="utf-8"))) or ""
        except (OSError, SyntaxError, ValueError):
            continue
        for m in ЛОВУШКА_РУ.finditer(док):
            вон.setdefault(ЧИСЛИТЕЛЬНЫЕ_РУ[m.group(1)], []).append(п.stem)
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что ОБА признака живы.

        ПРИБОР, ЗЕЛЕНЕЮЩИЙ ОТ НУЛЯ НАХОДОК, ОБЯЗАН ДОКАЗАТЬ, ЧТО УМЕЕТ НАХОДИТЬ.

    Ряд ведут ДВА признака — английский в объявлении мира и русский в заголовке дома, —
    и оба обязаны поймать свои строки. Проверяются и составные числительные: «thirty-third»
    обязано прочесться тридцать третьим, а не третьим, — на этом прибор уже спотыкался,
    объявив четыре повтора там, где ряд был цел.
    """
    случаи_ан = (("this is the tenth trap of the series", 10, None),
                 ("the seventh and eighth traps of the series", 7, 8),
                 ("это the thirty-third trap of the series — сложение отношений", 33, None),
                 ("about the series of traps and nothing more", None, None))
    случаи_ру = (("ТРИДЦАТЬ ПЯТАЯ ЛОВУШКА РЯДА — мера, растущая степенью", 35),
                 ("ДЕСЯТАЯ ЛОВУШКА РЯДА — третий род", 10),
                 ("дом без всякого номера в ряду", None))
    беды = []
    for текст, п1, п2 in случаи_ан:
        m = ЛОВУШКА.search(текст)
        было = (ЧИСЛИТЕЛЬНЫЕ.get((m.group(1) or "").lower()) if m else None,
                ЧИСЛИТЕЛЬНЫЕ.get((m.group(2) or "").lower()) if m and m.group(2) else None)
        if было != (п1, п2):
            беды.append(f"английский признак: прочтено {было}, а надо {(п1, п2)} — «{текст[:44]}»")
    for текст, ждём in случаи_ру:
        m = ЛОВУШКА_РУ.search(текст)
        было = ЧИСЛИТЕЛЬНЫЕ_РУ.get(m.group(1)) if m else None
        if было != ждём:
            беды.append(f"русский признак: прочтено {было}, а надо {ждём} — «{текст[:44]}»")
    return беды


def _проба_страховки():
    """ПРОБА СТРАХОВКИ: непрочитанное обязано кричать, а речь — молчать.

    ЗАКОН, КУПЛЕННЫЙ ДВАЖДЫ ЗА ОДИН ДЕНЬ: граница словаря, отодвинутая на шаг, есть та же
    граница. Проба держит слово ЗА пределом закона («hundredth» — закон идёт до 99) и
    честную речь, которую хватать нельзя.
    """
    беды = []
    случаи = (("the hundredth trap of the series", True, "за пределом закона — кричать"),
              ("Every earlier trap of the series", False, "речь, а не объявление"),
              ("the forty-second trap of the series", False, "закон знает — молчать"),
              ("the ninety-ninth trap of the series", False, "край закона — молчать"))
    for текст, ждём, что in случаи:
        m = ПЕРЕД_ЛОВУШКОЙ.search(текст)
        слово = m.group(1).lower() if m else ""
        кричит = bool(m) and bool(_ВИД_ОРДИНАЛА.search(слово)) and слово not in ЧИСЛИТЕЛЬНЫЕ
        if кричит != ждём:
            беды.append(f"{что}: «{текст}» → {кричит}, а надо {ждём}")
    ру = (("СОТАЯ ЛОВУШКА РЯДА", True, "русское за пределом"),
          ("СОРОК ВТОРАЯ ЛОВУШКА РЯДА", False, "русское в законе"))
    for текст, ждём, что in ру:
        m = ПЕРЕД_ЛОВУШКОЙ_РУ.search(текст)
        слово = m.group(1) if m else ""
        кричит = bool(m) and bool(_ВИД_ОРДИНАЛА_РУ.search(слово)) and слово not in ЧИСЛИТЕЛЬНЫЕ_РУ
        if кричит != ждём:
            беды.append(f"{что}: «{текст}» → {кричит}, а надо {ждём}")
    # И САМ ЗАКОН ЧИСЛИТЕЛЬНОГО: составное обязано складываться, а не искаться в списке.
    для = (("forty-first", 41), ("ninety-ninth", 99), ("fortieth", 40), ("twelfth", 12))
    for имя, n in для:
        if ЧИСЛИТЕЛЬНЫЕ.get(имя) != n:
            беды.append(f"числительное «{имя}»: {ЧИСЛИТЕЛЬНЫЕ.get(имя)} вместо {n}")
    для_ру = (("СОРОК ПЕРВАЯ", 41), ("ДЕВЯНОСТО ДЕВЯТАЯ", 99), ("СОРОКОВАЯ", 40))
    for имя, n in для_ру:
        if ЧИСЛИТЕЛЬНЫЕ_РУ.get(имя) != n:
            беды.append(f"числительное «{имя}»: {ЧИСЛИТЕЛЬНЫЕ_РУ.get(имя)} вместо {n}")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    беды = _проба() + _проба_страховки()
    if беды:
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"РЯД ЛОВУШЕК ОТКАЗ: прибор не доказал, что умеет находить ({len(беды)} бед)")
        return 2
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
        if not манифест.is_file():
            print(f"РЯД ЛОВУШЕК ОТКАЗ: манифеста нет — {манифест}")
            return 2
    найдено = ряд(манифест)
    if not найдено:
        print("РЯД ЛОВУШЕК ОТКАЗ: ни одной ловушки не названо, судить нечего")
        return 2
    высшая = max(найдено)
    пропуски = [n for n in range(1, высшая + 1) if n not in найдено]
    повторы = {n: м for n, м in найдено.items() if len(м) > 1}
    for n in range(1, высшая + 1):
        кто = найдено.get(n)
        метка = ", ".join(кто) if кто else "— НЕ НАЗВАНА"
        print(f"  {n:3}  {метка}")
    for n, м in повторы.items():
        print(f"  ПОВТОР {n}: {м}")
    # ДВА ОБЪЯВЛЕНИЯ ОДНОГО ФАКТА ОБЯЗАНЫ СОЙТИСЬ, ИНАЧЕ ОДНО ИЗ НИХ ЛЖЁТ. Номер ловушки
    # стои́т в заголовке ДОМА (по-русски) и в объявлении МИРА (по-английски); дом, забывший
    # свой номер, не есть беда ряда — но дом, назвавший ЧУЖОЙ номер, есть.
    в_домах = дома(КОРЕНЬ)
    чужие = sorted(n for n in в_домах if n not in найдено)
    безымянные = sorted(n for n in найдено if n not in в_домах)
    for n in чужие:
        print(f"  ДОМ НАЗВАЛ НОМЕР, КОТОРОГО НЕТ В ОБЪЯВЛЕНИЯХ: {n} — {в_домах[n]}")
    немые = непрочитанные(манифест, КОРЕНЬ)
    for где, что in немые[:6]:
        print(f"  НОМЕР НЕ ПРОЧТЁН [{где}]: {что}")
    поза = ("PASS" if len(повторы) <= ПОВТОРОВ_РУБЕЖ and len(пропуски) <= ПРОПУСКОВ_РУБЕЖ
            and not чужие and len(немые) <= НЕПРОЧИТАННЫХ_РУБЕЖ
            else "FAIL")
    print(f"РЯД ЛОВУШЕК {поза}: названо {len(найдено)} из {высшая}, "
          f"пропусков {len(пропуски)} {пропуски} (рубеж {ПРОПУСКОВ_РУБЕЖ}), "
          f"НОМЕР НЕ ПРОЧТЁН {len(немые)} (рубеж {НЕПРОЧИТАННЫХ_РУБЕЖ}), "
          f"повторов {len(повторы)} (рубеж {ПОВТОРОВ_РУБЕЖ})"
          f"; в заголовках домов названо {len(в_домах)}, из них с чужим номером {len(чужие)} (рубеж 0), миров без дома с номером {len(безымянные)} — не долг, а граница")
    return 0 if поза == "PASS" else 1


