#!/usr/bin/env python3
"""[РЯД ЛОВУШЕК] — ловушки свода пронумерованы, и ряд обязан быть без дыр и без повторов.

Свод учит не только верному, но и тому, ГДЕ ЧИТАТЕЛЬ ОШИБЁТСЯ, и такие места он называет
ЛОВУШКАМИ РЯДА: «двадцать восьмая ловушка ряда», «седьмая и восьмая ловушки ряда, обе ждут
у нуля». Номер есть обещание: назвав двадцать восьмую, свод обещает двадцать семь прежних.

    РЯД С ДЫРОЙ ЕСТЬ НЕ РЯД, А СПИСОК: ловушка, объявленная третьей, обещает первую и вторую,
    которых читатель не найдёт.

    НОМЕР, ПОВТОРЁННЫЙ ДВАЖДЫ, ХУЖЕ ПРОПУСКА: пропуск виден, а повтор читается как одна
    ловушка, и вторая пропадает молча.

ЗАМЕР 12.09 ПО 257 МИРАМ ПОКАЗОВ: названо было двадцать шесть ловушек (мир степеней несёт
СЕДЬМУЮ И ВОСЬМУЮ разом), повторов нет, а ряд НАЧИНАЛСЯ С ТРЕТЬЕЙ: первая и вторая не были
названы нигде.

    ПОРЯДОК, ЗАВЕДЁННЫЙ ПОСРЕДИ ДЕЛА, НЕ ОХВАТЫВАЕТ СДЕЛАННОГО ДО НЕГО.

ДОЛГ УПЛАЧЕН В ТОТ ЖЕ ЧАС, И НОМЕРА ВЫВЕДЕНЫ, А НЕ НАЗНАЧЕНЫ. Ряд получил имя лишь у третьей
ловушки (`divshare`, выкован в 03:21 одиннадцатого сентября), и две прежние ходили без номера
сутки. Порядок их прочтён по записи самого свода: `cmpshare` выкован в 02:28, `mulshare` в 02:52,
оба прежде наименования, — и третий дом прямо называет второй своим основанием («дом умножения
долей показал, что умножение на долю УМЕНЬШАЕТ; обратного хода не показано вовсе»).

    НУМЕРАЦИЯ, НАЧАТАЯ ПОСРЕДИ РАБОТЫ, ЛЕЧИТСЯ ЗАПИСЬЮ, А НЕ ДОГАДКОЙ: порядок появления
    написан в истории и нуждается лишь в прочтении.

Ныне ряд сомкнут: двадцать восемь из двадцати восьми, пропусков ноль, повторов ноль.

ЧТО СУДИТСЯ: повторов ноль (рубеж 0) и пропусков не больше объявленного. Прибор печатает весь
ряд поимённо, чтобы читатель видел его целиком — этого не даёт ни манифест, ни указатель миров.

ГРАНИЦА НАЗВАНА: прибор читает ОБЪЯВЛЕНИЯ, а не страницы. Ловушка, показанная миром и не
названная в его жанре, для него не существует — и это верно: неназванной ловушки читатель
не найдёт, как бы хорошо она ни была показана.

    python3 scripts/trap_series.py
"""
# ПУСТОЙ-ОБХОД: --манифест no-such-manifest
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"

# РУБЕЖ-ДОЛГА: ПОВТОРОВ_РУБЕЖ = 0
ПОВТОРОВ_РУБЕЖ = 0
# РУБЕЖ-ДОЛГА: ПРОПУСКОВ_РУБЕЖ = 0
ПРОПУСКОВ_РУБЕЖ = 0

ЧИСЛИТЕЛЬНЫЕ = {
    "first": 1, "second": 2, "third": 3, "fourth": 4, "fifth": 5, "sixth": 6, "seventh": 7,
    "eighth": 8, "ninth": 9, "tenth": 10, "eleventh": 11, "twelfth": 12, "thirteenth": 13,
    "fourteenth": 14, "fifteenth": 15, "sixteenth": 16, "seventeenth": 17, "eighteenth": 18,
    "nineteenth": 19, "twentieth": 20, "twenty-first": 21, "twenty-second": 22,
    "twenty-third": 23, "twenty-fourth": 24, "twenty-fifth": 25, "twenty-sixth": 26,
    "twenty-seventh": 27, "twenty-eighth": 28, "twenty-ninth": 29, "thirtieth": 30,
}
_ПОРЯДОК = "|".join(sorted(ЧИСЛИТЕЛЬНЫЕ, key=len, reverse=True))
# ОДИН МИР МОЖЕТ НЕСТИ ДВЕ ЛОВУШКИ РАЗОМ: «the seventh and eighth traps of the series».
# Первая редакция признака искала «Nth trap of the series» и потеряла обе — ряд показался
# дырявым там, где он цел.
#
#     ПРИЗНАК, ЖДУЩИЙ ОДНОГО, НЕ ВИДИТ ДВУХ, СКАЗАННЫХ ОДНОЙ ФРАЗОЙ.
ЛОВУШКА = re.compile(
    rf"\b({_ПОРЯДОК})\b(?:\s+and\s+({_ПОРЯДОК})\b)?\s+traps?\s+of\s+the\s+series", re.I)


def ряд(манифест):
    """{номер: [миры]} — ловушки, названные объявлениями миров показов."""
    тело = json.loads(манифест.read_text(encoding="utf-8"))
    вон = {}
    for з in тело["worlds"]:
        if з.get("text") != "shows":
            continue
        for m in ЛОВУШКА.finditer(з.get("genre") or ""):
            for группа in (m.group(1), m.group(2)):
                if группа:
                    вон.setdefault(ЧИСЛИТЕЛЬНЫЕ[группа.lower()], []).append(з["name"])
    return вон


def main():
    манифест = МАНИФЕСТ
    if "--манифест" in sys.argv:
        манифест = pathlib.Path(sys.argv[sys.argv.index("--манифест") + 1])
        if not манифест.is_file():
            print(f"РЯД ЛОВУШЕК ОТКАЗ: манифеста нет — {манифест}")
            return 2
    найдено = ряд(манифест)
    if not найдено:
        print("РЯД ЛОВУШЕК ОТКАЗ: ни одной ловушки не названо, судить нечего")
        return 2
    высшая = max(найдено)
    пропуски = [n for n in range(1, высшая + 1) if n not in найдено]
    повторы = {n: м for n, м in найдено.items() if len(м) > 1}
    for n in range(1, высшая + 1):
        кто = найдено.get(n)
        метка = ", ".join(кто) if кто else "— НЕ НАЗВАНА"
        print(f"  {n:3}  {метка}")
    for n, м in повторы.items():
        print(f"  ПОВТОР {n}: {м}")
    поза = ("PASS" if len(повторы) <= ПОВТОРОВ_РУБЕЖ and len(пропуски) <= ПРОПУСКОВ_РУБЕЖ
            else "FAIL")
    print(f"РЯД ЛОВУШЕК {поза}: названо {len(найдено)} из {высшая}, "
          f"пропусков {len(пропуски)} {пропуски} (рубеж {ПРОПУСКОВ_РУБЕЖ}), "
          f"повторов {len(повторы)} (рубеж {ПОВТОРОВ_РУБЕЖ})")
    return 0 if поза == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
