# Оттого признак требует, чтобы слева от числительного не стояло дефиса.
_ПОРЯДОК = "|".join(sorted(ЧИСЛИТЕЛЬНЫЕ, key=len, reverse=True))

# РУССКИЕ ЧИСЛИТЕЛЬНЫЕ — ДЛЯ ЗАГОЛОВКОВ ДОМОВ. Объявление мира пишется по-английски
