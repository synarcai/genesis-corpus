#!/usr/bin/env python3
"""[РОДЫ] — прочёл ли строку ТОТ, чьему роду принадлежит её утверждение.

Охват спрашивает «читает ли строку хоть кто-нибудь» и на этом
успокаивается. Но строка, говорящая ДВЕ вещи, может быть прочитана
судом, знающим ОДНУ, — и тогда сто процентов охвата скрывают ложь.
Так и вышло: русская рамка «вера написала 3 книги… всего 9 книг» была
судима судом согласования (формы верны) и ложна по числу.

ПРИБОР СПРАШИВАЕТ ИНАЧЕ: для КАЖДОГО рода, чей признак виден в строке,
хоть один ХОЗЯИН этого рода обязан был её прочесть. Роды и хозяева
объявлены в `tools/genera.py` — не выведены из кода.

ЧТО ЭТО НЕ ЗНАЧИТ: прибор не утверждает, что перечислены ВСЕ роды
утверждений. Такого списка нет ни у кого. Он ловит те, чьи признаки
механически видны, и его молчание о прочих есть граница, а не полнота.
"""
import collections
import concurrent.futures
import os
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from genera import РОДЫ  # noqa: E402
from genesis import Unreadable, worlds  # noqa: E402
import panel  # noqa: E402
from panel import палата  # noqa: E402

# РУБЕЖ-ДОЛГА: СИРОТ_РУБЕЖ = 0
СИРОТ_РУБЕЖ = 0

# ПУСТОЙ-ОБХОД: --manifest no-such-manifest


_ПАЛАТА_РАБОЧЕГО = None
_ОБРАЗЦЫ = None


def _снасть(имена):
    """Палата и образцы родов — по одному набору на процесс.

    СУЖЕНИЕ ОБЪЯВЛЕНО ЗАДАЧЕЙ, А НЕ УНАСЛЕДОВАНО: рабочий строит своё сам
    (spawn на этой машине), и если бы он не знал о доводе `--род`, он мерил
    бы ВЕСЬ свод родов и вернул чужие числа.
    """
    global _ПАЛАТА_РАБОЧЕГО, _ОБРАЗЦЫ
    if _ПАЛАТА_РАБОЧЕГО is None:
        _ПАЛАТА_РАБОЧЕГО = палата()
        свод = [р for р in РОДЫ if not имена or р.имя in имена]
        _ОБРАЗЦЫ = [(р, re.compile(р.признак, re.I)) for р in свод]
    return _ПАЛАТА_РАБОЧЕГО, _ОБРАЗЦЫ


def _живые_с_хвостом(путь):
    """Непустые строки С ХВОСТОВЫМ ПЕРЕВОДОМ — ровно как их читал прежний обход.

    ХВОСТ СТРОКИ ЕСТЬ ЧАСТЬ СТРОКИ, ПОКА СУД НЕ СКАЗАЛ ИНОГО. Прочие приборы
    свода снимают «\n» (`panel._живые_строки`), а этот не снимал никогда — и
    менять это заодно с раздачей значило бы смешать две правки в одной и не
    знать потом, которая сдвинула вердикт.
    """
    вон = []
    with pathlib.Path(путь).open(encoding="utf-8", errors="replace") as поток:
        for с in поток:
            if с.strip():
                вон.append(с)
    return вон


def _судить_ломоть(задача):
    """Один ЛОМОТЬ мира: (имя, начало, всего, сирот, по_мирам, примеры).

    ЛОМОТЬ, А НЕ МИР. Прибор ходил весь свод В ОДИН ПОТОК — тридцать две минуты
    на набор, четвёртый по цене. Слои строятся по ЦЕЛОМУ файлу в каждом ломте,
    судятся строки [начало, конец).

        САМАЯ ДЛИННАЯ ЗАДАЧА ЕСТЬ ДНО СРОКА.
    """
    путь, начало, конец, имена = задача
    путь = pathlib.Path(путь)
    суд, образцы = _снасть(имена)
    слои = суд.слои(путь)
    строки = _живые_с_хвостом(путь)
    сирот = всего = 0
    по_мирам = collections.Counter()
    примеры = []
    for строка in строки[начало:конец]:
        видны = [р for р, о in образцы if о.search(строка)]
        if not видны:
            continue
        всего += 1
        _, _, кем = суд.судить(строка, слои)
        for род in видны:
            if not (род.хозяева & set(кем)):
                сирот += 1
                по_мирам[(путь.name, род.имя, tuple(кем))] += 1
                if len(примеры) < 4:
                    примеры.append(
                        f"{путь.name} [{род.имя}] "
                        f"{строка.strip()[:70]} — читали {кем}")
                break
    return путь.name, начало, всего, сирот, по_мирам, примеры


def обход():
    if "--manifest" in sys.argv:
        import genesis
        genesis.MANIFEST = pathlib.Path(
            sys.argv[sys.argv.index("--manifest") + 1])
    try:
        return [п for п in worlds(kind="shows") if п.is_file()]
    except Unreadable as беда:
        print(f"РОДЫ ОТКАЗ: {беда}")
        sys.exit(2)


def выбранные():
    """Роды, названные доводом `--род`, или весь свод.

    МЕРИТЬ ОДИН РОД — НЕ ПОБЛАЖКА, А НУЖДА СТЕНДА: прибор есть
    МЕТА-прибор над всей палатой, и честный близнец, требующий живой
    палаты, судил бы полноту дерева, а не прибор. Один названный род
    отделяет вопрос прибора от вопроса окружения. Тем же пользуются в
    работе, закрывая один род.
    """
    имена = [sys.argv[i + 1] for i, а in enumerate(sys.argv)
             if а == "--род" and i + 1 < len(sys.argv)]
    if not имена:
        return РОДЫ
    выбор = [р for р in РОДЫ if р.имя in имена]
    if not выбор:
        print(f"РОДЫ ОТКАЗ: род {имена} не объявлен в своде")
        sys.exit(2)
    return выбор


def main():
    пути = обход()
    if not пути:
        print("РОДЫ ОТКАЗ: обход пуст, мерить нечего")
        return 2
    суд = палата()
    свод = выбранные()
    сирот, всего = 0, 0
    примеры = []
    # ПО МИРАМ И РОДАМ: четыре примера не говорят, где долг; счёт по (мир,
    # род) говорит, какой суд не читает свой род и в каком мире.
    по_мирам = collections.Counter()
    # ЛОМТИ, ДЛИННЫМИ ВПЕРЁД. Прибор ходил ВЕСЬ СВОД В ОДИН ПОТОК — тридцать две
    # минуты на набор, четвёртый по цене. Ныне список задач плоский,
    # режется общим законом палаты по замеренной цене и раздаётся длинными вперёд.
    имена = tuple(р.имя for р in свод) if len(свод) != len(РОДЫ) else ()
    jobs = panel._джобы()
    ломти = panel.ломти(пути, panel.ЦЕЛЬ_ЛОМТЯ if jobs > 1 else 0)
    порядок = {п_.name: i for i, п_ in enumerate(пути)}
    задачи = [(str(п_), a, b, имена) for п_, a, b, _ц in ломти]
    if jobs <= 1:
        итоги = [_судить_ломоть(з) for з in задачи]
    else:
        # СТОРОЖ РОДИТЕЛЯ: рабочий, переживший убитый набор, есть память,
        # которую никто не освободит (79 таких сирот на 5.9 ГБ, замер 12.09).
        with concurrent.futures.ProcessPoolExecutor(
                max_workers=jobs, initializer=panel._сторожить_родителя,
                initargs=(os.getpid(),)) as пул:
            итоги = list(пул.map(_судить_ломоть, задачи))
    # СБОРКА В ПОРЯДКЕ ОБХОДА И СТРОК: вердикт обязан читаться так же,
    # как читался бы в один поток.
    итоги.sort(key=lambda и: (порядок.get(и[0], 10**9), и[1]))
    for _имя, _нач, своё_всего, свои_сирот, своё_по_мирам, свои_примеры in итоги:
        всего += своё_всего
        сирот += свои_сирот
        по_мирам.update(своё_по_мирам)
        for п_ in свои_примеры:
            if len(примеры) < 4:
                примеры.append(п_)
    for п in примеры:
        print(f"  {п}")
    for (мир, род, кем), n in по_мирам.most_common(10):
        print(f"  ПО МИРАМ {мир} [{род}] {n} строк — читали {list(кем)}")
    поза = "PASS" if сирот <= СИРОТ_РУБЕЖ else "FAIL"
    print(f"РОДЫ {поза}: {сирот} строк прочтены НЕ ХОЗЯИНОМ рода "
          f"из {всего} с видимым родом (рубеж {СИРОТ_РУБЕЖ}, "
          f"{len(пути)} файлов, родов объявлено {len(свод)})")
    return 0 if сирот <= СИРОТ_РУБЕЖ else 1


if __name__ == "__main__":
    sys.exit(main())
