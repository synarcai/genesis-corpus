#!/usr/bin/env python3
"""КОВКА ДОМА НЕОБХОДИМОГО И ДОСТАТОЧНОГО.

ДВА НАПРАВЛЕНИЯ ИДУТ В ОДНОМ ПРОХОДЕ: «чтобы делиться на 2, довольно делиться на 4» и «чтобы
делиться на 4, необходимо делиться на 2» суть минимальная пара ПО НАПРАВЛЕНИЮ — те же два
делителя, тот же свидетель, и разница в одном: какой делитель стои́т в условии, а какой в выводе.
Порознь читатель выведет, что «довольно» и «необходимо» суть одно слово, сказанное дважды.

ДВА ОТРИЦАНИЯ И ДВЕ РАВНОСИЛЬНОСТИ ИДУТ СВОЕЙ ГРУППОЙ: первый род говорит, что условие не даёт
ни того ни другого, второй — что даёт и то и другое. Без пары читатель решит, что клеток три.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import nesufforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_nesuf.txt"
ГРУППЫ = (("довольно", "необходимо"), ("ни то ни другое", "и то и другое"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
