#!/usr/bin/env python3
"""НАЧЕРТАНИЯ ОДНОГО ЗНАКА: дом пар и их канона.

ОДИН ЗНАК, ДВА НАЧЕРТАНИЯ — ОБА ЖИВУТ, ИЛИ ОРГАНИЗМ ЗНАЕТ ОДНО.

ЗАМЕР, ВСКРЫВШИЙ БЕДУ (по своду в 194 392 строки):

    'x^2'  1702    'x²'      0
    'sqrt' 2091    '√'       6
    '->'   4238    '→'     328
    '<='      0    '≤'     351
    '>='      0    '≥'      43
    '!='      0    '≠'      56

Корпус знает КАЖДЫЙ ЗНАК ТОЛЬКО В ОДНОМ НАЧЕРТАНИИ, и в разных знаках
— в РАЗНЫХ. Организм увидит «≤» и не узнает «<=»; увидит «x^2» и не
узнает «x²». Это не пробел ПРЕДМЕТА — квадратные уравнения показаны
сотнями, — это НЕДОСТАЮЩАЯ ЗАПИСЬ уже показанного, и оттого она
дешевле любого нового мира и опаснее: беда невидима мере предметов.

НАШЛА ЕЁ ПОЛОСА, А НЕ ЧТЕНИЕ. Прибор «мир × полоса» назвал «x² − 16 =
0» ненайденным, но нашёл его числа: род ПОКАЗАН, записан ИНАЧЕ.
Разбор подтвердил: в своде живёт «x^2 - 16 = 0», четырнадцать раз.

ПАРА ОБЪЯВЛЯЕТСЯ, А НЕ ВЫВОДИТСЯ. Начертания не связаны правилом —
их связывает письменная традиция, и знать её может лишь объявление.
Здесь оно одно на весь корпус: и генератор, и суд читают ЭТУ таблицу,
и потому разойтись не могут.
"""
import re

# (начертание ASCII, начертание типографское, имя по-английски, по-русски)
ПАРЫ = (
    ("x^2", "x²", "x squared", "икс в квадрате"),
    ("x^3", "x³", "x cubed", "икс в кубе"),
    ("<=", "≤", "less than or equal", "меньше или равно"),
    (">=", "≥", "greater than or equal", "больше или равно"),
    ("!=", "≠", "not equal", "не равно"),
    ("->", "→", "leads to", "ведёт к"),
    ("<->", "↔", "equivalent to", "равносильно"),
    ("*", "×", "times", "умножить"),
    ("/", "÷", "divided by", "разделить"),
    ("sqrt", "√", "square root", "квадратный корень"),
    ("-", "−", "minus", "минус"),
)

# Начертание, чей знак меняется ВНУТРИ слова, режется иначе: «sqrt» есть
# слово, а «≤» — знак. Признак объявлен, ибо от него зависит замена.
СЛОВОМ = {"sqrt"}

ПО_ASCII = {а: (т, en, ru) for а, т, en, ru in ПАРЫ}
ПО_ТИПОГРАФСКОМУ = {т: (а, en, ru) for а, т, en, ru in ПАРЫ}


# КОЭФФИЦИЕНТ ПРИ ПЕРЕМЕННОЙ ПИШЕТСЯ И РАЗДЕЛЬНО, И СЛИТНО. Корпус пишет
# «x^2 - 3 x + 2 = 0», полоса спрашивает «x² − 5x + 6 = 0»: три различия
# в одной строке — степень, минус и «3 x» против «5x». Первые два дом
# уже знал; третье есть то же начертание: правило, а не пара, ибо
# коэффициент любой. Мера «мир × полоса» назвала семнадцать родов
# квадратных уравнений «без мира» ровно из-за этого — при том, что
# уравнения показаны сотнями.
СЛИТНО = re.compile(r"(\d)x\b")
РАЗДЕЛЬНО = re.compile(r"(\d) x\b")


def канон(запись):
    """Запись, приведённая к ASCII-начертанию.

    КАНОН НУЖЕН СУДУ, А НЕ ПОКАЗУ. Показ говорит обоими начертаниями;
    суд же обязан убедиться, что за ними ОДНА запись, и потому сводит
    их к одному виду — как две дороги сводятся к одной карте.
    """
    вон = запись
    for типографское, (ascii_, _, _) in ПО_ТИПОГРАФСКОМУ.items():
        вон = вон.replace(типографское, ascii_)
    вон = СЛИТНО.sub(r"\1 x", вон)
    return " ".join(вон.split())


def двойник(запись):
    """Та же запись в другом начертании, или None — двойника нет."""
    вон = запись
    менялось = False
    for ascii_, (типографское, _, _) in ПО_ASCII.items():
        if ascii_ in вон:
            вон = вон.replace(ascii_, типографское)
            менялось = True
    if РАЗДЕЛЬНО.search(вон):
        вон = РАЗДЕЛЬНО.sub(r"\1x", вон)
        менялось = True
    return вон if менялось else None


# Надстрочная цифра есть ЗАПИСЬ СТЕПЕНИ, а не украшение. Раскрытие
# нужно не показу, а РАЗБОРУ: суду всё равно, каким начертанием
# записана степень, но не всё равно, прочёл ли он её.
НАДСТРОЧНЫЕ = {"⁰": "0", "¹": "1", "²": "2", "³": "3", "⁴": "4",
               "⁵": "5", "⁶": "6", "⁷": "7", "⁸": "8", "⁹": "9"}


def раскрыть_степени(запись):
    """«x² − 36 = 0» → «x ^ 2 − 36 = 0»; прочее не трогается.

    ЗНАК, КОТОРОГО РАЗБОР НЕ ЗНАЕТ, ОН ГЛОТАЕТ МОЛЧА — И ЭТО ХУЖЕ
    ОТКАЗА. Арифметический суд читал «x² − 36 = 0» как «x − 36 = 0»:
    надстрочная двойка не была ни числом, ни знаком, и разбор её
    ПРОПУСКАЛ, а затем выносил вердикт по остатку. Строка объявлялась
    ЛОЖНОЙ — не потому, что лгала, а потому, что была прочитана
    наполовину.

    Раскрытие ставит степень в то начертание, которое разбор знает.
    Дом начертаний один на весь корпус, и служит он не только показу.
    """
    вон = []
    подряд = []
    for знак in запись:
        цифра = НАДСТРОЧНЫЕ.get(знак)
        if цифра is not None:
            подряд.append(цифра)
            continue
        if подряд:
            вон.append(" ^ " + "".join(подряд) + " ")
            подряд = []
        вон.append(знак)
    if подряд:
        вон.append(" ^ " + "".join(подряд))
    return " ".join("".join(вон).split())
