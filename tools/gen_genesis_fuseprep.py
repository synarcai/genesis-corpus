#!/usr/bin/env python3
"""GENESIS layer: СЛИЯНИЕ ПРЕДЛОГА С АРТИКЛЕМ — see tools/fuseprepforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Слияние названо» и «слияние обязательно» идут вместе: первое показывает, ЧТО сливается,
второе тут же отнимает вывод «а можно и врозь», который читатель сделал бы из первого сам.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Неопределённый не сливается» и «сосед сливает не всё» — второй группой: обе о ГРАНИЦАХ
слияния, одна внутрь языка (не всякий артикль), другая вширь (не всякий язык одинаково).

«Немец волен» — третьей и особо: это единственное место, где раздельная запись ЗАКОННА, и
соседство с итальянским запретом разбавило бы обе стороны.

    ЛИБО СЛИЯНИЕ ЕСТЬ ЗАКОН, И ТОГДА РАЗДЕЛЬНАЯ ЗАПИСЬ НЕВОЗМОЖНА, ЛИБО ЭТО ВОЛЯ, И ТОГДА
    ОБЕ ЗАПИСИ ЗАКОННЫ. Третьего нет.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import fuseprepforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_fuseprep.txt"
ГРУППЫ = (("слияние названо", "слияние обязательно"),
          ("неопределённый не сливается", "сосед сливает не всё"),
          ("немец волен",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
