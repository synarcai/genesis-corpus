#!/usr/bin/env python3
"""GENESIS layer: ДВА «БЫТЬ» — see tools/serestarforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ У ЧИТАТЕЛЯ.

«Два слова на одно» и «свойство и состояние» идут вместе: первое говорит, что выбор есть,
второе тут же показывает, что выбор МЕНЯЕТ СМЫСЛ. Порознь первое читалось бы как весть о двух
синонимах.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Место всегда estar» и «занятие только ser» — второй группой, и это ПАРА ПРОТИВОПОЛОЖНЫХ
исключений: там, где читатель ждёт «ser» (вечное место города), стои́т «estar»; там, где он
ждёт выбора (занятие на один день), выбора нет вовсе. Врозь каждое учило бы своему перекосу.

«Откуда и где» и «сосед делит так же» — третьей: одна о том, что предлог и глагол ходят
парами, другая о том, что деление это не причуда одного языка.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import serestarforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_serestar.txt"
ГРУППЫ = (("два слова на одно", "свойство и состояние"),
          ("место всегда estar", "занятие только ser"),
          ("откуда и где", "сосед делит так же"),
          # ВОПРОСНЫЙ РОД ИДЁТ СВОЕЙ ГРУППОЙ: мир, который только сообщает, учит узнавать,
          # а не спрашивать, — и вопрос, разбавленный объяснениями, теряется среди них.
          ("спрошено и отвечено",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
