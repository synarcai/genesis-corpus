def тройки():
    """(a, b, c): ставка, единиц, итог — ставка не равна числу единиц, итог не кончается единицей."""
    return [(a, b, a * b) for a in СТАВКИ for b in ЕДИНИЦ if a != b and not _на_единице(a * b)]


# СУММА ДВУХ СЧЁТОВ (заказ руки rate: «15 X и 62 X; в каждом X по N Y» → (15 + 62) × N) — два привоза
# вместилищ и ставка: сперва сумма, затем произведение, и оба шага стоят уравнением на странице.
# Везут то, что возят: коробки и пеналы (вместилища 0 и 2), а не полки.
ВЕЗУТ = (0, 2)


def суммы():
    """(a, b1, b2, b, c): два счёта b1 < b2 из 2…9, их сумма b, итог c = a·b — ставка не равна
    сумме, итог не кончается единицей; взят каждый четвёртый набор ряда, чтобы род весил, как
    прочие (около сорока семи страниц на вместилище), а не вчетверо больше."""
    ряд = [(a, b1, b2, b1 + b2, a * (b1 + b2)) for a in СТАВКИ for b1 in ЕДИНИЦ for b2 in ЕДИНИЦ
           if b1 < b2 and a != b1 + b2 and not _на_единице(a * (b1 + b2))]
    return ряд[::4]


def ячейка(язык, n):
    """Имя ячейки счёта при n по правилу пакета («one», «few», «many»)."""
    имена = list(P.вещи(язык)[0])
    return P.форма(язык, dict(zip(имена, имена)), n)


def _дыры(язык, i):
    """Места вместилища, вещи и вопросные слова — всё, что не зависит от чисел."""
    в = ВМЕСТИЛИЩА[язык][i]
    вещь = P.вещи(язык)[i]
    с = ВЕЩЬ_СТАВКИ[язык][i]
    дыры = {к: з for к, з in в.items() if isinstance(з, str) and к != "род"}
    дыры.update(X1=в["счёт"]["one"], Xмн=в["счёт"]["many"], Yмн=вещь["many"],
                Yмн_ном=с.get("мн_ном", вещь["many"]), вещь_ставки=с["ставки"])
    if "после" in с:
        дыры["ставка_после"] = с["после"]
    if язык in ВОПРОС:
        дыры["КСК_Y"] = ВОПРОС[язык][РОД_ВЕЩИ[язык][i]]
        дыры["КСК_X"] = ВОПРОС[язык][в["род"]]
    return дыры


def _рамка(язык, i, род):
    """Рамка рода с местами вместилища и вещи, вставленными ДО чисел: места сами несут {b} и {Xb}."""
    шаблон = РАМКИ[язык][_РАМКА_РОДА[род]]
    дыры = _дыры(язык, i)
    return re.sub(r"\{([^}:]+)\}", lambda м: дыры.get(м.group(1), м.group(0)), шаблон)


def страница(язык, i, род, a, b, c, b1=None, b2=None, перевернуть_пары=False, **замена):
    """Страница рода на тройке (у суммы — и на двух счётах b1, b2); `замена` подменяет дыру,
    `перевернуть_пары` ставит глагол пары в чужую ячейку (так самопроверка портит согласование)."""
    вещь = P.вещи(язык)[i]
    вместилище = ВМЕСТИЛИЩА[язык][i]["счёт"]
    поля = dict(a=a, b=b, c=c, Ya=P.форма(язык, вещь, a), Yb=P.форма(язык, вещь, b),
                Yc=P.форма(язык, вещь, c), Xb=P.форма(язык, вместилище, b),
                Рa=P.форма(язык, P.валюта(язык), a), Рc=P.форма(язык, P.валюта(язык), c))
    if b1 is not None:
        поля.update(b1=b1, b2=b2, Xb1=P.форма(язык, вместилище, b1), Xb2=P.форма(язык, вместилище, b2))
    поля.update(замена)
    числа = dict(a=a, b=b)
    текст = _ПАРА.sub(lambda м: м.group(2) if (ячейка(язык, числа[м.group(1)]) == "few") != перевернуть_пары
                      else м.group(3), _рамка(язык, i, род))
    return текст.format(**поля)


СУММА = "итог двух счётов"


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for i in range(len(ВМЕСТИЛИЩА[язык])):
            for a, b, c in тройки():
                for род in РОДЫ:
                    if род != СУММА:
                        вон[страница(язык, i, род, a, b, c)] = (язык, род)
            if i in ВЕЗУТ:
                for a, b1, b2, b, c in суммы():
                    вон[страница(язык, i, СУММА, a, b, c, b1=b1, b2=b2)] = (язык, СУММА)
    return вон


ПОКАЗЫ = _показы()


def _alt(слова):
    return "(?:" + "|".join(re.escape(с) for с in sorted(set(слова), key=lambda с: (-len(с), с))) + ")"


def _образцы():
    """[(образ, язык, вещь, род, пары)] — рамка каждого рода с дырами-группами.

    Каждое ВХОЖДЕНИЕ дыры — своя группа, и повторённая дыра, несущая два значения, есть ложь
    (закон дома цены, М-106): «24 apples: 4 × 6 = 25» не чужая строка, а ложная. Пара глагола
    («są|jest») — своя группа, и суд сверяет её с ячейкой своего числа.
    """
    вон = []
    for язык in ЯЗЫКИ:
        валюта = P.валюта(язык)
        for i in range(len(ВМЕСТИЛИЩА[язык])):
            вещь = P.вещи(язык)[i]
            вм = _alt(ВМЕСТИЛИЩА[язык][i]["счёт"].values())
            группы = {"a": r"\d+", "b": r"\d+", "c": r"\d+", "b1": r"\d+", "b2": r"\d+",
                      "Ya": _alt(вещь.values()), "Yb": _alt(вещь.values()), "Yc": _alt(вещь.values()),
                      "Xb": вм, "Xb1": вм, "Xb2": вм,
                      "Рa": _alt(валюта.values()), "Рc": _alt(валюта.values())}
            for род in РОДЫ:
                if род == СУММА and i not in ВЕЗУТ:
                    continue
                счёт, куски, пары = {}, [], []
                for кусок in re.split(r"(\{[^}]+\})", _рамка(язык, i, род)):
                    if not кусок.startswith("{"):
                        куски.append(re.escape(кусок))
                        continue
                    м = _ПАРА.fullmatch(кусок)
                    if м:
                        имя = f"пара{len(пары)}"
                        пары.append((имя, м.group(1), м.group(2), м.group(3)))
                        куски.append(f"(?P<{имя}>{_alt((м.group(2), м.group(3)))})")
                        continue
                    имя = кусок[1:-1]
                    счёт[имя] = счёт.get(имя, 0) + 1
                    куски.append(f"(?P<h_{имя}__{счёт[имя]}>{группы[имя]})")
                вон.append((re.compile("^" + "".join(куски) + "$"), язык, i, род, пары))
    return вон


ОБРАЗЦЫ = _образцы()


def _значения(м):
    вон = {}
    for ключ, знач in м.groupdict().items():
        if not ключ.startswith("h_"):
            continue
        имя, _ = ключ[2:].rsplit("__", 1)
        if имя in вон and вон[имя] != знач:
            return None
        вон[имя] = знач
    return вон


def _судить_образцом(строка):
    """(судимо, истинно): итог есть произведение ставки на число единиц, всякая форма счёта — та,
    какую правило пакета выбирает при своём числе, и глагол пары — в ячейке своего числа."""
    с = строка.strip()
    for образ, язык, i, род, пары in ОБРАЗЦЫ:
        м = образ.match(с)
        if not м:
            continue
        г = _значения(м)
        if г is None:
            return True, False
        a, b, c = int(г["a"]), int(г["b"]), int(г["c"])
        if a < 2 or b < 2 or a * b != c:
            return True, False
        if "b1" in г and (int(г["b1"]) < 2 or int(г["b2"]) < 2 or int(г["b1"]) + int(г["b2"]) != b):
            return True, False
        вещь, валюта, вм = P.вещи(язык)[i], P.валюта(язык), ВМЕСТИЛИЩА[язык][i]["счёт"]
        надо = {"Ya": (вещь, a), "Yb": (вещь, b), "Yc": (вещь, c), "Xb": (вм, b),
                "Рa": (валюта, a), "Рc": (валюта, c)}
        if "b1" in г:
            надо.update(Xb1=(вм, int(г["b1"])), Xb2=(вм, int(г["b2"])))
        if any(г[к] != P.форма(язык, т, n) for к, (т, n) in надо.items() if к in г):
            return True, False
        числа = dict(a=a, b=b)
        for имя, чьё, при_few, при_прочих in пары:
            if м.group(имя) != (при_few if ячейка(язык, числа[чьё]) == "few" else при_прочих):
                return True, False
        return True, True
    return False, False


import closedworld as _зк  # noqa: E402 — закон замкнутого мира читается после сборки показов
_СКЕЛЕТЫ_ЗНАКА = _зк.скелеты_знака(ПОКАЗЫ)


def судить(строка):
    """(судимо, истинно) — с ЗАКОНОМ ЗНАКА поверх образца: строка, становящаяся истинной при
    замене одного знака, есть строка этого дома с испорченным знаком (М-489), а не чужая."""
    вердикт = _судить_образцом(строка)
    if вердикт[0] is False and _зк.ложь_по_знаку(строка, _СКЕЛЕТЫ_ЗНАКА, ПОКАЗЫ, _судить_образцом):
        return True, False
    return вердикт


def _самопроверка():
    беды = []
    for показ, (язык, род) in ПОКАЗЫ.items():
        if судить(показ) != (True, True):
            беды.append(f"своя строка не истинна [{язык} {род}]: {показ}")
    мутантов = пойманных = 0
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            вещь = P.вещи(язык)[0]
            if род == СУММА:
                # у суммы порча ставится на настоящих наборах дома: закон знака узнаёт строку
                # дома лишь по скелету его показа
                a, b1, b2, b, c = next(н for н in суммы() if н[4] >= 10)
                с = страница(язык, 0, род, a, b, c, b1=b1, b2=b2)
                чужая = next(ф for ф in вещь.values() if ф != P.форма(язык, вещь, c))
                порчи = [
                    страница(язык, 0, род, a, b, c + 1, b1=b1, b2=b2),        # итог мимо произведения
                    с.replace(" × ", " ÷ "),                                  # знак действия
                    страница(язык, 0, род, a, b, c, b1=b1, b2=b2, Yc=чужая),  # форма счёта при итоге
                    страница(язык, 0, род, a, b, c, b1=b1, b2=b2 + 1),        # сумма счётов мимо
                ]
                if "{по_" in РАМКИ[язык][_РАМКА_РОДА[род]]:
                    for н in суммы():
                        if ячейка(язык, н[0]) == "few":
                            порчи.append(страница(язык, 0, род, н[0], н[3], н[4], b1=н[1], b2=н[2],
                                                  перевернуть_пары=True))
                            break
                    порчи.append(страница(язык, 0, род, a, b, c, b1=b1, b2=b2, перевернуть_пары=True))
            else:
                с = страница(язык, 0, род, 6, 4, 24)
                чужая = next(ф for ф in вещь.values() if ф != P.форма(язык, вещь, 24))
                валюта = P.валюта(язык)
                чужая_валюта = next((ф for ф in валюта.values() if ф != P.форма(язык, валюта, 24)), None)
                порчи = [
                    # итог мимо произведения — во всех местах, чтобы рамка держалась
                    с.replace(" 24 ", " 25 ").replace("= 24.", "= 25.").replace("24 ", "25 ", 1),
                    # знак действия: × ↔ ÷
                    с.replace(" × ", " ÷ ") if " × " in с else с.replace(" ÷ ", " × "),
                    # форма счёта вещи при итоге — чужая форма той же вещи
                    страница(язык, 0, род, 6, 4, 24, Yc=чужая),
                ]
                if чужая_валюта is not None and "{Рc}" in РАМКИ[язык][_РАМКА_РОДА[род]]:
                    # форма валюты при итоге — чужая форма той же валюты
                    порчи.append(страница(язык, 0, род, 6, 4, 24, Рc=чужая_валюта))
                # глагол пары не в ячейке своего числа — при ячейке «few» и при прочих
                if "{по_" in РАМКИ[язык][_РАМКА_РОДА[род]]:
                    порчи.append(страница(язык, 0, род, 3, 4, 12, перевернуть_пары=True))
                    порчи.append(страница(язык, 0, род, 6, 5, 30, перевернуть_пары=True))
            for п in порчи:
                if п == с:
                    continue
                мутантов += 1
                if судить(п) == (True, False):
                    пойманных += 1
                else:
                    беды.append(f"порча не поймана [{язык} {род}] {судить(п)}: {п}")
    return беды, мутантов, пойманных


