#!/usr/bin/env python3
"""GENESIS layer: ЛОВУШКИ СЛУЧАЯ И СРЕДНЕГО — see tools/chancetrapforms.py for the law.

ДВЕ ЛОВУШКИ СРЕДНЕГО ИДУТ ОДНОЙ ГРУППОЙ: «среднего нет ни у кого» и «среднее скрывает
разброс» суть две половины одной мысли — среднее есть число НАБОРА, и потому не говорит
ни о члене, ни о разбросе. Разлучить их значило бы отдать читателю половину.

ДВЕ ЛОВУШКИ СЛУЧАЯ — второй группой: частота против вероятности и память монеты. Обе о
том, что случившееся НЕ МЕНЯЕТ ожидаемого, и вторая есть первая, повторённая во времени.

ТРЕТЬЯ ПРИЧИНА СТОИ́Т ОСОБО, ибо это не ловушка счёта, а ловушка ВЫВОДА: числа верны,
арифметика верна, и неверен только переход от «вместе» к «из-за». ВОПРОС отдельно.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import chancetrapforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_chancetrap.txt"
ГРУППЫ = (("среднего нет ни у кого", "среднее скрывает разброс"),
          ("частота не есть вероятность", "монета не помнит"),
          ("вместе не значит из-за",),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
