#!/usr/bin/env python3
"""ДОМ НЕОБХОДИМОГО И ДОСТАТОЧНОГО — ДВА ВОПРОСА ОБ ОДНОМ УСЛОВИИ, И ОТВЕТЫ У НИХ РАЗНЫЕ.

    НИ ОДНОЙ СТРОКОЙ СВОД НЕ СПРАШИВАЕТ, НЕОБХОДИМО ЛИ УСЛОВИЕ. Замер 11.09 по 255 мирам
    показов и по объявлениям всех миров: «необходимо и достаточно», «necessary and sufficient» —
    НОЛЬ. Свод рассуждает много и точно: строгий вывод (`infer`) знает modus ponens и modus
    tollens, дом двух условий (`both`) показывает таблицу конъюнкции счётом, дом достаточности
    (`enough`) решает, хватит ли денег. И ни один не спрашивает, ЧТО ЗА УСЛОВИЕ ПЕРЕД НИМ.

    СВОД УМЕЕТ ПРОВЕРЯТЬ УСЛОВИЯ И НЕ УМЕЕТ ИХ РАЗЛИЧАТЬ.

ДВАДЦАТЬ СЕДЬМАЯ ЛОВУШКА РЯДА, И ОНА НЕ В ЧИСЛЕ, А В ВОПРОСЕ: «ДОВОЛЬНО ЛИ?» И «НЕОБХОДИМО ЛИ?» —
РАЗНЫЕ ВОПРОСЫ, И ЧИТАТЕЛЬ, ОТВЕТИВШИЙ НА ОДИН, ДУМАЕТ, ЧТО ОТВЕТИЛ НА ОБА.

    УСЛОВИЕ, ДОСТАТОЧНОЕ ДЛЯ ВЫВОДА, НЕ ОБЯЗАНО БЫТЬ НЕОБХОДИМЫМ, И НАОБОРОТ. ЭТО ДВА
    НЕЗАВИСИМЫХ СВОЙСТВА, И ПОТОМУ КЛЕТОК ЧЕТЫРЕ, А НЕ ДВЕ.

ЧЕТЫРЕ РОДА СУТЬ ПОЛНАЯ ТАБЛИЦА ДВУХ СВОЙСТВ, ПОКАЗАННАЯ ДЕЛИМОСТЬЮ — тем единственным
предметом, где ОБА ответа проверяются счётом на той же странице:

    довольно, не необходимо   чтобы делиться на 2, довольно делиться на 4 (4 = 2 × 2),
                              но не необходимо: 6 делится на 2 и не делится на 4.
    необходимо, не довольно   чтобы делиться на 6, необходимо делиться на 2 (6 = 2 × 3),
                              но не довольно: 8 делится на 2 и не делится на 6.
    ни то ни другое           чтобы делиться на 4, делимость на 3 ни довольна, ни необходима:
                              3 делится на 3 и не на 4, а 4 делится на 4 и не на 3.
    и то и другое             чтобы делиться на 10, необходимо и довольно кончаться нулём.

ПЕРВЫЕ ДВА РОДА СУТЬ МИНИМАЛЬНАЯ ПАРА ПО НАПРАВЛЕНИЮ: те же два делителя, и разница в одном —
какой из них стои́т в условии, а какой в выводе. Читатель, видевший лишь один, выведет, что
«довольно» и «необходимо» суть одно слово, сказанное дважды.

ТРЕТИЙ РОД НЕСЁТ ДВА ПРОТИВОПРИМЕРА, А НЕ ОДИН, и это не щедрость: «ни довольно, ни необходимо»
есть ДВА отрицания, и каждое обязано быть куплено своим свидетелем.

    ОТРИЦАНИЕ ДВУХ СВОЙСТВ РАЗОМ ТРЕБУЕТ ДВУХ СВИДЕТЕЛЕЙ; ОДИН ДОКАЗАЛ БЫ ПОЛОВИНУ И
    ОСТАВИЛ БЫ ВТОРУЮ НА ВЕРУ.

ЧЕТВЁРТЫЙ РОД БЕРЁТ ДВА РАЗНЫХ НА ВИД УСЛОВИЯ, РАВНЫХ ПО СИЛЕ: «делится на 10» и «кончается
нулём». Условие, совпадающее с искомым дословно, было бы клеткой без содержания; здесь же
равносильность есть ЗНАНИЕ, а не тождество слов. Правило последней цифры объявлено соседом
(`divrule`), и дом его не переписывает, а употребляет — и говорит об этом вслух.

ВСЯКОЕ УТВЕРЖДЕНИЕ КУПЛЕНО СЧЁТОМ НА ТОЙ ЖЕ СТРАНИЦЕ: и «4 = 2 × 2» (откуда следует включение
кратных), и «6 = 4 × 1 + 2» (откуда следует, что 6 на 4 не делится). Общий суд арифметики читает
их все — проба четырёх страниц дала «0 ложных из 6 судимых, неразобрано 0».

    ВЫВОД О ДЕЛИМОСТИ ПОКУПАЕТСЯ ОСТАТКОМ: «не делится» есть утверждение, и свидетель его —
    остаток, отличный от нуля, написанный тут же.

    python3 tools/nesufforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("довольно", "необходимо", "ни то ни другое", "и то и другое")

ДЕЛИТЕЛИ = tuple(range(2, 13))
# ОСНОВАНИЕ ПОСЛЕДНЕЙ ЦИФРЫ ОБЪЯВЛЕНО СОСЕДОМ `divrule`, а не выведено здесь.
ДЕСЯТЬ = 10

РАМКИ = {
    "ru": {
        "довольно": "чтобы число делилось на {b}, довольно ли делиться на {a}? да: "
                    "{a} = {b} × {k}, и всякое кратное {a} кратно {b}. а необходимо ли? нет: "
                    "{c} делится на {b} и не делится на {a}: {c} = {b} × {m}, "
                    "и {c} = {a} × {q} + {r}.",
        "необходимо": "чтобы число делилось на {b}, необходимо ли делиться на {a}? да: "
                      "{b} = {a} × {k}, и всякое кратное {b} кратно {a}. а довольно ли? нет: "
                      "{c} делится на {a} и не делится на {b}: {c} = {a} × {m}, "
                      "и {c} = {b} × {q} + {r}.",
        "ни то ни другое": "чтобы число делилось на {b}, делимость на {a} ни довольна, "
                           "ни необходима: {c} делится на {a} и не делится на {b}, а {d} делится "
                           "на {b} и не делится на {a}: {c} = {a} × {m}, и {d} = {b} × {m2}.",
        "и то и другое": "чтобы число делилось на 10, необходимо и довольно кончаться нулём: "
                         "{c} кончается нулём и делится на 10, а {d} не кончается нулём и не "
                         "делится на 10: {c} = 10 × {m}, и {d} = 10 × {q} + {r}.",
    },
    "en": {
        "довольно": "for a number to be divisible by {b}, is it enough to be divisible by {a}? "
                    "yes: {a} = {b} × {k}, and every multiple of {a} is a multiple of {b}. and "
                    "is it necessary? no: {c} is divisible by {b} and not by {a}: "
                    "{c} = {b} × {m}, and {c} = {a} × {q} + {r}.",
        "необходимо": "for a number to be divisible by {b}, is it necessary to be divisible by "
                      "{a}? yes: {b} = {a} × {k}, and every multiple of {b} is a multiple of "
                      "{a}. and is it enough? no: {c} is divisible by {a} and not by {b}: "
                      "{c} = {a} × {m}, and {c} = {b} × {q} + {r}.",
        "ни то ни другое": "for a number to be divisible by {b}, divisibility by {a} is neither "
                           "enough nor necessary: {c} is divisible by {a} and not by {b}, and "
                           "{d} is divisible by {b} and not by {a}: {c} = {a} × {m}, "
                           "and {d} = {b} × {m2}.",
        "и то и другое": "for a number to be divisible by 10, ending in a zero is both necessary "
                         "and enough: {c} ends in a zero and is divisible by 10, and {d} does "
                         "not end in a zero and is not divisible by 10: {c} = 10 × {m}, "
                         "and {d} = 10 × {q} + {r}.",
    },
}
ПУСТО = dict(a=0, b=0, c=0, d=0, k=0, m=0, m2=0, q=0, r=0)


def _свидетели(кратно, не_кратно, сколько=3):
    """Числа, кратные первому и НЕ кратные второму, БОЛЬШЕ второго.

    СВИДЕТЕЛЬ, МЕНЬШИЙ ТОГО, ЧЕМУ ОН НЕ КРАТЕН, ВЫРОЖДЕН: «2 делится на 2 и не делится на 4»
    верно, и остаток пишется как «2 = 4 × 0 + 2» — частное ноль, и свидетельство держится
    не на делении, а на малости. Первая редакция брала именно такие.

        СВИДЕТЕЛЬ ОБЯЗАН БЫТЬ БОЛЬШЕ ТОГО, ЧЕМУ ОН НЕ КРАТЕН: иначе он свидетельствует
        о размере, а не о делимости.

    И КРАТНОСТЬ ЕГО ОБЯЗАНА БЫТЬ НЕ ЕДИНИЧНОЙ: «7 делится на 7: 7 = 7 × 1» истинно и пусто —
    произведение на единицу не показывает деления, а повторяет само число.

        СВИДЕТЕЛЬСТВО, ДЕРЖАЩЕЕСЯ НА УМНОЖЕНИИ НА ЕДИНИЦУ, ПОВТОРЯЕТ ВОПРОС ВМЕСТО ОТВЕТА.
    """
    вон, n = [], кратно * 2
    while len(вон) < сколько and n <= кратно * не_кратно * 5:
        if n > не_кратно and n % не_кратно:
            вон.append(n)
        n += кратно
    return вон


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for b in ДЕЛИТЕЛИ:
            for a in ДЕЛИТЕЛИ:
                if a == b:
                    continue
                if a % b == 0:
                    # ДОВОЛЬНО, НЕ НЕОБХОДИМО: a есть кратное b, значит кратные a суть
                    # кратные b; свидетель обратного — кратное b, не кратное a.
                    for c in _свидетели(b, a):
                        вон[рамки["довольно"].format(
                            **dict(ПУСТО, a=a, b=b, k=a // b, c=c, m=c // b,
                                   q=c // a, r=c % a))] = (язык, "довольно")
                elif b % a == 0:
                    # НЕОБХОДИМО, НЕ ДОВОЛЬНО: то же двумя делителями, взятыми наоборот.
                    for c in _свидетели(a, b):
                        вон[рамки["необходимо"].format(
                            **dict(ПУСТО, a=a, b=b, k=b // a, c=c, m=c // a,
                                   q=c // b, r=c % b))] = (язык, "необходимо")
                elif (a + b) % 3 == 0:
                    # НИ ТО НИ ДРУГОЕ: два свидетеля, по одному на каждое отрицание.
                    for c, d in zip(_свидетели(a, b, 2), _свидетели(b, a, 2)):
                        вон[рамки["ни то ни другое"].format(
                            **dict(ПУСТО, a=a, b=b, c=c, d=d, m=c // a,
                                   m2=d // b))] = (язык, "ни то ни другое")
        # И ТО И ДРУГОЕ: правило последней цифры, взятое у соседа и показанное обеими сторонами.
        # ТОТ ЖЕ ЗАКОН О ЕДИНИЦЕ: «10 = 10 × 1» повторяет число вместо того, чтобы показать
        # его делимость, и потому кратность берётся от двух.
        for m in range(2, 22):
            c = ДЕСЯТЬ * m
            for r in range(1, 10):
                if (m + r) % 7:
                    continue
                d = c + r
                вон[рамки["и то и другое"].format(
                    **dict(ПУСТО, c=c, d=d, m=m, q=d // ДЕСЯТЬ, r=r))] = (язык, "и то и другое")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) = (\d+) × (\d+)(?![/\d])")
_С_ОСТАТКОМ = re.compile(r"(?<![/\d])(\d+) = (\d+) × (\d+) \+ (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # ОСТАТОК СУДИТСЯ ПЕРВЫМ: «6 = 4 × 1 + 2» есть и произведение, и остаток, и свёртка
    # произведения прочла бы в нём «6 = 4 × 1» — ложь о строке, которой в ней нет.
    с_остатком = set()
    for a, b, q, r in _С_ОСТАТКОМ.findall(с):
        с_остатком.add((a, b, q))
        if int(b) * int(q) + int(r) != int(a) or not 0 < int(r) < int(b):
            return True, False
    for a, b, q in _ПРОИЗВ.findall(с):
        if (a, b, q) in с_остатком:
            continue
        if int(b) * int(q) != int(a):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    дов = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "довольно")
    ни = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "ни то ни другое")
    for страница, слово, куда in ((дов, "довольно", "довольн"), (ни, "делимость", "делимост")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(дов + " " + дов)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # СВИДЕТЕЛЬ ОТРИЦАНИЯ ОБЯЗАН БЫТЬ СВИДЕТЕЛЕМ: остаток не ноль на всякой странице отказа.
    for с, (я, р) in ПОКАЗЫ.items():
        if р not in ("довольно", "необходимо") or я != "ru":
            continue
        найдено = _С_ОСТАТКОМ.findall(с)
        if len(найдено) != 1 or int(найдено[0][3]) == 0:
            беды.append(f"свидетель без остатка: {с[:80]}")
            break
    # РОД «НИ ТО НИ ДРУГОЕ» НЕСЁТ ДВУХ СВИДЕТЕЛЕЙ, а не одного.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "ни то ни другое" or я != "ru":
            continue
        if len(_ПРОИЗВ.findall(с)) != 2:
            беды.append(f"у двойного отрицания не два свидетеля: {с[:80]}")
            break
    # ПЕРВЫЕ ДВА РОДА СТОЯ́Т НА ОДНИХ ПАРАХ ДЕЛИТЕЛЕЙ, взятых наоборот.
    пары_д = {tuple(sorted((int(a), int(b)))) for с, (я, р) in ПОКАЗЫ.items()
              if я == "ru" and р == "довольно"
              for a, b, _ in [_ПРОИЗВ.findall(с)[0]]}
    пары_н = {tuple(sorted((int(a), int(b)))) for с, (я, р) in ПОКАЗЫ.items()
              if я == "ru" and р == "необходимо"
              for a, b, _ in [_ПРОИЗВ.findall(с)[0]]}
    if пары_д != пары_н:
        беды.append(f"пары разошлись: {sorted(пары_д ^ пары_н)[:6]}")
    print(f"НЕОБХОДИМОЕ И ДОСТАТОЧНОЕ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, "
          f"бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
