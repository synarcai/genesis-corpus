def подсказано(код, слово, род):
    """Подсказывает ли окончание род: «-o» мужской, «-a» женский — и только там, где так.

    ФРАНЦУЗСКОМУ ЭТА ПОДСКАЗКА НЕ ДАНА ВОВСЕ: «le livre» и «la table» кончаются одинаково.
    """
    if код == "fr":
        return False
    if слово.endswith("o"):
        return род == "м"
    if слово.endswith("a"):
        return род == "ж"
    return False


