def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _нарушает(тело):
    """Нарушает ли цитата закон дома: артикль не того рода, что объявлен для имени.

    ОДНО СЛОВО ЖИВЁТ В ДВУХ ПЛАСТАХ РАЗОМ («casa» в трёх, «libro» в двух), И РОД У НЕГО
    МОЖЕТ БЫТЬ РАЗНЫЙ. Цитата законна, если ЕСТЬ ХОТЬ ОДИН пласт, где этот артикль при этом
    имени объявлен, — иначе суд назвал бы ложью верную страницу соседнего языка.

    ПАРА СУДИТСЯ ЛИШЬ ТОГДА, КОГДА АРТИКЛЬ И ИМЯ МОГУТ БЫТЬ ИЗ ОДНОГО ПЛАСТА (13.09, куплено
    ложью суда). Английская глосса «a table» несёт «a» — португальский артикль женского! — и
    «table», объявленное французским. Суд читал их как одну пару и звал ложью восемь честных
    страниц.

        ГЛОССА НА ЯЗЫКЕ ОБЪЯСНЕНИЯ СОВПАЛА ПО ВИДУ С РЕЧЬЮ ЯЗЫКА ПРЕДМЕТА, и суд, читающий
        по виду, не отличил одного от другого. Пласт, где ОБА куска законны, — вот признак
        того, что цитата вообще об этом доме.
    """
    for арт, слово in _ПАРА.findall(тело.lstrip("*")):
        по_пластам = _РОД_СЛОВА.get(слово)
        if not по_пластам:
            continue
        свои = {к: р for к, р in по_пластам.items()
                if арт in (ПЛАСТЫ[к][2], ПЛАСТЫ[к][3])}
        if not свои:
            continue                   # ни в одном пласте этот артикль при этом имени не свой
        if not any(артикль(к, р) == арт for к, р in свои.items()):
            return True
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        if not _ПАРА.search(цитата.lstrip("*")):
            continue
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:110])
            беды += 1
    # СВЕРКА С ПЛАСТАМИ: всякая пара «артикль + имя» ОБЯЗАНА СТОЯТЬ в своём пласте.
    сверено = 0
    for код, ряд in ИМЕНА.items():
        п = КОРЕНЬ / "datasets" / f"genesis_lang_{код}.txt"
        т = п.read_text(encoding="utf-8", errors="replace").lower() if п.is_file() else ""
        if not т:
            print(f"  ПЛАСТА НЕТ НА МЕСТЕ: {код}")
            беды += 1
            continue
        for слово, род, *_ in ряд:
            if f"{артикль(код, род)} {слово}" not in т:
                print(f"  ПАРЫ НЕТ В ПЛАСТЕ [{код}]: «{артикль(код, род)} {слово}»")
                беды += 1
            else:
                сверено += 1
    # МУТАНТЫ: подмена артикля на артикль ЧУЖОГО рода того же пласта.
    мутантов = 0
    for показ in ПОКАЗЫ:
        порча = None
        for цитата in _re.findall(r"«([^»]+)»", показ):
            if цитата.startswith("*"):
                continue
            пары = _ПАРА.findall(цитата)
            if not пары:
                continue
            арт, слово = пары[0]
            по_пластам = _РОД_СЛОВА.get(слово)
            if not по_пластам:
                continue
            чужие = [артикль(к, "ж" if р == "м" else "м") for к, р in по_пластам.items()]
            чужой = next((а for а in чужие
                          if not any(артикль(к, р) == а for к, р in по_пластам.items())), None)
            if чужой is None:
                continue
            порча = показ.replace(f"«{цитата}»",
                                  "«" + цитата.replace(f"{арт} {слово}", f"{чужой} {слово}", 1) + "»", 1)
            break
        if not порча or порча == показ or порча in ПОКАЗЫ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:110])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    ложные = ("по-испански «la gato» — кот.", "по-французски «la livre» — книга.",
              "по-итальянски «*il fiore» не говорят.")
    for ложь in ложные:
        ПОКАЗЫ[ложь] = ("ru", "проба")
        try:
            if судить(ложь) != (True, False):
                print("  ЛОЖНАЯ СТРАНИЦА ПРОШЛА:", ложь[:100])
                беды += 1
        finally:
            del ПОКАЗЫ[ложь]
    написано = {род for _, род in ПОКАЗЫ.values()}
    if написано != set(РОДЫ):
        print(f"  РОДЫ РАЗОШЛИСЬ: обещано {sorted(РОДЫ)}, написано {sorted(написано)}")
        беды += 1
    for чужая in ("en el diccionario está «el libro», y no es una página de esta casa.",
                  "он выписал «la flor» на поля, и это не страница дома."):
        if судить(чужая) != (False, False):
            print("  ЧУЖАЯ РЕЧЬ СУДИМА:", чужая[:100])
            беды += 1
    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, мутантов поймано {мутантов}, "
          f"пластов {len(ПЛАСТЫ)}, имён {sum(len(р) for р in ИМЕНА.values())}, "
          f"сверено с пластами {сверено}, бед {беды}")
    return беды


if __name__ == "__main__":
    sys.exit(1 if _самопроверка() else 0)
