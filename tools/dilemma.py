def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    for язык in ЯЗЫКИ:
        имена = [и for и, _в in ВЫБОРЫ[язык]]
        assert len(set(имена)) == len(имена), f"выбор дважды: {язык}"
        for имя, выходы in ВЫБОРЫ[язык]:
            assert len(set(выходы)) == len(выходы), f"выход дважды: {имя}"
            assert len(выходы) >= 2, f"выходов меньше двух: {имя}"
        # ОБА ВИДА КУПЛЕНЫ: есть наборы полные (два выхода) и неполные (три и более).
        длины = {len(в) for _и, в in ВЫБОРЫ[язык]}
        assert 2 in длины and max(длины) >= 3, f"куплен один вид набора: {язык}"
        for имя, лево, право, ступеней in ШКАЛЫ[язык]:
            assert ступеней >= 2, f"шкала без середины: {имя}"
            assert лево != право, f"края шкалы совпали: {имя}"
    import collections as _сч
    счёт = _сч.Counter(р for _я, р in ПОКАЗЫ.values())
    assert min(счёт.values()) >= 9, f"род ниже закона массы: {счёт.most_common()[-1]}"
    for с, (язык, _р) in ПОКАЗЫ.items():
        совпали = [род for род, о in _ОБРАЗЦЫ[язык] if о.fullmatch(с)]
        assert len(совпали) == 1, f"две рамки на одной записи ({совпали}): {с}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
