def страница(язык, род, место, пропуск=0, вопросом=False):
    """Страница рода; `вопросом` даёт ВТОРУЮ ПОВЕРХНОСТЬ того же дела."""
    рамки = РАМКИ[язык]
    ключ = род + "_воп" if вопросом else род
    if род == "середина":
        что, а, б, ступеней = ШКАЛЫ[язык][место]
        return рамки[ключ].format(что=что, а=а, б=б, n=ступеней)
    что, выходы = ВЫБОРЫ[язык][место]
    if род == "все_названы":
        if len(выходы) != 2:
            return None
        return рамки[ключ].format(что=что, а=выходы[0], б=выходы[1])
    if len(выходы) < 3 or пропуск >= len(выходы) - 2:
        return None
    return рамки[ключ].format(что=что, а=выходы[0], б=выходы[1],
                              n=len(выходы), в=выходы[2 + пропуск])


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for место in range(len(ВЫБОРЫ[язык])):
            for род in ("все_названы", "третий_есть"):
                for пропуск in range(3):
                    for вопросом in (False, True):
                        п = страница(язык, род, место, пропуск, вопросом)
                        if п:
                            вон.setdefault(п, (язык, род))
        for место in range(len(ШКАЛЫ[язык])):
            for вопросом in (False, True):
                вон.setdefault(страница(язык, "середина", место, вопросом=вопросом),
                               (язык, "середина"))
    return вон


ПОКАЗЫ = _показы()


