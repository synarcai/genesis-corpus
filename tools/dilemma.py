"""ДОМ ЛОЖНОЙ ДИЛЕММЫ (14.09, последний ноль пробы из шестидесяти шести семейств).

Замерено 14.09: «ложная дилемма» / «false dilemma» / «третьего не дано» — НОЛЬ строк. Корпус
знает связки («или» в булевых выражениях), знает выбор действия (`opchoice`), знает отказ по
нехватке данных — и нигде не говорит, что САМ ПЕРЕЧЕНЬ ВЫХОДОВ БЫВАЕТ НЕПОЛОН.

    «ИЛИ ТО, ИЛИ ЭТО» ЕСТЬ УТВЕРЖДЕНИЕ О МИРЕ, А НЕ О ЛОГИКЕ. Связка «или» верна всегда;
    неверным бывает СПИСОК, к какому она приставлена. И проверяется это не рассуждением, а
    ПЕРЕСЧЁТОМ: сколько выходов объявлено и сколько названо.

СУД НЕ РЕШАЕТ, ПОЛОН ЛИ СПИСОК ВООБЩЕ, — этого не решить счётом. Он сверяет названное с
ОБЪЯВЛЕННЫМ набором выходов: набор объявлен поимённо, и всё проверяемо принадлежностью.

ПОЛНОТА ЗДЕСЬ ЕСТЬ ОБЪЯВЛЕНИЕ, А НЕ ИСТИНА О МИРЕ. Дом не берётся решать, все ли выходы у
вещи бывают: он объявляет НАБОР и судит названное по нему. «Дверь заперта или не заперта»
полна потому, что второй выход есть отрицание первого; «монета орлом или решкой» неполна
потому, что в наборе объявлено ребро. И то и другое — объявления, и суд сверяет с ними, а не
с миром.

ТРИ РОДА ПО ДЕЛУ:

    все_названы    выходов объявлено два, и названы оба: дилемма ЧЕСТНАЯ. Род нужен не для
                   полноты — без него читатель выучит, что всякое «или-или» есть обман;
    третий_есть    выходов объявлено три и более, а названы два: третий НАЗВАН прямо, и тем
                   доказана неполнота;
    середина       выходы объявлены как края ШКАЛЫ, и названы лишь края: середина есть, и
                   она названа числом. Это не «третий выход», а ЦЕЛЫЙ РЯД пропущенных.
"""
