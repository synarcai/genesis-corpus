# СУД ПЕРЕСЧИТЫВАЕТ ВЫХОДЫ ПО ОБЪЯВЛЕНИЮ и не берётся решать, полон ли набор вообще: этого
# не решить счётом. Он требует, чтобы названные два были ПЕРВЫМИ ДВУМЯ объявленного набора,
# число выходов сошлось, а пропущенный и правда стои́л в наборе и не был назван.
def _образцы(язык):
    """[(род, образец)] по всем поверхностям рамок — сказанной и вопросной.

    ДЫРА, ПОВТОРЁННАЯ В РАМКЕ, СТАНОВИТСЯ ОБРАТНОЙ ССЫЛКОЙ (16.09). Вопросная поверхность
    называет выходы ДВАЖДЫ — «или {а}, или {б}… названы оба — {а} и {б}», — и второе
    вхождение обязано нести ТО ЖЕ слово. Именованная группа повторяться не может; обратная
    ссылка не только это чинит, но и ПРОВЕРЯЕТ: страница, назвавшая во второй раз иное
    слово, в рамку не ляжет вовсе.
    """
    вон = []
    for ключ in РАМКИ[язык]:
        род = ключ[:-4] if ключ.endswith("_воп") else ключ
        о = re.escape(РАМКИ[язык][ключ])
        for дыра, узор in (("что", "[^:.]+"), ("а", "[^,.]+?"), ("б", "[^,.—]+?"),
                           ("в", "[^.]+"), ("n", r"\d+")):
            метка = re.escape("{" + дыра + "}")
            if метка not in о:
                continue
            о = о.replace(метка, f"(?P<{дыра}>{узор})", 1)
            о = о.replace(метка, f"(?P={дыра})")
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def _набор(язык, что):
    for имя, выходы in ВЫБОРЫ[язык]:
        if имя == что:
            return выходы
    return None


def _шкала(язык, что, а, б):
    for имя, лево, право, ступеней in ШКАЛЫ[язык]:
        if имя == что and лево == а and право == б:
            return ступеней
    return None


def судить(строка):
    """(судимо, истинно) — выходы пересчитаны по объявлению; о мире суд не судит."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            что, а, б = д["что"].strip(), д["а"].strip(), д["б"].strip()
            if род == "середина":
                ступеней = _шкала(язык, что, а, б)
                if ступеней is None:
                    continue                   # чужая шкала — запись не наша
                return True, int(д["n"]) == ступеней
            выходы = _набор(язык, что)
            if выходы is None:
                continue                       # чужой выбор — запись не наша
            # НАЗВАННЫЕ ДВА ОБЯЗАНЫ БЫТЬ ПЕРВЫМИ ДВУМЯ НАБОРА: иначе «пропущенный» назывался
            # бы из тех, что уже названы, и показ лгал бы о неполноте.
            if (а, б) != tuple(выходы[:2]):
                return True, False
            if род == "все_названы":
                return True, len(выходы) == 2
            в = д["в"].strip()
            return True, (len(выходы) >= 3 and int(д["n"]) == len(выходы)
                          and в in выходы[2:])
    return False, True


