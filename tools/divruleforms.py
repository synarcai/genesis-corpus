#!/usr/bin/env python3
"""ДОМ ПРИЗНАКОВ ДЕЛИМОСТИ — узнать делителя, НЕ ДЕЛЯ, и тут же проверить делением.

    ПРИЗНАК ПОКАЗАН ТОЛЬКО ДЛЯ ТРОЙКИ. Замер 11.09 по мирам показов: «делится на 3, когда» —
    160 вхождений (мир дознания), а «делится на 5, когда», «на 9», «на 10», «на 4» — НОЛЬ
    каждое. Последняя цифра как признак упомянута ДВАЖДЫ на весь свод.

    ПРАВИЛО, ПОКАЗАННОЕ В ОДНОМ СЛУЧАЕ ИЗ ШЕСТИ, ЧИТАЕТСЯ КАК ОСОБЕННОСТЬ ТРОЙКИ, А НЕ КАК
    РОД. Между тем признаков три вида, и они устроены по-разному: один смотрит на ХВОСТ числа,
    другой на СУММУ его цифр, третий — на хвост из ДВУХ цифр.

ШЕСТЬ РОДОВ — ТРИ ВИДА ПРИЗНАКА, И У КАЖДОГО СВОЁ ДА И СВОЁ НЕТ:

    хвост да    250 делится на 5, ибо последняя цифра 0, а число делится на 5, когда
                последняя цифра 0 или 5: 250 ÷ 5 = 50.
    хвост нет   117 не делится на 2, ибо последняя цифра 7, а она нечётна: 117 = 2 × 58 + 1.
    сумма да    117 делится на 9, ибо сумма цифр 1 + 1 + 7 = 9, и 9 делится на 9: 117 ÷ 9 = 13.
    сумма нет   118 не делится на 9, ибо сумма цифр 1 + 1 + 8 = 10, а 10 на 9 не делится:
                118 = 9 × 13 + 1.
    пара да     116 делится на 4, ибо две последние цифры дают 16, и 16 делится на 4:
                116 ÷ 4 = 29.
    пара нет    118 не делится на 4, ибо две последние цифры дают 18, а 18 на 4 не делится:
                118 = 4 × 29 + 2.

ПРИЗНАК И ПРОВЕРКА СТОЯ́Т НА ОДНОЙ СТРАНИЦЕ, И В ЭТОМ ВЕСЬ ДОМ. Правило экономит труд — но оно
не заклинание: рядом с ним показано деление, которое его подтверждает. Читатель видит и то,
что признак работает, и то, ЧЕМ он проверяется.

    ПРАВИЛО, ПОКАЗАННОЕ БЕЗ ПРОВЕРКИ, ЗАПОМИНАЕТСЯ КАК ОБЫЧАЙ. Показанное с проверкой —
    как следствие.

ТРИ ВИДА ВЗЯТЫ НЕ ДЛЯ ПОЛНОТЫ ТАБЛИЦЫ, А ПОТОМУ ЧТО ОНИ РАЗНОГО УСТРОЙСТВА: хвост смотрит на
ОДНУ цифру, сумма — на ВСЕ, пара — на ДВЕ. Показав лишь хвост, дом учил бы, что признак всегда
в последней цифре; показав лишь сумму — что всегда в сумме.

ОТКАЗ ПОКАЗАН ОСТАТКОМ, А НЕ ТОЛЬКО СЛОВОМ: «117 = 2 × 58 + 1» — и суд его пересчитывает.

    python3 tools/divruleforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("хвост да", "хвост нет", "сумма да", "сумма нет", "пара да", "пара нет")

# ПРАВИЛО ХВОСТА: делитель → допустимые последние цифры, названные словом правила.
ХВОСТ = {2: "0, 2, 4, 6 или 8", 5: "0 или 5", 10: "0"}
ХВОСТ_EN = {2: "0, 2, 4, 6 or 8", 5: "0 or 5", 10: "0"}
СУММА = (3, 9)
ПАРА = (4,)

РАМКИ = {
    "ru": {
        "хвост да": "{n} делится на {d}, ибо последняя цифра {ц}, а число делится на {d}, когда последняя цифра {правило}: {n} ÷ {d} = {q}.",
        "хвост нет": "{n} не делится на {d}, ибо последняя цифра {ц}, а число делится на {d} лишь когда последняя цифра {правило}: {n} = {d} × {q} + {r}.",
        "сумма да": "{n} делится на {d}, ибо сумма цифр {слож} = {с}, и {с} делится на {d}: {n} ÷ {d} = {q}.",
        "сумма нет": "{n} не делится на {d}, ибо сумма цифр {слож} = {с}, а {с} на {d} не делится: {n} = {d} × {q} + {r}.",
        "пара да": "{n} делится на {d}, ибо две последние цифры дают {пара}, и {пара} делится на {d}: {n} ÷ {d} = {q}.",
        "пара нет": "{n} не делится на {d}, ибо две последние цифры дают {пара}, а {пара} на {d} не делится: {n} = {d} × {q} + {r}.",
    },
    "en": {
        "хвост да": "{n} is divisible by {d}, because the last digit is {ц}, and a number is divisible by {d} when its last digit is {правило}: {n} ÷ {d} = {q}.",
        "хвост нет": "{n} is not divisible by {d}, because the last digit is {ц}, and a number is divisible by {d} only when its last digit is {правило}: {n} = {d} × {q} + {r}.",
        "сумма да": "{n} is divisible by {d}, because the digit sum {слож} = {с}, and {с} is divisible by {d}: {n} ÷ {d} = {q}.",
        "сумма нет": "{n} is not divisible by {d}, because the digit sum {слож} = {с}, and {с} is not divisible by {d}: {n} = {d} × {q} + {r}.",
        "пара да": "{n} is divisible by {d}, because the last two digits give {пара}, and {пара} is divisible by {d}: {n} ÷ {d} = {q}.",
        "пара нет": "{n} is not divisible by {d}, because the last two digits give {пара}, and {пара} is not divisible by {d}: {n} = {d} × {q} + {r}.",
    },
}


def _слож(n):
    """Сумма цифр, записанная сложением: «1 + 1 + 7». Ход показан, а не объявлен."""
    цифры = [int(з) for з in str(n)]
    return " + ".join(str(з) for з in цифры), sum(цифры)


def _ряд(язык):
    """Числа для страниц: по двенадцать кратных и некратных на всякий делитель.

    Ряд один на язык и потому даёт близнецов: русская и английская страницы говорят об ОДНОМ
    числе, а не о разных, — иначе пара языков учила бы двум разным примерам под видом одного.
    """
    вон = []
    for d in list(ХВОСТ) + list(СУММА) + list(ПАРА):
        кратные = [n for n in range(102, 400) if n % d == 0][:12]
        прочие = [n for n in range(102, 400) if n % d][:12]
        вон += кратные + прочие
    return sorted(set(вон))


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        правила = ХВОСТ if язык == "ru" else ХВОСТ_EN
        # ЧИСЛА БЕРУТСЯ ОТ ДЕЛИТЕЛЕЙ, А НЕ ПОДРЯД, И ЭТО ДВЕ ЗАБОТЫ РАЗОМ. Первый заход брал
        # все числа от 102 до 259 и дал 1896 страниц при перекосе: отказов втрое больше
        # согласий (349 против 125), ибо в природе чисел непопаданий и правда больше. Шаг в
        # семь укоротил дом до 276 страниц, но перекос остался, и род «пара да» набрал ШЕСТЬ —
        # меньше девяти, то есть НЕПОКУПАЕМ.
        #
        #     ДОМ, ГДЕ ОТКАЗОВ ВТРОЕ БОЛЬШЕ СОГЛАСИЙ, УЧИТ ОСТОРОЖНОСТИ ВМЕСТО ПРАВИЛА.
        #
        # Ныне для КАЖДОГО делителя берётся по двенадцать кратных и по двенадцать некратных:
        # правило показано на обоих исходах поровну, и ни один род не остаётся без массы.
        for n in _ряд(язык):
            слож, с = _слож(n)
            пара = int(str(n)[-2:])
            общее = dict(n=n, ц=n % 10, слож=слож, с=с, пара=пара)
            for d, правило in правила.items():
                род = "хвост да" if n % d == 0 else "хвост нет"
                вон[рамки[род].format(**общее, d=d, правило=правило,
                                      q=n // d, r=n % d)] = (язык, род)
            for d in СУММА:
                род = "сумма да" if n % d == 0 else "сумма нет"
                # ПРИЗНАК СУММЫ ВЕРЕН ЛИШЬ ТОГДА, КОГДА СУММА И ЧИСЛО СХОДЯТСЯ: иначе
                # страница утверждала бы правило там, где оно молчит.
                if (с % d == 0) != (n % d == 0):
                    continue
                вон[рамки[род].format(**общее, d=d, правило="",
                                      q=n // d, r=n % d)] = (язык, род)
            for d in ПАРА:
                род = "пара да" if n % d == 0 else "пара нет"
                if (пара % d == 0) != (n % d == 0):
                    continue
                вон[рамки[род].format(**общее, d=d, правило="",
                                      q=n // d, r=n % d)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ЧАСТНОЕ = re.compile(r"(\d+) ÷ (\d+) = (\d+)(?!\d)")
_ОСТАТОК = re.compile(r"(\d+) = (\d+) × (\d+) \+ (\d+)(?!\d)")
_СЛОЖЕНИЕ = re.compile(r"(?:сумма цифр|digit sum) ((?:\d \+ )+\d) = (\d+)(?!\d)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: частное, остаток и САМА СУММА ЦИФР своими
    # глазами. Признак здесь не берётся на веру: суд складывает цифры сам.
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b, q, r in _ОСТАТОК.findall(с):
        if int(a) != int(b) * int(q) + int(r) or not 0 < int(r) < int(b):
            return True, False
    for слож, итог in _СЛОЖЕНИЕ.findall(с):
        if sum(int(з) for з in слож.split(" + ")) != int(итог):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:74]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    хв = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "хвост да")
    су = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "сумма да")
    if судить(хв.replace("ибо", "иб"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(су.replace("цифр", "циф"))[1] is not False:
        беды.append("обрезанное слово в сумме прошло")
    if судить(хв + " " + хв)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ПРИЗНАКИ ДЕЛИМОСТИ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
