#!/usr/bin/env python3
"""РОД ОПОЗНАЁТСЯ ОБЪЯВЛЕНИЕМ, А НЕ ИМЕНЕМ.

Сто четыре мира несли поле `genre` — вольную прозу, иногда в полтораста
слов. Проза ЦЕННА: она называет замысел мира и его границу, и потому
остаётся на месте. Но её не читал НИКТО: ни один прибор не мог спросить
манифест «какие миры учат отказу?» или «где показан обратный ход?», и
обещание, которого никто не сверяет, неотличимо от факта, пока не
спросят. Свободный текст есть ИМЯ; объявление есть то, что прибор умеет
прочесть и суд умеет проверить.

ТРИ ОБЪЯВЛЕНИЯ, И КАЖДОЕ ВЫВЕДЕНО ИЗ ТОГО, ЧТО ПРОЗА УЖЕ ГОВОРИЛА:

    АКТ (`act`) — что организм на строках мира УМЕЕТ делать. Не тема,
        а действие: «арифметическая школа» есть ПЕРЕСЧЁТ, «сравнительный
        род» есть СРАВНЕНИЕ, «парадигмы, графемы, неправильные» есть
        ФОРМА. Акт — список: лестница дознания показывает ЧЕТЫРЕ рунга
        одним миром (определение, решённый случай, контрпример, закон),
        и одно значение солгало бы о трёх.
    ОРАКУЛ (`oracle`) — чем истинность строки ПРОВЕРЯЕТСЯ. Двадцать
        пять миров говорят это дословно («forms agree with the pack's
        own rules»), три называют оракул по имени («the oracle is
        REVERSIBILITY»), два требуют ОДНОГО ПРЕДМЕТА от двух разных
        разборов («requires the SAME RECORD, not the same string»).
    ГРАНИЦА (`boundary`) — чего мир НЕ показывает и почему. Это тоже
        сказано прозой и тоже дословно: «only whole results are uttered
        — a percent that does not come out whole is not shown at all»,
        «flat records only, because nesting is held differently by every
        format», «a construct whose reading does not return what was
        written never reaches the corpus».

«НЕ НАЗВАНО» ЕСТЬ ЗНАЧЕНИЕ, А НЕ ПРОБЕЛ. Где проза называет тему и
молчит об акте («markdown/mermaid structures»), стоит `unnamed` — и
стоит ОДНО: смешать его с настоящим значением значит объявить и знание,
и незнание разом. Честное число неназванных дороже заполненной таблицы,
ибо оно показывает, где прозу надо дописать, а не где прибор слеп.

ЗАКОНЫ ДЕЛА (ими объявление проверяется НЕ по списку, а по корпусу):

    ОТКАЗ ОТРИЦАЕТ САМО ИСКОМОЕ, А НЕ ЕГО СВОЙСТВО. «нет целого корня
        от 0 до 10: всякое значение даёт остаток» есть отказ; «функция
        не инъективна: f(3) = f(5)» есть КОНТРПРИМЕР, а «является ли 6
        корнем? нет: 36 - 24 = 12» есть решённый случай с отрицательным
        вердиктом. Различает их не отрицание, а то, ЧТО отрицается, и
        основание, стоящее ПОСЛЕ отрицания.
    ТОЧНОЕ ИЛИ НИЧЕГО ВИДНО ЗАПИСЬЮ ЧИСЛА. Мир, объявивший «только
        целые» или «только точные», не смеет нести дробную запись:
        неточный итог в этом корпусе пишется ровно ею.
    ЯРУС ОБЪЯВЛЯЕТ ПАКЕТ, А НЕ ПРОЗА. «tier 1: structure green» есть
        утверждение о ПАКЕТЕ языка, и проверяется оно у пакета.

ЧЕГО ЭТОТ СВОД НЕ ГОВОРИТ. Метка отказа `¬` объявлена кузницей пакетов
(`langpack_forge`), но тот же знак живёт в мире логики СВЯЗКОЙ («¬ F =
T.»), и по одной метке отказ от строки истинностной таблицы не
отличить. Оборот «no change:» в мире валентности отрицает сущее по
форме и отказом не является. Отрицание читается на ДВУХ языках
корпуса, и «no» третьего языка читается тем же признаком: испанское
«cuando k no es 0» есть отрицание свойства, а прочтётся отрицанием
сущего. Потому мера отказов ОБЯЗЫВАЕТ там, где отказ объявлен, и
МОЛЧИТ там, где не объявлен: обвинение по неточному признаку дороже
пропуска.
"""

import json
import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ПАКЕТЫ = КОРЕНЬ / "tools" / "langpacks"

# НЕ НАЗВАНО СТОИТ ОДНО. Значение объявлено рядом с прочими, потому что
# незнание есть такое же утверждение о мире, как знание, — и подлежит
# тому же суду.
НЕ_НАЗВАНО = "unnamed"

# АКТ: ЧТО ОРГАНИЗМ НА ЭТИХ СТРОКАХ УМЕЕТ ДЕЛАТЬ.
АКТЫ = {
    "recount": "пересчитать величину: строка утверждает число",
    "name": "назвать: что вещь ЕСТЬ и как она зовётся",
    "decide": "решить случай: вердикт с основанием рядом",
    "refuse": "отказать с основанием: искомого нет",
    "translate": "сказать то же другой поверхностью, языком, записью",
    "invert": "пройти обратным ходом: от итога к тому, что его дало",
    "compare": "сравнить двоих: больше, меньше, во столько же раз",
    "inflect": "поставить слово в форму по объявленному правилу",
    "generalize": "назвать закон над случаями",
    "refute": "опровергнуть контрпримером: одно свидетельство",
    "expound": "изложить связной речью (свод прозы)",
    "assemble": "собрать сборку: акты входящих миров, своих нет",
    НЕ_НАЗВАНО: "проза называет тему и молчит об акте",
}

# ОРАКУЛ: ЧЕМ ИСТИННОСТЬ СТРОКИ ПРОВЕРЯЕТСЯ.
ОРАКУЛЫ = {
    "recompute": "пересчётом: основание стоит рядом с утверждением",
    "declared": "сверкой с объявленным — таблицей, правилом, деревом",
    "reversibility": "обратимостью: прочтённое возвращает написанное",
    "same_object": "согласием двух разборов об ОДНОМ предмете",
    "none": "оракула нет: проза не есть перечень проверяемого",
    НЕ_НАЗВАНО: "проза не называет, чем строка проверяется",
}

# ГРАНИЦА: ЧЕГО МИР НЕ ПОКАЗЫВАЕТ И ПОЧЕМУ.
ГРАНИЦЫ = {
    "whole_only": "только целые итоги: нецелое не произносится вовсе",
    "exact_only": "только точные значения: приблизительных нет",
    "unsigned_only": "только неотрицательные: знаковый близнец — свой мир",
    "flat_only": "только плоские записи: вложенность у форматов разная",
    "reversible_only": "только обратимое: необратимое в корпус не попало",
    "tier1_unverified": "строение зелено, язык носителем не проверен",
    "assembled_only": "своей строки нет: сборка есть следствие манифеста",
    НЕ_НАЗВАНО: "проза не называет, чего мир не показывает",
}

# ПОЛЕ ЗНАЕТ СВОЙ НАБОР В ОДНОМ МЕСТЕ. Два списка одного набора
# разойдутся в день, когда тронут любой из них (шрам списка судов,
# жившего разом в палате и в приборе судимости).
ПОЛЯ = (("act", АКТЫ), ("oracle", ОРАКУЛЫ), ("boundary", ГРАНИЦЫ))

# МЕТКА ОТКАЗА ОБЪЯВЛЕНА КУЗНЕЙ ПАКЕТОВ: `"marker": "¬ "`.
ОТКАЗ_МЕТКА = "¬"

# ОТРИЦАНИЕ САМОГО ИСКОМОГО — на обоих языках корпуса. «нет» и «no»
# берутся ТОЛЬКО со словом следом: голое «нет:» есть вердикт решённого
# случая, а не отказ.
ОТРИЦАНИЕ_СУЩЕГО = re.compile(
    r"(?:\bнет\s+\w|\bне сказано\b|\bникуда\b"
    r"|\bno\s+\w|\bnot said\b|\bnowhere\b)", re.I)

# ДРОБНАЯ ЗАПИСЬ ЧИСЛА — «3.5», «3,5». Ею и только ею в этом корпусе
# пишется итог, не вышедший целым.
ДРОБЬ = re.compile(r"\d[.,]\d")


def отказов(текст):
    """Сколько строк несут ОТКАЗ С ОСНОВАНИЕМ.

    Отказ есть отрицание искомого, за которым назван повод: основание
    стоит ПОСЛЕ отрицания, через двоеточие. Строка, начатая меткой
    пакета, есть отказ по объявлению кузни — её основанием служит
    законный близнец, стоящий парой.
    """
    сколько = 0
    for строка in текст.splitlines():
        строка = строка.strip()
        if not строка:
            continue
        if строка.startswith(ОТКАЗ_МЕТКА):
            сколько += 1
            continue
        найдено = ОТРИЦАНИЕ_СУЩЕГО.search(строка)
        if найдено and ":" in строка[найдено.end():]:
            сколько += 1
    return сколько


def дробных(текст):
    """Сколько строк несут дробную запись числа."""
    return sum(1 for с in текст.splitlines() if ДРОБЬ.search(с))


def ярус_пакета(имя_мира):
    """Ярус, объявленный ПАКЕТОМ языка, или None.

    Имя мира несёт язык («lang_es» → `langpacks/es.json`) — тем же
    законом, каким суд прозы читает язык из имени свода. None значит
    «пакета нет или ярус в нём не объявлен», и это не то же самое, что
    ярус первый: незаявленное не есть заявленное.
    """
    if not имя_мира.startswith("lang_"):
        return None
    пакет = ПАКЕТЫ / f"{имя_мира[len('lang_'):]}.json"
    if not пакет.is_file():
        return None
    try:
        return json.loads(пакет.read_text(encoding="utf-8")).get("tier")
    except (OSError, ValueError):
        return None
