def _смыслы(абзацы):
    """[(помета, текст)] — толкования статьи Webster по порядку."""
    вон, ожидаю = [], None
    for а in абзацы[1:]:
        м = СМЫСЛ.match(а)
        if м:
            остаток, помета = м.group(2), None
            мм = ПОМЕТА.match(остаток)
            if мм:
                помета, остаток = мм.group(1), остаток[мм.end():]
            if остаток.startswith("Etym:") or not остаток:
                ожидаю = помета
                continue
            if остаток.startswith("Defn:"):
                остаток = остаток[5:].strip()
            вон.append((помета, остаток))
            ожидаю = None
        elif а.startswith("Defn:"):
            т, помета = а[5:].strip(), ожидаю
            мм = ПОМЕТА.match(т)
            if мм:
                помета, т = мм.group(1), т[мм.end():]
            вон.append((помета, т))
            ожидаю = None
    return вон


def _первая_фраза_en(т):
    if т.startswith("(a) "):
        т = т[4:]
    for м in КОНЕЦ_EN.finditer(т):
        хвост = re.search(r"([A-Za-z]+)$", т[:м.start()])
        if хвост and (хвост.group(1).lower() in СОКР_EN
                      or (len(хвост.group(1)) == 1 and хвост.group(1).isupper())):
            continue
        т = т[:м.start()]
        break
    for знак in ПРИМЕР_EN:
        k = т.find(знак)
        if k > 0:
            т = т[:k]
    т = re.sub(r"[,;]?\s*etc\.?$", "", т.strip())
    return т.strip().rstrip(",;")


def _чисто_en(т):
    return (т and not ПЛОХО_EN.search(т) and _скобки_парны(т)
            and not т.startswith("(") and not ЧУЖОЙ_НАЧАЛ_EN.match(т)
            and 2 <= _слов(т) <= МАКС_СЛОВ and not _чужой_род(т)
            and т[0].isalpha())


def цитаты_webster(понятие):
    """[(цитата, статья)] — первое толкование и первое научное, из
    статьи-существительного с наибольшим числом толкований."""
    словарь = D.словарь("webster")
    статьи = [с for _, с in словарь.по_слову(понятие)
              if re.search(r"(?:^|[ ,])n\.", с.тело.split("\n", 1)[0])]
    if not статьи:
        return []
    разобранные = [(с, _смыслы(с.тело.split("\n"))) for с in статьи]
    разобранные = [(с, см) for с, см in разобранные if см]
    if not разобранные:
        return []
    главная, смыслы = max(разобранные, key=lambda x: len(x[1]))
    вон = []
    for помета, т in [смыслы[0]] + [
            (п, т) for с, см in разобранные for п, т in см if п and НАУКА.search(п)][:1]:
        ф = _укоротить(_первая_фраза_en(т))
        if ф and _чисто_en(ф) and not any(ф == г for г, _ in вон):
            вон.append((ф, главная))
    return вон


