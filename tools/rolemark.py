#!/usr/bin/env python3
"""ДОМ МЕТКИ РОЛИ (14.09, куплен нулём пробы).

Замерено 14.09: «порядок слов меняет смысл» / «word order changes the meaning» — НОЛЬ строк.
Мир порядка слов (`wordorder`) знает, ГДЕ СТОИ́Т ГЛАГОЛ, и мерит это числом; о том, чем
помечено, КТО ДЕЙСТВУЕТ, корпус не говорит нигде.

    РОЛЬ ПОМЕЧЕНА МЕСТОМ ИЛИ ОКОНЧАНИЕМ, И ЯЗЫКИ ДЕЛЯТСЯ ИМЕННО ЗДЕСЬ. «The cat sees the
    dog» и «the dog sees the cat» суть разные события: в английском роль метит МЕСТО. А
    «кошка видит собаку» и «собаку видит кошка» суть ОДНО событие: в русском роль метит
    ОКОНЧАНИЕ, и место свободно.

ЗДЕСЬ ЯЗЫК И ЕСТЬ ПРЕДМЕТ ПОКАЗА, А НЕ ЕГО ПОВЕРХНОСТЬ. Корпус держит закон: язык не есть
род, и один род ходит по всем языкам. Дом этот — ОБЪЯВЛЕННОЕ ИСКЛЮЧЕНИЕ: он о том, ЧЕМ
РАЗНЯТСЯ языки, и потому два его рода живут каждый в своём. Исключение названо вслух, а не
внесено молча: молчаливое исключение растёт, объявленное — считается.

МЕСТОИМЕНИЕ ТРЕБУЕТ РОДА, А ДОМ ЕГО НЕ ОБЪЯВЛЯЛ, и потому рамки обходятся БЕЗ местоимений:
«кошка… он» и «mother… it» суть ошибки согласования, каких не поймал бы ни один здешний суд.
Объявить род каждому имени значило бы завести второй дом грамматики внутри этого; не
объявить и всё же писать местоимение значило бы лгать. Третий путь — не писать его вовсе.

ТРИ РОДА ПО ДЕЛУ:

    место_решает      (англ.) две расстановки — два события: кто перед глаголом, тот и
                      действует;
    окончание_решает  (рус.) две расстановки — одно событие: кто в именительном, тот и
                      действует, где бы ни стоял;
    кто_действует     вопрос к ОДНОЙ расстановке, и притом к ПЕРЕСТАВЛЕННОЙ. Здесь читатель
                      либо идёт за меткой своего языка, либо промахивается. Род двуязычен, и
                      в нём вся проверка.
"""
import itertools
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("место_решает", "окончание_решает", "кто_действует")
РОД_В_ПОКАЗЕ = 1

# ИСКЛЮЧЕНИЕ, НАЗВАННОЕ ПРОЗОЙ, НЕВИДИМО ПРИБОРУ (15.09). Шапка этого дома с первого дня
# говорит вслух: два его рода живут каждый в своём языке, и это ПРЕДМЕТ дома, а не дыра в
# ковке. Прибор щербатости прочёл дом впервые сегодня — знаменатель его вырос с двадцати
# трёх домов до двухсот трёх — и назвал оба рода щербатыми, ибо читает он словарь, а не
# прозу.
#
#     ЧЕСТНОСТЬ ПЕРЕД ЧЕЛОВЕКОМ НЕ ЕСТЬ ЧЕСТНОСТЬ ПЕРЕД ПРИБОРОМ. Дом, назвавший своё
#     исключение словами и не назвавший словарём, отличим от дома небрежного лишь чтением —
#     а прибор ходит по трёмстам домам и читать их не станет. Объявление кладётся туда, где
#     его ищет прибор, и проза остаётся при нём объяснением, а не заменой.
#
# Здесь дыра есть само содержание показа: «окончание решает» по-английски было бы ложью, ибо
# английское имя не склоняется (это и проверяет самопроверка ниже), а «место решает»
# по-русски ложь ровно в той же мере.
ОБЪЯВЛЕННЫЕ_ПРОПУСКИ = {"место_решает": frozenset({"ru"}),
                        "окончание_решает": frozenset({"en"})}

ЗАЧЕМ_РОДА = {
    "место_решает": "две расстановки — два события: роль метит место",
    "окончание_решает": "две расстановки — одно событие: роль метит окончание",
    "кто_действует": "вопрос к переставленной расстановке: за чем идти — за местом или окончанием",
}

# ИМЕНА ОБЪЯВЛЕНЫ ДВУМЯ ФОРМАМИ: кто действует и кого действуют. Для английского формы
# совпадают — и это ФАКТ ЯЗЫКА, а не небрежность объявления.
ИМЕНА = {
    "ru": (("кошка", "кошку"), ("собака", "собаку"), ("мама", "маму"), ("сестра", "сестру")),
    "en": (("the cat", "the cat"), ("the dog", "the dog"), ("mother", "mother"),
           ("the sister", "the sister")),
}
ГЛАГОЛЫ = {"ru": ("видит", "зовёт", "ждёт"), "en": ("sees", "calls", "awaits")}

РАМКИ = {
    "ru": {
        "прямо": "{кто} {гл} {кого}",
        "обратно": "{кого} {гл} {кто}",
        "окончание_решает": "«{а}» и «{б}»: слова переставлены, а событие одно — в русском "
                            "роль метит ОКОНЧАНИЕ, и в обоих действует {кто}.",
        "кто_действует": "«{б}». кто действует? {кто}: именительный падеж метит "
                         "действующего, а место тут ничего не решает.",
    },
    "en": {
        "место_решает": "«{а}» and «{б}»: the same words, and the events are two — in "
                        "english the PLACE marks the role, so in the first {кто} acts and "
                        "in the second {кого}.",
        "прямо": "{кто} {гл} {кого}",
        "обратно": "{кого} {гл} {кто}",
        "кто_действует": "«{б}». who acts? {кого}: in english the place before the verb "
                         "marks the actor, and the ending decides nothing here.",
    },
}


def предложение(язык, ключ, пара, гл):
    (кто, _), (кого_им, кого_вин) = пара
    рамки = РАМКИ[язык]
    если = {"кто": кто, "гл": гл, "кого": кого_вин if язык == "ru" else кого_им}
    return рамки[ключ].format(**если)


def страница(язык, род, пара, гл):
    (кто, _), (кого_им, _кого_вин) = пара
    рамки = РАМКИ[язык]
    прямо = предложение(язык, "прямо", пара, гл)
    обратно = предложение(язык, "обратно", пара, гл)
    if род == "место_решает":
        if язык != "en":
            return None
        return рамки["место_решает"].format(а=прямо, б=обратно, кто=кто, кого=кого_им)
    if род == "окончание_решает":
        if язык != "ru":
            return None
        return рамки["окончание_решает"].format(а=прямо, б=обратно, кто=кто)
    # ВОПРОС СТАВИТСЯ К ПЕРЕСТАВЛЕННОЙ РАССТАНОВКЕ: к прямой его ставить нечего, там обе
    # метки — место и окончание — говорят одно и то же, и промахнуться негде.
    if язык == "ru":
        return рамки["кто_действует"].format(б=обратно, кто=кто)
    return рамки["кто_действует"].format(б=обратно, кого=кого_им)


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for пара in itertools.permutations(ИМЕНА[язык], 2):
                for гл in ГЛАГОЛЫ[язык]:
                    п = страница(язык, род, пара, гл)
                    if п:
                        вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД РАЗБИРАЕТ ПРЕДЛОЖЕНИЕ И НАХОДИТ ДЕЙСТВУЮЩЕГО САМ — по МЕТКЕ СВОЕГО ЯЗЫКА, а не по
# тому, что сказано на странице. Для русского он смотрит, какое имя стои́т в именительном;
# для английского — какое стои́т перед глаголом. Имя или глагол вне объявленных делает запись
# не нашей.
def _образцы(язык):
    вон = []
    for род in РОДЫ:
        рамка = РАМКИ[язык].get(род)
        if рамка is None:
            continue
        о = re.escape(рамка)
        for дыра, узор in (("а", "[^«»]+"), ("б", "[^«»]+"), ("кто", "[^«».,:]+"),
                           ("кого", "[^«».,:]+")):
            дыра_о = re.escape("{" + дыра + "}")
            первый = True
            while дыра_о in о:
                о = о.replace(дыра_о, f"(?P<{дыра}>{узор})" if первый else f"(?P={дыра})", 1)
                первый = False
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def действующий(язык, предложение_):
    """Кто действует — по МЕТКЕ ЯЗЫКА. None, если предложение не наше."""
    слова = предложение_.split()
    глаголы = ГЛАГОЛЫ[язык]
    места = [i for i, с in enumerate(слова) if с in глаголы]
    if len(места) != 1:
        return None
    гл = места[0]
    перед, после = " ".join(слова[:гл]), " ".join(слова[гл + 1:])
    if язык == "en":
        # МЕСТО МЕТИТ РОЛЬ: действует тот, кто перед глаголом.
        имена = {и for и, _в in ИМЕНА[язык]}
        return перед if перед in имена and после in имена and перед != после else None
    им = {и: и for и, _в in ИМЕНА["ru"]}
    вин = {в: и for и, в in ИМЕНА["ru"]}
    # ОКОНЧАНИЕ МЕТИТ РОЛЬ: действует тот, кто в именительном, где бы ни стоял.
    if перед in им and после in вин and им[перед] != вин[после]:
        return перед
    if перед in вин and после in им and вин[перед] != им[после]:
        return после
    return None


def судить(строка):
    """(судимо, истинно) — действующий найден заново по метке своего языка."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            б = действующий(язык, д["б"])
            if б is None:
                continue                       # чужое имя или глагол — запись не наша
            if род == "кто_действует":
                назван = д.get("кто") or д.get("кого")
                return True, назван == б
            а = действующий(язык, д["а"])
            if а is None:
                return True, False
            if род == "окончание_решает":
                # ОДНО СОБЫТИЕ: перестановка не сменила действующего, и назван он же.
                return True, а == б and д["кто"] == а
            # ДВА СОБЫТИЯ: перестановка сменила действующего, и названы оба по местам.
            return True, а != б and д["кто"] == а and д["кого"] == б
    return False, True


# ПОДСАДКИ ОБЪЯВЛЕНЫ ЗДЕСЬ, И СУД БЕРЁТ ИХ ОТСЮДА ЖЕ.
ПОДСАДКИ = (
    "«собаку видит кошка». кто действует? собака: именительный падеж метит действующего, а "
    "место тут ничего не решает.",
    "«кошка видит собаку» и «собаку видит кошка»: слова переставлены, а событие одно — в "
    "русском роль метит ОКОНЧАНИЕ, и в обоих действует собака.",
    "«the dog sees the cat». who acts? the cat: in english the place before the verb marks "
    "the actor, and the ending decides nothing here.",
    "«the cat sees the dog» and «the dog sees the cat»: the same words, and the events are "
    "two — in english the PLACE marks the role, so in the first the dog acts and in the "
    "second the cat.",
)


def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    # АНГЛИЙСКИЕ ФОРМЫ СОВПАДАЮТ, РУССКИЕ — НЕТ, И ЭТО ФАКТ ЯЗЫКА, А НЕ НЕБРЕЖНОСТЬ.
    assert all(и == в for и, в in ИМЕНА["en"]), "английское имя вдруг склонилось"
    assert all(и != в for и, в in ИМЕНА["ru"]), "русское имя не склонилось"
    # МЕТКА РАБОТАЕТ НА ОБЪЯВЛЕННОМ ПРИМЕРЕ, А НЕ НА ВЕРЕ.
    assert действующий("ru", "собаку видит кошка") == "кошка", "окончание не метит роли"
    assert действующий("en", "the dog sees the cat") == "the dog", "место не метит роли"
    import collections as _сч
    счёт = _сч.Counter(р for _я, р in ПОКАЗЫ.values())
    assert min(счёт.values()) >= 9, f"род ниже закона массы: {счёт.most_common()[-1]}"
    for с, (язык, _р) in ПОКАЗЫ.items():
        совпали = [род for род, о in _ОБРАЗЦЫ[язык] if о.fullmatch(с)]
        assert len(совпали) == 1, f"две рамки на одной записи ({совпали}): {с}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
