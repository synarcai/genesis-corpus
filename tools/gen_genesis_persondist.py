#!/usr/bin/env python3
"""GENESIS layer: РАЗЛИЧЕНИЕ ЛИЦА — see tools/persondistforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Сколько форм различает» и «какие лица совпали» идут вместе: первое даёт ЧИСЛО, второе
отнимает вывод «значит, совпали случайные» — совпадения объявлены таблицей.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Совпавших различает местоимение» и «ступень лестницы» — второй группой: обе о том, что
совпадение НЕ ЕСТЬ ПОТЕРЯ. Первая внутрь языка, вторая — сравнением всех двенадцати.

«Отказ свода назван» и «спрошено и отвечено» — третьей: первый показывает ТУ САМУЮ строку,
которую свод отвергает.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import persondistforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_persondist.txt"
ГРУППЫ = (("сколько форм различает", "какие лица совпали"),
          ("совпавших различает местоимение", "ступень лестницы"),
          ("отказ свода назван", "спрошено и отвечено"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
