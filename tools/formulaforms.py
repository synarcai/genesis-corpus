#!/usr/bin/env python3
"""ДОМ ЯЗЫКА ФОРМУЛ — запись формулы словами, по ГЛУБИНЕ дерева.

Мир `formula_lang` (2 583 строки) стоял без объявленного рода. Роды его были в кузнице с
первого дня и назывались там ГРУППАМИ: четыре глубины дерева и квадратные уравнения.

    ГЛУБИНА ЗДЕСЬ И ЕСТЬ ПРЕДМЕТ УРОКА, а не мера сложности: «модуль a» и «модуль суммы
    корня и синуса» суть разные умения, и мешать их в один род значило бы звать одним именем
    первый шаг и пятый.
"""

import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import formula_lang as фл  # noqa: E402

ПЕРЕМЕННЫЕ = ("a", "b", "c", "x", "y", "n")
# РОДЫ УЗЛОВ, ПОКАЗЫВАЕМЫЕ СЛОЕМ. Прибавить род — значит объявить его
# в доме формул; здесь он лишь называется.
# РАВЕНСТВО НЕ ВХОДИТ В СЛУЧАЙНЫЕ УЗЛЫ. Случайное «=» рождает ЛОЖНОЕ
# равенство («| 9 | = 4 + 11»), а корпус не смеет нести ложь даже
# примером конверсии: арифметический суд поймал две такие строки в тот
# же час, и он был прав. Равенство ставится ОТДЕЛЬНО — и правая часть
# ВЫЧИСЛЯЕТСЯ из левой, а не бросается жребием.
УЗЛЫ = ("+", "-", "*", "/", "^", "корень", "модуль", "функ", "сумма")
ФУНКЦИИ = ("sin", "cos", "log")


def дерево(r, глубина):
    """Дерево объявленной глубины — построено, а не выписано."""
    if глубина <= 0:
        return (фл.чис(r.randint(1, 20)) if r.random() < 0.5
                else фл.пер(r.choice(ПЕРЕМЕННЫЕ)))
    род = r.choice(УЗЛЫ)
    if род == "корень":
        return ("корень", дерево(r, глубина - 1))
    if род == "модуль":
        return ("модуль", дерево(r, глубина - 1))
    if род == "функ":
        return ("функ", r.choice(ФУНКЦИИ), дерево(r, глубина - 1))
    if род == "сумма":
        return ("сумма", "i", дерево(r, глубина - 1),
                дерево(r, глубина - 1), дерево(r, глубина - 1))
    return (род, дерево(r, глубина - 1), дерево(r, глубина - 1))


def показы_глубины(шаг, глубина, сколько):
    """Конверсия обеими сторонами и на двух языках, одной глубины."""
    r = random.Random(1000 * глубина + шаг)
    вон = []
    for k in range(сколько):
        д = дерево(r, глубина)
        # КАЖДЫЙ ТРЕТИЙ ПОКАЗ — РАВЕНСТВО, И ОНО ИСТИННО ПО ПОСТРОЕНИЮ:
        # правая часть есть ВЫЧИСЛЕННАЯ величина левой. Открытое дерево
        # (со свободной переменной) величины не имеет и равенством не
        # становится — это свойство выражения, а не отказ прибора.
        if k % 3 == 2:
            в = фл.значение(д)
            if в is not None and в >= 0:
                д = ("=", д, фл.чис(в))
        лат, гл = фл.латех(д), фл.глиф(д)
        ен, ру = фл.слова(д, "en"), фл.слова(д, "ru")
        # ХОДЫ СВЕРЯЮТСЯ ПЕРЕД ПОКАЗОМ: дерево, не вернувшееся всеми
        # обратными ходами, не имеет права стать строкой корпуса.
        if (фл.разобрать_глиф(гл) != д
                or фл.разобрать_слова(ен, "en") != д
                or фл.разобрать_слова(ру, "ru") != д):
            continue
        вон.append((f"$ {лат} $ in words is {ен}.", "en"))
        вон.append((f"{ен} in symbols is $ {лат} $.", "en"))
        вон.append((f"$ {лат} $ в словах есть {ру}.", "ru"))
        вон.append((f"{ру} в записи есть $ {лат} $.", "ru"))
        вон.append((f"$ {лат} $ in glyphs is {гл}.", "en"))
        вон.append((f"{гл} в словах есть {ру}.", "ru"))
        вон.append((f"how is $ {лат} $ said in words? $ {лат} $ in "
                   f"words is {ен}.", "en"))
        вон.append((f"как читается $ {лат} $? $ {лат} $ в словах есть "
                   f"{ру}.", "ru"))
    return вон


def квадратные(шаг):
    """УРАВНЕНИЕ, ПРОЧИТАННОЕ ВСЛУХ, и оно же записью.

    «x squared minus five x plus six equals zero» — так уравнение
    произносят, и корпус, знавший только описательную речь («the sum
    of …»), не узнал бы его на слух. Коэффициенты выводятся из корней
    по Виете: показ несёт не случайные числа, а уравнение, у которого
    корни ЕСТЬ.
    """
    вон = []
    for i in range(10):
        r1 = 1 + (шаг + i) % 9
        r2 = 1 + (шаг * 3 + i * 2) % 11
        b, c = r1 + r2, r1 * r2
        x = фл.пер("x")
        д = ("=", ("+", ("-", ("^", x, фл.чис(2)),
                         ("*", фл.чис(b), x)), фл.чис(c)), фл.чис(0))
        if not фл.читается_вслух(д):
            continue
        гл, лат = фл.глиф(д), фл.латех(д)
        for яз, вопрос, связка in (
                ("en", "how is {г} read aloud?", "read aloud is"),
                ("ru", "как читается вслух {г}?", "вслух читается как")):
            вслух = фл.инфикс(д, яз)
            вон.append((f"{гл} {связка} {вслух}.", яз))
            вон.append((f"{вслух} in glyphs is {гл}." if яз == "en"
                        else f"{вслух} в записи есть {гл}.", яз))
            вон.append((f"{вопрос.format(г=гл)} {гл} {связка} {вслух}.", яз))
        вон.append((f"$ {лат} $ in glyphs is {гл}.", "en"))
    return вон

# ------------------------------------------------------------------ ОБЪЯВЛЕНИЕ ДОМА

ГЛУБИНЫ = (1, 2, 3, 4)
РОДЫ = tuple(f"глубина {г}" for г in ГЛУБИНЫ) + ("квадратные",)

ЗАЧЕМ_РОДА = {
    **{f"глубина {г}": f"формула дерева глубины {г}, сказанная словами" for г in ГЛУБИНЫ},
    "квадратные": "квадратное уравнение: запись, чтение словами и корни",
}


def группы(шаг):
    """[[(страница, язык)]] — ровно те группы и в том порядке, какими кормится кузница."""
    return ([показы_глубины(шаг, г, 14) for г in ГЛУБИНЫ] + [квадратные(шаг)])


def группы_страниц(шаг):
    """[[страница]] — то же без меток: этим кормится `emit_grouped`."""
    return [[с for с, _я in г] for г in группы(шаг)]


def перебор_с_языком(шаг):
    """[(страница, род, ЯЗЫК)] — язык проставлен при каждой рамке.

    ЗАПИСЬ ФОРМУЛЫ ВНЕЯЗЫЧНА, А РЕЧЬ О НЕЙ — НЕТ. «$ x^2 $ in words is x squared» говорит
    по-английски о записи, которой язык не нужен; «$ x^2 $ в словах есть икс в квадрате» —
    по-русски о ней же. Язык страницы есть язык ОБЁРТКИ, и он был известен рамке.
    """
    вон = []
    for имя, группа in zip(РОДЫ, группы(шаг)):
        for с, язык in группа:
            вон.append((с, имя, язык))
    return вон


def перебор(шаг):
    """[(страница, род)] — те же группы, но каждая под своим именем."""
    return [(с, р) for с, р, _я in перебор_с_языком(шаг)]


def _показы():
    """{строка свода: (язык, род)} — ПОСТРОЧНО: свод построчен, а показ бывает многострочен."""
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род, язык in перебор_с_языком(шаг):
            for строка in с.split("\n"):
                if строка.rstrip():
                    вон.setdefault(строка.rstrip(), (язык, род))
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, а не с кортежем."""
    assert all(isinstance(р, str) for р in РОДЫ), "РОДЫ обязаны быть рядом ИМЁН"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    assert len(группы(0)) == len(РОДЫ), "групп не столько, сколько родов"
    assert all("\n" not in к for к in ПОКАЗЫ), "словарь показов обязан быть построчным"
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка()
