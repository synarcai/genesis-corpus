def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, а не с кортежем.

    ГРУППА И РОД БОЛЬШЕ НЕ ОДНО И ТО ЖЕ (14.09): группа падежей называет свои строки сама,
    по одному роду на падеж, и потому число групп с числом родов не сходится. Сверяется то,
    что и должно: имена групп — с рядом `ИМЕНА_ГРУПП`, а всякий кованый род — с объявлением.
    """
    имена = tuple(с.__name__ for с in ГРУППЫ)
    ждём = tuple(и if и is not None else "падежи" for и in ИМЕНА_ГРУПП)
    assert имена == ждём, f"кортеж {имена} разошёлся с рядом групп {ждём}"
    сколько = len(группы(0))
    assert сколько == len(ГРУППЫ), f"проход даёт {сколько} групп при {len(ГРУППЫ)} строителях"
    кованые = {р for _с, р in перебор(0)}
    вне = кованые - set(РОДЫ)
    assert not вне, f"род кован и не объявлен: {sorted(вне)}"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка()
