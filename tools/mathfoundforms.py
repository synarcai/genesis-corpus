def мощность(шаг):
    """Мощность конечного и счётность бесконечного."""
    вон = []
    буквы = "a b c d e f g h".split()
    for n in range(1, 9):
        если = " ".join(буквы[:n])
        вон.append(f"мощность множества {{{если}}} равна {n}.")
