#
#     СТЕНД, БЕРУЩИЙ ЧИСЛА ИЗ ТЕХ ЖЕ ФУНКЦИЙ, ЧТО И КОРПУС, СПРАШИВАЕТ О ТОМ, ЧТО САМ
#     ЖЕ И ПОКАЗАЛ. Такая мера отвечается ПАМЯТЬЮ: она завышена и нечувствительна разом
#     — рост её не говорит о росте понимания, а падение не говорит о его убыли.
#
# ЛЕЧЕНИЕ — НЕ ПОДСТАНОВКА ГОТОВОГО СПИСКА, А ЗАТВОР В САМОМ СТЕНДЕ: число берётся из
# ряда до тех пор, пока его ВОПРОС не окажется свободным от свода. Так стенд чинит себя
# сам при всяком росте корпуса, а список, вписанный рукой, устарел бы в первый же день.
#
# ЧТО СЧИТАЕТСЯ НЕСВОБОДНЫМ: вопрос СО СВОИМИ ЧИСЛАМИ, стоящий в своде. Голая
# формулировка («how far did the frog jump») несвободной не считается — родам корпус
# учит нарочно, и течёт ПАРА «вопрос с числами → ответ», ибо только она отвечается
# памятью.
_СВОДЫ = (КОРЕНЬ / "datasets" / "GENESIS-FULL.txt",
          pathlib.Path("/tmp/full27.txt"))
_ТЕКСТ = None


def свободен(вопрос):
    """Не стои́т ли этот вопрос со своими числами ни в одном из сводов."""
    global _ТЕКСТ
    if _ТЕКСТ is None:
        _ТЕКСТ = []
        for п in _СВОДЫ:
            try:
                _ТЕКСТ.append(п.read_text(encoding="utf-8", errors="replace").lower())
            except OSError:
                pass
    н = вопрос.lower().strip()
    return all(н not in т for т in _ТЕКСТ)

# ПОВЕРХНОСТЬ ОБЪЯВЛЯЕТСЯ И ДЛЯ ВЕРДИКТА, А НЕ ТОЛЬКО ДЛЯ ЗНАЧЕНИЯ (07.09, замер omega-ad).
#
# Полоса несла 128 тактов с `{"kind": "verdict", "v": "no"}` и 48 со значением; прибор снятия
# (`exam_runner`) читает лишь значение — и зачёл 48 из 176, назвав 123 верных ответа лживыми.
# Ответы читателя были ПРАВИЛЬНЫ («is 142 a prime number?» → «no: 142 = 2 × 71»), лгало число.
#
#     ПОЛОСА, ГОВОРЯЩАЯ РОДОМ, КОТОРОГО ПРИБОР НЕ ЗНАЕТ, МЕРИТ ПРИБОР, А НЕ ЧИТАТЕЛЯ. Чинить
#     прибор — дело того, чей он; но полоса обязана говорить и на общем языке, ибо
#     договориться о роде можно, а угадать его нельзя.
#
# Потому вердикт несёт `surfaces` — те же слова, что и `v`, — и всякий прибор, умеющий
# сверять поверхности, зачтёт такт, не зная слова «verdict».
def _вердикт(яз, да_ли):
    слово = ("yes" if яз == "en" else "да") if да_ли else ("no" if яз == "en" else "нет")
    return {"kind": "verdict", "v": слово, "surfaces": [слово]}

ЛОЖНЫЕ = {
    "prime": ("a prime number is a whole number whose only divisor is itself.", "простое число — это целое число, у которого один делитель — оно само."),
    "divisible": ("a number is divisible by another when the remainder is 1.", "число делится на другое, когда остаток равен единице."),
    "root": ("a root of an equation is any value of x.", "корень уравнения — это любое значение x."),
    "mean": ("the mean of a list is its largest number.", "среднее набора — это его наибольшее число."),
    "median": ("the median of a list is its first number.", "медиана набора — это его первое число."),
}


_ВЗЯТЫЕ = set()
_ВЗЯТЫЕ_НАБОРЫ = set()
_ВЗЯТЫЕ_ПАРЫ = set()


def _свободное_число(n, вопрос, предел=400):
    """Первое ЕЩЁ НЕ ВЗЯТОЕ число от n вверх, чей вопрос свободен от свода.

    ВЗЯТЫЕ ПОМНЯТСЯ, ИБО СВОБОДНЫЙ ПОИСК СХОДИТСЯ К ОДНОМУ (07.09). Свод пишет вопрос о
    простоте для всех чисел до 141 подряд; поиск «первого свободного вверх» от каждого
    из шести начальных дал 142 всем шести — и стенд стал спрашивать об одном числе
    двадцать четыре раза.

        МЕРА, СПРАШИВАЮЩАЯ ОБ ОДНОМ ПРЕДМЕТЕ ДВАДЦАТЬ ЧЕТЫРЕ РАЗА, ЕСТЬ ОДНА ПРОБА,
        ПОВТОРЁННАЯ ДВАДЦАТЬ ЧЕТЫРЕ РАЗА. Разнообразие такта есть часть меры, а не
        её украшение: род, показанный одним числом, не отличить от заученного.
    """
    x = n
    while x < предел:
        if x not in _ВЗЯТЫЕ and all(свободен(в) for в in вопрос(x)):
            _ВЗЯТЫЕ.add(x)
            return x
        x += 1
    return n        # свободного не нашлось — берём как было, и течь скажет прибор


def _свободный_набор(набор, вопрос, сдвигов=60):
    """Набор, сдвинутый на общее слагаемое, пока его вопрос не свободен.

    СДВИГ ОБЩИМ СЛАГАЕМЫМ СОХРАНЯЕТ МЕДИАНУ КАК ПОРЯДОК И СРЕДНЕЕ КАК ДЕЛЕНИЕ: род
    задачи не меняется, меняются лишь числа. Замена набора чужим сменила бы и род.
    """
    for d in range(0, сдвигов):
        новый = [x + d for x in набор]
        ключ = tuple(новый)
        if ключ not in _ВЗЯТЫЕ_НАБОРЫ and all(свободен(в) for в in вопрос(новый)):
            _ВЗЯТЫЕ_НАБОРЫ.add(ключ)
            return новый
    return list(набор)


def _свободные_пары(шаг, запас=40):
    """Пары корней, чьё уравнение свод не писал (сдвиг обоих корней вверх)."""
    вон = []
    for r1, r2 in E.пары(шаг):
        # ПАРА С НУЛЁМ НЕ СДВИГАЕТСЯ СВОИМ ДЕЛЕНИЕМ (07.09, третий заход): у пары
        # (0, 4) уравнение есть «x² − 4x = 0» без свободного члена, и сдвиг обоих
        # корней даёт «x² − 6x + 5», где нуля уже нет; но исходная пара свободной так
        # и не становится, а цикл выходил по первому же успеху СДВИНУТОЙ.
        #
        #     ПОИСК СВОБОДНОГО ЗАМЕНИТЕЛЯ ОБЯЗАН ПРОВЕРЯТЬ ТО, ЧТО ВЕРНЁТ, А НЕ ТО, С
        #     ЧЕГО НАЧАЛ. Иначе затвор доложит об успехе, а наружу выйдет исходное.
        for d in range(1, запас):
            a, b = r1 + d, r2 + d
            s, p = E.по_виете(a, b)
            # ЗАТВОР СПРАШИВАЕТ ОБА ЯЗЫКА, А НЕ ОДИН (07.09, второй шрам того же часа).
            # Первая редакция проверяла лишь английскую форму — и шестнадцать русских
            # тактов «является ли 4 корнем x^2 - 4 x = 0?» прошли мимо: свод пишет это
            # уравнение по-русски, а по-английски не пишет.
            #
            #     ЗАТВОР, ПРОВЕРЯЮЩИЙ ОДИН ЯЗЫК ИЗ ДВУХ, ЗАКРЫТ НАПОЛОВИНУ. Такт живёт
            #     на обоих языках, и свободен он лишь тогда, когда свободны ОБА.
            ур = E.уравнение(s, p)
            if ((a, b) not in _ВЗЯТЫЕ_ПАРЫ
                    and свободен(f"is {a} a root of {ур}?")
                    and свободен(f"является ли {a} корнем {ур}?")
                    and свободен(f"is {r2 + d + 1} a root of {ур}?")
                    and свободен(f"является ли {r2 + d + 1} корнем {ур}?")):
                _ВЗЯТЫЕ_ПАРЫ.add((a, b))
                вон.append((a, b))
                break
        if len(вон) >= 3:
            break
    return вон or E.пары(шаг)


