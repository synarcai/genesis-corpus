"""ДОМ ОТРИЦАНИЯ КВАНТОРА — «не все красные» и «все не красные» суть РАЗНЫЕ высказывания.

    ОТРИЦАНИЕ, ПОСТАВЛЕННОЕ В ДРУГОЕ МЕСТО, ЕСТЬ ДРУГОЕ ВЫСКАЗЫВАНИЕ, ХОТЯ СЛОВА ТЕ ЖЕ
    И ПОРЯДОК ИХ ПОЧТИ ТОТ ЖЕ.

ПОВОД, ЗАМЕРЕННЫЙ 12.09 по девятому десятку понятий: «не все ≠ все не» — ноль упоминаний
и ноль показов; «отрицание квантора» — ноль и ноль. А кванторы свод показывает: дом
`quantforms` считает красные и зелёные яблоки в корзине и отвечает «все ли красные? нет:
3 зелёных».

СОСЕД И РАЗЛИЧИЕ. Тот дом о СЧЁТЕ при кванторе — сколько их и каков свидетель. Этот — о
ПРЕОБРАЗОВАНИИ отрицания: какое высказывание равносильно какому, и какое НЕ равносильно.
Счёт здесь лишь свидетель, а предмет — равносильность.

ЧЕТЫРЕ РАВНОСИЛЬНОСТИ И ОДНО РАЗЛИЧИЕ:

    неверно, что ВСЕ красные       ≡  ХОТЯ БЫ ОДИН не красный
    неверно, что ХОТЯ БЫ ОДИН      ≡  НИ ОДИН не красный
    неверно, что НИ ОДИН           ≡  ХОТЯ БЫ ОДИН красный
    НЕ ВСЕ красные                 ≢  ВСЕ НЕ красные

ПОСЛЕДНЯЯ СТРОКА ЕСТЬ СЕРДЦЕ ДОМА, и показана она ТРЕМЯ МЕШКАМИ, а не одним:

    смешанный (2 из 4 красных)   «не все» ИСТИННО, «все не» ЛОЖНО — вот где они расходятся
    пустой (0 из 4)              оба ИСТИННЫ — совпали
    полный (4 из 4)              оба ЛОЖНЫ — совпали

    ДВА ВЫСКАЗЫВАНИЯ, СОВПАДАЮЩИЕ В ДВУХ СЛУЧАЯХ ИЗ ТРЁХ, РАЗЛИЧАЮТСЯ ИМЕННО В ТРЕТЬЕМ,
    И ПОКАЗАТЬ НАДО ВСЕ ТРИ: читатель, видевший лишь совпадения, решит, что это одно
    высказывание, и будет прав ровно до первого смешанного мешка.

ВСЯКОЕ УТВЕРЖДЕНИЕ НЕСЁТ СВОЙ СЧЁТ, и потому проверяется пересчётом: «красных 2, а шаров
4» есть и довод, и свидетель разом.

    python3 tools/negquantforms.py     # самопроверка с мутантами
"""
