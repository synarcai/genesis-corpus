#!/usr/bin/env python3
"""ДОМ УМНОЖЕНИЯ ДОЛЕЙ — умножение НЕ ВСЕГДА УВЕЛИЧИВАЕТ, и это показано счётом.

    УМНОЖЕНИЯ ДОЛЕЙ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по мирам показов: «2/5 × 3»,
    «\\d+ × \\d/\\d» — НОЛЬ вхождений; «доля от доли», «половина от трети» — НОЛЬ; деление на
    долю — НОЛЬ. Дом сложения долей уже приводит их к общему знаменателю, дом сравнения знает
    их порядок, а перемножить две доли не умеет никто.

ГЛАВНОЕ ЗДЕСЬ — ВТОРОЙ РОД, И ОН ПРОТИВ ПРИВЫЧКИ:

    ВСЮДУ УМНОЖЕНИЕ УВЕЛИЧИВАЕТ. Половина от трети есть ШЕСТАЯ — меньше и половины, и трети.
    Читатель, знающий умножение лишь на целых, ждёт роста и получает убыль.

ЧЕТЫРЕ РОДА:

    на число   2/5 × 3: числитель умножается, а знаменатель остаётся: 2 × 3 = 6,
               и выходит 6/5.                                     ← ЗДЕСЬ РАСТЁТ
    доля доли  1/2 × 1/3: умножаются и числители, и знаменатели: 1 × 1 = 1, и 2 × 3 = 6,
               и выходит 1/6, а 1/6 меньше и 1/2, и 1/3.           ← ЗДЕСЬ УБЫВАЕТ
    единица    1/3 × 3: … и выходит 3/3, а это ровно единица.      ← ВОЗВРАТ К ЦЕЛОМУ
    больше     3/4 × 3: … и выходит 9/4, а это больше единицы: 9 = 4 × 2 + 1.

ПЕРВЫЙ И ВТОРОЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО НАПРАВЛЕНИЮ — как «один знаменатель» и «один
числитель» в доме сравнения. Разница видна в одном месте: умножается ли ЗНАМЕНАТЕЛЬ. Умножили
на целое — знаменатель цел, доля растёт; умножили на долю — знаменатель вырос, доля убыла.

    УБЫЛЬ ОТ УМНОЖЕНИЯ НЕ ОБЪЯВЛЯЕТСЯ, А ПОКАЗЫВАЕТСЯ: «1/6 меньше и 1/2, и 1/3» стои́т в
    строке, и суд сверяет это сравнение по числам.

ТРЕТИЙ РОД ЗАМЫКАЕТ КРУГ: доля, умноженная на свой знаменатель, даёт целое — и потому доля
есть не иная порода числа, а то же число, только делённое.

ЧЕТВЁРТЫЙ СМЫКАЕТ ДОМ С СОСЕДОМ: произведение выходит за единицу, и разбор берётся тем же
ледже́ром, каким живёт дом дроби и единицы.

    python3 tools/mulshareforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("на число", "доля доли", "единица", "больше")

РАМКИ = {
    "ru": {
        "на число": "{a}/{b} × {k}: числитель умножается, а знаменатель остаётся: {a} × {k} = {n}, и выходит {n}/{b}.",
        "доля доли": "{a}/{b} × {c}/{d}: умножаются и числители, и знаменатели: {a} × {c} = {n}, и {b} × {d} = {m}, и выходит {n}/{m}, а {n}/{m} меньше и {a}/{b}, и {c}/{d}.",
        "единица": "{a}/{b} × {k}: числитель умножается, а знаменатель остаётся: {a} × {k} = {n}, и выходит {n}/{b}, а это ровно единица.",
        "больше": "{a}/{b} × {k}: числитель умножается, а знаменатель остаётся: {a} × {k} = {n}, и выходит {n}/{b}, а это больше единицы: {n} = {b} × {q} + {r}.",
    },
    "en": {
        "на число": "{a}/{b} × {k}: the numerator is multiplied and the denominator stays: {a} × {k} = {n}, and it gives {n}/{b}.",
        "доля доли": "{a}/{b} × {c}/{d}: both numerators and denominators are multiplied: {a} × {c} = {n}, and {b} × {d} = {m}, and it gives {n}/{m}, and {n}/{m} is less than both {a}/{b} and {c}/{d}.",
        "единица": "{a}/{b} × {k}: the numerator is multiplied and the denominator stays: {a} × {k} = {n}, and it gives {n}/{b}, and that is exactly one.",
        "больше": "{a}/{b} × {k}: the numerator is multiplied and the denominator stays: {a} × {k} = {n}, and it gives {n}/{b}, and that is greater than one: {n} = {b} × {q} + {r}.",
    },
}


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        пусто = dict(c=0, d=0, m=0, q=0, r=0)
        # МНОЖИТЕЛЬ ДО ПЯТИ, А НЕ ДО СЕМИ: род «больше единицы» иначе набирает вчетверо
        # против «на число», и дом учит выходу за единицу больше, чем самому умножению.
        for b in range(2, 11):
            for a in range(1, b):
                for k in range(2, 6):
                    n = a * k
                    поля = dict(пусто, a=a, b=b, k=k, n=n)
                    if n < b:
                        вон[рамки["на число"].format(**поля)] = (язык, "на число")
                    elif n == b:
                        вон[рамки["единица"].format(**поля)] = (язык, "единица")
                    else:
                        вон[рамки["больше"].format(**dict(поля, q=n // b, r=n % b))] = (
                            язык, "больше")
        # ДОЛЯ ОТ ДОЛИ: обе меньше единицы, и произведение обязано быть МЕНЬШЕ ОБЕИХ —
        # иначе строка утверждала бы то, чего нет.
        # РЯД ДОЛИ ОТ ДОЛИ СУЖЕН ПО ЗАМЕРУ: при полном переборе он давал 441 страницу против
        # 14 у рода «ровно единица» — перекос в тридцать раз, и дом читался бы как дом одного
        # рода с тремя приложениями. Числители до трёх показывают закон не хуже.
        for b in range(2, 8):
            for a in range(1, min(4, b)):
                for d in range(2, 8):
                    for c in range(1, min(4, d)):
                        n, m = a * c, b * d
                        if n * b >= a * m or n * d >= c * m:
                            continue
                        вон[рамки["доля доли"].format(
                            a=a, b=b, c=c, d=d, n=n, m=m, k=0, q=0, r=0)] = (
                            язык, "доля доли")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ДРОБНАЯ ЧЕРТА ЕСТЬ ГРАНИЦА ЧИСЛА: без оглядки на «/» счёт читается сквозь дробь.
_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ОСТАТОК = re.compile(r"(?<![/\d])(\d+) = (\d+) × (\d+) \+ (\d+)(?![/\d])")
_МЕНЬШЕ_ДОЛЕЙ = re.compile(
    r"(\d+)/(\d+) (?:меньше и|is less than both) (\d+)/(\d+), (?:и|and) (\d+)/(\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: произведения, ледже́р и САМА УБЫЛЬ, сверенная
    # перекрёстным умножением, а не принятая на слово.
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, q, r in _ОСТАТОК.findall(с):
        if int(a) != int(b) * int(q) + int(r) or int(r) >= int(b):
            return True, False
    for n, m, a, b, c, d in _МЕНЬШЕ_ДОЛЕЙ.findall(с):
        if int(n) * int(b) >= int(a) * int(m) or int(n) * int(d) >= int(c) * int(m):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    дд = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "доля доли")
    нч = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "на число")
    if судить(нч.replace("остаётся", "остаётс"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(дд.replace("меньше", "больше", 1))[1] is not False:
        беды.append("подмена направления прошла")
    if судить(нч + " " + нч)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"УМНОЖЕНИЕ ДОЛЕЙ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
