def _ш(n, язык):
    """Счётная форма шага — оба языка по своему закону, и ни один по догадке."""
    return rugram.форма("шаг", n) if язык == "ru" else by_count(n, "steps")


def _з(n):
    """Число письмом свода: минус есть знак «−», а не дефис."""
    return f"−{abs(n)}" if n < 0 else str(n)


