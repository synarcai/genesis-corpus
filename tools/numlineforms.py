        if not (a < 0 and b < 0):
            беды.append(f"не оба отрицательны: {(a, b)}")
        if not a < b:
            беды.append(f"левое не левее правого: {(a, b)}")
        if not abs(a) > abs(b):
            беды.append(f"цифры не лгут в этой паре, ловушка не видна: {(a, b)}")
