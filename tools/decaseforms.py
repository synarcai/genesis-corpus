def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for имя, род, дат, вин, ру, ан, ру_пред, ру_вин in ИМЕНА:
            общ = dict(имя=имя, дат=дат, вин=вин, ру=ру, ан=ан,
                       ру_пред=ру_пред, ру_вин=ру_вин,
                       ан_место=f"in {ан}", ан_напр=f"into {ан}",
                       дат_предлог=ТОЛЬКО_ДАТ[0], вин_предлог=ТОЛЬКО_ВИН[0])
            for род_страницы in ("не всякий предлог таков", "сосед различает иначе"):
                вон[рамки[род_страницы].format(предлог="in", **общ)] = (язык, род_страницы)
            # ТРИ ПРЕДЛОГА ИЗ ДЕВЯТИ, И ЭТО ГРАНИЦА, А НЕ ЛЕНЬ: показаны те, чьи слитные формы
            # свод пишет тысячами («im», «am»), и «auf», который не сливается вовсе.
            for предлог in ("in", "an", "auf"):
                for род_страницы in ("один предлог, два падежа", "вопрос отличает"):
                    вон[рамки[род_страницы].format(предлог=предлог, **общ)] = (
                        язык, род_страницы)
            for место_гл, напр_гл, ру_место, ру_напр in ГЛАГОЛЫ:
                вон[рамки["падеж выбирает глагол"].format(
                    имя="das Buch", имя2=имя, дат=дат, вин=вин,
                    место_гл=место_гл, напр_гл=напр_гл,
                    ру_место=f"книга {ру_место} {ру_пред}",
                    ру_напр=f"книга {ру_напр} {ру_вин}")] = (язык, "падеж выбирает глагол")
