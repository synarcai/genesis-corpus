#!/usr/bin/env python3
"""СЛОЙ GENESIS: МИР УРАВНЕНИЙ — буква, стоящая вместо значения.

ЧЕГО КОРПУСУ НЕ ХВАТАЛО. Корпус знал число и знал счёт: он умножал,
делил, раскладывал на простые. Но во всём этом ЧИСЛО БЫЛО ИЗВЕСТНО
ЗАРАНЕЕ. Уравнение начинается там, где число НЕ известно, и на его
месте стоит буква; и первое, чего требует уравнение, — не формулы, а
ДВУХ ПОСТУПКОВ, которых не бывает в арифметике:

    ПОДСТАВИТЬ    — взять значение, поставить его вместо буквы и
                    ПОСЧИТАТЬ, что вышло;
    ВЫНЕСТИ ВЕРДИКТ — сказать «да» или «нет» ПО РЕЗУЛЬТАТУ СЧЁТА, а не
                    по виду записи.

Оттого главный показ этого мира не «корень равен двум», а «is 2 a root
of x^2 - 5 x + 6 = 0? yes: 4 - 10 + 6 = 0.» — вердикт И ОСНОВАНИЕ
РЯДОМ, где основание есть ПОСЧИТАННАЯ ПОДСТАНОВКА, а не переписанное
уравнение. Показ, повторяющий уравнение вместо счёта, учит списывать.

ЛЕСТНИЦА ОДНА НА ВСЕ РОДЫ. Форма взята у слоя дознания и не написана
заново: РОД ОБЪЯВЛЯЕТ ЧЕТВЁРКУ — определение, исполнение, контрпример,
обобщение, — а обход лестницы один. Прибавить род сюда стоит одного
объявления и ни строки механизма; это и есть проба, что форма есть
форма, а не шаблон.

ПЯТЬ РОДОВ ЭТОГО МИРА:

    КОРЕНЬ        — что такое корень, и как подстановка решает дело;
    ПЕРЕМЕННАЯ    — буква стоит вместо ЗНАЧЕНИЯ, а не вместо числа,
                    которое уже известно; у одного уравнения корней
                    бывает два, и это убивает «у уравнения один корень»;
    РАЗЛОЖЕНИЕ    — Виета ПОКАЗАМИ, а не формулой в лоб: сумма и
                    произведение корней стоят рядом с самим
                    разложением, и каждое из трёх можно пересчитать;
    ОТКАЗ         — уравнение, у которого целого корня НЕТ, и основание
                    отказа названо: всякое значение отрезка даёт
                    остаток. Отказ есть ПОЛНОПРАВНЫЙ ОТВЕТ, и у него
                    обязана быть вопросная поверхность, иначе организм
                    выучит, что на вопрос всегда есть число;
    КВАДРАТНЫЙ КОРЕНЬ — обратная поверхность квадрата: «квадрат 15 есть
                    225, значит квадратный корень из 225 есть 15».

КОЭФФИЦИЕНТЫ НЕ НАЗНАЧАЮТСЯ, А ВЫВОДЯТСЯ. Случаи не перечислены
списком: берутся ЦЕЛЫЕ КОРНИ ИЗ ДИАПАЗОНА, зависящего от номера
прохода, и коэффициенты выводятся из них по Виете (b = -(r1 + r2),
c = r1 * r2). Оттого каждый проход несёт ДРУГИЕ уравнения, а не те же
самые в другом порядке, и объём покупает новые факты, а не вес.

ЗАКОН НУЛЕВОГО СЛАГАЕМОГО. Слагаемое, равное нулю, НЕ ПИШЕТСЯ ВОВСЕ —
ни в уравнении, ни в подстановке: «x^2 - 16 = 0» (b = 0) и
«x^2 - 5 x = 0» (c = 0) суть отдельные ЗАКОННЫЕ формы записи, а не
особые случаи. Организм, видевший лишь полную запись, читает укороченную
как испорченную. Потому шесть родов пар корней (оба положительных, оба
отрицательных, симметричные, нуль с положительным, нуль с
отрицательным, разных знаков) проходятся В КАЖДОМ ПРОХОДЕ: все шесть
форм записи показываются всегда.

ЗНАК СТАВИТСЯ ПО ЧИСЛУ, А НЕ ПО ОБРАЗЦУ: при b отрицательном пишется
«- 5 x», при положительном «+ 5 x», при единичном по величине —
«- x» без единицы, ибо «- 1 x» не пишет никто.

ОБА ЯЗЫКА НА ОДНИХ ЧИСЛАХ. Английский и русский говорят об ОДНОМ И ТОМ
ЖЕ уравнении с теми же корнями и тем же основанием, и судятся одним
пересчётом: дефект одной поверхности не может спрятаться за другой.

ЗА ЧИСЛОМ В РУССКОЙ СТРОКЕ НЕ СТОИТ ИМЯ — ЗАКОН, КУПЛЕННЫЙ ЧУЖИМ
СУДОМ. Первая редакция говорила «в x^2 - 3 x + 2 = 0 значение 1 даёт
1 - 3 + 2 = 0», и суд русского согласования объявил СОРОК таких строк
ложью — и был прав по своему роду: он увидел «0 значение», то есть
счётную пару «число + имя», где ноль пришёл из ХВОСТА УРАВНЕНИЯ, а имя
принадлежало следующей мысли. Уравнение кончается нулём всегда, и
всякое русское ИМЯ сразу за ним читается как сосчитанное этим нулём.
Оттого здесь за числом стоит предлог или глагол («при x = 1 выходит»),
но не имя: строка, говорящая две вещи, будет прочитана судом, знающим
одну.

ЧУЖОЙ РОД ПРОВЕРЕН НАРОЧНО. Арифметический суд корпуса читает всякую
строку со знаком «=», а здесь знак «=» стоит в каждом показе. Записи
подобраны так, чтобы тот суд либо судил их ВЕРНО (чистая подстановка
«4 - 10 + 6 = 0» есть истина и судится истиной), либо не судил вовсе
(строка с буквой между величинами ему нема). Ни одна строка слоя не
даёт ему (судимо, ложно) — это замерено, а не предположено.
"""

