# ---------------------------------------------------------- ЗАПИСЬ

def слагаемое(коэф, имя=""):
    """Слагаемое СО ЗНАКОМ ВПЕРЕДИ; НУЛЕВОЕ НЕ ПИШЕТСЯ ВОВСЕ.

    Три закона записи в одном месте, и все три — не украшение, а то,
    по чему строку узнаёт читатель:

      · НУЛЬ НЕ ПИШЕТСЯ. «x^2 + 0 x + 6 = 0» не пишет никто, и корпус,
        пишущий так, учит форме, которой в мире нет. Пустая строка
        отсюда — законная запись, а не пропуск;
      · ЕДИНИЦА ПРИ БУКВЕ НЕ ПИШЕТСЯ: «- x», а не «- 1 x». При голом
        числе единица пишется («+ 1»), ибо там она и есть величина;
      · ЗНАК СТОИТ ВПЕРЕДИ И ОТДЕЛЁН ПРОБЕЛАМИ. Пробелы не украшение:
        по ним арифметический суд корпуса режет запись на величины, и
        «x^2-5x+6=0» он прочёл бы одним комом.
    """
    if коэф == 0:
        return ""
    знак = "+" if коэф > 0 else "-"
    величина = abs(коэф)
    if имя and величина == 1:
        тело = имя
    elif имя:
        тело = f"{величина} {имя}"
    else:
        тело = str(величина)
    return f" {знак} {тело}"


def уравнение(b, c):
    """«x^2 - 5 x + 6 = 0» — приведённое квадратное по своим b и c."""
    return f"x^2{слагаемое(b, 'x')}{слагаемое(c)} = 0"


def множитель(корень):
    """«( x - 2 )» для корня 2, «( x + 4 )» для корня -4, «( x )» для 0.

    ЗАКОН НУЛЕВОГО СЛАГАЕМОГО ПРАВИТ И ЗДЕСЬ: у корня 0 множитель есть
    просто «( x )», и это та же самая укороченная запись, что
    «x^2 - 5 x = 0». Один закон, показанный в двух местах, читается
    как закон; два разных закона в двух местах читаются как случайность.
    """
    return f"( x{слагаемое(-корень)} )"


def значение(b, c, v):
    """Величина многочлена x^2 + b x + c при x = v."""
    return v * v + b * v + c


def основание(b, c, v):
    """(запись, итог) ПОСЧИТАННОЙ подстановки: «4 - 10 + 6 = 0».

    ОСНОВАНИЕ ЕСТЬ СЧЁТ, А НЕ ПЕРЕПИСАННОЕ УРАВНЕНИЕ. Ответ «yes: 2 is
    a root» ничего не показывает; ответ «yes: 4 - 10 + 6 = 0» показывает
    ровно тот поступок, которым вердикт добыт, и его можно пересчитать —
    и суд слоя его пересчитывает.

    ГОЛОВА ПИШЕТСЯ ВСЕГДА, ХВОСТ — ПО ЗАКОНУ НУЛЕВОГО СЛАГАЕМОГО. С
    квадрата счёт НАЧИНАЕТСЯ, и запись без головы не была бы записью
    вовсе («- 10 + 6 = -4» не есть подстановка); а нулевое слагаемое
    после головы не пишется ровно так же, как в самом уравнении.
    """
    запись = str(v * v) + слагаемое(b * v) + слагаемое(c)
    return f"{запись} = {значение(b, c, v)}", значение(b, c, v)


def по_виете(r1, r2):
    """(b, c) ПО КОРНЯМ: b = -(r1 + r2), c = r1 * r2.

    Коэффициенты не назначаются рукой — они ВЫВОДЯТСЯ из корней, и
    потому всякое уравнение слоя заведомо имеет объявленные корни.
    Обратный порядок (назначить коэффициенты, потом искать корни) дал
    бы либо перебор, либо список готовых случаев; и то и другое есть
    отказ от диапазона в пользу перечня.
    """
    return -(r1 + r2), r1 * r2


# ШЕСТЬ РОДОВ ПАР КОРНЕЙ — ВСЕ ЗАКОННЫЕ ФОРМЫ ЗАПИСИ РАЗОМ. Форма
# записи есть следствие ЗНАКОВ КОРНЕЙ, а не отдельная сущность:
# оба положительных дают «- 5 x + 6», оба отрицательных «+ 5 x + 6»,
# симметричные «- 16» (b обнулился), нуль с корнем «- 5 x» (c
# обнулился), разные знаки «- 3 x - 10». Перечислены здесь ПАРЫ, а не
# уравнения: уравнение выводится из пары, и потому таблица не стареет.
ФОРМЫ = (
    ("оба-плюс", lambda a, d: (a, a + d)),
    ("оба-минус", lambda a, d: (-(a + d), -a)),
    ("симметричные", lambda a, d: (-(a + d), a + d)),
    ("нуль-и-плюс", lambda a, d: (0, a + d)),
    ("минус-и-нуль", lambda a, d: (-(a + d), 0)),
    ("разных-знаков", lambda a, d: (-a, a + d + 1)),
)


def пары(шаг):
    """Шесть пар корней прохода: диапазоном по номеру прохода.

    ДИАПАЗОН, А НЕ СПИСОК. Основание (a, d) сдвигается номером прохода,
    и оттого пятикратный слой несёт пять РАЗНЫХ наборов уравнений, а не
    один набор пять раз. Объём тогда покупает факты, а не вес.
    """
    вон = []
    формы = [(и, в) for и, в in ФОРМЫ
             if _СО_ЗНАКОМ or и in ("оба-плюс", "нуль-и-плюс")]
    for i, (_имя, вывести) in enumerate(формы):
        a = 1 + (шаг * 2 + i) % 8
        d = 1 + (шаг + i) % 6
        вон.append(вывести(a, d))
    return вон


def свидетель_да(r1, r2):
    """Корень для показа «да»: тот, что дальше от нуля.

    НУЛЬ ПЛОХОЙ СВИДЕТЕЛЬ. Подстановка нуля в «x^2 - 5 x = 0» даёт
    «0 = 0» — истину, которая не показывает НИЧЕГО: все слагаемые
    исчезли по закону нулевого слагаемого, и поступка не видно. Пара,
    где один корень нуль, показывает «да» на другом корне; сам нуль как
    корень показан родом разложения, где он виден множителем «( x )».
    """
    return r1 if abs(r1) >= abs(r2) else r2


def свидетель_нет(r1, r2, сдвиг):
    """Значение ВНЕ отрезка корней — оттого подстановка заведомо > 0.

    ЗНАК ИТОГА ЗДЕСЬ НЕ УКРАШЕНИЕ. Между корнями многочлен
    ОТРИЦАТЕЛЕН, и основание вышло бы вида «1 - 5 = -4» — запись, где
    правая сторона начинается минусом. Такая запись честна, но она
    лишний род для чужих судов и лишняя развилка для читателя; взяв
    свидетеля за большим корнем, мы получаем итог строго
    положительный — и «нет» показывается остатком, а не знаком.
    """
    return max(r1, r2) + 1 + сдвиг % 3


