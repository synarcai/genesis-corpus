def исп_корень(шаг):
    """Подстановка с вердиктом: «да» на корне, «нет» на не-корне."""
    вон = []
    for i, (r1, r2) in enumerate(пары(шаг)):
        b, c = по_виете(r1, r2)
        ур = уравнение(b, c)
        да = свидетель_да(r1, r2)
        нет = свидетель_нет(r1, r2, шаг + i)
        осн_да, _ = основание(b, c, да)
        осн_нет, _ = основание(b, c, нет)
        вон.append(f"is {да} a root of {ур}? yes: {осн_да}.")
        вон.append(f"является ли {да} корнем {ур}? да: {осн_да}.")
        вон.append(f"is {нет} a root of {ур}? no: {осн_нет}.")
        вон.append(f"является ли {нет} корнем {ур}? нет: {осн_нет}.")
    return вон


def контр_корень(шаг):
    """«Всякое значение годится» убито ОДНИМ посчитанным свидетелем."""
    вон = []
    for i in range(4):
        r1 = 1 + (шаг + i) % 7
        r2 = r1 + 1 + (шаг * 2 + i) % 4
        b, c = по_виете(r1, r2)
        ур = уравнение(b, c)
        v = свидетель_нет(r1, r2, шаг + i)
        осн, итог = основание(b, c, v)
        вон.append(f"every value satisfies {ур} is false: at x = {v} it "
                   f"gives {осн}, and {итог} is not 0.")
        вон.append(f"всякое значение удовлетворяет {ур} — ложь: при "
                   f"x = {v} выходит {осн}, а {итог} не 0.")
    return вон


def общ_корень(шаг):
    """Закон, случаями которого были все вердикты рода."""
    вон = []
    for i in range(4):
        r1 = 1 + (шаг * 3 + i) % 9
        r2 = r1 + 1 + (шаг + i) % 5
        b, c = по_виете(r1, r2)
        ур = уравнение(b, c)
        r = r1 if i % 2 == 0 else r2
        осн, _ = основание(b, c, r)
        вон.append(f"a value is a root exactly when the substitution "
                   f"gives 0: in {ур} the value {r} gives {осн}.")
        вон.append(f"значение есть корень ровно тогда, когда подстановка "
                   f"даёт 0: в {ур} при x = {r} выходит {осн}.")
    return вон


