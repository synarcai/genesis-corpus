def бесплодное(шаг, i):
    """(b, c, начало, конец) уравнения, у которого корня ТАМ И ВПРЯМЬ НЕТ.

    ОТКАЗ ПРОВЕРЯЕТСЯ, А НЕ ОБЪЯВЛЯЕТСЯ. Написать «у x^2 - x + 7 = 0
    нет целого корня» легко; строка станет ложью в тот день, когда
    коэффициенты сдвинутся проходом. Потому здесь ИЩЕТСЯ: свободный
    член растёт, пока хоть одно значение отрезка обращает многочлен в
    нуль. Диапазон остаётся диапазоном, а истина остаётся истиной.

    Отдельно: при b от -1 до -4 и c не меньше семи вершина параболы
    стоит между нулём и двойкой, а её высота не меньше трёх — оттого
    многочлен на всём отрезке ПОЛОЖИТЕЛЕН, и в показах не заводится
    отрицательных величин.
    """
    начало = 0
    конец = 10 + (шаг + i) % 3
    b = -1 - (шаг + i) % 4
    c = 7 + (шаг * 3 + i) % 11
    while any(значение(b, c, v) == 0 for v in range(начало, конец + 1)):
        c += 1
    return b, c, начало, конец


def наименьшее(b, c, начало, конец):
    """(величина, значение x) наименьшей высоты многочлена на отрезке.

    Ничьи здесь бывают («x^2 - x + 7» равен семи и при нуле, и при
    единице), и потому суд обязан проверять не «это первый наименьший»,
    а «эта высота есть наименьшая, и она вправду достигается в названной
    точке». Прибор, требующий большего, чем утверждает показ, зовёт
    чинить исправное.
    """
    точки = range(начало, конец + 1)
    низ = min(значение(b, c, v) for v in точки)
    где = next(v for v in точки if значение(b, c, v) == низ)
    return низ, где


def исп_отказ(шаг):
    """Отказ с основанием — утверждением И ответом на вопрос.

    У ОТКАЗА ОБЯЗАНА БЫТЬ ВОПРОСНАЯ ПОВЕРХНОСТЬ. Корпус, где всякий
    вопрос кончается числом, учит, что число есть всегда; и организм,
    так выученный, на неразрешимом вопросе выдумает число вместо того,
    чтобы отказать. Отказ есть ответ, и спрашивать о нём надо так же,
    как обо всяком другом.
    """
    вон = []
    for i in range(4):
        b, c, начало, конец = бесплодное(шаг, i)
        ур = уравнение(b, c)
        англ = (f"{ур} has no whole root between {начало} and {конец}: "
                f"every value leaves a remainder.")
        рус = (f"у {ур} нет целого корня от {начало} до {конец}: всякое "
               f"значение даёт остаток.")
        вон.append(англ)
        вон.append(рус)
        вон.append(f"what are the whole roots of {ур} between {начало} "
                   f"and {конец}? {англ}")
        вон.append(f"каковы целые корни {ур} от {начало} до {конец}? "
                   f"{рус}")
    return вон


def контр_отказ(шаг):
    """«У всякого уравнения есть целый корень» убито наименьшей высотой."""
