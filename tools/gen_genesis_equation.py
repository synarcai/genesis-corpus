def _виета_показ(ур, м1, м2, r1, r2, c):
    """Английский и русский показ Виеты на ОДНИХ числах.

    ВИЕТА ПОКАЗАНА, А НЕ НАЗВАНА. Формула «сумма корней равна минус b»
    выучивается как заклинание и не проверяется ничем; здесь рядом
    стоят три вещи — само разложение, сумма и произведение, — и каждую
    из трёх можно пересчитать по записанному уравнению. Суд слоя все
    три и пересчитывает.
    """
    return [
        f"{ур} factors as {м1} {м2}: {r1} + {r2} = {r1 + r2} and "
        f"{r1} * {r2} = {c}; the roots are {r1} and {r2}.",
        f"{ур} раскладывается как {м1} {м2}: {r1} + {r2} = {r1 + r2} и "
        f"{r1} * {r2} = {c}; корни — {r1} и {r2}.",
    ]


def исп_разложение(шаг):
    """Разложение утверждением И ответом на вопрос — на всех формах."""
    вон = []
    for r1, r2 in пары(шаг):
        b, c = по_виете(r1, r2)
        ур = уравнение(b, c)
        англ, рус = _виета_показ(ур, множитель(r1), множитель(r2),
                                 r1, r2, c)
        вон.append(англ)
        вон.append(рус)
        вон.append(f"what are the roots of {ур}? {англ}")
        вон.append(f"каковы корни {ур}? {рус}")
    return вон


