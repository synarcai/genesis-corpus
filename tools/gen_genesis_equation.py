# РОД ОБЪЯВЛЯЕТ ЧЕТВЁРКУ И НИЧЕГО БОЛЬШЕ. Лестница ниже одна на все
# роды: прибавить род — значит объявить определение, исполнение,
# контрпример и обобщение, а не написать новый обход. Форма взята у
# слоя дознания без правок, и это её проба: она перенеслась на другой
# предмет ЦЕЛИКОМ.
РОДЫ = (
    ("root", ВОПР_КОРЕНЬ, ОПР_КОРЕНЬ, исп_корень, контр_корень,
     общ_корень),
    ("variable", ВОПР_ПЕРЕМЕННАЯ, ОПР_ПЕРЕМЕННАЯ, исп_переменная,
     контр_переменная, общ_переменная),
    ("factoring", ВОПР_РАЗЛОЖЕНИЕ, ОПР_РАЗЛОЖЕНИЕ, исп_разложение,
     контр_разложение, общ_разложение),
    ("no-whole-root", ВОПР_ОТКАЗ, ОПР_ОТКАЗ, исп_отказ, контр_отказ,
     общ_отказ),
    ("square-root", ВОПР_КВКОРЕНЬ, ОПР_КВКОРЕНЬ, исп_квкорень,
     контр_квкорень, общ_квкорень),
)


def ступень_определения(вопр, опр):
    """Определение сказано УТВЕРЖДЕНИЕМ и сказано ОТВЕТОМ НА ВОПРОС.

    Шрам куплен слоем дознания и здесь не покупается заново: организм,
    знавший определение повествовательно, немел на прямом вопросе.
    Знание, у которого одна поверхность, не отвечает — оно только
    сообщает. Вопрос со своим ответом есть ВТОРАЯ поверхность того же
    факта и стоит одной строки.
    """
    return list(опр) + [f"{в} {о}" for в, о in zip(вопр, опр)]


def pass_groups(шаг):
    """Одна группа на РОД: ступени рода не мешаются с чужими.

    Перемешивание внутри группы — закон дома (`layer.emit_grouped`), и
    оно есть перестановка, а не выборка. Границей между родами стоит
    шов, и читатель корпуса режет по нему честно.
    """
    вон = []
    for _имя, вопр, опр, исп, контр, общ in РОДЫ:
        вон.append(ступень_определения(вопр, опр)
                   + исп(шаг) + контр(шаг) + общ(шаг))
    return вон


def main():
    global _СО_ЗНАКОМ
    _СО_ЗНАКОМ = False
    emit_grouped(ЦЕЛЬ, pass_groups)
    _СО_ЗНАКОМ = True
    emit_grouped(ЦЕЛЬ_СО_ЗНАКОМ, pass_groups)


if __name__ == "__main__":
    main()
