def исп_переменная(шаг):
    """Буква ПРИНИМАЕТ значение, и оттого запись превращается в счёт."""
    вон = []
    for i, (r1, r2) in enumerate(пары(шаг)):
        b, c = по_виете(r1, r2)
        ур = уравнение(b, c)
        v = свидетель_да(r1, r2) if i % 2 == 0 else свидетель_нет(
            r1, r2, шаг + i)
        осн, _ = основание(b, c, v)
        вон.append(f"in {ур} the letter x stands for a value: put {v} in "
                   f"place of x and it gives {осн}.")
        вон.append(f"в {ур} буква x стоит вместо значения: подставь {v} "
                   f"вместо x, и выйдет {осн}.")
    return вон


def контр_переменная(шаг):
    """«У уравнения один корень» убито ДВУМЯ разными корнями сразу.

    ЭТО САМЫЙ ДЕШЁВЫЙ ИЗ ВОЗМОЖНЫХ КОНТРПРИМЕРОВ И САМЫЙ НУЖНЫЙ. Пока
    буква читается как «неизвестное число», корней обязано быть не
    больше одного: число одно. Ровно два корня у одного уравнения и
    ломают это чтение — буква стоит вместо ЗНАЧЕНИЯ, и значений бывает
    несколько.
    """
    вон = []
    for i in range(4):
        r1 = 1 + (шаг * 2 + i) % 6
        r2 = r1 + 1 + (шаг + i) % 5
        b, c = по_виете(r1, r2)
        ур = уравнение(b, c)
        вон.append(f"an equation has one root is false: {ур} gives 0 at "
                   f"x = {r1} and at x = {r2}.")
        вон.append(f"у уравнения один корень — ложь: {ур} даёт 0 при "
                   f"x = {r1} и при x = {r2}.")
    return вон


def общ_переменная(шаг):
    """Переменная пробегает значения, и нули стоят ровно на корнях."""
    вон = []
    for i in range(4):
        r1 = 1 + (шаг + i * 2) % 7
        r2 = r1 + 1 + (шаг * 2 + i) % 4
        b, c = по_виете(r1, r2)
        ур = уравнение(b, c)
        v3 = свидетель_нет(r1, r2, шаг + i)
        итоги = ", ".join(str(значение(b, c, v)) for v in (r1, r2, v3))
        вон.append(f"a variable takes every value in turn: in {ур} the "
                   f"values {r1}, {r2}, {v3} give {итоги}.")
        вон.append(f"переменная принимает все значения по очереди: в "
                   f"{ур} при x = {r1}, {r2}, {v3} выходят {итоги}.")
    return вон


