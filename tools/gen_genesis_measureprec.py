#!/usr/bin/env python3
"""GENESIS layer: ИЗМЕРЕНИЕ И ЕГО ТОЧНОСТЬ — see tools/measureprecforms.py for the law.

СЧЁТ И ИЗМЕРЕНИЕ ИДУТ ПЕРВОЙ ГРУППОЙ ВМЕСТЕ С ЦЕНОЙ ДЕЛЕНИЯ, и это не введение, а сам
предмет дома: пять яблок суть ровно пять, а пять сантиметров суть «между 4,5 и 5,5», и
цена деления говорит, откуда взялись эти границы. Разлучить их значило бы оставить
читателя при мысли, что число есть число.

РАЗБРОС И СЛОЖЕНИЕ ПОГРЕШНОСТЕЙ — второй группой: обе о том, что неточность ВЕДЁТ СЕБЯ,
а не просто есть. Первая показывает её повторением, вторая — сложением.

ДЕЛЕНИЕ СТОИ́Т ОСОБО, ибо это главный род дома и самая частая ошибка школы: цифры,
выданные счётом сверх цены деления, суть узор, а не знание. Соседство разбавило бы его.

ВОПРОС отдельно — ответ рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import measureprecforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_measureprec.txt"
ГРУППЫ = (("счёт против измерения", "цена деления"),
          ("разброс повторений", "погрешность складывается"),
          ("деление не создаёт точности",),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
