#!/usr/bin/env python3
"""GENESIS layer: ПЕРЕВОД ЕДИНИЦ РУССКОЙ ВОПРОСНОЙ ФОРМОЙ.

Мир перевода единиц у корпуса есть, но спрашивается он по-английски.
Русская вопросная рамка — «сколько минут в двух часах?» — требует
ЧИСЛИТЕЛЬНОГО В КОСВЕННОМ ПАДЕЖЕ («в двух», «в трёх», «в пяти»), а за
ним ПРЕДЛОЖНОГО МНОЖЕСТВЕННОГО имени («часах», «неделях»). Ни того, ни
другого корпус не показывал: замер по 97 мирам нашёл ноль строк вида
«в двух часах».

ТРИ ФОРМЫ, И НИ ОДНА НЕ НАПИСАНА РУКОЙ:
  · косвенное числительное берётся из `langpacks/ru.json`
    (`numeral_oblique`) — таблица языка, а не выдумка мира;
  · предложное множественное выводится правилом дома русской
    грамматики (`rugram.предложный_мн`) из родительного единственного;
  · счётная форма единицы — из дома единиц (`units.рус`), где закон
    1 / 2-4 / 5+ живёт как данные пакета.
Генератор, берущий форму отсюда, не может написать неверную.

ОСНОВАНИЕ СТОИТ РЯДОМ С ВЕРДИКТОМ, И ЭТО ГЛАВНОЕ. Не «в двух часах
120 минут», а «в двух часах 120 минут: в часе 60 минут, 60 × 2 = 120».
Первое есть факт, который остаётся заучить; второе есть ВЫВОД, и суд
пересчитывает его отношением из объявленного графа единиц, а не
сверяется с записанным ответом.

ОБРАТНАЯ РАМКА ПОКАЗАНА РЯДОМ С ПРЯМОЙ, на тех же числах: перевод есть
отношение, и оно читается в обе стороны. Умножение и деление стоят
двумя поверхностями одного факта.

ОТКАЗ С ОСНОВАНИЕМ. «сколько минут в двух метрах?» — вопрос
грамматически безупречный и по существу пустой. Организм, у которого
всякий вопрос имеет число в ответе, выучит, что число есть всегда, и
незнание выйдет наружу выдумкой. Основание отказа проверяемо: дом
единиц НЕ ОБЪЯВЛЯЕТ ребра между этими величинами, и суд спрашивает у
графа заново.

ПАРЫ ВЗЯТЫ ТЕ, У КОТОРЫХ ОБА ДОМА ГОВОРЯТ ИДИОМАТИЧНО. «в сутках» для
дня объявлено домом единиц отдельной формой, а «в дне» неверно; для
метра и килограмма дом единиц предложной рамки не объявляет вовсе.
Такие пары не взяты — не потому, что трудны, а потому, что мир не
вправе досказывать за дом.
"""

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import rugram  # noqa: E402
import units  # noqa: E402
from layer import emit_grouped  # noqa: E402

ЦЕЛЬ = "datasets/genesis_ru_conversions.txt"

# ЯДРО ДОСЛОВНЫХ ПОВТОРОВ: столько первых случаев каждого рода стоят во
# ВСЕХ проходах слово в слово. Форма чеканится повторностью.
ЯДРО = 3
СЛУЧАЕВ = 8

# КОСВЕННОЕ ЧИСЛИТЕЛЬНОЕ — ТАБЛИЦА ЯЗЫКА, А НЕ МИРА. Пакет объявляет
# формы 1..20; мир берёт из них ровно те, что объявлены, и выше не
# поднимается.
_ПАКЕТ = json.loads(
    (pathlib.Path(__file__).resolve().parent
     / "langpacks/ru.json").read_text(encoding="utf-8"))
КОСВЕННЫЕ = {int(к): з for к, з in _ПАКЕТ["numeral_oblique"].items()}
# ЕДИНИЦА В КОСВЕННОМ ПАДЕЖЕ НЕ БЕРЁТСЯ: «в одном часе» есть уже
# предложная рамка дома единиц, и она стоит основанием, а не вопросом.
СЧЁТЫ = tuple(sorted(n for n in КОСВЕННЫЕ if n >= 2))

# ПАРЫ ЕДИНИЦ: (большая, малая). Ребро между ними объявлено графом
# `units.РЁБРА`, и отношение спрашивается у него, а не пишется здесь.
ПАРЫ = (("hour", "minute"), ("minute", "second"), ("week", "day"),
        ("rouble", "kopeck"), ("kilometre", "metre"))

# ПАРА БЕЗ РЕБРА — та, на которой строится отказ. Взята не наугад:
# проверяется при сборке, что графа между ними и вправду нет.
БЕЗ_РЕБРА = (("metre", "minute"), ("kopeck", "second"),
             ("gram", "hour"))


def ключ(имя):
    """Русский именительный единственного единицы — ключ дома форм."""
    return units.ФОРМЫ_ВСЕХ[имя][1][0]


def родительный_мн(имя):
    """Третья счётная форма: её требует «сколько ЧЕГО».

    Взята прямо из объявленной тройки, а не через счёт с выдуманным
    числом: «сколько минут» стои́т при любом счёте и потому не должно
    зависеть от того, какое число мы подставили бы ради формы.
    """
    return units.ФОРМЫ_ВСЕХ[имя][1][2]


def предложный_ед(имя):
    """«в часе», «в неделе» — предложное единственного из парадигмы."""
    формы = rugram.ПАРАДИГМЫ.get(ключ(имя))
    return формы[rugram.ПАДЕЖИ.index("предложный")] if формы else None


def предложный_мн(имя):
    """«в часах», «в неделях» — правилом дома, а не списком."""
    return rugram.предложный_мн(ключ(имя))


def творительный(имя):
    """«между метром и минутой» — предлог «между» правит творительным."""
    формы = rugram.ПАРАДИГМЫ.get(ключ(имя))
    return формы[rugram.ПАДЕЖИ.index("творительный")] if формы else None


def предложный_по_счёту(имя, n):
    """«в 120 секундах», но «в 21 дне»: число правит и падежной формой.

    ЗАКОН ТОТ ЖЕ, ЧТО У СЧЁТА, И БЕРЁТСЯ ОТТУДА ЖЕ. После числительного
    в косвенном падеже имя стоит во множественном — кроме случая, когда
    числительное кончается на «один»: там единственное. Разряд не
    вычисляется здесь заново, а спрашивается у закона ПАКЕТА теми же
    тремя ячейками, какими живёт счётная форма: первая ячейка есть
    «один», и только она даёт единственное.
    """
    ячейки = ("_ОДИН", "_ДВА", "_ПЯТЬ")
    единственное = units.ру_форма(ячейки, n) == ячейки[0]
    return предложный_ед(имя) if единственное else предложный_мн(имя)


def годная(пара):
    """Оба дома говорят о паре идиоматично — иначе мир её не берёт."""
    большая, малая = пара
    return (units.отношение(большая, малая) is not None
            and предложный_ед(большая) is not None
            and предложный_мн(большая) is not None
            and малая in units.ФОРМЫ_ВСЕХ)


ЖИВЫЕ = tuple(п for п in ПАРЫ if годная(п))


def семя(шаг, i):
    """Первые ЯДРО случаев прохода не знают — оттого и дословны."""
    return i if i < ЯДРО else шаг * 13 + i


def _вперёд(имя_б, имя_м, n):
    """«сколько минут в двух часах?» — прямая рамка с основанием."""
    r = int(units.отношение(имя_б, имя_м))
    итог = r * n
    косв, пм = КОСВЕННЫЕ[n], предложный_мн(имя_б)
    return (f"сколько {родительный_мн(имя_м)} в {косв} {пм}? "
            f"в {косв} {пм} {итог} {units.рус(имя_м, итог)}: "
            f"в {предложный_ед(имя_б)} {r} {units.рус(имя_м, r)}, "
            f"{r} × {n} = {итог}.")


def _назад(имя_б, имя_м, n):
    """«сколько часов в 120 минутах?» — то же отношение обратным ходом.

    ЧИСЛО ЗДЕСЬ ИДЁТ ЦИФРОЙ, А НЕ СЛОВОМ, и это не небрежность: пакет
    объявляет косвенные числительные до двадцати, а произведение
    выходит за них уже на второй паре. Цифра честнее выдуманного слова.
    """
    r = int(units.отношение(имя_б, имя_м))
    итог = r * n
    где = предложный_по_счёту(имя_м, итог)
    return (f"сколько {родительный_мн(имя_б)} в {итог} {где}? "
            f"в {итог} {где} {n} {units.рус(имя_б, n)}: "
            f"в {предложный_ед(имя_б)} {r} {units.рус(имя_м, r)}, "
            f"{итог} ÷ {r} = {n}.")


def _отказ(имя_б, имя_м, n):
    """Вопрос без ответа — и ОСНОВАНИЕ, по которому его нет."""
    косв, пм = КОСВЕННЫЕ[n], предложный_мн(имя_б)
    # ОТКАЗ СКАЗАН ТОЙ ФОРМОЙ, КАКУЮ ОБЪЯВЛЯЕТ ДОМ: отрицание сущего,
    # за ним двоеточие и основание (`tools/manifest_kinds.отказов`).
    # «нельзя» есть отказ по смыслу и не отказ по объявлению — а мир
    # обязан говорить словарём дома, а не своим.
    return (f"сколько {родительный_мн(имя_м)} в {косв} {пм}? нет "
            f"такого перевода: дом единиц не объявляет ребра между "
            f"{творительный(имя_б)} и {творительный(имя_м)}.")


def прямые(шаг):
    вон = []
    for i in range(СЛУЧАЕВ):
        с = семя(шаг, i)
        имя_б, имя_м = ЖИВЫЕ[с % len(ЖИВЫЕ)]
        вон.append(_вперёд(имя_б, имя_м, СЧЁТЫ[с % len(СЧЁТЫ)]))
    return вон


def обратные(шаг):
    вон = []
    for i in range(СЛУЧАЕВ):
        с = семя(шаг, i)
        имя_б, имя_м = ЖИВЫЕ[(с + 1) % len(ЖИВЫЕ)]
        вон.append(_назад(имя_б, имя_м, СЧЁТЫ[с % len(СЧЁТЫ)]))
    return вон


def отказы(шаг):
    """ОТКАЗ ВЫПУСКАЕТСЯ ТОЛЬКО ТАМ, ГДЕ РЕБРА И ВПРЯМЬ НЕТ."""
    вон = []
    for i in range(ЯДРО):
        с = семя(шаг, i)
        имя_б, имя_м = БЕЗ_РЕБРА[с % len(БЕЗ_РЕБРА)]
        if units.отношение(имя_б, имя_м) is not None:
            continue
        if предложный_мн(имя_б) is None:
            continue
        if творительный(имя_б) is None or творительный(имя_м) is None:
            continue
        вон.append(_отказ(имя_б, имя_м, СЧЁТЫ[с % len(СЧЁТЫ)]))
    return вон


ГРУППЫ = (прямые, обратные, отказы)


def pass_groups(шаг):
    return [сделать(шаг) for сделать in ГРУППЫ]


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
