# ИМЯ ОБЪЯВЛЕНО В ДВУХ ПАДЕЖАХ: рамка отношения стои́т на «правее», и по-русски это требует
# родительного («правее Клары», а не «правее Клара»). Форма объявлена, а не выведена.
ЛЮДИ = {
    "ru": (("Клара", "Клары"), ("Дмитрий", "Дмитрия"), ("Елена", "Елены")),
    "en": (("clara", "clara"), ("dmitri", "dmitri"), ("elena", "elena")),
}
МЕСТА = {
    "ru": ("первом", "втором", "третьем"),
    "en": ("first", "second", "third"),
}
РАМКИ = {
    "ru": {
        "не": "{кто} не в {где}",
        "правее": "{кто} правее {чем}",
        "левее": "{кто} левее {чем}",
        "показ": "три дома в ряд. {условия}. кто где живёт? в первом {а}, во втором {б}, "
                 "в третьем {в}.",
    },
    "en": {
        "не": "{кто} is not in the {где}",
        "правее": "{кто} is to the right of {чем}",
        "левее": "{кто} is to the left of {чем}",
        "показ": "three houses in a row. {условия}. who lives where? in the first {а}, in "
                 "the second {б}, in the third {в}.",
    },
}


def _держит(условие, рассадка):
    """Держится ли условие на рассадке. `рассадка[i]` — номер человека в i-м доме."""
    вид = условие[0]
    место = {кто: i for i, кто in enumerate(рассадка)}
    if вид == "не":
        return место[условие[1]] != условие[2]
    if вид == "правее":
        return место[условие[1]] > место[условие[2]]
    return место[условие[1]] < место[условие[2]]


def решения(условия):
    return [р for р in itertools.permutations(range(3))
            if all(_держит(у, р) for у in условия)]


def _род(условия):
    виды = {у[0] for у in условия}
    if виды == {"не"}:
        return "запрет"
    if "не" not in виды:
        return "порядок"
    # СМЕШАННЫЙ РОД ПРОВЕРЕН, А НЕ ОБЪЯВЛЕН: ни один вид в одиночку не решает.
    только_запреты = [у for у in условия if у[0] == "не"]
    только_порядок = [у for у in условия if у[0] != "не"]
    if len(решения(только_запреты)) == 1 or len(решения(только_порядок)) == 1:
        return None
    return "смешанно"


def _слова(язык, условие):
    люди, места, рамки = ЛЮДИ[язык], МЕСТА[язык], РАМКИ[язык]
    вид = условие[0]
    if вид == "не":
        return рамки["не"].format(кто=люди[условие[1]][0], где=места[условие[2]])
    return рамки[вид].format(кто=люди[условие[1]][0], чем=люди[условие[2]][1])


def минимален(условия):
    """ИЗБЫТОЧНОЕ УСЛОВИЕ НЕ УЧИТ НИЧЕМУ. Набор, из какого можно выбросить условие и
    рассадка останется единственной, дом не берёт: лишнее условие учит, что условия можно
    не читать, — а читатель, выучивший это, промахнётся там, где лишних нет."""
    return all(len(решения(условия[:i] + условия[i + 1:])) != 1
               for i in range(len(условия)))


def страница(язык, условия):
    род = _род(условия)
    если = решения(условия)
    if род is None or len(если) != 1 or not минимален(tuple(условия)):
        return None
    люди = ЛЮДИ[язык]
    а, б, в = (люди[к][0] for к in если[0])
    условия_слова = ". ".join(_слова(язык, у) for у in условия)
    return РАМКИ[язык]["показ"].format(условия=условия_слова, а=а, б=б, в=в), род


# УСЛОВИЯ ОБЪЯВЛЕНЫ ПОИМЁННО, А НАБОРЫ ПЕРЕБРАНЫ: дом берёт всякую двойку и тройку условий
# и оставляет те, у каких рассадка ЕДИНСТВЕННА. Род читается из дела, а не назначается.
УСЛОВИЯ = tuple(("не", кто, где) for кто in range(3) for где in range(3)) + tuple(
    (вид, а, б) for вид in ("правее", "левее") for а in range(3) for б in range(3) if а != б)


# РОД НЕ ДОЛЖЕН ЗАГЛУШАТЬ РОД. Смешанных наименьших наборов из трёх условий вышло 168 при
# 24 чистых порядковых и 36 чистых запретных — всемеро больше. Таково их ЧИСЛО, а не их
# важность: смешанная тройка есть смешанная двойка плюс третье условие, и третье условие уже
# показано в чистых родах. Потому смешанные берутся ТОЛЬКО ДВОЙКАМИ, а чистые — и двойками,
# и тройками. Перекос 7,0 стал 1,5, и ни одна страница не потеряна ради равенства ради
# равенства: потеряны те, какие ничего не добавляли.
ПРЕДЕЛ_СМЕШАННЫХ = 2


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for сколько in (2, 3):
            for набор in itertools.combinations(УСЛОВИЯ, сколько):
                вышло = страница(язык, набор)
                if not вышло:
                    continue
                if вышло[1] == "смешанно" and сколько > ПРЕДЕЛ_СМЕШАННЫХ:
                    continue
                вон.setdefault(вышло[0], (язык, вышло[1]))
    return вон


ПОКАЗЫ = _показы()


