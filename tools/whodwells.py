# СУД ЧИТАЕТ УСЛОВИЯ ИЗ ЗАПИСИ и перебирает ВСЕ ШЕСТЬ рассадок сам. Он требует двух вещей:
# названная рассадка держит каждое условие, и она ЕДИНСТВЕННАЯ такая.
def _разбор_условия(язык, кусок):
    люди, места, рамки = ЛЮДИ[язык], МЕСТА[язык], РАМКИ[язык]
    имена = {и: k for k, (и, _р) in enumerate(люди)}
    родит = {р: k for k, (_и, р) in enumerate(люди)}
    for вид in ("не", "правее", "левее"):
        о = re.escape(рамки[вид])
        о = (о.replace(re.escape("{кто}"), "(?P<кто>[^.,]+?)")
             .replace(re.escape("{где}"), "(?P<где>[^.,]+?)")
             .replace(re.escape("{чем}"), "(?P<чем>[^.,]+?)"))
        м = re.fullmatch(о, кусок.strip())
        if not м:
            continue
        кто = имена.get(м.group("кто"))
        if кто is None:
            return None
        if вид == "не":
            где = места.index(м.group("где")) if м.group("где") in места else None
            return None if где is None else ("не", кто, где)
        чем = родит.get(м.group("чем"))
        return None if чем is None else (вид, кто, чем)
    return None


def судить(строка):
    """(судимо, истинно) — условия прочитаны, все шесть рассадок перебраны заново."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        о = re.escape(РАМКИ[язык]["показ"])
        о = (о.replace(re.escape("{условия}"), "(?P<условия>.+?)")
             .replace(re.escape("{а}"), "(?P<а>[^.,]+?)")
             .replace(re.escape("{б}"), "(?P<б>[^.,]+?)")
             .replace(re.escape("{в}"), "(?P<в>[^.,]+?)"))
        м = re.fullmatch(о, строка)
        if not м:
            continue
        условия = [_разбор_условия(язык, к) for к in м.group("условия").split(". ")]
        if not условия or any(у is None for у in условия):
            continue                     # чужое условие — запись не наша
        # ЗАПИСЬ С ОДНИМ УСЛОВИЕМ ВСЁ РАВНО НАША. Дом таких не строит — одного условия мало
        # для единственности, — но суд обязан их СУДИТЬ, а не молчать: молчание вывело бы
        # целый разряд заведомо ложных записей из-под суда, и подсадка на нём пропала бы.
        имена = {и: k for k, (и, _р) in enumerate(ЛЮДИ[язык])}
        рассадка = tuple(имена.get(м.group(д)) for д in ("а", "б", "в"))
        if any(к is None for к in рассадка) or len(set(рассадка)) != 3:
            return True, False
        нашлись = решения(условия)
        # ЗАДАЧА, У КОТОРОЙ ДВА РЕШЕНИЯ, НЕ ЕСТЬ ЗАДАЧА: суд требует ЕДИНСТВЕННОСТИ, а не
        # только согласия названной рассадки с условиями. И ИЗБЫТОЧНОЕ УСЛОВИЕ НЕ УЧИТ
        # НИЧЕМУ: набор обязан быть наименьшим — выбрось любое условие, и единственность
        # обязана пропасть.
        return True, (len(нашлись) == 1 and нашлись[0] == рассадка
                      and минимален(tuple(условия)))
    return False, True


