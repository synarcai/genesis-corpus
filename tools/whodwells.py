def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    for язык in ЯЗЫКИ:
        assert len(ЛЮДИ[язык]) == 3 and len(МЕСТА[язык]) == 3, f"не трое: {язык}"
        имена = [и for и, _р in ЛЮДИ[язык]]
        assert len(set(имена)) == 3, f"имя дважды: {язык}"
    # ВСЕ ШЕСТЬ РАССАДОК ДЕРЖАТСЯ БЕЗ УСЛОВИЙ: пустой набор ничего не решает.
    assert len(решения(())) == 6, "перебор рассадок сломан"
    # НАИМЕНЬШЕЕ ОБЯЗАНО БЫТЬ ПРОВЕРЕНО, А НЕ ОБЪЯВЛЕНО: вот набор с лишним условием, и дом
    # его не строит.
    лишний = (("не", 0, 0), ("не", 0, 2), ("правее", 0, 1))
    assert len(решения(лишний)) == 1 and not минимален(лишний), "проба на лишнее слаба"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


