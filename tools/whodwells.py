"""ДОМ РАССАДКИ ПО ОГРАНИЧЕНИЯМ (14.09, куплен нулём пробы).

Замерено 14.09 по своду: «кто где живёт» / «who lives where» — НОЛЬ строк. Мир вывода
(`inferforms`) держит ОДИН ход — из посылки следствие; мир строгого вывода знает поненс,
толленс и две ошибки. Но ВЫВОД ИЗ НЕСКОЛЬКИХ ОГРАНИЧЕНИЙ РАЗОМ, где ни одно само по себе
ничего не решает, корпус не показывал нигде.

    ОДИН ХОД И ПЕРЕСЕЧЕНИЕ ЗАПРЕТОВ — РАЗНЫЕ ДЕЛА. Модус поненс берёт одну посылку и делает
    один шаг. Здесь ни одно ограничение не даёт ответа в одиночку: ответ рождается ТЕМ, ЧТО
    ОСТАЛОСЬ, когда все запреты наложены друг на друга. Это не длинная цепь шагов, а
    ОДНОВРЕМЕННОСТЬ.

ТРИ РОДА ПО ДЕЛУ — по тому, ЧЕМ ограничения режут:

    запрет      все ограничения вида «X не в N-м»: чистое вычёркивание;
    порядок     все ограничения вида «X правее Y»: режется ОТНОШЕНИЕ, а не место;
    смешанно    и те и другие, и НИ ОДИН ВИД В ОДИНОЧКУ НЕ РЕШАЕТ — это проверено домом, а
                не объявлено словом: убери запреты — останется больше одной рассадки; убери
                отношения — то же самое.

    ЗАДАЧА, У КОТОРОЙ ДВА РЕШЕНИЯ, НЕ ЕСТЬ ЗАДАЧА. Дом строит страницу лишь там, где
    рассадка ЕДИНСТВЕННА, и суд проверяет единственность сам, перебирая все шесть рассадок.
"""
