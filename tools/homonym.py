def где(язык, слово):
    """Ряды, в каких слово объявлено, — в порядке объявления."""
    return [имя for имя, ряд in РЯДЫ[язык].items() if слово in ряд]


def _союз(язык, имена):
    и = " и " if язык == "ru" else " and "
    return и.join(имена) if len(имена) == 2 else ", ".join(имена[:-1]) + и + имена[-1]


def страница(язык, род, слово, ряд=None, соседи=None):
    рамки, мои = РАМКИ[язык], где(язык, слово)
    if род == "два_ряда":
        if len(мои) < 2:
            return None
        return рамки["два_ряда"].format(с=слово, ряды=_союз(язык, мои))
    if род == "один_ряд":
        if len(мои) != 1:
            return None
        return рамки["один_ряд"].format(с=слово, ряд=мои[0])
    # ПО СОСЕДЯМ: соседи берутся из ОДНОГО ряда и сами не двусмысленны, иначе решать было бы
    # нечем и вопрос имел бы два ответа.
    if ряд not in мои or len(мои) < 2:
        return None
    чисто = [с for с in РЯДЫ[язык][ряд] if с != слово and len(где(язык, с)) == 1]
    if len(чисто) < 2:
        return None
    return рамки["по_соседям"].format(соседи=_союз(язык, чисто[:2]), с=слово, ряд=ряд)


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        слова = sorted({с for ряд in РЯДЫ[язык].values() for с in ряд})
        for слово in слова:
            for род in ("два_ряда", "один_ряд"):
                п = страница(язык, род, слово)
                if п:
                    вон.setdefault(п, (язык, род))
            for ряд in где(язык, слово):
                п = страница(язык, "по_соседям", слово, ряд=ряд)
                if п:
                    вон.setdefault(п, (язык, "по_соседям"))
    return вон


