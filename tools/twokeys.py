def раньше(язык, а, б):
    """(род, ранняя запись или None) — ВТОРОЙ КЛЮЧ МОЛЧИТ, ПОКА ГОВОРИТ ПЕРВЫЙ."""
    (иа, ча), (иб, чб) = а, б
    if ча != чб:
        return "первый_решил", (а if ча < чб else б)
    if иа != иб:
        первый = по_азбуке(язык, [иа, иб])[0]
        return "второй_решил", (а if первый == иа else б)
    return "оба_равны", None


def страница(язык, род, а, б):
    вышло, ранняя = раньше(язык, а, б)
    if вышло != род:
        return None
    рамки = РАМКИ[язык]
    (иа, ча), (иб, чб) = а, б
    если = {"и1": иа, "ч1": ча, "и2": иб, "ч2": чб}
    if род == "оба_равны":
        return рамки["оба_равны"].format(**если)
    зап = f"{ранняя[0]}, {ранняя[1]}"
    if род == "первый_решил":
        return рамки["первый_решил"].format(**если, м=min(ча, чб), б=max(ча, чб),
                                            ранняя=зап)
    ра, рб = по_азбуке(язык, [иа, иб])
    return рамки["второй_решил"].format(**если, ра=ра, рб=рб, ранняя=зап)


ПРЕДЕЛ_ПЕРВЫХ = 2      # соседей на запись в роде «первый решил»


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            # РОД НЕ ДОЛЖЕН ЗАГЛУШАТЬ РОД: пар с РАЗНЫМИ числами вчетверо больше, чем с
            # равными, и это их число, а не важность. Роду «первый решил» даётся по два
            # соседа на запись — довода от третьего соседа не прибавится.
            сколько = {}
            for а, б in itertools.combinations(ЗАПИСИ[язык], 2):
                if род == "первый_решил" and сколько.get(а, 0) >= ПРЕДЕЛ_ПЕРВЫХ:
                    continue
                п = страница(язык, род, а, б)
                if п:
                    вон.setdefault(п, (язык, род))
                    сколько[а] = сколько.get(а, 0) + 1
            # РАВНЫ ОБА — ЛИШЬ У ЗАПИСИ С НЕЮ ЖЕ: иных равных пар в объявлении нет, и род
            # покупается парой записи с собою, а не выдуманным близнецом.
            for а in ЗАПИСИ[язык]:
                п = страница(язык, род, а, а)
                if п:
                    вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


