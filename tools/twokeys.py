# СУД СРАВНИВАЕТ ЗАПИСИ ЗАНОВО, и порядок ключей он берёт из ОБЪЯВЛЕНИЯ, а не со страницы.
# Сверх ответа он проверяет ИМЯ РЕШИВШЕГО: сказать «решила азбука» там, где числа различны,
# — ложь, даже когда ранняя запись названа верно.
def _образцы(язык):
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык][род])
        for дыра, узор in (("и1", "[^«»,]+"), ("и2", "[^«»,]+"), ("ч1", r"\d+"),
                           ("ч2", r"\d+"), ("ранняя", "[^«»]+"), ("ра", "[^«»]+"),
                           ("рб", "[^«»]+"), ("м", r"\d+"), ("б", r"\d+")):
            дыра_о = re.escape("{" + дыра + "}")
            первый = True
            while дыра_о in о:
                о = о.replace(дыра_о, f"(?P<{дыра}>{узор})" if первый else f"(?P={дыра})", 1)
                первый = False
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def _своё(язык, имя):
    return имя in {и for и, _ч in ЗАПИСИ[язык]}


def судить(строка):
    """(судимо, истинно) — записи сравнены заново; имя решившего проверено порознь."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            if not (_своё(язык, д["и1"]) and _своё(язык, д["и2"])):
                continue                       # чужое имя — запись не наша
            а, б = (д["и1"], int(д["ч1"])), (д["и2"], int(д["ч2"]))
            вышло, ранняя = раньше(язык, а, б)
            if вышло != род:
                return True, False             # имя решившего разошлось с делом
            if род == "оба_равны":
                return True, а == б
            if f"{ранняя[0]}, {ранняя[1]}" != д["ранняя"]:
                return True, False
            if род == "первый_решил":
                return True, (int(д["м"]) == min(а[1], б[1])
                              and int(д["б"]) == max(а[1], б[1]))
            # ВТОРОЙ КЛЮЧ ПРОВЕРЯЕТСЯ ТОЙ ЖЕ АЗБУКОЙ, ЧТО И СТРОИТСЯ: она объявлена у дома
            # азбучного порядка, и второго её объявления здесь нет.
            ра, рб = по_азбуке(язык, [а[0], б[0]])
            return True, д["ра"] == ра and д["рб"] == рб


    return False, True


