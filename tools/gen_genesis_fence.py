#!/usr/bin/env python3
"""GENESIS layer: СЧЁТ ВКЛЮЧИТЕЛЬНО — see tools/fenceforms.py for the law.

ДВЕ СТОРОНЫ ОДНОЙ ПОТЕРИ ИДУТ РАЗНЫМИ ГРУППАМИ, и это не разлучение, а показ самой
разницы: «дней на один больше» и «пролётов на один меньше» суть одна единица, теряемая в
две стороны, и читатель обязан встретить обе, чтобы не выучить «прибавляй всегда».

    ОДНА И ТА ЖЕ ЕДИНИЦА ТЕРЯЕТСЯ ДВАЖДЫ И В ДВЕ СТОРОНЫ: кто считает предметы
    разностью, теряет один; кто считает промежутки перечислением — прибавляет лишний.

СТОЛБЫ, РАСПИЛЫ И МАРШИ — одной группой: три одежды одного счёта, и врозь они читались бы
как три правила. ВОПРОС отдельно — ответ рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import fenceforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_fence.txt"
ГРУППЫ = (("дни включительно",),
          ("столбы и пролёты", "распилы", "этажи и марши"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
