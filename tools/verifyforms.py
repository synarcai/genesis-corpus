def страница(язык, форма, i, ложное=1, что="первое"):
    """One page of a frame; `i` picks the numbers, `ложное` the offset of the false claim."""
    с = СЛОВА[язык]
    if форма in ("чётность_верна", "чётность_ложна"):
        if форма == "чётность_верна":
            e = ЧЁТНЫЕ[i % len(ЧЁТНЫЕ)]
            return РАМКИ[язык][форма].format(e=e, h=e // 2)
        o = НЕЧЁТНЫЕ[i % len(НЕЧЁТНЫЕ)]
        return РАМКИ[язык][форма].format(o=o, h=(o - 1) // 2, НЕТ=НЕТ[язык])
    a, b = ПАРЫ[i % len(ПАРЫ)]
    v, d = a + b, a - b
    if форма == "проверка_верна":
        return РАМКИ[язык][форма].format(a=a, b=b, v=v)
    if форма == "проверка_ложна":
        return РАМКИ[язык][форма].format(a=a, b=b, v=v, w=v + ложное, НЕТ=НЕТ[язык])
    if форма == "не_проверено":
        return РАМКИ[язык][форма].format(a=a, b=b, v=v, d=d)
    # две_проверки: вопрос о ЧИСЛЕ, ответ называет утверждение — и оно зависит от вопроса
    if что == "первое":
        return РАМКИ[язык][форма].format(a=a, b=b, t=v, ЧТО=с["первое"], ЗН="+")
    return РАМКИ[язык][форма].format(a=a, b=b, t=d, ЧТО=с["второе"], ЗН="−")


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for i in range(len(ПАРЫ)):
            for форма in ("проверка_верна", "не_проверено"):
                вон[страница(язык, форма, i)] = (язык, форма)
            for сдвиг in (1, 2, 10):     # ложь мимо на единицу, на две и на десяток
                вон[страница(язык, "проверка_ложна", i, ложное=сдвиг)] = (язык, "проверка_ложна")
            for что in ("первое", "второе"):
                вон[страница(язык, "две_проверки", i, что=что)] = (язык, "две_проверки")
        for i in range(len(ЧЁТНЫЕ)):
            вон[страница(язык, "чётность_верна", i)] = (язык, "чётность_верна")
            вон[страница(язык, "чётность_ложна", i)] = (язык, "чётность_ложна")
    return вон


ПОКАЗЫ = _показы()


def _образец(язык, форма):
    """One pattern over the whole page; a hole standing twice is «hole__1», «hole__2»."""
    с = СЛОВА[язык]
    дыры = {"a": r"\d+", "b": r"\d+", "v": r"\d+", "w": r"\d+", "d": r"\d+", "e": r"\d+",
            "o": r"\d+", "h": r"\d+", "t": r"\d+", "НЕТ": re.escape(НЕТ[язык]),
            "ЧТО": "(?:" + "|".join(re.escape(x) for x in sorted((с["первое"], с["второе"]), key=lambda x: (-len(x), x))) + ")",
            "ЗН": "[+−]"}
    счёт, куски = {}, []
    for кусок in re.split(r"(\{[^}]+\})", РАМКИ[язык][форма]):
        if кусок.startswith("{"):
            д = кусок[1:-1]
            счёт[д] = счёт.get(д, 0) + 1
            куски.append(f"(?P<h_{д}__{счёт[д]}>{дыры[д]})")
        else:
            куски.append(re.escape(кусок))
    return re.compile("^" + "".join(куски) + "$")


ОБРАЗЦЫ = [(_образец(язык, форма), язык, форма) for язык in ЯЗЫКИ for форма in ФОРМЫ]


def _вердикт(язык, форма, м):
    """The verdict agrees with the check, and every equality of the page is recomputed."""
    з = {}
    for ключ, v in м.groupdict().items():
        д = ключ[2:].rsplit("__", 1)[0]
        if д in з and з[д] != v:
            return False        # a hole standing twice carries one value
        з[д] = v
    число = lambda имя: int(з[имя])
    if форма == "проверка_верна":
        return число("a") + число("b") == число("v")
    if форма == "проверка_ложна":
        # the quoted claim is FALSE, the answer names the true value, and the ledger holds
        return число("a") + число("b") == число("v") and число("w") != число("v")
    if форма == "не_проверено":
        # the claim holds, the check is about ANOTHER act — and therefore verifies nothing
        return число("a") + число("b") == число("v") and число("a") - число("b") == число("d")
    if форма == "чётность_верна":
        e, h = число("e"), число("h")
        return e % 2 == 0 and e == h * 2
    if форма == "чётность_ложна":
        o, h = число("o"), число("h")
        return o % 2 == 1 and o == h * 2 + 1
    # две_проверки: the named claim is the one that gives the asked number
    a, b, t = число("a"), число("b"), число("t")
    знак, что = з["ЗН"], з["ЧТО"]
    значение = a + b if знак == "+" else a - b
    if значение != t:
        return False
    ждём = СЛОВА[язык]["первое"] if знак == "+" else СЛОВА[язык]["второе"]
    return что == ждём


def судить(строка):
    """(судимо, истинно): a page of a frame of the house whose verdict agrees with its check."""
    с = строка.strip()
    if с in ПОКАЗЫ:
        return True, True
    for образ, язык, форма in ОБРАЗЦЫ:
        м = образ.match(с)
        if м:
            return True, _вердикт(язык, форма, м)
    return False, False


def _самопроверка():
    for показ in ПОКАЗЫ:
        assert судить(показ) == (True, True), показ
    мутанты = 0
    for язык in ЯЗЫКИ:
        с = СЛОВА[язык]
        # (1) вердикт «верно» при неверной проверке
        в = страница(язык, "проверка_верна", 0)
        a, b = ПАРЫ[0]
        битая = в.replace(f"= {a + b}.", f"= {a + b + 1}.", 1)
        assert судить(битая) == (True, False), битая
        # (2) вердикт «ложно» при верной цитате — цитата обязана быть ложной
        л = страница(язык, "проверка_ложна", 0)
        assert судить(л) == (True, True), л
        честная = л.replace(f"= {a + b + 1}{с['вопрос']}", f"= {a + b}{с['вопрос']}", 1)
        assert судить(честная) == (True, False), честная
        # (3) исправление названо неверным числом
        кривое = л.replace(f"{с['верное']} {a + b}.", f"{с['верное']} {a + b + 2}.", 1)
        assert судить(кривое) == (True, False), кривое
        # (4) «не проверено» при СОВПАДАЮЩЕЙ проверке — проверка обязана быть о другом
        н = страница(язык, "не_проверено", 0)
        assert судить(н) == (True, True), н
        совпало = н.replace(f"{a} − {b} = {a - b}.", f"{a} + {b} = {a + b}.", 1)
        assert судить(совпало) == (False, False), совпало   # это уже не рамка дома
        # (5) чётность: проверка не тождество
        ч = страница(язык, "чётность_верна", 0)
        e = ЧЁТНЫЕ[0]
        assert судить(ч.replace(f"= {e // 2} ×", f"= {e // 2 + 1} ×", 1)) == (True, False), ч
        # (6) нечётное названо чётным без остатка — рамка лжи обязана нести остаток
        нч = страница(язык, "чётность_ложна", 0)
        o = НЕЧЁТНЫЕ[0]
