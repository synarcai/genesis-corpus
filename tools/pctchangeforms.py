import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётная форма «процентов» объявлена там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("рост", "убыль", "туда-обратно", "основание")
ПРОЦЕНТ = "процент"


def процентов(язык, n):
    return ("percent" if язык == "en" else rugram.форма(ПРОЦЕНТ, n))


РАМКИ = {
    "ru": {
        "рост": "цена {p} выросла на {k} {пр}: {p} × {k} = {m}, и {m} ÷ 100 = {д}, и {p} + {д} = {p2}.",
        "убыль": "цена {p} упала на {k} {пр}: {p} × {k} = {m}, и {m} ÷ 100 = {д}, и {p} − {д} = {p3}.",
        "туда-обратно": "цена {p} выросла на {k} {пр} и упала на {k} {пр}, и вышло меньше прежнего: {p2} × {k} = {m2}, и {m2} ÷ 100 = {д2}, и {p2} − {д2} = {итог}.",
        "основание": "второй процент взят от {p2}, а не от {p}, и потому он больше: {p2} − {p} = {д}, и {д2} − {д} = {разница}.",
    },
    "en": {
        "рост": "a price of {p} grew by {k} {пр}: {p} × {k} = {m}, and {m} ÷ 100 = {д}, and {p} + {д} = {p2}.",
        "убыль": "a price of {p} fell by {k} {пр}: {p} × {k} = {m}, and {m} ÷ 100 = {д}, and {p} − {д} = {p3}.",
        "туда-обратно": "a price of {p} grew by {k} {пр} and fell by {k} {пр}, and came out below the old one: {p2} × {k} = {m2}, and {m2} ÷ 100 = {д2}, and {p2} − {д2} = {итог}.",
        "основание": "the second percent is taken from {p2} and not from {p}, and so it is bigger: {p2} − {p} = {д}, and {д2} − {д} = {разница}.",
    },
}
ПУСТО = dict(p=0, k=0, m=0, д=0, p2=0, p3=0, m2=0, д2=0, итог=0, разница=0, пр="")

# ПРОЦЕНТЫ ВЗЯТЫ ТЕ, ЧТО ДАЮТ ЦЕЛЫЕ ДОЛИ ДВАЖДЫ ПОДРЯД: иначе вторая доля вышла бы дробной, и
# дом заговорил бы о десятичной записи — предмете соседа, а не своём.
ПРОЦЕНТЫ = (10, 20, 50)


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for p in range(100, 2100, 100):
            for k in ПРОЦЕНТЫ:
                m = p * k
                д = m // 100
                p2, p3 = p + д, p - д
                m2 = p2 * k
                д2 = m2 // 100
                if m % 100 or m2 % 100:
                    continue
                общ = dict(ПУСТО, p=p, k=k, m=m, д=д, p2=p2, p3=p3, m2=m2, д2=д2,
                           итог=p2 - д2, разница=д2 - д, пр=процентов(язык, k))
                вон[рамки["рост"].format(**общ)] = (язык, "рост")
                вон[рамки["убыль"].format(**общ)] = (язык, "убыль")
                вон[рамки["туда-обратно"].format(**общ)] = (язык, "туда-обратно")
                вон[рамки["основание"].format(**общ)] = (язык, "основание")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_СУММА = re.compile(r"(?<![/\d])(\d+) \+ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (\d+)(?![/\d])")
_ВЫРОСЛА = re.compile(r"(?:цена|a price of) (\d+) (?:выросла|grew)")
_ИТОГ_МЕНЬШЕ = re.compile(r"(?:меньше прежнего|below the old one)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    # ЛОВУШКА ОБЯЗАНА ЛОВИТЬ: итог туда-обратно обязан быть МЕНЬШЕ прежней цены, иначе
    # страница говорит о возврате, а не о потере.
    if _ИТОГ_МЕНЬШЕ.search(с):
        начало = _ВЫРОСЛА.findall(с)
        разности = _РАЗНОСТЬ.findall(с)
        if not начало or not разности:
            return True, False
        if int(разности[-1][2]) >= int(начало[0]):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


