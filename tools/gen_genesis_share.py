#!/usr/bin/env python3
"""СЛОЙ GENESIS: МИР ДОЛЕЙ СЛОВАМИ — доля, сказанная речью, а не записью.

ЧЕГО КОРПУСУ НЕ ХВАТАЛО. Корпус знает «1/2» и знает «0.5». Он не знает
«two thirds», «три четверти», «half as many», «полтора». Тринадцать
вопросов полосы умирают именно здесь: спрошено РЕЧЬЮ, а корпус держал
только ЗАПИСЬ. Доля, сказанная словом, есть ОТДЕЛЬНАЯ ПОВЕРХНОСТЬ того
же числа — не украшение записи, а другой вход к ней, — и её не было.

ШЕСТЬ РОДОВ ЭТОГО МИРА:

    ИМЯ И ЗАПИСЬ  — «two thirds is 2/3», «две трети — это 2/3»: слово и
                    запись стоят рядом, и потому имя есть ЧИСЛО, а не
                    оборот речи;
    ДОЛЯ ОТ ВЕЛИЧИНЫ — «two thirds of 12 is 8» с ОСНОВАНИЕМ рядом:
                    поделить на знаменатель, умножить на числитель.
                    Ответ без основания учит помнить, ответ с
                    основанием учит СЧИТАТЬ;
    ВОПРОС        — «what is two thirds of 12?» со своим ответом: та же
                    вторая поверхность, что и всюду в корпусе;
    СРАВНЕНИЕ     — «half as many apples as Tom», «вдвое меньше яблок,
                    чем у Тома»: доля как ОТНОШЕНИЕ ДВУХ КОЛИЧЕСТВ, а
                    не как действие над одним. Это и есть род полосы;
    СМЕШАННОЕ ЧИСЛО — «one and a half», «полтора»: целое и доля в одном
                    имени, и запись 3/2 рядом;
    ЦЕЛОЕ ИЗ ДОЛЕЙ — «one third and two thirds make one whole»: доли
                    складываются и дают единицу.

ВСЁ ВЫЧИСЛЯЕТСЯ, НИЧТО НЕ ПИШЕТСЯ РУКОЙ. Доли живут точными дробями
(`fractions.Fraction`), и показ ВЫПУСКАЕТСЯ ТОЛЬКО ТОГДА, когда доля
от величины ЦЕЛАЯ. Для несократимой доли это равносильно делимости
величины на знаменатель, и величины берутся кратными ему — не отбором
из перебора, а построением. Всё прочее — ЧЕСТНОЕ МОЛЧАНИЕ: показ
«two thirds of 10 is 6.67» был бы ложью, а «примерно 7» — ложью
худшего рода, ибо выглядит ответом.

РУССКИЙ ЧИСЛИТЕЛЬ ПРИ ДОЛЕ СКЛОНЯЕТСЯ, И ФОРМЫ ОБЪЯВЛЕНЫ ЗДЕСЬ. «одна
треть», «две трети», «три четверти», «пять шестых» — три разные формы
одного имени, и вывести их из знаменателя нельзя: «треть» третьего
склонения, «пятая» есть прилагательное. Объявлены МАЛЫМ СПИСКОМ и
только те, в которых есть уверенность; дом русского счёта
(`tools/rugram.py`) держит имена ПРЕДМЕТОВ и зовётся для них, а имена
ДОЛЕЙ он не объявляет и выдумывать за него нельзя.

ЯДРО ДОСЛОВНЫХ ПОВТОРОВ. Первые три случая КАЖДОГО рода одинаковы во
всех проходах, остальные ходят числами. Рамка «вопрос — ответ»
покупается организмом лишь тогда, когда один и тот же показ встречен
многократно ДОСЛОВНО; показ, каждый раз новый, учит роду, но не учит
рамке. Ядро есть плата за рамку, ход — плата за род, и нужны оба.

ЧУЖОЙ РОД ПРОВЕРЕН НАРОЧНО, И ДВАЖДЫ:

  · МИР ЗАПИСИ (`notation`) уже говорит «three and a half plus three
    and a half is seven» и «дважды два с половиной — пять». Его образцы
    привязаны к КОНЦУ строки, и здешние показы кончаются иначе: за
    итогом стоит ОСНОВАНИЕ дробями («: 5/2 + 5/2 = 5»), которого у него
    нет вовсе. Форма не повторена, и суд записи здешних строк не
    читает — это замерено;
  · АРИФМЕТИЧЕСКИЙ СУД читает «two thirds of 12 is 8» САМ: английские
    доли объявлены в языковом пакете, и он разворачивает их в
    «12 * 2 / 3 = 8». Это не помеха, а ВТОРОЙ НЕЗАВИСИМЫЙ СЧЁТ: он
    зовёт «two thirds of 12 is 9» ложью. Русская поверхность ему нема
    (связка «— это» равенством не объявлена), и потому русский счёт
    держит только суд этого слоя.

РУССКИЙ ВОПРОС НАЧИНАЕТСЯ С «ЧЕМУ РАВНА», А НЕ С «СКОЛЬКО БУДЕТ», И
ЭТО НЕ ВКУС. Свод родов утверждений (`tools/genera.py`) видит род СЧЁТА
по образцу «сколько … ? … цифра» и требует, чтобы такую строку прочёл
ХОЗЯИН счёта — суд арифметики или его родня. Русская связка «— это»
арифметике нема, хозяина у строки не нашлось бы, и суд родов объявил бы
её СИРОТОЙ. «Чему равна треть от 12?» говорит то же самое и сиротой не
становится.
"""

import pathlib
