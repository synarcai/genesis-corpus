# ------------------------------------------------------------- ИМЕНА

# ЧИСЛИТЕЛЬНОЕ ПРИ ДОЛЕ ЖЕНСКОГО РОДА: «ОДНА треть», «ДВЕ трети».
# «Два» здесь было бы ошибкой, и ошибкой незаметной — оттого формы
# названы, а не взяты из общего дома числительных.
ЧИСЛИТЕЛЬ_Ж = {1: "одна", 2: "две", 3: "три", 4: "четыре", 5: "пять",
               6: "шесть", 7: "семь", 8: "восемь", 9: "девять"}
# Целое при смешанном числе — мужского рода: «ДВА с половиной».
ЧИСЛИТЕЛЬ_М = {1: "один", 2: "два", 3: "три", 4: "четыре", 5: "пять",
               6: "шесть", 7: "семь"}
ЧИСЛИТЕЛЬ_EN = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five",
                6: "six", 7: "seven", 8: "eight", 9: "nine"}

# ЗНАМЕНАТЕЛИ ОБЪЯВЛЕНЫ МАЛЫМ СПИСКОМ — ТОЛЬКО ТЕ, В КОТОРЫХ ЕСТЬ
# УВЕРЕННОСТЬ. Для каждого: английское имя в единственном и во
# множественном, и ТРИ русские формы — при одном, при двух-четырёх, при
# пяти и более. Третьей формы русский требует не всегда («пятых» стоит и
# при двух, и при пяти), но объявить её отдельно дешевле, чем вывести:
# «треть» склоняется как имя третьего склонения, «пятая» — как
# прилагательное, и одного закона на оба нет.
ДОЛИ = (
    (2, "half", "halves", ("половина", "половины", "половин")),
    (3, "third", "thirds", ("треть", "трети", "третей")),
    (4, "quarter", "quarters", ("четверть", "четверти", "четвертей")),
    (5, "fifth", "fifths", ("пятая", "пятых", "пятых")),
    (6, "sixth", "sixths", ("шестая", "шестых", "шестых")),
    (8, "eighth", "eighths", ("восьмая", "восьмых", "восьмых")),
    (10, "tenth", "tenths", ("десятая", "десятых", "десятых")),
)
ПО_ЗНАМЕНАТЕЛЮ = {з: (ед, мн, формы) for з, ед, мн, формы in ДОЛИ}


def форма_доли(формы, числитель):
    """Русская форма имени доли при данном числителе.

    Числитель доли всегда меньше знаменателя, а знаменатели здесь не
    больше десяти — оттого закона о «одиннадцати» и о «двадцати одном»
    не требуется вовсе, и его тут НЕТ. Граница объявлена, а не забыта.
    """
    if числитель == 1:
        return формы[0]
    if числитель <= 4:
        return формы[1]
    return формы[2]


def имя_англ(числитель, знаменатель):
    """«half», «two thirds», «three quarters» — доля словом."""
    ед, мн, _формы = ПО_ЗНАМЕНАТЕЛЮ[знаменатель]
    if знаменатель == 2 and числитель == 1:
        return "half"
    if числитель == 1:
        return f"one {ед}"
    return f"{ЧИСЛИТЕЛЬ_EN[числитель]} {мн}"


def имя_рус(числитель, знаменатель):
    """«половина», «две трети», «пять шестых» — доля словом.

    ПОЛОВИНА СТОИТ БЕЗ ЧИСЛИТЕЛЬНОГО. «одна половина» по-русски не
    говорят, говорят «половина»; корпус, пишущий «одна половина», учит
    обороту, которого в языке нет. Исключение названо, а не спрятано.
    """
    _ед, _мн, формы = ПО_ЗНАМЕНАТЕЛЮ[знаменатель]
    if знаменатель == 2 and числитель == 1:
        return "половина"
    return f"{ЧИСЛИТЕЛЬ_Ж[числитель]} {форма_доли(формы, числитель)}"


def связка_рус(числитель):
    """«чему РАВНА половина» против «чему РАВНЫ две трети»."""
    return "равна" if числитель == 1 else "равны"


def числители(знаменатель):
    """Числители НЕСОКРАТИМЫХ правильных долей этого знаменателя.

    Сокращаемая доля есть та же доля под другим именем, и «two quarters»
    рядом с «half» учит, что имён у числа много, — но учит этому ПРЕЖДЕ,
    чем самому числу. Список выведен наибольшим общим делителем, а не
    перечислен.
    """
    return [ч for ч in range(1, знаменатель)
            if gcd(ч, знаменатель) == 1]


# --------------------------------------------------------- ЗАКОН ХОДА

def случаи(ядро, ход):
    """ЯДРО ДОСЛОВНО ВО ВСЕХ ПРОХОДАХ, ХОД — ЧИСЛАМИ ПО ПРОХОДУ.

    Один закон на все шесть родов. Первые три случая рода одинаковы в
    каждом проходе и потому встречаются организму пять раз ДОСЛОВНО;
    остальные ходят числами и покупают род.

    ЗАЧЕМ ДОСЛОВНОСТЬ. Рамка «вопрос — ответ» есть не факт, а СПОСОБ, и
    способ покупается повторением одного и того же показа, а не потоком
    разных. Слой, где каждый показ нов, учит роду и не учит рамке; слой
    из одного повторённого показа учит рамке и не учит роду. Нужны оба,
    и оттого закон здесь один, а не два.

    Случай хода, совпавший с ядром, ВЫБРАСЫВАЕТСЯ: перемешивание есть
    перестановка, и двойник в одном проходе стал бы двумя строками.
    """
    видано = list(ядро)
    return видано + [с for с in ход if с not in видано]


def величина(знаменатель, шаг, i):
    """Величина, КРАТНАЯ знаменателю — оттого доля от неё целая.

    Целость не проверяется отбором из перебора, а СТРОИТСЯ: величина
    есть знаменатель, умноженный на целое. Отбор дал бы то же множество
    и скрыл бы закон за фильтром.
    """
    return знаменатель * (2 + (шаг * 3 + i * 2) % 9)


# ------------------------------------------------- РОД: ИМЯ И ЗАПИСЬ

ЯДРО_ИМЕНИ = ((2, 3), (3, 4), (1, 2))


def ход_имени(шаг):
    вон = []
    for i, (з, _ед, _мн, _формы) in enumerate(ДОЛИ):
        доступные = числители(з)
        for сдвиг in range(2):
            вон.append((доступные[(шаг + i + сдвиг) % len(доступные)], з))
    return вон


def имя_и_запись(шаг):
    """Доля словом и доля записью стоят РЯДОМ, в одной строке.

    Имя без записи есть оборот речи; запись без имени есть глиф. Вместе
    они суть одно число, и корпус, державший их порознь, немел на
    всяком вопросе, заданном словом.
    """
    вон = []
    for ч, з in случаи(ЯДРО_ИМЕНИ, ход_имени(шаг)):
        вон.append(f"{имя_англ(ч, з)} is {ч}/{з}.")
        вон.append(f"{имя_рус(ч, з)} — это {ч}/{з}.")
    return вон


# -------------------------------------------- РОД: ДОЛЯ ОТ ВЕЛИЧИНЫ

ЯДРО_ОТ_ВЕЛИЧИНЫ = ((2, 3, 12), (3, 4, 20), (1, 2, 14))


def ход_от_величины(шаг):
    вон = []
    for i, (з, _ед, _мн, _формы) in enumerate(ДОЛИ):
        доступные = числители(з)
        for сдвиг in range(2):
            ч = доступные[(шаг * 2 + i + сдвиг) % len(доступные)]
            вон.append((ч, з, величина(з, шаг, i + сдвиг * 3)))
    return вон


def основание(ч, з, сколько):
    """(частное, итог) — ПОСЧИТАННЫЙ ход: поделить, затем умножить."""
    доля = Fraction(ч, з) * сколько
    return сколько // з, int(доля)


def ходом(ч, з, сколько, англ):
    """Запись основания; УМНОЖЕНИЕ НА ЕДИНИЦУ НЕ ПИШЕТСЯ.

    У доли с числителем один второго действия НЕТ: «половина от 14»
    есть деление, и только деление. Запись «14 divided by 2 is 7, and 7
    times 1 is 7» договаривает шаг, которого никто не делает, и учит
    считать лишнее. Тот же закон, что «нулевое слагаемое не пишется» в
    мире уравнений: действие, ничего не меняющее, не есть действие.
    """
    частное, итог = основание(ч, з, сколько)
    if англ:
        первое = f"{сколько} divided by {з} is {частное}"
        return (первое if ч == 1 else
                f"{первое}, and {частное} times {ч} is {итог}")
    первое = f"{сколько} разделить на {з} — это {частное}"
    return (первое if ч == 1 else
            f"{первое}, а {частное} умножить на {ч} — это {итог}")


def от_величины(шаг):
    """Доля от величины с ОСНОВАНИЕМ рядом: делением и умножением.

    Ответ «two thirds of 12 is 8» без основания учит ПОМНИТЬ; ответ с
    основанием «12 divided by 3 is 4, and 4 times 2 is 8» учит СЧИТАТЬ,
    и его можно пересчитать — суд слоя пересчитывает оба действия.
    """
    вон = []
    for ч, з, сколько in случаи(ЯДРО_ОТ_ВЕЛИЧИНЫ, ход_от_величины(шаг)):
        _частное, итог = основание(ч, з, сколько)
        вон.append(f"{имя_англ(ч, з)} of {сколько} is {итог}: "
                   f"{ходом(ч, з, сколько, True)}.")
        вон.append(f"{имя_рус(ч, з)} от {сколько} — это {итог}: "
                   f"{ходом(ч, з, сколько, False)}.")
    return вон


def вопросом(шаг):
    """Та же доля, спрошенная — и отвеченная своей же короткой формой.

    РУССКИЙ ВОПРОС НЕ НАЧИНАЕТСЯ С «СКОЛЬКО БУДЕТ», И ЭТО КУПЛЕНО
    СВОДОМ РОДОВ. «Сколько … ? … цифра» есть объявленный признак рода
    СЧЁТА, а хозяева счёта — суды, умеющие считать; русскую связку
    «— это» арифметика равенством не считает, хозяина бы не нашлось, и
    строка стала бы СИРОТОЙ у суда родов. «Чему равна треть от 12?»
    говорит ровно то же и хозяина не требует.
    """
    вон = []
    for ч, з, сколько in случаи(ЯДРО_ОТ_ВЕЛИЧИНЫ, ход_от_величины(шаг)):
        _частное, итог = основание(ч, з, сколько)
        англ = имя_англ(ч, з)
        рус = имя_рус(ч, з)
        вон.append(f"what is {англ} of {сколько}? {англ} of {сколько} "
                   f"is {итог}.")
        вон.append(f"чему {связка_рус(ч)} {рус} от {сколько}? {рус} от "
                   f"{сколько} — это {итог}.")
    return вон


# ------------------------------------------------------ РОД: СРАВНЕНИЕ

# ИМЕНА И ВЕЩИ ОБЪЯВЛЕНЫ ПАРАМИ. Русское имя дано СРАЗУ В РОДИТЕЛЬНОМ
# («у Тома», «у Ани»): выводить падеж из именительного значило бы
# писать склонение имён собственных, которого дом русского счёта не
# объявляет. Вещь названа КЛЮЧОМ этого дома — форму при числе даёт он.
ЛЮДИ = (("Tom", "Тома"), ("Ann", "Ани"), ("Ben", "Бена"),
        ("Kate", "Кати"), ("Sam", "Сэма"), ("Vera", "Веры"))
ВЕЩИ = (("apples", "яблоко"), ("books", "книга"),
        ("sweets", "конфета"), ("pens", "ручка"),
        ("pencils", "карандаш"), ("coins", "монета"),
        ("marbles", "шарик"), ("flowers", "цветок"))
# КРАТНОСТЬ СКАЗАНА ОДНИМ СЛОВОМ, И ЭТО ОТДЕЛЬНОЕ СЛОВО ЯЗЫКА.
# «Вдвое меньше» не выводится из «половина» ни в русском, ни в
# английском: это самостоятельная лексика отношения, и она объявлена.
КРАТНО = {2: ("half", "вдвое"), 3: ("a third", "втрое"),
          4: ("a quarter", "вчетверо"), 5: ("a fifth", "впятеро")}

ЯДРО_СРАВНЕНИЯ = ((2, 12, 0, 1, 0), (3, 12, 0, 1, 0), (4, 20, 2, 3, 1))


def ход_сравнения(шаг):
    вон = []
    for i, з in enumerate(sorted(КРАТНО)):
        for сдвиг in range(2):
            меньший = 2 + (шаг + i * 3 + сдвиг * 5) % 7
            вон.append((з, меньший * з,
                        (шаг + i + сдвиг) % len(ЛЮДИ),
                        (шаг + i + сдвиг + 1) % len(ЛЮДИ),
                        (шаг * 2 + i + сдвиг * 3) % len(ВЕЩИ)))
    return вон


def сравнением(шаг):
    """Доля как ОТНОШЕНИЕ ДВУХ КОЛИЧЕСТВ — род, на котором мёрла полоса.

    «Half as many apples as Tom» не есть действие над числом: тут два
    количества стоят рядом, и доля СВЯЗЫВАЕТ их. Организм, знавший
    только «half of 12 is 6», на этой связи немел — она другая, хотя
    число то же.

    Русская пара говорит кратностью («вдвое меньше»), а не долей, ибо
    так говорит язык; вторая русская поверхность даёт и долевой оборот
    («треть от того, что у Тома»), чтобы связь была видна обоими
    способами.
    """
    вон = []
    for з, больше, а, б, в in случаи(ЯДРО_СРАВНЕНИЯ, ход_сравнения(шаг)):
        меньше = больше // з
        англ_имя, рус_имя = ЛЮДИ[а]
        англ_имя2, рус_имя2 = ЛЮДИ[б]
        англ_вещь, ключ = ВЕЩИ[в]
        доля_англ, кратно_рус = КРАТНО[з]
        вон.append(f"{англ_имя} has {больше} {англ_вещь} and "
                   f"{англ_имя2} has {меньше} {англ_вещь}; {англ_имя2} "
                   f"has {доля_англ} as many {англ_вещь} as {англ_имя}.")
        вон.append(f"у {рус_имя} {больше} {rugram.форма(ключ, больше)}, "
                   f"а у {рус_имя2} {меньше} "
                   f"{rugram.форма(ключ, меньше)}; у {рус_имя2} "
                   f"{кратно_рус} меньше {rugram.форма(ключ, 5)}, чем у "
                   f"{рус_имя}.")
        вон.append(f"{англ_имя2} has {имя_англ(1, з)} of what "
                   f"{англ_имя} has: {больше} divided by {з} is "
                   f"{меньше}.")
        вон.append(f"у {рус_имя2} {имя_рус(1, з)} от того, что у "
                   f"{рус_имя}: {больше} разделить на {з} — это "
                   f"{меньше}.")
    return вон


# ---------------------------------------------- РОД: СМЕШАННОЕ ЧИСЛО

ЯДРО_СМЕШАННОГО = (1, 2, 3)


def ход_смешанного(шаг):
    return [1 + (шаг + i) % 7 for i in range(5)]


def смешанное_англ(целое):
    return f"{ЧИСЛИТЕЛЬ_EN[целое]} and a half"


def смешанное_рус(целое):
    """«полтора» — ОТДЕЛЬНОЕ СЛОВО, а не «один с половиной».

    Русский держит для полутора собственное имя, и корпус, пишущий
    «один с половиной», учит обороту, которого в языке нет. Исключение
    названо здесь; прочие целые говорят общим законом.
    """
    if целое == 1:
        return "полтора"
    return f"{ЧИСЛИТЕЛЬ_М[целое]} с половиной"


def смешанным(шаг):
    """Целое и доля одним именем — и запись 3/2 рядом с ним.

    ТРИ ПОВЕРХНОСТИ ОДНОГО ЧИСЛА: имя с записью, сумма двух таких имён
    с основанием дробями, и перевод в мелкую единицу («полтора часа —
    это 90 минут»). Последняя есть мост в мир единиц: смешанное число
    живёт в речи именно там, где считают время.

    СУММА ДВУХ «h с половиной» ЕСТЬ 2h + 1, А НЕ 2h. Этот шрам корпус
    уже покупал миром записи; здесь он не покупается заново, а
    ПЕРЕСЧИТЫВАЕТСЯ: основание стоит дробями рядом с итогом.
    """
    вон = []
    for целое in случаи(ЯДРО_СМЕШАННОГО, ход_смешанного(шаг)):
        числитель = 2 * целое + 1
        сумма = числитель
        минуты = числитель * 30
        англ = смешанное_англ(целое)
        рус = смешанное_рус(целое)
        вон.append(f"{англ} is {числитель}/2.")
        вон.append(f"{рус} — это {числитель}/2.")
        вон.append(f"{англ} plus {англ} is {сумма}: {числитель}/2 + "
                   f"{числитель}/2 = {сумма}.")
        вон.append(f"{рус} плюс {рус} — это {сумма}: {числитель}/2 + "
                   f"{числитель}/2 = {сумма}.")
        вон.append(f"{англ} hours is {минуты} minutes.")
        вон.append(f"{рус} {rugram.форма('час', целое if целое > 1 else 2)}"
                   f" — это {минуты} {rugram.форма('минута', минуты)}.")
    return вон


# ------------------------------------------------ РОД: ЦЕЛОЕ ИЗ ДОЛЕЙ

ЯДРО_ЦЕЛОГО = ((1, 3), (3, 4), (2, 3))


def ход_целого(шаг):
    """Обе доли НЕСОКРАТИМЫ и РАЗЛИЧНЫ.

    Половина с половиной выпадает сама: «половина и половина» называет
    одно имя дважды и учит не сложению долей, а повтору. Условие
    записано как условие («доля не равна своему дополнению»), а не как
    вычеркнутый из списка знаменатель.
    """
    вон = []
    for i, (з, _ед, _мн, _формы) in enumerate(ДОЛИ):
        доступные = [ч for ч in числители(з)
                     if gcd(з - ч, з) == 1 and ч != з - ч]
        # ПОЛОВИНА ВЫПАДАЕТ ЗДЕСЬ, И ЭТО НЕ ОШИБКА, А ЗАКОН: у двойки
        # единственная несократимая доля равна своему дополнению, и
        # знаменателю нечего сказать этим родом. Пустой список есть
        # честный ответ дома, а не случай, забытый обходом.
        for сдвиг in range(2):
            if доступные:
                вон.append(
                    (доступные[(шаг + i + сдвиг) % len(доступные)], з))
    return вон


def целым(шаг):
    """Доли складываются и дают ЕДИНИЦУ — с записью сложения рядом.

    Обе доли берутся НЕСОКРАТИМЫМИ: «два шестых и четыре шестых» верно
    по числу и неверно по речи — так не говорят, и корпус, так
    говорящий, учит несуществующему обороту вместе с верным счётом.
    """
    вон = []
    for ч, з in случаи(ЯДРО_ЦЕЛОГО, ход_целого(шаг)):
        второй = з - ч
        вон.append(f"{имя_англ(ч, з)} and {имя_англ(второй, з)} make "
                   f"one whole: {ч}/{з} + {второй}/{з} = 1.")
        вон.append(f"{имя_рус(ч, з)} и {имя_рус(второй, з)} составляют "
                   f"целое: {ч}/{з} + {второй}/{з} = 1.")
    return вон


