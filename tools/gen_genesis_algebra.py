#!/usr/bin/env python3
"""GENESIS layer: SIGNS, IDENTITIES, AND SIMPLIFICATION.

The owner's demand is exact: the formula material must cover every
variation the corpora actually use, and must be enough to WRITE new
formulas, to COMPUTE and to SIMPLIFY them. So the layer is built from
a MEASURED inventory, not from taste — the census of msfs, uhm, mf,
diakrisis and verum gave 89 distinct mathematical signs, dominated by
arrows (→ 5178, ↔ 1077), Greek letters (α 2461, Γ 1135, ι 1013, ρ, Ω,
κ, φ, σ, Σ), ∞ 1851, ∈ 403, × 499, ≈ 266, with 418 powers and 26
subscripts, and NOT ONE \\frac or \\begin.

THREE THINGS A SIGN NEEDS, and the layer gives all three:
  · its NAME, in every language the pack declares it («α is called
    alpha», «α называется альфа», «α heisst alpha»);
  · its USE in a formula;
  · and for every identity, an INSTANTIATION whose arithmetic can be
    checked — because an identity shown only in letters teaches the
    shape of algebra and none of its truth.

SIMPLIFICATION IS SHOWN AS A CHAIN, not as an answer: «2 x + 3 x = 5 x»
beside «with x = 4 this is 8 + 12 = 20». The organism sees the rule and
its warrant in one show, and the warrant is checkable.
"""

import bilang  # noqa: E402 — язык показа по азбуке
import json
import pathlib
import sys

# ПУТЬ, СКАЗАННЫЙ ТОЛЬКО В ЗОВЕ, ЕСТЬ ПУТЬ, О КОТОРОМ НЕ ОБЪЯВЛЕНО (14.09): указатель
# читает объявление СТРОКОЙ ВЕРХНЕГО УРОВНЯ, и мир, названный лишь внутри `emit`,
# остаётся не связанным ни с одним домом.
ЦЕЛЬ = "datasets/genesis_algebra.txt"

ЗДЕСЬ = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(ЗДЕСЬ))
from layer import PASSES, Сбор, emit  # noqa: E402
import mass  # noqa: E402

# ЗАКОН ПОВТОРА — из кремния архитектуры; здесь ЧИТАЕТСЯ.
LAW = 2

ПАКЕТЫ = {я: json.loads((ЗДЕСЬ / f"langpacks/{я}.json").read_text(
    encoding="utf-8")) for я in ("en", "ru", "de")}
РАМКА = {"en": "{з} is called {и}.", "ru": "{з} называется {и}.",
         "de": "{з} heisst {и}."}
# знаки, чьё имя объявлено во ВСЕХ трёх языках — иначе показ был бы
# о пробеле в описании, а не о знаке
ЗНАКИ = sorted(set(ПАКЕТЫ["en"]["sign_names"])
               & set(ПАКЕТЫ["ru"]["sign_names"])
               & set(ПАКЕТЫ["de"]["sign_names"]))
# МАССА ОТ ПРАВИЛА (tools/mass.py, М-148): каждая тройка составляется из
# взаимно простых циклов множителей шагом k — различных показов на рамку
# до 77 (было 8–10: таблица повторялась каждым проходом).
ОСНОВАНИЯ = [2, 3, 5, 4, 10, 6, 7]
ПОКАЗАТЕЛИ = [(3, 4), (2, 3), (4, 2), (2, 2), (2, 5), (3, 2), (5, 3),
              (2, 4), (3, 3), (1, 2), (4, 3)]
КОЭФ = [2, 4, 3, 6, 1, 5, 7]
СВОБОДНЫЕ = [(3, 4), (1, 5), (5, 2), (2, 3), (7, 6), (4, 2), (8, 3),
             (2, 4), (3, 5), (1, 2), (6, 7)]
ПЕРВЫЕ = [3, 5, 7, 6, 9, 8, 4, 10, 11, 2, 12]
ВТОРЫЕ = [4, 2, 3, 5, 7]
ШИРИНА = 10


# ИСКОМОЕ ОБЪЯВЛЯЕТ СВОЙ ВОПРОС ОДИН РАЗ, и вопрос берёт ТУ ЖЕ фразу
# предмета, какую берёт ответ. Замер вопросной поверхности назвал этот
# мир немым: 1342 строки, вопросов ноль.
СПРОСИТЬ = {
    "value": "what is {предмет}?",
    "значение": "чему равно {предмет}?",
}


def спросить(искомое, предмет, ответ):
    """Вопрос о предмете и ответ о нём же — одной строкой."""
    return f"{СПРОСИТЬ[искомое].format(предмет=предмет)} {ответ}"


# ШЕСТЬ РОДОВ НАЗВАНЫ РАЗДЕЛАМИ «# ---» И НЕ ВЫШЛИ НАРУЖУ. Знаки, стоящие первыми, суть
# отдельное дело: там не считают, а НАЗЫВАЮТ знак словом.
ИМЯ_ЗНАКА = "имя знака: символ назван словом на своём языке"
СТЕПЕНИ = "законы степеней: правило и его подстановка числами"
ПОДОБНЫЕ = "приведение подобных — и отказ там, где привести нельзя"
РАСПРЕДЕЛЕНИЕ = "распределительный закон в обе стороны: раскрыть и свернуть"
ИНДЕКСЫ = "индексы: x₁ и x₂ и сумма двух членов"
ОТНОШЕНИЯ = "отношения, поставленные числами: ≥, ≠, перестановочность"


def pass_shows(pass_i):
    out = Сбор(ИМЯ_ЗНАКА)
    for i, знак in enumerate(ЗНАКИ):
        # ЗАКОН ПОВТОРА РЕШАЕТ, СКОЛЬКО РАЗ ПОКАЗАН ЗНАК. Прежнее «% 3»
        # давало знаку от одного до двух проходов, и показанный ОДНАЖДЫ
        # знак не покупается вовсе — перепись честно назвала тринадцать
        # таких одиночек (\emptyset, \geq, α, π…). Каждый знак живёт
        # ровно LAW проходов из пяти: столько, сколько нужно закону, и
        # ни одним больше.
        if (i + pass_i) % len(PASSES) >= LAW:
            continue
        for я, рамка in РАМКА.items():
            # ИМЁН У ЗНАКА НЕСКОЛЬКО, а называется он ПЕРВЫМ: у стрелки
            # первое имя — форма («arrow»), второе — роль («implies»),
            # и показ учит канон/ основному, а суд принимает любое
            # объявленное.
            имена = ПАКЕТЫ[я]["sign_names"][знак]
            имя = имена if isinstance(имена, str) else имена[0]
            # ЯЗЫК РАМКИ ЗДЕСЬ И ЕСТЬ ЯЗЫК СТРОКИ, и брать его у письма было бы ошибкой:
            # немецкое «≈ heisst ungefähr» латиницею неотличимо от английского.
            out.язык = я
            out.append(рамка.format(з=знак, и=имя))
    # ПОЛЕ СБОРА ДЕРЖИТСЯ, ПОКА ЕГО НЕ СМЕНЯТ, и это его свойство, а не оплошность: род
    # ставят однажды на всю ветвь. Язык же назван ТОЛЬКО у имени знака, и потому здесь он
    # снимается: прочие ветви дома пишут на двух азбуках, и читать их надлежит начертанием.
    out.язык = None
    for i in range(ШИРИНА):
        k = mass.шаг(pass_i, i, ШИРИНА)
        a, (m, n) = mass.пара(k, ОСНОВАНИЯ, ПОКАЗАТЕЛИ)
        p, (q, x) = mass.пара(k, КОЭФ, СВОБОДНЫЕ)
        u, v = mass.пара(k, ПЕРВЫЕ, ВТОРЫЕ)
        out.род = СТЕПЕНИ
        # --- законы степеней: правило и его подстановка
        out.append("a^m × a^n = a^( m + n ).")
        степ = f"{a}^{m} × {a}^{n}"
        out.append(f"{степ} = {a}^{m + n}.")
        out.append(спросить("значение", степ, f"{степ} = {a}^{m + n}."))
        произв = f"{a ** m} × {a ** n}"
        out.append(f"{произв} = {a ** (m + n)}.")
        out.append(спросить("value", произв,
                            f"{произв} = {a ** (m + n)}."))
        out.append("( a^m )^n = a^( m × n ).")
        вложен = f"( {a}^{m} )^{n}"
        out.append(f"{вложен} = {a}^{m * n}.")
        out.append(спросить("значение", вложен, f"{вложен} = {a}^{m * n}."))
        встепени = f"{a ** m} в степени {n}"
        out.append(f"{встепени} равно {a ** (m * n)}.")
        out.append(спросить("значение", встепени,
                            f"{встепени} равно {a ** (m * n)}."))
        out.род = ПОДОБНЫЕ
        # --- приведение подобных: правило и оправдание
        подобные = f"{p} x + {q} x"
        out.append(f"{подобные} = {p + q} x.")
        out.append(спросить("значение", подобные, f"{подобные} = {p + q} x."))
        # ОТКАЗ С ОСНОВАНИЕМ: слагаемые с РАЗНЫМИ неизвестными не
        # приводятся. Основание вычислимо и судимо: имена неизвестных
        # различны, и сложить их значило бы солгать о самом законе
        # приведения подобных.
        out.append(f"чему равно {p} x + {q} y? привести нельзя: "
                   f"{p} x и {q} y — слагаемые с разными неизвестными.")
        out.append(f"what is {p} x + {q} y? cannot be reduced: "
                   f"{p} x and {q} y have different unknowns.")
        out.append(f"при x = {x} это {p * x} + {q * x} = {(p + q) * x}.")
        out.append(f"with x = {x} this is {p * x} + {q * x} = {(p + q) * x}.")
        out.род = РАСПРЕДЕЛЕНИЕ
        # --- распределительный закон
        out.append("a × ( b + c ) = a × b + a × c.")
        распр = f"{p} × ( {q} + {x} )"
        out.append(f"{распр} = {p * q} + {p * x}.")
        out.append(спросить("значение", распр,
                            f"{распр} = {p * q} + {p * x}."))
        свёрнут = f"{p} × {q + x}"
        out.append(f"{свёрнут} = {p * (q + x)}.")
        out.append(спросить("value", свёрнут,
                            f"{свёрнут} = {p * (q + x)}."))
        out.род = ИНДЕКСЫ
        # --- индексы: сумма двух членов
        инд_en = f"x_1 = {u} and x_2 = {v}"
        инд_ru = f"x_1 = {u} и x_2 = {v}"
        утв_и_en = f"{инд_en}, so x_1 + x_2 = {u + v}."
        утв_и_ru = f"{инд_ru}, значит x_1 + x_2 = {u + v}."
        out.append(утв_и_en)
        out.append(утв_и_ru)
        out.append(f"{инд_en} — what is x_1 + x_2? {утв_и_en}")
        out.append(f"{инд_ru} — чему равно x_1 + x_2? {утв_и_ru}")
        out.род = ОТНОШЕНИЯ
        # --- отношения, поставленные числами
        out.append(f"{u} ≥ {v}." if u >= v else f"{u} ≤ {v}.")
        out.append(f"{u} ≠ {v}." if u != v else f"{u} = {v}.")
        # ВЫВОД ПРИ ЧИСЛАХ СКАЗАН РЕЧЬЮ, И РЕЧЬ ЭТА БЫЛА ОДНА (15.09): «поэтому ×
        # перестановочно» стоя́ло только по-русски, и весь род отношений числился русским
        # при выкладках, слов не несущих вовсе.
        out.append(f"{u * v} = {v * u}, поэтому × перестановочно.")
        out.append(f"{u * v} = {v * u}, so × is commutative.")
    return out


# --------------------------------------------------------------- ОБЪЯВЛЕНИЕ ДОМА

РОДЫ = (ИМЯ_ЗНАКА, СТЕПЕНИ, ПОДОБНЫЕ, РАСПРЕДЕЛЕНИЕ, ИНДЕКСЫ, ОТНОШЕНИЯ)

# НЕМЕЦКИЙ ЖИВЁТ ЗДЕСЬ ТОЛЬКО У ИМЕНИ ЗНАКА, И ЭТО ОБЪЯВЛЕНИЕ, А НЕ ДОЛГ (15.09). Пакеты
# языков дают `sign_names` на трёх языках — оттого «≈ heisst ungefähr» и звучит рядом с «≈
# is called approximately» и «≈ называется приближённо». Алгебраической же прозы по-немецки
# дом не держит: ни рамок степеней, ни подобных, ни распределительного закона — и выдумать
# их значило бы сочинить немецкий учебник из ничего.
#
#     ЯЗЫК, ВОШЕДШИЙ В ДОМ ОДНОЙ ВЕТВЬЮ, ДОЛЖЕН ПРОЧИМ ВЕТВЯМ РОВНО СТОЛЬКО, СКОЛЬКО ДОМ
#     ЕМУ ОБЕЩАЛ. Обещал он имя знака — имя знака и сказано.
#
# Отношения же (≥, ≠, перестановочность) не говорят ни на одном языке: они поставлены
# ЧИСЛАМИ, и внеязычность их объявлена тем, что слов в них нет вовсе.
ОБЪЯВЛЕННЫЕ_ПРОПУСКИ = {р: frozenset({"de"}) for р in РОДЫ if р != ИМЯ_ЗНАКА}

ЗАЧЕМ_РОДА = {
    ИМЯ_ЗНАКА: "«знак ∅ читается как пустое множество» — каждый знак живёт ровно столько "
               "проходов, сколько нужно закону массы, и ни одним больше",
    СТЕПЕНИ: "aᵐ × aⁿ = aᵐ⁺ⁿ и (aᵐ)ⁿ = aᵐⁿ — правило и тут же подстановка числами",
    ПОДОБНЫЕ: "p·x + q·x = (p+q)·x, и «p·x + q·y привести нельзя» с основанием",
    РАСПРЕДЕЛЕНИЕ: "a(b + c) = ab + ac, раскрытое и свёрнутое — два дела одной формулы",
    ИНДЕКСЫ: "x₁ и x₂: имя с индексом есть имя, а не выражение",
    ОТНОШЕНИЯ: "≥, ≠ и перестановочность умножения, показанные числами",
}


def страницы(pass_i):
    return pass_shows(pass_i)


def перебор_страниц(pass_i):
    return pass_shows(pass_i).тройками


def группы(pass_i):
    return [страницы(pass_i)]


def _показы():
    from layer import PASSES                             # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род, язык in перебор_страниц(шаг):
            for строка in с.split("\n"):
                if строка.rstrip():
                    вон.setdefault(строка.rstrip(),
                                   (bilang.сказанный(язык, строка.rstrip()), род))
    return вон


ПОКАЗЫ = _показы()

# ЯЗЫК ПОКАЗА НАЗВАН ПЕРВЫМ, РОД — ВТОРЫМ: так читает прибор щербатости.
РОД_В_ПОКАЗЕ = 1


def _самопроверка_дома():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    сбор = pass_shows(0)
    assert len(сбор) == len(сбор.роды), "показ остался без рода"
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка_дома()


def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
