def вещей(язык, i, n):
    """«5 книг», «5 książek» — товар и правило счёта берутся у дома цены."""
    return "%d %s" % (n, P.форма(язык, P.ЯЗЫКИ[язык]["вещи"][i], n))


def множ(язык, i, счётная=True):
    """ДВЕ ФОРМЫ МНОЖЕСТВА, И ЭТО НЕ ОДНА ФОРМА.

    «сколько книг» требует счётной (родительный количества), «кто дал Ане книги» — винительной.
    Дом, взявший одну на оба места, написал бы «кто дал Ане книг?» — тот же род ошибки, что
    и «коробку с 12 мелков»: СЧЁТНАЯ ФОРМА НЕ ЕСТЬ ПАДЕЖНАЯ. Языковой пакет держит обе (`many`
    и `few`), и там, где различия нет, обе ячейки дают одно слово.
    """
    ф = P.ЯЗЫКИ[язык]["вещи"][i]
    ф = ф if isinstance(ф, dict) else {"many": ф[-1], "few": ф[-1]}
    return ф["many"] if счётная else ф.get("few", ф["many"])


def _поля(язык, i, родня):
    р = РЕЧЬ[язык]
    род = РОД_ТОВАРА.get(язык, {}).get(i)
    по = {к: в[род] for к, в in ПО_РОДУ.get(язык, {}).items()} if род else {}
    return dict(имя=р["имя"], имяд=р["имяд"], имяр=р["имяр"],
                Тмн=множ(язык, i), Твин=множ(язык, i, счётная=False), **по,
                Р=р["родитель"][родня], дал=р["дал"][родня], П=р["получатель"][родня],
                Держ=р["держатель"][родня], имелР=р["имелР"][родня], отдала=р["отдала"])


def страница(язык, форма, i, родня, числа):
    р = РЕЧЬ[язык]
    п = _поля(язык, i, родня)
    дв = р["двоеточие"]
    if форма in ("дар", "даритель"):
        n, k = числа
        голова = (р["было"].format(N=вещей(язык, i, n), **п) + " "
                  + р["дар"].format(K=вещей(язык, i, k), **п))
        if форма == "даритель":
            # ВОПРОС ДОСТАЁТ САМОГО НОСИТЕЛЯ, А НЕ ЕГО ЧИСЛО
            return голова + " " + р["вопрос_кто"].format(**п) + " " + п["Р"] + "."
        return (голова + " " + р["вопрос_счёта"].format(**п) + " "
                + вещей(язык, i, n + k) + дв + f"{n} + {k} = {n + k}.")
    if форма == "отдача":
        n, k = числа
        # ТОТ ЖЕ НОСИТЕЛЬ В ПАДЕЖЕ ПОЛУЧАТЕЛЯ, И ЛЕДЖЕР ВЫЧИТАЕТ
        голова = (р["было"].format(N=вещей(язык, i, n), **п) + " "
                  + р["отдача"].format(K=вещей(язык, i, k), **п))  # {отдала} — форма девочки
        return (голова + " " + р["вопрос_остатка"].format(**п) + " "
                + вещей(язык, i, n - k) + дв + f"{n} − {k} = {n - k}.")
    if форма == "ряд":
        # ОДИН НОСИТЕЛЬ В ТРЁХ РОЛЯХ, И ЛЕДЖЕР ВЕДЁТСЯ ПО НЕМУ
        nа, nб, k, m = числа
        голова = р["ряд"].format(NА=вещей(язык, i, nа), NБ=вещей(язык, i, nб),
                                 K=вещей(язык, i, k), M=вещей(язык, i, m), **п)
        остаток, итог = nб - k, nб - k + m
        return (голова + " " + р["вопрос_ряда"].format(**п) + " " + вещей(язык, i, итог) + дв
                + f"{nб} − {k} = {остаток}, {остаток} + {m} = {итог}.")
    n, k1, k2 = числа
    # ДВА НОСИТЕЛЯ В ОДНОЙ СТРАНИЦЕ, И ЛЕДЖЕР В ДВА ШАГА
    пм, по = _поля(язык, i, "мать"), _поля(язык, i, "отец")
    голова = (р["было"].format(N=вещей(язык, i, n), **п) + " "
              + р["двое"].format(Р1=пм["Р"], дал1=пм["дал"], K1=вещей(язык, i, k1),
                                 Р2=по["Р"], дал2=по["дал"], K2=вещей(язык, i, k2)))
    return (голова + " " + р["вопрос_двоих"].format(**п) + " "
            + вещей(язык, i, n + k1 + k2) + дв
            + f"{n} + {k1} = {n + k1}, {n + k1} + {k2} = {n + k1 + k2}.")


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for i in ТОВАРЫ:
            for родня in РОДНЯ:
                for числа in ПАРЫ_ДАРА:
                    for форма in ("дар", "даритель"):
                        вон[страница(язык, форма, i, родня, числа)] = (язык, форма)
                for числа in ПАРЫ_ОТДАЧИ:
                    вон[страница(язык, "отдача", i, родня, числа)] = (язык, "отдача")
            for числа in ПАРЫ_ДВОИХ:
                вон[страница(язык, "двое", i, "мать", числа)] = (язык, "двое")
            for родня in РОДНЯ:
                for числа in ЧЕТВЁРКИ_РЯДА:
                    вон[страница(язык, "ряд", i, родня, числа)] = (язык, "ряд")
    return вон


ПОКАЗЫ = _показы()


def _альт(слова):
    сорт = sorted({с for с in слова if с}, key=lambda с: (-len(с), с))
    return "(?:" + "|".join(re.escape(с) for с in сорт) + ")"


def _дыры(язык, i):
    ф = P.ЯЗЫКИ[язык]["вещи"][i]
    формы = _альт(ф.values() if isinstance(ф, dict) else ф)
    число = r"\d+ " + формы
    р = РЕЧЬ[язык]
    # НОСИТЕЛЬ — ОБЪЯВЛЕННОЕ СЛОВО, А НЕ ЛЮБОЕ: ячейка родителя принимает только объявленных
    return {"N": число, "K": число, "K1": число, "K2": число, "S": число,
            "Р": _альт(р["родитель"].values()), "Р1": _альт(р["родитель"].values()),
            "Р2": _альт(р["родитель"].values()), "ОТВ": _альт(р["родитель"].values()),
            "дал": _альт(р["дал"].values()), "дал1": _альт(р["дал"].values()),
            "дал2": _альт(р["дал"].values()), "П": _альт(р["получатель"].values()),
            # ЯЧЕЙКИ РЯДА: держатель и его глагол — объявленные формы, а не любые слова
            "Держ": _альт(р["держатель"].values()), "имелР": _альт(р["имелР"].values()),
            "NА": число, "NБ": число, "M": число}


def рамка(язык, форма, i):
    р = РЕЧЬ[язык]
    п = _поля(язык, i, "мать")
    неизм = {к: в for к, в in п.items()
             if к not in ("Р", "дал", "П", "отдала", "Держ", "имелР")}
    дв = р["двоеточие"]
    if форма in ("дар", "даритель"):
        голова = (р["было"].format(N="{N}", **неизм) + " "
                  + р["дар"].format(K="{K}", Р="{Р}", дал="{дал}", П="{П}", **неизм))
        if форма == "даритель":
            return голова + " " + р["вопрос_кто"].format(**неизм) + " {ОТВ}."
        return голова + " " + р["вопрос_счёта"].format(**неизм) + " {S}" + дв + "{n} {зн} {k} = {s}."
    if форма == "отдача":
        голова = (р["было"].format(N="{N}", **неизм) + " "
                  + р["отдача"].format(K="{K}", П="{П}", отдала=р["отдала"], **неизм))
        return голова + " " + р["вопрос_остатка"].format(**неизм) + " {S}" + дв + "{n} {зн} {k} = {s}."
    if форма == "ряд":
        голова = р["ряд"].format(NА="{NА}", NБ="{NБ}", K="{K}", M="{M}", Р="{Р}", дал="{дал}",
                                 П="{П}", Держ="{Держ}", имелР="{имелР}",
                                 отдала=р["отдала"], **неизм)
        return (голова + " " + р["вопрос_ряда"].format(Держ="{Держ}", **неизм) + " {S}" + дв
                + "{nб} {зн1} {k} = {r}, {r2} {зн2} {m} = {s}.")
    голова = (р["было"].format(N="{N}", **неизм) + " "
              + р["двое"].format(Р1="{Р1}", дал1="{дал1}", K1="{K1}",
                                 Р2="{Р2}", дал2="{дал2}", K2="{K2}"))
    return (голова + " " + р["вопрос_двоих"].format(**неизм) + " {S}" + дв
            + "{n} {зн1} {k1} = {p}, {p2} {зн2} {k2} = {s}.")


_ЧИСЛА = {"n": r"(?P<n>\d+)", "k": r"(?P<k>\d+)", "s": r"(?P<s>\d+)", "k1": r"(?P<k1>\d+)",
          "k2": r"(?P<k2>\d+)", "p": r"(?P<p>\d+)", "p2": r"(?P<p2>\d+)",
          "nб": r"(?P<nb>\d+)", "m": r"(?P<m>\d+)", "r": r"(?P<r>\d+)", "r2": r"(?P<r2>\d+)",
          # ЗНАК ДЕЙСТВИЯ СТОИТ ДЫРОЙ: подменённый знак обязан быть ЛОЖЬЮ,
          # а не немотой (М-489); иначе истина берётся у соседа (М-131)
          "зн": r"(?P<zn>[+−])", "зн1": r"(?P<zn1>[+−])", "зн2": r"(?P<zn2>[+−])"}


def _образец(язык, форма, i):
    дыры, счёт, куски = _дыры(язык, i), {}, []
    for кусок in re.split(r"(\{[^}]+\})", рамка(язык, форма, i)):
        if not кусок.startswith("{"):
            куски.append(re.escape(кусок)); continue
        дыра = кусок[1:-1]
        if дыра in _ЧИСЛА:
            куски.append(_ЧИСЛА[дыра]); continue
        счёт[дыра] = счёт.get(дыра, 0) + 1
        куски.append(f"(?P<h_{дыра}__{счёт[дыра]}>{дыры[дыра]})")
    return re.compile("^" + "".join(куски) + "$")


ОБРАЗЦЫ = [(_образец(язык, форма, i), язык, форма, i)
           for язык in ЯЗЫКИ for форма in ФОРМЫ for i in ТОВАРЫ]


def _значения(м):
    вон = {}
    for ключ, знач in м.groupdict().items():
        if not ключ.startswith("h_"):
            вон[ключ] = знач; continue
        дыра, _ = ключ[2:].rsplit("__", 1)
        if дыра in вон and вон[дыра] != знач:
            return None
        вон[дыра] = знач
    return вон


def _число(кусок):
    return int(кусок.split(" ", 1)[0])


def _родня_по_слову(язык, слово, поле="родитель"):
    for родня, с in РЕЧЬ[язык][поле].items():
        if с == слово:
            return родня
    return None


def _вердикт(язык, форма, i, зн):
    р = РЕЧЬ[язык]
    вещь = lambda c: вещей(язык, i, c)
    if форма == "даритель":
        # ОТВЕТ ЕСТЬ САМ НОСИТЕЛЬ, И ИМЕННО ТОТ, ЧТО ДЕЙСТВОВАЛ
        родня = _родня_по_слову(язык, зн["Р"])
        if родня is None or зн["ОТВ"] != зн["Р"]:
            return False
        # ГЛАГОЛ СОГЛАСОВАН С РОДОМ РОДСТВЕННИКА (там, где язык его двигает)
        return зн["дал"] == РЕЧЬ[язык]["дал"][родня]
    if форма == "ряд":
        if зн.get("zn1") != "−" or зн.get("zn2") != "+":
            return False
        nа, nб = _число(зн["NА"]), _число(зн["NБ"])
        k, m = _число(зн["K"]), _число(зн["M"])
        родня = _родня_по_слову(язык, зн["Р"])
        # ДЕРЖАТЕЛЬ, ДЕЯТЕЛЬ И ПОЛУЧАТЕЛЬ — ОДНО ЛИЦО: три формы одного носителя, а не три лица
        if родня is None or зн["Держ"] != р["держатель"][родня]:
            return False
        # ГЛАГОЛ ДЕРЖАТЕЛЯ ЕСТЬ У ЯЗЫКОВ, ЧТО ЕГО СТАВЯТ: русский говорит «а у её мамы — 16»
        # без глагола вовсе, и требовать его от него значило бы требовать несуществующего
        if "имелР" in зн and зн["имелР"] != р["имелР"][родня]:
            return False
        if зн["дал"] != р["дал"][родня]:
            return False
        if зн["П"] != р["получатель"][родня]:
            return False
        if k >= nб:
            return False
        остаток, итог = nб - k, nб - k + m
        шаги = (int(зн["nb"]), int(зн["k"]), int(зн["r"]), int(зн["r2"]), int(зн["m"]), int(зн["s"]))
        if шаги != (nб, k, остаток, остаток, m, итог):
            return False
        return (зн["NА"] == вещь(nа) and зн["NБ"] == вещь(nб) and зн["K"] == вещь(k)
                and зн["M"] == вещь(m) and зн["S"] == вещь(итог))
    if форма == "двое":
        if зн.get("zn1") != "+" or зн.get("zn2") != "+":
            return False
        n, k1, k2 = _число(зн["N"]), _число(зн["K1"]), _число(зн["K2"])
        if зн["Р1"] == зн["Р2"]:
            return False  # ДВА НОСИТЕЛЯ, А НЕ ОДИН, НАЗВАННЫЙ ДВАЖДЫ
        for слово, глагол in ((зн["Р1"], зн["дал1"]), (зн["Р2"], зн["дал2"])):
            родня = _родня_по_слову(язык, слово)
            if родня is None or глагол != РЕЧЬ[язык]["дал"][родня]:
                return False
        шаги = (int(зн["n"]), int(зн["k1"]), int(зн["p"]), int(зн["p2"]), int(зн["k2"]), int(зн["s"]))
        if шаги != (n, k1, n + k1, n + k1, k2, n + k1 + k2):
            return False
        return зн["N"] == вещь(n) and зн["K1"] == вещь(k1) and зн["K2"] == вещь(k2) \
            and зн["S"] == вещь(n + k1 + k2)
    n, k = _число(зн["N"]), _число(зн["K"])
    if форма == "дар":
        if зн.get("zn") != "+":
            return False
        итог = n + k
    else:
        родня = _родня_по_слову(язык, зн["П"], "получатель")
        if родня is None:
            return False
        if зн.get("zn") != "−":
            return False
        if k >= n:
            return False
        итог = n - k
    if (int(зн["n"]), int(зн["k"]), int(зн["s"])) != (n, k, итог):
        return False
    if форма == "дар":
        родня = _родня_по_слову(язык, зн["Р"])
        if родня is None or зн["дал"] != РЕЧЬ[язык]["дал"][родня]:
            return False
    return зн["N"] == вещь(n) and зн["K"] == вещь(k) and зн["S"] == вещь(итог)


def судить(строка):
    """(судимо, истинно): a page whose bearer is a possessive relative that ACTS."""
    с = строка.strip()
    if с in ПОКАЗЫ:
        return True, True
    for образ, язык, форма, i in ОБРАЗЦЫ:
        м = образ.match(с)
        if not м:
            continue
        зн = _значения(м)
        if зн is None:
            return True, False
        return True, _вердикт(язык, форма, i, зн)
    return False, False


# ЧИСЛИТЕЛЬНОЕ ПРИ ЦИФРЕ: ячейка «one» дома цены несёт САМО СЛОВО («один карандаш», «jedna
# książka», «one book»), и русский даёт её не только единице, но и 21, 31, 41, 101. Строка
# «21 одна книга» есть ложь письма, и рубеж стоит здесь, чтобы такое число не вошло в набор
# незамеченным при следующей правке.
_ЧИСЛИТЕЛЬНОЕ_ПРИ_ЦИФРЕ = re.compile(
    r"\d+ (?:один|одна|одно|jeden|jedna|jedno|one |un |una |uno |ein |eine |eem |uma )")


def _самопроверка():
    for показ in ПОКАЗЫ:
        assert судить(показ) == (True, True), показ
    # РУБЕЖ ЧИСЛИТЕЛЬНОГО ПРИ ЦИФРЕ
    при_цифре = [с for с in ПОКАЗЫ if _ЧИСЛИТЕЛЬНОЕ_ПРИ_ЦИФРЕ.search(с)]
    assert not при_цифре, при_цифре[:3]
    # РУБЕЖ РОДА ТОВАРА: объявленный род должен покрывать КАЖДЫЙ товар языка, который его метит
    for язык, роды in РОД_ТОВАРА.items():
        assert set(роды) == set(ТОВАРЫ), (язык, sorted(роды), sorted(ТОВАРЫ))
        for ключ, формы in ПО_РОДУ[язык].items():
            for i in ТОВАРЫ:
                assert роды[i] in формы, (язык, ключ, i, роды[i])
    мутанты = 0
    for язык in ЯЗЫКИ:
        р = РЕЧЬ[язык]
        д = страница(язык, "дар", 1, "отец", (5, 4))
        # (1) ЛЕДЖЕР НЕ СХОДИТСЯ
        битая = д.replace("5 + 4 = 9", "5 + 4 = 10")
        assert судить(битая) == (True, False), битая
        # (2) ОТВЕТ НЕ ЕСТЬ ИТОГ ЛЕДЖЕРА
        битая = д.replace("? " + вещей(язык, 1, 9), "? " + вещей(язык, 1, 8))
        assert судить(битая) == (True, False), битая
        мутанты += 2
        к = страница(язык, "даритель", 1, "отец", (5, 4))
        # (3) ОТВЕТ НАЗВАЛ ДРУГОГО НОСИТЕЛЯ
        битая = к[: к.rindex(р["родитель"]["отец"])] + р["родитель"]["мать"] + "."
        assert судить(битая) == (True, False), битая
        мутанты += 1
        о = страница(язык, "отдача", 1, "мать", (9, 3))
        # (4) ВЫЧИТАНИЕ ОБРАЩЕНО
        битая = о.replace("9 − 3 = 6", "3 − 9 = 6")
        assert судить(битая) == (True, False), битая
        мутанты += 1
        дв = страница(язык, "двое", 1, "мать", (2, 3, 4))
        # (5) ВТОРОЙ ШАГ НЕ ОПИРАЕТСЯ НА ПЕРВЫЙ
        битая = дв.replace("2 + 3 = 5, 5 + 4 = 9", "2 + 3 = 5, 2 + 4 = 9")
        assert судить(битая) == (True, False), битая
        # (6) ДВА НОСИТЕЛЯ СЛИЛИСЬ В ОДНОГО
        битая = дв.replace(р["родитель"]["отец"], р["родитель"]["мать"])
        assert судить(битая) == (True, False), битая
        мутанты += 2
        # (7) ГЛАГОЛ НЕ СОГЛАСОВАН С РОДОМ РОДСТВЕННИКА (там, где язык его двигает)
        if р["дал"]["мать"] != р["дал"]["отец"]:
            м = страница(язык, "дар", 1, "мать", (5, 4))
            битая = м.replace(f'{р["родитель"]["мать"]} {р["дал"]["мать"]}',
                              f'{р["родитель"]["мать"]} {р["дал"]["отец"]}')
            assert судить(битая) == (True, False), битая
            мутанты += 1
        ряд = страница(язык, "ряд", 1, "мать", (4, 12, 3, 5))
        assert судить(ряд) == (True, True), ряд
        # (8) РЯД РАЗОРВАН: держатель и деятель — РАЗНЫЕ лица
        битая = ряд.replace(р["держатель"]["мать"], р["держатель"]["отец"], 1)
        assert судить(битая) == (True, False), битая
        # (9) ЛЕДЖЕР РЯДА ВЗЯТ ПО ДЕВОЧКЕ, А НЕ ПО НОСИТЕЛЮ
        битая = ряд.replace("12 − 3 = 9, 9 + 5 = 14", "4 − 3 = 1, 1 + 5 = 6")
        assert судить(битая) == (True, False), битая
        мутанты += 2
        # (10) ЗНАК ДЕЙСТВИЯ ПОДМЕНЁН: сложение стало вычитанием при том же ответе
        битая = д.replace("5 + 4 = 9", "5 − 4 = 9")
        assert судить(битая) == (True, False), битая
        битая = о.replace("9 − 3 = 6", "9 + 3 = 6")
        assert судить(битая) == (True, False), битая
        мутанты += 2
        # (11) ЗАЧИН ВОПРОСА ОБЪЯВЛЕН ДОМОМ ПАРЫ
        for стр in (д, к, о, дв, ряд):
            голова = стр[:стр.index("?") + 1]
            вопрос = голова[голова.rindex(". ") + 2:] if ". " in голова else голова
            assert asking.зачин_объявлен(вопрос) is not False, (язык, вопрос)
    for язык in ЯЗЫКИ:
        print("  ", страница(язык, "дар", 1, "отец", (5, 4)))
    for язык in ЯЗЫКИ:
        print("  ", страница(язык, "ряд", 1, "мать", (4, 12, 3, 5)))
    for язык in ("ru", "de", "fr", "pl"):
        print("  ", страница(язык, "даритель", 1, "мать", (5, 4)))
        print("  ", страница(язык, "отдача", 2, "отец", (9, 3)))
        print("  ", страница(язык, "двое", 1, "мать", (2, 3, 4)))
    по_форме = {}
    for _, (_я, форма) in ПОКАЗЫ.items():
        по_форме[форма] = по_форме.get(форма, 0) + 1
    print(f"  мутантов поймано: {мутанты}")
    print(f"  дом пишет показов: {len(ПОКАЗЫ)} (языков {len(ЯЗЫКИ)}, образцов {len(ОБРАЗЦЫ)}): "
          + ", ".join(f"{ф} {к}" for ф, к in по_форме.items()))


if __name__ == "__main__":
    _самопроверка()
