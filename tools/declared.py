#!/usr/bin/env python3
"""ОБЪЯВЛЕННОЕ ЗНАНИЕ: максимы и имена фигур, читаемые ДВУМЯ судами.

Есть утверждения, которые нельзя пересчитать и незачем: «одно
свидетельство убивает всеобщее утверждение», «рекурсия без основания
есть зависание». Это не арифметика и не грамматика — это ЗНАНИЕ,
объявленное рядом со списком, который оно уточняет (М-103), и потому
проверяемое ровно так же, как имена знаков: сверкой с объявлением.

ДРЕЙФ ОБЪЯВЛЕННОГО ВИДЕН ПАДЕНИЕМ СУДИМОСТИ, А НЕ ЛОЖЬЮ. Максима,
переписанная мимо объявления, не зовётся ложью — суд не знает, стала
она неверной или просто новой, — но и не проходит молча: она уходит из
судимых, и прибор охвата это показывает числом. Молчание здесь не
читается как чистота.

ДОМ ОДИН, ЧИТАТЕЛЕЙ ДВА. Максимы живут и в слое программ, и в слое
доказательства; два читателя одного объявления разошлись бы в день,
когда тронут любого из них.
"""

import json
import pathlib
import re

ПАКЕТЫ = pathlib.Path(__file__).resolve().parent / "langpacks"

_МАКСИМЫ = None
_ФИГУРЫ = None

# «закон; его пример» — максима и рядом с нею случай, её показывающий
С_ПРИМЕРОМ = re.compile(r"^(.+?);\s*(.+)$")
ФИГУРОЙ = re.compile(
    r"^(?:фигура|the shape)\s+(\S+)\s+"
    r"(?:читается как|is read as)\s+(.+?)[.。]?$")


def _пакеты():
    if ПАКЕТЫ.is_dir():
        for ф in sorted(ПАКЕТЫ.glob("*.json")):
            try:
                yield json.loads(ф.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue


def максимы():
    """{максима в нижнем регистре} — из пакетов языков."""
    global _МАКСИМЫ
    if _МАКСИМЫ is None:
        _МАКСИМЫ = {str(м).lower().rstrip(".。")
                    for п in _пакеты() for м in (п.get("maxims") or [])}
    return _МАКСИМЫ


def фигуры():
    """{имя фигуры: что она значит} — из пакетов языков."""
    global _ФИГУРЫ
    if _ФИГУРЫ is None:
        вон = {}
        for п in _пакеты():
            for фигура, смысл in (п.get("shape_names") or {}).items():
                вон.setdefault(str(фигура).lower(), set()).add(
                    str(смысл).lower())
        _ФИГУРЫ = вон
    return _ФИГУРЫ


def судить_объявленное(строка, счёт=None):
    """(судимо, истинно) для максимы и для имени фигуры.

    `счёт` — суд арифметики (или None): пример при максиме есть
    самостоятельное утверждение, и если его можно пересчитать, он
    ПЕРЕСЧИТЫВАЕТСЯ, а не принимается вместе с законом.
    """
    с = строка.strip().rstrip(".。")
    m = ФИГУРОЙ.match(с)
    if m:
        имя, смысл = m.group(1).lower(), m.group(2).lower()
        объявлено = фигуры().get(имя)
        if объявлено is None:
            return False, True
        return True, смысл in объявлено
    голова, пример = с, None
    m = С_ПРИМЕРОМ.match(с)
    if m:
        голова, пример = m.group(1).strip(), m.group(2).strip()
    if голова.lower() not in максимы():
        return False, True
    if пример and счёт is not None:
        судимо, истинно = счёт(пример)
        if судимо:
            return True, истинно
    return True, True
