#!/usr/bin/env python3
"""ОБЪЯВЛЕННОЕ ЗНАНИЕ: максимы и имена фигур, читаемые ДВУМЯ судами.

Есть утверждения, которые нельзя пересчитать и незачем: «одно
свидетельство убивает всеобщее утверждение», «рекурсия без основания
есть зависание». Это не арифметика и не грамматика — это ЗНАНИЕ,
объявленное рядом со списком, который оно уточняет (М-103), и потому
проверяемое ровно так же, как имена знаков: сверкой с объявлением.

ДРЕЙФ ОБЪЯВЛЕННОГО ВИДЕН ПАДЕНИЕМ СУДИМОСТИ, А НЕ ЛОЖЬЮ. Максима,
переписанная мимо объявления, не зовётся ложью — суд не знает, стала
она неверной или просто новой, — но и не проходит молча: она уходит из
судимых, и прибор охвата это показывает числом. Молчание здесь не
читается как чистота.

ДОМ ОДИН, ЧИТАТЕЛЕЙ ДВА. Максимы живут и в слое программ, и в слое
доказательства; два читателя одного объявления разошлись бы в день,
когда тронут любого из них.
"""

import json
import pathlib
import re

ПАКЕТЫ = pathlib.Path(__file__).resolve().parent / "langpacks"

_МАКСИМЫ = None
_ФИГУРЫ = None

# «закон; его пример» — максима и рядом с нею случай, её показывающий
С_ПРИМЕРОМ = re.compile(r"^(.+?);\s*(.+)$")
# ФИГУРУ ЗОВУТ И БЕЗ СЛОВА «ФИГУРА»: «the diamond is read as decision»
# есть то же утверждение, что «the shape diamond is read as choice».
# Неизвестное имя не зовётся ложью, и потому широкая голова безопасна:
# знак и буква сюда просто не попадут — их имён здесь нет.
ФИГУРОЙ = re.compile(
    r"^(?:фигура|the shape|the)\s+(\S+)\s+"
    r"(?:читается как|is read as)\s+(.+?)[.。]?$")


def _пакеты():
    if ПАКЕТЫ.is_dir():
        for ф in sorted(ПАКЕТЫ.glob("*.json")):
            try:
                yield json.loads(ф.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue


def максимы():
    """{максима в нижнем регистре} — из пакетов языков."""
    global _МАКСИМЫ
    if _МАКСИМЫ is None:
        _МАКСИМЫ = {str(м).lower().rstrip(".。")
                    for п in _пакеты() for м in (п.get("maxims") or [])}
    return _МАКСИМЫ


def фигуры():
    """{имя фигуры: что она значит} — из пакетов языков."""
    global _ФИГУРЫ
    if _ФИГУРЫ is None:
        вон = {}
        for п in _пакеты():
            for фигура, смысл in (п.get("shape_names") or {}).items():
                # У ФИГУРЫ БЫВАЕТ ДВА ИМЕНИ, И ОБЪЯВЛЕНИЕ ТОГДА СПИСОК.
                # Обращённый в строку целиком, список стал ОДНИМ
                # именем «['choice', 'decision']» — и оба настоящих
                # имени пропали, объявив ложью восемь честных строк.
                если = ([смысл] if isinstance(смысл, str)
                        else list(смысл or []))
                вон.setdefault(str(фигура).lower(), set()).update(
                    str(x).lower() for x in если)
        _ФИГУРЫ = вон
    return _ФИГУРЫ


_ПОНЯТИЯ = None

# ПОНЯТИЕ ОБЪЯВЛЕНО, И ПОТОМУ ЕГО ОПРЕДЕЛЕНИЕ ПРОВЕРЯЕМО. «остаток —
# это то, что не разделилось» нельзя пересчитать, но можно сверить с
# объявлением, как имя знака. Вопрос о понятии ручается за одно:
# спрошенное объявлено.
ПОНЯТИЕМ = re.compile(
    r"^(?:an? ([^\W\d_]+) is (.+?)|([^\W\d_]+) — это (.+?))[.。]?$")
ВОПРОСОМ = re.compile(
    r"^(?:what is an? ([^\W\d_]+)\?|что такое ([^\W\d_]+)\?)$")


def понятия():
    """{имя понятия: {объявленные определения}} — из пакетов."""
    global _ПОНЯТИЯ
    if _ПОНЯТИЯ is None:
        вон = {}
        for п in _пакеты():
            for имя, смысл in (п.get("concepts") or {}).items():
                вон.setdefault(str(имя).lower(), set()).add(
                    str(смысл).lower())
        _ПОНЯТИЯ = вон
    return _ПОНЯТИЯ


def судить_объявленное(строка, счёт=None):
    """(судимо, истинно) для максимы и для имени фигуры.

    `счёт` — суд арифметики (или None): пример при максиме есть
    самостоятельное утверждение, и если его можно пересчитать, он
    ПЕРЕСЧИТЫВАЕТСЯ, а не принимается вместе с законом.
    """
    с = строка.strip().rstrip(".。")
    m = ФИГУРОЙ.match(с)
    if m:
        имя, смысл = m.group(1).lower(), m.group(2).lower()
        объявлено = фигуры().get(имя)
        if объявлено is None:
            return False, True
        return True, смысл in объявлено
    m = ВОПРОСОМ.match(с + ("?" if not с.endswith("?") else ""))
    if m:
        имя = next(г for г in m.groups() if г)
        return (True, True) if имя.lower() in понятия() else (False, True)
    m = ПОНЯТИЕМ.match(с)
    if m:
        группы = [г for г in m.groups() if г is not None]
        имя, смысл = группы[0].lower(), группы[1].lower()
        объявлено = понятия().get(имя)
        if объявлено is not None:
            return True, смысл in объявлено
    голова, пример = с, None
    m = С_ПРИМЕРОМ.match(с)
    if m:
        голова, пример = m.group(1).strip(), m.group(2).strip()
    if голова.lower() not in максимы():
        return False, True
    if пример and счёт is not None:
        судимо, истинно = счёт(пример)
        if судимо:
            return True, истинно
    return True, True
