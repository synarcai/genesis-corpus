#!/usr/bin/env python3
"""ДОМ СРЕДНЕГО И РАЗБРОСА (14.09, куплен нулём пробы).

Замерено 14.09 по своду: «среднее скрывает разброс» / «the average hides» — НОЛЬ строк. Мир
среднего (`average`) СЧИТАЕТ среднее и умеет это хорошо. Но что среднее СКРЫВАЕТ, корпус не
говорит нигде — а именно этим средним и злоупотребляют.

    СРЕДНЕЕ ЕСТЬ ОДНО ЧИСЛО О МНОГИХ, И ОНО ТЕРЯЕТ ИХ РАЗЛИЧИЯ. Два ряда с ОДНИМ средним
    могут расходиться как угодно широко; два ряда с одним РАЗБРОСОМ — стоять где угодно
    далеко друг от друга. И самое неприятное: среднее бывает числом, какого нет НИ У КОГО.

ТРИ РОДА ПО ДЕЛУ:

    среднее_одно      средние равны, разбросы разные — и оба названы числом;
    разброс_один      разбросы равны, средние разные: та же потеря с другого конца;
    среднего_нет      среднее не совпадает ни с одним числом ряда. «Среднее 4» при ряде
                      1, 1, 10 верно и не описывает никого.

    ОБА ЧИСЛА НАЗВАНЫ, И ОБА ПРОВЕРЯЕМЫ. Дом не говорит «среднее обманывает» — это было бы
    мнение. Он ставит рядом два числа, какие можно пересчитать, и различие видно само.

ГРАНИЦА ОБЪЯВЛЕНА: среднее всякого ряда — целое. Дробное среднее есть иное дело (оно живёт
в мире доли единицы), и мешать его с разбросом значит учить обоим наполовину.
"""
import itertools
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("среднее_одно", "разброс_один", "среднего_нет")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "среднее_одно": "средние равны, разбросы разные — и оба названы числом",
    "разброс_один": "разбросы равны, средние разные: та же потеря с другого конца",
    "среднего_нет": "среднее не совпадает ни с одним числом ряда",
}

РЯДЫ = (
    (3, 4, 5), (1, 4, 7), (2, 4, 6), (4, 4, 4), (0, 4, 8),
    (1, 2, 3), (5, 6, 7), (10, 11, 12), (2, 3, 4), (7, 8, 9),
    (1, 1, 10), (2, 2, 14), (1, 5, 15), (3, 3, 12), (1, 1, 1),
    (2, 2, 11), (1, 2, 12), (3, 4, 14), (1, 3, 14), (2, 5, 17),
    (6, 6, 6), (9, 10, 11), (0, 6, 12), (5, 5, 5), (2, 6, 10),
)

РАМКИ = {
    "ru": {
        "среднее_одно": "первый ряд: {р1}; второй ряд: {р2}. среднее одно — {с}, а разброс "
                        "разный: у первого {д1}, у второго {д2}.",
        "разброс_один": "первый ряд: {р1}; второй ряд: {р2}. разброс один — {д}, а среднее "
                        "разное: у первого {с1}, у второго {с2}.",
        "среднего_нет": "ряд: {р1}. среднее {с}, и такого числа в ряду нет ни одного.",
    },
    "en": {
        "среднее_одно": "first row: {р1}; second row: {р2}. the mean is the same — {с}, and "
                        "the spread is not: the first {д1}, the second {д2}.",
        "разброс_один": "first row: {р1}; second row: {р2}. the spread is the same — {д}, "
                        "and the mean is not: the first {с1}, the second {с2}.",
        "среднего_нет": "row: {р1}. the mean is {с}, and no number in the row is that.",
    },
}


def среднее(ряд):
    """Среднее — или None, если оно не целое: граница дома объявлена."""
    сумма = sum(ряд)
    return сумма // len(ряд) if сумма % len(ряд) == 0 else None


def разброс(ряд):
    return max(ряд) - min(ряд)


def страница(язык, род, а, б):
    са, сб = среднее(а), среднее(б)
    if са is None or сб is None:
        return None
    рамки = РАМКИ[язык]
    ряд = lambda р: ", ".join(str(n) for n in р)     # noqa: E731 — одна строка, одно дело
    if род == "среднего_нет":
        if са in а:
            return None
        return рамки["среднего_нет"].format(р1=ряд(а), с=са)
    if а == б:
        return None
    if род == "среднее_одно":
        if са != сб or разброс(а) == разброс(б):
            return None
        return рамки["среднее_одно"].format(р1=ряд(а), р2=ряд(б), с=са,
                                            д1=разброс(а), д2=разброс(б))
    if разброс(а) != разброс(б) or са == сб:
        return None
    return рамки["разброс_один"].format(р1=ряд(а), р2=ряд(б), д=разброс(а), с1=са, с2=сб)


ПРЕДЕЛ_ПАР = 2      # сколько соседей даётся одному ряду в родах о паре


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for а in РЯДЫ:
            п = страница(язык, "среднего_нет", а, а)
            if п:
                вон.setdefault(п, (язык, "среднего_нет"))
        # ПАРА РЯДУ НУЖНА ОДНА-ДВЕ, А НЕ ВСЕ. Третий сосед с тем же средним повторяет
        # второго: та же мысль теми же числами. Без этого предела пара родов заглушала род
        # «среднего нет» вчетверо с лишним.
        for род in ("среднее_одно", "разброс_один"):
            сколько = {}
            for а, б in itertools.combinations(РЯДЫ, 2):
                if сколько.get(а, 0) >= ПРЕДЕЛ_ПАР:
                    continue
                п = страница(язык, род, а, б)
                if п:
                    вон.setdefault(п, (язык, род))
                    сколько[а] = сколько.get(а, 0) + 1
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД ПЕРЕСЧИТЫВАЕТ ОБА ЧИСЛА: среднее и разброс, — и требует, чтобы сказанное сошлось. Он
# проверяет и САМО ОСНОВАНИЕ показа: «среднее одно» при разных средних есть ложь, даже когда
# оба числа посчитаны верно.
def _образцы(язык):
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык][род])
        for дыра, узор in (("р1", r"[\d, ]+"), ("р2", r"[\d, ]+"), ("с1", r"\d+"),
                           ("с2", r"\d+"), ("д1", r"\d+"), ("д2", r"\d+"),
                           ("с", r"\d+"), ("д", r"\d+")):
            о = о.replace(re.escape("{" + дыра + "}"), f"(?P<{дыра}>{узор})")
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def _ряд(кусок):
    try:
        ряд = tuple(int(с) for с in кусок.split(","))
    except ValueError:
        return None
    return ряд if len(ряд) >= 2 else None


def судить(строка):
    """(судимо, истинно) — среднее и разброс пересчитаны, основание показа проверено."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            а = _ряд(д["р1"])
            if а is None:
                continue
            са = среднее(а)
            if са is None:
                return True, False
            if род == "среднего_нет":
                return True, int(д["с"]) == са and са not in а
            б = _ряд(д["р2"])
            if б is None:
                continue
            сб = среднее(б)
            if сб is None or а == б:
                return True, False
            if род == "среднее_одно":
                return True, (са == сб and int(д["с"]) == са
                              and int(д["д1"]) == разброс(а) and int(д["д2"]) == разброс(б)
                              and разброс(а) != разброс(б))
            return True, (разброс(а) == разброс(б) and int(д["д"]) == разброс(а)
                          and int(д["с1"]) == са and int(д["с2"]) == сб and са != сб)
    return False, True


# ПОДСАДКИ ОБЪЯВЛЕНЫ ЗДЕСЬ, И СУД БЕРЁТ ИХ ОТСЮДА ЖЕ.
ПОДСАДКИ = (
    "первый ряд: 3, 4, 5; второй ряд: 1, 4, 7. среднее одно — 5, а разброс разный: у "
    "первого 2, у второго 6.",
    "первый ряд: 3, 4, 5; второй ряд: 1, 4, 7. среднее одно — 4, а разброс разный: у "
    "первого 3, у второго 6.",
    "первый ряд: 1, 2, 3; второй ряд: 2, 3, 4. среднее одно — 2, а разброс разный: у "
    "первого 2, у второго 2.",
    "ряд: 3, 4, 5. среднее 4, и такого числа в ряду нет ни одного.",
    "первый ряд: 1, 2, 3; второй ряд: 5, 6, 7. разброс один — 2, а среднее разное: у "
    "первого 2, у второго 5.",
    "first row: 3, 4, 5; second row: 1, 4, 7. the mean is the same — 4, and the spread is "
    "not: the first 2, the second 5.",
)


def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    for ряд in РЯДЫ:
        assert среднее(ряд) is not None, f"среднее не целое: {ряд}"
        assert len(ряд) >= 2, f"ряд короче двух: {ряд}"
    # ОБА ЛИЦА СРЕДНЕГО КУПЛЕНЫ: есть ряды, где среднее в ряду есть, и где его нет.
    лица = {среднее(р) in р for р in РЯДЫ}
    assert лица == {True, False}, "куплено одно лицо среднего"
    # ЗАКОН МАССЫ ПРОВЕРЕН ДОМОМ, А НЕ ОТЛОЖЕН НА ПРИБОР: род ниже девяти показов не
    # выучивается, и дом обязан знать это о себе сам.
    import collections as _сч
    счёт = _сч.Counter(р for _я, р in ПОКАЗЫ.values())
    assert min(счёт.values()) >= 9, f"род ниже закона массы: {счёт.most_common()[-1]}"
    # ДВЕ РАМКИ НА ОДНОЙ ЗАПИСИ ДЕЛАЮТ РОД НЕРАЗЛИЧИМЫМ: страж дома двух процентов.
    for с, (язык, _р) in ПОКАЗЫ.items():
        совпали = [род for род, о in _ОБРАЗЦЫ[язык] if о.fullmatch(с)]
        assert len(совпали) == 1, f"две рамки на одной записи ({совпали}): {с}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
