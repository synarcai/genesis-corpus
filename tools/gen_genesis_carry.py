#!/usr/bin/env python3
"""КОВКА ДОМА ИМЕНОВАННОГО ЧИСЛА.

ПЕРЕНОС И ЕГО ОТСУТСТВИЕ ИДУТ В ОДНОМ ПРОХОДЕ: «40 + 80 = 120, перенос» и «40 + 50 = 90, переноса
нет» суть минимальная пара ПО ОСНОВАНИЮ — те же меры, то же действие, и разница в одном: перешла
ли малая доля за основание. Порознь читатель выведет, что перенос бывает всегда.

ЗАЁМ И ОСНОВАНИЕ ИДУТ СВОЕЙ ГРУППОЙ: первый есть обратный ход того же закона (основание не
прибавляется, а занимается), второй говорит, ЧЬЁ это основание. Порознь заём читался бы правилом
вычитания, а не обратной стороной переноса.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import carryforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_carry.txt"
ГРУППЫ = (("перенос", "без переноса"), ("заём", "основание"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
