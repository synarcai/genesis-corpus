def _роды_страниц(показы, место=1):
    """{род: [страницы]} — ЗНАЧЕНИЕ ПОКАЗА У ДОМОВ ДВОЯКО: (язык, род) у двуязычных, род у прочих.

    ТРЕТИЙ ЧЛЕН ЗНАЧЕНИЯ ЕСТЬ У ДВУХ ДОМОВ, И ЗНАЧИТ ОН У НИХ РАЗНОЕ: у `pronobject` это
    местоимение — ДОВОД страницы, а род стоит вторым; у `cmpframes` вторым стоит группа
    товаров, а род — третьим. Указатель не гадает: дом, у которого род не второй, говорит
    это сам, объявляя `РОД_В_ПОКАЗЕ`.

        УКАЗАТЕЛЬ, ВЫБИРАЮЩИЙ ЧЛЕН ЗНАЧЕНИЯ ПО ДОГАДКЕ, НАЗОВЁТ РОДОМ ДОВОД — и назовёт
        одинаково у двух домов, у которых на этом месте стоит разное.
    """
    вон = {}
    for стр, знач in (показы.items() if isinstance(показы, dict) else ()):
        род = знач[место] if isinstance(знач, tuple) and len(знач) > место else знач
        вон.setdefault(род, []).append(стр)
    return вон


def разобрать(имя, модуль):
    """(взят?, запись | причина отказа). ОДНО ПРАВИЛО ДОПУСКА ДЛЯ ОБОИХ ИМЁН ОБЪЯВЛЕНИЯ."""
    роды, формы = getattr(модуль, "РОДЫ", None), getattr(модуль, "ФОРМЫ", None)
    какое, объявлено = ("РОДЫ", роды) if роды else ("ФОРМЫ", формы) if формы else (None, None)
    if not объявлено:
        return None
    if isinstance(объявлено, dict):
        # СЛОВАРЬ, ЧИТАЕМЫЙ КАК РЯД, ОТДАЁТ КЛЮЧИ — И КЛЮЧИ ЭТИ ПРОЙДУТ ПРОВЕРКУ НА ИМЕНА.
        # У `coprime` и `parity` `ФОРМЫ` есть {язык: рамка}; в кортеж он обращается списком
        # языков, и всякий язык — строка. Правило имён их пропустило бы; спасала лишь
        # недостача словаря страниц, то есть УДАЧА, А НЕ ЗАКОН.
        return (False, имя, какое, "объявление есть словарь рамок, а не ряд имён рода")
    объявлено = tuple(объявлено)
    if not all(isinstance(р, str) for р in объявлено):
        return (False, имя, какое, "объявление не кортеж имён, а таблица, совпавшая именем")
    место = getattr(модуль, "РОД_В_ПОКАЗЕ", 1)
    по_роду = _роды_страниц(getattr(модуль, "ПОКАЗЫ", None), место)
    if какое == "ФОРМЫ" and not по_роду:
        # СТАРШЕЕ ИМЯ ПЕРЕГРУЖЕНО И ОБЯЗАНО ДОКАЗАТЬ СЕБЯ СТРАНИЦАМИ: у `units` это единицы
        # времени, у `parity` и `coprime` языки. Слово `РОДЫ` однозначно и доказательств не
        # просит — оттого дом, кующий по запросу, объявляет роды им, а не старшим словом.
        return (False, имя, какое, "старшее имя объявления без словаря страниц не доказано")
    if по_роду and not any(р in по_роду for р in объявлено):
        return (False, имя, какое,
                f"ни одно из {len(объявлено)} объявленных имён не назвало страницы "
                f"(страницы метятся иначе: {', '.join(sorted(по_роду)[:3])}…)")
    зачем = getattr(модуль, "ЗАЧЕМ_РОДА", None) or {}
    ряд = [(р, len(по_роду.get(р, ())) if по_роду else None,
            (по_роду.get(р) or [""])[0][:ОБРАЗЕЦ_ДО], зачем.get(р)) for р in объявлено]
    вне = sorted(((р, len(с)) for р, с in по_роду.items() if р not in set(объявлено)),
                 key=lambda т: (-т[1], т[0]))
    return (True, имя, какое, ряд, вне)


