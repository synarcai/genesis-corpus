#!/usr/bin/env python3
"""УКАЗАТЕЛЬ РОДОВ — имя всякого объявленного рода показа, его дом, число страниц и образец.

    РОД, ОБЪЯВЛЕННЫЙ ДОМОМ, ЕСТЬ СУЩНОСТЬ, А НЕ ПОБОЧНОЕ СВОЙСТВО НАБОРА СТРАНИЦ. Дом говорит
    `РОДЫ = ("после числа партитив", "это единственное, а не множественное", …)` — и всякая
    его страница знает, к которому она принадлежит.

ПОВОД ПРИШЁЛ СНАРУЖИ (13.09). holon-f9 спросил, есть ли у корпуса МАШИННО ЧИТАЕМЫЙ список
объявленных родов: имя рода и признак, по которому страница к нему принадлежит. У читателя
род есть побочный эффект набора дорог, и организм не может сказать «этот род я знаю, этого не
знаю»; корзина «страниц без рода» у него — 139 форм, и разности «объявлено − прочитано» ему не
из чего взять.

Список этот в корпусе БЫЛ — по частям и без имени: 114 домов объявляют `РОДЫ`, 577 родов
всего, 498 различных. Не было ОДНОГО МЕСТА, где он собран.

    ЗНАНИЕ, ЛЕЖАЩЕЕ В СТА ЧЕТЫРНАДЦАТИ ФАЙЛАХ ПОРОЗНЬ, ЕСТЬ ЗНАНИЕ КОРПУСА И НЕ ЕСТЬ ЗНАНИЕ
    ЧИТАТЕЛЯ: последнему нужен один файл, а не сто четырнадцать ввозов.

ЧТО В УКАЗАТЕЛЕ, И ПОЧЕМУ ИМЕННО ЭТО:

    ИМЯ ДОМА и МИР, который он кует, — чтобы читатель знал, где страницы лежат;
    ИМЯ РОДА дословно, как объявил дом;
    ЧИСЛО СТРАНИЦ этого рода — знаменатель для всякой меры покрытия;
    ОБРАЗЕЦ — первая страница рода, дословно, до ста двадцати знаков.

    ОБРАЗЕЦ ДАЁТ ЧИТАТЕЛЮ ПРИЗНАК, КОТОРОГО ИМЯ РОДА НЕ ДАЁТ: по имени «спрошенное» не
    узнать страницы, по образцу — узнать. Признак этот НЕ ОБЪЯВЛЕН ФОРМАЛЬНО, и сказано
    почему: у 498 родов он был бы 498 разными выражениями, и всякое разошлось бы с домом на
    первой же правке рамки.

ЧЕТЫРНАДЦАТЬ ДОМОВ ОБЪЯВЛЯЮТ РОДЫ И НЕ ДЕРЖАТ СЛОВАРЯ СТРАНИЦ, и это названо, а не пропущено.
Дома старшего устройства (`calforms`, `geoforms`, `physforms`, `primeforms` и десять прочих)
строят страницу ПО ЗАПРОСУ, а не хранят набором: `ПОКАЗЫ` у них нет вовсе. Их роды объявлены
и здесь СЧИТАЮТСЯ, но числа страниц и образца у них нет — взять их значило бы позвать
кузницу, а указатель кузниц не зовёт.

    УКАЗАТЕЛЬ, ЗОВУЩИЙ КУЗНИЦУ, ПЕРЕСТАЁТ БЫТЬ УКАЗАТЕЛЕМ И СТАНОВИТСЯ ВТОРОЙ КУЗНИЦЕЙ: он
    подорожает вдесятеро и разойдётся с первой на первой же правке.

ЧЕГО ЗДЕСЬ НЕТ. Формального образца принадлежности («страница рода X, если совпала с этим
выражением»). Дом узнаёт свою страницу ПО ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку, —
и это его закон, а не недосмотр.

    ДОМ, УЗНАЮЩИЙ СТРАНИЦУ ПО ПРИЗНАКУ, А НЕ ПО НАБОРУ, ЗОВЁТ СВОЕЙ ЧУЖУЮ РЕЧЬ, СОВПАВШУЮ С
    НИМ ФОРМОЙ. Читателю, которому нужен признак, довольно образца и имени мира: страницы
    рода лежат в мире целиком.

    python3 tools/genus_atlas.py [--собрать] [--json]
"""
# ПУСТОЙ-ОБХОД: --двор no-such-dir
import argparse
import importlib
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ЦЕЛЬ = КОРЕНЬ / "reports" / "ATLAS-GENERA.md"
ЦЕЛЬ_JSON = КОРЕНЬ / "reports" / "ATLAS-GENERA.json"
ОБРАЗЕЦ_ДО = 120


def дома(двор):
    """[(имя дома, имя мира, [(род, число страниц, образец)])] — по объявлению `РОДЫ`."""
    import genesis                                       # noqa: PLC0415
    миры = {м["name"] for м in genesis.manifest()["worlds"] if м.get("text") == "shows"}
    вон = []
    for п in sorted(pathlib.Path(двор).glob("*forms.py")):
        try:
            м = importlib.import_module(п.stem)
        except Exception:                                # noqa: BLE001
            continue
        роды, показы = getattr(м, "РОДЫ", None), getattr(м, "ПОКАЗЫ", None)
        if not роды:
            continue
        # ДОМ БЕЗ СЛОВАРЯ СТРАНИЦ СЧИТАЕТСЯ РОДАМИ, А НЕ СТРАНИЦАМИ: он строит показ по
        # запросу, и указатель кузницы не зовёт.
        по_роду = {}
        for стр, знач in (показы.items() if isinstance(показы, dict) else ()):
            # ЗНАЧЕНИЕ ПОКАЗА У ДОМОВ ДВОЯКО: (язык, род) у двуязычных, просто род у прочих.
            род = знач[1] if isinstance(знач, tuple) and len(знач) > 1 else знач
            по_роду.setdefault(род, []).append(стр)
        имя_мира = п.stem[:-5] if п.stem.endswith("forms") else п.stem
        ряд = [(р, len(по_роду.get(р, ())) if по_роду else None,
                (по_роду.get(р) or [""])[0][:ОБРАЗЕЦ_ДО]) for р in роды]
        вон.append((п.stem, имя_мира if имя_мира in миры else None, ряд))
    return вон


def _проба():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что род и его страницы РАЗБИРАЮТСЯ.

        ЭТОТ УКАЗАТЕЛЬ ЗЕЛЕНЕЕТ ОТ СОВПАДЕНИЯ С САМИМ СОБОЙ. Пусть разбор `ПОКАЗЫ` сломается
        — и всякий род получит ноль страниц, а указатель сойдётся сам с собою, пустой.

    Два выдуманных дома: двуязычный (значение — пара) и одноязычный (значение — род).
    """
    беды = []
    двуязычный = {"а": ("ru", "первый"), "б": ("en", "первый"), "в": ("ru", "второй")}
    одноязычный = {"а": "первый", "б": "первый", "в": "второй"}
    for имя, показы, ждём in (("двуязычный", двуязычный, {"первый": 2, "второй": 1}),
                              ("одноязычный", одноязычный, {"первый": 2, "второй": 1})):
        по_роду = {}
        for стр, знач in показы.items():
            род = знач[1] if isinstance(знач, tuple) and len(знач) > 1 else знач
            по_роду.setdefault(род, []).append(стр)
        вышло = {р: len(с) for р, с in по_роду.items()}
        if вышло != ждём:
            беды.append(f"{имя}: разобрано {вышло}, а надо {ждём}")
    return беды


def main():
    # ПРОБА ИДЁТ ПРИ ВСЯКОМ ПРОГОНЕ, А НЕ ПО ПРОСЬБЕ.
    if (беды := _проба()):
        for б in беды:
            print(f"  ПРОБА ПАЛА: {б}")
        print(f"УКАЗАТЕЛЬ РОДОВ ОТКАЗ: разбор рода не доказан ({len(беды)} бед)")
        return 2
    ап = argparse.ArgumentParser()
    ап.add_argument("--двор", default=None)
    ап.add_argument("--собрать", action="store_true")
    ап.add_argument("--json", action="store_true")
    дов = ап.parse_args()
    двор = pathlib.Path(дов.двор) if дов.двор else КОРЕНЬ / "tools"
    if not двор.is_dir():
        print(f"УКАЗАТЕЛЬ РОДОВ ОТКАЗ: двора нет — {двор}")
        return 2
    ряд = дома(двор)
    if not ряд:
        print("УКАЗАТЕЛЬ РОДОВ ОТКАЗ: домов с объявленными родами нет")
        return 2
    всего = sum(len(р) for _и, _м, р in ряд)
    различных = len({р for _и, _м, рр in ряд for р, _n, _о in рр})
    страниц = sum(n for _и, _м, рр in ряд for _р, n, _о in рр if n is not None)
    без_страниц = sum(1 for _и, _м, рр in ряд if all(n is None for _р, n, _о in рр))
    без_мира = sum(1 for _и, м, _р in ряд if м is None)

    тело_json = json.dumps(
        {"домов": len(ряд), "родов": всего, "различных": различных, "страниц": страниц,
         "домов_без_словаря_страниц": без_страниц,
         "дома": [{"дом": и, "мир": м,
                   "роды": [{"род": р, "страниц": n, "образец": о} for р, n, о in рр]}
                  for и, м, рр in ряд]},
        ensure_ascii=False, indent=2) + "\n"

    out = [f"# УКАЗАТЕЛЬ РОДОВ — {всего} объявленных родов показа в {len(ряд)} домах", "",
           "Собран из дерева орудием `tools/genus_atlas.py`. Род объявляется домом в таблице",
           "`РОДЫ`, и всякая его страница знает, к которому принадлежит.", "",
           "    РОД, ОБЪЯВЛЕННЫЙ ДОМОМ, ЕСТЬ СУЩНОСТЬ, А НЕ ПОБОЧНОЕ СВОЙСТВО НАБОРА СТРАНИЦ.",
           "",
           f"**Родов {всего}, различных имён {различных}, страниц под ними {страниц}.**",
           f"Домов без своего мира показов — {без_мира}: их страницы живут в чужих мирах или",
           "не кованы вовсе. Домов, строящих страницу ПО ЗАПРОСУ и не держащих её набором, —",
           f"{без_страниц}: их роды объявлены, а числа страниц и образца у них нет.", "",
           "Машинное чтение: `reports/ATLAS-GENERA.json` — тот же список без прозы.", ""]
    for имя, мир, рр in ряд:
        out += ["", f"## `{имя}`" + (f" → мир `{мир}`" if мир else " (мира показов нет)"), ""]
        for р, n, о in рр:
            out.append(f"- **{р}** — " + (f"страниц {n}" if n is not None
                                          else "страница строится по запросу"))
            if о:
                out.append(f"  образец: {о}")
    тело = "\n".join(out) + "\n"

    ЦЕЛЬ.parent.mkdir(parents=True, exist_ok=True)
    было = ЦЕЛЬ.read_text(encoding="utf-8") if ЦЕЛЬ.is_file() else ""
    было_json = ЦЕЛЬ_JSON.read_text(encoding="utf-8") if ЦЕЛЬ_JSON.is_file() else ""
    if not дов.собрать:
        сошлось = (было == тело) and (было_json == тело_json)
        поза = "PASS" if сошлось else "FAIL"
        if not сошлось:
            print(f"  указатель на диске разошёлся с деревом: строк было "
                  f"{было.count(chr(10))}, стало бы {тело.count(chr(10))}")
        print(f"УКАЗАТЕЛЬ РОДОВ {поза}: {0 if сошлось else 1} расхождений с деревом "
              f"(рубеж 0); домов {len(ряд)}, родов {всего}, страниц {страниц}")
        return 0 if сошлось else 1
    ЦЕЛЬ.write_text(тело, encoding="utf-8")
    ЦЕЛЬ_JSON.write_text(тело_json, encoding="utf-8")
    print(f"УКАЗАТЕЛЬ РОДОВ СОБРАН: {ЦЕЛЬ.name} и {ЦЕЛЬ_JSON.name}, домов {len(ряд)}, "
          f"родов {всего}, различных {различных}, страниц {страниц}, строк {len(out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
