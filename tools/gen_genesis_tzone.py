#!/usr/bin/env python3
"""GENESIS layer: ЧАСОВОЙ ПОЯС — see tools/tzoneforms.py for the law.

ОБЕ СТОРОНЫ ЛОВУШКИ ИДУТ ОДНОЙ ГРУППОЙ: «полдень не всюду полдень» и «в одном поясе время
одно». Показанная порознь, первая отменяет само понятие пояса, вторая переносит согласие на
всех.

    ЧАСОВОЙ ПОЯС ЕСТЬ ИМЕННО ТО МНОЖЕСТВО МЕСТ, ГДЕ ЧАС ОДИН И ТОТ ЖЕ.

КРУГ СУТОК — одной группой обе стороны: назад через полночь и вперёд через неё. Разность
поясов и её независимость от часа — вместе: второе есть довод первого. ВОПРОС отдельно.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import tzoneforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_tzone.txt"
ГРУППЫ = (("разница поясов", "разница не зависит от часа", "время по разнице"),
          ("полдень не всюду полдень", "в одном поясе время одно"),
          ("через полночь назад", "через полночь вперёд"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
