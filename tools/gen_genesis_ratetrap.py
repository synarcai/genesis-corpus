#!/usr/bin/env python3
"""GENESIS layer: ЛОВУШКИ ОТНОШЕНИЯ — see tools/ratetrapforms.py for the law.

СКОРОСТЬ И РАБОТА ИДУТ ОДНОЙ ГРУППОЙ: обе о том, что складывать надо ОБРАТНОЕ тому, что
дано, — пути и времена вместо скоростей, работу за час вместо часов. Это один приём в двух
одеждах, и разлучить их значило бы показать приём дважды как два разных.

ПРИРОСТ И СКИДКА — второй группой, и это не удобство: они ЗЕРКАЛЬНЫ. Прирост даёт больше
суммы процентов, убыль — меньше, и читатель, получивший одно без другого, выучит правило
«всегда больше» либо «всегда меньше», и оба будут ложны.

    ЛОВУШКА, ПОКАЗАННАЯ ОДНОЙ СТОРОНОЙ, УЧИТ НОВОЙ ЛОВУШКЕ.

ВОПРОС отдельно — ответ рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import ratetrapforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_ratetrap.txt"
ГРУППЫ = (("средняя скорость", "совместная работа"),
          ("два прироста", "две скидки"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
