#!/usr/bin/env python3
"""КОВКА ДОМА СРАВНЕНИЯ ВЕЛИЧИН.

ЛОВУШКА И ЕЁ УПРАВА ИДУТ В ОДНОМ ПРОХОДЕ: «900 метров или 1 километр» и «900 метров или
200 метров» суть минимальная пара ПО МЕРЕ — те же числа, тот же вопрос, и разница в одном: одна
мера или две. Порознь читатель выведет, что число обманывает всегда, и станет искать подвох там,
где мера одна.

ОСНОВАНИЕ И ОТКАЗ ИДУТ СВОЕЙ ГРУППОЙ: первое говорит, откуда берётся обман, второй — где вопрос
вовсе не имеет ответа. Обе страницы об одном: величина есть число И мера, и без меры не решить
ни что больше, ни можно ли сравнивать.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import unitcmpforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_unitcmp.txt"
ГРУППЫ = (("число обманывает", "мера одна"), ("основание", "не сравнить"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
