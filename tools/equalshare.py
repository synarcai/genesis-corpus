import actturn as A  # noqa: E402 — девять языков берутся у соседа, а не объявляются вторым списком

ЯЗЫКИ = A.ЯЗЫКИ
РОДЫ = ("ровно", "с_остатком", "на_ноль")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "ровно": "«раздели 14 на 2 поровну» — делится нацело, и ответ распределительный: «по 7»",
    "с_остатком": "«раздели 14 на 3 поровну» — «по 4, и 2 останется»: остаток НАЗВАН",
    "на_ноль": "«раздели 14 на 0 поровну» — отказ с основанием, а не молчание и не ноль",
}

# ПАРЫ «СКОЛЬКО, НА СКОЛЬКО»: первые делятся нацело, вторые дают остаток. Ноль стои́т
# отдельно — он не пара чисел, а объявленная невозможность.
РОВНЫЕ = ((14, 2), (12, 3), (20, 4), (18, 6), (24, 8), (15, 5), (16, 2), (21, 7),
          (30, 5), (28, 4), (36, 6), (27, 3))
С_ОСТАТКОМ = ((14, 3), (17, 5), (22, 4), (13, 2), (19, 6), (25, 7), (23, 4), (11, 3),
              (29, 5), (31, 6), (26, 8), (10, 4))
НА_НОЛЬ = (14, 12, 20, 18, 24, 15, 16, 21, 30, 28, 36, 27)

# ИМЯ ЧАСТИ СОГЛАСУЕТСЯ С ЧИСЛОМ, И ГДЕ СОГЛАСУЕТСЯ — ОБЪЯВЛЕНО ФУНКЦИЕЙ (14.09). У восьми
# языков имя части при числе не меняется («2 parts égales», «5 parts égales»), у польского
# меняется падеж: 2…4 требуют именительного множественного («2 równe części»), прочие — и
# ноль в том числе — родительного множественного («5 równych części», «0 równych części»).
#
#     ЗАКОН СОГЛАСОВАНИЯ ЕСТЬ ЗАКОН ЯЗЫКА, А НЕ ДОМА, И ДОМ ЕГО НЕ ВЫВОДИТ, А ЗОВЁТ. Здесь
#     он объявлен там же, где речь, и суд проверяет его на каждой странице: форма части,
#     не отвечающая числу, есть ложь, видная в грамматике.
ЧАСТИ = {
    "pl": lambda b: "równe części" if 2 <= b % 10 <= 4 and not 12 <= b % 100 <= 14
          else "równych części",
}


def часть(язык, b):
    """Имя части при числе — объявлением языка, где оно согласуется."""
    правило = ЧАСТИ.get(язык)
    return правило(b) if правило else None


# РЕЧЬ: приказ, вопрос, ответ доли, хвост остатка и отказ. «{a}» — сколько, «{b}» — на
# сколько, «{q}» — доля, «{r}» — остаток, «{Ч}» — имя части, согласованное с числом.
РЕЧЬ = {
    "ru": {"приказ": "раздели {a} на {b} поровну", "вопрос": "что получится?",
           "доля": "по {q}", "остаток": ", и {r} останется",
           "ноль": "на ноль делить нельзя: доли не выйдет ни одной"},
    "en": {"приказ": "divide {a} into {b} equal parts", "вопрос": "what do you get?",
           "доля": "{q} each", "остаток": ", and {r} left over",
           "ноль": "you cannot divide into zero parts: not one share comes out"},
    "de": {"приказ": "teile {a} in {b} gleiche Teile", "вопрос": "was kommt heraus?",
           "доля": "je {q}", "остаток": ", und {r} bleibt übrig",
           "ноль": "durch null kann man nicht teilen: nicht ein Anteil kommt heraus"},
    "fr": {"приказ": "partage {a} en {b} parts égales", "вопрос": "qu'est-ce qu'on obtient ?",
           "доля": "{q} chacune", "остаток": ", et il reste {r}",
           "ноль": "on ne peut pas partager en zéro parts : pas une part n'en sort"},
    "es": {"приказ": "reparte {a} en {b} partes iguales", "вопрос": "¿qué sale?",
           "доля": "{q} cada una", "остаток": ", y sobran {r}",
           "ноль": "no se puede repartir en cero partes: no sale ni una parte"},
    "it": {"приказ": "dividi {a} in {b} parti uguali", "вопрос": "che cosa viene fuori?",
           "доля": "{q} ciascuna", "остаток": ", e ne restano {r}",
           "ноль": "non si può dividere in zero parti: non ne viene fuori nemmeno una"},
    "pt": {"приказ": "divide {a} em {b} partes iguais", "вопрос": "o que sai?",
           "доля": "{q} cada uma", "остаток": ", e sobram {r}",
           "ноль": "não se pode dividir em zero partes: não sai nem uma parte"},
    "nl": {"приказ": "verdeel {a} in {b} gelijke delen", "вопрос": "wat komt eruit?",
           "доля": "elk {q}", "остаток": ", en er blijft {r} over",
           "ноль": "in nul delen kun je niet verdelen: er komt geen enkel deel uit"},
    "pl": {"приказ": "podziel {a} na {b} {Ч}", "вопрос": "co wychodzi?",
           "доля": "po {q}", "остаток": ", i zostaje {r}",
           "ноль": "przez zero dzielić nie można: nie wychodzi ani jedna część"},
}


def страница(язык, род, k, с_вопросом):
    """Одна страница равной доли; поверхность выбирается ЧЕРЕДОВАНИЕМ, а не родом."""
    р = РЕЧЬ[язык]
    if род == "на_ноль":
        a, b = НА_НОЛЬ[k % len(НА_НОЛЬ)], 0
        ответ = р["ноль"]
    else:
        ряд = РОВНЫЕ if род == "ровно" else С_ОСТАТКОМ
        a, b = ряд[k % len(ряд)]
        q, r = divmod(a, b)
        ответ = р["доля"].format(q=q) + (р["остаток"].format(r=r) if r else "")
    приказ = р["приказ"].format(a=a, b=b, Ч=часть(язык, b) or "")
    if с_вопросом:
        return f"{приказ}. {р['вопрос']} {ответ}."
    return f"{приказ}: {ответ}."


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            ряд = НА_НОЛЬ if род == "на_ноль" else (РОВНЫЕ if род == "ровно" else С_ОСТАТКОМ)
            for k in range(len(ряд)):
                # ЧЕРЕДОВАНИЕ ПО НОМЕРУ, А НЕ ПО РОДУ: обе поверхности встречаются в
                # каждом роде поровну, и ни одна не достаётся одному роду целиком.
                for с_вопросом in (k % 2 == 0, k % 2 == 1):
                    вон.setdefault(страница(язык, род, k, с_вопросом), (язык, род))
    return вон


ПОКАЗЫ = _показы()


