def страница(язык, род, k, с_вопросом):
    """Одна страница равной доли; поверхность выбирается ЧЕРЕДОВАНИЕМ, а не родом."""
    р = РЕЧЬ[язык]
    if род == "на_ноль":
        a, b = НА_НОЛЬ[k % len(НА_НОЛЬ)], 0
        ответ = р["ноль"]
    else:
        ряд = РОВНЫЕ if род == "ровно" else С_ОСТАТКОМ
        a, b = ряд[k % len(ряд)]
        q, r = divmod(a, b)
        ответ = р["доля"].format(q=q) + (р["остаток"].format(r=r) if r else "")
    приказ = р["приказ"].format(a=a, b=b, Ч=часть(язык, b) or "")
    if с_вопросом:
        return f"{приказ}. {р['вопрос']} {ответ}."
    return f"{приказ}: {ответ}."


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            ряд = НА_НОЛЬ if род == "на_ноль" else (РОВНЫЕ if род == "ровно" else С_ОСТАТКОМ)
            for k in range(len(ряд)):
                # ЧЕРЕДОВАНИЕ ПО НОМЕРУ, А НЕ ПО РОДУ: обе поверхности встречаются в
                # каждом роде поровну, и ни одна не достаётся одному роду целиком.
                for с_вопросом in (k % 2 == 0, k % 2 == 1):
                    вон.setdefault(страница(язык, род, k, с_вопросом), (язык, род))
    return вон


