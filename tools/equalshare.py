# СУД ПЕРЕСЧИТЫВАЕТ ЧАСТНОЕ И ОСТАТОК, А НЕ СВЕРЯЕТ СО СТРОИТЕЛЕМ.
def _образец(рамка, **дыры):
    куски, поз = [], 0
    for м in re.finditer(r"\{(\w+)\}", рамка):
        куски.append(re.escape(рамка[поз:м.start()]))
        куски.append(дыры.get(м.group(1),
                              r"(?P<Ч>[^:.?!]+)" if м.group(1) == "Ч" else r"(\d+)"))
        поз = м.end()
    куски.append(re.escape(рамка[поз:]))
    return "".join(куски)


def _по_частям(р, ответ, q, r):
    """(судимо, истинно) для ответа, НЕ РАВНОГО ожидаемому целиком.

    ЧУЖАЯ РАМКА КУПЛЕНА ЗДЕСЬ (16.09, прибор `scripts/house_reach.py`): приказ «раздели 12
    на 3 поровну» употребляют ТРИ дома, и каждый отвечает по-своему —

        equalshare  «по 4.»                     доля, ибо дом о РАСПРЕДЕЛЕНИИ;
        opforms     «что получится? 4.»         частное, ибо дом о ПОВЕЛЕНИИ;
        numberline  «по 4: 12 ÷ 3 = 4.»         доля и леджер, ибо дом о ЛИНИИ ЧИСЕЛ.

    Все три ЧЕСТНЫ. Суд равной доли называл ложью 1056 чужих честных страниц — не потому,
    что счёл их неверными, а потому, что они сложены не его словами.

        РАМКА, УПОТРЕБЛЁННАЯ ТРЕМЯ ДОМАМИ, НЕ ПРИНАДЛЕЖИТ НИ ОДНОМУ. Суд судит СЧЁТ, а не
        то, что фраза сложена не по-моему; ответ, чьей формы он не объявлял, — не его дело,
        и о нём молчат. МОЛЧАНИЕ ЕСТЬ ТРЕТИЙ ИСХОД, И ОНО НЕ СЛАБОСТЬ: строку, не судимую
        никем, останавливают ВОРОТА, а чужую страницу судит её собственный дом.

    ГРАНИЦА ПРОВЕДЕНА ТАМ, ГДЕ ДОМ ЕЁ САМ ОБЪЯВИЛ В ЗАГОЛОВКЕ: «ответ у него
    РАСПРЕДЕЛИТЕЛЬНЫЙ („по 7“), а не числовой». Отличие было НАЗВАНО и не проведено в суде —
    закон, живущий в докстринге и не живущий в коде, есть закон только на вид.

    И ГРАНИЦА НЕ ЕСТЬ СЛЕПОТА: доля, названная СВОЕЙ формой и неверная числом, остаётся
    ложью — даже когда за ней идёт чужая пристройка. Молчат о ЧУЖОМ, а не о своём.
    """
    мд = re.match("^" + _образец(р["доля"]), ответ)
    if not мд:
        return False, True                      # ответ не распределительный — чужая рамка
    if int(мд.group(1)) != q:
        return True, False                      # доля названа МОЕЙ формой и неверна
    хвост = ответ[мд.end():]
    if not хвост:
        # ДОМ, МОЛЧАЩИЙ ОБ ОСТАТКЕ, УЧИТ, ЧТО ЕГО НЕ БЫВАЕТ (объявлено при рождении дома).
        return True, not r
    мо = re.match("^" + _образец(р["остаток"]), хвост)
    if мо:
        # ХВОСТ ЗА ОСТАТКОМ — ТО ЖЕ ЧУЖОЕ, ЧТО И ХВОСТ ЗА ДОЛЕЙ (16.09, прибор
        # `scripts/prefix_traps.py`). Прежде он звался ложью, и суд тем самым был
        # ЛОВУШКОЙ, ВЗВЕДЁННОЙ НА БУДУЩЕЕ: он молчал бы ровно до дня, когда сосед
        # напишет строку, начинающуюся моим приказом, — и сломал бы не себя, а соседа.
        if хвост[мо.end():]:
            return False, True
        return True, bool(r) and int(мо.group(1)) == r
    return False, True                          # доля верна, дальше — пристройка чужого дома


def судить(строка):
    """(судимо, истинно) — приказ разобран, частное и остаток пересчитаны."""
    for язык in ЯЗЫКИ:
        р = РЕЧЬ[язык]
        м = re.match("^" + _образец(р["приказ"]), строка)
        if not м:
            continue
        a, b = int(м.group(1)), int(м.group(2))
        # ФОРМА ЧАСТИ ПРОВЕРЯЕТСЯ ЧИСЛОМ: «na 5 równe części» есть ложь грамматики, и суд
        # обязан её видеть так же ясно, как ложь арифметики.
        if "{Ч}" in р["приказ"]:
            if м.groupdict().get("Ч") != часть(язык, b):
                return True, False
        хвост = строка[м.end():]
        # ПОВЕРХНОСТЬ ОБЪЯВЛЕНА, И СУД ЧИТАЕТ ОБЕ: «. вопрос ответ.» либо «: ответ.»
        if хвост.startswith(". " + р["вопрос"] + " "):
            ответ = хвост[len(". " + р["вопрос"] + " "):]
        elif хвост.startswith(": "):
            ответ = хвост[2:]
        else:
            return False, True                  # ход речи не мой — см. закон при `_по_частям`
        if not ответ.endswith("."):
            return False, True
        ответ = ответ[:-1]
        if b == 0:
            # ДЕЛЕНИЕ НА НОЛЬ ЕСТЬ НЕВОЗМОЖНОСТЬ, И ВСЯКИЙ ОТВЕТ, КРОМЕ ОТКАЗА, ЛОЖЕН, ЧЬЕЙ
            # БЫ ПОВЕРХНОСТИ НИ БЫЛ: здесь дом судит СУЩЕСТВО, а не свою речь, и потому
            # молчания тут нет — молчание было бы согласием с невозможным.
            #
            # ОДНО ИСКЛЮЧЕНИЕ, И ОНО НЕ О СУЩЕСТВЕ, А О ГРАНИЦЕ СТРОКИ (16.09, прибор
            # `scripts/prefix_traps.py`): отказ, СКАЗАННЫЙ ЦЕЛИКОМ, а за ним ещё текст, —
            # это не «неверный ответ», а ДВЕ СТРАНИЦЫ, и вторая мне не принадлежит.
            # Судить их как одну значило бы звать ложью соседа за то, что он начал с меня.
            if ответ.startswith(р["ноль"]) and ответ != р["ноль"]:
                return False, True
            return True, ответ == р["ноль"]
        q, r = divmod(a, b)
        ждём = р["доля"].format(q=q) + (р["остаток"].format(r=r) if r else "")
        if ответ == ждём:
            return True, True
        return _по_частям(р, ответ, q, r)
    return False, True


