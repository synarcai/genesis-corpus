# СУД ПЕРЕСЧИТЫВАЕТ ЧАСТНОЕ И ОСТАТОК, А НЕ СВЕРЯЕТ СО СТРОИТЕЛЕМ.
def _образец(рамка, **дыры):
    куски, поз = [], 0
    for м in re.finditer(r"\{(\w+)\}", рамка):
        куски.append(re.escape(рамка[поз:м.start()]))
        куски.append(дыры.get(м.group(1),
                              r"(?P<Ч>[^:.?!]+)" if м.group(1) == "Ч" else r"(\d+)"))
        поз = м.end()
    куски.append(re.escape(рамка[поз:]))
    return "".join(куски)


def судить(строка):
    """(судимо, истинно) — приказ разобран, частное и остаток пересчитаны."""
    for язык in ЯЗЫКИ:
        р = РЕЧЬ[язык]
        м = re.match("^" + _образец(р["приказ"]), строка)
        if not м:
            continue
        a, b = int(м.group(1)), int(м.group(2))
        # ФОРМА ЧАСТИ ПРОВЕРЯЕТСЯ ЧИСЛОМ: «na 5 równe części» есть ложь грамматики, и суд
        # обязан её видеть так же ясно, как ложь арифметики.
        if "{Ч}" in р["приказ"]:
            if м.groupdict().get("Ч") != часть(язык, b):
                return True, False
        хвост = строка[м.end():]
        # ПОВЕРХНОСТЬ ОБЪЯВЛЕНА, И СУД ЧИТАЕТ ОБЕ: «. вопрос ответ.» либо «: ответ.»
        if хвост.startswith(". " + р["вопрос"] + " "):
            ответ = хвост[len(". " + р["вопрос"] + " "):]
        elif хвост.startswith(": "):
            ответ = хвост[2:]
        else:
            return True, False
        if not ответ.endswith("."):
            return True, False
        ответ = ответ[:-1]
        if b == 0:
            return True, ответ == р["ноль"]
        q, r = divmod(a, b)
        ждём = р["доля"].format(q=q) + (р["остаток"].format(r=r) if r else "")
        return True, ответ == ждём
    return False, True


# ПОДСАДКИ ОБЪЯВЛЕНЫ ЗДЕСЬ, И СУД БЕРЁТ ИХ ОТСЮДА ЖЕ (14.09). Дом скобок держал свой
# список, суд — свой, похожий; рамка вопроса в доме переменилась, а в суде осталась
# прежней, и четыре подсадки из семи перестали попадать в рамку — то есть перестали быть
# судимыми вовсе, а прибор доложил, что не поймал их. ДВА ПОХОЖИХ СПИСКА РАСХОДЯТСЯ
# МОЛЧА; один список расходиться не с чем.
ПОДСАДКИ = ("раздели 14 на 2 поровну. что получится? по 6.",
            "раздели 14 на 3 поровну. что получится? по 4.",
            "раздели 14 на 3 поровну: по 4, и 3 останется.",
            "раздели 14 на 0 поровну: по 0.",
            "divide 14 into 2 equal parts: 6 each.",
            "podziel 15 na 5 równe części: po 3.")


def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    assert set(РЕЧЬ) == set(ЯЗЫКИ), "речь объявлена не на всех языках"
    for язык in ЯЗЫКИ:
        for ключ in ("приказ", "вопрос", "доля", "остаток", "ноль"):
            assert ключ in РЕЧЬ[язык], f"{язык}: нет речи «{ключ}»"
    # ВСЯКАЯ СТРАНИЦА СУДИМА И ИСТИННА, И ЭТО ПРОВЕРЯЕТСЯ ЗДЕСЬ, А НЕ НА СЛОВО.
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    # ПРОБА НА ЗАВЕДОМО ЛОЖНОМ: суд обязан ловить порчу доли, остатка и нуля.
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    пустые = set(РОДЫ) - роды
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
