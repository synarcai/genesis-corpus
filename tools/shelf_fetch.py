#!/usr/bin/env python3
"""КНИГА С ПОЛКИ БЕРЁТСЯ ПРИБОРОМ, А НЕ РУКОЙ.

Полка объявлена договором `declarations/SHELF.md`: внешние книги брать
можно, если происхождение чисто (издано до рубежа 2022) и текст плотен.
Но «взял из интернета» не есть происхождение, и книга, положенная в
корпус рукой, не сверяема ни с чем: никто не скажет, ЧТО именно взято и
откуда. Здесь берущий назван прибором — заглавие страницы Викитеки, — и
всякий волен повторить обход и сличить.

ЧИСТКА СТРУКТУРНАЯ, А НЕ СЛОВАРНАЯ. Выкидывается ПОДДЕРЕВО служебного
узла целиком (рамка издания, навигация, сноски, указатели скана), а не
строки, ПОХОЖИЕ на служебные. Список подозрительных слов стареет рукой;
разметка издания объявлена самой Викитекой классами узлов, и её довольно.

ОТЛОЖЕННОЕ ОТКЛАДЫВАЕТСЯ ПРИ РОЖДЕНИИ, А НЕ ПЕРЕД ЗАМЕРОМ. Последняя
двадцатая часть каждой книги уходит в отдельный файл СРАЗУ, до всякого
чтения: мера «до и после главы», взятая по уже прочитанному, всегда
хороша и потому ничего не говорит.

СТРОКА ПОЛКИ НЕ ДЛИННЕЕ САМОЙ ДЛИННОЙ СТРОКИ СВОИХ СВОДОВ. Замер по
222 215 строкам семи прозаических сводов корпуса: медиана 54 знака,
сотая доля длиннее 484, самая длинная — 5263. Страница Викитеки иногда
несёт статью ОДНИМ абзацем в 59 232 знака; такой абзац режется по концам
предложений на куски не длиннее того, что корпус уже держит. Меньше не
режем: чужое членение на абзацы есть свидетельство об издании, и портить
его без нужды значило бы терять его.
"""

import html.parser
import json
import math
import pathlib
import re
import sys
import time
import urllib.parse
import urllib.request

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
АДРЕС = "https://ru.wikisource.org/w/api.php"
# Викимедиа требует называющего себя просителя; без него API молча
# отдаёт пустоту — что и вышло на первом обходе категорий.
ЛИЦО = ("genesis-corpus-shelf/1.0 (public-domain shelf for a research "
        "corpus; contact: taaliman@protonmail.com)")
ПАУЗА = 0.6

# ЗАМЕР 02.09 по своим сводам прозы: самая длинная строка — 5263 знака.
ПРЕДЕЛ_СТРОКИ = 5263
# ОТЛОЖЕННОЕ — последняя двадцатая часть, как объявлено договором.
ДОЛЯ_ОТЛОЖЕННОГО = 0.05

СЛУЖЕБНЫЕ_КЛЕЙМА = (
    "ws-noexport", "headertemplate", "navbox", "reflist", "mw-references",
    "ws-summary", "infobox", "ambox", "pagenum", "noprint",
    "mw-editsection", "catlinks", "printfooter", "reference",
    "prp-pagequality", "mw-cite-backlink", "mw-indicators", "sub_nav",
    "ws-header", "ws-footer", "sisterprojects", "interproject",
    # ФОРМУЛА ВИКИТЕКИ ОТДАЁТ РАЗОМ ДВЕ ЗАПИСИ, И ОБЕ НЕЧИТАЕМЫ: скрытую
    # MathML («1 2 m v 2») и подпись TeX («{\displaystyle \textstyle
    # ={\frac {1}{2}}mv^{2}}»). Тридцать восемь строк статьи о механике
    # были ими засеяны. Запись формул у корпуса своя (миры LaTeX и
    # языка формул), и чужая полуразобранная здесь не нужна.
    "mwe-math",
)
ВЫКИНУТЬ_ТЕГ = {"table", "style", "script", "figure", "figcaption",
                "noscript", "audio", "video", "sup", "sub", "math"}
# ВЫКИНУТОЕ ВНУТРИ СТРОКИ НЕ РАЗРЫВАЕТ АБЗАЦА. Знак сноски и формула
# стоят ПОСРЕДИ предложения; закрывая на них абзац, разбор резал
# предложение надвое — и вторая половина начиналась с точки: «. Шеллинг
# застал борьбу разных взглядов…». Выкидывается содержимое, а не абзац,
# и различает это не список выкинутых, а СТРОЧНОСТЬ узла.
СТРОЧНЫЕ = {"span", "a", "sup", "sub", "math", "i", "b", "em", "strong",
            "small", "abbr", "cite", "code", "q", "u", "s", "var",
            "big", "tt", "font", "time", "ruby", "rt", "bdi", "mark"}
ПУСТЫЕ = {"br", "img", "hr", "meta", "link", "input", "source", "wbr",
          "col", "area", "base", "embed", "param", "track"}
БЛОЧНЫЕ = {"p", "h1", "h2", "h3", "h4", "h5", "h6", "li", "dd", "dt",
           "blockquote", "div", "center", "poem", "pre"}
ЗАГОЛОВКИ = {"h1", "h2", "h3", "h4", "h5", "h6"}

КОНЕЦ_ПРЕДЛОЖЕНИЯ = re.compile(r'(?<=[.!?…])\s+(?=[«"(\[]?[А-ЯЁA-Z0-9])')
ТОМ_И_ГОД = re.compile(r"т\.\s*([IVXLCa]+)\s*\((\d{4})\)")

# ХВОСТ ИЗДАНИЯ ОТРЕЗАЕТСЯ ПО СВОЕЙ РУБРИКЕ, И ПРИЧИНА ТОМУ ПРАВОВАЯ, А
# НЕ ВКУСОВАЯ. Комментарий и указатель имён академического издания суть
# труд ИЗДАТЕЛЯ, а не автора: права на текст 1846 года истекли, права на
# примечания 1954 года — нет. Договор полки велит спорное не брать.
# Рубрика узнаётся строкой целиком и заглавными: «КОММЕНТАРИИ»,
# «УКАЗАТЕЛЬ ИМЁН». Авторские «ПРИМЕЧАНИЯ» не трогаем — они того же
# возраста, что и текст.
ХВОСТ_ИЗДАНИЯ = re.compile(
    r"^(?:КОММЕНТАРИИ|УКАЗАТЕЛЬ(?:\s+\S+)*|"
    r"ПРИНЯТЫЕ\s+СОКРАЩЕНИЯ)[.:]?$")


class Разбор(html.parser.HTMLParser):
    """Абзацы и заголовки страницы; служебные поддеревья не читаются."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.куски = []
        self.текущий = []
        self.глубина = 0
        self.вон_с = None
        self.заголовок = False
        self.формул = 0

    def _служебный(self, свойства):
        д = dict(свойства)
        клеймо = (д.get("class", "") + " " + д.get("id", "")).lower()
        return any(к in клеймо for к in СЛУЖЕБНЫЕ_КЛЕЙМА)

    def _формула(self, тег, свойства):
        """Узел формулы — сам `math` или обёртка Викитеки вокруг него."""
        клеймо = dict(свойства).get("class", "").lower()
        return тег == "math" or "mwe-math" in клеймо

    def handle_starttag(self, тег, свойства):
        if тег in ПУСТЫЕ:
            if self.вон_с is None and тег == "br":
                self._закрыть()
            return
        self.глубина += 1
        if self.вон_с is not None:
            return
        if тег in ВЫКИНУТЬ_ТЕГ or self._служебный(свойства):
            if тег not in СТРОЧНЫЕ:
                self._закрыть()
            if self._формула(тег, свойства):
                self.формул += 1
            self.вон_с = self.глубина
            return
        if тег in БЛОЧНЫЕ:
            self._закрыть()
            self.заголовок = тег in ЗАГОЛОВКИ

    def handle_endtag(self, тег):
        if тег in ПУСТЫЕ:
            return
        if self.вон_с is not None:
            # ГЛУБИНА СЧИТАЕТСЯ ПО ВСЕМ ТЕГАМ, А НЕ ПО ВЫКИНУТЫМ. Первая
            # редакция выпускала разбор из выкинутого поддерева на
            # закрытии ЛЮБОГО вложенного узла — и вся навигация Викитеки
            # просачивалась в текст.
            if self.глубина <= self.вон_с:
                self.вон_с = None
            self.глубина = max(0, self.глубина - 1)
            return
        if тег in БЛОЧНЫЕ:
            self._закрыть()
        self.глубина = max(0, self.глубина - 1)

    def handle_data(self, данные):
        if self.вон_с is None:
            self.текущий.append(данные)

    def _закрыть(self):
        текст = re.sub(r"\s+", " ", "".join(self.текущий)).strip()
        self.текущий = []
        if текст:
            self.куски.append((текст, self.заголовок))
        self.заголовок = False


def спросить(**поля):
    """Ответ API Викитеки, с паузой и повтором при обрыве."""
    поля.setdefault("format", "json")
    поля.setdefault("formatversion", "2")
    запрос = urllib.request.Request(
        АДРЕС + "?" + urllib.parse.urlencode(поля),
        headers={"User-Agent": ЛИЦО})
    for попытка in range(4):
        try:
            with urllib.request.urlopen(запрос, timeout=90) as ответ:
                тело = json.loads(ответ.read().decode("utf-8"))
            time.sleep(ПАУЗА)
            return тело
        except Exception:
            if попытка == 3:
                raise
            time.sleep(2 * (попытка + 1))
    return None


def страница(титул):
    """(куски, издание, формул) — тело, выходные данные и счёт формул."""
    д = спросить(action="parse", page=титул, prop="text")
    if "parse" not in д:
        raise SystemExit(f"ПОЛКА ОТКАЗ: страницы «{титул}» нет")
    сырое = д["parse"]["text"]
    издание = ТОМ_И_ГОД.search(сырое)
    разбор = Разбор()
    разбор.feed(сырое)
    разбор._закрыть()
    куски = разбор.куски
    # ЗАГОЛОВОК БЕЗ РАЗДЕЛА ЕСТЬ РУБРИКА ВЫКИНУТОГО СЛУЖЕБНОГО
    # («Примечания» над списком сносок, которого больше нет).
    while куски and куски[-1][1]:
        куски.pop()
    for где, (текст, _заг) in enumerate(куски):
        if ХВОСТ_ИЗДАНИЯ.match(текст.strip()):
            куски = куски[:где]
            break
    return (куски, (издание.group(2) if издание else None),
            разбор.формул)


def выходные_данные(титул):
    """{АВТОР, ДАТАПУБЛИКАЦИИ, ИСТОЧНИК} из шаблона «Отексте»."""
    д = спросить(action="query", prop="revisions", rvprop="content",
                 rvslots="main", titles=титул)
    стр = д.get("query", {}).get("pages", [{}])[0]
    if "revisions" not in стр:
        return {}
    вики = стр["revisions"][0]["slots"]["main"]["content"]
    вон = {}
    for поле in ("АВТОР", "ДАТАПУБЛИКАЦИИ", "ИСТОЧНИК"):
        найдено = re.search(rf"\|\s*{поле}\s*=\s*(.*)", вики)
        if найдено:
            вон[поле] = найдено.group(1).strip()
    return вон


def строки(куски):
    """Абзацы и заголовки в строй прозаических сводов корпуса."""
    вон = []
    for текст, заголовок in куски:
        if заголовок:
            вон.append("")
        for кусок in порезать(текст):
            вон.append(кусок)
        вон.append("")
    return вон


def порезать(абзац):
    """Абзац длиннее предела — по концам предложений, иначе как есть."""
    if len(абзац) <= ПРЕДЕЛ_СТРОКИ:
        return [абзац]
    вон, свой = [], ""
    for предложение in КОНЕЦ_ПРЕДЛОЖЕНИЯ.split(абзац):
        если = (свой + " " + предложение).strip()
        if свой and len(если) > ПРЕДЕЛ_СТРОКИ:
            вон.append(свой)
            свой = предложение
        else:
            свой = если
    if свой:
        вон.append(свой)
    return вон


def отложить(строки_мира):
    """(тело, отложенное) — последняя двадцатая часть по границе абзаца.

    ДОЛЯ СЧИТАЕТСЯ ЗНАКАМИ, А НЕ СТРОКАМИ. Первая редакция резала по
    счёту строк — и там, где книга набрана длинными абзацами, пять
    процентов строк дали десятую часть текста, а где последние абзацы
    коротки, — три десятых процента. Отложенное меряется тем же, чем
    меряется книга.
    """
    знаков = sum(len(с) for с in строки_мира)
    if not знаков:
        return строки_мира, []
    надо = math.ceil(знаков * ДОЛЯ_ОТЛОЖЕННОГО)
    набрано, рубеж = 0, len(строки_мира)
    while рубеж > 0 and набрано < надо:
        рубеж -= 1
        набрано += len(строки_мира[рубеж])
    # РЕЖЕМ ПО ГРАНИЦЕ АБЗАЦА: половина абзаца не есть текст.
    while рубеж > 0 and строки_мира[рубеж - 1].strip():
        рубеж -= 1
    if рубеж <= 0:
        return строки_мира, []
    return строки_мира[:рубеж], строки_мира[рубеж:]


def записать(путь, строки_мира):
    тело = "\n".join(строки_мира).strip("\n")
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(тело + "\n", encoding="utf-8")
    return len(тело.encode("utf-8")), sum(1 for с in строки_мира if с.strip())


def собрать(имя, титулы):
    """Мир полки из одной или нескольких страниц Викитеки."""
    все, года, откуда, формул = [], [], [], 0
    for титул in титулы:
        куски, год, своих_формул = страница(титул)
        формул += своих_формул
        # ЗАГЛАВИЕ СТАТЬИ СТАНОВИТСЯ ЗАГОЛОВКОМ РАЗДЕЛА, когда мир
        # собран из нескольких статей одного издания: иначе читающий не
        # знает, где кончилась одна статья и началась другая.
        if len(титулы) > 1:
            куски = [(титул.split("/")[-1], True)] + куски
        все += куски
        откуда.append(титул)
        if год:
            года.append(int(год))
    тело, отложенное = отложить(строки(все))
    свой = записать(КОРЕНЬ / "shelf" / "ru" / f"{имя}.txt", тело)
    ещё = записать(КОРЕНЬ / "shelf" / "ru" / f"{имя}.holdout.txt",
                   отложенное) if отложенное else (0, 0)
    return {"имя": имя, "страниц": len(титулы), "год": max(года) if года
            else None, "байт": свой[0], "строк": свой[1],
            "отложено_строк": ещё[1], "откуда": откуда,
            "формул_выкинуто": формул}


def main():
    """Ввод: строки «имя<TAB>заглавие[;заглавие…]»."""
    для_отчёта = []
    for строка in sys.stdin:
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        имя, титулы = строка.split("\t", 1)
        итог = собрать(имя, [т.strip() for т in титулы.split(";")])
        для_отчёта.append(итог)
        print(f"{итог['имя']:<22} {итог['байт']:>8} байт "
              f"{итог['строк']:>6} строк, отложено "
              f"{итог['отложено_строк']:>5}, издание {итог['год']}, "
              f"формул выкинуто {итог['формул_выкинуто']}")
    return 0 if для_отчёта else 2


if __name__ == "__main__":
    sys.exit(main())
