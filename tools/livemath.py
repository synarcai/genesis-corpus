#!/usr/bin/env python3
"""[ЖИВЫЕ ЗАДАЧИ] — дом живой задачи: условие GSM8K рядом с программой его решения, в девяти числах.

Закон — в `tools/livemath_law.py` (повод, программа, строй варианта, суд). Здесь — ДОМ: он берёт
всякую задачу источника, какую закон разобрал, и выводит из неё род: саму задачу и восемь её
вариантов, хранящих строй. Род, не добравший девяти показов (закон массы соседа,
`form_census.LAW2`), в дом не идёт вовсе: показ, который не купится, есть вес без знания.

ЧИСЛА ВАРИАНТА БЕРУТСЯ ЖРЕБИЕМ С ЗЕРНОМ, А НЕ ЧАСАМИ: зерно — `zlib.crc32` номера задачи и
попытки, одно во всяком процессе (шрам подсадки словом, 06.09: `hash()` солится на процесс).
Всякий вход берёт значение из отрезка от половины до удвоенного своего, шагом своей последней
цифры («16.50» — сотыми); годность решает закон.

ПОИСК ВАРИАНТОВ ДОРОГ, И ОН ЗАПИСАН НА ПОЛКУ (`datasets/GENESIS-FULL.livemath.tsv`), как покупки
двери лиц: дом при всяком импорте лишь РИСУЕТ строки с полки и проверяет каждую законом, а ищет —
только сборка полки. Двадцать с лишним приборов свода импортируют всякий дом; поиск при импорте
стоил бы им по две с половиной минуты каждому. Суд строки полки не читает вовсе — он пересчитывает.

    python3 tools/livemath.py            # свежесть полки против поиска и самопроверка подсадками
    python3 tools/livemath.py --собрать  # поиск вариантов и запись полки
"""
# ПУСТОЙ-ОБХОД: --источник no-such-source
import pathlib
import sys
import zlib
from fractions import Fraction

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import livemath_law as З  # noqa: E402 — закон живой задачи: одна дверь

ПОПЫТОК = 400
ПОЛКА = pathlib.Path(__file__).resolve().parents[1] / "datasets" / "GENESIS-FULL.livemath.tsv"


def масса():
    """Закон массы берётся у соседа (`form_census.LAW2`), а не заводится свой. Ввоз — лишь здесь:
    кузница рисует строки с полки и закона массы не спрашивает, а двор воспроизводимости несёт
    дома и кузницы, но не приборы `scripts/`."""
    путь = str(pathlib.Path(__file__).resolve().parents[1] / "scripts")
    if путь not in sys.path:
        sys.path.insert(0, путь)
    import form_census
    return form_census.LAW2


def варианты(п, нужно=None, попыток=ПОПЫТОК):
    """Годные варианты задачи: [(значения, итоги)] — не более `нужно`, без повторов и без исходной."""
    нужно = масса() - 1 if нужно is None else нужно
    знаков = {образец[0]: образец[3] for образец in п.числа}
    вон, видено = [], {tuple(п.входы)}
    for t in range(попыток):
        значения = {}
        for j, в in enumerate(п.входы):
            шаг = Fraction(1, 10 ** знаков.get(в, 0))
            низ, верх = в / 2, в * 2
            ступеней = max(int((верх - низ) / шаг), 1)
            жребий = zlib.crc32(f"{п.номер}:{t}:{j}".encode("utf-8"))
            значение = низ + шаг * (жребий % (ступеней + 1))
            значения[в] = (значение // шаг) * шаг
        ключ = tuple(значения[в] for в in п.входы)
        if ключ in видено:
            continue
        итоги = п.вычислить(значения)
        if итоги is None or not З.годен(п, значения, итоги):
            continue
        видено.add(ключ)
        вон.append((значения, итоги))
        if len(вон) >= нужно:
            break
    return вон


def найти():
    """Поиск: номер задачи → её годные варианты, лишь у задач, добравших массу."""
    вон = {}
    годные, _ = З.программы()
    for п in годные:
        вв = варианты(п)
        if len(вв) >= масса() - 1:
            вон[п.номер] = [tuple(з[в] for в in п.входы) for з, _ in вв]
    return вон


def строки_полки(найдено):
    вон = ["# ЖИВЫЕ ЗАДАЧИ — числа вариантов, найденные поиском `python3 tools/livemath.py --собрать`.",
           "# Столбцы: номер задачи источника (tools/seeds/gsm8k/train.jsonl), номер варианта,",
           "# значения входов в порядке возрастания исходных, через «;». Вариант 0 — сама задача — не пишется."]
    for номер in sorted(найдено):
        for k, значения in enumerate(найдено[номер], start=1):
            вон.append(f"{номер}\t{k}\t{';'.join(З.число_выкладки(v) for v in значения)}")
    return вон


def полка():
    """Полка: номер → [значения вариантов]; полки нет — пусто."""
    вон = {}
    try:
        строки = ПОЛКА.read_text(encoding="utf-8").splitlines()
    except OSError:
        return вон
    for строка in строки:
        if строка.startswith("#") or not строка.strip():
            continue
        номер, _, значения = строка.split("\t")
        вон.setdefault(int(номер), []).append(tuple(Fraction(v) for v in значения.split(";")))
    return вон


ЯЗЫК = "en"


def род(п):
    """Род страницы — ФОРМА ПРОГРАММЫ её задачи («живая: × · +»): рынку и читателю покупать
    род, а не задачу; девять показов всякой задачи несут род не беднее массы."""
    return "живая: " + З.форма_программы(п)


def _показы():
    """(ПОКАЗЫ, ПРОИСХОЖДЕНИЕ): строка → (язык, род) по обычаю домов свода (сайдкары родов и
    языков читают эту пару); строка → (номер задачи источника, номер варианта; 0 — сама задача).

    Рисуются с полки; вариант, какого закон не признаёт годным (полка устарела), не рисуется —
    и суд свежести назовёт это расхождением.
    """
    вон, откуда = {}, {}
    годные, _ = З.программы()
    по_номеру = {п.номер: п for п in годные}
    for номер, наборы in sorted(полка().items()):
        п = по_номеру.get(номер)
        if п is None:
            continue
        исходные = {в: в for в in п.входы}
        строки = [З.отрисовать(п, исходные, п.итоги)]
        for набор in наборы:
            значения = dict(zip(п.входы, набор))
            итоги = п.вычислить(значения)
            if итоги is not None and З.годен(п, значения, итоги):
                строки.append(З.отрисовать(п, значения, итоги))
        for k, с in enumerate(строки):
            if с not in вон:
                вон[с] = (ЯЗЫК, род(п))
                откуда[с] = (номер, k)
    return вон, откуда


ПОКАЗЫ, ПРОИСХОЖДЕНИЕ = _показы()
# Роды дома — формы программ его задач; объявление выводится из страниц, а не пишется рукой.
РОДЫ = tuple(sorted({род_ for _, род_ in ПОКАЗЫ.values()}))


def судить(строка):
    return З.судить(строка)


def _самопроверка():
    """Всякая строка дома истинна; порча числа, слова и выкладки — ложь."""
    беды = []
    строки = list(ПОКАЗЫ)
    if not строки:
        return ["дом пуст — источника нет или закон не разобрал ни одной задачи"]
    for с in строки[::max(len(строки) // 300, 1)]:
        судимо, верно = судить(с)
        if not (судимо and верно):
            беды.append(f"своя строка не истинна: {с[:100]}")
    for с in строки[:60]:
        вопрос, хвост = с.rsplit(": ", 1)
        порченые = []
        # число условия
        чс = З.числа(вопрос)
        if чс:
            v, начало, конец = чс[0][:3]
            порченые.append(вопрос[:начало] + str(int(v) + 1 if v.denominator == 1 else v + 1) + вопрос[конец:] + ": " + хвост)
        # слово условия
        слова = вопрос.split(" ")
        for i, слово in enumerate(слова):
            if слово.isalpha() and len(слово) > 3:
                порченые.append(" ".join(слова[:i] + [слово[:-1]] + слова[i + 1:]) + ": " + хвост)
                break
        # итог выкладки
        левая, итог = хвост.rsplit(" = ", 1)
        порченые.append(вопрос + ": " + левая + " = " + str(int(итог.rstrip(".").split(".")[0]) + 1) + ".")
        for п in порченые:
            судимо, верно = судить(п)
            if not судимо or верно:
                беды.append(f"порча не поймана: {п[:110]}")
    return беды


def main():
    if "--источник" in sys.argv:
        источник = pathlib.Path(sys.argv[sys.argv.index("--источник") + 1])
        if not источник.is_file():
            print(f"ЖИВЫЕ ЗАДАЧИ ОТКАЗ: источника «{источник}» нет — мерить нечего")
            return 2
    if "--собрать" in sys.argv:
        найдено = найти()
        ПОЛКА.write_text("\n".join(строки_полки(найдено)) + "\n", encoding="utf-8")
        print(f"ЖИВЫЕ ЗАДАЧИ: полка собрана — задач {len(найдено)}, вариантов "
              f"{sum(len(в) for в in найдено.values())} → {ПОЛКА.name}")
        return 0
    найдено = найти()
    было = полка()
    расхождений = len(set(найдено) ^ set(было)) + sum(1 for н in set(найдено) & set(было) if найдено[н] != было[н])
    годные, причины = З.программы()
    задач = len({номер for номер, _ in ПРОИСХОЖДЕНИЕ.values()})
    print(f"ЖИВЫЕ ЗАДАЧИ: источник — задач разобрано {len(годные)}; причины отказа: "
          + ", ".join(f"{к} {н}" for к, н in sorted(причины.items(), key=lambda x: -x[1]) if к != "годна"))
    print(f"  задач с массой {масса()}: {задач}; родов (форм программ) {len(РОДЫ)}; строк {len(ПОКАЗЫ)}")
    беды = _самопроверка()
    if расхождений:
        беды.append(f"полка разошлась с поиском в {расхождений} задачах — пересобрать `--собрать`")
    for б in беды[:10]:
        print("  БЕДА:", б)
    print(f"ЖИВЫЕ ЗАДАЧИ {'PASS' if not беды else 'FAIL'}: бед {len(беды)}; полка против поиска — "
          f"расхождений {расхождений} (рубеж 0); строк {len(ПОКАЗЫ)}")
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())
