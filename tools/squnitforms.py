    # ТАБЛИЦА ПАР ОБЯЗАНА БЫТЬ ТЕМ, ЧЕМ НАЗВАНА.
    for б, м, k in ПАРЫ:
        if k < 10:
            беды.append(f"множитель мал, ошибка не видна: {(б, м, k)}")
        for язык in ЯЗЫКИ:
            if б not in ИМЕНА[язык] or м not in ИМЕНА[язык]:
                беды.append(f"единица без имени [{язык}]: {(б, м)}")
            if б not in _ЗНАК[язык] or м not in _ЗНАК[язык]:
                беды.append(f"единица без знака [{язык}]: {(б, м)}")
    # ОБЕ СТОРОНЫ ЛОВУШКИ ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ.
    for язык in ЯЗЫКИ:
        if not (по_роду.get((язык, "множитель длины ложен"))
                and по_роду.get((язык, "множитель длины верен"))):
            беды.append(f"показана лишь одна сторона ловушки [{язык}]")
    # СТЕПЕНИ ОБЯЗАНЫ РАЗЛИЧАТЬСЯ ЗНАКОМ, ИНАЧЕ ЛОВУШКА НЕ ВИДНА ВОВСЕ.
    if _е("м", "ru") == _е("м", "ru", 2) or _е("м", "ru", 2) == _е("м", "ru", 3):
        беды.append("знаки степеней совпали — площадь неотличима от длины")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    кв = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "площадь в квадрате")
    порча = кв.replace("КВАДРАТЕ", "КВАДРАТ", 1)
    if порча == кв:
        беды.append("порча не состоялась: нет слова «КВАДРАТЕ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(кв + " " + кв)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"КВАДРАТНЫЕ ЕДИНИЦЫ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
