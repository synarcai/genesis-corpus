"""ДОМ ДОЛИ — «две трети от 12» ходом, а не ответом.

Доля берётся ДВУМЯ ходами: делением на знаменатель и умножением на числитель, — и оба
хода стоя́т на странице. Имя `shareforms` уже занято ИНЫМ домом, домом ИМЁН доли в восьми
языках; спрошено у двора прежде записи и взято свободное.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

ТАБЛИЦА ПЕРЕИМЕНОВАНА В `СОСТАВ`: имя `РОДЫ` корпус держит за РЯДОМ ИМЁН, и указатель
отвергает дом, положивший под этим именем таблицу.
"""
