# РОД ОБЪЯВЛЯЕТ СЕБЯ ОДНОЙ СТРОКОЙ, И ОБХОД ОДИН НА ВСЕ РОДЫ.
# Прибавить род — значит назвать его здесь, а не написать новый обход.
СОСТАВ = (
    ("name-and-record", имя_и_запись),
    ("share-of", от_величины),
    ("asked", вопросом),
    ("as-many", сравнением),
    ("mixed", смешанным),
    ("whole", целым),
    ("обратно", обратно),
)


РОДЫ = tuple(с[0] for с in СОСТАВ)

ЗАЧЕМ_РОДА = {и: f"род «{и}», объявленный построением" for и in РОДЫ}


def группы(шаг):
    """[[страница]] — ровно та сборка, какою кормится кузница."""
    return [сказать(шаг) for _имя, сказать in СОСТАВ]


def перебор(шаг):
    """[(страница, род)] — род взят У СТРОИТЕЛЯ, до всякой пересборки."""
    вон = []
    for имя, сказать in СОСТАВ:
        for с in сказать(шаг):
            вон.append((с, имя))
    return вон


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            вон.setdefault(с, род)
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Ряд имён — имена; сборка — страница в страницу с перебором."""
    assert all(isinstance(р, str) for р in РОДЫ), "РОДЫ обязаны быть рядом ИМЁН"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    из_перебора = sorted(с for с, _р in перебор(0))
    из_групп = sorted(с for г in группы(0) for с in г)
    assert из_перебора == из_групп, (
        f"пересборка потеряла или выдумала страницы: перебор {len(из_перебора)}, "
        f"группы {len(из_групп)}")
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка()
