#!/usr/bin/env python3
"""СБОР ДВУЯЗЫЧНОГО ДОМА: язык берётся У СТРОИТЕЛЯ, а не гадается по письму (15.09).

Пять домов дознания (`inqdefr`, `inqesit`, `inqpltr`, `inqptnl`, `inquiryforms`) кладут
одно и то же утверждение НА ДВУХ языках подряд — сперва первому языку мира, потом второму:

    вон.append("ist 41 eine Primzahl? ja: ...")
    вон.append("41 est-il un nombre premier ? oui : ...")

Язык тут известен ТОЧНО — и известен он в месте кладки, а не потом. Прибор щербатости
спрашивал у домов пару «(язык, род)», дома отдавали один род строкой, и сорок три дома
стояли мимо меры. Гадать язык по письму было бы можно — `universals.язык` умеет это для
утверждений, — но вопросы («ist 41 eine Primzahl?», «41 est-il ... ?») его признаков не
несут вовсе, и 443 строки одного лишь `inqdefr` остались бы без языка.

    ЯЗЫК, ИЗВЕСТНЫЙ СТРОИТЕЛЮ, НЕ ДОЛЖЕН УГАДЫВАТЬСЯ ЧИТАТЕЛЕМ. Догадка по письму есть мера
    ПОСЛЕДНЕГО средства: ею проверяют метку, а не ставят её.

`Двое` есть тот же список, что и был, и кладут в него ровно так же — но он ПОМНИТ, какою по
счёту положена строка, и оттого знает её язык. Замена стои́т одной строки на функцию
(`вон = []` → `вон = bilang.Двое(ЯЗЫКИ_МИРА)`), и порядок кладки при этом объявлен, а не
подразумеваем: дом, положивший три строки подряд на одном языке, будет пойман сверкой с
письмом в самопроверке.
"""


class Двое(list):
    """Список строк двуязычного дома: первая — первому языку, вторая — второму, и так далее."""

    def __init__(self, языки):
        super().__init__()
        assert len(языки) == 2, "двуязычный сбор ждёт ровно двух языков"
        self.языки = tuple(языки)
        self.метки = []

    def append(self, с):
        self.метки.append(self.языки[len(self) % 2])
        super().append(с)

    def extend(self, что):
        for с in что:
            self.append(с)

    @property
    def парами(self):
        """[(строка, язык)] — то, ради чего сбор и заведён."""
        return list(zip(self, self.метки))


class Узором(list):
    """Сбор дома, кладущего НЕ ПОПОЛАМ: узор кладки объявлен, и метка идёт по нему.

    У польско-турецкого дома на один польский показ приходятся ДВЕ турецкие поверхности —
    «bölünür mü?» и «bölünüyor mu?», ибо частица гармонии при них разная. Узор («pl», «tr»,
    «tr») тут есть свойство ДЕЛА, а не сбоя: сбор, требующий кладки пополам, заставил бы
    дом лгать о себе.

        УЗОР КЛАДКИ ОБЪЯВЛЯЕТСЯ ТАМ, ГДЕ ОН НЕ РОВЕН. Дом, у которого поверхностей у языков
        поровну, объявляет это молчанием — `Двое`; дом, у которого их разное число, обязан
        сказать узор вслух.
    """

    def __init__(self, узор):
        super().__init__()
        assert узор, "узор кладки не может быть пуст"
        self.узор = tuple(узор)
        self.метки = []

    def append(self, с):
        self.метки.append(self.узор[len(self) % len(self.узор)])
        super().append(с)

    def extend(self, что):
        for с in что:
            self.append(с)

    @property
    def парами(self):
        return list(zip(self, self.метки))


def парами(что, языки):
    """Пары «строка, язык» из чего угодно: из `Двое` — его метками, из списка — чередованием.

    ЧЕРЕДОВАНИЕ ЗДЕСЬ НЕ ДОГАДКА, А ОБЪЯВЛЕНИЕ ВЫЗЫВАЮЩЕГО: так метятся только те списки,
    о которых дом сам говорит, что кладёт их парами.
    """
    if isinstance(что, (Двое, Узором)):
        return что.парами
    return [(с, языки[i % 2]) for i, с in enumerate(что)]
