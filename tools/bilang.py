#!/usr/bin/env python3
"""СБОР ДВУЯЗЫЧНОГО ДОМА: язык берётся У СТРОИТЕЛЯ, а не гадается по письму (15.09).

Пять домов дознания (`inqdefr`, `inqesit`, `inqpltr`, `inqptnl`, `inquiryforms`) кладут
одно и то же утверждение НА ДВУХ языках подряд — сперва первому языку мира, потом второму:

    вон.append("ist 41 eine Primzahl? ja: ...")
    вон.append("41 est-il un nombre premier ? oui : ...")

Язык тут известен ТОЧНО — и известен он в месте кладки, а не потом. Прибор щербатости
спрашивал у домов пару «(язык, род)», дома отдавали один род строкой, и сорок три дома
стояли мимо меры. Гадать язык по письму было бы можно — `universals.язык` умеет это для
утверждений, — но вопросы («ist 41 eine Primzahl?», «41 est-il ... ?») его признаков не
несут вовсе, и 443 строки одного лишь `inqdefr` остались бы без языка.

    ЯЗЫК, ИЗВЕСТНЫЙ СТРОИТЕЛЮ, НЕ ДОЛЖЕН УГАДЫВАТЬСЯ ЧИТАТЕЛЕМ. Догадка по письму есть мера
    ПОСЛЕДНЕГО средства: ею проверяют метку, а не ставят её.

`Двое` есть тот же список, что и был, и кладут в него ровно так же — но он ПОМНИТ, какою по
счёту положена строка, и оттого знает её язык. Замена стои́т одной строки на функцию
(`вон = []` → `вон = bilang.Двое(ЯЗЫКИ_МИРА)`), и порядок кладки при этом объявлен, а не
подразумеваем: дом, положивший три строки подряд на одном языке, будет пойман сверкой с
письмом в самопроверке.
"""
import re

# АЗБУКА РАЗЛИЧАЕТ ЛИШЬ ТЕХ, КТО ПИШЕТ РАЗНЫМИ ЗНАКАМИ, И ТОЛЬКО ИХ.
КИРИЛЛИЦА = re.compile(r"[а-яёА-ЯЁ]")
СЛОВО_ЛАТИНИЦЕЙ = re.compile(r"[a-zA-Z]{3,}")
# ПРИКАЗ РАЗМЕТКИ НЕ ЕСТЬ СЛОВО РЕЧИ (15.09). «$ x \cdot y = y \cdot x $» писано латиницей и
# не сказано ни на одном языке: «cdot» есть имя знака в письме TeX, как «×» есть знак. Строка,
# у которой все латинские слова суть приказы разметки, внеязычна — и звать её английской
# значило бы приписать английскому чужую запись.
ПРИКАЗ_РАЗМЕТКИ = re.compile(r"\\[a-zA-Z]+")
# ВНЕЯЗЫЧНОСТЬ ОБЪЯВЛЯЕТСЯ ТЕМ ЖЕ ЗНАКОМ, ЧТО И У ПРИБОРА ЩЕРБАТОСТИ (`scripts/form_matrix`).
ВНЕЯЗЫЧНО = "—"


def азбукой(с, языки=("en", "ru")):
    """Язык строки по НАЧЕРТАНИЮ — для домов, чьи два языка пишутся разными азбуками.

    Кириллица есть в русской строке всегда — даже когда в ней стои́т латинская «k»
    переменной; в английской её нет ни разу. Оттого для пары en/ru письмо И ЕСТЬ
    объявление, и гадать тут не о чем.

        СТРОКА БЕЗ ЕДИНОГО СЛОВА НЕ ПРИНАДЛЕЖИТ ЯЗЫКУ, А НЕ «ПРИНАДЛЕЖИТ АНГЛИЙСКОМУ».
        «100 + 0 = 100.» и «| 1 | 1 |» суть показы без речи, и звать их английскими значило
        бы приписать английскому то, чего он не говорил. Такие строки объявляются
        ВНЕЯЗЫЧНЫМИ — знаком «—», каким прибор щербатости их и ждёт.

    Латинское слово берётся длиною от трёх букв: «a», «b», «x» суть имена величин, а не
    речь, и строка «a^m × a^n = a^( m + n )» внеязычна ровно так же, как «4 ÷ 2 = 2».

        ГДЕ ДОМ ГОВОРИТ О ЧУЖОЙ АЗБУКЕ, АЗБУКА ПЕРЕСТАЁТ БЫТЬ ПРИЗНАКОМ ЯЗЫКА (15.09).

    Эта мера НЕ ГОДИТСЯ дому, который говорит О БУКВАХ: английская страница дома глифов —
    «glyph … is the capital Latin letter A and the capital Cyrillic letter А» — несёт
    кириллицу в кавычках речи, и начертание назвало бы её русскою. Там язык берут у
    строителя (`Двое`, `Узором` или поле `Сбор.язык`), а не у письма; проба на подлог
    проста: страница, помеченная «ru», в которой ЛАТИНСКИХ слов больше, чем кириллических,
    подозрительна и требует глаз.
    """
    assert set(языки) == {"en", "ru"}, (
        f"азбукой различимы лишь en и ru; для {языки} язык берут у строителя")
    if КИРИЛЛИЦА.search(с):
        return "ru"
    речь = ПРИКАЗ_РАЗМЕТКИ.sub(" ", с)
    return "en" if СЛОВО_ЛАТИНИЦЕЙ.search(речь) else ВНЕЯЗЫЧНО


class Двое(list):
    """Список строк двуязычного дома: первая — первому языку, вторая — второму, и так далее."""

    def __init__(self, языки):
        super().__init__()
        assert len(языки) == 2, "двуязычный сбор ждёт ровно двух языков"
        self.языки = tuple(языки)
        self.метки = []

    def append(self, с):
        self.метки.append(self.языки[len(self) % 2])
        super().append(с)

    def extend(self, что):
        for с in что:
            self.append(с)

    @property
    def парами(self):
        """[(строка, язык)] — то, ради чего сбор и заведён."""
        return list(zip(self, self.метки))


class Узором(list):
    """Сбор дома, кладущего НЕ ПОПОЛАМ: узор кладки объявлен, и метка идёт по нему.

    У польско-турецкого дома на один польский показ приходятся ДВЕ турецкие поверхности —
    «bölünür mü?» и «bölünüyor mu?», ибо частица гармонии при них разная. Узор («pl», «tr»,
    «tr») тут есть свойство ДЕЛА, а не сбоя: сбор, требующий кладки пополам, заставил бы
    дом лгать о себе.

        УЗОР КЛАДКИ ОБЪЯВЛЯЕТСЯ ТАМ, ГДЕ ОН НЕ РОВЕН. Дом, у которого поверхностей у языков
        поровну, объявляет это молчанием — `Двое`; дом, у которого их разное число, обязан
        сказать узор вслух.
    """

    def __init__(self, узор):
        super().__init__()
        assert узор, "узор кладки не может быть пуст"
        self.узор = tuple(узор)
        self.метки = []

    def append(self, с):
        self.метки.append(self.узор[len(self) % len(self.узор)])
        super().append(с)

    def extend(self, что):
        for с in что:
            self.append(с)

    @property
    def парами(self):
        return list(zip(self, self.метки))


def сказанный(язык_строителя, строка):
    """Язык показа: НАЗВАННЫЙ строителем, а если не назван — прочтённый по азбуке.

    ОБЪЯВЛЕНИЕ СИЛЬНЕЕ ДОГАДКИ ВЕЗДЕ, ГДЕ ОНО ЕСТЬ (15.09). Дом, у которого одни ветви
    называют язык, а другие молчат, читается этой мерой без правки молчащих ветвей: назвал —
    взяли названное; не назвал — прочли начертание и, если слов нет вовсе, объявили
    внеязычность.

    Помнить при этом надо границу самой азбуки: она различает лишь русский с английским, и
    дом, говорящий на третьем языке латиницей, ОБЯЗАН назвать язык сам.
    """
    return язык_строителя if язык_строителя else азбукой(строка)


def парами(что, языки):
    """Пары «строка, язык» из чего угодно: из `Двое` — его метками, из списка — чередованием.

    ЧЕРЕДОВАНИЕ ЗДЕСЬ НЕ ДОГАДКА, А ОБЪЯВЛЕНИЕ ВЫЗЫВАЮЩЕГО: так метятся только те списки,
    о которых дом сам говорит, что кладёт их парами.
    """
    if isinstance(что, (Двое, Узором)):
        return что.парами
    return [(с, языки[i % 2]) for i, с in enumerate(что)]
