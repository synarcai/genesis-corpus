#!/usr/bin/env python3
"""GENESIS layer: КРАТНОЕ ПРОТИВ РАЗНОСТНОГО, ПО-РУССКИ.

Английский `compare_mult` показал вещь, ради которой этот мир и
кладётся: две рамки, которые язык держит порознь, обязаны стоять НА
ОДНИХ И ТЕХ ЖЕ ЧИСЛАХ РЯДОМ — иначе организм покупает одну и не
покупает другую. По-английски врозь стояли счётное и несчётное («as
many as» против «as much as»). По-русски различие иное и путается чаще
всего:

    ВО СКОЛЬКО РАЗ больше — ДЕЛЕНИЕ
    НА СКОЛЬКО больше     — ВЫЧИТАНИЕ

Оба вопроса грамматически одинаковы, оба про «больше», и ответы у них
разные: 12 больше 4 В ТРИ РАЗА и НА ВОСЕМЬ. Мир, показывающий только
одну рамку, учит слышать в «больше» одно действие; здесь обе стоят на
одной паре чисел, и третьим показом стоит их РАЗЛИЧИЕ, названное вслух.

ОСНОВАНИЕ РЯДОМ С ВЕРДИКТОМ. Не «в 3 раза», а «в 3 раза: 12 = 3 × 4»;
не «на 8», а «на 8: 12 − 4 = 8». Суд делит и вычитает заново, а не
сверяется с записанным ответом.

ОТКАЗ С ОСНОВАНИЕМ — И ОН ЗДЕСЬ РОДНОЙ. «во сколько раз 10 больше 4?»
целым числом ответа не имеет, и честный ответ есть отказ С ПРИЧИНОЙ:
«10 = 2 × 4 + 2, остаток 2». Разностный вопрос на той же паре ответ
имеет всегда — и это само по себе показывает, что рамки разные:
отказать можно одной и нельзя другой.

ЧИСЛА ВЫВОДЯТСЯ ДИАПАЗОНАМИ, А НЕ ПЕРЕЧИСЛЯЮТСЯ. Кратные пары строятся
ОТ ОТВЕТА: берутся меньшее и множитель, большее собирается из них — и
кратность истинна по построению, а не по удаче. Пары для отказа
строятся так же и от обратного: с остатком, заведомо не нулевым.

СЧЁТНАЯ ФОРМА — ИЗ ДОМА. «в 3 раза», но «в 5 раз»; «на 8 рублей», но
«на 21 рубль». Ни одна форма здесь не написана рукой: их даёт
`rugram.форма`, где закон 1 / 2-4 / 5+ живёт как данные пакета.
"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import rugram  # noqa: E402
from gen_genesis_compare_mult import в_раза  # noqa: E402  — одна форма множителя словом на весь корпус
from layer import emit_grouped  # noqa: E402

ЦЕЛЬ = "datasets/genesis_ru_compare.txt"

# ЯДРО ДОСЛОВНЫХ ПОВТОРОВ: столько первых случаев каждого рода стоят во
# ВСЕХ проходах слово в слово.
ЯДРО = 3
СЛУЧАЕВ = 10

# ВЕЩИ ДЛЯ ЦЕНОВОЙ РАМКИ: ключ дома форм и его именительный.
# Цена меряется рублём, и рубль объявлен там же.
ВЕЩИ = ("книга", "ручка", "карта", "чашка", "монета")
ДЕНЬГИ = "рубль"


def семя(шаг, i):
    """Первые ЯДРО случаев прохода не знают — оттого и дословны."""
    return i if i < ЯДРО else шаг * 13 + i


def _пара_кратная(с):
    """(меньшее, множитель, большее) — кратность ПО ПОСТРОЕНИЮ.

    Меньшее и множитель берутся диапазонами, большее собирается из них.
    Пара, взятая наугад, давала бы целую кратность по удаче, и ветвь
    отказа съела бы почти все случаи.
    """
    меньшее = 2 + с % 9
    множитель = 2 + с % 5
    return меньшее, множитель, меньшее * множитель


def _пара_с_остатком(с):
    """(меньшее, частное, остаток, большее) — остаток заведомо не нуль."""
    меньшее = 3 + с % 8
    частное = 2 + с % 4
    остаток = 1 + с % (меньшее - 1)
    return меньшее, частное, остаток, частное * меньшее + остаток


def кратное(шаг):
    """«во сколько раз больше» — деление, с основанием рядом."""
    вон = []
    for i in range(СЛУЧАЕВ):
        м, к, б = _пара_кратная(семя(шаг, i))
        # ОДИН РАССКАЗ НА ВОПРОС ВО ВСЁМ КОРПУСЕ (М-153; класс tellings-differ
        # holon): та же форма, что в мире сравнения, — множитель словом и
        # звено делением; проверочное «14 = 2 × 7» было вторым рассказом.
        вон.append(f"во сколько раз {б} больше {м}? {б} больше {м} {в_раза(к)}: {б} ÷ {м} = {к}.")
    return вон


def разностное(шаг):
    """«на сколько больше» — вычитание, на ТЕХ ЖЕ числах."""
    вон = []
    for i in range(СЛУЧАЕВ):
        м, _к, б = _пара_кратная(семя(шаг, i))
        вон.append(f"на сколько {б} больше {м}? на {б - м}: "
                   f"{б} − {м} = {б - м}.")
    return вон


def рядом(шаг):
    """ДВЕ РАМКИ НА ОДНОЙ ПАРЕ, И РАЗЛИЧИЕ НАЗВАНО ВСЛУХ.

    Показ, ради которого мир и кладётся: пока ответы стоят порознь,
    «больше» слышится одним действием. Рядом — и видно, что вопросов
    два и действия два.
    """
    вон = []
    for i in range(СЛУЧАЕВ):
        м, к, б = _пара_кратная(семя(шаг, i))
        вон.append(f"{б} больше {м} в {к} {rugram.форма('раз', к)} и на "
                   f"{б - м}: во сколько раз — это деление, на сколько "
                   f"— это вычитание.")
    return вон


def цена(шаг):
    """Та же двойня в ценовой рамке: вещь, вещь и обе меры разом."""
    вон = []
    for i in range(СЛУЧАЕВ):
        с = семя(шаг, i)
        м, к, б = _пара_кратная(с)
        дорогая = ВЕЩИ[с % len(ВЕЩИ)]
        дешёвая = ВЕЩИ[(с + 1 + с % (len(ВЕЩИ) - 1)) % len(ВЕЩИ)]
        вон.append(f"{дорогая} стоит {б} {rugram.форма(ДЕНЬГИ, б)}, "
                   f"{дешёвая} стоит {м} {rugram.форма(ДЕНЬГИ, м)}: "
                   f"{дорогая} дороже в {к} {rugram.форма('раз', к)} и "
                   f"на {б - м} {rugram.форма(ДЕНЬГИ, б - м)}.")
    return вон


def отказ(шаг):
    """Кратный вопрос без целого ответа — и разностный рядом с ним.

    ОТКАЗ ПОКАЗАН НЕ ОДИН: рядом стоит вопрос, на который ответ ЕСТЬ.
    Отказ без соседа учит, что вопросы этого вида безответны; отказ с
    соседом учит, что безответен ИМЕННО ЭТОТ, и называет почему.
    """
    вон = []
    for i in range(ЯДРО + 2):
        м, ч, о, б = _пара_с_остатком(семя(шаг, i))
        # ОТКАЗ СКАЗАН ОБЪЯВЛЕННОЙ ФОРМОЙ ДОМА: отрицание сущего,
        # двоеточие, основание (`tools/manifest_kinds.отказов`).
        # ОТКАЗ — СВОЙ ВОПРОС «ДА/НЕТ» (М-147): «во сколько раз» без целого
        # ответа спрашивается кратностью, основание — деление с остатком в
        # порядке дознания (делитель × частное + остаток); второй вопрос той же
        # строки («на сколько») живёт своей строкой (разностное).
        вон.append(f"кратно ли {б} числу {м}? нет: {б} = {м} × {ч} + {о}, остаток {о}.")
    return вон


ГРУППЫ = (кратное, разностное, рядом, цена, отказ)


def pass_groups(шаг):
    return [сделать(шаг) for сделать in ГРУППЫ]


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
