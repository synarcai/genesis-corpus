#!/usr/bin/env python3
"""СЕМЕЙСТВО ЕСТЬ РОД, ФОРМА — ЕГО ПОВЕРХНОСТЬ (М-146, 03.09).

Прибор ширины вопроса (scripts/ask_width.py) считает родом якорный образец
суда. Суд, судящий одну рамку несколькими формами — повествованием,
отрицанием, вопросом, русской формой, — обязан объявить рамку ОДНИМ
образцом-перечислением своих форм, а вердикт отдавать совпавшей форме;
иначе прибор умножает роды на число форм и зовёт долгом повествование, у
которого вопрос есть. Здесь — один дом слияния на все семейные суды:
вердикты не меняются (каждая форма судится своим прежним образцом), меняется
только то, ЧТО прибор видит родом.
"""
import re


def слить(формы, обёртка=None):
    """(общий образец, судья) из [(образец-строка, судья формы)].

    Общий образец — якорное перечисление форм; судья ищет ту форму, что
    совпала целиком, и зовёт её судью с совпадением этой формы (или с
    тем, во что его завернёт `обёртка` — суд, выравнивающий группы,
    делает это сам). Формы без якорей не принимаются: род есть форма
    показа, а не кусок строки.
    """
    for о, _ in формы:
        if not (о.startswith("^") and о.endswith("$")):
            raise ValueError(f"форма без якорей: {о[:60]}")
    собранные = tuple((re.compile(о), п) for о, п in формы)
    общий = re.compile("^(?:" + "|".join(f"(?:{о[1:-1]})" for о, _ in формы) + ")$")

    def судья(м):
        строка = м.group(0)
        for о, п in собранные:
            мм = о.match(строка)
            if мм:
                return п(обёртка(мм) if обёртка else мм)
        return False
    return общий, судья


КИРИЛЛИЦА = re.compile(r"[а-яё]", re.I)


def язык_формы(образец):
    """«ru», если в образце есть кириллица вне классов букв, иначе «en»."""
    чистый = образец.replace("[а-яё]", "").replace("[А-Яа-яЁё]", "").replace("[а-яё ]", "")
    return "ru" if КИРИЛЛИЦА.search(чистый) else "en"


def правила(семейства, обёртка=None):
    """[(общий образец, судья)] — по семейству и языку.

    `семейства` — [(имя, [(образец, судья), …])]; формы одного семейства
    делятся по языку, ибо русская и английская рамки — два рода одной
    рамки: у каждой своя вопросная поверхность.
    """
    вон = []
    for _, формы in семейства:
        for язык in ("en", "ru"):
            свои = [(о, п) for о, п in формы if язык_формы(о) == язык]
            if свои:
                вон.append(слить(свои, обёртка))
    return tuple(вон)
