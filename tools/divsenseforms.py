#!/usr/bin/env python3
"""ДОМ ДВУХ СМЫСЛОВ ДЕЛЕНИЯ — ОДНО РАВЕНСТВО ОТВЕЧАЕТ НА ДВА РАЗНЫХ ВОПРОСА.

    РАЗЛИЧЕНИЯ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 246 мирам показов: «два смысла»,
    «two meanings», «по скольку каждому» — НОЛЬ. При этом ОБА ВИДА задач свод пишет давно: мир
    быта делит между друзьями («каждому досталось по 4 карты», 30 строк), мир меры считает, по
    скольку вышло частей (313 строк).

    СВОД РЕШАЕТ ОБЕ ЗАДАЧИ И НЕ ГОВОРИТ, ЧТО ОНИ РАЗНЫЕ.

ВОСЕМНАДЦАТАЯ ЛОВУШКА РЯДА, И ОНА НЕ В СЧЁТЕ, А В СМЫСЛЕ: 12 ÷ 4 = 3 ЗНАЧИТ И «ПО ТРИ КАЖДОМУ ИЗ
ЧЕТЫРЁХ», И «ТРИ КОРОБКИ ПО ЧЕТЫРЕ». Число ответа одно, а вещи за ним — разные: в первом случае
три КОНФЕТЫ, во втором три КОРОБКИ.

    ЧИСЛО ОТВЕТА НЕ ЕСТЬ ОТВЕТ: ОТВЕТ ЕСТЬ ЧИСЛО С ВЕЩЬЮ, И ДЕЛЕНИЕ РАЗЛИЧАЕТСЯ ИМЕННО ВЕЩЬЮ.

ЧЕТЫРЕ РОДА:

    на части     12 конфет на 4 учеников — это по 3 конфеты каждому: 12 ÷ 4 = 3,
                 и 4 × 3 = 12.
    по содержанию 12 конфет по 3 в коробку — это 4 коробки: 12 ÷ 3 = 4, и 3 × 4 = 12.
    два смысла   у равенства 12 ÷ 4 = 3 два смысла: по 3 конфеты на каждого из 4 и 3 коробки
                 по 4 конфеты: 4 × 3 = 12.                                   ← ЛОВУШКА
    вещь ответа  число одно, а вещи разные — 3 конфеты и 3 коробки: 12 ÷ 4 = 3,
                 и 12 ÷ 3 = 4.                                               ← ПРИЧИНА

ПЕРВЫЙ И ВТОРОЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО ВОПРОСУ: те же три числа, то же действие, и разница в
одном месте — что известно, ЧИСЛО ЧАСТЕЙ или ВЕЛИЧИНА ЧАСТИ. Порознь читатель решил бы, что
деление одно, и застрял бы на задаче другого вида.

ТРЕТИЙ РОД СВОДИТ ОБА В ОДНУ СТРОКУ, И ЭТО ЕДИНСТВЕННОЕ МЕСТО СВОДА, ГДЕ ОНИ ВСТРЕЧАЮТСЯ.
ЧЕТВЁРТЫЙ НАЗЫВАЕТ ПРИЧИНУ: одно и то же число ответа носит разные вещи, и вещь берётся не из
счёта, а из ВОПРОСА.

СЧЁТНЫЕ ФОРМЫ ВЕЩЕЙ БЕРУТСЯ У ЯЗЫКА: «3 конфеты», «5 конфет», «4 коробки» — дом не пишет своих
окончаний там, где свод держит таблицу русского счёта.

    python3 tools/divsenseforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётные формы вещей объявлены там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("на части", "по содержанию", "два смысла", "вещь ответа")

АНГЛ = {"конфета": ("sweet", "sweets"), "ученик": ("pupil", "pupils"),
        "коробка": ("box", "boxes")}


def форма(язык, ключ, n):
    if язык == "en":
        один, много = АНГЛ[ключ]
        return один if n == 1 else много
    return rugram.форма(ключ, n)


РАМКИ = {
    "ru": {
        "на части": "{в} {кв} на {n} {уч} — это по {k} {кк} каждому: {в} ÷ {n} = {k}, и {n} × {k} = {в}.",
        "по содержанию": "{в} {кв} по {k} в коробку — это {n} {кр}: {в} ÷ {k} = {n}, и {k} × {n} = {в}.",
        "два смысла": "у равенства {в} ÷ {n} = {k} два смысла: по {k} {кк} на каждого из {n} и {k} {крk} по {n} {кв_n}: {n} × {k} = {в}.",
        "вещь ответа": "число одно, а вещи разные — {k} {кк} и {k} {крk}: {в} ÷ {n} = {k}, и {в} ÷ {k} = {n}.",
    },
    "en": {
        "на части": "{в} {кв} for {n} {уч} is {k} {кк} each: {в} ÷ {n} = {k}, and {n} × {k} = {в}.",
        "по содержанию": "{в} {кв} packed {k} to a box is {n} {кр}: {в} ÷ {k} = {n}, and {k} × {n} = {в}.",
        "два смысла": "the equality {в} ÷ {n} = {k} has two meanings: {k} {кк} for each of {n}, and {k} {крk} of {n} {кв_n}: {n} × {k} = {в}.",
        "вещь ответа": "the number is one and the things differ — {k} {кк} and {k} {крk}: {в} ÷ {n} = {k}, and {в} ÷ {k} = {n}.",
    },
}
ПУСТО = dict(в=0, n=0, k=0, кв="", кк="", уч="", кр="", крk="", кв_n="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for n in range(2, 13):
            for k in range(2, 13):
                в = n * k
                if в > 100 or n == k:
                    continue
                общ = dict(ПУСТО, в=в, n=n, k=k,
                           кв=форма(язык, "конфета", в),
                           кк=форма(язык, "конфета", k),
                           кв_n=форма(язык, "конфета", n),
                           уч=форма(язык, "ученик", n),
                           кр=форма(язык, "коробка", n),
                           крk=форма(язык, "коробка", k))
                вон[рамки["на части"].format(**общ)] = (язык, "на части")
                вон[рамки["по содержанию"].format(**общ)] = (язык, "по содержанию")
                if (n + k) % 2 == 0:
                    вон[рамки["два смысла"].format(**общ)] = (язык, "два смысла")
                if (n * k) % 3 == 0:
                    вон[рамки["вещь ответа"].format(**общ)] = (язык, "вещь ответа")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_ДВА_СМЫСЛА = re.compile(r"(?:два смысла|two meanings)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    # ДВА СМЫСЛА ОБЯЗАНЫ БЫТЬ ДВУМЯ: делитель и частное на такой странице ОБЯЗАНЫ РАЗОЙТИСЬ,
    # иначе оба смысла совпали бы и показывать было бы нечего.
    if _ДВА_СМЫСЛА.search(с):
        частные = _ЧАСТНОЕ.findall(с)
        if not частные or частные[0][1] == частные[0][2]:
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:92]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    дс = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "два смысла")
    нч = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "на части")
    for страница, слово, куда in ((дс, "смысла", "смысл"), (нч, "каждому", "каждом")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(дс + " " + дс)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ДЕЛИТЕЛЬ И ЧАСТНОЕ РАЗНЫЕ — ИНАЧЕ ДВА СМЫСЛА СЛИЛИСЬ БЫ В ОДИН.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "два смысла":
            continue
        a, b, c = _ЧАСТНОЕ.findall(с)[0]
        if b == c:
            беды.append(f"смыслы слились: {с[:70]}")
            break
    # СЧЁТНАЯ ФОРМА БЕРЁТСЯ У ЯЗЫКА.
    for кусок in ("2 конфеты", "5 конфет", "2 коробки", "5 коробок"):
        if not any(кусок in с for с in ПОКАЗЫ):
            беды.append(f"СЧЁТНАЯ ФОРМА НЕ ПОКАЗАНА: {кусок}")
    # СЛОВА ДО ПОСЛЕДНЕГО ДВОЕТОЧИЯ, РАВЕНСТВА ПОСЛЕ.
    for с in ПОКАЗЫ:
        хвост = с.rsplit(":", 1)[1]
        if re.search(r"[A-Za-zА-Яа-яЁё]{3,}", хвост.replace("and", "").replace("и", "")):
            беды.append(f"СЛОВА ПОСЛЕ ДВОЕТОЧИЯ: {с[:70]}")
            break
    print(f"ДВА СМЫСЛА ДЕЛЕНИЯ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
