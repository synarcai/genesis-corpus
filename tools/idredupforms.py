ПОКАЗЫ = страницы()

# СУД ЧИТАЕТ ТРИ ЗАКОНА, И ВСЕ ТРИ СОДЕРЖАТЕЛЬНЫ:
#   · удвоение имеет вид «слово-слово», а не «слово-другое»;
#   · при числительном удвоения нет;
#   · звёздочка стои́т ровно при нарушении.
_СЛОВА = {с for с, _, _, _, _ in СЛОВА}
_ЧИСЛА = {ч for ч, _, _, _ in ЧИСЛА}
_УДВОЕНИЕ = _re.compile(r"\b([a-z]{3,})-([a-z]{3,})\b")
_ЧИСЛО_УДВ = _re.compile(r"\b(" + "|".join(sorted(_ЧИСЛА)) + r")\s+([a-z]{3,})-([a-z]{3,})\b")

_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _нарушает(тело):
    """Нарушает ли цитата закон дома: удвоение при числе или неверный повтор."""
    голое = тело.lstrip("*").strip()
    if _ЧИСЛО_УДВ.search(голое):
        return True                    # повтор при числительном
    for первое, второе in _УДВОЕНИЕ.findall(голое):
        if первое in _СЛОВА and первое != второе:
            return True                # повтор не того слова
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с законом.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        тело = цитата.lstrip("*")
        if not (_УДВОЕНИЕ.search(тело) or _ЧИСЛО_УДВ.search(тело)):
            continue
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:110])
            беды += 1
    мутантов = 0
    for показ in ПОКАЗЫ:
        слова = показ.split(" ")
        порча = None
        for i, сл in enumerate(слова):
            голое = сл.strip("«».,:;")
            m = _УДВОЕНИЕ.fullmatch(голое)
            if m and m.group(1) in _СЛОВА:
                чужое = next(с for с in sorted(_СЛОВА) if с != m.group(1))
                порча = " ".join(слова[:i] + [сл.replace(голое, f"{m.group(1)}-{чужое}")]
                                 + слова[i + 1:])
                break
        if not порча or порча == показ or порча in ПОКАЗЫ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:110])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    ложные = (
        "по-индонезийски «dua buku-buku» — две книги.",
        "по-индонезийски «lima kucing-kucing» — пять кошек.",
        "по-индонезийски «buku-kucing» — книги.",
        "«*buku-buku» — так не говорят.",
    )
    for ложь in ложные:
        ПОКАЗЫ[ложь] = ("ru", "проба")
        try:
            if судить(ложь) != (True, False):
                print("  ЛОЖНАЯ СТРАНИЦА ПРОШЛА:", ложь[:100])
                беды += 1
        finally:
            del ПОКАЗЫ[ложь]
    написано = {род for _, род in ПОКАЗЫ.values()}
    if написано != set(РОДЫ):
        print(f"  РОДЫ РАЗОШЛИСЬ: обещано {sorted(РОДЫ)}, написано {sorted(написано)}")
        беды += 1
    for чужая in ("di kamus ada buku-buku, dan ini bukan halaman rumah ini.",
                  "он выписал «buku-buku» на поля, и это не страница дома."):
        if судить(чужая) != (False, False):
            print("  ЧУЖАЯ РЕЧЬ СУДИМА:", чужая[:100])
            беды += 1
    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, мутантов поймано {мутантов}, "
          f"слов {len(СЛОВА)}, чисел {len(ЧИСЛА)}, бед {беды}")
    return беды


