#!/usr/bin/env python3
"""ДОМ УСЛОВИЙ ЗАДАЧИ — ЧТО НУЖНО ДЛЯ ОТВЕТА, И ЧЕГО НЕ НУЖНО.

    НИ НЕДОСТАЮЩЕГО, НИ ЛИШНЕГО УСЛОВИЯ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 249 мирам
    показов: «не хватает данных», «нельзя ответить», «not enough data» — НОЛЬ; «лишнее условие»,
    «не нужно для ответа» — НОЛЬ. Всякая задача свода ПОЛНА: в ней ровно столько чисел, сколько
    нужно, и ни одним больше.

    СВОД УЧИТ РЕШАТЬ И НЕ УЧИТ СМОТРЕТЬ, ЕСТЬ ЛИ ЧТО РЕШАТЬ.

ДВАДЦАТЬ ПЕРВАЯ ЛОВУШКА РЯДА, И ОНА ОТНИМАЕТ У ЧИТАТЕЛЯ ПРИВЫЧКУ: ЕСЛИ В ЗАДАЧЕ ДВА ЧИСЛА, ИХ
НАДО СЛОЖИТЬ. Привычка эта верна ровно до первой задачи, где число лишнее или где его не хватает,
и оба случая свод не показывал никогда.

    ЧИСЛО В УСЛОВИИ НЕ ЕСТЬ ПРИКАЗ СЧИТАТЬ: СПЕРВА СМОТРЯТ, О ТОМ ЛИ ОНО, О ЧЁМ ВОПРОС.

ЧЕТЫРЕ РОДА:

    хватает      на полке 5 книг, в шкафу 3 книги; сколько книг всего? данных хватает:
                 5 + 3 = 8.
    не хватает   на полке 5 книг; сколько книг всего? ответа нет: про шкаф ничего
                 не сказано.                                                  ← ОТКАЗ
    лишнее       на полке 5 книг, в шкафу 3 книги, на столе 2 яблока; сколько книг всего?
                 яблоки лишние: 5 + 3 = 8.                                    ← ЛОВУШКА
    какое лишнее лишнее число здесь 2, ибо оно о яблоках, а вопрос о книгах: 5 + 3 = 8.

ВТОРОЙ РОД ЕСТЬ ОТКАЗ, И ОН ОБЪЯВЛЕН АКТОМ МИРА: страница не отвечает и говорит ОСНОВАНИЕ отказа.
Свод знает отказ в мирах языка и границы, но ни разу не отказывал по НЕДОСТАТКУ УСЛОВИЯ.

    ОТКАЗ БЕЗ ОСНОВАНИЯ ЕСТЬ МОЛЧАНИЕ; ОТКАЗ С ОСНОВАНИЕМ ЕСТЬ ОТВЕТ.

ПЕРВЫЙ И ВТОРОЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО ПОЛНОТЕ: та же задача, тот же вопрос, и разница в одном
месте — сказано ли о втором слагаемом. ТРЕТИЙ И ЧЕТВЁРТЫЙ — пара по делу: третий показывает
лишнее, четвёртый называет ЕГО ИМЕНЕМ и говорит, почему оно лишнее.

ЛИШНЕЕ ЧИСЛО ВСЕГДА О ДРУГОЙ ВЕЩИ, А НЕ О ТОЙ ЖЕ: «2 яблока» при вопросе о книгах лишние не
потому, что их мало, а потому, что они не книги. Число той же вещи лишним не бывает — оно либо
слагаемое, либо часть ответа.

    python3 tools/needforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётные формы вещей объявлены там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("хватает", "не хватает", "лишнее", "какое лишнее")

# ВЕЩИ И МЕСТА ОБЪЯВЛЕНЫ, А НЕ ВЫВЕДЕНЫ: счётные формы берутся у языка, места — постоянные
# обороты, в которых склонять нечего.
ВЕЩИ = ("книга", "карандаш", "конфета", "яблоко")
МЕСТА = {"ru": ("на полке", "в шкафу", "на столе"),
         "en": ("on the shelf", "in the cupboard", "on the table")}
АНГЛ = {"книга": ("book", "books"), "карандаш": ("pencil", "pencils"),
        "конфета": ("sweet", "sweets"), "яблоко": ("apple", "apples")}
# ИМЯ ВЕЩИ ВО МНОЖЕСТВЕННОМ ИМЕНИТЕЛЬНОМ — для оборота «яблоки лишние». Берётся у языка тем же
# правилом, каким `rugram` выводит именительное множественное.
МНОЖЕСТВЕННОЕ = {"ru": lambda к: rugram.именительный_мн(к),
                 "en": lambda к: АНГЛ[к][1]}
ЛИШНИЕ = {"ru": {"книга": "лишние", "карандаш": "лишние", "конфета": "лишние",
                 "яблоко": "лишние"},
          "en": {к: "are not needed" for к in ВЕЩИ}}


def форма(язык, ключ, n):
    if язык == "en":
        один, много = АНГЛ[ключ]
        return один if n == 1 else много
    return rugram.форма(ключ, n)


РАМКИ = {
    "ru": {
        "хватает": "{место1} {a} {вещь_a}, {место2} {b} {вещь_b}; сколько {вещь_род} всего? данных хватает: {a} + {b} = {s}.",
        "не хватает": "{место1} {a} {вещь_a}; сколько {вещь_род} всего? ответа нет: про {место2_что} ничего не сказано.",
        "лишнее": "{место1} {a} {вещь_a}, {место2} {b} {вещь_b}, {место3} {c} {чужое_c}; сколько {вещь_род} всего? {чужое_мн} лишние: {a} + {b} = {s}.",
        "какое лишнее": "лишнее число здесь {c}: оно считает {чужое_мн}, а вопрос про {вещь_мн}: {a} + {b} = {s}.",
    },
    "en": {
        "хватает": "{место1} there are {a} {вещь_a}, {место2} there are {b} {вещь_b}; how many {вещь_мн} in all? the data is enough: {a} + {b} = {s}.",
        "не хватает": "{место1} there are {a} {вещь_a}; how many {вещь_мн} in all? there is no answer: nothing is said about {место2_что}.",
        "лишнее": "{место1} there are {a} {вещь_a}, {место2} there are {b} {вещь_b}, {место3} there are {c} {чужое_c}; how many {вещь_мн} in all? the {чужое_мн} {лишние}: {a} + {b} = {s}.",
        "какое лишнее": "the extra number here is {c}: it counts {чужое_мн}, and the question is about {вещь_мн}: {a} + {b} = {s}.",
    },
}
# ПАДЕЖИ БЕРУТСЯ ТОЛЬКО ТЕ, ЧТО ЯЗЫК ВЫВОДИТ. Первая редакция просила предложное множественное
# («о яблоках»), а `rugram` выводит его лишь для слов своей падежной парадигмы — для трёх вещей
# из четырёх вышло None, и тридцать восемь страниц сказали «о None». Рамка переписана на
# ВИНИТЕЛЬНЫЙ множественного, который для неодушевлённых совпадает с именительным и выводится
# для всех: «считает яблоки», «про книги».
#
#     ДОМ БЕРЁТ У ЯЗЫКА ТО, ЧТО ЯЗЫК ДАЁТ, И МЕНЯЕТ ОБОРОТ, А НЕ ДОПИСЫВАЕТ ОКОНЧАНИЕ.
ПУСТО = dict(место1="", место2="", место3="", место2_что="", a=0, b=0, c=0, s=0,
             вещь_a="", вещь_b="", вещь_мн="", вещь_род="", чужое_c="", чужое_мн="",
             лишние="")
МЕСТА_ЧТО = {"ru": ("полку", "шкаф", "стол"), "en": ("the shelf", "the cupboard", "the table")}


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, места = РАМКИ[язык], МЕСТА[язык]
        что = МЕСТА_ЧТО[язык]
        # ОТКАЗ КУЁТСЯ СВОИМ ПЕРЕБОРОМ: он не зависит ни от второго числа, ни от лишней
        # вещи, и внутри чужих циклов его страницы схлопывались в двадцать одну против
        # шестидесяти трёх у прочих. РЯД, ЗАВИСЯЩИЙ ОТ МЕНЬШЕГО ЧИСЛА ПРИЗНАКОВ, КУЁТСЯ
        # ОТДЕЛЬНО, А НЕ ВНУТРИ ЧУЖОГО ПЕРЕБОРА.
        #
        # НЕДОСТАЁТ НЕ ВСЕГДА ВТОРОГО: отказ показан с обеих сторон, иначе читатель решил бы,
        # что пропадает всегда последнее условие.
        for вещь in ВЕЩИ:
            for a in range(2, 10):
                общ = dict(ПУСТО, место1=места[0], место2_что=что[1], a=a,
                           вещь_a=форма(язык, вещь, a),
                           вещь_род=(форма(язык, вещь, 5) if язык == "ru"
                                     else МНОЖЕСТВЕННОЕ[язык](вещь)))
                вон[рамки["не хватает"].format(**общ)] = (язык, "не хватает")
                вон[рамки["не хватает"].format(
                    **dict(общ, место1=места[1], место2_что=что[0]))] = (язык, "не хватает")
        # «ХВАТАЕТ» КУЁТСЯ ТЕМ ЖЕ ПРАВИЛОМ, ЧТО И ОТКАЗ: его страница не знает о лишней вещи,
        # и внутри чужого перебора схлопывалась так же — 21 против 63.
        for вещь in ВЕЩИ:
            for a in range(2, 10):
                for b in range(2, 10):
                    # РЯД ВЫРАВНЕН ЗАМЕРОМ: у рода «лишнее» на каждую пару чисел приходится
                    # ТРИ чужие вещи, и потому его страниц втрое больше. Здесь взята пара в
                    # одном порядке (a ≤ b) — ряд выходит вровень с прочими.
                    if (a + b) % 2 or a > b:
                        continue
                    вон[рамки["хватает"].format(
                        **dict(ПУСТО, место1=места[0], место2=места[1], a=a, b=b, s=a + b,
                               вещь_a=форма(язык, вещь, a), вещь_b=форма(язык, вещь, b),
                               вещь_род=(форма(язык, вещь, 5) if язык == "ru"
                                         else МНОЖЕСТВЕННОЕ[язык](вещь))))] = (язык, "хватает")
        for вещь in ВЕЩИ:
            for чужое in ВЕЩИ:
                if чужое == вещь:
                    continue
                for a in range(2, 10):
                    for b in range(2, 10):
                        if (a * b + len(вещь)) % 7:
                            continue
                        # ЛИШНЕЕ ЧИСЛО НЕ СОВПАДАЕТ НИ СО СЛАГАЕМЫМ, НИ С ОТВЕТОМ:
                        # иначе оно неотличимо от нужного, и страница учит обратному.
                        c = next(к for к in range(2, 12)
                                 if к not in (a, b, a + b))
                        общ = dict(
                            ПУСТО, место1=места[0], место2=места[1], место3=места[2],
                            место2_что=что[1], a=a, b=b, c=c, s=a + b,
                            вещь_a=форма(язык, вещь, a), вещь_b=форма(язык, вещь, b),
                            вещь_мн=МНОЖЕСТВЕННОЕ[язык](вещь),
                            # ПОСЛЕ «СКОЛЬКО» СТОИ́Т РОДИТЕЛЬНЫЙ МНОЖЕСТВЕННОГО — третья
                            # счётная форма языка: «сколько книг», а не «сколько книги».
                            вещь_род=(форма(язык, вещь, 5) if язык == "ru"
                                      else МНОЖЕСТВЕННОЕ[язык](вещь)),
                            чужое_c=форма(язык, чужое, c),
                            чужое_мн=МНОЖЕСТВЕННОЕ[язык](чужое),
                            лишние=ЛИШНИЕ[язык][чужое])
                        # ТРИ РОДА СУЖЕНЫ ДО ЧЁТНОЙ СУММЫ — ряды выравниваются с отказом.
                        if (a + b) % 2:
                            continue
                        вон[рамки["лишнее"].format(**общ)] = (язык, "лишнее")
                        вон[рамки["какое лишнее"].format(**общ)] = (язык, "какое лишнее")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА = re.compile(r"(?<![/\d])(\d+) \+ (\d+) = (\d+)(?![/\d])")
_ОТКАЗ = re.compile(r"(?:ответа нет|there is no answer)")
_ЛИШНЕЕ_ЧИСЛО = re.compile(r"(?:лишнее число здесь|the extra number here is) (\d+)")
_ЧИСЛА = re.compile(r"(?<![/\d])(\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, итог in _СУММА.findall(с):
        if int(a) + int(b) != int(итог):
            return True, False
    # ОТКАЗ ОБЯЗАН БЫТЬ ОТКАЗОМ: на такой странице НЕТ ни суммы, ни второго слагаемого — иначе
    # она отказывает в том, на что сама же и отвечает.
    if _ОТКАЗ.search(с):
        if _СУММА.search(с) or len(_ЧИСЛА.findall(с)) != 1:
            return True, False
    # ЛИШНЕЕ ОБЯЗАНО БЫТЬ ЛИШНИМ: названное число не входит в сумму страницы.
    for лишнее in _ЛИШНЕЕ_ЧИСЛО.findall(с):
        слагаемые = {a for a, b, _ in _СУММА.findall(с)} | {b for _, b, _ in _СУММА.findall(с)}
        if лишнее in слагаемые:
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    нх = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "не хватает")
    лш = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "лишнее")
    for страница, слово, куда in ((нх, "сказано", "сказан"), (лш, "лишние", "лишни")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(нх + " " + нх)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ОТКАЗ НЕСЁТ ОСНОВАНИЕ, И ОНО ОТДЕЛЕНО ДВОЕТОЧИЕМ — того же требует манифест от акта отказа.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "не хватает":
            continue
        if ("нет:" not in с and "no answer:" not in с) or not с.rsplit(":", 1)[1].strip():
            беды.append(f"отказ без основания: {с[:70]}")
            break
    # ЛИШНЕЕ ВСЕГДА О ДРУГОЙ ВЕЩИ: страница, где лишнее той же вещи, учила бы обратному.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "лишнее":
            continue
        числа = _ЧИСЛА.findall(с)
        if len(set(числа)) < 3:
            беды.append(f"лишнее неотличимо от слагаемых: {с[:70]}")
            break
    print(f"УСЛОВИЯ ЗАДАЧИ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
