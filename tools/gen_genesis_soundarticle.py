#!/usr/bin/env python3
"""GENESIS layer: АРТИКЛЬ ПО ЗВУКУ — see tools/soundarticleforms.py for the law.

ПРАВИЛО И ДВЕ ЕГО СТОРОНЫ РАЗДЕЛЕНЫ ПО ТОМУ, В КАКУЮ СТОРОНУ РАСХОДЯТСЯ БУКВА И ЗВУК.

«Правило названо» идёт вместе с «буква согласная, звук гласный»: первое даёт закон, второе
тут же показывает слово, на котором буква обманывает.

Вторая сторона — «буква гласная, звук согласный» — стои́т ОТДЕЛЬНО, и это нарочно: читатель,
встретивший обе стороны разом, запомнит, что «буква обманывает», и не запомнит, В КАКУЮ
сторону. Каждая сторона заучивается своим показом, а сводит их третья группа.

    ЛОВУШКА, ПОКАЗАННАЯ ДВУМЯ СТОРОНАМИ СРАЗУ, УЧИТ НЕДОВЕРИЮ К ПРАВИЛУ, А НЕ ПРАВИЛУ.

«Одна буква, два правила» и «правило смотрит за себя» — третьей группой: обе о том, что закон
читается не по слову, а по тому, что за ним и что в нём звучит.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import soundarticleforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_soundarticle.txt"
ГРУППЫ = (("правило названо", "буква согласная, звук гласный"),
          ("буква гласная, звук согласный",),
          ("одна буква, два правила", "правило смотрит за себя"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
