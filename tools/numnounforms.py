    for путь in sorted(ДВОР.glob("*.json")):
        код = путь.stem
        тело = _пакет(код)
        отк = _отказы(код, тело)
        if not отк:
            continue
        лагерь = _лагерь(тело.get("count_agreement"))
        if лагерь is None:
            continue
        сч = ((тело.get("morph_classes") or {}).get("noun_count") or {}).get("lexemes") or {}
        первое = next(iter(сч.items()), None)
        имя = tuple(первое[1][:2]) if первое and len(первое[1]) >= 2 else None
        чис = тело.get("numerals") or {}
        вон[код] = (лагерь, tuple(str(п) for п in тело["count_agreement"]), отк, имя, чис)
    return вон


