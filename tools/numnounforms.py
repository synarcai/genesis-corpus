def _лагерь(правило):
    """Имя лагеря ПО ОБЪЯВЛЕННОМУ ПРАВИЛУ: разбор данных, а не список языков рукой."""
    if not правило:
        return None
    формы = [п.get("form") for п in правило]
    if len(правило) == 1 and формы == ["one"]:
        return ЕДИНСТВЕННОЕ
    if формы[-1] == "one":
        return ВОЗВРАТ                     # лестница, замыкающаяся на единственном
    if any("mod" in п for п in правило) or "few" in формы:
        return ЛЕСТНИЦА
    if формы[-1] == "many":
        return МНОЖЕСТВЕННОЕ
    return None


