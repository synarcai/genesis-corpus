def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая её цитата сходится с пакетом.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        тело = цитата.lstrip("*")
        if тело not in ЛОЖЬ and тело not in ПРАВДА:
            continue                      # цитата, о которой пакет не говорит, не судима
        if _нарушает(тело) != звезда:
            return True, False
    return True, True


