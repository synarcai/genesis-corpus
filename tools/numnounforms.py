def _соседи(код, лагерь, язык):
    """«, и так же отвечают X, Y и Z» — или речь о ЛАГЕРЕ ИЗ ОДНОГО, а не «никто более».

    ЛАГЕРЬ ИЗ ОДНОГО ЕСТЬ ФАКТ, А НЕ ПУСТОЙ СПИСОК: арабский отвечает так ОДИН, и сказать
    об этом надо словами, а не пустотой на месте перечня.
    """
    имена = [ИМЯ_ЯЗЫКА[к][0 if язык == "ru" else 1]
             for к in ЛАГЕРИ[лагерь] if к != код and к in ИМЯ_ЯЗЫКА]
    if not имена:
        return (", и так отвечает он ОДИН из всех" if язык == "ru"
                else ", and it answers so ALONE among all")
    союз = " и " if язык == "ru" else " and "
    перечень = имена[0] if len(имена) == 1 else ", ".join(имена[:-1]) + союз + имена[-1]
    return (f", и так же отвечают {перечень}" if язык == "ru"
            else f", and so do {перечень}")


