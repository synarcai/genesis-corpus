#!/usr/bin/env python3
"""СЛИЧЕНИЕ ВЕРДИКТОВ: снимок приговоров палаты о мирах — до правки суда и после.

    ПРАВКА СУДА ПРОВЕРЯЕТСЯ НЕ ЧТЕНИЕМ, А СЛИЧЕНИЕМ. Суд можно переписать так, что он перестанет
    видеть часть строк, — и НИ ОДНА не станет ложной: они просто выйдут из-под суда МОЛЧА. Ни
    ворота записи, ни палата такой беды не назовут, ибо немота не есть ложь.

ТАК И БЫЛО 08.09: слив рассказ с вопросом в один образец, я сдвинул номера групп, и обратная
ссылка второй ветви стала указывать на первую. Семьдесят четыре строки дома быта вышли из-под
суда молча. Нашло это сличение вердиктов, и с тех пор ни одна правка суда не идёт без него.

КАК ПОЛЬЗОВАТЬСЯ (двумя вызовами вокруг правки):

    python3 tools/verdicts.py снять /tmp/до.json datasets/genesis_everyday.txt
    …правка суда…
    python3 tools/verdicts.py снять /tmp/после.json datasets/genesis_everyday.txt
    python3 tools/verdicts.py сличить /tmp/до.json /tmp/после.json

СНИМОК ХРАНИТ ТРОЙКУ на каждую строку: судимо, истинно, КЕМ. Третье поле важно не меньше первых
двух: строка, перешедшая от своего суда к соседу, осталась бы неотличимой без него, — а это
ровно та подмена, о какой говорит закон разделения труда.
"""
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))


def снять(цель, миры):
    """Снимок вердиктов палаты о названных мирах."""
    import panel
    П = panel.палата()
    вон = []
    for мир in миры:
        for с, судимо, истинно, кем in П.судить_файл(мир, jobs=1):
            вон.append([судимо, истинно, sorted(кем)])
    pathlib.Path(цель).write_text(json.dumps(вон), encoding="utf-8")
    судимых = sum(1 for с, _и, _к in вон if с)
    ложных = sum(1 for с, и, _к in вон if с and not и)
    print(f"СНИМОК: вердиктов {len(вон)}, судимо {судимых}, ложных {ложных} → {цель}")
    return вон


def сличить(до, после):
    """Расхождения двух снимков: сколько и какого рода."""
    а = json.loads(pathlib.Path(до).read_text(encoding="utf-8"))
    б = json.loads(pathlib.Path(после).read_text(encoding="utf-8"))
    if len(а) != len(б):
        print(f"СЛИЧЕНИЕ ОТКАЗ: снимки разной длины ({len(а)} и {len(б)}) — "
              f"миры менялись между съёмками, и сличать нечего")
        return 2
    роды = {"замолчал": 0, "заговорил": 0, "истина→ложь": 0, "ложь→истина": 0, "сменил судью": 0}
    def тройка(з):
        # СНИМОК СТАРОГО ОБРАЗЦА ЧИТАЕТСЯ ТОЖЕ: третье поле («кем») могло не сниматься.
        return (з[0], з[1], з[2] if len(з) > 2 else None)

    for з1, з2 in zip(а, б):
        (с1, и1, к1), (с2, и2, к2) = тройка(з1), тройка(з2)
        if с1 and not с2:
            роды["замолчал"] += 1
        elif с2 and not с1:
            роды["заговорил"] += 1
        elif с1 and с2 and и1 != и2:
            роды["истина→ложь" if и1 else "ложь→истина"] += 1
        elif к1 is not None and к2 is not None and к1 != к2:
            роды["сменил судью"] += 1
    всего = sum(роды.values())
    хвост = ", ".join(f"{и} {n}" for и, n in роды.items() if n)
    print(f"СЛИЧЕНИЕ: вердиктов {len(а)}, РАСХОЖДЕНИЙ {всего}" + (f" — {хвост}" if хвост else ""))
    return 0 if всего == 0 else 1


def main():
    if len(sys.argv) < 3:
        print(__doc__.split("КАК ПОЛЬЗОВАТЬСЯ")[1].split('"""')[0].strip())
        return 2
    дело = sys.argv[1]
    if дело == "снять":
        снять(sys.argv[2], sys.argv[3:])
        return 0
    if дело == "сличить":
        return сличить(sys.argv[2], sys.argv[3])
    print(f"СЛИЧЕНИЕ ОТКАЗ: неведомое дело «{дело}» — есть «снять» и «сличить»")
    return 2


if __name__ == "__main__":
    sys.exit(main())
