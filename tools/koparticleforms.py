def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for сл, согл, ру, ан in СЛОВА:
            звук = "согласным" if согл else "гласным"
            звук_en = "a consonant" if согл else "a vowel"
            for после_согл, после_гласн, роль, роль_en in ПАРЫ:
                своя = после_согл if согл else после_гласн
                чужая = после_гласн if согл else после_согл
                общ = dict(сл=сл, своя=своя, чужая=чужая, ру=ру, ан=ан, роль=роль,
                           роль_en=роль_en, звук=звук, звук_en=звук_en)
                for род in РОДЫ:
                    # РОД «ВЫБОР НЕ О СМЫСЛЕ» ИДЁТ ПО ОДНОМУ РАЗУ НА ПАРУ ЧАСТИЦ, А НЕ ОДИН
                    # НА ДОМ (13.09, куплено прибором «слово однажды»). Первая редакция
                    # ставила его единожды — и четыре слова этой страницы («Оба», «Both»,
                    # «ЗВУЧАЩИЙ», «СМЫСЛОВОЙ») остались во всём своде РОВНО РАЗ.
                    #
                    #     СЛОВО, ПОКАЗАННОЕ ОДИН РАЗ, ЕСТЬ СЛОВО НЕПОКАЗАННОЕ: читателю не с
                    #     чем его сличить. Довод, сказанный однажды, разделяет его участь.
                    if род == "выбор не о смысле" and сл != "책":
                        continue
                    вон[рамки[род].format(**общ)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()

# СУД ЧИТАЕТ ДВА ЗАКОНА, И ОБА СОДЕРЖАТЕЛЬНЫ:
#   · частица при слове обязана сойтись с объявленной для его последнего звука;
#   · звёздочка стои́т ровно при нарушении.
_СОГЛАСНОЕ = {сл: согл for сл, согл, _, _ in СЛОВА}
_ПОСЛЕ_СОГЛ = {а for а, _, _, _ in ПАРЫ}
_ПОСЛЕ_ГЛАСН = {б for _, б, _, _ in ПАРЫ}
_ВСЕ_ЧАСТИЦЫ = _ПОСЛЕ_СОГЛ | _ПОСЛЕ_ГЛАСН
_СЛОВО_ЧАСТИЦА = _re.compile(r"(" + "|".join(sorted(_СОГЛАСНОЕ, key=len, reverse=True)) +
                             r")(" + "|".join(sorted(_ВСЕ_ЧАСТИЦЫ)) + r")")

_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _нарушает(тело):
    """Нарушает ли цитата закон дома: частица не того ряда при слове."""
    for сл, час in _СЛОВО_ЧАСТИЦА.findall(тело.lstrip("*").strip()):
        согл = _СОГЛАСНОЕ[сл]
        законная = _ПОСЛЕ_СОГЛ if согл else _ПОСЛЕ_ГЛАСН
        if час not in законная:
            return True
    return False


# ЦИТАТА ЕСТЬ РЕЧЬ ОБЪЯВЛЕННОГО ЯЗЫКА, И ВСЯКИЙ ЕЁ КУСОК СТОИ́Т В ТАБЛИЦЕ (13.09).
#
# `scripts/house_mutant.py` назвал дом СТЕРЕГУЩИМ НАБОРОМ, А НЕ ЗАКОНОМ, и был прав: порча,
# вписанная в набор показов, ломала цитату так, что признак её больше не узнавал, — и закон,
# проверяющий лишь узнанное, молчал.
#
#     ЗАКОН, ПРОВЕРЯЮЩИЙ ЛИШЬ ТО, ЧТО РАСПОЗНАЛ, СЛЕП К ПОРЧЕ, СДЕЛАВШЕЙ ЦИТАТУ
#     НЕРАСПОЗНАВАЕМОЙ: испортить строку до неузнаваемости — вернейший способ пройти суд,
#     читающий по образцу.
#
# Корейская цитата бывает четырёх видов, и все четыре объявлены: слово, частица, слово с
# частицей — и ТУРЕЦКОЕ слово рода «сосед клеит иначе» («evler», «kitaplar»), названное
# поимённо, чтобы не прошло любое латинское.
_ХАНГЫЛЬ = _re.compile(r"[\uac00-\ud7af]")
# ТУРЕЦКИЕ СЛОВА, ЦИТИРУЕМЫЕ ДОМОМ ПРИ СРАВНЕНИИ. Хангыля в них нет, и закон их не читает;
# объявлены они здесь, чтобы читатель видел ПОЛНЫЙ список чужой речи дома.
СОСЕДНИЕ = ("evler", "kitaplar")


def _чужое_в_цитате(тело):
    """Кусок корейской цитаты, не объявленный домом, — либо None."""
    х = тело.lstrip("*")
    if not _ХАНГЫЛЬ.search(х):
        return None
    if х in _ВСЕ_ЧАСТИЦЫ:
        return None
    for слово, *_ in СЛОВА:
        if х == слово:
            return None
        if х.startswith(слово) and х[len(слово):] in _ВСЕ_ЧАСТИЦЫ:
            return None
    return х


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        if _чужое_в_цитате(цитата) is not None:
            return True, False
        if not _СЛОВО_ЧАСТИЦА.search(цитата.lstrip("*")):
            continue
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:110])
            беды += 1
    мутантов = 0
    for показ in ПОКАЗЫ:
        порча = None
        for сл, час in _СЛОВО_ЧАСТИЦА.findall(показ):
            согл = _СОГЛАСНОЕ[сл]
            чужая = next(iter(_ПОСЛЕ_ГЛАСН if согл else _ПОСЛЕ_СОГЛ))
            порча = показ.replace(сл + час, сл + чужая, 1)
            break
        if not порча or порча == показ or порча in ПОКАЗЫ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:110])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    ложные = (
        "по-корейски «책가» — книга.",
        "по-корейски «나무이» — дерево.",
        "по-корейски «책를» — книгу.",
        "«*나무가» — так не говорят.",
    )
    for ложь in ложные:
        ПОКАЗЫ[ложь] = ("ru", "проба")
        try:
            if судить(ложь) != (True, False):
                print("  ЛОЖНАЯ СТРАНИЦА ПРОШЛА:", ложь[:100])
                беды += 1
        finally:
            del ПОКАЗЫ[ложь]
    написано = {род for _, род in ПОКАЗЫ.values()}
    if написано != set(РОДЫ):
        print(f"  РОДЫ РАЗОШЛИСЬ: обещано {sorted(РОДЫ)}, написано {sorted(написано)}")
        беды += 1
    for чужая in ("사전에는 책이 있고 이것은 이 집의 페이지가 아닙니다.",
                  "он выписал «책이» на поля, и это не страница дома."):
        if судить(чужая) != (False, False):
            print("  ЧУЖАЯ РЕЧЬ СУДИМА:", чужая[:100])
            беды += 1
    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, мутантов поймано {мутантов}, "
          f"слов {len(СЛОВА)}, пар частиц {len(ПАРЫ)}, бед {беды}")
    return беды


