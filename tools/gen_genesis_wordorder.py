#!/usr/bin/env python3
"""МЕСТО СКАЗУЕМОГО: порядок слов, показанный СЧЁТОМ, а не именем схемы.

    ПОРЯДОК, НАЗВАННЫЙ СЛОВОМ «SOV», НЕ УЧИТ НИЧЕМУ: имя схемы есть ярлык, который нечем
    проверить. Порядок, показанный СЧЁТОМ МЕСТА — «сказуемое есть слово 3 из 3», — читается
    и проверяется тем же способом, каким читается «0x1F means 1 × 16 + 15 = 31».

ЗАМЕР, ВСКРЫВШИЙ ДЫРУ (свод 382 829 строк, 07.09): слов «SOV», «SVO», «порядок слов»,
«word order» — НОЛЬ во всём своде. Двадцать девять языковых пластов живут, и ни одна страница
не говорит, ГДЕ в них стои́т сказуемое.

ДОМ НЕ ПРИНОСИТ НОВОГО ЗНАНИЯ О ЯЗЫКЕ. Он берёт предложения, УЖЕ написанные пластами, находит
в них глагол, УЖЕ объявленный пакетом, и называет его место числом. Проверяется это счётом
слов, и подмена числа делает страницу ложной.

    22 100 простых предложений с ровно одним объявленным глаголом живут в пластах; дом берёт
    из них выборку по языкам, и в ней сама собою видна разница порядков:

        ko  «저는 먹어요»        сказуемое — слово 2 из 2 (последнее)
        de  «ich sehe den hof»  сказуемое — слово 2 из 4 (второе)
        hu  «köszönök valamit»  сказуемое — слово 1 из 5 (первое)

СТРАНИЦА СРАВНЕНИЯ И ЕСТЬ ТА, ЧТО УЧИТ. Одиночная страница говорит о своём предложении;
страница, ставящая рядом язык с последним сказуемым и язык со вторым, говорит О ПОРЯДКЕ. Обе
половины её счётны, и потому она не мнение, а факт.
"""
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from layer import PASSES, emit  # noqa: E402

ЦЕЛЬ = "datasets/genesis_wordorder.txt"
ПАКЕТЫ = КОРЕНЬ / "tools" / "langpacks"
# ВЫБОРКА ОБЪЯВЛЕНА ЧИСЛОМ, А НЕ ВКУСОМ: сорок предложений на язык — выше LAW³ = 8 вчетверо
# и ниже того, чтобы дом заслонил собою пласты, из которых взят.
НА_ЯЗЫК = 40


def предложения():
    """(язык, предложение, глагол, место, всего) — по пластам, детерминированно."""
    вон = []
    for п in sorted(ПАКЕТЫ.glob("*.json")):
        пак = json.loads(п.read_text(encoding="utf-8"))
        я = пак.get("lang", п.stem)
        if пак.get("segmentation") == "longest-match":
            continue          # письмо без пробелов не режется на слова по пробелу
        глаголы = set()
        for имя, кл in (пак.get("morph_classes") or {}).items():
            if "verb" not in имя:
                continue
            for _л, формы in (кл.get("lexemes") or {}).items():
                глаголы |= {str(ф) for ф in формы}
        if not глаголы:
            continue
        слой = КОРЕНЬ / "datasets" / f"genesis_lang_{я}.txt"
        if not слой.is_file():
            continue
        свои = []
        for с in слой.read_text(encoding="utf-8").split("\n"):
            с = с.strip()
            # ОТКАЗ НЕ ЕСТЬ РЕЧЬ: строка, помеченная «¬», объявлена пластом КАК НЕВЕРНАЯ,
            # и называть в ней место сказуемого значило бы утверждать о ней как о речи.
            # Первая проба взяла их — «¬ أنا تكتب» вошло в выборку арабского.
            if not с or "¬" in с or "?" in с or "=" in с or any(зн.isdigit() for зн in с):
                continue
            слова = с.rstrip(".!").split()
            # ДВУСЛОВНОЕ ПРЕДЛОЖЕНИЕ НИЧЕГО НЕ ГОВОРИТ О ПОРЯДКЕ: в «я работаю» сказуемое
            # последнее у ВСЯКОГО языка, и дом, взявший такие, учил бы краткости, а не
            # порядку. Первая проба взяла их — и дала 892 «последних» из тысячи.
            if not (3 <= len(слова) <= 6):
                continue
            места = [i for i, w in enumerate(слова) if w.strip(".,!") in глаголы]
            if len(места) != 1:
                continue
            свои.append((я, " ".join(слова), слова[места[0]].strip(".,!"),
                         места[0] + 1, len(слова)))
        # ВЫБОРКА РОВНЫМ ШАГОМ, А НЕ ПЕРВЫЕ СОРОК: первые сорок строк пласта суть один вид
        # показа, и дом выучил бы вид, а не язык.
        if свои:
            шаг = max(1, len(свои) // НА_ЯЗЫК)
            вон.extend(свои[::шаг][:НА_ЯЗЫК])
    return вон


РЯД = предложения()
# СТРАНИЦЫ СРАВНЕНИЯ ЗДЕСЬ НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ (07.09, поймано глазом до записи).
#
# Первый замысел ставил рядом язык с последним сказуемым и язык со вторым — и назвал бы
# вьетнамский языком с сказуемым в конце: «anh ấy làm» есть слово 3 из 3. Но «anh ấy» —
# ПОДЛЕЖАЩЕЕ ИЗ ДВУХ СЛОВ, и вьетнамский порядок тут ровно тот же, что английский.
#
#     СЧЁТ СЛОВ НЕ ЗНАЕТ ГРАНИЦ ЧЛЕНОВ ПРЕДЛОЖЕНИЯ. Он честно говорит, ГДЕ стои́т слово, и
#     не вправе говорить, КАКОВ порядок: для второго нужно знать протяжённость подлежащего,
#     а её счёт слов не даёт.
#
# Потому дом называет МЕСТО и молчит о СХЕМЕ. Порядок виден из массы страниц — у корейского
# и тамильского сказуемое последнее во всех, у немецкого и русского ни в одной, — и это
# видит читатель, а не утверждает дом.


def pass_shows(pass_i):
    out = []
    for k, (я, с, гл, место, всего) in enumerate(РЯД):
        if k % len(PASSES) != pass_i:
            continue
        out.append(f"в предложении «{с}» сказуемое «{гл}» — слово {место} из {всего}.")
        out.append(f'in the sentence "{с}" the verb "{гл}" is word {место} of {всего}.')
        out.append(f"какое слово в «{с}» сказуемое? «{гл}» — слово {место} из {всего}.")
        out.append(f'which word in "{с}" is the verb? "{гл}" is word {место} of {всего}.')
    return out


def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
