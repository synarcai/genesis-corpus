def _смещение(город):
    return ГОРОДА[город][0]


def _г(город, язык):
    """Имя города в том падеже, какого требует рамка: русская ставит предложный."""
    return ГОРОДА[город][1] if язык == "ru" else ГОРОДА[город][2]


def _и(город, язык):
    """Имя города именительным — там, где предлога нет."""
    return город if язык == "ru" else ГОРОДА[город][2]


def _ч(n, язык):
    return rugram.форма("час", n) if язык == "ru" else by_count(n, "hours")


def _пояс(город):
    с = _смещение(город)
    return f"+{с}" if с > 0 else (str(с) if с < 0 else "+0")


def _чис(n):
    """Число письмом свода: минус есть знак «−» (U+2212), а не дефис."""
    return f"−{abs(n)}" if n < 0 else str(n)


def _запись(ha, d, итог):
    """«10 + 6 = 16» или «12 − 3 = 9» — знак берётся по СТОРОНЕ СВЕТА, а не по модулю.

    ЗНАК ЗАПИСИ ЕСТЬ ЧАСТЬ УТВЕРЖДЕНИЯ. Первая редакция писала всюду «−» и модуль разницы,
    и «10 − 6 = 16» прошло бы мимо всякого глаза, кроме разбора, — а разбор назвал его
    ложью, и был прав.
    """
    return f"{ha} {'−' if d > 0 else '+'} {abs(d)} = {_чис(итог)}"


