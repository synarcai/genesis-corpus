def _общее(A, B, ha, язык):
    d = _смещение(A) - _смещение(B)
    сырое = ha - d
    hb = сырое % 24
    return dict(A=_и(A, язык), B=_и(B, язык), Ап=_г(A, язык), Bп=_г(B, язык),
                sa=_пояс(A), sb=_пояс(B), d=abs(d), ha=ha, hb=hb, сырое=сырое,
                ч=_ч(abs(d), язык), чa=_ч(ha, язык), чb=_ч(hb, язык),
                сыроез=_чис(сырое),
                зап=_запись(ha, d, сырое))


def _безопасные_часы(A, B):
    """Два часа, при которых пересчёт не уходит за сутки ни разу."""
    d = _смещение(A) - _смещение(B)
    годны = [h for h in range(24) if 0 <= h - d <= 23]
    return (годны[1], годны[-2]) if len(годны) >= 4 else (годны[0], годны[-1])


