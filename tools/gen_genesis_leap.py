import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import leapforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_leap.txt"
ГРУППЫ = (("делится на четыре", "век не високосен", "четырёхсотый високосен",
           "не делится не високосен"),
          ("дней в году", "дней в феврале"),
          ("сколько в веке",),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
