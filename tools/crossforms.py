def страница(язык, i, форма="перекрёсток"):
    с = СЛОВА[язык]
    if форма.startswith("просьба"):
        просьбы = ПРОСЬБА[язык]
        если_вы = форма.endswith("_вы")
        if если_вы and len(просьбы) == 1:
            return None
        просьба = просьбы[1 if если_вы else 0]
        return f"{просьба} {страница(язык, i, 'перекрёсток')}"
    if форма.startswith("согласен"):
        рамки = СОГЛАСИЕ[язык]
        если_вы = форма.endswith("_вы")
        if если_вы and len(рамки) == 1:
            return None
        знак, имя, пары = ДЕЙСТВИЯ[i % len(ДЕЙСТВИЯ)]
        a, b = пары[(i // len(ДЕЙСТВИЯ)) % len(пары)]
        v = значение(знак, a, b)
        пр = с.get("пробел_перед_знаком", "")
        вопрос = рамки[1 if если_вы else 0].format(a=a, b=b, v=v, д=с[имя])
        if пр and not вопрос.endswith(" ?"):
            вопрос = вопрос[:-1] + пр + "?"
        return f"{вопрос} {ДА[язык]}, {a} {знак} {b} = {v}."
    if форма == "знаком":
        # THE QUESTION IN SIGNS (seventh band, 06.09: «ile jest 100 − 1?» — the person writes
        # the sign, and the house answered only the word «minus»)
        голова = с["головы"][i % len(с["головы"])]
        к = i // len(с["головы"])
        знак, имя, пары = ДЕЙСТВИЯ[к % len(ДЕЙСТВИЯ)]
        a, b = пары[(к // len(ДЕЙСТВИЯ)) % len(пары)]
        v = значение(знак, a, b)
        пр = с.get("пробел_перед_знаком", "")
        return f"{голова} {a} {знак} {b}{пр}? {a} {знак} {b} = {v}."
    if форма == "цепочка":
        голова = с["головы"][i % len(с["головы"])]
        ц = ЦЕПОЧКИ[(i // len(с["головы"])) % len(ЦЕПОЧКИ)]
        a, з1, b, слово, c_ = ц
        v1, v = цепочка_значение(ц)
        пр = с.get("пробел_перед_знаком", "")
        return f"{голова} {a} {з1} {b}, {ПОТОМ[язык]} {с[слово]} {c_}{пр}? {a} {з1} {b} = {v1}, {v1} {ЗНАК_СЛОВА[слово]} {c_} = {v}."
    if форма in ("согласен_знаком", "несогласен_знаком"):
        воп, да, нет = СОГЛАСИЕ_ЗНАКОМ[язык]
        a, b = СУММЫ_ЗНАКОМ[i % len(СУММЫ_ЗНАКОМ)]
        v = a + b
        if форма == "согласен_знаком":
            return f"{воп.format(a=a, b=b, w=v)} {да.format(a=a, b=b, v=v)}"
        return f"{воп.format(a=a, b=b, w=v + 1)} {нет.format(a=a, b=b, v=v)}"
    if форма == "старшинство":
        голова = с["головы"][i % len(с["головы"])]
        т4 = СТАРШИНСТВО[(i // len(с["головы"])) % len(СТАРШИНСТВО)]
        a, з, b, c_ = т4
        p, v = старшинство_значение(т4)
        пр = с.get("пробел_перед_знаком", "")
        сн, пт = ПОРЯДОК_СЛОВА[язык]
        return f"{голова} {a} {з} {b} × {c_}{пр}? {a} {з} {b} × {c_} = {v}: {сн} {b} × {c_} = {p}, {пт} {a} {з} {p} = {v}."
    if форма == "тройка":
        голова = с["головы"][i % len(с["головы"])]
        т3 = ТРОЙКИ[(i // len(с["головы"])) % len(ТРОЙКИ)]
        a, з1, b, з2, c = т3
        пр = с.get("пробел_перед_знаком", "")
        return f"{голова} {a} {з1} {b} {з2} {c}{пр}? {a} {з1} {b} {з2} {c} = {тройка_значение(т3)}."
    if форма == "словом":
        # тот же перекрёсток, но числа вопроса — СЛОВОМ пакета; кузница цифрами
        голова = с["головы"][i % len(с["головы"])]
        к = i // len(с["головы"])
        знак, имя, пары = ДЕЙСТВИЯ[к % len(ДЕЙСТВИЯ)]
        a, b = пары[(к // len(ДЕЙСТВИЯ)) % len(пары)]
        A, B = числом(язык, a), числом(язык, b)
        if A is None or B is None:
            return None
        v = значение(знак, a, b)
        пр = с.get("пробел_перед_знаком", "")
        return f"{голова} {A} {с[имя]} {B}{пр}? {a} {знак} {b} = {v}."
    if форма == "именем":
        знак, имя, пары = ДЕЙСТВИЯ[i % len(ДЕЙСТВИЯ)]
        a, b = пары[(i // len(ДЕЙСТВИЯ)) % len(пары)]
        v = значение(знак, a, b)
        return f"{ИМЕНА[язык][имя].format(a=a, b=b)} {a} {знак} {b} = {v}."
    if форма == "именем2":
        знак, имя, пары = ДЕЙСТВИЯ[i % len(ДЕЙСТВИЯ)]
        a, b = пары[(i // len(ДЕЙСТВИЯ)) % len(пары)]
        v = значение(знак, a, b)
        поверхности = ИМЕНА2.get(язык, {}).get(имя, ())
        if not поверхности:
            return None
        return f"{поверхности[(i // (len(ДЕЙСТВИЯ) * len(пары))) % len(поверхности)].format(a=a, b=b)} {a} {знак} {b} = {v}."
    голова = с["головы"][i % len(с["головы"])]
    к = i // len(с["головы"])
    знак, имя, пары = ДЕЙСТВИЯ[к % len(ДЕЙСТВИЯ)]
    a, b = пары[(к // len(ДЕЙСТВИЯ)) % len(пары)]
    v = значение(знак, a, b)
    # ПРОБЕЛ ПЕРЕД ВОПРОСИТЕЛЬНЫМ ЗНАКОМ — строй французского, объявленный,
    # а не угаданный; язык, где его нет, поля не держит
    пр = с.get("пробел_перед_знаком", "")
    return f"{голова} {a} {с[имя]} {b}{пр}? {a} {знак} {b} = {v}."


def _показы():
    сколько = 2 * len(ДЕЙСТВИЯ) * len(ДЕЙСТВИЯ[0][2])
    вон = {страница(язык, i): (язык, "перекрёсток") for язык in ЯЗЫКИ for i in range(сколько)}
    именем = len(ДЕЙСТВИЯ) * len(ДЕЙСТВИЯ[0][2])
    вон.update({страница(язык, i, "именем"): (язык, "именем")
                for язык in ЯЗЫКИ for i in range(именем)})
    for язык in ЯЗЫКИ:
        for i in range(2 * именем):
            с = страница(язык, i, "именем2")
            if с is not None:
                вон[с] = (язык, "именем")
    for форма in ("согласен", "согласен_вы"):
        for язык in ЯЗЫКИ:
            for i in range(именем):
                с = страница(язык, i, форма)
                if с is not None:
                    вон[с] = (язык, форма)
    for язык in ЯЗЫКИ:
        for i in range(2 * len(ТРОЙКИ)):
            вон[страница(язык, i, "тройка")] = (язык, "тройка")
        for i in range(2 * len(СТАРШИНСТВО)):
            вон[страница(язык, i, "старшинство")] = (язык, "старшинство")
        for i in range(2 * len(ЦЕПОЧКИ)):
            вон[страница(язык, i, "цепочка")] = (язык, "цепочка")
        for i in range(len(СУММЫ_ЗНАКОМ)):
            вон[страница(язык, i, "согласен_знаком")] = (язык, "согласен_знаком")
            вон[страница(язык, i, "несогласен_знаком")] = (язык, "несогласен_знаком")
    for форма in ("просьба", "просьба_вы", "словом", "знаком"):
        for язык in ЯЗЫКИ:
            for i in range(сколько):
                с = страница(язык, i, форма)
                if с is not None:
                    вон[с] = (язык, форма)
    return вон


ПОКАЗЫ = _показы()


