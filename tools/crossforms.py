def числом(язык, n):
    """The numeral of n as the pack declares it, or None."""
    if язык not in _ЧИСЛА:
        import json
        п = json.loads((_ПАКЕТЫ / f"{язык}.json").read_text(encoding="utf-8"))
        _ЧИСЛА[язык] = {int(k): str(v) for k, v in (п.get("numerals") or {}).items() if str(k).isdigit()}
    return _ЧИСЛА[язык].get(n)


def числа_словом(язык):
    числом(язык, 0)
    return _ЧИСЛА[язык]


def значение(знак, a, b):
    return {"+": a + b, "−": a - b, "×": a * b, "÷": a // b}[знак]


