def значение(знак, a, b):
    # ЛЕНИВО: словарь всех четырёх делил бы на ноль и при вычитании («5 − 0»)
    if знак == "+":
        return a + b
    if знак == "−":
        return a - b
    if знак == "×":
        return a * b
    return a // b


