#!/usr/bin/env python3
"""ДОМ МАСШТАБА — ЧЕМ БОЛЬШЕ ЧИСЛО В МАСШТАБЕ, ТЕМ МЕЛЬЧЕ КАРТА.

    МАСШТАБА КАРТЫ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 245 мирам показов: «масштаб
    карты», «scale of the map», запись «1 : 1000» — НОЛЬ. Слово «масштаб» встречается 43 раза и
    всё в ПРОЗЕ: у Даля («жезл размерный»), в определениях да в мирах физики о шкале градусов.

    СЛОВО ЕСТЬ, ДЕЛА НЕТ: свод умеет сказать, ЧТО ТАКОЕ масштаб, и ни разу не переводит по нему
    длину.

СЕМНАДЦАТАЯ ЛОВУШКА РЯДА, И ОНА РОДНАЯ СЕСТРА ПЕРВОЙ: МАСШТАБ 1 : 2000 МЕЛЬЧЕ МАСШТАБА 1 : 1000,
ХОТЯ 2000 БОЛЬШЕ 1000. Та же обратность, что у долей — знаменатель растёт, доля убывает, — только
названная другим словом и живущая на карте.

    ОДНА ОБРАТНОСТЬ, ВСТРЕЧЕННАЯ В ДВУХ ОБЛАСТЯХ, ЕСТЬ ОДИН ЗАКОН, А НЕ ДВА СОВПАДЕНИЯ.

ЧЕТЫРЕ РОДА:

    на землю    масштаб 1 : 1000, и 3 сантиметра на карте суть 30 метров на земле:
                3 × 1000 = 3000, и 3000 ÷ 100 = 30.
    на карту    масштаб 1 : 1000, и 50 метров на земле суть 5 сантиметров на карте:
                50 × 100 = 5000, и 5000 ÷ 1000 = 5.                       ← ОБРАТНЫЙ ХОД
    мельче      масштаб 1 : 2000 мельче масштаба 1 : 1000, хотя 2000 больше 1000:
                4000 ÷ 1000 = 4, и 4000 ÷ 2000 = 2.                       ← ЛОВУШКА
    во сколько  на карте масштаба 1 : 1000 всякая длина уменьшена в 1000 раз:
                7000 ÷ 1000 = 7.                                          ← ЧТО ЗНАЧИТ ЗАПИСЬ

ПЕРВЫЙ И ВТОРОЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО НАПРАВЛЕНИЮ ХОДА: те же числа, тот же масштаб, и
разница в одном месте — умножают на масштаб или делят на него. Порознь читатель выучил бы одно
направление и застрял в обратной задаче.

ЧЕТВЁРТЫЙ РОД ГОВОРИТ, ЧТО ЗНАЧИТ САМА ЗАПИСЬ, и без него три первых были бы приёмами без
понятия: «1 : 1000» есть не пара чисел, а ОТНОШЕНИЕ — то самое, что дом пропорции показал днём
раньше. Масштаб есть пропорция, приложенная к земле.

ЕДИНИЦЫ ПЕРЕВОДЯТСЯ ЧЕРЕЗ СТО, И ЭТО ПОКАЗАНО СЧЁТОМ, А НЕ ОБЪЯВЛЕНО: «3000 ÷ 100 = 30» стои́т
на странице, ибо мир единиц уже объявил «один метр равно 100 сантиметров», и дом не заводит
второго объявления там, где свод держит первое.

    python3 tools/mapscaleforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётные формы мер объявлены там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("на землю", "на карту", "мельче", "во сколько")


def форма(язык, ключ, n):
    if язык == "en":
        англ = {"метр": ("metre", "metres"), "сантиметр": ("centimetre", "centimetres"),
                "раз": ("time", "times")}[ключ]
        return англ[0] if n == 1 else англ[1]
    return rugram.форма(ключ, n)


РАМКИ = {
    "ru": {
        "на землю": "масштаб 1 : {m}, и {c} {сант} на карте суть {земля} {метр} на земле: {c} × {m} = {всего}, и {всего} ÷ 100 = {земля}.",
        "на карту": "масштаб 1 : {m}, и {земля} {метр} на земле суть {c} {сант} на карте: {земля} × 100 = {всего}, и {всего} ÷ {m} = {c}.",
        "мельче": "масштаб 1 : {m2} мельче масштаба 1 : {m}, хотя {m2} больше {m}: {всего} ÷ {m} = {c}, и {всего} ÷ {m2} = {c2}.",
        "во сколько": "на карте масштаба 1 : {m} всякая длина уменьшена в {m} {раз}: {всего} ÷ {m} = {c}.",
    },
    "en": {
        "на землю": "a scale of 1 : {m}, and {c} {сант} on the map are {земля} {метр} on the ground: {c} × {m} = {всего}, and {всего} ÷ 100 = {земля}.",
        "на карту": "a scale of 1 : {m}, and {земля} {метр} on the ground are {c} {сант} on the map: {земля} × 100 = {всего}, and {всего} ÷ {m} = {c}.",
        "мельче": "a scale of 1 : {m2} is smaller than a scale of 1 : {m}, although {m2} is greater than {m}: {всего} ÷ {m} = {c}, and {всего} ÷ {m2} = {c2}.",
        "во сколько": "on a map of scale 1 : {m} every length is reduced {m} {раз}: {всего} ÷ {m} = {c}.",
    },
}
ПУСТО = dict(m=0, m2=0, c=0, c2=0, земля=0, всего=0, сант="", метр="", раз="")

# МАСШТАБЫ ВЗЯТЫ ХОДОВЫЕ, И ВСЕ КРАТНЫ СОТНЕ: иначе перевод в метры дал бы дробь, и дом
# заговорил бы о десятичной записи — предмете соседа.
МАСШТАБЫ = (100, 200, 250, 500, 1000, 2000, 2500, 5000, 10000)


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for m in МАСШТАБЫ:
            for c in range(1, 13):
                всего = c * m
                if всего % 100:
                    continue
                земля = всего // 100
                общ = dict(ПУСТО, m=m, c=c, земля=земля, всего=всего,
                           сант=форма(язык, "сантиметр", c),
                           метр=форма(язык, "метр", земля),
                           раз=форма(язык, "раз", m))
                вон[рамки["на землю"].format(**общ)] = (язык, "на землю")
                вон[рамки["на карту"].format(**общ)] = (язык, "на карту")
                # РЯД ВЫРАВНЕН ЗАМЕРОМ: при отборе каждой третьей длины род «во сколько»
                # давал 34 страницы против 102 у перевода — перекос втрое.
                вон[рамки["во сколько"].format(**общ)] = (язык, "во сколько")
                # МЕЛЬЧЕ: второй масштаб вдвое крупнее числом и вдвое мельче делом.
                m2 = 2 * m
                if всего % m2 == 0 and m2 <= 20000 and c % 2 == 0:
                    вон[рамки["мельче"].format(
                        **dict(общ, m2=m2, c2=всего // m2))] = (язык, "мельче")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_БОЛЬШЕ = re.compile(r"(?<![/\d:])(\d+) (?:больше|is greater than) (\d+)(?![/\d])")
_МЕЛЬЧЕ = re.compile(r"1 : (\d+) (?:мельче|is smaller than)(?: масштаба| a scale of)? 1 : (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    # ЛОВУШКА ОБЯЗАНА ЛОВИТЬ: мельче тот масштаб, у которого ЧИСЛО больше, а изображение
    # короче — и обе половины сверяются числами страницы.
    for m2, m in _МЕЛЬЧЕ.findall(с):
        if int(m2) <= int(m):
            return True, False
        частные = _ЧАСТНОЕ.findall(с)
        if len(частные) < 2 or int(частные[0][2]) <= int(частные[1][2]):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:92]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    мл = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "мельче")
    зм = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "на землю")
    for страница, слово, куда in ((мл, "мельче", "мельч"), (зм, "масштаб", "масшта")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(мл + " " + мл)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # СЧЁТНАЯ ФОРМА БЕРЁТСЯ У ЯЗЫКА: «1 сантиметр», «2 сантиметра», «5 сантиметров».
    for кусок in ("1 сантиметр ", "2 сантиметра ", "5 сантиметров "):
        if not any(кусок in с for с in ПОКАЗЫ):
            беды.append(f"СЧЁТНАЯ ФОРМА НЕ ПОКАЗАНА: {кусок.strip()}")
    # СЛОВА ДО ПОСЛЕДНЕГО ДВОЕТОЧИЯ, РАВЕНСТВА ПОСЛЕ.
    for с in ПОКАЗЫ:
        хвост = с.rsplit(":", 1)[1]
        if re.search(r"[A-Za-zА-Яа-яЁё]{3,}", хвост.replace("and", "").replace("и", "")):
            беды.append(f"СЛОВА ПОСЛЕ ДВОЕТОЧИЯ: {с[:70]}")
            break
    print(f"МАСШТАБ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
