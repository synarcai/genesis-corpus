ЯЗЫКИ = tuple(ГОЛОВЫ)
ФОРМЫ = ("задание", "задание_вопрос", "задание_именем", "задание_словом")

for _яз in ЯЗЫКИ:
    assert _яз in C.СЛОВА, _яз
    assert len(ГОЛОВЫ[_яз]) >= 2, _яз
    assert _яз in ВОПРОСЫ, _яз
    for _, _имя, _ in C.ДЕЙСТВИЯ:
        assert _имя in ИМЕНА_ВИН[_яз], (_яз, _имя)


def страница(язык, i, форма="задание"):
    головы = ГОЛОВЫ[язык]
    голова = головы[i % len(головы)]
    к = i // len(головы)
    знак, имя, пары = C.ДЕЙСТВИЯ[к % len(C.ДЕЙСТВИЯ)]
    a, b = пары[(к // len(C.ДЕЙСТВИЯ)) % len(пары)]
    v = C.значение(знак, a, b)
    хвост = f"{a} {знак} {b} = {v}."
    if форма == "задание_именем":
        return f"{голова} {ИМЕНА_ВИН[язык][имя].format(a=a, b=b)}. {хвост}"
    if форма == "задание_словом":
        # ЧИСЛО СЛОВОМ ПАКЕТА (карта holon на четвёртой точке, 05.09: клетки
        # «calculate/compute/find × word», «вычисли/найди/посчитай × слово» пусты).
        # Числительное, которого пакет не объявил, страницы не пишет.
        A, B = C.числом(язык, a), C.числом(язык, b)
        if A is None or B is None:
            return None
        return f"{голова} {A} {C.СЛОВА[язык][имя]} {B}. {хвост}"
    если_вопрос = f" {ВОПРОСЫ[язык]}" if форма == "задание_вопрос" else ""
    return f"{голова} {a} {C.СЛОВА[язык][имя]} {b}.{если_вопрос} {хвост}"


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        сколько = len(ГОЛОВЫ[язык]) * len(C.ДЕЙСТВИЯ) * len(C.ДЕЙСТВИЯ[0][2])
        for форма in ФОРМЫ:
            for i in range(сколько):
                с = страница(язык, i, форма)
                if с is not None:
                    вон[с] = (язык, форма)
    return вон


ПОКАЗЫ = _показы()


def main():
    поймано = 0
    for язык in ЯЗЫКИ:
        print(f"  {язык}: {страница(язык, 0)} | {страница(язык, 5)}")
        с = C.СЛОВА[язык]
        г = ГОЛОВЫ[язык][0]
        # МУТАНТЫ: неверное значение; слово и знак о РАЗНЫХ действиях; числа
        # задания и ответа разные
        мутанты = (f"{г} 17 {с['плюс']} 25. 17 + 25 = 43.",
                   f"{г} 17 {с['минус']} 25. 17 + 25 = 42.",
                   f"{г} 17 {с['плюс']} 25. 18 + 25 = 43.")
        for м in мутанты:
            поймано += 0 if м in ПОКАЗЫ else 1
    print(f"  мутантов вне показов: {поймано} из {3 * len(ЯЗЫКИ)}")
    print(f"  дом пишет показов: {len(ПОКАЗЫ)} (языков {len(ЯЗЫКИ)}, голов 2, "
          f"действий {len(C.ДЕЙСТВИЯ)})")
    return 0


