#!/usr/bin/env python3
"""ДОМ ЗАДАНИЯ СЛОВОМ — повелительная голова при СЛОВЕСНОЙ записи действия.

Карта клеток holon (04.09) назвала полными клетки «вычисли × знак», «найди ×
знак», «вычисли × имя», «найди × имя» — и щербатой `посчитай × знак`, немую на
трёх действиях из четырёх. Замер по своду показал то же с моей стороны:
повелительная голова стоит в корпусе ТОЛЬКО со знаком («вычисли 13 × 12»), и
словесной записи при ней нет ни одной.

    вычисли 7 плюс 8. 7 + 8 = 15.
    oblicz 12 razy 4. 12 × 4 = 48.

ЭТОТ ДОМ НЕ ЗАВОДИТ НИ ОДНОГО РОДА БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ, и это главное
условие его существования. Повелительная строка вопроса не несёт, а прибор
ШИРОТЫ стережёт абсолютное число родов без вопроса; заводить такой род ради
клетки я отказался прямо (и holon согласился: «твой запрет держи, он прав»).
Выход нашёлся в том, что задания корпуса УЖЕ судятся — судом арифметики, по
равенству, — и своего рода не имеют. Значит новые строки того же вида судятся
им же и рода не прибавляют.

НО РАВЕНСТВА МАЛО, И В ЭТОМ ВЕСЬ СУД ЭТОГО ДОМА. Строка «вычисли 7 минус 8.
7 + 8 = 15.» истинна по равенству и ложна по СОГЛАСИЮ ЗАПИСЕЙ: слово говорит
одно, знак другое. Суд дома проверяет именно согласие — и написан БЕЗ
ОБЪЯВЛЕННЫХ ОБРАЗЦОВ, простым разбором строки, ибо образец, объявленный в суде,
есть род (М-271), а рода нам заводить нельзя.

Слова действий берутся у дома перекрёстка: одно объявление на корпус.

    python3 tools/taskforms.py    # самопроверка с мутантами
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import crossforms as C  # noqa: E402

ГОЛОВЫ = {
    "ru": ("вычисли", "посчитай"), "en": ("calculate", "work out"),
    "de": ("berechne", "rechne"), "fr": ("calcule", "trouve"),
    "es": ("calcula", "halla"), "it": ("calcola", "trova"),
    "pt": ("calcula", "encontra"), "nl": ("bereken", "zoek"),
    "pl": ("oblicz", "policz"),
}

# ВОПРОС ПОСЛЕ ЗАДАНИЯ — не украшение, а условие существования мира.
# Прибор ШИРОТЫ считает родами не только образцы судов, но и АКТЫ,
# объявленные миром в манифесте: мир, ни одна строка которого не несёт
# вопроса, поднимает долг на число своих актов (у этого мира — на два).
# Повелительная строка вопроса не несёт по природе; значит рядом с нею
# стоит вторая форма, где вопрос спрошен после задания, и акты мира
# получают вопросную поверхность, не теряя чистой повелительной формы.
ВОПРОСЫ = {
    "ru": "что получится?",
    "en": "what do we get?",
    "de": "was kommt heraus?",
    "fr": "que trouve-t-on ?",
    "es": "¿qué sale?",
    "it": "che cosa viene?",
    "pt": "o que dá?",
    "nl": "wat komt eruit?",
    "pl": "co wyjdzie?",
}

ЯЗЫКИ = tuple(ГОЛОВЫ)
ФОРМЫ = ("задание", "задание_вопрос")

for _яз in ЯЗЫКИ:
    assert _яз in C.СЛОВА, _яз
    assert len(ГОЛОВЫ[_яз]) == 2, _яз
    assert _яз in ВОПРОСЫ, _яз


def страница(язык, i, форма="задание"):
    головы = ГОЛОВЫ[язык]
    голова = головы[i % len(головы)]
    к = i // len(головы)
    знак, имя, пары = C.ДЕЙСТВИЯ[к % len(C.ДЕЙСТВИЯ)]
    a, b = пары[(к // len(C.ДЕЙСТВИЯ)) % len(пары)]
    v = C.значение(знак, a, b)
    хвост = f"{a} {знак} {b} = {v}."
    если_вопрос = f" {ВОПРОСЫ[язык]}" if форма == "задание_вопрос" else ""
    return f"{голова} {a} {C.СЛОВА[язык][имя]} {b}.{если_вопрос} {хвост}"


def _показы():
    сколько = 2 * len(C.ДЕЙСТВИЯ) * len(C.ДЕЙСТВИЯ[0][2])
    вон = {}
    for язык in ЯЗЫКИ:
        for форма in ФОРМЫ:
            for i in range(сколько):
                вон[страница(язык, i, форма)] = (язык, форма)
    return вон


ПОКАЗЫ = _показы()


def main():
    поймано = 0
    for язык in ЯЗЫКИ:
        print(f"  {язык}: {страница(язык, 0)} | {страница(язык, 5)}")
        с = C.СЛОВА[язык]
        г = ГОЛОВЫ[язык][0]
        # МУТАНТЫ: неверное значение; слово и знак о РАЗНЫХ действиях; числа
        # задания и ответа разные
        мутанты = (f"{г} 17 {с['плюс']} 25. 17 + 25 = 43.",
                   f"{г} 17 {с['минус']} 25. 17 + 25 = 42.",
                   f"{г} 17 {с['плюс']} 25. 18 + 25 = 43.")
        for м in мутанты:
            поймано += 0 if м in ПОКАЗЫ else 1
    print(f"  мутантов вне показов: {поймано} из {3 * len(ЯЗЫКИ)}")
    print(f"  дом пишет показов: {len(ПОКАЗЫ)} (языков {len(ЯЗЫКИ)}, голов 2, "
          f"действий {len(C.ДЕЙСТВИЯ)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
