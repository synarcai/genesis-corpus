#!/usr/bin/env python3
"""ЕДИНИЦЫ: ОДИН дом отношений, и приставка в нём — ЗАКОН, а не список.

Отношения единиц жили в ТРЁХ домах сразу: `gen_genesis_conversions.py`
объявлял восемь фактов, `gen_genesis_units.py` — семь своих (повторив
два чужих и заведя ТРЕТЬЮ копию русского согласования, от которой
сосед прямо предостерегал), а `gen_genesis_physics.py` держал пять
строк приставок написанными от руки. Три дома одного знания расходятся
в тот день, когда тронут любой из них.

ЗДЕСЬ ОДИН ДОМ И ОДИН ЗАКОН. Приставка СИ не есть пять фактов о метре
— она есть множитель, приложимый к ЛЮБОЙ базовой единице; «километр»
выводится, а не называется. Именованные отношения (сутки — часы, доллар
— центы) выводу не поддаются и объявлены фактами, каждый истинен.

ОТНОШЕНИЯ СУТЬ РЁБРА ГРАФА, А НЕ СТОЛБЕЦ ВЕСОВ. Год считается
месяцами, а месяц не есть постоянное число секунд: единого основания
для всех единиц не существует, и попытка свести их к одному весу
лгала бы. Суд ПРОХОДИТ путь и перемножает рёбра — то же исполнение
утверждения, каким суд сортировки пересортировывает список.
"""

import json
import pathlib
import sys
from fractions import Fraction

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from langpack import count_form_index  # noqa: E402

# Базовая единица: английские написания С ИМЕНАМИ (британское и
# американское — оба живут в корпусе и оба истинны) и русские формы
# один / два-четыре / пять. ПИСЬМО НАЗЫВАЕТСЯ, А НЕ НУМЕРУЕТСЯ:
# «второй вариант» у метра американский, а у грамма — британский, и
# порядковый выбор молча дал бы «grammes» там, где нужен «grams».
БАЗА = {
    "metre": ({"brit": ("metre", "metres"),
               "amer": ("meter", "meters")},
              ("метр", "метра", "метров")),
    "gram": ({"amer": ("gram", "grams"),
              "brit": ("gramme", "grammes")},
             ("грамм", "грамма", "граммов")),
    "second": ({"amer": ("second", "seconds")},
               ("секунда", "секунды", "секунд")),
}

# Приставка: английская, русская, множитель. ЗАКОН, приложимый ко
# всякой базовой единице, — оттого их три, а не пятнадцать фактов.
ПРИСТАВКИ = (
    ("kilo", "кило", 1000),
    ("centi", "санти", Fraction(1, 100)),
    ("milli", "милли", Fraction(1, 1000)),
)

# Именованное отношение: (что, в чём, сколько). Ни одно не выводится
# приставкой, и каждое названо фактом.
НАЗВАННЫЕ = (
    ("day", "hour", 24),
    ("hour", "minute", 60),
    ("minute", "second", 60),
    ("week", "day", 7),
    ("year", "month", 12),
    ("dollar", "cent", 100),
    ("foot", "inch", 12),
    ("dozen", "item", 12),
)

# Формы единиц, у которых нет приставочного вывода. Русский
# именительный объявлен ОТДЕЛЬНО, а не отрезан от предложного: форму
# нельзя получить усечением, её называют (шрам слоя конверсий —
# «году — это мера»).
ФОРМЫ = {
    # СУТКИ — ТА ЖЕ ЕДИНИЦА, ЧТО ДЕНЬ, И НЕ ФОРМА ЕГО: у суток нет
    # счётного единственного, и вывести их из «дня» нельзя — их зовут.
    "day": ({"amer": ("day", "days")},
            ("день", "дня", "дней", "сутки")),
    "hour": ({"amer": ("hour", "hours")}, ("час", "часа", "часов")),
    "minute": ({"amer": ("minute", "minutes")},
               ("минута", "минуты", "минут")),
    "week": ({"amer": ("week", "weeks")}, ("неделя", "недели", "недель")),
    "month": ({"amer": ("month", "months")},
              ("месяц", "месяца", "месяцев")),
    "year": ({"amer": ("year", "years")}, ("год", "года", "лет")),
    "dollar": ({"amer": ("dollar", "dollars")},
               ("доллар", "доллара", "долларов")),
    "cent": ({"amer": ("cent", "cents")}, ("цент", "цента", "центов")),
    "foot": ({"amer": ("foot", "feet")}, ("фут", "фута", "футов")),
    "inch": ({"amer": ("inch", "inches")}, ("дюйм", "дюйма", "дюймов")),
    "dozen": ({"amer": ("dozen", "dozens")},
              ("дюжина", "дюжины", "дюжин")),
    "item": ({"amer": ("item", "items")}, ("штука", "штуки", "штук")),
}

# ПРЕДЛОЖНЫЙ ПАДЕЖ НАЗВАН, А НЕ ВЫВЕДЕН: «в сутках», «в году» —
# русская форма не получается приписыванием предлога к именительному.
# Здесь же живёт имя единицы, которым её зовёт слой конверсий: у
# суток нет счётного единственного, и «сутки» — не форма «дня».
В_ЧЁМ = {
    "day": ("в сутках", "сутки"),
    "hour": ("в часе", "час"),
    "minute": ("в минуте", "минута"),
    "week": ("в неделе", "неделя"),
    "year": ("в году", "год"),
    "dollar": ("в долларе", "доллар"),
    "foot": ("в футе", "фут"),
    "kilometre": ("в километре", "километр"),
}

_RU = json.loads((pathlib.Path(__file__).resolve().parent
                  / "langpacks/ru.json").read_text(encoding="utf-8"))
_ПРАВИЛО = {"forms": ["one", "few", "many"],
            "count_agreement": _RU["count_agreement"]}


def _собрать():
    """(формы единиц, рёбра отношений) — вывод, а не список."""
    формы = dict(ФОРМЫ)
    рёбра = {(а, б): Fraction(к) for а, б, к in НАЗВАННЫЕ}
    for основа, (en, ru) in БАЗА.items():
        формы[основа] = (en, ru)
        for пр, пр_ru, множитель in ПРИСТАВКИ:
            имя = пр + основа
            формы[имя] = ({п: tuple(пр + ф for ф in пара)
                           for п, пара in en.items()},
                          tuple(пр_ru + ф for ф in ru))
            # РЕБРО ИДЁТ ОТ БОЛЬШЕЙ ЕДИНИЦЫ К МЕНЬШЕЙ: «1 километр =
            # 1000 метров» и «1 метр = 100 сантиметров» суть одно
            # знание, прочтённое с двух сторон, и граф проходится в
            # обе.
            if множитель >= 1:
                рёбра[(имя, основа)] = Fraction(множитель)
            else:
                рёбра[(основа, имя)] = 1 / Fraction(множитель)
    return формы, рёбра


ФОРМЫ_ВСЕХ, РЁБРА = _собрать()

# поверхность → каноническое имя единицы
ПОВЕРХНОСТЬ = {}
for _имя, (_en, _ru) in ФОРМЫ_ВСЕХ.items():
    for _пара in _en.values():
        for _ф in _пара:
            ПОВЕРХНОСТЬ[_ф] = _имя
    for _ф in _ru:
        ПОВЕРХНОСТЬ[_ф] = _имя


def англ(имя, много=False, письмо="amer"):
    """Английская форма единицы данным письмом (brit/amer)."""
    пары = ФОРМЫ_ВСЕХ[имя][0]
    пара = пары.get(письмо) or next(iter(пары.values()))
    return пара[1 if много else 0]


def рус(имя, счёт=1):
    """Русская форма единицы при данном счёте — по закону ПАКЕТА.

    Правило 1 / 2-4 / 5+ с исключением подростков живёт в
    `langpacks/ru.json` как данные. Здесь была бы ТРЕТЬЯ его копия
    (первая в движке, вторая в генераторе единиц) — а копия закона
    расходится с оригиналом в день, когда тронут любую.
    """
    return ру_форма(ФОРМЫ_ВСЕХ[имя][1], счёт)


def ру_форма(формы, счёт):
    """Форма из тройки один/два-четыре/пять по закону пакета."""
    return формы[count_form_index(_RU, _ПРАВИЛО, счёт)]


def единица(слово):
    """Каноническое имя единицы по любой её форме, или None."""
    return ПОВЕРХНОСТЬ.get(слово.strip().lower())


def отношение(что, в_чём):
    """Сколько «в_чём» в одном «что» — точной дробью, или None.

    Путь ищется обходом в ширину по объявленным рёбрам в обе стороны:
    отношение есть СВЯЗЬ, а не запись в таблице, и «1 километр = 100000
    сантиметров» истинно, хотя такого факта никто не объявлял.
    """
    if что == в_чём:
        return Fraction(1)
    видано = {что}
    очередь = [(что, Fraction(1))]
    while очередь:
        узел, вес = очередь.pop(0)
        for (а, б), к in РЁБРА.items():
            for сосед, шаг in ((б, вес * к) if а == узел else
                               (а, вес / к) if б == узел else (None, None),):
                if сосед is None or сосед in видано:
                    continue
                if сосед == в_чём:
                    return шаг
                видано.add(сосед)
                очередь.append((сосед, шаг))
    return None
