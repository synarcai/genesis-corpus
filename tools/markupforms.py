def формулы(шаг):
    """LaTeX-арифметика: всё вычислено, ни одно число не написано."""
    вон = []
    for i in range(len(СЛОВА)):
        a, b = (i * 2 + шаг) % 12 + 2, (i * 3 + шаг) % 9 + 1
        # ЗНАК И СЛОВО — ДВЕ ПОВЕРХНОСТИ ОДНОГО ДЕЙСТВИЯ, И ОБЕ ПОЛОВИНЫ
        # МИРА ДОЛЖНЫ ЗНАТЬ ОБЕ (закон, названный holon 03.09 на мире
        # линала; прибор scripts/sign_word.py нашёл здесь последнее место в
        # своде). Сложение читалось ТОЛЬКО по-русски, вычитание ТОЛЬКО
        # по-английски: читатель одной половины видел действие лишь знаком
        # и не мог узнать в слове ту же цепочку.
        вон.append((f"$ {a} + {b} = {a + b} $.",
                    f"{a} плюс {b} равно {a + b}."))
        вон.append((f"{a} plus {b} is {a + b}.",
                    f"$ {a} - {b} = {a - b} $."))
        вон.append((f"{a} minus {b} is {a - b}.",
                    f"{a} минус {b} равно {a - b}."))
        с = (i + шаг) % 3 + 2
        вон.append((f"$ {с}^{2} = {с ** 2} $.",
                    f"{с} в степени 2 равно {с ** 2}."))
        квадрат = ((i + шаг) % 8 + 2) ** 2
        вон.append((f"$ \\sqrt{{{квадрат}}} = {int(квадрат ** 0.5)} $.",
                    f"корень из {квадрат} равен {int(квадрат ** 0.5)}."))
        верх = (i + шаг) % 4 + 2
        сумма = верх * (верх + 1) // 2
        вон.append((f"$ \\sum_{{i=1}}^{{{верх}}} i = {сумма} $.",
                    f"сумма i от 1 до {верх} равно {сумма}."))
        ч, зн = (i + шаг) % 8 + 1, (i * 2 + шаг) % 8 + 2
        доля = Fraction(ч, зн)
        вон.append((f"$ \\frac{{{ч}}}{{{зн}}} $ читается как "
                    f"{ч} делить {зн}.",
                    f"$ \\frac{{{ч}}}{{{зн}}} = "
                    f"\\frac{{{доля.numerator}}}{{{доля.denominator}}} $."))
        # ВОПРОСНАЯ ПОВЕРХНОСТЬ И ОТКАЗ — оба на родах, которые СУД
        # АЛГОРИТМОВ уже читает, и потому судятся тем же судом, что и
        # утверждение. Вопрос ПОРОЖДЁН ответом: числа вопроса суть
        # начальный отрезок чисел ответа (`tools/asking.py`), и порча
        # любого из них рвёт пару.
        вон.append((f"чему равно {с} в степени 2? "
                    f"{с} в степени 2 равно {с ** 2}.",
                    f"what is {с} to the power 2? "
                    f"{с} to the power 2 is {с ** 2}."))
        # ОТКАЗ С ОСНОВАНИЕМ: за концом ряда ничего нет, и суд считает
        # длину сам, а не верит слову «нет». Ряд взят свой же — числа,
        # уже стоящие в формулах этого прохода.
        ряд = list(range(a, a + 5))
        печать = " ".join(str(x) for x in ряд)
        место = len(ряд) + 1 + (i % 3)
        вон.append((f"на месте {место} нет ничего: в списке {печать} "
                    f"всего {len(ряд)} элементов.",
                    f"no item at place {место}: the list {печать} has "
                    f"{len(ряд)} {by_count(len(ряд), 'items')}."))
    return вон


