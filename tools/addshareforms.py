#!/usr/bin/env python3
"""ДОМ СЛОЖЕНИЯ ДОЛЕЙ — доли складываются только приведёнными к одному знаменателю.

    СЛОЖЕНИЕ ДОЛЕЙ С РАЗНЫМИ ЗНАМЕНАТЕЛЯМИ В СВОДЕ ОТСУТСТВУЕТ. Замер 11.09 по мирам показов:
    «1/2 + 1/3», «1/3 + 1/4» — НОЛЬ вхождений; вычитание долей — НОЛЬ; наименьшее общее кратное
    — НОЛЬ. Сложение долей с ОДНИМ знаменателем есть (108 строк), и оттого дыра особенно
    опасна: показан лёгкий случай, а трудный — тот, где и живёт правило, — не показан вовсе.

    ЧИТАТЕЛЬ, ВИДЕВШИЙ ТОЛЬКО «1/5 + 2/5 = 3/5», СЛОЖИТ И «1/2 + 1/3» ТАК ЖЕ — И ПОЛУЧИТ
    «2/5». Правило, показанное лишь там, где оно не нужно, учит его не знать.

ЧЕТЫРЕ РОДА, И ПЕРВЫЙ ЗДЕСЬ РАДИ ВТОРОГО:

    общий      1/5 + 2/5: знаменатель один и тот же, и складываются ЧИСЛИТЕЛИ: 1 + 2 = 3,
               и выходит 3/5.                                        ← ЛЁГКИЙ СЛУЧАЙ
    разные     1/2 + 1/3: приведём к общему знаменателю 6: 1 × 3 = 3, и 1 × 2 = 2, и 1/2 есть
               3/6, а 1/3 есть 2/6, и 3 + 2 = 5, и выходит 5/6.       ← ГДЕ ЖИВЁТ ПРАВИЛО
    вычесть    1/2 − 1/3: … и 3 − 2 = 1, и выходит 1/6.
    больше     2/3 + 3/4: … и 8 + 9 = 17, и выходит 17/12, а это больше единицы: 17 = 12 × 1
               + 5, и это 1 целая и 5/12.                             ← СУММА ВЫШЛА ЗА ЕДИНИЦУ

ЧЕТВЁРТЫЙ РОД СМЫКАЕТ ДОМ С СОСЕДОМ: сумма долей нередко выходит за единицу, и, не показав
этого, дом внушал бы, что доли всегда складываются в долю. Разбор на целое и остаток берётся
тем же ледже́ром, каким живёт дом дроби и единицы.

    ЗНАМЕНАТЕЛИ СКЛАДЫВАТЬ НЕЛЬЗЯ, И ЭТО ПОКАЗАНО, А НЕ ЗАПРЕЩЕНО: в первом роде виден ход
    «складываются числители» при неизменном знаменателе; во втором — что до сложения надо
    сделать знаменатели одинаковыми. Запрет вышел бы из этих двух страниц сам.

ОБЩИЙ ЗНАМЕНАТЕЛЬ БЕРЁТСЯ ТАК ЖЕ, КАК В ДОМЕ СРАВНЕНИЯ: больший, если делится на меньший, иначе
произведение. Наименьшее общее кратное — предмет иного дома, и здесь оно было бы вторым законом
на одной странице.

    python3 tools/addshareforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("общий", "разные", "вычесть", "больше")

РАМКИ = {
    "ru": {
        "общий": "{a}/{b} + {c}/{b}: знаменатель один и тот же, и складываются числители: {a} + {c} = {s}, и выходит {s}/{b}.",
        "разные": "{a}/{b} + {c}/{d}: приведём к общему знаменателю {об}: {a} × {к1} = {n1}, и {c} × {к2} = {n2}, и {a}/{b} есть {n1}/{об}, а {c}/{d} есть {n2}/{об}, и {n1} + {n2} = {s}, и выходит {s}/{об}.",
        "вычесть": "{a}/{b} − {c}/{d}: приведём к общему знаменателю {об}: {a} × {к1} = {n1}, и {c} × {к2} = {n2}, и {a}/{b} есть {n1}/{об}, а {c}/{d} есть {n2}/{об}, и {n1} − {n2} = {s}, и выходит {s}/{об}.",
        "больше": "{a}/{b} + {c}/{d}: приведём к общему знаменателю {об}: {a} × {к1} = {n1}, и {c} × {к2} = {n2}, и {n1} + {n2} = {s}, и выходит {s}/{об}, а это больше единицы: {s} = {об} × {q} + {r}.",
    },
    "en": {
        "общий": "{a}/{b} + {c}/{b}: the denominator is the same, and the numerators are added: {a} + {c} = {s}, and it gives {s}/{b}.",
        "разные": "{a}/{b} + {c}/{d}: bring them to the common denominator {об}: {a} × {к1} = {n1}, and {c} × {к2} = {n2}, and {a}/{b} is {n1}/{об}, and {c}/{d} is {n2}/{об}, and {n1} + {n2} = {s}, and it gives {s}/{об}.",
        "вычесть": "{a}/{b} − {c}/{d}: bring them to the common denominator {об}: {a} × {к1} = {n1}, and {c} × {к2} = {n2}, and {a}/{b} is {n1}/{об}, and {c}/{d} is {n2}/{об}, and {n1} − {n2} = {s}, and it gives {s}/{об}.",
        "больше": "{a}/{b} + {c}/{d}: bring them to the common denominator {об}: {a} × {к1} = {n1}, and {c} × {к2} = {n2}, and {n1} + {n2} = {s}, and it gives {s}/{об}, and that is greater than one: {s} = {об} × {q} + {r}.",
    },
}


def _общий(b, d):
    """Тот же закон, что в доме сравнения долей: больший, если делится, иначе произведение."""
    б, м = max(b, d), min(b, d)
    return б if б % м == 0 else b * d


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        пусто = dict(об=0, к1=0, к2=0, n1=0, n2=0, q=0, r=0, d=0)
        # ОБЩИЙ ЗНАМЕНАТЕЛЬ: сумма остаётся долей, иначе род «больше» сказал бы то же дважды.
        # РЯДЫ СУЖЕНЫ ПО ЗАМЕРУ: первый заход дал 1784 страницы — вдвое больше соседних
        # домов при том же законе. Правило видно на восьми знаменателях не хуже, чем на
        # двенадцати, а лишние страницы суть повторение, а не показ.
        for b in range(3, 10):
            for a in range(1, b):
                for c in range(1, min(4, b - a + 1)):
                    if a + c < b:
                        вон[рамки["общий"].format(**dict(пусто, a=a, b=b, c=c,
                                                         s=a + c))] = (язык, "общий")
        for b in range(2, 10):
            for d in range(2, 10):
                if b == d:
                    continue
                об = _общий(b, d)
                if об > 24:
                    continue
                к1, к2 = об // b, об // d
                for a in range(1, min(4, b)):
                    for c in range(1, min(4, d)):
                        n1, n2 = a * к1, c * к2
                        s = n1 + n2
                        поля = dict(a=a, b=b, c=c, d=d, об=об, к1=к1, к2=к2,
                                    n1=n1, n2=n2, s=s, q=s // об, r=s % об)
                        if s < об:
                            вон[рамки["разные"].format(**поля)] = (язык, "разные")
                        elif s > об:
                            вон[рамки["больше"].format(**поля)] = (язык, "больше")
                        # ВЫЧИТАНИЕ ТОЛЬКО ПРИ ПОЛОЖИТЕЛЬНОМ ИТОГЕ: отрицательные доли суть
                        # предмет иного дома, и здесь были бы вторым законом.
                        if n1 > n2:
                            вон[рамки["вычесть"].format(**dict(поля, s=n1 - n2))] = (
                                язык, "вычесть")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ДРОБНАЯ ЧЕРТА ЕСТЬ ГРАНИЦА ЧИСЛА: без оглядки на «/» счёт читается сквозь дробь.
_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_СУММА = re.compile(r"(?<![/\d])(\d+) \+ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (\d+)(?![/\d])")
_ОСТАТОК = re.compile(r"(?<![/\d])(\d+) = (\d+) × (\d+) \+ (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: приведение, сложение, вычитание и ледже́р.
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    for a, b, q, r in _ОСТАТОК.findall(с):
        if int(a) != int(b) * int(q) + int(r) or int(r) >= int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    об = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "общий")
    ра = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "разные")
    if судить(об.replace("складываются", "складывают"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(ра.replace("приведём", "приведё"))[1] is not False:
        беды.append("обрезанное слово в приведении прошло")
    if судить(об + " " + об)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"СЛОЖЕНИЕ ДОЛЕЙ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
