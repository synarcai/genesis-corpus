#!/usr/bin/env python3
"""GENESIS layer: НИДЕРЛАНДСКИЙ АРТИКЛЬ — see tools/nlarticleforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Два артикля на один смысл» и «по слову не угадать» идут вместе: первое говорит, что выбор
есть, второе тут же отнимает надежду вывести его из слова.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Уменьшительное всегда het» и «множественное всегда de» — второй группой: это ДВА ПРАВИЛА БЕЗ
ИСКЛЮЧЕНИЙ, стоящие среди непредсказуемого, и порознь каждое читалось бы как частный случай.

    ПРАВИЛО, СТОЯЩЕЕ СРЕДИ НЕПРЕДСКАЗУЕМОГО, НЕЗАМЕТНО ВДВОЙНЕ: его не ищут, ибо решили, что
    искать нечего.

«Сосед делит натрое» — третьей и особо: это довод НАРУЖУ, к немецкому, и соседство с
внутренними правилами его бы разбавило.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import nlarticleforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_nlarticle.txt"
ГРУППЫ = (("два артикля на один смысл", "по слову не угадать"),
          ("уменьшительное всегда het", "множественное всегда de"),
          ("сосед делит натрое",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
