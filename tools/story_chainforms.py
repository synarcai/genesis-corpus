#!/usr/bin/env python3
"""ДОМ ЦЕПОЧЕК РАССКАЗА — три действия подряд и знак итога.

Цепочка есть рассказ, где каждое действие меняет счёт, и знак итога выводится, а не
объявляется. Два рода — по языку рассказа.

2 родов объявлены не здесь: их назвала СВОЯ ЖЕ КУЗНИЦА кортежем `ГРУППЫ`.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

ЧИТАТЕЛЬ ПЯТОГО РОДА НАЗВАН ПОИМЁННО: суд этого мира ВВОЗИТ дом модулем и берёт `ТРОЙКИ_EN`, `ТРОЙКИ_RU`, `ВЕЩИ_EN`.
Связь эта рвётся МОЛЧА при ввозе суда, а не при ковке, — оттого самопроверка дома сверяет, что
все эти имена у него есть.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import rugram  # noqa: E402
import verbthings  # noqa: E402

РОДЫ = ('цепочки_en', 'цепочки_ru')

ЗАЧЕМ_РОДА = {
    "цепочки_en": "цепочка трёх действий по-английски",
    "цепочки_ru": "она же по-русски",
}


ПРЕДЕЛ = 50
# (первый глагол, второй, третий, ОСНОВНАЯ ФОРМА третьего, знак).
# ОСНОВНАЯ ФОРМА НАЗВАНА ОТДЕЛЬНО, ПОТОМУ ЧТО ВОПРОС ЕЁ ТРЕБУЕТ: «how
# many apples does Tom KEEP?» — после «does» стоит голая основа, и
# «does Tom keeps» есть ошибка, которую слой учил бы с полной
# судимостью. Третье лицо и основа суть две разные формы одного
# глагола, и обе объявлены, а не выведены отсечением «s».
ТРОЙКИ_EN = (
    ("picked", "gave away", "keeps", "keep", "-"),
    ("bought", "ate", "has left", "have left", "-"),
    ("had", "found", "holds", "hold", "+"),
    ("counted", "lost", "keeps", "keep", "-"),
    ("brought", "sold", "has left", "have left", "-"),
    ("saved", "earned", "holds", "hold", "+"),
)
ТРОЙКИ_RU = (
    ("взял", "отдал", "осталось", "-"),
    ("купил", "съел", "осталось", "-"),
    ("имел", "нашёл", "стало", "+"),
    ("сосчитал", "потерял", "осталось", "-"),
    ("принёс", "продал", "осталось", "-"),
    ("скопил", "заработал", "стало", "+"),
)
ЛЮДИ_EN = ("Tom", "Ann", "Sam", "Kate", "Ben", "Mia")
# РОД ЛИЦА ОБЪЯВЛЕН, А НЕ ВЫВЕДЕН ПО ПОСЛЕДНЕЙ БУКВЕ (08.09). Дом брал женский род у всякого
# имени на «-а/-я» и оттого писал «Ваня взяла», «Миша купила» — шестьдесят две страницы.
# «Ваня» и «Миша» суть мужские имена, склоняющиеся как женские, и правило по окончанию верно
# для четырёх имён из шести.
#
#     ПРАВИЛО, ВЕРНОЕ ДЛЯ ЧЕТЫРЁХ ИЗ ШЕСТИ, ЕСТЬ НЕ ЗАКОН, А УДАЧА — И УДАЧА КОНЧАЕТСЯ НА
#     ПЕРВОМ ЖЕ «ВАНЕ».
ЛЮДИ_RU = (("Том", "Тома", "m"), ("Аня", "Ани", "f"), ("Миша", "Миши", "m"),
           ("Оля", "Оли", "f"), ("Ваня", "Вани", "m"), ("Катя", "Кати", "f"))
ВЕЩИ_EN = (("apple", "apples"), ("book", "books"), ("coin", "coins"),
           ("card", "cards"), ("egg", "eggs"), ("pen", "pens"))
ВЕЩИ_RU = ("яблоко", "книга", "монета", "карта", "яйцо", "ручка")
assert len(ВЕЩИ_RU) == len(ВЕЩИ_EN), "русские вещи идут парой к английским"


def _числа(шаг, i, знак):
    """Тройка чисел, где ВСЕ три ≤ предела и итог целый."""
    а = 6 + (шаг * 7 + i * 5) % (ПРЕДЕЛ // 2)
    б = 1 + (шаг * 3 + i * 7) % max(1, а - 1)
    итог = а - б if знак == "-" else а + б
    if итог < 1 or итог > ПРЕДЕЛ or а > ПРЕДЕЛ or б > ПРЕДЕЛ:
        return None
    return а, б, итог


def _мн(пара, n):
    return пара[0] if n == 1 else пара[1]


def цепочки_en(шаг):
    вон = []
    for т, (в1, в2, в3, основа, знак) in enumerate(ТРОЙКИ_EN):
        for i in range(12):
            числа = _числа(шаг, i + т * 13, знак)
            if числа is None:
                continue
            а, б, итог = числа
            кто = ЛЮДИ_EN[(шаг + i + т) % len(ЛЮДИ_EN)]
            # A VERB TAKES ITS OWN KIND OF THINGS (tools/verbthings.py): «ate» — food only
            вещь = verbthings.подобрать((в1, в2), ВЕЩИ_EN, шаг * 2 + i + т, ключ=lambda в: в[1])
            вон.append(f"{кто} {в1} {а} {_мн(вещь, а)} and {в2} "
                       f"{б} {_мн(вещь, б)}; {кто} {в3} {итог} "
                       f"{_мн(вещь, итог)}.")
            if i < 3:
                вон.append(f"how many {вещь[1]} does {кто} "
                           f"{основа}? "
                           f"{кто} {в1} {а} {_мн(вещь, а)} and {в2} "
                           f"{б} {_мн(вещь, б)}; {кто} {в3} {итог} "
                           f"{_мн(вещь, итог)}.")
    return вон


def цепочки_ru(шаг):
    вон = []
    for т, (в1, в2, в3, знак) in enumerate(ТРОЙКИ_RU):
        for i in range(12):
            числа = _числа(шаг, i + т * 13, знак)
            if числа is None:
                continue
            а, б, итог = числа
            им, род, пол = ЛЮДИ_RU[(шаг + i + т) % len(ЛЮДИ_RU)]
            # русская вещь — парой к английской того же рода (тройки RU идут в порядке EN)
            вещь = ВЕЩИ_RU[verbthings.индекс(ТРОЙКИ_EN[т][:2], ВЕЩИ_EN, шаг * 2 + i + т, ключ=lambda в: в[1])]
            # ГЛАГОЛ БЕРЁТСЯ У ДОМА ЯЗЫКА ЦЕЛОЙ ФОРМОЙ: «нашёл» + «а» дало бы «нашёла»,
            # «принёс» + «а» — «принёса»; ни того, ни другого в русском нет. Дом гнул их
            # суффиксом и написал сто двадцать таких страниц.
            г1, г2 = rugram.прошедшее(в1, пол), rugram.прошедшее(в2, пол)
            вон.append(f"{им} {г1} {а} {rugram.форма(вещь, а)} и "
                       f"{г2} {б} {rugram.форма(вещь, б)}; у "
                       f"{род} {в3} {итог} {rugram.форма(вещь, итог)}.")
            if i < 3:
                вон.append(f"сколько {rugram.форма(вещь, 5)} у {род}? "
                           f"{им} {г1} {а} "
                           f"{rugram.форма(вещь, а)} и {г2} {б} "
                           f"{rugram.форма(вещь, б)}; у {род} {в3} "
                           f"{итог} {rugram.форма(вещь, итог)}.")
    return вон

# РОД, ЧЬЁ ИМЯ ЕСТЬ ЯЗЫК, ОДНОЯЗЫЧЕН ПО ОПРЕДЕЛЕНИЮ (15.09). Дом делит свои цепочки не по
# делу, а по языку: `цепочки_en` и `цепочки_ru` суть одно и то же дело, сказанное дважды. Едва
# дом объявил язык при странице, мера щербатости справедливо назвала обе клетки пустыми —
# английского в русском роде нет и быть не может.
#
#     ТАМ, ГДЕ РОД И ЯЗЫК СОВПАЛИ, ЩЕРБАТОСТЬ ИЗМЕРЯЕТ СОБСТВЕННОЕ ОПРЕДЕЛЕНИЕ РОДА. Это не
#     долг дома и не порок меры: это ИМЯ, сказавшее то же, что показ, — и объявление лишь
#     переводит сказанное на язык прибора.
ОБЪЯВЛЕННЫЕ_ПРОПУСКИ = {"цепочки_en": frozenset({"ru"}),
                        "цепочки_ru": frozenset({"en"})}

ГРУППЫ = (цепочки_en, цепочки_ru)


def группы(шаг):
    """[[страница]] — ровно те группы и в том порядке, какими кузница кормит `emit_grouped`."""
    return [сделать(шаг) for сделать in ГРУППЫ]


def перебор_с_языком(шаг):
    """[(страница, род, ЯЗЫК)] — ЯЗЫК СТОИ́Т В ИМЕНИ СТРОИТЕЛЯ (15.09).

    Два строителя этого дома зовутся `цепочки_en` и `цепочки_ru`, и язык назван в самом их
    имени — назван с первого дня и не записан в словарь показов.

        ИМЯ СТРОИТЕЛЯ ЕСТЬ ОБЪЯВЛЕНИЕ РОВНО В ТОЙ МЕРЕ, В КАКОЙ ЕГО ЧИТАЮТ. Читаемое одним
        человеком, оно для прибора немо; прочтённое суффиксом — становится объявлением.
    """
    вон = []
    for (род, сделать), группа in zip(zip(РОДЫ, ГРУППЫ), группы(шаг)):
        язык = сделать.__name__.rsplit("_", 1)[-1]
        assert язык in ("en", "ru"), f"имя строителя {сделать.__name__} не кончается языком"
        for с in группа:
            вон.append((с, род, язык))
    return вон


def перебор(шаг):
    """[(страница, род)] — те же группы, но каждая под своим именем."""
    return [(с, р) for с, р, _я in перебор_с_языком(шаг)]


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род, язык in перебор_с_языком(шаг):
            вон.setdefault(с, (язык, род))
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, и имена, каких ждёт суд, — с домом."""
    имена = tuple(с.__name__ for с in ГРУППЫ)
    assert имена == РОДЫ, f"кортеж {имена} разошёлся с объявлением {РОДЫ}"
    сколько = len(группы(0))
    assert сколько == len(РОДЫ), f"проход даёт {сколько} групп при {len(РОДЫ)} родах"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"
    for имя in ('ТРОЙКИ_EN', 'ТРОЙКИ_RU', 'ВЕЩИ_EN'):
        assert имя in globals(), f"суд ждёт имени «{имя}», а дом его не держит"


_самопроверка()
