#!/usr/bin/env python3
"""GENESIS layer: ОБЩАЯ МЕРА — see tools/measureforms.py for the law.

ОБЕ СТОРОНЫ ЛОВУШКИ ИДУТ ОДНОЙ ГРУППОЙ, а не разными: «НОД 12 и 18 — 6, а не 12» и
«НОД 6 и 18 — 6, ибо 6 делит 18» суть ОДНО правило, дающее разные ответы, и читатель
обязан встретить их рядом.

    ПРАВИЛО, ПОКАЗАННОЕ ТОЛЬКО ТАМ, ГДЕ ОНО ОТВЕРГАЕТ, УЧИТ ОТВЕРГАТЬ ВСЕГДА.

Так же и вторая: «НОК меньше произведения» рядом с «НОК и есть произведение».

СМЫСЛ МЕРЫ И СЧЁТ ЕЁ ДЕЛИТЕЛЕЙ — одной группой: второе есть довод первого, а не
отдельное дело. ВОПРОС отдельно — ответ рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import measureforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_measure.txt"
ГРУППЫ = (("общая мера", "все общие делители"),
          ("общее кратное", "закон произведения"),
          ("меньшее не есть мера", "меньшее и есть мера"),
          ("кратное меньше произведения", "кратное и есть произведение"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
