#!/usr/bin/env python3
"""ДОМ ДЕЛЕНИЯ НА ДОЛЮ — деление НЕ ВСЕГДА УМЕНЬШАЕТ, и вопрос звучит «сколько их тут».

    ДЕЛЕНИЯ НА ДОЛЮ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по мирам показов: «÷ 1/2»,
    «divided by 1/2» — НОЛЬ вхождений. Дом умножения долей показал, что умножение на долю
    УМЕНЬШАЕТ; обратный ход не показан вовсе.

    ДЕЛЕНИЕ НА ДОЛЮ УВЕЛИЧИВАЕТ, И ЭТО ТРЕТЬЯ ЛОВУШКА РЯДА. Умножили на долю — стало меньше;
    разделили на долю — стало больше. Читатель, знающий деление лишь на целых, ждёт убыли и
    получает рост.

ВОПРОС ЗДЕСЬ ЗВУЧИТ ИНАЧЕ, ЧЕМ В ЦЕЛЫХ, И В ЭТОМ ВЕСЬ ДОМ: «3 ÷ 1/2» не значит «разделить три
пополам» — оно значит «СКОЛЬКО ПОЛОВИН В ТРЁХ». Разделить на долю есть спросить, сколько раз
доля укладывается в целом.

    ДЕЙСТВИЕ, ЧЬЁ ИМЯ ЗНАКОМО, А ВОПРОС ИНОЙ, ОПАСНЕЕ ДЕЙСТВИЯ НЕЗНАКОМОГО.

ЧЕТЫРЕ РОДА:

    целое на долю  3 ÷ 1/2: сколько половин в трёх? в одном целом 2 половины, и 3 × 2 = 6,
                   и выходит 6, а 6 больше трёх.                        ← РАСТЁТ
    доля на долю   1/2 ÷ 1/4: сколько четвертей в половине? 1/2 есть 2/4, и в ней 2 четверти,
                   и выходит 2.
    доля на число  6/7 ÷ 3: числитель делится, а знаменатель остаётся: 6 ÷ 3 = 2,
                   и выходит 2/7.                                        ← УБЫВАЕТ
    проверка       проверим обратным ходом: 6 половин это 6 ÷ 2 = 3 целых, и потому в трёх
                   целых 6 половин.                                      ← ОРАКУЛ ДОМА

ПЕРВЫЙ И ТРЕТИЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО НАПРАВЛЕНИЮ, и разница снова в одном месте: на что
делят — на ДОЛЮ или на ЧИСЛО. Тот же ход, что различил рост и убыль в доме умножения.

ЧЕТВЁРТЫЙ РОД ЕСТЬ ОРАКУЛ, СКАЗАННЫЙ ВСЛУХ: деление проверяется обратным ходом, и проверка эта
не приписана снаружи, а показана страницей. Без неё «в трёх целых шесть половин» осталось бы
утверждением, которое читателю нечем поверить.

ЗАПИСЬ «6 × 1/2 = 3» СЮДА НЕ ВЗЯТА, И ЭТО КУПЛЕНО СУДОМ АРИФМЕТИКИ: он читает такую строку
сквозь дробную черту и зовёт её ложью. Проверка потому идёт словами и целыми числами — «6
половин это 6 ÷ 2 = 3 целых», — и суд её принимает.

    python3 tools/divshareforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — русский счёт объявлен там, а не здесь

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("целое на долю", "доля на долю", "доля на число", "проверка")

# ИМЕНА ДОЛЕЙ. Русские формы берутся у `rugram`, где счётные тройки живут для всего корпуса:
# «в одном целом 4 четверти», но «сколько четвертей». ПЕРВЫЙ ЗАМЕР ЭТОГО ДОМА ВЫДАЛ «4
# четвертей» — счёт русского языка не есть частное дело дома, и таблица долей внесена в rugram,
# где её сторожит суд согласования. Английские формы множественны всегда: счёт здесь ≥ 2.
ДОЛИ = {2: "половина", 3: "треть", 4: "четверть", 5: "пятая", 6: "шестая",
        8: "восьмая", 10: "десятая"}
ДОЛИ_EN = {2: "halves", 3: "thirds", 4: "quarters", 5: "fifths", 6: "sixths",
           8: "eighths", 10: "tenths"}


def имя(язык, b, счёт):
    """Имя доли 1/b при данном счёте — по закону языка, а не по закону дома."""
    return ДОЛИ_EN[b] if язык == "en" else rugram.форма(ДОЛИ[b], счёт)

РАМКИ = {
    "ru": {
        "целое на долю": "{n} ÷ 1/{b}: сколько {сколько} в числе {n}? в одном целом {b} {при_b}, и {n} × {b} = {r}, и выходит {r}, а {r} больше числа {n}.",
        "доля на долю": "{a}/{b} ÷ 1/{d}: сколько {сколько} в доле {a}/{b}? {a}/{b} есть {n1}/{d}, и в ней {n1} {при_n1}, и выходит {n1}.",
        "доля на число": "{a}/{b} ÷ {k}: числитель делится, а знаменатель остаётся: {a} ÷ {k} = {q}, и выходит {q}/{b}.",
        "проверка": "проверим обратным ходом: {r} {при_r} это {r} ÷ {b} = {n} целых, и потому в {n} целых {r} {при_r}.",
    },
    "en": {
        "целое на долю": "{n} ÷ 1/{b}: how many {сколько} are in {n}? one whole holds {b} {при_b}, and {n} × {b} = {r}, and it gives {r}, and {r} is greater than {n}.",
        "доля на долю": "{a}/{b} ÷ 1/{d}: how many {сколько} are in {a}/{b}? {a}/{b} is {n1}/{d}, and it holds {n1} {при_n1}, and it gives {n1}.",
        "доля на число": "{a}/{b} ÷ {k}: the numerator is divided and the denominator stays: {a} ÷ {k} = {q}, and it gives {q}/{b}.",
        "проверка": "let us check backwards: {r} {при_r} are {r} ÷ {b} = {n} wholes, and so {n} wholes hold {r} {при_r}.",
    },
}


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        пусто = dict(a=0, d=0, k=0, q=0, n1=0, при_n1="", при_b="", при_r="", сколько="")
        for b in ДОЛИ:
            мн = имя(язык, b, 5)          # «сколько ЧЕТВЕРТЕЙ» — родительное множественное
            for n in range(2, 13):
                r = n * b
                вон[рамки["целое на долю"].format(
                    **dict(пусто, n=n, b=b, r=r, сколько=мн,
                           при_b=имя(язык, b, b)))] = (язык, "целое на долю")
                вон[рамки["проверка"].format(
                    **dict(пусто, n=n, b=b, r=r,
                           при_r=имя(язык, b, r)))] = (язык, "проверка")
        # ДОЛЯ НА ДОЛЮ: знаменатель делителя КРАТЕН знаменателю делимого — иначе итог не
        # целый, а дробь от дроби есть предмет иного разговора.
        for b in (2, 3, 4, 5):
            for k in (2, 3, 4):
                d = b * k
                if d not in ДОЛИ:
                    continue
                for a in range(1, b):
                    вон[рамки["доля на долю"].format(
                        **dict(пусто, a=a, b=b, d=d, n1=a * k, n=0, r=0,
                               сколько=имя(язык, d, 5),
                               при_n1=имя(язык, d, a * k)))] = (язык, "доля на долю")
        # ДОЛЯ НА ЧИСЛО: числитель обязан делиться нацело, иначе понадобился бы рост
        # знаменателя — иной ход, и он был бы вторым законом на странице.
        for b in range(3, 13):
            for k in range(2, 6):
                for q in range(1, 5):
                    a = q * k
                    if a < b:
                        вон[рамки["доля на число"].format(
                            **dict(пусто, a=a, b=b, k=k, q=q, n=0, r=0))] = (
                            язык, "доля на число")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ДРОБНАЯ ЧЕРТА ЕСТЬ ГРАНИЦА ЧИСЛА: без оглядки на «/» счёт читается сквозь дробь.
_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_БОЛЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:больше числа|is greater than) (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: произведение, частное и сам РОСТ, сверенный
    # числами, а не принятый на слово.
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    цд = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "целое на долю")
    пр = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "проверка")
    if судить(цд.replace("целом", "цело"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(пр.replace("обратным", "обратны"))[1] is not False:
        беды.append("обрезанное слово в проверке прошло")
    if судить(цд + " " + цд)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ДЕЛЕНИЕ НА ДОЛЮ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
