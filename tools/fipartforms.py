def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for им, парт, мн, тройка, ан, ан_мн in СЛОВА:
            for чис, счёт, ру_чис, ан_чис in ЧИСЛА:
                общ = dict(им=им, парт=парт, мн=мн, ру_ед=тройка[0],
                           ру=units.ру_форма(тройка, счёт), ан=ан, ан_мн=ан_мн,
                           чис=чис, ру_чис=rugram.числительное(ру_чис, тройка[0]), ан_чис=ан_чис,
                           ру_один=rugram.числительное("один", тройка[0]))
                for род in РОДЫ:
                    вон[рамки[род].format(**общ)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()

# СУД ЧИТАЕТ ДВА ЗАКОНА, И ОБА СОДЕРЖАТЕЛЬНЫ:
#   · после числа больше единицы стои́т ПАРТИТИВ, при «yksi» — именительный;
#   · звёздочка стои́т ровно при нарушении.
_ПАРТИТИВ = {им: парт for им, парт, _, _, _, _ in СЛОВА}
_ВСЕ_ФОРМЫ = {}
for _им, _парт, _мн, *_ in СЛОВА:
    _ВСЕ_ФОРМЫ[_им] = ("им", _им)
    _ВСЕ_ФОРМЫ[_парт] = ("парт", _им)
    _ВСЕ_ФОРМЫ[_мн] = ("мн", _им)
_ЧИСЛА_СЛ = {ч for ч, _, _, _ in ЧИСЛА} | {"yksi"}
_ПАРА = _re.compile(r"\b(" + "|".join(sorted(_ЧИСЛА_СЛ)) + r")\s+([a-zäöå]+)")

_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _нарушает(тело):
    """Нарушает ли цитата закон дома: не тот падеж после числа."""
    for чис, форма in _ПАРА.findall(тело.lstrip("*").strip()):
        если = _ВСЕ_ФОРМЫ.get(форма)
        if если is None:
            continue
        вид, _основа = если
        нужен = "им" if чис == "yksi" else "парт"
        if вид != нужен:
            return True
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        if not _ПАРА.search(цитата.lstrip("*")):
            continue
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:110])
            беды += 1
    мутантов = 0
    for показ in ПОКАЗЫ:
        порча = None
        for чис, форма in _ПАРА.findall(показ):
            если = _ВСЕ_ФОРМЫ.get(форма)
            if если is None:
                continue
            вид, основа = если
            чужая = _ПАРТИТИВ[основа] if вид == "им" else основа
            if чужая != форма:
                порча = показ.replace(f"{чис} {форма}", f"{чис} {чужая}", 1)
                break
        if not порча or порча == показ or порча in ПОКАЗЫ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:110])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    ложные = (
        "по-фински «kaksi talo» — два дома.",
        "по-фински «yksi taloa» — один дом.",
        "по-фински «kolme talot» — три дома.",
        "«*kaksi taloa» — так не говорят.",
    )
    for ложь in ложные:
        ПОКАЗЫ[ложь] = ("ru", "проба")
        try:
            if судить(ложь) != (True, False):
                print("  ЛОЖНАЯ СТРАНИЦА ПРОШЛА:", ложь[:100])
                беды += 1
        finally:
            del ПОКАЗЫ[ложь]
    написано = {род for _, род in ПОКАЗЫ.values()}
    if написано != set(РОДЫ):
        print(f"  РОДЫ РАЗОШЛИСЬ: обещано {sorted(РОДЫ)}, написано {sorted(написано)}")
        беды += 1
    for чужая in ("sanakirjassa on kaksi taloa, eikä tämä ole tämän talon sivu.",
                  "он выписал «kaksi taloa» на поля, и это не страница дома."):
        if судить(чужая) != (False, False):
            print("  ЧУЖАЯ РЕЧЬ СУДИМА:", чужая[:100])
            беды += 1
    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, мутантов поймано {мутантов}, "
          f"слов {len(СЛОВА)}, чисел {len(ЧИСЛА)}, бед {беды}")
    return беды


