"""ДОМ НЕСВОДИМЫХ МЕР (14.09, куплен нулём пробы).

Замерено 14.09 по своду: «нельзя сложить» / «cannot be added» — НОЛЬ строк; «метры и
килограммы» — НОЛЬ. Мир смешанной меры (`mixedunits`) умеет «2 кг 300 г» и перенос между
ступенями ОДНОЙ меры. А о том, что бывают меры, между какими переноса НЕТ ВОВСЕ, корпус не
говорит нигде.

    ЧИСЛО БЕЗ МЕРЫ НЕ ЕСТЬ ВЕЛИЧИНА. «30» само по себе не значит ничего: 30 см и 30 м —
    разные вещи, и вторая больше первой в сто раз. А 3 м и 40 кг не складываются вовсе:
    между длиной и массой нет множителя, каким одно превратилось бы в другое.

    СЛОЖИТЬ МОЖНО ЛИШЬ ОДНОРОДНОЕ, И ЭТО НЕ ПРАВИЛО ЗАПИСИ, А СВОЙСТВО МИРА. Читатель,
    выучивший «складывай числа», сложит метры с килограммами и получит число, какого нет.

ТРИ РОДА ПО ДЕЛУ:

    свести_и_сложить  меры одного рода, ступени разные: сведи к меньшей и сложи. Множитель
                      назван на странице, а не подразумеван;
    сложить_нельзя    меры разного рода: отказ, и сказано ЧТО ЧЕМ меряет каждая. Отказ с
                      причиной, а не запрет;
    число_одно        одно и то же число при разных мерах: величины разные, и названо, во
                      сколько раз.

СТУПЕНИ ОБЪЯВЛЕНЫ ЧИСЛОМ, А НЕ ИМЕНЕМ: «см» есть 10 мелких долей, «м» — 1000, и отсюда «в
метре 100 см» выводится счётом, а не памятью.
"""
import itertools
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("свести_и_сложить", "сложить_нельзя", "число_одно")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "свести_и_сложить": "меры одного рода: сведи к меньшей и сложи, множитель назван",
    "сложить_нельзя": "меры разного рода: отказ, и сказано, что чем меряет каждая",
    "число_одно": "одно число при разных мерах: названо, во сколько раз величины разнятся",
}

# (имя меры по языкам, ступень в самых мелких долях, род величины)
МЕРЫ = (
    ({"ru": "мм", "en": "mm"}, 1, "длина"),
    ({"ru": "см", "en": "cm"}, 10, "длина"),
    ({"ru": "м", "en": "m"}, 1000, "длина"),
    ({"ru": "г", "en": "g"}, 1, "масса"),
    ({"ru": "кг", "en": "kg"}, 1000, "масса"),
    ({"ru": "с", "en": "s"}, 1, "время"),
    ({"ru": "мин", "en": "min"}, 60, "время"),
    ({"ru": "ч", "en": "h"}, 3600, "время"),
)
ЧТО_МЕРИТ = {
    "ru": {"длина": "длину", "масса": "массу", "время": "время"},
    "en": {"длина": "length", "масса": "mass", "время": "time"},
}
ПАРЫ = ((3, 40), (2, 15), (5, 60), (7, 25), (4, 30), (6, 45))

РАМКИ = {
    "ru": {
        "свести_и_сложить": "{a} {ма} и {b} {мб}. сколько всего? {итог} {мб}: в {ма1} "
                            "{кратно} {мб}, и {a} {ма} это {свели} {мб}.",
        "сложить_нельзя": "{a} {ма} и {b} {мб}. сколько всего? ничего: {ма} мерит {чта}, "
                          "{мб} мерит {чтб}, и сложить их нечем.",
        "число_одно": "{a} {ма} и {a} {мб}: число одно, а мера разная — {a} {мб} это "
                      "{свели} {ма}, в {раз} раз больше.",
    },
    "en": {
        "свести_и_сложить": "{a} {ма} and {b} {мб}. how much altogether? {итог} {мб}: there "
                            "are {кратно} {мб} in one {ма1}, and {a} {ма} is {свели} {мб}.",
        "сложить_нельзя": "{a} {ма} and {b} {мб}. how much altogether? nothing: {ма} "
                          "measures {чта}, {мб} measures {чтб}, and there is nothing to add "
                          "them with.",
        "число_одно": "{a} {ма} and {a} {мб}: the number is the same and the measure is "
                      "not — {a} {мб} is {свели} {ма}, {раз} times more.",
    },
}


def страница(язык, род, i, j, пара):
    имя_а, шаг_а, род_а = МЕРЫ[i]
    имя_б, шаг_б, род_б = МЕРЫ[j]
    ма, мб = имя_а[язык], имя_б[язык]
    a, b = пара
    рамки = РАМКИ[язык]
    if род == "сложить_нельзя":
        if род_а == род_б:
            return None
        чм = ЧТО_МЕРИТ[язык]
        return рамки["сложить_нельзя"].format(a=a, b=b, ма=ма, мб=мб,
                                              чта=чм[род_а], чтб=чм[род_б])
    if род_а != род_б or шаг_а <= шаг_б:
        return None            # первая мера обязана быть КРУПНЕЕ второй
    кратно = шаг_а // шаг_б
    if род == "число_одно":
        return рамки["число_одно"].format(a=a, ма=мб, мб=ма, свели=a * кратно, раз=кратно)
    return рамки["свести_и_сложить"].format(a=a, b=b, ма=ма, мб=мб, ма1=ма, кратно=кратно,
                                            свели=a * кратно, итог=a * кратно + b)


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for i, j in itertools.permutations(range(len(МЕРЫ)), 2):
            for место, пара in enumerate(ПАРЫ):
                for род in РОДЫ:
                    # РОД НЕ ДОЛЖЕН ЗАГЛУШАТЬ РОД. Пар РАЗНОРОДНЫХ мер — сорок две, а
                    # однородных со ступенью вниз — семь: шестикратно больше, и это их
                    # ЧИСЛО, а не их важность. Отказ показывается на ОДНОЙ паре чисел (он
                    # от чисел не зависит вовсе), а сведе́ние и равенство числа — на всех.
                    if род == "сложить_нельзя" and место:
                        continue
                    п = страница(язык, род, i, j, пара)
                    if п:
                        вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД СВОДИТ МЕРЫ САМ: он берёт ступени из объявления, считает множитель делением и требует,
# чтобы названное на странице сошлось. Мера вне объявленных делает запись не нашей.
def _образцы(язык):
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык][род])
        for дыра, узор in (("ма1", "[^ .,?]+"), ("ма", "[^ .,?]+"), ("мб", "[^ .,?]+"),
                           ("чта", "[^ .,?]+"), ("чтб", "[^ .,?]+"),
                           ("кратно", r"\d+"), ("свели", r"\d+"), ("итог", r"\d+"),
                           ("раз", r"\d+"), ("a", r"\d+"), ("b", r"\d+")):
            дыра_о = re.escape("{" + дыра + "}")
            первый = True
            while дыра_о in о:
                о = о.replace(дыра_о, f"(?P<{дыра}>{узор})" if первый else f"(?P={дыра})", 1)
                первый = False
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def _мера(язык, имя):
    for шаг, (имена, ступень, род) in enumerate(МЕРЫ):
        if имена[язык] == имя:
            return ступень, род
    return None


# ЧИСЛА РОДА «СЛОЖИТЬ НЕЛЬЗЯ» СВОБОДНЫ, И ЭТО ЗАКОН ДОМА, А НЕ ОГОВОРКА (16.09). «3 мм и
# 40 г. сколько всего? ничего: мм мерит длину, г мерит массу, и сложить их нечем» — истинно
# при ВСЯКИХ числах: несложимость длины с массой от величин не зависит вовсе. Закон дома
# читает тут МЕРЫ и то, что они мерят; числа он не читает и читать не должен.
#
#     МЕСТО, ГДЕ ЗАКОН ДОМА ЧИСЛА НЕ ЧИТАЕТ, ЕСТЬ СВОБОДНОЕ МЕСТО. Прибор мутантов дома
#     (`scripts/house_mutant.py`) читает это объявление и не подсаживает туда порчи: подмена
#     свободного числа даёт ДРУГУЮ ЧЕСТНУЮ страницу, и суд, назвавший её истиной, прав.
#
# Прочие два рода дома («число одно», «свести к мелкой») числа ЧИТАЮТ и пересчитывают, и
# свободных мест в них нет: объявлена лишь рамка несложимости.
СВОБОДНОЕ_ЧИСЛО = tuple(
    re.compile(r"(\d+)(?=\s+\S+\s+(?:и|and)\s+\d+\s+\S+\.\s+(?:сколько всего|how much in all)"
               r"\?\s+(?:ничего|nothing))")
    for _ in (0,)) + tuple(
    re.compile(r"(?:и|and)\s+(\d+)(?=\s+\S+\.\s+(?:сколько всего|how much in all)"
               r"\?\s+(?:ничего|nothing))")
    for _ in (0,))


# ЗАКОН СКЕЛЕТА (16.09, тот же, что дан тринадцати домам 13.09). Прибор [СУД ДОМА ЛОВИТ
# ПОРЧУ] вписывает порченую страницу В НАБОР показов на время опыта и спрашивает суд о
# странице, которая в наборе ЕСТЬ. Дом, отвечающий по набору, стережёт себя
# ПРИНАДЛЕЖНОСТЬЮ, а не проверкой: испорченная проза рамки проходит, ибо словарь страницы
# не изменился.
#
#     СТРАНИЦА ОБЯЗАНА СОБИРАТЬСЯ ХОТЬ ОДНОЙ ОБЪЯВЛЕННОЙ РАМКОЙ ДОМА: дыры рамки берут что
#     угодно, проза между ними — только себя. Подмена двух слов прозы местами ломает
#     порядок и ловится, хотя ни одно слово страницы не переменилось.
_re_скелет = re.compile(r"\{[^{}]+\}")


def _образцы_рамок():
    """Рамки дома, обращённые в образцы: дыра берёт что угодно, проза — только себя."""
    вон = []
    ряды = РАМКИ.values() if isinstance(РАМКИ, dict) else РАМКИ
    for ряд in ряды:
        рамки = ряд.values() if isinstance(ряд, dict) else ([ряд] if isinstance(ряд, str) else ряд)
        for рамка in рамки:
            if not isinstance(рамка, str):
                continue
            куски, конец = [], 0
            for м in _re_скелет.finditer(рамка):
                куски.append(re.escape(рамка[конец:м.start()]))
                куски.append(r"[\s\S]+?")
                конец = м.end()
            куски.append(re.escape(рамка[конец:]))
            вон.append(re.compile("^" + "".join(куски) + "$"))
    return tuple(вон)


_ОБРАЗЦЫ_РАМОК = _образцы_рамок()


def _скелет_объявлен(с):
    """Собирается ли страница хоть одной объявленной рамкой дома."""
    return any(о.match(с) for о in _ОБРАЗЦЫ_РАМОК)


def судить(строка):
    """(судимо, истинно) — меры сведены заново по объявленным ступеням."""
    # СКЕЛЕТ ПРОВЕРЯЕТСЯ У СТРОКИ, КОТОРУЮ ДОМ ПРИЗНАЛ СВОЕЙ ПО НАБОРУ (16.09). Прибор
    # [СУД ДОМА ЛОВИТ ПОРЧУ] вписывает порчу В НАБОР показов и спрашивает суд о странице,
    # которая в наборе ЕСТЬ: дом, отвечающий по набору, стережёт себя ПРИНАДЛЕЖНОСТЬЮ, а не
    # проверкой, и содержательный его закон не спрашивается ни разу.
    #
    #     ЗАКОН, ПОСТАВЛЕННЫЙ ПРЕЖДЕ ВСЯКОГО ОПОЗНАНИЯ, СУДИТ ЧУЖИЕ СТРАНИЦЫ; ЗАКОН,
    #     ПОСТАВЛЕННЫЙ ЗА ОПОЗНАНИЕМ РАМКОЙ, НЕ СПРАШИВАЕТСЯ ТАМ, ГДЕ ПОРЧА ЛОМАЕТ РАМКУ.
    #     Место ему — там, где дом уже сказал «страница моя», но ещё не сказал «она верна».
    if строка.strip() in ПОКАЗЫ and not _скелет_объявлен(строка.strip()):
        return True, False
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if м is None:
                continue
            д = м.groupdict()
            а, б = _мера(язык, д["ма"]), _мера(язык, д["мб"])
            if а is None or б is None or д["ма"] == д["мб"]:
                continue                       # чужая мера — запись не наша
            (шаг_а, род_а), (шаг_б, род_б) = а, б
            if род == "сложить_нельзя":
                чм = ЧТО_МЕРИТ[язык]
                return True, (род_а != род_б and д["чта"] == чм[род_а]
                              and д["чтб"] == чм[род_б])
            if род_а != род_б:
                return True, False
            if род == "число_одно":
                # В РОДЕ «ЧИСЛО ОДНО» РАМКА СТАВИТ МЕЛКУЮ МЕРУ ПЕРВОЙ: крупная обязана быть
                # второй, иначе «в столько-то раз больше» сказано о меньшем.
                if шаг_б <= шаг_а:
                    return True, False
                кратно = шаг_б // шаг_а
                a = int(д["a"])
                return True, (int(д["раз"]) == кратно and int(д["свели"]) == a * кратно)
            if шаг_а <= шаг_б:
                return True, False
            кратно = шаг_а // шаг_б
            a, b = int(д["a"]), int(д["b"])
            return True, (int(д["кратно"]) == кратно and int(д["свели"]) == a * кратно
                          and int(д["итог"]) == a * кратно + b and д["ма1"] == д["ма"])
    return False, True


