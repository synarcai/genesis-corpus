#!/usr/bin/env python3
"""GENESIS layer: PER CENT — a part of a hundred, and the five acts on it.

The corpus knew the percent SIGN and one act with it. «20% of 40 is 8»
lived in the notation layer as one of the four clothes a number wears,
and that is the ALPHABET of the percent, not the percent: a reader who
owns only that line can recite a share and cannot answer a question
about one, cannot say what a share IS in any other words, cannot walk
back from the share to the whole, and has never met a quantity that
GREW or FELL by a percent — which is the only reason percents are
spoken outside a textbook at all.

FIVE ACTS, ONE ARITHMETIC. Every act here is the same multiplication
and division; what differs is the QUESTION the act answers, and a
question is not derivable from the answer to another one:

    ДОЛЯ       — «20% of 80 is 16»: the share of a named whole
    ВОПРОС     — «what is 20% of 80?» carrying its own answer
    КОНВЕРСИЯ  — «20% is 20 hundredths» and «one half is 50%»: the
                 percent said as a fraction, the fraction said as a
                 percent — the bridge walked in both directions
    ОБРАТНОЕ   — «16 is 20% of 80»: the same fact read from the share
    РОСТ/УБЫЛЬ — «80 grown by 25% is 100»: the percent as an OPERATOR
                 on a quantity, which is what a price, a rate and a
                 measurement error actually are

THREE SURFACES OF ONE FACT. The glyph («20%»), the English word
(«twenty percent») and the Russian word («двадцать процентов») stand on
the SAME computed number. A corpus that shows only the glyph teaches
the sign; a corpus that shows only the word teaches a phrase. Both
tongues speak the same instances, so a defect in one surface cannot
hide behind the other.

NOTHING IS WRITTEN BY HAND, AND WHAT IS NOT WHOLE IS NOT SAID. Every
number below is computed, and a pair whose share is not a whole number
is not shown at all: «a third is 33%» is false, «33.33%» needs a
notation for repeating decimals that this corpus does not yet have, and
a rounded percent taught as an equality is a lie with perfect grammar.
HONEST SILENCE IS THE CHEAPEST TRUTH A GENERATOR CAN BUY.
"""

import pathlib
import sys
from fractions import Fraction

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import numerals  # noqa: E402
import units  # noqa: E402
from layer import emit_grouped  # noqa: E402
from plural import by_count  # noqa: E402

# ЦЕЛЬ ОБЪЯВЛЕНА ИМЕНЕМ МОДУЛЯ, А НЕ ПЕРЕМЕННОЙ ВНУТРИ ТЕЛА. Прибор
# воспроизводимости читает цель генератора ОБЪЯВЛЕНИЕМ; путь, живший бы
# лишь в теле функции, сделал бы слой невидимым для меры — и слой L4 был
# невидим ей всё время своего существования.
ЦЕЛЬ = "datasets/genesis_percent.txt"

# ПРОЦЕНТЫ И ЦЕЛЫЕ ОБЪЯВЛЕНЫ, ИХ ПАРЫ — ВЫВЕДЕНЫ. Ни одна пара не
# написана рукой: годной зовётся та, у которой доля ЦЕЛАЯ, и негодная
# не может быть показана, ибо её попросту нет в своде.
ПРОЦЕНТЫ = (1, 2, 4, 5, 10, 20, 25, 40, 50, 60, 75, 80)
ЦЕЛЫЕ = (20, 25, 40, 50, 60, 75, 80, 100, 120, 140, 160, 180, 200,
         240, 300)

# ШИРИНА ОКНА РОДА В ПРОХОДЕ. Пять проходов на пять родов дают
# двадцать пять окон, и окно шире восьми перестало бы отличать проход
# от прохода: объём покупал бы вес, а не новые факты.
ОКНО_РОДА = 8

# ФОРМЫ СЧЁТА ОБЪЯВЛЕНЫ, А ЗАКОН СОГЛАСОВАНИЯ ВЗЯТ ИЗ ПАКЕТА ЯЗЫКА.
# Правило «один / два-четыре / пять» с исключением подростков живёт в
# langpacks/ru.json как данные; вторая его копия здесь разошлась бы с
# оригиналом в день, когда тронут любую из двух.
ФОРМЫ_ПРОЦЕНТА = ("процент", "процента", "процентов")
# ДОЛЯ СЧИТАЕТСЯ ИНАЧЕ, ЧЕМ ПРЕДМЕТ: «одна сотая», но «две сотых» и
# «пять сотых» — родительный множественного стоит и при двойке. Оттого
# тройка своя, а не взятая у процента.
ФОРМЫ_СОТОЙ = ("сотая", "сотых", "сотых")

# ИМЯ ДОЛИ И ЕЁ ВЕЛИЧИНА. ТРЕТЬ ОБЪЯВЛЕНА НАРОЧНО: её процент не целый,
# и слой о ней МОЛЧИТ — молчание, видное в объявлении, есть закон, а
# молчание от невключения в список есть случайность.
ДОЛИ = (
    ("one half", "половина", Fraction(1, 2)),
    ("one third", "треть", Fraction(1, 3)),
    ("one quarter", "четверть", Fraction(1, 4)),
    ("three quarters", "три четверти", Fraction(3, 4)),
    ("one fifth", "пятая часть", Fraction(1, 5)),
    ("two fifths", "две пятых", Fraction(2, 5)),
    ("one tenth", "десятая часть", Fraction(1, 10)),
    ("one twentieth", "двадцатая часть", Fraction(1, 20)),
    ("one hundredth", "сотая часть", Fraction(1, 100)),
)

# ЧИСЛО СЛОВОМ БЕРЁТСЯ У ДОМА ЧИСЛИТЕЛЬНЫХ, а не пишется вторым
# списком рядом с таблицей пакета: слой, выписавший числительные рукой,
# разошёлся бы с языком в первый же день.
ТАБЛИЦЫ = {"en": numerals.таблица("en"), "ru": numerals.таблица("ru")}


# ---------------------------------------------------------------- счёт

def доля(процент, целое):
    """Часть целого, или None — доля не целая, и показа не будет.

    ЗДЕСЬ ЖИВЁТ ГЛАВНЫЙ ЗАКОН СЛОЯ. Округление есть самая убедительная
    ложь, какую может нести корпус процентов: «3% от 50 — это 2»
    правильно по форме, правдоподобно на глаз и неверно по существу.
    Отказ считать нецелую долю делает такой показ НЕВОЗМОЖНЫМ, а не
    обнаружимым.
    """
    произведение = процент * целое
    return произведение // 100 if произведение % 100 == 0 else None


def годные():
    """Пары (процент, целое) с целой долей — и только они."""
    return tuple((п, ц) for п in ПРОЦЕНТЫ for ц in ЦЕЛЫЕ
                 if доля(п, ц) is not None)


ГОДНЫЕ = годные()


def окно(свод, шаг, сколько=ОКНО_РОДА):
    """Подряд идущие члены свода, своё окно у рода в каждом проходе.

    ОДИН ЗАКОН НА ЛЮБОЙ СВОД. Роду доли нужна пара, а роду конверсии —
    один процент: доля от целого и сотая часть суть разные утверждения,
    и второму целое не нужно вовсе. Окно, знавшее только пары, выдавало
    роду конверсии восемь пар ОДНОГО процента (свод перебирается по
    процентам), и весь проход говорил о сотых долях одним числом.
    """
    начало = шаг * сколько
    return [свод[(начало + i) % len(свод)] for i in range(сколько)]


def процентов(n):
    """«процент / процента / процентов» по закону пакета языка."""
    return units.ру_форма(ФОРМЫ_ПРОЦЕНТА, n)


def сотых(n):
    """«сотая / сотых» по тому же закону и своим формам."""
    return units.ру_форма(ФОРМЫ_СОТОЙ, n)


# --------------------------------------------------------------- РОДЫ

def показ_доли(шаг):
    """ТРИ ПОВЕРХНОСТИ ОДНОГО ФАКТА: глиф, слово и оба языка.

    Одно и то же вычисленное число сказано знаком процента и сказано
    словом. Знак без слова учит записи, слово без знака учит обороту, и
    ни то ни другое не есть доля. Язык, не умеющий назвать этот
    процент по своему пакету, МОЛЧИТ о нём — и молчит на обоих языках
    сразу, чтобы поверхности не разошлись числом.
    """
    вон = []
    for п, ц in окно(ГОДНЫЕ, шаг):
        д = доля(п, ц)
        # ЗВЕНЬЯ ЦЕПИ (compose, e9): ц × п, 10 × 10 = 100, ÷ 100 — сто не константа
        # оси, оно показано звеном.
        цепь = f"{ц} × {п} = {ц * п}, 10 × 10 = 100, {ц * п} ÷ 100 = {д}"
        вон.append(f"{п}% of {ц} is {д}: {цепь}.")
        вон.append(f"{п}% от {ц} — это {д}: {цепь}.")
        имя_en = numerals.назвать(п, ТАБЛИЦЫ["en"])
        имя_ru = numerals.назвать(п, ТАБЛИЦЫ["ru"])
        if имя_en is None or имя_ru is None:
            continue
        вон.append(f"{имя_en} percent of {ц} is {д}.")
        вон.append(f"{имя_ru} {процентов(п)} от {ц} — это {д}.")
    return вон


def показ_вопроса(шаг):
    """ОТВЕТ ПОВТОРЯЕТ СПРОШЕННОЕ, а не указывает на него.

    Слой записи спрашивал «what is 20% of 40?» и отвечал «it is 8».
    Человеку этого довольно, учащемуся отвечать — нет: «it is 8» не
    есть утверждение о доле, оно есть УКАЗАНИЕ на соседнюю строку, и
    вырванное из пары оно не значит ничего. Ответ, стоящий сам по себе,
    стоит одной лишней фразы и покупает вопросную поверхность, годную к
    проверке своим же судом.
    """
    вон = []
    for п, ц in окно(ГОДНЫЕ, шаг):
        д = доля(п, ц)
        цепь = f"{ц} × {п} = {ц * п}, 10 × 10 = 100, {ц * п} ÷ 100 = {д}"
        вон.append(f"what is {п}% of {ц}? {п}% of {ц} is {д}: {цепь}.")
        вон.append(f"сколько будет {п}% от {ц}? {п}% от {ц} — это {д}: {цепь}.")
    return вон


def показ_конверсии(шаг):
    """ПРОЦЕНТ ЕСТЬ СОТАЯ ДОЛЯ, и мост этот ходится в обе стороны.

    Без обратного хода процент остаётся именем действия: организм,
    знающий «20% от 80 — это 16» и не знающий «половина — это 50%»,
    владеет процедурой и не владеет ОТНОШЕНИЕМ, которое она исполняет.
    Доля, чей процент не целый, здесь не говорится вовсе.
    """
    вон = []
    for п in окно(ПРОЦЕНТЫ, шаг):
        вон.append(f"{п}% is {п} {by_count(п, 'hundredths')}.")
        вон.append(f"{п}% — это {п} {сотых(п)}.")
    for имя_en, имя_ru, знач in ДОЛИ:
        сотые = знач * 100
        # ТРЕТЬ МОЛЧИТ. «треть — это 33%» ложно, а «33.33%» требует
        # записи, которой у корпуса нет: округление, сказанное
        # равенством, есть ложь с безупречной грамматикой.
        if сотые.denominator != 1:
            continue
        вон.append(f"{имя_en} is {сотые.numerator}%.")
        вон.append(f"{имя_ru} — это {сотые.numerator}%.")
    return вон


def показ_обратного(шаг):
    """ОБРАТНАЯ ЗАДАЧА: тот же факт, прочтённый от доли к целому.

    «16 — это 20% от 80» не выводится из «20% от 80 — это 16» никаким
    правилом языка: это ДРУГОЕ предложение о том же счёте, и корпус,
    показавший лишь прямое, учит порядку слов, а не отношению.
    """
    вон = []
    for п, ц in окно(ГОДНЫЕ, шаг):
        д = доля(п, ц)
        вон.append(f"{д} is {п}% of {ц}.")
        вон.append(f"{д} — это {п}% от {ц}.")
    return вон


def показ_роста(шаг):
    """ПРОЦЕНТ КАК ДЕЙСТВИЕ НАД ВЕЛИЧИНОЙ: рост и убыль.

    Цена, ставка и погрешность живут именно здесь, а не в доле: доля
    отвечает «сколько это», рост отвечает «чем это стало». Убыль
    показывается лишь там, где остаток положителен, — и это условие
    ВЫВЕДЕНО из чисел, а не обеспечено удачным подбором таблицы: свод
    процентов, дополненный завтра сотней, не родит «100, уменьшенное на
    120%».
    """
    вон = []
    for п, ц in окно(ГОДНЫЕ, шаг):
        д = доля(п, ц)
        вон.append(f"{ц} grown by {п}% is {ц + д}.")
        вон.append(f"{ц}, выросшее на {п}%, — это {ц + д}.")
        if д < ц:
            вон.append(f"{ц} cut by {п}% is {ц - д}.")
            вон.append(f"{ц}, уменьшенное на {п}%, — это {ц - д}.")
    return вон


# РОД ОБЪЯВЛЯЕТ ИМЯ И СВОЙ ПОКАЗ, И НИЧЕГО БОЛЬШЕ. Механизм прохода
# ниже один на все роды: прибавить род — значит объявить пару, а не
# написать новый обход, и это проба, что форма есть форма.
РОДЫ = (
    ("share", показ_доли),
    ("question", показ_вопроса),
    ("conversion", показ_конверсии),
    ("inverse", показ_обратного),
    ("change", показ_роста),
)


def pass_groups(шаг):
    """Одна группа на РОД: роды не перемешиваются друг с другом.

    ОКНО ПАР ВЫВОДИТСЯ ИЗ НОМЕРА РОДА В СВОДЕ, а не назначается числом
    при каждом роде. Род, прибавленный завтра, получит своё окно сам, и
    ни один род не повторит чужих пар в том же проходе.
    """
    вон = []
    for н, (_имя, показать) in enumerate(РОДЫ):
        вон.append(показать(шаг * len(РОДЫ) + н))
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
