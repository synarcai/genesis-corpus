def страница(язык, род, место):
    у = УТВЕРЖДЕНИЯ[язык][место]
    д = ДОВОДЫ[язык][род][место]
    return РАМКИ[язык][род].format(у=у, д=д)


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for место in range(len(УТВЕРЖДЕНИЯ[язык])):
                вон.setdefault(страница(язык, род, место), (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
