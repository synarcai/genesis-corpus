# СУД ПЕРЕСЧИТЫВАЕТ, А НЕ СВЕРЯЕТ СО СТРОИТЕЛЕМ. Позвать `страница()` и сличить строки было
# бы мерой, зеленеющей от совпадения с самой собою: испортись строитель — и мир, им же
# построенный, сойдётся с ним до буквы. Оттого суд читает ОБЪЯВЛЕНИЕ (`РЕЧЬ`, `ЛЕДЖЕРЫ`),
# разбирает страницу на приказ, ветвь и наблюдение и ПЕРЕСЧИТЫВАЕТ сравнение сам.


def _образец(рамка, **дыры):
    """Образец из объявленной речи: дословное — дословно, дыры — своими выражениями."""
    куски, поз = [], 0
    for м in re.finditer(r"\{(\w+)\}", рамка):
        куски.append(re.escape(рамка[поз:м.start()]))
        куски.append(дыры.get(м.group(1), r"(?P<%s>[^:.,?!]+)" % м.group(1)))
        поз = м.end()
    куски.append(re.escape(рамка[поз:]))
    return "".join(куски)


_ЧИСЛО = r"(\d+)"


def _язык(строка):
    """Язык страницы — по слову роли, объявленному домом акта; берётся ДЛИННЕЙШЕЕ совпадение."""
    вон, длина = None, -1
    for язык in ЯЗЫКИ:
        метка = A.РЕЧЬ[язык]["польз"] + A.РЕЧЬ[язык]["двоеточие"]
        if строка.startswith(метка) and len(метка) > длина:
            вон, длина = язык, len(метка)
    return вон


def _приказы(язык, строка):
    """Все приказы строки слева направо: [(сравнение, леджер, цель, начало, конец)].

    ПРИКАЗОВ БЫВАЕТ ДВА, И СУД ОБЯЗАН УВИДЕТЬ ОБА. Мера, берущая первое совпадение, читала
    бы строку-задачу как страницу об одной цели — и второй приказ, со всем его ходом, ушёл
    бы из-под суда незамеченным.
    """
    найдено = []
    for сравнение in СРАВНЕНИЯ:
        рамка = РЕЧЬ[язык][сравнение]
        for л in _ВСЕ[язык]:
            о = re.compile(_образец(рамка, L=re.escape(л[0]), N=_ЧИСЛО))
            for м in о.finditer(строка):
                найдено.append((сравнение, л, int(м.group(1)), м.start(), м.end()))
    найдено.sort(key=lambda з: (з[3], -з[4]))
    вон = []
    for з in найдено:
        if not вон or з[3] >= вон[-1][4]:
            вон.append(з)
    return вон


def _реплики(язык, строка):
    """Строка, разрезанная по говорящим: речь читается репликами, а не сплошняком."""
    метки = (A.РЕЧЬ[язык]["польз"] + A.РЕЧЬ[язык]["двоеточие"],
             A.РЕЧЬ[язык]["орг"] + A.РЕЧЬ[язык]["двоеточие"])
    о = re.compile("(?=" + "|".join(re.escape(м) for м in метки) + ")")
    return [ч.strip() for ч in о.split(строка) if ч.strip()]


def _наблюдение(язык, строка):
    """(метка, стало, было) хвоста страницы — по объявленной рамке наблюдения, или None."""
    рамка = РЕЧЬ[язык]["наблюдение"]
    for л in _ВСЕ[язык]:
        о = re.compile(_образец(рамка, О=re.escape(л[1]), V=_ЧИСЛО, B=_ЧИСЛО))
        м = о.search(строка)
        if м:
            # {V} стои́т в рамке дважды: берутся оба и сверяются между собой.
            числа = [int(г) for г in м.groups()]
            if числа[0] != числа[-1]:
                return л, числа[0], числа[1], False
            return л, числа[0], числа[1], True
    return None


def _орган(язык, рамка, строка, **дыры):
    """Совпадение рамки, СКАЗАННОЙ ОРГАНОМ: реплика читается вместе с говорящим.

    РЕЧЬ БЕЗ ГОВОРЯЩЕГО НЕ ЧИТАЕТСЯ (14.09). Суд, искавший рамку где угодно в строке, не
    отличал предложения органа от тех же слов, сказанных кем угодно, — и закон покрытия
    палаты назвал такую реплику НЕПРОЧИТАННОЙ: испорти «organisme» — и вердикт не дрогнет.
    """
    голова = re.escape(A.РЕЧЬ[язык]["орг"] + A.РЕЧЬ[язык]["двоеточие"])
    return re.compile(голова + _образец(рамка, **дыры)).search(строка)


def _предложение(язык, строка, леджер):
    """Число предложения органа, или None: рамка объявлена, и суд читает ЕЁ целиком."""
    м = _орган(язык, РЕЧЬ[язык]["предложение"], строка,
               L=re.escape(леджер[0]), N=_ЧИСЛО)
    return int(м.group(1)) if м else None


def _отчёт(язык, строка, леджер):
    """Число отчёта органа, или None."""
    м = _орган(язык, РЕЧЬ[язык]["отчёт"], строка, L=re.escape(леджер[0]), N=_ЧИСЛО)
    return int(м.group(1)) if м else None


def _судить_цель(язык, участок, сравнение, леджер, цель):
    """(судимо, истинно) для ОДНОЙ цели: её наблюдение, её ветвь и её число.

    УЧАСТОК ЕСТЬ РЕЧЬ ОБ ЭТОЙ ЦЕЛИ И ТОЛЬКО О НЕЙ. Для страницы об одной цели он есть вся
    строка; для строки-задачи о двух — те реплики, где названа она. Суд одной цели не
    знает, сколько их было: он пересчитывает сравнение по объявлению дома.
    """
    наблюдение = _наблюдение(язык, участок)
    if наблюдение is None:
        return False, True
    метка, стало, было, ровно = наблюдение
    если_держится = ДЕРЖИТСЯ[сравнение](было, цель)
    р = РЕЧЬ[язык]
    # СЛОВО СОГЛАСИЯ ЧИТАЕТСЯ ВМЕСТЕ С ТЕМ, КТО ЕГО СКАЗАЛ (14.09). Первая редакция искала
    # «да.» где угодно в строке — и не отличала согласия ПОЛЬЗОВАТЕЛЯ от слова, сказанного
    # кем угодно. Закон покрытия палаты поймал это: испорти «user» в реплике «user: yes.» —
    # и вердикт не дрогнет, то есть реплику не читает никто.
    #
    #     СОГЛАСИЕ ЕСТЬ ДЕЙСТВИЕ ЛИЦА, А НЕ СЛОВО В СТРОКЕ. Ход, взявший «да» без
    #     говорящего, совершён по слову, которого никто не говорил.
    реплика = A.РЕЧЬ[язык]["польз"] + A.РЕЧЬ[язык]["двоеточие"]
    есть_да = f"{реплика}{A.РЕЧЬ[язык]['да']}." in участок
    есть_нет = f"{реплика}{A.РЕЧЬ[язык]['нет']}." in участок
    # ВСЯКАЯ РЕПЛИКА ОРГАНА ЧИТАЕТСЯ ВМЕСТЕ С ГОВОРЯЩИМ И ЦЕЛИКОМ: «держится» и «только
    # читается» суть утверждения ОРГАНА о мире, и подпись под ними та же, что под ходом.
    держится_сказано = _орган(язык, р["держится"], участок,
                              О=re.escape(леджер[1]), B=_ЧИСЛО)
    чтение_сказано = bool(_орган(язык, р["только_чтение"], участок,
                                 О=re.escape(леджер[2])))
    if not ровно:
        return True, False                      # наблюдение само с собою не сошлось
    if метка is not леджер:
        return True, False                      # приказ об одном леджере, отчёт о другом
    if чтение_сказано:
        # ТОЛЬКО ЧТЕНИЕ: леджер обязан быть объявлен НЕСТАВИМЫМ, и мир не двинут.
        return True, (not леджер[4]) and стало == было
    if держится_сказано:
        # ЧИСЛО В ДОВОДЕ ЧИТАЕТСЯ ТОЖЕ, А НЕ ТОЛЬКО РАМКА ВОКРУГ НЕГО (15.09). Суд, бравший
        # у реплики «угол щита 0 — цель уже достигнута» одно лишь совпадение образца, звал
        # правдой и «угол щита 1» при нуле в наблюдении: орган называл мир числом, какого в
        # мире нет, и мера этого не видела.
        #
        #     ДОВОД ЕСТЬ УТВЕРЖДЕНИЕ О МИРЕ, А НЕ УКРАШЕНИЕ ПРИ ВЕРДИКТЕ. Число в нём
        #     обязано быть тем же числом, какое показывает наблюдение.
        return True, (если_держится and стало == было
                      and int(держится_сказано.group(1)) == было)
    if есть_нет or есть_да:
        # ПРЕДЛОЖЕНИЕ ЧИТАЕТСЯ ЦЕЛИКОМ, А НЕ ПРОПУСКАЕТСЯ (14.09). Первая редакция судила
        # приказ и наблюдение, а предложение органа — «предлагаю поставить угол на 30.
        # подтверждено ли это?» — не читала вовсе. Закон покрытия палаты поймал это раньше
        # меня: строку, чьё предложение не читает никто, палата обращает в НЕМОТУ, и 442
        # честные страницы не прошли ворот.
        #
        #     ПРЕДЛОЖЕНИЕ ЕСТЬ МЕСТО, ГДЕ ОРГАН НАЗЫВАЕТ ТО, ЧТО СОБИРАЕТСЯ СДЕЛАТЬ. Суд,
        #     его не читающий, не отличит «предлагаю поставить угол на 30» от «предлагаю
        #     поставить мощность на 5» — а весь ход стои́т на том, что предложено ИМЕННО
        #     то, о чём просили.
        предложено = _предложение(язык, участок, леджер)
        if предложено != цель:
            return True, False
    if есть_да:
        # ОТЧЁТ ТОЖЕ ЧИТАЕТСЯ ЦЕЛИКОМ И ТОЖЕ С ГОВОРЯЩИМ: «поставил угол на 30» есть
        # утверждение органа о СДЕЛАННОМ, и число в нём обязано быть числом цели.
        if _отчёт(язык, участок, леджер) != цель:
            return True, False
    if есть_нет:
        # ОТКАЗ ОРГАНА ЧИТАЕТСЯ ТОЖЕ, И ТОЖЕ С ГОВОРЯЩИМ (14.09). Слово «нет» говорит
        # ПОЛЬЗОВАТЕЛЬ, а «подтверждения нет — акт не совершён» отвечает ОРГАН, и это две
        # разные реплики: суд, читавший лишь первую, оставлял вторую непрочитанной, и закон
        # покрытия палаты обращал честную страницу в немоту.
        if not _орган(язык, A.РЕЧЬ[язык]["отказ"], участок):
            return True, False
        # ОТКАЗ СЛОВОМ: мир не двинут, и цель ДО отказа не держалась — иначе предлагать
        # было бы нечего.
        return True, стало == было and not если_держится and леджер[4]
    if есть_да:
        # ХОД: стало есть цель, ставимость объявлена, и до хода цель не держалась.
        return True, стало == цель and леджер[4] and not если_держится
    return True, False


def _по_целям(язык, строка, леджеры):
    """Реплики после приказа, разнесённые по целям: чья речь — та, чьё имя в ней названо.

    РЕПЛИКА БЕЗ ИМЕНИ ИДЁТ ТОЙ ЦЕЛИ, О КОТОРОЙ СЕЙЧАС ГОВОРЯТ. «пользователь: да.» не
    называет ни угла, ни предмета — и принадлежит тому ходу, чьё предложение только что
    прозвучало. Согласие, отданное неизвестно чему, было бы согласием ни на что.
    """
    участки, текущий = [[], []], None
    for р in _реплики(язык, строка)[1:]:
        for i, л in enumerate(леджеры):
            if any(ф in р for ф in (л[0], л[1], л[2])):
                текущий = i
        if текущий is None:
            return None
        участки[текущий].append(р)
    if not all(участки):
        return None
    return [" ".join(у) for у in участки]


def _судить_задачу(язык, строка, приказы):
    """Строка-задача из двух приказов: оба пересчитаны, и предмет обязан их различать."""
    (с1, л1, ц1, _н1, к1), (с2, л2, ц2, н2, _к2) = приказы
    # ОДНО СРАВНЕНИЕ НА ОБА ПРИКАЗА: «доведи до» и «держи не выше» суть разные глаголы, и
    # речь, их смешавшая, не строится домом ни в одном из девяти языков.
    if с1 != с2 or л1 is л2:
        return True, False
    # СОЮЗ ЧИТАЕТСЯ, А НЕ ПРОПУСКАЕТСЯ: между приказами стои́т ОБЪЯВЛЕННОЕ слово языка.
    # Суд, глядящий лишь на два приказа, не заметил бы, что их склеили чем попало.
    if строка[к1:н2] != СОЮЗ[язык]:
        return True, False
    участки = _по_целям(язык, строка, (л1, л2))
    if участки is None:
        return True, False
    вон = True
    for участок, л, ц in zip(участки, (л1, л2), (ц1, ц2)):
        судимо, истинно = _судить_цель(язык, участок, с1, л, ц)
        if not судимо:
            return False, True
        вон = вон and истинно
    return True, вон


def судить(строка):
    """(судимо, истинно) — страница цели пересчитана по объявлению, а не по строителю."""
    язык = _язык(строка)
    if язык is None:
        return False, True
    вопрос = any(строка.startswith(A.РЕЧЬ[язык]["польз"] + A.РЕЧЬ[язык]["двоеточие"] + л[3])
                 for л in _ВСЕ[язык])
    if вопрос:
        # ВОПРОС О ЗНАЧЕНИИ: ответ обязан назвать ТОТ ЖЕ леджер и одно число.
        for л in _ВСЕ[язык]:
            голова = A.РЕЧЬ[язык]["польз"] + A.РЕЧЬ[язык]["двоеточие"] + л[3]
            if строка.startswith(голова):
                хвост = строка[len(голова):]
                о = re.compile(re.escape(A.РЕЧЬ[язык]["орг"] + A.РЕЧЬ[язык]["двоеточие"])
                               + re.escape(л[1]) + r" " + _ЧИСЛО + r"\.$")
                return True, bool(о.search(хвост.strip()))
        return True, False
    приказы = _приказы(язык, строка)
    if not приказы:
        return False, True
    if len(приказы) == 1:
        сравнение, леджер, цель, _н, _к = приказы[0]
        return _судить_цель(язык, строка, сравнение, леджер, цель)
    if len(приказы) == 2:
        return _судить_задачу(язык, строка, приказы)
    # ТРЁХ ПРИКАЗОВ ДОМ НЕ КУЁТ, И СТРОКА С ТРЕМЯ ЕСТЬ ЛОЖЬ ПРИ ЭТОМ ОБЪЯВЛЕНИИ, а не
    # немота: рамки прочтены все три, и мера вправе сказать о них «нет».
    return True, False


