# ЗНАЧЕНИЯ НАБЛЮДЕНИЯ: пары «было, цель». Числа круглые и малые — школьная таблица держит
# их все, и суд пересчитывает сравнение сам.
# РАВЕНСТВО ПОКАЗАНО ТРИЖДЫ, А НЕ ДВАЖДЫ: ветвь «держится» у сравнения «равно» живёт ТОЛЬКО
# на парах, где было = цель, и двух таких пар хватало ровно на закон (LAW = 2) без запаса.
# Форма, показанная ровно столько, сколько требует закон, падает от одной правки жребия.
ПАРЫ = ((0, 30), (10, 40), (24, 30), (55, 40), (18, 25), (5, 20),
        (30, 30), (12, 12), (25, 25), (45, 20), (60, 50))
ДЕРЖИТСЯ = {"равно": lambda b, n: b == n,
            "не_меньше": lambda b, n: b >= n,
            "не_выше": lambda b, n: b <= n}


def _реплика(язык, кто, что):
    return f"{A.РЕЧЬ[язык][кто]}{A.РЕЧЬ[язык]['двоеточие']}{что}"


def страница(язык, сравнение, ветвь, k):
    """Одна страница цели: приказ речью, ход органа и наблюдение числом."""
    р, лз = РЕЧЬ[язык], ЛЕДЖЕРЫ[язык]
    # ЛЕДЖЕР ТОЛЬКО ДЛЯ ЧТЕНИЯ ОБЪЯВЛЕН ТРЕТЬИМ, и ветвь отказа по имени берёт ЕГО, а прочие
    # ветви — ставимые: страница, где датчик и ручка перепутаны, учила бы неверному миру.
    место = 2 if ветвь == "только_чтение" else k % 2
    имя_п, имя_о, имя_р, вопрос, ставится = лз[место]
    было, цель = ПАРЫ[k % len(ПАРЫ)]
    держится = ДЕРЖИТСЯ[сравнение](было, цель)
    if ветвь == "держится" and not держится:
        return None
    if ветвь == "ход" and (держится or not ставится):
        return None
    if ветвь == "отказ_словом" and (держится or not ставится):
        return None
    if ветвь == "только_чтение" and ставится:
        return None
    приказ = р[сравнение].format(L=имя_п, N=цель)
    стало = цель if ветвь == "ход" else было
    наблюдение = р["наблюдение"].format(О=имя_о, V=стало, B=было)
    куски = [_реплика(язык, "польз", f"{приказ}.")]
    if ветвь == "ход":
        куски.append(_реплика(язык, "орг", р["предложение"].format(L=имя_п, N=цель)))
        куски.append(_реплика(язык, "польз", f"{A.РЕЧЬ[язык]['да']}."))
        куски.append(_реплика(язык, "орг", f"{р['отчёт'].format(L=имя_п, N=цель)}. "
                                           f"{наблюдение}."))
    elif ветвь == "отказ_словом":
        куски.append(_реплика(язык, "орг", р["предложение"].format(L=имя_п, N=цель)))
        куски.append(_реплика(язык, "польз", f"{A.РЕЧЬ[язык]['нет']}."))
        куски.append(_реплика(язык, "орг", f"{A.РЕЧЬ[язык]['отказ']}. {наблюдение}."))
    elif ветвь == "держится":
        # «ДЕРЖИТСЯ» БЕРЁТ ГОЛУЮ МЕТКУ, А НЕ ПОДЛЕЖАЩЕЕ С АРТИКЛЕМ: «Winkel 30 — цель уже
        # достигнута» есть наблюдение с доводом, и метка при числе тут та же, что в самой
        # строке наблюдения. «Der Winkel 30» было бы подлежащим без сказуемого.
        куски.append(_реплика(язык, "орг", f"{р['держится'].format(О=имя_о, B=было)}. "
                                           f"{наблюдение}."))
    else:
        куски.append(_реплика(язык, "орг", f"{р['только_чтение'].format(О=имя_р)}. "
                                           f"{наблюдение}."))
    return " ".join(куски)


def страница_вопроса(язык, сравнение, k):
    """Вопрос о значении — та же цель, спрошенная; род у него тот же, что у сравнения."""
    р, лз = РЕЧЬ[язык], ЛЕДЖЕРЫ[язык]
    имя_п, имя_о, имя_р, вопрос, ставится = лз[k % 2]
    было, цель = ПАРЫ[k % len(ПАРЫ)]
    if ДЕРЖИТСЯ[сравнение](было, цель) or not ставится:
        return None
    return " ".join((_реплика(язык, "польз", вопрос),
                     _реплика(язык, "орг", f"{имя_о} {цель}.")))


def _показы():
    """{строка: (язык, сравнение)} — род идёт по СРАВНЕНИЮ, а отказ словом стои́т особняком."""
    вон = {}
    for язык in ЯЗЫКИ:
        for сравнение in СРАВНЕНИЯ:
            for ветвь in ВЕТВИ:
                for k in range(len(ПАРЫ)):
                    с = страница(язык, сравнение, ветвь, k)
                    if с:
                        род = "отказ_словом" if ветвь == "отказ_словом" else сравнение
                        вон.setdefault(с, (язык, род))
            for k in range(len(ПАРЫ)):
                с = страница_вопроса(язык, сравнение, k)
                if с:
                    вон.setdefault(с, (язык, сравнение))
    return вон


