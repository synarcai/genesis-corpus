    assert set(ПРЕДМЕТЫ) == set(СОБСТВЕННЫЕ) == set(СОЮЗ) == set(ЯЗЫКИ), \
        "предмет, собственный леджер или союз объявлены не всюду"
    for язык in ЯЗЫКИ:
        assert len(ЛЕДЖЕРЫ[язык]) == 3, f"{язык}: леджеров не три"
        assert all(len(л) == 6 for л in ЛЕДЖЕРЫ[язык]), f"{язык}: у леджера не шесть форм"
        # ШЕСТАЯ ФОРМА — ВОПРОС С ДЫРОЙ ПОД ПРЕДМЕТ, и дыра в ней обязана быть: «какой угол
