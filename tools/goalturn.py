            места.setdefault(место, []).append(len(леджеры))
            леджеры.append((f"{имя_п} {форма}", f"{имя_о} {форма}", f"{имя_р} {форма}",
                            рамка.format(П=форма), ставится, ПАРЫ_ПРЕДМЕТА, СРАВНЕНИЯ))
