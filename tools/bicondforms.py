def вид(a, b):
    """«одна» или «обе» — или None, если из A не следует B. ВЫВЕДЕНО ОБХОДОМ РЯДА."""
    A, B = СВОЙСТВА[a][0], СВОЙСТВА[b][0]
    if any(A(n) and not B(n) for n in РЯД):
        return None
    return "одна" if any(B(n) and not A(n) for n in РЯД) else "обе"


def _свидетели(a, b, сколько=3):
    """(против, за, ни_то_ни_то) — числа ряда: B и не A; A и B; ни A, ни B."""
    A, B = СВОЙСТВА[a][0], СВОЙСТВА[b][0]
    против = [n for n in РЯД if B(n) and not A(n)][:сколько]
    за = [n for n in РЯД if A(n) and B(n)][:сколько]
    ни = [n for n in РЯД if not A(n) and not B(n)][:сколько]
    return против, за, ни


def страница(язык, род, a, b, i):
    вид_ = вид(a, b)
    if вид_ is None:
        return None
    A, A_нет = СВОЙСТВА[a][1][язык]
    B, B_нет = СВОЙСТВА[b][1][язык]
    против, за, ни = _свидетели(a, b)
    рамки = РАМКИ[язык]
    if род == "одна_сторона":
        if вид_ != "одна" or i >= len(против):
            return None
        return рамки["одна_сторона"].format(A=A, B=B, A_нет=A_нет, n=против[i])
    if род == "обе_стороны":
        if вид_ != "обе" or i >= min(len(за), len(ни)):
            return None
        return рамки["обе_стороны"].format(A=A, B=B, A_нет=A_нет, B_нет=B_нет,
                                           n=за[i], m=ни[i])
    if вид_ == "одна":
        if i >= len(против):
            return None
        return рамки["нужно_мало"].format(A=A, B=B, A_нет=A_нет, n=против[i])
    if i >= len(за):
        return None
    return рамки["нужно_довольно"].format(A=A, B=B, n=за[i])


