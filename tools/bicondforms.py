def _по_словам(язык):
    вон = {}
    for имя, (_ф, формы) in СВОЙСТВА.items():
        сказ, отказ = формы[язык]
        вон.setdefault(сказ, (имя, True))
        вон.setdefault(отказ, (имя, False))
    return вон


_СЛОВА = {я: _по_словам(я) for я in ЯЗЫКИ}


def _образец(язык, рамка):
    """Рамка в образец. ДЫРА СОБРАНА ИЗ ОБЪЯВЛЕННЫХ ФОРМ, А НЕ ИЗ «ЧЕГО УГОДНО»: подсудность
    определяется словарём дома, и запись с чужим свойством суд просто не читает. Дыра,
    названная дважды (а рамка двусторонней связи поминает свойство трижды), вторым и
    третьим разом становится ССЫЛКОЙ на первую: иначе тот же образец разрешил бы записи,
    где одно и то же место названо по-разному."""
    формы = sorted(_СЛОВА[язык], key=len, reverse=True)
    словарь = "(?:" + "|".join(re.escape(ф) for ф in формы) + ")"
    части, виден = [], set()
    for кусок in re.split(r"(\{[A-Za-z_А-Яа-яЁё]+\})", рамка):
        if кусок.startswith("{") and кусок.endswith("}"):
            имя = кусок[1:-1]
            if имя in виден:
                части.append(f"(?P={имя})")
            else:
                виден.add(имя)
                части.append(f"(?P<{имя}>" + (r"\d+" if имя in ("n", "m") else словарь) + ")")
        else:
            части.append(re.escape(кусок))
    return re.compile("".join(части) + r"$")


_ОБРАЗЦЫ = {я: {к: _образец(я, р) for к, р in рамки.items()}
            for я, рамки in РАМКИ.items()}


def _свойство(язык, кусок, ждём_сказ):
    пара = _СЛОВА[язык].get(кусок.strip())
    if пара is None or пара[1] is not ждём_сказ:
        return None
    return пара[0]


def судить(строка):
    """(судимо, истинно) — вид связи выведен обходом ряда, пример проверен порознь."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for ключ, образец in _ОБРАЗЦЫ[язык].items():
            м = образец.fullmatch(строка)
            if not м:
                continue
            дыры = м.groupdict()
            a = _свойство(язык, дыры["A"], True)
            b = _свойство(язык, дыры["B"], True)
            if a is None or b is None:
                continue                       # чужое свойство — запись не наша
            if "A_нет" in дыры and _свойство(язык, дыры["A_нет"], False) != a:
                return True, False
            if "B_нет" in дыры and _свойство(язык, дыры["B_нет"], False) != b:
                return True, False
            A, B = СВОЙСТВА[a][0], СВОЙСТВА[b][0]
            вид_ = вид(a, b)
            n = int(дыры["n"])
            if ключ == "обе_стороны":
                m = int(дыры["m"])
                return True, (вид_ == "обе" and A(n) and B(n)
                              and not A(m) and not B(m))
            if ключ == "нужно_довольно":
                return True, вид_ == "обе" and A(n) and B(n)
            # «одна_сторона» и «нужно_мало»: связь обязана быть односторонней, а названное
            # число — быть обратным примером, а не каким угодно.
            return True, вид_ == "одна" and B(n) and not A(n)
    return False, True


