"""GENESIS layer: ОСНОВАНИЕ ПРОЦЕНТА — see tools/pctbaseforms.py for the law.

ОБЕ СТОРОНЫ ЛОВУШКИ ИДУТ ОДНОЙ ГРУППОЙ. При разных основаниях сравнение процентов лжёт, при
одном — верно в точности; показанные порознь, они учат либо не верить процентам вовсе, либо
верить им всегда.

    ПРОЦЕНТ ЕСТЬ ОТНОШЕНИЕ, А НЕ ЧИСЛО; ДВА ОТНОШЕНИЯ СРАВНИМЫ ЛИШЬ ПРИ ОБЩЕМ ОСНОВАНИИ.

СЧЁТ И ЕГО ОБРАТНАЯ ДОРОГА — одной группой: «10 % от 500 есть 50» и «50 из 500 есть 10 %»
суть один закон, спрошенный с двух концов. ЛЮДИ, НЕСКЛАДЫВАЕМОСТЬ И НАЗВАННОЕ ОСНОВАНИЕ —
вместе: все три о том, что отношение без своего целого не есть величина. ВОПРОС отдельно.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pctbaseforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_pctbase.txt"
ГРУППЫ = (("процент от основания", "сколько процентов"),
          ("больший процент меньшее число", "то же основание"),
          ("люди а не доли", "сложить нельзя", "основание названо"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
