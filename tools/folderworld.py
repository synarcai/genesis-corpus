#!/usr/bin/env python3
"""МИР ПАПКИ — ход мира на странице дома актов: то, что мир `ozar-core/src/world.rs` ответил бы на акт (25.09).

Ведущий (коллегия «ответ мира в словах дома», М-2013 и далее): место итога, которое заполняет мир — найденный файл,
номер строки, текст строки, значение ключа, число строк или байт, — рынок покупает только ЭХОМ: текст итога равен
клетке хода мира на той же странице. Из одного отчёта организма происхождение поля не доказать; нужен третий голос.
Этот модуль и есть третий голос: мир, в котором дом держит свой репозиторий, отвечает на акт так, как ответил бы
мир ядра, — мерами и строками объявленных полей, — и страница печатает его ход, никогда не набранный руками.

ОДНА ДВЕРЬ СМЫСЛА МИРА — ЯДРО. Здесь та же семантика, что у `world.rs`, строка в строку:
  · файлы места — простые файлы под ним в порядке имён, вглубь (`files_under`), скрытые имена не видны;
  · строки файла — куски между переводами строки, пустой хвост не строка (`lines_of`);
  · находка — подстрока в строке (`contains`), и не словом: «lamp» стоит и в «lamps»;
  · счёт папки — простые файлы прямо в ней (`count`), не вглубь;
  · перенос в место кладёт внутрь, строка акта — новое имя;
  · замена — всякое вхождение слева направо без наложений (`replaced`);
  · запись по имени (`locate`, М-2075) — всякая видимая запись места на любой глубине, чьё собственное имя — данное:
    вглубь в порядке имён (папка прежде своих записей), путь от корня, папка кончается «/»; имя, что ходит («a/b»,
    «..»), — не имя: отказ outside-the-world; имени нет ни у одной записи — ход без строк, не отказ; мера entries,
    строки path.
Меры и поля строк — объявление мира папки (закон B коллегии): find — occurrences (всякое вхождение), matches
(совпавшие строки), files; строки path, line, text; lines — bytes, lines; строки path, line, text; list — строки path;
count — files, строка path (считанное место); read — bytes, строка path; всякий акт — строка path, где объект стоит
ПОСЛЕ акта; прогон — runs, exit, millis, lines. Сверено с миром закона B (М-2017): пустое имя корня печатается «.» —
в голове акта и в клетке path одинаково; счёт ФАЙЛА ядро считает счётом его папки — здесь это отказ not-there, и
страницы такого хода не печатают.

Байты — байты UTF-8 файла, чьи строки кончаются переводом строки.
"""
import dataclasses

ПЕРЕВОД = "\n"
# ВИДЫ ХОДА — акты, какие мир печатает головой своего хода (мир папки и мир-процесс: «run»). По ним знак языка
# (`langsign`) узнаёт ход мира в строке: провод один на всех языках и речью страницы не судится.
ВИДЫ = ("find", "lines", "read", "count", "list", "create", "delete", "move", "line", "replace", "run")


# ЗАПИСЬ ПО ИМЕНИ (М-2075): мир печатает и чтение `locate <имя>` головой своего хода
ВИДЫ += ("locate",)
# МИР ИНСТРУМЕНТОВ (М-2100, дом `toolmemory`): роды, какие сервер memory объявил мосту ядра (`memoryworld.объявление`,
# ответ «declare» в семени) и какие мост печатает головой хода, — самопроверка мира сверяет их с этим списком
ВИДЫ += ("create_entities", "create_relations", "add_observations", "delete_entities", "delete_observations",
         "delete_relations", "read_graph", "search_nodes", "open_nodes")


@dataclasses.dataclass(frozen=True)
class Наблюдение:
    """Ход мира: акт (вид, объект, доводы), меры (имя, значение) и строки — кортежи (поле, значение)."""
    вид: str
    объект: str
    доводы: tuple
    меры: tuple
    строки: tuple

    def мера(self, имя):
        return dict(self.меры).get(имя)


@dataclasses.dataclass(frozen=True)
class Отказ:
    """Отказ мира по имени: already-there, not-there, outside-the-world, no-such-act."""
    вид: str
    объект: str
    доводы: tuple
    почему: str
    что: str = ""       # что названо в отказе — объект акта, если не сказано иное

    def названо(self):
        return self.что or self.объект


class Папка:
    """Репозиторий в памяти: путь → строки файла. Акты возвращают новое состояние и ход мира."""

    def __init__(self, файлы):
        self.файлы = {путь: tuple(строки) for путь, строки in файлы.items()}

    # ---- чтения состояния --------------------------------------------------------------------------------
    def байты(self, путь):
        return len("".join(с + ПЕРЕВОД for с in self.файлы[путь]).encode("utf-8"))

    def есть_файл(self, путь):
        return путь in self.файлы

    def есть_папка(self, место):
        return место in ("", ".") or any(п.startswith(место + "/") for п in self.файлы)

    def файлы_под(self, место):
        """Файлы места в порядке мира: имена записей по порядку, папка — вглубь на своём месте."""
        if место in self.файлы:
            return [место]
        голова = "" if место in ("", ".") else место + "/"
        под = [п for п in self.файлы if п.startswith(голова)]

        def ключ(путь):
            # порядок `seen_entries`: записи папки по имени, папка обходится там, где стоит её имя
            return tuple(путь[len(голова):].split("/"))
        return sorted(под, key=ключ)

    def счёт(self, место):
        голова = "" if место in ("", ".") else место + "/"
        return sum(1 for п in self.файлы if п.startswith(голова) and "/" not in п[len(голова):])

    # ---- акты ----------------------------------------------------------------------------------------------
    def find(self, место, литерал):
        знак = "" if место == "." else место
        if знак and not (self.есть_файл(знак) or self.есть_папка(знак)):
            return self, Отказ("find", место, (литерал,), "not-there")
        строки, вхождений, файлов = [], 0, 0
        for путь in self.файлы_под(знак):
            было = len(строки)
            for i, строка in enumerate(self.файлы[путь], 1):
                if литерал and литерал in строка:
                    строки.append((("path", путь), ("line", str(i)), ("text", строка)))
                    вхождений += строка.count(литерал)
            файлов += len(строки) > было
        меры = (("occurrences", вхождений), ("matches", len(строки)), ("files", файлов))
        return self, Наблюдение("find", место, (литерал,), меры, tuple(строки))

    def lines(self, путь):
        if not self.есть_файл(путь):
            return self, Отказ("lines", путь, (), "not-there")
        строки = tuple((("path", путь), ("line", str(i)), ("text", с)) for i, с in enumerate(self.файлы[путь], 1))
        меры = (("files", self.счёт(_папка(путь))), ("bytes", self.байты(путь)), ("lines", len(self.файлы[путь])))
        return self, Наблюдение("lines", путь, (), меры, строки)

    def read(self, путь):
        if not self.есть_файл(путь):
            return self, Отказ("read", путь, (), "not-there")
        return self, Наблюдение("read", путь, (), (("files", self.счёт(_папка(путь))), ("bytes", self.байты(путь))),
                                ((("path", путь),),))

    def count(self, место):
        if not self.есть_папка(место):
            return self, Отказ("count", место, (), "not-there")
        return self, Наблюдение("count", место or ".", (), (("files", self.счёт(место)),), ((("path", место or "."),),))

    def list(self, место):
        if not self.есть_папка(место):
            return self, Отказ("list", место, (), "not-there")
        голова = "" if место in ("", ".") else место + "/"
        записи = sorted({п[len(голова):].split("/")[0] + ("/" if "/" in п[len(голова):] else "")
                         for п in self.файлы if п.startswith(голова)})
        return self, Наблюдение("list", место or ".", (), (("files", self.счёт(место)),),
                                tuple((("path", з),) for з in записи))

    def записи_под(self, место):
        """Записи места вглубь — папки (с «/») и файлы, путь от корня — в порядке мира (`entries_under`, М-2075): имена
        по порядку, папка прежде своих записей; скрытого имени мир не видит."""
        голова = "" if место in ("", ".") else место + "/"
        записи = set()
        for путь in self.файлы:
            if not путь.startswith(голова):
                continue
            части = путь[len(голова):].split("/")
            if any(ч.startswith(".") for ч in части):
                continue
            записи |= {голова + "/".join(части[:i]) + "/" for i in range(1, len(части))}
            записи.add(путь)
        return sorted(записи, key=lambda з: tuple(з.rstrip("/").split("/")))

    def locate(self, место, имя):
        """Запись по имени во всём дереве места (М-2075): всякая видимая запись, чьё собственное имя — данное, на любой
        глубине — строка своего пути; имя, что ходит, — не имя (отказ outside-the-world); имени нет — ход без строк."""
        знак = "" if место in ("", ".") else место
        if знак and (знак in self.файлы or not self.есть_папка(знак)):
            return self, Отказ("locate", место, (имя,), "not-there")
        if not имя or "/" in имя or имя in (".", ".."):
            return self, Отказ("locate", место, (имя,), "outside-the-world", имя)
        строки = tuple((("path", з),) for з in self.записи_под(знак) if з.rstrip("/").rsplit("/", 1)[-1] == имя)
        return self, Наблюдение("locate", место, (имя,), (("entries", len(строки)),), строки)

    def _после(self, файлы, вид, объект, доводы, путь, меры):
        return Папка(файлы), Наблюдение(вид, объект, доводы, меры, ((("path", путь),),))

    def create(self, путь):
        if self.есть_файл(путь):
            return self, Отказ("create", путь, (), "already-there")
        файлы = dict(self.файлы)
        файлы[путь] = ()
        return self._после(файлы, "create", путь, (), путь, (("files", Папка(файлы).счёт(_папка(путь))),))

    def delete(self, путь):
        if not self.есть_файл(путь):
            return self, Отказ("delete", путь, (), "not-there")
        файлы = {п: с for п, с in self.файлы.items() if п != путь}
        return self._после(файлы, "delete", путь, (), путь, (("files", Папка(файлы).счёт(_папка(путь))),))

    def move(self, путь, куда):
        """Довод — как в приказе: полный новый путь или существующая папка (тогда кладёт внутрь)."""
        новый = (куда + "/" + путь.rsplit("/", 1)[-1]) if self.есть_папка(куда) and куда not in self.файлы else куда
        if not self.есть_файл(путь):
            return self, Отказ("move", путь, (куда,), "not-there")
        if self.есть_файл(новый):
            # отказ ядра называет место, какое занято
            return self, Отказ("move", путь, (куда,), "already-there", новый)
        файлы = {п: с for п, с in self.файлы.items() if п != путь}
        файлы[новый] = self.файлы[путь]
        return self._после(файлы, "move", путь, (куда,), новый, (("files", Папка(файлы).счёт(_папка(новый))),))

    def line(self, путь, строка):
        """Дописать строку: мир сам пишет конец строки — строк ровно +1 (М-2016). Файла нет — нет."""
        if not self.есть_файл(путь):
            return self, Отказ("line", путь, (строка,), "not-there")
        файлы = dict(self.файлы)
        файлы[путь] = self.файлы[путь] + (строка,)
        новая = Папка(файлы)
        return self._после(файлы, "line", путь, (строка,), путь,
                           (("files", новая.счёт(_папка(путь))), ("lines", len(файлы[путь]))))

    def replace(self, путь, старое, новое):
        if not self.есть_файл(путь):
            return self, Отказ("replace", путь, (старое, новое), "not-there")
        n = sum(с.count(старое) for с in self.файлы[путь]) if старое else 0
        if n == 0:
            # отказ ядра называет не файл, а заменяемое
            return self, Отказ("replace", путь, (старое, новое), "not-there", старое)
        файлы = dict(self.файлы)
        файлы[путь] = tuple(с.replace(старое, новое) for с in self.файлы[путь])
        новая = Папка(файлы)
        return self._после(файлы, "replace", путь, (старое, новое), путь,
                           (("files", новая.счёт(_папка(путь))), ("bytes", новая.байты(путь)), ("occurrences", n)))


def прогон(имя, снятое, прогонов_до):
    """Ход мира-процесса на прогон: настоящий отчёт бегуна (снятый прибором), запусков — на один больше. Меры — в
    порядке мира-процесса (М-2017): runs · exit · millis · lines."""
    строки = tuple((("path", имя), ("line", str(i)), ("text", с)) for i, с in enumerate(снятое["report"], 1))
    меры = (("runs", прогонов_до + 1), ("exit", снятое["exit"]), ("millis", снятое["millis"]),
            ("lines", снятое["lines"]))
    return Наблюдение("run", имя, (), меры, строки)


def счёт_прогонов(имя, прогонов):
    """Чтение мира-процесса: сколько было прогонов имени (ход отказа пользователем — чтение «до»)."""
    return Наблюдение("count", имя, (), (("runs", прогонов),), ((("path", имя),),))


def _папка(путь):
    return путь.rsplit("/", 1)[0] if "/" in путь else ""


def текст(ход):
    """Ход мира строкой (договор ведущего): «<вид> <объект> ["<довод>"…] · <мера> <значение> · … · path … · line … ·
    text "…"» — одинаково на всех языках; довод-текст и значение text — в ASCII-кавычках, путь довода — без; отказ —
    «<голова> · refused <почему> "<что>"». ЗНАЧЕНИЕ С ПРОБЕЛОМ — В КАВЫЧКАХ (29.09, слово ведущего, мир памяти М-2100):
    читатель ядра (М-2057) берёт клеткой одно голое слово или значение в обёртке, а прогон из нескольких голых слов
    клеткой не читает — и ход теряет все клетки («message "Entities deleted successfully"», «relationType "works at"»);
    у мира папки и мира кода таких значений нет, их ходы — байт в байт."""
    доводы = [д if ход.вид == "move" else f'"{д}"' for д in ход.доводы]
    куски = [" ".join([ход.вид, ход.объект or "."] + доводы)]
    if isinstance(ход, Отказ):
        куски.append(f'refused {ход.почему} "{ход.названо()}"')
        return " · ".join(куски)
    куски += [f"{имя} {значение}" for имя, значение in ход.меры]
    for строка in ход.строки:
        for поле, значение in строка:
            куски.append(f'{поле} "{значение}"' if поле == "text" or " " in str(значение) else f"{поле} {значение}")
    return " · ".join(куски)
