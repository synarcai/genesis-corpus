#!/usr/bin/env python3
"""GENESIS layer: ОБХОД ПРОСТОТЫ — see tools/primewalkforms.py for the law.

ДВА ИСХОДА ОДНОГО ОБХОДА ИДУТ ОДНОЙ ГРУППОЙ, и это не удобство раздачи, а сам предмет
дома: «обход исчерпан» и «обход оборван» суть один способ с двумя концами, и читатель,
получивший лишь первый, решит, что обход всегда доходит до корня.

    СПОСОБ, ПОКАЗАННЫЙ ОДНИМ СВОИМ ИСХОДОМ, БУДЕТ ПОНЯТ КАК ОБРЯД, А НЕ КАК ПОИСК.

ГРАНИЦА И ЕЁ ЦЕНА — вторая группа: «довольно корня» говорит, ПОЧЕМУ обход там кончается,
«счёт проб» — во сколько это обходится. Довод без цены оставил бы границу отвлечённой.

ТРУД НЕ РАВЕН стои́т своей группой: страница эта говорит не о числе, а о ДВУХ ОТВЕТАХ,
и соседство с обычным обходом сделало бы её примечанием к нему. ВОПРОС отдельно — ответ
рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import primewalkforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_primewalk.txt"
ГРУППЫ = (("обход исчерпан", "обход оборван"),
          ("довольно корня", "счёт проб"),
          ("труд не равен",),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
