def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    assert {о[0] for о in ОЧЕРТАНИЯ} == set(РОДЫ), "очертание объявлено не всякому роду"
    # ПОРЯДОК ШАГОВ ОБЯЗАН СОГЛАСОВАТЬСЯ С ЗАПИСЬЮ: итог шагов и итог разбора — одно число.
    for род, запись, порядок in ОЧЕРТАНИЯ:
        for набор in НАБОРЫ:
            шаги = _шаги(порядок, набор)
            assert шаги[-1][3] == _считать(запись.format(**набор)), (
                f"шаги дома разошлись с записью: {запись} на {набор}")
    # СКОБКА ОБЯЗАНА ЧТО-ТО РЕШАТЬ: снимешь её — и число обязано измениться хоть где-то.
    for род, запись, _п in ОЧЕРТАНИЯ:
        голая = запись.replace("( ", "").replace(" )", "")
        разошлось = any(_считать(запись.format(**н)) != _считать(голая.format(**н))
                        for н in НАБОРЫ)
        assert разошлось, f"скобка ничего не решает ни на одном наборе: {запись}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
