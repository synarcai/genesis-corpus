"""ДОМ МНОГОШАГОВОГО СЧЁТА (14.09, ступень 2, просьба holon-f9).

Вторая ступень лестницы (BBH) держит род `multistep_arithmetic_two`: дано выражение со
скобками и несколькими знаками, и надо назвать его значение. Замерено 14.09 по своду:
строк со СКОБКОЙ ВНУТРИ СКОБКИ — НОЛЬ. Скобка с двумя знаками в корпусе есть (334 строки,
«(8 + 5) + 3 × 8 = 45»), а вложенной — ни одной; и нигде не сказано, В КАКОМ ПОРЯДКЕ идут
шаги, — сказан лишь итог.

    ИТОГ НЕ ЕСТЬ ПУТЬ. Строка «((3 + 5) × 2) − 7 = 9» истинна и не учит ничему: из неё не
    видно, что считалось первым. Дом называет ШАГИ — «сначала 3 + 5 = 8, потом 8 × 2 = 16,
    потом 16 − 7 = 9», — и каждый шаг есть число, какое можно проверить порознь. Это тот же
    закон, по которому мир плана требует, чтобы конец шага был проверяем числом.

ТРИ РОДА ПО ДЕЛУ — по тому, ЧЕМ РЕШАЕТСЯ ПОРЯДОК ШАГОВ:

    скобка_в_скобке        «((a + b) × c) − d»: внутрь, потом наружу, потом остальное —
                           вложенность решает всё, и в корпусе её не было ни разу;
    две_скобки             «(a + b) × (c − d)»: две скобки НЕЗАВИСИМЫ, считаются порознь, и
                           лишь потом соединяются. Порядок между ними не важен — важно, что
                           обе прежде знака между ними;
    скобка_и_старшинство   «(a + b) × c − d»: скобка первой, а дальше решает СТАРШИНСТВО —
                           «×» прежде «−». Читатель, считающий слева направо, получит
                           другое число, и именно здесь он это увидит.

ГРАНИЦА ОБЪЯВЛЕНА: числа малы и ни один шаг не уходит ниже нуля. Отрицательные в корпусе
есть (464 строки), но они — иное дело, и мешать их с порядком шагов значит учить двум
вещам разом.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("скобка_в_скобке", "две_скобки", "скобка_и_старшинство")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "скобка_в_скобке": "скобка внутри скобки: внутрь, потом наружу, потом остальное",
    "две_скобки": "две независимые скобки считаются порознь и лишь потом соединяются",
    "скобка_и_старшинство": "скобка первой, а дальше «×» прежде «+» и «−»",
}

ЗНАКИ = {"+": lambda a, b: a + b, "−": lambda a, b: a - b, "×": lambda a, b: a * b}

# ОЧЕРТАНИЯ ОБЪЯВЛЕНЫ ПОИМЁННО. Каждое есть (род, запись, порядок шагов): запись — как
# выражение печатается, порядок — какие шаги и в каком порядке дом называет. Ни то ни
# другое не выводится из другого: печать говорит, ЧТО написано, порядок — КАК считать.
ОЧЕРТАНИЯ = (
    ("скобка_в_скобке", "( ( {a} + {b} ) × {c} ) − {d}",
     (("a", "+", "b"), (0, "×", "c"), (1, "−", "d"))),
    ("скобка_в_скобке", "( ( {a} − {b} ) + {c} ) × {d}",
     (("a", "−", "b"), (0, "+", "c"), (1, "×", "d"))),
    ("скобка_в_скобке", "{d} + ( ( {a} + {b} ) × {c} )",
     (("a", "+", "b"), (0, "×", "c"), ("d", "+", 1))),
    ("две_скобки", "( {a} + {b} ) × ( {d} − {c} )",
     (("a", "+", "b"), ("d", "−", "c"), (0, "×", 1))),
    ("две_скобки", "( {a} + {b} ) − ( {d} − {c} )",
     (("a", "+", "b"), ("d", "−", "c"), (0, "−", 1))),
    ("две_скобки", "( {a} × {b} ) − ( {c} + {d} )",
     (("a", "×", "b"), ("c", "+", "d"), (0, "−", 1))),
    ("скобка_и_старшинство", "( {a} + {b} ) × {c} − {d}",
     (("a", "+", "b"), (0, "×", "c"), (1, "−", "d"))),
    ("скобка_и_старшинство", "{d} + {a} × ( {b} − {c} )",
     (("b", "−", "c"), ("a", "×", 0), ("d", "+", 1))),
    ("скобка_и_старшинство", "( {a} − {b} ) × {c} + {d}",
     (("a", "−", "b"), (0, "×", "c"), (1, "+", "d"))),
)

НАБОРЫ = (
    {"a": 3, "b": 5, "c": 2, "d": 7}, {"a": 9, "b": 4, "c": 3, "d": 6},
    {"a": 7, "b": 2, "c": 4, "d": 5}, {"a": 12, "b": 8, "c": 3, "d": 9},
    {"a": 6, "b": 6, "c": 5, "d": 11}, {"a": 15, "b": 7, "c": 2, "d": 4},
    {"a": 8, "b": 3, "c": 6, "d": 20}, {"a": 4, "b": 9, "c": 5, "d": 13},
)

РАМКИ = {
    "ru": {"показ": "{выражение}: сначала {шаги}. ответ {итог}.",
           "потом": "потом ", "шаг": "{a} {знак} {b} = {c}"},
    "en": {"показ": "{выражение}: first {шаги}. the answer is {итог}.",
           "потом": "then ", "шаг": "{a} {знак} {b} = {c}"},
}


def _шаги(порядок, набор):
    """Числа шагов: место `k` берёт итог k-го шага, имя — число из набора."""
    итоги, вышло = [], []
    for левое, знак, правое in порядок:
        a = итоги[левое] if isinstance(левое, int) else набор[левое]
        b = итоги[правое] if isinstance(правое, int) else набор[правое]
        c = ЗНАКИ[знак](a, b)
        итоги.append(c)
        вышло.append((a, знак, b, c))
    return вышло


def страница(язык, очертание, набор):
    _род, запись, порядок = очертание
    шаги = _шаги(порядок, набор)
    if any(c < 0 for *_х, c in шаги):
        return None                     # граница объявлена: ни один шаг не ниже нуля
    рамки = РАМКИ[язык]
    сказ = [рамки["шаг"].format(a=a, знак=з, b=b, c=c) for a, з, b, c in шаги]
    сказ = [сказ[0]] + [рамки["потом"] + ш for ш in сказ[1:]]
    return рамки["показ"].format(выражение=запись.format(**набор),
                                 шаги=", ".join(сказ), итог=шаги[-1][3])


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for очертание in ОЧЕРТАНИЯ:
            for набор in НАБОРЫ:
                п = страница(язык, очертание, набор)
                if п:
                    вон.setdefault(п, (язык, очертание[0]))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД СЧИТАЕТ ВЫРАЖЕНИЕ САМ — спуском по старшинству над самой ЗАПИСЬЮ, не зная ни
# очертания, ни порядка шагов дома. Сверх итога он проверяет КАЖДЫЙ ШАГ: шаг обязан быть
# верным счётом, его слагаемые — либо числами выражения, либо итогами прежних шагов, число
# шагов — числом знаков, а последний итог — объявленным ответом.
#
#     ИТОГ НЕ ЕСТЬ ПУТЬ, И СУД ПРОВЕРЯЕТ ОБА. Строка с верным итогом и лживым шагом лжёт.
def _считать(запись):
    слова = запись.split()
    место = [0]

    def вперёд():
        return слова[место[0]] if место[0] < len(слова) else None

    def значение():
        с = вперёд()
        if с == "(":
            место[0] += 1
            v = сумма()
            if вперёд() != ")":
                raise ValueError("скобка не закрыта")
            место[0] += 1
            return v
        if с is None or not re.fullmatch(r"-?\d+", с):
            raise ValueError(f"не число: {с}")
        место[0] += 1
        return int(с)

    def произведение():
        v = значение()
        while вперёд() == "×":
            место[0] += 1
            v *= значение()
        return v

    def сумма():
        v = произведение()
        while вперёд() in ("+", "−"):
            з = вперёд()
            место[0] += 1
            п = произведение()
            v = v + п if з == "+" else v - п
        return v

    v = сумма()
    if место[0] != len(слова):
        raise ValueError("хвост не разобран")
    return v


_ШАГ = re.compile(r"(-?\d+) ([+−×]) (-?\d+) = (-?\d+)$")
_ОБРАЗЦЫ = {я: re.compile(re.escape(р["показ"])
                          .replace(r"\{выражение\}", r"(?P<выражение>[^:]+)")
                          .replace(r"\{шаги\}", r"(?P<шаги>.+)")
                          .replace(r"\{итог\}", r"(?P<итог>-?\d+)") + r"$")
            for я, р in РАМКИ.items()}


def судить(строка):
    """(судимо, истинно) — выражение посчитано заново, и каждый шаг проверен порознь."""
    for язык in ЯЗЫКИ:
        м = _ОБРАЗЦЫ[язык].fullmatch(строка.strip())
        if not м:
            continue
        запись = м.group("выражение")
        try:
            итог = _считать(запись)
        except (ValueError, IndexError):
            return True, False
        if итог != int(м.group("итог")):
            return True, False
        числа = {int(с) for с in запись.split() if re.fullmatch(r"-?\d+", с)}
        знаков = sum(1 for с in запись.split() if с in ЗНАКИ)
        куски = [к.strip() for к in м.group("шаги").split(",")]
        потом = РАМКИ[язык]["потом"]
        итоги = []
        for i, кусок in enumerate(куски):
            if i and not кусок.startswith(потом):
                return True, False
            ш = _ШАГ.fullmatch(кусок[len(потом):] if i else кусок)
            if not ш:
                return True, False
            a, з, b, c = int(ш.group(1)), ш.group(2), int(ш.group(3)), int(ш.group(4))
            if ЗНАКИ[з](a, b) != c:
                return True, False
            если_есть = set(числа) | set(итоги)
            if a not in если_есть or b not in если_есть:
                return True, False      # шаг взял число ниоткуда
            итоги.append(c)
        return True, len(куски) == знаков and итоги[-1] == итог
    return False, True


