#!/usr/bin/env python3
"""ДОМ ПЛАНА: приказ-ряд с условием и ОТЧЁТ ИСПОЛНЕНИЯ как страница мира.

Форма заказана holon (PLAN-GENUS-0907) под рынок речи-в-план: страница несёт ПРИКАЗ-РЯД
(«создай файл a.txt. затем запусти сборку. если exit = 0, посади.»), ОТЧЁТ наблюдения
(«files 1, runs 1, exit 0, millis 700») и ВЕРДИКТ, следующий из условия и наблюдения.

    ОТЧЁТ ЕСТЬ ЗАПИСЬ НАБЛЮДЕНИЯ, А НЕ РАССКАЗ О НЁМ. Он пишется леджером — «files 1, runs 1,
    exit 0, millis 700», — и потому не требует ни согласования, ни времени глагола: девять
    языков пишут его одинаково, и разнятся лишь слово отчёта и вердикт.

ЭТО НЕ УДОБСТВО, А ВЕРНОСТЬ ПРЕДМЕТУ. Кабина возвращает наблюдение записью, а не прозой; имена
леджеров (`files`, `runs`, `exit`, `millis`) суть имена наблюдения, и страница, переводящая их,
учила бы речи о несуществующем леджере.

ГЛАГОЛЫ АКТОВ ДОМ НЕ ОБЪЯВЛЯЕТ ЗАНОВО. Они уже стоя́т в доме хода (`actturn.ГЛАГОЛЫ`) тремя
формами на девяти языках; здесь объявлено лишь то, чего там нет: слово следования, ОБРАЗЕЦ
УСЛОВИЯ ЦЕЛИКОМ (порядок слов у немецкого и нидерландского иной — «wenn exit 0 ist»), акт
посадки и вопросные зачины.

ЧЕТЫРЕ РОДА, И У КАЖДОГО ВОПРОСНАЯ ПОВЕРХНОСТЬ:

    приказ и отчёт     «… если exit = 0, посади. отчёт: … exit 0 … — посажено.»
    вопрос о леджере   «отчёт: … какой exit у сборки? 0.»
    вопрос о счёте     «отчёт: … сколько запусков было? 1.»
    вопрос о вердикте  «если exit = 0, посади. отчёт: … exit 3 … посажено ли? нет.»

ОБЕ ВЕТКИ НА КАЖДОМ ЯЗЫКЕ: exit равен условию — посажено; не равен — не посажено. Вердикт
СЛЕДУЕТ из сличения, и суд проверяет его сличением, а не словарём.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from layer import PASSES, emit  # noqa: E402
import actturn as A  # noqa: E402
import planlang as P  # noqa: E402

ЦЕЛЬ = "datasets/genesis_plan.txt"
# АКТЫ, БЕРУЩИЕ ФАЙЛ: посадка и запуск объявлены здесь, прочее — у дома хода
АКТЫ = ("создать", "удалить", "прочитать", "дописать")
# СДВИГ ПАПКИ ОБЪЯВЛЕН ДОМОМ ХОДА, И БЕРЁТСЯ ОТТУДА, А НЕ ПОВТОРЯЕТСЯ
ФАЙЛОВ_ПОСЛЕ = {"создать": 1, "удалить": 0, "прочитать": 1, "дописать": 1}
ВЫХОДЫ = (0, 1, 2, 3)
МИЛЛИ = (700, 900, 1200, 450)
УСЛОВНОЕ = 0          # условие всякой страницы: exit = 0


def _отчёт(с, файлов, запусков, выход, милли):
    return (f"{с['отчёт']}: files {файлов}, runs {запусков}, "
            f"exit {выход}, millis {милли}")


def страницы(язык, акт, файл, выход, милли):
    с = P.СЛОВА[язык]
    приказ_акта = A.ГЛАГОЛЫ[язык][акт][0]
    файлов = ФАЙЛОВ_ПОСЛЕ[акт]
    посажено = выход == УСЛОВНОЕ
    вердикт = с["посажено"] if посажено else с["не_посажено"]
    условие = с["условие"].format(v=УСЛОВНОЕ, посади=с["посади"])
    приказ = (f"{приказ_акта} {с['файл']} {файл}. {с['затем']} {с['запусти']}. "
              f"{условие}.")
    отчёт = _отчёт(с, файлов, 1, выход, милли)
    # ВОПРОС СТОИ́Т В ОДНОМ ПРЕДЛОЖЕНИИ С ЛЕДЖЕРОМ, А НЕ ЗА ТОЧКОЙ ОТ НЕГО.
    #
    # Палата зачитывает строку лишь тогда, когда покрыто КАЖДОЕ её предложение; «¿aterrizó?
    # no.» в одиночку не проверить ничем — леджера в нём нет. Ворота записи назвали это
    # несудимостью двухсот страниц, и правильно назвали:
    #
    #     ВОПРОС, ОТОРВАННЫЙ ОТ СВОЕГО ЛЕДЖЕРА ТОЧКОЙ, НЕПРОВЕРЯЕМ. Тире держит их в одном
    #     предложении, и суд читает вопрос вместе с тем, чем он проверяется.
    return [
        f"{приказ} {отчёт} — {вердикт}.",
        f"{отчёт} — {с['какой_exit']} {выход}.",
        f"{отчёт} — {с['сколько_запусков']} 1.",
        # ОТВЕТ НЕСЁТ СВОЁ ОСНОВАНИЕ, А НЕ ОДНО СЛОВО.
        #
        # Палата режет строку по вопросительному знаку, и голое «no.» не читает никто — ни
        # мой суд, ни чужой: в нём нечего проверить. Ворота назвали это несудимостью 56
        # испанских страниц (русское «нет.» проходило по счастливой случайности — его читал
        # сосед). Ответ со сличением — «нет: exit 2 ≠ 0» — проверяем САМ ПО СЕБЕ.
        #
        #     ОТВЕТ, НЕ НЕСУЩИЙ СВОЕГО ОСНОВАНИЯ, ПРОВЕРЯЕМ ТОЛЬКО СОСЕДОМ ПО СТРОКЕ. Стои́т
        #     палате разрезать строку — и он становится словом без опоры.
        f"{условие}. {отчёт} — {с['посажено_ли']} "
        f"{с['да'] if посажено else с['нет']}: exit {выход} "
        f"{'=' if посажено else '≠'} {УСЛОВНОЕ}.",
    ]


def pass_shows(pass_i):
    out = []
    k = 0
    for язык in P.СЛОВА:
        for акт in АКТЫ:
            for i, выход in enumerate(ВЫХОДЫ):
                файл = A.ФАЙЛЫ[(АКТЫ.index(акт) + i) % len(A.ФАЙЛЫ)]
                милли = МИЛЛИ[(i + АКТЫ.index(акт)) % len(МИЛЛИ)]
                k += 1
                if k % len(PASSES) != pass_i:
                    continue
                out.extend(страницы(язык, акт, файл, выход, милли))
    return out


def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
