def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for ед, мн, класс, один, два, ру, ан in ИМЕНА:
            # ЧУЖОЕ ЧИСЛИТЕЛЬНОЕ БЕРЁТСЯ ИЗ ДРУГОГО КЛАССА, А НЕ ВПИСЫВАЕТСЯ РУКОЙ
            # (12.09, поймано своей же пробой): первая редакция ставила «*{ед} mmoja» ко
            # всякому имени — и при классе 1/2, где «mmoja» СВОЁ, звёздочка оказывалась при
            # верной форме, а суд звал страницу ложью.
            #
            #     ПРИМЕР ЧУЖОГО, ВПИСАННЫЙ ОДИН НА ВСЕХ, ПРИ КОМ-ТО ОКАЗЫВАЕТСЯ СВОИМ.
            чужой = next(о for _, _, к, о, _, _, _ in ИМЕНА if к != класс and о != один)
            общ = dict(ед=ед, мн=мн, класс=класс, один=один, два=два, ру=ру, ан=ан,
                       чужой=чужой)
            for род in РОДЫ:
                # КЛАСС БЕЗ ПЕРЕМЕНЫ ПОКАЗЫВАЕТСЯ ЛИШЬ ТЕМ, КТО ЕГО ИМЕЕТ: ставить этот род
                # при «kitabu» значило бы сказать, что и оно не меняется.
                if род == "класс без перемены" and ед != мн:
                    continue
                if род == "множественное меняет приставку" and ед == мн:
                    continue
                вон[рамки[род].format(**общ)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()

# СУД ЧИТАЕТ ТРИ ЗАКОНА, И ВСЕ ТРИ СОДЕРЖАТЕЛЬНЫ:
#   · числительное при имени обязано сойтись с объявленным для его класса;
#   · множественное имя берёт числительное множественного, единственное — единственного;
#   · звёздочка стои́т ровно при нарушении.
_ОДИН = {ед: о for ед, _, _, о, _, _, _ in ИМЕНА}
_ДВА = {мн: д for _, мн, _, _, д, _, _ in ИМЕНА}
_ДВА_ЕД = {ед: д for ед, мн, _, _, д, _, _ in ИМЕНА if ед == мн}
_ВСЕ_ЧИСЛА = set(_ОДИН.values()) | set(_ДВА.values())
_ПАРА = _re.compile(r"\b([a-z]{3,})\s+(" + "|".join(sorted(_ВСЕ_ЧИСЛА)) + r")\b")

_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _нарушает(тело):
    """Нарушает ли цитата закон дома: числительное чужого класса при имени."""
    for имя, число in _ПАРА.findall(тело.lstrip("*").strip()):
        законные = set()
        if имя in _ОДИН:
            законные.add(_ОДИН[имя])
        if имя in _ДВА:
            законные.add(_ДВА[имя])
        if имя in _ДВА_ЕД:
            законные.add(_ДВА_ЕД[имя])
        if законные and число not in законные:
            return True
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        if not _ПАРА.search(цитата.lstrip("*")):
            continue
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:110])
            беды += 1
    мутантов = 0
    for показ in ПОКАЗЫ:
        слова = показ.split(" ")
        порча = None
        for i, сл in enumerate(слова):
            голое = сл.strip("«».,:;")
            if голое in _ВСЕ_ЧИСЛА:
                чужое = next(ч for ч in sorted(_ВСЕ_ЧИСЛА) if ч != голое)
                порча = " ".join(слова[:i] + [сл.replace(голое, чужое)] + слова[i + 1:])
                break
        if not порча or порча == показ or порча in ПОКАЗЫ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:110])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    ложные = (
        "по-суахили «kitabu mmoja» — одна книга.",
        "по-суахили «mtu kimoja» — один человек.",
        "по-суахили «vitabu wawili» — две книги.",
        "«*kitabu kimoja» — так не говорят.",
    )
    for ложь in ложные:
        ПОКАЗЫ[ложь] = ("ru", "проба")
        try:
            if судить(ложь) != (True, False):
                print("  ЛОЖНАЯ СТРАНИЦА ПРОШЛА:", ложь[:100])
                беды += 1
        finally:
            del ПОКАЗЫ[ложь]
    написано = {род for _, род in ПОКАЗЫ.values()}
    if написано != set(РОДЫ):
        print(f"  РОДЫ РАЗОШЛИСЬ: обещано {sorted(РОДЫ)}, написано {sorted(написано)}")
        беды += 1
