#!/usr/bin/env python3
"""ДОМ ДВУХ ОТКАЗОВ (14.09, куплен нулём пробы — и НЕМЕДЛЕННО ПЕРЕСТРОЕН, когда ноль оказался
нулём СЛОВ, а не нулём ДЕЛА).

ИСТОРИЯ ЭТОГО ДОМА ЕСТЬ ЕГО ГЛАВНЫЙ УРОК. Проба на ноль сказала: «деление на ноль» — 0 строк,
«division by zero» — 0. Я купил на это дом. А прибор очертаний, пущенный через час, назвал
`zerodivforms` — дом, живущий с прежних дней, 346 страниц, и говорящий ровно то же ДРУГИМИ
СЛОВАМИ: «сколько будет 4 ÷ 0? делить 4 на 0 нельзя: 0 × 1 = 0, и 0 × 2 = 0, и ни одно
произведение не равно 4».

    ПРОБА НА НОЛЬ МЕРИТ СЛОВА, А НЕ ДЕЛА. Ноль слов не есть ноль дела: дом может делать то
    же самое, называя это иначе, и проба его не увидит. Потому находка пробы есть ПОВОД
    СПРОСИТЬ, А НЕ ПРАВО СТРОИТЬ, и первое действие при ней — то же, что при находке для
    прибора: НЕ ПИСАТЬ, А СПРОСИТЬ, НЕ НАПИСАНО ЛИ.

Дом перестроен в тот же час. Из трёх его родов два повторяли `zerodivforms` («4 ÷ 0 нельзя»
и «0 ÷ 2 = 0») и убраны. Осталось то, чего нет нигде, — РАЗЛИЧИЕ ДВУХ ОТКАЗОВ:

    НЕВОЗМОЖНОЕ ПО ЧИСЛУ И НЕВОЗМОЖНОЕ ПО МИРУ — РАЗНЫЕ ОТКАЗЫ. «12 ÷ 0» не имеет ответа
    ПО ЧИСЛУ: нет числа, какое, умноженное на ноль, дало бы двенадцать. А «отдать 5 яблок из
    3» невозможно НЕ ПО ЧИСЛУ — число тут есть, и оно −2, — а ПО МИРУ: яблок минус два не
    бывает. Отказ, не различающий этих двух, учит бояться обоих одинаково и не понимать ни
    одного.

    НЕВОЗМОЖНОЕ ПО ЧИСЛУ И НЕВОЗМОЖНОЕ ПО МИРУ — РАЗНЫЕ ОТКАЗЫ, И ЭТО ГЛАВНОЕ. «5 ÷ 0» не
    имеет ответа НИКАКОГО: нет числа, какое, умноженное на ноль, дало бы пять. А «отдать 8
    яблок из 5» невозможно НЕ ПО ЧИСЛУ — число тут есть, и оно −3, — а по миру: яблок
    минус три не бывает. Отказ, не различающий этих двух, учит бояться обоих одинаково и не
    понимать ни одного.

ТРИ РОДА ПО ДЕЛУ — И ВСЕ ТРИ О РАЗЛИЧИИ, А НЕ О САМИХ ОТКАЗАХ ПОРОЗНЬ:

    по_числу       отказ назван ПО ЧИСЛУ и сказано, чего именно нет: числа, какое,
                   умноженное на ноль, дало бы делимое. Не «нельзя», а «нет такого числа»;
    по_миру        отказ назван ПО МИРУ, и разность ПРЕДЪЯВЛЕНА числом: число есть, и оно
                   отрицательно, — а мира для него нет;
    оба_рядом      две невозможности на одной странице, и сказано, ЧЕМ они разнятся. Без
                   этого рода первые два учат двум запретам, а не одному различию.

    ОТКАЗ С ПРИЧИНОЙ, А НЕ ЗАПРЕТ. «На ноль не делят» есть правило, какое читатель запомнит
    и не поймёт; «нет числа, какое, умноженное на ноль, дало бы 12» есть довод, и из него
    видно, ПОЧЕМУ правило таково.
"""
