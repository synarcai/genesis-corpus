def страница(язык, род, n, пара):
    рамки = РАМКИ[язык]
    было, надо = пара
    if род == "по_числу":
        return рамки["по_числу"].format(n=n)
    if надо <= было:
        return None            # отдать столько, сколько есть, можно — отказывать не в чем
    # АНГЛИЙСКОЕ ИМЯ ГНЁТСЯ ЗАКОНОМ, А НЕ СТОИТ ЛИТЕРАЛОМ (16.09, `scripts/half_law.py`):
    # правота «apples» держалась тем, что пары чисел дома не дают единицы.
    имена = dict(Иb=by_count(надо, "apples"), Иd=by_count(надо - было, "apples"))
    if род == "по_миру":
        return рамки["по_миру"].format(a=было, b=надо, d=надо - было, **имена)
    return рамки["оба_рядом"].format(n=n, a=было, b=надо, d=надо - было, **имена)


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for n in ЧИСЛА:
            вон.setdefault(страница(язык, "по_числу", n, (0, 0)), (язык, "по_числу"))
        for пара in ПАРЫ:
            п = страница(язык, "по_миру", 0, пара)
            if п:
                вон.setdefault(п, (язык, "по_миру"))
        # РОД «ОБА РЯДОМ» БЕРЁТ ПО ОДНОМУ ЧИСЛУ НА ПАРУ: он показывает РАЗЛИЧИЕ, и различие
        # от выбора делимого не зависит вовсе.
        for место, пара in enumerate(ПАРЫ):
            п = страница(язык, "оба_рядом", ЧИСЛА[место % len(ЧИСЛА)], пара)
            if п:
                вон.setdefault(п, (язык, "оба_рядом"))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД ПРОВЕРЯЕТ ДОВОД, А НЕ ЗАПОМИНАЕТ ЗАПРЕТ. Он считает разность сам, требует, чтобы
# делимое в отказе о нуле было НЕ НУЛЬ (ибо «0 ÷ 0» есть третий случай, и дом его не берёт),
# и чтобы в роде «больше, чем есть» отдать и правда просили больше, чем было.
def _образцы(язык):
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык][род])
        for дыра, узор in (("n", r"\d+"), ("a", r"\d+"), ("b", r"\d+"), ("d", r"\d+"),
                           # ИМЯ — ДЫРА, А НЕ БУКВА: подмена формы при числе есть ложь
                           ("Иb", "[a-z]+"), ("Иd", "[a-z]+")):
            дыра_о = re.escape("{" + дыра + "}")
            первый = True
            while дыра_о in о:
                о = о.replace(дыра_о, f"(?P<{дыра}>{узор})" if первый else f"(?P={дыра})", 1)
                первый = False
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


# ЗАКОН СКЕЛЕТА (16.09, тот же, что дан тринадцати домам 13.09). Прибор [СУД ДОМА ЛОВИТ
# ПОРЧУ] вписывает порченую страницу В НАБОР показов на время опыта и спрашивает суд о
# странице, которая в наборе ЕСТЬ. Дом, отвечающий по набору, стережёт себя
# ПРИНАДЛЕЖНОСТЬЮ, а не проверкой: испорченная проза рамки проходит, ибо словарь страницы
# не изменился.
#
#     СТРАНИЦА ОБЯЗАНА СОБИРАТЬСЯ ХОТЬ ОДНОЙ ОБЪЯВЛЕННОЙ РАМКОЙ ДОМА: дыры рамки берут что
#     угодно, проза между ними — только себя. Подмена двух слов прозы местами ломает
#     порядок и ловится, хотя ни одно слово страницы не переменилось.
_re_скелет = re.compile(r"\{[^{}]+\}")


def _образцы_рамок():
    """Рамки дома, обращённые в образцы: дыра берёт что угодно, проза — только себя."""
    вон = []
    ряды = РАМКИ.values() if isinstance(РАМКИ, dict) else РАМКИ
    for ряд in ряды:
        рамки = ряд.values() if isinstance(ряд, dict) else ([ряд] if isinstance(ряд, str) else ряд)
        for рамка in рамки:
            if not isinstance(рамка, str):
                continue
            куски, конец = [], 0
            for м in _re_скелет.finditer(рамка):
                куски.append(re.escape(рамка[конец:м.start()]))
                куски.append(r"[\s\S]+?")
                конец = м.end()
            куски.append(re.escape(рамка[конец:]))
            вон.append(re.compile("^" + "".join(куски) + "$"))
    return tuple(вон)


_ОБРАЗЦЫ_РАМОК = _образцы_рамок()


def _скелет_объявлен(с):
    """Собирается ли страница хоть одной объявленной рамкой дома."""
    return any(о.match(с) for о in _ОБРАЗЦЫ_РАМОК)


def судить(строка):
    """(судимо, истинно) — довод проверен счётом, а не сверен со списком запретов."""
    # СКЕЛЕТ ПРОВЕРЯЕТСЯ У СТРОКИ, КОТОРУЮ ДОМ ПРИЗНАЛ СВОЕЙ ПО НАБОРУ (16.09). Прибор
    # [СУД ДОМА ЛОВИТ ПОРЧУ] вписывает порчу В НАБОР показов и спрашивает суд о странице,
    # которая в наборе ЕСТЬ: дом, отвечающий по набору, стережёт себя ПРИНАДЛЕЖНОСТЬЮ, а не
    # проверкой, и содержательный его закон не спрашивается ни разу.
    #
    #     ЗАКОН, ПОСТАВЛЕННЫЙ ПРЕЖДЕ ВСЯКОГО ОПОЗНАНИЯ, СУДИТ ЧУЖИЕ СТРАНИЦЫ; ЗАКОН,
    #     ПОСТАВЛЕННЫЙ ЗА ОПОЗНАНИЕМ РАМКОЙ, НЕ СПРАШИВАЕТСЯ ТАМ, ГДЕ ПОРЧА ЛОМАЕТ РАМКУ.
    #     Место ему — там, где дом уже сказал «страница моя», но ещё не сказал «она верна».
    if строка.strip() in ПОКАЗЫ and not _скелет_объявлен(строка.strip()):
        return True, False
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            if род == "по_числу":
                # НОЛЬ НА НОЛЬ ЕСТЬ ТРЕТИЙ СЛУЧАЙ, и дом его не берёт: там ответом было бы
                # ВСЯКОЕ число, а это иное дело, чем «ответа нет».
                return True, int(д["n"]) > 0
            было, надо, разность = int(д["a"]), int(д["b"]), int(д["d"])
            ладно = надо > было and разность == надо - было
            # ДВА СУДА НА ОДИН ПОКАЗ: счёт и язык. Форма имени, не отвечающая числу, есть
            # ложь грамматики, и она видна суду так же ясно, как ложь арифметики.
            for дыра, счёт in (("Иb", надо), ("Иd", разность)):
                если = д.get(дыра)
                if если is not None and если != by_count(счёт, "apples"):
                    return True, False
            if род == "по_миру":
                return True, ладно
            return True, ладно and int(д["n"]) > 0
    return False, True


