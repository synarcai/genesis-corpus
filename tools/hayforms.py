def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for ед, мн in ВЕЩИ:
            общ = dict(есть=ЕСТЬ["наст"], прош=ЕСТЬ["прош"], ед=ед, мн=мн,
                       ед_стоит=СТОИТ["ед"], мн_стоит=СТОИТ["мн"],
                       пл2=plgram.форма(ПОЛЬСКОЕ, 2), св2=plgram.связка("наст", 2),
                       пл5=plgram.форма(ПОЛЬСКОЕ, 5), св5=plgram.связка("наст", 5),
                       перевод=ПЕРЕВОД[ед][0 if язык == "ru" else 1])
            for род in РОДЫ:
                вон[рамки[род].format(**общ)] = (язык, род)
    return вон


