for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _образцы_рамок():
    """Рамки дома, обращённые в образцы: дыра берёт что угодно, проза — только себя."""
    вон = []
    for _язык, ряд in РАМКИ.items():
        for рамка in ряд.values():
            куски, конец = [], 0
            for м in _re_скелет.finditer(r"", рамка) if False else _re_скелет.finditer(рамка):
                куски.append(_re_дом.escape(рамка[конец:м.start()]))
                куски.append(r"[\s\S]+?")
                конец = м.end()
            куски.append(_re_дом.escape(рамка[конец:]))
            вон.append(_re_дом.compile("^" + "".join(куски) + "$"))
    return tuple(вон)


_ОБРАЗЦЫ_РАМОК = _образцы_рамок()


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома и ничья более.

        СУД, ЧИТАЮЩИЙ ПО ПРИЗНАКУ, А НЕ ПО ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, ЗОВЁТ ЛОЖЬЮ ЧУЖУЮ
        РЕЧЬ, СОВПАВШУЮ С НИМ ФОРМОЙ. Идиома взята у соседей сразу верная.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # СКЕЛЕТ СТРАНИЦЫ ОБЯЗАН БЫТЬ ОДНИМ ИЗ ОБЪЯВЛЕННЫХ (13.09): [СУД ДОМА ЛОВИТ ПОРЧУ]
    # вписывает порчу В НАБОР и спрашивает суд о странице, КОТОРАЯ В НАБОРЕ ЕСТЬ.
    #
    #     СУД, ЧИТАЮЩИЙ ЛИШЬ ЦИТАТЫ, СТЕРЕЖЁТ ЛИШЬ ЦИТАТЫ; ОСТАЛЬНАЯ СТРАНИЦА У НЕГО НЕ
    #     ПРОВЕРЯЕТСЯ, А ЛИШЬ ЧИСЛИТСЯ.
    if not any(о.match(с) for о in _ОБРАЗЦЫ_РАМОК):
        return True, False
    return True, True


