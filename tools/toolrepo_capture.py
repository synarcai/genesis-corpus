#!/usr/bin/env python3
"""ПРИБОР СЪЁМКИ ПРОГОНОВ дома `toolrepo`: настоящий вывод бегунов тестов, снятый один раз (25.09).

Ведущий: ход мира на странице прогона — НАСТОЯЩИЙ вывод бегуна, не объявленные строки. Бегун идёт не при каждой
сборке свода (время бегуна и имя сборки плавают — свод перестал бы быть воспроизводимым), а однажды, этим прибором:
репозиторий дома кладётся в папку, мир-процесс держит свои прогоны в `.ozar/acts/<имя>` (как мир ядра `process.rs`:
отчёт — stdout и stderr одним файлом в порядке записи, `lines` — число переводов строки, `millis` — стенное время,
`exit` — код), каждый прогон исполняется, и снятое ложится семенем в `tools/seeds/toolrepo_runs.json`. Дом читает его и
печатает отчёт строками хода мира; самопроверка дома сверяет снятое с объявленным кодом.

СОСТОЯНИЯ ПРОЕКТА (27.09, наряд ведущего: у прогона оба исхода, иное число тестов): мир объявляет правки проекта
одним актом (`repoworld.ПРАВКИ_ПРОЕКТА`), и всякий прогон снимается с каждого состояния, какое различает его код, —
семя: имя прогона → отпечаток состояния (код прогона и его команда) → снятое. Снятое прежде не переснимается: время
бегуна плавает, и страница, стоявшая на нём, осталась бы прежней лишь со старым отчётом.

    ОРУДИЕ, ПЕРЕПИСЫВАЮЩЕЕ ДЕРЕВО, НЕ ПИШЕТ БЕЗ ДОВОДА. Самопроверка домов зовёт всякий файл парка без доводов;
    прибор, который при этом снимал бы прогоны заново, переписывал бы время бегуна посреди суда. Без доводов он
    только читает: снятое верно, пока отпечаток состояния (код прогона и его команда) тот же, что при съёмке.

    python3 tools/toolrepo_capture.py            # самопроверка без процессов: отпечатки и строки снятого
    python3 tools/toolrepo_capture.py --сверить  # снять заново: итог и строки те же, числа и порядок нитей плавают
    python3 tools/toolrepo_capture.py --снять    # снять недостающее и записать; снятое прежде остаётся
    python3 tools/toolrepo_capture.py --заново   # снять всё заново и записать

МИР ПРОЦЕССА С ДОМОМ (27.09, слово ведущего: орган и дом видят одну строку отчёта): с доводом `--процесс <ozar_process>`
прибор гонит прогон через сервер мира процесса ядра (`ozar_process <мир> <дом>`, М-2069) — отчёт называет пути от
дома мира («  File "tests/test_main.py", line 5, …»), как их увидит орган; меры и ряды — ответ мира строка в строку.
"""
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import repoworld as R  # noqa: E402 — объявление мира: код проекта, его состояния и прогоны

ЦЕЛЬ = R.СЕМЯ_ПРОГОНОВ


def нужные():
    """{(имя прогона, отпечаток): файлы проекта} — всякий прогон на всяком состоянии, какое различает его код."""
    вон = {}
    for _состояние, проект in R.состояния():
        for имя in R.ПРОГОНЫ:
            вон.setdefault((имя, R.отпечаток(имя, проект)), проект)
    return вон


def _через_мир(мир, корень, имя, процесс):
    """Снятое одного прогона ответом сервера мира процесса: меры runs · exit · millis · lines и ряды отчёта."""
    ответ = subprocess.run([процесс, str(мир), str(корень)], input=json.dumps({"act": "run", "object": имя}) + "\n",
                           capture_output=True, text=True, cwd=мир, check=True).stdout
    р = json.loads(ответ.splitlines()[0])
    меры = {м["ledger"]: м["value"] for м in р["measures"]}
    строки = [ряд[2] for ряд in р.get("rows") or []]
    return {"exit": меры["exit"], "millis": меры["millis"], "lines": меры["lines"], "report": строки}


def снять(проект, имена, процесс=None):
    """{имя: снятое} — прогоны `имена` на проекте в состоянии `проект`; с `процесс` — через мир процесса ядра."""
    корень = pathlib.Path(tempfile.mkdtemp(prefix="toolrepo-"))
    try:
        for путь, строки in проект.items():
            файл = корень / путь
            файл.parent.mkdir(parents=True, exist_ok=True)
            файл.write_text("".join(с + "\n" for с in строки), encoding="utf-8")
        мир = корень / ".ozar"
        (мир / "acts").mkdir(parents=True)
        (мир / "reports").mkdir()
        вон = {}
        for имя in имена:
            act = мир / "acts" / имя
            act.write_text(f"#!/bin/sh\ncd .. && {R.ПРОГОНЫ[имя]}\n", encoding="utf-8")
            act.chmod(0o755)
            if процесс:
                вон[имя] = _через_мир(мир, корень, имя, процесс)
                continue
            лог = мир / "reports" / f"{имя}.log"
            with open(лог, "wb") as out:
                начало = time.monotonic()
                код = subprocess.run([str(act)], cwd=мир, stdin=subprocess.DEVNULL, stdout=out, stderr=out,
                                     env={**os.environ}).returncode
                millis = int((time.monotonic() - начало) * 1000)
            отчёт = лог.read_bytes()
            вон[имя] = {"exit": код, "millis": millis, "lines": отчёт.count(b"\n"),
                        "report": отчёт.decode("utf-8").split("\n")[:-1] if отчёт.endswith(b"\n")
                        else отчёт.decode("utf-8").split("\n")}
        return вон
    finally:
        shutil.rmtree(корень, ignore_errors=True)


def _снятое():
    return json.loads(ЦЕЛЬ.read_text(encoding="utf-8")) if ЦЕЛЬ.exists() else {}


def _самопроверка():
    """Без процессов: снято ровно то, что объявлено, — всякий прогон на всяком состоянии проекта; снятое лежит под
    своим отпечатком; lines сходится с отчётом."""
    было, нужно, беды = _снятое(), нужные(), []
    есть = {(имя, знак) for имя, снятые in было.items() for знак in снятые}
    for имя, знак in sorted(set(нужно) - есть):
        беды.append(f"{имя}: состояние {знак} не снято — снять: --снять")
    for имя, знак in sorted(есть - set(нужно)):
        беды.append(f"{имя}: снято состояние {знак}, какого мир не объявляет")
    for имя, снятые in было.items():
        for знак, снятое in снятые.items():
            if снятое.get("source") != знак:
                беды.append(f"{имя}: снятое под {знак} несёт отпечаток {снятое.get('source')}")
            if not снятое["lines"] <= len(снятое["report"]) <= снятое["lines"] + 1:
                беды.append(f"{имя} {знак}: lines {снятое['lines']}, а строк отчёта {len(снятое['report'])}")
    for беда in беды:
        print("  БЕДА", беда)
    print(f"СЪЁМКА ПРОГОНОВ {'FAIL' if беды else 'PASS'}: прогонов {len(R.ПРОГОНЫ)}, снятых состояний {len(есть)}, "
          f"объявленных {len(нужно)}, бед {len(беды)}")
    return 1 if беды else 0


ЧИСЛО = re.compile(r"\d+")
# строка прогресса бегуна: точки и «k/n» — сколько тестов нить уже кончила к той минуте
ПРОГРЕСС = re.compile(r"^\.*(?: \d+/\d+)?$")


def _строки(отчёт):
    """Строки отчёта, какие обязаны повториться: без пустых и строк прогресса, числа — знаком «#»."""
    return sorted(ЧИСЛО.sub("#", с) for с in отчёт if с.strip() and not ПРОГРЕСС.match(с))


def сверить():
    """Снять заново и сравнить со снятым: exit и строки итога бегуна обязаны совпасть; прочие строки — тем же
    множеством. Числа (время бегуна, номер нити) плавают; порядок блоков и точек прогресса — дело бегуна: cargo гоняет
    тесты нитями, и какой тест кончит раньше, решает не проект. Разница видна глазу."""
    было, беды = _снятое(), []
    for (имя, знак), проект in нужные().items():
        a, b = было.get(имя, {}).get(знак), снять(проект, [имя])[имя]
        if a is None:
            беды.append(f"{имя} {знак}: не снят")
            continue
        итоги = [[ЧИСЛО.sub("#", с) for с in x["report"] if с.startswith(("test result:", "Ran ", "OK", "FAILED"))]
                 for x in (a, b)]
        if a["exit"] != b["exit"] or итоги[0] != итоги[1]:
            беды.append(f"{имя} {знак}: exit {a['exit']} → {b['exit']}, итог {итоги[0]} → {итоги[1]}")
        if _строки(a["report"]) != _строки(b["report"]):
            беды.append(f"{имя} {знак}: строки отчёта разнятся словами")
        elif a["report"] != b["report"]:
            print(f"  {имя} {знак}: плавают числа и порядок нитей (lines {a['lines']} → {b['lines']})")
    for беда in беды:
        print("  БЕДА", беда)
    print(f"СВЕРКА ПРОГОНОВ {'FAIL' if беды else 'PASS'}: состояний {len(нужные())}, бед {len(беды)}")
    return 1 if беды else 0


def main():
    if "--сверить" in sys.argv:
        return сверить()
    if "--снять" not in sys.argv and "--заново" not in sys.argv:
        return _самопроверка()
    было = {} if "--заново" in sys.argv else _снятое()
    процесс = sys.argv[sys.argv.index("--процесс") + 1] if "--процесс" in sys.argv else None
    вон = {имя: {} for имя in R.ПРОГОНЫ}
    for (имя, знак), проект in нужные().items():
        снятое = было.get(имя, {}).get(знак)
        if снятое is None:
            снятое = снять(проект, [имя], процесс)[имя]
            снятое["source"] = знак
            print(f"{имя} {знак}: exit {снятое['exit']} · millis {снятое['millis']} · lines {снятое['lines']}")
            for строка in снятое["report"]:
                print("    |", строка)
        вон[имя][знак] = снятое
    ЦЕЛЬ.write_text(json.dumps(вон, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
