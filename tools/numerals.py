#!/usr/bin/env python3
"""ДОМ ЧИСЛИТЕЛЬНЫХ: назвать число словами языка и прочесть его обратно.

Закон составного числительного жил внутри арифметического суда — там,
где числа ЧИТАЮТ. Но это закон ЯЗЫКА, а не закон суда: тот же закон
нужен всякому, кто числа ГОВОРИТ. Свод, желавший сказать «сорок два
минус пять будет тридцать семь», не имел иного пути, кроме как выписать
числительные рукой — то есть завести второй список рядом с таблицей
пакета, и разойтись с нею в первый же день.

ЗДЕСЬ ЗАКОН ОДИН И ОБРАТИМ. `назвать` раскладывает число по объявленным
ступеням таблицы; `прочесть` складывает слова обратно по тому же закону
разрядов. Они проверяют друг друга: имя, которое не читается обратно в
то же число, НЕ ВЫДАЁТСЯ вовсе — честное молчание вместо правдоподобной
поверхности. Никакой род не может быть назван языком, который его не
объявил, и это видно числом, а не догадкой.

ЗАКОН РАЗРЯДОВ, всеобщий и без флагов: меньшее, чем СТУПЕНЬ предыдущего,
прибавляется («twenty one» = 21, «noventa y nueve» = 99, «three and a
half» = 3½, «сорок два» = 42); степень десяти, большая предыдущего,
умножает («two hundred» = 200). Всё прочее не составное — и «one two»
остаётся двумя величинами, отчего читающий честно немеет.
"""

import json
import pathlib
from fractions import Fraction

ПАКЕТЫ = pathlib.Path(__file__).resolve().parent / "langpacks"


def ступень(х):
    """Разряд величины: до какой точности она сказана.

    Двадцать сказано с точностью до десятка, три — до единицы, сто —
    до сотни. Это и есть мера, решающая, СКЛАДЫВАЕТСЯ ли следующее
    числительное с предыдущим.
    """
    if х <= 0:
        return Fraction(1)
    ш = Fraction(1)
    while х % (ш * 10) == 0:
        ш *= 10
    return ш


def составить(а, б):
    """Величина составного числительного, или None, если не составное."""
    if б < ступень(а):
        return а + б
    if б > а >= 1 and б >= 100 and ступень(б) == б:
        return а * б
    return None


def таблица(язык):
    """{значение: слово} по объявлению пакета, или {} — пакета нет."""
    ф = ПАКЕТЫ / f"{язык}.json"
    try:
        п = json.loads(ф.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    вон = {}
    for ключ, слово in (п.get("numerals") or {}).items():
        try:
            в = Fraction(str(ключ))
        except (ValueError, ZeroDivisionError):
            continue
        if в == int(в) and в >= 0:
            вон[int(в)] = str(слово)
    return вон


# ЭТО ПРИБОР КОРПУСА, А НЕ ЗАКОН ОРГАНИЗМА, и граница названа прежде повода.
# Организм не вправе читать объявленное: числительное он обязан ЧЕКАНИТЬ сам —
# наполнителями операндной позиции купленной формы (слово d5, 04.09: «список
# есть подгон под известные языки и умрёт на тридцатом; чеканка работает на
# любом, включая тот, которого в пакетах нет»). Здешняя функция служит МЕРЕ:
# ею я считаю по своду, сколько строк несут число словом, и отвечаю числом на
# вопросы соседей. Ни один суд и ни одна дорога её не зовут.
#
# ЧИСЛИТЕЛЬНОЕ ЛЮБОГО ОБЪЯВЛЕННОГО ЯЗЫКА (04.09). Повод — рынок обмена holon:
# его страж отсекал строки с ЦИФРОЙ и со счётными словами латиницы-кириллицы до
# десяти, и оттого 662 строки словесной арифметики тринадцати языков проходили в
# рамку обмена как приветствия: «soixante moins dix égale cinquante», «ሁለት ሲባዛ
# ሶስት እኩል ስድስት». Страж по БУКВАМ не закроет их никогда; страж по ОБЪЯВЛЕНИЮ
# закрывает разом, ибо числительные всех языков объявлены пакетами, и второго
# списка заводить не нужно.
_ВСЕ_СЛОВА = None


def все_числительные():
    """{слово: (язык, значение)} по всем объявленным пакетам — читается однажды."""
    global _ВСЕ_СЛОВА
    if _ВСЕ_СЛОВА is None:
        вон = {}
        for ф in sorted(ПАКЕТЫ.glob("*.json")):
            for в, слово in таблица(ф.stem).items():
                вон.setdefault(слово, (ф.stem, в))
        _ВСЕ_СЛОВА = вон
    return _ВСЕ_СЛОВА


def есть_числительное(строка):
    """(слово, язык, значение) — первое числительное ЛЮБОГО объявленного языка
    в строке, или None. Слово ищется целиком: письмо без пробелов проверяется
    вхождением, письмо с пробелами — по границе слова."""
    все = все_числительные()
    низ = строка.lower()
    for слово, (язык, в) in все.items():
        if not слово:
            continue
        сл = слово.lower()
        i = низ.find(сл)
        while i >= 0:
            слева = низ[i - 1] if i else " "
            справа = низ[i + len(сл)] if i + len(сл) < len(низ) else " "
            # для письма без пробелов границы нет — вхождение и есть слово
            без_пробелов = not any(c.isspace() for c in строка.strip())
            if без_пробелов or (not слева.isalpha() and not справа.isalpha()):
                return слово, язык, в
            i = низ.find(сл, i + 1)
    return None


def _путь(остаток, текущее, табл, глубина=0):
    """[слова] на остаток, или None — этим путём число не сказать.

    ЖАДНОСТЬ БЕЗ ВОЗВРАТА ЗАСТРЕВАЕТ НА ОБЪЯВЛЕННОМ СОСТАВНОМ. Русский
    пакет объявляет и «тридцать», и «тридцать шесть»; жадный ход брал
    на 137 сперва сто, затем ТРИДЦАТЬ ШЕСТЬ — и оставался с единицей,
    которую уже некуда прибавить (единица не мельче ступени ста
    тридцати шести). Число называлось невозможным, будучи выразимым.
    Возврат ищет путь, на котором КАЖДЫЙ шаг законен по разрядам, — и
    потому имя верно по построению, а не по проверке.
    """
    if остаток == 0:
        return []
    if глубина > 8:
        return None
    for з in sorted((k for k in табл if 0 < k <= остаток), reverse=True):
        новое = (Fraction(з) if текущее is None
                 else составить(текущее, Fraction(з)))
        if новое is None:
            continue
        хвост = _путь(остаток - з, новое, табл, глубина + 1)
        if хвост is not None:
            return [табл[з]] + хвост
    return None


def назвать(n, табл, связки=()):
    """Число словами языка, или None — язык его назвать не может.

    Имя строится путём, законным по разрядам на каждом шагу, и ПРОВЕРЯЕТСЯ
    чтением: то, что `прочесть` не возвращает в то же число, не выдаётся.

    НАЗВАННЫЙ ПРЕДЕЛ: язык, объявивший СВЯЗКИ числительных, здесь не
    называется вовсе. Испанское «noventa y nueve» и португальское
    «cento e trinta e sete» ставят связку по СВОИМ правилам (испанское —
    лишь перед последней единицей, португальское — между всеми
    членами), и правил этих пакет пока не объявляет. Выдать «cuarenta
    dos» значило бы сказать неидиоматично, а неидиоматичная поверхность
    учит неверному языку с полной судимостью. Молчание честнее.
    """
    if not табл or n < 0 or связки:
        return None
    if n in табл:
        имя = табл[n]
        return имя if прочесть(имя, табл) == n else None
    куски = _путь(n, None, табл)
    if куски is None:
        return None
    имя = " ".join(куски)
    return имя if прочесть(имя, табл) == n else None


def прочесть(имя, табл):
    """Величина сказанного словами числа, или None.

    Слова читаются по таблице и складываются законом разрядов; лишнее
    слово или несоставимая пара делают чтение невозможным — и это
    ОТКАЗ, а не догадка по остатку.
    """
    по_слову = {с.lower(): з for з, с in табл.items()}
    итог = None
    for слово in имя.split():
        з = по_слову.get(слово.lower())
        if з is None:
            return None
        if итог is None:
            итог = Fraction(з)
            continue
        вместе = составить(итог, Fraction(з))
        if вместе is None:
            return None
        итог = вместе
    if итог is None:
        return None
    return int(итог) if итог == int(итог) else итог
