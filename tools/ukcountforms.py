    # ЯЗЫК ОБЪЯСНЕНИЯ ПРОВЕРЯЕТСЯ ПО ВЫХОДУ, А НЕ ПО ЗАМЫСЛУ (13.09).
    #
    # Дом писал «один яблуко» (one apples): украинскую ячейку он считал по закону, а
    # английскую скобку подставлял одной и той же множественной формой. Поймал не суд и
