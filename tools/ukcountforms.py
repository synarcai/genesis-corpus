    #     ПРОВЕРКА, ЧИТАЮЩАЯ ЗАМЫСЕЛ ДОМА, ПОВТОРЯЕТ ЕГО ОШИБКУ; проверка, читающая
    #     НАПИСАННУЮ СТРОКУ, её видит.
