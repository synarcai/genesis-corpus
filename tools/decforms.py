#!/usr/bin/env python3
"""ДОМ ДЕСЯТИЧНОЙ ЗАПИСИ ДОЛИ — ТО ЖЕ ЧИСЛО, ЗАПИСАННОЕ ИНАЧЕ.

    ДЕСЯТИЧНОЙ ЗАПИСИ ДОЛИ В СВОДЕ ПОЧТИ НЕТ. Замер 11.09 по 237 мирам показов: равенство
    «0,5 = 1/2» или «3/4 = 0.75» встречается ШЕСТНАДЦАТЬ раз, и все шестнадцать — в одном мире
    единиц алгебры, строкой без вывода («1/4 = 0.25. четверть. quarter.»).

    ПРИ ЭТОМ САМИ ДЕСЯТИЧНЫЕ ЧИСЛА СВОД ПИШЕТ 1842 РАЗА — и все в ценах: «$29.95», «3,10 рубля».
    Свод умеет писать десятичное число и не умеет сказать, ЧТО ОНО ЕСТЬ ДОЛЯ.

    ДЕВЯТАЯ ЛОВУШКА РЯДА: 0,25 МЕНЬШЕ 0,5, ХОТЯ 25 БОЛЬШЕ 5. Читатель, знающий целые, сравнивает
    их по длине записи и по цифрам — и ошибается ровно там, где записи разной длины.

ЧЕТЫРЕ РОДА:

    запись доли   0,75 = 3/4: в сотых долях это 75/100, и 75 = 3 × 25, и 100 = 4 × 25.
    сравнение     0,25 меньше 0,5, хотя 25 больше 5: в сотых долях это 25/100 и 50/100,
                  и 25 меньше 50.                                            ← ЛОВУШКА
    лишний ноль   0,5 = 0,50: приписанный ноль стоит в сотых долях, и 50 = 5 × 10.
    граница       1/6 конечной десятичной записи не имеет: 6 = 2 × 3, и среди множителей
                  есть 3, а не только двойки и пятёрки.                      ← ЗАКОН С ГРАНИЦЕЙ

ВТОРОЙ РОД ЕСТЬ ЛОВУШКА, И ЛЕЧИТСЯ ОНА ОДНИМ ХОДОМ: привести к ОДНОМУ РАЗРЯДУ. Тот же ход, каким
дом сравнения долей приводил к общему знаменателю, — и это не совпадение: сотая доля есть
знаменатель 100, а приведение к сотым есть приведение к общему знаменателю, сказанное иначе.

    ОДИН ХОД, ПОВТОРЁННЫЙ В ДВУХ ЗАПИСЯХ, ЕСТЬ ОДИН ЗАКОН, А НЕ ДВА ПРАВИЛА.

ТРЕТИЙ РОД ГОВОРИТ ОБРАТНОЕ ПРИВЫЧКЕ ЦЕЛЫХ: там приписанный справа ноль умножает на десять, здесь
не меняет ничего. Первый и третий суть минимальная пара по МЕСТУ нуля — до запятой и после неё.

ЧЕТВЁРТЫЙ РОД НАЗЫВАЕТ ГРАНИЦУ ЗАКОНА, И БЕЗ НЕЁ ДОМ ЛГАЛ БЫ НАПОЛОВИНУ: не всякая доля
записывается десятичной дробью. Конечную запись дают только те знаменатели, что разложены на
двойки и пятёрки, — ибо десять есть 2 × 5, и иных множителей разряду взять неоткуда.

    ЗАКОН БЕЗ ГРАНИЦЫ ЕСТЬ ЛОЖЬ, СКАЗАННАЯ НАПОЛОВИНУ.

РАЗДЕЛИТЕЛЬ СЛЕДУЕТ ЯЗЫКУ ЗАПИСИ, И ЭТО НЕ ВЫБОР ДОМА, А ОБЫЧАЙ СВОДА: мир денег пишет «$29.95»
по-английски и «3,10 рубля» по-русски, а мир записи объявляет прямо — «0,5 и 0.5 — одно число».
Замер: запятой 279 русских строк и 2248 иноязычных (европейские деньги), точкой 983 английских.

    python3 tools/decforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("запись доли", "сравнение", "лишний ноль", "граница")
РАЗДЕЛИТЕЛЬ = {"ru": ",", "en": "."}

РАМКИ = {
    "ru": {
        "запись доли": "0{з}{д} = {a}/{b}: в сотых долях это {n}/100, и {n} = {a} × {k}, и 100 = {b} × {k}.",
        "сравнение": "0{з}{м} меньше 0{з}{б}, хотя {мц} больше {бц}: в сотых долях это {мс}/100 и {бс}/100, и {мс} меньше {бс}.",
        "лишний ноль": "0{з}{d} = 0{з}{d}0: приписанный ноль стоит в сотых долях, и {d0} = {d} × 10.",
        "граница": "1/{b} конечной десятичной записи не имеет: {b} = {разложение}, и среди множителей есть {p}, а не только двойки и пятёрки.",
        "граница простого": "1/{b} конечной десятичной записи не имеет: {b} простое и не есть ни 2, ни 5, а конечную запись дают только двойки и пятёрки.",
        "лишний ноль в тысячных": "0{з}{d} = 0{з}{d}0: приписанный ноль стоит в тысячных долях, и {d0} = {d} × 10.",
    },
    "en": {
        "запись доли": "0{з}{д} = {a}/{b}: in hundredths this is {n}/100, and {n} = {a} × {k}, and 100 = {b} × {k}.",
        "сравнение": "0{з}{м} is less than 0{з}{б}, although {мц} is greater than {бц}: in hundredths this is {мс}/100 and {бс}/100, and {мс} is less than {бс}.",
        "лишний ноль": "0{з}{d} = 0{з}{d}0: the appended zero stands in the hundredths, and {d0} = {d} × 10.",
        "граница": "1/{b} has no finite decimal writing: {b} = {разложение}, and among its factors there is {p}, and not only twos and fives.",
        "граница простого": "1/{b} has no finite decimal writing: {b} is prime and is neither 2 nor 5, and only twos and fives give a finite writing.",
        "лишний ноль в тысячных": "0{з}{d} = 0{з}{d}0: the appended zero stands in the thousandths, and {d0} = {d} × 10.",
    },
}
ПУСТО = dict(з="", д="", a=0, b=0, n=0, k=0, м="", б="", мц=0, бц=0, мс=0, бс=0,
             d=0, d0=0, разложение="", p=0)


def _разложить(b):
    """Множители по возрастанию: 12 → [2, 2, 3]. Нужны И для границы, И для её проверки."""
    вон, m, д = [], b, 2
    while д * д <= m:
        while m % д == 0:
            вон.append(д)
            m //= д
        д += 1
    if m > 1:
        вон.append(m)
    return вон


def _сотые(a, b):
    """Число сотых долей у a/b, или None, если запись не конечна в сотых."""
    return a * 100 // b if (a * 100) % b == 0 else None


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, з = РАМКИ[язык], РАЗДЕЛИТЕЛЬ[язык]
        # ЗАПИСЬ ДОЛИ: знаменатель делит сто, доля несократима — иначе одно число пришло бы
        # дважды под разными именами, и ряд рос бы, не показывая нового.
        for b in (2, 4, 5, 10, 20, 25, 50):
            k = 100 // b
            for a in range(1, b):
                if _разложить(a) and set(_разложить(a)) & set(_разложить(b)):
                    continue
                n = a * k
                # ЗАПИСЬ ВЫВОДИТСЯ ИЗ РАЗРЯДА, А НЕ ИЗ ЦИФР ЧИСЛА. Первая редакция писала
                # «0,5 = 1/20» вместо «0,05»: она брала число сотых как строку и обрезала нули
                # справа, потеряв ВЕДУЩИЙ ноль разряда. Сотых всегда две цифры; одна остаётся
                # лишь тогда, когда вторая — ноль.
                ц = f"{n:02d}"
                д = ц[0] if ц.endswith("0") else ц
                вон[рамки["запись доли"].format(
                    **dict(ПУСТО, з=з, д=д, a=a, b=b, n=n, k=k))] = (язык, "запись доли")
        # СРАВНЕНИЕ: у меньшего числа ЦИФР БОЛЬШЕ — иначе ловушки нет вовсе.
        for дес in range(1, 10):
            for сот in range(11, 100):
                if сот >= дес * 10 or сот <= дес or сот % 10 == 0 or (дес + сот) % 7:
                    continue
                вон[рамки["сравнение"].format(
                    **dict(ПУСТО, з=з, м=str(сот), б=str(дес), мц=сот, бц=дес,
                           мс=сот, бс=дес * 10))] = (язык, "сравнение")
        for d in range(1, 10):
            вон[рамки["лишний ноль"].format(
                **dict(ПУСТО, з=з, d=d, d0=d * 10))] = (язык, "лишний ноль")
        # ТОТ ЖЕ ЗАКОН ЭТАЖОМ НИЖЕ: ноль, приписанный к сотым, уходит в тысячные и опять
        # ничего не меняет. Ряд рода выравнивается с прочими, и закон показан не одним разрядом.
        for d in range(11, 100):
            if d % 10 == 0 or (d * 7) % 13 > 4:
                continue
            вон[рамки["лишний ноль в тысячных"].format(
                **dict(ПУСТО, з=з, d=d, d0=d * 10))] = (язык, "лишний ноль")
        # ГРАНИЦА: знаменатель несёт множитель, отличный от 2 и 5.
        for b in range(3, 60):
            м = _разложить(b)
            чужие = [p for p in м if p not in (2, 5)]
            if not чужие:
                continue
            # ПРОСТОЕ ЧИСЛО НЕ РАЗЛАГАЕТСЯ, И «3 = 3» НЕ ЕСТЬ РАЗЛОЖЕНИЕ. Своя рамка
            # говорит о нём прямо, а не притворяется произведением одного множителя.
            имя = "граница простого" if len(м) == 1 else "граница"
            вон[рамки[имя].format(
                **dict(ПУСТО, b=b, разложение=" × ".join(str(x) for x in м),
                       p=чужие[0]))] = (язык, "граница")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ПРОИЗВЕДЕНИЕ ДВУХ НЕ ЕСТЬ ГОЛОВА ПРОИЗВЕДЕНИЯ ТРЁХ. Образец без хвостовой оглядки брал из
# разложения «12 = 2 × 2 × 3» кусок «12 = 2 × 2» и звал семнадцать честных страниц ложью — та же
# жадность, что трижды за смену брала «21 = 2 × 1» из «21 = 2 × 10 + 1».
_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) = (\d+) × (\d+)(?![/\d])(?! ×)")
_ДЕСЯТИЧНОЕ = re.compile(r"0[.,](\d+)")
_СОТЫЕ = re.compile(r"(\d+)/100")
# ЗАПЯТАЯ И ТОЧКА СУТЬ ГРАНИЦЫ ЧИСЛА, КАК ДРОБНАЯ ЧЕРТА. Образец без этой оглядки читал
# «0,12 меньше 0,2» как «12 меньше 0» — брал хвост одного числа и голову другого — и звал
# честную страницу ложью. Хвост «(?![.,]\d)» пропускает точку конца строки и ловит точку разряда.
_ЦЕЛ = r"(?<![/\d.,])(\d+)(?![/\d])(?![.,]\d)"
_МЕНЬШЕ_ЦЕЛ = re.compile(_ЦЕЛ + r" (?:меньше|is less than) " + _ЦЕЛ)
_БОЛЬШЕ_ЦЕЛ = re.compile(_ЦЕЛ + r" (?:больше|is greater than) " + _ЦЕЛ)
_РАВНЫ_ДЕС = re.compile(r"0[.,](\d+) = 0[.,](\d+)")
_ТОЧКА_РАЗРЯДА = re.compile(r"\d\.\d")
_ЗАПЯТАЯ_РАЗРЯДА = re.compile(r"\d,\d")
_МЕНЬШЕ_ДЕС = re.compile(r"0[.,](\d+) (?:меньше|is less than) 0[.,](\d+)")
_ДОЛЯ = re.compile(r"(?<![/\d])(\d+)/(\d+)(?![/\d])")
_РАЗЛОЖЕНИЕ = re.compile(r"(?<![/\d])(\d+) = (\d+(?: × \d+)+)(?![/\d])")


def _знач(цифры):
    """Величина десятичной записи в СОТЫХ долях: «5» → 50, «25» → 25, «50» → 50."""
    ц = цифры[:2].ljust(2, "0")
    return int(ц)


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАЗЛОЖЕНИЕ СЧИТАЕТСЯ ПЕРВЫМ: «6 = 2 × 3» есть произведение из ТРЁХ и более чисел, и
    # образец произведения взял бы у него лишь хвост.
    разложено = set()
    for целое, хвост in _РАЗЛОЖЕНИЕ.findall(с):
        множители = [int(x) for x in хвост.split(" × ")]
        произведение = 1
        for м in множители:
            произведение *= м
        if произведение != int(целое):
            return True, False
        разложено.add(f"{целое} = {хвост}")
    for a, b, c in _ПРОИЗВ.findall(с):
        if f"{a} = {b} × {c}" in разложено:
            continue
        if int(a) != int(b) * int(c):
            return True, False
    # ДЕСЯТИЧНАЯ ЗАПИСЬ И ДОЛЯ СУТЬ ОДНО ЧИСЛО, И ЭТО ПЕРЕСЧИТЫВАЕТСЯ, А НЕ ПРИНИМАЕТСЯ.
    дес = _ДЕСЯТИЧНОЕ.findall(с)
    сотые = [int(x) for x in _СОТЫЕ.findall(с)]
    for ц, сот in zip(дес, сотые):
        if _знач(ц) != сот:
            return True, False
    доли = [(int(a), int(b)) for a, b in _ДОЛЯ.findall(с) if int(b) != 100]
    if дес and доли:
        a, b = доли[0]
        if b == 0 or _знач(дес[0]) * b != a * 100:
            return True, False
    for a, b in _МЕНЬШЕ_ЦЕЛ.findall(с):
        if int(a) >= int(b):
            return True, False
    for a, b in _БОЛЬШЕ_ЦЕЛ.findall(с):
        if int(a) <= int(b):
            return True, False
    for a, b in _МЕНЬШЕ_ДЕС.findall(с):
        if _знач(a) >= _знач(b):
            return True, False
    # РАВЕНСТВО ДВУХ ЗАПИСЕЙ ЕСТЬ РАВЕНСТВО ВЕЛИЧИН: «0,5 = 0,50» истинно, «0,5 = 0,55» нет.
    for a, b in _РАВНЫ_ДЕС.findall(с):
        if _знач(a) != _знач(b) or a.rstrip("0") != b.rstrip("0"):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:86]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    ср = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "сравнение")
    гр = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "граница")
    if судить(ср.replace("хотя", "хот"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(ср + " " + ср)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ПОРЧА, НЕ СОСТОЯВШАЯСЯ, ЕСТЬ ПРОВЕРКА, КОТОРОЙ НЕТ. Первая редакция портила слово
    # «множителей», а рамка простого его не содержит вовсе: замена молча возвращала ту же
    # строку, и страж докладывал о беде там, где не было даже подсадки.
    порча = гр.replace("конечной", "конечно", 1)
    if порча == гр:
        беды.append("порча не состоялась: слова нет в рамке")
    elif судить(порча)[1] is not False:
        беды.append("обрезанное слово в границе прошло")
    # РАЗДЕЛИТЕЛЬ СЛЕДУЕТ ЯЗЫКУ: русская страница с точкой и английская с запятой суть чужие
    # записи, и дом обязан держать свою.
    #
    # РАЗДЕЛИТЕЛЬ УЗНАЁТСЯ ПО МЕСТУ МЕЖДУ ЦИФР, А НЕ ПО САМОМУ ЗНАКУ: русская страница кончается
    # точкой, и страж, искавший точку где угодно, обвинял КАЖДУЮ. Признак берётся по существу.
    if any(_ТОЧКА_РАЗРЯДА.search(с) for с, (я, _р) in ПОКАЗЫ.items() if я == "ru"):
        беды.append("ТОЧКА В РАЗРЯДЕ РУССКОЙ СТРАНИЦЫ")
    if any(_ЗАПЯТАЯ_РАЗРЯДА.search(с) for с, (я, _р) in ПОКАЗЫ.items() if я == "en"):
        беды.append("ЗАПЯТАЯ В РАЗРЯДЕ АНГЛИЙСКОЙ СТРАНИЦЫ")
    # ЛОВУШКА ОБЯЗАНА БЫТЬ ЛОВУШКОЙ: у меньшего числа цифр БОЛЬШЕ, иначе показывать нечего.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "сравнение":
            continue
        м, б = _МЕНЬШЕ_ДЕС.findall(с)[0]
        if not (int(м) > int(б) and _знач(м) < _знач(б)):
            беды.append(f"ловушка не ловит: {с[:70]}")
            break
    print(f"ДЕСЯТИЧНАЯ ДОЛЯ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
