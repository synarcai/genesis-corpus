#!/usr/bin/env python3
"""ДОМ СОКРАЩЕНИЯ ДРОБИ — общий множитель уходит из обеих частей, и дробь остаётся той же.

    СОКРАЩЕНИЯ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по мирам показов: «сократить»,
    «reduce the fraction», «in lowest terms» — НОЛЬ вхождений; «наименьшее общее кратное» —
    ноль; «наибольший общий делитель» — восемь на весь свод. При этом дом одной доли уже
    говорит, что «2 из 4» и «1 из 2» суть одно, а дом разложения — что 4 = 2 × 2 и 6 = 2 × 3.

    ДВА ДОМА ЗНАЮТ ПОСЫЛКИ, И НИ ОДИН НЕ ДЕЛАЕТ ШАГА. Сокращение и есть тот шаг: общий
    множитель, найденный разложением, уходит из числителя и знаменателя, и дробь не меняется.

ЧЕТЫРЕ РОДА, И ТРЕТИЙ ВАЖНЕЕ ПРОЧИХ:

    сокращается  4/6 сокращается на 2: 4 = 2 × 2, и 6 = 2 × 3, и общий множитель 2,
                 и 4 ÷ 2 = 2, и 6 ÷ 2 = 3, и выходит 2/3.
    нельзя       3/5 сократить нельзя: 3 = 3, а 5 = 5, и общего множителя нет.
    не до конца  8/12 сокращается на 2 и даёт 4/6, но 4/6 сокращается ещё: 4 ÷ 2 = 2,
                 и 6 ÷ 2 = 3, и до конца выходит 2/3.        ← СОКРАЩЕНО НЕ ЗНАЧИТ ДО КОНЦА
    та же доля   4/6 и 2/3 — одно и то же: от 12 оба дают 8.  ← ПРОВЕРКА СЧЁТОМ ОТ ЦЕЛОГО

ТРЕТИЙ РОД ЕСТЬ ГЛАВНОЕ, ЧЕМУ ЗДЕСЬ УЧАТ. Сокративший однажды считает дело сделанным — а дробь
сокращается ещё, и ответ, поданный как окончательный, окончательным не был.

    ДЕЙСТВИЕ, ВЫПОЛНЕННОЕ ОДИН РАЗ, НЕ ЕСТЬ ДЕЙСТВИЕ, ВЫПОЛНЕННОЕ ДО КОНЦА.

ЧЕТВЁРТЫЙ РОД ЗАМЫКАЕТ ДОМ НА СОСЕДА: сокращение обязано сохранять величину, и это не
объявляется, а ПРОВЕРЯЕТСЯ счётом от целого — тем же оракулом, каким живёт дом одной доли.
Без него «сокращается» было бы обрядом переписывания.

ВТОРОЙ РОД ПОКАЗЫВАЕТ ГРАНИЦУ: не всякая дробь сокращается, и «нельзя» здесь не отказ от
работы, а её ИТОГ — разложение выполнено, общего множителя не нашлось.

ЧИСЛА БЕРУТСЯ ТАК, ЧТОБЫ РАЗЛОЖЕНИЕ ЧИТАЛОСЬ ГЛАЗОМ: числитель и знаменатель не больше
тридцати, простые множители — 2, 3, 5, 7.

ОСТАТОК ДОЛГА НАЗВАН ЧИСЛОМ: двенадцать родов дома непокупаемы, и все двенадцать — от РАЗНЫХ
ДЛИН разложения в паре («# = # × # × #» против «# = # × #»). Длина есть часть формы, и свести её
к одной значило бы показывать сокращение только на числах одного устройства.

    python3 tools/reduceforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("сокращается", "нельзя", "не до конца", "та же доля")
ПРОСТЫЕ = (2, 3, 5, 7)
# ДЛИНА РАЗЛОЖЕНИЯ ЕСТЬ ЧАСТЬ ФОРМЫ, И ПРЕДЕЛ ЕЙ ВЫБРАН ЗАМЕРОМ, А НЕ НА ГЛАЗ:
#
#     без предела   730 страниц, 50 родов, 28 непокупаемых
#     предел три    570 страниц, 32 рода,  12 непокупаемых
#     предел два    184 страницы, 14 родов, 4 непокупаемых — НО РОД «НЕ ДО КОНЦА» ПУСТ
#
# Второй предел дёшев и негоден: сокращаемое дважды требует хотя бы трёх множителей, и, отняв
# их, дом теряет главный свой род. Взят третий; остаток долга назван ниже числом.
ДЛИННЕЕ_НЕ_БРАТЬ = 3

РАМКИ = {
    "ru": {
        "сокращается": "{a}/{b} сокращается на {g}: {a} = {раза}, и {b} = {разб}, и общий множитель {g}, и {a} ÷ {g} = {a2}, и {b} ÷ {g} = {b2}, и выходит {a2}/{b2}.",
        "нельзя": "{a}/{b} сократить нельзя: {a} = {раза}, а {b} = {разб}, и общего множителя нет.",
        "не до конца": "{a}/{b} сокращается на {g} и даёт {a2}/{b2}, но {a2}/{b2} сокращается ещё: {a2} ÷ {g2} = {a3}, и {b2} ÷ {g2} = {b3}, и до конца выходит {a3}/{b3}.",
        "та же доля": "{a}/{b} и {a2}/{b2} — одно и то же: от {ц} оба дают {v}, ибо {ц} ÷ {b} = {ш1}, и {ш1} × {a} = {v}, и {ц} ÷ {b2} = {ш2}, и {ш2} × {a2} = {v}.",
    },
    "en": {
        "сокращается": "{a}/{b} is reduced by {g}: {a} = {раза}, and {b} = {разб}, and the common factor is {g}, and {a} ÷ {g} = {a2}, and {b} ÷ {g} = {b2}, and it gives {a2}/{b2}.",
        "нельзя": "{a}/{b} cannot be reduced: {a} = {раза}, and {b} = {разб}, and there is no common factor.",
        "не до конца": "{a}/{b} is reduced by {g} and gives {a2}/{b2}, but {a2}/{b2} is reduced further: {a2} ÷ {g2} = {a3}, and {b2} ÷ {g2} = {b3}, and in the end it is {a3}/{b3}.",
        "та же доля": "{a}/{b} and {a2}/{b2} are the same: of {ц} both give {v}, because {ц} ÷ {b} = {ш1}, and {ш1} × {a} = {v}, and {ц} ÷ {b2} = {ш2}, and {ш2} × {a2} = {v}.",
    },
}


def разложить(n):
    """Простые множители по возрастанию; для простого — оно само."""
    вон, ост = [], n
    for p in ПРОСТЫЕ:
        while ост % p == 0:
            вон.append(p)
            ост //= p
    return вон if ост == 1 else None


def _запись(n):
    м = разложить(n)
    return " × ".join(str(x) for x in м) if м and len(м) > 1 else str(n)


def _нод(a, b):
    while b:
        a, b = b, a % b
    return a


def _целое(b, b2):
    """Целое, делящееся на оба знаменателя, — доля без целого не есть число."""
    for ц in (12, 24, 36, 48, 60, 72, 84, 96, 120):
        if ц % b == 0 and ц % b2 == 0:
            return ц
    return None


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        # ДЛИНА РАЗЛОЖЕНИЯ ЕСТЬ ЧАСТЬ ФОРМЫ, И ПОТОМУ ОГРАНИЧЕНА — тот же урок, что в доме
        # разложения: «# = # × # × # × #» даёт рамку, какая во всём доме одна, и род выходит
        # непокупаемым. Замер 11.09: без предела дом дал 50 родов при 28 непокупаемых.
        for b in range(3, 31):
            for a in range(2, b):
                ра, рб = разложить(a), разложить(b)
                if ра is None or рб is None:
                    continue
                if len(ра) > ДЛИННЕЕ_НЕ_БРАТЬ or len(рб) > ДЛИННЕЕ_НЕ_БРАТЬ:
                    continue
                g = _нод(a, b)
                общее = dict(a=a, b=b, раза=_запись(a), разб=_запись(b))
                if g == 1:
                    вон[рамки["нельзя"].format(**общее, g=0, a2=0, b2=0, g2=0,
                                               a3=0, b3=0, ц=0, v=0, ш1=0, ш2=0)] = (
                        язык, "нельзя")
                    continue
                # СОКРАЩЕНИЕ НА НАИМЕНЬШИЙ ОБЩИЙ МНОЖИТЕЛЬ, А НЕ НА ВЕСЬ НОД: так виден
                # третий род — сокращённое не до конца.
                p = разложить(g)[0]
                a2, b2 = a // p, b // p
                вон[рамки["сокращается"].format(**общее, g=p, a2=a2, b2=b2, g2=0,
                                                a3=0, b3=0, ц=0, v=0, ш1=0, ш2=0)] = (
                    язык, "сокращается")
                g2 = _нод(a2, b2)
                if g2 > 1:
                    p2 = разложить(g2)[0]
                    вон[рамки["не до конца"].format(**общее, g=p, a2=a2, b2=b2, g2=p2,
                                                    a3=a2 // p2, b3=b2 // p2,
                                                    ц=0, v=0, ш1=0, ш2=0)] = (
                        язык, "не до конца")
                ц = _целое(b, b2)
                if ц:
                    вон[рамки["та же доля"].format(**общее, g=p, a2=a2, b2=b2, g2=0,
                                                   a3=0, b3=0, ц=ц, v=ц // b * a,
                                                   ш1=ц // b, ш2=ц // b2)] = (
                        язык, "та же доля")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ЧАСТНОЕ = re.compile(r"(\d+) ÷ (\d+) = (\d+)(?!\d)")
_ПРОИЗВ = re.compile(r"(\d+) × (\d+) = (\d+)(?!\d)")
_РАЗЛОЖЕНИЕ = re.compile(r"(\d+) = ((?:\d+ × )+\d+)(?!\d)(?! \+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: разложение, частные и произведения своими глазами.
    for n, разл in _РАЗЛОЖЕНИЕ.findall(с):
        произв = 1
        for м in разл.split(" × "):
            произв *= int(м)
        if произв != int(n):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    со = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "сокращается")
    не = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "не до конца")
    if судить(со.replace("общий", "общи"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(не.replace("ещё", "ещ"))[1] is not False:
        беды.append("обрезанное слово в неполном прошло")
    if судить(со + " " + со)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"СОКРАЩЕНИЕ ДРОБИ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
