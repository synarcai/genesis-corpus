#!/usr/bin/env python3
"""GENESIS layer: КЛАСС В СУАХИЛИ — see tools/swclassforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Число по классу» и «класс не есть род» идут вместе: первое даёт закон, второе отнимает
надежду вывести класс из смысла или приставки.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Множественное меняет приставку» и «класс без перемены» — второй группой: обе о том, ГДЕ
искать число, и вторая ломает первую («nyumba» не меняется вовсе).

«Спрошено и отвечено» — третьей: вопрос и ответ в одной строке, чтобы мир не только сообщал.

    МИР, КОТОРЫЙ ТОЛЬКО СООБЩАЕТ, УЧИТ УЗНАВАТЬ, А НЕ СПРАШИВАТЬ.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import swclassforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_swclass.txt"
ГРУППЫ = (("число по классу", "класс не есть род"),
          ("множественное меняет приставку", "класс без перемены"),
          ("спрошено и отвечено",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
