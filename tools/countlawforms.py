def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, имена = РАМКИ[язык], ЯЗЫК_ИМЯ[язык]
        for ру, пл, ан in ПАРЫ:
            ф = lambda n: форма("ru", ру, n)
            общ = dict(язык=имена["ru"], ф1=ф(1), ф2=ф(2), ф5=ф(5), ф11=ф(11), ф12=ф(12),
                       ф21=ф(21), ф24=ф(24), ф25=ф(25))
            вон[рамки["форма названа"].format(**общ)] = (язык, "форма названа")
            вон[рамки["подростки ломают правило"].format(**общ)] = (
                язык, "подростки ломают правило")
            вон[рамки["правило читается сверху вниз"].format(**общ)] = (
                язык, "правило читается сверху вниз")
