def _пакет(язык):
    return json.loads((_ПАКЕТЫ / f"{язык}.json").read_text(encoding="utf-8"))


ПАКЕТ = {я: _пакет(я) for я in ("ru", "pl", "en")}


def ячейка(язык, n):
    """Имя счётной ячейки языка для n: «one», «few» или «many» — по данным пакета."""
    return _ФОРМЫ[langpack.count_form_index(ПАКЕТ[язык], {"forms": list(_ФОРМЫ)}, n)]


def форма(язык, ключ, n):
    """Форма имени при числе, взятая У ДОМА ЯЗЫКА, а не выведенная здесь."""
    return rugram.форма(ключ, n) if язык == "ru" else plgram.форма(ключ, n)


