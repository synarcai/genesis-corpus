#!/usr/bin/env python3
"""СБОРКА HOLDOUT: тот же свод, но вопросы дознания ВЫРЕЗАНЫ.

СУД ОРГАНА ОБРАЩЕНИЯ ТРЕБУЕТ ЧИСТОГО ОПЫТА. Спор о том, дефект ли
вопросная поверхность, решается так: организм растёт на своде, где у
шести вердиктных родов дознания есть ПОВЕСТВОВАНИЕ («91 is not a prime
number: 91 = 7 × 13») и НЕТ ВОПРОСА («is 91 a prime number?»), — и
затем его спрашивают. Отвечает — обращение есть операция, купленная из
повествования. Молчит — вопрос был единственной поверхностью, и орган
не куплен.

СБОРКА ЕСТЬ СЛЕДСТВИЕ ПОЛНОЙ, А НЕ ЕЁ КОПИЯ. Здесь не второй обход
манифеста: берётся `собрать()` полного свода и к ОДНОМУ миру
прикладывается вырезка. Разойтись с каноном сборка не может — она из
него выведена.

ЭТО НЕ КАНОН. Манифест не трогается, `size` не пишется, в набор
поставки сборка не входит. Она живёт для одного суда и умирает с ним.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402
import gen_genesis_full as полная  # noqa: E402

ВЫХОД = КОРЕНЬ / "datasets" / "GENESIS-HOLDOUT.txt"
# Мир, чьи вопросы вырезаются, и признак вопроса. Признак — знак, а не
# список слов: у дознания все вопросы несут «?», и это замерено.
ВЫРЕЗКА = {"inquiry": "?"}


def собрать_holdout():
    куски, перепись, вырезано = [], [], 0
    for мир in genesis.manifest()["worlds"]:
        if мир.get("text") != "shows":
            continue
        путь = genesis._resolve(мир["file"])
        if not путь.is_file():
            continue
        строки = путь.read_text(encoding="utf-8").strip("\n").splitlines()
        знак = ВЫРЕЗКА.get(мир["name"])
        if знак is not None:
            до = len(строки)
            строки = [с for с in строки if знак not in с]
            вырезано += до - len(строки)
        тело = "\n".join(строки)
        if not тело.strip():
            continue
        куски.append(тело)
        перепись.append((мир["name"], sum(1 for с in строки if с.strip())))
    return полная.SEAM.join(куски) + "\n", перепись, вырезано


def main():
    тело, перепись, вырезано = собрать_holdout()
    if not вырезано:
        print("HOLDOUT ОТКАЗ: вырезать нечего — мир дознания без вопросов "
              "или не найден; сборка была бы тождественна полной")
        return 2
    ВЫХОД.write_text(тело, encoding="utf-8")
    строк = sum(1 for с in тело.splitlines() if с.strip())
    print(f"written {ВЫХОД.relative_to(КОРЕНЬ)}: {len(тело.encode())} bytes, "
          f"{строк} lines, {len(перепись)} worlds; вырезано вопросов "
          f"дознания {вырезано}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
