#!/usr/bin/env python3
"""СЕТКА ПРОСТРАНСТВА — носитель, нотация и исполнители одним домом.

Мандат 02.09 §L3: «пространство = род показа с геометрией»: сетка есть
показ со своей нотацией (та же, что у глифов: «#» закрашено, «.» пусто,
строки через «/») и своими ИСПОЛНИТЕЛЯМИ — перенос, поворот, отражение,
соседство, путь, счёт. Дом исполнителей ОДИН для генератора и суда, как
таблица шрифта у глифов: закон живёт в одном месте, показ — его след.
Координаты клетки — (строка, столбец) от единицы, сверху слева.
"""
import collections
import re

СЕТКА = re.compile(r"[#.]{3,5}(?:/[#.]{3,5}){2,4}")


def разобрать(текст):
    """Список строк сетки; None — не прямоугольник от 3×3 до 5×5."""
    строки = текст.split("/")
    if not (3 <= len(строки) <= 5) or len({len(с) for с in строки}) != 1:
        return None
    if not (3 <= len(строки[0]) <= 5):
        return None
    return строки


def записать(строки):
    return "/".join(строки)


def поворот(строки, градусов):
    """Поворот по часовой стрелке на 90, 180 или 270 градусов."""
    n, m = len(строки), len(строки[0])
    if градусов == 90:
        return ["".join(строки[n - 1 - r][c] for r in range(n)) for c in range(m)]
    if градусов == 180:
        return [с[::-1] for с in строки[::-1]]
    if градусов == 270:
        return ["".join(строки[r][m - 1 - c] for r in range(n)) for c in range(m)]
    raise ValueError(градусов)


def отражение(строки, ось):
    """«left-right» — зеркало по вертикальной оси; «top-bottom» — по горизонтальной."""
    if ось == "left-right":
        return [с[::-1] for с in строки]
    if ось == "top-bottom":
        return строки[::-1]
    raise ValueError(ось)


def сдвиг(строки, куда, k):
    """Перенос фигуры на k клеток; ушедшее за край теряется, вошедшее пусто."""
    n, m = len(строки), len(строки[0])
    dr, dc = {"right": (0, k), "left": (0, -k), "down": (k, 0), "up": (-k, 0)}[куда]
    вон = [["."] * m for _ in range(n)]
    for r in range(n):
        for c in range(m):
            if строки[r][c] == "#" and 0 <= r + dr < n and 0 <= c + dc < m:
                вон[r + dr][c + dc] = "#"
    return ["".join(с) for с in вон]


def теряет(строки, куда, k):
    """Уходит ли при сдвиге хоть одна закрашенная клетка за край."""
    return sum(с.count("#") for с in сдвиг(строки, куда, k)) < sum(
        с.count("#") for с in строки)


def соседи(строки, r, c):
    """Число закрашенных соседей по стороне у клетки (r, c), от единицы."""
    n, m = len(строки), len(строки[0])
    вон = 0
    for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        rr, cc = r - 1 + dr, c - 1 + dc
        if 0 <= rr < n and 0 <= cc < m and строки[rr][cc] == "#":
            вон += 1
    return вон


def путь(строки, a, b):
    """Длина кратчайшего пути по пустым клеткам по стороне; None — пути нет."""
    n, m = len(строки), len(строки[0])
    (r1, c1), (r2, c2) = (a[0] - 1, a[1] - 1), (b[0] - 1, b[1] - 1)
    if строки[r1][c1] == "#" or строки[r2][c2] == "#":
        return None
    видены = {(r1, c1): 0}
    очередь = collections.deque([(r1, c1)])
    while очередь:
        r, c = очередь.popleft()
        if (r, c) == (r2, c2):
            return видены[(r, c)]
        for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            rr, cc = r + dr, c + dc
            if 0 <= rr < n and 0 <= cc < m and строки[rr][cc] == "." and (rr, cc) not in видены:
                видены[(rr, cc)] = видены[(r, c)] + 1
                очередь.append((rr, cc))
    return None


def закрашено(строки):
    return sum(с.count("#") for с in строки)


def разница(а, б):
    """Число клеток, в которых две сетки одной формы расходятся; None —
    формы разные (тогда расходится всё)."""
    if len(а) != len(б) or len(а[0]) != len(б[0]):
        return None
    return sum(x != y for ра, рб in zip(а, б) for x, y in zip(ра, рб))


def основание_en(k):
    """Основание полярности словами: сколько клеток расходится."""
    return "no cell differs" if k == 0 else f"{k} cell{'s' if k != 1 else ''} differ{'s' if k == 1 else ''}"


def основание_ru(k):
    if k == 0:
        return "ни одна клетка не отличается"
    ед = k % 10 == 1 and k % 100 != 11
    неск = k % 10 in (2, 3, 4) and k % 100 not in (12, 13, 14)
    форма = "клетка" if ед else ("клетки" if неск else "клеток")
    return f"{'отличается' if ед else 'отличаются'} {k} {форма}"
