#!/usr/bin/env python3
"""ДОМ МЕРЫ ДЕЙСТВИЯ — число, которое МЕРЯЕТ действие, а не считает товар; и число,
которое считает НОСИТЕЛЕЙ, а не вещи.

Род назван d5 на живой полосе (05.09): из 289 немых тактов SVAMP 205 молчат при
купленном глаголе, а среди прочих стоят предложения, которых рамка
«актор — глагол — число — товар» не читает вовсе, потому что число в них — не
счёт товара:

    the frog jumped 12 inches.            число меряет действие (длина)
    the bag weighed 5 pounds.             число меряет действие (вес)
    6 birds were sitting on the fence. 4 more birds came.     число считает носителей

Замер по срезу t7_svamp_s1 (726 тактов): мера действия в 46 тактах (только ею
держатся 34), число-подлежащее в 130 (только им — 78): 112 тактов из 726 не
читаются никакой рамкой счёта товара. Глаголов меры на срезе ровно два — jumped
и weighed; единицы — inches, feet, pounds, kilograms. Дом объявляет то, что
показал срез, и ничего сверх: времени («lasted 3 hours») на срезе нет, и дом его
не выдумывает.

ЕДИНИЦА ПРИНАДЛЕЖИТ ГЛАГОЛУ, И ЭТО ЗАКОН, А НЕ УДОБСТВО. Прыгают на длину, весят
вес; «the frog jumped 12 pounds» — ложь по единице, и суд говорит это, не считая
чисел. Единица объявлена при глаголе видом меры, а виды — списком единиц со
счётными формами (у русского три: «сантиметр / сантиметра / сантиметров»).

ЧИСЛО-ПОДЛЕЖАЩЕЕ считает носителей: «на заборе сидели 4 птицы. прилетели ещё 3
птицы. всего 7 птиц» — суд складывает носителей и требует счётной формы при
каждом числе; убыль («сошли 2 ребёнка») — вычитает. Носитель здесь не актёр
действия с товаром, а то, что считают, и потому дом кладёт эту форму рядом с
мерой: обе суть «число не при товаре», и обе не читались.

ВСЯКАЯ СТРАНИЦА НЕСЁТ ВОПРОС (прибор ШИРОТЫ ВОПРОСА держит долг родов без
вопроса абсолютным числом): факт меры спрошен «how far did the frog jump?»,
сумма — «how far in all?», носители — «how many birds are on the fence now?».

МАССА ПО ПРАВИЛУ (LAW² = 9): на всякую форму в каждом языке ≥ 9 показов —
деятели × числа; всё объявлено здесь и нигде больше.

    python3 tools/actionmeasure.py    # самопроверка с мутантами
"""
import re

# --- меры: вид → единицы со счётными формами (en: ед./мн.; ru: 1 / 2–4 / 5+)
ЕДИНИЦЫ = {
    "en": {"длина": (("inch", "inches"), ("foot", "feet")),
           "вес": (("pound", "pounds"), ("kilogram", "kilograms"))},
    "ru": {"длина": (("сантиметр", "сантиметра", "сантиметров"), ("метр", "метра", "метров")),
           "вес": (("килограмм", "килограмма", "килограммов"), ("грамм", "грамма", "граммов"))},
}

ЯЗЫКИ = {
    "en": dict(
        # деятели меры: (имя, род) — род нужен русскому, английский его не читает
        деятели=(("the frog", "f"), ("the kangaroo", "m"), ("the dog", "m"), ("the cat", "f")),
        # глаголы меры: прошедшее, голая форма для вопроса, ВИД МЕРЫ
        глаголы=(("jumped", "jump", "длина"), ("weighed", "weigh", "вес")),
        вопрос={"длина": "how far did {A} {Гб}?", "вес": "how much did {A} {Гб}?"},
        факт="{A} {Гп} {n} {ЕДn}.",
        ответ_меры="{n} {ЕДn}.",
        сумма_факт="{A} {Гп} {a} {ЕДa} and then {b} {ЕДb}.",
        сумма_вопрос={"длина": "how far did {A} {Гб} in all?", "вес": "how much did {A} {Гб} in all?"},
        сумма_ответ="{s} {ЕДs}: {a} + {b} = {s}.",
        # носители: (ед., мн.) и место; прибыль и убыль
        носители=(("bird", "birds", "on the fence", "were sitting", "came", "flew away"),
                  ("child", "children", "on the bus", "were riding", "got on", "got off"),
                  ("boat", "boats", "in the harbour", "were moored", "arrived", "left")),
        было="{n} {Нn} {БЫЛИ} {ГДЕ}.",
        прибыль="{k} more {Нk} {ПРИШЛИ}.", убыль="{k} {Нk} {УШЛИ}.",
        носители_вопрос="how many {Нмн} are {ГДЕ} now?",
        носители_ответ="{r} {Нr}: {n} {знак} {k} = {r}.",
    ),
    "ru": dict(
        деятели=(("лягушка", "f"), ("кенгуру", "m"), ("пёс", "m"), ("кошка", "f")),
        # (мужское прошедшее, женское, предлог перед мерой, вид)
        глаголы=(("прыгнул", "прыгнула", "на ", "длина"), ("весил", "весила", "", "вес")),
        вопрос={"длина": "на сколько {ЕДмн} {Гп} {A}?", "вес": "сколько {ЕДмн} {Гп} {A}?"},
        факт="{A} {Гп} {ПР}{n} {ЕДn}.",
        ответ_меры="{ПР}{n} {ЕДn}.",
        сумма_факт="{A} {Гп} {ПР}{a} {ЕДa}, потом ещё {ПР}{b} {ЕДb}.",
        сумма_вопрос={"длина": "на сколько {ЕДмн} {Гп} {A} всего?", "вес": "сколько {ЕДмн} {Гп} {A} всего?"},
        сумма_ответ="{ПР}{s} {ЕДs}: {a} + {b} = {s}.",
        # носители: три счётные формы, место, глаголы состояния/прибыли/убыли (мн. ч.)
        носители=(("птица", "птицы", "птиц", "на заборе", "сидели", "прилетели ещё", "улетели"),
                  ("ребёнок", "ребёнка", "детей", "в автобусе", "ехали", "вошли ещё", "вышли"),
                  ("лодка", "лодки", "лодок", "в гавани", "стояли", "пришли ещё", "ушли")),
        было="{ГДЕ} {БЫЛИ} {n} {Нn}.",
        прибыль="{ПРИШЛИ} {k} {Нk}.", убыль="{УШЛИ} {k} {Нk}.",
        носители_вопрос="сколько {Нмн} {ГДЕ} теперь?",
        носители_ответ="{r} {Нr}: {n} {знак} {k} = {r}.",
    ),
}
ФОРМЫ = ("мера", "сумма", "прибыль", "убыль")
ЧИСЛА_МЕРЫ = (12, 5, 27, 8, 15, 31, 9, 20, 46)
ПАРЫ_СУММЫ = ((12, 8), (5, 9), (27, 13), (15, 6), (31, 19), (9, 4), (20, 25), (46, 14), (8, 8))
НОСИТЕЛИ_ЧИСЛА = ((6, 4), (43, 21), (12, 5), (9, 3), (28, 14), (7, 6), (15, 8), (30, 12), (11, 9))


def счётная(формы, n):
    """Счётная форма единицы или носителя при числе — объявленная, не выведенная."""
    if len(формы) == 2:
        return формы[0] if n == 1 else формы[1]
    if n % 100 in range(11, 15):
        return формы[2]
    п = n % 10
    return формы[0] if п == 1 else формы[1] if п in (2, 3, 4) else формы[2]


def _глагол(язык, г, деятель):
    формы = ЯЗЫКИ[язык]["глаголы"][г]
    if язык == "en":
        return формы[0], формы[1], "", формы[2]
    род = ЯЗЫКИ[язык]["деятели"][деятель][1]
    return (формы[0] if род == "m" else формы[1]), "", формы[2], формы[3]


def _единица(язык, вид, i):
    ряд = ЕДИНИЦЫ[язык][вид]
    return ряд[i % len(ряд)]


def страница(язык, форма, i):
    я = ЯЗЫКИ[язык]
    if форма == "мера":
        деятель = i % len(я["деятели"])
        г = (i // len(я["деятели"])) % len(я["глаголы"])
        A = я["деятели"][деятель][0]
        Гп, Гб, ПР, вид = _глагол(язык, г, деятель)
        ед = _единица(язык, вид, i)
        n = ЧИСЛА_МЕРЫ[i % len(ЧИСЛА_МЕРЫ)]
        факт = я["факт"].format(A=A, Гп=Гп, ПР=ПР, n=n, ЕДn=счётная(ед, n))
        воп = я["вопрос"][вид].format(A=A, Гб=Гб, Гп=Гп, ЕДмн=счётная(ед, 5))
        return f"{факт} {воп} {я['ответ_меры'].format(ПР=ПР, n=n, ЕДn=счётная(ед, n))}"
    if форма == "сумма":
        деятель = i % len(я["деятели"])
        г = (i // len(я["деятели"])) % len(я["глаголы"])
        A = я["деятели"][деятель][0]
        Гп, Гб, ПР, вид = _глагол(язык, г, деятель)
        ед = _единица(язык, вид, i)
        a, b = ПАРЫ_СУММЫ[i % len(ПАРЫ_СУММЫ)]
        s = a + b
        факт = я["сумма_факт"].format(A=A, Гп=Гп, ПР=ПР, a=a, ЕДa=счётная(ед, a), b=b, ЕДb=счётная(ед, b))
        воп = я["сумма_вопрос"][вид].format(A=A, Гб=Гб, Гп=Гп, ЕДмн=счётная(ед, 5))
        return f"{факт} {воп} {я['сумма_ответ'].format(ПР=ПР, s=s, ЕДs=счётная(ед, s), a=a, b=b)}"
    # носители: прибыль или убыль
    н = я["носители"][i % len(я["носители"])]
    формы_н = н[:-4] if язык == "ru" else н[:2]
    ГДЕ, БЫЛИ, ПРИШЛИ, УШЛИ = н[-4:]
    n, k = НОСИТЕЛИ_ЧИСЛА[i % len(НОСИТЕЛИ_ЧИСЛА)]
    if форма == "убыль" and k > n:
        n, k = k, n
    r = n + k if форма == "прибыль" else n - k
    знак = "+" if форма == "прибыль" else "−"
    было = я["было"].format(n=n, Нn=счётная(формы_н, n), БЫЛИ=БЫЛИ, ГДЕ=ГДЕ)
    ход = (я["прибыль"].format(k=k, Нk=счётная(формы_н, k), ПРИШЛИ=ПРИШЛИ) if форма == "прибыль"
           else я["убыль"].format(k=k, Нk=счётная(формы_н, k), УШЛИ=УШЛИ))
    воп = я["носители_вопрос"].format(Нмн=формы_н[1] if язык == "en" else формы_н[2], ГДЕ=ГДЕ)
    отв = я["носители_ответ"].format(r=r, Нr=счётная(формы_н, r), n=n, знак=знак, k=k)
    return f"{было} {ход} {воп} {отв}"


def _все_показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for форма in ФОРМЫ:
            for i in range(18):
                вон[страница(язык, форма, i)] = (язык, форма)
    return вон


ПОКАЗЫ = _все_показы()


# --- суд: пересчёт, единица по глаголу, счётная форма
def _alt(слова):
    return "(?:" + "|".join(re.escape(с) for с in sorted(слова, key=len, reverse=True)) + ")"


def _образцы(язык):
    я = ЯЗЫКИ[язык]
    деятели = _alt([д for д, _ in я["деятели"]])
    все_ед = _alt([ф for вид in ЕДИНИЦЫ[язык].values() for ряд in вид for ф in ряд])
    глаголы = _alt([г[0] for г in я["глаголы"]] + ([г[1] for г in я["глаголы"]] if язык == "ru" else []))
    голые = _alt([г[1] for г in я["глаголы"]]) if язык == "en" else None
    ч = r"(\d+)"
    if язык == "en":
        мера = re.compile(rf"^({деятели}) ({глаголы}) {ч} ({все_ед})\. how (?:far|much) did \1 ({голые})\? {ч} ({все_ед})\.$")
        сумма = re.compile(rf"^({деятели}) ({глаголы}) {ч} ({все_ед}) and then {ч} ({все_ед})\. how (?:far|much) did \1 ({голые}) in all\? {ч} ({все_ед}): {ч} \+ {ч} = {ч}\.$")
    else:
        мера = re.compile(rf"^({деятели}) ({глаголы}) (на )?{ч} ({все_ед})\. (?:на сколько|сколько) ({все_ед}) \2 \1\? (на )?{ч} ({все_ед})\.$")
        сумма = re.compile(rf"^({деятели}) ({глаголы}) (на )?{ч} ({все_ед}), потом ещё (на )?{ч} ({все_ед})\. (?:на сколько|сколько) ({все_ед}) \2 \1 всего\? (на )?{ч} ({все_ед}): {ч} \+ {ч} = {ч}\.$")
    # НОСИТЕЛИ: число перед подлежащим, прибыль и убыль — суд складывает и
    # вычитает носителей и требует счётной формы при каждом числе
    формы_н = [ф for н in я["носители"] for ф in (н[:2] if язык == "en" else н[:3])]
    имена_н = _alt(формы_н)
    if язык == "en":
        места = _alt([н[2] for н in я["носители"]]); были = _alt([н[3] for н in я["носители"]])
        пришли = _alt([н[4] for н in я["носители"]]); ушли = _alt([н[5] for н in я["носители"]])
        носители = re.compile(rf"^(?P<n>\d+) (?P<н1>{имена_н}) ({были}) (?P<где>{места})\. (?P<k>\d+) (more )?(?P<н2>{имена_н}) (?P<ход>{пришли}|{ушли})\. how many (?P<н3>{имена_н}) are ({места}) now\? (?P<r>\d+) (?P<н4>{имена_н}): (?P<n2>\d+) (?P<знак>[+−]) (?P<k2>\d+) = (?P<r2>\d+)\.$")
    else:
        места = _alt([н[3] for н in я["носители"]]); были = _alt([н[4] for н in я["носители"]])
        пришли = _alt([н[5] for н in я["носители"]]); ушли = _alt([н[6] for н in я["носители"]])
        носители = re.compile(rf"^(?P<где>{места}) ({были}) (?P<n>\d+) (?P<н1>{имена_н})\. (?P<ход>{пришли}|{ушли}) (?P<k>\d+) (?P<н2>{имена_н})\. сколько (?P<н3>{имена_н}) ({места}) теперь\? (?P<r>\d+) (?P<н4>{имена_н}): (?P<n2>\d+) (?P<знак>[+−]) (?P<k2>\d+) = (?P<r2>\d+)\.$")
    return мера, сумма, носители


def _ряд_носителя(язык, слово):
    for н in ЯЗЫКИ[язык]["носители"]:
        ряд = н[:2] if язык == "en" else н[:3]
        if слово in ряд:
            return ряд, н
    return None, None


_ОБРАЗЦЫ = {язык: _образцы(язык) for язык in ЯЗЫКИ}
def _вид_по_глаголу(язык, слово):
    for г in ЯЗЫКИ[язык]["глаголы"]:
        формы = г[:2]
        if слово in формы:
            return г[-1]
    return None


def _вид_по_единице(язык, слово):
    for вид, ряды in ЕДИНИЦЫ[язык].items():
        for ряд in ряды:
            if слово in ряд:
                return вид, ряд
    return None, None


def судить(строка):
    """(судимо, истинно): показ дома истинен; строка его рамки с иным числом,
    единицей не по глаголу или счётной формой не по числу — ложна."""
    с = строка.strip()
    if с in ПОКАЗЫ:
        return True, True
    for язык, (мера, сумма, носители) in _ОБРАЗЦЫ.items():
        м = носители.match(с)
        if м:
            g = м.groupdict()
            n, k, r, n2, k2, r2 = (int(g[x]) for x in ("n", "k", "r", "n2", "k2", "r2"))
            н1, н2, н3, н4, ход, знак = g["н1"], g["н2"], g["н3"], g["н4"], g["ход"], g["знак"]
            прибыль = any(ход == (н[4] if язык == "en" else н[5]) for н in ЯЗЫКИ[язык]["носители"])
            ряд, _ = _ряд_носителя(язык, н1)
            ожид = n + k if прибыль else n - k
            return True, (ряд is not None and all(x in ряд for x in (н2, н3, н4)) and (n, k) == (n2, k2)
                          and знак == ("+" if прибыль else "−") and r == r2 == ожид and ожид >= 0
                          and счётная(ряд, n) == н1 and счётная(ряд, k) == н2 and счётная(ряд, r) == н4)
        м = мера.match(с)
        if м:
            г = м.group(2)
            if язык == "en":
                n, ед, n2, ед2 = int(м.group(3)), м.group(4), int(м.group(6)), м.group(7)
            else:
                n, ед, n2, ед2 = int(м.group(4)), м.group(5), int(м.group(8)), м.group(9)
            вид = _вид_по_глаголу(язык, г)
            вид_ед, ряд = _вид_по_единице(язык, ед)
            return True, (n == n2 and ед == ед2 and вид == вид_ед and ряд is not None
                          and счётная(ряд, n) == ед)
        м = сумма.match(с)
        if м:
            г = м.group(2)
            if язык == "en":
                a, еда, b, едb, s, едs, a2, b2, s2 = (int(м.group(3)), м.group(4), int(м.group(5)), м.group(6),
                                                     int(м.group(8)), м.group(9), int(м.group(10)), int(м.group(11)), int(м.group(12)))
            else:
                a, еда, b, едb, s, едs, a2, b2, s2 = (int(м.group(4)), м.group(5), int(м.group(7)), м.group(8),
                                                     int(м.group(11)), м.group(12), int(м.group(13)), int(м.group(14)), int(м.group(15)))
            вид = _вид_по_глаголу(язык, г)
            вид_ед, ряд = _вид_по_единице(язык, еда)
            return True, (ряд is not None and вид == вид_ед and едb in ряд and едs in ряд
                          and (a, b) == (a2, b2) and s == s2 == a + b
                          and счётная(ряд, a) == еда and счётная(ряд, b) == едb and счётная(ряд, s) == едs)
    return False, False


def _самопроверка():
    мутанты = 0
    for язык in ЯЗЫКИ:
        for форма in ФОРМЫ:
            с = страница(язык, форма, 0)
            assert судить(с) == (True, True), (язык, форма, с)
        # МУТАНТ 1: единица не по глаголу — прыгнул на килограммы
        с = страница(язык, "мера", 0)
        ед_длины = ЕДИНИЦЫ[язык]["длина"][0]; ед_веса = ЕДИНИЦЫ[язык]["вес"][0]
        битая = с.replace(счётная(ед_длины, 12), счётная(ед_веса, 12))
        assert битая != с and судить(битая) == (True, False), (язык, битая)
        мутанты += 1
        # МУТАНТ 2: сумма сложена неверно
        с = страница(язык, "сумма", 0)
        битая = с.replace("= 20.", "= 21.")
        assert битая != с and судить(битая) == (True, False), (язык, битая)
        мутанты += 1
        # МУТАНТ 3: счётная форма не по числу (у русского) / число ответа не по факту
        с = страница(язык, "мера", 1)
        битая = re.sub(r"(\d+)(\D+)$", lambda м: str(int(м.group(1)) + 1) + м.group(2), с, count=1)
        assert битая != с and судить(битая) == (True, False), (язык, битая)
        мутанты += 1
