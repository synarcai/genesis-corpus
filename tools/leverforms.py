СТОРОНЫ = {"ru": ("левая", "правая"), "en": ("left", "right")}


def при(язык, вид, n):
    """Форма единицы при счёте: у русского спрашивается дом, у английского — множественное."""
    имя = ЕДИНИЦЫ[язык][вид]
    if язык == "ru":
        return rugram.форма(имя, n)
    один, много = имя
    return один if n == 1 else много


def _равные():
    """Четвёрки (m1, d1, m2, d2) с равными произведениями: m1·d1 = m2·d2, все от двух."""
    вон = []
    видано = set()
    for m1 in range(2, 10):
        for d1 in range(2, 10):
            п = m1 * d1
            for d2 in range(2, 13):
                if d2 == d1:
                    continue
                m2, ост = divmod(п, d2)
                if ост or not 2 <= m2 <= 12 or m2 == m1:
                    continue
                ключ = (m1, d1, m2, d2)
                if ключ in видано or (m2, d2, m1, d1) in видано:
                    continue
                видано.add(ключ)
                вон.append(ключ)
    return вон


def _кратные():
    """(m1, d1, m2, d2, k) для рода смысла: левый груз тяжелее ровно в k раз.

    РОД, ГОВОРЯЩИЙ ЗАКОН ВСЛУХ, НЕ ДОЛЖЕН БЫТЬ ОСТАТКОМ ОТ ЧУЖОГО ОТБОРА. Первый заход брал
    кратные из четвёрок равновесия и получил девять страниц против семидесяти восьми — род,
    несущий смысл дома, вышел самым тощим. Числа ему даются свои.
    """
    вон = []
    for m2 in range(2, 7):
        for k in range(2, 6):
            m1 = m2 * k
            if m1 > 12:
                continue
            for d1 in range(2, 7):
                d2 = d1 * k
                if d2 > 20:
                    continue
                вон.append((m1, d1, m2, d2, k))
    return вон


def страницы():
    вон = {}
    равные = _равные()
    for язык in ЯЗЫКИ:
        левая, правая = СТОРОНЫ[язык]
        for к, (m1, d1, m2, d2) in enumerate(равные):
            п = m1 * d1
            общее = dict(m1=m1, d1=d1, m2=m2, d2=d2, p1=п, p2=п,
                         в1=при(язык, "вес", m1), л1=при(язык, "длина", d1),
                         в2=при(язык, "вес", m2), л2=при(язык, "длина", d2))
            for род in ("равновесие", "груз", "плечо"):
                вон[РАМКИ[язык][род].format(**общее, больше="", меньше="", сторона="", к="", кр="")] = (язык, род)
            # ПЕРЕВЕС: то же самое с одним изменённым числом, и сторона чередуется — иначе
            # ответ был бы всегда один, и страница учила бы не закону, а привычке.
            слева = к % 2 == 0
            п1, п2 = (п + d1, п) if слева else (п, п + d2)
            м1, м2 = (m1 + 1, m2) if слева else (m1, m2 + 1)
            поля = dict(общее, m1=м1, m2=м2, p1=п1, p2=п2,
                        в1=при(язык, "вес", м1), в2=при(язык, "вес", м2),
                        больше=max(п1, п2), меньше=min(п1, п2),
                        сторона=левая if слева else правая)
            вон[РАМКИ[язык]["перевес"].format(**поля, к="", кр="")] = (язык, "перевес")
        # ОБРАТНО: свои числа, ибо кратность должна быть целой — дробей этот дом не берёт.
        for m1, d1, m2, d2, k in _кратные():
            поля = dict(m1=m1, d1=d1, m2=m2, d2=d2, p1=m1 * d1, p2=m2 * d2,
                        в1=при(язык, "вес", m1), л1=при(язык, "длина", d1),
                        в2=при(язык, "вес", m2), л2=при(язык, "длина", d2),
                        k=k, кр=при("ru", "кратность", k), больше="", меньше="", сторона="")
            вон[РАМКИ[язык]["обратно"].format(**поля)] = (язык, "обратно")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ. Порча ОДНИМ словом не меняет числа слов, и потому строка, чьей длины
# нет среди объявленных, не может быть порчей ни одной страницы. Без указателя суд разбирал все
# семьсот рамок на каждой из четырёхсот тысяч строк свода и не кончал за две минуты.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(\d+) × (\d+) = (\d+)")
_ЧАСТНОЕ = re.compile(r"(\d+) ÷ (\d+) = (\d+)")
_БОЛЬШЕ = re.compile(r"(\d+) (?:больше|is greater than) (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки. Тот же ход, каким живут дом вероятности,
    пласт языков и дом выбора действия.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: произведения, частные и сравнение своими глазами.
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


