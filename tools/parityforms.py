ПУСТО = dict(a=0, b=0, s=0, p=0, a2=0, b2=0, s2=0, p2=0)


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a2 in range(1, 13):
            for b2 in range(1, 13):
                чч = dict(ПУСТО, a=2 * a2, b=2 * b2, a2=a2, b2=b2,
                          s=2 * a2 + 2 * b2, s2=a2 + b2)
                нн = dict(ПУСТО, a=2 * a2 + 1, b=2 * b2 + 1, a2=a2, b2=b2,
                          s=2 * a2 + 2 * b2 + 2, s2=a2 + b2 + 1)
                чн = dict(ПУСТО, a=2 * a2, b=2 * b2 + 1, a2=a2, b2=b2,
                          s=2 * a2 + 2 * b2 + 1, s2=a2 + b2)
                if (a2 + b2) % 3 == 0:
                    вон[рамки["чёт и чёт"].format(**чч)] = (язык, "чёт и чёт")
                if (a2 + b2) % 3 == 1:
                    вон[рамки["нечёт и нечёт"].format(**нн)] = (язык, "нечёт и нечёт")
                if (a2 + b2) % 3 == 2:
                    вон[рамки["чёт и нечёт"].format(**чн)] = (язык, "чёт и нечёт")
                # СПРОШЕННОЕ: тот же закон чёта с нечётом, поставленный ВОПРОСОМ, и ответ
                # его — ОТКАЗ с обоснованием: «нет, нечётна», а не голое «нечётна».
                #
                #     МИР БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ ПОКАЗЫВАЕТ ОТВЕТ, НЕ ПОКАЗЫВАЯ ЗАДАЧИ.
                if (a2 + b2) % 5 == 0:
                    вон[рамки["спрошенное"].format(**чн)] = (язык, "спрошенное")
                # МНОЖИТЕЛЬ: первый множитель ЛЮБОЙ, второй чётный — ровно в этом закон
