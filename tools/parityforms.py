    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:92]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    нн = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "нечёт и нечёт")
    мн = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "множитель")
    for страница, слово, куда in ((нн, "нечётное", "нечётно"), (мн, "множитель", "множител")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(нн + " " + нн)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ПОЛНОТА СЛУЧАЕВ СЛОЖЕНИЯ ЕСТЬ УСЛОВИЕ ЗАКОНА, А НЕ УКРАШЕНИЕ.
    сложение = {р for _я, р in ПОКАЗЫ.values()} & {"чёт и чёт", "нечёт и нечёт", "чёт и нечёт"}
    if len(сложение) != 3:
        беды.append("СЛУЧАИ СЛОЖЕНИЯ НЕПОЛНЫ: закон о классах показан не весь")
    # СЛОВА ДО ДВОЕТОЧИЯ, РАВЕНСТВА ПОСЛЕ.
    for с in ПОКАЗЫ:
        хвост = с.rsplit(":", 1)[1]
        if re.search(r"[A-Za-zА-Яа-яЁё]{3,}", хвост.replace("and", "").replace("и", "")):
            беды.append(f"СЛОВА ПОСЛЕ ДВОЕТОЧИЯ: {с[:70]}")
            break
    print(f"ЧЁТНОСТЬ ДЕЙСТВИЙ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


