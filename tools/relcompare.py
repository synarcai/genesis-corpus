#!/usr/bin/env python3
"""ДОМ ОТНОСИТЕЛЬНОГО ФАКТА — число, принадлежащее РАЗНОСТИ, а не носителю (07.09).

ЗАКАЗ КУПЛЕН ПЕРЕПИСЬЮ. Атлас непрочитанных чисел (томограф st48, omega-ad) ставит МАРКЕР
СРАВНЕНИЯ восьмым классом — 48 историй: «458 more girls than boys», «6 fewer peaches than
Steven». Форма в своде ЕСТЬ, и потому дом строится не ради формы, а ради двух её изъянов,
и оба замерены на своде `e3f88242d50ebd2b` (380 610 строк):

    «N more X than Y»       645 строк, 75 разных товаров
    «N fewer X than Y»      184 строки, 40 товаров
    «N times as many»        96
    ВОПРОС О РАЗНОСТИ «how many more X than Y»    52

ИЗЪЯН ПЕРВЫЙ: ОДНОБОКОСТЬ. Свод пишет относительный факт ВПЕРЁД — дано меньшее и
разность, найди большее — восемьсот двадцать девять раз, а спрашивает НАЗАД — даны оба,
найди разность — пятьдесят два. Читатель, выучивший один ход, на другом молчит.

ИЗЪЯН ВТОРОЙ, И ОН ХУЖЕ ПЕРВОГО: РАЗНОСТЬ ПОЧТИ ВСЕГДА КРОШЕЧНАЯ.

    1: 107   2: 145   3: 97   4: 56   5: 49   6: 78   7: 55   8: 41   9: 39
    10: 8    11: 11   12: 17   13: 11   14: 12   …   наибольшая 234

Восемьсот двадцать девять вхождений, сорок разных чисел — и ВОСЕМЬДЕСЯТ ПРОЦЕНТОВ МАССЫ
СТОИТ НА ЕДИНИЦЕ…ДЕВЯТКЕ.

    РОД, ПОКАЗАННЫЙ ТОЛЬКО В МАЛЫХ ЧИСЛАХ, ВЫУЧИВАЕТСЯ КАК ПОПРАВКА, А НЕ КАК ОТНОШЕНИЕ.
    Читатель, видевший «1 more cookie» сто семь раз, берёт число при «more» за мелкую
    добавку к соседнему; «458 more girls than boys» для него ведёт себя иначе, ибо там
    число есть самостоятельная величина. Это тот же изъян, что был у мира букв с его
    четырьмя длинами: мера, у которой мало разных ответов и один из них частый,
    отвечается угадыванием.

ЧТО ПИШЕТ ЭТОТ ДОМ (условия holon-f9, все исполнены поимённо):

    ДВЕ СТОРОНЫ ВОПРОСА. О том, у кого БОЛЬШЕ («how many apples does Ben have?»), и о
        том, у кого МЕНЬШЕ («how many apples does Carla have?») — читатель, взявший
        «more» за приказ складывать, на второй стороне лжёт.
    ДВА ХОДА. Вперёд (дано меньшее и разность) и НАЗАД (даны оба, найди разность) — в
        обеих формах вопроса о разности: «how many more … than …» и «how many fewer …
        than …».
    ОБА ПОРЯДКА ПРЕДЛОЖЕНИЙ. Относительный факт после опорного и ПЕРЕД ним: «Ben has 47
        more apples than Carla. Carla has 3 apples.» — там носитель Carla назван ПОСЛЕ
        того, как на неё сослались, и рамка, ищущая опору слева, молчит.
    РАЗНОСТЬ ПО ВСЕМУ ДИАПАЗОНУ — от единицы до пятисот, и малых не больше, чем больших;
        это и есть главное, ради чего дом стои́т.

ЗАКОН ЧИСЛА: не менее LAW³ = 8 страниц на каждую из пяти рамок и не менее LAW² = 4
товаров; разностей — не менее LAW³ = 8 разных ярусов величины.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from layer import emit                                            # noqa: E402
from plural import by_count                                       # noqa: E402

_ПАКЕТ = json.loads((pathlib.Path(__file__).resolve().parent / "langpacks" / "en.json")
                    .read_text(encoding="utf-8"))
_ИМЕНА_ПАКЕТА = set(_ПАКЕТ["person_names"])
_ПО_СТРОЧНОМУ = {и.lower(): и for и in _ИМЕНА_ПАКЕТА}
ИМЕНА = [_ПО_СТРОЧНОМУ[и] for и in
         ("ann", "ben", "carla", "dan", "elena", "felix", "grace", "hugo", "ava", "carlos")]
assert set(ИМЕНА) <= _ИМЕНА_ПАКЕТА, "имя не объявлено пакетом en"

ТОВАРЫ = ("apple", "book", "card", "coin", "egg", "pencil", "flower", "stamp",
          "ball", "seed", "cookie", "page")
МНОГО = {т: _ПАКЕТ["noun_forms"][т] for т in ТОВАРЫ}   # форма — объявление пакета

# ЯРУСЫ РАЗНОСТИ: восемь порядков величины, и малых не больше, чем больших. Ярус выбирается
# по шагу, число внутри яруса — по зерну; так ни одно число не становится частым.
ЯРУСЫ = ((1, 9), (10, 29), (30, 69), (70, 129), (130, 199), (200, 299), (300, 399), (400, 599))


def _разность(зерно):
    низ, верх = ЯРУСЫ[зерно % len(ЯРУСЫ)]
    return низ + (зерно * 7 // len(ЯРУСЫ)) % (верх - низ + 1)


def показы(pi):
    основа = pi * 41
    вон = []
    for i in range(len(ТОВАРЫ) * len(ЯРУСЫ) * 5):
        товар = ТОВАРЫ[(основа + i) % len(ТОВАРЫ)]
        мн = МНОГО[товар]
        меньший = ИМЕНА[(основа + i) % len(ИМЕНА)]
        больший = ИМЕНА[(основа + i + 3) % len(ИМЕНА)]
        d = _разность(основа + i)
        n = (основа + i * 13) % 90 + 5          # 5..94 — у меньшего
        m = n + d                               # у большего
        рамка = ((основа + i) // len(ТОВАРЫ)) % 5
        факт_меньшего = f"{меньший} has {n} {by_count(n, мн)}."
        факт_большего = f"{больший} has {m} {by_count(m, мн)}."
        больше_чем = f"{больший} has {d} more {by_count(d, мн)} than {меньший}."
        меньше_чем = f"{меньший} has {d} fewer {by_count(d, мн)} than {больший}."
        if рамка == 0:
            # ВПЕРЁД, ВОПРОС О БОЛЬШЕМ
            вон.append(
                f"{факт_меньшего} {больше_чем} "
                f"how many {мн} does {больший} have? "
                f"{m} {by_count(m, мн)}: {n} + {d} = {m}.")
        elif рамка == 1:
            # ВПЕРЁД, ВОПРОС О МЕНЬШЕМ — тот же маркер, обратное действие
            вон.append(
                f"{факт_большего} {меньше_чем} "
                f"how many {мн} does {меньший} have? "
                f"{n} {by_count(n, мн)}: {m} − {d} = {n}.")
        elif рамка == 2:
            # НАЗАД: даны оба, спрошена РАЗНОСТЬ («how many more … than …»)
            вон.append(
                f"{факт_меньшего} {факт_большего} "
                f"how many more {мн} does {больший} have than {меньший}? "
                f"{d} {by_count(d, мн)}: {m} − {n} = {d}.")
        elif рамка == 3:
            # НАЗАД, ДРУГАЯ СТОРОНА: «how many fewer … than …»
            вон.append(
                f"{факт_большего} {факт_меньшего} "
                f"how many fewer {мн} does {меньший} have than {больший}? "
                f"{d} {by_count(d, мн)}: {m} − {n} = {d}.")
        else:
            # ОТНОСИТЕЛЬНЫЙ ФАКТ ПЕРЕД ОПОРНЫМ: носитель назван ПОСЛЕ ссылки на него.
            #
            # ПОРЯДОК ПРЕДЛОЖЕНИЙ ЕСТЬ ПОКАЗАННЫЙ ФАКТ, А НЕ УДОБСТВО ПИСЬМА. Рамка,
            # ищущая опору слева от относительного факта, на этой странице её не найдёт:
            # опора стои́т справа. Свод пишет такой порядок редко, и читатель, выучивший
            # один порядок, на другом молчит — как и с ходом назад.
            вон.append(
                f"{больше_чем} {факт_меньшего} "
                f"how many {мн} does {больший} have? "
                f"{m} {by_count(m, мн)}: {n} + {d} = {m}.")
    return вон


def main():
    emit("datasets/genesis_relcompare.txt", показы)


if __name__ == "__main__":
    main()
