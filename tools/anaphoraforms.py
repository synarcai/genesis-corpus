#!/usr/bin/env python3
"""ДОМ АНАФОРЫ — второе упоминание лица, и ДВА способа его нести.

Замер по своду (04.09): местоименная отсылка живёт в русском (746 «она», 873
«он»), английском (608/547), немецком (324/586), французском (137) — и почти
или вовсе отсутствует в испанском (0 «ella»), итальянском (0 «lei») и польском
(0 «ona»). Три языка из девяти не показывают второго упоминания ни разу.

И ЭТО НЕ ПРОСТО ПРОБЕЛ, А ДВА РАЗНЫХ СТРОЯ, СМЕШАННЫХ В ОДНОМ ПРОБЕЛЕ.
Испанский, итальянский и польский ОПУСКАЮТ подлежащее: «Ana tiene 7 pelotas.
dio 2 pelotas» — второе упоминание несёт не местоимение, а ОКОНЧАНИЕ ГЛАГОЛА, и
поставить там «ella dio» значило бы написать неидиоматично. То есть корпус,
дописав им местоимения, научил бы неверной речи; а не дописав ничего — не
научил бы отсылке вовсе.

    у Анны 7 шаров. она отдала 2 шара. сколько у неё осталось? 5 шаров: 7 − 2 = 5.
    Ana tiene 7 pelotas. dio 2 pelotas. ¿cuántas le quedan? 5 pelotas: 7 − 2 = 5.
    Anna ma 7 piłek. dała 2 piłki. ile jej zostało? 5 piłek: 7 − 2 = 5.

ЯЗЫКИ РАЗДЕЛЕНЫ ОБЪЯВЛЕНИЕМ, А НЕ ДОГАДКОЙ: `ОПУСКАЮТ_ПОДЛЕЖАЩЕЕ` называет
поимённо те три, где второе упоминание несёт глагол. Прочие шесть ставят
местоимение, и оно согласуется с родом имени — оттого дом пишет ОБА рода, как
их пишет дом поведения после уплаты своего долга.

ФОРМА ВЕЩИ ПРИ ЧИСЛЕ БЕРЁТСЯ У ДОМА ПРИРОДЫ. Числа таковы, что вычитание не
уходит в ноль и не даёт единицу: у единицы своя форма вещи во всех славянских,
и показывать её здесь значило бы мерить не анафору, а склонение.

    python3 tools/anaphoraforms.py    # самопроверка с мутантами
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import natureforms as N  # noqa: E402

ПАРЫ = ((7, 2), (12, 5), (9, 4), (20, 8), (15, 6), (11, 3))
ОПУСКАЮТ_ПОДЛЕЖАЩЕЕ = frozenset({"es", "it", "pl"})

ВЕЩИ = {
    "ru": ("шар", "книга", "монета", "яблоко"),
    "pl": ("piłka", "książka", "moneta", "jabłko"),
    "en": (("ball", "balls"), ("book", "books"), ("coin", "coins"), ("apple", "apples")),
    "de": (("Ball", "Bälle"), ("Buch", "Bücher"), ("Münze", "Münzen"), ("Apfel", "Äpfel")),
    "fr": (("balle", "balles"), ("livre", "livres"), ("pièce", "pièces"), ("pomme", "pommes")),
    "es": (("pelota", "pelotas"), ("libro", "libros"), ("moneda", "monedas"), ("manzana", "manzanas")),
    "it": (("palla", "palle"), ("libro", "libri"), ("moneta", "monete"), ("mela", "mele")),
    "pt": (("bola", "bolas"), ("livro", "livros"), ("moeda", "moedas"), ("maçã", "maçãs")),
    "nl": (("bal", "ballen"), ("boek", "boeken"), ("munt", "munten"), ("appel", "appels")),
}

# (имена женские, имена мужские) — по два на язык довольно: дом мерит отсылку,
# а не разнообразие имён
ИМЕНА = {
    "ru": (("Анна", "Ольга"), ("Пётр", "Иван")),
    "en": (("anna", "kate"), ("tom", "ben")),
    "de": (("Anna", "Lena"), ("Paul", "Jonas")),
    "fr": (("Anne", "Claire"), ("Paul", "Hugo")),
    "es": (("Ana", "Elena"), ("Pablo", "Luis")),
    "it": (("Anna", "Chiara"), ("Marco", "Luca")),
    "pt": (("Ana", "Rita"), ("Pedro", "Rui")),
    "nl": (("Anna", "Lotte"), ("Paul", "Jonas")),
    "pl": (("Anna", "Ewa"), ("Piotr", "Marek")),
}

# РОДИТЕЛЬНЫЙ ИМЕНИ — только русскому и только потому, что его рамка стоит на
# предлоге «у»: «у Анны», а не «у Анна». Падеж имени объявляется, а не
# выводится отсечением окончания (тот же закон, по которому дом историй
# отношений объявляет дательный: пакет их не держит).
ИМЕНА_РОДИТЕЛЬНЫЙ = {"Анна": "Анны", "Ольга": "Ольги", "Пётр": "Петра", "Иван": "Ивана"}

РАМКИ = {
    "ru": dict(ж="у {и} {a} {ва}. она отдала {b} {вб}. сколько у неё осталось? {c} {вс}: {a} − {b} = {c}.",
               м="у {и} {a} {ва}. он отдал {b} {вб}. сколько у него осталось? {c} {вс}: {a} − {b} = {c}."),
    "en": dict(ж="{и} has {a} {ва}. she gave away {b} {вб}. how many does she have left? {c} {вс}: {a} − {b} = {c}.",
               м="{и} has {a} {ва}. he gave away {b} {вб}. how many does he have left? {c} {вс}: {a} − {b} = {c}."),
    "de": dict(ж="{и} hat {a} {ва}. sie gab {b} {вб} weg. wie viele hat sie noch? {c} {вс}: {a} − {b} = {c}.",
               м="{и} hat {a} {ва}. er gab {b} {вб} weg. wie viele hat er noch? {c} {вс}: {a} − {b} = {c}."),
    "fr": dict(ж="{и} a {a} {ва}. elle a donné {b} {вб}. combien lui en reste-t-il ? {c} {вс} : {a} − {b} = {c}.",
               м="{и} a {a} {ва}. il a donné {b} {вб}. combien lui en reste-t-il ? {c} {вс} : {a} − {b} = {c}."),
    "nl": dict(ж="{и} heeft {a} {ва}. zij gaf {b} {вб} weg. hoeveel heeft zij nog? {c} {вс}: {a} − {b} = {c}.",
               м="{и} heeft {a} {ва}. hij gaf {b} {вб} weg. hoeveel heeft hij nog? {c} {вс}: {a} − {b} = {c}."),
    "pt": dict(ж="{и} tem {a} {ва}. ela deu {b} {вб}. quantas lhe restam? {c} {вс}: {a} − {b} = {c}.",
               м="{и} tem {a} {ва}. ele deu {b} {вб}. quantas lhe restam? {c} {вс}: {a} − {b} = {c}."),
    # ТРИ ЯЗЫКА БЕЗ МЕСТОИМЕНИЯ: второе упоминание несёт ОКОНЧАНИЕ ГЛАГОЛА
    "es": dict(ж="{и} tiene {a} {ва}. dio {b} {вб}. ¿cuántas le quedan? {c} {вс}: {a} − {b} = {c}.",
               м="{и} tiene {a} {ва}. dio {b} {вб}. ¿cuántas le quedan? {c} {вс}: {a} − {b} = {c}."),
    "it": dict(ж="{и} ha {a} {ва}. ne ha date {b}. quante gliene restano? {c} {вс}: {a} − {b} = {c}.",
               м="{и} ha {a} {ва}. ne ha date {b}. quante gliene restano? {c} {вс}: {a} − {b} = {c}."),
    "pl": dict(ж="{и} ma {a} {ва}. dała {b} {вб}. ile jej zostało? {c} {вс}: {a} − {b} = {c}.",
               м="{и} ma {a} {ва}. dał {b} {вб}. ile mu zostało? {c} {вс}: {a} − {b} = {c}."),
}

ЯЗЫКИ = tuple(РАМКИ)
ФОРМЫ = ("ж", "м")

for _a, _b in ПАРЫ:
    assert _a - _b >= 2, (_a, _b)      # единица имеет свою форму вещи; не наш предмет
for _имя in ИМЕНА["ru"][0] + ИМЕНА["ru"][1]:
    assert _имя in ИМЕНА_РОДИТЕЛЬНЫЙ, _имя
for _яз in ЯЗЫКИ:
    assert len(ВЕЩИ[_яз]) == len(ВЕЩИ["ru"]), _яз
    assert len(ИМЕНА[_яз]) == 2 and all(len(р) == 2 for р in ИМЕНА[_яз]), _яз
    assert set(РАМКИ[_яз]) == set(ФОРМЫ), _яз


def страница(язык, форма, i):
    a, b = ПАРЫ[i % len(ПАРЫ)]
    c = a - b
    в = ВЕЩИ[язык][i % len(ВЕЩИ[язык])]
    имена = ИМЕНА[язык][0 if форма == "ж" else 1]
    и = имена[(i // len(ПАРЫ)) % len(имена)]
    if язык == "ru":
        и = ИМЕНА_РОДИТЕЛЬНЫЙ[и]
    return РАМКИ[язык][форма].format(
        и=и, a=a, b=b, c=c, ва=N.вещь(язык, в, a), вб=N.вещь(язык, в, b), вс=N.вещь(язык, в, c))


def _показы():
    return {страница(язык, форма, i): (язык, форма)
            for язык in ЯЗЫКИ for форма in ФОРМЫ for i in range(2 * len(ПАРЫ))}


ПОКАЗЫ = _показы()


def main():
    поймано = 0
    for язык in ЯЗЫКИ:
        метка = "без местоимения" if язык in ОПУСКАЮТ_ПОДЛЕЖАЩЕЕ else "с местоимением"
        print(f"  {язык} ({метка}): {страница(язык, 'ж', 0)}")
        a, b = ПАРЫ[0]
        в = ВЕЩИ[язык][0]
        и = ИМЕНА[язык][0][0]
        if язык == "ru":
            и = ИМЕНА_РОДИТЕЛЬНЫЙ[и]
        # МУТАНТЫ: неверный остаток; форма вещи от другого числа; мужская
        # рамка при женском имени (там, где рамки различаются)
        мутанты = (РАМКИ[язык]["ж"].format(и=и, a=a, b=b, c=a - b + 1, ва=N.вещь(язык, в, a),
                                           вб=N.вещь(язык, в, b), вс=N.вещь(язык, в, a - b + 1)),
                   РАМКИ[язык]["ж"].format(и=и, a=a, b=b, c=a - b, ва=N.вещь(язык, в, b),
                                           вб=N.вещь(язык, в, b), вс=N.вещь(язык, в, a - b)),
                   РАМКИ[язык]["м"].format(и=и, a=a, b=b, c=a - b, ва=N.вещь(язык, в, a),
                                           вб=N.вещь(язык, в, b), вс=N.вещь(язык, в, a - b)))
        for м in мутанты:
            поймано += 0 if м in ПОКАЗЫ else 1
    # НЕПОЙМАННЫЙ МУТАНТ ЗДЕСЬ НЕ ИЗЪЯН, А ЗАКОННЫЙ ПОКАЗ, и это проверяется
    # принадлежностью к ПОКАЗЫ, а не рассуждением. Две причины, по которым
    # мутант совпадает с показом: рамки родов совпадают слово в слово там, где
    # язык опускает подлежащее; и форма вещи одна там, где счёт не различает
    # 7 и 2 (все неславянские). Обе законны, и обе названы числом.
    законных = 3 * len(ЯЗЫКИ) - поймано
    print(f"  мутантов вне показов: {поймано} из {3 * len(ЯЗЫКИ)}; "
          f"остальные {законных} суть ЗАКОННЫЕ показы — проверено принадлежностью, "
          f"а не рассуждением")
    print(f"  дом пишет показов: {len(ПОКАЗЫ)} (языков {len(ЯЗЫКИ)}, пар {len(ПАРЫ)}, "
          f"опускают подлежащее {len(ОПУСКАЮТ_ПОДЛЕЖАЩЕЕ)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
