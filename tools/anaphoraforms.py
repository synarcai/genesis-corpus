# ЛИЦО БЕЗ ИМЕНИ — НОСИТЕЛЬ СТРАНИЦЫ, И ЭТОГО СВОД НЕ ГОВОРИЛ НИГДЕ (13.09).
#
# Долг назван соседом (holon-f9) на страницах возраста, писанных от первого лица: их рынок
# местоимений покупает «я/ты/мы» лишь как ДЕЯТЕЛЕЙ с референтом в истории, а у первого лица
# референта в тексте нет. Проверка по своду: о ЛИЦЕ первого лица корпус говорил только в
# согласовании глагола («„je“ есть лицо „я“»), а о том, КОГО это лицо называет, — нигде.
#
#     МЕСТОИМЕНИЕ ТРЕТЬЕГО ЛИЦА ИЩЕТ ИМЯ В ТЕКСТЕ; ПЕРВОЕ ЛИЦО ЕГО НЕ ИЩЕТ — И ЭТО НЕ ДЫРА
#     В СТРАНИЦЕ, А ЕЁ УСТРОЙСТВО.
#
# Показ несёт то же вычитание, что и весь мир, и добавляет к нему ОДНО утверждение о себе:
# имени носителя в странице нет. Утверждение это ПРОВЕРЯЕМО механически — суд смотрит, что
# ни одно объявленное имя в строке не стои́т, — и потому оно есть закон, а не заверение.
#
# ВРЕМЯ НАСТОЯЩЕЕ, И ЭТО НЕ ВКУС: русское прошедшее первого лица несёт РОД («я отдал» против
# «я отдала»), а род говорящего страница знать не может. Настоящее его не требует.
