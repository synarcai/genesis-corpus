#!/usr/bin/env python3
"""THE CLOSED WORLD — a line of a world every line of which is a shape of
its court, and which that court does not recognise, is a lie.

The gate demands that every line be judged by SOME court; a corrupted line
of the rates world («th book costs 26 dollars…», «he ha 56 dollars…») was
judged by the count court alone and passed (mutation 04.09). Where the
world's own court covers all of the world's honest lines, silence of that
court on a line of that world is not honest silence but a shape the world
never wrote. A court declares its closed worlds by name; the palata hands
it the layer of the file being judged (the world's name, read from the
manifest — the gate's temporary «<world>.txt.ворота» included).
"""
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
МАНИФЕСТ = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"


class Слой:
    """Протокол палаты: создаётся пустым и впитывает файл мира."""

    def __init__(self):
        self.мир = None

    def впитать(self, путь):
        имя = pathlib.Path(путь).name
        for суффикс in (".ворота",):
            if имя.endswith(суффикс):
                имя = имя[:-len(суффикс)]
        try:
            м = json.loads(МАНИФЕСТ.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return
        for мир in м.get("worlds", ()):
            if pathlib.Path(мир.get("file", "")).name == имя:
                self.мир = мир.get("name")
                return


def замкнут(слой, миры):
    """Is the file being judged one of the court's closed worlds?"""
    return слой is not None and getattr(слой, "мир", None) in миры


def замкнуть(судить_, миры):
    """The court's judge wrapped by the law: silence on a line of a closed
    world becomes a lie. The palata passes the layer when the court exports
    `Слой` (import it from here beside this call)."""
    миры = frozenset(миры)

    def судить(строка, слой=None):
        вердикт = судить_(строка)
        if вердикт[0] is False and замкнут(слой, миры) and строка.strip() and not строка.startswith("\x0c"):
            return True, False
        return вердикт
    судить.__wrapped__ = судить_
    return судить


# СЛОЙ ОДИН, А ПОЛЕЙ У НЕГО ДВА (06.09). Суд, у которого слой УЖЕ несёт свой смысл —
# договор полки у `engram`, лица говорящих у `speech` и `episode`, — не может отдать
# своё поле под имя мира: палата кладёт в `слои[имя]` РОВНО ОДИН предмет, и два слоя в
# одном имени столкнулись бы молча. Обёртка выше слой СЪЕДАЕТ (зовёт `судить_(строка)`),
# и для таких судов она не годится: замыкание отняло бы у них договор.
#
#     ЗАМЫКАНИЕ ЕСТЬ НАДСТРОЙКА НАД ЧТЕНИЕМ, А НЕ ЗАМЕНА ЕМУ. Суд, читающий слой,
#     обязан получить его целиком; имя мира едет в том же слое отдельным полем.
#
# Потому здесь второй ход обёртки, а слой таких судов наследует `Слой` этого модуля и
# зовёт `super().впитать` первым: одно поле `мир` от нас, прочие — от суда.
def замкнуть_слоем(судить_, миры):
    """Как `замкнуть`, но слой ПЕРЕДАЁТСЯ суду, а не съедается обёрткой."""
    миры = frozenset(миры)

    def судить(строка, слой=None):
        вердикт = судить_(строка, слой)
        if вердикт[0] is False and замкнут(слой, миры) and строка.strip() \
                and not строка.startswith("\x0c"):
            return True, False
        return вердикт
    судить.__wrapped__ = судить_
    return судить


# ЦИФРОВОЙ СКЕЛЕТ — ЗАКОН ЗАМКНУТОГО МИРА, ПРОДОЛЖЕННЫЙ НА ЦИФРЫ (05.09, прибор мутантов:
# СЕМЬ судов ОНЕМЕЛИ на порче одного числа). Дом, чьи показы объявлены списком, узнаёт свою
# строку по букве — и порча «в сутках 24 часа» → «в сутках 25 часа» выводит её из
# объявленного. Суд молчит, палата отдаёт молчание соседу, и ложь проходит.
#
# ЗАКОН: строка, отличающаяся от показа ЛИШЬ ЦИФРАМИ, есть строка ЭТОГО дома — и, не будучи
# показом, есть его ЛОЖЬ. Это ровно то, что уже объявлено словами «мир замкнут»: набор
# показов полон, и всё, что имеет форму показа, но показом не является, ложно. Цифра формы
# не меняет.
#
# ГРАНИЦА: закон применим лишь там, где мир ОБЪЯВЛЕН ЗАМКНУТЫМ (его показы суть весь мир).
# Дом, чьи страницы порождаются законом над свободными числами, судит числа своим законом, и
# скелет ему не судья — там повторное вхождение дыры проверяется значением (см. дома ночи).
_ЦИФРЫ = __import__("re").compile(r"\d+")


def скелет(строка):
    """«в сутках 24 часа» → «в сутках # часа»: строка без своих чисел."""
    return _ЦИФРЫ.sub("#", строка.strip())


def скелеты(показы):
    """Множество скелетов объявленных показов — читается домом один раз при сборке."""
    return frozenset(скелет(с) for с in показы)


def ложь_по_цифре(строка, скелеты_, показы):
    """True — строка не показ, но отличается от показа лишь цифрами: ложь дома."""
    с = строка.strip()
    return с not in показы and скелет(с) in скелеты_


# ЛОЖЬ ПО ЗНАКУ — БРАТ ЗАКОНА ВЫШЕ, И ДОВОД ТОТ ЖЕ.
#
# Прибор scripts/sign_traps.py (06.09) нашёл 29 домов, немеющих на подмене СОБСТВЕННОГО знака
# действия: «сложи 3 и 4. что получится? 7: 3 − 4 = 7.» — дом операции молчал; «полчаса — это
# сколько минут? 30 минут: 60 × 2 = 30.» — дом дроби молчал. Образец, держащий знак БУКВОЙ, не
# совпадает с испорченной строкой, и суд говорит «не моя» там, где обязан сказать «ложь». Палата
# ловила их судом арифметики — то есть брала истину У СОСЕДА (М-131), и в день, когда сосед
# сузится, порча стала бы невидимой.
#
# ЗАКОН: строка, которая СТАНОВИТСЯ ИСТИННОЙ СТРАНИЦЕЙ дома при замене ОДНОГО знака действия,
# есть строка ЭТОГО дома с испорченным знаком — то есть его ЛОЖЬ. Довод тот же, что у цифры:
# знак формы страницы не меняет, а замкнутый мир полон, и всё, что имеет форму показа, но
# показом не является, ложно.
#
# ГРАНИЦА, НАЗВАННАЯ ЧЕСТНО: дом, где ЗНАК И ЕСТЬ ПРЕДМЕТ ВОПРОСА («сколько будет 0 × 5?» рядом
# с «сколько будет 0 ÷ 5?»), показывает два РАЗНЫХ показа, различающихся только знаком. Замер по
# всем 68 домам с показами нашёл ровно один такой — crossforms, 28 пар. Для него закон всё равно
# верен: строка, чей ВОПРОС говорит «×», а леджер «÷», не есть ни один из двух показов и ложна.
# Ложного обвинения закон не даёт нигде: он зовёт ложью лишь то, что САМО не истинно.
#
# ЦЕНА: проверка идёт лишь тогда, когда строка НЕ ОПОЗНАНА образцом и её скелет со стёртым знаком
# известен дому. Честная страница не платит ничего, чужая строка — одного поиска в множестве.
# ЗНАК ДЕЙСТВИЯ ЕСТЬ ЗНАК МЕЖДУ ЧИСЛАМИ — и в живой строке, и в скелете, где число уже «#»
_ЗНАК_ДЕЙСТВИЯ = __import__("re").compile(r"(?<=[\d#] )[+−×÷](?= [\d#])")
_ЗНАКИ = "+−×÷"


def скелет_знака(строка):
    """«8 ÷ 2 = 16» → «# ○ # = #»: строка без своих чисел И без знака действия."""
    return _ЗНАК_ДЕЙСТВИЯ.sub("○", скелет(строка))


def скелеты_знака(показы):
    """Множество скелетов со стёртым знаком — читается домом один раз при сборке."""
    return frozenset(скелет_знака(с) for с in показы)


def ложь_по_знаку(строка, скелеты_знака_, показы, судить_):
    """True — строка не судима, но становится ИСТИННОЙ при замене одного знака действия.

    `судить_` — СЫРОЙ суд дома (тот, что читает образцом), а не обёрнутый: иначе проверка
    позвала бы саму себя.
    """
    с = строка.strip()
    if с in показы or скелет_знака(с) not in скелеты_знака_:
        return False
    for м in _ЗНАК_ДЕЙСТВИЯ.finditer(с):
        i = м.start()
        for знак in _ЗНАКИ:
            if знак == с[i]:
                continue
            судимо, истинно = судить_(с[:i] + знак + с[i + 1:])[:2]
            if судимо and истинно:
                return True
    return False

# ЛОЖЬ ПО СЛОВУ ВОПРОСА — ТРЕТИЙ БРАТ ЗАКОНОВ ЗАМКНУТОГО МИРА (06.09).
#
# Прибор подсадки словом держал 124 строки, где палата зовёт ПОРЧЕНУЮ строку ИСТИНОЙ, и
# имя долга было названо: СЛОВА ВОПРОСА НЕ ЧИТАЕТ НИКТО. Порченый вопрос («кратн ли 7
# числу 3?») остаётся вопросной половиной объявленной пары и покрыт правилом (б) закона
# покрытия; закон пары проверяет ВЕЛИЧИНЫ вопроса и их порядок, а слова — нет.
#
# ТРИ ПРАВИЛА БЫЛИ ПРЕДЛОЖЕНЫ И ДВА ОТВЕРГНУТЫ СОБСТВЕННЫМ ЗАМЕРОМ, прежде чем нашлось
# третье: «слово вопроса объявлено или повторено в ответе» роняло 3720 честных строк из
# 4655 (вопрос корпуса несёт СОДЕРЖАНИЕ, которого нет ни в объявлении, ни в ответе);
# «объявленный предикат обязан стоять целым» роняло 174, затем 34 — список собирался
# выборкой одного языка и не знал английских братьев тех же миров.
#
#     СПИСОК, СОБРАННЫЙ ВЫБОРКОЙ ОДНОГО ЯЗЫКА, ЕСТЬ ОБЪЯВЛЕНИЕ О ВЫБОРКЕ, А НЕ О МИРЕ.
#
# ЗАКОН: вопрос, несущий слово, которого нет НИ В ОДНОМ вопросе этого дома, не есть
# вопрос этого дома — и строка с ним ложна. Довод тот же, что у цифры и у знака: набор
# показов полон, и всё, что имеет форму показа, но показом не является, ложно.
#
# ЦЕНА РАВНА НУЛЮ ПО ПОСТРОЕНИЮ И ПРОВЕРЕНА ЗАМЕРОМ: словарь собирается из САМИХ
# ПОКАЗОВ, и честная страница несёт свои слова целыми. Замер по своду: 1389 честных
# вопросных строк — падает 0; порч, ныне зовомых истиной, ловится 66 из 70.
#
# ЧЕТЫРЕ, ПРОХОДЯЩИЕ МИМО, НАЗВАНЫ ЧИСЛОМ И ЛИЦОМ: порча даёт слово, которое В СЛОВАРЕ
# МИРА ЕСТЬ. «2^2 − 1 = 3 ist eine Primzahl» → «is eine Primzahl» в многоязычном мире
# `indu`, где «is» стои́т в голландских строках. Это честный предел закона: замкнутый
# мир замкнут по СЛОВАРЮ, а не по языку, и слово чужого языка того же мира ему своё.
#
# ВОРОТА НЕ ЗАПИРАЮТСЯ: замер по всем 39 домам с показами и своим файлом показал, что
# словарь вопроса ПОКАЗОВ и словарь вопроса ФАЙЛА совпадают точно в обе стороны — дом
# пишет ровно теми словами, что стоя́т в его мире. Дом, дописавший новую форму, приносит
# её слова СВОИМИ ПОКАЗАМИ, и закон читает их вместе с нею.
#
# УТОЧНЕНИЕ, ПРЕДЛОЖЕННОЕ И ОТВЕРГНУТОЕ ЗАМЕРОМ (holon): брать словарь по ВСЕМУ файлу
# мира за вычетом самой строки — чтобы порченый вопрос не подтвердил себя своим же
# ответом. Ловля растёт на две (66 → 68), но цена прыгает с нуля до 52: слово, стоящее в
# мире ОДИН раз (имя, товар единственной страницы), становится чужим самому себе.
# Словарь вопросов свободен от этого по построению: он включает и эту строку тоже, а
# порченое слово в него не входит НИКОГДА, ибо порча рождает слово, которого дом не
# писал.
_СЛОВО_ВОПРОСА = __import__("re").compile(r"(?<![\w-])[^\W\d_]{3,}(?![\w-])")


# ЗАТВОР, КУПЛЕННЫЙ ШРАМОМ ТОГО ЖЕ ЧАСА: первая редакция закона не спрашивала, ЧЬЯ это
# строка, — и дом цены назвал ложью честные строки чужих миров («кратно ли 7 числу 3?»,
# «сколько будет 14 + 3?», «what is the area of a rectangle 2 by 7?»). Прибор подсадки
# увидел это мгновенно: число ПРОБ упало с 4568 до 1856, ибо проба берётся лишь с
# истинной строки, а истинных стало вдвое меньше.
#
#     ЗАКОН ЗАМКНУТОГО МИРА ОБЯЗАН ЗНАТЬ, ЧЕЙ МИР ОН СУДИТ. Братья по семье — цифра и
#     знак — узнают свою строку СКЕЛЕТОМ: чужая строка не совпадает ни с одним, и закон
#     о ней молчит. У слова вопроса скелета нет: порча слова рушит скелет вместе со
#     словом, и признак остаётся без затвора.
#
# ЗАТВОР ВЗЯТ ПО ОТВЕТНОЙ ПОЛОВИНЕ: ответ строки обязан быть ответом ЭТОГО дома — то
# есть его скелет (цифры под «#») обязан стоять среди скелетов ответов показов. Тогда
# «одн яблоко стоит 2 рубля. сколько стоят 2 яблока? 4 рубля: 2 × 2 = 4.» судится (ответ
# домовый, вопрос порчен), а «кратно ли 7 числу 3? нет: 7 = 3 × 2 + 1, остаток 1.»
# проходит мимо — такого ответа дом цены не пишет.
def _ответ_и_вопрос(с):
    try:
        import asking
    except Exception:
        return None
    return asking.пара(с)


def словарь_вопроса(показы):
    """(слова вопросов дома, скелеты ответов дома) — читается один раз при сборке."""
    слова, ответы = set(), set()
    for показ in показы:
        пара = _ответ_и_вопрос(str(показ).strip())
        if пара is None:
            continue
        слова |= {м.group().lower() for м in _СЛОВО_ВОПРОСА.finditer(пара[0])}
        ответы.add(скелет(пара[1]))
    return frozenset(слова), frozenset(ответы)


def ложь_по_слову_вопроса(строка, словарь_, показы):
    """True — ответ строки домовый, а её вопрос несёт слово, которого дом не писал."""
    if not словарь_:
        return False
    слова, ответы = словарь_
    с = строка.strip()
    if с in показы or not слова or not ответы:
        return False
    пара = _ответ_и_вопрос(с)
    if пара is None or скелет(пара[1]) not in ответы:
        return False        # ответ не наш — строка чужая, и закон о ней молчит
    return any(м.group().lower() not in слова
               for м in _СЛОВО_ВОПРОСА.finditer(пара[0]))
