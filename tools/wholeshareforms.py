#!/usr/bin/env python3
"""ДОМ ДРОБИ И ЕДИНИЦЫ — дробь бывает больше целого, и тогда в ней есть ЦЕЛЫЕ.

    ДРОБЬ В СВОДЕ ВСЕГДА МЕНЬШЕ ЕДИНИЦЫ. Замер 11.09 по мирам показов: «неправильная дробь»,
    «improper fraction» — НОЛЬ вхождений; «смешанное число», «mixed number» — НОЛЬ; «дробь есть
    деление» — НОЛЬ. Дом долей говорит «две трети от 12», дом сравнения — какая доля больше, и
    ни один не показывает дроби, у которой числитель БОЛЬШЕ знаменателя.

    ДОЛЯ, ПОКАЗАННАЯ ТОЛЬКО МЕНЬШЕЙ ЕДИНИЦЫ, ЧИТАЕТСЯ КАК ЧАСТЬ, А НЕ КАК ЧИСЛО. Читатель,
    видевший лишь такие, сочтёт «7/3» опиской.

ЧЕТЫРЕ РОДА, И ВСЕ ОПИРАЮТСЯ НА ОДИН ЛЕДЖЕР — ДЕЛЕНИЕ С ОСТАТКОМ:

    больше     7/3 больше единицы, ибо числитель 7 больше знаменателя 3: 7 = 3 × 2 + 1.
    меньше     2/3 меньше единицы, ибо числитель 2 меньше знаменателя 3, и целых нет вовсе:
               2 = 3 × 0 + 2.
    ровно      3/3 есть ровно единица, ибо числитель 3 равен знаменателю 3: 3 = 3 × 1 + 0.
    целых      7/3 есть 2 целых и 1/3, ибо 7 = 3 × 2 + 1: целых столько, сколько раз
               знаменатель вошёл в числитель, а остаток даёт долю.   ← РАЗБОР НА ЦЕЛОЕ И ДОЛЮ

ПЕРВЫЕ ТРИ РОДА СУТЬ ПОЛНЫЙ РЯД СРАВНЕНИЯ С ЕДИНИЦЕЙ, и третий не лишний: без него читатель
делит дроби надвое — «меньше» и «больше», — а «3/3» окажется меж двух стульев.

ЧЕТВЁРТЫЙ РОД ЕСТЬ ТО, РАДИ ЧЕГО ДОМ ЗАВЕДЁН: он говорит, ЧТО ИМЕННО значит «больше единицы» —
не «странная запись», а два целых и ещё треть. И говорит одним и тем же ледже́ром: частное даёт
целые, остаток даёт долю.

    ОДНО ДЕЛЕНИЕ С ОСТАТКОМ ОТВЕЧАЕТ НА ОБА ВОПРОСА: сколько тут целых и что от них осталось.

ЛЕДЖЕР ПИШЕТСЯ И ТАМ, ГДЕ ЧАСТНОЕ РАВНО НУЛЮ («2 = 3 × 0 + 2»), И ТАМ, ГДЕ ОСТАТОК НУЛЕВОЙ
(«3 = 3 × 1 + 0»). Это не украшение ради единообразия: показ, где ход опущен «за очевидностью»,
учит опускать его и там, где он нужен.

ЗНАМЕНАТЕЛИ БЕРУТСЯ ОТ ДВУХ ДО ДВЕНАДЦАТИ, ЧИСЛИТЕЛИ ДО ДВАДЦАТИ ЧЕТЫРЁХ: ледже́р должен читаться глазом.

    python3 tools/wholeshareforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("больше", "меньше", "ровно", "целых")

РАМКИ = {
    "ru": {
        "больше": "{a}/{b} больше единицы, ибо числитель {a} больше знаменателя {b}: {a} = {b} × {q} + {r}.",
        "меньше": "{a}/{b} меньше единицы, ибо числитель {a} меньше знаменателя {b}, и целых нет вовсе: {a} = {b} × 0 + {a}.",
        "ровно": "{a}/{b} есть ровно единица, ибо числитель {a} равен знаменателю {b}: {a} = {b} × 1 + 0.",
        "целых": "{a}/{b} есть {q} целых и {r}/{b}, ибо {a} = {b} × {q} + {r}: целых столько, сколько раз знаменатель вошёл в числитель, а остаток даёт долю.",
    },
    "en": {
        "больше": "{a}/{b} is greater than one, because the numerator {a} is greater than the denominator {b}: {a} = {b} × {q} + {r}.",
        "меньше": "{a}/{b} is less than one, because the numerator {a} is less than the denominator {b}, and there are no wholes at all: {a} = {b} × 0 + {a}.",
        "ровно": "{a}/{b} is exactly one, because the numerator {a} equals the denominator {b}: {a} = {b} × 1 + 0.",
        "целых": "{a}/{b} is {q} wholes and {r}/{b}, because {a} = {b} × {q} + {r}: there are as many wholes as times the denominator went into the numerator, and the remainder gives the share.",
    },
}


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        # ЗНАМЕНАТЕЛИ ДО ДВЕНАДЦАТИ, И ЭТО КУПЛЕНО МЕРОЙ МАССЫ: род «ровно единица» возможен
        # ровно однажды на знаменатель («3/3», «4/4»), и при восьми знаменателях он набирал
        # ВОСЕМЬ страниц — меньше девяти, то есть непокупаем. Одиннадцать знаменателей дают
        # ему одиннадцать.
        for b in range(2, 13):
            for a in range(1, 25):
                q, r = divmod(a, b)
                поля = dict(a=a, b=b, q=q, r=r)
                if a < b:
                    вон[рамки["меньше"].format(**поля)] = (язык, "меньше")
                elif a == b:
                    вон[рамки["ровно"].format(**поля)] = (язык, "ровно")
                else:
                    вон[рамки["больше"].format(**поля)] = (язык, "больше")
                    # РАЗБОР НА ЦЕЛОЕ И ДОЛЮ ТОЛЬКО ПРИ НЕНУЛЕВОМ ОСТАТКЕ: при нулевом дробь
                    # есть ЦЕЛОЕ ЧИСЛО, и говорить «2 целых и 0/3» значило бы учить лишней
                    # доле там, где её нет.
                    if r:
                        вон[рамки["целых"].format(**поля)] = (язык, "целых")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ДРОБНАЯ ЧЕРТА ЕСТЬ ГРАНИЦА ЧИСЛА: без оглядки на «/» сравнение читается сквозь дробь.
_ОСТАТОК = re.compile(r"(?<![/\d])(\d+) = (\d+) × (\d+) \+ (\d+)(?![/\d])")
_БОЛЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:больше|is greater than) (\d+)(?![/\d])")
_МЕНЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:меньше|is less than) (\d+)(?![/\d])")
_РАВЕН = re.compile(r"(?<![/\d])(\d+) (?:равен|equals) (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: ледже́р и сравнение своими глазами. Остаток
    # обязан быть МЕНЬШЕ делителя — иначе деление не доведено до конца.
    for a, b, q, r in _ОСТАТОК.findall(с):
        if int(a) != int(b) * int(q) + int(r) or int(r) >= int(b):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    for a, b in _МЕНЬШЕ.findall(с):
        if int(a) >= int(b):
            return True, False
    for a, b in _РАВЕН.findall(с):
        if int(a) != int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    бо = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "больше")
    це = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "целых")
    if судить(бо.replace("больше", "меньше", 1))[1] is not False:
        беды.append("подмена направления прошла")
    if судить(це.replace("остаток", "остато"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(бо + " " + бо)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ДРОБЬ И ЕДИНИЦА: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
