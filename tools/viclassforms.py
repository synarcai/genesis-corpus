# СУД ЧИТАЕТ ТРИ ЗАКОНА, И ВСЕ ТРИ СОДЕРЖАТЕЛЬНЫ:
#   · счётное при имени обязано сойтись с объявленным;
#   · между числом и именем счётное обязано стоять;
#   · звёздочка стои́т ровно при нарушении.
_СЧЁТНОЕ = {и: с for и, с, _, _, _, _ in ИМЕНА}
_ВСЕ_СЧЁТНЫЕ = set(_СЧЁТНОЕ.values())
_ЧИСЛА_СЛ = {ч for ч, _, _, _ in ЧИСЛА}
_ИМЕНА_РЕ = "|".join(sorted(_СЧЁТНОЕ, key=len, reverse=True))
_ТРОЙКА = _re.compile(r"\b(" + "|".join(sorted(_ЧИСЛА_СЛ)) + r")\s+(?:(" +
                      "|".join(sorted(_ВСЕ_СЧЁТНЫЕ)) + r")\s+)?(" + _ИМЕНА_РЕ + r")\b")

_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _нарушает(тело):
    """Нарушает ли цитата закон дома: чужое счётное или его отсутствие."""
    for _чис, сч, имя in _ТРОЙКА.findall(тело.lstrip("*").strip()):
        if _СЧЁТНОЕ.get(имя) != сч:
            return True                      # чужое счётное — или его нет вовсе
    return False


# ЦИТАТА ЕСТЬ РЕЧЬ ОБЪЯВЛЕННОГО ЯЗЫКА, И ВСЯКИЙ ЕЁ КУСОК СТОИ́Т В ТАБЛИЦЕ (13.09).
#
# `scripts/house_mutant.py` назвал дом СТЕРЕГУЩИМ НАБОРОМ, А НЕ ЗАКОНОМ, и был прав: порча,
# вписанная в набор показов, ломала цитату так, что признак её больше не узнавал, — и закон,
# проверяющий лишь узнанное, молчал.
#
#     ЗАКОН, ПРОВЕРЯЮЩИЙ ЛИШЬ ТО, ЧТО РАСПОЗНАЛ, СЛЕП К ПОРЧЕ, СДЕЛАВШЕЙ ЦИТАТУ
#     НЕРАСПОЗНАВАЕМОЙ: испортить строку до неузнаваемости — вернейший способ пройти суд,
#     читающий по образцу.
#
# Второй закон дома потому таков: цитата, несущая хоть один НЕОБЪЯВЛЕННЫЙ кусок, ложна сама
# по себе, распознан в ней образец или нет.
# В объявленное входит и КИТАЙСКИЙ ЗНАК СОСЕДА: дом сравнивает наборы разрядов и цитирует
# его прямо («по-китайски то же берёт „只“»), а цитата соседа тоже объявлена таблицей.
_ОБЪЯВЛЕНО = ({ч for ч, _, _, _ in ЧИСЛА}
              | {с for _, с, *_ in ИМЕНА} | {и for и, *_ in ИМЕНА}
              | {ост[-1] for _, _, *ост in ИМЕНА if ост[-1]})


def _чужое_в_цитате(тело):
    """Слово цитаты, не объявленное таблицей дома, — либо None."""
    for слово in тело.lstrip("*").split():
        if слово not in _ОБЪЯВЛЕНО:
            return слово
    return None


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        if _чужое_в_цитате(цитата) is not None:
            return True, False
        if not _ТРОЙКА.search(цитата.lstrip("*")):
            continue
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


