#!/usr/bin/env python3
"""ДОМ ИМЕНОВАННОГО ЧИСЛА — ОСНОВАНИЕ ПЕРЕНОСА ОБЪЯВЛЯЕТ ЕДИНИЦА, А НЕ ЧИСЛО.

    НИ ОДНОЙ СТРОКОЙ СВОД НЕ СКЛАДЫВАЕТ МЕТРЫ С САНТИМЕТРАМИ. Замер 11.09 по 251 миру показов
    (429 194 строки): «N м N см», «N км N м», «N кг N г» — НОЛЬ.

Перенос через недесятичное основание в своде ЕСТЬ, и он один: дом часов (`clockforms`) 117 раз
складывает и вычитает время — «11 часов 45 минут + 2 часа 35 минут = 14 часов 20 минут». Шестьдесят
минут в часе, и перенос идёт через шестьдесят. Больше нигде.

    ЗАКОН, ПОКАЗАННЫЙ НА ОДНИХ ЧАСАХ, ЧИТАЕТСЯ КАК СВОЙСТВО ЧАСОВ. Читатель, видевший перенос
    только через 60, выведет, что 60 и есть правило, — и в метре, где сто сантиметров, ошибётся.

ЭТОТ ДОМ БЕРЁТ ЧУЖОЙ ЗАКОН И СПРАШИВАЕТ, ЧЕЙ ОН: часов или переноса. Ответ дан делом — тот же
перенос на четырёх мерах с ТРЕМЯ РАЗНЫМИ ОСНОВАНИЯМИ:

    в метре 100 сантиметров      в километре 1000 метров
    в рубле 100 копеек           в килограмме 1000 граммов

ЧЕТЫРЕ РОДА:

    перенос        3 метра 40 сантиметров и 1 метр 80 сантиметров дают вместе 5 метров
                   20 сантиметров, ибо 40 + 80 = 120, а в метре 100 сантиметров: 120 − 100 = 20.
    без переноса   …дают вместе 4 метра 90 сантиметров, ибо 40 + 50 = 90, и 90 меньше 100.
    заём           от 5 метров 20 сантиметров отнять 1 метр 80 сантиметров остаётся 3 метра
                   40 сантиметров, ибо 20 меньше 80 и один метр берётся в заём.
    основание      в метре 100 сантиметров, а в килограмме 1000 граммов, и ТЕ ЖЕ ЧИСЛА дают
                   разный перенос: 40 + 80 = 120, и 120 больше 100, но 120 меньше 1000.

ВТОРОЙ РОД ЕСТЬ УПРАВА: без него читатель выведет, что перенос бывает всегда. ТРЕТИЙ — обратный
ход того же закона: при вычитании основание не прибавляется, а занимается. ЧЕТВЁРТЫЙ говорит
закон делом, и говорит его ЕДИНСТВЕННЫМ способом, каким закон об основании вообще можно показать:
двумя мерами на одних и тех же числах.

    ОДНА МЕРА ПОКАЗЫВАЕТ ПЕРЕНОС; ДВЕ МЕРЫ С РАЗНЫМИ ОСНОВАНИЯМИ ПОКАЗЫВАЮТ, ЧТО ОСНОВАНИЕ
    ЕСТЬ СВОЙСТВО МЕРЫ.

ИМЕНОВАННАЯ СУММА ПИШЕТСЯ СЛОВОМ, А НЕ ЗНАКОМ РАВЕНСТВА, и это куплено замером. Письмо соседа —
«3 метра 40 сантиметров + 1 метр 80 сантиметров = 5 метров 20 сантиметров» — суд арифметики НЕ
ЧИТАЕТ ВОВСЕ: проба четырёх таких строк дала «0 ложных из 0 судимых, неразобрано 4». Переписанные
словом («дают вместе»), те же страницы дали «0 ложных из 3 судимых, неразобрано 1».

    РАВЕНСТВО, КОТОРОГО НЕ ЧИТАЕТ НИ ОДИН СОСЕД, ЕСТЬ УТВЕРЖДЕНИЕ ПОД ОХРАНОЙ ОДНОГО ДОМА.
    Слово вместо знака отдаёт страницу общему суду — и всякий знак равенства на ней прочтён.

ПИСЬМО СОСЕДА НЕ ПРАВЛЕНО: дом часов живёт как жил, и переписывать его ради единообразия значило
бы править чужой дом ради своего удобства.

ОСНОВАНИЯ ОБЪЯВЛЕНЫ ТАБЛИЦЕЙ, А НЕ ВЫВЕДЕНЫ: сколько сантиметров в метре — знание о мире, а не
следствие счёта. Тем же законом живут счётные тройки `rugram` и границы вещей в `plaus`:
ФАКТ, КОТОРОГО НЕОТКУДА ВЫВЕСТИ, ОБЪЯВЛЯЕТСЯ ПОИМЁННО.

    python3 tools/carryforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётные формы мер объявлены там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("перенос", "без переноса", "заём", "основание")

# МЕРА: (большая, малая, основание). ЗНАНИЕ О МИРЕ, ОБЪЯВЛЕННОЕ, А НЕ ВЫВЕДЕННОЕ.
МЕРЫ = (("метр", "сантиметр", 100),
        ("рубль", "копейка", 100),
        ("километр", "метр", 1000),
        ("килограмм", "грамм", 1000))
АНГЛ = {"метр": ("metre", "metres"), "сантиметр": ("centimetre", "centimetres"),
        "рубль": ("rouble", "roubles"), "копейка": ("kopeck", "kopecks"),
        "километр": ("kilometre", "kilometres"), "килограмм": ("kilogram", "kilograms"),
        "грамм": ("gram", "grams")}


def форма(язык, ключ, n):
    if язык == "en":
        один, много = АНГЛ[ключ]
        return один if n == 1 else много
    return rugram.форма(ключ, n)


# ПРЕДЛОЖНЫЙ ПАДЕЖ ОБЪЯВЛЕН ПОИМЁННО: таблица `rugram` даёт счётные формы, а не падежи
# единственного числа, и брать у неё то, чего она не обещала, значило бы лгать о языке.
_ПРЕДЛОЖНЫЙ = {"метр": "в метре", "рубль": "в рубле", "километр": "в километре",
               "килограмм": "в килограмме"}


def предл(язык, ключ):
    """«в метре», «in a metre» — оборот, в котором названо основание."""
    return f"in a {АНГЛ[ключ][0]}" if язык == "en" else _ПРЕДЛОЖНЫЙ[ключ]

РАМКИ = {
    "ru": {
        "перенос": "{a} {б_a} {c} {м_c} и {d} {б_d} {e} {м_e} дают вместе {s} {б_s} {t} {м_t}, "
                   "ибо {c} + {e} = {ce}, а {предл} {осн} {м_осн}: {ce} − {осн} = {t}, "
                   "и {a} + {d} + 1 = {s}.",
        "без переноса": "{a} {б_a} {c} {м_c} и {d} {б_d} {e} {м_e} дают вместе {s} {б_s} {ce} "
                        "{м_ce}, ибо {c} + {e} = {ce}, и {ce} меньше {осн}: переноса нет, "
                        "и {a} + {d} = {s}.",
        # ПОСЛЕ «ОТ» СТОИ́Т РОДИТЕЛЬНЫЙ, А СЧЁТНАЯ ФОРМА ЕГО НЕ ДАЁТ: «от 4 метра» есть ложь
        # о языке. Оборот перестроен так, чтобы всюду стояла счётная форма самого числа.
        "заём": "было {s} {б_s} {t} {м_t}, отняли {d} {б_d} {e} {м_e}, осталось {a} {б_a} "
                "{c} {м_c}, ибо {t} меньше {e} и {один_б} берётся в заём: {осн} + {t} = {ct}, "
                "и {ct} − {e} = {c}, и {s} − {d} − 1 = {a}.",
        "основание": "{предл} {осн} {м_осн}, а {предл2} {осн2} {м_осн2}, и те же числа дают "
                     "разный перенос: {c} + {e} = {ce}, и {ce} больше {осн}, "
                     "но {ce} меньше {осн2}.",
    },
    "en": {
        "перенос": "{a} {б_a} {c} {м_c} and {d} {б_d} {e} {м_e} come to {s} {б_s} {t} {м_t}, "
                   "for {c} + {e} = {ce}, and {предл} there are {осн} {м_осн}: "
                   "{ce} − {осн} = {t}, and {a} + {d} + 1 = {s}.",
        "без переноса": "{a} {б_a} {c} {м_c} and {d} {б_d} {e} {м_e} come to {s} {б_s} {ce} "
                        "{м_ce}, for {c} + {e} = {ce}, and {ce} is less than {осн}: there is "
                        "no carry, and {a} + {d} = {s}.",
        "заём": "there were {s} {б_s} {t} {м_t}, {d} {б_d} {e} {м_e} were taken away, and "
                "{a} {б_a} {c} {м_c} are left, for {t} is less than {e} and {один_б} is "
                "borrowed: {осн} + {t} = {ct}, and {ct} − {e} = {c}, and {s} − {d} − 1 = {a}.",
        "основание": "{предл} there are {осн} {м_осн}, and {предл2} there are {осн2} {м_осн2}, "
                     "and the same numbers give a different carry: {c} + {e} = {ce}, and {ce} "
                     "is greater than {осн}, but {ce} is less than {осн2}.",
    },
}
ПУСТО = dict(a=0, c=0, d=0, e=0, s=0, t=0, ce=0, ct=0, осн=0, осн2=0,
             б_a="", б_d="", б_s="", м_c="", м_e="", м_t="", м_ce="", м_осн="", м_осн2="",
             предл="", предл2="", один_б="")


def _доли(основание):
    """Малые доли, на которых куётся дом: круглые и читаемые."""
    шаг = основание // 10
    return tuple(range(шаг, основание, шаг))


def страницы():
    вон = {}
    сотни = [м for м in МЕРЫ if м[2] == 100]
    тысячи = [м for м in МЕРЫ if м[2] == 1000]
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for большая, малая, осн in МЕРЫ:
            доли = _доли(осн)
            for a in range(2, 8):
                for d in range(1, 6):
                    for c in доли:
                        for e in доли:
                            если = (a + d + c // (осн // 10) + e // (осн // 10) + len(большая))
                            общ = dict(ПУСТО, a=a, c=c, d=d, e=e, осн=осн,
                                       б_a=форма(язык, большая, a), б_d=форма(язык, большая, d),
                                       м_c=форма(язык, малая, c), м_e=форма(язык, малая, e),
                                       м_осн=форма(язык, малая, осн),
                                       предл=предл(язык, большая),
                                       один_б=("one " + форма(язык, большая, 1) if язык == "en"
                                               else "один " + форма(язык, большая, 1)))
                            if c + e >= осн and если % 11 == 0:
                                t = c + e - осн
                                стр = рамки["перенос"].format(
                                    **dict(общ, s=a + d + 1, t=t, ce=c + e,
                                           б_s=форма(язык, большая, a + d + 1),
                                           м_t=форма(язык, малая, t)))
                                вон[стр] = (язык, "перенос")
                                стр = рамки["заём"].format(
                                    **dict(общ, s=a + d + 1, t=t, ce=c + e, ct=осн + t,
                                           б_s=форма(язык, большая, a + d + 1),
                                           м_t=форма(язык, малая, t)))
                                вон[стр] = (язык, "заём")
                            if c + e < осн and если % 7 == 0:
                                стр = рамки["без переноса"].format(
                                    **dict(общ, s=a + d, ce=c + e,
                                           б_s=форма(язык, большая, a + d),
                                           м_ce=форма(язык, малая, c + e)))
                                вон[стр] = (язык, "без переноса")
        # ОСНОВАНИЕ ПОКАЗЫВАЕТСЯ ДВУМЯ МЕРАМИ РАЗОМ: одна мера сказала бы о мере, а не об
        # основании. Числа берутся те, что переносятся в сотне и не переносятся в тысяче.
        for бол1, мал1, осн1 in сотни:
            for бол2, мал2, осн2 in тысячи:
                for c in _доли(осн1):
                    for e in _доли(осн1):
                        # ПАРА БЕРЁТСЯ ОДНА ИЗ ДВУХ ЗЕРКАЛЬНЫХ: «40 и 80» и «80 и 40»
                        # говорят одно, и вторая была бы повтором, а не показом.
                        if not (c < e and осн1 < c + e < осн2):
                            continue
                        стр = РАМКИ[язык]["основание"].format(
                            **dict(ПУСТО, c=c, e=e, ce=c + e, осн=осн1, осн2=осн2,
                                   м_осн=форма(язык, мал1, осн1), м_осн2=форма(язык, мал2, осн2),
                                   предл=предл(язык, бол1), предл2=предл(язык, бол2)))
                        вон[стр] = (язык, "основание")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# СВЁРТКА ДВУХ СЛАГАЕМЫХ НЕ СМЕЕТ ЛОВИТЬ ХВОСТ ТРЁХ. Первая редакция читала в «2 + 1 + 1 = 4»
# подстроку «1 + 1 = 4» и звала ложью 1692 честные страницы: у ДЕЙСТВИЯ, стоя́щего слева,
# отнимался его первый операнд.
#
#     СВЁРТКА, НЕ СМОТРЯЩАЯ ВЛЕВО, ЧИТАЕТ ХВОСТ ВЫРАЖЕНИЯ КАК ЦЕЛОЕ ВЫРАЖЕНИЕ.
_СУММА = re.compile(r"(?<![/\d])(?<!\+ )(\d+) \+ (\d+) = (\d+)(?![/\d])")
_СУММА3 = re.compile(r"(?<![/\d])(\d+) \+ (\d+) \+ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(?<!− )(\d+) − (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ3 = re.compile(r"(?<![/\d])(\d+) − (\d+) − (\d+) = (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c, d in _СУММА3.findall(с):
        if int(a) + int(b) + int(c) != int(d):
            return True, False
    for a, b, c, d in _РАЗНОСТЬ3.findall(с):
        if int(a) - int(b) - int(c) != int(d):
            return True, False
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    пн = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "перенос")
    осн = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "основание")
    for страница, слово, куда in ((пн, "вместе", "вмест"), (осн, "перенос", "перенс")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(пн + " " + пн)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # РОД ОСНОВАНИЯ ОБЯЗАН НЕСТИ ДВА РАЗНЫХ ОСНОВАНИЯ: одна мера сказала бы о мере.
    основания = set()
    for с, (я, р) in ПОКАЗЫ.items():
        if р == "основание" and я == "ru":
            основания |= {int(x) for x in re.findall(r"\b(100|1000)\b", с)}
    if основания != {100, 1000}:
        беды.append(f"род основания стои́т на одном основании: {sorted(основания)}")
    # ЗАЁМ ЕСТЬ ОБРАТНЫЙ ХОД ПЕРЕНОСА, И ОН КУЁТСЯ НА ТЕХ ЖЕ ТРОЙКАХ.
    пер = {len(с.split()) for с, (я, р) in ПОКАЗЫ.items() if р == "перенос"}
    зм = {len(с.split()) for с, (я, р) in ПОКАЗЫ.items() if р == "заём"}
    if not пер or not зм:
        беды.append("перенос или заём пуст")
    print(f"ИМЕНОВАННОЕ ЧИСЛО: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
