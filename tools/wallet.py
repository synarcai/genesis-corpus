# ВИНИТЕЛЬНЫЙ ПАДЕЖ ВЕЩИ — ОБЪЯВЛЕН, А НЕ ВЫВЕДЕН (21.09). Дом цены объявляет вещь в
# ИМЕНИТЕЛЬНОМ: «одна книга стоит 2 рубля». Здесь же вещь стои́т дополнением — «купил ОДНУ
