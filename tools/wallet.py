def _валюта(язык, сколько):
    """Счётная форма валюты для числа — ПРАВИЛОМ ПАКЕТА, а не выбором дома."""
    return P.форма(язык, P.ЯЗЫКИ[язык]["валюта"], сколько)


def _вещь(язык, i, сколько=1, падеж="им"):
    """Вещь в счётной форме; винительный берётся ИЗ ОБЪЯВЛЕНИЯ, а страницы без него нет."""
    таблица = P.ЯЗЫКИ[язык]["вещи"][i % len(P.ЯЗЫКИ[язык]["вещи"])]
    форма = P.форма(язык, таблица, сколько)
    if падеж == "вин" and язык in ВИНИТЕЛЬНЫЙ:
        return ВИНИТЕЛЬНЫЙ[язык].get(форма)     # None — страница НЕ ПИШЕТСЯ
    return форма


def _лицо(язык, i):
    ряд = A.ЛИЦА[язык]
    return ряд[i % len(ряд)]


def _дательный_pl(имя):
    """Польский дательный лица — только для объявленных; иначе страница НЕ ПИШЕТСЯ."""
    ряд = {"Anna": "Annie", "Piotr": "Piotrowi", "Maria": "Marii", "Jan": "Janowi",
           "Ewa": "Ewie", "Adam": "Adamowi", "Zofia": "Zofii", "Marek": "Markowi"}
    return ряд.get(имя)


def страница(язык, род, лицо_i, вещь_i, n, k):
    """Страница кошелька — или None, если объявления не хватает (падежа, формы)."""
    р = РЕЧЬ[язык]
    имя, пол, родит = _лицо(язык, лицо_i)
    а = ХВОСТ_ПОЛА.get(язык, {}).get(пол, "")
    общ = {"X": имя, "Xр": родит, "а": а}
    if язык == "pl":
        дат = _дательный_pl(имя)
        if дат is None:
            return None            # ПАДЕЖ, КОТОРОГО ДОМ НЕ ОБЪЯВИЛ, НЕ УГАДЫВАЕТСЯ
        общ["Xд"] = дат
    if род == "купил_остаток":
        if k >= n:
            return None
        r = n - k
        вин = _вещь(язык, вещь_i, падеж="вин")
        if вин is None:
            return None
        факт = (р["было"].format(**общ, n=n, Рn=_валюта(язык, n)) + " "
                + р["купил"].format(**общ, В=вин, k=k, Рk=_валюта(язык, k)))
        воп = р["воп_остаток"].format(**общ, Рм=_валюта(язык, 5))
        ответ = f"{r} {_валюта(язык, r)}"
        леджер = f"{n} − {k} = {r}."
    else:
        s = n + k
        # ТРАТА «НА {вещь}» ИДЁТ С ПРЕДЛОГОМ, И ПАДЕЖ ЕГО У СЛАВЯН ВИНИТЕЛЬНЫЙ ТОЖЕ
        в1, в2 = _вещь(язык, вещь_i, падеж="вин"), _вещь(язык, вещь_i + 1, падеж="вин")
        if в1 is None or в2 is None:
            return None
        факт = р["потратил"].format(**общ, a=n, Рa=_валюта(язык, n), b=k,
                                    Рb=_валюта(язык, k), В=в1, В2=в2)
        воп = р["воп_потратил"].format(**общ, Рм=_валюта(язык, 5))
        ответ = f"{s} {_валюта(язык, s)}"
        леджер = f"{n} + {k} = {s}."
    return f"{факт} {воп} {ответ}{р['двоеточие']}{леджер}"


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for в in range(ВЕЩЕЙ):
                for i, n in enumerate(ЧИСЛА):
                    k = ЧИСЛА[(i + 3) % len(ЧИСЛА)]
                    с = страница(язык, род, i + в, в, n, k)
                    if с:
                        вон[с] = (язык, род)
    return вон


ПОКАЗЫ = _показы()

ЛЕДЖЕР = re.compile(r"(\d+)\s*([+−])\s*(\d+)\s*=\s*(\d+)\.$")
ХВОСТ = re.compile(r"[?？]\s")


def _образцы():
    """Рамки дома как образцы: суд узнаёт СВОЮ страницу по рамке, а не по признакам.

    СУЖЕНИЕ КУПЛЕНО ЗАХВАТОМ ЧУЖОГО (21.09). Первая редакция звала своей всякую строку, где
    есть валюта, леджер и вопросительный знак, — и назвала ЛОЖЬЮ честную страницу соседа:
    «Ben has 7 dollars. Felix has 2 dollars. Ava has 4 dollars. how many dollars do Ben
    Felix and Ava have?» Там три кошелька и сложение трёх, а здешний закон ждёт двух.

        ПРАВО НАЗВАТЬ СТРОКУ ЛОЖНОЙ ПОКУПАЕТСЯ СУЖЕНИЕМ. Открытая функция, судящая всё,
        есть ловушка для следующего, кто её позовёт, — и ловушка тем опаснее, что своя
        палата её не видит: чужие страницы в СВОЙ мир не попадают.

    Образец собирается из той же речи, какой пишется страница: рамка экранируется целиком,
    а дыры принимают лишь объявленное — числа цифрами, валюту в счётных формах, лицо из
    ряда дома действий, вещь — в объявленном винительном.
    """
    вон = []
    for язык in ЯЗЫКИ:
        р = РЕЧЬ[язык]
        лица = [л[0] for л in A.ЛИЦА[язык]]
        родит = [л[2] for л in A.ЛИЦА[язык]]
        валюты = {_валюта(язык, x) for x in range(1, 101)}
        вещи = set()
        for i in range(ВЕЩЕЙ + 1):
            for падеж in ("им", "вин"):
                в = _вещь(язык, i, падеж=падеж)
                if в:
                    вещи.add(в)
        альт = lambda ряд: "(?:" + "|".join(  # noqa: E731
            re.escape(з) for з in sorted({з for з in ряд if з}, key=lambda з: (-len(з), з))) + ")"
        # ДАТЕЛЬНЫЙ БЕРЁТСЯ ИЗ ТОГО ЖЕ ОБЪЯВЛЕНИЯ, ЧТО И СТРАНИЦА: образец, собранный из
        # иного источника, чем письмо, разойдётся с письмом на первом же имени.
        дательные = [д for д in (_дательный_pl(и) for и in лица) if д]
        дыры = {"X": альт(лица), "Xр": альт(родит), "Xд": альт(лица + родит + дательные),
                "а": "(?:а|a|)", "В": альт(вещи), "В2": альт(вещи),
                "Рм": альт(валюты)}
        for чис in ("n", "k", "a", "b"):
            дыры[чис] = r"\d+"
        for вал in ("Рn", "Рk", "Рa", "Рb"):
            дыры[вал] = альт(валюты)
        for род in РОДЫ:
            куски = (р["было"] + " " + р["купил"] + " " + р["воп_остаток"]
                     if род == "купил_остаток"
                     else р["потратил"] + " " + р["воп_потратил"])
            хвост = r"\s*(?P<v>\d+)\s+(?P<Рv>" + альт(валюты) + r")" \
                    + re.escape(р["двоеточие"]) + r"(?P<лед>[^\n]+)$"
            узор, счёт = "", {}
            for часть in re.split(r"(\{[^}]+\})", куски):
                if часть.startswith("{"):
                    имя = часть[1:-1]
                    счёт[имя] = счёт.get(имя, 0) + 1
                    узор += f"(?P<{имя}_{счёт[имя]}>{дыры.get(имя, '.+?')})"
                else:
                    узор += re.escape(часть)
            вон.append((re.compile("^" + узор + хвост), язык, род))
    return tuple(вон)


ОБРАЗЦЫ = _образцы()


def судить(строка):
    """(судимо, истинно): деньги убывают на цену и складываются в трату.

    ЗАКОН ДОМА: число ответа есть число леджера, знак леджера отвечает роду страницы, а
    ВАЛЮТА при всяком числе стои́т в счётной форме ЭТОГО числа — «20 рублей», но «8 рублей»
    и «1 рубль». Страница, где валюта не согласована со своим числом, есть ложь этого дома:
    счётная форма объявлена пакетом, и проверить её можно, не веря странице.
    """
    с = строка.strip()
    судимо = False
    for образец, язык, род in ОБРАЗЦЫ:
        м = образец.match(с)
        if not м:
            continue
        судимо = True
        зн = м.groupdict()
        v = int(зн["v"])
        лед = ЛЕДЖЕР.search(зн["лед"])
        if not лед:
            continue
        a, знак, b, итог = (int(лед.group(1)), лед.group(2),
                            int(лед.group(3)), int(лед.group(4)))
        ждём = a + b if знак == "+" else a - b
        if итог != ждём or итог != v:
            continue
        # ЛЕДЖЕР ГОВОРИТ О ТЕХ ЖЕ ЧИСЛАХ, ЧТО И ИСТОРИЯ, И ЗНАК ОТВЕЧАЕТ РОДУ СТРАНИЦЫ
        числа = [int(з) for и, з in зн.items()
                 if и.rsplit("_", 1)[0] in ("n", "k", "a", "b") and з]
        if sorted(числа) != sorted({a, b}) and set(числа) != {a, b}:
            continue
        if знак != ("−" if род == "купил_остаток" else "+"):
            continue
        # ХВОСТ ГЛАГОЛА — ПО ПОЛУ ЛИЦА, И СУД ЧИТАЕТ ЕГО, А НЕ ВЕРИТ СТРАНИЦЕ (22.09).
        # Прибор рода прошедшего подсадил «Иван купила одно яблоко» тридцать три раза, и суд
        # пропустил все тридцать три: хвост стоял в образце дырой, которую никто не сверял.
        #
        #     СУД, ЧИТАЮЩИЙ ФОРМУ ОБРАЗЦОМ И НЕ СВЕРЯЮЩИЙ ЕЁ С ОБЪЯВЛЕНИЕМ, ЗОВЁТ ИСТИНОЙ
        #     ВСЯКУЮ ФОРМУ, КАКУЮ ОБРАЗЕЦ ПРОПУСКАЕТ.
        #
        # Пол лица объявлен домом действий (`actionpages.ЛИЦА`), хвост — таблицей этого дома;
        # язык, хвоста по полу не имеющий, не сверяется и не платит ничем.
        хвосты = ХВОСТ_ПОЛА.get(язык)
        if хвосты:
            имя = next((з for и, з in зн.items() if и.startswith("X_") and з), None)
            пол = next((л[1] for л in A.ЛИЦА[язык] if л[0] == имя), None)
            если_ждём = хвосты.get(пол)
            if пол is not None and any(з != если_ждём
                                       for и, з in зн.items()
                                       if и.startswith("а_") and з is not None):
                return True, False
        # ВАЛЮТА ПРИ ВСЯКОМ ЧИСЛЕ — В СЧЁТНОЙ ФОРМЕ ЭТОГО ЧИСЛА
        ладно = зн["Рv"] == _валюта(язык, v)
        for и, з in зн.items():
            основа = и.rsplit("_", 1)[0]
            if основа in ("Рn", "Рk", "Рa", "Рb") and з:
                чей = {"Рn": "n", "Рk": "k", "Рa": "a", "Рb": "b"}[основа]
                число = next((int(x) for к, x in зн.items()
                              if к.rsplit("_", 1)[0] == чей and x), None)
                if число is not None and з != _валюта(язык, число):
                    ладно = False
        if ладно:
            return True, True
    return (True, False) if судимо else (False, False)


def _подсадки():
    """Представленное «НЕТ»: итог не сходится, валюта не той счётной формы, чужой знак."""
    вон = []
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            с = next((п for п, (я, ф) in ПОКАЗЫ.items() if я == язык and ф == род), None)
            if not с:
                continue
            вон.append(ЛЕДЖЕР.sub(
                lambda м: f"{м.group(1)} {м.group(2)} {м.group(3)} = {int(м.group(4)) + 1}.",
                с, count=1))
            иная = _валюта(язык, 1)
            много = _валюта(язык, 5)
            if иная != много and много in с:
                вон.append(с.replace(много, иная, 1))
    return tuple(вон)


