# ХВОСТ ГЛАГОЛА ПО ПОЛУ — там, где язык его гнёт; у прочих дыра пуста. Объявлено рядом с
# рамками, ибо это их часть, а не свойство языка вообще.
ХВОСТ_ПОЛА = {"ru": {"f": "а", "m": ""}, "pl": {"f": "a", "m": ""}}
ЧИСЛА = (5, 7, 8, 12, 15, 20, 30, 40)
ВЕЩЕЙ = 3


def _валюта(язык, сколько):
    """Счётная форма валюты для числа — ПРАВИЛОМ ПАКЕТА, а не выбором дома."""
    return P.форма(язык, P.ЯЗЫКИ[язык]["валюта"], сколько)


def _вещь(язык, i, сколько=1, падеж="им"):
    """Вещь в счётной форме; винительный берётся ИЗ ОБЪЯВЛЕНИЯ, а страницы без него нет."""
    таблица = P.ЯЗЫКИ[язык]["вещи"][i % len(P.ЯЗЫКИ[язык]["вещи"])]
    форма = P.форма(язык, таблица, сколько)
    if падеж == "вин" and язык in ВИНИТЕЛЬНЫЙ:
        return ВИНИТЕЛЬНЫЙ[язык].get(форма)     # None — страница НЕ ПИШЕТСЯ
    return форма


def _лицо(язык, i):
    ряд = A.ЛИЦА[язык]
    return ряд[i % len(ряд)]


def _дательный_pl(имя):
    """Польский дательный лица — только для объявленных; иначе страница НЕ ПИШЕТСЯ."""
    ряд = {"Anna": "Annie", "Piotr": "Piotrowi", "Maria": "Marii", "Jan": "Janowi",
           "Ewa": "Ewie", "Adam": "Adamowi", "Zofia": "Zofii", "Marek": "Markowi"}
    return ряд.get(имя)


def страница(язык, род, лицо_i, вещь_i, n, k):
    """Страница кошелька — или None, если объявления не хватает (падежа, формы)."""
    р = РЕЧЬ[язык]
    имя, пол, родит = _лицо(язык, лицо_i)
    а = ХВОСТ_ПОЛА.get(язык, {}).get(пол, "")
    общ = {"X": имя, "Xр": родит, "а": а}
    if язык == "pl":
        дат = _дательный_pl(имя)
        if дат is None:
            return None            # ПАДЕЖ, КОТОРОГО ДОМ НЕ ОБЪЯВИЛ, НЕ УГАДЫВАЕТСЯ
        общ["Xд"] = дат
    if род == "купил_остаток":
        if k >= n:
            return None
        r = n - k
        вин = _вещь(язык, вещь_i, падеж="вин")
        if вин is None:
            return None
        факт = (р["было"].format(**общ, n=n, Рn=_валюта(язык, n)) + " "
                + р["купил"].format(**общ, В=вин, k=k, Рk=_валюта(язык, k)))
        воп = р["воп_остаток"].format(**общ, Рм=_валюта(язык, 5))
        ответ = f"{r} {_валюта(язык, r)}"
        леджер = f"{n} − {k} = {r}."
    else:
        s = n + k
        # ТРАТА «НА {вещь}» ИДЁТ С ПРЕДЛОГОМ, И ПАДЕЖ ЕГО У СЛАВЯН ВИНИТЕЛЬНЫЙ ТОЖЕ
        в1, в2 = _вещь(язык, вещь_i, падеж="вин"), _вещь(язык, вещь_i + 1, падеж="вин")
        if в1 is None or в2 is None:
            return None
        факт = р["потратил"].format(**общ, a=n, Рa=_валюта(язык, n), b=k,
                                    Рb=_валюта(язык, k), В=в1, В2=в2)
        воп = р["воп_потратил"].format(**общ, Рм=_валюта(язык, 5))
        ответ = f"{s} {_валюта(язык, s)}"
        леджер = f"{n} + {k} = {s}."
    return f"{факт} {воп} {ответ}{р['двоеточие']}{леджер}"


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for в in range(ВЕЩЕЙ):
                for i, n in enumerate(ЧИСЛА):
                    k = ЧИСЛА[(i + 3) % len(ЧИСЛА)]
                    с = страница(язык, род, i + в, в, n, k)
                    if с:
                        вон[с] = (язык, род)
    return вон


ПОКАЗЫ = _показы()

ЛЕДЖЕР = re.compile(r"(\d+)\s*([+−])\s*(\d+)\s*=\s*(\d+)\.$")
ХВОСТ = re.compile(r"[?？]\s")


def судить(строка):
    """(судимо, истинно): деньги убывают на цену и складываются в трату.

    ЗАКОН ДОМА: число ответа есть число леджера, знак леджера отвечает роду страницы, а
    ВАЛЮТА при всяком числе стои́т в счётной форме ЭТОГО числа — «20 рублей», но «8 рублей»
    и «1 рубль». Страница, где валюта не согласована со своим числом, есть ложь этого дома:
    счётная форма объявлена пакетом, и проверить её можно, не веря странице.
    """
    с = строка.strip()
    м = ЛЕДЖЕР.search(с)
    вопрос = list(ХВОСТ.finditer(с))
    if not м or not вопрос:
        return False, False
    история, ответ = с[:вопрос[-1].end()], с[вопрос[-1].end():]
    a, зн, b, v = int(м.group(1)), м.group(2), int(м.group(3)), int(м.group(4))
    судимо = False
    for язык in ЯЗЫКИ:
        валюты = {_валюта(язык, x) for x in (1, 2, 5, a, b, v)}
        if not any(вал and вал in с for вал in валюты):
            continue
        судимо = True
        # ЧИСЛО ОТВЕТА СТОИ́Т ПЕРЕД ВАЛЮТОЙ И РАВНО ИТОГУ ЛЕДЖЕРА
        ждём = a + b if зн == "+" else a - b
        if v != ждём:
            continue
        свои = re.match(rf"\s*{v}\s+{re.escape(_валюта(язык, v))}\b", ответ)
        if not свои:
            continue
        # ВАЛЮТА ПРИ КАЖДОМ ЧИСЛЕ ИСТОРИИ — В СЧЁТНОЙ ФОРМЕ ЭТОГО ЧИСЛА
        ладно = True
        for число in re.findall(r"\d+", история):
            вал = _валюта(язык, int(число))
            если = re.search(rf"\b{число}\s+(\S+)", история)
            if если and если.group(1).rstrip(".,?!") in валюты and если.group(1).rstrip(".,?!") != вал:
                ладно = False
                break
        if ладно:
            return True, True
    return (True, False) if судимо else (False, False)


def _подсадки():
    """Представленное «НЕТ»: итог не сходится, валюта не той счётной формы, чужой знак."""
    вон = []
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            с = next((п for п, (я, ф) in ПОКАЗЫ.items() if я == язык and ф == род), None)
            if not с:
                continue
            вон.append(ЛЕДЖЕР.sub(
                lambda м: f"{м.group(1)} {м.group(2)} {м.group(3)} = {int(м.group(4)) + 1}.",
                с, count=1))
            иная = _валюта(язык, 1)
            много = _валюта(язык, 5)
            if иная != много and много in с:
                вон.append(с.replace(много, иная, 1))
    return tuple(вон)


ПОДСАДКИ = _подсадки()


def _самопроверка():
    for показ in ПОКАЗЫ:
        assert судить(показ) == (True, True), показ
    пойманы = sum(1 for с in ПОДСАДКИ if судить(с)[:2] == (True, False))
    for язык in ("ru", "en", "pl"):
        с = next((п for п, (я, ф) in ПОКАЗЫ.items() if я == язык and ф == "купил_остаток"), None)
        if с:
            print(f"  {язык}: {с}")
    с = next((п for п, (я, ф) in ПОКАЗЫ.items() if я == "en" and ф == "потратил_на_два"), None)
    print(f"  en: {с}")
    print(f"  подсадок поймано: {пойманы} из {len(ПОДСАДКИ)}")
    print(f"  дом пишет показов: {len(ПОКАЗЫ)} (языков {len(ЯЗЫКИ)}, родов {len(РОДЫ)})")
    assert пойманы == len(ПОДСАДКИ), f"поймано {пойманы} из {len(ПОДСАДКИ)}"


