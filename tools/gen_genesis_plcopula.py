#!/usr/bin/env python3
"""GENESIS layer: ПОЛЬСКАЯ СВЯЗКА — see tools/plcopulaforms.py for the law.

ПРАВИЛО И ЕГО ЛОВУШКА РАЗДЕЛЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ЛОМАЮТ.

«Связка названа» и «пять есть, а две суть» идут вместе: первое даёт закон по ячейкам, второе
тут же отнимает вывод «связка идёт по числу вещей», который читатель сделал бы из первого сам.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Ячейки те же, что у имени» стои́т особо: это ДОВОД, связывающий два дома — счётной формы
(ловушка 52) и связки, — и соседство разбавило бы его.

«Прошедшее теряет род» и «русский обходится без связки» — третьей группой: обе о ГРАНИЦАХ
закона, одна внутрь языка (род исчезает с ростом счёта), другая наружу (язык без связки её
закона не имеет).
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import plcopulaforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_plcopula.txt"
ГРУППЫ = (("связка названа", "пять есть, а две суть"),
          ("ячейки те же, что у имени",),
          ("прошедшее теряет род", "русский обходится без связки"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
