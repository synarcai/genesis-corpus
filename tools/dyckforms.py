#!/usr/bin/env python3
"""ДОМ СКОБОК — ПОСЛЕДОВАТЕЛЬНОСТЬ, КОТОРУЮ НАДО ЗАКРЫТЬ (14.09, ступень 2, просьба holon-f9).

Вторая ступень лестницы (BBH) держит род `dyck_languages`: дан начатый ряд скобок, и надо
дописать закрывающий хвост. Корпус показывал скобки лишь как ЗНАК внутри формулы; ряда,
который надо ЗАКРЫТЬ, в нём не было ни одного.

    СКОБКА В ФОРМУЛЕ ЕСТЬ ЗНАК ПРИ ЧИСЛАХ; СКОБКА В РЯДУ ЕСТЬ ПАМЯТЬ О ТОМ, ЧТО ОТКРЫТО.
    Это два разных умения, и второму корпус не учил ничем.

ТРИ РОДА ПО ДЕЛУ:

    хвост     «( [ { } ] — чем закрыть? )»: дописать ровно то, что закрывает открытое, и
              в обратном порядке. Ответ ПОКАЗЫВАЕТ СТОПКУ, а не угадывает её;
    ровна_ли  «уравновешен ли ряд» — да с числом пар, нет с числом открытых без пары;
    глубина   «на сколько вложены скобки» — число, какое стопка держала в самом глубоком
              месте. Оно есть ПАМЯТЬ ряда, и без него закрытие есть угадывание.

ПАРЫ СКОБОК ОБЪЯВЛЕНЫ, А НЕ ВЫВЕДЕНЫ: три вида — круглые, квадратные, фигурные, — и всякая
закрывается своей. Ряд строится СТОПКОЙ, и потому всякий показ верен по построению; суд не
верит построению и считает стопку заново.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("хвост", "ровна_ли", "глубина")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "хвост": "дописать закрывающий хвост: стопка показана, а не угадана",
    "ровна_ли": "уравновешен ли ряд — да с числом пар, нет с числом открытых без пары",
    "глубина": "на сколько вложены скобки: память ряда числом",
}

# ПАРЫ ОБЪЯВЛЕНЫ ЗДЕСЬ И НИГДЕ БОЛЬШЕ: закрывающая скобка не выводится из открывающей
# никаким правилом, кроме этой таблицы.
ПАРЫ = (("(", ")"), ("[", "]"), ("{", "}"))
ОТКРЫТЫЕ = tuple(о for о, _з in ПАРЫ)
# ИМЯ ГОВОРИТ О ДЕЛЕ: словарь ведёт ОТ открывающей К закрывающей, и проверка
# «з in ЗАКРЫВАЕТ» есть проверка «открывающая ли».
ЗАКРЫВАЕТ = {о: з for о, з in ПАРЫ}

РЕЧЬ = {
    # ОТВЕТ ЕСТЬ ПРЕДЛОЖЕНИЕ, А НЕ ГОЛЫЙ ХВОСТ (14.09). Первая редакция отвечала одними
    # скобками — «чем закрыть ряд «[ ] {»? }.» — и палата обратила пятьдесят четыре честные
    # страницы в НЕМОТУ: закон покрытия требует, чтобы каждое предложение кто-то читал, и
    # проверяет это ПОРЧЕЙ СЛОВА или ЧИСЛА. В голом хвосте нет ни слова, ни числа — портить
    # нечего, и «читал ли кто» не проверить ничем.
    #
    #     ОТВЕТ ИЗ ОДНИХ ЗНАКОВ НЕЛЬЗЯ ИСПЫТАТЬ ПОРЧЕЙ, А ЗНАЧИТ, НЕЛЬЗЯ И ДОКАЗАТЬ, ЧТО
    #     ЕГО КТО-ТО ЧИТАЕТ. Оттого ответ несёт слово: «закрывают «}»».
    #
    # РЯД ВЗЯТ В КАВЫЧКИ, ЧТОБЫ ЗНАК ВОПРОСА НЕ ПРИЛИП К СКОБКЕ: «ряд [ ] {? }» читается
    # как скобка со знаком вопроса, а корпус знает «?» на месте числа за ДЫРУ. Кавычки
    # отделяют приводимый ряд от речи о нём — тем же законом, каким проза отделяет цитату.
    #
    # ВОПРОСНОЕ СЛОВО СТОИТ ПЕРВЫМ, И ЭТО ЗАКОН ЗАПИСИ, А НЕ ВКУС (14.09). Первая редакция
    # писала «ряд ( { — чем закрыть? } )», и суд письма назвал сорок две честные страницы
    # ложью: вопрос, чья голова не есть объявленное вопросное слово, ложен ПО ЗАПИСИ (96,6 %
    # честных вопросов свода несут его первым). Голова здесь была «ряд».
    #
    #     ВОПРОС УЗНАЁТСЯ ПО ГОЛОВЕ, А НЕ ПО ЗНАКУ В КОНЦЕ. Знак вопроса ставит всякий;
    #     вопросное слово объявлено, и оно одно отличает вопрос от утверждения со знаком.
    "ru": {"хвост": "чем закрыть ряд «{ряд}»? закрывают «{хвост}»",
           "ровна": "ряд {ряд} уравновешен: пар {n}",
           "неровна": "ряд {ряд} не уравновешен: открытых без пары {n}",
           "глубина": "ряд {ряд} вложен на {n}"},
    "en": {"хвост": "how is the row «{ряд}» closed? it is closed by «{хвост}»",
           "ровна": "the row {ряд} is balanced: {n} pairs",
           "неровна": "the row {ряд} is not balanced: {n} open without a pair",
           "глубина": "the row {ряд} nests {n} deep"},
}

# ШИРИНА ВЗЯТА ПО ЧИСЛУ РАЗЛИЧНЫХ РЯДОВ, А НЕ ПО КРУГЛОМУ ЧИСЛУ (14.09): при 24 шагах
# ряды повторялись и мир вышел в 90 страниц — меньше, чем родов на языке по закону массы
# хватает с запасом, но слишком мало, чтобы рынок увидел РАЗНЫЕ стопки. Шагов 96, и длина
# растёт вместе с номером.
ШИРИНА = 96
ДЛИНЫ = (2, 3, 4, 5, 6, 7)


def _ряд(k, длина):
    """Открывающие и закрывающие вперемешку — СТОПКОЙ, а не жребием.

    ПОКАЗ СТРОИТСЯ ТЕМ ЖЕ УСТРОЙСТВОМ, ЧТО ЕГО ЧИТАЕТ: стопка кладёт открытую скобку и
    снимает её закрытой. Ряд, собранный жребием, пришлось бы чинить после проверки.
    """
    вон, стопка = [], []
    for i in range(длина):
        открыть = not стопка or (k + i) % 3 != 2
        if открыть:
            о = ОТКРЫТЫЕ[(k + i * 2) % len(ОТКРЫТЫЕ)]
            стопка.append(о)
            вон.append(о)
        else:
            вон.append(ЗАКРЫВАЕТ[стопка.pop()])
    return " ".join(вон), [ЗАКРЫВАЕТ[о] for о in reversed(стопка)]


def страница(язык, род, k):
    длина = ДЛИНЫ[k % len(ДЛИНЫ)] + (k // len(ДЛИНЫ)) % 6
    ряд, хвост = _ряд(k, длина)
    р = РЕЧЬ[язык]
    if род == "хвост":
        if not хвост:
            return None                      # закрывать нечего — это род «ровна_ли»
        return р["хвост"].format(ряд=ряд, хвост=" ".join(хвост)) + "."
    if род == "ровна_ли":
        if хвост:
            return р["неровна"].format(ряд=ряд, n=len(хвост)) + "."
        return р["ровна"].format(ряд=ряд, n=len(ряд.split()) // 2) + "."
    глубина = _глубина(ряд)
    return р["глубина"].format(ряд=ряд, n=глубина) + "."


def _глубина(ряд):
    глубина = сейчас = 0
    for з in ряд.split():
        if з in ЗАКРЫВАЕТ:
            сейчас += 1
            глубина = max(глубина, сейчас)
        else:
            сейчас -= 1
    return глубина


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for k in range(ШИРИНА):
                с = страница(язык, род, k)
                if с:
                    вон.setdefault(с, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
def _образец(рамка, **дыры):
    куски, поз = [], 0
    for м in re.finditer(r"\{(\w+)\}", рамка):
        куски.append(re.escape(рамка[поз:м.start()]))
        куски.append(дыры.get(м.group(1), r"(.+?)"))
        поз = м.end()
    куски.append(re.escape(рамка[поз:]))
    return "".join(куски)


def _разбор(ряд):
    """(закрывающий хвост или None при порче, число пар, глубина) — СТОПКОЙ, заново."""
    стопка, пар, глубина = [], 0, 0
    for з in ряд.split():
        if з in ЗАКРЫВАЕТ:
            стопка.append(з)
            глубина = max(глубина, len(стопка))
        else:
            if not стопка or ЗАКРЫВАЕТ[стопка[-1]] != з:
                return None, 0, 0            # закрыта не та скобка либо закрывать нечего
            стопка.pop()
            пар += 1
    return [ЗАКРЫВАЕТ[о] for о in reversed(стопка)], пар, глубина


def судить(строка):
    """(судимо, истинно) — стопка пересчитана, и ни одному числу страницы веры нет."""
    for язык in ЯЗЫКИ:
        р = РЕЧЬ[язык]
        for ключ in ("хвост", "ровна", "неровна", "глубина"):
            м = re.fullmatch(_образец(р[ключ], n=r"(\d+)") + r"\.", строка)
            if not м:
                continue
            ряд = м.group(1)
            хвост, пар, глубина = _разбор(ряд)
            if хвост is None:
                return True, False           # ряд сам по себе порчен
            if ключ == "хвост":
                return True, м.group(2).split() == хвост and bool(хвост)
            n = int(м.group(2))
            if ключ == "ровна":
                return True, not хвост and n == пар
            if ключ == "неровна":
                return True, bool(хвост) and n == len(хвост)
            return True, n == глубина
    return False, True


# ПОДСАДКИ ОБЪЯВЛЕНЫ ЗДЕСЬ, И СУД БЕРЁТ ИХ ОТСЮДА ЖЕ (14.09). Дом скобок держал свой
# список, суд — свой, похожий; рамка вопроса в доме переменилась, а в суде осталась
# прежней, и четыре подсадки из семи перестали попадать в рамку — то есть перестали быть
# судимыми вовсе, а прибор доложил, что не поймал их. ДВА ПОХОЖИХ СПИСКА РАСХОДЯТСЯ
# МОЛЧА; один список расходиться не с чем.
# ПРОБА НА ЗАВЕДОМО ЛОЖНОМ: суд обязан ловить чужой хвост, чужое число и чужую скобку.
# ПОДСАДКА ОБЯЗАНА БЫТЬ ЛОЖЬЮ, А НЕ ПОХОЖЕЙ НА НЕЁ (14.09): первая редакция взяла
# «ряд ( [ — чем закрыть? ] ).» за ложь, а «] )» и есть верный хвост — проба ловила
# собственную описку, а не суд.
ПОДСАДКИ = ("чем закрыть ряд «( [»? закрывают «]».",
            "чем закрыть ряд «( [»? закрывают «) ]».",
            "ряд ( ) уравновешен: пар 2.",
            "ряд ( [ не уравновешен: открытых без пары 1.",
            "ряд ( [ ] ) вложен на 1.",
            "how is the row «( [» closed? it is closed by «] } )».",
            "the row ( ) nests 2 deep.")


def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    assert set(РЕЧЬ) == set(ЯЗЫКИ), "речь объявлена не на всех языках"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
