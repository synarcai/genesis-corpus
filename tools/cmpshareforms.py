#!/usr/bin/env python3
"""ДОМ СРАВНЕНИЯ ДОЛЕЙ — какая доля больше, и почему знаменатель ведёт себя НАОБОРОТ.

    СРАВНЕНИЯ ДРОБЕЙ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по мирам показов: «1/3 больше
    1/…», «which is greater: 1/…» — НОЛЬ; «общий знаменатель», «common denominator» — НОЛЬ;
    «вычесть дроби», «дробь больше единицы» — НОЛЬ. Дом сокращения умеет равенство долей, дом
    одной доли — их тождество, а какая из двух БОЛЬШЕ, не говорит никто.

    ЧИСЛО, КОТОРОЕ НЕЛЬЗЯ СРАВНИТЬ, НЕ ЕСТЬ ВЕЛИЧИНА. Доля, о которой известно лишь, чему она
    равна, остаётся именем — и не встаёт в ряд с другими.

ЧЕТЫРЕ РОДА, И ВТОРОЙ ЕСТЬ ГЛАВНАЯ ЛОВУШКА СЧЁТА:

    один знаменатель  3/8 и 5/8: знаменатель один и тот же, и больше та доля, у которой
                      числитель больше: 5 больше 3, и 5/8 больше 3/8.
    один числитель    1/3 и 1/5: числитель один и тот же, а больше та доля, у которой
                      знаменатель МЕНЬШЕ: 3 меньше 5, и 1/3 больше 1/5.   ← НАОБОРОТ
    общий знаменатель 2/3 и 3/5: приведём к общему знаменателю 15: 2 × 5 = 10, и 3 × 3 = 9,
                      и 2/3 есть 10/15, а 3/5 есть 9/15, и 10 больше 9, и 2/3 больше 3/5.
    равные            2/4 и 1/2: приведём к общему знаменателю 4: 1 × 2 = 2, и 1/2 есть 2/4,
                      и 2 равно 2, и доли равны.

ВТОРОЙ РОД ПРОТИВЕН ПРИВЫЧКЕ, И РАДИ НЕГО ДОМ ЗАВЕДЁН. Всюду большее число значит большее — и
только в знаменателе наоборот: чем на большее число делят целое, тем меньше доля. Читатель,
видевший лишь первый род, обобщит его на второй и решит, что 1/5 больше 1/3.

    ПЕРВЫЙ И ВТОРОЙ РОД СУТЬ МИНИМАЛЬНАЯ ПАРА ПО НАПРАВЛЕНИЮ: в одном большее число даёт
    большее, в другом — меньшее, и обе страницы устроены одинаково, чтобы разница читалась
    в одном слове.

ТРЕТИЙ РОД ЕСТЬ ОБЩИЙ СЛУЧАЙ, К КОТОРОМУ СВОДЯТСЯ ПЕРВЫЕ ДВА: приведение к общему знаменателю
работает и там, где числители равны, и там, где знаменатели. Он показан ПОСЛЕ них, а не вместо:
частные правила дешевле, и знать их стои́т, но опираются они на общее.

ЧЕТВЁРТЫЙ ЗАМЫКАЕТ РЯД: доли бывают и равны, и тогда сравнение кончается не «больше», а
«равны» — иначе читатель ждал бы от сравнения непременного перевеса.

ОБЩИЙ ЗНАМЕНАТЕЛЬ БЕРЁТСЯ ПРОИЗВЕДЕНИЕМ ЗНАМЕНАТЕЛЕЙ ИЛИ БОЛЬШИМ ИЗ НИХ, если он делится на
меньший: наименьшее общее кратное — предмет иного дома, и брать его здесь значило бы учить двум
законам на одной странице.

    python3 tools/cmpshareforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("один знаменатель", "один числитель", "общий знаменатель", "равные")

РАМКИ = {
    "ru": {
        "один знаменатель": "{a}/{b} и {c}/{b}: знаменатель один и тот же, и больше та доля, у которой числитель больше: {в1} больше {в2}, и {б1}/{b} больше {б2}/{b}.",
        "один числитель": "{a}/{b} и {a}/{d}: числитель один и тот же, а больше та доля, у которой знаменатель меньше: {м1} меньше {м2}, и {a}/{м1} больше {a}/{м2}.",
        "общий знаменатель": "{a}/{b} и {c}/{d}: приведём к общему знаменателю {об}: {a} × {к1} = {n1}, и {c} × {к2} = {n2}, и {a}/{b} есть {n1}/{об}, а {c}/{d} есть {n2}/{об}, и {в1} больше {в2}, и {б1}/{бз1} больше {б2}/{бз2}.",
        "равные": "{a}/{b} и {c}/{d}: приведём к общему знаменателю {об}: {a} × {к1} = {n1}, и {c} × {к2} = {n2}, и {n1} равно {n2}, и доли равны.",
    },
    "en": {
        "один знаменатель": "{a}/{b} and {c}/{b}: the denominator is the same, and the greater share is the one with the greater numerator: {в1} is greater than {в2}, and {б1}/{b} is greater than {б2}/{b}.",
        "один числитель": "{a}/{b} and {a}/{d}: the numerator is the same, and the greater share is the one with the smaller denominator: {м1} is less than {м2}, and {a}/{м1} is greater than {a}/{м2}.",
        "общий знаменатель": "{a}/{b} and {c}/{d}: bring them to the common denominator {об}: {a} × {к1} = {n1}, and {c} × {к2} = {n2}, and {a}/{b} is {n1}/{об}, and {c}/{d} is {n2}/{об}, and {в1} is greater than {в2}, and {б1}/{бз1} is greater than {б2}/{бз2}.",
        "равные": "{a}/{b} and {c}/{d}: bring them to the common denominator {об}: {a} × {к1} = {n1}, and {c} × {к2} = {n2}, and {n1} equals {n2}, and the shares are equal.",
    },
}


def _общий(b, d):
    """Общий знаменатель: больший из двух, если он делится на меньший, иначе произведение.

    НАИМЕНЬШЕЕ ОБЩЕЕ КРАТНОЕ — ПРЕДМЕТ ИНОГО ДОМА, и брать его здесь значило бы учить двум
    законам на одной странице.
    """
    б, м = max(b, d), min(b, d)
    return б if б % м == 0 else b * d


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        # ОДИН ЗНАМЕНАТЕЛЬ: числители разные.
        # ЧИСЛИТЕЛИ БЕРУТСЯ БЛИЗКИЕ, А НЕ ВСЕ ПАРЫ: разница в один-два показывает правило
        # ровно так же, как разница в семь, а страниц даёт втрое меньше. Первый заход дал 1098
        # страниц — вдвое больше соседних домов при том же законе.
        for b in range(3, 13):
            for a in range(1, b):
                for c in range(a + 1, min(a + 3, b)):
                    вон[рамки["один знаменатель"].format(
                        a=a, b=b, c=c, d=0, в1=c, в2=a, б1=c, б2=a,
                        м1=0, м2=0, об=0, к1=0, к2=0, n1=0, n2=0,
                        бз1=0, бз2=0)] = (язык, "один знаменатель")
        # ОДИН ЧИСЛИТЕЛЬ: знаменатели разные, и ход ОБРАТНЫЙ.
        for b in range(2, 13):
            for d in range(b + 1, 13):
                вон[рамки["один числитель"].format(
                    a=1, b=b, c=0, d=d, м1=b, м2=d, в1=0, в2=0, б1=0, б2=0,
                    об=0, к1=0, к2=0, n1=0, n2=0, бз1=0, бз2=0)] = (
                    язык, "один числитель")
        # ОБЩИЙ ЗНАМЕНАТЕЛЬ и РАВНЫЕ.
        for b in range(2, 10):
            for d in range(2, 10):
                if b == d:
                    continue
                for a in range(1, b):
                    for c in range(1, d):
                        об = _общий(b, d)
                        # ОБЩИЙ ЗНАМЕНАТЕЛЬ НЕ ВЫШЕ ТРИДЦАТИ: приведение должно читаться
                        # глазом, а не проверяться на веру.
                        if об > 30:
                            continue
                        к1, к2 = об // b, об // d
                        n1, n2 = a * к1, c * к2
                        if об > 40:
                            continue
                        if n1 == n2:
                            вон[рамки["равные"].format(
                                a=a, b=b, c=c, d=d, об=об, к1=к1, к2=к2, n1=n1, n2=n2,
                                в1=0, в2=0, б1=0, б2=0, м1=0, м2=0, бз1=0, бз2=0)] = (
                                язык, "равные")
                        elif n1 > n2:
                            вон[рамки["общий знаменатель"].format(
                                a=a, b=b, c=c, d=d, об=об, к1=к1, к2=к2, n1=n1, n2=n2,
                                в1=n1, в2=n2, б1=a, б2=c, бз1=b, бз2=d,
                                м1=0, м2=0)] = (язык, "общий знаменатель")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(\d+) × (\d+) = (\d+)(?!\d)")
# ДРОБНАЯ ЧЕРТА ЕСТЬ ГРАНИЦА ЧИСЛА, И БЕЗ НЕЁ СРАВНЕНИЕ ЧИТАЕТСЯ СКВОЗЬ ДРОБЬ. Образец без
# оглядки на «/» брал из «1/2 больше 2/5» пару «2 больше 2» — знаменатель первой доли и
# числитель второй — и объявлял ложными 62 честные страницы. Сравниваются ЦЕЛЫЕ числа
# (числители, приведённые к общему знаменателю), а сравнение самих долей суд проверяет не
# здесь, а через них.
_БОЛЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:больше|is greater than) (\d+)(?![/\d])")
_МЕНЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:меньше|is less than) (\d+)(?![/\d])")
_РАВНО = re.compile(r"(?<![/\d])(\d+) (?:равно|equals) (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: приведение и все три сравнения своими глазами.
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    for a, b in _МЕНЬШЕ.findall(с):
        if int(a) >= int(b):
            return True, False
    for a, b in _РАВНО.findall(с):
        if int(a) != int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    оз = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "один знаменатель")
    оч = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "один числитель")
    if судить(оч.replace("меньше", "больше", 1))[1] is not False:
        беды.append("подмена направления прошла")
    if судить(оз.replace("больше", "больш", 1))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(оз + " " + оз)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"СРАВНЕНИЕ ДОЛЕЙ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
