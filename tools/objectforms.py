ЯЗЫКИ = tuple(РАМКИ)
ФОРМЫ = ("да", "нет", "да_вы", "нет_вы")

for _a, _b in ПАРЫ:
    assert _a > _b > 0, (_a, _b)
for _яз in РАМКИ:
    assert (_яз in БЕЗ_РАЗЛИЧИЯ_РЕГИСТРА) != (_яз in ВЕЖЛИВЫЕ), _яз
    assert _a - _b != _a - _b + СДВИГ, (_a, _b)


def страница(язык, форма, i):
    a, b = ПАРЫ[i % len(ПАРЫ)]
    c = a - b
    рамки = ВЕЖЛИВЫЕ[язык] if форма.endswith("_вы") else РАМКИ[язык]
    ключ = форма[:-3] if форма.endswith("_вы") else форма
    if ключ == "да":
        return рамки["да"].format(a=a, b=b, c=c)
    x = c + СДВИГ
    return рамки["нет"].format(a=a, b=b, x=x, y=x + b)


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for форма in ФОРМЫ:
            if форма.endswith("_вы") and язык in БЕЗ_РАЗЛИЧИЯ_РЕГИСТРА:
                continue          # язык без различия пишет ОДНУ форму
            for i in range(len(ПАРЫ)):
                вон[страница(язык, форма, i)] = (язык, форма)
    return вон


ПОКАЗЫ = _показы()


def main():
    поймано = 0
    for язык in ЯЗЫКИ:
        print(f"  {язык}: {страница(язык, 'нет', 0)}")
        a, b = ПАРЫ[0]
        c = a - b
        # МУТАНТЫ: согласие с неверным остатком; проверка, дающая не то число;
        # возражение, чья проверка сходится (то есть возражение на верное)
        мутанты = (РАМКИ[язык]["да"].format(a=a, b=b, c=c + 1),
                   РАМКИ[язык]["нет"].format(a=a, b=b, x=c + 1, y=a),
                   РАМКИ[язык]["нет"].format(a=a, b=b, x=c, y=a))
        for м in мутанты:
            поймано += 0 if м in ПОКАЗЫ else 1
    print(f"  мутантов вне показов: {поймано} из {3 * len(ЯЗЫКИ)}")
    print(f"  дом пишет показов: {len(ПОКАЗЫ)} (языков {len(ЯЗЫКИ)}, пар {len(ПАРЫ)}, форм {len(ФОРМЫ)})")
    return 0


