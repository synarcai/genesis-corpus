#!/usr/bin/env python3
"""КОВКА ДОМА ЧИСЛА-ИМЕНИ.

МЕРА И ИМЯ ИДУТ В ОДНОМ ПРОХОДЕ: «2 страницы и ещё 5 страниц» и «страница 2 и страница 5» суть
минимальная пара ПО ДЕЛУ ЧИСЛА — те же два числа, та же вещь, то же сложение, и разница в одном:
стои́т число перед словом или после. Порознь первая учила бы, что складывать можно всё, а вторая —
что нельзя ничего.

ПОРЯДОК И ДВА ДЕЛА ИДУТ СВОЕЙ ГРУППОЙ: первый говорит, что именам МОЖНО (идти по порядку), второй
ставит одно число дважды в одной строке. Без первого закон запретил бы больше, чем надо, и объявил
бы неправым мир прогрессий, который считает по номеру и прав.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import numlabelforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_numlabel.txt"
ГРУППЫ = (("мера", "имя"), ("порядок", "два дела"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
