#!/usr/bin/env python3
"""ДОМ ДЕЛЕНИЯ С ОСТАТКОМ — СУММА СХОДИТСЯ, А ДЕЛЕНИЕ НЕ ДОВЕДЕНО.

    ЗАКОНА ОБ ОСТАТКЕ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 237 мирам показов: «остаток
    меньше делителя», «remainder is less than» — НОЛЬ; «делимое = делитель × частное + остаток»
    — НОЛЬ. При этом само деление с остатком свод пишет: дом дроби и единицы выводит «5 = 4 × 1
    + 1», признаки делимости считают остатки, мир чисел держит сравнения по модулю.

    СВОД СЧИТАЕТ ОСТАТКИ И НЕ ГОВОРИТ, ЧЕМ ОСТАТОК ОТЛИЧАЕТСЯ ОТ ПРОСТО ЧИСЛА.

ТРИНАДЦАТАЯ ЛОВУШКА РЯДА, И ОНА ТОНЬШЕ ПРЕЖНИХ: РАВЕНСТВО СХОДИТСЯ, А ОТВЕТ НЕВЕРЕН.

    17 ÷ 5 = 2 и остаток 7?   5 × 2 = 10, и 10 + 7 = 17 — СУММА ВЕРНА.
    И ВСЁ ЖЕ ЭТО НЕ ОТВЕТ: 7 не меньше 5, и из остатка вышла бы ещё одна пятёрка.

Все прежние ловушки ловились пересчётом: подмени число — и равенство рассыплется. Эта не ловится
пересчётом вовсе. Проверка суммы её ПРОПУСКАЕТ, и потому закон об остатке — не украшение к
делению, а ЕДИНСТВЕННОЕ, что делает ответ однозначным.

    ПРОВЕРКА, КОТОРУЮ ПРОХОДИТ И НЕВЕРНЫЙ ОТВЕТ, НЕ ЕСТЬ ПРОВЕРКА ОТВЕТА.

ЧЕТЫРЕ РОДА:

    с остатком   17 ÷ 5 даёт 3 и остаток 2: 5 × 3 = 15, и 15 + 2 = 17.
    не доведено  17 ÷ 5 не даёт 2 и остаток 7, ибо 7 не меньше 5: 5 × 2 = 10,
                 и 10 + 7 = 17.                                              ← ЛОВУШКА
    ещё одна     из остатка 7 вышла бы ещё одна пятёрка, и остался бы 2: 7 − 5 = 2,
                 и 5 × 3 = 15, и 15 + 2 = 17.                                ← ПРИЧИНА
    нацело       20 ÷ 5 даёт 4 и остаток 0, и это деление нацело: 5 × 4 = 20, и 20 + 0 = 20.

ВТОРОЙ И ТРЕТИЙ СТОЯ́Т НА ОДНИХ ЧИСЛАХ: первый показывает НЕВЕРНЫЙ ответ, прошедший проверку,
второй — ПОЧЕМУ он неверен. Порознь второй был бы придиркой, а третий — правилом без повода.

ЧЕТВЁРТЫЙ РОД ЕСТЬ ГРАНИЦА СНИЗУ: остаток ноль тоже остаток, и деление нацело есть частный
случай, а не иное действие. Без него читатель решил бы, что остаток обязан быть больше нуля.

ФОРМА ДЕРЖИТ ЗАКОН ЧУЖОГО ПРИБОРА: слова до последнего двоеточия, равенства после, — и суд
арифметики читает каждую страницу. ОН ЖЕ ПОДТВЕРДИТ И ЛОВУШКУ: «10 + 7 = 17» истинно, и в этом
вся её соль.

    python3 tools/remforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("с остатком", "не доведено", "ещё одна", "нацело")

# ИМЕНА ДЕЛИТЕЛЕЙ СЛОВОМ нужны третьему роду: «вышла бы ещё одна ПЯТЁРКА». Объявлены таблицей,
# ибо это факт русского языка, а не факт дома.
ДОЛЯМИ = {2: "двойка", 3: "тройка", 4: "четвёрка", 5: "пятёрка", 6: "шестёрка",
          7: "семёрка", 8: "восьмёрка", 9: "девятка", 10: "десятка"}

РАМКИ = {
    "ru": {
        "с остатком": "{a} ÷ {b} даёт {q} и остаток {r}: {b} × {q} = {p}, и {p} + {r} = {a}.",
        "не доведено": "{a} ÷ {b} не даёт {q2} и остаток {r2}, ибо {r2} не меньше {b}: {b} × {q2} = {p2}, и {p2} + {r2} = {a}.",
        "ещё одна": "из остатка {r2} вышла бы ещё одна {имя}, и остался бы {r}: {r2} − {b} = {r}, и {b} × {q} = {p}, и {p} + {r} = {a}.",
        "нацело": "{a} ÷ {b} даёт {q} и остаток 0, и это деление нацело: {b} × {q} = {a}, и {a} + 0 = {a}.",
    },
    "en": {
        "с остатком": "{a} ÷ {b} gives {q} and a remainder of {r}: {b} × {q} = {p}, and {p} + {r} = {a}.",
        "не доведено": "{a} ÷ {b} does not give {q2} and a remainder of {r2}, for {r2} is not less than {b}: {b} × {q2} = {p2}, and {p2} + {r2} = {a}.",
        "ещё одна": "the remainder {r2} would yield one more {b}, and {r} would be left: {r2} − {b} = {r}, and {b} × {q} = {p}, and {p} + {r} = {a}.",
        "нацело": "{a} ÷ {b} gives {q} and a remainder of 0, and that is an exact division: {b} × {q} = {a}, and {a} + 0 = {a}.",
    },
}
ПУСТО = dict(a=0, b=0, q=0, r=0, p=0, q2=0, r2=0, p2=0, имя="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for b in range(2, 11):
            имя = ДОЛЯМИ[b]
            for q in range(2, 13):
                for r in range(1, b):
                    a = b * q + r
                    общ = dict(ПУСТО, a=a, b=b, q=q, r=r, p=b * q,
                               q2=q - 1, r2=r + b, p2=b * (q - 1), имя=имя)
                    if (a + r) % 4 == 0:
                        вон[рамки["с остатком"].format(**общ)] = (язык, "с остатком")
                    if (a + b) % 5 == 0:
                        вон[рамки["не доведено"].format(**общ)] = (язык, "не доведено")
                    if (a * b) % 7 == 0:
                        вон[рамки["ещё одна"].format(**общ)] = (язык, "ещё одна")
            # НАЦЕЛО: остаток ноль, и это тот же закон при r = 0.
            for q in range(2, 25):
                a = b * q
                if (a + q) % 6 == 0:
                    вон[рамки["нацело"].format(
                        **dict(ПУСТО, a=a, b=b, q=q, p=a, имя=имя))] = (язык, "нацело")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_СУММА = re.compile(r"(?<![/\d])(\d+) \+ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (\d+)(?![/\d])")
_ДЕЛЕНИЕ = re.compile(r"(\d+) ÷ (\d+) (?:даёт|gives) (\d+) (?:и остаток|and a remainder of) (\d+)")
_НЕ_ДАЁТ = re.compile(r"(\d+) ÷ (\d+) (?:не даёт|does not give) (\d+) (?:и остаток|and a remainder of) (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    # ЗАКОН ОБ ОСТАТКЕ ПРОВЕРЯЕТСЯ ЗДЕСЬ, И БОЛЬШЕ НИГДЕ: суд арифметики сверит сумму и
    # подтвердит даже НЕДОВЕДЁННОЕ деление — в этом вся ловушка дома.
    for a, b, q, r in _ДЕЛЕНИЕ.findall(с):
        if int(b) * int(q) + int(r) != int(a) or not 0 <= int(r) < int(b):
            return True, False
    for a, b, q, r in _НЕ_ДАЁТ.findall(с):
        # ОТВЕРГНУТЫЙ ОТВЕТ ОБЯЗАН СХОДИТЬСЯ СУММОЙ И ОБЯЗАН НАРУШАТЬ ЗАКОН ОБ ОСТАТКЕ:
        # иначе страница отвергает не то, что читатель мог бы подумать.
        if int(b) * int(q) + int(r) != int(a) or int(r) < int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:90]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    ос = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "с остатком")
    нд = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "не доведено")
    for страница, слово, куда in ((ос, "остаток", "остато"), (нд, "меньше", "меньш")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(ос + " " + ос)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ЛОВУШКА ОБЯЗАНА БЫТЬ ЛОВУШКОЙ: у отвергнутого ответа СУММА СХОДИТСЯ.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "не доведено":
            continue
        a, b, q, r = _НЕ_ДАЁТ.findall(с)[0]
        if int(b) * int(q) + int(r) != int(a) or int(r) < int(b):
            беды.append(f"ловушка не ловит: {с[:70]}")
        break
    # СЛОВА ДО ПОСЛЕДНЕГО ДВОЕТОЧИЯ, РАВЕНСТВА ПОСЛЕ.
    for с in ПОКАЗЫ:
        хвост = с.rsplit(":", 1)[1]
        if re.search(r"[A-Za-zА-Яа-яЁё]{3,}", хвост.replace("and", "").replace("и", "")):
            беды.append(f"СЛОВА ПОСЛЕ ПОСЛЕДНЕГО ДВОЕТОЧИЯ: {с[:70]}")
            break
    print(f"ДЕЛЕНИЕ С ОСТАТКОМ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
