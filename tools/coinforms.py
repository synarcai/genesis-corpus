# КОРЕНЬ ЗАВЕДЁН ВЫШЕ И ЗДЕСЬ НЕ ПОВТОРЯЕТСЯ (16.09): `parent.parent` и `parents[1]` суть
# один путь, и второе присвоение лишь затеняло первое.
_EN = json.loads((КОРЕНЬ / "tools" / "langpacks" / "en.json").read_text(encoding="utf-8"))
_RU = json.loads((КОРЕНЬ / "tools" / "langpacks" / "ru.json").read_text(encoding="utf-8"))
ИМЕНА_EN = _EN["person_names"][:16]
ИМЕНА_RU = [(n.capitalize(), ф["gender"]) for n, ф in list(_RU["person_forms"].items())[:16]]
# (thing, plural, russian) — the things of a price
ВЕЩИ = (("pen", "pens", "ручка"), ("book", "books", "книга"), ("apple", "apples", "яблоко"),
        ("pencil", "pencils", "карандаш"), ("cup", "cups", "чашка"))
ШИРИНА = 10


def ру(слово, n):
    return rugram.форма(слово, n)


def дол(d, c):
    return f"{d}.{c:02d}"


def запись_ru(d, c):
    """Русская десятичная запись денег: «2,05 рубля» — запятая и родительный единственного.

    ДРОБНОЕ ЧИСЛО ПРАВИТ РУССКОЙ ФОРМОЙ ИНАЧЕ, ЧЕМ ЦЕЛОЕ (15.09). «2 рубля» и «5 рублей»
    выбираются остатком, а «2,05 рубля» — самой дробностью: после десятичной дроби русский
    ставит родительный ЕДИНСТВЕННОГО, каким бы ни был остаток. Правило это объявлено в
    пакете русского (`count_agreement`, «fractional»), а не написано здесь: движок счётной
    формы читает объявление и не знает языков.

        ЗАПЯТАЯ ЕСТЬ ЧАСТЬ УРОКА, А НЕ ОФОРМЛЕНИЕ. Русский пишет «2,05», и строка «2.05
        рубля» учила бы английской записи русскими словами.
    """
    return f"{d},{c:02d} {ру('рубль', d + c / 100)}"


def запись(d, c, k):
    """The two writings of a price, alternating: «16.50 dollars» and «$16.50»
    (e9 04.09: the g1 band writes money with the sign)."""
    # ЧИСЛОМ, ПРАВЯЩИМ ФОРМОЙ, ЕСТЬ ВЕЛИЧИНА, А НЕ ЕЁ ЗАПИСЬ (08.09). «дол(d, c)» отдаёт СТРОКУ
    # («16.50»), и закон счёта на ней спотыкается; величина же есть d + c/100, и она отвечает
    # верно на обоих концах: «1.00 dollar» при ровной единице, «1.50 dollars» при дроби.
    return (f"${дол(d, c)}" if k % 2 else
            f"{дол(d, c)} {by_count(d + c / 100, 'dollars')}")


def мост(шаг):
    """The decimal writing and the cents, with the ledger between them."""
    вон = []
    for i in range(ШИРИНА):
        d = 3 + (шаг * 7 + i * 5) % 40
        # cents ≥ 10: «.05» would read as the quantity «05» beside the answer's «5»
        c = 5 * ((шаг * 3 + i * 7) % 18 + 2)          # 10..95
        всего = d * 100 + c
        леджер = f"{d} × 100 = {d * 100}, {d * 100} + {c} = {всего}"
        if i % 2 == 0:
            вон.append(f"{запись(d, c, шаг + i // 2)} is {всего} {by_count(всего, 'cents')}: {леджер}.")
            вон.append(f"{d} {ру('рубль', d)} {c} {ру('копейка', c)} — это {всего} {ру('копейка', всего)}: {леджер}.")
        else:
            вон.append(f"how many cents is {запись(d, c, шаг + i // 2)}? {леджер} {by_count(всего, 'cents')}.")
            вон.append(f"сколько копеек составляют {d} {ру('рубль', d)} {c} {ру('копейка', c)}? {леджер} {ру('копейка', всего)}.")
        # the way back: cents to dollars and cents (a statement; the question
        # would have to open with the cents and answer with the dollars)
        # the way back in both writings: «16 dollars 50 cents» and «$16.50»
        обратно = f"${дол(d, c)}" if i % 2 else f"{d} {by_count(d, 'dollars')} {c} {by_count(c, 'cents')}"
        вон.append(f"{всего} {by_count(всего, 'cents')} is {обратно}: {d} × 100 = {d * 100}, {всего} − {d * 100} = {c}.")
    return вон


def цены(шаг):
    вон = []
    for i in range(ШИРИНА):
        т1, т2 = ВЕЩИ[(шаг + i) % len(ВЕЩИ)], ВЕЩИ[(шаг + i + 2) % len(ВЕЩИ)]
        p1 = 5 * (3 + (шаг * 11 + i * 7) % 60)
        p2 = 5 * (2 + (шаг * 5 + i * 13) % 50)
        k = 2 + (шаг + i) % 4
        if i % 2 == 0:
            вон.append(f"{_арт(т1[0])} costs {p1} {by_count(p1, 'cents')} and {_арт(т2[0])} costs {p2} {by_count(p2, 'cents')}; together they cost {p1 + p2} {by_count(p1 + p2, 'cents')}: {p1} + {p2} = {p1 + p2}.")
            вон.append(f"{т1[2]} стоит {p1} {ру('копейка', p1)}, а {т2[2]} стоит {p2} {ру('копейка', p2)}; вместе они стоят {p1 + p2} {ру('копейка', p1 + p2)}: {p1} + {p2} = {p1 + p2}.")
            вон.append(f"{_арт(т1[0])} costs {p1} {by_count(p1, 'cents')}. how much do {k} {т1[1]} cost? {p1} × {k} = {p1 * k} {by_count(p1 * k, 'cents')}.")
        else:
            вон.append(f"{_арт(т1[0])} costs {p1} {by_count(p1, 'cents')} and {_арт(т2[0])} costs {p2} {by_count(p2, 'cents')}. how much do they cost together? {p1} + {p2} = {p1 + p2} {by_count(p1 + p2, 'cents')}.")
            вон.append(f"{т1[2]} стоит {p1} {ру('копейка', p1)}, а {т2[2]} стоит {p2} {ру('копейка', p2)}. сколько они стоят вместе? {p1} + {p2} = {p1 + p2} {ру('копейка', p1 + p2)}.")
            вон.append(f"{_арт(т1[0])} costs {p1} {by_count(p1, 'cents')}; {k} {т1[1]} cost {p1 * k} {by_count(p1 * k, 'cents')}: {p1} × {k} = {p1 * k}.")
    return вон


def сдача(шаг):
    вон = []
    for i in range(ШИРИНА):
        имя = ИМЕНА_EN[(шаг * 3 + i) % len(ИМЕНА_EN)]
        имя_ру, род = ИМЕНА_RU[(шаг * 3 + i) % len(ИМЕНА_RU)]
        т = ВЕЩИ[(шаг + i) % len(ВЕЩИ)]
        p = 5 * (5 + (шаг * 7 + i * 11) % 150)
        paid = ((p // 100) + 1 + (шаг + i) % 3) * 100
        сдача_ = paid - p
        заплатил = "заплатила" if род == "f" else "заплатил"
        получил = "получила" if род == "f" else "получил"
        if i % 2 == 0:
            вон.append(f"{имя} paid {paid} {by_count(paid, 'cents')} for {_арт(т[0])} that costs {p} {by_count(p, 'cents')}; {имя} got {сдача_} {by_count(сдача_, 'cents')} change: {paid} − {p} = {сдача_}.")
            вон.append(f"{имя_ру} {заплатил} {paid} {ру('копейка', paid)}, а {т[2]} стоила {p} {ру('копейка', p)}; сдача — {сдача_} {ру('копейка', сдача_)}: {paid} − {p} = {сдача_}.")
        else:
            вон.append(f"{имя} paid {paid} {by_count(paid, 'cents')} for {_арт(т[0])} that costs {p} {by_count(p, 'cents')}. how much change did {имя} get? {paid} − {p} = {сдача_} {by_count(сдача_, 'cents')}.")
            вон.append(f"{имя_ру} {заплатил} {paid} {ру('копейка', paid)}, а {т[2]} стоила {p} {ру('копейка', p)}. сколько сдачи {получил} {имя_ру}? {paid} − {p} = {сдача_} {ру('копейка', сдача_)}.")
    return вон


def суммы(шаг):
    """The decimal sum with the cents beside it — the axis of the decimal writing."""
    вон = []
    for i in range(ШИРИНА):
        a, ac = 2 + (шаг * 5 + i * 3) % 30, 5 * ((шаг + i * 3) % 19 + 1)
        b, bc = 1 + (шаг * 3 + i * 7) % 20, 5 * ((шаг * 7 + i) % 19 + 1)
        A, B = a * 100 + ac, b * 100 + bc
        S = A + B
        s, sc = divmod(S, 100)
        if i % 2 == 0:
            вон.append(f"{запись(a, ac, шаг + i // 2)} + {запись(b, bc, шаг + i // 2)} = {запись(s, sc, шаг + i // 2)}: {A} + {B} = {S} {by_count(S, 'cents')}.")
            вон.append(f"{запись_ru(a, ac)} + {запись_ru(b, bc)} = {запись_ru(s, sc)}: "
                       f"{A} + {B} = {S} {ру('копейка', S)}.")
        else:
            k = шаг + i // 2
            вон.append(f"how much is {запись(a, ac, k)} + {запись(b, bc, k)}? {запись(a, ac, k)} + {запись(b, bc, k)} = {запись(s, sc, k)}: {A} + {B} = {S} {by_count(S, 'cents')}.")
            вон.append(f"сколько будет {запись_ru(a, ac)} + {запись_ru(b, bc)}? "
                       f"{запись_ru(a, ac)} + {запись_ru(b, bc)} = {запись_ru(s, sc)}: "
                       f"{A} + {B} = {S} {ру('копейка', S)}.")
    return вон

ГРУППЫ = (мост, цены, сдача, суммы)


def группы(шаг):
    """[[страница]] — ровно те группы и в том порядке, какими кузница кормит `emit_grouped`."""
    return [сделать(шаг) for сделать in ГРУППЫ]


def перебор(шаг):
    """[(страница, род)] — те же группы, но каждая под своим именем."""
    вон = []
    for род, группа in zip(РОДЫ, группы(шаг)):
        for с in группа:
            вон.append((с, род))
    return вон


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            вон.setdefault(с, (bilang.азбукой(с), род))
    return вон


ПОКАЗЫ = _показы()

