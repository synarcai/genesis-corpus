# ЯЗЫКОВОЙ ДОЛГ ДОМА НАЗВАН УТРОМ И ВЫПЛАЧЕН ВЕЧЕРОМ (15.09), и стоил он не рамки, а ПРАВИЛА
# ЯЗЫКА. Род «суммы» — сложение десятичной записи денег — звучал только по-английски, и
# русская сторона его была не переводом, а вторым уроком: у рубля запись идёт запятой, а
# счётная форма при дробном числе стои́т в родительном ЕДИНСТВЕННОГО («2,05 рубля», а не
