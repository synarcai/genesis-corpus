#
#     ПЕРЕВОД РАМКИ И ВТОРОЙ УРОК — РАЗНЫЕ РАБОТЫ, И ВТОРАЯ ДОРОЖЕ ПЕРВОЙ. Дом, написавший
#     «2,05 рублей», учил бы неверному.
#
# Правило дробного счёта вписано В ПАКЕТ РУССКОГО, а не в этот дом: движок счётной формы
# спрашивал «каков остаток» и никогда «цело ли число», отчего всякая дробь молча падала в
# последнюю ячейку. Ныне пакет объявляет `{"fractional": true, "form": "few"}`, и движок
# читает объявление, по-прежнему не зная языков.
