"""ДОМ МОНЕТЫ — счёт в центах и копейках, целыми.

Мир денег считает в МЕЛКОЙ единице и целыми числами: доля рубля есть копейка, а не
«0,5 рубля». Оттого здесь нет дробей вовсе, и сдача выходит ровной.

`tools/moneyforms.py` уже занят ИНЫМ домом — домом ЗАПИСИ денег (десятичная
запятая в девяти языках). Имя спрошено у двора ПРЕЖДЕ записи, как велит сегодняшний закон,
и взято свободное: дом зовётся по МОНЕТЕ, ибо считает мелкой единицей.

4 родов объявлены не здесь: их назвала СВОЯ ЖЕ КУЗНИЦА кортежем `ГРУППЫ`.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

ЧИТАТЕЛЬ ПЯТОГО РОДА НАЗВАН ПОИМЁННО: суд этого мира ВВОЗИТ дом модулем и берёт `ВЕЩИ`, `ИМЕНА_EN`.
Самопроверка сверяет, что все эти имена у дома есть, — связь рвётся МОЛЧА при ввозе суда.
"""
