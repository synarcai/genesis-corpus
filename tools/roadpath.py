# СУД СТРОИТ СЕТЬ ЗАНОВО ПО ЗАПИСИ и ходит по ней сам: считает кратчайшие пути, считает круг
# достижимых мест. Ни сети, ни пути он у дома не берёт. Место вне объявленных делает запись
# не нашей, и суд о ней молчит.
def _образцы(язык):
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык]["дороги"] + РАМКИ[язык][род])
        for дыра, узор in (("сеть", "[^.]+"), ("середина", "[^:.?]+"), ("путь", "[^.]+"),
                           ("круг", "[^.]+"), ("а", "[^ .,?]+"), ("б", "[^ .,?]+")):
            дыра_о = re.escape("{" + дыра + "}")
            первый = True
            while дыра_о in о:
                о = о.replace(дыра_о, f"(?P<{дыра}>{узор})" if первый else f"(?P={дыра})", 1)
                первый = False
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def _сеть(язык, кусок):
    места = МЕСТА[язык]
    рамка = re.escape(РАМКИ[язык]["дорога"]).replace(re.escape("{а}"), "(?P<а>[^ ,.—]+)") \
        .replace(re.escape("{б}"), "(?P<б>[^ ,.—]+)")
    вон = []
    for пара in кусок.split(", "):
        м = re.fullmatch(рамка, пара.strip())
        if not м or м.group("а") not in места or м.group("б") not in места:
            return None
        вон.append((места.index(м.group("а")), места.index(м.group("б"))))
    return вон or None


def судить(строка):
    """(судимо, истинно) — сеть построена заново, и путь найден судом."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        места = МЕСТА[язык]
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            сеть = _сеть(язык, м.group("сеть"))
            д = м.groupdict()
            if сеть is None or д["а"] not in места or д["б"] not in места:
                continue
            а, б = места.index(д["а"]), места.index(д["б"])
            если = страница(язык, сеть, а, б)
            # СТРАНИЦА СОБРАНА ЗАНОВО И СВЕРЕНА ЦЕЛИКОМ: и род, и путь, и круг. Отказ без
            # круга и путь не кратчайший равно суть ложь.
            return True, если is not None and если[0] == строка and если[1] == род
    return False, True


