def _соседи(сеть):
    вон = collections.defaultdict(set)
    for а, б in сеть:
        вон[а].add(б)
        вон[б].add(а)
    return вон


def пути(сеть, откуда, куда):
    """Все кратчайшие пути — список списков мест. Пусто, если пути нет."""
    соседи = _соседи(сеть)
    волна, найдено, длина = [[откуда]], [], None
    виден = {откуда}
    while волна:
        если_длина = len(волна[0])
        if длина is not None and если_длина > длина:
            break
        новая, пришли = [], set()
        for путь in волна:
            for сосед in sorted(соседи[путь[-1]]):
                if сосед in путь:
                    continue
                шаг = путь + [сосед]
                if сосед == куда:
                    найдено.append(шаг)
                    длина = len(шаг)
                elif сосед not in виден:
                    новая.append(шаг)
                    пришли.add(сосед)
        виден |= пришли
        волна = новая
    return найдено


def круг(сеть, откуда):
    """Все места, куда из начала дойти можно, — кроме самого начала."""
    соседи, виден, волна = _соседи(сеть), {откуда}, [откуда]
    while волна:
        место = волна.pop()
        for сосед in соседи[место]:
            if сосед not in виден:
                виден.add(сосед)
                волна.append(сосед)
    return sorted(виден - {откуда})


def страница(язык, сеть, а, б):
    места, рамки = МЕСТА[язык], РАМКИ[язык]
    голова = рамки["дороги"].format(
        сеть=", ".join(рамки["дорога"].format(а=места[x], б=места[y]) for x, y in сеть))
    найдено = пути(сеть, а, б)
    if not найдено:
        могу = круг(сеть, а)
        if not могу:
            return None            # из места, откуда никуда нельзя, отказ ничему не учит
        хвост = рамки["никак"].format(а=места[а], б=места[б],
                                      круг=" и ".join(места[м] for м in могу))
        return голова + хвост, "никак"
    if len(найдено) > 1:
        return None                # два кратчайших пути — не вопрос
    путь = найдено[0]
    if len(путь) == 2:
        return голова + рамки["прямо"].format(а=места[а], б=места[б]), "прямо"
    середина = " и ".join(места[м] for м in путь[1:-1])
    дорогами = ", ".join(рамки["дорога"].format(а=места[x], б=места[y])
                         for x, y in zip(путь, путь[1:]))
    return голова + рамки["через"].format(а=места[а], б=места[б], середина=середина,
                                          путь=дорогами), "через"


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for сеть in СЕТИ:
            for а, б in itertools.permutations(range(len(МЕСТА[язык])), 2):
                вышло = страница(язык, сеть, а, б)
                if вышло:
                    вон.setdefault(вышло[0], (язык, вышло[1]))
    return вон


ПОКАЗЫ = _показы()


