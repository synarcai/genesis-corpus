def _доля(p, b):
    return b // 100 * p if b % 100 == 0 else b * p // 100


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for p, b in ДОЛИ:
            d = _доля(p, b)
            вон[рамки["процент от основания"].format(p=p, b=b, d=d)] = (
                язык, "процент от основания")
            вон[рамки["сколько процентов"].format(p=p, b=b, d=d)] = (язык, "сколько процентов")
        for (p1, b1), (p2, b2) in ПЕРЕВЁРНУТЫЕ:
            d1, d2 = _доля(p1, b1), _доля(p2, b2)
            общ = dict(p1=p1, b1=b1, d1=d1, p2=p2, b2=b2, d2=d2,
                       ч1=_ч(d1, язык), ч2=_ч(d2, язык), с=d1 + d2, pp=p1 + p2)
            for род in ("больший процент меньшее число", "люди а не доли", "сложить нельзя",
                        "спрошенное"):
                вон[рамки[род].format(**общ)] = (язык, род)
            иное = ИНОЕ_ОСНОВАНИЕ[p1]
            вон[рамки["основание названо"].format(
                p=p1, b=b1, d=d1, b2=иное,
                d2=_доля(p1, иное))] = (язык, "основание названо")
        for (p1, b1), (p2, _b2) in ОБЩЕЕ_ОСНОВАНИЕ:
            вон[рамки["то же основание"].format(
                p1=p1, b1=b1, d1=_доля(p1, b1), p2=p2,
                d2=_доля(p2, b1))] = (язык, "то же основание")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка И
    ЕСЛИ ВСЯКАЯ ЗАПИСЬ В НЕЙ ПЕРЕСЧИТЫВАЕТСЯ РАЗБОРОМ (`arithread`).

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать;
    ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    return True, arithread.записи_верны(с)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    import re
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ВСЕ ДОЛИ ЦЕЛЫЕ, И ОСНОВАНИЯ ОБЪЯВЛЕНЫ ТЕМ, ЧЕМ НАЗВАНЫ.
    for p, b in ДОЛИ:
        if b * p % 100:
            беды.append(f"доля не целая: {p} % от {b}")
        if not 0 < p < 100:
            беды.append(f"процент вне ста: {p}")
    for (p1, b1), (p2, b2) in ПЕРЕВЁРНУТЫЕ:
        if not p1 > p2:
            беды.append(f"первый процент не больше второго: {(p1, p2)}")
        if not _доля(p1, b1) < _доля(p2, b2):
            беды.append(f"переворота нет: {p1}% от {b1} против {p2}% от {b2}")
        if b1 == b2:
            беды.append(f"основания равны, а пара лежит в перевёрнутых: {(b1, b2)}")
        for p, b in ((p1, b1), (p2, b2), (p1, ИНОЕ_ОСНОВАНИЕ[p1])):
            if b * p % 100:
                беды.append(f"доля не целая в паре: {p} % от {b}")
        if ИНОЕ_ОСНОВАНИЕ[p1] == b1:
            беды.append(f"иное основание совпало со своим: {p1} % от {b1}")
    for (p1, b1), (p2, b2) in ОБЩЕЕ_ОСНОВАНИЕ:
        if b1 != b2:
            беды.append(f"основания разны, а пара лежит в общих: {(b1, b2)}")
        if not p1 > p2 or not _доля(p1, b1) > _доля(p2, b1):
            беды.append(f"при общем основании порядок не сохранён: {(p1, p2, b1)}")
    # ОБЕ СТОРОНЫ ЛОВУШКИ ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ.
    for язык in ЯЗЫКИ:
        if not (по_роду.get((язык, "больший процент меньшее число"))
                and по_роду.get((язык, "то же основание"))):
            беды.append(f"показана лишь одна сторона ловушки [{язык}]")
    # СЧЁТ ДОЛИ ПРОВЕРЯЕТСЯ НА ЗАВЕДОМО ИЗВЕСТНОМ, А НЕ ТОЛЬКО НА СВОИХ СТРАНИЦАХ.
    for p, b, ждём in ((10, 500, 50), (50, 20, 10), (25, 80, 20), (5, 600, 30), (40, 45, 18)):
        if _доля(p, b) != ждём:
            беды.append(f"доля {p} % от {b}: {_доля(p, b)} вместо {ждём}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ, ГДЕ ЕСТЬ ЗАПИСЬ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    осн = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "процент от основания")
    порча = осн.replace("ОСНОВАНИЯ", "ОСНОВАНИ", 1)
    if порча == осн:
        беды.append("порча не состоялась: нет слова «ОСНОВАНИЯ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(осн + " " + осн)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ОСНОВАНИЕ ПРОЦЕНТА: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
