#!/usr/bin/env python3
"""ДОМ ОСНОВАНИЯ ПРОЦЕНТА — процент без основания не есть число.

    50 % БОЛЬШЕ 10 %, НО 50 % ОТ 20 ЕСТЬ 10, А 10 % ОТ 500 ЕСТЬ 50. Больший процент дал
    меньшее число, и это не редкий случай, а правило всякий раз, когда основания разны.

ПОВОД, ЗАМЕРЕННЫЙ 12.09 ПО ВСЕМУ СВОДУ В 39 МБ: «база процента» — НОЛЬ вхождений, «от чего
процент» — ноль, «процент от разного» — ноль. Свод берёт процент от числа тысячами страниц и
знает процентную разницу (дом `pctdiff`) — но ни разу не спрашивает, ОТ ЧЕГО взят процент, и
ни разу не сравнивает два процента от РАЗНЫХ оснований.

ВОСЕМЬ РОДОВ, И ДВА ИЗ НИХ СУТЬ ОДНА ЛОВУШКА, ПОКАЗАННАЯ ОБЕИМИ СТОРОНАМИ:

    ПРОЦЕНТ ОТ ОСНОВАНИЯ   «10 % от 500 есть 50: 500 ÷ 100 × 10 = 50».
    БОЛЬШИЙ ПРОЦЕНТ, МЕНЬШЕЕ ЧИСЛО — сравнение процентов лжёт при разных основаниях.
    ТО ЖЕ ОСНОВАНИЕ        сравнение процентов верно, и верно ЛИШЬ ПОТОМУ, что основание одно.
    ЛЮДИ, А НЕ ДОЛИ        «50 % из 20 — это 10 человек, 10 % из 500 — это 50».
    ОСНОВАНИЕ НАЗВАНО      «вырос на 30 %» без основания не есть утверждение.
    СЛОЖИТЬ НЕЛЬЗЯ         два процента от разных оснований не складываются в процент.
    СКОЛЬКО ПРОЦЕНТОВ      обратная дорога: «10 из 500 есть 2 %».
    СПРОШЕННОЕ             вопрос, чей ответ есть само основание.

ПОЧЕМУ ОБЕ СТОРОНЫ ОБЯЗАТЕЛЬНЫ. Учащийся, встретивший лишь «процент лжёт», перестанет верить
процентам вовсе — а при одном основании они сравнимы в точности. Встретивший лишь «50 больше
10» будет сравнивать проценты всегда и ошибётся всякий раз, когда основания разошлись.

    ПРОЦЕНТ ЕСТЬ ОТНОШЕНИЕ, А НЕ ЧИСЛО; ДВА ОТНОШЕНИЯ СРАВНИМЫ ЛИШЬ ПРИ ОБЩЕМ ОСНОВАНИИ, И
    ПОТОМУ ПРОЦЕНТ, СКАЗАННЫЙ БЕЗ НЕГО, НЕ ЛОЖЕН — ОН ПРОСТО НИЧЕГО НЕ ГОВОРИТ.

СОРОК ПЯТАЯ ЛОВУШКА РЯДА — сравнение процентов при разных основаниях. Номер выведен по записи
свода (час ковки), а не назначен, и стои́т ЗДЕСЬ, а не только в объявлении мира:

    ДОМ, НЕ ЗНАЮЩИЙ СВОЕГО МЕСТА В РЯДУ, УЗНАЁТ О НЁМ ИЗ ЧУЖОГО ОБЪЯВЛЕНИЯ;
    А ЧИТАЮЩИЙ ДОМ МАНИФЕСТА НЕ ЧИТАЕТ.

ВСЕ ДОЛИ ЦЕЛЫЕ, И ЭТО НЕ УДОБСТВО, А ЗАКОН СВОДА: корпус, сказавший «12,5 человека», научил
бы округлению как истине. Основания подобраны так, что процент от них делится нацело, и
самопроверка дома этого требует.

ПУТЬ СЧЁТА ПИШЕТСЯ УМНОЖЕНИЕМ ВПЕРЁД: «20 × 50 ÷ 100 = 10», а не «20 ÷ 100 × 50». Значение
у них одно, но первый путь идёт ЦЕЛЫМИ ЧИСЛАМИ, а второй выходит из них на первом же шаге —
20 ÷ 100 не есть целое. Общий разбор свода (`arithread`) берёт деление только нацело и
второй путь ОТВЕРГ, назвав честную страницу ложной.

    ЗАПИСЬ, ЧЕСТНАЯ ПО ЗНАЧЕНИЮ, МОЖЕТ БЫТЬ НЕЧЕСТНОЙ ПО ПУТИ: ТОТ ЖЕ ОТВЕТ, ДОБЫТЫЙ ЧЕРЕЗ
    ДРОБЬ, УЧИТ ДРОБИ ТАМ, ГДЕ ЕЁ МОЖНО БЫЛО НЕ ТРОГАТЬ.

    python3 tools/pctbaseforms.py     # самопроверка с мутантами
"""
