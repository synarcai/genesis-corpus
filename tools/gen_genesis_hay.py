#!/usr/bin/env python3
"""GENESIS layer: ИСПАНСКОЕ HAY — see tools/hayforms.py for the law.

ПРАВИЛО И ЕГО ЛОЖНЫЕ СЛЕДСТВИЯ РАЗДЕЛЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ЛОМАЮТ.

«hay не меняется» и «прошедшее тоже не меняется» идут вместе: первое даёт закон, второе тут же
отнимает вывод «в прошедшем-то поменяется», который читатель сделал бы из первого сам.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Сосед меняется» стои́т ОСОБО: это сердце дома — ловушка на ПЕРЕНОСЕ, и соседство с правилом
разбавило бы её. Ловит она того, кто уже выучил польскую связку или английское «there is/are».

«Это не лень языка» и «число несёт имя» — третьей группой: обе о том, ЧТО ИМЕННО неизменно, —
одна показывает, что испанский согласует прочие глаголы, другая — кто несёт число вместо
глагола.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import hayforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_hay.txt"
ГРУППЫ = (("hay не меняется", "прошедшее тоже не меняется"),
          ("сосед меняется",),
          ("это не лень языка", "число несёт имя"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
