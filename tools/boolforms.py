#!/usr/bin/env python3
"""ДОМ БУЛЕВЫХ ВЫРАЖЕНИЙ — значение выражения из истины, лжи и трёх связок, где решает
ПОРЯДОК шагов (14.09, ступень 2, просьба holon-f9).

Вторая ступень лестницы (BBH) держит род `boolean_expressions`: дано выражение из истины,
лжи и трёх связок, и надо назвать его значение. Корпус знал связки лишь ТАБЛИЦЕЙ («T ∧ T =
T» в мире логики множеств) и не показывал ВЫРАЖЕНИЯ, где связок несколько и порядок их
решает всё.

    ТАБЛИЦА СВЯЗКИ УЧИТ ОДНОМУ ШАГУ; ВЫРАЖЕНИЕ УЧИТ ПОРЯДКУ ШАГОВ. Второе не выводится из
    первого ничем: «не истина и ложь» есть ложь, а «не ( истина и ложь )» — истина, и
    таблица об этом молчит.

ЧЕТЫРЕ РОДА ПО ДЕЛУ:

    отрицание   «не истина — это ложь»: одна связка над одним значением;
    и_или       «истина и ложь — это ложь»: одна связка над двумя;
    порядок     «не истина и ложь — это ложь»: ДВЕ связки без скобок, и старшинство решает;
    скобки      «не ( истина и ложь ) — это истина»: скобки МЕНЯЮТ ответ, и обе стороны
                показаны рядом — иначе читатель выучит, что скобки не значат ничего.

СТАРШИНСТВО ОБЪЯВЛЕНО, А НЕ ПОДРАЗУМЕВАЕТСЯ: «не» сильнее «и», «и» сильнее «или». Дом
строит выражения ДЕРЕВОМ и печатает их по этому старшинству; суд разбирает запись заново и
считает значение сам, не веря ни дереву, ни печати.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("одна_связка", "порядок", "скобки")
РОД_В_ПОКАЗЕ = 1

# ЗАКОН МАССЫ СВЁЛ «ОТРИЦАНИЕ» И «И_ИЛИ» В ОДИН РОД (14.09): «не истина» и «не ложь» — все
# две страницы, какие отрицание над голым значением вообще даёт, и родом они были бы вдвое
# ниже закона. Одна связка над значениями есть ОДНО дело; сколько у неё мест — один или два
# — есть свойство связки, а не иное умение.
ЗАЧЕМ_РОДА = {
    "одна_связка": "«не истина», «истина и ложь», «истина или ложь»: одна связка, и ответ "
                   "берётся прямо из неё",
    "порядок": "две связки без скобок: старшинство решает, и ответ это показывает",
    "скобки": "скобки МЕНЯЮТ ответ, и обе стороны показаны рядом",
}

СЛОВА = {
    "ru": {"истина": "истина", "ложь": "ложь", "не": "не", "и": "и", "или": "или",
           "рамка": "{в} — это {з}", "обе": "{в1} — это {з1}, а {в2} — это {з2}"},
    "en": {"истина": "True", "ложь": "False", "не": "not", "и": "and", "или": "or",
           "рамка": "{в} is {з}", "обе": "{в1} is {з1}, and {в2} is {з2}"},
}

def _знач(язык, b):
    return СЛОВА[язык]["истина" if b else "ложь"]


def _печать(язык, узел, сверху=0):
    """Запись узла со скобками ТОЛЬКО там, где их требует старшинство."""
    с = СЛОВА[язык]
    if isinstance(узел, bool):
        return _знач(язык, узел)
    вид = узел[0]
    if вид == "не":
        внутри = _печать(язык, узел[1], 3)
        запись = f"{с['не']} {внутри}"
        сила = 3
    elif вид == "и":
        запись = f"{_печать(язык, узел[1], 2)} {с['и']} {_печать(язык, узел[2], 2)}"
        сила = 2
    else:
        запись = f"{_печать(язык, узел[1], 1)} {с['или']} {_печать(язык, узел[2], 1)}"
        сила = 1
    return f"( {запись} )" if сила < сверху else запись


def _значение(узел):
    if isinstance(узел, bool):
        return узел
    if узел[0] == "не":
        return not _значение(узел[1])
    if узел[0] == "и":
        return _значение(узел[1]) and _значение(узел[2])
    return _значение(узел[1]) or _значение(узел[2])


# ОЧЕРТАНИЯ ОБЪЯВЛЕНЫ ПОИМЁННО, А НЕ ВЫВЕДЕНЫ ИЗ ОСТАТКА ОТ ДЕЛЕНИЯ (14.09). Пока
# очертание выбиралось через `k % 3`, набор значений и очертание тянули ОДИН И ТОТ ЖЕ
# номер, и половина строк таблицы истинности не была кована ни разу. Теперь очертание —
# строка объявления, а значения перебираются ВСЕ: дом обязан показать связку на каждом
# наборе, иначе читатель выучит её на половине.
#
# Каждое очертание есть (число мест, дерево от значений); для «скобок» дерево возвращает
# ПАРУ — одно и то же выражение без скобок и со скобками.
ОЧЕРТАНИЯ = {
    "одна_связка": (
        (1, lambda a, b, c: ("не", a)),
        (2, lambda a, b, c: ("и", a, b)),
        (2, lambda a, b, c: ("или", a, b)),
    ),
    "порядок": (
        (2, lambda a, b, c: ("и", ("не", a), b)),
        (2, lambda a, b, c: ("или", ("не", a), b)),
        (2, lambda a, b, c: ("и", a, ("не", b))),
        (2, lambda a, b, c: ("или", a, ("не", b))),
        (2, lambda a, b, c: ("и", ("не", a), ("не", b))),
        (3, lambda a, b, c: ("или", ("и", a, b), c)),
        (3, lambda a, b, c: ("или", a, ("и", b, c))),
        (3, lambda a, b, c: ("или", ("и", ("не", a), b), c)),
    ),
    # СКОБКА, МЕНЯЮЩАЯ ОТВЕТ ТОЛЬКО ПРИ «НЕ», НАУЧИЛА БЫ, ЧТО ПРИ «И» И «ИЛИ» ОНА ПРАЗДНА.
    # И ОБЕ СТОРОНЫ ОБЯЗАНЫ БЫТЬ ОДНОЙ ЗАПИСЬЮ: сними скобки — останется ТО ЖЕ слово за тем
    # же словом. Пара «не a и не b» / «не ( a и b )» есть закон де Моргана, а не скобка:
    # слова разошлись, и показ учил бы другому делу под чужим именем.
    "скобки": (
        (2, lambda a, b, c: (("и", ("не", a), b), ("не", ("и", a, b)))),
        (2, lambda a, b, c: (("или", ("не", a), b), ("не", ("или", a, b)))),
        (3, lambda a, b, c: (("или", ("и", a, b), c), ("и", a, ("или", b, c)))),
        (3, lambda a, b, c: (("или", a, ("и", b, c)), ("и", ("или", a, b), c))),
        (3, lambda a, b, c: (("или", ("и", a, ("не", b)), c),
                             ("и", a, ("не", ("или", b, c))))),
        (3, lambda a, b, c: (("или", ("и", ("не", a), b), c),
                             ("и", ("не", a), ("или", b, c)))),
    ),
}


def наборы(мест):
    """ВСЕ наборы значений на заданном числе мест — а не какие достал остаток."""
    места = [(False, True)] * мест + [(False,)] * (3 - мест)
    return [(x, y, z) for x in места[0] for y in места[1] for z in места[2]]


def страница(язык, род, очертание, набор):
    с = СЛОВА[язык]
    if род != "скобки":
        узел = очертание(*набор)
        return с["рамка"].format(в=_печать(язык, узел), з=_знач(язык, _значение(узел))) + "."
    без, со = очертание(*набор)
    з1, з2 = _значение(без), _значение(со)
    if з1 == з2:
        return None            # скобки ничего не изменили — показывать нечего
    return с["обе"].format(в1=_печать(язык, без), з1=_знач(язык, з1),
                           в2=_печать(язык, со), з2=_знач(язык, з2)) + "."


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for мест, очертание in ОЧЕРТАНИЯ[род]:
                for набор in наборы(мест):
                    п = страница(язык, род, очертание, набор)
                    if п:
                        вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД РАЗБИРАЕТ ЗАПИСЬ ЗАНОВО: он не знает дерева дома и строит своё по записи, а потом
# считает значение. Порча скобки, связки или значения меняет его ответ.
def _разобрать(язык, слова):
    """(значение, остаток) — спуск по старшинству: или ← и ← не ← скобка/значение."""
    с = СЛОВА[язык]

    def значение(сл):
        if not сл:
            raise ValueError("пусто")
        if сл[0] == "(":
            v, ост = дизъюнкция(сл[1:])
            if not ост or ост[0] != ")":
                raise ValueError("скобка не закрыта")
            return v, ост[1:]
        if сл[0] == с["не"]:
            v, ост = значение(сл[1:])
            return (not v), ост
        if сл[0] == с["истина"]:
            return True, сл[1:]
        if сл[0] == с["ложь"]:
            return False, сл[1:]
        raise ValueError(f"чужое слово: {сл[0]}")

    def конъюнкция(сл):
        v, сл = значение(сл)
        while сл and сл[0] == с["и"]:
            п, сл = значение(сл[1:])
            v = v and п
        return v, сл

    def дизъюнкция(сл):
        v, сл = конъюнкция(сл)
        while сл and сл[0] == с["или"]:
            п, сл = конъюнкция(сл[1:])
            v = v or п
        return v, сл

    return дизъюнкция(слова)


def _считать(язык, запись):
    слова = запись.split()
    v, ост = _разобрать(язык, слова)
    if ост:
        raise ValueError(f"хвост не разобран: {ост}")
    return v


# ЧУЖАЯ ЗАПИСЬ НЕ ЕСТЬ ЛОЖНАЯ ЗАПИСЬ (14.09, ворота мира многошагового счёта). Дыра `{в}`
# стояла как `.+?`, и английская рамка «{в} is {з}» хватала ЛЮБУЮ строку, кончавшуюся на
# «is <что-то>», — «… the answer is 120.» из чужого мира разбиралась и объявлялась ЛОЖЬЮ,
# ибо «answer» не булево слово. Суд, не умеющий читать запись, обязан МОЛЧАТЬ о ней, а не
# звать её ложной: подсудность определяется словарём, и потому дыра собрана из объявленных
# слов дома, а не из «чего угодно».
_СЛОВАРЬ = {я: "(?:" + "|".join(re.escape(с[к]) for к in
                                ("истина", "ложь", "не", "и", "или")) + r"|\(|\))"
            for я, с in СЛОВА.items()}
_ВЫРАЖЕНИЕ = {я: f"{сл}(?: {сл})*" for я, сл in _СЛОВАРЬ.items()}
_ЗНАЧЕНИЕ = {я: "(?:" + "|".join(re.escape(с[к]) for к in ("истина", "ложь")) + ")"
             for я, с in СЛОВА.items()}


def судить(строка):
    """(судимо, истинно) — выражение разобрано и посчитано заново."""
    for язык in ЯЗЫКИ:
        с = СЛОВА[язык]
        for ключ, дыры in (("обе", ("в1", "з1", "в2", "з2")), ("рамка", ("в", "з"))):
            рамка = с[ключ]
            образец = re.escape(рамка)
            for д in дыры:
                узор = _ЗНАЧЕНИЕ[язык] if д.startswith("з") else _ВЫРАЖЕНИЕ[язык]
                образец = образец.replace(re.escape("{" + д + "}"), f"(?P<{д}>{узор})")
            м = re.fullmatch(образец + r"\.", строка)
            if not м:
                continue
            try:
                if ключ == "рамка":
                    return True, _знач(язык, _считать(язык, м.group("в"))) == м.group("з")
                ладно = (_знач(язык, _считать(язык, м.group("в1"))) == м.group("з1")
                         and _знач(язык, _считать(язык, м.group("в2"))) == м.group("з2"))
                # ОБЕ СТОРОНЫ ОБЯЗАНЫ РАЗОЙТИСЬ: показ о скобках, где ответы равны, ничему
                # не учит, и дом такого не строит — а суд такого не пропускает.
                return True, ладно and м.group("з1") != м.group("з2")
            except ValueError:
                return True, False
    return False, True


# ПОДСАДКИ ОБЪЯВЛЕНЫ ЗДЕСЬ, И СУД БЕРЁТ ИХ ОТСЮДА ЖЕ (14.09). Дом скобок держал свой
# список, суд — свой, похожий; рамка вопроса в доме переменилась, а в суде осталась
# прежней, и четыре подсадки из семи перестали попадать в рамку — то есть перестали быть
# судимыми вовсе, а прибор доложил, что не поймал их. ДВА ПОХОЖИХ СПИСКА РАСХОДЯТСЯ
# МОЛЧА; один список расходиться не с чем.
ПОДСАДКИ = ("не истина — это истина.",
            "истина и ложь — это истина.",
            "не истина и ложь — это истина.",
            "не ( истина и ложь ) — это ложь.",
            "не истина и ложь — это ложь, а не ( истина и ложь ) — это ложь.",
            "not True and False is True.")


def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    # СНИМИ СКОБКИ — ОСТАНЕТСЯ ТА ЖЕ ЗАПИСЬ: иначе стороны разошлись не скобкой.
    for язык in ЯЗЫКИ:
        for мест, очертание in ОЧЕРТАНИЯ["скобки"]:
            for набор in наборы(мест):
                без, со = очертание(*набор)
                голые = [[с for с in _печать(язык, у).split() if с not in "()"]
                         for у in (без, со)]
                assert голые[0] == голые[1], f"скобки развели слова: {голые}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
