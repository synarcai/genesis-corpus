#!/usr/bin/env python3
"""ДОМ ОБХОДА ПРОСТОТЫ — свод показывал, ПОЧЕМУ число составное, и лишь ГОВОРИЛ, что оно простое.

    СОСТАВНОСТЬ ДОКАЗЫВАЕТСЯ ОДНИМ СВИДЕТЕЛЕМ, ПРОСТОТА — ОБХОДОМ ВСЕХ.
    ПОКАЗАВ ПЕРВОЕ И СКАЗАВ ВТОРОЕ, СВОД УЧИТ ЛЕГЧАЙШЕЙ ПОЛОВИНЕ.

ПОВОД. Замер 12.09 по третьему десятку свойств: «простота числа» названа в восемнадцати
мирах — и ни в одном не показана. Свод пишет «13 is prime.», «19 is prime.», а рядом,
на той же странице, честно показывает составность: «the next prime after 17 is 19:
18 = 2 × 9, 19 is prime». Составное разложено, простое — объявлено.

Дом восьми языков (`primeforms`) идёт дальше и УТВЕРЖДАЕТ делителей: «17 ist eine
Primzahl; ihre Teiler sind 1 und 17». Но и это утверждение, а не показ: откуда читателю
знать, что их только два? Ему остаётся верить.

    УТВЕРЖДЕНИЕ О ВСЕХ ЕСТЬ ПОКАЗ ЛИШЬ ТОГДА, КОГДА ВСЕ ПЕРЕЧИСЛЕНЫ.

ЧТО ЗДЕСЬ ПОКАЗАНО ВПЕРВЫЕ. Обход целиком, пробой за пробой: «17 ПРОСТОЕ, и вот весь
обход — пробы: 2 — нет, 3 — нет, 4 — нет; дальше пробовать нечего, ибо 5 × 5 = 25 больше
17». И зеркально — обход, оборванный находкой: «91 НЕ ПРОСТОЕ… 7 — ДА: 91 = 7 × 13;
дальше идти незачем, ибо одного делителя довольно».

ГРАНИЦА ОБХОДА ПОКАЗАНА, А НЕ ЗАДАНА. Почему довольно дойти до корня — отдельный род, и
он показывает довод, а не правило: «91 = 7 × 13, меньший множитель 7, и 7 × 7 = 49 не
больше 91. Будь ОБА множителя больше 9, произведение было бы не меньше 10 × 10 = 100, а
100 больше 91 — потому такой пары нет».

    ПРАВИЛО «ДО КОРНЯ» БЕЗ ЕГО ДОВОДА ЕСТЬ ОБЫЧАЙ, КОТОРОМУ ПОДЧИНЯЮТСЯ, А НЕ ЗНАНИЕ.

И РАЗНИЦА ТРУДА НАЗВАНА ПРЯМО: род «труд не равен» ставит рядом один свидетель и полный
обход — не как замечание, а как предмет страницы. Это первый урок свода о том, что ДВА
ОТВЕТА ОБ ОДНОМ ПРЕДМЕТЕ МОГУТ СТОИТЬ РАЗНОГО ТРУДА, и он же — зерно всего, что после
зовут сложностью.

ПРОБЫ ИДУТ ПОДРЯД, А НЕ ПО ПРОСТЫМ, И ЭТО НАРОЧНО: обход по 2, 3, 4, 5 честен и понятен
тому, кто ещё не знает, что делитель составного числа сам имеет простого делителя. Умный
обход — по одним простым — есть следствие, и учить ему прежде довода значило бы снова
дать обычай вместо знания.

    python3 tools/primewalkforms.py     # самопроверка с мутантами
"""
