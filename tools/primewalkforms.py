СЛОВА = {
    "ru": dict(нет="нет", да_ответ="да", нет_ответ="нет"),
    "en": dict(нет="no", да_ответ="yes", нет_ответ="no"),
}

ОТВЕТЫ = {
    "ru": dict(прост="да: обход {пробы}; ни одна проба не удалась, а дальше пробовать "
                     "нечего, ибо {k1} × {k1} = {kk} больше {n}.",
               сост="нет: {n} = {d} × {m}, и одного свидетеля довольно."),
    "en": dict(прост="yes: the walk is {пробы}; not one try succeeded, and there is "
                     "nothing further to try, for {k1} × {k1} = {kk} is greater than {n}.",
               сост="no: {n} = {d} × {m}, and one witness is enough."),
}

ПУСТО = dict(n=0, n1=0, k=0, k1=0, kk=0, d=0, m=0, dd=0, c=0, cd=0, cm=0, проб=0, все=0,
             пробы="", ответ="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, слова, ответы = РАМКИ[язык], СЛОВА[язык], ОТВЕТЫ[язык]
        for n in ПРОСТЫЕ:
            k = math.isqrt(n)
            общ = dict(ПУСТО, n=n, n1=n - 1, k=k, k1=k + 1, kk=(k + 1) ** 2, проб=k - 1,
                       все=n - 2,
                       пробы=_пробы(n, k, слова["нет"]))
            вон[рамки["обход исчерпан"].format(**общ)] = (язык, "обход исчерпан")
            вон[рамки["счёт проб"].format(**общ)] = (язык, "счёт проб")
            вон[рамки["спрошенное"].format(**dict(общ, ответ=ответы["прост"].format(**общ)))] = (язык, "спрошенное")
        for n in СОСТАВНЫЕ:
            d, k = делитель(n), math.isqrt(n)
            общ = dict(ПУСТО, n=n, d=d, m=n // d, dd=d * d, k=k, k1=k + 1,
                       kk=(k + 1) ** 2, пробы=_пробы(n, d - 1, слова["нет"]))
            вон[рамки["обход оборван"].format(**общ)] = (язык, "обход оборван")
            вон[рамки["довольно корня"].format(**общ)] = (язык, "довольно корня")
            вон[рамки["спрошенное"].format(**dict(общ, ответ=ответы["сост"].format(**общ)))] = (язык, "спрошенное")
        # ТРУД НЕ РАВЕН: простое и составное СТАВЯТСЯ РЯДОМ на одной странице, ибо
        # предмет её есть именно РАЗНИЦА, а разницу порознь не показать.
        for n, c in zip(ПРОСТЫЕ, СОСТАВНЫЕ):
            k, cd = math.isqrt(n), делитель(c)
            общ = dict(ПУСТО, n=n, c=c, cd=cd, cm=c // cd, k=k, проб=k - 1,
                       пробы=_пробы(n, k, слова["нет"]))
            вон[рамки["труд не равен"].format(**общ)] = (язык, "труд не равен")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ПРОБА ЧИТАЕТСЯ КАК ПРОБА, А НЕ КАК ЧИСЛО РЯДОМ С ТИРЕ: «7 — нет» на странице числа 91
# есть ЛОЖЬ, ибо 91 делится на 7, и суд обязан её увидеть.
_ПРОБА_НЕТ = re.compile(r"(?<![\d/])(\d+) — (?:нет|no)(?![\d/])")
_ПРОБА_ДА = re.compile(r"(?<![\d/])(\d+) — (?:ДА|YES)(?![\d/])")
_ПРОИЗВЕДЕНИЕ = re.compile(r"(?<![\d/])(\d+) = (\d+) × (\d+)(?![\d/])")
_КВАДРАТ = re.compile(r"(?<![\d/])(\d+) × (\d+) = (\d+)(?![\d/])")
_БОЛЬШЕ = re.compile(r"(?<![\d/])(\d+) больше (\d+)(?![\d/])"
                     r"|(?<![\d/])(\d+) is greater than (\d+)(?![\d/])")
_НЕ_БОЛЬШЕ = re.compile(r"(?<![\d/])(\d+) не больше (\d+)(?![\d/])"
                        r"|(?<![\d/])(\d+) is not greater than (\d+)(?![\d/])")
_ГОЛОВА = re.compile(r"^(\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _КВАДРАТ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for n, d, m in _ПРОИЗВЕДЕНИЕ.findall(с):
        if int(d) * int(m) != int(n):
            return True, False
    for ру1, ру2, ан1, ан2 in _БОЛЬШЕ.findall(с):
        if int(ру1 or ан1) <= int(ру2 or ан2):
            return True, False
    for ру1, ру2, ан1, ан2 in _НЕ_БОЛЬШЕ.findall(с):
        if int(ру1 or ан1) > int(ру2 or ан2):
            return True, False
    # ОБХОД ПЕРЕСЧИТЫВАЕТСЯ ЦЕЛИКОМ, И ПРЕДМЕТ ЕГО ВЗЯТ ПО ЗАКОНУ ДОМА:
    #
    #     ЧИСЛО, КОТОРОЕ ОБХОДЯТ, НАЗВАНО НЕПОСРЕДСТВЕННО ПЕРЕД ПЕРВОЙ ПРОБОЙ.
    #
    # Взять его из ГОЛОВЫ строки было первой правкой — и самопроверка её отвергла:
    # на странице «труд не равен» в голове стои́т СОСТАВНОЕ («21 не простое»), а
    # обходят на ней ПРОСТОЕ, и суд объявил тридцать две честные страницы ложными.
    # Оттого рамка того рода ныне называет предмет прямо: «вот они для 11 — 2 — нет».
    предмет = None
    первая = _ПРОБА_НЕТ.search(с) or _ПРОБА_ДА.search(с)
    if первая:
        слева = re.findall(r"(?<![\d/])(\d+)(?![\d/])", с[:первая.start()])
        предмет = int(слева[-1]) if слева else None
    if предмет is not None and предмет > 1:
        for d in _ПРОБА_НЕТ.findall(с):
            if предмет % int(d) == 0:
                return True, False
        for d in _ПРОБА_ДА.findall(с):
            if предмет % int(d):
                return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ОБЪЯВЛЕННЫЕ ЧИСЛА ОБЯЗАНЫ БЫТЬ ТЕМ, ЧЕМ НАЗВАНЫ.
    for n in ПРОСТЫЕ:
        if not простое(n):
            беды.append(f"в ПРОСТЫХ стои́т составное: {n}")
    for n in СОСТАВНЫЕ:
        if простое(n):
            беды.append(f"в СОСТАВНЫХ стои́т простое: {n}")
        elif делитель(n) == 2:
            беды.append(f"составное с делителем 2 оборвёт обход на первой пробе: {n}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        числа = list(re.finditer(r"\d+", страница))
        m = числа[-1] if числа else None
        порча = (страница[:m.start()] + str(int(m.group()) + 1) + страница[m.end():]
                 if m else страница)
        if порча == страница:
            беды.append(f"порча не состоялась в роде {род}")
        elif судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО ПРОБЕ: «нет» вместо «ДА» на найденном делителе обязан быть пойман.
    оборван = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "обход оборван")
    порча = оборван.replace(" — ДА", " — нет", 1)
    if порча == оборван:
        беды.append("порча не состоялась: нет пробы «— ДА»")
    elif судить(порча)[1] is not False:
        беды.append(f"проба «нет» на истинном делителе прошла: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    исчерпан = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "обход исчерпан")
    порча = исчерпан.replace("обход", "обхо", 1)
    if порча == исчерпан:
        беды.append("порча не состоялась: нет слова «обход»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(исчерпан + " " + исчерпан)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ГРАНИЦА ОБХОДА ОБЯЗАНА БЫТЬ ВЕРНОЙ: последняя проба есть ⌊√n⌋, и следующая уже лишняя.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "обход исчерпан" or я != "ru":
            continue
        n = int(_ГОЛОВА.match(с).group(1))
        пробы = [int(d) for d in _ПРОБА_НЕТ.findall(с)]
        if пробы != list(range(2, math.isqrt(n) + 1)):
            беды.append(f"обход не до корня: {n} → {пробы}")
            break
    print(f"ОБХОД ПРОСТОТЫ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
