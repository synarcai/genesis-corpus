"""ДОМ ОДНОШАГОВОГО УРАВНЕНИЯ — НЕИЗВЕСТНОЕ НАХОДИТСЯ ОБРАТНЫМ ДЕЙСТВИЕМ.

    ЧТОБЫ УЗНАТЬ СЛАГАЕМОЕ, ВЫЧИТАЮТ; ЧТОБЫ УЗНАТЬ МНОЖИТЕЛЬ, ДЕЛЯТ.
    Обратное действие есть не приём решения, а СМЫСЛ РАВЕНСТВА: строка
    «x + 4 = 18» уже содержит «x = 18 − 4», и решение лишь произносит это.

ПОВОД — ДОЛГ, А НЕ ЗАМЫСЕЛ. Прибор `orphan_world` держал рубеж «один мир нельзя
собрать заново»: `algebra_units`, 261 строка, писанная рукой в начале свода, до
того как свод научился ковать.

    МИР, КОТОРЫЙ НЕЛЬЗЯ СОБРАТЬ ЗАНОВО, ЕСТЬ МИР, КОТОРЫЙ НЕЛЬЗЯ ПОЧИНИТЬ.

Замер 12.09 разложил его РОВНО НА ОДИННАДЦАТЬ РАМОК и нашёл, что 115 строк из 261
суть копии (различных всего 146). Затем каждая рамка была спрошена у всего свода
показов: показывает ли её кто-нибудь ещё?

    ПОКАЗАНЫ ДРУГИМИ        перевод единиц ru/en (conversions, money_langs, physics),
                            чтение знака ru/en (school_biling_v2c, logic_sets, md_latex)
    НИГДЕ БОЛЬШЕ            уравнение голое, уравнение словом ru, уравнение словом en,
                            уравнение с умножением, сумма долей до единицы,
                            доля с именем, десятичная запись доли

    ДОМ СТРОИТСЯ НА ТОМ, ЧТО МИР НЕСЁТ ОДИН, А НЕ НА ВСЁМ, ЧТО В НЁМ НАПИСАНО:
    рамка, показанная соседом, есть его дело, и повторять её здесь значило бы
    ковать двойника — чем уже однажды кончился дом переноса.

ПЯТЬ РОДОВ, И ВСЕ ПЯТЬ — ОБ ОДНОМ ЗАКОНЕ:

    голое            x + 4 = 18. x = 18 − 4. x = 14.
    словом ru        задача: три плюс x равно шесть. решение: x = 6 − 3 = 3. ответ: три.
    словом en        task: x plus 7 equals 10. solution: x = 10 − 7 = 3. answer: 3.
    умножением       5 × x = 20. x = 20 ÷ 5. x = 4.
    доля до единицы  4/10 + 6/10 = 1.

ПЯТЫЙ РОД СТОИ́Т ЗДЕСЬ ПО ПРАВУ, А НЕ ПО СОСЕДСТВУ: «4/10 + 6/10 = 1» есть то же
одношаговое уравнение, у которого неизвестное УЖЕ НАЙДЕНО и названо единицей —
дополнение доли до целого. Читатель, решивший «x + 4 = 18», решает и «4/10 + x = 1».

ЧИСЛИТЕЛЬНЫЕ БЕРУТСЯ У ДОМА ЧИСЛИТЕЛЬНЫХ (`numerals.назвать`), а не объявляются здесь.

    СВОЙ СПИСОК СЛОВ ДЛЯ ЧИСЕЛ БЫЛ БЫ ТРЕТЬЕЙ ПРАВДОЙ О НИХ — тем же законом, каким
    дом формульной речи отказался от своей дюжины.

РАВЕНСТВО СТОИ́Т ПОСЛЕДНИМ В КАЖДОМ ЗВЕНЕ, ЧТОБЫ ЕГО ПРОЧЁЛ ОБЩИЙ СУД: дом, чьи
равенства читает только он сам, охраняет их в одиночку.

    python3 tools/onestepforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import numerals  # noqa: E402

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("голое", "словом", "умножением", "доля до единицы", "спрошенное", "единственность")

РАМКИ = {
    "ru": {
        "голое": "x + {a} = {s}. x = {s} − {a}. x = {x}.",
        "словом": "задача: {a_сл} плюс x равно {s_сл}. решение: x = {s} − {a} = {x}. "
                  "ответ: {x_сл}.",
        "умножением": "{k} × x = {p}. x = {p} ÷ {k}. x = {x}.",
        "доля до единицы": "{a}/{n} + {b}/{n} = 1.",
        "спрошенное": "чему равен x, если x + {a} = {s}? x = {x}, ибо {s} − {a} = {x}.",
        "единственность": "у уравнения x + {a} = {s} ровно один корень: при x = {м} вышло бы "
                          "{м} + {a} = {мs} — меньше {s}; при x = {б} вышло бы {б} + {a} = {бs} "
                          "— больше {s}; и только x = {x} даёт {x} + {a} = {s}.",
    },
    "en": {
        "голое": "x + {a} = {s}. x = {s} − {a}. x = {x}.",
        "словом": "task: x plus {a_сл} equals {s_сл}. solution: x = {s} − {a} = {x}. "
                  "answer: {x_сл}.",
        "умножением": "{k} × x = {p}. x = {p} ÷ {k}. x = {x}.",
        "доля до единицы": "{a}/{n} + {b}/{n} = 1.",
        "спрошенное": "what is x if x + {a} = {s}? x = {x}, for {s} − {a} = {x}.",
        "единственность": "the equation x + {a} = {s} has exactly one root: at x = {м} it would "
                          "give {м} + {a} = {мs} — less than {s}; at x = {б} it would give "
                          "{б} + {a} = {бs} — greater than {s}; and only x = {x} gives "
                          "{x} + {a} = {s}.",
    },
}
# ГОЛОЕ И УМНОЖЕНИЕ ПИШУТСЯ ОДИНАКОВО НА ОБОИХ ЯЗЫКАХ — в них нет ни одного слова.
# Потому они кладутся ОДИН РАЗ и числятся русскими: показ, положенный дважды под
# двумя языками, был бы одной страницей, объявленной двумя родами.
БЕЗ_СЛОВ = ("голое", "умножением", "доля до единицы")

ПУСТО = dict(a=0, b=0, n=0, s=0, x=0, k=0, p=0, м=0, б=0, мs=0, бs=0,
             a_сл="", s_сл="", x_сл="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        табл = numerals.таблица(язык)
        # ГОЛОЕ: слагаемое неизвестно, и сумма его открывает.
        if язык == "ru":
            for x in range(1, 20):
                for a in range(1, 16):
                    s = x + a
                    if s > 20 or (x + a) % 3:
                        continue
                    вон[рамки["голое"].format(**dict(ПУСТО, a=a, s=s, x=x))] = (язык, "голое")
            # УМНОЖЕНИЕМ: множитель неизвестен, и произведение его открывает.
            for k in range(2, 10):
                for x in range(2, 10):
                    p = k * x
                    if p > 60 or (k + x) % 2:
                        continue
                    вон[рамки["умножением"].format(
                        **dict(ПУСТО, k=k, p=p, x=x))] = (язык, "умножением")
            # ДОЛЯ ДО ЕДИНИЦЫ: то же уравнение, чьё неизвестное уже названо целым.
            for n in (2, 4, 5, 10):
                for a in range(1, n):
                    вон[рамки["доля до единицы"].format(
                        **dict(ПУСТО, a=a, b=n - a, n=n))] = (язык, "доля до единицы")
        # ЕДИНСТВЕННОСТЬ: корень не просто НАЙДЕН, но показан ЕДИНСТВЕННЫМ — двумя
        # соседями, промахивающимися каждый в свою сторону.
        #
        #     ЕДИНСТВЕННОСТЬ ПОКАЗЫВАЕТСЯ ДВУМЯ СОСЕДЯМИ: числом меньшим и числом
        #     бо́льшим, и оба промахиваются в СВОЮ сторону.
        #
        # Свод называл «единственность» одиннадцать раз своею прозой и показывал её лишь
        # о медиане — не о корне. Слово, названное и не показанное, есть обещание.
        for x in range(2, 15):
            for a in range(1, 12):
                s = x + a
                if s > 20 or (x + a) % 4:
                    continue
                вон[рамки["единственность"].format(**dict(
                    ПУСТО, a=a, s=s, x=x, м=x - 1, б=x + 1,
                    мs=x - 1 + a, бs=x + 1 + a))] = (язык, "единственность")
        # СПРОШЕННОЕ: то же равенство, поставленное ВОПРОСОМ. Мир, который только
        # утверждает, учит читателя узнавать ответ, но не искать его.
        #
        #     МИР БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ ПОКАЗЫВАЕТ ОТВЕТ, НЕ ПОКАЗЫВАЯ ЗАДАЧИ.
        for x in range(1, 16):
            for a in range(1, 13):
                s = x + a
                if s > 20 or (x * a + s) % 5:
                    continue
                вон[рамки["спрошенное"].format(
                    **dict(ПУСТО, a=a, s=s, x=x))] = (язык, "спрошенное")
        # СЛОВОМ: то же равенство, сказанное речью, — и числа произносит дом числительных.
        for x in range(1, 13):
            for a in range(1, 13):
                s = x + a
                if s > 20 or (x * a) % 4:
                    continue
                a_сл, s_сл, x_сл = (numerals.назвать(v, табл) for v in (a, s, x))
                if not (a_сл and s_сл and x_сл):
                    continue
                вон[рамки["словом"].format(**dict(
                    ПУСТО, a=a, s=s, x=x, a_сл=a_сл, s_сл=s_сл, x_сл=x_сл))] = (язык, "словом")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА = re.compile(r"(?<![/\d])x \+ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"x = (\d+) − (\d+)(?: = (\d+))?(?![/\d])")
_ПРОИЗВЕДЕНИЕ = re.compile(r"(?<![/\d])(\d+) × x = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"x = (\d+) ÷ (\d+)(?![/\d])")
# КОРЕНЬ КОНЧАЕТСЯ ТОЧКОЙ ИЛИ ЗАПЯТОЙ: у родов утверждения он последнее слово строки,
# у рода вопроса за ним идёт «ибо» с доказательством. Признак, знавший одну точку,
# отверг все вопросные страницы разом — и сказал об этом самопроверкой в тот же миг.
# КОРЕНЬ ОПОЗНАЁТСЯ ТЕМ, ЧТО ЗА НИМ СТОИ́Т, А НЕ ТЕМ, ЧТО ОН «x = N».
#
#     «x = N» ЕСТЬ И ШАГ РЕШЕНИЯ, И ЕГО ИТОГ, И ПРОМАХ СОСЕДА — три разные вещи одним
#     начертанием, и различает их ТОЛЬКО СОСЕДСТВО.
#
# Корень кончает предложение («x = 14.»), стои́т перед «ибо» («x = 1, ибо…») или несёт
# слово «даёт» («только x = 2 даёт…»). А «x = 13 − 12 = 1» есть ШАГ, и «при x = 1 вышло
# бы» — ПРОМАХ; ни то, ни другое корнем не зовётся. Две редакции подряд сломались здесь:
# первая требовала точки и не видела корня перед словом, вторая брала всякое «x = N» и
# принимала за корень первый шаг решения.
_КОРЕНЬ = re.compile(r"x = (\d+)(?=[.,]|\s+(?:даёт|gives))")

# АРИФМЕТИКА СВИДЕТЕЛЕЙ ПРОВЕРЯЕТСЯ ТОЖЕ. Род единственности несёт три числовые
# суммы — две промахивающиеся и одну верную, — и ни одна из них не начинается с «x».
# Прежний судья их не читал вовсе.
#
#     СТРАНИЦА, ДОКАЗЫВАЮЩАЯ СВИДЕТЕЛЯМИ, ДОЛЖНА БЫТЬ СУДИМА И ПО СВИДЕТЕЛЯМ:
#     иначе доказательство её есть украшение, а не довод.
_ЧИСЛОВАЯ_СУММА = re.compile(r"(?<![\w/])(\d+) \+ (\d+) = (\d+)(?![\d/])")
_ДОЛИ = re.compile(r"(?<![/\d])(\d+)/(\d+) \+ (\d+)/(\d+) = 1(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    корни = [int(к) for к in _КОРЕНЬ.findall(с)]
    for a, s in _СУММА.findall(с):
        if not корни or int(s) - int(a) != корни[-1]:
            return True, False
    for s, a, r in _РАЗНОСТЬ.findall(с):
        если = int(s) - int(a)
        if r and если != int(r):
            return True, False
        if корни and если != корни[-1]:
            return True, False
    for k, p in _ПРОИЗВЕДЕНИЕ.findall(с):
        if not корни or int(k) * корни[-1] != int(p):
            return True, False
    for p, k in _ЧАСТНОЕ.findall(с):
        if int(k) == 0 or int(p) % int(k) or int(p) // int(k) != корни[-1]:
            return True, False
    for a, b, r in _ЧИСЛОВАЯ_СУММА.findall(с):
        if int(a) + int(b) != int(r):
            return True, False
    for a, n, b, m in _ДОЛИ.findall(с):
        if n != m or int(a) + int(b) != int(n):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if род in БЕЗ_СЛОВ and язык != "ru":
                continue
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # МУТАНТ ПО ЧИСЛУ: подмена корня обязана быть поймана в КАЖДОМ роде.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род), None)
        if страница is None:
            continue
        # ПОРЧА ИДЁТ ТУДА, ГДЕ У РОДА СТОИ́Т ЧИСЛО-ОТВЕТ, а не в одно место для всех:
        # род «словом» кончается СЛОВОМ, и правка последнего «x = N.» его не касается.
        if род == "доля до единицы":
            порча = re.sub(r"= 1\.$", "= 2.", страница)
        elif род == "словом":
            порча = re.sub(r"(x = \d+ − \d+ = )(\d+)",
                           lambda m: f"{m.group(1)}{int(m.group(2)) + 1}", страница)
        elif род == "единственность":
            # ПОРЧА ИДЁТ В СВИДЕТЕЛЯ, А НЕ В КОРЕНЬ: у этого рода три числовые суммы,
            # и подмена любой из них разводит доказательство с тем, что оно доказывает.
            порча = re.sub(r"(вышло бы \d+ \+ \d+ = )(\d+)",
                           lambda m: f"{m.group(1)}{int(m.group(2)) + 1}", страница, count=1)
        elif род == "спрошенное":
            # ПОРЧА ИДЁТ В ДОКАЗАТЕЛЬСТВО, А НЕ В КОРЕНЬ: у этого рода корень назван
            # ДВАЖДЫ — «x = 1, ибо 3 − 2 = 1», — и подмена одного из двух разводит их.
            порча = re.sub(r"(− \d+ = )(\d+)\.$",
                           lambda m: f"{m.group(1)}{int(m.group(2)) + 1}.", страница)
        else:
            порча = re.sub(r"x = (\d+)\.$",
                           lambda m: f"x = {int(m.group(1)) + 1}.", страница)
        if порча == страница:
            беды.append(f"порча не состоялась в роде {род}: {страница[:70]}")
        elif судить(порча)[1] is not False:
            беды.append(f"подменённый корень прошёл в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ: обрезанное слово речи обязано быть поймано.
    сл = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "словом")
    порча = сл.replace("плюс", "плю", 1)
    if порча == сл:
        беды.append("порча не состоялась: нет слова «плюс»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(сл + " " + сл)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ОБРАТНОЕ ДЕЙСТВИЕ ОБЯЗАНО СТОЯТЬ НА СТРАНИЦЕ, А НЕ ПОДРАЗУМЕВАТЬСЯ.
    for с, (_я, р) in ПОКАЗЫ.items():
        if р == "голое" and " − " not in с:
            беды.append(f"голое без вычитания: {с[:70]}")
            break
        if р == "умножением" and " ÷ " not in с:
            беды.append(f"умножение без деления: {с[:70]}")
            break
    print(f"ОДНОШАГОВОЕ УРАВНЕНИЕ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, "
          f"бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
