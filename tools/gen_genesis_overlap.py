#!/usr/bin/env python3
"""GENESIS layer: ДВА КРУЖКА — see tools/overlapforms.py for the law.

ОБЕ СТОРОНЫ ЛОВУШКИ ИДУТ ОДНОЙ ГРУППОЙ, и здесь это важнее, чем где бы то ни было в своде.
Превышение суммы над целым есть признак ДОСТАТОЧНЫЙ, но не необходимый; показанный порознь
со своей границей, он читается как необходимый, и выучивший его так ошибётся не в редком
случае, а в половине всех.

    ПРИЗНАК ДОСТАТОЧНЫЙ, ПОКАЗАННЫЙ БЕЗ СВОЕЙ ГРАНИЦЫ, ЧИТАЕТСЯ КАК НЕОБХОДИМЫЙ.

СЧЁТ И РАЗБОР ЦЕЛОГО — одной группой: «занятых 16», «ни в одном 4» и «только шахматы 7»
суть три взгляда на одно деление класса. ВОПРОС отдельно — ответ рядом с ним отнял бы у
него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import overlapforms as O  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_overlap.txt"
ГРУППЫ = (("сумма с перекрытием", "ни в одном", "только одно"),
          ("сумма больше целого", "сумма не больше целого"),
          ("общее есть часть", "без перекрытия"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in O.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in O.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
