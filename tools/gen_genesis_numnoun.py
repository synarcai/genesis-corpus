#!/usr/bin/env python3
"""GENESIS layer: ИМЯ ПОСЛЕ ЧИСЛИТЕЛЬНОГО — see tools/numnounforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Четыре ответа на один вопрос» и «перенос между лагерями и есть отказ» идут вместе: первое
говорит, ЧТО ответов четыре, второе показывает ЦЕНУ незнания этого — отвергнутую строку.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Одно слово правила о трёх законах», «двойственное не есть ячейка» и «лестница замыкается» —
второй группой: все три о том, что ОБЪЯВЛЕНИЕ КОРОЧЕ ЗАКОНА. Первое — о недоборе объявления,
второе — о форме, которой в таблице нет вовсе, третье — о лестнице, читаемой как восхождение.

«Спрошено и отвечено» — третьей.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import numnounforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_numnoun.txt"
ГРУППЫ = (("четыре ответа на один вопрос", "перенос между лагерями и есть отказ"),
          ("одно слово правила о трёх законах", "двойственное не есть ячейка",
           "числительное гнётся под имя", "лестница замыкается"),
          ("спрошено и отвечено",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
