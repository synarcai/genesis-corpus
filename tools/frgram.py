#!/usr/bin/env python3
"""ФРАНЦУЗСКАЯ ЭЛИЗИЯ: один дом закона, которым пользуются все.

    СЛУЖЕБНОЕ СЛОВО, СТОЯЩЕЕ В РАМКЕ ЦЕЛЫМ, НЕ СЛЫШИТ ТОГО, ЧТО ЗА НИМ ПОДСТАВЯТ.

Французское «je» перед гласной обязано стать «j'», «de» — «d'», «que» — «qu'». Это не оттенок
речи, а её закон: «combien de abdos», «est-ce que une souris», «je ouvre» суть ошибки, а не
варианты. Рамка держит служебное слово ЦЕЛЫМ — иначе она не покрыла бы согласных, — и потому
сокращение делается ПОСЛЕ подстановки, когда слово за ним уже известно.

ДВА ЧИТАТЕЛЯ У ОДНОГО ЗАКОНА, И ОБА ЗДЕСЬ:

  · дом пишет страницу и зовёт `элизия` над готовой строкой;
  · суд строит образец и зовёт `в_образце` над неизменным куском — образец, собранный из
    рамки, обязан знать всё, что дом делает ПОСЛЕ подстановки, и потому принимает ОБЕ формы.

    КАКАЯ ИЗ ДВУХ ФОРМ ВЕРНА, РЕШАЕТ НЕ ОБРАЗЕЦ, А ЗАКОН: образцу довольно не звать чужой ту
    страницу, которую дом написал верно.

«h» БЫВАЕТ ПРИДЫХАТЕЛЬНЫМ («le héros», «la hache»), и перед ним элизии НЕТ. Оттого слова с
НЕМЫМ «h» названы поимённо, а не выведены буквой: правило по букве сократило бы и «le héros».

    python3 tools/frgram.py    # самопроверка
"""
import re

# СЛУЖЕБНОЕ СЛОВО → ЕГО СОКРАЩЕНИЕ. Список закрыт: французская элизия есть закон о ЭТИХ
# словах, а не о всяком слове на «-e».
ПАРЫ = {
    "je": "j'", "que": "qu'", "ne": "n'", "de": "d'", "le": "l'", "la": "l'",
    "ce": "c'", "se": "s'", "me": "m'", "te": "t'", "si": "s'",
}
ГЛАСНЫЕ = "aeiouéèêàâîôûyœæ"
# СЛОВА С НЕМЫМ «h» — перед ними элизия ЕСТЬ; перед придыхательным её нет.
НЕМОЕ_H = frozenset((
    "heure", "heures", "homme", "hommes", "histoire", "histoires", "hiver", "hôpital",
    "hôtel", "herbe", "huile", "habitude", "habitudes", "école",
))
# СЛОВА С ПРИДЫХАТЕЛЬНЫМ «h» — перед ними элизии НЕТ, и ряд их объявлен ТАБЛИЦЕЙ (12.09).
# Прежде он жил в прозе заголовка («le héros», «la hache») и потому не читался ничем, кроме
# человека: дом, которому эти слова нужны, переписал бы их у себя и завёл второе объявление.
#
#     ЗНАНИЕ, ЗАПИСАННОЕ ПРОЗОЙ, НЕ ЧИТАЕТСЯ НИКЕМ, КРОМЕ ЧЕЛОВЕКА.
#
# Ряд НЕ ЕСТЬ отрицание немого: слово, не стоящее ни в одном из двух рядов, элизии не получает
# по общему правилу буквы — таблица придыхательных нужна тому, кто ПОКАЗЫВАЕТ границу, а не
# тому, кто её применяет.
ПРИДЫХАТЕЛЬНОЕ_H = frozenset(("héros", "hache", "haricot", "hibou"))

# «si» сокращается ТОЛЬКО перед «il»/«ils», и это единственное исключение из общего правила
_ТОЛЬКО_ПЕРЕД = {"si": ("il", "ils")}
_СЛОВО = re.compile(r"[a-zà-ÿœæ]+", re.IGNORECASE)


def _сократить(целое, следом):
    низ = следом.lower()
    если = _ТОЛЬКО_ПЕРЕД.get(целое)
    if если is not None:
        return низ in если
    if низ[:1] in ГЛАСНЫЕ:
        return True
    return низ[:1] == "h" and низ in НЕМОЕ_H


def элизия(строка):
    """Готовая французская строка с обязательными сокращениями."""
    вон = строка
    for целое, сокращённое in ПАРЫ.items():
        образец = re.compile(r"(?<![-\w'’])" + re.escape(целое) + r" (?=([a-zà-ÿœæ]+))",
                             re.IGNORECASE)
        вон = образец.sub(
            lambda м, ц=целое, с=сокращённое: с if _сократить(ц, м.group(1)) else м.group(0),
            вон)
    return вон


# РАЗВОРОТ СТЯЖЕНИЯ: обратная дорога того же закона. Пишущий сливает, читающий разделяет —
# и оба берут правило ЗДЕСЬ, а не каждый у себя.
#
#     ОДИН ЗАКОН, ДВА ЧИТАТЕЛЯ: элизия есть правило ПИСЬМА, а не другое слово. Прибор,
#     читающий «s'il» как новое слово, дробит род по знаку апострофа и объявляет долгом
#     то, что было единым до утренней правки.
#
# Пары читаются из того же объявления, что и элизия; «s'» стои́т в них дважды («se» и «si»),
# и разворот берёт то из двух, что подходит следующему слову: «si» — лишь перед «il»/«ils».
_РАЗВОРОТ = re.compile(r"\b([a-zà-ÿœæ]{1,3})['’]([a-zà-ÿœæ]+)", re.IGNORECASE)


def развернуть(строка):
    """Строка, где стяжения разведены обратно: «s'il» → «si il», «j'ai» → «je ai».

    ЭТО НЕ ПИСЬМО, А ЧТЕНИЕ: разведённая строка не показывается никому, она лишь даёт
    прибору увидеть то же слово, какое стояло до элизии.
    """
    короткие = {}
    for целое, сокращённое in ПАРЫ.items():
        короткие.setdefault(сокращённое.rstrip("'").lower(), []).append(целое)

    def один(м):
        начало, хвост = м.group(1), м.group(2)
        свои = короткие.get(начало.lower())
        if not свои:
            return м.group(0)
        # СЛОВО С ОБЪЯВЛЕННОЙ ГРАНИЦЕЙ СПРАШИВАЕТСЯ ПЕРВЫМ: «s'» есть и «se», и «si», но
        # «si» сокращается ЛИШЬ перед «il»/«ils» — и потому именно оно верно в «s'il».
        # Слово без границы подходит ко всему и, спрошенное первым, забрало бы чужое.
        #
        #     ЧАСТНОЕ ПРАВИЛО СТАРШЕ ОБЩЕГО ТАМ, ГДЕ ОБА ПОДХОДЯТ.
        for целое in sorted(свои, key=lambda ц: _ТОЛЬКО_ПЕРЕД.get(ц) is None):
            только = _ТОЛЬКО_ПЕРЕД.get(целое)
            if только is None or хвост.lower() in только:
                return f"{целое} {хвост}"
        return м.group(0)

    return _РАЗВОРОТ.sub(один, строка)


def в_образце(сырой, экранировать=re.escape):
    """Экранированный кусок образца, где служебное слово принимает ОБЕ формы.

    РАБОТА ИДЁТ НАД СЫРЫМ ТЕКСТОМ, А НЕ НАД ЭКРАНИРОВАННЫМ: `re.escape` пробела не трогает
    с версии 3.7, и якорь по экранированному пробелу не совпал бы ни разу.
    """
    for целое, сокращённое in ПАРЫ.items():
        хвост = целое + " "
        if сырой.endswith(хвост) and (len(сырой) == len(хвост)
                                      or not сырой[-len(хвост) - 1].isalpha()):
            голова = экранировать(сырой[:-len(хвост)])
            return голова + "(?:" + экранировать(хвост) + "|" + экранировать(сокращённое) + ")"
    return экранировать(сырой)


def _самопроверка():
    случаи = (
        ("je ouvre.", "j'ouvre."),
        ("je vends.", "je vends."),
        ("combien de abdos a fait Hugo ?", "combien d'abdos a fait Hugo ?"),
        ("combien de livres ?", "combien de livres ?"),
        ("est-ce que une souris ?", "est-ce qu'une souris ?"),
        ("qu'est-ce que une intention ?", "qu'est-ce qu'une intention ?"),
        ("combien de heures ?", "combien d'heures ?"),
        ("le héros court.", "le héros court."),
        ("avais-je au début ?", "avais-je au début ?"),
        ("il ne a pas.", "il n'a pas."),
    )
    for дано, ждём in случаи:
        дало = элизия(дано)
        assert дало == ждём, (дано, дало, ждём)
    # РАЗВОРОТ ЕСТЬ ОБРАТНАЯ ДОРОГА, И ОНА ПРОВЕРЯЕТСЯ НА ЗАВЕДОМО ИЗВЕСТНОМ.
    развороты = (("s'il en donne 13", "si il en donne 13"),
                 ("s'est levé", "se est levé"),
                 ("j'ai deux chats", "je ai deux chats"),
                 ("si elle en donne 3", "si elle en donne 3"),
                 ("combien d'abdos", "combien de abdos"),
                 ("l'heure", "le heure"),
                 ("aujourd'hui", "aujourd'hui"))
    for дано, ждём in развороты:
        дало = развернуть(дано)
        assert дало == ждём, (дано, дало, ждём)
    кусок = в_образце("combien de ")
    assert "d'" in кусок and "de\\ " in кусок or "d'" in кусок, кусок
    assert в_образце("combien ") == re.escape("combien "), в_образце("combien ")
    print(f"  случаев проверено: {len(случаи)}; пар объявлено: {len(ПАРЫ)}; "
          f"слов с немым h: {len(НЕМОЕ_H)}")
    for дано, ждём in случаи[:5]:
        print(f"    {дано!r} → {элизия(дано)!r}")


if __name__ == "__main__":
    _самопроверка()
