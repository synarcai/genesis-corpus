#!/usr/bin/env python3
"""РОДЫ УТВЕРЖДЕНИЙ: кто ОБЯЗАН читать строку, а не кто её прочёл.

СУДИМОСТЬ СТРОКИ НЕ ЕСТЬ СУДИМОСТЬ ВСЕХ ЕЁ УТВЕРЖДЕНИЙ, и это вскрылось
делом: слой русских глаголов прошёл ворота записи, ибо КАЖДАЯ строка
была судима — судом СОГЛАСОВАНИЯ. Но согласование читает формы, а не
счёт, и строка «вера написала 3 книги… всего 9 книг» верна по формам,
ложна по числу и была ПРОПУЩЕНА.

Мера охвата спрашивала «читает ли строку хоть кто-нибудь». Верный
вопрос иной: «прочёл ли её ТОТ, чьему роду принадлежит её утверждение».

РОД ОБЪЯВЛЕН ПРИЗНАКОМ И ХОЗЯЕВАМИ. Признак — то, по чему род виден в
строке; хозяева — суды, которые этим родом владеют. Ни признак, ни
список хозяев не выводятся из кода: их называют, и потому они здесь.

ЧЕГО ЭТОТ СВОД НЕ ГОВОРИТ: он не перечисляет ВСЕ роды утверждений —
такого списка нет ни у кого. Он называет те, чьи признаки МЕХАНИЧЕСКИ
видны, и потому его молчание о прочих есть честная граница, а не
утверждение полноты.
"""

import collections
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from rugram import ПО_ФОРМЕ  # noqa: E402

# ПРИЗНАК РОДА ВЫВОДИТСЯ ИЗ ОБЪЯВЛЕННОГО, А НЕ УГАДЫВАЕТСЯ. Первая
# редакция искала согласование образцом «число + русское слово» — и
# назвала им «число 10 читается как десять»: «читается» не имя, и рода
# там нет вовсе. Шестьсот ложных обвинений в первый же прогон.
# Согласование видно РОВНО ТАМ, где за числом стоит форма, объявленная
# домом русского счёта.
СОГЛАСОВАНИЕ = (r"\b\d+ (?:"
                + "|".join(sorted((re.escape(ф) for ф in ПО_ФОРМЕ),
                                  key=len, reverse=True))
                + r")\b")

Род = collections.namedtuple("Род", "имя зачем признак хозяева")

РОДЫ = (
    Род("счёт",
        "два числа и знак итога: утверждение о ВЕЛИЧИНЕ, и его обязан "
        "пересчитать суд, умеющий считать",
        r"(?:\d[^.]*\d[^.]*(?:всего|in all|итог|hence)"
        r"|сколько[^?]*\?[^.]*\d"
        r"|how many[^?]*\?[^.]*\d)",
        # МИР СТАВОК СЧИТАЕТ ПО СУЩЕСТВУ: «сколько минут в двух часах»
        # есть его собственный род, и он пересчитывает отношение по
        # объявленному графу единиц, а не догадывается.
        #
        # ТРИ РУССКИХ СУДА ВНЕСЕНЫ ПОСЛЕ ЗАМЕРА, А НЕ ПО ИМЕНИ. Миры
        # `ru_conversions`, `ru_compare` и `ru_story` пришли в свод
        # сегодня со своими судами, и 245 их строк объявились
        # прочтёнными НЕ ХОЗЯИНОМ — не оттого, что их читал чужой, а
        # оттого, что свод не знал имён новых хозяев. Каждый ПЕРЕСЧИТЫВАЕТ
        # по существу: перевод единиц спрашивает отношение у графа
        # `units.РЁБРА`, сравнение делит и вычитает заново и порознь,
        # словесная задача складывает цепь и держит одного носителя.
        # Владение доказано делом суда, а не его именем.
        #
        # ВНЕСЕНЫ 03.09 ПО ЗАМЕРУ СУДА РОДОВ (380 строк не хозяином):
        # суд пространства пересчитывает соседей клетки по сетке
        # (`_соседи`), суд школьных форм пересчитывает каждую рамку
        # лямбдой над её числами — оба владеют счётом делом.
        {"rates", "percent", "average", "equation", "everyday", "story_chain", "age", "share", "compare_mult", "inquiry_de_fr",
         "selfmeasure", "ru_conversion", "ru_compare", "ru_story", "space", "gsmforms",
         # СУД МЕСТОИМЕНИЙ пересчитывает итог страницы K = N ± M (03.09).
         "pronoun",
         # РАССУЖДЕНИЯ (дом речи, 03.09): связка «hence» стоит в признаке
         # счёта; суды дознания и уравнений пересчитывают свидетеля
         # рассуждения сами («40 = 2 × 20», «4 − 6 + 2 = 0»).
         "inquiry", "equation",
         # СУД ПРОСТРАНСТВ пересчитывает число вершин и рёбер в вопросе
         # «how many edges does graph … have?» (03.09).
         "mathspaces",
         "inquiry_es_it", "arith", "episode", "algo", "number", "sequence", "geometry",
         # СУД ДЕНЕГ пересчитывает центы, мосты и сдачу сам (04.09, 50 строк
         # по замеру суда родов); СУД ДЫР пересчитывает ответ «сколько» из
         # факта-фрейма (04.09).
         "money", "holes",
         # ДОМА ИСТОРИЙ 05.09 (замер суда родов на седьмой точке: 7 147 строк не хозяином):
         # суд форм SVAMP пересчитывает леджер и цепочку шагов и требует числа истории в
         # леджере; суд стыков пересчитывает сумму фраз; суд историй отношений — итог
         # отношения. Владение делом, не именем.
         "svamp", "joints", "relations_story",
         # суды историй меры, страниц действия, историй денег и двух родов пересчитывают
         # свой леджер сами (замер суда родов 05.09)
         "measure_story", "action_pages", "money_story", "two_kinds",
         # дома беседы и меры (05.09): суд связок пересчитывает леджер разговора, суд меры
         # действия — сумму мер и носителей, суды числового ряда, счётных фактов, цены,
         # единиц времени, перекрёстка, заданий, меры на языках и букв — свои ответы
         "links", "action_measure", "unit_counts", "numberline", "countfacts", "price",
         "timeunits", "cross", "task", "measure_langs", "letters", "joint2", "nature",
         # ДОМА ФРАЗ НА ЯЗЫКАХ (04.09): каждый суд пересчитывает свой леджер
         # сам (мост центов, площадь, отношение единиц, среднее и процент,
         # цикл недели, член прогрессии, разность и отношение).
         "money_langs", "geometry_langs", "units_langs", "stats_langs", "calendar_langs", "sequences_langs", "compare_langs", "share_langs", "physics_langs",
         "linalg", "statistics", "program", "compsci", "unit",
         "notation", "formula", "physlaw", "physics", "calendar",
         "speech", "case", "valence", "cyber", "machine", "proof"}),
    Род("согласование",
        "число при имени: утверждение о ЯЗЫКЕ, и его обязан прочесть "
        "суд формы, а не суд счёта",
        СОГЛАСОВАНИЕ,
        # СУД САМОМЕРЫ ДЕРЖИТ СВОЮ ТАБЛИЦУ СЧЁТНЫХ ФОРМ, сверенную с
        # домом русского счёта (assert против rugram.СЧЁТНЫЕ), и судит
        # форму при числе сам — внесён 03.09 по замеру (110 строк).
        {"rugram", "episode", "speech", "unit", "notation", "physlaw",
         # суд природы (04.09) и суд связок (05.09) принимают только объявленные счётные
         # формы своих рамок — форма при числе судится ими по построению
         "nature", "links",
         "compsci", "case", "valence", "calendar", "statistics",
         "formula", "sequence", "number", "algo", "cyber", "machine",
         "geometry", "program", "proof", "linalg", "selfmeasure",
         # СУД ПРОСТРАНСТВ сверяет счётную форму при числе вершин и
         # рёбер с домом русского счёта (03.09, 20 строк).
         "mathspaces",
         # СУД ШКОЛЬНЫХ ФОРМ сверяет все пары «число слово» своих русских
         # строк с домом счёта, включая косвенную форму под предлогом.
         "gsmforms"}),
    Род("имя знака",
        "«читается как»: утверждение об ИМЕНИ, и его сверяют с "
        "объявлением, а не с числом",
        r"читается как|is read as",
        # МИР ПОЛНОЙ РАЗМЕТКИ ГОВОРИТ ЭТИМ РОДОМ ЗАКОННО: «читается
        # как» есть его собственный оборот для стилей, и он же держит
        # ВОПРОСНУЮ поверхность того же утверждения, какой старый суд
        # стиля не читает (его образец привязан к зачину записи).
        # МИР ГЛИФОВ ГОВОРИТ ЭТИМ РОДОМ ЗАКОННО: «ряд глифов … читается
        # как слово» — его суд отрисовывает слово таблицей шрифта и
        # сличает клетки, а не верит имени (внесён 03.09, 90 строк).
        {"logic", "markup", "program", "proof", "compsci", "markdown", "glyph",
         # МИР КОНВЕРСИИ ГОВОРИТ ЭТИМ РОДОМ ЗАКОННО: «вслух читается
         # как» есть его собственный оборот, и он проверяет его
         # РАЗБОРОМ обеих сторон в одно дерево.
         "formula_lang"}),
    Род("оценка",
        "оценочное слово: утверждение о ЦЕННОСТИ, и оно обязано нести "
        "вычислимое основание",
        r"стало лучше|стало хуже|страшно|спокойно|тревожно",
        {"valence"}),
)

assert len({р.имя for р in РОДЫ}) == len(РОДЫ)
