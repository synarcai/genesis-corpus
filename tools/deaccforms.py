_МЕТКИ = {"именительный": "им", "nominative": "им", "подлежащим": "им", "subject": "им",
          "винительный": "вин", "accusative": "вин"}
# МЕТКА СТОИ́Т НЕ ВПЛОТНУЮ: «„den Tisch“ стои́т подлежащим» — между цитатой и меткой слово.
# Окно узкое: три слова, — иначе метка соседней цитаты приписалась бы этой.
ОКНО_МЕТКИ = 3


def _падеж_цитаты(строка, начало, конец, тело):
    """«им» / «вин» / None — падеж, которого страница требует от ЭТОЙ цитаты.

    МЕТКА СТОИ́Т ПО ОБЕ СТОРОНЫ ЦИТАТЫ, И ЧИТАЮТСЯ ОБЕ: «винительный „den Baum“» и «„den
    Tisch“ стои́т подлежащим» — одна и та же речь о падеже, сказанная с разных сторон.
    """
    if "ich sehe" in тело:
        return "вин"
    перед = _re.findall(r"[^\W\d_]+", строка[:начало])[-ОКНО_МЕТКИ:]
    for сл in reversed(перед):
        если = _МЕТКИ.get(сл.lower())
        if если is not None:
            return если
    for сл in _re.findall(r"[^\W\d_]+", строка[конец:])[:ОКНО_МЕТКИ]:
        если = _МЕТКИ.get(сл.lower())
        if если is not None:
            return если
    return None


def _нарушает(тело, падеж):
    """Нарушает ли цитата закон дома: артикль не тот, какого требуют род и падеж."""
    for артикль, имя in _ПАРА.findall(тело.lstrip("*")):
        род = _РОД_ИМЕНИ.get(имя)
        if род is None:
            continue
        им, вин = НЕМ_РОДЫ[род][:2]
        if артикль != (вин if падеж == "вин" else им):
            return True
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for m in _re.finditer(r"«([^»]+)»", с):
        цитата = m.group(1)
        звезда = цитата.startswith("*")
        if not _ПАРА.search(цитата.lstrip("*")):
            continue
        падеж = _падеж_цитаты(с, m.start(), m.end(), цитата)
        if падеж is None:
            continue                   # страница о падеже этой цитаты не сказала — не сужу
        if _нарушает(цитата, падеж) != звезда:
            return True, False
    return True, True


