#!/usr/bin/env python3
"""ДОМ МЕРЫ ЧЕРЕЗ «of» — число считает СОСУД, а вещь стои́т за предлогом (07.09).

ЗАКАЗ КУПЛЕН ПЕРЕПИСЬЮ, А НЕ ДОГАДКОЙ. Атлас непрочитанных чисел базы p156 (томограф
st48, omega-ad) ставит МЕРУ И ПАРТИТИВ вторым классом — 107 историй из 420. Перепись по
своду разделила класс надвое, и одна половина оказалась не нашей:

    «N of them»        1 645 партитивов в своде, из них голых «N of them» 1 061 —
                       форма живая и частая; падение читателя на ней есть стена его
                       рамочного пути, а не долг корпуса (подтверждено holon-f9).
    «3 cups of sugar»  198 строк в четырёх мирах, пар «мера + вещь» 23 — и вот
                       раскладка: cups of water 64, а остальные двадцать две пары по
                       ДЕВЯТЬ и менее.

    РЫНОК, ВСТРЕТИВШИЙ МЕРУ С ОДНОЙ ВЕЩЬЮ ШЕСТЬДЕСЯТ ЧЕТЫРЕ РАЗА И С ДВАДЦАТЬЮ ДВУМЯ ПО
    ДЕВЯТЬ, КУПИЛ КОЛЛОКАЦИЮ, А НЕ МЕРУ. «cups of water» он знает как одно слово;
    «cups of» как рамку с дырой — нет.

ЧТЕНИЕ ЗДЕСЬ ИНОЕ, ЧЕМ ВЕЗДЕ В СВОДЕ. Число стои́т при СОСУДЕ, а вещь — за предлогом и во
множественное не идёт («3 cups of sugar», а не «sugars»). Весь прочий свод учит числу при
самой вещи («Ben had 22 books»), и рамка, выученная там, здесь берёт не то слово.

ТРИ УСЛОВИЯ СХЕМЫ, ОБЪЯВЛЕННЫЕ holon-f9 И ИСПОЛНЕННЫЕ ЗДЕСЬ ПОИМЁННО:

    ОТВЕТ НЕСЁТ СОСУД. «5 cups of sugar», а не «5 sugar» и не голое «5»: схема читает
        счётное существительное по месту цифры (М-700), «cups» ложится числом, «sugar» —
        меткой факта; ответ без сосуда развёл бы ключ с чтением.
    ВОПРОС О ВЕЩИ — ОТДЕЛЬНАЯ ОБЪЯВЛЕННАЯ РАМКА. «how much sugar does Ann have?» идёт тем
        же рядом по метке, и мост «метка → товар» есть у читателя, а не у корпуса; рамка
        объявлена нарочно, чтобы отказ на ней считался стеной читателя, а не ложью свода.
    ОБЕ ФОРМЫ СУММЫ. Один сосуд и две вещи («2 bags of sugar and 3 bags of flour») —
        пара списка по метке, та самая форма «19 apps and 18 files», на которой читатель
        падает семьюдесятью историями атласа; и одна метка у двух носителей («Ann has 2
        cups of sugar and Ben has 3 cups of sugar») — свёртка по метке.

ЗАКОН ЧИСЛА: не менее LAW³ = 8 страниц на рамку, сосудов не менее LAW² = 4 видов, вещей
не менее LAW² = 4 — иначе рамка «[Number Vessel of Goods]» не анти-унифицируется, и
рынок снова купит одну пару словом.

СТРАНИЦУ «the recipe calls for 3 cups of sugar» ЭТОТ ДОМ НЕ ПИШЕТ, и это сказано, а не
забыто: носитель там — «recipe», вещь неодушевлённая и без деятельности, глагол «calls
for»; это отдельная стена («сцена — носитель»), и мешать её с мерой значило бы мерить
две стены одним числом.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from layer import emit                                            # noqa: E402
from plural import by_count                                       # noqa: E402

_ПАКЕТ = json.loads((pathlib.Path(__file__).resolve().parent / "langpacks" / "en.json")
                    .read_text(encoding="utf-8"))
_ИМЕНА_ПАКЕТА = set(_ПАКЕТ["person_names"])
_ПО_СТРОЧНОМУ = {и.lower(): и for и in _ИМЕНА_ПАКЕТА}
ИМЕНА = [_ПО_СТРОЧНОМУ.get(и, и) for и in
         ("ann", "ben", "carla", "dan", "elena", "felix", "grace", "hugo")]
assert set(ИМЕНА) <= _ИМЕНА_ПАКЕТА, "имя не объявлено пакетом en"

# СОСУД ОБЪЯВЛЕН ПАКЕТОМ, А ВЕЩЬ — НЕТ, И ТАК И ДОЛЖНО БЫТЬ. Счёт идёт по сосуду, и
# сосуд обязан быть словом объявленным (суд памяти судит счёт объявленного слова);
# вещь за предлогом не считается никогда, во множественное не идёт и объявления счёта
# не требует.
СОСУДЫ = ("cup", "bag", "bottle", "box", "pack", "basket", "crate")
for _с in СОСУДЫ:
    assert _с in _ПАКЕТ["noun_forms"], "сосуд не объявлен пакетом: " + _с

# МНОЖЕСТВЕННОЕ БЕРЁТСЯ У ПАКЕТА, А НЕ СКЛЕИВАЕТСЯ БУКВОЙ «s» (07.09, первая проба дома
# написала «16 boxs of honey»). Пакет объявляет «box → boxes»; дом, приписавший «s» сам,
# сочинил слово, какого в языке нет, и суд памяти назвал бы его ложью — если бы дошёл.
#
#     ФОРМА СЛОВА ЕСТЬ ОБЪЯВЛЕНИЕ ПАКЕТА, А НЕ ПРАВИЛО ДОМА. Дом, знающий правило лучше
#     пакета, знает его только для тех слов, о которых не подумал.
МНОГО = {с: _ПАКЕТ["noun_forms"][с] for с in СОСУДЫ}

# ВЕЩЬ БЕРЁТ СВОЙ СОСУД, А НЕ ВСЯКИЙ: мука бывает в чашке и в мешке, молоко — в бутылке
# и в ящике, но не в мешке. Таблица объявлена, а не угадана соседством.
ВЕЩИ = {
    "sugar":  ("cup", "bag", "box", "pack"),
    "flour":  ("cup", "bag", "box"),
    "salt":   ("cup", "bag", "pack", "box"),
    "rice":   ("cup", "bag", "box", "pack"),
    "water":  ("cup", "bottle", "crate"),
    "milk":   ("cup", "bottle", "crate", "box"),
    "juice":  ("cup", "bottle", "crate"),
    "tea":    ("cup", "box", "pack"),
    "coffee": ("cup", "bag", "pack", "box"),
    "honey":  ("cup", "bottle", "jar_none", "box"),
    "oil":    ("cup", "bottle", "crate"),
    "jam":    ("cup", "bottle", "box", "basket"),
}
ВЕЩИ = {в: tuple(с for с in сс if с in СОСУДЫ) for в, сс in ВЕЩИ.items()}
СПИСОК_ВЕЩЕЙ = tuple(sorted(ВЕЩИ))
for _в, _сс in ВЕЩИ.items():
    assert len(_сс) >= 2, _в


def _пара_вещей(зерно, сосуд):
    """Две РАЗНЫЕ вещи, обе берущие ЭТОТ сосуд — иначе пара списка была бы ложью."""
    годные = [в for в in СПИСОК_ВЕЩЕЙ if сосуд in ВЕЩИ[в]]
    a = годные[зерно % len(годные)]
    b = годные[(зерно // len(годные) + 1) % len(годные)]
    if b == a:
        b = годные[(годные.index(a) + 1) % len(годные)]
    return a, b


def показы(pi):
    основа = pi * 31
    вон = []
    for i in range(len(СПИСОК_ВЕЩЕЙ) * len(СОСУДЫ) * 3):
        вещь = СПИСОК_ВЕЩЕЙ[(основа + i) % len(СПИСОК_ВЕЩЕЙ)]
        годные = ВЕЩИ[вещь]
        сосуд = годные[(основа + i) % len(годные)]
        имя = ИМЕНА[(основа + i) % len(ИМЕНА)]
        второй = ИМЕНА[(основа + i + 3) % len(ИМЕНА)]
        n = (основа + i * 7) % 40 + 2          # 2..41
        m = (основа + i * 11) % 33 + 2         # 2..34
        рамка = ((основа + i) // len(СПИСОК_ВЕЩЕЙ)) % 4
        мера_n = f"{n} {by_count(n, МНОГО[сосуд])} of {вещь}"
        мера_m = f"{m} {by_count(m, МНОГО[сосуд])} of {вещь}"
        if рамка == 0:
            # СВЁРТКА ПО ОДНОЙ МЕТКЕ, ДВА НОСИТЕЛЯ, СТЫК «and» МЕЖДУ ДВУМЯ ЧИСЛАМИ
            вон.append(
                f"{имя} has {мера_n} and {второй} has {мера_m}. "
                f"how many {by_count(2, МНОГО[сосуд])} of {вещь} do they have in all? "
                f"{n + m} {by_count(n + m, МНОГО[сосуд])} of {вещь}: {n} + {m} = {n + m}.")
        elif рамка == 1:
            # ПАРА СПИСКА: ОДИН СОСУД, ДВЕ ВЕЩИ — форма «19 apps and 18 files»
            a, b = _пара_вещей(основа + i, сосуд)
            вон.append(
                f"{имя} has {n} {by_count(n, МНОГО[сосуд])} of {a} and "
                f"{m} {by_count(m, МНОГО[сосуд])} of {b}. "
                f"how many {by_count(2, МНОГО[сосуд])} does {имя} have in all? "
                f"{n + m} {by_count(n + m, МНОГО[сосуд])}: {n} + {m} = {n + m}.")
        elif рамка == 2:
            # УБЫЛЬ: ответ несёт сосуд и вещь целиком
            k = m if m < n else n - 1
            вон.append(
                f"{имя} has {мера_n}. {имя} uses {k} {by_count(k, МНОГО[сосуд])} of {вещь}. "
                f"how many {by_count(2, МНОГО[сосуд])} of {вещь} does {имя} have now? "
                f"{n - k} {by_count(n - k, МНОГО[сосуд])} of {вещь}: {n} − {k} = {n - k}.")
        else:
            # ВОПРОС О ВЕЩИ — ОТДЕЛЬНАЯ ОБЪЯВЛЕННАЯ РАМКА (условие holon-f9).
            #
            # «how much sugar» спрашивает вещь, а ответ всё равно несёт СОСУД: вещь эта
            # неисчислима, и числом её не назвать. Мост «метка → товар» есть у читателя;
            # отказ на этой рамке есть его стена, а не ложь свода, и потому рамка стои́т
            # здесь ОБЪЯВЛЕННОЙ, а не подразумеваемой.
            вон.append(
                f"{имя} has {мера_n}. "
                f"how much {вещь} does {имя} have? "
                f"{мера_n}.")
    return вон


def main():
    emit("datasets/genesis_measureof.txt", показы)


if __name__ == "__main__":
    main()
