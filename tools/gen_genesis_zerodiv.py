#!/usr/bin/env python3
"""КОВКА ДОМА ДЕЛЕНИЯ НА НОЛЬ.

ОСНОВАНИЕ И ПЕРВЫЙ НОЛЬ ИДУТ В ОДНОМ ПРОХОДЕ: «12 ÷ 3 = 4, ибо 4 × 3 = 12» и «0 ÷ 6 = 0, ибо
0 × 6 = 0» суть один закон на двух числах, и порознь второе читалось бы особым правилом о нуле,
которого нет. ДВА ОТКАЗА идут своей группой: они об ином — о том, что поиск бывает пустым и
бывает переполненным, и рядом друг с другом их причины различимы.

Группы берутся у самих показов, а не у объявленного списка: первый заход дома вероятности
резал их по таблице пар и молча терял целый род.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import zerodivforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_zerodiv.txt"
ГРУППЫ = (("деление", "ноль сверху"), ("ноль снизу", "ноль на ноль"),
          ("проверка нельзя", "проверка всякое"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
