def _оракул_дерева():
    беды = []
    начало = корень()
    if начало is None:
        беды.append(("дерево", "корень не один"))
        return беды
    if len(set(ИМЕНА)) != len(ИМЕНА):
        беды.append(("дерево", "имена узлов не различны"))
    русские = [УЗЕЛ[и][1] for и in ИМЕНА]
    if len(set(русские)) != len(русские):
        беды.append(("дерево", "русские имена не различны"))
    г = глубины()
    if set(г) != set(ИМЕНА):
        беды.append(("дерево", "обход от корня достал не все узлы"))
    for и in ИМЕНА:
        р = УЗЕЛ[и][0]
        if р is not None and р not in УЗЕЛ:
            беды.append(("дерево", f"{и}: родителя {р} нет"))
        if и in г and уровень(и) != г[и]:
            беды.append(("дерево", f"{и}: вверх {уровень(и)} против "
                                   f"вниз {г[и]}"))
        if len(путь_от_корня(и)) - 1 != уровень(и):
            беды.append(("дерево", f"{и}: путь не равен уровню"))
    for a in ИМЕНА:
        вниз = set(потомки(a))
        for b in ИМЕНА:
            if (b in вниз) != (a in предки(b)):
                беды.append(("дерево", f"{a}/{b}: вниз и вверх разошлись"))
    н = номера_обхода()
    if sorted(н.values()) != list(range(1, len(ИМЕНА) + 1)):
        беды.append(("дерево", "номера обхода не суть перестановка"))
    return беды


def _оракул_отношений():
    беды = []
    for имя, _ру, _п in ОТНОШЕНИЯ:
        перебором = (свидетель_рефлексивности(имя) is None,
                     свидетель_симметричности(имя) is None,
                     свидетель_транзитивности(имя) is None)
        if перебором != свойства_алгеброй(имя):
            беды.append(("отношение", f"{имя}: перебор {перебором} против "
                                      f"алгебры {свойства_алгеброй(имя)}"))
        свид = свидетель_транзитивности(имя)
        if свид is not None:
            a, b, c = свид
            if not (стоит(имя, a, b) and стоит(имя, b, c)
                    and not стоит(имя, a, c)):
                беды.append(("отношение", f"{имя}: свидетель не свидетель"))
        if замыкание(имя) != замыкание_составом(имя):
            беды.append(("замыкание", f"{имя}: достижимость против состава"))
        if свидетель_транзитивности(имя) is None and (
                замыкание(имя) != set(пары(имя))):
            беды.append(("замыкание", f"{имя}: транзитивно, а замыкание шире"))
    return беды


def _оракул_классов():
    беды = []
    for м in МОДУЛИ:
        по_ящикам = tuple(sorted(классы(м).values()))
        обходом = классы_обходом(м)
        if по_ящикам != обходом:
            беды.append(("классы", f"модуль {м}: ящики против обхода"))
        собрано = sorted(н for с in обходом for н in с)
        if собрано != sorted(ЧИСЛА):
            беды.append(("классы", f"модуль {м}: разбиение не покрывает"))
        if len(собрано) != len(set(собрано)):
            беды.append(("классы", f"модуль {м}: классы пересекаются"))
        if эквивалентность(м) != (True, True, True):
            беды.append(("классы", f"модуль {м}: не эквивалентность"))
    return беды


def _оракул_соответствий():
    беды = []
    for имя, _ру, _а, _р, _п in СООТВЕТСТВИЯ:
        туда = отображение(имя)
        обратно = обратное(имя)
        for э, з in туда.items():
            if э not in обратно[з]:
                беды.append(("соответствие", f"{имя}: {э} не вернулся"))
        if однозначно(имя):
            if len(обратно) != len(туда):
                беды.append(("соответствие", f"{имя}: счёт не сошёлся"))
            for з, с in обратно.items():
                if туда[с[0]] != з:
                    беды.append(("соответствие", f"{имя}: {з} не вернулось"))
        elif свидетель_однозначности(имя) is None:
            беды.append(("соответствие", f"{имя}: нет свидетеля"))
    return беды


def _оракул_порядков():
    беды = []
    for имя, множество in ПОРЯДКИ:
        if свидетель_рефлексивности(имя, множество) is not None:
            беды.append(("порядок", f"{имя}: не рефлексивен"))
        if свидетель_транзитивности(имя, множество) is not None:
            беды.append(("порядок", f"{имя}: не транзитивен"))
        прямо = set(пары(имя, множество))
        обходом = порядок_обходом(имя, множество)
        if прямо != обходом:
            беды.append(("порядок", f"{имя}: правило против покрытий"))
        for ц in цепи(имя, множество):
            for a, b in zip(ц, ц[1:]):
                if not стоит(имя, a, b):
                    беды.append(("порядок", f"{имя}: цепь {ц} рвётся"))
    return беды


def _оракул_графа():
    беды = []
    for a in УЗЛЫ:
        вп = вперёд(a)
        for b in УЗЛЫ:
            нз = назад(b)
            if вп.get(b) != нз.get(a):
                беды.append(("граф", f"{a}→{b}: вперёд {вп.get(b)} против "
                                     f"назад {нз.get(a)}"))
        for b in УЗЛЫ:
            п = путь(a, b)
            if п is None:
                continue
            if len(п) - 1 != вп.get(b):
                беды.append(("граф", f"{a}→{b}: длина пути не кратчайшая"))
            for u, v in zip(п, п[1:]):
                if not есть_ребро(u, v):
                    беды.append(("граф", f"{a}→{b}: ребра {u}→{v} нет"))
    return беды


def _оракул_пространства():
    беды = []
    for a in УЗЛЫ:
        for b in УЗЛЫ:
            d = расстояние(a, b)
            if d is None:
                беды.append(("пространство", f"{a}/{b}: расстояния нет"))
                continue
            if расстояние(b, a) != d:
                беды.append(("пространство", f"{a}/{b}: не симметрично"))
            if (d == 0) != (a == b):
                беды.append(("пространство", f"{a}/{b}: ноль не на себе"))
            for c in УЗЛЫ:
                через = расстояние(a, c) + расстояние(c, b)
                if d > через:
                    беды.append(("пространство",
                                 f"{a}/{c}/{b}: треугольник нарушен"))
    return беды


def оракул():
    """[(род, беда)] — где два встречных хода разошлись.

    ВСТРОЕННЫЙ ОРАКУЛ ЕСТЬ ФАКТ, ОБЪЯВЛЕННЫЙ ДВАЖДЫ РАЗНЫМИ РУКАМИ, и
    потому здесь не сверяется ни одна запись: сводятся ХОДЫ. Уровень
    вверх против глубины вниз; свидетель против алгебры множеств;
    ящики остатка против связных кусков; правило порядка против
    достижимости по покрытиям; обход вперёд против обхода назад;
    законы расстояния на всех парах и тройках. Показы не имеют права
    родиться, покуда хоть один ход разошёлся со встречным.
    """
    return (_оракул_дерева() + _оракул_отношений() + _оракул_классов()
            + _оракул_соответствий() + _оракул_порядков()
            + _оракул_графа() + _оракул_пространства())
