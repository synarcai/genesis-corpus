# ══════════════════ ДЕРЕВО РОДОВ: ВЛОЖЕННОСТЬ И ИЕРАРХИЯ ══════════════
#
# ДЕРЕВО МАЛО НАРОЧНО, как и дерево документов по соседству: оно должно
# быть ОБОЗРИМО целиком, иначе показы о нём будут о частностях.
# Восемнадцать узлов, пять уровней, семнадцать рёбер. Узел — (имя,
# родитель, русское имя); корень объявлен отсутствием родителя и
# НАХОДИТСЯ ОБХОДОМ, а не записан вторым именем.
#
# ИМЕНА УЗЛОВ ЛАТИНИЦЕЙ И В ОБОИХ ЯЗЫКАХ РАВНО: узел зовётся «stone» и
# в английском показе, и в русском, а «камень» есть ЗНАЧЕНИЕ
# соответствия «имя по-русски», то есть предмет отдельного показа, а не
# второе имя того же узла. Так снимается склонение чужого имени внутри
# русской рамки — тот же ход, каким живёт дерево документов.
ДЕРЕВО = (
    ("thing", None, "вещь"),
    ("body", "thing", "тело"),
    ("sign", "thing", "знак"),
    ("measure", "thing", "мера"),
    ("solid", "body", "твёрдое"),
    ("liquid", "body", "жидкое"),
    ("digit", "sign", "цифра"),
    ("letter", "sign", "буква"),
    ("size", "measure", "размер"),
    ("weight", "measure", "вес"),
    ("stone", "solid", "камень"),
    ("metal", "solid", "металл"),
    ("water", "liquid", "вода"),
    ("oil", "liquid", "масло"),
    ("flint", "stone", "кремень"),
    ("chalk", "stone", "мел"),
    ("iron", "metal", "железо"),
    ("tin", "metal", "олово"),
)
ИМЕНА = tuple(и for и, _р, _ру in ДЕРЕВО)
УЗЕЛ = {и: (р, ру_имя) for и, р, ру_имя in ДЕРЕВО}
ДЕТИ = {и: tuple(д for д, р, _ру in ДЕРЕВО if р == и) for и in ИМЕНА}


def корень():
    """Узел, не лежащий ни в одном узле, — или None, если он не один."""
    без = [и for и in ИМЕНА if УЗЕЛ[и][0] is None]
    return без[0] if len(без) == 1 else None


def предки(узел):
    """ХОД ВВЕРХ: цепь родителей от ближайшего до корня."""
    вон, текущий = [], УЗЕЛ[узел][0]
    while текущий is not None and текущий not in вон:
        вон.append(текущий)
        текущий = УЗЕЛ[текущий][0]
    return tuple(вон)


def потомки(узел):
    """ХОД ВНИЗ: все узлы, лежащие в этом, обходом в ширину."""
    вон, очередь = [], list(ДЕТИ[узел])
    while очередь:
        и = очередь.pop(0)
        if и in вон:
            continue
        вон.append(и)
        очередь.extend(ДЕТИ[и])
    return tuple(вон)


def содержит(верхний, нижний):
    """Лежит ли нижний узел внутри верхнего — ходом ВНИЗ."""
    return нижний in потомки(верхний)


def уровень(узел):
    """ХОД ВВЕРХ: число шагов от узла до корня."""
    return len(предки(узел))


def глубины():
    """ХОД ВНИЗ: глубина каждого узла обходом в ширину от корня."""
    начало = корень()
    if начало is None:
        return {}
    вон, очередь = {начало: 0}, [начало]
    while очередь:
        и = очередь.pop(0)
        for д in ДЕТИ[и]:
            if д not in вон:
                вон[д] = вон[и] + 1
                очередь.append(д)
    return вон


def путь_от_корня(узел):
    """Узлы от корня до этого включительно."""
    return tuple(reversed(предки(узел))) + (узел,)


def листья():
    """Узлы, не содержащие ни одного узла."""
    return tuple(и for и in ИМЕНА if not ДЕТИ[и])


def уровней():
    """Сколько уровней в дереве: от нулевого до самого глубокого."""
    return max(глубины().values()) + 1


def номера_обхода():
    """Номер каждого узла в обходе в глубину, считая с единицы."""
    порядок, стек = [], [корень()]
    while стек:
        и = стек.pop()
        порядок.append(и)
        стек.extend(reversed(ДЕТИ[и]))
    return {и: н for н, и in enumerate(порядок, 1)}


# ══════════════ ОТНОШЕНИЯ НА КОНЕЧНОМ МНОЖЕСТВЕ ═══════════════════════
#
# ОТНОШЕНИЕ ОБЪЯВЛЕНО ПРАВИЛОМ, А ПАРЫ ВЫВОДЯТСЯ ПРОГОНОМ ПРАВИЛА ПО
# МНОЖЕСТВУ. Перечислить пары рукой значило бы объявить один факт
# дважды: и правилом в имени, и списком в теле.
#
# СЕМЬ ОТНОШЕНИЙ ВЗЯТЫ ТАК, ЧТОБЫ КАЖДОЕ СВОЙСТВО ИМЕЛО И
# ПОДТВЕРЖДАЮЩИЙ СЛУЧАЙ, И СЛУЧАЙ-НАРУШИТЕЛЯ: «не больше» рефлексивно и
# транзитивно, но не симметрично; «следующий» не рефлексивен, не
# симметричен и не транзитивен; «сосед» симметричен, но не рефлексивен и
# не транзитивен; «различно» симметрично и НЕ транзитивно (1→2 и 2→1, а
# 1→1 нет) — самый неочевидный из нарушителей; «делит» на этом множестве
# есть порядок, и притом НЕ линейный.
МНОЖЕСТВО = (1, 2, 3, 4)
ОТНОШЕНИЯ = (
    ("at most", "не больше", lambda a, b: a <= b),
    ("equal", "равно", lambda a, b: a == b),
    ("same parity", "та же чётность", lambda a, b: a % 2 == b % 2),
    ("next", "следующий", lambda a, b: b == a + 1),
    ("neighbour", "сосед", lambda a, b: abs(a - b) == 1),
    ("divides", "делит", lambda a, b: b % a == 0),
    ("different", "различно", lambda a, b: a != b),
)
ПРАВИЛО = {и: п for и, _ру, п in ОТНОШЕНИЯ}
ПО_РУССКИ = {ру_имя: и for и, ру_имя, _п in ОТНОШЕНИЯ}
ИМЯ_ПО_РУССКИ = {и: ру_имя for и, ру_имя, _п in ОТНОШЕНИЯ}


def стоит(имя, a, b):
    """Стоит ли пара в отношении — правилом."""
    return bool(ПРАВИЛО[имя](a, b))


def пары(имя, множество=МНОЖЕСТВО):
    """ХОД ВПЕРЁД: правило прогнано по всем парам множества."""
    return tuple((a, b) for a in множество for b in множество
                 if стоит(имя, a, b))


def свидетель_рефлексивности(имя, множество=МНОЖЕСТВО):
    """Элемент, не стоящий к самому себе, — или None."""
    for a in множество:
        if not стоит(имя, a, a):
            return a
    return None


def свидетель_симметричности(имя, множество=МНОЖЕСТВО):
    """Пара, у которой нет обратной, — или None."""
    for a in множество:
        for b in множество:
            if стоит(имя, a, b) and not стоит(имя, b, a):
                return (a, b)
    return None


def свидетель_транзитивности(имя, множество=МНОЖЕСТВО):
    """Тройка a→b, b→c без a→c — или None."""
    for a in множество:
        for b in множество:
            if not стоит(имя, a, b):
                continue
            for c in множество:
                if стоит(имя, b, c) and not стоит(имя, a, c):
                    return (a, b, c)
    return None


def свойства_алгеброй(имя, множество=МНОЖЕСТВО):
    """ВСТРЕЧНЫЙ ХОД: те же три свойства как включения множеств пар.

    Перебор ищет СВИДЕТЕЛЯ нарушения; алгебра сравнивает МНОЖЕСТВА
    целиком и свидетеля не знает вовсе. Два хода отвечают на один
    вопрос, не заглядывая друг в друга.
    """
    R = set(пары(имя, множество))
    диагональ = {(a, a) for a in множество}
    обратное = {(b, a) for a, b in R}
    состав = {(a, c) for a, b in R for b2, c in R if b == b2}
    return (диагональ <= R, обратное == R, состав <= R)


def замыкание(имя, множество=МНОЖЕСТВО):
    """ТРАНЗИТИВНОЕ ЗАМЫКАНИЕ ходом ДОСТИЖИМОСТИ (обход в ширину)."""
    R = set(пары(имя, множество))
    вперёд_из = {a: [b for (x, b) in R if x == a] for a in множество}
    вон = set()
    for a in множество:
        видано, очередь = set(), [a]
        while очередь:
            x = очередь.pop(0)
            for y in вперёд_из[x]:
                if y not in видано:
                    видано.add(y)
                    очередь.append(y)
        вон.update((a, y) for y in видано)
    return вон


def замыкание_составом(имя, множество=МНОЖЕСТВО):
    """ВСТРЕЧНЫЙ ХОД: то же замыкание ПОВТОРНЫМ СОСТАВОМ до покоя."""
    текущее, было = set(пары(имя, множество)), None
    while текущее != было:
        было = set(текущее)
        текущее |= {(a, c) for a, b in было for b2, c in было if b == b2}
    return текущее


def цепь(имя, начало, конец, множество=МНОЖЕСТВО):
    """Кратчайшая цепь ШАГОВ отношения из начала в конец, или None.

    ЦЕПЬ ИЩЕТСЯ ПО ШАГАМ, А НЕ ПО УЗЛАМ. Пара (a, a) стоит в замыкании
    симметричного отношения, не стоя в нём самом («сосед»: 1→2→1), и
    цепь тут есть настоящий круг. Обход, метящий начало посещённым,
    круга не нашёл бы вовсе и объявил бы честную пару беспутной.
    """
    вперёд_из = {a: [b for (x, b) in пары(имя, множество) if x == a]
                 for a in множество}
    очередь, видано = [(начало, (начало,))], set()
    while очередь:
        x, дорога = очередь.pop(0)
        for y in вперёд_из[x]:
            если = дорога + (y,)
            if y == конец:
                return если
            if y in видано:
                continue
            видано.add(y)
            очередь.append((y, если))
    return None


# ══════════════ ЭКВИВАЛЕНТНОСТЬ И КЛАССЫ ══════════════════════════════
#
# РАЗБИЕНИЕ ЕСТЬ СЛЕДСТВИЕ ЭКВИВАЛЕНТНОСТИ, А НЕ ВТОРОЕ ОБЪЯВЛЕНИЕ.
# Объявлены только модули и предел; классы выводятся, их число
# считается, и то же разбиение приходит вторым ходом — обходом связных
# кусков отношения «тот же остаток», который об остатке не спрашивает
# вовсе, а идёт по парам.
МОДУЛИ = (3, 4)
ПРЕДЕЛ = 12
ЧИСЛА = tuple(range(1, ПРЕДЕЛ + 1))


def остаток(число, модуль):
    return число % модуль


def классы(модуль, числа=ЧИСЛА):
    """ХОД ФУНКЦИЕЙ: числа разложены по ящикам остатка."""
    вон = {}
    for н in числа:
        вон.setdefault(остаток(н, модуль), []).append(н)
    return {о: tuple(с) for о, с in sorted(вон.items())}


def классы_обходом(модуль, числа=ЧИСЛА):
    """ВСТРЕЧНЫЙ ХОД: класс есть СВЯЗНЫЙ КУСОК отношения.

    Ход функцией кладёт число в ящик ПО КЛЮЧУ — по его остатку. Ход
    обходом ключа не вычисляет ни разу: он идёт от числа по парам
    отношения «разность делится на модуль», пока идётся, и берёт
    найденное куском. Совпадение двух разбиений и есть проверка того,
    что отношение действительно эквивалентность: у неэквивалентного
    связные куски с ящиками не сошлись бы.
    """
    родня = {н: [м for м in числа if (н - м) % модуль == 0] for н in числа}
    остались, вон = list(числа), []
    while остались:
        начало = остались[0]
        кусок, очередь = set(), [начало]
        while очередь:
            x = очередь.pop(0)
            if x in кусок:
                continue
            кусок.add(x)
            очередь.extend(родня[x])
        вон.append(tuple(sorted(кусок)))
        остались = [н for н in остались if н not in кусок]
    return tuple(sorted(вон))


def эквивалентность(модуль, числа=ЧИСЛА):
    """(рефлексивно, симметрично, транзитивно) для «тот же остаток»."""
    равно = ((a, b) for a in числа for b in числа)
    R = {(a, b) for a, b in равно if остаток(a, модуль) == остаток(b, модуль)}
    диагональ = {(a, a) for a in числа}
    обратное = {(b, a) for a, b in R}
    состав = {(a, c) for a, b in R for b2, c in R if b == b2}
    return (диагональ <= R, обратное == R, состав <= R)


