#!/usr/bin/env python3
"""ДОМ РАЗМЕТКИ: конструкция объявляет ЗАПИСЬ и ЧТЕНИЕ, и они обратимы.

Разметка лежала в корпусе ПРЕДМЕТОМ ПОКАЗА — девять форм из тридцати
девяти, показанных как строки, о которых говорят. Но разметка есть
ЗАПИСЬ, а у корпуса уже есть закон записи: ЗАПИСЬ ПОНИЖАЕТСЯ В ЗАПИСЬ
(словесная арифметика → LaTeX → глифы). Markdown встаёт в ту же
лестницу, и тогда у него появляется то, чего нет у показа: ОБРАТНЫЙ ХОД.

ВСТРОЕННЫЙ ОРАКУЛ ЕСТЬ САМА ОБРАТИМОСТЬ. Конструкция объявляет, как
её ПИСАТЬ (из полей — строка) и как её ЧИТАТЬ (из строки — поля); ни
одна из двух записей не выводится из другой, и потому их согласие есть
настоящая проверка, а не пересказ. Конструкция, чьё чтение не
возвращает написанного, не выпускается в корпус вовсе — ошибка в
грамматике формата становится НЕВОЗМОЖНОЙ, а не обнаружимой.

ПРИБАВИТЬ КОНСТРУКЦИЮ — ЗНАЧИТ ОБЪЯВИТЬ ЧЕТВЁРКУ: образец чтения,
сборку записи, смысл на двух языках и случаи для показа. Ни строки
обхода. Тем же способом прибавляется НОВЫЙ ФОРМАТ: семья есть поле
конструкции, и JSON, YAML, BibTeX, mermaid лягут сюда же — грамматика
объявляется, а не пишется кодом.

СЕМЬИ: commonmark (ядро), gfm (расширения GitHub), mdx (Docusaurus и
MDX). Структура документа — относительные ссылки, якоря, дерево — есть
ОТДЕЛЬНЫЙ РОД: она судится не строкой, а графом, и живёт своим домом.
"""

import re

# (имя, семья, образец чтения, сборка записи, смысл_en, смысл_ru, случаи)
# «случаи» берут шаг и возвращают список словарей полей.
_К = []


def конструкция(имя, семья, образец, собрать, смысл_en, смысл_ru,
                случаи):
    _К.append((имя, семья, re.compile(образец, re.S), собрать,
               смысл_en, смысл_ru, случаи))


def все():
    return tuple(_К)


def читать(имя, текст):
    """Поля конструкции из её записи, или None."""
    for и, _с, образец, *_ in _К:
        if и != имя:
            continue
        м = образец.fullmatch(текст)
        return dict(м.groupdict()) if м else None
    return None


def писать(имя, поля):
    for и, _с, _о, собрать, *_ in _К:
        if и == имя:
            return собрать(поля)
    return None


# ------------------------------------------------------------- ЯДРО

# СЛОВА БЕРУТСЯ ИЗ ДОМА ПАР, А НЕ ЗАВОДЯТСЯ ЗДЕСЬ. Первая редакция
# выписала двадцать слов своей рукой — и суд разметки объявил ложью две
# с половиной тысячи строк, ибо у корпуса ЕСТЬ закон: слово в заголовке
# или пункте взято из объявленного набора, а слово вне его есть ДРЕЙФ.
# Закон верен, а свод был неправ: словарь у корпуса один.
import lexicon  # noqa: E402
import rugram  # noqa: E402

_ПАРЫ = tuple((англ[0], рус) for рус, англ in lexicon.ПАРЫ)
_СЛОВА = tuple(а for а, _р in _ПАРЫ)


_РУС = {а: (р, rugram.род(р)) for а, р in _ПАРЫ}

_ЧИСЛОМ_EN = ("one", "two", "three", "four", "five", "six")
_ЧИСЛОМ_RU = ("один", "два", "три", "четыре", "пять", "шесть")


def слово(шаг, i=0):
    return _СЛОВА[(шаг * 3 + i) % len(_СЛОВА)]


def уровень_слова(с):
    """Уровень заголовка, закреплённый ЗА СЛОВОМ, а не за случаем.

    У КОРПУСА УЖЕ ЕСТЬ ЗАКОН: слово, объявленное заголовком одного
    уровня, не может стоять заголовком другого — суд разметки зовёт
    это противоречием, и правильно: в ДОКУМЕНТЕ так и есть. Каталог
    синтаксиса, показывающий одно слово на шести уровнях, нарушал бы
    закон ради удобства показа. Уровень закреплён за словом, и всякий
    показ заголовка — какой бы конструкцией он ни делался — берёт
    уровень отсюда.
    """
    return (_СЛОВА.index(с) % 6) + 1


def слова_уровня(*уровни):
    return [с for с in _СЛОВА if уровень_слова(с) in уровни]


def ру(с):
    """Русское слово в именительном."""
    return _РУС[с][0]


def род(с):
    return _РУС[с][1]


def полное(основа, с):
    """Прилагательное, согласованное с родом слова: «жирный свет»."""
    return rugram.полное(основа, ру(с))


def краткое(основа, с):
    """Краткая форма, согласованная с родом: «вложена», «вложено»."""
    return rugram.краткое(основа, ру(с))


