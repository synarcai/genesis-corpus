def оракул():
    """[(имя, случай)] — конструкции, чьё чтение не вернуло записи.

    ЭТО И ЕСТЬ ВСТРОЕННЫЙ ОРАКУЛ ДОМА. Пустой список значит, что каждая
    объявленная конструкция обратима на каждом своём случае; всё, что
    сюда попало, не имеет права выйти в корпус.
    """
    беды = []
    for имя, _семья, образец, собрать, _en, _ru, случаи in _К:
        for шаг in range(5):
            for поля in случаи(шаг):
                текст = собрать(поля)
                м = образец.fullmatch(текст)
                if м is None:
                    беды.append((имя, текст, "не читается"))
                    continue
                назад = м.groupdict()
                for к, з in поля.items():
                    if з is not None and назад.get(к) != з:
                        беды.append((имя, текст,
                                     f"{к}: {з!r} → {назад.get(к)!r}"))
    return беды
