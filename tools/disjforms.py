ЯЗЫКИ = tuple(РАМКИ)
ФОРМЫ = ("ряд", "исключение", "вопрос_исключения")


def _соединить(числа, соединитель, последний, перед=""):
    """«0, 1, 2, 3 или 4» — последний член присоединяется СВОИМ словом языка.

    ЧАСТИЦА ОТРИЦАНИЯ ПОВТОРЯЕТСЯ ПРИ КАЖДОМ ЧЛЕНЕ ИЛИ СТОИТ ОДНАЖДЫ, и это
    строй языка, а не выбор: русское «не 0, не 1 и не 4» повторяет частицу,
    немецкое «weder 0 noch 1 noch 4» ставит зачин однажды, английское «none of
    0, 1 and 4» — тоже. Оттого «один_перед» объявлен у тех языков, где он
    таков, и не выведен ниоткуда.
    """
    числа = [str(ч) for ч in числа]
    if len(числа) == 1:
        return перед + числа[0]
    хвост = соединитель.join(перед + ч for ч in числа[:-1]) + последний + перед + числа[-1]
    return хвост


def страница(язык, форма, i):
    n, d = СЛУЧАИ[i % len(СЛУЧАИ)]
    r = n % d
    ряд_чисел = list(range(d))
    лишние = [ч for ч in ряд_чисел if ч != r]
    я = РАМКИ[язык]
    ряд = _соединить(ряд_чисел, ", ", я["или"])
    if я.get("один_перед"):
        нет = я["перед"] + _соединить(лишние, я["соед"], я["послед"])
    else:
        нет = _соединить(лишние, я["соед"], я["послед"], перед=я["перед"])
    нет_голый = _соединить(лишние, ", ", я["и"])
    if форма == "ряд":
        return я["ряд"].format(n=n, d=d, ряд=ряд)
    исключение = я["исключение"].format(n=n, d=d, ряд=ряд, нет=нет, r=r)
    if форма == "исключение":
        return исключение
    return я["вопрос"].format(n=n, d=d, голый=нет_голый) + " " + исключение


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for форма in ФОРМЫ:
            for i in range(len(СЛУЧАИ)):
                вон[страница(язык, форма, i)] = (язык, форма)
    return вон


ПОКАЗЫ = _показы()


def main():
    поймано = 0
    for язык in ЯЗЫКИ:
        print(f"  {язык}: {страница(язык, 'исключение', 0)}")
        n, d = СЛУЧАИ[0]
        плохой = РАМКИ[язык]["исключение"].format(
            n=n, d=d, ряд=_соединить(range(d), ", ", РАМКИ[язык]["или"]),
            нет=РАМКИ[язык]["перед"] + "0", r=(n % d) + 1)  # вывод не тот остаток
        поймано += 0 if плохой in ПОКАЗЫ else 1
    print(f"  мутантов вне показов: {поймано} из {len(ЯЗЫКИ)}")
    print(f"  дом пишет показов: {len(ПОКАЗЫ)} (языков {len(ЯЗЫКИ)}, случаев {len(СЛУЧАИ)}, форм {len(ФОРМЫ)})")
    return 0


