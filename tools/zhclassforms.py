#     читающий по образцу.
#
# Второй закон дома потому таков: цитата, несущая хоть один НЕОБЪЯВЛЕННЫЙ кусок, ложна сама
# по себе, распознан в ней образец или нет. Письмо здесь без пробелов, и «кусок» отрезается
# ДЛИННЕЙШИМ СОВПАДЕНИЕМ с объявленным: иначе имя из двух знаков разошлось бы на два куска.
_ОБЪЯВЛЕНО = tuple(sorted(
    ({ч for ч, _, _, _ in ЧИСЛА} | {с for _, с, *_ in ИМЕНА} | {и for и, *_ in ИМЕНА}),
    key=len, reverse=True))


# ЦИТАТА СОСЕДА НЕ ЕСТЬ ЦИТАТА ЯЗЫКА ДОМА. Дом берёт в ёлочки и русскую, и английскую речь
# («пять машин», «five cars»), и требовать от неё китайской таблицы значило бы звать ложью
# верное. Проверяется цитата, В КОТОРОЙ ЕСТЬ ХОТЬ ОДИН ЗНАК ХАНЬ, — и проверяется ЦЕЛИКОМ.
_ХАНЬ = _re.compile(r"[\u3400-\u9fff]")


def _чужое_в_цитате(тело):
    """Кусок китайской цитаты, не объявленный таблицей дома, — либо None."""
    if not _ХАНЬ.search(тело):
        return None
    хвост = тело.lstrip("*")
    while хвост:
        for кусок in _ОБЪЯВЛЕНО:
            if хвост.startswith(кусок):
                хвост = хвост[len(кусок):]
                break
        else:
            return хвост[0]
    return None


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        if _чужое_в_цитате(цитата) is not None:
            return True, False
        if not _ТРОЙКА.search(цитата.lstrip("*")):
            continue
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:110])
            беды += 1
    мутантов = 0
    for показ in ПОКАЗЫ:
        порча = None
        for сч in sorted(_ВСЕ_СЧЁТНЫЕ):
            if сч in показ:
                чужое = next(с for с in sorted(_ВСЕ_СЧЁТНЫЕ) if с != сч)
                порча = показ.replace(сч, чужое, 1)
                break
        if not порча or порча == показ or порча in ПОКАЗЫ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:110])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    # ЛОЖНЫЕ СТРАНИЦЫ БЕРУТСЯ ИЗ ИМЁН, КОТОРЫЕ ДОМ ЗНАЕТ (12.09, поймано своей же пробой).
    # Первая редакция брала «一本笔» — отказ из пласта свода, — а «笔» (ручка) в таблицу дома
    # не входит: признак её не знает, и ложь прошла зелёной.
    #
    #     ЛОЖНАЯ СТРАНИЦА, ПОСТРОЕННАЯ НА СЛОВЕ ВНЕ ТАБЛИЦЫ, ПРОВЕРЯЕТ НЕ ЗАКОН, А ГРАНИЦУ
    #     ТАБЛИЦЫ — и проходит по той же причине, по какой суд молчит о чужой речи.
    ложные = (
        "по-китайски «一本猫» — одна кошка.",
        "по-китайски «三本猫» — три кошки.",
        "по-китайски «三书» — три книги.",
        "«*三本书» — так не говорят.",
    )
    for ложь in ложные:
        ПОКАЗЫ[ложь] = ("ru", "проба")
        try:
            if судить(ложь) != (True, False):
                print("  ЛОЖНАЯ СТРАНИЦА ПРОШЛА:", ложь[:100])
                беды += 1
        finally:
            del ПОКАЗЫ[ложь]
    написано = {род for _, род in ПОКАЗЫ.values()}
    if написано != set(РОДЫ):
        print(f"  РОДЫ РАЗОШЛИСЬ: обещано {sorted(РОДЫ)}, написано {sorted(написано)}")
        беды += 1
    for чужая in ("字典里有三本书，这不是这个家的一页。",
                  "он выписал «三本书» на поля, и это не страница дома."):
        if судить(чужая) != (False, False):
            print("  ЧУЖАЯ РЕЧЬ СУДИМА:", чужая[:100])
            беды += 1
    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, мутантов поймано {мутантов}, "
          f"имён {len(ИМЕНА)}, счётных {len(_ВСЕ_СЧЁТНЫЕ)}, бед {беды}")
    return беды


if __name__ == "__main__":
    sys.exit(1 if _самопроверка() else 0)
