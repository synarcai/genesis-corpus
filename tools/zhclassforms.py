def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _нарушает(тело):
    """Нарушает ли цитата закон дома: чужое счётное или его отсутствие."""
    # ОДНА ПРОВЕРКА ВМЕСТО ДВУХ, И ЭТО СНЯТО ПРОБОЙ ПРОБЫ (12.09). Прежде здесь стояла
    # отдельная ветвь «если счётного нет вовсе — нарушение», и порча, снимавшая её,
    # оставляла пробу зелёной: сравнение с таблицей ловит тот же случай, ибо пустая строка
    # не равна ни одному объявленному счётному.
    #
    #     ВЕТВЬ, ПРИ УДАЛЕНИИ КОТОРОЙ НИЧЕГО НЕ МЕНЯЕТСЯ, ЕСТЬ УКРАШЕНИЕ, И ЧИТАЕТСЯ ОНА
    #     ХУЖЕ, ЧЕМ ОТСУТСТВУЕТ: за нею мерещится закон, которого нет.
    for _чис, сч, имя in _ТРОЙКА.findall(тело.lstrip("*").strip()):
        if _СЧЁТНОЕ.get(имя) != сч:
            return True                      # чужое счётное — или его нет вовсе
    return False


