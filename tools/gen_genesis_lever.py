#!/usr/bin/env python3
"""КОВКА ДОМА РЫЧАГА.

РАВНОВЕСИЕ И ПЕРЕВЕС ИДУТ В ОДНОМ ПРОХОДЕ: они суть минимальная пара — одно число иное, и
вердикт иной. ГРУЗ И ПЛЕЧО идут своей парой: числа те же, неизвестное переставлено. ОБРАТНО
идёт отдельно: это единственный род, где сказан СМЫСЛ закона, а не только его счёт, и рядом с
вычислениями он читался бы шестым способом умножить.

Группы берутся у самих показов, а не у объявленного списка: первый заход дома вероятности
резал их по таблице пар и молча терял целый род.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import leverforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_lever.txt"
ГРУППЫ = (("равновесие", "перевес"), ("груз", "плечо"), ("обратно",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
