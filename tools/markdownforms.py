#!/usr/bin/env python3
"""ДОМ РАЗМЕТКИ — запись, её смысл и вопрос о ней, в трёх договорах.

Мир `markdown` (3 428 строк) был вторым по величине бездомным миром свода: страницы его писала
кузница безымянным потоком, и сайдкар родов не мог назвать ни одной.

    МИР, ЧЬИ СТРАНИЦЫ НЕ НАЗВАНЫ РОДОМ, ЧИТАЕТСЯ ТОЛЬКО ТЕМ, КТО ЧИТАЕТ КУЗНИЦУ.

РОД ЗДЕСЬ ДВУМЕРЕН, И ОБА ИЗМЕРЕНИЯ БЫЛИ В КУЗНИЦЕ С ПЕРВОГО ДНЯ:

    СЕМЬЯ       commonmark · gfm · mdx — ТРИ РАЗНЫХ ДОГОВОРА, а не три части одного;
                кузница и прежде не мешала их, отдавая каждую своей группой.
    ПОВЕРХНОСТЬ запись · смысл · вопрос · код-блок · русская запись.

Имя рода их соединяет («gfm: вопрос»), и это не украшение: вопрос о зачёркивании из gfm и
вопрос о выделении из commonmark суть вопросы о РАЗНЫХ договорах, и читатель, купивший один,
не вправе считать, что купил другой.

    РАЗДЕЛЯЯ ВЕЛИКАНА, ЛЕГКО СЛОЖИТЬ НОВОГО: род «вопрос обо всём» есть тот же великан,
    только собранный по ФОРМЕ РЕЧИ вместо ПРЕДМЕТА.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import markdown as md  # noqa: E402

СЕМЬИ = ("commonmark", "gfm", "mdx")
# ПОВЕРХНОСТЕЙ ПЯТЬ, И РОДОМ НИ ОДНА ИЗ НИХ НЕ СТАЛА: запись, смысл, вопрос, код-блок и
# русская запись говорят об ОДНОМ предмете — о конструкции, — и род у них общий.
ПОВЕРХНОСТИ = ("запись", "смысл", "вопрос", "код-блок", "русская запись")

ВОПРОС = {"en": "what does «{запись}» mean?",
          "ru": "что значит «{запись}»?"}
# У МНОГОСТРОЧНОЙ КОНСТРУКЦИИ ВОПРОС КЛЮЧИТСЯ НА ЗАЧИН, А НЕ НА ВЕСЬ
# БЛОК. Корпус построчен, и вопрос, вобравший перевод строки, распался
# бы на несколько строк, из которых ни одна не была бы показом.
# Зачин при этом и есть то, что различает конструкции глазом: «:::note»,
# «---», «```mermaid» узнаются по первой строке.
ВОПРОС_БЛОКА = {"en": "what does a block opening with «{зачин}» mean?",
                "ru": "что значит блок, начатый с «{зачин}»?"}


def _ключ(запись, ответ):
    """Чем вопрос называет предмет: цитатой из ОТВЕТА, иначе записью."""
    if "\n" in запись:
        return {"зачин": запись.split("\n")[0]}
    м = re.search(r"«(.+?)»", ответ)
    return {"запись": м.group(1) if м else запись}


def поверхности(семья, шаг):
    """[(запись, [поверхности])] — показы семьи с их ЗАПИСЬЮ рядом.

    Запись отдаётся вместе с поверхностями нарочно: суду нужно знать, О
    ЧЁМ говорит предложение, чтобы сосчитать притязание САМОМУ. Не всякое
    предложение цитирует свою запись («текст, подчёркнутый знаками
    равенства, …» её не несёт), и суд, вынимавший запись из кавычек,
    оставался без предмета счёта.
    """
    вон = []
    for имя, своя, _обр, собрать, смысл_en, смысл_ru, случаи in md.все():
        if своя != семья:
            continue
        for поля in случаи(шаг):
            запись = собрать(поля)
            ен, ру = смысл_en(поля), смысл_ru(поля)
            # ВОПРОС ЦИТИРУЕТ ТУ ЖЕ ЗАПИСЬ, ЧТО И ЕГО ОТВЕТ. Русский
            # ответ о стиле цитирует РУССКУЮ запись («*вода*»), и
            # вопрос, спрашивавший английскую, разошёлся бы с ним в
            # первой же строке — тот же шрам, что «что даёт вычитание 4
            # и 2?» при ответе «вычитание 2 из 4». Запись берётся ИЗ
            # ОТВЕТА, а не из полей.
            шаблон = (ВОПРОС_БЛОКА if "\n" in запись else ВОПРОС)
            # СОДЕРЖИМОЕ ОГРАДЫ ОБЪЯВЛЯЕТСЯ — тем же оборотом, каким
            # его объявляет старый слой разметки. Код, которого никто
            # не объявлял, есть дрейф той же природы, что заголовок без
            # уровня; закон не мой, и второго оборота ему не нужно.
            # У СТИЛЯ ЕСТЬ И РУССКАЯ ЗАПИСЬ. Разметка обнимает слово
            # любого языка, и русское предложение цитирует русскую
            # запись; она обязана быть в слое МАТЕРИАЛОМ, а не только
            # внутри предложения о ней.
            близнец = []
            поле = поля.get("текст") or поля.get("код")
            if имя in ("emphasis", "strong", "strikethrough",
                       "code_span") and поле:
                близнец = [собрать({**поля,
                                    ("код" if имя == "code_span"
                                     else "текст"): md.ру(поле)})]
            блок = []
            if запись.startswith("```") and запись.count("\n") == 2:
                тело = запись.split("\n")[1]
                блок = [f"a code block of one line: {тело}",
                        f"код-блок из одной строки: {тело}"]
            # РОД ЕСТЬ КОНСТРУКЦИЯ, А НЕ ПОВЕРХНОСТЬ (13.09, замер до и после).
            #
            # Первая редакция дома звала родом ПОВЕРХНОСТЬ («commonmark: смысл»), и вышло
            # тринадцать родов с перекосом в 80 раз: 638 страниц смысла против восьми
            # код-блоков mdx, — а [ОБЕЩАНИЕ ДОМА] нашло род ниже закона массы. Замер второй
            # редакции: род по КОНСТРУКЦИИ даёт 33 рода, перекос 2,0× и НИ ОДНОГО ниже девяти.
            #
            #     СТРАНИЦА ГОВОРИТ О ТОМ, ЧТО В НЕЙ НАПИСАНО, А НЕ О ТОМ, КАКОЙ ФРАЗОЙ ЭТО
            #     СКАЗАНО: запись, её смысл и вопрос о ней суть три поверхности ОДНОГО
            #     предмета, и род у них один — сама конструкция.
            род = f"{семья}: {имя}"
            меченые = [(с, род) for с in
                       блок + близнец
                       + [запись, ен, ру,
                          f"{шаблон['en'].format(**_ключ(запись, ен))} {ен}",
                          f"{шаблон['ru'].format(**_ключ(запись, ру))} {ру}"]]
            вон.append((запись, меченые))
    return вон


def показы_семьи(семья, шаг):
    """Только поверхности, без записи и без метки рядом — ровно то, чем кормится кузница."""
    return [с for _з, стр in поверхности(семья, шаг) for с, _р in стр]

def группы(шаг):
    """[[страница]] — одна группа на СЕМЬЮ, как кормит `emit_grouped`."""
    return [показы_семьи(с, шаг) for с in СЕМЬИ]


def перебор(шаг):
    """[(страница, «семья: поверхность»)] — род взят У СТРОИТЕЛЯ, до всякой пересборки."""
    вон = []
    for семья in СЕМЬИ:
        for _з, стр in поверхности(семья, шаг):
            вон.extend(стр)
    return вон


def _показы():
    """{строка свода: род} — ПОСТРОЧНО: конструкции разметки бывают многострочны.

        МЕРА, ЧИТАЮЩАЯ СТРОКУ, НЕ НАЙДЁТ ИМЕНИ, ПОЛОЖЕННОГО ПОД ПОКАЗ: строка и показ суть
        разные единицы, и словарь обязан говорить на языке того, кто его читает.
    """
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            for строка in с.split("\n"):
                if строка.rstrip():
                    вон.setdefault(строка.rstrip(), род)
    return вон


ПОКАЗЫ = _показы()

РОДЫ = tuple(sorted({р for р in ПОКАЗЫ.values()}))

ЗАЧЕМ_РОДА = {
    р: (f"конструкция «{р.split(': ')[1]}» договора {р.split(': ')[0]}: её запись, её смысл "
        f"и вопрос о ней") for р in РОДЫ
}


def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, а не с кортежем."""
    assert all(isinstance(р, str) for р in РОДЫ), "РОДЫ обязаны быть рядом ИМЁН"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    из_прохода = {р for _с, р in перебор(0)}
    assert из_прохода <= set(РОДЫ), f"роды вне объявления: {sorted(из_прохода - set(РОДЫ))}"
    из_перебора = sorted(с for с, _р in перебор(0))
    из_групп = sorted(с for г in группы(0) for с in г)
    assert из_перебора == из_групп, (
        f"пересборка потеряла или выдумала страницы: перебор {len(из_перебора)}, "
        f"группы {len(из_групп)}")


_самопроверка()
