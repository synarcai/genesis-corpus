#!/usr/bin/env python3
"""СТЕНОГРАММЫ ИНТЕРАКТИВА v0 — действие → отклик среды, среда — сетка.

Форма объявлена договором declarations/STENOGRAM.md; среда — сетка
пространственного мира, исполнители — дом tools/spacegrid.py, тот же,
что у суда. Стенограмма есть ОДИН ПОКАЗ В НЕСКОЛЬКО СТРОК: заголовок,
шаги «действие → отклик», конец. Отклик выведен исполнением, не вписан;
отказ среды показан там, где действие невозможно (клетка вне сетки), —
среда отвечает отказом, а не молчит. Двадцать стенограмм на проход,
длина 2–5 шагов, действия — по остаткам от номера прохода и показа.
"""
import bilang  # noqa: E402 — язык показа по азбуке
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
# ВВОЗ ИДЁТ В ДОМ, А НЕ В КУЗНИЦУ, ИЗ КОТОРОЙ ДОМ ВЫЕХАЛ (14.09): сетка пространства
# переехала в `spaceforms`.
import spaceforms as П  # noqa: E402
import spacegrid as S  # noqa: E402
from layer import Сбор, emit  # noqa: E402

ЦЕЛЬ = "datasets/genesis_stenogram.txt"
СТОРОНЫ = (("right", "вправо"), ("left", "влево"), ("down", "вниз"), ("up", "вверх"))
ОСИ = (("left-right", "слева направо"), ("top-bottom", "сверху вниз"))


СДВИГ = "шаг: сдвиг сетки на клетку"
ПОВОРОТ = "шаг: поворот сетки на угол"
ОТРАЖЕНИЕ = "шаг: отражение сетки по оси"
ЗАКРАСКА = "шаг: закрасить пустую клетку"
СТИРАНИЕ = "шаг: стереть закрашенную клетку"
ВНЕ_СЕТКИ = "отказ среды: клетка вне сетки, и причина названа"


def действие(состояние, шаг, i, j, ru):
    """(текст, новое состояние или None, текст отказа, РОД действия).

    ПЕРЕМЕННАЯ, НАЗВАННАЯ `род`, И ЕСТЬ РОД (14.09): шесть ветвей этого выбора суть шесть
    разных дел над сеткой, и своду о них не говорил никто. Сдвиг, поворот, отражение,
    закраска, стирание и выход за край — разные умения, и учатся они порознь.
    """
    n = len(состояние)
    род = (шаг + i * 3 + j * 5) % 6
    if род == 0:
        en, р = СТОРОНЫ[(шаг + j) % 4]
        k = 1
        return ((f"сдвиг {р} на {k}" if ru else f"shift {en} by {k}"),
                S.сдвиг(состояние, en, k), None, СДВИГ)
    if род == 1:
        угол = (90, 180, 270)[(шаг + j) % 3]
        return ((f"поворот на {угол}° по часовой стрелке" if ru else
                 f"rotate {угол}° clockwise"), S.поворот(состояние, угол), None, ПОВОРОТ)
    if род == 2:
        en, р = ОСИ[(шаг + j) % 2]
        return ((f"отражение {р}" if ru else f"reflect {en}"),
                S.отражение(состояние, en), None, ОТРАЖЕНИЕ)
    r, c = 1 + (шаг + i + j) % n, 1 + (шаг * 2 + j) % n
    if род == 5 and (i + j) % 3 == 0:
        r = n + 1                       # клетка вне сетки — среда откажет
        return ((f"закрасить ({r}, {c})" if ru else f"paint ({r}, {c})"), None,
                (f"клетка ({r}, {c}) вне сетки" if ru
                 else f"cell ({r}, {c}) is outside the grid"), ВНЕ_СЕТКИ)
    закрасить = род in (3, 5)
    # КРАСИТСЯ ПУСТАЯ, СТИРАЕТСЯ ЗАКРАШЕННАЯ: действие без следа в отклике
    # учит, что среда не отвечает; клетка берётся из тех, где след будет.
    годные = [(rr + 1, cc + 1) for rr in range(n) for cc in range(n)
              if (состояние[rr][cc] == S.ПУСТО) == закрасить]
    if годные:
        r, c = годные[(шаг + i * 3 + j) % len(годные)]
    ряд = list(состояние[r - 1])
    ряд[c - 1] = "#" if закрасить else S.ПУСТО
    новое = list(состояние)
    новое[r - 1] = "".join(ряд)
    return (((f"закрасить ({r}, {c})" if закрасить else f"стереть ({r}, {c})") if ru else
             (f"paint ({r}, {c})" if закрасить else f"erase ({r}, {c})")), новое, None,
            ЗАКРАСКА if закрасить else СТИРАНИЕ)


# СТЕНОГРАММА МНОГОСТРОЧНА, И РОД ЕЁ СТРОК РАЗНЫЙ (14.09). Обычай дома даёт роду показ
# целиком, а здесь один показ несёт заголовок, два-пять шагов и конец, и дело у них разное:
# заголовок объявляет длину и начальную сетку, шаг несёт «состояние → действие → отклик»,
# отказ несёт причину вместо новой сетки, конец закрывает эпизод точкой. Оттого `Сбор`
# собирает СТРОКИ, а кузница сшивает их переводом строки — один обход, два чтения.
ЗАГОЛОВОК = "заголовок стенограммы: длина и начальная сетка"
КОНЕЦ = "конец стенограммы: последняя сетка с точкой"


def стенограмма(шаг, i):
    ru = (шаг + i) % 2 == 1
    состояние = П.сетка(шаг, i + 100)
    шагов = 2 + (шаг + i) % 4
    строки = Сбор(ЗАГОЛОВОК)
    строки.append(f"стенограмма {шагов} на сетке {S.записать(состояние)}" if ru else
                  f"transcript {шагов} on grid {S.записать(состояние)}")
    последнее = S.записать(состояние)
    for j in range(1, шагов + 1):
        # СТРОКА ШАГА САМОДОСТАТОЧНА (holon, e9: «строка = эпизод»): она несёт
        # состояние среды ДО действия, действие и отклик; читатель судит её
        # без соседей, а слой суда лишь сверяет непрерывность цепи.
        вход = S.записать(состояние)
        текст, новое, отказ, род_шага = действие(состояние, шаг, i, j, ru)
        if новое is None:
            # ОТКАЗ СРЕДЫ — ФОРМОЙ ОТКАЗА КОРПУСА («no: …» / «нет: …»), чтобы
            # суд манифеста видел объявленный акт отказа теми же глазами.
            отклик = f"нет: {отказ}" if ru else f"no: {отказ}"
            строки.род = род_шага
        else:
            состояние = новое
            последнее = S.записать(новое)
            отклик = f"сетка {последнее}" if ru else f"grid {последнее}"
            строки.род = род_шага
        строки.append((f"шаг {j} на сетке {вход}: действие «{текст}» → отклик: {отклик}") if ru else
                      (f"step {j} on grid {вход}: action «{текст}» → response: {отклик}"))
    # КОНЕЦ — С ТОЧКОЙ, ШАГИ — БЕЗ: у читателя свода (e9) строка закрывает
    # эпизод лишь концевым знаком или швом; шаги без точки остаются в
    # эпизоде своей стенограммы, точка конца его закрывает.
    строки.род = КОНЕЦ
    строки.append(f"конец: сетка {последнее}." if ru else f"end: grid {последнее}.")
    return строки


def pass_shows(шаг):
    return ["\n".join(стенограмма(шаг, i)) for i in range(20)]


# --------------------------------------------------------------- ОБЪЯВЛЕНИЕ ДОМА

РОДЫ = (ЗАГОЛОВОК, СДВИГ, ПОВОРОТ, ОТРАЖЕНИЕ, ЗАКРАСКА, СТИРАНИЕ, ВНЕ_СЕТКИ, КОНЕЦ)

ЗАЧЕМ_РОДА = {
    ЗАГОЛОВОК: "«стенограмма 3 на сетке …»: длина цепи и её начало",
    СДВИГ: "строка-эпизод самодостаточна: среда ДО действия, сдвиг, новая сетка",
    ПОВОРОТ: "поворот на 90°, 180° или 270° по часовой стрелке",
    ОТРАЖЕНИЕ: "отражение по объявленной оси",
    ЗАКРАСКА: "красится ПУСТАЯ клетка: действие без следа в отклике учило бы, что среда "
              "не отвечает",
    СТИРАНИЕ: "стирается ЗАКРАШЕННАЯ клетка — по тому же закону следа",
    ВНЕ_СЕТКИ: "«нет: …» формой отказа корпуса — среда не приняла действия, и сказано "
               "почему",
    КОНЕЦ: "точка закрывает эпизод: шаги идут без неё, конец — с нею",
}


def страницы(шаг):
    return pass_shows(шаг)


def перебор_страниц(шаг):
    """[(строка, род)] ПОСТРОЧНО: показ здесь многострочен, а роды строк розны."""
    return [п for i in range(20) for п in стенограмма(шаг, i).парами]


def группы(шаг):
    return [страницы(шаг)]


def _показы():
    from layer import PASSES                             # noqa: PLC0415
    вон = {}
    for ш in range(len(PASSES)):
        for с, род in перебор_страниц(ш):
            if с.rstrip():
                вон.setdefault(с.rstrip(), (bilang.азбукой(с.rstrip()), род))
    return вон


ПОКАЗЫ = _показы()

# ЯЗЫК ПОКАЗА НАЗВАН ПЕРВЫМ, РОД — ВТОРЫМ: так читает прибор щербатости.
РОД_В_ПОКАЗЕ = 1


def _самопроверка_дома():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    # СШИТЫЙ ПОКАЗ И ПОСТРОЧНЫЙ ПЕРЕБОР — ОДИН ОБХОД, И ЭТО ПРОВЕРЯЕТСЯ.
    сшито = "\n".join(pass_shows(0))
    построчно = "\n".join(с for с, _р in перебор_страниц(0))
    if сшито != построчно:
        raise AssertionError("перебор строк разошёлся со сшитыми показами")
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка_дома()


def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
