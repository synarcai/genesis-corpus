#!/usr/bin/env python3
"""СТЕНОГРАММЫ ИНТЕРАКТИВА v0 — действие → отклик среды, среда — сетка.

Форма объявлена договором declarations/STENOGRAM.md; среда — сетка
пространственного мира, исполнители — дом tools/spacegrid.py, тот же,
что у суда. Стенограмма есть ОДИН ПОКАЗ В НЕСКОЛЬКО СТРОК: заголовок,
шаги «действие → отклик», конец. Отклик выведен исполнением, не вписан;
отказ среды показан там, где действие невозможно (клетка вне сетки), —
среда отвечает отказом, а не молчит. Двадцать стенограмм на проход,
длина 2–5 шагов, действия — по остаткам от номера прохода и показа.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import gen_genesis_space as П  # noqa: E402
import spacegrid as S  # noqa: E402
from layer import emit  # noqa: E402

ЦЕЛЬ = "datasets/genesis_stenogram.txt"
СТОРОНЫ = (("right", "вправо"), ("left", "влево"), ("down", "вниз"), ("up", "вверх"))
ОСИ = (("left-right", "слева направо"), ("top-bottom", "сверху вниз"))


def действие(состояние, шаг, i, j, ru):
    """(текст действия, новое состояние или None при отказе, текст отказа)."""
    n = len(состояние)
    род = (шаг + i * 3 + j * 5) % 6
    if род == 0:
        en, р = СТОРОНЫ[(шаг + j) % 4]
        k = 1
        return (f"сдвиг {р} на {k}" if ru else f"shift {en} by {k}"), S.сдвиг(состояние, en, k), None
    if род == 1:
        угол = (90, 180, 270)[(шаг + j) % 3]
        return (f"поворот на {угол}° по часовой стрелке" if ru else
                f"rotate {угол}° clockwise"), S.поворот(состояние, угол), None
    if род == 2:
        en, р = ОСИ[(шаг + j) % 2]
        return (f"отражение {р}" if ru else f"reflect {en}"), S.отражение(состояние, en), None
    r, c = 1 + (шаг + i + j) % n, 1 + (шаг * 2 + j) % n
    if род == 5 and (i + j) % 3 == 0:
        r = n + 1                       # клетка вне сетки — среда откажет
        return (f"закрасить ({r}, {c})" if ru else f"paint ({r}, {c})"), None, (
            f"клетка ({r}, {c}) вне сетки" if ru else f"cell ({r}, {c}) is outside the grid")
    закрасить = род in (3, 5)
    # КРАСИТСЯ ПУСТАЯ, СТИРАЕТСЯ ЗАКРАШЕННАЯ: действие без следа в отклике
    # учит, что среда не отвечает; клетка берётся из тех, где след будет.
    годные = [(rr + 1, cc + 1) for rr in range(n) for cc in range(n)
              if (состояние[rr][cc] == S.ПУСТО) == закрасить]
    if годные:
        r, c = годные[(шаг + i * 3 + j) % len(годные)]
    ряд = list(состояние[r - 1])
    ряд[c - 1] = "#" if закрасить else S.ПУСТО
    новое = list(состояние)
    новое[r - 1] = "".join(ряд)
    return ((f"закрасить ({r}, {c})" if закрасить else f"стереть ({r}, {c})") if ru else
            (f"paint ({r}, {c})" if закрасить else f"erase ({r}, {c})")), новое, None


def стенограмма(шаг, i):
    ru = (шаг + i) % 2 == 1
    состояние = П.сетка(шаг, i + 100)
    шагов = 2 + (шаг + i) % 4
    строки = [f"стенограмма {шагов} на сетке {S.записать(состояние)}" if ru else
              f"transcript {шагов} on grid {S.записать(состояние)}"]
    последнее = S.записать(состояние)
    for j in range(1, шагов + 1):
        текст, новое, отказ = действие(состояние, шаг, i, j, ru)
        if новое is None:
            # ОТКАЗ СРЕДЫ — ФОРМОЙ ОТКАЗА КОРПУСА («no: …» / «нет: …»), чтобы
            # суд манифеста видел объявленный акт отказа теми же глазами.
            отклик = f"нет: {отказ}" if ru else f"no: {отказ}"
        else:
            состояние = новое
            последнее = S.записать(новое)
            отклик = f"сетка {последнее}" if ru else f"grid {последнее}"
        строки.append((f"шаг {j}: действие «{текст}» → отклик: {отклик}") if ru else
                      (f"step {j}: action «{текст}» → response: {отклик}"))
    строки.append(f"конец: сетка {последнее}" if ru else f"end: grid {последнее}")
    return "\n".join(строки)


def pass_shows(шаг):
    return [стенограмма(шаг, i) for i in range(20)]


def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
