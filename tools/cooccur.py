#!/usr/bin/env python3
"""ДОМ СОВПАДЕНИЯ И ПРИЧИНЫ (14.09, куплен нулём пробы).

Замерено 14.09 по своду: «совпадение, а не причина» / «correlation is not» — НОЛЬ строк.
Корпус умеет спрашивать «почему?» (мир связей, мир фактов о вещах) и умеет отвечать
основанием. Но того, что ИЗ СОВМЕСТНОГО ДВИЖЕНИЯ ДВУХ ЧИСЕЛ ПРИЧИНА НЕ СЛЕДУЕТ, он не
говорит нигде — а это первое, чему учат всякого, кто берётся читать числа.

    ЧИСЛА ГОВОРЯТ, ЧТО БЫЛО, И МОЛЧАТ О ТОМ, ПОЧЕМУ. «Оба выросли» есть ФАКТ, и он
    проверяется вычитанием. «Одно подняло другое» есть ПРИЧИНА, и из тех же чисел она не
    выводится ничем. Дом показывает первое и ОТКАЗЫВАЕТ во втором — и отказ этот есть
    ГЛАВНОЕ, чему дом учит.

ТРИ РОДА ПО ДЕЛУ:

    оба_выросли   числа пошли в одну сторону, и это сказано числом: «первое на 15, второе
                  на 10». Причина отвергнута;
    разошлись     одно выросло, другое упало. Отказ тот же, а арифметика иная — и это
                  важно: читатель не должен выучить, что причина отвергается лишь при
                  согласном движении;
    третье        вместе с обоими выросло ТРЕТЬЕ число, и оно названо. Тогда отказ
                  становится СИЛЬНЕЕ: есть чему объяснить оба разом, и связь первого со
                  вторым не доказана тем более.

    СУД СЧИТАЕТ ФАКТЫ И НЕ СУДИТ ПРИЧИН. Он проверяет числа, разности и направление
    движения; отказ он сверяет с ОБЪЯВЛЕННЫМ словом, а не решает, верен ли он. Причину не
    проверить вычитанием — на то она и причина, и прибор, взявшийся её проверять, лгал бы.

ГРАНИЦА ОБЪЯВЛЕНА: числа кончаются на 0 или 5, и потому имя после них всегда в родительном
множественного. Согласование числительного есть дело дома `numnounforms`.
"""
import itertools
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("оба_выросли", "разошлись", "третье")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "оба_выросли": "числа пошли в одну сторону, и причина всё равно отвергнута",
    "разошлись": "одно выросло, другое упало: отказ тот же, арифметика иная",
    "третье": "третье число выросло вместе с обоими и названо: отказ сильнее",
}

ВЕЩИ = {
    "ru": ("зонтов", "плащей", "шляп", "сапог"),
    "en": ("umbrellas", "raincoats", "hats", "boots"),
}
ТРЕТЬЕ = {"ru": "дождливых дней", "en": "rainy days"}
МЕСЯЦЫ = {"ru": ("в марте", "в апреле"), "en": ("in march", "in april")}

# ЧИСЛА КОНЧАЮТСЯ НА 0 ИЛИ 5. (было1, стало1, было2, стало2, было3, стало3)
НАБОРЫ = (
    (30, 45, 20, 30, 5, 15), (40, 60, 25, 35, 10, 20), (50, 75, 15, 40, 5, 20),
    (60, 45, 20, 35, 10, 25), (80, 55, 30, 45, 15, 30), (35, 20, 40, 55, 5, 10),
    (25, 40, 45, 30, 10, 5), (70, 90, 35, 20, 20, 30),
)

РАМКИ = {
    "ru": {
        "зачин": "{м1} продано {a1} {в1} и {b1} {в2}, {м2} — {a2} {в1} и {b2} {в2}.",
        "оба_выросли": " оба числа выросли: первое на {da}, второе на {db}. что из этого "
                       "следует о причине? ничего: из того, что оба выросли, причина не "
                       "следует.",
        "разошлись": " одно выросло, другое упало: первое на {da}, второе на {db}. что из "
                     "этого следует о причине? ничего: из того, что числа разошлись, "
                     "причина не следует.",
        "третье": " вместе с ними выросло и третье: {в3} с {c1} до {c2}. что из этого "
                  "следует о причине? ничего: третье могло поднять оба, и одно другого не "
                  "объясняет.",
    },
    "en": {
        "зачин": "{м1} {a1} {в1} and {b1} {в2} were sold, {м2} — {a2} {в1} and {b2} {в2}.",
        "оба_выросли": " both numbers rose: the first by {da}, the second by {db}. what "
                       "follows from this about the cause? nothing: from both rising a "
                       "cause does not follow.",
        "разошлись": " one rose and the other fell: the first by {da}, the second by {db}. "
                     "what follows from this about the cause? nothing: from the numbers "
                     "diverging a cause does not follow.",
        "третье": " a third rose along with them: {в3} from {c1} to {c2}. what follows from "
                  "this about the cause? nothing: the third could have raised both, and "
                  "one does not explain the other.",
    },
}


def _род(a1, a2, b1, b2):
    if a1 == a2 or b1 == b2:
        return None            # число, не двинувшееся вовсе, ничему не учит
    return "оба_выросли" if (a2 > a1) == (b2 > b1) else "разошлись"


def страница(язык, род, набор, пара):
    a1, a2, b1, b2, c1, c2 = набор
    свой = _род(a1, a2, b1, b2)
    if свой is None:
        return None
    рамки, вещи, месяцы = РАМКИ[язык], ВЕЩИ[язык], МЕСЯЦЫ[язык]
    в1, в2 = вещи[пара[0]], вещи[пара[1]]
    зачин = рамки["зачин"].format(м1=месяцы[0], м2=месяцы[1], a1=a1, a2=a2, b1=b1, b2=b2,
                                  в1=в1, в2=в2)
    if род == "третье":
        # ТРЕТЬЕ БЕРЁТСЯ ЛИШЬ ТАМ, ГДЕ ОНО И ПРАВДА ВЫРОСЛО ВМЕСТЕ С ОБОИМИ: иначе слово
        # «вместе с ними» есть ложь записи.
        if not (c2 > c1 and a2 > a1 and b2 > b1):
            return None
        return зачин + рамки["третье"].format(в3=ТРЕТЬЕ[язык], c1=c1, c2=c2)
    if род != свой:
        return None
    return зачин + рамки[род].format(da=abs(a2 - a1), db=abs(b2 - b1))


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for набор in НАБОРЫ:
                for пара in itertools.permutations(range(len(ВЕЩИ[язык])), 2):
                    п = страница(язык, род, набор, пара)
                    if п:
                        вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД СЧИТАЕТ ФАКТЫ И НЕ СУДИТ ПРИЧИН. Он берёт из записи четыре числа, считает разности,
# смотрит направление движения — и требует, чтобы сказанное на странице сошлось с этим.
# Отказ («ничего: …») он сверяет с ОБЪЯВЛЕННЫМ словом и не решает, верен ли отказ: причину
# не проверить вычитанием, и прибор, взявшийся её проверять, лгал бы.
def _образцы(язык):
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык]["зачин"] + РАМКИ[язык][род])
        for дыра, узор in (("м1", "[^,.]+?"), ("м2", "[^,.]+?"), ("в1", "[^0-9,.]+?"),
                           ("в2", "[^0-9,.]+?"), ("в3", "[^0-9,.]+?"),
                           ("a1", r"\d+"), ("a2", r"\d+"), ("b1", r"\d+"), ("b2", r"\d+"),
                           ("c1", r"\d+"), ("c2", r"\d+"), ("da", r"\d+"), ("db", r"\d+")):
            дыра_о = re.escape("{" + дыра + "}")
            первый = True
            while дыра_о in о:
                о = о.replace(дыра_о, f"(?P<{дыра}>{узор})" if первый else f"(?P={дыра})", 1)
                первый = False
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def судить(строка):
    """(судимо, истинно) — числа и разности проверены; о причине суд не судит."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            if д["в1"] not in ВЕЩИ[язык] or д["в2"] not in ВЕЩИ[язык] or д["в1"] == д["в2"]:
                continue                      # чужая вещь — запись не наша
            if list(МЕСЯЦЫ[язык]) != [д["м1"], д["м2"]]:
                continue
            a1, a2 = int(д["a1"]), int(д["a2"])
            b1, b2 = int(д["b1"]), int(д["b2"])
            свой = _род(a1, a2, b1, b2)
            if свой is None:
                return True, False
            if род == "третье":
                if д["в3"] != ТРЕТЬЕ[язык]:
                    continue
                c1, c2 = int(д["c1"]), int(д["c2"])
                return True, c2 > c1 and a2 > a1 and b2 > b1
            return True, (свой == род and int(д["da"]) == abs(a2 - a1)
                          and int(д["db"]) == abs(b2 - b1))
    return False, True


