#!/usr/bin/env python3
"""GENESIS layer: ВЕНГЕРСКОЕ ОБЪЕКТНОЕ СПРЯЖЕНИЕ — see tools/huobjforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Два ряда, а не один» и «выбирает предмет, а не говорящий» идут вместе: первое называет
РАЗЛИЧИЕ, второе отнимает вывод «значит, можно взять любое».

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Это не время и не наклонение», «определённость сказана дважды» и «сосед говорит это один
раз» — второй группой: все три о ГРАНИЦАХ. Первая внутрь языка (различает не время), вторая
внутрь строки (две половины обязаны сойтись), третья наружу.

«Спрошено и отвечено» — третьей.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import huobjforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_huobj.txt"
ГРУППЫ = (("два ряда, а не один", "выбирает предмет, а не говорящий"),
          ("это не время и не наклонение", "определённость сказана дважды",
           "сосед говорит это один раз"),
          ("спрошено и отвечено",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
