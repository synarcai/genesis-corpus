def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for i, (a, b, c) in enumerate(ТРОЙКИ):
            общ = dict(ПУСТО, a=_зн(a), b=_зн(b), c=_зн(c),
                       ca=_зн(c - a), ac=_зн(a - c))
            вон[рамки["транзитивность"].format(**общ)] = (язык, "транзитивность")
            вон[рамки["трихотомия"].format(**общ)] = (язык, "трихотомия")
            вон[рамки["антисимметрия"].format(**общ)] = (язык, "антисимметрия")
            вон[рамки["спрошенное"].format(**общ)] = (язык, "спрошенное")
            s = СЛАГАЕМЫЕ[i % len(СЛАГАЕМЫЕ)]
            вон[рамки["прибавление"].format(**dict(
                общ, s=_зн(s), **{"as": _зн(a + s)}, cs=_зн(c + s)))] = (язык, "прибавление")
            m = МНОЖИТЕЛИ[i % len(МНОЖИТЕЛИ)]
            вон[рамки["умножение на положительное"].format(**dict(
                общ, m=_зн(m), am=_зн(a * m), cm=_зн(c * m)))] = (
                    язык, "умножение на положительное")
            n = ОТРИЦАТЕЛЬНЫЕ[i % len(ОТРИЦАТЕЛЬНЫЕ)]
            вон[рамки["переворот"].format(**dict(
                общ, n=_зн(n), an=_зн(a * n), cn=_зн(c * n)))] = (язык, "переворот")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ЧИСЛО ЧИТАЕТСЯ СО СВОИМ ЗНАКОМ: «−12» есть минус двенадцать, а не двенадцать рядом
# со знаком. Суд, читающий число без знака, объявил бы «−12 больше −20» ложью.
_Ч = r"(−?\d+)"
_РАЗНОСТЬ = re.compile(rf"(?<![\d/−]){_Ч} − {_Ч} = {_Ч}(?![\d/])")
_ПРОИЗВЕДЕНИЕ = re.compile(rf"(?<![\d/−]){_Ч} × {_Ч} = {_Ч}(?![\d/])")
_МЕНЬШЕ = re.compile(rf"(?<![\d/−]){_Ч} меньше {_Ч}(?![\d/])"
                     rf"|(?<![\d/−]){_Ч} is less than {_Ч}(?![\d/])")
_БОЛЬШЕ = re.compile(rf"(?<![\d/−]){_Ч} больше {_Ч}(?![\d/])"
                     rf"|(?<![\d/−]){_Ч} is greater than {_Ч}(?![\d/])")
# УПОМЯНУТЬ НЕ ЗНАЧИТ УТВЕРДИТЬ. Страница трихотомии НАЗЫВАЕТ все три возможности,
# и две из них ложны по самому её предмету: «„1 больше 7“ ложно» есть истинная строка,
# содержащая ложное сравнение. Первая редакция суда читала их как утверждения и объявила
# сорок честных страниц ложными — ровно та беда, от которой манифест бережёт ПРОЗУ:
# «a falsehood may be QUOTED to be refuted».
#
#     СВОЙСТВО, ГОВОРЯЩЕЕ О НЕВОЗМОЖНОМ, ПОКАЗЫВАЕТСЯ ТОЛЬКО НАЗЫВАНИЕМ НЕВОЗМОЖНОГО;
#     СУД, ЧИТАЮЩИЙ НАЗВАННОЕ КАК УТВЕРЖДЁННОЕ, ЗАПРЕЩАЕТ ГОВОРИТЬ О ЛОЖНОМ ВОВСЕ.
#
# Оттого дом ставит всякую НАЗВАННУЮ возможность в кавычки-ёлочки, а суд вырезает их
# содержимое прежде счёта. Кавычки здесь суть ЧАСТЬ ЗАКОНА, а не украшение записи.
_НАЗВАННОЕ = re.compile(r"«[^»]*»")


def _пары(рег, с):
    """Пары чисел сравнения — из какой бы половины правила они ни пришли."""
    for г in рег.findall(с):
        ру1, ру2, ан1, ан2 = г
        yield int((ру1 or ан1).replace("−", "-")), int((ру2 or ан2).replace("−", "-"))


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, r in _РАЗНОСТЬ.findall(с):
        if int(a.replace("−", "-")) - int(b.replace("−", "-")) != int(r.replace("−", "-")):
            return True, False
    for a, b, r in _ПРОИЗВЕДЕНИЕ.findall(с):
        if int(a.replace("−", "-")) * int(b.replace("−", "-")) != int(r.replace("−", "-")):
            return True, False
    # СРАВНЕНИЯ СЧИТАЮТСЯ ЛИШЬ ВНЕ КАВЫЧЕК: названное не есть утверждённое.
    вне = _НАЗВАННОЕ.sub(" ", с)
    for x, y in _пары(_МЕНЬШЕ, вне):
        if x >= y:
            return True, False
    for x, y in _пары(_БОЛЬШЕ, вне):
        if x <= y:
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ОБЪЯВЛЕННЫЕ ТРОЙКИ ОБЯЗАНЫ ИДТИ ПО ВОЗРАСТАНИЮ, И СРЕДИ НИХ ОБЯЗАНЫ БЫТЬ
    # ОТРИЦАТЕЛЬНЫЕ: порядок на одних счётных числах есть порядок количества.
    for a, b, c in ТРОЙКИ:
        if not (a < b < c):
            беды.append(f"тройка не по возрастанию: {a} {b} {c}")
    if not any(a < 0 for a, _b, _c in ТРОЙКИ):
        беды.append("ни одной отрицательной тройки")
    if not any(n < 0 for n in ОТРИЦАТЕЛЬНЫЕ):
        беды.append("множитель переворота не отрицателен")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        числа = list(re.finditer(r"−?\d+", страница))
        m = числа[-1] if числа else None
        порча = (страница[:m.start()] + str(int(m.group().replace("−", "-")) + 1)
                 + страница[m.end():] if m else страница)
        if порча == страница:
            беды.append(f"порча не состоялась в роде {род}")
        elif судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПЕРЕВОРОТА: сказать «меньше» там, где знак перевернулся, — главная ложь
    # этого дома, и она обязана быть поймана.
    пер = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "переворот")
    порча = пер.replace("БОЛЬШЕ", "меньше", 1)
    if порча == пер:
        беды.append("порча не состоялась: нет слова «БОЛЬШЕ» в перевороте")
    elif судить(порча)[1] is not False:
        беды.append(f"переворот, сказанный как сохранение, прошёл: {порча[:70]}")
    # МУТАНТ АНТИСИММЕТРИИ: снятое «НЕ» обращает страницу в ложь.
    # МУТАНТ АНТИСИММЕТРИИ: СНЯТЫЕ КАВЫЧКИ обращают названное в утверждённое, и
    # страница становится ложной, не изменив ни одного числа и ни одного слова.
    анти = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "антисимметрия")
    порча = анти.replace("«", "", 1).replace("» ложно", "", 1)
    if порча == анти:
        беды.append("порча не состоялась: нет кавычек с «ложно»")
    elif судить(порча)[1] is not False:
        беды.append(f"снятые кавычки прошли: {порча[:80]}")
    # МУТАНТ ПО СЛОВУ.
