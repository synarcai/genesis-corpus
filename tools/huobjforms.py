def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _чужое_в_цитате(тело):
    """Кусок ВЕНГЕРСКОЙ цитаты, не объявленный таблицей дома, — либо None.

    ЦИТАТА СОСЕДА НЕ ЕСТЬ ЦИТАТА ЯЗЫКА ДОМА: дом берёт в ёлочки и пары форм через косую
    черту, и русскую речь тоже. Судится цитата, несущая хоть один объявленный кусок.
    """
    куски = [к for к in _re.split(r"[\s/]+", тело.lstrip("*")) if к]
    if not any(к in _ОБЪЯВЛЕНО for к in куски):
        return None
    for кусок in куски:
        if кусок not in _ОБЪЯВЛЕНО:
            return кусок
    return None


def _нарушает(тело):
    """Нарушает ли цитата закон дома: ряд глагола разошёлся с предметом действия.

    ЦИТАТА ИЗ ДВУХ КУСКОВ ЕСТЬ «ГЛАГОЛ + ПРЕДМЕТ», И ДВА ГЛАГОЛА РЯДОМ НЕ ЕСТЬ РЕЧЬ (13.09,
    куплено ложной страницей). Первая редакция ловила лишь расхождение РЯДА и пропускала
    «látok írom»: оба куска объявлены таблицей, предмета же нет вовсе, и закон о ряде
    спросить было не о чем.

        ЗАКОН, ПРОВЕРЯЮЩИЙ СОГЛАСИЕ ДВУХ МЕСТ, МОЛЧИТ, КОГДА ВТОРОЕ МЕСТО ЗАНЯТО ЧЕМ-ТО
        ТРЕТЬИМ, — и порча, УБРАВШАЯ предмет, проходит мимо него.
    """
    куски = тело.lstrip("*").split()
    if len(куски) != 2:
        return False
    if куски[0] in _РЯД and куски[1] not in (НЕЧТО, ЭТО):
        return True                    # глагол, за которым стои́т не предмет
    if куски[1] not in (НЕЧТО, ЭТО):
        return False
    ряд = _РЯД.get(куски[0])
    if ряд is None:
        return False
    нужен = "опр" if куски[1] == ЭТО else "неопр"
    return ряд != нужен


