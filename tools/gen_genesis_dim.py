#!/usr/bin/env python3
"""GENESIS layer: РАЗМЕРНОСТЬ — see tools/dimforms.py for the law.

ПРАВИЛО И ЕГО ОТКАЗ ИДУТ ОДНОЙ ГРУППОЙ, и это сам предмет дома: «3 м + 4 м = 7 м» и
«3 м + 4 кг не даёт ничего» суть одно правило, сказанное с двух сторон.

    ОТКАЗ, НЕ ПОКАЗАННЫЙ РЯДОМ С ПРАВИЛОМ, ЧИТАЕТСЯ КАК НЕДОСМОТР, А НЕ КАК ГРАНИЦА.

УМНОЖЕНИЕ И ДЕЛЕНИЕ — второй группой: оба о том, что от действия рождается НОВАЯ единица,
и оба не требуют однородности. Порознь читатель решил бы, что новая единица есть свойство
умножения, а не обоих действий.

СРАВНЕНИЕ стои́т особо: оно подчиняется закону сложения, но даёт ТРЕТИЙ ответ —
«несравнимы», — которого у сравнения обычно нет, и соседство разбавило бы эту новизну.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import dimforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_dim.txt"
ГРУППЫ = (("сложение однородного", "отказ разнородному"),
          ("умножение рождает единицу", "деление рождает единицу"),
          ("сравнение однородного",),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
