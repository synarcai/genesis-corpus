#!/usr/bin/env python3
"""ДОМ СТАВОК — отношение, которое ПРОХОДИТСЯ, а не пишется.

Отношение крупной единицы к мелкой здесь не записано числом: оно проходится по
объявленному графу единиц, и оттого «сколько минут в двух часах» есть счёт по существу.

7 родов объявлены не здесь: их назвала СВОЯ ЖЕ КУЗНИЦА кортежем `ГРУППЫ`.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

ЧИТАТЕЛЬ ПЯТОГО РОДА НАЗВАН ПОИМЁННО: суд этого мира ВВОЗИТ дом модулем и берёт `ДЕЯТЕЛИ`.
Связь эта рвётся МОЛЧА при ввозе суда, а не при ковке, — оттого самопроверка дома сверяет, что
все эти имена у него есть.
"""
