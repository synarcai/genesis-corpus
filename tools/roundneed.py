# (делимое, делитель). Пары объявлены с остатком и без: род «обе_рядом» берёт оба случая.
ПАРЫ = ((95, 40), (13, 3), (50, 12), (77, 10), (31, 8), (64, 9),
        (80, 40), (12, 3), (60, 12), (100, 10))


def _счёт(n, k):
    """(вверх, вниз, остаток) — одно деление и оба его прочтения."""
    return -(-n // k), n // k, n % k


def страница(язык, род, i, пара):
    n, k = пара
    вверх, вниз, остаток = _счёт(n, k)
    рамки = РАМКИ[язык][род]
    if род != "обе_рядом":
        if остаток == 0:
            return None            # нулевой остаток стирает разницу — учить нечему
        if i >= len(рамки):
            return None
        return рамки[i].format(n=n, k=k, v=вверх if род == "вверх" else вниз)
    if i >= len(рамки):
        return None
    зачин, с_остатком, без_остатка = рамки[i]
    хвост = с_остатком.format(r=остаток) if остаток else без_остатка
    return зачин.format(n=n, k=k, в=вверх, z=вниз) + хвост


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for i in range(len(РАМКИ[язык][род])):
                for пара in ПАРЫ:
                    п = страница(язык, род, i, пара)
                    if п:
                        вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД ДЕЛИТ ЗАНОВО и читает по рамке, КАКОЕ ИЗ ДВУХ ПРОЧТЕНИЙ на странице спрошено. Он не
# знает рода: рамка сама говорит, что́ обещано, и суд сверяет обещанное со своим делением.
def _образцы(язык):
    вон = []
    for род in ("вверх", "вниз"):
        for рамка in РАМКИ[язык][род]:
            о = (re.escape(рамка).replace(re.escape("{n}"), r"(?P<n>\d+)")
                 .replace(re.escape("{k}"), r"(?P<k>\d+)")
                 .replace(re.escape("{v}"), r"(?P<v>\d+)"))
            вон.append((род, re.compile(о + r"$")))
    for зачин, с_остатком, без_остатка in РАМКИ[язык]["обе_рядом"]:
        for хвост, есть in ((с_остатком, True), (без_остатка, False)):
            о = (re.escape(зачин + хвост).replace(re.escape("{n}"), r"(?P<n>\d+)")
                 .replace(re.escape("{k}"), r"(?P<k>\d+)")
                 .replace(re.escape("{в}"), r"(?P<в>\d+)")
                 .replace(re.escape("{z}"), r"(?P<z>\d+)")
                 .replace(re.escape("{r}"), r"(?P<r>\d+)"))
            вон.append(("обе_с" if есть else "обе_без", re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def судить(строка):
    """(судимо, истинно) — деление сделано заново, прочтение взято из рамки."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for вид, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            n, k = int(м.group("n")), int(м.group("k"))
            if k == 0:
                return True, False
            вверх, вниз, остаток = _счёт(n, k)
            if вид == "вверх":
                # ОСТАТОК НУЛЬ СТИРАЕТ РАЗНИЦУ: страница без остатка ничему не учит, и суд
                # её не пропускает — иначе «вверх» и «вниз» стали бы одним родом молча.
                return True, остаток > 0 and int(м.group("v")) == вверх
            if вид == "вниз":
                return True, остаток > 0 and int(м.group("v")) == вниз
            ладно = int(м.group("в")) == вверх and int(м.group("z")) == вниз
            if вид == "обе_с":
                return True, ладно and остаток > 0 and int(м.group("r")) == остаток
            return True, ладно and остаток == 0
    return False, True


