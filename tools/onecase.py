def держится(a, b):
    """Верно ли «если A, то B» на всём объявленном ряду."""
    A, B = СВОЙСТВА[a][0], СВОЙСТВА[b][0]
    return not any(A(n) and not B(n) for n in РЯД)


def случаи(a, b, годные=True, сколько=3):
    """Числа ряда, где A держится и B (или не B)."""
    A, B = СВОЙСТВА[a][0], СВОЙСТВА[b][0]
    return [n for n in РЯД if A(n) and (B(n) is годные)][:сколько]


def сколько_под(a):
    return sum(1 for n in РЯД if СВОЙСТВА[a][0](n))


def страница(язык, род, a, b, i):
    if a == b:
        return None
    A, _ = СВОЙСТВА[a][1][язык]
    B, B_нет = СВОЙСТВА[b][1][язык]
    рамки, верно = РАМКИ[язык], держится(a, b)
    if род == "контрпример_довод":
        если = случаи(a, b, годные=False)
        if верно or i >= len(если):
            return None
        return рамки["контрпример_довод"].format(A=A, B=B, B_нет=B_нет, n=если[i])
    if not верно:
        return None
    если = случаи(a, b, годные=True)
    if род == "пример_не_довод":
        if i >= len(если):
            return None
        return рамки["пример_не_довод"].format(A=A, B=B, n=если[i])
    if i:
        return None
    k = сколько_под(a)
    # ОБХОД ДОКАЗЫВАЕТ ЛИШЬ ТОГДА, КОГДА ЕСТЬ ЧТО ОБХОДИТЬ: утверждение о пустом множестве
    # верно даром, и показывать в нём нечего.
    if k < 2:
        return None
    return рамки["обход_довод"].format(A=A, B=B, а=РЯД[0], я=РЯД[-1], k=k)


# ПАРЫ ОБЪЯВЛЕНЫ, А НЕ ПЕРЕБРАНЫ. Среди всех пар свойств ложных импликаций вдесятеро больше
# верных — таково их ЧИСЛО, а не их важность, и перебор дал перекос 15. Верные пары берутся у
# дома двусторонней связи (там они уже проверены обходом ряда), а ложные суть ОБРАЩЕНИЯ тех
# из них, что односторонни: обращение односторонней связи ложно ровно потому, что она
# односторонняя, и вот где эти два дома сходятся.
ВЕРНЫЕ = tuple(СВЯЗИ)
ЛОЖНЫЕ = tuple((b, a) for a, b in СВЯЗИ if вид(a, b) == "одна")


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for a, b in ВЕРНЫЕ:
            for i in range(3):
                п = страница(язык, "пример_не_довод", a, b, i)
                if п:
                    вон.setdefault(п, (язык, "пример_не_довод"))
            п = страница(язык, "обход_довод", a, b, 0)
            if п:
                вон.setdefault(п, (язык, "обход_довод"))
        for a, b in ЛОЖНЫЕ:
            for i in range(3):
                п = страница(язык, "контрпример_довод", a, b, i)
                if п:
                    вон.setdefault(п, (язык, "контрпример_довод"))
    return вон


ПОКАЗЫ = _показы()


