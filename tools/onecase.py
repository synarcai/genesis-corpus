# СУД ПРОВЕРЯЕТ УТВЕРЖДЕНИЕ ОБХОДОМ РЯДА, а случай — порознь. Он не верит ни слову «неверно»,
# ни слову «если»: держится ли импликация, он решает сам, и названное число обязано БЫТЬ тем
# самым случаем, а не каким угодно.
def _образцы(язык):
    формы = sorted({ф for _и, (_п, с) in СВОЙСТВА.items() for ф in с[язык]},
                   key=len, reverse=True)
    словарь = "(?:" + "|".join(re.escape(ф) for ф in формы) + ")"
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык][род])
        for дыра, узор in (("B_нет", словарь), ("A", словарь), ("B", словарь),
                           ("n", r"\d+"), ("а", r"\d+"), ("я", r"\d+"), ("k", r"\d+")):
            дыра_о = re.escape("{" + дыра + "}")
            первый = True
            while дыра_о in о:
                о = о.replace(дыра_о, f"(?P<{дыра}>{узор})" if первый else f"(?P={дыра})", 1)
                первый = False
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def _имя(язык, форма, сказ=True):
    for имя, (_п, формы) in СВОЙСТВА.items():
        если = формы[язык]
        if форма == (если[0] if сказ else если[1]):
            return имя
    return None


def судить(строка):
    """(судимо, истинно) — импликация проверена обходом ряда, случай проверен порознь."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            a, b = _имя(язык, д["A"]), _имя(язык, д["B"])
            if a is None or b is None or a == b:
                continue                      # чужое свойство — запись не наша
            A, B = СВОЙСТВА[a][0], СВОЙСТВА[b][0]
            верно = держится(a, b)
            if род == "контрпример_довод":
                if _имя(язык, д["B_нет"], сказ=False) != b:
                    return True, False
                n = int(д["n"])
                # КОНТРПРИМЕР ОБЯЗАН БЫТЬ КОНТРПРИМЕРОМ: и утверждение ложно, и число его
                # валит. Ложное утверждение с «примером», какой ему отвечает, есть ложь.
                return True, (not верно) and n in РЯД and A(n) and not B(n)
            if род == "пример_не_довод":
                n = int(д["n"])
                return True, верно and n in РЯД and A(n) and B(n)
            if int(д["а"]) != РЯД[0] or int(д["я"]) != РЯД[-1]:
                return True, False
            # ОБХОД ЗАСЧИТЫВАЕТСЯ ЛИШЬ ПРИ ВЕРНОМ ЧИСЛЕ ПРОЙДЕННЫХ: «проверены все» без
            # счёта есть слово, а не обход.
            return True, верно and int(д["k"]) == сколько_под(a) and сколько_под(a) >= 2
    return False, True


