#!/usr/bin/env python3
"""ДОМ РАЗРЯДА — МЕСТО ЦИФРЫ ЕСТЬ ЕЁ ВЕС.

    СВОД ОКРУГЛЯЕТ ДО СОТЕН И НИ РАЗУ НЕ ГОВОРИТ, ЧТО ТАКОЕ СОТНИ. Замер 11.09 по 253 мирам
    показов: разложение числа по разрядам («300 + 40 + 7 = 347») — НОЛЬ; «цифра стои́т на месте»,
    «в разряде» — НОЛЬ; «те же цифры, а числа разные» — НОЛЬ.

Слова «десятки» и «сотни» в своде есть — сто восемьдесят раз, — и все они о ДРУГОМ: `roundforms`
округляет до сотен (48), `handy` дополняет до десятка (72), `rem` вынимает из остатка ещё одну
десятку (15). Прочее — чужие языки: португальское «tens» значит «ты имеешь», и признак, писанный
по-русски, ловит его наравне со своим.

    ПРИЗНАК, ИЩУЩИЙ СЛОВО В СВОДЕ ДВАДЦАТИ ДЕВЯТИ ЯЗЫКОВ, НАХОДИТ ЧУЖИЕ СЛОВА ТОЙ ЖЕ БУКВЫ.

СВОД СЧИТАЕТ В ДЕСЯТИЧНОЙ ЗАПИСИ СОТНЯМИ ТЫСЯЧ СТРОК И НИ РАЗУ НЕ ГОВОРИТ, ПОЧЕМУ ОНА ТАК УСТРОЕНА.
Он округляет ДО разряда, дополняет ДО десятка, переносит через основание — и место цифры при этом
остаётся молчаливым уговором между писавшим и читающим.

ДВАДЦАТЬ ПЯТАЯ ЛОВУШКА РЯДА: 347 И 374 СОСТАВЛЕНЫ ИЗ ОДНИХ ЦИФР, А ЧИСЛА РАЗНЫЕ. Разница не
в цифрах, а в их местах — и это тот же закон, что в паре координат (`point`), но лежащий глубже:
там порядок объявлен записью, здесь он объявлен САМИМ СЧИСЛЕНИЕМ.

    ЦИФРА БЕЗ МЕСТА НЕ ЕСТЬ ЧИСЛО. МЕСТО ЦИФРЫ ЕСТЬ ЕЁ ВЕС, И ВЕС ЭТОТ РАСТЁТ ВДЕСЯТЕРО
    С КАЖДЫМ ШАГОМ ВЛЕВО.

ЧЕТЫРЕ РОДА:

    разложение    в числе 347 цифра 3 стои́т на месте сотен, цифра 4 — на месте десятков,
                  цифра 7 — на месте единиц: 300 + 40 + 7 = 347.
    те же цифры   347 и 374 составлены из одних цифр, а числа разные: 374 − 347 = 27.  ← ЛОВУШКА
    вес места     в числе 347 цифра 3 значит 300, а в числе 734 та же цифра значит 3:
                  300 ÷ 3 = 100.
    ноль держит   в числе 307 на месте десятков стои́т ноль, и без него вышло бы 37:
                  307 − 37 = 270.                                              ← ГЛУБЖЕ ВСЕГО

ЧЕТВЁРТЫЙ РОД ЕСТЬ СЕРДЦЕ ДОМА. Ноль — единственная цифра, которая ничего не считает и всё же
обязана стоять: она держит место, чтобы соседи не съехали. Свод знает ноль как итог вычитания
и как невозможный делитель, но не знает его как ДЕРЖАТЕЛЯ МЕСТА.

    НОЛЬ В ЗАПИСИ ЧИСЛА НИЧЕГО НЕ СЧИТАЕТ И ВСЁ ЖЕ НЕОБХОДИМ: ОН ГОВОРИТ НЕ «СКОЛЬКО»,
    А «ЗДЕСЬ НИЧЕГО, И СЛЕДУЮЩИЙ НЕ ЗАНИМАЕТ ЭТО МЕСТО».

СЧЁТНЫХ ФОРМ СЛОВ РАЗРЯДА ДОМ НЕ ПРОСИТ, И ЭТО КУПЛЕНО ОШИБКОЙ. Первая редакция писала «три сотни,
четыре десятка, семь единиц» и потребовала объявить в `rugram` слово «десяток». Объявление тотчас
назвало ложью ПЯТНАДЦАТЬ честных строк дома остатка: тот пишет «вышла бы ещё одна деся́тка» —
женское слово с той же формой, что у мужского «деся́ток».

    СЛОВО, КОТОРОЕ В ЯЗЫКЕ ЕСТЬ ДВАЖДЫ, НЕЛЬЗЯ ОБЪЯВИТЬ ОДИН РАЗ: таблица, знающая одно,
    назовёт ложью строку о другом.

Язык возвращён нетронутым, а дом перестроен на обороты, где согласования нет вовсе: «на месте
сотен» есть родительный множественного в постоянном обороте, «цифра 3» ставит число ПОСЛЕ слова.

    ДОМ, ТРЕБУЮЩИЙ ПРАВКИ ЯЗЫКА РАДИ ОДНОГО ОБОРОТА, ОБЯЗАН СПЕРВА ПОИСКАТЬ ДРУГОЙ ОБОРОТ.

    python3 tools/placevalforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("разложение", "те же цифры", "вес места", "ноль держит")

# ИМЕНА МЕСТ — ПОСТОЯННЫЕ ОБОРОТЫ, А НЕ СКЛОНЯЕМЫЕ СЛОВА: «на месте сотен» не меняется
# от числа, и потому счётной формы не просит.
МЕСТА = {"ru": ("единиц", "десятков", "сотен"),
         "en": ("units", "tens", "hundreds")}
ВЕСА = (1, 10, 100)

РАМКИ = {
    "ru": {
        "разложение": "в числе {n} цифра {c} стои́т на месте {м2}, цифра {d} — на месте {м1}, "
                      "цифра {e} — на месте {м0}: {c00} + {d0} + {e} = {n}.",
        "те же цифры": "{n} и {m} составлены из одних цифр, а числа разные: {m} − {n} = {r}; "
                       "разница не в цифрах, а в их местах.",
        "вес места": "в числе {n} цифра {c} значит {c00}, а в числе {k} та же цифра значит {c}: "
                     "{c00} ÷ {c} = 100.",
        "ноль держит": "в числе {z} на месте {м1} стои́т ноль, и без него вышло бы {zz}: "
                       "{z} − {zz} = {rz}; ноль ничего не считает и держит место.",
    },
    "en": {
        "разложение": "in the number {n} the digit {c} stands in the {м2} place, the digit {d} "
                      "in the {м1} place, the digit {e} in the {м0} place: "
                      "{c00} + {d0} + {e} = {n}.",
        "те же цифры": "{n} and {m} are made of the same digits, and the numbers differ: "
                       "{m} − {n} = {r}; the difference is not in the digits but in their places.",
        "вес места": "in the number {n} the digit {c} means {c00}, and in the number {k} the same "
                     "digit means {c}: {c00} ÷ {c} = 100.",
        "ноль держит": "in the number {z} a zero stands in the {м1} place, and without it {zz} "
                       "would come out: {z} − {zz} = {rz}; a zero counts nothing and holds "
                       "the place.",
    },
}
ПУСТО = dict(n=0, m=0, k=0, z=0, zz=0, c=0, d=0, e=0, c00=0, d0=0, r=0, rz=0,
             м0="", м1="", м2="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, места = РАМКИ[язык], МЕСТА[язык]
        общее = dict(ПУСТО, м0=места[0], м1=места[1], м2=места[2])
        for c in range(1, 10):
            for d in range(0, 10):
                for e in range(0, 10):
                    n = c * 100 + d * 10 + e
                    # РАЗЛОЖЕНИЕ ПОКАЗЫВАЕТСЯ ТАМ, ГДЕ ВСЕ ТРИ МЕСТА ЗАНЯТЫ: ноль в середине
                    # есть предмет ЧЕТВЁРТОГО рода и показывается там со своим законом.
                    # РАЗЛОЖЕНИЕ ПОКАЗЫВАЕТ РАЗНЫЕ МЕСТА, А НЕ ОДНУ ЦИФРУ ТРИЖДЫ: у числа
                    # 111 разложение верно и не учит ничему, ибо места неразличимы.
                    if d and e and len({c, d, e}) > 1 and (c + d + e) % 3 == 0:
                        вон[рамки["разложение"].format(
                            **dict(общее, n=n, c=c, d=d, e=e, c00=c * 100, d0=d * 10))] = (
                            язык, "разложение")
                    # ТЕ ЖЕ ЦИФРЫ: переставлены ДВА последних места, и число обязано вырасти,
                    # иначе разность вышла бы отрицательной, а знака дом не показывает.
                    if e > d and (c + d + e) % 4 == 0:
                        m = c * 100 + e * 10 + d
                        вон[рамки["те же цифры"].format(
                            **dict(общее, n=n, m=m, r=m - n))] = (язык, "те же цифры")
                    # ВЕС МЕСТА: одна цифра на месте сотен и она же на месте единиц.
                    # ВЕС МЕСТА ПОКАЗЫВАЕТСЯ НЕВЫРОЖДЕННЫМ ЧАСТНЫМ: при цифре 1 равенство
                    # «100 ÷ 1 = 100» истинно и об отношении весов не говорит ничего.
                    if c > 1 and c != e and d and (c + d + e) % 5 == 0:
                        k = e * 100 + d * 10 + c
                        вон[рамки["вес места"].format(
                            **dict(общее, n=n, k=k, c=c, c00=c * 100))] = (язык, "вес места")
            # НОЛЬ ДЕРЖИТ МЕСТО: в середине ноль, и выбросив его, получаем ДВУЗНАЧНОЕ число.
            for e in range(1, 10):
                z = c * 100 + e
                zz = c * 10 + e
                вон[рамки["ноль держит"].format(
                    **dict(общее, z=z, zz=zz, rz=z - zz))] = (язык, "ноль держит")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА3 = re.compile(r"(?<![/\d])(\d+) \+ (\d+) \+ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(?<!− )(\d+) − (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c, d in _СУММА3.findall(с):
        if int(a) + int(b) + int(c) != int(d):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    раз = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "разложение")
    нол = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "ноль держит")
    for страница, слово, куда in ((раз, "цифра", "цифр"), (нол, "место", "мест")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(раз + " " + раз)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ЛОВУШКА ОБЯЗАНА СТОЯТЬ НА ОДНИХ ЦИФРАХ: иначе она не о местах, а о разных числах.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "те же цифры" or я != "ru":
            continue
        a, b, _ = _РАЗНОСТЬ.findall(с)[0]
        if sorted(a) != sorted(b):
            беды.append(f"цифры разошлись: {с[:80]}")
            break
    # НОЛЬ ДЕРЖИТ МЕСТО ЛИШЬ ТАМ, ГДЕ ОН В СЕРЕДИНЕ: ноль в конце — другой закон.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "ноль держит" or я != "ru":
            continue
        a, b, _ = _РАЗНОСТЬ.findall(с)[0]
        if len(a) != 3 or a[1] != "0" or len(b) != 2:
            беды.append(f"ноль не в середине: {с[:80]}")
            break
    print(f"РАЗРЯД: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
