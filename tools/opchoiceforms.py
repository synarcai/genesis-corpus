#!/usr/bin/env python3
"""ДОМ ВЫБОРА ДЕЙСТВИЯ — какой знак требует само положение, и ПОЧЕМУ именно он.

    КОРПУС УЧИЛ СЧИТАТЬ И УЧИЛ НАЗЫВАТЬ ДЕЙСТВИЕ, КОГДА ЕГО НАЗЫВАЕТ ВОПРОС, — И НЕ УЧИЛ
    ВЫБИРАТЬ ЕГО ИЗ ПОЛОЖЕНИЯ. Дом перекрёстка пишет «чему равно 20 плюс 5?», дом задачи —
    «посчитай 20 плюс 5»: знак стои́т в самом вопросе, и выбирать нечего.

ПОВОД — ЗАМЕР, А НЕ ЗАМЫСЕЛ. Прибор [СВОД СПРАШИВАЕТ СЕБЯ] держит восемь лжей читателя при
рубеже ноль, и разбор развёл их по родам: читатель СЧИТАЕТ ВЕРНО, а ДЕЙСТВИЕ БЕРЁТ НЕ ТО.

    «Ира нашла 11 орехов. она потеряла 9 из них.»   → ответил 11 + 9 = 20  (надо −)
    «Вера собрала 27 яблок. потом потеряла 13.»     → ответил 27 + 13 = 40 (надо −)
    «Ivan shared 6 coins among 3 friends.»          → ответил 18          (надо ÷)
    «Grace has 2 fewer cookies than Carla…»         → ответил 10          (надо −)

Четыре ошибки из восьми суть ОДНА дыра: слово, решающее знак, нигде не показано решающим.

ЗАКОН ПОКУПАЕТСЯ МИНИМАЛЬНОЙ ПАРОЙ, А НЕ ПРИМЕРОМ. Две страницы стоя́т рядом с ОДНИМИ И ТЕМИ
ЖЕ ЧИСЛАМИ, и разнятся они ровно одним словом — тем, что решает знак:

    у Димы было 11 орехов. он нашёл ещё 9. находка прибавляет: 11 + 9 = 20.
    у Димы было 11 орехов. он потерял 9. потеря убавляет: 11 − 9 = 2.

Пара есть довод: числа те же, ответ иной, и причина различия названа В САМОЙ СТРОКЕ. Одна
страница учила бы счёту, две — ВЫБОРУ.

ТРИ РАЗВИЛКИ, И КАЖДАЯ ВЗЯТА ИЗ ОШИБКИ ЧИТАТЕЛЯ, А НЕ ИЗ ПОЛНОТЫ ТАБЛИЦЫ:
  · НАХОДКА / ПОТЕРЯ            — прибавить или убавить;
  · ДЕЛЁЖ ПОРОВНУ / ПОВТОР      — разделить или умножить;
  · БОЛЬШЕ НА / МЕНЬШЕ НА       — прибавить или убавить при сравнении.

ЧЕТВЁРТАЯ ОШИБКА ЧИТАТЕЛЯ ЗДЕСЬ НЕ ЗАКРЫТА, И ЭТО СКАЗАНО, А НЕ УМОЛЧАНО: «у пии было 36
монет. четверть монет ушла» есть ЦЕПЬ ИЗ ДВУХ действий (36 ÷ 4 = 9, затем 36 − 9 = 27), а
здесь показывается ВЫБОР ОДНОГО. Цепь есть предмет дома цепей, и писать её здесь значило бы
смешать два закона в одной странице.

СЛОВО, РЕШАЮЩЕЕ ЗНАК, ОБЪЯВЛЕНО ТАБЛИЦЕЙ, А НЕ УГАДАНО ПО СТРОКЕ: суд читает `РЕШАЮЩИЕ` и
сверяет знак леджера с объявленным. Подмена «потеря убавляет: 11 + 9 = 20» ловится машинально.

ЧИСЛА ВЫБРАНЫ ПОД РУССКИЙ СЧЁТ, И ЭТО НЕ КАПРИЗ: имя стои́т при первом числе («11 орехов»), и
форма его есть родительное множественное, какого требует русский при 5–20 и при 11–14 в
сотне. Прочие числа страницы стоя́т БЕЗ ИМЕНИ, и склонять там нечего.

    python3 tools/opchoiceforms.py     # самопроверка с мутантами
"""
import re

ЯЗЫКИ = ("ru", "en")

# ЗНАК ДЕЙСТВИЯ, РЕШЁННЫЙ СЛОВОМ. Ключ — оборот, стоящий в странице ПЕРЕД леджером; значение —
# знак, которого этот оборот требует. Объявлено рукой, читается судом.
ЗНАК_РОДА = {"находка": "+", "потеря": "−", "делёж": "÷",
             "повтор": "×", "больше": "+", "меньше": "−"}
ОБОРОТ = {
    "ru": {"находка": "находка прибавляет", "потеря": "потеря убавляет",
           "делёж": "делёж поровну делит", "повтор": "повтор умножает",
           "больше": "больше на — значит прибавить", "меньше": "меньше на — значит убавить"},
    "en": {"находка": "finding adds", "потеря": "losing takes away",
           "делёж": "sharing equally divides", "повтор": "repeating multiplies",
           "больше": "more by means adding", "меньше": "fewer by means taking away"},
}
# ОБОРОТ ОБЪЯВЛЕН ОДИН РАЗ И ЧИТАЕТСЯ И РАМКОЙ, И СУДОМ, И ВОПРОСОМ: закон, записанный
# дважды, расходится на второй правке.
РЕШАЮЩИЕ = {язык: {об: ЗНАК_РОДА[род] for род, об in таблица.items()}
            for язык, таблица in ОБОРОТ.items()}

# ВОПРОСНОЕ СЛОВО БЕРЁТСЯ У ПАКЕТА, А НЕ СОЧИНЯЕТСЯ: «какой» и «which» объявлены в `ask_words`.
ВОПРОС = {"ru": "какой знак нужен?", "en": "which sign is needed?"}

ИМЕНА = {
    "ru": ("Дима", "Иван", "Коля", "Петя", "Юра", "Марк", "Павел", "Глеб"),
    "en": ("Dan", "Ivan", "Mark", "Ben", "Felix", "Greg", "Hugo", "Kyle"),
}
# РОДИТЕЛЬНЫЙ ОБЪЯВЛЕН ПОИМЁННО, А НЕ ВЫВЕДЕН, И КУПЛЕН ОШИБКОЙ. Первая редакция писала
# «у Дима было 5 орехов» — предлог «у» требует родительного, а рамка ставила именительный.
# Вывести его правилом нельзя: «Дима» → «Димы», но «Иван» → «Ивана», «Павел» → «Павла» с
# беглой гласной. Таблица есть объявление руки, отвечающей за него.
РОДИТЕЛЬНЫЙ = {"Дима": "Димы", "Иван": "Ивана", "Коля": "Коли", "Петя": "Пети",
               "Юра": "Юры", "Марк": "Марка", "Павел": "Павла", "Глеб": "Глеба"}
assert set(РОДИТЕЛЬНЫЙ) == set(ИМЕНА["ru"]), "родительный объявлен не для всех имён"
ВЕЩИ = {
    "ru": (("орехов", "орехов"), ("книг", "книг"), ("монет", "монет"),
           ("шаров", "шаров"), ("яблок", "яблок")),
    "en": (("books", "books"), ("cards", "cards"), ("pages", "pages"),
           ("eggs", "eggs"), ("messages", "messages")),
}

# ЧИСЛО ПРИ ИМЕНИ ОБЯЗАНО БРАТЬ РОДИТЕЛЬНОЕ МНОЖЕСТВЕННОЕ (русский счёт).
def _родительное(n):
    return n % 100 in range(11, 15) or n % 10 in (0, 5, 6, 7, 8, 9)


РАМКИ = {
    "ru": {
        "находка": "у {род} было {a} {вещь}. он нашёл ещё {b}. находка прибавляет: {a} + {b} = {c}.",
        "потеря": "у {род} было {a} {вещь}. он потерял {b}. потеря убавляет: {a} − {b} = {c}.",
        "делёж": "{имя} разделил {a} {вещь} поровну между {b} друзьями. делёж поровну делит: {a} ÷ {b} = {c}.",
        "повтор": "{имя} взял {a} {вещь} {b} раза подряд. повтор умножает: {a} × {b} = {c}.",
        "больше": "у {род2} {a} {вещь}. у {род} на {b} больше. больше на — значит прибавить: {a} + {b} = {c}.",
        "меньше": "у {род2} {a} {вещь}. у {род} на {b} меньше. меньше на — значит убавить: {a} − {b} = {c}.",
    },
    "en": {
        "находка": "{имя} had {a} {вещь}. he found {b} more. finding adds: {a} + {b} = {c}.",
        "потеря": "{имя} had {a} {вещь}. he lost {b}. losing takes away: {a} − {b} = {c}.",
        "делёж": "{имя} shared {a} {вещь} equally among {b} friends. sharing equally divides: {a} ÷ {b} = {c}.",
        "повтор": "{имя} took {a} {вещь} {b} times over. repeating multiplies: {a} × {b} = {c}.",
        "больше": "{имя2} has {a} {вещь}. {имя} has {b} more. more by means adding: {a} + {b} = {c}.",
        "меньше": "{имя2} has {a} {вещь}. {имя} has {b} fewer. fewer by means taking away: {a} − {b} = {c}.",
    },
}
ПАРЫ = (("находка", "потеря"), ("делёж", "повтор"), ("больше", "меньше"))
ДЕЙСТВИЕ = {"находка": lambda a, b: a + b, "потеря": lambda a, b: a - b,
             "делёж": lambda a, b: a // b, "повтор": lambda a, b: a * b,
             "больше": lambda a, b: a + b, "меньше": lambda a, b: a - b}


def _числа():
    """(a, b) для каждой развилки — числа ОДНИ на обе страницы пары."""
    вон = {"находка": [], "делёж": [], "больше": []}
    for a in range(5, 40):
        if not _родительное(a):
            continue
        for b in range(2, 10):
            if a - b > 0 and len(вон["находка"]) < 24:
                вон["находка"].append((a, b))
            # «{b} раза» верно при 2–4; при пяти и больше русский требует «раз», и
            # рамка повтора взяла бы не ту форму. Развилка сужена ЧИСЛОМ, а не оговоркой.
            if a % b == 0 and 1 < b < 5 and a // b > 1 and len(вон["делёж"]) < 24:
                вон["делёж"].append((a, b))
            if a - b > 0 and b < 6 and len(вон["больше"]) < 24:
                вон["больше"].append((a, b))
    return вон


def страницы():
    """{строка: (язык, род)} — пары и вопросные показы, порождённые раз."""
    вон = {}
    числа = _числа()
    for язык in ЯЗЫКИ:
        имена, вещи = ИМЕНА[язык], ВЕЩИ[язык]
        for н, (первый, второй) in enumerate(ПАРЫ):
            for к, (a, b) in enumerate(числа[первый]):
                имя = имена[(н + к) % len(имена)]
                имя2 = имена[(н + к + 3) % len(имена)]
                вещь = вещи[(н + к) % len(вещи)][0]
                for род in (первый, второй):
                    c = ДЕЙСТВИЕ[род](a, b)
                    род_имя = РОДИТЕЛЬНЫЙ.get(имя, имя)
                    род_имя2 = РОДИТЕЛЬНЫЙ.get(имя2, имя2)
                    строка = РАМКИ[язык][род].format(имя=имя, имя2=имя2, род=род_имя,
                                                     род2=род_имя2, вещь=вещь, a=a, b=b, c=c)
                    вон[строка] = (язык, род)
                    # ВОПРОС ВСТАВЛЯЕТСЯ ПЕРЕД РЕШАЮЩИМ ОБОРОТОМ, а не по счёту точек:
                    # первая редакция резала по второй точке и на одном предложении давала
                    # «…делит: 27 ÷ 3 = 9.. какой знак нужен? » — хвост пустой, голова вся.
                    # МЕСТО РЕЗА ЕСТЬ ОБЪЯВЛЕННЫЙ ОБОРОТ, а не привычка страницы.
                    if к % 3 == 0:
                        оборот = ОБОРОТ[язык][род]
                        место = строка.index(оборот)
                        вон[строка[:место] + ВОПРОС[язык] + " " + строка[место:]] = (язык, род)
    return вон


ПОКАЗЫ = страницы()
_ЛЕДЖЕР = re.compile(r"(\d+) ([+−×÷]) (\d+) = (\d+)")
_СЧЁТ = {"+": lambda a, b: a + b, "−": lambda a, b: a - b,
         "×": lambda a, b: a * b, "÷": lambda a, b: a // b if b and a % b == 0 else None}


def судить(строка):
    """(судимо, истинно): знак леджера ТОТ, какого требует решающее слово, и счёт верен."""
    с = строка.strip()
    if not с:
        return False, False
    for язык, таблица in РЕШАЮЩИЕ.items():
        for оборот, знак in таблица.items():
            if оборот not in с:
                continue
            найдено = _ЛЕДЖЕР.search(с)
            if not найдено:
                return True, False      # решающее слово без леджера: довод без дела
            a, взят, b, ответ = найдено.groups()
            если = _СЧЁТ[взят](int(a), int(b))
            return True, взят == знак and если is not None and если == int(ответ)
    return False, False


def _самопроверка():
    """Подмена знака и подмена решающего слова обязаны ловиться обе."""
    беды = []
    for строка in ПОКАЗЫ:
        судимо, истинно = судить(строка)
        if not (судимо and истинно):
            беды.append(f"честная не прошла: {строка[:70]}")
    образец = "у Димы было 11 орехов. он потерял 9. потеря убавляет: 11 − 9 = 2."
    порчи = [
        образец.replace("11 − 9 = 2", "11 + 9 = 20"),          # знак не тот
        образец.replace("потеря убавляет", "находка прибавляет"),  # слово не то
        образец.replace("= 2", "= 3"),                          # счёт не тот
    ]
    for п in порчи:
        if судить(п)[1]:
            беды.append(f"порча прошла: {п[:70]}")
    print(f"ВЫБОР ДЕЙСТВИЯ: страниц {len(ПОКАЗЫ)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    import sys
    sys.exit(_самопроверка())
