                имя2 = имена[(н + к + 3) % len(имена)]
                лемма = вещи[(н + к) % len(вещи)]
                for род in (первый, второй):
                    c = ДЕЙСТВИЕ[род](a, b)
                    род_имя = РОДИТЕЛЬНЫЙ.get(имя, имя)
                    род_имя2 = РОДИТЕЛЬНЫЙ.get(имя2, имя2)
                    строка = РАМКИ[язык][род].format(
                        имя=имя, имя2=имя2, род=род_имя, род2=род_имя2,
                        вещь=вещь_при(язык, лемма, a), вещь_b=вещь_при(язык, лемма, b),
                        друзья=друзья_при(язык, b), a=a, b=b, c=c)
                    вон[строка] = (язык, род)
                    # ВОПРОС ВСТАВЛЯЕТСЯ ПЕРЕД РЕШАЮЩИМ ОБОРОТОМ, а не по счёту точек:
                    # первая редакция резала по второй точке и на одном предложении давала
