def _числа():
    """(a, b) для каждой развилки — числа ОДНИ на обе страницы пары."""
    вон = {"находка": [], "делёж": [], "больше": []}
    for a in range(5, 40):
        if not _родительное(a):
            continue
        for b in range(2, 10):
            if a - b > 0 and len(вон["находка"]) < 24:
                вон["находка"].append((a, b))
            # «{b} раза» верно при 2–4; при пяти и больше русский требует «раз», и
            # рамка повтора взяла бы не ту форму. Развилка сужена ЧИСЛОМ, а не оговоркой.
            if a % b == 0 and 1 < b < 5 and a // b > 1 and len(вон["делёж"]) < 24:
                вон["делёж"].append((a, b))
            if a - b > 0 and b < 6 and len(вон["больше"]) < 24:
                вон["больше"].append((a, b))
    return вон


