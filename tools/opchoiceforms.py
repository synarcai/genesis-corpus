_СЧЁТ = {"+": lambda a, b: a + b, "−": lambda a, b: a - b,
         "×": lambda a, b: a * b, "÷": lambda a, b: a // b if b and a % b == 0 else None}



# ПОРОЖДАЕМОСТЬ РАМКОЙ — ЗАКОН СИЛЬНЕЕ ТРЁХ ПРОВЕРОК ПОРОЗНЬ (09.09, вечер).
#
# Суд читал оборот, леджер, имя и падеж — четыре проверки, и каждая ловила своё. Приборы нашли
# пятое и шестое: подмену рода прошедшего («Иван разделила») и литеральное множественное
# («friends»). Дописывать проверку на всякую новую порчу значит гнаться за порчей.
#
#     СТРАНИЦА ЗАМКНУТОГО МИРА ИСТИННА, ЕСЛИ ЕЁ ПОРОЖДАЕТ ОБЪЯВЛЕННАЯ РАМКА. Всё, что рамка
#     не порождает, — ложь, и порчу искать поимённо больше не нужно.
#
# Тот же ход, каким закрыт пласт языков (`langgen_court`): дыры рамки суть объявленные ряды,
# а не «что угодно».
def _альт(слова):
    return "(?:" + "|".join(re.escape(с) for с in sorted(set(слова), key=lambda с: (-len(с), с))) + ")"



def _дыры(язык):
    """Объявленные ряды под каждую дыру рамки — общие для образца и для сличения по словам."""
    вещи_все = []
    for лемма in ВЕЩИ[язык]:
        вещи_все += [вещь_при(язык, лемма, n) for n in (1, 2, 5)]
    дыры = {
        "имя": _альт(ИМЕНА[язык]), "имя2": _альт(ИМЕНА[язык]),
        "род": _альт(РОДИТЕЛЬНЫЙ.values()), "род2": _альт(РОДИТЕЛЬНЫЙ.values()),
        "вещь": _альт(вещи_все), "вещь_b": _альт(вещи_все),
        "друзья": _альт(друзья_при(язык, n) for n in (2, 3, 4)),
        "a": r"\d+", "b": r"\d+", "c": r"\d+",
        "зн": r"\d+", "ушло": r"\d+", "осталось": r"\d+",
        "доля": _альт(д[0] for д in ДОЛИ[язык]),
        "первый": _альт(ОБОРОТ_ДОЛИ[язык][0].format(доля=д[0], слово=д[2]) for д in ДОЛИ[язык]),
        "второй": re.escape(ОБОРОТ_ДОЛИ[язык][1]),
    }
    return дыры


def _образцы():
    """Образец на (язык, род): дыры суть объявленные ряды, числа — цифры."""
    вон = []
    for язык in ЯЗЫКИ:
        дыры = _дыры(язык)
        рамки = list(РАМКИ[язык].items()) + [("доля", РАМКА_ДОЛИ[язык])]
        for род, рамка in рамки:
            куски = []
            for кусок in re.split(r"(\{[^}]+\})", рамка):
                куски.append(дыры[кусок[1:-1]] if кусок.startswith("{") else re.escape(кусок))
            тело = "".join(куски)
            # ВОПРОС СТОИ́Т ПЕРЕД РЕШАЮЩИМ ОБОРОТОМ, и образец обязан его допустить.
            оборот = ОБОРОТ[язык][род] if род != "доля" else ОБОРОТ_ДОЛИ[язык][0].format(
                доля=ДОЛИ[язык][0][0], слово=ДОЛИ[язык][0][2])
            место = тело.find(re.escape(оборот)) if род != "доля" else -1
            вон.append((re.compile(тело + "$"), язык, род))
            if род != "доля" and место >= 0:
                с_воп = тело[:место] + re.escape(ВОПРОС[язык] + " ") + тело[место:]
                вон.append((re.compile(с_воп + "$"), язык, род))
    return вон


ОБРАЗЦЫ = _образцы()


# ЛОЖЬ ПО ОДНОМУ СЛОВУ — ТРЕТИЙ ЗАКОН, МИРЯЩИЙ ДВА ПЕРВЫХ (09.09, ночь).
#
# Прибор [ЛОВУШКА НАЧАЛА] требует МОЛЧАНИЯ о строке, которой рамка не породила: удвоенная
# страница «X. X.» есть не показ и не ложь. Прибор [РОД ПРОШЕДШЕГО] требует ПРИГОВОРА над
# подменой рода: «Иван разделила» есть порча страницы, а не чужая строка. Оба закона верны,
# и мирит их третий:
#
#     СТРОКА, ОТЛИЧАЮЩАЯСЯ ОТ ПОРОЖДАЕМОЙ РОВНО ОДНИМ СЛОВОМ, ЕСТЬ ПОРЧА ЭТОЙ СТРАНИЦЫ.
#     Строка, отличающаяся целым куском, — не её дело, и о ней молчат.
#
# Признак берётся по СЛОВАМ рамки: дыра принимает свой объявленный ряд, прочее стои́т буквой.
# Удвоение даёт вдвое больше слов и до сличения не доходит; подмена рода даёт то же число
# слов при одном несовпавшем — и зовётся ложью.
def _слова_рамки(рамка, дыры):
    """Рамка по словам: (образец слова, есть ли дыра) для каждого слова."""
    вон = []
    for слово in рамка.split(" "):
        куски = []
        for кусок in re.split(r"(\{[^}]+\})", слово):
            куски.append(дыры[кусок[1:-1]] if кусок.startswith("{") else re.escape(кусок))
        вон.append(re.compile("".join(куски) + "$"))
    return вон


def _рамки_словами():
    вон = []
    for язык in ЯЗЫКИ:
        дыры = _дыры(язык)
        рамки = list(РАМКИ[язык].items()) + [("доля", РАМКА_ДОЛИ[язык])]
        for род, рамка in рамки:
            вон.append(_слова_рамки(рамка, дыры))
            оборот = (ОБОРОТ[язык][род] if род != "доля"
                      else ОБОРОТ_ДОЛИ[язык][0].format(доля=ДОЛИ[язык][0][0], слово=ДОЛИ[язык][0][2]))
            место = рамка.find(оборот)
            if род != "доля" and место >= 0:
                вон.append(_слова_рамки(рамка[:место] + ВОПРОС[язык] + " " + рамка[место:], дыры))
    return вон


РАМКИ_СЛОВАМИ = _рамки_словами()


def порча_одним_словом(строка):
    """Отличается ли строка от какой-нибудь рамки РОВНО ОДНИМ словом."""
    слова = строка.split(" ")
    for рамка in РАМКИ_СЛОВАМИ:
        if len(рамка) != len(слова):
            continue
        не_сошлось = sum(1 for о, с in zip(рамка, слова) if not о.match(с))
        if не_сошлось == 1:
            return True
    return False




def порождаема(строка):
    """Порождает ли строку хоть одна объявленная рамка."""
    return any(о.match(строка) for о, _, _ in ОБРАЗЦЫ)


def _обороты(с):
    """Все решающие обороты строки — (место, знак), по всем языкам."""
    вон = []
    for таблица in РЕШАЮЩИЕ.values():
        for оборот, знак in таблица.items():
            место = с.find(оборот)
            if место >= 0:
                вон.append((место, знак))
    for язык, (первый, второй) in ОБОРОТ_ДОЛИ.items():
        # ОБА ОБОРОТА ЦЕПИ, А НЕ ПЕРВЫЙ. Первая редакция брала у доли только оборот деления,
        # и подмена ВТОРОГО шага проходила целой: «ушедшее убавляет: 8 + 2 = 10». Цепь есть
        # два выбора, и суд обязан спросить об обоих — иначе он судит половину закона.
        for доля, зн, слово in ДОЛИ[язык]:
            место = с.find(первый.format(доля=доля, слово=слово))
            if место >= 0:
                вон.append((место, "÷"))
        место = с.find(второй)
        if место >= 0:
            вон.append((место, "−"))
    return sorted(вон)


def судить(строка):
    """(судимо, истинно): страницу судит РАМКА, а всё прочее оставлено МОЛЧАНИЮ.

    СТРОКА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ЕЙ ПРОСТО НЕЧЕГО СКАЗАТЬ.
    Прибор [ЛОВУШКА НАЧАЛА] назвал здесь сорок проб из сорока: суд читал решающий оборот и,
    не найдя рамки, звал строку ложной — а удвоенная страница «X. X.» есть не показ и не ложь.

        СУД ПО НАЧАЛУ СТРОКИ ЕСТЬ ЛОВУШКА, ВЗВЕДЁННАЯ НА БУДУЩЕЕ: он молчит ровно до дня,
        когда сосед напишет свою первую строку, начинающуюся объявленным словом, — и тогда
        ломает не себя, а СОСЕДА, чья строка честна.

    Ложь о СВОЁМ мире говорит не этот суд, а ЗАМЫКАНИЕ (`closedworld.замкнуть` в суде дома):
    молчание о строке замкнутого мира и есть его ложь. Тот же ход держит пласт языков.
    """
    с = строка.strip()
    if not с:
        return False, False
    if not порождаема(с):
        # ЛОЖЬ ПО ОДНОМУ СЛОВУ: страница, разошедшаяся с рамкой ровно одним словом, есть
        # ПОРЧА ЭТОЙ страницы; разошедшаяся целым куском — не её дело.
        return (True, False) if порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРОКУ — ОСТАЛСЯ СЧЁТ: числа в рамке стоя́т дырами, и всякий решающий
    # оборот отвечает за СВОЙ леджер, тот, что стои́т за ним ближе прочих.
    места = _обороты(с)
    леджеры = [(м.start(), м.groups()) for м in _ЛЕДЖЕР.finditer(с)]
    for место, знак in места:
        свой = next((г for н, г in леджеры if н > место), None)
        if свой is None:
            return True, False
        a, взят, b, ответ = свой
        было = _СЧЁТ[взят](int(a), int(b))
        if взят != знак or было is None or было != int(ответ):
            return True, False
    return True, True


def _самопроверка():
    """Подмена знака и подмена решающего слова обязаны ловиться обе."""
    беды = []
    for строка in ПОКАЗЫ:
        судимо, истинно = судить(строка)
        if not (судимо and истинно):
            беды.append(f"честная не прошла: {строка[:70]}")
    образец = "у Димы было 11 орехов. он потерял 9. потеря убавляет: 11 − 9 = 2."
    порчи = [
        образец.replace("11 − 9 = 2", "11 + 9 = 20"),          # знак не тот
        образец.replace("потеря убавляет", "находка прибавляет"),  # слово не то
        образец.replace("= 2", "= 3"),                          # счёт не тот
    ]
    # ЦЕПЬ ПРОВЕРЯЕТСЯ ОБОИМИ ШАГАМИ, И ЭТО КУПЛЕНО ДЫРОЙ: первая редакция суда брала у доли
    # лишь оборот деления, и подмена ВТОРОГО шага проходила целой.
    # ОБРАЗЕЦ ЦЕПИ БЕРЁТСЯ ИЗ САМИХ ПОКАЗОВ, А НЕ ПИШЕТСЯ ЛИТЕРАЛОМ: литерал устарел на первой
    # же правке рамки и объявил честную страницу непрошедшей.
    цепь = next(с for с, (_, р) in ПОКАЗЫ.items() if р == "доля")
    if not судить(цепь)[1]:
        беды.append(f"честная цепь не прошла: {цепь[:70]}")
    порчи += [
        образец.replace("Димы", "Дим"),               # обрезанное имя лица
        "Иван разделила 6 книг поровну между 2 друзьями. делёж поровну делит: 6 ÷ 2 = 3.",
        "Ivan shared 6 books equally among 2 friend. sharing equally divides: 6 ÷ 2 = 3.",
        цепь.replace("Димы", "Дим"),                  # то же в цепи
        цепь.replace("8 ÷ 4 = 2", "8 × 4 = 32"),      # первый шаг: знак
        цепь.replace("8 − 2 = 6", "8 + 2 = 10"),      # ВТОРОЙ шаг: знак
        цепь.replace("8 − 2 = 6", "8 − 2 = 7"),       # второй шаг: счёт
    ]
    for п in порчи:
        if судить(п)[1]:
            беды.append(f"порча прошла: {п[:70]}")
    print(f"ВЫБОР ДЕЙСТВИЯ: страниц {len(ПОКАЗЫ)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


