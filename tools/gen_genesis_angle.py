#!/usr/bin/env python3
"""GENESIS layer: СУММА УГЛОВ — see tools/angleforms.py for the law.

ПОСТОЯНСТВО И ЕГО ГРАНИЦА ИДУТ ОДНОЙ ГРУППОЙ: «иной треугольник — та же сумма» и «у
четырёхугольника 360». Показанное порознь, первое переносится на всякую фигуру, второе
читается как рост суммы с размером.

    ПОСТОЯНСТВО, ПОКАЗАННОЕ БЕЗ СВОЕЙ ГРАНИЦЫ, ЧИТАЕТСЯ КАК ВСЕОБЩЕЕ.

ОБЩИЙ ЗАКОН И ЕГО СЛЕДСТВИЯ — одной группой: «(n − 2) × 180», третий угол по двум и два
острых при прямом суть одно правило, спрошенное с разных сторон. ГРАНИЦА НЕВОЗМОЖНОГО стои́т
отдельно: она есть СЛЕДСТВИЕ СЧЁТА, а не ещё один случай. ВОПРОС отдельно.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import angleforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_angle.txt"
ГРУППЫ = (("сумма треугольника", "иной треугольник", "четырёхугольник"),
          ("многоугольник", "третий по двум", "два острых при прямом"),
          ("двух прямых не бывает",),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
