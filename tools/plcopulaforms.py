def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, имена = РАМКИ[язык], ИМЯ_РОДА[язык]
        for пл, ру, ан in ПАРЫ:
            род = plgram.РОД[пл]
            общ = dict(
                ф1=plgram.форма(пл, 1), ф2=plgram.форма(пл, 2), ф5=plgram.форма(пл, 5),
                с1=plgram.связка("наст", 1), с2=plgram.связка("наст", 2),
                с5=plgram.связка("наст", 5),
                п1=plgram.связка("прош", 1, род), п2=plgram.связка("прош", 2, род),
                п5=plgram.связка("прош", 5, род),
                род=имена[род], перевод=ру if язык == "ru" else ан,
                рф5=rugram.форма(ру, 5))
            for род_страницы in РОДЫ:
                вон[рамки[род_страницы].format(**общ)] = (язык, род_страницы)
    return вон


ПОКАЗЫ = страницы()


# СУД ЧИТАЕТ ТРОЙКУ «ЧИСЛО + ИМЯ + СВЯЗКА» И СВЕРЯЕТ ЕЁ С ДОМОМ ЯЗЫКА.
# ВЫБОР ЧИТАЕТСЯ ПО ПЕРВОЙ ПОДХОДЯЩЕЙ ВЕТВИ, А НЕ ПО ДЛИННЕЙШЕЙ, И ГРАНИЦА СЛОВА ОБЯЗАТЕЛЬНА:
# без неё «było» читается как «był», и суд зовёт ложью верную страницу. Поймано пробою в час
# написания — ровно тем случаем, ради которого проба и ставится.
#
#     ОБРАЗЕЦ БЕЗ ГРАНИЦЫ СЛОВА ЧИТАЕТ НАЧАЛО ЧУЖОГО СЛОВА КАК СВОЁ.
_ТРОЙКА = _re.compile(r"(\d+)\s+([a-ząćęłńóśźż]+)\s+(jest|są|była|było|były|był)\b", _re.UNICODE)
_ПАРА_ИМЕНИ = _re.compile(r"(\d+)\s+([a-ząćęłńóśźż]+)", _re.UNICODE)
_ИМЕНА = {пл for пл, _, _ in ПАРЫ}
_ФОРМЫ_ИМЕНИ = {}
for _пл in _ИМЕНА:
    for _n in range(1, 101):
        _ФОРМЫ_ИМЕНИ.setdefault(plgram.форма(_пл, _n), set()).add(_пл)


_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая пара «число + имя + связка» в ней сходится с законом.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА. Два соседних дома этой же
    ночи звали ложью чужую прозу — сноску у Бердяева, письмо Чаадаева, — оттого что судили ПО
    ПРИЗНАКУ, а не по принадлежности к своему набору. Здесь идиома взята сразу верная.

        СУД, ЧИТАЮЩИЙ ПО ПРИЗНАКУ, А НЕ ПО ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, ЗОВЁТ ЛОЖЬЮ ЧУЖУЮ
        РЕЧЬ, СОВПАВШУЮ С НИМ ФОРМОЙ.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    пары = [(int(n), сл) for n, сл in _ПАРА_ИМЕНИ.findall(с) if сл in _ФОРМЫ_ИМЕНИ]
    if not пары:
        return True, True
    for n, сл in пары:
        if not any(plgram.форма(пл, n) == сл for пл in _ФОРМЫ_ИМЕНИ[сл]):
            return True, False
    for n, сл, связка in _ТРОЙКА.findall(строка):
        n = int(n)
        if сл not in _ФОРМЫ_ИМЕНИ:
            continue
        свои = {plgram.связка("наст", n)} | {
            plgram.связка("прош", n, plgram.РОД[пл]) for пл in _ФОРМЫ_ИМЕНИ[сл]}
        if связка not in свои:
            return True, False
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:100])
            беды += 1
    # МУТАНТ ЕСТЬ ПОРЧА СВОЕЙ СТРАНИЦЫ ОДНИМ СЛОВОМ: связка меняется на связку ДРУГОЙ ячейки,
    # число слов сохраняется. Проба на выдуманной строке проверяла бы признак, а не суд.
    мутантов = 0
    подмены = (("jest", "są"), ("są", "jest"), ("było", "były"), ("były", "było"))
    for показ in ПОКАЗЫ:
        порча = None
        слова = показ.split(" ")
        for i, сл in enumerate(слова):
            голое = сл.strip(".,:;«»?!")
            for свой, чужой in подмены:
                if голое == свой:
                    порча = " ".join(слова[:i] + [сл.replace(свой, чужой)] + слова[i + 1:])
                    break
            if порча:
                break
        if not порча or порча == показ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:100])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    for чужая in ("w słowniku stoi 5 książek jest, i to nie jest pokaz tego domu wcale.",
                  "он выписал «2 książki są» на поля, и это не страница дома."):
        if судить(чужая) != (False, False):
            print("  ЧУЖАЯ РЕЧЬ СУДИМА:", чужая[:100])
            беды += 1
    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, мутантов поймано {мутантов}, "
          f"пар имён {len(ПАРЫ)}, бед {беды}")
    return беды



