def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, ряд = РАМКИ[язык], СТОРОНЫ[язык]
        цеп = lambda путь: " → ".join(путь)
        for сторона in ряд:
            for род, поворот in (("направо", "направо"), ("налево", "налево"),
                                 ("кругом", "кругом")):
                b, путь = куда(язык, сторона, (поворот,))
                вон[рамки[род].format(a=сторона, b=b, цепь=цеп(путь))] = (язык, род)
            _b, путь = куда(язык, сторона, ("направо",) * 4)
            вон[рамки["четыре поворота"].format(цепь=цеп(путь))] = (язык, "четыре поворота")
            b, путь = куда(язык, сторона, ("налево",))
            род = "налево и есть запад" if сторона == ряд[0] else "налево не есть запад"
            вон[рамки[род].format(a=сторона, b=b, цепь=цеп(путь))] = (язык, род)
            b, путь = куда(язык, сторона, ("направо",))
            вон[рамки["спрошенное"].format(
                a=сторона, b=b, п1=_пер("направо", язык), цепь=цеп(путь))] = (язык, "спрошенное")
            for п1, п2 in ПАРЫ:
                b, путь = куда(язык, сторона, (п1, п2))
                вон[рамки["сложение поворотов"].format(
                    a=сторона, b=b, п1=_пер(п1, язык), п2=_пер(п2, язык), цепь=цеп(путь),
                    итог=ИТОГИ[язык][п1 != п2])] = (язык, "сложение поворотов")
            for п1, п2, п3 in ТРОЙКИ:
                b, путь = куда(язык, сторона, (п1, п2, п3))
                вон[рамки["путь из поворотов"].format(
                    a=сторона, b=b, п1=_пер(п1, язык), п2=_пер(п2, язык), п3=_пер(п3, язык),
                    цепь=цеп(путь))] = (язык, "путь из поворотов")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ВСЕ_СТОРОНЫ = [с for ряд in СТОРОНЫ.values() for с in ряд]
_ЦЕПЬ = re.compile("(?:" + "|".join(_ВСЕ_СТОРОНЫ) + r")(?: → (?:"
                   + "|".join(_ВСЕ_СТОРОНЫ) + "))+")
# ПОВОРОТ БЕРЁТСЯ ЛИШЬ СТРОЧНЫМ: прописное написание есть РЕЧЬ О ПОВОРОТЕ, а не поворот.
_ПОВОРОТ = re.compile(r"(?<![^\W\d_])(" + "|".join(
    п for г in ПОВОРОТЫ.values() for п in г) + r")(?![^\W\d_])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка И
    ЕСЛИ ЦЕПЬ СТОРОН ПЕРЕСЧИТЫВАЕТСЯ ПО НАЗВАННЫМ В НЕЙ ЖЕ ПОВОРОТАМ.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать;
    ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    язык = ПОКАЗЫ[с][0]
    повороты = [ПОВОРОТЫ["ru"].get(п, ПОВОРОТЫ["en"].get(п)) for п in _ПОВОРОТ.findall(с)]
    for цепь in _ЦЕПЬ.findall(с):
        звенья = цепь.split(" → ")
        шагов = len(звенья) - 1
        # ОДИН НАЗВАННЫЙ ПОВОРОТ НА НЕСКОЛЬКО ЗВЕНЬЕВ ЕСТЬ ТОТ ЖЕ ПОВОРОТ, ПОВТОРЁННЫЙ:
        # так писан род четырёх поворотов, и иначе его не сказать одним словом.
        если = повороты if len(повороты) == шагов else (
            повороты * шагов if len(повороты) == 1 else None)
        if если is None:
            return True, False
        ряд = СТОРОНЫ[язык]
        if any(з not in ряд for з in звенья):
            return True, False
        i = ряд.index(звенья[0])
        for шаг, п in zip(звенья[1:], если):
            i = (i + п) % 4
            if ряд[i] != шаг:
                return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ОБЕ СТОРОНЫ ЛОВУШКИ ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ, И НЕСОВПАДЕНИЕ ОБЯЗАНО ПЕРЕВЕШИВАТЬ.
    for язык in ЯЗЫКИ:
        совпало = по_роду.get((язык, "налево и есть запад"), 0)
        нет = по_роду.get((язык, "налево не есть запад"), 0)
        if not совпало or not нет:
            беды.append(f"показана лишь одна сторона ловушки [{язык}]")
        if совпало != 1 or нет != 3:
            беды.append(f"доли ловушки [{язык}]: совпало {совпало}, нет {нет} — надо 1 и 3")
    # СЧЁТ ПОВОРОТОВ ПРОВЕРЯЕТСЯ НА ЗАВЕДОМО ИЗВЕСТНОМ, А НЕ ТОЛЬКО НА СВОИХ СТРАНИЦАХ.
    for сторона, ряд_п, ждём in (("север", ("направо",), "восток"),
                                 ("север", ("налево",), "запад"),
                                 ("юг", ("налево",), "восток"),
                                 ("запад", ("кругом",), "восток"),
                                 ("восток", ("направо",) * 4, "восток"),
                                 ("юг", ("налево", "направо"), "юг")):
        дало = куда("ru", сторона, ряд_п)[0]
        if дало != ждём:
            беды.append(f"счёт поворотов: {сторона} + {ряд_п} = {дало}, а надо {ждём}")
    # ПРОПИСНОЕ НАПИСАНИЕ НЕ ЕСТЬ ПОВОРОТ, И ЭТО ПРОВЕРЯЕТСЯ ПРЯМО.
    если = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "налево не есть запад")
    if len(_ПОВОРОТ.findall(если)) != 1:
        беды.append(f"прописное «НАЛЕВО» сочтено поворотом: {_ПОВОРОТ.findall(если)}")
    # МУТАНТ ПО СТОРОНЕ В КАЖДОМ РОДЕ: подмена звена цепи обязана быть названа ложью.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"→ (\w+)", страница)
        if not m:
            беды.append(f"в роде {род} нет цепи")
            continue
        чужая = next(с for с in СТОРОНЫ["ru"] if с != m.group(1))
        порча = страница[:m.start(1)] + чужая + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённая сторона прошла в роде {род}: {порча[:70]}")
    # МУТАНТ ПО ПОВОРОТУ: та же цепь при ином названном повороте есть ложь.
    пр = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "направо")
    порча = пр.replace("повернул направо", "повернул налево", 1)
    if судить(порча)[1] is not False:
        беды.append(f"подменённый поворот прошёл: {порча[:70]}")
    if судить(пр + " " + пр)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"СТОРОНЫ И ПОВОРОТЫ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


