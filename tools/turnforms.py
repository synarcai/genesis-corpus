def _пер(слово, язык):
    """Русское имя поворота, сказанное языком пласта."""
    return слово if язык == "ru" else list(ПОВОРОТЫ["en"])[list(ПОВОРОТЫ["ru"]).index(слово)]


def куда(язык, сторона, повороты):
    """Сторона, на которую смотрят после ряда поворотов, и весь путь звеньями."""
    ряд = СТОРОНЫ[язык]
    i = ряд.index(сторона)
    путь = [сторона]
    for п in повороты:
        i = (i + ПОВОРОТЫ["ru"][п]) % 4
        путь.append(ряд[i])
    return ряд[i], путь


