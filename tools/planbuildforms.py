#!/usr/bin/env python3
"""ДОМ ПЛАНА — приказ, отчёт сборки и вердикт по коду выхода.

Мир `plan` (576 строк) был последним из тринадцати, чей дом объявлял роды без страниц — вернее,
дома у него не было вовсе: `planforms` носит похожее имя, а кормит ИНОЙ мир, и страницы его с
этим миром не сходятся ни одной.

    ИМЯ ДОМА, ПОХОЖЕЕ НА ИМЯ МИРА, НЕ ЕСТЬ СВЯЗЬ С НИМ. Указатель ищет связь по ввозу кузницы,
    и он был прав, не находя её здесь.

ЧЕТЫРЕ РОДА, И ВСЕ ЧЕТЫРЕ БЫЛИ В КУЗНИЦЕ С ПЕРВОГО ДНЯ:

    приказ и вердикт     «собери проект … — сборка удалась.»
    код выхода           «… — какой exit у сборки? 1.»
    число запусков       «… — сколько запусков? 1.»
    условие посадки      «если exit равен нулю, посажено … — посажено ли? нет: exit 1 ≠ 0.»
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import actturn as A  # noqa: E402
import planlang as P  # noqa: E402

# ТАБЛИЦЫ ПЕРЕЕХАЛИ ВМЕСТЕ СО СТРОИТЕЛЕМ: акты, коды выхода и миллисекунды суть материал
# дома, а не кузницы, и оставить их там значило бы дать дому строителя без сырья.
АКТЫ = ("создать", "удалить", "прочитать", "дописать")
ФАЙЛОВ_ПОСЛЕ = {"создать": 1, "удалить": 0, "прочитать": 1, "дописать": 1}
ВЫХОДЫ = (0, 1, 2, 3)
МИЛЛИ = (700, 900, 1200, 450)
УСЛОВНОЕ = 0          # условие всякой страницы: exit = 0

def _отчёт(с, файлов, запусков, выход, милли):
    return (f"{с['отчёт']}: files {файлов}, runs {запусков}, "
            f"exit {выход}, millis {милли}")


def страницы(язык, акт, файл, выход, милли):
    с = P.СЛОВА[язык]
    приказ_акта = A.ГЛАГОЛЫ[язык][акт][0]
    файлов = ФАЙЛОВ_ПОСЛЕ[акт]
    посажено = выход == УСЛОВНОЕ
    вердикт = с["посажено"] if посажено else с["не_посажено"]
    условие = с["условие"].format(v=УСЛОВНОЕ, посади=с["посади"])
    приказ = (f"{приказ_акта} {с['файл']} {файл}. {с['затем']} {с['запусти']}. "
              f"{условие}.")
    отчёт = _отчёт(с, файлов, 1, выход, милли)
    # ВОПРОС СТОИ́Т В ОДНОМ ПРЕДЛОЖЕНИИ С ЛЕДЖЕРОМ, А НЕ ЗА ТОЧКОЙ ОТ НЕГО.
    #
    # Палата зачитывает строку лишь тогда, когда покрыто КАЖДОЕ её предложение; «¿aterrizó?
    # no.» в одиночку не проверить ничем — леджера в нём нет. Ворота записи назвали это
    # несудимостью двухсот страниц, и правильно назвали:
    #
    #     ВОПРОС, ОТОРВАННЫЙ ОТ СВОЕГО ЛЕДЖЕРА ТОЧКОЙ, НЕПРОВЕРЯЕМ. Тире держит их в одном
    #     предложении, и суд читает вопрос вместе с тем, чем он проверяется.
    return [
        f"{приказ} {отчёт} — {вердикт}.",
        f"{отчёт} — {с['какой_exit']} {выход}.",
        f"{отчёт} — {с['сколько_запусков']} 1.",
        # ОТВЕТ НЕСЁТ СВОЁ ОСНОВАНИЕ, А НЕ ОДНО СЛОВО.
        #
        # Палата режет строку по вопросительному знаку, и голое «no.» не читает никто — ни
        # мой суд, ни чужой: в нём нечего проверить. Ворота назвали это несудимостью 56
        # испанских страниц (русское «нет.» проходило по счастливой случайности — его читал
        # сосед). Ответ со сличением — «нет: exit 2 ≠ 0» — проверяем САМ ПО СЕБЕ.
        #
        #     ОТВЕТ, НЕ НЕСУЩИЙ СВОЕГО ОСНОВАНИЯ, ПРОВЕРЯЕМ ТОЛЬКО СОСЕДОМ ПО СТРОКЕ. Стои́т
        #     палате разрезать строку — и он становится словом без опоры.
        f"{условие}. {отчёт} — {с['посажено_ли']} "
        f"{с['да'] if посажено else с['нет']}: exit {выход} "
        f"{'=' if посажено else '≠'} {УСЛОВНОЕ}.",
    ]


def pass_shows(pass_i):
    out = []
    k = 0
    for язык in P.СЛОВА:
        for акт in АКТЫ:
            for i, выход in enumerate(ВЫХОДЫ):
                файл = A.ФАЙЛЫ[(АКТЫ.index(акт) + i) % len(A.ФАЙЛЫ)]
                милли = МИЛЛИ[(i + АКТЫ.index(акт)) % len(МИЛЛИ)]
                k += 1
                if k % len(PASSES) != pass_i:
                    continue
                out.extend(страницы(язык, акт, файл, выход, милли))
    return out

# ------------------------------------------------------------------ ОБЪЯВЛЕНИЕ ДОМА

РОДЫ = ("приказ и вердикт", "код выхода", "число запусков", "условие посадки")

ЗАЧЕМ_РОДА = {
    "приказ и вердикт": "приказ сборки и её вердикт в одном показе",
    "код выхода": "отчёт и вопрос о коде выхода — в одном предложении с леджером",
    "число запусков": "отчёт и вопрос о числе запусков",
    "условие посадки": "условие на код выхода и ответ с основанием: exit = 0 или ≠ 0",
}

# РОД-УПРАЖНЕНИЕ ОБЪЯВЛЕН ВСЛУХ (14.09, ключ `--свод`: решено по КАЖДОМУ роду
# дома). Три рода этого дома суть чтение ОДНОГО отчёта при разных числах: exit, число запусков,
# условие посадки — мысль в каждом одна, числа при ней материал. Род «приказ и вердикт» (144
# страницы на 144 очертания) РОВЕН СОБОЮ: там перебираются САМИ ПРИКАЗЫ — удали файл, запусти
# сборку, — и всякая страница несёт свой.
#
#     РОД РОВЕН САМ СОБОЮ, КОГДА ЕГО МАТЕРИАЛ МНОГОМЕРЕН.
ОЧЕРТАНИЕ_ПО_ПРИРОДЕ = ("код выхода",
                        "число запусков",
                        "условие посадки",)
РОВНЫ_СОБОЮ = ("приказ и вердикт",)


def _меченые(язык, акт, файл, выход, милли):
    """[(страница, род)] — те же четыре страницы, каждая под своим именем."""
    return list(zip(страницы(язык, акт, файл, выход, милли), РОДЫ))


def перебор_страниц(шаг):
    from layer import PASSES                              # noqa: PLC0415
    вон, k = [], 0
    for язык in P.СЛОВА:
        for акт in АКТЫ:
            for i, выход in enumerate(ВЫХОДЫ):
                файл = A.ФАЙЛЫ[(АКТЫ.index(акт) + i) % len(A.ФАЙЛЫ)]
                милли = МИЛЛИ[(i + АКТЫ.index(акт)) % len(МИЛЛИ)]
                k += 1
                if k % len(PASSES) != шаг:
                    continue
                вон.extend(_меченые(язык, акт, файл, выход, милли))
    return вон


def страницы_прохода(шаг):
    """Ряд строк без меток — ровно то, чем кормится кузница."""
    return [с for с, _р in перебор_страниц(шаг)]


def группы(шаг):
    """Одна группа: мир куётся `emit`, а не `emit_grouped`."""
    return [страницы_прохода(шаг)]


def _показы():
    """Словарь ПОСТРОЧНО: свод построчен, а показ бывает многострочен."""
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор_страниц(шаг):
            for строка in с.split("\n"):
                if строка.rstrip():
                    вон.setdefault(строка.rstrip(), род)
    return вон


ПОКАЗЫ = _показы()


def _самопроверка_страниц():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    assert all("\n" not in к for к in ПОКАЗЫ), "словарь показов обязан быть построчным"
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка_страниц()
