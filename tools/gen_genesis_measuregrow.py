#!/usr/bin/env python3
"""GENESIS layer: РОСТ МЕРЫ — see tools/measuregrowforms.py for the law.

ПЛОЩАДЬ И ОБЪЁМ ИДУТ ОДНОЙ ГРУППОЙ: обе о том, что мера растёт СТЕПЕНЬЮ, а не разом с
длиной, и вторая есть первая, поднятая на одну ступень. Порознь читатель выучил бы
«вчетверо» как свойство площади, а не как второй шаг лестницы.

ПЕРИМЕТР И ПЛОЩАДЬ — второй группой, и они ЗЕРКАЛЬНЫ: одна мера не определяет другой ни в
ту, ни в другую сторону. Показать одну сторону значило бы дать правило «периметр свободен,
а площадь связана» либо обратное, и оба были бы ложны.

    ЛОВУШКА, ПОКАЗАННАЯ ОДНОЙ СТОРОНОЙ, УЧИТ НОВОЙ ЛОВУШКЕ.

ВОПРОС отдельно — ответ рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import measuregrowforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_measuregrow.txt"
# ЛИНЕЙНОЕ И КВАДРАТИЧНОЕ — ОДНОЙ ГРУППОЙ, И ЭТО ОБЕ СТОРОНЫ ОДНОЙ ЛОВУШКИ: показанное
# порознь, «площадь вчетверо» учит учетверять и периметр, а «периметр вдвое» — удваивать и
# площадь.
ГРУППЫ = (("сторона и площадь", "сторона и периметр", "ребро и объём"),
          ("один периметр разные площади", "одна площадь разные периметры"),
          ("квадрат наибольший", "почему так"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
