#!/usr/bin/env python3
"""ПОЛЬСКОЕ СОГЛАСОВАНИЕ ПО СЧЁТУ: тот же дом, что у русского, для своего языка.

Голландский вошёл в дом страниц действия парой «один / много» и тем открыл
себе миры сочленений и связок. Польский так войти НЕ МОГ: у него ТРИ формы при
числе, как у русского, —

    1 piłka · 2 piłki · 5 piłek

— и пара «один/много» сказала бы о нём ложь при всяком числе от двух до
четырёх. Долг был назван вслух и вот погашен.

ПРАВИЛО (объявлено, а не выведено): единица — именительный единственного;
две-четыре, кроме тринадцати-четырнадцати сотенного остатка, — именительный
множественного; всё прочее, включая ноль, пять и подростков, — родительный
множественного. Это ТО ЖЕ правило, что у русского, и совпадение здесь не
случайно: оба языка славянские, — но объявлено оно всё равно порознь, ибо
совпадение правил не есть тождество языков, и день, когда они разойдутся,
не должен стоить правки в чужом доме.

ТРОЙКИ ФОРМ ОБЪЯВЛЕНЫ ЗДЕСЬ — их нельзя вывести, их знают.

    python3 tools/plgram.py    # самопроверка
"""

# лемма → (именительный единственного, именительный множественного, родительный множественного)
СЧЁТНЫЕ = {
    "moneta": ("moneta", "monety", "monet"),
    "piłka": ("piłka", "piłki", "piłek"),
    "książka": ("książka", "książki", "książek"),
    "jabłko": ("jabłko", "jabłka", "jabłek"),
    "jajko": ("jajko", "jajka", "jajek"),
    "kwiat": ("kwiat", "kwiaty", "kwiatów"),
    "karta": ("karta", "karty", "kart"),
    "długopis": ("długopis", "długopisy", "długopisów"),
    "rzecz": ("rzecz", "rzeczy", "rzeczy"),
    "dzień": ("dzień", "dni", "dni"),
    "godzina": ("godzina", "godziny", "godzin"),
    "minuta": ("minuta", "minuty", "minut"),
}


def индекс(счёт):
    """0 — единица, 1 — две-четыре, 2 — прочее (включая ноль и подростков)."""
    сотня, десяток = счёт % 100, счёт % 10
    if десяток == 1 and сотня != 11:
        return 0
    if 2 <= десяток <= 4 and not 12 <= сотня <= 14:
        return 1
    return 2


def форма(ключ, счёт):
    """Форма леммы при числе; лемма, которой дом не знает, есть ошибка вызова."""
    тройка = СЧЁТНЫЕ.get(ключ)
    if тройка is None:
        raise KeyError(f"полская лемма не объявлена: {ключ}")
    return тройка[индекс(счёт)]


def _самопроверка():
    случаи = ((1, 0), (2, 1), (4, 1), (5, 2), (11, 2), (12, 2), (14, 2), (21, 0),
              (22, 1), (25, 2), (101, 0), (112, 2), (0, 2))
    for счёт, ждём in случаи:
        assert индекс(счёт) == ждём, (счёт, индекс(счёт), ждём)
    for ключ in СЧЁТНЫЕ:
        assert len(СЧЁТНЫЕ[ключ]) == 3, ключ
    for n in (1, 2, 5, 21, 22, 25, 12):
        print(f"  {n:3} {форма('piłka', n):8} {форма('jabłko', n):8} {форма('dzień', n)}")
    print(f"  лемм объявлено: {len(СЧЁТНЫЕ)}; случаев правила проверено: {len(случаи)}")


if __name__ == "__main__":
    _самопроверка()
