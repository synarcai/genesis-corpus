#!/usr/bin/env python3
"""ПОЛЬСКОЕ СОГЛАСОВАНИЕ ПО СЧЁТУ: тот же дом, что у русского, для своего языка.

Голландский вошёл в дом страниц действия парой «один / много» и тем открыл
себе миры сочленений и связок. Польский так войти НЕ МОГ: у него ТРИ формы при
числе, как у русского, —

    1 piłka · 2 piłki · 5 piłek

— и пара «один/много» сказала бы о нём ложь при всяком числе от двух до
четырёх. Долг был назван вслух и вот погашен.

ПРАВИЛО (объявлено, а не выведено): единица — именительный единственного;
две-четыре, кроме тринадцати-четырнадцати сотенного остатка, — именительный
множественного; всё прочее, включая ноль, пять и подростков, — родительный
множественного. Это ТО ЖЕ правило, что у русского, и совпадение здесь не
случайно: оба языка славянские, — но объявлено оно всё равно порознь, ибо
совпадение правил не есть тождество языков, и день, когда они разойдутся,
не должен стоить правки в чужом доме.

ТРОЙКИ ФОРМ ОБЪЯВЛЕНЫ ЗДЕСЬ — их нельзя вывести, их знают.

    python3 tools/plgram.py    # самопроверка
"""
import re as _re

# лемма → (именительный единственного, именительный множественного, родительный множественного)
СЧЁТНЫЕ = {
    "moneta": ("moneta", "monety", "monet"),
    "piłka": ("piłka", "piłki", "piłek"),
    "książka": ("książka", "książki", "książek"),
    "jabłko": ("jabłko", "jabłka", "jabłek"),
    "jajko": ("jajko", "jajka", "jajek"),
    "kwiat": ("kwiat", "kwiaty", "kwiatów"),
    "karta": ("karta", "karty", "kart"),
    "długopis": ("długopis", "długopisy", "długopisów"),
    "rzecz": ("rzecz", "rzeczy", "rzeczy"),
    "dzień": ("dzień", "dni", "dni"),
    "godzina": ("godzina", "godziny", "godzin"),
    "minuta": ("minuta", "minuty", "minut"),
    # ЧАСТИ ТЕЛА И ПРЕДМЕТОВ (04.09, мир природы)
    "noga": ("noga", "nogi", "nóg"),
    "łapa": ("łapa", "łapy", "łap"),
    "skrzydło": ("skrzydło", "skrzydła", "skrzydeł"),
    "palec": ("palec", "palce", "palców"),
    "koło": ("koło", "koła", "kół"),
    "ząb": ("ząb", "zęby", "zębów"),
    "ręka": ("ręka", "ręce", "rąk"),
    "oko": ("oko", "oczy", "oczu"),
    "kolor": ("kolor", "kolory", "kolorów"),
    "planeta": ("planeta", "planety", "planet"),
    "serce": ("serce", "serca", "serc"),
    "stopień": ("stopień", "stopnie", "stopni"),
}


def индекс(счёт):
    """0 — ровно единица, 1 — две-четыре (кроме 12–14), 2 — прочее (ноль, подростки, 21, 101).

    ПОЛЬСКИЙ НЕ РУССКИЙ ПРИ ДВАДЦАТИ ОДНОМ (05.09, суд согласования на седьмой точке:
    «21 kwiat», «31 moneta», «61 długopis» — 23 настоящих ошибки в связках и стыках).
    По-русски 21 берёт единственное число («21 монета»); по-польски единственное
    берёт только ровно 1 («1 moneta»), а 21, 31, 101 — родительный множественного
    («21 monet», «101 monet»), как и пакет pl объявляет ({"in": [1]} → one).
    """
    сотня, десяток = счёт % 100, счёт % 10
    if счёт == 1:
        return 0
    if 2 <= десяток <= 4 and not 12 <= сотня <= 14:
        return 1
    return 2


def форма(ключ, счёт):
    """Форма леммы при числе; лемма, которой дом не знает, есть ошибка вызова."""
    тройка = СЧЁТНЫЕ.get(ключ)
    if тройка is None:
        raise KeyError(f"полская лемма не объявлена: {ключ}")
    return тройка[индекс(счёт)]


# РОД ЛЕММЫ ОБЪЯВЛЕН, А НЕ ВЫВЕДЕН ПО ОКОНЧАНИЮ. Правило «кончается на -a — женский, на
# -o/-e — средний, иначе мужской» верно для двадцати трёх лемм из двадцати четырёх и лжёт о
# двадцать четвёртой: «rzecz» кончается согласной и есть женского рода. Род знают, как знают
# тройку форм, — и объявляют там же.
#
#     ПРАВИЛО, ВЕРНОЕ ДЛЯ ДВАДЦАТИ ТРЁХ ИЗ ДВАДЦАТИ ЧЕТЫРЁХ, ЕСТЬ НЕ ЗАКОН, А УДАЧА.
РОД = {
    "moneta": "z", "piłka": "z", "książka": "z", "karta": "z", "godzina": "z", "minuta": "z",
    "noga": "z", "ręka": "z", "łapa": "z", "planeta": "z", "rzecz": "z",
    "jabłko": "n", "jajko": "n", "koło": "n", "oko": "n", "serce": "n", "skrzydło": "n",
    "dzień": "m", "długopis": "m", "kolor": "m", "kwiat": "m", "palec": "m",
    "stopień": "m", "ząb": "m",
}

# СВЯЗКА ГНЁТСЯ ТОЙ ЖЕ ПОЛОСОЙ, ЧТО И ВЕЩЬ, А В ЕДИНИЦЕ — ЕЩЁ И РОДОМ (08.09).
#
# Дом знал три формы существительного и брал их законом; связку при том же числе пять его
# читателей писали БУКВОЙ — «na półce jest 3 jabłka», «było 4 minuty», — и восемьдесят семь
# страниц свода были ложны по-польски, а палата звала их истиной: связка стояла в образцах
# литералом, и подмена не совпала бы с образцом вовсе (род немоты, названный `sign_traps`).
#
#     ДОМ, ЗНАЮЩИЙ ЗАКОН ДЛЯ СУЩЕСТВИТЕЛЬНОГО И НЕ ДАЮЩИЙ ЕГО ГЛАГОЛУ, ЗНАЕТ ЗАКОН
#     НАПОЛОВИНУ — И ПОЛОВИНА ЭТА ВЫХОДИТ ЛОЖЬЮ РОВНО ТАМ, ГДЕ ЯЗЫК РАСХОДИТСЯ С ЧИСЛОМ.
#
# Настоящее время рода не различает: «jest» при единице и при родительном множественном,
# «są» при именительном множественном. Прошедшее различает — но ТОЛЬКО при ровно единице:
# «był 1 kot», «była 1 gazeta», «było 1 jajko»; при двух-четырёх стоит «były», при прочем
# «było». Средний род единственного и «прочее» пишутся одинаково, и это совпадение форм,
# а не одна форма: они объявлены порознь.
#
# НИ ОДНА ОБЪЯВЛЕННАЯ ЛЕММА НЕ ЕСТЬ МУЖСКО-ЛИЧНАЯ, и это сказано, а не умолчано: у
# мужско-личных польский берёт иные формы («byli», «są» при «pięciu mężczyzn było»), и дом
# их не пишет, ибо не объявлял таких лемм. День, когда объявит, есть день правки этого места.
СВЯЗКА = {
    "наст": ("jest", "są", "jest"),
    "прош": ({"m": "był", "z": "była", "n": "było"}, "były", "było"),
}


# ГРУППЫ ВЗАИМОЗАМЕНЯЕМЫХ ФОРМ — для закона замкнутого мира: подмена внутри группы есть
# ПОРЧА страницы, а не чужая строка (`closedworld.ложь_по_связке`). Собраны из объявления,
# а не переписаны рядом с ним: разойтись им негде.
ГРУППЫ_СВЯЗКИ = tuple(
    frozenset(
        ф for ячейка in ряд
        for ф in (ячейка.values() if isinstance(ячейка, dict) else (ячейка,))
    )
    for ряд in СВЯЗКА.values()
)


def связка(время, счёт, род=None):
    """Связка при числе: «jest/są», «był/była/było/były». Род нужен лишь прошедшему в единице."""
    ряд = СВЯЗКА.get(время)
    if ряд is None:
        raise KeyError(f"время не объявлено: {время}")
    ячейка = ряд[индекс(счёт)]
    if isinstance(ячейка, dict):
        if род not in ячейка:
            raise KeyError(f"прошедшее в единице требует рода: {время} {счёт} {род!r}")
        return ячейка[род]
    return ячейка


def связка_вещи(время, ключ, счёт):
    """Связка при объявленной лемме — род берётся у леммы, а не у зовущего."""
    if ключ not in СЧЁТНЫЕ:
        raise KeyError(f"полская лемма не объявлена: {ключ}")
    return связка(время, счёт, РОД.get(ключ))


# ЧТЕНИЕ СТРОКИ: связка, стоящая ПЕРЕД числом и объявленной вещью, правится ЭТИМ числом.
# Признак узок нарочно: связка после числа («o ile 4 jest cieplej niż −14?») правится не им,
# а подлежащим, и о ней этот дом молчит.
_ФОРМА_ПОЛОСЫ = {}
for _лемма, _тройка in СЧЁТНЫЕ.items():
    for _и, _ф in enumerate(_тройка):
        _ФОРМА_ПОЛОСЫ.setdefault(_ф, set()).add((_и, РОД[_лемма]))
_ВРЕМЯ_ФОРМЫ = {ф: время for время, ряд in СВЯЗКА.items() for ячейка in ряд
                for ф in (ячейка.values() if isinstance(ячейка, dict) else (ячейка,))}
_ТРОЙКА = _re.compile(
    r"\b(" + "|".join(sorted(_ВРЕМЯ_ФОРМЫ, key=lambda с: (-len(с), с)))
    + r")\s+(\d+)\s+([a-ząćęłńóśźż]+)")


def обвинения(строка):
    """[(связка, число, вещь, ждём)] — связки строки, стоящие не по закону своего числа."""
    вон = []
    for форма, число, слово in _ТРОЙКА.findall(строка):
        полосы = _ФОРМА_ПОЛОСЫ.get(слово)
        if not полосы:
            continue                    # вещь дому не объявлена — не судим
        n = int(число)
        и = индекс(n)
        роды = {род for полоса, род in полосы if полоса == и}
        if not роды:
            continue                    # вещь и сама не в форме своего числа — иной порок
        время = _ВРЕМЯ_ФОРМЫ[форма]
        ждём = {связка(время, n, род) for род in роды}
        if форма not in ждём:
            вон.append((форма, n, слово, "/".join(sorted(ждём))))
    return вон


def не_по_полосе(строка):
    """True — в строке есть связка, стоящая не по полосе своего числа."""
    return bool(обвинения(строка))


def _самопроверка():
    случаи = ((1, 0), (2, 1), (4, 1), (5, 2), (11, 2), (12, 2), (14, 2), (21, 2),
              (22, 1), (25, 2), (31, 2), (101, 2), (112, 2), (122, 1), (0, 2))
    for счёт, ждём in случаи:
        assert индекс(счёт) == ждём, (счёт, индекс(счёт), ждём)
    for ключ in СЧЁТНЫЕ:
        assert len(СЧЁТНЫЕ[ключ]) == 3, ключ
        assert РОД.get(ключ) in ("m", "z", "n"), f"род леммы не объявлен: {ключ}"
    assert set(РОД) == set(СЧЁТНЫЕ), set(РОД) ^ set(СЧЁТНЫЕ)
    # связка при числе — по полосе, а в прошедшей единице по роду
    for время, счёт, ключ, ждём in (("наст", 1, "piłka", "jest"), ("наст", 3, "piłka", "są"),
                                    ("наст", 22, "jabłko", "są"), ("наст", 5, "jabłko", "jest"),
                                    ("наст", 21, "dzień", "jest"),
                                    ("прош", 1, "kwiat", "był"), ("прош", 1, "karta", "była"),
                                    ("прош", 1, "jajko", "było"), ("прош", 3, "minuta", "były"),
                                    ("прош", 7, "minuta", "było"), ("прош", 21, "stopień", "było")):
        дано = связка_вещи(время, ключ, счёт)
        assert дано == ждём, (время, счёт, ключ, дано, ждём)
    for n in (1, 2, 5, 21, 22, 25, 12):
        print(f"  {n:3} {форма('piłka', n):8} {форма('jabłko', n):8} {форма('dzień', n)}")
    print(f"  лемм объявлено: {len(СЧЁТНЫЕ)}; случаев правила проверено: {len(случаи)}")


if __name__ == "__main__":
    _самопроверка()
