#!/usr/bin/env python3
"""GENESIS layer: ЗАКОНЫ ПОРЯДКА — see tools/orderlawforms.py for the law.

ПРАВИЛО И ЕГО ОТМЕНА ИДУТ ОДНОЙ ГРУППОЙ, и это не удобство раздачи, а сам предмет дома:
«умножим оба на 4 — порядок сохранён» и «умножим оба на −4 — знак перевернулся» суть
правило и его граница, и разлучить их значило бы выучить читателя ошибке, которую потом
придётся ломать.

    ПРАВИЛО, РАЗЛУЧЁННОЕ СО СВОЕЙ ГРАНИЦЕЙ, БУДЕТ ПРИМЕНЕНО ТАМ, ГДЕ ГРАНИЦА МОЛЧИТ.

ТРАНЗИТИВНОСТЬ И ТРИХОТОМИЯ идут своей группой: обе говорят о том, что порядок даёт
ЗНАНИЕ сверх двух сравненных чисел — первая о третьем числе, вторая о двух отвергнутых
возможностях. АНТИСИММЕТРИЯ и ПРИБАВЛЕНИЕ — третьей: обе о том, что порядок ТЕРПИТ и
чего НЕ ТЕРПИТ. ВОПРОС стои́т отдельно — ответ рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import orderlawforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_orderlaw.txt"
ГРУППЫ = (("транзитивность", "трихотомия"),
          ("антисимметрия", "прибавление"),
          ("умножение на положительное", "переворот"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
