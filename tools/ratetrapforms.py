def _годна_дорога(путь, v1, v2):
    if путь % v1 or путь % v2:
        return False
    t = путь // v1 + путь // v2
    return t and (2 * путь) % t == 0 and (2 * путь) // t != (v1 + v2) // 2


def _годна_работа(дел, h1, h2):
    if дел % h1 or дел % h2:
        return False
    r = дел // h1 + дел // h2
    return r and дел % r == 0


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        ч = (lambda n: rugram.форма("час", n)) if язык == "ru" else (lambda n: "h")
        for путь, v1, v2 in ДОРОГИ:
            if not _годна_дорога(путь, v1, v2):
                continue
            t1, t2 = путь // v1, путь // v2
            t = t1 + t2
            общ = dict(путь=путь, путь2=2 * путь, v1=v1, v2=v2, полу=(v1 + v2) // 2,
                       t1=t1, t2=t2, t=t, средняя=2 * путь // t,
                       ч1=ч(t1), ч2=ч(t2), ч=ч(t))
            вон[рамки["средняя скорость"].format(**общ)] = (язык, "средняя скорость")
            вон[рамки["спрошенное"].format(**общ)] = (язык, "спрошенное")
        for дел, h1, h2 in РАБОТЫ:
            if not _годна_работа(дел, h1, h2):
                continue
            r1, r2 = дел // h1, дел // h2
            r = r1 + r2
            # И ЗДЕСЬ ФОРМА БЕРЁТСЯ У ПАКЕТА. Ворота поймали «24 деталей» — рамка
