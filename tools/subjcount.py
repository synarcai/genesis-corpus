#!/usr/bin/env python3
"""ДОМ СЧЁТА ПОДЛЕЖАЩЕГО — число стои́т при ТОМ, КТО ДЕЙСТВУЕТ (07.09).

ЗАКАЗ КУПЛЕН АТЛАСОМ НЕПРОЧИТАННОГО, А НЕ ДОГАДКОЙ (holon-f9 по томографу st48 omega-ad).
Из 539 отказов читателя на базе p156 разобрано 420 историй, и СЧЁТ ПОДЛЕЖАЩЕГО — третий
по величине класс: 104 истории. Образец: «43 children were riding on the bus. 82 children
got on the bus. how many children are on the bus now?»

    ЧИСЛО ПРИ ПОДЛЕЖАЩЕМ ЕСТЬ ИНОЕ ЧТЕНИЕ, ЧЕМ ЧИСЛО ПРИ ДОПОЛНЕНИИ. Весь свод учит
    читателя счёту ИМУЩЕСТВА: «у Ани 5 монет», «Ben had 22 books» — число стои́т при
    вещи, которой владеет НОСИТЕЛЬ, и рамка ищет носителя. Здесь носителя нет вовсе:
    считаются САМИ ДЕЙСТВУЮЩИЕ, а место (автобус, забор, лавка) есть СЦЕНА, а не
    владелец. Читатель, выучивший одну рамку, на другой молчит.

ПЕРЕПИСЬ, КУПИВШАЯ ДОМ (07.09, свод 32 590 756 байт, 378 361 строка). Форма в своде
ПОЧТИ ОТСУТСТВУЕТ, и это сказано числом, а не на глаз:

    «N X got off …»            6 страниц        «N X flew away …»       6
    «N X were riding …»       15                «N X got on the …»      8
    экзистенциал «there are/were N X»       4 165 — иная форма и иной класс атласа (92)

Шести страниц не хватает и на LAW³ = 8. Экзистенциала же в своде вдоволь — и он-то и
показывает, чего недостаёт: свод умеет говорить «there were 43 kids on the bus», но почти
не умеет «43 kids were riding on the bus». РАЗНИЦА НЕ В СМЫСЛЕ, А В МЕСТЕ ЧИСЛА: в первом
случае число стои́т после пустого «there», во втором — В ГОЛОВЕ, при подлежащем, и рамка
читателя обязана искать его там.

ЧТО ПИШЕТ ЭТОТ ДОМ, И ПОЧЕМУ ИМЕННО ТАК:

    БЕЗ «there» — НАРОЧНО. Экзистенциальную форму свод уже несёт четырьмя тысячами
        строк; дом, написавший её в пятый раз, не покупает ничего. Здесь первое слово
        страницы есть ЧИСЛО.
    СЦЕНА ЕСТЬ МЕСТО, И ВОПРОС ЕЁ НАЗЫВАЕТ. «how many children are on the bus now?» —
        читатель, потерявший сцену, не отличит её от иной, а страница с двумя сценами
        (см. ниже) наказывает эту потерю прямо.
    ЧЕТЫРЕ РАМКИ, И ЧЕТВЁРТАЯ ЕСТЬ ЗАТВОР ПРОТИВ ОТВЕТА ПО МЕСТУ. Прибыль (складывается),
        убыль (вычитается), два шага (складывается и вычитается в объявленном порядке) —
        и ВОПРОС О САМОМ ДЕЙСТВИИ: «how many children got on the bus?», где ответ есть
        ВТОРОЕ число страницы, а не итог. Читатель, отвечающий «последнее число» или
        «сумма всего, что видел», на четвёртой рамке лжёт.
    ГЛАГОЛ ДВИЖЕНИЯ БЕРЁТ ТОЛЬКО ТО, ЧТО ДВИЖЕТСЯ САМО, и род объявлен ЗДЕСЬ, а не в
        общем доме `verbthings`. Это куплено шрамом 06.09: семь глаголов моста, внесённых
        в общий `ГЛАГОЛ_БЕРЁТ`, уронили суд эпизода 986 ложными строками в одиннадцати
        мирах. Общий дом молчит о «got on» — и пусть молчит.
    СЦЕНА СОГЛАСОВАНА С ГЛАГОЛОМ: «flew away» пишется о том, что летает, «got off» — о
        том, что ездит; птица не сходит с автобуса, и покупатель не улетает с забора.
        Пары объявлены таблицей, а не угаданы соседством.
    ЛЕДЖЕР СТОИТ НА СТРАНИЦЕ. «43 + 82 = 125» — тот же сосед, на которого опирается
        палата: суд арифметики читает страницу и без своего дома.

ЗАКОН ЧИСЛА: не менее LAW³ = 8 страниц на каждую рамку и не менее LAW² = 4 сцены — иначе
рамка показана, а не куплена.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from layer import emit                                            # noqa: E402
from plural import by_count                                       # noqa: E402

# СЦЕНА И ЕЁ НАРОД: что где бывает и каким глаголом приходит и уходит.
#
# РОД ГЛАГОЛА ДВИЖЕНИЯ ОБЪЯВЛЕН ЗДЕСЬ, А НЕ В ОБЩЕМ ДОМЕ (шрам 06.09, см. описание).
# Каждая запись: сцена → (народ, глагол стояния, глагол прибытия, глагол убытия).
СЦЕНЫ = (
    ("bus",    "children", "were riding on the bus",     "got on the bus",      "got off the bus"),
    ("bus",    "kids",     "were riding on the bus",     "got on the bus",      "got off the bus"),
    ("fence",  "birds",    "were sitting on the fence",  "flew to the fence",   "flew away"),
    ("tree",   "birds",    "were sitting in the tree",   "flew to the tree",    "flew away"),
    ("shop",   "customers", "were waiting in the shop",  "came into the shop",  "left the shop"),
    ("hall",   "students", "were waiting in the hall",   "came into the hall",  "left the hall"),
    ("train",  "passengers", "were riding on the train", "got on the train",    "got off the train"),
    ("yard",   "puppies",  "were playing in the yard",   "ran into the yard",   "ran out of the yard"),
)

# ПРЕДЛОГ СЦЕНЫ В ВОПРОСЕ: «on the bus» против «in the shop» — сказано, а не выведено.
ГДЕ = {"bus": "on the bus", "fence": "on the fence", "tree": "in the tree",
       "shop": "in the shop", "hall": "in the hall", "train": "on the train",
       "yard": "in the yard"}


def _сцена(i):
    return СЦЕНЫ[i % len(СЦЕНЫ)]


def показы(pi):
    основа = pi * 29
    вон = []
    for i in range(len(СЦЕНЫ) * 12):
        место, народ, стоят, пришли, ушли = _сцена(основа + i)
        где = ГДЕ[место]
        n = (основа + i * 7) % 60 + 9          # 9..68
        m = (основа + i * 11) % (n - 4) + 3    # 3..n-2, всегда меньше n
        # РАМКА И СЦЕНА НЕ ДОЛЖНЫ ШАГАТЬ В НОГУ (07.09, первая проба дома). Сцен восемь,
        # рамок четыре, и «рамка = i % 4» при «сцена = i % 8» связывает их намертво:
        # каждая рамка встречала РОВНО ДВЕ сцены из восьми, и четвёртая рамка вышла
        # написанной только о дереве и о дворе.
        #
        #     ДВА СЧЁТЧИКА ОТ ОДНОГО ЧИСЛА СВЯЗАНЫ, А НЕ НЕЗАВИСИМЫ. Дом, объявивший
        #     «не менее LAW² = 4 сцены на рамку», нарушал свой же закон молча — и увидеть
        #     это можно было только пересчётом, ибо страницы по отдельности честны.
        #
        # Рамка берётся от ЧАСТНОГО, а не от остатка: сцена меняется на каждом шаге,
        # рамка — раз в восемь шагов, и за полный оборот каждая рамка встречает каждую сцену.
        рамка = ((основа + i) // len(СЦЕНЫ)) % 4
        если_н = f"{n} {by_count(n, народ)} {стоят}."
        if рамка == 0:
            # ПРИБЫЛЬ
            вон.append(
                f"{если_н} {m} {by_count(m, народ)} {пришли}. "
                f"how many {народ} are {где} now? "
                f"{n + m} {by_count(n + m, народ)}: {n} + {m} = {n + m}.")
        elif рамка == 1:
            # УБЫЛЬ
            вон.append(
                f"{если_н} {m} {by_count(m, народ)} {ушли}. "
                f"how many {народ} are {где} now? "
                f"{n - m} {by_count(n - m, народ)}: {n} − {m} = {n - m}.")
        elif рамка == 2:
            # ДВА ШАГА: сперва убыль, потом прибыль — порядок объявлен леджером
            k = (основа + i * 5) % 9 + 2       # 2..10
            вон.append(
                f"{если_н} {m} {by_count(m, народ)} {ушли}. "
                f"{k} more {by_count(k, народ)} {пришли}. "
                f"how many {народ} are {где} now? "
                f"{n - m + k} {by_count(n - m + k, народ)}: "
                f"{n} − {m} = {n - m}, {n - m} + {k} = {n - m + k}.")
        else:
            # ВОПРОС О САМОМ ДЕЙСТВИИ: ответ есть ВТОРОЕ число, а не итог.
            #
            # ОТВЕТ ПОВТОРЯЕТ ФАКТ ЦЕЛИКОМ, А НЕ ОДНО ЧИСЛО (07.09, вторая проба дома).
            # Голый ответ «10 birds.» не читал НИКТО из палаты на четырёх сценах из
            # семи: страница без леджера держится только памятью, а суду памяти нужен
            # ФАКТ, с которым сверять, — не число, висящее в воздухе.
            #
            #     СТРАНИЦА БЕЗ СЧЁТА ДЕРЖИТСЯ ПОВТОРОМ, И ПОВТОР ДОЛЖЕН БЫТЬ ПОЛНЫМ.
            #     Это тот же закон, которым живёт дом моста вопросной формы: ответ есть
            #     ФАКТ ТОЙ ЖЕ ИСТОРИИ, а не вычисление и не обрывок.
            вон.append(
                f"{если_н} {m} {by_count(m, народ)} {пришли}. "
                f"how many {народ} {пришли}? "
                f"{m} {by_count(m, народ)} {пришли}.")
    return вон


def main():
    emit("datasets/genesis_subjcount.txt", показы)


if __name__ == "__main__":
    main()
