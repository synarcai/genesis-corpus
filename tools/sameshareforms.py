#!/usr/bin/env python3
"""ДОМ ОДНОЙ ДОЛИ В РАЗНЫХ ЗАПИСЯХ — «1 из 4», «одна четверть» и «1/4» суть одно число.

    ТРИ ДОМА ГОВОРЯТ ОБ ОДНОМ И НЕ ЗНАЮТ ДРУГ О ДРУГЕ. Дом вероятности пишет «вероятность есть
    1 из 4»; дом долей — «одна четверть — это 1/4» и «одна четверть от 24 — это 6»; дом
    переписи связывает арифметические записи («3 × 8» и «8 × 3»), но о долях не говорит.
    Замер 11.09: связи «1 из 4» с «одной четвертью» нет НИ ОДНОЙ строкой.

    ОДНО ЧИСЛО, НАЗВАННОЕ ТРЕМЯ ИМЕНАМИ И НИ РАЗУ НЕ ОТОЖДЕСТВЛЁННОЕ, ЕСТЬ ТРИ РАЗНЫХ ЧИСЛА
    ДЛЯ ТОГО, КТО ЧИТАЕТ.

ЧЕТЫРЕ РОДА, И ВСЕ ПРОВЕРЯЮТСЯ ОДНИМ ОРАКУЛОМ — СЧЁТОМ ОТ ЦЕЛОГО:

    имя        1 из 4 и одна четверть — одно и то же: от 12 оба дают 3, ибо 12 ÷ 4 = 3.
    равные     2 из 4 и 1 из 2 — одно и то же? да: от 12 оба дают 6, ибо 12 ÷ 4 = 3,
               и 3 × 2 = 6, и 12 ÷ 2 = 6.                        ← РАЗНЫЕ ЗАПИСИ, ОДНО ЧИСЛО
    разные     1 из 3 и 1 из 4 — одно и то же? нет: от 12 первое даёт 4, а второе 3,
               ибо 12 ÷ 3 = 4, и 12 ÷ 4 = 3.                      ← ПОХОЖИЕ, НО РАЗНЫЕ
    дробь      1 из 4 записывается 1/4: от 12 это 3, ибо 12 ÷ 4 = 3.

ВТОРОЙ И ТРЕТИЙ РОД СУТЬ МИНИМАЛЬНАЯ ПАРА, И БЕЗ НЕЁ ДОМ УЧИЛ БЫ ПОЛОВИНЕ ДЕЛА: «2 из 4» и
«1 из 2» отличаются всеми цифрами и суть одно; «1 из 3» и «1 из 4» отличаются одной цифрой и
суть разное.

    СХОЖЕСТЬ ЗАПИСИ НЕ ЕСТЬ РАВЕНСТВО ЧИСЛА, А РАЗЛИЧИЕ ЗАПИСИ НЕ ЕСТЬ РАЗЛИЧИЕ ЧИСЛА.
    Решает СЧЁТ ОТ ЦЕЛОГО, и он показан на каждой странице.

ЦЕЛОЕ БЕРЁТСЯ ТАКОЕ, ЧТОБЫ ДЕЛИЛОСЬ НА ОБА ЗНАМЕНАТЕЛЯ: иначе счёт дал бы дробь, а дом не о
дробях от дробей. Целое НАЗВАНО В СТРОКЕ («от 12»), и это не мелочь: доля без целого не есть
число, и две доли сравнимы лишь при одном целом.

ИМЕНА ДОЛЕЙ БЕРУТСЯ У ДОМА ДОЛЕЙ (`fracforms.доля_слово`), а не пишутся здесь: дом, повторивший
чужую таблицу, разойдётся с нею на первой же правке.

    python3 tools/sameshareforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import fracforms  # noqa: E402 — имена долей объявлены там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("имя", "равные", "разные", "дробь", "процент")

РАМКИ = {
    "ru": {
        "имя": "{a} из {b} и {слово} — одно и то же: от {ц} оба дают {v}, ибо {ц} ÷ {b} = {v}.",
        "равные": "{a} из {b} и {c} из {d} — одно и то же? да: от {ц} оба дают {v}, ибо {ц} ÷ {b} = {ч1}, и {ч1} × {a} = {v}, и {ц} ÷ {d} = {v}.",
        "разные": "{a} из {b} и {c} из {d} — одно и то же? нет: от {ц} первое даёт {v}, а второе {w}, ибо {ц} ÷ {b} = {v}, и {ц} ÷ {d} = {w}.",
        "дробь": "{a} из {b} записывается {a}/{b}: от {ц} это {v}, ибо {ц} ÷ {b} = {v}.",
        "процент": "{п} % и {слово} — одно и то же: от {ц} оба дают {v}, ибо {ц} ÷ {b} = {v}, и {ц} × {п} = {пр}, и {пр} ÷ 100 = {v}.",
    },
    "en": {
        "имя": "{a} out of {b} and {слово} are the same: of {ц} both give {v}, because {ц} ÷ {b} = {v}.",
        "равные": "{a} out of {b} and {c} out of {d} — the same? yes: of {ц} both give {v}, because {ц} ÷ {b} = {ч1}, and {ч1} × {a} = {v}, and {ц} ÷ {d} = {v}.",
        "разные": "{a} out of {b} and {c} out of {d} — the same? no: of {ц} the first gives {v}, the second {w}, because {ц} ÷ {b} = {v}, and {ц} ÷ {d} = {w}.",
        "дробь": "{a} out of {b} is written {a}/{b}: of {ц} it is {v}, because {ц} ÷ {b} = {v}.",
        "процент": "{п} % and {слово} are the same: of {ц} both give {v}, because {ц} ÷ {b} = {v}, and {ц} × {п} = {пр}, and {пр} ÷ 100 = {v}.",
    },
}

# ЦЕЛЫЕ, ДЕЛЯЩИЕСЯ НА ВСЕ ЗНАМЕНАТЕЛИ РЯДА: доля без целого не есть число, и целое обязано
# делиться нацело, иначе счёт даст дробь — работу иного дома.
ЦЕЛЫЕ = (12, 24, 36, 48, 60)
ЕДИНИЧНЫЕ = ((1, 2), (1, 3), (1, 4), (1, 6), (1, 12))
# ДОЛИ, ДАЮЩИЕ ЦЕЛЫЙ ПРОЦЕНТ, И ЦЕЛЫЕ ПОД НИХ. Треть процентом не пишется («33,333…»), и
# ставить её сюда значило бы учить округлению под видом тождества — работе иного дома.
ПРОЦЕНТНЫЕ = ((1, 2, 50), (1, 4, 25), (1, 5, 20), (1, 10, 10), (1, 20, 5))
ЦЕЛЫЕ_ПРОЦЕНТА = (20, 40, 60, 80, 100)


def _имя_доли(язык, n, d):
    """Слово доли берётся у дома долей; None — дом такого слова не объявил."""
    try:
        return fracforms.доля_слово(язык, n, d)
    except Exception:      # noqa: BLE001 — дом молчит о доле, и мы её не берём
        return None


def _равные():
    """((a, b), (c, d)): доли РАВНЫЕ, но записанные разными числами."""
    вон = []
    for (c, d) in ЕДИНИЧНЫЕ:
        for k in (2, 3, 4):
            a, b = c * k, d * k
            if b <= 48:
                вон.append(((a, b), (c, d)))
    return вон


def _разные():
    """((a, b), (c, d)): доли РАЗНЫЕ, и всякая пара берётся из объявленного ряда.

    Первый отбор брал лишь СОСЕДНИЕ знаменатели (b + 1, b + 2) ради обманчивого сходства
    записи — и дал СЕМЬ страниц: соседний знаменатель редко делит объявленное целое (седьмых
    долей от двенадцати не бывает). Род с массой меньше девяти организмом не покупается, а
    этот — половина минимальной пары дома. Ныне берутся все пары ряда, чьи доли не равны;
    соседние среди них остаются.
    """
    вон = []
    for (a, b) in ЕДИНИЧНЫЕ:
        for (c, d) in ЕДИНИЧНЫЕ:
            if b != d and a * d != c * b:
                вон.append(((a, b), (c, d)))
    return вон


def _целое(*знаменатели):
    """Наименьшее из объявленных целых, делящееся на все знаменатели, или None."""
    for ц in ЦЕЛЫЕ:
        if all(ц % з == 0 for з in знаменатели):
            return ц
    return None


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for (a, b) in ЕДИНИЧНЫЕ:
            слово = _имя_доли(язык, a, b)
            for ц in ЦЕЛЫЕ:
                if ц % b:
                    continue
                поля = dict(a=a, b=b, c=0, d=0, ц=ц, v=ц // b, w=0, ч1=0, слово=слово, п=0, пр=0)
                if слово:
                    вон[рамки["имя"].format(**поля)] = (язык, "имя")
                вон[рамки["дробь"].format(**поля)] = (язык, "дробь")
        for (a, b), (c, d) in _равные():
            ц = _целое(b, d)
            if ц is None:
                continue
            поля = dict(a=a, b=b, c=c, d=d, ц=ц, v=ц // d, w=0, ч1=ц // b, слово=None, п=0, пр=0)
            вон[рамки["равные"].format(**поля)] = (язык, "равные")
        # ЧЕТВЁРТАЯ ЗАПИСЬ ТОГО ЖЕ ЧИСЛА — ПРОЦЕНТ. Замер 11.09: мир процентов считает «1% от
        # 200 — это 2», мир долей — «одна четверть от 24 — это 6», а связи «25 % и одна
        # четверть» не делает ни одна строка свода. Дом, чей предмет уже объявлен, растёт
        # РОДОМ, а не близнецом: оракул тот же — счёт от целого, и он показан дважды, ибо
        # процент считается своим ходом (умножить и разделить на сто).
        for a, b, п in ПРОЦЕНТНЫЕ:
            слово = _имя_доли(язык, a, b)
            if not слово:
                continue
            for ц in ЦЕЛЫЕ_ПРОЦЕНТА:
                if ц % b or (ц * п) % 100:
                    continue
                поля = dict(a=a, b=b, c=0, d=0, ц=ц, v=ц // b, w=0, ч1=0,
                            слово=слово, п=п, пр=ц * п)
                вон[рамки["процент"].format(**поля)] = (язык, "процент")
        for (a, b), (c, d) in _разные():
            ц = _целое(b, d)
            if ц is None:
                continue
            поля = dict(a=a, b=b, c=c, d=d, ц=ц, v=ц // b, w=ц // d, ч1=0, слово=None, п=0, пр=0)
            вон[рамки["разные"].format(**поля)] = (язык, "разные")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ЧАСТНОЕ = re.compile(r"(\d+) ÷ (\d+) = (\d+)")
_ПРОИЗВ = re.compile(r"(\d+) × (\d+) = (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ, И СЧИТАЕТСЯ ТОЛЬКО ОТВЕЧАЮЩАЯ ЧАСТЬ.
    ответ = с.split("?", 1)[1] if "?" in с else с
    for a, b, c in _ЧАСТНОЕ.findall(ответ):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b, c in _ПРОИЗВ.findall(ответ):
        if int(a) * int(b) != int(c):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:74]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    рав = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "равные")
    раз = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "разные")
    if судить(рав.replace("одно и то же? да", "одно и то же? д"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(раз.replace("первое", "перво"))[1] is not False:
        беды.append("обрезанное слово в различии прошло")
    if судить(рав + " " + рав)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ОДНА ДОЛЯ РАЗНЫМИ ЗАПИСЯМИ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, "
          f"бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
