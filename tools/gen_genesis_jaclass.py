#!/usr/bin/env python3
"""GENESIS layer: ЯПОНСКОЕ СЧЁТНОЕ — see tools/jaclassforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Счётное обязательно» и «счётное выбирает имя» идут вместе: первое — что слово нужно, второе
— что выбирает его не говорящий.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Один знак, две роли» и «порядок иной, чем у соседа» — второй группой: обе отнимают догадку о
знаке, одна внутри языка (本 есть и книга, и мера длинных вещей), другая снаружи (китайский
ставит счётное между числом и именем, японский — после числа за именем).

«Спрошено и отвечено» — третьей.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import jaclassforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_jaclass.txt"
ГРУППЫ = (("счётное обязательно", "счётное выбирает имя"),
          ("один знак, две роли", "порядок иной, чем у соседа"),
          ("спрошено и отвечено",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
