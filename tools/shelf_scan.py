#!/usr/bin/env python3
"""ПОЛКА СО СКАНОВ ВИКИТЕКИ: книга, живущая страницами «Страница:…».

Даль на Викитеке не лежит текстом: статья «ТСД2/Ящик» есть шаблон, а
слова живут в пространстве страниц скана (2931 страница четырёх томов
2-го издания), откуда их собирает модуль сайта, по пути переводя
орфографию. Кузница полки (Gutenberg) и сборщик Викитеки
(shelf_fetch) такой книги не видят. Отсюда третий путь на полку:
индекс скана → список страниц → Special:Export пачками (200 страниц за
запрос, 15 запросов на словарь вместо 45 тысяч запросов к статьям) →
чистка разметки правилом → орфография правилом (oldspell) → статьи с
заголовком капсом в начале строки — та единица, которой словарь
меряется (М-141).

ЧТО СНИМАЕТСЯ И ЧТО ОСТАЁТСЯ. Ударения ({{акут}}) снимаются: организм
читает слова наших сводов без ударений, и «сито́» стало бы вторым
словом рядом с «сито». Разделитель значений «||» остаётся — это знак
самого Даля. Пометы (<small>м.</small>, «пск.», «црк.») остаются
словами, помечающими род и говор, — теги снимаются, слова нет.
Колонтитулы, номера страниц, примечания Викитеки, неизвестные шаблоны
снимаются целиком: они не текст книги. Перенос слова между страницами
склеивается по шаблону ({{перенос}} несёт обе половины).

Использование:
  python3 tools/shelf_scan.py --кэш <каталог> [--только dal_1880] [--манифест]
  python3 tools/shelf_scan.py --кэш <каталог> --суд 120     # орфография
"""

import argparse
import html
import json
import pathlib
import re
import sys
import time
import urllib.parse
import urllib.request

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import oldspell  # noqa: E402
import shelf_fetch  # noqa: E402

UA = "genesis-corpus shelf_scan (contact: luxquant@gst.st)"
API = "https://ru.wikisource.org/w/api.php"
EXPORT = "https://ru.wikisource.org/wiki/Special:Export"
ПАЧКА = 200


class Скан:
    """Объявление книги со сканов — и ничего сверх объявленного."""

    def __init__(self, имя, индексы, тема, плотность, издано, заглавие,
                 автор, язык="ru"):
        self.имя = имя
        self.индексы = индексы
        self.тема = тема
        self.плотность = плотность
        self.издано = издано
        self.заглавие = заглавие
        self.автор = автор
        self.язык = язык


ПОЛКА = (
    Скан("dal_1880",
         ["Толковый словарь Даля (2-е издание). Том 1 (1880).pdf",
          "Толковый словарь Даля (2-е издание). Том 2 (1881).pdf",
          "Толковый словарь Даля (2-е издание). Том 3 (1882).pdf",
          "Толковый словарь Даля (2-е издание). Том 4 (1882).pdf"],
         "язык", "словарь", 1882,
         "Толковый словарь живого великорусского языка, 2-е издание",
         "Владимир Даль"),
)


def спросить(**поля):
    поля["format"] = "json"
    з = urllib.request.Request(API + "?" + urllib.parse.urlencode(поля),
                               headers={"User-Agent": UA})
    return json.load(urllib.request.urlopen(з, timeout=120))


def страницы_индекса(индекс):
    """Титулы «Страница:…/N» индекса, по номеру."""
    титулы, дальше = [], None
    while True:
        поля = dict(action="query", list="allpages", apnamespace="104",
                    apprefix=индекс + "/", aplimit="max")
        if дальше:
            поля["apcontinue"] = дальше
        д = спросить(**поля)
        титулы += [p["title"] for p in д["query"]["allpages"]]
        дальше = д.get("continue", {}).get("apcontinue")
        if not дальше:
            break
        time.sleep(0.3)
    return sorted(титулы, key=lambda т: int(т.rsplit("/", 1)[1]))


def выгрузить(индекс, кэш):
    """XML-выгрузки страниц индекса — в кэш, пачками."""
    кэш.mkdir(parents=True, exist_ok=True)
    ключ = re.sub(r"[^\w]+", "_", индекс)[:60]
    готовые = sorted(кэш.glob(ключ + "_*.xml"))
    if готовые:
        return готовые
    титулы = страницы_индекса(индекс)
    вон = []
    for i in range(0, len(титулы), ПАЧКА):
        тело = urllib.parse.urlencode(
            {"pages": "\n".join(титулы[i:i + ПАЧКА]), "curonly": "1",
             "wpDownload": "1"}).encode()
        з = urllib.request.Request(EXPORT, data=тело,
                                   headers={"User-Agent": UA})
        путь = кэш / f"{ключ}_{i // ПАЧКА:02}.xml"
        путь.write_bytes(urllib.request.urlopen(з, timeout=600).read())
        вон.append(путь)
        time.sleep(1.0)
    return вон


def страницы_из_xml(пути, индексы):
    """[(номер, wikitext)] — тома в порядке объявления, внутри тома по
    номеру страницы. Первая редакция сортировала все страницы одним
    числом и смешала четыре тома: словарь начинался с буквы «П»."""
    вон = []
    for путь in пути:
        x = путь.read_text(encoding="utf-8")
        for м in re.finditer(
                r"<title>(.*?)</title>.*?<text[^>]*>(.*?)</text>", x, re.S):
            титул, номер = м.group(1).rsplit("/", 1)
            том = next((i for i, и in enumerate(индексы)
                        if титул.endswith(и)), len(индексы))
            вон.append(((том, int(номер)), html.unescape(м.group(2))))
    return [(н, т) for (_том, н), т in sorted(вон, key=lambda п: п[0])]


# ЧИСТКА — ПРАВИЛАМИ В ПОРЯДКЕ, И КАЖДОЕ НАЗВАНО.
ШАБЛОНЫ = (
    (re.compile(r"\{\{перенос2\|[^}]*\}\}"), ""),
    (re.compile(r"\{\{перенос\|([^|}]*)\|([^|}]*)\}\}"), r"\1\2"),
    (re.compile(r"\{\{[Аа]кут3?\}\}"), ""),
    (re.compile(r"\{\{!\}\}"), "|"),
    (re.compile(r"\{\{tsd[ls]\|([^|{}]*)(?:\|[^{}]*)?\}\}"), r"\1"),
    (re.compile(r"\{\{lang\|[^|{}]*\|([^{}]*)\}\}"), r"\1"),
    (re.compile(r"\{\{дробь\|([^|{}]*)\|([^|{}]*)\|([^|{}]*)\}\}"),
     r"\1 \2/\3"),
    (re.compile(r"\{\{дробь\|([^|{}]*)\|([^|{}]*)\}\}"), r"\1/\2"),
    (re.compile(r"\{\{опечатка2?\|[^|{}]*\|([^|{}]*)(?:\|[^{}]*)?\}\}"),
     r"\1"),
)
ЛЮБОЙ_ШАБЛОН = re.compile(r"\{\{[^{}]*\}\}")
# ССЫЛКИ ВИКИ: картинка снимается целиком (буква-цифра кириллицы —
# рисунок, не слово), ссылка со словом оставляет слово.
ССЫЛКИ = (
    (re.compile(r"\[\[(?:File|Файл|Image|Изображение):[^\[\]]*\]\]"), ""),
    (re.compile(r"\[\[[^\[\]|]*\|([^\[\]]*)\]\]"), r"\1"),
    (re.compile(r"\[\[([^\[\]]*)\]\]"), r"\1"),
)
ЗАГОЛОВОК = "⁣"   # невидимый разделитель — маркер заголовка гнезда


def чистый(wikitext):
    """Текст страницы без разметки; заголовки гнёзд помечены маркером."""
    т = re.sub(r"<noinclude>.*?</noinclude>", "", wikitext, flags=re.S)
    т = re.sub(r"<!--.*?-->", "", т, flags=re.S)
    for образец, замена in ШАБЛОНЫ:
        т = образец.sub(замена, т)
    while ЛЮБОЙ_ШАБЛОН.search(т):
        т = ЛЮБОЙ_ШАБЛОН.sub("", т)
    for образец, замена in ССЫЛКИ:
        т = образец.sub(замена, т)
    # ЗАГОЛОВОК ГНЕЗДА — ИМЯ СЕКЦИИ, А НЕ ЖИРНЫЙ ШРИФТ. Первая редакция
    # брала заголовком жирное слово: жирным у Даля набраны и
    # подзаголовки внутри гнезда, а курсив, примыкающий к жирному без
    # пробела, даёт пять апострофов подряд — и разбор разметки
    # сбивался на 1512 заголовках из 83 611, вынося текст мимо гнёзд.
    # Секция же режет книгу ровно по статьям (так её читает сама
    # Викитека), и имя секции есть заголовок в современной орфографии.
    # СЕКЦИИ ВЛОЖЕНЫ: гнездо «Авось» несёт внутри секцию «Абы» (слово,
    # на которое ссылаются отдельно), и пустые секции-указатели. Оба
    # края секции остаются маркерами, а статьи собирает стек.
    т = re.sub(r'<section (begin|end)="([^"]+)" ?/>',
               lambda м: ЗАГОЛОВОК + м.group(1)[0] + м.group(2).strip()
               + ЗАГОЛОВОК, т)
    т = re.sub(r"<[^<>]+>", "", т)
    т = т.replace("__NOEDITSECTION__", "")
    т = т.replace("'''", "").replace("''", "")
    # ОСТАТКИ РАЗБИТОЙ РАЗМЕТКИ (шаблон, закрытый на другой странице,
    # скобка без пары) — не текст книги; их число печатается отчётом.
    т = re.sub(r"\{\{|\}\}|\[\[|\]\]", " ", т)
    т = re.sub(r"[ \t\r\f\v]+", " ", т)
    т = re.sub(r"\s*\n\s*", " ", т)
    return т.strip()


def статьи(текст):
    """[(ЗАГОЛОВОК, тело)] — по маркерам секций, стеком; орфография
    современная. Текст принадлежит ВЕРХНЕЙ открытой секции; закрытие
    вложенной возвращает слово гнезду; часть гнезда, разорванного
    страницей, склеивается по имени; пустая секция не есть статья."""
    куски = текст.split(ЗАГОЛОВОК)
    тела, порядок, стек, хвост = {}, [], [], []
    for i, кусок in enumerate(куски):
        if i % 2 == 1:                      # маркер: bИмя / eИмя
            имя = кусок[1:]
            if кусок[0] == "b":
                стек.append(имя)
                if имя not in тела:
                    тела[имя] = []
                    порядок.append(имя)
            elif имя in стек:
                стек.remove(имя)
            continue
        if стек:
            тела[стек[-1]].append(кусок)
        else:
            хвост.append(кусок)
    вон = []
    подлинник = " ".join(" ".join(тела[и]) for и in порядок
                         if not и.endswith("+"))
    св = oldspell.свидетели(подлинник)
    for имя in порядок:
        # СТРАНИЦА НЕСЁТ ТЕКСТ ДВАЖДЫ: подлинник в секции «Имя» и его
        # модернизацию редакторов Викитеки в секции «Имя+». Книга
        # берётся с подлинника одной дорогой (правило oldspell), а
        # копия «+» служит СУДОМ дороги — иначе словарь лёг бы на полку
        # вдвое (88 852 статьи вместо 44 тысяч).
        if имя.endswith("+"):
            continue
        тело = oldspell.современно(" ".join(тела[имя]), св).strip()
        тело = re.sub(r"\s+", " ", тело)
        первое = re.match(r"[А-Яа-яЁё\-]+", oldspell.современно(имя, св))
        if not первое or not тело:
            continue
        заголовок = oldspell.современно(имя, св).strip(" .,;:")
        вон.append((первое.group().upper() + заголовок[первое.end():],
                    тело))
    return вон, " ".join(хвост).strip()


def строки_книги(статьи_):
    """Статья — строка «ЗАГОЛОВОК тело», между статьями пустая строка."""
    вон = []
    for заголовок, тело in статьи_:
        вон.append(f"{заголовок} {тело}".strip())
        вон.append("")
    return вон


def секции(страницы):
    """{имя секции: сырой wikitext секции} — имена суть современные
    заголовки Викитеки, по ним судится орфография."""
    вон = {}
    for _н, т in страницы:
        for м in re.finditer(
                r'<section begin="([^"]+)" ?/>(.*?)<section end="\1" ?/>',
                т, re.S):
            вон.setdefault(м.group(1), м.group(2))
    return вон


def суд_орфографии(страницы, сколько):
    """Доля наших слов, найденных в модернизации Викитеки тех же статей.

    Суд ЛОКАЛЕН: страница несёт подлинник («Имя») и чужую модернизацию
    («Имя+») рядом, и пара для суда есть у каждой статьи без единого
    запроса. Берутся все пары либо каждая k-я до заданного числа.
    """
    все = секции(страницы)
    имена = sorted(и for и in все if и + "+" in все)
    шаг = max(1, len(имена) // сколько) if сколько else 1
    св = oldspell.свидетели(" ".join(чистый(все[и]) for и in все
                                     if not и.endswith("+")))
    пары = []
    for имя in имена[::шаг]:
        наше = oldspell.современно(чистый(все[имя]), св)
        чужое = чистый(все[имя + "+"])
        пары.append((re.sub(ЗАГОЛОВОК + "[^" + ЗАГОЛОВОК + "]*" + ЗАГОЛОВОК,
                            " ", наше),
                     re.sub(ЗАГОЛОВОК + "[^" + ЗАГОЛОВОК + "]*" + ЗАГОЛОВОК,
                            " ", чужое).replace("\u0301", "")))
    доля, расхождения = oldspell.суд(пары)
    print(f"ОРФОГРАФИЯ: статей с парой {len(имена)}, судимо {len(пары)}, "
          f"наших слов найдено у Викитеки {100 * доля:.2f}%")
    for (а, б), n in расхождения[:28]:
        print(f"  {n:5}  наше «{а}» — у них «{б}»")
    return доля


def объявление(скан, сдал, байт, строк):
    return {
        "name": скан.имя + "_ru",
        "file": f"shelf/{скан.язык}/{скан.имя}.txt",
        "genre": (f"{скан.автор}, «{скан.заглавие}» ({скан.издано}): "
                  f"словарь гнёздами — заголовок капсом, толкование, "
                  f"пословицы и говоры при нём; орфография переведена "
                  f"правилом (tools/oldspell.py)"),
        "act": ["expound"],
        "oracle": ["none"],
        "boundary": ["unnamed"],
        "size": байт,
        "tiers": [],
        "text": "prose",
        "язык": скан.язык,
        "тема": скан.тема,
        "плотность": скан.плотность,
        "издано": скан.издано,
        "источник": "public-domain",
        "происхождение": "wikisource-scan:" + "; ".join(скан.индексы),
        "held_out": f"shelf/{скан.язык}/{скан.имя}.holdout.txt",
        "судится": сдал,
    }


def вписать(узел):
    путь = КОРЕНЬ / "datasets" / "GENESIS-MANIFEST.json"
    м = json.loads(путь.read_text(encoding="utf-8"))
    миры = [w for w in м["worlds"] if w.get("name") != узел["name"]]
    заменено = len(м["worlds"]) - len(миры)
    миры.append(узел)
    м["worlds"] = миры
    путь.write_text(json.dumps(м, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")
    return заменено


def ковать(скан, кэш, манифест):
    пути = []
    for индекс in скан.индексы:
        пути += выгрузить(индекс, кэш)
    страницы = страницы_из_xml(пути, скан.индексы)
    текст = " ".join(чистый(т) for _н, т in страницы)
    все, хвост = статьи(текст)
    строки = строки_книги(все)
    тело, отложенное = shelf_fetch.отложить(строки)
    выход = КОРЕНЬ / "shelf" / скан.язык
    байт, строк = shelf_fetch.записать(выход / f"{скан.имя}.txt", тело)
    ещё = (shelf_fetch.записать(выход / f"{скан.имя}.holdout.txt",
                                отложенное) if отложенное else (0, 0))
    слов = sum(len(re.findall(r"[А-Яа-яЁё]+", с)) for с in тело)
    print(f"  {скан.имя:<22} страниц {len(страницы)}, статей {len(все)}, "
          f"строк {строк}, слов {слов}, байт {байт}, отложено {ещё[1]}, "
          f"вне гнёзд {len(хвост)} знаков: «{хвост[:160]}…»")
    if манифест:
        import shelf_forge
        сдал = shelf_forge.читающие(выход / f"{скан.имя}.txt")
        заменено = вписать(объявление(скан, sorted(сдал), байт, строк))
        print(f"  МАНИФЕСТ: {'заменено' if заменено else 'добавлено'} "
              f"{скан.имя}_ru, судится {sorted(сдал) or '—'}")
    return страницы


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--кэш", required=True)
    ap.add_argument("--только", default="")
    ap.add_argument("--манифест", action="store_true")
    ap.add_argument("--суд", type=int, default=-1,
                    help="судить орфографию: 0 — все статьи, N — выборка")
    а = ap.parse_args()
    кэш = pathlib.Path(а.кэш)
    книги = [к for к in ПОЛКА if not а.только or к.имя == а.только]
    for скан in книги:
        if а.суд >= 0:
            пути = []
            for индекс in скан.индексы:
                пути += выгрузить(индекс, кэш)
            суд_орфографии(страницы_из_xml(пути, скан.индексы), а.суд)
        else:
            ковать(скан, кэш, а.манифест)
    return 0


if __name__ == "__main__":
    sys.exit(main())
