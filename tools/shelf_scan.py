def спросить(вики="ru", **поля):
    поля["format"] = "json"
    з = urllib.request.Request(API.format(вики=вики) + "?"
                               + urllib.parse.urlencode(поля),
                               headers={"User-Agent": UA})
    return json.load(urllib.request.urlopen(з, timeout=120))


_ПРОСТРАНСТВО = {}


def пространство_страниц(вики):
    """Номер пространства страниц скана — у Викитек он разный («Страница»
    и «Page» — 104, польская «Strona» — 100): спрашивается у самой вики
    по каноническому имени «Page», а не зашивается."""
    if вики not in _ПРОСТРАНСТВО:
        д = спросить(вики, action="query", meta="siteinfo", siprop="namespaces")
        _ПРОСТРАНСТВО[вики] = next(
            k for k, v in д["query"]["namespaces"].items()
            if v.get("canonical") == "Page")
    return _ПРОСТРАНСТВО[вики]


НОМЕР_СТРАНИЦЫ = re.compile(r"(\d+)(?:\.jpe?g|\.png)?$", re.I)


def страницы_индекса(индекс, вики="ru"):
    """Титулы страниц индекса по номеру: «…djvu/N» у книг одним файлом,
    «… N.jpeg» у книг, снятых постранично (Брюкнер на польской Викитеке)."""
    титулы, дальше = [], None
    постранично = not индекс.lower().endswith((".djvu", ".pdf"))
    приставка = индекс + (" " if постранично else "/")
    while True:
        поля = dict(action="query", list="allpages",
                    apnamespace=пространство_страниц(вики),
                    apprefix=приставка, aplimit="max")
        if дальше:
            поля["apcontinue"] = дальше
        д = спросить(вики, **поля)
        титулы += [p["title"] for p in д["query"]["allpages"]]
        дальше = д.get("continue", {}).get("apcontinue")
        if not дальше:
            break
        time.sleep(0.3)
    return sorted((т for т in титулы if НОМЕР_СТРАНИЦЫ.search(т)),
                  key=lambda т: int(НОМЕР_СТРАНИЦЫ.search(т).group(1)))


def выгрузить(индекс, кэш, вики="ru"):
    """XML-выгрузки страниц индекса — в кэш, пачками."""
    кэш.mkdir(parents=True, exist_ok=True)
    ключ = re.sub(r"[^\w]+", "_", индекс)[:60]
    готовые = sorted(кэш.glob(ключ + "_*.xml"))
    if готовые:
        return готовые
    титулы = страницы_индекса(индекс, вики)
    вон = []
    for i in range(0, len(титулы), ПАЧКА):
        тело = urllib.parse.urlencode(
            {"pages": "\n".join(титулы[i:i + ПАЧКА]), "curonly": "1",
             "wpDownload": "1"}).encode()
        з = urllib.request.Request(EXPORT.format(вики=вики), data=тело,
                                   headers={"User-Agent": UA})
        путь = кэш / f"{ключ}_{i // ПАЧКА:02}.xml"
        путь.write_bytes(urllib.request.urlopen(з, timeout=600).read())
        вон.append(путь)
        time.sleep(1.0)
    return вон


def страницы_из_xml(пути, индексы):
    """[(номер, wikitext)] — тома в порядке объявления, внутри тома по
    номеру страницы. Первая редакция сортировала все страницы одним
    числом и смешала четыре тома: словарь начинался с буквы «П»."""
    вон = []
    for путь in пути:
        x = путь.read_text(encoding="utf-8")
        for м in re.finditer(
                r"<title>(.*?)</title>.*?<text[^>]*>(.*?)</text>", x, re.S):
            титул = html.unescape(м.group(1))
            м_номер = НОМЕР_СТРАНИЦЫ.search(титул)
            if not м_номер:
                continue
            # Том — тот индекс, чьё имя стоит в титуле («…djvu/N» или «… N.jpeg»).
            том = next((i for i, и in enumerate(индексы) if и in титул), len(индексы))
            вон.append(((том, int(м_номер.group(1))), html.unescape(м.group(2))))
    return [(н, т) for (_том, н), т in sorted(вон, key=lambda п: п[0])]


# ЧИСТКА — ПРАВИЛАМИ В ПОРЯДКЕ, И КАЖДОЕ НАЗВАНО.
ШАБЛОНЫ = (
    (re.compile(r"\{\{перенос2\|[^}]*\}\}"), ""),
    (re.compile(r"\{\{перенос\|([^|}]*)\|([^|}]*)\}\}"), r"\1\2"),
    (re.compile(r"\{\{[Аа]кут3?\}\}"), ""),
    (re.compile(r"\{\{!\}\}"), "|"),
    (re.compile(r"\{\{tsd[ls]\|([^|{}]*)(?:\|[^{}]*)?\}\}"), r"\1"),
    (re.compile(r"\{\{lang\|[^|{}]*\|([^{}]*)\}\}"), r"\1"),
    (re.compile(r"\{\{дробь\|([^|{}]*)\|([^|{}]*)\|([^|{}]*)\}\}"),
     r"\1 \2/\3"),
    (re.compile(r"\{\{дробь\|([^|{}]*)\|([^|{}]*)\}\}"), r"\1/\2"),
    (re.compile(r"\{\{опечатка2?\|[^|{}]*\|([^|{}]*)(?:\|[^{}]*)?\}\}"),
     r"\1"),
)
ЛЮБОЙ_ШАБЛОН = re.compile(r"\{\{[^{}]*\}\}")
# ССЫЛКИ ВИКИ: картинка снимается целиком (буква-цифра кириллицы —
# рисунок, не слово), ссылка со словом оставляет слово.
ССЫЛКИ = (
    (re.compile(r"\[\[(?:File|Файл|Image|Изображение):[^\[\]]*\]\]"), ""),
    (re.compile(r"\[\[[^\[\]|]*\|([^\[\]]*)\]\]"), r"\1"),
    (re.compile(r"\[\[([^\[\]]*)\]\]"), r"\1"),
)
ЗАГОЛОВОК = "⁣"   # невидимый разделитель — маркер заголовка гнезда


def чистый(wikitext):
    """Текст страницы без разметки; заголовки гнёзд помечены маркером."""
    т = re.sub(r"<noinclude>.*?</noinclude>", "", wikitext, flags=re.S)
    т = re.sub(r"<!--.*?-->", "", т, flags=re.S)
    for образец, замена in ШАБЛОНЫ:
        т = образец.sub(замена, т)
    while ЛЮБОЙ_ШАБЛОН.search(т):
        т = ЛЮБОЙ_ШАБЛОН.sub("", т)
    for образец, замена in ССЫЛКИ:
        т = образец.sub(замена, т)
    # ЗАГОЛОВОК ГНЕЗДА — ИМЯ СЕКЦИИ, А НЕ ЖИРНЫЙ ШРИФТ. Первая редакция
    # брала заголовком жирное слово: жирным у Даля набраны и
    # подзаголовки внутри гнезда, а курсив, примыкающий к жирному без
    # пробела, даёт пять апострофов подряд — и разбор разметки
    # сбивался на 1512 заголовках из 83 611, вынося текст мимо гнёзд.
    # Секция же режет книгу ровно по статьям (так её читает сама
    # Викитека), и имя секции есть заголовок в современной орфографии.
    # СЕКЦИИ ВЛОЖЕНЫ: гнездо «Авось» несёт внутри секцию «Абы» (слово,
    # на которое ссылаются отдельно), и пустые секции-указатели. Оба
    # края секции остаются маркерами, а статьи собирает стек.
    т = re.sub(r'<section (begin|end)="([^"]+)" ?/>',
               lambda м: ЗАГОЛОВОК + м.group(1)[0] + м.group(2).strip()
               + ЗАГОЛОВОК, т)
    т = re.sub(r"<[^<>]+>", "", т)
    т = т.replace("__NOEDITSECTION__", "")
    т = т.replace("'''", "").replace("''", "")
    # ОСТАТКИ РАЗБИТОЙ РАЗМЕТКИ (шаблон, закрытый на другой странице,
    # скобка без пары) — не текст книги; их число печатается отчётом.
    т = re.sub(r"\{\{|\}\}|\[\[|\]\]", " ", т)
    т = re.sub(r"[ \t\r\f\v]+", " ", т)
    т = re.sub(r"\s*\n\s*", " ", т)
    return т.strip()


def статьи(текст, орфография=True):
    """[(ЗАГОЛОВОК, тело)] — по маркерам секций, стеком; орфография
    современная у русского подлинника (у иных языков — как есть). Текст
    принадлежит ВЕРХНЕЙ открытой секции; закрытие вложенной возвращает
    слово гнезду; часть гнезда, разорванного страницей, склеивается по
    имени; пустая секция не есть статья."""
    совр = oldspell.современно if орфография else (lambda т, св=None: т)
    куски = текст.split(ЗАГОЛОВОК)
    тела, порядок, стек, хвост = {}, [], [], []
    for i, кусок in enumerate(куски):
        if i % 2 == 1:                      # маркер: bИмя / eИмя
            имя = кусок[1:]
            if кусок[0] == "b":
                стек.append(имя)
                if имя not in тела:
                    тела[имя] = []
                    порядок.append(имя)
            elif имя in стек:
                стек.remove(имя)
            continue
        if стек:
            тела[стек[-1]].append(кусок)
        else:
            хвост.append(кусок)
    вон = []
    подлинник = " ".join(" ".join(тела[и]) for и in порядок
                         if not и.endswith("+"))
    св = oldspell.свидетели(подлинник) if орфография else None
    for имя in порядок:
        # СТРАНИЦА НЕСЁТ ТЕКСТ ДВАЖДЫ: подлинник в секции «Имя» и его
        # модернизацию редакторов Викитеки в секции «Имя+». Книга
        # берётся с подлинника одной дорогой (правило oldspell), а
        # копия «+» служит СУДОМ дороги — иначе словарь лёг бы на полку
        # вдвое (88 852 статьи вместо 44 тысяч).
        if имя.endswith("+"):
            continue
        тело = совр(" ".join(тела[имя]), св).strip()
        тело = re.sub(r"\s+", " ", тело)
        первое = re.match(r"[^\W\d_][\w\-]*", совр(имя, св))
        if not первое or not тело:
            continue
        заголовок = совр(имя, св).strip(" .,;:")
        вон.append((первое.group().upper() + заголовок[первое.end():],
                    тело))
    return вон, " ".join(хвост).strip()


def строки_книги(статьи_):
    """Статья — строка «ЗАГОЛОВОК тело», между статьями пустая строка."""
    вон = []
    for заголовок, тело in статьи_:
        вон.append(f"{заголовок} {тело}".strip())
        вон.append("")
    return вон


def секции(страницы):
    """{имя секции: сырой wikitext секции} — имена суть современные
    заголовки Викитеки, по ним судится орфография."""
    вон = {}
    for _н, т in страницы:
        for м in re.finditer(
                r'<section begin="([^"]+)" ?/>(.*?)<section end="\1" ?/>',
                т, re.S):
            вон.setdefault(м.group(1), м.group(2))
    return вон


def суд_орфографии(страницы, сколько):
    """Доля наших слов, найденных в модернизации Викитеки тех же статей.

    Суд ЛОКАЛЕН: страница несёт подлинник («Имя») и чужую модернизацию
    («Имя+») рядом, и пара для суда есть у каждой статьи без единого
    запроса. Берутся все пары либо каждая k-я до заданного числа.
    """
    все = секции(страницы)
    имена = sorted(и for и in все if и + "+" in все)
    шаг = max(1, len(имена) // сколько) if сколько else 1
    св = oldspell.свидетели(" ".join(чистый(все[и]) for и in все
                                     if not и.endswith("+")))
    пары = []
    for имя in имена[::шаг]:
        наше = oldspell.современно(чистый(все[имя]), св)
        чужое = чистый(все[имя + "+"])
        пары.append((re.sub(ЗАГОЛОВОК + "[^" + ЗАГОЛОВОК + "]*" + ЗАГОЛОВОК,
                            " ", наше),
                     re.sub(ЗАГОЛОВОК + "[^" + ЗАГОЛОВОК + "]*" + ЗАГОЛОВОК,
                            " ", чужое).replace("\u0301", "")))
    доля, расхождения = oldspell.суд(пары)
    print(f"ОРФОГРАФИЯ: статей с парой {len(имена)}, судимо {len(пары)}, "
          f"наших слов найдено у Викитеки {100 * доля:.2f}%")
    for (а, б), n in расхождения[:28]:
        print(f"  {n:5}  наше «{а}» — у них «{б}»")
    return доля


