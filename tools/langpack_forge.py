#!/usr/bin/env python3
"""КУЗНЯ ПАКЕТОВ: язык стоит СЛОВАРЯ, а не двухсот строк описания.

Владелец расширил цель до ВСЕХ языков: «лучше вообще все добавить и
постепенно подтягивать». Пакет руками стоит двухсот пятидесяти строк
JSON — при таком счёте двадцать языков суть пять тысяч строк, и большая
часть из них ОДИНАКОВА: роды показов, шаблоны, связки с ядром, форма
отказа. Одинаковое обязано жить в одном месте.

СЕМЯ ЯЗЫКА — ТОЛЬКО ТО, ЧТО У ЯЗЫКА СВОЁ: письмо, буквы, числительные,
закон согласования по счёту, слова действий, глагольная парадигма,
имена с артиклем, местоимения, пять пар отказа. Сорок строк вместо
двухсот пятидесяти.

ФОРМА ПОКАЗА ОБЩАЯ, СЛОВА СВОИ. Отсюда же следует то, ради чего это и
делается: КАЖДЫЙ ЯЗЫК ПОЛУЧАЕТ ОДИН И ТОТ ЖЕ НАБОР РОДОВ, и потому
пласты сравнимы между собой — организм видит один факт на двадцати
поверхностях, а не двадцать разных корпусов.

ЧЕГО КУЗНЯ НЕ ДЕЛАЕТ, И ЭТО ГЛАВНОЕ: она НЕ ПРОВЕРЯЕТ ЯЗЫК. Верны ли
формы «hablas» и «parlez» — знает носитель, а не кузня. Движок пакетов
судит СТРОЕНИЕ (роды раздельны, буквы прожиты, отказы парны,
арифметика сходится), и его девять полей — это всё, что мы вправе
утверждать до проверки носителем. Потому всякое семя несёт ярус:
`tier: 1` значит «строение зелено, язык не проверен носителем».
"""

import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parent
ПАКЕТЫ = КОРЕНЬ / "langpacks"

# ОБЩИЙ ЗАКОН ИСТОЧНИКА ЛЕКСЕМ — один на все языки.
ЗАКОН_ЛЕКСЕМ = {
    "law": ("every morph class must carry >= LAW distinct lexemes; a class "
            "below its declared need is judged poor by the engine"),
    "need_per_class": 5,
}


def выковать(семя):
    """Полный пакет из семени языка."""
    я = семя["lang"]
    оп = семя["ops"]                     # слово → глиф
    гл = семя["verbs"]                   # инфинитив → формы по лицам
    им = семя["nouns"]                   # ключ → [ед., мн.]
    лица = семя["persons"]
    сл = семя["words"]                   # служебные имена ролей
    клетки = len(next(iter(гл.values())))
    формы_лиц = ["s1", "s2", "s3", "p1", "p2", "p3"][:клетки]

    классы = {
        "verb_pres": {"forms": формы_лиц, "paradigm_cells": клетки,
                      "need": 5, "lexemes": гл},
        "noun_count": {"forms": ["one", "many"], "paradigm_cells": 2,
                       "need": 5, "lexemes": им},
    }
    # ВСТРОЕННЫЙ ОРАКУЛ (замысел verum-6c): ФОРМА УТВЕРЖДАЕТСЯ ДВАЖДЫ,
    # НЕЗАВИСИМЫМИ ПУТЯМИ — клеткой таблицы и ВЫВОДОМ ИЗ ПРАВИЛА
    # (основа + окончание). Правило и таблица суть два независимых
    # высказывания об одном факте, и подмена клетки соседней рушится о
    # правило: не потому, что движок знает язык, а потому что ЛОЖЬ
    # ПРИШЛОСЬ БЫ СОЛГАТЬ СОГЛАСОВАННО ДВАЖДЫ.
    #
    # ВЫИГРЫШ, РАДИ КОТОРОГО ЭТО И ДЕЛАЕТСЯ: носитель нужен ПРАВИЛАМ
    # (десятки), а не каждой форме (тысячи). Доверяемое основание падает
    # на два порядка, и двадцать языков перестают быть балластом.
    #
    # ЧЕСТНАЯ ГРАНИЦА: проба обнаруживает НЕСОГЛАСОВАННОСТЬ, а не
    # ложность. Пакет, одинаково неверный на обоих путях, пройдёт — и
    # заявление звучит ровно так: «формы согласны с объявленными
    # правилами», не «формы верны».
    if "verb_rule" in семя:
        классы["verb_pres"]["rule"] = семя["verb_rule"]
    if "adjs" in семя:
        прил = семя["adjs"]
        классы["adj_forms"] = {
            "forms": семя.get("adj_cells", ["a", "b", "c", "d"])[
                :len(next(iter(прил.values())))],
            "paradigm_cells": len(next(iter(прил.values()))),
            "need": 5, "lexemes": прил}

    # ШАБЛОНЫ ЛИЦ СТРОЯТСЯ ПО ЧИСЛУ КЛЕТОК, а не пишутся списком:
    # язык с четырьмя лицами не обязан выдумывать шестое.
    спряжение = [f"{лица[i]} {{lex:verb_pres:{формы_лиц[i]}}}."
                 for i in range(клетки)]

    # ЧИСЛО ПОКАЗОВ НА ПРОХОД ВЫВОДИТСЯ ИЗ ЧИСЛА ЛЕКСЕМ, А НЕ ПИШЕТСЯ
    # РУКОЙ. Первое же семя вскрыло дефект: с четырнадцатью именами
    # рукописная дюжина показов давала каждому имени по два прохода, с
    # двадцатью тремя — одному имени достался ОДИН, и закон повтора
    # пал. Закон, который лишь ПРОВЕРЯЕТСЯ после сборки, обязан быть
    # ГАРАНТИРОВАН при сборке: столько показов, чтобы всякая лексема
    # прожила дважды, — и ни один язык не упрётся в чужую константу.
    показов_имён = max(12, 2 * len(им))
    показов_лиц = max(12, 2 * len(гл))
    роды = {
        "arithmetic": {
            "lexicon": list(оп),
            "ops": оп,
            "instances_per_pass": 14,
            "templates": [
                f"{{num:n}} {семя['w_plus']} {{num:m}} "
                f"{семя['w_eq']} {{num:sum}}.",
                "{n} + {m} = {sum}.",
                f"{{num:sum}} {семя['w_minus']} {{num:m}} "
                f"{семя['w_eq']} {{num:n}}.",
                f"{{num:n}} {семя['w_times']} {{num:m}} "
                f"{семя['w_eq']} {{num:prod}}.",
                f"{{num:prod}} {семя['w_div']} {{num:m}} "
                f"{семя['w_eq']} {{num:n}}.",
            ]},
        "conjugation": {
            "lexicon": лица, "instances_per_pass": показов_лиц,
            "templates": спряжение},
        # ШАБЛОН БЕРЁТСЯ У ЯЗЫКА, А НЕ НАВЯЗЫВАЕТСЯ ЕМУ. Испанский
        # ставит «aquí está» при единственном и «aquí están» при
        # множественном — язык, которому навязали одну рамку, был бы
        # неграмотен по построению, и кузня учила бы ошибке.
        "counting": {
            "lexicon": сл["count_lexicon"],
            "instances_per_pass": показов_имён,
            "templates": [т.replace("{one}", "{lex:noun_count:one}")
                          .replace("{many}", "{lex:noun_count:many}")
                          for т in сл["count_templates"]]},
        "definition": {
            "lexicon": сл["def_lexicon"],
            "instances_per_pass": показов_имён,
            "templates": [т.replace("{one}", "{lex:noun_count:one}")
                          for т in сл["def_templates"]]},
        "refusals": {
            "refusal": True, "marker": "¬ ", "lexicon": ["¬"],
            "pairs": семя["refusals"]},
    }
    if "adjs" in семя:
        роды["agreement"] = {
            "lexicon": семя["adj_lexicon"],
            "instances_per_pass": 12,
            "templates": семя["adj_templates"]}

    пакет = {
        "lang": я,
        "script": семя["script"],
        "script_range": семя["script_range"],
        "graphemes": семя["graphemes"],
        "tier": семя.get("tier", 1),
        "comment": семя["comment"],
        "lexeme_source": ЗАКОН_ЛЕКСЕМ,
        "numerals": семя["numerals"],
        "count_agreement": семя["count_agreement"],
        "morph_classes": классы,
        "show_kinds": роды,
        "core_pairing": [
            {"lang_word": сл_, "core": глиф, "core_form": глиф,
             "lang_form": сл_}
            for сл_, глиф in (("w_plus", "+"), ("w_minus", "-"),
                              ("w_times", "×"), ("w_div", "÷"),
                              ("w_eq", "="))
            for сл_ in [семя[сл_]]],
        "cross_kind_share": семя.get("cross_kind_share", 0.3),
        "irregulars": семя["irregulars"],
        "probe": {"words": sorted(set(семя["probe"])),
                  "diacritics": семя.get("diacritics", "")},
    }
    for поле in ("segmentation", "script_default", "stem_min",
                 "ending_max", "reserved"):
        if поле in семя:
            пакет[поле] = семя[поле]
    return пакет


def записать(семя):
    пакет = выковать(семя)
    путь = ПАКЕТЫ / f"{семя['lang']}.json"
    путь.write_text(json.dumps(пакет, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")
    return путь
