#!/usr/bin/env python3
"""ДОМ ЧИСЛА-ИМЕНИ — ОДНО И ТО ЖЕ ЧИСЛО ЗОВЁТ ВЕЩЬ И МЕРИТ ЕЁ, И ЭТО ДВА РАЗНЫХ ДЕЛА.

    НИ ОДНОЙ СТРОКОЙ СВОД НЕ ОТЛИЧАЕТ ИМЕНИ ОТ МЕРЫ. Замер 11.09 по 256 мирам показов:
    «дом 5», «автобус 12», «квартира 7» — НОЛЬ; «номер не складывают», «labels are not added» —
    НОЛЬ; «одно число значит разное» — НОЛЬ.

Свод считает сотнями тысяч строк и всякий раз считает МЕРУ. Слово «номер» в нём есть — 2515 раз
в двенадцати мирах, — и почти всюду это ПОРЯДКОВЫЙ НОМЕР: «член номер 5 прогрессии от 2 с шагом 2
равен 10: 5 − 1 = 4». Над таким номером свод СЧИТАЕТ, и считает верно.

    НАД ИМЕНЕМ СЧИТАТЬ МОЖНО, НО НЕ ВСЯКИМ СЧЁТОМ: ИМЕНА ДОПУСКАЮТ ПОРЯДОК И ШАГ,
    НО НЕ СУММУ ДВУХ ИМЁН.

Мир прогрессий (`sequences`) вычитает из номера единицу и получает ШАГ ПО ПОРЯДКУ — это законно
и здесь не оспаривается. Оспаривается иное: сложение ДВУХ имён, которого свод не показывал и
не запрещал.

ДВАДЦАТЬ ВОСЬМАЯ ЛОВУШКА РЯДА, И ОНА ПЕРВАЯ, ГДЕ СЧЁТ ВЕРЕН, А ОТВЕТ НЕ СУЩЕСТВУЕТ:

    ВЕРНЫЙ СЧЁТ НАД ИМЕНАМИ ДАЁТ ВЕРНОЕ ЧИСЛО И НИКАКОЙ ВЕЩИ.

«Страница 5 и страница 3»: 5 + 3 = 8 — равенство истинно, и страницы 8 из него не выходит.
Всякая прежняя ловушка ряда ловила ошибку в счёте, в порядке или в вопросе; эта ловит счёт
БЕЗУПРЕЧНЫЙ и потому невидимый ни одному суду арифметики.

ЧЕТЫРЕ РОДА:

    мера         5 страниц и ещё 3 страницы — это 8 страниц: 5 + 3 = 8.
    имя          страница 5 и страница 3 — это две страницы: 1 + 1 = 2; а 5 + 3 = 8
                 не называет никакой страницы.                                    ← ЛОВУШКА
    порядок      страница 5 стои́т между 3 и 7: 3 меньше 5, и 5 меньше 7; имена идут
                 по порядку, а складывать их нельзя.                              ← ГРАНИЦА
    два дела     клетка 5, а в ней 5 шариков: первое 5 — имя, второе — мера.

ПЕРВЫЙ И ВТОРОЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО ДЕЛУ ЧИСЛА: те же два числа, та же вещь, то же сложение,
и разница в одном — стои́т число ПЕРЕД словом (мера) или ПОСЛЕ него (имя). По-русски это видно
самой расстановкой, и потому дом не просит у языка ни одной новой формы.

    ЧИСЛО ПЕРЕД СЛОВОМ МЕРИТ, ЧИСЛО ПОСЛЕ СЛОВА ЗОВЁТ. Одна перестановка — и сложение из
    осмысленного делается пустым.

ТРЕТИЙ РОД ЕСТЬ ГРАНИЦА ЗАКОНА, БЕЗ КОТОРОЙ ЗАКОН ЛОЖЕН: имена сравнивают и по ним идут — иначе
`sequences` был бы объявлен неправым, а он прав.

    ПРАВИЛО, ЗАПРЕЩАЮЩЕЕ БОЛЬШЕ, ЧЕМ НАДО, ОБЪЯВЛЯЕТ ЛОЖЬЮ ЧЕСТНУЮ РАБОТУ СОСЕДА.

ЧЕТВЁРТЫЙ СТАВИТ ОДНО ЧИСЛО ДВАЖДЫ В ОДНОЙ СТРОКЕ, раз именем и раз мерой, — и тем показывает,
что дело числа не в нём самом, а в месте.

ВСЕ СЛОВА ВЗЯТЫ У ЯЗЫКА, И НИ ОДНО НЕ ОБЪЯВЛЕНО РАДИ ЭТОГО ДОМА: «страница», «билет», «клетка»,
«вершина», «шарик», «орех», «камень», «знак» стоя́т в счётной таблице `rugram` с 03.09. Утром
этой смены правка языка ради одного оборота стоила пятнадцати чужих строк, и второй раз платить
за то же незачем.

    python3 tools/numlabelforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётные формы взяты там, новых не заведено

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("мера", "имя", "порядок", "два дела", "спрошенное")

# ВЕЩИ, НОСЯЩИЕ ИМЯ-ЧИСЛО, и вещи, которые ими меряют. Все объявлены языком.
ИМЕНА = ("страница", "билет", "клетка", "вершина")
ВЕЩИ = ("шарик", "орех", "камень", "знак")
АНГЛ = {"страница": ("page", "pages"), "билет": ("ticket", "tickets"),
        "клетка": ("cell", "cells"), "вершина": ("vertex", "vertices"),
        "шарик": ("ball", "balls"), "орех": ("nut", "nuts"),
        "камень": ("stone", "stones"), "знак": ("sign", "signs")}


def форма(язык, ключ, n):
    if язык == "en":
        один, много = АНГЛ[ключ]
        return один if n == 1 else много
    return rugram.форма(ключ, n)


РАМКИ = {
    "ru": {
        "мера": "{a} {и_a} и ещё {b} {и_b} — это {s} {и_s}: {a} + {b} = {s}.",
        # ИМЯ ВЫДЕЛЕНО В ОБОИХ ЯЗЫКАХ (12.09). Английская страница писала «a number after
        # the word CALLS and does not MEASURE», выделяя оба дела заглавными, а русская —
        # «номер зовёт, а не мерит», без выделения: русский читатель не видел, что перед
        # ним ДВА НАЗВАННЫХ ДЕЛА числа, а не оборот речи.
        #
        #     ВЫДЕЛЕНИЕ ЕСТЬ ЧАСТЬ ИМЕНИ: слово, названное в одном языке и сказанное
        #     мимоходом в другом, читается как имя только там, где выделено.
        "имя": "{имя} {a} и {имя} {b} — разные, и суммы у них нет: {a} + {b} = {s} — число, "
               "а не {имя}; номер ЗОВЁТ, а не МЕРИТ.",
        "порядок": "{имя} {b} стои́т между {c} и {a}: {c} меньше {b}, и {b} меньше {a}; "
                   "имена идут по порядку, а складывать их нельзя.",
        "два дела": "{имя} {a} и {a} {в_a} — одно число дважды: первое зовёт, второе мерит; "
                    "так же {имя} {b} и {b} {в_b}. вместе {s} {в_s}: {a} + {b} = {s} — "
                    "сложились меры, а не имена.",
        "спрошенное": "сколько будет {a} {и_a} и ещё {b} {и_b}? {s} {и_s}: {a} + {b} = {s}.",
    },
    "en": {
        "мера": "{a} {и_a} and {b} {и_b} more — that is {s} {и_s}: {a} + {b} = {s}.",
        "имя": "{имя} {a} and {имя} {b} are different, and they have no sum: {a} + {b} = {s} "
               "is a number and not a {имя}; a number after the word CALLS and does not MEASURE.",
        "порядок": "{имя} {b} stands between {c} and {a}: {c} is less than {b}, and {b} is less "
                   "than {a}; names go in order, and adding them is not allowed.",
        "два дела": "{имя} {a} and {a} {в_a} — one number twice: the first calls, the second "
                    "measures; and so with {имя} {b} and {b} {в_b}. together {s} {в_s}: "
                    "{a} + {b} = {s} — the measures were added, the names were not.",
        "спрошенное": "how much is {a} {и_a} and {b} {и_b} more? {s} {и_s}: {a} + {b} = {s}.",
    },
}
# РОД СЛОВА ЯЗЫКОМ НЕ ОБЪЯВЛЕН, И ДОМ ЕГО НЕ УГАДЫВАЕТ: ни «две/два», ни «в ней/в нём»
# в рамках нет вовсе — всё сказано так, что род не нужен.
#
#     ЧЕГО ЯЗЫК НЕ ОБЪЯВИЛ, ТОГО ДОМ НЕ ЗНАЕТ; ОБОРОТ, ТРЕБУЮЩИЙ НЕОБЪЯВЛЕННОГО,
#     ЗАМЕНЯЕТСЯ ОБОРОТОМ, НЕ ТРЕБУЮЩИМ ЕГО.
ПУСТО = dict(a=0, b=0, c=0, d=0, s=0, имя="", и_a="", и_b="", и_s="",
             в_a="", в_b="", в_s="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for имя, вещь in zip(ИМЕНА, ВЕЩИ):
            # ИМЯ ВЕЩИ В ЕДИНСТВЕННОМ — то, что стои́т перед числом-именем: «страница 5».
            одно = форма(язык, имя, 1)
            for a in range(2, 13):
                for b in range(2, 13):
                    if a == b or (a + b + len(имя)) % 3:
                        continue
                    общ = dict(ПУСТО, a=a, b=b, s=a + b, имя=одно,
                               и_a=форма(язык, имя, a), и_b=форма(язык, имя, b),
                               и_s=форма(язык, имя, a + b))
                    вон[рамки["мера"].format(**общ)] = (язык, "мера")
                    # СПРОШЕННОЕ: тот же закон, поставленный ВОПРОСОМ.
                    #
                    #     МИР БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ ПОКАЗЫВАЕТ ОТВЕТ, НЕ ПОКАЗЫВАЯ ЗАДАЧИ.
                    if (a + b) % 3 == 0:
                        вон[рамки["спрошенное"].format(**общ)] = (язык, "спрошенное")
                    вон[рамки["имя"].format(**общ)] = (язык, "имя")
            # ПОРЯДОК: имя стои́т между двумя другими, и сравнения истинны.
            for b in range(3, 12):
                for шаг in (1, 2, 3):
                    c, a = b - шаг, b + шаг
                    if c < 1 or (b + шаг + len(имя)) % 2:
                        continue
                    вон[рамки["порядок"].format(
                        **dict(ПУСТО, a=a, b=b, c=c, имя=одно))] = (язык, "порядок")
            # ДВА ДЕЛА: одно число дважды — именем и мерой, и так дважды в одной строке.
            for a in range(2, 10):
                for b in range(a + 1, 11):
                    if (a + b + len(вещь)) % 4:
                        continue
                    вон[рамки["два дела"].format(
                        **dict(ПУСТО, a=a, b=b, s=a + b, имя=одно,
                               в_a=форма(язык, вещь, a), в_b=форма(язык, вещь, b),
                               в_s=форма(язык, вещь, a + b)))] = (язык, "два дела")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА = re.compile(r"(?<![/\d])(?<!\+ )(\d+) \+ (\d+) = (\d+)(?![/\d])")
_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_МЕНЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:меньше|is less than) (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b in _МЕНЬШЕ.findall(с):
        if int(a) >= int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    мер = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "мера")
    им = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "имя")
    for страница, слово, куда in ((мер, "ещё", "ещ"), (им, "номер", "номе")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(мер + " " + мер)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # МИНИМАЛЬНАЯ ПАРА: у меры и у имени ОДНИ И ТЕ ЖЕ тройки чисел, иначе пара не минимальна.
    тр_м = {tuple(sorted(_СУММА.findall(с)[0])) for с, (я, р) in ПОКАЗЫ.items()
            if я == "ru" and р == "мера"}
    # У РОДА ИМЕНИ ПЕРВОЙ СТОИ́Т ПАРА «1 + 1 = 2» — счёт САМИХ СТРАНИЦ, а не их имён;
    # тройка имени есть ПОСЛЕДНЯЯ сумма строки.
    тр_и = {tuple(sorted(_СУММА.findall(с)[-1])) for с, (я, р) in ПОКАЗЫ.items()
            if я == "ru" and р == "имя"}
    if тр_м != тр_и:
        беды.append(f"тройки меры и имени разошлись: {len(тр_м)} и {len(тр_и)}")
    # РОД ИМЕНИ ОБЯЗАН НЕСТИ ЧИСЛО ПОСЛЕ СЛОВА, род меры — перед словом.
    for с, (я, р) in ПОКАЗЫ.items():
        if я != "ru":
            continue
        if р == "имя" and not re.match(r"^\S+ \d", с):
            беды.append(f"имя не стои́т перед числом: {с[:70]}")
            break
        if р == "мера" and not re.match(r"^\d", с):
            беды.append(f"мера не начата числом: {с[:70]}")
            break
    print(f"ЧИСЛО-ИМЯ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
