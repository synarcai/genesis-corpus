#!/usr/bin/env python3
"""GENESIS layer: ЗАКОН СЧЁТНОЙ ФОРМЫ — see tools/countlawforms.py for the law.

ПРАВИЛО И ЕГО ЛОВУШКИ РАЗДЕЛЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ЛОМАЮТ.

«Форма названа» и «подростки ломают правило» идут вместе: первое даёт правило по последней
цифре, второе тут же отнимает вывод «последняя цифра решает всё», который читатель сделал бы
из первого сам.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Двадцать один — не один» стои́т особо: это не ловушка, а ДОВОД — два языка, одно число, две
формы, — и соседство разбавило бы его.

«Язык без трёх форм» и «правило читается сверху вниз» — третьей группой: обе о ГРАНИЦАХ
правила, одна вширь (иные языки), другая вглубь (порядок правил внутри одного языка).
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import countlawforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_countlaw.txt"
ГРУППЫ = (("форма названа", "подростки ломают правило"),
          ("двадцать один — не один",),
          ("язык без трёх форм", "правило читается сверху вниз"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
