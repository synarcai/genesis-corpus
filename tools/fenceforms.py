#     ФОРМА, ВЫХОДЯЩАЯ ЛИШЬ ПРИ ОДНОМ ЧИСЛЕ ТАБЛИЦЫ, ЖИВЁТ РОВНО СТОЛЬКО РАЗ, СКОЛЬКО
#     ТАКИХ ЧИСЕЛ В НЕЙ.
РЯДЫ = (5, 6, 8, 10, 12, 4, 3)


def _ф(ключ, n, язык, ан):
    return rugram.форма(ключ, n) if язык == "ru" else (ан if n == 1 else ан + "s")


