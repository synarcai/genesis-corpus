def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a, b in ДНИ:
            разн, дней = b - a, b - a + 1
            общ = dict(a=a, b=b, разн=разн, дней=дней,
                       д=_ф("день", дней, язык, "day"))
            вон[рамки["дни включительно"].format(**общ)] = (язык, "дни включительно")
            вон[рамки["спрошенное"].format(**общ)] = (язык, "спрошенное")
        for n in РЯДЫ:
            m = n - 1
            вон[рамки["столбы и пролёты"].format(
                n=n, m=m, с=_ф("столб", n, язык, "post"),
                п=_ф("пролёт", m, язык, "span"))] = (язык, "столбы и пролёты")
            вон[рамки["распилы"].format(
                n=n, m=m, ч=_ф("часть", n, язык, "piece"))] = (язык, "распилы")
            вон[рамки["этажи и марши"].format(
                n=n, m=m, мар=_ф("марш", m, язык, "flight"))] = (язык, "этажи и марши")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_РАЗНОСТЬ = re.compile(r"(?<![\d/])(\d+) − (\d+) = (\d+)(?![\d/])")
_СУММА = re.compile(r"(?<![\d/])(\d+) \+ (\d+) = (\d+)(?![\d/])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, r in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(r):
            return True, False
    for a, b, r in _СУММА.findall(с):
        if int(a) + int(b) != int(r):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ЛОВУШКА ОБЯЗАНА БЫТЬ ВИДНА: разность не должна равняться числу предметов.
    for a, b in ДНИ:
        if b - a < 2:
            беды.append(f"промежуток мал, потеря не видна: {a}–{b}")
        if b <= a:
            беды.append(f"конец не позже начала: {a}–{b}")
    for n in РЯДЫ:
        if n < 3:
            беды.append(f"ряд короток, пролёт не виден: {n}")
    # ОБЕ СТОРОНЫ ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ: где прибавляют и где отнимают.
    прибавляют = {р for _я, р in по_роду if р in ("дни включительно", "спрошенное")}
    отнимают = {р for _я, р in по_роду if р in ("столбы и пролёты", "распилы", "этажи и марши")}
    if not прибавляют or not отнимают:
        беды.append("показана лишь одна сторона ловушки")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    дн = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "дни включительно")
    порча = дн.replace("ПРОМЕЖУТКИ", "ПРОМЕЖУТК", 1)
    if порча == дн:
        беды.append("порча не состоялась: нет слова «ПРОМЕЖУТКИ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(дн + " " + дн)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"СЧЁТ ВКЛЮЧИТЕЛЬНО: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
