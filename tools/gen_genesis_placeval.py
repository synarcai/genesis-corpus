#!/usr/bin/env python3
"""КОВКА ДОМА РАЗРЯДА.

РАЗЛОЖЕНИЕ И ЛОВУШКА ИДУТ В ОДНОМ ПРОХОДЕ: первое говорит, ЧТО значит место, вторая показывает,
что без места цифры ничего не решают. Порознь разложение было бы обрядом без причины, а ловушка —
загадкой без ключа.

ВЕС И НОЛЬ ИДУТ СВОЕЙ ГРУППОЙ: первый мерит, во сколько раз место тяжелее соседнего, второй
показывает единственную цифру, которая ничего не считает и всё же обязана стоять. Обе страницы
об одном: место есть вещь, а не пробел между цифрами.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import placevalforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_placeval.txt"
# ВОПРОС СТОИ́Т СВОЕЙ ГРУППОЙ: он не новый случай закона, а ТОТ ЖЕ,
# поставленный иначе. Ответ рядом с вопросом отнимает у вопроса цену.
ГРУППЫ = (("разложение", "те же цифры"), ("вес места", "ноль держит"), ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
