#!/usr/bin/env python3
"""THE HOUSE OF SUMMARY PHRASES — the mean and the percent in eight languages.

The average world says «the average of 10, 14, 15 is 13: 10 + 14 + 15 = 39,
39 ÷ 3 = 13» and the percent world «2% of 50 is 1» in English and Russian.
This house says the two facts in de/fr/es/it/pt/nl/pl/tr — statement and
question answered by the statement (М-153) — with a ledger the court
recomputes: the mean as the sum and the division, the percent as the
product and the division by 100. Generator and court read one table.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import phrases  # noqa: E402

# {р} — the list «10, 14, 15»; {с} — the mean; {л} — the ledger;
# {p} — the percent, {n} — the number, {в} — the value
ЯЗЫКИ = {
    "de": dict(ср="der Durchschnitt von {р} ist {с}: {л}.", в_ср="was ist der Durchschnitt von {р}?",
               пр="{p} % von {n} sind {в}: {л}.", в_пр="was sind {p} % von {n}?"),
    "fr": dict(ср="la moyenne de {р} est {с} : {л}.", в_ср="quelle est la moyenne de {р} ?",
               пр="{p} % de {n} font {в} : {л}.", в_пр="combien font {p} % de {n} ?"),
    "es": dict(ср="el promedio de {р} es {с}: {л}.", в_ср="¿cuál es el promedio de {р}?",
               пр="el {p} % de {n} es {в}: {л}.", в_пр="¿cuánto es el {p} % de {n}?"),
    "it": dict(ср="la media di {р} è {с}: {л}.", в_ср="qual è la media di {р}?",
               пр="il {p} % di {n} è {в}: {л}.", в_пр="quanto fa il {p} % di {n}?"),
    "pt": dict(ср="a média de {р} é {с}: {л}.", в_ср="qual é a média de {р}?",
               пр="{p} % de {n} é {в}: {л}.", в_пр="quanto é {p} % de {n}?"),
    "nl": dict(ср="het gemiddelde van {р} is {с}: {л}.", в_ср="wat is het gemiddelde van {р}?",
               пр="{p} % van {n} is {в}: {л}.", в_пр="hoeveel is {p} % van {n}?"),
    "pl": dict(ср="średnia z {р} to {с}: {л}.", в_ср="ile wynosi średnia z {р}?",
               пр="{p} % z {n} to {в}: {л}.", в_пр="ile to {p} % z {n}?"),
    "tr": dict(ср="{р} sayılarının ortalaması: {л}.", в_ср="{р} sayılarının ortalaması kaçtır?",
               пр="{n} sayısının yüzde {p} kısmı: {л}.", в_пр="{n} sayısının yüzde {p} kısmı kaçtır?"),
}

# ИМЕНА РОДОВ ДЛЯ ПЕРЕПИСИ ДОМОВ (`scripts/houses_census.py`): она печатает их тому, кто ищет
# в своде дыру, — чтобы дом не был построен второй раз. Имена ВЫВОДЯТСЯ ИЗ таблицы `ЯЗЫКИ`, а
# не пишутся рядом с нею: список, живущий отдельно, расходится с делом на первой же правке, а
# этот на новом ключе без имени валит дом ПРЯМО НА ВВОЗЕ.
_ИМЯ_РОДА = {"ср": "среднее с леджером",
              "в_ср": "вопрос о среднем",
              "пр": "процент с леджером",
              "в_пр": "вопрос о проценте"}
РОДЫ = tuple(_ИМЯ_РОДА[к] for к in next(iter(ЯЗЫКИ.values())))



def леджер_среднего(ряд):
    s = sum(ряд)
    return f"{' + '.join(map(str, ряд))} = {s}, {s} ÷ {len(ряд)} = {s // len(ряд)}"


def леджер_процента(p, n):
    return f"{n} × {p} = {n * p}, {n * p} ÷ 100 = {n * p // 100}"


def среднее(язык, ряд):
    assert sum(ряд) % len(ряд) == 0
    я = ЯЗЫКИ[язык]
    return я["ср"].format(р=", ".join(map(str, ряд)), с=sum(ряд) // len(ряд), л=леджер_среднего(ряд))


def вопрос_среднего(язык, ряд):
    return f"{ЯЗЫКИ[язык]['в_ср'].format(р=', '.join(map(str, ряд)))} {среднее(язык, ряд)}"


def процент(язык, p, n):
    assert (n * p) % 100 == 0
    я = ЯЗЫКИ[язык]
    return я["пр"].format(p=p, n=n, в=n * p // 100, л=леджер_процента(p, n))


def вопрос_процента(язык, p, n):
    return f"{ЯЗЫКИ[язык]['в_пр'].format(p=p, n=n)} {процент(язык, p, n)}"


_РЯД = r"(\d+(?:, \d+)+)"
_ЛЕДЖЕР_СР = r"((?:\d+ \+ )+\d+ = \d+, \d+ ÷ \d+ = \d+)"
_ЛЕДЖЕР_ПР = r"(\d+ × \d+ = \d+, \d+ ÷ 100 = \d+)"


def _образец(шаблон, л):
    дыры = {"р": _РЯД, "с": r"(\d+)", "л": л, "p": r"(\d+)", "n": r"(\d+)", "в": r"(\d+)"}
    return phrases.образец(шаблон, дыры)


def образцы(язык):
    """[(regex, kind, asked)] — kinds «ср» and «пр»."""
    я = ЯЗЫКИ[язык]
    ср, пр = _образец(я["ср"], _ЛЕДЖЕР_СР), _образец(я["пр"], _ЛЕДЖЕР_ПР)
    return [(re.compile("^" + ср + "$"), "ср", False),
            (re.compile("^" + _образец(я["в_ср"], "") + " " + ср + "$"), "ср", True),
            (re.compile("^" + пр + "$"), "пр", False),
            (re.compile("^" + _образец(я["в_пр"], "") + " " + пр + "$"), "пр", True)]


def судить_группы(язык, вид, спрошено, группы):
    """Groups follow the template's hole order; the tr statement has no {с}/{в}."""
    я = ЯЗЫКИ[язык]
    шаблон = я[вид]
    порядок = phrases.порядок(шаблон)
    г = list(группы)
    if спрошено:
        в_порядок = phrases.порядок(я["в_" + вид])
        спрош = dict(zip(в_порядок, г[:len(в_порядок)])); г = г[len(в_порядок):]
    else:
        спрош = {}
    з = dict(zip(порядок, г))
    if вид == "ср":
        ряд = [int(x) for x in з["р"].split(", ")]
        if sum(ряд) % len(ряд):
            return False
        if з["л"] != леджер_среднего(ряд):
            return False
        if "с" in з and int(з["с"]) != sum(ряд) // len(ряд):
            return False
        return not спрош or спрош.get("р") == з["р"]
    p, n = int(з["p"]), int(з["n"])
    if (n * p) % 100 or з["л"] != леджер_процента(p, n):
        return False
    if "в" in з and int(з["в"]) != n * p // 100:
        return False
    return not спрош or (int(спрош.get("p", p)) == p and int(спрош.get("n", n)) == n)


# ------------------------------------------------------------------ СТРАНИЦЫ МИРА
#
# СТРОИТЕЛЬ ПЕРЕЕХАЛ ИЗ КУЗНИЦЫ В ДОМ (13.09) — тем же движением, что стало обычаем.
#
#     ДОМ, ОБЪЯВИВШИЙ РОДЫ И НЕ ОТДАВШИЙ СТРАНИЦ, ОБЕЩАЕТ ИМЕНА, КОТОРЫХ НЕКОМУ ПРИЛОЖИТЬ.

ПРОЦЕНТЫ = ((20, 50), (10, 40), (25, 80), (50, 30), (5, 60), (30, 90), (75, 40), (20, 35), (40, 25), (15, 60), (60, 45), (8, 75))


def ряд(шаг, i):
    """A list with an integer mean: a base, a step and a length from the seams."""
    длина = 2 + (шаг + i) % 4
    старт = 3 + (шаг * 5 + i * 7) % 20
    шаг_ = 1 + (шаг * 3 + i) % 6
    р = [старт + k * шаг_ for k in range(длина)]
    while sum(р) % длина:
        р[-1] += 1
    return р


def язык_группа(шаг, язык):
    вон = []
    for i in range(6):
        р = ряд(шаг, i)
        вон.append(среднее(язык, р) if i % 2 == 0 else вопрос_среднего(язык, р))
        p, n = ПРОЦЕНТЫ[(шаг * 5 + i * 2) % len(ПРОЦЕНТЫ)]
        вон.append(вопрос_процента(язык, p, n) if i % 2 == 0 else процент(язык, p, n))
    return вон

def _меченая(шаг, язык):
    """[(страница, род)] — среднее и процент, утверждением и вопросом."""
    ср, ср_воп, пр, пр_воп = РОДЫ
    вон = []
    for i in range(6):
        р = ряд(шаг, i)
        вон.append((среднее(язык, р), ср) if i % 2 == 0
                   else (вопрос_среднего(язык, р), ср_воп))
        p, n = ПРОЦЕНТЫ[(шаг * 5 + i * 2) % len(ПРОЦЕНТЫ)]
        вон.append((вопрос_процента(язык, p, n), пр_воп) if i % 2 == 0
                   else (процент(язык, p, n), пр))
    return вон



def группы(шаг):
    """[[страница]] — ровно те группы и в том порядке, какими кузница кормит `emit_grouped`."""
    return [язык_группа(шаг, язык) for язык in ЯЗЫКИ]


def перебор_с_языком(шаг):
    """[(страница, род, ЯЗЫК)] — тройка, и третье поле есть объявление языка страницы.

    ЯЗЫК СТОИТ В ЗАГОЛОВКЕ ЦИКЛА И ТЕРЯЛСЯ НА ПОРОГЕ СЛОВАРЯ (15.09): обход идёт по языкам и
    каждому отдаёт свою группу, а `ПОКАЗЫ` клали одно имя рода — и дом становился для меры
    щербатости НЕЧИТАЕМЫМ: не «ровным», а именно нечитаемым, ибо сравнить страницу не с чем.

        ТО, ЧТО СТОИТ В ЗАГОЛОВКЕ ЦИКЛА, ЗНАЕТ СТРОИТЕЛЬ; ТО, ЧТО НЕ ЛЕГЛО В ОБЪЯВЛЕНИЕ, НЕ
        ЗНАЕТ НИКТО. Восстановить язык потом можно лишь гаданием по виду строки — а гадание
        корпус не принимает ни от прибора, ни от дома.

    Пара «(страница, род)» осталась при `перебор_страниц` нетронутой: её форму знают чужие
    читатели, и менять её ради третьего поля значило бы платить чужими договорами за своё.
    """
    вон = []
    for язык in ЯЗЫКИ:
        вон.extend((с, р, язык) for с, р in _меченая(шаг, язык))
    return вон


def перебор_страниц(шаг):
    """[(страница, род)] — те же группы, но каждая страница под своим именем."""
    return [(с, р) for с, р, _я in перебор_с_языком(шаг)]


def _показы():
    """Словарь ПОСТРОЧНО: свод построчен, а показ бывает многострочен."""
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род, язык in перебор_с_языком(шаг):
            for строка in с.split("\n"):
                if строка.rstrip():
                    вон.setdefault(строка.rstrip(), (язык, род))
    return вон


ПОКАЗЫ = _показы()


def _самопроверка_страниц():
    assert all("\n" not in к for к in ПОКАЗЫ), "словарь показов обязан быть построчным"
    # ПОКАЗ НЕСЁТ ПАРУ «(ЯЗЫК, РОД)», И САМОПРОВЕРКА ЧИТАЕТ ОБЕ ПОЛОВИНЫ.
    сказанные = {я for я, _р in ПОКАЗЫ.values()}
    assert сказанные == set(ЯЗЫКИ), (
        f"язык объявлен и не кован либо кован и не объявлен: {sorted(сказанные ^ set(ЯЗЫКИ))}")
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"
    из_перебора = sorted(с for с, _р in перебор_страниц(0))
    из_групп = sorted(с for г in группы(0) for с in г)
    assert из_перебора == из_групп, "пересборка потеряла или выдумала страницы"


_самопроверка_страниц()
