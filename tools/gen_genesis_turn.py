#!/usr/bin/env python3
"""GENESIS layer: СТОРОНЫ И ПОВОРОТЫ — see tools/turnforms.py for the law.

ОБЕ СТОРОНЫ ЛОВУШКИ ИДУТ ОДНОЙ ГРУППОЙ. «Смотрящий на юг, повернув налево, смотрит на
восток» и «смотрящий на север, повернув налево, смотрит на запад» суть ОДНО правило,
дающее разные ответы, и читатель обязан встретить их рядом — иначе он выучит равенство
«налево = запад» и будет прав ровно в четверти случаев.

    ПРАВИЛО, ПОКАЗАННОЕ ЛИШЬ ТАМ, ГДЕ ОНО СОВПАДАЕТ С ПРОСТЫМ ОТВЕТОМ, УЧИТ ПРОСТОМУ
    ОТВЕТУ, А НЕ ПРАВИЛУ.

ОДИНОЧНЫЕ ПОВОРОТЫ ОТДЕЛЬНО ОТ СОСТАВНЫХ: сперва четверть круга во все стороны, затем
сложение и путь. ВОПРОС отдельно — ответ рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import turnforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_turn.txt"
ГРУППЫ = (("направо", "налево", "кругом"),
          ("налево не есть запад", "налево и есть запад"),
          ("четыре поворота", "сложение поворотов", "путь из поворотов"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
