#!/usr/bin/env python3
"""СЛОЙ GENESIS: НАЧЕРТАНИЯ ОДНОГО ЗНАКА.

ОДИН ЗНАК, ДВА НАЧЕРТАНИЯ — ОБА ЖИВУТ, ИЛИ ОРГАНИЗМ ЗНАЕТ ОДНО.

ЭТОТ МИР НЕ ДОБАВЛЯЕТ ПРЕДМЕТА, И В ЭТОМ ЕГО ОСОБЕННОСТЬ. Квадратные
уравнения показаны сотнями строк, неравенства — тоже; недостаёт не
знания, а ЗАПИСИ, в которой оно узнаётся. Замер по своду в 194 392
строки: «x^2» — 1702, «x²» — НОЛЬ; «≤» — 351, «<=» — НОЛЬ; «sqrt» —
2091, «√» — шесть; «->» — 4238, «→» — 328. Каждый знак живёт в ОДНОМ
начертании, и в разных знаках — в разных: организм узнает «≤» и не
узнает «<=», узнает «x^2» и не узнает «x²».

БЕДА НЕВИДИМА МЕРЕ ПРЕДМЕТОВ, и потому она дожила до сегодня. Мера
охвата понятия спрашивает, показан ли ПРЕДМЕТ, и отвечает «да»: корни
уравнений показаны. Нашла беду ПОЛОСА — прибор «мир × полоса» назвал
образец «x² − 16 = 0» ненайденным, но нашёл ЕГО ЧИСЛА, и различил два
рода ненайденного: пробел рода и расхождение записи.

ЧЕТЫРЕ РОДА ПОКАЗА, И КАЖДЫЙ ПРОВЕРЯЕМ ИСПОЛНЕНИЕМ:
  · ПАРА — две записи одной вещи, сведённые к канону;
  · ВОПРОС — «как ещё пишется X?», ответ выводится, а не помнится;
  · ОТКАЗ — запись, у которой двойника НЕТ, и это сказано прямо;
  · ВЕРДИКТ — неравенство, посчитанное в обоих начертаниях.

ДВА НАЧЕРТАНИЯ ОБЯЗАНЫ РАЗЛИЧАТЬСЯ: показ ««x^2» и «x^2» суть одна
запись» истинен по букве и пуст по делу. Суд зовёт такое ложью.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "courts"))
import notation_variants as НВ  # noqa: E402
from layer import PASSES, emit  # noqa: E402

ЦЕЛЬ = "datasets/genesis_notationvar.txt"

# Диапазон свободных членов: полные квадраты, чтобы корень был целым и
# показ нёс проверяемое содержание, а не одну лишь запись.
КВАДРАТЫ = tuple(к * к for к in range(2, 21))
# ТРЁХЧЛЕНЫ: коэффициенты диапазонами, а не по полосе. Малые — все пары
# b, c от 0 до 12; большие — b десятками с полным квадратом c = (b/2)²,
# чтобы двузначный и трёхзначный коэффициент тоже имели оба начертания.
# Знак при b обоими: «- 5 x» и «+ 5 x».
# Диапазон до 30 — двузначные коэффициенты («x² − 30x + 221») суть то же
# начертание, и оно должно жить на двузначных числах, а не только на
# однозначных: полоса спрашивает их, корпус писал до 12.
ТРЁХЧЛЕНЫ = tuple((зн, b, c) for b in range(0, 31) for c in range(0, 31)
                  for зн in ("-", "+") if b or зн == "-")
ТРЁХЧЛЕНЫ += tuple(("-", b, (b // 2) ** 2) for b in range(10, 101, 10))
# ЕДИНИЧНЫЙ КОЭФФИЦИЕНТ ОПУСКАЕТСЯ («x² − x + 7»), СТАРШИЙ — ПИШЕТСЯ
# ПЕРЕД СТЕПЕНЬЮ («2x² − 8x + 6»). Оба суть начертания той же записи, и
# оба живут в полосе. Старший коэффициент — диапазоном 2..5, а не единицей.
ЕДИНИЧНЫЕ = tuple((зн, c) for c in range(1, 13) for зн in ("-", "+"))
# b от 2: единичный коэффициент не пишется, и «2x² − 1x» не запись.
СТАРШИЙ = tuple((a, зн, b, c) for a in range(2, 6) for b in range(2, 9)
                for c in range(0, 9) for зн in ("-", "+"))
# Пары чисел для неравенств: обе стороны и равные, и разные, чтобы
# вердикт не был всегда одним.
ЧИСЛА = tuple((а, б) for а in range(1, 13) for б in range(1, 13)
              if abs(а - б) <= 3)


def буква(i):
    """Буква переменной ходит по показам: начертание есть свойство СТЕПЕНИ,
    а не буквы «икс» (03.09, тот же закон, каким живут универсалии)."""
    return НВ.БУКВЫ[i % len(НВ.БУКВЫ)][0]


def показы():
    вон = []
    for i, c in enumerate(КВАДРАТЫ):
        б = буква(i)
        ascii_ = f"{б}^2 - {c} = 0"
        вон.append(f"«{ascii_}» и «{НВ.двойник(ascii_)}» суть одна запись.")
        вон.append(f"«{ascii_}» and «{НВ.двойник(ascii_)}» are one record.")
        вон.append(f"как ещё пишется «{ascii_}»? — «{НВ.двойник(ascii_)}».")
        вон.append(f"how else is «{ascii_}» written? — "
                   f"«{НВ.двойник(ascii_)}».")
    for i, (зн, b, c) in enumerate(ТРЁХЧЛЕНЫ):
        б = буква(i)
        b_часть = f" {зн} {b} {б}" if b else ""
        c_часть = f" + {c}" if c else ""
        ascii_ = f"{б}^2{b_часть}{c_часть} = 0"
        дв = НВ.двойник(ascii_)
        if дв is None:
            continue
        вон.append(f"«{ascii_}» и «{дв}» суть одна запись.")
        вон.append(f"как ещё пишется «{ascii_}»? — «{дв}».")
    for i, (зн, c) in enumerate(ЕДИНИЧНЫЕ):
        б = буква(i)
        ascii_ = f"{б}^2 {зн} {б} + {c} = 0"
        дв = НВ.двойник(ascii_)
        if дв:
            вон.append(f"«{ascii_}» и «{дв}» суть одна запись.")
            вон.append(f"как ещё пишется «{ascii_}»? — «{дв}».")
    for i, (a, зн, b, c) in enumerate(СТАРШИЙ):
        б = буква(i)
        c_часть = f" + {c}" if c else ""
        ascii_ = f"{a} {б}^2 {зн} {b} {б}{c_часть} = 0"
        дв = НВ.двойник(ascii_)
        if дв:
            вон.append(f"«{ascii_}» и «{дв}» суть одна запись.")
            вон.append(f"как ещё пишется «{ascii_}»? — «{дв}».")
    for знак_a, знак_t in (("<=", "≤"), (">=", "≥"), ("!=", "≠")):
        for а, б in ЧИСЛА:
            верно = {"<=": а <= б, ">=": а >= б, "!=": а != б}[знак_a]
            вон.append(f"«{а} {знак_a} {б}» {'верно' if верно else 'неверно'}"
                       f", и «{а} {знак_t} {б}» говорит то же.")
            вон.append(f"как ещё пишется «{а} {знак_a} {б}»? — "
                       f"«{а} {знак_t} {б}».")
    # ОТКАЗ: записи, ни один знак которых двойника не имеет.
    for n in range(1, 21):
        запись = f"{n} = {n}"
        if НВ.двойник(запись) is None:
            вон.append(f"у записи «{запись}» второго начертания нет: "
                       f"ни один её знак не имеет двойника.")
    return вон


def main():
    # ПОКАЗЫ ДЕЛЯТСЯ МЕЖДУ ПРОХОДАМИ, А НЕ ПОВТОРЯЮТСЯ В КАЖДОМ. Первая
    # редакция отдавала ВСЕ показы в каждый из пяти проходов, и мир
    # записался впятеро — 26 930 показов вместо 5386; та же ошибка была
    # поймана утром у школьного мира (М-126) и прожита здесь второй раз,
    # ибо была допущена раньше, чем записан закон.
    все = показы()
    emit(ЦЕЛЬ, lambda i: [п for k, п in enumerate(все) if k % len(PASSES) == i])


if __name__ == "__main__":
    main()
