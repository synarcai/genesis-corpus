#!/usr/bin/env python3
"""УКАЗАТЕЛЬ ЗАКОНОВ — общее право свода, собранное из его же докстрингов.

Свод пишет законы прописными, и они рассеяны по семистам файлам: всякий дом, всякий суд, всякий
прибор объявляет, на чём стои́т. Замер 12.09: ТРИ ТЫСЯЧИ ВОСЕМЬСОТ ВОСЕМЬДЕСЯТ ТРИ разных закона
на 4409 упоминаний — и ни одного места, где их видно разом.

    ЗАКОН, СКАЗАННЫЙ ОДНАЖДЫ В ОДНОМ ФАЙЛЕ, ЕСТЬ РАССУЖДЕНИЕ ЭТОГО ФАЙЛА; ЗАКОН, ПОВТОРЁННЫЙ
    ДВАДЦАТЬЮ ФАЙЛАМИ, ЕСТЬ ОБЩЕЕ ПРАВО СВОДА.

Указатель берёт ОБЩИЕ — те, что держатся не одним файлом: их сто семьдесят девять. Прочие три
тысячи семьсот четыре сказаны однажды и остаются при своём месте, ибо местное рассуждение,
вынутое из своего дела, теряет смысл.

ПОЧЕМУ ЭТО ОРУДИЕ, А НЕ СУД. Указатель миров сличает себя с манифестом и потому судит: манифест
меняется редко и нарочно. Указатель законов зависит от ВСЯКОЙ СТРОКИ ДЕРЕВА — от любой правки
любого докстринга.

    УКАЗАТЕЛЬ, ЗАВИСЯЩИЙ ОТ ВСЯКОЙ СТРОКИ ДЕРЕВА, НЕ МОЖЕТ БЫТЬ СУДОМ: он краснел бы при
    всякой правке, и краснота его ничего бы не значила.

Потому метки пустого обхода он не несёт, в набор не зовётся и рубежа не держит — он собирается
рукой, когда рука хочет видеть право свода целиком.

    python3 tools/law_atlas.py            # СУДИТЬ: сошёлся ли указатель на диске с деревом
    python3 tools/law_atlas.py --собрать  # собрать reports/ATLAS-LAWS.md
    python3 tools/law_atlas.py --считать  # только числа, без записи
"""
import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ДВОРЫ = ("tools", "courts", "scripts")
ЦЕЛЬ = КОРЕНЬ / "reports" / "ATLAS-LAWS.md"
ОБЩИЙ = 2
# ЗАКОН — связная речь ПРОПИСНЫМИ, не короче четырёх слов и не длиннее сотни знаков.
ЗАКОН = re.compile(r"(?<![А-ЯЁA-Z])([А-ЯЁ][А-ЯЁ ,:«»—–-]{25,}[А-ЯЁ])(?![а-яё])")


def собрать(корень):
    """{закон: {файлы}} по всем дворам орудий."""
    где = collections.defaultdict(set)
    for двор in ДВОРЫ:
        путь = корень / двор
        if not путь.is_dir():
            continue
        for п in sorted(путь.glob("*.py")):
            for m in ЗАКОН.finditer(п.read_text(encoding="utf-8", errors="replace")):
                з = " ".join(m.group(1).split())
                if len(з.split()) >= 4:
                    где[з].add(f"{двор}/{п.name}")
    return где


def main():
    где = собрать(КОРЕНЬ)
    общие = {з: v for з, v in где.items() if len(v) >= ОБЩИЙ}
    if "--считать" in sys.argv:
        print(f"законов {len(где)}, упоминаний {sum(len(v) for v in где.values())}, "
              f"общих (в {ОБЩИЙ}+ файлах) {len(общие)}")
        return 0
    ряды = sorted(общие.items(), key=lambda п: (-len(п[1]), п[0]))
    out = [f"# УКАЗАТЕЛЬ ЗАКОНОВ — общее право свода: {len(общие)} законов", "",
           "Собран из докстрингов и комментариев `tools`, `courts`, `scripts` орудием",
           "`tools/law_atlas.py`. Взяты ОБЩИЕ законы — те, что держатся не одним файлом.", "",
           "    ЗАКОН, СКАЗАННЫЙ ОДНАЖДЫ В ОДНОМ ФАЙЛЕ, ЕСТЬ РАССУЖДЕНИЕ ЭТОГО ФАЙЛА;",
           "    ЗАКОН, ПОВТОРЁННЫЙ ДВАДЦАТЬЮ ФАЙЛАМИ, ЕСТЬ ОБЩЕЕ ПРАВО СВОДА.", "",
           f"Всего в дереве {len(где)} разных законов на "
           f"{sum(len(v) for v in где.values())} упоминаний; сказанных однажды — "
           f"{len(где) - len(общие)}, и они остаются при своём месте.", ""]
    порог = None
    for з, файлы in ряды:
        if len(файлы) != порог:
            порог = len(файлы)
            out += ["", f"## Держат {порог} файлов", ""]
        out.append(f"- **{з}**  ")
        out.append(f"  {', '.join(sorted(файлы)[:6])}"
                   + (f" … и ещё {len(файлы) - 6}" if len(файлы) > 6 else ""))
    ЦЕЛЬ.parent.mkdir(parents=True, exist_ok=True)
    # УКАЗАТЕЛЬ СУДИТ РАСХОЖДЕНИЕ, А ПИШЕТ ЛИШЬ ПО ПРОСЬБЕ (12.09).
    #
    # Два указателя из четырёх не были вписаны в набор и собирались лишь рукой:
    # указатель законов отстал на день, указатель приборов — на часы.
    #
    #     УКАЗАТЕЛЬ, НЕ ВПИСАННЫЙ В НАБОР, СОБИРАЕТСЯ ЛИШЬ ТОГДА, КОГДА О НЁМ
    #     ВСПОМНЯТ, И ОТСТАЁТ РОВНО НА СТОЛЬКО, НА СКОЛЬКО О НЁМ ЗАБЫЛИ.
    #
    # В набор он входит СУДЬЁЙ, а не писцом: прибор, молча меняющий дерево
    # посреди набора, двигает дерево под набором — и это уже названный порок.
    тело = "\n".join(out) + "\n"
    ЦЕЛЬ.parent.mkdir(parents=True, exist_ok=True)
    было = ЦЕЛЬ.read_text(encoding="utf-8") if ЦЕЛЬ.is_file() else ""
    if "--собрать" not in sys.argv:
        поза = "PASS" if было == тело else "FAIL"
        if было != тело:
            print(f"  указатель на диске разошёлся с деревом: строк было "
                  f"{было.count(chr(10))}, стало бы {тело.count(chr(10))}")
        print(f"УКАЗАТЕЛЬ ЗАКОНОВ {поза}: {0 if было == тело else 1} расхождений "
              f"с деревом (рубеж 0)")
        return 0 if было == тело else 1
    ЦЕЛЬ.write_text(тело, encoding="utf-8")
    print(f"УКАЗАТЕЛЬ ЗАКОНОВ СОБРАН: {ЦЕЛЬ.name}, законов общих {len(общие)} "
          f"из {len(где)}, строк {len(out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
