#!/usr/bin/env python3
"""КОВКА ДОМА ВЫБОРА ДЕЙСТВИЯ.

ПАРА ИДЁТ В ОДНОМ ПРОХОДЕ, А НЕ ВРАЗБИВКУ. Довод здешнего дома есть МИНИМАЛЬНАЯ ПАРА: две
страницы с одними числами, разнящиеся решающим словом. Читатель, увидевший их порознь, увидит
два примера; увидевший рядом — увидит ЗАКОН. Оттого группы прохода режутся по РОДАМ развилки,
и обе половины пары попадают в один блок.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import opchoiceforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_opchoice.txt"


# ГРУППЫ БЕРУТСЯ ИЗ ОБЪЯВЛЕННЫХ РОДОВ, А НЕ ИЗ СПИСКА ПАР. Первая редакция резала по `ПАРЫ`, и
# четвёртая развилка — доля — не попала в ковку ВОВСЕ: дом объявлял 432 страницы, мир получил
# 384, и никто не сказал ни слова, ибо кузница пишет ровно то, что ей дали.
#
#     КУЗНИЦА, БЕРУЩАЯ НЕ ВСЁ ОБЪЯВЛЕННОЕ, МОЛЧА ТЕРЯЕТ ЗАКОН. Признак взят у САМИХ ПОКАЗОВ:
#     группы суть роды, какие в них есть.
def _роды_групп():
    """Роды показов, слитые в группы: обе половины пары — вместе, доля — своей группой."""
    вон = [{первый, второй} for первый, второй in F.ПАРЫ]
    прочие = {р for _, р in F.ПОКАЗЫ.values()} - set().union(*вон)
    вон += [{р} for р in sorted(прочие)]
    return вон


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in _роды_групп():
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
