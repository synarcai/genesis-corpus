#!/usr/bin/env python3
"""ДОМ НУЛЕВОЙ И ОТРИЦАТЕЛЬНОЙ СТЕПЕНИ — ЛЕСТНИЦА, ПРОДОЛЖЕННАЯ ЗА НОЛЬ.

    НУЛЕВОЙ СТЕПЕНИ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 236 мирам показов: «^0» —
    НОЛЬ; «⁰» — НОЛЬ; «в нулевой степени», «to the power of zero» — НОЛЬ. Отрицательного
    показателя тоже нет: «^-», «^−», «⁻» — НОЛЬ на весь свод.

    ПРИ ЭТОМ СТЕПЕНЬ СВОД ПИШЕТ ОБИЛЬНО: шапка «^» встречается 1796 раз в восьми мирах, и мир
    алгебры держит закон сложения показателей — «5^1 × 5^2 = 5^3» (650 строк). Закон объявлен
    ДЛЯ ПОЛОЖИТЕЛЬНЫХ и обрывается на единице: что будет при показателе 0 и ниже, не сказано.

СЕДЬМАЯ И ВОСЬМАЯ ЛОВУШКИ РЯДА, И ОБЕ ЖДУТ ЧИТАТЕЛЯ У НУЛЯ:

    5^0 = 1, А НЕ 0.     Показатель ноль — и ждут ноль; выходит единица.
    2^-3 = 1/8, А НЕ −8. Минус в показателе — и ждут отрицательное; выходит ДОЛЯ.

    МИНУС В ПОКАЗАТЕЛЕ ДАЁТ ДОЛЮ, А НЕ ЗНАК.

ЧЕТЫРЕ РОДА:

    лестница        шаг вниз делит на 5: 5^3 = 125, и 125 ÷ 5 = 25, и 5^2 = 25.  ← ОРАКУЛ
    нулевая         5^0 = 1, а не 0: 5^1 = 5, и 5 ÷ 5 = 1.                       ← ЛОВУШКА 7
    отрицательная   2^-3 = 1/8, а не −8: 2^3 = 8.                                ← ЛОВУШКА 8
    замок           показатели 3 и −3 в сумме дают 0, и потому 2^3 × 2^-3 = 8 × 1/8 = 1.

ПЕРВЫЙ РОД ЕСТЬ ПРИЧИНА, ПОКАЗАННАЯ ЛЕСТНИЦЕЙ, — тот же ход, каким дом правила знаков вывел
«минус на минус». Спускаясь на единицу, степень всякий раз ДЕЛИТСЯ на основание; дойдя до
первой и шагнув дальше, она обязана поделиться ещё раз — и потому выходит единица, а не ноль.
Шагнув ещё, она уходит в доли: так лестница СШИВАЕТ ЭТОТ ДОМ С ДРОБНЫМ.

    ПРАВИЛО, КОТОРОЕ НЕЧЕМ ВЫВЕСТИ, ЧИТАТЕЛЬ ОБЯЗАН ЗАПОМНИТЬ; ПРАВИЛО, ВЫВЕДЕННОЕ ПРИ НЁМ,
    ОН МОЖЕТ ВОССТАНОВИТЬ.

ЧЕТВЁРТЫЙ РОД ПРОДОЛЖАЕТ ЗАКОН МИРА АЛГЕБРЫ ЗА ЕГО ГРАНИЦУ: показатели складываются и по ту
сторону нуля, и 3 + (−3) = 0 даёт ровно единицу. Он же связывает дом со знаковым: там
противоположные числа в сумме давали ноль, здесь противоположные ПОКАЗАТЕЛИ в произведении
дают единицу — одно и то же уничтожение, сказанное на другом этаже.

ЗАПИСЬ ВЫБРАНА ЗАМЕРОМ, А НЕ ВКУСОМ. Верхних индексов, кроме «²» и «³», свод не пишет НИ РАЗУ,
и «⁰» в нём нет вовсе; степень пишется ШАПКОЙ, в том числе в мирах, где рядом стоят
типографские «× ÷ −». Шапка есть МАШИННАЯ запись, и минус в ней — дефис («2^-3»), как дефис
живёт в матрицах и LaTeX; знак минус «−» стои́т при ЧИСЛЕ, о котором говорят («а не −8»).

    ОДНА ВЕЩЬ — ОДИН ЗНАК, И РАЗНЫЕ ВЕЩИ РАЗЛИЧАЮТСЯ ЗНАКОМ: показатель степени и число —
    разные вещи, и потому «2^-3» и «−8» пишутся в одной строке по-разному.

РАВЕНСТВО СТОИ́Т ПОСЛЕДНИМ, И ЭТО КУПЛЕНО ЗАМЕРОМ. Суд арифметики читает строку ЦЕЛИКОМ или не
читает вовсе: приписанный в конце довод словами гасит проверку ВСЕЙ строки. Замерено палатой —
«…2^3 × 2^-3 = 8 × 1/8 = 1, и показатели в сумме дают 0» суд не читает, и подсадка «= 2»
проходит молча; та же страница с доводом ВПЕРЕДИ читается и подсадку ловит.

    ХВОСТ ПОСЛЕ ПОСЛЕДНЕГО РАВЕНСТВА ГАСИТ ПРОВЕРКУ ВСЕЙ СТРОКИ.

ГРАНИЦА СУДА АРИФМЕТИКИ НАЗВАНА ЗАМЕРОМ: он читает свидетеля («2^3 = 8»), но САМУ отрицательную
степень не считает — «2^-3 = 1/9» проходит у него как истина. Эту половину пересчитывает суд
ЭТОГО дома, и потому страница проверена дважды разными приборами.

ЧТО СЮДА НЕ ВЗЯТО, И ПОЧЕМУ:
    0^0 — договор, а не счёт: его значение УСЛОВЛЕНО, и показывать условие как вывод значило бы
          лгать о природе правила. Основания начинаются с двойки.
    1^n — вырожденный случай: единица в любой степени единица, и лестница на ней ничего не
          показывает. ПРИМЕР, В КОТОРОМ НЕЧЕГО НАБЛЮДАТЬ, НЕ ПОКАЗЫВАЕТ ЗАКОНА.

    python3 tools/powforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("лестница", "нулевая", "отрицательная", "замок", "спрошенное")
ШАПКА = "^"
МИНУС = "−"

РАМКИ = {
    "ru": {
        "лестница": "шаг вниз делит на {a}: {a}^{n} = {A}, и {A} ÷ {a} = {B}, и {a}^{m} = {B}.",
        "нулевая": "{a}^0 = 1, а не 0: {a}^1 = {a}, и {a} ÷ {a} = 1.",
        "отрицательная": "{a}^-{n} = 1/{A}, а не −{A}: {a}^{n} = {A}.",
        "замок": "показатели {n} и −{n} в сумме дают 0, и потому {a}^{n} × {a}^-{n} = {A} × 1/{A} = 1.",
        "спрошенное": "чему равно {a}^{n}? {a}^{n} = {A}, ибо {a}^{m} = {B}, и {B} × {a} = {A}.",
    },
    "en": {
        "лестница": "a step down divides by {a}: {a}^{n} = {A}, and {A} ÷ {a} = {B}, and {a}^{m} = {B}.",
        "нулевая": "{a}^0 = 1, and not 0: {a}^1 = {a}, and {a} ÷ {a} = 1.",
        "отрицательная": "{a}^-{n} = 1/{A}, and not −{A}: {a}^{n} = {A}.",
        "замок": "the exponents {n} and −{n} add up to 0, and so {a}^{n} × {a}^-{n} = {A} × 1/{A} = 1.",
        "спрошенное": "what is {a}^{n}? {a}^{n} = {A}, for {a}^{m} = {B}, and {B} × {a} = {A}.",
    },
}
ПУСТО = dict(a=0, n=0, m=0, A=0, B=0)
ПРЕДЕЛ = 100000


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        # ЛЕСТНИЦА: показатель спускается на единицу, и степень делится на основание.
        for a in range(2, 13):
            for n in range(2, 7):
                A = a ** n
                if A > ПРЕДЕЛ:
                    break
                вон[рамки["лестница"].format(**dict(ПУСТО, a=a, n=n, m=n - 1,
                                                    A=A, B=A // a))] = (язык, "лестница")
        # СПРОШЕННОЕ: та же лестница, поставленная ВОПРОСОМ. Мир, который только
        # утверждает, учит читателя узнавать ответ, но не искать его.
        #
        #     МИР БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ ПОКАЗЫВАЕТ ОТВЕТ, НЕ ПОКАЗЫВАЯ ЗАДАЧИ.
        for a in range(2, 13):
            for n in range(2, 7):
                A = a ** n
                if A > ПРЕДЕЛ:
                    break
                if (a + n) % 3:
                    continue
                вон[рамки["спрошенное"].format(**dict(ПУСТО, a=a, n=n, m=n - 1,
                                                      A=A, B=A // a))] = (язык, "спрошенное")
        # НУЛЕВАЯ: основание берётся широко — ловушка не зависит от величины.
        for a in range(2, 46):
            вон[рамки["нулевая"].format(**dict(ПУСТО, a=a))] = (язык, "нулевая")
        # ОТРИЦАТЕЛЬНАЯ И ЗАМОК идут ПАРОЙ по одним и тем же числам: вторая страница
        # проверяет первую произведением, и разлучать их значило бы оставить долю без оправдания.
        for a in range(2, 13):
            for n in range(1, 6):
                A = a ** n
                if A > ПРЕДЕЛ:
                    break
                вон[рамки["отрицательная"].format(
                    **dict(ПУСТО, a=a, n=n, A=A))] = (язык, "отрицательная")
                if (a + n) % 2 == 0:
                    вон[рамки["замок"].format(
                        **dict(ПУСТО, a=a, n=n, A=A))] = (язык, "замок")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ШАПКА ЕСТЬ ЧАСТЬ ЧИСЛА, И ОБРАЗЕЦ ОБЯЗАН ЕЁ БРАТЬ: «2^3» и «3» суть разные величины.
_СТЕПЕНЬ = re.compile(r"(?<![/\d])(\d+)\^(\d+) = (\d+)(?![/\d])")
_ОТРИЦ = re.compile(r"(?<![/\d])(\d+)\^-(\d+) = 1/(\d+)(?![/\d])")
_НЕ_ЗНАК = re.compile(r"(?:а не|and not) −(\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_ДОЛЯ_РАЗ = re.compile(r"(?<![/\d])(\d+) × 1/(\d+) = (\d+)(?![/\d])")
_ПОКАЗАТЕЛИ = re.compile(r"(?:показатели|the exponents) (\d+) (?:и|and) −(\d+)")
_ВЫРОЖДЕННОЕ = re.compile(r"(?<!\d)[01]\^")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ, И СТЕПЕНЬ СЧИТАЕТСЯ ЗДЕСЬ, А НЕ ПРИНИМАЕТСЯ:
    # суд арифметики отрицательной степени не считает вовсе (замер 11.09).
    for a, n, c in _СТЕПЕНЬ.findall(с):
        if int(a) ** int(n) != int(c):
            return True, False
    for a, n, c in _ОТРИЦ.findall(с):
        if int(a) ** int(n) != int(c):
            return True, False
    # ОЖИДАНИЕ, НАЗВАННОЕ СТРАНИЦЕЙ, ТОЖЕ СЧИТАЕТСЯ: «а не −8» обязано назвать ровно ту
    # величину, которую читатель ждал, — иначе ловушка промахивается мимо ошибки.
    for ждали in _НЕ_ЗНАК.findall(с):
        if not any(int(ждали) == int(a) ** int(n) for a, n, _c in _ОТРИЦ.findall(с)):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for A, B, c in _ДОЛЯ_РАЗ.findall(с):
        if int(A) != int(B) or int(c) != 1:
            return True, False
    for n, m in _ПОКАЗАТЕЛИ.findall(с):
        if int(n) != int(m):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    лс = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "лестница")
    от = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "отрицательная")
    if судить(лс.replace("вниз", "вни"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(лс + " " + лс)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # СТЕПЕНЬ ОБЯЗАНА СЧИТАТЬСЯ, А НЕ ПРИНИМАТЬСЯ: подмена доли есть ложь этого дома, и суд
    # арифметики её НЕ ловит — проверено палатой на «2^-3 = 1/9».
    порча = от.replace("= 1/", "= 1/9", 1)
    if порча != от and судить(порча)[1]:
        беды.append("ДОЛЯ НЕ СЧИТАЕТСЯ: подменённый знаменатель прошёл")
    if судить("5^0 = 1, а не 0: 5^1 = 6, и 5 ÷ 5 = 1.")[1]:
        беды.append("СТЕПЕНЬ НЕ СЧИТАЕТСЯ: подменённая первая степень прошла")
    # ВЫРОЖДЕННОЕ И УСЛОВЛЕННОЕ ВНЕ ДОМА, И ЭТО СТОРОЖИТСЯ, А НЕ ОБЕЩАЕТСЯ.
    #
    # ОСНОВАНИЕ БЕРЁТСЯ С ГРАНИЦЕЙ, А НЕ ПОДСТРОКОЙ. Первая редакция стража искала «1^» где
    # угодно — и обвинила честную страницу «11^0 = 1», в которой единицы-основания нет вовсе.
    # Это третье за смену обвинение по форме без разбора связи, и лечится оно всякий раз
    # одинаково: ГРАНИЦА ЧИСЛА ЕСТЬ ЧАСТЬ ЧИСЛА.
    if any(_ВЫРОЖДЕННОЕ.search(с) for с in ПОКАЗЫ):
        беды.append("ЕДИНИЦА ИЛИ НОЛЬ В ОСНОВАНИИ: вырожденный или условленный случай")
    print(f"СТЕПЕНЬ ЗА НУЛЁМ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
