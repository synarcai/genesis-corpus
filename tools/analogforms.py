#!/usr/bin/env python3
"""ДОМ ПОДОБИЯ — аналогия и ЕЁ ПРОВЕРКА, а не её ощущение.

Четвёртый и последний долг карты форм рассуждения: «переход между двумя рядами
по общему отношению; ни одного показа». Долг закрыт тем же ходом, что три
предыдущих: ряд взят такой, где отношение ПРОВЕРЯЕТСЯ, а не объявляется.

    2 относится к 6, как 5 к 15.
    2 относится к 6, как 5 к чему? к 15.
    2 относится к 6, как 5 к 12? нет: 2 × 12 = 24, а 6 × 5 = 30.

ТРЕТЬЯ ФОРМА И ЕСТЬ ДОМ. Первые две показывают подобие; третья показывает
ПРОВЕРКУ подобия — перекрёстное произведение, — и без неё аналогия осталась бы
тем, чем она чаще всего бывает: ощущением похожести без права на вывод.
Организм, выучивший только первые две, будет находить подобия всюду; выучивший
третью — умеет их отвергать, и умеет назвать, чем именно отверг.

ЧИСЛА ЧЕТВЁРКИ НЕ ОБЪЯВЛЕНЫ ОТНОШЕНИЕМ, А ПРОВЕРЕНЫ ИМ при ввозе: a × d = b × c
для верных четвёрок и a × d ≠ b × c для ложной. Дом, объявивший подобие
неподобных, не доживает до записи мира.

НАЗВАННЫЙ ДОЛГ — ПОДОБИЕ РОДОВОЕ («акула относится к рыбам, как дуб к
деревьям»). Оно требует МНОЖЕСТВЕННЫХ форм классов, каких дом фактов мира не
объявляет: там класс стоит в единственном («акула — рыба»). Родовое подобие
ждёт этой волны и назовётся ею, а не догадкой о множественном числе.

    python3 tools/analogforms.py    # самопроверка с мутантами
"""
# (a, b, c, d) — верная четвёрка; ложное d берётся как d + 1
ЧЕТВЁРКИ = ((2, 6, 5, 15), (3, 12, 4, 16), (4, 10, 6, 15), (5, 20, 7, 28),
            (6, 9, 8, 12), (7, 21, 9, 27), (8, 12, 10, 15), (9, 15, 12, 20))

for _a, _b, _c, _d in ЧЕТВЁРКИ:
    assert _a * _d == _b * _c, (_a, _b, _c, _d)
    assert _a * (_d + 1) != _b * _c, (_a, _b, _c, _d)

РАМКИ = {
    "ru": dict(утв="{a} относится к {b}, как {c} к {d}.",
               воп="{a} относится к {b}, как {c} к чему? к {d}.",
               нет="{a} относится к {b}, как {c} к {x}? нет: {a} × {x} = {p}, а {b} × {c} = {q}."),
    "en": dict(утв="{a} is to {b} as {c} is to {d}.",
               воп="{a} is to {b} as {c} is to what? to {d}.",
               нет="is {a} to {b} as {c} is to {x}? no: {a} × {x} = {p}, and {b} × {c} = {q}."),
    "de": dict(утв="{a} verhält sich zu {b} wie {c} zu {d}.",
               воп="{a} verhält sich zu {b} wie {c} zu was? zu {d}.",
               нет="verhält sich {a} zu {b} wie {c} zu {x}? nein: {a} × {x} = {p}, und {b} × {c} = {q}."),
    "fr": dict(утв="{a} est à {b} ce que {c} est à {d}.",
               воп="{a} est à {b} ce que {c} est à quoi ? à {d}.",
               нет="{a} est-il à {b} ce que {c} est à {x} ? non : {a} × {x} = {p}, et {b} × {c} = {q}."),
    "es": dict(утв="{a} es a {b} como {c} es a {d}.",
               воп="¿{a} es a {b} como {c} es a qué? a {d}.",
               нет="¿es {a} a {b} como {c} es a {x}? no: {a} × {x} = {p}, y {b} × {c} = {q}."),
    "it": dict(утв="{a} sta a {b} come {c} sta a {d}.",
               воп="{a} sta a {b} come {c} sta a che cosa? a {d}.",
               нет="{a} sta a {b} come {c} sta a {x}? no: {a} × {x} = {p}, e {b} × {c} = {q}."),
    "pt": dict(утв="{a} está para {b} como {c} está para {d}.",
               воп="{a} está para {b} como {c} está para quê? para {d}.",
               нет="{a} está para {b} como {c} está para {x}? não: {a} × {x} = {p}, e {b} × {c} = {q}."),
    "nl": dict(утв="{a} verhoudt zich tot {b} als {c} tot {d}.",
               воп="{a} verhoudt zich tot {b} als {c} tot wat? tot {d}.",
               нет="verhoudt {a} zich tot {b} als {c} tot {x}? nee: {a} × {x} = {p}, en {b} × {c} = {q}."),
    "pl": dict(утв="{a} ma się do {b} jak {c} do {d}.",
               воп="{a} ma się do {b} jak {c} do czego? do {d}.",
               нет="czy {a} ma się do {b} jak {c} do {x}? nie: {a} × {x} = {p}, a {b} × {c} = {q}."),
}

ЯЗЫКИ = tuple(РАМКИ)
ФОРМЫ = ("воп", "нет")


def страница(язык, форма, i):
    a, b, c, d = ЧЕТВЁРКИ[i % len(ЧЕТВЁРКИ)]
    р = РАМКИ[язык][форма]
    if форма == "нет":
        x = d + 1
        return р.format(a=a, b=b, c=c, x=x, p=a * x, q=b * c)
    return р.format(a=a, b=b, c=c, d=d)


# ГОЛОГО УТВЕРЖДЕНИЯ ДОМ НЕ ПИШЕТ, и снято оно тем же вычитанием, каким сняты
# голый факт дома фактов мира и голый силлогизм: «2 относится к 6, как 5 к 15.»
# не несёт НИЧЕГО, чего не несёт вопросная форма («…как 5 к чему? к 15.»), —
# а родом без вопросной поверхности быть перестаёт. Прибор ШИРОТЫ поймал ровно
# девять таких родов (по одному на язык) и поднял долг 1109 → 1118; вычитание
# вернуло его на рубеж, не тронув ни одной формы. Рамка «утв» ОСТАЁТСЯ в
# объявлении: ею живёт вопросная форма, и по ней же суд читает подсудность.


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for форма in ФОРМЫ:
            for i in range(len(ЧЕТВЁРКИ)):
                вон[страница(язык, форма, i)] = (язык, форма)
    return вон


ПОКАЗЫ = _показы()


def main():
    поймано = 0
    for язык in ЯЗЫКИ:
        print(f"  {язык}: {страница(язык, 'нет', 0)}")
        a, b, c, d = ЧЕТВЁРКИ[0]
        мутант = РАМКИ[язык]["утв"].format(a=a, b=b, c=c, d=d + 1)   # подобие неподобных
        поймано += 0 if мутант in ПОКАЗЫ else 1
    print(f"  мутантов вне показов: {поймано} из {len(ЯЗЫКИ)}")
    print(f"  дом пишет показов: {len(ПОКАЗЫ)} (языков {len(ЯЗЫКИ)}, четвёрок {len(ЧЕТВЁРКИ)}, форм {len(ФОРМЫ)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
