#!/usr/bin/env python3
"""ДВУЯЗЫЧНЫЕ ПАРЫ: один дом слов, которыми слои размечают и рисуют.

Слой структур объявлял двадцать пар, слой разметки-и-формул — свои
двадцать одну, и в двух домах одно слово разошлось: «гора» была
mountain в одном и hill в другом. Оба перевода истинны, и потому
расхождение не поймал бы никакой счёт — его ловит только ОДИН ДОМ, где
у слова названы ВСЕ его переводы, а слой называет, каким пользуется.

Пара здесь — не словарь языка (тот живёт в `langpacks/`), а РАБОЧИЙ
НАБОР слоёв: слова коротки, конкретны и одинаково звучат в обоих
языках, чтобы разметка проверялась разметкой, а не знанием о мире.
"""

# (русское, (английские — первый основной, прочие синонимы))
ПАРЫ = (
    ("вода", ("water",)),
    ("сила", ("force",)),
    ("город", ("city",)),
    ("поле", ("field",)),
    ("время", ("time",)),
    ("дорога", ("road",)),
    ("мера", ("measure",)),
    ("число", ("number",)),
    ("слово", ("word",)),
    ("камень", ("stone",)),
    ("свет", ("light",)),
    ("звук", ("sound",)),
    ("дом", ("house",)),
    ("лес", ("forest",)),
    ("река", ("river",)),
    ("гора", ("mountain", "hill")),
    ("мост", ("bridge",)),
    ("круг", ("circle",)),
    ("точка", ("point",)),
    ("линия", ("line",)),
    ("схема", ("schema",)),
    ("закон", ("law",)),
    ("знание", ("knowledge",)),
    ("форма", ("form",)),
    ("материя", ("matter",)),
)

РУС = tuple(р for р, _ in ПАРЫ)
АНГЛ = {р: а for р, а in ПАРЫ}


def англ(рус, синоним=None):
    """Английское слово пары; синоним обязан быть ОБЪЯВЛЕН.

    Выбор молча непринятого перевода был бы вторым домом с одним
    словом — потому он проверяется здесь, а не доверяется вызывающему.
    """
    варианты = АНГЛ[рус]
    if синоним is None:
        return варианты[0]
    assert синоним in варианты, (рус, синоним, варианты)
    return синоним


def набор(слова, синонимы=()):
    """[(русское, английское)] в названном порядке."""
    выбор = dict(синонимы)
    return [(р, англ(р, выбор.get(р))) for р in слова]
