#!/usr/bin/env python3
"""ДОМ ШКАЛЫ УВЕРЕННОСТИ — слово степени есть ИМЯ ОТНОШЕНИЯ, а не чувство.

    ДОМ ВЕРОЯТНОСТИ СЧИТАЕТ «3 ИЗ 5» И НЕ НАЗЫВАЕТ ЭТОГО НИКАК. Замер 10.09 по мирам показов:
    слов «наверняка», «вряд ли», «скорее всего», «маловероятно», «почти наверняка» — НИ ОДНОГО
    ВХОЖДЕНИЯ; «likely» и «unlikely» стоя́т лишь в мире о вычислениях и в черновиках. Свод умеет
    получить число и не умеет сказать, что оно значит.

    ЧИСЛО БЕЗ ИМЕНИ НЕ ВХОДИТ В РЕЧЬ. Организм, считающий «1 из 10» и не знающий, что это
    «вряд ли», не поймёт человека, который говорит словами, — и сам скажет число там, где
    нужно слово.

ГРАНИЦА ШКАЛЫ ОБЪЯВЛЕНА, А НЕ ПОЧУВСТВОВАНА, И ЭТО ГЛАВНОЕ РЕШЕНИЕ ДОМА. «Вряд ли» начинается
там, где отношение меньше половины; «скорее всего» — где больше; ровно половина есть «равно
возможно». Правило СКАЗАНО НА КАЖДОЙ СТРАНИЦЕ («а это меньше половины»), и потому читатель
берёт не привычку, а меру.

    ШКАЛА, ЧЬЯ ГРАНИЦА НЕ НАЗВАНА, УЧИТ УГАДЫВАТЬ. Названная — учит считать.

ТРИ РОДА, И ВСЕ ТРИ ПРОВЕРЯЮТСЯ ТЕМ ЖЕ ПЕРЕСЧЁТОМ, ЧТО И ДОМ ВЕРОЯТНОСТИ:

    вряд ли        в мешке 1 красный шар и 9 синих шаров. вынуть красный вряд ли:
                   1 + 9 = 10, и вероятность есть 1 из 10, а это меньше половины.
    скорее всего   в мешке 9 красных шаров и 1 синий шар. вынуть красный скорее всего:
                   9 + 1 = 10, и вероятность есть 9 из 10, а это больше половины.
    поровну        в мешке 5 красных шаров и 5 синих шаров. вынуть красный и вынуть синий
                   равно возможно: 5 + 5 = 10, и вероятность есть 5 из 10, а это ровно
                   половина.                                        ← ГРАНИЦА ИЗНУТРИ

ТРЕТИЙ РОД ЕСТЬ САМА ГРАНИЦА, А НЕ СЕРЕДИНА ДЛЯ ПОЛНОТЫ: без него читатель вправе решить, что
шкала имеет две ступени, и половина отойдёт к одной из них наугад. Здесь она показана СВОИМ
именем.

КРАЯ ШКАЛЫ («невозможное» и «достоверное») ЗДЕСЬ НЕ ПОВТОРЯЮТСЯ: их показывает дом вероятности
(«0 из 5», «5 из 5»), и писать их второй раз значило бы учить одному дважды. Этот дом берёт
ровно то, чего там нет, — СЕРЕДИНУ и её ИМЕНА.

ЧИСЛА ВЫБРАНЫ ПОД РУССКИЙ СЧЁТ: имя стои́т при числе, форма берётся у дома русской грамматики,
вещи только мужского рода — у женского гнулось бы и прилагательное, а его склонений дом не
объявлял. Тот же довод и та же граница, что у дома вероятности.

    python3 tools/likelyforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import rugram  # noqa: E402 — счётная форма имени берётся у дома, а не пишется на глаз

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("вряд ли", "скорее всего", "поровну")

ВЕЩИ = {"ru": ("шар", "камень", "ключ", "орех"),
        "en": (("ball", "balls"), ("stone", "stones"), ("key", "keys"), ("nut", "nuts"))}
ЦВЕТА = {
    "ru": (("красных", "красный"), ("синих", "синий"), ("жёлтых", "жёлтый"),
           ("белых", "белый"), ("чёрных", "чёрный")),
    "en": (("red", "red"), ("blue", "blue"), ("yellow", "yellow"),
           ("white", "white"), ("black", "black")),
}
РАМКИ = {
    "ru": {
        "вряд ли": "в мешке {a} {ц1} {в_a} и {b} {ц2} {в_b}. вынуть {ц1е} вряд ли: {a} + {b} = {n}, и вероятность есть {a} из {n}, а это меньше половины.",
        "скорее всего": "в мешке {a} {ц1} {в_a} и {b} {ц2} {в_b}. вынуть {ц1е} скорее всего: {a} + {b} = {n}, и вероятность есть {a} из {n}, а это больше половины.",
        "поровну": "в мешке {a} {ц1} {в_a} и {b} {ц2} {в_b}. вынуть {ц1е} и вынуть {ц2е} равно возможно: {a} + {b} = {n}, и вероятность есть {a} из {n}, а это ровно половина.",
    },
    "en": {
        "вряд ли": "a bag holds {a} {ц1} {в_a} and {b} {ц2} {в_b}. drawing a {ц1е} one is unlikely: {a} + {b} = {n}, and the chance is {a} out of {n}, which is less than half.",
        "скорее всего": "a bag holds {a} {ц1} {в_a} and {b} {ц2} {в_b}. drawing a {ц1е} one is likely: {a} + {b} = {n}, and the chance is {a} out of {n}, which is more than half.",
        "поровну": "a bag holds {a} {ц1} {в_a} and {b} {ц2} {в_b}. drawing a {ц1е} one and drawing a {ц2е} one are equally likely: {a} + {b} = {n}, and the chance is {a} out of {n}, which is exactly half.",
    },
}


def вещь_при(язык, лемма, n):
    """Форма вещи при счёте: у русского спрашивается дом, у английского — множественное."""
    if язык == "ru":
        return rugram.форма(лемма, n)
    один, много = лемма
    return один if n == 1 else много


def _род(a, n):
    """Имя степени по отношению — по счёту, а не по списку: половина сравнивается БЕЗ ДРОБЕЙ,
    удвоением числителя, ибо дробь здесь была бы чужой работой и своим источником ошибки."""
    if 2 * a < n:
        return "вряд ли"
    return "скорее всего" if 2 * a > n else "поровну"


def _наборы():
    """(a, b): всякая степень набирает СВОЮ массу, и это куплено мерой.

    Первый отбор брал шесть полных чисел (10…20), и род «поровну» вышел на ШЕСТЬ страниц:
    равенство долей возможно лишь при чётном полном числе, и шести чётных на всю шкалу мало.
    Род с массой меньше девяти организмом не покупается, а тут это род ГРАНИЦЫ — тот самый,
    ради которого дом и отличается от дома вероятности.
    """
    вон = []
    for n in range(4, 31, 2):
        for a in range(1, n):
            b = n - a
            if 1 <= b and (a <= 3 or b <= 3 or a == b):
                вон.append((a, b))
    return вон


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        вещи, цвета = ВЕЩИ[язык], ЦВЕТА[язык]
        for к, (a, b) in enumerate(_наборы()):
            лемма = вещи[к % len(вещи)]
            ц1, ц1е = цвета[к % len(цвета)]
            ц2, ц2е = цвета[(к + 1) % len(цвета)]
            n = a + b
            поля = dict(a=a, b=b, n=n, ц1=ц1, ц1е=ц1е, ц2=ц2, ц2е=ц2е,
                        в_a=вещь_при(язык, лемма, a), в_b=вещь_при(язык, лемма, b))
            вон[РАМКИ[язык][_род(a, n)].format(**поля)] = (язык, _род(a, n))
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА = re.compile(r"(\d+) \+ (\d+) = (\d+)")
_ДОЛЯ = re.compile(r"(?:есть|is) (\d+) (?:из|out of) (\d+)")
_МЕНЬШЕ = re.compile(r"меньше половины|less than half")
_БОЛЬШЕ = re.compile(r"больше половины|more than half")
_РОВНО = re.compile(r"ровно половина|exactly half")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: сумма, отношение и СЛОВО ГРАНИЦЫ, сверенное с
    # отношением. Слово здесь есть утверждение о числе, и подмена его есть ложь.
    сум = _СУММА.search(с)
    доля = _ДОЛЯ.search(с)
    if сум and int(сум.group(1)) + int(сум.group(2)) != int(сум.group(3)):
        return True, False
    if not доля:
        return True, False
    a, n = int(доля.group(1)), int(доля.group(2))
    if a > n:
        return True, False
    if _МЕНЬШЕ.search(с) and not 2 * a < n:
        return True, False
    if _БОЛЬШЕ.search(с) and not 2 * a > n:
        return True, False
    if _РОВНО.search(с) and 2 * a != n:
        return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:74]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    вр = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "вряд ли")
    пол = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "поровну")
    if судить(вр.replace("меньше", "больше"))[1] is not False:
        беды.append("подмена границы прошла")
    if судить(пол.replace("ровно половина", "меньше половины"))[1] is not False:
        беды.append("подмена границы в равенстве прошла")
    if судить(вр.replace("вряд", "вря"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(вр + " " + вр)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ШКАЛА УВЕРЕННОСТИ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
