#!/usr/bin/env python3
"""ВОПРОСНАЯ ПАРА: вопрос принадлежит всем, РОД ОПРЕДЕЛЯЕТСЯ ОТВЕТОМ.

ЗНАНИЕ БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ НЕ ОТВЕЧАЕТ — ОНО ТОЛЬКО СООБЩАЕТ.
Мир, показывающий «прямоугольник 4 на 5 имеет площадь 20» и ни разу не
спрашивающий «чему равна площадь прямоугольника 4 на 5?», учит УЗНАВАТЬ
утверждение, а не ОТВЕЧАТЬ на вопрос.

ВОПРОС, НАПИСАННЫЙ ОТДЕЛЬНО ОТ ОТВЕТА, РАЗОЙДЁТСЯ С НИМ В ТОТ ЖЕ ДЕНЬ.
Это не опасение, а замер: подсадка мутантов нашла в языке формул строку
«how is $|16|$ said in words? $|15|$ in words is …», которую суд звал
ИСТИНОЙ, ибо читал только вторую половину. Вопрос спрашивал об одном,
ответ отвечал о другом, и оба были грамматичны.

ЛЕЧЕНИЕ — ОДИН ЗАКОН, И ОН ЖИВЁТ ЗДЕСЬ, А НЕ ЧЕТЫРЬМЯ КОПИЯМИ В ЧЕТЫРЁХ
СУДАХ. Закон о двух половинах:

    РОД ОПРЕДЕЛЯЕТСЯ ОТВЕТОМ. Суд берётся за пару лишь тогда, когда её
    ОТВЕТ судим им самим. Иначе образец «что-нибудь? что-нибудь» ловил
    бы весь корпус: вопросная форма принадлежит всем родам сразу, и суд
    поверхностей однажды объявил ложью четыреста сорок честных строк
    чужих миров ровно по этой причине.

    ВОПРОС ОБЯЗАН СПРАШИВАТЬ О ТОМ ЖЕ, ЧЕМ ОТВЕЧАЕТ. Связь проверяется
    ЧИСЛАМИ: ответ ОТКРЫВАЕТСЯ первой величиной вопроса и называет все
    его величины В ЕГО ПОРЯДКЕ; между ними вправе стоять искомое или
    шаг вычисления. Так устроены показы: вопрос называет ПРЕДМЕТ
    («прямоугольник 4 на 5»), ответ повторяет предмет и добавляет
    ИСКОМОЕ («площадь 20 и периметр 18»). Порча любой величины вопроса
    рвёт порядок, и пара становится ложью — той самой, которую суд
    формул не увидел.

ПОЧЕМУ ПОРЯДОК И ПЕРВОЕ МЕСТО, А НЕ ПРОСТОЕ ВХОЖДЕНИЕ. Вхождение
(«числа вопроса встречаются в ответе») прошло бы и тогда, когда вопрос
спрашивает об одном члене, а ответ говорит о другом, случайно
содержащем то же число. Порядок и первое место требуют, чтобы предмет
стоял в ответе первым, ибо ответ есть предмет плюс искомое.

ПОЧЕМУ НЕ НАЧАЛЬНЫЙ ОТРЕЗОК (закон до 03.09). Отрезок запрещал ответу
ЛЮБОЙ шаг между величинами вопроса, и второй слой школьных форм показал
цену: «Mia has 5 books, Sam has 3 more books than Mia, and Kate has
twice as many books as Mia, how many books do they have together?»
честно отвечается «5 + (5 + 3) + 2 × 5 = 23», где между 5 и 3 стоит
шаг; «how many times more is 12 than 3?» — «12 is four times more than
3», где между величинами стоит искомое. Отрезок звал обе ложью. Что он
ловил, ловит и порядок: подменённая величина вопроса не найдётся в
ответе на своём месте, вставленная — не найдётся вовсе, выброшенная
первая — уступит место чужой; перестановку величин вопроса отрезок
звал ложью, а она ложью не была.

ОТБОР — ВТОРОЙ ВИД ОТВЕТА (03.09, роды SVAMP по замеру e9: «how many X
did A V» после двух-трёх фактов с отвлекающими числами). Ответ, все
величины которого названы вопросом, не считает, а отбирает, и о том же
по построению; верен ли отбор — судит суд семейства, читающий слова
вопроса. До этой редакции вопрос с отбором был НЕМ ПО ПОСТРОЕНИЮ СУДА:
ни отрезок, ни порядок не пускали ответ «8» на вопрос о 6, 8 и 2.

ЧЕГО ЭТОТ ЗАКОН НЕ ТРЕБУЕТ: дословного повтора фразы. Русский вопрос
ставит предмет в родительный («площадь прямоугольникА»), а ответ — в
именительный, и требование дословности заставило бы язык говорить
криво. Числа же падежей не имеют.

ВЕЛИЧИНА, НАЗВАННАЯ СЛОВОМ, ЕСТЬ ВЕЛИЧИНА (03.09, второй слой школьных
форм). Вопрос «the design started with 7 panels, was tripled and then
reduced by 4» отвечается «7 × 3 − 4 = 17»; читай дом только цифры,
тройка встала бы МЕЖДУ величинами вопроса и рвала отрезок, а честная
пара звалась бы ложью. Кратные слова (twice, tripled, вдвое, утроили)
объявлены пакетами языка (`quantity_words`) и читаются как число, в
порядке текста, вместе с цифрами. ДОЛИ (half, четверть) НЕ читаются:
доля — часть, а не счёт, и её число в ответе — делитель, которого слово
прямо не называет; «half of 6000 → 6000 ÷ 2» держится цифрой 6000.
"""

import json
