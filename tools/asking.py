# ЗАЙМ ГАСИТСЯ ПАКЕТАМИ (М-137; 04.09): зачины, объявленные пакетами языков
# (ask_words), входят в множество наравне с займом — «zijn 4 en 9 onderling
# ondeelbaar?», «sono 4 e 9 coprimi?» открываются множественной связкой,
# которой займ не знал, и суд письма звал их ложью.
def _зачины_пакетов():
    вон = set()
    for путь in sorted(ПАКЕТЫ.glob("*.json")):
        try:
            пакет = json.loads(путь.read_text(encoding="utf-8"))
        except ValueError:
            continue
        вон.update(w.lower() for w in (пакет.get("ask_words") or {}).get("words", ()) if w != "¬")
    return вон


ЗАЧИНЫ = frozenset(ЗАЧИНЫ | _зачины_пакетов())
# ВОПРОСНОЕ СЛОВО СТОИТ ТАМ, ГДЕ ЕГО СТАВИТ ЯЗЫК. Турецкий («bir sayının
# karesi nedir?»), суахили («ndizi ni nini?»), японский ставят его В
# КОНЦЕ; зачин первого слова для них ложен по устройству. Дом судит
# зачин лишь там, где язык ставит вопросное слово вперёд: кириллица и
# латиница БЕЗ диакритик (диакритика — знак языка, чьих зачинов дом не
# объявил). Объявить зачины обязан ПАКЕТ языка; пока они здесь — долг.
КИРИЛЛИЦА = re.compile(r"[а-яё]", re.I)
СЛОВО_ЗАЧИНА = re.compile(r"[¿]?[^\W\d_][^\W\d_'\-]*(?:['\-][^\W\d_]+)*")
# ДИАКРИТИКА — БУКВА, А НЕ ЗНАК: прежняя проверка «весь вопрос в ASCII»
# молчала на «what is 5 − 1?» из-за минуса, и порча «wha is» проходила.
# Молчит дом лишь там, где есть латинская буква с диакритикой (языки,
# чьи зачины не объявлены); знаки счёта письму не помеха.
ДИАКРИТИКА = re.compile(r"[\u00c0-\u00d6\u00d8-\u00f6\u00f8-\u024f]")
ВЫБОР = re.compile(r"\s(?:или|or|oder|ou|o)\s")
РАЗДЕЛ = re.compile(r"[.;:,]\s+|\s—\s")
# ПРЕДЛОГ ПЕРЕД ЗАЧИНОМ ПРОЗРАЧЕН: «за сколько шагов», «во сколько раз»,
# «на что делится», «by how much», «for what n» — вопросное слово стоит
# вторым, и предлог его не прячет.
ПРЕДЛОГИ = frozenset("""в за во на по с со до через от к ко у из о об при
in at by for from to of on with about under over""".split())
# ЗАЧИН ЖИВЁТ В НАЧАЛЕ ЛЮБОЙ КЛАУЗЫ ВОПРОСА, А НЕ ТОЛЬКО ПОСЛЕДНЕЙ.
# «если n чётно, чётно ли n + 8?» несёт зачин первым словом; «для
# f(t) = t^2, чему равно…» — вторым; «какова скорость тела, прошедшего
# 63 метра…» — первым, а последняя клауза начинается причастием.
# Требовать зачин от одной клаузы значило звать ложью честное.


def зачин_объявлен(вопрос):
    """True — вопрос начат объявленным зачином или дом о нём молчит.

    None — молчание (письмо без пробелов, вопрос-выбор, вопрос, начатый
    предметом или числом); False — зачин есть слово, но не вопросное.
    """
    if not ПИСЬМО_С_ПРОБЕЛАМИ.search(вопрос):
        return None
    if not КИРИЛЛИЦА.search(вопрос) and ДИАКРИТИКА.search(вопрос):
        return None  # язык с диакритикой: зачины не объявлены — молчим
    if ВЫБОР.search(" " + вопрос + " "):
        return None
    начала = []
    for клауза in РАЗДЕЛ.split(вопрос):
        слова = [w.strip(_КРАЙ).lower() for w in клауза.strip().split()]
        слова = [w for w in слова if w]
        if not слова:
            continue
        # ЧАСТИЦА «ЛИ» СТОИТ ВТОРОЙ ПО ЗАКОНУ ЯЗЫКА и сама есть вопрос:
        # «делится ли», «инъективна ли», «чётно ли» — первое слово тут
        # предикат, а не зачин, и порча его этим признаком не ловится.
        if len(слова) > 1 and слова[1] == "ли":
            return True
        начала.append(слова[0])
        if слова[0] in ПРЕДЛОГИ and len(слова) > 1:
            начала.append(слова[1])
    # НАЧАЛО-ПРЕДМЕТ («f(x)», «2x²», «a+b») — не слово, и зачин при нём
    # не спрашивается: вопрос, начатый формулой, есть вопрос о предмете,
    # и дом о нём молчит (inquiry_de_fr: «f(x) = x × 0 est-elle injective
    # sur 1, 2, 3 ?» — 60 честных строк роняла первая редакция).
    начала = [н for н in начала if н and СЛОВО_ЗАЧИНА.fullmatch(н)]
    if not начала:
        return None  # только числа, формулы, знаки — предмет, не зачин
    return any(н in ЗАЧИНЫ for н in начала)


def вопросное_слово_есть(вопрос):
    """Совместимость: истина, если зачин объявлен или дом молчит."""
    return зачин_объявлен(вопрос) is not False


# ЗАДАНИЕ — ПАРА БЕЗ ВОПРОСНОГО ЗНАКА (04.09, Т-4 коллегии выразительности:
# «compute 47 + 38», «tell me whether 91 is prime» молчали — у повеления нет
# «?», и дом пары его не читал). Задание открывается зачином, ОБЪЯВЛЕННЫМ
# пакетом языка (task_words), и кончается первой точкой; ответ за ней судится
# тем же судом, что и ответ на вопрос, и о том же (о_том_же).
def _задания():
    слова = set()
    for путь in sorted(ПАКЕТЫ.glob("*.json")):
        try:
            пакет = json.loads(путь.read_text(encoding="utf-8"))
        except ValueError:
            continue
        слова.update(w.lower() for w in (пакет.get("task_words") or {}).get("words", ()))
    if not слова:
        return None
    зачины = "|".join(re.escape(w) for w in sorted(слова, key=len, reverse=True))
    return re.compile(rf"^((?:{зачины})\b[^.?!]*?)\. (.+)$")


ЗАДАНИЕ = _задания()


# ВОПРОС О ЗНАЧЕНИИ ВЫРАЖЕНИЯ СВЯЗАН СВОЕЙ ФОРМОЙ (04.09): «what is 220 + 11?
# 220 + 10 = 230.» судил один суд арифметики — по равенству, не по паре, и
# порча числа вопроса проходила. Форма значения объявлена пакетом
# (ask_forms.value); вопрос, который есть такая форма вокруг ЧИСТО ЧИСЛОВОГО
# выражения, обязан быть о том же, что и ответ.
ВЫРАЖЕНИЕ = re.compile(r"^[\d\s+\-*/×÷^√().,\u2212\u22c5]+$")


def _формы_значения():
    вон = []
    for путь in sorted(ПАКЕТЫ.glob("*.json")):
        try:
            пакет = json.loads(путь.read_text(encoding="utf-8"))
        except ValueError:
            continue
        for форма in (пакет.get("ask_forms") or {}).get("value", ()):
            перед, после = форма.split("{}", 1)
            вон.append(re.compile("^" + re.escape(перед) + "(.+?)" + re.escape(после.rstrip("?.")) + "$"))
    return tuple(вон)


ФОРМЫ_ЗНАЧЕНИЯ = _формы_значения()


def форма_значения(вопрос):
    """True — вопрос (или задание) есть объявленная форма значения вокруг
    чисто числового выражения; такой вопрос связан с ответом домом пары."""
    голова = вопрос.strip().rstrip("?.").strip()
    for о in ФОРМЫ_ЗНАЧЕНИЯ:
        м = о.match(голова)
        if м and ВЫРАЖЕНИЕ.match(м.group(1).strip()):
            return True
    return False


def пара(строка):
    """(вопрос, ответ) или None — строка не вопросная и не задание."""
    с = строка.strip()
    м = ПАРА.match(с)
    if м:
        return м.group(1), м.group(2)
    if ЗАДАНИЕ is not None:
        м = ЗАДАНИЕ.match(с)
        if м:
            return м.group(1), м.group(2)
    return None


def о_том_же(вопрос, ответ):
    """Спрашивает ли вопрос о том же предмете, о котором отвечает."""
    свои = величины(вопрос)
    ответные = величины(ответ)
    # ВОПРОС БЕЗ ВЕЛИЧИН СПРАШИВАЕТ О ТОМ ЖЕ, ЕСЛИ И ОТВЕТ БЕЗ НИХ: «what
    # does «**field**» mean? «**field**» is read as bold field» — пара о
    # слове, не о числе, и суд разметки судит её сам. Редакция 08:39
    # требовала величин в каждом вопросе и назвала ложью 160 честных пар
    # разметки; порча же, вынувшая числа из вопроса при числовом ответе,
    # по-прежнему ловится: величины ответа тогда есть, а в вопросе нет.
    if not свои:
        return not ответные
    # ОТБОР, А НЕ СЧЁТ: ответ, все величины которого суть величины вопроса,
    # ничего не считает — он отбирает названное вопросом («…6 in the
    # morning, 8 in the afternoon and 2 in the evening, how many in the
    # afternoon? 8»), и о том же по построению. Подмена отобранной
    # величины в вопросе рвёт вхождение; подмена отвлекающей — не ложь,
    # ибо о ней не спрашивали; ВЕРЕН ЛИ отбор — знает суд семейства,
    # читающий слова вопроса, а не дом пары (03.09, роды SVAMP по e9).
    if ответные and all(в in свои for в in ответные):
        return True
    if not ответные or ответные[0] != свои[0]:
        return False
    # ВЕЛИЧИНЫ ВОПРОСА В ЕГО ПОРЯДКЕ: подпоследовательность величин ответа.
    место = 0
    for величина in свои:
        while место < len(ответные) and ответные[место] != величина:
            место += 1
        if место == len(ответные):
            return False
        место += 1
    return True


def судить_парой(строка, судить_ответ):
    """(судимо, истинно) о вопросной строке, или None — пара не наша.

    `судить_ответ` есть тот же самый судья утверждения, каким мир
    судится без вопроса: ОТВЕТ СУДИМ ТЕМ ЖЕ СУДОМ, ЧТО СУДИТ
    УТВЕРЖДЕНИЕ. Вопрос, ответ которого палата не берётся судить, хуже
    отсутствия вопроса — он выглядит поверхностью, ею не будучи, и
    ворота записи такую строку не пропустят.
    """
    если = пара(строка)
    if если is None:
        return None
    вопрос, ответ = если
    судимо, истинно = судить_ответ(ответ)
    if not судимо:
        return None
    # у задания зачин уже объявлен пакетом (иначе пара не сложилась бы);
    # вопросное слово спрашивается только с вопроса
    return True, (bool(истинно) and о_том_же(вопрос, ответ)
                  and (вопросное_слово_есть(вопрос) if вопрос.endswith("?") else True))
