import re

# Вопрос кончается знаком, и до него знака нет: пара есть ОДИН вопрос и
# ОДИН ответ, а не цепочка.
ПАРА = re.compile(r"^([^?]*\?) (.+)$")
ЧИСЛО = re.compile(r"\d+")

ПАКЕТЫ = pathlib.Path(__file__).resolve().parent / "langpacks"


def _величины_словом():
    """слово → число из `quantity_words` каждого пакета языка (М-131: один
    словарь на всех, читается группой)."""
    слова = {}
    for путь in sorted(ПАКЕТЫ.glob("*.json")):
        пакет = json.loads(путь.read_text(encoding="utf-8"))
        for слово, число in пакет.get("quantity_words", {}).items():
            слова[слово.lower()] = int(число)
    return слова


ВЕЛИЧИНЫ_СЛОВОМ = _величины_словом()
ВЕЛИЧИНА = re.compile(
    r"\d+|" + "|".join(r"\b" + re.escape(с) + r"\b" for с in
                       sorted(ВЕЛИЧИНЫ_СЛОВОМ, key=len, reverse=True)),
    re.I)


def величины(текст):
    """Величины текста в его порядке: цифрами — как есть, кратным словом —
    число, которое оно называет (строками, как и ЧИСЛО.findall)."""
    return [x if x.isdigit() else str(ВЕЛИЧИНЫ_СЛОВОМ[x.lower()])
            for x in ВЕЛИЧИНА.findall(текст)]


