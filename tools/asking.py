#!/usr/bin/env python3
"""ВОПРОСНАЯ ПАРА: вопрос принадлежит всем, РОД ОПРЕДЕЛЯЕТСЯ ОТВЕТОМ.

ЗНАНИЕ БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ НЕ ОТВЕЧАЕТ — ОНО ТОЛЬКО СООБЩАЕТ.
Мир, показывающий «прямоугольник 4 на 5 имеет площадь 20» и ни разу не
спрашивающий «чему равна площадь прямоугольника 4 на 5?», учит УЗНАВАТЬ
утверждение, а не ОТВЕЧАТЬ на вопрос.

ВОПРОС, НАПИСАННЫЙ ОТДЕЛЬНО ОТ ОТВЕТА, РАЗОЙДЁТСЯ С НИМ В ТОТ ЖЕ ДЕНЬ.
Это не опасение, а замер: подсадка мутантов нашла в языке формул строку
«how is $|16|$ said in words? $|15|$ in words is …», которую суд звал
ИСТИНОЙ, ибо читал только вторую половину. Вопрос спрашивал об одном,
ответ отвечал о другом, и оба были грамматичны.

ЛЕЧЕНИЕ — ОДИН ЗАКОН, И ОН ЖИВЁТ ЗДЕСЬ, А НЕ ЧЕТЫРЬМЯ КОПИЯМИ В ЧЕТЫРЁХ
СУДАХ. Закон о двух половинах:

    РОД ОПРЕДЕЛЯЕТСЯ ОТВЕТОМ. Суд берётся за пару лишь тогда, когда её
    ОТВЕТ судим им самим. Иначе образец «что-нибудь? что-нибудь» ловил
    бы весь корпус: вопросная форма принадлежит всем родам сразу, и суд
    поверхностей однажды объявил ложью четыреста сорок честных строк
    чужих миров ровно по этой причине.

    ВОПРОС ОБЯЗАН СПРАШИВАТЬ О ТОМ ЖЕ, ЧЕМ ОТВЕЧАЕТ. Связь проверяется
    ЧИСЛАМИ: величины вопроса суть НАЧАЛЬНЫЙ ОТРЕЗОК величин ответа.
    Так устроены показы: вопрос называет ПРЕДМЕТ («прямоугольник 4 на
    5»), ответ повторяет предмет и добавляет ИСКОМОЕ («площадь 20 и
    периметр 18»). Порча любой величины вопроса рвёт отрезок, и пара
    становится ложью — той самой, которую суд формул не увидел.

ПОЧЕМУ ИМЕННО НАЧАЛЬНЫЙ ОТРЕЗОК, А НЕ ВХОЖДЕНИЕ. Вхождение («числа
вопроса встречаются в ответе») прошло бы и тогда, когда вопрос
спрашивает об одном члене, а ответ говорит о другом, случайно
содержащем то же число. Отрезок требует ПОРЯДКА и МЕСТА: предмет стоит
в ответе первым, ибо ответ есть предмет плюс искомое.

ЧЕГО ЭТОТ ЗАКОН НЕ ТРЕБУЕТ: дословного повтора фразы. Русский вопрос
ставит предмет в родительный («площадь прямоугольникА»), а ответ — в
именительный, и требование дословности заставило бы язык говорить
криво. Числа же падежей не имеют.
"""

import re

# Вопрос кончается знаком, и до него знака нет: пара есть ОДИН вопрос и
# ОДИН ответ, а не цепочка.
ПАРА = re.compile(r"^([^?]*\?) (.+)$")
ЧИСЛО = re.compile(r"\d+")


def пара(строка):
    """(вопрос, ответ) или None — строка не вопросная."""
    м = ПАРА.match(строка.strip())
    return (м.group(1), м.group(2)) if м else None


def о_том_же(вопрос, ответ):
    """Спрашивает ли вопрос о том же предмете, о котором отвечает."""
    свои = ЧИСЛО.findall(вопрос)
    ответные = ЧИСЛО.findall(ответ)
    return bool(свои) and ответные[:len(свои)] == свои


def судить_парой(строка, судить_ответ):
    """(судимо, истинно) о вопросной строке, или None — пара не наша.

    `судить_ответ` есть тот же самый судья утверждения, каким мир
    судится без вопроса: ОТВЕТ СУДИМ ТЕМ ЖЕ СУДОМ, ЧТО СУДИТ
    УТВЕРЖДЕНИЕ. Вопрос, ответ которого палата не берётся судить, хуже
    отсутствия вопроса — он выглядит поверхностью, ею не будучи, и
    ворота записи такую строку не пропустят.
    """
    если = пара(строка)
    if если is None:
        return None
    вопрос, ответ = если
    судимо, истинно = судить_ответ(ответ)
    if not судимо:
        return None
    return True, bool(истинно) and о_том_же(вопрос, ответ)
