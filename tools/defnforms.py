def _без_скобок(т):
    return re.sub(r"\([^)]*\)", "", т)


def _первая_фраза_ru(т):
    for м in КОНЕЦ_RU.finditer(т):
        хвост = re.search(r"([А-ЯЁа-яёA-Za-z]+)$", т[:м.start()])
        if хвост and (хвост.group(1).lower() in СОКР_RU
                      or (len(хвост.group(1)) == 1 and хвост.group(1).isupper())):
            continue
        т = т[:м.start()]
        break
    for знак in ПРИМЕР_RU:
        k = т.find(знак)
        if k > 0:
            т = т[:k]
    k = т.find(":")
    if k > 0:
        т = т[:k]
    т = re.sub(r"[,;]?\s+(?:или|и|а|но|либо|же)$", "", т.strip())
    return т.strip().rstrip(",;—- ")


def _чисто_ru(т):
    return (т and not ПЛОХО_RU.search(т) and _скобки_парны(т)
            and not ЛАТИНИЦА_ВНЕ_СКОБОК.search(_без_скобок(т))
            and т[0].isalpha() and т[0].islower()
            and not ГЛАГОЛ_RU.match(т)
            and not (ПРЕДЛОГ_RU.match(т) and _слов(т) < 6)
            and not ОБОРОТ_RU.match(т)
            and 2 <= _слов(т) <= МАКС_СЛОВ and not _чужой_род(т))


def _ранг_эсбе(понятие, заголовок):
    """0 — точный заголовок, 1 — уточнённый запятой, иначе составное понятие."""
    з = D.норма(заголовок).casefold()
    if з == понятие:
        return 0
    if з.startswith(понятие + ","):
        return 1
    return 2


def _тире_вне_скобок(т, с):
    """Позиция первого « — » на нулевой глубине скобок, начиная с с."""
    глубина = 0
    for i in range(с, len(т)):
        з = т[i]
        if з == "(":
            глубина += 1
        elif з == ")":
            глубина = max(0, глубина - 1)
        elif з == "—" and глубина == 0 and i > 0 and т[i - 1] == " ":
            return i
    return -1


def _кандидаты_эсбе(понятие, статья):
    т = статья.тело
    титул = понятие[0].upper() + понятие[1:]
    вон = []
    if т.startswith(титул):
        k = _тире_вне_скобок(т, len(титул))
        if 0 < k < 200:
            вон.append(т[k + 1:].lstrip())
    м = ВЕРБ_ОПР.search(т[:500])
    if м:
        вон.append(т[м.end():])
    м = re.match(re.escape(титул) + r"[^—.]{0,80}?\sесть\s+(.*)$", т)
    if м:
        вон.append(м.group(1))
    return вон


def цитата_эсбе(понятие):
    """(цитата, статья) из ЭСБЕ или None — статьи точные раньше уточнённых."""
    статьи = [(_ранг_эсбе(понятие, с.заголовок), i, с)
              for i, (_, с) in enumerate(D.словарь("esbe").по_слову(понятие))]
    for ранг, _, с in sorted(статьи, key=lambda x: (x[0], x[1])):
        if ранг > 1:
            break
        for к in _кандидаты_эсбе(понятие, с):
            ф = _укоротить(_первая_фраза_ru(ВЕДУЩИЕ.sub("", к.strip())))
            if ф and _чисто_ru(ф):
                return ф, с
    return None


