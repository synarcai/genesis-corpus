def _строчная(ц):
    """Первая буква толкования — строчной, если за ней строчная."""
    return ц[0].lower() + ц[1:] if len(ц) > 1 and ц[0].isupper() and ц[1].islower() else ц


def факты(язык, понятие):
    """[(цитата, ярлык)] — что полка знает о понятии; [] — не знает."""
    вон = []
    if язык == "en":
        ярл = D.ярлык(D.ИСТОЧНИКИ["webster"])
        if ярл:
            for ц, _ in цитаты_webster(понятие):
                вон.append((_строчная(ц), ярл))
    else:
        э = цитата_эсбе(понятие)
        if э:
            вон.append((_строчная(э[0]), D.ярлык(D.ИСТОЧНИКИ["esbe"], э[1])))
        д = цитата_даля(понятие)
        ярл = D.ярлык(D.ИСТОЧНИКИ["dal"])
        if д and ярл:
            вон.append((_строчная(д[0]), ярл))
    return вон


def показ(язык, понятие, цитата, ярлык, вопрос):
    if язык == "en":
        тело = f"{понятие} is {цитата}: {ярлык}."
        return f"what is {понятие}? {тело}" if вопрос else тело
    тело = f"{понятие} — это {цитата}: {ярлык}."
    return f"что такое {понятие}? {тело}" if вопрос else тело


def _отсев(строки):
    """Строка, которую чужой суд зовёт ложью, в мир не идёт — и об этом
    сказано вслух: отбор цитаты правится, суд нет."""
    try:
        from panel import палата
        суд = палата()
    except Exception:
        return строки
    if not суд.живых:
        return строки
    вон = []
    for с in строки:
        судимо, истинно, кем = суд.судить(с)
        if судимо and not истинно:
            print(f"  ОТСЕЯНО ({', '.join(кем)}): {с[:100]}")
            continue
        вон.append(с)
    return вон


def собрать():
    """{(язык, понятие): [(цитата, ярлык)]} по объявлению; немые названы."""
    вон, немые = {}, []
    for язык, понятие in понятия():
        ф = факты(язык, понятие)
        if ф:
            вон[(язык, понятие)] = ф
        else:
            немые.append(f"{язык}:{понятие}")
    if немые:
        print(f"НЕ НАЙДЕНО НА ПОЛКЕ ({len(немые)}): {' '.join(немые)}")
    return вон


