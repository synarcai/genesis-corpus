def цитата_даля(понятие):
    """(цитата, статья) из Даля или None."""
    for _, с in D.словарь("dal").по_слову(понятие):
        if D.норма(с.заголовок).casefold().split()[0] != понятие:
            continue
        м = ТЕЛО_ДАЛЯ.match(с.тело)
        if not м or м.group("титул").lower() != понятие:
            continue
        хвост = ПОМЕТЫ_ДАЛЯ.sub("", м.group("хвост"))
        k = хвост.find("||")
        if k > 0:
            хвост = хвост[:k]
        ф = _укоротить(_первая_фраза_ru(хвост))
        if ф and _чисто_ru(ф):
            return ф, с
    return None


