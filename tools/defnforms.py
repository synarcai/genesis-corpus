def понятия():
    """[(язык, понятие)] из объявления — по одному в строке, «язык<TAB>слово»."""
    вон = []
    for с in ПОНЯТИЯ.read_text(encoding="utf-8").splitlines():
        с = с.strip()
        if not с or с.startswith("#"):
            continue
        язык, _, слово = с.partition("\t")
        if язык in ("en", "ru") and слово:
            вон.append((язык, слово.strip()))
    return вон


def _слов(т):
    return len(т.split())


def _скобки_парны(т):
    глубина = 0
    for з in т:
        if з == "(":
            глубина += 1
        elif з == ")":
            глубина -= 1
            if глубина < 0:
                return False
    return глубина == 0


def _укоротить(т, границы=("; ", ", ")):
    """Фраза длиннее МАКС_СЛОВ режется по последней границе в пределе —
    цитата остаётся дословным началом фразы."""
    if _слов(т) <= МАКС_СЛОВ:
        return т
    предел = len(" ".join(т.split()[:МАКС_СЛОВ]))
    k = max(т.rfind(г, 0, предел) for г in границы)
    return т[:k] if k > 0 else None


def _чужой_род(т):
    return any(п.search(т) for п in ПРИЗНАКИ_РОДОВ)


