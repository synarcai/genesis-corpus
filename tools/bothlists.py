"""ДОМ ДВУХ СПИСКОВ (14.09, куплен нулём пробы).

Замерено 14.09: «и там и там» / «in both lists» — НОЛЬ строк. Мир множеств (`logic_sets`)
знает ЗНАКИ — «{b c} ⊂ {b c e} = T», — и знает их чтение словом. Но чтобы два списка имён
были даны прозой и спрошено «кто есть и там и там», корпус не говорит нигде.

    «И» НАД ИСТИННОСТЬЮ И «И» НАД ПРИНАДЛЕЖНОСТЬЮ — ОДИН ЗАКОН И ДВА ДЕЛА. Мир булевых
    выражений, выкованный нынче утром, учит первому: «истина и ложь — это ложь». Здесь то же
    «и» ходит по спискам: «кто есть и там и там» есть пересечение, и ответ — не «да» и не
    «нет», а ИМЕНА. Из умения считать связку второе не следует ничем.

ТРИ РОДА ПО ДЕЛУ:

    и_там_и_там   пересечение: кто есть в обоих списках;
    хоть_где_то   объединение: кто есть хоть в одном. Порядок ответа ОБЪЯВЛЕН — сперва по
                  первому списку, потом новые из второго, — иначе у вопроса два ответа;
    только_в_одном  разность: кто есть в первом и нет во втором.

    ПУСТОЙ ОТВЕТ ЕСТЬ ОТВЕТ, И ОН НАЗВАН СЛОВОМ. «Никого» — такой же ответ, как список имён,
    и дом показывает его НАРОЧНО: читатель, не видевший пустого ответа, при встрече с ним
    либо смолчит, либо выдумает имя.

    А ГДЕ ПУСТОЙ ОТВЕТ НЕВОЗМОЖЕН, ЭТО СКАЗАНО, А НЕ ОБОЙДЕНО. Объединение двух НЕПУСТЫХ
    списков непусто ВСЕГДА, и род «хоть где-то» пустого ответа не даёт ни на одной паре.
    Требовать его там значило бы портить дом ради ровности закона; самопроверка потому и
    делит роды, а не равняет их.
"""
