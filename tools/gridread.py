def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    assert {р for _в, р in ВИДЫ} == set(РОДЫ), "вид вопроса объявлен не всякому роду"
    for язык, таблицы in ТАБЛИЦЫ.items():
        for строки, столбцы, числа in таблицы:
            assert len(числа) == len(строки), "полос не столько, сколько строк"
            assert all(len(ряд) == len(столбцы) for ряд in числа), "ряд не по столбцам"
            assert len(set(строки)) == len(строки), f"строка дважды: {строки}"
            assert len(set(столбцы)) == len(столбцы), f"столбец дважды: {столбцы}"
            # ЧИСЛА В СТОЛБЦЕ РАЗЛИЧНЫ — иначе обратное чтение немо на этой таблице.
            for j in range(len(столбцы)):
                столбец = [ряд[j] for ряд in числа]
                assert len(set(столбец)) == len(столбец), f"число дважды в столбце: {столбец}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


