# СУД СТРОИТ ТАБЛИЦУ ЗАНОВО ПО ЗАПИСИ: он читает имена строк, имена столбцов и полосы чисел,
# сверяет, что полос столько же, сколько строк, а чисел в полосе — сколько столбцов, и лишь
# потом отвечает на вопрос сам. Порча имени, числа или координаты меняет вердикт.
def _разбор_головы(язык, кусок):
    рамки = РАМКИ[язык]
    о = (re.escape(рамки["таблица"]).replace(re.escape("{строки}"), "(?P<строки>[^;]+?)")
         .replace(re.escape("{столбцы}"), "(?P<столбцы>[^.;]+?)")
         .replace(re.escape("{тело}"), "(?P<тело>.+)"))
    м = re.fullmatch(о, кусок)
    if not м:
        return None
    строки = [с.strip() for с in м.group("строки").split(",")]
    столбцы = [с.strip() for с in м.group("столбцы").split(",")]
    полоса = (re.escape(рамки["полоса"]).replace(re.escape("{имя}"), "(?P<имя>[^:.]+?)")
              .replace(re.escape("{числа}"), r"(?P<числа>[\d, ]+)"))
    числа = []
    куски = [к.strip() for к in м.group("тело").split(". ")]
    if len(куски) != len(строки):
        return None
    for имя, кусок_ in zip(строки, куски):
        п = re.fullmatch(полоса, кусок_)
        if not п or п.group("имя") != имя:
            return None
        ряд = [int(ч) for ч in п.group("числа").split(",")]
        if len(ряд) != len(столбцы):
            return None
        числа.append(ряд)
    if len(set(строки)) != len(строки) or len(set(столбцы)) != len(столбцы):
        return None
    return строки, столбцы, числа


def судить(строка):
    """(судимо, истинно) — таблица построена заново, ответ добыт из неё судом."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for вид, _род in ВИДЫ:
            о = re.escape(рамки[вид])
            for дыра, узор in (("с", "[^.,?]+?"), ("к", "[^.,?]+?"), ("v", r"\d+")):
                о = о.replace(re.escape("{" + дыра + "}"), f"(?P<{дыра}>{узор})")
            м = re.search(о + r"$", строка)
            if not м:
                continue
            голова = _разбор_головы(язык, строка[:м.start()].strip())
            if голова is None:
                continue
            строки, столбцы, числа = голова
            дыры = м.groupdict()
            v = int(дыры["v"])
            if "к" in дыры and дыры["к"] not in столбцы:
                return True, False
            if "с" in дыры and дыры["с"] not in строки:
                return True, False
            j = столбцы.index(дыры["к"]) if "к" in дыры else None
            i = строки.index(дыры["с"]) if "с" in дыры else None
            if вид == "пересечение":
                return True, числа[i][j] == v
            if вид == "итог_столбца":
                return True, sum(ряд[j] for ряд in числа) == v
            if вид == "итог_строки":
                return True, sum(числа[i]) == v
            столбец = [ряд[j] for ряд in числа]
            # ОБРАТНОЕ ЧТЕНИЕ ВЕРНО ЛИШЬ ПРИ ЕДИНСТВЕННОМ ЗНАЧЕНИИ: спроси о числе, стоящем
            # в столбце дважды, — и всякий ответ будет и верен, и ложен.
            return True, столбец.count(v) == 1 and столбец[i] == v
    return False, True


