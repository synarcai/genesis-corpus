#!/usr/bin/env python3
"""GENESIS layer: ВЗВЕШЕННОЕ СРЕДНЕЕ — see tools/wmeanforms.py for the law.

ОБЕ СТОРОНЫ ЛОВУШКИ ИДУТ ОДНОЙ ГРУППОЙ. Полусумма средних НЕ ВСЕГДА ложна: при равных
группах она верна, и верна не случайно, а по тому же закону, взятому при равных весах.
Показанная лишь там, где она лжёт, она научила бы не доверять ей никогда — и это была бы
вторая ловушка вместо первой.

    ПРАВИЛО, ПОКАЗАННОЕ ЛИШЬ ТАМ, ГДЕ ОНО ОТВЕРГАЕТ, УЧИТ ОТВЕРГАТЬ ВСЕГДА.

СЧЁТ И ЕГО СЛЕДСТВИЯ — одной группой: «среднее целого 2», «оно между 1 и 5» и «оно ближе к
среднему большей группы» суть три взгляда на один вес. ВОПРОС отдельно.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import wmeanforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_wmean.txt"
ГРУППЫ = (("взвешенное среднее", "среднее между крайними", "ближе к большей"),
          ("среднее средних не то", "среднее средних то же"),
          ("вес есть число",),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
