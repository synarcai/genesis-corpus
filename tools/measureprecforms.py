# ПАРЫ ДЛЯ СЛОЖЕНИЯ ПОГРЕШНОСТЕЙ: два измерения с одной ценой деления.
ДЕЛИТЕЛИ = (3, 7, 6, 9)


def _д(x):
    """Десятичное с запятой — русская запись; точка остаётся английской."""
    return str(x)


def _десятая(x):
    """Ровно одна цифра после запятой: «5,0» рядом с «4,9» и «5,1».

    РАЗНОБОЙ ЗАПИСИ ЧИТАЕТСЯ КАК РАЗНОБОЙ ТОЧНОСТИ: «4,9, 5 и 5,1» говорит, будто
    среднее измерение было точнее двух крайних, а оно было тем же самым.
    """
    return str(Decimal(x).quantize(Decimal("0.1")))


def _ру(x):
    return str(x).replace(".", ",")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        зп = _ру if язык == "ru" else _д
        for i, (пру, пан, пара, панмн, знач, цена, сру, сан) in enumerate(ИЗМЕРЕНИЯ):
            n = Decimal(знач)
            ц = Decimal(цена)
            низ, верх = n - ц / 2, n + ц / 2
            предмет = пру if язык == "ru" else пан
            счётное = сру if язык == "ru" else сан
            сч = 5 + i
            общ = dict(предмет=предмет, счётное=счётное, сч=сч, знач=зп(n), цена=зп(ц),
                       низ=зп(низ), верх=зп(верх), полцены=зп(ц / 2),
                       пара=пара if язык == "ru" else f"two {панмн}")
            вон[рамки["счёт против измерения"].format(**общ)] = (язык, "счёт против измерения")
            вон[рамки["цена деления"].format(**общ)] = (язык, "цена деления")
            вон[рамки["спрошенное"].format(**общ)] = (язык, "спрошенное")
            # РАЗБРОС: три повторения вокруг значения, шагом в десятую.
            деся = Decimal("0.1")
            вон[рамки["разброс повторений"].format(
                **dict(общ, п1=зп(_десятая(n - деся)), п2=зп(_десятая(n)),
                       п3=зп(_десятая(n + деся)),
                       размах=зп(_десятая(2 * деся))))] = (язык, "разброс повторений")
            # ПОГРЕШНОСТЬ СКЛАДЫВАЕТСЯ: два таких же предмета вместе.
            вон[рамки["погрешность складывается"].format(
                **dict(общ, сумма=зп(2 * n), сумниз=зп(2 * низ), сумверх=зп(2 * верх),
                       сумцена=зп(ц)))] = (
                           язык, "погрешность складывается")
            # ДЕЛЕНИЕ НЕ СОЗДАЁТ ТОЧНОСТИ.
            d = ДЕЛИТЕЛИ[i % len(ДЕЛИТЕЛИ)]
            длинное = str((n / d).quantize(Decimal("0.000001")))
            # ГРАНИЦЫ ЧАСТНОГО БЕРУТСЯ ОТ ГРАНИЦ ИЗМЕРЕНИЯ, А НЕ ОТ ЕГО СЕРЕДИНЫ:
            # длина была между низом и верхом, и частное лежит между их частными.
            вон[рамки["деление не создаёт точности"].format(
                **dict(общ, делитель=d, длинное=зп(длинное),
                       чниз=зп(_десятая(низ / d)), чверх=зп(_десятая(верх / d)),
                       честное=зп(_десятая(n / d))))] = (
                           язык, "деление не создаёт точности")
    return вон


