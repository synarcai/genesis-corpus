# ЧИСЛО ЧИТАЕТСЯ С ЗАПЯТОЙ ИЛИ С ТОЧКОЙ — по языку страницы, и суд обязан знать оба.
_ЧИСЛО = r"(\d+(?:[.,]\d+)?)"
_МЕЖДУ = re.compile(rf"между {_ЧИСЛО} и {_ЧИСЛО}|between {_ЧИСЛО} and {_ЧИСЛО}")
_ВМЕСТЕ = re.compile(rf"по {_ЧИСЛО} см вместе дают {_ЧИСЛО}"
                     rf"|of {_ЧИСЛО} cm each make {_ЧИСЛО}")


def _чис(s):
    return Decimal(s.replace(",", "."))


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # ГРАНИЦЫ ОБЯЗАНЫ ИДТИ ПО ВОЗРАСТАНИЮ И ОТСТОЯТЬ НА ЦЕНУ ДЕЛЕНИЯ.
    for г in _МЕЖДУ.findall(с):
        низ, верх = [x for x in г if x][:2]
        if _чис(низ) >= _чис(верх):
            return True, False
    for г in _ВМЕСТЕ.findall(с):
        один, сумма = [x for x in г if x][:2]
        if _чис(один) * 2 != _чис(сумма):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"между (\d+(?:,\d+)?) и", страница)
        if m:
            порча = (страница[:m.start(1)] + _ру(_чис(m.group(1)) + 100)
                     + страница[m.end(1):])
            if судить(порча)[1] is not False:
                беды.append(f"подменённая граница прошла в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    сч = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "счёт против измерения")
    порча = сч.replace("линейка", "линейк", 1)
    if порча == сч:
        беды.append("порча не состоялась: нет слова «линейка»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(сч + " " + сч)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ГЛАВНЫЙ РОД ОБЯЗАН НЕСТИ ОБА ЧИСЛА: длинное счётное и честное.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "деление не создаёт точности" or я != "ru":
            continue
        if "счёт даёт" not in с or "Честный ответ" not in с or "частное" not in с:
            беды.append(f"главный род без обоих чисел: {с[:80]}")
        break
    print(f"ИЗМЕРЕНИЕ И ТОЧНОСТЬ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


