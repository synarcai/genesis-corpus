# РОД «ДЕЛЕНИЕ ЗНАКОМ» ДЕРЖИТ ДВЕ РАМКИ ОДНОГО ЗАКОНА: деление минус-на-минус и минус-на-плюс
# суть одно правило, взятое обратным ходом от умножения, и разлучать их значило бы говорить, что
# у деления правил два.
_РАМКИ_ДЕЛЕНИЯ = ("деление знаком", "деление плюсом")
ПАРЫ = [(a, b) for a in range(2, 13) for b in range(2, 13) if (a + b) % 3 != 2]


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a, b in ПАРЫ:
            п = a * b
            вон[рамки["минус на плюс"].format(a=a, b=b, p=п, d=0)] = (язык, "минус на плюс")
            вон[рамки["минус на минус"].format(a=a, b=b, p=п, d=0)] = (язык, "минус на минус")
            # СПРОШЕННОЕ: тот же закон, поставленный ВОПРОСОМ О ЗНАКЕ, а не о величине.
            #
            #     МИР БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ ПОКАЗЫВАЕТ ОТВЕТ, НЕ ПОКАЗЫВАЯ ЗАДАЧИ.
            if (a + b) % 4 == 0:
                вон[рамки["спрошенное"].format(a=a, b=b, p=п, d=0)] = (язык, "спрошенное")
        for a, b in ПАРЫ[::2]:
            п = a * b
            for имя in _РАМКИ_ДЕЛЕНИЯ:
                вон[рамки[имя].format(a=a, b=b, p=п, d=0)] = (язык, "деление знаком")
        for a in range(2, 40):
            вон[рамки["лестница"].format(a=a, b=0, p=0, d=a * 2)] = (язык, "лестница")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ЗН = r"\(?−?\d+\)?"
_ПРОИЗВ = re.compile(rf"({_ЗН}) × ({_ЗН}) = (−?\d+)")
_ЧАСТНОЕ = re.compile(rf"({_ЗН}) ÷ ({_ЗН}) = (−?\d+)")


def _цел(с):
    return int(с.strip("()").replace("−", "-"))


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ СО ЗНАКОМ, СВЕРЕННЫЙ ЦЕЛИКОМ.
    for a, b, c in _ПРОИЗВ.findall(с):
        if _цел(a) * _цел(b) != _цел(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if _цел(b) == 0 or _цел(a) != _цел(b) * _цел(c):
            return True, False
    return True, True


def _порча_одним_словом(с):
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    мм = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "минус на минус")
    лс = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "лестница")
    if судить(мм.replace("минус на минус", "минус на мину"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(лс.replace("прибавляет", "прибавляе"))[1] is not False:
        беды.append("обрезанное слово в лестнице прошло")
    if судить(мм + " " + мм)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    if any("-" in с for с in ПОКАЗЫ):
        беды.append("ДЕФИС В ПОКАЗЕ: дом обязан писать знаком минус U+2212")
    # ЗНАК ОБЯЗАН ВХОДИТЬ В СЧЁТ: подмена итога на противоположный есть ложь.
    порча = мм.replace("= 12:", "= −12:", 1) if "= 12:" in мм else None
    if порча and судить(порча)[1] is not False:
        беды.append("ЗНАК ИТОГА НЕ СВЕРЕН: противоположный ответ прошёл")
    print(f"ПРАВИЛО ЗНАКОВ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


