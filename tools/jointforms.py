#!/usr/bin/env python3
"""ДОМ СОЧЛЕНЕНИЙ — слово между двумя числовыми фразами одной клаузы.

Повод (04.09, число 32). Рынок агрегатных списков покупает слово-сочленение
из квада; читатель же вправе прочесть его РАНЬШЕ всякой покупки — ПО
ПОЗИЦИИ: «слово, стоящее между двумя числовыми фразами одной клаузы, есть
сочленение по позиции» (М-162, роль узнаётся позицией, закон покупается
связями). Отсюда долг корпуса, и он именно корпусный: если в этой позиции
показано ОДНО слово, куплена будет не позиция, а слово. Сегодня во всём
своде там почти всегда «and» и шесть его переводов — то есть стенд, на
котором лексическую покупку не отличить от позиционной.

Дом показывает в одной и той же позиции ВЕЕР слов и, что важнее, ПУСТОТУ:

    ann has 5 apples and 3 pears.        ← слово
    ann has 5 apples plus 3 pears.       ← другое слово, та же роль
    ann has 5 apples, 3 pears and 2 plums.   ← запятая И слово в одной клаузе
    ann has 5 apples, 3 pears, 2 plums.      ← позиция БЕЗ слова вовсе

Третья строка — суд позиции: запятая и слово стоят в ОДНОЙ клаузе в ОДНОЙ
роли, и читатель, купивший слово, а не позицию, споткнётся на первой из них.
Четвёртая — предел: если сочленение читается позицией, то голый перечень
читается тоже, а если словом — не читается никак.

ВЕЩИ, ИМЕНА И СЛОВО ПРЕДМЕТА НЕ ОБЪЯВЛЯЮТСЯ ЗАНОВО. Они уже объявлены домом
страниц действия (`tools/actionpages.py`) со всеми формами счёта семи
языков, и дом сочленений читает их оттуда: два дома, один словарь. Своё у
него одно — рамка с ДЫРОЙ на месте сочленения и веер слов, которые в эту
дыру встают.

    python3 tools/jointforms.py    # самопроверка с мутантами
"""
