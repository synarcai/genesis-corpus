ФОРМЫ = ("две", "три", "голый")
# ГОЛАЯ ПОЗИЦИЯ СОЧЛЕНЕНИЯ НЕ ЕСТЬ СЛОВО, И ЕЁ НЕЛЬЗЯ ОБЪЯВИТЬ В ВЕЕРЕ:
# запятая стоит В РАМКЕ, а не в дыре, иначе рамка «{n1} {Т1} , {n2}» дала бы
# пробел перед запятой. Оттого форм три, а не одна с пустым словом.


def страница(язык, форма, X, товары, числа, сочленение=None):
    """Показ дома: одна клаузa с двумя-тремя числовыми фразами и её ответ."""
    я = ЯЗЫКИ[язык]
    лицо = A.ЛИЦА[язык][X]
    r = sum(числа)
    if len(числа) == 2:
        л = f"{числа[0]} + {числа[1]} = {r}."
    else:
        s = числа[0] + числа[1]
        л = f"{числа[0]} + {числа[1]} = {s}, {s} + {числа[2]} = {r}."
    поля = dict(X=лицо[0], Xр=лицо[2], r=r, л=л,
                ВЕЩ=A._предмет(язык, r), ВЕЩ2=A._предмет(язык, 5))
    for k, (т, n) in enumerate(zip(товары, числа), start=1):
        поля[f"n{k}"] = n
        поля[f"Т{k}"] = A._вещь(язык, т, n)
    if форма != "голый":
        поля["СЧ"] = сочленение
    return я[форма].format(**поля)


# --- сторона суда ---
def _дыры(язык):
    д = dict(A._дыры(язык))
    д["Т1"] = д["Т2"] = д["Т3"] = д["Тn"]
    д["n1"] = д["n2"] = д["n3"] = д["r"] = r"(\d+)"
    д["ВЕЩ"] = д["ВЕЩ2"] = A._альт(A._предмет(язык, n) for n in range(0, 400))
    д["СЧ"] = A._альт(ЯЗЫКИ[язык]["сочленения"])
    д["л"] = r"((?:\d+ [+−×÷] \d+ = \d+(?:, )?)+\.)"
    return д


def образцы(язык):
    д = _дыры(язык)
    return [(re.compile("^" + phrases.образец(ЯЗЫКИ[язык][ф], д) + "$"),
             phrases.порядок(ЯЗЫКИ[язык][ф]), ф) for ф in ФОРМЫ]


ОБРАЗЦЫ = {л: образцы(л) for л in ЯЗЫКИ}


def _индекс_вещи(язык, слово, n):
    """Индекс товара, чья форма при счёте n есть это слово."""
    for i in range(len(A.ЯЗЫКИ[язык]["вещи"])):
        if A._вещь(язык, i, n) == слово:
            return i
    return None


def разобрать(язык, строка):
    """Поля показа, прочитанные из строки, или None."""
    for образец, порядок, форма in ОБРАЗЦЫ[язык]:
        м = образец.match(строка)
        if not м:
            continue
        з = dict(zip(порядок, м.groups()))
        лица = A.ЛИЦА[язык]
        X = next((i for i, л in enumerate(лица)
                  if л[0] == з.get("X") or л[2] == з.get("Xр")), None)
        if X is None:
            continue
        сколько = 3 if форма != "две" else 2
        числа, товары = [], []
        for k in range(1, сколько + 1):
            n = int(з[f"n{k}"])
            i = _индекс_вещи(язык, з[f"Т{k}"], n)
            if i is None:
                break
            числа.append(n)
            товары.append(i)
        if len(числа) != сколько:
            continue
        return dict(форма=форма, X=X, товары=товары, числа=числа,
                    сочленение=з.get("СЧ"))
    return None


def судить(строка):
    """(судимо, истинно) — показ судится ПЕРЕПИСЫВАНИЕМ: прочитанные поля
    возвращаются в дом, и строка обязана совпасть с рождённой заново."""
    с = строка.strip()
    for язык in ЯЗЫКИ:
        п = разобрать(язык, с)
        if п is None:
            continue
        форма = п.pop("форма")
        try:
            return True, страница(язык, форма, **п) == с
        except (KeyError, IndexError, ValueError):
            return True, False
    return False, False


def _самопроверка():
    показы, мутанты = [], 0
    for язык in ЯЗЫКИ:
        для_языка = []
        for ф in ФОРМЫ:
            сч = ЯЗЫКИ[язык]["сочленения"][0] if ф != "голый" else None
            n = 2 if ф == "две" else 3
            с = страница(язык, ф, 0, tuple(range(n)), tuple(range(5, 5 + n)), сч)
            для_языка.append(с)
            судимо, истинно = судить(с)
            assert судимо and истинно, (язык, ф, с)
        показы += для_языка
        # МУТАНТ: подменённый ИТОГ КУЗНИЦЫ обязан быть назван ложью. Портится
        # последнее число леджера — оно есть у всякого языка, а слово ответа
        # стоит у каждого по-своему («11 things:», «11 choses :»), и мутант,
        # цепляющийся за него, молчал бы на французском.
        битая = re.sub(r"= (\d+)\.$", lambda м: f"= {int(м.group(1)) + 1}.", для_языка[0])
        assert битая != для_языка[0], (язык, для_языка[0])
        судимо, истинно = судить(битая)
        assert судимо and not истинно, (язык, битая)
        мутанты += 1
        # МУТАНТ: чужое сочленение (не объявленное веером) не судится вовсе
        чужое = для_языка[0].replace(f" {ЯЗЫКИ[язык]['сочленения'][0]} ", " xor ", 1)
        assert not судить(чужое)[0], (язык, чужое)
        мутанты += 1
    for с in показы[:3]:
        print("  ", с[:110])
    print(f"  мутантов поймано: {мутанты}")
    сколько = sum(len(ЯЗЫКИ[л]["сочленения"]) * 2 + 1 for л in ЯЗЫКИ)
    print(f"  дом пишет рамок: {сколько} (языков {len(ЯЗЫКИ)}, форм {len(ФОРМЫ)})")


if __name__ == "__main__":
    _самопроверка()
