ФОРМЫ = ("две", "три", "голый")

# РОДЫ ЕСТЬ ФОРМЫ — И ЭТО НЕ ПОВТОР, А РАЗРЕШЕНИЕ ДВУСМЫСЛЕННОСТИ (13.09). Дом кует страницу
# ПО ЗАПРОСУ и словаря страниц не держит, оттого указатель родов не может доказать делом, что
# `ФОРМЫ` здесь суть роды показа: слово это в корпусе перегружено — у `units` это единицы
# времени, у `parity` и `coprime` языки. Сказать может только дом, и говорит он младшим,
# однозначным словом.
#
#     СЛОВО, ЗНАЧАЩЕЕ У СОСЕДЕЙ РАЗНОЕ, ТРЕБУЕТ ОТ ДОМА ВТОРОГО СЛОВА, А НЕ ОТ ЧИТАТЕЛЯ —
#     ДОГАДКИ. Указатель, зовущий кузницу ради проверки, перестаёт быть указателем.
