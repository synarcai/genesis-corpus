"""СЕМЕНА ТАЙСКОГО И СУАХИЛИ — три пробы, каких у движка не было.

Оба языка легли рядом с прежними тринадцатью, и каждый принёс свою
беду. Беды эти не о словах, а о СТРОЕНИИ ПАКЕТА; здесь они объявлены
честно, а чего движок не умеет — сказано, а не обойдено.

ПРОБА ПЕРВАЯ: ПИСЬМО, ГДЕ ПРОБЕЛ ЕСТЬ, НО НЕ МЕЖДУ СЛОВАМИ. Китайский
не ставит пробелов вовсе, латиница ставит их между словами; тайский
делает ТРЕТЬЕ — пишет слова слитно, а пробелом отделяет предложения и
обороты. Движок знал два случая («есть пробел» и «нет пробела»), и
третий должен был бы упасть между ними.

    ОН НЕ УПАЛ, И ЭТО НАХОДКА В ПОЛЬЗУ АРХИТЕКТУРЫ. Объявление
    `segmentation: longest-match` говорит не «пробелов нет», а «режь по
    объявленному словарю»; сегментатор пробел ПРОПУСКАЕТ, а не требует.
    Потому смешанное письмо разбирается тем же объявлением, каким живёт
    китайский, — поле оказалось шире случая, ради которого написано.
    Граница у этого всё же есть, и она названа ниже.

ПРОБА ВТОРАЯ: ГЛАСНАЯ, НАПИСАННАЯ ДО СОГЛАСНОЙ. Тайское «เก» читается
«ке»: знак «เ» стоит ПЕРВЫМ и звучит ВТОРЫМ, а тоны пишутся НАД
согласной. Поле `graphemes` есть плоское множество знаков, и сказать в
нём о ПОРЯДКЕ — что этот знак пишется слева, а звучит справа, что тот
не буква, а тон над буквой, — нечем. Инвентарь проходит (знаки живут в
пласте), но утверждение «письмо объявлено» здесь слабее, чем кажется:
объявлены ЗНАКИ, а не письмо.

ПРОБА ТРЕТЬЯ, И ГЛАВНАЯ: СОГЛАСОВАНИЕ, ИДУЩЕЕ В ДРУГУЮ СТОРОНУ. У
суахили около пятнадцати ИМЕННЫХ КЛАССОВ, и класс имени управляет
ПРИСТАВКОЙ у числительного, прилагательного и глагола: «kitabu
kimoja», но «mtu mmoja» — одно и то же «один» меняет НАЧАЛО слова по
классу имени.

    НАШ `count_agreement` СПРАШИВАЕТ ОБРАТНОЕ: какую форму принимает
    ИМЯ при числе. Здесь имя не меняется вовсе — меняется ЧИСЛИТЕЛЬНОЕ
    при имени, и поля для этого нет ни одного. Класс имени объявить
    негде; согласование зависимого слова объявить негде; и правило
    («класс 7 даёт ki-, класс 2 даёт wa-») не выразимо, ибо `verb_rule`
    умеет только ОСНОВА + ОКОНЧАНИЕ, а здесь приставка.

    Явление ПОКАЗАНО — целыми оборотами в собственной парадигме имени,
    как японские счётные слова, — и потому организм его увидит. Но
    движком оно НЕ СУДИМО: пакет с «kitabu wamoja» пройдёт все девять
    полей. Это не подгон и не дыра в языке: это дыра в движке, и она
    названа числом в отчёте.

ЧЕГО ДВИЖОК НАВЯЗАЛ ОБОИМ. Кузня пишет два рода показов ЖЁСТКИМ
шаблоном — «{лицо} {глагол}.» и «{число} {знак} {число} {равно}
{число}.» — с пробелами и латинской точкой. Суахили пишет и то и
другое, и ему всё равно; тайский не пишет ни пробелов внутри
предложения, ни точки в конце, и эти два рода выходят у него с чужой
разметкой. Свои роды (счёт предметов, определение, согласование,
отказы) написаны здесь по-тайски. Подгонять язык под кузню запрещено,
и он не подогнан — испорченное названо.

ЛИЦА У ТАЙСКОГО НЕТ ВОВСЕ: ผมอ่าน и พวกเขาอ่าน — одна форма глагола.
Шесть клеток кузни заполнены ею одной, как у японского и корейского, и
это строение языка, а не бедность пакета.

ЯРУС ПЕРВЫЙ ОБОИМ: строение зелено, формы не проверены носителем.
"""

import re

# ПОЛЯ, НЕСУЩИЕ ЯЗЫК, а не служебное имя. Инвентарь знаков собирается
# ровно из них: `comment` написан по-английски, `adj_cells` — латинские
# имена клеток, и попади они в инвентарь, пакет заявил бы знаки,
# которых сам не пишет.
ЯЗЫКОВЫЕ_ПОЛЯ = ("numerals", "ops", "persons", "verbs", "nouns",
                 "adjs", "adj_lexicon", "adj_templates", "words",
                 "irregulars", "refusals")
# Поля, где КЛЮЧ есть слово языка (а не имя поля): у остальных берутся
# только значения.
СЛОВАРНЫЕ = frozenset({"ops", "verbs", "nouns", "adjs"})


def знаки(семя):
    """Инвентарь письма, ВЫВЕДЕННЫЙ из объявленного, а не написанный.

    `graphemes` есть утверждение «каждый из этих знаков прожит в пласте
    не реже двух раз». Написанный рукой, он расходится со словарём в
    день первой правки; собранный ОБХОДОМ СЕМЕНИ, он не может отстать —
    поле, добавленное завтра, попадёт в инвентарь само, если названо
    языковым. (Соседнее семя востока перечисляет источники по одному, и
    забытое поле выпало бы из инвентаря молча.)

    Дыра шаблона в инвентарь не идёт: «{lex:adj_forms:plain}» написано
    латиницей и в пласт не попадает ни разу.
    """
    куски = []

    def собрать(значение, брать_ключи):
        if isinstance(значение, dict):
            for ключ, вложенное in значение.items():
                # ПРИЧИНА ОТКАЗА — ИМЯ РОДА, А НЕ СЛОВО ЯЗЫКА:
                # «agreement» пишется латиницей в любом пакете.
                if ключ == "reason":
                    continue
                if брать_ключи:
                    куски.append(str(ключ))
                собрать(вложенное, False)
        elif isinstance(значение, (list, tuple)):
            for вложенное in значение:
                собрать(вложенное, брать_ключи)
        elif значение is not None:
            куски.append(str(значение))

    for поле in ЯЗЫКОВЫЕ_ПОЛЯ:
        собрать(семя.get(поле), поле in СЛОВАРНЫЕ)
    вон = set()
    for кусок in куски:
        for знак in re.sub(r"\{[^}]*\}", "", кусок):
            if знак.isalpha():
                вон.add(знак)
    return "".join(sorted(вон))


