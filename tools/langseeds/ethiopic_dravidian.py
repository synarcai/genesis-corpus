СЛОВАРНЫЕ = frozenset({"ops"})


def знаки(семя):
    """Инвентарь письма, ВЫВЕДЕННЫЙ из объявленного, а не написанный.

    `graphemes` есть утверждение «каждый из этих знаков прожит в пласте
    не реже двух раз». Написанный рукой, он расходится со словарём в
    день первой правки; собранный обходом семени, он не может отстать.

    МЕТКА СЧИТАЕТСЯ ЗНАКОМ ПИСЬМА НАРАВНЕ С БУКВОЙ — тем же законом,
    каким её читает сегментатор. Значок гласной абугиды не есть `alpha`
    по Юникоду, но письмо без него не письмо: тамильское «பா» без «ா»
    читается другим слогом. Движок считает графемой ОТДЕЛЬНЫЙ КОДОВЫЙ
    ЗНАК (`body.count(g)`), и значок при согласной — такой же знак, как
    согласная.

    ЭТОТ ЗАКОН ЖИВЁТ ТЕПЕРЬ В ТРЁХ СЕМЕНАХ (восточном, тайском и
    здесь), и это долг: место ему в кузне, которая собирала бы
    инвентарь всякому семени, не объявившему его руками. Кузню мне
    править не поручено, и потому долг назван, а не спрятан.
    """
    куски = []

    def собрать(значение, брать_ключи):
        if isinstance(значение, dict):
            for ключ, вложенное in значение.items():
                # ПРИЧИНА ОТКАЗА — ИМЯ РОДА, А НЕ СЛОВО ЯЗЫКА.
                if ключ == "reason":
                    continue
                if брать_ключи:
                    куски.append(str(ключ))
                собрать(вложенное, False)
        elif isinstance(значение, (list, tuple)):
            for вложенное in значение:
                собрать(вложенное, брать_ключи)
        elif значение is not None:
            куски.append(str(значение))

    for поле in ЯЗЫКОВЫЕ_ПОЛЯ:
        собрать(семя.get(поле), поле in СЛОВАРНЫЕ)
    вон = set()
    for кусок in куски:
        for знак in re.sub(r"\{[^}]*\}", "", кусок):
            if знак.isalpha() or unicodedata.category(знак).startswith("M"):
                вон.add(знак)
    return "".join(sorted(вон))


def метки(строка):
    """Комбинирующие метки инвентаря — для поля `diacritics`."""
    return "".join(з for з in строка
                   if unicodedata.category(з).startswith("M"))


