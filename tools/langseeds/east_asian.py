import re


def _знаки(*строки):
    """Буквенные знаки всего сказанного — ИНВЕНТАРЬ ВЫВОДИТСЯ, НЕ ПИШЕТСЯ.

    `graphemes` есть утверждение «каждый из этих знаков прожит в пласте
    не реже двух раз», и писать его рукой значит писать список, который
    завтра разойдётся со словарём. Здесь он СОБИРАЕТСЯ из того же, из
    чего собран пакет: из форм лексем, из числительных, из слов
    действий и из постоянного текста шаблонов. Знак, попавший в пласт,
    попал и сюда; знак, выпавший из словаря, выпадет и отсюда.

    Небуквенное (。、 точка, пробел, цифры, скобка отказа) в инвентарь
    не идёт: это знаки препинания, а не письмо, и требовать от них
    двойной жизни значило бы мерить не то.
    """
    вон = set()
    for строка in строки:
        # ДЫРА ШАБЛОНА НЕ ЕСТЬ ТЕКСТ ЯЗЫКА. «{lex:adj_forms:plain}»
        # написано латиницей и в пласт не попадает ни разу; собрав его
        # буквы в инвентарь, пакет заявил бы девятнадцать знаков,
        # которых сам не пишет, — и был бы честно уличён судом графем.
        # Первый прогон уличил.
        for знак in re.sub(r"\{[^}]*\}", "", str(строка)):
            if знак.isalpha():
                вон.add(знак)
    return "".join(sorted(вон))


def _всё(семя, *ещё):
    """Все строки семени, из которых собирается инвентарь знаков."""
    куски = list(ещё)
    куски += list(семя["numerals"].values())
    куски += list(семя["ops"])
    куски += семя["persons"]
    for формы in семя["verbs"].values():
        куски += формы
    for формы in семя["nouns"].values():
        куски += формы
    for формы in семя.get("adjs", {}).values():
        куски += формы
    сл = семя["words"]
    куски += сл["count_lexicon"] + сл["count_templates"]
    куски += сл["def_lexicon"] + сл["def_templates"]
    куски += семя.get("adj_lexicon", []) + семя.get("adj_templates", [])
    for пара in семя["refusals"]:
        куски += [пара["bad"], пара["good"]]
    return куски


