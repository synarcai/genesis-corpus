# СЛОВАРЬ СТРАНИЦ ДОМА МЕРНОЙ ИСТОРИИ (13.09, шестой переезд того же вида). Две двери —
# `мера` и `пара`, — и род у обеих стои́т переменной `форма` прямо над вызовом.
#
#     ДОМ, НЕ ЗНАЮЩИЙ СВОИХ СТРАНИЦ, НЕ МОЖЕТ НАЗВАТЬ ИХ РОДА.
def перебор(шаг, язык):
    я = ЯЗЫКИ[язык]
    вон = []
    for г in range(len(я["глаголы"])):
        свои, меры = я["кто"][г], я["меры_глагола"][г]
        for i in range(6):
            д = свои[(шаг * 3 + г * 2 + i) % len(свои)]
            второй = свои[(свои.index(д) + 1 + i % (len(свои) - 1)) % len(свои)]
            a, b = ПАРЫ_МЕРЫ[(шаг * 5 + г * 3 + i) % len(ПАРЫ_МЕРЫ)]
            for форма in ("мера_больше", "мера_меньше"):
                вон.append((мера(язык, форма, a, b, м=меры[(шаг + г + i) % len(меры)],
                                 г=г, деятель=д, второй=второй), форма))
    for k in МНОЖИТЕЛИ:
        for i in range(6):
            товар = (шаг + k + i) % len(я["товары"])
            основание = ОСНОВАНИЯ_ЦЕНЫ[(шаг * 3 + k * 2 + i) % len(ОСНОВАНИЯ_ЦЕНЫ)]
            for форма in ("пара_мал", "пара_бол"):
                вон.append((пара(язык, форма, товар=товар, k=k, основание=основание), форма))
    # СРАВНЕНИЕ ПУТИ (24.09): на всякий глагол — по три эпизода на форму за проход; слово пути идёт по
    # кругу своего глагола, и всякое слово за пять проходов стоит в четвёрке не менее LAW² раз
    for г in range(len(я["глаголы"])):
        свои, меры, слова = я["кто"][г], я["меры_глагола"][г], я["сравнения"][г]
        for i in range(3):
            д = свои[(шаг * 5 + г + i * 2) % len(свои)]
            второй = свои[(свои.index(д) + 1 + (шаг + i) % (len(свои) - 1)) % len(свои)]
            for j, форма in enumerate(СРАВНЕНИЯ):
                a, b = ПАРЫ_МЕРЫ[(шаг * 3 + г * 5 + i * 2 + j) % len(ПАРЫ_МЕРЫ)]
                вон.append((сравнение(язык, форма, a, b, м=меры[(шаг + г + i + j) % len(меры)], г=г,
                                      деятель=д, второй=второй, ср=(шаг + i + j) % len(слова)), форма))
    return вон


