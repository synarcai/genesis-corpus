def счётная(формы, n):
    """The declared form of a unit beside its count (two forms or three)."""
    if len(формы) == 2:
        return формы[0] if n == 1 else формы[1]
    if n % 100 in range(11, 15):
        return формы[2]
    последняя = n % 10
    if последняя == 1:
        return формы[0]
    if последняя in (2, 3, 4):
        return формы[1]
    return формы[2]


def _глагол(язык, г, деятель):
    """Прошедшее время: русское согласуется с деятелем в роде."""
    формы = ЯЗЫКИ[язык]["глаголы"][г]
    if язык != "ru":
        return формы[0]
    _, род = ЯЗЫКИ[язык]["деятели"][деятель]
    return формы[0] if род == "m" else формы[1]


def мера(язык, форма, a, b, м=0, г=0, деятель=0, второй=1):
    """«the horse ran 51 metres. the fox ran 19 metres. how many more metres did the horse run
    than the fox? 51 − 19 = 32.» — деятели и мера обязаны быть глагола."""
    я = ЯЗЫКИ[язык]
    if деятель == второй or a <= b:
        raise ValueError("нужны разные деятели и положительная разность")
    if деятель not in я["кто"][г] or второй not in я["кто"][г]:
        raise ValueError("деятель не глагола: глагол берёт своего деятеля")
    if м not in я["меры_глагола"][г]:
        raise ValueError("мера не глагола")
    A, B = я["деятели"][деятель][0], я["деятели"][второй][0]
    формы = я["меры"][м]
    з = dict(A=A, B=B, МЕРА=счётная(формы, 2), МЕРАМ=счётная(формы, 5))
    пр = я["глаголы"][г][2] if len(я["глаголы"][г]) > 2 else ""
    факт = (я["мера_утв"].format(**з, Гп=_глагол(язык, г, деятель), ПР=пр, n=a, МЕРАn=счётная(формы, a))
            + " " + я["мера_утв"].format(**dict(з, A=B), Гп=_глагол(язык, г, второй), ПР=пр, n=b, МЕРАn=счётная(формы, b)))
    воп = я["мера_воп_больше" if форма == "мера_больше" else "мера_воп_меньше"].format(
        **з, Гб=я["глаголы"][г][1] if язык == "en" else "",
        Гп=_глагол(язык, г, деятель), Гв=_глагол(язык, г, второй))
    return f"{факт} {воп} {a} − {b} = {a - b}. {я['ответ'].format(r=a - b)}"


def пара(язык, форма, товар=0, k=2, основание=30):
    """«a tent and a lantern cost 100 dollars together. the tent costs three times as much as
    the lantern. how much does the lantern cost? 3 + 1 = 4, 100 ÷ 4 = 25.»"""
    я = ЯЗЫКИ[язык]
    Б1, Б2, М1, М2 = я["товары"][товар]
    S = (k + 1) * основание
    з = dict(Б1=Б1, Б2=Б2, М1=М1, М2=М2, S=S, K=я["кратные"][k],
             ДЕНЬГИ=счётная(я["деньги"], S))
    факт = я["пара_утв"].format(**з)
    if форма == "пара_мал":
        r = основание
        леджер = f"{k} + 1 = {k + 1}, {S} ÷ {k + 1} = {r}."
        воп = я["пара_воп_мал"].format(**з)
    else:
        r = k * основание
        леджер = f"{k} + 1 = {k + 1}, {S} ÷ {k + 1} = {основание}, {k} × {основание} = {r}."
        воп = я["пара_воп_бол"].format(**з)
    return f"{факт} {воп} {леджер} {я['ответ'].format(r=r)}"


def сравнение(язык, форма, a, b, м=0, г=0, деятель=0, второй=1, ср=0):
    """«the fox ran 19 metres. the horse ran 32 metres farther than the fox. how far did the horse
    run? the horse ran 51 metres: 19 + 32 = 51.» — ОПОРА ДО СРАВНЕНИЯ, СРАВНИВАЕМОЕ ПОСЛЕ.

    Деятель — больший (a), второй — меньший (b), разность d = a − b. «сравнение_дальше» даёт опору
    меньшего и спрашивает большего; «сравнение_меньше» — наоборот, словом «less»; «насколько_дальше»
    даёт обоих и спрашивает разность словом пути. Слово пути — глагола (`сравнения`), как и мера."""
    я = ЯЗЫКИ[язык]
    if деятель == второй or a <= b:
        raise ValueError("нужны разные деятели и положительная разность")
    if деятель not in я["кто"][г] or второй not in я["кто"][г]:
        raise ValueError("деятель не глагола: глагол берёт своего деятеля")
    if м not in я["меры_глагола"][г]:
        raise ValueError("мера не глагола")
    СР = я["сравнения"][г][ср]
    A, B = я["деятели"][деятель][0], я["деятели"][второй][0]
    формы, d = я["меры"][м], a - b
    пр = я["глаголы"][г][2] if len(я["глаголы"][г]) > 2 else ""
    з = dict(A=A, B=B, a=a, b=b, d=d, СР=СР, ВОПР=я["вопрос_сравнения"][СР], ПР=пр,
             МЕРАa=счётная(формы, a), МЕРАb=счётная(формы, b), МЕРАd=счётная(формы, d),
             МЕРАМ=счётная(формы, 5), Гб=я["глаголы"][г][1] if язык == "en" else "")
    ГпA, ГпB = _глагол(язык, г, деятель), _глагол(язык, г, второй)
    факт_a = я["мера_утв"].format(A=A, Гп=ГпA, ПР=пр, n=a, МЕРАn=з["МЕРАa"])
    факт_b = я["мера_утв"].format(A=B, Гп=ГпB, ПР=пр, n=b, МЕРАn=з["МЕРАb"])
    if форма == "сравнение_дальше":
        return " ".join((факт_b, я["сравн_утв"].format(**з, Гп=ГпA), я["сравн_воп"].format(**з, Гп=ГпA),
                         я["сравн_ответ"].format(**з, Гп=ГпA)))
    if форма == "сравнение_меньше":
        return " ".join((факт_a, я["меньше_утв"].format(**з, Гп=ГпB), я["меньше_воп"].format(**з, Гп=ГпB),
                         я["меньше_ответ"].format(**з, Гп=ГпB)))
    if форма == "насколько_дальше":
        return " ".join((факт_a, факт_b, я["насколько_воп"].format(**з, Гп=ГпA),
                         я["насколько_ответ"].format(**з)))
    raise ValueError(f"форма не сравнения: {форма}")


def _альт(слова):
    return "(?:" + "|".join(re.escape(с) for с in sorted(set(слова), key=lambda с: (-len(с), с))) + ")"


