    я = ЯЗЫКИ["en"]
    прыжок = next(г for г, сс in enumerate(я["сравнения"]) if len(сс) > 2)
    бег = next(г for г, сс in enumerate(я["сравнения"]) if я["сравнения"][прыжок][-1] not in сс)
    слово = я["сравнения"][прыжок][-1]
    с = сравнение("en", "сравнение_дальше", a0, b0, м=0, г=бег, деятель=КТО[бег][0], второй=КТО[бег][1])
    вон.append(("слово пути не глагола", с, с.replace(f" {я['сравнения'][бег][0]} than ", f" {слово} than ")
                .replace(f"how {я['вопрос_сравнения'][я['сравнения'][бег][0]]} ",
                         f"how {я['вопрос_сравнения'][слово]} ")))
    for род, с, битая in вон:
        assert битая != с, (род, с)
    return [(род, битая) for род, _, битая in вон]


