#!/usr/bin/env python3
"""ПОЛНЫЙ МИКС GENESIS: один дом вместо снимков по рукам.

Полный корпус собирался всякий раз заново и всякий раз чужой рукой:
у одной сессии лежал `genesis_full5.txt` от тридцать первого августа,
у другой — склейка `datasets/*` вслепую, вместе с прозаическими сводами,
которым в лестнице не место, и со старыми снимками. Два хозяина одного
вопроса расходятся в первый же день — этот шрам мы сегодня уже платили
списком судов, жившим сразу в палате и в приборе судимости.

ЗДЕСЬ ПОЛНЫЙ МИКС ЕСТЬ СЛЕДСТВИЕ МАНИФЕСТА, А НЕ РЕШЕНИЕ СОБИРАЮЩЕГО.
Входят ровно те миры, у кого `text == "shows"`, в порядке манифеста,
сшитые тем же швом, каким сшиты проходы внутри слоя. Прибавился мир —
прибавился сам; выбыл — выбыл сам. Собирающему нечего решать, и потому
нечему разойтись.

МИКС НЕ ЕСТЬ МИР. Он объявлен в манифесте как `text: "mix"`, и меры
корпуса его не считают: строка, посчитанная дважды, удваивает и охват,
и ложь, а мера, которую можно раздуть повтором, не мера.
"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import genesis  # noqa: E402
from layer import SEAM  # noqa: E402

ЦЕЛЬ = "datasets/GENESIS-FULL.txt"


def собрать():
    """(тело, [(имя мира, строк)]) — миры показов в порядке манифеста."""
    куски, перепись = [], []
    for мир in genesis.manifest()["worlds"]:
        if мир.get("text") != "shows":
            continue
        путь = genesis._resolve(мир["file"])
        if not путь.is_file():
            continue
        тело = путь.read_text(encoding="utf-8").strip("\n")
        if not тело:
            continue
        куски.append(тело)
        перепись.append((мир["name"],
                         sum(1 for с in тело.splitlines() if с.strip())))
    return SEAM.join(куски) + "\n", перепись


def main():
    тело, перепись = собрать()
    путь = genesis._resolve(ЦЕЛЬ)
    путь.write_text(тело, encoding="utf-8")
    строк = sum(n for _и, n in перепись)
    print(f"written {ЦЕЛЬ}: {len(тело.encode('utf-8'))} bytes, "
          f"{строк} lines, {len(перепись)} worlds")
    return 0


if __name__ == "__main__":
    sys.exit(main())
