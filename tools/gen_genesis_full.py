#!/usr/bin/env python3
"""ПОЛНЫЙ МИКС GENESIS: один дом вместо снимков по рукам.

Полный корпус собирался всякий раз заново и всякий раз чужой рукой:
у одной сессии лежал `genesis_full5.txt` от тридцать первого августа,
у другой — склейка `datasets/*` вслепую, вместе с прозаическими сводами,
которым в лестнице не место, и со старыми снимками. Два хозяина одного
вопроса расходятся в первый же день — этот шрам мы сегодня уже платили
списком судов, жившим сразу в палате и в приборе судимости.

ЗДЕСЬ ПОЛНЫЙ МИКС ЕСТЬ СЛЕДСТВИЕ МАНИФЕСТА, А НЕ РЕШЕНИЕ СОБИРАЮЩЕГО.
Входят ровно те миры, у кого `text == "shows"`, в порядке манифеста,
сшитые тем же швом, каким сшиты проходы внутри слоя. Прибавился мир —
прибавился сам; выбыл — выбыл сам. Собирающему нечего решать, и потому
нечему разойтись.

МИКС НЕ ЕСТЬ МИР. Он объявлен в манифесте как `text: "mix"`, и меры
корпуса его не считают: строка, посчитанная дважды, удваивает и охват,
и ложь, а мера, которую можно раздуть повтором, не мера.
"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import genesis  # noqa: E402
from layer import SEAM  # noqa: E402

ЦЕЛЬ = "datasets/GENESIS-FULL.txt"
# СБОРКА ОБЪЯВЛЯЕТСЯ МАНИФЕСТОМ, А НЕ СПИСКОМ ЗДЕСЬ. Мир входит в
# сборку, если несёт её имя в поле `assemblies`; полный микс берёт
# ВСЕ миры показов и потому имени не спрашивает. Так у всякой сборки
# один хозяин — манифест, — и всякий, кому нужна школьная лестница,
# цитирует сборку, а не склеивает файлы своей рукой.
СБОРКИ = {"full": None, "school": "school"}


def собрать(сборка="full", семя=None):
    """(тело, [(имя мира, строк)]) — миры сборки в порядке манифеста.

    ПЕРЕСТАНОВКА — ТОТ ЖЕ СВОД В ДРУГОМ ПОРЯДКЕ МИРОВ. Семя объявлено
    вызывающим и печатается сборщиком; множество строк не меняется ни
    на одну (сборщик сверяет это отпечатком отсортированных строк). Так
    проверяется независимость выученного от ПРЕДСТАВЛЕНИЯ: схема,
    сваренная из двух порядков, обязана совпасть отпечатком, иначе
    организм учил порядок файла, а не язык.
    """
    имя_сборки = СБОРКИ.get(сборка, сборка)
    куски, перепись = [], []
    for мир in genesis.manifest()["worlds"]:
        if мир.get("text") != "shows":
            continue
        if имя_сборки is not None and имя_сборки not in (
                мир.get("assemblies") or ()):
            continue
        путь = genesis._resolve(мир["file"])
        if not путь.is_file():
            continue
        тело = путь.read_text(encoding="utf-8").strip("\n")
        if not тело:
            continue
        куски.append(тело)
        перепись.append((мир["name"],
                         sum(1 for с in тело.splitlines() if с.strip())))
    if семя is not None:
        import random
        порядок = list(range(len(куски)))
        random.Random(семя).shuffle(порядок)
        куски = [куски[i] for i in порядок]
        перепись = [перепись[i] for i in порядок]
    return SEAM.join(куски) + "\n", перепись


ШКОЛА = "datasets/GENESIS-SCHOOL.txt"
ПЕРЕСТАНОВКА = "datasets/GENESIS-SCHOOL-PERMUTED.txt"


def отпечаток_множества(тело):
    """sha256 ОТСОРТИРОВАННЫХ строк — порядок не входит в отпечаток."""
    import hashlib
    строки = sorted(с for с in тело.splitlines() if с.strip())
    return hashlib.sha256("\n".join(строки).encode("utf-8")).hexdigest()


def переставить(семя):
    """Записать школьную сборку в порядке миров, заданном семенем.

    Не пересобирает SCHOOL: поставочный срез лежит и не трогается.
    Отпечаток множества строк обязан совпасть с лежащим срезом — иначе
    миры изменились с последней сборки, и перестановка сравнивала бы
    два разных свода.
    """
    тело, перепись = собрать("school", семя)
    лежит = genesis._resolve(ШКОЛА).read_text(encoding="utf-8")
    свой, чужой = отпечаток_множества(тело), отпечаток_множества(лежит)
    if свой != чужой:
        print(f"ПЕРЕСТАНОВКА ОТКАЗ: множество строк не совпадает с "
              f"{ШКОЛА} — миры менялись после сборки; сперва соберите")
        return 2
    путь = genesis._resolve(ПЕРЕСТАНОВКА)
    путь.write_text(тело, encoding="utf-8")
    print(f"written {ПЕРЕСТАНОВКА}: {len(тело.encode('utf-8'))} bytes, "
          f"{sum(n for _и, n in перепись)} lines, {len(перепись)} worlds, "
          f"семя {семя}, отпечаток множества строк {свой[:16]} = "
          f"{ШКОЛА}; первые миры: "
          + ", ".join(и for и, _n in перепись[:4]))
    return 0


def записать_размер(цель, байт, строк):
    """Вписать НАСТОЯЩИЙ размер сборки в её узел манифеста.

    Поле `size` стояло обещанием, которого никто не сверял, — и сосед,
    варивший канон по манифесту, взял старое число и потерял хвост.
    Объявление, которого не сверяют, есть та же дыра, что мера, которой
    нет: обещание неотличимо от факта, пока не спросят. Свод вписывает
    факт при каждой сборке, а суд манифеста роняет расхождение.
    """
    import collections
    import json
    путь = genesis.MANIFEST
    м = json.loads(путь.read_text(encoding="utf-8"),
                   object_pairs_hook=collections.OrderedDict)
    тронуто = False
    for мир in м["worlds"]:
        if мир.get("file") != цель:
            continue
        if мир.get("size") != байт or мир.get("lines") != строк:
            мир["size"], мир["lines"] = байт, строк
            тронуто = True
    if тронуто:
        путь.write_text(json.dumps(м, ensure_ascii=False, indent=2)
                        + "\n", encoding="utf-8")


def main():
    if "--permute" in sys.argv:
        где = sys.argv.index("--permute")
        семя = int(sys.argv[где + 1]) if где + 1 < len(sys.argv) else 1
        return переставить(семя)
    for сборка, цель in (("full", ЦЕЛЬ), ("school", ШКОЛА)):
        тело, перепись = собрать(сборка)
        if not перепись:
            print(f"СБОРКА ОТКАЗ: {сборка} пуста — ни один мир не "
                  f"объявил её в поле assemblies")
            return 2
        путь = genesis._resolve(цель)
        путь.write_text(тело, encoding="utf-8")
        строк = sum(n for _и, n in перепись)
        байт = len(тело.encode("utf-8"))
        записать_размер(цель, байт, строк)
        print(f"written {цель}: {байт} bytes, "
              f"{строк} lines, {len(перепись)} worlds")
    return 0


if __name__ == "__main__":
    sys.exit(main())
