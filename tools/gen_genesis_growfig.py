#!/usr/bin/env python3
"""GENESIS layer: РОСТ ФИГУРЫ — see tools/growfigforms.py for the law.

ТРИ ЗАКОНА РОСТА ИДУТ ОДНОЙ ГРУППОЙ: сторона, площадь и объём растут линейно, квадратично и
кубически, и врозь они читались бы как три отдельных правила вместо одного, взятого при трёх
степенях.

    ДВЕ ВЕЛИЧИНЫ ОДНОЙ ФИГУРЫ РАСТУТ ПО РАЗНЫМ ЗАКОНАМ, И ЗНАТЬ ОДИН ЗНАЧИТ НЕ ЗНАТЬ ДРУГОГО.

ДВЕ НЕЗАВИСИМОСТИ — ВМЕСТЕ: «периметр не определяет площади» и «площадь не определяет
периметра» суть одно незнание, взятое с двух концов. ПЕРЕБОР отдельно: он есть ДОКАЗАТЕЛЬСТВО
счётом, а не ещё один случай. ВОПРОС отдельно.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import growfigforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_growfig.txt"
ГРУППЫ = (("сторона и площадь", "сторона и периметр", "сторона и объём"),
          ("тот же периметр", "та же площадь"),
          ("квадрат наибольший", "почему так"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
