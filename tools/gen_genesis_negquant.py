#!/usr/bin/env python3
"""GENESIS layer: ОТРИЦАНИЕ КВАНТОРА — see tools/negquantforms.py for the law.

РАЗЛИЧИЕ СТОИ́Т ПЕРВЫМ И ОТДЕЛЬНО: «не все» против «все не» есть то, ради чего дом
построен, и соседство с равносильностями разбавило бы его. Три вида мешка — смешанный,
пустой, полный — идут в одной группе нарочно: врозь читатель увидел бы лишь совпадения
либо лишь расхождение, а предмет есть ИХ РАЗНИЦА.

ТРИ РАВНОСИЛЬНОСТИ — второй группой: все три об одном приёме (отрицание переносится
внутрь, меняя квантор на противоположный), и порознь они читались бы как три правила.

ВОПРОС отдельно — ответ рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import negquantforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_negquant.txt"
ГРУППЫ = (("не все против все не",),
          ("отрицание всеобщего", "отрицание существования", "двойное отрицание"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
