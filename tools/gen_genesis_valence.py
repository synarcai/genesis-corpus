ВВЕРХ = ("стало лучше", "better", "спокойно", "calm",
         "не страшно", "not afraid")
ВНИЗ = ("стало хуже", "worse", "страшно", "afraid", "тревожно")


def полярность(показ):
    """+1, −1 или 0 — знак урока, читаемый из самого показа."""
    if any(с in показ for с in ("не страшно", "not afraid")):
        return 1
    if any(с in показ for с in ВНИЗ):
        return -1
    if any(с in показ for с in ВВЕРХ):
        return 1
    return 0


def чередуя(показы):
    """Полярность по чётности индекса, длина чётная.

    Нейтральные показы не мешают: они кладутся в хвост, где чередование
    уже нечего беречь.
    """
    вверх = [п for п in показы if полярность(п) > 0]
    вниз = [п for п in показы if полярность(п) < 0]
    нейтраль = [п for п in показы if полярность(п) == 0]
    # ИЗБЫТОК ОДНОЙ ПОЛЯРНОСТИ УХОДИТ В ХВОСТ, А НЕ ЛОЖИТСЯ ПОДРЯД:
    # приписанный к концу, он даёт ровно ту череду одинаковых уроков,
    # которую детектор события читает нейтралью. Лучше честно вынести
    # его туда, где чередования никто не обещал.
    пар = min(len(вверх), len(вниз))
    вон = []
    for i in range(пар):
        вон.append(вверх[i])
        вон.append(вниз[i])
    нейтраль = вверх[пар:] + вниз[пар:] + нейтраль
    # ДЛИНА ОБЯЗАНА БЫТЬ ЧЁТНОЙ, иначе шаг перемешки может стать
    # чётным и чередование распадётся.
    if len(вон) % 2:
        нейтраль.insert(0, вон.pop())
    return вон, нейтраль


