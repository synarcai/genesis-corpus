#!/usr/bin/env python3
"""GENESIS layer: ЭЛИЗИЯ — see tools/elisionforms.py for the law.

ПРАВИЛО И ЕГО ГРАНИЦЫ РАЗДЕЛЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ЛОМАЮТ.

«Сокращение названо» и «граница правила» идут вместе: первое даёт закон, второе тут же
отнимает вывод «сокращается всякое слово», который читатель сделал бы из первого сам.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Буква h молчит не всегда» стои́т особо: это ловушка ряда, и соседство разбавило бы её.

«Своя граница у одного слова» и «апостроф не есть буква» — третьей группой: обе о том, что
правило ЧИТАЕТСЯ НЕ ЦЕЛИКОМ, — одна о его ширине, другая о том, что апостроф оставляет два
слова двумя.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import elisionforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_elision.txt"
ГРУППЫ = (("сокращение названо", "граница правила"),
          ("буква h молчит не всегда",),
          ("своя граница у одного слова", "апостроф не есть буква"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
