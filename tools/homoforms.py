def _имя(я, язык, падеж=0):
    """Имя языка: русское именительным (0) или творительным (1), либо английское."""
    ряд = ИМЕНА.get(я, (я, я, я))
    return ряд[2] if язык != "ru" else ряд[падеж]


def _перечень(языки, язык):
    имена = [_имя(я, язык) for я in языки]
    if язык == "ru":
        return ", ".join(имена[:-1]) + " и " + имена[-1] if len(имена) > 1 else имена[0]
    return ", ".join(имена[:-1]) + " and " + имена[-1] if len(имена) > 1 else имена[0]


