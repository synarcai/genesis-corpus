def _формы(пак):
    вон = set()
    for _и, кл in (пак.get("morph_classes") or {}).items():
        for _л, формы in (кл.get("lexemes") or {}).items():
            вон |= {str(ф).lower() for ф in формы if str(ф).strip()}
    for л, мн in (пак.get("noun_forms") or {}).items():
        вон.add(str(л).lower())
        вон.add(str(мн).lower())
    return {ф for ф in вон if ф.isalpha()}


def перепись():
    """({слово: [языки]}, всего форм) — по ПАКЕТАМ, а не по списку в доме."""
    по_слову = {}
    всего = 0
    for п in sorted(ПАКЕТЫ.glob("*.json")):
        # ПОРЧЕНЫЙ ПАКЕТ НЕ СМЕЕТ УРОНИТЬ ПАЛАТУ. Дом читается при ВВОЗЕ, а ввозится он
        # палатой — и `json.loads`, брошенный вверх, снял бы разом все двести тридцать
        # восемь судов. Нечитаемый пакет есть находка ИНОГО прибора (`json_hand`,
        # `langpack_court`), и здесь он молча пропускается.
        #
        #     ДОМ, ЧИТАЮЩИЙ ЧУЖОЕ ПРИ ВВОЗЕ, ОТВЕЧАЕТ ЗА ВСЮ ПАЛАТУ: ЕГО ПАДЕНИЕ ЕСТЬ
        #     ПАДЕНИЕ ВСЕХ, КОГО ОНА НЕСЁТ.
        try:
            пак = json.loads(п.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        я = пак.get("lang", п.stem)
        свои = _формы(пак)
        всего += len(свои)
        for с in свои:
            по_слову.setdefault(с, []).append(я)
    return {с: sorted(я) for с, я in по_слову.items()}, всего


