    # ВСЯКИЙ ОМОГРАФ ОБЯЗАН НЕСТИ НЕ МЕНЕЕ ДВУХ ЯЗЫКОВ, И ЯЗЫКИ ОБЯЗАНЫ БЫТЬ НАЗВАНЫ.
