"""ДОМ СЛЕЖЕНИЯ ЗА ВЕЩАМИ (14.09, ступень 2, просьба holon-f9).

Вторая ступень лестницы (BBH) держит род `tracking_shuffled_objects`: у каждого в руках
вещь, они меняются по очереди, и надо назвать, что у кого в конце. Замерено 14.09 по своду:
строк со словами «меняются», «обменял», «swap», «traded» — НОЛЬ. Корпус знал, что вещь
ПЕРЕХОДИТ («анна отдала 1 монету»), и считал остаток, но не знал ОБМЕНА, где вещь не
исчезает и не появляется, а меняет руку, и число у всех остаётся одно.

    СЧЁТ ОСТАТКА И СЛЕЖЕНИЕ ЗА ВЕЩЬЮ — РАЗНЫЕ ДЕЛА. В первом вещь безлика и важно её
    количество; во втором вещь одна, количество не меняется никогда, и важно ТОЛЬКО ГДЕ
    она. Из умения вычитать второе не следует ничем.

ТРИ РОДА ПО ДЕЛУ — по тому, ЧЕГО ТРЕБУЕТ ОТВЕТ:

    мимо            спрошенного не тронул ни один обмен: ответ есть НАЧАЛО, и вся запись
                    про обмены к нему не относится. Читатель, выучивший «раз названо — то
                    изменилось», здесь ошибётся;
    один_обмен      обмен всего один и спрошенный в нём: ответ есть начальная вещь напарника;
    цепь_обменов    обменов несколько и спрошенный тронут ими: ответ требует НЕСТИ
                    СОСТОЯНИЕ вперёд, ибо напарник к своему обмену держит уже не то, с чего
                    начал. Сюда же ложится обмен, повторённый дважды: вещи возвращаются, и
                    «названо дважды» не значит «изменилось дважды».

РОД ЧИТАЕТСЯ ИЗ ДЕЛА, А НЕ НАЗНАЧАЕТСЯ ПОКАЗУ: дом перебирает все объявленные ряды обменов
и всех спрошенных, а потом СМОТРИТ, что вышло, и тем именует род.
"""
