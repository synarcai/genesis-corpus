def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    for язык in ЯЗЫКИ:
        assert len(set(ИМЕНА[язык])) == len(ИМЕНА[язык]), "имя дважды"
        assert len(ИМЕНА[язык]) <= len(ВЕЩИ[язык]), "вещей меньше, чем рук"
        assert len(set(ВЕЩИ[язык])) == len(ВЕЩИ[язык]), "вещь дважды"
    # ОБМЕН НИЧЕГО НЕ СОЗДАЁТ И НЕ ТЕРЯЕТ: сколько вещей было, столько и осталось.
    for ряд in РЯДЫ:
        assert sorted(разыграть(ряд, 3)) == [0, 1, 2], f"обмен потерял вещь: {ряд}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


