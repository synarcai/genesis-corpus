ЯЗЫКИ = ("ru", "en")
РОДЫ = ("мимо", "один_обмен", "цепь_обменов")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "мимо": "спрошенного не тронул ни один обмен: ответ есть начало",
    "один_обмен": "обмен один и спрошенный в нём: ответ есть начальная вещь напарника",
    "цепь_обменов": "обменов несколько и спрошенный тронут: состояние надо нести вперёд",
}

ИМЕНА = {"ru": ("Анна", "Борис", "Вера"), "en": ("anna", "boris", "vera")}

# ВЕЩИ ОБЪЯВЛЕНЫ В ВИНИТЕЛЬНОМ, А НЕ В СЛОВАРНОЙ ФОРМЕ: рамка стоит на «держит», и
# «держит книга» есть не оговорка, а ложь записи. Форма ОБЪЯВЛЕНА, а не выведена отсечением
# окончания, — тот же закон, по которому дом анафоры объявляет родительный имени. Для «мяч»
# и «ключ» винительный совпал с именительным, для «книгу» и «ленту» — нет, и ровно поэтому
# правило «отсечь и приписать» здесь и лжёт, и молчит попеременно.
ВЕЩИ = {
    "ru": ("мяч", "книгу", "ключ", "ленту"),
    "en": ("the ball", "the book", "the key", "the ribbon"),
}

РАМКИ = {
    "ru": {"держит": "{кто} держит {что}", "обмен": "{а} и {б} меняются",
           "вопрос": "что держит {кто}?"},
    "en": {"держит": "{кто} holds {что}", "обмен": "{а} and {б} swap",
           "вопрос": "what does {кто} hold?"},
}

# РЯДЫ ОБМЕНОВ ОБЪЯВЛЕНЫ ПОИМЁННО: пара — места в ряду людей, а не имена.
РЯДЫ = (
    ((0, 1),), ((1, 2),), ((0, 2),),
    ((0, 1), (1, 2)), ((0, 1), (0, 2)), ((1, 2), (0, 1)), ((0, 2), (1, 2)),
    ((0, 1), (1, 2), (0, 2)), ((1, 2), (0, 2), (0, 1)),
    ((0, 1), (0, 1)), ((1, 2), (1, 2)),
)
СДВИГИ = (0, 1, 2)      # какой вещью начинает первый человек


def разыграть(ряд, сколько):
    """Места вещей после ряда обменов: `вон[i]` — номер вещи в руках i-го человека."""
    вон = list(range(сколько))
    for а, б in ряд:
        вон[а], вон[б] = вон[б], вон[а]
    return вон


def _род(ряд, кого):
    тронут = sum(1 for пара in ряд if кого in пара)
    if тронут == 0:
        return "мимо"
    if len(ряд) == 1:
        return "один_обмен"
    return "цепь_обменов"


def страница(язык, ряд, сдвиг, кого):
    люди, вещи, рамки = ИМЕНА[язык], ВЕЩИ[язык], РАМКИ[язык]
    начало = [вещи[(i + сдвиг) % len(вещи)] for i in range(len(люди))]
    места = разыграть(ряд, len(люди))
    зачин = ", ".join(рамки["держит"].format(кто=люди[i], что=начало[i])
                      for i in range(len(люди)))
    ходы = ". ".join(рамки["обмен"].format(а=люди[а], б=люди[б]) for а, б in ряд)
    ответ = начало[места[кого]]
    return f"{зачин}. {ходы}. {рамки['вопрос'].format(кто=люди[кого])} {ответ}."


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for ряд in РЯДЫ:
            for сдвиг in СДВИГИ:
                for кого in range(len(ИМЕНА[язык])):
                    вон.setdefault(страница(язык, ряд, сдвиг, кого),
                                   (язык, _род(ряд, кого)))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД РАЗЫГРЫВАЕТ ОБМЕНЫ ЗАНОВО по ЗАПИСИ: он читает зачин (кто с чего начал), читает ходы
# (кто с кем менялся) и ведёт свои руки. Ни начала, ни ряда обменов он от дома не берёт.
# Порча имени, вещи или порядка ходов меняет вердикт.
def _разбор(язык, строка):
    рамки, вещи = РАМКИ[язык], ВЕЩИ[язык]

    def образец(ключ, **дыры):
        о = re.escape(рамки[ключ])
        for д, узор in дыры.items():
            о = о.replace(re.escape("{" + д + "}"), f"(?P<{д}>{узор})")
        return о

    держит = re.compile(образец("держит", кто=r"[^,.?]+?", что=r"[^,.?]+?"))
    обмен = re.compile(образец("обмен", а=r"[^,.?]+?", б=r"[^,.?]+?"))
    вопрос = re.compile(образец("вопрос", кто=r"[^,.?]+?") + r" (?P<ответ>[^.?]+)\.$")

    м = вопрос.search(строка)
    if not м:
        return None
    голова = строка[:м.start()].rstrip()
    куски = [к.strip() for к in голова.split(".") if к.strip()]
    if len(куски) < 2:
        return None
    руки, порядок = {}, []
    for кусок in куски[0].split(","):
        д = держит.fullmatch(кусок.strip())
        if not д:
            return None
        руки[д.group("кто")] = д.group("что")
        порядок.append(д.group("кто"))
    if len(руки) != len(порядок):
        return None
    for кусок in куски[1:]:
        о = обмен.fullmatch(кусок.strip())
        if not о or о.group("а") not in руки or о.group("б") not in руки:
            return None
        а, б = о.group("а"), о.group("б")
        if а == б:
            return None
        руки[а], руки[б] = руки[б], руки[а]
    кто = м.group("кто")
    if кто not in руки or руки[кто] not in вещи:
        return None
    return руки[кто] == м.group("ответ")


def судить(строка):
    """(судимо, истинно) — обмены разыграны заново по самой записи."""
    for язык in ЯЗЫКИ:
        ответ = _разбор(язык, строка.strip())
        if ответ is not None:
            return True, ответ
    return False, True


