# СЛОВО ПЕРЕД ЛИЦОМ — ЧЕТВЁРТЫЙ СЛОЙ ТОЙ ЖЕ ДВЕРИ.
#
#     СЛОВО, ЗА КОТОРЫМ СВОД СТАВИЛ ЛИШЬ ОБЪЯВЛЕННОЕ — ЛИЦО, МЕСТОИМЕНИЕ, ОТРИЦАНИЕ, — НЕ ТЕРПИТ
#     ЗА СОБОЙ НЕОБЪЯВЛЕННОГО: ОБРЕЗОК ИМЕНИ НА ЭТОМ МЕСТЕ ЕСТЬ ЛОЖЬ.
#
# ПОВОД — КАРТА СЛЕПОТЫ (22.09, ночь). Порча каждого объявленного имени в любом месте строки по
# 42 мирам деятелей, вердикт палаты — уже с законом падежа лица: в зачине обрезок проходит 102
# раза из 79 233, ВНУТРИ предложения — 1 731 из 88 165, и ещё 340 немы. Слепота живёт внутри, и
# больше всего — после вспомогательного глагола: «how many eggs does Ben hold now?» → «…does Be
# hold now?», «how many things did Tom buy?» → «…did To buy?». Закон зачина туда не ходит по
# своей границе (судится лишь зачин), закон падежа — по своей (обрезок не есть форма лица).
#
# ЧТО ПОКУПАЕТСЯ — ЗЕРКАЛО ЗАКОНА ЗАЧИНА. Там класс слова ПЕРЕД словом при лице; здесь класс
# слова ЗА словом, после которого свод ставил лицо. Пары «слово → класс слова за ним» при знаке
# языка; классы — те же, что объявил пакет, а необъявленное слово есть «·неизвестно». Слово
# куплено при девяти показах, если за ним хоть раз стояло лицо, и СТРОГО, если «·неизвестно» за
# ним не стояло ни разу.
#
# ЧЕМ ЗАКОН СУДИТ: за строгим словом стоит слово, какого пакет не объявил НИКАКИМ классом.
# Объявленное, но на этом месте невиданное («в четверг кто-то…» при «в четверг Анна…»), не
# обвиняется: это новый, но ЗНАКОМЫЙ род, и замер назвал цену обратного — 13 обвинений из 17 на
# невиданной половине были именно такими.
#
#     ЗАКОН ЛОВИТ НЕЗНАКОМОЕ, А НЕ НЕВИДАННОЕ.
#
# КЛАСС ОТРИЦАНИЯ КУПЛЕН ЭТИМ ЖЕ ЗАМЕРОМ. Без него строгих слов 48 из 289, закон ловит 55 порч
# из 2 071 непойманных, и «does» не строг: за ним 309 раз стоит «not». Отрицание объявлено
# пакетом однажды — чтением знака «¬» — и взято оттуда (`классы_пакета`): строгих 49, улов 521.
#
#     порча имени внутри предложения: палата пропускала 1 731 — закон ловит 494;
#                                     немых было 340 — закон судит 27;
#     улов по мирам: genesis_compare 180, everyday 75, genesis_story 60, gsmwide 60, gsmlex 50,
#                    story_chain 45, realverbs 30, heads 20, gsmforms 1;
#     цена на невиданной половине: 4 обвинения на 40 247 строках; на полном своде 0.
#
# Цена названа поимённо: «yesterday comes before today» (everyday, 2) — за «yesterday» половина
# свода ставила лишь лицо; «melk is een vloeistof», «sap is een vloeistof» (sceneforms, 2) — вещь
# на месте лица, тот же предел, что держит закон зачина.
#
# ЧЕГО ЗАКОН НЕ СУДИТ, И ЭТО ГРАНИЦА:
#   · «did» и «do»: за ними свод ставит «more», «fewer», «than» (`cmpframes`), а класса сравнения
#     пакет не объявляет — оба слова нестроги, и обрезок имени за ними не судится (67 и 35 порч).
#     Дверь сравнения есть долг пакета, а не этого закона;
#   · слово, за которым свод ставит что угодно: «and» (316 непойманных), «than» (142), «that»
#     (69), «as» (62) — строгими их не сделает никакой класс, и обрезок за ними ничей; из 1 731
#     пропущенных остаются 1 237;
#   · обрезок, ставший ОБЪЯВЛЕННЫМ словом иного класса: он знаком и не судится;
#   · слово, за которым лица не было ни разу, — рынок его не покупает.

САЙДКАР_СОСЕДА = КОРЕНЬ / "datasets" / "GENESIS-FULL.beforeperson.tsv"
_КУПЛЕН_СОСЕД = None


def класс_слова(язык, слово):
    """Классы слова, объявленные пакетом; необъявленное — «·неизвестно»."""
    return классы_пакета(язык).get(слово) or frozenset({НЕТ_КЛАССА})


def собрать_рынок_соседа(доля=None):
    """(язык, слово) → {класс слова за ним: показы}. `доля` — отбор строк для цены."""
    import langsign
    рынок = collections.defaultdict(collections.Counter)
    for _, путь, языки in миры_деятелей():
        if not путь.exists():
            continue
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            строка = строка.strip()
            if not строка or (доля is not None and not доля(строка)):
                continue
            низ = строка.lower()
            for язык in языки:
                if langsign.чужой(низ, язык):
                    continue
                for перед, за in соседи(низ):
                    рынок[(язык, перед)].update(класс_слова(язык, за))
    return рынок


def куплены_соседом(рынок):
    """Слово перед лицом: девять показов и хоть раз за ним лицо."""
    масса = закон_массы()
    return {к: frozenset(классы) for к, классы in рынок.items()
            if sum(классы.values()) >= масса and КЛАСС_ЛИЦО in классы}


def куплен_сосед():
    """Рынок соседа с полки: (язык, слово) → классы слова за ним. Сайдкара нет — пусто."""
    global _КУПЛЕН_СОСЕД
    if _КУПЛЕН_СОСЕД is None:
        _КУПЛЕН_СОСЕД = полка(САЙДКАР_СОСЕДА)
    return _КУПЛЕН_СОСЕД


def порча_соседа(строка, языки, куп=None):
    """((слово, слово за ним, язык), …) — необъявленное слово за строгим словом перед лицом.

    Языковой знак спрашивается лишь при кандидате в обвинение, как и у закона зачина.
    """
    куп = куплен_сосед() if куп is None else куп
    if not куп:
        return ()
    низ = строка.strip().lower()
    беды, свои = [], None
    for перед, за in соседи(низ):
        судящие = [я for я in языки if НЕТ_КЛАССА not in куп.get((я, перед), {НЕТ_КЛАССА})]
        if not судящие or any(классы_пакета(я).get(за) for я in судящие):
            continue
        if свои is None:
            import langsign
            свои = {я for я in языки if not langsign.чужой(низ, я)}
        for язык in судящие:
            if язык in свои:
                беды.append((перед, за, язык))
                break
    return tuple(беды)
