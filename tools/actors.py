# КАЖДОГО зачина предложения (обрезание и двойник буквы, как у подсадки словом) по всем 42
# мирам деятелей, вердикт всей палаты до и после:
#
#     два класса:                   закон обвиняет вновь 1 964 — палата ловила все 1 964 и прежде;
#     ПОТОЛОК — все 296 слов строги: закон обвиняет вновь 10 214 — палата ловила все 10 214;
#                                   единоличных поимок 0, а честных строк стало бы ложью 1 237
#                                   (lang_ru 501, action_pages 248 — «es gab…», everyday 132 …).
#
#     ПОРЧУ ЗАЧИНА ПЕРЕД СЛОВОМ ПРИ ЛИЦЕ СВОД УЖЕ ЛОВИТ ЦЕЛИКОМ: СТРОГОСТЬ, КУПЛЕННАЯ СВЕРХ
#     НЫНЕШНЕЙ, ЕСТЬ ВТОРОЙ СТОРОЖ У ДВЕРИ, КОТОРУЮ СТЕРЕЖЁТ ПЕРВЫЙ, — и потолок её стоит лжей.
#
# Оттого классы НЕ поставлены и объявление НЕ сделано: закон, не поймавший ни одной порчи,
# какую не поймал бы сосед, не заговорил. Карта продавцов выше остаётся картой СТРОГОСТИ,
