#
# ДВАДЦАТЬ ОДИН МИР ПИСАЛ ЛИЦА И НЕ ОБЪЯВЛЯЛ ДЕЯТЕЛЕЙ ВОВСЕ, И НАШЁЛ ИХ САМ ЗАКОН. Подсадка
# словом назвала худшим мир `verbal` (5 дыр из 22); порча КАЖДОЙ его строки дала 80 непойманных
# из 798, и ВСЕ восемьдесят — порча имени: «vera»→«ver», «lena»→«len», «tom»→«to». Мир этот
# деятелей не объявлял, и потому закон о нём молчал по праву. Обход нашёл ещё двадцать таких
# миров показов — около 11 565 строк, открытых лицом.
#
#     МИР, ПИШУЩИЙ ЛИЦА И НЕ ОБЪЯВИВШИЙ ИХ, НЕ ЕСТЬ МИР БЕЗ ЛИЦ: он есть мир, чьи лица
#     не охраняет никто, и молчание закона о нём — не граница, а незаданный вопрос.
#
# Объявлены все двадцать один, измерены поодиночке и ТРИНАДЦАТЬ ОСТАВЛЕНЫ (мир деятелей
# 29 → 42), а ВОСЕМЬ СНЯТЫ, ибо стоили бы соседу лжей: links 578, opchoice 192, behavior 100,
# svamp 99, handover 75, kinbearer 42, anaphora 12, degrees 12. Обвинения эти ЧЕСТНЫ и
# называют три чужих долга: полярное «no» (230 строк), необъявленные повелительные зачины
# («say» 224, «explain» 112, «step» 110) и — важнее прочего — НЕОБЪЯВЛЕННЫЕ ИМЕНА при живом
# доме имён: «boris» 72, «jane» 18, «john» 18.
#
#     ДОМ ИМЁН (М-131) ГОВОРИТ: «всякое имя лица, какое вправе взять порождатель, объявлено
#     здесь однажды». Имя, писанное домом мимо пакета, есть вторая дверь — и видна она лишь
#     тогда, когда мир объявит деятелей и закон спросит.
#
# ВТОРАЯ ДВЕРЬ НАЙДЕНА ПОИМЁННО: `tools/handoverforms.py:45` держит `ИМЕНА = {"ru": ("Анна",
# "Борис", "Вера"), "en": ("anna", "boris", "vera")}`, `tools/bothlists.py:48` — свою шестёрку
# («anna, boris, vera, gleb, daria, egor»). Из 1110 обвинений соседа 108 суть ровно эти имена.
#
# ДОЛГ ЭТОТ НЕ ПЛАТИТСЯ ЗДЕСЬ, И ПРИЧИНА ЗАМЕРЕНА, А НЕ ПРЕДПОЛОЖЕНА. Четыре дома пишут
# 27 необъявленных пар «язык × имя» (четвёртый — `behaviorforms.py:120/471`). Все 27 объявлены
# в ПРОБНОМ дереве, в конец списков, без перестановки прежних, — и воспроизводимость дала
# 17 расхождений из 348: `holdforms` +109 строк и `genderverb` +42 (страница на каждое имя),
# а `action_pages`, `cmpframes`, `compare_langs` сохранили число строк и сменили ИМЕНА в них.
#
#     ДОМ ИМЁН, КОТОРЫЙ ЧИТАЮТ, ЕСТЬ НЕ ТОЛЬКО СЛОВАРЬ, НО И ЗАКАЗ: всякое имя в нём есть
#     страница у того, кто показывает всех лиц.
#
# Закон, сдвигающий свод, мерится двумя варками всего свода и отвечает перед его читателями.
#
# ДВА ЧУЖИХ ДОЛГА НАЙДЕНЫ ТЕМ ЖЕ ЗАМЕРОМ, НАЗВАНЫ ЧИСЛОМ И ЗДЕСЬ НЕ УПЛАЧЕНЫ.
#
# ПЕРВЫЙ — ОБЪЯВЛЕНИЕ СПИСКОМ НЕВИДИМО ЗАКОНУ, ЧИТАЮЩЕМУ ЕГО СТРОКОЙ. Мир вправе объявить
# деятелей одним ключом через запятую (`person_names:ru,en,de,fr,es,it,pt,nl,pl`), а
# `Слой.лица(язык)` сличает ключ ЦЕЛИКОМ — и для такого мира отвечает «нет» на всякий язык.
# Закон лица суда эпизода нем на ТРЁХ мирах и 17 075 строках: holdforms 6777, cmpframes 6480,
# sceneforms 3818. Здешний закон не слеп (он зовёт `Слой.языки()`, который запятую
# разворачивает) и на тех строках нашёл НОЛЬ лжей.
#
#     ОДНО ПОНЯТИЕ, ПРОЧТЁННОЕ ДВУМЯ РУКАМИ ПО-РАЗНОМУ, ЕСТЬ ДВЕ ДВЕРИ, ИЗ КОТОРЫХ ОДНА
#     ЗАПЕРТА, И ЗАПЕРТА МОЛЧА.
#
# Прозрение соседа замерено и СТОИТ 200 ОБВИНЕНИЙ НА ЧЕСТНЫХ СТРОКАХ, у каждого своя причина:
# 96 в sceneforms (польские строки судит английская ветвь; ответ голым словом «red.») и 104 в
# speech. Оттого запятая здесь НЕ разворачивается у соседа: долг назван, а платится он
# объявлением пакета, не правкой чтения.
#
# ВТОРОЙ — АНГЛИЙСКИЙ ПАКЕТ ОБЪЯВЛЯЕТ «yes» ЗАЧИНОМ, А «no» — НЕТ, хотя оба объявлены им же
# полем `polarity` («the word that opens an answer», «declared per language, never derived»).
# Из 128 обвинений соседа в sceneforms 32 снимаются одним чтением полярности как зачина.
#
# ЦЕНА СОБСТВЕННОГО ОБЪЯВЛЕНИЯ ЗАМЕРЕНА ДО ПОСАДКИ, И ОДНО ИЗ ДВЕНАДЦАТИ СНЯТО. Мир `speech`
# пишет 380 английских строк при русских деятелях; объявление `person_names:en` разбудило
# английскую ветвь соседа и родило 104 НОВЫЕ ЛЖИ на честных страницах («all of 4, 6, 8 are
# even…» — квантор «all» английским пакетом зачином не объявлен). Объявление снято.
#
#     ЗАКОН, ПРИБАВЛЯЮЩИЙ ЛЖИ У СОСЕДА, НЕ ЕСТЬ ПРИБЫЛЬ: одиннадцать объявлений из
#     двенадцати стоили НОЛЬ, и взяты только они.
#
# СИЛА ЗАКОНА МЕРИТСЯ ПОЛКОЙ, А НЕ ОБЕЩАНИЕМ: слово СТРОГО, если среди его купленных классов
# нет «·неизвестно», то есть свод НИКОГДА не открывал его необъявленным словом. Первый замер —
# 206 из 260 (ru 48/77); ныне, при 42 мирах деятелей, шестом классе и русской парадигме
# местоимений, — 259 из 296: en 108/109, ru 82/90, pl 21/21, es 17/17, de 7/16, pt 13/13, nl 2/10, tr 1/8, fr 2/6, it 6/6.
# Где слово нестрого, там порча прячется за вещью, и число это есть карта слепоты закона.
#
# ОБОБЩЕНИЕ ЗА ПРЕДЕЛЫ ЛИЦА ИЗМЕРЕНО И ОТВЕРГНУТО (22.09, вечер). Мысль: требовать класса
# перед ВСЯКИМ словом, какое свод открывает лишь объявленными классами, а не только при лице, —
# ради порч «чему равен» → «чем равен», «простое ли» → «просто ли». Замер: куплено 593 против
# 296, цена на невиданной половине 18 обвинений (все — дробь в зачине: «треть яблок ушла»,
# «половина книг ушла», класса у пакета нет), а обе цели НЕ достигнуты: они живут в мирах без
# деятелей (`linalg`, `numbers`), куда рынок места лица не ходит. Вопросный зачин есть иной закон
# и иной рынок — по всем мирам показов, а не по мирам лиц.
#
# ЧЕГО ЗАКОН НЕ СУДИТ, И ЭТО ГРАНИЦА, А НЕ ПОЛНОТА:
#   · мир, НЕ объявивший деятелей, — там нет лиц, и место лица не определено;
#   · строку, чей языковой знак чужой объявленному языку (`langsign.чужой`), — её судит
#     закон её языка, а не этот;
#   · ОБРЕЗОК ИМЕНИ, БУДУЧИ ИМЕНЕМ. Мир `verbal`, объявив деятелей, отдал три четверти своей
#     дыры (непойманных 80 → 20, пойманных 638 → 698), и ВЕСЬ остаток одного рода: «anna» →
#     «ann», где обрезок сам есть объявленное лицо. Закон места молчит здесь ПО ПРАВУ — место
#     занято лицом; видит такую порчу лишь закон о СВЯЗНОСТИ ЛИЦА («лицо, названное в строке
#     дважды, есть одно лицо»), а он живёт в эпизодной алгебре, не здесь;
#   · слово ВНУТРИ предложения: судится лишь ЗАЧИН, ибо только о нём свод говорит показами;
#   · слово, купленное ДВУМЯ языками мира врозь, судится мягко: довольно, чтобы зачин был
#     законен хоть на одном из них, даже если знак строки тому языку чужой. Мягкость эта
#     ТЕРЯЕТ ПОИМКИ И НЕ РОЖДАЕТ ЛЖЕЙ, и взята она ценой: строгость стоила бы языкового
#     знака на КАЖДОЙ строке свода (0,14 мс × миллион), а не на кандидате в обвинение.

КЛАСС_ЛИЦО = "лицо"
НЕТ_КЛАССА = "·неизвестно"
# Поля пакета, объявляющие класс зачина. Список есть ИМЕНА ПОЛЕЙ, а не слова языка.
ПОЛЯ_КЛАССОВ = (("ask_words", "вопрос"), ("task_words", "задание"))
ПОЛЕ_РОДА = "gender"
# Знак отрицания в `sign_names` пакета: его чтения суть слово отрицания языка.
ЗНАКИ_ОТРИЦАНИЯ = ("¬", "\\neg")
КЛАСС_ОТРИЦАНИЯ = "отрицание"
САЙДКАР = КОРЕНЬ / "datasets" / "GENESIS-FULL.actorplace.tsv"
# Зачин предложения и слово сразу за ним. Буква — всякая буква всякого письма.
ЗАЧИН_СЛОВО = re.compile(r"(?:^|(?<=[.?!] ))([^\W\d_]+) ([^\W\d_]+)")

_КЛАССЫ = {}
_КУПЛЕНО = None


def классы_пакета(язык):
    """слово → набор классов, ОБЪЯВЛЕННЫХ ПАКЕТОМ этого языка."""
    if язык not in _КЛАССЫ:
        путь = КОРЕНЬ / "tools" / "langpacks" / f"{язык}.json"
        вон = collections.defaultdict(set)
        try:
            пакет = json.loads(путь.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            пакет = {}
        for и in пакет.get("person_names", ()):
            вон[и.lower()].add(КЛАСС_ЛИЦО)
        for формы in пакет.get("person_forms", {}).values():
            for поле, ф in формы.items():
                # `gender` объявляет РОД имени, а не имя: «f» и «m» — пометы, не лица.
                if поле != ПОЛЕ_РОДА and isinstance(ф, str):
                    вон[ф.lower()].add(КЛАСС_ЛИЦО)
        for поле, имя in ПОЛЯ_КЛАССОВ:
            for с in (пакет.get(поле) or {}).get("words", ()):
                вон[с.lower()].add(имя)
        # ЧИСЛИТЕЛЬНОЕ СЛОВОМ объявлено полем `numerals` (все 29 пакетов): ключ — цифра,
        # значение — слово или ряд слов. Класс этот куплен замером, а не догадкой: без него
        # «three and…», «five and…» продавали слову «and» класс «·неизвестно», и порча
        # «Ann and Tom» → «An and Tom» проходила палату истиной.
        for значение in (пакет.get("numerals") or {}).values():
            ряд = [значение] if isinstance(значение, str) else (
                list(значение) if isinstance(значение, (list, tuple)) else [])
            for с in ряд:
                if isinstance(с, str) and с.strip():
                    вон[с.strip().lower()].add("число")
        # `sentence_openers` объявлен ПЛОСКИМ списком, а не парой «words/position», как
        # вопрос и задание, — оттого он читается врозь, а не через `ПОЛЯ_КЛАССОВ`.
        for з in пакет.get("sentence_openers", ()):
            вон[з.lower()].add("зачин")
        # ОТРИЦАНИЕ объявлено пакетом однажды — чтением знака «¬» (`sign_names`: en «not»,
        # ru «не»), и класс взят у этой двери, а не списком. Куплен он законом соседа (см.
        # «СЛОВО ПЕРЕД ЛИЦОМ» ниже): после «does» свод ставит лицо — и «not» 309 раз, и без
        # класса отрицания «does» не был строг ни разу. Зачин есть одно слово, и потому
        # чтение из нескольких слов («not equal») классом не ставится.
        for знак in ЗНАКИ_ОТРИЦАНИЯ:
            for с in (пакет.get("sign_names") or {}).get(знак, ()):
                if isinstance(с, str) and len(с.split()) == 1:
                    вон[с.lower()].add(КЛАСС_ОТРИЦАНИЯ)
        _КЛАССЫ[язык] = {с: frozenset(к) for с, к in вон.items()}
    return _КЛАССЫ[язык]


def миры_деятелей():
    """(имя мира, путь, языки деятелей) — из манифеста, а не из списка."""
    try:
        м = json.loads(МАНИФЕСТ.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return
    for мир in м.get("worlds", ()):
        а = мир.get("actors") or ()
        а = [а] if isinstance(а, str) else а
        языки = [я for к in а if к.startswith("person_names:")
                 for я in к.split(":", 1)[1].split(",") if я]
        if языки:
            yield мир.get("name"), КОРЕНЬ / мир.get("file", ""), языки


def собрать_рынок(доля=None):
    """(язык, слово) → {класс зачина: показы}. `доля` — отбор строк для замера цены."""
    import langsign
    рынок = collections.defaultdict(collections.Counter)
    for _, путь, языки in миры_деятелей():
        if not путь.exists():
            continue
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            строка = строка.strip()
            if not строка or (доля is not None and not доля(строка)):
                continue
            низ = строка.lower()
            for язык in языки:
                if langsign.чужой(низ, язык):
                    continue
                клс = классы_пакета(язык)
                for м in ЗАЧИН_СЛОВО.finditer(низ):
                    рынок[(язык, м.group(2))].update(клс.get(м.group(1)) or {НЕТ_КЛАССА})
    return рынок


def закон_массы():
    """Девять показов — закон массы берётся у соседа (`form_census.LAW2`), а не заводится свой."""
    import sys as _sys
    путь = str(КОРЕНЬ / "scripts")
    if путь not in _sys.path:
        _sys.path.insert(0, путь)
    import form_census
    return form_census.LAW2


def куплены(рынок):
    """Слова ПРИ ЛИЦЕ: девять показов и хоть один зачин — объявленное лицо."""
    масса = закон_массы()
    return {к: frozenset(классы) for к, классы in рынок.items()
            if sum(классы.values()) >= масса and КЛАСС_ЛИЦО in классы}


def полка(путь):
    """Полка рынка: (язык, слово) → купленные классы. Строка — язык, слово, показы, классы."""
    вон = {}
    try:
        строки = путь.read_text(encoding="utf-8").splitlines()
    except OSError:
        строки = ()
    for строка in строки:
        if строка.startswith("#") or not строка.strip():
            continue
        часть = строка.split("\t")
        if len(часть) == 4:
            вон[(часть[0], часть[1])] = frozenset(часть[3].split(","))
    return вон


def куплено():
    """Рынок с полки: (язык, слово) → купленные классы зачина. Сайдкара нет — пусто."""
    global _КУПЛЕНО
    if _КУПЛЕНО is None:
        _КУПЛЕНО = полка(САЙДКАР)
    return _КУПЛЕНО


def порча(строка, языки, куп=None):
    """((зачин, слово, язык), …) — зачины, каких свод перед этим словом не ставил.

    ЯЗЫКОВОЙ ЗНАК СПРАШИВАЕТСЯ ЛИШЬ ПРИ КАНДИДАТЕ В ОБВИНЕНИЕ, а не при всякой строке:
    он стои́т 0,14 мс, обвинения редки, и набор не платит за молчание.
    """
    куп = куплено() if куп is None else куп
    if not куп:
        return ()
    низ = строка.strip().lower()
    беды, свои = [], None
    for м in ЗАЧИН_СЛОВО.finditer(низ):
        зачин, слово = м.group(1), м.group(2)
        судящие = [я for я in языки if (я, слово) in куп]
        if not судящие:
            continue
        if any((классы_пакета(я).get(зачин) or {НЕТ_КЛАССА}) & куп[(я, слово)] for я in судящие):
            continue
        if свои is None:
            import langsign
            свои = {я for я in языки if not langsign.чужой(низ, я)}
        for язык in судящие:
            if язык in свои:
                беды.append((зачин, слово, язык))
                break
    return tuple(беды)


