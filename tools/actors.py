# дереве: строгих 259 → 274 из 296 (de 7 → 12, nl 2 → 7, tr 1 → 8), цена на невиданной
# половине 2 → 2, воспроизводимость 0 из 348, подсадка словом 7873 / 35 / 9 знак в знак.
