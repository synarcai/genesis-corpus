#
#     ЛИЦО ПОСЛЕ СЛОВА СТОИТ В ТОМ ПАДЕЖЕ, В КАКОМ СВОД ЕГО ПОСЛЕ ЭТОГО СЛОВА СТАВИЛ; А КАКОЙ
#     ЭТО ПАДЕЖ, ГОВОРИТ ПАКЕТ, ОБЪЯВИВШИЙ ФОРМЫ ИМЕНИ ПОИМЁННО, А НЕ ПРАВИЛО ОКОНЧАНИЙ.
#
# ПОВОД — ЗАКАЗ СМЕНЫ (доска 22.09, 19:32, первый): падеж, которым правит предлог. Подсадка
# словом держала непойманным «у Ивана было 5 яблок…» → «у Иван было 5 яблок…» (мир `speech`):
# обе формы — русские, обе стоя́т в своде, и словарь молчит по праву. Меняется ПАДЕЖ, и его в
# работе не читал никто. Прямой путь — замкнуть показами пару «предлог + слово» — измерен и
# закрыт (458 невиданных пар на честной половине, см. `reports/DAY-2026-09-22.md`), ибо обе
# половины пары суть СЛОВА, и хвост их бесконечен.
#
# ЗДЕСЬ ОДНА ПОЛОВИНА ЕСТЬ ОБЪЯВЛЕННЫЙ КЛАСС. Пакет объявляет формы лица поимённо — родительный
# и дательный при каждом имени (`person_forms`: «Иван» → gen «Ивана», dat «Ивану»; М-131), и
# форма знает свой падеж ИЗ ОБЪЯВЛЕНИЯ, а не из окончания. Рынок считает пары «слово перед
# лицом → падеж формы»; слово куплено при девяти показах (закон массы соседа), и купленные
# падежи его суть право: после «у» свод ставит лицо в родительном — «у Иван» есть ложь.
# Форма, чьи падежи совпали («Марии» — и gen, и dat), несёт оба, и слово покупает оба.
#
# ЗАКОН ЗАГОВОРИЛ, И ЧИСЛО ЭТО ЕСТЬ УЛОВ ЕДИНОЛИЧНЫЙ. Порча КАЖДОЙ формы лица внутри строки
# (обрезание и двойник буквы, как у подсадки словом) во всех русских мирах деятелей, вердикт
# всей палаты рядом с вердиктом закона:
#
#     обрезание: палата ловит 17 832, пропускает 460 — из них закон ловит 418 (everyday 324,
#                speech 73, story_chain 15, pronouns 4, ruverbs 2);
#     двойник:   палата ловит все 14 942 — закону здесь делать нечего;
#     цена на невиданной половине: 0 обвинений на 30 836 строках; на полном своде 0.
#
#     «у Иры 3 книги, а у Тома 5 книг» → «…а у Том 5 книг»     палата была: ИСТИНА
#     «…чем у Ивана. сколько карт у Лены?» → «…чем у Иван…»    палата была: ИСТИНА
#
# ЧЕГО ЗАКОН НЕ СУДИТ, И ЭТО ГРАНИЦА, А НЕ ПОЛНОТА:
#   · обрезок, не ставший ФОРМОЙ лица: «у Розы» → «у Роз», «Том» → «То». Слово, какого пакет
#     лицом не объявлял, здесь не судится вовсе; внутри предложения оно ничьё (42 порчи из 460),
#     а в зачине его судит закон зачина;
#   · языки, чей пакет падежей лица не объявляет (ныне все, кроме русского): у них нет класса,
#     и рынок не покупает ничего;
#   · слово, после которого свод ставил один падеж, в НОВОМ мире с иным управлением того же
#     слова («купил Ивану подарок» при «купил Том» в своде) будет обвинено. Риск этот мерится
#     ценой на половине (`scripts/personcase_market.py --цена`), а не помнится.

ПАДЕЖ_ИМЕНИ = "nom"                        # ключ `person_forms` есть само имя, именительный
САЙДКАР_ПАДЕЖА = КОРЕНЬ / "datasets" / "GENESIS-FULL.personcase.tsv"
# Слово — ряд букв всякого письма; лицо судится, когда от слова перед ним его отделяет пробел.
СЛОВО = re.compile(r"[^\W\d_]+")

_ПАДЕЖИ = {}
_КУПЛЕН_ПАДЕЖ = None


def падежи_лиц(язык):
    """форма лица (строчными) → падежи, какими её объявил пакет; пусто, если падежей нет."""
    if язык not in _ПАДЕЖИ:
        путь = КОРЕНЬ / "tools" / "langpacks" / f"{язык}.json"
        try:
            пакет = json.loads(путь.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            пакет = {}
        вон = collections.defaultdict(set)
        for имя, формы in (пакет.get("person_forms") or {}).items():
            падежи = {п: ф for п, ф in формы.items() if п != ПОЛЕ_РОДА and isinstance(ф, str)}
            if not падежи:
                continue
            вон[имя.lower()].add(ПАДЕЖ_ИМЕНИ)
            for падеж, форма in падежи.items():
                вон[форма.lower()].add(падеж)
        _ПАДЕЖИ[язык] = {ф: frozenset(п) for ф, п in вон.items()}
    return _ПАДЕЖИ[язык]


def соседи(низ):
    """(слово, слово за ним) — всякая пара слов одного предложения, разделённая одним пробелом."""
    слова = list(СЛОВО.finditer(низ))
    for перед, за in zip(слова, слова[1:]):
        if низ[перед.end():за.start()] == " ":
            yield перед.group(), за.group()


def пары_падежа(низ, падежи):
    """(слово перед, форма лица) — всякая форма, отделённая от слова перед ней одним пробелом."""
    for перед, форма in соседи(низ):
        if форма in падежи:
            yield перед, форма


def собрать_рынок_падежа(доля=None):
    """(язык, слово перед лицом) → {падеж формы: показы}. `доля` — отбор строк для цены."""
    import langsign
    рынок = collections.defaultdict(collections.Counter)
    for _, путь, языки in миры_деятелей():
        языки = [я for я in языки if падежи_лиц(я)]
        if not языки or not путь.exists():
            continue
        for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
            строка = строка.strip()
            if not строка or (доля is not None and not доля(строка)):
                continue
            низ = строка.lower()
            for язык in языки:
                if langsign.чужой(низ, язык):
                    continue
                падежи = падежи_лиц(язык)
                for перед, форма in пары_падежа(низ, падежи):
                    рынок[(язык, перед)].update(падежи[форма])
    return рынок


def куплены_падежи(рынок):
    """Слово перед лицом куплено при девяти показах — и с ним падежи, какие свод за ним ставил."""
    масса = закон_массы()
    return {к: frozenset(п) for к, п in рынок.items() if sum(п.values()) >= масса}


def куплен_падеж():
    """Рынок падежа с полки: (язык, слово перед лицом) → падежи. Сайдкара нет — пусто."""
    global _КУПЛЕН_ПАДЕЖ
    if _КУПЛЕН_ПАДЕЖ is None:
        _КУПЛЕН_ПАДЕЖ = полка(САЙДКАР_ПАДЕЖА)
    return _КУПЛЕН_ПАДЕЖ


def порча_падежа(строка, языки, куп=None):
    """((слово перед, форма, язык), …) — лицо в падеже, какого свод после этого слова не ставил.

    Языковой знак спрашивается лишь при кандидате в обвинение, как и у закона зачина.
    """
    куп = куплен_падеж() if куп is None else куп
    if not куп:
        return ()
    низ = строка.strip().lower()
    беды, свои = [], None
    for язык in языки:
        падежи = падежи_лиц(язык)
        if not падежи:
            continue
        for перед, форма in пары_падежа(низ, падежи):
            купл = куп.get((язык, перед))
            if купл is None or падежи[форма] & купл:
                continue
            if свои is None:
                import langsign
                свои = {я for я in языки if not langsign.чужой(низ, я)}
            if язык in свои:
                беды.append((перед, форма, язык))
    return tuple(беды)


