#!/usr/bin/env python3
"""ДОМ ВЕРОЯТНОСТИ — отношение числа благоприятных случаев к полному, и оно СЧИТАЕТСЯ.

    КОРПУС ОПРЕДЕЛЯЛ ВЕРОЯТНОСТЬ И НИ РАЗУ ЕЁ НЕ СЧИТАЛ. Мир определений цитирует словарь:
    «вероятность — это отношение числа случаев, благоприятствующих событию, к полному числу
    случаев». Двадцать три строки об этом — и ни одной, где отношение было бы ВЫЧИСЛЕНО.

ПОВОД — ЗАМЕР, А НЕ ЗАМЫСЕЛ. Перепись форм говорит: последняя доля свода даёт НОЛЬ новых рамок
и НОЛЬ новых родов на тысячу строк — корпус насыщен, и рост его стал повторением. Значит,
развивать надо РОДЫ, а не объём. Обход всех 214 миров показал: мир статистики знает среднее и
медиану, мир науки о счёте — биты при равновозможных исходах, а вероятности как ОТНОШЕНИЯ нет
нигде.

    ПОНЯТИЕ, НАЗВАННОЕ СЛОВАРЁМ И НЕ ПОКАЗАННОЕ СЧЁТОМ, ЕСТЬ ПОНЯТИЕ НЕПОКАЗАННОЕ.

ЧЕТЫРЕ РОДА, И ВСЕ ЧЕТЫРЕ ПРОВЕРЯЮТСЯ ПЕРЕСЧЁТОМ, А НЕ МНЕНИЕМ:

    доля         в мешке 3 красных шара и 2 синих шара. какова вероятность вынуть красный?
                 3 + 2 = 5, и вероятность есть 3 из 5.
    дополнение   …какова вероятность вынуть синий? 3 + 2 = 5, и вероятность есть 2 из 5.
    невозможное  …какова вероятность вынуть зелёный? зелёных в мешке нет, и вероятность есть 0 из 5.
    достоверное  …какова вероятность вынуть красный или синий? других шаров нет, и вероятность
                 есть 5 из 5.

ДОЛЯ И ДОПОЛНЕНИЕ СУТЬ МИНИМАЛЬНАЯ ПАРА: числа те же, вопрос иной, и ответ иной ровно потому,
что спрошено о другом цвете. Невозможное и достоверное суть КРАЯ ряда, и без них вероятность
выглядела бы вечно дробной — а она бывает и нулём, и единицей.

ЧИСЛА ВЫБРАНЫ ПОД РУССКИЙ СЧЁТ: имя стои́т при числе, и форма его берётся у дома русской
грамматики (`rugram.форма`), а не пишется на глаз. Прилагательное во всех этих числах стои́т
родительным множественным («3 красных шара», «5 красных шаров») и потому не гнётся; вещи
взяты только мужского рода, ибо у женского гнулось бы и оно («3 красные карты» против
«5 красных карт»), а склонять прилагательное дом не объявлял.

    python3 tools/chanceforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import rugram  # noqa: E402 — счётная форма имени берётся у дома, а не пишется на глаз

ЯЗЫКИ = ("ru", "en")

# ВЕЩИ ТОЛЬКО МУЖСКОГО РОДА — причина названа в докстринге и проверена: у женского гнётся и
# прилагательное, а его склонения дом не объявлял.
ВЕЩИ = {"ru": ("шар", "камень", "ключ", "орех"),
        "en": (("ball", "balls"), ("stone", "stones"), ("key", "keys"), ("nut", "nuts"))}
# ЦВЕТ ОБЪЯВЛЕН ТРЕМЯ ФОРМАМИ: родительная множественная при счёте, винительная единственная
# при «вынуть», и имя рода для страницы невозможного.
ЦВЕТА = {
    "ru": (("красных", "красный"), ("синих", "синий"), ("жёлтых", "жёлтый"),
           ("белых", "белый"), ("чёрных", "чёрный"), ("зелёных", "зелёный")),
    "en": (("red", "red"), ("blue", "blue"), ("yellow", "yellow"),
           ("white", "white"), ("black", "black"), ("green", "green")),
}
РАМКИ = {
    "ru": {
        "доля": "в мешке {a} {ц1} {в_a} и {b} {ц2} {в_b}. какова вероятность вынуть {ц1е}? {a} + {b} = {n}, и вероятность есть {a} из {n}.",
        "дополнение": "в мешке {a} {ц1} {в_a} и {b} {ц2} {в_b}. какова вероятность вынуть {ц2е}? {a} + {b} = {n}, и вероятность есть {b} из {n}.",
        "невозможное": "в мешке {a} {ц1} {в_a} и {b} {ц2} {в_b}. какова вероятность вынуть {ц3е}? {ц3} в мешке нет, и вероятность есть 0 из {n}.",
        "достоверное": "в мешке {a} {ц1} {в_a} и {b} {ц2} {в_b}. какова вероятность вынуть {ц1е} или {ц2е}? других нет, и вероятность есть {n} из {n}.",
    },
    "en": {
        "доля": "a bag holds {a} {ц1} {в_a} and {b} {ц2} {в_b}. what is the chance of drawing a {ц1е} one? {a} + {b} = {n}, and the chance is {a} out of {n}.",
        "дополнение": "a bag holds {a} {ц1} {в_a} and {b} {ц2} {в_b}. what is the chance of drawing a {ц2е} one? {a} + {b} = {n}, and the chance is {b} out of {n}.",
        "невозможное": "a bag holds {a} {ц1} {в_a} and {b} {ц2} {в_b}. what is the chance of drawing a {ц3е} one? the bag holds no {ц3} ones, and the chance is 0 out of {n}.",
        "достоверное": "a bag holds {a} {ц1} {в_a} and {b} {ц2} {в_b}. what is the chance of drawing a {ц1е} or {ц2е} one? there are no others, and the chance is {n} out of {n}.",
    },
}
РОДЫ = ("доля", "дополнение", "невозможное", "достоверное")


def вещь_при(язык, лемма, n):
    """Форма вещи при счёте: у русского спрашивается дом, у английского — множественное."""
    if язык == "ru":
        return rugram.форма(лемма, n)
    один, много = лемма
    return один if n == 1 else много


def _числа():
    """(a, b): оба от двух, и полное число не длиннее двух знаков."""
    вон = []
    for a in range(2, 10):
        for b in range(2, 10):
            if a != b and a + b <= 12 and len(вон) < 28:
                вон.append((a, b))
    return вон


def страницы():
    вон = {}
    числа = _числа()
    for язык in ЯЗЫКИ:
        вещи, цвета = ВЕЩИ[язык], ЦВЕТА[язык]
        for к, (a, b) in enumerate(числа):
            лемма = вещи[к % len(вещи)]
            ц1, ц1е = цвета[к % len(цвета)]
            ц2, ц2е = цвета[(к + 1) % len(цвета)]
            ц3, ц3е = цвета[(к + 3) % len(цвета)]
            поля = dict(a=a, b=b, n=a + b, ц1=ц1, ц1е=ц1е, ц2=ц2, ц2е=ц2е, ц3=ц3, ц3е=ц3е,
                        в_a=вещь_при(язык, лемма, a), в_b=вещь_при(язык, лемма, b))
            for род in РОДЫ:
                вон[РАМКИ[язык][род].format(**поля)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()
_СУММА = re.compile(r"(\d+) \+ (\d+) = (\d+)")
_ДОЛЯ = re.compile(r"(?:есть|is) (\d+) (?:из|out of) (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание. Тот же ход, каким живут пласт языков и дом выбора действия.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: сумма и отношение читаются своими глазами.
    сум = _СУММА.search(с)
    доля = _ДОЛЯ.search(с)
    if сум and int(сум.group(1)) + int(сум.group(2)) != int(сум.group(3)):
        return True, False
    if доля and int(доля.group(1)) > int(доля.group(2)):
        return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for показ in ПОКАЗЫ:
        свои = показ.split(" ")
        if len(свои) != len(слова):
            continue
        if sum(1 for x, y in zip(свои, слова) if x != y) == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:70]}")
    образец = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "доля")
    порчи = [
        образец.replace("вероятность есть", "вероятность ест"),   # обрезанное слово
        образец + " " + образец,                                   # удвоение — ЕМУ МОЛЧАТЬ
    ]
    if судить(порчи[0])[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(порчи[1])[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ВЕРОЯТНОСТЬ: страниц {len(ПОКАЗЫ)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
