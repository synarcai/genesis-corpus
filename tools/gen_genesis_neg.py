#!/usr/bin/env python3
"""КОВКА ДОМА ОТРИЦАТЕЛЬНОГО ЧИСЛА.

ПЕРЕВОРОТ И ЕГО ОТСУТСТВИЕ ИДУТ В ОДНОМ ПРОХОДЕ: «-5 меньше -2» и «-3 меньше 2» суть минимальная
пара по месту нуля, и разница между ними — в одном месте: по одну ли сторону нуля стоят оба
числа. Порознь первое внушало бы, что у отрицательных всё наоборот, второе — что ничего не
изменилось.

НУЛЬ И РАССТОЯНИЕ ДО НЕГО идут своей группой: «меньше нуля» и «противоположные» обе меряют
шагами от нуля — одна в одну сторону, другая в обе.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import negforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_neg.txt"
ГРУППЫ = (("за нулём", "через ноль"), ("меньше нуля", "противоположные"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
