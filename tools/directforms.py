def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать;
    ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for род in РОДЫ:
        if not по_роду.get(("ru", род)):
            беды.append(f"род пуст: {род}")
    # ПРАВИЛО ПРОВЕРЯЕТСЯ НА ЗАВЕДОМО ИЗВЕСТНОМ, А НЕ ТОЛЬКО НА СВОИХ СТРАНИЦАХ.
    случаи = (
        (("иди сюда", ".", "сказал он"), "«Иди сюда», — сказал он.", "точка снята"),
        (("кто там", "?", "спросила она"), "«Кто там?» — спросила она.",
         "вопрос остался, запятой нет"),
        (("как хорошо", "!", "сказал он"), "«Как хорошо!» — сказал он.",
         "восклицание, запятой нет"),
    )
    for (т, з, а), ждём, что in случаи:
        дало = речь_впереди(т, з, а)
        if дало != ждём:
            беды.append(f"{что}: «{дало}» вместо «{ждём}»")
    если = автор_впереди("иди сюда", ".", "он сказал")
    if если != "Он сказал: «Иди сюда».":
        беды.append(f"автор впереди: «{если}»")
    раз = разорвана("иди", "сюда", ".", "сказал он")
    if раз != "«Иди, — сказал он, — сюда».":
        беды.append(f"разрыв: «{раз}»")
    # ЗАПЯТАЯ ОБЯЗАНА СТОЯТЬ ЛИШЬ ТАМ, ГДЕ СНЯТА ТОЧКА.
    if ", — " in речь_впереди("кто там", "?", "сказал он"):
        беды.append("ЗАПЯТАЯ ПОСЛЕ ВОПРОСА — правило применено там, где исключение")
    if ", — " not in речь_впереди("иди сюда", ".", "сказал он"):
        беды.append("запятой нет там, где точка снята")
    # ТОЧКА ОБЯЗАНА СНИМАТЬСЯ, А ВОПРОС — ОСТАВАТЬСЯ: обе стороны прямо.
    if "." in речь_впереди("иди сюда", ".", "сказал он").split("»")[0]:
        беды.append("ТОЧКА НЕ СНЯТА — правило не работает")
    if "?" not in речь_впереди("кто там", "?", "сказал он").split("»")[0]:
        беды.append("ВОПРОС СНЯТ — исключение не работает")
    # КАВЫЧКИ ОБЪЯВЛЕНЫ ЁЛОЧКАМИ, И ПРЯМЫХ ЗНАКОВ В СТРАНИЦАХ БЫТЬ НЕ ДОЛЖНО.
    for с in ПОКАЗЫ:
        if '"' in с or "“" in с:
            беды.append(f"чужие кавычки на странице: {с[:70]}")
            break
    # РЕЧИ ОБЪЯВЛЕНЫ СО СВОИМ ЗНАКОМ, И ЗНАКИ ОБЯЗАНЫ БЫТЬ ВСЕ ТРИ.
    for з in {з for _т, з in РЕЧИ}:
        if з not in ИМЯ_ЗНАКА:
            беды.append(f"знак без имени: {з}")
    if {з for _т, з in РЕЧИ} != {".", "?", "!"}:
        беды.append(f"знаки конца не все: {sorted({з for _т, з in РЕЧИ})}")
    # ОБА ПОРЯДКА СЛОВ АВТОРА ОБЪЯВЛЕНЫ И РАЗЛИЧНЫ.
    for за, впер in АВТОРЫ:
        if за == впер:
            беды.append(f"порядок слов автора не различён: {за}")
        if set(за.split()) != set(впер.split()):
            беды.append(f"слова автора разошлись, а не переставились: {за} / {впер}")
    # МУТАНТ ПО СЛОВУ.
    пв = next(с for с, (я, р) in ПОКАЗЫ.items() if р == "речь впереди")
    порча = пв.replace("ЗАПЯТОЙ", "ЗАПЯТО", 1)
    if порча == пв:
        беды.append("порча не состоялась: нет слова «ЗАПЯТОЙ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    # МУТАНТ ПО ЗНАКУ: запятая, поставленная после вопроса, есть ложь письма.
    вп = next(с for с, (я, р) in ПОКАЗЫ.items() if р == "знак вопроса остаётся")
    порча = вп.replace("?»", "»", 1)
    if порча != вп and судить(порча)[1] is not False:
        беды.append(f"снятый вопросительный знак прошёл: {порча[:70]}")
    if судить(пв + " " + пв)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ПРЯМАЯ РЕЧЬ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


