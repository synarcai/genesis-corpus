def _заглавная(с):
    return с[:1].upper() + с[1:]


def речь_впереди(текст, знак, автор):
    """«П», — а. при точке; «П?» — а. при вопросе и восклицании.

    ЗАПЯТАЯ СТАВИТСЯ ТОЛЬКО ВМЕСТО СНЯТОЙ ТОЧКИ. Первая редакция дома писала её всюду —
    «Кто там?», — спросила она, — и ошиблась ровно тем, о чём сам дом и говорит: применила
    правило там, где стои́т исключение.

        ДОМ, ПОКАЗЫВАЮЩИЙ ПРАВИЛО, ОБЯЗАН ЕМУ СЛЕДОВАТЬ ПЕРВЫМ; ИНАЧЕ ОН УЧИТ СВОЕЙ
        ОШИБКЕ ТОЧНЕЕ, ЧЕМ СВОИМ ЗАКОНОМ.
    """
    внутри = _заглавная(текст) + ("" if знак == "." else знак)
    разделитель = ", — " if знак == "." else " — "
    return f"{ЁЛОЧКИ[0]}{внутри}{ЁЛОЧКИ[1]}{разделитель}{автор}."


def автор_впереди(текст, знак, автор):
    """А: «П».  — двоеточие перед речью, знак конца ВНУТРИ кавычек, точка за ними."""
    внутри = _заглавная(текст) + ("" if знак == "." else знак)
    хвост = "." if знак == "." else ""
    return f"{_заглавная(автор)}: {ЁЛОЧКИ[0]}{внутри}{ЁЛОЧКИ[1]}{хвост}"


def разорвана(первый, второй, знак, автор):
    """«П, — а, — п».  — оба тире, запятая перед вторым куском."""
    хвост = "" if знак == "." else знак
    return (f"{ЁЛОЧКИ[0]}{_заглавная(первый)}, — {автор}, — {второй}{хвост}"
            f"{ЁЛОЧКИ[1]}{'.' if знак == '.' else ''}")


