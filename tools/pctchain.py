def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    # ЦЕПЬ СЧИТАЕТСЯ ШАГ ЗА ШАГОМ, А НЕ СУММОЙ ПРОЦЕНТОВ: вот показ этого.
    assert цепь(200, -10, -10) == (180, 162), "цепь считается не по шагам"
    assert _шаг(200, -20) == 160, "наивный ответ считается не так"
    assert цепь(200, 10, -10) == (220, 198), "плюс-минус вернул к началу"
    assert цепь(200, -10, 20)[1] == цепь(200, 20, -10)[1], "порядок изменил итог"
    # ДВЕ РАМКИ, СОВПАДАЮЩИЕ НА ОДНОЙ ЗАПИСИ, ДЕЛАЮТ РОД НЕРАЗЛИЧИМЫМ (14.09). Первая
    # редакция писала «стало 198, а не 200» для рода «не_возвращается», и эта запись
    # ложилась ТАКЖЕ в рамку рода «не_складываются», где «200» читалось наивным ответом.
    # Суд решал род ПОРЯДКОМ ПЕРЕБОРА рамок — то есть случайностью записи в дереве, а не
    # делом страницы. Рамки разведены, и вот страж, чтобы они не сошлись снова.
    for с, (язык, _р) in ПОКАЗЫ.items():
        совпали = [род for род, образец in _ОБРАЗЦЫ[язык] if образец.fullmatch(с)]
        assert len(совпали) == 1, f"две рамки на одной записи ({совпали}): {с}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
