#!/usr/bin/env python3
"""ДОМ ДВУХ ПРОЦЕНТОВ ПОДРЯД (14.09, куплен нулём пробы).

Замерено 14.09 по своду: «процент от процента» / «percent of a percent» — НОЛЬ строк. Мир
процента (`percent`) считает ОДИН процент от числа. Что будет, если процент взять ДВАЖДЫ,
корпус не говорит нигде — а это ровно то место, где ошибается всякий:

    ПРОЦЕНТЫ НЕ СКЛАДЫВАЮТСЯ, ИБО ВТОРОЙ БЕРЁТСЯ НЕ ОТ ТОГО ЖЕ ЧИСЛА. «Минус десять и ещё
    минус десять» есть не минус двадцать, а минус девятнадцать: вторую десятую снимают уже с
    180, а не с 200. И «плюс десять, потом минус десять» НЕ ВОЗВРАЩАЕТ к началу — прибавляли
    от 200, а снимают от 220.

ТРИ РОДА ПО ДЕЛУ:

    не_складываются   два изменения в одну сторону: итог назван И НАЗВАН НАИВНЫЙ ОТВЕТ, и
                      сказано, от какого числа берётся второй процент;
    не_возвращается   изменения в разные стороны: начало не возвращается, и сказано почему;
    порядок_не_важен  положительная сторона того же закона: переставь два изменения — итог
                      ТОТ ЖЕ. Умножение переместительно, и это стои́т показать рядом с тем,
                      что сложение процентов НЕ работает.

    ОШИБКА НАЗВАНА НА СТРАНИЦЕ, А НЕ ОБОЙДЕНА. Страница говорит не только «стало 162», но и
    «а не 160»: читатель, который иначе сложил бы проценты, видит своё число рядом с верным.

ГРАНИЦА ОБЪЯВЛЕНА: дом берёт лишь такие числа и проценты, где КАЖДЫЙ шаг даёт целое.
Дробная часть есть иное дело (она живёт в мире доли единицы), и мешать её с двумя процентами
подряд значит учить обоим наполовину.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("не_складываются", "не_возвращается", "порядок_не_важен")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "не_складываются": "два изменения в одну сторону: итог и наивный ответ рядом",
    "не_возвращается": "изменения в разные стороны: начало не возвращается",
    "порядок_не_важен": "переставь два изменения — итог тот же: умножение переместительно",
}

ЧИСЛА = (200, 300, 400, 500, 600, 800, 1000, 2000)
ШАГИ = (10, 20, 25, 50, -10, -20, -25, -50)

РАМКИ = {
    "ru": {
        "знак": {1: "+", -1: "−"},
        "не_складываются": "цена {н}. сначала {а} %, потом {б} %. стало {итог}, а не "
                           "{наивно}: второй процент берётся от {середина}, а не от {н}.",
        "не_возвращается": "цена {н}. сначала {а} %, потом {б} %. стало {итог}: к началу "
                           "не вернулось, ибо второй процент берётся от {середина}, а не "
                           "от {н}.",
        "порядок_не_важен": "цена {н}. {а} %, потом {б} % даёт {итог}; {б} %, потом {а} % "
                            "даёт тоже {итог}: порядок не меняет итога.",
    },
    "en": {
        "знак": {1: "+", -1: "−"},
        "не_складываются": "the price is {н}. first {а} %, then {б} %. it became {итог}, "
                           "not {наивно}: the second percent is taken of {середина}, not "
                           "of {н}.",
        "не_возвращается": "the price is {н}. first {а} %, then {б} %. it became {итог}: "
                           "it did not come back to the start, for the second percent is "
                           "taken of {середина}, not of {н}.",
        "порядок_не_важен": "the price is {н}. {а} %, then {б} % gives {итог}; {б} %, then "
                            "{а} % gives {итог} too: the order does not change the total.",
    },
}


def _шаг(число, процент):
    """Число после изменения на процент — или None, если вышло не целое."""
    вышло = число * (100 + процент)
    return вышло // 100 if вышло % 100 == 0 else None


def цепь(н, а, б):
    """(середина, итог) — или None, если хоть один шаг не целый."""
    середина = _шаг(н, а)
    if середина is None:
        return None
    итог = _шаг(середина, б)
    return None if итог is None else (середина, итог)


def _знак(язык, п):
    return РАМКИ[язык]["знак"][1 if п > 0 else -1] + str(abs(п))


def _род(а, б, н, итог):
    if (а > 0) == (б > 0):
        return "не_складываются"
    return "не_возвращается" if итог != н else None


def страница(язык, род, н, а, б):
    вышло = цепь(н, а, б)
    обратно = цепь(н, б, а)
    if вышло is None or обратно is None:
        return None
    середина, итог = вышло
    рамки = РАМКИ[язык]
    if род == "порядок_не_важен":
        # ПОКАЗ О ПЕРЕСТАНОВКЕ ЖИВ ЛИШЬ ТАМ, ГДЕ ОБЕ ДОРОГИ ЦЕЛЫ и итог один; иначе
        # переставлять нечего.
        # ПАРА СТРОИТСЯ ОДИН РАЗ, А НЕ ДВАЖДЫ: страница и так называет ОБА порядка, и
        # вторая страница с переставленными местами говорит ровно то же другими словами.
        if обратно[1] != итог or а >= б:
            return None
        return рамки["порядок_не_важен"].format(н=н, а=_знак(язык, а), б=_знак(язык, б),
                                                итог=итог)
    если = _род(а, б, н, итог)
    if если != род:
        return None
    наивно = _шаг(н, а + б)
    if род == "не_складываются":
        # НАИВНЫЙ ОТВЕТ ОБЯЗАН ОТЛИЧАТЬСЯ ОТ ВЕРНОГО: там, где он совпал, ошибки нет и
        # показывать нечего.
        if наивно is None or наивно == итог:
            return None
        return рамки["не_складываются"].format(н=н, а=_знак(язык, а), б=_знак(язык, б),
                                               итог=итог, наивно=наивно, середина=середина)
    return рамки["не_возвращается"].format(н=н, а=_знак(язык, а), б=_знак(язык, б),
                                           итог=итог, середина=середина)


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for н in ЧИСЛА:
                for а in ШАГИ:
                    for б in ШАГИ:
                        п = страница(язык, род, н, а, б)
                        if п:
                            вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД СЧИТАЕТ ЦЕПЬ ЗАНОВО и проверяет КАЖДОЕ число записи: середину, итог, наивный ответ и
# то, что наивный от верного ОТЛИЧАЕТСЯ. Порча любого из них меняет вердикт.
def _образцы(язык):
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык][род])
        for дыра, узор in (("н", r"\d+"), ("а", "[+−]\\d+"), ("б", "[+−]\\d+"),
                           ("итог", r"\d+"), ("наивно", r"\d+"), ("середина", r"\d+")):
            дыра_о = re.escape("{" + дыра + "}")
            первый = True
            while дыра_о in о:
                о = о.replace(дыра_о, f"(?P<{дыра}>{узор})" if первый else f"(?P={дыра})", 1)
                первый = False
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def _процент(язык, слово):
    знаки = {v: k for k, v in РАМКИ[язык]["знак"].items()}
    if слово[0] not in знаки:
        return None
    return знаки[слово[0]] * int(слово[1:])


def судить(строка):
    """(судимо, истинно) — цепь посчитана заново, и каждое число записи проверено."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            н = int(д["н"])
            а, б = _процент(язык, д["а"]), _процент(язык, д["б"])
            if а is None or б is None or н <= 0:
                return True, False
            вышло = цепь(н, а, б)
            if вышло is None:
                return True, False
            середина, итог = вышло
            if int(д["итог"]) != итог:
                return True, False
            if род == "порядок_не_важен":
                обратно = цепь(н, б, а)
                return True, обратно is not None and обратно[1] == итог and а != б
            if int(д["середина"]) != середина:
                return True, False
            if род == "не_возвращается":
                return True, (а > 0) != (б > 0) and итог != н
            наивно = _шаг(н, а + б)
            return True, ((а > 0) == (б > 0) and наивно is not None
                          and int(д["наивно"]) == наивно and наивно != итог)
    return False, True


