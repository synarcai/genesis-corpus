def чужой(символ, сдвиг):
    """Символ того же класса, отличный от данного, — сдвигом по кольцу."""
    ряд = ПО_КЛАССУ[G.РОД[символ]]
    if len(ряд) == 1:
        ряд = СИМВОЛЫ
    i = ряд.index(символ)
    return ряд[(i + 1 + сдвиг % (len(ряд) - 1)) % len(ряд)]


def близнец(символ):
    """Символ другого письма с той же сеткой (гомоглиф), или None.

    ГОМОГЛИФ ЕСТЬ ФАКТ ШРИФТА, А НЕ ОШИБКА КОРПУСА (holon, прибор имён 03.09):
    латинская C и русская С в 5×7 — одна сетка, и пара «что показывает глиф?»
    с одним именем двусмысленна. Корпус говорит правду целиком: глиф — это
    оба знака, и два письма делят его. Близнец ВЫВОДИТСЯ из таблицы
    равенством сеток, а не объявляется списком."""
    return next((c for c in G.ТАБЛИЦА if c != символ and G.ТАБЛИЦА[c] == G.ТАБЛИЦА[символ]), None)


