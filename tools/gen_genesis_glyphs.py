#!/usr/bin/env python3
"""ГЛИФОВЫЙ МИР v0 — распознавание текста как показ «сетка → символ».

Мандат владельца (02.09, вечер; reference/EMBODIED-REASONING-MANDATE.md
§L5): «исходный GENESIS уже должен давать распознавание текста и
фундаментальные основы воплощённого восприятия». Каждый символ — битовая
сетка 5×7 с именем (tools/glyphs.py — единая таблица, она же закон суда);
слово — ряд глифов через пустой столбец. Тот же глаз, что читает
ARC-сетку, читает буквы: OCR рынком, без сетей и без списков.

ЧЕТЫРЕ ПОВЕРХНОСТИ ОДНОГО ФАКТА, и каждый символ в проходе получает одну
из них по номеру прохода (не все четыре разом — иначе свод учил бы
повтор, а не закон):
  · сетка → имя      «glyph … is the capital Latin letter A.»
  · имя → сетка      «заглавная русская буква Б глифом 5×7 — …»
  · отрицание        «glyph … is not the digit 8.» — чужой символ ТОГО
                     ЖЕ класса (цифра против цифры), выбранный сдвигом
  · вопрос           «what does glyph … show? it shows the digit 7.»
СЛОВА — рядами: существительные пакетов (английские формы пакета en,
русские счётные слова дома rugram), ЧИСЛА (двух- и трёхзначные) и
ВЕРНЫЕ ВЫРАЖЕНИЯ («3+4=7», выведенные счётом, чтобы глаз не учил ложь
как картинку). Имя символа всегда несёт письмо и регистр — сетка без
письма многозначна, имя нет.
"""
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import glyphs as G  # noqa: E402
import spacegrid as S  # noqa: E402
import rugram  # noqa: E402
from layer import PASSES, emit  # noqa: E402

ЦЕЛЬ = "datasets/genesis_glyphs.txt"
СИМВОЛЫ = [с for с in G.ТАБЛИЦА if с != " "]
ПО_КЛАССУ = {}
for _с in СИМВОЛЫ:
    ПО_КЛАССУ.setdefault(G.РОД[_с], []).append(_с)

_EN = json.loads((КОРЕНЬ / "tools" / "langpacks" / "en.json")
                 .read_text(encoding="utf-8"))["noun_forms"]
СЛОВА_EN = sorted(w for w in _EN if 2 <= len(w) <= 6 and w.isalpha() and w.isascii())
СЛОВА_RU = sorted(w for w in rugram.СЧЁТНЫЕ if 2 <= len(w) <= 6 and w.isalpha()
                  and all(с in G.ТАБЛИЦА for с in w))


def чужой(символ, сдвиг):
    """Символ того же класса, отличный от данного, — сдвигом по кольцу."""
    ряд = ПО_КЛАССУ[G.РОД[символ]]
    if len(ряд) == 1:
        ряд = СИМВОЛЫ
    i = ряд.index(символ)
    return ряд[(i + 1 + сдвиг % (len(ряд) - 1)) % len(ряд)]


def показ_символа(символ, форма, сдвиг):
    сетка = G.сетка(символ)
    en, ru = G.имя_en(символ), G.имя_ru(символ)
    # ПОЛЯРНОСТЬ С ОСНОВАНИЕМ ПОСЛЕ ДВОЕТОЧИЯ (holon, 02.09: полярное слово
    # покупается сильной парой): основание — число расходящихся клеток
    # между показанной сеткой и рендером названного символа, и суд его
    # пересчитывает.
    if форма == 0:
        return [f"glyph {сетка} is {en}: {S.основание_en(0)}.",
                f"глиф {сетка} — это {ru}: {S.основание_ru(0)}."]
    if форма == 1:
        # ВОПРОСНАЯ ПОВЕРХНОСТЬ ИМЕНИ → СЕТКИ (М-146): ответ — само утверждение.
        if сдвиг % 2:
            return [f"what is {en} as a 5×7 glyph? {en} as a 5×7 glyph is {сетка}.",
                    f"какова {ru} глифом 5×7? {ru} глифом 5×7 — {сетка}."]
        return [f"{en} as a 5×7 glyph is {сетка}.", f"{ru} глифом 5×7 — {сетка}."]
    if форма == 2:
        ч = чужой(символ, сдвиг)
        k = S.разница(G.ТАБЛИЦА[символ], G.ТАБЛИЦА[ч])
        return [f"glyph {сетка} is not {G.имя_en(ч)}: {S.основание_en(k)}.",
                f"глиф {сетка} — не {G.имя_ru(ч)}: {S.основание_ru(k)}."]
    # ОТВЕТ ЕСТЬ САМО УТВЕРЖДЕНИЕ, а не «it shows»: род сетка→знак получает вопрос.
    return [f"what does glyph {сетка} show? glyph {сетка} is {en}.",
            f"что показывает глиф {сетка}? глиф {сетка} — это {ru}."]


def показ_слова(слово, en, номер):
    сетка = G.слово_сеткой(слово)
    род_en = "number" if слово.isdigit() else ("expression" if any(
        з in слово for з in "+−×÷=") else "word")
    род_ru = {"number": "число", "expression": "выражение", "word": "слово"}[род_en]
    if номер % 4 == 0:
        return (f"the {род_en} \"{слово}\" in 5×7 glyphs is {сетка}." if en else
                f"{род_ru} «{слово}» глифами 5×7 — {сетка}.")
    if номер % 4 == 1:
        return (f"glyph rows {сетка} read as the {род_en} \"{слово}\"." if en else
                f"ряд глифов {сетка} читается как {род_ru} «{слово}».")
    # ВОПРОСНЫЕ ПОВЕРХНОСТИ СЛОВА (М-146): ответ — само утверждение.
    if номер % 4 == 2:
        return (f"what is the {род_en} \"{слово}\" in 5×7 glyphs? the {род_en} \"{слово}\" in 5×7 glyphs is {сетка}." if en else
                f"каково {род_ru} «{слово}» глифами 5×7? {род_ru} «{слово}» глифами 5×7 — {сетка}.")
    return (f"what do glyph rows {сетка} read as? glyph rows {сетка} read as the {род_en} \"{слово}\"." if en else
            f"как читается ряд глифов {сетка}? ряд глифов {сетка} читается как {род_ru} «{слово}».")


def выражение(шаг, i):
    a = 2 + (шаг * 7 + i * 3) % 9
    b = 1 + (шаг * 5 + i) % 9
    return [f"{a}+{b}={a + b}", f"{a}×{b}={a * b}", f"{a + b}−{b}={a}"][i % 3]


import laws  # noqa: E402


def pass_shows(шаг):
    вон = list(laws.ступень("glyphs"))
    for k, символ in enumerate(СИМВОЛЫ):
        форма = (шаг + k) % 4
        пара = показ_символа(символ, форма, шаг + k)
        вон.append(пара[(шаг + k) % 2])
    for i in range(24):
        en = СЛОВА_EN[(шаг * 11 + i * 7) % len(СЛОВА_EN)]
        ru = СЛОВА_RU[(шаг * 13 + i * 5) % len(СЛОВА_RU)]
        вон.append(показ_слова(en, True, i))
        вон.append(показ_слова(ru, False, i))
    for i in range(12):
        число = str(10 + (шаг * 37 + i * 29) % 990)
        вон.append(показ_слова(число, i % 2 == 0, i))
        вон.append(показ_слова(выражение(шаг, i), i % 2 == 1, i))
    return вон


def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
