НЕ_ТОТ_ЗНАК = "сетка — не тот знак, и сказано на сколько клеток"
ДВА_ПИСЬМА = "один глиф у двух письмён"


def показ_символа(символ, форма, сдвиг):
    сетка = G.сетка(символ)
    en, ru = G.имя_en(символ), G.имя_ru(символ)
    двойник = близнец(символ)
    if двойник is not None and форма in (0, 3):
        en2, ru2 = G.имя_en(двойник), G.имя_ru(двойник)
        if форма == 0:
            return ДВА_ПИСЬМА, [f"glyph {сетка} is {en} and {en2}: the two scripts share it.",
                    f"глиф {сетка} — это {ru} и {ru2}: два письма делят его."]
        return ДВА_ПИСЬМА, [f"what does glyph {сетка} show? glyph {сетка} is {en} and {en2}: the two scripts share it.",
                f"что показывает глиф {сетка}? глиф {сетка} — это {ru} и {ru2}: два письма делят его."]
    # ПОЛЯРНОСТЬ С ОСНОВАНИЕМ ПОСЛЕ ДВОЕТОЧИЯ (holon, 02.09: полярное слово
    # покупается сильной парой): основание — число расходящихся клеток
    # между показанной сеткой и рендером названного символа, и суд его
    # пересчитывает.
    if форма == 0:
        return СЕТКА_В_ЗНАК, [f"glyph {сетка} is {en}: {S.основание_en(0)}.",
                f"глиф {сетка} — это {ru}: {S.основание_ru(0)}."]
    if форма == 1:
        # ВОПРОСНАЯ ПОВЕРХНОСТЬ ИМЕНИ → СЕТКИ (М-146): ответ — само утверждение.
        if сдвиг % 2:
            return ЗНАК_В_СЕТКУ, [f"what is {en} as a 5×7 glyph? {en} as a 5×7 glyph is {сетка}.",
                    f"какова {ru} глифом 5×7? {ru} глифом 5×7 — {сетка}."]
        return ЗНАК_В_СЕТКУ, [f"{en} as a 5×7 glyph is {сетка}.", f"{ru} глифом 5×7 — {сетка}."]
    if форма == 2:
        ч = чужой(символ, сдвиг)
        k = S.разница(G.ТАБЛИЦА[символ], G.ТАБЛИЦА[ч])
        return НЕ_ТОТ_ЗНАК, [f"glyph {сетка} is not {G.имя_en(ч)}: {S.основание_en(k)}.",
                f"глиф {сетка} — не {G.имя_ru(ч)}: {S.основание_ru(k)}."]
    # ОТВЕТ ЕСТЬ САМО УТВЕРЖДЕНИЕ, а не «it shows»: род сетка→знак получает вопрос.
    return СЕТКА_В_ЗНАК, [f"what does glyph {сетка} show? glyph {сетка} is {en}.",
            f"что показывает глиф {сетка}? глиф {сетка} — это {ru}."]


def показ_слова(слово, en, номер):
    сетка = G.слово_сеткой(слово)
    род_en = "number" if слово.isdigit() else ("expression" if any(
        з in слово for з in "+−×÷=") else "word")
    род_ru = {"number": "число", "expression": "выражение", "word": "слово"}[род_en]
    # ИМЯ РОДА ЗДЕСЬ УЖЕ СОСЧИТАНО (`род_ru`) И ОСТАВАЛОСЬ НАЗВАТЬ ЕГО ВСЛУХ, прибавив
    # СТОРОНУ ПЕРЕВОДА: «слово → ряд глифов» и «ряд глифов → слово» суть два разных дела,
    # а вопросная поверхность каждого — то же дело, спрошенное.
    в_глифы = f"{род_ru} → ряд глифов"
    из_глифов = f"ряд глифов → {род_ru}"
    if номер % 4 == 0:
        return в_глифы, (f"the {род_en} \"{слово}\" in 5×7 glyphs is {сетка}." if en else
                f"{род_ru} «{слово}» глифами 5×7 — {сетка}.")
    if номер % 4 == 1:
        return из_глифов, (f"glyph rows {сетка} read as the {род_en} \"{слово}\"." if en else
                f"ряд глифов {сетка} читается как {род_ru} «{слово}».")
    # ВОПРОСНЫЕ ПОВЕРХНОСТИ СЛОВА (М-146): ответ — само утверждение.
    if номер % 4 == 2:
        return в_глифы, (f"what is the {род_en} \"{слово}\" in 5×7 glyphs? the {род_en} \"{слово}\" in 5×7 glyphs is {сетка}." if en else
                f"каково {род_ru} «{слово}» глифами 5×7? {род_ru} «{слово}» глифами 5×7 — {сетка}.")
    return из_глифов, (f"what do glyph rows {сетка} read as? glyph rows {сетка} read as the {род_en} \"{слово}\"." if en else
            f"как читается ряд глифов {сетка}? ряд глифов {сетка} читается как {род_ru} «{слово}».")


def выражение(шаг, i):
    a = 2 + (шаг * 7 + i * 3) % 9
    b = 1 + (шаг * 5 + i) % 9
    return [f"{a}+{b}={a + b}", f"{a}×{b}={a * b}", f"{a + b}−{b}={a}"][i % 3]


import laws  # noqa: E402


def _положить(вон, пара, язык):
    """Показ кладётся ВМЕСТЕ СО СВОИМ РОДОМ И ЯЗЫКОМ, названными там, где они сосчитаны.

    ЗДЕСЬ АЗБУКА НЕ РАЗЛИЧАЕТ ЯЗЫКОВ, И ЭТО СВОЙСТВО САМОГО ДОМА (15.09). Дом глифов
    ГОВОРИТ О БУКВАХ обеих азбук, и английская страница «glyph … is the capital Latin letter
    A and the capital Cyrillic letter А» несёт кириллицу В КАВЫЧКАХ РЕЧИ. Мера по начертанию
    назвала бы её русскою — и была бы неправа ровно там, где дом учит различать письмена.

        ГДЕ ДОМ ГОВОРИТ О ЧУЖОЙ АЗБУКЕ, АЗБУКА ПЕРЕСТАЁТ БЫТЬ ПРИЗНАКОМ ЯЗЫКА. Язык берётся
        у строителя: он выбрал сторону пары и знает её точно.
    """
    род, строка = пара
    вон.род, вон.язык = род, язык
    вон.append(строка)


def pass_shows(шаг):
    # ОПРЕДЕЛЕНИЕ ПРИНАДЛЕЖИТ ТОМУ ДЕЛУ, КОТОРОЕ ОНО ДЕЛАЕТ ВОЗМОЖНЫМ (14.09). Восемь
    # строк ступени одинаковы во всех проходах и родом дали бы миру род в восемь страниц
    # — ниже закона массы. «Глиф есть сетка 5×7» есть страница о чтении сетки; «ряд
    # глифов есть строка глифов через пустой столбец» — страница о СБОРКЕ ряда.
    вон = Сбор()
    for строка, k in laws.ступень_по_законам("glyphs"):
        вон.род = (СЕТКА_В_ЗНАК, "слово → ряд глифов")[k]
        вон.язык = bilang.азбукой(строка)      # ступень закона: своя азбука, чужой нет
        вон.append(строка)
    # ТОТ ЖЕ СЦЕП, ЧТО И НИЖЕ, И ОН ЖЕ СНЯТ (15.09): форма бралась по `(шаг + k) % 4`, а язык
    # по `(шаг + k) % 2` — и всякая нечётная форма выходила только по-русски. Оттого род
    # «знак → сетка» (форма 1) не сказал по-английски ни слова, а «один глиф у двух письмён»
    # (форма 3) — тем более. Язык берётся ныне от ЧЕТВЁРКИ форм: при неподвижной форме k
    # растёт на четыре, и чётность четвёрки меняется на каждом её повторе.
    for k, символ in enumerate(СИМВОЛЫ):
        форма = (шаг + k) % 4
        род, пара = показ_символа(символ, форма, шаг + k)
        сторона = ((шаг + k) // 4) % 2
        вон.род, вон.язык = род, ("en", "ru")[сторона]
        вон.append(пара[сторона])
    for i in range(24):
        en = СЛОВА_EN[(шаг * 11 + i * 7) % len(СЛОВА_EN)]
        ru = СЛОВА_RU[(шаг * 13 + i * 5) % len(СЛОВА_RU)]
        _положить(вон, показ_слова(en, True, i), "en")
        _положить(вон, показ_слова(ru, False, i), "ru")
    # НАПРАВЛЕНИЕ И ЯЗЫК СЦЕПИЛИСЬ ОДНИМ СЧЁТЧИКОМ, И ЭТО ВИДНО ЛИШЬ МЕРОЙ (15.09). Сторона
    # перевода бралась по `номер % 4`, а язык — по `i % 2`, и оба счётчика суть один: всякое
    # чётное i давало «в глифы» и по-английски разом. Оттого четыре рода жили на одном языке
    # — «число → ряд глифов» только по-английски, «ряд глифов → число» только по-русски, —
    # и ни одна страница не была ложью: дом просто ни разу не сказал половины того, что умел.
    #
    #     ДВА ПРИЗНАКА, ВЗЯТЫЕ ОТ ОДНОГО СЧЁТЧИКА, ЕСТЬ ОДИН ПРИЗНАК ПОД ДВУМЯ ИМЕНАМИ.
    #
    # Язык берётся ныне от `i // 2`: направление меняется на каждом шаге, язык — на каждом
    # втором, и все четыре сочетания звучат.
    for i in range(12):
        число = str(10 + (шаг * 37 + i * 29) % 990)
        по_английски = (i // 2) % 2 == 0
        _положить(вон, показ_слова(число, по_английски, i), "en" if по_английски else "ru")
        _положить(вон, показ_слова(выражение(шаг, i), not по_английски, i),
                  "ru" if по_английски else "en")
    return вон


