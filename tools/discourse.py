#!/usr/bin/env python3
"""ДОМ РЕЧИ — ответ-рассуждение как ОДИН ЛЕДЖЕР в несколько предложений.

Слово коллегии (03.09, владелец: «точная причина бедности текстов и
рассуждений»): 98 % ответов корпуса — одно предложение в шесть слов, связка
вывода стоит в 1,7 % ответов, а свидетель, который у корпуса есть, сжат в
счёт после двоеточия и в речь не развёрнут; закон живёт отдельной строкой и
к вердикту не пришит. Организм зеркалит корпус: отвечает одним предложением.

ФОРМА РАССУЖДЕНИЯ ОДНА НА КОРПУС (согласована с holon 03.09), И ОНА ЗДЕСЬ:

    {вопрос}? {вердикт}: {свидетель}. {связка} {вывод}. {закон}.
    why …? {потому что} {свидетель}: {вывод}. {закон}.

Четыре части суть четыре судимые вещи: ВЕРДИКТ СО СВИДЕТЕЛЕМ ПОСЛЕ
ДВОЕТОЧИЯ — та же форма полярности, что покупают рынки организма («нет:
91 = 7 × 13»), свидетель — счёт, который суд мира пересчитывает; ВЫВОД —
своё предложение, открытое связкой как частью формы, и оно ОБЯЗАНО нести
величины леджера («значит у 91 есть делитель 7, кроме 1 и себя»), иначе
суд не отличит вывод от украшения; ЗАКОН — общее утверждение БЕЗ чисел
вопроса, чьи слова покрывают понятие рамки, — объявленное определение мира,
живущее в мире и отдельной строкой, чтобы организм купил его носителем и
пришил к вердикту сам. СВЯЗКА объявлена пакетом языка (`connectives`) —
для организма это слово формы, для суда — замкнутое множество; чужое слово
на её месте есть ложь формы, не молчание. Ложный закон — не в корпус, а в
стенд (t9_reasoning.jsonl, отрицательный контроль суда verum). Дом только
СОСТАВЛЯЕТ и РАЗБИРАЕТ; истинность частей судят суды миров.

Ответ открывается величинами вопроса в его порядке (М-145).
"""
import json
import pathlib
import re

ПАКЕТЫ = pathlib.Path(__file__).resolve().parent / "langpacks"


def _связки():
    вон = {}
    for яз in ("en", "ru"):
        вон[яз] = json.loads((ПАКЕТЫ / f"{яз}.json").read_text(encoding="utf-8"))["connectives"]
    return вон


СВЯЗКИ = _связки()
# СВЯЗКА ВЫВОДА (после свидетеля) и СВЯЗКА ПРИЧИНЫ (после «почему») — две
# роли, объявленные поимённо: не всякая связка годится в обе.
ВЫВОДНЫЕ = {"en": ("therefore", "so", "hence", "thus"), "ru": ("значит", "поэтому", "стало быть", "следовательно")}
ПРИЧИННЫЕ = {"en": ("because", "since"), "ru": ("потому что", "так как")}
for яз in ("en", "ru"):
    assert set(ВЫВОДНЫЕ[яз]) <= set(СВЯЗКИ[яз]) and set(ПРИЧИННЫЕ[яз]) <= set(СВЯЗКИ[яз]), яз
ПОЧЕМУ = {"en": "why", "ru": "почему"}


# ОДНА СВЯЗКА НА ЯЗЫК И РОЛЬ В ПОКАЗЕ (holon, 03.09: форма организма — вся
# строка ответа с дырками леджера, одна на полярность; связка, менявшаяся
# показ от показа, дробила форму на четыре и делила её массу). Суд читает
# любую связку пакета; показ пишет первую. `k` оставлен подписью — он больше
# не выбирает.
def рассуждение(язык, вопрос, вердикт, свидетель, вывод, закон, k=0):
    """«{вопрос}? {вердикт}: {свидетель}. {связка} {вывод}. {закон}.»"""
    связка = ВЫВОДНЫЕ[язык][0]
    return f"{вопрос}? {вердикт}: {свидетель}. {связка} {вывод}. {закон}"


def рассуждение_величины(язык, вопрос, свидетель, вывод, закон, k=0):
    """ОТВЕТ ОТКРЫВАЕТ РАССКАЗ (holon + omega-f2 03.09): «{вопрос}? {вывод}:
    {свидетель}. {закон}.» — та же форма, что у вердикта «да: свидетель»:
    голова ответа — вывод (значение = последнее новое число головы до первого
    двоеточия), хвост — леджер и закон. Прежняя форма «{свидетель}. значит
    {вывод}.» открывала тот же вопрос иначе, чем простой ответ, — два
    рассказа одного вопроса (класс tellings-differ). Если звено уже стоит в
    выводе (геометрия: «has area 7 × 8 = 56»), свидетель не повторяется."""
    if свидетель in вывод:
        return f"{вопрос}? {вывод}. {закон}"
    return f"{вопрос}? {вывод}: {свидетель}. {закон}"


def почему(язык, вопрос_почему, свидетель, вывод, закон, k=0):
    """«why …? because {свидетель}: {вывод}. {закон}.»"""
    связка = ПРИЧИННЫЕ[язык][0]
    return f"{вопрос_почему}? {связка} {свидетель}: {вывод}. {закон}"


# --------------------------------------------------------------- РАЗБОР

def _образцы():
    вон = {}
    for яз in ("en", "ru"):
        выв = "|".join(re.escape(с) for с in sorted(ВЫВОДНЫЕ[яз], key=len, reverse=True))
        прич = "|".join(re.escape(с) for с in sorted(ПРИЧИННЫЕ[яз], key=len, reverse=True))
        вон[яз] = (
            re.compile(rf"^(?P<вопрос>[^?]+)\? (?:(?P<вердикт>[^:.]+): )?(?P<свидетель>[^.]+)\. (?P<связка>{выв}) (?P<вывод>[^.]+)\. (?P<закон>.+)$"),
            re.compile(rf"^(?P<вопрос>{ПОЧЕМУ[яз]} [^?]+)\? (?P<связка>{прич}) (?P<свидетель>.+?): (?P<вывод>[^.]+)\. (?P<закон>.+)$"),
            # ответ о величине: голова до первого двоеточия — вывод, за ним
            # свидетель (леджер) до точки, затем закон; свидетеля может не быть
            re.compile(r"^(?P<вопрос>[^?]+)\? (?P<вывод>[^:.]+)(?:: (?P<свидетель>[^.]+))?\. (?P<закон>.+)$"),
        )
    return вон


ОБРАЗЦЫ = _образцы()


# СВЯЗКА НЕ ИЗ ПАКЕТА — ЛОЖЬ ФОРМЫ, А НЕ МОЛЧАНИЕ: строка с очертанием
# рассуждения и чужим словом на месте связки разбирается с пометой
# связка=None, и суд мира зовёт её ложью (порча «therefore → however»).
_ЧУЖАЯ = {
    "en": re.compile(r"^(?P<вопрос>[^?]+)\? (?:(?P<вердикт>[^:.]+): )?(?P<свидетель>[^.]+)\. (?P<связка>[a-z]+) (?P<вывод>[^.]+)\. (?P<закон>.+)$"),
    "ru": re.compile(r"^(?P<вопрос>[^?]+)\? (?:(?P<вердикт>[^:.]+): )?(?P<свидетель>[^.]+)\. (?P<связка>[а-яё]+(?: [а-яё]+)?) (?P<вывод>[^.]+)\. (?P<закон>.+)$"),
}


_ЧУЖАЯ_ПОЧЕМУ = {
    "en": re.compile(r"^(?P<вопрос>why [^?]+)\? (?P<связка>[a-z]+) (?P<свидетель>[^:]+): (?P<вывод>[^.]+)\. (?P<закон>.+)$"),
    "ru": re.compile(r"^(?P<вопрос>почему [^?]+)\? (?P<связка>[а-яё]+(?: [а-яё]+)?) (?P<свидетель>[^:]+): (?P<вывод>[^.]+)\. (?P<закон>.+)$"),
}


def части(строка, язык):
    """dict частей рассуждения (вопрос, вердикт|None, свидетель, связка,
    вывод, закон), или None — строка не рассуждение этой формы.
    Связка вне пакета возвращается как None при прочих частях."""
    с = строка.strip()
    for о in ОБРАЗЦЫ[язык]:
        м = о.match(с)
        if м:
            d = м.groupdict()
            d.setdefault("вердикт", None)
            d.setdefault("связка", None)
            d.setdefault("свидетель", None)
            return d
    м = _ЧУЖАЯ[язык].match(с)
    if м and (м.group("вердикт") is None or м.group("вердикт").strip().lower() in ("yes", "no", "да", "нет")):
        d = м.groupdict()
        d["связка"] = ""            # чужая связка: не None (форма величины), а пустая — ложь формы
        return d
    м = _ЧУЖАЯ_ПОЧЕМУ[язык].match(с)
    if м:
        d = м.groupdict()
        d["связка"] = ""
        d["вердикт"] = None
        return d
    return None


def почему_ли(ч_):
    """Вопрос «почему …?» — по первому слову вопроса."""
    return ч_["вопрос"].split(" ", 1)[0].lower() in ПОЧЕМУ.values()


def форма_верна(ч_, язык):
    """Связка на своём месте: у «почему» — причинная из пакета; у ответа о
    величине (ОТВЕТ ОТКРЫВАЕТ РАССКАЗ) связки нет; чужая связка — ложь."""
    св = ч_["связка"]
    if св == "":
        return False
    if почему_ли(ч_):
        return св in ПРИЧИННЫЕ[язык]
    return св is None


# ------------------------------------ РАССУЖДЕНИЕ МИРА О ВЕЛИЧИНЕ (общее)
# Мир, чьи утверждения несут звенья цепи и чьи законы объявлены в доме
# законов, получает рассуждение БЕЗ своего судьи рассуждения: свидетель —
# одно звено утверждения, вывод — само утверждение мира (его судит суд мира),
# закон — из свода мира. Один судья на все такие миры; дом делит с судами
# определение формы, вывод же (истинность утверждения) остаётся за миром.
ЗВЕНО = re.compile(r"^-?\d+ [+−×÷] -?\d+ = -?\d+$")


def рассуждение_мира(язык, вопрос, звено, утверждение, закон):
    """«{вопрос}? {звено}. {связка} {утверждение}. {закон}» — утверждение без
    конечной точки; звено — «a op b = c» из его цепи."""
    return рассуждение_величины(язык, вопрос, звено, утверждение.rstrip("."), закон)


def почему_мира(язык, вопрос_почему, звено, утверждение, закон):
    return почему(язык, вопрос_почему, звено, утверждение.rstrip("."), закон)


def судить_рассуждение_мира(строка, судить_мира, законы_языка):
    """(судимо, истинно) для рассуждения мира, или None — не рассуждение.

    `судить_мира` — суд утверждений мира; `законы_языка` — {язык: множество
    строк-законов}. Ложь: чужая связка, вердикт словом там, где его нет,
    закон не из свода, свидетель не звено или не из цепи вывода, вывод не
    истинен по суду мира, вопрос не о том же (дом пары)."""
    import asking
    с = строка.strip()
    язык = "ru" if re.search(r"[а-яё]", с) else "en"
    ч_ = части(с, язык)
    if ч_ is None or ч_["закон"] not in законы_языка.get(язык, ()):
        return None
    if ч_["вердикт"] is not None or not форма_верна(ч_, язык):
        return True, False
    if почему_ли(ч_):
        # «почему …? потому что {звено}: {утверждение}. {закон}» — звено из цепи утверждения
        if not ЗВЕНО.match(ч_["свидетель"]) or ч_["свидетель"] not in ч_["вывод"]:
            return True, False
        утверждение = ч_["вывод"] + "."
    else:
        # ОТВЕТ ОТКРЫВАЕТ РАССКАЗ: утверждение мира — голова и, если есть,
        # леджер за двоеточием; каждое звено леджера — «a op b = c».
        свидетель = ч_["свидетель"]
        if свидетель is not None and not all(ЗВЕНО.match(з.strip()) for з in свидетель.split(", ")):
            return True, False
        утверждение = ч_["вывод"] + (f": {свидетель}" if свидетель else "") + "."
    судимо, истинно = судить_мира(утверждение)
    if not (судимо and истинно):
        return True, False
    пара = asking.пара(с)
    return True, bool(пара) and asking.о_том_же(пара[0], пара[1])
