def добыть(сочинение, страница, кэш):
    файл = кэш / f"{сочинение.имя}_{страница}.html"
    if файл.is_file():
        return файл.read_text(encoding="utf-8"), False
    адрес = f"{ХОЗЯИН}/{сочинение.каталог}/{страница}.shtml"
    з = urllib.request.Request(адрес, headers={"User-Agent": "genesis-corpus shelf_libru/1.0 (research corpus)"})
    with urllib.request.urlopen(з, timeout=60) as r:
        текст = r.read().decode("cp1251", "replace")
    файл.parent.mkdir(parents=True, exist_ok=True)
    файл.write_text(текст, encoding="utf-8")
    return текст, True


def тело(страница_html):
    """(абзацы, остаток разметки) — только между вехами сочинения."""
    н = НАЧАЛО.search(страница_html)
    к = КОНЕЦ.search(страница_html, н.end() if н else 0)
    кусок = страница_html[н.end():к.start()] if н and к else страница_html
    кусок = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", кусок, flags=re.S | re.I)
    # ПЕРЕНОС В ИСТОЧНИКЕ — ПРОБЕЛ, А НЕ АБЗАЦ (Герцен 03.09: страница без
    # <dd>/<p>, текст перенесён по ~80 знаков, и каждая строка стала абзацем —
    # мера речью упала до 32 %). Абзац кончается пустой строкой или тегом
    # абзаца; одиночный перенос — пробел, как читает его всякий браузер.
    кусок = re.sub(r"\n[ \t]*\n", "\x00", кусок)
    кусок = кусок.replace("\n", " ").replace("\x00", "\n")
    кусок = re.sub(r"<(?:br\s*/?|/p|/dd|/div|/pre|/h\d)>", "\n", кусок, flags=re.I)
    кусок = html.unescape(ТЕГ.sub(" ", кусок))
    абзацы = []
    for строка in кусок.splitlines():
        строка = re.sub(r"\s+", " ", строка).strip()
        if len(строка.split()) >= 2 and not СЛУЖЕБНАЯ.match(строка):
            абзацы.append([строка])
    остаток = sum(len(ОСТАТОК.findall(" ".join(б[0] for б in абзацы))) for _ in (0,))
    return абзацы, остаток


def ковать(сочинение, кэш, в_манифест):
    блоки, остаток, взято = [], 0, 0
    for страница in сочинение.страницы:
        сырое, свежее = добыть(сочинение, страница, кэш)
        аб, ост = тело(сырое)
        блоки += аб
        остаток += ост
        взято += свежее
    мир, хвост = shelf_forge.разрезать(блоки)
    папка = КОРЕНЬ / "shelf" / "ru"
    shelf_forge.записать(папка / f"{сочинение.имя}.txt", мир)
    shelf_forge.записать(папка / f"{сочинение.имя}.holdout.txt", хвост)
    файл = папка / f"{сочинение.имя}.txt"
    слов = sum(len(б[0].split()) for б in мир)
    print(f"  {сочинение.имя:26} страниц {len(сочинение.страницы):2} взято у источника {взято:2} абзацев {len(мир):6} отложено {len(хвост):5} слов {слов:8} байт {файл.stat().st_size:9} остаток разметки {остаток}")
    if в_манифест:
        узел = shelf_kinds.объявление_мира(
            имя=сочинение.имя, файл=f"shelf/ru/{сочинение.имя}.txt",
            жанр=f"{сочинение.заглавие} — {сочинение.автор}; lib.ru/Классика",
            язык="ru", тема=сочинение.тема, плотность=сочинение.плотность, издано=сочинение.издано,
            происхождение=f"lib.ru:{сочинение.каталог}/{'+'.join(сочинение.страницы)}",
            судится=[], размер=файл.stat().st_size)
        узел["автор"] = сочинение.автор
        заменено = shelf_scan.вписать(узел)
        print(f"  МАНИФЕСТ: {'заменено' if заменено else 'добавлено'} {сочинение.имя}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--кэш", required=True)
    ap.add_argument("--только", default="")
    ap.add_argument("--манифест", action="store_true")
    а = ap.parse_args()
    хотим = set(а.только.split(",")) if а.только else None
    for с in ПОЛКА:
        if хотим and с.имя not in хотим:
            continue
        ковать(с, pathlib.Path(а.кэш), а.манифест)
    return 0


if __name__ == "__main__":
    sys.exit(main())
