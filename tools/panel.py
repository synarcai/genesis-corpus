#!/usr/bin/env python3
"""ПАЛАТА СУДОВ: один дом, знающий, КАК спросить у всех судов о строке.

ДВА ПРИБОРА СПРАШИВАЛИ ОДНО И ТО ЖЕ ПО-РАЗНОМУ. Порядок зова судов,
особые случаи (арифметика режет строку на предложения, разметка и
формулы требуют слоя, пласт языка судится словарём пакета) жили внутри
прибора судимости. Всякий, кому понадобится тот же вопрос, написал бы
их заново — и разошёлся бы в первый же день. Здесь этот вопрос ОДИН.

ЗАЧЕМ ЭТО ПОНАДОБИЛОСЬ ВТОРОМУ ЧИТАТЕЛЮ, И ЭТО ГЛАВНОЕ:

    СЛОЙ НЕ МОЖЕТ БЫТЬ ЗАПИСАН, ЕСЛИ ХОТЬ ОДНА ЕГО СТРОКА НЕСУДИМА
    ИЛИ ХОТЬ ОДИН СУД ЗОВЁТ ЕЁ ЛОЖЬЮ.

Прежде порядок был иной: генератор писал файл, а суды спрашивали
потом, обходом. Это ловит дефект, но ДОПУСКАЕТ ЕГО СУЩЕСТВОВАНИЕ — и
сегодня допустило дважды за час: «1 days after saturday» (английское
согласование в слое календаря) и шесть честных русских ставок,
объявленных ложью чужим судом из-за совпадения формы. Оба поймал
обход, и оба УСПЕЛИ ЛЕЧЬ В КОРПУС.

Проверка в момент записи превращает дефект из ОБНАРУЖИМОГО в
НЕВОЗМОЖНЫЙ. Это разница между «мы это ловим» и «этого не бывает», и
она есть разница между приборной дисциплиной и архитектурной
целостностью.

ПАЛАТА, КОТОРОЙ НЕТ, НЕ ДОЛЖНА МОЛЧА ПРОПУСКАТЬ. Если суды не
загрузились (сборка в пустом дереве, урезанное окружение), запись не
запрещается — но число живых судов ВОЗВРАЩАЕТСЯ вызывающему, и он
обязан сказать о нём вслух. Тихо выключенная охрана хуже, чем её
отсутствие: отсутствие видно.
"""

import importlib
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
for _где in (КОРЕНЬ / "courts", КОРЕНЬ / "tools", КОРЕНЬ / "scripts"):
    if _где.is_dir() and str(_где) not in sys.path:
        sys.path.insert(0, str(_где))

# Суды с особым зовом — каждый по своей причине, названной здесь.
ОСОБЫЕ = ("arith", "logic", "markup", "formula", "langlayer")
# Прочие судят строку одним доводом.
ПРОСТЫЕ = ("algo", "physics", "cyber", "notation", "program", "statistics",
           "proof", "machine", "episode", "copula", "unit", "number",
           "sequence", "geometry", "linalg", "calendar", "speech",
           "rugram", "physlaw", "compsci", "case", "valence",
           "inquiry", "surfaces", "markdown",
           "doctree")


def _взять(имя):
    try:
        return importlib.import_module(f"{имя}_court")
    except Exception:
        return None


class Палата:
    """Все суды разом, с их слоями и особенностями зова."""

    def __init__(self):
        self.суды = {и: с for и in ОСОБЫЕ + ПРОСТЫЕ if (с := _взять(и))}
        A = self.суды.get("arith")
        self.словарь = A.словари() if A else None
        L = self.суды.get("logic")
        self.знаки = L.имена_знаков() if L else {}

    @property
    def живых(self):
        return len(self.суды)

    def слои(self, путь):
        """Контекст файла для судов, читающих слой целиком.

        СЛОЙ ПОЛАГАЕТСЯ ВСЯКОМУ, КТО ЕГО ОБЪЯВИЛ, а не двум названным
        поимённо. Прибор судимости держал именно такой — общий — зов, и
        в этом был правее палаты; палата берёт его себе, и список
        «markup, formula» перестаёт существовать как список.
        """
        вон = {}
        for имя, суд in self.суды.items():
            если = getattr(суд, "Слой", None)
            if если is not None:
                вон[имя] = если()
                вон[имя].впитать(путь)
        ep = self.суды.get("episode")
        if ep is not None:
            ep.впитать_ставки(путь)
            ep.впитать_итоги(путь)
        return вон

    def судить(self, строка, слои=None, пласт=None):
        """(судимо, истинно, кем) — вердикт всей палаты о строке.

        ЛОЖЬ ХОТЬ ОДНОГО СУДА ЕСТЬ ЛОЖЬ: суды не голосуют. Каждый
        владеет своим родом, и найденное одним не отменяется молчанием
        прочих.
        """
        слои = слои or {}
        судимо, кем = False, []
        for имя, суд in self.суды.items():
            try:
                if имя == "arith":
                    части = [суд.судить(ч, self.словарь)
                             for ч in суд.предложения(строка)]
                    свой = next((р for р in части if р[0]), (False, True))
                elif имя == "logic":
                    свой = суд.судить(строка, self.знаки)
                elif имя == "markup":
                    свой = суд.судить(строка, слои.get("markup"))
                elif имя == "langlayer":
                    continue
                elif имя in слои:
                    свой = суд.судить(строка, слой=слои[имя])
                else:
                    свой = суд.судить(строка)
            except Exception:
                continue
            if not свой[0]:
                continue
            судимо = True
            кем.append(имя)
            if not свой[1]:
                return True, False, [имя]
        if not судимо and пласт is not None:
            # ПЛАСТ ЯЗЫКА СУДИТСЯ СЛОВАРЁМ ПАКЕТА, а не содержанием:
            # слово, объявленное языком, есть его законная строка.
            return True, True, ["langlayer"]
        return судимо, True, кем

    def пласт_файла(self, путь):
        """Словарь пакета, если файл есть пласт языка, иначе None.

        Имя пласта несёт свой язык («genesis_lang_uk» → «uk»), и
        спрашивать об этом дважды в разных домах — тот же двойник, что
        два списка судов.
        """
        LL = self.суды.get("langlayer")
        основа = pathlib.Path(путь).stem
        if LL is None or "_lang_" not in основа:
            return None
        слова, _ = LL.словарь_пакета(основа.rsplit("_", 1)[-1])
        return слова

    def судить_файл(self, путь):
        """[(строка, судимо, истинно, кем)] по всему файлу."""
        путь = pathlib.Path(путь)
        слои = self.слои(путь)
        пласт = self.пласт_файла(путь)
        вон = []
        with путь.open(encoding="utf-8", errors="replace") as поток:
            for строка in поток:
                if not строка.strip():
                    continue
                судимо, истинно, кем = self.судить(строка, слои,
                                                    пласт)
                вон.append((строка.rstrip("\n"), судимо, истинно, кем))
        return вон


_ПАЛАТА = None


def палата():
    """Одна палата на процесс — суды дороги при загрузке."""
    global _ПАЛАТА
    if _ПАЛАТА is None:
        _ПАЛАТА = Палата()
    return _ПАЛАТА
