def _взять(модуль):
    """Суд, если он загрузился; None — если нет.

    ОТКАЗ ОДНОГО СУДА НЕ ЕСТЬ ОТКАЗ ПАЛАТЫ. Суд вправе отказать о
    СЕБЕ — «источника нет, судить не вправе», — и делает это выходом с
    кодом два. Но `SystemExit` не есть `Exception`, и такой отказ
    УБИВАЛ ВЕСЬ ПРОЦЕСС вместе с палатой и её звавшим: в стенде парка
    один суд без своего генератора обрушил прибор судимости целиком, и
    честное дерево объявилось нечитаемым. Палата ловит и это: суд,
    отказавший о себе, просто отсутствует, и его отсутствие ВИДНО
    числом живых.
    """
    try:
        return importlib.import_module(модуль)
    except (Exception, SystemExit):
        return None


# РОД ТЕКСТА, КОТОРЫЙ СУД БЕРЁТСЯ СУДИТЬ. Всякий суд объявляет свой
# обход `worlds(kind="shows")` — то есть говорит прямо в коде, что
# берётся за ПОКАЗЫ и не берётся за прозу. Палата этого объявления не
# читала и звала каждый суд на всякую строку; оттого чтение прозы
# выглядело возражением суда, а было ЧТЕНИЕМ ВНЕ ПОДСУДНОСТИ. Суд
# вправе объявить иное поле `РОД_ТЕКСТА`; по умолчанию — показы.
ПО_УМОЛЧАНИЮ_РОД = "shows"


def род_текста(суд):
    """Какой род текста суд берётся судить — по его объявлению."""
    return getattr(суд, "РОД_ТЕКСТА", ПО_УМОЛЧАНИЮ_РОД)


def _строчный(модуль):
    """Судит ли модуль СТРОКУ — по имени первого довода его `судить`."""
    суд = _взять(модуль)
    если = getattr(суд, "судить", None)
    if если is None:
        return False
    try:
        доводы = list(inspect.signature(если).parameters)
    except (TypeError, ValueError):
        return False
    return bool(доводы) and доводы[0] == "строка"


def _род(модуль):
    """Короткое имя рода: им палата различает особый зов."""
    return модуль[:-len("_court")] if модуль.endswith("_court") else модуль


