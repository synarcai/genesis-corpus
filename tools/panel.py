    def __init__(self):
        # СОСТАВ БЕРЁТСЯ ОБХОДОМ, А ОБЪЯВЛЕНИЕ ЕГО СВЕРЯЕТ.
        #
        # Палата держала состав СПИСКОМ, пополняемым рукой, — ровно тот
        # порок, что был казнён у прибора судимости: список разошёлся с
        # явью в тот же день, когда рядом появились суды. Два новых
        # суда лежали в каталоге, читались, судили — и палата их не
        # знала, а стало быть ворота записи не пропускали ни одной их
        # строки: два готовых мира не собирались, и причина не была
        # видна ни в одном отчёте.
        #
        # Истина о составе есть КАТАЛОГ. Список остаётся ОБЪЯВЛЕНИЕМ —
        # он нужен читателю и прибору зависимостей, что выводит соседей
        # по строкам-литералам, — но истиной больше не является: палата
        # сверяет его с обходом и хранит расхождение под именем, чтобы
        # его назвал суд. СПИСОК, КОТОРЫЙ НАДО ПОПОЛНЯТЬ РУКОЙ,
        # РАЗОЙДЁТСЯ С ЖИВУЩИМИ; вопрос лишь в том, назовёт ли кто-то
        # день расхождения.
        # ПАЛАТА БЕРЁТ СУД, ЧЬЯ ПОДПИСЬ ОБЪЯВЛЯЕТ СТРОКУ. Каталог судов
        # держит и тех, кто судит не строку: согласование числа читает
        # ФАЙЛ ЦЕЛИКОМ («судить(путь, закон)»), правило языка — ПАКЕТ
        # («судить_пакет(путь)»). Взять их сюда значило бы звать с
        # чужими доводами; отобрать по имени — снова завести список.
        # Отбор идёт ПОДПИСЬЮ: первый довод назван «строка» — суд
        # здешний. Подпись есть объявление, и оно живёт при самом суде.
        живут = tuple(sorted(
            м for п in (КОРЕНЬ / "courts").glob("*_court.py")
            if _строчный(м := п.stem)))
        объявлены = set(ОСОБЫЕ + ПРОСТЫЕ)
        self.незаявленные = tuple(м for м in живут if м not in объявлены)
        в_каталоге = {п.stem for п in (КОРЕНЬ / "courts").glob("*.py")}
        self.призраки = tuple(sorted(объявлены - в_каталоге))
        self.суды = {_род(м): с for м in живут if (с := _взять(м))}
        # СЛУЖЕБНЫЙ НЕ ЕСТЬ СУД СТРОКИ, НО ПАЛАТЕ НУЖЕН.
        #
        # Отбор по подписи (первый довод «строка») верно отсёк тех, кто
        # судит файл и пакет, — но заодно отсёк langlayer, который
        # СТРОКУ НЕ СУДИТ ВОВСЕ: он даёт словарь пакета, которым палата
        # зачитывает пласт языка. Он выпал из состава, `пласт_файла`
        # стал возвращать None, запасной ход перестал срабатывать — и
        # 2187 строк девяти языковых пластов оказались СЛЕПЫМИ: их не
        # читал никто и не зачитывал никто.
        #
        # Нашла это соседняя рука, мерившая совсем другое, и нашла
        # ЧИСЛОМ: «зачтено словарём пакета 0 при долге 67 162». Ноль
        # там, где вчера было шестьдесят семь тысяч, есть не победа, а
        # вопрос — и он был задан вовремя.
        #
        # Служебный берётся ПОИМЁННО и живёт отдельно от судов, чтобы
        # обход строк его не звал: у него нет вердикта, есть услуга.
        self.служебные = {_род(м): с for м in ("langlayer_court",)
                          if (с := _взять(м))}
        A = self.суды.get("arith")
        self.словарь = A.словари() if A else None
        L = self.суды.get("logic")
        self.знаки = L.имена_знаков() if L else {}
        self._предметы_миров = None
        self._роды_миров = None
        self._в_покрытии = False

    @property
    def живых(self):
        return len(self.суды)

    def слои(self, путь):
        """Контекст файла для судов, читающих слой целиком.

        СЛОЙ ПОЛАГАЕТСЯ ВСЯКОМУ, КТО ЕГО ОБЪЯВИЛ, а не двум названным
        поимённо. Прибор судимости держал именно такой — общий — зов, и
        в этом был правее палаты; палата берёт его себе, и список
        «markup, formula» перестаёт существовать как список.
        """
        вон = {}
        for имя, суд in self.суды.items():
            если = getattr(суд, "Слой", None)
            if если is not None:
                вон[имя] = если()
                вон[имя].впитать(путь)
        ep = self.суды.get("episode")
        if ep is not None:
            ep.впитать_ставки(путь)
            ep.впитать_итоги(путь)
        # ФОРМЫ ПРЕДМЕТА ЭТОГО МИРА — для закона покрытия (см. `судить`). Ключ не есть
        # имя суда и ни с одним слоем не столкнётся.
        вон["#предметы"] = self._предметы(путь)
        # СЛОВАРЬ ВОПРОСА ЭТОГО МИРА — для пятого лица покрытия (см. `_непокрыто`).
        вон["#словарь"] = self._словарь_вопроса(путь)
        # РОД ТЕКСТА — для закона покрытия: он есть закон о ПОКАЗАХ (см. `_непокрыто`).
        вон["#показы"] = (self._род_текста(путь) == "shows")
        return вон

    _СЛОВО_ВОПРОСА = __import__("re").compile(r"(?<![\w-])[^\W\d_]{3,}(?![\w-])")

    def _словарь_вопроса(self, путь):
        """Слова всех вопросов ЭТОГО мира — собираются по его файлу один раз.

        СЛОВАРЬ ВОПРОСА МИРА ЗАМКНУТ (06.09): вопрос, несущий слово, которого нет ни в
        одном вопросе этого мира, не есть вопрос этого мира. Это третий брат законов
        замкнутого мира — после цифры и знака, — и он покупает то, чего не покупает
        закон пары: пара проверяет ВЕЛИЧИНЫ вопроса и их порядок, а слова — нет.

        ЗАМЕР ПРЕЖДЕ ПОСАДКИ: 1389 честных вопросных строк — падает 0 (словарь собран
        из самих строк мира); порч, ныне зовомых истиной, ловится 66 из 70. Четыре,
        проходящие мимо, названы: порча даёт слово, которое В СЛОВАРЕ МИРА ЕСТЬ («ist»
        → «is» в многоязычном `indu`, где «is» стои́т в голландских строках) — честный
        предел закона: замкнутый мир замкнут по СЛОВАРЮ, а не по языку.

        ЖИВЁТ ЗАКОН ЗДЕСЬ, А НЕ В ДОМЕ, И ЭТО КУПЛЕНО ШРАМОМ. Посаженный в 23 дома, он
        назвал ложью 135 честных строк ЧУЖИХ миров: дом не знает, чья строка перед ним,
        а затвор по форме ответа слаб — дома делят формы ответа («13 books: 11 + 2 =
        13»). Братья по семье — цифра и знак — узнают свою строку СКЕЛЕТОМ; у слова
        вопроса скелета нет, ибо порча слова рушит скелет вместе со словом.

            ЗАКОН ЗАМКНУТОГО МИРА ОБЯЗАН ЗНАТЬ, ЧЕЙ МИР ОН СУДИТ. Палата знает файл, и
            потому словарь мира живёт у неё, а не у дома.
        """
        try:
            import asking
        except Exception:
            return frozenset()
        вон = set()
        try:
            for строка in pathlib.Path(путь).read_text(
                    encoding="utf-8", errors="replace").splitlines():
                строка = строка.strip()
                if "?" not in строка:
                    continue
                пара = asking.пара(строка)
                if пара is None:
                    continue
                вон |= {м.group().lower()
                        for м in self._СЛОВО_ВОПРОСА.finditer(пара[0])}
        except OSError:
            return frozenset()
        return frozenset(вон)

    def _предметы(self, путь):
        """Формы предмета, объявленные миром этого файла (поле «ПРЕДМЕТЫ» манифеста)."""
        if self._предметы_миров is None:
            self._предметы_миров = {}
            try:
                import genesis
                for м in genesis.manifest()["worlds"]:
                    ф = м.get("ПРЕДМЕТЫ")
                    if ф:
                        self._предметы_миров[pathlib.Path(м.get("file", "")).name] = frozenset(ф)
            except Exception:
                pass
        имя = pathlib.Path(путь).name
        if имя.endswith(".ворота"):
            имя = имя[:-len(".ворота")]
        return self._предметы_миров.get(имя, frozenset())

    # ЗАКОН ПОКРЫТИЯ ВЕРДИКТА (06.09, предложен holon, замерен прежде посадки).
    #
    # ЧТО СУД НЕ ЧИТАЕТ, ТО ОН ПОДПИСЫВАЕТ. Вердикт даётся строке ЦЕЛИКОМ, а читает суд
    # её ЧАСТЬ: арифметика находит «7 = 3 × 2 + 1, остаток 1» целым и зовёт истиной всю
    # строку вместе с изувеченным вопросом «кратн ли 7 числу 3?». Пока строка была
    # НЕСУДИМА, ворота её не пускали; став судимой наполовину, она проходит.
    #
    #     ВСЯКИЙ ЗАКОН, ЧИТАЮЩИЙ ЧАСТЬ СТРОКИ, ЕСТЬ ВЫИГРЫШ ДЛЯ МЕРЫ И ПРОИГРЫШ ДЛЯ
    #     ВОРОТ, ПОКУДА ПОКРЫТИЕ ТОЛЬКО МЕРЯЕТ, А НЕ ЗАПРЕЩАЕТ.
    #
    # ПОКРЫТИЕ ЕСТЬ ЧЕТЫРЕ ВЕЩИ: предложение покрыто, если (а) судимо само, (б) есть
    # вопросная половина объявленной пары, чей ответ судим, (в) есть ОБЪЯВЛЕННЫЙ предмет
    # мира (поле `ПРЕДМЕТЫ`), или (г) суд читает его В СОСТАВЕ ЦЕЛОЙ СТРОКИ — что
    # проверяется ПОРЧЕЙ: если порча слова (а где слова нет — числа) меняет вердикт
    # строки, суд это предложение читал.
    #
    # НЕПОКРЫТАЯ СТРОКА СТАНОВИТСЯ НЕСУДИМОЙ, А НЕ ЛОЖНОЙ: мы не знаем, что она лжёт,
    # мы знаем, что не можем за неё ручаться. Молчание есть честный отказ; ворота
    # несудимое не пускают, и того довольно.
    #
    # ЦЕНА ЗАМЕРЕНА ПРЕЖДЕ ПОСАДКИ: на выборке в 12 155 истинных строк (60 на мир)
    # замолкает 4, и обе причины названы поимённо — номер пункта списка в md_latex,
    # которого не читает никто, и русский инвариант compsci, где суд при порче ЗАМОЛКАЕТ,
    # а сосед `rugram` продолжает звать строку истиной (М-131). По времени палата дороже
    # в 1,4 раза, и проверка порчей спрашивается лишь о том, что не прошло дешёвого
    # разбора.

    def судить(self, строка, слои=None, пласт=None):
        """(судимо, истинно, кем) — вердикт всей палаты о строке.

        ЛОЖЬ ХОТЬ ОДНОГО СУДА ЕСТЬ ЛОЖЬ: суды не голосуют. Каждый
        владеет своим родом, и найденное одним не отменяется молчанием
        прочих.
        """
        слои = слои or {}
        судимо, кем = False, []
        for имя, суд in self.суды.items():
            try:
                if имя == "arith":
                    # СВЯЗЬ ПАРЫ — ПО ЦЕЛОЙ СТРОКЕ, СЧЁТ — ПО ПРЕДЛОЖЕНИЯМ, ЦИТАТА В
                    # ВОПРОСЕ — ОТВЕТОМ (05.09): один суд строки у прибора и палаты.
                    части = суд.судить_строку(строка, self.словарь)
                    свой = next((р for р in части if р[0]), (False, True))
                elif имя == "logic":
                    свой = суд.судить(строка, self.знаки)
                elif имя == "markup":
                    свой = суд.судить(строка, слои.get("markup"))
                elif имя == "langlayer":
                    continue
                elif имя in слои:
                    свой = суд.судить(строка, слой=слои[имя])
                else:
                    свой = суд.судить(строка)
            except (Exception, SystemExit):
                # СУД, ОТКАЗАВШИЙ О СТРОКЕ, МОЛЧИТ О НЕЙ — И ТОЛЬКО.
                continue
            if not свой[0]:
                continue
            судимо = True
            кем.append(имя)
            if not свой[1]:
                return True, False, [имя]
        if пласт is not None and судимо:
            # СЛОВАРЬ ПЛАСТА ЕСТЬ ЗАКОН ПЛАСТА, А НЕ ЗАПАСНОЙ ХОД (08.09).
            #
            # Проверка стояла под «if not судимо»: словарь читался ЛИШЬ ТОГДА, КОГДА МОЛЧАЛИ
            # ВСЕ ПРОЧИЕ. Оттого сосед, прочитавший ПОЛОВИНУ строки, закрывал ему рот:
            # «wa ist fünfundvierzig durch fünf? fünfundvierzig durch fünf gleich neun»
            # читается судом арифметики по числительным, зовётся истиной — и «wa», слова, не
            # объявленного немецким пакетом, не видит никто.
            #
            #     СЛОВАРЬ, ЧИТАЕМЫЙ ЛИШЬ В МОЛЧАНИИ ПРОЧИХ, ЕСТЬ НЕ ЗАКОН, А ЗАПАСНОЙ ХОД:
            #     ЕГО ГАСИТ ПЕРВЫЙ ЖЕ СОСЕД, ПРОЧИТАВШИЙ ХОТЬ СЛОВО.
            #
            # ЦЕНА ЗАМЕРЕНА, А НЕ ОБЕЩАНА: обход всех 29 пластов (94 128 строк) нашёл строк
            # с необъявленным словом РОВНО НОЛЬ. Закон, ставший законом, не роняет ни одной
            # честной страницы — он лишь перестаёт молчать о порченых.
            LL = self.служебные.get("langlayer")
            if LL is not None:
                без_пробела = self.без_пробела.get(id(пласт), False)
                if LL.чужие(строка, пласт, без_пробела):
                    return True, False, ["langlayer:словарь"]
        if not судимо and пласт is not None:
            # ПЛАСТ ЯЗЫКА СУДИТСЯ СЛОВАРЁМ ПАКЕТА, А НЕ СОДЕРЖАНИЕМ —
            # И ЭТО НАДО НЕ ТОЛЬКО СКАЗАТЬ, НО И СДЕЛАТЬ.
            #
            # Первая редакция здесь просто ВОЗВРАЩАЛА ИСТИНУ: строка,
            # которую не прочёл ни один суд, объявлялась судимой и
            # истинной по признаку ИМЕНИ ФАЙЛА. Замером вскрыто, чего
            # это стоило: языковых пластов 29, строк 82 774, и суд
            # истины (арифметический) читает из них 14 979 — восемнадцать
            # процентов. Прочие 67 795 строк — тридцать семь процентов
            # ВСЕГО свода показов — не читал НИКТО, и все они входили в
            # «судимость 100%» ЗАЧЁТОМ ПО УМОЛЧАНИЮ.
            #
            # Ныне зачёт делает работу: словарь пакета СПРАШИВАЕТСЯ, и
            # строка со словом, которого пакет не объявлял, есть ЛОЖЬ, а
            # не молчание. Это по-прежнему проверка СЛОВАРЯ, а не истины
            # — ложное утверждение из объявленных слов её пройдёт, — и
            # потому вердикт помечен своим именем: кто читает меру,
            # обязан видеть, ЧЕМ строка зачтена.
            # ЖАДНАЯ РЕЗКА ДЕЛАЕТ СЛОВАРНУЮ ПРОВЕРКУ СЛЕПОЙ ТАМ, ГДЕ
            # ПИСЬМО НЕ СТАВИТ ПРОБЕЛОВ, И ЭТО НАДО ОБЪЯВИТЬ.
            #
            # Подсадка в тайский пласт: 25 строк, в каждой испорчено
            # СЛОВО (выброшен последний знак, число не тронуто).
            # Поймано 17, ВОСЕМЬ названы истиной. Пример:
            # «ประตูเล็กมาก» → «ประตูเล็กมา», вердикт
            # ['langlayer:словарь'].
            #
            # Причина не в словаре, а в РЕЗКЕ: порченое «เล็กมา»
            # распадается на два ОБЪЯВЛЕННЫХ слова — «เล็ก» (малый) и
            # «มา» (приходить), — и проверка честно говорит «все слова
            # объявлены». Строка при этом перестала быть тайским
            # языком.
            #
            # ЗАЧЁТ СЛОВАРЁМ СЛАБЕЕ ТАМ, ГДЕ НЕТ ПРОБЕЛОВ, НО СЛАБЕЕ
            # НЕ ВДВОЙНЕ — И ЭТО ИСПРАВЛЕНИЕ ЧИСЛА, СТОЯВШЕГО ЗДЕСЬ.
            #
            # Первый замер дал 17 из 25 (68 %) и был вписан сюда
            # потолком. Он оказался АРТЕФАКТОМ УЗКОЙ ВЫБОРКИ: брались
            # первые 400 строк одного пласта и только те, что читает
            # суд формы. Широкая равномерная проба по всем трём
            # письменам без пробелов дала иное:
            #     тайский  12 из 12, японский 12 из 12, китайский 9 из 12
            #     вместе   33 из 36 — ДЕВЯНОСТО ОДИН ПРОЦЕНТ
            #
            # ЗАКОН ВЕРЕН, ЧИСЛО ПРИ НЁМ БЫЛО НЕВЕРНО, и разницу эту
            # надо держать в уме всегда: слепота словарной проверки —
            # свойство ПИСЬМА, а её величина — свойство ВЫБОРКИ. Тот,
            # кто мерил, сам и опроверг своё число, не дожидаясь, пока
            # это сделает кто-то другой.
            #
            # Свежий свидетель, уже китайский: «四十除以五等于八。» →
            # «四十除以五等于。» — восьмёрка выброшена, равенство стало
            # бессмыслицей, остаток режется на объявленные слова, и
            # зачёт говорит «все слова объявлены». Такое случается в
            # трёх случаях из тридцати шести, а не в трети.
            #
            # Вердикт помечен своим именем, и мера судимости считает
            # такие строки ОТДЕЛЬНЫМ числом (СЛОВАРЁМ_РУБЕЖ): сто
            # процентов читаются как «столько прочитано формой, столько
            # зачтено словарём». Настоящий путь вниз — не усиление
            # зачёта, а рост суда формы пласта, который читает
            # СОДЕРЖАНИЕ.
            LL = self.служебные.get("langlayer")
            if LL is None:
                return False, True, []
            без_пробела = self.без_пробела.get(id(пласт), False)
            чужие = LL.чужие(строка, пласт, без_пробела)
            return True, not чужие, ["langlayer:словарь"]
        if судимо and not self._в_покрытии and self._непокрыто(строка, слои, пласт, кем):
            return False, True, []      # молчание: за строку поручиться нечем
        return судимо, True, кем

    _СЛОВО_ПОРЧИ = __import__("re").compile(r"(?<![\w-])[^\W\d_]{3,}(?![\w-])")
    _ЧИСЛО_ПОРЧИ = __import__("re").compile(r"\d+")

    def _род_текста(self, путь):
        """Объявленный род текста этого файла: «shows», «prose» или иное.

        РОД ТЕКСТА БЕРЁТСЯ У МАНИФЕСТА, А НЕ У ДОГОВОРА (шрам 07.09, второй за час).
        Первая починка спрашивала признак «полка» у слоёв соседей — но «полка» у них
        значит «чужой текст, КОТОРЫЙ МЕНЯ НЕ НАЗВАЛ», и у книги, назвавшей судью,
        она ЛОЖНА. Оттого закон покрытия продолжал глушить именно тех судей, которых
        книга позвала: Пуанкаре назвал engram, halves и prosetree — и все трое
        замолчали, оставив три разлада.

            ПРИЗНАК ЧУЖОГО ТЕКСТА И ПРИЗНАК ЧУЖОГО ДОГОВОРА СУТЬ РАЗНЫЕ ПРИЗНАКИ.
            Первый говорит, ЧТО перед судом; второй — вправе ли суд это читать. Закон
            покрытия спрашивает первое, договор — второе, и подменять одно другим
            значит наказывать книгу за её же приглашение.
        """
        if self._роды_миров is None:
            self._роды_миров = {}
            try:
                import genesis
                for м in genesis.manifest()["worlds"]:
                    self._роды_миров[pathlib.Path(м.get("file", "")).name] = м.get("text")
            except Exception:
                pass
        имя = pathlib.Path(путь).name
        if имя.endswith(".ворота"):
            имя = имя[:-len(".ворота")]
        return self._роды_миров.get(имя)

    def _непокрыто(self, строка, слои, пласт, кем=()):
        """Есть ли в строке предложение, за которое палата ручиться не может.

        ЗАКОН ПОКРЫТИЯ ЕСТЬ ЗАКОН О ПОКАЗАХ, А НЕ О ЧУЖОМ ТЕКСТЕ (шрам 07.09). Прибор
        полки пал девятнадцатью разладами: `rugram` перестал читать русскую прозу
        ВОВСЕ, ибо строка прозы длинна, многопредложна и покрыть её нечем — суды показов
        читают в ней своё и молчат об остальном ЗАКОННО, ибо остальное им не подсудно.
        Названный судья стал молчащим, и объявление книги обратилось в ложь.

            ЗАКОН, ПОСТАВЛЕННЫЙ НА ПОКАЗЫ, ОБЯЗАН СПРАШИВАТЬ РОД ТЕКСТА, ПРЕЖДЕ ЧЕМ
            СУДИТЬ. Проза цитирует, отрицает и предполагает; требовать от неё покрытия
            каждого предложения значит требовать, чтобы суд показов знал всё.

        Признак рода взят у соседей (`halves`, `engram`, `formula`): чужой текст есть
        полка и проза, и он узнаётся по слою мира, а не по длине строки.
        """
        if not (слои or {}).get("#показы", True):
            return False        # проза и полка: закон покрытия есть закон о ПОКАЗАХ
        суд = self.суды.get("arith")
        if суд is None:
            return False
        части = [ч.strip() for ч in суд.предложения(строка) if ч.strip()]
        if len(части) < 2:
            return False
        знаки = [м.group(0).strip() for м in суд.ПРЕДЛОЖЕНИЕ.finditer(строка)]
        части = [ч + знаки[i] if i < len(знаки) else ч for i, ч in enumerate(части)]
        # НОМЕР ПУНКТА В НАЧАЛЕ СТРОКИ ЕСТЬ НОМЕР, А НЕ ПРЕДЛОЖЕНИЕ (шрам 07.09, прибор
        # судимости). Резка по точке делит «1. water.» надвое, и первая половина —
        # голая цифра — не покрыта ничем: порча её вердикта не меняет, ибо номер
        # пункта в списке и вправду никто не читает по отдельности. Оттого закон
        # покрытия обратил в немоту 84 честные строки мира `md_latex`, а прибор
        # судимости упал с 100 % на 99 %.
        #
        #     ЦИФРА С ТОЧКОЙ В НАЧАЛЕ СТРОКИ ЕСТЬ НОМЕР ПУНКТА, А НЕ ПРЕДЛОЖЕНИЕ. Суд
        #     разметки читает «1. water.» ЦЕЛИКОМ (порча «wate» делает её ложью), и
        #     мера, разрезавшая её надвое, мерит свою резку, а не корпус.
        #
        # Тот же закон уже стои́т в суде формул: «номер, стоящий перед записью,
        # принадлежит тексту, а не формуле» — и различает их МЕСТО.
        if len(части) > 1 and _НОМЕР_ПУНКТА.fullmatch(части[0]):
            части = [части[0] + " " + части[1]] + части[2:]
            if len(части) < 2:
                return False
        предметы = (слои or {}).get("#предметы") or frozenset()
        вопрос = ""
        try:
            import asking
            пара = asking.пара(строка)
            вопрос = пара[0] if пара else ""
        except Exception:
            pass
        self._в_покрытии = True
        try:
            for ч in части:
                if self.судить(ч, слои, пласт)[0]:
                    continue
                голое = ч.rstrip(".?!…。")
                if вопрос and голое in вопрос:
                    # ПОБЛАЖКА ВОПРОСУ СУЖЕНА СЛОВАРЁМ МИРА (пятое лицо покрытия):
                    # вопрос покрыт лишь тогда, когда все его слова — слова этого мира.
                    словарь = (слои or {}).get("#словарь") or frozenset()
                    if not словарь or all(
                            м.group().lower() in словарь
                            for м in self._СЛОВО_ВОПРОСА.finditer(голое)):
                        continue
                if предметы:
                    try:
                        import subjectforms
                        if subjectforms.форма(ч) in предметы:
                            continue
                    except Exception:
                        pass
                if self._читано_целиком(строка, ч, слои, пласт, кем):
                    continue
                return True
        finally:
            self._в_покрытии = False
        return False

    def _читано_целиком(self, строка, предложение, слои, пласт, кем=()):
        """Читал ли КТО-НИБУДЬ это предложение — проверка порчей.

        ЧИТАНО ЕСТЬ «ВЕРДИКТ ДРОГНУЛ ИЛИ СОСТАВ ПАЛАТЫ ДРОГНУЛ», А НЕ ОДИН ВЕРДИКТ
        (шрам 06.09, прибор родов). Первая редакция спрашивала только вердикт строки — и
        назвала непрочитанными пятьдесят строк мира compsci: суд науки о счёте читает
        русскую строку своим образцом и при порче ЗАМОЛКАЕТ, а сосед `rugram` продолжает
        звать порченую строку истиной. Вердикт не дрогнул, и мера сказала «не читал
        никто» — а читал, и притом целиком.

            МОЛЧАНИЕ СУДА, ЗАГЛУШЁННОЕ СОГЛАСИЕМ СОСЕДА, ЕСТЬ ЧТЕНИЕ, А НЕ СЛЕПОТА.
            Признак обязан смотреть на СОСТАВ подписавших, а не только на подпись:
            суд, выпавший из состава при порче, тем самым показал, что слово читал.
        """
        i = строка.find(предложение)
        if i < 0:
            return False
        м = self._СЛОВО_ПОРЧИ.search(предложение)
        if м:
            порча = строка[:i + м.start()] + м.group()[:-1] + строка[i + м.end():]
        else:
            ч = self._ЧИСЛО_ПОРЧИ.search(предложение)
            if not ч:
                return False
            порча = строка[:i + ч.start()] + str(int(ч.group()) + 1) + строка[i + ч.end():]
        судимо, истинно, кем2 = self.судить(порча, слои, пласт)
        if (not судимо) or (not истинно):
            return True
        return set(кем or ()) != set(кем2 or ())

