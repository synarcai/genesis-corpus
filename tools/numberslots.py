#!/usr/bin/env python3
"""СЛОВО ШАБЛОНА ЗА ЧИСЛОМ — слово, какое дом пишет за числовой дырой своего шаблона одинаково при всяком числе (29.09).

Суд согласования (`courts/agreement_court.py`) зовёт ложью «1 слово», если то же слово стоит и после чисел больше
единицы: так он ловит «ben has 1 eggs». Но глагол, какой шаблон ставит сразу за числом («… und {k} weggab», «omdat …
er {n} had en {k} weggaf», «{call} geeft {v} terug»), стоит после ВСЯКОГО числа одним словом — по построению, а не по
ошибке, — и корпус сам этого не различит: у слова, встреченного и после единицы, и после пятёрки, нет второй формы.

    ТОТ, КТО ПОРОДИЛ СЛОВО, ЗНАЕТ, ЧТО ОНО НЕ СОГЛАСУЕТСЯ С ЧИСЛОМ. Не список слов в пакете (слово ведущего 29.09:
    никаких списков слов), а таблица генератора: дом объявляет, какие дыры его шаблонов суть числа, и слова за ними
    выводятся из самих шаблонов. Глагол в конце придаточного у нового дома закрывается его же таблицей, без новой руки.

    слова_после_числа(таблицы, числа) -> {язык: frozenset(слов)}
"""
import re

_СЛОВО = re.compile(r"[^\W\d_]+")


def _строки(узел):
    """Все строки таблицы: значения словарей, члены кортежей и списков — вглубь."""
    if isinstance(узел, str):
        yield узел
    elif isinstance(узел, dict):
        for значение in узел.values():
            yield from _строки(значение)
    elif isinstance(узел, (tuple, list)):
        for член in узел:
            yield from _строки(член)


def слова_после_числа(таблицы, числа):
    """{язык: frozenset(слов)} — слова, какие стоят в шаблонах сразу за дырой числа (имена дыр — `числа`); таблицы —
    словари «язык → шаблоны» (всякое вложение строк)."""
    за_числом = re.compile(r"\{(?:" + "|".join(map(re.escape, числа)) + r")\} (" + _СЛОВО.pattern + r")")
    вон = {}
    for таблица in таблицы:
        for язык, шаблоны in таблица.items():
            слова = {м.group(1).lower() for строка in _строки(шаблоны) for м in за_числом.finditer(строка)}
            вон[язык] = вон.get(язык, frozenset()) | frozenset(слова)
    return вон
