ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА3 = re.compile(r"(\d+) \+ (\d+) \+ (\d+) = (\d+)")
_ДЕЛЕНИЕ = re.compile(r"(\d+) ÷ (\d+) = (\d+)")
_ПРОИЗВ = re.compile(r"(\d+) × (\d+) = (\d+)")
_РАЗНОСТЬ_СК = re.compile(r"\((\d+) − (\d+)\)")
_БОЛЬШЕ_НА = re.compile(r"больше на (\d+)|(\d+) more")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c, s in _СУММА3.findall(с):
        if int(a) + int(b) + int(c) != int(s):
            return True, False
    for a, b, r in _ДЕЛЕНИЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(r):
            return True, False
    for a, b, r in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(r):
            return True, False
    for a, b in _РАЗНОСТЬ_СК.findall(с):
        # размах объявлен перед скобкой: «размах 8 (10 − 2)»
        m = re.search(r"размах (\d+) \(|spread of (\d+) \(", с)
        if m:
            сказано = int(m.group(1) or m.group(2))
            if int(a) - int(b) != сказано:
                return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # СРЕДНЕЕ ОБЯЗАНО БЫТЬ ЦЕЛЫМ И НЕ РАВНЫМ НИ ОДНОМУ ЧЛЕНУ — иначе ловушка спрячется.
    for (a, b, c), вру, ван, сру, сан in НАБОРЫ:
        s = a + b + c
        if s % 3:
            беды.append(f"среднее не целое: {a}, {b}, {c}")
        elif s // 3 in (a, b, c):
            беды.append(f"среднее совпало с членом и ловушка спряталась: {a}, {b}, {c}")
        if вру not in ВМЕСТИЛИЩА_МН or ван not in ВМЕСТИЛИЩА_МН:
            беды.append(f"вместилище без объявленной формы: {вру}/{ван}")
        if вру not in СРЕДНЕГО:
            беды.append(f"вместилище без падежной формы среднего: {вру}")
    # ЧАСТОТА ОБЯЗАНА ОТЛИЧАТЬСЯ ОТ ПОЛОВИНЫ — иначе нечего и различать.
    for всего, орлов in БРОСКИ:
        if Fraction(орлов, всего) == Fraction(1, 2):
            беды.append(f"частота равна вероятности, ловушки нет: {орлов}/{всего}")
    # ТРЕТЬЯ ПРИЧИНА ОБЯЗАНА РАСТИ ВМЕСТЕ С ОБОИМИ.
    for сру, сан, дру, дан, зс, зд, гс, гд, дс, дд in ТРЕТЬЯ:
        if not (зд > зс and гд > гс and дд > дс):
            беды.append(f"третья причина не растёт вместе: {сру}/{дру}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    ср = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "среднего нет ни у кого")
    порча = ср.replace("Среднее", "Средне", 1)
    if порча == ср:
        беды.append("порча не состоялась: нет слова «Среднее»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
