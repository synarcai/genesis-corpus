#!/usr/bin/env python3
"""ДОМ ГРАНИЦЫ ВЕЛИЧИНЫ — не всякое верное вычитание есть возможное действие.

    В СВОДЕ 997 ЗАДАЧ ВИДА «БЫЛО N, ОТДАЛ M», И НИ В ОДНОЙ M НЕ БОЛЬШЕ N. Замер 10.09 по всем
    мирам показов. Корпус тщательно обходит невозможное положение — и потому не учит его
    РАСПОЗНАВАТЬ. Отрицательных итогов у вещей нет ни одного; слов «нельзя взять», «невозможно
    отдать» нет вовсе.

ЭТО ИНОЙ РОД ОТКАЗА, ЧЕМ ДЕЛЕНИЕ НА НОЛЬ, И РАЗЛИЧИЕ ЗДЕСЬ ГЛАВНОЕ. Там действия не было
вовсе: числа, дающего при умножении на ноль шестёрку, нет на свете. Здесь действие есть и счёт
верен — «12 − 15 = −3» истинно в мире чисел, и мир знаковых чисел это показывает 360 раз. Но
орехов не бывает минус три.

    ВЕЛИЧИНА ИМЕЕТ ГРАНИЦУ, И АРИФМЕТИКА ЕЁ НЕ ЗНАЕТ. Число вещей не бывает меньше нуля, и
    вычитание, законное над числами, над вещами бывает НЕВЫПОЛНИМО.

ЧЕТЫРЕ РОДА, И ВСЕ ПРОВЕРЯЮТСЯ ДВУМЯ СЧЁТАМИ — СРАВНЕНИЕМ И ВЫЧИТАНИЕМ:

    можно      взяли 5 из 12: взять 5 из 12 можно: 5 меньше 12, и осталось 7 орехов: 12 − 5 = 7.
    ровно всё  взяли 12 из 12: взять 12 из 12 можно: 12 не больше 12, и осталось 0 орехов:
               12 − 12 = 0.                                                    ← ГРАНИЦА САМА
    нельзя     взяли 15 из 12: взять 15 из 12 нельзя: 15 больше 12.
    число      в числах 12 − 15 = −3, но орехов не бывает −3, и потому взять 15 из 12 нельзя.
                                                                    ← ГРАНИЦА ПРИМЕНИМОСТИ

СРАВНЕНИЕ ИДЁТ ПРЕЖДЕ ДЕЙСТВИЯ, И ЭТО ВЕСЬ ПРЕДМЕТ ДОМА. Первый род не повторяет мира историй
(«было 12, отдали 5, осталось 7»): он добавляет к нему ШАГ, которого там нет, — проверку
возможности ДО счёта. Без этого шага третий род был бы запретом ниоткуда, а четвёртый —
софизмом.

ВТОРОЙ РОД ЕСТЬ САМА ГРАНИЦА, А НЕ ЛИШНИЙ ПРИМЕР: «взять 12 из 12» — последнее возможное, и
без него читатель вправе решить, что нельзя брать «столько же». Граница показывается изнутри,
а не описывается снаружи.

ЧЕТВЁРТЫЙ РОД — ЕДИНСТВЕННЫЙ, ГДЕ СКАЗАНО, ПОЧЕМУ НЕЛЬЗЯ, ПРИ ТОМ ЧТО СЧЁТ ВЕРЕН. Он ставит
рядом два верных утверждения из разных миров и показывает, что второе отменяет первое НЕ ПО
АРИФМЕТИКЕ, а по природе величины.

    ДВА ВЕРНЫХ УТВЕРЖДЕНИЯ МОГУТ ПРОТИВОРЕЧИТЬ ДРУГ ДРУГУ, ЕСЛИ ОНИ О РАЗНОМ.

Вещи взяты только мужского рода, а действие безлично («взяли»): у женского гнулось бы
прилагательное, которого дом не объявлял, а лицо потребовало бы согласования глагола по роду —
это предмет иных домов. Счётная форма имени берётся у дома русской грамматики.

    python3 tools/boundforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import rugram  # noqa: E402 — счётная форма имени берётся у дома, а не пишется на глаз

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("можно", "ровно всё", "нельзя", "число", "проверка")

ВЕЩИ = {"ru": ("орех", "ключ", "камень", "шар"),
        "en": (("nut", "nuts"), ("key", "keys"), ("stone", "stones"), ("ball", "balls"))}
МЕСТА = {"ru": ("в коробке", "в мешке", "на полке", "в ящике"),
         "en": ("a box", "a bag", "a shelf", "a crate")}

РАМКИ = {
    "ru": {
        "можно": "{место} было {n} {в_n}. взяли {m} {в_m}. сколько {в_р} осталось? взять {m} из {n} можно: {m} меньше {n}, и осталось {r} {в_r}: {n} − {m} = {r}.",
        "ровно всё": "{место} было {n} {в_n}. взяли {n} {в_n}. сколько {в_р} осталось? взять {n} из {n} можно: {n} не больше {n}, и осталось 0 {в_р}: {n} − {n} = 0.",
        "нельзя": "{место} было {n} {в_n}. взяли {m} {в_m}. сколько {в_р} осталось? взять {m} из {n} нельзя: {m} больше {n}.",
        "число": "{место} было {n} {в_n}. взяли {m} {в_m}. в числах {n} − {m} = −{d}, но {в_р} не бывает −{d}, и потому взять {m} из {n} нельзя.",
        "проверка": "{место} было {n} {в_n}. взяли {m} {в_m}. верно ли, что осталось −{d} {в_d}? нет: {в_р} не бывает −{d}, и взять {m} из {n} нельзя.",
    },
    "en": {
        "можно": "{место} held {n} {в_n}. {m} {в_m} {было} taken. how many {в_р} remain? taking {m} out of {n} is possible: {m} is less than {n}, and {r} {в_r} remain: {n} − {m} = {r}.",
        "ровно всё": "{место} held {n} {в_n}. {n} {в_n} were taken. how many {в_р} remain? taking {n} out of {n} is possible: {n} is not greater than {n}, and 0 {в_р} remain: {n} − {n} = 0.",
        "нельзя": "{место} held {n} {в_n}. {m} {в_m} {было} taken. how many {в_р} remain? taking {m} out of {n} is impossible: {m} is greater than {n}.",
        "число": "{место} held {n} {в_n}. {m} {в_m} {было} taken. in numbers {n} − {m} = −{d}, but there are never −{d} {в_р}, and so taking {m} out of {n} is impossible.",
        "проверка": "{место} held {n} {в_n}. {m} {в_m} {было} taken. is it true that −{d} {в_р} remain? no: there are never −{d} {в_р}, and taking {m} out of {n} is impossible.",
    },
}


def при(язык, лемма, n):
    """Форма вещи при счёте: у русского спрашивается дом, у английского — множественное."""
    if язык == "ru":
        return rugram.форма(лемма, n)
    один, много = лемма
    return один if n == 1 else много


def _пары():
    """(n, m): было n, взяли m — и меньше, и ровно, и больше; всё в пределах двух знаков."""
    вон = []
    for n in range(4, 16):
        вон.append((n, n - 3))       # можно
        вон.append((n, n + 3))       # нельзя
    return вон


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        вещи, места = ВЕЩИ[язык], МЕСТА[язык]
        for к, (n, m) in enumerate(_пары()):
            лемма = вещи[к % len(вещи)]
            место = места[к % len(места)]
            # МНОЖЕСТВЕННОЕ ИМЯ ВЕЩИ («орехов») стои́т там, где числа при нём нет: у русского
            # это родительный множественный, и он берётся у дома счётом заведомо многим.
            поля = dict(место=место, n=n, m=m, r=abs(n - m), d=abs(n - m),
                        в_n=при(язык, лемма, n), в_m=при(язык, лемма, m),
                        в_r=при(язык, лемма, abs(n - m)),
                        в_d=при(язык, лемма, abs(n - m)),
                        в_р=при(язык, лемма, 5),
                        # АНГЛИЙСКИЙ ГЛАГОЛ СОГЛАСУЕТСЯ С ЧИСЛОМ, И ЭТО НЕ МЕЛОЧЬ: первый
                        # заход написал «1 nut were taken» — рамка ставила «were» литералом,
                        # не спросив о числе. Русскому здесь согласовывать нечего: «взяли»
                        # безлично, и оттого ошибка была видна лишь на другом языке.
                        было="was" if m == 1 else "were")
            if m < n:
                вон[РАМКИ[язык]["можно"].format(**поля)] = (язык, "можно")
            else:
                вон[РАМКИ[язык]["нельзя"].format(**поля)] = (язык, "нельзя")
                вон[РАМКИ[язык]["число"].format(**поля)] = (язык, "число")
                # ВТОРАЯ ПОВЕРХНОСТЬ ОТКАЗА — ПРОВЕРКА ПРЕДЛОЖЕННОГО, и она куплена прибором
                # манифеста: акт `refuse` объявлен, а строк отказа В ОБЪЯВЛЕННОЙ ФОРМЕ («нет:
                # основание») в доме не было — он говорил «нельзя», и признак его не узнавал.
                #
                #     ПРИБОР, НЕ УЗНАВШИЙ ОТКАЗА, ПРАВ, ПОКА ФОРМА ОТКАЗА НЕ ОБЪЯВЛЕНА.
                #
                # Долг уплачен формой, а не расширением общего признака под свой дом: у отказа
                # и правда есть вторая сторона — не «сколько осталось», а «верно ли, что
                # осталось −3». И она учит иному: не выдать свой ответ, а отвергнуть чужой.
                вон[РАМКИ[язык]["проверка"].format(**поля)] = (язык, "проверка")
            вон[РАМКИ[язык]["ровно всё"].format(**поля)] = (язык, "ровно всё")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_РАЗНОСТЬ = re.compile(r"(\d+) − (\d+) = (−?)(\d+)")
_МЕНЬШЕ = re.compile(r"(\d+) (?:меньше|is less than) (\d+)")
_БОЛЬШЕ = re.compile(r"(\d+) (?:больше|is greater than) (\d+)")
_НЕ_БОЛЬШЕ = re.compile(r"(\d+) (?:не больше|is not greater than) (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: разность и оба сравнения своими глазами.
    # Знак минуса перед разностью читается: «12 − 15 = −3» истинно, «12 − 15 = 3» ложно.
    for a, b, знак, c in _РАЗНОСТЬ.findall(с):
        итог = -int(c) if знак else int(c)
        if int(a) - int(b) != итог:
            return True, False
    for a, b in _МЕНЬШЕ.findall(с):
        if int(a) >= int(b):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    for a, b in _НЕ_БОЛЬШЕ.findall(с):
        if int(a) > int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:70]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    можно = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "можно")
    нельзя = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "нельзя")
    число = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "число")
    if судить(можно.replace("можно:", "можн:"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(нельзя.replace("нельзя:", "нельз:"))[1] is not False:
        беды.append("обрезанное слово в отказе прошло")
    if судить(число.replace("бывает", "бывае"))[1] is not False:
        беды.append("обрезанное слово в границе прошло")
    if судить(можно + " " + можно)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ГРАНИЦА ВЕЛИЧИНЫ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
