def спросить(искомое, ответ, **части):
    """Вопрос и ответ одной строкой; величины у них одни и те же."""
    return f"{СПРОСИТЬ[искомое].format(**части)} {ответ}"


def делители(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def простое(n):
    return n > 1 and len(делители(n)) == 2


def разложение(n):
    вон, d = [], 2
    while d * d <= n:
        while n % d == 0:
            вон.append(d)
            n //= d
        d += 1
    if n > 1:
        вон.append(n)
    return вон


def простые(шаг):
    """Простое и составное — каждое со своим свидетельством."""
    вон = []
    # МАССА ОТ ПРАВИЛА (М-148): ряд чисел сдвигается проходом — одни и те
    # же 28 чисел пятью проходами были весом, не массой.
    for n in range(2 + 28 * шаг, 30 + 28 * шаг):
        if простое(n):
            утв_en = f"{n} is prime; its divisors are 1 and {n}."
            утв_ru = f"{n} простое; его делители — 1 и {n}."
        else:
            м = разложение(n)
            утв_en = f"{n} is not prime; {n} = {м[0]} × {n // м[0]}."
            утв_ru = f"{n} составное; {n} = {м[0]} × {n // м[0]}."
        вон.append(утв_en)
        вон.append(утв_ru)
        # THE VERDICT WORD OPENS THE ANSWER (М-147, holon 03.09: «простое ли #»
        # answered by the bare statement read as a value, not a verdict).
        # ПЕРЕФРАЗА — ФОРМА ПАКЕТА (Т-4): вопрос о простоте всеми формами
        # пакета, ответ один; масса пары ×2.
        for форма in paraphrase.формы("en", "prime"):
            вон.append(f"{форма.format(n)} {'yes: ' if простое(n) else 'no: '}{утв_en}")
        for форма in paraphrase.формы("ru", "prime"):
            вон.append(f"{форма.format(n)} {'да: ' if простое(n) else 'нет: '}{утв_ru}")
    return вон


def ни_то_ни_другое(шаг):
    """Отказ с основанием: единица не проста и не составна.

    ВОПРОС, НА КОТОРЫЙ ЧЕСТНЫЙ ОТВЕТ — «НИ ТО НИ ДРУГОЕ». Простое имеет
    ровно два делителя, составное — больше двух; у единицы делитель
    ОДИН, и она не попадает ни в один род. Основание названо числом, и
    суд пересчитывает его тем же перебором делителей, каким судит
    простоту.
    """
    n = 1
    утв_en = f"{n} is neither prime nor composite: its only divisor is {n}."
    утв_ru = (f"{n} ни простое, ни составное: его единственный делитель "
              f"— {n}.")
    # ОТКАЗ СПРАШИВАЕТСЯ ВСЕМИ ФОРМАМИ РОДА, А НЕ СВОЕЙ ОСОБОЙ (прибор
    # scripts/word_gap.py, 03.09): единица спрашивалась голым шаблоном
    # «простое ли 1?» — формой, которой в мире нет больше нигде, ибо все
    # сто сорок прочих вопросов о простоте идут формами пакета («простое
    # ли ЧИСЛО 3?», «является ли 3 простым числом?»). Мир, говорящий об
    # отказе своим языком, учит, что отказ есть другой род вопроса; он
    # тот же род, и спрашивается так же.
    вон = []
    for форма in paraphrase.формы("en", "prime"):
        вон.append(f"{форма.format(n)} {утв_en}")
    for форма in paraphrase.формы("ru", "prime"):
        вон.append(f"{форма.format(n)} {утв_ru}")
    return вон


