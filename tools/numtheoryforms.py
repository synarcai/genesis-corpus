def сравнения(шаг):
    """Остаток есть отношение, а не только действие."""
    вон = []
    for i in range(24):
        a, m = 7 + i * 3 + шаг, 2 + (i % 7)
        r = a % m
        # СВИДЕТЕЛЬ — НОВОЕ ЧИСЛО (holon 04.09): второе число ≥ модуля, иначе
        # его остаток повторяет вход («1 mod 6 = 1» — эхо, рамка не
        # покупается); и не равно первому — иначе вопрос о числе с собой.
        k = 1 + (i % 3)
        if k == a // m:
            k += 1
        b = r + m * k
        утв_о_en, утв_о_ru = (f"{a} mod {m} = {r}.",
                              f"{a} по модулю {m} равно {r}.")
        утв_с_en = f"{a} and {b} are congruent modulo {m}."
        утв_с_ru = f"{a} и {b} сравнимы по модулю {m}."
        вон.append(утв_о_en)
        вон.append(утв_о_ru)
        вон.append(утв_с_en)
        вон.append(утв_с_ru)
        вон.append(спросить("mod", утв_о_en, a=a, m=m))
        вон.append(спросить("остаток", утв_о_ru, a=a, m=m))
        # СЛОВО ВЕРДИКТА И ОСНОВАНИЕ У «ДА» (М-147; класс tellings-differ):
        # «да» несёт оба остатка, как «нет» — иначе две формы рассказа.
        да_en = f"yes: {a} and {b} are congruent modulo {m}: {a} mod {m} = {r}, {b} mod {m} = {r}."
        да_ru = f"да: {a} и {b} сравнимы по модулю {m}: {a} по модулю {m} равно {r}, {b} по модулю {m} равно {r}."
        вон.append(спросить("congruent", да_en, a=a, b=b, m=m))
        вон.append(спросить("сравнимы", да_ru, a=a, b=b, m=m))
        # ВТОРАЯ ПОЛЯРНОСТЬ ТОЙ ЖЕ РАМКОЙ (аудит покупок holon 03.09):
        # 120 показов «сравнимы» без единого «нет» — форма без
        # фальсификатора. Несравнимое число — соседний остаток.
        b2 = (r + 1 if r + 1 < m else r - 1) + m * k   # ≥ модуля: остаток — новое число
        нет_en = (f"{a} and {b2} are not congruent modulo {m}: "
                  f"{a} mod {m} = {r}, {b2} mod {m} = {b2 % m}.")
        нет_ru = (f"{a} и {b2} не сравнимы по модулю {m}: "
                  f"{a} по модулю {m} равно {r}, {b2} по модулю {m} равно {b2 % m}.")
        вон.append(нет_en)
        вон.append(нет_ru)
        вон.append(спросить("congruent", "no: " + нет_en, a=a, b=b2, m=m))
        вон.append(спросить("сравнимы", "нет: " + нет_ru, a=a, b=b2, m=m))
    return вон


def взаимно_простые(шаг):
    """Взаимная простота есть НОД, равный единице."""
    from math import gcd
    вон = []
    for i in range(20):
        a, b = 4 + i + шаг, 9 + i * 2
        если = "coprime" if gcd(a, b) == 1 else "not coprime"
        ру = "взаимно просты" if gcd(a, b) == 1 else "не взаимно просты"
        утв_en = f"{a} and {b} are {если}; their gcd is {gcd(a, b)}."
        утв_ru = f"{a} и {b} {ру}; их нод равен {gcd(a, b)}."
        вон.append(утв_en)
        вон.append(утв_ru)
        вон.append(спросить("coprime", ("yes: " if gcd(a, b) == 1 else "no: ") + утв_en, a=a, b=b))
        вон.append(спросить("взаимно", ("да: " if gcd(a, b) == 1 else "нет: ") + утв_ru, a=a, b=b))
    return вон



