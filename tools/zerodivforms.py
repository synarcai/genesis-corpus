#!/usr/bin/env python3
"""ДОМ ДЕЛЕНИЯ НА НОЛЬ — отказ, у которого есть ПРИЧИНА, и причина СЧИТАЕТСЯ.

    ВО ВСЁМ СВОДЕ НЕТ НИ ОДНОГО ДЕЛЕНИЯ НА НОЛЬ. Замер 10.09 по 216 мирам показов:
    умножение на ноль — 696 вхождений, ноль в делимом («0 ÷ 3») — 644, а выражения «n ÷ 0» нет
    НИ ОДНОГО. Корпус учит, что на ноль можно умножать и что ноль можно делить, и молчит о
    третьем случае — том, где ответа нет вовсе.

ПОЧЕМУ ЭТОГО РОДА НЕ БЫЛО, И ЭТО НЕ СЛУЧАЙНОСТЬ. Ворота записи его не пропускали. Суд
арифметики знает закон СВЯЗИ ПАРЫ: вопрос формы значения обязан получить ответ О ТОМ ЖЕ — с
теми же величинами в том же порядке. «сколько будет 6 ÷ 0? на ноль делить нельзя» этот закон
рвёт: в вопросе шесть и ноль, в ответе один ноль, — и суд зовёт строку ложью, не читая её
смысла.

    ОТКАЗ, НЕ ПОВТОРИВШИЙ ВОПРОСА, НЕОТЛИЧИМ ОТ УКЛОНЕНИЯ — и для суда, и для читателя.

Так свод и научил этот дом форме: «делить 6 на 0 нельзя». Тем же ходом живёт отказ в мире
`svamp` — «сколько шаров у Ани? не знаю: сколько шаров у Ани, не сказано»: вопрос повторён
внутри отказа. Отказ здесь не объявляется, а ВЫВОДИТСЯ, и потому дом начинается не с нуля.

ЧЕТЫРЕ РОДА, И ВСЕ ЧЕТЫРЕ ПРОВЕРЯЮТСЯ ОДНИМ И ТЕМ ЖЕ ПЕРЕСЧЁТОМ — умножением:

    деление     сколько будет 12 ÷ 3? 12 ÷ 3 = 4, ибо 4 × 3 = 12.          ← ЧТО ЗНАЧИТ ДЕЛИТЬ
    ноль сверху сколько будет 0 ÷ 6? 0 ÷ 6 = 0, ибо 0 × 6 = 0.             ← ТОТ ЖЕ ЗАКОН
    ноль снизу  сколько будет 6 ÷ 0? делить 6 на 0 нельзя: 0 × 1 = 0, и 0 × 2 = 0,
                и ни одно произведение не равно 6.                          ← НЕТ НИ ОДНОГО
    ноль на ноль сколько будет 0 ÷ 0? делить 0 на 0 нельзя однозначно: 0 × 1 = 0,
                и 0 × 7 = 0, и подходит всякое число.                       ← ПОДХОДИТ ЛЮБОЕ

ПЕРВЫЙ РОД ЕСТЬ ОСНОВАНИЕ ОСТАЛЬНЫХ ТРЁХ, А НЕ ПОВТОРЕНИЕ ИЗВЕСТНОГО. Разделить значит найти
число, которое при умножении на делитель даёт делимое; сказав это вслух, дом получает право
на три отказа, ибо каждый из них есть ПОИСК, кончившийся ничем или кончившийся всем. Без
первого рода «нельзя» было бы запретом, объявленным взрослым, а не следствием счёта.

ТРЕТИЙ И ЧЕТВЁРТЫЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО ПРИЧИНЕ: оба «нельзя», и причины ПРОТИВОПОЛОЖНЫ —
не подходит НИ ОДНО число против подходит ВСЯКОЕ. Второй и третий суть минимальная пара по
месту нуля: числа те же, порядок иной, и ответ иной.

    ДВА ОТКАЗА С РАЗНЫМИ ПРИЧИНАМИ УЧАТ БОЛЬШЕМУ, ЧЕМ ДЕСЯТЬ ОТКАЗОВ С ОДНОЙ.

СВИДЕТЕЛИ ВЫБРАНЫ, А НЕ ВЗЯТЫ ПОДРЯД: при «нельзя» показываются два произведения (0 × 1 и
0 × 2 — наименьшие, чтобы читатель видел, что дело не в величине), при «всякое» — два далёких
друг от друга (0 × 1 и 0 × 7), чтобы «всякое» читалось как всякое, а не как соседнее.

    python3 tools/zerodivforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("деление", "ноль сверху", "ноль снизу", "ноль на ноль")

# СВИДЕТЕЛИ ОТКАЗА: два произведения при «нельзя» и два далёких при «всякое».
СВИДЕТЕЛИ_НЕТ = (1, 2)
СВИДЕТЕЛИ_ВСЯКОЕ = (1, 7)

РАМКИ = {
    "ru": {
        "деление": "сколько будет {a} ÷ {b}? {a} ÷ {b} = {q}, ибо {q} × {b} = {a}.",
        "ноль сверху": "сколько будет 0 ÷ {b}? 0 ÷ {b} = 0, ибо 0 × {b} = 0.",
        "ноль снизу": "сколько будет {a} ÷ 0? делить {a} на 0 нельзя: 0 × {с1} = 0, и 0 × {с2} = 0, и ни одно произведение не равно {a}.",
        "ноль на ноль": "сколько будет 0 ÷ 0? делить 0 на 0 нельзя однозначно: 0 × {в1} = 0, и 0 × {в2} = 0, и подходит всякое число.",
    },
    "en": {
        "деление": "what is {a} ÷ {b}? {a} ÷ {b} = {q}, because {q} × {b} = {a}.",
        "ноль сверху": "what is 0 ÷ {b}? 0 ÷ {b} = 0, because 0 × {b} = 0.",
        "ноль снизу": "what is {a} ÷ 0? dividing {a} by 0 is impossible: 0 × {с1} = 0, and 0 × {с2} = 0, and no product equals {a}.",
        "ноль на ноль": "what is 0 ÷ 0? dividing 0 by 0 has no single answer: 0 × {в1} = 0, and 0 × {в2} = 0, and every number fits.",
    },
}


def _пары():
    """(a, b, q) — деление НАЦЕЛО: дом о нуле, а не о дробях, и остаток был бы здесь чужим."""
    вон = []
    for b in range(2, 10):
        for q in range(2, 10):
            a = b * q
            if a <= 72:
                вон.append((a, b, q))
    return вон


def страницы():
    вон = {}
    пары = _пары()
    с1, с2 = СВИДЕТЕЛИ_НЕТ
    в1, в2 = СВИДЕТЕЛИ_ВСЯКОЕ
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a, b, q in пары:
            поля = dict(a=a, b=b, q=q, с1=с1, с2=с2, в1=в1, в2=в2)
            вон[рамки["деление"].format(**поля)] = (язык, "деление")
            вон[рамки["ноль сверху"].format(**поля)] = (язык, "ноль сверху")
            вон[рамки["ноль снизу"].format(**поля)] = (язык, "ноль снизу")
        # ЕДИНСТВЕННАЯ СТРАНИЦА НА ЯЗЫК: у «0 ÷ 0» нет переменных чисел вовсе, и повторять её
        # с разными свидетелями значило бы делать вид, что случаев много, когда он один.
        вон[рамки["ноль на ноль"].format(a=0, b=0, q=0, с1=с1, с2=с2, в1=в1, в2=в2)] = (
            язык, "ноль на ноль")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки, и потому строка, чьей
# длины нет среди объявленных, не может быть порчей ни одной страницы.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(\d+) × (\d+) = (\d+)")
_ЧАСТНОЕ = re.compile(r"(\d+) ÷ (\d+) = (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: всякое произведение и всякое частное своими
    # глазами. Деление на ноль в рамке «нельзя» не считается — его и нет: там стоя́т только
    # произведения, и это не уловка, а сам предмет дома.
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:70]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    образец = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "деление")
    отказ = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "ноль снизу")
    if судить(образец.replace("ибо", "иб"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(отказ.replace("нельзя", "нельз"))[1] is not False:
        беды.append("обрезанное слово в отказе прошло")
    if судить(образец + " " + образец)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ДЕЛЕНИЕ НА НОЛЬ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
