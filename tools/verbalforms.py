#!/usr/bin/env python3
"""ДОМ СЛОВЕСНОГО РАВЕНСТВА И ПРОШЕДШЕГО — «семь равно семи» и «купил вчера».

Два хвоста, спрошенные полосой: равенство, СКАЗАННОЕ СЛОВОМ, и прошедшее время
действия. Причина обоих замерена, а не предположена.

2 родов объявлены не здесь: их назвала СВОЯ ЖЕ КУЗНИЦА кортежем `ГРУППЫ`, и род всякой
страницы известен по тому, ЧЬЯ ФУНКЦИЯ её сделала.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

ПЕРЕЕЗЖАЕТ НЕ ФУНКЦИЯ, А ЗАМЫКАНИЕ ЦЕЛИКОМ: сюда переехали все ряды, помощники и строители.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

from plural import singular  # noqa: E402

РОДЫ = ('равенство_словом', 'прошедшее')

ЗАЧЕМ_РОДА = {
    "равенство_словом": "равенство, сказанное словом, а не знаком",
    "прошедшее": "действие в прошедшем времени",
}

# РОД-УПРАЖНЕНИЕ ОБЪЯВЛЕН ВСЛУХ (14.09, прибор очертаний; прочтён весь свод
# родов). «Равенство словом» есть одна запись счёта на многих числах. Род «прошедшее» (200 страниц
# на 200 очертаний) НЕ объявлен: там вместе с числами разнятся ИМЕНА И ГЛАГОЛЫ, и материал
# многомерен сам собою.
#
#     РОД РОВЕН САМ СОБОЮ, КОГДА ЕГО МАТЕРИАЛ МНОГОМЕРЕН; ОБЪЯВЛЕНИЕ НУЖНО ЛИШЬ
#     ТАМ, ГДЕ МЕРНОСТЬ ОДНА: ЧИСЛА ПРИ НЕИЗМЕННОЙ ЗАПИСИ.
ОЧЕРТАНИЕ_ПО_ПРИРОДЕ = ("равенство_словом",)

# РОДЫ, ПРОЧТЁННЫЕ И ПРИЗНАННЫЕ РОВНЫМИ СОБОЮ (14.09): объявление им не нужно,
# и надевать его нельзя — довод у каждого назван выше. Список объявлен отдельно,
# чтобы прибор отличал РЕШЕНО ОСТАВИТЬ от ЕЩЁ НЕ СМОТРЕЛИ: первое есть состояние,
# второе — долг.
РОВНЫ_СОБОЮ = ("прошедшее",)

ДЕЙСТВИЯ = (("plus", "+", lambda a, b: a + b),
            ("minus", "-", lambda a, b: a - b),
            ("times", "×", lambda a, b: a * b))

# (настоящее, прошедшее, вещь) — прошедшее объявлено, а не выведено:
# «wrote» из «write» правилом не получить.
ГЛАГОЛЫ = (("writes", "wrote", "novels"), ("bakes", "baked", "cakes"),
           ("sells", "sold", "books"), ("takes", "took", "coins"),
           ("gives", "gave", "pens"), ("reads", "read", "pages"),
           ("grows", "grew", "flowers"), ("eats", "ate", "apples"),
           ("buys", "bought", "cards"), ("makes", "made", "toys"))
ЛИЦА = ("regina", "vera", "peter", "anna", "ivan", "sara",
        "tom", "wanda", "carlos", "lena")


def равенство_словом(шаг):
    """Одно равенство двумя связками: «is» рядом с «equals»."""
    вон = []
    for i in range(24):
        имя, глиф, действие = ДЕЙСТВИЯ[(i + шаг) % 3]
        a = 2 + (i + шаг) % 12
        b = 1 + (i * 2 + шаг) % 9
        if имя == "minus" and b > a:
            a, b = b, a
        итог = действие(a, b)
        вон.append(f"{a} {имя} {b} is {итог}.")
        вон.append(f"{a} {имя} {b} equals {итог}.")
        вон.append(f"{a} {глиф} {b} = {итог}.")
    return вон


def прошедшее(шаг):
    """Прошедшее время в той же рамке, что и настоящее."""
    вон = []
    for i, (наст, прош, вещь) in enumerate(ГЛАГОЛЫ):
        кто = ЛИЦА[(i + шаг) % len(ЛИЦА)]
        n = 3 + (i + шаг) % 9
        вон.append(f"{кто} {наст} {n} {вещь}.")
        вон.append(f"{кто} {прош} {n} {вещь}.")
        вон.append(f"{кто} {прош} {n} {вещь}. how many {вещь} "
                   f"did {кто} {наст.rstrip('s')}? {кто} {прош} "
                   f"{n} {вещь}.")
        m = 1 + (i + шаг) % 4
        # ФОРМА ИДЁТ ЗА ЧИСЛОМ И ЗДЕСЬ: «1 novels more» ложно о языке
        # при верном счёте — тот самый род, что слой речи и учит.
        одна = singular(вещь) if m == 1 else вещь
        # ОТВЕТ И ЕГО КУЗНИЦА — ДВЕ ПОВЕРХНОСТИ ОДНОГО ФАКТА (М-166):
        # прочие формы этого мира ПРОЧИТЫВАЮТ число вопроса и выводить в них
        # нечего, а эта — единственная — его ВЫЧИСЛЯЕТ, и шага не было.
        кузн = f": {n} + {m} = {n + m}" if (i + шаг) % 2 == 0 else ""
        вон.append(f"{кто} {прош} {n} {вещь}. {кто} {прош} {m} {одна} "
                   f"more. how many {вещь} did {кто} "
                   f"{наст.rstrip('s')} in all? {кто} {прош} "
                   f"{n + m} {вещь}{кузн}.")
    return вон

ГРУППЫ = (равенство_словом, прошедшее)


def группы(шаг):
    """[[страница]] — ровно те группы и в том порядке, какими кузница кормит `emit_grouped`."""
    return [сделать(шаг) for сделать in ГРУППЫ]


def перебор(шаг):
    """[(страница, род)] — те же группы, но каждая под своим именем."""
    вон = []
    for род, группа in zip(РОДЫ, группы(шаг)):
        for с in группа:
            вон.append((с, род))
    return вон


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            вон.setdefault(с, род)
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, а не с кортежем."""
    имена = tuple(с.__name__ for с in ГРУППЫ)
    assert имена == РОДЫ, f"кортеж {имена} разошёлся с объявлением {РОДЫ}"
    сколько = len(группы(0))
    assert сколько == len(РОДЫ), f"проход даёт {сколько} групп при {len(РОДЫ)} родах"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка()
