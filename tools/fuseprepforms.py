def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


# ВЫДУМАННОЕ СЛИЯНИЕ ЕСТЬ ТАКОЕ ЖЕ НАРУШЕНИЕ, КАК РАЗДЕЛЬНАЯ ЗАПИСЬ ОБЯЗАТЕЛЬНОГО (12.09,
# поймано своей же пробой). Дом показывает «*inun», «*ala», «*deel» — формы, которых нет ни
# в одном языке, — и без этого признака суд звал бы их безобидными, а звёздочку при них
# лишней. Признак точен: слово, собранное из ОБЪЯВЛЕННОГО предлога и ОБЪЯВЛЕННОГО артикля,
# но отсутствующее в таблице слияний, есть форма выдуманная.
_ПРЕДЛОГИ = {п for п, _ in _СЛИЯНИЯ} | {п for п, _ in _НЕМЕЦКИЕ} | {п for _, _, п, _ in НЕОПР}
_АРТИКЛИ = ({а for _, а in _СЛИЯНИЯ} | {а for _, а in _НЕМЕЦКИЕ}
            | {а for _, _, _, а in НЕОПР}
            # АРТИКЛИ ИЗ НЕСЛИВАЮЩИХСЯ ПРИМЕРОВ — ТОЖЕ АРТИКЛИ: без них «*alos» и «*delas»
            # не опознаются как выдуманные слияния, и звёздочка при них кажется лишней.
            | {в.split(" ")[1] for *_, в in ЕС} | {в.split(" ")[1] for *_, в in ФР})
_ВЫДУМАННЫЕ = {п + а for п in _ПРЕДЛОГИ for а in _АРТИКЛИ} - _ВСЕ_СЛИТЫЕ


def _нарушает(тело):
    """Нарушает ли цитата закон дома: раздельная запись обязательного или выдуманная форма."""
    слова = тело.lstrip("*").strip().split(" ")
    for сл in слова:
        if сл.strip(".,:;!?") in _ВЫДУМАННЫЕ:
            return True          # слияния такого нет ни в одном языке
    for i in range(len(слова) - 1):
        пара = (слова[i], слова[i + 1])
        if пара in _СЛИЯНИЯ:
            return True          # обязательное слияние написано врозь
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        тело = цитата.lstrip("*").strip()
        # НЕМЕЦКАЯ РАЗДЕЛЬНАЯ ЗАПИСЬ ЗАКОННА И ОТДЕЛЬНОЙ ВЕТВИ НЕ ТРЕБУЕТ, ХОТЬ ОНА ЗДЕСЬ И
        # СТОЯЛА (12.09, снята пробой пробы). Ветвь «если пара немецкая — пропустить»
        # ничего не решала: немецких пар нет в таблице ОБЯЗАТЕЛЬНЫХ слияний, и общий путь
        # даёт тот же ответ. Порча, снимавшая её, оставляла пробу зелёной.
        #
        #     ВЕТВЬ, ПРИ УДАЛЕНИИ КОТОРОЙ НИЧЕГО НЕ МЕНЯЕТСЯ, ЕСТЬ УКРАШЕНИЕ, И ЧИТАЕТСЯ ОНА
        #     ХУЖЕ, ЧЕМ ОТСУТСТВУЕТ: за нею мерещится закон, которого нет.
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:110])
            беды += 1
    мутантов = 0
    for показ in ПОКАЗЫ:
        слова = показ.split(" ")
        порча = None
        for i, сл in enumerate(слова):
            голое = сл.strip("«».,:;")
            if голое in _ВСЕ_СЛИТЫЕ:
                чужое = next(ф for ф in sorted(_ВСЕ_СЛИТЫЕ) if ф != голое)
                порча = " ".join(слова[:i] + [сл.replace(голое, чужое)] + слова[i + 1:])
                break
        if not порча or порча == показ or порча in ПОКАЗЫ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:110])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    # СОДЕРЖАТЕЛЬНЫЙ ЗАКОН ПРОБУЕТСЯ ЛОЖНОЙ СТРАНИЦЕЙ, ВПИСАННОЙ В НАБОР.
    ложные = (
        "по-итальянски пишут «in il libro», и это верно.",
        "по-итальянски «*nel libro» не говорят вовсе.",
        "по-испански «a el libro» стои́т врозь.",
        "по-немецки «*in dem Haus» не говорят.",
    )
    for ложь in ложные:
        ПОКАЗЫ[ложь] = ("ru", "проба")
        try:
            if судить(ложь) != (True, False):
                print("  ЛОЖНАЯ СТРАНИЦА ПРОШЛА:", ложь[:100])
                беды += 1
        finally:
            del ПОКАЗЫ[ложь]
    написано = {род for _, род in ПОКАЗЫ.values()}
    if написано != set(РОДЫ):
        print(f"  РОДЫ РАЗОШЛИСЬ: обещано {sorted(РОДЫ)}, написано {sorted(написано)}")
        беды += 1
    for чужая in ("в словаре стои́т nel libro, и это не страница этого дома вовсе.",
                  "он выписал «del libro» на поля, и это не страница дома."):
        if судить(чужая) != (False, False):
            print("  ЧУЖАЯ РЕЧЬ СУДИМА:", чужая[:100])
            беды += 1
    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, мутантов поймано {мутантов}, "
          f"слияний объявлено {len(_СЛИЯНИЯ)}, немецких {len(_НЕМЕЦКИЕ)}, бед {беды}")
