"""ДОМ НЕХВАТКИ ДАННЫХ (14.09, куплен нулём пробы — и самым дорогим из всех).

Замерено 14.09 по своду в 448 335 строк:

    «лишнее число в задаче» / «не нужно для ответа»       63 строки — ЕСТЬ
    «данных не хватает» / «cannot be determined»           0 строк — НЕТ

    КОРПУС НАУЧИЛ ОТБРАСЫВАТЬ ЛИШНЕЕ И НИ РАЗУ НЕ НАУЧИЛ ОСТАНАВЛИВАТЬСЯ. Читатель, у
    какого всякая задача решаема, отвечает и там, где ответа НЕТ, — и отвечает уверенно,
    ибо уверенности его не на чем сломаться. Это не пробел в счёте: это пробел в ЧЕСТНОСТИ,
    и он опаснее всякой арифметической ошибки, потому что арифметическую ошибку видно.

ТРИ РОДА ПО ДЕЛУ:

    хватает      данные определяют ответ, и он назван. Род нужен не для полноты: без него
                 читатель выучит ОТКАЗЫВАТЬ ВСЕГДА, а это та же беда с другого конца;
    не_хватает   нужного числа НЕТ, и страница называет ИМЕННО ЕГО: «не сказано, сколько
                 отдано». Отказ без имени недостающего есть уклонение, а не отказ;
    лишнее       есть число, для ответа не нужное. Ответ назван, и лишнее НАЗВАНО лишним:
                 иначе читатель выучит, что всякое число в задаче обязано войти в счёт.

    ОТКАЗ БЕЗ ИМЕНИ НЕДОСТАЮЩЕГО ЕСТЬ УКЛОНЕНИЕ. Сказать «неизвестно» может всякий; сказать
    «не сказано, сколько отдано» может лишь тот, кто прочёл задачу и знает, чего в ней нет.

ГРАНИЦА ОБЪЯВЛЕНА: имя стои́т ПЕРЕД числом («яблок было 12»), и согласование числительного с
именем дом не трогает — оно дело дома `numnounforms`.
"""
import itertools
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("хватает", "не_хватает", "лишнее")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "хватает": "данные определяют ответ, и он назван",
    "не_хватает": "нужного числа нет, и страница называет именно его",
    "лишнее": "есть число, для ответа не нужное, и оно названо лишним",
}

ВЕЩИ = {"ru": ("яблок", "груш", "книг", "монет"), "en": ("apples", "pears", "books",
                                                         "coins")}

РАМКИ = {
    "ru": {
        "было": "{в} было {n}",
        "отдано": "отдано {n}",
        "отдано_нет": "отдано сколько-то",
        "было_нет": "{в} было сколько-то",
        "вопрос": "сколько осталось?",
        "отдано_чего": "отдано {в} {n}",
        "вопрос_чего": "сколько {в} осталось?",
        "ответ": " {n}.",
        "нет_ответа": " неизвестно: не сказано, сколько {чего}.",
        "лишнее": " {n}; {в} для ответа не нужны.",
        "чего_отдано": "отдано",
        "чего_было": "было вначале",
    },
    "en": {
        "было": "there were {n} {в}",
        "отдано": "{n} were given away",
        "отдано_нет": "some were given away",
        "было_нет": "there were some {в}",
        "вопрос": "how many are left?",
        "отдано_чего": "{n} {в} were given away",
        "вопрос_чего": "how many {в} are left?",
        "ответ": " {n}.",
        "нет_ответа": " unknown: it is not said how many {чего}.",
        "лишнее": " {n}; the {в} are not needed for the answer.",
        "чего_отдано": "were given away",
        "чего_было": "there were at the start",
    },
}

ПАРЫ = ((12, 5), (20, 8), (30, 11), (15, 6), (40, 17), (25, 9), (50, 23), (18, 7))
ЛИШНИЕ = (4, 9, 13, 6)


def страница(язык, род, пара, вещи, лишнее):
    было, отдано = пара
    рамки = РАМКИ[язык]
    в1 = ВЕЩИ[язык][вещи[0]]
    if род == "хватает":
        зачин = (рамки["было"].format(в=в1, n=было) + ", "
                 + рамки["отдано"].format(n=отдано))
        return f"{зачин}. {рамки['вопрос']}" + рамки["ответ"].format(n=было - отдано)
    if род == "не_хватает":
        # ДВЕ НЕХВАТКИ, А НЕ ОДНА: нет отданного — и нет начального. Дом показывает обе,
        # иначе читатель выучит искать пропажу лишь в одном месте.
        if лишнее:
            зачин = рамки["было"].format(в=в1, n=было) + ", " + рамки["отдано_нет"]
            чего = рамки["чего_отдано"]
        else:
            зачин = рамки["было_нет"].format(в=в1) + ", " + рамки["отдано"].format(n=отдано)
            чего = рамки["чего_было"]
        return (f"{зачин}. {рамки['вопрос']}"
                + рамки["нет_ответа"].format(чего=чего))
    # ВОПРОС, У КОГО ДВА ОТВЕТА, НЕ ЕСТЬ ВОПРОС. Когда вещей две, и «отдано», и вопрос
    # обязаны называть, о ЧЁМ речь: «отдано 5» при яблоках и грушах не значит ничего.
    в2 = ВЕЩИ[язык][вещи[1]]
    зачин = (рамки["было"].format(в=в1, n=было) + ", "
             + рамки["было"].format(в=в2, n=лишнее) + ", "
             + рамки["отдано_чего"].format(в=в1, n=отдано))
    вопрос = рамки["вопрос_чего"].format(в=в1)
    return (f"{зачин}. {вопрос}"
            + рамки["лишнее"].format(n=было - отдано, в=в2))


# РОД НЕ ДОЛЖЕН ЗАГЛУШАТЬ РОД. Первая редакция гоняла ВСЕ три рода по всем парам вещей и
# всем лишним числам, а «хватает» и «не хватает» второй вещи не поминают вовсе — и потому
# сходились в одну страницу, пока «лишнее» множилось: 768 против 64, перекос 12. Теперь
# каждый род перебирает ровно то, от чего ЗАВИСИТ: «хватает» — пары и первую вещь, «не
# хватает» — их же и две стороны нехватки, «лишнее» — обе вещи, а лишнее число берётся по
# месту пары. Перекос 12,0 стал 3,0, и ни одной страницы не потеряно.
def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        вещи_все = list(itertools.permutations(range(len(ВЕЩИ[язык])), 2))
        for место, пара in enumerate(ПАРЫ):
            for вещи in вещи_все:
                вон.setdefault(страница(язык, "хватает", пара, вещи, 0), (язык, "хватает"))
                for сторона in (0, 1):
                    п = страница(язык, "не_хватает", пара, вещи, сторона)
                    вон.setdefault(п, (язык, "не_хватает"))
                п = страница(язык, "лишнее", пара, вещи, ЛИШНИЕ[место % len(ЛИШНИЕ)])
                вон.setdefault(п, (язык, "лишнее"))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД ЧИТАЕТ ЗАДАЧУ ЗАНОВО и решает, ХВАТАЕТ ЛИ ДАННЫХ, — а потом сверяет своё решение со
# сказанным на странице. Он не верит ни ответу, ни отказу: отказ там, где данных довольно,
# есть ложь ровно так же, как ответ там, где их нет.
def _образцы(язык):
    рамки = РАМКИ[язык]
    вон = []
    было = re.escape(рамки["было"]).replace(re.escape("{в}"), "(?P<в1>[^0-9,.]+?)") \
        .replace(re.escape("{n}"), r"(?P<n1>\d+)")
    было2 = re.escape(рамки["было"]).replace(re.escape("{в}"), "(?P<в2>[^0-9,.]+?)") \
        .replace(re.escape("{n}"), r"(?P<n2>\d+)")
    отдано = re.escape(рамки["отдано"]).replace(re.escape("{n}"), r"(?P<d>\d+)")
    вопрос = re.escape(". " + рамки["вопрос"])
    ответ = re.escape(рамки["ответ"]).replace(re.escape("{n}"), r"(?P<ответ>\d+)")
    нет = re.escape(рамки["нет_ответа"]).replace(re.escape("{чего}"), "(?P<чего>[^.]+)")
    лишнее = re.escape(рамки["лишнее"]).replace(re.escape("{n}"), r"(?P<ответ>\d+)") \
        .replace(re.escape("{в}"), "(?P<лишняя>[^0-9,.;]+?)")
    отдано_чего = (re.escape(рамки["отдано_чего"])
                   .replace(re.escape("{в}"), "(?P<вд>[^0-9,.]+?)")
                   .replace(re.escape("{n}"), r"(?P<d>\d+)"))
    вопрос_чего = re.escape(". " + рамки["вопрос_чего"]).replace(
        re.escape("{в}"), "(?P<вв>[^0-9,.?]+?)")
    вон.append(("хватает", re.compile(было + ", " + отдано + вопрос + ответ + r"$")))
    вон.append(("нет_отдано",
                re.compile(было + ", " + re.escape(рамки["отдано_нет"]) + вопрос + нет
                           + r"$")))
    вон.append(("нет_было",
                re.compile(re.escape(рамки["было_нет"]).replace(re.escape("{в}"),
                                                               "(?P<в1>[^0-9,.]+?)")
                           + ", " + отдано + вопрос + нет + r"$")))
    вон.append(("лишнее", re.compile(было + ", " + было2 + ", " + отдано_чего
                                     + вопрос_чего + лишнее + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def судить(строка):
    """(судимо, истинно) — суд сам решает, хватает ли данных, и сверяет со страницей."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for вид, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            вещи = ВЕЩИ[язык]
            if д.get("в1") and д["в1"] not in вещи:
                continue                       # чужая вещь — запись не наша
            if вид == "хватает":
                было, отдано = int(д["n1"]), int(д["d"])
                # ОТДАТЬ БОЛЬШЕ, ЧЕМ БЫЛО, НЕЛЬЗЯ: такая задача не решаема, а не трудна.
                return True, отдано <= было and int(д["ответ"]) == было - отдано
            if вид == "нет_отдано":
                return True, д["чего"].strip() == рамки["чего_отдано"]
            if вид == "нет_было":
                return True, д["чего"].strip() == рамки["чего_было"]
            если = д.get("в2")
            if если is not None and если not in вещи:
                continue                       # чужая вещь — запись не наша
            было, отдано = int(д["n1"]), int(д["d"])
            # ЛИШНЕЕ ОБЯЗАНО БЫТЬ И ПРАВДА ЛИШНИМ: названная лишней вещь не смеет быть той
            # же, о какой спрошено, — иначе «лишнее» есть подмена, а не показ.
            # И «ОТДАНО», И ВОПРОС ОБЯЗАНЫ ГОВОРИТЬ ОБ ОДНОЙ ВЕЩИ — той, о какой спрошено.
            return True, (отдано <= было and int(д["ответ"]) == было - отдано
                          and д["лишняя"].strip() == если and если != д["в1"]
                          and д["вд"].strip() == д["в1"] and д["вв"].strip() == д["в1"])
    return False, True


# ПОДСАДКИ ОБЪЯВЛЕНЫ ЗДЕСЬ, И СУД БЕРЁТ ИХ ОТСЮДА ЖЕ.
ПОДСАДКИ = (
    "яблок было 12, отдано 5. сколько осталось? 8.",
    "яблок было 12, отдано 15. сколько осталось? 3.",
    "яблок было 12, отдано сколько-то. сколько осталось? неизвестно: не сказано, сколько "
    "было вначале.",
    "яблок было сколько-то, отдано 5. сколько осталось? неизвестно: не сказано, сколько "
    "отдано.",
    "яблок было 12, груш было 4, отдано яблок 5. сколько яблок осталось? 7; яблок для "
    "ответа не нужны.",
    "яблок было 12, груш было 4, отдано груш 5. сколько яблок осталось? 7; груши для "
    "ответа не нужны.",
    "there were 12 apples, 5 were given away. how many are left? 8.",
)


def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    for было, отдано in ПАРЫ:
        assert 0 < отдано < было, f"отдано не меньше бывшего: {было}, {отдано}"
    # ДВЕ НЕХВАТКИ КУПЛЕНЫ ОБЕ: и без отданного, и без начального.
    виды = set()
    for язык in ЯЗЫКИ:
        хвост = РАМКИ[язык]["нет_ответа"].format(чего=РАМКИ[язык]["чего_отдано"])
        for пара in ПАРЫ:
            for сторона in (0, 1):
                с = страница(язык, "не_хватает", пара, (0, 1), сторона)
                виды.add(с.endswith(хвост))
    assert виды == {True, False}, "куплена лишь одна нехватка из двух"
    # ДВЕ РАМКИ НА ОДНОЙ ЗАПИСИ ДЕЛАЮТ РОД НЕРАЗЛИЧИМЫМ: страж дома двух процентов.
    for с, (язык, _р) in ПОКАЗЫ.items():
        совпали = [вид for вид, о in _ОБРАЗЦЫ[язык] if о.fullmatch(с)]
        assert len(совпали) == 1, f"две рамки на одной записи ({совпали}): {с}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
