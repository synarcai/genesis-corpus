#!/usr/bin/env python3
"""ДОМ НЕГОДНОГО ОСНОВАНИЯ (14.09, куплен нулём пробы).

Замерено 14.09: «круг в доказательстве» / «circular reasoning» — НОЛЬ строк. Мир вывода
(`inferforms`) называет две ФОРМАЛЬНЫЕ ошибки — обращение и отрицание — и проверяет их
счётом. А о том, что основание бывает НЕГОДНЫМ, не будучи ложным, корпус не говорит нигде.

    ОСНОВАНИЕ БЫВАЕТ ИСТИННЫМ И НЕГОДНЫМ РАЗОМ. «12 делится на 2, потому что оно чётное» —
    оба утверждения истинны, и второе не доказывает первого: это ОДНО И ТО ЖЕ, сказанное
    дважды. «12 делится на 4, потому что оно делится на 2» — тоже оба истинны, и второе
    СЛАБЕЕ первого: из него первое не следует. Ложь тут ни при чём, и потому ни один суд над
    истинностью такого не поймает.

ТРИ РОДА ПО СИЛЕ ОСНОВАНИЯ, И ВСЕ ТРИ РЕШАЮТСЯ ОБХОДОМ РЯДА, А НЕ ЧУТЬЁМ:

    круг       основание и утверждение РАВНОСИЛЬНЫ: из каждого следует другое. Сказано то
               же самое другими словами, и прибавлено ровно ничего;
    слабое     из основания утверждение НЕ СЛЕДУЕТ: основание шире, и пример этому назван.
               Это самая частая ошибка живого рассуждения;
    годное     из основания утверждение следует ВСЕГДА, а обратное неверно: основание
               строго сильнее. Род нужен не для полноты — без него читатель выучит
               отвергать всякое основание, а это та же беда с другого конца.

РАМКА НЕ СМЕЕТ ПАДАТЬ В РАМКУ ЧУЖОГО МИРА (14.09). Первая редакция писала «почему 27
делится на 3? потому что оно делится на 9» — и ворота закрылись: это рамка мира лестницы
вопроса (`inquiry`), и судил мои страницы ЕГО суд, по своему закону. Основание названо
основанием прямо: «27 делится на 3. основание: оно делится на 9».

СВОЙСТВА И РЯД БЕРУТСЯ У ДОМА ДВУСТОРОННЕЙ СВЯЗИ, а вид связи — у его же `вид()`: круг есть
связь двусторонняя, годное — односторонняя в сторону утверждения, слабое — односторонняя в
обратную. ОДИН ДОМ СЛОВ, А НЕ ТРИ ПОХОЖИХ ОБЪЯВЛЕНИЯ.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from bicondforms import РЯД, СВОЙСТВА, СВЯЗИ, вид  # noqa: E402 — один дом слов

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("круг", "слабое", "годное")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "круг": "основание и утверждение равносильны: то же самое другими словами",
    "слабое": "из основания утверждение не следует, и пример этому назван",
    "годное": "из основания утверждение следует всегда, а обратное неверно",
}

РАМКИ = {
    "ru": {
        "круг": "{n} {A}. основание: оно {B}. это КРУГ: «{B}» и «{A}» суть одно и то "
                "же — из всякого числа ряда, какое {B}, следует {A}, и обратно тоже.",
        "слабое": "{n} {A}. основание: оно {B}. это НЕ ДОВОД: из «{B}» не следует "
                  "«{A}» — вот {m}: оно {B} и оно {A_нет}.",
        "годное": "{n} {A}. основание: оно {B}. это ДОВОД: из «{B}» следует «{A}» "
                  "всегда, а обратное неверно — вот {m}: оно {A} и оно {B_нет}.",
    },
    "en": {
        "круг": "{n} {A}. the ground: it {B}. this is a CIRCLE: «{B}» and «{A}» are one and "
                "the same — every number of the range that {B} also {A}, and the other way "
                "round too.",
        "слабое": "{n} {A}. the ground: it {B}. this is NO ARGUMENT: «{A}» does not follow "
                  "from «{B}» — take {m}: it {B} and it {A_нет}.",
        "годное": "{n} {A}. the ground: it {B}. this is an ARGUMENT: «{A}» follows from "
                  "«{B}» always, and not the other way round — take {m}: it {A} and it "
                  "{B_нет}.",
    },
}


def _держит(a, b):
    """Следует ли B из A на всём объявленном ряду."""
    A, B = СВОЙСТВА[a][0], СВОЙСТВА[b][0]
    return not any(A(n) and not B(n) for n in РЯД)


def _род(основание, утверждение):
    """Круг, слабое или годное — ВЫВЕДЕНО обходом ряда, а не объявлено."""
    сюда = _держит(основание, утверждение)
    туда = _держит(утверждение, основание)
    if сюда and туда:
        return "круг"
    if сюда:
        return "годное"
    return "слабое" if туда else None      # связи нет вовсе — не наше дело


def _числа(проба, сколько=3):
    return [n for n in РЯД if проба(n)][:сколько]


def страница(язык, род, основание, утверждение, i):
    if основание == утверждение or _род(основание, утверждение) != род:
        return None
    A, A_нет = СВОЙСТВА[утверждение][1][язык]
    B, B_нет = СВОЙСТВА[основание][1][язык]
    Ф_A, Ф_B = СВОЙСТВА[утверждение][0], СВОЙСТВА[основание][0]
    рамки = РАМКИ[язык]
    # ЧИСЛО ПОКАЗА ОБЯЗАНО ОТВЕЧАТЬ ОБОИМ: спорить о доводе на числе, какое не делает ни
    # того ни другого, значит спорить ни о чём.
    свои = _числа(lambda n: Ф_A(n) and Ф_B(n))
    if i >= len(свои):
        return None
    n = свои[i]
    if род == "круг":
        return рамки["круг"].format(n=n, A=A, B=B)
    if род == "слабое":
        # СВИДЕТЕЛЬ СЛАБОСТИ: число, где основание держится, а утверждение нет.
        прочь = _числа(lambda m: Ф_B(m) and not Ф_A(m), 1)
        if not прочь:
            return None
        return рамки["слабое"].format(n=n, A=A, B=B, A_нет=A_нет, m=прочь[0])
    прочь = _числа(lambda m: Ф_A(m) and not Ф_B(m), 1)
    if not прочь:
        return None
    return рамки["годное"].format(n=n, A=A, B=B, B_нет=B_нет, m=прочь[0])


# ПАРЫ ОБЪЯВЛЕНЫ ЧЕРЕЗ СОСЕДА: верные связи дома двусторонней связи дают «годное» (основание
# сильнее) и «слабое» (то же в обратную сторону), а двусторонние из них — «круг». Перебор
# всех пар свойств дал бы вдесятеро больше слабых, и это было бы их ЧИСЛО, а не важность.
ПАРЫ = tuple({(a, b) for a, b in СВЯЗИ} | {(b, a) for a, b in СВЯЗИ})


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for основание, утверждение in sorted(ПАРЫ):
                for i in range(3):
                    п = страница(язык, род, основание, утверждение, i)
                    if п:
                        вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
