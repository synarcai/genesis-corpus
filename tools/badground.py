# СУД ВЫВОДИТ СИЛУ ОСНОВАНИЯ ОБХОДОМ РЯДА, а не читает слово «КРУГ» на странице. Он берёт из
# записи два свойства, проходит весь объявленный ряд в обе стороны — и требует, чтобы имя,
# какое страница дала доводу, сошлось с делом. Свидетель обязан БЫТЬ свидетелем.
def _образцы(язык):
    формы = sorted({ф for _и, (_п, с) in СВОЙСТВА.items() for ф in с[язык]},
                   key=len, reverse=True)
    словарь = "(?:" + "|".join(re.escape(ф) for ф in формы) + ")"
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык][род])
        for дыра, узор in (("A_нет", словарь), ("B_нет", словарь), ("A", словарь),
                           ("B", словарь), ("n", r"\d+"), ("m", r"\d+")):
            дыра_о = re.escape("{" + дыра + "}")
            первый = True
            while дыра_о in о:
                о = о.replace(дыра_о, f"(?P<{дыра}>{узор})" if первый else f"(?P={дыра})", 1)
                первый = False
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def _имя(язык, форма, сказ=True):
    for имя, (_п, формы) in СВОЙСТВА.items():
        если = формы[язык]
        if форма == (если[0] if сказ else если[1]):
            return имя
    return None


def судить(строка):
    """(судимо, истинно) — сила основания выведена обходом ряда, свидетель проверен."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            a, b = _имя(язык, д["A"]), _имя(язык, д["B"])
            if a is None or b is None or a == b:
                continue                      # чужое свойство — запись не наша
            A, B = СВОЙСТВА[a][0], СВОЙСТВА[b][0]
            n = int(д["n"])
            if n not in РЯД or not (A(n) and B(n)):
                return True, False            # число показа не отвечает обоим
            if _род(b, a) != род:
                return True, False            # имя довода разошлось с делом
            if род == "круг":
                return True, True
            m = int(д["m"])
            if m not in РЯД:
                return True, False
            if род == "слабое":
                # СВИДЕТЕЛЬ СЛАБОСТИ: основание держится, утверждение нет.
                return True, (B(m) and not A(m)
                              and _имя(язык, д["A_нет"], сказ=False) == a)
            # СВИДЕТЕЛЬ СТРОГОСТИ: утверждение держится, основание нет.
            return True, A(m) and not B(m) and _имя(язык, д["B_нет"], сказ=False) == b
    return False, True


