#!/usr/bin/env python3
"""ДОМ САМОИСПРАВЛЕНИЯ — проверить СВОЙ ответ и назвать, ошибся ли.

    «Я ОШИБСЯ» ЕСТЬ В СВОДЕ ТОЛЬКО КАК ИЗВИНЕНИЕ. Замер 11.09: слова эти встречаются в мире
    диалога и в доме самомодели — «извини, я ошибся. всё в порядке», «что такое извини, я
    ошибся? — это извинение». Признания ошибки В СЧЁТЕ, с проверкой и верным ответом, нет ни
    одной строкой; «была ошибка», «верный ответ», «i was wrong» — НИ ОДНОГО ВХОЖДЕНИЯ.

    ОРГАНИЗМ, УМЕЮЩИЙ ИЗВИНЯТЬСЯ И НЕ УМЕЮЩИЙ ПЕРЕСЧИТЫВАТЬ, ИЗВИНЯЕТСЯ ВМЕСТО ТОГО, ЧТОБЫ
    ИСПРАВИТЬ.

ТРИ РОДА, И ВСЕ ТРИ ПРОВЕРЯЮТСЯ ПЕРЕСЧЁТОМ ОБОИХ ШАГОВ:

    ошибся     меня спросили, сколько будет 2 + 3 × 4, и я сказал 20. проверяю: умножение
               идёт прежде сложения, и 3 × 4 = 12, и 2 + 12 = 14. я ошибся: верно 14.
    не ошибся  …и я сказал 14. проверяю: … я не ошибся: верно 14.   ← ТА ЖЕ ПРОВЕРКА
    ход        …и я сказал 14. это верно, но объяснил я неверно: я сказал, что сложение идёт
               прежде, а прежде идёт умножение: 3 × 4 = 12, и 2 + 12 = 14.
                                                    ← ВЕРНЫЙ ОТВЕТ ПРИ НЕВЕРНОМ ХОДЕ

ПЕРВЫЙ И ВТОРОЙ СУТЬ МИНИМАЛЬНАЯ ПАРА: проверка ОДНА И ТА ЖЕ, а итог её разный. Без второго
рода дом учил бы, что проверка всегда кончается покаянием, — и проверка стала бы обрядом.

    ПРОВЕРКА, КОТОРАЯ ВСЕГДА НАХОДИТ ОШИБКУ, НЕ ЕСТЬ ПРОВЕРКА.

ТРЕТИЙ РОД ГЛУБЖЕ ПЕРВЫХ ДВУХ И РАДИ НЕГО ДОМ ЗАВЕДЁН ТРЁХРОДНЫМ: ответ верен, а ход неверен, и
это НЕ ЗАСЧИТЫВАЕТСЯ. Тот, кто получил четырнадцать, сложив прежде умножения, получил его
случайно — и в другой раз ошибётся.

    ВЕРНЫЙ ОТВЕТ НЕ ОПРАВДЫВАЕТ НЕВЕРНОГО ХОДА.

ОШИБОЧНЫЙ ОТВЕТ НАЗЫВАЕТСЯ ЧИСЛОМ, А НЕ РАВЕНСТВОМ, И ЭТО КУПЛЕНО СУДОМ АРИФМЕТИКИ. Первая
редакция писала «я сказал, что 2 + 3 × 4 = 20» — и суд назвал строку ложью, будучи прав: это
УТВЕРЖДЁННОЕ равенство, а не процитированное вопросом. Окно цитаты у него открывается вопросом
(«верно ли, что…? нет»), а здесь вопроса нет. Ныне ошибка стои́т числом («и я сказал 20»), и
ложного равенства в своде не появляется вовсе.

    ЧТОБЫ ПОКАЗАТЬ ОШИБКУ, НЕ ОБЯЗАТЕЛЬНО ЕЁ УТВЕРЖДАТЬ.

ЧИСЛА БЕРУТСЯ У ДОМА ПОРЯДКА ДЕЙСТВИЙ: ошибка «слева направо» есть та самая, ради которой тот
дом заведён, и здесь она получает вторую поверхность — не «как надо», а «я проверил себя».

    python3 tools/amendforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("ошибся", "не ошибся", "ход")

РАМКИ = {
    "ru": {
        "ошибся": "меня спросили, сколько будет {a} + {b} × {c}, и я сказал {слева}. проверяю: умножение идёт прежде сложения, и {b} × {c} = {п}, и {a} + {п} = {верно}. я ошибся: верно {верно}.",
        "не ошибся": "меня спросили, сколько будет {a} + {b} × {c}, и я сказал {верно}. проверяю: умножение идёт прежде сложения, и {b} × {c} = {п}, и {a} + {п} = {верно}. я не ошибся: верно {верно}.",
        "ход": "меня спросили, сколько будет {a} + {b} × {c}, и я сказал {верно}. это верно, но объяснил я неверно: я сказал, что сложение идёт прежде, а прежде идёт умножение: {b} × {c} = {п}, и {a} + {п} = {верно}.",
    },
    "en": {
        "ошибся": "i was asked what {a} + {b} × {c} is, and i said {слева}. i check: multiplication goes before addition, and {b} × {c} = {п}, and {a} + {п} = {верно}. i was wrong: it is {верно}.",
        "не ошибся": "i was asked what {a} + {b} × {c} is, and i said {верно}. i check: multiplication goes before addition, and {b} × {c} = {п}, and {a} + {п} = {верно}. i was not wrong: it is {верно}.",
        "ход": "i was asked what {a} + {b} × {c} is, and i said {верно}. that is right, but my reasoning was wrong: i said addition goes first, while multiplication goes first: {b} × {c} = {п}, and {a} + {п} = {верно}.",
    },
}


def _тройки():
    """(a, b, c): ошибка «слева направо» обязана ОТЛИЧАТЬСЯ от верного, иначе рода нет."""
    вон = []
    for a in range(2, 9):
        for b in range(2, 8):
            for c in range(2, 6):
                верно, слева = a + b * c, (a + b) * c
                if верно != слева and слева <= 99:
                    вон.append((a, b, c))
    return вон[:32]


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a, b, c in _тройки():
            поля = dict(a=a, b=b, c=c, п=b * c, верно=a + b * c, слева=(a + b) * c)
            for род in РОДЫ:
                вон[рамки[род].format(**поля)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(\d+) × (\d+) = (\d+)(?!\d)")
_СУММА = re.compile(r"(\d+) \+ (\d+) = (\d+)(?!\d)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ. Ошибочный ответ здесь стои́т ЧИСЛОМ и равенством
    # не объявлен, потому пересчитывать в нём нечего: считаются шаги проверки.
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:74]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    ош = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "ошибся")
    не = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "не ошибся")
    ход = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "ход")
    if судить(ош.replace("ошибся", "ошибс"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(не.replace("проверяю", "проверя"))[1] is not False:
        беды.append("обрезанное слово в согласии прошло")
    if судить(ход.replace("неверно", "неверн"))[1] is not False:
        беды.append("обрезанное слово в ходе прошло")
    if судить(ош + " " + ош)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"САМОИСПРАВЛЕНИЕ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
