def високосный(год):
    """Правило целиком, тремя слоями и в один взгляд."""
    return год % 4 == 0 and (год % 100 != 0 or год % 400 == 0)


def _счёт(a, b):
    return sum(1 for г in range(a, b + 1) if високосный(г))


