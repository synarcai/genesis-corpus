def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка И
    ЕСЛИ ВСЯКАЯ ЗАПИСЬ В НЕЙ ПЕРЕСЧИТЫВАЕТСЯ РАЗБОРОМ (`arithread`).

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать;
    ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    return True, arithread.записи_верны(с)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    import re
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ПРАВИЛО ПРОВЕРЯЕТСЯ НА ЗАВЕДОМО ИЗВЕСТНОМ, А НЕ ТОЛЬКО НА СВОИХ СТРАНИЦАХ.
    for г, ждём in ((2024, True), (1900, False), (2000, True), (2023, False),
                    (1600, True), (2100, False), (4, True), (100, False), (400, True)):
        if високосный(г) != ждём:
            беды.append(f"правило: {г} → {високосный(г)}, а надо {ждём}")
    # ТАБЛИЦЫ ОБЯЗАНЫ БЫТЬ ТЕМ, ЧЕМ НАЗВАНЫ, — ИНАЧЕ СЛОЙ ПОКАЗАН НЕ ТОТ.
    for г in ПРОСТЫЕ_ВИСОКОСНЫЕ:
        if not (г % 4 == 0 and г % 100 != 0):
            беды.append(f"не простой високосный: {г}")
    for г in ВЕКА_НЕ_ВИСОКОСНЫЕ:
        if not (г % 100 == 0 and г % 400 != 0):
            беды.append(f"не век без четырёхсот: {г}")
    for г in ЧЕТЫРЁХСОТЫЕ:
        if г % 400:
            беды.append(f"не делится на четыреста: {г}")
    for г in НЕ_ДЕЛЯТСЯ:
        if г % 4 == 0:
            беды.append(f"делится на четыре, а лежит в неделящихся: {г}")
    # ВСЕ ТРИ СЛОЯ ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ: без любого правило становится ложью.
    for язык in ЯЗЫКИ:
        слои = [по_роду.get((язык, р)) for р in ("делится на четыре", "век не високосен",
                                                 "четырёхсотый високосен")]
        if not all(слои):
            беды.append(f"показаны не все три слоя правила [{язык}]: {слои}")
    # СЧЁТ ПО ВЕКУ ОБЯЗАН ДАВАТЬ ОБА ЧИСЛА — 24 И 25, ИНАЧЕ ИСКЛЮЧЕНИЕ НЕ ВИДНО.
    счета = {_счёт(a, b) for a, b in ВЕКА}
    if счета != {24, 25}:
        беды.append(f"счёт по векам дал {sorted(счета)} — оба случая не показаны")
    for a, b in ВЕКА:
        if b - a != 99:
            беды.append(f"век не в сто лет: {(a, b)}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ, ГДЕ ЕСТЬ ЗАПИСЬ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    век = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "век не високосен")
    порча = век.replace("ИСКЛЮЧЕНИЕ", "ИСКЛЮЧЕНИ", 1)
    if порча == век:
        беды.append("порча не состоялась: нет слова «ИСКЛЮЧЕНИЕ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(век + " " + век)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ВИСОКОСНЫЙ ГОД: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


