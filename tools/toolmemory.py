def _ф(язык, строка):
    return R._ф(язык, строка)


def _р(язык, ключ, **п):
    return РЕЧЬ[язык][ключ].format(**п)


def имена(язык, x):
    """Имя во всех падежах страницы: X, Xп («о ком»), Xв, Xт, Xр (дверь `memoryworld.ФОРМЫ_ИМЁН`)."""
    return dict(X=x, Xп=П.форма(язык, x, "пр"), Xв=П.форма(язык, x, "вин"), Xт=П.форма(язык, x, "твор"),
                Xр=П.форма(язык, x, "род"))


def к_файлу(язык, f):
    return К_ФАЙЛУ.get(язык, R._о(язык, "в_файле" if язык in К_ФАЙЛУ_МЕСТОМ else "в_файл")).format(f=f)


def род_(язык, x, t):
    """«nora is a teacher» — род человека, клетка entityType."""
    return _ф(язык, _р(язык, "a_род", X=x, T=t))


def наблюдения_(язык, x, наблюдения):
    """«nora plays the cello and lives by the sea» — наблюдения, клетки observations по порядку, дословно."""
    return _ф(язык, _р(язык, "a_наблюдения", X=x, М=R.список(язык, list(наблюдения))))


def связь_(язык, a, r, b):
    """«nora knows pavel» — связь, клетки from, relationType, to (дополнение — в падеже голоса)."""
    return _ф(язык, _р(язык, "a_связь", A=a, R=r, B=П.форма(язык, b, "вин")))


def перечень_людей(язык, люди_):
    return _ф(язык, _р(язык, "a_всё", М=R.список(язык, list(люди_))))


def знание(язык, x, t=None, наблюдения=(), связи=()):
    """Что память держит о человеке — предложениями: род, наблюдения, связи; без рода — «не помню»."""
    if t is None:
        return _ф(язык, _р(язык, "a_не_помню", **имена(язык, x))) + "."
    части = [род_(язык, x, t)]
    if наблюдения:
        части.append(наблюдения_(язык, x, наблюдения))
    части += [связь_(язык, a, r, b) for a, r, b in связи]
    return ". ".join(части) + "."


def клетки_знания(ход_):
    """(род, наблюдения, связи) из рядов хода open_nodes / search_nodes: ряд человека — имя, род и наблюдение (у
    человека без наблюдений — без него), ряд связи — from, to, relationType."""
    t, наблюдения, связи = None, [], []
    for р in П.ряды(ход_):
        if "name" in р:
            t = р.get("entityType")
            if "observations" in р:
                наблюдения.append(р["observations"])
        elif "from" in р:
            связи.append((р["from"], р["relationType"], р["to"]))
    return t, наблюдения, связи


