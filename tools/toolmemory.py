def _ход(язык, род, объект="", доводы=()):
    ход_ = П.ход(язык, род, объект, доводы)
    return ход_, W.текст(ход_)


def ответ_знания(язык, x, ход_):
    t, наблюдения, связи = клетки_знания(ход_)
    return знание(язык, x, t, наблюдения, связи)


def ответ_связей(язык, x, ход_):
    """Кто связан с X: связи хода; у человека без связей — «никто»; у незнакомого — «не помню»."""
    t, _н, связи = клетки_знания(ход_)
    if t is None and not связи:
        return _ф(язык, _р(язык, "a_не_помню", **имена(язык, x))) + "."
    if not связи:
        return _ф(язык, _р(язык, "a_никто", **имена(язык, x))) + "."
    return ". ".join(связь_(язык, a, r, b) for a, r, b in связи) + "."


def ответ_всего(язык, ход_):
    люди_ = list(dict.fromkeys(р["name"] for р in П.ряды(ход_) if "name" in р))
    связи = [(р["from"], р["relationType"], р["to"]) for р in П.ряды(ход_) if "from" in р]
    return ". ".join([перечень_людей(язык, люди_)] + [связь_(язык, a, r, b) for a, r, b in связи]) + "."


def страница(язык, род, x=None, доводы=()):
    """Страница рода на семени мира памяти."""
    if род in (ЗНАЕШЬ, НЕ_ПОМНЮ) and доводы != ("связан",):
        ход_, мир_ = _ход(язык, "open_nodes", x)
        return сборка_знаешь(язык, x, мир_, ответ_знания(язык, x, ход_))
    if род in (СВЯЗАН, НЕ_ПОМНЮ):
        ход_, мир_ = _ход(язык, "search_nodes", x)
        return сборка_связан(язык, x, мир_, ответ_связей(язык, x, ход_))
    if род == ВСЁ:
        ход_, мир_ = _ход(язык, "read_graph")
        return сборка_всё(язык, мир_, ответ_всего(язык, ход_))
    if род == ЗАБЫТЬ_НЕЧЕГО:
        return сборка_забыть_нечего(язык, x, _ход(язык, "open_nodes", x)[1])
    raise ValueError(род)


def страница_запомни(язык, род, вид, x, доводы, регистр="плоский"):
    """Запомнить: вид «нового» (create_entities x род наблюдение), «факта» (add_observations x наблюдение), «связи»
    (create_relations x к кому связь); отказ — чтение «до» (open_nodes x)."""
    kind = {"нового": "create_entities", "факта": "add_observations", "связи": "create_relations"}[вид]
    if вид == "нового":
        клауза_ = клауза(язык, вид, X=x, T=доводы[0], O=доводы[1])
    elif вид == "факта":
        клауза_ = клауза(язык, вид, X=x, O=доводы[0])
    else:
        клауза_ = клауза(язык, вид, A=x, B=доводы[0], R=доводы[1])
    if род == ЗАПОМНИ_ОТКАЗ:
        чтение, мир_ = _ход(язык, "open_nodes", x)
        return сборка_запомни(язык, род, клауза_, мир_, ответ_знания(язык, x, чтение), регистр)
    ход_, мир_ = _ход(язык, kind, x, доводы)
    if род == ФАКТ_НЕЗНАКОМОМУ:
        return сборка_факт_незнакомому(язык, x, клауза_, мир_, регистр)
    return сборка_запомни(язык, род, клауза_, мир_, регистр=регистр)


def страница_забудь(язык, род, вид, x, доводы=(), регистр="плоский"):
    """Забыть: вид «человека» (delete_entities x), «факта» (delete_observations x наблюдение), «связи»
    (delete_relations x к кому связь); отказ — чтение «до» (open_nodes x)."""
    kind = {"человека": "delete_entities", "факта": "delete_observations", "связи": "delete_relations"}[вид]
    клауза_ = (None if вид == "человека" else клауза(язык, "факта", X=x, O=доводы[0]) if вид == "факта"
               else клауза(язык, "связи", A=x, B=доводы[0], R=доводы[1]))
    if род == ЗАБУДЬ_ОТКАЗ:
        чтение, мир_ = _ход(язык, "open_nodes", x)
        return сборка_забудь(язык, род, x, клауза_, мир_, ответ_знания(язык, x, чтение), регистр)
    return сборка_забудь(язык, род, x, клауза_, _ход(язык, kind, x, доводы)[1], регистр=регистр)


def страница_плана(язык, род, x, f=ФАЙЛ):
    """План двух миров на семени: чтение памяти — ход open_nodes, затем line мира папки дома актов на всякое
    наблюдение — строка файла дословно клетка observations; на «нет» — чтение «до» мира папки (lines файла)."""
    мир_папки = R.папка(язык)
    if род == ПЛАН_ОТКАЗ:
        ход_ = мир_папки.lines(f)[1]
        n = ход_.мера("lines")
        return сборка_плана(язык, род, x, f, W.текст(ход_), None,
                            чтение=T.наблюдение(язык, R._строк_в(язык, f, T.строк_вин(язык, n)), R._л(n, 0)))
    ход1, мир1 = _ход(язык, "open_nodes", x)
    t, наблюдения, _связи = клетки_знания(ход1)
    if not наблюдения:
        итог1 = ((род_(язык, x, t) if t is not None else _ф(язык, _р(язык, "a_не_помню", **имена(язык, x)))) + ". "
                 + _ф(язык, _р(язык, "нечего_писать", К=к_файлу(язык, f))) + ".")
        return сборка_плана(язык, род, x, f, мир1, итог1)
    строки_ = []
    for н in наблюдения:
        мир_папки, ход_ = мир_папки.line(f, н)
        n = ход_.мера("lines")
        строки_.append((W.текст(ход_), отчёт_строки(язык, н, f, T.строк_вин(язык, n), R._л(n - 1, 1))))
    return сборка_плана(язык, род, x, f, мир1, наблюдения_(язык, x, наблюдения) + ".", строки_)


def _показы():
    вон, перепись = {}, {}

    def положить(стр, язык, род, форма, дыры):
        if стр not in вон:
            вон[стр] = (язык, род, форма, "плоский")
            перепись[стр] = дыры

    for язык in ЯЗЫКИ:
        г = П.ГРАФ[язык]
        люди_ = [имя_ for имя_, _р, _н in П.люди(язык)]
        незнакомый = г["незнакомый"]
        for x in люди_:
            положить(страница(язык, ЗНАЕШЬ, x), язык, ЗНАЕШЬ, "знаешь", {"X": x})
            положить(страница(язык, СВЯЗАН, x), язык, СВЯЗАН, "связан", {"X": x})
        положить(страница(язык, НЕ_ПОМНЮ, незнакомый), язык, НЕ_ПОМНЮ, "знаешь", {"X": незнакомый})
        положить(страница(язык, НЕ_ПОМНЮ, незнакомый, ("связан",)), язык, НЕ_ПОМНЮ, "связан", {"X": незнакомый})
        положить(страница(язык, ВСЁ), язык, ВСЁ, "всё", {})
        # ЗАПОМНИТЬ: новые люди, факты о знакомых, новые связи; отказ «нет» — на первом из каждого вида
        for x, t, o in г["новые"]:
            положить(страница_запомни(язык, ЗАПОМНИ_НОВОГО, "нового", x, (t, o)), язык, ЗАПОМНИ_НОВОГО, "нового",
                     {"X": x, "T": t, "O": o})
        for м, o in zip((0, 1, 3), г["добавить"]):
            x = П.имя(язык, м)
            положить(страница_запомни(язык, ЗАПОМНИ_ФАКТ, "факта", x, (o,)), язык, ЗАПОМНИ_ФАКТ, "факта",
                     {"X": x, "O": o})
        for a, b in П.НОВЫЕ_СВЯЗИ:
            x, y = П.имя(язык, a), П.имя(язык, b)
            положить(страница_запомни(язык, ЗАПОМНИ_СВЯЗЬ, "связи", x, (y, г["связь"])), язык, ЗАПОМНИ_СВЯЗЬ, "связи",
                     {"X": x, "Y": y})
        x, t, o = г["новые"][0]
        положить(страница_запомни(язык, ЗАПОМНИ_ОТКАЗ, "нового", x, (t, o)), язык, ЗАПОМНИ_ОТКАЗ, "нового",
                 {"X": x, "T": t, "O": o})
        o = г["добавить"][0]
        положить(страница_запомни(язык, ЗАПОМНИ_ОТКАЗ, "факта", П.имя(язык, 0), (o,)), язык, ЗАПОМНИ_ОТКАЗ, "факта",
                 {"X": П.имя(язык, 0), "O": o})
        положить(страница_запомни(язык, ФАКТ_НЕЗНАКОМОМУ, "факта", незнакомый, (o,)), язык, ФАКТ_НЕЗНАКОМОМУ, "факта",
                 {"X": незнакомый, "O": o})
        # ЗАБЫТЬ: всякого знакомого, первый факт у всякого с фактами, всякую связь; отказ «нет» — на первом из каждого
        for x in люди_:
            положить(страница_забудь(язык, ЗАБУДЬ, "человека", x), язык, ЗАБУДЬ, "человека", {"X": x})
        for x, _t, наблюдения in П.люди(язык):
            if наблюдения:
                положить(страница_забудь(язык, ЗАБУДЬ_ФАКТ, "факта", x, (наблюдения[0],)), язык, ЗАБУДЬ_ФАКТ, "факта",
                         {"X": x, "O": наблюдения[0]})
        for a, b in П.СВЯЗИ:
            x, y = П.имя(язык, a), П.имя(язык, b)
            положить(страница_забудь(язык, ЗАБУДЬ_СВЯЗЬ, "связи", x, (y, г["связь"])), язык, ЗАБУДЬ_СВЯЗЬ, "связи",
                     {"X": x, "Y": y})
        положить(страница_забудь(язык, ЗАБУДЬ_ОТКАЗ, "человека", люди_[1]), язык, ЗАБУДЬ_ОТКАЗ, "человека",
                 {"X": люди_[1]})
        x, _t, наблюдения = П.люди(язык)[2]
        положить(страница_забудь(язык, ЗАБУДЬ_ОТКАЗ, "факта", x, (наблюдения[0],)), язык, ЗАБУДЬ_ОТКАЗ, "факта",
                 {"X": x, "O": наблюдения[0]})
        положить(страница(язык, ЗАБЫТЬ_НЕЧЕГО, незнакомый), язык, ЗАБЫТЬ_НЕЧЕГО, "человека", {"X": незнакомый})
        # ПЛАН: люди с наблюдениями — строки файла; без наблюдений и незнакомый — писать нечего; отказ «нет»
        for x, _t, наблюдения in П.люди(язык):
            род = ПЛАН if наблюдения else ПЛАН_НЕЧЕГО
            положить(страница_плана(язык, род, x), язык, род, "план", {"X": x})
        положить(страница_плана(язык, ПЛАН_НЕЧЕГО, незнакомый), язык, ПЛАН_НЕЧЕГО, "план", {"X": незнакомый})
        положить(страница_плана(язык, ПЛАН_ОТКАЗ, люди_[0]), язык, ПЛАН_ОТКАЗ, "план", {"X": люди_[0]})
    return вон, перепись


