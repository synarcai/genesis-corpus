#!/usr/bin/env python3
"""GENESIS layer: МЕСТО ЧИСЛА В ИМЕНИ — see tools/numplaceforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Девять мест одного числа» и «место есть свойство слова» идут вместе: первое даёт СПИСОК мест,
второе отнимает вывод «значит, у каждого языка своё одно место».

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Число сказано пропажей», «форма одна на оба числа» и «ломаное множественное» — второй
группой: все три о том, что ПРИБАВКА ЗНАКА НЕ ЕСТЬ ЕДИНСТВЕННЫЙ СПОСОБ сказать о числе. Первое
— знак снят, второе — знака нет вовсе, третье — слово перестроено вместо удлинения.

«Число сказано наполовину» и «спрошено и отвечено» — третьей: цена незнания и прямой ответ.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import numplaceforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_numplace.txt"
ГРУППЫ = (("девять мест одного числа", "место есть свойство слова"),
          ("число сказано пропажей", "форма одна на оба числа", "ломаное множественное"),
          ("число сказано наполовину", "спрошено и отвечено"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
