#!/usr/bin/env python3
"""GENESIS layer: УКРАИНСКАЯ СЧЁТНАЯ ЯЧЕЙКА — see tools/ukcountforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Три формы, а не две» и «решает последняя цифра» идут вместе: первое говорит, что форм три,
второе — чем выбирается каждая. Порознь первое учило бы считать по величине числа.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Сосед делит иначе» и «третья форма не редка» — второй группой: одна о ложном переносе от
близкого языка, другая о ложном выводе из самого свода (третью ячейку он почти не показывал).

«Спрошено и отвечено» — третьей.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import ukcountforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_ukcount.txt"
ГРУППЫ = (("три формы, а не две", "решает последняя цифра"),
          ("сосед делит иначе", "третья форма не редка"),
          ("спрошено и отвечено",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
