#!/usr/bin/env python3
"""GENESIS layer: ВЕЩЕСТВО, СРАВНЁННОЕ КРАТНО — «twice as much money as», опора до сравнения (25.09).

ПОВОД — строка долга от ведущего (М-1274, мультипликативное сравнение как состав): рынок подписей сравнения
(`buy_cmp_markers`) не купил «as much as» ни в одной роли — слова «much» у рынка нет. В своде «as much … as»
есть, но не в форме, какую рынок читает: compare_mult говорит оба количества разом и сравнение следом («the tank
holds 20 cups of water and the bucket holds 5 cups of water; the tank holds four times as much water as the
bucket»), measure_story выводит опору из суммы пары. Рынок берёт значение B из последнего факта ДО четвёрки
«A has k times as much X as B», значение A — из первого ПОСЛЕ неё.

    НЕСЧЁТНОЕ СРАВНИВАЮТ СЛОВОМ «MUCH», СЧЁТНОЕ — «MANY»; КРАТНОСТЬ ОДНА, И ОПОРА СКАЗАНА ПРЕЖДЕ, ЧЕМ
    СПРОШЕНО СРАВНИВАЕМОЕ.

ТРИ ВЕЩЕСТВА ПО СЛОВУ ВЕДУЩЕГО — деньги, вода, время, — каждое со своей мерой и своим глаголом: «has 30 dollars
… twice as much money», «has 4 litres of water … 3 times as much water», «spent 20 minutes on homework … half as
much time on homework». ТРИ ФОРМЫ: вдвое («twice»), в k раз («k times», k от 3 до 5), вдвое меньше («half»);
ответ называет лицо и несёт звено («2 × 30 = 60», «30 ÷ 2 = 15»). ПО-РУССКИ «much» своего слова не имеет:
«у Веры вдвое больше денег, чем у Вани», «в 3 раза больше воды», «вдвое меньше времени» — формы единиц при числе берутся у двери единиц
(`units`), винительный длительности и прошедшее по роду — у `rugram`, родительный лица — у пакета ru.

СОСЕД — МИР `height` (рост лиц): там два лица сравнены РАЗНОСТЬЮ («8 cm taller than»), здесь несчётное —
КРАТНОСТЬЮ («twice as much money as»); опора и ответ со звеном у обоих одни.

ЛИЦА — ПАКЕТОВ, У ВСЯКОГО ЯЗЫКА СВОИ (как в мирах областей и роста). СУД — `courts/much_court.py`, вторая рука:
слово кратности и знак звена сверяются между собою, «half» при «×» — ложь, а не немота.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import rugram  # noqa: E402 — винительный длительности и прошедшее по роду
import units  # noqa: E402 — дверь единиц: форма доллара, литра, минуты и рубля при числе
from layer import Сбор, emit  # noqa: E402

# ПУТЬ, СКАЗАННЫЙ ТОЛЬКО В ЗОВЕ, ЕСТЬ ПУТЬ, О КОТОРОМ НЕ ОБЪЯВЛЕНО (14.09).
ЦЕЛЬ = "datasets/genesis_much.txt"

_ТУТ = pathlib.Path(__file__).resolve().parent
_ПАКЕТЫ = {я: json.loads((_ТУТ / "langpacks" / f"{я}.json").read_text(encoding="utf-8")) for я in ("en", "ru")}
ИМЕНА = {"en": ("Ben", "Carla", "Dan", "Elena", "Felix", "Grace"),
         "ru": ("Ваня", "Вера", "Дима", "Лена", "Маша", "Петя")}
for _я, _имена in ИМЕНА.items():
    assert set(_имена) <= set(_ПАКЕТЫ[_я]["person_names"]), ("имя не объявлено пакетом", _я)
_ЛИЦА_RU = _ПАКЕТЫ["ru"]["person_forms"]

ВДВОЕ = "вдвое: twice as much"
В_РАЗ = "в k раз: k times as much"
ВДВОЕ_МЕНЬШЕ = "вдвое меньше: half as much"
РОДЫ = (ВДВОЕ, В_РАЗ, ВДВОЕ_МЕНЬШЕ)

# ВЕЩЕСТВО: (имя английской единицы, имя русской единицы, размах количества опоры) — ИМЕНА, какими дом зовёт
# дверь единиц (`units`), а не формы: форму при числе даёт дверь (прибор `unit_doors`: форма рукой — вторая дверь)
ВЕЩЕСТВА = ("деньги", "вода", "время")
МЕРА = {"деньги": ("dollar", "rouble", (10, 90)), "вода": ("litre", "litre", (2, 20)),
        "время": ("minute", "minute", (10, 60))}


def _en_мера(вещество, n):
    # ПИСЬМО СВОДА, А НЕ ДВЕРИ ПО УМОЛЧАНИЮ (25.09, набор 408): дверь пишет американским письмом, и вода стала
    # «liters» — словом, которого в своде не было и которого не читает ни один суд числа (прибор `unknown_name`:
    # 1 «liter» и 119 «liters»). Литр свод пишет британским письмом («litres»: мир physics), и дом берёт то же письмо
    # у той же двери.
    return units.англ(МЕРА[вещество][0], n != 1, письмо="brit")


def _ru_мера(вещество, n):
    """Форма при числе у двери единиц; длительность — в винительном («потратила 21 минуту»): падежа дверь
    единиц не знает, и винительный берётся у `rugram` по ключу, который даёт та же дверь."""
    имя = МЕРА[вещество][1]
    if вещество == "время":
        return rugram.винительный_при_числе(units.рус(имя, 1), n)
    return units.рус(имя, n)


def _en_факт(вещество, кто, n):
    if вещество == "деньги":
        return f"{кто} has {n} {_en_мера(вещество, n)}"
    if вещество == "вода":
        return f"{кто} has {n} {_en_мера(вещество, n)} of water"
    return f"{кто} spent {n} {_en_мера(вещество, n)} on homework"


def _en_кратно(вещество, кто, слово, опора):
    if вещество == "время":
        return f"{кто} spent {слово} as much time on homework as {опора}"
    return f"{кто} has {слово} as much {'money' if вещество == 'деньги' else 'water'} as {опора}"


def _en_вопрос(вещество, кто):
    if вещество == "время":
        return f"how much time did {кто} spend on homework?"
    return f"how much {'money' if вещество == 'деньги' else 'water'} does {кто} have?"


def _ru_факт(вещество, кто, n):
    if вещество == "время":
        return (f"{кто} {rugram.прошедшее_рода('потратил', _ЛИЦА_RU[кто]['gender'] == 'f' and 'ж' or 'м')} на уроки "
                f"{n} {_ru_мера(вещество, n)}")
    хвост = " воды" if вещество == "вода" else ""
    return f"у {_ЛИЦА_RU[кто]['gen']} {n} {_ru_мера(вещество, n)}{хвост}"


def _ru_кратно(вещество, кто, слово, опора):
    чего = {"деньги": "денег", "вода": "воды", "время": "времени"}[вещество]
    if вещество == "время":
        глагол = rugram.прошедшее_рода("потратил", "ж" if _ЛИЦА_RU[кто]["gender"] == "f" else "м")
        return f"{кто} {глагол} на уроки {слово} {чего}, чем {опора}"
    return f"у {_ЛИЦА_RU[кто]['gen']} {слово} {чего}, чем у {_ЛИЦА_RU[опора]['gen']}"


def _ru_вопрос(вещество, кто):
    if вещество == "время":
        глагол = rugram.прошедшее_рода("потратил", "ж" if _ЛИЦА_RU[кто]["gender"] == "f" else "м")
        return f"сколько времени {кто} {глагол} на уроки?"
    return f"сколько {'денег' if вещество == 'деньги' else 'воды'} у {_ЛИЦА_RU[кто]['gen']}?"


def кратность(род, k):
    """(множитель, знак звена, слово en, слово ru): вдвое — ×2, в k раз — ×k, вдвое меньше — ÷2."""
    if род == ВДВОЕ:
        return 2, "×", "twice", "вдвое больше"
    if род == В_РАЗ:
        return k, "×", f"{k} times", f"в {k} {rugram.форма('раз', k)} больше"
    return 2, "÷", "half", "вдвое меньше"


def страница(язык, род, вещество, опора, кто, n, k=3):
    """«Ben has 30 dollars. Carla has twice as much money as Ben. how much money does Carla have? Carla has 60
    dollars: 2 × 30 = 60.» — опора (n) до сравнения, сравниваемое (m) после, звено."""
    множ, зн, слово_en, слово_ru = кратность(род, k)
    m = n * множ if зн == "×" else n // множ
    звено = f"{множ} × {n} = {m}" if зн == "×" else f"{n} ÷ {множ} = {m}"
    if язык == "en":
        return (f"{_en_факт(вещество, опора, n)}. {_en_кратно(вещество, кто, слово_en, опора)}. "
                f"{_en_вопрос(вещество, кто)} {_en_факт(вещество, кто, m)}: {звено}.")
    return (f"{_ru_факт(вещество, опора, n)}. {_ru_кратно(вещество, кто, слово_ru, опора)}. "
            f"{_ru_вопрос(вещество, кто)} {_ru_факт(вещество, кто, m)}: {звено}.")


def случаи(шаг):
    """(род, вещество, i опоры, i сравниваемого, n, k): по четыре на пару «род × вещество» за проход;
    у «вдвое меньше» опора чётна — половина целая."""
    вон = []
    for р, род in enumerate(РОДЫ):
        for в, вещество in enumerate(ВЕЩЕСТВА):
            lo, hi = МЕРА[вещество][2]
            for i in range(4):
                опора = (шаг + р * 2 + в + i) % 6
                кто = (опора + 1 + (шаг + i + р) % 5) % 6
                n = lo + (шаг * 7 + р * 5 + в * 3 + i * 11) % (hi - lo + 1)
                if род == ВДВОЕ_МЕНЬШЕ and n % 2:
                    n += 1
                k = 3 + (шаг + i + в) % 3
                вон.append((род, вещество, опора, кто, n, k))
    return вон


def pass_shows(pass_i):
    out = Сбор()
    for род, вещество, опора, кто, n, k in случаи(pass_i):
        out.род = род
        for язык in ("en", "ru"):
            out.язык = язык
            out.append(страница(язык, род, вещество, ИМЕНА[язык][опора], ИМЕНА[язык][кто], n, k))
    return out


# --------------------------------------------------------------- ОБЪЯВЛЕНИЕ ДОМА

ЗАЧЕМ_РОДА = {
    ВДВОЕ: "«Ben has 30 dollars. Carla has twice as much money as Ben. how much money does Carla have? Carla "
           "has 60 dollars: 2 × 30 = 60.» — опора до сравнения; по-русски «вдвое больше денег, чем у Вани»",
    В_РАЗ: "«Dan has 4 litres of water. Elena has 3 times as much water as Dan. … 3 × 4 = 12.» — «в 3 раза "
           "больше воды, чем у Димы»",
    ВДВОЕ_МЕНЬШЕ: "«Felix spent 40 minutes on homework. Grace spent half as much time on homework as Felix. … "
                  "40 ÷ 2 = 20.» — «вдвое меньше времени»",
}


def страницы(pass_i):
    return pass_shows(pass_i)


def перебор_с_языком(pass_i):
    """[(строка, род, ЯЗЫК)] — тот же обход, прочтённый тремя столбцами."""
    return pass_shows(pass_i).тройками


def перебор_страниц(pass_i):
    return pass_shows(pass_i).парами


def группы(pass_i):
    return [страницы(pass_i)]


def _показы():
    from layer import PASSES                             # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род, язык in перебор_с_языком(шаг):
            for строка in с.split("\n"):
                if строка.rstrip():
                    вон.setdefault(строка.rstrip(), (язык, род))
    return вон


ПОКАЗЫ = _показы()


def _самопроверка_дома():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    сбор = pass_shows(0)
    assert len(сбор) == len(сбор.роды), "показ остался без рода"
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"
    for род, _в, опора, кто, n, _k in (с for шаг in range(5) for с in случаи(шаг)):
        assert опора != кто and n >= 2 and (род != ВДВОЕ_МЕНЬШЕ or n % 2 == 0)


_самопроверка_дома()


def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
