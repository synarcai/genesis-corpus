#!/usr/bin/env python3
"""ДОМ СРАВНЕНИЯ ИМЕНОВАННЫХ ВЕЛИЧИН — БО́ЛЬШЕЕ ЧИСЛО НАЗЫВАЕТ МЕ́НЬШУЮ ВЕЛИЧИНУ.

    НИ ОДНОЙ СТРОКОЙ СВОД НЕ СПРАШИВАЕТ, ЧТО БОЛЬШЕ: 900 МЕТРОВ ИЛИ 1 КИЛОМЕТР. Замер 11.09
    по 256 мирам показов: вопрос сравнения с ДВУМЯ РАЗНЫМИ МЕРАМИ — НОЛЬ.

Свод умеет всё, что нужно для ответа, и не задаёт вопроса. Он переводит в мелкую меру (141 строка
дома денег: «33 рубля 40 копеек — это 3340 копеек»), называет основание на странице (573 строки:
«в часе 60 минут»), складывает и вычитает смешанную меру с переносом и заёмом (926 строк дома
`mixedunits`), ставит две меры одной пары в строку (4248 строк). И НИ РАЗУ НЕ СРАВНИВАЕТ.

    СВОД УМЕЕТ ПЕРЕВОДИТЬ И НЕ УМЕЕТ СПРАШИВАТЬ, ЗАЧЕМ ПЕРЕВОДЯТ.

ДВАДЦАТЬ ЧЕТВЁРТАЯ ЛОВУШКА РЯДА, И ОНА ПЕРВАЯ, ГДЕ ОБМАНЫВАЕТ САМО ЧИСЛО: 900 больше 1, а
900 метров МЕНЬШЕ одного километра. Всякая прежняя ловушка ряда обманывала действием, порядком
или вопросом; эта обманывает тем, что число видно, а мера — нет.

    ЧИСЛО БЕЗ МЕРЫ НЕ ЕСТЬ ВЕЛИЧИНА, И СРАВНИВАТЬ ЧИСЛА ВМЕСТО ВЕЛИЧИН — ЗНАЧИТ СРАВНИВАТЬ
    НЕ ТО, О ЧЁМ СПРОШЕНО.

ЧЕТЫРЕ РОДА:

    число обманывает  что больше: 900 метров или 1 километр? 1 километр, хотя 900 больше 1:
                      в километре 1000 метров, и 1 × 1000 = 1000, и 1000 больше 900.  ← ЛОВУШКА
    мера одна         что больше: 900 метров или 200 метров? 900 метров, ибо мера одна
                      и 900 больше 200.                                               ← УПРАВА
    основание         в метре 100 сантиметров, а в километре 1000 метров, и те же числа дают
                      разный перенос: 20 + 90 = 110, и 110 больше 100, но 110 меньше 1000.
    не сравнить       что больше: 900 граммов или 500 метров? ответа нет: масса и длина
                      не сравниваются.                                                ← ОТКАЗ

ВТОРОЙ РОД ЕСТЬ УПРАВА НАД ПЕРВЫМ: без него читатель выведет, что число ВСЕГДА обманывает, и
станет искать подвох там, где мера одна и числа решают прямо. Ловушка без своей управы плодит
новое суеверие ровно так же, как правило без исключения.

ТРЕТИЙ РОД ГОВОРИТ, ОТКУДА БЕРЁТСЯ ОБМАН: основание есть свойство ПАРЫ МЕР, а не числа и не рода
вещи. Одни и те же числа переходят через сотню и не переходят через тысячу — и это видно на одной
странице, двумя мерами разом.

    ОДНА МЕРА ПОКАЗЫВАЕТ ПЕРЕВОД; ДВЕ МЕРЫ С РАЗНЫМИ ОСНОВАНИЯМИ ПОКАЗЫВАЮТ, ЧТО ОСНОВАНИЕ
    ЕСТЬ СВОЙСТВО МЕРЫ.

ЧЕТВЁРТЫЙ РОД ЕСТЬ ОТКАЗ С ОСНОВАНИЕМ, и он не прихоть: вопрос «что больше» имеет ответ не
всегда. Масса и длина не сравниваются, и сказать это вслух — ответ, а не уклонение.

    ОТКАЗ БЕЗ ОСНОВАНИЯ ЕСТЬ МОЛЧАНИЕ; ОТКАЗ С ОСНОВАНИЕМ ЕСТЬ ОТВЕТ.

ЭТОТ ДОМ ЕСТЬ ПОЧИНКА ДВОЙНИКА, И ЭТО СКАЗАНО ЗДЕСЬ, А НЕ УМОЛЧАНО. Первая его редакция звалась
домом именованного числа (`carry`) и показывала перенос и заём на четырёх мерах — то самое, что
дом `mixedunits` показывает с 06.09. Я не увидел соседа, ибо замерил ПИСЬМО, а не ДЕЛО: искал
«3 м 40 см» и нашёл ноль, тогда как свод пишет то же словами — «3 метра 40 сантиметров».

    ЗАМЕР ПИСЬМА НЕ ЕСТЬ ЗАМЕР ДЕЛА. ДЫРА, НАЙДЕННАЯ ОДНИМ НАПИСАНИЕМ, ЕСТЬ ДЫРА В ЗАПРОСЕ,
    А НЕ В СВОДЕ.

Из прежнего дома уцелел один род — «основание», которого у соседа нет: `mixedunits` переносит
через оба основания, но НИ РАЗУ не называет основание на странице и ни разу не ставит два
основания рядом (замер: 0 строк с «в метре 100»).

РАВЕНСТВО СТАВИТСЯ ПОСЛЕДНИМ, ПОСЛЕ ДВОЕТОЧИЯ, И ЭТО КУПЛЕНО ПРОБОЙ. Первая редакция писала
«…: в метре 100 сантиметров, и 3 × 100 = 300, и 300 больше 140» — и суд арифметики не прочёл
НИ ОДНОЙ из 908 страниц: 514 легли в долю «запятая: равенство рядом с неравенством», ту самую,
что прибор долга назвал третьей по величине бедой свода. Переставив равенство в хвост, за
двоеточие, дом отдал страницы общему суду.

    РАВЕНСТВО, КОТОРОГО НЕ ЧИТАЕТ НИ ОДИН СОСЕД, ЕСТЬ УТВЕРЖДЕНИЕ ПОД ОХРАНОЙ ОДНОГО ДОМА.
    СУД АРИФМЕТИКИ ЧИТАЕТ ТО, ЧТО СТОИ́Т ПОСЛЕ ДВОЕТОЧИЯ, — и дом, знающий это, пишет так,
    чтобы его проверили дважды.

МЕРЫ И ИХ ОСНОВАНИЯ ОБЪЯВЛЕНЫ ТАБЛИЦЕЙ, А НЕ ВЫВЕДЕНЫ: сколько метров в километре — знание
о мире. Тем же законом живут счётные тройки `rugram` и границы вещей в `plaus`.

    python3 tools/unitcmpforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётные формы мер объявлены там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("число обманывает", "мера одна", "основание", "не сравнить")

# МЕРА: (большая, малая, основание, семья). ЗНАНИЕ О МИРЕ, ОБЪЯВЛЕННОЕ, А НЕ ВЫВЕДЕННОЕ.
МЕРЫ = (("метр", "сантиметр", 100, "длина"),
        ("рубль", "копейка", 100, "цена"),
        ("километр", "метр", 1000, "длина"),
        ("килограмм", "грамм", 1000, "масса"))
АНГЛ = {"метр": ("metre", "metres"), "сантиметр": ("centimetre", "centimetres"),
        "рубль": ("rouble", "roubles"), "копейка": ("kopeck", "kopecks"),
        "километр": ("kilometre", "kilometres"), "килограмм": ("kilogram", "kilograms"),
        "грамм": ("gram", "grams")}
# ПРЕДЛОЖНЫЙ ПАДЕЖ ОБЪЯВЛЕН ПОИМЁННО: таблица `rugram` даёт счётные формы, а не падежи
# единственного числа, и брать у неё то, чего она не обещала, значило бы лгать о языке.
ПРЕДЛОЖНЫЙ = {"метр": "в метре", "рубль": "в рубле", "километр": "в километре",
              "килограмм": "в килограмме"}
СЕМЬИ = {"длина": ("длина", "length"), "масса": ("масса", "mass"), "цена": ("цена", "price")}


def форма(язык, ключ, n):
    if язык == "en":
        один, много = АНГЛ[ключ]
        return один if n == 1 else много
    return rugram.форма(ключ, n)


def предл(язык, ключ):
    return f"in a {АНГЛ[ключ][0]}" if язык == "en" else ПРЕДЛОЖНЫЙ[ключ]


РАМКИ = {
    "ru": {
        "число обманывает": "что больше: {a} {м_a} или {b} {б_b}? {b} {б_b}, хотя {a} больше "
                            "{b}. {предл} {осн} {м_осн}, и {bo} больше {a}: "
                            "{b} × {осн} = {bo}.",
        "мера одна": "что больше: {a} {м_a} или {c} {м_c}? {a} {м_a}, ибо мера одна "
                     "и {a} больше {c}: {a} − {c} = {разн}.",
        "основание": "{предл} {осн} {м_осн}, а {предл2} {осн2} {м_осн2}, и те же числа дают "
                     "разный перенос — {xy} больше {осн}, но {xy} меньше {осн2}: "
                     "{x} + {y} = {xy}.",
        "не сравнить": "что больше: {a} {м_a} или {d} {м_d}? ответа нет: {семья_a} и {семья_d} "
                       "не сравниваются.",
    },
    "en": {
        "число обманывает": "which is greater: {a} {м_a} or {b} {б_b}? {b} {б_b}, though {a} is "
                            "greater than {b}. {предл} there are {осн} {м_осн}, and {bo} is "
                            "greater than {a}: {b} × {осн} = {bo}.",
        "мера одна": "which is greater: {a} {м_a} or {c} {м_c}? {a} {м_a}, for the measure is one "
                     "and {a} is greater than {c}: {a} − {c} = {разн}.",
        "основание": "{предл} there are {осн} {м_осн}, and {предл2} there are {осн2} {м_осн2}, "
                     "and the same numbers give a different carry — {xy} is greater than {осн}, "
                     "but {xy} is less than {осн2}: {x} + {y} = {xy}.",
        "не сравнить": "which is greater: {a} {м_a} or {d} {м_d}? there is no answer: {семья_a} "
                       "and {семья_d} are not compared.",
    },
}
ПУСТО = dict(a=0, b=0, c=0, d=0, bo=0, осн=0, осн2=0, x=0, y=0, xy=0, разн=0,
             м_a="", м_c="", м_d="", б_b="", м_осн="", м_осн2="",
             предл="", предл2="", семья_a="", семья_d="")


def страницы():
    вон = {}
    сотни = [м for м in МЕРЫ if м[2] == 100]
    тысячи = [м for м in МЕРЫ if м[2] == 1000]
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for большая, малая, осн, семья in МЕРЫ:
            for b in range(1, 6):
                bo = b * осн
                # ЧИСЛО ОБМАНЫВАЕТ ЛИШЬ ТОГДА, КОГДА ОНО БОЛЬШЕ, А ВЕЛИЧИНА МЕНЬШЕ.
                for a in range(осн // 10, bo, осн // 10):
                    if not (a > b and a < bo):
                        continue
                    if (a // (осн // 10) + b + len(большая)) % 3:
                        continue
                    общ = dict(ПУСТО, a=a, b=b, bo=bo, осн=осн,
                               м_a=форма(язык, малая, a), б_b=форма(язык, большая, b),
                               м_осн=форма(язык, малая, осн), предл=предл(язык, большая))
                    вон[рамки["число обманывает"].format(**общ)] = (язык, "число обманывает")
                    # УПРАВА КУЁТСЯ НА ТОМ ЖЕ ЧИСЛЕ И ТОЙ ЖЕ МЕРЕ, что и ловушка: иначе
                    # правило и его управа говорят о разном.
                    c = a - осн // 10
                    if c > 0:
                        вон[рамки["мера одна"].format(
                            **dict(общ, c=c, разн=a - c, м_c=форма(язык, малая, c)))] = (
                            язык, "мера одна")
        # ОСНОВАНИЕ ПОКАЗЫВАЕТСЯ ДВУМЯ МЕРАМИ РАЗОМ: одна мера сказала бы о мере, а не об
        # основании. Числа берутся те, что переходят сотню и не переходят тысячу.
        for бол1, мал1, осн1, _ in сотни:
            for бол2, мал2, осн2, _ in тысячи:
                for x in range(10, 100, 10):
                    for y in range(10, 100, 10):
                        if not (x < y and осн1 < x + y < осн2):
                            continue
                        вон[РАМКИ[язык]["основание"].format(
                            **dict(ПУСТО, x=x, y=y, xy=x + y, осн=осн1, осн2=осн2,
                                   м_осн=форма(язык, мал1, осн1),
                                   м_осн2=форма(язык, мал2, осн2),
                                   предл=предл(язык, бол1), предл2=предл(язык, бол2)))] = (
                            язык, "основание")
        # НЕ СРАВНИТЬ: меры РАЗНЫХ СЕМЕЙ. Отказ с основанием, и основание есть имя семьи.
        for б1, м1, о1, с1 in МЕРЫ:
            for б2, м2, о2, с2 in МЕРЫ:
                if с1 >= с2:
                    continue
                for a in range(100, 1000, 50):
                    if (a // 50 + len(м1) + len(м2)) % 2:
                        continue
                    вон[РАМКИ[язык]["не сравнить"].format(
                        **dict(ПУСТО, a=a, d=a + 100, м_a=форма(язык, м1, a),
                               м_d=форма(язык, м2, a + 100),
                               семья_a=СЕМЬИ[с1][0 if язык == "ru" else 1],
                               семья_d=СЕМЬИ[с2][0 if язык == "ru" else 1]))] = (
                        язык, "не сравнить")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА = re.compile(r"(?<![/\d])(?<!\+ )(\d+) \+ (\d+) = (\d+)(?![/\d])")
_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(?<!− )(\d+) − (\d+) = (\d+)(?![/\d])")
_БОЛЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:больше|is greater than) (\d+)(?![/\d])")
_МЕНЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:меньше|is less than) (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    # СРАВНЕНИЕ ЕСТЬ УТВЕРЖДЕНИЕ И СУДИТСЯ КАК УТВЕРЖДЕНИЕ, а не как оборот речи.
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    for a, b in _МЕНЬШЕ.findall(с):
        if int(a) >= int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    лов = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "число обманывает")
    отк = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "не сравнить")
    for страница, слово, куда in ((лов, "больше", "больш"), (отк, "ответа", "отвта")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(лов + " " + лов)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ЛОВУШКА ОБЯЗАНА ОБМАНЫВАТЬ: на всякой её странице большее ЧИСЛО стои́т при меньшей величине.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "число обманывает" or я != "ru":
            continue
        пары = _БОЛЬШЕ.findall(с)
        if len(пары) != 2:
            беды.append(f"ловушка без двух сравнений: {с[:80]}")
            break
    # ОТКАЗ НЕ СМЕЕТ НЕСТИ РАВЕНСТВА: отказ, на котором стои́т счёт, отрицает сам себя.
    for с, (я, р) in ПОКАЗЫ.items():
        if р == "не сравнить" and ("=" in с or _БОЛЬШЕ.search(с)):
            беды.append(f"на отказе стои́т счёт: {с[:80]}")
            break
    # УПРАВА СТОИ́Т ПРИ ТЕХ ЖЕ ЧИСЛАХ, что и ловушка, — иначе она управа над другим.
    числа_ловушки = {int(_БОЛЬШЕ.findall(с)[0][0]) for с, (я, р) in ПОКАЗЫ.items()
                     if я == "ru" and р == "число обманывает"}
    числа_управы = {int(_БОЛЬШЕ.findall(с)[0][0]) for с, (я, р) in ПОКАЗЫ.items()
                    if я == "ru" and р == "мера одна"}
    if not числа_управы or not числа_управы <= числа_ловушки:
        беды.append(f"управа на чужих числах: {sorted(числа_управы - числа_ловушки)[:6]}")
    print(f"СРАВНЕНИЕ ВЕЛИЧИН: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
