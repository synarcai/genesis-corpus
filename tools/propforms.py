#!/usr/bin/env python3
"""ДОМ ПРОПОРЦИИ — РАВЕНСТВО ОТНОШЕНИЙ, КОТОРОЕ НЕ ЕСТЬ РАВЕНСТВО РАЗНОСТЕЙ.

    ПРОПОРЦИИ В СВОДЕ НЕТ НИ ОДНОЙ ПОКАЗАННОЙ СТРОКОЙ. Замер 11.09 по 237 мирам показов: слово
    «пропорция» встречается 29 раз, и ВСЕ 29 — в мире определений, прозой и по-английски
    («momentum … being always proportioned to the …»). Записи «a : b = c : d» нет вовсе, и
    произведения крест-накрест не показаны ни разу.

ДВЕНАДЦАТАЯ ЛОВУШКА РЯДА — ТРЕТИЙ РОД: ОТНОШЕНИЕ СОХРАНЯЕТСЯ, РАЗНОСТЬ НЕТ. Кто прочёл «4 : 2 =
6 : 3» как «одно и то же расстояние между числами», получит 2 и 3 — и удивится. Отношение
отвечает на вопрос ВО СКОЛЬКО РАЗ, а разность — на вопрос НА СКОЛЬКО, и это разные вопросы об
одной паре.

    ДВА ВОПРОСА ОБ ОДНОЙ ПАРЕ ДАЮТ ДВА РАЗНЫХ ОТВЕТА, И ПУТАЮТ ИХ ЧАЩЕ ВСЕГО ТАМ, ГДЕ ОДИН
    ИЗ НИХ СОХРАНЯЕТСЯ.

ЧЕТЫРЕ РОДА:

    отношения     в пропорции 4 : 2 = 6 : 3 оба отношения равны 2: 4 = 2 × 2, и 6 = 3 × 2.
    крест-накрест в пропорции 4 : 2 = 6 : 3 произведения крест-накрест равны:
                  4 × 3 = 12, и 2 × 6 = 12.                                  ← ОРАКУЛ ДОМА
    разность      в пропорции 4 : 2 = 6 : 3 отношение сохранилось, а разность нет:
                  4 − 2 = 2, и 6 − 3 = 3.                                    ← ЛОВУШКА
    неизвестный   неизвестный член пропорции 4 : 2 = x : 3 находится крест-накрест:
                  4 × 3 = 12, и 12 ÷ 2 = 6.

ВТОРОЙ РОД ЕСТЬ ОРАКУЛ, СКАЗАННЫЙ ВСЛУХ: пропорция проверяется произведениями крест-накрест, и
проверка эта показана страницей, а не приписана снаружи. Четвёртый род тем же ходом НАХОДИТ
неизвестное — оракул и орудие суть одно правило, взятое в две стороны.

ПЕРВЫЙ И ТРЕТИЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО ВОПРОСУ: та же пропорция, те же четыре числа, и разница
в одном месте — спрашивают «во сколько раз» или «на сколько».

ФОРМА СТРАНИЦЫ ДЕРЖИТ ЗАКОН ЧУЖОГО ПРИБОРА: слова и сама запись «4 : 2 = 6 : 3» стоя́т ДО
последнего двоеточия, равенства — ПОСЛЕ, и потому суд арифметики читает каждую страницу этого
дома и считает её заново.

    python3 tools/propforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("отношения", "крест-накрест", "разность", "неизвестный")

РАМКИ = {
    "ru": {
        "отношения": "в пропорции {a} : {b} = {c} : {d} оба отношения равны {k}: {a} = {b} × {k}, и {c} = {d} × {k}.",
        "крест-накрест": "в пропорции {a} : {b} = {c} : {d} произведения крест-накрест равны: {a} × {d} = {p}, и {b} × {c} = {p}.",
        "разность": "в пропорции {a} : {b} = {c} : {d} отношение сохранилось, а разность нет: {a} − {b} = {r1}, и {c} − {d} = {r2}.",
        "неизвестный": "неизвестный член пропорции {a} : {b} = x : {d} находится крест-накрест: {a} × {d} = {p}, и {p} ÷ {b} = {c}.",
    },
    "en": {
        "отношения": "in the proportion {a} : {b} = {c} : {d} both ratios equal {k}: {a} = {b} × {k}, and {c} = {d} × {k}.",
        "крест-накрест": "in the proportion {a} : {b} = {c} : {d} the cross products are equal: {a} × {d} = {p}, and {b} × {c} = {p}.",
        "разность": "in the proportion {a} : {b} = {c} : {d} the ratio is kept and the difference is not: {a} − {b} = {r1}, and {c} − {d} = {r2}.",
        "неизвестный": "the unknown member of the proportion {a} : {b} = x : {d} is found crosswise: {a} × {d} = {p}, and {p} ÷ {b} = {c}.",
    },
}
ПУСТО = dict(a=0, b=0, c=0, d=0, k=0, p=0, r1=0, r2=0)


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for k in range(2, 10):
            for b in range(2, 10):
                for d in range(2, 10):
                    # РАЗНЫЕ ВТОРЫЕ ЧЛЕНЫ — ИНАЧЕ ЛОВУШКИ НЕТ: при равных b и d разности
                    # совпали бы, и третий род показывал бы ровно обратное тому, ради чего
                    # написан.
                    if b == d:
                        continue
                    a, c = b * k, d * k
                    общ = dict(ПУСТО, a=a, b=b, c=c, d=d, k=k, p=a * d,
                               r1=a - b, r2=c - d)
                    if (a + d) % 5 == 0:
                        вон[рамки["отношения"].format(**общ)] = (язык, "отношения")
                    if (b + c) % 5 == 0:
                        вон[рамки["крест-накрест"].format(**общ)] = (язык, "крест-накрест")
                    if (a + c) % 7 == 0:
                        вон[рамки["разность"].format(**общ)] = (язык, "разность")
                    if (b * d) % 7 == 0:
                        вон[рамки["неизвестный"].format(**общ)] = (язык, "неизвестный")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОПОРЦИЯ = re.compile(r"(\d+) : (\d+) = (\d+) : (\d+)")
_ПРОПОРЦИЯ_X = re.compile(r"(\d+) : (\d+) = x : (\d+)")
_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (\d+)(?![/\d])")
_РАВНЫ = re.compile(r"(?:равны|equal) (\d+):")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    # САМА ПРОПОРЦИЯ ПЕРЕСЧИТЫВАЕТСЯ КРЕСТ-НАКРЕСТ, А НЕ ПРИНИМАЕТСЯ ЗАПИСЬЮ.
    for a, b, c, d in _ПРОПОРЦИЯ.findall(с):
        if int(b) == 0 or int(d) == 0 or int(a) * int(d) != int(b) * int(c):
            return True, False
    for имя in _РАВНЫ.findall(с):
        пары = _ПРОПОРЦИЯ.findall(с)
        if пары and int(пары[0][0]) != int(пары[0][1]) * int(имя):
            return True, False
    # ЛОВУШКА ОБЯЗАНА ЛОВИТЬ: разности на странице третьего рода обязаны РАЗОЙТИСЬ.
    if "разность нет" in с or "the difference is not" in с:
        рр = _РАЗНОСТЬ.findall(с)
        if len(рр) < 2 or int(рр[0][2]) == int(рр[1][2]):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:86]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    кр = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "крест-накрест")
    рз = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "разность")
    for страница, слово, куда in ((кр, "равны", "равн"), (рз, "сохранилось", "сохранилос")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(кр + " " + кр)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # СЛОВА ДО ПОСЛЕДНЕГО ДВОЕТОЧИЯ, РАВЕНСТВА ПОСЛЕ — иначе суд арифметики страницу не прочтёт.
    for с in ПОКАЗЫ:
        хвост = с.rsplit(":", 1)[1]
        if re.search(r"[A-Za-zА-Яа-яЁё]{3,}", хвост.replace("and", "").replace("и", "")):
            беды.append(f"СЛОВА ПОСЛЕ ПОСЛЕДНЕГО ДВОЕТОЧИЯ: {с[:70]}")
            break
    print(f"ПРОПОРЦИЯ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
