def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    assert ПОКАЗЫ, "дом не кован"
    роды = {р for _я, р in ПОКАЗЫ.values()}
    assert not (set(РОДЫ) - роды), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    for с in ПОКАЗЫ:
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    # ЧУЖОЕ СЛОВО — ЧУЖАЯ СТРАНИЦА: суд молчит, а не зовёт ложью.
    чужая = "«a sturdy red table» or «a red sturdy table»? «a sturdy red table»: sturdy comes before red."
    assert судить(чужая) == (False, True), "суд взялся за слово вне объявленного ряда"
    # УДВОЕНИЕ СТРАНИЦЫ ЕСТЬ ДВЕ СТРАНИЦЫ, А НЕ ОДНА ЛОЖНАЯ (проверка та же, какой прибор
    # ловушки начала проверяет всякий дом; здесь она держится узостью дыр образца).
    о = next(iter(ПОКАЗЫ))
    assert судить(о + " " + о) == (False, True), "удвоение своей страницы зовётся ложью"
    # ЗАКОН ЧИТАЕТСЯ У ПАКЕТА, И ЭТО ПРОВЕРЯЕТСЯ: ряд дома обязан быть рядом пакета.
    свой = json.loads((КОРЕНЬ / "tools" / "langpacks" / "en.json")
                      .read_text(encoding="utf-8"))["adjective_order"]["ranks"]
    assert list(РАЗРЯДЫ) == свой, "ряд разрядов разошёлся с пакетом"


_самопроверка()


def main():
    import collections
    print(f"  показов {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, разрядов {len(РАЗРЯДЫ)}")
    print("  ", collections.Counter(р for _я, р in ПОКАЗЫ.values()).most_common())
    for род in РОДЫ:
        с = next(с for с, (_я, р) in ПОКАЗЫ.items() if р == род)
        print(f"  {род}: {с[:150]}")
    поймано = sum(1 for с in ПОДСАДКИ if судить(с) == (True, False))
    print(f"  подсадок поймано: {поймано} из {len(ПОДСАДКИ)}")
    return 0


