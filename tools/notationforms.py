"""ДОМ НАЧЕРТАНИЙ ОДНОГО ЗНАКА — четыре рода показа, и каждый проверяем исполнением.

ОДИН ЗНАК, ДВА НАЧЕРТАНИЯ — ОБА ЖИВУТ, ИЛИ ОРГАНИЗМ ЗНАЕТ ОДНО.

Четыре рода объявлены не здесь и не сегодня: их назвала СВОЯ ЖЕ КУЗНИЦА, прозой в заголовке,
14.09 — «ПАРА, ВОПРОС, ОТКАЗ, ВЕРДИКТ, и каждый проверяем исполнением». Дом не выдумывает
объявления и не решает за кузницу: он забирает УЖЕ СКАЗАННОЕ и кладёт рядом со страницами.

    РОД, НАЗВАННЫЙ В ЗАГОЛОВКЕ КУЗНИЦЫ И НЕ ОБЪЯВЛЕННЫЙ ДОМОМ, ЕСТЬ ИМЯ БЕЗ АДРЕСА: указатель
    его не видит, сайдкар не может назвать им ни одной строки, и пять тысяч триста восемьдесят
    шесть строк свода живут безымянными при живом имени.

    ДОМ, НЕ ЗНАЮЩИЙ СВОИХ СТРАНИЦ, НЕ МОЖЕТ НАЗВАТЬ ИХ РОДА.

ПЕРЕЕЗЖАЕТ НЕ ФУНКЦИЯ, А ЗАМЫКАНИЕ ЦЕЛИКОМ: вместе с построителем сюда переехали все ряды, из
которых он берёт числа (`КВАДРАТЫ`, `ТРЁХЧЛЕНЫ`, `ЕДИНИЧНЫЕ`, `СТАРШИЙ`, `ЧИСЛА`), и правило
буквы. Оставь их в кузнице — и первая же правка ряда разведёт два перебора одного пространства.

ЧТО ДЕЛАЕТ КАЖДЫЙ РОД:

    ПАРА     — две записи одной вещи, сведённые к канону: «x^2 - 4 = 0» и «x² − 4 = 0».
    ВОПРОС   — «как ещё пишется X?», и ответ ВЫВОДИТСЯ двойником, а не помнится.
    ВЕРДИКТ  — неравенство, посчитанное в обоих начертаниях: «3 <= 5 верно, и 3 ≤ 5 говорит
               то же». Истинность считается, а не пишется.
    ОТКАЗ    — запись, у которой двойника НЕТ, и это сказано прямо.

ДВА НАЧЕРТАНИЯ ОБЯЗАНЫ РАЗЛИЧАТЬСЯ: показ ««x^2» и «x^2» суть одна запись» истинен по букве и
пуст по делу. Оттого двойник, вернувший None, страницы не даёт вовсе.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
sys.path.insert(0, str(КОРЕНЬ / "courts"))

import notation_variants as НВ  # noqa: E402

РОДЫ = ("пара", "вопрос", "вердикт", "отказ")

ЗАЧЕМ_РОДА = {
    "пара": "две записи одной вещи, сведённые к канону",
    "вопрос": "«как ещё пишется X?» — ответ выводится двойником, а не помнится",
    "вердикт": "неравенство, посчитанное в обоих начертаниях: истинность считается",
    "отказ": "запись, у которой двойника нет, и это сказано прямо",
}

# РОДЫ, ЧЬЁ ЧИСЛО СТРАНИЦ ЕСТЬ ФАКТ О ПРЕДМЕТЕ, А НЕ ВЫБОР ДОМА (13.09).
#
#     РОД, ЧЬЁ ЧИСЛО СТРАНИЦ ЕСТЬ ФАКТ О ПРЕДМЕТЕ, НЕ ПОДЛЕЖИТ МЕРЕ РОВНОСТИ — НО ОБЯЗАН
#     БЫТЬ ОБЪЯВЛЕН ТАКОВЫМ, ИНАЧЕ ПОД ЭТИМ ИМЕНЕМ СПРЯЧЕТСЯ ВСЯКИЙ НЕДОПИСАННЫЙ.
#
# Объявление это ЧИТАЕТ `scripts/house_skew.py` и печатает поимённо: освобождение не молчит.
РОДЫ_ПО_ПРЕДМЕТУ = {
    "отказ": "записей без второго начертания ровно столько, сколько их есть среди 1..20; выдумать двадцать первую значило бы солгать",
}

# Диапазон свободных членов: полные квадраты, чтобы корень был целым и
# показ нёс проверяемое содержание, а не одну лишь запись.
КВАДРАТЫ = tuple(к * к for к in range(2, 21))
# ТРЁХЧЛЕНЫ: коэффициенты диапазонами, а не по полосе. Малые — все пары
# b, c от 0 до 12; большие — b десятками с полным квадратом c = (b/2)²,
# чтобы двузначный и трёхзначный коэффициент тоже имели оба начертания.
ТРЁХЧЛЕНЫ = tuple((зн, b, c) for b in range(0, 31) for c in range(0, 31)
                  for зн in ("-", "+") if b or зн == "-")
ТРЁХЧЛЕНЫ += tuple(("-", b, (b // 2) ** 2) for b in range(10, 101, 10))
# ЕДИНИЧНЫЙ КОЭФФИЦИЕНТ ОПУСКАЕТСЯ («x² − x + 7»), СТАРШИЙ — ПИШЕТСЯ
# ПЕРЕД СТЕПЕНЬЮ («2x² − 8x + 6»). Оба суть начертания той же записи.
ЕДИНИЧНЫЕ = tuple((зн, c) for c in range(1, 13) for зн in ("-", "+"))
# b от 2: единичный коэффициент не пишется, и «2x² − 1x» не запись.
СТАРШИЙ = tuple((a, зн, b, c) for a in range(2, 6) for b in range(2, 9)
                for c in range(0, 9) for зн in ("-", "+"))
# Пары чисел для неравенств: обе стороны и равные, и разные, чтобы
# вердикт не был всегда одним.
ЧИСЛА = tuple((а, б) for а in range(1, 13) for б in range(1, 13)
              if abs(а - б) <= 3)

ЗНАКИ_НЕРАВЕНСТВА = (("<=", "≤"), (">=", "≥"), ("!=", "≠"))


def буква(i):
    """Буква переменной ходит по показам: начертание есть свойство СТЕПЕНИ,
    а не буквы «икс» (03.09, тот же закон, каким живут универсалии)."""
    return НВ.БУКВЫ[i % len(НВ.БУКВЫ)][0]


def перебор():
    """[(страница, род)] — ВЕСЬ порядок мира, страница за страницей.

    Порядок здесь есть часть дела, а не украшение: кузница режет этот самый ряд по проходам
    остатком от деления, и всякая перестановка сдвинула бы мир целиком.
    """
    вон = []
    for i, c in enumerate(КВАДРАТЫ):
        б = буква(i)
        ascii_ = f"{б}^2 - {c} = 0"
        вон.append((f"«{ascii_}» и «{НВ.двойник(ascii_)}» суть одна запись.", "пара"))
        вон.append((f"«{ascii_}» and «{НВ.двойник(ascii_)}» are one record.", "пара"))
        вон.append((f"как ещё пишется «{ascii_}»? — «{НВ.двойник(ascii_)}».", "вопрос"))
        вон.append((f"how else is «{ascii_}» written? — "
                    f"«{НВ.двойник(ascii_)}».", "вопрос"))
    for i, (зн, b, c) in enumerate(ТРЁХЧЛЕНЫ):
        б = буква(i)
        b_часть = f" {зн} {b} {б}" if b else ""
        c_часть = f" + {c}" if c else ""
        ascii_ = f"{б}^2{b_часть}{c_часть} = 0"
        дв = НВ.двойник(ascii_)
        if дв is None:
            continue
        вон.append((f"«{ascii_}» и «{дв}» суть одна запись.", "пара"))
        вон.append((f"как ещё пишется «{ascii_}»? — «{дв}».", "вопрос"))
    for i, (зн, c) in enumerate(ЕДИНИЧНЫЕ):
        б = буква(i)
        ascii_ = f"{б}^2 {зн} {б} + {c} = 0"
        дв = НВ.двойник(ascii_)
        if дв:
            вон.append((f"«{ascii_}» и «{дв}» суть одна запись.", "пара"))
            вон.append((f"как ещё пишется «{ascii_}»? — «{дв}».", "вопрос"))
    for i, (a, зн, b, c) in enumerate(СТАРШИЙ):
        б = буква(i)
        c_часть = f" + {c}" if c else ""
        ascii_ = f"{a} {б}^2 {зн} {b} {б}{c_часть} = 0"
        дв = НВ.двойник(ascii_)
        if дв:
            вон.append((f"«{ascii_}» и «{дв}» суть одна запись.", "пара"))
            вон.append((f"как ещё пишется «{ascii_}»? — «{дв}».", "вопрос"))
    for знак_a, знак_t in ЗНАКИ_НЕРАВЕНСТВА:
        for а, б in ЧИСЛА:
            верно = {"<=": а <= б, ">=": а >= б, "!=": а != б}[знак_a]
            вон.append((f"«{а} {знак_a} {б}» {'верно' if верно else 'неверно'}"
                        f", и «{а} {знак_t} {б}» говорит то же.", "вердикт"))
            вон.append((f"как ещё пишется «{а} {знак_a} {б}»? — "
                        f"«{а} {знак_t} {б}».", "вопрос"))
    # ОТКАЗ: записи, ни один знак которых двойника не имеет.
    for n in range(1, 21):
        запись = f"{n} = {n}"
        if НВ.двойник(запись) is None:
            вон.append((f"у записи «{запись}» второго начертания нет: "
                        f"ни один её знак не имеет двойника.", "отказ"))
    return вон


def _показы():
    return {с: р for с, р in перебор()}


ПОКАЗЫ = _показы()


def _самопроверка():
    """Всякий объявленный род обязан дать хоть одну страницу, и всякая страница — знать род.

    РОД, ОБЪЯВЛЕННЫЙ И НЕ КОВАННЫЙ, ЕСТЬ ОБЕЩАНИЕ, А НЕ РОД.
    """
    ряд = перебор()
    данные = {р for _с, р in ряд}
    лишние = данные - set(РОДЫ)
    assert not лишние, f"страница назвала род вне объявления: {sorted(лишние)}"
    пустые = set(РОДЫ) - данные
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"


_самопроверка()
