#!/usr/bin/env python3
"""РОДОВАЯ ФОРМА ГЛАГОЛА: «сделал + а = сделала», и «а» есть род, а не украшение.

    ЯЗЫК, ГДЕ ПОДЛЕЖАЩЕЕ ОПУСКАЕТСЯ, НЕ ИМЕЕТ СЛОВА НОСИТЕЛЯ — ОН ИМЕЕТ ЕГО ОКОНЧАНИЕ.

Заказ пришёл от holon (волна X, место носителя): на страницах ДВУХ носителей — «Maria miała 14,
Piotr miał 22. oddała 9» — правило «последнего названного» лжёт, и найти носителя можно лишь по
СОГЛАСОВАНИЮ ГЛАГОЛА. Свод писал обе формы («сделал» и «сделала») сотнями страниц и НИ РАЗУ не
говорил, что «а» есть женский род.

ДОМ БЕРЁТ ТО, ЧТО УЖЕ ОБЪЯВЛЕНО, И НЕ ПРИДУМЫВАЕТ ЯЗЫКА. Основы взяты из рамок домов историй
(дыра рода `{а}`), лица и их род — из объявленных лиц. Дыра эта живёт ТОЛЬКО у двух языков:

    pl 84 вхождения (16 основ) · ru 60 (14 основ) · у прочих семи — НОЛЬ

    СЕМЬ ЯЗЫКОВ ИЗ ДЕВЯТИ РОДОВОЙ ДЫРЫ В ГЛАГОЛЕ НЕ ИМЕЮТ ВОВСЕ. Их прошедшее рода не
    различает, и носитель в опущенном подлежащем восстанавливается там ЛИЦОМ И ЧИСЛОМ, а не
    родом. Дом закрывает беду для двух языков и молчит о семи — и это сказано, а не скрыто.

ЧЕТЫРЕ ПОКАЗА, И ПОСЛЕДНИЙ ЕСТЬ ГЛАВНЫЙ: он связывает окончание с РОДОМ ИМЕНИ, и связь эта
счётна — суд сверяет объявленный род лица с окончанием формы.
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from layer import PASSES, emit  # noqa: E402
import svampforms as S  # noqa: E402

ЦЕЛЬ = "datasets/genesis_genderverb.txt"
ОСНОВА = re.compile(r"([^\W\d_]+)\{а\}")
# СЛОВА РОДА ОБЪЯВЛЕНЫ, А НЕ ВЫВЕДЕНЫ: польское «rodzaj żeński» и русское «женского рода»
# суть разные обороты, и склейка из общих частей дала бы не речь.
СЛОВА = {
    "ru": dict(жен="женского рода", муж="мужского рода", ж="женского", м="мужского",
               какого="какого рода", лицо_жен="{X} женского рода",
               лицо_муж="{X} мужского рода", потому="и потому", какого_лица="какого рода {X}?",
               окончание="а"),
    "pl": dict(жен="rodzaj żeński", муж="rodzaj męski", ж="żeńskiego", м="męskiego",
               какого="jakiego rodzaju jest", лицо_жен="{X} jest rodzaju żeńskiego",
               лицо_муж="{X} jest rodzaju męskiego", потому="dlatego",
               какого_лица="jakiego rodzaju jest {X}?", окончание="a"),
}


def основы(язык):
    """Основы прошедшего с дырой рода — из рамок домов историй, а не из нового списка."""
    вон = []
    видано = set()
    for таблица in (S.РАМКИ.get(язык, {}), S.РАМКИ_АКТОВ.get(язык, {})):
        for _ф, рамка in taбл(таблица):
            for м in ОСНОВА.finditer(рамка):
                о = м.group(1)
                if о not in видано:
                    видано.add(о)
                    вон.append(о)
    return вон


def taбл(таблица):
    for ф, рамка in таблица.items():
        for р in (рамка if isinstance(рамка, tuple) else (рамка,)):
            yield ф, р


ЛИЦА = {я: [(и, род) for и, род, *_ in S.A.ЛИЦА[я]] for я in СЛОВА}
РЯД = [(я, о) for я in СЛОВА for о in основы(я)]


def страницы(язык, о):
    с = СЛОВА[язык]
    ж = о + с["окончание"]
    вон = [
        f"{о} + {с['окончание']} = {ж}.",
        f"what is {о} + {с['окончание']}? {о} + {с['окончание']} = {ж}.",
        f"{ж} — {с['жен']}, {о} — {с['муж']}.",
        f"{с['какого']} {ж}? {с['ж']}.",
        f"{с['какого']} {о}? {с['м']}.",
    ]
    for имя, род in ЛИЦА[язык]:
        поле = с["лицо_жен"] if род == "f" else с["лицо_муж"]
        форма = ж if род == "f" else о
        вон.append(f"{поле.format(X=имя)}, {с['потому']} {имя} {форма}.")
        вон.append(f"{с['какого_лица'].format(X=имя)} "
                   f"{с['ж'] if род == 'f' else с['м']}, {с['потому']} {имя} {форма}.")
    return вон


def pass_shows(pass_i):
    out = []
    for k, (язык, о) in enumerate(РЯД):
        if k % len(PASSES) != pass_i:
            continue
        out.extend(страницы(язык, о))
    return out


def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
