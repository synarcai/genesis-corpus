# ЯЗЫКИ, ЧЕЙ ЗАКОН ЗДЕСЬ НАЗВАН. Читатели: `scripts/refusal_reason.py`, `refusal_house.py`.
ЯЗЫК_ЗАКОНА = ("ru", "pl")

# ОТКАЗЫ ПАКЕТОВ, ЧЕЙ ЗАКОН ЭТОТ ДОМ ОБЪЯСНЯЕТ: (отвергнутое, имя, неверная форма, верная).
# Сверяются с объявлением пакета и с пластом при сборке.
ОТКАЗЫ_ПАКЕТОВ = {
    "ru": (("маша получил зонт", "маша", "получил", "получила"),),
}
ОСНОВА = re.compile(r"([^\W\d_]+)\{а\}")
# СЛОВА РОДА ОБЪЯВЛЕНЫ, А НЕ ВЫВЕДЕНЫ: польское «rodzaj żeński» и русское «женского рода»
# суть разные обороты, и склейка из общих частей дала бы не речь.
СЛОВА = {
    "ru": dict(жен="женского рода", муж="мужского рода", ж="женского", м="мужского",
               какого="какого рода", нет="нет", верно_ли="верно ли, что", лицо_жен="{X} женского рода",
               лицо_муж="{X} мужского рода", потому="и потому", какого_лица="какого рода {X}?",
               окончание="а"),
    "pl": dict(жен="rodzaj żeński", муж="rodzaj męski", ж="żeńskiego", м="męskiego",
               какого="jakiego rodzaju jest", нет="nie", верно_ли="czy to prawda, że", лицо_жен="{X} jest rodzaju żeńskiego",
               лицо_муж="{X} jest rodzaju męskiego", потому="dlatego",
               какого_лица="jakiego rodzaju jest {X}?", окончание="a"),
}


def основы(язык):
    """Основы прошедшего с дырой рода — из рамок домов историй, а не из нового списка."""
    вон = []
    видано = set()
    for таблица in (S.РАМКИ.get(язык, {}), S.РАМКИ_АКТОВ.get(язык, {})):
        for _ф, рамка in taбл(таблица):
            for м in ОСНОВА.finditer(рамка):
                о = м.group(1)
                if о not in видано:
                    видано.add(о)
                    вон.append(о)
    return вон


def taбл(таблица):
    for ф, рамка in таблица.items():
        for р in (рамка if isinstance(рамка, tuple) else (рамка,)):
            yield ф, р


ЛИЦА = {я: [(и, род) for и, род, *_ in S.A.ЛИЦА[я]] for я in СЛОВА}
РЯД = [(я, о) for я in СЛОВА for о in основы(я)]

# ДОМ, УЧАЩИЙ ПРАВИЛУ, ОБЯЗАН ПОКАЗАТЬ И ЕГО ИСКЛЮЧЕНИЕ (08.09).
#
# Дом учил «основа + а = женское» и собирал основы у соседа. Среди них стояло «нашёл», и дом
# писал «нашёл + а = нашёла, нашёла — женского рода» — слово, которого в русском нет.
# Восемнадцать страниц ДОМА О ПРАВИЛЕ учили правилу на том самом глаголе, на котором оно
# ломается.
#
#     ПРАВИЛО, ПОКАЗАННОЕ БЕЗ ИСКЛЮЧЕНИЯ, ЕСТЬ ЛОЖНОЕ ВСЕОБЩЕЕ. И хуже того: правило,
#     показанное НА своём исключении, есть ложь дважды.
#
# Ныне исключения объявлены домом языка (`rugram.ПРОШЕДШЕЕ_ЖЕНСКОЕ`), и дом показывает их
# ОТКАЗОМ С ОСНОВАНИЕМ — «нашёл + а = нашёла? нет: нашла», — а не молчанием о них.
НЕПРАВИЛЬНЫЕ = {"ru": [м for м in sorted(rugram.ПРОШЕДШЕЕ_ЖЕНСКОЕ)], "pl": []}


def страницы_исключения(язык, о):
    """Страницы глагола, чьё женское НЕ есть мужское плюс буква."""
    с = СЛОВА[язык]
    ок = с["окончание"]
    ж = rugram.прошедшее(о, "f") if язык == "ru" else о + ок
    склейка = о + ок
    if ж == склейка:
        return []
    вон = [
        f"{с['верно_ли']} {о} + {ок} = {склейка}? {с['нет']}: {ж}.",
        f"{ж} — {с['жен']}, {о} — {с['муж']}.",
        f"{с['какого']} {ж}? {с['ж']}.",
        f"{с['какого']} {о}? {с['м']}.",
    ]
    for имя, род in ЛИЦА[язык]:
        поле = с["лицо_жен"] if род == "f" else с["лицо_муж"]
        форма = ж if род == "f" else о
        вон.append(f"{поле.format(X=имя)}, {с['потому']} {имя} {форма}.")
    return вон


def страницы(язык, о):
    с = СЛОВА[язык]
    ж = о + с["окончание"]
    вон = [
        f"{о} + {с['окончание']} = {ж}.",
        f"what is {о} + {с['окончание']}? {о} + {с['окончание']} = {ж}.",
        f"{ж} — {с['жен']}, {о} — {с['муж']}.",
        f"{с['какого']} {ж}? {с['ж']}.",
        f"{с['какого']} {о}? {с['м']}.",
    ]
    for имя, род in ЛИЦА[язык]:
        поле = с["лицо_жен"] if род == "f" else с["лицо_муж"]
        форма = ж if род == "f" else о
        вон.append(f"{поле.format(X=имя)}, {с['потому']} {имя} {форма}.")
        вон.append(f"{с['какого_лица'].format(X=имя)} "
                   f"{с['ж'] if род == 'f' else с['м']}, {с['потому']} {имя} {форма}.")
    return вон


РЯД_ИСКЛЮЧЕНИЙ = [(я, о) for я in СЛОВА for о in НЕПРАВИЛЬНЫЕ[я]]


def страницы_отказа(язык):
    """Страницы, цитирующие ТОТ САМЫЙ отказ пакета — со звёздочкой, как велит закон знака."""
    с = СЛОВА[язык]
    вон = []
    for отказ, имя, неверн, верн in ОТКАЗЫ_ПАКЕТОВ.get(язык, ()):
        вон.append(f"свод отвергает «*{отказ}», и вот закон: {имя} — {с['жен']}, "
                   f"и потому «{имя} {верн}», а «{неверн}» — {с['муж']}.")
        вон.append(f"почему свод отвергает «*{отказ}»? Потому что «{неверн}» есть форма "
                   f"{с['м']} рода, а {имя} — {с['ж']}: «{имя} {верн}».")
    return вон


# ТРИ СТРОИТЕЛЯ — ТРИ РОДА, И ИМЯ КАЖДОГО СТОЯЛО В ИМЕНИ ФУНКЦИИ (14.09).
ПРАВИЛО = "род подлежащего правит прошедшим: правило на правильной основе"
ИСКЛЮЧЕНИЕ = "та же основа, где правило даёт не ту форму, и дом показывает верную"


def pass_shows(pass_i):
    # ЯЗЫК БЕРЁТСЯ У СТРОИТЕЛЯ, И ЗДЕСЬ ЭТО НЕ ПРИХОТЬ, А ЕДИНСТВЕННЫЙ ПУТЬ (15.09). Дом
    # говорит по-русски и ПО-ПОЛЬСКИ, а польский пишется латиницей: мера по начертанию
    # назвала бы «dostał + a = dostała» английской строкой — и назвала, покуда язык не был
    # взят у того, кто его выбрал.
    #
    #     ДВА ЯЗЫКА ОДНОЙ АЗБУКИ НЕРАЗЛИЧИМЫ ПИСЬМОМ, И МЕРА, ЧИТАЮЩАЯ ПИСЬМО, НАЗОВЁТ ОДИН
    #     ИЗ НИХ ДРУГИМ — молча и уверенно.
    out = Сбор()
    out.род = ПРАВИЛО
    for k, (язык, о) in enumerate(РЯД):
        if k % len(PASSES) != pass_i:
            continue
        out.язык = язык
        out.extend(страницы(язык, о))
    out.род = ИСКЛЮЧЕНИЕ
    for k, (язык, о) in enumerate(РЯД_ИСКЛЮЧЕНИЙ):
        if k % len(PASSES) != pass_i:
            continue
        out.язык = язык
        out.extend(страницы_исключения(язык, о))
    # СТРАНИЦЫ ОТКАЗА ИДУТ КАЖДЫМ ПРОХОДОМ: их две на язык, и делить их между проходами
    # значило бы дать читателю урок в одном месте и молчание в четырёх.
    # ОТКАЗ ПРИНАДЛЕЖИТ ИСКЛЮЧЕНИЮ, КОТОРОЕ ОН СТЕРЕЖЁТ (14.09): «свод отвергает *нашёла»
    # есть страница о ТОЙ ЖЕ основе, о какой говорит исключение, и двух этих строк на весь
    # свод родом не сделать — они много ниже закона массы.
    out.род = ИСКЛЮЧЕНИЕ
    for язык in СЛОВА:
        out.язык = язык
        out.extend(страницы_отказа(язык))
    return out


# --------------------------------------------------------------- ОБЪЯВЛЕНИЕ ДОМА

# ЯЗЫКОВОЙ ДОЛГ ДОМА НАЗВАН (15.09): род ИСКЛЮЧЕНИЯ кован только по-русски (236 страниц), и
# причина стои́т строкою выше — `НЕПРАВИЛЬНЫЕ["pl"]` пуст. Польские основы с чередованием у
# прошедшего («szedł → szła», «mógł → mogła», «niósł → niosła») существуют и учат ровно
# тому же, чему учат русские; недостаёт ОБЪЯВЛЕНИЯ их словарём и польского женского,
# выводимого правилом, — у русского оно берётся у `rugram.прошедшее`, у польского его нет.
#
#     ПУСТОЙ СПИСОК ЕСТЬ ЧЕСТНОЕ МОЛЧАНИЕ, ПОКА ОН НАЗВАН. Названный, он есть работа.
РОДЫ = (ПРАВИЛО, ИСКЛЮЧЕНИЕ)

ЗАЧЕМ_РОДА = {
    ПРАВИЛО: "«X нашёл» при мужском, «X нашла» при женском — правило, работающее на "
             "правильной основе, и вопрос о лице при нём",
    ИСКЛЮЧЕНИЕ: "основы, где прибавление «а» даёт не ту форму: дом показывает верную, а "
                "не молчит об исключении, и отказ «свод отвергает *нашёла» стои́т здесь же",
}


def страницы_прохода(pass_i):
    return pass_shows(pass_i)


def перебор_страниц(pass_i):
    return pass_shows(pass_i).тройками


def группы(pass_i):
    return [страницы_прохода(pass_i)]


def _показы():
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род, язык in перебор_страниц(шаг):
            for строка in с.split("\n"):
                if строка.rstrip():
                    вон.setdefault(строка.rstrip(), (язык, род))
    return вон


ПОКАЗЫ = _показы()

# ЯЗЫК ПОКАЗА НАЗВАН ПЕРВЫМ, РОД — ВТОРЫМ: так читает прибор щербатости.
РОД_В_ПОКАЗЕ = 1


def _самопроверка_дома():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    сбор = pass_shows(0)
    assert len(сбор) == len(сбор.роды), "показ остался без рода"
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка_дома()


def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
