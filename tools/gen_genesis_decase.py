#!/usr/bin/env python3
"""GENESIS layer: НЕМЕЦКИЙ ПРЕДЛОГ ДВУХ ПАДЕЖЕЙ — see tools/decaseforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Один предлог, два падежа» и «падеж выбирает глагол» идут вместе: первое говорит, что выбор
есть, второе — кто его делает. Порознь первое учило бы, что падеж при этих предлогах
произволен.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Вопрос отличает» и «не всякий предлог таков» — второй группой: одна даёт ПРИЗНАК выбора
(wo? / wohin?), другая его ГРАНИЦУ (у mit и für выбора нет вовсе).

«Сосед различает иначе» — третьей и особо: это довод НАРУЖУ, к русскому и английскому, и
соседство с немецкими правилами его бы разбавило.

    ОДНО РАЗЛИЧЕНИЕ, ТРИ СПОСОБА: падежом при одном предлоге, падежом же (русский), двумя
    разными предлогами (английский).
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import decaseforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_decase.txt"
ГРУППЫ = (("один предлог, два падежа", "падеж выбирает глагол"),
          ("вопрос отличает", "не всякий предлог таков"),
          ("сосед различает иначе",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
