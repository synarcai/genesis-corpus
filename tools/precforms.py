    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:74]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    ст = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "старшинство")
    ск = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "скобки")
    ош = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "ошибка")
    if судить(ст.replace("ибо", "иб"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(ск.replace("скобки", "скобк"))[1] is not False:
        беды.append("обрезанное слово в скобках прошло")
    if судить(ош.replace("нет:", "не:"))[1] is not False:
        беды.append("обрезанное слово в ошибке прошло")
    if судить(ст + " " + ст)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ПОРЯДОК ДЕЙСТВИЙ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


