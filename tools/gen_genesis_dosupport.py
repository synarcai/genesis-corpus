#!/usr/bin/env python3
"""GENESIS layer: АНГЛИЙСКОЕ «do» — see tools/dosupportforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Вспомогательный из ниоткуда» стои́т ОДИН: это само правило, и всякий сосед разбавил бы его.

«Лицо уходит на does» и «время уходит на did» — второй группой: обе о ПЕРЕНОСЕ признака с
глагола на вспомогательный, и порознь каждая читалась бы как случай, а вместе — как закон.

    ОДНО ОКОНЧАНИЕ НА ДВОИХ НЕ ДЕЛИТСЯ.

«При be и модальных do не нужен» и «вопрос о подлежащем do не берёт» — третьей: обе о
ГРАНИЦАХ правила, и обе отнимают вывод, который читатель сделал бы из первой группы сам.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ГРАНИЦ, ЛОЖНО РОВНО ЗА ИХ ПРЕДЕЛАМИ — и ученик переходит их
    тем увереннее, чем лучше выучил правило.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import dosupportforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_dosupport.txt"
ГРУППЫ = (("вспомогательный из ниоткуда",),
          ("лицо уходит на does", "время уходит на did"),
          ("при be и модальных do не нужен", "вопрос о подлежащем do не берёт"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
