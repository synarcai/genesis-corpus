#!/usr/bin/env python3
"""ДОМ ДЕРЕВА ДОКУМЕНТОВ: ссылка есть РЕБРО, и вердикт о ней — разрешимость.

Разметка судится СТРОКОЙ: три решётки суть заголовок третьего уровня, и
чтобы это проверить, довольно самой строки. СТРУКТУРА так не судится.
«[форма](../ядро/форма.md#вид)» верна или ложна не сама по себе, а
ОТНОСИТЕЛЬНО ДЕРЕВА: есть ли такой документ, если считать от того, где
ссылка стоит; есть ли в нём такой якорь. Это вердикт о РЕБРЕ ГРАФА, и
корпус, знающий разметку ссылки и не знающий её разрешения, выучил
скобки и не выучил ссылаться.

ЧЕТЫРЕ ВЕЩИ, КОТОРЫХ НЕТ В СИНТАКСИСЕ И БЕЗ КОТОРЫХ НЕТ СТРУКТУРЫ:
    ПУТЬ ОТНОСИТЕЛЬНЫЙ — «./сосед.md» и «../выше/иной.md» значат разное
        в зависимости от того, ГДЕ стоят; один и тот же текст ссылки из
        двух разных документов ведёт в два разных места;
    ЯКОРЬ — «#вид» указывает не на документ, а на его ЧАСТЬ, и часть
        эта должна в документе быть;
    ИМЯ ЗАГОЛОВКА В ЯКОРЬ — правило приведения («Вид Формы» → «вид-формы»)
        объявлено, и потому проверяемо;
    ПОРЯДОК — sidebar_position задаёт последовательность, и «следующий
        документ» есть вычислимый факт, а не оборот речи.

ДЕРЕВО ОБЪЯВЛЕНО ЗДЕСЬ ОДНАЖДЫ, и по нему считают все: свод, который
показы порождает, и суд, который их проверяет, — но считают РАЗНЫМИ
ходами. Свод идёт от пары документов к тексту ссылки; суд идёт от текста
ссылки к паре документов. Согласие двух встречных ходов и есть проверка.
"""

import posixpath
import re

# ДЕРЕВО МАЛО НАРОЧНО: оно должно быть ОБОЗРИМО целиком, иначе показы о
# нём будут о частностях. Каждый узел — (путь, заголовок, место, разделы).
ДЕРЕВО = (
    ("intro.md", "beginning", 1, ("what is here", "how to read")),
    ("core/form.md", "form", 1, ("kinds of form", "form and matter")),
    ("core/matter.md", "matter", 2, ("kinds of matter", "matter and force")),
    ("core/force.md", "force", 3, ("force and motion",)),
    ("world/water.md", "water", 1, ("water and stone", "water and light")),
    ("world/stone.md", "stone", 2, ("stone and road",)),
    ("world/light.md", "light", 3, ("light and sound",)),
    ("method/measure.md", "measure", 1, ("measure and number",)),
    ("method/law.md", "law", 2, ("law and schema",)),
)
ПУТИ = tuple(п for п, _з, _м, _р in ДЕРЕВО)
УЗЕЛ = {п: (з, м, р) for п, з, м, р in ДЕРЕВО}


def якорь(заголовок):
    """Имя раздела, приведённое в якорь, — правилом, а не таблицей.

    Docusaurus строит якорь из текста заголовка: нижний регистр, пробелы
    в дефисы, прочее выброшено. Правило объявлено здесь, и потому
    «what is here» → «what-is-here» есть ПРОВЕРЯЕМОЕ утверждение, а не
    соглашение, о котором корпус умалчивает.
    """
    с = заголовок.lower().strip()
    с = re.sub(r"[^\w\s-]", "", с)
    return re.sub(r"\s+", "-", с)


def имя_файла(путь):
    """id документа по умолчанию: имя файла без расширения."""
    return posixpath.basename(путь).rsplit(".", 1)[0]


def папка(путь):
    return posixpath.dirname(путь)


def относительно(откуда, куда):
    """Текст ссылки из документа «откуда» на документ «куда».

    Прямой ход: от пары документов к записи. Обратный ход — `разрешить`.
    """
    от, до = папка(откуда), папка(куда)
    if от == до:
        return "./" + posixpath.basename(куда)
    свои, чужие = (от.split("/") if от else []), (до.split("/") if до else [])
    общих = 0
    while (общих < len(свои) and общих < len(чужие)
           and свои[общих] == чужие[общих]):
        общих += 1
    вверх = [".."] * (len(свои) - общих)
    вниз = чужие[общих:] + [posixpath.basename(куда)]
    return "/".join(вверх + вниз) if вверх else "./" + "/".join(вниз)


def разрешить(откуда, ссылка):
    """(путь, якорь) — куда ведёт ссылка, или None, если никуда.

    Обратный ход: от записи к паре документов. Ссылка на несуществующий
    документ или на отсутствующий раздел РАЗРЕШЕНИЯ НЕ ИМЕЕТ, и это
    ложь, вычислимая точно так же, как ложное равенство.
    """
    путь, _, метка = ссылка.partition("#")
    if путь:
        цель = posixpath.normpath(posixpath.join(папка(откуда), путь))
    else:
        цель = откуда
    if цель not in УЗЕЛ:
        return None
    if метка:
        разделы = УЗЕЛ[цель][2]
        if метка not in {якорь(р) for р in разделы}:
            return None
    return цель, метка


def следующий(путь):
    """Документ, идущий следом в том же разделе по sidebar_position."""
    своя = папка(путь)
    рядом = sorted(((м, п) for п, _з, м, _р in ДЕРЕВО if папка(п) == своя))
    места = [п for _м, п in рядом]
    i = места.index(путь)
    return места[i + 1] if i + 1 < len(места) else None


def оракул():
    """[(откуда, куда)] — пары, где прямой и обратный ход разошлись.

    ВСТРОЕННЫЙ ОРАКУЛ ДЕРЕВА: для КАЖДОЙ пары документов текст ссылки
    строится прямым ходом и разрешается обратным; если разрешение не
    вернуло исходную цель, дерево или ходы неверны, и показы о них не
    имеют права родиться.
    """
    беды = []
    for откуда in ПУТИ:
        for куда in ПУТИ:
            текст = относительно(откуда, куда)
            вышло = разрешить(откуда, текст)
            if вышло is None or вышло[0] != куда:
                беды.append((откуда, куда, текст, вышло))
            for раздел in УЗЕЛ[куда][2]:
                сяк = f"{текст}#{якорь(раздел)}"
                вышло = разрешить(откуда, сяк)
                if вышло is None or вышло[0] != куда:
                    беды.append((откуда, куда, сяк, вышло))
    return беды
