#!/usr/bin/env python3
"""[ЖИВАЯ ЗАДАЧА — ЗАКОН] — задача, написанная живым языком, и её программа, взятая из её же решения.

    ЖИВОЙ ТЕКСТ НЕ ПОВТОРЯЕТСЯ НИ ПРЕДЛОЖЕНИЕМ, НИ КЛАУЗОЙ; ПОВТОРЯЕТСЯ ПРОГРАММА. Задача
    учит, лишь когда её числа меняются, а ход решения — нет.

ПОВОД — ПЕРЕПИСЬ 23.09 (прибор `canon/judges/tools/clause_census.py`). Публичный ключ организма —
задачи GSM8K и SVAMP — стоит на 89–96 верных из 1 422; последний отказ читателя в 997 немых из
1 309 — «uncertified-arithmetic»: задача узнана, выкладка не собрана. Рамка предложения публичного
GSM8K показана сводом в 2,8 % случаев, а со ВСЕЙ обучающей частью GSM8K — в 5,6 %; клауза — в
19,8 % и 35,5 %. Рамочная покупка живого текста не покрывает ни синтетикой, ни чужим сводом.

Этот закон даёт своду то, чего в нём не было: живую задачу рядом с её программой. Сырьё — обучающая
часть GSM8K (`datasets/sources/gsm8k/train.jsonl`, MIT, взята по слову владельца 23.09: «можно всё —
лишь бы не костыли, хардкод или подгонка»). Две задачи, похожие на задачи ключей (≥ 50 % восьмисловных
шинглов), вычеркнуты прибором (`leak_near_duplicate_ids.json`); точных совпадений с ключами ноль.

ПРОГРАММА БЕРЁТСЯ ИЗ РЕШЕНИЯ, А НЕ ПИШЕТСЯ РУКОЙ. Решение GSM8K несёт выкладки «<<48/2=24>>»;
каждое число выкладки есть либо ЧИСЛО УСЛОВИЯ (вход), либо ИТОГ прежнего шага, либо ПОСТОЯННАЯ мира
(60 минут, 100 процентов), которой в условии нет. Равные числа условия суть ОДИН вход: вариант, где
они меняются вместе, есть частный случай той же задачи. Задача, где число выкладки равно и числу
условия, и итогу прежнего шага, двусмысленна и в дом не идёт; как и та, чья выкладка не
воспроизводит свой же итог.

ВАРИАНТ ГОДЕН, ЕСЛИ ХРАНИТ СТРОЙ ЗАДАЧИ — и строй этот есть свойство самой задачи, а не правило
смысла, писанное рукой:
  · порядок всех величин (входов, постоянных, итогов) тот же — что было меньше, то и осталось;
  · целое осталось целым, дробное — конечной дробью не длиннее прежней; знак тот же;
  · счётная форма слова при каждом входе та же — по закону счёта пакета (`count_agreement`):
    «3 pairs» не станет «1 pairs»;
  · числа условия, которых выкладка не берёт (порядковые, отвлекающие), не тронуты.

СУД — ТОТ ЖЕ ЗАКОН, ЧИТАЮЩИЙ СТРОКУ НАЗАД. Строка истинна, если её условие есть условие задачи
источника (скелет с числами «#» тот же), числа условия составляют годный вариант, и выкладка с
ответом суть ТОЧНО то, что даёт программа задачи на этих числах. Порча слова ломает скелет, порча
числа — выкладку или годность, порча выкладки — пересчёт.
"""
import json
import pathlib
import re
import sys
from fractions import Fraction

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ИСТОЧНИК = КОРЕНЬ / "datasets" / "sources" / "gsm8k" / "train.jsonl"
ВЫЧЕРКНУТЫ = КОРЕНЬ / "datasets" / "sources" / "gsm8k" / "leak_near_duplicate_ids.json"

# Число условия, писанное цифрами: разряды через запятую («1,200») и дробная часть («16.50»).
# Число, прилипшее к слову («1st», «3rd»), числом условия не считается и не меняется.
ЧИСЛО = re.compile(r"(?<![\w.,])(\d{1,3}(?:,\d{3})+|\d+)(?:\.(\d+))?(?![\w])")
ВЫКЛАДКА = re.compile(r"<<([^=<>]+)=([^<>]+)>>")
ЛЕКСЕМА = re.compile(r"\d+(?:\.\d+)?|[()+\-*/]")
ЗНАК = {"*": "×", "/": "÷", "-": "−", "+": "+"}
# Хвост строки дома: «… условие ОТВЕТ: выкладка.» — в выкладке двоеточий нет.
ХВОСТ = re.compile(r"^(?P<вопрос>.+) (?P<ответ>-?\d+(?:\.\d+)?): (?P<выкладка>[^:]+)\.$")


def знаков_после_точки(x):
    """Сколько цифр после точки нужно конечной дроби; None — дробь бесконечна."""
    x = Fraction(x)
    d, n = x.denominator, 0
    while d % 10 == 0:
        d //= 10
        n += 1
    while d % 2 == 0:
        d //= 2
        n += 1
    while d % 5 == 0:
        d //= 5
        n += 1
    if d != 1:
        return None
    # n — верхняя граница; сжимаем до наименьшей
    k = 0
    while (x * 10 ** k).denominator != 1:
        k += 1
    return k


def число_выкладки(x):
    """Число выкладки: целое без точки, дробь — наименьшим конечным видом."""
    x = Fraction(x)
    if x.denominator == 1:
        return str(x.numerator)
    k = знаков_после_точки(x)
    целое = abs(x.numerator) * 10 ** k // x.denominator
    текст = f"{целое // 10 ** k}.{целое % 10 ** k:0{k}d}"
    return ("-" if x < 0 else "") + текст


def число_условия(x, образец):
    """Число условия в виде ОБРАЗЦА: те же разряды через запятую, столько же знаков после точки."""
    _, _, _, знаков, разряды = образец
    x = Fraction(x)
    целое = x.numerator * 10 ** знаков // x.denominator
    голова, хвост = divmod(целое, 10 ** знаков) if знаков else (целое, None)
    голова = f"{голова:,}" if разряды else str(голова)
    return голова if хвост is None else f"{голова}.{хвост:0{знаков}d}"


def числа(текст):
    """[(значение, начало, конец, знаков после точки, разряды через запятую)] — числа условия."""
    вон = []
    for м in ЧИСЛО.finditer(текст):
        целая = м.group(1).replace(",", "")
        дробь = м.group(2) or ""
        значение = Fraction(целая + ("." + дробь if дробь else ""))
        вон.append((значение, м.start(), м.end(), len(дробь), "," in м.group(1)))
    return вон


def скелет(текст):
    return ЧИСЛО.sub("#", текст)


def _счётная_форма():
    """Форма слова при числе — по закону счёта английского пакета, а не по правилу рукой."""
    import langpack
    пакет = json.loads((КОРЕНЬ / "tools" / "langpacks" / "en.json").read_text(encoding="utf-8"))
    имена = []
    for правило in пакет.get("count_agreement") or ():
        if правило.get("form") and правило["form"] not in имена:
            имена.append(правило["form"])
    класс = {"forms": имена}
    return lambda k: имена[langpack.count_form_index(пакет, класс, k)] if имена else ""


_ФОРМА = None


def форма_счёта(k):
    global _ФОРМА
    if _ФОРМА is None:
        _ФОРМА = _счётная_форма()
    return _ФОРМА(k)


class Программа:
    """Задача источника: условие, его числа, входы, шаги выкладки, итоги и ответ."""

    __slots__ = ("номер", "вопрос", "числа", "входы", "шаги", "итоги", "финал", "постоянные")

    def вычислить(self, значения):
        """Итоги шагов при данных значениях входов; None — деление на ноль."""
        итоги = []
        for лексемы, ссылки in self.шаги:
            if (итог := _вычислить(лексемы, ссылки, значения, итоги)) is None:
                return None
            итоги.append(итог)
        return итоги

    def величины(self, значения, итоги):
        return [значения[в] for в in self.входы] + list(self.постоянные) + list(итоги)


_СБОРКА = {}


def _код(лексемы):
    """Выражение шага, собранное ОДИН раз: числа — места a0, a1, …, знаки — свои."""
    ключ = tuple(лексемы)
    if ключ not in _СБОРКА:
        части, к = [], 0
        for л in лексемы:
            if л[0].isdigit():
                части.append(f"a{к}")
                к += 1
            else:
                части.append(л)
        _СБОРКА[ключ] = compile("".join(части), "<шаг>", "eval")
    return _СБОРКА[ключ]


def _вычислить(лексемы, ссылки, значения, итоги):
    места = {}
    for к, (вид, x) in enumerate(ссылки):
        места[f"a{к}"] = значения[x] if вид == "вход" else (итоги[x] if вид == "шаг" else x)
    try:
        return eval(_код(лексемы), {"__builtins__": {}}, места)
    except ZeroDivisionError:
        return None


def разобрать(номер, задача):
    """(Программа, "годна") или (None, причина)."""
    вопрос = " ".join(задача["question"].split())
    решение = задача["answer"]
    try:
        ответ = Fraction(решение.rsplit("####", 1)[-1].strip().replace(",", ""))
    except ValueError:
        return None, "ответ не число"
    чс = числа(вопрос)
    значения_условия = {з for з, *_ in чс}
    шаги, итоги, постоянные = [], [], []
    for м in ВЫКЛАДКА.finditer(решение):
        выражение = м.group(1).replace(" ", "")
        лексемы = ЛЕКСЕМА.findall(выражение)
        if "".join(лексемы) != выражение:
            return None, "выкладка не из чисел и знаков"
        for i, л in enumerate(лексемы):
            if л == "-" and (i == 0 or лексемы[i - 1] in "(+-*/"):
                return None, "унарный минус"
        try:
            итог = Fraction(м.group(2).strip().replace(",", "").rstrip("."))
        except ValueError:
            return None, "итог не число"
        ссылки = []
        for л in лексемы:
            if not л[0].isdigit():
                continue
            v = Fraction(л)
            прежние = [i for i, r in enumerate(итоги) if r == v]
            if v in значения_условия and прежние:
                return None, "число и условия, и прежнего шага"
            if прежние:
                ссылки.append(("шаг", прежние[-1]))
            elif v in значения_условия:
                ссылки.append(("вход", v))
            else:
                ссылки.append(("пост", v))
                if v not in постоянные:
                    постоянные.append(v)
        if _вычислить(лексемы, ссылки, {v: v for v in значения_условия}, итоги) != итог:
            return None, "выкладка не воспроизводит свой итог"
        шаги.append((лексемы, ссылки))
        итоги.append(итог)
    if not шаги:
        return None, "выкладок нет"
    if ответ not in итоги:
        return None, "ответ не есть итог шага"
    финал = max(i for i, r in enumerate(итоги) if r == ответ)
    п = Программа()
    п.номер, п.вопрос, п.числа = номер, вопрос, чс
    п.шаги, п.итоги, п.финал = шаги[:финал + 1], итоги[:финал + 1], финал
    п.входы = sorted({x for _, сс in п.шаги for вид, x in сс if вид == "вход"})
    п.постоянные = tuple(sorted({x for _, сс in п.шаги for вид, x in сс if вид == "пост"}))
    if not п.входы:
        return None, "входов нет"
    return п, "годна"


def _порядок(величины):
    return tuple((a > b) - (a < b) for i, a in enumerate(величины) for b in величины[i + 1:])


def годен(п, значения, итоги):
    """Хранит ли вариант строй задачи — см. докстринг."""
    исходные = {в: в for в in п.входы}
    for было, стало in zip(п.итоги, итоги):
        if (было > 0) != (стало > 0) or (было < 0) != (стало < 0):
            return False
        if (было.denominator == 1) != (стало.denominator == 1):
            return False
        if стало.denominator != 1:
            k = знаков_после_точки(стало)
            if k is None or k > знаков_после_точки(было):
                return False
    for в in п.входы:
        if значения[в] <= 0 or форма_счёта(значения[в]) != форма_счёта(в):
            return False
    return _порядок(п.величины(значения, итоги)) == _порядок(п.величины(исходные, п.итоги))


def отрисовать(п, значения, итоги):
    """Строка дома: условие с числами варианта, ответ, выкладка."""
    куски, конец = [], 0
    for образец in п.числа:
        v, начало, конец_числа = образец[0], образец[1], образец[2]
        куски.append(п.вопрос[конец:начало])
        куски.append(число_условия(значения.get(v, v), образец))
        конец = конец_числа
    куски.append(п.вопрос[конец:])
    вопрос = "".join(куски)
    шаги = []
    for (лексемы, ссылки), итог in zip(п.шаги, итоги):
        части, к = [], 0
        for л in лексемы:
            if л[0].isdigit():
                вид, x = ссылки[к]
                к += 1
                части.append(число_выкладки(значения[x] if вид == "вход" else (итоги[x] if вид == "шаг" else x)))
            else:
                части.append(ЗНАК.get(л, л))
        выражение = " ".join(части).replace("( ", "(").replace(" )", ")")
        шаги.append(f"{выражение} = {число_выкладки(итог)}")
    return f"{вопрос} {число_выкладки(итоги[-1])}: {', '.join(шаги)}."


_ПРОГРАММЫ = None
_ПО_СКЕЛЕТУ = None


def программы():
    """Все годные к разбору задачи источника, кроме вычеркнутых; с причинами отказа."""
    global _ПРОГРАММЫ, _ПО_СКЕЛЕТУ
    if _ПРОГРАММЫ is None:
        try:
            вычеркнуты = set(json.loads(ВЫЧЕРКНУТЫ.read_text(encoding="utf-8")))
        except (OSError, ValueError):
            вычеркнуты = set()
        годные, причины = [], {}
        try:
            строки = ИСТОЧНИК.read_text(encoding="utf-8").splitlines()
        except OSError:
            строки = []
        for номер, строка in enumerate(строки):
            if номер in вычеркнуты:
                причины["вычеркнута прибором утечки"] = причины.get("вычеркнута прибором утечки", 0) + 1
                continue
            п, почему = разобрать(номер, json.loads(строка))
            причины[почему] = причины.get(почему, 0) + 1
            if п is not None:
                годные.append(п)
        _ПРОГРАММЫ = (годные, причины)
        _ПО_СКЕЛЕТУ = {}
        for п in годные:
            _ПО_СКЕЛЕТУ.setdefault(скелет(п.вопрос), []).append(п)
    return _ПРОГРАММЫ


def судить(строка):
    """(судимо, истинно): строка дома есть годный вариант задачи источника с её выкладкой."""
    с = " ".join(строка.split())
    м = ХВОСТ.match(с)
    if not м:
        return False, False
    программы()
    кандидаты = _ПО_СКЕЛЕТУ.get(скелет(м.group("вопрос")), [])
    if not кандидаты:
        return True, False
    чс = числа(м.group("вопрос"))
    for п in кандидаты:
        if len(чс) != len(п.числа):
            continue
        значения, годно = {}, True
        for (новое, *_), (старое, *_) in zip(чс, п.числа):
            if старое in п.входы:
                if значения.setdefault(старое, новое) != новое:
                    годно = False
                    break
            elif новое != старое:
                годно = False
                break
        if not годно:
            continue
        итоги = п.вычислить(значения)
        if итоги is None or not годен(п, значения, итоги):
            continue
        if отрисовать(п, значения, итоги) == с:
            return True, True
    return True, False
