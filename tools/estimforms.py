#!/usr/bin/env python3
"""ДОМ ПРИКИДКИ — округлить ДО счёта и тем поймать грубую ошибку.

    ЗНАК «≈» СВОД НАЗЫВАЕТ И НЕ ПРИМЕНЯЕТ. Замер 10.09 по мирам показов: «≈» встречается 34
    раза, и все они суть ИМЯ знака («≈ называется приближённо», «≈ heisst ungefähr»). Мир
    обихода умеет округлить ОДНО число («Маша насчитала 21 карту; это примерно 20 карт»), дом
    округления знает правило половины. Но ВЫЧИСЛЕНИЯ НАД ОКРУГЛЁННЫМИ ЧИСЛАМИ нет ни одного.

    ПРИКИДКА ЕСТЬ НЕ ЛЕНЬ, А ПРОВЕРКА. Тот, кто прикинул «около четырёхсот», не примет ответа
    «три тысячи девятьсот девяносто»: он поймает ошибку в ДЕСЯТЬ РАЗ прежде, чем начнёт
    считать. Организм, не умеющий прикидывать, верит всякому своему ответу.

ЧЕТЫРЕ РОДА, И ГЛАВНЫЙ ИЗ НИХ ЧЕТВЁРТЫЙ:

    произведение  сколько примерно будет 19 × 21? 19 × 21 — это около 400, ибо 19 ≈ 20,
                  и 21 ≈ 20, и 20 × 20 = 400.
    сумма         сколько примерно будет 48 + 31? 48 + 31 — это около 80, ибо 48 ≈ 50,
                  и 31 ≈ 30, и 50 + 30 = 80.
    точно         прикидка дала 400, а точно 19 × 21 = 399, и прикидка больше на 1.
                                                              ← ЦЕНА ПРИКИДКИ НАЗВАНА
    ловит         верно ли, что 19 × 21 = 3990? нет: 19 ≈ 20, и 21 ≈ 20, и 20 × 20 = 400,
                  а 3990 вдесятеро больше.                     ← РАДИ ЭТОГО ВСЁ

ТРЕТИЙ РОД НЕ ХВАЛИТ ПРИКИДКУ, А НАЗЫВАЕТ ЕЁ ЦЕНУ. Показ, где прикидка и точное совпали бы,
учил бы, что округление даром; показ, где расхождение НАЗВАНО ЧИСЛОМ, учит, чего оно стоит.
Без третьего рода четвёртый был бы фокусом: читатель вправе спросить, отчего «около 400»
отвергает 3990 и не отвергает 399.

    ПРИКИДКА ОТВЕРГАЕТ ПО ПОРЯДКУ ВЕЛИЧИНЫ, А НЕ ПО ТОЧНОМУ ЧИСЛУ, И ГРАНИЦА ЭТА ПОКАЗАНА,
    А НЕ ОБЪЯВЛЕНА: 399 от 400 отличается на единицу, 3990 — вдесятеро.

ЧИСЛА ОТОБРАНЫ ТАК, ЧТОБЫ ОКРУГЛЕНИЕ БЫЛО ЧЕСТНЫМ: берутся те, что стоя́т не далее двух единиц
от круглого десятка, и правило половины здесь не спорит с домом округления — оно сюда и не
входит. Грубая ошибка четвёртого рода есть ровно десятикратная: она получается приписью нуля —
самая частая описка на свете, и оттого самая нужная к поимке.

ЗАЧИН ВОПРОСА — ОБЪЯВЛЕННОЕ ВОПРОСНОЕ СЛОВО, И ЭТО КУПЛЕНО СУДОМ ПИСЬМА. Первая редакция
спрашивала «roughly what is 19 × 21?» — и суд назвал строку ложью по записи: вопрос обязан
открываться словом, объявленным пакетом языка, а «roughly» им не объявлено. Ныне «what is
roughly …» и «сколько примерно будет …».

    python3 tools/estimforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("произведение", "сумма", "точно", "ловит")

РАМКИ = {
    "ru": {
        "произведение": "сколько примерно будет {a} × {b}? {a} × {b} — это около {при}, ибо {a} ≈ {ка}, и {b} ≈ {кб}, и {ка} × {кб} = {при}.",
        "сумма": "сколько примерно будет {c} + {d}? {c} + {d} — это около {прс}, ибо {c} ≈ {кс}, и {d} ≈ {кд}, и {кс} + {кд} = {прс}.",
        "точно": "прикидка дала {при}, а точно {a} × {b} = {точ}, и прикидка {знак} на {разн}.",
        "ловит": "верно ли, что {a} × {b} = {груб}? нет: {a} ≈ {ка}, и {b} ≈ {кб}, и {ка} × {кб} = {при}, а в {груб} знаков {згруб}, тогда как в {при} их {зпри}.",
    },
    "en": {
        "произведение": "what is roughly {a} × {b}? {a} × {b} is about {при}, because {a} ≈ {ка}, and {b} ≈ {кб}, and {ка} × {кб} = {при}.",
        "сумма": "what is roughly {c} + {d}? {c} + {d} is about {прс}, because {c} ≈ {кс}, and {d} ≈ {кд}, and {кс} + {кд} = {прс}.",
        "точно": "the estimate gave {при}, and exactly {a} × {b} = {точ}, and the estimate is {знак} by {разн}.",
        "ловит": "is it true that {a} × {b} = {груб}? no: {a} ≈ {ка}, and {b} ≈ {кб}, and {ка} × {кб} = {при}, and {груб} has {згруб} digits while {при} has {зпри}.",
    },
}
ЗНАКИ = {"ru": ("больше", "меньше"), "en": ("greater", "less")}


def _круглое(n):
    """Ближайший десяток. Дом о прикидке, а не о правиле половины: числа берутся такие,
    где до круглого не далее двух, и спорить с домом округления здесь не о чем."""
    return round(n / 10) * 10


def _пары():
    """(a, b): прикидка обязана разойтись с точным НЕ БОЛЕЕ ЧЕМ НА ДЕСЯТУЮ.

    ПЕРВЫЙ ОТБОР БРАЛ ВСЯКОЕ ЧИСЛО ВБЛИЗИ ДЕСЯТКА, и вышло «18 × 19: прикидка 400, точно 342»
    — расхождение в семнадцать сотых. Такая страница учит не прикидке, а небрежности: округляя
    ОБА множителя в одну сторону, ошибку удваивают, и дом обязан это знать сам, а не надеяться
    на глазомер. Ныне пара входит, лишь если |прикидка − точное| ≤ точное ÷ 10.
    """
    вон = []
    for a in (18, 19, 21, 22, 28, 29, 31, 32, 38, 39, 41, 42, 48, 49, 51, 52):
        for b in (19, 21, 29, 31, 41, 49):
            если = abs(a - _круглое(a)) <= 2 and abs(b - _круглое(b)) <= 2 and a * b <= 2600
            if не_далеко(a, b) and если:
                вон.append((a, b))
    return вон[:30]


def не_далеко(a, b):
    """Разошлась ли прикидка с точным не более чем на десятую долю точного."""
    точ = a * b
    return abs(_круглое(a) * _круглое(b) - точ) * 10 <= точ


def _суммы():
    """(c, d): та же мера близости к десятку, и сумма не длиннее трёх знаков."""
    вон = []
    for c in (48, 31, 19, 22, 39, 51, 68, 72, 88, 91):
        for d in (31, 19, 29, 41, 52):
            if abs(c - _круглое(c)) <= 2 and abs(d - _круглое(d)) <= 2:
                вон.append((c, d))
    return вон[:24]


def страницы():
    вон = {}
    пары, суммы = _пары(), _суммы()
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        больше, меньше = ЗНАКИ[язык]
        for a, b in пары:
            ка, кб = _круглое(a), _круглое(b)
            при, точ = ка * кб, a * b
            поля = dict(a=a, b=b, ка=ка, кб=кб, при=при, точ=точ,
                        груб=точ * 10, разн=abs(при - точ),
                        # РАЗРЯД, А НЕ КРАТНОСТЬ: «вдесятеро больше» сравнивало грубую ошибку
                        # с ТОЧНЫМ (342 × 10 = 3420), а стои́т она в строке рядом с ПРИКИДКОЙ
                        # (400), и читатель вправе счесть, что 3420 = 400 × 10. Число знаков
                        # проверяется глазом и судом, и оно же есть суть прикидки.
                        згруб=len(str(точ * 10)), зпри=len(str(ка * кб)),
                        знак=больше if при > точ else меньше,
                        c=0, d=0, кс=0, кд=0, прс=0)
            вон[рамки["произведение"].format(**поля)] = (язык, "произведение")
            вон[рамки["ловит"].format(**поля)] = (язык, "ловит")
            # ПРИКИДКА, СОШЕДШАЯСЯ С ТОЧНЫМ, НЕ НАЗЫВАЕТ СВОЕЙ ЦЕНЫ, и род «точно» её
            # пропускает: страница «прикидка дала 400, а точно 400, и прикидка больше на 0»
            # учила бы, что округление даром.
            if при != точ:
                вон[рамки["точно"].format(**поля)] = (язык, "точно")
        for c, d in суммы:
            кс, кд = _круглое(c), _круглое(d)
            поля = dict(a=0, b=0, ка=0, кб=0, при=0, точ=0, груб=0, разн=0, знак=больше,
                        c=c, d=d, кс=кс, кд=кд, прс=кс + кд)
            вон[рамки["сумма"].format(**поля)] = (язык, "сумма")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(\d+) × (\d+) = (\d+)")
_СУММА = re.compile(r"(\d+) \+ (\d+) = (\d+)")
_ОКОЛО = re.compile(r"(\d+) ≈ (\d+)")
# ЧИСЛО И ЧИСЛО ЕГО ЗНАКОВ — по одному образцу на язык, и оба с ДВУМЯ группами: образец с
# ветвлением дал бы четыре группы, из них две пустые, и разбор оступился бы на первой строке.
_ЗНАКОВ = re.compile(r"в (\d+) знаков (\d+)")
_ЗНАКОВ_ИХ = re.compile(r"в (\d+) их (\d+)")
_DIGITS = re.compile(r"(\d+) has (\d+) digits")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ, И СЧИТАЕТСЯ ТОЛЬКО ОТВЕЧАЮЩАЯ ЧАСТЬ: равенство,
    # СПРОШЕННОЕ вопросом («верно ли, что 19 × 21 = 3990?»), не утверждено.
    ответ = с.split("?", 1)[1] if "?" in с else с
    for a, b, c in _ПРОИЗВ.findall(ответ):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _СУММА.findall(ответ):
        if int(a) + int(b) != int(c):
            return True, False
    # ОКРУГЛЕНИЕ ПРОВЕРЯЕТСЯ СВОИМ ПРАВИЛОМ, А НЕ ПРИНИМАЕТСЯ НА ВЕРУ: «19 ≈ 30» есть ложь
    # этого дома, хотя оба числа целы и никакого равенства в строке нет.
    for a, b in _ОКОЛО.findall(ответ):
        if _круглое(int(a)) != int(b):
            return True, False
    # ЧИСЛО ЗНАКОВ, НАЗВАННОЕ В СТРОКЕ, ПЕРЕСЧИТЫВАЕТСЯ: «в 3990 знаков 3» есть ложь дома.
    for образец in (_ЗНАКОВ, _ЗНАКОВ_ИХ, _DIGITS):
        for число, знаков in образец.findall(ответ):
            if len(число) != int(знаков):
                return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:74]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    пр = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "произведение")
    ло = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "ловит")
    то = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "точно")
    if судить(пр.replace("ибо", "иб"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(ло.replace("тогда", "тогд"))[1] is not False:
        беды.append("обрезанное слово в ловле прошло")
    # ЧИСЛО ЗНАКОВ, НАЗВАННОЕ НЕВЕРНО, ОБЯЗАНО ЛОВИТЬСЯ СЧЁТОМ, А НЕ СЛОВАРЁМ РАМОК: подмена
    # «знаков 4» на «знаков 5» есть порча ОДНИМ словом и была бы поймана и без пересчёта —
    # потому здесь портится ДВА места разом, и ловит её только счёт.
    двумя = ло.replace("знаков 4", "знаков 5").replace("их 3", "их 2")
    if двумя != ло and судить(двумя)[1] is not False:
        беды.append("подмена числа знаков прошла")
    if судить(то.replace("точно", "точн"))[1] is not False:
        беды.append("обрезанное слово в цене прошло")
    if судить(пр + " " + пр)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ПРИКИДКА: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
