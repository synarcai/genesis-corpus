def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    for язык in ЯЗЫКИ:
        assert len(МЕСЯЦЫ[язык]) == 12, f"месяцев не двенадцать: {язык}"
        assert len(set(МЕСЯЦЫ[язык])) == 12, f"имя месяца дважды: {язык}"
    assert len(set(ДАТЫ)) == len(ДАТЫ), "дата дважды"
    for д, м, г in ДАТЫ:
        assert 1 <= м <= 12 and 1 <= д <= ДЛИНЫ[м - 1], f"такой даты нет: {д}.{м}.{г}"
    # ВСЯКИЙ РОД ОБЯЗАН БЫТЬ КУПЛЕН ПАРАМИ, А НЕ ОБЪЯВЛЕН: иначе объявление лжёт.
    виды = {что_решило(а, б) for а, б in itertools.combinations(ДАТЫ, 2)}
    assert виды == set(РОДЫ), f"род объявлен и не куплен парами: {set(РОДЫ) - виды}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
