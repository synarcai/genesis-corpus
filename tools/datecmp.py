#!/usr/bin/env python3
"""ДОМ СРАВНЕНИЯ ДАТ (14.09, куплен нулём пробы).

Замерено 14.09 по своду в 447 451 строку: «какая дата» / «which date» — НОЛЬ строк. Слово
«раньше» есть (152 строки), но всё это ВРЕМЯ СУТОК — «ушла утром, а пришла днём»; о том,
какая из двух ДАТ раньше, корпус не говорит нигде. Мир даты (`dateforms`, 480 страниц)
умеет считать вперёд и назад через край месяца — и ни разу не СРАВНИВАЕТ.

    У ДАТЫ ТРИ ЧИСЛА, И ВЕСА ИХ РАЗНЫ. Год тяжелее месяца, месяц тяжелее дня, и решает
    САМОЕ ТЯЖЁЛОЕ ИЗ РАЗЛИЧНЫХ. «31 декабря 2023 раньше, чем 1 января 2024», хотя 31 больше
    1: день здесь не решает ничего, ибо разошёлся год. Читатель, сравнивающий первое число,
    какое видит, ошибётся ровно здесь.

ЭТО ТОТ ЖЕ ЗАКОН, ЧТО В ДОМЕ АЗБУКИ, И ДРУГОЙ. Там ключ составной по МЕСТУ («дом» перед
«дома», ибо буквы кончились), здесь — по ВЕСУ (год перед днём, ибо год тяжелее). Место и
вес суть разные вещи, и потому мир отдельный.

ТРИ РОДА ПО ДЕЛУ — по тому, ЧТО РЕШИЛО:

    по_году     годы различны: день и месяц не значат ничего;
    по_месяцу   год один, месяцы различны: день не значит ничего;
    по_дню      год и месяц одни — и лишь тогда решает день.

    ОТВЕТ БЕЗ ПРИЧИНЫ НЕ ЕСТЬ ОТВЕТ. Страница называет не только раннюю дату, но и ЧТО
    решило. Сказать «решает день» там, где разошёлся год, — ложь, даже когда названа верная
    дата, и суд такую страницу не пропускает.
"""
import itertools
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("по_году", "по_месяцу", "по_дню")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "по_году": "годы различны: день и месяц не значат ничего",
    "по_месяцу": "год один, месяцы различны: день не значит ничего",
    "по_дню": "год и месяц одни — и лишь тогда решает день",
}

# ИМЯ МЕСЯЦА ОБЪЯВЛЕНО В ТОЙ ФОРМЕ, В КАКОЙ СТОИ́Т В ДАТЕ: по-русски это родительный («31
# декабря»), и он не выводится из именительного отсечением окончания.
МЕСЯЦЫ = {
    "ru": ("января", "февраля", "марта", "апреля", "мая", "июня",
           "июля", "августа", "сентября", "октября", "ноября", "декабря"),
    "en": ("january", "february", "march", "april", "may", "june",
           "july", "august", "september", "october", "november", "december"),
}
ДЛИНЫ = (31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)   # високосный год допущен

ДАТЫ = ((31, 12, 2023), (18, 12, 2023), (5, 5, 2023), (7, 5, 2023), (9, 11, 2023),
        (1, 1, 2024), (15, 2, 2024), (28, 3, 2024), (3, 4, 2024), (12, 4, 2024),
        (27, 4, 2024), (2, 6, 2024), (21, 6, 2024), (30, 6, 2024))

РАМКИ = {
    "ru": {
        "дата": "{д} {м} {г}",
        "вопрос": "что раньше: {а} или {б}? раньше {ранняя}: {почему}.",
        "по_году": "год решает, и {меньше} меньше {больше}",
        "по_месяцу": "год один, решает месяц: {меньше} идёт раньше, чем {больше}",
        "по_дню": "год и месяц одни, решает день: {меньше} меньше {больше}",
    },
    "en": {
        "дата": "{д} {м} {г}",
        "вопрос": "which is earlier: {а} or {б}? {ранняя} is earlier: {почему}.",
        "по_году": "the year decides, and {меньше} is less than {больше}",
        "по_месяцу": "the year is the same, the month decides: {меньше} comes before "
                     "{больше}",
        "по_дню": "the year and the month are the same, the day decides: {меньше} is less "
                  "than {больше}",
    },
}


def дата_слова(язык, дата):
    д, м, г = дата
    return РАМКИ[язык]["дата"].format(д=д, м=МЕСЯЦЫ[язык][м - 1], г=г)


def что_решило(а, б):
    """«по_году», «по_месяцу» или «по_дню» — САМОЕ ТЯЖЁЛОЕ ИЗ РАЗЛИЧНЫХ."""
    if а[2] != б[2]:
        return "по_году"
    if а[1] != б[1]:
        return "по_месяцу"
    return "по_дню" if а[0] != б[0] else None


def _ключ(дата):
    return (дата[2], дата[1], дата[0])


def страница(язык, а, б):
    род = что_решило(а, б)
    if род is None:
        return None                     # даты равны — ранней нет
    ранняя, поздняя = sorted((а, б), key=_ключ)
    рамки = РАМКИ[язык]
    if род == "по_году":
        почему = рамки["по_году"].format(меньше=ранняя[2], больше=поздняя[2])
    elif род == "по_месяцу":
        почему = рамки["по_месяцу"].format(меньше=МЕСЯЦЫ[язык][ранняя[1] - 1],
                                           больше=МЕСЯЦЫ[язык][поздняя[1] - 1])
    else:
        почему = рамки["по_дню"].format(меньше=ранняя[0], больше=поздняя[0])
    return рамки["вопрос"].format(а=дата_слова(язык, а), б=дата_слова(язык, б),
                                  ранняя=дата_слова(язык, ранняя), почему=почему), род


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for а, б in itertools.permutations(ДАТЫ, 2):
            вышло = страница(язык, а, б)
            if вышло:
                вон.setdefault(вышло[0], (язык, вышло[1]))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД РАЗБИРАЕТ ОБЕ ДАТЫ ЗАНОВО, СРАВНИВАЕТ ИХ САМ и сверх того проверяет ПРИЧИНУ: какое
# поле названо решившим и то ли оно, какое решило на деле. Имя месяца берётся из объявления,
# и месяц чужого языка запись не нашей делает.
def _дата(язык, кусок):
    м = re.fullmatch(r"(\d{1,2}) (\S+) (\d{4})", кусок.strip())
    if not м or м.group(2) not in МЕСЯЦЫ[язык]:
        return None
    день, месяц, год = int(м.group(1)), МЕСЯЦЫ[язык].index(м.group(2)) + 1, int(м.group(3))
    if not 1 <= день <= ДЛИНЫ[месяц - 1]:
        return None                     # такого числа в этом месяце нет
    return день, месяц, год


def _образец(язык):
    о = re.escape(РАМКИ[язык]["вопрос"])
    for дыра in ("а", "б", "ранняя"):
        о = о.replace(re.escape("{" + дыра + "}"), f"(?P<{дыра}>[^:?]+?)")
    return re.compile(о.replace(re.escape("{почему}"), "(?P<почему>[^.?]+)") + r"$")


_ОБРАЗЦЫ = {я: _образец(я) for я in ЯЗЫКИ}


def судить(строка):
    """(судимо, истинно) — даты сравнены заново, и причина сверена с делом."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        м = _ОБРАЗЦЫ[язык].fullmatch(строка)
        if not м:
            continue
        а, б = _дата(язык, м.group("а")), _дата(язык, м.group("б"))
        ранняя = _дата(язык, м.group("ранняя"))
        if а is None or б is None or ранняя is None:
            continue                    # чужая запись — суд о ней молчит
        род = что_решило(а, б)
        if род is None:
            return True, False          # даты равны, а ранняя названа
        если_бы = страница(язык, а, б)
        # СТРАНИЦА СОБРАНА ЗАНОВО И СВЕРЕНА ЦЕЛИКОМ: и ранняя дата, и причина, и то, какое
        # поле названо решившим. Ответ без причины не есть ответ.
        return True, если_бы is not None and если_бы[0] == строка
    return False, True


