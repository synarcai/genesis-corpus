#!/usr/bin/env python3
"""СИРОТА ПОЛУЧАЕТ ГЕНЕРАТОР: мир «prog» из семени с вопросной поверхностью.

Мир лежал в datasets/ без генератора и без единого вопроса; владелец
объявил ноль немых законом. Вчерашний файл стал СЕМЕНЕМ в tools/seeds/:
генератор переносит каждую его строку и к обратимым прикладывает вопрос
по ОБЪЯВЛЕННЫМ образцам дома обращения (tools/inverting.py). Ответ
судится тем же судом, что и утверждение; порча ловится — проверено
палатой до записи.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import inverting  # noqa: E402
from layer import PASSES, Сбор, emit  # noqa: E402
import re as _re  # noqa: E402

СЕМЯ = КОРЕНЬ / "tools" / "seeds" / "genesis_l3_prog.txt"
ЦЕЛЬ = "datasets/genesis_l3_prog.txt"
ОБРАЩЕНИЯ = ('ход',)


# РОД СТРОКИ СЕМЕНИ ЧИТАЕТСЯ ПО ЕЁ СОБСТВЕННОМУ ОБОРОТУ (14.09). Мир этот не строится
# ветвями: строки пришли семенем, и дело каждой записано в ней первым же словом — «let»
# есть связывание, «сортировка» есть ход над рядом, «массив» есть опрос его частей.
# Вопрос идёт в род своего утверждения: `inverting.с_вопросами` кладёт его СРАЗУ ЗА нею.
# ЗАКОН МАССЫ СВЁЛ СЕМЬ РОДОВ К ПЯТИ (14.09): мир мал — 144 различных строки, — и трое
# из семи несли по четыре страницы. Сведено по родству:
#
#     НАКОПЛЕНИЕ И РЕКУРСИЯ СУТЬ ОДНА ЦЕПЬ ШАГОВ: у обеих есть основание, шаг и итог; цикл
#     разворачивает её трассой, рекурсия сворачивает к предыдущему.
#
# А чтение слова идёт К СВОЕМУ ДЕЛУ: «слово let» и «знак ;» суть страницы о связывании,
# «слово return» — о цепи шагов.
СВЯЗЫВАНИЕ = "связывание: имя значению, счёт над именами и чтение его слов"
ВЕТВЛЕНИЕ = "ветвление: вход назван, выход вычислен"
ЦЕПЬ_ШАГОВ = "цепь шагов: накопление с трассой и рекурсия со своим основанием"
МАССИВ = "массив: длина, первый и последний"
СОРТИРОВКА = "сортировка ряда: ход и его итог"

_ОБОРОТЫ = (
    (_re.compile(r"^(let|пусть) "), СВЯЗЫВАНИЕ),
    (_re.compile(r"^(if|если) "), ВЕТВЛЕНИЕ),
    (_re.compile(r"^s = 0"), ЦЕПЬ_ШАГОВ),
    (_re.compile(r"^(массив|array) "), МАССИВ),
    (_re.compile(r"^(сортировка|sort) "), СОРТИРОВКА),
    (_re.compile(r"^(что даёт |what does )?(сортировка|sort) "), СОРТИРОВКА),
    (_re.compile(r"factorial"), ЦЕПЬ_ШАГОВ),
    (_re.compile(r"(слово return|word return)"), ЦЕПЬ_ШАГОВ),
    (_re.compile(r"(слово let|word let|знак ;|sign ;)"), СВЯЗЫВАНИЕ),
)


def род_строки(с):
    """Род строки семени — по её собственному обороту."""
    for образец, род in _ОБОРОТЫ:
        if образец.search(с):
            return род
    return None


def показы(шаг):
    строки = СЕМЯ.read_text(encoding="utf-8").splitlines()
    вон = Сбор()
    for с in inverting.с_вопросами(строки, ОБРАЩЕНИЯ, len(PASSES), шаг):
        род = род_строки(с)
        if род is not None:
            вон.род = род
        вон.append(с)
    return вон


def main():
    if not СЕМЯ.exists():
        print(f"ОТКАЗ: семени {СЕМЯ.name} нет")
        return 2
    emit(ЦЕЛЬ, показы)
    return 0


# --------------------------------------------------------------- ОБЪЯВЛЕНИЕ ДОМА

РОДЫ = (СВЯЗЫВАНИЕ, ВЕТВЛЕНИЕ, ЦЕПЬ_ШАГОВ, МАССИВ, СОРТИРОВКА)


def страницы(шаг):
    return показы(шаг)


def перебор_страниц(шаг):
    return показы(шаг).парами


def группы(шаг):
    return [страницы(шаг)]


def _показы_дома():
    вон = {}
    for ш in range(len(PASSES)):
        for с, род in перебор_страниц(ш):
            if с.rstrip():
                вон.setdefault(с.rstrip(), род)
    return вон


ПОКАЗЫ = _показы_дома()


def _самопроверка_дома():
    # НИ ОДНА СТРОКА СЕМЕНИ НЕ ОСТАЁТСЯ БЕЗ РОДА, И ЭТО РУБЕЖ: читатель семени, у
    # которого есть «прочее», молча кладёт туда всё, чего не понял.
    строки = [с for с in СЕМЯ.read_text(encoding="utf-8").splitlines() if с.strip()]
    немые = [с for с in строки if род_строки(с) is None]
    assert not немые, f"строк семени без рода: {len(немые)}, первая — {немые[0][:70]}"
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка_дома()


if __name__ == "__main__":
    sys.exit(main())
