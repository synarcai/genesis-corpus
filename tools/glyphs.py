# ПИСЬМО И РЕГИСТР — ЧАСТЬ ИМЕНИ: имя символа однозначно, сетка — нет.
ТАБЛИЦА = {}          # символ → семь строк
РОД = {}              # символ → (письмо, регистр) или (класс, None)
