ИМЕНА_ЗНАКОВ = {
    "?": ("the question mark", "вопросительный знак"),
    "!": ("the exclamation mark", "восклицательный знак"),
    ".": ("the full stop", "точка"), ",": ("the comma", "запятая"),
    ":": ("the colon", "двоеточие"), ";": ("the semicolon", "точка с запятой"),
    "/": ("the slash", "косая черта"), "%": ("the percent sign", "знак процента"),
    "(": ("the left parenthesis", "левая скобка"),
    ")": ("the right parenthesis", "правая скобка"),
    " ": ("the space", "пробел"),
}


def имя_en(символ):
    письмо, регистр = РОД[символ]
    if письмо == "digit":
        return f"the digit {символ}"
    if письмо == "sign":
        return ИМЕНА_ЗНАКОВ.get(символ, (f"the sign {символ}",))[0]
    return f"the {регистр} {'Latin' if письмо == 'latin' else 'Cyrillic'} letter {символ}"


def имя_ru(символ):
    письмо, регистр = РОД[символ]
    if письмо == "digit":
        return f"цифра {символ}"
    if письмо == "sign":
        return ИМЕНА_ЗНАКОВ.get(символ, (None, f"знак {символ}"))[1]
    return (f"{'заглавная' if регистр == 'capital' else 'строчная'} "
            f"{'латинская' if письмо == 'latin' else 'русская'} буква {символ}")


# ИМЯ ОДНОЗНАЧНО ВЕДЁТ К СИМВОЛУ — таблица строится из тех же функций, что
# пишут показ; суд читает имя ею же (одна рука пишет, та же читает).
ПО_ИМЕНИ = {}
for _с in ТАБЛИЦА:
    for _имя in (имя_en(_с), имя_ru(_с)):
        assert _имя not in ПО_ИМЕНИ or ПО_ИМЕНИ[_имя] == _с, _имя
        ПО_ИМЕНИ[_имя] = _с
ОБРАЗЕЦ_ИМЕНИ = "(?:" + "|".join(
    re.escape(и) for и in sorted(ПО_ИМЕНИ, key=len, reverse=True)) + ")"


def символ_по_имени(имя):
    """Символ по имени в любом из двух языков; None — имя не наше."""
    return ПО_ИМЕНИ.get(имя)
