def страницы():
    вон = {}
    si_il, si_elle = frgram.элизия("si il"), frgram.элизия("si elle")
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for ц, гл, сг, п_гл_ru, п_сг_ru, п_гл_en, п_сг_en in СЛУЧАИ:
            сокр = frgram.элизия(f"{ц} {гл}")
            целое = frgram.элизия(f"{ц} {сг}")
            общ = dict(ц=ц, гл=гл, сг=сг, сокр=сокр, целое=целое,
                       перевод_гл=п_гл_ru if язык == "ru" else п_гл_en,
                       перевод_сг=п_сг_ru if язык == "ru" else п_сг_en)
            вон[рамки["сокращение названо"].format(**общ)] = (язык, "сокращение названо")
            вон[рамки["граница правила"].format(**общ)] = (язык, "граница правила")
        for глухое in ГЛУХИЕ:
            for придых in ПРИДЫХАТЕЛЬНЫЕ:
                вон[рамки["буква h молчит не всегда"].format(
                    глухое=глухое, придых=придых,
                    сокр_глухое=frgram.элизия(f"le {глухое}"))] = (
                    язык, "буква h молчит не всегда")
        вон[рамки["своя граница у одного слова"].format(si_il=si_il, si_elle=si_elle)] = (
            язык, "своя граница у одного слова")
        вон[рамки["апостроф не есть буква"].format(si_il=si_il)] = (
            язык, "апостроф не есть буква")
    return вон


ПОКАЗЫ = страницы()


# СУД ЧИТАЕТ ФРАНЦУЗСКИЙ КУСОК СТРАНИЦЫ И СВЕРЯЕТ ЕГО С ЗАКОНОМ. Всякая французская пара
# «служебное слово + слово» на странице обязана быть ровно тем, что даёт `frgram.элизия` над
# развёрнутой формой: сокращена, если закон сокращает, и цела, если нет.
#
#     СУД, СВЕРЯЮЩИЙ ФОРМУ С ЗАКОНОМ ДОМА ЯЗЫКА, НЕ ЗНАЕТ ФРАНЦУЗСКОГО И НЕ ДОЛЖЕН ЗНАТЬ.
_ФР = _re.compile(r"«([^»]+)»")


def _французский(кусок):
    """True, если кусок есть французская пара «служебное слово + слово» или её сокращение."""
    слова = кусок.split()
    if len(слова) == 2 and слова[0].lower() in frgram.ПАРЫ:
        return True
    развёрнут = frgram.развернуть(кусок)
    return развёрнут != кусок and len(развёрнут.split()) == 2


_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякий французский кусок в ней сходится с законом.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА (12.09, ночь, поймано судом
    прозы). Первая редакция судила ВСЯКУЮ строку, где в кавычках стояла пара, похожая на
    французскую, — и назвала ложью письмо Чаадаева об эпиграфе. Русская проза, ставящая в
    кавычки два слова, не есть показ этого дома.

        СУД, ЧИТАЮЩИЙ ПО ПРИЗНАКУ, А НЕ ПО ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, ЗОВЁТ ЛОЖЬЮ ЧУЖУЮ
        РЕЧЬ, СОВПАВШУЮ С НИМ ФОРМОЙ.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    куски = [к for к in _ФР.findall(с) if _французский(к)]
    if not куски:
        return True, True
    for кусок in куски:
        развёрнут = frgram.развернуть(кусок)
        if frgram.элизия(развёрнут) != кусок:
            return True, False
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:100])
            беды += 1
    # МУТАНТ ЕСТЬ ПОРЧА СВОЕЙ СТРАНИЦЫ ОДНИМ СЛОВОМ, А НЕ ВЫДУМАННАЯ СТРОКА.
    #
    #     ПРОБА, ПОСТАВЛЕННАЯ НА СТРОКЕ, КОТОРОЙ ДОМ НЕ ПИШЕТ, ПРОВЕРЯЕТ ПРИЗНАК, А НЕ СУД.
    # ПОРЧА ОБЯЗАНА СОХРАНЯТЬ ЧИСЛО СЛОВ, ИБО ПРИЗНАК ПОРЧИ СЧИТАЕТ РАСХОЖДЕНИЕ ПОСЛОВНО.
    # Первая редакция разворачивала стяжение («s'il» → «si il») и тем МЕНЯЛА ДЛИНУ строки —
    # признак такой порчи не видел вовсе и звал её чужой речью.
    #
    #     ПОРЧА, МЕНЯЮЩАЯ ЧИСЛО СЛОВ, НЕ ЕСТЬ ПОРЧА ОДНИМ СЛОВОМ: она уходит мимо признака,
    #     и проба, на ней стоящая, доказывает лишь то, что признак её не берёт.
    мутантов = 0
    чужие_служебные = sorted(frgram.ПАРЫ)
    for показ in ПОКАЗЫ:
        слова = показ.split(" ")
        порча = None
        for i, сл in enumerate(слова):
            если = сл.strip(".,:;«»\"„“?!")
            if если in frgram.ПАРЫ:
                иное = next(ц for ц in чужие_служебные if ц != если)
                порча = " ".join(слова[:i] + [сл.replace(если, иное)] + слова[i + 1:])
                break
        if порча is None or порча == показ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:100])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    # ЧУЖАЯ РЕЧЬ НЕ ПОДСУДНА.
    for чужая in ("Что касается самого эпиграфа, то с ним сопряжено «несколько недоразумений».",
                  "он писал «je vends» на полях, и это была не элизия."):
        if судить(чужая) != (False, False):
            print("  ЧУЖАЯ РЕЧЬ СУДИМА:", чужая[:100])
            беды += 1
    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, мутантов поймано {мутантов}, "
          f"немых h {len(frgram.НЕМОЕ_H)}, придыхательных {len(ПРИДЫХАТЕЛЬНЫЕ)}, бед {беды}")
    return беды



if __name__ == "__main__":
    sys.exit(1 if _самопроверка() else 0)
