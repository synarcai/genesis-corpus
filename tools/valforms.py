def валентность(шаг):
    """Знак производной жизнеспособности — и ничего сверх него."""
    знам, порог = доли(шаг)
    вон = []
    for i in range(12):
        было = порог + 1 + i % (знам - порог - 1)
        стало = было + (1 if i % 2 else -1)
        if not порог < стало <= знам:
            стало = было + 1 if было < знам else было - 1
        лучше = стало > было
        ру = (f"жизнеспособность была {было} из {знам}, стала "
              f"{стало} из {знам}: {'рост' if лучше else 'убыль'}, "
              f"{'стало лучше' if лучше else 'стало хуже'}.")
        ан = (f"viability was {было} of {знам} and is {стало} of "
              f"{знам}: {'a rise' if лучше else 'a fall'}, "
              f"{'better' if лучше else 'worse'}.")
