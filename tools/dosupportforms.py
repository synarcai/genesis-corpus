def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _куски(строка):
    """Цитаты в «ёлочках»."""
    return _re.findall(r"«([^»]+)»", строка)


def _нарушает(тело):
    """Нарушает ли цитата хоть один из пяти законов дома."""
    голое = тело.lstrip("*").strip()
    m = _ЦЕПЬ.search(голое)
    if m:
        всп, кто, глагол = m.group(1), m.group(2), m.group(3)
        # ЛИЦО: «does» ходит с третьим лицом единственного, «do» — с прочими.
        if всп in ("do", "does") and кто in _DO_ЛИЦО and _DO_ЛИЦО[кто] != всп:
            return True
        # ГЛАГОЛ ПОСЛЕ ВСПОМОГАТЕЛЬНОГО — ТОЛЬКО БАЗОВЫЙ.
        if глагол in _НЕ_БАЗЫ:
            return True
        # «be» и модальные вспомогательного не берут.
        if глагол == "be" or глагол in _МОДАЛЫ:
            return True
    # ВОПРОС О ПОДЛЕЖАЩЕМ: «who» и вспомогательный вместе не ходят.
    if _re.search(r"\bwho\s+(do|does|did)\b", голое):
        return True
    # ПРИ СВЯЗКЕ И МОДАЛЬНОМ ВСПОМОГАТЕЛЬНОГО НЕТ: «*do you be ready».
    if _re.search(r"\b(do|does|did)\s+\w+\s+(be|" + "|".join(sorted(_МОДАЛЫ)) + r")\b", голое):
        return True
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с законом.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _куски(с):
        звезда = цитата.startswith("*")
        if not _ВСПОМ.search(цитата) and not звезда:
            continue
        if звезда != _нарушает(цитата):
            return True, False
    return True, True


