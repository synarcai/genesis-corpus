#!/usr/bin/env python3
"""ДОМ ОБРАТНОЙ ЗАДАЧИ — ТЕ ЖЕ ТРИ ЧИСЛА, И ВОПРОС С ДРУГОГО КОНЦА.

    ОБРАТНОЙ ЗАДАЧИ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 249 мирам показов: «обратная
    задача», «inverse task» — НОЛЬ. Свод решает тысячи прямых задач и сто двадцать три раза
    проверяет ответ ОБРАТНЫМ ХОДОМ («проверим обратным ходом: 6 половин это 6 ÷ 2 = 3 целых»),
    но ни разу не ставит обратную задачу КАК ЗАДАЧУ.

    ПРОВЕРИТЬ ОБРАТНЫМ ХОДОМ И РЕШИТЬ ОБРАТНУЮ ЗАДАЧУ — РАЗНЫЕ ДЕЛА: первое подтверждает
    известный ответ, второе ищет неизвестное условие.

ДВАДЦАТЬ ВТОРАЯ ЛОВУШКА РЯДА — В ЗНАКЕ ДЕЙСТВИЯ: задача, где сказано «прибавили», решается
ВЫЧИТАНИЕМ, если спрашивают не итог, а слагаемое. Читатель, привыкший брать действие из слова
условия, возьмёт сложение и ошибётся.

    ДЕЙСТВИЕ БЕРЁТСЯ ИЗ ВОПРОСА, А НЕ ИЗ СЛОВА УСЛОВИЯ.

ЧЕТЫРЕ РОДА, ДВЕ ПАРЫ:

    прямая сумма    на полке 5 книг, в шкафу 3 книги; всего 8 книг: 5 + 3 = 8.
    обратная сумма  всего 8 книг, на полке 5 книг; в шкафу 3 книги: 8 − 5 = 3.  ← ЛОВУШКА
    прямое деление  в 3 коробках по 4 конфеты; всего 12 конфет: 3 × 4 = 12.
    обратное деление всего 12 конфет в 3 коробках; в каждой 4 конфеты: 12 ÷ 3 = 4.

ПЕРВАЯ ПАРА И ВТОРАЯ СТОЯ́Т НА ОДНОМ ЗАКОНЕ: у сложения обратное — вычитание, у умножения —
деление, и обратная задача решается ОБРАТНЫМ действием. Показать одну пару значило бы сказать
правило о сложении; две пары говорят ЗАКОН.

    ЗАКОН, ПОКАЗАННЫЙ НА ОДНОМ ДЕЙСТВИИ, ЧИТАЕТСЯ КАК СВОЙСТВО ЭТОГО ДЕЙСТВИЯ.

ТРИ ЧИСЛА У ПРЯМОЙ И ОБРАТНОЙ ЗАДАЧИ ОДНИ И ТЕ ЖЕ, И ЭТО ВИДНО СТРАНИЦЕЙ: меняются местами
известное и искомое, а числа остаются. Потому пары кованы на одной тройке — разные тройки развели
бы стороны одного дела.

    python3 tools/inverseforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётные формы вещей объявлены там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("прямая сумма", "обратная сумма", "прямое деление", "обратное деление")

ВЕЩИ = ("книга", "карандаш", "конфета", "яблоко")
АНГЛ = {"книга": ("book", "books"), "карандаш": ("pencil", "pencils"),
        "конфета": ("sweet", "sweets"), "яблоко": ("apple", "apples"),
        "коробка": ("box", "boxes")}
МЕСТА = {"ru": ("на полке", "в шкафу"), "en": ("on the shelf", "in the cupboard")}


def форма(язык, ключ, n):
    if язык == "en":
        один, много = АНГЛ[ключ]
        return один if n == 1 else много
    return rugram.форма(ключ, n)


def род_мн(язык, ключ):
    """Родительный множественного — то, что стои́т после «сколько» и «всего»."""
    return АНГЛ[ключ][1] if язык == "en" else rugram.форма(ключ, 5)


РАМКИ = {
    "ru": {
        "прямая сумма": "{место1} {a} {вещь_a}, {место2} {b} {вещь_b}; всего {s} {вещь_s}: {a} + {b} = {s}.",
        "обратная сумма": "всего {s} {вещь_s}, {место1} {a} {вещь_a}; {место2} {b} {вещь_b}: {s} − {a} = {b}.",
        "прямое деление": "{k} {короб_k} по {m} {вещь_m}; всего {p} {вещь_s}: {k} × {m} = {p}.",
        "обратное деление": "всего {p} {вещь_s} на {k} {короб_k}; в каждой {m} {вещь_m}: {p} ÷ {k} = {m}.",
    },
    "en": {
        "прямая сумма": "{место1} there are {a} {вещь_a}, {место2} there are {b} {вещь_b}; in all {s} {вещь_s}: {a} + {b} = {s}.",
        "обратная сумма": "in all {s} {вещь_s}, {место1} there are {a} {вещь_a}; {место2} there are {b} {вещь_b}: {s} − {a} = {b}.",
        "прямое деление": "{k} {короб_k} hold {m} {вещь_m} each; in all {p} {вещь_s}: {k} × {m} = {p}.",
        "обратное деление": "in all {p} {вещь_s} spread over {k} {короб_k}; in each one {m} {вещь_m}: {p} ÷ {k} = {m}.",
    },
}
# ПОСЛЕ «ВСЕГО» СТОИ́Т СЧЁТНАЯ ФОРМА САМОГО ЧИСЛА, А НЕ РОДИТЕЛЬНЫЙ МНОЖЕСТВЕННОГО: «всего 4
# книги», а не «всего 4 книг». Первая редакция брала третью форму на все случаи, и палата
# назвала бы это ложью устами суда русского счёта.
ПУСТО = dict(место1="", место2="", a=0, b=0, s=0, k=0, m=0, p=0,
             вещь_a="", вещь_b="", вещь_m="", вещь_s="", короб_k="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, места = РАМКИ[язык], МЕСТА[язык]
        for вещь in ВЕЩИ:
            род = род_мн(язык, вещь)
            for a in range(2, 13):
                for b in range(2, 13):
                    if (a * b + len(вещь)) % 5:
                        continue
                    общ = dict(ПУСТО, место1=места[0], место2=места[1], a=a, b=b, s=a + b,
                               вещь_a=форма(язык, вещь, a), вещь_b=форма(язык, вещь, b),
                               вещь_s=форма(язык, вещь, a + b))
                    вон[рамки["прямая сумма"].format(**общ)] = (язык, "прямая сумма")
                    вон[рамки["обратная сумма"].format(**общ)] = (язык, "обратная сумма")
            for k in range(2, 10):
                for m in range(2, 10):
                    if (k + m + len(вещь)) % 3:
                        continue
                    общ = dict(ПУСТО, k=k, m=m, p=k * m, вещь_m=форма(язык, вещь, m),
                               вещь_s=форма(язык, вещь, k * m),
                               короб_k=форма(язык, "коробка", k))
                    вон[рамки["прямое деление"].format(**общ)] = (язык, "прямое деление")
                    вон[рамки["обратное деление"].format(**общ)] = (язык, "обратное деление")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА = re.compile(r"(?<![/\d])(\d+) \+ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (\d+)(?![/\d])")
_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    # ОБРАТНАЯ ЗАДАЧА РЕШАЕТСЯ ОБРАТНЫМ ДЕЙСТВИЕМ, И ЭТО ПРОВЕРЯЕТСЯ: на странице, где итог
    # назван ПЕРВЫМ, стои́т вычитание или деление, а не сложение с умножением.
    первое = с.split(";")[0]
    if первое.startswith(("всего", "in all")):
        if _СУММА.search(с) or _ПРОИЗВ.search(с):
            return True, False
        if not (_РАЗНОСТЬ.search(с) or _ЧАСТНОЕ.search(с)):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    об = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "обратная сумма")
    пд = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "прямое деление")
    for страница, слово, куда in ((об, "всего", "всег"), (пд, "коробки", "коробк")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(об + " " + об)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ПАРЫ СТОЯ́Т НА ОДНОЙ ТРОЙКЕ ЧИСЕЛ: иначе прямая и обратная задачи — про разное.
    прямые = {tuple(sorted(_СУММА.findall(с)[0])) for с, (я, р) in ПОКАЗЫ.items()
              if я == "ru" and р == "прямая сумма"}
    обратные = {tuple(sorted((a, c, b))) for с, (я, р) in ПОКАЗЫ.items()
                if я == "ru" and р == "обратная сумма"
                for a, b, c in [_РАЗНОСТЬ.findall(с)[0]]}
    if прямые != обратные:
        беды.append(f"тройки прямых и обратных разошлись: {len(прямые)} и {len(обратные)}")
    print(f"ОБРАТНАЯ ЗАДАЧА: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
