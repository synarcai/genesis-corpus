#!/usr/bin/env python3
"""ДОМ МОДУЛЯ ЧИСЛА — РАССТОЯНИЕ ДО НУЛЯ, У КОТОРОГО НЕТ ЗНАКА.

    МОДУЛЯ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 237 мирам показов: запись «|−5|» —
    НОЛЬ; «расстояние до нуля», «distance from zero» — НОЛЬ. Слово «модуль» встречается 2540
    раз и ВСЕГДА ОБ ИНОМ: это остаток по модулю («7 по модулю 2 равно 1»), сравнения по модулю
    — арифметика вычетов, а не величина числа. Ещё 297 раз модуль читается в мире записи
    формул, но ЛАТЕХОМ («\\left| 15 \\right|») и как ИМЯ ЗНАКА, а не как число.

    СЛОВО, ЗАНЯТОЕ ДРУГИМ ПОНЯТИЕМ, НЕ ЕСТЬ ПОКАЗАННОЕ ПОНЯТИЕ.

ЭТОТ ДОМ ЗАМЫКАЕТ ЗНАКОВУЮ ОБЛАСТЬ ЧЕТВЁРТЫМ ЧЛЕНОМ и даёт имя тому, что три прежних дома
показывали без имени: дом порядка мерил ШАГИ ВЛЕВО ОТ НУЛЯ, дом знакового сложения показал, что
противоположные в сумме дают ноль, — и оба говорили о РАССТОЯНИИ ДО НУЛЯ. Его имя — модуль.

    ТО, ЧТО ПОКАЗАНО ТРИЖДЫ БЕЗ ИМЕНИ, ОБЯЗАНО ПОЛУЧИТЬ ИМЯ, ИНАЧЕ ЧИТАТЕЛЬ НЕ УЗНАЁТ ЕГО
    В ЧЕТВЁРТЫЙ РАЗ.

ЧЕТЫРЕ РОДА:

    расстояние    |−5| = 5: от −5 до нуля 5 шагов, и от 5 до нуля столько же.
    равные модули |−5| = |5|, хотя −5 и 5 разные числа: до нуля им поровну — 5 шагов.
    модуль суммы  |−5 + 3| = 2, а |−5| + |3| = 8: модуль суммы не есть сумма модулей. ← ЛОВУШКА
    порядок       −5 меньше −2, хотя |−5| больше |−2|: дальше влево — значит меньше.  ← ШОВ

ДЕСЯТАЯ ЛОВУШКА РЯДА — ТРЕТИЙ РОД: действие и модуль НЕ ПЕРЕСТАВЛЯЮТСЯ. Читатель, привыкший, что
скобку можно раскрыть почленно, раскроет и эту — и получит восемь вместо двух.

ЧЕТВЁРТЫЙ РОД ЕСТЬ ШОВ С ДОМОМ ПОРЯДКА, И ОН ЖЕ ВТОРАЯ ЛОВУШКА ДОМА: у меньшего числа модуль
БОЛЬШЕ. Порознь дом порядка внушал бы, что «дальше от нуля» значит «больше», — а за нулём это
ровно наоборот.

ВТОРОЙ РОД ГОВОРИТ ГРАНИЦУ ОБРАТНОГО ХОДА: равенство модулей НЕ ЕСТЬ равенство чисел. Модуль
теряет знак, и потому по нему нельзя вернуться к числу — из «до нуля пять шагов» не следует, в
какую сторону.

ЗНАК МОДУЛЯ ЕСТЬ ПРЯМАЯ ЧЕРТА «|», А ЧИСЛО ВНУТРИ ПИШЕТСЯ ЗНАКОМ МИНУС «−», как во всей знаковой
области свода.

    python3 tools/absforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — русский счёт объявлен там, а не здесь

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("расстояние", "равные модули", "модуль суммы", "порядок")
ШАГ = "шаг"


def шагов(язык, n):
    return ("step" if n == 1 else "steps") if язык == "en" else rugram.форма(ШАГ, n)


def бытие(n):
    """Английский оборот бытия ПО ЧИСЛУ своего подлежащего.

    СВЯЗКА СОГЛАСУЕТСЯ ПО ЧИСЛУ ТАК ЖЕ, КАК ИМЯ. Дом склонял «step/steps» и держал
    «there are» намертво — и при a = 1 выходило «from −1 to zero there are 1 step».
    Одна страница из сорока, и нашёл её не суд дома, а прибор связки по полосе:

        ДОМ, СКЛОНЯЮЩИЙ ИМЯ И НЕ СКЛОНЯЮЩИЙ СВЯЗКУ, ЗНАЕТ ПОЛОВИНУ СОГЛАСОВАНИЯ.
    """
    return "there is" if n == 1 else "there are"


РАМКИ = {
    "ru": {
        "расстояние": "|−{a}| = {a}: от −{a} до нуля {a} {ша}, и от {a} до нуля столько же.",
        "равные модули": "|−{a}| = |{a}|, хотя −{a} и {a} разные числа: до нуля им поровну — {a} {ша}.",
        "модуль суммы": "|−{a} + {b}| = {c}, а |−{a}| + |{b}| = {s}: модуль суммы не есть сумма модулей.",
        "порядок": "−{a} меньше −{b}, хотя |−{a}| больше |−{b}|: дальше влево — значит меньше.",
    },
    "en": {
        "расстояние": "|−{a}| = {a}: from −{a} to zero {есть} {a} {ша}, and from {a} to zero just as many.",
        "равные модули": "|−{a}| = |{a}|, although −{a} and {a} are different numbers: both stand {a} {ша} from zero.",
        "модуль суммы": "|−{a} + {b}| = {c}, and |−{a}| + |{b}| = {s}: the modulus of a sum is not the sum of moduli.",
        "порядок": "−{a} is less than −{b}, although |−{a}| is greater than |−{b}|: farther to the left means less.",
    },
}
ПУСТО = dict(a=0, b=0, c=0, s=0, ша="", есть="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a in range(1, 41):
            ша = шагов(язык, a)
            вон[рамки["расстояние"].format(
                **dict(ПУСТО, a=a, ша=ша, есть=бытие(a)))] = (язык, "расстояние")
            вон[рамки["равные модули"].format(**dict(ПУСТО, a=a,
                                                     ша=ша))] = (язык, "равные модули")
        # МОДУЛЬ СУММЫ: слагаемые РАЗНОГО знака — иначе модуль суммы совпал бы с суммой модулей
        # и ловушки не было бы вовсе.
        for a in range(2, 14):
            for b in range(1, 14):
                c, s = abs(b - a), a + b
                if c == 0 or c == s or (a + b) % 3:
                    continue
                вон[рамки["модуль суммы"].format(
                    **dict(ПУСТО, a=a, b=b, c=c, s=s))] = (язык, "модуль суммы")
        for a in range(2, 15):
            for b in range(1, 14):
                if b >= a or (a * b) % 4:
                    continue
                вон[рамки["порядок"].format(**dict(ПУСТО, a=a, b=b))] = (язык, "порядок")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# МОДУЛЬ, СТОЯЩИЙ СЛАГАЕМЫМ, НЕ ЕСТЬ ОТДЕЛЬНОЕ РАВЕНСТВО. На странице «|−2| + |1| = 3» образец
# без оглядки назад брал «|1| = 3» — второе слагаемое вместе с итогом ВСЕЙ суммы — и звал
# девяносто шесть честных страниц ложью. ЗНАК ПЕРЕД ЧИСЛОМ ГОВОРИТ, ЧЕЙ ЭТО ЧЛЕН: та же беда и
# то же лечение, что у дома законов действия днём раньше.
_МОДУЛЬ = re.compile(r"(?<!\+ )\|(−?)(\d+)\| = (\d+)(?![/\d])")
_РАВНЫ = re.compile(r"\|−(\d+)\| = \|(\d+)\|")
_МОДУЛЬ_СУММЫ = re.compile(r"\|−(\d+) \+ (\d+)\| = (\d+)(?![/\d])")
_СУММА_МОДУЛЕЙ = re.compile(r"\|−(\d+)\| \+ \|(\d+)\| = (\d+)(?![/\d])")
_МЕНЬШЕ_ОТР = re.compile(r"−(\d+) (?:меньше|is less than) −(\d+)")
_БОЛЬШЕ_МОД = re.compile(r"\|−(\d+)\| (?:больше|is greater than) \|−(\d+)\|")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # МОДУЛЬ СЧИТАЕТСЯ, А НЕ ПРИНИМАЕТСЯ: ни один суд свода его не считает (замер 11.09).
    for _знак, число, итог in _МОДУЛЬ.findall(с):
        if int(число) != int(итог):
            return True, False
    for a, b in _РАВНЫ.findall(с):
        if int(a) != int(b):
            return True, False
    for a, b, c in _МОДУЛЬ_СУММЫ.findall(с):
        if abs(int(b) - int(a)) != int(c):
            return True, False
    for a, b, s in _СУММА_МОДУЛЕЙ.findall(с):
        if int(a) + int(b) != int(s):
            return True, False
    # ЛОВУШКА ОБЯЗАНА ЛОВИТЬ: модуль суммы и сумма модулей на странице обязаны РАЗОЙТИСЬ.
    пары = _МОДУЛЬ_СУММЫ.findall(с)
    суммы = _СУММА_МОДУЛЕЙ.findall(с)
    if пары and суммы and int(пары[0][2]) == int(суммы[0][2]):
        return True, False
    for a, b in _МЕНЬШЕ_ОТР.findall(с):
        if int(a) <= int(b):
            return True, False
    for a, b in _БОЛЬШЕ_МОД.findall(с):
        if int(a) <= int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:86]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    мс = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "модуль суммы")
    рс = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "расстояние")
    for страница, слово, куда in ((мс, "модулей", "модуле"), (рс, "нуля", "нул")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(мс + " " + мс)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ДЕФИС ВМЕСТО ЗНАКА МИНУС ЕСТЬ ЧУЖАЯ ЗАПИСЬ В ЗНАКОВОЙ ОБЛАСТИ.
    if any("-" in с for с in ПОКАЗЫ):
        беды.append("ДЕФИС В ПОКАЗЕ: дом обязан писать знаком минус U+2212")
    # СЧЁТНАЯ ФОРМА ПРИ ЧИСЛЕ БЕРЁТСЯ У ЯЗЫКА: «1 шаг», «2 шага», «5 шагов».
    if not any(с.endswith("1 шаг, и от 1 до нуля столько же.") for с in ПОКАЗЫ):
        беды.append("СЧЁТНАЯ ФОРМА НЕ СОГЛАСОВАНА при единице")
    print(f"МОДУЛЬ ЧИСЛА: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
