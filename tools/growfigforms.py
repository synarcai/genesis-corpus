    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ТАБЛИЦЫ ОБЯЗАНЫ БЫТЬ ТЕМ, ЧЕМ НАЗВАНЫ.
    for a, k in РОСТ:
        if k < 2:
            беды.append(f"рост меньше двух, разницы не видно: {(a, k)}")
    for (a1, b1), (a2, b2) in ОДИН_ПЕРИМЕТР:
        if a1 + b1 != a2 + b2:
            беды.append(f"периметры разны, а пара лежит в равнопериметрных: {(a1, b1, a2, b2)}")
        if a1 * b1 == a2 * b2:
            беды.append(f"площади равны — ловушка не видна: {(a1, b1, a2, b2)}")
    for (a1, b1), (a2, b2) in ОДНА_ПЛОЩАДЬ:
        if a1 * b1 != a2 * b2:
            беды.append(f"площади разны, а пара лежит в равноплощадных: {(a1, b1, a2, b2)}")
        if a1 + b1 == a2 + b2:
            беды.append(f"периметры равны — ловушка не видна: {(a1, b1, a2, b2)}")
    # ПЕРЕБОР ОБЯЗАН БЫТЬ ПОЛОН И ОБЯЗАН ДАВАТЬ КВАДРАТ НАИБОЛЬШИМ.
    for h in ПОЛУПЕРИМЕТРЫ:
        ряд = _перебор(h)
        if h % 2:
            беды.append(f"полупериметр нечётен, квадрата не выйдет: {h}")
        if len(ряд) != h // 2:
            беды.append(f"перебор неполон при {h}: {len(ряд)} вместо {h // 2}")
        лучший = max(ряд, key=lambda т: т[2])
        if лучший[0] != лучший[1]:
            беды.append(f"наибольшую площадь дал не квадрат: {лучший} при {h}")
        for a, b, s in ряд:
            if a + b != h or a * b != s:
                беды.append(f"перебор лжёт: {(a, b, s)} при {h}")
    # ОБЕ СТОРОНЫ ЛОВУШКИ ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ.
    for язык in ЯЗЫКИ:
        if not (по_роду.get((язык, "сторона и площадь"))
                and по_роду.get((язык, "сторона и периметр"))):
            беды.append(f"показана лишь одна сторона ловушки [{язык}]")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ, ГДЕ ЕСТЬ ЗАПИСЬ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    пл = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "сторона и площадь")
    порча = пл.replace("КВАДРАТ", "КВАДРА", 1)
    if порча == пл:
        беды.append("порча не состоялась: нет слова «КВАДРАТ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(пл + " " + пл)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"РОСТ ФИГУРЫ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


