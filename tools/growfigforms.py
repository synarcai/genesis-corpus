def _перебор(полупериметр):
    """[(a, b, площадь)] — все целые прямоугольники этого полупериметра, по возрастанию a."""
    return [(a, полупериметр - a, a * (полупериметр - a))
            for a in range(1, полупериметр // 2 + 1)]


