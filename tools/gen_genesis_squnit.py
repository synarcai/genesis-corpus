#!/usr/bin/env python3
"""GENESIS layer: КВАДРАТНЫЕ И КУБИЧЕСКИЕ ЕДИНИЦЫ — see tools/squnitforms.py for the law.

ОБЕ СТОРОНЫ ЛОВУШКИ ИДУТ ОДНОЙ ГРУППОЙ. Простой множитель верен на длине и ложен на
площади; показанный порознь, он учит одному из двух — и ошибается на всём остальном.

    МНОЖИТЕЛЬ ЕСТЬ ОДИН И ТОТ ЖЕ; В СТЕПЕНЬ ЕГО ВОЗВОДИТ НЕ ЕДИНИЦА, А РАЗМЕРНОСТЬ.

ТРИ СТЕПЕНИ — ОДНОЙ ГРУППОЙ: длина, площадь и объём суть один закон при первой, второй и
третьей степени, и врозь они читались бы как три правила. ПОЧЕМУ ТАК — отдельно: счёт
клеток есть основание, а не ещё один случай. ВОПРОС отдельно.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import squnitforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_squnit.txt"
ГРУППЫ = (("длина прямо", "площадь в квадрате", "объём в кубе"),
          ("множитель длины ложен", "множитель длины верен"),
          ("почему так", "дорога обратно"),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
