# СВЕРКА

def цитата_в_теле(цитата, тело):
    """Стоит ли цитата в теле подстрокой — после нормализации пробелов.

    ПЕРВАЯ БУКВА ВОЛЬНА В РЕГИСТРЕ, И ТОЛЬКО ОНА: словарь начинает
    толкование с заглавной («A certain property of a body…»), показ
    ставит его после связки строчной («entropy is a certain property…»).
    Это свойство вёрстки, а не толкования; всякое иное расхождение —
    порча цитаты.
    """
    ц, т = норма(цитата), норма(тело)
    if not ц:
        return False
    варианты = {ц, ц[0].upper() + ц[1:], ц[0].lower() + ц[1:]}
    return any(в in т for в in варианты)


def понятие_в_заголовке(понятие, заголовок):
    """Слово-понятие стоит в заголовке статьи целым словом."""
    свои = слова(понятие)
    return bool(свои) and all(w in слова(заголовок) for w in свои)
