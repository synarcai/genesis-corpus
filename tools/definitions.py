#!/usr/bin/env python3
"""ДОМ ОПРЕДЕЛЕНИЙ — словари полки как источник дословных цитат.

Заказ holon (02.09): организм молчит на «what is entropy» и «что такое
сознание», потому что в своде нет ни одной строки-определения. Мир
определений (tools/gen_genesis_definitions.py) отвечает на это строкой
«понятие — это <цитата>: <источник>», и цитата в ней НЕ ПИШЕТСЯ РУКОЙ:
она берётся дословно из словаря, лежащего на полке корпуса, и суд
(courts/definitions_court.py) находит её там снова.

ЗАКОН ДОМА: суд делит с генератором ОПРЕДЕЛЕНИЕ, но не ВЫВОД. Здесь
живёт то, что обоим надо понимать одинаково — какие словари полки суть
источники, чем источник называется в показе, как файл словаря режется
на статьи (заголовок и тело) и как текст приводится к виду, в котором
подстрока ищется. Какую именно фразу статьи взять в цитату, решает
генератор своими правилами отбора; суд этих правил не знает и знать
не должен — он проверяет три вещи, и все три без вывода: источник
объявлен на полке (манифест), цитата стоит в теле статьи подстрокой,
слово-понятие стоит в заголовке этой статьи.

ТРИ СЛОВАРЯ, ТРИ РАЗРЕЗА. Webster 1913 (Gutenberg) идёт статьями в
несколько строк: заголовок капсом на своей строке, ниже слово с
ударениями, ниже толкования «Defn:» или нумерованные. ЭСБЕ и Даль
(Викитека, скан) идут статьёй в одну строку: заголовок капсом в начале,
тело при нём. Разрез каждого объявлен здесь, и он один у обоих
читателей.

ПОЛКА — ЭТО МАНИФЕСТ, А НЕ КАТАЛОГ. Файл словаря есть источник лишь
тогда, когда манифест объявляет мир с этим `file`; отложенная часть
(`held_out`) источником не является никогда, и дом её не читает. Год
издания берётся из объявления мира (`издано`), и ярлык показа несёт
именно его — суд сверяет ярлык с манифестом, а не с памятью.
"""

import collections
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import genesis  # noqa: E402

Статья = collections.namedtuple("Статья", "заголовок тело")
# тело: абзацы через «\n», пробелы внутри абзаца схлопнуты; полная
# нормализация (все пробелы в один) делается функцией норма() при сверке.


def норма(текст):
    """Пробелы схлопнуты: подстрока ищется в этом виде и только в нём."""
    return " ".join(текст.split())


def слова(текст):
    """Слова текста в нижнем регистре — ими проверяется заголовок."""
    return re.findall(r"[^\W\d_]+", текст.casefold())


# ---------------------------------------------------------------------------
# РАЗРЕЗЫ

# Webster: заголовок — строка из заглавных латинских букв (с цифрой,
# апострофом, дефисом, точкой, запятой и «;» у двойных заголовков вроде
# «COHERENCE; COHERENCY»), стоящая после пустой строки и перед непустой.
ЗАГ_EN = re.compile(r"^[A-Z][A-Z0-9' .,;-]*$")


def статьи_вебстера(текст):
    строки = текст.split("\n")
    n = len(строки)

    def заголовок(i):
        return (ЗАГ_EN.match(строки[i]) is not None
                and (i == 0 or not строки[i - 1].strip())
                and i + 1 < n and bool(строки[i + 1].strip()))

    i = 0
    while i < n:
        if not заголовок(i):
            i += 1
            continue
        j = i + 1
        абзацы, тек = [], []
        while j < n and not заголовок(j):
            т = строки[j].strip()
            if т:
                тек.append(т)
            elif тек:
                абзацы.append(" ".join(тек))
                тек = []
            j += 1
        if тек:
            абзацы.append(" ".join(тек))
        yield Статья(строки[i].strip(), "\n".join(абзацы))
        i = j


# ЭСБЕ: «СИЛА, в механике Сила (la force, die Kraft, механ.). — С.
# называется причина…» — заголовок капсом (с уточнением строчными),
# тело начинается ПОВТОРОМ заглавного слова в обычном регистре.
КАПС_RU = re.compile(r"^([А-ЯЁ][А-ЯЁ-]+)")


def статьи_эсбе(текст):
    for с in текст.splitlines():
        м = КАПС_RU.match(с)
        if not м:
            continue
        слово = м.group(1)
        титул = слово[0] + слово[1:].lower()
        k = с.find(" " + титул, len(слово))
        if k < 0:
            заг, тело = слово, с[len(слово):]
        else:
            заг, тело = с[:k], с[k + 1:]
        yield Статья(норма(заг), норма(тело))


# Даль: «ПАМЯТЬ Память ж. (мнить, мнети) способность помнить…» —
# заголовок капсом (омонимы с номером: «ДУША 2»), тело при нём.
ЗАГ_ДАЛЬ = re.compile(r"^([А-ЯЁ][А-ЯЁ-]+)(?:\s+\d+)?")


def статьи_даля(текст):
    for с in текст.splitlines():
        м = ЗАГ_ДАЛЬ.match(с)
        if not м:
            continue
        yield Статья(норма(м.group(0)), норма(с[м.end():]))


# ---------------------------------------------------------------------------
# ИСТОЧНИКИ

Источник = collections.namedtuple("Источник", "имя язык файлы разбор")

ИСТОЧНИКИ = {
    "webster": Источник("webster", "en", ("shelf/en/webster_1913.txt",),
                        статьи_вебстера),
    "esbe": Источник("esbe", "ru", tuple(
        f"shelf/ru/esbe_{т}_ru.txt"
        for т in ("math", "nature", "logic", "language", "method", "technics")),
        статьи_эсбе),
    "dal": Источник("dal", "ru", ("shelf/ru/dal_1880.txt",), статьи_даля),
}

# ЯРЛЫК ИСТОЧНИКА В ПОКАЗЕ — основание после двоеточия. У словарей с
# одним заголовком на понятие (Webster, Даль) статья не называется:
# её называет само понятие; у ЭСБЕ заголовок несёт уточнение («Сила,
# в механике»), и он пишется в ярлык.
ЯРЛЫКИ = {
    "webster": re.compile(r"^Webster's Unabridged Dictionary, (\d{4})$"),
    "dal": re.compile(r"^Толковый словарь Даля, (\d{4})$"),
    "esbe": re.compile(r"^ЭСБЕ, статья «([^«»]+)»$"),
}


def _миры():
    try:
        return genesis.manifest()["worlds"]
    except (genesis.Unreadable, KeyError):
        return []


def объявленные_файлы(источник):
    """Файлы источника, объявленные манифестом И лежащие на полке.

    Источник, не объявленный, на полке НЕ ЛЕЖИТ, сколько бы байтов ни
    было в каталоге: полка есть договор, и договор читается из манифеста.
    """
    объявлено = {м.get("file") for м in _миры()}
    return tuple(ф for ф in источник.файлы
                 if ф in объявлено and (КОРЕНЬ / ф).is_file())


def год(источник):
    """Год издания из объявления мира полки (`издано`), или None."""
    for м in _миры():
        if м.get("file") in источник.файлы and isinstance(м.get("издано"), int):
            return м["издано"]
    return None


def титул(заголовок):
    """Заголовок ЭСБЕ в обычном регистре: «СИЛА, в механике» → «Сила, в механике»."""
    return re.sub(r"^([А-ЯЁ])([А-ЯЁ-]+)",
                  lambda м: м.group(1) + м.group(2).lower(), заголовок)


def ярлык(источник, статья=None):
    """Ярлык источника для показа; None, если источник не объявлен."""
    if источник.имя == "esbe":
        return f"ЭСБЕ, статья «{титул(статья.заголовок)}»" if статья else None
    г = год(источник)
    if г is None:
        return None
    if источник.имя == "webster":
        return f"Webster's Unabridged Dictionary, {г}"
    return f"Толковый словарь Даля, {г}"


class Словарь:
    """Статьи одного источника, разрезанные один раз и найденные по слову."""

    def __init__(self, источник):
        self.источник = источник
        self._статьи = None
        self._по_слову = None
        self._по_заголовку = None

    def статьи(self):
        if self._статьи is None:
            вон = []
            for ф in объявленные_файлы(self.источник):
                текст = (КОРЕНЬ / ф).read_text(encoding="utf-8", errors="replace")
                вон.extend((ф, с) for с in self.источник.разбор(текст))
            self._статьи = вон
            self._по_слову = collections.defaultdict(list)
            self._по_заголовку = collections.defaultdict(list)
            for ф, с in вон:
                self._по_заголовку[норма(с.заголовок).casefold()].append((ф, с))
                for w in set(слова(с.заголовок)):
                    self._по_слову[w].append((ф, с))
        return self._статьи

    def по_слову(self, слово):
        """[(файл, статья)] — статьи, в чьём заголовке стоит слово."""
        self.статьи()
        return list(self._по_слову.get(слово.casefold(), ()))

    def по_заголовку(self, заголовок):
        """[(файл, статья)] — статьи с этим заголовком (регистр не важен)."""
        self.статьи()
        return list(self._по_заголовку.get(норма(заголовок).casefold(), ()))


_СЛОВАРИ = {}


def словарь(имя):
    """Один разрез на процесс: словари тяжелы (26 МБ у Webster)."""
    if имя not in _СЛОВАРИ:
        _СЛОВАРИ[имя] = Словарь(ИСТОЧНИКИ[имя])
    return _СЛОВАРИ[имя]


