def отказ_длины(шаг):
    """Вопрос, чей честный ответ — «целого нет, и вот почему».

    ДЛИНА ВЕКТОРА ЕСТЬ КОРЕНЬ, И КОРЕНЬ РЕДКО ЦЕЛ. Мир пишет длину
    только на точных тройках — таков его объявленный закон, — и отказ
    называет ОСНОВАНИЕ числом: сумму квадратов и то, что она не полный
    квадрат. Суд пересчитывает оба.
    """
    вон = []
    for i in range(16):
        a = 2 + (шаг + i) % 9
        b = a + 1 + (шаг * 3 + i) % 7
        # WHOLENESS IS A YES/NO QUESTION (holon 03.09, value-not-verdict: a
        # question for a VALUE answered by a refusal looked like a verdict
        # frame with one polarity). The value question keeps its value
        # answers; wholeness is asked as its own question, and both answers
        # lie side by side — «yes» with the whole value, «no» with the reason.
        if i % 3 == 0:
            a, b = ТОЧНЫЕ_КАТЕТЫ[(шаг + i) % len(ТОЧНЫЕ_КАТЕТЫ)]
        с = a * a + b * b
        if полный_квадрат(с):
            c = math.isqrt(с)
            вон.append(спросить("whole_length", f"the vector ({a}, {b})",
                                f"yes: {a}^2 + {b}^2 = {с} = {c}^2, the length is {c}."))
            вон.append(спросить("целая_длина", f"вектора ({a}, {b})",
                                f"да: {a}^2 + {b}^2 = {с} = {c}^2, длина равна {c}."))
        else:
            вон.append(спросить("whole_length", f"the vector ({a}, {b})",
                                f"no: {a}^2 + {b}^2 = {с}, and {с} is not a perfect square."))
            вон.append(спросить("целая_длина", f"вектора ({a}, {b})",
                                f"нет: {a}^2 + {b}^2 = {с}, а {с} не полный квадрат."))
    return вон


def произведения(шаг):
    вон = []
    for i in range(24):
        a, b = 1 + (i % 6) + шаг, 2 + (i % 5)
        c, d = 3 + (i % 4), 1 + (i % 7)
        пред_en = f"({a}, {b}) and ({c}, {d})"
        пред_ru = f"({a}, {b}) и ({c}, {d})"
        цепь = f"{a} × {c} = {a * c}, {b} × {d} = {b * d}, {a * c} + {b * d} = {a * c + b * d}"
        утв_en = f"the dot product of {пред_en} is {a * c + b * d}: {цепь}."
        утв_ru = (f"скалярное произведение {пред_ru} равно "
                  f"{a * c + b * d}: {цепь}.")
        вон.append(утв_en)
        вон.append(утв_ru)
        вон.append(спросить("dot", пред_en, утв_en))
        вон.append(спросить("скалярное", пред_ru, утв_ru))
