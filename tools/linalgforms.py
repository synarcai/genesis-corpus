            # КОРЕНЬ — НЕ ЗАКОН ОСИ (e9): квадрат длины показан звеньями, корень — проверкой «c × c».
            цепь = f"{x} × {x} = {x * x}, {y} × {y} = {y * y}, {x * x} + {y * y} = {c * c}, {c} × {c} = {c * c}"
