def делители(n):
    """Все делители числа по возрастанию — перебором до корня, без таблиц."""
    вон = set()
    k = 1
    while k * k <= n:
        if n % k == 0:
            вон.add(k)
            вон.add(n // k)
        k += 1
    return sorted(вон)


