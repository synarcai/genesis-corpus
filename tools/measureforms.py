# РАВЕНСТВО ЗДЕСЬ ХОДИТ ЦЕПЬЮ, А НЕ ПАРОЙ: «36 = 12 × 3 = 18 × 2» есть ОДНО
# утверждение о трёх звеньях. Первая мера читала пары и на этой же строке нашла
# «12 × 3 = 18» — ложь, которой в строке нет:
#
#     ПРИЗНАК, ЧИТАЮЩИЙ ПАРАМИ ТО, ЧТО ПИСАНО ЦЕПЬЮ, НАХОДИТ ЛОЖЬ В МЕСТЕ СКЛЕЙКИ
#     ДВУХ ИСТИН.
#
# Потому цепь берётся целиком, и всякое её звено считается своим делом.
_ЗВЕНО = r"\d+(?:\s[×÷]\s\d+)?"
# ХВОСТ ЦЕПИ СТЕРЕЖЁТСЯ ТРЕМЯ ЗНАКАМИ, А НЕ ОДНИМ. Первая правка запретила лишь
# «+», и признак, отступив, прочёл в «18 = 12 × 1 + 6» короткую цепь «18 = 12»:
#
#     ЗАПРЕТ, СНЯТЫЙ ОТСТУПЛЕНИЕМ, НЕ ЕСТЬ ЗАПРЕТ: признак, которому нельзя взять
#     ЦЕЛОЕ, возьмёт ЧАСТЬ и назовёт её ложью.
_ЦЕПЬ = re.compile(rf"(?<![×÷]\s)(?<![\d/])({_ЗВЕНО}(?:\s=\s{_ЗВЕНО})+)"
                   rf"(?!\s[+×÷]\s\d)(?![\d/])")
_С_ОСТАТКОМ = re.compile(r"(?<![\d/])(\d+) = (\d+) × (\d+) \+ (\d+)(?![\d/])")


def _цена(звено):
    """Число звена цепи: одно число, произведение или частное."""
    m = re.fullmatch(r"(\d+)(?:\s([×÷])\s(\d+))?", звено)
    a = int(m.group(1))
    if not m.group(2):
        return a
    b = int(m.group(3))
    if m.group(2) == "×":
        return a * b
    return None if b == 0 or a % b else a // b


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка
    И ЕСЛИ ВСЯКОЕ РАВЕНСТВО В НЕЙ ПЕРЕСЧИТЫВАЕТСЯ.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цепь in _ЦЕПЬ.findall(с):
        цены = [_цена(з) for з in цепь.split(" = ")]
        if None in цены or len(set(цены)) != 1:
            return True, False
    for целое, дел, ч, ост in _С_ОСТАТКОМ.findall(с):
        if int(дел) * int(ч) + int(ост) != int(целое) or not 0 < int(ост) < int(дел):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ТАБЛИЦЫ ОБЯЗАНЫ БЫТЬ ТЕМ, ЧЕМ НАЗВАНЫ, — ИНАЧЕ ЛОВУШКА ПОКАЗАНА НЕ ТА.
    for a, b in ОБЩИЕ:
        d = math.gcd(a, b)
        if not a < b:
            беды.append(f"порядок пары нарушен: {a}, {b}")
        if d == 1:
            беды.append(f"пара взаимно проста, а лежит в общих: {a}, {b}")
        if b % a == 0:
            беды.append(f"меньшее делит большее, а пара лежит в общих: {a}, {b}")
        if d == a:
            беды.append(f"мера равна меньшему, ловушка не видна: {a}, {b}")
    for a, b in ДЕЛИТ:
        if b % a:
            беды.append(f"меньшее не делит большего, а пара лежит в делящих: {a}, {b}")
        if math.gcd(a, b) != a:
            беды.append(f"мера не равна меньшему в делящей паре: {a}, {b}")
    for a, b in ВЗАИМНЫЕ:
        if math.gcd(a, b) != 1:
            беды.append(f"пара не взаимно проста, а лежит во взаимных: {a}, {b}")
    # ОБЕ СТОРОНЫ ОБЕИХ ЛОВУШЕК ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ.
    for одна, друга in (("меньшее не есть мера", "меньшее и есть мера"),
                        ("кратное меньше произведения", "кратное и есть произведение")):
        for язык in ЯЗЫКИ:
            if not (по_роду.get((язык, одна)) and по_роду.get((язык, друга))):
                беды.append(f"показана лишь одна сторона ловушки [{язык}]: {одна} / {друга}")
    # ДЕЛИТЕЛИ СЧИТАЮТСЯ ПЕРЕБОРОМ, И ЭТО ПРОВЕРЯЕТСЯ НА ЗАВЕДОМО ИЗВЕСТНОМ.
    for n, ждём in ((1, [1]), (6, [1, 2, 3, 6]), (7, [1, 7]), (36, [1, 2, 3, 4, 6, 9, 12, 18, 36])):
        if делители(n) != ждём:
            беды.append(f"делители {n}: {делители(n)} вместо {ждём}")
    # ЗАКОН ПРОИЗВЕДЕНИЯ ОБЯЗАН ДЕРЖАТЬСЯ НА ВСЕХ ТРЁХ ТАБЛИЦАХ, А НЕ ЛИШЬ НА ПОКАЗАННЫХ.
    for a, b in ОБЩИЕ + ДЕЛИТ + ВЗАИМНЫЕ:
        о = _общее(a, b)
        if о["d"] * о["l"] != a * b:
            беды.append(f"закон произведения не держится: {a}, {b}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    мера = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "все общие делители")
    порча = мера.replace("НАИБОЛЬШИЙ", "НАИБОЛЬШИ", 1)
    if порча == мера:
        беды.append("порча не состоялась: нет слова «НАИБОЛЬШИЙ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
