import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётные формы вещей объявлены там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("вверх", "вниз", "без остатка", "два ответа")

ВЕЩИ = ("книга", "карандаш", "конфета", "яблоко")
АНГЛ = {"книга": ("book", "books"), "карандаш": ("pencil", "pencils"),
        "конфета": ("sweet", "sweets"), "яблоко": ("apple", "apples"),
        "коробка": ("box", "boxes")}


def форма(язык, ключ, n):
    if язык == "en":
        один, много = АНГЛ[ключ]
        return один if n == 1 else много
    return rugram.форма(ключ, n)


РАМКИ = {
    "ru": {
        "вверх": "{n} {вещь_n} кладут по {m} в коробку; чтобы уместились все, нужно {q1} "
                 "{короб_q1}, ибо {n} ÷ {m} даёт {q} и остаток {r}: {m} × {q} = {p}, "
                 "и {p} + {r} = {n}.",
        "вниз": "{n} {вещь_n} кладут по {m} в коробку; доверху наполнится {q} {короб_q}, "
                "а {r} {вещь_r} останется: {m} × {q} = {p}, и {p} + {r} = {n}.",
        "без остатка": "{n} {вещь_n} кладут по {m} в коробку; и нужно {q} {короб_q}, "
                       "и наполнится {q} {короб_q}, ибо остатка нет: {m} × {q} = {n}.",
        "два ответа": "одно деление, два вопроса: {n} ÷ {m} даёт {q} и остаток {r}; чтобы "
                      "уместились все — {q1} {короб_q1}, а доверху наполнится {q} {короб_q}: "
                      "{q1} − {q} = 1.",
    },
    "en": {
        "вверх": "{n} {вещь_n} are put {m} to a box; to fit them all one needs {q1} {короб_q1}, "
                 "for {n} ÷ {m} gives {q} and a remainder of {r}: {m} × {q} = {p}, "
                 "and {p} + {r} = {n}.",
        "вниз": "{n} {вещь_n} are put {m} to a box; {q} {короб_q} will be filled to the top, "
                "and {r} {вещь_r} will be left over: {m} × {q} = {p}, and {p} + {r} = {n}.",
        "без остатка": "{n} {вещь_n} are put {m} to a box; one needs {q} {короб_q}, and {q} "
                       "{короб_q} will be filled, for there is no remainder: {m} × {q} = {n}.",
        "два ответа": "one division, two questions: {n} ÷ {m} gives {q} and a remainder of {r}; "
                      "to fit them all — {q1} {короб_q1}, and filled to the top {q} {короб_q}: "
                      "{q1} − {q} = 1.",
    },
}
ПУСТО = dict(n=0, m=0, q=0, q1=0, r=0, p=0,
             вещь_n="", вещь_r="", короб_q="", короб_q1="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for вещь in ВЕЩИ:
            for m in range(3, 11):
                for q in range(2, 9):
                    # БЕЗ ОСТАТКА — УПРАВА, И ОНА КУЁТСЯ НА ТЕХ ЖЕ ЧИСЛАХ, что и ловушка:
                    # разные числа развели бы правило и его исключение по разным задачам.
                    n0 = m * q
                    общ0 = dict(ПУСТО, n=n0, m=m, q=q, вещь_n=форма(язык, вещь, n0),
                                короб_q=форма(язык, "коробка", q))
                    if (m + q + len(вещь)) % 3 == 0:
                        вон[рамки["без остатка"].format(**общ0)] = (язык, "без остатка")
                    for r in range(1, m):
                        if (m * q + r + len(вещь)) % 7:
                            continue
                        n = m * q + r
                        общ = dict(ПУСТО, n=n, m=m, q=q, q1=q + 1, r=r, p=m * q,
                                   вещь_n=форма(язык, вещь, n), вещь_r=форма(язык, вещь, r),
                                   короб_q=форма(язык, "коробка", q),
                                   короб_q1=форма(язык, "коробка", q + 1))
                        for род in ("вверх", "вниз", "два ответа"):
                            вон[рамки[род].format(**общ)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА = re.compile(r"(?<![/\d])(\d+) \+ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (\d+)(?![/\d])")
_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
# ЧАСТНОЕ С ОСТАТКОМ — «N ÷ M даёт Q и остаток R», на обоих языках.
_С_ОСТАТКОМ = re.compile(
    r"(\d+) ÷ (\d+) (?:даёт (\d+) и остаток (\d+)|gives (\d+) and a remainder of (\d+))")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for n, m, q_ru, r_ru, q_en, r_en in _С_ОСТАТКОМ.findall(с):
        q, r = int(q_ru or q_en), int(r_ru or r_en)
        n, m = int(n), int(m)
        # ОСТАТОК ОБЯЗАН БЫТЬ МЕНЬШЕ ДЕЛИТЕЛЯ, иначе деление не доведено до конца.
        if m * q + r != n or not 0 <= r < m:
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    вв = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "вверх")
    дв = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "два ответа")
    for страница, слово, куда in ((вв, "нужно", "нужн"), (дв, "вопроса", "вопрос")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(вв + " " + вв)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ДВА ОТВЕТА РАСХОДЯТСЯ РОВНО НА ЕДИНИЦУ, И ЭТО ПРОВЕРЯЕТСЯ ПО ВСЕМ СТРАНИЦАМ РОДА.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "два ответа":
            continue
        пары = _РАЗНОСТЬ.findall(с)
        if len(пары) != 1 or int(пары[0][0]) - int(пары[0][1]) != 1:
            беды.append(f"расхождение не единица: {с[:80]}")
            break
    # УПРАВА СТОИ́Т НА ТЕХ ЖЕ ДЕЛИТЕЛЯХ, что и ловушка: иначе правило и исключение о разном.
    дел_ловушки = {int(_ПРОИЗВ.findall(с)[0][0]) for с, (я, р) in ПОКАЗЫ.items()
                   if я == "ru" and р == "вниз"}
    дел_управы = {int(_ПРОИЗВ.findall(с)[0][0]) for с, (я, р) in ПОКАЗЫ.items()
                  if я == "ru" and р == "без остатка"}
    if not дел_управы or not дел_управы <= дел_ловушки:
        беды.append(f"управа на чужих делителях: {sorted(дел_управы - дел_ловушки)}")
    print(f"ДВА ОТВЕТА ОДНОГО ДЕЛЕНИЯ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, "
          f"бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
