ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА = re.compile(r"(?<![\d/])(\d+) \+ (\d+) = (\d+)(?![\d/])")
_ПРОИЗВ = re.compile(r"(?<![\d/])(\d+) × (\d+) = (\d+)(?![\d/])")
_ДЕЛЕНИЕ = re.compile(r"(?<![\d/])(\d+) ÷ (\d+) = (\d+)(?![\d/])")
_БОЛЬШЕ = re.compile(r"(?<![\d/])(\d+) больше (\d+)(?![\d/])"
                     r"|(?<![\d/])(\d+) is greater than (\d+)(?![\d/])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, r in _СУММА.findall(с):
        if int(a) + int(b) != int(r):
            return True, False
    for a, b, r in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(r):
            return True, False
    for a, b, r in _ДЕЛЕНИЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(r):
            return True, False
    for ру1, ру2, ан1, ан2 in _БОЛЬШЕ.findall(с):
        if int(ру1 or ан1) <= int(ру2 or ан2):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ЕДИНИЦЫ ОБЯЗАНЫ МЕРЯТЬ РАЗНОЕ: дом, взявший две единицы одной меры, показал бы
    # ОТКАЗ там, где сложение законно.
    меры = [что for _ру, _ан, что, _ч2 in ЕДИНИЦЫ]
    if len(set(меры)) != len(меры):
        беды.append(f"две единицы мерят одно: {меры}")
    # ЧАСТНОЕ ОБЯЗАНО БЫТЬ ЦЕЛЫМ — дом целых чисел не вправе выдать дробь.
    for a, _е1, b, _е2, *_ in ЧАСТНЫЕ:
        if b == 0 or a % b:
            беды.append(f"частное не целое: {a}/{b}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    от = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "отказ разнородному")
    порча = от.replace("НЕЛЬЗЯ", "НЕЛЬЗ", 1)
    if порча == от:
        беды.append("порча не состоялась: нет слова «НЕЛЬЗЯ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(от + " " + от)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"РАЗМЕРНОСТЬ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


