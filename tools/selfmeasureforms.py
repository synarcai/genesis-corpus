def отказы(шаг):
    """ОТКАЗ О БУДУЩЕМ, И ЕГО ОСНОВАНИЕ ТОЖЕ ПЕРЕСЧИТЫВАЕТСЯ.

    Организм, умеющий отказать в вопросе о себе, не научится хвастать.
    Основание отказа не «я не хочу», а факт о таблице снимков: замеры
    есть по названный день и НЕТ НИ ОДНОГО позже. Суд сверяется с той
    же таблицей.
    """
    вон = []
    for прибор, что, _взято, _всего in ПОСЛЕДНИЙ_СНИМОК:
        # ОТКАЗ СКАЗАН ФОРМОЙ, КАКУЮ ОБЪЯВЛЯЕТ ДОМ: отрицание сущего,
        # двоеточие, основание (`tools/manifest_kinds.отказов`). И он
        # точнее «не знаю»: отказывает не незнание, а ОТСУТСТВИЕ
        # ЗАМЕРА — то есть проверяемый факт о таблице снимков.
        вон.append(f"сколько {СЧЁТНЫЕ[что][2]} насчитает у меня "
                   f"прибор {прибор} завтра? нет такого замера: у "
                   f"прибора {прибор} есть замеры по {ПОСЛЕДНИЙ_ДЕНЬ} и ни "
                   f"одного позже.")
    return вон

ГРУППЫ = (состояние, граница, нужда, рост, несравнимость, вопросы,
          отказы)


def группы(шаг):
    """[[страница]] — ровно те группы и в том порядке, какими кузница кормит `emit_grouped`."""
    return [сделать(шаг) for сделать in ГРУППЫ]


def перебор(шаг):
    """[(страница, род)] — те же группы, но каждая под своим именем."""
    вон = []
    for род, группа in zip(РОДЫ, группы(шаг)):
        for с in группа:
            вон.append((с, род))
    return вон


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            вон.setdefault(с, род)
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, а не с кортежем."""
    имена = tuple(с.__name__ for с in ГРУППЫ)
    assert имена == РОДЫ, f"кортеж {имена} разошёлся с объявлением {РОДЫ}"
    сколько = len(группы(0))
    assert сколько == len(РОДЫ), f"проход даёт {сколько} групп при {len(РОДЫ)} родах"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка()
