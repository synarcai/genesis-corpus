def рост(шаг):
    """РОСТ ЕСТЬ РАЗНОСТЬ ДВУХ ЗАМЕРОВ, И ОБЕ ЧАСТИ НАЗВАНЫ.

    Здесь и стоит самая соблазнительная ложь мира о себе: сказать «я
    вырос», назвав прибавку взятого и умолчав, что выросло и целое.
    Показ называет обе прибавки, и суд пересчитывает обе: рост
    числителя не есть рост доли.
    """
    вон = []
    for _и1, _и2, _д1, _д2, (прибор, что, было, было_всего), (
            _п, _ч, стало, стало_всего), п1, п2 in _соседние():
        if п1 != п2:
            continue                      # не рост, а разница приборов: см. род `несравнимость`
        прибавка = стало - было
        прибавка_всего = стало_всего - было_всего
        # ЧЕСТНЫЙ НУЛЬ НАЗЫВАЕТСЯ НУЛЁМ, А УБЫЛЬ — УБЫЛЬЮ. «названо стало больше на −390»
        # есть оборот, учащий читать минус как прибавку; а
        #
        #     РОСТ ЧИСЛИТЕЛЯ ПРИ УБЫВШЕМ ЗНАМЕНАТЕЛЕ ЕСТЬ ДВА СОБЫТИЯ, А НЕ ОДНО,
        #
        # и оба обязаны быть названы своими словами. Третий замер это и принёс: у
        # `biblio_reach` взятое выросло 62 → 135, а названное УБЫЛО 2074 → 1684.
        if прибавка_всего == 0:
            хвост = (f"а названо не изменилось, ибо {стало_всего} − "
                     f"{было_всего} = 0")
        elif прибавка_всего < 0:
            хвост = (f"а названо стало МЕНЬШЕ на {-прибавка_всего}, ибо "
                     f"{было_всего} − {стало_всего} = {-прибавка_всего}")
        else:
            хвост = (f"но и названо стало больше на {прибавка_всего}, ибо "
                     f"{стало_всего} − {было_всего} = {прибавка_всего}")
        вон.append(f"прибор {прибор} насчитал у меня {было} "
                   f"{счётная(что, было)} {_и1} {_д1} и {стало} {_и2} "
                   f"{_д2}: прибавилось {прибавка}, ибо {стало} − "
                   f"{было} = {прибавка}; {хвост}.")
    return вон


def несравнимость(шаг):
    """ОТКАЗ ВЫЧЕСТЬ, И ОСНОВАНИЕ ЕГО — ПОДПИСЬ ПРИБОРА.

    Самая складная ложь мира о себе — не «я вырос», а «я вырос на столько-то», сказанное о
    двух числах, снятых РАЗНЫМИ приборами: вычитание верно, утверждение ложно.

        ЧИСЛО, СНЯТОЕ ДРУГИМ ПРИБОРОМ, ЕСТЬ ЧИСЛО О ДРУГОМ ПРЕДМЕТЕ.

    Отказ называет ОБЕ подписи — проверяемый факт о файлах, а не «я не уверен».
    """
    вон = []
    for имя1, имя2, _д1, _д2, (прибор, что, _в1, _вс1), _б, п1, п2 in _соседние():
        if п1 == п2:
            continue
        вон.append(f"на сколько {СЧЁТНЫЕ[что][1]} прибавилось у меня по прибору "
                   f"{прибор} между тем, что было {имя1}, и тем, что стало {имя2}? "
                   f"нет такого числа: {имя1} прибор был {п1}, {имя2} — {п2}, и "
                   f"разность их чисел есть разница приборов, а не рост.")
    return вон


