#!/usr/bin/env python3
"""ДОМ САМОИЗМЕРЕНИЯ — состояние, граница, нужда, рост.

Организм, умеющий сказать о СЕБЕ: сколько есть, где предел, чего недостаёт и насколько
выросло. Четыре разных вопроса, и ни один не выводится из прочих.

6 родов объявлены не здесь: их назвала СВОЯ ЖЕ КУЗНИЦА кортежем `ГРУППЫ`.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

Читателей пятого рода у этого мира нет: карта (13.09) спрошена ПРЕЖДЕ переезда, и ни один суд
не ввозит его кузницу и не разбирает её исходник.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import rugram  # noqa: E402
import units  # noqa: E402

РОДЫ = ('состояние', 'граница', 'нужда', 'рост', 'вопросы', 'отказы')

ЗАЧЕМ_РОДА = {
    "состояние": "сколько есть сейчас",
    "граница": "где предел",
    "нужда": "чего и сколько недостаёт",
    "рост": "насколько выросло",
    "вопросы": "то же, спрошенное вопросом",
    "отказы": "чего сказать нельзя, и это сказано",
}


# ЯДРО ДОСЛОВНЫХ ПОВТОРОВ: столько первых случаев каждого рода стоят во
# ВСЕХ проходах слово в слово. Форма чеканится повторностью.
ЯДРО = 3

# ДЕНЬ СНИМКА. Оба замера сняты в один день, и потому день назван один,
# а замеры различены порядком: между ними корпус успел вырасти под
# девятью руками — это само по себе есть довод в пользу даты.
ДЕНЬ = "2 сентября 2026 года"
ЗАМЕР_ПЕРВЫЙ = "в первом замере"
ЗАМЕР_ВТОРОЙ = "во втором замере"

# ИСТОРИЯ НЕ РЕДАКТИРУЕТСЯ — ТРЕБОВАНИЕ Т-1 (holon, 02.09): когда прибор
# даст третий замер, он ДОПИСЫВАЕТСЯ третьим снимком, а первые два не
# переписываются и не удаляются. Леджер пути хранит ПУТЬ, не состояние;
# организм, у которого старые замеры исчезают, не помнит, как рос, — и
# его рассказ о росте становится рассказом о нынешнем числе.
# СНИМОК: (прибор, что мерено (род. мн.), взято, из скольких).
# Числа СНЯТЫ, а не выдуманы: рядом с каждым стои́т имя прибора, и
# всякий волен позвать его заново — `python3 scripts/<прибор>.py`.
# Первый снимок принесён заданием коллегии, второй снят мною следом;
# оба помечены своим порядком, ибо привести чужой замер как свой
# значило бы солгать об источнике числа.
СНИМОК_ПЕРВЫЙ = (
    ("concept_reach", "предмет", 773, 7668),
    ("ask_reach", "мир", 76, 101),
    ("ask_width", "род", 135, 885),
    ("biblio_reach", "источник", 45, 1992),
)
СНИМОК_ВТОРОЙ = (
    ("concept_reach", "предмет", 901, 8221),
    ("ask_reach", "мир", 77, 101),
    ("ask_width", "род", 370, 1098),
    ("biblio_reach", "источник", 62, 2074),
)

# СЧЁТНАЯ ФОРМА ИМЕНИ ЗАМЕРА. «901 предмет», но «77 миров» и «62
# источника»: последняя цифра правит формой, и написать её рукой значит
# написать неверно. Три имени из четырёх дом русского счёта не
# объявляет вовсе (мир, род, источник) — их тройки стоят здесь, ибо
# внести их в общий дом значило бы менять вердикты счётного суда по
# всему корпусу, чего эта задача не касается.
#
# ЧЕТВЁРТОЕ ИМЯ ОБЪЯВЛЕНО ДОМОМ, И ЭТО ДАЁТ ДАРОВОЙ ОРАКУЛ: тройка
# «предмета» сверяется с домом при сборке, и расхождение двух домов
# обрушит слой здесь, а не в корпусе.
СЧЁТНЫЕ = {
    "предмет": ("предмет", "предмета", "предметов"),
    "мир": ("мир", "мира", "миров"),
    "род": ("род", "рода", "родов"),
    "источник": ("источник", "источника", "источников"),
}
assert СЧЁТНЫЕ["предмет"] == rugram.СЧЁТНЫЕ["предмет"], "предмет"


def счётная(ключ, n):
    """Форма имени при счёте — законом ПАКЕТА, а не рукой."""
    return units.ру_форма(СЧЁТНЫЕ[ключ], n)


# ДОЛИ, С КОТОРЫМИ СРАВНИВАЕТСЯ ЗАМЕР: (знаменатель, имя доли).
# Сравнение точно и целочисленно — «N из M больше одной K-й» есть
# ровно «K × N > M», — и потому не требует ни округления, ни дроби.
ДОЛИ = ((2, "половины"), (4, "четверти"), (10, "десятой доли"),
        (100, "сотой доли"))

# ЧТО ИМЕННО МЕРИТ ПРИБОР — сказано словами, чтобы показ читался.
О_ЧЁМ = {
    "concept_reach": "предметы, названные корпусами",
    "ask_reach": "миры, которые задают хоть один вопрос",
    "ask_width": "роды суда, у которых есть вопросная поверхность",
    "biblio_reach": "источники, лежащие на полке",
}


def семя(шаг, i):
    """Первые ЯДРО случаев прохода не знают — оттого и дословны."""
    return i if i < ЯДРО else шаг * 13 + i


def _доля(взято, из_скольких, знаменатель):
    """«больше» или «меньше» одной K-й — точно и целыми числами."""
    произведение = знаменатель * взято
    return ("больше" if произведение > из_скольких else "меньше",
            произведение)


def состояние(шаг):
    """ДОЛЯ, НАЗВАННАЯ ТОЧНОЙ ГРАНИЦЕЙ, а не округлением.

    Показ не говорит «примерно десятая часть»: он говорит, с какой
    стороны от доли лежит замер, и приводит умножение, которым это
    видно. Округление здесь было бы первой ложью: оно превращает
    неравенство в впечатление.
    """
    вон = []
    for i, (прибор, что, взято, всего) in enumerate(СНИМОК_ВТОРОЙ):
        знаменатель, имя_доли = ДОЛИ[семя(шаг, i) % len(ДОЛИ)]
        куда, произведение = _доля(взято, всего, знаменатель)
        вон.append(f"{ЗАМЕР_ВТОРОЙ} {ДЕНЬ} прибор {прибор} насчитал у "
                   f"меня {взято} {счётная(что, взято)} из {всего}: "
                   f"это {куда} {имя_доли}, ибо {знаменатель} × "
                   f"{взято} = {произведение}, а всего {всего}.")
    return вон


def граница(шаг):
    """НЕМОТА, НАЗВАННАЯ ЧИСЛОМ. Дополнение сходится с целым."""
    вон = []
    for i, (прибор, что, взято, всего) in enumerate(СНИМОК_ВТОРОЙ):
        нет = всего - взято
        вон.append(f"{ЗАМЕР_ВТОРОЙ} {ДЕНЬ} прибор {прибор} насчитал у "
                   f"меня {взято} {счётная(что, взято)} из {всего}: "
                   f"вне меня осталось {нет} {счётная(что, нет)}, ибо "
                   f"{взято} + {нет} = {всего}.")
    return вон


def нужда(шаг):
    """НУЖДА ЕСТЬ РАЗНОСТЬ ДВУХ ЗАМЕРОВ, А НЕ ЖЕЛАНИЕ.

    «мне не хватает книг» без числа есть впечатление; «названо 2074, у
    меня 62, не хватает 2012» есть вычитание, и его пересчитывают.
    """
    вон = []
    for i, (прибор, что, взято, всего) in enumerate(СНИМОК_ВТОРОЙ):
        не_хватает = всего - взято
        вон.append(f"чего мне не хватало {ЗАМЕР_ВТОРОЙ} {ДЕНЬ}? "
                   f"прибор {прибор} назвал {всего} "
                   f"{счётная(что, всего)}, у меня было {взято}: мне "
                   f"не хватало {не_хватает} {счётная(что, не_хватает)}"
                   f", ибо {всего} − {взято} = {не_хватает}.")
    return вон


def рост(шаг):
    """РОСТ ЕСТЬ РАЗНОСТЬ ДВУХ ЗАМЕРОВ, И ОБЕ ЧАСТИ НАЗВАНЫ.

    Здесь и стоит самая соблазнительная ложь мира о себе: сказать «я
    вырос», назвав прибавку взятого и умолчав, что выросло и целое.
    Показ называет обе прибавки, и суд пересчитывает обе: рост
    числителя не есть рост доли.
    """
    вон = []
    for (прибор, что, было, было_всего), (_п, _ч, стало, стало_всего) in zip(
            СНИМОК_ПЕРВЫЙ, СНИМОК_ВТОРОЙ):
        прибавка = стало - было
        прибавка_всего = стало_всего - было_всего
        # ЧЕСТНЫЙ НУЛЬ НАЗЫВАЕТСЯ НУЛЁМ, А НЕ ПРЯЧЕТСЯ: «названо стало
        # больше на 0» есть оборот, учащий видеть рост там, где его
        # нет. Прибавка целого сказана своим словом, когда её нет.
        хвост = (f"а названо не изменилось, ибо {стало_всего} − "
                 f"{было_всего} = 0"
                 if прибавка_всего == 0 else
                 f"но и названо стало больше на {прибавка_всего}, ибо "
                 f"{стало_всего} − {было_всего} = {прибавка_всего}")
        вон.append(f"прибор {прибор} насчитал у меня {было} "
                   f"{счётная(что, было)} {ЗАМЕР_ПЕРВЫЙ} {ДЕНЬ} и "
                   f"{стало} {ЗАМЕР_ВТОРОЙ} того же дня: прибавилось "
                   f"{прибавка}, ибо {стало} − {было} = {прибавка}; "
                   f"{хвост}.")
    return вон


def вопросы(шаг):
    """ВОПРОСНАЯ ПОВЕРХНОСТЬ НА КАЖДЫЙ РОД: мир не смеет родиться немым.

    Знание, у которого есть лишь повествовательная поверхность, не
    отвечает — оно только сообщает. Владелец объявил правило: НЕМЫХ
    МИРОВ ДОЛЖНО БЫТЬ 0.
    """
    вон = []
    for i, (прибор, что, взято, всего) in enumerate(СНИМОК_ВТОРОЙ):
        нет = всего - взято
        вон.append(f"сколько {СЧЁТНЫЕ[что][2]} насчитал у меня прибор "
                   f"{прибор} {ЗАМЕР_ВТОРОЙ} {ДЕНЬ}? {взято} "
                   f"{счётная(что, взято)} из {всего}.")
        вон.append(f"чего я не показывал {ЗАМЕР_ВТОРОЙ} {ДЕНЬ} по "
                   f"прибору {прибор}? {О_ЧЁМ[прибор]}: их было {всего}, "
                   f"а у меня {взято}, и вне меня осталось {нет} "
                   f"{счётная(что, нет)}.")
    return вон


def отказы(шаг):
    """ОТКАЗ О БУДУЩЕМ, И ЕГО ОСНОВАНИЕ ТОЖЕ ПЕРЕСЧИТЫВАЕТСЯ.

    Организм, умеющий отказать в вопросе о себе, не научится хвастать.
    Основание отказа не «я не хочу», а факт о таблице снимков: замеры
    есть по названный день и НЕТ НИ ОДНОГО позже. Суд сверяется с той
    же таблицей.
    """
    вон = []
    for прибор, что, _взято, _всего in СНИМОК_ВТОРОЙ:
        # ОТКАЗ СКАЗАН ФОРМОЙ, КАКУЮ ОБЪЯВЛЯЕТ ДОМ: отрицание сущего,
        # двоеточие, основание (`tools/manifest_kinds.отказов`). И он
        # точнее «не знаю»: отказывает не незнание, а ОТСУТСТВИЕ
        # ЗАМЕРА — то есть проверяемый факт о таблице снимков.
        вон.append(f"сколько {СЧЁТНЫЕ[что][2]} насчитает у меня "
                   f"прибор {прибор} завтра? нет такого замера: у "
                   f"прибора {прибор} есть замеры по {ДЕНЬ} и ни "
                   f"одного позже.")
    return вон

ГРУППЫ = (состояние, граница, нужда, рост, вопросы, отказы)


def группы(шаг):
    """[[страница]] — ровно те группы и в том порядке, какими кузница кормит `emit_grouped`."""
    return [сделать(шаг) for сделать in ГРУППЫ]


def перебор(шаг):
    """[(страница, род)] — те же группы, но каждая под своим именем."""
    вон = []
    for род, группа in zip(РОДЫ, группы(шаг)):
        for с in группа:
            вон.append((с, род))
    return вон


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            вон.setdefault(с, род)
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, а не с кортежем."""
    имена = tuple(с.__name__ for с in ГРУППЫ)
    assert имена == РОДЫ, f"кортеж {имена} разошёлся с объявлением {РОДЫ}"
    сколько = len(группы(0))
    assert сколько == len(РОДЫ), f"проход даёт {сколько} групп при {len(РОДЫ)} родах"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка()
