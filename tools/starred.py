#!/usr/bin/env python3
"""ЗВЁЗДОЧКА — общий читатель знака невозможного для судов, которые о ней не знают.

    ЦИТАТА ПОД ЗВЁЗДОЧКОЙ НЕ ЕСТЬ РЕЧЬ СТРОКИ, А ОБРАЗЕЦ НЕВОЗМОЖНОЙ РЕЧИ; СУД, СУДЯЩИЙ
    ОБРАЗЕЦ, СУДИТ УРОК.

ПОВОД, ПРОЖИТЫЙ 13.09. `declarations/STARRED.md` объявил звёздочку 12.09 и назвал её
читателей поимённо: суды ПЯТИ домов, у каждого — свой содержательный закон. Прочие суды о ней
не знали, и покуда звёздная цитата стояла лишь в тех пяти мирах, разницы не было.

Дом причины отказа показывает 150 отвергнутых строк на 29 языках — и палата назвала ложью 76
его страниц: суд русской грамматики прочёл «*двадцать два час.» как русскую речь, суд письма
прочёл «؟» внутри арабской цитаты как вопросительный знак СТРОКИ.

    ЗНАК, ОБЪЯВЛЕННЫЙ ЗАКОНОМ ПЯТИ ДОМОВ, А НЕ ЗАКОНОМ СВОДА, ДЕРЖИТСЯ РОВНО ДО ТОГО ДНЯ,
    КОГДА ШЕСТОЙ ДОМ ПОКАЖЕТ ЕГО СУДУ, КОТОРОГО НЕ СПРАШИВАЛИ.

Двадцать пять страниц свода УЖЕ несли цитируемый вопрос внутри утверждения (`gender` 18,
`direct` 7), и суд письма пропускал их лишь оттого, что они СЛУЧАЙНО начинались вопросным
словом («сколько», «Кто»).

    ПРАВОТА, ДЕРЖАЩАЯСЯ НА ТОМ, ЧТО СТРОКА СЛУЧАЙНО НАЧАЛАСЬ ВОПРОСНЫМ СЛОВОМ, НЕ ЕСТЬ
    ПРАВОТА — ОНА НЕ ПРОВЕРЕНА.

ЧТО ЗДЕСЬ ЕСТЬ, И ЧЕГО ЗДЕСЬ НЕТ. Два признака, и оба формальные:

    `без_звёздных`  — строка без цитат вида «*…»: то, о чём суду языка спрашивать нечего.
    `вне_ёлочек`    — строка без ВСЯКИХ цитат: то, что говорит САМА строка, а не то, что она
                      приводит. Читается для решения «вопрос ли это», а не для суда о речи.

Дома, читающие звёздочку СОДЕРЖАТЕЛЬНО (serestar, dosupport, fuseprep, nlarticle, decase и
все, что пришли после), этот читатель НЕ ЗОВУТ: у них звезда есть закон, а не помеха.

    python3 tools/starred.py    # самопроверка
"""
import re
import sys

ЗВЁЗДНАЯ = re.compile(r"«\*[^»]*»")
ЁЛОЧКИ = re.compile(r"«[^»]*»")


def без_звёздных(строка):
    """Строка без цитат под звёздочкой. Образец невозможной речи не есть речь строки."""
    return ЗВЁЗДНАЯ.sub(" ", строка)


def вне_ёлочек(строка):
    """Строка без всякой цитаты — то, что говорит она сама, а не то, что приводит."""
    return ЁЛОЧКИ.sub(" ", строка)


def _самопроверка():
    беды = 0
    случаи = (
        ("пакет объявляет «*двадцать два час.» отвергаемой.", "двадцать два час", False),
        ("пакет объявляет «двадцать два часа.» верной.", "двадцать два часа", True),
        ("«*in il libro» по-итальянски не говорят.", "in il libro", False),
    )
    for строка, кусок, остаётся in случаи:
        есть = кусок in без_звёздных(строка)
        if есть != остаётся:
            print(f"  ЗВЁЗДНАЯ ЦИТАТА {'не снята' if есть else 'снята лишняя'}: {строка[:60]}")
            беды += 1
    вопросы = (
        ("сколько будет 2 + 2?", True),
        ("пакет объявляет строку «ما لون سبعة ؟» отвергаемой.", False),
        ("он спросил «сколько?» и ушёл.", False),
        ("«Кто там?» — спросила она. — так пишут прямую речь?", True),
    )
    for строка, вопрос in вопросы:
        есть = any(z in вне_ёлочек(строка) for z in "?？؟")
        if есть != вопрос:
            print(f"  ВОПРОС ПРОЧТЁН {'там' if есть else 'не там'}: {строка[:60]}")
            беды += 1
    print(f"  ЗВЁЗДОЧКА: случаев {len(случаи) + len(вопросы)}, бед {беды}")
    return беды


if __name__ == "__main__":
    sys.exit(1 if _самопроверка() else 0)
