#!/usr/bin/env python3
"""GENESIS layer: МЕСТО ЛИЦА В ГЛАГОЛЕ — see tools/personplaceforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Где живёт лицо» и «что не меняется» идут вместе: первое называет МЕСТО, второе отнимает
вывод «значит, меняется всё слово» — корень стои́т один и тот же, меняется оправа.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

Два рода о местоимении — «лицо видно и без местоимения» и «лицо без местоимения не видно» —
стоя́т в ОДНОЙ группе, хотя и не встречаются у одного языка: они суть ДВЕ ПОЛОВИНЫ ОДНОГО
ОТВЕТА, и читатель, увидевший в одном проходе обе, видит закон целиком. С ними же «сосед
держит иначе» — о границе наружу.

«Отказ свода назван» и «спрошено и отвечено» — третьей: первый показывает ТУ САМУЮ строку,
которую свод отвергает, второй спрашивает о законе.

    ДОМ, ОБЪЯСНЯЮЩИЙ ОТКАЗ, ОБЯЗАН ПРОЦИТИРОВАТЬ ТОТ САМЫЙ ОТКАЗ, А НЕ ПОХОЖИЙ НА НЕГО.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import personplaceforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_personplace.txt"
ГРУППЫ = (("где живёт лицо", "что не меняется"),
          ("лицо видно и без местоимения", "лицо без местоимения не видно",
           "сосед держит иначе"),
          ("отказ свода назван", "спрошено и отвечено"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
