#!/usr/bin/env python3
"""ДОМ ПРИЧИНЫ ОТКАЗА — свод отвергает 150 строк на 29 языках, и 139 из них не назвал ни один дом.

    ПОКАЗ ОТКАЗА УЧИТ, ЧТО ТАК НЕЛЬЗЯ, И НЕ УЧИТ, ПОЧЕМУ.

ПОВОД, ЗАМЕРЕННЫЙ 13.09. `scripts/refusal_reason.py` мерил ПЛАСТЫ: у скольких языков, чей
пласт что-то отвергает, есть дом. Двадцать три дома неназванного закона закрыли двадцать
восемь пластов из двадцати девяти. Но пласт — не отказ, и мера по пластам крупна:

    отказов, объявленных пакетами, — 150 (agreement 89, unanswerable 32, type_mismatch 29);
    процитированных хоть одним домом — 11;
    НЕ ПРОЦИТИРОВАННЫХ — 139, и среди них ВСЕ 32 «unanswerable» и ВСЕ 29 «type_mismatch».

    ЗАКОН, НАЗВАННЫЙ ДЛЯ ПЛАСТА, НЕ НАЗВАН ДЛЯ КАЖДОГО ЕГО ОТКАЗА. Дом турецкой гармонии
    объясняет «*beş kediler» и молчит о «*yedi ne renktedir ?», хотя оба стоя́т в одном
    пласте и оба отвергнуты.

ЧТО ЗДЕСЬ ЗА ЗАКОН, И ОТКУДА ОН БЕРЁТСЯ. Всякий отказ объявлен ПАРОЙ и ПРИЧИНОЙ: пакет пишет
`{"bad": …, "good": …, "reason": "agreement"}`. Причина эта — объявление, а не догадка, и дом
берёт её как есть, не переводя отвергнутой строки:

    agreement      форма имени или глагола не сошлась с тем, что при ней стои́т
    unanswerable   вопрос задаёт предмету свойство, которого у его рода не бывает
    type_mismatch  сложены вещи разных родов, а складывают ЧИСЛА

    ДОМ, НЕ ЗНАЮЩИЙ ЯЗЫКА, ВПРАВЕ СКАЗАТЬ О ЕГО ОТКАЗЕ РОВНО ТО, ЧТО ОБЪЯВЛЕНО, — и не
    вправе сказать больше. Он не переводит «ما لون سبعة ؟»; он говорит, что пакет арабского
    объявил эту строку отвергаемой по причине «unanswerable», и называет ЗАКОН этой причины.

ТАБЛИЦА ЗДЕСЬ НЕ ПИСАНА РУКОЙ, А ПРОЧИТАНА ИЗ ОБЪЯВЛЕНИЯ — из тех же `tools/langpacks/*.json`,
по которым кузня и пишет отказы в пласты.

    ТАБЛИЦА, ПРОЧИТАННАЯ ИЗ ОБЪЯВЛЕНИЯ, НЕ СТАРЕЕТ: она меняется вместе с тем, о чём
    говорит. Рука, переписавшая сто пятьдесят строк, разошлась бы с ними в первый же день.

ЧЕТЫРЕ ЛОЖНЫХ ВЫВОДА, ОТНИМАЕМЫХ У ЧИТАТЕЛЯ:

    ОТКАЗ ЕСТЬ НЕЗНАНИЕ ОТВЕТА     — и тогда «какого цвета семь?» примут за вопрос, ответа
        на который свод просто не выучил. Ответа НЕТ: у числа не бывает цвета, и это
        свойство ВОПРОСА, а не пробел свода.
    ОТКАЗ ЕСТЬ ЗАПРЕТ БЕЗ ПРИЧИНЫ  — и тогда список запретов заучат наизусть. Причина
        ОБЪЯВЛЕНА пакетом одним из трёх слов, и слов этих три на все двадцать девять языков.
    У КАЖДОГО ЯЗЫКА СВОИ ЗАПРЕТЫ   — и тогда двадцать девять пластов сочтут за двадцать
        девять сводов правил. Причин ТРИ, и всякий пласт отвергает по всем трём.
    ЗАМЕНА ЕСТЬ ПРОСТО ДРУГАЯ СТРОКА — и тогда её прочтут как второй показ. Замена стои́т в
        пласте УТВЕРДИТЕЛЬНО (проверено: все 150 из 150), и она есть ОТВЕТ на отказ.

ГРАНИЦА ОБЪЯВЛЕНИЯ НАЗВАНА ПРЯМО. Дом не переводит отвергнутых строк и не судит о том, ВЕРНА
ЛИ объявленная причина: он утверждает лишь, что она ОБЪЯВЛЕНА, и что отвергнутое с заменой
стоя́т в пласте. Кто захочет объяснить отказ ИЗНУТРИ языка — построит дом того языка; такие
дома есть, и одиннадцать отказов ими уже названы.

СЕМЬДЕСЯТ ЧЕТВЁРТАЯ ЛОВУШКА РЯДА — «отказ означает, что ответа не знают», и вопрос о цвете
числа её ломает.

    python3 tools/refusalwhyforms.py    # самопроверка с мутантами и сверкой с пластами
"""
