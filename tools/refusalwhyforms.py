def страницы():
    вон = {}
    по_причине = {}
    for код, _b, _g, why in ПАРЫ:
        по_причине.setdefault(why, set()).add(код)
    счёт = {why: sum(1 for _к, _b, _g, w in ПАРЫ if w == why) for why in ПРИЧИНЫ}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for код, плохо, хорошо, why in ПАРЫ:
            общ = dict(яз_ру=ИМЕНА[код][0], яз_ан=ИМЕНА[код][1], плохо=плохо, хорошо=хорошо,
                       причина=why, закон=ПРИЧИНЫ[why][0], закон_en=ПРИЧИНЫ[why][1])
            for род in ("отказ, замена и причина", "спрошено и отвечено"):
                вон[рамки[род].format(**общ)] = (язык, род)
        for why in sorted(ПРИЧИНЫ):
            if why not in по_причине:
                continue
            зп, зп_en = ПРИЧИНЫ[why]
            # ЛИТЕРАЛ МНОЖЕСТВЕННОГО НЕ ПИШЕТСЯ РУКОЙ, ДАЖЕ КОГДА ЧИСЛО ЗАВЕДОМО БОЛЬШЕ
            # ОДНОГО: `scripts/half_law.py` считает МЕСТО, где закон МОЖЕТ понадобиться, а
            # не ложь сегодняшнего дня.
            #     ПРАВОТА, ДЕРЖАЩАЯСЯ НА ТОМ, ЧТО ЖРЕБИЙ НЕ ДАЛ ЕДИНИЦЫ, НЕ ЕСТЬ ПРАВОТА.
            общ = dict(причина=why, сколько_яз=len(по_причине[why]), сколько_пар=счёт[why],
                       всего_пар=len(ПАРЫ), закон_прописью=зп, закон_прописью_en=зп_en,
                       пакет_ан=units.ан_форма(("pack", "packs"), len(по_причине[why])))
            вон[рамки["один закон, много языков"].format(**общ)] = (язык, "один закон, много языков")
    return вон


ПОКАЗЫ = страницы()

# СУД ЧИТАЕТ ДВА ЗАКОНА, И ОБА СОДЕРЖАТЕЛЬНЫ:
#   · звезда стои́т РОВНО на строках, объявленных пакетом отвергаемыми, и ни на каких иных;
#   · цитата без звезды есть ОБЪЯВЛЕННАЯ ЗАМЕНА, а не что придётся.
_ОТВЕРГНУТЫЕ = frozenset(b for _к, b, _g, _w in ПАРЫ)
_ЗАМЕНЫ = frozenset(g for _к, _b, g, _w in ПАРЫ)
_ПРИЧИНЫ_СЛОВА = frozenset(ПРИЧИНЫ)

_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней стои́т по объявлению.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        if цитата.startswith("*"):
            if цитата[1:] not in _ОТВЕРГНУТЫЕ:
                return True, False     # звезда на том, что пакет отвергаемым не объявлял
        elif цитата in _ОТВЕРГНУТЫЕ and цитата not in _ЗАМЕНЫ:
            return True, False         # отвергнутое показано БЕЗ звезды
        elif цитата not in _ЗАМЕНЫ and цитата not in _ПРИЧИНЫ_СЛОВА:
            return True, False         # цитата не объявлена ни заменой, ни причиной
    return True, True


def _самопроверка():
    беды = 0
    for показ in ПОКАЗЫ:
        if судить(показ) != (True, True):
            print("  ЧЕСТНАЯ НЕ ПРОШЛА:", показ[:120])
            беды += 1
    # СВЕРКА С ПЛАСТАМИ: и отвергнутое, и замена ОБЯЗАНЫ СТОЯТЬ в своём пласте.
    сверено = 0
    for код, плохо, хорошо, _why in ПАРЫ:
        п = КОРЕНЬ / "datasets" / f"genesis_lang_{код}.txt"
        т = п.read_text(encoding="utf-8", errors="replace") if п.is_file() else ""
        if плохо not in т:
            print(f"  ОТВЕРГНУТОГО НЕТ В ПЛАСТЕ [{код}]: «{плохо[:40]}»")
            беды += 1
        elif хорошо not in т:
            print(f"  ЗАМЕНЫ НЕТ В ПЛАСТЕ [{код}]: «{хорошо[:40]}»")
            беды += 1
        else:
            сверено += 1
    # МУТАНТЫ: снять звезду с отвергнутого и поставить её на замену.
    мутантов = 0
    for показ in ПОКАЗЫ:
        порча = None
        for цитата in _re.findall(r"«([^»]+)»", показ):
            if цитата.startswith("*") and цитата[1:] in _ОТВЕРГНУТЫЕ:
                порча = показ.replace(f"«{цитата}»", f"«{цитата[1:]}»", 1)
                break
            if цитата in _ЗАМЕНЫ:
                порча = показ.replace(f"«{цитата}»", f"«*{цитата}»", 1)
                break
        if not порча or порча == показ or порча in ПОКАЗЫ:
            continue
        if судить(порча) != (True, False):
            print("  МУТАНТ НЕ ПОЙМАН:", порча[:120])
            беды += 1
        else:
            мутантов += 1
    if not мутантов:
        print("  МУТАНТОВ НЕ ПОСТРОЕНО ВОВСЕ — проба слепа")
        беды += 1
    написано = {род for _, род in ПОКАЗЫ.values()}
    if написано != set(РОДЫ):
        print(f"  РОДЫ РАЗОШЛИСЬ: обещано {sorted(РОДЫ)}, написано {sorted(написано)}")
        беды += 1
    for чужая in ("в словаре стои́т «*three childs», и это не страница дома.",
                  "he wrote «two book» in the margin, and that is not a page of this house."):
        if судить(чужая) != (False, False):
            print("  ЧУЖАЯ РЕЧЬ СУДИМА:", чужая[:100])
            беды += 1
    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, мутантов поймано {мутантов}, "
          f"пар прочитано {len(ПАРЫ)}, сверено с пластами {сверено}, "
          f"причин {len(ПРИЧИНЫ)}, бед {беды}")
    return беды


if __name__ == "__main__":
    sys.exit(1 if _самопроверка() else 0)
