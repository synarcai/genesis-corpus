#!/usr/bin/env python3
"""ЧУЖОЙ ТЕКСТ И ЕГО ДОГОВОР — один закон на все суды, а не копия в каждом.

    ПОЛКА И ПРОЗА СУТЬ ЧУЖОЙ ТЕКСТ: он писан не нами, цитирует чужие записи и теряет знаки
    при сборке. МЕРА ПОКАЗОВ ЕМУ НЕ СУДЬЯ — он судится своей, и судья его назван ДОГОВОРОМ
    книги (поле «судится» манифеста). Суд, читающий чужой текст своим правилом, даёт не
    находку, а ШУМ, за которым не видно настоящих находок.

ПОЧЕМУ ЗДЕСЬ, А НЕ В СУДЕ. Закон этот жил внутри `engram_court` — и когда рядом встал второй
суд счёта (`langcount`, объявленный хозяином рода «счёт» 09.09), он его НЕ УНАСЛЕДОВАЛ: прибор
прозы дал 898 возражений из 1145 одним этим судом, и все они — чтение чужого текста мерой
показов. Копировать закон во второй дом значило бы завести двойника, против которого корпус
держит отдельный прибор.

    ЗАКОН, ЖИВУЩИЙ В ОДНОМ СУДЕ, НЕ ЕСТЬ ЗАКОН КОРПУСА. Суд, вставший рядом, наследует
    ПРЕДМЕТ, а не ОПЫТ, — и повторяет чужие ошибки как свои первые.

ПОДСУДНОСТЬ ОБЪЯВЛЯЕТСЯ РОДОМ ТЕКСТА МИРА, А НЕ ПУТЁМ ФАЙЛА: мир, чей объявленный `text` не
есть «shows», есть чужой текст, где бы он ни лежал. Договор старше общего правила: книга,
назвавшая суд поимённо, им и судится.
"""
import pathlib

РОД_ТЕКСТА = "shows"
_ПРОЗА = None
_ДОГОВОРЫ = None


def прозаические():
    """Имена миров, чей объявленный род текста НЕ «показы»."""
    global _ПРОЗА
    if _ПРОЗА is None:
        try:
            import genesis
            показы = {pathlib.Path(п).stem
                      for п in genesis.worlds(existing=False, kind=РОД_ТЕКСТА)}
            все = {pathlib.Path(п).stem for п in genesis.worlds(existing=False)}
            _ПРОЗА = frozenset(все - показы)
        except Exception:
            _ПРОЗА = frozenset()
    return _ПРОЗА


def договор(путь):
    """Имена судов, названных договором полки для ЭТОЙ книги («судится» манифеста)."""
    global _ДОГОВОРЫ
    if _ДОГОВОРЫ is None:
        _ДОГОВОРЫ = {}
        try:
            import genesis
            for м in genesis.manifest()["worlds"]:
                с = м.get("судится")
                if с:
                    _ДОГОВОРЫ[pathlib.Path(м["file"]).stem] = frozenset(с)
        except Exception:
            pass
    return _ДОГОВОРЫ.get(pathlib.Path(путь).stem, frozenset())


def чужой(путь, имя_суда):
    """Чужой ли этот текст ЭТОМУ суду: проза или полка, чей договор его не назвал."""
    п = pathlib.Path(путь)
    свой_род = ("shelf" in п.parts) or (п.stem in прозаические())
    return свой_род and имя_суда not in договор(путь)
