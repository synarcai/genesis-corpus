def _клетки_хода(мир_):
    """Клетки хода мира страницы: ход мира кода — по полям его рода (`codeworld.клетки`), ход мира процесса — клетками
    дома актов."""
    return (К.клетки if мир_.split(" ", 1)[0] in К.ПОЛЯ else R.клетки)(мир_)


def _разведено(стр, язык, род):
    """Число ответа организма — клетка хода мира, и ни одно прочее число ответа не равно мере хода, какой оно не
    называет: номер строки не равен счёту, счёт — ни одному номеру строки (дверь дома актов `toolrepo._разведено`)."""
    return R._разведено(стр, язык, род, клетки_=_клетки_хода)


def условия_рынка():
    беды = []
    for стр, (язык, род, форма, регистр) in ПОКАЗЫ.items():
        дыры = ПЕРЕПИСЬ[стр]
        части = R.реплики(стр, язык)
        приказ_ = части[0][1]
        итог = " ".join(т for роль, т in части[1:] if роль == "орг")
        for имя, знач in дыры.items():
            if знач not in R._слова_органа(приказ_):
                беды.append(f"дыра {имя}={знач} не слово приказа: {стр[:140]}")
            if род not in НЕВОЗМОЖНЫЕ | ОТКАЗЫ and знач not in R._слова_органа(итог):
                беды.append(f"итог не называет дыру {имя}={знач}: {стр[:140]}")
        if not _разведено(стр, язык, род):
            беды.append(f"источники не разведены: {стр[:160]}")
    return беды


def пары_перефраза():
    """У всякой правленой формы и всякого регистра, кроме прямого, — каноническая прямая пара: те же язык, род, дыры и
    ход мира."""
    основы = {}
    for стр, (я, род, форма, р) in ПОКАЗЫ.items():
        if форма not in ПЕРЕФРАЗ_ФОРМЫ and р == "плоский":
            основы.setdefault((я, род, tuple(sorted(ПЕРЕПИСЬ[стр].items()))), set()).add(R._ходы_мира(стр, я))
    беды = []
    for стр, (я, род, форма, р) in ПОКАЗЫ.items():
        if род in ОТКАЗЫ | НЕВОЗМОЖНЫЕ or форма not in ПЕРЕФРАЗ_ФОРМЫ and р == "плоский":
            continue
        if R._ходы_мира(стр, я) not in основы.get((я, род, tuple(sorted(ПЕРЕПИСЬ[стр].items()))), ()):
            беды.append(f"правка без пары одного хода мира: {стр[:140]}")
    return беды


