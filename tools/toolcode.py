def страница(язык, род, форма, объект, довод=None, регистр="плоский"):
    """Страница рода на семени мира кода: ход мира — ответ сервера, снятый прибором; части ответа — его клетки."""
    if род == ИМЕНИ_НЕТ:
        # имени нет: вопрос об определении («где») или об упоминаниях («где·упом») — отказ мира not-there
        if форма.endswith("·упом"):
            return сборка_упоминаний(язык, форма.partition("·")[0], объект, W.текст(К.ход("refs", объект)), нет=True)
        return сборка_определения(язык, форма, объект, W.текст(К.ход("define", объект)))
    if род == ОПРЕДЕЛЕНИЕ:
        ход_ = К.ход("define", объект)
        (строка_,) = ход_.строки
        поля = dict(строка_)
        return сборка_определения(язык, форма, объект, W.текст(ход_), поля["sort"], поля["path"], поля["line"])
    if род in (УПОМИНАНИЯ, НЕ_УПОМИНАЕТСЯ):
        ход_ = К.ход("refs", объект)
        N, L = счёт(язык, ход_.мера(К.СЧЁТ["refs"]))
        места_ = места(язык, [(dict(с)["line"], dict(с)["path"]) for с in ход_.строки]) if ход_.строки else None
        sort = _сорт_определения(К.ход("define", объект)) if форма in ФОРМЫ_СОРТОМ else None
        return сборка_упоминаний(язык, форма, объект, W.текст(ход_), N, L, места_, sort=sort)
    if род in (СИМВОЛЫ, СИМВОЛОВ_НЕТ, ФАЙЛА_НЕТ):
        ход_ = К.ход("symbols", объект)
        if род == ФАЙЛА_НЕТ:
            return сборка_символов(язык, форма, объект, W.текст(ход_), нет=True)
        символы_ = (символы(язык, [(dict(с)["sort"], dict(с)["name"], dict(с)["line"]) for с in ход_.строки])
                    if ход_.строки else None)
        return сборка_символов(язык, форма, объект, W.текст(ход_), символы_)
    sort = _сорт_определения(К.ход("define", объект)) if форма == "сорт" else None
    if род == ПЕРЕИМЕНОВАНИЕ_ОТКАЗ:
        чтение = К.ход("refs", объект)
        N, L = счёт(язык, чтение.мера(К.СЧЁТ["refs"]))
        return сборка_переименования(язык, род, форма, регистр, объект, довод, W.текст(чтение), sort, N, L)
    ход_ = К.ход("rename", объект, довод)
    if род in НЕВОЗМОЖНЫЕ:
        return сборка_переименования(язык, род, форма, регистр, объект, довод, W.текст(ход_), sort)
    k = ход_.мера(К.СЧЁТ["rename"])
    return сборка_переименования(язык, род, форма, регистр, объект, довод, W.текст(ход_), sort, T.раз(язык, k),
                                 R._л(k, 0), файлы(язык, К.поле(ход_, "path")))


# ПРОГОН ПО ИМЕНИ РЕЧИ: имя прогона мира → имя, каким речь его называет («the Gauge tests», «the Rust tests»)
ИМЯ_В_РЕЧИ = {имя: я for я, имя in R.ИМЕНА_ПРОГОНОВ.items()}


def страница_плана(язык, род, x, y, имя, было):
    """План двух миров на семени: ход правки — ответ сервера, ход прогона — отчёт бегуна, снятый на проекте после этой
    правки (`codeworld.снятое_после`); `было` — прогонов мира процесса до плана."""
    я = ИМЯ_В_РЕЧИ[имя]
    if род == ПЛАН_ОТКАЗ:
        чтение = К.ход("refs", x)
        return сборка_плана(язык, род, x, y, я, W.текст(чтение), *счёт(язык, чтение.мера(К.СЧЁТ["refs"])))
    ход1 = К.ход("rename", x, y)
    k = ход1.мера(К.СЧЁТ["rename"])
    снятое = К.снятое_после(x, y, имя)
    ход2 = W.прогон(имя, снятое, было)
    числа, исход_ = R.исход(язык, я, снятое)
    runs = ход2.мера("runs")
    return сборка_плана(язык, род, x, y, я, W.текст(ход1), T.раз(язык, k), R._л(k, 0), файлы(язык, К.поле(ход1, "path")),
                        W.текст(ход2), числа, исход_, A.запусков(язык, runs), R._л(runs - 1, 1))


def _показы():
    вон, перепись = {}, {}

    def положить(стр, язык, род, форма, регистр, дыры):
        if стр not in вон:
            вон[стр] = (язык, род, форма, регистр)
            перепись[стр] = дыры

    п_ = "плоский"
    for язык in ЯЗЫКИ:
        # ОПРЕДЕЛЕНИЕ: всякая форма на четырёх основах, по кругу имён (у каждой формы свои); имена, каких нет
        for i, форма in enumerate(ФОРМЫ_ОПРЕДЕЛЕНИЯ):
            # каноническая форма — на всяком имени; правленая — на четырёх из них (по кругу): пара одного хода мира
            for x in (К.ОПРЕДЕЛЕНИЯ if форма in ("где", "где·сорт") else R._кругом(К.ОПРЕДЕЛЕНИЯ, 4 * i)):
                положить(страница(язык, ОПРЕДЕЛЕНИЕ, форма, x), язык, ОПРЕДЕЛЕНИЕ, форма, п_, {"x": x})
        for x in К.НЕТ_ИМЁН:
            положить(страница(язык, ИМЕНИ_НЕТ, "где", x), язык, ИМЕНИ_НЕТ, "где", п_, {"x": x})
        # УПОМИНАНИЯ: всякая форма на четырёх упоминаемых именах; имена, каких не упоминает никто; имена, каких нет
        снятые = frozenset(К.семя().get("reads", {}))
        for форма in ФОРМЫ_УПОМИНАНИЙ:
            for x in К.УПОМИНАЕМЫЕ:
                if форма in ФОРМЫ_СОРТОМ and К.ключ("define", x) not in снятые:
                    continue
                положить(страница(язык, УПОМИНАНИЯ, форма, x), язык, УПОМИНАНИЯ, форма, п_, {"x": x})
        for форма in ("где", "сколько", "где·сорт"):
            for x in К.НЕУПОМИНАЕМЫЕ:
                положить(страница(язык, НЕ_УПОМИНАЕТСЯ, форма, x), язык, НЕ_УПОМИНАЕТСЯ, форма, п_, {"x": x})
        for x in К.НЕТ_ИМЁН:
            положить(страница(язык, ИМЕНИ_НЕТ, "где·упом", x), язык, ИМЕНИ_НЕТ, "где·упом", п_, {"x": x})
        # СИМВОЛЫ: всякая форма на четырёх файлах по кругу; файл без имён; файлы, каких нет
        for i, форма in enumerate(ФОРМЫ_СИМВОЛОВ):
            for f in (К.ФАЙЛЫ_КОДА if форма == "что" else R._кругом(К.ФАЙЛЫ_КОДА, 2 * i)):
                положить(страница(язык, СИМВОЛЫ, форма, f), язык, СИМВОЛЫ, форма, п_, {"f": f})
            for f in К.ФАЙЛЫ_БЕЗ_ИМЁН:
                положить(страница(язык, СИМВОЛОВ_НЕТ, форма, f), язык, СИМВОЛОВ_НЕТ, форма, п_, {"f": f})
        for f in К.НЕТ_ФАЙЛОВ_КОДА:
            положить(страница(язык, ФАЙЛА_НЕТ, "что", f), язык, ФАЙЛА_НЕТ, "что", п_, {"f": f})
        # ПЕРЕИМЕНОВАНИЕ: всякая форма на четырёх переименованиях по кругу; отказ пользователем — на двух основах всякой
        # формы (чтение «до» — упоминания имени); новое имя занято; имени нет
        for i, форма in enumerate(ФОРМЫ_ПЕРЕИМЕНОВАНИЯ):
            пары = К.ПЕРЕИМЕНОВАНИЯ if форма == "канон" else R._кругом(К.ПЕРЕИМЕНОВАНИЯ, 2 * i)
            for x, y in пары:
                положить(страница(язык, ПЕРЕИМЕНОВАНИЕ, форма, x, y), язык, ПЕРЕИМЕНОВАНИЕ, форма, п_, {"x": x, "y": y})
            for x, y in пары[:2]:
                положить(страница(язык, ПЕРЕИМЕНОВАНИЕ_ОТКАЗ, форма, x, y), язык, ПЕРЕИМЕНОВАНИЕ_ОТКАЗ, форма, п_,
                         {"x": x, "y": y})
        # РЕГИСТРЫ: вежливая и вопросная просьба канонической формы — на двух основах по кругу, у каждого регистра свои
        for i, регистр in enumerate(РЕГИСТРЫ[1:]):
            for x, y in R._кругом(К.ПЕРЕИМЕНОВАНИЯ, 3 + 2 * i, 2):
                положить(страница(язык, ПЕРЕИМЕНОВАНИЕ, "канон", x, y, регистр), язык, ПЕРЕИМЕНОВАНИЕ, "канон", регистр,
                         {"x": x, "y": y})
        for x, y in К.ЗАНЯТЫЕ:
            положить(страница(язык, ПЕРЕИМЕНОВАНИЕ_ЗАНЯТО, "канон", x, y), язык, ПЕРЕИМЕНОВАНИЕ_ЗАНЯТО, "канон", п_,
                     {"x": x, "y": y})
        for x, y in К.ПЕРЕИМЕНОВАНИЯ_НЕТ:
            положить(страница(язык, ПЕРЕИМЕНОВАНИЕ_НЕТ, "канон", x, y), язык, ПЕРЕИМЕНОВАНИЕ_НЕТ, "канон", п_,
                     {"x": x, "y": y})
        # ПЛАН ДВУХ МИРОВ: всякое переименование с всяким прогоном, чей код правка тронула; прогонов до плана — по кругу
        # (`toolrepo.ЗАПУСКИ_ДО`: ни одно не равно числу отчёта); отказ пользователем — на двух планах
        планы = [(x, y, имя) for x, y in К.ПЕРЕИМЕНОВАНИЯ for имя in К.прогоны_после(x, y)]
        for i, (x, y, имя) in enumerate(планы):
            было = R.ЗАПУСКИ_ДО[i % len(R.ЗАПУСКИ_ДО)]
            положить(страница_плана(язык, ПЛАН, x, y, имя, было), язык, ПЛАН, "план", п_,
                     {"x": x, "y": y, "Я": ИМЯ_В_РЕЧИ[имя]})
        for x, y, имя in планы[:2]:
            положить(страница_плана(язык, ПЛАН_ОТКАЗ, x, y, имя, 0), язык, ПЛАН_ОТКАЗ, "план", п_,
                     {"x": x, "y": y, "Я": ИМЯ_В_РЕЧИ[имя]})
    return вон, перепись


