def _р(язык, ключ, **п):
    return РЕЧЬ[язык][ключ].format(**п)


def сорт(язык, sort, x, падеж=0):
    """Слово сорта с именем: «the function half», «функцию half» (падеж 1 — форма приказа переименования)."""
    return СОРТ[язык][sort][падеж].format(x=x)


def _сорт_определения(ход_):
    (sort,) = dict.fromkeys(К.поле(ход_, "sort"))
    return sort


# ПЕРЕЧНИ ОТВЕТА — дверь голоса: места упоминаний, символы файла, файлы правки; что в них стоит, решает тот, кто зовёт
# (дом — из строк хода, суд — из клеток страницы)
def места(язык, пары):
    """«line 10 of gauge/src/lib.rs and line 3 of gauge/tests/checks.rs» — [(номер строки, путь)] по порядку."""
    return R.список(язык, [_р(язык, "место", n=n, p=p) for n, p in пары])


def символы(язык, тройки):
    """«the function add on line 1 and the function shout on line 4» — [(сорт, имя, номер строки)] по порядку."""
    return R.список(язык, [_р(язык, "символ", С=сорт(язык, sort, имя), n=n) for sort, имя, n in тройки])


def файлы(язык, пути):
    """«in the file gauge/src/lib.rs», «in the files a and b» — пути изменённых файлов по порядку."""
    if len(пути) == 1:
        return R._о(язык, "в_файле").format(f=пути[0])
    return _р(язык, "в_файлах", С=R.список(язык, пути))


def счёт(язык, k):
    """(N, L) счёта k: фраза раз и леджер «k = k»; нулю — (None, None): ответ «нигде не упоминается»."""
    return (T.раз(язык, k), R._л(k, 0)) if k else (None, None)


def ответ_определения(язык, sort, x, f, n):
    """«the function half is defined in the file gauge/src/lib.rs on line 4» — сорт, путь и строка — клетки хода."""
    прич = ОПРЕДЕЛЁН.get(язык, {}).get(СОРТ[язык][sort][2], "")
    return _ф(язык, _р(язык, "a_определено", С=сорт(язык, sort, x), прич=прич, М=R._о(язык, "в_файле").format(f=f),
                      n=n))


def _счёт_упоминаний(язык, x, N, L):
    """«half is referenced 6 times: 6 = 6.» — счёт меры references с леджером; без счёта — «нигде не упоминается»."""
    if N is None:
        return _ф(язык, _р(язык, "a_нигде", x=x)) + "."
    return T.наблюдение(язык, _ф(язык, _р(язык, "a_упоминается", x=x, N=N)), L)


def ответ_упоминаний(язык, x, N, L, места_):
    """Счёт упоминаний с леджером и их места — строки хода мира по порядку («line 10 of gauge/src/lib.rs, …»)."""
    вон = _счёт_упоминаний(язык, x, N, L)
    if N is not None:
        вон += " " + _ф(язык, _р(язык, "a_места", М=места_)) + "."
    return вон


def ответ_символов(язык, f, символы_):
    """«the file tally/src/lib.rs defines: the function add on line 1 and …»; без символов — «ничего не определяет»."""
    if символы_ is None:
        return _ф(язык, _р(язык, "a_ничего", f=f))
    return _ф(язык, _р(язык, "a_определяет", f=f, М=символы_))


def _вопрос_текст(язык, ключ, **п):
    return _ф(язык, _р(язык, ключ, **п))


# СБОРКИ СТРАНИЦ берут части текстом — имя, путь, ход мира, счёт, перечень: дом подаёт клетки хода, суд — метки
# (рамка страницы — та же сборка дома)
def сборка_определения(язык, форма, x, мир_, sort=None, f=None, n=None):
    """Вопрос об определении имени: ход мира и ответ; без находки (отказ мира not-there) — «в проекте нет имени x»."""
    ключ = {"где": "q_где", "сорт": "q_сорт", "найди": "q_найди", "где·сорт": "q_где_с"}[форма]
    прич = ОПРЕДЕЛЁН.get(язык, {}).get(СОРТ[язык][sort][2], "") if форма in ФОРМЫ_СОРТОМ else ""
    вопрос_ = _вопрос_текст(язык, ключ, x=x, С=сорт(язык, sort, x) if форма in ФОРМЫ_СОРТОМ else None, прич=прич)
    if f is None:
        return R.вопрос(язык, вопрос_, мир_, _ф(язык, _р(язык, "нет_имени", x=x)))
    return R.вопрос(язык, вопрос_, мир_, ответ_определения(язык, sort, x, f, n))


def сборка_упоминаний(язык, форма, x, мир_, N=None, L=None, места_=None, нет=False, sort=None):
    """Вопрос об упоминаниях: счёт и места; ноль — «нигде»; имени нет — отказ мира not-there; форма «где·сорт» называет
    символ родом (`sort` — клетка sort его определения)."""
    ключ = {"где": "q_где_упом", "сколько": "q_сколько", "найди": "q_найди_упом", "где·сорт": "q_упом_с"}[форма]
    вопрос_ = _вопрос_текст(язык, ключ, x=x, **({"С": сорт(язык, sort, x), "С2": сорт(язык, sort, x, 1)}
                                               if форма in ФОРМЫ_СОРТОМ else {}))
    if нет:
        return R.вопрос(язык, вопрос_, мир_, _ф(язык, _р(язык, "нет_имени", x=x)))
    return R.вопрос(язык, вопрос_, мир_, ответ_упоминаний(язык, x, N, L, места_))


def сборка_символов(язык, форма, f, мир_, символы_=None, нет=False):
    """Вопрос о символах файла: перечень; пустой файл — «ничего не определяет»; файла нет — отказ мира not-there."""
    вопрос_ = _вопрос_текст(язык, {"что": "q_что", "перечисли": "q_перечисли"}[форма], f=f)
    if нет:
        return R.вопрос(язык, вопрос_, мир_, _ф(язык, _р(язык, "нет_файла", f=f)))
    return R.вопрос(язык, вопрос_, мир_, ответ_символов(язык, f, символы_))


def _приказ_переименования(язык, форма, x, y, sort=None):
    """Приказ: голым именем («rename half to halve»), словом сорта («rename the function half to halve»), «во всём
    проекте»; инфинитив — канонический (предложение и регистры)."""
    if форма == "везде":
        imp = _р(язык, "везде", x=x, y=y)
    else:
        imp = _р(язык, "переименуй", X=сорт(язык, sort, x, 1) if форма == "сорт" else x, y=y)
    return R.Приказ(_ф(язык, imp), _ф(язык, _р(язык, "инф", x=x, y=y)))


def сборка_переименования(язык, род, форма, регистр, x, y, мир_, sort=None, N=None, L=None, F=None):
    """Акт переименования: приказ · предложение · «да»/«нет» · ход мира · отчёт с числом вхождений и файлами правки;
    на «нет» — чтение «до» (счёт упоминаний x); невозможный — отказ мира по имени: новое имя уже определено или имени
    нет."""
    приказ_ = _приказ_переименования(язык, форма, x, y, sort)
    предложение_ = R._предложение(язык, _ф(язык, _р(язык, "инф", x=x, y=y)), _ф(язык, _р(язык, "zu", x=x, y=y)))
    if род == ПЕРЕИМЕНОВАНИЕ_ЗАНЯТО:
        return R.невозможный(язык, регистр, приказ_, мир_, A.РЕЧЬ[язык]["есть"].format(Ф=РЕЧЬ[язык]["имя"][0].format(x=y)))
    if род == ПЕРЕИМЕНОВАНИЕ_НЕТ:
        return R.невозможный(язык, регистр, приказ_, мир_,
                             A.РЕЧЬ[язык]["пуст"].format(НФ=РЕЧЬ[язык]["имя"][1].format(x=x)))
    if род == ПЕРЕИМЕНОВАНИЕ_ОТКАЗ:
        return R.ход(язык, регистр, приказ_, предложение_, False, мир_, R._отказ(язык, _счёт_упоминаний(язык, x, N, L)))
    return R.ход(язык, регистр, приказ_, предложение_, True, мир_, _отчёт_переименования(язык, x, y, N, L, F))


def _отчёт_переименования(язык, x, y, N, L, F):
    """«renamed half to halve. the name was replaced 7 times in the files …: 7 = 7.» — счёт occurrences и файлы правки."""
    отчёт_ = _ф(язык, T.РЕЧЬ[язык]["отчёт"].format(past=_р(язык, "прош", x=x, y=y)))
    return отчёт_ + ". " + T.наблюдение(язык, _ф(язык, _р(язык, "a_заменено", N=N, F=F)), L)


def сборка_плана(язык, род, x, y, я, мир1, N1=None, L1=None, F1=None, мир2=None, ЧИСЛА=None, ИСХОД=None, N=None,
                 L=None):
    """План двух миров (М-2056 — акт идёт в мир, какой объявил его род): «rename half to halve, then run the Gauge
    tests» — правку отвечает сервер языка (мир кода), прогон — мир процесса на проекте, каким его оставила правка;
    итог прогона — числа отчёта бегуна и исход по коду выхода (дверь дома актов). На «нет» — чтение «до» мира кода
    (упоминания имени), и прогон не идёт."""
    приказ_п = _приказ_переименования(язык, "канон", x, y)
    imp_т, inf_т, _zu, _past = T._ступени(язык, "тесты", **R._тесты(язык, я))
    приказ_, предложение_ = R._план(язык, (приказ_п, приказ_п.инф), (_ф(язык, imp_т), _ф(язык, inf_т)))
    if род == ПЛАН_ОТКАЗ:
        return R._план_ход(язык, приказ_, предложение_, False,
                           [(мир1, R._отказ(язык, _счёт_упоминаний(язык, x, N1, L1)))])
    return R._план_ход(язык, приказ_, предложение_, True,
                       [(мир1, _отчёт_переименования(язык, x, y, N1, L1, F1)),
                        (мир2, R._итог_прогона(язык, я, ЧИСЛА, ИСХОД, N, L))])


