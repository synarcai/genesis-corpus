РОД_EN = {"среднего": "neuter", "мужского": "masculine", "женского": "feminine"}


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for слово, арт, умен, мн, ру, ан, нем, нем_род in СЛОВА:
            общ = dict(слово=слово, арт=арт, чужой="de" if арт == "het" else "het",
                       умен=умен, мн=мн, ру=ру, ан=ан, нем=нем, нем_род=нем_род,
                       нем_род_en=РОД_EN[нем_род])
            for род in РОДЫ:
                вон[рамки[род].format(**общ)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()

# СУД ЧИТАЕТ ЧЕТЫРЕ ЗАКОНА, И ВСЕ ЧЕТЫРЕ СОДЕРЖАТЕЛЬНЫ:
#   · артикль при слове обязан сойтись с объявленной таблицей;
#   · уменьшительное берёт только «het»;
#   · множественное берёт только «de»;
#   · звёздочка стои́т ровно при нарушении — ни раньше, ни позже.
_АРТИКЛЬ = {с: а for с, а, _, _, _, _, _, _ in СЛОВА}
_УМЕНЬШИТЕЛЬНЫЕ = {у for _, _, у, _, _, _, _, _ in СЛОВА}
_МНОЖЕСТВЕННЫЕ = {м for _, _, _, м, _, _, _, _ in СЛОВА}
_ПАРА = _re.compile(r"\b(de|het)\s+([a-z]+)\b")

_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _нарушает(тело):
    """Нарушает ли цитата закон дома: чужой артикль при слове, уменьшительном или множественном."""
    for арт, слово in _ПАРА.findall(тело.lstrip("*").strip()):
        if слово in _УМЕНЬШИТЕЛЬНЫЕ and арт != "het":
            return True
        if слово in _МНОЖЕСТВЕННЫЕ and арт != "de":
            return True
        if слово in _АРТИКЛЬ and арт != _АРТИКЛЬ[слово]:
            return True
    return False


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        if not _ПАРА.search(цитата.lstrip("*")):
            continue
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


