#!/usr/bin/env python3
"""ФОРМА ПРЕДМЕТА — скелет предложения с двумя родами дыр, и оба объявлены.

ОБЪЯВЛЕНИЕ ПРЕДМЕТА ЕСТЬ ФОРМА БЕЗ УТВЕРЖДЕНИЯ (06.09, третье лицо закона покрытия).
«массив [6 4 7]», «x = 4», «вход x = 5» ничего не утверждают — они НАЗЫВАЮТ предмет, о
котором утверждают следующие предложения; истинности у них нет, и требовать от суда
вердикта о них — то же, что требовать вердикта о заголовке. Мир объявляет свои формы
поимённо в поле `ПРЕДМЕТЫ` манифеста, и прибор покрытия зачитывает третье лицо ТОЛЬКО
по этому объявлению: иначе оно станет карманом, куда уедет всё непрочитанное.

    #   — ЧИСЛО: цифры или объявленное числительное пакета («три», «three»).
          Мир варьирует и то и другое, и дыра обязана закрывать оба: иначе
          «задача: шесть плюс x равно тринадцать» и «задача: три плюс x равно
          шесть» суть две разные формы, и объявление растёт числом страниц.
    …   — ПОВТОР: одна и та же часть, повторённая подряд, есть ТА ЖЕ форма.
          «трасса: i=# s=#; i=# s=#; i=# s=#» и «трасса: i=# s=#» отличаются
          длиной хода, а не родом предложения; «цепь: # # #» и «цепь: # #» —
          длиной цепи. Свёртка объявлена, а не угадана: подряд идущие РАВНЫЕ
          части, разделённые «; », сводятся к одной, и подряд идущие равные
          лексемы — к одной.

ЗАЧЕМ СВЁРТКА, А НЕ СПИСОК ДЛИН: список длин есть объявление о ВЫБОРКЕ, а не о
мире, — завтрашняя страница с четвёртым шагом окажется необъявленной, и прибор
назовёт непокрытым то, что покрыто по существу.
"""
import json
import pathlib
import re

К = pathlib.Path(__file__).resolve().parents[1]
_ЦИФРЫ = re.compile(r"\d+")
_СЛОВО = re.compile(r"[^\W\d_]+")


def числительные():
    слова = set()
    for путь in sorted((К / "tools" / "langpacks").glob("*.json")):
        try:
            пакет = json.loads(путь.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        for поле in ("numerals", "numeral_oblique"):
            зн = пакет.get(поле)
            if isinstance(зн, dict):
                for v in зн.values():
                    if isinstance(v, str):
                        слова.add(v.lower())
                    elif isinstance(v, (list, tuple)):
                        слова.update(str(x).lower() for x in v)
            elif isinstance(зн, (list, tuple)):
                слова.update(str(x).lower() for x in зн)
    return frozenset(w for w in слова if w and w.isalpha())


ЧИСЛИТЕЛЬНЫЕ = числительные()


_РЯД_ЧИСЕЛ = re.compile(r"#(?: #)+")


def _свернуть_повтор(с):
    """Повтор сводится к «…»: ряд чисел и повторённая часть суть одна форма.

    ЯРЛЫК ПЕРВОЙ ЧАСТИ НЕ ЕСТЬ ЧАСТЬ ПОВТОРА: «трасса: i=# s=#» повторяется частью
    «i=# s=#», и сравнивать надо ХВОСТ ПОСЛЕ ЯРЛЫКА, иначе один и тот же ход в два
    шага и в три дадут две формы.
    """
    с = _РЯД_ЧИСЕЛ.sub("#…", с)          # «[# # #]» → «[#…]», «цепь: # #» → «цепь: #…»
    части = с.split("; ")
    вон, эталон = [], None
    for ч in части:
        if эталон is not None and ч == эталон:
            continue                      # повтор уже помечен «…»
        предыдущее = вон[-1] if вон else None
        хвост = предыдущее.split(": ", 1)[-1] if предыдущее else None
        if предыдущее is not None and ч in (предыдущее, хвост):
            эталон = ч
            вон.append("…")
            continue
        эталон = None
        вон.append(ч)
    return "; ".join(вон)


_КОНЕЦ = re.compile(r"[.?!。…]+$")


def форма(предложение):
    """Скелет предложения: числа — дырой, повтор — свёрнут, конечный знак снят.

    КОНЕЧНЫЙ ЗНАК ЕСТЬ ПУНКТУАЦИЯ СТРОКИ, А НЕ ЧАСТЬ ФОРМЫ. Мера покрытия подаёт
    предложение суду СО ЗНАКОМ (суды держат его в образце), но форма предмета
    описывает само предложение: «x = 4» и «x = 4.» суть одна форма, и объявление,
    зависящее от того, стои́т ли предложение последним в строке, было бы объявлением
    о ПУНКТУАЦИИ.
    """
    с = _КОНЕЦ.sub("", предложение.strip())
    с = _ЦИФРЫ.sub("#", с)
    с = _СЛОВО.sub(lambda m: "#" if m.group(0).lower() in ЧИСЛИТЕЛЬНЫЕ else m.group(0), с)
    return _свернуть_повтор(с)
