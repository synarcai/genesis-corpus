# СУД ЧИТАЕТ СОГЛАСИЕ, А НЕ ИСТИНУ РОДА: пара «артикль ↔ имя рода» обязана сойтись с
# объявленной таблицей. Проверяется то, что дом объявил, а не то, чего он знать не может.
_ПАРА = re.compile(r"\b(der|die|das|le|la|les|el|los|las)\s+(\w+)\s*\((\w+)\b")
_АРТ_РОД = {}
for (_я, _сл), (_р, _а, _амн, _слмн, _ру, _ан) in СЛОВА.items():
    _АРТ_РОД[(_я, _сл)] = (_р, _а, _амн)


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for арт, слово, род in _ПАРА.findall(с):
        свои = [(я, сл) for (я, сл) in _АРТ_РОД if сл == слово]
        if not свои:
            continue
        р, а, амн = _АРТ_РОД[свои[0]]
        if арт not in (а, амн):
            return True, False
        if арт == а and род not in (ИМЕНА_РОДА["ru"][р], ИМЕНА_РОДА["en"][р]):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ТАБЛИЦА ОБЯЗАНА БЫТЬ СОГЛАСНА С СОБОЮ.
    for (я, сл), (р, а, амн, слмн, ру, ан) in СЛОВА.items():
        if р not in ("м", "ж", "с"):
            беды.append(f"неведомый род: {я}/{сл} = {р}")
        if not а or not амн or not слмн:
            беды.append(f"пустая клетка: {я}/{сл}")
    # ОДИН ПРЕДМЕТ — ОДИН РУССКИЙ РОД ВО ВСЕЙ ТАБЛИЦЕ.
    for (я, сл), з in СЛОВА.items():
        ру = з[4]
        if ру in РУССКИЙ_РОД and not РУССКИЙ_РОД[ру]:
            беды.append(f"русский род пуст: {ру}")
    # СЕРДЦЕ ДОМА: солнце обязано дать ТРИ разных рода в четырёх языках.
    солнца = {я: з[0] for (я, сл), з in СЛОВА.items() if з[4] == "солнце"}
    солнца["ru"] = РУССКИЙ_РОД["солнце"]
    if len(set(солнца.values())) < 3:
        беды.append(f"солнце не даёт трёх родов: {солнца}")
    # МУТАНТ ПО АРТИКЛЮ В КАЖДОМ РОДЕ: подменённый артикль обязан быть пойман.
    for род in ("род назван", "спрошенное"):
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        порча = страница.replace("der ", "die ", 1) if "der " in страница else (
            страница.replace("die ", "der ", 1) if "die " in страница else
            страница.replace("das ", "der ", 1))
        if порча == страница:
            беды.append(f"порча не состоялась в роде {род}")
        elif судить(порча)[1] is not False:
            беды.append(f"подменённый артикль прошёл в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    наз = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "род назван")
    порча = наз.replace("артикль", "артикл", 1)
    if порча == наз:
        беды.append("порча не состоялась: нет слова «артикль»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(наз + " " + наз)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"РОД В ЧУЖОМ ЯЗЫКЕ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


