def _тройки(язык_слова):
    """Тройки слов ОДНОГО языка с ТРЕМЯ разными родами — для страниц о неразличимости."""
    по_роду = {}
    for (я, сл), (р, а, амн, слмн, _ру, _ан) in СЛОВА.items():
        if я == язык_слова:
            по_роду.setdefault(р, []).append((сл, а, амн, слмн))
    if len(по_роду) < 3:
        return []
    м, ж, с = по_роду.get("м", []), по_роду.get("ж", []), по_роду.get("с", [])
    return [(м[i % len(м)], ж[i % len(ж)], с[i % len(с)])
            for i in range(max(len(м), len(ж), len(с)))]


