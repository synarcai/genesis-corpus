#!/usr/bin/env python3
"""GENESIS layer: ИНДОНЕЗИЙСКОЕ УДВОЕНИЕ — see tools/idredupforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Множественное есть повтор» и «при числе повтора нет» идут вместе: первое даёт правило,
второе тут же отнимает вывод «повтор нужен всегда, где много».

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Слово не меняется вовсе» и «сосед меняет конец слова» — второй группой: обе о том, ГДЕ
искать признак числа, и вторая показывает, что искать его по-своему бесполезно.

«Спрошено и отвечено» — третьей: вопрос и ответ в одной строке.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import idredupforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_idredup.txt"
ГРУППЫ = (("множественное есть повтор", "при числе повтора нет"),
          ("слово не меняется вовсе", "сосед меняет конец слова"),
          ("спрошено и отвечено",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
