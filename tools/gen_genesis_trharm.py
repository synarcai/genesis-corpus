#!/usr/bin/env python3
"""GENESIS layer: ТУРЕЦКАЯ ГАРМОНИЯ — see tools/trharmforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Один суффикс, две гласные» и «решает последняя гласная» идут вместе: первое говорит, что
суффикс один, второе — что именно выбирает его обличье. Порознь первое учило бы искать
выбор в любой гласной основы.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«При числе суффикса нет» и «сосед не гармонирует» — второй группой: обе о ГРАНИЦАХ, одна
внутрь языка (там, где число названо словом, суффикс лишний), другая наружу.

«Спрошено и отвечено» — третьей.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import trharmforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_trharm.txt"
ГРУППЫ = (("один суффикс, две гласные", "решает последняя гласная"),
          ("при числе суффикса нет", "сосед не гармонирует"),
          ("спрошено и отвечено",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
