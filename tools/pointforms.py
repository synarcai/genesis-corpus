#!/usr/bin/env python3
"""ДОМ ТОЧКИ НА ПЛОСКОСТИ — ПАРА ЧИСЕЛ, В КОТОРОЙ ПОРЯДОК ЗНАЧИТ.

    ЧТЕНИЯ ПАРЫ КООРДИНАТ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 248 мирам показов:
    «точка (3, 2)», «point (3, 2)», «вправо и вверх» — НОЛЬ. Запись «(a, b)» встречается 4141
    раз — и вся она в мирах векторов, поворотов и отношений, где пара УЖЕ ПОНЯТНА читателю:
    свод считает с координатами, ни разу не сказав, что они значат.

    СВОД СЧИТАЕТ ПАРАМИ И НЕ УЧИТ ИХ ЧИТАТЬ.

ДВАДЦАТАЯ ЛОВУШКА РЯДА, И ОНА ПЕРВАЯ, ГДЕ ЛОЖЬ НЕ В ЧИСЛЕ, А В ПОРЯДКЕ: точки (3, 2) и (2, 3) —
РАЗНЫЕ, хотя числа в них одни и те же. Всё, чему свод учил прежде, было о величине; здесь
величины равны, а вещи разные.

    ПАРА НЕ ЕСТЬ МНОЖЕСТВО: В НЕЙ ЗНАЧИТ НЕ ТОЛЬКО ЧТО, НО И ГДЕ.

ЧЕТЫРЕ РОДА:

    чтение пары  у точки (3, 2) первое число 3 — вправо, второе 2 — вверх: 3 − 2 = 1.
    порядок      точки (3, 2) и (2, 3) различны, хотя числа те же: 3 − 2 = 1,
                 и 1 больше 0.                                               ← ЛОВУШКА
    вправо       от точки (3, 2) до точки (7, 2) 4 шага вправо, а высота та же: 7 − 3 = 4.
    вверх        от точки (3, 2) до точки (3, 9) 7 шагов вверх, а место вправо то же:
                 9 − 2 = 7.

ТРЕТИЙ И ЧЕТВЁРТЫЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО НАПРАВЛЕНИЮ: тот же ход, те же числа, и разница в
одном месте — которое из двух чисел меняется. Порознь читатель решил бы, что первое число и есть
«расстояние», а второе — приложение к нему.

ВТОРОЙ РОД ОПИРАЕТСЯ НА ПЕРВЫЙ: пока не сказано, ЧТО значит каждое число пары, «различны» было бы
объявлением без основания. Потому первый род и стои́т первым: он даёт паре смысл, второй — закон.

ШАГ СЧИТАЕТСЯ ФОРМОЙ ЯЗЫКА: «1 шаг», «2 шага», «7 шагов» — дом берёт их у счётной таблицы, а не
пишет окончаний рукой.

ТИРЕ ПЕРЕД ЧИСЛОМ СТОИ́Т НЕ ДЛЯ КРАСОТЫ, А РАДИ ЧУЖОГО ПРИБОРА, И ЭТО НАЙДЕНО НАБОРОМ. Суд родов
сказал: 126 строк этого дома несут род «согласование» («4 шага»), а читают их только арифметика
да суд дома — суд русского счёта молчал. Причина в его страже «число внутри записи»: перед
числом стояла ЗАКРЫВАЮЩАЯ СКОБКА пары («(6, 4) 4 шага»), а скобка объявлена там знаком
выражения — «N = q²+q+1 узлов». Скобка пары и скобка выражения неразличимы по виду.

    ЗНАК, ОБЪЯВЛЕННЫЙ ДЛЯ ОДНОГО ДЕЛА, НЕ ПЕРЕСТАЁТ БЫТЬ СОБОЙ В ЧУЖОМ ДЕЛЕ.

Дом уступил чужому стражу: тире отделяет счёт от пары, и суд счёта читает страницу — проверено
прямо («— 4 шагов» он зовёт ложью, «— 4 шага» истиной). ПРАВИТЬ ЧУЖОЙ СТРАЖ РАДИ СВОЕГО ДОМА
ДОРОЖЕ, ЧЕМ ПОСТАВИТЬ В СВОЁМ ДОМЕ ОДИН ЗНАК.

    python3 tools/pointforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётная форма «шага» объявлена там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("чтение пары", "порядок", "вправо", "вверх")


def шагов(язык, n):
    return ("step" if n == 1 else "steps") if язык == "en" else rugram.форма("шаг", n)


РАМКИ = {
    "ru": {
        "чтение пары": "у точки ({x}, {y}) первое число {x} — вправо, второе {y} — вверх: {x} − {y} = {d}.",
        "порядок": "точки ({x}, {y}) и ({y}, {x}) различны, хотя числа те же: {x} − {y} = {d}, и {d} больше 0.",
        "вправо": "от точки ({x}, {y}) до точки ({x2}, {y}) — {шх} {шагх} вправо, а высота та же: {x2} − {x} = {шх}.",
        "вверх": "от точки ({x}, {y}) до точки ({x}, {y2}) — {шу} {шагу} вверх, а место вправо то же: {y2} − {y} = {шу}.",
    },
    "en": {
        "чтение пары": "in the point ({x}, {y}) the first number {x} goes right and the second {y} goes up: {x} − {y} = {d}.",
        "порядок": "the points ({x}, {y}) and ({y}, {x}) are different, although the numbers are the same: {x} − {y} = {d}, and {d} is greater than 0.",
        "вправо": "from the point ({x}, {y}) to the point ({x2}, {y}) there are {шх} {шагх} right, and the height is the same: {x2} − {x} = {шх}.",
        "вверх": "from the point ({x}, {y}) to the point ({x}, {y2}) there are {шу} {шагу} up, and the place to the right is the same: {y2} − {y} = {шу}.",
    },
}
ПУСТО = dict(x=0, y=0, d=0, x2=0, y2=0, шх=0, шу=0, шагх="", шагу="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for x in range(1, 13):
            for y in range(0, 12):
                # ЧИСЛА ПАРЫ РАЗНЫЕ — ИНАЧЕ ПОРЯДОК НИЧЕГО НЕ РЕШАЕТ: у (3, 3) переставлять
                # нечего, и ловушка обратилась бы в свою противоположность.
                if x <= y:
                    continue
                d = x - y
                общ = dict(ПУСТО, x=x, y=y, d=d)
                # РЯДЫ ВЫРАВНЕНЫ ЗАМЕРОМ: при отборе по чётности и остатку два первых
                # рода давали 26 и 36 страниц против 78 у хода — перекос втрое.
                вон[рамки["чтение пары"].format(**общ)] = (язык, "чтение пары")
                вон[рамки["порядок"].format(**общ)] = (язык, "порядок")
                for шаг in (2, 4, 7):
                    if (x + y + шаг) % 4 == 0 and x + шаг <= 20:
                        вон[рамки["вправо"].format(
                            **dict(общ, x2=x + шаг, шх=шаг,
                                   шагх=шагов(язык, шаг)))] = (язык, "вправо")
                    if (x * y + шаг) % 4 == 0 and y + шаг <= 20:
                        вон[рамки["вверх"].format(
                            **dict(общ, y2=y + шаг, шу=шаг,
                                   шагу=шагов(язык, шаг)))] = (язык, "вверх")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (\d+)(?![/\d])")
_БОЛЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:больше|is greater than) (\d+)(?![/\d])")
_ПАРЫ = re.compile(r"\((\d+), (\d+)\)")
_РАЗЛИЧНЫ = re.compile(r"(?:различны|are different)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    пары = [(int(a), int(b)) for a, b in _ПАРЫ.findall(с)]
    # ЛОВУШКА ОБЯЗАНА ЛОВИТЬ: на странице о порядке пары обязаны БЫТЬ ПЕРЕСТАВЛЕННЫМИ и
    # РАЗНЫМИ — совпавшая пара показала бы обратное тому, ради чего страница написана.
    if _РАЗЛИЧНЫ.search(с):
        if len(пары) < 2 or пары[0] == пары[1] or пары[0] != пары[1][::-1]:
            return True, False
    # ДВЕ ТОЧКИ ОДНОЙ ВЫСОТЫ ИЛИ ОДНОГО МЕСТА: страница о ходе обязана менять РОВНО ОДНО число.
    elif len(пары) == 2:
        (x1, y1), (x2, y2) = пары
        if (x1 == x2) == (y1 == y2):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:92]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    пр = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "порядок")
    вп = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "вправо")
    for страница, слово, куда in ((пр, "различны", "различн"), (вп, "высота", "высот")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(пр + " " + пр)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ЧИСЛА ПАРЫ РАЗНЫЕ ТАМ, ГДЕ ЗНАЧИТ ПОРЯДОК, И ТОЛЬКО ТАМ.
    #
    # Первая редакция стража искала равные числа по ВСЕМУ дому — и обвинила честную страницу
    # «от точки (5, 1) до точки (5, 5)», где (5, 5) есть просто конец пути и порядок в нём
    # ничего не решает. Четвёртое за смену обвинение по форме без разбора связи, и лечится
    # оно всякий раз одинаково: СТРАЖ СМОТРИТ СВОИ РОДЫ, А НЕ ВСЕ.
    for с, (_я, р) in ПОКАЗЫ.items():
        if р not in ("чтение пары", "порядок"):
            continue
        if any(a == b for a, b in _ПАРЫ.findall(с)):
            беды.append(f"пара с равными числами: {с[:70]}")
            break
    # СЧЁТНАЯ ФОРМА ШАГА БЕРЁТСЯ У ЯЗЫКА.
    for кусок in ("2 шага ", "4 шага ", "7 шагов "):
        if not any(кусок in с for с in ПОКАЗЫ):
            беды.append(f"СЧЁТНАЯ ФОРМА НЕ ПОКАЗАНА: {кусок.strip()}")
    print(f"ТОЧКА НА ПЛОСКОСТИ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
