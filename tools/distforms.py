"""ДОМ ТРЁХ ЗАКОНОВ РАССТОЯНИЯ — ЧТО ДЕЛАЕТ РАССТОЯНИЕ РАССТОЯНИЕМ.

    ПУТЬ ЧЕРЕЗ ТРЕТЬЮ ТОЧКУ НЕ КОРОЧЕ ПРЯМОГО — И РАВЕН ЕМУ, КОГДА ТОЧКА ЛЕЖИТ НА ПУТИ.

ПОВОД — ЗАМЕР, А НЕ ЗАМЫСЕЛ, и тот же, что дал дом замкнутости. В списке понятий, названных
нашей прозой и не показанных, стои́т «метрика» — восемнадцать раз. Мир `mathspaces` СЧИТАЕТ
расстояния сотнями страниц («расстояние между (−1, 2) и (−16, 10) — 17: 15² + 8² = 17²») и
нигде не говорит, ЧТО ДЕЛАЕТ ЭТО ЧИСЛО РАССТОЯНИЕМ.

Замер 12.09 по 258 мирам показов:

    симметрия расстояния     показана (`abs` о нуле, `relation` о свойстве отношения)
    ноль только до себя      НИГДЕ
    путь через третью точку  НИГДЕ
    неравенство треугольника НИГДЕ

    СВОД, СЧИТАЮЩИЙ ВЕЛИЧИНУ И НЕ НАЗЫВАЮЩИЙ ЕЁ ЗАКОНОВ, УЧИТ СЧИТАТЬ, А НЕ ПОНИМАТЬ.

ПЯТЬ РОДОВ, И ПЯТЫЙ ЕСТЬ ГРАНИЦА ТРЕТЬЕГО С ЧЕТВЁРТЫМ:

    симметрия      от (0, 0) до (3, 4) — 5, и от (3, 4) до (0, 0) тоже 5: 3² + 4² = 5².
    ноль до себя   от (3, 4) до (3, 4) — 0, и только до себя ноль: до (3, 5) уже 1.
    через третью   путь через третью точку не короче прямого: прямо 5, а через (3, 0) —
                   3 + 4 = 7, и 7 больше 5.
    через угол     и через ДРУГОЙ угол не короче: через (0, 4) — 4 + 3 = 7.
    на пути        а когда третья точка лежит НА пути, путь РАВЕН прямому: от (0, 0)
                   до (6, 8) прямо 10, а через (3, 4) — 5 + 5 = 10.       ← ЛОВУШКА
    спрошенное     тот же закон, поставленный вопросом.

ЧЕТВЁРТЫЙ РОД СТОИ́Т ПРОТИВ ЛОЖНОГО ВЫВОДА, что дело в ЭТОМ угле: один угол показал бы
читателю особенность точки, а не закон. Два угла показывают закон.

ПЯТЫЙ РОД ЕСТЬ ЛОВУШКА ТРЕТЬЕГО, И ЭТО ЕГО ГЛАВНОЕ ДЕЛО. Читатель, выучивший «через
третью точку дольше», применит это и там, где третья точка лежит на самом пути, — и
ошибётся, ибо там путь РАВЕН. Неравенство треугольника есть «не короче», а не «длиннее».

    ПРАВИЛО, НЕ СКАЗАВШЕЕ, ГДЕ ОНО ОБРАЩАЕТСЯ В РАВЕНСТВО, БУДЕТ ПРИМЕНЕНО КАК СТРОГОЕ.

ЧИСЛА БЕРУТСЯ ТОЛЬКО ЦЕЛЫЕ, И ЭТО ГРАНИЦА, А НЕ УДОБСТВО: расстояние берётся по
пифагоровым тройкам (3–4–5, 5–12–13, 8–15–17, 7–24–25, 20–21–29 и их кратным), и всякое
число страницы — целое. Дробного корня дом не пишет вовсе.

    МИР, ПОКАЗЫВАЮЩИЙ ЗАКОН НА ДРОБНОМ КОРНЕ, УЧИТ ДВУМ ВЕЩАМ РАЗОМ И НИ ОДНОЙ ДО КОНЦА.

РАВЕНСТВО СТОИ́Т ПОСЛЕДНИМ В КАЖДОМ ЗВЕНЕ, ЧТОБЫ ЕГО ПРОЧЁЛ ОБЩИЙ СУД.

    python3 tools/distforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("симметрия", "ноль до себя", "через третью", "через угол", "на пути",
        "спрошенное")

# ПИФАГОРОВЫ ТРОЙКИ — ОБЪЯВЛЕНЫ ЗДЕСЬ И НИГДЕ БОЛЬШЕ. Всякая проверена: a² + b² = c².
ТРОЙКИ = ((3, 4, 5), (6, 8, 10), (5, 12, 13), (9, 12, 15), (8, 15, 17),
          (12, 16, 20), (7, 24, 25), (20, 21, 29), (10, 24, 26), (15, 20, 25),
          (9, 40, 41), (12, 35, 37), (16, 30, 34), (18, 24, 30), (21, 28, 35),
          (24, 32, 40), (11, 60, 61), (28, 45, 53), (33, 56, 65), (16, 63, 65),
          (13, 84, 85), (36, 77, 85), (39, 80, 89), (65, 72, 97), (20, 48, 52))

РАМКИ = {
    "ru": {
        "симметрия": "расстояние от (0, 0) до ({a}, {b}) — {c}, и от ({a}, {b}) до (0, 0) "
                     "тоже {c}: {a}² + {b}² = {c}².",
        "ноль до себя": "расстояние от ({a}, {b}) до ({a}, {b}) — 0, и только до себя оно "
                        "ноль: до ({a}, {b1}) уже 1, ибо {b1} − {b} = 1.",
        "через третью": "путь через третью точку не короче прямого: от (0, 0) до ({a}, {b}) "
                        "прямо {c}, а через ({a}, 0) — {a} + {b} = {s}, и {s} больше {c}.",
        "на пути": "а когда третья точка лежит НА пути, путь равен прямому: от (0, 0) до "
                   "({a2}, {b2}) прямо {c2}, а через ({a}, {b}) — {c} + {c} = {c2}.",
        "через угол": "и через другой угол не короче: от (0, 0) до ({a}, {b}) прямо {c}, "
                      "а через (0, {b}) — {b} + {a} = {s}, и {s} больше {c}.",
        "спрошенное": "каково расстояние от (0, 0) до ({a}, {b})? {c}, ибо {a}² + {b}² = {c}².",
    },
    "en": {
        "симметрия": "the distance from (0, 0) to ({a}, {b}) is {c}, and from ({a}, {b}) to "
                     "(0, 0) it is {c} as well: {a}² + {b}² = {c}².",
        "ноль до себя": "the distance from ({a}, {b}) to ({a}, {b}) is 0, and only to itself "
                        "it is zero: to ({a}, {b1}) it is already 1, for {b1} − {b} = 1.",
        "через третью": "a way through a third point is not shorter than the straight one: "
                        "from (0, 0) to ({a}, {b}) straight is {c}, and through ({a}, 0) it "
                        "is {a} + {b} = {s}, and {s} is greater than {c}.",
        "на пути": "and when the third point lies ON the way, the way equals the straight "
                   "one: from (0, 0) to ({a2}, {b2}) straight is {c2}, and through ({a}, {b}) "
                   "it is {c} + {c} = {c2}.",
        "через угол": "and through the other corner it is not shorter either: from (0, 0) "
                      "to ({a}, {b}) straight is {c}, and through (0, {b}) it is "
                      "{b} + {a} = {s}, and {s} is greater than {c}.",
        "спрошенное": "what is the distance from (0, 0) to ({a}, {b})? {c}, for "
                      "{a}² + {b}² = {c}².",
    },
}
ПУСТО = dict(a=0, b=0, c=0, s=0, b1=0, a2=0, b2=0, c2=0)


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a, b, c in ТРОЙКИ:
            общ = dict(ПУСТО, a=a, b=b, c=c, s=a + b, b1=b + 1,
                       a2=2 * a, b2=2 * b, c2=2 * c)
            вон[рамки["симметрия"].format(**общ)] = (язык, "симметрия")
            вон[рамки["ноль до себя"].format(**общ)] = (язык, "ноль до себя")
            вон[рамки["через третью"].format(**общ)] = (язык, "через третью")
            # ВТОРОЙ УГОЛ ТОГО ЖЕ ПРЯМОУГОЛЬНИКА: путь через (0, b) так же длиннее
            # прямого. Один угол показал бы, что дело в НЁМ, а не в законе.
            вон[рамки["через угол"].format(**общ)] = (язык, "через угол")
            вон[рамки["на пути"].format(**общ)] = (язык, "на пути")
            вон[рамки["спрошенное"].format(**общ)] = (язык, "спрошенное")
            # И ЗЕРКАЛЬНАЯ ТРОЙКА: та же, с переставленными катетами — расстояние
            # от перестановки не меняется, и это тоже показ симметрии.
            if a != b:
                общ2 = dict(ПУСТО, a=b, b=a, c=c, s=a + b, b1=a + 1,
                            a2=2 * b, b2=2 * a, c2=2 * c)
                вон[рамки["симметрия"].format(**общ2)] = (язык, "симметрия")
                вон[рамки["спрошенное"].format(**общ2)] = (язык, "спрошенное")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПИФАГОР = re.compile(r"(\d+)² \+ (\d+)² = (\d+)²")
_СУММА = re.compile(r"(?<![\d/])(\d+) \+ (\d+) = (\d+)(?![\d/])")
_РАЗНОСТЬ = re.compile(r"(?<![\d/])(\d+) − (\d+) = (\d+)(?![\d/])")
_БОЛЬШЕ = re.compile(r"(?<![\d/])(\d+) больше (\d+)(?![\d/])"
                     r"|(\d+) is greater than (\d+)(?![\d/])")
_ТОЧКА = re.compile(r"\((-?\d+), (-?\d+)\)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _ПИФАГОР.findall(с):
        if int(a) ** 2 + int(b) ** 2 != int(c) ** 2:
            return True, False
    for a, b, s in _СУММА.findall(с):
        if int(a) + int(b) != int(s):
            return True, False
    for a, b, r in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(r):
            return True, False
    for ру1, ру2, ан1, ан2 in _БОЛЬШЕ.findall(с):
        x, y = int(ру1 or ан1), int(ру2 or ан2)
        if x <= y:
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ: подмена последнего числа обязана быть поймана.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        числа = list(re.finditer(r"\d+", страница))
        m = числа[-1] if числа else None
        порча = (страница[:m.start()] + str(int(m.group()) + 1) + страница[m.end():]
                 if m else страница)
        if порча == страница:
            беды.append(f"порча не состоялась в роде {род}")
        elif судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    сим = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "симметрия")
    порча = сим.replace("расстояние", "расстояни", 1)
    if порча == сим:
        беды.append("порча не состоялась: нет слова «расстояние»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(сим + " " + сим)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ЛОВУШКА ОБЯЗАНА ЛОВИТЬ: третья точка лежит НА пути, и путь РАВЕН прямому.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "на пути" or я != "ru":
            continue
        точки = [(int(x), int(y)) for x, y in _ТОЧКА.findall(с)]
        if len(точки) < 3:
            беды.append(f"ловушка без трёх точек: {с[:70]}")
            break
        (_, _), (a2, b2), (a, b) = точки[0], точки[1], точки[2]
        # третья точка обязана лежать РОВНО посередине
        if (2 * a, 2 * b) != (a2, b2):
            беды.append(f"третья точка НЕ на пути: {с[:80]}")
        break
    # ТРЕТИЙ РОД ОБЯЗАН БЫТЬ СТРОГИМ: путь через угол ДЛИННЕЕ прямого.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "через третью" or я != "ru":
            continue
        пары = _БОЛЬШЕ.findall(с)
        if not пары:
            беды.append(f"третий род без сравнения: {с[:70]}")
        break
    print(f"РАССТОЯНИЕ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
