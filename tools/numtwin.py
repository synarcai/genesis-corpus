"""ДВОЙНИК ЧИСЛА — цифра и слово на одной странице как РАВНЫЕ: «40 — это сорок».

    ЦИФРА И СЛОВО СУТЬ ДВА ПИСЬМА ОДНОГО ЧИСЛА, И РАВЕНСТВО ИХ НАДО ПОКАЗАТЬ, А НЕ ВЫВЕСТИ.

ЗАМЕР 21.09: миров, где цифра и слово стоя́т РЯДОМ как двойники («20 = twenty», «сорок — это
40»), у свода НЕТ НИ ОДНОГО. Дом чтения чисел (`readnum`, 3 240 показов) учит иному — он
читает список вещей и спрашивает об их числе; слово-числительное живёт у него в вопросе, а
не против своей цифры.

ПОВОД ПРИШЁЛ ОТ СОСЕДА (holon-87, рынок счёта): организм, встречая цепь двадцаток, ценит
звено НОМЕРОМ в цепи — «venti» становится единицей, «quaranta» двойкой, «cento» пятёркой, —
ибо масштабировать цепь ему нечем. Масштаб даёт ЗАСВИДЕТЕЛЬСТВОВАННЫЙ член: слово, у
которого в показах есть двойник-цифра. Двойников же у десятков и сотни не было.

    ЗНАНИЕ, КОТОРОЕ ЧИТАТЕЛЬ ВЫВОДИТ ИЗ ПОРЯДКА, А НЕ ИЗ ПОКАЗА, ДЕРЖИТСЯ РОВНО ДО ПЕРВОЙ
    ПЕРЕСТАНОВКИ. Цепь, где «сорок» стои́т вторым, учит, что сорок есть два, — и учит этому
    тем вернее, чем стройнее цепь.

ЧИСЛА ВЗЯТЫ ДЕСЯТКАМИ И СОТНЕЙ (20…100), ибо именно их не было; единицы и подростки у свода
показаны довольно. СЛОВА БЕРУТСЯ ИЗ `numerals` ПАКЕТА, а не пишутся здесь вторым списком.

    python3 tools/numtwin.py    # самопроверка с мутантами
"""
