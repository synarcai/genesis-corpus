#!/usr/bin/env python3
"""ДОМ ДВУХ УСЛОВИЙ — вывод, которому мало ОДНОГО основания.

    ВЕСЬ ВЫВОД СВОДА ИДЁТ ОТ ОДНОЙ ПОСЫЛКИ. Дом строгого вывода: «12 делится на 4. значит 12
    делится на 2» — посылка одна. Дом исключения: «остаток не 0 и не 1, значит он 2» — ряд
    сужается отрицаниями, но заключение опирается на исчерпание, а не на СЛОЖЕНИЕ доводов.
    Замер 10.09 по связкам рассуждения: «во-первых» — НОЛЬ вхождений, «во-вторых» — НОЛЬ,
    «например» — НОЛЬ, «однако» — НОЛЬ. Свод не перечисляет доводов, ибо ему довольно одного.

    ВЫВОД, КОТОРОМУ ХВАТАЕТ ОДНОГО ДОВОДА, НЕ УЧИТ ПРОВЕРЯТЬ ВТОРОЙ. А в жизни условий два и
    больше, и всякое из них может подвести порознь.

ЧЕТЫРЕ РОДА, И ЭТО ПОЛНАЯ ТАБЛИЦА КОНЪЮНКЦИИ, ПОКАЗАННАЯ СЧЁТОМ, А НЕ БУКВАМИ:

    оба        подходит ли 14? 14 чётно: 14 = 2 × 7, и 14 больше 10. оба условия выполнены,
               и 14 подходит.                                            ← И · И
    первое     подходит ли 15? 15 нечётно: 15 = 2 × 7 + 1, хотя 15 больше 10. первое условие
               не выполнено, и 15 не подходит.                            ← ЛОЖЬ · И
    второе     подходит ли 8? 8 чётно: 8 = 2 × 4, но 8 не больше 10. второе условие не
               выполнено, и 8 не подходит.                                ← И · ЛОЖЬ
    ни одного  подходит ли 7? 7 нечётно: 7 = 2 × 3 + 1, и 7 не больше 10. ни одно условие
               не выполнено, и 7 не подходит.                             ← ЛОЖЬ · ЛОЖЬ

ВТОРОЙ И ТРЕТИЙ РОД СУТЬ МИНИМАЛЬНАЯ ПАРА, И БЕЗ НЕЁ ДОМ БЫЛ БЫ ПОЛОВИНОЙ СЕБЯ: подводит то
первое условие, то второе, и вердикт один и тот же. Читатель, увидевший обе, не может решить,
что важно лишь начало проверки.

ЧЕТВЁРТЫЙ РОД НЕ ЛИШНИЙ, ХОТЯ И «ОЧЕВИДЕН»: без него таблица неполна, а неполная таблица учит
угадывать недостающую клетку. Здесь она показана.

СЛОВА «ХОТЯ» И «НО» СТОЯ́Т НЕ ДЛЯ КРАСОТЫ: они несут УСТУПКУ — признание довода, который
всё-таки не спасает. Свод знал «но» шестнадцать тысяч раз и «хотя» тридцать три; здесь уступка
стои́т там, где она и есть логически, — между выполненным условием и общим отказом.

ОБА УСЛОВИЯ ПРОВЕРЯЮТСЯ СЧЁТОМ, А НЕ ОБЪЯВЛЕНИЕМ: чётность — записью «n = 2 × k» или
«n = 2 × k + 1», величина — сравнением с порогом. Суд пересчитывает и то и другое, и потому
подмена любого числа ловится.

    python3 tools/bothforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("оба", "первое", "второе", "ни одного")
# ПОРОГ НЕ ОДИН, И ЭТО КУПЛЕНО МЕРОЙ МАССЫ. При единственном пороге 10 клетки «второе
# условие» и «ни одного» набирали по пяти и четыре страницы — меньше девяти, то есть
# НЕПОКУПАЕМЫ: чисел, меньших десяти, всего девять. Порогов дано три, и каждая клетка таблицы
# наполняется до покупаемой.
#
#     ТАБЛИЦА, ЧЬЯ КЛЕТКА ПОКАЗАНА ЧЕТЫРЕ РАЗА, УЧИТ ТРЁМ КЛЕТКАМ ИЗ ЧЕТЫРЁХ.
ПОРОГИ = (10, 20, 30)

РАМКИ = {
    "ru": {
        "оба": "нужно число чётное и большее {порог}. подходит ли {n}? во-первых, {n} чётно: {n} = 2 × {k}. во-вторых, {n} больше {порог}. оба условия выполнены, и {n} подходит.",
        "первое": "нужно число чётное и большее {порог}. подходит ли {n}? {n} нечётно: {n} = 2 × {k} + 1, хотя {n} больше {порог}. первое условие не выполнено, и {n} не подходит.",
        "второе": "нужно число чётное и большее {порог}. подходит ли {n}? {n} чётно: {n} = 2 × {k}, но {n} не больше {порог}. второе условие не выполнено, и {n} не подходит.",
        "ни одного": "нужно число чётное и большее {порог}. подходит ли {n}? {n} нечётно: {n} = 2 × {k} + 1, и {n} не больше {порог}. ни одно условие не выполнено, и {n} не подходит.",
    },
    "en": {
        "оба": "a number must be even and greater than {порог}. does {n} fit? first, {n} is even: {n} = 2 × {k}. second, {n} is greater than {порог}. both conditions hold, and {n} fits.",
        "первое": "a number must be even and greater than {порог}. does {n} fit? {n} is odd: {n} = 2 × {k} + 1, though {n} is greater than {порог}. the first condition fails, and {n} does not fit.",
        "второе": "a number must be even and greater than {порог}. does {n} fit? {n} is even: {n} = 2 × {k}, but {n} is not greater than {порог}. the second condition fails, and {n} does not fit.",
        "ни одного": "a number must be even and greater than {порог}. does {n} fit? {n} is odd: {n} = 2 × {k} + 1, and {n} is not greater than {порог}. neither condition holds, and {n} does not fit.",
    },
}


def _род(n, ПОРОГ):
    """Какая клетка таблицы приходится на это число — по счёту, а не по списку."""
    чётно, больше = n % 2 == 0, n > ПОРОГ
    if чётно and больше:
        return "оба"
    if больше:
        return "первое"
    return "второе" if чётно else "ни одного"


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for порог in ПОРОГИ:
            for n in range(2, порог + 13):
                род = _род(n, порог)
                поля = dict(n=n, k=n // 2, порог=порог)
                вон[рамки[род].format(**поля)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ГРАНИЦА ЦИФРЫ ОБЯЗАТЕЛЬНА, И ЭТО КУПЛЕНО САМОПРОВЕРКОЙ. Образец без `(?!\d)` брал из
# «21 = 2 × 10 + 1» подстроку «21 = 2 × 1» — единицу из десятки, — и объявлял честную страницу
# ложной: 21 ≠ 2 × 1. Тот же род лжи корпус знает под именем «ложь по цифре».
_ЧЁТНО = re.compile(r"(\d+) = 2 × (\d+)(?!\d)(?! \+)")
_НЕЧЁТНО = re.compile(r"(\d+) = 2 × (\d+) \+ 1(?!\d)")
_БОЛЬШЕ = re.compile(r"(\d+) (?:больше|is greater than) (\d+)")
_НЕ_БОЛЬШЕ = re.compile(r"(\d+) (?:не больше|is not greater than) (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ, И СЧИТАЕТСЯ ТОЛЬКО ОТВЕЧАЮЩАЯ ЧАСТЬ: условие,
    # названное в зачине («нужно число чётное и большее 10»), есть УСЛОВИЕ ЗАДАЧИ, а не
    # утверждение о числе, и пересчитывать в нём нечего.
    ответ = с.split("?", 1)[1] if "?" in с else с
    for n, k in _ЧЁТНО.findall(ответ):
        if int(n) != 2 * int(k):
            return True, False
    for n, k in _НЕЧЁТНО.findall(ответ):
        if int(n) != 2 * int(k) + 1:
            return True, False
    for a, b in _БОЛЬШЕ.findall(ответ):
        if int(a) <= int(b):
            return True, False
    for a, b in _НЕ_БОЛЬШЕ.findall(ответ):
        if int(a) > int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:74]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    оба = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "оба")
    вто = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "второе")
    if судить(оба.replace("чётно:", "чётн:"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(вто.replace("выполнено", "выполнен"))[1] is not False:
        беды.append("обрезанное слово во втором прошло")
    if судить(оба + " " + оба)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ДВА УСЛОВИЯ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
