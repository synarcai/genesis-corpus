#!/usr/bin/env python3
"""РОМАНСКОЕ ВОПРОСНОЕ СЛОВО: один дом закона, которым пользуются все.

    СЛУЖЕБНОЕ СЛОВО, СТОЯЩЕЕ В РАМКЕ ЦЕЛЫМ, НЕ СЛЫШИТ ТОГО, ЧТО ЗА НИМ ПОДСТАВЯТ.

Испанское «cuántos», итальянское «quanti» и португальское «quantos» согласуются в роде с тем,
о чём спрашивают: «cuántas manzanas», «quante mele», «quantas maçãs». Это не оттенок речи, а
её закон — «quanti mele» есть ошибка, а не вариант, — и рамка, держащая вопросное слово ЦЕЛЫМ,
нарушает его молча: она не знает, что за ним подставят.

ЦЕНА, КОТОРОЙ КУПЛЕН ЭТОТ ДОМ (12.09). Прибор перекоса согласования (`scripts/agree_skew.py`),
написанный ради РОВНОСТИ показа, на первом же прогоне по своду назвал не неровность, а ЛОЖЬ:
«quanti mele» 3 страницы против «quante mele» 411, «quantos mensagens» 208, «quanti voci» 213,
«cuántos horas» 15. Семь домов писали вопросное слово вписанным в рамку, и ни один суд свода
этого не видел.

    МЕРА, ПОСТАВЛЕННАЯ РАДИ РОВНОСТИ, НАШЛА ЛОЖЬ: неровность показа и ложь согласования суть
    ОДИН И ТОТ ЖЕ СЛЕД, и отличает их лишь то, есть ли у формы верная сестра.

ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ. Здесь — ПАРЫ вопросного слова по роду и правило выбора. Здесь НЕТ
рода вещей: он принадлежит тому дому, чьи вещи, и объявляется там (`toolforms.РОД`,
`cmpforms.РОД_ВЕЩЕЙ`, `timeunits.РОД_МАЛОЙ`, …). Дом языка знает язык, дом вещей знает вещи.

    python3 tools/romgram.py    # самопроверка
"""
import re

# ЯЗЫК → (мужское, женское). Язык, чьё вопросное слово рода не знает, сюда не входит вовсе:
# пустая пара сказала бы, что закон есть и не сработал, а его нет.
ПАРЫ = {
    "es": ("cuántos", "cuántas"),
    "it": ("quanti", "quante"),
    "pt": ("quantos", "quantas"),
}


# АРТИКЛЬ И НЕОПРЕДЕЛЁННОЕ ПРИ ИМЕНИ — ТОТ ЖЕ ЗАКОН, ЧТО И ВОПРОСНОЕ СЛОВО (12.09). Служебное
# слово, стоящее в рамке целым, не слышит того, что за ним подставят, — будь то «cuántos» или
# «el». Таблица объявлена ЗДЕСЬ, чтобы страж (`scripts/twogender.py`) сверял артикль с родом
# имени, объявленным домом этого имени.
#
# СЛОВА ЭТИ МНОГОЗНАЧНЫ: португальское «a» есть и артикль, и предлог; итальянское «le» — и
# артикль, и местоимение; испанское «la» — и артикль, и местоимение. Двусмысленность НИЧЕГО
# не стои́т, покуда сверка идёт лишь там, где род следующего слова ОБЪЯВЛЕН: «a mesa» сверится,
# «a Ana» — нет, ибо род имени лица здесь не объявлен никем.
#
# ИТАЛЬЯНСКОЕ «un'» ЕСТЬ ЖЕНСКОЕ, А «un» — МУЖСКОЕ, и различает их АПОСТРОФ, а не буква:
# читающий обязан смотреть на сырую строку, а не на разбитые слова. Признак назван в стра́же.
#
# ПОЧЕМУ ЗДЕСЬ НЕТ НЕМЕЦКОГО И ФРАНЦУЗСКОГО — ЗАМЕРЕНО, А НЕ РЕШЕНО (12.09). Немецкий артикль
# гнётся ПО ПАДЕЖУ, и один и тот же «der» есть мужской именительный И женский дательный: сверка
# по роду назвала бы ложью 177 верных «der Lampe», 152 верных «dem Buch», 35 верных «der
# Bücher». Французский же и без того показан обеими сторонами — мир языка держит «le livre est
# petit» рядом с «¬ la livre est petit», — и сверка нашла в нём ровно эти пять объявленных
# ложными строк и ни одной иной.
#
#     АРТИКЛЬ, ГНУЩИЙСЯ ПО ПАДЕЖУ, НЕ ЕСТЬ ЗНАК ОДНОГО РОДА, И МЕРА, ЧИТАЮЩАЯ ЕГО РОДОМ,
#     СЧИТАЕТ ПАДЕЖИ ОШИБКАМИ.
#
# Испанский, итальянский и португальский падежом артикля не гнут — оттого закон здесь и о них.
АРТИКЛИ = {
    "es": {"el": "m", "los": "m", "un": "m", "unos": "m",
           "la": "f", "las": "f", "una": "f", "unas": "f"},
    "it": {"il": "m", "lo": "m", "i": "m", "gli": "m", "un": "m", "uno": "m",
           "la": "f", "le": "f", "una": "f"},
    "pt": {"o": "m", "os": "m", "um": "m", "uns": "m",
           "a": "f", "as": "f", "uma": "f", "umas": "f"},
}
# СЛОВО, ЧЬЁ ЖЕНСКОЕ ПИШЕТСЯ С АПОСТРОФОМ: «un'ora» женское, «un tavolo» мужское.
С_АПОСТРОФОМ = {"it": {"un": "f"}}


def артикль(язык, слово, апостроф=False):
    """Род, какой служебное слово назначает следующему имени; не артикль — None."""
    ряд = АРТИКЛИ.get(язык)
    if not ряд:
        return None
    низ = слово.lower()
    if апостроф and низ in С_АПОСТРОФОМ.get(язык, {}):
        return С_АПОСТРОФОМ[язык][низ]
    return ряд.get(низ)


def гнётся(язык):
    """True, если вопросное слово этого языка согласуется в роде."""
    return язык in ПАРЫ


def вопросное(язык, род):
    """Вопросное слово языка для рода «m» или «f»; язык без гнутья даёт пустую строку."""
    пара = ПАРЫ.get(язык)
    if not пара:
        return ""
    return пара[0] if род == "m" else пара[1]


def по_слову(язык, слово, роды, умолчание=None):
    """Вопросное слово, согласованное с ИМЕНЕМ, чей род объявлен домом этого имени.

    РОД БЕРЁТСЯ У ХОЗЯИНА ИМЕНИ, А НЕ УГАДЫВАЕТСЯ ПО ОКОНЧАНИЮ: «la mano» кончается на «-o» и
    женского рода, «il problema» — на «-a» и мужского. Имя, чьего рода хозяин не объявил, есть
    беда объявления, а не строки: без `умолчание` дом падает здесь, а не пишет ложь.
    """
    if язык not in ПАРЫ:
        return ""
    род = роды.get(слово, умолчание)
    if род is None:
        raise KeyError(f"род имени «{слово}» ({язык}) не объявлен")
    return вопросное(язык, род)


def в_образце(язык, экранировать=re.escape):
    """Кусок образца, где вопросное слово принимает ОБЕ формы: образец не решает, какая верна."""
    пара = ПАРЫ.get(язык)
    if not пара:
        return ""
    return "(?:" + "|".join(экранировать(с) for с in пара) + ")"


def _самопроверка():
    assert вопросное("it", "f") == "quante" and вопросное("it", "m") == "quanti"
    assert вопросное("ru", "f") == "", "язык без гнутья обязан молчать, а не выдумывать"
    assert not гнётся("ru") and гнётся("pt")
    роды = {"mele": "f", "libri": "m"}
    assert по_слову("it", "mele", роды) == "quante"
    assert по_слову("it", "libri", роды) == "quanti"
    assert по_слову("ru", "яблоки", роды) == "", "чужой язык не спрашивается о роде вовсе"
    # ИМЯ БЕЗ ОБЪЯВЛЕННОГО РОДА РОНЯЕТ ДОМ, А НЕ ПИШЕТ ЛОЖЬ — обе стороны показаны.
    try:
        по_слову("it", "penne", роды)
    except KeyError:
        pass
    else:
        raise AssertionError("имя без объявленного рода прошло молча")
    assert по_слову("it", "penne", роды, умолчание="f") == "quante", "умолчание объявляется явно"
    assert артикль("es", "la") == "f" and артикль("es", "el") == "m"
    assert артикль("it", "un") == "m" and артикль("it", "un", апостроф=True) == "f", \
        "«un'ora» женское, и различает их АПОСТРОФ"
    assert артикль("pt", "Ana") is None, "не артикль — не род"
    assert артикль("de", "der") is None, "язык без гнутья артикля не имеет здесь вовсе"
    об = в_образце("it")
    assert re.fullmatch(об, "quanti") and re.fullmatch(об, "quante")
    assert в_образце("de") == "", "язык без гнутья не даёт куска образца"
    print(f"  языков с гнутьём: {len(ПАРЫ)}; артиклей объявлено: "
          f"{sum(len(р) for р in АРТИКЛИ.values())}; пары: "
          + ", ".join(f"{я}: {м}/{ж}" for я, (м, ж) in sorted(ПАРЫ.items())))


if __name__ == "__main__":
    _самопроверка()
