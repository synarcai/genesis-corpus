#!/usr/bin/env python3
"""СОСТАВ СЛОВА: «talo + ssa = talossa» — слово есть склейка частей.

    ЯЗЫК, ПОКАЗАННЫЙ ТОЛЬКО ЦЕЛЫМИ СЛОВАМИ, УЧИТ СПИСКУ СЛОВ, А НЕ СЛОВООБРАЗОВАНИЮ.

ЗАМЕР, ВСКРЫВШИЙ БЕДУ (свод 382 125 строк, 07.09):

    страниц вида «слово + часть = слово»            НОЛЬ
        (52 совпадения оказались арифметикой: «8 + 9 = 17»)
    «приставка» 0 · «корень слова» 0 · «prefix» 0 · «suffix» 0 · «суффикс» 4
    финский: talossa 10, talosta 10 — а taloissa 0, taloista 0
    турецкий: kitap/kitaplar — и больше ничего

Двенадцать финских падежей, показанных двенадцатью ГОТОВЫМИ формами, суть двенадцать слов;
тот же ряд, показанный как «talo + ssa = talossa», есть ОДИН закон.

ДОМ НЕ ПРИНОСИТ НОВОГО ЗНАНИЯ О ЯЗЫКЕ И НЕ ТРОГАЕТ ПАКЕТОВ. Он показывает состав ТЕХ форм,
которые пакеты УЖЕ объявили, и только там, где основа стои́т неизменной: если объявленная
форма начинается с леммы, остаток есть часть, и склейка проверяема счётом.

    794 такие формы из 3978 объявленных, в двадцати двух языках:
    hu 98 · fi 60 · fr 55 · ko 54 · pt 53 · ru 53 · es 51 · ta 50 · he 45 · nl 44 · id 42
    fa 37 · tr 31 · en 29 · pl 24 · de 17 · sv 13 · hi 7 · uk 6 · am 4 · ka 2

ЧЕГО ДОМ НЕ ПОКАЗЫВАЕТ, И ЭТО СКАЗАНО. Форм со СМЕНОЙ ОСНОВЫ («kitap → kitabım», «стол →
стлы») он не берёт: склейка их не даёт, и страница «kitap + ım = kitabım» была бы ложью
счёта при верности языку. Их состав есть иной закон (чередование), и он ждёт своего дома.
Не берёт он и «частей» с пробелом внутри («mtu + ' mmoja'» суахили): пробел есть граница
слова, а не шов внутри него.

    ЧАСТЬ, ПРИКЛЕЕННАЯ НЕ СКЛЕЙКОЙ, НЕ ЕСТЬ ЧАСТЬ ЭТОГО ДОМА. Дом, взявший её, учил бы
    склейке там, где её нет, — и суд, проверяющий склейку, назвал бы собственную страницу
    ложью.

ДВЕ СТУПЕНИ («talo + i + ssa») здесь НЕ показаны: пакеты их не объявляют (taloissa 0 во всём
своде). Это названная дыра, а не забытая.
"""
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))
from layer import PASSES, emit  # noqa: E402

ЦЕЛЬ = "datasets/genesis_wordparts.txt"
ПАКЕТЫ = КОРЕНЬ / "tools" / "langpacks"


def составы():
    """(язык, лемма, часть, слово) для каждой объявленной формы, наращивающей лемму."""
    вон = []
    for п in sorted(ПАКЕТЫ.glob("*.json")):
        пак = json.loads(п.read_text(encoding="utf-8"))
        я = пак.get("lang", п.stem)
        # ПИСЬМО БЕЗ ПРОБЕЛОВ НЕ РЕЖЕТСЯ ПО КРАЮ СЛОВА, и шов в нём — иной вопрос
        if пак.get("segmentation") == "longest-match":
            continue
        видано = set()
        for _имя, кл in (пак.get("morph_classes") or {}).items():
            for лемма, формы in (кл.get("lexemes") or {}).items():
                for ф in формы:
                    ф = str(ф)
                    if ф == лемма or not ф.startswith(лемма) or len(ф) <= len(лемма):
                        continue
                    часть = ф[len(лемма):]
                    if " " in часть or " " in лемма:
                        continue          # пробел есть граница слова, а не шов
                    ключ = (я, лемма, часть)
                    if ключ in видано:
                        continue
                    видано.add(ключ)
                    вон.append((я, лемма, часть, ф))
    return вон


СОСТАВЫ = составы()


def pass_shows(pass_i):
    из = [с for k, с in enumerate(СОСТАВЫ) if k % len(PASSES) == pass_i]
    out = []
    for я, лемма, часть, слово in из:
        out.append(f"{лемма} + {часть} = {слово}.")
        out.append(f"what is {лемма} + {часть}? {лемма} + {часть} = {слово}.")
        out.append(f"сколько будет {лемма} + {часть}? {лемма} + {часть} = {слово}.")
        out.append(f"{слово} is {лемма} with the ending -{часть}.")
        out.append(f"{слово} — это {лемма} с окончанием -{часть}.")
        out.append(f"what is {слово} made of? {слово} is {лемма} with the ending -{часть}.")
        out.append(f"из чего состои́т {слово}? {слово} — это {лемма} "
                   f"с окончанием -{часть}.")
    return out





def main():
    emit(ЦЕЛЬ, pass_shows)


if __name__ == "__main__":
    main()
