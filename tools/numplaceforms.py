    print(f"  страниц {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, пластов {len(ПЛАСТЫ)}, мест "
          f"{len(МЕСТА)} ({местами}), пар форм {sum(sum(по.values()) for по in МЕСТА.values())}, "
          f"счётной речью {len(СЧЁТНОЙ_РЕЧЬЮ)}, отказов половинных {len(ПОЛОВИННЫЕ)}, "
          f"цитат сверено {сверено}, форм найдено в пластах {в_пласте} (мимо {len(мимо)}), "
          f"мутантов поймано {мутантов}, бед {беды}")
    return беды


