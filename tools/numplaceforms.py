def _пакет(код):
    return json.loads((ДВОР / f"{код}.json").read_text(encoding="utf-8"))


def место(ед, мн):
    """ГДЕ РАЗОШЛИСЬ ДВЕ ОБЪЯВЛЕННЫЕ ФОРМЫ — вычислено сравнением, а не объявлено списком.

    Порядок проверок значим: сперва пропажа и прибавка ЦЕЛОГО СЛОВА, потом служебное слово,
    и лишь затем буквы. Иначе «en bok» → «böcker» читалось бы как перестройка изнутри.
    """
    if ед == мн:
        return НИГДЕ
    сл_е, сл_м = ед.split(), мн.split()
    if len(сл_м) > len(сл_е):
        return ВПЕРЕДИ if мн.endswith(ед) else ЗАМЕНЕНО
    if len(сл_м) < len(сл_е):
        return УБРАНО
    if len(сл_е) == 2:
        # ДВА СЛОВА: служебное впереди, имя позади — и число может стоять в любом из них.
        if сл_е[1] == сл_м[1]:
            return СЛУЖЕБНОЕ
        if сл_е[0] != сл_м[0]:
            return СЛУЖЕБНОЕ_И_ИМЯ
    if мн.startswith(ед):
        return ХВОСТ
    if мн.endswith(ед):
        return ГОЛОВА
    зачин = 0
    while зачин < min(len(ед), len(мн)) and ед[зачин] == мн[зачин]:
        зачин += 1
    хвост = 0
    while хвост < min(len(ед), len(мн)) - зачин and ед[-1 - хвост] == мн[-1 - хвост]:
        хвост += 1
    if зачин and хвост:
        return ВНУТРИ
    if зачин:
        return ХВОСТ
    if хвост:
        return ГОЛОВА
    return ЗАМЕНЕНО


def счётная_речь(код, тело):
    """Пласт, у которого клетка МНОЖЕСТВЕННОГО держит СЧЁТНУЮ РЕЧЬ, а не форму имени.

    ЯПОНСКИЙ И ТАЙСКИЙ МНОЖЕСТВЕННОГО ЧИСЛА У ИМЕНИ НЕ ИМЕЮТ, и пакет кладёт в его клетку
    оборот «三枚のカード» — «три листа карт». Место, вычисленное для такого пласта, есть место
    СЧЁТНОГО СЛОВА, а не знака числа, и звать его знаком числа значило бы приписать языку
    категорию, которой у него нет.

        КЛЕТКА, НАЗВАННАЯ «МНОЖЕСТВЕННЫМ», МОЖЕТ ДЕРЖАТЬ НЕ ФОРМУ, А ОБОРОТ, — и узнаётся
        это по числительному внутри неё, а не по имени клетки.

    Признак — ДЕЛОМ: в клетке множественного стои́т числительное того же пакета.
    """
    чис = {(тело.get("numerals") or {}).get(str(n)) for n in range(1, 21)}
    чис.discard(None)
    лекс = ((тело.get("morph_classes") or {}).get("noun_count") or {}).get("lexemes") or {}
    сколько = sum(1 for ф in лекс.values()
                  if len(ф) >= 2 and any(numerals.стоит_словом(с, ф[1]) for с in чис))
    return сколько and сколько * 2 >= len(лекс)


def _собрать():
    """{код: {место: [(имя, ед, мн)]}} — по объявленному счётному ряду имени."""
    вон = {}
    for путь in sorted(ДВОР.glob("*.json")):
        тело = _пакет(путь.stem)
        лекс = ((тело.get("morph_classes") or {}).get("noun_count") or {}).get("lexemes") or {}
        по_месту = {}
        for имя, формы in лекс.items():
            if len(формы) < 2 or not формы[0] or not формы[1]:
                continue
            по_месту.setdefault(место(формы[0], формы[1]), []).append(
                (имя, формы[0], формы[1]))
        if по_месту:
            вон[путь.stem] = по_месту
    return вон


def _половинные():
    """[(код, отвергнутое, замена, имя, ед, мн)] — отказы, где число сказано НАПОЛОВИНУ.

    ОТБОР ДЕЛОМ: пласт держит артикль ВНУТРИ счётной клетки (`count_one`/`count_many` рядом
    с `one`/`many`), и в отвергнутой строке стои́т артикль множественного при голом имени
    единственного. Испанский и португальский сюда не идут: там артикль ошибается РОДОМ.
    """
    вон = []
    for путь in sorted(ДВОР.glob("*.json")):
        тело = _пакет(путь.stem)
        ряд = ((тело.get("morph_classes") or {}).get("noun_count") or {})
        if "count_many" not in (ряд.get("forms") or ()):
            continue
        лекс = ряд.get("lexemes") or {}
        for пр in ((тело.get("show_kinds") or {}).get("refusals") or {}).get("pairs", ()):
            if пр.get("reason") != "agreement":
                continue
            плохо = (пр.get("bad") or "").strip().rstrip(КОНЕЦ_ФРАЗЫ)
            хорошо = (пр.get("good") or "").strip().rstrip(КОНЕЦ_ФРАЗЫ)
            if not плохо or not хорошо:
                continue
            for имя, ф in лекс.items():
                if len(ф) < 4 or " " not in ф[1]:
                    continue
                артикль = ф[1].split()[0]
                if артикль in плохо.split() and ф[2] in плохо.split() and ф[3] in хорошо.split():
                    вон.append((путь.stem, плохо, хорошо, имя, ф[0], ф[1]))
                    break
    return вон


