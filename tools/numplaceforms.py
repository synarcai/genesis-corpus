def _перечень(коды, язык):
    имена = [ИМЯ_ЯЗЫКА[к][0 if язык == "ru" else 1] for к in коды if к in ИМЯ_ЯЗЫКА]
    if len(имена) == 1:
        return имена[0]
    союз = " и " if язык == "ru" else " and "
    return ", ".join(имена[:-1]) + союз + имена[-1]


def _слово_пласт(n, язык):
    """Счётная форма слова «пласт» — законом, а не рукой: 1 пласт, 3 пласта, 6 пластов."""
    return (units.ру_форма(("пласт", "пласта", "пластов"), n) if язык == "ru"
            else units.ан_форма(("layer", "layers"), n))


