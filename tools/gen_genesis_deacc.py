#!/usr/bin/env python3
"""GENESIS layer: НЕМЕЦКИЙ ВИНИТЕЛЬНЫЙ ПРИ ГЛАГОЛЕ — see tools/deaccforms.py for the law.

ГРУППЫ СЛОЖЕНЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ОТНИМАЮТ.

«Падеж при глаголе» и «меняется ли артикль» идут вместе: первое даёт ПРАВИЛО, второе отнимает
вывод «значит, перемена видна всегда» — у женского и среднего её нет.

    ПРАВИЛО, ДАННОЕ БЕЗ СВОИХ ЛОЖНЫХ СЛЕДСТВИЙ, УЧИТ ИМ НАРАВНЕ С СОБОЮ.

«Род и падеж одним словом» и оба рода о соседе — второй группой: все три о ГРАНИЦАХ. Первый
внутрь языка («den» не есть четвёртый род), два прочих наружу — и они ВЗАИМНО ИСКЛЮЧАЮТ друг
друга, а стоя́т в одной группе: читатель, увидевший в одном проходе обе половины, видит закон
целиком.

«Спрошено и отвечено» — третьей.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import deaccforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_deacc.txt"
ГРУППЫ = (("падеж при глаголе", "меняется ли артикль"),
          ("род и падеж одним словом", "сосед меняет само имя", "сосед не меняет ничего"),
          ("спрошено и отвечено",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
