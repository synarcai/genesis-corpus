#!/usr/bin/env python3
"""УКАЗАТЕЛЬ ПРИБОРОВ — что свод меряет о самом себе, и чем он себе должен.

Свод держит сто семьдесят семь приборов, и всякий объявляет, как его позвать с пустым обходом —
то есть чем доказать, что он умеет ОТКАЗАТЬ, а не только соглашаться. Сто двадцать пять из них
несут РУБЕЖ ДОЛГА: число, ниже которого прибор молчит, а выше — падает.

    РУБЕЖ ЕСТЬ ОБЪЯВЛЕННЫЙ ДОЛГ, А НЕ ПОБЛАЖКА: он говорит, сколько беды свод знает за собой
    и согласен нести, покуда не уплатит.

Замер 12.09: 141 рубеж на 125 приборов, и сумма объявленного долга — ШЕСТНАДЦАТЬ ТЫСЯЧ
ВОСЕМЬСОТ ШЕСТЬДЕСЯТ ШЕСТЬ. Числа этого нет нигде, кроме как в ста двадцати пяти файлах
порознь.

ТРИ РУБЕЖА ЖИВУТ ВНЕ ПРИБОРОВ и в сумму эту не входят: `scripts/cell_shown.py` (32),
`scripts/pack_singular_risk.py` (0) и `courts/money_court.py` (0). Я проверил их: все трое
названы в `scripts/courts.sh` и все трое стоя́т в леджере — долг их МЕРЯЕТСЯ, просто носитель
не объявил пустого обхода. Указатель их не берёт: он считает по объявлению, а не по месту
в дереве, и пусть лучше сумма будет меньше правды, чем собрана по двум разным признакам.

ЧТО В УКАЗАТЕЛЕ. Имя прибора, его рубежи поимённо со значениями и ПОСЛЕДНИЙ ВЕРДИКТ из леджера —
взятый ДОСЛОВНО, без разбора.

    ВЕРДИКТ ПИСАН ДЛЯ ЧИТАТЕЛЯ, А НЕ ДЛЯ РАЗБОРА: число в нём стои́т там, где его удобнее
    прочесть глазом. Потому он переносится целиком, а не пересказывается числом.

Это куплено отказом: вечером 11.09 я пробовал вывести «слабину рубежа» — насколько дело ниже
объявленного, — и два честных разбора одной строки дали 3845 и 4974. Прибора не вышло; вышел
указатель, который кладёт вердикт рядом с рубежом и оставляет сравнение глазу.

КУПЛЕНО ПАДЕНИЕМ. Как только указатель встал в `tools/`, суд состава упал.
Указатель СЧЁЛ ПРИБОРОМ САМОГО СЕБЯ: в нём стои́т строка `ПРИЗНАК = "ПУСТОЙ-ОБХОД"`,
а признак искался ПОДСТРОКОЙ.

    ПРИЗНАК, ИСКОМЫЙ ПОДСТРОКОЙ, НАХОДИТСЯ В ТОМ, КТО О НЁМ ГОВОРИТ.

Та же беда лежала и в суде состава — он искал так же и падал бы на всяком, кто помянет
помету. Оба правлены разом: признак опознаётся ПОМЕТОЙ В НАЧАЛЕ СТРОКИ (`^# ПУСТОЙ-ОБХОД:`),
а не упоминанием где придётся. Из ста семидесяти восьми поминающих помету несут ровно сто
семьдесят семь; расхождение было одно — этот файл.

ПОЧЕМУ ОРУДИЕ, А НЕ СУД: указатель зависит и от всякого файла дерева, и от леджера, который
меняется всяким прогоном набора.

    УКАЗАТЕЛЬ, ЗАВИСЯЩИЙ ОТ ВСЯКОЙ СТРОКИ ДЕРЕВА, НЕ МОЖЕТ БЫТЬ СУДОМ.

    python3 tools/court_atlas.py            # собрать reports/ATLAS-COURTS.md
    python3 tools/court_atlas.py --считать  # только числа
"""
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ДВОРЫ = ("scripts", "courts", "tools")
ЦЕЛЬ = КОРЕНЬ / "reports" / "ATLAS-COURTS.md"
ЛЕДЖЕР = КОРЕНЬ / "reports" / "ledger.tsv"
ПРИЗНАК = re.compile(r"^#\s*ПУСТОЙ-ОБХОД:", re.M)  # ПОМЕТА, А НЕ УПОМИНАНИЕ
МЕТКА = re.compile(r"^#\s*РУБЕЖ-ДОЛГА:\s*([A-ZА-ЯЁ_]+)\s*=\s*(-?\d+)\s*$", re.M)
ЗАЧИН = re.compile(r'^"""\[([^\]]+)\]\s*[—–-]\s*(.+?)(?:\.|$)', re.M)


def вердикты():
    """{имя файла: последняя строка вердикта} — дословно, без разбора."""
    вон = {}
    if not ЛЕДЖЕР.is_file():
        return вон
    for строка in ЛЕДЖЕР.read_text(encoding="utf-8", errors="replace").splitlines():
        поля = строка.split("\t")
        if len(поля) >= 4:
            вон[поля[1]] = поля[3]
    return вон


def приборы(корень):
    """[(двор/имя, заглавие, [(рубеж, значение)])] — по всем дворам."""
    вон = []
    for двор in ДВОРЫ:
        путь = корень / двор
        if not путь.is_dir():
            continue
        for п in sorted(путь.glob("*.py")):
            т = п.read_text(encoding="utf-8", errors="replace")
            if not ПРИЗНАК.search(т):
                continue
            m = ЗАЧИН.search(т)
            заглавие = f"[{m.group(1)}] — {m.group(2).strip()}" if m else ""
            вон.append((f"{двор}/{п.name}", заглавие,
                        [(и, int(з)) for и, з in МЕТКА.findall(т)]))
    return вон


def main():
    все = приборы(КОРЕНЬ)
    с_рубежом = [п for п in все if п[2]]
    сумма = sum(з for _, _, рр in все for _, з in рр)
    if "--считать" in sys.argv:
        print(f"приборов {len(все)}, с рубежом {len(с_рубежом)}, "
              f"рубежей {sum(len(р) for _, _, р in все)}, объявленный долг {сумма}")
        return 0
    в = вердикты()
    out = [f"# УКАЗАТЕЛЬ ПРИБОРОВ — {len(все)} приборов, {len(с_рубежом)} с объявленным долгом",
           "",
           "Собран из дерева и леджера орудием `tools/court_atlas.py`. Прибор опознаётся",
           "объявлением о пустом обходе — тем, чем он доказывает, что умеет ОТКАЗАТЬ.", "",
           "    РУБЕЖ ЕСТЬ ОБЪЯВЛЕННЫЙ ДОЛГ, А НЕ ПОБЛАЖКА: он говорит, сколько беды свод знает",
           "    за собой и согласен нести, покуда не уплатит.", "",
           f"**Сумма объявленного долга: {сумма}** на {sum(len(р) for _, _, р in все)} рубежей.",
           "", "Вердикт перенесён из леджера ДОСЛОВНО: вердикт писан для читателя, а не для",
           "разбора, и число в нём стои́т там, где его удобнее прочесть глазом.", ""]
    for двор in ДВОРЫ:
        свои = [п for п in все if п[0].startswith(двор + "/")]
        if not свои:
            continue
        out += ["", f"## {двор} — {len(свои)} приборов", ""]
        for путь, заглавие, рр in свои:
            имя = pathlib.Path(путь).name
            out.append(f"- **`{путь}`**" + (f" {заглавие}" if заглавие else ""))
            if рр:
                out.append("  рубеж: " + ", ".join(f"`{и}` = {з}" for и, з in рр))
            вер = в.get(имя)
            if вер:
                out.append(f"  последний вердикт: {вер[:150]}")
    ЦЕЛЬ.parent.mkdir(parents=True, exist_ok=True)
    ЦЕЛЬ.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"УКАЗАТЕЛЬ ПРИБОРОВ СОБРАН: {ЦЕЛЬ.name}, приборов {len(все)}, "
          f"с рубежом {len(с_рубежом)}, объявленный долг {сумма}, строк {len(out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
