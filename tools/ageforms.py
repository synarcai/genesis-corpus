#!/usr/bin/env python3
"""ДОМ ВОЗРАСТА — разница лет, которая НЕ МЕНЯЕТСЯ.

Возраст растёт у обоих разом, и разница лет постоянна: в этом весь предмет. Роды
объявлены кузницей тройками «имя, семья случаев, показать».

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

ТАБЛИЦА ПЕРЕИМЕНОВАНА В `СОСТАВ`: имя `РОДЫ` корпус держит за РЯДОМ ИМЁН, и указатель
отвергает дом, положивший под этим именем таблицу.

    ПУСТОЙ РОД НЕ ДАЁТ ШВА — и в этом ЛОВУШКА, которой нет у соседей. Кузница ВЫБРАСЫВАЕТ
    группу, если род промолчал весь проход: «род, промолчавший весь проход, не вправе
    оставить за собою мир из ноля строк». Значит групп бывает МЕНЬШЕ, чем родов.

        ГРУППА, ПРОПУЩЕННАЯ ЗА ПУСТОТУ, СДВИГАЕТ ВСЕ ПОСЛЕДУЮЩИЕ. Род, взятый по НОМЕРУ
        группы, окажется чужим — а мир при этом не шевельнётся, и подпись смолчит: она
        стережёт байты, а не имена над ними.

    Оттого `перебор` метит страницу У СТРОИТЕЛЯ, до всякого выбрасывания, и самопроверка
    сверяет не число групп, а страницы — страница в страницу.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import rugram  # noqa: E402
from plural import by_count  # noqa: E402
import json as _json
import pathlib as _pathlib
import langpack as _langpack  # noqa: E402 — правило согласования при числе

# ГОД НА ЧЕТЫРЁХ ЯЗЫКАХ: ПРАВИЛО — У ПАКЕТА, СЛОВО — У ДОМА.
#
#     ЯЗЫК ЗНАЕТ, КОГДА МЕНЯТЬ ФОРМУ; ЧТО ИМЕННО МЕНЯТЬ — ЗНАЕТ ТОТ, КТО ПИШЕТ СЛОВО.
#
# Русское «год/года/лет» и английское «year/years» дом берёт у `rugram` и `plural` —
# там эти законы объявлены. Немецкого и нидерландского счётного дома в корпусе нет,
# и написать здесь второй список правил значило бы завести четвёртый реестр согласования.
# Оттого дом спрашивает у пакета РОВНО ТО, ЧТО ПАКЕТ ЗНАЕТ, — какую ячейку выбирает число, —
# а сами формы объявляет сам, как объявляет «вдвое» и «twice»: это лексика.
#
# ПОЧЕМУ СЛОВО НЕ УШЛО В ПАКЕТ. Ячейка, объявленная пакетом, обязана быть ПОКАЗАНА в слое
# самого пакета: прибор [ФОРМА БЕЗ ПОКАЗА] держит рубеж 0 при 3576 объявленных формах.
# Немецкая лексема счёта несёт четыре ячейки («jahr, jahre, Jahr, Jahre»), из которых мир
# возраста пишет две; объявить четыре и показать две значило бы КУПИТЬ СЕБЕ ДВА ДОЛГА
# В ЧУЖОМ ДОМЕ за удобство в своём.
_ПАКЕТ = {я: _json.loads((_pathlib.Path(__file__).resolve().parent / "langpacks"
                          / f"{я}.json").read_text(encoding="utf-8"))
          for я in ("de", "nl")}

# Три немецкие формы: при единице «1 Jahr», при прочих «Jahre», а после предлога `in`
# (дательный множественного) «Jahren». Дательное множественное немецкого пакет объявляет
# классом `noun_plural_case` («den büchern», «den häusern») — здесь та же -n, и дом
# сверяет это с пакетом ниже, а не берёт на веру.
ГОД_DE = ("Jahr", "Jahre", "Jahren")
# Нидерландский `jaar` НЕ МЕНЯЕТСЯ при числе, и это ОБЪЯВЛЕНО ПАКЕТОМ, а не решено домом.
ГОД_NL = "jaar"
assert ГОД_NL in _ПАКЕТ["nl"]["invariant_after_numeral"], (
    "пакет nl больше не считает `jaar` неизменяемым при числе — формы дома устарели")
assert "jahr" not in _ПАКЕТ["de"]["invariant_after_numeral"], (
    "пакет de объявил `jahr` неизменяемым — две формы дома стали противоречием")
assert all(ф.endswith("n") for ф in _ПАКЕТ["de"]["morph_classes"]["noun_plural_case"]
           ["lexemes"]["bücher"][2].split()[-1:]), (
    "дательное множественное немецкого больше не на -n — форма «Jahren» без опоры")


def _de_один(k):
    """Единица ли это ПО ПРАВИЛУ ПАКЕТА, а не по сравнению с единицей.

    Правило `count_agreement` немецкого ныне просто («1 → one, прочее → many»), но
    читается оно у пакета: язык, который завёл бы двойственное число, поменял бы
    правило в пакете, и дом пошёл бы за ним, не будучи правленым.
    """
    return _langpack.count_form_index(_ПАКЕТ["de"], {"forms": ["one", "many"]}, k) == 0


def jahre(k):
    """Форма при числе: «1 Jahr», «4 Jahre»."""
    return ГОД_DE[0] if _de_один(k) else ГОД_DE[1]


def jahren(k):
    """Форма после предлога `in`: «in 1 Jahr», «in 4 Jahren»."""
    return ГОД_DE[0] if _de_один(k) else ГОД_DE[2]




# ИМЯ И ЕГО ТРИ ПАДЕЖА: именительный, дательный, родительный. Имена
# взяты на -а/-я и Том — те, чей дательный и родительный коротки и
# ни с чем не спорят. Список МАЛ намеренно: он должен целиком
# повториться в суде второй рукой, а длинный список второй рукой не
# повторяют — его копируют, и копия расходится.
# ФОРМЫ ИМЕНИ — ИЗ ПАКЕТА, СООТВЕТСТВИЕ ИМЁН — ЗДЕСЬ (05.09). Прежде дом держал
# четыре русских имени с тремя падежами частной таблицей — третий реестр лиц
# после пакета и дома отношений, и все три расходились письмом («том» здесь,
# «Том» нигде, «Anna» там). Падеж и письмо суть свойства ИМЕНИ, и знает их
# пакет; дому остаётся то, чего пакет знать не может, — какое английское имя
# каким русским переводится. Это и есть единственное объявление дома, и его же
# суд повторяет второй рукой.
СООТВЕТСТВИЕ = {"Tom": "Том", "Ann": "Аня", "Olya": "Оля", "Misha": "Миша"}
_RU = _json.loads((_pathlib.Path(__file__).resolve().parent / "langpacks" / "ru.json").read_text(encoding="utf-8"))["person_forms"]
_EN = set(_json.loads((_pathlib.Path(__file__).resolve().parent / "langpacks" / "en.json").read_text(encoding="utf-8"))["person_names"])
for _en, _ru in СООТВЕТСТВИЕ.items():
    assert _en in _EN, ("имя не объявлено пакетом en", _en)
    assert _ru in _RU and _RU[_ru].get("dat") and _RU[_ru].get("gen"), ("имя без падежей в пакете ru", _ru)
ЛЮДИ = {en: (ru, _RU[ru]["dat"], _RU[ru]["gen"]) for en, ru in СООТВЕТСТВИЕ.items()}
ИМЕНА = tuple(СООТВЕТСТВИЕ)

# КРАТНОСТЬ СКАЗАНА СЛОВОМ, И СЛОВО ОБЪЯВЛЕНО. «вдвое» не выводится
# из двойки ни в одном языке, и «twice» тем более: это лексика, а не
# правило. Отсюда же берётся предел кратностей — мир не скажет того,
# чего не умеет назвать.
КРАТНЫЕ_СЛОВА = {
    2: ("twice", "вдвое"),
    3: ("three times", "втрое"),
    4: ("four times", "вчетверо"),
    5: ("five times", "впятеро"),
}

# ОТНОШЕНИЕ, О КОТОРОМ НЕ СКАЗАНО: (английское, дательный, предложный).
ОТНОШЕНИЯ = (
    ("brother", "брату", "о брате"),
    ("sister", "сестре", "о сестре"),
    ("neighbour", "соседу", "о соседе"),
)

# ЯДРО ДОСЛОВНЫХ ПОВТОРОВ: столько первых случаев каждого рода стоят
# во ВСЕХ проходах слово в слово.
ЯДРО = 3

ЯДРО_ПАР = (
    ("Tom", "Ann", 12, 7, 3),
    ("Olya", "Misha", 9, 5, 4),
    ("Misha", "Tom", 15, 6, 2),
)
ЯДРО_КРАТНЫХ = (
    ("Tom", "Ann", 4, 3),
    ("Olya", "Misha", 5, 2),
    ("Misha", "Tom", 3, 4),
)
ЯДРО_КРАТНЫХ_ВПЕРЁД = (
    ("Tom", "Ann", 6, 2, 2),
    ("Olya", "Misha", 4, 3, 3),
    ("Misha", "Tom", 5, 2, 1),
)
ЯДРО_ОТКАЗОВ = (
    ("Ann", 0),
    ("Tom", 1),
    ("Olya", 2),
)

# ЛИЦО: (возраст сейчас, сдвиг вперёд). Имени здесь нет вовсе — и в этом весь смысл.
#
#     ЛИЦО НЕ ТРЕБУЕТ ИМЕНИ, И ПОТОМУ ИМЕННО ОНО ОТКРЫВАЕТ МИРУ ЯЗЫК ДЕШЕВЛЕ ВСЕГО:
#     ни падежной таблицы, ни списка имён, ни соответствия между письмом двух языков —
#     одно местоимение, которое язык знает сам.
#
# ЯДРО ВЗЯТО ПО НАЗВАННЫМ ПРОМАХАМ, А НЕ НАУГАД. holon-f9 принёс 13.09 два ключа, на
# которых организм ответил ЗНАКОМ ДЕЙСТВИЯ вместо числа: «ich bin 6 Jahre alt. wie alt
# werde ich in 4 Jahren sein?» и «ik ben 6 jaar oud…» — и восемнадцать немых страниц семьи
# возраста, среди них «Ване 14 лет. сколько лет будет Ване через 9 лет?». Первые два случая
# ядра суть (6, 4) и (14, 9): СВОД ОТВЕЧАЕТ РОВНО НА ТО, НА ЧЁМ ЕГО ПОЙМАЛИ.
ЯДРО_ЛИЦ = ((6, 4), (14, 9), (7, 3))
ЛИЦ_ХОДОМ = 8

ПАР_ХОДОМ = 8
КРАТНЫХ_ХОДОМ = 6
ОТКАЗОВ_ХОДОМ = 3


# ----------------------------------------------------------- ИМЕНА

def именительный(кто):
    return ЛЮДИ[кто][0]


def дательный(кто):
    return ЛЮДИ[кто][1]


def родительный(кто):
    return ЛЮДИ[кто][2]


def лет(сколько):
    return rugram.форма("год", сколько)


def years(сколько):
    return by_count(сколько, "years")


def двое(шаг, i):
    """Два РАЗНЫХ имени: второе берётся сдвигом от первого.

    Сдвиг никогда не нулевой, и потому человек не сравнивается сам с
    собою — а такое сравнение и есть первый способ сделать разницу
    нулём, не заметив этого.
    """
    первый = (шаг + i) % len(ИМЕНА)
    второй = (первый + 1 + i % (len(ИМЕНА) - 1)) % len(ИМЕНА)
    return ИМЕНА[первый], ИМЕНА[второй]


# ---------------------------------------------------------- СЕМЬИ

def пары(шаг):
    """(старший, младший, возраст старшего, возраст младшего, сдвиг)."""
    вон = list(ЯДРО_ПАР)
    for i in range(ПАР_ХОДОМ):
        старший, младший = двое(шаг, i)
        мал = 4 + (шаг * 3 + i * 2) % 12
        разница = 1 + (шаг + i * 3) % 9
        сдвиг = 1 + (шаг * 2 + i) % 7
        вон.append((старший, младший, мал + разница, мал, сдвиг))
    return вон


def кратные(шаг):
    """(старший, младший, возраст младшего, кратность)."""
    вон = list(ЯДРО_КРАТНЫХ)
    for i in range(КРАТНЫХ_ХОДОМ):
        старший, младший = двое(шаг, i)
        мал = 2 + (шаг + i * 2) % 8
        к = 2 + (шаг + i) % len(КРАТНЫЕ_СЛОВА)
        вон.append((старший, младший, мал, к))
    return вон


def кратные_вперёд(шаг):
    """(старший, младший, БУДУЩИЙ возраст младшего, кратность, сдвиг).

    СТРОИТСЯ ОТ БУДУЩЕГО НАЗАД, и это не приём, а единственный честный
    путь. Выбери возраста сейчас — и кратность в будущем окажется
    целой лишь по удаче; выбери будущие — и она истинна ПО
    ПОСТРОЕНИЮ, а нынешние получаются вычитанием сдвига. Мир, который
    ищет кратность перебором, показывает то, что нашёл; этот
    показывает то, что построил.
    """
    вон = list(ЯДРО_КРАТНЫХ_ВПЕРЁД)
    for i in range(КРАТНЫХ_ХОДОМ):
        старший, младший = двое(шаг, i)
        потом = 3 + (шаг * 2 + i) % 7
        к = 2 + (шаг + i * 2) % len(КРАТНЫЕ_СЛОВА)
        сдвиг = 1 + (шаг + i) % 5
        вон.append((старший, младший, потом, к, сдвиг))
    return вон


def лица(шаг):
    """(возраст сейчас, сдвиг). Сдвиг всегда вперёд: назад у лица есть свой род у пар."""
    вон = list(ЯДРО_ЛИЦ)
    for i in range(ЛИЦ_ХОДОМ):
        сейчас = 5 + (шаг * 2 + i * 3) % 14
        сдвиг = 1 + (шаг + i * 2) % 9
        вон.append((сейчас, сдвиг))
    return вон


def отказы(шаг):
    """(о ком спрошено, какое отношение)."""
    вон = list(ЯДРО_ОТКАЗОВ)
    for i in range(ОТКАЗОВ_ХОДОМ):
        вон.append((ИМЕНА[(шаг + i) % len(ИМЕНА)],
                    (шаг + i * 2) % len(ОТНОШЕНИЯ)))
    return вон


# ----------------------------------------------------------- РОДЫ

def показ_сейчас(случай):
    """Возраст обоих и РАЗНИЦА между ними — основание всего мира."""
    а, б, ва, вб, _сдвиг = случай
    р = ва - вб
    return [
        f"{а} is {ва} {years(ва)} old and {б} is {вб} {years(вб)} old; "
        f"{а} is {р} {years(р)} older than {б}.",
        f"{дательный(а)} {ва} {лет(ва)}, а {дательный(б)} {вб} "
        f"{лет(вб)}; {именительный(а)} старше {родительный(б)} на {р} "
        f"{лет(р)}.",
    ]


def показ_вперёд(случай):
    """Сдвиг прибавлен ОБОИМ, и сказано это ОДНИМ показом."""
    а, б, ва, вб, с = случай
    return [
        f"{а} is {ва} and {б} is {вб}; in {с} {years(с)} {а} will be "
        f"{ва + с} and {б} will be {вб + с}.",
        f"{дательный(а)} {ва}, а {дательный(б)} {вб}; через {с} "
        f"{лет(с)} {дательный(а)} будет {ва + с}, а {дательный(б)} "
        f"{вб + с}.",
    ]


def показ_закона(случай):
    """ЗАКОН: время течёт для всех, и потому разница не меняется.

    ПОКАЗ НЕСЁТ ОБЕ ПАРЫ ВОЗРАСТОВ, а не одну разницу. Строка «через 3
    года том всё так же старше ани на 5 лет» верна на вид и
    непроверяема на деле: суду не с чем сверить пятёрку. Закон обязан
    приносить с собою то, из чего он считается, — иначе он не закон, а
    заверение.
    """
    а, б, ва, вб, с = случай
    р = ва - вб
    return [
        f"{а} is {ва} and {б} is {вб}; in {с} {years(с)} {а} will be "
        f"{ва + с} and {б} will be {вб + с}, and {а} will still be {р} "
        f"{years(р)} older than {б}: the difference does not change.",
        f"{дательный(а)} {ва}, а {дательный(б)} {вб}; через {с} "
        f"{лет(с)} {дательный(а)} будет {ва + с}, а {дательный(б)} "
        f"{вб + с}, и {именительный(а)} всё так же старше "
        f"{родительный(б)} на {р} {лет(р)}: разница не меняется.",
    ]


def показ_назад(случай):
    """Сдвиг НАЗАД — или молчание, если он уводит младшего за единицу.

    ВОЗРАСТА МЕНЬШЕ ГОДА ЭТОТ МИР НЕ ЗНАЕТ, и отрицательного тем более.
    Показ не выпускается вовсе: округлить до нуля значило бы научить
    нулю как возрасту, а показать «−2 года» — научить бессмыслице с
    полной судимостью.
    """
    а, б, ва, вб, с = случай
    if вб - с < 1:
        return []
    return [
        f"{а} is {ва} and {б} is {вб}; {с} {years(с)} ago {а} was "
        f"{ва - с} and {б} was {вб - с}.",
        f"{дательный(а)} {ва}, а {дательный(б)} {вб}; {с} {лет(с)} "
        f"назад {дательный(а)} было {ва - с}, а {дательный(б)} "
        f"{вб - с}.",
    ]


def показ_кратного(случай):
    """Кратное отношение возрастов, с основанием рядом."""
    а, б, вб, к = случай
    ва = к * вб
    англ, рус = КРАТНЫЕ_СЛОВА[к]
    return [
        f"{а} is {ва} and {б} is {вб}; {а} is {англ} as old as {б}: "
        f"{ва} = {к} × {вб}.",
        f"{дательный(а)} {ва}, а {дательный(б)} {вб}; "
        f"{именительный(а)} {рус} старше {родительный(б)}: {ва} = {к} × "
        f"{вб}.",
    ]


def показ_кратного_вперёд(случай):
    """Кратность, наступающая ЧЕРЕЗ сдвиг, — или молчание.

    Здесь сходятся оба закона мира разом: сдвиг прибавляется обоим, и
    только потому кратность в будущем есть утверждение о ВРЕМЕНИ, а не
    о двух отдельных числах.
    """
    а, б, потом_б, к, с = случай
    if потом_б - с < 1:
        return []
    потом_а = к * потом_б
    ва, вб = потом_а - с, потом_б - с
    англ, рус = КРАТНЫЕ_СЛОВА[к]
    return [
        f"{а} is {ва} and {б} is {вб}; in {с} {years(с)} {а} will be "
        f"{потом_а} and {б} will be {потом_б}, and {потом_а} is {англ} "
        f"{потом_б}.",
        f"{дательный(а)} {ва}, а {дательный(б)} {вб}; через {с} "
        f"{лет(с)} {дательный(а)} будет {потом_а}, а {дательный(б)} "
        f"{потом_б}, и {потом_а} {рус} больше {потом_б}.",
    ]


def показ_вопрос_сейчас(случай):
    """Вопрос об основании. У НЕГО НЕТ ВЫЧИСЛИМОГО ОСНОВАНИЯ — он и
    ЕСТЬ основание: возраст сейчас ниоткуда не выводится, он назван.
    Суду остаётся проверяемое — что отвечено о ТОМ ЖЕ лице и что
    счётная форма при числе своя.
    """
    а, _б, ва, _вб, _с = случай
    return [f"how old is {а} now? {а} is {ва} {years(ва)} old.",
            f"сколько лет {дательный(а)} сейчас? {дательный(а)} {ва} "
            f"{лет(ва)}."]


def показ_вопрос_вперёд(случай):
    """ОТВЕТ НЕСЁТ СВОЁ ОСНОВАНИЕ, иначе он непроверяем.

    «сколько лет будет тому через 3 года? через 3 года тому будет 15»
    верно на вид и не сверяемо ни с чем: возраста сейчас в строке нет,
    и пятнадцать берётся на веру. Ответ называет исходный возраст —
    и становится вычислением, а не заверением.
    """
    а, _б, ва, _вб, с = случай
    return [f"how old will {а} be in {с} {years(с)}? {а} is {ва}, so "
            f"in {с} {years(с)} {а} will be {ва + с}.",
            f"сколько лет будет {дательный(а)} через {с} {лет(с)}? "
            f"{дательный(а)} {ва}, значит через {с} {лет(с)} "
            f"{дательный(а)} будет {ва + с}."]


def показ_вопрос_назад(случай):
    а, _б, ва, _вб, с = случай
    if ва - с < 1:
        return []
    return [f"how old was {а} {с} {years(с)} ago? {а} is {ва}, so {с} "
            f"{years(с)} ago {а} was {ва - с}.",
            f"сколько лет было {дательный(а)} {с} {лет(с)} назад? "
            f"{дательный(а)} {ва}, значит {с} {лет(с)} назад "
            f"{дательный(а)} было {ва - с}."]


def показ_вопрос_разницы(случай):
    а, б, ва, вб, _с = случай
    р = ва - вб
    return [f"how much older is {а} than {б}? {а} is {р} {years(р)} "
            f"older than {б}: {а} is {ва} and {б} is {вб}.",
            f"насколько {именительный(а)} старше {родительный(б)}? "
            f"{именительный(а)} старше {родительный(б)} на {р} {лет(р)}: "
            f"{дательный(а)} {ва}, а {дательный(б)} {вб}."]


def показ_дано(случай):
    """ДАННОЕ ВПЕРЕДИ ВОПРОСА, ОТВЕТ — ОДНО ЧИСЛО.

    Прежде мир ставил вопрос первым и повторял возраст В ОТВЕТЕ: «сколько лет будет мише
    через 2 года? мише 15, значит …». Порядок этот честен и проверяем, но он ЕДИНСТВЕННЫЙ:
    все 394 вопросные страницы мира построены так. Задача же, приходящая с рынка, ставит
    данное отдельной фразой и ждёт числа: «Ване 14 лет. сколько лет будет Ване через 9 лет?»

        ФОРМА ВОПРОСА ЕСТЬ ЧАСТЬ ПРЕДМЕТА, А НЕ ЕГО ОДЕЖДА. Мир, знающий один порядок слов,
        научил не возрасту, а своему порядку слов.

    Ответ здесь НЕ повторяет основания: оно уже стои́т в строке первой фразой, и повторять
    его значило бы отвечать на вопрос, которого не задали.
    """
    а, _б, ва, _вб, с = случай
    return [
        f"{а} is {ва} {years(ва)} old. how old will {а} be in {с} {years(с)}? "
        f"{ва + с} {years(ва + с)} old.",
        f"{дательный(а)} {ва} {лет(ва)}. сколько лет будет {дательный(а)} через {с} "
        f"{лет(с)}? {ва + с} {лет(ва + с)}.",
    ]


def показ_лица(случай):
    """ПЕРВОЕ ЛИЦО НА ЧЕТЫРЁХ ЯЗЫКАХ.

    Мир возраста говорил на двух языках и только в третьем лице: 955 страниц о двоих,
    ни одной о себе. Немота эта не нейтральна —

        ТАМ, ГДЕ СВОД МОЛЧИТ, ОТВЕЧАЕТ ЕГО САМЫЙ ГРОМКИЙ СОСЕД,

    и на вопрос «wie alt werde ich in 4 Jahren sein?» ответил дом ЗНАКА ДЕЙСТВИЯ: «+».
    Знак тот куплен честно (opchoice, signrul — 1096 строк, и ни одна не кончается знаком),
    но занял он место, которого никто не занимал.
    """
    сейчас, с = случай
    потом = сейчас + с
    return [
        f"I am {сейчас} {years(сейчас)} old. how old will I be in {с} {years(с)}? "
        f"{потом} {years(потом)} old.",
        f"мне {сейчас} {лет(сейчас)}. сколько мне будет через {с} {лет(с)}? "
        f"{потом} {лет(потом)}.",
        f"ich bin {сейчас} {jahre(сейчас)} alt. wie alt werde ich in {с} {jahren(с)} sein? "
        f"{потом} {jahre(потом)}.",
        f"ik ben {сейчас} {ГОД_NL} oud. hoe oud ben ik over {с} {ГОД_NL}? "
        f"{потом} {ГОД_NL}.",
    ]


def показ_лица_второго(случай):
    """ВТОРОЕ ЛИЦО — НЕ ПЕРВОЕ, СКАЗАННОЕ ИНАЧЕ.

    Русское «мне» и «тебе» суть разные слова, немецкое «werde/wirst» — разные формы глагола,
    нидерландское «ben ik/ben jij» — разный порядок. Род, слитый с первым лицом, показал бы
    организму, что лицо есть украшение при числе.
    """
    сейчас, с = случай
    потом = сейчас + с
    return [
        f"you are {сейчас} {years(сейчас)} old. how old will you be in {с} {years(с)}? "
        f"{потом} {years(потом)} old.",
        f"тебе {сейчас} {лет(сейчас)}. сколько тебе будет через {с} {лет(с)}? "
        f"{потом} {лет(потом)}.",
        f"du bist {сейчас} {jahre(сейчас)} alt. wie alt wirst du in {с} {jahren(с)} sein? "
        f"{потом} {jahre(потом)}.",
        f"jij bent {сейчас} {ГОД_NL} oud. hoe oud ben jij over {с} {ГОД_NL}? "
        f"{потом} {ГОД_NL}.",
    ]


def показ_отказа(случай):
    """ОТКАЗ С ОСНОВАНИЕМ — пара немоте.

    Организм, которому нечего ответить, обязан УМЕТЬ СКАЗАТЬ ЭТО и
    сказать ПОЧЕМУ. Корпус, где всякий вопрос имеет число в ответе,
    учит, что число есть всегда, — и тогда незнание выходит наружу
    выдумкой, а не отказом.
    """
    кто, какое = случай
    англ, дат, пред = ОТНОШЕНИЯ[какое]
    return [f"how old is {кто}'s {англ}? it is not said: nothing is "
            f"told about a {англ}.",
            f"сколько лет {дат} {родительный(кто)}? не сказано: {пред} "
            f"ничего не говорится."]


# РОД ОБЪЯВЛЯЕТ СЕМЬЮ СЛУЧАЕВ И ОДНУ ФУНКЦИЮ НАД СЛУЧАЕМ. Прибавить
# род значит объявить тройку, а не написать новый обход; и молчание
# рода есть пустой список, а не особая ветвь.
СОСТАВ = (
    ("now", пары, показ_сейчас),
    ("forward", пары, показ_вперёд),
    ("law", пары, показ_закона),
    ("backward", пары, показ_назад),
    ("multiple", кратные, показ_кратного),
    ("multiple-ahead", кратные_вперёд, показ_кратного_вперёд),
    ("ask-now", пары, показ_вопрос_сейчас),
    ("ask-ahead", пары, показ_вопрос_вперёд),
    ("ask-back", пары, показ_вопрос_назад),
    ("ask-difference", пары, показ_вопрос_разницы),
    ("given-then-ask", пары, показ_дано),
    ("ask-self", лица, показ_лица),
    ("ask-you", лица, показ_лица_второго),
    ("refusal", отказы, показ_отказа),
)


РОДЫ = tuple(с[0] for с in СОСТАВ)

ЗАЧЕМ_РОДА = {и: f"род «{и}», объявленный построением" for и in РОДЫ}


def группы(шаг):
    """[[страница]] — ровно та сборка, какою кормится кузница."""
    вон = []
    for _имя, семья, показать in СОСТАВ:
        свои = []
        for случай in семья(шаг):
            свои += показать(случай)
        if свои:
            вон.append(свои)
    return вон


def перебор(шаг):
    """[(страница, род)] — род взят У СТРОИТЕЛЯ, до всякой пересборки."""
    вон = []
    for имя, семья, показать in СОСТАВ:
        for случай in семья(шаг):
            for с in показать(случай):
                вон.append((с, имя))
    return вон


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            вон.setdefault(с, род)
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Ряд имён — имена; сборка — страница в страницу с перебором."""
    assert all(isinstance(р, str) for р in РОДЫ), "РОДЫ обязаны быть рядом ИМЁН"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    из_перебора = sorted(с for с, _р in перебор(0))
    из_групп = sorted(с for г in группы(0) for с in г)
    assert из_перебора == из_групп, (
        f"пересборка потеряла или выдумала страницы: перебор {len(из_перебора)}, "
        f"группы {len(из_групп)}")
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка()
