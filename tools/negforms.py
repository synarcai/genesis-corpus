#!/usr/bin/env python3
"""ДОМ ОТРИЦАТЕЛЬНОГО ЧИСЛА — ПОРЯДОК ПЕРЕВОРАЧИВАЕТСЯ ЗА НУЛЁМ.

    ОТРИЦАТЕЛЬНОГО ЧИСЛА В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 232 мирам показов:
    «отрицательн», «negative number» — НОЛЬ вхождений; сравнения двух отрицательных — НОЛЬ;
    «противоположное число» — НОЛЬ; числовая прямая — НОЛЬ.

    ЗАМЕР ПО ВСЕМ ФАЙЛАМ ДАВАЛ 1539, И ЭТО БЫЛА ЛОЖЬ ЗАМЕРА: слово стои́т в ПРОЗЕ — у ЭСБЕ,
    Соловьёва, Богданова, — где «отрицательное» значит «отрицающее», а не «меньшее нуля».
    ПРОЗА И ПОКАЗ СУТЬ РАЗНЫЕ МИРЫ, И СЧЁТ ПО ВСЕМ ФАЙЛАМ СМЕШИВАЕТ ИХ.

    Знак минус при числе свод пишет 222 раза — и все в координатах векторов да в корнях
    уравнений, где он есть ЧАСТЬ ЗАПИСИ, а не предмет разговора. Числом его никто не называл.

ЧЕТВЁРТАЯ ЛОВУШКА РЯДА, И САМАЯ ЧИСТАЯ: −5 МЕНЬШЕ −2, ХОТЯ 5 БОЛЬШЕ 2. Дробная область дала
три переворота — деление увеличивает, умножение уменьшает, знаменатель растёт обратно доле;
здесь переворачивается САМ ПОРЯДОК, и переворачивается он ровно за нулём.

    ПОРЯДОК, ВЕРНЫЙ ПО ОДНУ СТОРОНУ НУЛЯ, ОБРАТЕН ПО ДРУГУЮ.

ЧЕТЫРЕ РОДА:

    меньше нуля     −5 меньше нуля: от нуля влево 5 шагов.
    за нулём        −5 меньше −2, хотя 5 больше 2: влево от нуля 5 шагов дальше,
                    чем 2 шага.                                          ← ЛОВУШКА
    противоположные −5 и 5 противоположны: их сумма равна 0, и до нуля им поровну —
                    5 шагов.
    через ноль      −3 меньше 2: всякое отрицательное число меньше всякого положительного.

ВТОРОЙ И ЧЕТВЁРТЫЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО МЕСТУ НУЛЯ: в одном оба числа по левую сторону и
порядок переворачивается, в другом они по разные стороны и переворачивать нечего. Порознь
второй внушал бы, что у отрицательных всё наоборот, а четвёртый — что ничего не изменилось.

ПРИЧИНА ПОКАЗАНА, А НЕ ОБЪЯВЛЕНА: «влево от нуля 5 шагов дальше, чем 2 шага» — это и есть
переворот, сказанный расстоянием. Без него страница была бы правилом, которое надо запомнить.

ТРЕТИЙ РОД ДЕРЖИТ ВЕСЬ ДОМ НА НУЛЕ: противоположные равно отстоят от нуля и в сумме дают ноль.
Отсюда видно, что отрицательное есть не иная порода числа, а ТО ЖЕ ЧИСЛО ПО ДРУГУЮ СТОРОНУ.

    python3 tools/negforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — русский счёт объявлен там, а не здесь

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("меньше нуля", "за нулём", "противоположные", "через ноль")

# ЗНАК МИНУС ЕСТЬ «−» (U+2212), А НЕ ДЕФИС. Первая ковка писала дефисом, и замер по 233 мирам
# показал разлад: словесная математика свода — знаковый мир, шкала температур, границы, доказа-
# тельства — пишет «−» 4442 раза; дефис живёт только в МАШИННОЙ записи (матрицы `[2 3; 4 2]`,
# LaTeX, код) и в мирах, объявивших ASCII-запись парой к типографской («x^2 - 7 x» при «x² − 7x»).
# Дом словесный, и знак у него словесный.
#
#     ОДНА ВЕЩЬ — ОДИН ЗНАК. ДОМ, ВОШЕДШИЙ В ОБЛАСТЬ СО СВОИМ ЗНАКОМ, РАЗБИВАЕТ ЕЁ.
#
# Судья читает ОБА знака: строка, написанная дефисом, есть ПОРЧА страницы этого дома, и звать её
# несудимой значило бы пропускать порчу, которую сам же дом и породил бы при обратной правке.
МИНУС = "−"

# ШАГ ЕСТЬ МЕРА РАССТОЯНИЯ ДО НУЛЯ, и форма его идёт за числом: «1 шаг», «2 шага», «5 шагов».
ШАГ = "шаг"


def шагов(язык, n):
    return ("step" if n == 1 else "steps") if язык == "en" else rugram.форма(ШАГ, n)


РАМКИ = {
    "ru": {
        "меньше нуля": "−{a} меньше нуля: от нуля влево {a} {ша}.",
        "за нулём": "−{a} меньше −{b}, хотя {a} больше {b}: влево от нуля {a} {ша} дальше, чем {b} {шb}.",
        "противоположные": "−{a} и {a} противоположны: их сумма равна 0, и до нуля им поровну — {a} {ша}.",
        "через ноль": "−{a} меньше {b}: всякое отрицательное число меньше всякого положительного.",
    },
    "en": {
        "меньше нуля": "−{a} is less than zero: {a} {ша} to the left of zero.",
        "за нулём": "−{a} is less than −{b}, although {a} is greater than {b}: {a} {ша} to the left of zero are farther than {b} {шb}.",
        "противоположные": "−{a} and {a} are opposite: their sum is 0, and both stand {a} {ша} from zero.",
        "через ноль": "−{a} is less than {b}: every negative number is less than every positive one.",
    },
}

# РАЗНОСТИ ВЗЯТЫ РЕДЕЮЩИМ РЯДОМ, А НЕ СПЛОШЬ: полный перебор пар дал бы роду «за нулём» втрое
# больше страниц, чем прочим трём вместе, и дом читался бы как дом одного рода с приложениями.
РАЗНОСТИ = (1, 2, 3, 5, 8)
ПРЕДЕЛ = 40


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a in range(1, ПРЕДЕЛ + 1):
            ша = шагов(язык, a)
            вон[рамки["меньше нуля"].format(a=a, b=0, ша=ша, шb="")] = (язык, "меньше нуля")
            вон[рамки["противоположные"].format(a=a, b=0, ша=ша,
                                                шb="")] = (язык, "противоположные")
        for a in range(2, 21):
            for д in РАЗНОСТИ:
                b = a - д
                if b < 1:
                    continue
                вон[рамки["за нулём"].format(a=a, b=b, ша=шагов(язык, a),
                                             шb=шагов(язык, b))] = (язык, "за нулём")
        for a in range(1, 11):
            for b in range(1, 7):
                вон[рамки["через ноль"].format(a=a, b=b, ша="", шb="")] = (язык, "через ноль")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ЗНАК МИНУС ЕСТЬ ЧАСТЬ ЧИСЛА, И ОБРАЗЕЦ ОБЯЗАН ЕГО БРАТЬ. Читать «5 меньше 2» сквозь «-5
# меньше -2» — та самая жадность, что трижды за две смены брала «21 = 2 × 1» из «21 = 2 × 10 +
# 1». Знак здесь несёт весь смысл дома, и потерять его значит потерять предмет.
_ЗН = r"[−-]?\d+"
_МЕНЬШЕ = re.compile(rf"(?<![\d/])({_ЗН}) (?:меньше|is less than) ({_ЗН})(?![\d/])")
_БОЛЬШЕ = re.compile(rf"(?<![\d/])({_ЗН}) (?:больше|is greater than) ({_ЗН})(?![\d/])")
_ДАЛЬШЕ = re.compile(rf"(?<![\d/])({_ЗН}) \S+ дальше, чем ({_ЗН})|(?<![\d/])({_ЗН}) \S+ "
                     rf"to the left of zero are farther than ({_ЗН})")


def _цел(с):
    """Число со знаком МИНУС (U+2212) или дефисом — одно и то же число."""
    return int(с.replace("−", "-"))


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ ПОРЯДОК, СВЕРЕННЫЙ ЧИСЛАМИ СО ЗНАКОМ.
    for a, b in _МЕНЬШЕ.findall(с):
        if _цел(a) >= _цел(b):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if _цел(a) <= _цел(b):
            return True, False
    for группы in _ДАЛЬШЕ.findall(с):
        a, b = (группы[0], группы[1]) if группы[0] else (группы[2], группы[3])
        if _цел(a) <= _цел(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    зн = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "за нулём")
    пр = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "противоположные")
    if судить(зн.replace("влево", "влев"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(пр.replace("противоположны", "противоположно"))[1] is not False:
        беды.append("обрезанное слово в противоположных прошло")
    if судить(зн + " " + зн)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ЗНАК ОБЯЗАН ЧИТАТЬСЯ: «-5 меньше -2» истинно, «5 меньше 2» — ложь, и разница вся в знаке.
    if судить("−5 меньше 2: всякое отрицательное число меньше всякого положительного.") != (
            True, True):
        беды.append("честная через ноль не прошла")
    if судить("5 меньше 2: всякое отрицательное число меньше всякого положительного.")[1]:
        беды.append("ЗНАК ПОТЕРЯН: строка без минуса прошла как истинная")
    if any("-" in с for с in ПОКАЗЫ):
        беды.append("ДЕФИС В ПОКАЗЕ: дом обязан писать знаком минус U+2212")
    print(f"ОТРИЦАТЕЛЬНОЕ ЧИСЛО: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
