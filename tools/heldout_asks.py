#!/usr/bin/env python3
"""HELD-OUT ВОПРОСНАЯ ПОВЕРХНОСТЬ: два набора вопросов одной формы.

ЗАКАЗ ШТУРМА. Владелец спросил: не есть ли необходимость ПОКАЗЫВАТЬ
вопрос обобщающий дефект архитектуры? Спор об этом решается не
рассуждением, а опытом:

    МОЖЕТ ЛИ ОРГАНИЗМ ОТВЕТИТЬ НА ВОПРОС О ФАКТЕ,
    ВОПРОС К КОТОРОМУ ЕМУ НЕ ПОКАЗЫВАЛИ?

Если да — вопросная поверхность есть учебный материал для покупки
ФОРМЫ, и немые миры суть долг обучения. Если нет — обращение не
операция, а таблица пар, и никакое число миров этого не вылечит.

ДВА НАБОРА, И РАЗНИЦА МЕЖДУ НИМИ ДОЛЖНА БЫТЬ ЧИСТОЙ.
  · ПОКАЗАННАЯ ФОРМА (`held_out_form: false`) — вопрос взят ИЗ КОРПУСА
    дословно: организм видел и его, и ответ.
  · СКРЫТАЯ ФОРМА (`held_out_form: true`) — вопрос СОБРАН ЗДЕСЬ по той
    же форме, но к факту из мира, где вопросов нет ВОВСЕ. Организм
    видел утверждение и не видел вопроса к нему ни разу.

ЧЕСТНАЯ ОГОВОРКА, БЕЗ КОТОРОЙ ОПЫТ НЕЛЬЗЯ ЧИТАТЬ. Роды в двух наборах
РАЗНЫЕ — иначе и быть не может: род либо имеет показанный вопрос, либо
нет. Потому сравнение чисто по ФОРМЕ ВОПРОСА, а не по роду, и всякая
разница может нести в себе трудность самого рода. Смягчено тем, что
формы берутся ОДНИ И ТЕ ЖЕ («what is …», «чему равно …»), а факты — из
миров сравнимой простоты. Полностью чистый опыт требовал бы пересборки
корпуса с вырезанными вопросами ОДНОГО рода — это дороже и делается
следующим шагом, если разница окажется невелика.

ОТВЕТ ОБЪЯВЛЯЕТСЯ ЗДЕСЬ ЖЕ И ВЗЯТ ИЗ КОРПУСА, а не вычислен заново:
проверяющий сверяет ответ организма с тем, что корпус УЖЕ утверждает.
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent

# ФОРМЫ ОБРАЩЕНИЯ: как утверждение становится вопросом. Взяты замером
# по своду (34 700 вопросных строк): «what is» 4952, «чему равно» 1408,
# «how many» 1440. Это не выдумка, а самые частые формы корпуса.
ОБРАЩЕНИЯ = (
    # (образец утверждения, как спросить, что ждём)
    (re.compile(r"^(?P<что>.+?) is (?P<ответ>\d+)\.?$"),
     "what is {что}?", "value"),
    (re.compile(r"^(?P<что>.+?) равно (?P<ответ>\d+)\.?$"),
     "чему равно {что}?", "value"),
    (re.compile(r"^(?P<что>.+?) равна (?P<ответ>\d+)\.?$"),
     "чему равна {что}?", "value"),
    (re.compile(r"^(?P<что>.+?) равен (?P<ответ>\d+)\.?$"),
     "чему равен {что}?", "value"),
)

# Вопрос, УЖЕ показанный корпусом: берётся дословно вместе с ответом.
ПОКАЗАННЫЙ = re.compile(
    r"^(?P<вопрос>(?:what is|чему равно|чему равна|чему равен|how many)"
    r"[^?]{3,90}\?)\s*(?P<хвост>.{3,120})$", re.I)
ЧИСЛО_В_ХВОСТЕ = re.compile(r"(\d+)\s*\.?$")


def факты(путь, предел):
    """Строки мира, годные для обращения: утверждение с числом в конце."""
    вон = []
    for с in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        т = с.strip()
        if not т or "?" in т:
            continue
        for образец, форма, род in ОБРАЩЕНИЯ:
            m = образец.match(т)
            if m and m.group("что").strip():
                вон.append((m.group("что").strip(),
                            int(m.group("ответ")), форма, род))
                break
        if len(вон) >= предел:
            break
    return вон


def показанные(путь, предел):
    """Вопросы, УЖЕ стоящие в корпусе, с их ответом."""
    вон = []
    for с in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        т = с.strip()
        m = ПОКАЗАННЫЙ.match(т)
        if not m:
            continue
        ч = ЧИСЛО_В_ХВОСТЕ.search(m.group("хвост"))
        if not ч:
            continue
        вон.append((m.group("вопрос").strip(), int(ч.group(1))))
        if len(вон) >= предел:
            break
    return вон


# ТРЕТЬЯ ГРУППА: РОД С ПОВЕСТВОВАНИЕМ, НО БЕЗ ПОКАЗАННОГО ВОПРОСА.
#
# Две первые группы различались РОДОМ, и разница могла нести трудность
# рода. Третья группа чиста ПО РОДУ: те же шесть вердиктных родов
# дознания, что и во второй, но организм растёт на сборке HOLDOUT, где
# их вопросы ВЫРЕЗАНЫ, а повествование («91 is not a prime number: 91 =
# 7 × 13») оставлено. Вопрос здесь СТРОИТСЯ из повествования дословным
# обращением сказуемого — «is 91 a prime number?» — и ответ есть
# полярность сказуемого, а не вычисление.
ПОВЕСТВОВАНИЯ = (
    # (образец повествования, форма вопроса, род, ответ из полярности)
    (re.compile(r"^(?P<n>\d+) is (?P<pol>not )?a prime number: "),
     "is {n} a prime number?", "primality"),
    (re.compile(r"^(?P<n>\d+) is (?P<pol>not )?divisible by (?P<b>\d+): "),
     "is {n} divisible by {b}?", "divisibility"),
    (re.compile(r"^f\(x\) = x × (?P<k>\d+) (?P<pol>is not |is )injective "
                r"on 1, 2, 3: "),
     "is f(x) = x × {k} injective on 1, 2, 3?", "injectivity"),
    (re.compile(r"^if n is even, n \+ (?P<m>\d+) (?P<pol>is not |is )even: "),
     "if n is even, is n + {m} even?", "conditional"),
)


def третья_группа(путь, предел):
    """Вопросы к повествованиям дознания; ответ — полярность сказуемого."""
    вон = []
    for с in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        т = с.strip()
        if not т or "?" in т:
            continue
        for образец, форма, род in ПОВЕСТВОВАНИЯ:
            m = образец.match(т)
            if not m:
                continue
            нет = bool(m.group("pol")) and "not" in m.group("pol")
            вон.append((форма.format(**{k: v for k, v in m.groupdict().items()
                                          if k != "pol"}),
                        "no" if нет else "yes", род))
            break
        if len(вон) >= предел:
            break
    return вон


def main():
    предел = 60
    если = [а for а in sys.argv[1:] if not а.startswith("-")]
    вон = []
    n = 0
    # НЕМЫЕ МИРЫ — источник СКРЫТОЙ формы: вопросов в них нет ни одного.
    for имя in ("genesis_machine", "genesis_numbers", "genesis_algebra",
                "genesis_sequences", "genesis_statistics"):
        путь = КОРЕНЬ / "datasets" / f"{имя}.txt"
        if not путь.exists():
            continue
        for что, ответ, форма, род in факты(путь, предел // 4):
            n += 1
            вон.append({
                "id": f"ho{n:04d}",
                "ask": форма.format(что=что),
                "expect": {"kind": род, "n": ответ},
                "tags": ["held_out_form:true", f"genus:{имя}",
                         "source:constructed"],
            })
    # МИРЫ С ПОКАЗАННЫМ ВОПРОСОМ — источник видённой формы.
    for имя in ("genesis_inquiry", "genesis_surfaces", "genesis_percent",
                "genesis_metalang", "genesis_relation"):
        путь = КОРЕНЬ / "datasets" / f"{имя}.txt"
        if not путь.exists():
            continue
        for вопрос, ответ in показанные(путь, предел // 4):
            n += 1
            вон.append({
                "id": f"ho{n:04d}",
                "ask": вопрос,
                "expect": {"kind": "value", "n": ответ},
                "tags": ["held_out_form:false", f"genus:{имя}",
                         "source:corpus"],
            })
    # ТРЕТЬЯ ГРУППА — из повествований дознания (сборка HOLDOUT вырезает
    # их вопросы; здесь вопрос строится заново обращением сказуемого).
    путь = КОРЕНЬ / "datasets" / "genesis_inquiry.txt"
    if путь.exists():
        for вопрос, ответ, род in третья_группа(путь, предел):
            n += 1
            вон.append({
                "id": f"ho{n:04d}",
                "ask": вопрос,
                "expect": {"kind": "verdict", "v": ответ},
                "tags": ["held_out_form:true", "narrative_shown:true",
                         f"genus:{род}", "source:inverted"],
            })
    if not вон:
        print("HELD-OUT ОТКАЗ: ни одного вопроса не собрано")
        return 2
    выход = КОРЕНЬ / "forge" / "heldout_asks.jsonl"
    выход.parent.mkdir(exist_ok=True)
    with выход.open("w", encoding="utf-8") as ф:
        for з in вон:
            ф.write(json.dumps(з, ensure_ascii=False) + "\n")
    третья = sum(1 for з in вон if "narrative_shown:true" in з["tags"])
    скрытых = sum(1 for з in вон if "held_out_form:true" in з["tags"]) - третья
    print(f"HELD-OUT: {len(вон)} вопросов записано в {выход.name} — "
          f"скрытая форма {скрытых}, показанная {len(вон) - скрытых - третья}, "
          f"третья группа (повествование без вопроса) {третья}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
