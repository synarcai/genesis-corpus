#!/usr/bin/env python3
"""ДОМ ПОВЕРХНОСТЕЙ АКТА — один факт, много способов его сказать.

Два рода объявлены не здесь: их назвала СВОЯ ЖЕ КУЗНИЦА кортежем `ГРУППЫ = (именование,
связкой_будет)`, и род всякой страницы известен по тому, ЧЬЯ ФУНКЦИЯ её сделала.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.
    Переносчик, берущий имя функции-строителя, НИЧЕГО НЕ РЕШАЕТ ЗА ДОМ: он переписывает
    решение, принятое автором кузницы.

    ДОМ, НЕ ЗНАЮЩИЙ СВОИХ СТРАНИЦ, НЕ МОЖЕТ НАЗВАТЬ ИХ РОДА, — и две тысячи двести девять
    строк мира `surfaces` жили безымянными при двух живых именах.

ЧТО ДЕЛАЕТ КАЖДЫЙ РОД:

    ИМЕНОВАНИЕ    — действие, названное ИМЕНЕМ: номинализация («сложение 7 и 6») и имя
                    результата («сумма 7 и 6»), с управлением, объявленным ОДИН раз.
                    Управление есть то, чего таблица синонимов не несёт: «вычитание 12 ИЗ 5»
                    не малая ошибка, а обратное утверждение.
    СВЯЗКОЙ_БУДЕТ — вторая русская связка и вторая поверхность числа: «сорок два минус пять
                    будет тридцать семь». Ни одна из двух не выводится из другой.

ПЕРЕЕЗЖАЕТ НЕ ФУНКЦИЯ, А ЗАМЫКАНИЕ ЦЕЛИКОМ: вместе с обоими строителями сюда переехали
таблицы `ДЕЙСТВИЯ` и `РЕЧЬ`, из которых они берут фразы, и правило пар чисел.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import numerals  # noqa: E402

РОДЫ = ("именование", "связкой_будет")

ЗАЧЕМ_РОДА = {
    "именование": "действие, названное именем: номинализация, имя результата и управление",
    "связкой_будет": "вторая связка русского и число, СКАЗАННОЕ СЛОВАМИ",
}

# ДЕЙСТВИЕ ОБЪЯВЛЯЕТ ДВЕ ФРАЗЫ И РОД ИМЕНИ РЕЗУЛЬТАТА — БОЛЬШЕ
# НИЧЕГО. Вопрос НЕ объявляется: он выводится из той же фразы, что и
# ответ. Первая редакция держала вопрос отдельной строкой — и тут же
# солгала управлением: спрашивала «что даёт вычитание 4 И 2?», а
# отвечала «вычитание 2 ИЗ 4». Две записи одного управления расходятся
# в первой же строке; управление объявлено ОДИН раз.
#   (знак, фраза номинализации, фраза имени результата, род имени)
ДЕЙСТВИЯ = {
 "ru": (
   ("+", "сложение {a} и {b}", "сумма {a} и {b}", "ж"),
   ("-", "вычитание {b} из {a}", "разность {a} и {b}", "ж"),
   ("*", "умножение {a} на {b}", "произведение {a} и {b}", "с"),
   ("/", "деление {a} на {b}", "частное {a} и {b}", "с"),
 ),
 "en": (
   ("+", "the addition of {a} and {b}", "the sum of {a} and {b}", "-"),
   ("-", "the subtraction of {b} from {a}",
    "the difference of {a} and {b}", "-"),
   ("*", "the multiplication of {a} by {b}",
    "the product of {a} and {b}", "-"),
   ("/", "the division of {a} by {b}",
    "the quotient of {a} and {b}", "-"),
 ),
}
# ЯЗЫК ОБЪЯВЛЯЕТ, ЧЕМ ФРАЗА СТАНОВИТСЯ УТВЕРЖДЕНИЕМ И ЧЕМ — ВОПРОСОМ.
#   (глагол номинализации, вопрос к ней,
#    {род: связка результата}, {род: вопрос к результату})
РЕЧЬ = {
 "ru": ("даёт", "что даёт {фраза}?",
        {"ж": "равна", "с": "равно"},
        {"ж": "чему равна {фраза}?", "с": "чему равно {фраза}?"}),
 "en": ("gives", "what does {фраза} give?",
        {"-": "is"}, {"-": "what is {фраза}?"}),
}


def _пары(шаг):
    """Пары чисел, на которых действие определено во всех четырёх."""
    вон = []
    for i in range(12):
        b = 2 + (шаг + i) % 9
        a = b * (2 + (шаг * 2 + i) % 8)
        вон.append((a, b))
    return вон


def именование(шаг):
    """Действие, названное именем: номинализация и имя результата."""
    вон = []
    for язык, действия in ДЕЙСТВИЯ.items():
        глагол, вопрос_н, связки, вопросы_р = РЕЧЬ[язык]
        for знак, шаб_н, шаб_р, род in действия:
            for a, b in _пары(шаг):
                c = {"+": a + b, "-": a - b, "*": a * b,
                     "/": a // b}[знак]
                фраза_н = шаб_н.format(a=a, b=b)
                фраза_р = шаб_р.format(a=a, b=b)
                утв_н = f"{фраза_н} {глагол} {c}."
                утв_р = f"{фраза_р} {связки[род]} {c}."
                вон.append(утв_н)
                вон.append(утв_р)
                вон.append(f"{вопрос_н.format(фраза=фраза_н)} {утв_н}")
                вон.append(
                    f"{вопросы_р[род].format(фраза=фраза_р)} {утв_р}")
    return вон


def связкой_будет(шаг):
    """Русская связка «будет» — и числа, СКАЗАННЫЕ СЛОВАМИ.

    «сорок два минус пять будет» немело в пробе, потому что корпус
    писал русскую арифметику цифрами и связкой «равно». Связка «будет»
    есть вторая связка языка, а числительное словами — вторая
    поверхность числа; ни одна из двух не выводится из другой.
    """
    табл = numerals.таблица("ru")
    знаки = (("+", "плюс"), ("-", "минус"))
    вон = []
    for i in range(14):
        a = 21 + (шаг * 5 + i * 3) % 78
        b = 2 + (шаг + i) % 9
        for знак, слово in знаки:
            c = a + b if знак == "+" else a - b
            имена = [numerals.назвать(x, табл) for x in (a, b, c)]
            if any(и is None for и in имена):
                continue
            са, сб, сц = имена
            вон.append(f"{са} {слово} {сб} будет {сц}.")
            вон.append(f"сколько будет {са} {слово} {сб}? "
                       f"{са} {слово} {сб} будет {сц}.")
    return вон

ГРУППЫ = (именование, связкой_будет)


def перебор(шаг):
    """[(страница, род)] — порядок тот же, каким кузница режет проходы."""
    вон = []
    for сделать in ГРУППЫ:
        род = сделать.__name__
        for с in сделать(шаг):
            вон.append((с, род))
    return вон


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            вон.setdefault(с, род)
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Имя всякой группы обязано стоять в объявлении, и всякий род — дать страницу.

    РОД, ОБЪЯВЛЕННЫЙ И НЕ КОВАННЫЙ, ЕСТЬ ОБЕЩАНИЕ, А НЕ РОД.
    """
    имена = tuple(с.__name__ for с in ГРУППЫ)
    assert имена == РОДЫ, f"группы кузницы {имена} разошлись с объявлением {РОДЫ}"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    данные = set(ПОКАЗЫ.values())
    пустые = set(РОДЫ) - данные
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка()
