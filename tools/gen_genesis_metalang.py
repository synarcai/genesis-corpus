# СТУПЕНЬ ОБЪЯВЛЯЕТ ИМЯ И ОДНУ ФУНКЦИЮ, И БОЛЬШЕ НИЧЕГО. Прибавить
# ступень стоит одной строки здесь и одного образца в суде; обход
# ступеней не знает ни одной из них поимённо.
СТУПЕНИ = (
    ("definition", показ_определение),
    ("axiom", показ_аксиома),
    ("lemma", показ_лемма),
    ("theorem", показ_теорема),
    ("condition-fails", показ_условие_нарушено),
    ("proof", показ_доказательство),
    ("corollary", показ_следствие),
    ("hypothesis-refuted", показ_гипотеза_убита),
    ("hypothesis-open", показ_гипотеза_жива),
    ("counterexample", показ_контрпример),
    ("statement", показ_утверждение),
    ("linkage", показ_связь),
)


def pass_groups(шаг):
    """Одна группа на СТУПЕНЬ: ступени не мешаются друг с другом.

    Перемешивание внутри группы — закон дома (`layer.emit_grouped`), и
    оно есть перестановка, а не выборка. Границей между ступенями стоит
    шов, и читатель корпуса режет по нему честно.
    """
    return [показать(шаг) for _имя, показать in СТУПЕНИ]


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
