# У РОДА (2, 0) ЯЗЫК ИМЕЕТ СВОЁ СЛОВО, И КОРПУС ОБЯЗАН ЕГО ЗНАТЬ.
# «Делится на 2 без остатка» и «чётно» суть одно и то же для счёта и
# ДВЕ РАЗНЫЕ ПОВЕРХНОСТИ для языка: организм, встречающий в прозе
# «чётное число» и знающий лишь описание через делитель, немеет на
# слове. Особые имена объявлены здесь, прочие СТРОЯТСЯ по паре.
ОСОБЫЕ_ИМЕНА = {
    (2, 0): ("чётно", "is even"),
    (2, 1): ("нечётно", "is odd"),
}


def сказуемое(d, r):
    """(ru, en) — СКАЗУЕМОЕ О ЧИСЛЕ рода (делитель d, остаток r).

    Сказуемое, а не прилагательное: «6 чётно», «6 делится на 3 без
    остатка», «6 даёт остаток 1 при делении на 5». Прилагательное
    потребовало бы падежей при всяком употреблении и завело бы за
    числом ИМЯ — ту самую счётную пару, на которой мир уравнений уже
    потерял сорок строк.
    """
    if (d, r) in ОСОБЫЕ_ИМЕНА:
        return ОСОБЫЕ_ИМЕНА[(d, r)]
    if r == 0:
        return f"делится на {d} без остатка", f"is divisible by {d}"
    return (f"даёт остаток {r} при делении на {d}",
            f"leaves remainder {r} when divided by {d}")


def представление(n, d):
    """«6 = 2 * 3» или «7 = 2 * 3 + 1» — число, разложенное своим родом.

    ЗАКОН НУЛЕВОГО СЛАГАЕМОГО ВЗЯТ У МИРА УРАВНЕНИЙ И НЕ ПИШЕТСЯ
    ЗАНОВО: слагаемое, равное нулю, не пишется вовсе. «6 = 2 * 3 + 0»
    не пишет никто, и корпус, пишущий так, учит форме, которой в мире
    нет.
    """
    k, r = divmod(n, d)
    хвост = f" + {r}" if r else ""
    return f"{n} = {d} * {k}{хвост}"


# ---------------------------------------------------- ЗАКОН

def итог_рода(знак, d, r1, r2):
    """Остаток итога: закон сложения и умножения остатков.

    ЭТО И ЕСТЬ ВЕСЬ ЗАКОН МИРА, И ОН ЗАНИМАЕТ ДВЕ СТРОКИ. «Сумма двух
    чётных чётна» и «произведение двух нечётных нечётно» суть один
    закон при разных парах остатков; заучивать их порознь значит
    заучивать следствия вместо основания.
    """
    return ((r1 + r2) % d) if знак == "+" else ((r1 * r2) % d)


def закон(знак, d, r1, r2):
    """(ru, en) — всеобщее утверждение о числах двух родов."""
    п1, а1 = сказуемое(d, r1)
    п2, а2 = сказуемое(d, r2)
    пи, аи = сказуемое(d, итог_рода(знак, d, r1, r2))
    return (f"если a {п1} и b {п2}, то a {знак} b {пи}",
            f"if a {а1} and b {а2}, then a {знак} b {аи}")


def ложный_закон(знак, d, r1, r2, dл, rл):
    """(ru, en) — то же утверждение с ЧУЖИМ заключением: заведомо ложь.

    Ложь тут не описка, а ПРЕДМЕТ ПОКАЗА: контрпримеру нужно то, что
    он убивает. Заключение берётся о ДРУГОМ делителе («сумма двух
    чётных делится на 4 без остатка») — ошибка, которую делает всякий,
    кто читает закон как заклинание, а не как счёт остатков.
    """
    п1, а1 = сказуемое(d, r1)
    п2, а2 = сказуемое(d, r2)
    пл, ал = сказуемое(dл, rл)
    return (f"если a {п1} и b {п2}, то a {знак} b {пл}",
            f"if a {а1} and b {а2}, then a {знак} b {ал}")


def счесть(знак, a, b):
    return a + b if знак == "+" else a * b


def ход(знак, d, r1, r2, k1, k2):
    """Цепочка равенств от условия к заключению — ВЫВЕДЕННАЯ, не вписанная.

    ОДНА ФОРМУЛА НА ВСЕ СЛУЧАИ, и обе её половины суть раскрытие
    скобок:

        (d k1 + r1) + (d k2 + r2) = d ( k1 + k2 + p ) + r
        (d k1 + r1) (d k2 + r2) = d ( d k1 k2 + k1 r2 + k2 r1 + p ) + r

    где p есть перенос (целая часть от деления суммы или произведения
    остатков на d), а r — сам остаток итога. Нулевые слагаемые не
    пишутся, и потому доказательство для чётных короче, чем для
    нечётных: короче ровно на те слагаемые, которых там нет.
    """
    a, b = d * k1 + r1, d * k2 + r2
    сырой = (r1 + r2) if знак == "+" else (r1 * r2)
    перенос, остаток = divmod(сырой, d)
    if знак == "+":
        части = [str(k1), str(k2)]
    else:
        части = [f"{d} * {k1} * {k2}"]
        части += [str(ч) for ч in (k1 * r2, k2 * r1) if ч]
    if перенос:
        части.append(str(перенос))
    внутри = " + ".join(части)
    K = sum(int(ч) for ч in части) if знак == "+" else (
        d * k1 * k2 + k1 * r2 + k2 * r1 + перенос)
    хвост = f" + {остаток}" if остаток else ""
    итог = счесть(знак, a, b)
    return (f"{a} {знак} {b} = {d} * ( {внутри} ){хвост} = "
            f"{d} * {K}{хвост} = {итог}")


# ---------------------------------------------------- ЧИСЛА ПРОХОДА

# ДИАПАЗОН, А НЕ СПИСОК. Делитель, остатки и множители сдвигаются
# номером прохода: пятикратный слой несёт пять РАЗНЫХ наборов теорем.
# Верхний предел делителя взят пятью, ибо при большем остатки родов
# перестают встречаться в школьной речи («даёт остаток 6 при делении
# на 7» есть верное, но мёртвое сказуемое), а нижний — двойкой, ибо
# делитель единица не различает ничего.
ДЕЛИТЕЛИ = (2, 3, 4, 5)
ЗНАКИ = ("+", "*")


def случаи(шаг, сколько):
    """[(знак, d, r1, r2, k1, k2)] — случаи прохода, выведенные сдвигом.

    Пары остатков перебираются ПО КРУГУ внутри делителя, и потому при
    d = 2 показываются все четыре сочетания чётного и нечётного, а при
    d = 5 — пять разных пар на пять проходов. Ни одна пара не вписана
    рукой: она есть остаток от деления номера на делитель.
    """
    вон = []
    for i in range(сколько):
        знак = ЗНАКИ[(шаг + i) % len(ЗНАКИ)]
        d = ДЕЛИТЕЛИ[(шаг + i) % len(ДЕЛИТЕЛИ)]
        r1 = (шаг + i) % d
        r2 = (шаг * 2 + i) % d
        k1 = 2 + (шаг * 3 + i) % 7
        k2 = k1 + 1 + (шаг + i * 2) % 5
        вон.append((знак, d, r1, r2, k1, k2))
    return вон


# ---------------------------------------------------- ОПРЕДЕЛЕНИЕ

def через_что(d, r):
    """(ru, en) — ЧЕМ определяется род, и это НЕ ТЕ ЖЕ СЛОВА.

    ОПРЕДЕЛЕНИЕ, ПОВТОРЯЮЩЕЕ ОПРЕДЕЛЯЕМОЕ, ЕСТЬ ТАВТОЛОГИЯ, а не
    определение: «число делится на 3 без остатка, если при делении на 3
    остаток есть 0» не говорит ничего сверх имени. Оттого сторона
    определяющая берётся ДРУГАЯ, чем сторона определяемая:

      · род со СВОИМ ИМЕНЕМ («чётно») определяется ОСТАТКОМ, ибо имя
        об остатке молчит;
      · род, названный ОСТАТКОМ, определяется ПРЕДСТАВЛЕНИЕМ («есть
        3 * k при целом k»), ибо представление есть иная сторона того
        же факта — та самая, на которой стоит лемма.
    """
    if (d, r) in ОСОБЫЕ_ИМЕНА:
        return (f"при делении на {d} оно даёт остаток {r}",
                f"it leaves remainder {r} when divided by {d}")
    хвост = f" + {r}" if r else ""
    return (f"оно есть {d} * k{хвост} при целом k",
            f"it is {d} * k{хвост} for a whole k")


def показ_определение(шаг):
    """Понятие, случай ПОД определением и случай ВНЕ его.

    ГРАНИЦА ОПРЕДЕЛЕНИЯ ПОКАЗЫВАЕТСЯ ОТКАЗОМ. Определение, при котором
    стоит только подпадающий случай, учит узнавать, но не учит
    ОТЛИЧАТЬ: организм, видевший десять чётных чисел под словом
    «чётно», не знает об этом слове ничего, пока не увидит числа,
    которому в нём отказано, и ОСНОВАНИЕ отказа числом.
    """
    вон = []
    for i in range(4):
        d = ДЕЛИТЕЛИ[(шаг + i) % len(ДЕЛИТЕЛИ)]
        r = (шаг + i) % d
        п, а = сказуемое(d, r)
        чем_ру, чем_ан = через_что(d, r)
        k = 3 + (шаг * 2 + i) % 6
        n = d * k + r
        друг = (r + 1 + (шаг + i) % (d - 1)) % d if d > 1 else r
        m = d * k + друг
        вон.append(f"определение: число {п}, если {чем_ру}. {n} "
                   f"подпадает под определение: {представление(n, d)}. "
                   f"{m} не подпадает: {представление(m, d)}.")
        вон.append(f"definition: a number {а} if {чем_ан}. {n} falls "
                   f"under the definition: {представление(n, d)}. {m} "
                   f"does not: {представление(m, d)}.")
        вон.append(f"что есть определение? определение говорит, что "
                   f"понятие есть, и отделяет подпадающее от "
                   f"неподпадающего: {n} {п}, ибо {представление(n, d)}, "
                   f"а {m} нет, ибо {представление(m, d)}.")
        вон.append(f"what is a definition? a definition says what a "
                   f"notion is and separates what falls under it from "
                   f"what does not: {n} {а}, since {представление(n, d)}, "
                   f"and {m} does not, since {представление(m, d)}.")
        вон.append(f"{n} {п} по определению, а {m} нет: "
                   f"{представление(n, d)}, а {представление(m, d)}.")
        вон.append(f"в определении названо, при каком остатке число {п}: "
                   f"{n} даёт остаток {r} при делении на {d}, а {m} "
                   f"нет: {представление(n, d)}, а {представление(m, d)}.")
        вон.append(f"определим род числа остатком, и он определяется "
                   f"делением, а не видом записи: {n} {п}, а {m} нет: "
                   f"{представление(n, d)}, а {представление(m, d)}.")
    return вон


