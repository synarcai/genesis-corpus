#!/usr/bin/env python3
"""[КУЗНИЦА БЛОКА] — собирает `blocks/BBH-CHAIN-ORDER-*.tsv`: цепь свидетельств и порядок.

    БЛОК ОТЛИЧАЕТСЯ ОТ МИРА НЕ РАСПИСАНИЕМ, А ОБЛАСТЬЮ.

Повод, замеренный 21.09. Первая сборка блока брала рамки домов и их же лиц и вещи — и в
час замера ни одна её страница в своде не жила. Через день дома `liarchain` и `adjorder`
вошли в свод, и сорок страниц блока оказались прожиты дословно: блок стал мерить память о
своде.

    ПРОВЕРКА «НЕТ В СВОДЕ СЕГОДНЯ» СТАРЕЕТ ВМЕСТЕ СО СВОДОМ. ПРОВЕРКА «ВЗЯТО ИЗ ОБЛАСТИ,
    КОТОРОЙ СВОД НЕ БЕРЁТ ВОВСЕ» НЕ СТАРЕЕТ НИКОГДА.

Потому блок берёт РАМКИ домов дословно — иначе он мерил бы чужой закон, — но область его
с областью домов не пересекается, и трижды:

  1. ЛИЦА вне `person_names` пакета. Дом берёт лиц только у пакета и объявляет это
     законом; лицо вне пакета не встретится в мире никогда.
  2. ДЛИНА ЦЕПИ больше всякой объявленной домом (дом: 2…4; блок: 5…6). Цепь длиннее
     виданной есть единственная честная проверка того, что закон усвоен, а не заучен.
  3. ВЕЩИ вне `adjorder.ВЕЩИ`. Та же мера для второго рода.

Сборка утверждает все три при всяком запуске: разойдись область — блок не соберётся.

    python3 tools/gen_block_bbh.py [--цель blocks/ИМЯ.tsv]
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import adjorder            # noqa: E402
import liarchain           # noqa: E402
from plural import article  # noqa: E402

ЦЕЛЬ = КОРЕНЬ / "blocks" / "BBH-CHAIN-ORDER-2026-09-21.tsv"

# Лица, которых нет ни в одном пакете свода: блок не может их прожить.
ЛИЦА = {
    "en": ("Quinn", "Zola", "Bruno", "Esme", "Gunnar", "Ines", "Otto", "Thea"),
    "ru": ("Фёдор", "Зоя", "Клим", "Лариса", "Богдан", "Тамара", "Руслан", "Эмма"),
}
# Вещи вне `adjorder.ВЕЩИ` («table», «ball», «box», «chair», «cup»).
ВЕЩИ = ("shelf", "lamp", "bowl", "clock", "bench")
# Длины цепи больше всякой объявленной домом.
ДЛИНЫ = (5, 6)

ЦЕПЕЙ_НА_ЯЗЫК = 20
ПОРЯДКОВ = 40


def _область_чиста():
    """Утверждение при сборке: область блока не пересекается с областью домов."""
    беды = []
    for язык, ряд in ЛИЦА.items():
        общие = set(ряд) & set(liarchain.ЛИЦА[язык])
        if общие:
            беды.append(f"{язык}: лица блока живут в пакете — {sorted(общие)}")
    общие = set(ВЕЩИ) & set(adjorder.ВЕЩИ)
    if общие:
        беды.append(f"вещи блока живут в доме — {sorted(общие)}")
    домовы = set()
    for д in liarchain.ДЛИНЫ.values():
        домовы |= {д} if isinstance(д, int) else set(д)
    if not min(ДЛИНЫ) > max(домовы):
        беды.append(f"длины блока {ДЛИНЫ} не длиннее домовых {sorted(домовы)}")
    return беды


def _цепь(язык, лица, первый_правдив, сказанное):
    """Страница цепи рамками дома: (ответ, вопрос, история).

    Разбора здесь нет намеренно: дом пишет разбор на той же странице, потому что учит, —
    блок же спрашивает, и ответ его отрезается одной командой.
    """
    р = liarchain.РЕЧЬ[язык]
    правда = liarchain._истина(первый_правдив, сказанное)
    голова = (р["правдив"] if первый_правдив else р["лжив"]).format(X=лица[0]) + р["точка"]
    хвост = []
    for i, сказал in enumerate(сказанное, start=1):
        формула = (р["правдив"] if сказал else р["лжив"]).format(X=лица[i - 1])
        хвост.append(р["свидетель"].format(Y=лица[i], формула=формула) + р["точка"])
    кого = len(лица) - 1
    вопрос = р["вопрос"].format(Z=лица[кого])
    ответ = р["да"] if правда[кого] else р["нет"]
    return ответ, вопрос, " ".join([голова] + хвост)


def _цепи(язык):
    """Двадцать цепей: десять правдивых ответов и десять лживых, поровну.

    ПЕРЕВЕС ОТВЕТА ЕСТЬ ПОДСКАЗКА: читатель, отвечающий всегда «да», не должен взять
    больше половины. Оттого страницы берутся не подряд, а ПОДБОРОМ до равновесия.
    """
    р = liarchain.РЕЧЬ[язык]
    ряд, вон = ЛИЦА[язык], []
    хочу = {р["да"]: ЦЕПЕЙ_НА_ЯЗЫК // 2, р["нет"]: ЦЕПЕЙ_НА_ЯЗЫК // 2}
    семя = 0
    while sum(хочу.values()) and семя < 4096:
        длина = ДЛИНЫ[семя % len(ДЛИНЫ)]
        лица = [ряд[(семя + i * 3) % len(ряд)] for i in range(длина)]
        if len(set(лица)) == длина:
            первый = (семя // 2) % 2 == 0
            сказанное = [bool((семя >> (k + 2)) & 1) for k in range(длина - 1)]
            ответ, вопрос, история = _цепь(язык, лица, первый, сказанное)
            свежа = all(и != история for _, _, и in вон)
            if хочу.get(ответ, 0) and свежа:
                хочу[ответ] -= 1
                вон.append((ответ, вопрос, история))
        семя += 1
    return вон


def _запись(слова, вещь):
    """Запись рамкой дома: артикль по ЗВУКУ первого слова, а не по его букве."""
    return f"{article(слова[0])} " + " ".join(слова) + " " + вещь


def _порядки():
    """Сорок пар: верная запись против переставленной, вещи — вне дома."""
    вон, взято = [], set()
    рамка = adjorder.РЕЧЬ["выбор"].split("?")[0] + "?"   # ««{верно}» or «{неверно}»?»
    разряды = adjorder.РАЗРЯДЫ
    for сдвиг in range(len(разряды)):
        for k in range(4):
            i = сдвиг % len(разряды)
            j = (сдвиг + 1) % len(разряды)
            if i >= j:
                continue
            а, б = разряды[i], разряды[j]
            сл_а = adjorder.СЛОВА[а][k % len(adjorder.СЛОВА[а])]
            сл_б = adjorder.СЛОВА[б][k % len(adjorder.СЛОВА[б])]
            if сл_а == сл_б:
                continue
            for вещь in ВЕЩИ:
                верно = _запись([сл_а, сл_б], вещь)
                if верно in взято or len(вон) >= ПОРЯДКОВ:
                    continue
                взято.add(верно)
                неверно = _запись([сл_б, сл_а], вещь)
                вон.append((верно, "which order is right?",
                            рамка.format(верно=верно, неверно=неверно)))
    return вон


def main():
    цель = ЦЕЛЬ
    if "--цель" in sys.argv:
        цель = pathlib.Path(sys.argv[sys.argv.index("--цель") + 1])
    if (беды := _область_чиста()):
        for б in беды:
            print(f"  ОБЛАСТЬ НЕЧИСТА: {б}")
        print("КУЗНИЦА БЛОКА ОТКАЗ: область блока пересеклась с областью домов")
        return 2
    строки = _цепи("en") + _цепи("ru") + _порядки()
    ждали = ЦЕПЕЙ_НА_ЯЗЫК * 2 + ПОРЯДКОВ
    if len(строки) != ждали:
        print(f"КУЗНИЦА БЛОКА ОТКАЗ: собрано {len(строки)} строк, а ждали {ждали}")
        return 2
    цель.parent.mkdir(parents=True, exist_ok=True)
    цель.write_text("\n".join("\t".join(с) for с in строки) + "\n", encoding="utf-8")
    print(f"КУЗНИЦА БЛОКА: {цель.relative_to(КОРЕНЬ)} — строк {len(строки)} "
          f"(цепей {ЦЕПЕЙ_НА_ЯЗЫК * 2}, порядков {ПОРЯДКОВ}); "
          f"длины цепи {ДЛИНЫ}, лиц вне пакета {sum(map(len, ЛИЦА.values()))}, "
          f"вещей вне дома {len(ВЕЩИ)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
