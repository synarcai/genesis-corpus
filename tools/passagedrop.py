#!/usr/bin/env python3
"""ДОМ ОТРЫВКА И ВОПРОСА К НЕМУ (14.09, ступень 2, просьба holon-f9 — DROP одним миром).

Рынок DROP (`Discrete Reasoning Over Paragraphs`) ставит к одному отрывку вопросы РАЗНОЙ
ПРИРОДЫ, и в этом всё дело: иной ответ ЛЕЖИТ В ТЕКСТЕ и его надо ВЫПИСАТЬ, а иной в
тексте НЕ НАПИСАН НИГДЕ и его надо ПОСЧИТАТЬ. Holon-f9 просил DROP одним миром — «спан плюс
арифметика», — и он прав: врозь эти роды перестают быть DROP’ом, ибо весь рынок стоит на
том, что читатель ЗАРАНЕЕ НЕ ЗНАЕТ, какого рода вопрос ему задали.

    ОТВЕТ, КОТОРЫЙ ЕСТЬ В ТЕКСТЕ, И ОТВЕТ, КОТОРОГО В ТЕКСТЕ НЕТ, — РАЗНЫЕ ДЕЛА. Первое
    есть ВЫБОР из написанного, второе — СЧЁТ над написанным. Корпус умел и то и другое
    порознь, но нигде не ставил их к ОДНОМУ отрывку, и потому нигде не учил РАЗЛИЧАТЬ.

ОДИН ОТРЫВОК — ШЕСТЬ ВОПРОСОВ, ТРИ РОДА:

    спан        «какой месяц дал больше всего колёс? май» — ответ есть СЛОВО ОТРЫВКА,
                выписанное дословно; считать нечего, надо выбрать;
    счёт        «сколько месяцев дали больше 100 колёс? 2» — ответа в отрывке нет, но и
                арифметики нет: надо пересчитать подходящие;
    разность    «на сколько май дал больше, чем апрель? на 45» — ответа в отрывке нет и
                быть не может: он рождается вычитанием двух написанных чисел.

ГРАНИЦА ОБЪЯВЛЕНА: числа кончаются на 0 или 5, и потому имя после них стоит в родительном
множественного всегда («колёс», а не «колеса»). Согласование числительного с именем есть
дело ИНОГО дома (`numnounforms`), и мешать два дела в одном показе значит учить обоим
наполовину.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("спан", "счёт", "разность")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "спан": "ответ есть слово отрывка, выписанное дословно: выбрать, а не считать",
    "счёт": "ответа в отрывке нет: пересчитать подходящие",
    "разность": "ответа в отрывке нет и быть не может: он рождается вычитанием",
}

# МЕСЯЦЫ СТОЯТ В ИМЕНИТЕЛЬНОМ И ТОЛЬКО В НЁМ: ответ рода «спан» обязан быть СЛОВОМ
# ОТРЫВКА, буква в букву. Скажи отрывок «в марте», а ответ «март» — и род лжёт своим
# именем: выписать уже нельзя, надо ещё и склонить.
МЕСЯЦЫ = {
    "ru": ("март", "апрель", "май", "июнь", "июль"),
    "en": ("march", "april", "may", "june", "july"),
}
ВЕЩИ = {"ru": ("колёс", "метров"), "en": ("wheels", "metres")}

# (три числа, порог). Пороги объявлены так, чтобы счёт выходил РАЗНЫЙ: 2, 1, 3, 0, 2, 1 —
# показ, где ответ всегда один и тот же, учит его называть, не считая.
ЧИСЛА = ((120, 95, 140, 100), (60, 85, 45, 80), (200, 150, 175, 140),
         (30, 55, 40, 60), (105, 90, 115, 100), (70, 65, 80, 75))
ОКНА = (0, 1)          # с какого месяца начинается тройка

РАМКИ = {
    "ru": {
        "отрывок": "{м1} дал {n1} {вещь}, {м2} дал {n2} {вещь}, {м3} дал {n3} {вещь}.",
        "больше_всего": "какой месяц дал больше всего {вещь}? {ответ}.",
        "меньше_всего": "какой месяц дал меньше всего {вещь}? {ответ}.",
        "сколько_больше": "сколько месяцев дали больше {порог} {вещь}? {ответ}.",
        "сколько_меньше": "сколько месяцев дали меньше {порог} {вещь}? {ответ}.",
        "разность": "на сколько {a} дал больше, чем {b}? на {ответ}.",
    },
    "en": {
        "отрывок": "{м1} gave {n1} {вещь}, {м2} gave {n2} {вещь}, {м3} gave {n3} {вещь}.",
        "больше_всего": "which month gave the most {вещь}? {ответ}.",
        "меньше_всего": "which month gave the fewest {вещь}? {ответ}.",
        "сколько_больше": "how many months gave more than {порог} {вещь}? {ответ}.",
        "сколько_меньше": "how many months gave fewer than {порог} {вещь}? {ответ}.",
        "разность": "how many more {вещь} did {a} give than {b}? {ответ}.",
    },
}

ВОПРОСЫ = (("больше_всего", "спан"), ("меньше_всего", "спан"),
           ("сколько_больше", "счёт"), ("сколько_меньше", "счёт"),
           ("разность", "разность"), ("разность", "разность"))


def _ответ(вид, месяцы, числа, порог, пара):
    пары = list(zip(месяцы, числа))
    if вид == "больше_всего":
        return max(пары, key=lambda п: п[1])[0]
    if вид == "меньше_всего":
        return min(пары, key=lambda п: п[1])[0]
    if вид == "сколько_больше":
        return str(sum(1 for _м, n in пары if n > порог))
    if вид == "сколько_меньше":
        return str(sum(1 for _м, n in пары if n < порог))
    a, b = пара
    return str(dict(пары)[a] - dict(пары)[b])


def страница(язык, окно, набор, вещь, вид, который):
    рамки = РАМКИ[язык]
    месяцы = МЕСЯЦЫ[язык][окно:окно + 3]
    *числа, порог = набор
    пары = sorted(zip(месяцы, числа), key=lambda п: п[1])
    # ПЕРВЫЙ ОБЯЗАН БЫТЬ БОЛЬШИМ: «на сколько март дал больше, чем май» при меньшем марте
    # есть не трудный вопрос, а ложный, и дом такого не ставит.
    пара = (пары[2][0], пары[0][0]) if который == 0 else (пары[1][0], пары[0][0])
    отрывок = рамки["отрывок"].format(вещь=вещь, **{f"м{i + 1}": м for i, м in
                                                    enumerate(месяцы)},
                                      **{f"n{i + 1}": n for i, n in enumerate(числа)})
    вопрос = рамки[вид].format(вещь=вещь, порог=порог, a=пара[0], b=пара[1],
                               ответ=_ответ(вид, месяцы, числа, порог, пара))
    return f"{отрывок} {вопрос}"


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for окно in ОКНА:
            for набор in ЧИСЛА:
                for вещь in ВЕЩИ[язык]:
                    пара = 0
                    for вид, род in ВОПРОСЫ:
                        вон.setdefault(страница(язык, окно, набор, вещь, вид, пара),
                                       (язык, род))
                        пара += вид == "разность"   # две разности на отрывок: 0 и 1
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД ЧИТАЕТ ОТРЫВОК ЗАНОВО: он выбирает из записи все пары «имя — число», а потом отвечает
# на вопрос сам. Ни чисел, ни имён он от дома не берёт; порча любого числа или имени меняет
# либо ответ, либо саму подсудность.
def _пары(язык, отрывок, вещь):
    один = РАМКИ[язык]["отрывок"].split(", ")[0]          # «{м1} дал {n1} {вещь}»
    о = (re.escape(один).replace(re.escape("{м1}"), "(?P<м>[^,.?]+?)")
         .replace(re.escape("{n1}"), r"(?P<n>\d+)")
         .replace(re.escape("{вещь}"), re.escape(вещь)))
    образец = re.compile(о)
    вон = []
    for кусок in отрывок.rstrip(".").split(", "):
        м = образец.fullmatch(кусок.strip())
        if not м:
            return None
        # МЕСЯЦ ОБЪЯВЛЕН ТАБЛИЦЕЙ, А НЕ ОПОЗНАЁТСЯ ДЫРОЙ (16.09, прибор
        # `scripts/word_mutants.py`: подмена буквы «april» → «apri» прошла незамеченной).
        # Дыра «любое слово до запятой» читает месяцем всякое слово, и подсадка, тронувшая
        # ИМЯ месяца, не задевала ни одного числа — а суд считает числа.
        #
        #     ИМЯ, ОПОЗНАВАЕМОЕ ДЫРОЙ, ПОДМЕНЯЕТСЯ БЕЗ ПОСЛЕДСТВИЙ: дом объявил свои пять
        #     месяцев таблицей, и всякое шестое слово на их месте есть порча, а не месяц.
        if м.group("м") not in МЕСЯЦЫ[язык]:
            return None
        вон.append((м.group("м"), int(м.group("n"))))
    return вон or None


def _вопрос_образцы(язык):
    рамки = РАМКИ[язык]
    вон = {}
    for вид in ("больше_всего", "меньше_всего", "сколько_больше", "сколько_меньше",
                "разность"):
        о = re.escape(рамки[вид])
        for дыра, узор in (("вещь", r"[^,.?]+?"), ("порог", r"\d+"), ("a", r"[^,.?]+?"),
                           ("b", r"[^,.?]+?"), ("ответ", r"[^.?]+")):
            о = о.replace(re.escape("{" + дыра + "}"), f"(?P<{дыра}>{узор})")
        вон[вид] = re.compile(о + r"$")
    return вон


_ВОПРОСЫ = {я: _вопрос_образцы(я) for я in ЯЗЫКИ}


def судить(строка):
    """(судимо, истинно) — отрывок прочитан заново, и ответ добыт из него судом."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for вид, образец in _ВОПРОСЫ[язык].items():
            м = образец.search(строка)
            if not м or not строка[:м.start()].strip():
                continue
            # ВЕЩЬ НАЗВАНА НЕ ВСЯКИМ ВОПРОСОМ: русская «разность» её не поминает
            # («на сколько май дал больше, чем апрель?»), и тогда суд перебирает
            # объявленные вещи, пока отрывок не прочтётся. Вещь ЧУЖАЯ — запись не наша, и
            # суд о ней молчит, а не зовёт ложной.
            названа = м.groupdict().get("вещь")
            if названа is not None and названа not in ВЕЩИ[язык]:
                continue
            вещи = [названа] if названа else list(ВЕЩИ[язык])
            пары = None
            for вещь in вещи:
                пары = _пары(язык, строка[:м.start()].strip(), вещь)
                if пары:
                    break
            if not пары:
                continue
            if len({м_ for м_, _n in пары}) != len(пары):
                return True, False
            месяцы = [м_ for м_, _n in пары]
            числа = [n for _м, n in пары]
            порог = int(м.group("порог")) if "порог" in м.groupdict() and \
                м.group("порог") else 0
            пара = (м.groupdict().get("a"), м.groupdict().get("b"))
            if вид == "разность":
                if пара[0] not in месяцы or пара[1] not in месяцы:
                    return True, False
                if dict(пары)[пара[0]] <= dict(пары)[пара[1]]:
                    return True, False      # «больше» сказано о меньшем
            return True, _ответ(вид, месяцы, числа, порог, пара) == м.group("ответ")
    return False, True


# ПОДСАДКИ ОБЪЯВЛЕНЫ ЗДЕСЬ, И СУД БЕРЁТ ИХ ОТСЮДА ЖЕ (14.09). Дом скобок держал свой
# список, суд — свой, похожий; рамка вопроса в доме переменилась, а в суде осталась
# прежней, и четыре подсадки из семи перестали попадать в рамку — то есть перестали быть
# судимыми вовсе, а прибор доложил, что не поймал их. ДВА ПОХОЖИХ СПИСКА РАСХОДЯТСЯ
# МОЛЧА; один список расходиться не с чем.
о = "март дал 120 колёс, апрель дал 95 колёс, май дал 140 колёс. "
ПОДСАДКИ = (о + "какой месяц дал больше всего колёс? март.",
            о + "какой месяц дал меньше всего колёс? март.",
            о + "сколько месяцев дали больше 100 колёс? 3.",
            о + "сколько месяцев дали меньше 100 колёс? 2.",
            о + "на сколько май дал больше, чем апрель? на 40.",
            о + "на сколько апрель дал больше, чем май? на 45.",
            "march gave 120 wheels, april gave 95 wheels, may gave 140 wheels. "
            "which month gave the most wheels? april.")


def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    assert {р for _в, р in ВОПРОСЫ} == set(РОДЫ), "вопрос объявлен не всякому роду"
    # СЧЁТ ОБЯЗАН ВЫХОДИТЬ РАЗНЫЙ: порог, дающий всегда одно число, учит его называть.
    счета = {sum(1 for n in набор[:3] if n > набор[3]) for набор in ЧИСЛА}
    assert len(счета) >= 3, f"порог даёт слишком ровный счёт: {sorted(счета)}"
    for набор in ЧИСЛА:
        assert len(set(набор[:3])) == 3, f"числа в наборе совпали: {набор}"
    # ОТВЕТ РОДА «СПАН» ОБЯЗАН БЫТЬ СЛОВОМ ОТРЫВКА, БУКВА В БУКВУ.
    for с, (_я, род) in ПОКАЗЫ.items():
        if род != "спан":
            continue
        отрывок, ответ = с.split("? ")[0].split(". ")[0], с.rsplit("? ", 1)[1].rstrip(".")
        assert ответ in отрывок.split(), f"спан не выписан из отрывка: {с}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
