#!/usr/bin/env python3
"""ДОМ ЗАКОНОВ ДЕЙСТВИЯ — И ГЛАВНОЕ В НЁМ ЕСТЬ ГРАНИЦА ЗАКОНА.

    ЗАКОНОВ ДЕЙСТВИЯ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 234 мирам показов:
    «переместительный», «commutative» — НОЛЬ; «сочетательный», «associative» — НОЛЬ;
    «распределительный», «раскрыть скобки», «distributive» — НОЛЬ; скобка «(a + b) × c» — НОЛЬ.

    Свод считает тысячами страниц и ни разу не сказал, что a + b = b + a.

ОДИН МИР ПОКАЗЫВАЕТ ЭТО ГОЛЫМ РАВЕНСТВОМ — 78 строк вида «1 + 3 = 3 + 1», без имени и без
причины. И среди них стои́т «1 + 1 = 1 + 1».

    ПРИМЕР, В КОТОРОМ НЕЧЕГО ПЕРЕСТАВЛЯТЬ, НЕ ПОКАЗЫВАЕТ ПЕРЕСТАНОВКИ.

Потому в родах перестановки здесь ВСЕГДА разные числа: вырожденный случай не пример закона, а
его пустая тень.

СЕРДЦЕ ДОМА — ТРЕТИЙ РОД, И ОН ГОВОРИТ, ГДЕ ЗАКОН КОНЧАЕТСЯ:

    ЗАКОН БЕЗ ГРАНИЦЫ ЕСТЬ ЛОЖЬ, СКАЗАННАЯ НАПОЛОВИНУ.

Читатель, выучивший «от перемены мест не меняется» на сложении и умножении, применит это к
вычитанию и делению — если ему не показать, ЧТО ИМЕННО там выходит. И показано не «нельзя», а
результат: ответ становится ПРОТИВОПОЛОЖНЫМ при вычитании и ДОЛЕЙ при делении. Обе границы
уводят в соседние дома — знаковый и дробный, — и дом стои́т на них, а не рядом.

ПЯТЬ РОДОВ:

    перестановка суммы    3 + 5 = 8 и 5 + 3 = 8: от перемены мест слагаемых сумма
                          не меняется.
    перестановка произв.  3 × 5 = 15 и 5 × 3 = 15: от перемены мест множителей
                          произведение не меняется.
    граница закона        5 − 3 = 2, а 3 − 5 = −2: вычитание перемены мест не терпит,
                          и ответ стал противоположным.                  ← СЕРДЦЕ ДОМА
                          6 ÷ 3 = 2, а 3 ÷ 6 = 1/2: деление перемены мест не терпит,
                          и ответ стал долей.
    сочетание             (3 + 5) + 2 = 10 и 3 + (5 + 2) = 10: скобка сумму не меняет.
    раскрытие скобки      (3 + 5) × 2 = 16 и 3 × 2 + 5 × 2 = 16: множитель достаётся
                          каждому слагаемому.

ПЕРВЫЙ И ТРЕТИЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО ДЕЙСТВИЮ: та же перестановка, те же числа, и разница в
одном месте — какое действие между ними. Порознь первый внушал бы, что переставлять можно всегда.

ПЯТЫЙ РОД ЕСТЬ ЕДИНСТВЕННОЕ МЕСТО СВОДА, ГДЕ СКОБКА РАСКРЫВАЕТСЯ. До него скобка умела только
менять старшинство (дом старшинства); здесь она показывает, что умножение ДЕЛИТСЯ между
слагаемыми, — и это уже не порядок счёта, а закон о самих действиях.

    python3 tools/opslawforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("перестановка суммы", "перестановка произведения", "граница закона",
        "сочетание", "раскрытие скобки")

РАМКИ = {
    "ru": {
        "перестановка суммы": "{a} + {b} = {s} и {b} + {a} = {s}: от перемены мест слагаемых сумма не меняется.",
        "перестановка произведения": "{a} × {b} = {p} и {b} × {a} = {p}: от перемены мест множителей произведение не меняется.",
        "граница вычитания": "{a} − {b} = {d}, а {b} − {a} = −{d}: вычитание перемены мест не терпит, и ответ стал противоположным.",
        "граница деления": "{a} ÷ {b} = {k}, а {b} ÷ {a} = 1/{k}: деление перемены мест не терпит, и ответ стал долей.",
        "сочетание": "({a} + {b}) + {c} = {s} и {a} + ({b} + {c}) = {s}: скобка сумму не меняет.",
        "раскрытие скобки": "({a} + {b}) × {c} = {p} и {a} × {c} + {b} × {c} = {p}: множитель достаётся каждому слагаемому.",
    },
    "en": {
        "перестановка суммы": "{a} + {b} = {s} and {b} + {a} = {s}: changing the order of addends does not change the sum.",
        "перестановка произведения": "{a} × {b} = {p} and {b} × {a} = {p}: changing the order of factors does not change the product.",
        "граница вычитания": "{a} − {b} = {d}, but {b} − {a} = −{d}: subtraction does not allow changing the order, and the answer became the opposite.",
        "граница деления": "{a} ÷ {b} = {k}, but {b} ÷ {a} = 1/{k}: division does not allow changing the order, and the answer became a share.",
        "сочетание": "({a} + {b}) + {c} = {s} and {a} + ({b} + {c}) = {s}: the bracket does not change the sum.",
        "раскрытие скобки": "({a} + {b}) × {c} = {p} and {a} × {c} + {b} × {c} = {p}: the multiplier reaches every addend.",
    },
}

# ГРАНИЦА ДЕРЖИТ ДВЕ РАМКИ ОДНОГО ЗАКОНА: вычитание и деление отказывают перестановке по одной
# причине, и разлучать их значило бы говорить, что отказов два.
_РАМКИ_ГРАНИЦЫ = ("граница вычитания", "граница деления")
ПУСТО = dict(a=0, b=0, c=0, s=0, p=0, d=0, k=0)


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        # ВЫРОЖДЕННЫЙ СЛУЧАЙ ИСКЛЮЧЁН ПО СУЩЕСТВУ: a < b, и переставлять всегда есть что.
        for a in range(1, 13):
            for b in range(a + 1, 13):
                вон[рамки["перестановка суммы"].format(
                    **dict(ПУСТО, a=a, b=b, s=a + b))] = (язык, "перестановка суммы")
                if a > 1:
                    вон[рамки["перестановка произведения"].format(
                        **dict(ПУСТО, a=a, b=b, p=a * b))] = (
                        язык, "перестановка произведения")
                if (a + b) % 2 == 0:
                    вон[рамки["граница вычитания"].format(
                        **dict(ПУСТО, a=b, b=a, d=b - a))] = (язык, "граница закона")
        # ГРАНИЦА ДЕЛЕНИЯ: делимое кратно делителю, и обратное частное есть ЕДИНИЧНАЯ доля
        # 1/k — то самое, чем живёт дом доли единицы.
        for b in range(2, 13):
            for k in range(2, 9):
                if b * k <= 96 and (b + k) % 2 == 0:
                    вон[рамки["граница деления"].format(
                        **dict(ПУСТО, a=b * k, b=b, k=k))] = (язык, "граница закона")
        for a in range(1, 9):
            for b in range(1, 9):
                for c in range(1, 9):
                    if (a + b + c) % 7 == 0:
                        вон[рамки["сочетание"].format(
                            **dict(ПУСТО, a=a, b=b, c=c, s=a + b + c))] = (язык, "сочетание")
        for a in range(1, 10):
            for b in range(a + 1, 11):
                for c in range(2, 6):
                    # МНОЖИТЕЛЬ, СОВПАВШИЙ СО СЛАГАЕМЫМ, ПРЯЧЕТ, ЧТО ОН МНОЖИТЕЛЬ:
                    # на «1 × 2 + 2 × 2» две двойки играют разные роли, и глазу их
                    # не развести. Страница остаётся истинной, но перестаёт показывать.
                    if (a + b + c) % 2 == 1 and c not in (a, b):
                        вон[рамки["раскрытие скобки"].format(
                            **dict(ПУСТО, a=a, b=b, c=c, p=(a + b) * c))] = (
                            язык, "раскрытие скобки")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ДРОБНАЯ ЧЕРТА И ЗНАК МИНУС СУТЬ ГРАНИЦЫ ЧИСЛА: «1/{k}» не есть единица при k, а «−{d}» не
# есть {d}. Образец, потерявший их, подтвердил бы ложь как истину.
_СУММА = re.compile(r"(?<![/\d])(\d+) \+ (\d+) = (\d+)(?![/\d])")
# ПРОИЗВЕДЕНИЕ, СТОЯЩЕЕ СЛАГАЕМЫМ, НЕ ЕСТЬ ОТДЕЛЬНОЕ РАВЕНСТВО. На строке «1 × 2 + 2 × 2 = 6»
# прежний образец брал «2 × 2 = 6» — второе слагаемое вместе с итогом ВСЕЙ суммы — и звал
# девяносто одну честную страницу ложью. Та же жадность, что брала «21 = 2 × 1» из «21 = 2 × 10 +
# 1»: ЗНАК ПЕРЕД ЧИСЛОМ ГОВОРИТ, ЧЕЙ ЭТО ЧЛЕН, и образец обязан его видеть.
_ПРОИЗВ = re.compile(r"(?<![/\d])(?<!\+ )(\d+) × (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (−?\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_ДОЛЯ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = 1/(\d+)(?![/\d])")
_СКОБКА_СУММА = re.compile(r"\((\d+) \+ (\d+)\) \+ (\d+) = (\d+)")
_СКОБКА_ПРАВО = re.compile(r"(\d+) \+ \((\d+) \+ (\d+)\) = (\d+)")
_РАСКРЫТИЕ = re.compile(r"\((\d+) \+ (\d+)\) × (\d+) = (\d+)")
_СЛОЖЕНО = re.compile(r"(\d+) × (\d+) \+ (\d+) × (\d+) = (\d+)")


def _цел(с):
    return int(с.replace("−", "-"))


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ, ПЕРЕСЧИТАННЫЙ ЦЕЛИКОМ, ВКЛЮЧАЯ ОБЕ СКОБКИ.
    for a, b, c in _СУММА.findall(с):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != _цел(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b, k in _ДОЛЯ.findall(с):
        if int(k) == 0 or int(b) != int(a) * int(k):
            return True, False
    for обр, счёт in ((_СКОБКА_СУММА, lambda g: int(g[0]) + int(g[1]) + int(g[2])),
                      (_СКОБКА_ПРАВО, lambda g: int(g[0]) + int(g[1]) + int(g[2])),
                      (_РАСКРЫТИЕ, lambda g: (int(g[0]) + int(g[1])) * int(g[2]))):
        for г in обр.findall(с):
            if счёт(г) != int(г[3]):
                return True, False
    for a, b, c, d, e in _СЛОЖЕНО.findall(с):
        if int(a) * int(b) + int(c) * int(d) != int(e):
            return True, False
    return True, True


def _порча_одним_словом(с):
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    пс = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "перестановка суммы")
    рс = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "раскрытие скобки")
    if судить(пс.replace("слагаемых", "слагаемы"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(рс.replace("достаётся", "достаётс"))[1] is not False:
        беды.append("обрезанное слово в раскрытии прошло")
    if судить(пс + " " + пс)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ВЫРОЖДЕННЫЙ СЛУЧАЙ НЕ ДОЛЖЕН БЫТЬ СКОВАН: «1 + 1 = 1 + 1» не показывает перестановки.
    #
    # СТРАЖ СМОТРИТ СВОИ РОДЫ, А НЕ ВСЕ. Первая редакция искала «a × a =» по ВСЕМУ дому и
    # обвинила девяносто честных страниц раскрытия: на «1 × 2 + 2 × 2 = 6» второе слагаемое
    # совпало с множителем, и это не вырожденная перестановка, а честный член суммы.
    # ОБВИНЕНИЕ ПО ФОРМЕ БЕЗ РАЗБОРА СВЯЗИ — та же беда, от которой суд согласования лечился
    # дважды. Страж поднят на свои два рода и молчит о прочих.
    перест = [с for с, (_, р) in ПОКАЗЫ.items() if р.startswith("перестановка")]
    if any(re.search(r"\b(\d+) \+ \1 =", с) for с in перест):
        беды.append("ВЫРОЖДЕННЫЙ ПРИМЕР: слагаемые равны, переставлять нечего")
    if any(re.search(r"\b(\d+) × \1 =", с) for с in перест):
        беды.append("ВЫРОЖДЕННЫЙ ПРИМЕР: множители равны")
    if any("-" in с for с in ПОКАЗЫ):
        беды.append("ДЕФИС В ПОКАЗЕ: дом обязан писать знаком минус U+2212")
    print(f"ЗАКОНЫ ДЕЙСТВИЯ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
