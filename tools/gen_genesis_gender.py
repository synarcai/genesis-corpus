#!/usr/bin/env python3
"""GENESIS layer: РОД В ЧУЖОМ ЯЗЫКЕ — see tools/genderforms.py for the law.

ПРАВИЛО И ЧЕТЫРЕ ЕГО ЛОВУШКИ РАЗДЕЛЕНЫ НА ГРУППЫ ПО ТОМУ, ЧТО ИМЕННО ОНИ ЛОМАЮТ.

«Род назван» и «род не есть пол» идут вместе: первое даёт правило, второе отнимает у
читателя вывод «род есть пол», который он сделал бы из первого сам. Дать одно без
другого значило бы выучить его ошибке вместе с правилом.

«Род не виден по слову» и «множественное стирает род» — второй группой: обе о том, ГДЕ
род виден и где невидим, и обе смотрят на одни и те же три слова.

«Солнце в четырёх языках» стои́т особо, ибо это не ловушка, а ДОВОД: один предмет,
четыре языка, три рода — и после него нельзя уже думать, будто род живёт в предмете.
«Артикль лжёт» тоже особо: единственный случай дома, и соседство разбавило бы его.

ВОПРОС отдельно — ответ рядом с ним отнял бы у него цену.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import genderforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_gender.txt"
ГРУППЫ = (("род назван", "род не есть пол"),
          ("род не виден по слову", "множественное стирает род"),
          ("солнце в четырёх языках",),
          ("артикль лжёт",),
          ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
