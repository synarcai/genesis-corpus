#!/usr/bin/env python3
"""ОБРАЩЕНИЕ: утверждение становится вопросом, не теряя ответа.

ВОПРОС ПОРОЖДАЕТСЯ ИЗ ОТВЕТА, А НЕ ПИШЕТСЯ РЯДОМ. Вопрос, написанный
отдельно от ответа, разошёлся бы с ним в тот же день: подсадка нашла в
языке формул строку «how is $|16|$ said in words? $|15|$ in words is …»,
которую суд звал истиной, читая только вторую половину. Здесь вопрос
есть ТА ЖЕ строка с вынутым сказуемым, поставленная перед нею целиком:
«два плюс четыре равно шесть» → «чему равно два плюс четыре? два плюс
четыре равно шесть.» Ответ судится ТЕМ ЖЕ судом, что и утверждение.

ОДИН ДОМ ДЛЯ ВСЕХ СИРОТ. Пять миров корпуса лежали без генератора и без
единого вопроса; владелец объявил ноль немых законом. Обращать каждый
своей таблицей значило бы пять таблиц, расходящихся в пять сторон.
Здесь таблица одна, а генератор сироты объявляет лишь, КАКИЕ образцы
из неё его касаются, — и это объявление читается, а не угадывается.

ЧТО ОБЯЗАН ДОКАЗАТЬ ВСЯКИЙ ОБРАЗЕЦ ДО ТОГО, КАК ВОЙТИ СЮДА: что
обращённая строка СУДИМА палатой и что ПОРЧА ответа ловится. Все
образцы ниже проверены так до записи — порча даёт (True, False).
"""
import re

# (имя, образец утверждения, форма вопроса). Форма ставится ПЕРЕД
# утверждением; утверждение остаётся целиком.
ОБРАЗЦЫ = {
    "равно": (re.compile(r"^(?P<л>.+?) равно (?P<п>.+?)\.$"),
              "чему равно {л}? "),
    "equals": (re.compile(r"^(?P<л>.+?) equals (?P<п>.+?)\.$"),
               "what is {л}? "),
    # ФОРМЫ ВОПРОСА О ЗНАЧЕНИИ — ИЗ ПАКЕТОВ ЯЗЫКА (Т-4 коллегии
    # выразительности, 03.09): вторая формулировка того же рода («сколько
    # будет …?», «how much is …?») объявлена пакетом, а не списком здесь;
    # чередование по номеру строки: чётные — русский, нечётные — английский,
    # форма — по половине номера, и каждая форма несёт свою массу.
    "глиф": (re.compile(r"^(?P<л>[\d\s+−×÷/*()-]+?) = (?P<п>-?\d+)\.$"),
             None),
    "число читается": (re.compile(r"^число (?P<л>\S+) читается как (?P<п>.+?)\.$"),
                       "как читается число {л}? "),
    "слово читается": (re.compile(r"^слово (?P<л>\S+) читается как (?P<п>.+?)\.$"),
                       "как читается слово {л}? "),
    "знак читается": (re.compile(r"^знак (?P<л>\S+) читается как (?P<п>.+?)\.$"),
                      "как читается знак {л}? "),
    "number read": (re.compile(r"^the number (?P<л>\S+) is read as (?P<п>.+?)\.$"),
                    "how is the number {л} read? "),
    "sign read": (re.compile(r"^the sign (?P<л>\S+) is read as (?P<п>.+?)\.$"),
                  "how is the sign {л} read? "),
    "word read": (re.compile(r"^the word (?P<л>\S+) is read as (?P<п>.+?)\.$"),
                  "how is the word {л} read? "),
    # программа: «function add(a b) return a + b. add(5 1) → 5 + 1 → 6.»
    "вызов": (re.compile(r"^function (?P<им>\w+)\(.+?\) return .+?\. "
                         r"(?P<л>(?P=им)\([^)]*\)) → .+$"),
              "what does {л} give? "),
    # логика множеств: «{b d} ⊂ {a b d} = T.»
    "подмножество": (re.compile(r"^(?P<л>\{[^}]*\} [⊂⊆∈∉] \{[^}]*\}) = [TF]\.$"),
                     "is {л}? "),
    # сортировка и прочие ходы программ: «сортировка [9 1 6] → [1 6 9].»
    "ход": (re.compile(r"^(?P<л>сортировка \[[^\]]*\]) → .+\.$"),
            "что даёт {л}? "),
}


# ПЕРЕМЕННАЯ: одиночная латинская буква или её русское имя.
ПЕРЕМЕННАЯ = re.compile(r"(?<![\w\\])([a-z]|икс|игрек|зет)(?![\w])")


def тождество(левое, правое):
    """Стоит ли одна и та же переменная по обе стороны равенства.

    ОБРАЩАЕТСЯ ВЫЧИСЛЕНИЕ, А НЕ ТОЖДЕСТВО. Ворота школьного мира закрыли
    120 строк вида «what is x plus y? x plus y equals y plus x»: вопрос
    «чему равно x плюс y» не имеет числового ответа, и суд формул честно
    зовёт его ложью. Тождество говорит о ФОРМЕ, а не о величине, и
    вопрос к нему иной («верно ли, что …») — здесь он не строится.
    """
    return bool(set(ПЕРЕМЕННАЯ.findall(левое))
                & set(ПЕРЕМЕННАЯ.findall(правое)))


_ФОРМЫ = {}


def формы_значения():
    """Формы вопроса о значении из пакетов ru и en — ru1, en1, ru2, en2, …:
    чётность номера строки выбирает язык, половина номера — форму."""
    if not _ФОРМЫ:
        import json
        import pathlib
        где = pathlib.Path(__file__).resolve().parent / "langpacks"
        по_языкам = [json.loads((где / f"{я}.json").read_text(encoding="utf-8"))["ask_forms"]["value"]
                     for я in ("ru", "en")]
        глубина = min(len(ф) for ф in по_языкам)
        _ФОРМЫ["value"] = tuple(по_языкам[я][k].replace("{}", "{л}") + " "
                               for k in range(глубина) for я in (0, 1))
    return _ФОРМЫ["value"]


def _разбор(строка, образцы):
    """(левое, утверждение, форма|None) по объявленным образцам, или None."""
    т = строка.strip()
    for имя in образцы:
        образец, форма = ОБРАЗЦЫ[имя]
        m = образец.match(т)
        if not m:
            continue
        if "п" in m.groupdict() and тождество(m.group("л"), m.group("п")):
            return None
        return m.group("л").strip(), т, форма
    return None


def обратить(строка, образцы, номер=0):
    """Вопросная строка к утверждению по ОБЪЯВЛЕННЫМ образцам, или None."""
    р = _разбор(строка, образцы)
    if р is None:
        return None
    л, т, форма = р
    if форма is None:
        форма = формы_значения()
    if isinstance(форма, tuple):
        # двуязычная форма чередуется по номеру строки, чтобы ни
        # один язык не остался без вопросной поверхности
        форма = форма[номер % len(форма)]
    return форма.format(л=л) + т


def обращения(строка, образцы, номер=0):
    """[вопросные строки] к утверждению: одна форма по номеру, а если она —
    ЗАДАНИЕ (форма без «?»), на каждой второй такой строке рядом встаёт
    первая вопросная форма того же языка (e9 04.09: суд перефраз видит
    задание и вопрос одной рамкой, когда они стоят на одной паре чисел)."""
    р = _разбор(строка, образцы)
    if р is None:
        return []
    л, т, форма = р
    вон = [обратить(строка, образцы, номер)]
    if форма is None:
        формы = формы_значения()
        выбранная = формы[номер % len(формы)]
        if "?" not in выбранная and (номер // len(формы)) % 2 == 0:
            вон.append(формы[номер % 2].format(л=л) + т)
    return вон


def с_вопросами(строки, образцы, проходов, шаг):
    """Доля семени для прохода `шаг` с вопросами к обратимым строкам.

    СЕМЯ ДЕЛИТСЯ МЕЖДУ ПРОХОДАМИ, А НЕ ПОВТОРЯЕТСЯ В КАЖДОМ: слой
    собирается несколькими проходами, и генератор, отдающий всё семя
    в каждый, размножил бы мир кратно. Строка идёт в проход по своему
    номеру и попадает в мир ровно один раз — и её вопрос с нею.
    """
    вон = []
    for номер, с in enumerate(строки):
        if not с.strip() or номер % проходов != шаг:
            continue
        вон.append(с)
        вон.extend(обращения(с, образцы, номер))
    return вон
