ПО_ФОРМЕ = {ф: ключ for ключ, формы in СЧЁТНЫЕ.items() for ф in формы}


def форма(ключ, счёт):
    """Русская форма слова при данном счёте — по закону ПАКЕТА."""
    return units.ру_форма(СЧЁТНЫЕ[ключ], счёт)


def согласовано(счёт, слово):
    """Верна ли форма при счёте; None — слово не объявлено."""
    ключ = ПО_ФОРМЕ.get(слово)
    if ключ is None:
        return None
    return слово == форма(ключ, счёт)
