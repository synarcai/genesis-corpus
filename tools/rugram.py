# утверждение о множестве БЕЗ СЧЁТА, — корпус не показывал ни разу.
#
# ФОРМА ВЫВОДИТСЯ, А НЕ ПЕРЕЧИСЛЯЕТСЯ. Основа берётся из РОДИТЕЛЬНОГО
# ЕДИНСТВЕННОГО — второй счётной формы, — ибо там она уже без беглой
# гласной: «день» → «дня» → «дн-», «цветок» → «цветка» → «цветк-»,
# «узел» → «узла» → «узл-». Тем же ходом живёт `предложный_мн` выше:
# один факт о русской основе — одно место.
#
# ОКОНЧАНИЕ ВЫБИРАЮТ РОД И МЯГКОСТЬ. «И» после шипящих и
# заднеязычных есть правило ПИСЬМА, а не морфологии («книги», не
# «книгы»), и оно уже объявлено в `_ТВЁРДЫЕ_НА_ПИСЬМЕ`.

# ИСКЛЮЧЕНИЯ НАЗВАНЫ ПОИМЁННО, А НЕ ОБОЙДЕНЫ МОЛЧА. Оба стоят ВНУТРИ
# объявленного словаря, и оба не подчиняются правилу по существу:
#   яблоко — средний род на «-и», а не на «-а»: правило дало бы
#            «яблока», то есть родительный единственного;
#   ребро  — чередование гласной в основе, которого никакое сцепление
#            строк дать не может: «рёбра», а не «ребра».
_МНОЖЕСТВЕННЫЕ_ИМЕНОВАННЫЕ = {"яблоко": "яблоки", "ребро": "рёбра"}

# ВНЕ ГРАНИЦЫ, И ГРАНИЦА ОБЪЯВЛЕНА. Правило требует ОДНОГО имени, у
# которого вторая счётная форма есть родительный единственного; здесь
# этого нет:
#   «квадратный метр», «кубический метр», «равновозможный исход» —
#       два слова, и прилагательное при них согласуется своей
#       парадигмой, какой дом не объявляет;
#   «седьмая» — субстантивированное прилагательное: во второй счётной
#       форме у него стоит «седьмых», то есть уже множественное.
# ВНЕ СЛОВАРЯ ВОВСЕ — супплетивные «человек → люди» и «ребёнок →
# дети»: их нельзя вывести никаким правилом, и внести их сюда значило
# бы менять вердикты счётного суда по всему корпусу, чего эта задача
# не касается. Молчание о них НАЗВАНО, а не оставлено пустым местом.
_МНОЖЕСТВЕННЫЕ_ВНЕ = frozenset((
    "квадратный метр", "кубический метр", "равновозможный исход",
    "седьмая"))


def именительный_мн(ключ):
    """Именительное множественное объявленного имени, или None.

    None есть ЧЕСТНАЯ ГРАНИЦА, а не пропуск: всякое слово, о котором
    правило молчит, названо выше вместе с причиной.

    ЧТО ПРАВИЛО НЕ РЕШАЕТ И НЕ ДЕЛАЕТ ВИД, ЧТО РЕШАЕТ: у иных имён
    живут ДВЕ законные формы — «годы» и «года», «цветки» и «цветы».
    Выдаётся одна, выведенная; вторая не объявлена и потому судом не
    читается вовсе — не ложь, а молчание.
    """
    if ключ in _МНОЖЕСТВЕННЫЕ_ИМЕНОВАННЫЕ:
        return _МНОЖЕСТВЕННЫЕ_ИМЕНОВАННЫЕ[ключ]
    if ключ in _МНОЖЕСТВЕННЫЕ_ВНЕ:
        return None
    формы = СЧЁТНЫЕ.get(ключ)
    if формы is None:
        return None
    род_ед = формы[1]
    основа = род_ед[:-1] if род_ед[-1] in "аяуыиеё" else род_ед
    мягко = род_ед[-1] in "яи" and основа[-1:] not in tuple(
        _ТВЁРДЫЕ_НА_ПИСЬМЕ)
    if род(ключ) == "с":
        return основа + ("я" if мягко else "а")
    if мягко or основа[-1:] in tuple(_ТВЁРДЫЕ_НА_ПИСЬМЕ):
        return основа + "и"
    return основа + "ы"


# поверхность → ключ, как ПО_ФОРМЕ этажом выше: всякая выведенная
# форма узнаётся обратно. Замер: 54 формы, ни одного столкновения и ни
# одного совпадения с ключом словаря.
ПО_МНОЖЕСТВЕННОМУ = {м: к for к in СЧЁТНЫЕ
                     if (м := именительный_мн(к)) is not None}
