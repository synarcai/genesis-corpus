# РОД ВЫВОДИТСЯ ИЗ ОКОНЧАНИЯ, А НЕ ОБЪЯВЛЯЕТСЯ СПИСКОМ. Десяток
# существительных на «-мя» средние вопреки виду («время», «семя») — это
# ИМЕНОВАННЫЙ класс исключений, а не перечень слов: правило знает,
# почему оно отступает. Прочее выводится: «-а/-я» женский, «-о/-е»
# средний, согласная — мужской. Правило живёт здесь, ибо это факт
# русского языка, а не факт разметки: им пользуются и слой разметки, и
# суд стиля, и всякий, кому надо согласовать прилагательное.
_ПОЛНЫЕ_ОКОНЧАНИЯ = {"м": "ый", "ж": "ая", "с": "ое"}
_КРАТКИЕ_ОКОНЧАНИЯ = {"м": "", "ж": "а", "с": "о"}


def род(слово):
    """Род русского существительного в именительном."""
    с = слово.lower()
    if с.endswith("мя"):
        return "с"
    if с[-1] in "ая":
        return "ж"
    if с[-1] in "ое":
        return "с"
    return "м"


def полное(основа, слово):
    """Прилагательное, согласованное со словом: «жирный свет»."""
    return основа + _ПОЛНЫЕ_ОКОНЧАНИЯ[род(слово)]


def краткое(основа, слово):
    """Краткая форма, согласованная со словом: «вложена», «вложено»."""
    return основа + _КРАТКИЕ_ОКОНЧАНИЯ[род(слово)]


