# ШИПЯЩИЕ И ЗАДНЕЯЗЫЧНЫЕ НЕ ТЕРПЯТ «Я» ПОСЛЕ СЕБЯ — это правило
# ПИСЬМА, а не морфологии, и оно названо отдельно, чтобы не выглядеть
# исключением там, где его нет: «копейках», а не «копейкях».
_ТВЁРДЫЕ_НА_ПИСЬМЕ = "кгхжчшщ"


def предложный_мн(слово):
    """Предложный множественного, выведенный из парадигмы, или None.

    Основа берётся из РОДИТЕЛЬНОГО единственного (там она уже без
    беглой гласной: «день» → «дня» → «дн-»), окончание — «-ах» или
    «-ях» по мягкости этой формы и правилу письма. На всех
    объявленных парадигмах правило даёт верную форму: «часах»,
    «днях», «неделях», «копейках», «рублях».
    """
    формы = ПАРАДИГМЫ.get(слово)
    if формы is None:
        return None
    род_ед = формы[1]
    основа = род_ед[:-1] if род_ед[-1] in "аяуыиеё" else род_ед
    мягко = род_ед[-1] in "яи" and основа[-1:] not in tuple(
        _ТВЁРДЫЕ_НА_ПИСЬМЕ)
    return основа + ("ях" if мягко else "ах")


def род(слово):
    """Род русского существительного в именительном."""
    с = слово.lower()
    if с.endswith("мя"):
        return "с"
    if с[-1] in "ая":
        return "ж"
    if с[-1] in "ое":
        return "с"
    return "м"


def полное(основа, слово):
    """Прилагательное, согласованное со словом: «жирный свет»."""
    return основа + _ПОЛНЫЕ_ОКОНЧАНИЯ[род(слово)]


def краткое(основа, слово):
    """Краткая форма, согласованная со словом: «вложена», «вложено»."""
    return основа + _КРАТКИЕ_ОКОНЧАНИЯ[род(слово)]


