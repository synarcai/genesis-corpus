#!/usr/bin/env python3
"""ДОМ РУССКОГО РАССКАЗА — цепь действий, вопрос к ней и отказ.

Рассказ по-русски со своим согласованием: цепь действий, вопрос о ней и отказ там, где
язык отвергает сказанное.

4 родов объявлены не здесь: их назвала СВОЯ ЖЕ КУЗНИЦА кортежем `ГРУППЫ`.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

Читателей пятого рода у этого мира нет: карта (13.09) спрошена ПРЕЖДЕ переезда, и ни один суд
не ввозит его кузницу и не разбирает её исходник.
"""
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

import pathlib as _pathlib

import rugram  # noqa: E402
import json as _json
from rugram import МЕСТОИМЕНИЯ as _МЕСТ, СУФФИКС_ПРОШЕДШЕГО as _СУФ

РОДЫ = ('цепи', 'вопросы', 'отказы', 'держание')

ЗАЧЕМ_РОДА = {
    "цепи": "цепь действий по-русски",
    "вопросы": "вопрос к цепи",
    "отказы": "то, чего русский не говорит, и это названо",
    "держание": "кто чем владеет и сколько",
}


# ЯДРО ДОСЛОВНЫХ ПОВТОРОВ: столько первых случаев каждого рода стоят во
# ВСЕХ проходах слово в слово.
ЯДРО = 3
СЛУЧАЕВ = 8

# ИМЯ СОБСТВЕННОЕ НЕ ЖИВЁТ НИ В ОДНОМ ДОМЕ, и потому объявлено здесь:
# (именительный, родительный, окончание прошедшего времени).
# Имена взяты на -я и -а, у которых родительный короток и однозначен.
# ЛИЦА — ИЗ ПАКЕТА (05.09): письмо, родительный и род — у пакета; суффикс по роду — rugram.
_RU = _json.loads((_pathlib.Path(__file__).resolve().parent / "langpacks" / "ru.json").read_text(encoding="utf-8"))["person_forms"]
_RU_ПО_СТРОЧНОМУ = {и.lower(): и for и in _RU}


def _лицо(имя):
    """(имя, родительный, род) из пакета — по строчному образу имени."""
    и = _RU_ПО_СТРОЧНОМУ[имя.lower()]
    ф = _RU[и]
    assert ф.get("gen") and ф.get("gender") in ("m", "f"), ("имя без падежа или рода в пакете", имя)
    return и, ф["gen"], ф["gender"]

_ВЫБОР = ("петя", "маша", "коля", "аня", "ваня", "оля")
ЛИЦА = tuple((и, р, _СУФ[g]) for и, р, g in map(_лицо, _ВЫБОР))

# ВЕЩИ — КЛЮЧИ ДОМА ФОРМ. Своей таблицы мир не заводит.
ВЕЩИ = ("яблоко", "книга", "монета", "ручка", "карта", "чашка",
        "игрушка")

# (основа прошедшего, оборот итога, знак). Убыль и прибыль суть одно
# движение с разным знаком, и строение у них общее.
ДЕЙСТВИЯ = (("отда", "осталось", -1), ("прода", "осталось", -1),
            ("купи", "стало", +1), ("взя", "стало", +1))


def семя(шаг, i):
    """Первые ЯДРО случаев прохода не знают — оттого и дословны."""
    return i if i < ЯДРО else шаг * 13 + i


def _случай(с):
    """(лицо, вещь, действие, было, изменение, стало).

    СЧЁТ ИДЁТ ОТ ДВУХ (см. докстринг), а убыль строится так, чтобы
    остаток был не меньше двух: «осталось 0 яблок» есть законная
    арифметика и негодная задача — она учит обороту на пустом множестве.
    """
    лицо = ЛИЦА[с % len(ЛИЦА)]
    вещь = ВЕЩИ[(с * 3) % len(ВЕЩИ)]
    основа, оборот, знак = ДЕЙСТВИЯ[с % len(ДЕЙСТВИЯ)]
    изменение = 2 + с % 5
    было = (изменение + 2 + с % 6) if знак < 0 else (2 + с % 9)
    стало = было + знак * изменение
    return лицо, вещь, (основа, оборот), было, изменение, стало


def _цепь(лицо, вещь, действие, было, изменение, стало):
    """Три факта, и у третьего носитель НАЗВАН, а не подразумевается."""
    им, род, г = лицо
    основа, оборот = действие
    return (f"у {род} было {было} {rugram.форма(вещь, было)}. "
            f"{им} {основа}л{г} {изменение} "
            f"{rugram.форма(вещь, изменение)}. "
            f"у {род} {оборот} {стало} {rugram.форма(вещь, стало)}.")


def цепи(шаг):
    вон = []
    for i in range(СЛУЧАЕВ):
        вон.append(_цепь(*_случай(семя(шаг, i))))
    return вон


def вопросы(шаг):
    """ТА ЖЕ ЦЕПЬ, НО С ВОПРОСОМ ВМЕСТО ГОТОВОГО ИТОГА.

    Знание, у которого есть лишь повествовательная поверхность, не
    отвечает — оно только сообщает. Здесь итог приходит ОТВЕТОМ, и
    носитель в нём назван так же явно.
    """
    вон = []
    for i in range(СЛУЧАЕВ):
        лицо, вещь, действие, было, изм, стало = _случай(семя(шаг, i))
        им, род, г = лицо
        основа, оборот = действие
        вон.append(f"у {род} было {было} {rugram.форма(вещь, было)}. "
                   f"{им} {основа}л{г} {изм} "
                   f"{rugram.форма(вещь, изм)}. "
                   f"сколько {rugram.форма(вещь, 5)} {оборот} у {род}? "
                   f"у {род} {оборот} {стало} "
                   f"{rugram.форма(вещь, стало)}.")
    return вон


def отказы(шаг):
    """Вопрос о том, кого в задаче не было, — и ОСНОВАНИЕ отказа.

    ОСНОВАНИЕ СКАЗАНО ИМЕНИТЕЛЬНЫМ, А НЕ ПРЕДЛОЖНЫМ. «речь шла о пете»
    требует предложного имени собственного, какого дом не объявляет, а
    предлог «о» перед гласной становится «об» («об ане»). Мир не вправе
    досказывать за дом — потому предлога здесь нет вовсе: «в задаче
    назван петя, а не маша».
    """
    вон = []
    for i in range(ЯДРО + 2):
        с = семя(шаг, i)
        лицо, вещь, _д, было, _и, _с = _случай(с)
        им, род, г = лицо
        # ЧУЖОЙ БЕРЁТСЯ ИЗ ТОГО ЖЕ СПИСКА И ЗАВЕДОМО ИНОЙ: сдвиг
        # никогда не нулевой, и потому носитель вопроса не может
        # совпасть с носителем задачи.
        чужой = ЛИЦА[(с + 1 + с % (len(ЛИЦА) - 1)) % len(ЛИЦА)]
        вон.append(f"у {род} было {было} {rugram.форма(вещь, было)}. "
                   f"сколько {rugram.форма(вещь, 5)} было у "
                   f"{чужой[1]}? не сказано: в задаче назван{г} {им}, "
                   f"а не {чужой[0]}.")
    return вон


МЕСТА = (("на", "полке"), ("в", "коробке"), ("на", "столе"), ("в", "корзине"))


def держание(шаг):
    """ДЕРЖАНИЕ БЕЗ НОСИТЕЛЯ (e9 04.09): «на полке 20 книг. петя взял 5 книг.
    сколько книг осталось? 20 − 5 = 15.» — страница открывается местом; вторая
    форма вопроса — «сколько книг теперь на полке?»."""
    вон = []
    for i in range(СЛУЧАЕВ):
        с = семя(шаг, i)
        (им, род, г), вещь = ЛИЦА[с % len(ЛИЦА)], ВЕЩИ[(с * 3) % len(ВЕЩИ)]
        предлог, место = МЕСТА[с % len(МЕСТА)]
        m = 2 + с % 4
        n = m + 2 + (с * 5) % 9
        вопрос = (f"сколько {rugram.форма(вещь, 5)} осталось?" if i % 2 == 0
                  else f"сколько {rugram.форма(вещь, 5)} теперь {предлог} {место}?")
        вон.append(f"{предлог} {место} {n} {rugram.форма(вещь, n)}. {им} взял{г} {m} "
                   f"{rugram.форма(вещь, m)}. {вопрос} {n} − {m} = {n - m}.")
    return вон

ГРУППЫ = (цепи, вопросы, отказы, держание)


def группы(шаг):
    """[[страница]] — ровно те группы и в том порядке, какими кузница кормит `emit_grouped`."""
    return [сделать(шаг) for сделать in ГРУППЫ]


def перебор(шаг):
    """[(страница, род)] — те же группы, но каждая под своим именем."""
    вон = []
    for род, группа in zip(РОДЫ, группы(шаг)):
        for с in группа:
            вон.append((с, род))
    return вон


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            вон.setdefault(с, род)
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, а не с кортежем."""
    имена = tuple(с.__name__ for с in ГРУППЫ)
    assert имена == РОДЫ, f"кортеж {имена} разошёлся с объявлением {РОДЫ}"
    сколько = len(группы(0))
    assert сколько == len(РОДЫ), f"проход даёт {сколько} групп при {len(РОДЫ)} родах"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка()
