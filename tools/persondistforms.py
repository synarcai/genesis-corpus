def различий(ряд):
    """Сколько РАЗНЫХ форм в ряду."""
    return len({ф for _м, ф in ряд})


def совпавшие(ряд, лица):
    """[(имена лиц, форма)] — группы лиц, у которых форма ОДНА."""
    по_форме = {}
    for (м, ф), (ру, _ан) in zip(ряд, лица):
        по_форме.setdefault(ф, []).append(ру)
    return [(имена, ф) for ф, имена in по_форме.items() if len(имена) > 1]


