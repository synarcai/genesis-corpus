#!/usr/bin/env python3
"""КОВКА ДОМА СТЕПЕНИ ЗА НУЛЁМ.

ЛЕСТНИЦА И ЕЁ ПЕРВАЯ СТУПЕНЬ ЗА НУЛЁМ идут в одном проходе: «5^3 = 125, и 125 ÷ 5 = 25» и
«5^0 = 1, а не 0» суть причина и следствие, и разлучить их значило бы оставить ловушку без
вывода.

ВОПРОС ИДЁТ ТРЕТЬЕЙ ГРУППОЙ (12.09, по указанию прибора широты вопроса: мир нёс НОЛЬ
вопросительных знаков на 340 страниц). Дом объявил род, а кузня его не звала — и это
поймал прибор «РОД ДОШЁЛ» в тот же миг:

    РОД, ОБЪЯВЛЕННЫЙ ДОМОМ И НЕ ПОЗВАННЫЙ КУЗНЕЙ, ЕСТЬ ЗАКОН БЕЗ СТРАНИЦЫ.

ДОЛЯ И ЕЁ ОПРАВДАНИЕ идут своей группой: «2^-3 = 1/8, а не −8» и «2^3 × 2^-3 = 8 × 1/8 = 1» —
вторая страница проверяет первую произведением, и порознь доля осталась бы объявлением.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import powforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_pow.txt"
# ВОПРОС СТОИ́Т СВОЕЙ ГРУППОЙ: он не причина и не следствие соседа, а ТА ЖЕ ЛЕСТНИЦА,
# поставленная иначе. Смешать его с утверждением значило бы дать читателю ответ РЯДОМ
# с вопросом — а вопрос тем и ценен, что ответ на него надо искать.
ГРУППЫ = (("лестница", "нулевая"), ("отрицательная", "замок"), ("спрошенное",))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
