#!/usr/bin/env python3
"""МУТАНТЫ: способна ли мера УПАСТЬ — и падает ли она от СВОЕГО.

МЕРА, КОТОРАЯ НИКОГДА НЕ ПАДАЛА, ПОДОЗРИТЕЛЬНА В НЕПОДКЛЮЧЁННОСТИ.
Нулевой счётчик отказов есть либо здоровье, либо оторванный провод, и
различить их изнутри нельзя: оба показывают ноль. У языкового пакета
девять полей, и каждое ОБЪЯВЛЯЕТ СЕБЯ мерой; но до сего дня никто не
спросил ни одно из них, способно ли оно вообще сказать «нет».

ПОВОД ИЗ ОПЫТА, А НЕ ИЗ ОСТОРОЖНОСТИ. Дважды за две смены нашлось
ЗЕЛЁНОЕ поле, измерившее не то: ONCE считал обломки деванагарских слов
за слова (77 «слов» вместо 166), ARITH видел 85 равенств из 425, ибо не
узнавал в «बराबर» знака равенства. Оба поля были зелены, и ни одно из
них не солгало — они честно ответили на вопрос, который сумели задать.
Прибор ниже задаёт им другой вопрос: ПАДАЕШЬ ЛИ ТЫ, КОГДА ДОЛЖЕН.

ДВА УСЛОВИЯ, И ВТОРОЕ ВАЖНЕЕ ПЕРВОГО:

    ПОДСАДКА ПОЙМАНА     — названное поле стало красным;
    ЧУЖОГО НЕ ЗАДЕТО     — прочие восемь остались зелены.

Первое говорит, что провод подключён. Второе — что он подключён ТУДА,
КУДА ОБЕЩАНО. Поле, краснеющее от чужой порчи, меряет не то, что
объявляет, и его зелень назавтра ничего не значит: она может держаться
на соседе.

ДИСЦИПЛИНА МУТАНТА (замысел verum-а, и он обязателен): МУТАНТ ОБЯЗАН
ДОКАЗАТЬ, ЧТО ДОХОДИТ ДО МЕСТА, О КОТОРОМ СПРАШИВАЕТ. Оттого всякая
подсадка идёт ПАРОЙ — испорченный пакет и его честный близнец,
разнящиеся РОВНО ОДНОЙ правкой. Близнец зелен, мутант красен —
подсадка доказана. Оба зелены — подсадка НЕ ДОШЛА, и это находка о
ПОЛЕ, а не о подсадке: её не переделывают под зелень, её называют.

ВЕРДИКТ БЕРЁТСЯ У СУДЬИ, А НЕ ЧИТАЕТСЯ У НЕГО С ЛИЦА. Судья возвращает
булево; прибор подменяет девять судей обёртками, ЗАПОМИНАЮЩИМИ этот
возврат, и зовёт `langpack.main()` — настоящий, целиком, без единой
переписанной строки. Разбор печатной прозы дал бы второй свод правил
рядом с первым и разошёлся бы с ним в первый же день; здесь свод один.

ТЕЛО ПОКАЗОВ ПРИБОР ТОЖЕ НЕ СТРОИТ САМ. Оно приходит к судьям
доводами, и обёртка запоминает его оттуда же. Ни проходы, ни перестановка,
ни швы здесь не повторены: закон сборки живёт в одном месте.

ПЕРВАЯ НАХОДКА ЭТОГО ПРИБОРА — НЕ ПОЛЕ, А ДВИЖОК. Строя подсадку для
ONCE изъятием показа, прибор упёрся в то, что показ, объявленный
ЭКЗАМЕНАЦИОННЫМ (`reserved`), удерживается НЕ ВЕСЬ: в `gen_kind`
дословное ядро кладётся в выдачу ПРЕЖДЕ проверки на экзамен, и потому
экзаменационная строка остаётся в мире по одному разу за проход.
Замерено на четырёх пакетах: «you own it.» 31 → 5, «вот комната.»
25 → 5, «ini kata.» 23 → 5, «მე მაქვს სკამი.» 23 → 5. Счётчик
`LANGPACK-RESERVED` этих пяти не считает: они не удержаны и о них не
сказано. Прибор от этого не лечится — он об этом ДОКЛАДЫВАЕТ.

ПРИБОР НИЧЕГО НЕ ПИШЕТ В КОРПУС. Пакеты портятся в ПАМЯТИ, копии
ложатся во временный каталог, и туда же уходит слой, который движок
пишет при зелёном вердикте.
"""

