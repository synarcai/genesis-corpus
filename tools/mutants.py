# ИМЯ ПОЛЯ → ИМЯ СУДЬИ В ДВИЖКЕ. Порядок тот же, каким их зовёт
# `langpack.main`, и он же порядок печати.
СУДЬИ = (
    ("MORPH", "judge_morph_classes"),
    ("KINDS", "judge_show_kinds"),
    ("PAIRING", "judge_core_pairing"),
    ("IRR", "judge_irregulars"),
    ("GRAPH", "judge_graphemes"),
    ("CROSS", "judge_cross_kind"),
    ("REFUSAL", "judge_refusals"),
    ("ARITH", "judge_arithmetic"),
    ("ONCE", "judge_once"),
)


class Прогон:
    """Что вернул каждый судья, и с каким телом он это сделал."""

    def __init__(self):
        self.вердикты = {}
        self.тело = None
        self.тела_родов = None
        self.беда = None

    @property
    def зелен(self):
        return all(self.вердикты.get(имя) for имя, _ in СУДЬИ)


def прогнать(пакет, ядро, каталог):
    """Девять вердиктов о пакете — от самих судей, целым `main`.

    ПОДМЕНА СУДЬИ ОБЁРТКОЙ, А НЕ ПОВТОРЕНИЕ ЕГО ЗОВА. `main` берёт
    судей из глобалей модуля в миг вызова, и потому обёртка, положенная
    на место судьи, попадает в настоящую цепь: тот же порядок, то же
    тело, тот же вывод. Прибор не знает и не желает знать, как это
    тело собирается.
    """
    итог = Прогон()
    путь = pathlib.Path(каталог) / "мутант.json"
    путь.write_text(json.dumps(пакет, ensure_ascii=False), encoding="utf-8")

    прежние = {}
    for имя, судья in СУДЬИ:
        прежние[судья] = getattr(langpack, судья)

    def надеть(имя, судья):
        оригинал = прежние[судья]

        def обёртка(*доводы, **прочее):
            # ТЕЛО И ТЕЛА РОДОВ ПРИХОДЯТ СУДЬЯМ ДОВОДАМИ, И ПРИБОР
            # БЕРЁТ ИХ ОТТУДА: подсадкам ONCE и REFUSAL нужно знать,
            # что мир СКАЗАЛ, а не что он объявил.
            if судья == "judge_once":
                итог.тело = доводы[1]
            if судья in ("judge_cross_kind", "judge_refusals"):
                итог.тела_родов = доводы[1]
            вердикт = оригинал(*доводы, **прочее)
            итог.вердикты[имя] = bool(вердикт)
            return вердикт

        setattr(langpack, судья, обёртка)

    for имя, судья in СУДЬИ:
        надеть(имя, судья)

    прежний_argv = sys.argv[:]
    sys.argv = ["langpack", str(путь), "--core", str(ядро),
                "--out", str(pathlib.Path(каталог) / "слой.txt")]
    langpack.WITHHELD.clear()
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            langpack.main()
    except SystemExit:
        pass
    except Exception as беда:            # noqa: BLE001
        # ОБВАЛ СУДЬИ ЕСТЬ ВЕРДИКТ О ПРИБОРЕ, А НЕ О ПОДСАДКЕ, и
        # потому он не прячется в «красное поле», а называется.
        итог.беда = f"{type(беда).__name__}: {беда}"
    finally:
        sys.argv = прежний_argv
        for судья, оригинал in прежние.items():
            setattr(langpack, судья, оригинал)
    return итог


# ─── ПОДСАДКИ: ПО ОДНОЙ НА ПОЛЕ ────────────────────────────────────
#
# Всякая подсадка правит пакет РОВНО В ОДНОМ МЕСТЕ и возвращает
# описание правки — или None, если на этом пакете её построить нельзя
# (честный отказ, а не молчаливый пропуск).
#
# ЧАСТЬ ПОДСАДОК ПРАВИТ ОБЪЯВЛЕНИЕ, ЧАСТЬ — ПОКАЗЫ, И ЭТО НЕ ВСЁ РАВНО.
# Правка объявления, показов не меняющая (число клеток парадигмы,
# порог доли, чужое слово в списке рода), доказуема ЧИСТО: тело обоих
# близнецов побайтово одно, и всякая разница вердиктов есть разница
# самого поля. Правка, меняющая показы, тащит за собой соседей, и
# прибор считает это числом «чужих задето», а не прячет.


def _нонсенс(тело, графемы):
    """Слово из букв пакета, которого в показах заведомо нет."""
    буква = next((з for з in графемы if з.isalpha()), "x")
    слово = буква * 3
    while слово in тело:
        слово += буква
    return слово


def _чужой_знак(тело):
    """Знак, которого в показах нет ни разу, — для порчи алфавита."""
    for знак in "ǂǁʘʕɸθ":
        if знак not in тело:
            return знак
    return None


def подсадка_morph(пакет, прогон, попытка=0):
    """MORPH: парадигма объявлена НЕ ВСЯ — клеток больше, чем форм.

    Показы не меняются ни на байт: `paradigm_cells` читает только
    судья, а порождение идёт по `forms`. Оттого подсадка доказуема
    начисто.
    """
    if попытка:
        return None
    классы = пакет.get("morph_classes") or {}
    if not классы:
        return None
    имя, класс = next(iter(классы.items()))
    было = класс.get("paradigm_cells", len(класс.get("forms", [])))
    класс["paradigm_cells"] = было + 1
    return f"класс «{имя}»: клеток {было} → {было + 1} при {было} формах"


def подсадка_kinds(пакет, прогон, попытка=0):
    """KINDS: слово одного рода объявлено и в другом.

    Словари родов обязаны не пересекаться: слово, встреченное только в
    арифметике, выучивается как арифметическое. Подсадка кладёт слово
    счёта в словарь определения — показы при этом те же, ибо `lexicon`
    есть объявление, а не источник строк.
    """
    if попытка:
        return None
    роды = пакет.get("show_kinds") or {}
    с_словарём = [(и, р) for и, р in роды.items() if р.get("lexicon")]
    if len(с_словарём) < 2:
        return None
    (и1, р1), (и2, р2) = с_словарём[0], с_словарём[1]
    слово = р1["lexicon"][0]
    if слово in р2["lexicon"]:
        return None
    р2["lexicon"] = list(р2["lexicon"]) + [слово]
    return f"слово «{слово}» рода «{и1}» объявлено и в роде «{и2}»"


def подсадка_pairing(пакет, прогон, попытка=0):
    """PAIRING: связка объявлена, но её языковой конец не прожит.

    У пары два конца, и поле требует ОБОИХ: понятие, объявленное в
    паре и не сказанное ни разу, есть мост в один пролёт.
    """
    if попытка:
        return None
    пары = пакет.get("core_pairing") or []
    if not пары:
        return None
    слово = _нонсенс(прогон.тело, пакет.get("graphemes", "x"))
    было = пары[0].get("lang_form", пары[0].get("lang_word"))
    пары[0]["lang_form"] = слово
    return f"языковой конец пары «{было}» подменён на «{слово}»"


def подсадка_irr(пакет, прогон, попытка=0):
    """IRR: объявлено исключение, которого в показах нет.

    Неправильная форма, не показанная, ОБРАТНО ПРАВИЛЬНЕЕТ: организм
    выучит «идил». Поле требует, чтобы всякое объявленное исключение
    прожило дважды.
    """
    if попытка:
        return None
    if not isinstance(пакет.get("irregulars"), list):
        return None
    слово = _нонсенс(прогон.тело, пакет.get("graphemes", "x"))
    пакет["irregulars"] = list(пакет["irregulars"]) + [слово]
    return f"в список исключений добавлено «{слово}», которого нет"


def подсадка_graph(пакет, прогон, попытка=0):
    """GRAPH: объявлена буква, которой пакет не пишет.

    Опись письма затем и объявляется, чтобы «всякая графема дважды»
    было ПРОВЕРЯЕМО, а не наблюдаемо. Буква, объявленная и не
    написанная, есть опись шире языка.
    """
    if попытка:
        return None
    знак = _чужой_знак(прогон.тело)
    if знак is None or not пакет.get("graphemes"):
        return None
    пакет["graphemes"] = пакет["graphemes"] + знак
    return f"в опись письма добавлен знак «{знак}», не написанный ни разу"


def подсадка_cross(пакет, прогон, попытка=0):
    """CROSS: объявленная доля перекрёстных лексем поднята до всех.

    ЗДЕСЬ ПОДСАДКА ПРАВИТ ПОРОГ, А НЕ ДАННЫЕ, И ЭТО СКАЗАНО ВСЛУХ.
    Поле сравнивает ЧИСЛО перекрёстных лексем с долей, ОБЪЯВЛЕННОЙ
    самим пакетом; данные же лежат в лексемах классов, и всякая их
    порча немедленно меняет показы — то есть бьёт по ONCE, GRAPH и
    ARITH разом, и тогда вердикт не скажет, чьё поле сработало.
    Порог есть то единственное место, где это поле фальсифицируемо
    хирургически, и подсадка бьёт ровно туда.
    """
    if попытка:
        return None
    if "cross_kind_share" not in пакет:
        return None
    было = пакет["cross_kind_share"]
    if было >= 1.0:
        return None
    пакет["cross_kind_share"] = 1.0
    return f"объявленная доля перекрёстных лексем {было} → 1.0"


def подсадка_refusal(пакет, прогон, попытка=0):
    """REFUSAL: законный близнец отказа совпал с показом-нормой.

    Одна строка не смеет стоять разом нормой и половиной
    контрпримера. Подсадка ДОБАВЛЯЕТ пару, чей близнец взят из тела
    чужого рода дословно, — и потому не вносит в мир ни одного нового
    слова: показ уже там стоял.
    """
    if попытка:
        return None
    роды = пакет.get("show_kinds") or {}
    отказные = {и for и, р in роды.items() if р.get("refusal")}
    if not отказные or not прогон.тела_родов:
        return None
    чужие = [т for и, т in прогон.тела_родов.items() if и not in отказные]
    строки = [с for т in чужие for с in т.splitlines() if с.strip()]
    if not строки:
        return None
    норма = строки[0]
    имя = sorted(отказные)[0]
    пара = {"bad": норма, "good": норма, "reason": "agreement"}
    роды[имя]["pairs"] = list(роды[имя].get("pairs", [])) + [пара]
    return f"близнец отказа взят дословно из показов: «{норма[:40]}»"


def подсадка_arith(пакет, прогон, попытка=0):
    """ARITH: два значения делят одно слово, и равенства лгут.

    Таблица числительных служит ОБОИМ концам: ею показ пишется, ею же
    судья читает. Пока она взаимно однозначна, прочитанное равно
    написанному — и поле не может упасть НИ ОТ ЧЕГО, кроме нарушения
    этой однозначности. Подсадка отнимает у одного значения его слово
    и отдаёт слово соседа: показы пятёрки читаются шестёркой.

    ЗНАЧЕНИЕ ВЫБИРАЕТСЯ НЕ ИЗ СПИСКА ИСКЛЮЧЕНИЙ. Подсадка, задевшая
    разом два объявления, не сказала бы, чьё поле сработало, — а
    прибор затем и заведён, чтобы это различать.
    """
    if попытка:
        return None
    числа = пакет.get("numerals") or {}
    исключения = set(пакет.get("irregulars") or [])
    ключи = [к for к in числа
             if str(к).lstrip("-").isdigit() and int(к) > 0]
    ключи.sort(key=lambda к: int(к))
    жертва = next((к for к in ключи if числа[к] not in исключения), None)
    сосед = next((к for к in ключи
                  if к != жертва and числа[к] != числа[жертва]), None)
    if жертва is None or сосед is None:
        return None
    было = числа[жертва]
    числа[жертва] = числа[сосед]
    return (f"значение {жертва} пишется теперь словом {сосед} "
            f"(«{было}» → «{числа[жертва]}»)")


def подсадка_once(пакет, прогон, попытка=0):
    """ONCE: слово объявлено и прожито РОВНО ОДИН РАЗ.

    Сказанное однажды не выучивается: один случай есть случайность,
    два владеют фактом. Немецкий пакет однажды показал «dreißig»,
    «einundzwanzig» и «fünfundzwanzig» по одному разу — произведения,
    достижимые ровно одной парой (n, m) из посева.

    ПОДСАДКА ИЩЕТ ТАКОЕ ЖЕ МЕСТО В САМОМ ТЕЛЕ, А НЕ ВЫДУМЫВАЕТ ЕГО:
    значение, написанное цифрой ровно однажды, получает слово — и это
    слово живёт ровно однажды. Ни одна строка при этом не исчезает.
    """
    числа = пакет.get("numerals") or {}
    объявлено = {int(к) for к in числа
                 if str(к).lstrip("-").isdigit()}
    одиночка = None
    for значение in range(1, 101):
        if значение in объявлено:
            continue
        сколько = len(re.findall(rf"(?<!\d){значение}(?!\d)",
                                 прогон.тело))
        if сколько == 1:
            одиночка = значение
            break
    if одиночка is not None and not попытка:
        слово = _нонсенс(прогон.тело, пакет.get("graphemes", "x"))
        числа[str(одиночка)] = слово
        return (f"значение {одиночка} названо словом «{слово}», "
                f"а написано в показах ровно один раз")
    # ВТОРОЙ ХОД, КОГДА ТАБЛИЦА ЧИСЛИТЕЛЬНЫХ ПОЛНА. У пакета без дыр
    # всякое значение уже названо словом и потому уже прожито дважды —
    # места первому ходу нет. Тогда подсадка не ДОБАВЛЯЕТ слова, а
    # ИЗЫМАЕТ ПОКАЗ: строка, объявленная в `reserved`, движком
    # удерживается, и слово, жившее в двух разных строках, остаётся в
    # одной. Это буквально то, чего требует поле: «объявлено, а
    # прожито однажды».
    return _изъять_показ(пакет, прогон, попытка)


def _изъять_показ(пакет, прогон, попытка):
    """Удержать один показ так, чтобы слово осталось жить однажды.

    ИЗЪЯТИЕ ТАЩИТ ЗА СОБОЙ СОСЕДЕЙ, И ПОТОМУ ПРОВЕРЯЕТСЯ ЗАРАНЕЕ: со
    строкой уходят все её буквы и все её слова, а поля GRAPH, IRR и
    PAIRING требуют, чтобы объявленное жило. Подсадка берёт первую
    строку, чьё изъятие роняет ИМЕННО ОДНО слово до единицы и не
    трогает ничего из объявленного, — а если такой строки нет,
    честно отказывается.

    СТРОКИ ПРОБУЮТСЯ ПО ОЧЕРЕДИ, ОТ РЕДКОЙ К ЧАСТОЙ, И ЭТО НЕ
    ПОДБОР ПОД ЗЕЛЕНЬ, А ПОИСК МЕСТА. Показ из ДОСЛОВНОГО ЯДРА
    объявлением `reserved` удерживается НЕ ВЕСЬ: в `gen_kind` ядро
    кладётся в выдачу ПРЕЖДЕ проверки на экзамен, и такая строка
    остаётся в мире по одному разу за проход. Замерено на четырёх
    пакетах: «you own it.» 31 → 5, «вот комната.» 25 → 5,
    «ini kata.» 23 → 5, «მე მაქვს სკამი.» 23 → 5. Изнутри тела
    отличить ядро от не-ядра нельзя, и потому прибор не гадает, а
    ПРОБУЕТ: отбор идёт по одному признаку — дошла ли подсадка до
    поля ONCE, — и никогда по цвету прочих восьми, который лишь
    считается и печатается.

    ТРИ ПРОВЕРКИ ПЕРЕД ИЗЪЯТИЕМ СТЕРЕГУТ НЕ ЗЕЛЕНЬ, А ЗАКОН «РОВНО
    В ОДНОМ МЕСТЕ»: со строкой уходят её буквы, её исключения и её
    концы связок, и подсадка, задевшая два объявления разом, не
    сказала бы, чьё поле сработало.
    """
    тело = прогон.тело
    словарь = langpack.pack_vocabulary(пакет)
    по_пробелу = пакет.get("segmentation", "by-space") != "longest-match"
    буквы = set(пакет.get("graphemes", ""))
    if not буквы:
        return None

    def слова(текст):
        return [с for с in langpack.tokens(текст.lower(), словарь,
                                           spaced=по_пробелу)
                if any(б in буквы for б in с)]

    строки = [с for с in тело.splitlines() if с.strip()]
    счёт, кратность = {}, {}
    for строка in строки:
        кратность[строка] = кратность.get(строка, 0) + 1
        for с in слова(строка):
            счёт[с] = счёт.get(с, 0) + 1
    объявленные_знаки = list(пакет.get("graphemes", ""))
    исключения = list(пакет.get("irregulars") or [])
    концы = [п.get("lang_form", п.get("lang_word"))
             for п in (пакет.get("core_pairing") or [])]
    годные = []
    for строка, сколько in sorted(кратность.items(),
                                  key=lambda п: (п[1], п[0])):
        свои = {}
        for с in слова(строка):
            свои[с] = свои.get(с, 0) + 1
        if not any(счёт[с] - сколько * n == 1 for с, n in свои.items()):
            continue
        if any(тело.count(з) - сколько * строка.count(з) < 2
               for з in объявленные_знаки):
            continue
        if any(тело.count(и) - сколько * строка.count(и) < 2
               for и in исключения):
            continue
        if any(к and к not in тело.replace(строка, "")
               for к in концы):
            continue
        упало = [с for с, n in свои.items()
                 if счёт[с] - сколько * n == 1]
        годные.append((строка, упало[0]))
    if попытка >= len(годные):
        return None
    строка, слово = годные[попытка]
    пакет["reserved"] = list(пакет.get("reserved") or []) + [строка]
    return (f"показ «{строка[:40]}» удержан как экзаменационный; "
            f"слово «{слово}» осталось жить однажды")


ПОДСАДКИ = (
    ("MORPH", подсадка_morph),
    ("KINDS", подсадка_kinds),
    ("PAIRING", подсадка_pairing),
    ("IRR", подсадка_irr),
    ("GRAPH", подсадка_graph),
    ("CROSS", подсадка_cross),
    ("REFUSAL", подсадка_refusal),
    ("ARITH", подсадка_arith),
    ("ONCE", подсадка_once),
)


def довод(имя, по_умолчанию):
    if имя in sys.argv:
        return sys.argv[sys.argv.index(имя) + 1]
    return по_умолчанию


def main():
    путь = КОРЕНЬ / довод("--pack", ПАКЕТ_ПО_УМОЛЧАНИЮ)
    ядро = КОРЕНЬ / довод("--core", ЯДРО_ПО_УМОЛЧАНИЮ)
    try:
        живой = json.loads(путь.read_text(encoding="utf-8"))
    except OSError as беда:
        print(f"МУТАНТЫ ОТКАЗ: пакет не читается ({беда})")
        return 2
    if not ядро.is_file():
        print(f"МУТАНТЫ ОТКАЗ: ядро не читается ({ядро})")
        return 2

    каталог = tempfile.mkdtemp(prefix="mutants-")
    try:
        близнец = прогнать(живой, ядро, каталог)
        if близнец.беда:
            print(f"МУТАНТЫ ОТКАЗ: близнец упал ({близнец.беда})")
            return 2
        # БЛИЗНЕЦ ОБЯЗАН БЫТЬ ЗЕЛЕН ЦЕЛИКОМ. На пакете, красном и без
        # подсадки, доказать нельзя ничего: красное поле мутанта не
        # отличить от красного поля близнеца.
        if not близнец.зелен:
            красные = [и for и, _ in СУДЬИ if not близнец.вердикты.get(и)]
            print(f"МУТАНТЫ ОТКАЗ: близнец {путь.name} не зелен "
                  f"({', '.join(красные)}) — подсадку доказать не на чем")
            return 2

        # КОНТРОЛЬ ПРЕЖДЕ ПОДСАДОК: тот же пакет, прогнанный дважды,
        # обязан дать те же девять вердиктов. Прибор держит движок в
        # своей памяти между прогонами (списки, кэши разбиения), и
        # утечка состояния сделала бы всякое «ПОЙМАН» подозрительным:
        # красное поле мутанта не отличить от красного поля от сора.
        второй = прогнать(живой, ядро, каталог)
        цел = (второй.беда is None
               and второй.вердикты == близнец.вердикты)
        print(f"КОНТРОЛЬ {'ЦЕЛ' if цел else 'НАРУШЕН':<9} "
              f"повторный прогон близнеца дал "
              f"{'те же' if цел else 'ИНЫЕ'} девять вердиктов")
        if not цел:
            print("МУТАНТЫ ОТКАЗ: движок недетерминирован между "
                  "прогонами — подсадки доказывать нечем")
            return 2

        поймано = задето_всего = не_построено = 0
        for имя, испортить in ПОДСАДКИ:
            # ПОПЫТКИ ОТБИРАЮТСЯ ПО ОДНОМУ ПРИЗНАКУ — ДОШЛА ЛИ
            # ПОДСАДКА ДО СВОЕГО ПОЛЯ. Цвет прочих восьми не влияет на
            # выбор ни в одной ветви: он считается и печатается таким,
            # каким вышел.
            описание = мутант = None
            попыток = 0
            for попытка in range(ПОПЫТОК):
                пакет = copy.deepcopy(живой)
                свежее = испортить(пакет, близнец, попытка)
                if свежее is None:
                    break
                описание, попыток = свежее, попытка + 1
                мутант = прогнать(пакет, ядро, каталог)
                if мутант.беда or not мутант.вердикты.get(имя, True):
                    break
            if мутант is None:
                не_построено += 1
                print(f"МУТАНТ {имя:<8} НЕ ПОСТРОЕН  "
                      f"пакет {путь.name} не даёт места для этой подсадки")
                continue
            if мутант.беда:
                print(f"МУТАНТ {имя:<8} ОБВАЛ        {мутант.беда}")
                continue
            своё_упало = not мутант.вердикты.get(имя, True)
            задето = [чужое for чужое, _ in СУДЬИ
                      if чужое != имя and not мутант.вердикты.get(чужое, True)]
            задето_всего += len(задето)
            поймано += своё_упало
            если = "ПОЙМАН   " if своё_упало else "НЕ ПОЙМАН"
            хвост = (f"чужих полей задето: {len(задето)}"
                     + (f" ({', '.join(задето)})" if задето else ""))
            if not своё_упало:
                хвост = "близнец и мутант оба зелены; " + хвост
            print(f"МУТАНТ {имя:<8} {если}    {хвост}"
                  + (f"; подсадок перебрано: {попыток}"
                     if попыток > 1 else ""))
            print(f"    подсадка: {описание}")
        всего = len(ПОДСАДКИ)
        поза = ("PASS" if (всего - поймано) <= НЕ_ПОЙМАНО_РУБЕЖ
                and не_построено == 0 and задето_всего == 0 else "FAIL")
        print(f"МУТАНТЫ {поза}: {поймано} полей из {всего} поймали свою "
              f"подсадку, чужих задето {задето_всего}"
              + (f", не построено {не_построено}" if не_построено else ""))
        return 0 if поза == "PASS" else 1
    finally:
        shutil.rmtree(каталог, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
