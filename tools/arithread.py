#!/usr/bin/env python3
"""ЧТЕНИЕ АРИФМЕТИЧЕСКОЙ ЗАПИСИ — один разбор на все дома, а не по одному в каждом.

    ЗАПИСЬ СУДИТСЯ РАЗБОРОМ, А НЕ ПАРОЙ ЧИСЕЛ. «20 − (12 + 9 − 5) = 4» есть ОДНО
    утверждение, и признак, читающий пары, найдёт в нём «9 − 5 = 4» — истину, стоящую не
    на своём месте, — и обманется вдвойне.

ПОВОД. Разбор этот писался в трёх домах подряд (`overlapforms`, `wmeanforms`, `condforms`) и
на третьем был вынесен сюда:

    ЗАКОН, ПЕРЕПИСАННЫЙ В ТРЕТИЙ РАЗ, ЕСТЬ УЖЕ НЕ ЗАКОН ДОМА, А ЗАКОН СВОДА, И МЕСТО ЕМУ
    ОБЩЕЕ. Три списка одного расходятся не «когда-нибудь», а на первой же правке.

ДЕЛЕНИЕ БЕРЁТСЯ ТОЛЬКО НАЦЕЛО, И ЭТО НЕ УПРОЩЕНИЕ, А ЗАКОН КОРПУСА: свод, сказавший
«среднее 3,25», научил бы округлению как истине. Запись с остатком не разбирается вовсе —
`счесть` отвечает НИЧЕМ, и дом, её написавший, будет назван лжецом своим же судьёй.

    python3 tools/arithread.py     # самопроверка
"""
import re
import sys

# КОРЕНЬ ОБЯЗАН ЗНАТЬ СВОИХ ЧИТАТЕЛЕЙ (`scripts/root_passport.py`): правка здесь меняет
# вердикт каждого из них, и день, когда список разойдётся с делом, есть день молчаливой
# порчи трёх миров разом.
ЧИТАЮТ = ("overlapforms", "wmeanforms", "condforms")

# ЗАПИСЬ ЕСТЬ ЦЕПЬ РАВНЫХ ЗВЕНЬЕВ, А НЕ ПАРА «ВЫРАЖЕНИЕ = ЧИСЛО». Справа от знака равенства
# стои́т выражение так же часто, как слева: «4 × 25 = 10 × 10» есть одно утверждение о двух
# произведениях, и признак, ждущий справа числа, прочёл бы «4 × 25 = 10» и назвал бы ложью
# истину.
#
#     ПРИЗНАК, ЗНАЮЩИЙ ЛИШЬ ОДИН ОБЛИК РАВЕНСТВА, НАХОДИТ ЛОЖЬ В ТОМ, ЧЕГО НЕ УМЕЕТ ПРОЧЕСТЬ.
#
# ХВОСТ ЦЕПИ СТЕРЕЖЁТСЯ ЧЕТЫРЬМЯ ЗНАКАМИ И РАВЕНСТВОМ: признак, которому нельзя взять ЦЕЛОЕ,
# отступит и возьмёт ЧАСТЬ — а часть истинной цепи бывает ложной сама по себе.
# ОДНОМЕСТНЫЙ МИНУС ЕСТЬ ЧАСТЬ ЧИСЛА, А НЕ ДЕЙСТВИЕ НАД НИМ: «3 − (−5) = 8» есть честная
# запись числовой прямой, и разбор, не знающий её, назвал бы её неразбираемой — то есть
# ЛОЖНОЙ, ибо судья, получивший НИЧЕГО, зовёт строку ложью.
#
#     ЗАПИСЬ, КОТОРУЮ РАЗБОР НЕ БЕРЁТ, ОБЪЯВЛЯЕТСЯ ЛОЖНОЙ, А НЕ НЕПОНЯТНОЙ, — И ПОТОМУ
#     ГРАНИЦА РАЗБОРА ЕСТЬ ГРАНИЦА ТОГО, ЧТО СВОДУ МОЖНО СКАЗАТЬ.
_ЗВЕНО = r"\(?−?\d+\)?(?:\s[+−×÷]\s\(?−?\d+\)?)*"
ЗАПИСЬ = re.compile(rf"(?<![+−×÷=]\s)(?<![\w/])({_ЗВЕНО}(?:\s=\s{_ЗВЕНО})+)"
                    rf"(?!\s[+−×÷=]\s\d)(?![\d/])")
_ТОКЕН = re.compile(r"\d+|[()+−×÷]")
_ЗНАКИ_ПЕРЕД = frozenset("(+−×÷")


def счесть(выражение):
    """Значение записи из чисел, знаков + − × ÷ и скобок; None — если не разбирается.

    НИЧЕГО отвечается на всё, чего разбор не берёт: чужой знак, незакрытая скобка, деление
    с остатком, деление на ноль, пустая запись. Судья, получивший НИЧЕГО, зовёт строку
    ложью — и это верно: строка, чью запись нельзя пересчитать, не доказана.
    """
    ток = _ТОКЕН.findall(выражение)
    if "".join(ток) != re.sub(r"\s", "", выражение):
        return None
    поз = 0

    def множитель():
        nonlocal поз
        if поз >= len(ток):
            return None
        # МИНУС ОДНОМЕСТЕН ТАМ, ГДЕ ПЕРЕД НИМ НЕТ ЧИСЛА: в начале записи или сразу за
        # знаком либо открытой скобкой. Иначе он есть вычитание, и его берёт `сумма`.
        if ток[поз] == "−" and (поз == 0 or ток[поз - 1] in _ЗНАКИ_ПЕРЕД):
            поз += 1
            знач = множитель()
            return None if знач is None else -знач
        if ток[поз] == "(":
            поз += 1
            знач = сумма()
            if знач is None or поз >= len(ток) or ток[поз] != ")":
                return None
            поз += 1
            return знач
        if ток[поз].isdigit():
            знач = int(ток[поз])
            поз += 1
            return знач
        return None

    def произведение():
        nonlocal поз
        знач = множитель()
        if знач is None:
            return None
        while поз < len(ток) and ток[поз] in "×÷":
            з = ток[поз]
            поз += 1
            ещё = множитель()
            if ещё is None:
                return None
            if з == "×":
                знач *= ещё
            else:
                if ещё == 0 or знач % ещё:
                    return None
                знач //= ещё
        return знач

    def сумма():
        nonlocal поз
        знач = произведение()
        if знач is None:
            return None
        while поз < len(ток) and ток[поз] in "+−":
            з = ток[поз]
            поз += 1
            ещё = произведение()
            if ещё is None:
                return None
            знач = знач + ещё if з == "+" else знач - ещё
        return знач

    знач = сумма()
    return знач if поз == len(ток) else None


def записи_верны(строка):
    """Правда, если ВСЯКАЯ цепь строки пересчитывается и все её звенья равны между собой."""
    for цепь in ЗАПИСЬ.findall(строка):
        цены = [счесть(з) for з in цепь.split(" = ")]
        if None in цены or len(set(цены)) != 1:
            return False
    return True


def _самопроверка():
    """ПРОБА НА ЗАВЕДОМО ИЗВЕСТНОМ: доказывает, что разбор берёт своё и не берёт чужого."""
    беды = []
    случаи = (("2 + 3 × 4", 14, "старшинство знаков"),
              ("(2 + 3) × 4", 20, "скобка старше знака"),
              ("(10 × 5 + 30 × 1) ÷ 40", 2, "запись взвешенного среднего"),
              ("20 − (12 + 9 − 5)", 4, "вычитание скобки"),
              ("1 + 2 − 3 + 4", 4, "цепь в одну сторону"),
              ("(7)", 7, "число в скобке"),
              ("7 ÷ 2", None, "деление с остатком не берётся"),
              ("8 ÷ 0", None, "деление на ноль не берётся"),
              ("(2 + 3", None, "незакрытая скобка"),
              ("2 ^ 3", None, "чужой знак"),
              ("3 − (−5)", 8, "одноместный минус в скобке"),
              ("−5 + 3", -2, "запись, начатая минусом"),
              ("−5 × −3", 15, "два одноместных минуса"),
              ("0 − −4", 4, "минус сразу за вычитанием"),
              ("5 − 3", 2, "двухместный минус остался вычитанием"),
              ("", None, "пустая запись"))
    for выр, ждём, что in случаи:
        дало = счесть(выр)
        if дало != ждём:
            беды.append(f"{что}: «{выр}» → {дало}, а надо {ждём}")
    # ПРИЗНАК ЗАПИСИ ОБЯЗАН БРАТЬ ЦЕЛОЕ, А НЕ ЧАСТЬ: «20 − (12 + 9 − 5) = 4» есть одна
    # запись, и «9 − 5 = 4» в ней НЕ запись.
    найдено = ЗАПИСЬ.findall("итого 20 − (12 + 9 − 5) = 4 шара")
    if найдено != ["20 − (12 + 9 − 5) = 4"]:
        беды.append(f"признак записи взял не целое: {найдено}")
    накрест = ЗАПИСЬ.findall("ибо 4 × 25 = 10 × 10, доля та же")
    if накрест != ["4 × 25 = 10 × 10"]:
        беды.append(f"признак не взял равенства двух выражений: {накрест}")
    трёх = ЗАПИСЬ.findall("36 = 12 × 3 = 18 × 2 и не иначе")
    if трёх != ["36 = 12 × 3 = 18 × 2"]:
        беды.append(f"признак не взял цепи из трёх звеньев: {трёх}")
    # ЗАПИСЬ С ОСТАТКОМ БЕРЁТСЯ ЦЕЛИКОМ И СЧИТАЕТСЯ ВЕРНО: «18 = 12 × 1 + 6» есть честное
    # равенство, и общий разбор читает его как всякое другое. Первая проба ждала здесь
    # ОТКАЗА — по памяти о признаке иного дома, где остаток надо было ещё и сравнить с
    # делителем. Прав оказался прибор.
    остаток = ЗАПИСЬ.findall("остаток 18 = 12 × 1 + 6 здесь")
    if остаток != ["18 = 12 × 1 + 6"]:
        беды.append(f"признак не взял записи с остатком целиком: {остаток}")
    if not записи_верны("остаток 18 = 12 × 1 + 6 здесь"):
        беды.append("верная запись с остатком названа ложью")
    if записи_верны("остаток 18 = 12 × 1 + 7 здесь"):
        беды.append("ЛОЖНАЯ запись с остатком прошла")
    if not записи_верны("от −5 до 3: 3 − (−5) = 8"):
        беды.append("верная запись с одноместным минусом названа ложью")
    if записи_верны("от −5 до 3: 3 − (−5) = 9"):
        беды.append("ЛОЖНАЯ запись с одноместным минусом прошла")
    if not записи_верны("накрест 4 × 25 = 10 × 10"):
        беды.append("верное равенство двух выражений названо ложью")
    if записи_верны("накрест 4 × 25 = 10 × 11"):
        беды.append("ЛОЖНОЕ равенство двух выражений прошло")
    if not записи_верны("сумма 10 × 5 + 30 × 1 = 80, и 80 ÷ 40 = 2"):
        беды.append("две верные записи одной строки названы ложью")
    if записи_верны("сумма 10 × 5 + 30 × 1 = 81"):
        беды.append("ЛОЖНАЯ ЗАПИСЬ ПРОШЛА — разбор мёртв")
    if записи_верны("доля 7 ÷ 2 = 3"):
        беды.append("деление с остатком прошло — округление принято за истину")
    print(f"ЧТЕНИЕ ЗАПИСИ: случаев {len(случаи)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
