#!/usr/bin/env python3
"""МИР КОДА дома `toolcode` — объявление, общее дому, суду и прибору съёмки (28.09, ведущий omega-90: М-2099).

Код репозитория — мир, его физику отвечает языковой сервер самого языка по протоколу LSP 3.17 (rust-analyzer для
Rust, pyright для Python). Мост — бинарь ядра `ozar_lsp_world <репозиторий> <сервер> … [-- <сервер> …]`: одна строка
JSON акта на входе, одна строка ответа на выходе. Роды мира — те, что его серверы заявили: define (где определено
имя), refs (где имя упомянуто, без определений), symbols (что определяет файл), rename (правка имени по всему
проекту). В корпусе НЕТ МОДЕЛИ ЯЗЫКА: ответы сервера снимает прибор `toolcode_capture.py` один раз в семя
`tools/seeds/toolcode_world.json` под отпечатком проекта; дом печатает ход мира из семени, суд сверяет его с семенем
байт в байт. Один источник правды — сервер языка.

ПРОЕКТ — тот же объявленный проект дома актов (`repoworld.ПРОЕКТ`: web/ и tests/ на Python, крейты tally/ и gauge/ на
Rust): миру кода не заведено ни одного своего файла, и страницы дома актов остаются байт в байт. Имена проекта не
совпадают с песочницей ключей агента.

ХОД МИРА — строкой дома актов (`folderworld.текст`, договор ведущего): «<род> <объект>[ "<довод>"] · <счёт> <число>
[ · <поле> <значение> …]», поля строк в объявленном порядке, текст в ASCII-кавычках; отказ — «<голова> · refused
<почему> "<что>"».
"""
import hashlib
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import folderworld as W  # noqa: E402 — ход мира строкой, общий с домом актов
import repoworld as Р  # noqa: E402 — объявленный проект: код и прогоны

СЕМЯ = pathlib.Path(__file__).resolve().parent / "seeds" / "toolcode_world.json"
ПРОЕКТ = Р.ПРОЕКТ

# ПОЛЯ СТРОК И СЧЁТ РОДА — объявление мира кода (контракт М-2099): строки define — path line text sort, refs — path
# line text, symbols — name sort line text, rename — path изменённых файлов; счёт — definitions, references (без
# определений), symbols, у rename — occurrences (всякое вхождение имени, определение тоже: одно имя — одна мера, как у
# замены в мире папки, М-2017)
ПОЛЯ = {"define": ("path", "line", "text", "sort"), "refs": ("path", "line", "text"),
        "symbols": ("name", "sort", "line", "text"), "rename": ("path",)}
СЧЁТ = {"define": "definitions", "refs": "references", "symbols": "symbols", "rename": "occurrences"}
# голова хода мира кода — вид провода, какой знак языка узнаёт (`folderworld.ВИДЫ`): провод речью страницы не судится
assert set(ПОЛЯ) <= set(W.ВИДЫ), sorted(set(ПОЛЯ) - set(W.ВИДЫ))

# ОСНОВЫ СТРАНИЦ — что мир снимает. Определения — у имён, чья строка определения не первая: число строки не равно
# счёту definitions (всегда 1), и рынок отличит одно от другого (разведение источников дома актов)
ОПРЕДЕЛЕНИЯ = ("shout", "unit", "GreetTests", "test_name", "half", "HelperTests", "nought", "test_lower", "halves",
               "zero", "test_empty", "odd")
# упоминания: имена с упоминаниями (счёт не равен ни одному номеру строки) и имена, каких никто не упоминает
УПОМИНАЕМЫЕ = ("greet", "add", "half", "name")
НЕУПОМИНАЕМЫЕ = ("shout", "GreetTests")
# файлы кода; у gauge/src/lib.rs счёт symbols (4) равен номеру строки своего же символа — источники не разведены,
# и страниц о нём дом не пишет; web/main.py не определяет ничего
ФАЙЛЫ_КОДА = ("tests/test_main.py", "tally/src/lib.rs", "tests/test_helpers.py", "tally/tests/checks.rs",
              "gauge/tests/checks.rs", "web/helpers.py")
ФАЙЛЫ_БЕЗ_ИМЁН = ("web/main.py",)
# имена и файлы, каких в проекте нет (отказ мира not-there)
НЕТ_ИМЁН = ("blink", "tidy")
НЕТ_ФАЙЛОВ_КОДА = ("web/views.py", "tally/src/io.rs")
# ПЕРЕИМЕНОВАНИЯ, какие мир исполняет (новое имя свободно); всякое снимается на свежей копии проекта — правка меняет мир
ПЕРЕИМЕНОВАНИЯ = (("half", "halve"), ("shout", "yell"), ("GreetTests", "WelcomeTests"), ("unit", "units"),
                  ("add", "plus"), ("greet", "welcome"), ("test_name", "test_named"), ("HelperTests", "UtilTests"))
# новое имя уже определено — отказ already-there (переименование никогда не сливает двух имён)
ЗАНЯТЫЕ = (("add", "shout"), ("HelperTests", "GreetTests"))
# переименование имени, какого нет (отказ not-there)
ПЕРЕИМЕНОВАНИЯ_НЕТ = (("blink", "wink"), ("tidy", "neat"))


def акты_чтения():
    """Акты, какие не меняют мир, — снимаются одной сессией на объявленном проекте: (род, объект, довод). Упоминания
    снимаются и у всякого имени, какое переименование правит: это чтение «до» у отказа пользователем."""
    # определение снимается и у всякого переименуемого имени: слово сорта приказа «rename the function …»
    вон = [("define", x, None) for x in dict.fromkeys(ОПРЕДЕЛЕНИЯ + НЕТ_ИМЁН + tuple(x for x, _ in ПЕРЕИМЕНОВАНИЯ))]
    вон += [("refs", x, None) for x in dict.fromkeys(УПОМИНАЕМЫЕ + НЕУПОМИНАЕМЫЕ + НЕТ_ИМЁН
                                                     + tuple(x for x, _ in ПЕРЕИМЕНОВАНИЯ))]
    вон += [("symbols", f, None) for f in ФАЙЛЫ_КОДА + ФАЙЛЫ_БЕЗ_ИМЁН + НЕТ_ФАЙЛОВ_КОДА]
    вон += [("rename", x, y) for x, y in ЗАНЯТЫЕ + ПЕРЕИМЕНОВАНИЯ_НЕТ]
    return list(dict.fromkeys(вон))


def ключ(род, объект, довод=None):
    """Ключ акта в семени: строка провода акта, как её шлёт прибор."""
    return json.dumps({"act": род, "object": объект, **({"arg": list(довод.encode())} if довод is not None else {})},
                      ensure_ascii=False)


def отпечаток():
    """Отпечаток объявленного проекта, объявленных актов и команд прогонов: семя верно, пока он тот же, что при
    съёмке."""
    h = hashlib.sha256()
    for путь in sorted(ПРОЕКТ):
        h.update(путь.encode() + b"\0" + "".join(с + "\n" for с in ПРОЕКТ[путь]).encode() + b"\0")
    h.update(json.dumps([акты_чтения(), ПЕРЕИМЕНОВАНИЯ, Р.ПРОГОНЫ], ensure_ascii=False).encode())
    return h.hexdigest()[:16]


_СЕМЯ = None


def семя():
    global _СЕМЯ
    if _СЕМЯ is None:
        _СЕМЯ = json.loads(СЕМЯ.read_text(encoding="utf-8")) if СЕМЯ.exists() else {}
    return _СЕМЯ


def из_ответа(ответ):
    """Ход мира из строки ответа провода: наблюдение (меры и строки объявленных полей) или отказ по имени."""
    акт = ответ.get("act") or {}
    if ответ["reply"] == "refused":
        return None, (ответ["why"], ответ["what"])
    род = акт["act"]
    довод = bytes(акт["arg"]).decode("utf-8") if акт.get("arg") is not None else None
    меры = tuple((м["ledger"], м["value"]) for м in ответ["measures"])
    строки = tuple(tuple(zip(ПОЛЯ[род], ряд)) for ряд in ответ.get("rows") or ())
    return W.Наблюдение(род, акт["object"], (довод,) if довод is not None else (), меры, строки), None


def ход(род, объект, довод=None):
    """Ход мира на акт по семени: наблюдение или отказ (`folderworld.Отказ`)."""
    с = семя()
    if род == "rename" and (объект, довод) in ПЕРЕИМЕНОВАНИЯ:
        ответ = с["renames"][ключ(род, объект, довод)]["reply"]
    else:
        ответ = с["reads"][ключ(род, объект, довод)]
    наблюдение, отказ = из_ответа(ответ)
    if отказ:
        return W.Отказ(род, объект, (довод,) if довод is not None else (), отказ[0], отказ[1])
    return наблюдение


def после(объект, довод):
    """Проект после переименования — файлы, какие правка сервера оставила (снято прибором вместе с ответом)."""
    файлы = семя()["renames"][ключ("rename", объект, довод)]["files"]
    return {**ПРОЕКТ, **{путь: tuple(строки) for путь, строки in файлы.items()}}


# ПРОГОНЫ ПОСЛЕ ПРАВКИ (план двух миров: «переименуй X в Y, затем прогони тесты», М-2056 — акт идёт в мир, какой объявил
# его род): прогон мира процесса идёт на проекте, каким его оставила правка сервера; прогоны, чей код правка тронула
# (`repoworld.КОД_ПРОГОНА`), сняты прибором вместе с правкой — настоящий отчёт бегуна на этом состоянии
def прогоны_затронутые(изменены):
    """Имена прогонов, чей код правка тронула — по путям изменённых файлов."""
    return [имя for имя in Р.ПРОГОНЫ if any(путь.startswith(Р.КОД_ПРОГОНА[имя]) for путь in изменены)]


def прогоны_после(объект, довод):
    """Прогоны, снятые на проекте после переименования (в порядке прогонов мира)."""
    return list(семя()["renames"][ключ("rename", объект, довод)].get("runs", {}))


def снятое_после(объект, довод, имя):
    """Снятый отчёт прогона `имя` на проекте после переименования `объект` → `довод`."""
    return семя()["renames"][ключ("rename", объект, довод)]["runs"][имя]


def клетки(мир_):
    """Клетки хода мира кода строкой: меры {имя: число}, строки [{поле: значение}] по полям, какие род объявил
    (`ПОЛЯ`), отказ — «почему "что"». Первое поле рода начинает строку."""
    куски = мир_.rstrip(".").split(" · ")
    поля = ПОЛЯ.get(куски[0].split(" ", 1)[0], ())
    меры, строки_, отказ_ = {}, [], None
    for кусок in куски[1:]:
        имя, _, значение = кусок.partition(" ")
        if имя == "refused":
            отказ_ = значение
        elif имя in поля:
            if имя == поля[0] or not строки_:
                строки_.append({})
            строки_[-1][имя] = значение[1:-1] if имя == "text" else значение
        else:
            меры[имя] = int(значение)
    return меры, строки_, отказ_


def поле(ход_, имя):
    return [значение for строка in ход_.строки for поле_, значение in строка if поле_ == имя]


if __name__ == "__main__":
    с = семя()
    print(f"МИР КОДА: актов чтения {len(акты_чтения())}, переименований {len(ПЕРЕИМЕНОВАНИЯ)}; отпечаток {отпечаток()},"
          f" семя {'есть' if с else 'нет'} ({с.get('source', '—')})")
