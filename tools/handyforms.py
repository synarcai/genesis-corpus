#!/usr/bin/env python3
"""ДОМ УДОБНОГО СЧЁТА — ЗАКОН, ПРИМЕНЁННЫЙ РАДИ ЛЁГКОСТИ.

    УДОБНОГО СЧЁТА В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 237 мирам показов: «удобно»,
    «перегруппиру», «дополнение до десятка» — НОЛЬ. Свод считает столбиком и по правилу, но
    нигде не показывает, что счёт можно ОБЛЕГЧИТЬ, переставив слагаемые к круглому числу.

ЭТОТ ДОМ СТОИ́Т НА ДОМЕ ЗАКОНОВ ДЕЙСТВИЯ, ПОСТРОЕННОМ В ТУ ЖЕ СМЕНУ: там сочетательный закон
объявлен и показан («скобка сумму не меняет»), здесь он РАБОТАЕТ. Закон, показанный без
применения, читается как украшение; применение без закона — как фокус.

    ЗАКОН И ЕГО ПРИМЕНЕНИЕ СУТЬ ДВЕ ПОЛОВИНЫ ОДНОГО ЗНАНИЯ, И ПОРОЗНЬ КАЖДАЯ БЕСПОЛЕЗНА.

ОДИННАДЦАТАЯ ЛОВУШКА РЯДА — ВТОРОЙ РОД: В ВЫЧИТАНИИ ЛИШНЕЕ ВОЗВРАЩАЮТ, А НЕ ОТНИМАЮТ. Кто занял
в сложении три — отдаёт три из второго слагаемого; кто вычел на два больше — ПРИБАВЛЯЕТ два
обратно. Направление поправки меняется на противоположное, и это ровно то место, где счёт в уме
ломается чаще всего.

ЧЕТЫРЕ РОДА:

    сложением     дополним 37 до 40 и вернём разницу: 48 − 3 = 45, и 40 + 45 = 85,
                  и 37 + 48 = 85.
    вычитанием    вычтем 40 вместо 38 и вернём лишнее: 85 − 40 = 45, и 45 + 2 = 47,
                  и 85 − 38 = 47.                                          ← ЛОВУШКА
    закон         перегруппировка законна, ибо скобка сумму не меняет: (37 + 3) + 45 = 85,
                  и 37 + (3 + 45) = 85.                                    ← ОСНОВАНИЕ
    дополнение    дополнение 37 до десятка: 40 − 37 = 3, и 37 + 3 = 40.

ПЕРВЫЙ И ВТОРОЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО НАПРАВЛЕНИЮ ПОПРАВКИ: те же круглые числа, тот же ход, и
разница в одном месте — прибавляют поправку или отнимают.

ФОРМА СТРАНИЦЫ КУПЛЕНА ЗАМЕРОМ ПАЛАТЫ, И ЗАМЕР НАЗВАЛ ЗАКОН ЧУЖОГО ПРИБОРА:

    СУД АРИФМЕТИКИ ЧИТАЕТ ТО, ЧТО СТОИ́Т ПОСЛЕ ДВОЕТОЧИЯ.

Проверено прямой пробой: «48 − 3 = 45: дополним 37 до 40.» — палата МОЛЧИТ; «дополним 37 до 40:
и 48 − 3 = 45.» — читает и считает. Потому всякая страница этого дома держит СЛОВА ДО ДВОЕТОЧИЯ,
а РАВЕНСТВА ПОСЛЕ — и каждая проверяется дважды: своим судом и судом арифметики.

    ДОМ, НАПИСАННЫЙ ПОД ЧУЖОЙ ПРИБОР, ПРОВЕРЯЕТСЯ ДВАЖДЫ; ДОМ, НАПИСАННЫЙ МИМО НЕГО, — ОДИН РАЗ.

    python3 tools/handyforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("сложением", "вычитанием", "закон", "дополнение")

РАМКИ = {
    "ru": {
        "сложением": "дополним {a} до {r} и вернём разницу: {b} − {d} = {b2}, и {r} + {b2} = {s}, и {a} + {b} = {s}.",
        "вычитанием": "вычтем {r} вместо {b} и вернём лишнее: {a} − {r} = {t}, и {t} + {d} = {c}, и {a} − {b} = {c}.",
        "закон": "перегруппировка законна, ибо скобка сумму не меняет: ({a} + {d}) + {b2} = {s}, и {a} + ({d} + {b2}) = {s}.",
        "дополнение": "дополнение {a} до десятка: {r} − {a} = {d}, и {a} + {d} = {r}.",
    },
    "en": {
        "сложением": "complete {a} to {r} and return the difference: {b} − {d} = {b2}, and {r} + {b2} = {s}, and {a} + {b} = {s}.",
        "вычитанием": "subtract {r} instead of {b} and return the extra: {a} − {r} = {t}, and {t} + {d} = {c}, and {a} − {b} = {c}.",
        "закон": "regrouping is lawful, for the bracket does not change the sum: ({a} + {d}) + {b2} = {s}, and {a} + ({d} + {b2}) = {s}.",
        "дополнение": "the complement of {a} to a ten: {r} − {a} = {d}, and {a} + {d} = {r}.",
    },
}
ПУСТО = dict(a=0, b=0, d=0, r=0, b2=0, s=0, t=0, c=0)


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a in range(11, 90):
            d = 10 - a % 10
            if d == 10:
                continue
            r = a + d
            # СЛОЖЕНИЕМ и ЗАКОН стоят на одних числах: вторая страница ОПРАВДЫВАЕТ первую,
            # и разлучать их значило бы оставить ход без основания.
            for b in range(11, 100):
                # РЯДЫ ВЫРАВНЕНЫ ЗАМЕРОМ, А НЕ ГЛАЗОМ: первый перебор дал роду сложения
                # 648 страниц против 24 у дополнения — перекос в двадцать семь раз, и дом
                # читался бы как дом одного рода с тремя приложениями.
                if b <= d or (a * b) % 11 or (a + b) % 2 or b % 3:
                    continue
                вон[рамки["сложением"].format(
                    **dict(ПУСТО, a=a, b=b, d=d, r=r, b2=b - d,
                           s=a + b))] = (язык, "сложением")
                if (a + b) % 6 == 0:
                    вон[рамки["закон"].format(
                        **dict(ПУСТО, a=a, d=d, b2=b - d, s=a + b))] = (язык, "закон")
            вон[рамки["дополнение"].format(
                **dict(ПУСТО, a=a, d=d, r=r))] = (язык, "дополнение")
        # ВЫЧИТАНИЕМ: вычитаемое округляется ВВЕРХ, и поправка возвращается СЛОЖЕНИЕМ.
        for b in range(11, 90):
            d = 10 - b % 10
            if d == 10:
                continue
            r = b + d
            for a in range(r + 5, 100):
                if (a * b) % 13 or (a + b) % 3:
                    continue
                вон[рамки["вычитанием"].format(
                    **dict(ПУСТО, a=a, b=b, d=d, r=r, t=a - r,
                           c=a - b))] = (язык, "вычитанием")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_СУММА = re.compile(r"(?<![/\d])(\d+) \+ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (\d+)(?![/\d])")
_СКОБКА_СЛЕВА = re.compile(r"\((\d+) \+ (\d+)\) \+ (\d+) = (\d+)")
_СКОБКА_СПРАВА = re.compile(r"(\d+) \+ \((\d+) \+ (\d+)\) = (\d+)")
_ДО_КРУГЛОГО = re.compile(r"(?:дополним|complete) (\d+) (?:до|to) (\d+)")
_ВМЕСТО = re.compile(r"(?:вычтем|subtract) (\d+) (?:вместо|instead of) (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # СКОБКИ СЧИТАЮТСЯ ПЕРВЫМИ, И ИХ ЧЛЕНЫ ИЗ ПРОСТОГО СЧЁТА ИСКЛЮЧАЮТСЯ: «(37 + 3) + 45 = 85»
    # не есть «37 + 3 = 85», и образец суммы без этой оглядки взял бы голову за целое.
    скобочные = set()
    for обр, счёт in ((_СКОБКА_СЛЕВА, lambda g: int(g[0]) + int(g[1]) + int(g[2])),
                      (_СКОБКА_СПРАВА, lambda g: int(g[0]) + int(g[1]) + int(g[2]))):
        for г in обр.findall(с):
            if счёт(г) != int(г[3]):
                return True, False
            скобочные.update(г[:3])
    без_скобок = re.sub(r"\([^)]*\)", "()", с)
    for a, b, c in _СУММА.findall(без_скобок):
        if int(a) + int(b) != int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(без_скобок):
        if int(a) - int(b) != int(c):
            return True, False
    # КРУГЛОЕ ЧИСЛО ОБЯЗАНО БЫТЬ КРУГЛЫМ, А ДОПОЛНЕНИЕ — ДОПОЛНЯТЬ: иначе ход показан, но не
    # показано, ЗАЧЕМ он.
    for a, r in _ДО_КРУГЛОГО.findall(с):
        if int(r) % 10 or not 0 < int(r) - int(a) < 10:
            return True, False
    for r, b in _ВМЕСТО.findall(с):
        if int(r) % 10 or not 0 < int(r) - int(b) < 10:
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:86]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    сл = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "сложением")
    вы = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "вычитанием")
    for страница, слово, куда in ((сл, "разницу", "разниц"), (вы, "лишнее", "лишне")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(сл + " " + сл)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # СЛОВА ДО ДВОЕТОЧИЯ, РАВЕНСТВА ПОСЛЕ — ИНАЧЕ СУД АРИФМЕТИКИ СТРАНИЦУ НЕ ПРОЧТЁТ.
    for с in ПОКАЗЫ:
        хвост = с.split(":", 1)[1] if ":" in с else ""
        if not хвост or re.search(r"[A-Za-zА-Яа-яЁё]{4,}", хвост.replace("and", "")
                                  .replace("и ", "")):
            беды.append(f"СЛОВА ПОСЛЕ ДВОЕТОЧИЯ: {с[:70]}")
            break
    print(f"УДОБНЫЙ СЧЁТ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
