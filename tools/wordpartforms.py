#!/usr/bin/env python3
"""ДОМ ЧАСТЕЙ СЛОВА — шов между леммой и окончанием, и разбор слова по этому шву.

Мир `wordparts` был САМЫМ БОЛЬШИМ БЕЗДОМНЫМ МИРОМ СВОДА: 4 767 строк без объявленного рода —
больше, чем у любого другого. Кузница его писала СЕМЬ разных страниц на всякий состав и звала
их одним безымянным потоком; сайдкар родов не мог назвать ни одной.

    МИР, ЧЬИ СТРАНИЦЫ НЕ НАЗВАНЫ РОДОМ, ЧИТАЕТСЯ ТОЛЬКО ТЕМ, КТО ЧИТАЕТ КУЗНИЦУ.

ЧЕТЫРЕ РОДА, И ВСЕ ЧЕТЫРЕ БЫЛИ В КУЗНИЦЕ С ПЕРВОГО ДНЯ — их не выдумали, а НАЗВАЛИ:

    шов              «книга + и = книги.» — сложение леммы с окончанием
    вопрос о шве     то же, спрошенное на двух языках
    разбор           «книги — это книга с окончанием -и.» — обратный ход
    вопрос о разборе «из чего состои́т книги?» — то же вопросом

    РАЗДЕЛЯЯ ВЕЛИКАНА, ЛЕГКО СЛОЖИТЬ НОВОГО: род «вопрос обо всём» есть тот же великан,
    только собранный по ФОРМЕ РЕЧИ вместо ПРЕДМЕТА. Оттого вопросов здесь ДВА рода, а не один:
    вопрос о шве и вопрос о разборе спрашивают о РАЗНОМ.

СОСТАВЫ БЕРУТСЯ У ПАКЕТОВ, А НЕ ПИШУТСЯ ЗДЕСЬ: всякая объявленная форма, НАРАЩИВАЮЩАЯ лемму,
даёт шов. Письмо без пробелов (`segmentation: longest-match`) по краю слова не режется, и такие
пакеты дом пропускает — шов в них есть иной вопрос.
"""
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ПАКЕТЫ = КОРЕНЬ / "tools" / "langpacks"

РОДЫ = ("шов", "вопрос о шве", "разбор", "вопрос о разборе")

ЗАЧЕМ_РОДА = {
    "шов": "лемма плюс окончание даёт слово: сложение частей",
    "вопрос о шве": "то же сложение, спрошенное вопросом на двух языках",
    "разбор": "слово разложено на лемму и окончание: обратный ход шва",
    "вопрос о разборе": "из чего состои́т слово — спрошено и отвечено",
}


def составы():
    """(язык, лемма, часть, слово) для каждой объявленной формы, наращивающей лемму."""
    вон = []
    for п in sorted(ПАКЕТЫ.glob("*.json")):
        пак = json.loads(п.read_text(encoding="utf-8"))
        я = пак.get("lang", п.stem)
        # ПИСЬМО БЕЗ ПРОБЕЛОВ НЕ РЕЖЕТСЯ ПО КРАЮ СЛОВА, и шов в нём — иной вопрос
        if пак.get("segmentation") == "longest-match":
            continue
        видано = set()
        for _имя, кл in (пак.get("morph_classes") or {}).items():
            for лемма, формы in (кл.get("lexemes") or {}).items():
                for ф in формы:
                    ф = str(ф)
                    if ф == лемма or not ф.startswith(лемма) or len(ф) <= len(лемма):
                        continue
                    часть = ф[len(лемма):]
                    if " " in часть or " " in лемма:
                        continue          # пробел есть граница слова, а не шов
                    ключ = (я, лемма, часть)
                    if ключ in видано:
                        continue
                    видано.add(ключ)
                    вон.append((я, лемма, часть, ф))
    return вон


СОСТАВЫ = составы()


def перебор(шаг):
    """[(страница, род, ЯЗЫК)] — те же семь страниц на состав, каждая под своим именем.

    ЯЗЫК СТРАНИЦЫ ЕСТЬ ЯЗЫК ЕЁ ОБЁРТКИ, А НЕ ЕЁ МАТЕРИАЛА (15.09). Дом показывает шов слова на
    двадцати одном языке — амхарском, венгерском, корейском, тамильском, — но ГОВОРИТ о нём на
    двух: «what is X + Y?» и «сколько будет X + Y?». Двадцать один язык здесь МАТЕРИАЛ показа,
    два — язык речи о нём.

        МЕРА ЩЕРБАТОСТИ СПРАШИВАЕТ, НА КАКОМ ЯЗЫКЕ ДОМ ГОВОРИТ, А НЕ О ЧЁМ. Пометь этот дом
        языком материала — и она потребовала бы амхарского вопроса о венгерском слове, чего
        дом не обещал и обещать не мог.

    Сам шов («ጠረጴዛ + ዎች = ጠረጴዛዎች.») обёртки не имеет вовсе: он ПОКАЗЫВАЕТ, а не говорит, — и
    помечен знаком «—», объявленной внеязычностью, как запись «(1, 2) + (3, 1) = (4, 3).» у
    дома линейной алгебры.

    ПОРЯДОК ТОТ ЖЕ, ЧТО У КУЗНИЦЫ, И ЭТО НЕ ВКУС: `группы` снимают метку и отдают ряд строк,
    а мир обязан остаться байт в байт прежним. Метка есть дело указателя, а не письма.
    """
    from layer import PASSES                              # noqa: PLC0415
    из = [с for k, с in enumerate(СОСТАВЫ) if k % len(PASSES) == шаг]
    вон = []
    for _я, лемма, часть, слово in из:
        вон.append((f"{лемма} + {часть} = {слово}.", "шов", "—"))
        вон.append((f"what is {лемма} + {часть}? {лемма} + {часть} = {слово}.",
                    "вопрос о шве", "en"))
        вон.append((f"сколько будет {лемма} + {часть}? {лемма} + {часть} = {слово}.",
                    "вопрос о шве", "ru"))
        вон.append((f"{слово} is {лемма} with the ending -{часть}.", "разбор", "en"))
        вон.append((f"{слово} — это {лемма} с окончанием -{часть}.", "разбор", "ru"))
        вон.append((f"what is {слово} made of? {слово} is {лемма} with the ending -{часть}.",
                    "вопрос о разборе", "en"))
        вон.append((f"из чего состои́т {слово}? {слово} — это {лемма} "
                    f"с окончанием -{часть}.", "вопрос о разборе", "ru"))
    return вон


def страницы(шаг):
    """Ряд строк без меток — ровно то, чем кормится кузница."""
    return [с for с, _р, _я in перебор(шаг)]


def группы(шаг):
    """Одна группа: кузница этого мира зовёт `emit`, а не `emit_grouped`."""
    return [страницы(шаг)]


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род, язык in перебор(шаг):
            вон.setdefault(с, (язык, род))
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, а не с кортежем."""
    assert all(isinstance(р, str) for р in РОДЫ), "РОДЫ обязаны быть рядом ИМЁН"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    из_прохода = {р for _с, р, _я in перебор(0)}
    assert из_прохода <= set(РОДЫ), f"роды вне объявления: {sorted(из_прохода - set(РОДЫ))}"
    assert set(РОДЫ) <= из_прохода, f"род объявлен и не кован: {sorted(set(РОДЫ) - из_прохода)}"
    из_перебора = sorted(с for с, _р, _я in перебор(0))
    из_групп = sorted(с for г in группы(0) for с in г)
    assert из_перебора == из_групп, "пересборка потеряла или выдумала страницы"


_самопроверка()
