#!/usr/bin/env python3
"""ДОМ ДЛИНЫ ЗАПИСИ — У ЦЕЛЫХ ЧИСЕЛ ДЛИННЕЕ ЗАПИСЬ ЗНАЧИТ БОЛЬШЕ ЧИСЛО.

    ЛОВУШКА СОСЕДА СТОИ́Т НА ПРАВИЛЕ, КОТОРОГО СВОД НЕ ГОВОРИЛ. Мир десятичной доли (`dec`)
    объявляет прямо: «читатель, знающий целые числа, сравнивает ПО ДЛИНЕ ЗАПИСИ и по цифрам —
    и ошибается ровно там, где записи разной длины». Он ловит читателя на этой привычке и
    учит, что для дробей она лжёт. А самого правила — верного для целых — свод не сказал
    ни разу.

Замер 11.09 по 254 мирам показов: «сколько цифр», «больше цифр», «more digits», «длиннее
запись» — НОЛЬ. Длину записи свод УПОТРЕБЛЯЕТ (мир прикидки отвергает ответ: «3990 has 4 digits
while 400 has 3») и не ОБЪЯВЛЯЕТ.

    ЛОВУШКА, СТОЯЩАЯ НА ПРАВИЛЕ, КОТОРОГО СВОД НЕ ГОВОРИЛ, ЛОВИТ ЧИТАТЕЛЯ НА ЧУЖОЙ ПРИВЫЧКЕ,
    А НЕ НА СВОЁМ УРОКЕ.

ДВАДЦАТЬ ШЕСТАЯ ЛОВУШКА РЯДА: 1000 БОЛЬШЕ 999, ХОТЯ КАЖДАЯ ЦИФРА 999 БОЛЬШЕ КАЖДОЙ ЦИФРЫ 1000.
Читатель, сравнивающий цифры, ошибётся; читатель, сравнивающий длины, — нет.

    ЦИФРЫ СРАВНИВАЮТ ЛИШЬ ПОСЛЕ ТОГО, КАК СРАВНИЛИ ДЛИНЫ; ДЛИНА РЕШАЕТ ПЕРВОЙ И РЕШАЕТ ОДНА,
    КОГДА ОНА РАЗНАЯ.

ЧЕТЫРЕ РОДА:

    длиннее      1000 больше 999, хотя каждая цифра 999 больше: в записи 1000 цифр 4,
                 а в записи 999 цифр 3.                                          ← ЛОВУШКА
    поровну      347 и 374: цифр поровну, и решает первое слева место, где они разошлись —
                 на месте десятков 7 больше 4: 374 − 347 = 27.
    сколько цифр в числе 347 цифр 3, ибо 347 больше 99 и меньше 1000.
    когда довольно  у 1000 и 999 длины разные, и длины довольно; у 347 и 374 длины равны,
                 и длины НЕ довольно: 374 − 347 = 27.

ЧЕТВЁРТЫЙ РОД ГОВОРИТ ЗАКОН ДЕЛОМ И ГОВОРИТ ЕГО ГРАНИЦУ РАЗОМ: длина решает, когда она разная,
и молчит, когда равная. Правило без своей границы читатель применит там, где оно немо.

    ПРАВИЛО, НЕ СКАЗАВШЕЕ, ГДЕ ОНО МОЛЧИТ, БУДЕТ ПРИМЕНЕНО ТАМ, ГДЕ ОНО МОЛЧИТ.

СЧЁТНЫХ ФОРМ СЛОВА «ЦИФРА» ДОМ НЕ ПРОСИТ: «в записи 1000 цифр 4» ставит число ПОСЛЕ слова, и
согласования нет. Это тот же ход, каким дом разряда обошёл необъявленное слово, и он взят
нарочно — правка языка ради одного оборота уже стоила однажды пятнадцати чужих строк.

РАВЕНСТВО СТОИ́Т ПОСЛЕДНИМ, ПОСЛЕ ДВОЕТОЧИЯ, ЧТОБЫ ЕГО ПРОЧЁЛ ОБЩИЙ СУД: дом, чьи равенства
читает только он сам, охраняет их в одиночку.

    python3 tools/digitlenforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("длиннее", "поровну", "сколько цифр", "когда довольно")

РАМКИ = {
    "ru": {
        "длиннее": "{b} больше {a}, хотя каждая цифра {a} больше: в записи {b} цифр {дб}, "
                   "а в записи {a} цифр {да}: {b} − {a} = {r}.",
        "поровну": "{n} и {m}: цифр поровну, и решает первое слева место, где они разошлись — "
                   "на месте {место} {ц2} больше {ц1}: {m} − {n} = {r}.",
        "сколько цифр": "в числе {n} цифр {д}, ибо {n} больше {ниже} и меньше {выше}: "
                        "{выше} − {ниже} = {шаг}.",
        "когда довольно": "у {b} и {a} длины разные, и длины довольно; у {n} и {m} длины равны, "
                          "и длины не довольно: {m} − {n} = {r}.",
    },
    "en": {
        "длиннее": "{b} is greater than {a}, though every digit of {a} is greater: the writing "
                   "{b} has {дб} digits and the writing {a} has {да}: {b} − {a} = {r}.",
        "поровну": "{n} and {m}: the digits are equally many, and the leftmost place where they "
                   "differ decides — in the {место} place {ц2} is greater than {ц1}: "
                   "{m} − {n} = {r}.",
        "сколько цифр": "the number {n} has {д} digits, for {n} is greater than {ниже} and less "
                        "than {выше}: {выше} − {ниже} = {шаг}.",
        "когда довольно": "{b} and {a} differ in length, and the length is enough; {n} and {m} "
                          "are of one length, and the length is not enough: {m} − {n} = {r}.",
    },
}
МЕСТА = {"ru": {1: "единиц", 2: "десятков", 3: "сотен"},
         "en": {1: "units", 2: "tens", 3: "hundreds"}}
ПУСТО = dict(a=0, b=0, n=0, m=0, r=0, да=0, дб=0, д=0, ниже=0, выше=0, шаг=0,
             место="", ц1=0, ц2=0)


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, места = РАМКИ[язык], МЕСТА[язык]
        # ДЛИННЕЕ: числа вида 99…9 и 10…0 — единственная пара, где КАЖДАЯ цифра меньшего
        # больше каждой цифры большего. Иначе ловушка не ловит.
        for д in (2, 3):
            b = 10 ** д
            for a in range(10 ** (д - 1), b):
                # ЛОВУШКА ЛОВИТ ЛИШЬ ТАМ, ГДЕ КАЖДАЯ ЦИФРА МЕНЬШЕГО БОЛЬШЕ КАЖДОЙ ЦИФРЫ
                # БОЛЬШЕГО: у 10^д цифры суть 1 и нули, значит цифры меньшего — от двух.
                if min(str(a)) <= max(str(b)) or (a + д) % 3:
                    continue
                вон[рамки["длиннее"].format(
                    **dict(ПУСТО, a=a, b=b, да=д, дб=д + 1, r=b - a))] = (язык, "длиннее")
        # ПОРОВНУ: переставлены два соседних места, и решает левое из них.
        for c in range(1, 10):
            for d in range(0, 9):
                for e in range(d + 1, 10):
                    if (c + d + e) % 4:
                        continue
                    n = c * 100 + d * 10 + e
                    m = c * 100 + e * 10 + d
                    общ = dict(ПУСТО, n=n, m=m, r=m - n, место=места[2], ц1=d, ц2=e)
                    вон[рамки["поровну"].format(**общ)] = (язык, "поровну")
                    # КОГДА ДОВОЛЬНО: та же пара равной длины СТОИ́Т РЯДОМ с парой разной длины —
                    # иначе закон говорит о разных числах и читается как два правила.
                    for д in (3,):
                        a, b = 10 ** д - 1, 10 ** д
                        вон[рамки["когда довольно"].format(
                            **dict(общ, a=a, b=b))] = (язык, "когда довольно")
        # СКОЛЬКО ЦИФР: граница разряда названа обеими сторонами.
        for д in (2, 3, 4):
            ниже, выше = 10 ** (д - 1) - 1, 10 ** д
            for n in range(10 ** (д - 1), 10 ** д, max(1, 10 ** (д - 1) // 12)):
                if (n + д) % 3:
                    continue
                вон[рамки["сколько цифр"].format(
                    **dict(ПУСТО, n=n, д=д, ниже=ниже, выше=выше, шаг=выше - ниже))] = (
                    язык, "сколько цифр")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_РАЗНОСТЬ = re.compile(r"(?<![/\d])(?<!− )(\d+) − (\d+) = (\d+)(?![/\d])")
_БОЛЬШЕ = re.compile(r"(?<![/\d])(\d+) больше (\d+)(?![/\d])"
                     r"|(\d+) is greater than (\d+)(?![/\d])")
_МЕНЬШЕ = re.compile(r"(?<![/\d])(\d+) меньше (\d+)(?![/\d])"
                     r"|(\d+) is less than (\d+)(?![/\d])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    for ру1, ру2, ан1, ан2 in _БОЛЬШЕ.findall(с):
        x, y = int(ру1 or ан1), int(ру2 or ан2)
        if x <= y:
            return True, False
    for ру1, ру2, ан1, ан2 in _МЕНЬШЕ.findall(с):
        x, y = int(ру1 or ан1), int(ру2 or ан2)
        if x >= y:
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    дл = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "длиннее")
    пв = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "поровну")
    for страница, слово, куда in ((дл, "цифра", "цифр"), (пв, "место", "мест")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(дл + " " + дл)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ЛОВУШКА ОБЯЗАНА ЛОВИТЬ: у меньшего числа КАЖДАЯ цифра больше каждой цифры большего.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "длиннее" or я != "ru":
            continue
        b, a, _ = _РАЗНОСТЬ.findall(с)[0]
        if not (len(b) == len(a) + 1 and min(a) > max(b)):
            беды.append(f"ловушка не ловит: {с[:80]}")
            break
    # ПОРОВНУ СТОИ́Т НА РАВНОЙ ДЛИНЕ, иначе это та же ловушка под другим именем.
    for с, (я, р) in ПОКАЗЫ.items():
        if р != "поровну" or я != "ru":
            continue
        m, n, _ = _РАЗНОСТЬ.findall(с)[0]
        if len(m) != len(n) or sorted(m) != sorted(n):
            беды.append(f"поровну не о равной длине: {с[:80]}")
            break
    print(f"ДЛИНА ЗАПИСИ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
