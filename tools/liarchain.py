#!/usr/bin/env python3
"""ДОМ ЦЕПИ СВИДЕТЕЛЬСТВ — кто говорит правду, если каждый говорит о предыдущем (16.09).

Вторая ступень лестницы (BBH) держит род `web_of_lies`: первый объявлен правдивым или
лживым, каждый следующий говорит О ПРЕДЫДУЩЕМ — «он говорит правду» либо «он лжёт», — и
надо решить, правдив ли названный. Замерено по своду 16.09: строк со словами «говорит
правду», «tells the truth», «лжёт» в этом смысле — НОЛЬ. Корпус знал ЛОЖЬ КАК СВОЙСТВО
СТРОКИ (суды зовут ложной страницу), но не знал ЛЖИ КАК СВИДЕТЕЛЬСТВА О ДРУГОМ.

    ЦЕПЬ СВИДЕТЕЛЬСТВ НЕ ЕСТЬ ЦЕПЬ СВЯЗОК. «не не истина» и «Вера говорит, что Аня лжёт»
    считаются одинаково — двойное отрицание, — но учат разному: первое есть правило записи,
    второе есть правило ДОВЕРИЯ. Из умения снимать отрицания не следует умение спросить «а
    кто это сказал?», и корпус, знающий одно и не знающий другого, о свидетельстве нем.

ЧЕТЫРЕ РОДА ПО ДЕЛУ:

    прямая      «Аня говорит правду. Вера говорит, что Аня говорит правду.» — один шаг;
    отрицание   «Аня лжёт. Вера говорит, что Аня лжёт.» — свидетель о лжеце правдив;
    цепь        три и четыре звена: ответ выводится проходом, а не запоминанием;
    о_среднем   спрошен не последний, а СЕРЕДИНА цепи — иначе читатель выучит, что
                вопрос всегда о крайнем, и станет отвечать по месту, а не по делу.

ОТВЕТ НЕСЁТ ПРОХОД, А НЕ ОДНО СЛОВО: «нет: Аня лжёт, значит Вера, сказавшая о ней правду,
лжёт». Голое «да» или «нет» учит называть исход, а не идти по цепи, — и проверить такую
страницу нечем, кроме как поверить ей.

    ПОКАЗ, ЧЕЙ ОТВЕТ НЕЛЬЗЯ ПРОВЕРИТЬ ИНАЧЕ, КАК ПОВЕРИВ ЕМУ, УЧИТ ДОВЕРИЮ, А НЕ ДЕЛУ.

ЛИЦА БЕРУТСЯ У ПАКЕТА, А НЕ ОБЪЯВЛЯЮТСЯ ЗДЕСЬ ВТОРЫМ СПИСКОМ (закон дня 16.09: лицо есть
объявление пакета, а не форма буквы). Суд читает тот же ряд и о слове вне ряда МОЛЧИТ:
строка, где на месте лица стои́т незнакомое слово, дому не принадлежит.
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "tools"))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("прямая", "отрицание", "цепь", "о_среднем")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "прямая": "«Аня говорит правду. Вера говорит, что Аня говорит правду» — один шаг доверия",
    "отрицание": "свидетель о лжеце: сказавший «он лжёт» о лжеце — говорит правду",
    "цепь": "три и четыре звена: ответ выводится проходом, а не запоминанием",
    "о_среднем": "спрошен не последний, а середина цепи — вопрос не о месте, а о деле",
}


def _лица(язык):
    """Имена лиц — из объявления пакета, а не из головы дома."""
    п = json.loads((КОРЕНЬ / "tools" / "langpacks" / f"{язык}.json").read_text(encoding="utf-8"))
    ряд = [str(и) for и in (п.get("person_names") or ())]
    # ИМЯ ПИШЕТСЯ С ЗАГЛАВНОЙ, И ПАКЕТ САМ ОБЪЯВЛЯЕТ ЕЁ (05.09, дом школьных задач).
    return tuple(dict.fromkeys(и[:1].upper() + и[1:] for и in ряд if len(и) > 2))


ЛИЦА = {я: _лица(я) for я in ЯЗЫКИ}

РЕЧЬ = {
    "ru": {"правдив": "{X} говорит правду", "лжив": "{X} лжёт",
           "свидетель": "{Y} говорит, что {формула}",
           "вопрос": "говорит ли {Z} правду?",
           "да": "да", "нет": "нет",
           "и": ", значит ", "двоеточие": ": ", "точка": "."},
    "en": {"правдив": "{X} tells the truth", "лжив": "{X} lies",
           "свидетель": "{Y} says that {формула}",
           "вопрос": "does {Z} tell the truth?",
           "да": "yes", "нет": "no",
           "и": ", so ", "двоеточие": ": ", "точка": "."},
}

# ДЛИНЫ ЦЕПИ ПО РОДАМ: род есть ДЕЛО, и дело здесь — сколько шагов надо пройти.
ДЛИНЫ = {"прямая": 2, "отрицание": 2, "цепь": (3, 4), "о_среднем": (3, 4)}


def _звенья(длина, семя):
    """[(правдив_ли_свидетель)] — что сказал каждый свидетель о предыдущем.

    ПЕРВОЕ ЗВЕНО ЕСТЬ ОБЪЯВЛЕНИЕ, А НЕ СВИДЕТЕЛЬСТВО: о первом говорит сама страница.
    """
    вон = []
    for i in range(длина - 1):
        вон.append(bool((семя >> i) & 1))
    return вон


def _истина(первый_правдив, сказанное):
    """Правдив ли каждый по цепи: свидетель правдив тогда и только тогда, когда его
    свидетельство совпало с делом."""
    вон = [первый_правдив]
    for сказал_правду_о_предыдущем in сказанное:
        # Свидетель утверждает «предыдущий правдив» (True) либо «предыдущий лжёт» (False).
        # Он сам правдив ровно тогда, когда его утверждение верно.
        вон.append(сказал_правду_о_предыдущем == вон[-1])
    return вон


def _разбор_прохода(язык, лица, правда, кого):
    """Проход до спрошенного: цепочка коротких утверждений, а не голое «да»."""
    р = РЕЧЬ[язык]
    куски = []
    for i in range(кого + 1):
        рамка = р["правдив"] if правда[i] else р["лжив"]
        куски.append(рамка.format(X=лица[i]))
    return р["и"].join(куски)


def страница(язык, род, семя, место=0):
    р = РЕЧЬ[язык]
    ряд = ЛИЦА[язык]
    длина = ДЛИНЫ[род] if isinstance(ДЛИНЫ[род], int) else ДЛИНЫ[род][семя % 2]
    if len(ряд) < длина:
        return None
    лица = [ряд[(место + i * 3) % len(ряд)] for i in range(длина)]
    if len(set(лица)) != длина:
        return None
    первый_правдив = (семя // 2) % 2 == 0
    if род == "отрицание":
        первый_правдив = False
    сказанное = _звенья(длина, семя // 4 if род != "прямая" else (семя % 2))
    if род == "прямая" and not all(сказанное):
        return None                    # прямая есть цепь без отрицаний
    правда = _истина(первый_правдив, сказанное)
    # СПРОШЕН ПОСЛЕДНИЙ — ИЛИ СЕРЕДИНА, И ЭТО РАЗНЫЕ РОДЫ.
    кого = (длина // 2) if род == "о_среднем" else длина - 1
    if род == "о_среднем" and кого == 0:
        return None
    голова = (р["правдив"] if первый_правдив else р["лжив"]).format(X=лица[0]) + р["точка"]
    хвост = []
    for i, сказал in enumerate(сказанное, start=1):
        формула = (р["правдив"] if сказал else р["лжив"]).format(X=лица[i - 1])
        хвост.append(р["свидетель"].format(Y=лица[i], формула=формула) + р["точка"])
    вопрос = р["вопрос"].format(Z=лица[кого])
    ответ = р["да"] if правда[кого] else р["нет"]
    проход = _разбор_прохода(язык, лица, правда, кого)
    return " ".join([голова] + хвост + [вопрос]) + " " + ответ + р["двоеточие"] + проход + р["точка"]


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for семя in range(16):
                for место in range(18):
                    с = страница(язык, род, семя, место)
                    if с:
                        вон.setdefault(с, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД ПРОХОДИТ ЦЕПЬ ЗАНОВО И НЕ ВЕРИТ НИ ОТВЕТУ, НИ ПРОХОДУ СТРАНИЦЫ.
def _образец(язык):
    р = РЕЧЬ[язык]
    ряд = "|".join(re.escape(и) for и in ЛИЦА[язык])
    правдив = re.escape(р["правдив"]).replace(re.escape("{X}"), f"(?:{ряд})")
    лжив = re.escape(р["лжив"]).replace(re.escape("{X}"), f"(?:{ряд})")
    return re.compile(
        r"^(?P<голова>" + f"(?:{правдив}|{лжив})" + r")\. "
        r"(?P<свидетели>.+?) "
        + re.escape(р["вопрос"]).replace(re.escape("{Z}"), f"(?P<кого>{ряд})")
        + r" (?P<ответ>" + re.escape(р["да"]) + "|" + re.escape(р["нет"]) + r")"
        + re.escape(р["двоеточие"]) + r"(?P<проход>.+)" + re.escape(р["точка"]) + r"$")


_ОБРАЗЦЫ = {я: _образец(я) for я in ЯЗЫКИ}


def _прочесть_голову(язык, кусок):
    р = РЕЧЬ[язык]
    for правдив_ли, ключ in ((True, "правдив"), (False, "лжив")):
        о = re.fullmatch(re.escape(р[ключ]).replace(re.escape("{X}"), r"(.+)"), кусок)
        if о and о.group(1) in ЛИЦА[язык]:
            return о.group(1), правдив_ли
    return None, None


def _прочесть_свидетелей(язык, кусок):
    """[(свидетель, о_ком, сказал_правду_ли)] или None — запись не наша."""
    р = РЕЧЬ[язык]
    вон = []
    for часть in кусок.split(р["точка"] + " "):
        часть = часть.rstrip(р["точка"])
        if not часть:
            continue
        нашли = False
        for правдив_ли, ключ in ((True, "правдив"), (False, "лжив")):
            формула = re.escape(р[ключ]).replace(re.escape("{X}"), r"(?P<о_ком>.+)")
            о = re.fullmatch(re.escape(р["свидетель"])
                             .replace(re.escape("{Y}"), r"(?P<кто>.+?)")
                             .replace(re.escape("{формула}"), формула), часть)
            if о and о.group("кто") in ЛИЦА[язык] and о.group("о_ком") in ЛИЦА[язык]:
                вон.append((о.group("кто"), о.group("о_ком"), правдив_ли))
                нашли = True
                break
        if not нашли:
            return None
    return вон or None


def судить(строка):
    """(судимо, истинно) — цепь пройдена заново; чужому лицу суд молчит."""
    с = строка.strip()
    for язык in ЯЗЫКИ:
        м = _ОБРАЗЦЫ[язык].fullmatch(с)
        if not м:
            continue
        первый, первый_правдив = _прочесть_голову(язык, м.group("голова"))
        if первый is None:
            continue                           # лицо вне объявленного ряда — не наша запись
        свидетели = _прочесть_свидетелей(язык, м.group("свидетели"))
        if not свидетели:
            continue
        # ЦЕПЬ ОБЯЗАНА БЫТЬ ЦЕПЬЮ: всякий свидетель говорит о ПРЕДЫДУЩЕМ, и порядок этот
        # есть предмет дома. Страница, где свидетель говорит через голову, дому не своя.
        лица = [первый]
        сказанное = []
        for кто, о_ком, сказал in свидетели:
            if о_ком != лица[-1] or кто in лица:
                return True, False             # цепь порвана либо лицо повторено
            лица.append(кто)
            сказанное.append(сказал)
        правда = _истина(первый_правдив, сказанное)
        кого = м.group("кого")
        if кого not in лица:
            return True, False
        i = лица.index(кого)
        р = РЕЧЬ[язык]
        ждём_ответ = р["да"] if правда[i] else р["нет"]
        if м.group("ответ") != ждём_ответ:
            return True, False
        return True, м.group("проход") == _разбор_прохода(язык, лица, правда, i)
    return False, True


# ПОДСАДКИ ОБЪЯВЛЕНЫ ЗДЕСЬ, И СУД БЕРЁТ ИХ ОТСЮДА ЖЕ: два похожих списка расходятся молча.
ПОДСАДКИ = (
    # ответ перевёрнут, проход верен
    "Анна говорит правду. Дима говорит, что Анна говорит правду. говорит ли Дима правду? "
    "нет: Анна говорит правду, значит Дима говорит правду.",
    # проход перевёрнут, ответ верен
    "Анна лжёт. Дима говорит, что Анна говорит правду. говорит ли Дима правду? "
    "нет: Анна говорит правду, значит Дима лжёт.",
    # цепь порвана: свидетель говорит не о предыдущем
    "Анна говорит правду. Дима говорит, что Анна говорит правду. Коля говорит, что Анна лжёт. "
    "говорит ли Коля правду? нет: Анна говорит правду, значит Дима говорит правду, значит Коля лжёт.",
    "Ann tells the truth. Dan says that Ann tells the truth. does Dan tell the truth? "
    "no: Ann tells the truth, so Dan tells the truth.",
)


def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    # ОБЪЯВЛЕНИЕ, КОТОРОЕ НЕ ЗОВЁТСЯ, ЕСТЬ ЛОЖЬ О ТОМ, ЧТО ДОМ ДЕЛАЕТ: всякий ключ речи
    # обязан стоять хоть на одной странице либо в образце суда.
    текст = pathlib.Path(__file__).read_text(encoding="utf-8")
    for язык in ЯЗЫКИ:
        for ключ in РЕЧЬ[язык]:
            assert f'"{ключ}"' in текст.split("РЕЧЬ = {", 1)[1].split("ДЛИНЫ = {", 1)[1], \
                f"ключ речи объявлен и не зовётся: {ключ}"
    assert ПОКАЗЫ, "дом не кован"
    роды = {р for _я, р in ПОКАЗЫ.values()}
    пустые = set(РОДЫ) - роды
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"
    языки = {я for я, _р in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    # ЧУЖОЕ ЛИЦО — ЧУЖАЯ СТРАНИЦА, И СУД О НЕЙ МОЛЧИТ (закон дня 16.09).
    чужая = "Зигфрид говорит правду. Дима говорит, что Зигфрид говорит правду. " \
            "говорит ли Дима правду? да: Зигфрид говорит правду, значит Дима говорит правду."
    assert судить(чужая) == (False, True), "суд взялся за лицо вне объявленного ряда"
    # ОБА ИСХОДА ПОКАЗАНЫ: мир, где ответ всегда один, учит называть его не считая.
    ответы = {с.split("? ")[1].split(":")[0] for с in ПОКАЗЫ if "? " in с}
    assert len(ответы) >= 4, f"исходов мало: {sorted(ответы)}"


_самопроверка()


def main():
    import collections
    print(f"  показов {len(ПОКАЗЫ)}, родов {len(РОДЫ)}, языков {len(ЯЗЫКИ)}")
    print("  ", collections.Counter(р for _я, р in ПОКАЗЫ.values()).most_common())
    for язык in ЯЗЫКИ:
        свои = [с for с, (я, _р) in ПОКАЗЫ.items() if я == язык]
        print(f"  {язык}: {свои[0][:150]}")
    поймано = sum(1 for с in ПОДСАДКИ if судить(с) == (True, False))
    print(f"  подсадок поймано: {поймано} из {len(ПОДСАДКИ)}")
    return 0


