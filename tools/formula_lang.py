#!/usr/bin/env python3
"""ЯЗЫК ФОРМУЛ: одно ДЕРЕВО, четыре поверхности, и все ходы обратимы.

Корпус знал формулы ШАБЛОНАМИ: «сумма первых n чисел есть n × ( n + 1 ) / 2»
объявлялась строкой, и рядом с нею объявлялся её словесный близнец. Так
можно выучить СПИСОК формул. Так нельзя научиться ПЕРЕВОДИТЬ формулу,
которой в списке нет, — а именно это и требуется: организм должен
обращать запись в речь и речь в запись при ЛЮБОЙ сложности выражения.

ОТСЮДА ЕДИНСТВЕННОЕ ВЕРНОЕ УСТРОЙСТВО: не список формул, а ДЕРЕВО
ВЫРАЖЕНИЯ и правила его чтения. Сложность приходит даром — дерево
складывается из деревьев, — и ни одна новая формула не стоит ни строки.

ЧЕТЫРЕ ПОВЕРХНОСТИ ОДНОГО ДЕРЕВА:
    ЛАТЕХ  — \\frac{a + b}{2}
    ГЛИФ   — ( a + b ) / 2
    АНГЛ   — the fraction with numerator ( a plus b ) and denominator 2
    РУС    — дробь с числителем ( a плюс b ) и знаменателем 2

И ЧЕТЫРЕ ОБРАТНЫХ ХОДА: каждая поверхность читается обратно В ТО ЖЕ
ДЕРЕВО. Это и есть встроенный оракул, и он сильнее всякой сверки строк:
восемь ходов (четыре туда, четыре обратно) написаны РАЗНЫМИ руками, и
согласие всех восьми на всяком дереве есть доказательство, а не пересказ.

СКОБКИ В РЕЧИ — НЕ УКРАШЕНИЕ, А ГРАММАТИКА. «сумма a и b умножить на c»
двусмысленна в любом языке; математик, говорящий вслух, скобки
ПРОИЗНОСИТ. Здесь составной довод всегда берётся в скобки, а простой —
никогда: правило одно, оно объявлено, и потому речь разбирается
однозначно на любой глубине.

ЧИСЛО СКОБОК В ЗАПИСИ РЕШАЕТ СТАРШИНСТВО, А НЕ ВКУС: глифовая
поверхность ставит скобки ровно там, где ребёнок слабее родителя, и
читает их обратно тем же правилом.
"""

import re

# ---------------------------------------------------------------- РОДЫ
# (знак глифа, латех-обёртка, английское имя, русское имя)
ДВУЧЛЕННЫЕ = {
    "+": ("+", "+", "the sum of", "сумма"),
    "-": ("-", "-", "the difference of", "разность"),
    "*": ("*", "\\cdot", "the product of", "произведение"),
    "/": ("/", None, "the quotient of", "частное"),
    "^": ("^", None, "the power of", "степень"),
    "=": ("=", "=", "the equality of", "равенство"),
    "<": ("<", "<", "the inequality less of", "неравенство меньше"),
    ">": (">", ">", "the inequality greater of", "неравенство больше"),
}
СТАРШИНСТВО = {"=": 0, "<": 0, ">": 0, "+": 1, "-": 1, "*": 2,
               "/": 2, "^": 3}
# слово-связка между доводами двучленного рода
СВЯЗКА = {"en": "and", "ru": "и"}


def чис(n):
    return ("чис", n)


def пер(и):
    return ("пер", и)


# --------------------------------------------------------------- ГЛИФ

def глиф(д, старше=-1):
    """Глифовая запись дерева; скобки — где ребёнок слабее родителя."""
    род = д[0]
    if род == "чис":
        return str(д[1])
    if род == "пер":
        return д[1]
    if род == "дробь":
        тело = f"( {глиф(д[1])} ) / ( {глиф(д[2])} )"
        return тело
    if род == "корень":
        return f"sqrt ( {глиф(д[1])} )"
    if род == "модуль":
        return f"abs ( {глиф(д[1])} )"
    if род == "функ":
        return f"{д[1]} ( {глиф(д[2])} )"
    if род == "сумма":
        return (f"sum {д[1]} from {глиф(д[2])} to {глиф(д[3])} of "
                f"( {глиф(д[4])} )")
    if род in ДВУЧЛЕННЫЕ:
        мой = СТАРШИНСТВО[род]
        лево, право = глиф(д[1], мой), глиф(д[2], мой + 1)
        тело = f"{лево} {род} {право}"
        return f"( {тело} )" if мой < старше else тело
    raise ValueError(род)


_ГЛИФ_ТОКЕН = re.compile(r"\(|\)|[+\-*/^=<>]|[A-Za-z_]\w*|\d+")


def разобрать_глиф(текст):
    """Дерево из глифовой записи, или None."""
    токены = _ГЛИФ_ТОКЕН.findall(текст)
    поз = [0]

    def взгляд():
        return токены[поз[0]] if поз[0] < len(токены) else None

    def взять(ожид=None):
        т = взгляд()
        if ожид is not None and т != ожид:
            raise ValueError(f"ждали {ожид}, нашли {т}")
        поз[0] += 1
        return т

    def простое():
        т = взгляд()
        if т is None:
            raise ValueError("пусто")
        if т == "(":
            взять("(")
            д = выражение(0)
            взять(")")
            return д
        if т == "sqrt":
            взять(); взять("(")
            д = выражение(0)
            взять(")")
            return ("корень", д)
        if т == "abs":
            взять(); взять("(")
            д = выражение(0)
            взять(")")
            return ("модуль", д)
        if т == "sum":
            взять()
            и = взять()
            взять("from")
            от = выражение(0)
            взять("to")
            до = выражение(0)
            взять("of"); взять("(")
            тело = выражение(0)
            взять(")")
            return ("сумма", и, от, до, тело)
        if т.isdigit():
            взять()
            return чис(int(т))
        if re.fullmatch(r"[A-Za-z_]\w*", т):
            взять()
            if взгляд() == "(":
                взять("(")
                д = выражение(0)
                взять(")")
                return ("функ", т, д)
            return пер(т)
        raise ValueError(т)

    def выражение(мин):
        левое = простое()
        while True:
            т = взгляд()
            if т not in ДВУЧЛЕННЫЕ or СТАРШИНСТВО[т] < мин:
                return левое
            взять()
            правое = выражение(СТАРШИНСТВО[т] + 1)
            левое = (т, левое, правое)

    try:
        д = выражение(0)
    except (ValueError, IndexError):
        return None
    return д if поз[0] == len(токены) else None


# -------------------------------------------------------------- ЛАТЕХ

def латех(д, старше=-1):
    """Запись LaTeX того же дерева."""
    род = д[0]
    if род == "чис":
        return str(д[1])
    if род == "пер":
        return д[1]
    if род == "дробь":
        return f"\\frac{{{латех(д[1])}}}{{{латех(д[2])}}}"
    if род == "корень":
        return f"\\sqrt{{{латех(д[1])}}}"
    if род == "модуль":
        return f"\\left| {латех(д[1])} \\right|"
    if род == "функ":
        return f"\\{д[1]}{{{латех(д[2])}}}"
    if род == "сумма":
        return (f"\\sum_{{{д[1]}={латех(д[2])}}}^{{{латех(д[3])}}} "
                f"{{{латех(д[4])}}}")
    if род == "/":
        return f"\\frac{{{латех(д[1])}}}{{{латех(д[2])}}}"
    if род == "^":
        # ОСНОВАНИЕ СТЕПЕНИ БЕРЁТСЯ В СКОБКИ, ЕСЛИ ОНО НЕ ПРОСТОЕ.
        # «\frac{b}{15}^{c}» читается ТеХом верно, но при понижении в
        # глифы даёт «( b ) / ( 15 ) ^ ( c )», что разбирается как
        # b / (15^c) — иной формулой. Скобка снимает двусмысленность
        # там, где она рождается, а не там, где её заметили.
        основа = латех(д[1], 4)
        if д[1][0] not in ("чис", "пер"):
            основа = f"\\left( {основа} \\right)"
        return f"{основа}^{{{латех(д[2])}}}"
    if род in ДВУЧЛЕННЫЕ:
        мой = СТАРШИНСТВО[род]
        знак = ДВУЧЛЕННЫЕ[род][1]
        тело = f"{латех(д[1], мой)} {знак} {латех(д[2], мой + 1)}"
        return f"\\left( {тело} \\right)" if мой < старше else тело
    raise ValueError(род)


# -------------------------------------------------------------- СЛОВА

def _атом(д):
    return д[0] in ("чис", "пер")


def слова(д, язык):
    """Речевая поверхность дерева на объявленном языке.

    СОСТАВНОЙ ДОВОД ВСЕГДА В СКОБКАХ, ПРОСТОЙ — НИКОГДА. Это правило
    делает речь разбираемой однозначно на любой глубине и повторяет то,
    что делает вслух всякий, кто читает формулу другому.
    """
    род = д[0]
    и = 2 if язык == "en" else 3
    if род == "чис":
        return str(д[1])
    if род == "пер":
        return д[1]

    def довод(п):
        т = слова(п, язык)
        return т if _атом(п) else f"( {т} )"

    if род == "дробь" or род == "/":
        если = ("the fraction with numerator {a} and denominator {b}"
                if язык == "en" else
                "дробь с числителем {a} и знаменателем {b}")
        return если.format(a=довод(д[1]), b=довод(д[2]))
    if род == "корень":
        если = ("the square root of {a}" if язык == "en"
                else "квадратный корень из {a}")
        return если.format(a=довод(д[1]))
    if род == "модуль":
        если = ("the absolute value of {a}" if язык == "en"
                else "модуль {a}")
        return если.format(a=довод(д[1]))
    if род == "функ":
        если = ("the {f} of {a}" if язык == "en" else "{f} от {a}")
        return если.format(f=д[1], a=довод(д[2]))
    if род == "сумма":
        если = ("the sum of {t} for {i} from {a} to {b}" if язык == "en"
                else "сумма {t} по {i} от {a} до {b}")
        return если.format(t=довод(д[4]), i=д[1], a=довод(д[2]),
                           b=довод(д[3]))
    if род == "^":
        если = ("{a} to the power {b}" if язык == "en"
                else "{a} в степени {b}")
        return если.format(a=довод(д[1]), b=довод(д[2]))
    if род in ДВУЧЛЕННЫЕ:
        имя = ДВУЧЛЕННЫЕ[род][и]
        return (f"{имя} {довод(д[1])} {СВЯЗКА[язык]} "
                f"{довод(д[2])}")
    raise ValueError(род)


_ИМЕНА = {}
for _з, _п in ДВУЧЛЕННЫЕ.items():
    if _з in ("/", "^"):
        continue
    _ИМЕНА[("en", _п[2])] = _з
    _ИМЕНА[("ru", _п[3])] = _з
_ОДНОЧЛЕН = {
    ("en", "the square root of"): "корень",
    ("ru", "квадратный корень из"): "корень",
    ("en", "the absolute value of"): "модуль",
    ("ru", "модуль"): "модуль",
}


def разобрать_слова(текст, язык):
    """Дерево из речевой поверхности, или None.

    Ход обратный `слова` и написанный отдельно от него: он не знает, КАК
    строилась речь, — он читает её по объявленным именам и скобкам.
    """
    т = текст.strip()
    try:
        д, хвост = _чит(т, язык)
    except (ValueError, IndexError):
        return None
    return д if not хвост.strip() else None


def _скобка(т):
    """(внутренность, хвост) для текста, начатого «( »."""
    if not т.startswith("( "):
        raise ValueError("не скобка")
    глубина, i = 0, 0
    while i < len(т):
        if т.startswith("( ", i):
            глубина += 1
            i += 2
            continue
        if т.startswith(" )", i):
            глубина -= 1
            i += 2
            if глубина == 0:
                return т[2:i - 2], т[i:]
            continue
        i += 1
    raise ValueError("скобка не закрыта")


def _довод(т, язык):
    т = т.lstrip()
    if т.startswith("( "):
        внутри, хвост = _скобка(т)
        д = разобрать_слова(внутри, язык)
        if д is None:
            raise ValueError("скобка не читается")
        return д, хвост
    м = re.match(r"(\d+|[A-Za-z_]\w*)", т)
    if not м:
        raise ValueError(f"не довод: {т[:20]}")
    знак = м.group(1)
    хвост = т[м.end():]
    return (чис(int(знак)) if знак.isdigit() else пер(знак)), хвост


def _чит(т, язык):
    т = т.lstrip()
    дробь = ("the fraction with numerator " if язык == "en"
             else "дробь с числителем ")
    знам = " and denominator " if язык == "en" else " и знаменателем "
    if т.startswith(дробь):
        лево, хвост = _довод(т[len(дробь):], язык)
        if not хвост.startswith(знам):
            raise ValueError("нет знаменателя")
        право, хвост = _довод(хвост[len(знам):], язык)
        return ("/", лево, право), хвост
    сумма = "the sum of " if язык == "en" else "сумма "
    для = " for " if язык == "en" else " по "
    от_ = " from " if язык == "en" else " от "
    до_ = " to " if язык == "en" else " до "
    if т.startswith(сумма):
        # СУММА РЯДА И СУММА ДВУХ РАЗЛИЧАЮТСЯ ХВОСТОМ, А НЕ ЗАЧИНОМ:
        # обе начинаются одним словом, и разбор обязан попробовать
        # ряд ПЕРВЫМ и честно отступить, если ряда нет.
        тело, хвост = _довод(т[len(сумма):], язык)
        if хвост.startswith(для):
            хвост = хвост[len(для):]
            м = re.match(r"([A-Za-z_]\w*)", хвост)
            if not м:
                raise ValueError("нет имени указателя")
            и, хвост = м.group(1), хвост[м.end():]
            if not хвост.startswith(от_):
                raise ValueError("нет начала")
            от, хвост = _довод(хвост[len(от_):], язык)
            if not хвост.startswith(до_):
                raise ValueError("нет конца")
            до, хвост = _довод(хвост[len(до_):], язык)
            return ("сумма", и, от, до, тело), хвост
    for (яз, имя), род in _ОДНОЧЛЕН.items():
        if яз != язык:
            continue
        если = имя + " "
        if т.startswith(если):
            д, хвост = _довод(т[len(если):], язык)
            return (род, д), хвост
    степень = " to the power " if язык == "en" else " в степени "
    for (яз, имя), знак in sorted(_ИМЕНА.items(),
                                  key=lambda п: -len(п[0][1])):
        if яз != язык:
            continue
        если = имя + " "
        if т.startswith(если):
            лево, хвост = _довод(т[len(если):], язык)
            связка = " " + СВЯЗКА[язык] + " "
            if not хвост.startswith(связка):
                raise ValueError("нет связки")
            право, хвост = _довод(хвост[len(связка):], язык)
            return (знак, лево, право), хвост
    функ = "the " if язык == "en" else ""
    лево, хвост = _довод(т, язык)
    if хвост.startswith(степень):
        право, хвост = _довод(хвост[len(степень):], язык)
        return ("^", лево, право), хвост
    if язык == "en" and т.startswith(функ):
        м = re.match(r"the (\w+) of ", т)
        if м:
            д, хвост = _довод(т[м.end():], язык)
            return ("функ", м.group(1), д), хвост
    if язык == "ru":
        м = re.match(r"(\w+) от ", т)
        if м:
            д, хвост = _довод(т[м.end():], язык)
            return ("функ", м.group(1), д), хвост
    return лево, хвост


# ------------------------------------------------- ОБРАТНЫЙ ХОД ЛАТЕХА

def _группа(т, i):
    r"""(содержимое {...}, позиция после), считая ВЛОЖЕННЫЕ скобки.

    Первая редакция понижала латех подстановкой `\{([^{}]*)\}` — и на
    вложенной сумме («\sum_{i=a}^{\sum_{...}}») образец не совпадал
    вовсе: триста восемь честных показов оказывались нечитаемыми. Скобка
    внутри скобки есть обычное дело записи, и читать её надо СЧЁТОМ
    ГЛУБИНЫ, а не образцом.
    """
    if i >= len(т) or т[i] != "{":
        raise ValueError("нет группы")
    глубина, j = 0, i
    while j < len(т):
        if т[j] == "{":
            глубина += 1
        elif т[j] == "}":
            глубина -= 1
            if глубина == 0:
                return т[i + 1:j], j + 1
        j += 1
    raise ValueError("группа не закрыта")


def латех_в_глиф(т):
    """LaTeX, понижённый в глифовую запись, — счётом скобок.

    Понижение записи в запись есть закон дома, а не приём суда: тем же
    ходом корпус понижает словесную арифметику в LaTeX, а LaTeX в глифы.
    """
    вон, i = [], 0
    while i < len(т):
        if т.startswith("\\frac{", i):
            верх, j = _группа(т, i + 5)
            низ, j = _группа(т, j)
            # ДРОБЬ ЗАКРЫВАЕТСЯ СНАРУЖИ, А НЕ ТОЛЬКО ВНУТРИ. «\\left| 6
            # \\right| \\cdot \\frac{12}{c}» понижалось в «abs ( 6 ) * (
            # 12 ) / ( c )», а это по старшинству есть ( abs(6) × 12 ) / c
            # — ДРУГАЯ формула. Дробь есть ОДИН довод и обязана выглядеть
            # одним доводом на любой глубине.
            вон.append(f"( ( {латех_в_глиф(верх)} ) / "
                       f"( {латех_в_глиф(низ)} ) )")
            i = j
            continue
        if т.startswith("\\sqrt{", i):
            тело, j = _группа(т, i + 5)
            вон.append(f"sqrt ( {латех_в_глиф(тело)} )")
            i = j
            continue
        сделано = False
        for имя in ("sin", "cos", "log"):
            если = "\\" + имя + "{"
            if т.startswith(если, i):
                тело, j = _группа(т, i + len(если) - 1)
                вон.append(f"{имя} ( {латех_в_глиф(тело)} )")
                i = j
                сделано = True
                break
        if сделано:
            continue
        if т.startswith("\\sum_{", i):
            низ, j = _группа(т, i + 5)
            if not т.startswith("^", j):
                raise ValueError("у суммы нет верха")
            верх, j = _группа(т, j + 1)
            while j < len(т) and т[j] == " ":
                j += 1
            тело, j = _группа(т, j)
            имя, _, от = низ.partition("=")
            вон.append(f"sum {имя} from {латех_в_глиф(от)} to "
                       f"{латех_в_глиф(верх)} of "
                       f"( {латех_в_глиф(тело)} )")
            i = j
            continue
        if т.startswith("^{", i):
            тело, j = _группа(т, i + 1)
            вон.append(f" ^ ( {латех_в_глиф(тело)} )")
            i = j
            continue
        for было, стало in (("\\left(", "("), ("\\right)", ")"),
                            ("\\left|", "abs ("), ("\\right|", ")"),
                            ("\\cdot", "*")):
            if т.startswith(было, i):
                вон.append(стало)
                i += len(было)
                break
        else:
            вон.append(т[i])
            i += 1
    return "".join(вон)


def разобрать_латех(т):
    """Дерево из записи LaTeX, или None."""
    try:
        return разобрать_глиф(латех_в_глиф(т))
    except (ValueError, IndexError):
        return None


def оракул(сколько=4000, глубина=4, семя=7):
    """[(дерево, чем)] — деревья, не вернувшиеся каким-либо ходом.

    ВОСЕМЬ ХОДОВ, ЧЕТЫРЕ ТУДА И ЧЕТЫРЕ ОБРАТНО, написаны отдельно друг
    от друга. Пустой список значит, что на всех проверенных деревьях
    каждая поверхность читается обратно В ТО ЖЕ дерево.
    """
    import random
    r = random.Random(семя)
    беды = []

    def построить(г):
        if г <= 0:
            return ((("чис", r.randint(1, 20))) if r.random() < 0.5
                    else ("пер", r.choice("abcxyz")))
        род = r.choice(["+", "-", "*", "/", "^", "=", "корень",
                        "модуль", "функ", "сумма"])
        if род == "корень":
            return ("корень", построить(г - 1))
        if род == "модуль":
            return ("модуль", построить(г - 1))
        if род == "функ":
            return ("функ", r.choice(["sin", "cos", "log"]),
                    построить(г - 1))
        if род == "сумма":
            return ("сумма", "i", построить(г - 1), построить(г - 1),
                    построить(г - 1))
        return (род, построить(г - 1), построить(г - 1))

    for _ in range(сколько):
        д = построить(r.randint(1, глубина))
        if разобрать_глиф(глиф(д)) != д:
            беды.append((д, "глиф"))
        if разобрать_латех(латех(д)) != д:
            беды.append((д, "латех"))
        for яз in ("en", "ru"):
            if разобрать_слова(слова(д, яз), яз) != д:
                беды.append((д, яз))
    return беды


def читается_вслух(д):
    """Возвращается ли дерево обеими инфиксными речами.

    ИНФИКСНАЯ РЕЧЬ ЧАСТИЧНА ПО ПРИРОДЕ, И ЭТО НЕ ИЗЪЯН ПРИБОРА.
    «the sum of a and b» описывает СТРОЕНИЕ и потому однозначно всегда;
    «a plus b over c» есть ЧТЕНИЕ ВСЛУХ, и человек на нём тоже
    переспрашивает. Слой произносит вслух только то, что возвращается
    обратно; доля таких деревьев названа числом (`доля_вслух`), а не
    спрятана за молчанием.
    """
    for яз in ("en", "ru"):
        try:
            if разобрать_инфикс(инфикс(д, яз), яз) != д:
                return False
        except (ValueError, IndexError, KeyError):
            return False
    return True


def доля_вслух(сколько=1500, глубина=4, семя=7):
    """(вернулось, всего) — какая доля деревьев читается вслух."""
    import random
    r = random.Random(семя)
    вернулось = 0

    def построить(г):
        if г <= 0:
            return ((("чис", r.randint(1, 12))) if r.random() < 0.5
                    else ("пер", r.choice("abcxyz")))
        род = r.choice(["+", "-", "*", "/", "^", "=", "корень",
                        "модуль"])
        if род in ("корень", "модуль"):
            return (род, построить(г - 1))
        return (род, построить(г - 1), построить(г - 1))

    for _ in range(сколько):
        вернулось += читается_вслух(построить(r.randint(1, глубина)))
    return вернулось, сколько


def значение(д):
    """Величина ЗАКРЫТОГО дерева, или None.

    Дерево со свободной переменной величины не имеет — и это не отказ
    прибора, а свойство выражения: «x + 1» не истинно и не ложно, оно
    ОТКРЫТО. Дробное и деление на ноль тоже дают None: слой, их
    показавший, обещал бы целое там, где его нет.
    """
    род = д[0]
    if род == "чис":
        return д[1]
    if род == "пер":
        return None
    if род == "модуль":
        в = значение(д[1])
        return None if в is None else abs(в)
    if род in ("корень", "функ", "сумма"):
        return None
    if род in ("+", "-", "*", "/", "^"):
        а, б = значение(д[1]), значение(д[2])
        if а is None or б is None:
            return None
        if род == "+":
            return а + б
        if род == "-":
            return а - б
        if род == "*":
            return а * б
        if род == "/":
            return а // б if б and а % б == 0 else None
        if род == "^":
            return а ** б if 0 <= б <= 6 else None
    return None


# ------------------------------------------------- ИНФИКСНАЯ РЕЧЬ
# ЧЕЛОВЕК ЧИТАЕТ ФОРМУЛУ ВСЛУХ ИНАЧЕ, ЧЕМ ЕЁ ОПИСЫВАЕТ. «the sum of a
# and b» — ОПИСАНИЕ строения; «a plus b» — ЧТЕНИЕ. Обе речи законны, и
# корпус, знавший лишь первую, не понял бы «x squared minus five x plus
# six equals zero» — а именно так уравнение и произносят. Инфиксная
# поверхность есть пятая грань того же дерева, со своим обратным ходом.
_ИНФИКС = {
    "en": {"+": "plus", "-": "minus", "*": "times", "/": "over",
           "=": "equals", "<": "is less than", ">": "is greater than"},
    "ru": {"+": "плюс", "-": "минус", "*": "умножить на",
           "/": "делить на", "=": "равно", "<": "меньше",
           ">": "больше"},
}
_КВАДРАТ = {"en": "squared", "ru": "в квадрате"}
_КУБ = {"en": "cubed", "ru": "в кубе"}
_СТЕПЕНЬ_ИНФ = {"en": "to the power of", "ru": "в степени"}
_КОРЕНЬ_ИНФ = {"en": "the square root of", "ru": "корень из"}
_МОДУЛЬ_ИНФ = {"en": "the modulus of", "ru": "модуль от"}
# ЧИСЛО ПРОИЗНОСИТСЯ ДОМОМ ЧИСЛИТЕЛЬНЫХ, А НЕ ТАБЛИЦЕЙ ЗДЕСЬ. Первая
# редакция держала свою дюжину слов — и «plus 15» звучало цифрой посреди
# речи. Дом уже умеет называть число по объявленной таблице пакета и
# читать имя обратно; второй список был бы третьей правдой о числах.
import numerals as _числ  # noqa: E402

_ТАБЛИЦЫ = {"en": _числ.таблица("en"), "ru": _числ.таблица("ru")}


def инфикс(д, язык, старше=-1):
    """Формула, ПРОЧИТАННАЯ вслух: «x squared minus five x plus six».

    Умножение числа на переменную произносится БЕЗ СЛОВА — «five x», а
    не «five times x»: так читают, и корпус обязан знать именно эту
    поверхность, иначе он не узнает уравнения на слух.
    """
    род = д[0]
    if род == "чис":
        имя = _числ.назвать(д[1], _ТАБЛИЦЫ[язык])
        return имя if имя else str(д[1])
    if род == "пер":
        return д[1]
    if род == "корень":
        return f"{_КОРЕНЬ_ИНФ[язык]} {инфикс(д[1], язык, 4)}"
    if род == "модуль":
        return f"{_МОДУЛЬ_ИНФ[язык]} {инфикс(д[1], язык, 4)}"
    if род == "^":
        основа = инфикс(д[1], язык, 4)
        сила = д[2]
        if сила[0] == "чис" and сила[1] == 2:
            return f"{основа} {_КВАДРАТ[язык]}"
        if сила[0] == "чис" and сила[1] == 3:
            return f"{основа} {_КУБ[язык]}"
        return (f"{основа} {_СТЕПЕНЬ_ИНФ[язык]} "
                f"{инфикс(сила, язык, 4)}")
    if род == "*" and д[1][0] == "чис" and д[2][0] in ("пер", "^"):
        # ЧИСЛО ПРИ ПЕРЕМЕННОЙ ПРОИЗНОСИТСЯ СЛИТНО: «five x».
        тело = f"{инфикс(д[1], язык)} {инфикс(д[2], язык, 3)}"
        return тело if СТАРШИНСТВО["*"] >= старше else f"( {тело} )"
    if род in ДВУЧЛЕННЫЕ:
        мой = СТАРШИНСТВО[род]
        тело = (f"{инфикс(д[1], язык, мой)} {_ИНФИКС[язык][род]} "
                f"{инфикс(д[2], язык, мой + 1)}")
        return f"( {тело} )" if мой < старше else тело
    return слова(д, язык)


def все_числа(текст, обратно):
    """Все ли слова отрывка суть объявленные числительные."""
    return bool(текст) and all(с.lower() in обратно
                               for с in текст.split())


def разобрать_инфикс(текст, язык):
    """Дерево из инфиксной речи, или None.

    Ход обратный `инфикс` и написанный отдельно: он читает слова как
    знаки по объявленной таблице и складывает их тем же старшинством,
    каким складывает глифы.
    """
    обратно = {с.lower(): n for n, с in _ТАБЛИЦЫ[язык].items()}
    знаки = {}
    for з, имя in _ИНФИКС[язык].items():
        знаки[имя] = з
    т = текст.strip()
    for имя, з in sorted(знаки.items(), key=lambda п: -len(п[0])):
        т = re.sub(rf"(?<![\w]){re.escape(имя)}(?![\w])", f" {з} ", т)
    т = re.sub(rf"(\S+) {re.escape(_КВАДРАТ[язык])}", r"\1 ^ 2", т)
    т = re.sub(rf"(\S+) {re.escape(_КУБ[язык])}", r"\1 ^ 3", т)
    т = т.replace(_СТЕПЕНЬ_ИНФ[язык], " ^ ")
    т = т.replace(_КОРЕНЬ_ИНФ[язык], " sqrt_ ")
    т = т.replace(_МОДУЛЬ_ИНФ[язык], " abs_ ")
    # СОСТАВНОЕ ЧИСЛИТЕЛЬНОЕ ЧИТАЕТСЯ ЦЕЛИКОМ: «twenty one» есть 21, а
    # не «20» и «1». Дом числительных складывает его законом разрядов.
    слова_ = т.split()
    куски, i = [], 0
    while i < len(слова_):
        взято = None
        for длина in (3, 2, 1):
            если = " ".join(слова_[i:i + длина])
            в = _числ.прочесть(если, _ТАБЛИЦЫ[язык])
            if в is not None and все_числа(если, обратно):
                взято = (в, длина)
                break
        if взято is not None:
            куски.append(str(взято[0]))
            i += взято[1]
            continue
        куски.append(слова_[i])
        i += 1
    т = " ".join(куски)
    # СЛИТНОЕ УМНОЖЕНИЕ ВОЗВРАЩАЕТ СВОЙ ЗНАК: «5 x» есть «5 * x».
    т = re.sub(r"(?<=\d) (?=[A-Za-zА-Яа-я_])", " * ", т)
    т = re.sub(r"sqrt_ ", "sqrt ( ", т)
    т = re.sub(r"abs_ ", "abs ( ", т)
    if "sqrt (" in т or "abs (" in т:
        т += " )" * (т.count("sqrt (") + т.count("abs ("))
    return разобрать_глиф(т)
