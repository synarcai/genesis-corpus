#!/usr/bin/env python3
"""РОДЫ И МЕРЫ ПОЛКИ: чем книга объявляется и чем она меряется.

Договор полки (`declarations/SHELF.md`) обратил условие владельца —
«чтобы не было нейрослопа и тексты были очень качественными» — в
признаки, исполнимые прибором. Здесь эти признаки живут кодом: закрытые
наборы, которыми книга ОБЪЯВЛЯЕТСЯ, и три меры, которыми она МЕРЯЕТСЯ.

ПЛОТНОСТЬ МЕРЯЕТСЯ ПРЕДЛОЖЕНИЯМИ, А НЕ СТРОКАМИ, И ЭТО КУПЛЕНО
ПРОМАХОМ. Первый замер считал долю СТРОК, несущих определение или
вывод, — и «Смысл жизни» Франка дал 72,8 % против 37,0 % у своего
плотнейшего свода. Разгадка не в тексте: страница Викитеки несёт абзац
в две с половиной тысячи знаков одной строкой, и всякая такая строка
несёт хоть один признак. Мера, зависящая от того, как чужой набор
переносит строки, меряет вёрстку. Предложение — единица самого текста.

ЗАМЕР 02.09 ПО СВОИМ СВОДАМ (доля предложений с признаком):

    mf_ru 23,6 %   msfs_en 21,2 %   uhm_en 14,5 %   msfs_ru 13,5 %
    uhm_ru 12,2 %  diakrisis_ru 6,0 %   verum_en 4,3 %

и по заведомо НЕплотному, взятому оттуда же, где берётся полка:

    «Каштанка» Чехова 3,7 %   «Кант и естествознание» Вернадского 4,3 %

Второе поучительнее первого: это не беллетристика, а очерк учёного о
науке — и он ПОВЕСТВУЕТ, а не доказывает. Мера отличила род речи, а не
предмет речи, и ради этого она и заведена.

ПОРОГ ЕСТЬ ПЛОТНОСТЬ САМОГО РЕДКОГО ИЗ НАЗВАННЫХ ПЛОТНЫМИ СВОДОВ —
шесть сотых. Полка не смеет быть реже того, что корпус уже держит; и
между нею и заведомо неплотным (3,7 % и 4,3 %) лежит зазор, а не
волосок.

СЛОВАРНАЯ НОВИЗНА СЧИТАЕТСЯ СВЕРХ ПРОЖИТОГО И СВЕРХ ЧУЖОГО. Слово,
уже стоящее в показах, куплено; слово, уже стоящее в другом своде
прозы, прочитано. Новизна книги есть то, чего нет НИ ТАМ, НИ ТАМ, — и
потому вторая копия одной книги (или второе издание того же труда)
принесёт ноль и будет названа.
"""

import re

# РУБЕЖ НЕЙРОСЛОПА: договор полки, раздел «отсеивается датой».
РУБЕЖ_МАШИНЫ = 2022
# ДОГОВОР: «PUBLIC DOMAIN ДО 1929 — чисто по определению».
РУБЕЖ_ОБЩЕСТВЕННОГО = 1929
# ЗАМЕР 02.09: плотность diakrisis_ru, самого редкого из своих плотных.
ПОРОГ_ПЛОТНОСТИ = 0.06
# Слово короче не берётся: тот же порог, что у охвата понятия, и по той
# же причине — трёх- и четырёхбуквенные обрывки суть служебные слова.
ДЛИНА_СЛОВА = 5

# НАБОР РАСТЁТ ПО СВИДЕТЕЛЬСТВУ, А НЕ ПО ДОГАДКЕ. «Научный метод»,
# «основания математики» и «метафизика» пришли с английской полки,
# набранной соседней рукой в тот же час, и все три там ЛЕЖАТ — Гершель,
# Лаплас, Кант, Спиноза. «Философия познания» взята ИМЕНЕМ ДОГОВОРА
# (образец в `declarations/SHELF.md`), и русские миры теории познания
# сведены к ней: два близких имени одного рода разошлись бы в первый же
# день, как всякий двойник.
ТЕМЫ = {
    "логика": "формы вывода и доказательства",
    "философия познания": "чем знание отличается от мнения",
    "научный метод": "как добывается и проверяется знание о природе",
    "метафизика": "что есть сущее и чем оно держится",
    "математика": "число, величина, пространство",
    "основания математики": "чем держится сама математика",
    "естествознание": "природа и её законы",
    "философия": "общие основания знания и жизни",
    "язык": "слово и его толкование: словари и грамматики",
}

ПЛОТНОСТИ = {
    # СЛОВАРЬ ПЛОТЕН ПО УСТРОЙСТВУ: каждая статья есть определение, и
    # мера плотности здесь не различает хорошее от плохого — ей нужна
    # своя мера (доля статей с примером, с этимологией, со ссылкой).
    "словарь": "статьи «слово — толкование»: определение в каждой строке",
    "трактат": "связное доказательное изложение целой книгой",
    "статья": "статья свода или журнала: короче трактата, не реже",
    "исследование": "разбор предмета по случаям, не по одной нити",
    "пересказ": "изложение чужого своими словами — на полку не кладём",
}

ИСТОЧНИКИ = {
    "public-domain": "права истекли; издано до рубежа общественного",
    "free-license": "издано до рубежа машины под свободной лицензией",
    "named-author": "издано после рубежа машины, автор назван человеком",
}

ЯЗЫКИ = {"ru": "русский", "en": "английский"}

# ПОЛЕ `язык` ДУБЛИРУЕТ СУЩЕСТВУЮЩЕЕ `lang`, И ЭТО ДЫРА ДОГОВОРА, А НЕ
# ПРИБОРА. Прозаические миры несут `lang` («msfs_en»: «lang»: «en») с
# первого дня; договор полки завёл рядом `язык`. Два имени одного факта
# суть два хозяина одного вопроса, и они разойдутся. Здесь берётся имя
# ДОГОВОРА — по нему уже набрана английская полка соседней рукой, и
# ломать её ради вкуса нельзя, — а дыра названа вслух: сводить два поля
# в одно есть дело хозяина договора, а не суда.
НАБОРЫ = (("тема", ТЕМЫ), ("плотность", ПЛОТНОСТИ),
          ("источник", ИСТОЧНИКИ), ("язык", ЯЗЫКИ))
# Поля, без которых мир полки есть «взято из интернета», а не книга.
# `автор` не здесь: договор требует названного человека лишь для
# изданного ПОСЛЕ рубежа машины, и требовать его от Гершеля 1830 года
# значило бы судить строже договора.
ПОЛЯ_ПОЛКИ = ("тема", "язык", "плотность", "издано", "источник",
              "происхождение", "held_out", "судится")

# ПРИЗНАКИ ПЛОТНОСТИ — на обоих языках корпуса, ибо на обоих написаны
# его своды. Признак широк нарочно: он ловит РОД РЕЧИ, а не отдельное
# утверждение, и одинаково завышен для всех, кого меряет.
ОПРЕДЕЛЕНИЕ = re.compile(
    r"(?:\bесть\b|\bсуть\b|\bназыва(?:ет|ют|ется|ются|емый)"
    r"|\bопределя(?:ет|ется|ем)|\bпонимает(?:ся)?\b|\bозначает\b"
    r"|\bпредставляет собой\b|—\s*это\b|\bопределение\b"
    r"|\bis\s+(?:a|an|the)\b|\bis\s+called\b|\bis\s+defined\b"
    r"|\bdenotes\b|\bmeans\b|\bwe\s+call\b|\bdefinition\b)", re.I)
ВЫВОД = re.compile(
    r"(?:\bследовательно\b|\bотсюда\b|\bтаким образом\b|\bпоэтому\b"
    r"|\bитак\b|\bстало быть\b|\bзначит\b|\bпотому что\b|\bибо\b"
    r"|\bесли\b.{0,80}\bто\b"
    r"|\bhence\b|\btherefore\b|\bthus\b|\bit follows\b|\bconsequently\b"
    r"|\bbecause\b|\bif\b.{0,80}\bthen\b)", re.I)
ССЫЛКА = re.compile(
    r"(?:\bпо теореме\b|\bпо определению\b|\bпо закону\b|\bсогласно\b"
    r"|\bв силу\b|\bсм\.|§|\bгл\.\s*\d|\bтеорем\w*\s+\d"
    r"|\bby theorem\b|\bby lemma\b|\bby definition\b|\bsee\s+(?:§|sec)"
    r"|\blemma\s+\d|\btheorem\s+\d)", re.I)
ПРИЗНАКИ = (("определение", ОПРЕДЕЛЕНИЕ), ("вывод", ВЫВОД),
            ("ссылка", ССЫЛКА))

КОНЕЦ_ПРЕДЛОЖЕНИЯ = re.compile(r'(?<=[.!?…])\s+(?=[«"(\[]?[А-ЯЁA-Z0-9])')
СЛОВО = re.compile(r"[^\W\d_]{%d,}" % ДЛИНА_СЛОВА, re.UNICODE)


def предложения(текст):
    """Предложения текста — единица, не зависящая от чужой вёрстки."""
    for строка in текст.splitlines():
        строка = строка.strip()
        if not строка:
            continue
        for кусок in КОНЕЦ_ПРЕДЛОЖЕНИЯ.split(строка):
            кусок = кусок.strip()
            if кусок:
                yield кусок


def плотность(текст):
    """(доля, предложений, {признак: сколько})."""
    все = list(предложения(текст))
    if не_пусто := len(все):
        счёт = {имя: 0 for имя, _ in ПРИЗНАКИ}
        несущих = 0
        for предложение in все:
            своё = False
            for имя, образец in ПРИЗНАКИ:
                if образец.search(предложение):
                    счёт[имя] += 1
                    своё = True
            несущих += своё
        return несущих / не_пусто, не_пусто, счёт
    return 0.0, 0, {имя: 0 for имя, _ in ПРИЗНАКИ}


# СЛОВАРЬ МЕРЯЕТСЯ СТАТЬЁЙ, А НЕ ПРЕДЛОЖЕНИЕМ. Признаки плотности прозы
# («определение», «вывод», «следствие») ищут слова, которыми проза
# объявляет своё определение; словарь их не пишет — он весь из
# определений и потому по прозаической мере выходит пустым (Webster
# 1913: 1.4% при пороге 6%). Единица словаря — СТАТЬЯ: заголовок
# капсом в начале строки, и толкование при нём — в той же строке
# (русские словари: «ЯЩИК м. …») или в следующих до нового заголовка
# («Defn:» и нумерованные значения у Webster). Плотность словаря есть
# доля статей, при которых толкование найдено.
ЗАГОЛОВОК_СТАТЬИ = re.compile(
    r"^([A-ZА-ЯЁ][A-ZА-ЯЁ'\-]+(?: [A-ZА-ЯЁ'\-]+)*)(?=[,.:;]| |$)")
# ОТСЫЛКА — ТОЖЕ ТОЛКОВАНИЕ: «АБДАЛ см. Абаим.» есть статья словаря,
# чьё толкование лежит по ссылке; у Даля таких 6084 из 71 123.
ТОЛКОВАНИЕ = re.compile(r"^(Defn:|\d+\.|см\.|See)\s|\w+\W+\w+\W+\w+")
# ПОРОГ — ПОЛОВИНА: единственная точка, которую не выбирают вкусом.
# Словарь есть текст, где статья ЧАЩЕ с толкованием, чем без; иначе
# это словник, а не словарь, и объявлять его толковым нельзя.
ПОРОГ_СЛОВАРЯ = 0.5


def статьи(текст):
    """[(заголовок, тело)] — статьи словаря по заголовкам капсом."""
    вон = []
    for строка in текст.splitlines():
        м = ЗАГОЛОВОК_СТАТЬИ.match(строка)
        if м and len(м.group(1)) > 1:
            вон.append([м.group(1), [строка[м.end():]]])
        elif вон:
            вон[-1][1].append(строка)
    return [(з, "\n".join(т)) for з, т in вон]


def плотность_словаря(текст):
    """(доля, статей, {признак: сколько}) — толкование при заголовке."""
    все = статьи(текст)
    счёт = {"толкование": 0, "этимология": 0}
    for _з, тело in все:
        тело = тело.strip()
        if ТОЛКОВАНИЕ.search(тело):
            счёт["толкование"] += 1
        if "Etym:" in тело or "этим." in тело.lower():
            счёт["этимология"] += 1
    if not все:
        return 0.0, 0, счёт
    return счёт["толкование"] / len(все), len(все), счёт


def мера(плотность_объявленная):
    """(мера, порог, единица) по объявленной плотности мира."""
    if плотность_объявленная == "словарь":
        return плотность_словаря, ПОРОГ_СЛОВАРЯ, "статей"
    return плотность, ПОРОГ_ПЛОТНОСТИ, "предл"


def слова(текст):
    """Слова длиной от порога, в нижнем регистре."""
    return {м.group().lower() for м in СЛОВО.finditer(текст)}
