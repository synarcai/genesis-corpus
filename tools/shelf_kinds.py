# РЕЧИ: единица текста, закрытая знаком конца (закон читателя: эпизод
# закрывается концевым знаком) и несущая хоть одно слово; оглавления,
# заголовки, списки глав и строки стиха без знака этой мерой не проходят.
# Реплика драмы «JUHANI.» — речь (Киви: 4 161 таких единиц из 8 632; порог
# в четыре слова звал бы роман-драму пустым). Мера не зависит от языка.
ПОРОГ_ПОВЕСТИ = 0.5
ЗНАК_КОНЦА = re.compile(r"[.!?…]['\"»)\]]?$")


# СТИХ МЕРЯЕТСЯ СТРОКОЙ МЕРНОЙ ДЛИНЫ: от двух до шестнадцати слов (замер
# 03.09: «Натан Мудрый» 0.91, проза Шиллера 0.56, Кафка 0.07 — прозу мера
# стиха не пропускает, и это её сила). Порог — семь десятых: у стиха строки
# ровны почти все, ремарки и имена говорящих — остаток.
ПОРОГ_СТИХА = 0.7
СЛОВ_В_СТРОКЕ_СТИХА = (2, 16)


def плотность_стиха(текст, язык=None):
    """(доля строк мерной длины, строк, {признак: сколько})."""
    строки = [l.strip() for l in текст.splitlines() if l.strip()]
    if не_пусто := len(строки):
        а, б = СЛОВ_В_СТРОКЕ_СТИХА
        мерных = sum(1 for l in строки if а <= len(СЛОВО.findall(l)) <= б)
        return мерных / не_пусто, не_пусто, {"мерных": мерных}
    return 0.0, 0, {"мерных": 0}


def плотность_повести(текст, язык=None):
    """(доля предложений речи, единиц, {признак: сколько})."""
    все = list(предложения(текст))
    if не_пусто := len(все):
        речь = sum(1 for п in все if ЗНАК_КОНЦА.search(п) and СЛОВО.search(п))
        return речь / не_пусто, не_пусто, {"речь": речь}
    return 0.0, 0, {"речь": 0}


# СЛОВАРЬ МЕРЯЕТСЯ СТАТЬЁЙ, А НЕ ПРЕДЛОЖЕНИЕМ. Признаки плотности прозы
# («определение», «вывод», «следствие») ищут слова, которыми проза
# объявляет своё определение; словарь их не пишет — он весь из
# определений и потому по прозаической мере выходит пустым (Webster
# 1913: 1.4% при пороге 6%). Единица словаря — СТАТЬЯ: заголовок
# капсом в начале строки, и толкование при нём — в той же строке
# (русские словари: «ЯЩИК м. …») или в следующих до нового заголовка
# («Defn:» и нумерованные значения у Webster). Плотность словаря есть
# доля статей, при которых толкование найдено.
ЗАГОЛОВОК_СТАТЬИ = re.compile(
    r"^([A-ZА-ЯЁ][A-ZА-ЯЁ'\-]+(?: [A-ZА-ЯЁ'\-]+)*)(?=[,.:;]| |$)")
# ОТСЫЛКА — ТОЖЕ ТОЛКОВАНИЕ: «АБДАЛ см. Абаим.» есть статья словаря,
# чьё толкование лежит по ссылке; у Даля таких 6084 из 71 123.
ТОЛКОВАНИЕ = re.compile(r"^(Defn:|\d+\.|см\.|See)\s|\w+\W+\w+\W+\w+")
# ПОРОГ — ПОЛОВИНА: единственная точка, которую не выбирают вкусом.
# Словарь есть текст, где статья ЧАЩЕ с толкованием, чем без; иначе
# это словник, а не словарь, и объявлять его толковым нельзя.
ПОРОГ_СЛОВАРЯ = 0.5


def статьи(текст):
    """[(заголовок, тело)] — статьи словаря по заголовкам капсом."""
    вон = []
    for строка in текст.splitlines():
        м = ЗАГОЛОВОК_СТАТЬИ.match(строка)
        if м and len(м.group(1)) > 1:
            вон.append([м.group(1), [строка[м.end():]]])
        elif вон:
            вон[-1][1].append(строка)
    return [(з, "\n".join(т)) for з, т in вон]


def плотность_словаря(текст):
    """(доля, статей, {признак: сколько}) — толкование при заголовке."""
    все = статьи(текст)
    счёт = {"толкование": 0, "этимология": 0}
    for _з, тело in все:
        тело = тело.strip()
        if ТОЛКОВАНИЕ.search(тело):
            счёт["толкование"] += 1
        if "Etym:" in тело or "этим." in тело.lower():
            счёт["этимология"] += 1
    if not все:
        return 0.0, 0, счёт
    return счёт["толкование"] / len(все), len(все), счёт


# ТЕЗАУРУС МЕРЯЕТСЯ ГНЕЗДОМ: «#1. Existence.—N. existence, being, …
# V. exist, be; … Adj. existing …» — заголовок номером и понятием,
# тело — ряды слов по частям речи. Гнездо без единого разряда части речи
# есть список, не тезаурус; плотность — доля гнёзд, несущих разряд.
ЗАГОЛОВОК_ГНЕЗДА = re.compile(r"^#(\d+[a-z]?)\. ([^.—]+)\.", re.M)
РАЗРЯД = re.compile(r"(?:^|[\s—])(N|V|Adj|Adv|Int|Phr|Pron|Prep|Conj)\. ")


def гнёзда(текст):
    """[(номер, понятие, тело)] тезауруса по заголовкам «#N. Понятие.»."""
    вон = []
    хвосты = ЗАГОЛОВОК_ГНЕЗДА.split(текст)
    # split даёт: [до, номер, понятие, тело, номер, понятие, тело, …]
    for i in range(1, len(хвосты) - 2, 3):
        вон.append((хвосты[i], хвосты[i + 1].strip(), хвосты[i + 2]))
    return вон


def плотность_тезауруса(текст):
    """(доля, гнёзд, {признак: сколько}) — разряд части речи в гнезде."""
    все = гнёзда(текст)
    счёт = {"разряд": 0, "ссылка": 0}
    for _н, _п, тело in все:
        if РАЗРЯД.search(тело):
            счёт["разряд"] += 1
        if "&c." in тело:
            счёт["ссылка"] += 1
    if not все:
        return 0.0, 0, счёт
    return счёт["разряд"] / len(все), len(все), счёт


def мера(плотность_объявленная, язык=None):
    """(мера, порог, единица) по объявленной плотности мира и его языку.

    Мера прозы мысли берёт признаки языка; язык без объявленных признаков
    (не ru/en и не в ПРИЗНАКИ_ЯЗЫКА) — отказ мерить, а не нуль: суд полки
    зовёт такой мир долгом объявления, не разладом дела."""
    if плотность_объявленная == "словарь":
        return плотность_словаря, ПОРОГ_СЛОВАРЯ, "статей"
    if плотность_объявленная == "тезаурус":
        return плотность_тезауруса, ПОРОГ_СЛОВАРЯ, "гнёзд"
    if плотность_объявленная == "повесть":
        return плотность_повести, ПОРОГ_ПОВЕСТИ, "речи"
    if плотность_объявленная == "стих":
        return плотность_стиха, ПОРОГ_СТИХА, "строк"
    if язык not in (None, "ru", "en") and язык not in ПРИЗНАКИ_ЯЗЫКА:
        return None, ПОРОГ_ПЛОТНОСТИ, "предл"
    return (lambda текст, я=язык: плотность(текст, я)), ПОРОГ_ПЛОТНОСТИ, "предл"


def слова(текст):
    """Слова длиной от порога, в нижнем регистре."""
    return {м.group().lower() for м in СЛОВО.finditer(текст)}


# ОДНО ОБЪЯВЛЕНИЕ МИРА ПОЛКИ НА ВСЕ ДОРОГИ. Кузница Gutenberg, дорога TeX,
# постатейные своды и сканы Викитеки писали узел манифеста каждая своей
# рукой — четыре копии одного договора (SHELF.md), расходившиеся полем
# за полем (имя с языком, жанр, размер). Договор пишется в одном месте,
# дороги подставляют лишь своё: откуда взято и чем читается.
def объявление_мира(имя, файл, жанр, язык, тема, плотность, издано,
                    происхождение, судится, размер=None,
                    источник="public-domain"):
    """Узел манифеста для мира полки — полями договора SHELF.md.

    `act`/`oracle`/`boundary` обязательны судом манифеста и берутся из
    закрытых наборов (tools/manifest_kinds.py) одними и теми же для всей
    прозы: трактат ИЗЛАГАЕТ, оракула у него нет, граница не названа.
    `held_out` — отложенная часть рядом с телом, по имени файла.
    """
    if тема not in ТЕМЫ or плотность not in ПЛОТНОСТИ or источник not in ИСТОЧНИКИ:
        raise ValueError(f"{имя}: объявление вне закрытых наборов полки "
                         f"({тема!r}, {плотность!r}, {источник!r})")
    узел = {
        "name": имя,
        "file": файл,
        "genre": жанр,
        "act": ["expound"],
        "oracle": ["none"],
        "boundary": ["unnamed"],
    }
    if размер is not None:
        узел["size"] = размер
    узел.update({
        "tiers": [],
        "text": "prose",
        "тема": тема,
        "язык": язык,
        "плотность": плотность,
        "издано": издано,
        "источник": источник,
        "происхождение": происхождение,
        "held_out": файл[:-len(".txt")] + ".holdout.txt",
        "судится": list(судится),
    })
    return узел
