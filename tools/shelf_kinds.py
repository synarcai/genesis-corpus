def предложения(текст):
    """Предложения текста — единица, не зависящая от чужой вёрстки."""
    for строка in текст.splitlines():
        строка = строка.strip()
        if not строка:
            continue
        for кусок in КОНЕЦ_ПРЕДЛОЖЕНИЯ.split(строка):
            кусок = кусок.strip()
            if кусок:
                yield кусок


def плотность(текст, язык=None):
    """(доля, предложений, {признак: сколько}) — признаками языка мира;
    ru/en — общие признаки корпуса, прочие — из ПРИЗНАКИ_ЯЗЫКА."""
    признаки = ПРИЗНАКИ_ПО_ЯЗЫКУ.get(язык, ПРИЗНАКИ)
    все = list(предложения(текст))
    if не_пусто := len(все):
        счёт = {имя: 0 for имя, _ in признаки}
        несущих = 0
        for предложение in все:
            своё = False
            for имя, образец in признаки:
                if образец.search(предложение):
                    счёт[имя] += 1
                    своё = True
            несущих += своё
        return несущих / не_пусто, не_пусто, счёт
    return 0.0, 0, {имя: 0 for имя, _ in признаки}


