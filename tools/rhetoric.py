#!/usr/bin/env python3
"""СВОД ФОРМ РЕЧИ И ИХ СТЫКОВ — третья мера рядом с судимостью и полнотой.

СУДИМОСТЬ говорит, что каждую строку кто-то читает. ПОЛНОТА говорит,
что всякий предмет оснований в корпусе есть. Ни одна не говорит, умеет
ли корпус СОЕДИНЯТЬ — а речь есть соединение, и рассуждение есть речь.

ФОРМА И ПРЕДМЕТ РАЗЛИЧАЮТСЯ ИСПОЛНЕНИЕМ (критерий holon-e2, взят
дословно): ПРЕДМЕТ — то, у чего своя таблица фактов, и суд читает
ФАКТЫ. ФОРМА — то, чьё исполнение берёт операндом ВЕРДИКТ ПОД-СУДА, а
не факты. Оттого модальность, квантор с областью и связка рассуждения
суть формы, а не предметы: «все P суть Q» исполняется пробегом по
фактам P с ПОД-СУДОМ Q.

ФОРМЫ РАСТУТ ЛИНЕЙНО, РЕЧЬ — СТЫКАМИ. Двадцать форм дают двадцать
умений и четыреста возможных пар; речь живёт в парах, а не в списке.
Потому вторая ось свода — СТЫКИ, и ориентация в них значима: «значит»
над анафорой и анафора над «значит» суть разные умения.

ПРОБА, НЕДОСЧИТЫВАЮЩАЯ СУЩЕСТВУЮЩЕЕ, ЛЖЁТ О ПРОБЕЛЕ — и солгала здесь
дважды в первый же час: «\bтезис:\b» требует буквы сразу за двоеточием,
а там пробел; стык «следование над анафорой» искал местоимение ПЕРЕД
«значит», тогда как оно стоит внутри следствия. Оба предмета лежали в
корпусе сотнями строк. Всякий нуль проверяется глазами ПРЕЖДЕ, чем
становится задачей.

ЧЕГО ЭТОТ СВОД НЕ ГОВОРИТ, И ЭТО ОБЪЯВЛЕНО ЗДЕСЬ, А НЕ СПРЯТАНО:
он мерит ОДИН столбец из трёх — ПОКАЗАНО (масса формы в корпусе).
Два других — КУПЛЕНО (рынок родил стор) и ИСПОЛНЕНО (дорога и
порождает, и судит) — живут на стороне организма и меряются там
(omega-e9, holon-e2). ПОКАЗАННОЕ ЕСТЬ ВЕРХНЯЯ ГРАНИЦА КУПЛЕННОГО И НЕ
БОЛЕЕ ТОГО: замер e9 говорит, что вне купленных родов организм нем
полностью — шестьдесят из шестидесяти пяти. Мера на входе не вправе
выдавать себя за меру на выходе.
"""

import collections

Форма = collections.namedtuple("Форма", "имя зачем проба масса")
Стык = collections.namedtuple("Стык", "верх низ зачем проба масса")

# ФОРМЫ. Масса учебная: форма, показанная трижды, не выучена.
ФОРМЫ = (
    Форма("анафора",
          "местоимение вместо имени — связь ЧЕРЕЗ предложение",
          r"\. (?:она|он|они) |\. (?:she|he|they) ", 40),
    Форма("связка следования",
          "«значит» — заключение, обязанное следовать из посылки",
          r"\bзначит\b|\btherefore\b|\bhence\b", 40),
    Форма("связка причины",
          "«потому что» — причина, объявленная и сверяемая",
          r"потому что|\bbecause\b", 20),
    Форма("связка уступки",
          "«хотя» — побеждённое ожидание по умолчанию",
          r"\bхотя\b|\balthough\b|\bthough\b", 20),
    Форма("придаточное определительное",
          "предикат внутри имени: «число, которое делится на 3»",
          r", котор\w+ |\bthat is divisible\b|\bwhich is\b", 20),
    Форма("квантор всеобщности",
          "«все P суть Q» — пробег по области с под-судом",
          r"\bвсе числа\b|\ball of\b|\bevery whole number\b", 20),
    Форма("квантор отрицания",
          "«ни один P не Q» — пробег с отрицанием",
          r"ни одно из|\bnone of\b|\bno \w+ is\b", 20),
    Форма("квантор существования",
          "«хотя бы один» — свидетель вместо пробега",
          r"хотя бы один|некоторые|\bat least one\b|\bsome \w+ are\b", 20),
    Форма("номинализация",
          "действие, названное предметом: «сложение 2 и 3»",
          r"\bсложение \d|\bумножение \d|\bthe addition of\b"
          r"|\bthe multiplication of\b", 20),
    Форма("модальность возможности",
          "«может» — существует продолжение, где утверждение стоит",
          r"\bможет быть\b|\bcan be\b|\bmay be\b", 20),
    Форма("модальность долженствования",
          "«должен» — во всех допущенных продолжениях",
          r"\bдолжен\b|\bобязан\b|\bmust be\b", 20),
    Форма("достаточное условие",
          "«A достаточно для B» — убивается одним A и не-B",
          r"достаточно для|\bis sufficient for\b", 20),
    Форма("необходимое условие",
          "«A необходимо для B» — убивается одним не-A и B",
          r"необходим\w+ для|\bis necessary for\b|не необходим", 20),
    Форма("условие если-то",
          "«если A, то B» — связка, истинностно-функциональная",
          r"\bесли\b.*\bто\b|\bif\b.*\bthen\b", 40),
    Форма("сравнение",
          "«больше», «меньше», «во сколько раз» — отношение величин",
          r"\bбольше\b|\bменьше\b|\bmore than\b|\bfewer than\b"
          r"|\btimes as many\b", 40),
    Форма("отрицание",
          "«не» как операция над утверждением, а не как слово",
          r"\bне чётно\b|\bis not even\b|\bне делится\b"
          r"|\bnot divisible\b", 20),
    Форма("перечисление",
          "ряд, названный союзом: «2, 4 и 6»",
          r"\d+, \d+ (?:и|and) \d+|\d+ (?:и|and) \d+", 40),
    Форма("вопрос к части",
          "«сколько», «какой» — вопрос об одной доле факта",
          r"\bсколько\b|\bкакой\b|\bhow many\b|\bwhat is\b", 40),
    # ЦЕПЬ ЕСТЬ ФОРМА, А НЕ СЛОВО «ВЕДЁТ К» (05.09): живой свод показывает цепи шагами —
    # «шаг 1: 12 + 5 = 17. шаг 2: 17 − 3 = 14. итог: 14.» (дом SVAMP, две длины одного
    # рода) — каждый шаг опирается на выведенное предыдущим; слово «ведёт к» жило в
    # легаси-мирах v0–v6, которых в манифесте нет
    Форма("цепь рассуждения",
          "три и более шага, каждый опирается на выведенное",
          r"ведёт к .*\. .*ведёт к |leads to .*\. .*leads to |шаг 1: .*шаг 2: |step 1: .*step 2: ", 20),
    Форма("тезис и вывод",
          "заявленное утверждение и шаги, ведущие ИМЕННО к нему",
          r"\bтезис: |\bthesis: |\bитог: |\bhence: ", 20),
)

# СТЫКИ. Масса КОНТРОЛЬНАЯ, а не учебная: композиция купленных форм
# есть ВЫВОД, а не заучивание (holon-e2), и покупки глубины 2 не
# существует. Проб довольно одной-двух на стык — мало, но вечно; они
# нужны прибору, чтобы отличить живой стык от мёртвого, а не рынку.
СТЫКИ = (
    Стык("связка следования", "анафора",
         "«У Веры 6 яблок. Значит у неё чётное число»",
         r"\bзначит\b[^.]*(?:у неё|у него|она |он )"
         r"|\btherefore\b[^.]*\b(?:he|she)\b", 2),
    Стык("квантор всеобщности", "придаточное определительное",
         "«все числа, которые делятся на 4, чётны»",
         r"все числа, котор\w+|all numbers that are", 2),
    Стык("связка следования", "связка следования",
         "два вывода подряд: A значит B, B значит C",
         r"\bзначит\b[^.]*\.[^.]*\bзначит\b"
         r"|\btherefore\b[^.]*\.[^.]*\btherefore\b", 2),
    Стык("отрицание", "квантор всеобщности",
         "«не все P суть Q» — отрицание над квантором",
         r"не все \w+|\bnot all \w+", 2),
    Стык("анафора", "перечисление",
         "местоимение, отсылающее к ряду: «они все чётны»",
         r"\. они\b|\. they are\b", 2),
    Стык("модальность возможности", "квантор существования",
         "«может быть, что хотя бы один…»",
         r"может быть, что|\bit may be that\b", 2),
)

assert len({ф.имя for ф in ФОРМЫ}) == len(ФОРМЫ), "форма названа дважды"
ИМЕНА = {ф.имя for ф in ФОРМЫ}
for _с in СТЫКИ:
    assert _с.верх in ИМЕНА, _с.верх
    assert _с.низ in ИМЕНА, _с.низ
