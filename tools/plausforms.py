#!/usr/bin/env python3
"""ДОМ ПРАВДОПОДОБИЯ — СЧЁТ СОШЁЛСЯ, А ОТВЕТ НЕВОЗМОЖЕН.

    ПРОВЕРКИ ОТВЕТА НА ПРАВДОПОДОБИЕ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 247 мирам
    показов: «может ли быть», «правдоподобн», «plausible» — НОЛЬ. Мир прикидки считает
    приблизительно, мир фактов объявляет факты, мир достаточности решает, хватит ли денег, — и
    ни один не спрашивает, ВОЗМОЖЕН ЛИ ВООБЩЕ полученный ответ.

ДЕВЯТНАДЦАТАЯ ЛОВУШКА РЯДА, И ОНА РОДНАЯ СЕСТРА ТРИНАДЦАТОЙ: ученик, весящий триста килограммов,
получается из совершенно верного счёта. Дом остатка показал равенство, которое сходится при
неверном ответе; здесь сходится ВСЁ, а ответ невозможен по существу вещи.

    ПРОВЕРКА СЧЁТА НЕ ЕСТЬ ПРОВЕРКА ОТВЕТА: ЧИСЛО МОЖЕТ БЫТЬ ВЕРНЫМ И НЕВОЗМОЖНЫМ РАЗОМ.

ЧЕТЫРЕ РОДА:

    правдоподобно  ученик весит 30 килограммов, и это правдоподобно: 30 больше 10,
                   и 30 меньше 100.
    слишком много  ученик не может весить 300 килограммов: 300 ÷ 30 = 10, и это вес
                   десяти учеников.                                          ← ЛОВУШКА
    слишком мало   ученик не может весить 3 килограмма: 30 ÷ 3 = 10, и это десятая доля
                   ученика.
    счёт сошёлся   счёт сошёлся, а ответ невозможен: 15 × 20 = 300, и 300 больше 100.
                                                                             ← ЗАКОН ДОМА

ГРАНИЦЫ ВЕЩЕЙ ОБЪЯВЛЕНЫ ТАБЛИЦЕЙ, А НЕ ВЫВЕДЕНЫ, И ЭТО НАЗВАНО ВСЛУХ. Сколько весит ученик и
сколько детей бывает в классе — знание о мире, а не следствие счёта; вывести его неоткуда, и дом
не притворяется, будто выводит. Тем же законом живут счётные тройки русского языка в `rugram` и
имена долей: ФАКТ, КОТОРЫЙ НЕЛЬЗЯ ВЫВЕСТИ, ОБЪЯВЛЯЮТ ПОИМЁННО.

    ГРАНИЦА, ВЗЯТАЯ ИЗ МИРА, ЧЕСТНЕЕ ГРАНИЦЫ, ВЗЯТОЙ ИЗ ВОЗДУХА, ЕСЛИ О НЕЙ СКАЗАНО, ОТКУДА
    ОНА ВЗЯТА.

ЧЕТВЁРТЫЙ РОД ЕСТЬ САМ ЗАКОН, ПОКАЗАННЫЙ ДЕЛОМ: счёт выписан целиком и верен, и рядом стои́т
сравнение с границей, которое его отвергает. Без него три первых были бы разрозненными заметками
о вещах, а не правилом проверки.

    python3 tools/plausforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётные формы мер и вещей объявлены там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("правдоподобно", "слишком много", "слишком мало", "счёт сошёлся")

# ВЕЩИ, ИХ МЕРЫ И ГРАНИЦЫ — ЗНАНИЕ О МИРЕ, ОБЪЯВЛЕННОЕ ПОИМЁННО. Границы взяты широкие: дом
# учит не точному весу ученика, а тому, что у всякой величины есть предел возможного.
ВЕЩИ = (
    # ключ вещи, ключ меры, обычное, нижняя граница, верхняя граница
    ("ученик", "килограмм", 30, 10, 100),
    ("ребёнок", "год", 9, 1, 18),
    ("книга", "страница", 200, 10, 1000),
    ("ученик", "рубль", 100, 1, 1000),
    ("ученик", "шаг", 60, 10, 200),
    ("ребёнок", "час", 9, 1, 16),
    ("книга", "рубль", 300, 10, 3000),
    ("ученик", "год", 12, 6, 18),
)
# ВЕЩИ ВЗЯТЫ ТОЛЬКО ОБЪЯВЛЕННЫЕ В СЧЁТНОЙ ТАБЛИЦЕ ЯЗЫКА. Первая редакция взяла «комнату», которой
# в `rugram` нет, и ковка легла с KeyError: дом не вправе писать русское склонение сам.
#
#     ДОМ, КОТОРОМУ НУЖНО НЕОБЪЯВЛЕННОЕ СЛОВО, ВЫБИРАЕТ МЕЖДУ ДВУМЯ ЧЕСТНЫМИ ХОДАМИ: ВЗЯТЬ
#     ДРУГОЕ СЛОВО ИЛИ ОБЪЯВИТЬ ЭТО В ЯЗЫКЕ. ТРЕТЬЕГО — НАПИСАТЬ ОКОНЧАНИЕ РУКОЙ — НЕТ.
АНГЛ = {"ученик": ("pupil", "pupils"), "ребёнок": ("child", "children"),
        "книга": ("book", "books"), "килограмм": ("kilogram", "kilograms"),
        "год": ("year", "years"), "страница": ("page", "pages"),
        "рубль": ("rouble", "roubles"), "шаг": ("step", "steps"),
        "час": ("hour", "hours")}
ДЕЛО = {"килограмм": ("весит", "weighs"), "год": ("прожил", "has lived"),
        "страница": ("несёт", "holds"), "рубль": ("стоит", "costs"),
        "шаг": ("делает", "makes"), "час": ("спит", "sleeps")}


def форма(язык, ключ, n):
    if язык == "en":
        один, много = АНГЛ[ключ]
        return один if n == 1 else много
    return rugram.форма(ключ, n)


РАМКИ = {
    "ru": {
        "правдоподобно": "{вещь} {дело} {n} {мера}, и это правдоподобно: {n} больше {низ}, и {n} меньше {верх}.",
        "слишком много": "{вещь} не может {делоинф} {много} {мера_м}, ибо это {раз} обычных: {много} ÷ {n} = {раз}.",
        "слишком мало": "{вещь} не может {делоинф} {мало} {мера_мало}, ибо это в {разм} {кратно} меньше обычного: {n} ÷ {мало} = {разм}.",
        "счёт сошёлся": "счёт сошёлся, а ответ невозможен: {a} × {b} = {много}, и {много} больше {верх}.",
    },
    "en": {
        "правдоподобно": "a {вещь} {дело} {n} {мера}, and that is plausible: {n} is greater than {низ}, and {n} is less than {верх}.",
        "слишком много": "a {вещь} cannot {делоинф} {много} {мера_м}, for that is {раз} usual ones: {много} ÷ {n} = {раз}.",
        "слишком мало": "a {вещь} cannot {делоинф} {мало} {мера_мало}, for that is {разм} times less than usual: {n} ÷ {мало} = {разм}.",
        "счёт сошёлся": "the counting adds up and the answer is impossible: {a} × {b} = {много}, and {много} is greater than {верх}.",
    },
}
ИНФИНИТИВ = {"весит": "весить", "прожил": "прожить", "несёт": "нести",
             "стоит": "стоить", "делает": "делать", "спит": "спать"}
ПУСТО = dict(вещь="", вещь_р="", дело="", делоинф="", n=0, мера="", мера_м="", мера_мало="",
             низ=0, верх=0, много=0, мало=0, раз=0, разм=0, a=0, b=0, кратно="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for вещь, мера, n, низ, верх in ВЕЩИ:
            дело = ДЕЛО[мера][0 if язык == "ru" else 1]
            делоинф = ИНФИНИТИВ[дело] if язык == "ru" else дело.split()[0]
            общ0 = dict(ПУСТО, вещь=форма(язык, вещь, 1), вещь_р=форма(язык, вещь, 2),
                        дело=дело, делоинф=делоинф, низ=низ, верх=верх)
            for k in range(1, 26):
                # ОБЫЧНОЕ ЗНАЧЕНИЕ СДВИГАЕТСЯ В ПРЕДЕЛАХ ГРАНИЦ, и каждая страница берёт своё.
                свой = n + k * max(1, n // 10)
                if not низ < свой < верх:
                    continue
                много = свой * (10 + k % 3)
                # МАЛОЕ БЕРЁТСЯ ДЕЛИТЕЛЕМ, А НЕ ЧАСТНЫМ ОТ ДЕСЯТИ: при делении с остатком
                # страница сказала бы «в 11 раз меньше», не будучи в 11 раз меньше. Первый
                # перебор давал роду пять страниц на язык против пятидесяти у соседей.
                делители = [d for d in range(1, свой) if свой % d == 0 and d < низ]
                мало = делители[-1] if делители else 0
                if not мало:
                    continue
                # СЧЁТНАЯ ФОРМА «РАЗА» БЕРЁТСЯ У ЯЗЫКА, А НЕ ПИШЕТСЯ РУКОЙ. Первая редакция
                # поставила «в 4 раз меньше» — и палата назвала двенадцать страниц ложью устами
                # суда русского счёта. СВОЙ ЖЕ ПРИБОР ПОЙМАЛ КОВКУ НА ЯЗЫКЕ, И ЭТО ЕГО ДЕЛО.
                общ = dict(общ0, n=свой, мера=форма(язык, мера, свой),
                           кратно=("times" if язык == "en" else rugram.форма("раз",
                                                                            свой // мало)),
                           мера_м=форма(язык, мера, много), мера_мало=форма(язык, мера, мало),
                           много=много, мало=мало, раз=много // свой,
                           разм=свой // мало)
                вон[рамки["правдоподобно"].format(**общ)] = (язык, "правдоподобно")
                if много > верх and много % свой == 0:
                    вон[рамки["слишком много"].format(**общ)] = (язык, "слишком много")
                if свой // мало > 1:
                    вон[рамки["слишком мало"].format(**общ)] = (язык, "слишком мало")
                # СЧЁТ СОШЁЛСЯ: произведение выписано верно и выходит за границу вещи.
                for a in range(2, 8):
                    if много % a == 0 and много > верх:
                        вон[рамки["счёт сошёлся"].format(
                            **dict(общ, a=a, b=много // a))] = (язык, "счёт сошёлся")
                        break
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_БОЛЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:больше|is greater than) (\d+)(?![/\d])")
_МЕНЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:меньше|is less than) (\d+)(?![/\d])")
_НЕВОЗМОЖЕН = re.compile(r"(?:ответ невозможен|the answer is impossible)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    for a, b in _МЕНЬШЕ.findall(с):
        if int(a) >= int(b):
            return True, False
    # ЗАКОН ДОМА ПРОВЕРЯЕТСЯ ДЕЛОМ: на странице «счёт сошёлся» произведение обязано быть
    # ВЕРНЫМ и обязано ВЫЙТИ за объявленную границу — иначе страница не о том.
    if _НЕВОЗМОЖЕН.search(с):
        произв = _ПРОИЗВ.findall(с)
        больше = _БОЛЬШЕ.findall(с)
        if not произв or not больше:
            return True, False
        if int(произв[0][2]) != int(больше[0][0]):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:92]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    сс = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "счёт сошёлся")
    пр = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "правдоподобно")
    for страница, слово, куда in ((сс, "невозможен", "невозможе"),
                                  (пр, "правдоподобно", "правдоподобн")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(сс + " " + сс)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # ГРАНИЦЫ ОБЪЯВЛЕНЫ И НЕПУСТЫ: вещь без границ показывать нечем.
    for вещь, мера, n, низ, верх in ВЕЩИ:
        if not низ < n < верх:
            беды.append(f"обычное вне границ: {вещь} {n} ∉ ({низ}, {верх})")
    # СЛОВА ДО ДВОЕТОЧИЯ, РАВЕНСТВА ПОСЛЕ.
    for с in ПОКАЗЫ:
        хвост = с.rsplit(":", 1)[1]
        чистый = хвост
        for слово in ("and", "и ", "больше", "меньше", "greater", "than", "less", "is"):
            чистый = чистый.replace(слово, "")
        if re.search(r"[A-Za-zА-Яа-яЁё]{4,}", чистый):
            беды.append(f"СЛОВА ПОСЛЕ ДВОЕТОЧИЯ: {с[:74]}")
            break
    print(f"ПРАВДОПОДОБИЕ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
