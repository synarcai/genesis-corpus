_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_БОЛЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:больше|is greater than) (\d+)(?![/\d])")
_МЕНЬШЕ = re.compile(r"(?<![/\d])(\d+) (?:меньше|is less than) (\d+)(?![/\d])")
_НЕВОЗМОЖЕН = re.compile(r"(?:невозможен|is impossible)")
_ЧИСЛО = re.compile(r"(?<![\d.])\d+(?![\d.])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b in _БОЛЬШЕ.findall(с):
        if int(a) <= int(b):
            return True, False
    for a, b in _МЕНЬШЕ.findall(с):
        if int(a) >= int(b):
            return True, False
    # ЗАКОН ДОМА ПРОВЕРЯЕТСЯ ДЕЛОМ: на странице «счёт сошёлся» произведение обязано быть
    # ВЕРНЫМ и обязано ВЫЙТИ за объявленную границу — иначе страница не о том.
    if _НЕВОЗМОЖЕН.search(с):
        произв = _ПРОИЗВ.findall(с)
        больше = _БОЛЬШЕ.findall(с)
        if not произв or not больше:
            return True, False
        if int(произв[0][2]) != int(больше[0][0]):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def граница_сказана(с):
    """Беды страницы, которая сравнивает с тем, чего не сказала.

    ЧИСЛО, С КОТОРЫМ СРАВНИВАЮТ ИЛИ КОТОРОЕ ДЕЛЯТ, СТОИТ В ТЕКСТЕ ДО ДВОЕТОЧИЯ: операнды первого
    равенства и правая сторона всякого сравнения названы словами страницы, а не взяты из таблицы
    дома молча.
    """
    голова, хвост = с.rsplit(":", 1)
    сказано = set(_ЧИСЛО.findall(голова))
    беды = []
    равенство = _ПРОИЗВ.search(хвост) or _ЧАСТНОЕ.search(хвост)
    if равенство and not {равенство.group(1), равенство.group(2)} <= сказано:
        беды.append(f"операнды не сказаны: {равенство.group(0)}")
    for _, b in _БОЛЬШЕ.findall(хвост) + _МЕНЬШЕ.findall(хвост):
        if b not in сказано:
            беды.append(f"граница не сказана: {b}")
    return беды


