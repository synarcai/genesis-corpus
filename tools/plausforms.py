def _мера(язык, мера, n):
    return f"{n} {units.рус(мера, n) if язык == 'ru' else units.англ(мера, много=n != 1)}"


def _вещи(язык, вещь, k):
    ru, en = вещь
    return f"{k} {rugram.форма(ru, k) if язык == 'ru' else plural.by_count(k, _ИМЕНА_EN[en])}"


def _правдоподобные(в):
    шаг = max(1, в["обычное"] // 10)
    return sorted({в["обычное"] + j * шаг for j in range(-25, 26)
                   if в["от"] < в["обычное"] + j * шаг < в["до"]})


def _промежуток(язык, в):
    слова = ("больше", "и меньше") if язык == "ru" else ("more than", "and less than")
    return f"{слова[0]} {в['от']} {слова[1]} {_мера(язык, в['мера'], в['до'])}"


def _раз(язык, k):
    return rugram.форма("раз", k) if язык == "ru" else "times"


