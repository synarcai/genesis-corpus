def _сошёлся(язык, в):
    """Страницы закона дома: умножено там, где нужно делить, и итог вышел за целое."""
    р = в[язык]
    вон = []
    for i, v in enumerate(_правдоподобные(в)):
        if в.get("период"):
            граница = units.отношение(в["период"], в["мера"])
            for k in ПЕРИОДЫ:
                всего = v * k
                вон.append(dict(итог=р["за"].format(n=_мера(язык, в["мера"], всего),
                                                   k=_мера(язык, в["период"], k)),
                                целое=unitforms.сказать_отношение(язык, в["период"], в["мера"]),
                                всего=всего, k=k, граница=int(граница)))
        elif в.get("вместе"):
            # ОДНО ЧИСЛО ВЕЩЕЙ НА ПРАВДОПОДОБНОЕ ЗНАЧЕНИЕ, ПЕРЕБОРОМ ПО КРУГУ: вес на все
            # одиннадцать чисел дал бы роду вдесятеро больше страниц, чем прочим вещам.
            k = ПЕРИОДЫ[i % len(ПЕРИОДЫ)]
            всего = v * k
            вон.append(dict(итог=р["итог"].format(k=_вещи(язык, в["вещь"], k),
                                                  n=_мера(язык, в["мера"], всего)),
                            целое=р["часть"].format(k=_вещи(язык, в["вещь"], k)),
                            всего=всего, k=k, граница=всего))
    for д in вон:
        д["много"] = д["всего"] * д["k"]
        д["ответ"] = р["есть"].format(об="", n=_мера(язык, в["мера"], д["много"]))
    return [д for д in вон if д["много"] > д["граница"]]


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for в in ВЕЩИ:
            р = в[язык]
            пусто = dict(в=(" " + р["в"]) if р.get("в") else "", от=в["от"], до=в["до"],
                         об=в["обычное"])
            обычно = р["есть"].format(об=ОБЫЧНО[язык], n=_мера(язык, в["мера"], в["обычное"]))
            for v in _правдоподобные(в):
                с = рамки["правдоподобно"].format(
                    **пусто, v=v, n=_мера(язык, в["мера"], v),
                    обычно=р["есть"].format(об=ОБЫЧНО[язык], n=_промежуток(язык, в)))
                вон[с] = (язык, "правдоподобно")
            for раз in РАЗЫ_МНОГО:
                много = в["обычное"] * раз
                с = рамки["слишком много"].format(
                    **пусто, обычно=обычно, нет=р["нет"].format(n=_мера(язык, в["мера"], много)),
                    раз=раз, разы=_раз(язык, раз), много=много)
                вон[с] = (язык, "слишком много")
            if в["снизу"]:
                for мало in range(1, в["обычное"]):
                    раз = в["обычное"] // мало
                    if в["обычное"] % мало or раз < ПОРОГ_НЕВОЗМОЖНОГО:
                        continue
                    с = рамки["слишком мало"].format(
                        **пусто, обычно=обычно,
                        нет=р["нет"].format(n=_мера(язык, в["мера"], мало)),
                        раз=раз, разы=_раз(язык, раз), мало=мало)
                    вон[с] = (язык, "слишком мало")
            for д in _сошёлся(язык, в):
                вон[рамки["счёт сошёлся"].format(**д)] = (язык, "счёт сошёлся")
    return вон


ПОКАЗЫ = страницы()
