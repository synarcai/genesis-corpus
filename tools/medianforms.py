    # ВСЕ СРЕДНИЕ ЦЕЛЫЕ — И ДО ЗАМЕНЫ, И ПОСЛЕ ОБЕИХ.
    for ряд in РОВНЫЕ:
        if ряд not in ВЫБРОСЫ:
            беды.append(f"ряд без выброса: {ряд}")
            continue
        в, в2 = ВЫБРОСЫ[ряд]
        for р in (ряд, ряд[:-1] + (в,), ряд[:-1] + (в2,)):
            if sum(р) % len(р):
                беды.append(f"среднее не целое: {р}")
        if len(ряд) % 2 == 0:
            беды.append(f"ряд чётной длины, медиана неоднозначна: {ряд}")
        if list(ряд) != sorted(ряд):
            беды.append(f"ряд не по возрастанию: {ряд}")
        if len(set(ряд)) != len(ряд):
            беды.append(f"ряд с повтором, место середины спорно: {ряд}")
        # ЛОВУШКА ОБЯЗАНА БЫТЬ ВИДНА: выброс обязан ДВИГАТЬ среднее и НЕ двигать медианы.
        ряд2 = ряд[:-1] + (в,)
        if _среднее(ряд2) == _среднее(ряд):
            беды.append(f"выброс не сдвинул среднего: {ряд} → {в}")
        if _медиана(ряд2) != _медиана(ряд):
            беды.append(f"выброс сдвинул медиану: {ряд} → {в}")
        if в <= ряд[-1]:
            беды.append(f"выброс не выше прежнего края: {ряд} → {в}")
        if в2 <= в:
            беды.append(f"второй выброс не дальше первого: {в} → {в2}")
        # И РОВНЫЙ РЯД ОБЯЗАН ДАВАТЬ СОВПАДЕНИЕ — ИНАЧЕ ВТОРАЯ СТОРОНА ЛОЖНА.
        if _среднее(ряд) != _медиана(ряд):
            беды.append(f"в ровном ряду среднее и медиана разошлись: {ряд}")
    # ОБЕ СТОРОНЫ ЛОВУШКИ ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ.
    for язык in ЯЗЫКИ:
        if not (по_роду.get((язык, "выброс двигает среднее"))
                and по_роду.get((язык, "ровный ряд"))):
            беды.append(f"показана лишь одна сторона ловушки [{язык}]")
    # МЕРЫ ПРОВЕРЯЮТСЯ НА ЗАВЕДОМО ИЗВЕСТНОМ, А НЕ ТОЛЬКО НА СВОИХ РЯДАХ.
    for ряд, ср, мед in (((1, 2, 3), 2, 2), ((1, 2, 90), 31, 2), ((5,), 5, 5),
                         ((2, 4, 6, 8, 10), 6, 6)):
        if _среднее(ряд) != ср or _медиана(ряд) != мед:
            беды.append(f"меры ряда {ряд}: {_среднее(ряд)}/{_медиана(ряд)} вместо {ср}/{мед}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ, ГДЕ ЕСТЬ ЗАПИСЬ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    ср = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "среднее ряда")
