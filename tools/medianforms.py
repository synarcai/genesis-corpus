def _среднее(ряд):
    return sum(ряд) // len(ряд)


def _медиана(ряд):
    return sorted(ряд)[len(ряд) // 2]


def _ряд(ряд):
    return ", ".join(str(x) for x in ряд)


def _сумма_записью(ряд):
    return " + ".join(str(x) for x in ряд) + f" = {sum(ряд)}"


