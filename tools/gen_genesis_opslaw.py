#!/usr/bin/env python3
"""КОВКА ДОМА ЗАКОНОВ ДЕЙСТВИЯ.

ЗАКОН И ЕГО ГРАНИЦА ИДУТ В ОДНОМ ПРОХОДЕ: «3 + 5 = 8 и 5 + 3 = 8» и «5 − 3 = 2, а 3 − 5 = −2»
суть минимальная пара по действию — те же числа, та же перестановка, и разница в одном месте:
какое действие между ними. Порознь первое внушало бы, что переставлять можно всегда.

СКОБКА идёт своей группой: сочетание говорит, что скобка суммы ничего не меняет, раскрытие — что
скобка произведения делит множитель между слагаемыми. Одна скобка и два разных закона о ней.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import opslawforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_opslaw.txt"
ГРУППЫ = (("перестановка суммы", "перестановка произведения", "граница закона"),
          ("сочетание", "раскрытие скобки"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
