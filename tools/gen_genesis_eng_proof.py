#!/usr/bin/env python3
"""СИРОТА ПОЛУЧАЕТ ГЕНЕРАТОР: мир «eng_proof» из семени с вопросной поверхностью.

Мир лежал в datasets/ без генератора и без единого вопроса; владелец
объявил ноль немых законом. Вчерашний файл стал СЕМЕНЕМ в tools/seeds/:
генератор переносит каждую его строку и к обратимым прикладывает вопрос
по ОБЪЯВЛЕННЫМ образцам дома обращения (tools/inverting.py). Ответ
судится тем же судом, что и утверждение; порча ловится — проверено
палатой до записи.
"""
import bilang  # noqa: E402 — язык показа по азбуке
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import inverting  # noqa: E402
from layer import PASSES, Сбор, emit  # noqa: E402
import re as _re  # noqa: E402

СЕМЯ = КОРЕНЬ / "tools" / "seeds" / "genesis_l3_eng_proof.txt"
ЦЕЛЬ = "datasets/genesis_l3_eng_proof.txt"
ОБРАЩЕНИЯ = ('вызов', 'sign read', 'number read', 'word read',)


# РОД СТРОКИ СЕМЕНИ ЧИТАЕТСЯ ПО ЕЁ СОБСТВЕННОМУ ОБОРОТУ (14.09): семя даёт строки, и дело
# каждой записано в ней — «function» есть вызов, «код: graph TD» есть запись хода графом,
# «база … шаг … итог» есть индукция. Вопрос идёт в род своего утверждения.
# ЗАКОН МАССЫ ОБРЕЗАЛ ПЕРВУЮ РЕДАКЦИЮ С ДЕВЯТИ РОДОВ ДО ШЕСТИ (14.09). Мир этот мал —
# 119 различных строк, — и девять родов дали бы пятерых ниже девяти показов. Сведено по
# родству, а не по остатку:
#
#     ЦИКЛ, ТРАССА И ИНДУКЦИЯ СУТЬ ОДНО УСТРОЙСТВО В ТРЁХ ЗАПИСЯХ: основание, шаг,
#     утверждение обо всей цепи. Граф рисует его стрелкой возврата, трасса — перечнем
#     значений, индукция — словами «база … шаг … итог».
#
# А чтение фигуры и слова идёт К СВОЕМУ ДЕЛУ: «ромб читается как выбор» и «слово if
# читается как если» суть страницы о ветвлении, а не отдельный род «чтение».
ВЫЗОВ = "вызов функции: тело объявлено, довод подставлен"
ВЕТВЛЕНИЕ_ГРАФОМ = "ветвление графом: обе ветви названы, и читаются его ромб и слово"
ЦЕПЬ_ШАГОВ = "цепь шагов: цикл, трасса и индукция — одно устройство в трёх записях"
ТАБЛИЦА = "таблица: сумма столбца по строкам"
ДОЛЯ = "доля благоприятных исходов"
ПРИБЛИЖЕНИЕ = "приближение числа: знак ≈ и его чтение"

_ОБОРОТЫ = (
    (_re.compile(r"^(function|функция) "), ВЫЗОВ),
    (_re.compile(r"^what does \w+\("), ВЫЗОВ),
    (_re.compile(r"^(цикл|loop|программа|program)[: ]"), ЦЕПЬ_ШАГОВ),
    (_re.compile(r"^(таблица|table)[: ]"), ТАБЛИЦА),
    (_re.compile(r"^(база|base|шаг от|step from)[: ]"), ЦЕПЬ_ШАГОВ),
    (_re.compile(r"^(исходов|outcomes|кость|die|монета|coin)"), ДОЛЯ),
    (_re.compile(r"≈"), ПРИБЛИЖЕНИЕ),
    (_re.compile(r"^(если|if) "), ВЕТВЛЕНИЕ_ГРАФОМ),
    (_re.compile(r"(ромб|diamond|слово if|word if)"), ВЕТВЛЕНИЕ_ГРАФОМ),
)


def род_строки(с):
    """Род строки семени — по её собственному обороту."""
    for образец, род in _ОБОРОТЫ:
        if образец.search(с):
            return род
    return None


def показы(шаг):
    строки = СЕМЯ.read_text(encoding="utf-8").splitlines()
    вон = Сбор()
    for с in inverting.с_вопросами(строки, ОБРАЩЕНИЯ, len(PASSES), шаг):
        род = род_строки(с)
        if род is not None:
            вон.род = род
        вон.append(с)
    return вон


def main():
    if not СЕМЯ.exists():
        print(f"ОТКАЗ: семени {СЕМЯ.name} нет")
        return 2
    emit(ЦЕЛЬ, показы)
    return 0


# --------------------------------------------------------------- ОБЪЯВЛЕНИЕ ДОМА

# ЯЗЫКОВОЙ ДОЛГ ДОМА НАЗВАН И ТУТ ЖЕ ВЫПЛАЧЕН (15.09). Три рода несли по одной стороне:
# вызов функции — только по-английски, таблица столбцов и доля исходов — только по-русски.
# Дом кован как ДВА урока разом, и сторона, оставшаяся без близнеца, была у каждого своя.
# Ныне семя несёт обе: «table: row1 = …» рядом с «таблица: строка1 = …», «outcomes 4,
# favourable 3» рядом с «исходов 4, благоприятных 3», «функция сложить(a b) вернуть a + b»
# рядом с «function add(a b) return a + b».
#
#     ИМЯ ФУНКЦИИ ПЕРЕВЕДЕНО ВМЕСТЕ С РАМКОЙ, А НЕ ОСТАВЛЕНО ЛАТИНИЦЕЙ: «add(5 1)» в русской
#     строке было бы не русской речью о вызове, а английским вызовом в русских скобках.
#
# Остаются несомкнутыми цепь шагов (ru 11, en 1) и ветвление графом (ru 5, en 6) — они ждут
# не рамки, а своих страниц.
РОДЫ = (ВЫЗОВ, ВЕТВЛЕНИЕ_ГРАФОМ, ЦЕПЬ_ШАГОВ, ТАБЛИЦА, ДОЛЯ, ПРИБЛИЖЕНИЕ)


def страницы(шаг):
    return показы(шаг)


def перебор_страниц(шаг):
    return показы(шаг).парами


def группы(шаг):
    return [страницы(шаг)]


def _показы_дома():
    вон = {}
    for ш in range(len(PASSES)):
        for с, род in перебор_страниц(ш):
            if с.rstrip():
                вон.setdefault(с.rstrip(), (bilang.азбукой(с.rstrip()), род))
    return вон


ПОКАЗЫ = _показы_дома()


def _самопроверка_дома():
    # НИ ОДНА СТРОКА СЕМЕНИ НЕ ОСТАЁТСЯ БЕЗ РОДА, И ЭТО РУБЕЖ: читатель семени, у
    # которого есть «прочее», молча кладёт туда всё, чего не понял.
    строки = [с for с in СЕМЯ.read_text(encoding="utf-8").splitlines() if с.strip()]
    немые = [с for с in строки if род_строки(с) is None]
    assert not немые, f"строк семени без рода: {len(немые)}, первая — {немые[0][:70]}"
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка_дома()


if __name__ == "__main__":
    sys.exit(main())
