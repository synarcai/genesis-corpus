def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a in КВАДРАТЫ:
            b = 2 * a
            общ = dict(a=a, b=b, aa=a * a, bb=b * b)
            вон[рамки["сторона и площадь"].format(**общ)] = (язык, "сторона и площадь")
            вон[рамки["спрошенное"].format(**общ)] = (язык, "спрошенное")
        for a in КУБЫ:
            b = 2 * a
            вон[рамки["ребро и объём"].format(
                a=a, b=b, aaa=a ** 3, bbb=b ** 3)] = (язык, "ребро и объём")
        for (a1, b1), (a2, b2) in ОДИН_ПЕРИМЕТР:
            if a1 + b1 != a2 + b2 or a1 * b1 == a2 * b2:
                continue
            вон[рамки["один периметр разные площади"].format(
                a1=a1, b1=b1, a2=a2, b2=b2, s1=a1 + b1, s2=a2 + b2,
                p=2 * (a1 + b1), q1=a1 * b1, q2=a2 * b2)] = (
                    язык, "один периметр разные площади")
        for (a1, b1), (a2, b2) in ОДНА_ПЛОЩАДЬ:
            if a1 * b1 != a2 * b2 or a1 + b1 == a2 + b2:
                continue
            вон[рамки["одна площадь разные периметры"].format(
                a1=a1, b1=b1, a2=a2, b2=b2, q=a1 * b1, s1=a1 + b1, s2=a2 + b2,
                p1=2 * (a1 + b1), p2=2 * (a2 + b2))] = (
                    язык, "одна площадь разные периметры")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ2 = re.compile(r"(?<![\d/])(\d+) × (\d+) = (\d+)(?![\d/ ]| ×)")
_ПРОИЗВ3 = re.compile(r"(?<![\d/])(\d+) × (\d+) × (\d+) = (\d+)(?![\d/])")
_СУММА = re.compile(r"(?<![\d/])(\d+) \+ (\d+) = (\d+)(?![\d/])")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего
    сказать; ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c, r in _ПРОИЗВ3.findall(с):
        if int(a) * int(b) * int(c) != int(r):
            return True, False
    без3 = _ПРОИЗВ3.sub(" ", с)
    for a, b, r in _ПРОИЗВ2.findall(без3):
        if int(a) * int(b) != int(r):
            return True, False
    for a, b, r in _СУММА.findall(с):
        if int(a) + int(b) != int(r):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ЛОВУШКА ОБЯЗАНА БЫТЬ ЛОВУШКОЙ: периметры равны, а площади РАЗНЫ, и наоборот.
    for (a1, b1), (a2, b2) in ОДИН_ПЕРИМЕТР:
        if a1 + b1 != a2 + b2:
            беды.append(f"периметры не равны: {a1}×{b1} и {a2}×{b2}")
        elif a1 * b1 == a2 * b2:
            беды.append(f"площади совпали, ловушки нет: {a1}×{b1} и {a2}×{b2}")
    for (a1, b1), (a2, b2) in ОДНА_ПЛОЩАДЬ:
        if a1 * b1 != a2 * b2:
            беды.append(f"площади не равны: {a1}×{b1} и {a2}×{b2}")
        elif a1 + b1 == a2 + b2:
            беды.append(f"периметры совпали, ловушки нет: {a1}×{b1} и {a2}×{b2}")
    # ЗАКОН РОСТА ОБЯЗАН СХОДИТЬСЯ ЧЕТЫРЬМЯ И ВОСЕМЬЮ.
    for a in КВАДРАТЫ:
        if (2 * a) ** 2 != 4 * a * a:
            беды.append(f"квадрат не вчетверо: {a}")
    for a in КУБЫ:
        if (2 * a) ** 3 != 8 * a ** 3:
            беды.append(f"куб не ввосьмеро: {a}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    ст = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "сторона и площадь")
    порча = ст.replace("площадь", "площад", 1)
    if порча == ст:
        беды.append("порча не состоялась: нет слова «площадь»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(ст + " " + ст)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"РОСТ МЕРЫ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


