def арифметические(шаг):
    """Прогрессия названа началом и шагом; члены выведены."""
    вон = []
    for i in range(24):
        a, d = 2 + i + шаг, 2 + (i % 5)
        члены = [a + k * d for k in range(ДЛИНА)]
        если = " ".join(str(x) for x in члены)
        n = ДЛИНА + 1
        en = f"the arithmetic progression from {a} with step {d}"
        ru = f"арифметическая прогрессия от {a} с шагом {d}"
        утв_en, утв_ru = f"{en} gives {если}.", f"{ru} даёт {если}."
        вон.append((утв_en, "арифметические", "en"))
        вон.append((утв_ru, "арифметические", "ru"))
        вон.append((спросить("gives", утв_en, предмет=en), "вопрос о прогрессии", "en"))
        вон.append((спросить("даёт", утв_ru, предмет=ru), "вопрос о прогрессии", "ru"))
        # ПОКАЗ САМОДОСТАТОЧЕН: «её член номер 5» без своей прогрессии
        # не значит ничего, а перестановка проходов разводит соседей.
        чл_en = (f"term number {n} of the progression from {a} "
                 f"with step {d}")
        чл_ru = f"член номер {n} прогрессии от {a} с шагом {d}"
        # ЗВЕНЬЯ ЦЕПИ (compose, e9): k − 1, × d, + a — каждое звено «a op b = c».
        цепь = f"{n} − 1 = {n - 1}, {n - 1} × {d} = {(n - 1) * d}, {a} + {(n - 1) * d} = {a + (n - 1) * d}"
        утв_чл_en = f"{чл_en} is {a + (n - 1) * d}: {цепь}."
        утв_чл_ru = f"{чл_ru} равен {a + (n - 1) * d}: {цепь}."
        вон.append((утв_чл_en, "арифметический член", "en"))
        вон.append((утв_чл_ru, "арифметический член", "ru"))
        вон.append((спросить("term", утв_чл_en, предмет=чл_en), "вопрос о члене", "en"))
        вон.append((спросить("член", утв_чл_ru, предмет=чл_ru), "вопрос о члене", "ru"))
        # РАССУЖДЕНИЕ МИРА (дом речи): звено сложения — свидетель, закон прогрессии — из дома законов.
        if i % 2 == 0:
            # СВИДЕТЕЛЬ ОТКРЫВАЕТСЯ ПЕРВЫМ ЧИСЛОМ ВОПРОСА (дом пары): первое звено цепи.
            вон.append((discourse.рассуждение_мира("en", f"what is {чл_en}", f"{n} − 1 = {n - 1}", утв_чл_en, laws.закон("sequences", 0, "en")), "рассуждение о члене", "en"))
            вон.append((discourse.рассуждение_мира("ru", f"чему равен {чл_ru}", f"{n} − 1 = {n - 1}", утв_чл_ru, laws.закон("sequences", 0, "ru")), "рассуждение о члене", "ru"))
        else:
            вон.append((discourse.почему_мира("en", f"why is {чл_en} equal to {a + (n - 1) * d}", f"{n} − 1 = {n - 1}", утв_чл_en, laws.закон("sequences", 0, "en")), "рассуждение о члене", "en"))
            вон.append((discourse.почему_мира("ru", f"почему {чл_ru} равен {a + (n - 1) * d}", f"{n} − 1 = {n - 1}", утв_чл_ru, laws.закон("sequences", 0, "ru")), "рассуждение о члене", "ru"))
        # СУММА ПРОГРЕССИИ ЗВЕНЬЯМИ: k × (первый + последний) ÷ 2.
        k, первый, последний = len(члены), члены[0], члены[-1]
        цепь_с = f"{первый} + {последний} = {первый + последний}, {k} × {первый + последний} = {k * (первый + последний)}, {k * (первый + последний)} ÷ 2 = {sum(члены)}"
        утв_с_en = f"the sum of {если} is {sum(члены)}: {цепь_с}."
        утв_с_ru = f"сумма {если} равна {sum(члены)}: {цепь_с}."
