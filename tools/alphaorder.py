#!/usr/bin/env python3
"""ДОМ АЗБУЧНОГО ПОРЯДКА (14.09, ступень 2, просьба holon-f9).

Вторая ступень лестницы (BBH) держит род `word_sorting`: дан ряд слов, и надо назвать их
в порядке азбуки. Замерено 14.09 по своду: строк со словами «по алфавиту» или
«alphabetical» — НОЛЬ. Мир `orderforms` ставит в порядок ЧИСЛА и знает «по возрастанию»;
о том, что у БУКВ тоже есть порядок и он не выводится из счёта, корпус не говорил нигде.

    ПОРЯДОК БУКВ ОБЪЯВЛЕН, А НЕ ВЗЯТ ИЗ КОДИРОВКИ. Дом не зовёт `sorted` над строками:
    в Юникоде «ё» (U+0451) стоит ПОСЛЕ «я» (U+044F), и всякий, кто сортирует строки
    кодировкой, получит «ящик, ёлка» и назовёт это азбукой. Азбука есть ОБЫЧАЙ, писанный
    ниже строкой `АЗБУКА`, и суд считает по ней же.

ТРИ РОДА ПО ДЕЛУ — по тому, ГДЕ РЕШАЕТСЯ порядок:

    первая_буква    «вода, дом, ёлка»: головы различны, и дело решено на первом шаге;
    общая_голова    «море, мост, мох»: головы совпали, и решение съехало на вторую букву,
                    на третью, — сравнение идёт ПОБУКВЕННО, пока буквы не разойдутся;
    слово_в_слове   «дом, дома, домик»: одно слово есть НАЧАЛО другого, и буквы не
                    разойдутся никогда. Тогда решает КОНЕЦ СЛОВА: короткое впереди. Это
                    ровно то место, где побуквенное сравнение само по себе молчит, и потому
                    род отдельный, а не случай предыдущего.

ГНЕЗДО — ТРИ СЛОВА, И ПОКАЗОВ У НЕГО ПЯТЬ: все перестановки, КРОМЕ УЖЕ ВЕРНОЙ. Показ, где
переставлять нечего, учит списывать ответ с вопроса, а не порядку.
"""
import itertools
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("первая_буква", "общая_голова", "слово_в_слове")
РОД_В_ПОКАЗЕ = 1

ЗАЧЕМ_РОДА = {
    "первая_буква": "головы слов различны: порядок решён на первой букве",
    "общая_голова": "головы совпали: решение съехало на вторую букву и дальше",
    "слово_в_слове": "одно слово есть начало другого: решает конец слова, короткое впереди",
}

# ОБЫЧАЙ, А НЕ КОДИРОВКА: «ё» стоит между «е» и «ж», как в азбуке, а не после «я», как в
# Юникоде. Мягкий и твёрдый знаки на своих местах, ибо слова дома их не несут в голове.
АЗБУКА = {
    "ru": "абвгдеёжзийклмнопрстуфхцчшщъыьэюя",
    "en": "abcdefghijklmnopqrstuvwxyz",
}

# ГНЁЗДА ОБЪЯВЛЕНЫ, А НЕ НАБРАНЫ ИЗ СЛОВАРЯ: род держится не словами, а тем, ГДЕ у этих
# слов расходятся буквы, и случайная тройка из словаря почти всегда даёт первый род.
ГНЁЗДА = {
    ("ru", "первая_буква"): (("вода", "дом", "ёлка"), ("камень", "лес", "мост"),
                             ("река", "свет", "точка"), ("гора", "звук", "круг")),
    ("ru", "общая_голова"): (("море", "мост", "мох"), ("сила", "сито", "синий"),
                             ("вода", "воля", "волк"), ("дело", "день", "дерево")),
    ("ru", "слово_в_слове"): (("дом", "дома", "домик"), ("сад", "сады", "садовник"),
                              ("лес", "леса", "лесник"), ("стол", "столы", "столик")),
    ("en", "первая_буква"): (("ash", "bell", "fire"), ("house", "river", "stone"),
                             ("light", "road", "word"), ("circle", "field", "law")),
    ("en", "общая_голова"): (("form", "fort", "fox"), ("road", "rock", "rod"),
                             ("star", "stem", "stone"), ("late", "law", "lay")),
    ("en", "слово_в_слове"): (("art", "arts", "article"), ("for", "fore", "forest"),
                              ("to", "top", "topic"), ("son", "song", "songs")),
}

РАМКИ = {
    "ru": "слова: {ряд}. как они идут по азбуке? {ответ}.",
    "en": "words: {ряд}. how do they go by the alphabet? {ответ}.",
}


def ключ(язык, слово):
    """Место слова в азбуке — список мест его букв. Буква вне азбуки есть отказ."""
    азбука = АЗБУКА[язык]
    места = []
    for буква in слово.lower():
        if буква not in азбука:
            raise ValueError(f"буква вне объявленной азбуки: {буква!r} в {слово!r}")
        места.append(азбука.index(буква))
    return места


def по_азбуке(язык, слова):
    """Порядок по ОБЪЯВЛЕННОЙ азбуке. Короткое слово впереди длинного, чьё оно начало."""
    return sorted(слова, key=lambda с: ключ(язык, с))


def _гнездо_родом(язык, род, гнездо):
    """Гнездо обязано делать ровно то дело, каким названо, — и это проверено."""
    порядок = по_азбуке(язык, гнездо)
    головы = {с[0] for с in гнездо}
    внутри = any(a != b and (a.startswith(b) or b.startswith(a))
                 for a in гнездо for b in гнездо)
    if род == "первая_буква":
        return len(головы) == len(гнездо) and not внутри
    if род == "общая_голова":
        return len(головы) < len(гнездо) and not внутри
    return внутри and len(порядок) == len(гнездо)


def страница(язык, род, гнездо, ряд):
    порядок = по_азбуке(язык, гнездо)
    if list(ряд) == порядок:
        return None                    # переставлять нечего — показ ничему не учит
    return РАМКИ[язык].format(ряд=", ".join(ряд), ответ=", ".join(порядок))


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for гнездо in ГНЁЗДА[(язык, род)]:
                for ряд in itertools.permutations(гнездо):
                    п = страница(язык, род, гнездо, ряд)
                    if п:
                        вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД СТАВИТ РЯД В ПОРЯДОК ЗАНОВО по той же объявленной азбуке и требует, чтобы ответ был
# ПЕРЕСТАНОВКОЙ вопроса: порча буквы в любом слове рушит либо порядок, либо самоё равенство
# наборов, и вердикт меняется.
_ОБРАЗЦЫ = {я: re.compile(re.escape(р).replace(r"\{ряд\}", r"(?P<ряд>[^.?]+)")
                          .replace(r"\{ответ\}", r"(?P<ответ>[^.?]+)") + r"$")
            for я, р in РАМКИ.items()}


def судить(строка):
    """(судимо, истинно) — ряд поставлен в порядок заново по объявленной азбуке."""
    for язык in ЯЗЫКИ:
        м = _ОБРАЗЦЫ[язык].fullmatch(строка.strip())
        if not м:
            continue
        ряд = [с.strip() for с in м.group("ряд").split(",")]
        ответ = [с.strip() for с in м.group("ответ").split(",")]
        if sorted(ряд) != sorted(ответ):
            return True, False         # ответ не есть перестановка вопроса
        try:
            верно = по_азбуке(язык, ряд)
        except ValueError:
            return True, False         # буква вне азбуки — судить нечем, и это ложь записи
        return True, ответ == верно and ряд != верно
    return False, True


# ПОДСАДКИ ОБЪЯВЛЕНЫ ЗДЕСЬ, И СУД БЕРЁТ ИХ ОТСЮДА ЖЕ (14.09). Дом скобок держал свой
# список, суд — свой, похожий; рамка вопроса в доме переменилась, а в суде осталась
# прежней, и четыре подсадки из семи перестали попадать в рамку — то есть перестали быть
# судимыми вовсе, а прибор доложил, что не поймал их. ДВА ПОХОЖИХ СПИСКА РАСХОДЯТСЯ
# МОЛЧА; один список расходиться не с чем.
ПОДСАДКИ = ("слова: дом, вода, ёлка. как они идут по азбуке? дом, вода, ёлка.",
            "слова: ёлка, ящик, дом. как они идут по азбуке? дом, ящик, ёлка.",
            "слова: дома, дом, домик. как они идут по азбуке? дома, дом, домик.",
            "слова: море, мох, мост. как они идут по азбуке? море, мох, мост.",
            "слова: дом, вода, ёлка. как они идут по азбуке? вода, дом, ель.",
            "words: fire, ash, bell. how do they go by the alphabet? bell, ash, fire.")


def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    assert set(ГНЁЗДА) == {(я, р) for я in ЯЗЫКИ for р in РОДЫ}, "гнездо объявлено не всем"
    for (язык, род), гнёзда in ГНЁЗДА.items():
        for гнездо in гнёзда:
            assert len(set(гнездо)) == len(гнездо), f"слово дважды в гнезде: {гнездо}"
            assert _гнездо_родом(язык, род, гнездо), f"гнездо не делает дела рода: {гнездо}"
    # АЗБУКА ОБЪЯВЛЕНА НЕ ЗРЯ: кодировка даёт ИНОЙ порядок, и вот показ этого.
    assert по_азбуке("ru", ["ящик", "ёлка"]) == ["ёлка", "ящик"], "азбука взята кодировкой"
    assert sorted(["ящик", "ёлка"]) == ["ящик", "ёлка"], "кодировка вдруг согласна с азбукой"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
