#!/usr/bin/env python3
"""КОВКА ДОМА ДЛИНЫ ЗАПИСИ.

ЛОВУШКА И СПОСОБ ИДУТ В ОДНОМ ПРОХОДЕ: «100 больше 22, хотя каждая цифра 22 больше» и «347 и 374:
цифр поровну, и решает первое слева место» суть минимальная пара ПО ДЛИНЕ — то же сравнение, и
разница в одном: равны ли длины. Порознь первая учила бы, что цифры не важны вовсе, а вторая — что
важны всегда.

СЧЁТ ЦИФР И ГРАНИЦА ПРАВИЛА ИДУТ СВОЕЙ ГРУППОЙ: первый говорит, чем мерят длину, вторая — когда
длины довольно и когда нет. Правило без своей границы будет применено там, где оно молчит.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import digitlenforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_digitlen.txt"
ГРУППЫ = (("длиннее", "поровну"), ("сколько цифр", "когда довольно"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
