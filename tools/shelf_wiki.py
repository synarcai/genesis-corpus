ПЕРЕНАПРАВЛЕНИЕ = re.compile(r"^\s*#(?:REDIRECT|ПЕРЕНАПРАВЛЕНИЕ|PATRZ)", re.I)


def чистый(wikitext):
    т = КАТЕГОРИЯ.sub("", wikitext)
    т = РАЗДЕЛ.sub(r"\1.", т)
    т = т.replace("\xa0", " ")
    return shelf_scan.чистый(т).replace(shelf_scan.ЗАГОЛОВОК, "")


def заголовок(титул, свод):
    """Заголовок статьи из титула: хвост после префикса, капсом первое
    слово; номер омонима у Арцта («1. Paka») снимается."""
    хвост = титул.split("/", 1)[-1] if "/" in титул else титул
    хвост = re.sub(r"^\d+\.\s*", "", хвост).strip()
    первое = re.match(r"[^\W\d_][\w'’\-]*", хвост)
    if not первое:
        return None
    return первое.group().upper() + хвост[первое.end():]


def строки_свода(свод, статьи_):
    """Словарь — статья строкой «ЗАГОЛОВОК тело»; трактат — заглавие
    страницы своей строкой и абзацы страницы своими строками."""
    вон, пропущено = [], 0
    for титул, wikitext in статьи_:
        if ПЕРЕНАПРАВЛЕНИЕ.match(wikitext):
            пропущено += 1
            continue
        з = заголовок(титул, свод)
        if свод.плотность == "словарь":
            тело = чистый(wikitext).strip()
            if not з or len(тело) < 20:
                пропущено += 1
                continue
            вон.append(f"{з} {тело}")
            вон.append("")
            continue
        абзацы = [" ".join(а.split()) for а in
                  re.split(r"\n\s*\n", чистый_абзацами(wikitext))]
        абзацы = [а for а in абзацы if len(а) > 1]
        if not абзацы:
            пропущено += 1
            continue
        вон += [титул.split("/", 1)[-1], ""]
        for а in абзацы:
            вон += [а, ""]
    return вон, пропущено


def чистый_абзацами(wikitext):
    """Как чистый(), но границы абзацев (пустые строки) сохранены."""
    куски = re.split(r"\n\s*\n", КАТЕГОРИЯ.sub("", wikitext))
    return "\n\n".join(чистый(к) for к in куски)


def объявление(свод, сдал, байт, строк):
    """Узел манифеста постатейного свода — договором полки (shelf_kinds)."""
    жанр = ((f"{свод.автор}, «{свод.заглавие}»: статьи по категориям Викитеки "
             + ", ".join(к.split(":", 1)[-1] for к in свод.категории))
            if свод.категории else
            f"{свод.автор}, «{свод.заглавие}» ({свод.издано}): словарь постатейно с Викитеки")
    происхождение = (f"wikisource-{свод.вики}:categories:" + ";".join(свод.категории)
                     if свод.категории else f"wikisource-{свод.вики}:prefix:{свод.префикс}")
    return shelf_kinds.объявление_мира(
        имя=свод.имя, файл=f"shelf/{свод.язык}/{свод.имя}.txt", жанр=жанр,
        язык=свод.язык, тема=свод.тема, плотность=свод.плотность,
        издано=свод.издано, происхождение=происхождение, судится=сдал,
        размер=байт, источник=свод.источник)


def ковать(свод, кэш, манифест):
    т = титулы(свод)
    пути = выгрузить(свод, т, кэш)
    статьи_ = статьи_из_xml(пути)
    строки, пропущено = строки_свода(свод, статьи_)
    тело, отложенное = shelf_fetch.отложить(строки)
    выход = КОРЕНЬ / "shelf" / свод.язык
    байт, строк = shelf_fetch.записать(выход / f"{свод.имя}.txt", тело)
    ещё = (shelf_fetch.записать(выход / f"{свод.имя}.holdout.txt", отложенное)
           if отложенное else (0, 0))
    слов = sum(len(re.findall(r"\w+", с)) for с in тело)
    остаток = sum(с.count("{{") + с.count("[[") + с.count("<") for с in тело)
    print(f"  {свод.имя:<18} титулов {len(т):>6} статей {len(статьи_):>6} "
          f"взято {строк:>6} пропущено {пропущено:>5} слов {слов:>8} байт "
          f"{байт:>9} отложено {ещё[1]:>5} остаток разметки {остаток}")
    if манифест:
        import shelf_forge
        сдал = sorted(shelf_forge.читающие(выход / f"{свод.имя}.txt"))
        заменено = shelf_scan.вписать(объявление(свод, сдал, байт, строк))
        print(f"  МАНИФЕСТ: {'заменено' if заменено else 'добавлено'} "
              f"{свод.имя}, судится {сдал or '—'}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--кэш", required=True)
    ap.add_argument("--только", default="")
    ap.add_argument("--манифест", action="store_true")
    а = ap.parse_args()
    кэш = pathlib.Path(а.кэш)
    хотим = set(а.только.split(",")) if а.только else None
    for свод in ПОЛКА:
        if хотим and свод.имя not in хотим:
            continue
        ковать(свод, кэш, а.манифест)
    return 0


if __name__ == "__main__":
    sys.exit(main())
