#!/usr/bin/env python3
"""ДОМ РУССКОГО ГЛАГОЛА — время, лицо и род прошедшего.

Русский глагол в прошедшем согласуется с РОДОМ деятеля, и это не украшение: «Вера
купил» есть ложь о языке при верной арифметике. Лица берутся из пакета, род — из rugram.

6 родов объявлены не здесь: их назвала СВОЯ ЖЕ КУЗНИЦА кортежем `ГРУППЫ`.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

ЧИТАТЕЛЬ ПЯТОГО РОДА НАЗВАН ПОИМЁННО: суд этого мира ВВОЗИТ дом модулем и берёт `ЛИЦА`, `ГЛАГОЛЫ`.
Самопроверка сверяет, что все эти имена у дома есть, — связь рвётся МОЛЧА при ввозе суда.
"""
