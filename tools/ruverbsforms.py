# ЯЗЫК ДОМА ОБЪЯВЛЕН (15.09). Прибор щербатости (`scripts/form_matrix.py`) читает показы,
# где при странице стои́т пара «(язык, род)», а этот дом кладёт одно имя рода. Для меры он был
# НЕЧИТАЕМ — и молчание её было неотличимо от долга: дом, потерявший язык на пороге словаря,
# выглядел так же, как дом, у которого языка и нет.
#
#     ДОМ, ПИШУЩИЙ НА ОДНОМ ЯЗЫКЕ, НЕ ДОЛЖЕН ВТОРОГО, И СКАЗАТЬ ОБ ЭТОМ ДЕШЕВЛЕ, ЧЕМ
#     ПЕРЕПИСЫВАТЬ ПОРОЖДЕНИЕ РАДИ ТОГО, ЧТО И ТАК ИЗВЕСТНО. Щербатости здесь быть не может:
#     сравнивать не с чем.
#
# Проверено счётом по ВСЕМУ словарю показов: 310 страниц, латиницы 0
ЯЗЫК = "ru"

РОДЫ = ('настоящее', 'прошедшее', 'вопрос', 'прибавка', 'анафора', 'множество')

ЗАЧЕМ_РОДА = {
    "настоящее": "глагол в настоящем времени",
    "прошедшее": "глагол в прошедшем, согласованный по роду",
    "вопрос": "тот же глагол, спрошенный вопросом",
    "прибавка": "действие, прибавляющее к счёту",
    "анафора": "местоимение вместо имени деятеля",
    "множество": "несколько деятелей разом",
}

# (имя, родительный, местоимение, «у него/неё», род прошедшего)
# ЛИЦА — ИЗ ПАКЕТА (05.09): дом выбирает шесть имён; письмо, родительный и род
# знает пакет, местоимение и суффикс по роду — rugram.
_RU = _json.loads((_pathlib.Path(__file__).resolve().parent / "langpacks" / "ru.json").read_text(encoding="utf-8"))["person_forms"]
_RU_ПО_СТРОЧНОМУ = {и.lower(): и for и in _RU}


def _лицо(имя):
    """(имя, родительный, род) из пакета — по строчному образу имени."""
    и = _RU_ПО_СТРОЧНОМУ[имя.lower()]
    ф = _RU[и]
    assert ф.get("gen") and ф.get("gender") in ("m", "f"), ("имя без падежа или рода в пакете", имя)
    return и, ф["gen"], ф["gender"]

_ВЫБОР = ("вера", "анна", "мария", "пётр", "иван", "юрий")
ЛИЦА = tuple((и, р, _МЕСТ[g][0], _МЕСТ[g][1], _СУФ[g]) for и, р, g in map(_лицо, _ВЫБОР))

# (настоящее 3л., прошедшее БЕЗ родового окончания, ключ вещи)
ГЛАГОЛЫ = (("пишет", "написал", "книга"),
           ("читает", "прочитал", "страница"),
           ("продаёт", "продал", "книга"),
           ("берёт", "взял", "монета"),
           ("даёт", "дал", "ручка"),
           ("ест", "съел", "яблоко"),
           ("покупает", "купил", "карта"),
           ("делает", "сделал", "игрушка"),
           ("растит", "вырастил", "цветок"),
           ("пьёт", "выпил", "чашка"))

# ВИНИТЕЛЬНЫЙ ЕДИНСТВЕННОГО НАЗВАН, А НЕ ОТСЕЧЁН: женский род меняет
# окончание, средний и мужской неодушевлённый — нет.
ВИНИТЕЛЬНЫЙ = {"книга": "книгу", "страница": "страницу",
               "монета": "монету", "ручка": "ручку", "яблоко": "яблоко",
               "карта": "карту", "игрушка": "игрушку",
               "цветок": "цветок", "чашка": "чашку"}
# родительный множественного для вопроса «сколько ЧЕГО»
РОДИТЕЛЬНЫЙ = {к: rugram.форма(к, 5) for к in ВИНИТЕЛЬНЫЙ}


def _вещь(ключ, n):
    """Форма вещи при счёте, с винительным при единице."""
    return ВИНИТЕЛЬНЫЙ[ключ] if n == 1 else rugram.форма(ключ, n)


def настоящее(шаг):
    """Голый факт настоящего времени — та же рамка, что в `verbal`."""
    вон = []
    for i, (наст, _, вещь) in enumerate(ГЛАГОЛЫ):
        имя, _, _, _, _ = ЛИЦА[(i + шаг) % len(ЛИЦА)]
        n = 3 + (i + шаг) % 9
        вон.append(f"{имя} {наст} {n} {rugram.форма(вещь, n)}.")
    return вон


def прошедшее(шаг):
    """Прошедшее время с РОДОМ действующего лица."""
    вон = []
    for i, (_, прош, вещь) in enumerate(ГЛАГОЛЫ):
        имя, _, _, _, род = ЛИЦА[(i + шаг) % len(ЛИЦА)]
        n = 3 + (i + шаг) % 9
        вон.append(f"{имя} {прош}{род} {n} {rugram.форма(вещь, n)}.")
    return вон


def вопрос(шаг):
    """Вопрос, повторяющий факт: ответ обязан сойтись числом и вещью."""
    вон = []
    for i, (_, прош, вещь) in enumerate(ГЛАГОЛЫ):
        имя, _, _, _, род = ЛИЦА[(i + шаг) % len(ЛИЦА)]
        n = 3 + (i + шаг) % 9
        вон.append(f"{имя} {прош}{род} {n} {rugram.форма(вещь, n)}. "
                   f"сколько {РОДИТЕЛЬНЫЙ[вещь]} {прош}{род} {имя}? "
                   f"{имя} {прош}{род} {n} {rugram.форма(вещь, n)}.")
    return вон


def прибавка(шаг):
    """Прибыло и итог — рамка, на которой куплена английская анафора."""
    вон = []
    for i, (_, прош, вещь) in enumerate(ГЛАГОЛЫ):
        имя, _, _, _, род = ЛИЦА[(i + шаг) % len(ЛИЦА)]
        n = 3 + (i + шаг) % 7
        m = 1 + (i + шаг) % 3
        # ОТВЕТ И ЕГО КУЗНИЦА — ДВЕ ПОВЕРХНОСТИ ОДНОГО ФАКТА (М-166): в этом
        # мире вычисляет ответ одна лишь рамка прибавки, и шага в ней не было.
        кузн = f": {n} + {m} = {n + m}" if (i + шаг) % 2 == 0 else ""
        вон.append(f"{имя} {прош}{род} {n} {rugram.форма(вещь, n)}. "
                   f"{имя} {прош}{род} ещё {m} {_вещь(вещь, m)}. "
                   f"сколько {РОДИТЕЛЬНЫЙ[вещь]} {прош}{род} {имя} "
                   f"всего? {имя} {прош}{род} {n + m} "
                   f"{rugram.форма(вещь, n + m)}{кузн}.")
    return вон


def анафора(шаг):
    """МЕСТОИМЕНИЕ ВМЕСТО ИМЕНИ — то, ради чего слой и кладётся."""
    вон = []
    for i, (_, прош, вещь) in enumerate(ГЛАГОЛЫ):
        имя, род_имени, он_она, него_неё, род = ЛИЦА[(i + шаг) % len(ЛИЦА)]
        было = 4 + (i + шаг) % 7
        ушло = 1 + (i + шаг) % 3
        стало = было - ушло
        вон.append(f"у {род_имени} было {было} "
                   f"{rugram.форма(вещь, было)}. "
                   f"{он_она} отдал{род} {ушло} {_вещь(вещь, ушло)}. "
                   f"у {него_неё} осталось {стало} "
                   f"{rugram.форма(вещь, стало)}.")
    return вон


# ИМЕНИТЕЛЬНОЕ МНОЖЕСТВЕННОЕ: МНОЖЕСТВО, НАЗВАННОЕ БЕЗ СЧЁТА.
#
# ЗАМЕР ДО ПРАВКИ, 96 миров манифеста: счётное согласование живёт в
# 6402 строках, а именительное множественное БЕЗ числа — в 46, и
# ВСЕГО ТРЕМЯ словами (элементы, рубли, узлы) на 54 выведенные формы;
# все 46 — технические утверждения о множествах и графах. Простой
# рамки здесь не было ни разу, а между тем с неё начинается всякое
# утверждение о множестве: «яблоки лежат на столе» сказано прежде,
# чем сосчитано.
#
# СКАЗУЕМОЕ ПРИВЯЗАНО К ВЕЩИ, А НЕ ВЫБИРАЕТСЯ ХОДОМ: книги СТОЯТ, а
# яблоки ЛЕЖАТ, и переставить их значило бы сказать по-русски неверно
# при верном согласовании. Ходом идёт МЕСТО — оно свободно.
#
# (ключ вещи, сказуемое ед., сказуемое мн., места)
МНОЖЕСТВА = (
    ("яблоко", "лежит", "лежат",
     ("на столе", "в корзине", "на тарелке")),
    ("книга", "стоит", "стоят", ("на полке", "в шкафу", "на столе")),
    ("монета", "лежит", "лежат", ("в кармане", "на столе", "в коробке")),
    ("ручка", "лежит", "лежат", ("на столе", "в коробке", "в сумке")),
    ("чашка", "стоит", "стоят", ("на столе", "на полке", "в шкафу")),
    ("игрушка", "лежит", "лежат", ("в коробке", "на полу", "на столе")),
    ("карта", "лежит", "лежат", ("на столе", "в коробке", "в сумке")),
)


def множество(шаг):
    """Множество без счёта — на ТРЁХ поверхностях.

    ЗНАНИЕ БЕЗ ВОПРОСНОЙ ПОВЕРХНОСТИ НЕ ОТВЕЧАЕТ — ОНО ТОЛЬКО
    СООБЩАЕТ. Потому утверждение идёт со своим вопросом; а третьей
    стоит ОТКАЗ С ОСНОВАНИЕМ, и он здесь не украшение, а сама суть
    рода: множество названо БЕЗ числа, и на вопрос «сколько» ответа
    нет — не потому, что организм не умеет считать, а потому, что
    числа не называли. Отказ несёт при себе то, что БЫЛО сказано.

    ФОРМА БЕРЁТСЯ У ДОМА (`rugram.именительный_мн`), а не пишется
    рукой: «яблоки» есть именованное исключение правила, и генератор,
    писавший бы её от себя, разошёлся бы с судом в первый же день.
    """
    вон = []
    for i, (вещь, ед, мн, места) in enumerate(МНОЖЕСТВА):
        имена_мн = rugram.именительный_мн(вещь)
        где = места[(i + шаг) % len(места)]
        вон.append(f"{имена_мн} {мн} {где}.")
        вон.append(f"где {мн} {имена_мн}? {имена_мн} {мн} {где}.")
        вон.append(f"сколько {РОДИТЕЛЬНЫЙ[вещь]} {ед} {где}? "
                   f"не сказано: {имена_мн} {мн} {где}, "
                   f"а число не названо.")
    return вон

ГРУППЫ = (настоящее, прошедшее, вопрос, прибавка, анафора, множество)


def группы(шаг):
    """[[страница]] — ровно те группы и в том порядке, какими кузница кормит `emit_grouped`."""
    return [сделать(шаг) for сделать in ГРУППЫ]


def перебор(шаг):
    """[(страница, род)] — те же группы, но каждая под своим именем."""
    вон = []
    for род, группа in zip(РОДЫ, группы(шаг)):
        for с in группа:
            вон.append((с, род))
    return вон


def _показы():
    from layer import PASSES                              # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор(шаг):
            вон.setdefault(с, род)
    return вон


ПОКАЗЫ = _показы()


def _самопроверка():
    """Объявление сверяется с ДЕЛОМ прохода, и имена, каких ждёт суд, — с домом."""
    имена = tuple(с.__name__ for с in ГРУППЫ)
    assert имена == РОДЫ, f"кортеж {имена} разошёлся с объявлением {РОДЫ}"
    сколько = len(группы(0))
    assert сколько == len(РОДЫ), f"проход даёт {сколько} групп при {len(РОДЫ)} родах"
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"
    for имя in ('ЛИЦА', 'ГЛАГОЛЫ'):
        assert имя in globals(), f"суд ждёт имени «{имя}», а дом его не держит"


_самопроверка()
