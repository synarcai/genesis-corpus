#!/usr/bin/env python3
"""ДОРЕФОРМЕННАЯ ОРФОГРАФИЯ → СОВРЕМЕННАЯ: правило, а не список слов.

Подлинник Даля (1880–82) набран по орфографии до 1918 года: ѣ, і, ѳ, ѵ,
ъ на конце слова, окончания -аго/-яго, -ыя/-ія, местоимения «ея»,
«онѣ», «однѣ». Организм, читающий наши своды в современной
орфографии, увидел бы в «свѣтъ» и «свет» два разных слова — и
словарь, положенный ради связности, связности бы не дал. Оттого
подлинник переводится ПРАВИЛОМ (закон переоткрытия: чужой модуль
модернизации не берётся, выводится свой), а правило судится ПО
ВЫБОРКЕ против чужой модернизации той же статьи (Викитека показывает
ТСД2/<слово> в современной орфографии): печатается доля совпавших
слов и верх расхождений. Порог не выбирается вкусом — число
печатается, и решение о полке принимается по нему вслух.

ЧЕГО ПРАВИЛО НЕ ДЕЛАЕТ. Окончание -ія у существительных («армія»,
«линія») даёт по букве «-ия» и верно; у прилагательных
множественного числа женского и среднего рода («синія», «добрыя»)
современная норма — «-ие/-ые», и различить их без морфологии нельзя.
Правило переводит «-ыя» всегда (существительных на «-ыя» язык не
знает) и «-ія» лишь после суффиксов прилагательных (-ск-, -н-, -ов-,
-ев-, -ист-, -чн-, -льн-); остаток расхождений — в числе суда.
"""

import re
import sys

БУКВЫ = str.maketrans({"ѣ": "е", "Ѣ": "Е", "і": "и", "І": "И",
                       "ѳ": "ф", "Ѳ": "Ф", "ѵ": "и", "Ѵ": "И"})

# СЛОВА, ЧЬЯ ФОРМА МЕНЯЕТСЯ ЦЕЛИКОМ: не буква, а слово. Их четыре, и
# они суть местоимения — единственный разряд, где реформа тронула не
# написание, а само слово («ея» → «её» звучит иначе).
СЛОВА = {"ея": "её", "нея": "неё", "онѣ": "они", "однѣ": "одни",
         "однѣхъ": "одних", "однѣмъ": "одним", "однѣми": "одними"}

# ОКОНЧАНИЯ — ПОСЛЕ БУКВ, ибо «-аго» ищется уже в современных буквах.
ОКОНЧАНИЯ = (
    (re.compile(r"(?<=[а-яё]{2})аго\b"), "ого"),
    (re.compile(r"(?<=[а-яё]{2})яго\b"), "его"),
    (re.compile(r"(?<=[а-яё]{2})ыя\b"), "ые"),
    (re.compile(r"\b([а-яё]+?(?:ск|нн|ов|ев|ист|чн|льн|шн|жн|тн|дн|рн))ия\b"),
     r"\1ие"),
)
# ИСКЛЮЧЕНИЯ ОКОНЧАНИЙ — слова, где «аго/яго» не есть окончание
# родительного падежа прилагательного, а корень.
КОРНИ_АГО = frozenset(("благо", "драго", "наго", "яго", "саго", "иаго"))
ТВЁРДЫЙ_ЗНАК_В_КОНЦЕ = re.compile(r"ъ(?![а-яёА-ЯЁ])")
# ПРИСТАВКИ НА З ПЕРЕД ГЛУХОЙ — реформа 1918 года: «разсказъ» → «рассказ»,
# «безсмертный» → «бессмертный», «изслѣдованіе» → «исследование».
ПРИСТАВКА_З = re.compile(r"^(без|воз|вз|из|низ|раз|роз|чрез|через)(?=[кпстфхцчшщ])",
                         re.I)
# «-ІЕ» ПОСЛЕ СОГЛАСНОЙ — ДВЕ НОРМЫ, И БУКВА ИХ НЕ ДЕЛИТ: «платіе» ныне
# «платье», а «состояніе» — «состояние»; «пособіе» — «пособие», а
# «здоровіе» — «здоровье». Различает этимология, а не буква, и списка
# слов правило не держит. Оно берёт СВИДЕТЕЛЯ ИЗ САМОГО ПОДЛИННИКА:
# если книга сама пишет форму с мягким знаком («платье» у Даля 88 раз
# рядом с «платіе» 232), слово с «-іе» есть то же слово, и оно
# переводится в «-ье»; слово, чьей ь-формы книга не знает («Россія»),
# остаётся по букве («Россия»). Свидетели собираются по книге один раз.
ГЛАСНЫЕ = "аеёиоуыэюя"
# СУФФИКС «-НИЕ» — КНИЖНАЯ НОРМА, и свидетель ему не указ: Даль пишет и
# «состояніе», и «состоянье», но наши своды говорят «утверждение»,
# «доказательство», и словарь обязан говорить с ними одним языком.
# Остаток («свинія» → «свиния», 68 случаев) назван долгом числом суда.
МЯГКИЙ_ХВОСТ = re.compile(r"([^аеёиоуыэюяьйн])и([еяию])$")
СЛОВО = re.compile(r"[А-Яа-яЁёѢѣІіѲѳѴѵЪъ]+")


def _окончания(слово):
    низ = слово.lower()
    if низ in КОРНИ_АГО:
        return слово
    for образец, замена in ОКОНЧАНИЯ:
        слово = образец.sub(замена, слово)
    return слово


def _буквы(с):
    """Буквенная часть правил: ъ, ѣ/і/ѳ/ѵ, приставки, окончания."""
    с = ТВЁРДЫЙ_ЗНАК_В_КОНЦЕ.sub("", с)
    с = с.translate(БУКВЫ)
    с = ПРИСТАВКА_З.sub(lambda м: м.group(1)[:-1] + ("с" if м.group(1)[-1] == "з"
                                                    else "С"), с)
    return _окончания(с)


def свидетели(текст):
    """Слова книги с мягким знаком перед конечной гласной — в нижнем
    регистре, после буквенных правил: «платье», «состоянье»."""
    вон = set()
    for м in СЛОВО.finditer(текст):
        с = _буквы(м.group()).lower()
        if re.search(r"ь[еяию]$", с):
            вон.add(с)
    return вон


def современно(текст, свидетели_=frozenset()):
    """Текст в современной орфографии — по правилам выше, в их порядке."""
    def слово(м):
        с = м.group()
        низ = с.lower()
        if низ in СЛОВА:
            з = СЛОВА[низ]
            return з.capitalize() if с[0].isupper() else з
        с = _буквы(с)
        if свидетели_:
            мягкое = МЯГКИЙ_ХВОСТ.sub(r"\1ь\2", с.lower())
            if мягкое != с.lower() and мягкое in свидетели_:
                return мягкое.capitalize() if с[0].isupper() else мягкое
        return с
    return СЛОВО.sub(слово, текст)


def _слова(текст):
    return [м.group().lower() for м in re.finditer(r"[а-яё]+", текст,
                                                    re.I)]


def суд(пары):
    """(доля совпавших слов, [(наше, чужое, сколько)]) по выборке статей.

    Сравниваются МУЛЬТИМНОЖЕСТВА слов: чужая модернизация переставляет
    ничего, но режет статью по-своему, и пословный шаг сбился бы на
    первом же разрыве. Расхождение — слово, которое есть у одного и
    нет у другого; верх расхождений печатается парами по общему
    началу, чтобы видеть ПРАВИЛО, а не случай.
    """
    import collections
    совпало = всего = 0
    расх = collections.Counter()
    for наше, чужое in пары:
        н, ч = collections.Counter(_слова(наше)), collections.Counter(_слова(чужое))
        всего += sum(н.values())
        совпало += sum((н & ч).values())
        лишние_у_нас = sorted((н - ч).elements())
        лишние_у_них = sorted((ч - н).elements())
        for а in лишние_у_нас:
            б = next((x for x in лишние_у_них if x[:3] == а[:3]), "—")
            расх[(а, б)] += 1
    return (совпало / всего if всего else 0.0), расх.most_common(30)


if __name__ == "__main__":
    print(современно(sys.stdin.read()), end="")
