#!/usr/bin/env python3
"""ДОМ МОСТА ВОПРОСНОЙ ФОРМЫ — глагол, спрошенный СВОЕЙ формой (07.09).

ЗАКАЗ КУПЛЕН ПЕРЕПИСЬЮ ЧИТАТЕЛЯ, А НЕ ДОГАДКОЙ (holon, школа fw15). Рынок мостов
покупает связь «did X SELL» → «sold» из соседства ЧИСТОГО ВОПРОСА и ФАКТА-ОТВЕТА; из
ста тридцати глаголов истории мост имеют двадцать три. «how many marbles did josh
lose?» лжёт, ибо «lose» в корпусе восемь раз и ни одного «did X lose?».

    БЕЗ МОСТА ЧИТАТЕЛЬ НЕ ЗНАЕТ, ЧТО «did he lose» И «lost» СУТЬ ОДИН ГЛАГОЛ. Он
    видел форму утверждения тысячу раз и вопросную — ни разу, и вопрос для него есть
    слово незнакомое.

ПЕРЕПИСЬ ПО СВОДУ (07.09, английские строки; глагол есть слово перед числом, живущее в
ДВУХ формах — место перед числом есть признак счёта, а глагол отличает СКЛОНЕНИЕ):
глаголов истории 54, с мостом 25. Без моста при сотне и более утверждений — семь:

    count 1152 утв. / 10 вопросов     earn 419 / 0      add 361 / 0
    pack   341 / 0                    collect 316 / 0   save 599 / 0
    delete 724 / 0

И ЭТО ДОЛГ КОРПУСА, А НЕ УЗОСТЬ РЫНКА — проверено образцами. Там, где мост в своде
есть, он ЧИСТЫЙ: «how many cards did Felix take? 4: 9 − 5 = 4». Там, где его нет,
страницы иного рода: у `count` вопрос несёт СВОЁ число и стои́т в условном наклонении
(«if the baker made 15 cakes … how many would he still have?»), у `eat` и `buy` вопрос
о причине и об орудии («why do people eat?», «what do people eat soup with?»).

    РЫНОК ПОКУПАЕТ МОСТ С ЧИСТОГО ВОПРОСА, И ЭТО ВЕРНО. Страница на условие есть
    задача, а не мост формы: там глагол стои́т не в вопросной форме своего акта, а в
    форме предположения.

ЧТО ПИШЕТ ЭТОТ ДОМ, И ПОЧЕМУ ИМЕННО ТАК:

    ВОПРОС ЧИСТ — в нём НЕТ ЧИСЛА. «how many cakes did the baker count?» и ни числом
        больше: число, стоящее в вопросе, обращает страницу в задачу на условие, и
        рынок моста её не берёт.
    ОТВЕТ ЕСТЬ ФАКТ ТОЙ ЖЕ ИСТОРИИ, а не вычисление: «the baker counted 62 cakes».
        Мост учит форме, а не счёту; счёту учат другие дома.
    ПОЛОВИНА СТРАНИЦ НЕСЁТ ДВА ФАКТА ДО ВОПРОСА (пожелание holon): «X counted 62
        cakes. X sold 9 cakes. how many cakes did X count?» — так одной страницей
        кормятся рынок мостов, рынок хвостов и знаки глаголов.
    ПРЕДМЕТ БЕРЁТСЯ У `verbthings.ГЛАГОЛ_БЕРЁТ` — глагол берёт свой род вещей, и
        «counted 8 miles» здесь невозможно по построению.
    ИМЯ ОБЪЯВЛЕНО ПАКЕТОМ ЯЗЫКА (М-131), а не списком дома.

ЗАКОН ЧИСЛА: не менее LAW² = 4 страниц на глагол и не менее LAW = 2 носителей — иначе
мост не куплен, а показан.
"""
import json
import pathlib

from layer import Сбор, emit
from plural import by_count

# ПУТЬ, СКАЗАННЫЙ ТОЛЬКО В ЗОВЕ, ЕСТЬ ПУТЬ, О КОТОРОМ НЕ ОБЪЯВЛЕНО (14.09): указатель
# читает объявление СТРОКОЙ ВЕРХНЕГО УРОВНЯ, и мир, названный лишь внутри `emit`,
# остаётся не связанным ни с одним домом.
ЦЕЛЬ = "datasets/genesis_verbbridge.txt"

_ПАКЕТ = json.loads((pathlib.Path(__file__).resolve().parent / "langpacks" / "en.json")
                    .read_text(encoding="utf-8"))
_ИМЕНА_ПАКЕТА = set(_ПАКЕТ["person_names"])
_ДОМ = ["ann", "ben", "carla", "dan", "elena", "felix", "grace", "hugo"]
_ПО_СТРОЧНОМУ = {и.lower(): и for и in _ИМЕНА_ПАКЕТА}
ИМЕНА = [_ПО_СТРОЧНОМУ.get(и.lower(), и) for и in _ДОМ]
assert set(ИМЕНА) <= _ИМЕНА_ПАКЕТА, "имя не объявлено пакетом en"

# ГЛАГОЛЫ ДОЛГА: (вопросная форма, прошедшее, настоящее третьего лица). Взяты из
# переписи 07.09 поимённо — те, у кого мост отсутствует при сотне и более утверждений.
ГЛАГОЛЫ = (
    ("count", "counted", "counts"),
    ("earn", "earned", "earns"),
    ("add", "added", "adds"),
    ("pack", "packed", "packs"),
    ("collect", "collected", "collects"),
    ("save", "saved", "saves"),
)
# ВТОРОЙ ГЛАГОЛ ДЛЯ ДВУХФАКТНОЙ СТРАНИЦЫ — тот, чей предмет тот же рода: страница о
# двух фактах обязана быть об ОДНОЙ истории, а не о двух разных.
# ВТОРОЙ ГЛАГОЛ ДАЁТСЯ ТРЕМЯ ФОРМАМИ, А НЕ ДВУМЯ: настоящее третьего лица есть своя
# форма («uses», не «use»), и страница, взявшая базу вместо неё, лжёт о языке — «Elena
# use 13 coins» было в первой пробе.
ВТОРОЙ = {"count": ("sold", "sells"), "earn": ("spent", "spends"), "add": ("used", "uses"),
          "pack": ("sold", "sells"), "collect": ("gave", "gives"), "save": ("spent", "spends")}
ВЕЩИ = ("cakes", "cookies", "books", "pages", "cards", "coins", "dollars",
        "apples", "eggs", "pencils", "seeds", "flowers")

# РОД ГЛАГОЛА ОБЪЯВЛЕН ЗДЕСЬ, А НЕ В ОБЩЕМ ДОМЕ, И ЭТО КУПЛЕНО ЗАМЕРОМ (07.09).
#
# Первая правка внесла семь глаголов моста в `verbthings.ГЛАГОЛ_БЕРЁТ` — туда, где
# живут роды всех прочих глаголов, — и суд эпизода тотчас пал 986 ложными строками в
# одиннадцати мирах:
#
#     «tara packed 5 hours. tara used 3 hours away…»          items 179
#     «pia counted 5 centimeters. pia found 3 more…»          gsmwide 334, lang_en 250
#
# ЛОЖЬ БЫЛА В КОРПУСЕ И ДО ОБЪЯВЛЕНИЯ. Дом молчал о глаголе, и суд молчал вслед за ним:
# неизвестный глагол не судится (так объявлено в `verbthings.берёт`). Объявление не
# создало дефекта — оно сделало его видимым, и это находка, а не поломка.
#
#     ОБЪЯВЛЕНИЕ РОДА ЕСТЬ ПРИБОР: оно зажигает ложь, спавшую в молчании. Но прибор,
#     зажжённый под замороженным сводом, светит туда, куда нельзя идти.
#
# Свод заморожен до перековки восьмой точки, и починка одиннадцати миров есть работа
# отдельная и большая. Потому род объявлен ЗДЕСЬ, в доме моста: он полон для СВОИХ
# страниц и не судит чужих. Заказ на общий дом назван числом и ждёт размороженного
# свода: 986 ложных строк, из них «packed/counted + время или мера» — 116 поимённо.
_РОД_МОСТА = {
    "count": {"cakes", "cookies", "books", "pages", "cards", "apples", "eggs",
              "pencils", "seeds", "flowers"},
    "earn": {"coins", "dollars"},
    "add": {"cards", "pages", "books", "cookies", "apples", "eggs", "coins", "dollars"},
    "pack": {"books", "cards", "apples", "eggs", "seeds", "pencils", "cookies"},
    "collect": {"cards", "seeds", "flowers", "eggs", "apples", "books", "pencils"},
    "save": {"coins", "dollars", "cards", "pages", "books", "eggs", "apples"},
}
_РОД_ВТОРОГО = {
    "sell": {"cakes", "cookies", "books", "cards", "apples", "eggs", "flowers", "pencils"},
    "spend": {"coins", "dollars"},
    "use": {"cards", "pages", "books", "cookies", "apples", "eggs", "seeds", "pencils"},
    "give": {"cards", "seeds", "flowers", "eggs", "apples", "books", "pencils", "coins"},
}


def _вещь(база, зерно):
    """Предмет, какой берёт ЭТОТ глагол по объявлению дома моста."""
    годные = sorted(_РОД_МОСТА.get(база) or ВЕЩИ)
    return годные[зерно % len(годные)]


# ДВЕ ВЕТВИ — ДВА ДЕЛА: страница об ОДНОМ факте и страница о ДВУХ фактах одной истории.
# Вторая учит тому, чего первая не может: что второй глагол НЕ СБИВАЕТ вопроса, заданного
# о первом. Прошедшее и настоящее — не роды, а времена одного дела.
ОДИН_ФАКТ = "один факт: вопрос о числе своего глагола"
ДВА_ФАКТА = "два факта одной истории: второй глагол не сбивает вопроса"


def показы(pi):
    основа = pi * 37
    вон = Сбор(ОДИН_ФАКТ)
    for i in range(len(ИМЕНА) * len(ГЛАГОЛЫ) * 2):
        имя = ИМЕНА[(основа + i) % len(ИМЕНА)]
        база, прош, наст = ГЛАГОЛЫ[((основа + i) // 2) % len(ГЛАГОЛЫ)]
        вещь = _вещь(база, основа + i)
        n = (основа + i * 7) % 40 + 5          # 5..44
        двухфактная = (основа + i) % 2 == 0
        прошедшее = ((основа + i) // 4) % 2 == 0
        глагол_вопроса = база
        факт = f"{имя} {прош if прошедшее else наст} {n} {by_count(n, вещь)}."
        вспом = "did" if прошедшее else "does"
        вопрос = f"how many {вещь} {вспом} {имя} {глагол_вопроса}?"
        ответ = f"{имя} {прош if прошедшее else наст} {n} {by_count(n, вещь)}."
        if двухфактная:
            вт_прош, вт_наст = ВТОРОЙ[база]
            m = (основа + i * 3) % (n - 1) + 1 if n > 2 else 1
            # ДВА ФАКТА ОДНОЙ СТРАНИЦЫ СУТЬ ОДНА ИСТОРИЯ, И ПРЕДМЕТ У НИХ ОДИН.
            # «Ann counted 5 cakes. Ann sold 1 cookie» есть две истории, склеенные
            # именем: рынок хвостов возьмёт из неё ложную пару, а читатель — ложный
            # предмет. Вещь второго факта берётся ТА ЖЕ, и второй глагол обязан её
            # принимать (`verbthings`), иначе пара глаголов не ставится вовсе.
            вт_база = {"sold": "sell", "spent": "spend", "used": "use", "gave": "give"}[вт_прош]
            if вещь not in (_РОД_ВТОРОГО.get(вт_база) or set()):
                вон.род = ОДИН_ФАКТ
                вон.append(f"{факт} {вопрос} {ответ}")
                continue
            второй = f"{имя} {вт_прош if прошедшее else вт_наст} {m} {by_count(m, вещь)}."
            вон.род = ДВА_ФАКТА
            вон.append(f"{факт} {второй} {вопрос} {ответ}")
        else:
            вон.род = ОДИН_ФАКТ
            вон.append(f"{факт} {вопрос} {ответ}")
    return вон


# --------------------------------------------------------------- ОБЪЯВЛЕНИЕ ДОМА

# ЯЗЫК ДОМА ОБЪЯВЛЕН (15.09). Прибор щербатости (`scripts/form_matrix.py`) читает показы,
# где при странице стои́т пара «(язык, род)», а этот дом кладёт одно имя рода. Для меры он был
# НЕЧИТАЕМ — и молчание её было неотличимо от долга: дом, потерявший язык на пороге словаря,
# выглядел так же, как дом, у которого языка и нет.
#
#     ДОМ, ПИШУЩИЙ НА ОДНОМ ЯЗЫКЕ, НЕ ДОЛЖЕН ВТОРОГО, И СКАЗАТЬ ОБ ЭТОМ ДЕШЕВЛЕ, ЧЕМ
#     ПЕРЕПИСЫВАТЬ ПОРОЖДЕНИЕ РАДИ ТОГО, ЧТО И ТАК ИЗВЕСТНО. Щербатости здесь быть не может:
#     сравнивать не с чем.
#
# Проверено счётом по ВСЕМУ словарю показов: 462 страницы, кириллицы 0, диакритики 0
ЯЗЫК = "en"

РОДЫ = (ОДИН_ФАКТ, ДВА_ФАКТА)

ЗАЧЕМ_РОДА = {
    ОДИН_ФАКТ: "«Ann baked 12 cakes. how many cakes did Ann bake?» — мост между глаголом "
               "вопроса и глаголом факта",
    ДВА_ФАКТА: "второй факт той же истории с ТЕМ ЖЕ предметом: вопрос по-прежнему о "
               "первом глаголе, и отвлечь его нечем",
}


def страницы(pi):
    return показы(pi)


def перебор_страниц(pi):
    return показы(pi).парами


def группы(pi):
    return [страницы(pi)]


def _показы_дома():
    from layer import PASSES                             # noqa: PLC0415
    вон = {}
    for шаг in range(len(PASSES)):
        for с, род in перебор_страниц(шаг):
            for строка in с.split("\n"):
                if строка.rstrip():
                    вон.setdefault(строка.rstrip(), род)
    return вон


ПОКАЗЫ = _показы_дома()


def _самопроверка_дома():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    сбор = показы(0)
    assert len(сбор) == len(сбор.роды), "показ остался без рода"
    вне = {р for _с, р in сбор.парами} - set(РОДЫ)
    assert not вне, f"род кован и не объявлен: {sorted(вне)}"
    пустые = set(РОДЫ) - set(ПОКАЗЫ.values())
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка_дома()


def main():
    emit(ЦЕЛЬ, показы)


if __name__ == "__main__":
    main()
