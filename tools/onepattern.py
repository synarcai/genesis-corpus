#!/usr/bin/env python3
"""ОДИН РОД — ОДИН ОБРАЗЕЦ: слияние ветвей, читаемых судом как одно.

    ЧТО СУД ЧИТАЕТ КАК ОДНО, ПУСТЬ И ОБЪЯВЛЕНО КАК ОДНО. Два образца об одном роде суть два
    списка об одном — тот же долг, что и всюду.

ПОВОД. Прибор ширины (`scripts/ask_width.py`) считает род ОБРАЗЦОМ: «один образец есть один род,
сколько бы имён ему ни дали». Суд, читающий рассказ и вопрос одним разбором — «A.match(с) or
B.match(с)», один набор захватов на обе половины, — объявляет их двумя образцами, и рассказ
выходит родом БЕЗ вопросной поверхности, сколько бы вопросов о том же самом ни стояло рядом.
То же и с половинами языков: суд календаря давно пишет их одним чередованием, прочие — двумя
образцами.

ЦЕНА СЛИЯНИЯ НАЗВАНА ЗДЕСЬ, ИБО ОНА НЕ ОЧЕВИДНА (08.09, поймано сличением вердиктов):

    ОБРАТНАЯ ССЫЛКА НЕ ПЕРЕЖИВАЕТ СЛИЯНИЯ БЕЗ ПЕРЕСЧЁТА. Образцы держат имя деятеля ссылкой
    («\\1 bought»); в чередовании номера групп СДВИГАЮТСЯ, и «\\1» второй ветви начинает
    указывать на первую, при этом совпадении пустую. Семьдесят четыре строки дома быта вышли
    из-под суда МОЛЧА — ни одна не стала ложной, и потому ни ворота, ни палата беды бы не
    назвали.

        ЧИСЛО ГРУППЫ ЕСТЬ ЕЁ МЕСТО В ОБРАЗЦЕ, А НЕ ЕЁ ИМЯ.

И ВТОРАЯ ГРАНИЦА, НАЙДЕННАЯ ТАМ ЖЕ: ОДИНАКОВОЕ ИМЯ НЕ ЕСТЬ ОДИНАКОВЫЙ РОД. Из десяти пар дома
быта, названных одинаково («МЕСТО» и «МЕСТО_ВОПРОС»), слить можно было лишь две: прочие восемь
судятся РАЗНЫМИ законами («_вместилище» против «_через»), и слить их значило бы солгать о
родстве. Родство проверяется чтением вердиктов, а не списка имён.
"""
import re


# ГРАНИЦЫ ВЕТВЕЙ СЛИТОГО ОБРАЗЦА: {id(образца): [(начало, сколько групп), …]}. Хранятся, чтобы
# вердикт мог читать совпадение КАК СОВПАДЕНИЕ СВОЕЙ ВЕТВИ — с её собственными пустыми группами.
СЛИТЫЕ = {}


# ИМЯ ГРУППЫ ЖИВЁТ В ОБРАЗЦЕ ОДИН РАЗ, И ЭТО ПРАВИЛО ЯЗЫКА, А НЕ ПРИХОТЬ (08.09). Две ветви,
# писанные одними именами («(?P<закон>…)» и там и тут), в чередовании столкнутся — Python не
# даст объявить имя дважды. Оттого имена ветвей, кроме первой, получают ПРИПИСКУ по номеру
# ветви, а `groupdict` совпадения снимает её обратно: вердикт видит свои имена нетронутыми.
_ИМЯ = re.compile(r"\(\?P<([A-Za-zА-Яа-я_][\w]*)>")


def вместе(*образцы):
    """Один образец из ветвей — чередованием, с пересчётом ссылок и приписью имён."""
    куски, сдвиг, границы = [], 0, []
    for номер, о in enumerate(образцы):
        текст = re.sub(r"\\(\d+)",
                       lambda м, с=сдвиг: "\\" + str(int(м.group(1)) + с), о.pattern)
        if номер:
            текст = _ИМЯ.sub(lambda м, н=номер: f"(?P<{м.group(1)}__в{н}>", текст)
            текст = re.sub(r"\(\?P=([A-Za-zА-Яа-я_]\w*)\)",
                           lambda м, н=номер: f"(?P={м.group(1)}__в{н})", текст)
        куски.append("(?:" + текст + ")")
        границы.append((сдвиг, о.groups))
        сдвиг += о.groups
    готовый = re.compile("|".join(куски))
    СЛИТЫЕ[id(готовый)] = границы
    return готовый


class _Ветвь:
    """Совпадение слитого образца, читаемое как совпадение ОДНОЙ ветви."""

    __slots__ = ("_м", "_г")

    def __init__(self, м, г):
        self._м, self._г = м, г

    def group(self, *номера):
        if not номера:
            return self._м.group(0)
        если = tuple(self._м.group(0) if n == 0 else self._г[n - 1] for n in номера)
        return если[0] if len(если) == 1 else если

    def groups(self):
        return tuple(self._г)

    def groupdict(self):
        """Имена своей ветви — без приписки, какой их развели при слиянии."""
        вон = {}
        for имя, знач in self._м.groupdict().items():
            голое = имя.split("__в")[0]
            if знач is not None or голое not in вон:
                вон[голое] = знач if знач is not None else вон.get(голое)
        return вон

    @property
    def string(self):
        return self._м.string


def как_ветвь(образец, м):
    r"""Совпадение, читаемое вердиктом ветви: чужие группы сняты, СВОИ ПУСТЫЕ — оставлены.

    ЗАХВАТ БЕЗ ПУСТЫХ ГОДИТСЯ НЕ ВСЯКОЙ ВЕТВИ (08.09). Ветвь бывает со СВОЕЙ необязательной
    группой — «(-?\d+) is( not)? a root», — и снять из неё пустое значит сдвинуть всё, что
    следом. Границы ветвей известны из слияния, и потому берётся РОВНО кусок своей ветви.
    """
    границы = СЛИТЫЕ.get(id(образец))
    if границы is None:
        return м
    все = м.groups()
    for нач, сколько in границы:
        кусок = все[нач:нач + сколько]
        if сколько and any(x is not None for x in кусок):
            return _Ветвь(м, кусок)
    return м


def захваты(м):
    """Захваты совпадения БЕЗ пустых: ветви равны числом групп, непойманная молчит.

    Пустая строка группы («купил(а?)» при мужском роде) не есть None и не теряется.
    """
    return [x for x in м.groups() if x is not None]


def слить_по_вердикту(образцы):
    """[(текст образца, вердикт)] → tuple[(образец, вердикт)] с ветвями одного вердикта в одном.

    ЗАКОН, А НЕ РУКА: ветви сводятся не списком имён, а признаком — ОДИН ВЕРДИКТ. Что суд читает
    одним законом, то и есть один род; порядок правил сохраняется по первому появлению вердикта.

    НЕ СЛИВАЕТСЯ ОДНА ВЕЩЬ, И ОНА НАЗВАНА: ряд, где хоть одна ветвь несёт ВОПРОС, — слияние там
    ширины не покупает, ибо вопросная поверхность у рода уже есть.

    И ТРЕТЬЯ ГРАНИЦА, КУПЛЕННАЯ ПОЛОМКОЙ (08.09, вечер): СЛИВАТЬ МОЖНО ЛИШЬ ТАМ, ГДЕ ПРАВИЛА
    ИДУТ ДО ПЕРВОГО СОВПАДЕНИЯ. Суд разметки применяет ВСЕ свои сверки к каждой строке, а не
    останавливается на первой; слитые две сверки сработали как одна, и 660 строк вышли из-под
    суда молча. Сличение вердиктов назвало это одним словом («замолчал 660»), и слияние там
    отозвано.

        ПОРЯДОК ПРИМЕНЕНИЯ ПРАВИЛ ЕСТЬ ЧАСТЬ ЗАКОНА СУДА, А НЕ ПОДРОБНОСТЬ ЕГО ПИСЬМА.

    ИМЕНОВАННЫЕ ГРУППЫ СЛИВАЮТСЯ ТОЖЕ (08.09, вечер): одно имя в двух ветвях столкнулось бы, и
    потому имена ветвей, кроме первой, получают приписку по номеру ветви, а `groupdict`
    совпадения снимает её обратно. Вердикт видит свои имена нетронутыми.
    """
    import re as _re
    по_вердикту, порядок = {}, []
    for текст, вердикт in образцы:
        ключ = id(вердикт)
        if ключ not in по_вердикту:
            по_вердикту[ключ] = []
            порядок.append((ключ, вердикт))
        # ОБРАЗЕЦ БЫВАЕТ УЖЕ СОБРАННЫМ: одни суды держат список текстов, другие — готовых
        # образцов; закон один, и он берёт оба.
        по_вердикту[ключ].append(текст if hasattr(текст, "pattern") else _re.compile(текст))
    вон = []
    for ключ, вердикт in порядок:
        ряд = по_вердикту[ключ]
        тексты = [о.pattern for о in ряд]
        сливаем = len(ряд) > 1 and not any("\\?" in т for т in тексты)
        if сливаем:
            вон.append((вместе(*ряд), вердикт))
        else:
            вон.extend((о, вердикт) for о in ряд)
    return tuple(вон)
