#!/usr/bin/env python3
"""ДОМ РАЗЛОЖЕНИЯ И ДЕЛИМОСТИ — множители называют ВСЕХ делителей разом.

    СВОД РАЗЛАГАЕТ НА ПРОСТЫЕ И ОТДЕЛЬНО СУДИТ О ДЕЛИМОСТИ, НЕ СВЯЗЫВАЯ ОДНОГО С ДРУГИМ.
    Замер 11.09: строк вида «84 = 2 × 2 × 3 × 7» в своде 256; строк о делимости («7 не делится
    на 3, значит 7 не делится на 6») — сотни. А слов «и потому делится», «и значит делится»,
    «so it is divisible» — НИ ОДНОГО ВХОЖДЕНИЯ.

    РАЗЛОЖЕНИЕ, НЕ СВЯЗАННОЕ С ДЕЛИМОСТЬЮ, ЕСТЬ ФОКУС: число разобрали на части и ничего этим
    не решили. А оно решает ВСЁ — всякий делитель есть произведение части множителей, и потому
    одно разложение отвечает сразу на все вопросы о делителях.

ЧЕТЫРЕ РОДА, И ПОСЛЕДНИЕ ДВА СУТЬ МИНИМАЛЬНАЯ ПАРА ПО ПРИЧИНЕ ОТКАЗА:

    множитель  12 = 2 × 2 × 3, и двойка среди множителей есть, и потому 12 делится на 2:
               12 ÷ 2 = 6.
    набор      12 = 2 × 2 × 3, и 6 = 2 × 3, и все множители шестёрки есть в двенадцати,
               и потому 12 делится на 6: 12 ÷ 6 = 2.          ← ДЕЛИТЕЛЬ ИЗ ЧАСТИ МНОЖИТЕЛЕЙ
    нет вовсе  12 = 2 × 2 × 3, а пятёрки среди множителей нет, и потому 12 на 5 не делится:
               12 = 5 × 2 + 2.                                 ← МНОЖИТЕЛЯ НЕТ
    не хватает 12 = 2 × 2 × 3, и 8 = 2 × 2 × 2, но третьей двойки в двенадцати нет, и потому
               12 на 8 не делится: 12 = 8 × 1 + 4.             ← МНОЖИТЕЛЬ ЕСТЬ, НО МАЛО

ТРЕТИЙ И ЧЕТВЁРТЫЙ ОТЛИЧАЮТСЯ НЕ ВЕРДИКТОМ, А ПРИЧИНОЙ, И БЕЗ ЭТОГО РАЗЛИЧЕНИЯ ДОМ УЧИЛ БЫ
ПОЛОВИНЕ: «нет пятёрки» и «двоек мало» суть разные беды, и вторая куда коварнее — множитель
ВИДЕН, а делимости нет. Тот же ход, что в доме деления на ноль: два отказа с противоположными
причинами учат большему, чем десять отказов с одной.

ОТКАЗ ПОКАЗАН ОСТАТКОМ, А НЕ ТОЛЬКО СЛОВОМ: «12 = 5 × 2 + 2» — деление с остатком, и суд его
пересчитывает. Утверждение «не делится» без остатка было бы объявлением.

    ЧТО СКАЗАНО СЛОВОМ, ПУСТЬ БУДЕТ ПОКАЗАНО ЧИСЛОМ.

ЧИСЛА БЕРУТСЯ МАЛЫЕ И РАЗЛОЖИМЫЕ: разложение должно читаться глазом, а не проверяться на веру.
Простые множители — 2, 3, 5, 7; целое не больше сотни.

ОСТАТОК ДОЛГА НАЗВАН ЧИСЛОМ: восемь родов дома непокупаемы, и все восемь — в роде «не
хватает». Он перебирает ПАРЫ длин: разложение числа и разложение делителя, — и всякая пара
даёт свою рамку. Сузить её значило бы отнять у рода его предмет: «не хватает» и есть сравнение
двух разложений. Дом прошёл путь 84 рода при 68 непокупаемых → 28 при 8, и остаток стои́т
названным, а не спрятанным.

    python3 tools/factorforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("множитель", "набор", "нет вовсе", "не хватает")
ПРОСТЫЕ = (2, 3, 5, 7)

# ПРОСТОЕ НАЗЫВАЕТСЯ ЧИСЛОМ, А НЕ СЛОВОМ, И ЭТО КУПЛЕНО МЕРОЙ МАССЫ (11.09). Первая редакция
# писала «двойка», «тройка», «пятёрка», «семёрка» и «второй», «третьей» — и дом дал 84 рода,
# из них 68 НЕПОКУПАЕМЫХ: всякое имя давало свою рамку, тогда как цифра на том же месте
# читается мерой как дыра «#», и рамки сходятся в одну.
#
# ПОПЫТКА ЛЕЧИТЬ ЭТО МЕРОЙ (отдать ей имена простых заполнителями) СДЕЛАЛА ХУЖЕ: слова эти уже
# читаются числительными, и, объявленные ещё и вещью, они стали «※» там, где рядом стои́т «#» —
# родов вышло 60 100 вместо 59 886.
#
#     ДЫРА, ОБЪЯВЛЕННАЯ ДВАЖДЫ РАЗНЫМИ ЗНАКАМИ, РАЗБИВАЕТ РАМКУ ВМЕСТО ТОГО, ЧТОБЫ ЕЁ СОБРАТЬ.
#
# Лечит дом, а не мера: число вместо имени. И это вернее по существу — дом говорит о ЧИСЛАХ,
# и называть их словами значило бы прибавить к предмету чужую заботу о склонении.
СКОЛЬКО = {"ru": {1: "один раз", 2: "два раза", 3: "три раза", 4: "четыре раза",
                  5: "пять раз"},
           "en": {1: "once", 2: "twice", 3: "three times", 4: "four times", 5: "five times"}}

РАМКИ = {
    "ru": {
        "множитель": "{n} = {разл}, и {d} среди множителей есть, и потому {n} делится на {d}: {n} ÷ {d} = {q}.",
        "набор": "{n} = {разл}, и {d} = {разлd}, и все множители числа {d} есть в числе {n}, и потому {n} делится на {d}: {n} ÷ {d} = {q}.",
        "нет вовсе": "{n} = {разл}, а {p} среди множителей нет, и потому {n} на {d} не делится: {n} = {d} × {q} + {r}.",
        "не хватает": "{n} = {разл}, и {d} = {разлd}, но {p} входит в {n} {сколько}, а нужно {надо}, и потому {n} на {d} не делится: {n} = {d} × {q} + {r}.",
    },
    "en": {
        "множитель": "{n} = {разл}, and {d} is among the factors, and so {n} is divisible by {d}: {n} ÷ {d} = {q}.",
        "набор": "{n} = {разл}, and {d} = {разлd}, and every factor of {d} is in {n}, and so {n} is divisible by {d}: {n} ÷ {d} = {q}.",
        "нет вовсе": "{n} = {разл}, and {p} is not among the factors, and so {n} is not divisible by {d}: {n} = {d} × {q} + {r}.",
        "не хватает": "{n} = {разл}, and {d} = {разлd}, but {p} goes into {n} {сколько}, and {надо} is needed, and so {n} is not divisible by {d}: {n} = {d} × {q} + {r}.",
    },
}


def разложить(n):
    """Простые множители по возрастанию, или None — число не разложимо нашими простыми."""
    вон, ост = [], n
    for p in ПРОСТЫЕ:
        while ост % p == 0:
            вон.append(p)
            ост //= p
    return вон if ост == 1 and len(вон) > 1 else None


def _запись(множители):
    return " × ".join(str(м) for м in множители)


# ДЛИНА РАЗЛОЖЕНИЯ ЕСТЬ ЧАСТЬ ФОРМЫ, И ПОТОМУ ОГРАНИЧЕНА. Мера массы 11.09: числа вроде
# 32 = 2 × 2 × 2 × 2 × 2 дают рамку «# = # × # × # × # × #», какая во всём доме одна, — и род
# выходит непокупаемым. Разложений длиной до четырёх множителей хватает и на закон, и на массу;
# пятое и шестое место учили бы лишь тому, что бывают длинные разложения.
ДЛИННЕЕ_НЕ_БРАТЬ = 4


def _числа():
    """Составные числа до сотни, раскладываемые нашими простыми, с коротким разложением."""
    return [n for n in range(4, 100)
            if разложить(n) and len(разложить(n)) <= ДЛИННЕЕ_НЕ_БРАТЬ]


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки, сколько = РАМКИ[язык], СКОЛЬКО[язык]
        for n in _числа():
            м = разложить(n)
            разл = _запись(м)
            общее = dict(n=n, разл=разл)
            # МНОЖИТЕЛЬ: делитель есть само простое из разложения.
            for p in sorted(set(м)):
                вон[рамки["множитель"].format(**общее, d=p, q=n // p, разлd="", p=p,
                                              сколько="", надо="", r=0)] = (
                    язык, "множитель")
            # НАБОР: делитель есть произведение ЧАСТИ множителей — не простое и не само число.
            for i in range(len(м) - 1):
                d = м[i] * м[i + 1]
                if d != n and разложить(d):
                    вон[рамки["набор"].format(**общее, d=d, q=n // d,
                                              разлd=_запись(разложить(d)),
                                              p=0, сколько="", надо="", r=0)] = (
                        язык, "набор")
            # НЕТ ВОВСЕ: простое, которого нет среди множителей.
            for p in ПРОСТЫЕ:
                if p not in м:
                    вон[рамки["нет вовсе"].format(**общее, d=p, q=n // p, r=n % p,
                                                  p=p, разлd="", сколько="", надо="")] = (
                        язык, "нет вовсе")
            # НЕ ХВАТАЕТ: делитель из ТЕХ ЖЕ простых, но одного из них в нём больше.
            for p in sorted(set(м)):
                k = м.count(p) + 1
                d = p ** k
                if d < n and n % d and k in сколько and (k - 1) in сколько:
                    вон[рамки["не хватает"].format(**общее, d=d, q=n // d, r=n % d,
                                                   разлd=_запись([p] * k), p=p,
                                                   сколько=сколько[k - 1], надо=сколько[k])] = (
                        язык, "не хватает")
    return вон


ПОКАЗЫ = страницы()
# УКАЗАТЕЛЬ ПО ЧИСЛУ СЛОВ: порча ОДНИМ словом не меняет длины строки.
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# ГРАНИЦА ЦИФРЫ ОБЯЗАТЕЛЬНА, И ЭТО ВТОРАЯ ТАКАЯ ОШИБКА ЗА ДВА ДНЯ. Образец без `(?!\d)` брал
# из «21 = 2 × 10 + 1» подстроку «21 = 2 × 1» — единицу из десятки — и объявлял ложными
# восемьдесят четыре честные страницы. Корпус знает этот род под именем «ложь по цифре»; здесь
# он повторился оттого, что закон писался заново вместо того, чтобы быть взятым.
_РАЗЛОЖЕНИЕ = re.compile(r"(\d+) = ((?:\d+ × )+\d+)(?!\d)(?! \+)")
_ЧАСТНОЕ = re.compile(r"(\d+) ÷ (\d+) = (\d+)")
_ОСТАТОК = re.compile(r"(\d+) = (\d+) × (\d+) \+ (\d+)")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    # РАМКА ПОРОДИЛА СТРАНИЦУ — ОСТАЛСЯ СЧЁТ: разложение, частное и остаток своими глазами.
    for n, разл in _РАЗЛОЖЕНИЕ.findall(с):
        произв = 1
        for м in разл.split(" × "):
            произв *= int(м)
        if произв != int(n):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b, q, r in _ОСТАТОК.findall(с):
        if int(a) != int(b) * int(q) + int(r) or not 0 < int(r) < int(b):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:74]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    мн = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "множитель")
    нет = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "нет вовсе")
    if судить(мн.replace("потому", "потом"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(нет.replace("делится", "делитс"))[1] is not False:
        беды.append("обрезанное слово в отказе прошло")
    if судить(мн + " " + мн)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"РАЗЛОЖЕНИЕ И ДЕЛИМОСТЬ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, "
          f"бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
