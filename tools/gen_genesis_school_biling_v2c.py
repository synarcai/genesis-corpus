def семя():
    if not СЕМЯ.exists():
        return None
    return СЕМЯ.read_text(encoding="utf-8").splitlines()


# РОД СТРОКИ СЕМЕНИ ЧИТАЕТСЯ ПО ЕЁ СОБСТВЕННОЙ ЗАПИСИ (14.09). Мир этот — крупнейший мир
# показов свода (11 380 строк), и строки его пришли семенем, а не ветвями. Манифест объявляет
# его ярусы (`t0_glyph_arith`, `t1_verbal_arith`, `t2_bridge`, `t3_multistep`, `t4_derivation`,
# `t6_refusals`), и роды идут по ним — но ЯРУС ЕЩЁ НЕ РОД: внутри яруса счёта живут ЧЕТЫРЕ
# действия, и каждое есть своё дело. Знак и слово при этом суть две ЗАПИСИ одного действия и
# роды тоже разные: ярус t0 и ярус t1 объявлены манифестом порознь именно поэтому.
#
#     ЗАПИСЬ И ДЕЙСТВИЕ — ДВЕ ОСИ, И РОД ЛЕЖИТ НА ИХ ПЕРЕСЕЧЕНИИ. Свести их в одну значило бы
#     либо назвать родом ярус (и получить великана в четыре тысячи страниц), либо назвать
#     родом действие (и смешать «7 + 5 = 12» с «семь плюс пять равно двенадцать»).
ЗНАК_СЛОЖЕНИЕ = "знаками: сложение"
ЗНАК_ВЫЧИТАНИЕ = "знаками: вычитание"
ЗНАК_УМНОЖЕНИЕ = "знаками: умножение"
ЗНАК_ДЕЛЕНИЕ = "знаками: деление"
СЛОВО_СЛОЖЕНИЕ = "словами: сложение"
СЛОВО_ВЫЧИТАНИЕ = "словами: вычитание"
СЛОВО_УМНОЖЕНИЕ = "словами: умножение"
СЛОВО_ДЕЛЕНИЕ = "словами: деление"
СТРЕЛКА = "стрелка: граф переходов и его пересказ словом"
СРАВНЕНИЕ = "сравнение и перестановочность: 3 < 7, 2 + 9 = 9 + 2, и закон её прозой"
РЯД_ЧИСЕЛ = "ряд чисел подряд: цифрами и словами, без единого действия"
ЗАКОН_БУКВАМИ = "закон, записанный буквами: сочетательный и распределительный"
ОТКАЗ_ДЕЛЕНИЯ = "делится ли нацело: да и нет одной рамкой, и остаток назван"

_ЗНАКОМ = {"+": ЗНАК_СЛОЖЕНИЕ, "−": ЗНАК_ВЫЧИТАНИЕ,
           "×": ЗНАК_УМНОЖЕНИЕ, "÷": ЗНАК_ДЕЛЕНИЕ}
_СЛОВОМ = {"плюс": СЛОВО_СЛОЖЕНИЕ, "plus": СЛОВО_СЛОЖЕНИЕ,
           "минус": СЛОВО_ВЫЧИТАНИЕ, "minus": СЛОВО_ВЫЧИТАНИЕ,
           "умножить": СЛОВО_УМНОЖЕНИЕ, "times": СЛОВО_УМНОЖЕНИЕ,
           "делить": СЛОВО_ДЕЛЕНИЕ, "divided": СЛОВО_ДЕЛЕНИЕ}

_СТРЕЛКА = re.compile(r"^graph TD|-->|^[A-Z] (ведёт к|leads to)|стрелка|arrow")
_РЯД = re.compile(r"^(\d+ )+\d+\.$|^(one|один) ")
_ПОРЯДОК = re.compile(r"не зависит от порядка|does not depend on the order")
_БУКВЫ = re.compile(r"^\(?[xyz]\b|^икс |^[a-z] × \(")
_НЕРАВЕНСТВО = re.compile(r"^\d[\d\s]*[<>]")
_ОБЕ_СТОРОНЫ = re.compile(r"^\d.*=\s*\d+\s*[+−×÷]")
_ЗНАК = re.compile(r"^\d[\d\s]*([+−×÷])")
_ЧТЕНИЕ_ЗНАКА = re.compile(r"(знак|sign) ([+−×÷=]) (читается|is read)")
_ЧТЕНИЕ = re.compile(r"читается как|is read as")
_РАВНО = re.compile(r"равно|equals")


def род_строки(с):
    """Род строки семени — по её собственной записи: сперва ЧТО записано, потом ЧЕМ."""
    if _СТРЕЛКА.search(с):
        return СТРЕЛКА
    if _РЯД.search(с):
        return РЯД_ЧИСЕЛ
    if _ПОРЯДОК.search(с) or _НЕРАВЕНСТВО.search(с) or _ОБЕ_СТОРОНЫ.search(с):
        return СРАВНЕНИЕ
    if _БУКВЫ.search(с):
        return ЗАКОН_БУКВАМИ
    м = _ЗНАК.search(с)
    if м:
        return _ЗНАКОМ[м.group(1)]
    м = _ЧТЕНИЕ_ЗНАКА.search(с)
    if м:
        return _ЗНАКОМ.get(м.group(2), ЗНАК_СЛОЖЕНИЕ)
    for слово, род in _СЛОВОМ.items():
        if слово in с:
            return род
    if _ЧТЕНИЕ.search(с):
        return ЗНАК_СЛОЖЕНИЕ
    if _РАВНО.search(с):
        return СЛОВО_СЛОЖЕНИЕ
    return None


def отказы(шаг):
    """Деление, не выходящее нацело, — с основанием и остатком."""
    вон = []
    for i in range(12):
        a = 30 + шаг * 7 + i * 11
        b = 4 + (шаг + i) % 9
        q, r = divmod(a, b)
        # ОДНА ФОРМА ВОПРОСА НА ОБЕ ПОЛЯРНОСТИ (holon, аудит покупок 03.09).
        вон.append(f"делится ли {a} на {b} нацело? {'да' if r == 0 else 'нет'}: "
                   f"{b} × {q} = {b * q}, остаток {r}.")
    return вон


def показы(шаг):
    вон = Сбор()
    for с in inverting.с_вопросами(семя(), ОБРАЩЕНИЯ, len(PASSES), шаг):
        род = род_строки(с)
        if род is not None:
            вон.род = род
        вон.append(с)
    вон.род = ОТКАЗ_ДЕЛЕНИЯ
    вон.extend(отказы(шаг))
    return вон


def main():
    if семя() is None:
        print(f"ШКОЛА ОТКАЗ: семени {СЕМЯ.relative_to(КОРЕНЬ)} нет")
        return 2
    emit(ЦЕЛЬ, показы)
    return 0


