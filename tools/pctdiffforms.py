#!/usr/bin/env python3
"""ДОМ ПРОЦЕНТНОЙ РАЗНИЦЫ — «БОЛЬШЕ НА СТОЛЬКО-ТО» И «МЕНЬШЕ НА СТОЛЬКО-ТО» СУТЬ РАЗНЫЕ ЧИСЛА.

    ПРОЦЕНТНОЙ РАЗНИЦЫ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 244 мирам показов: «на
    сколько процентов», «by what percent» — НОЛЬ; «больше на N %» — НОЛЬ; «меньше на N %» —
    НОЛЬ; «какую часть», «какой процент» — НОЛЬ. Мир процентов берёт процент ОТ числа, дом
    изменения на процент меняет число НА процент, и ни один не отвечает на вопрос СРАВНЕНИЯ.

    ВО СКОЛЬКО РАЗ свод спрашивает 268 раз, НА СКОЛЬКО ПРОЦЕНТОВ — ни разу.

ШЕСТНАДЦАТАЯ ЛОВУШКА РЯДА, И ОНА ТА ЖЕ, ЧТО ПЯТНАДЦАТАЯ, ВЗЯТАЯ С ДРУГОЙ СТОРОНЫ:

    100 БОЛЬШЕ 80 НА 25 ПРОЦЕНТОВ, А 80 МЕНЬШЕ 100 — НА 20.

Одна и та же разница в двадцать единиц даёт двадцать пять процентов в одну сторону и двадцать в
другую, ибо делится на РАЗНЫЕ основания.

    СРАВНЕНИЕ ПРОЦЕНТОМ НЕ СИММЕТРИЧНО, И ЭТО НЕ ОСОБЫЙ СЛУЧАЙ, А САМО УСТРОЙСТВО ПРОЦЕНТА.

Сравнение разностью симметрично («100 больше 80 на 20, и 80 меньше 100 на 20»), сравнение
отношением симметрично взаимно обратными числами, а процентное — НЕТ, и читатель, привыкший к
первому, переносит его сюда.

ЧЕТЫРЕ РОДА:

    доля в процентах  20 от 80 — это 25 процентов: 20 × 100 = 2000, и 2000 ÷ 80 = 25.
    больше на         100 больше 80 на 25 процентов: 100 − 80 = 20, и 20 × 100 = 2000,
                      и 2000 ÷ 80 = 25.
    меньше на         80 меньше 100 не на 25 процентов, а на 20: 100 − 80 = 20,
                      и 20 × 100 = 2000, и 2000 ÷ 100 = 20.                  ← ЛОВУШКА
    основание         один и тот же излишек делится на разные основания, и потому
                      проценты разные: 2000 ÷ 80 = 25, и 2000 ÷ 100 = 20.    ← ПРИЧИНА

ПЕРВЫЙ РОД ЕСТЬ ОБРАТНЫЙ ХОД МИРА ПРОЦЕНТОВ: тот спрашивает «сколько будет N % от числа», этот —
«сколько процентов составляет часть». Два вопроса об одном действии, и свод знал только первый.

ВТОРОЙ И ТРЕТИЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО НАПРАВЛЕНИЮ СРАВНЕНИЯ: те же два числа, та же разница,
и разница в одном месте — на что делят. Третий назван отрицанием прямо на странице («не на 25, а
на 20»), ибо ловушка, не названная вслух, ловит и читателя, и корпус.

ПАРЫ ВЗЯТЫ ТЕ, ГДЕ ОБА ПРОЦЕНТА ЦЕЛЫЕ: иначе дом заговорил бы о десятичной записи — предмете
соседа. ГРАНИЦА ДОМА ЕСТЬ ГРАНИЦА ЕГО ПРЕДМЕТА, А НЕ УДОБСТВО СЧЁТА.

    python3 tools/pctdiffforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — счётная форма «процентов» объявлена там

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("доля в процентах", "больше на", "меньше на", "основание")
ПРОЦЕНТ = "процент"


def процентов(язык, n):
    return "percent" if язык == "en" else rugram.форма(ПРОЦЕНТ, n)


РАМКИ = {
    "ru": {
        "доля в процентах": "{д} от {b} — это {вверх} {пр}: {д} × 100 = {м}, и {м} ÷ {b} = {вверх}.",
        "больше на": "{a} больше {b} на {вверх} {пр}: {a} − {b} = {д}, и {д} × 100 = {м}, и {м} ÷ {b} = {вверх}.",
        "меньше на": "{b} меньше {a} не на {вверх} {пр}, а на {вниз}: {a} − {b} = {д}, и {д} × 100 = {м}, и {м} ÷ {a} = {вниз}.",
        "основание": "один и тот же излишек делится на разные основания, и потому проценты разные: {м} ÷ {b} = {вверх}, и {м} ÷ {a} = {вниз}.",
    },
    "en": {
        "доля в процентах": "{д} of {b} is {вверх} percent: {д} × 100 = {м}, and {м} ÷ {b} = {вверх}.",
        "больше на": "{a} is greater than {b} by {вверх} percent: {a} − {b} = {д}, and {д} × 100 = {м}, and {м} ÷ {b} = {вверх}.",
        "меньше на": "{b} is less than {a} not by {вверх} percent but by {вниз}: {a} − {b} = {д}, and {д} × 100 = {м}, and {м} ÷ {a} = {вниз}.",
        "основание": "one and the same excess is divided by different bases, and so the percents differ: {м} ÷ {b} = {вверх}, and {м} ÷ {a} = {вниз}.",
    },
}
ПУСТО = dict(a=0, b=0, д=0, м=0, вверх=0, вниз=0, зазор=0, пр="")


def пары():
    """Пары, где ОБА процента целые: иначе показалась бы десятичная запись.

    ВЕЛИЧИНЫ ВЗЯТЫ ШКОЛЬНЫЕ, И ЭТО ЗАМЕР, А НЕ ВКУС. Первый перебор шёл шагом в двадцать и
    давал пары вроде «80 больше 20 на 300 процентов»: оба процента целы, но такая разница
    учит не сравнению, а кратности — о ней говорит сосед («во сколько раз», 268 строк).
    Рост свыше сотни процентов есть УЖЕ ИНОЙ РАЗГОВОР, и он здесь отрезан.

    ЧАСТЬ МЕНЬШЕ ЦЕЛОГО — ИНАЧЕ ПЕРВЫЙ РОД ПОКАЗЫВАЛ БЫ «20 ОТ 20 — ЭТО 100 ПРОЦЕНТОВ»,
    то есть долю, равную целому, где показывать нечего.
    """
    вон = []
    for b in range(20, 2001, 5):
        for a in range(b + 5, 2001, 5):
            д = a - b
            if (д * 100) % b or (д * 100) % a:
                continue
            вверх, вниз = д * 100 // b, д * 100 // a
            if вверх == вниз or вверх > 100 or вниз < 5 or д >= b:
                continue
            вон.append((a, b, д, вверх, вниз))
    return вон


ПАРЫ = пары()


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for (a, b, д, вверх, вниз) in ПАРЫ:
            общ = dict(ПУСТО, a=a, b=b, д=д, м=д * 100, вверх=вверх, вниз=вниз,
                       зазор=вверх - вниз, пр=процентов(язык, вверх))
            # ЧЕТЫРЕ РОДА НА ОДНОЙ ПАРЕ СУТЬ ОДИН УРОК, А НЕ ЧЕТЫРЕ РАЗНЫХ: читатель
            # видит те же числа с четырёх сторон — доля, рост, убыль и причина их
            # расхождения. РАЗНЫЕ ЧИСЛА В РОДАХ РАЗВЕЛИ БЫ СТОРОНЫ ОДНОГО ДЕЛА.
            for род in РОДЫ:
                вон[рамки[род].format(**общ)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

_ПРОИЗВ = re.compile(r"(?<![/\d])(\d+) × (\d+) = (\d+)(?![/\d])")
_ЧАСТНОЕ = re.compile(r"(?<![/\d])(\d+) ÷ (\d+) = (\d+)(?![/\d])")
_РАЗНОСТЬ = re.compile(r"(?<![/\d])(\d+) − (\d+) = (\d+)(?![/\d])")
_НЕ_НА = re.compile(r"(?:не на (\d+) \S+, а на (\d+)|not by (\d+) percent but by (\d+))")


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _ПРОИЗВ.findall(с):
        if int(a) * int(b) != int(c):
            return True, False
    for a, b, c in _ЧАСТНОЕ.findall(с):
        if int(b) == 0 or int(a) != int(b) * int(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if int(a) - int(b) != int(c):
            return True, False
    # ЛОВУШКА ОБЯЗАНА ЛОВИТЬ: отвергнутый процент обязан быть процентом ДРУГОЙ стороны, и
    # оба обязаны РАЗОЙТИСЬ — страница, где они совпали, отрицает ровно то, что утверждает.
    for г in _НЕ_НА.findall(с):
        отверг, верно = (г[0], г[1]) if г[0] else (г[2], г[3])
        if int(отверг) == int(верно):
            return True, False
        частные = _ЧАСТНОЕ.findall(с)
        if not частные or int(частные[-1][2]) != int(верно):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:92]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    мн = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "меньше на")
    ос = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "основание")
    for страница, слово, куда in ((мн, "меньше", "меньш"), (ос, "излишек", "излише")):
        порча = страница.replace(слово, куда, 1)
        if порча == страница:
            беды.append(f"порча не состоялась: нет слова «{слово}»")
        elif судить(порча)[1] is not False:
            беды.append(f"обрезанное слово прошло: {слово}")
    if судить(мн + " " + мн)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    # НЕСИММЕТРИЧНОСТЬ ЕСТЬ ПРЕДМЕТ ДОМА: пара с равными процентами показывала бы обратное.
    for a, b, д, вверх, вниз in ПАРЫ:
        if вверх == вниз:
            беды.append(f"пара симметрична, и ловушки в ней нет: {a} и {b}")
            break
    # СЛОВА ДО ПОСЛЕДНЕГО ДВОЕТОЧИЯ, РАВЕНСТВА ПОСЛЕ.
    for с in ПОКАЗЫ:
        хвост = с.rsplit(":", 1)[1]
        if re.search(r"[A-Za-zА-Яа-яЁё]{3,}", хвост.replace("and", "").replace("и", "")):
            беды.append(f"СЛОВА ПОСЛЕ ДВОЕТОЧИЯ: {с[:70]}")
            break
    print(f"ПРОЦЕНТНАЯ РАЗНИЦА: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, "
          f"пар {len(ПАРЫ)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
