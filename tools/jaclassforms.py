def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча ЭТОЙ страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _нарушает(тело):
    """Нарушает ли цитата закон дома: счётное чужого разряда при имени."""
    голое = тело.lstrip("*").strip()
    for имя, _чис, сч in _ЯПОНСКАЯ.findall(голое):
        if имя in _СЧЁТНОЕ and _СЧЁТНОЕ[имя] != сч:
            return True
    for _чис, сч, имя in _КИТАЙСКАЯ.findall(голое):
        if имя in _СЧЁТНОЕ and _СЧЁТНОЕ[имя] != сч:
            return True
    return False


# ЦИТАТА ЕСТЬ РЕЧЬ ОБЪЯВЛЕННОГО ЯЗЫКА, И ВСЯКИЙ ЕЁ КУСОК СТОИ́Т В ТАБЛИЦЕ (13.09).
#
# `scripts/house_mutant.py` назвал дом СТЕРЕГУЩИМ НАБОРОМ, А НЕ ЗАКОНОМ, и был прав: порча,
# вписанная в набор показов, ломала цитату так, что признак её больше не узнавал, — и закон,
# проверяющий лишь узнанное, молчал.
#
#     ЗАКОН, ПРОВЕРЯЮЩИЙ ЛИШЬ ТО, ЧТО РАСПОЗНАЛ, СЛЕП К ПОРЧЕ, СДЕЛАВШЕЙ ЦИТАТУ
#     НЕРАСПОЗНАВАЕМОЙ: испортить строку до неузнаваемости — вернейший способ пройти суд,
#     читающий по образцу.
#
# Проверяется цитата, В КОТОРОЙ ЕСТЬ ХОТЬ ОДИН ВОСТОЧНЫЙ ЗНАК (дом берёт в ёлочки и русскую
# речь), и проверяется ЦЕЛИКОМ: письмо здесь без пробелов, и кусок отрезается ДЛИННЕЙШИМ
# совпадением с объявленным — иначе «雑誌» разошлось бы на два незнакомых знака.
#
# СВЯЗКИ ОБЪЯВЛЕНЫ ПОИМЁННО, А НЕ ПРОПУЩЕНЫ ОПТОМ: «の», «が», «あります» суть та самая
# оправа, которой японский держит счёт, и знать её дом обязан наравне со счётными.
_ВОСТОК = _re.compile(r"[\u3040-\u30ff\u3400-\u9fff]")
_СВЯЗКИ = ("あります", "の", "が")
# «书» — китайская цитата рода «порядок иной, чем у соседа»: «三本书» против «本が三冊あります».
_СОСЕД = ("书",)
_ОБЪЯВЛЕНО = tuple(sorted(
    ({и for и, *_ in ИМЕНА} | {с for _, с, *_ in ИМЕНА} | {ч for ч, *_ in ЧИСЛА}
     | set(_СВЯЗКИ) | set(_СОСЕД)), key=len, reverse=True))


def _чужое_в_цитате(тело):
    """Кусок восточной цитаты, не объявленный домом, — либо None."""
    if not _ВОСТОК.search(тело):
        return None
    хвост = тело.lstrip("*")
    while хвост:
        for кусок in _ОБЪЯВЛЕНО:
            if хвост.startswith(кусок):
                хвост = хвост[len(кусок):]
                break
        else:
            return хвост[0]
    return None


def судить(строка):
    """(судимо, истинно): страница ЭТОГО дома, и всякая цитата в ней сходится с таблицей.

    СТРАНИЦА, КОТОРУЮ ДОМ НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА: суд читает по
    ПРИНАДЛЕЖНОСТИ К СВОЕМУ НАБОРУ, а не по признаку.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for цитата in _re.findall(r"«([^»]+)»", с):
        звезда = цитата.startswith("*")
        тело = цитата.lstrip("*")
        if _чужое_в_цитате(цитата) is not None:
            return True, False
        if not (_ЯПОНСКАЯ.search(тело) or _КИТАЙСКАЯ.search(тело)):
            continue
        if _нарушает(цитата) != звезда:
            return True, False
    return True, True


