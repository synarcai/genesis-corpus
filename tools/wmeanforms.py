# ЗАПИСЬ СУДИТСЯ РАЗБОРОМ СО СКОБКАМИ И ТРЕМЯ ЗНАКАМИ: «(10 × 5 + 30 × 1) ÷ 40 = 2» есть
# одно утверждение, и признак, читающий пары, нашёл бы в нём ложь на каждом шве.
_ЗАПИСЬ = re.compile(r"(?<![\w/])(\(?\d+\)?(?:\s[+−×÷]\s\(?\d+\)?)+)\s=\s(\d+)(?![\d/])")


def счесть(выражение):
    """Значение записи из чисел, знаков + − × ÷ и скобок; None — если не разбирается.

    ДЕЛЕНИЕ ЗДЕСЬ ТОЛЬКО НАЦЕЛО: корпус, сказавший «среднее 3,25», научил бы округлению
    как истине, и запись с остатком не есть запись этого дома.
    """
    ток = re.findall(r"\d+|[()+−×÷]", выражение)
    if "".join(ток) != re.sub(r"\s", "", выражение):
        return None
    поз = 0

    def множитель():
        nonlocal поз
        if поз >= len(ток):
            return None
        if ток[поз] == "(":
            поз += 1
            знач = сумма()
            if знач is None or поз >= len(ток) or ток[поз] != ")":
                return None
            поз += 1
            return знач
        if ток[поз].isdigit():
            знач = int(ток[поз])
            поз += 1
            return знач
        return None

    def произведение():
        nonlocal поз
        знач = множитель()
        if знач is None:
            return None
        while поз < len(ток) and ток[поз] in "×÷":
            з = ток[поз]
            поз += 1
            ещё = множитель()
            if ещё is None:
                return None
            if з == "×":
                знач *= ещё
            else:
                if ещё == 0 or знач % ещё:
                    return None
                знач //= ещё
        return знач

    def сумма():
        nonlocal поз
        знач = произведение()
        if знач is None:
            return None
        while поз < len(ток) and ток[поз] in "+−":
            з = ток[поз]
            поз += 1
            ещё = произведение()
            if ещё is None:
                return None
            знач = знач + ещё if з == "+" else знач - ещё
        return знач

    знач = сумма()
    return знач if поз == len(ток) else None


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка И
    ЕСЛИ ВСЯКАЯ ЗАПИСЬ В НЕЙ ПЕРЕСЧИТЫВАЕТСЯ РАЗБОРОМ.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать;
    ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for выражение, итог in _ЗАПИСЬ.findall(с):
        цена = счесть(выражение)
        if цена is None or цена != int(итог):
            return True, False
    return True, True


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ВСЕ ЧИСЛА ЦЕЛЫЕ, И ТАБЛИЦЫ СУТЬ ТО, ЧЕМ НАЗВАНЫ.
    for n1, m1, n2, m2 in НЕРАВНЫЕ + РАВНЫЕ:
        сум, n = n1 * m1 + n2 * m2, n1 + n2
        if сум % n:
            беды.append(f"среднее целого не целое: {(n1, m1, n2, m2)} → {сум}/{n}")
        if (m1 + m2) % 2:
            беды.append(f"полусумма средних не целая: {(n1, m1, n2, m2)}")
        if m1 == m2:
            беды.append(f"средние равны, ловушка не видна: {(n1, m1, n2, m2)}")
    for n1, m1, n2, m2 in НЕРАВНЫЕ:
        if n1 == n2:
            беды.append(f"группы равны, а пара лежит в неравных: {(n1, m1, n2, m2)}")
        if (n1 * m1 + n2 * m2) // (n1 + n2) == (m1 + m2) // 2:
            беды.append(f"счёты сошлись при неравных группах: {(n1, m1, n2, m2)}")
    for n1, m1, n2, m2 in РАВНЫЕ:
        if n1 != n2:
            беды.append(f"группы неравны, а пара лежит в равных: {(n1, m1, n2, m2)}")
        if (n1 * m1 + n2 * m2) // (n1 + n2) != (m1 + m2) // 2:
            беды.append(f"счёты разошлись при равных группах: {(n1, m1, n2, m2)}")
    # ОБЕ СТОРОНЫ ЛОВУШКИ ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ.
    for язык in ЯЗЫКИ:
        if not (по_роду.get((язык, "среднее средних не то"))
                and по_роду.get((язык, "среднее средних то же"))):
            беды.append(f"показана лишь одна сторона ловушки [{язык}]")
    # РАЗБОР ЗАПИСИ ПРОВЕРЯЕТСЯ НА ЗАВЕДОМО ИЗВЕСТНОМ, ВКЛЮЧАЯ ТО, ЧЕГО ОН НЕ ДОЛЖЕН БРАТЬ.
    for выр, ждём in (("2 + 3 × 4", 14), ("(10 × 5 + 30 × 1) ÷ 40", 2), ("7 ÷ 2", None),
                      ("8 ÷ 0", None), ("(2 + 3", None), ("5 × 6", 30)):
        дало = счесть(выр)
        if дало != ждём:
            беды.append(f"разбор «{выр}»: {дало}, а надо {ждём}")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    вз = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "вес есть число")
    порча = вз.replace("ВАЖНОСТЬ", "ВАЖНОСТ", 1)
    if порча == вз:
        беды.append("порча не состоялась: нет слова «ВАЖНОСТЬ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(вз + " " + вз)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ВЗВЕШЕННОЕ СРЕДНЕЕ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


