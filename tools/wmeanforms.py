def _общее(n1, m1, n2, m2, язык):
    n, сум = n1 + n2, n1 * m1 + n2 * m2
    m, мм = сум // n, (m1 + m2) // 2
    бол, мал = max(m1, m2), min(m1, m2)
    nб, mб = (n1, m1) if n1 >= n2 else (n2, m2)
    nм, mм = (n2, m2) if n1 >= n2 else (n1, m1)
    return dict(n1=n1, m1=m1, n2=n2, m2=m2, n=n, сум=сум, m=m, мм=мм, сумм=m1 + m2,
                бол=бол, мал=мал, nб=nб, mб=mб, nм=nм, mм=mм,
                дб=abs(m - mб), дм=abs(m - mм),
                уч=_ф(n, язык), уч1=_ф(n1, язык), уч2=_ф(n2, язык), учб=_ф(nб, язык))


