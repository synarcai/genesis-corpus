# ЕДИНИЦА ЦЕНЫ ЕСТЬ СВОЙСТВО НОСИТЕЛЯ, А НЕ ОДНО ЧИСЛО НА ВЕСЬ МИР.
# Первая редакция мерила всё десятью тысячами и продала велосипед за
