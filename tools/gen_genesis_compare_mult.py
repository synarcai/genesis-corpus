Случай = collections.namedtuple(
    "Случай", "множитель основание предмет первый второй несчитаемое "
              "денежное")


def случай(н):
    """Случай по НОМЕРУ, и номер есть единственный его вход.

    Тот же номер в другом проходе даёт ДОСЛОВНО тот же показ — на этом
    стоит ядро повторов. Пять величин берутся пятью остатками от
    попарно взаимно простых длин, и потому один шаг номера меняет их
    все разом. Денежный носитель берётся СЛЕДУЮЩИМ разрядом (номер,
    делённый на длину оснований): он обязан ходить медленнее цены,
    иначе всякий дом стоил бы всегда одну и ту же сумму.
    """
    return Случай(
        МНОЖИТЕЛИ[н % len(МНОЖИТЕЛИ)],
        ОСНОВАНИЯ[н % len(ОСНОВАНИЯ)],
        ПРЕДМЕТЫ[н % len(ПРЕДМЕТЫ)],
        ЛЮДИ[н % len(ЛЮДИ)],
        ЛЮДИ[(н + 1) % len(ЛЮДИ)],
        НЕСЧИТАЕМОЕ[н % len(НЕСЧИТАЕМОЕ)],
        ДЕНЕЖНЫЕ[(н // len(ОСНОВАНИЯ)) % len(ДЕНЕЖНЫЕ)],
    )


def случаи(шаг_рода):
    """Номера случаев рода в проходе: ядро дословно, хвост по проходу."""
    хвост = [len(ЯДРО) + шаг_рода * ШАГ_ХВОСТА + i
             for i in range(СЛУЧАЕВ_В_ХВОСТЕ)]
    return list(ЯДРО) * ПОВТОРОВ_ЯДРА + хвост


def артикль(слово):
    """«a» или «an» ПО ЗВУКУ первого слога."""
    if слово in НЕМАЯ_БУКВА:
        return "an"
    if слово in СОГЛАСНЫЙ_ЗВУК:
        return "a"
    return "an" if слово[0] in ГЛАСНЫЕ_БУКВЫ else "a"


def в_раза(k):
    """«в три раза»: числительное словом и форма слова «раз» при нём."""
    return f"в {numerals.назвать(k, ТАБЛИЦЫ['ru'])} {rugram.форма('раз', k)}"


def словом(k):
    """Множитель английским словом: «three»."""
    return numerals.назвать(k, ТАБЛИЦЫ["en"])


def винительный(форма):
    """Винительный единственного к счётной форме — правило, не список.

    ЧИСЛО, КОНЧАЮЩЕЕСЯ ЕДИНИЦЕЙ, СТАВИТ ИМЯ В ПАДЕЖ ФРАЗЫ. Дом русских
    форм даёт форму СЧЁТА, и она именительная: «1 книга» верно там, где
    счётная группа есть подлежащее. В прямом дополнении женское имя на
    «-а/-я» меняет окончание — «собрал 1 книгу», — а среднее и мужское
    неодушевлённое не меняет: «собрал 1 яблоко», «работал 1 час».
    Первая редакция писала «аня собрала 1 книга» и «ведро вмещает 1
    чашка воды»: счёт верен, язык — нет.

    ПРАВИЛО ВЫВЕДЕНО ИЗ ПИСЬМА, А НЕ ПЕРЕЧИСЛЕНО, и его граница
    названа: мужское ОДУШЕВЛЁННОЕ взяло бы родительный («вижу 1
    брата»), и потому в своде предметов одушевлённых нет.
    """
    if форма.endswith("а"):
        return форма[:-1] + "у"
    if форма.endswith("я"):
        return форма[:-1] + "ю"
    return форма


def при_счёте(ключ, счёт, дополнение=False):
    """Форма слова при счёте; в дополнении единица идёт винительным.

    Единицей кончаются и двадцать один, и сто один — но не одиннадцать,
    и это тот же ценз подростков, каким живёт согласование в пакете.
    """
    форма = rugram.форма(ключ, счёт)
    if дополнение and счёт % 10 == 1 and счёт % 100 != 11:
        return винительный(форма)
    return форма


