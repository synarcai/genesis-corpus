def показ_рамки(н):
    """ДВЕ РАМКИ БОК О БОК, И ЭТО ВЕСЬ УРОК.

    Считаемое берёт «as many», меряемое — «as much», множитель у обоих
    ОДИН. Порознь эти рамки суть две фразы; рядом на одном множителе
    они суть одно отношение, сказанное дважды, и разница между ними
    видна. Оттого обе живут в ОДНОМ показе: перестановка проходом
    мешает показы между собой, но не строки внутри показа.
    """
    с = случай(н)
    k, b = с.множитель, с.основание
    a = k * b
    предмет, ключ, личная, голая, основа = с.предмет
    им1, ру1 = с.первый
    им2, ру2 = с.второй
    соб1, соб2 = (rugram.краткое(основа, ру1),
                  rugram.краткое(основа, ру2))
    род_мн = rugram.форма(ключ, МНОГО)
    строки = [
        f"{им1} {личная} {a} {предмет} and {им2} {личная} {b} "
        f"{by_count(b, предмет)}; {им1} {личная} {словом(k)} times as "
        f"many {предмет} as {им2}.",
        f"{ру1} {соб1} {a} {при_счёте(ключ, a, True)}, {ру2} {соб2} {b} "
        f"{при_счёте(ключ, b, True)}; {ру1} {соб1} {НАРЕЧИЯ[k]} больше "
        f"{род_мн}, чем {ру2}.",
    ]
    if b == 1:
        # ЕДИНИЦА ГОВОРИТСЯ ДВУМЯ ПОВЕРХНОСТЯМИ: цифрой («1 apple») и
        # артиклем («an apple»). Первая учит согласованию при счёте,
        # вторая — выбору артикля по звуку, и ни одна не выводится из
        # другой.
        один = singular(предмет)
        строки.append(
            f"{им2} {личная} {артикль(один)} {один} and {им1} {личная} "
            f"{a} {предмет}; {им1} {личная} {словом(k)} times as many "
            f"{предмет} as {им2}.")
    носитель = с.несчитаемое
    бол, мал = носитель.большее, носитель.меньшее
    ру_бол, ру_мал = носитель.ру_большее, носитель.ру_меньшее
    if isinstance(носитель, Денежный):
        ц = b * носитель.единица
        стоил_б = rugram.краткое(СТОИЛ, ру_бол)
        стоил_м = rugram.краткое(СТОИЛ, ру_мал)
        строки.append(
            f"the {бол} cost {k * ц} dollars and the {мал} cost {ц} "
            f"dollars; the {бол} cost {словом(k)} times as much as the "
            f"{мал}.")
        строки.append(
            f"{ру_бол} {стоил_б} {k * ц} {при_счёте('доллар', k * ц, True)}, "
            f"{ру_мал} {стоил_м} {ц} {при_счёте('доллар', ц, True)}; "
            f"{ру_бол} {стоил_б} {в_раза(k)} дороже, чем {ру_мал}.")
    else:
        строки.append(
            f"the {бол} holds {a} cups of water and the {мал} holds {b} "
            f"{by_count(b, 'cups')} of water; the {бол} holds "
            f"{словом(k)} times as much water as the {мал}.")
        строки.append(
            f"{ру_бол} вмещает {a} {при_счёте('чашка', a, True)} воды, "
            f"{ру_мал} вмещает {b} {при_счёте('чашка', b, True)} воды; "
            f"{ру_бол} вмещает {НАРЕЧИЯ[k]} больше воды, чем {ру_мал}.")
    # ВОПРОС НЕСЁТ СВОИ ЧИСЛА. Вопросная поверхность без чисел («во
    # сколько раз больше яблок?») не проверяема ничем: она есть
    # указание на соседнюю строку, а не утверждение. Числа стоят в ней
    # самой, и суд пересчитывает ответ по ним.
    строки.append(
        f"{им1} {личная} {a} {предмет} and {им2} {личная} {b} "
        f"{by_count(b, предмет)}; how many times as many {предмет} does "
        f"{им1} {голая} as {им2}? {словом(k)} times as many.")
    строки.append(
        f"{ру1} {соб1} {a} {при_счёте(ключ, a, True)}, {ру2} {соб2} {b} "
        f"{при_счёте(ключ, b, True)}; во сколько раз больше {род_мн} "
        f"{соб1} {ру1}? {НАРЕЧИЯ[k]} больше.")
    return "\n".join(строки)


def показ_множителя(н):
    """МНОЖИТЕЛЬ СЛОВОМ, А НЕ ТОЛЬКО ЦИФРОЙ.

    «three times 5» и «thrice 5» суть одно число, сказанное двумя
    словами языка, и полоса спрашивает вторым. Русское наречие
    («вдвое») и оборот («в два раза») стоят на тех же числах.
    Число, которого язык назвать не может, не говорится вовсе.
    """
    с = случай(н)
    k, m = с.множитель, с.основание
    итог = k * m
    строки = [
        f"{словом(k)} times {m} is {итог}.",
        f"what is {словом(k)} times {m}? {словом(k)} times {m} is "
        f"{итог}.",
    ]
    for слово in СЛОВА_МНОЖИТЕЛЯ.get(k, ()):
        строки.append(f"{слово} {m} is {итог}.")
        строки.append(f"what is {слово} {m}? {слово} {m} is {итог}.")
    косв = КОСВЕННЫЕ.get(m)
    имя_итога = numerals.назвать(итог, ТАБЛИЦЫ["ru"])
    if косв is not None and имя_итога is not None:
        строки.append(f"{НАРЕЧИЯ[k]} больше {косв} — {имя_итога}.")
        строки.append(f"{в_раза(k)} больше {косв} — {имя_итога}.")
        строки.append(f"сколько будет {НАРЕЧИЯ[k]} больше {косв}? "
                      f"{НАРЕЧИЯ[k]} больше {косв} — {имя_итога}.")
    return "\n".join(строки)


def показ_основания(н):
    """ОСНОВАНИЕ СТОИТ РЯДОМ С УТВЕРЖДЕНИЕМ, а не позади него.

    «12 больше 4 в три раза» проверяемо лишь тем, кто помнит таблицу;
    «12 = 3 × 4» рядом делает утверждение проверяемым всяким, включая
    суд. Вопросная поверхность здесь — ДА-НЕТ: она спрашивает о том же
    отношении, а не о его величине.
    """
    с = случай(н)
    k, b = с.множитель, с.основание
    a = k * b
    return "\n".join([
        f"{a} is {словом(k)} times more than {b}: {a} = {k} × {b}.",
        f"is {a} {словом(k)} times more than {b}? yes: {a} = {k} × {b}.",
        f"{a} больше {b} {в_раза(k)}: {a} = {k} × {b}.",
        f"верно ли, что {a} больше {b} {в_раза(k)}? да: {a} = {k} × {b}.",
    ])


def показ_обратного(н):
    """ВО СКОЛЬКО РАЗ — ЭТО ДЕЛЕНИЕ, И ОСНОВАНИЕМ СТОИТ ОНО.

    Прямое утверждение несёт умножением, обратный вопрос — делением:
    это не украшение, а само действие, которым на вопрос отвечают.
    Обе поверхности живут рядом — с основанием и без него, — ибо
    полоса спрашивает голым вопросом, а корпус обязан уметь и то и
    другое.
    """
    с = случай(н)
    k, b = с.множитель, с.основание
    a = k * b
    return "\n".join([
        f"how many times more is {a} than {b}? {a} is {словом(k)} times "
        f"more than {b}.",
        f"how many times more is {a} than {b}? {a} is {словом(k)} times "
        f"more than {b}: {a} ÷ {b} = {k}.",
        f"во сколько раз {a} больше {b}? {a} больше {b} {в_раза(k)}.",
        f"во сколько раз {a} больше {b}? {a} больше {b} {в_раза(k)}: "
        f"{a} ÷ {b} = {k}.",
    ])


def показ_разности(н):
    """РАЗНОСТЬ И КРАТНОЕ НА ОДНИХ ЧИСЛАХ — И В ОДНОМ ПОКАЗЕ.

    «на 8 больше» и «втрое больше» суть разные отношения одной пары, и
    читатель, не видавший их вместе, не имеет способа узнать, что они
    различны: порознь обе фразы значат «больше». Урок различия есть
    соседство, и потому оно построено, а не оставлено случаю.
    """
    с = случай(н)
    k, b = с.множитель, с.основание
    a = k * b
    d = a - b
    предмет, ключ, личная, голая, основа = с.предмет
    им1, ру1 = с.первый
    им2, ру2 = с.второй
    соб1, соб2 = (rugram.краткое(основа, ру1),
                  rugram.краткое(основа, ру2))
    зачин_en = (f"{им1} {личная} {a} {предмет} and {им2} {личная} {b} "
                f"{by_count(b, предмет)}; ")
    зачин_ru = (f"{ру1} {соб1} {a} {при_счёте(ключ, a, True)}, {ру2} "
                f"{соб2} {b} {при_счёте(ключ, b, True)}; ")
    return "\n".join([
        f"{зачин_en}{им1} {личная} {d} more {by_count(d, предмет)} than "
        f"{им2}, and {словом(k)} times as many.",
        f"{зачин_en}how many more {предмет} does {им1} {голая} than "
        f"{им2}? {d} more {by_count(d, предмет)}.",
        f"{зачин_ru}{ру1} {соб1} на {d} {при_счёте(ключ, d, True)} больше, "
        f"чем {ру2}, и {НАРЕЧИЯ[k]} больше.",
        f"{зачин_ru}на сколько {rugram.форма(ключ, МНОГО)} больше "
        f"{соб1} {ру1}? на {d} {при_счёте(ключ, d, True)} больше.",
    ])


def показ_цены(н):
    """ДЕНЕЖНАЯ РАМКА ПОЛОСЫ: множитель назван, а величина выведена.

    Здесь кратное работает как действие: сказано, во сколько раз
    дороже, названа меньшая цена — и большая ВЫВОДИТСЯ. Это тот самый
    ход, которого полоса ждёт и на котором она умирает.
    """
    с = случай(н)
    k, b = с.множитель, с.основание
    носитель = с.денежное
    ц = b * носитель.единица
    бол, мал = носитель.большее, носитель.меньшее
    ру_бол, ру_мал = носитель.ру_большее, носитель.ру_меньшее
    стоил_б = rugram.краткое(СТОИЛ, ру_бол)
    стоил_м = rugram.краткое(СТОИЛ, ру_мал)
    долл_б = при_счёте("доллар", k * ц, True)
    долл_м = при_счёте("доллар", ц, True)
    return "\n".join([
        f"the {бол} cost {словом(k)} times as much as the {мал}; the "
        f"{мал} cost {ц} dollars, so the {бол} cost {k * ц} dollars.",
        f"the {мал} cost {ц} dollars and the {бол} cost {словом(k)} "
        f"times as much; how much did the {бол} cost? {k * ц} dollars.",
        f"{ру_бол} {стоил_б} {НАРЕЧИЯ[k]} дороже, чем {ру_мал}; "
        f"{ру_мал} {стоил_м} {ц} {долл_м}, значит {ру_бол} {стоил_б} "
        f"{k * ц} {долл_б}.",
        f"{ру_мал} {стоил_м} {ц} {долл_м}, а {ру_бол} {НАРЕЧИЯ[k]} "
        f"дороже; сколько {стоил_б} {ру_бол}? {k * ц} {долл_б}.",
    ])


# РОД ОБЪЯВЛЯЕТ ИМЯ И СВОЙ ПОКАЗ, И НИЧЕГО БОЛЬШЕ: механизм прохода
# один на все роды, и прибавить род — значит объявить пару.
РОДЫ = (
    ("frame", показ_рамки),
    ("multiplier", показ_множителя),
    ("ground", показ_основания),
    ("inverse", показ_обратного),
    ("difference", показ_разности),
    ("cost", показ_цены),
)


def шаг_хвоста():
    """Наименьший шаг окна, при котором ни один свод не замирает.

    ОКНО, ДВИГАЮЩЕЕСЯ КРАТНО ДЛИНЕ СВОДА, ЗАМИРАЕТ НА НЁМ — и это тот
    же резонанс, от которого спасают взаимно простые длины, только
    вошедший с другой стороны. Первая редакция двигала окно на ЧЕТЫРЕ
    случая; шесть родов дают двадцать четыре за проход, двадцать
    четыре делится на восемь — и род рамки во ВСЕХ ПЯТИ проходах
    показывал одни и те же четыре множителя из восьми. В показе этого
    не видно: видно только в счёте различных величин. Оттого шаг
    ВЫВОДИТСЯ из объявленных длин, а не берётся на глаз, и свод,
    дополненный завтра, пересчитает его сам.
    """
    длины = (len(МНОЖИТЕЛИ), len(ОСНОВАНИЯ), len(ПРЕДМЕТЫ),
             len(ЛЮДИ), len(НЕСЧИТАЕМОЕ))
    # ШАГ ШИРЕ ОКНА: иначе окна соседних проходов налегают друг на
    # друга и проход повторяет чужие случаи вместо своих.
    шаг = СЛУЧАЕВ_В_ХВОСТЕ + 1
    while any((len(РОДЫ) * шаг) % д == 0 for д in длины):
        шаг += 1
    return шаг


ШАГ_ХВОСТА = шаг_хвоста()


def pass_groups(шаг):
    """Одна группа на РОД, и своё окно случаев у каждого рода.

    Окно выводится из НОМЕРА рода в своде, а не назначается числом при
    каждом роде: род, прибавленный завтра, получит своё окно сам, и ни
    один род не повторит чужих случаев в том же проходе.
    """
    вон = []
    for н, (_имя, показать) in enumerate(РОДЫ):
        шаг_рода = шаг * len(РОДЫ) + н
        вон.append([показать(номер) for номер in случаи(шаг_рода)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


