# «a university» — наоборот. Правило смотрит на букву, а ИМЕНОВАННЫЙ
# класс говорит, где буква лжёт о звуке; класс, ни разу не сработавший
# на нынешнем своде предметов, объявлен всё равно — правило, знающее,
# ПОЧЕМУ оно отступает, есть правило, а список слов им не является.
НЕМАЯ_БУКВА = ("hour", "honest", "heir")
СОГЛАСНЫЙ_ЗВУК = ("university", "unit", "one")
ГЛАСНЫЕ_БУКВЫ = "aeiou"

# ЯДРО НАЗВАНО НОМЕРАМИ СЛУЧАЕВ, а не вычислено из прохода: ядро есть
# та часть слоя, которая обязана быть ДОСЛОВНО ОДНОЙ во всех проходах.
# ПОВТОРНОСТЬ ЕСТЬ ЦЕНА ФОРМЫ: пять проходов дают пять встреч, и этого
# мало — ядро говорится ДВАЖДЫ в проходе, десять раз в слое.
ЯДРО = (0, 1, 2)
ПОВТОРОВ_ЯДРА = 2
СЛУЧАЕВ_В_ХВОСТЕ = 4

ТАБЛИЦЫ = {"en": numerals.таблица("en"), "ru": numerals.таблица("ru")}


def косвенные():
    """Родительный числительного по ОБЪЯВЛЕНИЮ пакета языка.

    «вдвое больше семи» требует падежа, которого таблица числительных
    не несёт: она называет число, а не склоняет его. Пакет русского
    объявляет `numeral_oblique` отдельно, и берётся он оттуда — второй
    список здесь разошёлся бы с языком в первый же день.
    """
    файл = numerals.ПАКЕТЫ / "ru.json"
    try:
        пакет = json.loads(файл.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return {int(к): str(з)
            for к, з in (пакет.get("numeral_oblique") or {}).items()}


КОСВЕННЫЕ = косвенные()


