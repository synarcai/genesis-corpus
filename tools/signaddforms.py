#!/usr/bin/env python3
"""ДОМ ЗНАКОВОГО СЛОЖЕНИЯ — ВЫЧЕСТЬ ОТРИЦАТЕЛЬНОЕ ЗНАЧИТ ПРИБАВИТЬ.

    СЛОЖЕНИЯ ДВУХ ОТРИЦАТЕЛЬНЫХ В СВОДЕ НЕТ НИ ОДНОЙ СТРОКОЙ. Замер 11.09 по 234 мирам показов:
    «(−a) + (−b)» — НОЛЬ. Знаковый мир (1340 строк) показывает сложение в предметной обёртке —
    «утром было −3 градуса, стало на 14 теплее», «лифт на −3 этаже», — и всегда с ОДНИМ
    отрицательным: второе слагаемое там положительно. Вычитание отрицательного он пишет 360 раз
    («4 − (−19) = 23»), но как СЧЁТ, а не как ЗАКОН: почему так выходит, не сказано нигде.

ШЕСТАЯ ЛОВУШКА РЯДА: 5 − (−3) = 8. Вычитание — действие, которое всю жизнь уменьшало, — здесь
УВЕЛИЧИВАЕТ. Ряд ловушек свода сходится в одну: за нулём всякое действие меняет своё лицо.

    ДЕЙСТВИЕ УЗНАЮТ ПО ТОМУ, ЧТО ОНО ДЕЛАЕТ, А НЕ ПО ТОМУ, КАК ОНО ЗОВЁТСЯ.

ЧЕТЫРЕ РОДА:

    оба влево     (−3) + (−4) = −7: 3 шага влево от нуля и ещё 4 дают 7 влево.
    через ноль    5 − 8 = −3: вычли больше, чем было, и перешли за ноль на 3 шага.
    минус минуса  5 − (−3) = 8: вычесть отрицательное значит прибавить, ибо 5 + 3 = 8. ← ЛОВУШКА
    уничтожение   (−4) + 4 = 0: противоположные в сумме дают ноль.

ВТОРОЙ И ТРЕТИЙ СУТЬ МИНИМАЛЬНАЯ ПАРА ПО ЗНАКУ ВЫЧИТАЕМОГО, и разница между ними — в одном
месте: стои́т ли за минусом скобка. Вычли положительное — ушли влево; вычли отрицательное —
ушли вправо. Порознь второй внушал бы, что вычитание всегда уменьшает.

ЧЕТВЁРТЫЙ РОД ЕСТЬ ЗАМОК ВСЕЙ ЗНАКОВОЙ ОБЛАСТИ: он повторяет то, что дом порядка сказал
расстоянием («до нуля им поровну»), — но говорит это ДЕЙСТВИЕМ. Одно и то же, сказанное дважды
разными средствами, есть не повтор, а СШИВКА ДВУХ ДОМОВ.

ПРИЧИНА ПОКАЗАНА ШАГАМИ ОТ НУЛЯ, как и в доме порядка: страницы двух домов читаются одной
мерой, и потому «7 влево» здесь и «7 шагов влево» там суть одно место числовой прямой.

    python3 tools/signaddforms.py     # самопроверка с мутантами
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import rugram  # noqa: E402 — русский счёт объявлен там, а не здесь

ЯЗЫКИ = ("ru", "en")
РОДЫ = ("оба влево", "через ноль", "минус минуса", "уничтожение")
МИНУС = "−"
ШАГ = "шаг"


def шагов(язык, n):
    return ("step" if n == 1 else "steps") if язык == "en" else rugram.форма(ШАГ, n)


РАМКИ = {
    "ru": {
        "оба влево": "(−{a}) + (−{b}) = −{s}: {a} {ша} влево от нуля и ещё {b} дают {s} влево.",
        "через ноль": "{a} − {b} = −{d}: вычли больше, чем было, и перешли за ноль на {d} {шd}.",
        "минус минуса": "{a} − (−{b}) = {s}: вычесть отрицательное значит прибавить, ибо {a} + {b} = {s}.",
        "уничтожение": "(−{a}) + {a} = 0: противоположные в сумме дают ноль.",
    },
    "en": {
        "оба влево": "(−{a}) + (−{b}) = −{s}: {a} {ша} left of zero and {b} more give {s} to the left.",
        "через ноль": "{a} − {b} = −{d}: we took away more than there was and crossed zero by {d} {шd}.",
        "минус минуса": "{a} − (−{b}) = {s}: to subtract a negative is to add, for {a} + {b} = {s}.",
        "уничтожение": "(−{a}) + {a} = 0: opposites add up to zero.",
    },
}
ПУСТО = dict(a=0, b=0, s=0, d=0, ша="", шd="")


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for a in range(1, 13):
            for b in range(1, 13):
                if (a + b) % 2 == 0:
                    вон[рамки["оба влево"].format(
                        **dict(ПУСТО, a=a, b=b, s=a + b,
                               ша=шагов(язык, a)))] = (язык, "оба влево")
                if a < b and (a + b) % 3 != 2:
                    вон[рамки["через ноль"].format(
                        **dict(ПУСТО, a=a, b=b, d=b - a,
                               шd=шагов(язык, b - a)))] = (язык, "через ноль")
                if (a * b) % 3 != 1:
                    вон[рамки["минус минуса"].format(
                        **dict(ПУСТО, a=a, b=b, s=a + b))] = (язык, "минус минуса")
        for a in range(1, 61):
            вон[рамки["уничтожение"].format(**dict(ПУСТО, a=a))] = (язык, "уничтожение")
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

# СКОБКА ЕСТЬ ЧАСТЬ ЧИСЛА, И ОБРАЗЕЦ ОБЯЗАН ЕЁ БРАТЬ: «5 − (−3) = 8» и «5 − 3 = 8» разнятся
# ровно скобкой, и первое истинно, второе ложно.
_ЗН = r"\(?−?\d+\)?"
_СУММА = re.compile(rf"({_ЗН}) \+ ({_ЗН}) = (−?\d+)")
_РАЗНОСТЬ = re.compile(rf"({_ЗН}) − ({_ЗН}) = (−?\d+)")


def _цел(с):
    return int(с.strip("()").replace("−", "-"))


def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать; ложь о
    СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    for a, b, c in _СУММА.findall(с):
        if _цел(a) + _цел(b) != _цел(c):
            return True, False
    for a, b, c in _РАЗНОСТЬ.findall(с):
        if _цел(a) - _цел(b) != _цел(c):
            return True, False
    return True, True


def _порча_одним_словом(с):
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:76]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    мм = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "минус минуса")
    об = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "оба влево")
    if судить(мм.replace("прибавить", "прибавит"))[1] is not False:
        беды.append("обрезанное слово прошло")
    if судить(об.replace("влево", "влев"))[1] is not False:
        беды.append("обрезанное слово в «оба влево» прошло")
    if судить(мм + " " + мм)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    if any("-" in с for с in ПОКАЗЫ):
        беды.append("ДЕФИС В ПОКАЗЕ: дом обязан писать знаком минус U+2212")
    # СКОБКА ОБЯЗАНА ЧИТАТЬСЯ: без неё «5 − 3 = 8» есть ложь, и суд должен её звать ложью.
    без_скобки = мм.replace("(−", "", 1).replace(")", "", 1)
    if судить(без_скобки)[1]:
        беды.append("СКОБКА ПОТЕРЯНА: строка без скобки прошла как истинная")
    print(f"ЗНАКОВОЕ СЛОЖЕНИЕ: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


if __name__ == "__main__":
    sys.exit(_самопроверка())
