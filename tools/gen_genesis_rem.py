#!/usr/bin/env python3
"""КОВКА ДОМА ДЕЛЕНИЯ С ОСТАТКОМ.

ВЕРНЫЙ ОТВЕТ И НЕВЕРНЫЙ, ПРОШЕДШИЙ ПРОВЕРКУ, ИДУТ В ОДНОМ ПРОХОДЕ: «17 ÷ 5 даёт 3 и остаток 2» и
«17 ÷ 5 не даёт 2 и остаток 7» суть минимальная пара по ЗАКОНУ ОБ ОСТАТКЕ — суммы верны обе, и
различает их только сравнение остатка с делителем.

ПРИЧИНА И ГРАНИЦА идут своей группой: «из остатка вышла бы ещё одна пятёрка» говорит, ПОЧЕМУ
остаток обязан быть меньше делителя, а «остаток 0» показывает, что деление нацело есть частный
случай того же закона, а не иное действие.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import remforms as F  # noqa: E402
from layer import emit_grouped, PASSES  # noqa: E402

ЦЕЛЬ = "datasets/genesis_rem.txt"
ГРУППЫ = (("с остатком", "не доведено"), ("ещё одна", "нацело"))


def pass_groups(шаг):
    вон = []
    for язык in F.ЯЗЫКИ:
        for роды in ГРУППЫ:
            свои = [с for с, (л, р) in F.ПОКАЗЫ.items() if л == язык and р in роды]
            вон.append(свои[шаг::len(PASSES)])
    return вон


def main():
    emit_grouped(ЦЕЛЬ, pass_groups)


if __name__ == "__main__":
    main()
