#!/usr/bin/env python3
"""СИРОТА ПОЛУЧАЕТ ГЕНЕРАТОР: мир «logic_sets» из семени с вопросной поверхностью.

Мир лежал в datasets/ без генератора и без единого вопроса; владелец
объявил ноль немых законом. Вчерашний файл стал СЕМЕНЕМ в tools/seeds/:
генератор переносит каждую его строку и к обратимым прикладывает вопрос
по ОБЪЯВЛЕННЫМ образцам дома обращения (tools/inverting.py). Ответ
судится тем же судом, что и утверждение; порча ловится — проверено
палатой до записи.
"""
import bilang  # noqa: E402 — язык показа по азбуке
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "tools"))
import inverting  # noqa: E402
from layer import PASSES, Сбор, emit  # noqa: E402
import re as _re  # noqa: E402

СЕМЯ = КОРЕНЬ / "tools" / "seeds" / "genesis_l1_logic_sets.txt"
ЦЕЛЬ = "datasets/genesis_l1_logic_sets.txt"
ОБРАЩЕНИЯ = ('подмножество', 'sign read',)


# РОД СТРОКИ СЕМЕНИ ЧИТАЕТСЯ ПО ЕЁ СОБСТВЕННОМУ ЗНАКУ, И ЭТО НЕ «РОД ПО ПОВЕРХНОСТИ»
# (14.09). Мир этот не строится ветвями: строки пришли семенем, и дело каждой ЗАПИСАНО В
# НЕЙ ЗНАКОМ — ⊂ есть включение, ∈ есть принадлежность, ∩ есть пересечение. Знак тут не
# украшение речи, а само утверждение, и читать его значит читать дело.
#
#     ГДЕ ЗНАК ЕСТЬ САМО УТВЕРЖДЕНИЕ, ЧТЕНИЕ ЗНАКА ЕСТЬ ЧТЕНИЕ ДЕЛА, А НЕ ПОВЕРХНОСТИ.
#
# Вопрос идёт в род своего утверждения: `inverting.с_вопросами` кладёт его СРАЗУ ЗА нею.
ПОДМНОЖЕСТВО = "включение: одно множество внутри другого"
ПРИНАДЛЕЖНОСТЬ = "принадлежность: элемент и множество"
ПЕРЕСЕЧЕНИЕ = "пересечение множеств"
ОБЪЕДИНЕНИЕ = "объединение множеств"
СВЯЗКА = "логическая связка над истиной и ложью"
ВЫВОД = "modus ponens: из посылки и импликации следует вывод"
РЕФЛЕКСИВНОСТЬ = "всякое множество включает само себя поэлементно"

_ЗНАКИ = ((_re.compile(r"[⊂⊆]"), ПОДМНОЖЕСТВО),
          (_re.compile(r"[∈∉]"), ПРИНАДЛЕЖНОСТЬ),
          (_re.compile(r"∩"), ПЕРЕСЕЧЕНИЕ),
          (_re.compile(r"∪"), ОБЪЕДИНЕНИЕ),
          (_re.compile(r"[∧∨¬]"), СВЯЗКА))
# ЧТЕНИЕ ЗНАКА ЕСТЬ СТРАНИЦА О ТОМ ЗНАКЕ, А НЕ ОТДЕЛЬНЫЙ РОД «ЧТЕНИЕ» (14.09). Строки
# «знак ∈ читается как принадлежит» правило знаков уже отдало принадлежности — знак стои́т
# в них сам. Остались те, чей знак не входит в разбор: «→» и слова «истина», «ложь». Их
# семь на весь свод, и родом они дали бы род ниже закона массы; каждая идёт к своему делу:
# импликация — к выводу, истинностные слова — к связке.
_СЛОВА = ((_re.compile(r"^(из .+ следует|from .+ follows)"), ВЫВОД),
          (_re.compile(r"^(каждый элемент|every element of)"), РЕФЛЕКСИВНОСТЬ),
          (_re.compile(r"(знак →|sign →)"), ВЫВОД),
          (_re.compile(r"(слово (истина|ложь)|word (true|false))"), СВЯЗКА),
          (_re.compile(r"(равно|equals)"), СВЯЗКА))


def род_строки(с):
    """Род строки семени — по её собственному знаку, а если знака нет, по обороту."""
    for образец, род in _ЗНАКИ:
        if образец.search(с):
            return род
    for образец, род in _СЛОВА:
        if образец.search(с):
            return род
    return None


def показы(шаг):
    строки = СЕМЯ.read_text(encoding="utf-8").splitlines()
    вон = Сбор()
    for с in inverting.с_вопросами(строки, ОБРАЩЕНИЯ, len(PASSES), шаг):
        род = род_строки(с)
        if род is not None:
            вон.род = род
        вон.append(с)
    return вон


def main():
    if not СЕМЯ.exists():
        print(f"ОТКАЗ: семени {СЕМЯ.name} нет")
        return 2
    emit(ЦЕЛЬ, показы)
    return 0


# --------------------------------------------------------------- ОБЪЯВЛЕНИЕ ДОМА

РОДЫ = (ПОДМНОЖЕСТВО, ПРИНАДЛЕЖНОСТЬ, ПЕРЕСЕЧЕНИЕ, ОБЪЕДИНЕНИЕ, СВЯЗКА, ВЫВОД,
        РЕФЛЕКСИВНОСТЬ)

ЗАЧЕМ_РОДА = {
    ПОДМНОЖЕСТВО: "«{b c} ⊂ {b c e} = T» и вопрос к нему",
    ПРИНАДЛЕЖНОСТЬ: "«c ∈ {a b c} = T»: элемент, а не подмножество",
    ПЕРЕСЕЧЕНИЕ: "«{c d} ∩ {c e} = {c}»: общее двух множеств",
    ОБЪЕДИНЕНИЕ: "«{a} ∪ {b} = {a b}»: всё из обоих",
    СВЯЗКА: "«T ∧ T = T», «истина и ложь равно ложь», и чтение самих слов истины и лжи",
    ВЫВОД: "«из P и P → Q следует Q» — правило вывода, и чтение знака → здесь же",
    РЕФЛЕКСИВНОСТЬ: "«каждый элемент {a b c} принадлежит {a b c}» — включение самого себя",
}


def страницы(шаг):
    return показы(шаг)


def перебор_страниц(шаг):
    return показы(шаг).парами


def группы(шаг):
    return [страницы(шаг)]


def _показы_дома():
    вон = {}
    for ш in range(len(PASSES)):
        for с, род in перебор_страниц(ш):
            if с.rstrip():
                вон.setdefault(с.rstrip(), (bilang.азбукой(с.rstrip()), род))
    return вон


ПОКАЗЫ = _показы_дома()


def _самопроверка_дома():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    # НИ ОДНА СТРОКА СЕМЕНИ НЕ ОСТАЁТСЯ БЕЗ РОДА, И ЭТО РУБЕЖ, А НЕ ПОЖЕЛАНИЕ: читатель
    # семени, у которого есть «прочее», молча кладёт туда всё, чего не понял.
    строки = [с for с in СЕМЯ.read_text(encoding="utf-8").splitlines() if с.strip()]
    немые = [с for с in строки if род_строки(с) is None]
    assert not немые, f"строк семени без рода: {len(немые)}, первая — {немые[0][:70]}"
    пустые = set(РОДЫ) - {р for _я, р in ПОКАЗЫ.values()}
    assert not пустые, f"род объявлен и не кован: {sorted(пустые)}"


_самопроверка_дома()


if __name__ == "__main__":
    sys.exit(main())
