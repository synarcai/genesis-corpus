"""ДОМ ДЕЛЕНИЯ В СТОЛБИК — ход, итог и отказ.

Деление в столбик есть ХОД, а не ответ: каждый шаг назван и проверяем, и отказ —
там, где деление не сходится нацело, — сказан прямо.

    РОД, РЕШЁННЫЙ ПОСТРОЕНИЕМ, УЖЕ ОБЪЯВЛЕН — ОСТАЁТСЯ ЛИШЬ ЗАПИСАТЬ ЕГО ТАМ, ГДЕ ЕГО ИЩУТ.

ТАБЛИЦА ПЕРЕИМЕНОВАНА В `СОСТАВ`: имя `РОДЫ` корпус держит за РЯДОМ ИМЁН, и указатель
отвергает дом, положивший под этим именем таблицу.
"""
