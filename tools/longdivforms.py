# ЗНАК ДЕЛЕНИЯ ОБЪЯВЛЕН ДВУМЯ ЗАПИСЯМИ. Обе всеобщи и обеих ждут
# разные полосы; корпус, знающий одну, исполняет половину заказа.
ЗНАКИ_ДЕЛЕНИЯ = ("÷", "/")


def ход_деления(делимое, делитель):
    """[(снесённая цифра, текущее, цифра частного, произведение, остаток)].

    ХОД ВЫВОДИТСЯ, А НЕ ЗАПИСЫВАЕТСЯ. Это тот самый алгоритм, каким
    делят углом: цифры делимого берутся слева направо, каждая
    приписывается к остатку предыдущего шага, и пока набранное меньше
    делителя И частное ещё не начато — шага нет вовсе (ведущие цифры
    только набираются). Как только частное началось, шаг есть ВСЕГДА,
    даже если цифра частного НОЛЬ: пропустить его значило бы потерять
    ноль в середине частного, а это ровно та трудность, ради которой
    полоса и спрашивает про 5236 ÷ 17.

    Первая составляющая — снесённая цифра; у первого шага её нет
    (там набор, а не снос), и она объявлена пустой.
    """
    цифры = str(делимое)
    текущее = 0
    частное = ""
    шаги = []
    for i, ц in enumerate(цифры):
        текущее = текущее * 10 + int(ц)
        if not частное and текущее < делитель:
            continue
        цифра = текущее // делитель
        произведение = делитель * цифра
        остаток = текущее - произведение
        шаги.append(("" if not частное else ц, текущее, цифра,
                     произведение, остаток))
        частное += str(цифра)
        текущее = остаток
    return шаги, (int(частное) if частное else 0), текущее


def частичные(множимое, множитель):
    """[(цифра, разряд, частичное произведение)] умножения столбиком.

    РАЗРЯД НАЗВАН МНОЖИТЕЛЕМ, А НЕ ПОДРАЗУМЕВАЕТСЯ СДВИГОМ. «19 × 10 =
    190» есть равенство, которое можно пересчитать; «сдвинуть на одну
    позицию» есть указание руке, и проверить его нечем. Нулевая цифра
    множителя частичного произведения не даёт и в запись не идёт — тот
    же закон нулевого слагаемого, что в мире уравнений.
    """
    вон = []
    for i, ц in enumerate(reversed(str(множитель))):
        цифра = int(ц)
        if цифра == 0:
            continue
        разряд = цифра * 10 ** i
        вон.append((цифра, разряд, множимое * разряд))
    return вон


def случаи(ядро, ход):
    """ЯДРО ДОСЛОВНО ВО ВСЕХ ПРОХОДАХ, ХОД — ЧИСЛАМИ ПО ПРОХОДУ.

    Ядро здесь не выбрано вкусом: это ровно те четыре случая, какие
    назвала полоса своим реестром. Они обязаны стоять в КАЖДОМ проходе
    дословно — иначе род полосы снова окажется без мира в тот день,
    когда посев сдвинется.
    """
    видано = list(ядро)
    return видано + [с for с in ход if с not in видано]


# ------------------------------------------------------------- ЯДРО

# ЧЕТЫРЕ СЛУЧАЯ, НАЗВАННЫЕ ПОЛОСОЙ ДОСЛОВНО:
#   391 ÷ 17 → 23   (обратный ход)
#   5236 ÷ 17 → 308 (ноль в середине частного)
#   391 ÷ 19        (целого не даёт)
#   19 × 19 → 361   (умножение столбиком)
ЯДРО_ДЕЛЕНИЯ = ((391, 17), (5236, 17), (874, 23))
ЯДРО_ОТКАЗА = ((391, 19), (5236, 19), (5, 17))
ЯДРО_УМНОЖЕНИЯ = ((19, 19), (23, 17), (308, 17))


def ход_точных(шаг):
    """Точные деления прохода: делимое ВЫВОДИТСЯ из делителя и частного.

    ТРИ ФОРМЫ ПОКРЫТЫ НАРОЧНО, и все три названы полосой либо законом:
    трёхзначное на двузначное (частное двузначное), четырёхзначное на
    двузначное (частное трёхзначное) и четырёхзначное с НУЛЁМ в
    середине частного. Ноль не отбирается перебором — он СТРОИТСЯ:
    частное собирается из сотен и единиц, а десятки берутся нулём.
    """
    вон = []
    for i in range(3):
        b = 12 + (шаг * 3 + i * 5) % 18          # делитель 12..29
        q = 21 + (шаг * 7 + i * 11) % 29         # частное 21..49
        вон.append((b * q, b))
    for i in range(3):
        b = 13 + (шаг * 5 + i * 7) % 17
        q = 201 + (шаг * 13 + i * 23) % 299      # частное трёхзначное
        вон.append((b * q, b))
    for i in range(2):
        b = 14 + (шаг * 2 + i * 9) % 16
        сотни = 2 + (шаг + i * 3) % 7
        единицы = 1 + (шаг * 3 + i) % 9
        q = сотни * 100 + единицы                # ноль в десятках
        вон.append((b * q, b))
    return вон


def ход_отказов(шаг):
    """Неточные деления прохода — и случай, где делитель больше делимого."""
    вон = []
    for i in range(3):
        b = 13 + (шаг * 3 + i * 4) % 17
        q = 20 + (шаг * 5 + i * 9) % 30
        r = 1 + (шаг + i * 2) % (b - 1)          # остаток строго меньше
        вон.append((b * q + r, b))
    for i in range(2):
        b = 23 + (шаг * 4 + i * 7) % 40
        вон.append((2 + (шаг + i * 3) % 9, b))   # делимое меньше делителя
    return вон


def ход_умножений(шаг):
    вон = []
    for i in range(4):
        a = 12 + (шаг * 7 + i * 5) % 78
        b = 11 + (шаг * 3 + i * 13) % 79
        вон.append((a, b))
    return вон


# --------------------------------------------------------- ХОД УГЛОМ

def шаги_деления(шаг):
    """Каждый шаг деления — ОТДЕЛЬНОЙ строкой, ибо каждый есть факт."""
    вон = []
    for делимое, делитель in случаи(ЯДРО_ДЕЛЕНИЯ, ход_точных(шаг)):
        for снос, текущее, цифра, произведение, остаток in \
                ход_деления(делимое, делитель)[0]:
            если = (f"сносим {снос} и берём {текущее}" if снос
                    else f"берём {текущее}")
            вон.append(f"в делении {делимое} ÷ {делитель} {если}: "
                       f"{делитель} × {цифра} = {произведение}, "
                       f"{текущее} − {произведение} = {остаток}.")
            if цифра == 0:
                вон.append(f"в делении {делимое} ÷ {делитель} на "
                           f"{текущее} частное берёт 0: {делитель} "
                           f"больше {текущее}.")
    return вон


def итоги_деления(шаг):
    """Итог обеими записями знака — обе ждут разные полосы."""
    вон = []
    for делимое, делитель in случаи(ЯДРО_ДЕЛЕНИЯ, ход_точных(шаг)):
        _шаги, частное, остаток = ход_деления(делимое, делитель)
        for знак in ЗНАКИ_ДЕЛЕНИЯ:
            вон.append(f"{делимое} {знак} {делитель} = {частное}.")
        вон.append(f"{делимое} ÷ {делитель} = {частное}, остаток "
                   f"{остаток}.")
        вон.append(f"сколько будет {делимое} ÷ {делитель}? "
                   f"{делимое} ÷ {делитель} = {частное}.")
        # ОДНА ФОРМА ВОПРОСА НА ОБЕ ПОЛЯРНОСТИ (holon, аудит покупок
        # 03.09): «нацело» стояло только в «нет»-вопросах отказов, и
        # форма вопроса предсказывала ответ — рамка без фальсификатора
        # не покупается. Точное деление отвечает тем же вопросом «да».
        if остаток == 0:
            вон.append(f"делится ли {делимое} на {делитель} нацело? да: "
                       f"{делитель} × {частное} = {делимое}, остаток 0.")
    return вон


def обратный_ход(шаг):
    """ОРАКУЛ: тот же факт, объявленный умножением вместо деления."""
    вон = []
    for делимое, делитель in случаи(ЯДРО_ДЕЛЕНИЯ, ход_точных(шаг)):
        _шаги, частное, остаток = ход_деления(делимое, делитель)
        # ТОЖДЕСТВО ПРИВЯЗАНО К ДЕЛЕНИЮ ЗАЧИНОМ, И ЭТО КУПЛЕНО
        # ЗАМЕРОМ. Голое «23 × 17 + 0 = 391» неотличимо от обычной
        # арифметики: первый прогон суда назвал ложью пять честных
        # строк «2 × 3 + 4 = 10» из школьного мира — они складываются
        # верно, а делением не являются вовсе. Род, чей образец не
        # назван, забирает чужие строки.
        вон.append(f"в делении {делимое} ÷ {делитель} частное "
                   f"{частное} и остаток {остаток} дают делимое: "
                   f"{частное} × {делитель} + {остаток} = {делимое}.")
        вон.append(f"обратный ход деления {делимое} ÷ {делитель}: "
                   f"{частное} × {делитель} = {делимое}.")
        вон.append(f"чем проверить {делимое} ÷ {делитель} = {частное}? "
                   f"{частное} × {делитель} = {делимое}.")
    return вон


# --------------------------------------------------------- ОТКАЗ

def отказы(шаг):
    """Отказ, ЗАЖАТЫЙ ДВУМЯ КРАТНЫМИ, — деваться искомому некуда."""
    вон = []
    for делимое, делитель in случаи(ЯДРО_ОТКАЗА, ход_отказов(шаг)):
        частное = делимое // делитель
        снизу = делитель * частное
        сверху = делитель * (частное + 1)
        остаток = делимое - снизу
        вон.append(f"{делимое} ÷ {делитель} целого не даёт: {делитель} "
                   f"× {частное} = {снизу}, а {делимое} − {снизу} = "
                   f"{остаток}; {делитель} × {частное + 1} = {сверху} "
                   f"больше {делимое}.")
        вон.append(f"делится ли {делимое} на {делитель} нацело? нет: "
                   f"{делитель} × {частное} = {снизу}, остаток "
                   f"{остаток}.")
        вон.append(f"{делимое} ÷ {делитель} = {частное}, остаток "
                   f"{остаток}.")
    return вон


# --------------------------------------------------- УМНОЖЕНИЕ СТОЛБИКОМ

def умножения(шаг):
    """Частичные произведения названы и сложены — столбик как ход."""
    вон = []
    for множимое, множитель in случаи(ЯДРО_УМНОЖЕНИЯ,
                                      ход_умножений(шаг)):
        части = частичные(множимое, множитель)
        итог = множимое * множитель
        ряд = ", ".join(f"{множимое} × {разряд} = {произв}"
                        for _ц, разряд, произв in части)
        сумма = " + ".join(str(п) for _ц, _р, п in части)
        вон.append(f"{множимое} × {множитель} = {итог}: {ряд}; "
                   f"{сумма} = {итог}.")
        вон.append(f"{множимое} × {множитель} = {итог}.")
        вон.append(f"сколько будет {множимое} × {множитель}? "
                   f"{множимое} × {множитель} = {итог}.")
    return вон


