def _общее(n, a, b, c, язык):
    з = a + b - c
    return dict(n=n, a=a, b=b, c=c, з=з, сум=a + b, св=n - з, та=a - c, тб=b - c,
                м=min(a, b), уч=_ф(n, язык))


def страницы():
    вон = {}
    for язык in ЯЗЫКИ:
        рамки = РАМКИ[язык]
        for набор, роды in ((ПЕРЕКРЫТЫЕ + СКРЫТЫЕ,
                             ("сумма с перекрытием", "ни в одном", "только одно",
                              "общее есть часть")),
                            (ПЕРЕКРЫТЫЕ, ("сумма больше целого", "спрошенное")),
                            (СКРЫТЫЕ, ("сумма не больше целого",)),
                            (БЕЗ_ОБЩИХ, ("без перекрытия",))):
            for n, a, b, c in набор:
                общ = _общее(n, a, b, c, язык)
                for род in роды:
                    вон[рамки[род].format(**общ)] = (язык, род)
    return вон


ПОКАЗЫ = страницы()
_ПО_ДЛИНЕ = {}
for _п in ПОКАЗЫ:
    _слова = _п.split(" ")
    _ПО_ДЛИНЕ.setdefault(len(_слова), []).append(_слова)

def судить(строка):
    """(судимо, истинно): страница мира истинна, если её порождает объявленная рамка И
    ЕСЛИ ВСЯКАЯ ЗАПИСЬ В НЕЙ ПЕРЕСЧИТЫВАЕТСЯ РАЗБОРОМ.

    СТРАНИЦА, КОТОРУЮ РАМКА НЕ ПОРОЖДАЕТ, НЕ ЕСТЬ ЛОЖЬ ЭТОГО СУДА — ей нечего сказать;
    ложь о СВОЁМ мире говорит замыкание, а не начало строки.
    """
    с = строка.strip()
    if not с:
        return False, False
    if с not in ПОКАЗЫ:
        return (True, False) if _порча_одним_словом(с) else (False, False)
    return True, arithread.записи_верны(с)


def _порча_одним_словом(с):
    """Строка, разошедшаяся с показом РОВНО ОДНИМ словом, есть порча этой страницы."""
    слова = с.split(" ")
    for свои in _ПО_ДЛИНЕ.get(len(слова), ()):
        расход = 0
        for x, y in zip(свои, слова):
            if x != y:
                расход += 1
                if расход > 1:
                    break
        if расход == 1:
            return True
    return False


def _самопроверка():
    беды = []
    for с in ПОКАЗЫ:
        if судить(с) != (True, True):
            беды.append(f"честная не прошла: {с[:96]}")
    по_роду = {}
    for с, (я, р) in ПОКАЗЫ.items():
        по_роду[(я, р)] = по_роду.get((я, р), 0) + 1
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            if not по_роду.get((язык, род)):
                беды.append(f"род пуст: {язык}/{род}")
    # ТАБЛИЦЫ ОБЯЗАНЫ БЫТЬ ТЕМ, ЧЕМ НАЗВАНЫ, — ИНАЧЕ ЛОВУШКА ПОКАЗАНА НЕ ТА.
    for n, a, b, c in ПЕРЕКРЫТЫЕ + СКРЫТЫЕ + БЕЗ_ОБЩИХ:
        if not 0 <= c <= min(a, b):
            беды.append(f"общих больше меньшей группы: {(n, a, b, c)}")
        if a + b - c > n:
            беды.append(f"занятых больше класса: {(n, a, b, c)}")
    for n, a, b, c in ПЕРЕКРЫТЫЕ:
        if a + b <= n:
            беды.append(f"сумма не превышает целого, а пара лежит в перекрытых: {(n, a, b, c)}")
        if c == 0:
            беды.append(f"перекрытия нет, а пара лежит в перекрытых: {(n, a, b, c)}")
    for n, a, b, c in СКРЫТЫЕ:
        if a + b > n:
            беды.append(f"сумма превышает целое, а пара лежит в скрытых: {(n, a, b, c)}")
        if c == 0:
            беды.append(f"перекрытия нет, а пара лежит в скрытых: {(n, a, b, c)}")
    for n, a, b, c in БЕЗ_ОБЩИХ:
        if c:
            беды.append(f"перекрытие есть, а пара лежит в беспересечных: {(n, a, b, c)}")
    # ОБЕ СТОРОНЫ ЛОВУШКИ ОБЯЗАНЫ БЫТЬ ПОКАЗАНЫ.
    for язык in ЯЗЫКИ:
        if not (по_роду.get((язык, "сумма больше целого"))
                and по_роду.get((язык, "сумма не больше целого"))):
            беды.append(f"показана лишь одна сторона ловушки [{язык}]")
    # РАЗБОР ЗАПИСИ ПРОВЕРЯЕТСЯ НА ЗАВЕДОМО ИЗВЕСТНОМ, ВКЛЮЧАЯ ТО, ЧЕГО ОН НЕ ДОЛЖЕН БРАТЬ.
    # РАЗБОР ЗАПИСИ ЖИВЁТ В СВОДЕ (`arithread`), И ПРОБА ЕГО СТОИТ ТАМ ЖЕ. Здесь
    # спрашивается лишь то, что он ЖИВ И ПОДКЛЮЧЁН.
    if not arithread.записи_верны("12 + 9 − 5 = 16") or arithread.записи_верны("12 + 9 − 5 = 17"):
        беды.append("общий разбор записи мёртв или не подключён")
    # МУТАНТ ПО ЧИСЛУ В КАЖДОМ РОДЕ.
    for род in РОДЫ:
        страница = next((с for с, (я, р) in ПОКАЗЫ.items() if р == род and я == "ru"), None)
        if страница is None:
            continue
        m = re.search(r"= (\d+)", страница)
        if not m:
            continue
        порча = страница[:m.start(1)] + str(int(m.group(1)) + 1) + страница[m.end(1):]
        if судить(порча)[1] is not False:
            беды.append(f"подменённое число прошло в роде {род}: {порча[:70]}")
    # МУТАНТ ПО СЛОВУ.
    сум = next(с for с, (я, р) in ПОКАЗЫ.items() if я == "ru" and р == "сумма с перекрытием")
    порча = сум.replace("ДВАЖДЫ", "ДВАЖД", 1)
    if порча == сум:
        беды.append("порча не состоялась: нет слова «ДВАЖДЫ»")
    elif судить(порча)[1] is not False:
        беды.append(f"обрезанное слово прошло: {порча[:70]}")
    if судить(сум + " " + сум)[0] is not False:
        беды.append("удвоение не осталось без вердикта")
    print(f"ДВА КРУЖКА: страниц {len(ПОКАЗЫ)}, родов {len(по_роду)}, бед {len(беды)}")
    for б in беды[:6]:
        print(f"  {б}")
    return 0 if not беды else 1


