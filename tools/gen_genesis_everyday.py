        а = 2 + (шаг + i) % 7
        б = 2 + (шаг * 2 + i * 3) % 6
        место = места[(шаг + i) % len(места)]
        кто_en, кто_ru, _кто_род, женский = _кто(шаг, i)
        сф = суффикс_рода(женский)
