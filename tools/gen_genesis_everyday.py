ШИПЯЩИЕ = ("s", "x", "z", "ch", "sh", "o")


def артикль(слово):
    """«a» или «an» — по ЗВУКУ, с которого слово начинается."""
    if слово[0] in ГЛАСНЫЕ or слово.startswith(НЕМОЕ_H):
        return "an"
    return "a"


def _плюс_s(слово):
    """Общее правило «-s / -es / -ies» — им живут и имя, и глагол.

    Множественное существительного и третье лицо глагола суть ОДНО
    правило английского письма, и второй его список разошёлся бы с
    первым в тот же день, что и всякий двойник.
    """
    if слово.endswith(ШИПЯЩИЕ):
        return слово + "es"
    if слово.endswith("y") and слово[-2] not in ГЛАСНЫЕ:
        return слово[:-1] + "ies"
    return слово + "s"


def множественное(слово):
    """Множественное имени: список исключений, затем правило."""
    if слово in НЕПРАВИЛЬНОЕ_МН:
        return НЕПРАВИЛЬНОЕ_МН[слово]
    return _плюс_s(слово)


def по_счёту(n, слово):
    """Имя при числе: один — единственное, прочее — множественное.

    «1 apples» есть та же ложь, что «a hour»: число один требует
    единственного, и слой, писавший множественное всегда, учил бы
    английскому согласованию наоборот.
    """
    return слово if n == 1 else множественное(слово)


def третье_лицо(глагол):
    """Третье лицо единственного: то же правило «-s / -es / -ies»."""
    return _плюс_s(глагол)


def иметь(n):
    """«has» при одном, «have» при прочем — согласование по числу.

    «1 students have a key» есть ровно та ложь, ради которой этот род
    и заведён: слой, пишущий подлежащее числом, обязан согласовать с
    ним и глагол, иначе он учит английскому наоборот.
    """
    return "has" if n == 1 else "have"


def _гласных_групп(слово):
    """Сколько в слове гласных ГРУПП — грубая мера числа слогов.

    Удвоение конечной согласной живёт только в ОДНОСЛОЖНОМ слове:
    «stop → stopped», но «answer → answered», а не «answerred».
    Правило без этой проверки удваивает «-wer» и лжёт на каждом
    двусложном глаголе; счёт гласных групп его и держит.
    """
    групп, в_группе = 0, False
    for буква in слово:
        if буква in ГЛАСНЫЕ:
            if not в_группе:
                групп += 1
            в_группе = True
        else:
            в_группе = False
    return групп


def прошедшее(глагол):
    """Прошедшее: исключение по списку, иначе ВЫВЕДЕНО правилом.

    Четыре хода правила, и каждый назван:
      · немое «e» на конце поглощает «e» окончания: share → shared;
      · согласная + «y» переходит в «ied»: carry → carried, но
        play → played, ибо там гласная перед «y»;
      · односложное «согласная-гласная-согласная» удваивает конечную:
        stop → stopped (кроме «w», «x», «y», которые не удваиваются
        никогда);
      · прочее берёт «ed».
    """
    if глагол in НЕПРАВИЛЬНОЕ_ПРОШ:
        return НЕПРАВИЛЬНОЕ_ПРОШ[глагол]
    if глагол.endswith("e"):
        return глагол + "d"
    if глагол.endswith("y") and глагол[-2] not in ГЛАСНЫЕ:
        return глагол[:-1] + "ied"
    if (len(глагол) >= 3 and _гласных_групп(глагол) == 1
            and глагол[-1] not in ГЛАСНЫЕ + "wxy"
            and глагол[-2] in ГЛАСНЫЕ
            and глагол[-3] not in ГЛАСНЫЕ):
        return глагол + глагол[-1] + "ed"
    return глагол + "ed"


