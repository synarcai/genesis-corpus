def путь_вверх(что):
    """Цепь мест от вещи до корня — тот самый ход, что проверит суд.

    Достижимость не пишется в показ, она ПРОХОДИТСЯ. Обход защищён от
    петли: объявление, замкнувшее дерево в кольцо, обязано умереть
    здесь, у своего автора, а не разойтись тысячей ложных показов.
    """
    цепь, узел, видано = [], что, {что}
    while узел in ДЕРЕВО:
        узел = ДЕРЕВО[узел]
        if узел in видано:
            raise ValueError(f"дерево мест замкнулось на «{узел}»")
        видано.add(узел)
        цепь.append(узел)
    return цепь


