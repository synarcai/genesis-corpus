def формы_глагола(шаг):
    """Настоящее и прошедшее ОДНОГО глагола на одном дополнении.

    Тот же мост, о который встала полоса ставок на числоформе: слой
    знал «buy» и знал «bought» и не показывал, что это одно слово.
    Здесь обе формы стоят рядом, и правило, их связавшее, названо.
    """
    вон = []
    for i, (глагол, один, много) in enumerate(ГЛАГОЛЫ):
        if (шаг + i) % 2:
            continue
        кто_en, _ру_имя, _род, _ж = _кто(шаг, i)
        друг_en, _ру2, _род2, _ж2 = _кто(шаг, i + 1)
        вон.append(f"today {кто_en} {третье_лицо(глагол)} {один}; "
                   f"yesterday {кто_en} {прошедшее(глагол)} {один}.")
        вон.append(f"today {кто_en} and {друг_en} {глагол} {много}; "
                   f"yesterday {кто_en} and {друг_en} "
                   f"{прошедшее(глагол)} {много}.")
        вон.append(f"the past of {глагол} is {прошедшее(глагол)}.")
        вон.append(f"today {кто_en} {третье_лицо(глагол)} {один}. "
                   f"what is the past of {глагол}? the past of "
                   f"{глагол} is {прошедшее(глагол)}.")
    for i, (инф, наст, прош, доп) in enumerate(ГЛАГОЛЫ_RU):
        if (шаг + i) % 2:
            continue
        _en, кто_ru, _род, женский = _кто(шаг, i)
        сф = суффикс_рода(женский)
        вон.append(f"сегодня {кто_ru} {наст} {доп}; вчера {кто_ru} "
                   f"{прош}{сф} {доп}.")
        вон.append(f"глагол «{инф}» в прошедшем даёт «{прош}».")
    return вон


