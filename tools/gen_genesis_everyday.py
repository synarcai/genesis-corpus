def число_и_артикль(шаг):
    """«an apple», «a book», «there is 1» против «there are 3».

    Мелочь, которую корпус не смеет выучить неверно: артикль идёт за
    звуком, а «there is» и «there are» идут за числом. Слой, сказавший
    «a apple» или «there is 3 books», учил бы английскому наоборот, и
    учил бы с полной судимостью.
    """
    вон = []
    for i in range(8):
        en1, ru1 = ВЕЩИ_РУССКИЕ[(шаг + i) % len(ВЕЩИ_РУССКИЕ)]
        en2, _ru2 = ВЕЩИ[(шаг * 3 + i * 2) % len(ВЕЩИ)]
        if en1 == en2:
            continue
        сколько = 2 + (шаг + i) % 8
        место = ("table", "shelf", "chair", "floor")[(шаг + i) % 4]
        кто_en, _кто_ru, _род, _ж = _кто(шаг, i)
        вон.append(f"there is 1 {en1} {предлог(место)} the {место}, "
                   f"and there are {сколько} {множественное(en1)} "
                   f"{предлог(место)} the {место}.")
        вон.append(f"{кто_en} took 1 {en1} and 1 {en2}; {кто_en} "
                   f"took {артикль(en1)} {en1} and {артикль(en2)} "
                   f"{en2}.")
        вон.append(f"1 {en1} and {сколько} {множественное(en1)} make "
                   f"{сколько + 1} {множественное(en1)} in all.")
        вон.append(f"1 {_ру(ru1, 1)} и {сколько} {_ру(ru1, сколько)} "
                   f"дают всего {сколько + 1} "
                   f"{_ру(ru1, сколько + 1)}.")
    # ВСЯКАЯ ОБЪЯВЛЕННАЯ ВЕЩЬ ОБЯЗАНА ПОКАЗАТЬ ОБЕ СВОИ ФОРМЫ. Обход
    # идёт по ВСЕЙ таблице, а не выборкой: слово, попавшее в показ по
    # жребию, живёт в одних проходах и молчит в других, — а мера охвата
    # спрашивает не «случалось ли», а «прожито ли».
    for i, (en, _ru) in enumerate(ВЕЩИ):
        сколько = 2 + (шаг + i) % 6
        мн = множественное(en)
        вон.append(f"there is 1 {en} in the box, and there are "
                   f"{сколько} {мн} in the box.")
        вон.append(f"1 {en} and {сколько} {мн} make {сколько + 1} "
                   f"{мн} in all.")
    for слово in ("hour", "apple", "egg", "office", "book", "key",
                  "ticket", "letter"):
        вон.append(f"{ЛЮДИ[0][0]} waited {артикль(слово)} {слово} "
                   f"and counted 1 {слово}.")
    return вон


