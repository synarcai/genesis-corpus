# ─── ЧАСТОТА ВЫВОДИТСЯ ИЗ ДОЛИ ─────────────────────────────────────
#
# «often» есть утверждение о ДОЛЕ, и доля объявлена порогом, а не
# чутьём: строго больше половины и меньше всех. «once» и «twice» суть
# точные числа и потому идут прежде порога.
def частота(сколько, из_скольких):
    """Английское наречие частоты при паре (сколько, из скольких)."""
    if сколько == 0:
        return "never worked"
    if сколько == из_скольких:
        return "always worked"
    if сколько == 1:
        return "worked once"
    if сколько == 2:
        return "worked twice"
    if 2 * сколько > из_скольких:
        return "often worked"
    return "worked seldom"


