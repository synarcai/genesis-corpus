def _самопроверка():
    assert set(ЗАЧЕМ_РОДА) == set(РОДЫ), "глосса рода разошлась с объявлением"
    for язык in ЯЗЫКИ:
        for ключ in ("наоборот", "сдвиг"):
            for с in СЛОВА[язык][ключ]:
                assert _своё(язык, с), f"слово с буквой вне азбуки: {с}"
        for а, б in СЛОВА[язык]["пары"]:
            assert _своё(язык, а, б), f"пара с буквой вне азбуки: {а}, {б}"
    # ОБА ИСХОДА КУПЛЕНЫ, А НЕ ОБЪЯВЛЕНЫ: есть и палиндромы, и не-палиндромы; и анаграммы,
    # и не-анаграммы. Род, показывающий один исход, учит отвечать не глядя.
    for язык in ЯЗЫКИ:
        назад = {наоборот(с) == с for с in СЛОВА[язык]["наоборот"]}
        assert назад == {True, False}, f"один исход у «наоборот»: {язык}"
        набор = {sorted(а) == sorted(б) for а, б in СЛОВА[язык]["пары"]}
        assert набор == {True, False}, f"один исход у «те же буквы»: {язык}"
    # КОЛЬЦО КУПЛЕНО ХОТЬ ОДНОЙ СТРАНИЦЕЙ, иначе закон объявлен и не показан.
    кольцо = any(сдвинуть(я, с, n)[1] for я in ЯЗЫКИ for с in СЛОВА[я]["сдвиг"]
                 for n in СДВИГИ)
    assert кольцо, "азбука объявлена кольцом и ни разу им не показана"
    for с, (_я, _р) in ПОКАЗЫ.items():
        судимо, истинно = судить(с)
        assert судимо and истинно, f"дом построил страницу, какую не признаёт суд: {с}"
    for с in ПОДСАДКИ:
        судимо, истинно = судить(с)
        assert судимо and not истинно, f"подсадка не поймана: {с}"
    роды = {з[1] for з in ПОКАЗЫ.values()}
    assert роды == set(РОДЫ), f"род объявлен и не кован: {sorted(set(РОДЫ) - роды)}"
    языки = {з[0] for з in ПОКАЗЫ.values()}
    assert языки == set(ЯЗЫКИ), f"язык объявлен и не кован: {sorted(set(ЯЗЫКИ) - языки)}"


_самопроверка()
