def наоборот(слово):
    return слово[::-1]


def лишняя(а, б):
    """Первая буква, какой в «а» больше, чем в «б», — или None, если набор один."""
    остаток = list(б)
    for буква in а:
        if буква in остаток:
            остаток.remove(буква)
        else:
            return буква
    return None


def сдвинуть(язык, слово, n):
    """(слово, ушедшие) — сдвиг по ОБЪЯВЛЕННОЙ азбуке; азбука замкнута в кольцо."""
    азбука, вон, ушли = АЗБУКА[язык], [], []
    for буква in слово:
        место = азбука.index(буква) + n
        if место >= len(азбука):
            ушли.append(буква)
        вон.append(азбука[место % len(азбука)])
    return "".join(вон), ушли


def _страницы(язык):
    рамки, слова = РАМКИ[язык], СЛОВА[язык]
    вон = []
    for с in слова["наоборот"]:
        о = наоборот(с)
        ключ = "палиндром" if о == с else "не_палиндром"
        вон.append((рамки[ключ].format(с=с, о=о), "наоборот"))
    for а, б in слова["пары"]:
        х = лишняя(а, б)
        if х is None and лишняя(б, а) is None:
            буквы = ", ".join(sorted(set(а), key=АЗБУКА[язык].index))
            вон.append((рамки["анаграмма"].format(а=а, б=б, буквы=буквы), "те_же_буквы"))
        elif х is not None:
            вон.append((рамки["не_анаграмма"].format(а=а, б=б, х=х), "те_же_буквы"))
    for с in слова["сдвиг"]:
        for n in СДВИГИ:
            о, ушли = сдвинуть(язык, с, n)
            показ = рамки["сдвиг"].format(с=с, n=n, о=о)
            if ушли:
                показ = показ[:-1] + "," + рамки["кольцо"].format(к=ушли[0])
            вон.append((показ, "сдвиг"))
    return вон


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for показ, род in _страницы(язык):
            вон.setdefault(показ, (язык, род))
    return вон


