# СУД ДЕЛАЕТ ТО ЖЕ ДЕЛО ЗАНОВО: поворачивает ряд, перебирает буквы, двигает по объявленной
# азбуке. Слово с буквой вне азбуки он не судит — запись не наша.
def _образцы(язык):
    вон = []
    for ключ in ("палиндром", "не_палиндром", "анаграмма", "не_анаграмма", "сдвиг"):
        рамка = РАМКИ[язык][ключ]
        # У СДВИГА ХВОСТ ДВОЯКИЙ: либо точка, либо запятая и слово о кольце. Точка снимается
        # ДО огораживания, а не после: `rstrip` над огороженной строкой оставляет висячую
        # косую черту и ломает образец молча.
        основа = рамка[:-1] if ключ == "сдвиг" else рамка
        хвост = r"(?:\.|,(?P<кольцо>.+))$" if ключ == "сдвиг" else r"$"
        о = re.escape(основа)
        for дыра, узор in (("буквы", "[^—]+"), ("с", "[^«»]+"), ("о", "[^«»]+"),
                           ("а", "[^«»]+"), ("б", "[^«»]+"), ("х", "[^«»]+"),
                           ("n", r"\d+")):
            о = о.replace(re.escape("{" + дыра + "}"), f"(?P<{дыра}>{узор})")
        вон.append((ключ, re.compile(о + хвост)))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def _своё(язык, *слова):
    return all(с and all(б in АЗБУКА[язык] for б in с) for с in слова)


def судить(строка):
    """(судимо, истинно) — дело над буквами сделано заново по объявленной азбуке."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for ключ, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = м.groupdict()
            if ключ in ("палиндром", "не_палиндром"):
                if not _своё(язык, д["с"], д["о"]):
                    continue
                верно = наоборот(д["с"]) == д["о"]
                одно = д["о"] == д["с"]
                return True, верно and (одно if ключ == "палиндром" else not одно)
            if ключ == "анаграмма":
                if not _своё(язык, д["а"], д["б"]):
                    continue
                буквы = ", ".join(sorted(set(д["а"]), key=АЗБУКА[язык].index))
                return True, (sorted(д["а"]) == sorted(д["б"])
                              and д["буквы"].strip() == буквы)
            if ключ == "не_анаграмма":
                if not _своё(язык, д["а"], д["б"], д["х"]):
                    continue
                return True, лишняя(д["а"], д["б"]) == д["х"]
            if not _своё(язык, д["с"], д["о"]):
                continue
            о, ушли = сдвинуть(язык, д["с"], int(д["n"]))
            сказано = (д.get("кольцо") or "").strip()
            # ПЕРЕНОС ПОКАЗАН, А НЕ УМОЛЧАН: сказал о кольце, где его не было, — ложь;
            # смолчал, где было, — тоже.
            должно = (РАМКИ[язык]["кольцо"].format(к=ушли[0]).strip() if ушли else "")
            return True, о == д["о"] and сказано == должно
    return False, True


