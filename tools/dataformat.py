#!/usr/bin/env python3
"""ДОМ ФОРМАТОВ ДАННЫХ: JSON, YAML, TOML, CSV — одним законом.

Дом разметки показал, что формат берётся ОБЪЯВЛЕНИЕМ: конструкция
говорит, как её ПИСАТЬ и как ЧИТАТЬ, а их обратимость есть встроенный
оракул. Здесь тот же закон проверяется на другом предмете — и это
проверка не форматов, а ЗАКОНА: если механизм верен, новый формат
стоит объявления и ни строки обхода.

ЧТО ЗДЕСЬ ДРУГОГО, И ПОЧЕМУ ЭТО ВАЖНО. Markdown размечает ТЕКСТ:
конструкция говорит, как читать написанное. Форматы данных несут
СТРУКТУРУ: одно и то же дерево значений записывается четырьмя разными
письменами, и перевод между ними есть ровно та способность, какой мы
учили для формул. Организм, знающий JSON и не знающий, что YAML
говорит то же самое, знает синтаксис и не знает ДАННЫХ.

ОДНО ДЕРЕВО ЗНАЧЕНИЙ, ЧЕТЫРЕ ПИСЬМА:
    JSON  {"name": "form", "count": 3}
    YAML  name: form
          count: 3
    TOML  name = "form"
          count = 3
    CSV   name,count
          form,3

И ПЯТАЯ ПОВЕРХНОСТЬ — РЕЧЬ: «a record with field name equal to form
and field count equal to 3» / «запись с полем name равным form и полем
count равным 3». Она и делает формат ПОНЯТЫМ, а не просто разобранным.

ОРАКУЛ ТОТ ЖЕ: восемь ходов (четыре письма туда и обратно) плюс речь;
дерево, не вернувшееся хотя бы одним, в корпус не выходит.

ГРАНИЦА ОБЪЯВЛЕНА ЧЕСТНО: здесь живут ПЛОСКИЕ ЗАПИСИ — отображение
имён в простые значения (строка, целое, истина/ложь) — и СПИСКИ таких
записей. Вложенность форматы держат по-разному (CSV не держит вовсе), и
показывать её одним деревом значило бы врать о CSV. Вложенное придёт
своим родом, когда будет что сказать о нём во всех четырёх письменах.
"""

import csv
import io
import json
import re

ИМЕНА = ("name", "count", "size", "kind", "line", "point", "level",
         "width", "depth", "order", "value", "weight")
СЛОВА = ("form", "field", "light", "water", "stone", "sound", "line",
         "point", "number", "force", "matter", "circle")


def запись(r, сколько=3):
    """Плоская запись: имена в простые значения."""
    вон = {}
    for i in range(сколько):
        имя = ИМЕНА[(r.randrange(len(ИМЕНА)) + i) % len(ИМЕНА)]
        вид = r.randrange(3)
        if вид == 0:
            вон[имя] = СЛОВА[r.randrange(len(СЛОВА))]
        elif вид == 1:
            вон[имя] = r.randrange(0, 100)
        else:
            вон[имя] = bool(r.randrange(2))
    return вон


# ------------------------------------------------------------- JSON

def в_json(з):
    return json.dumps(з, ensure_ascii=False, sort_keys=True)


def из_json(т):
    try:
        в = json.loads(т)
    except ValueError:
        return None
    return в if isinstance(в, dict) else None


# ------------------------------------------------------------- YAML
# СВОЙ РАЗБОРЩИК, А НЕ БИБЛИОТЕКА: корпус обязан уметь объяснить, ЧТО
# он читает, а не звать чужой разбор. Подмножество объявлено: плоское
# отображение, значения — строка без кавычек, целое, true/false.

_YAML_СТРОКА = re.compile(r"^([a-z_]\w*): (.+)$")


def в_yaml(з):
    return "\n".join(f"{к}: {_простое_в_текст(з[к])}"
                     for к in sorted(з))


def из_yaml(т):
    вон = {}
    for строка in т.split("\n"):
        м = _YAML_СТРОКА.match(строка)
        if not м:
            return None
        вон[м.group(1)] = _текст_в_простое(м.group(2))
    return вон or None


# ------------------------------------------------------------- TOML

_TOML_СТРОКА = re.compile(r"^([a-z_]\w*) = (.+)$")


def в_toml(з):
    куски = []
    for к in sorted(з):
        в = з[к]
        если = (f'"{в}"' if isinstance(в, str)
                else ("true" if в is True else
                      "false" if в is False else str(в)))
        куски.append(f"{к} = {если}")
    return "\n".join(куски)


def из_toml(т):
    вон = {}
    for строка in т.split("\n"):
        м = _TOML_СТРОКА.match(строка)
        if not м:
            return None
        сырое = м.group(2)
        if сырое.startswith('"') and сырое.endswith('"'):
            вон[м.group(1)] = сырое[1:-1]
        else:
            вон[м.group(1)] = _текст_в_простое(сырое)
    return вон or None


# -------------------------------------------------------------- CSV

def в_csv(з):
    поток = io.StringIO()
    писарь = csv.writer(поток, lineterminator="\n")
    ключи = sorted(з)
    писарь.writerow(ключи)
    писарь.writerow([_простое_в_текст(з[к]) for к in ключи])
    return поток.getvalue().rstrip("\n")


_ИМЯ_ПОЛЯ = re.compile(r"^[a-z_]\w*$")


def из_csv(т):
    """Запись из CSV, или None.

    ИМЯ ПОЛЯ ОБЯЗАНО БЫТЬ ИМЕНЕМ. Первая редакция принимала за CSV
    ЛЮБЫЕ две строки с равным числом запятых — и потому «читала» текст
    YAML («level: true» ⏎ «weight: 61») как запись с полем «level:
    true». Разбор, соглашающийся на всё, не читает: он гадает, и его
    согласие с другим разборщиком ничего не значит.
    """
    строки = list(csv.reader(io.StringIO(т)))
    if len(строки) != 2 or len(строки[0]) != len(строки[1]):
        return None
    if not all(_ИМЯ_ПОЛЯ.match(к) for к in строки[0]):
        return None
    return {к: _текст_в_простое(в)
            for к, в in zip(строки[0], строки[1])} or None


# ------------------------------------------------------------- РЕЧЬ

# РЕЧЬ ПОСТРОЕНА ТАК, ЧТОБЫ НЕ ЛОМАТЬ ПАДЕЖ. «запись с полем kind
# равным ложь» неграмотно: «равным» требует творительного, а значение
# стоит именительным и склоняться не должно (оно ИМЯ значения, а не
# слово речи). Оборот «поле X имеет значение Y» законен в обоих языках
# при любом Y — и потому годится для формата, где значением бывает
# что угодно.
_РЕЧЬ = {
    "en": ("in the record ", ", ", "the field {имя} has value {знач}"),
    "ru": ("в записи ", ", ", "поле {имя} имеет значение {знач}"),
}
_ИСТИНА = {"en": ("true", "false"), "ru": ("истина", "ложь")}


def в_речь(з, язык):
    зачин, шов, поле = _РЕЧЬ[язык]
    части = []
    for к in sorted(з):
        в = з[к]
        если = (_ИСТИНА[язык][0 if в else 1] if isinstance(в, bool)
                else str(в))
        части.append(поле.format(имя=к, знач=если))
    return зачин + шов.join(части) + "."


def из_речи(т, язык):
    зачин, шов, поле = _РЕЧЬ[язык]
    т = т.rstrip(".")
    if not т.startswith(зачин):
        return None
    т = т[len(зачин):]
    куски = т.split(шов)
    середина = поле.replace("{имя}", r"([a-z_]\w*)")
    середина = середина.replace("{знач}", r"(.+)")
    образец = re.compile("^" + середина + "$")
    вон = {}
    for кусок in куски:
        м = образец.match(кусок.strip())
        if not м:
            return None
        имя, сырое = м.group(1), м.group(2).strip()
        if сырое == _ИСТИНА[язык][0]:
            вон[имя] = True
        elif сырое == _ИСТИНА[язык][1]:
            вон[имя] = False
        else:
            вон[имя] = _текст_в_простое(сырое)
    return вон or None


# ------------------------------------------------------- ПРОСТЫЕ

def _простое_в_текст(в):
    if в is True:
        return "true"
    if в is False:
        return "false"
    return str(в)


def _текст_в_простое(т):
    т = т.strip()
    if т == "true":
        return True
    if т == "false":
        return False
    if re.fullmatch(r"-?\d+", т):
        return int(т)
    return т


ПИСЬМЕНА = (("json", в_json, из_json), ("yaml", в_yaml, из_yaml),
            ("toml", в_toml, из_toml), ("csv", в_csv, из_csv))


def оракул(сколько=2000, семя=13):
    """[(запись, чем)] — записи, не вернувшиеся каким-либо ходом."""
    import random
    r = random.Random(семя)
    беды = []
    for _ in range(сколько):
        з = запись(r, 1 + r.randrange(4))
        for имя, писать, читать in ПИСЬМЕНА:
            if читать(писать(з)) != з:
                беды.append((з, имя))
        for язык in ("en", "ru"):
            if из_речи(в_речь(з, язык), язык) != з:
                беды.append((з, "речь:" + язык))
    return беды
