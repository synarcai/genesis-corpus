def числа(таблица):
    а, б, в, г = таблица
    д, м, оч, н = а + б, в + г, а + в, а + б + в + г
    # ЧИСЛА ХВОСТА ОБЪЯВЛЕНЫ ОТДЕЛЬНЫМИ ДЫРАМИ, А НЕ ССЫЛКАМИ НА ЗАЧИН (14.09). Со ссылками
    # рамка САМА не пускала бы страницу с чужим основанием — и сильнейшая ложь («доля 9 из
    # 20 среди девочек») стала бы НЕСУДИМОЙ вместо ложной. Суд обязан иметь возможность
    # назвать её ложью, а не промолчать о ней.
    return {"а": а, "в": в, "д": д, "м": м, "оч": оч, "н": н,
            "а1": а, "а2": а, "д1": д, "д2": д, "н1": н, "оч1": оч}


def страница(язык, род, таблица):
    ч = числа(таблица)
    if род == "две_стороны" and ч["д"] == ч["оч"]:
        return None            # основания совпали — доли равны, и показывать нечего
    рамки = РАМКИ[язык]
    return рамки["зачин"].format(**ч) + рамки[род].format(**ч)


def _показы():
    вон = {}
    for язык in ЯЗЫКИ:
        for род in РОДЫ:
            for таблица in ТАБЛИЦЫ:
                п = страница(язык, род, таблица)
                if п:
                    вон.setdefault(п, (язык, род))
    return вон


ПОКАЗЫ = _показы()


# --------------------------------------------------------------------------- СУД
#
# СУД СЧИТАЕТ ДОЛИ САМ ПО ЧЕТЫРЁМ ЧИСЛАМ ТАБЛИЦЫ и требует, чтобы ОСНОВАНИЕ было названо
# верно. Страница, где доля посчитана верно, а основание названо чужое, есть ложь.
def _образцы(язык):
    вон = []
    for род in РОДЫ:
        о = re.escape(РАМКИ[язык]["зачин"] + РАМКИ[язык][род])
        for дыра in ("оч1", "а1", "а2", "д1", "д2", "н1", "н", "д", "а", "м", "в", "оч"):
            о = о.replace(re.escape("{" + дыра + "}"), f"(?P<{дыра}>\\d+)")
        вон.append((род, re.compile(о + r"$")))
    return вон


_ОБРАЗЦЫ = {я: _образцы(я) for я in ЯЗЫКИ}


def судить(строка):
    """(судимо, истинно) — доли пересчитаны по таблице, основание сверено."""
    строка = строка.strip()
    for язык in ЯЗЫКИ:
        for род, образец in _ОБРАЗЦЫ[язык]:
            м = образец.fullmatch(строка)
            if not м:
                continue
            д = {к: int(v) for к, v in м.groupdict().items()}
            # ТАБЛИЦА ОБЯЗАНА СХОДИТЬСЯ: части не смеют превышать целого, а целое —
            # расходиться с суммой. Без этого доля считалась бы от выдуманного основания.
            if not (0 < д["а"] <= д["д"] and 0 <= д["в"] <= д["м"]
                    and д["н"] == д["д"] + д["м"]):
                return True, False
            оч = д["а"] + д["в"]
            if род == "среди_всех":
                return True, д["оч1"] == оч and д["н1"] == д["н"]
            if род == "среди_своих":
                # ОСНОВАНИЕ ОБЯЗАНО БЫТЬ НАЗВАНО ВЕРНО: доля, посчитанная верно от чужого
                # основания, есть ложь — и суд обязан звать её ложью, а не молчать.
                return True, (д["а1"] == д["а"] and д["д1"] == д["д"]
                              and д["н1"] == д["н"] and д["д2"] == д["д"])
            # ДВЕ ДОЛИ ОБЯЗАНЫ БЫТЬ РАЗНЫМИ: при равных основаниях показывать нечего.
            return True, (д["а1"] == д["а"] and д["а2"] == д["а"] and д["д1"] == д["д"]
                          and д["оч1"] == оч and д["д"] != оч)
    return False, True


