def форма(ф):
    """Целая форма из объявленных частей: голова + корень + хвост [+ отдельное слово]."""
    _м, голова, корень, хвост, отд = ф[:5]
    целое = голова + корень + хвост
    return f"{целое} {отд}" if отд else целое


def разбор(ф, место, язык):
    """Разбор формы на части — по МЕСТУ лица, объявленному языком."""
    _м, голова, корень, хвост, отд = ф[:5]
    if язык == "ru":
        if место == "нигде":
            return f"одно слово «{корень}», без головы и без хвоста"
        if место == "отдельное слово":
            return (f"корень «{корень}», окончание «{хвост}» и ОТДЕЛЬНОЕ слово «{отд}» — "
                    f"лицо стои́т в последнем")
        if место == "хвост":
            return f"корень «{корень}» и хвост «{хвост}»"
        # ПУСТОЕ МЕСТО ГОЛОВЫ ЕСТЬ ЗНАК НАРАВНЕ С ЗАНЯТЫМ, и сказать «голова „“» значило бы
        # показать пустые ёлочки вместо закона. Грузинское третье лицо тем и отличается от
        # первого, что головы у него НЕТ.
        if not голова:
            хв = f" и хвост «{хвост}»" if хвост else ""
            return (f"головы нет вовсе, корень «{корень}»{хв} — и ПУСТОЕ МЕСТО ГОЛОВЫ здесь "
                    f"тоже знак: им сказано третье лицо")
        если = f"голова «{голова}» и корень «{корень}»"
        if хвост:
            return f"{если}, а за ним хвост «{хвост}»"
        return f"{если}, и хвоста нет вовсе"
    if место == "нигде":
        return f"one word «{корень}», with no head and no tail"
    if место == "отдельное слово":
        return (f"the stem «{корень}», the ending «{хвост}» and a SEPARATE word «{отд}» — "
                f"the person stands in the last")
    if место == "хвост":
        return f"the stem «{корень}» and the tail «{хвост}»"
    if not голова:
        хв = f" and the tail «{хвост}»" if хвост else ""
        return (f"no head at all, the stem «{корень}»{хв} — and the EMPTY HEAD SLOT is itself "
                f"a sign here: it says the third person")
    если = f"the head «{голова}» and the stem «{корень}»"
    return f"{если}, then the tail «{хвост}»" if хвост else f"{если}, and no tail at all"


